def add(i, sql, test=None):
    # OPTION (RECOMPILE) : 변수 값 기준으로 실행 계획 작성(2026-11-23 개발 DB 실측 : SSP_DNM_STOCK_C 32.5초 → 2.3초)
    ASIS[i] = (sql.strip('\n') + '\nOPTION (RECOMPILE)', test or {})


