     , (SELECT COUNT(*) FROM ALL_SOURCE S
         WHERE S.OWNER = O.OWNER AND S.NAME = O.OBJECT_NAME AND S.TYPE = O.OBJECT_TYPE) AS LINE_CNT
  FROM ALL_OBJECTS O
 WHERE O.OWNER = 'SCM_MGR'
   AND O.OBJECT_NAME = 'PKG_DMF0082'
   AND O.OBJECT_TYPE IN ('PACKAGE','PACKAGE BODY');
