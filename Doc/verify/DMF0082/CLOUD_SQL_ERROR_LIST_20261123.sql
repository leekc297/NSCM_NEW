-- DMF0082 'Sql Error' 발생 목록과 원인 (클라우드 QA, LIVE 에서 전체 F5)
-- 조회만 함. 기간은 SYSDATE - 30 을 바꿈

-- [1] Sql Error 발생 목록
--   화면에 'Sql Error' 가 뜬 요청 1건 = 1행
--   ORA_MSG 가 실제 오류 원문. 첫 ORA 번호로 원인을 봄
SELECT L.CREATION_DATE                     AS ERR_AT
     , L.CREATED_BY                        AS USER_ID
     , L.SHT_NM                            AS SHEET
     , L.MNU_BTN_CD                        AS BUTTON
     , L.EXCT_MSG_CTN                      AS ORA_MSG
     , SUBSTR(L.SYS_LOG_MSG_CTN, 1, 2000)  AS SENT_VALUES
  FROM SCM_MGR.SCM_COM_SYS_LOG L
 WHERE L.MNU_ID = 'DMF0082'
   AND LENGTH(TRIM(L.EXCT_MSG_CTN)) > 0
   AND L.CREATION_DATE >= SYSDATE - 30
 ORDER BY L.CREATION_DATE DESC;

-- [2] SP 안에서 난 오류 (저장, 조회. 오류 줄 번호 포함)
--   [1] 의 ERR_AT, USER_ID 와 같은 행이 있으면 SP 안에서 실패한 것
--   SQL_BACKTRACE 의 'line 숫자' = PKG_DMF0082 몇 번째 줄에서 실패했는지
--   [1] 에는 있고 [2] 에 없으면 SP 를 부르기 전에 실패한 것
SELECT B.CREATION_DATE   AS ERR_AT
     , B.CREATED_BY      AS USER_ID
     , B.PROGRAM_NAME
     , B.SQL_ERR_CODE
     , B.SQL_ERR_MSG
     , B.SQL_BACKTRACE
     , B.DESCRIPTION
  FROM SCM_MGR.SCM_SYS_LOG_BATCH B
 WHERE B.PROGRAM_NAME IN ('PKG_DMF0082','PKG_DMF0000','SCM0002_SET_TITLESET_POPUP')
   AND B.SQL_ERR_MSG IS NOT NULL
   AND B.CREATION_DATE >= SYSDATE - 30
 ORDER BY B.CREATION_DATE DESC;

