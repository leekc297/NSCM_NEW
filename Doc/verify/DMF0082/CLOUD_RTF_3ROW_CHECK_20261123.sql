/* =====================================================================================
   DMF0082 Fcst&Price MGMT : 버전 선택 조회 시 RTF[R+P] 3행 표시 검증 (클라우드용, 조회 전용)
   작성 2026-11-23 · 사내 ZIOUI1 에서 Q1~Q6 실행 확인
   입력값은 각 쿼리 첫 줄 P 절만 바꾼다 (캡처 기준: Div 40, SF_W_20261116 버전, Model MCSS22531-B1)
   전체 F5 실행 가능 (DML 없음)
   ===================================================================================== */

/* Q1. 실적 측정값 매핑(ATTRIBUTE5). RESULT_MEASURE 가 RTF_SYS_RP 인 행이 3건이면 3행 원인 조건 충족 */
SELECT SHEET_NAME, COLUMN_NAME, ATTRIBUTE5 AS RESULT_MEASURE, VALID_YN
FROM   SCM_MGR.SCM_MST_SHEET_MEASURE
WHERE  PROGRAM_ID = 'DMF0082'
AND    SHEET_NAME = 'FcstNPrice'
AND    NVL(ATTRIBUTE5, COLUMN_NAME) = 'RTF_SYS_RP'
ORDER BY COLUMN_NAME;

/* Q2. 선택 버전과 실적을 읽는 SP 버전(SP_VERSION_NO). PKG 가 GT_DMF0082_T_VERSION 에 넣는 식과 같음 */
WITH P AS (SELECT '40' AS DIV, 'SF_W_20261116%' AS VER FROM DUAL)
SELECT B.VERSION_NO, B.YYYYMMDD, C.ISO_YYYYWW
     , (SELECT MAX(V2.VERSION_NO)
        FROM   SCM_MGR.DM_MST_VERSION V2
        JOIN   SCM_MGR.SCM_SYS_CALENDAR_M CM ON V2.YYYYMMDD = CM.BASIS_YYYYMMDD
        WHERE  V2.VERSION_TYPE LIKE 'SP%'
        AND    V2.DIVISION_ID  = B.DIVISION_ID
        AND    CM.ISO_YYYYWW   = C.ISO_YYYYWW) AS SP_VERSION_NO
FROM   P
JOIN   SCM_MGR.DM_MST_VERSION B      ON B.DIVISION_ID = P.DIV AND B.VERSION_NO LIKE P.VER
JOIN   SCM_MGR.SCM_SYS_CALENDAR_M C  ON C.BASIS_YYYYMMDD = B.YYYYMMDD
ORDER BY B.VERSION_NO;

/* Q3. 3행 재현. PKG SFR(버전 실적) 조인 그대로: 실적 1행이 Q1 측정값 수만큼 늘어나고 MEASURE 는 모두 RTF_SYS_RP
       OUT_ROWS = 3, PKG_OUT_MEASURE 가 RTF_SYS_RP 3개면 화면 현상과 같은 원인 */
WITH P AS (SELECT '40' AS DIV, 'SF_W_20261116%' AS VER, 'MCSS22531-B1' AS ITEM, '20261101' AS FR, '20270430' AS TOO FROM DUAL)
, V AS (
    SELECT B.VERSION_NO
         , (SELECT MAX(V2.VERSION_NO)
            FROM   SCM_MGR.DM_MST_VERSION V2
            JOIN   SCM_MGR.SCM_SYS_CALENDAR_M CM ON V2.YYYYMMDD = CM.BASIS_YYYYMMDD
            WHERE  V2.VERSION_TYPE LIKE 'SP%' AND V2.DIVISION_ID = B.DIVISION_ID AND CM.ISO_YYYYWW = C.ISO_YYYYWW) AS SP_VERSION_NO
    FROM   P
    JOIN   SCM_MGR.DM_MST_VERSION B     ON B.DIVISION_ID = P.DIV AND B.VERSION_NO LIKE P.VER
    JOIN   SCM_MGR.SCM_SYS_CALENDAR_M C ON C.BASIS_YYYYMMDD = B.YYYYMMDD)
, M AS (
    SELECT COLUMN_NAME AS MEASURE, NVL(ATTRIBUTE5, COLUMN_NAME) AS RESULT_MEASURE
    FROM   SCM_MGR.SCM_MST_SHEET_MEASURE
    WHERE  PROGRAM_ID = 'DMF0082' AND SHEET_NAME = 'FcstNPrice' AND VALID_YN = 'Y')
SELECT V.VERSION_NO, A.VERSION_NO AS SP_VERSION_NO, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.YYYYMMDD, A.QTY
     , COUNT(*) AS OUT_ROWS
     , LISTAGG(A.MEASURE, ',') WITHIN GROUP (ORDER BY M.MEASURE) AS PKG_OUT_MEASURE
     , LISTAGG(M.MEASURE, ',') WITHIN GROUP (ORDER BY M.MEASURE) AS SCREEN_MEASURE
FROM   P
JOIN   V ON 1 = 1
JOIN   SCM_MGR.DM_PLN_SALES_PLAN_RESULT_C A
  ON   A.DIVISION_ID = P.DIV
 AND   A.VERSION_NO  = V.SP_VERSION_NO
 AND   A.ITEM_ID     = P.ITEM
 AND   A.YYYYMMDD BETWEEN P.FR AND P.TOO
 AND   A.QTY <> 0
JOIN   M ON M.RESULT_MEASURE = A.MEASURE
GROUP BY V.VERSION_NO, A.VERSION_NO, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.YYYYMMDD, A.QTY
ORDER BY A.SCM_SITE_ID, A.YYYYMMDD;

/* Q4. 같은 조건의 Current 조회 경로(A8) 기준값. Current 는 화면 측정값(B.MEASURE)으로 내보내 MKT_FCST, SCM_FCST, RTF_SYS_RP 에 1행씩 들어감
       Q3 은 3행 모두 RTF_SYS_RP, Q4 는 측정값 3종 1행씩이면 버전 경로만 결함 */
WITH P AS (SELECT '40' AS DIV, 'MCSS22531-B1' AS ITEM, '20261101' AS FR, '20270430' AS TOO FROM DUAL)
, M AS (
    SELECT COLUMN_NAME AS MEASURE, NVL(ATTRIBUTE5, COLUMN_NAME) AS RESULT_MEASURE
    FROM   SCM_MGR.SCM_MST_SHEET_MEASURE
    WHERE  PROGRAM_ID = 'DMF0082' AND SHEET_NAME = 'FcstNPrice' AND VALID_YN = 'Y')
SELECT A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, M.MEASURE AS CURRENT_OUT_MEASURE, A.YYYYMMDD, A.QTY
FROM   P
JOIN   SCM_MGR.DM_PLN_SALES_PLAN_RESULT A
  ON   A.DIVISION_ID = P.DIV
 AND   A.ITEM_ID     = P.ITEM
 AND   A.YYYYMMDD BETWEEN P.FR AND P.TOO
 AND   A.QTY <> 0
JOIN   M ON M.RESULT_MEASURE = A.MEASURE
ORDER BY A.SCM_SITE_ID, A.YYYYMMDD, M.MEASURE;

/* Q5. 클라우드 PKG 가 사내와 같은 코드인지 확인. 사내 결과: MFR_ARM 6, SFR_ARM 6, SPR_ARM 6, RESULT_MEASURE_JOIN 30
       값이 같으면 클라우드도 버전 실적 arm 18곳이 A.MEASURE 로 내보내는 코드임 */
SELECT SUM(CASE WHEN TEXT LIKE '%/* ── MFR 실적%' THEN 1 ELSE 0 END) AS MFR_ARM
     , SUM(CASE WHEN TEXT LIKE '%/* ── SFR 실적%' THEN 1 ELSE 0 END) AS SFR_ARM
     , SUM(CASE WHEN TEXT LIKE '%/* ── SPR 실적%' THEN 1 ELSE 0 END) AS SPR_ARM
     , SUM(CASE WHEN TEXT LIKE '%B.RESULT_MEASURE = A.MEASURE%' THEN 1 ELSE 0 END) AS RESULT_MEASURE_JOIN
FROM   ALL_SOURCE
WHERE  OWNER = 'SCM_MGR'
AND    NAME  = 'PKG_DMF0082'
AND    TYPE  = 'PACKAGE BODY';

/* Q6. PKG 최종 컴파일 시각 (사내 2026-11-22 18:00:20 VALID) */
SELECT OBJECT_NAME, OBJECT_TYPE, LAST_DDL_TIME, STATUS
FROM   ALL_OBJECTS
WHERE  OWNER = 'SCM_MGR'
AND    OBJECT_NAME = 'PKG_DMF0082';

/* Q7. 이관 패키지(DMF0082_CLOUD_DB_MOD_20261123_1929) 적용 뒤 확인. 기대값: MARK_LINES 12, B_MEASURE_LINES 12 (MFR 6, SFR 6)
       사내 적용 2026-11-23 19:27:35 VALID. 적용 뒤 화면에서 SF 버전 조회 시 RTF[R+P] 1행, MKT FCST[R+P]와 SCM FCST[R+P]에 실적 표시 */
SELECT SUM(CASE WHEN TEXT LIKE '%E20261123-DMF0082RTF3ROW%' THEN 1 ELSE 0 END) AS MARK_LINES
     , SUM(CASE WHEN TEXT LIKE '%, B.MEASURE AS MEASURE  --[E20261123-DMF0082RTF3ROW]%' THEN 1 ELSE 0 END) AS B_MEASURE_LINES
FROM   ALL_SOURCE
WHERE  OWNER = 'SCM_MGR'
AND    NAME  = 'PKG_DMF0082'
AND    TYPE  = 'PACKAGE BODY';
