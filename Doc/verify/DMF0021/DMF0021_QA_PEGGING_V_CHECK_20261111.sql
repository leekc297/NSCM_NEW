  FROM USER_OBJECTS
 WHERE OBJECT_NAME IN ('PKG_DMF0021','PKG_DMF0045','PKG_SSP0026','PKG_SSP0045','PR_SCP_ANL_PSI_GLOBAL'
                      ,'PR_SCP_ANL_PSI_GLOBAL_SMALL','PR_SCP_ANL_SHIPMENT_PLAN_FG','PR_SSP_ANL_SHIP_PLAN_EE'
                      ,'PR_SSP_ANL_SHIP_REQ_FG','PR_SSP_ANL_SHIP_REQ_P','PR_SSP_MAIL_SHIP_REQ_MINUS_BALANCE_40'
                      ,'SCP_PLN_SHIP_PLAN_TARGET_V')
