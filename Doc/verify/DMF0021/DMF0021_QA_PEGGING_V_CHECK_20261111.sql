-- §1. 뷰와 원천 객체 존재·상태 (사내 기준 기대 = 전부 존재 · VALID)
SELECT X.EXPECT_NAME, X.EXPECT_TYPE, X.NOTE
     , O.OBJECT_TYPE AS QA_TYPE, O.STATUS AS QA_STATUS
     , TO_CHAR(O.LAST_DDL_TIME,'YYYY-MM-DD HH24:MI') AS QA_LAST_DDL
     , CASE WHEN O.OBJECT_NAME IS NULL THEN '누락' WHEN O.STATUS <> 'VALID' THEN 'INVALID' ELSE 'OK' END AS RESULT
  FROM ( SELECT 'SCP_OPT_SHIPMENT_PLAN_PEGGING_V' EXPECT_NAME, 'VIEW'     EXPECT_TYPE, '오류 대상 뷰'                      NOTE FROM DUAL
         UNION ALL SELECT 'SCP_OPT_SHIPMENT_PLAN_V',    'VIEW',     '같은 블록에서 함께 사용'           FROM DUAL
         UNION ALL SELECT 'SCP_EGN_OTPT_SIPM_M',        'TABLE',    'PEGGING_V 원천'                   FROM DUAL
         UNION ALL SELECT 'SCP_OPT_ENG_PLAN_MASTER_SN', 'SYNONYM',  'PEGGING_V 원천 (사내 → OPT_MGR.SCP_OPT_ENG_PLAN_MASTER)' FROM DUAL
         UNION ALL SELECT 'SCP_OPT_ENG_DEMAND_SN',      'SYNONYM',  'PEGGING_V 원천 (사내 → OPT_MGR.SCP_OPT_ENG_DEMAND)'      FROM DUAL
         UNION ALL SELECT 'DM_PLN_NET_DEMAND',          'TABLE',    'PEGGING_V 원천'                   FROM DUAL
         UNION ALL SELECT 'DM_MST_VERSION',             'TABLE',    'PEGGING_V 원천'                   FROM DUAL
         UNION ALL SELECT 'SCM_MST_PLAN',               'TABLE',    'PEGGING_V 원천'                   FROM DUAL
         UNION ALL SELECT 'SCM_SYS_CALENDAR_M',         'TABLE',    'PEGGING_V 원천'                   FROM DUAL ) X
  LEFT JOIN USER_OBJECTS O
    ON O.OBJECT_NAME = X.EXPECT_NAME
   AND O.OBJECT_TYPE NOT IN ('TABLE PARTITION','INDEX')
 ORDER BY CASE WHEN O.OBJECT_NAME IS NULL THEN 0 ELSE 1 END, X.EXPECT_NAME;

-- §2. 시노님 대상 확인 (QA 에서 OPT_MGR 쪽 실체가 보이는지)
SELECT S.SYNONYM_NAME, S.TABLE_OWNER, S.TABLE_NAME, S.DB_LINK
     , ( SELECT MAX(A.OBJECT_TYPE || ' ' || A.STATUS) FROM ALL_OBJECTS A
          WHERE A.OWNER = S.TABLE_OWNER AND A.OBJECT_NAME = S.TABLE_NAME ) AS TARGET_STATUS
  FROM USER_SYNONYMS S
 WHERE S.SYNONYM_NAME IN ('SCP_OPT_ENG_PLAN_MASTER_SN','SCP_OPT_ENG_DEMAND_SN');

