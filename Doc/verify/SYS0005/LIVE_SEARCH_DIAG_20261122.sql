-- 조회 흐름: FE → BE CommonSql.retrieveBtnInfoList
--            → SCM_MGR.PKG_NSCM_UI_COMM.PR_GET_PROC_INFO_LIST('SYS0005','procList','SEARCH')
--            → SCM_MGR.PKG_SYS0005.SYS0005_GET_MAIN_DATA(P_SCHEMA, P_PROC_NM, P_UPDATE_YN)
-- 사용법: QA 와 LIVE 에서 같은 계정(SCMP_APP 또는 SCM_MGR)으로 전체 F5 실행 후 결과 비교
