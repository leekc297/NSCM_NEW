-- [1] 접속 DB, 계정 확인
SELECT SYS_CONTEXT('USERENV','DB_NAME')        AS DB_NAME
     , SYS_CONTEXT('USERENV','CON_NAME')       AS CON_NAME
     , USER                                    AS LOGIN_USER
     , SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AS CUR_SCHEMA
  FROM DUAL;

-- [2] 객체 존재, 상태 확인
-- [기준] SCM_MGR PKG_SYS0005 PACKAGE/BODY VALID, PKG_NSCM_UI_COMM PACKAGE/BODY VALID,
--        FN_SPLITSTRING FUNCTION VALID, 테이블 4개 존재, SCMP_APP 시노님 VALID
SELECT OWNER, OBJECT_NAME, OBJECT_TYPE, STATUS, LAST_DDL_TIME
  FROM ALL_OBJECTS
 WHERE OBJECT_NAME IN ('PKG_SYS0005','PKG_NSCM_UI_COMM','FN_SPLITSTRING'
                      ,'SCM_ADM_PROC_M','SCM_ADM_LOOKUP_MASTER_DETAIL'
                      ,'SCM_ADM_MNU_BTN_MPG_M','SCM_ADM_API_M')
 ORDER BY OBJECT_NAME, OWNER, OBJECT_TYPE;

-- [3] 컴파일 오류 (0행이어야 함)
SELECT OWNER, NAME, TYPE, LINE, POSITION, TEXT
  FROM ALL_ERRORS
 WHERE OWNER = 'SCM_MGR'
   AND NAME IN ('PKG_SYS0005','PKG_NSCM_UI_COMM','FN_SPLITSTRING')
 ORDER BY NAME, TYPE, SEQUENCE;

-- [4] 실행 권한 (SCMP_APP 접속이면 PKG_SYS0005, PKG_NSCM_UI_COMM EXECUTE 필요)
-- [기준] PKG_SYS0005 EXECUTE → SCMP_APP, RL_SCM_SEL, RL_SCM_DML
SELECT GRANTEE, TABLE_SCHEMA, TABLE_NAME, PRIVILEGE
  FROM ALL_TAB_PRIVS
 WHERE TABLE_SCHEMA = 'SCM_MGR'
   AND TABLE_NAME IN ('PKG_SYS0005','PKG_NSCM_UI_COMM','FN_SPLITSTRING')
 ORDER BY TABLE_NAME, GRANTEE;

-- [5] 패키지 원문 비교값 (QA 와 LIVE 값이 다르면 LIVE 에 다른 버전이 적용된 상태)
SELECT TYPE
     , COUNT(*)                                        AS LINE_CNT
     , SUM(ORA_HASH(TEXT))                             AS SRC_HASH
     , SUM(CASE WHEN UPPER(TEXT) LIKE '%UI_PKG_NM%' THEN 1 ELSE 0 END) AS UI_PKG_NM_REF
  FROM ALL_SOURCE
 WHERE OWNER = 'SCM_MGR'
   AND NAME  = 'PKG_SYS0005'
 GROUP BY TYPE
 ORDER BY TYPE;

-- [6] 메뉴 버튼 → 프로시저 연결 메타
-- [기준] 4행: procInfo SAVE/SEARCH, procList SAVE/SEARCH
--        procList SEARCH = PKG_SYS0005.SYS0005_GET_MAIN_DATA
--        0행이면 PR_GET_PROC_INFO_LIST 가 ORA-01403(no data found) 로 끝남
SELECT T1.MNU_ID, T1.SHT_NM, T1.MNU_BTN_CD, T1.API_ID, T2.API_URL
  FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M T1
  JOIN SCM_MGR.SCM_ADM_API_M         T2
    ON T1.API_ID = T2.API_ID
 WHERE T1.MNU_ID = 'SYS0005'
 ORDER BY T1.SHT_NM, T1.MNU_BTN_CD;

-- [7] 프로시저 파라미터 메타 (BE 가 이 행으로 CALL 문을 만듦)
-- [기준] SYS0005_GET_MAIN_DATA 5행: schema/procedure/updateYn VARCHAR IN 1~3, o_rc CURSOR OUT 4, O_RESULT_CURSOR PROC_RESULT OUT 5
--        SYS0005_GET_PROC_DATA 5행: OWNER/PROC_NM/isYn VARCHAR IN 1~3, o_rc CURSOR OUT 4, O_RESULT_CURSOR PROC_RESULT OUT 5
SELECT PROC_NM, SORT_ORD, COL_NM, DATA_TP_CD, COL_TP_CD
  FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM IN ('PKG_SYS0005.SYS0005_GET_MAIN_DATA','PKG_SYS0005.SYS0005_GET_PROC_DATA')
 ORDER BY PROC_NM, SORT_ORD;

-- [8] 파라미터 메타 ↔ 실제 패키지 인자 개수, 순서 대조 (DIFF 행이 있으면 BE CALL 문 인자 불일치)
SELECT NVL(M.PROC_NM, A.PROC_NM) AS PROC_NM
     , NVL(M.SORT_ORD, A.POSITION) AS POS
     , M.COL_NM, A.ARGUMENT_NAME, A.IN_OUT, M.COL_TP_CD
     , CASE WHEN M.PROC_NM IS NULL OR A.PROC_NM IS NULL THEN 'DIFF'
            WHEN M.COL_TP_CD <> A.IN_OUT THEN 'DIFF' ELSE 'OK' END AS CHK
  FROM (SELECT PROC_NM, SORT_ORD, COL_NM, COL_TP_CD
          FROM SCM_MGR.SCM_ADM_PROC_M
         WHERE PROC_NM IN ('PKG_SYS0005.SYS0005_GET_MAIN_DATA','PKG_SYS0005.SYS0005_GET_PROC_DATA')) M
  FULL OUTER JOIN
       (SELECT PACKAGE_NAME || '.' || OBJECT_NAME AS PROC_NM, POSITION, ARGUMENT_NAME, IN_OUT
          FROM ALL_ARGUMENTS
         WHERE OWNER = 'SCM_MGR' AND PACKAGE_NAME = 'PKG_SYS0005'
           AND OBJECT_NAME IN ('SYS0005_GET_MAIN_DATA','SYS0005_GET_PROC_DATA')
           AND DATA_LEVEL = 0) A
    ON M.PROC_NM = A.PROC_NM AND M.SORT_ORD = A.POSITION
 ORDER BY 1, 2;

-- [9] 목록 대상 패키지 범위 Lookup (SYS0005_GET_MAIN_DATA 가 이 행으로 패키지를 거름)
-- [기준] 2행 VALID_YN=Y: SEGMENT1=SCM_MGR / SEGMENT2=PKG_ , SEGMENT1=PKG_SYS0005 / SEGMENT2=PKG_SYS0005
--        SCM_MGR / PKG_ 행이 없거나 VALID_YN=N 이면 목록 0건
SELECT LOOKUP_TYPE, SEGMENT1, SEGMENT2, VALID_YN, DISPLAY_SEQ, DESCRIPTION, LAST_UPDATE_DATE
  FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE = 'UI_PKG_NM'
 ORDER BY SEGMENT1, SEGMENT2;

-- [10] Lookup 범위 안 패키지 인자 건수 (프로시저 본문 DB 서브쿼리와 같은 조건)
-- [기준] 사내 10,797건, 0.36초
--        0건이면 [9] Lookup 또는 LIVE 패키지 소유자(OWNER) 확인
SELECT A.OWNER
     , COUNT(DISTINCT A.PACKAGE_NAME) AS PKG_CNT
     , COUNT(*)                       AS ARG_CNT
  FROM ALL_ARGUMENTS A
 WHERE A.TYPE_OBJECT_TYPE IS NULL
   AND EXISTS (SELECT 1
                 FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL L
                WHERE L.LOOKUP_TYPE = 'UI_PKG_NM'
                  AND L.VALID_YN    = 'Y'
                  AND A.OWNER       = TRIM(L.SEGMENT1)
                  AND A.PACKAGE_NAME LIKE TRIM(L.SEGMENT2) || '%')
 GROUP BY A.OWNER;

-- [11] LIVE 패키지 소유 스키마 확인 (SCM_MGR 이외 스키마에 PKG_ 패키지가 있으면 [9] SEGMENT1 값과 비교)
SELECT OWNER, COUNT(*) AS PKG_CNT
  FROM ALL_OBJECTS
 WHERE OBJECT_TYPE = 'PACKAGE'
   AND OBJECT_NAME LIKE 'PKG\_%' ESCAPE '\'
 GROUP BY OWNER
 ORDER BY OWNER;

-- [12] BE 와 같은 순서로 직접 호출: 메타 조회 → 목록 조회 (건수, 소요 시간, 오류 원문 출력)
--      SQL Developer / DBeaver 에서 DBMS_OUTPUT 켜고 실행
DECLARE
    V_META    SYS_REFCURSOR;
    V_CUR     SYS_REFCURSOR;
    V_RES     SYS_REFCURSOR;
    V_PROC_NM VARCHAR2(300);
    V_COL_NM  VARCHAR2(100);
    V_DTP     VARCHAR2(100);
    V_CTP     VARCHAR2(100);
    V_ORD     NUMBER;
    V_CNT     NUMBER := 0;
    V_T0      NUMBER;
    -- SYS0005_GET_MAIN_DATA 결과 컬럼 9개
    V_UPD     VARCHAR2(10);
    V_OWNER   VARCHAR2(128);
    V_PNM     VARCHAR2(300);
    V_ISYN    VARCHAR2(10);
    V_CB      VARCHAR2(100);
    V_CD      DATE;
    V_LB      VARCHAR2(100);
    V_LD      DATE;
BEGIN
    -- 12-1 메타 조회
    BEGIN
        SCM_MGR.PKG_NSCM_UI_COMM.PR_GET_PROC_INFO_LIST('SYS0005', 'procList', 'SEARCH', V_META);
        LOOP
            FETCH V_META INTO V_PROC_NM, V_COL_NM, V_DTP, V_CTP, V_ORD;
            EXIT WHEN V_META%NOTFOUND;
            DBMS_OUTPUT.PUT_LINE('[12-1] ' || V_PROC_NM || ' | ' || V_ORD || ' | ' || V_COL_NM || ' | ' || V_DTP || ' | ' || V_CTP);
        END LOOP;
        CLOSE V_META;
    EXCEPTION WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('[12-1] 메타 조회 오류: ' || SQLERRM);
    END;

    -- 12-2 목록 조회 (화면 기본 조건: Schema=ALL, Procedure 빈 값, Update=ALL)
    BEGIN
        V_T0 := DBMS_UTILITY.GET_TIME;
        SCM_MGR.PKG_SYS0005.SYS0005_GET_MAIN_DATA('ALL', NULL, 'ALL', V_CUR, V_RES);
        LOOP
            FETCH V_CUR INTO V_UPD, V_OWNER, V_PNM, V_ISYN, V_CB, V_CD, V_LB, V_LD;
            EXIT WHEN V_CUR%NOTFOUND;
            V_CNT := V_CNT + 1;
        END LOOP;
        CLOSE V_CUR;
        DBMS_OUTPUT.PUT_LINE('[12-2] 목록 건수 = ' || V_CNT || ' / 소요 ' || (DBMS_UTILITY.GET_TIME - V_T0) / 100 || '초');
    EXCEPTION WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('[12-2] 목록 조회 오류: ' || SQLERRM);
        DBMS_OUTPUT.PUT_LINE(DBMS_UTILITY.FORMAT_ERROR_BACKTRACE);
    END;
END;
