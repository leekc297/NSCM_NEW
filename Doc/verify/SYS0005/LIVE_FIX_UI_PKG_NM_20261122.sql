-- [4] 목록 SP 재호출 (DBMS_OUTPUT 켜고 실행 · 0건이 아니면 보완 완료)
DECLARE
    V_CUR   SYS_REFCURSOR;
    V_RES   SYS_REFCURSOR;
    V_CNT   NUMBER := 0;
    V_UPD   VARCHAR2(10);
    V_OWNER VARCHAR2(128);
    V_PNM   VARCHAR2(300);
    V_ISYN  VARCHAR2(10);
    V_CB    VARCHAR2(100);
    V_CD    DATE;
    V_LB    VARCHAR2(100);
    V_LD    DATE;
BEGIN
    SCM_MGR.PKG_SYS0005.SYS0005_GET_MAIN_DATA('ALL', NULL, 'ALL', V_CUR, V_RES);
    LOOP
        FETCH V_CUR INTO V_UPD, V_OWNER, V_PNM, V_ISYN, V_CB, V_CD, V_LB, V_LD;
        EXIT WHEN V_CUR%NOTFOUND;
        V_CNT := V_CNT + 1;
    END LOOP;
    CLOSE V_CUR;
    DBMS_OUTPUT.PUT_LINE('목록 건수 = ' || V_CNT);
END;
