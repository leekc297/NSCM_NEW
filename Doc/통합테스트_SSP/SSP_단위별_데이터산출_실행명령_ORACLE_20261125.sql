-- ==============================================================================================================
-- [0-1-확인] 공통 : 일 계획 ID 최신 일자 조회(조회 문장)
-- 40 의 LAST_PLAN_NAME 이 시험일 전날이면 [0-1] 은 하루치만 만들고, 더 이전이면 빠진 날부터 차례로 만듦
-- ==============================================================================================================
SELECT DIVISION_ID
     , MAX(PLAN_NAME) AS LAST_PLAN_NAME
     , MAX(PLAN_ID) KEEP (DENSE_RANK LAST ORDER BY PLAN_NAME) AS LAST_PLAN_ID
     , COUNT(*) AS ROW_CNT
  FROM SCM_MST_PLAN
 WHERE PLAN_CYCLE = 'DAILY'
 GROUP BY DIVISION_ID
 ORDER BY DIVISION_ID;

