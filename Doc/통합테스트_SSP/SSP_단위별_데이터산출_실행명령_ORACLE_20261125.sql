-- 확인 : 프로그램마다 START 와 END 가 짝으로 있고 ERROR 행 · SQL_ERR_CODE 가 없음. 로그가 없으면 진입 조건 미충족으로 건너뛴 것
-- ==============================================================================================================
WITH PRM AS (SELECT '20261125' AS P_TEST_DATE FROM DUAL)   /* 시험일. 이 줄의 값만 바꿔 실행 */
SELECT L.PROGRAM_NAME
     , L.LOG_TYPE                      /* START 시작, TXN 처리, END 종료, ERROR 오류 */
     , L.LOG_COUNT
     , SUBSTR(L.LOG_MESSAGE, 1, 200) AS LOG_MESSAGE
     , SUBSTR(L.DESCRIPTION, 1, 200) AS DESCRIPTION
     , L.SQL_ERR_CODE
     , SUBSTR(L.SQL_ERR_MSG, 1, 300) AS SQL_ERR_MSG
     , L.EVENT_DATE
  FROM SCM_SYS_LOG_BATCH L
     , PRM
 WHERE L.EVENT_DATE >= TO_DATE(PRM.P_TEST_DATE, 'YYYYMMDD')
   AND L.EVENT_DATE < TO_DATE(PRM.P_TEST_DATE, 'YYYYMMDD') + 1
   AND (   L.PROGRAM_NAME LIKE 'PR_SSP%'
        OR L.PROGRAM_NAME IN ('PR_SCM_MST_PLAN', 'PR_SCM_DNM_STOCK_V'))
 ORDER BY L.EVENT_DATE
        , L.PROGRAM_NAME;
