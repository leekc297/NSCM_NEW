CREATE FUNCTION [dbo].[FN_TIMEUOM_TOSECOND](@FROMTIME AS FLOAT, @FROMUOM AS VARCHAR(MAX))
RETURNS FLOAT
BEGIN
    IF @FROMTIME IS NULL OR @FROMUOM IS NULL
        RETURN NULL
    IF @FROMUOM = 'SECOND'
        RETURN @FROMTIME
    IF @FROMUOM = 'MINUTE'
        RETURN @FROMTIME * 60
    IF @FROMUOM = 'HOUR'
        RETURN @FROMTIME * 60 * 60
    IF @FROMUOM = 'DAY'
        RETURN @FROMTIME * 60 * 60 * 24
    IF @FROMUOM = 'WEEK'
        RETURN @FROMTIME * 60 * 60 * 24 * 7
    RETURN NULL
END
