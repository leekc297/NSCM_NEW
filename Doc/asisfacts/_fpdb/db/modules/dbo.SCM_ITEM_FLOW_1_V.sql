CREATE VIEW [dbo].[SCM_ITEM_FLOW_1_V]
AS
SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, B.PLANT_ID, B.FACTORY_ID, A.ITEM_ID,
       A.OPERATION_ID, A.OPERATION_SEQ, A.FLOW_ID,
       B.OPERATION_LOT_SIZE,B.MIN_LOT_SIZE,B.LOT_SIZE_UOM,  
       B.BUFFER_TIME, B.BUFFER_TIME_UOM, B.TAT, B.TAT_UOM,
       CASE WHEN C.CAPA_TYPE IN ('TAT', 'TAT_CAPA','TAT_MOVE','BATCH') THEN CONVERT(NVARCHAR, 'Y')
            ELSE CONVERT(NVARCHAR, 'N')
       END  TAT_FLAG, 
       C.CAPA_TYPE AS TAT_TYPE,
       B.PRECEDE_PRODUCING_TERM, B.PRECEDE_PRODUCING_TERM_UOM, 
       B.INITIAL_PRODUCING_LEAD_TIME, B.INITIAL_PRODUCING_LEAD_TIME_UOM, 
       B.ACTIVE_FLAG
FROM   (
        SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.ITEM_ID,
               A.OPERATION_ID, A.OPERATION_SEQ, A.FLOW_ID
        FROM  (
                SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.ITEM_ID,
                       B.FLOW_ID, B.OPERATION_ID, B.OPERATION_SEQ
                FROM   SCM_ITEM_M A(NOLOCK)
        INNER HASH JOIN SCM_OPERATION_FLOW_M B(NOLOCK)
        ON     A.COMPANY_ID = B.COMPANY_ID
                AND    A.DIVISION_ID = B.DIVISION_ID
                AND    A.SITE_ID = B.SITE_ID
                AND    A.FLOW_ID = B.FLOW_ID
        AND    B.ACTIVE_FLAG = 'Y'
                INNER HASH JOIN SCM_ITEM_CLASS_M C(NOLOCK)
                ON     A.ITEM_CLASS = C.CLASS_ID
        AND    C.USE_FLAG = 'Y'
        WHERE  A.ACTIVE_FLAG = 'Y'
        ) A
       ) A
       LEFT MERGE JOIN SCM_OPERATION_MOVE_M B(NOLOCK)
    ON     A.COMPANY_ID = B.COMPANY_ID
    AND    A.DIVISION_ID = B.DIVISION_ID
    AND    A.SITE_ID = B.SITE_ID
    AND    A.OPERATION_ID = B.OPERATION_ID
    AND    B.ACTIVE_FLAG = 'Y'
INNER HASH JOIN SCM_OPERATION_M C(NOLOCK)
ON     A.COMPANY_ID = C.COMPANY_ID
AND    A.DIVISION_ID = C.DIVISION_ID
AND    A.SITE_ID = C.SITE_ID
AND    A.OPERATION_ID = C.OPERATION_ID
