VIEW [dbo].[FP_CELL_ASSY_PRODUCT_MAP_V]
AS
SELECT	COMPANY_ID,	DIVISION_ID, SITE_ID, 
		APPLIED_MODEL AS CELL_PRODUCT_ITEM_ID,
		ITEM_ID AS CELL_ASSY_ITEM_ID
FROM SCM_ITEM_M WITH (NOLOCK) 
WHERE ITEM_CLASS = 'ES1901'  -- [ACACA]CELL ASSEMBLY
AND ACTIVE_FLAG = 'Y'
;
