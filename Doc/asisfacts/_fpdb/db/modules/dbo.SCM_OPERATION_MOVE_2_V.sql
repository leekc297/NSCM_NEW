CREATE VIEW [dbo].[SCM_OPERATION_MOVE_2_V]
AS
SELECT A.[COMPANY_ID]
   , A.[DIVISION_ID]
   , A.[SITE_ID]
   , A.[PLANT_ID]
   , A.[FACTORY_ID]
   , A.[OPERATION_ID]
   , A.[MODEL_TYPE]
   , A.[LINE_ATTR_1]
FROM ( SELECT OP.COMPANY_ID, OP.DIVISION_ID, OP.SITE_ID, L.PLANT_ID, L.FACTORY_ID, OP.OPERATION_ID, L.MODEL_TYPE, L.LINE_ATTR_1
       FROM   SCM_OPERATION_M  OP(NOLOCK)
       ,SCM_LINE_M       L(NOLOCK)
       WHERE  OP.COMPANY_ID = L.COMPANY_ID
       AND    OP.DIVISION_ID = L.DIVISION_ID
       AND    OP.SITE_ID = L.SITE_ID
       AND    OP.OPERATION_ID = L.OPERATION_ID
       AND 	  L.ACTIVE_FLAG = 'Y'
     GROUP BY  OP.COMPANY_ID, OP.DIVISION_ID, OP.SITE_ID, L.PLANT_ID, L.FACTORY_ID, OP.OPERATION_ID, L.MODEL_TYPE, L.LINE_ATTR_1 )  A
     LEFT OUTER JOIN SCM_OPERATION_MOVE_M B(NOLOCK)
            ON  A.COMPANY_ID = B.COMPANY_ID
            AND A.DIVISION_ID = B.DIVISION_ID
            AND A.SITE_ID = B.SITE_ID
            AND A.PLANT_ID = B.PLANT_ID
            AND A.FACTORY_ID = B.FACTORY_ID
            AND A.OPERATION_ID = B.OPERATION_ID
            AND     A.MODEL_TYPE = B.MODEL_TYPE
            AND     A.LINE_ATTR_1 = B.LINE_ATTR_1
