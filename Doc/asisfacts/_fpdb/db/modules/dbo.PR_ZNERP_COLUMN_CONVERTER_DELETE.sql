CREATE PROCEDURE [dbo].[PR_ZNERP_COLUMN_CONVERTER_DELETE]
AS
BEGIN
	DECLARE @TABLE_NAME   NVARCHAR(150) = N''; 
	DECLARE @TABLE_NAME_NEW   NVARCHAR(150) = N''; 
	DECLARE @COL_INFO   NVARCHAR(150) = N''; 
	DECLARE @TABLE_COL   NVARCHAR(150) = N''; 
	DECLARE @TABLE_COL2   NVARCHAR(150) = N''; 
	DECLARE @TABLE_COL3   NVARCHAR(150) = N''; 
	DECLARE @MASTER_CODETYPE   NVARCHAR(150) = N''; 
	DECLARE @MASTER_CODETYPE2   NVARCHAR(150) = N''; 
	DECLARE @MASTER_CODETYPE3   NVARCHAR(150) = N''; 
	DECLARE @CNT INT;
	DECLARE @SELECT_COL NVARCHAR(MAX);
	DECLARE @mEXEC NVARCHAR(MAX);
	DECLARE @BACKUP_START_TIME  NVARCHAR(50) = N''; 
	DECLARE @BACKUP_END_TIME  NVARCHAR(50) = N''; 
	DECLARE @UPDATE_START_TIME  NVARCHAR(50) = N''; 
	DECLARE @UPDATE_END_TIME  NVARCHAR(50) = N''; 

	------------------------------------------------------
	--STEP 1. PRE DATA DELETE
	------------------------------------------------------
	BEGIN

--0. 삭제전 데이터 로우 수량 확인
	UPDATE ZNERP_XLS_CHANGE_MASTER_CODE
	SET TABLE_ROWCNT = [ROWCOUNT]
	FROM ZNERP_XLS_CHANGE_MASTER_CODE A, (
	SELECT T.NAME [TABLENAME], SUM(ST.ROW_COUNT)[ROWCOUNT] 
 	 FROM SYS.TABLES T
 	 INNER JOIN SYS.SCHEMAS S 
 	 ON T.SCHEMA_ID = S.SCHEMA_ID
 	 INNER JOIN SYS.INDEXES I 
 	 ON T.OBJECT_ID = I.OBJECT_ID
 	 INNER JOIN SYS.DM_DB_PARTITION_STATS ST 
 	 ON T.OBJECT_ID = ST.OBJECT_ID
 	 AND I.INDEX_ID = ST.INDEX_ID
 	 WHERE I.INDEX_ID < 2
	 AND T.NAME IN (
		SELECT DISTINCT PROCESS_TYPE FROM [dbo].ZNERP_XLS_CHANGE_MASTER_CODE
		)
 	 GROUP BY T.NAME
	) B
	WHERE A.PROCESS_TYPE = B.[TABLENAME]


	----삭제데이터 백업
	--SELECT * INTO SCM_MMD_MODEL_ROUTE_M_2025 FROM SCM_MMD_MODEL_ROUTE_M
	--SELECT * INTO SCM_BOM_M_2025 FROM SCM_BOM_M
	--SELECT * INTO SCM_PLANT_M_2025 FROM SCM_PLANT_M
	--SELECT * INTO SCM_PSEUDO_DIVISION_M_2025 FROM SCM_PSEUDO_DIVISION_M
	--SELECT * INTO FP_MRP_CUTOFF_SUPPLY_H_2025 FROM FP_MRP_CUTOFF_SUPPLY_H
	--SELECT * INTO SCM_MMD_ITEM_ROUTE_TEMP_2025 FROM SCM_MMD_ITEM_ROUTE_TEMP
	----SELECT * INTO SCM_MODEL_COMP_TEMP_2025 FROM SCM_MODEL_COMP_TEMP

--중복값 삭제 : PK 에러 방지
--1.
	DELETE A FROM SCM_MMD_MODEL_ROUTE_M A, 
	(
	SELECT B.TO_PLANT_ID,  A.MODEL_ID, A.MMD_ROUTID, MIN(A.MMD_PLANT_ID) AS MMD_PLANT_ID, COUNT(*) AS CNT FROM SCM_MMD_MODEL_ROUTE_M A
	LEFT JOIN [ZNERP_CONV_MASTER] B
	ON A.MMD_PLANT_ID = B.FROM_PLANT_ID
	AND B.CODETYPE = 'PLANT_ID'
	WHERE B.TO_PLANT_ID IS NOT NULL
	GROUP BY B.TO_PLANT_ID,  A.MODEL_ID, A.MMD_ROUTID
	HAVING COUNT(*) > 1
	) B
	WHERE A.MMD_PLANT_ID = B.MMD_PLANT_ID
	AND A.MODEL_ID = B.MODEL_ID
	AND A.MMD_ROUTID = B.MMD_ROUTID


--2.
	DELETE A FROM SCM_BOM_M A,
	(
	SELECT PARENT_ITEM_ID, COMPANY_ID, DIVISION_ID, SITE_ID, CHILD_ITEM_ID, BOM_VERSION_ID, KEY_DATE, B.TO_PLANT_ID, MIN(A.PLANT_ID) AS PLANT_ID, COUNT(*) AS CNT FROM SCM_BOM_M A
	LEFT JOIN [ZNERP_CONV_MASTER] B
	ON A.PLANT_ID = B.FROM_PLANT_ID
	AND B.CODETYPE = 'PLANT_ID'
	WHERE B.TO_PLANT_ID IS NOT NULL
	GROUP BY PARENT_ITEM_ID, COMPANY_ID, DIVISION_ID, SITE_ID, CHILD_ITEM_ID, BOM_VERSION_ID, KEY_DATE, B.TO_PLANT_ID
	HAVING COUNT(*) > 1
	) B
	WHERE 1=1
	AND A.PARENT_ITEM_ID = B.PARENT_ITEM_ID
	AND A.COMPANY_ID = B.COMPANY_ID
	AND A.DIVISION_ID = B.DIVISION_ID 
	AND A.SITE_ID = B.SITE_ID
	AND A.CHILD_ITEM_ID = B.CHILD_ITEM_ID
	AND A.BOM_VERSION_ID = B.BOM_VERSION_ID
	AND A.KEY_DATE = B.KEY_DATE
	AND A.PLANT_ID = B.PLANT_ID

--3
	DELETE A FROM SCM_PLANT_M A,
	(
		SELECT COMPANY_ID, DIVISION_ID, SITE_ID, MIN(PLANT_ID) AS PLANT_ID, b.TO_PLANT_ID, COUNT(*) AS CNT FROM SCM_PLANT_M a
		LEFT JOIN [ZNERP_CONV_MASTER] B
		ON A.PLANT_ID = B.FROM_PLANT_ID
		AND B.CODETYPE = 'PLANT_ID'
		WHERE B.TO_PLANT_ID IS NOT NULL
		GROUP BY COMPANY_ID, DIVISION_ID, SITE_ID, b.TO_PLANT_ID
		HAVING COUNT(*) > 1
	)B
	WHERE A.COMPANY_ID = B.COMPANY_ID
	AND A.PLANT_ID = B.PLANT_ID
	AND A.SITE_ID = B.SITE_ID
	AND A.DIVISION_ID = B.DIVISION_ID

--4
	DELETE A FROM SCM_PSEUDO_DIVISION_M A,
	(
		SELECT COMPANY_ID, MIN(PLANT_ID) AS PLANT_ID, b.TO_PLANT_ID, COUNT(*) AS CNT FROM SCM_PSEUDO_DIVISION_M a
		LEFT JOIN [ZNERP_CONV_MASTER] B
		ON A.PLANT_ID = B.FROM_PLANT_ID
		AND B.CODETYPE = 'PLANT_ID'
		WHERE B.TO_PLANT_ID IS NOT NULL
		GROUP BY COMPANY_ID, b.TO_PLANT_ID
		HAVING COUNT(*) > 1
	)B
	WHERE A.COMPANY_ID = B.COMPANY_ID
	AND A.PLANT_ID = B.PLANT_ID

--5
	DELETE A FROM FP_MRP_CUTOFF_SUPPLY_H A,
	(
		SELECT COMPANY_ID, DIVISION_ID, SITE_ID, CUTOFF_DATE, SEQ, MIN(PLANT_ID) AS PLANT_ID, b.TO_PLANT_ID, COUNT(*) AS CNT FROM FP_MRP_CUTOFF_SUPPLY_H a
		LEFT JOIN [ZNERP_CONV_MASTER] B
		ON A.PLANT_ID = B.FROM_PLANT_ID
		AND B.CODETYPE = 'PLANT_ID'
		WHERE B.TO_PLANT_ID IS NOT NULL
		GROUP BY COMPANY_ID, DIVISION_ID, SITE_ID, CUTOFF_DATE, b.TO_PLANT_ID, SEQ
		HAVING COUNT(*) > 1
	)B
	WHERE A.COMPANY_ID = B.COMPANY_ID
	AND A.PLANT_ID = B.PLANT_ID
	AND A.SITE_ID = B.SITE_ID
	AND A.CUTOFF_DATE = B.CUTOFF_DATE
	AND A.SEQ = B.SEQ

--6
	DELETE  A FROM SCM_MMD_ITEM_ROUTE_TEMP A,
	(
		SELECT MIN(MMD_PLANT_ID) AS MMD_PLANT_ID, C.TO_PLANT_ID AS TO_MMD_PLANT_ID, MODEL_ID, MMD_ROUTID, COMPANY_ID, DIVISION_ID, SITE_ID,  CONCATENATE_ITEM, PARENT_DIVISION_ID, MIN(PARENT_PLANT_ID) AS PARENT_PLANT_ID, D.TO_PLANT_ID AS TO_PARENT_PLANT_ID
		, MIN(PLANT_ID) AS PLANT_ID, b.TO_PLANT_ID, COUNT(*) AS CNT FROM SCM_MMD_ITEM_ROUTE_TEMP a
		LEFT JOIN [ZNERP_CONV_MASTER] B
		ON A.PLANT_ID = B.FROM_PLANT_ID
		AND B.CODETYPE = 'PLANT_ID'
		LEFT JOIN [ZNERP_CONV_MASTER] C
		ON A.MMD_PLANT_ID = C.FROM_PLANT_ID
		AND C.CODETYPE = 'PLANT_ID'
		LEFT JOIN [ZNERP_CONV_MASTER] D
		ON A.PARENT_PLANT_ID = D.FROM_PLANT_ID
		AND D.CODETYPE = 'PLANT_ID'
		WHERE B.TO_PLANT_ID IS NOT NULL
		AND  C.TO_PLANT_ID IS NOT NULL
		AND  D.TO_PLANT_ID IS NOT NULL
		GROUP BY MODEL_ID, MMD_ROUTID, COMPANY_ID, DIVISION_ID, SITE_ID,  CONCATENATE_ITEM, PARENT_DIVISION_ID, b.TO_PLANT_ID,  C.TO_PLANT_ID,  D.TO_PLANT_ID
		HAVING COUNT(*) > 1
	)B
	WHERE A.MODEL_ID = B.MODEL_ID
	AND A.MMD_ROUTID = B.MMD_ROUTID
	AND A.COMPANY_ID = B.COMPANY_ID
	AND A.DIVISION_ID = B.DIVISION_ID
	AND A.SITE_ID = B.SITE_ID
	AND A.CONCATENATE_ITEM = B.CONCATENATE_ITEM
	AND A.PARENT_DIVISION_ID = B.PARENT_DIVISION_ID
	AND A.MMD_PLANT_ID = B.MMD_PLANT_ID
	AND A.PARENT_PLANT_ID = B.PARENT_PLANT_ID
	AND A.PLANT_ID = B.PLANT_ID


	DELETE  A FROM SCM_MMD_ITEM_ROUTE_TEMP A,
	(
	SELECT MODEL_ID, MMD_ROUTID, COMPANY_ID, DIVISION_ID, SITE_ID,  CONCATENATE_ITEM, PARENT_DIVISION_ID, MIN(PARENT_PLANT_ID) AS PARENT_PLANT_ID, D.TO_PLANT_ID AS TO_PARENT_PLANT_ID
		, MIN(PLANT_ID) AS PLANT_ID, b.TO_PLANT_ID, COUNT(*) AS CNT FROM SCM_MMD_ITEM_ROUTE_TEMP a
		LEFT JOIN [ZNERP_CONV_MASTER] B
		ON A.PLANT_ID = B.FROM_PLANT_ID
		AND B.CODETYPE = 'PLANT_ID'
		LEFT JOIN [ZNERP_CONV_MASTER] C
		ON A.MMD_PLANT_ID = C.FROM_PLANT_ID
		AND C.CODETYPE = 'PLANT_ID'
		LEFT JOIN [ZNERP_CONV_MASTER] D
		ON A.PARENT_PLANT_ID = D.FROM_PLANT_ID
		AND D.CODETYPE = 'PLANT_ID'
		WHERE B.TO_PLANT_ID IS NOT NULL
		
		AND  D.TO_PLANT_ID IS NOT NULL
		GROUP BY MODEL_ID, MMD_ROUTID, COMPANY_ID, DIVISION_ID, SITE_ID,  CONCATENATE_ITEM, PARENT_DIVISION_ID, b.TO_PLANT_ID,    D.TO_PLANT_ID
		HAVING COUNT(*) > 1
	)B
	WHERE A.MODEL_ID = B.MODEL_ID
	AND A.MMD_ROUTID = B.MMD_ROUTID
	AND A.COMPANY_ID = B.COMPANY_ID
	AND A.DIVISION_ID = B.DIVISION_ID
	AND A.SITE_ID = B.SITE_ID
	AND A.CONCATENATE_ITEM = B.CONCATENATE_ITEM
	AND A.PARENT_DIVISION_ID = B.PARENT_DIVISION_ID
	AND A.PARENT_PLANT_ID = B.PARENT_PLANT_ID
	AND A.PLANT_ID = B.PLANT_ID

--7
	DELETE A FROM SCM_MODEL_COMP_TEMP A,
	(
		SELECT COMPANY_ID, DIVISION_ID, SITE_ID, MODEL_ID, CONCATENATE_ITEM, MIN(PLANT_ID) AS PLANT_ID, b.TO_PLANT_ID, COUNT(*) AS CNT FROM SCM_MODEL_COMP_TEMP a
		LEFT JOIN [ZNERP_CONV_MASTER] B
		ON A.PLANT_ID = B.FROM_PLANT_ID
		AND B.CODETYPE = 'PLANT_ID'
		WHERE B.TO_PLANT_ID IS NOT NULL
		GROUP BY COMPANY_ID, DIVISION_ID, SITE_ID, CONCATENATE_ITEM, b.TO_PLANT_ID, MODEL_ID
		HAVING COUNT(*) > 1
	)B
	WHERE A.COMPANY_ID = B.COMPANY_ID
	AND A.PLANT_ID = B.PLANT_ID
	AND A.SITE_ID = B.SITE_ID
	AND A.CONCATENATE_ITEM = B.CONCATENATE_ITEM
	AND A.MODEL_ID = B.MODEL_ID


--8
	DELETE A FROM SCM_SLURRY_RATE_H A,
	(
		SELECT COMPANY_ID, DIVISION_ID, SITE_ID, PARENT_ITEM_ID, MIN(PLANT_ID) AS PLANT_ID, b.TO_PLANT_ID, COUNT(*) AS CNT FROM SCM_SLURRY_RATE_H a
		LEFT JOIN [ZNERP_CONV_MASTER] B
		ON A.PLANT_ID = B.FROM_PLANT_ID
		AND B.CODETYPE = 'PLANT_ID'
		WHERE B.TO_PLANT_ID IS NOT NULL
		GROUP BY COMPANY_ID, DIVISION_ID, SITE_ID, PARENT_ITEM_ID, b.TO_PLANT_ID
		HAVING COUNT(*) > 1
	)B
	WHERE A.COMPANY_ID = B.COMPANY_ID
	AND A.PLANT_ID = B.PLANT_ID
	AND A.SITE_ID = B.SITE_ID
	AND A.PARENT_ITEM_ID = B.PARENT_ITEM_ID



--9
	DELETE A FROM SCM_MODEL_COMP_EFFECTIVE_DATE A,
	(
		SELECT COMPANY_ID, DIVISION_ID, SITE_ID, MODEL_ID, CONCATENATE_ITEM, EFF_START_DATE, MIN(PLANT_ID) AS PLANT_ID, b.TO_PLANT_ID, COUNT(*) AS CNT FROM SCM_MODEL_COMP_EFFECTIVE_DATE a
		LEFT JOIN [ZNERP_CONV_MASTER] B
		ON A.PLANT_ID = B.FROM_PLANT_ID
		AND B.CODETYPE = 'PLANT_ID'
		WHERE B.TO_PLANT_ID IS NOT NULL
		GROUP BY COMPANY_ID, DIVISION_ID, SITE_ID, MODEL_ID, CONCATENATE_ITEM, EFF_START_DATE, b.TO_PLANT_ID
		HAVING COUNT(*) > 1
	)B
	WHERE A.COMPANY_ID = B.COMPANY_ID
	AND A.PLANT_ID = B.PLANT_ID
	AND A.SITE_ID = B.SITE_ID
	AND A.MODEL_ID = B.MODEL_ID
	AND A.CONCATENATE_ITEM = B.CONCATENATE_ITEM
	AND A.EFF_START_DATE = B.EFF_START_DATE


	END

	

END
