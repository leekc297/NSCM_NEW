CREATE         VIEW FP_MES_FACTORY_M_V AS

-- ================================================================================================
-- Program ID          : 
-- Program Name        : FP_MES_FACTORY_M_V
-- Param               :
-- Batch Period        : 
-- Description         :
-- Source Table        : SCM_FACTORY_M
-- Destination Table   : 
-- Version             : 1.0 	2026-01-02 yschoithira	[E20251205-001628] ESMI4동 ESS, 자동차 라인 MES DB통합에 따른 기능개선 건
--														Plant, Division, Factory 정보를 통합 되는 동 기준으로 변경하여 출력
-- ================================================================================================

SELECT DISTINCT
	  ISNULL(Y.COMPANY_ID,			X.COMPANY_ID)			AS COMPANY_ID
	, ISNULL(Y.DIVISION_ID,		X.DIVISION_ID)			AS DIVISION_ID
	, ISNULL(Y.SITE_ID,			X.SITE_ID)				AS SITE_ID
	, ISNULL(Y.PLANT_ID,			X.PLANT_ID)				AS PLANT_ID
	, ISNULL(Y.MES_PLANT_ID,		X.MES_PLANT_ID)			AS MES_PLANT_ID
	, ISNULL(Y.FACTORY_ID,			X.FACTORY_ID)			AS FACTORY_ID
	, ISNULL(Y.SHOP_GROUP_ID,		X.SHOP_GROUP_ID)		AS SHOP_GROUP_ID
	, ISNULL(Y.MES_SOURCE_GROUP,	X.MES_SOURCE_GROUP)		AS MES_SOURCE_GROUP
	, ISNULL(Y.SPC_SOURCE_GROUP,	X.SPC_SOURCE_GROUP)		AS SPC_SOURCE_GROUP
	, ISNULL(Y.FCS_SOURCE_GROUP,	X.FCS_SOURCE_GROUP)		AS FCS_SOURCE_GROUP
	, ISNULL(Y.ELEC_VERSION_TYPE,	X.ELEC_VERSION_TYPE)	AS ELEC_VERSION_TYPE
	, X.COMPANY_ID				AS ORG_COMPANY_ID
	, X.DIVISION_ID			AS ORG_DIVISION_ID
	, X.SITE_ID				AS ORG_SITE_ID
	, X.PLANT_ID				AS ORG_PLANT_ID
	, X.MES_PLANT_ID			AS ORG_MES_PLANT_ID
	, X.FACTORY_ID				AS ORG_FACTORY_ID
	, X.SHOP_GROUP_ID			AS ORG_SHOP_GROUP_ID
	, X.MES_SOURCE_GROUP		AS ORG_MES_SOURCE_GROUP
	, X.SPC_SOURCE_GROUP		AS ORG_SPC_SOURCE_GROUP
	, X.FCS_SOURCE_GROUP		AS ORG_FCS_SOURCE_GROUP
	, X.ELEC_VERSION_TYPE		AS ORG_ELEC_VERSION_TYPE
	, X.MES_MNGL_PRDN
	, ISNULL(X.MES_MNGL_PRDN, Y.FACTORY_ID) AS CONV_FACTORY_ID
	, CASE WHEN Y.FACTORY_ID <> X.FACTORY_ID THEN 'Y' ELSE 'N' END AS CONV_FACTORY_FLAG
FROM	SCM_FACTORY_M AS X WITH(NOLOCK)
	LEFT OUTER JOIN SCM_FACTORY_M AS Y WITH(NOLOCK)
	ON 1=1
	AND	X.MES_MNGL_PRDN = Y.FACTORY_ID
WHERE	1=1
;