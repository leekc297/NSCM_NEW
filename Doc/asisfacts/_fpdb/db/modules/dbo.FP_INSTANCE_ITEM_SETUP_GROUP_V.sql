

	CREATE VIEW [dbo].[FP_INSTANCE_ITEM_SETUP_GROUP_V]
AS	
SELECT 	A.INSTANCE_ID, A.OPERATION_ID, A.SETUP_CATEGORY_ID
		, CASE WHEN A.SETUP_KEY_ID = 'ATTRIBUTE1' THEN C.ATTRIBUTE1
			WHEN A.SETUP_KEY_ID = 'ATTRIBUTE2' THEN C.ATTRIBUTE2
			WHEN A.SETUP_KEY_ID = 'ATTRIBUTE3' THEN C.ATTRIBUTE3
			WHEN A.SETUP_KEY_ID = 'ATTRIBUTE4' THEN C.ATTRIBUTE4
			WHEN A.SETUP_KEY_ID = 'ATTRIBUTE5' THEN C.ATTRIBUTE5
			WHEN A.SETUP_KEY_ID = 'ATTRIBUTE6' THEN C.ATTRIBUTE6
			WHEN A.SETUP_KEY_ID = 'ATTRIBUTE7' THEN C.ATTRIBUTE7
			WHEN A.SETUP_KEY_ID = 'ATTRIBUTE8' THEN C.ATTRIBUTE8
			WHEN A.SETUP_KEY_ID = 'ATTRIBUTE9' THEN C.ATTRIBUTE9
			WHEN A.SETUP_KEY_ID = 'ATTRIBUTE10' THEN C.ATTRIBUTE10
			WHEN A.SETUP_KEY_ID = 'ATTRIBUTE11' THEN C.ATTRIBUTE11
			WHEN A.SETUP_KEY_ID = 'ATTRIBUTE12' THEN C.ATTRIBUTE12
			WHEN A.SETUP_KEY_ID = 'ATTRIBUTE13' THEN C.ATTRIBUTE13
			WHEN A.SETUP_KEY_ID = 'ATTRIBUTE14' THEN C.ATTRIBUTE14
			WHEN A.SETUP_KEY_ID = 'ATTRIBUTE15' THEN C.ATTRIBUTE15
			END AS SETUP_KEY_ID
		, B.ATTRIBUTE_LIST AS ITEM_SETUP_GROUP_ID, A.REFERANCE_OPERATION_ID, A.CALCULATION, A.SETUP_KEY_ID AS REFERANCE_ATTRIBUTE_ID
FROM 	FP_ITEM_SETUP_GROUP_M A,
		FP_INSTANCE_ITEM_SETUP_ATTR_LIST_M B,
		FP_INSTANCE_ITEM_SETUP_ATTR_TYPE_M C
WHERE 	1=1
AND 		A.INSTANCE_ID = B.INSTANCE_ID 
AND 		A.INSTANCE_ID = C.INSTANCE_ID
AND 		A.SETUP_CATEGORY_ID = 'ATTRIBUTE'
AND 		A.ACTIVE_FLAG = 'Y'
AND 		A.SETUP_KEY_ID = B.ATTRIBUTE_TYPE 
AND 		A.OPERATION_ID = C.OPERATION_ID 
UNION ALL
SELECT 	A.INSTANCE_ID, A.OPERATION_ID, A.SETUP_CATEGORY_ID, A.SETUP_KEY_ID, '-' AS ATTRIBUTE_VALUE, A.REFERANCE_OPERATION_ID, A.CALCULATION, '-' AS REFERANCE_ATTRIBUTE_ID
FROM 	FP_ITEM_SETUP_GROUP_M A
WHERE 	1=1
AND 		A.SETUP_CATEGORY_ID = 'ITEM'
AND 		A.ACTIVE_FLAG = 'Y'
	UNION ALL
	SELECT C.INSTANCE_ID, A.OPERATION_ID, A.SETUP_CATEGORY_ID, A.SETUP_KEY_ID, '-' AS ATTRIBUTE_VALUE, A.REFERANCE_OPERATION_ID, A.CALCULATION, '-' AS REFERANCE_ATTRIBUTE_ID
	FROM   SCM_ITEM_SETUP_GROUP_M  A,
		   SCM_SYS_LOOKUP_VALUE    B,
		   FP_INSTANCE_OPERATION_V C
	WHERE  B.LOOKUP_TYPE_CODE = 'SETUP_CATEGORY'
	AND    UPPER(A.SETUP_CATEGORY_ID) = UPPER('MATERIAL')
	AND    A.SETUP_CATEGORY_ID = B.SEGMENT1
	AND	   A.COMPANY_ID = C.COMPANY_ID
	AND	   A.DIVISION_ID = C.DIVISION_ID
	AND	   A.SITE_ID = C.SITE_ID
	AND	   A.OPERATION_ID = C.OPERATION_ID
	GROUP  BY C.INSTANCE_ID, A.OPERATION_ID, A.SETUP_CATEGORY_ID, A.SETUP_KEY_ID, A.REFERANCE_OPERATION_ID, A.CALCULATION
