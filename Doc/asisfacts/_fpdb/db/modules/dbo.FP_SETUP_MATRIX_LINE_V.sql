CREATE VIEW [dbo].[FP_SETUP_MATRIX_LINE_V]
--WITH SCHEMABINDING
AS
WITH
	SETUP_OPERATION
	AS (SELECT 	SEGMENT1 AS SITE_ID, SEGMENT2 AS DIVISION_ID, SEGMENT3 AS OPERATION_ID
		FROM 	SCM_SYS_LOOKUP_VALUE
		WHERE 	1=1
		AND 	LOOKUP_TYPE_CODE = 'SETUP_OPERATION'
		AND 	ACTIVE_FLAG = 'Y'),
	TIME_DATA
	AS (SELECT 	MIN(YYYYMM) AS S_MONTH, MAX(YYYYMM) AS E_MONTH, MIN(YYYYWW) AS S_WEEK, MAX(YYYYWW) AS E_WEEK
		FROM 	TH_UIS_CAL
		WHERE 	1=1
		AND 	YYYYMMDD >=  CONVERT(CHAR(8), GETDATE() - 7, 112)
		AND 	YYYYMMDD <=  CONVERT(CHAR(8), GETDATE() + 84, 112)),
	ITEM_LINE_SETUP_GROUP_ASSIGN
	AS	(SELECT 	DISTINCT A.COMPANY_ID, A.SITE_ID, A.DIVISION_ID, A.PLANT_ID, A.FACTORY_ID, A.ITEM_ID, A.OPERATION_ID, 
					A.LINE_ID, ISNULL(A.ELECTRODE_TYPE, '-') AS ELECTRODE_TYPE
	FROM 	SCM_ITEM_LINE_ASSIGN_M A,
			SCM_LINE_M B,
			SCM_ITEM_M C,
			(SELECT	DISTINCT A.SITE_ID, A.DIVISION_ID, A.ITEM_ID
			 FROM 	SCM_DEMAND_INFO_H A,
			 		TIME_DATA B
			 WHERE 	1=1
			 AND 	A.MFG_WEEK >= B.S_WEEK
			 AND 	A.MFG_WEEK <= B.E_WEEK
			 UNION ALL
			 SELECT 	A.SITE_ID, A.DIVISION_ID, A.ITEM_ID
			 FROM 	SCM_ITEM_M A
			 WHERE 	1=1
			 AND 	A.SITE_ID = 'A001'
			 AND 	A.DIVISION_ID = '40'
			 AND 	A.FLOW_ID = 'E0500'
			 ) D,
			 TIME_DATA E,
			 SETUP_OPERATION F
	WHERE 	1=1
	AND 	A.MONTH >= E.S_MONTH
	AND 	A.MONTH >= E.E_MONTH
	AND 	A.PRIORITY NOT IN ('0','9')
	AND 	A.ACTIVE_FLAG = 'Y'
	AND 	A.SITE_ID = B.SITE_ID
	AND 	A.DIVISION_ID = B.DIVISION_ID
	AND 	A.PLANT_ID = B.PLANT_ID
	AND 	A.LINE_ID = B.LINE_ID
	AND 	A.OPERATION_ID = B.OPERATION_ID
	AND 	ISNULL(A.ELECTRODE_TYPE, '-') = ISNULL(B.ELECTRODE_TYPE, '-')
	AND 	B.ACTIVE_FLAG = 'Y'
	AND 	A.SITE_ID = C.SITE_ID
	AND 	A.DIVISION_ID = C.DIVISION_ID
	AND 	A.ITEM_ID = C.ITEM_ID
	AND 	C.ACTIVE_FLAG = 'Y'	
	AND 	A.SITE_ID = D.SITE_ID
	AND 	A.DIVISION_ID = D.DIVISION_ID
	AND 	A.ITEM_ID = D.ITEM_ID
	AND 	A.SITE_ID = F.SITE_ID
	AND 	A.DIVISION_ID = F.DIVISION_ID
	AND 	A.OPERATION_ID = F.OPERATION_ID
	)
SELECT 	DISTINCT  A.COMPANY_ID, A.SITE_ID, A.DIVISION_ID, A.PLANT_ID, A.FACTORY_ID, A.OPERATION_ID, A.LINE_ID, ISNULL(A.ELECTRODE_TYPE, '-') AS ELECTRODE_TYPE, 
		A.ITEM_ID AS FROM_ITEM_ID, B.ITEM_ID AS TO_ITEM_ID
FROM 	ITEM_LINE_SETUP_GROUP_ASSIGN A,
		ITEM_LINE_SETUP_GROUP_ASSIGN B
WHERE 	1=1
AND 	A.SITE_ID = B.SITE_ID
AND 	A.DIVISION_ID = B.DIVISION_ID
AND 	A.PLANT_ID = B.PLANT_ID
AND 	A.FACTORY_ID = B.FACTORY_ID
AND 	A.LINE_ID = B.LINE_ID
AND 	ISNULL(A.ELECTRODE_TYPE, '-') = ISNULL(B.ELECTRODE_TYPE, '-')
AND 	A.OPERATION_ID = B.OPERATION_ID
AND 	A.ITEM_ID != B.ITEM_ID
