CREATE VIEW [dbo].[SCM_BOM_M_TEMP_V]
AS
with ORG_BOM as (
		select * from SCM_BOM_M_ORG with (nolock) 
		where 1=1
		-- 하드코딩 G380
		and company_id in (SELECT SEGMENT2 FROM SCM_CODE_LOOKUP_VALUE WITH(NOLOCK) WHERE LOOKUP_TYPE_CODE='SCM_BOM_M_TEMP_V' AND SEGMENT1  = 'EFFECTIVE_COMPANY' AND ACTIVE_FLAG='Y')
		-- 하드코딩 81
		and division_id  in (SELECT SEGMENT2 FROM SCM_CODE_LOOKUP_VALUE WITH(NOLOCK) WHERE LOOKUP_TYPE_CODE='SCM_BOM_M_TEMP_V' AND SEGMENT1  = 'EFFECTIVE_DIVISION' AND ACTIVE_FLAG='Y')
		-- 하드코딩 A003
		and site_id  in (SELECT SEGMENT2 FROM SCM_CODE_LOOKUP_VALUE WITH(NOLOCK) WHERE LOOKUP_TYPE_CODE='SCM_BOM_M_TEMP_V' AND SEGMENT1  = 'EFFECTIVE_SITE' AND ACTIVE_FLAG='Y')
		-- 하드코딩 G382
		and plant_id  in (SELECT SEGMENT2 FROM SCM_CODE_LOOKUP_VALUE WITH(NOLOCK) WHERE LOOKUP_TYPE_CODE='SCM_BOM_M_TEMP_V' AND SEGMENT1  = 'EFFECTIVE_PLANT' AND ACTIVE_FLAG='Y')
		and eff_end_date >= getdate()
		and parent_item_id in (
				select PARENT_ITEM_ID
				from SCM_MODEL_COMP_EFFECTIVE_DATE with (nolock) 
				where 1=1
				and company_id  in (SELECT SEGMENT2 FROM SCM_CODE_LOOKUP_VALUE WITH(NOLOCK) WHERE LOOKUP_TYPE_CODE='SCM_BOM_M_TEMP_V' AND SEGMENT1  = 'EFFECTIVE_COMPANY' AND ACTIVE_FLAG='Y')
				and division_id  in (SELECT SEGMENT2 FROM SCM_CODE_LOOKUP_VALUE WITH(NOLOCK) WHERE LOOKUP_TYPE_CODE='SCM_BOM_M_TEMP_V' AND SEGMENT1  = 'EFFECTIVE_DIVISION' AND ACTIVE_FLAG='Y')
				and site_id  in (SELECT SEGMENT2 FROM SCM_CODE_LOOKUP_VALUE WITH(NOLOCK) WHERE LOOKUP_TYPE_CODE='SCM_BOM_M_TEMP_V' AND SEGMENT1  = 'EFFECTIVE_SITE' AND ACTIVE_FLAG='Y')
				and plant_id  in (SELECT SEGMENT2 FROM SCM_CODE_LOOKUP_VALUE WITH(NOLOCK) WHERE LOOKUP_TYPE_CODE='SCM_BOM_M_TEMP_V' AND SEGMENT1  = 'EFFECTIVE_PLANT' AND ACTIVE_FLAG='Y')
				-- 하드코딩'APFCAPHEV-B2' 
				and model_id  in (SELECT SEGMENT2 FROM SCM_CODE_LOOKUP_VALUE WITH(NOLOCK) WHERE LOOKUP_TYPE_CODE='SCM_BOM_M_TEMP_V' AND SEGMENT1  = 'EFFECTIVE_MODEL' AND ACTIVE_FLAG='Y')
				-- 하드코딩'APFCAPHEV-B2' 
				and child_item_id not in (SELECT SEGMENT2 FROM SCM_CODE_LOOKUP_VALUE WITH(NOLOCK) WHERE LOOKUP_TYPE_CODE='SCM_BOM_M_TEMP_V' AND SEGMENT1  = 'EFFECTIVE_ITEM' AND ACTIVE_FLAG='Y')
				and eff_end_date >= getdate()
				group by parent_item_id 
				--'ABCAT1454B',
				--'ABCCT1447B',
				--'ACPN1046I-A1-200',
				--'AFCFC1447B',
				--'AMDAU0004I',
				--'ANPAN1834A',
				--'ANPCA1416B',
				--'APCAN2030A',
				--'APCCA1582B',
				--'APFCAPHEV-B2',
				--'ASLAN1575A',
				--'ASLCA1607A',
				--'ASLPD0073A',
				--'RSE01735AA'
			) 
) 
-- Pack 
select * 
from org_bom 
where parent_item_id = 'APFCAPHEV-B2'
-- Module 
union all 
select * 
from org_bom 
where parent_item_id = 'AMDAU0004I'
-- Cell Product - Cell Assy 
union all 
select	COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, 
		'ACPN1046I-A1-200' PARENT_ITEM_ID,
		'ACPN1046I-A1-200_ASSY' CHILD_ITEM_ID,
		BOM_VERSION_ID, KEY_DATE, BOM_VERSION_LINE, PARENT_QTY, PARENT_UOM, PARENT_QTY as CHILD_QTY, PARENT_UOM as CHILD_UOM, 
		ALT_ID, ALT_PRIORITY, ALT_RATE, EFF_START_DATE, EFF_END_DATE, ECO_CODE, PHANTOM, STANDARD_FLAG,
		ACTIVE_FLAG, DESCRIPTION, INSERT_ID, INSERT_TIME, UPDATE_ID, UPDATE_TIME   
from org_bom 
where parent_item_id = 'ACPN1046I-A1-200'
and child_item_id = 'AFCFC1447B'
-- Cell Assy and downward
union all 
select	COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, 
		'ACPN1046I-A1-200_ASSY' PARENT_ITEM_ID,
		CHILD_ITEM_ID,
		BOM_VERSION_ID, KEY_DATE, BOM_VERSION_LINE, PARENT_QTY, PARENT_UOM, PARENT_QTY as CHILD_QTY, PARENT_UOM as CHILD_UOM, 
		ALT_ID, ALT_PRIORITY, ALT_RATE, EFF_START_DATE, EFF_END_DATE, ECO_CODE, PHANTOM, STANDARD_FLAG,
		ACTIVE_FLAG, DESCRIPTION, INSERT_ID, INSERT_TIME, UPDATE_ID, UPDATE_TIME   
from org_bom 
where parent_item_id = 'ACPN1046I-A1-200'
-- Else
union all 
select	COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, 
		PARENT_ITEM_ID,
		CHILD_ITEM_ID,
		BOM_VERSION_ID, KEY_DATE, BOM_VERSION_LINE, PARENT_QTY, PARENT_UOM, PARENT_QTY as CHILD_QTY, PARENT_UOM as CHILD_UOM, 
		ALT_ID, ALT_PRIORITY, ALT_RATE, EFF_START_DATE, EFF_END_DATE, ECO_CODE, PHANTOM, STANDARD_FLAG,
		ACTIVE_FLAG, DESCRIPTION, INSERT_ID, INSERT_TIME, UPDATE_ID, UPDATE_TIME   
from org_bom 
where parent_item_id not in ('ACPN1046I-A1-200', 'APFCAPHEV-B2','AMDAU0004I')
;
