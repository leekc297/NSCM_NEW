CREATE VIEW [dbo].[SCM_PANCAKE_SLURRY_MATR_ALL_VER_V]
-- ================================================================================================
-- Program ID          : SCM_PANCAKE_SLURRY_MATR_ALL_VER_V
--
-- Program Name        : SCM_PANCAKE_SLURRY_MATR_ALL_VER_V
-- Param               :
-- Batch Period        : 
-- Description         : Pancake 하위 BOM 구성품 조회
--
-- Source System       : FP SDB
-- Destination System  : SCP SDB
-- Source Table        : SCM_BOM_M, SCM_ITEM_PLM_DESC_M, SCM_ITEM_M, SCM_ITEM_CLASS_M, SCM_SLURRY_SOLID_RATE
--                       FP_PROD_VERSION_M
-- Destination Table   : 
--
-- Create(Update) Date : 2022.11.24
-- Author              : 김춘동
-- Version             : 2022-11-24 kimcd SCM_PANCAKE_SLURRY_MATERIAL_V에서 분리하여 형성
--                                        최종 버전 뿐 아니라 전체 Version 정보 필요
-- ================================================================================================
AS
WITH PC_SL_MAX AS ( SELECT A.[COMPANY_ID]
						, A.[DIVISION_ID]
						, A.[SITE_ID]
						, A.[PLANT_ID]
						, A.[FACTORY_ID]
						, A.[PAN_MODEL_ID]
						, A.[PAN_ITEM_ID]
						, A.[PAN_PROD_VERSION]
						, A.[PAN_PROD_SEQ]          -- 2019-04-01 kimcd 차수 컬럼 추가
						, A.[PROD_VERSION_TYPE]
						, CASE WHEN LEFT(A.[PAN_PROD_VERSION], 1) = 'Z' THEN 'TEST' ELSE 'MASS' END AS PROD_TYPE
						, A.[SLA_MODEL_ID]
						, A.[SLA_ITEM_ID]
						, A.[SLA_PROD_VERSION]
						, A.[SLA_PROD_SEQ]          -- 2019-04-01 kimcd 차수 컬럼 추가
					FROM  ( SELECT PAN.[COMPANY_ID]
								 , PAN.[DIVISION_ID]
								 , PAN.[SITE_ID]
								 , PAN.[PLANT_ID]
								 , PAN.[FACTORY_ID]
								 , PAN.[MODEL_ID]          AS PAN_MODEL_ID
								 , PAN.[ITEM_ID]           AS PAN_ITEM_ID
								 , PAN.[PROD_VERSION]      AS PAN_PROD_VERSION
								 , PAN.[PROD_SEQ]          AS PAN_PROD_SEQ  -- 2019-04-01 kimcd 차수 컬럼 추가
								 , PAN.[PROD_VERSION_TYPE]
								 , SLA.[MODEL_ID]          AS SLA_MODEL_ID
								 , SLA.[ITEM_ID]           AS SLA_ITEM_ID
								 , SLA.[PROD_VERSION]      AS SLA_PROD_VERSION
								 , SLA.[PROD_SEQ]          AS SLA_PROD_SEQ  -- 2019-04-01 kimcd 차수 컬럼 추가
						  FROM    [FP_PROD_VERSION_M]     PAN,
								  [FP_PROD_VERSION_M]     SLA
						  WHERE   PAN.[COMPANY_ID]        = SLA.[COMPANY_ID]
						  AND     PAN.[DIVISION_ID]       = SLA.[DIVISION_ID]
						  AND     PAN.[SITE_ID]           = SLA.[SITE_ID]
						  AND     PAN.[PLANT_ID]          = SLA.[PLANT_ID]
						  AND     PAN.[FACTORY_ID]        = SLA.[FACTORY_ID]
						  AND     PAN.[MODEL_ID]          = SLA.[MODEL_ID]
						  AND     PAN.[PROD_VERSION_TYPE] = SLA.[PROD_VERSION_TYPE]
						  AND     PAN.[PROD_VERSION]      = SLA.[PROD_VERSION]
						  AND     PAN.[PROD_SEQ]          = SLA.[PROD_SEQ]  -- 2019-04-01 kimcd 차수 컬럼 추가
						  AND     SUBSTRING(PAN.ITEM_ID,4,1) = SUBSTRING(SLA.ITEM_ID,4,1)
						  AND     SLA.ITEM_ID          LIKE 'ASL%'
						  AND     SLA.ITEM_ID      NOT LIKE 'ASLP%'
						  AND     PAN.ITEM_ID          LIKE 'APC%' ) A
					 )
SELECT 	A.COMPANY_ID,  A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.PROD_VERSION_TYPE, A.PROD_TYPE, A.PAN_PROD_VERSION, A.MODEL_ID, A.PROD_SEQ, /* 2019-04-01 kimcd 적용 모델, 차수 추가 */
		A.PC_ITEM_ID, 
		A.MATERIAL_ITEM_ID,
		A.CLASS_NAME,
		A.CATEGORY + ' ' +
		CAST(ROW_NUMBER() OVER (PARTITION BY A.SITE_ID, A.DIVISION_ID, A.PLANT_ID, A.FACTORY_ID, A.PROD_VERSION_TYPE, A.PROD_TYPE, A.PC_ITEM_ID, A.PAN_PROD_VERSION, A.MODEL_ID, A.PROD_SEQ, A.CLASS_NAME, A.SLURRY_ITEM_ID  order by A.MATERIAL_ITEM_ID) AS CHAR(10)) AS UI_COLUMN,
		-- 2021-11-01 kimcd A.SLURRY_ITEM_ID를 PARTITION BY에 추가
		A.DESCRIPTION,
		A.SLURRY_ITEM_ID -- 2021-11-01 kimcd Double Layer용 Slurry 컬럼 추가
FROM (
SELECT 	DISTINCT A.COMPANY_ID,  A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.PROD_VERSION_TYPE, A.PROD_TYPE,  A.PAN_PROD_VERSION, A.[PAN_MODEL_ID] AS MODEL_ID, A.[PAN_PROD_SEQ] AS PROD_SEQ, /* 2019-04-01 kimcd 적용 모델, 차수 추가 */
		A.PAN_ITEM_ID AS PC_ITEM_ID,
		B.CHILD_ITEM_ID  AS  MATERIAL_ITEM_ID,
		F.LEVEL_2_NAME AS CLASS_NAME,
		ISNULL(ISNULL( CASE WHEN F.LEVEL_2_NAME = 'Binder' THEN G.DESCRIPTION + '(' + CONVERT(NVARCHAR(6),CONVERT(NUMERIC(5,2),MAX(B.SOLID_RATE))) +'%)' ELSE G.DESCRIPTION END, G.DESCRIPTION ),B.CHILD_ITEM_ID) AS DESCRIPTION, -- 2019-06-25 kimcd description 없는 경우 item_id 추가
		CASE WHEN F.LEVEL_2_NAME IN ('Cathode Active Material','Anode Active Material') THEN 'Active Material' 
		     ELSE  F.LEVEL_2_NAME END AS CATEGORY,
		A.SLA_ITEM_ID AS SLURRY_ITEM_ID -- 2021-11-01 kimcd Double Layer용 Slurry 컬럼 추가
FROM 	PC_SL_MAX A,
	    SCM_SLURRY_SOLID_RATE B WITH(NOLOCK)
		LEFT OUTER JOIN SCM_ITEM_PLM_DESC_M G WITH(NOLOCK)
		ON B.CHILD_ITEM_ID = G.ITEM_ID
		AND G.USE_YN = 'Y',
		SCM_ITEM_M E WITH(NOLOCK),
		SCM_ITEM_CLASS_M F WITH(NOLOCK)
WHERE 	1=1
AND     A.COMPANY_ID = B.COMPANY_ID
AND 	A.SITE_ID = B.SITE_ID
AND 	A.DIVISION_ID = B.DIVISION_ID
AND     A.PLANT_ID = B.PLANT_ID
AND     A.FACTORY_ID = B.FACTORY_ID
AND     A.SLA_MODEL_ID = B.MODEL_ID
AND     A.SLA_PROD_VERSION = B.VERSION_ID
AND     A.SLA_PROD_SEQ = B.VERSION_SEQ -- 2019-04-01 kimcd 차수 컬럼 추가
AND     A.SLA_ITEM_ID = B.SLURRY_ITEM_ID
AND 	B.COMPANY_ID = E.COMPANY_ID
AND 	B.SITE_ID = E.SITE_ID
AND 	B.DIVISION_ID = E.DIVISION_ID
AND 	B.CHILD_ITEM_ID = E.ITEM_ID
AND 	E.ITEM_CLASS = F.CLASS_ID
AND 	F.LEVEL_2_NAME IN ('Cathode Active Material','Anode Active Material','Binder', 'Conducting Material', 'Addition Agent')  -- 2021-01-13 kimcd 첨가제 조회 추가
GROUP BY A.COMPANY_ID,  A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.PROD_VERSION_TYPE, A.PROD_TYPE, A.PAN_PROD_VERSION, A.[PAN_MODEL_ID], A.[PAN_PROD_SEQ],
		A.PAN_ITEM_ID,
		B.CHILD_ITEM_ID,
		F.LEVEL_2_NAME,
		G.DESCRIPTION,
		CASE WHEN F.LEVEL_2_NAME IN ('Cathode Active Material','Anode Active Material') THEN 'Active Material' 
		     ELSE  F.LEVEL_2_NAME END,
        A.SLA_ITEM_ID  -- 2021-11-01 kimcd Double Layer용 Slurry 컬럼 추가
UNION ALL
SELECT 	DISTINCT A.COMPANY_ID,  A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.PROD_VERSION_TYPE, A.PROD_TYPE, A.PAN_PROD_VERSION, A.[PAN_MODEL_ID] AS MODEL_ID, A.[PAN_PROD_SEQ] AS PROD_SEQ, /* 2019-04-01 kimcd 적용 모델, 차수 추가 */
		A.PAN_ITEM_ID AS PC_ITEM_ID,
		B.CHILD_ITEM_ID  AS  MATERIAL_ITEM_ID,
		F.LEVEL_3_NAME AS CLASS_NAME,
		ISNULL( -- 2019-06-25 kimcd description 없는 경우 item_id 추가
		ISNULL( CASE WHEN F.LEVEL_3_NAME = 'Pre Dispersion Slurry' THEN
					E.NICK_NAME
				ELSE G.DESCRIPTION END  + '(' + CONVERT(NVARCHAR(6),CONVERT(NUMERIC(5,2),MAX(B.SOLID_RATE))) +'%)' ,
		CASE WHEN F.LEVEL_3_NAME = 'Pre Dispersion Slurry' THEN
		    E.NICK_NAME
		ELSE G.DESCRIPTION END), B.CHILD_ITEM_ID) AS DESCRIPTION, -- 2019-06-25 kimcd description 없는 경우 item_id 추가
		F.LEVEL_3_NAME AS CATEGORY,
		A.SLA_ITEM_ID AS SLURRY_ITEM_ID -- 2021-11-01 kimcd Double Layer용 Slurry 컬럼 추가
FROM 	PC_SL_MAX A,
	    SCM_SLURRY_SOLID_RATE B WITH(NOLOCK)
		LEFT OUTER JOIN SCM_ITEM_PLM_DESC_M G WITH(NOLOCK)
		ON B.CHILD_ITEM_ID = G.ITEM_ID
		AND G.USE_YN = 'Y',
		SCM_ITEM_M E WITH(NOLOCK),
		SCM_ITEM_CLASS_M F WITH(NOLOCK)
WHERE 	1=1
AND     A.COMPANY_ID = B.COMPANY_ID
AND 	A.SITE_ID = B.SITE_ID
AND 	A.DIVISION_ID = B.DIVISION_ID
AND     A.PLANT_ID = B.PLANT_ID
AND     A.FACTORY_ID = B.FACTORY_ID
AND     A.SLA_MODEL_ID = B.MODEL_ID
AND     A.SLA_PROD_VERSION = B.VERSION_ID
AND     A.SLA_PROD_SEQ = B.VERSION_SEQ -- 2019-04-01 kimcd 차수 컬럼 추가
AND     A.SLA_ITEM_ID = B.SLURRY_ITEM_ID
AND 	B.COMPANY_ID = E.COMPANY_ID
AND 	B.SITE_ID = E.SITE_ID
AND 	B.DIVISION_ID = E.DIVISION_ID
AND 	B.CHILD_ITEM_ID = E.ITEM_ID
AND 	E.ITEM_CLASS = F.CLASS_ID
AND 	F.LEVEL_3_NAME IN ('Pre Dispersion Slurry', 'CMC')
GROUP BY A.COMPANY_ID,  A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.PROD_VERSION_TYPE, A.PROD_TYPE, A.PAN_PROD_VERSION, A.[PAN_MODEL_ID], A.[PAN_PROD_SEQ],
		A.PAN_ITEM_ID,
		B.CHILD_ITEM_ID,
		F.LEVEL_3_NAME,
		CASE WHEN F.LEVEL_3_NAME = 'Pre Dispersion Slurry' THEN
		    E.NICK_NAME
		ELSE G.DESCRIPTION END ,
		F.LEVEL_3_NAME,
		A.SLA_ITEM_ID -- 2021-11-01 kimcd Double Layer용 Slurry 컬럼 추가
UNION ALL
SELECT 	DISTINCT A.COMPANY_ID,  A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, B.FACTORY_ID, B.PROD_VERSION_TYPE, B.PROD_TYPE, B.PAN_PROD_VERSION, B.[PAN_MODEL_ID] AS MODEL_ID, B.[PAN_PROD_SEQ] AS PROD_SEQ, /* 2019-04-01 kimcd 적용 모델, 차수 추가 */
		A.PARENT_ITEM_ID AS PC_ITEM_ID,
		A.CHILD_ITEM_ID  AS  MATERIAL_ITEM_ID,
		E.LEVEL_3_NAME AS CLASS_NAME,
		ISNULL(G.DESCRIPTION, A.CHILD_ITEM_ID) AS DESCRIPTION, -- 2019-06-25 kimcd description 없는 경우 item_id 추가
		E.LEVEL_3_NAME  AS CATEGORY,
		NULL            AS SLURRY_ITEM_ID -- 2021-11-01 kimcd Double Layer용 Slurry 컬럼 추가
FROM 	SCM_BOM_M A WITH(NOLOCK)
		LEFT OUTER JOIN SCM_ITEM_PLM_DESC_M G WITH(NOLOCK)
		ON A.CHILD_ITEM_ID = G.ITEM_ID
		AND G.USE_YN = 'Y'
		, PC_SL_MAX  B
		, SCM_ITEM_M C WITH(NOLOCK)
		, SCM_ITEM_CLASS_M E WITH(NOLOCK)
WHERE 	1=1
AND 	A.EFF_END_DATE > GETDATE()
AND 	A.ACTIVE_FLAG = 'Y'
AND 	(A.ALT_ID IS NULL OR A.ALT_PRIORITY = 1)
AND     A.COMPANY_ID = B.COMPANY_ID
AND 	A.SITE_ID = B.SITE_ID
AND 	A.DIVISION_ID = B.DIVISION_ID
AND     A.PLANT_ID = B.PLANT_ID
AND 	A.PARENT_ITEM_ID = B.PAN_ITEM_ID
AND     A.COMPANY_ID = C.COMPANY_ID
AND 	A.SITE_ID = C.SITE_ID
AND 	A.DIVISION_ID = C.DIVISION_ID
AND 	A.CHILD_ITEM_ID = C.ITEM_ID
AND 	C.ITEM_CLASS = E.CLASS_ID
AND 	E.LEVEL_3_NAME = 'CMC'
GROUP BY A.COMPANY_ID,  A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, B.FACTORY_ID, B.PROD_VERSION_TYPE, B.PROD_TYPE,  B.PAN_PROD_VERSION, B.[PAN_MODEL_ID], B.[PAN_PROD_SEQ],
		A.PARENT_ITEM_ID, 
		A.CHILD_ITEM_ID,
		E.LEVEL_3_NAME,
		G.DESCRIPTION,
		E.LEVEL_3_NAME		
UNION ALL
SELECT 	DISTINCT A.COMPANY_ID,  A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.PROD_VERSION_TYPE, A.PROD_TYPE, A.PAN_PROD_VERSION, A.[PAN_MODEL_ID] AS MODEL_ID, A.[PAN_PROD_SEQ] AS PROD_SEQ, /* 2019-04-01 kimcd 적용 모델, 차수 추가 */
		A.PAN_ITEM_ID  AS PC_ITEM_ID,
		A.SLA_ITEM_ID  AS  MATERIAL_ITEM_ID, 
		E.LEVEL_2_NAME AS CLASS_NAME,
		ISNULL(C.ITEM_NAME,A.SLA_ITEM_ID) AS DESCRIPTION,  -- 2019-06-25 kimcd description 없는 경우 item_id 추가
		E.LEVEL_2_NAME  AS CATEGORY,
		A.SLA_ITEM_ID AS SLURRY_ITEM_ID -- 2021-11-01 kimcd Double Layer용 Slurry 컬럼 추가
FROM 	PC_SL_MAX A
		, SCM_ITEM_M C WITH(NOLOCK)
		, SCM_ITEM_CLASS_M E WITH(NOLOCK)
WHERE 	A.COMPANY_ID = C.COMPANY_ID
AND 	A.SITE_ID = C.SITE_ID
AND 	A.DIVISION_ID = C.DIVISION_ID
AND 	A.SLA_ITEM_ID = C.ITEM_ID
AND 	C.ITEM_CLASS = E.CLASS_ID
AND 	E.LEVEL_2_NAME = 'Slurry'
AND 	E.LEVEL_3_NAME NOT IN ('Pre Dispersion Slurry')
GROUP BY A.COMPANY_ID,  A.DIVISION_ID, A.SITE_ID, A.PLANT_ID,  A.FACTORY_ID, A.PROD_VERSION_TYPE, A.PROD_TYPE, A.PAN_PROD_VERSION, A.[PAN_MODEL_ID], A.[PAN_PROD_SEQ],
		A.PAN_ITEM_ID, 
		A.SLA_ITEM_ID, 
		E.LEVEL_2_NAME,
		C.ITEM_NAME,
		E.LEVEL_2_NAME,
		A.SLA_ITEM_ID  -- 2021-11-01 kimcd Double Layer용 Slurry 컬럼 추가
) A





