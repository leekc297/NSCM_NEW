CREATE VIEW [dbo].[FP_AMEND_UI_V]
AS
SELECT 	'PLAN_AMEND_UI' AS AMEND_UI_NAME,
		SEGMENT1 AS INSTANCE_ID,
		ATTRIBUTE2 AS USE_FLAG
FROM 	SCM_SYS_LOOKUP_VALUE
WHERE 	1=1
AND 	LOOKUP_TYPE_CODE = 'INSTANCE AMEND UI'
AND 	ATTRIBUTE2 = 'Y'
UNION ALL
SELECT 	ATTRIBUTE3 AS AMEND_UI_NAME,
		SEGMENT1 AS INSTANCE_ID,
		ATTRIBUTE4 AS USE_FLAG
FROM 	SCM_SYS_LOOKUP_VALUE
WHERE 	1=1
AND 	LOOKUP_TYPE_CODE = 'INSTANCE AMEND UI'
AND 	ACTIVE_FLAG = 'Y'
AND 	ATTRIBUTE4 IS NOT NULL
UNION ALL
SELECT 	ATTRIBUTE5 AS AMEND_UI_NAME,
		SEGMENT1 AS INSTANCE_ID,
		ATTRIBUTE6 AS USE_FLAG
FROM 	SCM_SYS_LOOKUP_VALUE
WHERE 	1=1
AND 	LOOKUP_TYPE_CODE = 'INSTANCE AMEND UI'
AND 	ACTIVE_FLAG = 'Y'
AND 	ATTRIBUTE6 IS NOT NULL
