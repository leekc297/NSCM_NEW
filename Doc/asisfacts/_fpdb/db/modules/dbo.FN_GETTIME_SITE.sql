CREATE FUNCTION [dbo].[FN_GETTIME_SITE]
(@str1 nvarchar(MAX))
RETURNS DATETIME
WITH EXEC AS CALLER
AS
BEGIN
DECLARE @retVal DATETIME;

	set @retVal = (SELECT MAX(DATEADD(HOUR, CONVERT(NUMERIC, SEGMENT3), GETDATE())) FROM   SCM_SYS_LOOKUP_VALUE WHERE LOOKUP_TYPE_CODE = 'SITE_INTERVAL' AND SEGMENT1 = @str1)
 
	RETURN @retVal;
END
