CREATE VIEW [dbo].[FP_KPI_SATISFACTION_V]
-- ================================================================================================
-- Program ID          : FP_KPI_SATISFACTION_V
--
-- Program Name        : FP_KPI_SATISFACTION_V
-- Param               :
-- Batch Period        : 
-- Description         : KPI 지표 구분 ID - 충족율 - 012 : SCP타겟대비 FP 계획 충족율
--
-- Source System       : FP SDB
-- Destination System  : FP SDB
-- Source Table        : FP_WEEKLY_DEMAND_PRODUCT_H, FP_RELEASE_FULL_PLAN_H, SCM_DAILY_PRODUCT_RESULT_H
-- Destination Table   : 
--
-- Create(Update) Date : 2019.06.13
-- Author              : kim choon dong
-- Version             : 2019-06-13 kimcd 최종 수신된 SCP Target과 최종 배포된 Release 계획의 수요 만족율
--                       2019-06-24 kimcd Release Plan에서 Division 제거 오창 조립 81,82개 나와야 하나 81만 나옴
--                       2019-07-09 kimcd 전극은 6주로 단축
--                       2019-07-17 kimcd 전극 5주, 소형 6주 자동차 8주로 수정
--                       2021-11-03 kimcd P5200 공정 기준으로 Target 형성하면서 수정
-- ================================================================================================
AS
WITH SCP_PLAN
AS ( SELECT  A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.SHOP_GROUP_ID, A.SCP_PLAN_ID, C.WEEK AS TARGET_WEEK, SUBSTRING(A.SCP_PLAN_ID, 0,9) AS PLAN_START_DATE, D.WEEK AS END_WEEK,
             C.WEEKSTART_DATE, D.WEEKEND_DATE
     FROM    ( SELECT 	A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.SHOP_GROUP_ID, MAX(A.SCP_PLAN_ID) AS SCP_PLAN_ID
	           FROM 	FP_WEEKLY_DEMAND_PRODUCT_H A WITH(NOLOCK)
			   WHERE    A.SHOP_GROUP_ID = 'E'
               GROUP   BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.SHOP_GROUP_ID ) A,
             SCM_SYS_CALENDAR_M C WITH(NOLOCK),
             SCM_SYS_CALENDAR_M D WITH(NOLOCK)
     WHERE   C.DATE_ID = CONVERT(DATE,SUBSTRING(A.SCP_PLAN_ID, 0,9),112) 
     AND     D.DATE_ID = DATEADD( D, 28, CONVERT(DATE,SUBSTRING(A.SCP_PLAN_ID, 0,9) , 112)) -- 2019-07-17 kimcd 전극 5주. 2019-07-09 kimcd 전극 6주만 취합하기 위해 END WEEK 로직 분리
	 UNION ALL -- 2019-07-17 kimcd 소형 6주 추가
	 SELECT  A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.SHOP_GROUP_ID, A.SCP_PLAN_ID, C.WEEK AS TARGET_WEEK, SUBSTRING(A.SCP_PLAN_ID, 0,9) AS PLAN_START_DATE, D.WEEK AS END_WEEK,
             C.WEEKSTART_DATE, D.WEEKEND_DATE
     FROM    ( SELECT 	A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.SHOP_GROUP_ID, MAX(A.SCP_PLAN_ID) AS SCP_PLAN_ID
	           FROM 	FP_WEEKLY_DEMAND_PRODUCT_H A WITH(NOLOCK)
			   WHERE    A.SHOP_GROUP_ID != 'E'
			   AND      A.DIVISION_ID    = '40'
               GROUP   BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.SHOP_GROUP_ID ) A,
             SCM_SYS_CALENDAR_M C WITH(NOLOCK),
             SCM_SYS_CALENDAR_M D WITH(NOLOCK)
     WHERE   C.DATE_ID = CONVERT(DATE,SUBSTRING(A.SCP_PLAN_ID, 0,9),112) 
     AND     D.DATE_ID = DATEADD( D, 35, CONVERT(DATE,SUBSTRING(A.SCP_PLAN_ID, 0,9) , 112)) -- 2019-07-17 kimcd 소형 6주. 2019-07-09 kimcd 전극 6주만 취합하기 위해 END WEEK 로직 분리
	 UNION ALL
	 SELECT  A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.SHOP_GROUP_ID, A.SCP_PLAN_ID, C.WEEK AS TARGET_WEEK, SUBSTRING(A.SCP_PLAN_ID, 0,9) AS PLAN_START_DATE, D.WEEK AS END_WEEK,
             C.WEEKSTART_DATE, D.WEEKEND_DATE
     FROM    ( SELECT 	A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.SHOP_GROUP_ID, MAX(A.SCP_PLAN_ID) AS SCP_PLAN_ID
	           FROM 	FP_WEEKLY_DEMAND_PRODUCT_H A WITH(NOLOCK)
			   WHERE    A.SHOP_GROUP_ID != 'E'
			   AND      A.DIVISION_ID   != '40' -- 2019-07-17 kimcd 소형 제외
               GROUP   BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.SHOP_GROUP_ID ) A,
             SCM_SYS_CALENDAR_M C WITH(NOLOCK),
             SCM_SYS_CALENDAR_M D WITH(NOLOCK)
     WHERE   C.DATE_ID = CONVERT(DATE,SUBSTRING(A.SCP_PLAN_ID, 0,9),112) 
     AND     D.DATE_ID = DATEADD( D, 49, CONVERT(DATE,SUBSTRING(A.SCP_PLAN_ID, 0,9) , 112))  )
	, RELEASE_PLAN_INFO
AS ( SELECT  A.INSTANCE_ID, B.PART_ID AS SHOP_GROUP_ID, A.INSTANCE_DATE, A.FACTORY_ID, A.PLAN_GROUP_ID, A.RELEASE_PLAN_ID, A.INSERT_TIME,
			 ROW_NUMBER() OVER (PARTITION BY A.INSTANCE_ID, B.PART_ID, A.FACTORY_ID, A.PLAN_GROUP_ID ORDER BY A.INSERT_TIME DESC) AS ROW_NUM
	 FROM 	FP_RELEASE_PLAN_INFO_H A WITH(NOLOCK),
			FP_INSTANCE_CONFIG_M   B WITH(NOLOCK)
	 WHERE 	A.INSTANCE_ID = B.INSTANCE_ID
	 AND 	B.CATEGORY_ID = 'DEMAND_TARGET'
	 AND 	B.INSTANCE_ID NOT LIKE '%FORM%'
	 AND 	B.INSTANCE_ID NOT LIKE '%PMIX%'
	 AND 	B.USE_YN = 'Y'
	 AND 	B.VIEW_FLAG = 'Y'
	 )
	, RELEASE_PLAN
AS 	( SELECT A.INSTANCE_ID, A.SHOP_GROUP_ID, A.INSTANCE_DATE, A.FACTORY_ID, A.PLAN_GROUP_ID, A.RELEASE_PLAN_ID
      FROM   RELEASE_PLAN_INFO A
      WHERE  ROW_NUM = 1)
SELECT 	A.TARGET_WEEK, A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.SHOP_GROUP_ID, A.ITEM_ID, ISNULL(A.OPERATION_ID, SUBSTRING(B.FLOW_ID,1,5)) AS OPERATION_ID, MAX(B.NICK_NAME) AS NICK_NAME, A.MFG_WEEK, 
		SUM(A.TARGET_QTY) AS TARGET_QTY,
		SUM(A.PLAN_QTY) AS PLAN_QTY,
		SUM(A.ACTUAL_GOOD_QTY) AS ACTUAL_GOOD_QTY		
FROM 	(	
		SELECT 	B.TARGET_WEEK, B.COMPANY_ID, B.DIVISION_ID, B.SITE_ID, B.PLANT_ID, B.SHOP_GROUP_ID, A.ITEM_ID, A.OPERATION_ID, A.MFG_WEEK, 
				A.MFG_QTY AS TARGET_QTY, 
				0 AS PLAN_QTY, 
				0 AS ACTUAL_GOOD_QTY			
		FROM 	FP_WEEKLY_DEMAND_PRODUCT_H A WITH(NOLOCK),
				SCP_PLAN B
		WHERE 	A.COMPANY_ID  = B.COMPANY_ID
		AND 	A.DIVISION_ID = B.DIVISION_ID
		AND 	A.SITE_ID     = B.SITE_ID
		AND 	A.SCP_PLAN_ID = B.SCP_PLAN_ID
		AND 	A.SHOP_GROUP_ID = B.SHOP_GROUP_ID
		AND     A.PLANT_ID    = B.PLANT_ID
		AND 	A.MFG_WEEK   <= B.END_WEEK
		AND 	A.MFG_QTY     > 0
		UNION ALL
		SELECT 	B.TARGET_WEEK, B.COMPANY_ID, B.DIVISION_ID, B.SITE_ID, B.PLANT_ID, B.SHOP_GROUP_ID, A.ITEM_ID, A.OPERATION_ID, D.WEEK AS MFG_WEEK, 
				0 AS TARGET_QTY, 
				A.PLAN_QTY AS PLAN_QTY, 
				0 AS ACTUAL_GOOD_QTY
		FROM 	FP_RELEASE_FULL_PLAN_H A WITH(NOLOCK),
		        SCM_SYS_CALENDAR_M     D WITH(NOLOCK),
				SCM_FACTORY_M          F WITH(NOLOCK),
				RELEASE_PLAN           C,
				SCP_PLAN               B
		WHERE 	1=1
		AND 	A.RELEASE_PLAN_ID = C.RELEASE_PLAN_ID
		AND     A.FACTORY_ID      = F.FACTORY_ID
		AND     F.COMPANY_ID      = B.COMPANY_ID
		AND     F.DIVISION_ID     = B.DIVISION_ID
		AND     F.SITE_ID         = B.SITE_ID
		AND     F.PLANT_ID        = B.PLANT_ID
		AND     C.SHOP_GROUP_ID   = B.SHOP_GROUP_ID
		-- 하드코딩 전환 'E2000','A9000','A3000','P5200','P5500','P9500'
		AND 	A.OPERATION_ID   IN (SELECT SEGMENT2 FROM SCM_CODE_LOOKUP_VALUE WITH(NOLOCK) WHERE LOOKUP_TYPE_CODE='FP_KPI_SATISFACTION_V' AND SEGMENT1  = '0' AND ACTIVE_FLAG='Y'	) -- 2021-11-03 kimcd P5200 공정 포함
	
		AND 	A.PLAN_DATE       = D.DATE_ID
		AND 	A.PLAN_DATE      >= B.WEEKSTART_DATE
		AND     A.PLAN_DATE      <= B.WEEKEND_DATE
		AND 	A.PLAN_QTY        > 0
		UNION ALL
		SELECT 	B.TARGET_WEEK, B.COMPANY_ID, B.DIVISION_ID, B.SITE_ID, B.PLANT_ID, B.SHOP_GROUP_ID, A.ITEM_ID, A.OPERATION_ID, X.WEEK AS MFG_WEEK, 
				0 AS TARGET_QTY, 
				0 AS PLAN_QTY, 
				A.ACTUAL_GOOD_QTY AS ACTUAL_GOOD_QTY			
		FROM 	SCM_DAILY_PRODUCT_RESULT_H A WITH(NOLOCK, INDEX(IX02_SCM_DAILY_PRODUCT_RESULT_H)),
				SCM_SYS_CALENDAR_M         X WITH(NOLOCK),
				RELEASE_PLAN               C,
				SCP_PLAN                   B,
				FP_INSTANCE_LINE_V         D
		WHERE 	1=1
		AND     A.COMPANY_ID    = B.COMPANY_ID
		AND     A.DIVISION_ID   = B.DIVISION_ID
		AND     A.SITE_ID       = B.SITE_ID
		AND     A.PLANT_ID      = B.PLANT_ID
		AND     C.SHOP_GROUP_ID = B.SHOP_GROUP_ID
		AND 	A.SITE_ID       = D.SITE_ID
		AND 	A.DIVISION_ID   = D.DIVISION_ID
		AND 	A.PLAN_DATE     = X.DATE_ID
		-- 하드코딩 전환 'E2000','A9000','A3000','P5200','P5500','P9500'
		AND 	A.OPERATION_ID   IN (SELECT SEGMENT2 FROM SCM_CODE_LOOKUP_VALUE WITH(NOLOCK) WHERE LOOKUP_TYPE_CODE='FP_KPI_SATISFACTION_V' AND SEGMENT1  = '0' AND ACTIVE_FLAG='Y'	) -- 2021-11-03 kimcd P5200 공정 포함
		AND 	A.OPERATION_ID  = D.OPERATION_ID
		AND 	A.PLAN_DATE     < C.INSTANCE_DATE
		AND     A.PLAN_DATE    >= B.WEEKSTART_DATE
		AND     A.PLAN_DATE    <= B.WEEKEND_DATE
		AND     C.INSTANCE_ID   = D.INSTANCE_ID
		AND 	D.FACTORY_ID    = CASE WHEN C.PLAN_GROUP_ID = '-' THEN C.FACTORY_ID ELSE D.FACTORY_ID END
		AND 	D.MODEL_TYPE    = CASE WHEN C.PLAN_GROUP_ID = '-' THEN D.MODEL_TYPE ELSE C.PLAN_GROUP_ID END
		AND 	A.LINE_ID       = D.LINE_ID
		AND 	A.ACTUAL_GOOD_QTY > 0
		AND     A.PRODUCTION_TYPE != 'REWORK'
		) A,
		SCM_ITEM_M B WITH(NOLOCK)
WHERE 	1=1
AND     A.COMPANY_ID  = B.COMPANY_ID
AND 	A.SITE_ID     = B.SITE_ID
AND 	A.DIVISION_ID = B.DIVISION_ID
AND 	A.ITEM_ID     = B.ITEM_ID
AND 	B.ACTIVE_FLAG = 'Y'
GROUP BY A.TARGET_WEEK, A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.SHOP_GROUP_ID, A.ITEM_ID, ISNULL(A.OPERATION_ID, SUBSTRING(B.FLOW_ID,1,5)), A.MFG_WEEK




