CREATE VIEW [dbo].[FP_INSTANCE_INFO_V]
AS
SELECT 	DISTINCT A.SEGMENT1 AS INSTANCE_ID, B.SEGMENT2 AS INSTANCE_NAME, B.ATTRIBUTE1 AS CONFIRM_AREA, CASE WHEN B.ATTRIBUTE9 = 'E1' THEN 'E' ELSE B.ATTRIBUTE9 END AS INSTANCE_TYPE, 
		A.SEGMENT2 AS COMPANY_ID, A.SEGMENT3 AS DIVISION_ID, A.SEGMENT4 AS SITE_ID, A.SEGMENT5 AS PLANT_ID, 
--		ISNULL(C.SEGMENT2,'-') AS PLANNING_GROUP, 
		CASE WHEN B.ATTRIBUTE1 = 'BUILDING' THEN E.FACTORY_ID ELSE ISNULL(C.SEGMENT2,'-') END AS RELEASE_GROUP,
		ISNULL(D.SEGMENT3,'-') AS SCP_LINE_ID
FROM 	SCM_SYS_LOOKUP_VALUE A,
		SCM_SYS_LOOKUP_VALUE B
		LEFT OUTER JOIN SCM_SYS_LOOKUP_VALUE C
		ON 	1=1
		AND C.LOOKUP_TYPE_CODE = 'INSTANCE_PLANNING_GROUP'
		AND B.SEGMENT1 = C.SEGMENT1
		AND C.ACTIVE_FLAG = 'Y'
		LEFT OUTER JOIN (SELECT 	B.SITE_ID, B.DIVISION_ID, B.PLANT_ID, A.*
						 FROM 	FP_INSTANCE_FACTORY_M A,
								SCM_FACTORY_M B
						 WHERE 	1=1
						 AND 	A.FACTORY_ID = B.FACTORY_ID
						 AND 	B.ACTIVE_FLAG = 'Y') E
		ON 	1=1
		AND B.SEGMENT1 = E.INSTANCE_ID
		AND E.ACTIVE_FLAG = 'Y'
		LEFT OUTER JOIN SCM_SYS_LOOKUP_VALUE D
		ON 	1=1
		AND D.LOOKUP_TYPE_CODE = 'INSTANCE_SPLIT_LINE_DEFINITION'
		AND B.SEGMENT1 = D.SEGMENT1
		AND D.ACTIVE_FLAG = 'Y'
		AND E.FACTORY_ID = LEFT(D.SEGMENT3,2)
WHERE 	1=1
AND 	A.LOOKUP_TYPE_CODE = 'INSTANCE_INFO'
AND 	B.LOOKUP_TYPE_CODE = 'INSTANCE_ID'
AND 	A.SEGMENT1 = B.SEGMENT1		
AND 	A.ACTIVE_FLAG = 'Y'
AND 	B.ACTIVE_FLAG = 'Y'
AND 	A.SEGMENT5 = E.PLANT_ID
