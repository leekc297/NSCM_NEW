CREATE VIEW [dbo].[SCM_OPERATION_MOVE_V]
AS
SELECT A.[COMPANY_ID]
   , A.[DIVISION_ID]
   , A.[SITE_ID]
   , A.[PLANT_ID]
   , A.[FACTORY_ID]
   , A.[OPERATION_ID]
   , B.[OPERATION_LOT_SIZE]
   , B.[MIN_LOT_SIZE]
   , B.[LOT_SIZE_UOM]
   , B.[PRECEDE_PRODUCING_TERM]
   , B.[PRECEDE_PRODUCING_TERM_UOM]
   , B.[BUFFER_TIME]
   , B.[BUFFER_TIME_UOM]
   , B.[INITIAL_PRODUCING_LEAD_TIME]
   , B.[INITIAL_PRODUCING_LEAD_TIME_UOM]
   , B.[TAT]
   , B.[TAT_UOM]
   , B.[TRANSFER_LOT_SIZE]
   , B.[TRANSFER_LOT_SIZE_UOM]
   , B.[ACTIVE_FLAG]
   , B.[DESCRIPTION]
   , B.[INSERT_ID]
   , B.[INSERT_TIME]
   , B.[UPDATE_ID]
   , B.[UPDATE_TIME]
FROM ( SELECT OP.COMPANY_ID, OP.DIVISION_ID, OP.SITE_ID, L.PLANT_ID, L.FACTORY_ID, OP.OPERATION_ID
       FROM   SCM_OPERATION_M  OP(NOLOCK)
       ,SCM_LINE_M       L(NOLOCK)
       WHERE  OP.COMPANY_ID = L.COMPANY_ID
       AND    OP.DIVISION_ID = L.DIVISION_ID
       AND    OP.SITE_ID = L.SITE_ID
       AND    OP.OPERATION_ID = L.OPERATION_ID
       AND 	  L.ACTIVE_FLAG = 'Y'
     GROUP BY  OP.COMPANY_ID, OP.DIVISION_ID, OP.SITE_ID, L.PLANT_ID, L.FACTORY_ID, OP.OPERATION_ID )  A
     LEFT OUTER JOIN SCM_OPERATION_MOVE_M B(NOLOCK)
            ON  A.COMPANY_ID = B.COMPANY_ID
            AND A.DIVISION_ID = B.DIVISION_ID
            AND A.SITE_ID = B.SITE_ID
            AND A.PLANT_ID = B.PLANT_ID
            AND A.FACTORY_ID = B.FACTORY_ID
            AND A.OPERATION_ID = B.OPERATION_ID
