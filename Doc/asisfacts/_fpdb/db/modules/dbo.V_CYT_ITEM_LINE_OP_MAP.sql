CREATE VIEW [dbo].[V_CYT_ITEM_LINE_OP_MAP] AS 
 SELECT A.DIVISION_ID, A.plant_id, A.FACTORY_ID, A.ITEM_ID
      ,MAX( CASE A.OPERATION_SEQ WHEN 1 THEN OP.OPERATION_NAME ELSE NULL END ) STEP1
    ,MAX( CASE A.OPERATION_SEQ WHEN 1 THEN l.LINE_ID   ELSE NULL END ) STEP1_LINE
    ,MAX( CASE A.OPERATION_SEQ WHEN 1 THEN l.ELECTRODE_TYPE   ELSE NULL END ) STEP1_LINE_EC_TYPE
    ,MAX( CASE A.OPERATION_SEQ WHEN 1 THEN X.TACT_TIME   ELSE NULL END ) STEP1_TT
    ,MAX( CASE A.OPERATION_SEQ WHEN 1 THEN A.TAT   ELSE NULL END ) STEP1_TAT
    ,MAX( CASE A.OPERATION_SEQ WHEN 2 THEN OP.OPERATION_NAME ELSE NULL END ) STEP2
    ,MAX( CASE A.OPERATION_SEQ WHEN 2 THEN l.LINE_ID   ELSE NULL END ) STEP2_LINE
    ,MAX( CASE A.OPERATION_SEQ WHEN 2 THEN l.ELECTRODE_TYPE   ELSE NULL END ) STEP2_LINE_EC_TYPE
    ,MAX( CASE A.OPERATION_SEQ WHEN 2 THEN X.TACT_TIME   ELSE NULL END ) STEP2_TT
    ,MAX( CASE A.OPERATION_SEQ WHEN 2 THEN A.TAT   ELSE NULL END ) STEP2_TAT
    ,MAX( CASE A.OPERATION_SEQ WHEN 3 THEN OP.OPERATION_NAME ELSE NULL END ) STEP3
    ,MAX( CASE A.OPERATION_SEQ WHEN 3 THEN l.LINE_ID   ELSE NULL END ) STEP3_LINE
    ,MAX( CASE A.OPERATION_SEQ WHEN 3 THEN l.ELECTRODE_TYPE   ELSE NULL END ) STEP3_LINE_EC_TYPE
    ,MAX( CASE A.OPERATION_SEQ WHEN 3 THEN X.TACT_TIME   ELSE NULL END ) STEP3_TT
    ,MAX( CASE A.OPERATION_SEQ WHEN 3 THEN A.TAT   ELSE NULL END ) STEP3_TAT
    ,MAX( CASE A.OPERATION_SEQ WHEN 4 THEN OP.OPERATION_NAME ELSE NULL END ) STEP4
    ,MAX( CASE A.OPERATION_SEQ WHEN 4 THEN l.LINE_ID   ELSE NULL END ) STEP4_LINE
    ,MAX( CASE A.OPERATION_SEQ WHEN 4 THEN l.ELECTRODE_TYPE   ELSE NULL END ) STEP4_LINE_EC_TYPE
    ,MAX( CASE A.OPERATION_SEQ WHEN 4 THEN X.TACT_TIME   ELSE NULL END ) STEP4_TT
    ,MAX( CASE A.OPERATION_SEQ WHEN 4 THEN A.TAT   ELSE NULL END ) STEP4_TAT
    ,MAX( CASE A.OPERATION_SEQ WHEN 5 THEN OP.OPERATION_NAME ELSE NULL END ) STEP5
    ,MAX( CASE A.OPERATION_SEQ WHEN 5 THEN l.LINE_ID   ELSE NULL END ) STEP5_LINE
    ,MAX( CASE A.OPERATION_SEQ WHEN 5 THEN l.ELECTRODE_TYPE   ELSE NULL END ) STEP5_LINE_EC_TYPE
    ,MAX( CASE A.OPERATION_SEQ WHEN 5 THEN X.TACT_TIME   ELSE NULL END ) STEP5_TT
    ,MAX( CASE A.OPERATION_SEQ WHEN 5 THEN A.TAT   ELSE NULL END ) STEP5_TAT
  FROM [LGCE_FPDEV_TR].[DBO].[SCM_ITEM_FLOW_V] A
    INNER JOIN [LGCE_FPDEV_TR].DBO.SCM_OPERATION_M OP
      ON A.PLANT_ID = A.PLANT_ID --'A011'
       AND A.DIVISION_ID = OP.DIVISION_ID
       AND A.OPERATION_ID = OP.OPERATION_ID
   LEFT OUTER JOIN [DBO].[SCM_TACT_TIME_M] X
            ON X.MONTH        = convert(varchar(6),getdate(),112)
       AND X.ITEM_ID      = A.ITEM_ID 
       AND X.OPERATION_ID = A.OPERATION_ID
       AND X.FACTORY_ID   = A.FACTORY_ID
   LEFT OUTER JOIN [DBO].SCM_ITEM_LINE_ASSIGN_M l
            ON l.MONTH        = convert(varchar(6),getdate(),112)
       AND A.ITEM_ID      = l.ITEM_ID 
       AND A.OPERATION_ID = l.OPERATION_ID
       AND A.FACTORY_ID   = l.FACTORY_ID
GROUP BY A.DIVISION_ID, A.PLANT_ID, A.FACTORY_ID, A.ITEM_ID

