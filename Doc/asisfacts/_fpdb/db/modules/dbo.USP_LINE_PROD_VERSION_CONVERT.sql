       ,E.TABLE_NAME
       ,E.OP_TYPE
       ,E.EXPECTED_CNT
       ,A.ACTUAL_CNT
       ,CASE WHEN @P_DRY_RUN = 1 THEN N'DRY RUN (미실행)'
