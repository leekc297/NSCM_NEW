                        ,A.SLURRY_ITEM_ID, A.VERSION_ID, ISNULL(VERSION_SEQ,'00') AS VERSION_SEQ, A.PROD_VERSION_TYPE
                        ,ROW_NUMBER() OVER ( PARTITION BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID
                                                        , A.MODEL_ID, A.SLURRY_ITEM_ID
                                                        , CASE RIGHT(VERSION_ID,1) WHEN 'W' THEN 'W' WHEN 'P' THEN 'P' ELSE '-' END
                                                        , CASE WHEN LEFT(VERSION_ID,1) = 'Z' THEN 'T'
                                                               WHEN LEFT(VERSION_ID,1) = 'X' THEN 'X' ELSE 'M' END
                                             ORDER BY A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.MODEL_ID
                                                    , A.SLURRY_ITEM_ID, A.VERSION_ID DESC, ISNULL(VERSION_SEQ,'00') DESC ) AS ROW_NUM
                 FROM ( SELECT DISTINCT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.MODEL_ID
                              ,A.SLURRY_ITEM_ID, A.VERSION_ID, A.VERSION_SEQ, A.PROD_VERSION_TYPE, A.CHILD_CLASS_NAME
                       FROM SCM_SLURRY_SOLID_RATE A WITH(NOLOCK)
                       WHERE A.FACTORY_ID = @P_AREA_ID ) A ) A
           WHERE ROW_NUM = 1 ) A
    WHERE A.COMPANY_ID = B.COMPANY_ID AND A.DIVISION_ID = B.DIVISION_ID AND A.SITE_ID = B.SITE_ID
    AND   A.PLANT_ID = B.PLANT_ID AND A.FACTORY_ID = B.FACTORY_ID AND A.MODEL_ID = B.MODEL_ID
    AND   A.SLURRY_ITEM_ID = B.SLURRY_ITEM_ID AND A.VERSION_ID = B.VERSION_ID AND A.VERSION_SEQ = B.VERSION_SEQ;
    INSERT INTO #ACTUAL_LOG VALUES ('2-28b','SCM_SLURRY_SOLID_RATE','UPDATE(MAX_VER_FLAG=Y)', @@ROWCOUNT, @NOW);
