
CREATE   PROCEDURE dbo.USP_LINE_PROD_VERSION_CONVERT
(
    @P_SITE_ID                 VARCHAR(10),   -- SEGMENT1 / SITE_ID
    @P_DIVISION_ID              VARCHAR(10),   -- SEGMENT2 / DIVISION_ID
    @P_PLANT_ID                 VARCHAR(10),   -- SEGMENT3 / PLANT_ID
    @P_AREA_ID                  VARCHAR(10),   -- SEGMENT4 / FACTORY_ID
    @P_PLM_FACTORY               VARCHAR(20),  -- SEGMENT5(루트) / PLM_FACTORY
    @P_PROD_VERSION_TYPE_LABEL  VARCHAR(20),   -- ATTRIBUTE1(루트) / PROD_VERSION_TYPE 라벨
    @P_LINE_OPERATION_ID        VARCHAR(10) = 'E2000',
    @P_LINE_ID_PATTERN          VARCHAR(50) = NULL,
    @P_TX_OPERATION_IDS         VARCHAR(100) = 'E0500,E1000,E2000',
    @P_USER_ID                  VARCHAR(20)  = 'kimcd',
    @P_DRY_RUN                  BIT          = 1,
    @P_BACKUP_BATCH_TAG         VARCHAR(40)  = ''
)
AS
BEGIN
SET NOCOUNT ON;

DECLARE @P_RUN_TAG   VARCHAR(40) = @P_AREA_ID + '_' + REPLACE(CONVERT(VARCHAR(20), GETDATE(), 112),'/','')
                                    + REPLACE(CONVERT(VARCHAR(8), GETDATE(), 108), ':', '');
DECLARE @NOW         DATETIME    = GETDATE();
DECLARE @CHECK_CNT            NUMERIC(10);

IF OBJECT_ID('tempdb..#TX_OPS') IS NOT NULL DROP TABLE #TX_OPS;
SELECT LTRIM(RTRIM(token)) AS OPERATION_ID INTO #TX_OPS FROM STRING_SPLIT(@P_TX_OPERATION_IDS, ',');

IF OBJECT_ID('tempdb..#EXPECTED_LOG') IS NOT NULL DROP TABLE #EXPECTED_LOG;
CREATE TABLE #EXPECTED_LOG (STEP_NO VARCHAR(10), TABLE_NAME SYSNAME, OP_TYPE VARCHAR(30), EXPECTED_CNT INT, CHECK_TIME DATETIME);

IF OBJECT_ID('tempdb..#ACTUAL_LOG') IS NOT NULL DROP TABLE #ACTUAL_LOG;
CREATE TABLE #ACTUAL_LOG (STEP_NO VARCHAR(10), TABLE_NAME SYSNAME, OP_TYPE VARCHAR(30), ACTUAL_CNT INT, EXEC_TIME DATETIME);

PRINT N'=== PARAMETERS ===';
PRINT N'AREA_ID=' + @P_AREA_ID + ' / PLM_FACTORY=' + @P_PLM_FACTORY + ' / RUN_TAG=' + @P_RUN_TAG
      + ' / DRY_RUN=' + CAST(@P_DRY_RUN AS VARCHAR(1)) + ' / BACKUP_BATCH_TAG=' + @P_BACKUP_BATCH_TAG;


/* ============================================================================================
   0-1. SCM_SYS_LOOKUP_VALUE(LINE_PROD_VERSION_TYPE) 자동 구성 (SCM_LINE_M 기반, 수동 나열 없음)
   --------------------------------------------------------------------------------------------
   ※ 이 MERGE 는 @P_DRY_RUN 값과 무관하게 항상 실행됩니다(데이터 테이블이 아닌 참조/설정성
     lookup 값만 최신화하는 멱등적 작업이며, 아래 #LINE_VERSION_MAP/#PDS_VERSION_MAP 및 모든
     예상 건수 계산이 최신 lookup 값을 전제로 하기 때문입니다).
   ============================================================================================ */
INSERT INTO #EXPECTED_LOG (STEP_NO, TABLE_NAME, OP_TYPE, EXPECTED_CNT, CHECK_TIME)
SELECT '0-1', 'SCM_SYS_LOOKUP_VALUE', 'MERGE', COUNT(*) , @NOW    -- 수량에 +1 : 루트 행 더한 값 제거
FROM   SCM_LINE_M L
WHERE  L.PLANT_ID = @P_PLANT_ID AND L.FACTORY_ID = @P_AREA_ID AND L.OPERATION_ID = @P_LINE_OPERATION_ID
AND    L.ACTIVE_FLAG = 'Y' -- AND ( @P_LINE_ID_PATTERN IS NULL OR L.LINE_ID LIKE @P_LINE_ID_PATTERN )
AND    PATINDEX('%[0-9][0-9]_%', L.LINE_ID) > 0
AND    L.LINE_ID LIKE 'FP%'
AND    L.PROD_VERSION_TYPE = @P_PROD_VERSION_TYPE_LABEL;

MERGE INTO SCM_SYS_LOOKUP_VALUE LV
USING (
    /* 현재 존재하는 값은 변경 안 함
	SELECT  'LINE_PROD_VERSION_TYPE'    AS LOOKUP_TYPE_CODE
           ,@P_SITE_ID                 AS SEGMENT1
           ,@P_DIVISION_ID                 AS SEGMENT2
           ,@P_PLANT_ID                 AS SEGMENT3
           ,@P_AREA_ID                  AS SEGMENT4
           ,@P_PLM_FACTORY              AS SEGMENT5
           ,'Y'                         AS ACTIVE_FLAG
           ,@P_USER_ID                  AS CREATE_USER_ID
           ,@NOW                        AS CREATE_DATE
           ,@P_USER_ID                  AS MODIFY_USER_ID
           ,@NOW                        AS MODIFY_DATE
           ,@P_PROD_VERSION_TYPE_LABEL  AS ATTRIBUTE1
           ,CAST(NULL AS VARCHAR(20))   AS ATTRIBUTE2
           ,CAST(NULL AS VARCHAR(10))   AS ATTRIBUTE3
    UNION ALL*/
    SELECT  'LINE_PROD_VERSION_TYPE'  AS LOOKUP_TYPE_CODE, @P_SITE_ID AS SEGMENT1, @P_DIVISION_ID AS SEGMENT2, @P_PLANT_ID AS SEGMENT3, @P_AREA_ID AS SEGMENT4, L.LINE_ID AS SEGMENT5
           ,'Y' AS ACTIVE_FLAG, @P_USER_ID AS CREATE_USER_ID, @NOW AS CREATE_DATE, @P_USER_ID AS MODIFY_USER_ID, @NOW AS MODIFY_DATE
           ,L.LINE_ID AS ATTRIBUTE1, @P_PLM_FACTORY  AS ATTRIBUTE2
           ,'.' + CAST( CAST( SUBSTRING(L.LINE_ID, PATINDEX('%[0-9][0-9]_%', L.LINE_ID), 2) AS INT) AS VARCHAR(10))
                + RIGHT(L.LINE_ID, 1)  AS ATTRIBUTE3
    FROM   SCM_LINE_M L
    WHERE  L.PLANT_ID = @P_PLANT_ID AND L.FACTORY_ID = @P_AREA_ID AND L.OPERATION_ID = @P_LINE_OPERATION_ID
    AND    L.ACTIVE_FLAG = 'Y' --AND ( @P_LINE_ID_PATTERN IS NULL OR L.LINE_ID LIKE @P_LINE_ID_PATTERN )
    AND    PATINDEX('%[0-9][0-9]_%', L.LINE_ID) > 0
	AND    L.LINE_ID LIKE 'FP%'
    AND    L.PROD_VERSION_TYPE = @P_PROD_VERSION_TYPE_LABEL
) B
ON (    LV.[LOOKUP_TYPE_CODE] = B.[LOOKUP_TYPE_CODE]
    AND LV.[SEGMENT1] = B.[SEGMENT1] AND LV.[SEGMENT2] = B.[SEGMENT2] AND LV.[SEGMENT3] = B.[SEGMENT3]
    AND LV.[SEGMENT4] = B.[SEGMENT4] AND LV.[SEGMENT5] = B.[SEGMENT5] )
WHEN MATCHED THEN
    UPDATE SET LV.ACTIVE_FLAG = B.ACTIVE_FLAG, LV.MODIFY_USER_ID = B.MODIFY_USER_ID, LV.MODIFY_DATE = B.MODIFY_DATE
             , LV.ATTRIBUTE1 = B.ATTRIBUTE1, LV.ATTRIBUTE2 = B.ATTRIBUTE2, LV.ATTRIBUTE3 = B.ATTRIBUTE3
WHEN NOT MATCHED THEN
    INSERT ( LOOKUP_TYPE_CODE, SEGMENT1, SEGMENT2, SEGMENT3, SEGMENT4, SEGMENT5, ACTIVE_FLAG,
             CREATE_USER_ID, CREATE_DATE, MODIFY_USER_ID, MODIFY_DATE, ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3 )
    VALUES ( B.LOOKUP_TYPE_CODE, B.SEGMENT1, B.SEGMENT2, B.SEGMENT3, B.SEGMENT4, B.SEGMENT5, B.ACTIVE_FLAG,
             B.CREATE_USER_ID, B.CREATE_DATE, B.MODIFY_USER_ID, B.MODIFY_DATE, B.ATTRIBUTE1, B.ATTRIBUTE2, B.ATTRIBUTE3 );

INSERT INTO #ACTUAL_LOG VALUES ('0-1', 'SCM_SYS_LOOKUP_VALUE', 'MERGE', @@ROWCOUNT, @NOW);


/* ============================================================================================
   0-2. 공통 매핑 임시테이블 (한 번만 계산해서 이후 모든 단계에서 재사용)
   ============================================================================================ */
IF OBJECT_ID('tempdb..#LINE_VERSION_MAP') IS NOT NULL DROP TABLE #LINE_VERSION_MAP;
SELECT   SSLV.SEGMENT4 AS AREA_ID, SSLV.SEGMENT5 AS PLM_FACTORY, SSLV.ATTRIBUTE1 AS OLD_PROD_VERSION_TYPE
        ,SSLV2.SEGMENT5 AS LINE_ID, SSLV2.ATTRIBUTE1 AS NEW_PROD_VERSION_TYPE, SSLV2.ATTRIBUTE3 AS VERSION_SUFFIX
INTO     #LINE_VERSION_MAP
FROM     SCM_SYS_LOOKUP_VALUE SSLV
         LEFT OUTER JOIN SCM_SYS_LOOKUP_VALUE SSLV2
                ON SSLV2.LOOKUP_TYPE_CODE = 'LINE_PROD_VERSION_TYPE' AND SSLV2.SEGMENT4 = SSLV.SEGMENT4
               AND SSLV2.ATTRIBUTE2 = SSLV.SEGMENT5
WHERE    SSLV.LOOKUP_TYPE_CODE = 'LINE_PROD_VERSION_TYPE' AND SSLV.SEGMENT5 = @P_PLM_FACTORY;

-- ※ #PDS_VERSION_MAP 는 "2-4. SCM_ITEM_CONV_CALC_M 신규 행 INSERT" 결과를 전제로 하는 매핑이므로
--    여기서는 만들지 않고, 2-4-1 단계 직후("2-4-2")에서 만듭니다. (실행 순서 의존성 버그 방지)

SELECT @CHECK_CNT = COUNT(*) FROM #LINE_VERSION_MAP
PRINT N'STEP 0 완료: #LINE_VERSION_MAP ' + CAST((@CHECK_CNT) AS VARCHAR(10)) + N'건';

IF NOT EXISTS (SELECT 1 FROM #LINE_VERSION_MAP WHERE LINE_ID IS NOT NULL)
    PRINT N'경고: #LINE_VERSION_MAP 에 라인 정보가 없습니다. 파라미터를 다시 확인하세요.';


/* ============================================================================================
   1. (참고) 백업 여부 확인
   --------------------------------------------------------------------------------------------
   본 파일은 백업을 수행하지 않습니다. 01_BACKUP.sql 을 먼저 실행했는지 확인하세요.
   ============================================================================================ */
IF @P_BACKUP_BATCH_TAG = ''
    PRINT N'주의: @P_BACKUP_BATCH_TAG 가 비어 있습니다. 01_BACKUP.sql 을 먼저 실행했는지 확인하세요.';
ELSE IF OBJECT_ID('BAK_' + @P_BACKUP_BATCH_TAG + '_' + 'SCM_ITEM_CONV_CALC_M') IS NULL
    PRINT N'주의: BATCH_TAG(' + @P_BACKUP_BATCH_TAG + N') 로 생성된 백업 테이블을 찾을 수 없습니다. 01_BACKUP.sql 실행 여부를 확인하세요.';
ELSE
    PRINT N'백업 확인됨: BATCH_TAG = ' + @P_BACKUP_BATCH_TAG;


/* ============================================================================================
   2. CONVERT (본 전환)  — 모든 INSERT/UPDATE 문마다 [예상건수 계산 → (DRY_RUN=0 시) 실제 실행/@@ROWCOUNT 기록]
   ============================================================================================ */

-- 2-0. SCM_FACTORY_M.ELEC_VERSION_TYPE 초기화 --------------------------------------------------
INSERT INTO #EXPECTED_LOG
SELECT '2-0', 'SCM_FACTORY_M', 'UPDATE', COUNT(*), @NOW FROM SCM_FACTORY_M WHERE FACTORY_ID = @P_AREA_ID;

IF @P_DRY_RUN = 0
BEGIN
    UPDATE SCM_FACTORY_M SET ELEC_VERSION_TYPE = NULL WHERE FACTORY_ID = @P_AREA_ID;
    INSERT INTO #ACTUAL_LOG VALUES ('2-0','SCM_FACTORY_M','UPDATE', @@ROWCOUNT, @NOW);
END

-- 2-1. SCM_LINE_M.PROD_VERSION_TYPE 갱신 -------------------------------------------------------
INSERT INTO #EXPECTED_LOG
SELECT '2-1', 'SCM_LINE_M', 'MERGE', COUNT(*), @NOW
FROM   SCM_LINE_M LV
       JOIN #LINE_VERSION_MAP B ON LV.[FACTORY_ID] = B.AREA_ID AND LV.[LINE_ID] = B.LINE_ID
WHERE  LV.OPERATION_ID IN (SELECT OPERATION_ID FROM #TX_OPS UNION SELECT 'E0500');

IF @P_DRY_RUN = 0
BEGIN
    MERGE INTO SCM_LINE_M LV
    USING ( SELECT AREA_ID, LINE_ID, NEW_PROD_VERSION_TYPE, @P_USER_ID AS UPDATE_ID, @NOW AS UPDATE_TIME
            FROM #LINE_VERSION_MAP WHERE LINE_ID IS NOT NULL ) B
      ON ( LV.[FACTORY_ID] = B.AREA_ID AND LV.[LINE_ID] = B.LINE_ID AND LV.OPERATION_ID IN (SELECT OPERATION_ID FROM #TX_OPS UNION SELECT 'E0500') )
    WHEN MATCHED THEN
        UPDATE SET LV.PROD_VERSION_TYPE = B.NEW_PROD_VERSION_TYPE, LV.UPDATE_ID = B.UPDATE_ID, LV.UPDATE_TIME = B.UPDATE_TIME;
    INSERT INTO #ACTUAL_LOG VALUES ('2-1','SCM_LINE_M','MERGE', @@ROWCOUNT, @NOW);
END

-- 2-2. FP_PROD_VERSION_M (FROM = INSERT 대상과 동일 테이블) ------------------------------------
INSERT INTO #EXPECTED_LOG
SELECT '2-2', 'FP_PROD_VERSION_M', 'INSERT', COUNT(*), @NOW
FROM   FP_PROD_VERSION_M PV
       INNER JOIN #LINE_VERSION_MAP B ON PV.FACTORY_ID = B.AREA_ID AND PV.PROD_VERSION_TYPE = B.OLD_PROD_VERSION_TYPE
WHERE  NOT EXISTS ( SELECT 1 FROM FP_PROD_VERSION_M PVC
                    WHERE  PVC.[MODEL_ID] = PV.[MODEL_ID] AND PVC.[ITEM_ID] = PV.[ITEM_ID] AND PVC.[FACTORY_ID] = PV.[FACTORY_ID]
                    AND    PVC.[PROD_VERSION] = PV.[PROD_VERSION] + B.VERSION_SUFFIX AND PVC.[PROD_SEQ] = PV.[PROD_SEQ] );

IF @P_DRY_RUN = 0
BEGIN
    INSERT INTO FP_PROD_VERSION_M
    SELECT PV.[COMPANY_ID], PV.[DIVISION_ID], PV.[SITE_ID], PV.[PLANT_ID], PV.[FACTORY_ID], PV.[MODEL_ID], PV.[ITEM_ID]
          ,PV.[PROD_VERSION] + B.VERSION_SUFFIX, PV.[PROD_SEQ], PV.[APPLY_DATE], PV.[APPLY_END_DATE]
          ,PV.[INSERT_ID], PV.[INSERT_TIME], PV.[UPDATE_ID], @NOW, B.NEW_PROD_VERSION_TYPE, PV.[ORDER_TYPE]
    FROM   FP_PROD_VERSION_M PV
           INNER JOIN #LINE_VERSION_MAP B ON PV.FACTORY_ID = B.AREA_ID AND PV.PROD_VERSION_TYPE = B.OLD_PROD_VERSION_TYPE
    WHERE  NOT EXISTS ( SELECT 1 FROM FP_PROD_VERSION_M PVC
                        WHERE  PVC.[MODEL_ID] = PV.[MODEL_ID] AND PVC.[ITEM_ID] = PV.[ITEM_ID] AND PVC.[FACTORY_ID] = PV.[FACTORY_ID]
                        AND    PVC.[PROD_VERSION] = PV.[PROD_VERSION] + B.VERSION_SUFFIX AND PVC.[PROD_SEQ] = PV.[PROD_SEQ] );
    INSERT INTO #ACTUAL_LOG VALUES ('2-2','FP_PROD_VERSION_M','INSERT', @@ROWCOUNT, @NOW);
END

-- 2-3. FP_PDS_VERSION_M (FROM = INSERT 대상과 동일 테이블) -------------------------------------
INSERT INTO #EXPECTED_LOG
SELECT '2-3', 'FP_PDS_VERSION_M', 'INSERT', COUNT(*), @NOW
FROM   FP_PDS_VERSION_M PV
       INNER JOIN #LINE_VERSION_MAP B ON PV.FACTORY_ID = B.AREA_ID
WHERE  EXISTS ( SELECT 1 FROM SCM_ITEM_CONV_CALC_M CCM
                WHERE  CCM.FACTORY_ID = @P_AREA_ID AND CCM.CATEGORY = 'Lane Number'
                AND    CCM.[FACTORY_ID] = PV.[FACTORY_ID] AND CCM.[MODEL_ID] = PV.[MODEL_ID] AND CCM.[VERSION] = PV.[VERSION]
                AND    CCM.PDS_VERSION IS NULL
                AND    CCM.PROD_VERSION_TYPE IN (SELECT DISTINCT OLD_PROD_VERSION_TYPE FROM #LINE_VERSION_MAP) )
AND    NOT EXISTS ( SELECT 1 FROM FP_PDS_VERSION_M C
                    WHERE C.[FACTORY_ID] = PV.[FACTORY_ID] AND C.[MODEL_ID] = PV.[MODEL_ID] AND C.[VERSION] = PV.[VERSION] + B.VERSION_SUFFIX);

IF @P_DRY_RUN = 0
BEGIN
    INSERT INTO FP_PDS_VERSION_M
    SELECT PV.[COMPANY_ID], PV.[DIVISION_ID], PV.[SITE_ID], PV.[PLANT_ID], PV.[SHOP_GROUP_ID], PV.[FACTORY_ID]
          ,PV.[MODEL_ID], PV.[VERSION_TYPE], PV.[VERSION] + B.VERSION_SUFFIX, PV.[APPLY_DATE], @P_USER_ID, @NOW, @P_USER_ID, @NOW, PV.[VERSION]
    FROM   FP_PDS_VERSION_M PV
           INNER JOIN #LINE_VERSION_MAP B ON PV.FACTORY_ID = B.AREA_ID
    WHERE  EXISTS ( SELECT 1 FROM SCM_ITEM_CONV_CALC_M CCM
                    WHERE  CCM.FACTORY_ID = @P_AREA_ID AND CCM.CATEGORY = 'Lane Number'
                    AND    CCM.[FACTORY_ID] = PV.[FACTORY_ID] AND CCM.[MODEL_ID] = PV.[MODEL_ID] AND CCM.[VERSION] = PV.[VERSION]
                    AND    CCM.PDS_VERSION IS NULL
                    AND    CCM.PROD_VERSION_TYPE IN (SELECT DISTINCT OLD_PROD_VERSION_TYPE FROM #LINE_VERSION_MAP) )
	AND    NOT EXISTS ( SELECT 1 FROM FP_PDS_VERSION_M C
						WHERE C.[FACTORY_ID] = PV.[FACTORY_ID] AND C.[MODEL_ID] = PV.[MODEL_ID] AND C.[VERSION] = PV.[VERSION] + B.VERSION_SUFFIX);

    INSERT INTO #ACTUAL_LOG VALUES ('2-3','FP_PDS_VERSION_M','INSERT', @@ROWCOUNT, @NOW);
END

-- 2-4. SCM_ITEM_CONV_CALC_M (FROM = INSERT 대상과 동일 테이블) ---------------------------------
INSERT INTO #EXPECTED_LOG
SELECT '2-4', 'SCM_ITEM_CONV_CALC_M', 'INSERT', COUNT(*), @NOW
FROM   SCM_ITEM_CONV_CALC_M PV
       INNER JOIN #LINE_VERSION_MAP B ON PV.FACTORY_ID = B.AREA_ID AND PV.PROD_VERSION_TYPE = B.OLD_PROD_VERSION_TYPE
WHERE  NOT EXISTS ( SELECT 1 FROM SCM_ITEM_CONV_CALC_M PVC
                    WHERE  PVC.[COMPANY_ID] = PV.[COMPANY_ID] AND PVC.[FACTORY_ID] = PV.[FACTORY_ID] AND PVC.[MODEL_ID] = PV.[MODEL_ID]
                    AND    PVC.[VERSION] = PV.[VERSION] + B.VERSION_SUFFIX AND PVC.[OPERATION] = PV.[OPERATION]
                    AND    PVC.[ITEM_ID] = PV.[ITEM_ID] AND PVC.[CATEGORY] = PV.[CATEGORY] );

IF @P_DRY_RUN = 0
BEGIN
    INSERT INTO SCM_ITEM_CONV_CALC_M
    SELECT PV.[COMPANY_ID], PV.[DIVISION_ID], PV.[SITE_ID], PV.[PLANT_ID], PV.[FACTORY_ID], PV.[MODEL_ID], PV.[PJT_CODE]
          ,PV.[VERSION] + B.VERSION_SUFFIX, PV.[OPERATION], PV.[ITEM_ID], PV.[ELECTRODE_TYPE], PV.[CATEGORY], PV.[VALUE]
          ,PV.[MAX_VER_FLAG], PV.[MARK], @P_USER_ID, @NOW, PV.UPDATE_ID, @NOW, PV.[MMD_VALUE]
          ,B.NEW_PROD_VERSION_TYPE, PV.[VERSION_TYPE], PV.[PROD_SEQ], PV.[APPLY_DATE], PV.[VERSION]
          ,CASE WHEN ( SELECT TOP 1 'PDS'
		               FROM   SCM_ITEM_CONV_CALC_M PVX
					   WHERE  PVX.[COMPANY_ID] = PV.[COMPANY_ID] AND PVX.[FACTORY_ID] = PV.[FACTORY_ID] AND PVX.[MODEL_ID] = PV.[MODEL_ID] AND    PVX.[VERSION] = PV.[VERSION] 
					   AND 	  PVX.UPDATE_ID LIKE '%PDS%' ) = 'PDS' THEN 'PDS' ELSE 'PLM' END
    FROM   SCM_ITEM_CONV_CALC_M PV
           INNER JOIN #LINE_VERSION_MAP B ON PV.FACTORY_ID = B.AREA_ID AND PV.PROD_VERSION_TYPE = B.OLD_PROD_VERSION_TYPE
    WHERE  NOT EXISTS ( SELECT 1 FROM SCM_ITEM_CONV_CALC_M PVC
                        WHERE  PVC.[COMPANY_ID] = PV.[COMPANY_ID] AND PVC.[FACTORY_ID] = PV.[FACTORY_ID] AND PVC.[MODEL_ID] = PV.[MODEL_ID]
                        AND    PVC.[VERSION] = PV.[VERSION] + B.VERSION_SUFFIX AND PVC.[OPERATION] = PV.[OPERATION]
                        AND    PVC.[ITEM_ID] = PV.[ITEM_ID] AND PVC.[CATEGORY] = PV.[CATEGORY] );
    INSERT INTO #ACTUAL_LOG VALUES ('2-4','SCM_ITEM_CONV_CALC_M','INSERT', @@ROWCOUNT, @NOW);
END

-- 2-4-1. FP_PDS_VERSION_M 보강 추가 (FROM = SCM_ITEM_CONV_CALC_M, INSERT 대상과 다른 테이블) ----
INSERT INTO #EXPECTED_LOG
SELECT '2-4-1', 'FP_PDS_VERSION_M', 'INSERT', COUNT(*), @NOW
FROM ( SELECT DISTINCT PV.[COMPANY_ID], PV.[DIVISION_ID], PV.[SITE_ID], PV.[PLANT_ID], PV.[FACTORY_ID], PV.[MODEL_ID]
              ,PV.[VERSION_TYPE], PV.[VERSION], PV.[PDS_VERSION]
       FROM   SCM_ITEM_CONV_CALC_M PV
       WHERE  PV.FACTORY_ID = @P_AREA_ID AND PV.CATEGORY = 'Lane Number'
       AND    NOT EXISTS ( SELECT 1 FROM FP_PDS_VERSION_M C
                           WHERE C.[FACTORY_ID] = PV.[FACTORY_ID] AND C.[MODEL_ID] = PV.[MODEL_ID] AND C.[VERSION] = PV.[VERSION])
       AND    PV.PROD_VERSION_TYPE IN (SELECT DISTINCT NEW_PROD_VERSION_TYPE FROM #LINE_VERSION_MAP) ) X;

IF @P_DRY_RUN = 0
BEGIN
    INSERT INTO FP_PDS_VERSION_M
    SELECT DISTINCT PV.[COMPANY_ID], PV.[DIVISION_ID], PV.[SITE_ID], PV.[PLANT_ID], 'E', PV.[FACTORY_ID], PV.[MODEL_ID]
          ,PV.[VERSION_TYPE], PV.[VERSION]
          ,REPLACE(REPLACE(REPLACE(CONVERT(NVARCHAR(50), MIN(PV.[APPLY_DATE]), 120),'-',''),' ',''),':','')
          ,@P_USER_ID, @NOW, @P_USER_ID, @NOW, PV.[PDS_VERSION]
    FROM   SCM_ITEM_CONV_CALC_M PV
    WHERE  PV.FACTORY_ID = @P_AREA_ID AND PV.CATEGORY = 'Lane Number'
    AND    NOT EXISTS ( SELECT 1 FROM FP_PDS_VERSION_M C
                        WHERE C.[FACTORY_ID] = PV.[FACTORY_ID] AND C.[MODEL_ID] = PV.[MODEL_ID] AND C.[VERSION] = PV.[VERSION])
    AND    PV.PROD_VERSION_TYPE IN (SELECT DISTINCT NEW_PROD_VERSION_TYPE FROM #LINE_VERSION_MAP)
    GROUP BY PV.[COMPANY_ID], PV.[DIVISION_ID], PV.[SITE_ID], PV.[PLANT_ID], PV.[FACTORY_ID], PV.[MODEL_ID]
            ,PV.[VERSION_TYPE], PV.[VERSION], PV.[PDS_VERSION];
    INSERT INTO #ACTUAL_LOG VALUES ('2-4-1','FP_PDS_VERSION_M','INSERT', @@ROWCOUNT, @NOW);
END

-- 2-4-2. #PDS_VERSION_MAP 생성 (2-4 의 SCM_ITEM_CONV_CALC_M 신규 행 기준 매핑) -------------------
--         실제 반영(@P_DRY_RUN=0) 후에는 방금 INSERT 된 신규 행을 그대로 사용하고,
--         DRY RUN(@P_DRY_RUN=1) 이라 아직 INSERT 되지 않았다면 "2-4 에서 INSERT 될 예정인 행"을
--         동일한 규칙으로 시뮬레이션하여 UNION 합니다. 이렇게 하면 실행 순서와 무관하게
--         이후 트랜잭션성 테이블(2-12~2-26)의 예상 건수를 항상 정확히 계산할 수 있습니다.
IF OBJECT_ID('tempdb..#PDS_VERSION_MAP') IS NOT NULL DROP TABLE #PDS_VERSION_MAP;
SELECT DISTINCT FACTORY_ID, LINE_ID, MODEL_ID, ITEM_ID, VERSION, PDS_VERSION
INTO   #PDS_VERSION_MAP
FROM (
    -- (a) 이미 SCM_ITEM_CONV_CALC_M 에 실제로 존재하는 신규(라인별) 행
    SELECT PV.FACTORY_ID, PV.PROD_VERSION_TYPE AS LINE_ID, PV.MODEL_ID, PV.ITEM_ID, PV.VERSION, PV.PDS_VERSION
    FROM   SCM_ITEM_CONV_CALC_M PV
           INNER JOIN #LINE_VERSION_MAP B
               ON PV.FACTORY_ID = B.AREA_ID AND PV.PROD_VERSION_TYPE = B.LINE_ID AND PV.VERSION LIKE '%' + B.VERSION_SUFFIX
    WHERE  PV.CATEGORY = 'Lane Number'
    UNION
    -- (b) 2-4 에서 신규 INSERT 될 것으로 예상되는 행을 동일 규칙으로 시뮬레이션(DRY RUN 대비)
    SELECT PV.FACTORY_ID, B.NEW_PROD_VERSION_TYPE AS LINE_ID, PV.MODEL_ID, PV.ITEM_ID
          ,PV.VERSION + B.VERSION_SUFFIX AS VERSION, PV.VERSION AS PDS_VERSION
    FROM   SCM_ITEM_CONV_CALC_M PV
