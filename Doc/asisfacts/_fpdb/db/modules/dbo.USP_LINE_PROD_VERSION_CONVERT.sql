             WHEN E.EXPECTED_CNT = A.ACTUAL_CNT THEN N'일치'
             ELSE N'불일치(확인 필요)' END AS RESULT
INTO    #VALIDATE_RESULT
FROM    #EXPECTED_LOG E
        LEFT OUTER JOIN #ACTUAL_LOG A ON E.STEP_NO = A.STEP_NO AND E.TABLE_NAME = A.TABLE_NAME AND E.OP_TYPE = A.OP_TYPE;

