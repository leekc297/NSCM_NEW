BEGIN
	-- SET NOCOUNT ON added to prevent extra result sets from
	-- interfering with SELECT statements.
	SET NOCOUNT ON;

	-- SET NOCOUNT ON added to prevent extra result sets from
	-- interfering with SELECT statements.
	SET NOCOUNT ON;

	DECLARE @MANUAL_LOOKUP_PROCESS NVARCHAR(MAX) = ''

	drop table #TMP_SCM_SYS_LOOKUP_VALUE 
	DROP TABLE #TMP_KEY_NAME_TO_FIND
	DROP TABLE #SEG_LIST


	CREATE TABLE #TMP_KEY_NAME_TO_FIND (
	KEY_NAME_A [nvarchar] (40) NOT NULL,
	KEY_TYPE_A [nvarchar] (40) NOT NULL
	)
	CREATE TABLE #SEG_LIST (
	KEY_NAME_A [nvarchar] (40) NOT NULL,
	KEY_NAME_IDX [nvarchar] (40) NOT NULL
	)

	Insert into #TMP_KEY_NAME_TO_FIND (KEY_NAME_A,KEY_TYPE_A) VALUES ('COMPANY','company_id')
	Insert into #TMP_KEY_NAME_TO_FIND (KEY_NAME_A,KEY_TYPE_A) VALUES ('PLANT','plant_id')
