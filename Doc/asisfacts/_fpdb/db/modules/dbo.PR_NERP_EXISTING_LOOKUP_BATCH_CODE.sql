	CREATE TABLE #TMP_SCM_SYS_LOOKUP_VALUE (
	[LOOKUP_TYPE_CODE] [nvarchar](100) NOT NULL,
	[SEGMENT1] [nvarchar](40) NOT NULL,
	[SEGMENT2] [nvarchar](40) NOT NULL,
	[SEGMENT3] [nvarchar](40) NOT NULL,
	[SEGMENT4] [nvarchar](40) NOT NULL,
	[SEGMENT5] [nvarchar](40) NOT NULL,
	[SORT_ORDER] [numeric](10, 0) NULL,
	[ACTIVE_FLAG] [nvarchar](1) NULL,
	[VALUE_DESCRIPTION] [nvarchar](400) NULL,
	[CREATE_USER_ID] [nvarchar](50) NULL,
	[CREATE_DATE] [datetime] NULL,
	[MODIFY_USER_ID] [nvarchar](50) NULL,
	[MODIFY_DATE] [datetime] NULL,
	[ATTRIBUTE1] [nvarchar](200) NULL,
	[ATTRIBUTE2] [nvarchar](200) NULL,
	[ATTRIBUTE3] [nvarchar](200) NULL,
	[ATTRIBUTE4] [nvarchar](200) NULL,
	[ATTRIBUTE5] [nvarchar](200) NULL,
	[ATTRIBUTE6] [nvarchar](200) NULL,
	[ATTRIBUTE7] [nvarchar](200) NULL,
	[ATTRIBUTE8] [nvarchar](200) NULL,
	[ATTRIBUTE9] [nvarchar](200) NULL,
	[ATTRIBUTE10] [nvarchar](200) NULL,
	[ATTRIBUTE11] [nvarchar](200) NULL,
	[ATTRIBUTE12] [nvarchar](200) NULL,
	[ATTRIBUTE13] [nvarchar](200) NULL,
	[ATTRIBUTE14] [nvarchar](200) NULL,
	[ATTRIBUTE15] [nvarchar](200) NULL,
	[PLANT_ID] [nvarchar](30) NULL,
);


	SET @MANUAL_LOOKUP_PROCESS += 'BASIS_START_TIME_PLANT' + ','
	SET @MANUAL_LOOKUP_PROCESS += 'BOM_LINK_PLANT' + ','
	SET @MANUAL_LOOKUP_PROCESS += 'CAPA_UI_CAPA_DEFINIT' + ','
	SET @MANUAL_LOOKUP_PROCESS += 'CAPA_UI_EXCEPT_LINE' + ','
	SET @MANUAL_LOOKUP_PROCESS += 'SCP_PLANT' + ','
	SET @MANUAL_LOOKUP_PROCESS += 'SCP_PLANT' + ','
	SET @MANUAL_LOOKUP_PROCESS += 'SIMULATION_NAME' + ','
	SET @MANUAL_LOOKUP_PROCESS += 'ERP_MATERIAL_DOCUMENT_MAPPING' + ','
	SET @MANUAL_LOOKUP_PROCESS += 'ERP_MATERIAL_DOCUMENT_MAPPING_FOR_DW' + ','
	SET @MANUAL_LOOKUP_PROCESS += 'MATERIAL_SIMUL_STORAGE_TYPE' -- + ','


	----- COMPANYID -------

	--SET @in_cond = ' in (''SITE_ID'',''PLANT_ID'',''STORAGE_ID'')'
--SET @in_cond = ' in (''SITE_ID'')'

DECLARE @LOOKUP_TYPE_CODE NVARCHAR(MAX)=''
DECLARE @SEG1 NVARCHAR(MAX)=''
DECLARE @SEG2 NVARCHAR(MAX)=''
DECLARE @SEG3 NVARCHAR(MAX)=''
DECLARE @SEG4 NVARCHAR(MAX)=''
DECLARE @SEG5 NVARCHAR(MAX)=''

DECLARE @work int = 0

DECLARE @KEYNAME_TO_FIND NVARCHAR(MAX) = ''
DECLARE @KEYTYPE_TO_FIND NVARCHAR(MAX) = ''
DECLARE @CODE_COLUMN  NVARCHAR(MAX) = ''

DECLARE @v_SEQ Nvarchar(MAX) = ''
DECLARE @SEG_COLUMN  NVARCHAR(MAX) = ''
DECLARE @SEGMENT_IDX  NVARCHAR(MAX) = ''
set @KEYNAME_TO_FIND = ''
set @KEYTYPE_TO_FIND = ''
SET @CODE_COLUMN = ''

insert into #SEG_LIST ([KEY_NAME_A],[KEY_NAME_IDX]) VALUES ('SEGMENT2','SEGMENT2')
insert into #SEG_LIST ([KEY_NAME_A],[KEY_NAME_IDX]) VALUES ('SEGMENT3','SEGMENT3')
insert into #SEG_LIST ([KEY_NAME_A],[KEY_NAME_IDX]) VALUES ('SEGMENT4','SEGMENT4')
insert into #SEG_LIST ([KEY_NAME_A],[KEY_NAME_IDX]) VALUES ('SEGMENT5','SEGMENT5')

DECLARE KEY_NAME_CURSOR CURSOR FOR
select 	KEY_NAME_A, KEY_TYPE_A FROM #TMP_KEY_NAME_TO_FIND WITH(NOLOCK)

OPEN KEY_NAME_CURSOR;
FETCH NEXT FROM KEY_NAME_CURSOR INTO @KEYNAME_TO_FIND,@KEYTYPE_TO_FIND;
WHILE @@FETCH_STATUS = 0
BEGIN
   PRINT '-- o ---'
   PRINT @KEYNAME_TO_FIND
   PRINT @KEYTYPE_TO_FIND
	DECLARE LOOKUP_CURSOR CURSOR FOR
	select LOOKUP_TYPE_CODE  from scm_code_lookup_value WITH(NOLOCK) 
	group by LOOKUP_TYPE_CODE
	--AND LOOKUP_TYPE_CODE = 'CREATE_ALT_WO_E_PRE'
	OPEN LOOKUP_CURSOR;
	FETCH NEXT FROM LOOKUP_CURSOR
	INTO @LOOKUP_TYPE_CODE;

	WHILE  @@FETCH_STATUS = 0
	BEGIN
	    print '-- vv --'
		print @KEYTYPE_TO_FIND
		print @LOOKUP_TYPE_CODE -- + ' ' + @SEG1 + ' '+ @SEG2 + ' '+ @SEG3 + ' '+ @SEG4 + ' '+ @SEG5 + ' '



		--DELETE FROM #SEG_LIST WHERE 1=1
		--if @SEG1 LIKE  '%'+@KEYNAME_TO_FIND+'%' insert into #SEG_LIST ([KEY_NAME_A],[KEY_NAME_IDX]) VALUES (@SEG1,'SEGMENT1')
		--if @SEG2 LIKE  '%'+@KEYNAME_TO_FIND+'%' insert into #SEG_LIST ([KEY_NAME_A],[KEY_NAME_IDX]) VALUES (@SEG2,'SEGMENT2')
		--if @SEG3 LIKE  '%'+@KEYNAME_TO_FIND+'%' insert into #SEG_LIST ([KEY_NAME_A],[KEY_NAME_IDX]) VALUES (@SEG3,'SEGMENT3')
		--if @SEG4 LIKE  '%'+@KEYNAME_TO_FIND+'%' insert into #SEG_LIST ([KEY_NAME_A],[KEY_NAME_IDX]) VALUES (@SEG4,'SEGMENT4')
		--if @SEG5 LIKE  '%'+@KEYNAME_TO_FIND+'%' insert into #SEG_LIST ([KEY_NAME_A],[KEY_NAME_IDX]) VALUES (@SEG5,'SEGMENT5')

		DECLARE SEG_CURSOR CURSOR FOR
		SELECT KEY_NAME_A,KEY_NAME_IDX FROM #SEG_LIST WITH(NOLOCK)
		OPEN SEG_CURSOR;
		print 'open seg'
		print 'fetch seg'
		FETCH NEXT FROM SEG_CURSOR
		INTO @SEG_COLUMN,@SEGMENT_IDX


		while @@fetch_staTUS = 0
		begin
		    PRINT '--'
			PRINT @KEYNAME_TO_FIND
			
			PRINT @SEG_COLUMN + ' OF ' + @LOOKUP_TYPE_CODE
			PRINT @SEGMENT_IDX
		

			insert into #TMP_SCM_SYS_LOOKUP_VALUE select * from scm_code_lookup_value with(nolock)
			where lookup_type_code = @LOOKUP_TYPE_CODE 
		IF @KEYTYPE_TO_FIND = 'STORAGE_ID' BEGIN
			--IF @SEGMENT_IDX = 'SEGMENT1' BEGIN
			--		UPDATE #TMP_SCM_SYS_LOOKUP_VALUE 
			--		SET #TMP_SCM_SYS_LOOKUP_VALUE.SEGMENT1 = M.NEW_VALUE2
			--		FROM
			--		(SELECT * FROM NERP_CONV_MASTER  WHERE CODETYPE=@KEYTYPE_TO_FIND) as M
			--		WHERE #TMP_SCM_SYS_LOOKUP_VALUE.SEGMENT1 = M.OLD_VALUE2
			--		AND #TMP_SCM_SYS_LOOKUP_VALUE.LOOKUP_TYPE_CODE = @LOOKUP_TYPE_CODE 
			--END ELSE 
			IF @SEGMENT_IDX = 'SEGMENT2' BEGIN
					UPDATE #TMP_SCM_SYS_LOOKUP_VALUE 
					SET #TMP_SCM_SYS_LOOKUP_VALUE.SEGMENT2 = M.NEW_VALUE2
					FROM
					(SELECT * FROM NERP_CONV_MASTER  WHERE CODETYPE=@KEYTYPE_TO_FIND) as M
					WHERE #TMP_SCM_SYS_LOOKUP_VALUE.SEGMENT2 = M.OLD_VALUE2
					AND #TMP_SCM_SYS_LOOKUP_VALUE.LOOKUP_TYPE_CODE = @LOOKUP_TYPE_CODE 
			END ELSE IF @SEGMENT_IDX = 'SEGMENT3' BEGIN
					UPDATE #TMP_SCM_SYS_LOOKUP_VALUE 
					SET #TMP_SCM_SYS_LOOKUP_VALUE.SEGMENT3 = M.NEW_VALUE2
					FROM
					(SELECT * FROM NERP_CONV_MASTER  WHERE CODETYPE=@KEYTYPE_TO_FIND) as M
					WHERE #TMP_SCM_SYS_LOOKUP_VALUE.SEGMENT3 = M.OLD_VALUE2
					AND #TMP_SCM_SYS_LOOKUP_VALUE.LOOKUP_TYPE_CODE = @LOOKUP_TYPE_CODE 
			END ELSE IF @SEGMENT_IDX = 'SEGMENT4' BEGIN
					UPDATE #TMP_SCM_SYS_LOOKUP_VALUE 
					SET #TMP_SCM_SYS_LOOKUP_VALUE.SEGMENT4 = M.NEW_VALUE2
					FROM
					(SELECT * FROM NERP_CONV_MASTER  WHERE CODETYPE=@KEYTYPE_TO_FIND) as M
					WHERE #TMP_SCM_SYS_LOOKUP_VALUE.SEGMENT4 = M.OLD_VALUE2
					AND #TMP_SCM_SYS_LOOKUP_VALUE.LOOKUP_TYPE_CODE = @LOOKUP_TYPE_CODE 
			END ELSE IF @SEGMENT_IDX = 'SEGMENT5' BEGIN
					UPDATE #TMP_SCM_SYS_LOOKUP_VALUE 
					SET #TMP_SCM_SYS_LOOKUP_VALUE.SEGMENT5 = M.NEW_VALUE2
					FROM
					(SELECT * FROM NERP_CONV_MASTER  WHERE CODETYPE=@KEYTYPE_TO_FIND) as M
					WHERE #TMP_SCM_SYS_LOOKUP_VALUE.SEGMENT5 = M.OLD_VALUE2
					AND #TMP_SCM_SYS_LOOKUP_VALUE.LOOKUP_TYPE_CODE = @LOOKUP_TYPE_CODE 
			END
		END ELSE BEGIN
			--IF @SEGMENT_IDX = 'SEGMENT1' BEGIN
			--		UPDATE #TMP_SCM_SYS_LOOKUP_VALUE 
			--		SET #TMP_SCM_SYS_LOOKUP_VALUE.SEGMENT1 = M.NEW_VALUE1
			--		FROM
			--		(SELECT * FROM NERP_CONV_MASTER  WHERE CODETYPE=@KEYTYPE_TO_FIND) as M
			--		WHERE #TMP_SCM_SYS_LOOKUP_VALUE.SEGMENT1 = M.OLD_VALUE1
			--		AND #TMP_SCM_SYS_LOOKUP_VALUE.LOOKUP_TYPE_CODE = @LOOKUP_TYPE_CODE 
			--END ELSE 
			IF @SEGMENT_IDX = 'SEGMENT2' BEGIN
					UPDATE #TMP_SCM_SYS_LOOKUP_VALUE 
					SET #TMP_SCM_SYS_LOOKUP_VALUE.SEGMENT2 = M.NEW_VALUE1
					FROM
					(SELECT * FROM NERP_CONV_MASTER  WHERE CODETYPE=@KEYTYPE_TO_FIND) as M
					WHERE #TMP_SCM_SYS_LOOKUP_VALUE.SEGMENT2 = M.OLD_VALUE1
					AND #TMP_SCM_SYS_LOOKUP_VALUE.LOOKUP_TYPE_CODE = @LOOKUP_TYPE_CODE 
			END ELSE IF @SEGMENT_IDX = 'SEGMENT3' BEGIN
					UPDATE #TMP_SCM_SYS_LOOKUP_VALUE 
					SET #TMP_SCM_SYS_LOOKUP_VALUE.SEGMENT3 = M.NEW_VALUE1
					FROM
					(SELECT * FROM NERP_CONV_MASTER  WHERE CODETYPE=@KEYTYPE_TO_FIND) as M
					WHERE #TMP_SCM_SYS_LOOKUP_VALUE.SEGMENT3 = M.OLD_VALUE1
					AND #TMP_SCM_SYS_LOOKUP_VALUE.LOOKUP_TYPE_CODE = @LOOKUP_TYPE_CODE 
			END ELSE IF @SEGMENT_IDX = 'SEGMENT4' BEGIN
					UPDATE #TMP_SCM_SYS_LOOKUP_VALUE 
					SET #TMP_SCM_SYS_LOOKUP_VALUE.SEGMENT4 = M.NEW_VALUE1
					FROM
					(SELECT * FROM NERP_CONV_MASTER  WHERE CODETYPE=@KEYTYPE_TO_FIND) as M
					WHERE #TMP_SCM_SYS_LOOKUP_VALUE.SEGMENT4 = M.OLD_VALUE1
					AND #TMP_SCM_SYS_LOOKUP_VALUE.LOOKUP_TYPE_CODE = @LOOKUP_TYPE_CODE 
			END ELSE IF @SEGMENT_IDX = 'SEGMENT5' BEGIN
					UPDATE #TMP_SCM_SYS_LOOKUP_VALUE 
					SET #TMP_SCM_SYS_LOOKUP_VALUE.SEGMENT5 = M.NEW_VALUE1
					FROM
					(SELECT * FROM NERP_CONV_MASTER  WHERE CODETYPE=@KEYTYPE_TO_FIND) as M
					WHERE #TMP_SCM_SYS_LOOKUP_VALUE.SEGMENT5 = M.OLD_VALUE1
					AND #TMP_SCM_SYS_LOOKUP_VALUE.LOOKUP_TYPE_CODE = @LOOKUP_TYPE_CODE 
			END
		END



			delete from scm_code_lookup_value where lookup_type_code = @LOOKUP_TYPE_CODE 
			insert into scm_code_lookup_value
			select [LOOKUP_TYPE_CODE]
			,[SEGMENT1]
			,[SEGMENT2]
			,[SEGMENT3]
			,[SEGMENT4]
			,[SEGMENT5]
			,[SORT_ORDER]
			,[ACTIVE_FLAG]
			,[VALUE_DESCRIPTION]
			,[CREATE_USER_ID]
			,[CREATE_DATE]
			,[MODIFY_USER_ID]
			,[MODIFY_DATE]
			,[ATTRIBUTE1]
			,[ATTRIBUTE2]
			,[ATTRIBUTE3]
			,[ATTRIBUTE4]
			,[ATTRIBUTE5]
			,[ATTRIBUTE6]
			,[ATTRIBUTE7]
			,[ATTRIBUTE8]
			,[ATTRIBUTE9]
			,[ATTRIBUTE10]
			,[ATTRIBUTE11]
			,[ATTRIBUTE12]
			,[ATTRIBUTE13]
			,[ATTRIBUTE14]
			,[ATTRIBUTE15]
			,[PLANT_ID]
			from (select [LOOKUP_TYPE_CODE]
			,[SEGMENT1]
			,[SEGMENT2]
			,[SEGMENT3]
			,[SEGMENT4]
			,[SEGMENT5]
			,MAX([SORT_ORDER]) AS [SORT_ORDER]
			,MAX([ACTIVE_FLAG]) AS [ACTIVE_FLAG]
			,MAX([VALUE_DESCRIPTION]) AS [VALUE_DESCRIPTION]
			,MAX([CREATE_USER_ID]) AS [CREATE_USER_ID]
			,MAX([CREATE_DATE]) AS [CREATE_DATE]
			,MAX([MODIFY_USER_ID]) AS [MODIFY_USER_ID]
			,MAX([MODIFY_DATE]) AS [MODIFY_DATE]
			,MAX([ATTRIBUTE1]) AS [ATTRIBUTE1]
			,MAX([ATTRIBUTE2]) AS [ATTRIBUTE2]
			,MAX([ATTRIBUTE3]) AS [ATTRIBUTE3]
			,MAX([ATTRIBUTE4]) AS [ATTRIBUTE4]
			,MAX([ATTRIBUTE5]) AS [ATTRIBUTE5]
			,MAX([ATTRIBUTE6]) AS [ATTRIBUTE6]
			,MAX([ATTRIBUTE7]) AS [ATTRIBUTE7]
			,MAX([ATTRIBUTE8]) AS [ATTRIBUTE8]
			,MAX([ATTRIBUTE9]) AS [ATTRIBUTE9]
			,MAX([ATTRIBUTE10]) AS [ATTRIBUTE10]
			,MAX([ATTRIBUTE11]) AS [ATTRIBUTE11]
			,MAX([ATTRIBUTE12]) AS [ATTRIBUTE12]
			,MAX([ATTRIBUTE13]) AS [ATTRIBUTE13]
			,MAX([ATTRIBUTE14]) AS [ATTRIBUTE14]
			,MAX([ATTRIBUTE15]) AS [ATTRIBUTE15]
			,MAX([PLANT_ID]) AS PLANT_ID 
			from #TMP_SCM_SYS_LOOKUP_VALUE
			group by 	[LOOKUP_TYPE_CODE] ,
		[SEGMENT1] ,
		[SEGMENT2] ,
		[SEGMENT3] ,
		[SEGMENT4] ,
		[SEGMENT5] ) A
    		delete from #TMP_SCM_SYS_LOOKUP_VALUE where 1=1

			print 'fetch seg'
			FETCH NEXT FROM SEG_CURSOR
			INTO @SEG_COLUMN,@SEGMENT_IDX
		end
		print 'close seg'
		CLOSE SEG_CURSOR;
		DEALLOCATE SEG_CURSOR;

			
		print 'fetch lookup_'
		FETCH NEXT FROM LOOKUP_CURSOR
		INTO @LOOKUP_TYPE_CODE;
		end
    	print 'close lookup_ cur'
		CLOSE LOOKUP_CURSOR;
		DEALLOCATE LOOKUP_CURSOR;
		print 'fetch keyname'
		FETCH NEXT FROM KEY_NAME_CURSOR INTO @KEYNAME_TO_FIND,@KEYTYPE_TO_FIND;
	END
	print 'close keyname'
	CLOSE KEY_NAME_CURSOR;
	DEALLOCATE KEY_NAME_CURSOR;

	drop table #TMP_SCM_SYS_LOOKUP_VALUE 
	DROP TABLE #TMP_KEY_NAME_TO_FIND
	DROP TABLE #SEG_LIST
END



