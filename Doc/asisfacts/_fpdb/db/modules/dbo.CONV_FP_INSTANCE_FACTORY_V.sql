

CREATE VIEW [dbo].[CONV_FP_INSTANCE_FACTORY_V]
AS
SELECT INS.INSTANCE_ID, INS.FACTORY_ID, FAC.COMPANY_ID, FAC.DIVISION_ID, FAC.SITE_ID, FAC.PLANT_ID, FAC.SHOP_GROUP_ID
  FROM FP_INSTANCE_FACTORY_M AS INS WITH(NOLOCK)
       JOIN SCM_FACTORY_M AS FAC WITH(NOLOCK)
	ON INS.FACTORY_ID = FAC.FACTORY_ID
   AND INS.ACTIVE_FLAG = 'Y'
   AND FAC.ACTIVE_FLAG = 'Y'


