CREATE FUNCTION [dbo].[FN_GET_CONVERT_CAL]
-- ================================================================================================
-- Program ID          : 
-- Program Name      : [FN_GET_CONVERT_CAL]
-- Param               : 	COMPANY_ID / DIVISION_ID / SITE_ID / PLANT_ID / FACTORY_ID / OPERATION_ID
--                          MODEL_ID / ITEM_ID / VERSION / VERSION_TYPE / PROD_VERSION_TYPE / CATEGORY  
-- Batch Period        : 
-- Description         : 조건에 해당되는 Category 별 Max Version 환산정보 반환
--
-- Source System       : FP
-- Destination System  : FP
-- Source Table        : SCM_ITEM_CONV_CALC_M
-- Destination Table   : 
--
-- Create(Update) Date : 2019.10.29
-- Author              : cys
-- Version             : 1.0 SCM_ITEM_CONV_CALC_M 기준으로 Category 별 Max Version 환산정보 반환
-- ================================================================================================
(
	@P_COMPANY_ID      NVARCHAR(30) = '-'
   ,@P_DIVISION_ID			NVARCHAR(30) = '-'
   ,@P_SITE_ID				NVARCHAR(30) = '-'
   ,@P_PLANT_ID			NVARCHAR(30) = '-'
   ,@P_FACTORY_ID			NVARCHAR(30) = '-'
   ,@P_OPERATION_ID		NVARCHAR(30) = '-'
   ,@P_MODEL_ID			NVARCHAR(50) = '-'
   ,@P_ITEM_ID				NVARCHAR(50) = '-'
   ,@P_VERSION				NVARCHAR(30) = '-'
   ,@P_VERSION_TYPE      NVARCHAR(10) = '-'
   ,@P_PROD_VERSION_TYPE      NVARCHAR(50) = '-'
   ,@P_CATEGORY			NVARCHAR(30) = '-'
)
RETURNS NUMERIC(18,5)
AS

BEGIN
	DECLARE @COMPANY_ID      NVARCHAR(30)
	DECLARE @DIVISION_ID       NVARCHAR(30)
	DECLARE @SITE_ID				NVARCHAR(30)
	DECLARE @PLANT_ID			NVARCHAR(30)
	DECLARE @FACTORY_ID		NVARCHAR(30)
	DECLARE @OPERATION_ID	NVARCHAR(30)
	DECLARE @MODEL_ID			NVARCHAR(50)
    DECLARE @ITEM_ID			NVARCHAR(50)
    DECLARE @VERSION			NVARCHAR(30)
	DECLARE @VERSION_TYPE	NVARCHAR(10)
	DECLARE @PROD_VERSION_TYPE	NVARCHAR(50)
	DECLARE @CATEGORY			NVARCHAR(30)
	DECLARE @CONVERT_CAL     NUMERIC(18,5)
    
	IF @P_COMPANY_ID = '-' OR @P_COMPANY_ID = ''
    	SELECT @COMPANY_ID = NULL
    ELSE 
    	SELECT @COMPANY_ID = @P_COMPANY_ID

	IF @P_DIVISION_ID = '-' OR @P_DIVISION_ID = ''
    	SELECT @DIVISION_ID = NULL
    ELSE 
    	SELECT @DIVISION_ID = @P_DIVISION_ID

	IF @P_SITE_ID = '-' OR @P_SITE_ID = ''
    	SELECT @SITE_ID = NULL
    ELSE 
    	SELECT @SITE_ID = @P_SITE_ID

	IF @P_PLANT_ID = '-' OR @P_PLANT_ID = ''
    	SELECT @PLANT_ID = NULL
    ELSE 
    	SELECT @PLANT_ID = @P_PLANT_ID

	IF @P_FACTORY_ID = '-' OR @P_FACTORY_ID = ''
    	SELECT @FACTORY_ID = NULL
    ELSE 
    	SELECT @FACTORY_ID = @P_FACTORY_ID

    IF @P_OPERATION_ID = '-' OR @P_OPERATION_ID = ''
    	SELECT @OPERATION_ID = NULL
    ELSE 
    	SELECT @OPERATION_ID = @P_OPERATION_ID
    
    IF @P_MODEL_ID = '-' OR @P_MODEL_ID = ''
    	SELECT @MODEL_ID = NULL
    ELSE 
    	SELECT @MODEL_ID = @P_MODEL_ID

    IF @P_ITEM_ID = '-' OR @P_ITEM_ID = ''
    	SELECT @ITEM_ID = NULL
    ELSE 
    	SELECT @ITEM_ID = @P_ITEM_ID

	IF @P_VERSION = '-' OR @P_VERSION = ''
    	SELECT @VERSION = NULL
    ELSE 
    	SELECT @VERSION = @P_VERSION
   
   IF @P_VERSION_TYPE = '-' OR @P_VERSION_TYPE = ''
    	SELECT @VERSION_TYPE = NULL
    ELSE 
    	SELECT @VERSION_TYPE = @P_VERSION_TYPE
	
	IF @P_PROD_VERSION_TYPE = '-' OR @P_PROD_VERSION_TYPE = ''
    	SELECT @PROD_VERSION_TYPE = NULL
    ELSE 
    	SELECT @PROD_VERSION_TYPE = @P_PROD_VERSION_TYPE
	
	IF @P_CATEGORY = '-' OR @P_CATEGORY = ''
    	SELECT @CATEGORY = NULL
	ELSE IF @P_CATEGORY = 'M(P/C)'
		SELECT @CATEGORY = 'Pancake (m/batch)'
	ELSE IF @P_CATEGORY = 'J/R'
		SELECT @CATEGORY = 'Jumbo Roll (m/batch)'
	ELSE IF @P_CATEGORY = 'Cell'
		SELECT @CATEGORY = 'cell/batch'
    ELSE 
    	SELECT @CATEGORY = @P_CATEGORY
	
	IF  @P_FACTORY_ID NOT IN ('E2', 'E3', 'E5','E6', 'EB', 'EC', 'ED') AND (@P_VERSION_TYPE = '-' OR @P_VERSION_TYPE = '') AND (@P_PROD_VERSION_TYPE = '-' OR @P_PROD_VERSION_TYPE = '')
		
		SELECT 	@CONVERT_CAL = MAX(A.VALUE)
		FROM   	SCM_ITEM_CONV_CALC_M A WITH(NOLOCK)
		WHERE  	1=1
		AND		A.MAX_VER_FLAG = 'Y'
		AND		A.COMPANY_ID		= @COMPANY_ID
		AND		A.DIVISION_ID		= @DIVISION_ID
		AND		A.SITE_ID				= @SITE_ID
		AND		A.PLANT_ID			= @PLANT_ID
		AND		A.FACTORY_ID		= @FACTORY_ID
		AND		A.OPERATION		= @OPERATION_ID
		AND		A.MODEL_ID			LIKE @MODEL_ID + '%'
		AND		A.ITEM_ID			= @ITEM_ID
		AND		A.CATEGORY			= @CATEGORY

	ELSE IF  @P_FACTORY_ID NOT IN ('E2', 'E3', 'E5','E6', 'EB', 'EC', 'ED') AND (@P_VERSION_TYPE = '-' OR @P_VERSION_TYPE = '') 

		SELECT 	@CONVERT_CAL = MAX(A.VALUE)
		FROM   	SCM_ITEM_CONV_CALC_M A WITH(NOLOCK)
		WHERE  	1=1
		AND		A.MAX_VER_FLAG = 'Y'
		AND		A.COMPANY_ID		= @COMPANY_ID
		AND		A.DIVISION_ID		= @DIVISION_ID
		AND		A.SITE_ID				= @SITE_ID
		AND		A.PLANT_ID			= @PLANT_ID
		AND		A.FACTORY_ID		= @FACTORY_ID
		AND		A.OPERATION		= @OPERATION_ID
		AND		A.MODEL_ID			LIKE @MODEL_ID + '%'
		AND		A.ITEM_ID			= @ITEM_ID
		AND		A.PROD_VERSION_TYPE = @PROD_VERSION_TYPE
		AND		A.CATEGORY			= @CATEGORY

	ELSE IF (@P_VERSION_TYPE = '-' OR @P_VERSION_TYPE = '') AND (@P_PROD_VERSION_TYPE = '-' OR @P_PROD_VERSION_TYPE = '')
	    
		SELECT 	@CONVERT_CAL = MAX(A.VALUE)
		FROM   	SCM_ITEM_CONV_CALC_M A WITH(NOLOCK)
		WHERE  	1=1
		AND		A.MAX_VER_FLAG = 'Y'
		AND		A.COMPANY_ID		= @COMPANY_ID
		AND		A.DIVISION_ID		= @DIVISION_ID
		AND		A.SITE_ID				= @SITE_ID
		AND		A.PLANT_ID			= @PLANT_ID
		AND		A.FACTORY_ID		= @FACTORY_ID
		AND		A.OPERATION		= @OPERATION_ID
		AND		A.MODEL_ID			LIKE @MODEL_ID + '%'
		AND		A.ITEM_ID			= @ITEM_ID
		AND		A.VERSION			= @VERSION
		AND		A.CATEGORY			= @CATEGORY
		
	ELSE IF  (@P_VERSION_TYPE = '-' OR @P_VERSION_TYPE = '') 

		SELECT 	@CONVERT_CAL = MAX(A.VALUE)
		FROM   	SCM_ITEM_CONV_CALC_M A WITH(NOLOCK)
		WHERE  	1=1
		AND		A.MAX_VER_FLAG = 'Y'
		AND		A.COMPANY_ID		= @COMPANY_ID
		AND		A.DIVISION_ID		= @DIVISION_ID
		AND		A.SITE_ID				= @SITE_ID
		AND		A.PLANT_ID			= @PLANT_ID
		AND		A.FACTORY_ID		= @FACTORY_ID
		AND		A.OPERATION		= @OPERATION_ID
		AND		A.MODEL_ID			LIKE @MODEL_ID + '%'
		AND		A.ITEM_ID			= @ITEM_ID
		AND		A.VERSION			= @VERSION
		AND		A.PROD_VERSION_TYPE = @PROD_VERSION_TYPE
		AND		A.CATEGORY			= @CATEGORY
		
	ELSE
		
		SELECT 	@CONVERT_CAL = MAX(A.VALUE)
		FROM   	SCM_ITEM_CONV_CALC_M A WITH(NOLOCK)
		WHERE  	1=1
		AND		A.MAX_VER_FLAG = 'Y'
		AND		A.COMPANY_ID		= @COMPANY_ID
		AND		A.DIVISION_ID		= @DIVISION_ID
		AND		A.SITE_ID				= @SITE_ID
		AND		A.PLANT_ID			= @PLANT_ID
		AND		A.FACTORY_ID		= @FACTORY_ID
		AND		A.OPERATION		= @OPERATION_ID
		AND		A.MODEL_ID			= @MODEL_ID
		AND		A.ITEM_ID			= @ITEM_ID
		AND		A.VERSION			= @VERSION
		AND		A.VERSION_TYPE	= @VERSION_TYPE
		AND		A.PROD_VERSION_TYPE = @PROD_VERSION_TYPE
		AND		A.CATEGORY			= @CATEGORY
	
	IF @CONVERT_CAL IS NULL
	BEGIN
				IF  @P_FACTORY_ID NOT IN ('E2', 'E3', 'E5','E6', 'EB', 'EC', 'ED') AND (@P_VERSION_TYPE = '-' OR @P_VERSION_TYPE = '') AND (@P_PROD_VERSION_TYPE = '-' OR @P_PROD_VERSION_TYPE = '')
		
					SELECT 	@CONVERT_CAL = MAX(A.VALUE)
					FROM   	SCM_ITEM_CONV_CALC_M A WITH(NOLOCK)
					WHERE  	1=1
					--AND		A.MAX_VER_FLAG = 'Y'
					AND		A.COMPANY_ID		= @COMPANY_ID
					AND		A.DIVISION_ID		= @DIVISION_ID
					AND		A.SITE_ID				= @SITE_ID
					AND		A.PLANT_ID			= @PLANT_ID
					AND		A.FACTORY_ID		= @FACTORY_ID
					AND		A.OPERATION		= @OPERATION_ID
					AND		A.MODEL_ID			LIKE @MODEL_ID + '%'
					AND		A.ITEM_ID			= @ITEM_ID
					AND		A.CATEGORY			= @CATEGORY

				ELSE IF  @P_FACTORY_ID NOT IN ('E2', 'E3', 'E5','E6', 'EB', 'EC', 'ED') AND (@P_VERSION_TYPE = '-' OR @P_VERSION_TYPE = '') 

					SELECT 	@CONVERT_CAL = MAX(A.VALUE)
					FROM   	SCM_ITEM_CONV_CALC_M A WITH(NOLOCK)
					WHERE  	1=1
					--AND		A.MAX_VER_FLAG = 'Y'
					AND		A.COMPANY_ID		= @COMPANY_ID
					AND		A.DIVISION_ID		= @DIVISION_ID
					AND		A.SITE_ID				= @SITE_ID
					AND		A.PLANT_ID			= @PLANT_ID
					AND		A.FACTORY_ID		= @FACTORY_ID
					AND		A.OPERATION		= @OPERATION_ID
					AND		A.MODEL_ID			LIKE @MODEL_ID + '%'
					AND		A.ITEM_ID			= @ITEM_ID
					AND		A.PROD_VERSION_TYPE = @PROD_VERSION_TYPE
					AND		A.CATEGORY			= @CATEGORY

				ELSE IF (@P_VERSION_TYPE = '-' OR @P_VERSION_TYPE = '') AND (@P_PROD_VERSION_TYPE = '-' OR @P_PROD_VERSION_TYPE = '')
	    
					SELECT 	@CONVERT_CAL = MAX(A.VALUE)
					FROM   	SCM_ITEM_CONV_CALC_M A WITH(NOLOCK)
					WHERE  	1=1
					--AND		A.MAX_VER_FLAG = 'Y'
					AND		A.COMPANY_ID		= @COMPANY_ID
					AND		A.DIVISION_ID		= @DIVISION_ID
					AND		A.SITE_ID				= @SITE_ID
					AND		A.PLANT_ID			= @PLANT_ID
					AND		A.FACTORY_ID		= @FACTORY_ID
					AND		A.OPERATION		= @OPERATION_ID
					AND		A.MODEL_ID			LIKE @MODEL_ID + '%'
					AND		A.ITEM_ID			= @ITEM_ID
					AND		A.VERSION			= @VERSION
					AND		A.CATEGORY			= @CATEGORY
		
				ELSE IF  (@P_VERSION_TYPE = '-' OR @P_VERSION_TYPE = '') 

					SELECT 	@CONVERT_CAL = MAX(A.VALUE)
					FROM   	SCM_ITEM_CONV_CALC_M A WITH(NOLOCK)
					WHERE  	1=1
					--AND		A.MAX_VER_FLAG = 'Y'
					AND		A.COMPANY_ID		= @COMPANY_ID
					AND		A.DIVISION_ID		= @DIVISION_ID
					AND		A.SITE_ID				= @SITE_ID
					AND		A.PLANT_ID			= @PLANT_ID
					AND		A.FACTORY_ID		= @FACTORY_ID
					AND		A.OPERATION		= @OPERATION_ID
					AND		A.MODEL_ID			LIKE @MODEL_ID + '%'
					AND		A.ITEM_ID			= @ITEM_ID
					AND		A.VERSION			= @VERSION
					AND		A.PROD_VERSION_TYPE = @PROD_VERSION_TYPE
					AND		A.CATEGORY			= @CATEGORY
		
				ELSE
		
					SELECT 	@CONVERT_CAL = MAX(A.VALUE)
					FROM   	SCM_ITEM_CONV_CALC_M A WITH(NOLOCK)
					WHERE  	1=1
					--AND		A.MAX_VER_FLAG = 'Y'
					AND		A.COMPANY_ID		= @COMPANY_ID
					AND		A.DIVISION_ID		= @DIVISION_ID
					AND		A.SITE_ID				= @SITE_ID
					AND		A.PLANT_ID			= @PLANT_ID
					AND		A.FACTORY_ID		= @FACTORY_ID
					AND		A.OPERATION		= @OPERATION_ID
					AND		A.MODEL_ID			= @MODEL_ID
					AND		A.ITEM_ID			= @ITEM_ID
					AND		A.VERSION			= @VERSION
					AND		A.VERSION_TYPE	= @VERSION_TYPE
					AND		A.PROD_VERSION_TYPE = @PROD_VERSION_TYPE
					AND		A.CATEGORY			= @CATEGORY
		END
		
	RETURN @CONVERT_CAL

END
