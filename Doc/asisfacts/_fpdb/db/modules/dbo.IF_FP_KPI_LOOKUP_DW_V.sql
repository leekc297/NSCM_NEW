






CREATE VIEW [dbo].[IF_FP_KPI_LOOKUP_DW_V]
-- ================================================================================================
-- Program ID          : IF_FP_KPI_LOOKUP_DW_V
--
-- Program Name        : IF_FP_KPI_LOOKUP_DW_V
-- Param               :
-- Batch Period        : 
-- Description         : KPI 제공용 기준 정보 View - DW 제공용 분리
--
-- Source System       : FP SDB
-- Destination System  : SCP SDB
-- Source Table        : SCM_DIVISION_M, SCM_SITE_M SCM_PLANT_M SCM_FACTORY_M, SCM_SYS_LOOKUP_VALUE, SCM_LINE_M
-- Destination Table   : 
--
-- Create(Update) Date : 2022.03.30
-- Author              : kim choon dong
-- Version             : 2018-10-15 kimcd 최초 작성
--                       2018-11-07 kimcd line 정보 추가
--                       2018-12-07 kimcd plant 명을 lookup으로 대체
--                       2018-12-10 kimcd division 명 lookup으로 대체
--                       2019-01-16 kimcd 3050 plant 추가
--                       2019-04-26 kimcd COMPANY
--                                        PROD_TYPE
--                                        HI 지표용 정보 유형 추가
--                       2019-06-17 kimcd Division 정렬 순서 변경 81 40 82순으로 조정
--                       2019-10-02 kimcd 하위 공정 포함용 Operation추가
--                       2022-03-30 kimcd JV용 가상 Division 로직 추가 View 이름 변경하여 별도 형성
--                       2024-03-15 chkim.68 하드코딩 전환 (ref scm_code_lookup_value )
-- ================================================================================================
AS
SELECT 'DIVISION'  AS DATA_TYPE
     , DIVISION_ID AS SEGMENT1
     , ISNULL(MAX(V.ATTRIBUTE1),MAX(DIVISION_NAME)) AS DESCRIPTION
	 , NULL         AS ATTRIBUTE1
	 , NULL         AS ATTRIBUTE2
	 , NULL         AS ATTRIBUTE3
	 , 'Y' AS ACTIVE_FLAG
	 , DENSE_RANK() OVER (ORDER BY CASE WHEN DIVISION_ID = '81' THEN 1 WHEN DIVISION_ID = '40' THEN 2 WHEN DIVISION_ID = '82' THEN 3 END)  AS SORT_ORDER -- 2019-06-17 kimcd Division 정렬 순서 변경 81 40 82순으로 조정
	 , MAX(UPDATE_TIME) AS UPDATE_TIME
	 , NULL         AS SCM_DIVISION_ID  -- 2022-03-30 kimcd JV용 가상 Division 다른 정보와 컬럼 순서 맞추기 위해 추가
FROM   SCM_DIVISION_M D WITH(NOLOCK)
	   LEFT OUTER JOIN SCM_SYS_LOOKUP_VALUE V WITH(NOLOCK)  -- 2018-12-10 division 명을 lookup으로 대체
	   ON V.LOOKUP_TYPE_CODE = 'DIVISION_NAME'
	   AND D.DIVISION_ID = V.SEGMENT1
	   -- 하드코딩 전환 C100
WHERE  COMPANY_ID not in (SELECT SEGMENT2 FROM SCM_CODE_LOOKUP_VALUE WITH(NOLOCK) WHERE LOOKUP_TYPE_CODE='IF_FP_KPI_LOOKUP_DW_V' AND SEGMENT1  = 'EXP_COMPANY' AND ACTIVE_FLAG='Y')
AND    D.DIVISION_ID NOT IN  ( SELECT PD.PSEUDO_DIVISION_ID
							   FROM   SCM_PSEUDO_DIVISION_M PD (NOLOCK)) -- 2022-03-30 kimcd 가상 Division 제거 로직 추가
GROUP  BY DIVISION_ID
UNION ALL
SELECT 'SITE' AS DATA_TYPE
     , SITE_ID AS SEGMENT1
	 , MAX(SITE_NAME) AS DESCRIPTION
	 , NULL    AS ATTRIBUTE1
	 , NULL         AS ATTRIBUTE2
	 , NULL         AS ATTRIBUTE3
	 , 'Y'        AS ACTIVE_FLAG
	 , DENSE_RANK() OVER (ORDER BY SITE_ID )  AS SORT_ORDER
	 , MAX(UPDATE_TIME) AS UPDATE_TIME
	 , NULL         AS SCM_DIVISION_ID  -- 2022-03-30 kimcd JV용 가상 Division 다른 정보와 컬럼 순서 맞추기 위해 추가
FROM   SCM_SITE_M S WITH(NOLOCK)
GROUP BY SITE_ID
UNION ALL
SELECT 'PLANT' AS DATA_TYPE
     , P.PLANT_ID AS SEGMENT1
	 , ISNULL(V.ATTRIBUTE1, P.PLANT_NAME) AS DESCRIPTION  -- 2018-12-07 plant 명을 lookup으로 대체
	 , SITE_ID    AS ATTRIBUTE1
	 , ISNULL(PD.ORIGINAL_DIVISION_ID, P.DIVISION_ID) AS ATTRIBUTE2 -- 2022-03-30 kimcd JV용 가상 Division 추가
	 , NULL         AS ATTRIBUTE3
	 -- 하드코딩 전환 3050
	 , CASE WHEN P.PLANT_ID in (SELECT SEGMENT2 FROM SCM_CODE_LOOKUP_VALUE WITH(NOLOCK) WHERE LOOKUP_TYPE_CODE='IF_FP_KPI_LOOKUP_DW_V' AND SEGMENT1  = '0' AND ACTIVE_FLAG='Y') THEN 'N' ELSE 'Y' END    AS ACTIVE_FLAG -- 2018-12-07 plant 명을 lookup으로 대체
	 , ROW_NUMBER() OVER (ORDER BY SITE_ID, CASE WHEN ISNULL(PD.ORIGINAL_DIVISION_ID, P.DIVISION_ID) = '81' THEN 1 WHEN ISNULL(PD.ORIGINAL_DIVISION_ID, P.DIVISION_ID) = '40' THEN 2 WHEN ISNULL(PD.ORIGINAL_DIVISION_ID, P.DIVISION_ID) = '82' THEN 3 END, P.PLANT_ID )  AS SORT_ORDER -- 2019-06-17 kimcd Division 정렬 순서 변경 81 40 82순으로 조정
	  -- 2022-03-30 kimcd JV용 가상 Division을 정렬 순서 로직에 추가
	 , P.UPDATE_TIME
	 , P.DIVISION_ID AS SCM_DIVISION_ID  -- 2022-03-30 kimcd JV용 가상 Division 추가
FROM   SCM_PLANT_M P WITH(NOLOCK)
       LEFT OUTER JOIN SCM_SYS_LOOKUP_VALUE V WITH(NOLOCK)  -- 2018-12-07 plant 명을 lookup으로 대체
	   ON V.LOOKUP_TYPE_CODE = 'BASIS_START_TIME_PLANT'
	   AND P.PLANT_ID = V.SEGMENT1
	   LEFT OUTER JOIN SCM_PSEUDO_DIVISION_M PD (NOLOCK) -- 2022-03-30 kimcd JV용 가상 Divsion 로직 추가
	   ON PD.PLANT_ID = P.PLANT_ID
UNION ALL
SELECT 'BUILDING' AS DATA_TYPE
      , FACTORY_ID AS SEGMENT1
	  , FACTORY_NAME AS DESCRIPTION
	  , SITE_ID AS ATTRIBUTE1
	  , ISNULL(PD.ORIGINAL_DIVISION_ID, F.DIVISION_ID) AS ATTRIBUTE2 -- 2022-03-30 kimcd JV용 가상 Division 추가
	  , F.PLANT_ID AS ATTRIBUTE3
	  -- 하드코딩 전환 3050
	  , CASE WHEN F.PLANT_ID in (SELECT SEGMENT2 FROM SCM_CODE_LOOKUP_VALUE WITH(NOLOCK) WHERE LOOKUP_TYPE_CODE='IF_FP_KPI_LOOKUP_DW_V' AND SEGMENT1  = '0' AND ACTIVE_FLAG='Y') THEN 'N' ELSE ACTIVE_FLAG END AS ACTIVE_FLAG -- 2019-01-16 kimcd active 추가
	  , ROW_NUMBER() OVER (ORDER BY SITE_ID, CASE WHEN ISNULL(PD.ORIGINAL_DIVISION_ID, F.DIVISION_ID) = '81' THEN 1 WHEN ISNULL(PD.ORIGINAL_DIVISION_ID, F.DIVISION_ID) = '40' THEN 2 WHEN ISNULL(PD.ORIGINAL_DIVISION_ID, F.DIVISION_ID) = '82' THEN 3 END, F.PLANT_ID, FACTORY_ID )  AS SORT_ORDER  -- 2019-06-17 kimcd Division 정렬 순서 변경 81 40 82순으로 조정
	  -- 2022-03-30 kimcd JV용 가상 Division을 정렬 순서 로직에 추가
	  , F.UPDATE_TIME
	  , F.DIVISION_ID AS SCM_DIVISION_ID  -- 2022-03-30 kimcd JV용 가상 Division 추가
FROM   SCM_FACTORY_M F WITH(NOLOCK)
-- WHERE  PLANT_ID != '3050' 2019-01-16 kimcd 3050도 inactive로 추가
	   LEFT OUTER JOIN SCM_PSEUDO_DIVISION_M PD (NOLOCK) -- 2022-03-30 kimcd JV용 가상 Divsion 로직 추가
	   ON PD.PLANT_ID = F.PLANT_ID
UNION ALL
SELECT 'OPERATION' AS DATA_TYPE
      , SEGMENT1 AS SEGMENT1
	  , VALUE_DESCRIPTION AS DESCRIPTION
	  , NULL AS ATTRIBUTE1
	  , NULL AS ATTRIBUTE2
	  , NULL AS ATTRIBUTE3
	  , ATTRIBUTE7 AS ACTIVE_FLAG
	  , SORT_ORDER
	  , MODIFY_DATE AS UPDATE_TIME
	  , NULL        AS SCM_DIVISION_ID  -- 2022-03-30 kimcd JV용 가상 Division 다른 정보와 컬럼 순서 맞추기 위해 추가
FROM   SCM_SYS_LOOKUP_VALUE F WITH(NOLOCK)
WHERE  LOOKUP_TYPE_CODE = 'FP_OPERATION'
-- 2018-11-07 kimcd 라인 정보 추가 시작
UNION ALL
SELECT 'LINE'    AS DATA_TYPE
      , LINE_ID  AS SEGMENT1
	  , MAX(LINE_NAME)   AS DESCRIPTION
	  , SITE_ID AS ATTRIBUTE1
	  , ISNULL(PD.ORIGINAL_DIVISION_ID, L.DIVISION_ID) AS ATTRIBUTE2 -- 2022-03-30 kimcd JV용 가상 Division 추가
	  , L.PLANT_ID AS ATTRIBUTE3
	  , MAX(ACTIVE_FLAG) AS ACTIVE_FLAG
	  , ROW_NUMBER() OVER (ORDER BY SITE_ID, CASE WHEN ISNULL(PD.ORIGINAL_DIVISION_ID, L.DIVISION_ID) = '81' THEN 1 WHEN ISNULL(PD.ORIGINAL_DIVISION_ID, L.DIVISION_ID) = '40' THEN 2 WHEN ISNULL(PD.ORIGINAL_DIVISION_ID, L.DIVISION_ID) = '82' THEN 3 END, L.PLANT_ID, FACTORY_ID, LINE_ID )  AS SORT_ORDER -- 2019-06-17 kimcd Division 정렬 순서 변경 81 40 82순으로 조정
	   -- 2022-03-30 kimcd 정렬 순서에 JV 가상 Division 정보 추가
	  , MAX(L.UPDATE_TIME) AS UPDATE_TIME
	  , MAX(L.DIVISION_ID) AS SCM_DIVISION_ID  -- 2022-03-30 kimcd JV용 가상 Division 추가
FROM   SCM_LINE_M L WITH(NOLOCK)
	   LEFT OUTER JOIN SCM_PSEUDO_DIVISION_M PD (NOLOCK) -- 2022-03-30 kimcd JV용 가상 Divsion 로직 추가
	   ON PD.PLANT_ID = L.PLANT_ID
WHERE  OPERATION_ID IN ( SELECT F.SEGMENT1
						 FROM   SCM_SYS_LOOKUP_VALUE F WITH(NOLOCK)
						 WHERE  F.LOOKUP_TYPE_CODE = 'FP_OPERATION'
						 AND    F.ATTRIBUTE7 = 'Y' )
-- 하드코딩 전환 3050
AND    L.PLANT_ID not in (SELECT SEGMENT2 FROM SCM_CODE_LOOKUP_VALUE WITH(NOLOCK) WHERE LOOKUP_TYPE_CODE='IF_FP_KPI_LOOKUP_DW_V' AND SEGMENT1  = '0' AND ACTIVE_FLAG='Y')
AND    FACTORY_ID != 'E8'
GROUP BY L.COMPANY_ID, ISNULL(PD.ORIGINAL_DIVISION_ID, L.DIVISION_ID), L.SITE_ID, L.PLANT_ID, L.FACTORY_ID, L.LINE_ID -- 2022-03-30 kimcd JV 가상 Division 정보 추가
-- 2018-11-07 kimcd 라인 정보 추가 끝
-- 2019-04-26 kimcd COMPANY, PROD_TYPE 유형 추가 시작
UNION ALL
SELECT 'COMPANY'    AS DATA_TYPE
     , COMPANY_ID   AS SEGMENT1
     , COMPANY_NAME AS DESCRIPTION
	 , NULL         AS ATTRIBUTE1
	 , NULL         AS ATTRIBUTE2
	 , NULL         AS ATTRIBUTE3
	 , 'Y' AS ACTIVE_FLAG
	 , DENSE_RANK() OVER (ORDER BY COMPANY_ID)  AS SORT_ORDER
	 , UPDATE_TIME AS UPDATE_TIME
	 , NULL        AS SCM_DIVISION_ID  -- 2022-03-30 kimcd JV용 가상 Division 다른 정보와 컬럼 순서 맞추기 위해 추가
FROM   SCM_COMPANY_M C WITH(NOLOCK)
UNION ALL
SELECT 'PROD_TYPE'  AS DATA_TYPE
     , ATTRIBUTE2   AS SEGMENT1
     , MAX(SEGMENT3) AS DESCRIPTION
	 , NULL         AS ATTRIBUTE1
	 , NULL         AS ATTRIBUTE2
	 , NULL         AS ATTRIBUTE3
	 , 'Y' AS ACTIVE_FLAG
	 , DENSE_RANK() OVER (ORDER BY ATTRIBUTE2)  AS SORT_ORDER
	 , MAX(MODIFY_DATE) AS UPDATE_TIME
	 , NULL        AS SCM_DIVISION_ID  -- 2022-03-30 kimcd JV용 가상 Division 다른 정보와 컬럼 순서 맞추기 위해 추가
FROM   SCM_SYS_LOOKUP_VALUE F WITH(NOLOCK)
WHERE  F.LOOKUP_TYPE_CODE = 'DIVISION_DEMAND_TYPE'
AND    F.ACTIVE_FLAG = 'Y'
GROUP BY ATTRIBUTE2
-- 2019-04-26 kimcd COMPANY, PROD_TYPE 유형 추가 끝
-- 2019-10-02 kimcd 하위 공정용 공정 항목 추가 시작
UNION ALL
SELECT 'ALL_OPERATION' AS DATA_TYPE
      , SEGMENT1 AS SEGMENT1
	  , VALUE_DESCRIPTION AS DESCRIPTION
	  , NULL AS ATTRIBUTE1
	  , NULL AS ATTRIBUTE2
	  , NULL AS ATTRIBUTE3
	  , ACTIVE_FLAG
	  , SORT_ORDER
	  , MODIFY_DATE AS UPDATE_TIME
	  , NULL        AS SCM_DIVISION_ID  -- 2022-03-30 kimcd JV용 가상 Division 다른 정보와 컬럼 순서 맞추기 위해 추가
FROM   SCM_SYS_LOOKUP_VALUE F WITH(NOLOCK)
WHERE  LOOKUP_TYPE_CODE = 'FP_OPERATION'
-- 2019-10-02 kimcd 하위 공정용 공정 항목 추가 종료



