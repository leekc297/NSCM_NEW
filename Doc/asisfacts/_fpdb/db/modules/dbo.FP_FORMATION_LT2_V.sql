CREATE VIEW [dbo].[FP_FORMATION_LT2_V]
AS 
WITH 	FORM_BEFORE_DEGAS_ROUTE
AS 		(
		SELECT 	A.COMPANY_ID, A.SITE_ID, A.DIVISION_ID, A.PLANT_ID, A.ITEM_ID, B.NICK_NAME, A.FACTORY_ID, A.LINE_ID, B.FORMATION_FLOW_ID,
				A.ROUTE_ID, A.ROUTE_DESCRIPTION, A.ROUTE_TYPE, A.NEXT_ROUTE_ID, A.DEFAULT_ROUTE, SUM(STANDARD_LT) AS STANDARD_LT
		FROM 	SCM_AGING_ITEM_FLOW_M A,
				SCM_ITEM_M B
		WHERE 	1=1
		AND 	A.COMPANY_ID = B.COMPANY_ID
		AND 	A.SITE_ID = B.SITE_ID
		AND 	A.DIVISION_ID = B.DIVISION_ID
		AND 	A.ITEM_ID = B.ITEM_ID
		AND 	B.ACTIVE_FLAG = 'Y'
--		AND 	A.SITE_ID = 'A002'
--		AND 	A.DIVISION_ID IN ('81','82')
--		AND 	A.ITEM_ID = 'ACEN1063I-B1'
		AND 	A.ROUTE_TYPE IN ('D','R')
		GROUP BY A.COMPANY_ID, A.SITE_ID, A.DIVISION_ID, A.PLANT_ID, A.ITEM_ID, B.NICK_NAME, A.FACTORY_ID, A.LINE_ID, B.FORMATION_FLOW_ID,
				 A.ROUTE_ID, A.ROUTE_DESCRIPTION, A.ROUTE_TYPE, A.NEXT_ROUTE_ID, A.DEFAULT_ROUTE
		),
FORM_AFTER_DEGAS_ROUTE
AS 		(		 
		SELECT 	A.COMPANY_ID, A.SITE_ID, A.DIVISION_ID, A.PLANT_ID, A.ITEM_ID, B.NICK_NAME, A.FACTORY_ID, A.LINE_ID, B.FORMATION_FLOW_ID,
				A.ROUTE_ID, A.ROUTE_DESCRIPTION, A.ROUTE_TYPE, A.NEXT_ROUTE_ID, A.DEFAULT_ROUTE, SUM(STANDARD_LT) AS STANDARD_LT
		FROM 	SCM_AGING_ITEM_FLOW_M A,
				SCM_ITEM_M B
		WHERE 	1=1
		AND 	A.COMPANY_ID = B.COMPANY_ID
		AND 	A.SITE_ID = B.SITE_ID
		AND 	A.DIVISION_ID = B.DIVISION_ID
		AND 	A.ITEM_ID = B.ITEM_ID
		AND 	B.ACTIVE_FLAG = 'Y'
--		AND 	A.SITE_ID = 'A002'
--		AND 	A.DIVISION_ID IN ('81','82')
--		AND 	A.ITEM_ID = 'ACEN1063I-B1'
		AND 	A.ROUTE_TYPE IN ('C')
		GROUP BY A.COMPANY_ID, A.SITE_ID, A.DIVISION_ID, A.PLANT_ID, A.ITEM_ID, B.NICK_NAME, A.FACTORY_ID, A.LINE_ID, B.FORMATION_FLOW_ID,
				 A.ROUTE_ID, A.ROUTE_DESCRIPTION, A.ROUTE_TYPE, A.NEXT_ROUTE_ID, A.DEFAULT_ROUTE
		)
SELECT 	A.COMPANY_ID, A.SITE_ID, A.DIVISION_ID, A.PLANT_ID, A.ITEM_ID, A.NICK_NAME, A.FACTORY_ID, 
		CASE WHEN A.FORMATION_FLOW_ID = 'F6000' THEN 'F6000'
			 WHEN A.FORMATION_FLOW_ID = 'F4000F5500' THEN 'F5500'
			 ELSE NULL END AS SHORTER_OPERATION_ID, A.LINE_ID,
		A.ROUTE_ID AS BEFORE_DEGAS_ROUTE_ID, A.ROUTE_DESCRIPTION AS BEFORE_DEGAS_ROUTE_DESCRIPTION, A.ROUTE_TYPE AS BEFORE_DEGAS_ROUTE_TYPE, 
		A.STANDARD_LT AS BEFORE_DEGAS_LT, A.NEXT_ROUTE_ID AS BEFORE_DEGAS_NEXT_ROUTE_ID, A.DEFAULT_ROUTE AS BEFORE_DEGAS_DEFAULT_ROUTE,
		B.ROUTE_ID AS AFTER_DEGAS_ROUTE_ID, B.ROUTE_DESCRIPTION AS AFTER_DEGAS_ROUTE_DESCRIPTION, B.ROUTE_TYPE AS AFTER_DEGAS_ROUTE_TYPE, 
		B.STANDARD_LT AS AFTER_DEGAS_LT, B.NEXT_ROUTE_ID AS AFTER_DEGAS_NEXT_ROUTE_ID, B.DEFAULT_ROUTE AS AFTER_DEGAS_DEFAULT_ROUTE,
		CASE WHEN A.DEFAULT_ROUTE = 'Y' AND B.DEFAULT_ROUTE = 'Y' THEN 'Y' ELSE 'N' END AS DEFAULT_ROUTE
FROM 	FORM_BEFORE_DEGAS_ROUTE A
		LEFT OUTER JOIN FORM_AFTER_DEGAS_ROUTE B
		ON 	1=1
		AND A.DIVISION_ID = B.DIVISION_ID
		AND A.SITE_ID = B.SITE_ID
		AND A.ITEM_ID = B.ITEM_ID
		AND A.NEXT_ROUTE_ID = B.ROUTE_ID
WHERE 	1=1
