CREATE PROCEDURE [dbo].[PR_SCM_PROCEDURE_TEST]
AS
BEGIN
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;
	SET NOCOUNT ON; 
	SET XACT_ABORT ON;  

		-- LOG 용 변수 설정
	DECLARE @v_proc_name NVARCHAR(100) = 'PR_SCM_PROCEDURE_TEST'
	DECLARE @v_descr     NVARCHAR(250)
	DECLARE @v_count     INTEGER	   = 0
	DECLARE @sysdate     DATETIME      = GETDATE()

	
	IF [dbo].[FN_GET_PROCEDURE_EXECUTION_CHECK](@v_proc_name) > 0
		RETURN;

	BEGIN
 		WAITFOR DELAY '0:0:10'
	END
   
  
END
