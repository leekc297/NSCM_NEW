CREATE VIEW [dbo].[FP_INSTANCE_START_TIME_V]
AS
SELECT 	DISTINCT B.INSTANCE_ID, 
--		C.PLANT_ID, B.FACTORY_ID, 
		MIN(D.SEGMENT2) AS BASIS_START_TIME
FROM 	FP_INSTANCE_FACTORY_M B WITH(NOLOCK),
		SCM_FACTORY_M C WITH(NOLOCK),
		SCM_SYS_LOOKUP_VALUE D  WITH(NOLOCK)
WHERE 	1=1
AND 	B.ACTIVE_FLAG = 'Y'
AND 	B.FACTORY_ID = C.FACTORY_ID
AND 	C.ACTIVE_FLAG = 'Y'
AND 	D.LOOKUP_TYPE_CODE = 'BASIS_START_TIME_PLANT'
AND 	D.ACTIVE_FLAG = 'Y'
AND 	D.SEGMENT1 = C.PLANT_ID
GROUP BY B.INSTANCE_ID
