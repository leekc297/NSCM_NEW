CREATE VIEW [dbo].[FP_INSTANCE_OPERATION_V_NEW]

AS

WITH INSTANCE_OPERATION_1 AS (

							SELECT  DISTINCT B.INSTANCE_ID
									, A.COMPANY_ID
									, A.DIVISION_ID
									, A.SITE_ID
									, A.FACTORY_ID
									, C.OPERATION_ID
									, C.INSTANCE_TYPE
									, C.INSTANCE_TYPE AS ORG_INSTANCE_TYPE
									, C.AMEND_FLAG
									, C.AMEND_MAIN_FLAG

--							FROM	FP_INSTANCE_FACTORY_M B
							FROM	FP_INSTANCE_FACTORY_M B WITH(NOLOCK, INDEX(PK_FP_INSTANCE_FACTORY_M))
--									LEFT OUTER JOIN SCM_FACTORY_M A
									LEFT OUTER JOIN SCM_FACTORY_M A WITH(NOLOCK, INDEX(PK_SCM_FACTORY_M))
									ON 	A.FACTORY_ID = B.FACTORY_ID
									AND	B.ACTIVE_FLAG = 'Y',
									
--									SCM_OPERATION_M C
									SCM_OPERATION_M C WITH (NOLOCK, INDEX(PK_SCM_OPERATION_M))
							WHERE	1=1
							AND		A.ACTIVE_FLAG = 'Y'
							AND		A.COMPANY_ID = C.COMPANY_ID
							AND		A.DIVISION_ID = C.DIVISION_ID
							AND		A.SITE_ID = C.SITE_ID
							AND		B.INSTANCE_TYPE = C.INSTANCE_TYPE
							AND		C.ACTIVE_FLAG = 'Y'
							AND		C.OPERATION_ID != 'F4500'
							),

     INSTANCE_OPERATION AS (

							SELECT 	*
							FROM 	INSTANCE_OPERATION_1
							UNION ALL
							SELECT 	  A.SEGMENT1 AS INSTANCE_ID
							   		, B.COMPANY_ID
							   		, B.DIVISION_ID
							   		, B.SITE_ID 
							   		, A.SEGMENT3 AS FACTORY_ID 
							   		, A.SEGMENT4 AS OPERATION_ID
									, A.SEGMENT2 AS INSTANCE_TYPE
									, A.ATTRIBUTE3 AS ORG_INSTANCE_TYPE
									, A.ATTRIBUTE1 AS AMEND_FLAG
									, A.ATTRIBUTE2 AS AMEND_MAIN_FLAG
--							FROM 	SCM_SYS_LOOKUP_VALUE A,
--									FP_INSTANCE_INFO_V B
							FROM 	SCM_SYS_LOOKUP_VALUE A	WITH(NOLOCK, INDEX(PK_SCM_SYS_LOOKUP_VALUE)),
									FP_INSTANCE_INFO_V B	WITH(NOLOCK)
							WHERE 	1=1
							AND 	A.LOOKUP_TYPE_CODE = 'INSTANCE_ADD_OPERATION'
							AND 	A.ACTIVE_FLAG = 'Y'
							AND 	A.SEGMENT1 = B.INSTANCE_ID
							AND 	NOT EXISTS (
												SELECT 	*
												FROM 	INSTANCE_OPERATION_1 X
												WHERE 	1=1
												AND 	A.SEGMENT1 = X.INSTANCE_ID
												AND 	A.SEGMENT3 = X.OPERATION_ID
												AND 	A.SEGMENT2 = X.INSTANCE_TYPE
											   )
						  ),

	OPERATION_INSTANCE AS (

							SELECT	A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.FACTORY_ID, A.OPERATION_ID, A.MODEL_TYPE, A.INSTANCE_TYPE, SUM(A.EQUIP_CNT) AS EQUIP_CNT,
									CASE WHEN A.SITE_ID = 'A001' AND A.DIVISION_ID = '40' AND A.INSTANCE_TYPE = 'A' AND A.PLANT_ID = 'A010' THEN 'KR_CELL_M'
										 WHEN A.SITE_ID = 'A001' AND A.DIVISION_ID = '40' AND A.INSTANCE_TYPE = 'A' AND A.PLANT_ID = 'F030' THEN 'KR_CELL_M2'
										 WHEN A.SITE_ID = 'A001' AND A.DIVISION_ID = '40' AND A.INSTANCE_TYPE = 'E1' AND A.PLANT_ID = 'A011' THEN 'KR_E_PRE_M'
										 WHEN A.SITE_ID = 'A001' AND A.DIVISION_ID = '40' AND A.INSTANCE_TYPE = 'E1' AND A.PLANT_ID = 'F031' THEN 'KR_E_PRE_M2'
										 WHEN A.SITE_ID = 'A001' AND A.DIVISION_ID = '40' AND A.INSTANCE_TYPE = 'E1' THEN 'KR_E_PRE_M'
										 WHEN A.SITE_ID = 'A001' AND A.DIVISION_ID = '40' AND A.INSTANCE_TYPE = 'E2' THEN 'KR_E_POST_M'
										 WHEN A.SITE_ID = 'A001' AND A.DIVISION_ID = '40' AND A.INSTANCE_TYPE = 'F' THEN 'KR_FORM_M'
										 WHEN A.SITE_ID = 'A001' AND A.DIVISION_ID = '40' AND A.INSTANCE_TYPE = 'F0' THEN 'KR_FORM_T'
										 WHEN A.SITE_ID = 'A001' AND A.DIVISION_ID IN ('81','82') AND A.INSTANCE_TYPE = 'A' AND A.INSTANCE_ID = 'KR_CELL_A2' THEN 'KR_CELL_A2'
										 WHEN A.SITE_ID = 'A001' AND A.DIVISION_ID IN ('81','82') AND A.INSTANCE_TYPE = 'A' THEN 'KR_CELL'
										 WHEN A.SITE_ID = 'A001' AND A.DIVISION_ID = '40' AND A.INSTANCE_TYPE = 'E3' AND FACTORY_ID != 'EG' THEN 'KR_E_PMIX'	
										 WHEN A.SITE_ID = 'A001' AND A.DIVISION_ID = '81' AND A.INSTANCE_TYPE = 'E3' AND FACTORY_ID != 'EG' THEN 'KR_E_PMIX'
										 WHEN A.SITE_ID = 'A001' AND A.DIVISION_ID = '81' AND A.INSTANCE_TYPE = 'E1' AND FACTORY_ID != 'EG' THEN 'KR_E_PRE_A'
										 WHEN A.SITE_ID = 'A001' AND A.DIVISION_ID = '81' AND A.INSTANCE_TYPE = 'E1' AND FACTORY_ID = 'EG' THEN 'KR_E_PRE_A2'
										 WHEN A.SITE_ID = 'A001' AND A.DIVISION_ID = '81' AND A.INSTANCE_TYPE = 'E3' AND FACTORY_ID = 'EG' THEN 'KR_E_PRE_A2'									 
										 WHEN A.SITE_ID = 'A001' AND A.DIVISION_ID = '81' AND A.INSTANCE_TYPE = 'E2' THEN 'KR_E_POST_A'
										 WHEN A.SITE_ID = 'A001' AND A.DIVISION_ID IN ('81','82') AND A.INSTANCE_TYPE = 'F' THEN 'KR_FORM_A'
										 WHEN A.SITE_ID = 'A001' AND A.DIVISION_ID = '81' AND A.INSTANCE_TYPE = 'P' THEN 'KR_PACK'
										 WHEN A.SITE_ID = 'A001' AND A.DIVISION_ID = '81' AND A.INSTANCE_TYPE = 'S' THEN 'KR_SRS'
										 WHEN A.SITE_ID = 'A002' AND A.DIVISION_ID = '40' AND A.INSTANCE_TYPE = 'A' AND MODEL_TYPE IN ('Cylindrical','Prismatic','Subminiature Cylindrical') THEN 'CN_CELL_M'
										 WHEN A.SITE_ID = 'A002' AND A.DIVISION_ID = '40' AND A.INSTANCE_TYPE = 'A' AND MODEL_TYPE IN ('Pouch','3D') THEN 'CN_CELL_M2'
										 WHEN A.SITE_ID = 'A002' AND A.DIVISION_ID = '40' AND A.INSTANCE_TYPE = 'A' AND MODEL_TYPE IN ('SF') THEN 'CN_CELL_M3'
										 WHEN A.SITE_ID = 'A002' AND A.DIVISION_ID = '40' AND A.INSTANCE_TYPE = 'A' AND MODEL_TYPE IN ('EGL') THEN 'CN_CELL_M4'
										 WHEN A.SITE_ID = 'A002' AND A.DIVISION_ID = '40' AND A.INSTANCE_TYPE = 'A' AND MODEL_TYPE IN ('2D') THEN 'CN_CELL_M5'
										 WHEN A.SITE_ID = 'A002' AND A.DIVISION_ID IN ('40','81','82') AND A.INSTANCE_TYPE = 'E3' THEN 'CN_E_PMIX'
										 WHEN A.SITE_ID = 'A002' AND A.DIVISION_ID IN ('81','82') AND A.PLANT_ID = 'G452' AND A.INSTANCE_TYPE = 'E1' THEN 'CN_E_PRE'	
										 WHEN A.SITE_ID = 'A002' AND A.DIVISION_ID IN ('81','82') AND A.PLANT_ID = 'G452' AND A.INSTANCE_TYPE = 'E2' THEN 'CN_E_POST'
										 WHEN A.SITE_ID = 'A002' AND A.DIVISION_ID IN ('81','82') AND A.PLANT_ID = 'G632' AND A.INSTANCE_TYPE = 'E1' THEN 'CN_E_PRE_AB'
										 WHEN A.SITE_ID = 'A002' AND A.DIVISION_ID IN ('81','82') AND A.PLANT_ID = 'G632' AND A.INSTANCE_TYPE = 'E2' THEN 'CN_E_POST_AB'
										 WHEN A.SITE_ID = 'A002' AND A.DIVISION_ID IN ('40') AND A.INSTANCE_TYPE = 'E1' THEN 'CN_E_PRE_M'
										 WHEN A.SITE_ID = 'A002' AND A.DIVISION_ID IN ('40') AND A.INSTANCE_TYPE = 'E2' THEN 'CN_E_POST_M'
			 							 WHEN A.SITE_ID = 'A002' AND A.DIVISION_ID = '40' AND A.INSTANCE_TYPE = 'F' THEN 'CN_FORM_M'
										 WHEN A.SITE_ID = 'A002' AND A.DIVISION_ID = '81' AND A.PLANT_ID = 'G451' AND A.INSTANCE_TYPE = 'F' THEN 'CN_FORM_A'
										 WHEN A.SITE_ID = 'A002' AND A.DIVISION_ID = '81' AND A.PLANT_ID = 'G631' AND A.INSTANCE_TYPE = 'F' THEN 'CN_FORM_AB'
										 WHEN A.SITE_ID = 'A002' AND A.DIVISION_ID = '40' AND A.INSTANCE_TYPE = 'F0' THEN 'CN_FORM_T'
										 WHEN A.SITE_ID = 'A002' AND A.DIVISION_ID = '82' AND A.PLANT_ID = 'G184' AND A.INSTANCE_TYPE = 'A' THEN 'CN_CELL_E'
										 WHEN A.SITE_ID = 'A002' AND A.DIVISION_ID = '82' AND A.PLANT_ID = 'G634' AND A.INSTANCE_TYPE = 'A' THEN 'CN_CELL_EB'
										 WHEN A.SITE_ID = 'A002' AND A.DIVISION_ID = '81' AND A.PLANT_ID = 'G451' AND A.INSTANCE_TYPE = 'A' THEN 'CN_CELL'
										 WHEN A.SITE_ID = 'A002' AND A.DIVISION_ID = '81' AND A.PLANT_ID = 'G631' AND A.INSTANCE_TYPE = 'A' THEN 'CN_CELL_AB'
										 WHEN A.SITE_ID = 'A002' AND A.DIVISION_ID = '81' AND A.PLANT_ID = 'G451' AND A.INSTANCE_TYPE = 'P' THEN 'CN_PACK'
										 WHEN A.SITE_ID = 'A002' AND A.DIVISION_ID = '81' AND A.PLANT_ID = 'G631' AND A.INSTANCE_TYPE = 'P' THEN 'CN_PACK_AB'
										 WHEN A.SITE_ID = 'A002' AND A.DIVISION_ID = '40' AND A.PLANT_ID = 'G182' AND A.INSTANCE_TYPE = 'P' THEN 'CN_PACK_M'
										 WHEN A.SITE_ID = 'A002' AND A.DIVISION_ID = '82' AND A.PLANT_ID = 'G184' AND A.INSTANCE_TYPE = 'F' THEN 'CN_FORM_E'
										 WHEN A.SITE_ID = 'A002' AND A.DIVISION_ID = '82' AND A.PLANT_ID = 'G634' AND A.INSTANCE_TYPE = 'F' THEN 'CN_FORM_EB'
										 WHEN A.SITE_ID = 'A003' AND A.DIVISION_ID = '81_UC' AND A.PLANT_ID = 'G671' AND A.INSTANCE_TYPE = 'A' THEN 'UC_CELL_A'
										 WHEN A.SITE_ID = 'A003' AND A.DIVISION_ID = '81_UC' AND A.PLANT_ID = 'G672' AND A.INSTANCE_TYPE = 'E1' THEN 'UC_E_PRE_A'
										 WHEN A.SITE_ID = 'A003' AND A.DIVISION_ID = '81_UC' AND A.PLANT_ID = 'G671' AND A.INSTANCE_TYPE = 'F' THEN 'UC_FORM_A'
										 WHEN A.SITE_ID = 'A003' AND A.DIVISION_ID = '81_UC' AND A.PLANT_ID = 'G673' AND A.INSTANCE_TYPE = 'A' THEN 'UC_CELL_A2'
										 WHEN A.SITE_ID = 'A003' AND A.DIVISION_ID = '81_UC' AND A.PLANT_ID = 'G674' AND A.INSTANCE_TYPE = 'E1' THEN 'UC_E_PRE_A2'
										 WHEN A.SITE_ID = 'A003' AND A.DIVISION_ID = '81_UC' AND A.PLANT_ID = 'G673' AND A.INSTANCE_TYPE = 'F' THEN 'UC_FORM_A2'
										 WHEN A.SITE_ID = 'A003' AND A.DIVISION_ID = '81' AND A.PLANT_ID = 'G382' AND A.INSTANCE_TYPE = 'A' THEN 'US_CELL'
										 WHEN A.SITE_ID = 'A003' AND A.DIVISION_ID = '81' AND A.PLANT_ID = 'G383' AND A.INSTANCE_TYPE = 'E1' THEN 'US_E_PRE'
										 WHEN A.SITE_ID = 'A003' AND A.DIVISION_ID = '81' AND A.INSTANCE_TYPE = 'E2' THEN 'US_E_POST'
										 WHEN A.SITE_ID = 'A003' AND A.DIVISION_ID = '81' AND A.INSTANCE_TYPE = 'E3' THEN 'US_E_PMIX'
										 WHEN A.SITE_ID = 'A003' AND A.DIVISION_ID = '81' AND A.INSTANCE_TYPE = 'P' THEN 'US_PACK'
										 WHEN A.SITE_ID = 'A003' AND A.DIVISION_ID = '81' AND A.PLANT_ID = 'G382' AND A.INSTANCE_TYPE = 'F' THEN 'US_FORM_A'
										 WHEN A.SITE_ID = 'A004' AND A.DIVISION_ID = '81' AND A.INSTANCE_TYPE = 'E3' THEN 'PL_E_PMIX'
										 WHEN A.SITE_ID = 'A004' AND A.DIVISION_ID = '81' AND A.INSTANCE_TYPE = 'A' THEN 'PL_CELL'
										 WHEN A.SITE_ID = 'A004' AND A.DIVISION_ID = '81' AND A.INSTANCE_TYPE = 'P' THEN 'PL_PACK'
										 WHEN A.SITE_ID = 'A004' AND A.DIVISION_ID = '81' AND A.INSTANCE_TYPE = 'E1' THEN 'PL_E_PRE'
										 WHEN A.SITE_ID = 'A004' AND A.DIVISION_ID = '81' AND A.INSTANCE_TYPE = 'E2' THEN 'PL_E_POST'
										 WHEN A.SITE_ID = 'A004' AND A.DIVISION_ID = '81' AND A.INSTANCE_TYPE = 'F' THEN 'PL_FORM_A'
										 WHEN A.SITE_ID = 'A007' AND A.DIVISION_ID = '81_HM' AND A.PLANT_ID = 'G741' AND A.INSTANCE_TYPE = 'A' THEN 'ID_CELL_A'
										 WHEN A.SITE_ID = 'A007' AND A.DIVISION_ID = '81_HM' AND A.PLANT_ID = 'G742' AND A.INSTANCE_TYPE = 'E1' THEN 'ID_E_PRE_A'
										 WHEN A.SITE_ID = 'A007' AND A.DIVISION_ID = '81_HM' AND A.PLANT_ID = 'G741' AND A.INSTANCE_TYPE = 'F' THEN 'ID_FORM_A'
										 ELSE '-' END AS INSTANCE_ID
							FROM	(SELECT	A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.LINE_ID, A.ELECTRODE_TYPE, A.OPERATION_ID, A.MODEL_TYPE, ISNULL(B.EQUIP_CNT, 0) AS EQUIP_CNT, C.INSTANCE_TYPE, D.INSTANCE_ID
--										FROM	SCM_LINE_M A
										FROM	SCM_LINE_M A WITH(NOLOCK)
												LEFT OUTER JOIN (SELECT	A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, LINE_ID, ELECTRODE_TYPE, OPERATION_ID, COUNT(*) AS EQUIP_CNT
--																 FROM	SCM_EQUIPMENT_M A
																 FROM	SCM_EQUIPMENT_M A WITH(NOLOCK)
																 WHERE	1=1
																 AND		EQUIPMENT_TYPE = 'M'
																 AND		ACTIVE_FLAG = 'Y'
																 GROUP BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, LINE_ID, ELECTRODE_TYPE, OPERATION_ID) B
												ON 	A.COMPANY_ID = B.COMPANY_ID
												AND	A.DIVISION_ID = B.DIVISION_ID
												AND	A.SITE_ID = B.SITE_ID
												AND	A.FACTORY_ID = B.FACTORY_ID
												AND	A.LINE_ID = B.LINE_ID
												AND	A.ELECTRODE_TYPE = B.ELECTRODE_TYPE
												AND	A.OPERATION_ID = B.OPERATION_ID
												
												LEFT OUTER JOIN (SELECT SEGMENT1 AS INSTANCE_ID, SEGMENT1 AS ORG_INSTANCE_ID, SEGMENT3 AS LINE_ID 
--																   FROM SCM_SYS_LOOKUP_VALUE
																   FROM SCM_SYS_LOOKUP_VALUE WITH(NOLOCK)
--																   FROM SCM_SYS_LOOKUP_VALUE WITH(NOLOCK, INDEX(IDX_SCM_SYS_LOOKUP_VALUE_N2))
																 WHERE 	1=1
																 AND 	LOOKUP_TYPE_CODE = 'INSTANCE_SPLIT_LINE_DEFINITION'
																 AND 	ACTIVE_FLAG = 'Y'
																) D
												ON 	1=1
												AND A.LINE_ID = D.LINE_ID,
												
--												SCM_OPERATION_M C
												SCM_OPERATION_M C WITH (NOLOCK)

										WHERE	1=1
										AND		A.ACTIVE_FLAG = 'Y'
										AND		A.COMPANY_ID = C.COMPANY_ID
										AND		A.DIVISION_ID = C.DIVISION_ID
										AND		A.SITE_ID = C.SITE_ID
										AND		A.OPERATION_ID = C.OPERATION_ID
										AND 	C.ACTIVE_FLAG = 'Y'		) A
							WHERE	1=1
--							AND		A.EQUIP_CNT > 0
							GROUP BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.OPERATION_ID, A.MODEL_TYPE, A.INSTANCE_TYPE, A.INSTANCE_ID, A.FACTORY_ID
							)
							
SELECT	DISTINCT B.INSTANCE_ID,
		 A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.OPERATION_ID
		, A.INSTANCE_TYPE
		, B.MODEL_TYPE
		, A.AMEND_FLAG, A.AMEND_MAIN_FLAG
FROM	INSTANCE_OPERATION A
		LEFT OUTER JOIN OPERATION_INSTANCE B
		ON 	A.COMPANY_ID = B.COMPANY_ID
		AND	A.DIVISION_ID = B.DIVISION_ID
		AND	A.SITE_ID = B.SITE_ID
		AND	A.OPERATION_ID = B.OPERATION_ID
		AND	A.ORG_INSTANCE_TYPE = B.INSTANCE_TYPE
WHERE	1=1
AND		(B.INSTANCE_ID IS NOT NULL AND 	B.INSTANCE_ID != '-');
