							FROM	(
					    				SELECT DISTINCT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID AS CALC_PLANT_ID, A.FACTORY_ID, B.LINE_ID, A.MODEL_ID, A.ITEM_ID, B.ELECTRODE_TYPE
