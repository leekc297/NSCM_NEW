						AND   A.CALC_TYPE		= B.VERSION_TYPE
						AND   A.SEQ = 1
					) A
			WHERE	1=1
			AND		A.IDX = A.MIN_IDX


		END ; -- END Category IF

	IF @FLAG = 'CALC_TYPE'
		SET @R_VAL = @CALC_TYPE
	ELSE IF @FLAG = 'CALC_VERSION'
		SET @R_VAL = @CALC_VERSION
	ELSE	
		SET @R_VAL = @CALC_VALUE

	RETURN @R_VAL

END
