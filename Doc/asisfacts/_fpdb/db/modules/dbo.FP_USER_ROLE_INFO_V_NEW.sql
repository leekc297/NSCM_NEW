
-- dbo.FP_USER_ROLE_INFO_V source

 CREATE VIEW [dbo].[FP_USER_ROLE_INFO_V_NEW]
	
	AS
	
	SELECT B.USER_ID, C.INSTANCE_ID, C.COMPANY_ID, C.DIVISION_ID, C.SITE_ID, C.PLANT_ID, C.FACTORY_ID, C.PLAN_GROUP_ID
			 , D.ATTRIBUTE1 AS CONFIRM_AREA
			 , E.OPERATION_ID, E.LINE_ID, E.ELECTRODE_TYPE
			 , MAX(ISNULL(B.SAVE_FLAG,'N')) AS SAVE_FLAG
	FROM   TH_UIS_USER_INSTANCE_RELATE B WITH (NOLOCK)
				INNER JOIN (

									SELECT	C.ROLE_ID, C.INSTANCE_ID, C.COMPANY_ID, C.DIVISION_ID, C.SITE_ID, C.PLANT_ID, C.FACTORY_ID, A.OPERATION_ID, C.PLAN_GROUP_ID
									  FROM	FP_INSTANCE_OPERATION_V_NEW A WITH (NOLOCK)
--										  , TH_UIS_ROLE_INSTANCE_RELATE C WITH (NOLOCK)
										  , TH_UIS_ROLE_INSTANCE_RELATE C WITH (NOLOCK, INDEX(PK__TH_UIS_ROLE_INSTANCE_RELATE))
									WHERE	A.INSTANCE_ID = C.INSTANCE_ID
									AND		A.COMPANY_ID  = C.COMPANY_ID
									AND		A.DIVISION_ID = C.DIVISION_ID
									AND		A.SITE_ID	  = C.SITE_ID
									AND		C.USE_AT_FLAG = 'Y'
									GROUP BY C.ROLE_ID, C.INSTANCE_ID, C.COMPANY_ID, C.DIVISION_ID, C.SITE_ID, C.PLANT_ID, C.FACTORY_ID, A.OPERATION_ID, C.PLAN_GROUP_ID
				) C 
				ON     B.ROLE_ID          = C.ROLE_ID
				--LEFT OUTER JOIN SCM_SYS_LOOKUP_VALUE D WITH(NOLOCK)
				INNER JOIN SCM_SYS_LOOKUP_VALUE D WITH(NOLOCK)
					ON     1=1
					AND    D.LOOKUP_TYPE_CODE = 'INSTANCE_ID'
					AND    D.ACTIVE_FLAG      = 'Y'
					AND    C.INSTANCE_ID      = D.SEGMENT1
				INNER JOIN SCM_LINE_M E WITH(NOLOCK)
					ON     1=1
					AND    E.ACTIVE_FLAG = 'Y'
					AND    C.COMPANY_ID  = E.COMPANY_ID
					AND    C.DIVISION_ID = E.DIVISION_ID
					AND    C.SITE_ID	 = E.SITE_ID
					AND    C.PLANT_ID	 = E.PLANT_ID
					AND    C.FACTORY_ID  = E.FACTORY_ID
					AND    C.OPERATION_ID  = E.OPERATION_ID
					AND    (CASE WHEN D.ATTRIBUTE1 = 'PLAN GROUP' THEN C.PLAN_GROUP_ID ELSE '-' END) 
						 = (CASE WHEN D.ATTRIBUTE1 = 'PLAN GROUP' THEN E.MODEL_TYPE    ELSE '-' END)
	WHERE  B.USE_AT_FLAG = 'Y'
	GROUP BY B.USER_ID, C.INSTANCE_ID, C.COMPANY_ID, C.DIVISION_ID, C.SITE_ID, C.PLANT_ID, C.FACTORY_ID, C.PLAN_GROUP_ID
						, D.ATTRIBUTE1
						, E.OPERATION_ID, E.LINE_ID, E.ELECTRODE_TYPE;
