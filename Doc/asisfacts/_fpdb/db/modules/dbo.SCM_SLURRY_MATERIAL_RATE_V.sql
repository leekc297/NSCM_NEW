
CREATE VIEW [dbo].[SCM_SLURRY_MATERIAL_RATE_V]
AS
SELECT X.COMPANY_ID, X.DIVISION_ID, X.SITE_ID, X.PLANT_ID, X.PARENT_ITEM_ID, X.PARENT_ITEM_CLASS_NAME, X.CHILD_ITEM_ID, X.LEVEL_2_NAME, X.CHILD_QTY, X.CHILD_QTY/X.SUM_QTY*100 AS RATE
      ,CONVERT(NVARCHAR,RANK() OVER(PARTITION BY X.COMPANY_ID, X.DIVISION_ID, X.SITE_ID, X.PLANT_ID, X.PARENT_ITEM_ID, X.KEY_DATE ORDER BY X.CHILD_ITEM_ID, X.CHILD_QTY/X.SUM_QTY)) RANK
      ,X.KEY_DATE, X.INSERT_TIME  AS BOM_INSERT_TIME -- kimcd add 2017-01-13
FROM (
      SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.PARENT_ITEM_ID, A.PARENT_ITEM_CLASS_NAME, A.CHILD_ITEM_ID, A.LEVEL_2_NAME
            ,SUM(CHILD_QTY) OVER(PARTITION BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.PARENT_ITEM_ID, A.PARENT_ITEM_CLASS_NAME, A.KEY_DATE) AS SUM_QTY
            ,SUM(CHILD_QTY) OVER(PARTITION BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.PARENT_ITEM_ID, A.PARENT_ITEM_CLASS_NAME, A.CHILD_ITEM_ID, A.KEY_DATE) AS CHILD_QTY
            ,A.KEY_DATE, A.INSERT_TIME  -- kimcd add 2017-01-13
      FROM (
            SELECT  A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID 
                  ,A.PARENT_ITEM_ID, D.ITEM_NAME AS PARENT_ITEM_NAME, D.ITEM_CLASS_NAME AS PARENT_ITEM_CLASS_NAME, D.MATERIAL_CLASS_NAME AS PARENT_METERIAL_CLASS_NAME,  A.PARENT_QTY, A.PARENT_UOM, A.ALT_ID, A.ALT_PRIORITY 
                  ,A.CHILD_ITEM_ID, B.ITEM_NAME AS CHILD_ITEM_NAME, B.ITEM_CLASS AS CHILD_ITEM_CLASS, C.CLASS_NAME AS CHILD_ITEM_CLASS_NAME
                  , (CASE WHEN C.LEVEL_2_NAME = 'SLURRY' THEN C.LEVEL_3_NAME ELSE C.LEVEL_2_NAME END) AS LEVEL_2_NAME, B.MATERIAL_CLASS_NAME, A.CHILD_QTY, A.CHILD_UOM, C.USE_FLAG
                  --, A.BOM_VERSION_ID, A.KEY_DATE, A.EFF_START_DATE, A.EFF_END_DATE
                  ,A.KEY_DATE, A.INSERT_TIME -- kimcd add 2017-01-13
            FROM SCM_BOM_M A(NOLOCK)
            INNER HASH JOIN SCM_ITEM_M B(NOLOCK)
            ON A.COMPANY_ID = B.COMPANY_ID
            AND A.DIVISION_ID = B.DIVISION_ID
            AND A.SITE_ID = B.SITE_ID
            AND A.CHILD_ITEM_ID = B.ITEM_ID
            AND B.ACTIVE_FLAG = 'Y'
            INNER HASH JOIN SCM_ITEM_CLASS_M C(NOLOCK)
            ON B.ITEM_CLASS = C.CLASS_ID
            AND C.LEVEL_2_CODE != 'RSV'
            AND C.USE_FLAG = 'Y'
            INNER HASH JOIN SCM_ITEM_M D(NOLOCK)
            ON A.COMPANY_ID = D.COMPANY_ID
            AND A.DIVISION_ID = D.DIVISION_ID
            AND A.SITE_ID = D.SITE_ID
            AND A.PARENT_ITEM_ID = D.ITEM_ID
            INNER HASH JOIN SCM_ITEM_CLASS_M E(NOLOCK)
            ON D.ITEM_CLASS = E.CLASS_ID
            AND E.USE_FLAG = 'Y'
            AND E.LEVEL_2_CODE = 'ASL'
            WHERE 1=1
            --AND (C.LEVEL_2_NAME LIKE '%ACTIVE MATERIAL' OR C.LEVEL_2_NAME = 'CONDUCTING MATERIAL' OR C.LEVEL_2_NAME = 'BINDER')
            AND A.EFF_END_DATE > GETDATE()
            AND (A.ALT_PRIORITY IS NULL OR A.ALT_PRIORITY = 1)
           ) A
     ) X
