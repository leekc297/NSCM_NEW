CREATE VIEW [dbo].[FP_LINE_MASTER_MANAGEMENT_V]
AS
		SELECT 	  A.*, B.USER_ID_1, B.USER_ID_2, B.USER_ID_3, B.USER_ID_4, B.USER_ID_5, CASE WHEN ISNULL(B.CONFIRM_FLAG, 'N') = 'N' THEN NULL ELSE B.CONFIRM_FLAG END AS CONFIRM_FLAG
		FROM 	(
				SELECT 	  A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.LINE_ID, A.OPERATION_ID, A.ELECTRODE_TYPE
						, B.LOSS_CODE, B.CATEGORY, B.LOSS_NAME
				FROM 	SCM_LINE_M A,
						(
						SELECT 	A.SEGMENT1 AS LOSS_CODE, A.ATTRIBUTE1 AS CATEGORY, A.ATTRIBUTE2 AS LOSS_NAME, A.SORT_ORDER
						FROM 	SCM_SYS_LOOKUP_VALUE A
						WHERE 	1=1
						AND 	A.LOOKUP_TYPE_CODE = 'LOSS_TYPE_DEFINITION'
						) B,
						FP_INSTANCE_OPERATION_V C
				WHERE 	1=1
				AND 	A.ACTIVE_FLAG = 'Y'
				AND 	A.COMPANY_ID = C.COMPANY_ID
				AND 	A.DIVISION_ID = C.DIVISION_ID
				AND 	A.SITE_ID = C.SITE_ID
				AND 	A.OPERATION_ID = C.OPERATION_ID
				) A
				LEFT OUTER JOIN SCM_MASTER_MANAGER_M B
				ON 	1=1
				AND A.COMPANY_ID = B.COMPANY_ID
				AND A.DIVISION_ID = B.DIVISION_ID
				AND A.SITE_ID = B.SITE_ID
				AND A.FACTORY_ID = B.FACTORY_ID
				AND A.LINE_ID = B.LINE_ID
				AND A.ELECTRODE_TYPE = B.ELECTRODE_TYPE
		WHERE 	1=1	
