CREATE VIEW [dbo].[SCM_PDS_MATERIAL_V]
AS
SELECT 	A.COMPANY_ID,  A.DIVISION_ID, A.SITE_ID, A.PLANT_ID,
--		A.SLURRY_ITEM_ID, 
		A.PMIX_ITEM_ID, A.MATERIAL_ITEM_ID,
		A.CLASS_NAME,
		A.CATEGORY + ' ' +
		CAST(RANK() OVER (PARTITION BY A.SITE_ID, A.DIVISION_ID, A.PLANT_ID, A.PMIX_ITEM_ID, A.CLASS_NAME  order by A.CHILD_QTY DESC) AS CHAR(10)) AS UI_COLUMN,
		A.DESCRIPTION, ISNULL(B.BATCH_ID, A.PMIX_ITEM_ID) AS BATCH_ID
FROM (
SELECT 	DISTINCT A.COMPANY_ID,  A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, 
--		A.PARENT_ITEM_ID AS SLURRY_ITEM_ID,
		A.PARENT_ITEM_ID  AS  PMIX_ITEM_ID, 
		A.CHILD_ITEM_ID  AS  MATERIAL_ITEM_ID, A.CHILD_QTY,
--		F.LEVEL_1_NAME, 
		E.LEVEL_2_NAME AS CLASS_NAME,
		G.DESCRIPTION,
		E.LEVEL_2_NAME AS CATEGORY
FROM 	SCM_BOM_M A
		LEFT OUTER JOIN SCM_ITEM_PLM_DESC_M G
		ON A.CHILD_ITEM_ID = G.ITEM_ID
		AND G.USE_YN = 'Y',
		SCM_ITEM_M B,
		SCM_ITEM_CLASS_M C,
		SCM_ITEM_M D,
		SCM_ITEM_CLASS_M E
WHERE 	1=1
AND 	A.EFF_END_DATE >= GETDATE()
AND 	A.ACTIVE_FLAG = 'Y'
AND 	A.SITE_ID = B.SITE_ID
AND 	A.DIVISION_ID = B.DIVISION_ID
AND 	A.PARENT_ITEM_ID = B.ITEM_ID
AND 	B.ITEM_CLASS = C.CLASS_ID
AND 	C.LEVEL_3_NAME = 'Pre Dispersion Slurry'
AND 	A.SITE_ID = D.SITE_ID
AND 	A.DIVISION_ID = D.DIVISION_ID
AND 	A.CHILD_ITEM_ID = D.ITEM_ID
AND 	D.ITEM_CLASS = E.CLASS_ID
AND 	E.LEVEL_2_NAME IN ('Solvent','Binder','Conducting Material')
) A
LEFT OUTER JOIN SCM_BATCH_M B
ON 	1=1
AND 	A.COMPANY_ID = B.COMPANY_ID
AND 	A.DIVISION_ID = B.DIVISION_ID
AND 	A.SITE_ID = B.SITE_ID
AND		A.PLANT_ID = B.PLANT_ID
AND 	A.PMIX_ITEM_ID = B.ITEM_ID
