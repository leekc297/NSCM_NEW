	CREATE TABLE #TMP_KEY_NAME_TO_FIND (
	KEY_NAME_A [nvarchar] (40) NOT NULL,
	KEY_TYPE_A [nvarchar] (40) NOT NULL
	)
	CREATE TABLE #SEG_LIST (
	KEY_NAME_A [nvarchar] (40) NOT NULL,
