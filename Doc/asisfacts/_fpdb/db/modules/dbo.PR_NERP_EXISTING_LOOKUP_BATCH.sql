	IF OBJECT_ID('tempdb..#SEG_LIST') IS NOT NULL
	BEGIN drop table SEG_LIST  END

	IF OBJECT_ID('tempdb..#TMP_SCM_SYS_LOOKUP_VALUE') IS NOT NULL
	BEGIN drop table TMP_SCM_SYS_LOOKUP_VALUE  END

	IF OBJECT_ID('tempdb..#TMP_KEY_NAME_TO_FIND') IS NOT NULL
