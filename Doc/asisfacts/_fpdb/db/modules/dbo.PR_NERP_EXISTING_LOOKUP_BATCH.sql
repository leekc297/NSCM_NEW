			,[SEGMENT1]
			,[SEGMENT2]
			,[SEGMENT3]
			,[SEGMENT4]
			,[SEGMENT5]
			,[SORT_ORDER]
			,[ACTIVE_FLAG]
			,[VALUE_DESCRIPTION]
			,[CREATE_USER_ID]
			,[CREATE_DATE]
			,[MODIFY_USER_ID]
			,[MODIFY_DATE]
			,[ATTRIBUTE1]
			,[ATTRIBUTE2]
			,[ATTRIBUTE3]
			,[ATTRIBUTE4]
			,[ATTRIBUTE5]
			,[ATTRIBUTE6]
			,[ATTRIBUTE7]
			,[ATTRIBUTE8]
			,[ATTRIBUTE9]
			,[ATTRIBUTE10]
			,[ATTRIBUTE11]
			,[ATTRIBUTE12]
			,[ATTRIBUTE13]
			,[ATTRIBUTE14]
			,[ATTRIBUTE15]
			,[PLANT_ID]
			from (select [LOOKUP_TYPE_CODE]
			,[SEGMENT1]
			,[SEGMENT2]
			,[SEGMENT3]
			,[SEGMENT4]
			,[SEGMENT5]
			,MAX([SORT_ORDER]) AS [SORT_ORDER]
			,MAX([ACTIVE_FLAG]) AS [ACTIVE_FLAG]
			,MAX([VALUE_DESCRIPTION]) AS [VALUE_DESCRIPTION]
			,MAX([CREATE_USER_ID]) AS [CREATE_USER_ID]
			,MAX([CREATE_DATE]) AS [CREATE_DATE]
