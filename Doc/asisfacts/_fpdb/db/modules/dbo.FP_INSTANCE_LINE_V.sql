CREATE   VIEW [dbo].[FP_INSTANCE_LINE_V]
AS		
-- 추후 로직 보완
SELECT 'KR_FORM_FW' AS INSTANCE_ID, 'HQ00' AS COMPANY_ID, 'A001' AS SITE_ID, '81' AS DIVISION_ID, 'HQ07' AS PLANT_ID, 'A2' AS FACTORY_ID
		, 'B1000' AS OPERATION_ID, 'A2AP1' AS LINE_ID, '-' AS ELECTRODE_TYPE, 'Automotive' AS MODEL_TYPE, NULL AS LINE_SETUP_GROUP_ID
UNION ALL
SELECT 	DISTINCT ISNULL(D.INSTANCE_ID, B.INSTANCE_ID) AS INSTANCE_ID, 
--		B.INSTANCE_ID, C.INSTANCE_ID, D.INSTANCE_ID, 
		A.COMPANY_ID, A.SITE_ID, A.DIVISION_ID, A.PLANT_ID, A.FACTORY_ID, A.OPERATION_ID, A.LINE_ID, A.ELECTRODE_TYPE, A.MODEL_TYPE, A.LINE_SETUP_GROUP_ID 
FROM 	SCM_LINE_M A WITH(NOLOCK)
		LEFT OUTER JOIN (SELECT 	SEGMENT1 AS INSTANCE_ID, SEGMENT2 AS ORG_INSTANCE_ID, SEGMENT3 AS LINE_ID 
						 FROM 	SCM_SYS_LOOKUP_VALUE WITH(NOLOCK)
						 WHERE 	1=1
						 AND 	LOOKUP_TYPE_CODE = 'INSTANCE_SPLIT_LINE_DEFINITION'
						 AND 	ACTIVE_FLAG = 'Y'
						) D
		ON 	1=1
		AND A.LINE_ID = D.LINE_ID
		LEFT OUTER JOIN FP_INSTANCE_FACTORY_M E WITH(NOLOCK)
		ON 	1=1
		AND A.FACTORY_ID = E.FACTORY_ID
		AND E.ACTIVE_FLAG  = 'Y',
		FP_INSTANCE_OPERATION_V B,
		(SELECT 	SEGMENT1 AS INSTANCE_ID, SEGMENT2 AS ORG_INSTANCE_ID, SEGMENT3 AS LINE_ID 
						 FROM 	SCM_SYS_LOOKUP_VALUE WITH(NOLOCK)
						 WHERE 	1=1
						 AND 	LOOKUP_TYPE_CODE = 'INSTANCE_SPLIT_LINE_DEFINITION'
						 AND 	ACTIVE_FLAG = 'Y'
						) C
WHERE 	1=1
AND 	A.ACTIVE_FLAG = 'Y'
AND 	A.COMPANY_ID = B.COMPANY_ID
AND 	A.SITE_ID = B.SITE_ID
AND 	A.DIVISION_ID = B.DIVISION_ID
AND 	A.OPERATION_ID = B.OPERATION_ID
AND 	ISNULL(A.MODEL_TYPE,'-') = ISNULL(B.MODEL_TYPE,'-')
AND 	(B.INSTANCE_ID = E.INSTANCE_ID OR C.INSTANCE_ID = E.INSTANCE_ID OR D.INSTANCE_ID = E.INSTANCE_ID)
AND 	((B.INSTANCE_ID != C.INSTANCE_ID AND D.INSTANCE_ID IS NULL) OR (B.INSTANCE_ID = C.INSTANCE_ID AND B.INSTANCE_ID = D.INSTANCE_ID));