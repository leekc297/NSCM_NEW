CREATE VIEW [dbo].[FP_FORMATION_LT_V]
AS
SELECT 	COMPANY_ID, SITE_ID, DIVISION_ID, PLANT_ID, ITEM_ID, NICK_NAME, FACTORY_ID, SHORTER_OPERATION_ID, LINE_ID
		, MAX(BEFORE_DEGAS_ROUTE_ID) AS BEFORE_DEGAS_ROUTE_ID
		, MAX(BEFORE_DEGAS_ROUTE_DESCRIPTION) AS BEFORE_DEGAS_ROUTE_DESCRIPTION
		, MAX(BEFORE_DEGAS_ROUTE_TYPE) AS BEFORE_DEGAS_ROUTE_TYPE
		, MAX(BEFORE_DEGAS_LT) AS BEFORE_DEGAS_LT
		, MAX(BEFORE_DEGAS_NEXT_ROUTE_ID) AS BEFORE_DEGAS_NEXT_ROUTE_ID
		, MAX(AFTER_DEGAS_ROUTE_ID) AS AFTER_DEGAS_ROUTE_ID		
		, MAX(AFTER_DEGAS_ROUTE_DESCRIPTION) AS AFTER_DEGAS_ROUTE_DESCRIPTION		
		, MAX(AFTER_DEGAS_ROUTE_TYPE) AS AFTER_DEGAS_ROUTE_TYPE		
		, MAX(AFTER_DEGAS_LT) AS AFTER_DEGAS_LT
		, MAX(AFTER_DEGAS_NEXT_ROUTE_ID) AS AFTER_DEGAS_NEXT_ROUTE_ID
FROM (
			SELECT 	A.COMPANY_ID, A.SITE_ID, A.DIVISION_ID, A.PLANT_ID, A.ITEM_ID, B.NICK_NAME, A.FACTORY_ID, A.LINE_ID 
					, CASE WHEN ROUTE_TYPE = 'D' THEN MAX(ROUTE_ID) ELSE NULL END AS BEFORE_DEGAS_ROUTE_ID
					, CASE WHEN ROUTE_TYPE = 'C' THEN MAX(ROUTE_ID) ELSE NULL END AS AFTER_DEGAS_ROUTE_ID
					, CASE WHEN ROUTE_TYPE = 'D' THEN MAX(NEXT_ROUTE_ID) ELSE NULL END AS BEFORE_DEGAS_NEXT_ROUTE_ID
					, CASE WHEN ROUTE_TYPE = 'C' THEN MAX(NEXT_ROUTE_ID) ELSE NULL END AS AFTER_DEGAS_NEXT_ROUTE_ID
					, CASE WHEN ROUTE_TYPE = 'D' THEN MAX(ROUTE_DESCRIPTION) ELSE NULL END AS BEFORE_DEGAS_ROUTE_DESCRIPTION
					, CASE WHEN ROUTE_TYPE = 'C' THEN MAX(ROUTE_DESCRIPTION) ELSE NULL END AS AFTER_DEGAS_ROUTE_DESCRIPTION
					, CASE WHEN ROUTE_TYPE = 'D' THEN ROUTE_TYPE ELSE NULL END AS BEFORE_DEGAS_ROUTE_TYPE
					, CASE WHEN ROUTE_TYPE = 'C' THEN ROUTE_TYPE ELSE NULL END AS AFTER_DEGAS_ROUTE_TYPE
					, CASE WHEN ROUTE_TYPE = 'D' THEN SUM(STANDARD_LT) ELSE 0 END AS BEFORE_DEGAS_LT
					, CASE WHEN ROUTE_TYPE = 'C' THEN SUM(STANDARD_LT) ELSE 0 END AS AFTER_DEGAS_LT
					, CASE WHEN B.FORMATION_FLOW_ID = 'F6000' THEN 'F6000'
						   WHEN B.FORMATION_FLOW_ID = 'F4000F5500' THEN 'F5500'
						   ELSE NULL END AS SHORTER_OPERATION_ID
			FROM 	SCM_AGING_ITEM_FLOW_M A  WITH(NOLOCK),
						SCM_ITEM_M B  WITH(NOLOCK)
			WHERE 	1=1
			AND 	A.COMPANY_ID = B.COMPANY_ID
			AND 	A.SITE_ID = B.SITE_ID
			AND 	A.DIVISION_ID = B.DIVISION_ID
			AND 	A.ITEM_ID = B.ITEM_ID
			AND 	B.ACTIVE_FLAG = 'Y'
	--		AND 	A.SITE_ID = 'A001'
	--		AND 	A.DIVISION_ID IN ('81','82')
			AND 	DEFAULT_ROUTE = 'Y'
	--		AND 	B.FORMATION_FLOW_ID IS NULL
			AND   NOT EXISTS (
										SELECT 1
										FROM	(
													SELECT COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID
													FROM FP_INSTANCE_INFO_V
													-- 하드코딩 전환('G630','G450')
													WHERE COMPANY_ID IN (SELECT SEGMENT2 FROM SCM_CODE_LOOKUP_VALUE WITH(NOLOCK) WHERE LOOKUP_TYPE_CODE='FP_FORMATION_LT_V' AND SEGMENT1  = '0' AND ACTIVE_FLAG='Y')
													GROUP BY COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID
												) SA
										WHERE 1=1
										AND	SA.COMPANY_ID = A.COMPANY_ID
										AND	SA.DIVISION_ID = A.DIVISION_ID
										AND	SA.SITE_ID = A.SITE_ID
										AND	SA.PLANT_ID = A.PLANT_ID
									)
			AND  EXISTS (	-- ROUTE : LINE 는 1:1 이며 복수일 경우 MIN 으로 처리 2020-01-09 by cys
							SELECT 1
							FROM	(
										SELECT 	COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, FACTORY_ID, ITEM_ID, LINE_ID, ROUTE_TYPE, MIN(ROUTE_ID) AS ROUTE_ID
										FROM 	SCM_AGING_ITEM_FLOW_M	WITH(NOLOCK)							
										WHERE  ROUTE_TYPE IN ( 'C', 'D')
										AND    DEFAULT_ROUTE = 'Y'   
										GROUP BY COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, FACTORY_ID, ITEM_ID, LINE_ID, ROUTE_TYPE
									) B
							WHERE	A.COMPANY_ID	= B.COMPANY_ID
							AND		A.DIVISION_ID	= B.DIVISION_ID
							AND		A.SITE_ID		= B.SITE_ID
							AND		A.PLANT_ID		= B.PLANT_ID
							AND		A.FACTORY_ID	= B.FACTORY_ID	
							AND		A.ITEM_ID		= B.ITEM_ID	
							AND		A.LINE_ID		= B.LINE_ID
							AND		A.ROUTE_ID		= B.ROUTE_ID
							AND		A.ROUTE_TYPE	= B.ROUTE_TYPE
						)
			GROUP BY A.COMPANY_ID, A.SITE_ID, A.DIVISION_ID, A.PLANT_ID, A.ITEM_ID, B.NICK_NAME, A.FACTORY_ID, A.LINE_ID, A.ROUTE_TYPE,B.FORMATION_FLOW_ID		
		) A
WHERE 	1=1		
--AND 	ISNULL(BEFORE_DEGAS_NEXT_ROUTE_ID,'xxx') != ISNULL(AFTER_DEGAS_NEXT_ROUTE_ID,'xxx')
GROUP BY COMPANY_ID, SITE_ID, DIVISION_ID, PLANT_ID, ITEM_ID, NICK_NAME, FACTORY_ID, SHORTER_OPERATION_ID, LINE_ID
UNION ALL
SELECT 	COMPANY_ID, SITE_ID, DIVISION_ID, PLANT_ID, ITEM_ID, NICK_NAME, FACTORY_ID, SHORTER_OPERATION_ID, LINE_ID
			, MAX(BEFORE_DEGAS_ROUTE_ID) AS BEFORE_DEGAS_ROUTE_ID
			, MAX(BEFORE_DEGAS_ROUTE_DESCRIPTION) AS BEFORE_DEGAS_ROUTE_DESCRIPTION
			, MAX(BEFORE_DEGAS_ROUTE_TYPE) AS BEFORE_DEGAS_ROUTE_TYPE
			, MAX(BEFORE_DEGAS_LT) AS BEFORE_DEGAS_LT
			, MAX(BEFORE_DEGAS_NEXT_ROUTE_ID) AS BEFORE_DEGAS_NEXT_ROUTE_ID
			, MAX(AFTER_DEGAS_ROUTE_ID) AS AFTER_DEGAS_ROUTE_ID		
			, MAX(AFTER_DEGAS_ROUTE_DESCRIPTION) AS AFTER_DEGAS_ROUTE_DESCRIPTION		
			, MAX(AFTER_DEGAS_ROUTE_TYPE) AS AFTER_DEGAS_ROUTE_TYPE		
			, MAX(AFTER_DEGAS_LT) AS AFTER_DEGAS_LT
			, MAX(AFTER_DEGAS_NEXT_ROUTE_ID) AS AFTER_DEGAS_NEXT_ROUTE_ID
FROM (
			SELECT 	A.COMPANY_ID, A.SITE_ID, A.DIVISION_ID, A.PLANT_ID, A.ITEM_ID, B.NICK_NAME, A.FACTORY_ID, A.LINE_ID 
						, CASE WHEN ROUTE_TYPE = 'D' THEN MAX(ROUTE_ID) ELSE NULL END AS BEFORE_DEGAS_ROUTE_ID
						, CASE WHEN ROUTE_TYPE = 'C' THEN MAX(ROUTE_ID) ELSE NULL END AS AFTER_DEGAS_ROUTE_ID
						, CASE WHEN ROUTE_TYPE = 'D' THEN MAX(NEXT_ROUTE_ID) ELSE NULL END AS BEFORE_DEGAS_NEXT_ROUTE_ID
						, CASE WHEN ROUTE_TYPE = 'C' THEN MAX(NEXT_ROUTE_ID) ELSE NULL END AS AFTER_DEGAS_NEXT_ROUTE_ID
						, CASE WHEN ROUTE_TYPE = 'D' THEN MAX(ROUTE_DESCRIPTION) ELSE NULL END AS BEFORE_DEGAS_ROUTE_DESCRIPTION
						, CASE WHEN ROUTE_TYPE = 'C' THEN MAX(ROUTE_DESCRIPTION) ELSE NULL END AS AFTER_DEGAS_ROUTE_DESCRIPTION
						, CASE WHEN ROUTE_TYPE = 'D' THEN ROUTE_TYPE ELSE NULL END AS BEFORE_DEGAS_ROUTE_TYPE
						, CASE WHEN ROUTE_TYPE = 'C' THEN ROUTE_TYPE ELSE NULL END AS AFTER_DEGAS_ROUTE_TYPE
						, CASE WHEN ROUTE_TYPE = 'D' THEN SUM(STANDARD_LT) ELSE 0 END AS BEFORE_DEGAS_LT
						, CASE WHEN ROUTE_TYPE = 'C' THEN SUM(STANDARD_LT) ELSE 0 END AS AFTER_DEGAS_LT
						, CASE WHEN B.FORMATION_FLOW_ID = 'F6000' THEN 'F6000'
								 WHEN B.FORMATION_FLOW_ID = 'F4000F5500' THEN 'F5500'
								 WHEN T.INT = 1 AND B.FORMATION_FLOW_ID = 'F4000F6000' THEN 'F6000'
						 		 WHEN T.INT = 2 AND B.FORMATION_FLOW_ID = 'F4000F6000' THEN 'F4000'
								 ELSE NULL END AS SHORTER_OPERATION_ID
						, T.INT
			FROM 	 SCM_AGING_ITEM_FLOW_M A WITH(NOLOCK)
						, SCM_ITEM_M B  WITH(NOLOCK)
						, COPYT T WITH(NOLOCK)
			WHERE 	1=1
			AND	T.INT < 3
			AND 	A.COMPANY_ID = B.COMPANY_ID
			AND 	A.DIVISION_ID	= B.DIVISION_ID
			AND 	A.SITE_ID			= B.SITE_ID
			AND 	A.ITEM_ID		= B.ITEM_ID
			AND 	B.ACTIVE_FLAG	= 'Y'
			AND 	DEFAULT_ROUTE = 'Y'
			AND   EXISTS (
								SELECT 1
								FROM	(
											SELECT	COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID
											FROM		FP_INSTANCE_INFO_V
											-- 하드코딩 전환('G630','G450')
											WHERE	COMPANY_ID IN (SELECT SEGMENT2 FROM SCM_CODE_LOOKUP_VALUE WITH(NOLOCK) WHERE LOOKUP_TYPE_CODE='FP_FORMATION_LT_V' AND SEGMENT1  = '0' AND ACTIVE_FLAG='Y')
											GROUP BY COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID
										) SA
								WHERE 1=1
								AND	SA.COMPANY_ID = A.COMPANY_ID
								AND	SA.DIVISION_ID	 = A.DIVISION_ID
								AND	SA.SITE_ID		 = A.SITE_ID
								AND	SA.PLANT_ID		 = A.PLANT_ID
							)
			AND  EXISTS (	-- ROUTE : LINE 는 1:1 이며 복수일 경우 MIN 으로 처리 2020-01-09 by cys
							SELECT 1
							FROM	(
										SELECT 	COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, FACTORY_ID, ITEM_ID, LINE_ID, ROUTE_TYPE, MIN(ROUTE_ID) AS ROUTE_ID
										FROM 	SCM_AGING_ITEM_FLOW_M	WITH(NOLOCK)							
										WHERE  ROUTE_TYPE IN ( 'C', 'D')
										AND    DEFAULT_ROUTE = 'Y'   
										GROUP BY COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, FACTORY_ID, ITEM_ID, LINE_ID, ROUTE_TYPE
									) B
							WHERE	A.COMPANY_ID	= B.COMPANY_ID
							AND		A.DIVISION_ID	= B.DIVISION_ID
							AND		A.SITE_ID		= B.SITE_ID
							AND		A.PLANT_ID		= B.PLANT_ID
							AND		A.FACTORY_ID	= B.FACTORY_ID	
							AND		A.ITEM_ID		= B.ITEM_ID	
							AND		A.LINE_ID		= B.LINE_ID
							AND		A.ROUTE_ID		= B.ROUTE_ID
							AND		A.ROUTE_TYPE	= B.ROUTE_TYPE
						)
			GROUP BY A.COMPANY_ID, A.SITE_ID, A.DIVISION_ID, A.PLANT_ID, A.ITEM_ID, B.NICK_NAME, A.FACTORY_ID, A.LINE_ID, A.ROUTE_TYPE,B.FORMATION_FLOW_ID, T.INT
		) A
WHERE 	1=1		
GROUP BY COMPANY_ID, SITE_ID, DIVISION_ID, PLANT_ID, ITEM_ID, NICK_NAME, FACTORY_ID, SHORTER_OPERATION_ID, LINE_ID
