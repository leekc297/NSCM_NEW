CREATE VIEW [dbo].[FP_CONV_CALC_VALIDATION_V]
AS 
WITH  CONV_CALC_M AS (
					SELECT 	A.SITE_ID, A.DIVISION_ID, A.FACTORY_ID, A.MODEL_ID, A.ITEM_ID, 
							MAX(CELL_BATCH) AS CELL_BATCH, MAX(JR_CELL_M) AS JR_CELL_M, MAX(JR_M_BATCH) AS JR_M_BATCH, MAX(LANE_QTY) AS LANE_QTY, MAX(PC_CELL_M) AS PC_CELL_M, MAX(PC_M_BATCH) AS PC_M_BATCH
					FROM 	(SELECT 	SITE_ID, DIVISION_ID, FACTORY_ID, MODEL_ID, ITEM_ID, NULL AS CELL_BATCH, VALUE AS JR_CELL_M, NULL AS JR_M_BATCH, NULL AS LANE_QTY, NULL AS PC_CELL_M, NULL AS PC_M_BATCH
							FROM 	SCM_ITEM_CONV_CALC_M
							WHERE 	1=1
							AND 	OPERATION = 'E2000'
							AND 	MAX_VER_FLAG = 'Y'
							AND		CATEGORY =  'Jumbo Roll (cell/m)'
							UNION ALL
							SELECT 	SITE_ID, DIVISION_ID, FACTORY_ID,  MODEL_ID, ITEM_ID, NULL AS CELL_BATCH, NULL AS JR_CELL_M, VALUE AS JR_M_BATCH, NULL AS LANE_QTY, NULL AS PC_CELL_M, NULL AS PC_M_BATCH
							FROM 	SCM_ITEM_CONV_CALC_M
							WHERE 	1=1
							AND 	OPERATION = 'E2000'
							AND 	MAX_VER_FLAG = 'Y'
							AND		CATEGORY =  'Jumbo Roll (m/batch)'	
							UNION ALL
							SELECT 	SITE_ID, DIVISION_ID, FACTORY_ID,  MODEL_ID, ITEM_ID, VALUE AS CELL_BATCH, NULL AS JR_CELL_M, NULL AS JR_M_BATCH, NULL AS LANE_QTY, NULL AS PC_CELL_M, NULL AS PC_M_BATCH
							FROM 	SCM_ITEM_CONV_CALC_M
							WHERE 	1=1
							AND 	OPERATION = 'E2000'
							AND 	MAX_VER_FLAG = 'Y'
							AND		CATEGORY =  'Cell/batch'	
							UNION ALL
							SELECT 	SITE_ID, DIVISION_ID, FACTORY_ID,  MODEL_ID, ITEM_ID, NULL AS CELL_BATCH, NULL AS JR_CELL_M, NULL AS JR_M_BATCH, NULL AS LANE_QTY, NULL AS PC_CELL_M, VALUE AS PC_M_BATCH
							FROM 	SCM_ITEM_CONV_CALC_M
							WHERE 	1=1
							AND 	OPERATION = 'E2000'
							AND 	MAX_VER_FLAG = 'Y'
							AND		CATEGORY =  'Pancake (m/batch)'	
							UNION ALL
							SELECT 	SITE_ID, DIVISION_ID, FACTORY_ID,  MODEL_ID, ITEM_ID, NULL AS CELL_BATCH, NULL AS JR_CELL_M, NULL AS JR_M_BATCH, NULL AS LANE_QTY, VALUE AS PC_CELL_M, NULL AS PC_M_BATCH 
							FROM 	SCM_ITEM_CONV_CALC_M
							WHERE 	1=1
							AND 	OPERATION = 'E2000'
							AND 	MAX_VER_FLAG = 'Y'
							AND		CATEGORY =  'Pancake (cell/m)'	
							UNION ALL
							SELECT 	SITE_ID, DIVISION_ID, FACTORY_ID,  MODEL_ID, ITEM_ID, NULL AS 'CELL_BATCH', NULL AS 'JR_CELL_M', NULL AS 'JR_M_BATCH', VALUE AS 'LANE_QTY', NULL AS 'PC_CELL_M', NULL AS 'PC_M_BATCH'
							FROM 	SCM_ITEM_CONV_CALC_M
							WHERE 	1=1
							AND 	OPERATION = 'E2000'
							AND 	MAX_VER_FLAG = 'Y'
							AND		CATEGORY =  'Lane Number'
							) A
					WHERE 	1=1
					GROUP BY A.SITE_ID, A.DIVISION_ID, A.FACTORY_ID, A.MODEL_ID, A.ITEM_ID
					),
	 ITEM_ASSIGN_LANE_M AS (SELECT 	A.*, B.LANE_QTY_M
					 FROM 	SCM_ITEM_LINE_ASSIGN_M A
							LEFT OUTER JOIN (SELECT 	SITE_ID, DIVISION_ID, FACTORY_ID, ITEM_ID, LANE_QTY AS LANE_QTY_M --MAX(LANE_QTY) AS LANE_QTY_M
							 				 FROM 	SCM_ITEM_LANE_M 
							 				 WHERE 	1=1
							 				 AND 	ACTIVE_FLAG = 'Y'
--							 				 GROUP BY SITE_ID, DIVISION_ID, FACTORY_ID, ITEM_ID
							 				 ) B
							ON 	A.SITE_ID = B.SITE_ID
							AND A.DIVISION_ID = B.DIVISION_ID
							AND A.FACTORY_ID = B.FACTORY_ID
							AND A.ITEM_ID = B.ITEM_ID
					 WHERE 	1=1
					 AND 	A.OPERATION_ID = 'E2000'
					 AND 	A.ACTIVE_FLAG = 'Y'
					 AND 	A.PRIORITY NOT IN (0,9)
					 AND 	A.LANE_QTY IS NOT NULL
					 AND 	A.LANE_QTY != 0)					 
SELECT 	DISTINCT A.SITE_ID, A.DIVISION_ID, A.FACTORY_ID, D.APPLIED_MODEL, A.ITEM_ID, B.MODEL_ID, 
		B.CELL_BATCH, 
		B.JR_CELL_M * B.JR_M_BATCH AS CELL_BATCH_JR_CAL,
		B.PC_CELL_M * B.PC_M_BATCH AS CELL_BATCH_PC_CAL,
		B.JR_CELL_M, B.JR_M_BATCH,		
		B.LANE_QTY, 
		B.PC_CELL_M, B.PC_M_BATCH, A.LANE_QTY_M, A.LANE_QTY AS LANE_QTY_A,
		CASE WHEN B.LANE_QTY != A.LANE_QTY_M THEN 'X' ELSE 'O' END AS LANE_VALI_1,
		CASE WHEN B.LANE_QTY != A.LANE_QTY THEN 'X' ELSE 'O' END AS LANE_VALI_2,
		CASE WHEN B.JR_CELL_M * B.JR_M_BATCH IS NULL OR B.JR_CELL_M * B.JR_M_BATCH = 0 THEN '0' ELSE B.CELL_BATCH / (B.JR_CELL_M * B.JR_M_BATCH) * 100 END AS JR_VALI,
		CASE WHEN B.JR_CELL_M * B.JR_M_BATCH IS NULL OR B.JR_CELL_M * B.JR_M_BATCH = 0 THEN 'NONE'
			 WHEN B.CELL_BATCH / (B.JR_CELL_M * B.JR_M_BATCH) * 100 > 110 THEN 'OVER'
			 WHEN B.CELL_BATCH / (B.JR_CELL_M * B.JR_M_BATCH) * 100 < 90 THEN 'LESS'
			 ELSE 'NORMAL' END VALI3
FROM 	ITEM_ASSIGN_LANE_M A
		LEFT OUTER JOIN CONV_CALC_M B
		ON 		1=1
		AND 	A.SITE_ID = B.SITE_ID
		AND 	A.DIVISION_ID = B.DIVISION_ID
		AND 	A.FACTORY_ID = B.FACTORY_ID
		AND 	A.ITEM_ID = B.ITEM_ID,
		(SELECT 	DISTINCT A.SITE_ID, A.DIVISION_ID, A.ITEM_ID--* --DISTINCT DPP_PLAN_ID
		FROM 	FP_DAILY_NET_DEMAND_H A,
				(SELECT A.INSTANCE_ID, A.INSTANCE_DATE, A.DIVISION_ID, A.FACTORY_ID
		               , MAX(AMEND_PLAN_ID) AS AMEND_PLAN_ID
		          FROM   FP_RELEASE_PLAN_INFO_H A,
		                 (
		                  SELECT INSTANCE_ID
		                       , DIVISION_ID
		                       , FACTORY_ID
		                       , MAX(INSTANCE_DATE) AS INSTANCE_DATE
		                  FROM   FP_RELEASE_PLAN_INFO_H A
		                  WHERE  A.INSTANCE_DATE <= GETDATE()
		                  GROUP  BY INSTANCE_ID, DIVISION_ID, FACTORY_ID
		                 ) B
		          WHERE  A.INSTANCE_ID    = B.INSTANCE_ID
		          AND    A.INSTANCE_DATE  = B.INSTANCE_DATE
		          AND    A.DIVISION_ID    = B.DIVISION_ID
		          AND    A.FACTORY_ID     = B.FACTORY_ID
		          AND 	 A.INSTANCE_ID LIKE '%E_PRE%'
		          AND 	 A.INSTANCE_ID != 'KR_E_PRE'
		          AND 	 A.FACTORY_ID != 'E1'
		          GROUP  BY A.INSTANCE_ID, A.INSTANCE_DATE, A.DIVISION_ID, A.FACTORY_ID) B
		WHERE 	1=1
		AND 	A.DPP_PLAN_ID = B.AMEND_PLAN_ID) C,
		SCM_ITEM_M D
WHERE 	1=1
AND 	A.SITE_ID = C.SITE_ID
AND 	A.DIVISION_ID = C.DIVISION_ID
AND 	A.ITEM_ID = C.ITEM_ID
AND 	A.FACTORY_ID != 'E1'
AND 	A.SITE_ID = D.SITE_ID
AND 	A.DIVISION_ID = D.DIVISION_ID
AND 	A.ITEM_ID = D.ITEM_ID
AND 	D.ACTIVE_FLAG = 'Y'
