		DECLARE @WORK_AVALIABLE TABLE (TABLE_NAME NVARCHAR(150), PLANT_ID NVARCHAR(150), CNT NVARCHAR(150));

		DECLARE LOOKUP_CURSOR CURSOR FOR
		SELECT * FROM (
		--SELECT DISTINCT T.NAME AS TABLE_NAME, C.NAME AS COLUMN_NAME
		--FROM SYS.TABLES T INNER JOIN SYS.COLUMNS C ON T.OBJECT_ID = C.OBJECT_ID  INNER JOIN SYS.INDEXES I   ON T.OBJECT_ID = I.OBJECT_ID  INNER JOIN SYS.DM_DB_PARTITION_STATS ST   ON T.OBJECT_ID = ST.OBJECT_ID  AND I.INDEX_ID = ST.INDEX_ID WHERE C.NAME LIKE '%COMPANY%'
