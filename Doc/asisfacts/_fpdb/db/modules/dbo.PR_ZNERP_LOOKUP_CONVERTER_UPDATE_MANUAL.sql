CREATE PROCEDURE [dbo].[PR_ZNERP_LOOKUP_CONVERTER_UPDATE_MANUAL]
AS
BEGIN
	--------------------------------------------------
	-- Delete the data to duplecate
	--------------------------------------------------
	BEGIN
		DELETE A FROM SCM_SYS_LOOKUP_VALUE A, (
		SELECT A.LOOKUP_TYPE_CODE, A.SEGMENT1, MAX(A.SEGMENT2) AS SEGMENT2, MAX(A.SEGMENT3) AS SEGMENT3, MAX(A.SEGMENT4) AS SEGMENT4, MAX(A.SEGMENT5) AS SEGMENT5, B.TO_PLANT_ID, COUNT(*) AS CNT  FROM SCM_SYS_LOOKUP_VALUE A
		LEFT JOIN [ZNERP_CONV_MASTER] B
		ON A.SEGMENT2 = B.FROM_PLANT_ID
		AND B.CODETYPE = 'PLANT_ID'
		WHERE LOOKUP_TYPE_CODE = 'SCP_DEMAND_TYPE_MAPPING'
		AND B.TO_PLANT_ID IS NOT NULL
		GROUP BY A.LOOKUP_TYPE_CODE, A.SEGMENT1, B.TO_PLANT_ID
		HAVING COUNT(*) > 1
		) B
		WHERE A.LOOKUP_TYPE_CODE = B.LOOKUP_TYPE_CODE
		AND A.SEGMENT1 = B.SEGMENT1
		AND A.SEGMENT2 = B.SEGMENT2
		AND A.SEGMENT3 = B.SEGMENT3
		AND A.SEGMENT4 = B.SEGMENT4
		AND A.SEGMENT5 = B.SEGMENT5


		DELETE A FROM SCM_SYS_LOOKUP_VALUE A, (
		SELECT A.LOOKUP_TYPE_CODE, A.SEGMENT1, MAX(A.SEGMENT2) AS SEGMENT2, A.SEGMENT3, MAX(A.SEGMENT4) AS SEGMENT4, MAX(A.SEGMENT5) AS SEGMENT5, B.TO_PLANT_ID, COUNT(*) AS CNT  FROM SCM_SYS_LOOKUP_VALUE A
		LEFT JOIN [ZNERP_CONV_MASTER] B
		ON A.SEGMENT5 = B.FROM_PLANT_ID
		AND B.CODETYPE = 'PLANT_ID'
		WHERE LOOKUP_TYPE_CODE = 'PANCAKE_INSTANCE'
		AND B.TO_PLANT_ID IS NOT NULL
		GROUP BY A.LOOKUP_TYPE_CODE, A.SEGMENT1,A.SEGMENT3, B.TO_PLANT_ID
		HAVING COUNT(*) > 1
		) B
		WHERE A.LOOKUP_TYPE_CODE = B.LOOKUP_TYPE_CODE
		AND A.SEGMENT1 = B.SEGMENT1
		AND A.SEGMENT2 = B.SEGMENT2
		AND A.SEGMENT3 = B.SEGMENT3
		AND A.SEGMENT4 = B.SEGMENT4
		AND A.SEGMENT5 = B.SEGMENT5

		DELETE A FROM SCM_SYS_LOOKUP_VALUE A, (
		SELECT A.LOOKUP_TYPE_CODE, MAX(A.SEGMENT1) AS SEGMENT1, MAX(A.SEGMENT2) AS SEGMENT2, MAX(A.SEGMENT3) AS SEGMENT3, MAX(A.SEGMENT4) AS SEGMENT4, MAX(A.SEGMENT5) AS SEGMENT5, B.TO_PLANT_ID, COUNT(*) AS CNT  FROM SCM_SYS_LOOKUP_VALUE A
		LEFT JOIN [ZNERP_CONV_MASTER] B
		ON A.SEGMENT1 = B.FROM_PLANT_ID
		AND B.CODETYPE = 'PLANT_ID'
		WHERE LOOKUP_TYPE_CODE = 'BASIS_START_TIME_PLANT'
		AND B.TO_PLANT_ID IS NOT NULL
		GROUP BY A.LOOKUP_TYPE_CODE, B.TO_PLANT_ID
		HAVING COUNT(*) > 1
		) B
		WHERE A.LOOKUP_TYPE_CODE = B.LOOKUP_TYPE_CODE
		AND A.SEGMENT1 = B.SEGMENT1
		AND A.SEGMENT2 = B.SEGMENT2
		AND A.SEGMENT3 = B.SEGMENT3
		AND A.SEGMENT4 = B.SEGMENT4
		AND A.SEGMENT5 = B.SEGMENT5


		DELETE A FROM SCM_SYS_LOOKUP_VALUE A, (
		SELECT A.LOOKUP_TYPE_CODE, A.SEGMENT1 AS SEGMENT1, A.SEGMENT2 AS SEGMENT2, A.SEGMENT3 AS SEGMENT3, A.SEGMENT4 AS SEGMENT4, MAX(A.SEGMENT5) AS SEGMENT5, B.TO_PLANT_ID, COUNT(*) AS CNT  FROM SCM_SYS_LOOKUP_VALUE A
		LEFT JOIN [ZNERP_CONV_MASTER] B
		ON A.SEGMENT5 = B.FROM_PLANT_ID
		AND B.CODETYPE = 'PLANT_ID'
		WHERE LOOKUP_TYPE_CODE = 'INSTANCE_PANCAKE_VIEW'
		AND B.TO_PLANT_ID IS NOT NULL
		GROUP BY A.LOOKUP_TYPE_CODE, A.SEGMENT1, A.SEGMENT2, A.SEGMENT3, A.SEGMENT4, B.TO_PLANT_ID
		HAVING COUNT(*) > 1
		) B
		WHERE A.LOOKUP_TYPE_CODE = B.LOOKUP_TYPE_CODE
		AND A.SEGMENT1 = B.SEGMENT1
		AND A.SEGMENT2 = B.SEGMENT2
		AND A.SEGMENT3 = B.SEGMENT3
		AND A.SEGMENT4 = B.SEGMENT4
		AND A.SEGMENT5 = B.SEGMENT5


		--SEGMENT2 = Y인것을 남긴다.
		DELETE A FROM SCM_SYS_LOOKUP_VALUE A, (
		SELECT A.LOOKUP_TYPE_CODE, MAX(A.SEGMENT1) AS SEGMENT1, MIN(A.SEGMENT2) AS SEGMENT2, A.SEGMENT3 AS SEGMENT3, A.SEGMENT4 AS SEGMENT4, A.SEGMENT5 AS SEGMENT5, B.TO_PLANT_ID, COUNT(*) AS CNT  FROM SCM_SYS_LOOKUP_VALUE A
		LEFT JOIN [ZNERP_CONV_MASTER] B
		ON A.SEGMENT1 = B.FROM_PLANT_ID
		AND B.CODETYPE = 'PLANT_ID'
		WHERE LOOKUP_TYPE_CODE = 'WIP_LOCATION'
		AND B.TO_PLANT_ID IS NOT NULL
		GROUP BY A.LOOKUP_TYPE_CODE,   A.SEGMENT3, A.SEGMENT4, A.SEGMENT5, B.TO_PLANT_ID
		HAVING COUNT(*) > 1
		) B
		WHERE A.LOOKUP_TYPE_CODE = B.LOOKUP_TYPE_CODE
		AND A.SEGMENT1 = B.SEGMENT1
		AND A.SEGMENT2 = B.SEGMENT2
		AND A.SEGMENT3 = B.SEGMENT3
		AND A.SEGMENT4 = B.SEGMENT4
		AND A.SEGMENT5 = B.SEGMENT5


		DELETE A FROM SCM_SYS_LOOKUP_VALUE A,
		(
		SELECT T.LOOKUP_TYPE_CODE, MIN(T.SEGMENT1) AS SEGMENT1, MIN(T.SEGMENT2) AS SEGMENT2, Y.NEW_SEGMENT1, Y.NEW_SEGMENT2, COUNT(*) AS CNT FROM SCM_SYS_LOOKUP_VALUE T,
		(
		SELECT A.LOOKUP_TYPE_CODE, A.SEGMENT1, B.TO_PLANT_ID AS NEW_SEGMENT1, A.SEGMENT2, B1.TO_PLANT_ID AS NEW_SEGMENT2 FROM SCM_SYS_LOOKUP_VALUE A
		LEFT JOIN [ZNERP_CONV_MASTER] B
		ON A.SEGMENT1 = B.FROM_PLANT_ID
		AND B.CODETYPE = 'PLANT_ID'
		LEFT JOIN [ZNERP_CONV_MASTER] B1
		ON A.SEGMENT2 = B1.FROM_PLANT_ID
		AND B1.CODETYPE = 'PLANT_ID'
		WHERE LOOKUP_TYPE_CODE = 'BOM_LINK_PLANT'
		AND B.TO_PLANT_ID IS NOT NULL
		) Y
		WHERE T.LOOKUP_TYPE_CODE = Y.LOOKUP_TYPE_CODE
		AND T.SEGMENT1 = Y.SEGMENT1
		AND T.SEGMENT2 = Y.SEGMENT2
		GROUP BY  T.LOOKUP_TYPE_CODE, Y.NEW_SEGMENT1, Y.NEW_SEGMENT2
		HAVING COUNT(*) > 1
		) B
		WHERE A.LOOKUP_TYPE_CODE = B.LOOKUP_TYPE_CODE
		AND A.SEGMENT1 = B.SEGMENT1
		AND A.SEGMENT2 = B.SEGMENT2



		DELETE A FROM SCM_SYS_LOOKUP_VALUE A,
		(
		SELECT T.LOOKUP_TYPE_CODE, MIN(T.SEGMENT1) AS SEGMENT1, MIN(T.SEGMENT2) AS SEGMENT2, Y.NEW_SEGMENT1, Y.NEW_SEGMENT2, COUNT(*) AS CNT FROM SCM_SYS_LOOKUP_VALUE T,
		(
		SELECT A.LOOKUP_TYPE_CODE, A.SEGMENT1, B.TO_PLANT_ID AS NEW_SEGMENT1, A.SEGMENT2, B1.TO_PLANT_ID AS NEW_SEGMENT2 FROM SCM_SYS_LOOKUP_VALUE A
		LEFT JOIN [ZNERP_CONV_MASTER] B
		ON A.SEGMENT1 = B.FROM_PLANT_ID
		AND B.CODETYPE = 'PLANT_ID'
		LEFT JOIN [ZNERP_CONV_MASTER] B1
		ON A.SEGMENT2 = B1.FROM_PLANT_ID
		AND B1.CODETYPE = 'PLANT_ID'
		WHERE LOOKUP_TYPE_CODE = 'BOM_LINK_PLANT'
		AND B.TO_PLANT_ID IS NOT NULL
		) Y
		WHERE T.LOOKUP_TYPE_CODE = Y.LOOKUP_TYPE_CODE
		AND T.SEGMENT1 = Y.SEGMENT1
		AND T.SEGMENT2 = Y.SEGMENT2
		GROUP BY  T.LOOKUP_TYPE_CODE, Y.NEW_SEGMENT1, Y.NEW_SEGMENT2
		HAVING COUNT(*) > 1
		) B
		WHERE A.LOOKUP_TYPE_CODE = B.LOOKUP_TYPE_CODE
		AND A.SEGMENT1 = B.SEGMENT1
		AND A.SEGMENT2 = B.SEGMENT2


		DELETE FROM SCM_CODE_LOOKUP_VALUE
		WHERE LOOKUP_TYPE_CODE = 'PR_SCM_FORMATION_INVENTORY_GAP_INFO_SEND'
		AND SEGMENT2 = 'G183'

		DELETE FROM SCM_CODE_LOOKUP_VALUE
		WHERE LOOKUP_TYPE_CODE = 'PR_SCM_MANUAL_WO_UPLOAD'
		AND SEGMENT2 = 'G183'
		
	END

	------------------------------------------------------
	--STEP 2-1. Update the storage data
	------------------------------------------------------
	BEGIN
		UPDATE SCM_SYS_LOOKUP_VALUE 
		SET SEGMENT2 = MA.TO_STORAGE_ID
		, SEGMENT1 = MA.TO_PLANT_ID
		FROM SCM_SYS_LOOKUP_VALUE VA, (
		SELECT A.LOOKUP_TYPE_CODE, A.SEGMENT1, A.SEGMENT2, B.TO_PLANT_ID, B.TO_STORAGE_ID FROM SCM_SYS_LOOKUP_VALUE A
		LEFT JOIN ZNERP_CONV_MASTER B
		ON  B.CODETYPE = 'STORAGE_ID'
		AND A.SEGMENT1 = B.FROM_PLANT_ID
		AND A.SEGMENT2 = B.FROM_STORAGE_ID
		WHERE A.LOOKUP_TYPE_CODE = 'ERP_AS_DOCUMENT_MAPPING'
		AND B.TO_STORAGE_ID IS NOT NULL) MA
		WHERE VA.LOOKUP_TYPE_CODE = MA.LOOKUP_TYPE_CODE
		AND VA.SEGMENT1 = MA.SEGMENT1
		AND VA.SEGMENT2 = MA.SEGMENT2


		UPDATE SCM_SYS_LOOKUP_VALUE 
		SET SEGMENT2 = MA.TO_STORAGE_ID
		, SEGMENT1 = MA.TO_PLANT_ID
		FROM SCM_SYS_LOOKUP_VALUE VA, (
		SELECT A.LOOKUP_TYPE_CODE, A.SEGMENT1, A.SEGMENT2, B.TO_PLANT_ID, B.TO_STORAGE_ID FROM SCM_SYS_LOOKUP_VALUE A
		LEFT JOIN ZNERP_CONV_MASTER B
		ON  B.CODETYPE = 'STORAGE_ID'
		AND A.SEGMENT1 = B.FROM_PLANT_ID
		AND A.SEGMENT2 = B.FROM_STORAGE_ID
		WHERE A.LOOKUP_TYPE_CODE = 'ERP_MATERIAL_DOCUMENT_MAPPING'
		AND B.TO_STORAGE_ID IS NOT NULL) MA
		WHERE VA.LOOKUP_TYPE_CODE = MA.LOOKUP_TYPE_CODE
		AND VA.SEGMENT1 = MA.SEGMENT1
		AND VA.SEGMENT2 = MA.SEGMENT2

		UPDATE SCM_SYS_LOOKUP_VALUE 
		SET SEGMENT5 = MA.TO_STORAGE_ID
		, SEGMENT4 = MA.TO_PLANT_ID
		FROM SCM_SYS_LOOKUP_VALUE VA, (
		SELECT A.LOOKUP_TYPE_CODE, A.SEGMENT4, A.SEGMENT5, B.TO_PLANT_ID, B.TO_STORAGE_ID FROM SCM_SYS_LOOKUP_VALUE A
		LEFT JOIN ZNERP_CONV_MASTER B
		ON  B.CODETYPE = 'STORAGE_ID'
		AND A.SEGMENT4 = B.FROM_PLANT_ID
		AND A.SEGMENT5 = B.FROM_STORAGE_ID
		WHERE A.LOOKUP_TYPE_CODE = 'SIMULATION_BOH'
		AND B.TO_STORAGE_ID IS NOT NULL) MA
		WHERE VA.LOOKUP_TYPE_CODE = MA.LOOKUP_TYPE_CODE
		AND VA.SEGMENT4 = MA.SEGMENT4
		AND VA.SEGMENT5 = MA.SEGMENT5
					
					

		UPDATE SCM_SYS_LOOKUP_VALUE 
		SET SEGMENT5 = MA.TO_STORAGE_ID
		, SEGMENT3 = MA.TO_PLANT_ID
		FROM SCM_SYS_LOOKUP_VALUE VA, (
		SELECT A.LOOKUP_TYPE_CODE, A.SEGMENT3, A.SEGMENT5, B.TO_PLANT_ID, B.TO_STORAGE_ID FROM SCM_SYS_LOOKUP_VALUE A
		LEFT JOIN ZNERP_CONV_MASTER B
		ON  B.CODETYPE = 'STORAGE_ID'
		AND A.SEGMENT3 = B.FROM_PLANT_ID
		AND A.SEGMENT5 = B.FROM_STORAGE_ID
		WHERE A.LOOKUP_TYPE_CODE = 'FORMATION_TARGET_NETTING'
		AND B.TO_STORAGE_ID IS NOT NULL) MA
		WHERE VA.LOOKUP_TYPE_CODE = MA.LOOKUP_TYPE_CODE
		AND VA.SEGMENT3 = MA.SEGMENT3
		AND VA.SEGMENT5 = MA.SEGMENT5
	END

	------------------------------------------------------
	--STEP 2-2. Update the plant data
	------------------------------------------------------
	BEGIN
		UPDATE SCM_SYS_LOOKUP_VALUE
		SET SEGMENT1 = RESULT.NEW_SEGMENT1
		,   SEGMENT2 = RESULT.NEW_SEGMENT2
		,   SEGMENT3 = RESULT.NEW_SEGMENT3
		,   SEGMENT4 = RESULT.NEW_SEGMENT4
		,   SEGMENT5 = RESULT.NEW_SEGMENT5
		,   ATTRIBUTE1 = RESULT.NEW_ATTRIBUTE1
		,   ATTRIBUTE2 = RESULT.NEW_ATTRIBUTE2
		,   ATTRIBUTE3 = RESULT.NEW_ATTRIBUTE3
		,   ATTRIBUTE4 = RESULT.NEW_ATTRIBUTE4
		,   ATTRIBUTE5 = RESULT.NEW_ATTRIBUTE5
		,   ATTRIBUTE6 = RESULT.NEW_ATTRIBUTE6
		,   ATTRIBUTE7 = RESULT.NEW_ATTRIBUTE7
		FROM (
				SELECT A.LOOKUP_TYPE_CODE, 
				A.SEGMENT1_T, A.SEGMENT1,
				CASE WHEN SEGMENT1_T LIKE '%PLANT%'  THEN ISNULL(B.TO_PLANT_ID, A.SEGMENT1)  
				ELSE A.SEGMENT1 END AS NEW_SEGMENT1,
				A.SEGMENT2_T, A.SEGMENT2,
				CASE WHEN SEGMENT2_T LIKE '%PLANT%'  THEN  ISNULL(B1.TO_PLANT_ID, A.SEGMENT2) 
				ELSE A.SEGMENT2 END AS NEW_SEGMENT2,
				A.SEGMENT3_T, A.SEGMENT3,
				CASE WHEN SEGMENT3_T LIKE '%PLANT%'  THEN  ISNULL(B2.TO_PLANT_ID, A.SEGMENT3) 
				ELSE A.SEGMENT3 END AS NEW_SEGMENT3,
				A.SEGMENT4_T, A.SEGMENT4,
				CASE WHEN SEGMENT4_T LIKE '%PLANT%'  THEN  ISNULL(B3.TO_PLANT_ID, A.SEGMENT4)
				ELSE A.SEGMENT4 END AS NEW_SEGMENT4,
				A.SEGMENT5_T, A.SEGMENT5,
				CASE WHEN SEGMENT5_T LIKE '%PLANT%'  THEN  ISNULL(B4.TO_PLANT_ID, A.SEGMENT5)
				ELSE A.SEGMENT5 END AS NEW_SEGMENT5,
				A.ATTRIBUTE1_T, A.ATTRIBUTE1,
				CASE WHEN ATTRIBUTE1_T LIKE '%PLANT%'  THEN  ISNULL(B5.TO_PLANT_ID, A.ATTRIBUTE1)
				ELSE A.ATTRIBUTE1 END AS NEW_ATTRIBUTE1,
				A.ATTRIBUTE2_T, A.ATTRIBUTE2,
				CASE WHEN ATTRIBUTE2_T LIKE '%PLANT%'  THEN  ISNULL(B6.TO_PLANT_ID,	A.ATTRIBUTE2) 
				ELSE A.ATTRIBUTE2 END AS NEW_ATTRIBUTE2,
				A.ATTRIBUTE3_T, A.ATTRIBUTE3,
				CASE WHEN ATTRIBUTE3_T LIKE '%PLANT%'  THEN  ISNULL(B7.TO_PLANT_ID,	A.ATTRIBUTE3) 
				ELSE A.ATTRIBUTE3 END AS NEW_ATTRIBUTE3,
				A.ATTRIBUTE4_T, A.ATTRIBUTE4,
				CASE WHEN ATTRIBUTE4_T LIKE '%PLANT%'  THEN  ISNULL(B8.TO_PLANT_ID,	A.ATTRIBUTE4)
				ELSE A.ATTRIBUTE4 END AS NEW_ATTRIBUTE4,
				A.ATTRIBUTE5_T, A.ATTRIBUTE5,
				CASE WHEN ATTRIBUTE5_T LIKE '%PLANT%'  THEN  ISNULL(B9.TO_PLANT_ID,	A.ATTRIBUTE5)
				ELSE A.ATTRIBUTE5 END AS NEW_ATTRIBUTE5,
				A.ATTRIBUTE6_T, A.ATTRIBUTE6,
				CASE WHEN ATTRIBUTE6_T LIKE '%PLANT%'  THEN  ISNULL(B10.TO_PLANT_ID,	A.ATTRIBUTE6)
				ELSE A.ATTRIBUTE6 END AS NEW_ATTRIBUTE6,
				A.ATTRIBUTE7_T, A.ATTRIBUTE7,
				CASE WHEN ATTRIBUTE7_T LIKE '%PLANT%'  THEN  ISNULL(B11.TO_PLANT_ID,	A.ATTRIBUTE7)
				ELSE A.ATTRIBUTE7 END AS NEW_ATTRIBUTE7
				FROM (SELECT T.LOOKUP_TYPE_CODE,
					T.SEGMENT1 AS SEGMENT1_T, A.SEGMENT1, 
					T.SEGMENT2 AS SEGMENT2_T, A.SEGMENT2, 
					T.SEGMENT3 AS SEGMENT3_T, A.SEGMENT3, 
					T.SEGMENT4 AS SEGMENT4_T, A.SEGMENT4, 
					T.SEGMENT5 AS SEGMENT5_T, A.SEGMENT5,
					T.ATTRIBUTE1 AS ATTRIBUTE1_T, A.ATTRIBUTE1, 
					T.ATTRIBUTE2 AS ATTRIBUTE2_T, A.ATTRIBUTE2,
					T.ATTRIBUTE3 AS ATTRIBUTE3_T, A.ATTRIBUTE3,
					T.ATTRIBUTE4 AS ATTRIBUTE4_T, A.ATTRIBUTE4,
					T.ATTRIBUTE5 AS ATTRIBUTE5_T, A.ATTRIBUTE5,
					T.ATTRIBUTE6 AS ATTRIBUTE6_T, A.ATTRIBUTE6,
					T.ATTRIBUTE7 AS ATTRIBUTE7_T, A.ATTRIBUTE7,
					T.ATTRIBUTE8 AS ATTRIBUTE8_T, A.ATTRIBUTE8,
					T.ATTRIBUTE9 AS ATTRIBUTE9_T, A.ATTRIBUTE9,
					T.ATTRIBUTE10 AS ATTRIBUTE10_T, A.ATTRIBUTE10
				FROM SCM_SYS_LOOKUP_TYPE_M T
				LEFT JOIN SCM_SYS_LOOKUP_VALUE A
				ON T.LOOKUP_TYPE_CODE = A.LOOKUP_TYPE_CODE
				WHERE ((T.SEGMENT1 LIKE '%PLANT%'
					OR  T.SEGMENT2 LIKE '%PLANT%'
					OR  T.SEGMENT3 LIKE '%PLANT%'
					OR  T.SEGMENT4 LIKE '%PLANT%'
					OR  T.SEGMENT5 LIKE '%PLANT%'
					OR  T.ATTRIBUTE1 LIKE '%PLANT%'
					OR  T.ATTRIBUTE2 LIKE '%PLANT%'
					OR  T.ATTRIBUTE3 LIKE '%PLANT%'
					OR  T.ATTRIBUTE4 LIKE '%PLANT%'
					OR  T.ATTRIBUTE5 LIKE '%PLANT%'
					OR  T.ATTRIBUTE6 LIKE '%PLANT%'
					OR  T.ATTRIBUTE7 LIKE '%PLANT%'
					OR  T.ATTRIBUTE8 LIKE '%PLANT%'
					OR  T.ATTRIBUTE9 LIKE '%PLANT%'
					OR  T.ATTRIBUTE10 LIKE '%PLANT%'
					))
				--AND T.LOOKUP_TYPE_CODE NOT IN ('BOM_LINK_PLANT')
				)A
				LEFT JOIN ZNERP_CONV_MASTER B
				ON (B.CODETYPE = 'PLANT_ID' AND A.SEGMENT1 = B.FROM_PLANT_ID)
				LEFT JOIN ZNERP_CONV_MASTER B1
				ON (B1.CODETYPE = 'PLANT_ID' AND A.SEGMENT2 = B1.FROM_PLANT_ID)
				LEFT JOIN ZNERP_CONV_MASTER B2
				ON (B2.CODETYPE = 'PLANT_ID' AND A.SEGMENT3 = B2.FROM_PLANT_ID)
				LEFT JOIN ZNERP_CONV_MASTER B3
				ON (B3.CODETYPE = 'PLANT_ID' AND A.SEGMENT4 = B3.FROM_PLANT_ID)
				LEFT JOIN ZNERP_CONV_MASTER B4
				ON (B4.CODETYPE = 'PLANT_ID' AND A.SEGMENT5 = B4.FROM_PLANT_ID)
				LEFT JOIN ZNERP_CONV_MASTER B5
				ON (B5.CODETYPE = 'PLANT_ID' AND A.ATTRIBUTE1 = B5.FROM_PLANT_ID)
				LEFT JOIN ZNERP_CONV_MASTER B6
				ON (B6.CODETYPE = 'PLANT_ID' AND A.ATTRIBUTE2 = B6.FROM_PLANT_ID)
				LEFT JOIN ZNERP_CONV_MASTER B7
				ON (B7.CODETYPE = 'PLANT_ID' AND A.ATTRIBUTE3 = B7.FROM_PLANT_ID)
				LEFT JOIN ZNERP_CONV_MASTER B8
				ON (B8.CODETYPE = 'PLANT_ID' AND A.ATTRIBUTE4 = B8.FROM_PLANT_ID)
				LEFT JOIN ZNERP_CONV_MASTER B9
				ON (B9.CODETYPE = 'PLANT_ID' AND A.ATTRIBUTE5 = B9.FROM_PLANT_ID)
				LEFT JOIN ZNERP_CONV_MASTER B10
				ON (B10.CODETYPE = 'PLANT_ID' AND A.ATTRIBUTE6 = B10.FROM_PLANT_ID)
				LEFT JOIN ZNERP_CONV_MASTER B11
				ON (B11.CODETYPE = 'PLANT_ID' AND A.ATTRIBUTE7 = B11.FROM_PLANT_ID)
			) RESULT, SCM_SYS_LOOKUP_VALUE SOUR
			WHERE RESULT.LOOKUP_TYPE_CODE = SOUR.LOOKUP_TYPE_CODE
			AND RESULT.SEGMENT1 = SOUR.SEGMENT1
			AND RESULT.SEGMENT2 = SOUR.SEGMENT2
			AND RESULT.SEGMENT3 = SOUR.SEGMENT3
			AND RESULT.SEGMENT4 = SOUR.SEGMENT4
			AND RESULT.SEGMENT5 = SOUR.SEGMENT5
			AND ISNULL(RESULT.ATTRIBUTE1, '') = ISNULL(SOUR.ATTRIBUTE1, '')
			AND ISNULL(RESULT.ATTRIBUTE2, '') = ISNULL(SOUR.ATTRIBUTE2, '')
			AND ISNULL(RESULT.ATTRIBUTE3, '') = ISNULL(SOUR.ATTRIBUTE3, '')
			AND ISNULL(RESULT.ATTRIBUTE4, '') = ISNULL(SOUR.ATTRIBUTE4, '')
			AND ISNULL(RESULT.ATTRIBUTE5, '') = ISNULL(SOUR.ATTRIBUTE5, '')
			AND ISNULL(RESULT.ATTRIBUTE6, '') = ISNULL(SOUR.ATTRIBUTE6, '')
			AND ISNULL(RESULT.ATTRIBUTE7, '') = ISNULL(SOUR.ATTRIBUTE7, '')		
	END

	------------------------------------------------------
	--STEP 2-3. Update the company data
	------------------------------------------------------
	BEGIN
		UPDATE SCM_SYS_LOOKUP_VALUE
		SET SEGMENT1 = RESULT.NEW_SEGMENT1
		,   SEGMENT2 = RESULT.NEW_SEGMENT2
		,   SEGMENT3 = RESULT.NEW_SEGMENT3
		,   SEGMENT4 = RESULT.NEW_SEGMENT4
		,   SEGMENT5 = RESULT.NEW_SEGMENT5
		,   ATTRIBUTE1 = RESULT.NEW_ATTRIBUTE1
		,   ATTRIBUTE2 = RESULT.NEW_ATTRIBUTE2
		,   ATTRIBUTE3 = RESULT.NEW_ATTRIBUTE3
		,   ATTRIBUTE4 = RESULT.NEW_ATTRIBUTE4
		,   ATTRIBUTE5 = RESULT.NEW_ATTRIBUTE5
		,   ATTRIBUTE6 = RESULT.NEW_ATTRIBUTE6
		,   ATTRIBUTE7 = RESULT.NEW_ATTRIBUTE7
		FROM (
				SELECT A.LOOKUP_TYPE_CODE, 
				A.SEGMENT1_T, A.SEGMENT1,
				CASE WHEN SEGMENT1_T LIKE '%COMPANY%'  THEN ISNULL(B.TO_COMPANY_ID, A.SEGMENT1)  
				ELSE A.SEGMENT1 END AS NEW_SEGMENT1,
				A.SEGMENT2_T, A.SEGMENT2,
				CASE WHEN SEGMENT2_T LIKE '%COMPANY%'  THEN  ISNULL(B1.TO_COMPANY_ID, A.SEGMENT2) 
				ELSE A.SEGMENT2 END AS NEW_SEGMENT2,
				A.SEGMENT3_T, A.SEGMENT3,
				CASE WHEN SEGMENT3_T LIKE '%COMPANY%'  THEN  ISNULL(B2.TO_COMPANY_ID, A.SEGMENT3) 
				ELSE A.SEGMENT3 END AS NEW_SEGMENT3,
				A.SEGMENT4_T, A.SEGMENT4,
				CASE WHEN SEGMENT4_T LIKE '%COMPANY%'  THEN  ISNULL(B3.TO_COMPANY_ID, A.SEGMENT4)
				ELSE A.SEGMENT4 END AS NEW_SEGMENT4,
				A.SEGMENT5_T, A.SEGMENT5,
				CASE WHEN SEGMENT5_T LIKE '%COMPANY%'  THEN  ISNULL(B4.TO_COMPANY_ID, A.SEGMENT5)
				ELSE A.SEGMENT5 END AS NEW_SEGMENT5,
				A.ATTRIBUTE1_T, A.ATTRIBUTE1,
				CASE WHEN ATTRIBUTE1_T LIKE '%COMPANY%'  THEN  ISNULL(B5.TO_COMPANY_ID, A.ATTRIBUTE1)
				ELSE A.ATTRIBUTE1 END AS NEW_ATTRIBUTE1,
				A.ATTRIBUTE2_T, A.ATTRIBUTE2,
				CASE WHEN ATTRIBUTE2_T LIKE '%COMPANY%'  THEN  ISNULL(B6.TO_COMPANY_ID,	A.ATTRIBUTE2) 
				ELSE A.ATTRIBUTE2 END AS NEW_ATTRIBUTE2,
				A.ATTRIBUTE3_T, A.ATTRIBUTE3,
				CASE WHEN ATTRIBUTE3_T LIKE '%COMPANY%'  THEN  ISNULL(B7.TO_COMPANY_ID,	A.ATTRIBUTE3) 
				ELSE A.ATTRIBUTE3 END AS NEW_ATTRIBUTE3,
				A.ATTRIBUTE4_T, A.ATTRIBUTE4,
				CASE WHEN ATTRIBUTE4_T LIKE '%COMPANY%'  THEN  ISNULL(B8.TO_COMPANY_ID,	A.ATTRIBUTE4)
				ELSE A.ATTRIBUTE4 END AS NEW_ATTRIBUTE4,
				A.ATTRIBUTE5_T, A.ATTRIBUTE5,
				CASE WHEN ATTRIBUTE5_T LIKE '%COMPANY%'  THEN  ISNULL(B9.TO_COMPANY_ID,	A.ATTRIBUTE5)
				ELSE A.ATTRIBUTE5 END AS NEW_ATTRIBUTE5,
				A.ATTRIBUTE6_T, A.ATTRIBUTE6,
				CASE WHEN ATTRIBUTE6_T LIKE '%COMPANY%'  THEN  ISNULL(B10.TO_COMPANY_ID,	A.ATTRIBUTE6)
				ELSE A.ATTRIBUTE6 END AS NEW_ATTRIBUTE6,
				A.ATTRIBUTE7_T, A.ATTRIBUTE7,
				CASE WHEN ATTRIBUTE7_T LIKE '%COMPANY%'  THEN  ISNULL(B11.TO_COMPANY_ID,	A.ATTRIBUTE7)
				ELSE A.ATTRIBUTE7 END AS NEW_ATTRIBUTE7
				FROM (SELECT T.LOOKUP_TYPE_CODE,
					T.SEGMENT1 AS SEGMENT1_T, A.SEGMENT1, 
					T.SEGMENT2 AS SEGMENT2_T, A.SEGMENT2, 
					T.SEGMENT3 AS SEGMENT3_T, A.SEGMENT3, 
					T.SEGMENT4 AS SEGMENT4_T, A.SEGMENT4, 
					T.SEGMENT5 AS SEGMENT5_T, A.SEGMENT5,
					T.ATTRIBUTE1 AS ATTRIBUTE1_T, A.ATTRIBUTE1, 
					T.ATTRIBUTE2 AS ATTRIBUTE2_T, A.ATTRIBUTE2,
					T.ATTRIBUTE3 AS ATTRIBUTE3_T, A.ATTRIBUTE3,
					T.ATTRIBUTE4 AS ATTRIBUTE4_T, A.ATTRIBUTE4,
					T.ATTRIBUTE5 AS ATTRIBUTE5_T, A.ATTRIBUTE5,
					T.ATTRIBUTE6 AS ATTRIBUTE6_T, A.ATTRIBUTE6,
					T.ATTRIBUTE7 AS ATTRIBUTE7_T, A.ATTRIBUTE7,
					T.ATTRIBUTE8 AS ATTRIBUTE8_T, A.ATTRIBUTE8,
					T.ATTRIBUTE9 AS ATTRIBUTE9_T, A.ATTRIBUTE9,
					T.ATTRIBUTE10 AS ATTRIBUTE10_T, A.ATTRIBUTE10
				FROM SCM_SYS_LOOKUP_TYPE_M T
				LEFT JOIN SCM_SYS_LOOKUP_VALUE A
				ON T.LOOKUP_TYPE_CODE = A.LOOKUP_TYPE_CODE
				WHERE ((T.SEGMENT1 LIKE '%COMPANY%'
					OR  T.SEGMENT2 LIKE '%COMPANY%'
					OR  T.SEGMENT3 LIKE '%COMPANY%'
					OR  T.SEGMENT4 LIKE '%COMPANY%'
					OR  T.SEGMENT5 LIKE '%COMPANY%'
					OR  T.ATTRIBUTE1 LIKE '%COMPANY%'
					OR  T.ATTRIBUTE2 LIKE '%COMPANY%'
					OR  T.ATTRIBUTE3 LIKE '%COMPANY%'
					OR  T.ATTRIBUTE4 LIKE '%COMPANY%'
					OR  T.ATTRIBUTE5 LIKE '%COMPANY%'
					OR  T.ATTRIBUTE6 LIKE '%COMPANY%'
					OR  T.ATTRIBUTE7 LIKE '%COMPANY%'
					OR  T.ATTRIBUTE8 LIKE '%COMPANY%'
					OR  T.ATTRIBUTE9 LIKE '%COMPANY%'
					OR  T.ATTRIBUTE10 LIKE '%COMPANY%'
					))
				--AND T.LOOKUP_TYPE_CODE NOT IN ('BOM_LINK_PLANT')
				)A
				LEFT JOIN ZNERP_CONV_MASTER B
				ON (B.CODETYPE = 'COMPANY_ID' AND A.SEGMENT1 = B.FROM_COMPANY_ID)
				LEFT JOIN ZNERP_CONV_MASTER B1
				ON (B1.CODETYPE = 'COMPANY_ID' AND A.SEGMENT2 = B1.FROM_COMPANY_ID)
				LEFT JOIN ZNERP_CONV_MASTER B2
				ON (B2.CODETYPE = 'COMPANY_ID' AND A.SEGMENT3 = B2.FROM_COMPANY_ID)
				LEFT JOIN ZNERP_CONV_MASTER B3
				ON (B3.CODETYPE = 'COMPANY_ID' AND A.SEGMENT4 = B3.FROM_COMPANY_ID)
				LEFT JOIN ZNERP_CONV_MASTER B4
				ON (B4.CODETYPE = 'COMPANY_ID' AND A.SEGMENT5 = B4.FROM_COMPANY_ID)
				LEFT JOIN ZNERP_CONV_MASTER B5
				ON (B5.CODETYPE = 'COMPANY_ID' AND A.ATTRIBUTE1 = B5.FROM_COMPANY_ID)
				LEFT JOIN ZNERP_CONV_MASTER B6
				ON (B6.CODETYPE = 'COMPANY_ID' AND A.ATTRIBUTE2 = B6.FROM_COMPANY_ID)
				LEFT JOIN ZNERP_CONV_MASTER B7
				ON (B7.CODETYPE = 'COMPANY_ID' AND A.ATTRIBUTE3 = B7.FROM_COMPANY_ID)
				LEFT JOIN ZNERP_CONV_MASTER B8
				ON (B8.CODETYPE = 'COMPANY_ID' AND A.ATTRIBUTE4 = B8.FROM_COMPANY_ID)
				LEFT JOIN ZNERP_CONV_MASTER B9
				ON (B9.CODETYPE = 'COMPANY_ID' AND A.ATTRIBUTE5 = B9.FROM_COMPANY_ID)
				LEFT JOIN ZNERP_CONV_MASTER B10
				ON (B10.CODETYPE = 'COMPANY_ID' AND A.ATTRIBUTE6 = B10.FROM_COMPANY_ID)
				LEFT JOIN ZNERP_CONV_MASTER B11
				ON (B11.CODETYPE = 'COMPANY_ID' AND A.ATTRIBUTE7 = B11.FROM_COMPANY_ID)
			) RESULT, SCM_SYS_LOOKUP_VALUE SOUR
			WHERE RESULT.LOOKUP_TYPE_CODE = SOUR.LOOKUP_TYPE_CODE
			AND RESULT.SEGMENT1 = SOUR.SEGMENT1
			AND RESULT.SEGMENT2 = SOUR.SEGMENT2
			AND RESULT.SEGMENT3 = SOUR.SEGMENT3
			AND RESULT.SEGMENT4 = SOUR.SEGMENT4
			AND RESULT.SEGMENT5 = SOUR.SEGMENT5
			AND ISNULL(RESULT.ATTRIBUTE1, '') = ISNULL(SOUR.ATTRIBUTE1, '')
			AND ISNULL(RESULT.ATTRIBUTE2, '') = ISNULL(SOUR.ATTRIBUTE2, '')
			AND ISNULL(RESULT.ATTRIBUTE3, '') = ISNULL(SOUR.ATTRIBUTE3, '')
			AND ISNULL(RESULT.ATTRIBUTE4, '') = ISNULL(SOUR.ATTRIBUTE4, '')
			AND ISNULL(RESULT.ATTRIBUTE5, '') = ISNULL(SOUR.ATTRIBUTE5, '')
			AND ISNULL(RESULT.ATTRIBUTE6, '') = ISNULL(SOUR.ATTRIBUTE6, '')
			AND ISNULL(RESULT.ATTRIBUTE7, '') = ISNULL(SOUR.ATTRIBUTE7, '')		
	END


