      ,DPP.[LOCATION]
      ,DPP.[TOP_ITEM_ID]
      ,DPP.[ITEM_ID]
      ,DPP.[FP_PRODUCTION_TYPE]
      ,DPP.[MARKET]
      ,(SELECT TOP 1 FL.SEGMENT2
	    FROM   [DBO].[SCM_SYS_LOOKUP_VALUE]  FL WITH(NOLOCK)
		WHERE  FL.LOOKUP_TYPE_CODE = 'FORMATION_LINE_MAPPING' 
