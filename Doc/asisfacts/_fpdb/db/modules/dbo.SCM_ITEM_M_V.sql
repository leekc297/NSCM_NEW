and company_id in (SELECT SEGMENT2 FROM SCM_CODE_LOOKUP_VALUE WITH(NOLOCK) WHERE LOOKUP_TYPE_CODE='SCM_ITEM_M_V' AND SEGMENT1  = 'COMPANY_A' AND ACTIVE_FLAG='Y') 
