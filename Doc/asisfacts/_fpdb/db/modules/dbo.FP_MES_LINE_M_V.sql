
CREATE       VIEW FP_MES_LINE_M_V AS

SELECT	DISTINCT LM.COMPANY_ID, LM.SITE_ID, LM.DIVISION_ID, LM.PLANT_ID, LM.FACTORY_ID, LM.OPERATION_ID, EM.MES_LINE_ID, LM.LINE_ID, FM.MES_PLANT_ID, FM.MES_MNGL_PRDN
				,NM.MES_PLANT_ID AS MES_PLANT_ID_CONV, NM.FACTORY_ID AS FACTORY_ID_CONV, NM.DIVISION_ID AS DIVISION_ID_CONV, NM.PLANT_ID AS PLANT_ID_CONV
FROM	SCM_LINE_M LM WITH(NOLOCK) 
		INNER JOIN SCM_EQUIPMENT_M EM WITH(NOLOCK)
			ON 1=1
			AND		EM.ACTIVE_FLAG = 'Y'
			AND		EM.EQUIPMENT_TYPE = 'M'
			AND		LM.COMPANY_ID	= EM.COMPANY_ID
			AND		LM.SITE_ID		= EM.SITE_ID
			AND		LM.DIVISION_ID	= EM.DIVISION_ID
			AND		LM.PLANT_ID		= EM.PLANT_ID
			AND		LM.FACTORY_ID	= EM.FACTORY_ID
			AND		LM.OPERATION_ID = EM.OPERATION_ID
			AND		LM.LINE_ID		= EM.LINE_ID
	   INNER JOIN SCM_FACTORY_M FM WITH(NOLOCK)
			ON 1=1
			AND		FM.ACTIVE_FLAG = 'Y'
			AND		LM.COMPANY_ID	= FM.COMPANY_ID
			AND		LM.SITE_ID		= FM.SITE_ID
			AND		LM.DIVISION_ID	= FM.DIVISION_ID
			AND		LM.PLANT_ID		= FM.PLANT_ID
			AND		LM.FACTORY_ID	= FM.FACTORY_ID
		LEFT OUTER JOIN SCM_FACTORY_M NM WITH(NOLOCK)
			ON 1=1
			AND		NM.ACTIVE_FLAG = 'Y'
			AND		FM.MES_MNGL_PRDN	= NM.FACTORY_ID
WHERE	1=1
AND		LM.ACTIVE_FLAG = 'Y'
;
