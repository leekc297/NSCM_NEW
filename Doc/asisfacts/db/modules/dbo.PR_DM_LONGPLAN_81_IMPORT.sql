/*
 * Program ID   : PR_DM_LONGPLAN_81_IMPORT
 * Description  : 2021 자동차용 중장기계획을 위해서 MKT FCST IMPORT
 * Program History
 *===================================================================================================
 *   Date       In Charge      Description
 *===================================================================================================
 * 20210806 HWI1993 Initial Release 
 * 2022.06.21	rosia27		[C20220609-000168]GSCM Business Plan 신규 키컬럼 추가 및 체크박스 옵션 추가 요청의 건
 *
 * PR_DM_LONGPLAN_81_IMPORT 'MF_W_20210720_V001','SP_W_20210705_V001'
 */

CREATE PROC [dbo].[PR_DM_LONGPLAN_81_IMPORT]
@P_MF_VERSION_NO NVARCHAR(30)
, @P_SP_VERSION_NO NVARCHAR(30)
AS
BEGIN

    SET NOCOUNT ON;
    SET TRANSACTION ISOLATION LEVEL READ COMMITTED;
    SET XACT_ABORT ON;

	    -- LOG 용 변수 설정
    DECLARE @v_program_name NVARCHAR(150) = 'PR_DM_LONGPLAN_81_IMPORT';
    DECLARE @v_log_type     NVARCHAR(30); -- START/END/ERROR/...
    DECLARE @n_log_count    INTEGER = 0;
    DECLARE @v_log_message  NVARCHAR(1000);
    DECLARE @v_description  NVARCHAR(500);
    DECLARE @d_event_date   DATETIME;

	    -- 시작 LOG  (START)
    SET @v_log_type = 'START';
    SET @v_log_message = '########## Start of procedure ##########';
    SET @v_description = '';
    SET @d_event_date = SYSDATETIME();
    EXEC PR_SCM_SYS_LOG_BATCH @v_program_name, @v_log_type, @n_log_count, @v_log_message, @v_description, @d_event_date;
    SET @v_log_message = NULL      /*-- <- 변수 재사용을 위하여 초기화해야함 --*/
    -- 시작 LOG  (END)

	
	BEGIN TRY

print 'A--' + convert(varchar(30), getdate(), 121)

		EXEC DMF0042_SAVE_DM_PLN_BP_FCST_CUTOFF '81', N'중장기계획을 위해 기존 데이터 백업', 'BP_M', 'SYSTEM_PLAN'

print 'B--' + convert(varchar(30), getdate(), 121)

		DELETE FROM DM_PLN_BP_FCST WHERE DIVISION_ID = '81'

print 'C--' + convert(varchar(30), getdate(), 121)

		insert into DM_PLN_BP_FCST 
			( DIVISION_ID, PROJECT_CODE, PROJECT_NAME, SCM_SITE_ID, ITEM_ID
			 , DOM_EXP, FCST_TYPE, MEASURE, PLANT_SITE_ID, DEPT_ID
			 , END_CUSTOMER, BIZ_TYPE, YYYYMM, CURRENCY, ITEM_USE
			 , UNIT_ENERGY, QTY, CELL_PER_PACK, CELL_PER_MODULE, MODULE_PER_PACK
			 , CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE, INCOTERMS
			 , ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4
			 , ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9
			 , ATTRIBUTE10, CELL_PROD_SITE )
		SELECT A.DIVISION_ID, A.PROJECT_CODE, '' AS PROJECT_NAME, A.SCM_SITE_ID, A.ITEM_ID
			 , A.DOM_EXP, A.FCST_TYPE, 'MKT_FCST' AS MEASURE, A.PLANT_SITE_ID, C.DEPT_ID
			 , C.END_CUSTOMER, '' AS BIZ_TYPE, LEFT(A.YYYYMMDD, 6), SI.CURRENCY, '' AS ITEM_USE
			 , 0 AS UNIT_ENERGY, SUM(QTY) AS QTY, NULL AS CELL_PER_PACK, NULL AS CELL_PER_MODULE, NULL AS MODULE_PER_PACK
			 , 'SYSTEM_PLAN', getdate(), 'SYSTEM_PLAN', getdate(), A.INCOTERMS
			 , NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, '' AS CELL_PROD_SITE
		FROM DM_PLN_MKT_FCST_C A
		LEFT OUTER JOIN  ( 
							SELECT DISTINCT B.DIVISION_ID, B.PROJECT_CODE, B.SCM_SITE_ID, B.PLANT_SITE_ID, B.ITEM_ID, B.CURRENCY, B.DOM_EXP, B.FCST_TYPE, B.INCOTERMS
							FROM (
								SELECT DIVISION_ID, VERSION_NO, CUTOFF_TYPE, CUTOFF_YYYYMMDD, PROJECT_CODE, SCM_SITE_ID, PLANT_SITE_ID, ITEM_ID, MEASURE, DOM_EXP, FCST_TYPE, INCOTERMS
									, MAX(YYYYMMDD) AS YYYYMMDD
								FROM SCM_MST_FUTURE_PRICE_C A WITH(NOLOCK)
								WHERE A.VERSION_NO = @P_SP_VERSION_NO AND A.DIVISION_ID = '81' AND A.MEASURE = 'LOC' AND A.YYYYMMDD >= '20210801'
								GROUP BY DIVISION_ID, VERSION_NO, CUTOFF_TYPE, CUTOFF_YYYYMMDD, PROJECT_CODE, SCM_SITE_ID, PLANT_SITE_ID, ITEM_ID, MEASURE, DOM_EXP, FCST_TYPE, INCOTERMS
								) A
								JOIN SCM_MST_FUTURE_PRICE_C B WITH(NOLOCK) ON	A.DIVISION_ID		= B.DIVISION_ID
																			AND A.VERSION_NO		= B.VERSION_NO
																			AND A.CUTOFF_TYPE		= B.CUTOFF_TYPE
																			AND A.CUTOFF_YYYYMMDD	= B.CUTOFF_YYYYMMDD
																			AND A.PROJECT_CODE		= B.PROJECT_CODE
																			AND A.SCM_SITE_ID		= B.SCM_SITE_ID
																			AND A.PLANT_SITE_ID		= B.PLANT_SITE_ID
																			AND A.ITEM_ID			= B.ITEM_ID
																			AND A.MEASURE			= B.MEASURE
																			AND A.DOM_EXP			= B.DOM_EXP
																			AND A.FCST_TYPE			= B.FCST_TYPE
																			AND A.INCOTERMS			= B.INCOTERMS
																			AND A.YYYYMMDD			= B.YYYYMMDD
																			AND B.VERSION_NO	= @P_SP_VERSION_NO
																			AND B.DIVISION_ID	= '81'
																			AND B.MEASURE		= 'LOC'
						) SI
			ON		A.DIVISION_ID   = SI.DIVISION_ID
				AND A.PROJECT_CODE  = SI.PROJECT_CODE
				AND A.SCM_SITE_ID   = SI.SCM_SITE_ID
				AND A.ITEM_ID       = SI.ITEM_ID
				AND A.DOM_EXP       = SI.DOM_EXP
				AND A.FCST_TYPE     = SI.FCST_TYPE
				AND A.INCOTERMS     = SI.INCOTERMS
				AND A.PLANT_SITE_ID = SI.PLANT_SITE_ID
		LEFT OUTER JOIN SCM_MST_SITE C ON A.DIVISION_ID = C.DIVISION_ID AND A.SCM_SITE_ID = C.SCM_SITE_ID
		WHERE A.DIVISION_ID = '81' 
			AND A.VERSION_NO = @P_MF_VERSION_NO 
			AND A.MEASURE = 'MKT_FCST'
			AND SI.CURRENCY IS NOT NULL
			AND C.DEPT_ID IS NOT NULL
			AND A.YYYYMMDD >= '20210801'
		GROUP BY A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID
			 , A.DOM_EXP, A.FCST_TYPE, A.PLANT_SITE_ID, C.DEPT_ID
			 , C.END_CUSTOMER, LEFT(A.YYYYMMDD, 6), SI.CURRENCY
			 , A.INCOTERMS

print 'D--' + convert(varchar(30), getdate(), 121)

		-- Price
		insert into DM_PLN_BP_FCST 
			( DIVISION_ID, PROJECT_CODE, PROJECT_NAME, SCM_SITE_ID, ITEM_ID
			 , DOM_EXP, FCST_TYPE, MEASURE, PLANT_SITE_ID, DEPT_ID
			 , END_CUSTOMER, BIZ_TYPE, YYYYMM, CURRENCY, ITEM_USE
			 , UNIT_ENERGY, QTY, CELL_PER_PACK, CELL_PER_MODULE, MODULE_PER_PACK
			 , CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE, INCOTERMS
			 , ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4
			 , ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9
			 , ATTRIBUTE10, CELL_PROD_SITE )
		SELECT A.DIVISION_ID, A.PROJECT_CODE, '' AS PROJECT_NAME, A.SCM_SITE_ID, A.ITEM_ID
			 , A.DOM_EXP, A.FCST_TYPE, 'LOC' AS MEASURE, A.PLANT_SITE_ID, C.DEPT_ID
			 , C.END_CUSTOMER, '' AS BIZ_TYPE, LEFT(A.YYYYMMDD, 6), SI.CURRENCY, '' AS ITEM_USE
			 , 0 AS UNIT_ENERGY, MAX(ISNULL(QTY,0)) AS QTY, NULL AS CELL_PER_PACK, NULL AS CELL_PER_MODULE, NULL AS MODULE_PER_PACK
			 , 'SYSTEM_PLAN', getdate(), 'SYSTEM_PLAN', getdate(), A.INCOTERMS
			 , NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, '' AS CELL_PROD_SITE
		FROM DM_PLN_MKT_FCST_C A
		LEFT OUTER JOIN  ( 
							SELECT B.DIVISION_ID, B.PROJECT_CODE, B.SCM_SITE_ID, B.PLANT_SITE_ID, B.ITEM_ID, B.CURRENCY, B.DOM_EXP, B.FCST_TYPE, B.INCOTERMS, MAX(B.PRICE) AS PRICE
							FROM (
								SELECT DIVISION_ID, VERSION_NO, CUTOFF_TYPE, CUTOFF_YYYYMMDD, PROJECT_CODE, SCM_SITE_ID, PLANT_SITE_ID, ITEM_ID, MEASURE, DOM_EXP, FCST_TYPE, INCOTERMS
									, MAX(YYYYMMDD) AS YYYYMMDD
								FROM SCM_MST_FUTURE_PRICE_C A WITH(NOLOCK)
								WHERE VERSION_NO = @P_SP_VERSION_NO AND A.DIVISION_ID = '81' AND A.MEASURE = 'LOC' AND A.YYYYMMDD >= '20210801'
									AND A.PRICE <> 0
								GROUP BY DIVISION_ID, VERSION_NO, CUTOFF_TYPE, CUTOFF_YYYYMMDD, PROJECT_CODE, SCM_SITE_ID, PLANT_SITE_ID, ITEM_ID, MEASURE, DOM_EXP, FCST_TYPE, INCOTERMS
								) A
								JOIN SCM_MST_FUTURE_PRICE_C B WITH(NOLOCK) ON	A.DIVISION_ID		= B.DIVISION_ID
																			AND A.VERSION_NO		= B.VERSION_NO
																			AND A.CUTOFF_TYPE		= B.CUTOFF_TYPE
																			AND A.CUTOFF_YYYYMMDD	= B.CUTOFF_YYYYMMDD
																			AND A.PROJECT_CODE		= B.PROJECT_CODE
																			AND A.SCM_SITE_ID		= B.SCM_SITE_ID
																			AND A.PLANT_SITE_ID		= B.PLANT_SITE_ID
																			AND A.ITEM_ID			= B.ITEM_ID
																			AND A.MEASURE			= B.MEASURE
																			AND A.DOM_EXP			= B.DOM_EXP
																			AND A.FCST_TYPE			= B.FCST_TYPE
																			AND A.INCOTERMS			= B.INCOTERMS
																			AND A.YYYYMMDD			= B.YYYYMMDD
																			AND B.VERSION_NO		= @P_SP_VERSION_NO
																			AND B.MEASURE			= 'LOC'
																			AND B.DIVISION_ID		= '81'
							GROUP BY B.DIVISION_ID, B.PROJECT_CODE, B.SCM_SITE_ID, B.PLANT_SITE_ID, B.ITEM_ID, B.CURRENCY, B.DOM_EXP, B.FCST_TYPE, B.INCOTERMS
						) SI
			ON		A.DIVISION_ID   = SI.DIVISION_ID
				AND A.PROJECT_CODE  = SI.PROJECT_CODE
				AND A.SCM_SITE_ID   = SI.SCM_SITE_ID
				AND A.ITEM_ID       = SI.ITEM_ID
				AND A.DOM_EXP       = SI.DOM_EXP
				AND A.FCST_TYPE     = SI.FCST_TYPE
				AND A.INCOTERMS     = SI.INCOTERMS
				AND A.PLANT_SITE_ID = SI.PLANT_SITE_ID
		LEFT OUTER JOIN SCM_MST_SITE C ON A.DIVISION_ID = C.DIVISION_ID AND A.SCM_SITE_ID = C.SCM_SITE_ID
		WHERE A.DIVISION_ID = '81' 
			AND A.VERSION_NO = @P_MF_VERSION_NO 
			AND A.MEASURE = 'MKT_FCST'
			AND SI.CURRENCY IS NOT NULL
			AND C.DEPT_ID IS NOT NULL
			AND A.YYYYMMDD >= '20210801'
		GROUP BY A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID
			 , A.DOM_EXP, A.FCST_TYPE, A.PLANT_SITE_ID, C.DEPT_ID
			 , C.END_CUSTOMER, LEFT(A.YYYYMMDD, 6), SI.CURRENCY
			 , A.INCOTERMS

print 'E--' + convert(varchar(30), getdate(), 121)

		-- SALESAMT
		insert into DM_PLN_BP_FCST 
			( DIVISION_ID, PROJECT_CODE, PROJECT_NAME, SCM_SITE_ID, ITEM_ID
			 , DOM_EXP, FCST_TYPE, MEASURE, PLANT_SITE_ID, DEPT_ID
			 , END_CUSTOMER, BIZ_TYPE, YYYYMM, CURRENCY, ITEM_USE
			 , UNIT_ENERGY, QTY, CELL_PER_PACK, CELL_PER_MODULE, MODULE_PER_PACK
			 , CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE, INCOTERMS
			 , ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4
			 , ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9
			 , ATTRIBUTE10, CELL_PROD_SITE )
		SELECT A.DIVISION_ID, A.PROJECT_CODE, A.PROJECT_NAME, A.SCM_SITE_ID, A.ITEM_ID
			 , A.DOM_EXP, A.FCST_TYPE, 'SalesAmt_KRW' AS MEASURE, A.PLANT_SITE_ID, A.DEPT_ID
			 , A.END_CUSTOMER, A.BIZ_TYPE, A.YYYYMM, A.CURRENCY, A.ITEM_USE
			 , A.UNIT_ENERGY, A.QTY * B.QTY * C.EXCHANGE_PRICE AS QTY, A.CELL_PER_PACK, A.CELL_PER_MODULE, A.MODULE_PER_PACK
			 , A.CREATED_BY, A.CREATION_DATE, A.LAST_UPDATED_BY, A.LAST_UPDATE_DATE, A.INCOTERMS
			 , A.ATTRIBUTE1, A.ATTRIBUTE2, A.ATTRIBUTE3, A.ATTRIBUTE4
			 , A.ATTRIBUTE5, A.ATTRIBUTE6, A.ATTRIBUTE7, A.ATTRIBUTE8, A.ATTRIBUTE9
			 , A.ATTRIBUTE10, A.CELL_PROD_SITE
		FROM DM_PLN_BP_FCST A
		JOIN DM_PLN_BP_FCST B ON 	A.DIVISION_ID		= B.DIVISION_ID 
								AND A.PROJECT_CODE 		= B.PROJECT_CODE 
								AND A.SCM_SITE_ID 		= B.SCM_SITE_ID 
								AND A.ITEM_ID 			= B.ITEM_ID 
								AND A.FCST_TYPE 		= B.FCST_TYPE 
								AND A.DEPT_ID 			= B.DEPT_ID 
								AND A.END_CUSTOMER 		= B.END_CUSTOMER 
								AND A.BIZ_TYPE 			= B.BIZ_TYPE 
								AND A.YYYYMM 			= B.YYYYMM 
								AND A.CURRENCY 			= B.CURRENCY 
								AND A.ITEM_USE 			= B.ITEM_USE 
								AND A.UNIT_ENERGY 		= B.UNIT_ENERGY 
								AND A.PLANT_SITE_ID 	= B.PLANT_SITE_ID
								AND A.CELL_PROD_SITE	= B.CELL_PROD_SITE
								AND A.INCOTERMS			= B.INCOTERMS
								AND B.DIVISION_ID = '81'
								AND B.MEASURE = 'LOC'
		JOIN DM_BP_EXCHANGE_RATE C ON B.DIVISION_ID = C.DIVISION_ID 
									AND B.CURRENCY = C.UNIT_CURRENCY
									AND B.YYYYMM = LEFT(C.YYYYMMDD, 6) 
		WHERE A.DIVISION_ID = '81'
			AND A.MEASURE = 'MKT_FCST'

print 'F--' + convert(varchar(30), getdate(), 121)

    --------------------------------------------------------------------------------------------
    END TRY
    --------------------------------------------------------------------------------------------

    --------------------------------------------------------------
    BEGIN CATCH
    --------------------------------------------------------------
        -- ROLLBACK
        -- 트랜잭션 (END)

        -- ERROR LOG VALUE SAVE
        SET @v_log_type = 'ERROR';
        SET @v_log_message = CAST(ERROR_MESSAGE() AS NVARCHAR(1000));
        SET @v_description = 'ERROR_LINE : ' + STR(ERROR_LINE());
        SET @d_event_date = SYSDATETIME();

		--[C20200909-000203] LOG 표준화 적용
		EXEC PR_SCM_SYS_LOG_BATCH @v_program_name, @v_log_type, @n_log_count, @v_log_message, @v_description, @d_event_date;

        SELECT '[' + Convert(NVARCHAR(10), ERROR_NUMBER()) + ']' + ERROR_MESSAGE();  /*-- 에러메시지 DISPLAY --*/


    --------------------------------------------------------------
    END CATCH;
    --------------------------------------------------------------

    -- 종료 LOG
    SET @v_log_type = 'END';
    SET @v_log_message = '########## END of procedure ##########';
    SET @v_description = '';
    SET @d_event_date = SYSDATETIME();

    EXEC PR_SCM_SYS_LOG_BATCH @v_program_name, @v_log_type, @n_log_count, @v_log_message, @v_description, @d_event_date;
END





