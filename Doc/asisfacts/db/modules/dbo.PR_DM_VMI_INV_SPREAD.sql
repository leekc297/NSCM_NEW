		DECLARE @I INT, @CNT INT, @ROW_NUM INT, @I_QTY INT
				, @K INT, @K_QTY INT, @K_CNT INT, @K_SUM_QTY INT
		SELECT @I = 1
			, @CNT = MAX(ROW_NUM) 
		FROM #T_VMI_REQ

		WHILE ( @I <= @CNT )
		BEGIN
			SELECT @I_QTY = INV_QTY
			FROM #T_VMI_REQ
			WHERE ROW_NUM = @I

			IF @I_QTY > 0
			BEGIN
	
				SELECT @K= 1, @K_CNT = MAX(INV_ROW_NUM)
					, @K_QTY = MAX(INV_QTY), @K_SUM_QTY = SUM(QTY)
				FROM #T_VMI_REQ
				WHERE ROW_NUM = @I
				IF @K_CNT > 1
				BEGIN

					WHILE ( @K <= @K_CNT )
					BEGIN
						UPDATE A
						SET INV_QTY_ALLOC = ROUND(@K_QTY * QTY / @K_SUM_QTY , 0)
						FROM #T_VMI_REQ A
						WHERE ROW_NUM  = @I
						AND INV_ROW_NUM = @K

						SET @K = @K + 1
					END

					-- 소수점차이가 나면 한 곳으로 몰아준다.
					IF EXISTS (
						SELECT 1
						FROM #T_VMI_REQ
						WHERE ROW_NUM = @I
						GROUP BY ROW_NUM
						HAVING SUM(INV_QTY_ALLOC) <> MAX(INV_QTY)
						)
					BEGIN

						UPDATE A
						SET INV_QTY_ALLOC = INV_QTY_ALLOC + DIFF_QTY
						FROM #T_VMI_REQ A
						JOIN ( SELECT MAX(INV_QTY) - SUM(INV_QTY_ALLOC) AS DIFF_QTY
								FROM #T_VMI_REQ
								WHERE ROW_NUM = @I
								GROUP BY ROW_NUM
							) B ON 1=1
						WHERE A.ROW_NUM = @I
							AND A.INV_ROW_NUM = 1

					END
				END
				ELSE
				BEGIN
					UPDATE #T_VMI_REQ 
					SET INV_QTY_ALLOC = INV_QTY
					WHERE ROW_NUM = @I
				END
			END

			SET @I = @I + 1
		END
		
