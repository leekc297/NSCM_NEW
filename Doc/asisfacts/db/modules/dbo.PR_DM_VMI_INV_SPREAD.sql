		, YYYYMMDD			NVARCHAR(8)
		, QTY				NUMERIC(20,10)
		, SUM_QTY			NUMERIC(20,10)
		, ROW_NUM			INT
		, ROW_NUM_SUB		INT			-- 아이템 세부 ROWNUM
		)
		


		-- 날짜 매핑 및 일자별 수량 계산
		INSERT INTO #T_MKT_FCST
				( DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP
				, FCST_TYPE, INCOTERMS, MEASURE, PLANT_SITE_ID, YYYYMMDD
				, QTY, SUM_QTY, ROW_NUM, ROW_NUM_SUB )
		SELECT A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.DOM_EXP
				, A.FCST_TYPE, A.INCOTERMS, A.MEASURE, A.PLANT_SITE_ID, C.BASIS_YYYYMMDD
