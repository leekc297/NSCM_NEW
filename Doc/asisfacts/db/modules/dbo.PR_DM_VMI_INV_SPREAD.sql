		INSERT INTO #T_VMI_REQ ( DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, MEASURE, PLANT_SITE_ID
			, QTY, ROW_NUM, INV_ROW_NUM )
