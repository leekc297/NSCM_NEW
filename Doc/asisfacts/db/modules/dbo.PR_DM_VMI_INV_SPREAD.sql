					ROUND(A.INV_QTY_ALLOC/DATEDIFF(DAY, dbo.FN_NEXT_DAY(GETDATE(), 'MON'), DATEADD(DD, VMI_STD_DIO, @V_MON_DATE))
						, 0) = 0 
						THEN 1
					ELSE ROUND(A.INV_QTY_ALLOC/DATEDIFF(DAY, dbo.FN_NEXT_DAY(GETDATE(), 'MON'), DATEADD(DD, VMI_STD_DIO, @V_MON_DATE))
						, 0)
					END -- 재고가 7 미만일 경우 모두 0으로 뿌리므로, 1로 처리하고, 끝전처리에서 정리해준다.
					
				, A.INV_QTY_ALLOC 
				, DENSE_RANK() OVER ( ORDER BY A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.DOM_EXP
										, A.FCST_TYPE, A.INCOTERMS, A.MEASURE, A.PLANT_SITE_ID)
