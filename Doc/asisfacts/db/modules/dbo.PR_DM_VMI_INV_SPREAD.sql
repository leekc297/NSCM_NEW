		-- 1) 할당액누계가 할당대상액보다 큰 행들은 모두 할당액을 0으로 정리
		-- 2) 할당액이 있는 마지막 행에서 할당액 누계와 할당대상액을 비교해서 정리
		UPDATE A
		SET QTY = CASE WHEN A.QTY + ( B.SUM_QTY - B.ALLOC_SUM_QTY) > 0 
							THEN A.QTY + ( B.SUM_QTY - B.ALLOC_SUM_QTY)
					ELSE 0 END 
