		UPDATE A
		SET INV_QTY = ISNULL(B.QTY,0)
		FROM #T_VMI_REQ A
		LEFT OUTER JOIN ( SELECT DIVISION_ID, SCM_SITE_ID, ITEM_ID, SUM(QTY) AS QTY
						FROM #T_SLOC 
						GROUP BY DIVISION_ID, SCM_SITE_ID, ITEM_ID
						) B ON A.DIVISION_ID = B.DIVISION_ID AND A.SCM_SITE_ID = B.SCM_SITE_ID AND A.ITEM_ID = B.ITEM_ID 


