			, DENSE_RANK() OVER ( ORDER BY SCM_SITE_ID, ITEM_ID )
			, DENSE_RANK() OVER ( PARTITION BY SCM_SITE_ID, ITEM_ID ORDER BY QTY DESC )
		FROM (
			SELECT DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, MEASURE, PLANT_SITE_ID, SUM(QTY) AS QTY
			FROM DM_PLN_MKT_FCST ( NOLOCK )
			WHERE DIVISION_ID = @p_division_id
				AND MEASURE = 'VMI_In_Req'
				AND YYYYMMDD >= CONVERT(CHAR(8), DATEADD(DD, -7, dbo.FN_NEXT_DAY(CONVERT(CHAR(8), getdate(), 112), 'MON')), 112)
				AND QTY > 0
			GROUP BY DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, MEASURE, PLANT_SITE_ID
			) A
			
		
