		JOIN (
			SELECT A.ROW_NUM, A.ROW_NUM_SUB, A.ALLOC_SUM_QTY, A.SUM_QTY, A.QTY
			FROM (
				SELECT ROW_NUM, ROW_NUM_SUB
					, SUM(QTY) OVER ( PARTITION BY ROW_NUM ORDER BY ROW_NUM_SUB ) AS ALLOC_SUM_QTY
					, SUM_QTY, QTY
				FROM #T_MKT_FCST A
				) A
			LEFT OUTER JOIN 
				(
				SELECT ROW_NUM, MAX(ROW_NUM_SUB) AS MAX_ROW_NUM_SUB
				FROM #T_MKT_FCST A
				GROUP BY ROW_NUM
				) B ON A.ROW_NUM = B.ROW_NUM AND A.ROW_NUM_SUB = MAX_ROW_NUM_SUB
			WHERE ( A.ALLOC_SUM_QTY > A.SUM_QTY
					OR 
					B.ROW_NUM IS NOT NULL )
			) B ON A.ROW_NUM = B.ROW_NUM AND A.ROW_NUM_SUB = B.ROW_NUM_SUB





