CREATE PROCEDURE [dbo].[PR_SCP_CAPA_HIST_DATASET]
	 @SCP0049			AS DBO.SCP0049       READONLY
AS
BEGIN
	SET NOCOUNT ON;
	SET TRANSACTION ISOLATION LEVEL READ COMMITTED;

	-- 이력용 변수 설정
	DECLARE @v_job_type		NVARCHAR(10) = 'MERGE';

	-- 이력 저장용 테이블 생성
	IF OBJECT_ID('TEMPDB..#TMP_CAPA_HIST') IS NOT NULL
		DROP TABLE #TMP_CAPA_HIST;

	CREATE TABLE #TMP_CAPA_HIST
	(
		DATA_TABLE			NVARCHAR(030)
	  , DATA_TYPE			NVARCHAR(030)
	  , COMPANY_ID			NVARCHAR(030)
	  , DIVISION_ID			NVARCHAR(030)
	  , SITE_ID				NVARCHAR(030)
	  , PLANT_ID			NVARCHAR(030)
	  , FACTORY_ID			NVARCHAR(030)
	  , LINE_ID				NVARCHAR(030)
	  , ELECTRODE_TYPE		NVARCHAR(030)
	  , OPERATION_ID		NVARCHAR(030)
	  , LOSS_CODE			NVARCHAR(030)
	  , ITEM_ID				NVARCHAR(030)
	  , LANE_QTY			NVARCHAR(030)
	  , DAY_NAME			NVARCHAR(030)
	  , UPDATE_ID			NVARCHAR(030)
	)

	BEGIN
		
		INSERT INTO #TMP_CAPA_HIST
		(
			  DATA_TABLE
			, DATA_TYPE
			, LOSS_CODE
			, DIVISION_ID
			, COMPANY_ID
			, SITE_ID
			, PLANT_ID
			, FACTORY_ID
			, LINE_ID
			, ELECTRODE_TYPE
			, OPERATION_ID
			, ITEM_ID
			, LANE_QTY
			, DAY_NAME
			, UPDATE_ID
		)
		SELECT P_DATA_TABLE
			, P_DATA_TYPE
			, P_LOSS_CODE
			, P_DIVISION_ID
			, P_COMPANY_ID
			, P_SITE_ID
			, P_PLANT_ID
			, P_FACTORY_ID
			, P_LINE_ID
			, P_ELECTRODE_TYPE
			, P_OPERATION_ID
			, P_ITEM_ID
			, P_LANE_QTY
			, P_DAY_NAME
			, P_UPDATE_ID
		  FROM @SCP0049
		 WHERE P_DATA_TABLE IN ('LA','T','Y') -- LINE ASSIGN, TACT TIME , YIELD 만 생성
		;

		-- 삭제( LINE ASSIGN 9 값) 인 TACT TIME , YIELD 이력 저장
		-- 기존 변경 데이터가 있으면 제외 처리
		INSERT INTO #TMP_CAPA_HIST
		(
			  DATA_TABLE
			, DATA_TYPE
			, LOSS_CODE
			, DIVISION_ID
			, COMPANY_ID
			, SITE_ID
			, PLANT_ID
			, FACTORY_ID
			, LINE_ID
			, ELECTRODE_TYPE
			, OPERATION_ID
			, ITEM_ID
			, LANE_QTY
			, DAY_NAME
			, UPDATE_ID
		)
		SELECT 'T'	AS DATA_TABLE
			 , P_DATA_TYPE
			 , P_LOSS_CODE
			 , P_DIVISION_ID
			 , P_COMPANY_ID
			 , P_SITE_ID
			 , P_PLANT_ID
			 , P_FACTORY_ID
			 , P_LINE_ID
			 , P_ELECTRODE_TYPE
			 , P_OPERATION_ID
			 , P_ITEM_ID
			 , P_LANE_QTY
			 , P_DAY_NAME
			 , P_UPDATE_ID
		  FROM @SCP0049 A
		 WHERE P_DATA_TABLE = 'LA'
		   AND P_DATA_TYPE  <> 'LQ'
		   AND ISNULL(CONVERT(INT,CONVERT(NUMERIC(20,10),P_DAY_QTY)),0) =  9
		   AND NOT EXISTS(SELECT 1
							FROM #TMP_CAPA_HIST X
						   WHERE A.P_FACTORY_ID		= X.FACTORY_ID
							 AND A.P_LINE_ID		= X.LINE_ID
							 AND A.P_OPERATION_ID	= X.OPERATION_ID
							 AND A.P_ELECTRODE_TYPE	= X.ELECTRODE_TYPE
							 AND A.P_ITEM_ID		= X.ITEM_ID
							 AND A.P_DAY_NAME		= X.DAY_NAME
							 AND A.P_DATA_TYPE		= X.DATA_TYPE
							 AND X.DATA_TABLE		= 'T'
							)
		 ;




		INSERT INTO #TMP_CAPA_HIST
		(
			  DATA_TABLE
			, DATA_TYPE
			, LOSS_CODE
			, DIVISION_ID
			, COMPANY_ID
			, SITE_ID
			, PLANT_ID
			, FACTORY_ID
			, LINE_ID
			, ELECTRODE_TYPE
			, OPERATION_ID
			, ITEM_ID
			, LANE_QTY
			, DAY_NAME
			, UPDATE_ID
		)
		SELECT 'Y'	AS DATA_TABLE
			 , P_DATA_TYPE
			 , P_LOSS_CODE
			 , P_DIVISION_ID
			 , P_COMPANY_ID
			 , P_SITE_ID
			 , P_PLANT_ID
			 , P_FACTORY_ID
			 , P_LINE_ID
			 , P_ELECTRODE_TYPE
			 , P_OPERATION_ID
			 , P_ITEM_ID
			 , P_LANE_QTY
			 , P_DAY_NAME
			 , P_UPDATE_ID
		  FROM @SCP0049 A
		 WHERE P_DATA_TABLE = 'LA'
		   AND P_DATA_TYPE  <> 'LQ'
		   AND ISNULL(CONVERT(INT,CONVERT(NUMERIC(20,10),P_DAY_QTY)),0) =  9
		   AND NOT EXISTS(SELECT 1
							FROM #TMP_CAPA_HIST X
						   WHERE A.P_FACTORY_ID		= X.FACTORY_ID
							 AND A.P_LINE_ID		= X.LINE_ID
							 AND A.P_OPERATION_ID	= X.OPERATION_ID
							 AND A.P_ITEM_ID		= X.ITEM_ID
							 AND A.P_DAY_NAME		= X.DAY_NAME
							 AND A.P_DATA_TYPE		= X.DATA_TYPE
							 AND X.DATA_TABLE		= 'Y'
							)
		;

		-- 삭제( LINE ASSIGN 9 값) 인 LINE ASSIGN 이력 저장
		-- 월 삭제인 경우 일자 이력 저장을 위해 일별 데이터 생성
		INSERT INTO #TMP_CAPA_HIST
		(
			  DATA_TABLE
			, DATA_TYPE
			, LOSS_CODE
			, DIVISION_ID
			, COMPANY_ID
			, SITE_ID
			, PLANT_ID
			, FACTORY_ID
			, LINE_ID
			, ELECTRODE_TYPE
			, OPERATION_ID
			, ITEM_ID
			, LANE_QTY
			, DAY_NAME
			, UPDATE_ID
		)
		SELECT 'LA'	AS DATA_TABLE
			 , 'D'	AS DATA_TYPE
			 , P_LOSS_CODE
			 , P_DIVISION_ID
			 , P_COMPANY_ID
			 , P_SITE_ID
			 , P_PLANT_ID
			 , P_FACTORY_ID
			 , P_LINE_ID
			 , P_ELECTRODE_TYPE
			 , P_OPERATION_ID
			 , P_ITEM_ID
			 , P_LANE_QTY
			 , T.BASIS_YYYYMMDD	AS DAY_NAME
			 , P_UPDATE_ID
		  FROM @SCP0049 A
		 
		 CROSS APPLY ( SELECT DISTINCT BASIS_YYYYMM , BASIS_YYYYMMDD
						 FROM SCM_SYS_CALENDAR_M B  WITH(NOLOCK)  
						WHERE A.P_DAY_NAME	= B.BASIS_YYYYMM) T
		 WHERE P_DATA_TABLE = 'LA'
		   AND ISNULL(CONVERT(INT,CONVERT(NUMERIC(20,10),P_DAY_QTY)),0) =  9
		   AND P_DATA_TYPE = 'M'
		   AND NOT EXISTS(SELECT 1
							FROM #TMP_CAPA_HIST X
						   WHERE A.P_FACTORY_ID		= X.FACTORY_ID
							 AND A.P_LINE_ID		= X.LINE_ID
							 AND A.P_OPERATION_ID	= X.OPERATION_ID
							 AND A.P_ELECTRODE_TYPE	= X.ELECTRODE_TYPE
							 AND A.P_ITEM_ID		= X.ITEM_ID
							 AND T.BASIS_YYYYMMDD	= X.DAY_NAME
							 AND A.P_DATA_TYPE		= X.DATA_TYPE
							 AND X.DATA_TABLE		= 'LA'
							)
		 ;

		-- 삭제( LINE ASSIGN 9 값) 인 TACT TIME , YIELD 이력 저장
		-- 월 삭제인 경우 일자 이력 저장을 위해 일별 데이터 생성
		INSERT INTO #TMP_CAPA_HIST
		(
			  DATA_TABLE
			, DATA_TYPE
			, LOSS_CODE
			, DIVISION_ID
			, COMPANY_ID
			, SITE_ID
			, PLANT_ID
			, FACTORY_ID
			, LINE_ID
			, ELECTRODE_TYPE
			, OPERATION_ID
			, ITEM_ID
			, LANE_QTY
			, DAY_NAME
			, UPDATE_ID
		)
		SELECT 'T'	AS DATA_TABLE
			 , 'D'	AS DATA_TYPE
			 , P_LOSS_CODE
			 , P_DIVISION_ID
			 , P_COMPANY_ID
			 , P_SITE_ID
			 , P_PLANT_ID
			 , P_FACTORY_ID
			 , P_LINE_ID
			 , P_ELECTRODE_TYPE
			 , P_OPERATION_ID
			 , P_ITEM_ID
			 , P_LANE_QTY
			 , T.BASIS_YYYYMMDD	AS DAY_NAME
			 , P_UPDATE_ID
		  FROM @SCP0049 A
		 
		 CROSS APPLY ( SELECT DISTINCT BASIS_YYYYMM , BASIS_YYYYMMDD
						 FROM SCM_SYS_CALENDAR_M B  WITH(NOLOCK)  
						WHERE A.P_DAY_NAME	= B.BASIS_YYYYMM) T
		 WHERE P_DATA_TABLE = 'LA'
		   AND ISNULL(CONVERT(INT,CONVERT(NUMERIC(20,10),P_DAY_QTY)),0) =  9
		   AND P_DATA_TYPE = 'M'
		   AND NOT EXISTS(SELECT 1
							FROM #TMP_CAPA_HIST X
						   WHERE A.P_FACTORY_ID		= X.FACTORY_ID
							 AND A.P_LINE_ID		= X.LINE_ID
							 AND A.P_OPERATION_ID	= X.OPERATION_ID
							 AND A.P_ELECTRODE_TYPE	= X.ELECTRODE_TYPE
							 AND A.P_ITEM_ID		= X.ITEM_ID
							 AND T.BASIS_YYYYMMDD	= X.DAY_NAME
							 AND A.P_DATA_TYPE		= X.DATA_TYPE
							 AND X.DATA_TABLE		= 'T'
							)
		 ;

		-- 삭제( LINE ASSIGN 9 값) 인 TACT TIME , YIELD 이력 저장
		-- 월 삭제인 경우 일자 이력 저장을 위해 일별 데이터 생성
		INSERT INTO #TMP_CAPA_HIST
		(
			  DATA_TABLE
			, DATA_TYPE
			, LOSS_CODE
			, DIVISION_ID
			, COMPANY_ID
			, SITE_ID
			, PLANT_ID
			, FACTORY_ID
			, LINE_ID
			, ELECTRODE_TYPE
			, OPERATION_ID
			, ITEM_ID
			, LANE_QTY
			, DAY_NAME
			, UPDATE_ID
		)
		SELECT 'Y'	AS DATA_TABLE
			 , 'D'	AS DATA_TYPE
			 , P_LOSS_CODE
			 , P_DIVISION_ID
			 , P_COMPANY_ID
			 , P_SITE_ID
			 , P_PLANT_ID
			 , P_FACTORY_ID
			 , P_LINE_ID
			 , P_ELECTRODE_TYPE
			 , P_OPERATION_ID
			 , P_ITEM_ID
			 , P_LANE_QTY
			 , T.BASIS_YYYYMMDD	AS DAY_NAME
			 , P_UPDATE_ID
		  FROM @SCP0049 A
		 
		 CROSS APPLY ( SELECT DISTINCT BASIS_YYYYMM , BASIS_YYYYMMDD
						 FROM SCM_SYS_CALENDAR_M B  WITH(NOLOCK)  
						WHERE A.P_DAY_NAME	= B.BASIS_YYYYMM) T
		 WHERE P_DATA_TABLE = 'LA'
		   AND ISNULL(CONVERT(INT,CONVERT(NUMERIC(20,10),P_DAY_QTY)),0) =  9
		   AND P_DATA_TYPE = 'M'
		   AND NOT EXISTS(SELECT 1
							FROM #TMP_CAPA_HIST X
						   WHERE A.P_FACTORY_ID		= X.FACTORY_ID
							 AND A.P_LINE_ID		= X.LINE_ID
							 AND A.P_OPERATION_ID	= X.OPERATION_ID
							 AND A.P_ITEM_ID		= X.ITEM_ID
							 AND T.BASIS_YYYYMMDD	= X.DAY_NAME
							 AND A.P_DATA_TYPE		= X.DATA_TYPE
							 AND X.DATA_TABLE		= 'Y'
							)
		;

		-- LINE ASSIGN 월별 이력 저장
		INSERT INTO HIS_ITEM_LINE_ASSIGN_M_SN
		(
			  COMPANY_ID	,DIVISION_ID		,SITE_ID	,PLANT_ID			,FACTORY_ID
			, OPERATION_ID	,LINE_ID,ITEM_ID	,LANE_QTY
			, MONTH			,WORK_CENTER_ID		,PRIORITY	,CERTIFICATION_FLAG	,CERTIFICATION_DATE	,ACTIVE_FLAG
			, INSERT_ID		,INSERT_TIME		,UPDATE_ID	,UPDATE_TIME
			, WIP_LEVEL_QTY	,ELECTRODE_TYPE
			, JOB_USER_ID	,JOB_TIME			,JOB_TYPE
		)
		SELECT M.COMPANY_ID		,M.DIVISION_ID		,M.SITE_ID		,M.PLANT_ID				,M.FACTORY_ID
			 , M.OPERATION_ID	,M.LINE_ID			,M.ITEM_ID		,M.LANE_QTY
			 , M.MONTH			,M.WORK_CENTER_ID	,M.PRIORITY		,M.CERTIFICATION_FLAG	,M.CERTIFICATION_DATE	,M.ACTIVE_FLAG
			 , M.INSERT_ID		,M.INSERT_TIME		,M.UPDATE_ID	,M.UPDATE_TIME
			 , M.WIP_LEVEL_QTY	,M.ELECTRODE_TYPE
			 , B.UPDATE_ID		,SYSDATETIME()		,@v_job_type
		  FROM SCM_MST_ITEM_LINE_ASSIGN_SN M WITH(NOLOCK)
		  JOIN #TMP_CAPA_HIST B
		    ON M.COMPANY_ID		= B.COMPANY_ID
		   AND M.DIVISION_ID	= B.DIVISION_ID
		   AND M.SITE_ID		= B.SITE_ID
		   AND M.PLANT_ID		= B.PLANT_ID
		   AND M.FACTORY_ID		= B.FACTORY_ID
		   AND M.ITEM_ID		= B.ITEM_ID
		   AND M.OPERATION_ID	= B.OPERATION_ID
		   AND M.LINE_ID		= B.LINE_ID
		   AND M.ELECTRODE_TYPE	= B.ELECTRODE_TYPE
		   AND M.MONTH			>= CONVERT(NVARCHAR(6), GETDATE() , 112) 
		 WHERE DATA_TYPE = 'LQ'
		;

		-- LINE ASSIGN 일별 이력 저장
		INSERT INTO HIS_ITEM_LINE_ASSIGN_EXCEPT_M_SN
		(     COMPANY_ID	,DIVISION_ID	,SITE_ID	,PLANT_ID		,FACTORY_ID
			, ITEM_ID		,OPERATION_ID	,LINE_ID	,WORK_CENTER_ID	,PRIORITY
			, START_TIME    ,END_TIME		,DESCRIPTION,ACTIVE_FLAG
			, ELECTRODE_TYPE,LANE_QTY
			, INSERT_ID		,INSERT_TIME	,UPDATE_ID	,UPDATE_TIME
			, JOB_USER_ID	,JOB_TIME		,JOB_TYPE
		)
		SELECT M.COMPANY_ID		,M.DIVISION_ID		,M.SITE_ID		,M.PLANT_ID			,M.FACTORY_ID
			 , M.ITEM_ID			,M.OPERATION_ID	,M.LINE_ID		,M.WORK_CENTER_ID	,M.PRIORITY
			 , M.START_TIME		,M.END_TIME			,M.DESCRIPTION	,M.ACTIVE_FLAG
			 , M.ELECTRODE_TYPE	,M.LANE_QTY
			 , M.INSERT_ID		,M.INSERT_TIME		,M.UPDATE_ID	,M.UPDATE_TIME
			 , B.UPDATE_ID		,SYSDATETIME()		,@v_job_type
		  FROM SCM_MST_ITEM_LINE_ASSIGN_EXCEPT_SN M
		  JOIN #TMP_CAPA_HIST B
			ON M.COMPANY_ID		= B.COMPANY_ID
		   AND M.DIVISION_ID	= B.DIVISION_ID
		   AND M.SITE_ID		= B.SITE_ID
		   AND M.PLANT_ID		= B.PLANT_ID
		   AND M.FACTORY_ID		= B.FACTORY_ID
		   AND M.ITEM_ID		= B.ITEM_ID
		   AND M.OPERATION_ID	= B.OPERATION_ID
		   AND M.LINE_ID		= B.LINE_ID
		   AND M.ELECTRODE_TYPE	= B.ELECTRODE_TYPE
		   AND CONVERT(NVARCHAR(6),M.START_TIME,112) >= CONVERT(NVARCHAR(6), GETDATE() , 112) 
		 WHERE DATA_TYPE = 'LQ' 
		;

		-- LINE_ASSIGN 월별 이력 저장
		INSERT INTO HIS_ITEM_LINE_ASSIGN_M_SN
		(
			  COMPANY_ID	,DIVISION_ID		,SITE_ID	,PLANT_ID			,FACTORY_ID
			, OPERATION_ID	,LINE_ID,ITEM_ID	,LANE_QTY
			, MONTH			,WORK_CENTER_ID		,PRIORITY	,CERTIFICATION_FLAG	,CERTIFICATION_DATE	,ACTIVE_FLAG
			, INSERT_ID		,INSERT_TIME		,UPDATE_ID	,UPDATE_TIME
			, WIP_LEVEL_QTY	,ELECTRODE_TYPE
			, JOB_USER_ID	,JOB_TIME			,JOB_TYPE
		)
		SELECT M.COMPANY_ID		,M.DIVISION_ID		,M.SITE_ID		,M.PLANT_ID				,M.FACTORY_ID
			 , M.OPERATION_ID	,M.LINE_ID			,M.ITEM_ID		,M.LANE_QTY
			 , M.MONTH			,M.WORK_CENTER_ID	,M.PRIORITY		,M.CERTIFICATION_FLAG	,M.CERTIFICATION_DATE	,M.ACTIVE_FLAG
			 , M.INSERT_ID		,M.INSERT_TIME		,M.UPDATE_ID	,M.UPDATE_TIME
			 , M.WIP_LEVEL_QTY	,M.ELECTRODE_TYPE
			 , B.UPDATE_ID		,SYSDATETIME()		,@v_job_type
		  FROM SCM_MST_ITEM_LINE_ASSIGN_SN M
		  JOIN ( SELECT COMPANY_ID
					  , DIVISION_ID
					  , SITE_ID
					  , PLANT_ID
					  , FACTORY_ID
					  , ITEM_ID
					  , OPERATION_ID
					  , LINE_ID
					  , ELECTRODE_TYPE
					  , C.BASIS_YYYYMM AS WORK_MONTH
					  , DATA_TYPE
					  , UPDATE_ID
				   FROM #TMP_CAPA_HIST A
				   JOIN (SELECT DISTINCT BASIS_YYYYMM , CALENDAR_YYYY
						   FROM SCM_SYS_CALENDAR_M  WITH(NOLOCK) ) C
					 ON  CASE WHEN DATA_TYPE = 'Y' THEN CALENDAR_YYYY
						      WHEN DATA_TYPE = 'M' THEN BASIS_YYYYMM 
						 END = A.DAY_NAME
				  WHERE A.DATA_TABLE = 'LA'  -- SCM_ITEM_LINE_ASSIGN_M
					AND A.DATA_TYPE IN ( 'M' , 'Y')
				)B
		    ON M.COMPANY_ID		= B.COMPANY_ID
		   AND M.DIVISION_ID	= B.DIVISION_ID
		   AND M.SITE_ID		= B.SITE_ID
		   AND M.PLANT_ID		= B.PLANT_ID
		   AND M.FACTORY_ID		= B.FACTORY_ID
		   AND M.ITEM_ID		= B.ITEM_ID
		   AND M.OPERATION_ID	= B.OPERATION_ID
		   AND M.LINE_ID		= B.LINE_ID
		   AND M.ELECTRODE_TYPE	= B.ELECTRODE_TYPE
		   AND M.MONTH			= B.WORK_MONTH
		;

		-- LINE_ASSIGN 일별 이력 저장
		INSERT INTO HIS_ITEM_LINE_ASSIGN_EXCEPT_M_SN
		(     COMPANY_ID	,DIVISION_ID	,SITE_ID	,PLANT_ID		,FACTORY_ID
			, ITEM_ID		,OPERATION_ID	,LINE_ID	,WORK_CENTER_ID	,PRIORITY
			, START_TIME    ,END_TIME		,DESCRIPTION,ACTIVE_FLAG
			, ELECTRODE_TYPE,LANE_QTY
			, INSERT_ID		,INSERT_TIME	,UPDATE_ID	,UPDATE_TIME
			, JOB_USER_ID	,JOB_TIME		,JOB_TYPE
		)
		SELECT M.COMPANY_ID		,M.DIVISION_ID	,M.SITE_ID		,M.PLANT_ID			,M.FACTORY_ID
			 , M.ITEM_ID		,M.OPERATION_ID	,M.LINE_ID		,M.WORK_CENTER_ID	,M.PRIORITY
			 , M.START_TIME		,M.END_TIME		,M.DESCRIPTION	,M.ACTIVE_FLAG
			 , M.ELECTRODE_TYPE	,M.LANE_QTY
			 , M.INSERT_ID		,M.INSERT_TIME	,M.UPDATE_ID	,M.UPDATE_TIME
			 , B.UPDATE_ID		,SYSDATETIME()	,@v_job_type
		  FROM SCM_MST_ITEM_LINE_ASSIGN_EXCEPT_SN M
		  JOIN #TMP_CAPA_HIST B
		    ON M.COMPANY_ID			= B.COMPANY_ID
		   AND M.DIVISION_ID		= B.DIVISION_ID
		   AND M.SITE_ID			= B.SITE_ID
		   AND M.PLANT_ID			= B.PLANT_ID
		   AND M.FACTORY_ID			= B.FACTORY_ID
		   AND M.ITEM_ID			= B.ITEM_ID
		   AND M.OPERATION_ID		= B.OPERATION_ID
		   AND M.LINE_ID			= B.LINE_ID
		   AND M.ELECTRODE_TYPE		= B.ELECTRODE_TYPE
		   AND ISNULL(M.LANE_QTY,0)	= ISNULL(B.LANE_QTY,0)
		   AND CONVERT(NVARCHAR(8),M.START_TIME,112)	= B.DAY_NAME
		   AND B.DATA_TABLE	= 'LA'
		   AND B.DATA_TYPE	= 'D'

		-- TACT_TIME 월별 이력 저장
		INSERT INTO HIS_TACT_TIME_M_SN
		(
			COMPANY_ID		,DIVISION_ID,SITE_ID		,PLANT_ID	,FACTORY_ID
           ,OPERATION_ID	,LINE_ID	,ITEM_ID		,MONTH
           ,WORK_CENTER_ID	,TACT_TIME	,TACT_TIME_UOM
		   ,ELECTRODE_TYPE	,DAILY_CAPA
           ,INSERT_ID		,INSERT_TIME,UPDATE_ID		,UPDATE_TIME
           ,JOB_USER_ID		,JOB_TIME	,JOB_TYPE
		)
		SELECT M.COMPANY_ID		,M.DIVISION_ID	,M.SITE_ID		,M.PLANT_ID	,M.FACTORY_ID
			 , M.OPERATION_ID	,M.LINE_ID		,M.ITEM_ID		,M.MONTH
			 , M.WORK_CENTER_ID	,M.TACT_TIME	,M.TACT_TIME_UOM
			 , M.ELECTRODE_TYPE	,M.DAILY_CAPA
			 , M.INSERT_ID		,M.INSERT_TIME	,M.UPDATE_ID	,M.UPDATE_TIME
			 , B.UPDATE_ID		,SYSDATETIME()	,@v_job_type
		  FROM SCM_MST_TACT_TIME_SN M WITH(NOLOCK)
		  JOIN ( SELECT A.COMPANY_ID
					, A.DIVISION_ID
					, A.SITE_ID
					, A.PLANT_ID
					, A.FACTORY_ID
					, A.ITEM_ID
					, A.OPERATION_ID
					, A.LINE_ID
					, A.ELECTRODE_TYPE
					, C.BASIS_YYYYMM		AS WORK_MONTH
					, A.UPDATE_ID
				FROM #TMP_CAPA_HIST A
				JOIN (SELECT DISTINCT BASIS_YYYYMM , CALENDAR_YYYY
						FROM SCM_SYS_CALENDAR_M  WITH(NOLOCK) ) C
				  ON CASE WHEN DATA_TYPE = 'Y' THEN CALENDAR_YYYY
					  	  WHEN DATA_TYPE = 'M' THEN BASIS_YYYYMM
					 END = A.DAY_NAME
			   WHERE DATA_TABLE		= 'T'   -- SCM_TACT_TIME_M
				 AND DATA_TYPE		IN ( 'M' , 'Y') 
				) B
		   ON M.COMPANY_ID		= B.COMPANY_ID
		  AND M.DIVISION_ID		= B.DIVISION_ID
		  AND M.SITE_ID			= B.SITE_ID
		  AND M.PLANT_ID		= B.PLANT_ID
		  AND M.FACTORY_ID		= B.FACTORY_ID
		  AND M.ITEM_ID			= B.ITEM_ID
		  AND M.OPERATION_ID	= B.OPERATION_ID
		  AND M.LINE_ID			= B.LINE_ID
		  AND M.ELECTRODE_TYPE	= B.ELECTRODE_TYPE
		  AND M.MONTH			= B.WORK_MONTH
		;

		-- TACT_TIME 일별 이력 저장
		INSERT INTO HIS_TACT_TIME_EXCEPT_M_SN
		(
			 COMPANY_ID		,DIVISION_ID,SITE_ID	,PLANT_ID		,FACTORY_ID
           , OPERATION_ID	,LINE_ID    ,ITEM_ID	,WORK_CENTER_ID	,TACT_TIME
           , TACT_TIME_UOM	,START_TIME ,END_TIME	,ACTIVE_FLAG
		   , ELECTRODE_TYPE	,DAILY_CAPA
           , INSERT_ID		,INSERT_TIME,UPDATE_ID	,UPDATE_TIME
		   , JOB_USER_ID	,JOB_TIME   ,JOB_TYPE
		)
		SELECT M.COMPANY_ID		,M.DIVISION_ID	,M.SITE_ID	,M.PLANT_ID			,M.FACTORY_ID
             , M.OPERATION_ID	,M.LINE_ID		,M.ITEM_ID	,M.WORK_CENTER_ID	,M.TACT_TIME
             , M.TACT_TIME_UOM	,M.START_TIME	,M.END_TIME	,M.ACTIVE_FLAG
		     , M.ELECTRODE_TYPE	,M.DAILY_CAPA
             , M.INSERT_ID		,M.INSERT_TIME	,M.UPDATE_ID,M.UPDATE_TIME
		     , B.UPDATE_ID		,SYSDATETIME()	,@v_job_type
		  FROM SCM_MST_TACT_TIME_EXCEPT_SN M WITH(NOLOCK)
		  JOIN #TMP_CAPA_HIST B
		    ON M.COMPANY_ID				= B.COMPANY_ID
		   AND M.DIVISION_ID			= B.DIVISION_ID
		   AND M.SITE_ID				= B.SITE_ID
		   AND M.PLANT_ID				= B.PLANT_ID
		   AND M.FACTORY_ID				= B.FACTORY_ID
		   AND M.ITEM_ID				= B.ITEM_ID
		   AND M.OPERATION_ID			= B.OPERATION_ID
		   AND M.LINE_ID				= B.LINE_ID
		   AND M.ELECTRODE_TYPE			= B.ELECTRODE_TYPE
		   AND CONVERT(NVARCHAR(8),M.START_TIME,112)	= B.DAY_NAME
		 WHERE DATA_TABLE = 'T'
		   AND DATA_TYPE = 'D' 
		;


		-- YIELD 월별 이력 저장
		INSERT INTO HIS_YIELD_M_SN
		(	COMPANY_ID	,DIVISION_ID	,SITE_ID	,PLANT_ID	,FACTORY_ID
           ,OPERATION_ID,LINE_ID		,ITEM_ID	,MONTH		,WORK_CENTER_ID
           ,YIELD		,DESCRIPTION           
		   ,INSERT_ID	,INSERT_TIME	,UPDATE_ID	,UPDATE_TIME
           ,JOB_USER_ID	,JOB_TIME		,JOB_TYPE
		)
		SELECT M.COMPANY_ID		,M.DIVISION_ID	,M.SITE_ID		,M.PLANT_ID	,M.FACTORY_ID
			 , M.OPERATION_ID	,M.LINE_ID		,M.ITEM_ID		,M.MONTH	,M.WORK_CENTER_ID
			 , M.YIELD			,M.DESCRIPTION           
			 , M.INSERT_ID		,M.INSERT_TIME	,M.UPDATE_ID	,M.UPDATE_TIME
			 , B.UPDATE_ID		,SYSDATETIME()	,@v_job_type
		  FROM SCM_MST_YIELD_SN M WITH(NOLOCK)
		  JOIN (SELECT COMPANY_ID
					 , DIVISION_ID
					 , SITE_ID
					 , PLANT_ID
					 , FACTORY_ID
					 , ITEM_ID
					 , OPERATION_ID
					 , LINE_ID
					 , C.BASIS_YYYYMM		AS WORK_MONTH
					 , DATA_TYPE
					 , UPDATE_ID
				  FROM #TMP_CAPA_HIST X
				  JOIN (SELECT DISTINCT BASIS_YYYYMM , CALENDAR_YYYY
							FROM SCM_SYS_CALENDAR_M WITH(NOLOCK) ) C
					ON  CASE WHEN DATA_TYPE = 'Y' THEN CALENDAR_YYYY
							 WHEN DATA_TYPE = 'M' THEN BASIS_YYYYMM 
						END = X.DAY_NAME

				 WHERE DATA_TABLE = 'Y'
				   AND DATA_TYPE IN ( 'M' , 'Y')
				) B
			ON M.COMPANY_ID		= B.COMPANY_ID
		   AND M.DIVISION_ID	= B.DIVISION_ID
		   AND M.SITE_ID		= B.SITE_ID
		   AND M.PLANT_ID		= B.PLANT_ID
		   AND M.FACTORY_ID		= B.FACTORY_ID
		   AND M.ITEM_ID		= B.ITEM_ID
		   AND M.OPERATION_ID	= B.OPERATION_ID
		   AND M.LINE_ID		= B.LINE_ID
		   AND M.MONTH			= B.WORK_MONTH
		;

		-- YIELD 일별 이력 저장
		INSERT INTO HIS_YIELD_EXCEPT_M_SN
		(
			COMPANY_ID	,DIVISION_ID	,SITE_ID	,PLANT_ID		,FACTORY_ID
           ,OPERATION_ID,LINE_ID		,ITEM_ID    ,WORK_CENTER_ID ,YIELD
           ,START_TIME	,END_TIME		,ACTIVE_FLAG
           ,INSERT_ID	,INSERT_TIME	,UPDATE_ID  ,UPDATE_TIME
           ,JOB_USER_ID	,JOB_TIME		,JOB_TYPE
		)
		SELECT M.COMPANY_ID		,M.DIVISION_ID	,M.SITE_ID		,M.PLANT_ID			,M.FACTORY_ID
             , M.OPERATION_ID	,M.LINE_ID		,M.ITEM_ID		,M.WORK_CENTER_ID	,M.YIELD
             , M.START_TIME		,M.END_TIME		,M.ACTIVE_FLAG
             , M.INSERT_ID		,M.INSERT_TIME	,M.UPDATE_ID	,M.UPDATE_TIME
             , B.UPDATE_ID		,SYSDATETIME()	,@v_job_type
		  FROM SCM_MST_YIELD_EXCEPT_SN M WITH(NOLOCK)
		  JOIN #TMP_CAPA_HIST B
		    ON M.COMPANY_ID		= B.COMPANY_ID
		   AND M.DIVISION_ID	= B.DIVISION_ID
		   AND M.SITE_ID		= B.SITE_ID
		   AND M.PLANT_ID		= B.PLANT_ID
		   AND M.FACTORY_ID		= B.FACTORY_ID
		   AND M.ITEM_ID		= B.ITEM_ID
		   AND M.OPERATION_ID	= B.OPERATION_ID
		   AND M.LINE_ID		= B.LINE_ID
		   AND CONVERT(NVARCHAR(8),M.START_TIME,112)	= B.DAY_NAME
		 WHERE B.DATA_TABLE = 'Y'
		   AND B.DATA_TYPE  = 'D'
		;

