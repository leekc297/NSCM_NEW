 --CELL_PROD_SITE Key 컬럼 제외한 데이터 제공(2024.07월 이후에 원복 예정)
SELECT
	  A.DATA_TYPE
	, CASE WHEN A.DIVISION_ID LIKE '81%' THEN '81' ELSE A.DIVISION_ID END AS DIVISION_ID
	, A.VERSION_NO
	, A.CUTOFF_TYPE
	, A.CUTOFF_YYYYMMDD
	, A.DEPARTMENT_ID
	, A.DEPARTMENT_NAME
	, A.DEPT_ID
	, A.DEPT_NAME
	, MAX(A.END_CUST_REPORT)			AS END_CUST_REPORT
	, MAX(A.CUST_REPORT)				AS CUST_REPORT
	, MAX(A.PRODUCT_GROUP)				AS PRODUCT_GROUP
	, A.PROJECT_CODE
	, A.SCM_SITE_ID
	, A.ITEM_ID
	, A.DOM_EXP
	, A.FCST_TYPE
	, A.INCOTERMS
	, A.MEASURE
	, A.PLANT_SITE_ID
	, A.YYYYMMDD
	, A.CURRENCY
	, SUM( A.QTY )					AS QTY
	, MAX(A.CREATED_BY)				AS CREATED_BY
	, MAX(A.CREATION_DATE)			AS CREATION_DATE
	, MAX(A.LAST_UPDATED_BY)		AS LAST_UPDATED_BY
	, MAX(A.LAST_UPDATE_DATE)		AS LAST_UPDATE_DATE
	, MAX(A.ATTRIBUTE1 )			AS ATTRIBUTE1
	, MAX(A.ATTRIBUTE2 )			AS ATTRIBUTE2
	, MAX(A.ATTRIBUTE3 )			AS ATTRIBUTE3
	, MAX(A.ATTRIBUTE4 )			AS ATTRIBUTE4
	, MAX(A.ATTRIBUTE5 )			AS ATTRIBUTE5
	, MAX(A.ATTRIBUTE6 )			AS ATTRIBUTE6
	, MAX(A.ATTRIBUTE7 )			AS ATTRIBUTE7
	, MAX(A.ATTRIBUTE8 )			AS ATTRIBUTE8
	, MAX(A.ATTRIBUTE9 )			AS ATTRIBUTE9
	, MAX(A.ATTRIBUTE10)			AS ATTRIBUTE10
	, A.COMPANY_ID
	, MAX(A.SOLDTO_CUST_REPORT)		AS SOLDTO_CUST_REPORT
	, MAX(A.OWNER_NAME)				AS OWNER_NAME
	, MAX(A.CUST_GROUP_DTL)			AS CUST_GROUP_DTL
	, MAX(A.PRODUCT_DETAILS)		AS PRODUCT_DETAILS
	, MAX(A.FORECAST_INFO_SPEC)		AS FORECAST_INFO_SPEC
	, MAX(A.NICK_NAME)				AS NICK_NAME
	, MAX(A.FORECAST_INFO_CELL_MODEL) AS FORECAST_INFO_CELL_MODEL
	, MAX(A.FORECAST_INFO_CELL_PACK_COUNT) AS FORECAST_INFO_CELL_PACK_COUNT
	, MAX(A.FORECAST_INFO_BIZ_TYPE) AS FORECAST_INFO_BIZ_TYPE
	, MAX(A.COMPANY_NAME)			AS COMPANY_NAME
	, MAX(A.APPLICATION)			AS APPLICATION
	, MAX(A.APPLICATION_GR)			AS APPLICATION_GR
	, MAX(A.COUNTRY_KR_NAME)		AS COUNTRY_KR_NAME
	, MAX(A.ROUTE)					AS ROUTE
	, A.COMPO_40
	, A.DIVISION_ID AS SCM_DIVISION_ID
FROM [10.34.221.78,7433].[LGCE_SCMPROD].[dbo].DM_PLN_SALES_PLAN_REPORT_C A with(nolock)
WHERE 1=1 --CUTOFF_YYYYMMDD >= CONVERT(VARCHAR(8), getdate() - 1, 112)
AND   LAST_UPDATE_DATE >= getdate() - 1
GROUP BY A.DATA_TYPE
	, CASE WHEN A.DIVISION_ID LIKE '81%' THEN '81' ELSE A.DIVISION_ID END
	, A.VERSION_NO
	, A.CUTOFF_TYPE
	, A.CUTOFF_YYYYMMDD
	, A.DEPARTMENT_ID
	, A.DEPARTMENT_NAME
	, A.DEPT_ID
	, A.DEPT_NAME
	, A.PROJECT_CODE
	, A.SCM_SITE_ID
	, A.ITEM_ID
	, A.DOM_EXP
	, A.FCST_TYPE
	, A.INCOTERMS
	, A.MEASURE
	, A.PLANT_SITE_ID
	, A.YYYYMMDD
	, A.CURRENCY
	, A.COMPANY_ID
	, A.COMPO_40
	, A.DIVISION_ID 

