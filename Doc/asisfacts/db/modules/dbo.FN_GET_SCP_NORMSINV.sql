CREATE FUNCTION FN_GET_SCP_NORMSINV
(
    @p FLOAT
)
RETURNS FLOAT
AS
BEGIN
    IF (@p < 0 OR @p > 1)
        RETURN NULL;

    DECLARE @a1 FLOAT = -3.969683028665376e+01;
    DECLARE @a2 FLOAT =  2.209460984245205e+02;
    DECLARE @a3 FLOAT = -2.759285104469687e+02;
    DECLARE @a4 FLOAT =  1.383577518672690e+02;
    DECLARE @a5 FLOAT = -3.066479806614716e+01;
    DECLARE @a6 FLOAT =  2.506628277459239e+00;

    DECLARE @b1 FLOAT = -5.447609879822406e+01;
    DECLARE @b2 FLOAT =  1.615858368580409e+02;
    DECLARE @b3 FLOAT = -1.556989798598866e+02;
    DECLARE @b4 FLOAT =  6.680131188771972e+01;
    DECLARE @b5 FLOAT = -1.328068155288572e+01;

    DECLARE @c1 FLOAT = -7.784894002430293e-03;
    DECLARE @c2 FLOAT = -3.223964580411365e-01;
    DECLARE @c3 FLOAT = -2.400758277161838e+00;
    DECLARE @c4 FLOAT = -2.549732539343734e+00;
    DECLARE @c5 FLOAT =  4.374664141464968e+00;
    DECLARE @c6 FLOAT =  2.938163982698783e+00;

    DECLARE @d1 FLOAT =  7.784695709041462e-03;
    DECLARE @d2 FLOAT =  3.224671290700398e-01;
    DECLARE @d3 FLOAT =  2.445134137142996e+00;
    DECLARE @d4 FLOAT =  3.754408661907416e+00;

    DECLARE @q FLOAT;

    IF (@p < 0.02425)
        SET @q = SQRT(-2 * LOG(@p));
    ELSE
        SET @q = SQRT(-2 * LOG(1 - @p));

    DECLARE @t FLOAT;

    IF (ABS(@q) <= 0.425)
        SET @t = @q * @q;
    ELSE
        SET @t = @q;

    SET @t = (((((@c1 * @t + @c2) * @t + @c3) * @t + @c4) * @t + @c5) * @t + @c6) / 
             ((((@d1 * @t + @d2) * @t + @d3) * @t + @d4) * @t + 1.0);

    IF (@q < 0)
        SET @t = -@t;

    RETURN @t;
END;