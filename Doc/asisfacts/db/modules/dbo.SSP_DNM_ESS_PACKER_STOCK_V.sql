





CREATE VIEW [dbo].[SSP_DNM_ESS_PACKER_STOCK_V] AS
/*
 * Program ID   : SSP_DNM_PACKER_STOCK_V
 * Description  : ESS PACKER STOCK,  STORAGE_ID : 6000(구미 People works), E400(남경 People works) 
 * Program History
 *===================================================================================================
 *   Date       In Charge      Description
 *===================================================================================================
 * 2020.01.21  JUHLEE         Initial Release [C20200121-000352]  ESS Packer출하 적용을 위한 PACKER재고 
                              ERP 창고 6000,E400 창고대상으로  SCM_MST_SITE_ITEM에 등록된 SITE기준으로 SCM_SITE_ID 연결
 * 2024.10.01  KHJ            NERP_SSP                              
 */
 --82 PACKER 재고, SCM_MST_SITE_ITEM에 등록된 PACKER만 대상
SELECT   MX.SCM_SITE_ID          
		,ISNULL(DSS.COMPANY_ID, '*') AS COMPANY_ID
		,DSS.DIVISION_ID
		,ISNULL(DSS.SITE_ID, '*')    AS SITE_ID
		,ISNULL(DSS.PLANT_ID, '*')   AS PLANT_ID
		,ISNULL(DSS.FACTORY_ID, '*') AS FACTORY_ID
		,ISNULL(DSS.STORAGE_ID, '*') AS STORAGE_ID
		,DATEADD(DAY,-1,DSS.CUTOFF_DATE) CUTOFF_DATE -- STOCK 내에서 전부 BOH 일자 기준으로 처리되어서 EOH 기준일자로 변경함
		,DSS.SEQ
		,DSS.STOCK_TYPE
		,DSS.ITEM_ID
		,DSS.ITEM_ID  AS ORIGIN_ITEM_ID
		,ISNULL(DSS.QTY2, 0) + ISNULL(DSS.MOVING_QTY, 0) + ISNULL(DSS.DEFECT_QTY, 0) AS SCM_QTY 
		-- 출하가능재고에서 MOVING_QTY 제외 
		,ISNULL(DSS.QTY2, 0)      AS                   SSP_QTY
		,DSS.LANE
		,DSS.PRODUCTION_TYPE
		,DSS.AVAILABLE_DATE
		,DSS.REMAIN_LEAD_TIME
		,DSS.HOLDING_DATE
		,DSS.QTY
		,DSS.QTY_UOM
		,DSS.STOCK_STATUS
		,DSS.OPERATION_ID
		,DSS.LINE_ID
		,DSS.OUTSOURCING_FLAG
		,DSS.OUTSOURCING_FACTORY
		,DSS.DESCRIPTION
		,DSS.FP_APPLY_OPERATION_ID
		,DSS.FP_APPLY_ITEM_ID
		,DSS.FP_APPLY_WIPQTY
		,[DBO].[FN_SCM_SYS_NVL](DSS.WIPHOLD_YN, 'N') WIPHOLD_YN -- 20180511  KIM JIHYE
		,[DBO].[FN_SCM_SYS_NVL](DSS.QMS_HOLD_YN, 'N') QMS_HOLD_YN -- 20191030  추가
		,DSS.WIP_TYPE_CODE
		,DSS.QTY2
		,DSS.MODIFY_FP_APPLY_WIPQTY
		,DSS.MODIFY_DESCRIPTION
		,DSS.CAL_QTY
		,DSS.FORMATION_REWORK_TYPE
		,DSS.INSERT_ID
		,DSS.INSERT_TIME
		,DSS.UPDATE_ID
		,DSS.UPDATE_TIME
		,DSS.LOCATION
		,DSS.MOVING_QTY    -- 2018.08.07 이동중 재고(MOVING_QTY) 추가
		,DSS.CAPA_GRD_CODE -- 2018.10.23 등급 관련 컬럼 추가
		,DSS.VLTG_GRD_CODE -- 2018.10.23 등급 관련 컬럼 추가
		,DSS.RSST_GRD_CODE -- 2018.10.23 등급 관련 컬럼 추가
		,DSS.DEFECT_QTY    -- 2018.10.23 ERP 보류재고 수량 (DEFECT_QTY) 추가
		,DSS.UNHOLD_EXP_DATE -- 20191120 추가
		,DSS.MES_MAP_SLOC    -- 20191120 추가
FROM SCM_DNM_STOCK_SN DSS WITH(NOLOCK) 
JOIN (
		SELECT MS.DIVISION_ID 
		,      MS.PLANT_ID 
		,      MS.SITE_ID 
		,      MS.COMPANY_ID 
		,      MS.SCM_SITE_ID 
		,      MSI.ITEM_ID 
		FROM  SCM_MST_SITE_ITEM MSI WITH(NOLOCK) 
			  JOIN SCM_MST_SITE MS WITH(NOLOCK) 
				ON MSI.DIVISION_ID = MS.DIVISION_ID 
			   AND MSI.SCM_SITE_ID = MS.SCM_SITE_ID 
			   AND MS.SITE_TYPE = 'PLANT'
			   AND MS.OSP_YN = 'Y'
			   AND MS.VALID_YN = 'Y'
	) MX 
	  ON  MX.DIVISION_ID = DSS.DIVISION_ID 
	 AND  MX.SITE_ID = DSS.SITE_ID 
	 AND  MX.ITEM_ID = DSS.ITEM_ID 
JOIN dbo.SCM_MST_ITEM_SN AS M WITH(NOLOCK)
  ON DSS.COMPANY_ID = M.COMPANY_ID
 AND DSS.DIVISION_ID = M.DIVISION_ID
 AND DSS.SITE_ID = M.SITE_ID
 AND DSS.ITEM_ID = M.ITEM_ID
 AND M.ITEM_TYPE = 'P'
WHERE 1=1 
AND   DSS.DIVISION_ID  = '82'
--AND   DSS.STORAGE_ID IN ('6000','E400') 
AND   DSS.STORAGE_ID IN (select CODE from dbo.FN_LIST_LOOKUP_VALUE('SSP_DNM_ESS_PACKER_STOCK_V','PEOPLEWORK_STORAGE')) 
AND   DSS.CUTOFF_DATE  > CONVERT(VARCHAR, DATEADD(D, -3, GETDATE()) ,112) 
AND   DSS.CUTOFF_DATE  <= CONVERT(VARCHAR, GETDATE() ,112) 
 



