CREATE FUNCTION [dbo].[SCM_SITE_TIME] (@site_id nvarchar(max))
RETURNS datetime
BEGIN

 DECLARE @site_time datetime;
  
  SELECT @site_id = ISNULL(MAX(SITE_ID), 'A001')
  FROM   SCM_MST_SITE_SN
  WHERE  SITE_ID = @site_id
  

          SELECT @site_time = CASE  WHEN STANDARD_TIME >= FromDay AND STANDARD_TIME <= ToDay 
                                    THEN DATEADD(HOUR, ISNULL(ISNULL(SUMMER_TIME, INTERVAL), 0), STANDARD_TIME)
                                    ELSE DATEADD(HOUR, ISNULL(INTERVAL, 0), STANDARD_TIME)
                              END
        FROM   SCM_MST_SITE_SN A,
               (
                SELECT GETUTCDATE() AS STANDARD_TIME
               ) B,
               (
                SELECT 
                       DATEADD( HH, +7, CASE WHEN DATEPART(DW,CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-03-01'))=2 THEN DATEADD(DD,13,CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-03-01'))
                        WHEN DATEPART(DW,CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-03-01'))=3  THEN DATEADD(DD,12,CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-03-01'))
                         WHEN DATEPART(DW,CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-03-01'))=4 THEN DATEADD(DD,11,CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-03-01'))
                          WHEN DATEPART(DW,CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-03-01'))=5 THEN DATEADD(DD,10,CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-03-01'))
                           WHEN DATEPART(DW,CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-03-01'))=6 THEN DATEADD(DD,9,CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-03-01'))
                            WHEN DATEPART(DW,CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-03-01'))=7 THEN DATEADD(DD,8,CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-03-01'))
                             WHEN DATEPART(DW,CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-03-01'))=1 THEN DATEADD(DD,7,CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-03-01')) END
                       )AS FromDay     
                     , 
                       DATEADD( HH, +7, CASE WHEN DATEPART(DW,CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-11-01'))=2 THEN DATEADD(DD,6,CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-11-01'))
                        WHEN DATEPART(DW,CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-11-01'))=3 THEN DATEADD(DD,5,CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-11-01'))
                         WHEN DATEPART(DW,CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-11-01'))=4 THEN DATEADD(DD,4,CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-11-01'))
                          WHEN DATEPART(DW,CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-11-01'))=5 THEN DATEADD(DD,3,CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-11-01'))
                           WHEN DATEPART(DW,CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-11-01'))=6 THEN DATEADD(DD,2,CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-11-01'))
                            WHEN DATEPART(DW,CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-11-01'))=7 THEN DATEADD(DD,1,CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-11-01'))
                             WHEN DATEPART(DW,CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-11-01'))=1 THEN CONCAT(SUBSTRING(CONVERT( NVARCHAR(12), GETUTCDATE(), 112),1,4),'-11-01') END
                       ) AS ToDay
               ) C
        WHERE  SITE_ID = @site_id


  RETURN @site_time;
END;
