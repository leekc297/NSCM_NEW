 --R_S_20230911_V003	SP_W_20230831_V001

    EXEC DMF0068_GET_ORDERLIST @p_division_id='40',@P_VERSION_NO='R_B_20230824_V001', @P_FROMDT = '202201', @P_TODT = '202412'
 */
CREATE PROCEDURE [dbo].[DMF0068_GET_ORDERLIST]
 (
  	 @p_division_id		NVARCHAR(MAX)  
	,@p_version_no  	NVARCHAR(MAX) 
	,@p_fromdt  		NVARCHAR(MAX)
	,@p_todt  			NVARCHAR(MAX)
 )
AS
BEGIN
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;
	SET NOCOUNT ON;	
	
	--CELL QTY 정보를 위한 테이블-----------------------------------------------------
	IF OBJECT_ID('TEMPDB..#TEMP_DM_MST_ITEM_SINGLE_V') IS NOT NULL
		DROP TABLE #TEMP_DM_MST_ITEM_SINGLE_V;
	IF OBJECT_ID('TEMPDB..#TEMP_CELL_PACK_COUNT') IS NOT NULL
		DROP TABLE #TEMP_CELL_PACK_COUNT;		
	--PROJECT_INFO-----------------------------------------------------------------
	IF OBJECT_ID('TEMPDB..#TMP_PJTIFO') IS NOT NULL
		DROP TABLE #TMP_PJTIFO;		
	--SALES PLAN-------------------------------------------------------------------
	IF OBJECT_ID('TEMPDB..#TMP_SRESULT_SPLAN') IS NOT NULL
		DROP TABLE #TMP_SRESULT_SPLAN;		
	--BIZ PLAN---------------------------------------------------------------------
	IF OBJECT_ID('TEMPDB..#TMP_BRESULT_BPLAN') IS NOT NULL
		DROP TABLE #TMP_BRESULT_BPLAN;			
		
    DECLARE @V_SQL_TEXT         AS NVARCHAR(MAX);
	DECLARE @V_ORI_VERSION_NO	AS NVARCHAR(100);
	DECLARE @V_PV_LIST			AS NVARCHAR(MAX);
	DECLARE @V_PV_COL_LIST		AS NVARCHAR(MAX);
    DECLARE @V_SORT_ORDER_NO    AS NVARCHAR(50);
    DECLARE @V_PV_COLUMN_NAME   AS NVARCHAR(100);
    DECLARE @v_PV_NAME			AS NVARCHAR(50);
	DECLARE @V_NOW_YYYYMM		AS NVARCHAR(6);		--당월에 대한 데이터를 구하기 위함
	DECLARE @V_LAST_YYYYMM		AS NVARCHAR(6);		--전월에 대한 데이터를 구하기 위함

	SET @V_ORI_VERSION_NO = (SELECT TOP 1 ORI_CUTOFF_VERSION_NO FROM DM_MDF_VERSION WITH(NOLOCK) WHERE DIVISION_ID = @p_division_id AND  VERSION_NO = @p_version_no)

PRINT @V_ORI_VERSION_NO		
	--전월까지는 실적, 당월부터는 계획으로 잡는다
	--당월을 구한다.
	SET @V_NOW_YYYYMM = CONVERT(CHAR(6), GETDATE(), 112)
	--전월을 구한다.	
	SET @V_LAST_YYYYMM = CONVERT(CHAR(6), DATEADD(MM, -1, GETDATE()), 112)	
	
PRINT ( 'A--' + CONVERT(NVARCHAR(30), GETDATE(), 121))

	--월데이터별로 데이터를 만들기 위해서 해당 작업을 진행한다. 
	SELECT @V_PV_LIST = '', @V_PV_COL_LIST = ''
	DECLARE c_bucket CURSOR FAST_FORWARD FOR 
		SELECT 'ISNULL([' + A.BASIS_YYYYMM + '], 0) AS M' + CONVERT(CHAR(10), ROW_NUMBER() OVER(ORDER BY A.BASIS_YYYYMM)) AS COLUMN_NAME
			  ,'[' +  A.BASIS_YYYYMM  + ']' AS PV_name
			  , MIN(A.BASIS_START_DATE) + '_' + CONVERT(CHAR(2), 1) AS SORT_ORDER_NO
		FROM    [dbo].[SCM_SYS_CALENDAR_M] a WITH(NOLOCK)	
		WHERE  A.BASIS_YYYYMM >= @p_fromdt --CONVERT(CHAR(8), CURRENT_TIMESTAMP, 112)
		AND    A.BASIS_YYYYMM <= @p_todt   --CONVERT(CHAR(8), DATEADD(YYYY, 1, CURRENT_TIMESTAMP), 112)
		GROUP BY A.BASIS_YYYYMM
		ORDER BY SORT_ORDER_NO 
		;

	OPEN c_bucket;
	FETCH NEXT FROM c_bucket INTO @v_PV_column_name, @v_PV_name, @v_sort_order_no
		WHILE @@FETCH_STATUS = 0   
		BEGIN  
			SELECT @V_PV_COL_LIST	= @V_PV_COL_LIST + CASE WHEN @V_PV_COL_LIST <> '' THEN ',' ELSE '' END + @V_PV_COLUMN_NAME
				   , @V_PV_LIST		= @V_PV_LIST + CASE WHEN @V_PV_LIST <> '' THEN ',' ELSE '' END + @V_PV_NAME
    
			FETCH NEXT FROM c_Bucket INTO @v_PV_column_name, @v_PV_name, @v_sort_order_no
		END;

    CLOSE c_bucket;  
    DEALLOCATE c_bucket;	

PRINT ( 'B--' + CONVERT(NVARCHAR(30), GETDATE(), 121))

	--MASTER성 데이터이므로 SALES PLAN이나 BIZ PLAN 여부와 관계없이 무조건 필요한 데이터
	---------------------------------------------------------------------------------------------------------------------------------
	--[E20240208-001446]_[영업마케팅 PI팀] 소형 수주관리레포트(Demand Manager)화면 수량정보 수정
	--'RTF(R+P)', 'Business Plan' 메저값에 Business Plan 화면의 'Cell/Pack Count' 수량에 곱한 값을 표출 (셀Biz, 팩 Biz, 정상입력된 모듈 Biz)	
	--Business Plan화면의 Cell Pack Count값 = DM_MST_ITEM_SINGLE_V.FORECAST_INFO_CELL_PACK_COUNT		
	--ITEM_TYPE = SEMI-PRODUCT -> ITEM_TYPE: H
	---------------------------------------------------------------------------------------------------------------------------------
	--1.Business Plan화면 Cell Pack Count값 추출을 위해 해당 부분 임시 테이블에 데이터 보관
	SELECT DIVISION_ID,ITEM_ID,ITEM_NAME,ITEM_CLASS,ITEM_CLASS_NAME,NICK_NAME,ITEM_TYPE,MDM_PROJECT_NAME,MIN_CAPACITY,FORECAST_INFO_BIZ_TYPE,FORECAST_INFO_PRODUCT_GROUP
		,FORECAST_INFO_CELL_MODEL,FORECAST_INFO_CELL_PACK_COUNT,FORECAST_INFO_SPEC,FORECAST_INFOR_VERSION,CELL_TYPE,ENERGE, CELL_QUANTITY 
	INTO #TEMP_DM_MST_ITEM_SINGLE_V
	FROM 
	(
			SELECT	T1.DIVISION_ID,
				T1.ITEM_ID, 
				MAX(T1.ITEM_NAME)					AS ITEM_NAME,				--해당 컬럼이 NULL인 경우가 잇으므로 하나로 통일
				MAX(T1.ITEM_CLASS)					AS ITEM_CLASS,				--해당 컬럼이 NULL인 경우가 잇으므로 하나로 통일
				MAX(T1.ITEM_CLASS_NAME)				AS ITEM_CLASS_NAME,			--해당 컬럼이 NULL인 경우가 잇으므로 하나로 통일
				MAX(T1.NICK_NAME)					AS NICK_NAME,				--닉네임이 NULL인 경우가 있으므로 하나로 통일
				case  min( case when T1.item_type = 'P' then 1					--타입이 사이트와 사업부, 법인에 따라 다양하게 존재 하므로 하나로 통일
								when T1.item_type = 'H' then 2					--또한 가장 완성된 상태의 자재 타입을 판매한다고 가정, 해당 자재타입을 사용함
								when T1.item_type = 'Q' then 3
								else 4 end )  
												when 1 then 'P' 
												when 2 then 'H'
												when 3 then 'Q'
												else 'R' end	AS ITEM_TYPE,
				MAX(T1.MATERIAL_CLASS_NAME				)		AS MATERIAL_CLASS_NAME,
				MAX(T1.ITEM_UOM							)		AS ITEM_UOM,
				MAX(T1.SPEC								)		AS SPEC,
				MAX(T1.MDM_PROJECT_NAME					)		AS MDM_PROJECT_NAME,
				MAX(T1.MIN_CAPACITY						)		AS MIN_CAPACITY,
				MAX(T2.FORECAST_INFO_BIZ_TYPE			)		AS FORECAST_INFO_BIZ_TYPE,
				MAX(T2.FORECAST_INFO_PRODUCT_GROUP		)		AS FORECAST_INFO_PRODUCT_GROUP,
				MAX(T2.FORECAST_INFO_CELL_MODEL			)		AS FORECAST_INFO_CELL_MODEL,
				MAX(T2.FORECAST_INFO_CELL_PACK_COUNT	)		AS FORECAST_INFO_CELL_PACK_COUNT,
				MAX(T2.FORECAST_INFO_SPEC				)		AS FORECAST_INFO_SPEC,
				MAX(T2.FORECAST_INFOR_VERSION			)		AS FORECAST_INFOR_VERSION,
				MAX(T1.ACTIVE_FLAG						)		AS ACTIVE_FLAG,		-- 20180720 ADD 'Y'대상중 1건 추출
				MAX(T2.CELL_TYPE						)		AS CELL_TYPE,		-- 20180911 ADD cell_type
				MAX(T1.ENERGE							)  	    AS ENERGE,			-- 20200116 khsong ADD ENERGE
				MAX(T1.CELL_QUANTITY					)	    AS CELL_QUANTITY,	-- 20200116 khsong ADD CELL_QUANTITY
				MAX(T1.SCP_EXTRA_SPEC)						  AS SCP_EXTRA_SPEC		-- [20210428 SJHAN / CSR ID:C20210323-000420]
			FROM SCM_MST_ITEM_SN T1 WITH(NOLOCK)					
			INNER JOIN ( SELECT DIVISION_ID, LEFT(ITEM_ID, 12) AS ITEM_ID
							, MAX(FORECAST_INFO_BIZ_TYPE) AS FORECAST_INFO_BIZ_TYPE
							, MAX(FORECAST_INFO_PRODUCT_GROUP) AS FORECAST_INFO_PRODUCT_GROUP
							, MAX(FORECAST_INFO_CELL_MODEL) AS FORECAST_INFO_CELL_MODEL
							, MAX(FORECAST_INFO_CELL_PACK_COUNT) AS FORECAST_INFO_CELL_PACK_COUNT
							, MAX(FORECAST_INFO_SPEC) AS FORECAST_INFO_SPEC
							, MAX(FORECAST_INFOR_VERSION) AS FORECAST_INFOR_VERSION
							, MAX(CELL_TYPE) AS CELL_TYPE
						FROM  SCM_MST_ITEM_SN T2 WITH(NOLOCK) 
						GROUP BY DIVISION_ID, LEFT(ITEM_ID, 12)
					) T2 ON T1.DIVISION_ID = T2.DIVISION_ID
				AND SUBSTRING(T1.ITEM_ID,1,12) = T2.ITEM_ID
			WHERE 1=1
			AND		T1.DIVISION_ID = @p_division_id
			AND		T1.ACTIVE_FLAG = 'Y'
			GROUP BY T1.DIVISION_ID, T1.ITEM_ID
	) T2					
	WHERE DIVISION_ID = @p_division_id			
	GROUP BY DIVISION_ID,ITEM_ID,ITEM_NAME,ITEM_CLASS,ITEM_CLASS_NAME,NICK_NAME,ITEM_TYPE,MDM_PROJECT_NAME,MIN_CAPACITY,FORECAST_INFO_BIZ_TYPE,FORECAST_INFO_PRODUCT_GROUP
			,FORECAST_INFO_CELL_MODEL,FORECAST_INFO_CELL_PACK_COUNT,FORECAST_INFO_SPEC,FORECAST_INFOR_VERSION,CELL_TYPE,ENERGE, CELL_QUANTITY
			
PRINT ( 'C--' + CONVERT(NVARCHAR(30), GETDATE(), 121))

	--2.'Cell/Pack Count' 수량 없을 시 DM_BIZ_TYPE_40 룩업에서 동일한 모델코드의 'CELL_PACK_COUNT'의 수량 곱한 값을 표출(모듈 Biz 中 별도 룩업관리 건)
	SELECT F.DIVISION_ID, F.ITEM_ID, F.ITEM_NAME, F.ITEM_CLASS, F.ITEM_CLASS_NAME, F.NICK_NAME, F.ITEM_TYPE, F.MDM_PROJECT_NAME, F.MIN_CAPACITY, F.FORECAST_INFO_BIZ_TYPE, F.FORECAST_INFO_PRODUCT_GROUP, F.FORECAST_INFO_CELL_MODEL
		 , CASE WHEN F.ITEM_ID = LOOKA.MODEL AND F.FORECAST_INFO_CELL_PACK_COUNT = 0 THEN LOOKA.CELL_PACK_COUNT ELSE F.FORECAST_INFO_CELL_PACK_COUNT END AS FORECAST_INFO_CELL_PACK_COUNT
		 , F.FORECAST_INFO_SPEC, F.FORECAST_INFOR_VERSION, F.CELL_TYPE
	INTO #TEMP_CELL_PACK_COUNT
	FROM #TEMP_DM_MST_ITEM_SINGLE_V F
	LEFT JOIN ( 
				SELECT A.MODEL, A.BIZ_TYPE, A.CELL_PACK_COUNT, A.MODEL_RANK 
				FROM 
				(
					SELECT SEGMENT2 AS MODEL, SEGMENT3  AS BIZ_TYPE, SEGMENT4  AS CELL_PACK_COUNT
						 , RANK () OVER ( PARTITION BY SEGMENT2	ORDER BY DISPLAY_SEQ DESC) MODEL_RANK 
					FROM [dbo].[SCM_ADM_LOOKUP_MASTER_DETAIL] WITH(NOLOCK)
					WHERE LOOKUP_TYPE = 'DM_BIZ_TYPE_40' 
					AND SEGMENT1 = '40'
				) A
				WHERE MODEL_RANK = '1'
			) LOOKA
		ON LOOKA.MODEL = F.ITEM_ID		

PRINT ( 'D--' + CONVERT(NVARCHAR(30), GETDATE(), 121))

	--3. Business Plan 화면의 'Cell/Pack Count' 수량이 0 이면 'RTF(R+P)', 'Business Plan' 값을 0으로 표출 (상품 매출)
	--4. 3번의 'Cell/Pack Count'수량이 0이이지만 Item Type= Semi-Product라면, 'RTF(R+P)','Business Plan'값을 그대로 표출 (전극 Biz)
	SELECT A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID ,A.ITEM_ID, A.PROJECT_INFO, B.ITEM_TYPE
		 , CASE WHEN B.ITEM_TYPE = 'H' AND B.FORECAST_INFO_CELL_PACK_COUNT = 0 THEN 1
				ELSE B.FORECAST_INFO_CELL_PACK_COUNT END AS CELL_QTY
	INTO #TMP_PJTIFO
	FROM SCM_MST_SITE_ITEM A WITH(NOLOCK)
	LEFT OUTER JOIN #TEMP_CELL_PACK_COUNT B
				 ON A.DIVISION_ID = B.DIVISION_ID 
				AND A.ITEM_ID = B.ITEM_ID 
	WHERE ISNULL(A.PROJECT_INFO, '') <> ''
	GROUP BY A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID ,A.ITEM_ID, A.PROJECT_INFO, B.ITEM_TYPE, B.FORECAST_INFO_CELL_PACK_COUNT	
	---------------------------------------------------------------------------------------------------------------------------------
	
	--REPORT TYPE: R_S
	IF SUBSTRING(@p_version_no, 1 ,3) = 'R_S'	
	BEGIN

PRINT ( 'E--' + CONVERT(NVARCHAR(30), GETDATE(), 121))

	--구분: SALES_PLAN 
	--해당조건으로 데이터를 구하는 이유는, 소형수주 수주기간외의 데이터는 표출하지 않기때문에, 해당 조건으로 데이터를 표출한다.
	--SRESULT: 소형수주 수주기간내 전체 SUM / SPLAN: 소형수주 수주기간내 전체 PLAN
	--계획구간: DM_PLN_SALES_PLAN_C / 실적구간: DM_PLN_SALES_PLAN_RESULT

		SELECT A.DIVISION_ID, A.PROJECT_CODE, A.YYYYMM_FROM, A.YYYYMM_TO, A.MEASURE, T.YYYYMM
			 , T.GUBUN, SUM(T.SRESULT) AS SRESULT, SUM(T.SPLAN) AS SPLAN, SUM(QTY) AS QTY
		INTO #TMP_SRESULT_SPLAN
		FROM 
		(
			SELECT B.DIVISION_ID, B.PROJECT_CODE, B.YYYYMM_FROM, B.YYYYMM_TO
					, CASE WHEN B.MEASURE = 'MEA_1' THEN 'RTF_SYS_RP' ELSE B.MEASURE END AS MEASURE
			FROM DM_PLN_ORDER_MGT B WITH(NOLOCK)
		) A
		LEFT OUTER JOIN (
							--수주기간별 데이터 추출 목적
							SELECT 'PLAN' AS GUBUN, B.DIVISION_ID, B.PROJECT_CODE, PJT_IFO.PROJECT_INFO, B.SCM_SITE_ID, B.ITEM_ID, B.MEASURE, LEFT(B.YYYYMMDD, 6) AS YYYYMM
									, 0 AS SRESULT, CASE WHEN B.MEASURE = 'RTF_SYS_RP' THEN B.QTY * PJT_IFO.CELL_QTY ELSE B.QTY END AS SPLAN, 0 AS QTY 
							FROM DM_PLN_SALES_PLAN_C B WITH(NOLOCK)
							INNER JOIN #TMP_PJTIFO PJT_IFO
									ON B.PROJECT_CODE = PJT_IFO.PROJECT_CODE
									AND B.ITEM_ID = PJT_IFO.ITEM_ID
									AND B.SCM_SITE_ID = PJT_IFO.SCM_SITE_ID
							WHERE B.DIVISION_ID = @p_division_id
							AND B.MEASURE IN ('RTF_SYS_RP', 'SalesAmt_KRW')
							AND B.VERSION_NO = @V_ORI_VERSION_NO 
							UNION ALL
							--월별 데이터 추출 목적
							SELECT 'PLAN' AS GUBUN, B.DIVISION_ID, B.PROJECT_CODE, PJT_IFO.PROJECT_INFO, B.SCM_SITE_ID, B.ITEM_ID, B.MEASURE, LEFT(B.YYYYMMDD, 6) AS YYYYMM
									, 0 AS SRESULT, 0 AS SPLAN, CASE WHEN B.MEASURE = 'RTF_SYS_RP' THEN B.QTY * PJT_IFO.CELL_QTY ELSE B.QTY END AS QTY 
							FROM DM_PLN_SALES_PLAN_C B WITH(NOLOCK)
							INNER JOIN #TMP_PJTIFO PJT_IFO
									ON B.PROJECT_CODE = PJT_IFO.PROJECT_CODE
									AND B.ITEM_ID = PJT_IFO.ITEM_ID
									AND B.SCM_SITE_ID = PJT_IFO.SCM_SITE_ID
							WHERE B.DIVISION_ID = @p_division_id
							AND B.MEASURE IN ('RTF_SYS_RP', 'SalesAmt_KRW')
							AND B.VERSION_NO = @V_ORI_VERSION_NO
							AND LEFT(B.YYYYMMDD,6) BETWEEN @V_NOW_YYYYMM AND @p_todt
							UNION ALL
							--수주기간별 데이터 추출 목적
							SELECT 'RESULT' AS GUBUN, B.DIVISION_ID, B.PROJECT_CODE, PJT_IFO.PROJECT_INFO, B.SCM_SITE_ID, B.ITEM_ID, B.MEASURE, LEFT(B.YYYYMMDD, 6) AS YYYYMM
									, CASE WHEN B.MEASURE = 'RTF_SYS_RP' THEN B.QTY * PJT_IFO.CELL_QTY ELSE B.QTY END AS SRESULT, 0 AS SPLAN
									, 0 AS QTY 
							FROM DM_PLN_SALES_PLAN_RESULT B WITH(NOLOCK)
							INNER JOIN #TMP_PJTIFO PJT_IFO
									ON B.PROJECT_CODE = PJT_IFO.PROJECT_CODE
									AND B.ITEM_ID = PJT_IFO.ITEM_ID
									AND B.SCM_SITE_ID = PJT_IFO.SCM_SITE_ID
							WHERE B.DIVISION_ID = @p_division_id
							AND B.MEASURE IN ('RTF_SYS_RP', 'SalesAmt_KRW')
							UNION ALL
							--월별 데이터 추출 목적
							SELECT 'RESULT' AS GUBUN, B.DIVISION_ID, B.PROJECT_CODE, PJT_IFO.PROJECT_INFO, B.SCM_SITE_ID, B.ITEM_ID, B.MEASURE, LEFT(B.YYYYMMDD, 6) AS YYYYMM
									, 0 AS SRESULT, 0 AS SPLAN
									, CASE WHEN B.MEASURE = 'RTF_SYS_RP' THEN B.QTY * PJT_IFO.CELL_QTY ELSE B.QTY END AS QTY 
							FROM DM_PLN_SALES_PLAN_RESULT B WITH(NOLOCK)
							INNER JOIN #TMP_PJTIFO PJT_IFO
									ON B.PROJECT_CODE = PJT_IFO.PROJECT_CODE
									AND B.ITEM_ID = PJT_IFO.ITEM_ID
									AND B.SCM_SITE_ID = PJT_IFO.SCM_SITE_ID
							WHERE B.DIVISION_ID = @p_division_id
							AND B.MEASURE IN ('RTF_SYS_RP', 'SalesAmt_KRW')
							AND LEFT(B.YYYYMMDD,6) BETWEEN @p_fromdt AND @V_LAST_YYYYMM
						) T
					ON A.DIVISION_ID = T.DIVISION_ID
					AND A.MEASURE = T.MEASURE
					AND A.PROJECT_CODE = T.PROJECT_INFO
					AND T.YYYYMM >= A.YYYYMM_FROM
					AND T.YYYYMM <= A.YYYYMM_TO
			GROUP BY A.DIVISION_ID, A.PROJECT_CODE, A.YYYYMM_FROM, A.YYYYMM_TO, A.MEASURE, T.YYYYMM, T.GUBUN
			ORDER BY A.DIVISION_ID, A.PROJECT_CODE, A.YYYYMM_FROM, A.YYYYMM_TO, A.MEASURE, T.YYYYMM

PRINT ( 'F--' + CONVERT(NVARCHAR(30), GETDATE(), 121))

	SET @V_SQL_TEXT = N'		
						SELECT B.PROJECT_NAME				--Project
							 , CASE WHEN B.MEASURE = ''RTF_SYS_RP'' THEN ''QTY(Cell)'' ELSE ''Sales Amt.(KRW)'' END AS MEASURE --MEASURE		
							 , B.ORDERSTART					--수주기간(시작)
							 , B.ORDEREND					--수주기간(종료)
							 , B.ORDERAPPROVAL				--수주(품의)
							 , B.ORDERNOW					--수주(현재)
							 , B.SRESULT					--실적
							 , B.SPLAN						--계획
							 , B.ORDERNOW - B.SRESULT AS STOCK --잔고(실적기준)
							 , B.ORDERNOW - B.SRESULT - B.SPLAN AS STOCK2 --잔고(실적+계획 기준)		 
							 , B.ATTRIBUTE1  AS KEYVALUE
							 , B.ATTRIBUTE2	 AS KEYVALUE2
							 , B.MEASURE2
							 , [@V_PV_COL_LIST]    
						FROM 
						(
							SELECT A.PROJECT_CODE, A.PROJECT_NAME, A.YYYYMM_FROM AS ORDERSTART, A.YYYYMM_TO AS ORDEREND
								 , ISNULL(A.ORDER_APPROVAL, 0) AS ORDERAPPROVAL, ISNULL(A.ORDER_NOW, 0) AS ORDERNOW
								 , A.MEASURE, A.MEASURE2, ISNULL(T.SRESULT, 0) AS SRESULT, ISNULL(T.SPLAN, 0) AS SPLAN
								 , A.ATTRIBUTE1 
								 , A.ATTRIBUTE2  
								 , [@V_PV_LIST]    
							FROM
							(
								SELECT A.PROJECT_CODE, A.PROJECT_CODE AS PROJECT_NAME, A.YYYYMM_FROM, A.YYYYMM_TO, A.ORDER_APPROVAL, A.ORDER_NOW 
