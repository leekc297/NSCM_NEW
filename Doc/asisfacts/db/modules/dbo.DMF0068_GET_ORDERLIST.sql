 3. 프로젝트 코드가 아닌 SSPM에 등록한 PROJECT_INFO 단위로 데이터가 표시 되어야한다.
 4. R_S 로 시작하면 SALES PLAN
    실적: DM_PLN_SALES_PLAN_RESULT
