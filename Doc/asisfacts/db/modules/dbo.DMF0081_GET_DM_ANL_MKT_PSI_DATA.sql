	,CASE WHEN T1.MON_06_CUST_FCST_ACCUM_QTY > 0 THEN ((T1.MON_06_MKT_FCST_ACCUM_QTY/T1.MON_06_CUST_FCST_ACCUM_QTY)-1)*100 ELSE 0 END AS AVERAGE_06_SUM
	,CASE WHEN T1.MON_12_CUST_FCST_ACCUM_QTY > 0 THEN ((T1.MON_12_MKT_FCST_ACCUM_QTY/T1.MON_12_CUST_FCST_ACCUM_QTY)-1)*100 ELSE 0 END AS AVERAGE_12_SUM
	,NULL AS SIMULATION_03_SUM --항상 NULL로 해야 COALESCE 에서 정상적으로 가져감
	,NULL AS SIMULATION_06_SUM --항상 NULL로 해야 COALESCE 에서 정상적으로 가져감
	,NULL AS SIMULATION_12_SUM --항상 NULL로 해야 COALESCE 에서 정상적으로 가져감
	,NULL AS DEMAND_SUM --항상 NULL로 해야 COALESCE 에서 정상적으로 가져감
	-----
	,CASE WHEN T1.MON_03_CUST_FCST_ACCUM_QTY > 0 THEN
	 ((SELECT SUM(T1_SUB.CAR_PROD_DTL_QTY)
	 FROM #T1_RAW AS T1_SUB
	 WHERE T1_SUB.PLAN_YYYYMM BETWEEN CONVERT(CHAR(6), DATEADD(MONTH, -3, CONVERT(DATETIME, CONVERT(CHAR(6), T1.PLAN_YYYYMM, 112)+'01')), 112) 
							 	  AND CONVERT(CHAR(6), DATEADD(MONTH, -1, CONVERT(DATETIME, CONVERT(CHAR(6), T1.PLAN_YYYYMM, 112)+'01')), 112)
	 )/T1.MON_03_CUST_FCST_ACCUM_QTY)*100
	ELSE 0 END AS AVERAGE_03_CUSTOMER_DEMAND_CAR_PROD
	-----
	,CASE WHEN T1.MON_06_CUST_FCST_ACCUM_QTY > 0 THEN
	 ((SELECT SUM(T1_SUB.CAR_PROD_DTL_QTY)
	 FROM #T1_RAW AS T1_SUB
	 WHERE T1_SUB.PLAN_YYYYMM BETWEEN CONVERT(CHAR(6), DATEADD(MONTH, -6, CONVERT(DATETIME, CONVERT(CHAR(6), T1.PLAN_YYYYMM, 112)+'01')), 112) 
							 	  AND CONVERT(CHAR(6), DATEADD(MONTH, -1, CONVERT(DATETIME, CONVERT(CHAR(6), T1.PLAN_YYYYMM, 112)+'01')), 112)
	 )/T1.MON_06_CUST_FCST_ACCUM_QTY)*100
	ELSE 0 END AS AVERAGE_06_CUSTOMER_DEMAND_CAR_PROD
	-----
	,CASE WHEN T1.MON_12_CUST_FCST_ACCUM_QTY > 0 THEN
	 ((SELECT SUM(T1_SUB.CAR_PROD_DTL_QTY)
	 FROM #T1_RAW AS T1_SUB
	 WHERE T1_SUB.PLAN_YYYYMM BETWEEN CONVERT(CHAR(6), DATEADD(MONTH, -12, CONVERT(DATETIME, CONVERT(CHAR(6), T1.PLAN_YYYYMM, 112)+'01')), 112) 
							 	  AND CONVERT(CHAR(6), DATEADD(MONTH, -1, CONVERT(DATETIME, CONVERT(CHAR(6), T1.PLAN_YYYYMM, 112)+'01')), 112)
	 )/T1.MON_12_CUST_FCST_ACCUM_QTY)*100
	ELSE 0 END AS AVERAGE_12_CUSTOMER_DEMAND_CAR_PROD
	-----
	,CASE WHEN T1.MON_03_CUST_FCST_ACCUM_QTY > 0 THEN
	 ((SELECT SUM(T1_SUB.CAR_SALES_DTL_QTY)
	 FROM #T1_RAW AS T1_SUB
	 WHERE T1_SUB.PLAN_YYYYMM BETWEEN CONVERT(CHAR(6), DATEADD(MONTH, -3, CONVERT(DATETIME, CONVERT(CHAR(6), T1.PLAN_YYYYMM, 112)+'01')), 112) 
							 	  AND CONVERT(CHAR(6), DATEADD(MONTH, -1, CONVERT(DATETIME, CONVERT(CHAR(6), T1.PLAN_YYYYMM, 112)+'01')), 112)
	 )/T1.MON_03_CUST_FCST_ACCUM_QTY)*100
	ELSE 0 END AS AVERAGE_03_CUSTOMER_DEMAND_CAR_SALES
	-----
	,CASE WHEN T1.MON_06_CUST_FCST_ACCUM_QTY > 0 THEN
	 ((SELECT SUM(T1_SUB.CAR_SALES_DTL_QTY)
	 FROM #T1_RAW AS T1_SUB
	 WHERE T1_SUB.PLAN_YYYYMM BETWEEN CONVERT(CHAR(6), DATEADD(MONTH, -6, CONVERT(DATETIME, CONVERT(CHAR(6), T1.PLAN_YYYYMM, 112)+'01')), 112) 
							 	  AND CONVERT(CHAR(6), DATEADD(MONTH, -1, CONVERT(DATETIME, CONVERT(CHAR(6), T1.PLAN_YYYYMM, 112)+'01')), 112)
	 )/T1.MON_06_CUST_FCST_ACCUM_QTY)*100
	ELSE 0 END AS AVERAGE_06_CUSTOMER_DEMAND_CAR_SALES
	-----
	,CASE WHEN T1.MON_12_CUST_FCST_ACCUM_QTY > 0 THEN
	 ((SELECT SUM(T1_SUB.CAR_SALES_DTL_QTY)
	 FROM #T1_RAW AS T1_SUB
	 WHERE T1_SUB.PLAN_YYYYMM BETWEEN CONVERT(CHAR(6), DATEADD(MONTH, -12, CONVERT(DATETIME, CONVERT(CHAR(6), T1.PLAN_YYYYMM, 112)+'01')), 112) 
							 	  AND CONVERT(CHAR(6), DATEADD(MONTH, -1, CONVERT(DATETIME, CONVERT(CHAR(6), T1.PLAN_YYYYMM, 112)+'01')), 112)
	 )/T1.MON_12_CUST_FCST_ACCUM_QTY)*100
	ELSE 0 END AS AVERAGE_12_CUSTOMER_DEMAND_CAR_SALES
	-----
	,CASE WHEN T1.MON_03_CUST_FCST_ACCUM_QTY > 0 THEN
	 ((SELECT SUM(T1_SUB.DELIVERY_DTL_QTY)
	 FROM #T1_RAW AS T1_SUB
	 WHERE T1_SUB.PLAN_YYYYMM BETWEEN CONVERT(CHAR(6), DATEADD(MONTH, -3, CONVERT(DATETIME, CONVERT(CHAR(6), T1.PLAN_YYYYMM, 112)+'01')), 112) 
							 	  AND CONVERT(CHAR(6), DATEADD(MONTH, -1, CONVERT(DATETIME, CONVERT(CHAR(6), T1.PLAN_YYYYMM, 112)+'01')), 112)
	 )/T1.MON_03_CUST_FCST_ACCUM_QTY)*100
	ELSE 0 END AS AVERAGE_03_CUSTOMER_DEMAND_DELIVERY
	-----
	,CASE WHEN T1.MON_06_CUST_FCST_ACCUM_QTY > 0 THEN
	 ((SELECT SUM(T1_SUB.DELIVERY_DTL_QTY)
	 FROM #T1_RAW AS T1_SUB
	 WHERE T1_SUB.PLAN_YYYYMM BETWEEN CONVERT(CHAR(6), DATEADD(MONTH, -6, CONVERT(DATETIME, CONVERT(CHAR(6), T1.PLAN_YYYYMM, 112)+'01')), 112) 
							 	  AND CONVERT(CHAR(6), DATEADD(MONTH, -1, CONVERT(DATETIME, CONVERT(CHAR(6), T1.PLAN_YYYYMM, 112)+'01')), 112)
	 )/T1.MON_06_CUST_FCST_ACCUM_QTY)*100
	ELSE 0 END AS AVERAGE_06_CUSTOMER_DEMAND_DELIVERY
	-----
	,CASE WHEN T1.MON_12_CUST_FCST_ACCUM_QTY > 0 THEN
	 ((SELECT SUM(T1_SUB.DELIVERY_DTL_QTY)
	 FROM #T1_RAW AS T1_SUB
	 WHERE T1_SUB.PLAN_YYYYMM BETWEEN CONVERT(CHAR(6), DATEADD(MONTH, -12, CONVERT(DATETIME, CONVERT(CHAR(6), T1.PLAN_YYYYMM, 112)+'01')), 112) 
							 	  AND CONVERT(CHAR(6), DATEADD(MONTH, -1, CONVERT(DATETIME, CONVERT(CHAR(6), T1.PLAN_YYYYMM, 112)+'01')), 112)
	 )/T1.MON_12_CUST_FCST_ACCUM_QTY)*100
	ELSE 0 END AS AVERAGE_12_CUSTOMER_DEMAND_DELIVERY
	-----
	,CASE WHEN T1.MON_03_CUST_FCST_ACCUM_QTY > 0 THEN
	 ((SELECT SUM(T1_SUB.MODEL_MIX_DTL_QTY)
