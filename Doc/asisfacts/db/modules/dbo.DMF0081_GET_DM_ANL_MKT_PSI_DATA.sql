CREATE PROCEDURE [dbo].[DMF0081_GET_DM_ANL_MKT_PSI_DATA] 
	 @p_division_id NVARCHAR(30)
	,@p_end_customer NVARCHAR(50)
	,@p_project_code NVARCHAR(50)
AS
BEGIN
	SET NOCOUNT ON;

	DECLARE @YYYYMM1 CHAR(6) = CONVERT(CHAR(6), DATEADD(MONTH, -24, CONVERT(DATETIME, CONVERT(CHAR(6), GETDATE(), 112)+'01')), 112); -- ex) 202212 --24개월전
	DECLARE @YYYYMM2 CHAR(6) = CONVERT(CHAR(6), GETDATE(),112);																		 -- ex) 202412 --이번달
	DECLARE @YYYYMM3 CHAR(6) = CONVERT(CHAR(6), DATEADD(MONTH, -1, CONVERT(DATETIME, CONVERT(CHAR(6), GETDATE(), 112)+'01')), 112);	 -- ex) 202411 --직전달	
	DECLARE @YYYYMM4 CHAR(6) = CONVERT(CHAR(6), DATEADD(MONTH, -12, CONVERT(DATETIME, CONVERT(CHAR(6), GETDATE(), 112)+'01')), 112); -- ex) 202312 --12개월전
	
	-- 테이블중복제거
	IF OBJECT_ID(N'tempdb..#T1_RAW', N'U') IS NOT NULL
		DROP TABLE #T1_RAW

	-- 임시확인용테이블 중복제거
	IF OBJECT_ID(N'dbo.#T1_RAW', N'U') IS NOT NULL
		DROP TABLE #T1_RAW

	CREATE TABLE #T1_RAW(
		DIVISION_ID         NVARCHAR(30),
		END_CUSTOMER        NVARCHAR(50),
		PROJECT_NAME        NVARCHAR(200),
		PROJECT_CODE        NVARCHAR(50),
		MEASURE		        NVARCHAR(50),
		PLAN_YYYYMM         NVARCHAR(6),
		CUST_FCST_QTY       NUMERIC(20,8),
		MKT_FCST_QTY        NUMERIC(20,8),
		--MKT_CUST_GAP	    NUMERIC(20,8),
		M1_CUST_FCST_QTY    NUMERIC(20,8),
		M1_MKT_FCST_QTY     NUMERIC(20,8),
		M2_CUST_FCST_QTY    NUMERIC(20,8),
		M2_MKT_FCST_QTY     NUMERIC(20,8),
		M3_CUST_FCST_QTY    NUMERIC(20,8),
		M3_MKT_FCST_QTY     NUMERIC(20,8),
		TOTAL_QTY 	        NUMERIC(20,8),
		CAR_PROD_DTL_QTY    NUMERIC(20,8),
		CAR_SALES_DTL_QTY	NUMERIC(20,8),
		DELIVERY_DTL_QTY	NUMERIC(20,8),
		SALES_ALLOC_DTL_QTY	NUMERIC(20,8),
		MODEL_MIX_DTL_QTY	NUMERIC(20,8),
		SUPPLY_DTL_QTY		NUMERIC(20,8),
		MON_03_CUST_FCST_ACCUM_QTY  NUMERIC(20,8),
		MON_03_MKT_FCST_ACCUM_QTY   NUMERIC(20,8),
		MON_06_CUST_FCST_ACCUM_QTY  NUMERIC(20,8),
		MON_06_MKT_FCST_ACCUM_QTY   NUMERIC(20,8),
		MON_12_CUST_FCST_ACCUM_QTY NUMERIC(20,8),
		MON_12_MKT_FCST_ACCUM_QTY  NUMERIC(20,8),
		PLAN_YYYYMM_RANK    INT
	)

	INSERT INTO #T1_RAW
	SELECT 
		 S.DIVISION_ID
		,S.END_CUSTOMER
		,S.PROJECT_NAME
		,S.PROJECT_CODE
		,S.MEASURE
		,S.PLAN_YYYYMM
		,MAX(ISNULL(S.CUST_FCST_QTY,0))    AS CST_FCST_QTY
		,MAX(ISNULL(S.MKT_FCST_QTY,0))     AS MKT_FCST_QTY
		--,SUM(S.MKT_FCST_QTY) - SUM(S.CUST_FCST_QTY) AS MKT_CUST_GAP
		,MAX(ISNULL(S.M1_CUST_FCST_QTY,0)) AS M1_CUST_FCST_QTY
		,MAX(ISNULL(S.M1_MKT_FCST_QTY,0))  AS M1_MKT_FCST_QTY
		,MAX(ISNULL(S.M2_CUST_FCST_QTY,0)) AS M2_CUST_FCST_QTY
		,MAX(ISNULL(S.M2_MKT_FCST_QTY,0))  AS M2_MKT_FCST_QTY
		,MAX(ISNULL(S.M3_CUST_FCST_QTY,0)) AS M3_CUST_FCST_QTY
		,MAX(ISNULL(S.M3_MKT_FCST_QTY,0))  AS M3_MKT_FCST_QTY
		,SUM(FLOOR(ISNULL(DTL.QTY,0)))  AS DTL_TOTAL_QTY
		,SUM(IIF(DTL.ANLS_DIF_RSN_CD = 'CAR_PROD',    FLOOR(DTL.QTY), 0)) AS CAR_PROD_DTL_QTY
		,SUM(IIF(DTL.ANLS_DIF_RSN_CD = 'CAR_SALES',   FLOOR(DTL.QTY), 0)) AS CAR_SALES_DTL_QTY
		,SUM(IIF(DTL.ANLS_DIF_RSN_CD = 'DELIVERY',    FLOOR(DTL.QTY), 0)) AS DELIVERY_DTL_QTY
		,SUM(IIF(DTL.ANLS_DIF_RSN_CD = 'SALES_ALLOC', FLOOR(DTL.QTY), 0)) AS SALES_ALLOC_DTL_QTY
		,SUM(IIF(DTL.ANLS_DIF_RSN_CD = 'MODEL_MIX',   FLOOR(DTL.QTY), 0)) AS MODEL_MIX_DTL_QTY
		,SUM(IIF(DTL.ANLS_DIF_RSN_CD = 'SUPPLY',      FLOOR(DTL.QTY), 0)) AS SUPPLY_DTL_QTY
		,( SELECT SUM(ISNULL(SS.CUST_FCST_QTY,0))
			FROM DM_CUST_DEMAND_ANL_SUMMARY SS WITH(NOLOCK)
			WHERE SS.DIVISION_ID  = S.DIVISION_ID
			AND   SS.END_CUSTOMER = S.END_CUSTOMER
			AND   SS.PROJECT_CODE = S.PROJECT_CODE
			AND   SS.MEASURE      = S.MEASURE 
			AND   SS.PLAN_YYYYMM BETWEEN CONVERT(CHAR(6), DATEADD(MONTH, -3, CONVERT(DATETIME, CONVERT(CHAR(6), S.PLAN_YYYYMM, 112)+'01')), 112) 
									 AND CONVERT(CHAR(6), DATEADD(MONTH, -1, CONVERT(DATETIME, CONVERT(CHAR(6), S.PLAN_YYYYMM, 112)+'01')), 112)
		) AS MON_03_CUST_FCST_ACCUM_QTY
		,( SELECT SUM(ISNULL(SS.MKT_FCST_QTY,0))
			FROM DM_CUST_DEMAND_ANL_SUMMARY SS WITH(NOLOCK)
			WHERE SS.DIVISION_ID  = S.DIVISION_ID
			AND   SS.END_CUSTOMER = S.END_CUSTOMER
			AND   SS.PROJECT_CODE = S.PROJECT_CODE
			AND   SS.MEASURE      = S.MEASURE 
			AND   SS.PLAN_YYYYMM BETWEEN CONVERT(CHAR(6), DATEADD(MONTH, -3, CONVERT(DATETIME, CONVERT(CHAR(6), S.PLAN_YYYYMM, 112)+'01')), 112) 
								 	 AND CONVERT(CHAR(6), DATEADD(MONTH, -1, CONVERT(DATETIME, CONVERT(CHAR(6), S.PLAN_YYYYMM, 112)+'01')), 112)
		) AS MON_03_MKT_FCST_ACCUM_QTY
		,( SELECT SUM(ISNULL(SS.CUST_FCST_QTY,0))
			FROM DM_CUST_DEMAND_ANL_SUMMARY SS WITH(NOLOCK)
			WHERE SS.DIVISION_ID  = S.DIVISION_ID
			AND   SS.END_CUSTOMER = S.END_CUSTOMER
			AND   SS.PROJECT_CODE = S.PROJECT_CODE
			AND   SS.MEASURE      = S.MEASURE 
			AND   SS.PLAN_YYYYMM BETWEEN CONVERT(CHAR(6), DATEADD(MONTH, -6, CONVERT(DATETIME, CONVERT(CHAR(6), S.PLAN_YYYYMM, 112)+'01')), 112) 
									 AND CONVERT(CHAR(6), DATEADD(MONTH, -1, CONVERT(DATETIME, CONVERT(CHAR(6), S.PLAN_YYYYMM, 112)+'01')), 112)
		) AS MON_06_CUST_FCST_ACCUM_QTY
		,( SELECT SUM(ISNULL(SS.MKT_FCST_QTY,0))
			FROM DM_CUST_DEMAND_ANL_SUMMARY SS WITH(NOLOCK)
			WHERE SS.DIVISION_ID  = S.DIVISION_ID
			AND   SS.END_CUSTOMER = S.END_CUSTOMER
			AND   SS.PROJECT_CODE = S.PROJECT_CODE
			AND   SS.MEASURE      = S.MEASURE 
			AND   SS.PLAN_YYYYMM BETWEEN CONVERT(CHAR(6), DATEADD(MONTH, -6, CONVERT(DATETIME, CONVERT(CHAR(6), S.PLAN_YYYYMM, 112)+'01')), 112) 
									 AND CONVERT(CHAR(6), DATEADD(MONTH, -1, CONVERT(DATETIME, CONVERT(CHAR(6), S.PLAN_YYYYMM, 112)+'01')), 112)
		) AS MON_06_MKT_FCST_ACCUM_QTY
		,( SELECT SUM(ISNULL(SS.CUST_FCST_QTY,0))
			FROM DM_CUST_DEMAND_ANL_SUMMARY SS WITH(NOLOCK)
			WHERE SS.DIVISION_ID  = S.DIVISION_ID
			AND   SS.END_CUSTOMER = S.END_CUSTOMER
			AND   SS.PROJECT_CODE = S.PROJECT_CODE
			AND   SS.MEASURE      = S.MEASURE 
			AND   SS.PLAN_YYYYMM BETWEEN CONVERT(CHAR(6), DATEADD(MONTH, -12, CONVERT(DATETIME, CONVERT(CHAR(6), S.PLAN_YYYYMM, 112)+'01')), 112) 
									 AND CONVERT(CHAR(6), DATEADD(MONTH,  -1, CONVERT(DATETIME, CONVERT(CHAR(6), S.PLAN_YYYYMM, 112)+'01')), 112)
		) AS MON_12_CUST_FCST_ACCUM_QTY
		,( SELECT SUM(ISNULL(SS.MKT_FCST_QTY,0))
			FROM DM_CUST_DEMAND_ANL_SUMMARY SS WITH(NOLOCK)
			WHERE SS.DIVISION_ID  = S.DIVISION_ID
			AND   SS.END_CUSTOMER = S.END_CUSTOMER
			AND   SS.PROJECT_CODE = S.PROJECT_CODE
			AND   SS.MEASURE      = S.MEASURE 
			AND   SS.PLAN_YYYYMM BETWEEN CONVERT(CHAR(6), DATEADD(MONTH, -12, CONVERT(DATETIME, CONVERT(CHAR(6), S.PLAN_YYYYMM, 112)+'01')), 112) 
									 AND CONVERT(CHAR(6), DATEADD(MONTH,  -1, CONVERT(DATETIME, CONVERT(CHAR(6), S.PLAN_YYYYMM, 112)+'01')), 112)
		) AS MON_12_MKT_FCST_ACCUM_QTY
		,ROW_NUMBER() OVER(PARTITION BY S.DIVISION_ID,S.END_CUSTOMER,S.PROJECT_CODE,S.MEASURE ORDER BY S.PLAN_YYYYMM DESC) AS PLAN_YYYYMM_RANK
	FROM DM_CUST_DEMAND_ANL_SUMMARY S WITH(NOLOCK)
	LEFT OUTER JOIN DM_CUST_DEMAND_ANL_DETAIL DTL WITH(NOLOCK)
		ON  S.DIVISION_ID   = DTL.DIVISION_ID
		AND S.END_CUSTOMER  = DTL.END_CUSTOMER
		AND S.PROJECT_CODE  = DTL.PROJECT_CODE
		AND S.MEASURE       = DTL.MEASURE
		AND S.PLAN_YYYYMM   = DTL.PLAN_YYYYMM
	WHERE 
	--[테스트]
	--S.DIVISION_ID = '81' AND S.END_CUSTOMER = 'BMW' AND S.PROJECT_CODE = 'A15BW7002' 
	--S.DIVISION_ID = '81' AND S.END_CUSTOMER = 'Aeonus' AND S.PROJECT_CODE = 'A23US4001' 
	--S.DIVISION_ID = '81' AND S.END_CUSTOMER = 'Audi' AND S.PROJECT_CODE = 'A15AI7001'
	--AND S.PLAN_YYYYMM BETWEEN @YYYYMM1 AND @YYYYMM2
	--[운영]
	S.DIVISION_ID = @p_division_id AND S.END_CUSTOMER = @p_end_customer AND S.PROJECT_CODE = @p_project_code
	AND S.PLAN_YYYYMM BETWEEN @YYYYMM1 AND @YYYYMM2
	GROUP BY S.DIVISION_ID, S.END_CUSTOMER, S.PROJECT_NAME, S.PROJECT_CODE, S.MEASURE, S.PLAN_YYYYMM;

	--[테스트]
	--SELECT * FROM #T1_RAW
	--DROP TABLE #T1_RAW
		
