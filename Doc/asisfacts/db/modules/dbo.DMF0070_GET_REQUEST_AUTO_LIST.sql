CREATE PROCEDURE [dbo].[DMF0070_GET_REQUEST_AUTO_LIST]  
    @P_DIVISION_ID  NVARCHAR(30),
    @P_SCM_SITE_ID  NVARCHAR(4000),
    @P_DATE_FROM	NVARCHAR(100),
    @P_DATE_TO		NVARCHAR(100),
    @P_PROJECT      NVARCHAR(4000),
    @P_ITEM_ID		NVARCHAR(4000),
    @P_OWNER		NVARCHAR(4000),
	@P_USER_GROUP	NVARCHAR(100),
	@P_USER_ID		NVARCHAR(100)
AS
BEGIN
	
	
	SET NOCOUNT ON;

	--[E20240529-001017]_Auto PR Request 개선요청건
	DECLARE @V_ISO_YYYYWW	NVARCHAR(30)
	SET @V_ISO_YYYYWW = (SELECT ISO_YYYYWW FROM SCM_SYS_CALENDAR_M WITH (NOLOCK) WHERE BASIS_YYYYMMDD = CONVERT(VARCHAR(8), GETDATE(), 112));

		SELECT A.MAIL_INFO_DATE, A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.DOM_EXP, A.FCST_TYPE, A.INCOTERMS
			 , A.PLANT_SITE_ID, A.MKT_FCST_DATE, A.PLAN_QTY, A.AUTO_FLAG, A.BNP_IN_DATE, A.PROJECT_OWNER, A.OWNER
			 , A.CREATION_DATE, A.STORAGE_ID, A.PR_ITEM_DETAIL, A.STORAGE_PLANT_ID, A.ORIGIN_PLANT_SITE_ID, A.CHK_FLAG, A.BOD_VALIDATION 
		FROM
		(
			SELECT CONVERT(VARCHAR(10), CONVERT(DATE, ATO.MAIL_INFO_DATE), 120) AS MAIL_INFO_DATE
				 , ATO.DIVISION_ID, ATO.PROJECT_CODE, ATO.SCM_SITE_ID, ATO.ITEM_ID, ATO.DOM_EXP, ATO.FCST_TYPE, ATO.INCOTERMS, ATO.PLANT_SITE_ID
				 , CONVERT(VARCHAR(10), CONVERT(DATE, ATO.MKT_FCST_DATE), 120) AS MKT_FCST_DATE
				 , ATO.PLAN_QTY, ATO.AUTO_FLAG, ATO.BNP_IN_DATE
				 , (SELECT TOP 1 PROJECT_OWNER FROM SCM_MST_PROJECT MP WITH(NOLOCK)
					WHERE MP.DIVISION_ID = ATO.DIVISION_ID
					AND MP.PROJECT_CODE = ATO.PROJECT_CODE) AS PROJECT_OWNER
				 , (SELECT TOP 1 OWNER FROM SCM_MST_SITE_ITEM ITM WITH(NOLOCK)
					WHERE ITM.DIVISION_ID = ATO.DIVISION_ID
					AND ITM.PROJECT_CODE = ATO.PROJECT_CODE
					AND ITM.SCM_SITE_ID = ATO.SCM_SITE_ID
					AND ITM.ITEM_ID = ATO.ITEM_ID) AS OWNER
				 , ATO.CREATION_DATE, ATO.STORAGE_ID, ATO.PR_ITEM_DETAIL, ATO.STORAGE_PLANT_ID, ATO.PLANT_SITE_ID AS ORIGIN_PLANT_SITE_ID -- STORAGE_PLANT_ID 안쓸 경우 대비
				 --[E20240529-001017]_Auto PR Request 개선요청건
				 , CASE WHEN CAL.ISO_YYYYWW = @V_ISO_YYYYWW THEN 'Y' ELSE 'N' END AS CHK_FLAG
				 , CASE WHEN ISNULL(B.BOD_ID, '') = '' THEN 'N' ELSE 'Y' END AS BOD_VALIDATION
			FROM DM_PLN_AUTO_PR_CHECK ATO WITH (NOLOCK)
			--[E20240529-001017]_Auto PR Request 개선요청건 추가
			INNER JOIN SCM_SYS_CALENDAR_M CAL WITH (NOLOCK)
					ON ATO.MAIL_INFO_DATE = CAL.BASIS_YYYYMMDD
			LEFT OUTER JOIN ( SELECT DIVISION_ID, FROM_SITE, TO_SITE, INCOTERMS, BOD_VALID_YN, MAX(BOD_ID) AS BOD_ID
							  FROM SCP_MST_BOD_V WITH(NOLOCK)
							  GROUP BY DIVISION_ID, FROM_SITE, TO_SITE, INCOTERMS, BOD_VALID_YN
							  ) B
						ON B.DIVISION_ID = ATO.DIVISION_ID
					   --AND B.FROM_SITE	 = CASE WHEN ATO.PLANT_SITE_ID IS NULL OR ATO.PLANT_SITE_ID = '' THEN 'KR012031-P' ELSE  ATO.PLANT_SITE_ID END
					   -- [PJ20228272] NERP 하드코딩 대응 및 개선 SCM_CODE_LOOKUP_VALUE 테이블에서 관리 Start
					   AND B.FROM_SITE	 IN ( CASE WHEN ATO.PLANT_SITE_ID IS NULL OR ATO.PLANT_SITE_ID = '' 
					                               THEN  (SELECT CODE FROM [dbo].FN_LIST_LOOKUP_VALUE('DMF0070_GET_REQUEST_AUTO_LIST', 'SCP_SITE_ID'))
												   ELSE ATO.PLANT_SITE_ID 
											   END )
					   -- [PJ20228272] NERP 하드코딩 대응 및 개선 SCM_CODE_LOOKUP_VALUE 테이블에서 관리 End
					   AND B.TO_SITE	 = ATO.SCM_SITE_ID
					   AND B.INCOTERMS	 = ATO.INCOTERMS 
					   AND B.BOD_VALID_YN = 'Y'
			WHERE ATO.DIVISION_ID = @P_DIVISION_ID
			AND ATO.MAIL_INFO_DATE >= @P_DATE_FROM
			AND ATO.MAIL_INFO_DATE <= @P_DATE_TO
			AND CASE WHEN @P_SCM_SITE_ID = 'ALL' THEN @P_SCM_SITE_ID ELSE ATO.SCM_SITE_ID END IN ( SELECT TOKEN FROM DBO.STRING_SPLIT(@P_SCM_SITE_ID,',') )
			AND CASE WHEN @P_PROJECT = '' THEN @P_PROJECT ELSE ATO.PROJECT_CODE	END IN ( SELECT TOKEN FROM DBO.STRING_SPLIT(@P_PROJECT,',') )
			AND CASE WHEN @P_ITEM_ID = '' THEN @P_ITEM_ID ELSE ATO.ITEM_ID END IN ( SELECT TOKEN FROM DBO.STRING_SPLIT(@P_ITEM_ID,',') )
		) A
		WHERE CASE WHEN @P_OWNER = '' THEN @P_OWNER	ELSE A.OWNER END  IN ( SELECT TOKEN FROM DBO.STRING_SPLIT(@P_OWNER,',') )
	/*
		1) DM Planner, DM Planner(W/S): Owner, Project Owner에 본인이 포함되는 데이터만 조회&수정
		2) DM Viewer: Owner, Project Owner에 본인이 포함되는 데이터만 조회 (수정은 불가)
		3) DM ADMIN: 모든 데이터 조회&수정 가능					
	*/
		AND	((@P_USER_GROUP = 'ADMIN' OR @P_USER_GROUP = 'DM ADMIN') OR	(A.PROJECT_OWNER = @P_USER_ID OR A.OWNER = @P_USER_ID))
		ORDER BY A.MAIL_INFO_DATE DESC

END
