	--STEP 2. TARGET TABLE UPDATE 
	------------------------------------------------------
	BEGIN
		declare @p nvarchar(max) = '';
		DECLARE @WORK_AVALIABLE TABLE (TABLE_COL NVARCHAR(150), MASTER_CODETYPE NVARCHAR(150));

		DECLARE LOOKUP_CURSOR CURSOR FOR
