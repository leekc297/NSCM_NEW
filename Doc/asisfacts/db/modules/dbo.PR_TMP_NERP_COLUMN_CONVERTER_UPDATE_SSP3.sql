				--BEGIN
				--	SET @mUpdateWhereQuery = @mUpdateWhereQuery + ' AND A.' + @STD_COLUMN + ' > DATEADD(DAY, -' + @TERMS + ', ''20250300'') ' + CHAR(10);	
