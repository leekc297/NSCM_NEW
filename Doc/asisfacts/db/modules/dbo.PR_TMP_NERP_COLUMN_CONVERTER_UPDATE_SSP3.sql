					DROP TABLE ZNERP_TARGET_HIST_SSP
			
				DECLARE @SQL NVARCHAR(MAX);
				SET @SQL = 'CREATE TABLE ZNERP_TARGET_HIST_SSP(';
				SELECT @SQL = @SQL + @mTableQuery;
				SELECT @SQL = @SQL + ');'

				PRINT @SQL;

				EXEC(@SQL);

				DECLARE @mEXECSelInto NVARCHAR(MAX);
				SET @mEXECSelInto = '';
				SET @mEXECSelInto = @mEXECSelInto + 'INSERT INTO ZNERP_TARGET_HIST_SSP' +CHAR(10);	
				SET @mEXECSelInto = @mEXECSelInto + 'SELECT ' + @mDisQuery  +CHAR(10);	
				SET @mEXECSelInto = @mEXECSelInto + 'FROM ' + @TABLE_NAME + ' A'  +CHAR(10);	
				SET @mEXECSelInto = @mEXECSelInto + @mSubQuery;   


				PRINT @mEXECSelInto;
				EXEC SP_EXECUTESQL @mEXECSelInto ;

				PRINT @TABLE_NAME + '2. ' +CONVERT(CHAR(23), GETDATE(), 21);
				SET @UPDATE_START_TIME = CONVERT(CHAR(23), GETDATE(), 21);

				DECLARE @mEXEC_UPDATE NVARCHAR(MAX);
				SET @mEXEC_UPDATE = '';
				SET @mEXEC_UPDATE = @mEXEC_UPDATE + 'UPDATE '+ @TABLE_NAME + ' SET '  +CHAR(10);	
				SET @mEXEC_UPDATE = @mEXEC_UPDATE + @mUpdateQuery  +CHAR(10);	
				SET @mEXEC_UPDATE = @mEXEC_UPDATE + 'FROM ' + @TABLE_NAME + ' A,  ZNERP_TARGET_HIST_SSP C'  +CHAR(10);	
				SET @mEXEC_UPDATE = @mEXEC_UPDATE + 'WHERE 1=1'  +CHAR(10);	
				SET @mEXEC_UPDATE = @mEXEC_UPDATE + @mUpdateWhereQuery;   

				DECLARE @UPDATE_CNT INT;
				PRINT @mEXEC_UPDATE;
				EXEC SP_EXECUTESQL @mEXEC_UPDATE ;

				SELECT @UPDATE_CNT = @@ROWCOUNT;

				SET @UPDATE_END_TIME = CONVERT(CHAR(23), GETDATE(), 21);

				PRINT @TABLE_NAME + '3. ' +CONVERT(CHAR(23), GETDATE(), 21);

				UPDATE  ZNERP_XLS_CHANGE_MASTER_CODE_SSP3  
				SET UPDATE_QUERY = @mEXEC_UPDATE, 
				UPDATE_CNT = @UPDATE_CNT,
				UPDATE_START_TIME = @UPDATE_START_TIME, 
				UPDATE_END_TIME = @UPDATE_END_TIME
				WHERE PROCESS_TYPE = @TABLE_NAME;
				
				CLOSE LOOKUP_CURSOR2;
				DEALLOCATE LOOKUP_CURSOR2;
			END
			

			-----------------------------------------------
			--STEP 2-2. JOIN QUERY AUTO MAKE 
			-----------------------------------------------
			FETCH NEXT FROM LOOKUP_CURSOR
			INTO @TABLE_NAME, @STD_COLUMN ,@TERMS;
		END


		
		CLOSE LOOKUP_CURSOR;
		DEALLOCATE LOOKUP_CURSOR;
	END;
	------------------------------------------------------
	--STEP 3. MANUAL CASE 진행
	-- SSP_DNM_SHIP_RETURN_OWMS / SSP_DNM_SHIP_RETURN_OWMS / SSP_KPI_ATR_AIR_TRANSPORT_RATE
	------------------------------------------------------
	UPDATE  ZNERP_XLS_CHANGE_MASTER_CODE_SSP3  
	SET UPDATE_START_TIME = GETDATE() 
	WHERE PROCESS_TYPE = 'SSP_DNM_SHIP_RETURN_OWMS';

	IF OBJECT_ID('#ZNERP_TARGET_HIST_SSP1') IS NOT NULL	
		DROP TABLE #ZNERP_TARGET_HIST_SSP1
	;		

	CREATE TABLE #ZNERP_TARGET_HIST_SSP1(ATTRIBUTE5 NVARCHAR(100), COMPANY_ID_B1 NVARCHAR(100) , FROM_SITE NVARCHAR(100), SITE_ID_B2 NVARCHAR(100) , STORAGE_ID NVARCHAR(100), STORAGE_ID_B3 NVARCHAR(100) ) ;
		
	INSERT INTO #ZNERP_TARGET_HIST_SSP1
	SELECT DISTINCT A.ATTRIBUTE5, B1.NEW_VALUE1 AS COMPANY_ID_B1, A.FROM_SITE, B2.NEW_VALUE1 AS SITE_ID_B2, A.STORAGE_ID, B3.NEW_VALUE2 AS STORAGE_ID_B3
	FROM (	
			SELECT DISTINCT A.DIVISION_ID, A.ATTRIBUTE5, A.FROM_SITE, A.STORAGE_ID, B.PLANT_ID 
--				FROM SSP_DNM_SHIP_RETURN_OWMS_CONV_A A
			FROM SSP_DNM_SHIP_RETURN_OWMS A
			INNER JOIN [DBO].SCM_MST_SITE B
			ON B.SITE_TYPE = 'PLANT' AND B.VALID_YN = 'Y'
			WHERE RIGHT(FROM_SITE,1) != 'E'
			AND   A.DIVISION_ID = B.DIVISION_ID
			AND   A.FROM_SITE = B.SCM_SITE_ID
			UNION ALL
			SELECT DISTINCT A.DIVISION_ID, A.ATTRIBUTE5, A.FROM_SITE, A.STORAGE_ID, MAX(B.SEGMENT2) AS PLANT_ID
--				FROM SSP_DNM_SHIP_RETURN_OWMS_CONV_A A
			FROM SSP_DNM_SHIP_RETURN_OWMS A
			INNER JOIN [DBO].SCM_ADM_LOOKUP_MASTER_DETAIL B WITH(NOLOCK)
			ON  B.LOOKUP_TYPE	= 'ELECTRODE_OWMS_PLANT_MAPPING' 
			AND B.SEGMENT1 = A.DIVISION_ID
			AND B.SEGMENT3 = A.FROM_SITE
			WHERE RIGHT(FROM_SITE,1) = 'E'
			GROUP BY A.DIVISION_ID, A.ATTRIBUTE5, A.FROM_SITE, A.STORAGE_ID
		) A
	LEFT JOIN NERP_CONV_MASTER B1
	ON A.ATTRIBUTE5 = B1.OLD_VALUE1
	AND B1.CODETYPE = 'COMPANY_ID'
	AND B1.ATTRIBUTE5 <= '5th' 
	LEFT JOIN NERP_CONV_MASTER B2
	ON A.FROM_SITE = B2.OLD_VALUE1
	AND B2.CODETYPE = 'SCP_SITE_ID'
	AND B2.ATTRIBUTE5 <= '5th' 
	LEFT JOIN NERP_CONV_MASTER B3
	ON A.STORAGE_ID = B3.OLD_VALUE2
	AND B3.CODETYPE = 'STORAGE_ID'
	AND A.PLANT_ID = B3.OLD_VALUE1
	AND B3.ATTRIBUTE5 <= '5th' 
	;


--		UPDATE SSP_DNM_SHIP_RETURN_OWMS_CONV_A SET 
	UPDATE SSP_DNM_SHIP_RETURN_OWMS SET 
	ATTRIBUTE5 = ISNULL(C.COMPANY_ID_B1, A.ATTRIBUTE5), FROM_SITE = ISNULL(C.SITE_ID_B2, A.FROM_SITE), STORAGE_ID = ISNULL(C.STORAGE_ID_B3, A.STORAGE_ID)
--		FROM SSP_DNM_SHIP_RETURN_OWMS_CONV_A A,  #ZNERP_TARGET_HIST_SSP1 C
	FROM SSP_DNM_SHIP_RETURN_OWMS A,  #ZNERP_TARGET_HIST_SSP1 C
	WHERE 1=1
		AND ISNULL(A.ATTRIBUTE5, '') = ISNULL(C.ATTRIBUTE5, '') AND ISNULL(A.FROM_SITE, '') = ISNULL(C.FROM_SITE, '') AND ISNULL(A.STORAGE_ID, '') = ISNULL(C.STORAGE_ID, '')
	;

	UPDATE  ZNERP_XLS_CHANGE_MASTER_CODE_SSP3  
	SET UPDATE_END_TIME = GETDATE() 
	WHERE PROCESS_TYPE = 'SSP_DNM_SHIP_RETURN_OWMS';

----------------------------------------------------------------------------------------------------------

	UPDATE  ZNERP_XLS_CHANGE_MASTER_CODE_SSP3  
	SET UPDATE_START_TIME = GETDATE() 
	WHERE PROCESS_TYPE = 'SSP_DNM_SHIP_RESULT_OWMS';

	IF OBJECT_ID('#ZNERP_TARGET_HIST_SSP2') IS NOT NULL	
		DROP TABLE #ZNERP_TARGET_HIST_SSP2
	;
	
	CREATE TABLE #ZNERP_TARGET_HIST_SSP2(ATTRIBUTE5 NVARCHAR(100), COMPANY_ID_B1 NVARCHAR(100) , CUSTOMER_CODE NVARCHAR(100), END_CUSTOMER_ID_B2 NVARCHAR(100) , FROM_SITE NVARCHAR(100), SITE_ID_B3 NVARCHAR(100) , STORAGE_ID NVARCHAR(100), STORAGE_ID_B4 NVARCHAR(100) , TO_SITE NVARCHAR(100), SITE_ID_B5 NVARCHAR(100) , PLANT_ID NVARCHAR(100), SITE_ID_B6 NVARCHAR(100) );
		
	INSERT INTO #ZNERP_TARGET_HIST_SSP2
	SELECT DISTINCT A.ATTRIBUTE5, B1.NEW_VALUE1 AS COMPANY_ID_B1, A.CUSTOMER_CODE, B2.NEW_VALUE1 AS END_CUSTOMER_ID_B2, A.FROM_SITE, B3.NEW_VALUE1 AS SITE_ID_B3, A.STORAGE_ID, B4.NEW_VALUE2 AS STORAGE_ID_B4, A.TO_SITE, B5.NEW_VALUE1 AS SITE_ID_B5, A.PLANT_ID, B6.NEW_VALUE1 AS SITE_ID_B6
	FROM (	
			SELECT DISTINCT A.DIVISION_ID, A.ATTRIBUTE5, A.CUSTOMER_CODE, A.FROM_SITE, A.STORAGE_ID, A.TO_SITE, B.PLANT_ID 
--				FROM SSP_DNM_SHIP_RESULT_OWMS_CONV_A A
			FROM SSP_DNM_SHIP_RESULT_OWMS A
			INNER JOIN [DBO].SCM_MST_SITE B
			ON B.SITE_TYPE = 'PLANT' AND B.VALID_YN = 'Y'
			WHERE RIGHT(FROM_SITE,1) != 'E'
			AND   A.DIVISION_ID = B.DIVISION_ID
			AND   A.FROM_SITE = B.SCM_SITE_ID
			UNION ALL
			SELECT DISTINCT A.DIVISION_ID, A.ATTRIBUTE5, A.CUSTOMER_CODE, A.FROM_SITE, A.STORAGE_ID, A.TO_SITE, MAX(B.SEGMENT2) AS PLANT_ID
--				FROM SSP_DNM_SHIP_RESULT_OWMS_CONV_A A
			FROM SSP_DNM_SHIP_RESULT_OWMS A
			INNER JOIN [DBO].SCM_ADM_LOOKUP_MASTER_DETAIL B WITH(NOLOCK)
			ON  B.LOOKUP_TYPE	= 'ELECTRODE_OWMS_PLANT_MAPPING' 
			AND B.SEGMENT1 = A.DIVISION_ID
			AND B.SEGMENT3 = A.FROM_SITE
			WHERE RIGHT(FROM_SITE,1) = 'E'
			GROUP BY A.DIVISION_ID, A.ATTRIBUTE5, A.CUSTOMER_CODE, A.FROM_SITE, A.STORAGE_ID, A.TO_SITE
		) A		
	LEFT JOIN NERP_CONV_MASTER B1
	ON A.ATTRIBUTE5 = B1.OLD_VALUE1
	AND B1.CODETYPE = 'COMPANY_ID'
	AND B1.ATTRIBUTE5 <= '5th' 
	LEFT JOIN NERP_CONV_MASTER B2
	ON A.CUSTOMER_CODE = B2.OLD_VALUE1
	AND B2.CODETYPE = 'END_CUSTOMER_ID'
	AND B2.ATTRIBUTE5 <= '5th' 
	LEFT JOIN NERP_CONV_MASTER B3
	ON A.FROM_SITE = B3.OLD_VALUE1
	AND B3.CODETYPE = 'SCP_SITE_ID'
	AND B3.ATTRIBUTE5 <= '5th' 
	LEFT JOIN NERP_CONV_MASTER B4
	ON A.STORAGE_ID = B4.OLD_VALUE2
	AND A.PLANT_ID = B4.OLD_VALUE1
	AND B4.CODETYPE = 'STORAGE_ID'
	AND B4.ATTRIBUTE5 <= '5th' 
	AND A.PLANT_ID = B4.OLD_VALUE1
	LEFT JOIN NERP_CONV_MASTER B5
	ON A.TO_SITE = B5.OLD_VALUE1
	AND B5.CODETYPE = 'SCP_SITE_ID'	
	AND B5.ATTRIBUTE5 <= '5th' 
	LEFT JOIN NERP_CONV_MASTER B6
	ON A.TO_SITE = B6.OLD_VALUE1
	AND B5.CODETYPE = 'PLANT_ID'	
	AND B5.ATTRIBUTE5 <= '5th' 	;

--		UPDATE SSP_DNM_SHIP_RESULT_OWMS_CONV_A 
	UPDATE SSP_DNM_SHIP_RESULT_OWMS 
	SET 
			ATTRIBUTE5 = ISNULL(C.COMPANY_ID_B1, A.ATTRIBUTE5)
		, CUSTOMER_CODE = ISNULL(C.END_CUSTOMER_ID_B2, A.CUSTOMER_CODE)
		, FROM_SITE = ISNULL(C.SITE_ID_B3, A.FROM_SITE)
		, STORAGE_ID = ISNULL(C.STORAGE_ID_B4, A.STORAGE_ID)
		, TO_SITE = ISNULL(C.SITE_ID_B5, A.TO_SITE)
--		FROM SSP_DNM_SHIP_RESULT_OWMS_CONV_A A,  #ZNERP_TARGET_HIST_SSP2 C
	FROM SSP_DNM_SHIP_RESULT_OWMS A,  #ZNERP_TARGET_HIST_SSP2 C
	WHERE 1=1
		AND ISNULL(A.ATTRIBUTE5, '') = ISNULL(C.ATTRIBUTE5, '') 
		AND ISNULL(A.CUSTOMER_CODE, '') = ISNULL(C.CUSTOMER_CODE, '') 
		AND ISNULL(A.FROM_SITE, '') = ISNULL(C.FROM_SITE, '') 
		AND ISNULL(A.STORAGE_ID, '') = ISNULL(C.STORAGE_ID, '') 
		AND ISNULL(A.TO_SITE, '') = ISNULL(C.TO_SITE, '') 
		AND A.plant_issue_date > DATEADD(DAY, -90, '20241228') 

	UPDATE  ZNERP_XLS_CHANGE_MASTER_CODE_SSP3  
