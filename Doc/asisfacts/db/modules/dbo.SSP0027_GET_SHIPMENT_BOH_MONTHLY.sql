			                                   FROM SCM_MST_SLOC X WITH(NOLOCK) 
											  WHERE X.PLANT_ID = FP.PLANT_ID 
											    AND X.STORAGE_ID = FP.STORAGE_ID
												and X.VALID_YN = 'Y')
