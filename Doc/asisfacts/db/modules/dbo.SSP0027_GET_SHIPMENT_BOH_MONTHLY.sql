			,SUM(ISNULL(FP.[SSP_QTY],0))		 AS AVAILABLE_QTY
			,SUM(ISNULL(FP.[MOVING_QTY],0))      AS MOVING_QTY
			,SUM(ISNULL(FP.[DEFECT_QTY],0))		 AS DEFECT_QTY 
	FROM DBO.SCM_DNM_STOCK_V FP WITH(NOLOCK)

	INNER JOIN SCM_MST_ITEM_SN AS T WITH(NOLOCK)		
		ON FP.ITEM_ID		= T.ITEM_ID		
		AND FP.DIVISION_ID	= T.DIVISION_ID	
		AND T.COMPANY_ID	= @P_COMPANY_ID
		AND T.ITEM_TYPE		= 'Q'

	INNER JOIN SCM_ADM_LOOKUP_MASTER_DETAIL X WITH(NOLOCK)		
		ON X.LOOKUP_TYPE = 'ESS_STOCK_STORAGE_ID'
		AND X.SEGMENT1 = FP.STORAGE_ID
		AND ((@P_STORAGE_ID IS NULL OR @P_STORAGE_ID ='')	OR X.SEGMENT1 IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_STORAGE_ID, ',')))


	INNER JOIN #TMP_STOCK_DATA AS TSD
		ON FP.DIVISION_ID	= TSD.DIVISION_ID
		AND FP.COMPANY_ID	= TSD.COMPANY_ID
		AND FP.PLANT_ID		= TSD.PLANT_ID
		AND FP.CUTOFF_DATE  = TSD.CUTOFF_DATE		
		AND FP.ITEM_ID		= TSD.ITEM_ID
		--AND FP.STORAGE_ID	= TSD.STORAGE_ID

