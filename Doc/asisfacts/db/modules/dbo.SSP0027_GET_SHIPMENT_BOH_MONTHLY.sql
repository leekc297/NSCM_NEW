	AND FP.DIVISION_ID		  = @P_DIVISION_ID
	AND FP.COMPANY_ID		  = @P_COMPANY_ID
	AND FP.CUTOFF_DATE		  = @v_cutoff_date
	AND FP.STOCK_TYPE		  = 'INVENTORY'

