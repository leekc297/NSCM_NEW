            ,FP.[WIPHOLD_YN]        
            ,FP.[HOLDING_DATE]     
            ,FP.[AVAILABLE_DATE]  
            ,FP.[OUTSOURCING_FLAG]
            ,FP.[OUTSOURCING_FACTORY]		 
