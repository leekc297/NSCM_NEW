CREATE PROCEDURE [dbo].[PR_SCM_SIM_OPT_EE_PSI]
    @P_BATCH_ID      nvarchar(30) = '0'
   ,@P_USER_ID       nvarchar(30) = ''
   ,@P_SNAP_YYYYMMDD nvarchar(8) = ''   -- PLAN_START_YYYYMMDD 값이 넘어옴.
   ,@P_REPORT_TITLE  nvarchar(200) = ''
   ,@P_MAX_COLS_NUM  INT = 800
   ,@P_PLANT_ID      nvarchar(30) = ''
   ,@P_PLAN_GROUP    nvarchar(100) = ''
   ,@P_DIVISION_ID   nvarchar(30) = ''
   ,@P_PLAN_TYPE     nvarchar(30) = ''
   ,@P_PLAN_SEQ      nvarchar(2) = ''
   ,@P_OPT_PLAN_ID   nvarchar(MAX) = '' 
   ,@P_ITEM_ID_PLANT_IDS nvarchar(MAX) = ''
   ,@X_STATUS        INT OUTPUT           -- OUTPUT
   ,@X_MSG           NVARCHAR(200) OUTPUT -- OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    DECLARE @CNT BIGINT = 0;
    DECLARE @WORK_SECOND BIGINT;
    DECLARE @BATCH_START_TIME DATETIME;
    DECLARE @BATCH_END_TIME DATETIME;
    DECLARE @START_TIME DATETIME;
    DECLARE @END_TIME DATETIME;
    DECLARE @crlf  CHAR(2) = CHAR(13) + CHAR(10);
    DECLARE @BATCH_ID BIGINT = CONVERT(BIGINT,@P_BATCH_ID);
    DECLARE @DBPrefix NVARCHAR(254);
    DECLARE @DBOPTPrefix NVARCHAR(254);
    SET @DBPrefix = CASE WHEN 1=2 THEN '' ELSE '[DBO].' END; 
    SET @DBOPTPrefix = CASE WHEN 1=2 THEN '' ELSE '[OPTENG_SCP].[DBO].' END;
	DECLARE @TMP_STR NVARCHAR(MAX);
	
    -- LOG START
    DECLARE @v_online_user NVARCHAR(150) = IIF(ISNULL(@P_USER_ID,'')='','simulator',@P_USER_ID);
    DECLARE @v_program_name NVARCHAR(150) = 'PR_SCM_SIM_OPT_EE_PSI';
    DECLARE @v_log_type     NVARCHAR(30); -- START/END/ERROR/...
    DECLARE @n_log_count    INTEGER = 0;
    DECLARE @v_log_message  NVARCHAR(1000);
    DECLARE @v_description  NVARCHAR(500);
    DECLARE @d_event_date   DATETIME;
    SET @v_log_type = 'START';
    SET @v_log_message = '########## Start of procedure ##########';
    SET @v_description = '@P_USER_ID:'+@P_USER_ID+',@BATCH_ID:'+ISNULL(CONVERT(NVARCHAR(MAX),@BATCH_ID),'NULL')+',@P_SNAP_YYYYMMDD:'+@P_SNAP_YYYYMMDD+',@P_PLAN_TYPE:'+@P_PLAN_TYPE+',@P_PLAN_SEQ:'+@P_PLAN_SEQ+',@P_OPT_PLAN_ID:'+CONVERT(NVARCHAR(MAX),@P_OPT_PLAN_ID)+',@P_REPORT_TITLE:'+@P_REPORT_TITLE+',@P_MAX_COLS_NUM:'+CONVERT(NVARCHAR(MAX),@P_MAX_COLS_NUM)+',@P_PLANT_ID:'+@P_PLANT_ID+',@P_PLAN_GROUP:'+@P_PLAN_GROUP+',@P_DIVISION_ID:'+@P_DIVISION_ID+',@P_ITEM_ID_PLANT_IDS:'+ @P_ITEM_ID_PLANT_IDS;
    
    SET @BATCH_START_TIME = SYSDATETIME();
    SET @START_TIME = CONVERT(CHAR(23), GETDATE(), 21);
    EXEC PR_SCM_SYS_LOG_BATCH @v_program_name, 'START', 0, '0',@v_description, @START_TIME;
	SET @d_event_date = SYSDATETIME();

	BEGIN TRY
		CLOSE CURSOR_NUM;
		DEALLOCATE CURSOR_NUM;
	END TRY
	BEGIN CATCH
	END CATCH

	DECLARE @V_REPORT_TITLE_PSI_DETAIL NVARCHAR(256)=@P_REPORT_TITLE;
    DECLARE @V_REPORT_TITLE_RESOURCE NVARCHAR(256)=@P_REPORT_TITLE+N'_RESOURCE';

	SET @P_OPT_PLAN_ID = REPLACE(@P_OPT_PLAN_ID,'^', '');
    SET @p_division_id = 'EE';

	DELETE FROM SCM_SIM_DYN_COLS
	WHERE BATCH_ID=@BATCH_ID AND LAST_UPDATED_BY=@P_USER_ID;
			   
BEGIN TRY

    DECLARE @QUERY_START_YYYYMMDD NVARCHAR(8);
    SELECT  @QUERY_START_YYYYMMDD = BASIS_YYYYMMDD FROM  dbo.SCM_SYS_CALENDAR_M AS CM WITH(NOLOCK)
    WHERE  CM.DAYOFWEEK = 'MON'
    AND    @P_SNAP_YYYYMMDD BETWEEN CM.BASIS_START_DATE AND CM.BASIS_END_DATE;

    DECLARE @PREV_QUERY_START_YYYYMMDD NVARCHAR(8);
    SET @PREV_QUERY_START_YYYYMMDD = CONVERT(VARCHAR(8),DATEADD(WEEK, -4, @QUERY_START_YYYYMMDD ),112);

    DECLARE @QUERY_END_YYYYMMDD NVARCHAR(8);
    SET @QUERY_END_YYYYMMDD = 
       (SELECT CONVERT(NVARCHAR(8),DATEADD(DAY, 0, p.horizon_end_date),112) AS QUERY_END_YYYYMMDD
        FROM   dbo.scm_mst_plan p WITH(NOLOCK)
        WHERE  p.division_id = @p_division_id
        AND    PLAN_NAME = @QUERY_START_YYYYMMDD 
		AND    p.plan_cycle  = 'WEEKLY');
	
	DECLARE @END_WEEK_MONTH NVARCHAR(6) = LEFT(@QUERY_END_YYYYMMDD,6);

    DECLARE @TBL_USER_PLANT_ITEMS TABLE(
		ITEM_ID    NVARCHAR(50)
       ,PLANT_ID   NVARCHAR(30)
    );
    INSERT INTO @TBL_USER_PLANT_ITEMS 
    SELECT
        ITEM_ID  = LEFT(S.token, CHARINDEX('^', S.token) - 1),
        PLANT_ID = LEFT(SUBSTRING(S.token, CHARINDEX('^', S.token) + 1, LEN(S.token)),4)
    FROM STRING_SPLIT(@P_ITEM_ID_PLANT_IDS, ',') S
	ORDER BY 1, 2 ;
	
    DECLARE @TBL_VALID_LINES TABLE(
		PLANT_ID	NVARCHAR(50)
		,FACTORY_ID	NVARCHAR(50)
		,LINE_ID		NVARCHAR(50)
    );		
	INSERT INTO @TBL_VALID_LINES
	SELECT DISTINCT PLANT_ID,FACTORY_ID,LINE_ID 	
	FROM SCP_OPMZ_PLAN_GR_LINE_M WITH(NOLOCK)
	WHERE OPERATION_ID='E2000' AND VALID_YN='Y'
	AND OPMZ_PLAN_GR_ID= (SELECT TOP 1 OPMZ_PLAN_GR_ID FROM SCP_OPMZ_PLAN_GR_M  WITH (NOLOCK) WHERE OPMZ_PLAN_GR_NAME = @P_PLAN_GROUP)

	DROP TABLE IF EXISTS #VALID_LINE_ITEMS; 
	IF OBJECT_ID('tempdb..#VALID_LINE_ITEMS') IS NOT NULL BEGIN DROP TABLE #VALID_LINE_ITEMS; END;
	SELECT DISTINCT 'EE' AS DIVISION_ID, A.PLANT_ID, A.FACTORY_ID, A.LINE_ID, MFI.ELECTRODE_TYPE, A.ITEM_ID, LEFT(A.DIVISION_ID,2) AS ORIGIN_DIVISION_ID, 
						MFI.NICK_NAME, SMS.SITE_DESCRIPTION, MFI.CONVERT_QTY_CELL AS CELL_CF
	INTO #VALID_LINE_ITEMS
	FROM SCM_MST_ITEM_LINE_ASSIGN_SN AS A WITH(NOLOCK)
	JOIN @TBL_VALID_LINES AS B
		ON A.PLANT_ID = B.PLANT_ID AND A.FACTORY_ID = B.FACTORY_ID AND A.LINE_ID = B.LINE_ID
	JOIN @TBL_USER_PLANT_ITEMS AS C
		ON A.PLANT_ID = LEFT(C.PLANT_ID,4) AND A.ITEM_ID = C.ITEM_ID
	JOIN SCM_MST_SITE SMS WITH(NOLOCK)
		ON SITE_TYPE='PLANT'
		AND LEFT(SMS.SCM_SITE_ID,4) = A.PLANT_ID
		AND SMS.VALID_YN = 'Y'
		AND SMS.OPERATION_GROUP = 'E'
		AND A.DIVISION_ID = A.DIVISION_ID
	JOIN SCP_MST_FINAL_ITEM MFI WITH(NOLOCK)
		ON MFI.ITEM_ID = A.ITEM_ID
		AND MFI.DIVISION_ID=A.DIVISION_ID
		AND MFI.OPERATION_GROUP = 'E'
		AND A.DIVISION_ID = A.DIVISION_ID
	WHERE A.OPERATION_ID='E2000' AND [MONTH]>=LEFT(@QUERY_START_YYYYMMDD,6) AND A.ACTIVE_FLAG='Y';

	DROP TABLE IF EXISTS #VALID_PLANT_ITEMS; 
	IF OBJECT_ID('tempdb..#VALID_PLANT_ITEMS') IS NOT NULL BEGIN DROP TABLE #VALID_PLANT_ITEMS; END;
	SELECT DISTINCT  DIVISION_ID, PLANT_ID, ELECTRODE_TYPE, ITEM_ID,ORIGIN_DIVISION_ID, NICK_NAME, SITE_DESCRIPTION, CELL_CF, '-' AS FACTORY_ID, '-' AS LINE_ID, 'E' AS OPERATION_GROUP,
		'E2000' AS OPERATION_ID
	INTO #VALID_PLANT_ITEMS
	FROM #VALID_LINE_ITEMS WITH(NOLOCK);
	  	 
    DECLARE @TBL_PLANNED_LINE_ITEMS TABLE(
		PLANT_ID		NVARCHAR(50)
		,FACTORY_ID		NVARCHAR(50)
		,LINE_ID		NVARCHAR(50)
		,ELECTRODE_TYPE NVARCHAR(50)
		,ITEM_ID		NVARCHAR(50)
		,PLANNED		NVARCHAR(2)
    );		
	INSERT INTO @TBL_PLANNED_LINE_ITEMS
	SELECT DISTINCT B.PLANT_ID, B.FACTORY_ID, A.LINE_ID, A.ELECTRODE_TYPE, A.ITEM_ID, N'Y' AS PLANNED
	FROM SCP_ANL_PRODUCTION_PLAN AS A WITH(NOLOCK)
	JOIN #VALID_LINE_ITEMS AS B WITH(NOLOCK)
	ON LEFT(A.SCM_SITE_ID,4) = B.PLANT_ID AND A.ITEM_ID = B.ITEM_ID AND A.LINE_ID = B.LINE_ID 
		AND A.PLAN_START_YYYYMMDD=@QUERY_START_YYYYMMDD AND A.PLAN_TYPE=@P_PLAN_TYPE AND A.SEQ=CAST(@P_PLAN_SEQ AS BIGINT) AND A.OPERATION_ID='E2000' AND A.MEASURE='PROD_PLAN_AMEND';
		
	DROP TABLE IF EXISTS #PLANNED_PLANT_ITEMS; 
	IF OBJECT_ID('tempdb..#PLANNED_PLANT_ITEMS') IS NOT NULL BEGIN DROP TABLE #PLANNED_PLANT_ITEMS; END;
	SELECT DISTINCT PLANT_ID, ITEM_ID
	INTO #PLANNED_PLANT_ITEMS
	FROM @TBL_PLANNED_LINE_ITEMS;
		
    DECLARE @TBL_VALID_LINE_ITEMS2 TABLE(
		PLANT_ID				NVARCHAR(50)
		,FACTORY_ID				NVARCHAR(50)
		,LINE_ID				NVARCHAR(50)
		,ELECTRODE_TYPE			NVARCHAR(50)
		,ITEM_ID				NVARCHAR(50)
		,ORIGIN_DIVISION_ID		NVARCHAR(50)
		,NICK_NAME				NVARCHAR(50)
		,SITE_DESCRIPTION		NVARCHAR(50)
		,CELL_CF				NVARCHAR(50)
		,PLANNED				NVARCHAR(2)
    );		
	INSERT INTO @TBL_VALID_LINE_ITEMS2
	SELECT DISTINCT A.PLANT_ID, A.FACTORY_ID, A.LINE_ID, A.ELECTRODE_TYPE, A.ITEM_ID, A.ORIGIN_DIVISION_ID, A.NICK_NAME, A.SITE_DESCRIPTION, A.CELL_CF, B.PLANNED
	FROM #VALID_LINE_ITEMS AS A WITH(NOLOCK) 
	LEFT JOIN @TBL_PLANNED_LINE_ITEMS AS B
		ON A.PLANT_ID = B.PLANT_ID AND A.FACTORY_ID = B.FACTORY_ID AND A.LINE_ID = B.LINE_ID AND A.ITEM_ID = B.ITEM_ID;

    PRINT N'BASE TABLE 생성';      --========================================  	  
    DROP TABLE IF EXISTS #VALID_LINE_ITEM_BASE;
    IF OBJECT_ID('tempdb..#VALID_LINE_ITEM_BASE') IS NOT NULL BEGIN DROP TABLE #VALID_LINE_ITEM_BASE; END;
    CREATE TABLE #VALID_LINE_ITEM_BASE(
        DIVISION_ID         NVARCHAR(100)
       ,ORIGIN_DIVISION_ID  NVARCHAR(100)
       ,PLAN_START_YYYYMMDD NVARCHAR(30)
       ,PLAN_TYPE           NVARCHAR(30)
       ,SEQ                 INT
       ,OPERATION_GROUP     NVARCHAR(30)
       ,SCM_SITE_ID         NVARCHAR(100)
	   ,PLANT_ID		    NVARCHAR(30)
       ,SITE_DESCRIPTION    NVARCHAR(100)
       ,NICK_NAME           NVARCHAR(50)
       ,ITEM_ID             NVARCHAR(100)
       ,ELECTRODE_TYPE      NVARCHAR(100)
       ,CELL_CF             NVARCHAR(100)
       ,FACTORY_ID          NVARCHAR(100)
       ,LINE_ID             NVARCHAR(100)
       ,OPERATION_ID        NVARCHAR(100)
    );

    DROP TABLE IF EXISTS #VALID_PLANT_ITEM_BASE;
    IF OBJECT_ID('tempdb..#VALID_PLANT_ITEM_BASE') IS NOT NULL BEGIN DROP TABLE #VALID_PLANT_ITEM_BASE; END;
    CREATE TABLE #VALID_PLANT_ITEM_BASE(
        DIVISION_ID         NVARCHAR(100)
       ,ORIGIN_DIVISION_ID  NVARCHAR(100)
       ,PLAN_START_YYYYMMDD NVARCHAR(30)
       ,PLAN_TYPE           NVARCHAR(30)
       ,SEQ                 INT
       ,OPERATION_GROUP     NVARCHAR(30)
       ,SCM_SITE_ID         NVARCHAR(100)
	   ,PLANT_ID		    NVARCHAR(30)
       ,SITE_DESCRIPTION    NVARCHAR(100)
       ,NICK_NAME           NVARCHAR(50)
       ,ITEM_ID             NVARCHAR(100)
       ,ELECTRODE_TYPE      NVARCHAR(100)
       ,CELL_CF             NVARCHAR(100)
       ,FACTORY_ID          NVARCHAR(100)
       ,LINE_ID             NVARCHAR(100)
       ,OPERATION_ID        NVARCHAR(100)
    );
	
	INSERT INTO  #VALID_LINE_ITEM_BASE 
	SELECT DISTINCT
          'EE' AS DIVISION_ID
        , Z.ORIGIN_DIVISION_ID
        , @QUERY_START_YYYYMMDD AS PLAN_START_YYYYMMDD
        , @P_PLAN_TYPE AS PLAN_TYPE
        , @P_PLAN_SEQ AS SEQ
        , 'E' AS OPERATION_GROUP
        , ISNULL(Z.PLANT_ID,'')+'-E' AS SCM_SITE_ID
		, Z.PLANT_ID
        , Z.SITE_DESCRIPTION
        , Z.NICK_NAME
        , Z.ITEM_ID
        , Z.ELECTRODE_TYPE
        , Z.CELL_CF
        , Z.FACTORY_ID
        , Z.LINE_ID
        , 'E2000' AS OPERATION_ID
	FROM #VALID_LINE_ITEMS Z WITH(NOLOCK)

	INSERT INTO  #VALID_PLANT_ITEM_BASE 
	SELECT DISTINCT
          VXIB.DIVISION_ID
        , VXIB.ORIGIN_DIVISION_ID
        , VXIB.PLAN_START_YYYYMMDD
        , VXIB.PLAN_TYPE AS PLAN_TYPE
        , VXIB.SEQ AS SEQ
        , VXIB.OPERATION_GROUP
        , VXIB.SCM_SITE_ID
		, VXIB.PLANT_ID
        , VXIB.SITE_DESCRIPTION
        , VXIB.NICK_NAME
        , VXIB.ITEM_ID
        , VXIB.ELECTRODE_TYPE
        , VXIB.CELL_CF
        , '-' AS FACTORY_ID
        , '-' AS LINE_ID
        , VXIB.OPERATION_ID
	FROM #VALID_LINE_ITEM_BASE VXIB  WITH(NOLOCK)
	   
	DROP TABLE IF EXISTS #MEASURE_SEQ; 
	IF OBJECT_ID('tempdb..#MEASURE_SEQ') IS NOT NULL BEGIN DROP TABLE #MEASURE_SEQ; END;
    SELECT A.* INTO #MEASURE_SEQ
	FROM (
        SELECT TRIM('PKG_PLAN       ') AS MEAS, TRIM('Sale      ') AS MType, TRIM('PKG_PLAN         ') AS MALIAS, 01 REQ_REC, 01 SORT_SEQ UNION ALL
        SELECT TRIM('SHIP_PLAN_TOTAL') AS MEAS, TRIM('Sale      ') AS MType, TRIM('SHIP_PLAN_TOTAL  ') AS MALIAS, 01 REQ_REC, 02 SORT_SEQ UNION ALL
        SELECT TRIM('PROD_PLAN_TOTAL') AS MEAS, TRIM('Production') AS MType, TRIM('PROD_PLAN_TOTAL  ') AS MALIAS, 01 REQ_REC, 03 SORT_SEQ UNION ALL
        SELECT TRIM('PROD_PLAN_AMEND') AS MEAS, TRIM('Production') AS MType, TRIM('PROD_PLAN_AMEND1 ') AS MALIAS, 01 REQ_REC, 04 SORT_SEQ UNION ALL
        SELECT TRIM('Coating Speed  ') AS MEAS, TRIM('Production') AS MType, TRIM('Coating Speed1   ') AS MALIAS, 01 REQ_REC, 05 SORT_SEQ UNION ALL
        SELECT TRIM('Tact Time      ') AS MEAS, TRIM('Production') AS MType, TRIM('Tact Time1       ') AS MALIAS, 01 REQ_REC, 06 SORT_SEQ UNION ALL
        SELECT TRIM('INVENTORY_TOTAL') AS MEAS, TRIM('Inventory ') AS MType, TRIM('INVENTORY_TOTAL  ') AS MALIAS, 01 REQ_REC, 07 SORT_SEQ UNION ALL
        SELECT TRIM('Hold Release   ') AS MEAS, TRIM('Inventory ') AS MType, TRIM('Hold Release     ') AS MALIAS, 01 REQ_REC, 08 SORT_SEQ UNION ALL
        SELECT TRIM('INVENTORY_DIO  ') AS MEAS, TRIM('Inventory ') AS MType, TRIM('INVENTORY_DIO    ') AS MALIAS, 01 REQ_REC, 09 SORT_SEQ UNION ALL
        SELECT TRIM('Assy Yield     ') AS MEAS, TRIM('Yield     ') AS MType, TRIM('Assy Yield       ') AS MALIAS, 01 REQ_REC, 10 SORT_SEQ UNION ALL
        SELECT TRIM('Elec Yield     ') AS MEAS, TRIM('Yield     ') AS MType, TRIM('Elec Yield       ') AS MALIAS, 01 REQ_REC, 11 SORT_SEQ UNION ALL
		SELECT TRIM('Coating Yield  ') AS MEAS, TRIM('Yield     ') AS MType, TRIM('Coating Yield1   ') AS MALIAS, 01 REQ_REC, 12 SORT_SEQ 
		) AS A;			  
		
    DECLARE @CountOutput INT;
    DECLARE @SQL NVARCHAR(MAX) = '';
    DECLARE @PIVOT_COLS NVARCHAR(MAX) = '';
    DECLARE @PIVOT_COLS_WITH_ALIAS NVARCHAR(MAX) = '';
    DECLARE @INSERT_SELECT_COLS NVARCHAR(MAX) = '';
    DECLARE @INSERT_NULL_SELECT_COLS NVARCHAR(MAX) = '';	   
	   
    PRINT N'PROD_PLAN TABLE 입력';      --========================================  	  
    DROP TABLE IF EXISTS #PROD_PLAN;
    IF OBJECT_ID('tempdb..#PROD_PLAN') IS NOT NULL BEGIN DROP TABLE #PROD_PLAN; END;
    CREATE TABLE #PROD_PLAN(
        SCM_SITE_ID         NVARCHAR(100)
	   ,LINE_ID             NVARCHAR(100)
       ,ITEM_ID             NVARCHAR(100)
	   ,ELECTRODE_TYPE      NVARCHAR(100)
       ,YYYYMMDD            NVARCHAR(8)
       ,QTY					NUMERIC(19,9)
    );
	CREATE CLUSTERED INDEX IX01_PROD_PLAN ON #PROD_PLAN(SCM_SITE_ID, LINE_ID, ITEM_ID)

	INSERT INTO	#PROD_PLAN	-- 계획수립 이전 4주간 생산실적 추출
	        SELECT  
			PRH.PLANT_ID+'-E' 
            ,PRH.LINE_ID
            ,PRH.ITEM_ID
            ,UPPER(PRH.ELECTRODE_TYPE) AS ELECTRODE_TYPE
            ,CONVERT(VARCHAR(8),PRH.PLAN_DATE,112) AS YYYYMMDD
            ,CASE WHEN PRH.DIVISION_ID = '40' AND PRH.PRODUCTION_TYPE IN ('MASS','C-MASS','M-SAMPLE') THEN ISNULL(ACTUAL_GOOD_QTY,0.00)
                WHEN PRH.DIVISION_ID = '40' AND PRH.PRODUCTION_TYPE NOT IN ('MASS','C-MASS','M-SAMPLE') THEN 0
                ELSE ISNULL(PRH.ACTUAL_GOOD_QTY,0.00) END
                * ( SELECT ISNULL( MIN(Y.CONVERT_QTY_CELL),1)
                    FROM SCP_MST_FINAL_ITEM Y WITH (NOLOCK)
                    WHERE Y.ITEM_ID    = PRH.ITEM_ID
                    AND Y.CONVERT_QTY_CELL IS NOT NULL )
	FROM   SCM_DAILY_PRODUCT_RESULT_H_SN PRH WITH(NOLOCK)
    JOIN #VALID_LINE_ITEMS AS WI WITH(NOLOCK)
		ON  PRH.ITEM_ID               = WI.ITEM_ID
		AND PRH.PLANT_ID              = WI.PLANT_ID
		AND PRH.LINE_ID              = WI.LINE_ID
    WHERE  PRH.OPERATION_ID = 'E2000'
		AND    PRH.PLAN_DATE >= @PREV_QUERY_START_YYYYMMDD
		AND    PRH.PLAN_DATE < @QUERY_START_YYYYMMDD
		--Production type
		--자동차/ESS (81/82) : 4M-VALID,MASS,C-MASS,D-SAMPLE,M-SAMPLE,D-TEST,TEST,
		--소형 (40) : MASS,C-MASS,M-SAMPLE
		AND    PRH.PRODUCTION_TYPE IN ('4M-VALID','MASS','C-MASS','D-SAMPLE','M-SAMPLE','D-TEST','TEST')
		AND    PRH.ACTUAL_GOOD_QTY <> 0;
		
	INSERT INTO	#PROD_PLAN	-- 계획수립 구간 계획 추출
    SELECT DISTINCT
		PP.SCM_SITE_ID
        , PP.LINE_ID
        , PP.ITEM_ID
        , PP.ELECTRODE_TYPE
        , PP.YYYYMMDD
        , ISNULL(PP.qty,0.00)
						* ( SELECT ISNULL( MIN(Y.CONVERT_QTY_CELL),1)
							FROM SCP_MST_FINAL_ITEM Y WITH (NOLOCK)
							WHERE Y.ITEM_ID    = PP.ITEM_ID
								AND Y.CONVERT_QTY_CELL IS NOT NULL ) qty  
    FROM SCP_ANL_PRODUCTION_PLAN AS PP WITH(NOLOCK)
			JOIN #VALID_LINE_ITEMS PLI WITH(NOLOCK)        
			ON LEFT(PP.SCM_SITE_ID,4) = PLI.PLANT_ID
				AND PP.LINE_ID = PLI.LINE_ID
				AND PP.ELECTRODE_TYPE = PLI.ELECTRODE_TYPE
				AND PP.ITEM_ID = PLI.ITEM_ID
	WHERE   PP.DIVISION_ID          = 'EE'
    AND     PP.OPERATION_GROUP      = 'E'
	AND     PP.OPERATION_ID='E2000'
    AND     PP.MEASURE              ='PROD_PLAN_AMEND'
