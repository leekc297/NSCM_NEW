        ON    WAY.SCM_SITE_ID = VXIB.SCM_SITE_ID
        AND   WAY.ITEM_ID = VXIB.ITEM_ID
		'
        --ELEC YIELD ===================================
    SET @SQL += N'
        UNION ALL
        SELECT DISTINCT '+@VXIB_HEADER+'
            , ''Yield'' AS PSI_TYPE
            , ''Elec Yield'' AS MEASURE
            , ISNULL(YYYYMMDD,'''+@QUERY_START_YYYYMMDD+''') AS YYYYMMDD
            , WEY.YIELD AS QTY
        FROM  #VALID_PLANT_ITEM_BASE VXIB WITH(NOLOCK)
        LEFT JOIN  #TMP_W_ELEC_YIELD WEY WITH(NOLOCK)
        ON    WEY.SCM_SITE_ID = VXIB.SCM_SITE_ID
        AND   WEY.ITEM_ID = VXIB.ITEM_ID		
		'

