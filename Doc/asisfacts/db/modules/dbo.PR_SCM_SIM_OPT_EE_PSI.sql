    SET @SQL += N'
        UNION ALL
        SELECT DISTINCT '+@VXIB_HEADER+'
            , ''Yield'' AS PSI_TYPE
            , ''Coating Yield'' AS MEASURE
            , (CASE WHEN WCY.LINE_ID = VXIB.LINE_ID THEN  WCY.YYYYMMDD  ELSE '''+@QUERY_START_YYYYMMDD+''' END)  AS YYYYMMDD
			, (CASE WHEN WCY.LINE_ID = VXIB.LINE_ID THEN  WCY.YIELD  ELSE NULL END)  AS QTY
        FROM  #VALID_LINE_ITEM_BASE VXIB WITH(NOLOCK)
        LEFT JOIN  #TMP_W_COATING_YIELD WCY WITH(NOLOCK)
			ON    WCY.SCM_SITE_ID = VXIB.SCM_SITE_ID
			AND   WCY.LINE_ID = VXIB.LINE_ID
			AND   WCY.ITEM_ID = VXIB.ITEM_ID
		'
        --HOLD RELEASE ====================================				
    SET @SQL += N'
        UNION ALL
        SELECT DISTINCT '+@VXIB_HEADER+'
            , ''Inventory'' AS PSI_TYPE
            , ''Hold Release'' AS MEASURE
            , ISNULL(WHR.YYYYMMDD, '''+@QUERY_START_YYYYMMDD+''') AS YYYYMMDD
            , (CASE WHEN WHR.YYYYMMDD> '''+LEFT(@P_OPT_PLAN_ID,8)+N''' THEN WHR.Hold_Release_QTY ELSE NULL END)
                * ( SELECT ISNULL( MIN(Y.CONVERT_QTY_CELL),1)
                       FROM SCP_MST_FINAL_ITEM Y WITH (NOLOCK)
                      WHERE Y.ITEM_ID    = WHR.ITEM_ID
                        AND Y.CONVERT_QTY_CELL IS NOT NULL ) AS QTY
        FROM  #VALID_PLANT_ITEM_BASE VXIB WITH(NOLOCK)
        LEFT JOIN  #TMP_W_HOLD_REL_RAW WHR WITH(NOLOCK)
			ON WHR.ITEM_ID = VXIB.ITEM_ID
	--		AND   WHR.PLANT_ID = LEFT(VXIB.SCM_SITE_ID,4)   --  [[E20260709-001528] Hold Release추출시 Plant 조건삭제]  2026.7.20 박원채  PLANT 조건 삭제
    )
    , W_WEEKLY_SUM AS (
        SELECT '+@VXIB_HEADER+' 
            , PSI_TYPE
            , MEASURE
            , WC.PARTIAL_WEEK_NAME
            , WC.BASIS_START_DATE
            , WC.BASIS_END_DATE
            , QTY=CASE WHEN ( PSI_TYPE=''Yield'' OR MEASURE IN (''Tact Time'',''Coating Speed'',''INVENTORY_TOTAL'') ) THEN MAX(QTY) ELSE SUM(QTY) END
        FROM  #TMP_CALENDAR AS WC WITH(NOLOCK)
        LEFT JOIN  W_ALL_DSUM VXIB WITH(NOLOCK) ON VXIB.YYYYMMDD = WC.BASIS_YYYYMMDD     
        GROUP BY DIVISION_ID
            , ORIGIN_DIVISION_ID
            , PLAN_START_YYYYMMDD
            , PLAN_TYPE
            , SEQ
            , OPERATION_GROUP
            , SCM_SITE_ID
            , SITE_DESCRIPTION
            , NICK_NAME
            , ITEM_ID
            , ELECTRODE_TYPE
            , CELL_CF
            , FACTORY_ID
            , LINE_ID
            , OPERATION_ID
            , PSI_TYPE
            , MEASURE
            , WC.PARTIAL_WEEK_NAME
            , WC.BASIS_START_DATE 
            , WC.BASIS_END_DATE   
    )'
    SET @SQL += N'
    , W_PIV_SRC AS (
        SELECT  '+@VXIB_HEADER+'
              ,PSI_TYPE
              ,MEASURE
              ,BASIS_START_DATE
              ,QTY
        FROM   W_WEEKLY_SUM VXIB WITH(NOLOCK)
        WHERE  MEASURE IS NOT NULL
    )
    , W_PIV_RST_WEEK AS (
        SELECT
            DIVISION_ID
            ,ORIGIN_DIVISION_ID
            ,PLAN_START_YYYYMMDD
            ,PLAN_TYPE
            ,SEQ
            ,OPERATION_GROUP
            ,SCM_SITE_ID
            ,SITE_DESCRIPTION, NICK_NAME, ITEM_ID, ELECTRODE_TYPE, CELL_CF, FACTORY_ID, LINE_ID
            ,OPERATION_ID
            ,PSI_TYPE
            ,MEASURE
            ,NULL AS Elec_Site_QTY
            ,NULL AS Assy_Site_QTY
            ,NULL AS Intransit_QTY
            ,NULL AS HD_QTY
            ,'+@PIVOT_COLS_WITH_ALIAS+N'
        FROM W_PIV_SRC WPS  WITH(NOLOCK)
        PIVOT
            (
                SUM(QTY)
                FOR BASIS_START_DATE IN ('+@PIVOT_COLS+N')
            ) AS W_PIV_SRC
        UNION ALL
        SELECT DISTINCT '+@VXIB_HEADER+'
            , ''Inventory'' AS PSI_TYPE
            , ''INVENTORY_TOTAL'' AS MEASURE
            , WBP.Elec_Site_QTY
            , WBP.Assy_Site_QTY
            , WBP.Intransit_QTY
            , WBP.HD_QTY
            , '+@INSERT_NULL_SELECT_COLS+N'
        FROM #VALID_PLANT_ITEM_BASE VXIB WITH(NOLOCK)
        LEFT JOIN  #TMP_W_BOH_PIVOT_RAW WBP  WITH(NOLOCK)
			ON WBP.ITEM_ID = VXIB.ITEM_ID 
    ) '
    SET @SQL += N'
    INSERT INTO SCM_SIM_DYN_COLS(
        SNAP_YYYYMMDD
       ,REPORT_TITLE
       ,PLANT_ID
       ,PLAN_GROUP
       ,DIVISION_ID
       ,'+@COL_NUM1 +N'
       ,C371 -- ORIGIN_DIVISION_ID
       ,C372 -- OPERATION_GROUP
       ,C373 -- OPERATION_ID
       ,SORT_SEQ1
       ,CREATED_BY
       ,LAST_UPDATED_BY
       ,BATCH_ID
    )
    SELECT '''+@P_SNAP_YYYYMMDD+N'''
       ,'''+@V_REPORT_TITLE_PSI_DETAIL+N'''
       ,'''+@P_PLANT_ID+N'''
       ,'''+@P_PLAN_GROUP+N'''
       ,'''+@P_DIVISION_ID+N'''
       , DIVISION_ID, PLAN_START_YYYYMMDD, PLAN_TYPE, SEQ, SCM_SITE_ID
       , SITE_DESCRIPTION, NICK_NAME, ITEM_ID, ELECTRODE_TYPE, CELL_CF, FACTORY_ID, LINE_ID, PSI_TYPE
       , MEASURE
       , Elec_Site_QTY AS BOH1
       , Assy_Site_QTY AS BOH2
       , Intransit_QTY AS BOH3
       , HD_QTY AS BOH4
       , BOH5 = CONVERT(NUMERIC(19,9),CASE WHEN NOT ( Elec_Site_QTY IS NULL AND Assy_Site_QTY IS NULL AND Intransit_QTY IS NULL AND HD_QTY IS NULL ) 
                                           THEN 
                                               CONVERT(NUMERIC(19,9),ISNULL(Elec_Site_QTY,0.0))
                                              +CONVERT(NUMERIC(19,9),ISNULL(Assy_Site_QTY,0.0))
                                              +CONVERT(NUMERIC(19,9),ISNULL(Intransit_QTY,0.0))
                                              +CONVERT(NUMERIC(19,9),ISNULL(HD_QTY,0.0)       )
                                           END)
       , NULL AS UNIT
       ,'+@INSERT_SELECT_COLS+N'
       , ORIGIN_DIVISION_ID --C371 -- 
       , OPERATION_GROUP --C372 -- 
       , OPERATION_ID --C373 -- 
       , 10000
       ,'''+@v_online_user+N''' AS CREATED_BY
       ,'''+@v_online_user+N''' AS LAST_UPDATED_BY
       ,'''+CONVERT(NVARCHAR(MAX),@BATCH_ID)+N''' AS BATCH_ID
    FROM   W_PIV_RST_WEEK WRW  WITH(NOLOCK)
    LEFT JOIN #MEASURE_SEQ AS WM  WITH(NOLOCK) ON WM.MEAS = WRW.MEASURE;';
