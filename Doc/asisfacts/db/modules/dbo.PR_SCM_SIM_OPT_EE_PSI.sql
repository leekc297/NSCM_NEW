    PRINT N' 생산계획수립안된 LINE_ID 라인에 대하여 ^A 를 DIVISION_ID 자리에 넣는다.';  --==============================================
    UPDATE SDC
    SET    SDC.C6 = ISNULL(SDC.C6,'')+'^A', DEV1 = ISNULL(SDC.DEV1,'')+'^A'
    FROM   SCM_SIM_DYN_COLS SDC 
	JOIN @TBL_VALID_LINE_ITEMS2 VLI
		ON VLI.PLANT_ID = LEFT(SDC.C5,4)
		AND VLI.LINE_ID = SDC.C12
		AND VLI.ITEM_ID = SDC.C8
		AND ISNULL(VLI.PLANNED,'N') <> 'Y'
	WHERE  SDC.SNAP_YYYYMMDD = @P_SNAP_YYYYMMDD
		AND    SDC.REPORT_TITLE= @V_REPORT_TITLE_PSI_DETAIL
		AND    SDC.C14 = 'PROD_PLAN_AMEND'
		AND    SDC.PLAN_GROUP=@P_PLAN_GROUP		
		AND    SDC.DIVISION_ID=@P_DIVISION_ID
		AND    SDC.CREATED_BY = @v_online_user
		AND    SDC.BATCH_ID = @P_BATCH_ID;

	 PRINT N'SORT_SEQ1 번호 설정';   --==================================================================
	 WITH Ordered AS (
		SELECT 
			ROW_NUMBER() OVER (
				ORDER BY SDC.C5, SDC.C7, SDC.C8, m.SORT_SEQ, SDC.C12
			) AS rn,
			SDC.C5, SDC.C7, SDC.C8, SDC.C14, SDC.C12,m.MTYPE AS MTYPE
		FROM SCM_SIM_DYN_COLS SDC WITH(NOLOCK)
		JOIN #MEASURE_SEQ m WITH(NOLOCK)
		  ON SDC.C14 = m.MEAS   
		WHERE SDC.BATCH_ID = @P_BATCH_ID
        AND  SDC.SNAP_YYYYMMDD = @P_SNAP_YYYYMMDD
        AND  SDC.REPORT_TITLE= @V_REPORT_TITLE_PSI_DETAIL
        AND  SDC.PLAN_GROUP=@P_PLAN_GROUP
        AND  SDC.DIVISION_ID=@P_DIVISION_ID
        AND  SDC.CREATED_BY = @v_online_user
	)
	UPDATE SDC
	SET SORT_SEQ1 = 10000+o.rn*5, SDC.C13=o.MTYPE, C20 = 'CELL'
	FROM SCM_SIM_DYN_COLS SDC
	JOIN Ordered o WITH(NOLOCK)
	  ON SDC.C5=o.C5 AND SDC.C7=o.C7 AND SDC.C8=o.C8 AND SDC.C14=o.C14 AND ISNULL(SDC.C12,'')=ISNULL(o.C12,'')
	WHERE SDC.BATCH_ID = @P_BATCH_ID
    AND  SDC.SNAP_YYYYMMDD =@P_SNAP_YYYYMMDD
    AND  SDC.REPORT_TITLE= @V_REPORT_TITLE_PSI_DETAIL
    AND  SDC.PLAN_GROUP=@P_PLAN_GROUP
    AND  SDC.DIVISION_ID=@P_DIVISION_ID
    AND  SDC.CREATED_BY = @v_online_user;

    PRINT N'Resource 영역처리 시작'; --==========================================
	DECLARE @INSERT_HEADER NVARCHAR(MAX);
	SET @INSERT_HEADER = N'
				SNAP_YYYYMMDD
			   ,REPORT_TITLE
			   ,PLANT_ID
			   ,PLAN_GROUP
			   ,DIVISION_ID
			   ,C18,C19,C20
			   ,'+@COL_NUM21 +'
			   ,SORT_SEQ1
			   ,CREATED_BY
			   ,LAST_UPDATED_BY
			   ,BATCH_ID
			   ,CREATION_DATE
			   ,LAST_UPDATE_DATE
			)
			SELECT '''+@P_SNAP_YYYYMMDD+N'''
			   ,'''+@V_REPORT_TITLE_RESOURCE+N'''
			   ,'''+@P_PLANT_ID+'''
			   ,'''+@P_PLAN_GROUP+'''
			   ,'''+@P_DIVISION_ID+N'''
		';

	DECLARE CURSOR_NUM CURSOR FAST_FORWARD READ_ONLY LOCAL FOR
		SELECT 1 AS num  UNION ALL
		SELECT 2;
	OPEN CURSOR_NUM;
	FETCH NEXT FROM CURSOR_NUM INTO @LOOP_CNT;
	WHILE @@FETCH_STATUS = 0
	BEGIN
		IF @LOOP_CNT = 1 
			SET @DATA_STRS = @WQTY_LABEL_COLS
		ELSE
			SET @DATA_STRS = @WEEK_NAME_LABEL_COLS;
		SET @SQL = N'	
		INSERT INTO SCM_SIM_DYN_COLS(
			'+@INSERT_HEADER+'
		   ,''Change Time'' AS C18,''Resource'' AS C19,''TYPE'' AS C20
		   ,'+@DATA_STRS+'
		   , '+CAST(@LOOP_CNT*10 AS NVARCHAR)+' AS SORT_SEQ1
		   ,'''+@v_online_user+N'''
		   ,'''+@v_online_user+N'''
		   ,'''+@P_BATCH_ID+N'''
		   ,SYSDATETIME()
		   ,SYSDATETIME()
		   ';
		EXEC sp_executesql @SQL;
		FETCH NEXT FROM CURSOR_NUM INTO @LOOP_CNT;
	END;
	CLOSE CURSOR_NUM;
	DEALLOCATE CURSOR_NUM;

    DECLARE @TBL_CAPA_RAW TABLE(
		LINE_ID				NVARCHAR(50)
		,YYYYMMDD			NVARCHAR(50)
		,QTY				NUMERIC(19,9)
		,BASIS_START_DATE   NVARCHAR(8)
    );
	INSERT INTO @TBL_CAPA_RAW
	SELECT  SUBSTRING(C2, ((LEN(OPR.SITE) +2)+ 1),  LEN(C2) - (LEN(OPR.SITE) +2)) AS LINE_ID
            , DATE AS YYYYMMDD, CASE WHEN ISNUMERIC(QTY) = 1 THEN TRY_CONVERT(FLOAT,QTY) END AS QTY, CM.BASIS_START_DATE
	FROM OPTENG_SCP.DBO.SCP_OPT_ENG_OUT_PLAN_RESULT OPR WITH(NOLOCK)
    JOIN #TMP_CALENDAR AS CM WITH(NOLOCK)
		ON  OPR.DATE = CM.BASIS_YYYYMMDD
    WHERE   OPR.PLAN_ID = @P_OPT_PLAN_ID
		AND     OPR.C1='upper_limit'
		AND     TYPE='Capacity'
		AND     ITEM='LINE';
	
    DECLARE @TBL_CHG_TIME_DATA TABLE(
		LINE	  NVARCHAR(50)
		,CHG_TIME NUMERIC(19,9)
    );	
	INSERT INTO @TBL_CHG_TIME_DATA
	SELECT SEGMENT4 AS LINE, avg(convert(float,ATTRIBUTE3)+convert(float,ATTRIBUTE4)) AS  CHG_TIME
	FROM  SCP_OPMZ_LOOKUP_MASTER_DETAIL LMD WITH(NOLOCK)
	JOIN  (SELECT DISTINCT PLANT_ID FROM #VALID_PLANT_ITEMS WITH(NOLOCK)) WP ON WP.PLANT_ID+N'-E' = LMD.SEGMENT3
	WHERE LOOKUP_TYPE = N'SCP_OPT_ENG_CONST_SETUP'
		AND   ISNULL(SEGMENT6, '-')  = '-'
	GROUP BY  SEGMENT4;

	SET @TMP_STR = N'형교환 시간';
	DECLARE @CHG_TIME_STR NVARCHAR(50);
	SET @LOOP_CNT = 0;
	DECLARE @LINE_ID NVARCHAR(100);
	DECLARE CURSOR_NUM CURSOR FAST_FORWARD READ_ONLY LOCAL FOR
		SELECT DISTINCT C12 AS LINE_ID FROM SCM_SIM_DYN_COLS WITH(NOLOCK)
		WHERE BATCH_ID = @P_BATCH_ID 
			AND  SNAP_YYYYMMDD =@P_SNAP_YYYYMMDD
			AND  REPORT_TITLE= @V_REPORT_TITLE_PSI_DETAIL
			AND  PLAN_GROUP=@P_PLAN_GROUP
			AND  DIVISION_ID=@P_DIVISION_ID
			AND  CREATED_BY = @v_online_user
			AND  C14 = 'PROD_PLAN_AMEND'
		ORDER BY C12;
	OPEN CURSOR_NUM;
	FETCH NEXT FROM CURSOR_NUM INTO @LINE_ID;
	WHILE @@FETCH_STATUS = 0
	BEGIN
		WITH CAPA_DATA AS (
			SELECT DISTINCT CM.BASIS_START_DATE, CONVERT(NUMERIC(19,9),SUM(ISNULL(CR.QTY,0.00))) AS QTY
			FROM   #TMP_CALENDAR AS CM WITH(NOLOCK)
			LEFT JOIN @TBL_CAPA_RAW AS CR
				ON CR.YYYYMMDD = CM.BASIS_YYYYMMDD
				AND CR.LINE_ID = @LINE_ID
			GROUP BY CM.BASIS_START_DATE
			)
		SELECT @DATA_STRS = STRING_AGG(CAST(QUOTENAME(CONVERT(NVARCHAR,ISNULL(QTY,0.0)),'''') AS NVARCHAR(MAX)), ',') WITHIN GROUP (ORDER BY BASIS_START_DATE)
		FROM   CAPA_DATA WITH(NOLOCK);	
		SET @CHG_TIME_STR='0';
		SET @sql = N'
			INSERT INTO SCM_SIM_DYN_COLS(
				'+@INSERT_HEADER+'
			   ,'''' AS C18, VLI.LINE_ID AS C19,''CAPA'' AS C20
			   ,'+@DATA_STRS+N'
			   ,('+CAST(@LOOP_CNT AS NVARCHAR)+'*5 + 1)+1000 AS SORT_SEQ1
			   ,'''+@v_online_user+N'''
			   ,'''+@v_online_user+N'''
			   ,'''+CONVERT(NVARCHAR(MAX),@BATCH_ID)+N'''
			   ,SYSDATETIME()
			   ,SYSDATETIME()
			FROM (SELECT '''+@LINE_ID+''' AS LINE_ID) AS VLI
			';
		EXEC(@sql);

		IF EXISTS (SELECT TOP 1 * FROM @TBL_CHG_TIME_DATA WHERE LINE = @LINE_ID)
			SELECT @CHG_TIME_STR = CONVERT(NVARCHAR(30),CONVERT(NUMERIC(19,9),CHG_TIME)) FROM @TBL_CHG_TIME_DATA WHERE LINE = @LINE_ID	
		ELSE SET @CHG_TIME_STR=N'0';
		SET @sql = N'
			INSERT INTO SCM_SIM_DYN_COLS(
				'+@INSERT_HEADER+N'
			   ,(CASE WHEN CPT.RTYPE=N''CHG_HOUR'' THEN '''+@CHG_TIME_STR+''' ELSE '''' END) AS C18
			   ,(CASE WHEN CPT.RTYPE=N''CHG_HOUR'' THEN N'''+@TMP_STR+''' ELSE VLI.LINE_ID END) AS C19
			   ,CPT.RTYPE AS C20
			   ,'+@EMPTY_DATA_COLS+N'
			   ,('+CAST(@LOOP_CNT AS NVARCHAR)+'*5 + CPT.SEQ1)+1000 AS SORT_SEQ1
			   ,'''+@v_online_user+N'''
			   ,'''+@v_online_user+N'''
			   ,'''+CONVERT(NVARCHAR(MAX),@BATCH_ID)+N'''
			   ,SYSDATETIME()
			   ,SYSDATETIME()
			FROM (SELECT '''+@LINE_ID+''' AS LINE_ID) AS VLI
				CROSS JOIN (
					SELECT TRIM(''LOAD      '') AS RTYPE, ''2'' AS SEQ1 UNION ALL
					SELECT TRIM(''CHG_HOUR  '') AS RTYPE, ''3'' AS SEQ1 UNION ALL
					SELECT TRIM(''LOAD_RATIO'') AS RTYPE, ''4'' AS SEQ1 ) AS CPT
			';
		EXEC(@sql);
		SET @LOOP_CNT = @LOOP_CNT+1;
		FETCH NEXT FROM CURSOR_NUM INTO @LINE_ID;
	END;
	CLOSE CURSOR_NUM;
	DEALLOCATE CURSOR_NUM;
   
