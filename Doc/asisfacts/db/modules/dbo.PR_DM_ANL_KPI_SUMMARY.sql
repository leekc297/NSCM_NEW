 SELECT DIVISION_ID  
 FROM   #I_DIVISION WITH(NOLOCK)  
 GROUP BY DIVISION_ID  
  
 OPEN CUR_KPI_SUMMARY;  
 FETCH NEXT FROM CUR_KPI_SUMMARY INTO @V_DIVISION_ID ;  
  

 ----------------------------------------------------------------------------------------------------- ◇◇◇◇◇  
 --                                                                             CUR_KPI_SUMMARY CURSOR (BEGIN)  
 ----------------------------------------------------------------------------------------------------- ◇◇◇◇◇  
 WHILE (@@FETCH_STATUS = 0)  
 ----------------------------------------------------------------------------------------------------- ◇◇◇◇◇  
 BEGIN  

 
