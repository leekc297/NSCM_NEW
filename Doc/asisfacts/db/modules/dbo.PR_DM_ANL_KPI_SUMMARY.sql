 ----------------------------------------------------------------------------------------------------------------------------------------------------------------------------   
 --                                                                                                                                           DIVISION 별 CURSOR 수행 (BEGIN)  
 ----------------------------------------------------------------------------------------------------------------------------------------------------------------------------   
  
