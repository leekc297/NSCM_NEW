		, CONVERT( VARCHAR, DATEADD(DAY,-3/*주차차이*/*7, CAST(MIN(B.BASIS_YYYYMMDD) AS DATETIME) ) , 112) AS B4_BASIS_YYYYMMDD
		, CONVERT( VARCHAR, DATEADD(DAY,-4/*주차차이*/*7, CAST(MIN(B.BASIS_YYYYMMDD) AS DATETIME) ) , 112) AS B5_BASIS_YYYYMMDD
