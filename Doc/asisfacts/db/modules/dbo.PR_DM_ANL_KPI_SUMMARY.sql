		DROP TABLE #TEMP_DM_MST_ITEM_SINGLE_V

	SELECT DIVISION_ID, ITEM_ID, NICK_NAME
	INTO #TEMP_DM_MST_ITEM_SINGLE_V
	FROM DM_MST_ITEM_SINGLE_V 
