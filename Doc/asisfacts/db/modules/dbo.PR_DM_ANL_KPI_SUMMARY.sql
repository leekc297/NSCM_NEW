									AND X1.ITEM_ID        = A.ITEM_ID			AND X1.FCST_TYPE     = A.FCST_TYPE		AND X1.PARTIAL_WEEK_NAME = A.PARTIAL_WEEK_NAME  --AND Z.CALENDAR_YYYY+'_'+Z.PARTIAL_WEEK_NAME = B.CALENDAR_YYYY+'_'+B.PARTIAL_WEEK_NAME
	LEFT OUTER JOIN #DATE_TEMP X2 ON X2.MEASURE = @V_WHERE_MEASURE
									AND X2.DIVISION_ID    = A.DIVISION_ID		AND X2.SCM_SITE_ID   = A.SCM_SITE_ID	AND X2.PROJECT_CODE  = A.PROJECT_CODE	
									AND X2.ITEM_ID        = A.ITEM_ID			AND X2.FCST_TYPE     = A.FCST_TYPE		AND X2.PARTIAL_WEEK_NAME = A.PARTIAL_WEEK_NAME 
	LEFT OUTER JOIN #DATE_TEMP X3 ON X3.MEASURE = @V_WHERE_MEASURE		
									AND X3.DIVISION_ID    = A.DIVISION_ID		AND X3.SCM_SITE_ID   = A.SCM_SITE_ID	AND X3.PROJECT_CODE  = A.PROJECT_CODE	
									AND X3.ITEM_ID        = A.ITEM_ID			AND X3.FCST_TYPE     = A.FCST_TYPE		AND X3.PARTIAL_WEEK_NAME = A.PARTIAL_WEEK_NAME	
	LEFT OUTER JOIN #DATE_TEMP X4 ON X4.MEASURE = @V_WHERE_MEASURE
									AND X4.DIVISION_ID    = A.DIVISION_ID		AND X4.SCM_SITE_ID   = A.SCM_SITE_ID	AND X4.PROJECT_CODE  = A.PROJECT_CODE	
									AND X4.ITEM_ID        = A.ITEM_ID			AND X4.FCST_TYPE     = A.FCST_TYPE		AND X4.PARTIAL_WEEK_NAME = A.PARTIAL_WEEK_NAME 
	LEFT OUTER JOIN #DATE_TEMP X5 ON X5.MEASURE = @V_WHERE_MEASURE
									AND X5.DIVISION_ID    = A.DIVISION_ID		AND X5.SCM_SITE_ID   = A.SCM_SITE_ID	AND X5.PROJECT_CODE  = A.PROJECT_CODE  						   
