    FROM #I_DIVISION

    SELECT @V_DESCRIPTION = DBO.FN_GET_PIVOT_STRING(@T, ',')


 -------------------------------------------------------------------- LOG에 작업하는 DIVISION_ID 를 표기 (END)  
  
 -- 시작 LOG  (START)  
 SET @V_LOG_TYPE = 'START';  
 SET @V_LOG_MESSAGE = '########## START OF PROCEDURE ##########';  
 SET @D_EVENT_DATE = SYSDATETIME();  
 EXEC PR_SCM_SYS_LOG_BATCH @V_PROGRAM_NAME, @V_LOG_TYPE, @N_LOG_COUNT, @V_LOG_MESSAGE, @V_DESCRIPTION, @D_EVENT_DATE;  
 SET @V_LOG_MESSAGE = NULL      /*-- <- 변수 재사용을 위하여 초기화해야함 --*/  
 -- 시작 LOG  (END)  

 
 -- 트랜잭션 (START)  
 BEGIN TRANSACTION PR_DM_ANL_KPI_SUMMARY;  
 
 --------------------------------------------------------------------------------------------   
 BEGIN TRY  
 --------------------------------------------------------------------------------------------   
  
  
	 -- [C20201208-000161] TMP TABLE 로변경
	INSERT INTO #DATE_TEMP( QTY, BB_BASIS_YYYYMMDD, DIVISION_ID, SCM_SITE_ID, PROJECT_CODE, ITEM_ID, FCST_TYPE, PARTIAL_WEEK_NAME, MEASURE)		
		SELECT SUM(ISNULL(X.QTY,0)) QTY , MIN(Y.BB_BASIS_YYYYMMDD) AS BB_BASIS_YYYYMMDD 
			, X.DIVISION_ID, X.SCM_SITE_ID, X.PROJECT_CODE, X.ITEM_ID, X.FCST_TYPE
			, Z.CALENDAR_YYYY+'_'+Z.PARTIAL_WEEK_NAME AS PARTIAL_WEEK_NAME, X.MEASURE
		FROM DM_PLN_MKT_FCST_C X WITH(NOLOCK)  
			INNER JOIN
			(	
				SELECT AA.DIVISION_ID, MAX(AA.VERSION_NO) VERSION_NO  
					, BB.BASIS_YYYYMMDD AS BB_BASIS_YYYYMMDD 
				FROM [DBO].[DM_MST_VERSION] AA WITH(NOLOCK)  
						,[DBO].[SCM_SYS_CALENDAR_M] BB WITH(NOLOCK)  
						,[DBO].[SCM_SYS_CALENDAR_M] CC WITH(NOLOCK)  
				WHERE   AA.VERSION_TYPE = 'MF_W'  
					AND AA.YYYYMMDD >= @V_TO_DATE --'20180401' -- OPEN 이후 VERSION  
					AND AA.YYYYMMDD = CC.BASIS_YYYYMMDD  
					AND BB.ISO_YYYYWW = CC.ISO_YYYYWW  
					--AND CONVERT( VARCHAR, DATEADD(DAY,-0/*주차차이*/*7, CAST('20190124' AS DATETIME) ) , 112) = BB.BASIS_YYYYMMDD  
				GROUP BY AA.DIVISION_ID, BB.BASIS_YYYYMMDD

			) Y  ON X.DIVISION_ID		= Y.DIVISION_ID  
					AND X.VERSION_NO    = Y.VERSION_NO  						   						   
			INNER JOIN [DBO].[SCM_SYS_CALENDAR_M] Z  ON X.YYYYMMDD = Z.BASIS_YYYYMMDD
														--AND Z.CALENDAR_YYYY+'_'+Z.PARTIAL_WEEK_NAME = B.CALENDAR_YYYY+'_'+B.PARTIAL_WEEK_NAME
		WHERE  1=1    
				--AND X.DIVISION_ID   = A.DIVISION_ID  
				--AND X.SCM_SITE_ID   = A.SCM_SITE_ID  
				--AND X.PROJECT_CODE  = A.PROJECT_CODE  						   
				--AND X.ITEM_ID       = A.ITEM_ID  
				--AND X.FCST_TYPE     = A.FCST_TYPE  						   						   
				AND X.MEASURE       IN ('MKT_FCST','CUST_FCST','RTF')-- --= 'MKT_FCST'
				AND X.VERSION_NO LIKE 'MF_W%'
		GROUP BY X.DIVISION_ID, X.SCM_SITE_ID, X.PROJECT_CODE, X.ITEM_ID, X.FCST_TYPE
				, Z.CALENDAR_YYYY+'_'+Z.PARTIAL_WEEK_NAME	, X.MEASURE

