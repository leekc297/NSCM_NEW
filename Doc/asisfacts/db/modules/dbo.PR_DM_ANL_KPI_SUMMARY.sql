    SET XACT_ABORT ON;  
  
 -- LOG 용 변수 설정  
    DECLARE @V_PROGRAM_NAME NVARCHAR(150) = 'PR_DM_ANL_KPI_SUMMARY';  
    DECLARE @V_LOG_TYPE     NVARCHAR(30); -- START/END/ERROR/...  
    DECLARE @N_LOG_COUNT    INTEGER = 0;  
    DECLARE @V_LOG_MESSAGE  NVARCHAR(1000);  
    DECLARE @V_DESCRIPTION  NVARCHAR(500);  
    DECLARE @D_EVENT_DATE   DATETIME;  
  
 -- 변수  
    DECLARE @V_DIVISION_ID  NVARCHAR(30);  
    DECLARE @V_YYYYMMDD     NVARCHAR(08);  
	DECLARE @V_TO_DATE			NVARCHAR(08);	-- [C20201208-000161] '20180401' 기간변경
	DECLARE @V_WHERE_MEASURE	nvarchar(50)	-- [C20201208-000161] 기존 ISNULL 

	SET @V_TO_DATE = CONVERT(CHAR(8), DATEADD(MONTH, -6, GETDATE()), 112)
	SET @V_YYYYMMDD = CONVERT(VARCHAR,GETDATE(), 112)  
  
  /*
