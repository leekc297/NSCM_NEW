		, CONVERT( VARCHAR, DATEADD(DAY,-7/*주차차이*/*7, CAST(MIN(B.BASIS_YYYYMMDD) AS DATETIME) ) , 112) AS B8_BASIS_YYYYMMDD
		, CONVERT( VARCHAR, DATEADD(DAY,-8/*주차차이*/*7, CAST(MIN(B.BASIS_YYYYMMDD) AS DATETIME) ) , 112) AS B9_BASIS_YYYYMMDD
		, CONVERT( VARCHAR, DATEADD(DAY,-9/*주차차이*/*7, CAST(MIN(B.BASIS_YYYYMMDD) AS DATETIME) ) , 112) AS B10_BASIS_YYYYMMDD
		, CONVERT( VARCHAR, DATEADD(DAY,-10/*주차차이*/*7, CAST(MIN(B.BASIS_YYYYMMDD) AS DATETIME) ) , 112) AS B11_BASIS_YYYYMMDD
		, CONVERT( VARCHAR, DATEADD(DAY,-11/*주차차이*/*7, CAST(MIN(B.BASIS_YYYYMMDD) AS DATETIME) ) , 112) AS B12_BASIS_YYYYMMDD
		-- [C20201208-000161].E

		 FROM DM_PLN_MKT_FCST_RESULT A WITH(NOLOCK)  
		  ,[DBO].[SCM_SYS_CALENDAR_M] B WITH(NOLOCK)  
		  ,#TEMP_DM_MST_ITEM_SINGLE_V C WITH(NOLOCK)  
		  ,SCM_MST_SITE D  
		  ,SCM_MST_SITE_ITEM E  
		  ,[DBO].[SCM_MST_SSO_DEPT_INFO] F WITH(NOLOCK)--   
		  ,[DBO].[SCM_MST_SSO_USER_INFO] G WITH(NOLOCK)--   
	--      ,[DBO].[SCM_MST_PROJECT] G WITH(NOLOCK)--   
		WHERE A.DIVISION_ID		= @V_DIVISION_ID  
		  AND A.YYYYMMDD		>= @V_TO_DATE -- OPEN 이후 VERSION  
		  AND A.YYYYMMDD		= B.BASIS_YYYYMMDD  
		  AND A.MEASURE			= 'RTF'  
		  AND A.SCM_SITE_ID		<> '-'  
		  AND A.PROJECT_CODE	<> 'N'  
		  AND A.ITEM_ID			= C.ITEM_ID  
		  AND A.DIVISION_ID		= C.DIVISION_ID  
		  --AND C.ACTIVE_FLAG   = 'Y'  
		  AND A.DIVISION_ID		= D.DIVISION_ID  
		  AND A.SCM_SITE_ID		= D.SCM_SITE_ID  
		  AND D.VALID_YN		= 'Y'  
		  AND A.DIVISION_ID		= E.DIVISION_ID  
		  AND A.SCM_SITE_ID		= E.SCM_SITE_ID  
		  AND A.PROJECT_CODE	= E.PROJECT_CODE  
		  AND A.ITEM_ID			= E.ITEM_ID  
		  AND E.OWNER			= G.USER_ID  
		  AND G.DEPT_ID         = F.DEPT_ID  
  
	   GROUP BY A.DIVISION_ID, A.SCM_SITE_ID, A.PROJECT_CODE, A.ITEM_ID, A.FCST_TYPE,B.ISO_YYYYWW, B.CALENDAR_YYYY, B.PARTIAL_WEEK_NAME  
