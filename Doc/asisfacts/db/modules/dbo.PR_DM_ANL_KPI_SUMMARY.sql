									AND X9.DIVISION_ID   = A.DIVISION_ID		AND X9.SCM_SITE_ID   = A.SCM_SITE_ID	AND X9.PROJECT_CODE  = A.PROJECT_CODE  						   
									AND X9.ITEM_ID       = A.ITEM_ID			AND X9.FCST_TYPE     = A.FCST_TYPE		AND X9.PARTIAL_WEEK_NAME = A.PARTIAL_WEEK_NAME 
	LEFT OUTER JOIN #DATE_TEMP X10 ON X10.MEASURE = @V_WHERE_MEASURE
									AND X10.DIVISION_ID   = A.DIVISION_ID			AND X10.SCM_SITE_ID   = A.SCM_SITE_ID	AND X10.PROJECT_CODE  = A.PROJECT_CODE  						   
									AND X10.ITEM_ID       = A.ITEM_ID				AND X10.FCST_TYPE     = A.FCST_TYPE		AND X10.PARTIAL_WEEK_NAME = A.PARTIAL_WEEK_NAME 
