CREATE PROCEDURE [dbo].[SCP0083_GET_DIO_CYCLE_INVENTORY]
--chaan  @p_division_id            NVARCHAR(5),
    @p_division_id          NVARCHAR(30),--chaan
	@p_plan_start_yyyymmdd	NVARCHAR(8),
	@p_plan_type			NVARCHAR(5),
	@p_seq					NVARCHAR(2),
	@p_ver					INT,
	@p_user_id				NVARCHAR(30),
	@debug_mode				NVARCHAR(1) = 'T'

AS
BEGIN
    
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;
	SET NOCOUNT ON; 

	DECLARE @mEXEC NVARCHAR(MAX);


	IF OBJECT_ID('TEMPDB..#TMP_SCP0083_A') IS NOT NULL
		DROP TABLE #TMP_SCP0083_A;

	IF OBJECT_ID('TEMPDB..#TMP_SCP0083_P') IS NOT NULL
		DROP TABLE #TMP_SCP0083_P;


	BEGIN
	
		-- CELL일 때
		-- 주기재고 외 변경 안되는 SUM 값 등 조회
		--  ROW DATA 계산
		WITH MODEL_SUM AS (
			-- 모델별 합계, 호기별 수량(실제)
			SELECT 
				DIVISION_ID, PLAN_START_YYYYMMDD, PLAN_TYPE, SEQ, VER, FROM_SITE, TRANSPORT_MODE_LINE, NICK_NAME
				, SUM(M1+M2+M3+M4+M5+M6+M7+M8+M9+M10+M11+M12) AS MODEL_SUM
			FROM SCP_ANL_DIO_CYCLE_INVENTORY A WITH(NOLOCK)
			WHERE DIVISION_ID = @p_division_id
			AND PLAN_START_YYYYMMDD = @p_plan_start_yyyymmdd
			AND PLAN_TYPE = @p_plan_type
			AND SEQ = @p_seq
			AND VER = @p_ver
			AND OPERATION_GROUP = 'A'
			GROUP BY
				DIVISION_ID, PLAN_START_YYYYMMDD, PLAN_TYPE, SEQ, VER, FROM_SITE, TRANSPORT_MODE_LINE, NICK_NAME
		),
		LINE_SUM AS (
			--  라인별 총 합계
			SELECT 
				DIVISION_ID, PLAN_START_YYYYMMDD, PLAN_TYPE, SEQ, VER, FROM_SITE, TRANSPORT_MODE_LINE
				, SUM(MODEL_SUM) AS LINE_SUM, COUNT(NICK_NAME) AS MODEL_CNT
			FROM MODEL_SUM A WITH(NOLOCK)
			GROUP BY
				DIVISION_ID, PLAN_START_YYYYMMDD, PLAN_TYPE, SEQ, VER, FROM_SITE, TRANSPORT_MODE_LINE
		),
		LINE_RATIO AS (
			-- 호기 내 비중
			SELECT 
				A.DIVISION_ID, A.PLAN_START_YYYYMMDD, A.PLAN_TYPE, A.SEQ, A.VER, A.FROM_SITE, A.TRANSPORT_MODE_LINE, A.NICK_NAME
				, ROUND((A.MODEL_SUM/B.LINE_SUM)*100, 1) AS LINE_RATIO, B.MODEL_CNT
			FROM MODEL_SUM A
			JOIN LINE_SUM B
			ON A.FROM_SITE = B.FROM_SITE
			AND A.TRANSPORT_MODE_LINE = B.TRANSPORT_MODE_LINE
		),
		NON_OPERATION AS (
			-- 비가동률
			SELECT 
				A.DIVISION_ID, A.PLAN_START_YYYYMMDD, A.PLAN_TYPE, A.SEQ, A.VER, A.FROM_SITE, A.TRANSPORT_MODE_LINE, A.NICK_NAME, B.LINE_RATIO, B.MODEL_CNT
				, (100 - B.LINE_RATIO) AS NON_OPERATION
			FROM MODEL_SUM A
			JOIN LINE_RATIO B
			ON A.NICK_NAME = B.NICK_NAME
			AND A.FROM_SITE = B.FROM_SITE
			AND A.TRANSPORT_MODE_LINE = B.TRANSPORT_MODE_LINE
		),
		GLOBAL_MODEL_SUM AS (
			-- GLOBAL 수량
			SELECT
				NICK_NAME
				, SUM(MODEL_SUM) AS GLOBAL_MODEL_SUM
			FROM MODEL_SUM
			GROUP BY NICK_NAME
		),
		GLOBAL_RATIO AS (
			-- Global비중
			SELECT 
				A.DIVISION_ID, A.PLAN_START_YYYYMMDD, A.PLAN_TYPE, A.SEQ, A.VER, A.FROM_SITE, A.TRANSPORT_MODE_LINE, A.NICK_NAME, B.GLOBAL_MODEL_SUM
				, ROUND((A.MODEL_SUM/B.GLOBAL_MODEL_SUM)*100, 1) AS GLOBAL_RATIO
			FROM MODEL_SUM A
			JOIN GLOBAL_MODEL_SUM B
			ON A.NICK_NAME = B.NICK_NAME
		),
		GLOBAL_SITE_RATIO AS (
			-- Global Site 비중
			SELECT 
				A.DIVISION_ID, A.PLAN_START_YYYYMMDD, A.PLAN_TYPE, A.SEQ, A.VER, A.FROM_SITE, A.NICK_NAME
				, SUM(A.GLOBAL_RATIO) AS GLOBAL_SITE_RATIO
			FROM GLOBAL_RATIO A
			GROUP BY A.DIVISION_ID, A.PLAN_START_YYYYMMDD, A.PLAN_TYPE, A.SEQ, A.VER, A.FROM_SITE, A.NICK_NAME
		)
		SELECT 
			RTRIM(A.DIVISION_ID) AS DIVISION_ID
			, A.PLAN_START_YYYYMMDD
			, RTRIM(A.PLAN_TYPE) AS PLAN_TYPE
			, A.SEQ
			, A.VER
			, RTRIM(A.PLANT_ID) AS PLANT_ID
			, RTRIM(A.FROM_SITE) AS FROM_SITE
			, A.FROM_SITE_DESCRIPTION
			, RTRIM(A.TRANSPORT_MODE_LINE) AS TRANSPORT_MODE_LINE
			, RTRIM(A.NICK_NAME) AS NICK_NAME
			, RTRIM(A.PACK_GROUP) AS PACK_GROUP
			, A.CELL_GROUP
			, RTRIM(A.OPERATION_GROUP) AS OPERATION_GROUP
			, (SELECT SEGMENT2
				 FROM SCM_ADM_LOOKUP_MASTER_DETAIL X WITH(NOLOCK)
			    WHERE LOOKUP_TYPE = 'OPERATION_GROUP'
				  AND VALID_YN = 'Y'
				  AND X.SEGMENT1 = RTRIM(A.OPERATION_GROUP)
			  ) 							AS OPERATION_GROUP_NAME
			, A.M1, A.M2, A.M3, A.M4, A.M5, A.M6, A.M7, A.M8, A.M9, A.M10, A.M11, A.M12
			, B.MODEL_SUM																			-- 모델별 SUM
			, C.LINE_RATIO																			-- 호기내비중
			, C.NON_OPERATION																		-- 비가동률
			, ISNULL(A.PRIVATE_FLAG, IIF(C.MODEL_CNT=1, 'Y', 'N')) AS PRIVATE_FLAG					-- 전용여부 (SEL)
			, A.CYCLE																				-- 주기
			, (30.4*A.CYCLE/2*C.NON_OPERATION)*0.01 AS CYCLE_STOCK									-- 주기 재고
			, B.MODEL_SUM AS MODEL_SUM2																-- 호기별 수량(실제)
			, D.GLOBAL_MODEL_SUM																	-- GLOBAL 수량
			, D.GLOBAL_RATIO																		-- GLOBAL 비중
			, ((30.4*A.CYCLE/2*C.NON_OPERATION)*0.01) * D.GLOBAL_RATIO *0.01 AS WEIGHT_CYCLE_STOCK	-- 주기재고(비중반영)
			, E.GLOBAL_SITE_RATIO
		
		INTO #TMP_SCP0083_A
		FROM SCP_ANL_DIO_CYCLE_INVENTORY A WITH(NOLOCK)
		
		JOIN MODEL_SUM B 
		ON A.DIVISION_ID			= B.DIVISION_ID
		AND A.PLAN_START_YYYYMMDD	= B.PLAN_START_YYYYMMDD
		AND A.PLAN_TYPE				= B.PLAN_TYPE
		AND A.SEQ					= B.SEQ
		AND A.VER					= B.VER
		AND A.FROM_SITE				= B.FROM_SITE
		AND A.TRANSPORT_MODE_LINE	= B.TRANSPORT_MODE_LINE
		AND A.NICK_NAME				= B.NICK_NAME
	
		JOIN NON_OPERATION C
		ON A.DIVISION_ID			= C.DIVISION_ID
		AND A.PLAN_START_YYYYMMDD	= C.PLAN_START_YYYYMMDD
		AND A.PLAN_TYPE				= C.PLAN_TYPE
		AND A.SEQ					= C.SEQ
		AND A.VER					= C.VER
		AND A.FROM_SITE				= C.FROM_SITE
		AND A.TRANSPORT_MODE_LINE	= C.TRANSPORT_MODE_LINE
		AND A.NICK_NAME				= C.NICK_NAME

		JOIN GLOBAL_RATIO D
		ON A.DIVISION_ID			= D.DIVISION_ID
		AND A.PLAN_START_YYYYMMDD	= D.PLAN_START_YYYYMMDD
		AND A.PLAN_TYPE				= D.PLAN_TYPE
		AND A.SEQ					= D.SEQ
		AND A.VER					= D.VER
		AND A.FROM_SITE				= D.FROM_SITE
		AND A.TRANSPORT_MODE_LINE	= D.TRANSPORT_MODE_LINE
		AND A.NICK_NAME				= D.NICK_NAME
		
		JOIN GLOBAL_SITE_RATIO E
		ON A.DIVISION_ID			= E.DIVISION_ID
		AND A.PLAN_START_YYYYMMDD	= E.PLAN_START_YYYYMMDD
		AND A.PLAN_TYPE 			= E.PLAN_TYPE
		AND A.SEQ					= E.SEQ
		AND A.VER					= E.VER
		AND A.FROM_SITE				= E.FROM_SITE
		AND A.NICK_NAME				= E.NICK_NAME
	
		ORDER BY A.FROM_SITE, A.TRANSPORT_MODE_LINE, A.NICK_NAME
		;

	END
	
	BEGIN

		-- PACK일 때, PACK_GROUP 기준으로 SUM
		-- 주기재고 외 변경 안되는 SUM 값 등 조회
		-- ROW DATA 계산
		WITH MODEL_SUM AS (
			-- 모델별 합계, 호기별 수량(실제)
			SELECT 
				DIVISION_ID, PLAN_START_YYYYMMDD, PLAN_TYPE, SEQ, VER, FROM_SITE, TRANSPORT_MODE_LINE, PACK_GROUP
				, SUM(M1+M2+M3+M4+M5+M6+M7+M8+M9+M10+M11+M12) AS MODEL_SUM
			FROM SCP_ANL_DIO_CYCLE_INVENTORY A WITH(NOLOCK)
			WHERE DIVISION_ID = @p_division_id
			AND PLAN_START_YYYYMMDD = @p_plan_start_yyyymmdd
			AND PLAN_TYPE = @p_plan_type
			AND SEQ = @p_seq
			AND VER = @p_ver
			AND OPERATION_GROUP = 'P'
			AND PACK_GROUP IS NOT NULL
			GROUP BY
				DIVISION_ID, PLAN_START_YYYYMMDD, PLAN_TYPE, SEQ, VER, FROM_SITE, TRANSPORT_MODE_LINE, PACK_GROUP
		),
		LINE_SUM AS (
			--  라인별 총 합계
			SELECT 
				DIVISION_ID, PLAN_START_YYYYMMDD, PLAN_TYPE, SEQ, VER, FROM_SITE, TRANSPORT_MODE_LINE
				, SUM(MODEL_SUM) AS LINE_SUM, COUNT(PACK_GROUP) AS MODEL_CNT
			FROM MODEL_SUM A WITH(NOLOCK)
			GROUP BY
				DIVISION_ID, PLAN_START_YYYYMMDD, PLAN_TYPE, SEQ, VER, FROM_SITE, TRANSPORT_MODE_LINE
		),
		LINE_RATIO AS (
			-- 호기 내 비중
			SELECT 
				A.DIVISION_ID, A.PLAN_START_YYYYMMDD, A.PLAN_TYPE, A.SEQ, A.VER, A.FROM_SITE, A.TRANSPORT_MODE_LINE, A.PACK_GROUP
				, ROUND((A.MODEL_SUM/B.LINE_SUM)*100, 1) AS LINE_RATIO, B.MODEL_CNT
			FROM MODEL_SUM A
			JOIN LINE_SUM B
			ON A.FROM_SITE = B.FROM_SITE
			AND A.TRANSPORT_MODE_LINE = B.TRANSPORT_MODE_LINE
		),
		NON_OPERATION AS (
			-- 비가동률
			SELECT 
				A.DIVISION_ID, A.PLAN_START_YYYYMMDD, A.PLAN_TYPE, A.SEQ, A.VER, A.FROM_SITE, A.TRANSPORT_MODE_LINE, A.PACK_GROUP, B.LINE_RATIO, B.MODEL_CNT
				, (100 - B.LINE_RATIO) AS NON_OPERATION
			FROM MODEL_SUM A
			JOIN LINE_RATIO B
			ON A.PACK_GROUP = B.PACK_GROUP
			AND A.FROM_SITE = B.FROM_SITE
			AND A.TRANSPORT_MODE_LINE = B.TRANSPORT_MODE_LINE
		),
		GLOBAL_MODEL_SUM AS (
			-- GLOBAL 수량
			SELECT
				PACK_GROUP
				, SUM(MODEL_SUM) AS GLOBAL_MODEL_SUM
			FROM MODEL_SUM
			GROUP BY PACK_GROUP
		),
		GLOBAL_RATIO AS (
			-- Global비중
			SELECT 
				A.DIVISION_ID, A.PLAN_START_YYYYMMDD, A.PLAN_TYPE, A.SEQ, A.VER, A.FROM_SITE, A.TRANSPORT_MODE_LINE, A.PACK_GROUP, B.GLOBAL_MODEL_SUM
				, ROUND((A.MODEL_SUM/B.GLOBAL_MODEL_SUM)*100, 1) AS GLOBAL_RATIO
			FROM MODEL_SUM A
			JOIN GLOBAL_MODEL_SUM B
			ON A.PACK_GROUP = B.PACK_GROUP
		),
		GLOBAL_SITE_RATIO AS (
			-- Global Site 비중
			SELECT 
				A.DIVISION_ID, A.PLAN_START_YYYYMMDD, A.PLAN_TYPE, A.SEQ, A.VER, A.FROM_SITE, A.PACK_GROUP
				, SUM(A.GLOBAL_RATIO) AS GLOBAL_SITE_RATIO
			FROM GLOBAL_RATIO A
			GROUP BY A.DIVISION_ID, A.PLAN_START_YYYYMMDD, A.PLAN_TYPE, A.SEQ, A.VER, A.FROM_SITE, A.PACK_GROUP
		)
		SELECT 
			RTRIM(A.DIVISION_ID) AS DIVISION_ID
			, A.PLAN_START_YYYYMMDD
			, RTRIM(A.PLAN_TYPE) AS PLAN_TYPE
			, A.SEQ
			, A.VER
			, RTRIM(A.PLANT_ID) AS PLANT_ID
			, RTRIM(A.FROM_SITE) AS FROM_SITE
			, A.FROM_SITE_DESCRIPTION
			, RTRIM(A.TRANSPORT_MODE_LINE) AS TRANSPORT_MODE_LINE
			, RTRIM(A.NICK_NAME) AS NICK_NAME
			, RTRIM(A.PACK_GROUP) AS PACK_GROUP
			, A.CELL_GROUP
			, RTRIM(A.OPERATION_GROUP) AS OPERATION_GROUP
			, (SELECT SEGMENT2
				 FROM SCM_ADM_LOOKUP_MASTER_DETAIL X WITH(NOLOCK)
			    WHERE LOOKUP_TYPE = 'OPERATION_GROUP'
				  AND VALID_YN = 'Y'
				  AND X.SEGMENT1 = RTRIM(A.OPERATION_GROUP)
			  ) 							AS OPERATION_GROUP_NAME
			, A.M1, A.M2, A.M3, A.M4, A.M5, A.M6, A.M7, A.M8, A.M9, A.M10, A.M11, A.M12
			, B.MODEL_SUM																			-- 모델별 SUM
			, C.LINE_RATIO																			-- 호기내비중
			, C.NON_OPERATION																		-- 비가동률
			, ISNULL(A.PRIVATE_FLAG, IIF(C.MODEL_CNT=1, 'Y', 'N')) AS PRIVATE_FLAG					-- 전용여부 (SEL)
			, A.CYCLE																				-- 주기
			, (30.4*A.CYCLE/2*C.NON_OPERATION)*0.01 AS CYCLE_STOCK									-- 주기 재고
			, B.MODEL_SUM AS MODEL_SUM2																-- 호기별 수량(실제)
			, D.GLOBAL_MODEL_SUM																	-- GLOBAL 수량
			, D.GLOBAL_RATIO																		-- GLOBAL 비중
			, ((30.4*A.CYCLE/2*C.NON_OPERATION)*0.01) * D.GLOBAL_RATIO *0.01 AS WEIGHT_CYCLE_STOCK	-- 주기재고(비중반영)
			, E.GLOBAL_SITE_RATIO
		
		INTO #TMP_SCP0083_P
		FROM SCP_ANL_DIO_CYCLE_INVENTORY A WITH(NOLOCK)
		
		JOIN MODEL_SUM B 
		ON A.DIVISION_ID			= B.DIVISION_ID
		AND A.PLAN_START_YYYYMMDD	= B.PLAN_START_YYYYMMDD
		AND A.PLAN_TYPE				= B.PLAN_TYPE
		AND A.SEQ					= B.SEQ
		AND A.VER					= B.VER
		AND A.FROM_SITE				= B.FROM_SITE
		AND A.TRANSPORT_MODE_LINE	= B.TRANSPORT_MODE_LINE
		AND A.PACK_GROUP			= B.PACK_GROUP
	
		JOIN NON_OPERATION C
		ON A.DIVISION_ID			= C.DIVISION_ID
		AND A.PLAN_START_YYYYMMDD	= C.PLAN_START_YYYYMMDD
		AND A.PLAN_TYPE				= C.PLAN_TYPE
		AND A.SEQ					= C.SEQ
		AND A.VER					= C.VER
		AND A.FROM_SITE				= C.FROM_SITE
		AND A.TRANSPORT_MODE_LINE	= C.TRANSPORT_MODE_LINE
		AND A.PACK_GROUP			= C.PACK_GROUP

		JOIN GLOBAL_RATIO D
		ON A.DIVISION_ID			= D.DIVISION_ID
		AND A.PLAN_START_YYYYMMDD	= D.PLAN_START_YYYYMMDD
		AND A.PLAN_TYPE				= D.PLAN_TYPE
		AND A.SEQ					= D.SEQ
		AND A.VER					= D.VER
		AND A.FROM_SITE				= D.FROM_SITE
		AND A.TRANSPORT_MODE_LINE	= D.TRANSPORT_MODE_LINE
		AND A.PACK_GROUP			= D.PACK_GROUP
		
		JOIN GLOBAL_SITE_RATIO E
		ON A.DIVISION_ID			= E.DIVISION_ID
		AND A.PLAN_START_YYYYMMDD	= E.PLAN_START_YYYYMMDD
		AND A.PLAN_TYPE 			= E.PLAN_TYPE
		AND A.SEQ					= E.SEQ
		AND A.VER					= E.VER
		AND A.FROM_SITE				= E.FROM_SITE
		AND A.PACK_GROUP			= E.PACK_GROUP

		ORDER BY A.FROM_SITE, A.TRANSPORT_MODE_LINE, A.PACK_GROUP
		;


	END


	SET @MEXEC = '';
	SET @MEXEC = @MEXEC+'SELECT *' + CHAR(10);
	SET @MEXEC = @MEXEC+'FROM (' + CHAR(10);

		BEGIN
		SET @MEXEC = @MEXEC+'SELECT * FROM #TMP_SCP0083_A ' + CHAR(10);
		SET @MEXEC = @MEXEC+'UNION ALL ' + CHAR(10);
		SET @MEXEC = @MEXEC+'SELECT * FROM #TMP_SCP0083_P ' + CHAR(10);
		END

	SET @MEXEC = @MEXEC+') T' + CHAR(10);
	SET @MEXEC = @MEXEC+'ORDER BY FROM_SITE, TRANSPORT_MODE_LINE, NICK_NAME, PACK_GROUP, OPERATION_GROUP' + CHAR(10);

	EXEC(@MEXEC);

	-----------------------------------------------------------	
	-- DEBUG
	-----------------------------------------------------------
	IF( @debug_mode ='T')
		BEGIN				
			DECLARE @POS INT =1;
			DECLARE @LEN INT =LEN(@MEXEC);
			WHILE @POS <= @LEN
				BEGIN
					PRINT SUBSTRING(@MEXEC,@POS,4000);
					SET @POS = @POS+4000;
				END;
		END;



	-- RETURN TABLE[1]
	-- 몇 개월 선택과 개월 칼럼
	-- PLAN DATE 차월 부터 집계 됨
	SELECT TOP 1 
		  CONVERT(CHAR(7), DATEADD(MONTH, 1, @p_plan_start_yyyymmdd), 23) AS M1
		, CONVERT(CHAR(7), DATEADD(MONTH, 2, @p_plan_start_yyyymmdd), 23) AS M2
		, CONVERT(CHAR(7), DATEADD(MONTH, 3, @p_plan_start_yyyymmdd), 23) AS M3
		, CONVERT(CHAR(7), DATEADD(MONTH, 4, @p_plan_start_yyyymmdd), 23) AS M4
		, CONVERT(CHAR(7), DATEADD(MONTH, 5, @p_plan_start_yyyymmdd), 23) AS M5
		, CONVERT(CHAR(7), DATEADD(MONTH, 6, @p_plan_start_yyyymmdd), 23) AS M6
		, CONVERT(CHAR(7), DATEADD(MONTH, 7, @p_plan_start_yyyymmdd), 23) AS M7
		, CONVERT(CHAR(7), DATEADD(MONTH, 8, @p_plan_start_yyyymmdd), 23) AS M8
		, CONVERT(CHAR(7), DATEADD(MONTH, 9, @p_plan_start_yyyymmdd), 23) AS M9
		, CONVERT(CHAR(7), DATEADD(MONTH, 10, @p_plan_start_yyyymmdd), 23) AS M10
		, CONVERT(CHAR(7), DATEADD(MONTH, 11, @p_plan_start_yyyymmdd), 23) AS M11
		, CONVERT(CHAR(7), DATEADD(MONTH, 12, @p_plan_start_yyyymmdd), 23) AS M12
		, DATA_RANGE
	FROM SCP_ANL_DIO_CYCLE_INVENTORY A WITH(NOLOCK)
	WHERE DIVISION_ID = @p_division_id
	AND PLAN_START_YYYYMMDD = @p_plan_start_yyyymmdd
	AND PLAN_TYPE = @p_plan_type
	AND SEQ = @p_seq
	AND VER = @p_ver
	;


	------------------------------------------------------------
	--	임시테이블 삭제
	------------------------------------------------------------
	IF OBJECT_ID('TEMPDB..#TMP_SCP0083_A') IS NOT NULL
		DROP TABLE #TMP_SCP0083_A
		;

	IF OBJECT_ID('TEMPDB..#TMP_SCP0083_P') IS NOT NULL
		DROP TABLE #TMP_SCP0083_P
		;


END
