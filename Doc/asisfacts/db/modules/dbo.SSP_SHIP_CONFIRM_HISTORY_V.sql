


CREATE VIEW [dbo].[SSP_SHIP_CONFIRM_HISTORY_V] AS
/********************************************************************************************************************************
* VIEW NAME     : [SSP_SHIP_CONFIRM_HISTORY_V]
* DESCRIPTION   : 출하확정 변경 히스토리 
*          
* PROGRAM HISTORY
*--------------------------------------------------------------
*  DATE      IN CHARGE           DESCRIPTION
*--------------------------------------------------------------
* 2019.06.14   juhlee     Initial Release 
********************************************************************************************************************************/
SELECT C.CONFIRM_ID 
,      ROW_NUMBER() OVER(PARTITION BY H.CONFIRM_ID ORDER BY H.HISTORY_SEQ) AS SEQ
,      CASE WHEN H.HISTORY_SEQ =  (SELECT MAX(T.HISTORY_SEQ) FROM SSP_ANL_SHIP_CONFIRM_H T WITH(NOLOCK) WHERE T.CONFIRM_ID = C.CONFIRM_ID ) THEN 'C' ELSE 'H' END AS HISTORY 
,      C.DIVISION_ID 
,      C.FROM_SITE
,      C.ITEM_ID 
,      DBO.FN_GET_ITEM_NICKNAME((CASE WHEN C.DIVISION_ID = 'EE' THEN C.ORIGIN_FROM_DIVISION_ID ELSE C.DIVISION_ID END), C.ITEM_ID ) AS NICK_NAME
,      C.TO_SITE
,      C.PROJECT_CODE 
,      C.FCST_TYPE 
,      ''   AS END_CUSTOMER 

-------------------------------------------------------------------
,      H.YYYYMMDD
,      H.QTY 
,      H.TRANSPORT_MODE 
,      H.INCOTERMS 
,      H.CUSTOMER_LT
--------------------------------------------------------------------
,      D.YYYYMMDD		AS BEFORE_YYYYMMDD
,      D.QTY			AS BEFORE_QTY
,      D.TRANSPORT_MODE AS BEFORE_TRANSPORT_MODE
,      D.INCOTERMS      AS BEFORE_INCOTERMS
-----------------------------------------------------------------------
--,      ISNULL(L2.SEGMENT2 ,'' )			AS CHANGE_TYPE 

,      CASE WHEN H.CHANGE_REQ_NO IS NULL THEN 'New'
            ELSE 
			     CASE WHEN D.NEW_YN = 'Y' THEN 'New' ELSE 'Change' END  
			END										AS TYPE 

,      CASE WHEN ISNULL(M.CHANGE_TYPE,'System Create') = 'A' THEN 'Adjustment' 
            WHEN ISNULL(M.CHANGE_TYPE,'System Create') IN( 'N','C') THEN 'Change Request' 
	   ELSE 'System Create' END         AS CHANGE_TYPE 
,      M.CHANGE_REASON_CODE
,      L.SEGMENT2         AS CHANGE_REASON_CODE_DESC_K
,      L.SEGMENT3         AS CHANGE_REASON_CODE_DESC_E
--,      CASE WHEN M.CHANGE_REASON_CODE = 'C00' THEN '' ELSE L.SEGMENT2 END           AS CHANGE_REASON_CODE_DESC_K
--,      CASE WHEN M.CHANGE_REASON_CODE = 'C00' THEN 'Change without application' ELSE L.SEGMENT3 END         AS CHANGE_REASON_CODE_DESC_E
,      M.REQUEST_TITLE 
,      M.REQUEST_USER 
,      U.USERNAME    AS REQUEST_USER_NAME
,      U.USERNAME_E  AS REQUEST_USER_NAME_EN
,      M.REQUEST_DEPT  
,      DT.DEPT_NAME_KO   AS REQUEST_DEPT_NAME
,      DT.DEPT_NAME_EN   AS REQUEST_DEPT_NAME_EN
,      M.REQUEST_TIME
,      M.APPROVAL_USER
,      U2.USERNAME    AS APPROVAL_USER_NAME
,      U2.USERNAME_E  AS APPROVAL_USER_NAME_EN
,      M.APPROVAL_DEPT
,      DT2.DEPT_NAME_KO  AS APPROVAL_DEPT_NAME
,      DT2.DEPT_NAME_EN  AS APPROVAL_DEPT_NAME_EN
,      M.APPROVAL_TIME


,      ABS(ISNULL(D.QTY,0) - ISNULL(D.NEW_QTY,0) )   AS VARIABLE_QTY

,      H.CHANGE_REQ_NO 
,      M.CHANGE_REASON_DETAIL 
,      ISNULL(M.APPROVAL_TIME, C.CREATION_DATE ) AS UPDATED_DATE

-------------------------------------------------
,      H.REMARKS    AS REMARKS
,      H.REMARKS2   AS BULIDING
,      H.REMARKS3   AS CUSTORMER_REQUIREMENTS 
-------------------------------------------------
,      CASE WHEN H.HISTORY_SEQ =  (SELECT MAX(T.HISTORY_SEQ) FROM SSP_ANL_SHIP_CONFIRM_H T WITH(NOLOCK) WHERE T.CONFIRM_ID = C.CONFIRM_ID ) THEN C.ERP_SO_NO ELSE NULL END  AS ERP_SO_NO  

,      C.ERP_STATUS
--,      C.ERP_SO_NO  
,     S.USER_ID   AS MODEL_PIC 

,     DBO.FN_GET_SSP_MKT_OWNER_NAME (SI.OWNER, ',', 'KO') AS MTK_OWNER_KR  
,     DBO.FN_GET_SSP_MKT_OWNER_NAME (SI.OWNER, ',', 'EN') AS MTK_OWNER_EN 


,     DBO.FN_GET_SITE_CUSTOMER_INFO((CASE WHEN C.DIVISION_ID = 'EE' THEN C.ORIGIN_FROM_DIVISION_ID ELSE C.DIVISION_ID END), C.TO_SITE, 'SOLDTO_DESCRIPTION' ) AS SOLDTO_DESCRIPTION
,     DBO.FN_GET_SITE_CUSTOMER_INFO((CASE WHEN C.DIVISION_ID = 'EE' THEN C.ORIGIN_FROM_DIVISION_ID ELSE C.DIVISION_ID END), C.TO_SITE, 'SHIPTO_DESCRIPTION' ) AS SHIPTO_DESCRIPTION

,      CASE WHEN ISNULL(D.YYYYMMDD,'')       <> ISNULL(D.NEW_YYYYMMDD,'')       THEN 'Y' ELSE 'N' END  AS DATE_CHANGE_YN 
,      CASE WHEN ISNULL(D.QTY,0)             <> ISNULL(D.NEW_QTY,0)             THEN 'Y' ELSE 'N' END  AS QTY_CHANGE_YN 
,      CASE WHEN ISNULL(D.TRANSPORT_MODE,'') <> ISNULL(D.NEW_TRANSPORT_MODE,'') THEN 'Y' ELSE 'N' END  AS TRANSPORT_CHANGE_YN 
,      CASE WHEN  ( D.YYYYMMDD = D.NEW_YYYYMMDD  AND D.QTY = D.NEW_QTY  AND  D.TRANSPORT_MODE = D.NEW_TRANSPORT_MODE ) THEN 'Y' ELSE 'N' END AS ONLY_REMARK_CHANGE_YN


,      M.CHANGE_REQ_STATUS
,      [dbo].[FN_GET_LOOKUP_CODE_DESC]( 'CHANGE_REQ_STATUS', M.CHANGE_REQ_STATUS)  AS CHANGE_REQ_STATUS_DESC


,      C.REQUESTOR   AS SHIP_REQ_REQUESTOR 
,      C.ATTRIBUTE10 AS REQ_DET_ID
FROM SSP_ANL_SHIP_CONFIRM  C WITH(NOLOCK)
           JOIN SSP_ANL_SHIP_CONFIRM_H  H         WITH(NOLOCK) ON H.CONFIRM_ID = C.CONFIRM_ID  
LEFT OUTER JOIN SSP_ANL_SHIP_CONFIRM_CHG_REQ M    WITH(NOLOCK) ON M.CHANGE_REQ_NO = H.CHANGE_REQ_NO AND M.CHANGE_REQ_STATUS ='A' AND M.VALID_YN = 'Y'
LEFT OUTER JOIN SSP_ANL_SHIP_CONFIRM_CHG_REQ_DE D WITH(NOLOCK) ON D.CHANGE_REQ_NO = M.CHANGE_REQ_NO AND  C.CONFIRM_ID = D.CONFIRM_ID AND D.VALID_YN = 'Y'
                                                             --     AND  ( D.YYYYMMDD <> D.NEW_YYYYMMDD  OR D.QTY <> D.NEW_QTY  OR D.TRANSPORT_MODE <> D.NEW_TRANSPORT_MODE ) 
LEFT OUTER JOIN SCM_ADM_LOOKUP_MASTER_DETAIL L    WITH(NOLOCK) ON M.CHANGE_REASON_CODE = L.SEGMENT1 AND L.LOOKUP_TYPE = 'CHANGE_REASON_CODE' 
LEFT OUTER JOIN SCM_ADM_LOOKUP_MASTER_DETAIL L2   WITH(NOLOCK) ON M.CHANGE_TYPE = L2.SEGMENT1 AND L2.LOOKUP_TYPE = 'CHANGE_REQ_TYPE' 

LEFT OUTER JOIN TB_FX_USER U ON M.REQUEST_USER = U.USERID AND U.USEYN = 'Y'
LEFT OUTER JOIN TB_FX_USER U2 ON M.APPROVAL_USER = U2.USERID AND U2.USEYN = 'Y'

LEFT OUTER JOIN SCM_MST_SSO_DEPT_INFO DT ON M.REQUEST_DEPT = DT.DEPT_ID
LEFT OUTER JOIN SCM_MST_SSO_DEPT_INFO DT2 ON M.APPROVAL_DEPT = DT2.DEPT_ID

LEFT OUTER JOIN SSP_MST_MODEL_USER S WITH(NOLOCK) ON S.DIVISION_ID = C.DIVISION_ID AND S.FROM_SITE = C.FROM_SITE AND S.ITEM_ID = C.ITEM_ID AND S.VALID_YN ='Y'

LEFT OUTER JOIN SCM_MST_SITE_ITEM SI WITH(NOLOCK) ON SI.DIVISION_ID  = (CASE WHEN C.DIVISION_ID ='EE' THEN C.ORIGIN_TO_DIVISION_ID ELSE C.DIVISION_ID END) 
												AND SI.SCM_SITE_ID  = C.TO_SITE  
												AND SI.ITEM_ID  = C.ITEM_ID              
												AND SI.PROJECT_CODE  = C.PROJECT_CODE



--LEFT OUTER JOIN SCM_MST_PROJECT P WITH(NOLOCK) ON P.DIVISION_ID = (CASE WHEN C.DIVISION_ID = 'EE' THEN C.ORIGIN_FROM_DIVISION_ID ELSE C.DIVISION_ID END) 
--                                               AND P.PROJECT_CODE = C.PROJECT_CODE    

              


WHERE   C.CHANGE_TYPE = 'C'

AND    C.CONFIRM_ID >= 'C20190419518861'

--AND    C.DIVISION_ID = '40'

--AND  ISNULL(D.NEW_INCOTERMS,'') <> ISNULL(D.INCOTERMS,'')







