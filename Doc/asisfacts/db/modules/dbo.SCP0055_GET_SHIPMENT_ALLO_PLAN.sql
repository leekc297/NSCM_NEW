CREATE PROCEDURE [dbo].[SCP0055_GET_SHIPMENT_ALLO_PLAN]
--CREATE PROCEDURE [dbo].[SCP0055_GET_SHIPMENT_ALLO_PLAN]
	@P_FROM_YYYYMMDD		NVARCHAR(8),
	@P_TO_YYYYMMDD			NVARCHAR(8),
	@P_DIVISION_ID			NVARCHAR(30),
	@P_BIZ_TYPE				NVARCHAR(30),
	@P_ITEM_ID				NVARCHAR(MAX),
	@P_CELL_TYPE_GR         NVARCHAR(3),
	@P_PLAN_START_YYYYMMDD  NVARCHAR(8),
	@P_FROMSITE				NVARCHAR(MAX),
	@P_TEAM_ID              NVARCHAR(MAX),
	@P_NICKNAME             NVARCHAR(MAX),
	@P_PROGRAM_ID			NVARCHAR(10) = 'SCP0055' ,
	@P_SHEET_NAME			NVARCHAR(30) = 'SHIPMENT(ALLO) REPORT' ,
	@P_USER_ID				NVARCHAR(30),
	@P_FCST_YN				NVARCHAR(2),
	@DEBUG_MODE             NVARCHAR(1) ='F'
AS
BEGIN
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;
	SET NOCOUNT ON; 

	--DECLARE @P_FROM_YYYYMMDD		NVARCHAR(8)		= N'20231001';
	--DECLARE @P_TO_YYYYMMDD			NVARCHAR(8)		= N'20240430';
	--DECLARE @P_DIVISION_ID			NVARCHAR(30)	= N'40';
	--DECLARE @P_BIZ_TYPE				NVARCHAR(30)	= N'A';
	--DECLARE @P_ITEM_ID				NVARCHAR(MAX)	= N'';
	--DECLARE @P_CELL_TYPE_GR         NVARCHAR(3)		= N'C';
	--DECLARE @P_PLAN_START_YYYYMMDD  NVARCHAR(8)		= N'20240101';
	--DECLARE @P_FROMSITE				NVARCHAR(MAX)	= N'';
	--DECLARE @P_TEAM_ID              NVARCHAR(MAX)	= N'';
	--DECLARE @P_NICKNAME             NVARCHAR(MAX)	= N'';
	--DECLARE @P_PROGRAM_ID			NVARCHAR(10)	= N'SCP0055';
	--DECLARE @P_SHEET_NAME			NVARCHAR(30)	= N'Shipment(Allo) Report';
	--DECLARE @P_USER_ID				NVARCHAR(30)	= N'iamarock';
	--DECLARE @P_FCST_YN				NVARCHAR(2)		= N'N';
	--DECLARE @DEBUG_MODE             NVARCHAR(1)		= N'F';


    DECLARE @V_FROM_YYYYMMDD     AS NVARCHAR(8);
	DECLARE @V_TO_YYYYMMDD       AS NVARCHAR(8);
	DECLARE @V_FROM_RESULT       AS NVARCHAR(8);
	DECLARE @V_TO_RESULT         AS NVARCHAR(8);

	DECLARE @V_PLAN_TYPE         AS NVARCHAR(8);
	DECLARE @V_SEQ               AS NVARCHAR(8);

	SET @V_FROM_YYYYMMDD = '';
	SET @V_TO_YYYYMMDD   = '';
	SET @V_FROM_RESULT   = '';
	SET @V_TO_RESULT     = '';

	SELECT @V_FROM_YYYYMMDD = C.BASIS_START_DATE
	FROM   [DBO].[SCM_SYS_CALENDAR_M]      C
	WHERE  1 = 1
	AND    C.BASIS_YYYYMMDD = @P_PLAN_START_YYYYMMDD

	SELECT @V_FROM_RESULT = C.BASIS_START_DATE
	FROM   [DBO].[SCM_SYS_CALENDAR_M]      C
	WHERE  1 = 1
	AND    C.BASIS_YYYYMMDD = @P_FROM_YYYYMMDD;

	SELECT @V_TO_RESULT = C.BASIS_START_DATE
	FROM   [DBO].[SCM_SYS_CALENDAR_M]      C
	WHERE  1 = 1
	AND    C.BASIS_YYYYMMDD = @P_TO_YYYYMMDD;

	IF @V_FROM_YYYYMMDD > @V_FROM_RESULT
	  BEGIN -- 실적 보여줌
	  SET @V_TO_YYYYMMDD   = @P_TO_YYYYMMDD;
	  SET @V_TO_RESULT     = @V_FROM_YYYYMMDD;
	  END;
	ELSE IF @V_FROM_YYYYMMDD <= @V_FROM_RESULT
	  BEGIN -- 실적 없음
	  SET @V_TO_YYYYMMDD   = @P_TO_YYYYMMDD;
	  SET @V_FROM_RESULT = CONVERT(CHAR(8), DATEADD(MM, 6, CONVERT(DATETIME,@P_PLAN_START_YYYYMMDD)), 112);
	  SET @V_TO_RESULT = CONVERT(CHAR(8), DATEADD(MM, -6, CONVERT(DATETIME,@P_PLAN_START_YYYYMMDD)), 112)
	  END;
	ELSE IF @V_FROM_YYYYMMDD > @V_TO_RESULT
	  BEGIN
	  SET @V_FROM_YYYYMMDD = CONVERT(CHAR(8), DATEADD(MM, -6,  CONVERT(DATETIME,@P_PLAN_START_YYYYMMDD)), 112);
	  SET @V_TO_YYYYMMDD = CONVERT(CHAR(8), DATEADD(MM, -6,  CONVERT(DATETIME,@P_PLAN_START_YYYYMMDD)), 112);
	  SET @V_FROM_RESULT = @P_FROM_YYYYMMDD;
	  SET @V_TO_RESULT = @P_TO_YYYYMMDD;
	  END;
	ELSE IF @V_FROM_YYYYMMDD = @V_TO_RESULT
	  BEGIN
	  SET @V_TO_YYYYMMDD = @V_FROM_YYYYMMDD
	  SET @V_FROM_RESULT = @P_FROM_YYYYMMDD;
	  SET @V_TO_RESULT = @P_TO_YYYYMMDD;
	END;

    DECLARE @ARR_PROJECT_CODE VARCHAR(MAX) , @ARR_ITEM_ID VARCHAR(MAX) , @ARR_ELECTRODE_TYPE VARCHAR(MAX) , @ARR_FROMSITE VARCHAR(MAX), @ARR_TOSITE VARCHAR(MAX);
	SELECT @ARR_ITEM_ID     = ISNULL(@ARR_ITEM_ID  + ',''' + TOKEN +'''', ''''+TOKEN+'''') FROM DBO.STRING_SPLIT(@P_ITEM_ID ,',');
	SELECT @ARR_FROMSITE    = ISNULL(@ARR_FROMSITE + ',''' + TOKEN +'''', ''''+TOKEN+'''') FROM DBO.STRING_SPLIT(@P_FROMSITE,',');
	
	
	/*
	-- 최신 PLAN TYPE, SEQ 조회
	##################################################################################
	-- 20220413 요청사항
	PR까지만 진행된 경우엔 PR의 amend
	MA까지 진행된경우엔 MA의 amend값
	FN이 진행되어도 MA의 amend값
	*/
	WITH TEMP_PLAN AS (
    SELECT PLAN_TYPE AS CODE
         , PLAN_TYPE AS NAME
         , MAX(PLAN_SEQ) AS PLAN_SEQ
         , MAX(PLAN_TYPE_ORDER) AS  PLAN_TYPE_ORDER
      FROM SCP_PLAN_VERSION_V WITH(NOLOCK)
     WHERE 1=1
       AND DIVISION_ID = @P_DIVISION_ID
       AND PLAN_START_YYYYMMDD = @P_PLAN_START_YYYYMMDD
	   AND PLAN_TYPE IN ('PR','MA')
    GROUP BY PLAN_TYPE
    --ORDER BY PLAN_TYPE_ORDER
    ) 
    SELECT @V_PLAN_TYPE = CODE,
	       @V_SEQ = PLAN_SEQ
	  FROM TEMP_PLAN
     WHERE PLAN_TYPE_ORDER = (SELECT MAX(PLAN_TYPE_ORDER) FROM TEMP_PLAN);

	/*
	##################################################################################
	-- 20220425 요청사항
	P_FCST_YN = Y => FN
	P_FCST_YN = N => PR, MA
	*/
	IF @P_FCST_YN ='Y'
	BEGIN
	WITH TEMP_PLAN AS (
    SELECT PLAN_TYPE AS CODE
         , PLAN_TYPE AS NAME
         , MAX(PLAN_SEQ) AS PLAN_SEQ
         , MAX(PLAN_TYPE_ORDER) AS  PLAN_TYPE_ORDER
      FROM SCP_PLAN_VERSION_V WITH(NOLOCK)
     WHERE 1=1
       AND DIVISION_ID = @P_DIVISION_ID
       AND PLAN_START_YYYYMMDD = @P_PLAN_START_YYYYMMDD
	   AND PLAN_TYPE IN ('PR','MA','FN')
    GROUP BY PLAN_TYPE
    --ORDER BY PLAN_TYPE_ORDER
    ) 
    SELECT @V_PLAN_TYPE = CODE,
	       @V_SEQ = PLAN_SEQ
	  FROM TEMP_PLAN
     WHERE PLAN_TYPE_ORDER = (SELECT MAX(PLAN_TYPE_ORDER) FROM TEMP_PLAN);
	END




	IF @DEBUG_MODE ='T'
	BEGIN
		PRINT '----------------------------------';
		PRINT '@P_PLAN_START_YYYYMMDD =' +@P_PLAN_START_YYYYMMDD;
		PRINT '@V_FROM_YYYYMMDD =' +@V_FROM_YYYYMMDD;
		PRINT '@V_TO_YYYYMMDD =' +@V_TO_YYYYMMDD;
		PRINT '@V_FROM_RESULT =' +@V_FROM_RESULT;
		PRINT '@V_TO_RESULT =' +@V_TO_RESULT	;
		PRINT '@V_PLAN_TYPE =' +@V_PLAN_TYPE;
		PRINT '@V_SEQ =' +@V_SEQ;
		PRINT '----------------------------------';
	END;

	IF OBJECT_ID('tempdb..#TMP_SCP0055_PLAN_FG') IS NOT NULL
		DROP TABLE #TMP_SCP0055_PLAN_FG;

	-- 계획 (Shipment Plan FG)

	SELECT F.DIVISION_ID, 
		   F.FROM_SITE AS SITE_ID,
		   ISNULL((SELECT TOP 1 SITE_DESCRIPTION FROM SCM_MST_SITE WHERE 1=1 AND SCM_SITE_ID = F.FROM_SITE),'-') AS SITE_NAME,
		   (SELECT TOP 1 ISNULL(NULLIF(SCP_EXTRA_SPEC, ''),'-') FROM DBO.SCM_MST_ITEM_SN X WITH(NOLOCK) WHERE 1=1 AND X.DIVISION_ID = F.DIVISION_ID AND X.ITEM_ID = F.ITEM_ID) AS EXTRA_SPEC,
		   (SELECT TOP 1 ISNULL(NULLIF(NICK_NAME, ''), '-') FROM DBO.SCM_MST_ITEM_SN X WITH(NOLOCK) WHERE 1=1 AND X.ITEM_ID = F.ITEM_ID) AS NICK_NAME,
	       --F.ITEM_ID, 
		   SUI.DEPT_ID,
		   SDI.DEPT_NAME_KO AS DEPT_NAME,
		   F.YYYYMMDD,
		   SUM(F.QTY) AS QTY,
		   'FG' AS PLAN_FROM
    INTO #TMP_SCP0055_PLAN_FG
	FROM SCP_ANL_SHIPMENT_PLAN_FG F WITH (NOLOCK)
         INNER JOIN SCP_MST_FINAL_ITEM MFI WITH (NOLOCK) ON F.DIVISION_ID = MFI.DIVISION_ID AND F.BIZ_TYPE = MFI.OPERATION_GROUP_ID AND F.ITEM_ID = MFI.ITEM_ID
         INNER JOIN SCM_MST_SITE_ITEM MSI WITH (NOLOCK) ON F.DIVISION_ID = MSI.DIVISION_ID
   	                                                  AND F.TO_SITE = MSI.SCM_SITE_ID
   			   										  AND F.PROJECT_CODE = MSI.PROJECT_CODE
   													  AND F.ITEM_ID = MSI.ITEM_ID
   												      AND MSI.VALID_YN = 'Y'
         LEFT OUTER JOIN SCM_MST_SSO_USER_INFO SUI WITH (NOLOCK) ON SUBSTRING( MSI.OWNER, 0, CASE WHEN CHARINDEX(',', MSI.OWNER) = 0 THEN LEN(MSI.OWNER)+1 
   	                                                                                        ELSE CHARINDEX(',', MSI.OWNER) END ) = SUI.USER_ID
         LEFT OUTER JOIN SCM_MST_SSO_DEPT_INFO SDI WITH (NOLOCK) ON SUI.DEPT_ID = SDI.DEPT_ID
	WHERE  F.YYYYMMDD				>= @V_FROM_YYYYMMDD
	AND    F.YYYYMMDD				<= @V_TO_YYYYMMDD
	AND    F.DIVISION_ID			=  @P_DIVISION_ID
	AND    F.BIZ_TYPE				=  @P_BIZ_TYPE
	AND    ((@P_FROMSITE IS NULL OR @P_FROMSITE ='') OR F.FROM_SITE IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_FROMSITE, ',')))
	AND    ((@P_TEAM_ID IS NULL OR @P_TEAM_ID ='') OR SUI.DEPT_ID IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_TEAM_ID, ',')))
	AND    ((@P_ITEM_ID IS NULL OR @P_ITEM_ID ='') OR F.ITEM_ID IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_ITEM_ID, ',')))
    AND    ((@P_CELL_TYPE_GR IS NULL OR @P_CELL_TYPE_GR = '') OR MFI.CELL_TYPE_GROUP_CODE IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_CELL_TYPE_GR, ',')))
	AND    F.MEASURE                =  'SHIP_PLAN_AMEND'
	AND    F.PLAN_START_YYYYMMDD	=  @P_PLAN_START_YYYYMMDD
	AND    ((@DEBUG_MODE = 'T') OR (F.PLAN_TYPE = @V_PLAN_TYPE))
	AND    ((@DEBUG_MODE = 'T') OR (F.SEQ = @V_SEQ))
	AND    F.QTY > 0
	GROUP BY F.DIVISION_ID,
	         F.PLAN_START_YYYYMMDD,
		     F.PLAN_TYPE,
		     F.SEQ,
		     F.BIZ_TYPE,
		     F.FROM_SITE,
		     F.ITEM_ID,
			 SUI.DEPT_ID,
			 SDI.DEPT_NAME_KO,
		     F.YYYYMMDD
	ORDER BY F.DIVISION_ID,
	         F.PLAN_START_YYYYMMDD,
		     F.PLAN_TYPE,
		     F.SEQ,
		     F.BIZ_TYPE,
			 F.FROM_SITE,
		     F.ITEM_ID,
			 SUI.DEPT_ID,
			 SDI.DEPT_NAME_KO,
		     F.YYYYMMDD

	-- 계획 (Shipment Plan Semi)

	IF OBJECT_ID('tempdb..#TMP_SCP0055_PLAN_SEMI') IS NOT NULL
		DROP TABLE #TMP_SCP0055_PLAN_SEMI;

	SELECT F.DIVISION_ID, 
		   F.FROM_SITE AS SITE_ID,
		   ISNULL((SELECT TOP 1 SITE_DESCRIPTION FROM SCM_MST_SITE WHERE 1=1 AND SCM_SITE_ID = F.FROM_SITE),'-') AS SITE_NAME,
		   (SELECT TOP 1 ISNULL(NULLIF(SCP_EXTRA_SPEC, ''),'-') FROM DBO.SCM_MST_ITEM_SN X WITH(NOLOCK) WHERE 1=1 AND X.DIVISION_ID = F.DIVISION_ID AND X.ITEM_ID = F.ITEM_ID) AS EXTRA_SPEC,
		   (SELECT TOP 1 ISNULL(NULLIF(NICK_NAME, ''), '-') FROM DBO.SCM_MST_ITEM_SN X WITH(NOLOCK) WHERE 1=1 AND X.ITEM_ID = F.ITEM_ID) AS NICK_NAME,
	       --F.ITEM_ID, 
		   LMD.ATTRIBUTE1 AS DEPT_ID,
		   LMD.ATTRIBUTE2 AS DEPT_NAME,
		   F.YYYYMMDD,
		   SUM(F.QTY) AS QTY,
		   'SEMI' AS PLAN_FROM
	INTO #TMP_SCP0055_PLAN_SEMI
	FROM SCP_ANL_SHIPMENT_PLAN_SEMI F WITH (NOLOCK)
         INNER JOIN SCP_MST_FINAL_ITEM MFI WITH (NOLOCK) ON F.DIVISION_ID = MFI.DIVISION_ID AND F.OPERATION_GROUP = MFI.OPERATION_GROUP_ID AND F.ITEM_ID = MFI.ITEM_ID
		 LEFT OUTER JOIN SCM_ADM_LOOKUP_MASTER_DETAIL LMD WITH (NOLOCK) ON F.FROM_SITE = LMD.SEGMENT1 AND F.TO_SITE = LMD.SEGMENT2 AND F.ITEM_ID = LMD.SEGMENT3 AND LMD.LOOKUP_TYPE = 'SHIPMENT_REPORT_LOOKUP'
	WHERE  F.YYYYMMDD				>= @V_FROM_YYYYMMDD
	AND    F.YYYYMMDD				<= @V_TO_YYYYMMDD
	AND    F.DIVISION_ID			=  @P_DIVISION_ID
	AND    F.OPERATION_GROUP		=  @P_BIZ_TYPE
	AND    ((@P_FROMSITE IS NULL OR @P_FROMSITE ='') OR F.FROM_SITE IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_FROMSITE, ',')))
	AND    ((@P_TEAM_ID IS NULL OR @P_TEAM_ID ='') OR LMD.ATTRIBUTE1 IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_TEAM_ID, ',')))
	AND    ((@P_ITEM_ID IS NULL OR @P_ITEM_ID ='') OR F.ITEM_ID IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_ITEM_ID, ',')))
    AND    ((@P_CELL_TYPE_GR IS NULL OR @P_CELL_TYPE_GR = '') OR MFI.CELL_TYPE_GROUP_CODE IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_CELL_TYPE_GR, ',')))
	AND    F.MEASURE                =  'SHIP_PLAN_AMEND'
	AND    F.PLAN_START_YYYYMMDD	=  @P_PLAN_START_YYYYMMDD
	AND    ((@DEBUG_MODE = 'T') OR (F.PLAN_TYPE = @V_PLAN_TYPE))
	AND    ((@DEBUG_MODE = 'T') OR (F.SEQ = @V_SEQ))
	AND    F.QTY > 0
	GROUP BY F.DIVISION_ID,
	         F.PLAN_START_YYYYMMDD,
		     F.PLAN_TYPE,
		     F.SEQ,
		     F.OPERATION_GROUP,
		     F.FROM_SITE,
		     F.ITEM_ID,
			 LMD.ATTRIBUTE1,
			 LMD.ATTRIBUTE2,
		     F.YYYYMMDD
	ORDER BY F.DIVISION_ID,
	         F.PLAN_START_YYYYMMDD,
		     F.PLAN_TYPE,
		     F.SEQ,
		     F.OPERATION_GROUP,
			 F.FROM_SITE,
		     F.ITEM_ID,
			 LMD.ATTRIBUTE1,
			 LMD.ATTRIBUTE2,
		     F.YYYYMMDD;

    IF OBJECT_ID('tempdb..#TMP_SCP0055_PLAN') IS NOT NULL
		DROP TABLE #TMP_SCP0055_PLAN;

	SELECT * INTO #TMP_SCP0055_PLAN FROM (
        SELECT * FROM #TMP_SCP0055_PLAN_FG
	    UNION ALL
	    SELECT * FROM #TMP_SCP0055_PLAN_SEMI
	) AS TEMP;

	IF OBJECT_ID('tempdb..#TMP_SCP0055_PLAN_TOTAL') IS NOT NULL
		DROP TABLE #TMP_SCP0055_PLAN_TOTAL;

	SELECT F.DIVISION_ID, 
		   F.SITE_ID,
		   F.SITE_NAME,
		   F.EXTRA_SPEC,
		   F.NICK_NAME,
		   F.DEPT_ID,
		   F.DEPT_NAME,
		   F.YYYYMMDD,
		   SUM(F.QTY) AS QTY,
		   'PLAN_TOTAL' AS PLAN_FROM
	INTO #TMP_SCP0055_PLAN_TOTAL
	FROM #TMP_SCP0055_PLAN F WITH (NOLOCK)
	WHERE ((@P_NICKNAME IS NULL OR @P_NICKNAME = '') OR F.NICK_NAME IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_NICKNAME, ',')))
	GROUP BY F.DIVISION_ID,
			 F.NICK_NAME,
		     F.SITE_ID,
			 F.SITE_NAME,
			 F.EXTRA_SPEC,
			 F.DEPT_ID,
			 F.DEPT_NAME,
		     F.YYYYMMDD
	ORDER BY F.DIVISION_ID,
			 F.NICK_NAME,
		     F.SITE_ID,
			 F.SITE_NAME,
			 F.EXTRA_SPEC,
			 F.DEPT_ID,
			 F.DEPT_NAME,
		     F.YYYYMMDD;

	---------------------------------------------------------------------------------------------------------
	-- 출력 결과 1 : 계획 데이터
	---------------------------------------------------------------------------------------------------------
    SELECT * FROM #TMP_SCP0055_PLAN_TOTAL WITH (NOLOCK);

	--팀별 출하 실적 (ERP)
	IF OBJECT_ID('tempdb..#TMP_SCP0055_RESULT1') IS NOT NULL
		DROP TABLE #TMP_SCP0055_RESULT1;

		-- ERP 출하실적에서 CONFIRM_ID 존재, SSP_TYPE 대상 
		SELECT E.DIVISION_ID AS DIVISION_ID,
		       SC.FROM_SITE AS SITE_ID,
		       ISNULL((SELECT TOP 1 SITE_DESCRIPTION FROM SCM_MST_SITE WHERE 1=1 AND SCM_SITE_ID = SC.FROM_SITE),'-') AS SITE_NAME,
		       (SELECT TOP 1 ISNULL(NULLIF(SCP_EXTRA_SPEC, ''),'-') FROM DBO.SCM_MST_ITEM_SN X WITH(NOLOCK) WHERE 1=1 AND X.DIVISION_ID = E.DIVISION_ID AND X.ITEM_ID = E.ITEM_ID) AS EXTRA_SPEC,
	           (SELECT TOP 1 ISNULL(NULLIF(NICK_NAME, ''), '-') FROM DBO.SCM_MST_ITEM_SN X WITH(NOLOCK) WHERE 1=1 AND X.ITEM_ID = E.ITEM_ID) AS NICK_NAME,
		       ISNULL(SUI.DEPT_ID, LMD.ATTRIBUTE1) AS DEPT_ID,
			   --SUI.DEPT_ID AS DEPT_ID,
		       ISNULL(ISNULL(SDI.DEPT_NAME_KO, LMD.ATTRIBUTE2), SMS.SITE_DESCRIPTION) AS DEPT_NAME,
	           E.EXFACTORY_DATE AS YYYYMMDD,
	           SUM(E.EXFACTORY_QTY) AS QTY,
	           'RESULT_CE' AS PLAN_FROM,
			   E.CONFIRM_ID
	    INTO #TMP_SCP0055_RESULT1
		FROM SCM_DNM_EXFACTORY_RESULT E WITH(NOLOCK)
		     INNER JOIN SSP_ANL_SHIP_CONFIRM SC WITH (NOLOCK) ON E.DIVISION_ID = SC.DIVISION_ID AND E.CONFIRM_ID = SC.CONFIRM_ID --AND E.EXFACTORY_DATE = SC.YYYYMMDD 
		     JOIN SCP_MST_FINAL_ITEM F WITH(NOLOCK) ON F.ITEM_ID = E.ITEM_ID 
			                                           AND F.DIVISION_ID = E.DIVISION_ID
			 JOIN SCM_ADM_LOOKUP_MASTER_DETAIL L WITH(NOLOCK) ON L.LOOKUP_TYPE = 'ERP_SSP_TYPE' -- LOOKUP에 등록된 공정만 
	 		                                                     AND L.VALID_YN = 'Y'
			                                                     AND L.SEGMENT1    = E.SSP_TYPE 
			 LEFT OUTER JOIN SCM_ADM_LOOKUP_MASTER_DETAIL L3 WITH(NOLOCK) ON L3.LOOKUP_TYPE = 'SHIP_RESULT_TO_SITE_MAPPING' --SOLDTO, SHIPTO 과 MAPPING되는 TO_SITE 
				                                                             AND L3.SEGMENT1    = E.DIVISION_ID 
				                                                             AND L3.SEGMENT2    = E.SOLDTO_CODE
				                                                             AND L3.SEGMENT3    = E.SHIPTO_CODE
			 LEFT OUTER JOIN SCM_MST_SSO_USER_INFO SUI WITH (NOLOCK) ON (
		                                                                 SELECT TOP 1 MSI.OWNER
																	  	   FROM SCM_MST_SITE_ITEM MSI WITH (NOLOCK)
																		  WHERE MSI.DIVISION_ID = E.DIVISION_ID
	                                                                        AND MSI.SCM_SITE_ID = ISNULL(L3.SEGMENT4, SC.TO_SITE)
											                        	    AND MSI.ITEM_ID = E.ITEM_ID
											                         	    AND MSI.VALID_YN = 'Y'
		                                                                ) = SUI.USER_ID
             LEFT OUTER JOIN SCM_MST_SSO_DEPT_INFO SDI WITH (NOLOCK) ON SUI.DEPT_ID = SDI.DEPT_ID 
			                                                            AND SDI.VALID_YN ='Y'
		     LEFT OUTER JOIN SCM_ADM_LOOKUP_MASTER_DETAIL LMD WITH (NOLOCK) ON E.FROM_SCM_SITE_ID = LMD.SEGMENT1 
			                                                                   AND ISNULL(L3.SEGMENT4, SC.TO_SITE) = LMD.SEGMENT2 
		                                                                       AND E.ITEM_ID = LMD.SEGMENT3 
																			   AND LMD.LOOKUP_TYPE = 'SHIPMENT_REPORT_LOOKUP'
		     LEFT OUTER JOIN SCM_MST_SITE SMS WITH (NOLOCK) ON 1=1
			                                                   AND E.DIVISION_ID = SMS.DIVISION_ID
			                                                   AND SC.TO_SITE = SMS.SCM_SITE_ID 
