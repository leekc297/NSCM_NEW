		FROM DM_ANL_CAR_FCST_REF WITH(NOLOCK) 
		WHERE CREATION_DATE = 
		(
			SELECT MAX(CREATION_DATE)
			FROM DM_ANL_CAR_FCST_REF WITH(NOLOCK) 
			WHERE MAKER_NAME = 'Ford' 
			AND CAR_MODEL = 'Ford Mustang Mach-E BEV' 
		)

		SELECT TOP 100 *
		FROM DM_ANL_CAR_FCST_REF WITH(NOLOCK) 
		WHERE MAKER_NAME = 'Ford' 
		AND CAR_MODEL = 'Ford Mustang Mach-E BEV' 
		ORDER BY CREATION_DATE DESC		
		*/

END

