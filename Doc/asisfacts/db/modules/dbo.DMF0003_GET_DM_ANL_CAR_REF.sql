CREATE PROCEDURE [dbo].[DMF0003_GET_DM_ANL_CAR_REF]
	@p_from_yyyymmdd	NVARCHAR(8),
	@p_to_yyyymmdd	    NVARCHAR(8),
	@p_car_maker        NVARCHAR(50),
	@p_car_model	    NVARCHAR(50)
AS

--EXEC DMF0003_GET_DM_ANL_CAR_REF '20230701', '20240630', 'FORD', 'Ford Mustang Mach-E BEV'

DECLARE @p_from_yyyyQQ	NVARCHAR(6)
DECLARE @p_to_yyyyQQ	NVARCHAR(6)
DECLARE @COLUMNS	    NVARCHAR(MAX)
DECLARE @SQL	        NVARCHAR(MAX)
DECLARE @SQL0	        NVARCHAR(MAX)
DECLARE @SQL1	        NVARCHAR(MAX)
DECLARE @SQL2	        NVARCHAR(MAX)
DECLARE @SQL3	        NVARCHAR(MAX)
DECLARE @SQL4	        NVARCHAR(MAX)
DECLARE @SQL5	        NVARCHAR(MAX)
DECLARE @SQL6	        NVARCHAR(MAX)
DECLARE @SQL7	        NVARCHAR(MAX)

CREATE TABLE #TEMP_DATA(  
  MAKER_NAME              NVARCHAR(30) NOT NULL,  
  CAR_MODEL          NVARCHAR(30)  NOT NULL,  
  YYYYQQ          NVARCHAR(30) NOT NULL,  
  P_QTY         INT,  
  S_QTY         INT,  
  I_QTY         INT,  
  )

BEGIN
	SET NOCOUNT ON;

	SELECT @p_from_yyyyQQ = CALENDAR_YYYYQQ FROM SCM_SYS_CALENDAR_M WHERE BASIS_YYYYMMDD = @p_from_yyyymmdd
	SELECT @p_to_yyyyQQ = CALENDAR_YYYYQQ FROM SCM_SYS_CALENDAR_M WHERE BASIS_YYYYMMDD = @p_to_yyyymmdd

	PRINT @p_from_yyyyQQ
	PRINT @p_to_yyyyQQ
	PRINT @p_car_maker

	SELECT DISTINCT YYYYQQ FROM DM_ANL_CAR_FCST_REF WHERE YYYYQQ BETWEEN @p_from_yyyyQQ AND @p_to_yyyyQQ ORDER BY YYYYQQ ASC

	SET @COLUMNS = ''
	SELECT @COLUMNS = @COLUMNS + '[' + YYYYQQ + '],' FROM 
	(SELECT DISTINCT YYYYQQ FROM DM_ANL_CAR_FCST_REF WHERE YYYYQQ BETWEEN @p_from_yyyyQQ AND @p_to_yyyyQQ) YYYYQQ
	ORDER BY YYYYQQ 



	IF (@p_car_maker != '' AND @p_car_model!= '')
	BEGIN
		INSERT INTO #TEMP_DATA
		SELECT MAKER_NAME,CAR_MODEL,YYYYQQ,P_QTY,S_QTY,I_QTY  FROM DM_ANL_CAR_FCST_REF WITH(NOLOCK) WHERE 1=1
		AND YYYYQQ BETWEEN @p_from_yyyyQQ AND @p_to_yyyyQQ
		AND MAKER_NAME = @p_car_maker 
		AND CAR_MODEL = @p_car_model 
	END
	ELSE IF (@p_car_maker != '' AND @p_car_model = '')
	BEGIN
		INSERT INTO #TEMP_DATA
		SELECT MAKER_NAME,CAR_MODEL,YYYYQQ,P_QTY,S_QTY,I_QTY FROM DM_ANL_CAR_FCST_REF WITH(NOLOCK) WHERE 1=1
		AND YYYYQQ BETWEEN @p_from_yyyyQQ AND @p_to_yyyyQQ
		AND MAKER_NAME = @p_car_maker 
	END

	--SELECT * FROM #TEMP_DATA
	
SET @COLUMNS = LEFT(@COLUMNS, LEN(@COLUMNS) - 1)

SET @SQL = N'
SELECT * FROM(
	SELECT *, ''차량대수별'' AS MAJOR_CAT, N''P) 차량생산[R+P]'' AS MINOR_CAT FROM(
	SELECT * FROM (SELECT MAKER_NAME, CAR_MODEL, YYYYQQ, P_QTY FROM #TEMP_DATA) AS RESULT PIVOT (SUM(P_QTY) FOR YYYYQQ IN (' + @COLUMNS + ')) AS PIVOT_RESULT
	) A
	UNION ALL
	SELECT *,  N''차량대수별'' AS MAJOR_CAT, N''S) 차량판매[R+P]'' AS MINOR_CAT FROM(
	SELECT * FROM (SELECT MAKER_NAME, CAR_MODEL, YYYYQQ, S_QTY FROM #TEMP_DATA) AS RESULT PIVOT (SUM(S_QTY) FOR YYYYQQ IN (' + @COLUMNS + ')) AS PIVOT_RESULT
	) A
	UNION ALL
	SELECT *,  ''차량대수별'' AS MAJOR_CAT, ''I) 누적차량재고[R+P]'' AS MINOR_CAT FROM(
	SELECT * FROM (SELECT MAKER_NAME, CAR_MODEL, YYYYQQ, I_QTY FROM #TEMP_DATA) AS RESULT PIVOT (SUM(I_QTY) FOR YYYYQQ IN (' + @COLUMNS + ')) AS PIVOT_RESULT
	) A
) AA ORDER BY AA.MAKER_NAME, AA.CAR_MODEL
'

SET @SQL0 = N'SELECT * FROM('

SET @SQL1 = N'
	SELECT *, N''차량대수별'' AS MAJOR_CAT, N''P) 차량생산[R+P]'' AS MINOR_CAT FROM(
	SELECT * FROM (SELECT MAKER_NAME, CAR_MODEL, YYYYQQ, P_QTY FROM #TEMP_DATA) AS RESULT PIVOT (SUM(P_QTY) FOR YYYYQQ IN (' + @COLUMNS + ')) AS PIVOT_RESULT
	) A
	UNION ALL
'
SET @SQL2 = N'
	SELECT *,  N''차량대수별'' AS MAJOR_CAT, N''S) 차량판매[R+P]'' AS MINOR_CAT FROM(
	SELECT * FROM (SELECT MAKER_NAME, CAR_MODEL, YYYYQQ, S_QTY FROM #TEMP_DATA) AS RESULT PIVOT (SUM(S_QTY) FOR YYYYQQ IN (' + @COLUMNS + ')) AS PIVOT_RESULT
	) A
	UNION ALL
'
SET @SQL3 = N'
	SELECT *,  N''차량대수별'' AS MAJOR_CAT, N''I) 누적차량재고[R+P]'' AS MINOR_CAT FROM(
	SELECT * FROM (SELECT MAKER_NAME, CAR_MODEL, YYYYQQ, I_QTY FROM #TEMP_DATA) AS RESULT PIVOT (SUM(I_QTY) FOR YYYYQQ IN (' + @COLUMNS + ')) AS PIVOT_RESULT
	) A
	UNION ALL
'
SET @SQL4 = N'
	SELECT *,  N''BIZ단위환산'' AS MAJOR_CAT, N''P) 차량생산[R+P]'' AS MINOR_CAT FROM(
	SELECT * FROM (SELECT MAKER_NAME, CAR_MODEL, YYYYQQ, 0 P_QTY FROM #TEMP_DATA) AS RESULT PIVOT (SUM(P_QTY) FOR YYYYQQ IN (' + @COLUMNS + ')) AS PIVOT_RESULT
	) A
	UNION ALL
'
SET @SQL5 = N'
	SELECT *,  N''BIZ단위환산'' AS MAJOR_CAT, N''S) 차량판매[R+P]'' AS MINOR_CAT FROM(
	SELECT * FROM (SELECT MAKER_NAME, CAR_MODEL, YYYYQQ, 0 S_QTY FROM #TEMP_DATA) AS RESULT PIVOT (SUM(S_QTY) FOR YYYYQQ IN (' + @COLUMNS + ')) AS PIVOT_RESULT
	) A
	UNION ALL
'
SET @SQL6 = N'
	SELECT *,  N''BIZ단위환산'' AS MAJOR_CAT, N''I) 누적차량재고[R+P]'' AS MINOR_CAT FROM(
	SELECT * FROM (SELECT MAKER_NAME, CAR_MODEL, YYYYQQ, 0 I_QTY FROM #TEMP_DATA) AS RESULT PIVOT (SUM(I_QTY) FOR YYYYQQ IN (' + @COLUMNS + ')) AS PIVOT_RESULT
	) A
'

SET @SQL7 = N') AA ORDER BY AA.MAKER_NAME, AA.CAR_MODEL'

EXEC(@SQL0+@SQL1+@SQL2+@SQL3+@SQL4+@SQL5+@SQL6+@SQL7)
--EXEC(@SQL0+@SQL1+@SQL2+@SQL3+@SQL7)

--엑셀 추가정보 조회
--SELECT DISTINCT ATTRIBUTE1, ATTRIBUTE2
SELECT 
MAX(ATTRIBUTE1) ATTRIBUTE1 --Data Source
, MAX(ATTRIBUTE2) ATTRIBUTE2 --Basis Date
FROM DM_ANL_CAR_FCST_REF WITH(NOLOCK) 
WHERE CREATION_DATE = 
(
	SELECT MAX(CREATION_DATE)
	FROM DM_ANL_CAR_FCST_REF WITH(NOLOCK) 
	WHERE 1=1
	AND YYYYQQ BETWEEN @p_from_yyyyQQ AND @p_to_yyyyQQ
	AND MAKER_NAME = @p_car_maker 
	AND CAR_MODEL = @p_car_model 
)
AND YYYYQQ BETWEEN @p_from_yyyyQQ AND @p_to_yyyyQQ
AND MAKER_NAME = @p_car_maker 
AND CAR_MODEL = @p_car_model 
		/*

