	@P_BIZ_TYPE				NVARCHAR(30),
	@P_PLANT_SITE			NVARCHAR(MAX),
	@P_BUILDING				NVARCHAR(MAX),
	@P_LINE_ID				NVARCHAR(MAX),
	@P_OPERATION_ID			NVARCHAR(MAX),
	@P_ITEM_ID  			NVARCHAR(MAX),
	@P_EXTRASPEC 			NVARCHAR(MAX),
	@P_ITEMCLASS 			NVARCHAR(MAX),
	@P_PROJECT  			NVARCHAR(MAX),
	@P_NICKNAME  			NVARCHAR(MAX),
	@P_FROM_YYYYMMDD		NVARCHAR(8),
	@P_TO_YYYYMMDD			NVARCHAR(8),
	@P_PROGRAM_ID			NVARCHAR(10) 	= 'SCP0056' ,
	@P_SHEET_NAME			NVARCHAR(30) 	= 'SCP0056_GEN_MPP_SNAPSHOT' ,
	@P_USER_ID				NVARCHAR(30),
	@DEBUG_MODE             NVARCHAR(1) 	='F'
AS
BEGIN
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;
	SET NOCOUNT ON;

	-- LOG 용 변수 설정
	DECLARE @v_program_name 					NVARCHAR(150) 	= 'PR_SCM_DNM_MPP_SNAPSHOT';
	DECLARE @v_log_type     					NVARCHAR(30); -- START/END/ERROR/...
	DECLARE @n_log_count    					INTEGER 		= 0;
	DECLARE @v_log_message  					NVARCHAR(1000);
	DECLARE @v_description  					NVARCHAR(500);
	DECLARE @v_table_id     					NVARCHAR(150) 	= 'SCM_DNM_MPP_SNAPSHOT';
	DECLARE @v_table_id2    					NVARCHAR(150) 	= 'SCM_DNM_MPP';
	DECLARE @d_event_date   					DATETIME;

	-- SNAPSHOT_WEEK
	DECLARE @P_SNPASHOT_WEEK 					NVARCHAR(50);

	-- 최신 PLAN TYPE, SEQ 조회
	DECLARE @V_PLAN_TYPE         				NVARCHAR(8);
	DECLARE @V_SEQ               				NVARCHAR(8);

	DECLARE @V_PLAN_START_YYYYMMDD 				NVARCHAR(8);
	DECLARE @V_PLAN_START_YYYYMMDD_CURRENT 		NVARCHAR(8);
	DECLARE @V_PLAN_START_YYYYMMDD_LastweekSUN 	NVARCHAR(8);
	DECLARE @V_PLAN_START_YYYYMMDD_TUE 			NVARCHAR(8); -- 0804hseokjang
	DECLARE @V_PLAN_START_YYYYMMDD_ThisweekMON 	NVARCHAR(8); -- 0804hseokjang

		--SELECT @V_PLAN_START_YYYYMMDD = A.BASIS_START_DATE
	 --     FROM SCM_SYS_CALENDAR_M A WITH (NOLOCK)
	 --    WHERE A.BASIS_YYYYMMDD = CONVERT(VARCHAR, GETDATE(), 112);


	--HSEOKJANG 지난주 월요일 일자 추출. SCP PLAN ID 찾기용
	SELECT @V_PLAN_START_YYYYMMDD = B.BASIS_YYYYMMDD
	  FROM
			(
				 SELECT *
				 FROM SCM_SYS_CALENDAR_M A WITH (NOLOCK)
				 WHERE  1=1
				   AND  BASIS_YYYYMMDD = CONVERT(VARCHAR, GETDATE()-7, 112) /*지난주 기준 계획데이터 가져온다*/
			)A,
			SCM_SYS_CALENDAR_M B
	 WHERE A.ISO_YYYYWW = B.ISO_YYYYWW
	   AND B.DAYOFWEEK ='MON';



	--HSEOKJANG 당주 월요일 일자 추출. SCP PLAN 시작일자 찾기용
	SELECT @V_PLAN_START_YYYYMMDD_CURRENT = B.BASIS_YYYYMMDD
	  FROM  (
				 SELECT *
				 FROM SCM_SYS_CALENDAR_M A WITH (NOLOCK)
				 WHERE  1=1
				   AND  BASIS_YYYYMMDD = CONVERT(VARCHAR, GETDATE(), 112)
			)A,
			SCM_SYS_CALENDAR_M B
	 WHERE A.ISO_YYYYWW = B.ISO_YYYYWW
	   AND B.DAYOFWEEK ='MON';

	 -- 0804hseokjang 당주 화요일 일자 추출. 자동차 사업부는 월요일까지의 실적을 기준으로 함
	SELECT @V_PLAN_START_YYYYMMDD_TUE = B.BASIS_YYYYMMDD
	  FROM  (
				 SELECT *
				 FROM SCM_SYS_CALENDAR_M A WITH (NOLOCK)
				 WHERE  1=1
				   AND  BASIS_YYYYMMDD = CONVERT(VARCHAR, GETDATE(), 112)
			)A,
			SCM_SYS_CALENDAR_M B
	 WHERE A.ISO_YYYYWW = B.ISO_YYYYWW
	   AND B.DAYOFWEEK ='TUE';

		--HSEOKJANG 전주 일요일 일자 추출. 실적 범위 찾기용
	   SELECT @V_PLAN_START_YYYYMMDD_LastweekSUN = B.BASIS_YYYYMMDD
	  FROM  (
				 SELECT *
				 FROM SCM_SYS_CALENDAR_M A WITH (NOLOCK)
				 WHERE  1=1
				   AND  BASIS_YYYYMMDD = CONVERT(VARCHAR, GETDATE()-7, 112)
			)A,
			SCM_SYS_CALENDAR_M B
	 WHERE A.ISO_YYYYWW = B.ISO_YYYYWW
	   AND B.DAYOFWEEK ='SUN';

	-- 0804hseokjang 당주 월요일 일자 추출. 자동차 사업부는 월요일까지의 실적을 기준으로 함
	SELECT	@V_PLAN_START_YYYYMMDD_ThisweekMON =B.BASIS_YYYYMMDD
	FROM  	(
				SELECT *
				FROM SCM_SYS_CALENDAR_M A WITH (NOLOCK)
				WHERE  1=1
				  AND  BASIS_YYYYMMDD = CONVERT(VARCHAR, GETDATE(), 112)
			)A,
			SCM_SYS_CALENDAR_M B
	WHERE 	A.ISO_YYYYWW = B.ISO_YYYYWW
		AND B.DAYOFWEEK ='MON';


	IF OBJECT_ID('tempdb..#TEMP_PLAN_SEQ') IS NOT NULL
		DROP TABLE #TEMP_PLAN_SEQ;

	--20210706 START
	SELECT DIVISION_ID
		 , MAX(PLAN_SEQ) AS PLAN_SEQ
	  INTO #TEMP_PLAN_SEQ
	  FROM SCP_PLAN_VERSION_V WITH(NOLOCK)
	 WHERE PLAN_START_YYYYMMDD  = @V_PLAN_START_YYYYMMDD
	   AND PLAN_TYPE = 'FN'
	   AND DIVISION_ID IN ( '40','82')
	 GROUP BY DIVISION_ID;
	--20210706 END


	--WITH TEMP_PLAN AS (
	 --   SELECT PLAN_TYPE AS CODE
	 --        , PLAN_TYPE AS NAME
	 --        , MAX(PLAN_SEQ) AS PLAN_SEQ
	 --        , MAX( PLAN_TYPE_ORDER) AS  PLAN_TYPE_ORDER
	 --     FROM SCP_PLAN_VERSION_V WITH(NOLOCK)
	 --    WHERE 1=1
	 --      AND DIVISION_ID = @P_DIVISION_ID
	 --      AND PLAN_START_YYYYMMDD = @V_PLAN_START_YYYYMMDD
	 --    GROUP BY PLAN_TYPE
	 --   )
	 --   SELECT @V_PLAN_TYPE = CODE,
		--       @V_SEQ = PLAN_SEQ
		--  FROM TEMP_PLAN
	 --    --WHERE PLAN_TYPE_ORDER = (SELECT MAX(PLAN_TYPE_ORDER) FROM TEMP_PLAN);
		-- WHERE PLAN_TYPE_ORDER = (SELECT MAX(PLAN_TYPE_ORDER) FROM TEMP_PLAN WHERE 1=1 AND NAME = 'FN');

	-- 시작 LOG
	SET @v_log_type 	= 'START';
	SET @v_log_message 	= '########## Start of procedure ##########';
	SET @v_description 	= '' ;
	SET @d_event_date 	= SYSDATETIME();

	EXEC PR_SCM_SYS_LOG_BATCH @v_program_name, @v_log_type, @n_log_count, @v_log_message, @v_description, @d_event_date;

	BEGIN TRY
	BEGIN
		--HSEOKJANG 당주 SNAPSHOT WEEK 찾기용
		--SELECT @P_SNPASHOT_WEEK = CALENDAR_YYYY + '-' + REPLACE(WEEK_NAME, 'W', '')
		SELECT @P_SNPASHOT_WEEK = CALENDAR_YYYY + '-' + WEEK_NAME
		  FROM SCM_SYS_CALENDAR_M WITH (NOLOCK)
		 WHERE BASIS_YYYYMMDD = CONVERT(VARCHAR, GETDATE(), 112);


		PRINT @P_SNPASHOT_WEEK;

		--HSEOKJANG 과거 7주구간 가져옴. 계획/실적 모두 6주 전 데이터부터 재생성.
		IF ((@P_FROM_YYYYMMDD IS NULL OR @P_FROM_YYYYMMDD =''))
		BEGIN
			SELECT @P_FROM_YYYYMMDD = CONVERT(VARCHAR,  DATEADD(dd, -49, GETDATE()), 112)

			PRINT '@P_FROM_YYYYMMDD = ' + @P_FROM_YYYYMMDD;
		END;

		--HSEOKJANG 미래 7주구간 가져옴. 계획 용도.
		IF ((@P_TO_YYYYMMDD IS NULL OR @P_TO_YYYYMMDD =''))
		BEGIN
			SELECT @P_TO_YYYYMMDD = CONVERT(VARCHAR,  DATEADD(dd, 49, GETDATE()), 112)

			PRINT '@P_TO_YYYYMMDD = ' + @P_TO_YYYYMMDD;
		END;

		-- 기준 날짜
		IF OBJECT_ID('tempdb..#TMP_SCP0056_BASIS_DATE') IS NOT NULL
			DROP TABLE #TMP_SCP0056_BASIS_DATE;

		--SELECT REPLACE(WEEK_NAME, 'W', '') AS WEEK_NAME,


		SELECT WEEK_NAME AS WEEK_NAME,
			   BASIS_YYYYMMDD,
			   CALENDAR_YYYY AS BASIS_YEAR,
			   CALENDAR_YYYY + '-' + CALENDAR_MONTH AS BASIS_MONTH,
			   --CALENDAR_YYYY + '-' + REPLACE(WEEK_NAME, 'W', '') AS BASIS_WEEK,
			   --CALENDAR_YYYY + '-' + WEEK_NAME AS BASIS_WEEK,
			   CALENDAR_YYYY + '-' + PARTIAL_WEEK_NAME AS BASIS_WEEK,
			   LEFT(CONVERT(VARCHAR, CONVERT(DATE, BASIS_YYYYMMDD), 126), 10) AS BASIS_DATE,
			   BASIS_YYYYMM
		  INTO #TMP_SCP0056_BASIS_DATE
		  FROM SCM_SYS_CALENDAR_M WITH (NOLOCK)
		 WHERE BASIS_DATE BETWEEN @P_FROM_YYYYMMDD AND @P_TO_YYYYMMDD;

		--SELECT *
		--FROM #TMP_SCP0056_BASIS_DATE
		--ORDER BY BASIS_DATE;

		-- MPP 계획 (일자별)
		IF OBJECT_ID('tempdb..#TMP_SCP0056_MPP_D') IS NOT NULL
			DROP TABLE #TMP_SCP0056_MPP_D;

		SELECT
			   MPP.DIVISION_ID,
			   MPP.SITE_ID,
			   MPP.PLANT_ID,
			   MPP.FACTORY_ID,
			   MIS.SCP_OPERATION_GROUP,
			   MPP.OPERATION_ID,
			   MPP.LINE_ID,
			   MLS.LINE_NAME,
			   ISNULL(MIS.DOE, MPP.ITEM_ID) AS BASIC_ITEM,
			   --20210706 START
			   --(SELECT TOP 1 ISNULL(NULLIF(NICK_NAME, ''), '-') FROM DBO.SCM_MST_ITEM_SN X WITH(NOLOCK) WHERE 1=1 AND X.ITEM_ID = ISNULL(MIS.DOE, MPP.ITEM_ID)) AS BASIC_NICK_NAME,
			   (
					SELECT TOP 1 ISNULL(NULLIF(NICK_NAME, ''), '-')
					FROM DBO.SCM_MST_ITEM_SN X WITH(NOLOCK)
					WHERE 1=1 AND X.DIVISION_ID = MPP.DIVISION_ID
					--AND X.SITE_ID = MPP.SITE_ID
					AND X.ITEM_ID = ISNULL(MIS.DOE, MPP.ITEM_ID)
				) AS BASIC_NICK_NAME,
			   --20210706 END
			   MPP.ITEM_ID,
			   MPP.PRODUCTION_TYPE,
			   --20210706 START
			   --(SELECT TOP 1 ISNULL(NULLIF(NICK_NAME, ''), '-') FROM DBO.SCM_MST_ITEM_SN X WITH(NOLOCK) WHERE 1=1 AND X.ITEM_ID = ISNULL(MIS.DOE, MPP.ITEM_ID)		   ) AS NICK_NAME,
			   (
				   SELECT TOP 1 ISNULL(NULLIF(NICK_NAME, ''), '-')
				   FROM DBO.SCM_MST_ITEM_SN X WITH(NOLOCK)
				   WHERE 1=1
					 AnD X.DIVISION_ID = MPP.DIVISION_ID
					 --AND X.SITE_ID = MPP.SITE_ID
					 AND X.ITEM_ID = ISNULL(MIS.DOE, MPP.ITEM_ID)
			   ) AS NICK_NAME,
			   --20210706 END
			   (SELECT TOP 1 ISNULL(NULLIF(SCP_EXTRA_SPEC, ''),'-') FROM DBO.SCM_MST_ITEM_SN X WITH(NOLOCK) WHERE 1=1 AND X.DIVISION_ID = MPP.DIVISION_ID AND X.ITEM_ID = ISNULL(MIS.DOE, MPP.ITEM_ID)) AS EXTRA_SPEC,
			   --(SELECT TOP 1 ISNULL(NULLIF(ITEM_CLASS_NAME, ''),'-') FROM DBO.SCM_MST_ITEM_SN X WITH(NOLOCK) WHERE 1=1 AND X.DIVISION_ID = MPP.DIVISION_ID AND X.ITEM_ID = ISNULL(MIS.DOE, MPP.ITEM_ID)) AS ITEM_CLASS,
			   '-' AS ITEM_CLASS,
			   LEFT(CONVERT(VARCHAR, MPP.PLAN_DATE, 126), 10) MPP_DATE,
			   SUM(MPP.PLAN_QTY) AS QTY,
			   0 AS SCP_QTY
		  INTO #TMP_SCP0056_MPP_D
		  FROM SCM_DNM_FP_RELEASE_PROD_PLAN_SN MPP WITH (NOLOCK)

			INNER JOIN SCM_MST_LINE_SN MLS WITH (NOLOCK)
			 ON  MPP.DIVISION_ID    = MLS.DIVISION_ID
			 AND MPP.SITE_ID        = MLS.SITE_ID
			 AND MPP.PLANT_ID       = MLS.PLANT_ID
			 AND MPP.LINE_ID        = MLS.LINE_ID
			 AND MPP.OPERATION_ID   = MLS.OPERATION_ID
			 AND MLS.ACTIVE_FLAG    = 'Y'
			 AND MPP.ELECTRODE_TYPE = MLS.ELECTRODE_TYPE --AND MLS.ELECTRODE_TYPE = 'Cathode'

			LEFT OUTER JOIN SCM_MST_ITEM_SN MIS WITH (NOLOCK) ON
					MPP.DIVISION_ID = MIS.DIVISION_ID
				AND MLS.COMPANY_ID  = MIS.COMPANY_ID
				AND MPP.ITEM_ID     = isnull(MIS.ITEM_ID,MIS.DOE)

			/*   INNER JOIN SCM_MST_LINE_SN MLS WITH (NOLOCK) ON MPP.DIVISION_ID = MLS.DIVISION_ID AND MPP.SITE_ID = MLS.SITE_ID AND MPP.LINE_ID = MLS.LINE_ID AND MPP.OPERATION_ID = MLS.OPERATION_ID AND MLS.ACTIVE_FLAG = 'Y' AND MPP.ELECTRODE_TYPE = MLS.ELECTRODE_TYPE --AND MLS.ELECTRODE_TYPE = 'Cathode'
			   --LEFT OUTER JOIN SCM_MST_ITEM_SN MIS WITH (NOLOCK) ON MPP.DIVISION_ID = MIS.DIVISION_ID AND MPP.SITE_ID = MIS.SITE_ID AND ISNULL(MIS.DOE, MPP.ITEM_ID) = MIS.ITEM_ID
			   --2021.07.08 SITE ID 가져오는 로직 변경 START
			   --LEFT OUTER JOIN SCM_MST_ITEM_SN MIS WITH (NOLOCK) ON MPP.DIVISION_ID = MIS.DIVISION_ID AND MPP.SITE_ID = MIS.SITE_ID AND MPP.ITEM_ID = isnull(MIS.ITEM_ID,MIS.DOE)
			   LEFT OUTER JOIN SCM_MST_ITEM_SN MIS WITH (NOLOCK) ON
						MPP.DIVISION_ID = MIS.DIVISION_ID
					AND (SELECT TOP 1 SITE_ID FROM SCM_LINE_M_SN L
						WHERE  1=1
						AND    MPP.OPERATION_ID = L.OPERATION_ID
						AND    MPP.LINE_ID = L.LINE_ID
						) = MIS.SITE_ID
					AND MPP.ITEM_ID = isnull(MIS.ITEM_ID,MIS.DOE)
				--2021.07.08 SITE ID 가져오는 로직 변경 END
				*/
		 WHERE 1=1
		   AND ((@P_DIVISION_ID IS NULL OR @P_DIVISION_ID ='') OR MPP.DIVISION_ID IN ( SELECT TOKEN FROM DBO.STRING_SPLIT(@P_DIVISION_ID, ',')))
		   AND ((@P_PLANT_SITE IS NULL OR @P_PLANT_SITE ='') OR MPP.PLANT_ID IN ( SELECT TOKEN FROM DBO.STRING_SPLIT(@P_PLANT_SITE, ',')))
		   AND ((@P_ITEM_ID IS NULL OR @P_ITEM_ID ='') OR MPP.ITEM_ID IN ( SELECT TOKEN FROM DBO.STRING_SPLIT(@P_ITEM_ID, ',')))
		   AND ((@P_OPERATION_ID IS NULL OR @P_OPERATION_ID ='') OR MPP.OPERATION_ID IN ( SELECT TOKEN FROM DBO.STRING_SPLIT(@P_OPERATION_ID, ',')))
		   AND ((@P_LINE_ID IS NULL OR @P_LINE_ID ='') OR MPP.LINE_ID IN ( SELECT TOKEN FROM DBO.STRING_SPLIT(@P_LINE_ID, ',')))
		   AND MPP.PLAN_TYPE = 'MPP'
		   AND MPP.PLAN_DATE BETWEEN @P_FROM_YYYYMMDD AND @P_TO_YYYYMMDD
