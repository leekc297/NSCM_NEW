CREATE PROCEDURE [dbo].[PR_DM_ANL_MKT_PSI_DATA] 
AS
BEGIN
	SET NOCOUNT ON;
	SET TRANSACTION ISOLATION LEVEL READ COMMITTED;
	SET XACT_ABORT ON; 

	
	BEGIN TRAN PR_DM_ANL_MKT_PSI_DATA;

	BEGIN TRY

		-- LOG 용 변수 설정
		DECLARE @V_PROGRAM_NAME		NVARCHAR(150) = 'PR_DM_ANL_MKT_PSI_DATA';
		DECLARE @V_LOG_TYPE			NVARCHAR(30); -- START/END/ERROR/...
		DECLARE @N_LOG_COUNT		INTEGER = 0;
		DECLARE @V_LOG_MESSAGE		NVARCHAR(1000);
		DECLARE @V_DESCRIPTION		NVARCHAR(500);
		DECLARE @D_EVENT_DATE		DATETIME;
		DECLARE @N_DELETE_COUNT		INTEGER = 0;
		DECLARE @N_INSERT_COUNT     INTEGER = 0;
		DECLARE @V_CREATED_BY		NVARCHAR(150)	= 'SYS_PSI_DATA';

		-- 시작 LOG
		SET @V_LOG_TYPE = 'START';
		SET @V_LOG_MESSAGE = '########## START OF PROCEDURE ##########';
		SET @V_DESCRIPTION = '';
		SET @D_EVENT_DATE = SYSDATETIME();
		EXEC  PR_DM_SYS_LOG_BATCH @V_PROGRAM_NAME, @V_LOG_TYPE, @N_LOG_COUNT, @V_LOG_MESSAGE, @V_DESCRIPTION, @D_EVENT_DATE, @V_CREATED_BY;
 
       

		DECLARE @v_0month_tuesday NVARCHAR(08);--당월의 첫번째 수요일이 포함된 주차의 MKT_FCST Cutoff	
		DECLARE @v_delimiter NVARCHAR(1);
	 
	  
		DECLARE @v_CNT INTEGER = 0;
		DECLARE @v_CNT_PRE INTEGER = 0;
		DECLARE @v_from_yyyymmdd NVARCHAR(08);
		DECLARE @v_to_yyyymmdd   NVARCHAR(08);
    	DECLARE @v_from_yyyymmdd_R NVARCHAR(08);
	    DECLARE @v_to_yyyymmdd_R   NVARCHAR(08);

		
         PRINT ( 'A1--#TEMP_DATA ' + CONVERT(NVARCHAR(30), GETDATE(), 121))
	
		-- 테이블중복제거
		IF OBJECT_ID(N'tempdb..#TEMP_DATA', N'U') IS NOT NULL
			DROP TABLE #TEMP_DATA

		-- 임시확인용테이블 중복제거
		IF OBJECT_ID(N'dbo.#TEMP_DATA', N'U') IS NOT NULL
			DROP TABLE #TEMP_DATA

		CREATE TABLE #TEMP_DATA (
			 DIVISION_ID  NVARCHAR(30) NOT NULL
			,End_Customer NVARCHAR(50) NOT NULL
			,PROJECT_CODE NVARCHAR(50) NOT NULL 
			,YYYYMM       NVARCHAR(08) NOT NULL
			,MEASURE      NVARCHAR(50) NOT NULL 
			);
				 
		BEGIN		  
			SET @v_from_yyyymmdd = CONVERT(VARCHAR, SUBSTRING(CONVERT(CHAR(8), DATEADD(mm, - 12, GETDATE()),  112), 1, 6) + '01', 112) 
			--SET @v_to_yyyymmdd = CONVERT(CHAR(8), GETDATE(), 112) 
	     	SET @v_to_yyyymmdd = CONVERT(CHAR(8), DATEADD(DD, - 1, DATEADD(MM, 1, SUBSTRING(CONVERT(CHAR(8), GETDATE(), 112), 1, 6) + '01')),  112) 
		END

		BEGIN 
			-- 테이블중복제거
    		IF OBJECT_ID(N'tempdb..#TEMP_SCM_SYS_CALENDAR_M', N'U') IS NOT NULL
	    		DROP TABLE #TEMP_SCM_SYS_CALENDAR_M

     		-- 임시확인용테이블 중복제거
    		IF OBJECT_ID(N'dbo.#TEMP_SCM_SYS_CALENDAR_M', N'U') IS NOT NULL
			   DROP TABLE #TEMP_SCM_SYS_CALENDAR_M
		   
			-- YYYYMM  13개월 가져오기
			SELECT DISTINCT BASIS_YYYYMM AS YYYYMM 
			INTO #TEMP_SCM_SYS_CALENDAR_M
			FROM   [dbo].[SCM_SYS_CALENDAR_M] A WITH(NOLOCK)		 
			WHERE  A.basis_yyyymmdd >= @v_from_yyyymmdd
			AND    A.basis_yyyymmdd <= @v_to_yyyymmdd  

			
     		-- 실적구간 / 계획구간 구분 
			SELECT @v_from_yyyymmdd_R = ISNULL(MAX(X.YYYYMMDD),CONVERT(CHAR(8), DATEADD(DD, - 1,@V_from_yyyymmdd),  112))
				 , @v_to_yyyymmdd_R = ISNULL(MAX(X.YYYYMMDD),@V_to_yyyymmdd) 
			FROM DM_PLN_MKT_FCST_RESULT X WITH (NOLOCK) 	
			WHERE 1 = 1 
			AND X.DIVISION_ID LIKE '81%'	
			AND X.MEASURE IN ('CUST_FCST_EDI','CUST_FCST')	 
			AND X.YYYYMMDD  >= @V_from_yyyymmdd
			AND X.YYYYMMDD  <= @V_to_yyyymmdd 
		
		END
	 
	 
		/*	
		  대상추출(DM_ANL_MKT_PSI 에 없는건 추출(당월 ~ -12개월)
		*/
		BEGIN
	
		   INSERT INTO #TEMP_DATA 
		   SELECT T1.DIVISION_ID
				, T1.END_CUSTOMER
				, T1.PROJECT_CODE 
				, T2.YYYYMM  
				, T3.MEASURE
			FROM  
				(SELECT A.DIVISION_ID
					  , A.END_CUSTOMER
					  , A.PROJECT_CODE 
				   FROM (SELECT X.DIVISION_ID
							  , H.END_CUSTOMER
							  , X.PROJECT_CODE 
						   FROM DM_PLN_MKT_FCST_RESULT X WITH (NOLOCK) 			   
						   JOIN SCM_MST_SITE_ITEM F WITH(NOLOCK) 
								ON	F.DIVISION_ID    = X.DIVISION_ID
							   AND	F.PROJECT_CODE   = X.PROJECT_CODE
							   AND	F.SCM_SITE_ID    = X.SCM_SITE_ID
							   AND	F.ITEM_ID        = X.ITEM_ID			   
						   JOIN SCM_MST_SITE H WITH(NOLOCK) 
								ON	F.DIVISION_ID    = H.DIVISION_ID 
							   AND	F.SCM_SITE_ID    = H.SCM_SITE_ID
						  JOIN SCM_ADM_LOOKUP_MASTER_DETAIL G WITH(NOLOCK) 
							   ON	G.SEGMENT1    = X.FCST_TYPE
							  AND	G.LOOKUP_TYPE = 'SALES_TYPE_CODE' 
						  WHERE 1 = 1 
							AND X.DIVISION_ID LIKE '81%'	
							AND X.MEASURE IN ('CUST_FCST_EDI','CUST_FCST')	
							AND X.YYYYMMDD  >= @V_from_yyyymmdd
							AND X.YYYYMMDD  <= @v_to_yyyymmdd_R
						  GROUP BY X.DIVISION_ID
								 , H.END_CUSTOMER
								 , X.PROJECT_CODE 
						 UNION ALL
						 SELECT X.DIVISION_ID
							  , H.END_CUSTOMER
							  , X.PROJECT_CODE 
						   FROM DM_PLN_MKT_FCST X WITH (NOLOCK) 			   
							JOIN SCM_MST_SITE_ITEM F WITH(NOLOCK) 
								ON	F.DIVISION_ID    = X.DIVISION_ID
								AND	F.PROJECT_CODE   = X.PROJECT_CODE
								AND	F.SCM_SITE_ID    = X.SCM_SITE_ID
								AND	F.ITEM_ID        = X.ITEM_ID			   
							JOIN SCM_MST_SITE H WITH(NOLOCK) 
								ON	F.DIVISION_ID    = H.DIVISION_ID 
								AND	F.SCM_SITE_ID    = H.SCM_SITE_ID
							JOIN SCM_ADM_LOOKUP_MASTER_DETAIL G WITH(NOLOCK) 
								ON	G.SEGMENT1    = X.FCST_TYPE
								AND	G.LOOKUP_TYPE = 'SALES_TYPE_CODE' 
							WHERE 1 = 1 
							AND X.DIVISION_ID LIKE '81%'	
							AND X.MEASURE IN ('CUST_FCST_EDI','CUST_FCST')	
							AND X.YYYYMMDD  > @V_from_yyyymmdd_R
							AND X.YYYYMMDD  <= @V_to_yyyymmdd 
						GROUP BY X.DIVISION_ID
								, H.END_CUSTOMER
								, X.PROJECT_CODE 
					  ) A
				GROUP BY A.DIVISION_ID
					  , A.END_CUSTOMER
					  , A.PROJECT_CODE  
				) T1		  
				INNER JOIN 
				#TEMP_SCM_SYS_CALENDAR_M T2
				ON 1 = 1  
				INNER JOIN 
				(SELECT 'AN_RESULT' AS MEASURE UNION ALL
				 SELECT 'AN_LOGIC' AS MEASURE UNION ALL
				 SELECT 'DP_INIT' AS MEASURE UNION ALL
				 SELECT 'DP_RESULT' AS MEASURE
				) T3		  
				ON 1 = 1
				LEFT OUTER JOIN 
				(
					SELECT T1.DIVISION_ID
						  ,T1.PROJECT_CODE
						  ,T1.END_CUSTOMER 
						  ,T1.YYYYMM
					FROM DM_ANL_MKT_PSI T1 WITH (NOLOCK)
					JOIN #TEMP_SCM_SYS_CALENDAR_M T2
						 ON T1.YYYYMM  = T2.YYYYMM 
					GROUP BY T1.DIVISION_ID,T1.PROJECT_CODE,T1.END_CUSTOMER,T1.YYYYMM 
					) T4 
					ON T1.DIVISION_ID = T4.DIVISION_ID
				   AND T1.END_CUSTOMER = T4.END_CUSTOMER
				   AND T1.PROJECT_CODE = T4.PROJECT_CODE 
				   AND T2.YYYYMM = T4.YYYYMM
			 WHERE T4.YYYYMM IS NULL
		END
	   	 
		 
         PRINT ( 'A2--DM_ANL_MKT_PSI INSERT ' + CONVERT(NVARCHAR(30), GETDATE(), 121))

		/*	
		  DM_ANL_MKT_PSI 저장
		*/
		BEGIN
			INSERT INTO DM_ANL_MKT_PSI (
				 DIVISION_ID
				,END_CUSTOMER
				,PROJECT_CODE
				,YYYYMM
				,CUST_FCST_M
				,MEASURE
				,P_VALUE
				,S_VALUE
				,I_VALUE
				,V_VALUE
				,M_VALUE
				,MKT_FCST_M
				,CUST_FCST_M_CELL
				,P_VALUE_CELL
				,S_VALUE_CELL
				,I_VALUE_CELL
				,V_VALUE_CELL
				,M_VALUE_CELL
				,MKT_FCST_M_CELL
				,CREATED_BY
				,CREATION_DATE
				,LAST_UPDATED_BY
				,LAST_UPDATE_DATE
				,CP_VALUE
				,CP_VALUE_CELL
				)
				SELECT T1.DIVISION_ID
					,T1.END_CUSTOMER
					,T1.PROJECT_CODE
					,T1.YYYYMM
					,0 AS CUST_FCST_M
					,T1.MEASURE
					,0 AS P_VALUE
					,0 AS S_VALUE
					,0 AS I_VALUE
					,0 AS V_VALUE
					,0 AS M_VALUE
					,0 AS MKT_FCST_M
					,0 AS CUST_FCST_M_CELL
					,0 AS P_VALUE_CELL
					,0 AS S_VALUE_CELL
					,0 AS I_VALUE_CELL
					,0 AS V_VALUE_CELL
					,0 AS M_VALUE_CELL
					,0 AS MKT_FCST_M_CELL
					,'BATCH SYSTEM' AS CREATED_BY
					,SYSDATETIME() AS CREATION_DATE
					,'BATCH SYSTEM' AS LAST_UPDATED_BY
					,SYSDATETIME() AS LAST_UPDATE_DATE
					,0 AS CP_VALUE
					,0 AS CP_VALUE_CELL
				FROM #TEMP_DATA T1 			
		END

		
	
         PRINT ( 'A3-- PROJECT TRANSLATOR ' + CONVERT(NVARCHAR(30), GETDATE(), 121))

		/*	
		   환산자 추출
		*/
	 
		BEGIN
		
        	-- 테이블중복제거
        	IF OBJECT_ID (N'tempdb..#TMP_PROJECT_TRANSLATOR', N'U')			IS NOT NULL	DROP TABLE #TMP_PROJECT_TRANSLATOR

        	-- 임시확인용테이블 중복제거
        	IF OBJECT_ID (N'dbo.#TMP_PROJECT_TRANSLATOR', N'U')				IS NOT NULL	DROP TABLE #TMP_PROJECT_TRANSLATOR

			--SELECT AAAA.PROJECT_CODE, AAAA.ITEM_ID, AAAA.BIZ_TYPE FROM(
			SELECT AAAA.DIVISION_ID
				 , AAAA.PROJECT_CODE
				 , AAAA.ITEM_ID 
				 , AAAA.BIZ_TYPE 
				 , BBBB.CELL_CF AS TRANSLATOR
			  INTO #TMP_PROJECT_TRANSLATOR
			  FROM (
		            SELECT AAA.DIVISION_ID
					     , AAA.PROJECT_CODE
					     , AAA.ITEM_ID
			             , CASE WHEN SUBSTRING(AAA.ITEM_ID, 1,2) = 'AP' THEN 'PACK' 
						        WHEN SUBSTRING(AAA.ITEM_ID, 1,2) = 'AM' THEN 'MODULE' 
								WHEN SUBSTRING(AAA.ITEM_ID, 1,2) = 'AC' THEN 'CELL' 
						   END BIZ_TYPE
			            ,  ROW_NUMBER() OVER (PARTITION BY AAA.DIVISION_ID,AAA.PROJECT_CODE ORDER BY AAA.DIVISION_ID,AAA.PROJECT_CODE, SUBSTRING(AAA.ITEM_ID, 2,1) DESC) AS RNK 
					FROM (
		          	      SELECT AA.DIVISION_ID
						       , AA.PROJECT_CODE
						       , BB.ITEM_ID 
						   FROM
			                    (SELECT DISTINCT DIVISION_ID,PROJECT_CODE 
								   FROM DM_ANL_MKT_PSI_DETAIL WITH (NOLOCK)  
							    ) AA INNER JOIN 
			                    (SELECT A.DIVISION_ID, A.PROJECT_CODE, A.ITEM_ID
			                       FROM SCM_MST_SITE_ITEM A  WITH (NOLOCK)  INNER JOIN 
								        DM_MST_ITEM_SINGLE_V B   WITH (NOLOCK)
										ON A.DIVISION_ID = B.DIVISION_ID 
									   AND A.ITEM_ID = B.ITEM_ID 
			                      WHERE A.DIVISION_ID  LIKE '81%'	 
								    AND A.VALID_YN = 'Y' 
									AND B.ITEM_TYPE = 'P'
			                      GROUP BY A.DIVISION_ID, A.PROJECT_CODE, A.ITEM_ID
							   ) BB 
			                   ON AA.DIVISION_ID  = BB.DIVISION_ID
			                  AND AA.PROJECT_CODE = BB.PROJECT_CODE
			            ) AAA 
			   ) AAAA  INNER JOIN  
			   SCP_MST_FINAL_ITEM BBBB  WITH (NOLOCK)
			   ON AAAA.ITEM_ID = BBBB.ITEM_ID	
			  AND AAAA.DIVISION_ID = BBBB.DIVISION_ID	
			 WHERE AAAA.RNK = 1 
		END
		 
		
         PRINT ( 'A4-- DM_ANL_MKT_PSI UPDATE(DM_ANL_MKT_PSI_DETAIL SUM) ' + CONVERT(NVARCHAR(30), GETDATE(), 121))
		
		/*	
		   DM_ANL_MKT_PSI_DETAIL 입력값 반영
		*/
	
		BEGIN
			UPDATE T1
			SET P_VALUE = T2.P_VALUE
			  , S_VALUE = T2.S_VALUE
			  , I_VALUE = T2.I_VALUE
			  , V_VALUE = T2.V_VALUE
			  , M_VALUE = T2.M_VALUE
			  , CP_VALUE = T2.CP_VALUE
			  , P_VALUE_CELL = T2.P_VALUE_CELL
			  , S_VALUE_CELL = T2.S_VALUE_CELL
			  , I_VALUE_CELL = T2.I_VALUE_CELL
			  , V_VALUE_CELL = T2.V_VALUE_CELL
			  , M_VALUE_CELL = T2.M_VALUE_CELL
			  , CP_VALUE_CELL = T2.CP_VALUE_CELL 
			  , MKT_FCST_M    = T2.MKT_FCST_M
			  , CUST_FCST_M    = T2.CUST_FCST_M
			  , LAST_UPDATED_BY  = 'BATCH SYSTEM'
			  , LAST_UPDATE_DATE = SYSDATETIME()
			FROM [dbo].[DM_ANL_MKT_PSI] T1
			JOIN 
				 (	
					SELECT T1.DIVISION_ID
						,T1.END_CUSTOMER
						,T1.PROJECT_CODE
						,T1.YYYYMM
						,T1.CUST_FCST_M
						,T1.MEASURE
						,ISNULL(CEILING(T1.P_VALUE), 0) AS P_VALUE
						,ISNULL(CEILING(T1.S_VALUE), 0) AS S_VALUE
						,ISNULL(CEILING(T1.I_VALUE), 0) AS I_VALUE
						,ISNULL(CEILING(T1.V_VALUE), 0) AS V_VALUE
						,ISNULL(CEILING(T1.M_VALUE), 0) AS M_VALUE 
						, CASE WHEN T1.MEASURE = 'DP_RESULT' 
							   THEN ISNULL(CEILING(T1.MKT_FCST_M), 0)
							   ELSE ISNULL(CEILING(T1.CUST_FCST_M - (CEILING(T1.P_VALUE) + CEILING(T1.S_VALUE) + CEILING(T1.I_VALUE) + CEILING(T1.V_VALUE) + CEILING(T1.M_VALUE) + CEILING(T1.CP_VALUE))), 0) 
						  END  AS  MKT_FCST_M 
						,T1.CUST_FCST_M * ISNULL(T2.TRANSLATOR,0) AS CUST_FCST_M_CELL
						,ISNULL(CEILING(T1.P_VALUE * ISNULL(T2.TRANSLATOR,0)), 0) AS P_VALUE_CELL
						,ISNULL(CEILING(T1.S_VALUE * ISNULL(T2.TRANSLATOR,0)), 0) AS S_VALUE_CELL
						,ISNULL(CEILING(T1.I_VALUE * ISNULL(T2.TRANSLATOR,0)), 0) AS I_VALUE_CELL
						,ISNULL(CEILING(T1.V_VALUE * ISNULL(T2.TRANSLATOR,0)), 0) AS V_VALUE_CELL
						,ISNULL(CEILING(T1.M_VALUE * ISNULL(T2.TRANSLATOR,0)), 0) AS M_VALUE_CELL
						, CASE WHEN T1.MEASURE = 'DP_RESULT' 
							   THEN ISNULL(CEILING(T1.MKT_FCST_M * ISNULL(T2.TRANSLATOR,0)), 0)
							   ELSE ISNULL(CEILING(CEILING(T1.CUST_FCST_M - (CEILING(T1.P_VALUE) + CEILING(T1.S_VALUE) + CEILING(T1.I_VALUE) + CEILING(T1.V_VALUE) + CEILING(T1.M_VALUE) + CEILING(T1.CP_VALUE))) * ISNULL(T2.TRANSLATOR,0)), 0)
						  END  AS  MKT_FCST_M_CELL 
						,ISNULL(CEILING(T1.CP_VALUE), 0)  AS CP_VALUE
						,ISNULL(CEILING(T1.CP_VALUE * ISNULL(T2.TRANSLATOR,0)), 0) AS CP_VALUE_CELL
					FROM (
						SELECT DIVISION_ID
							,END_CUSTOMER
							,PROJECT_CODE
							,YYYYMM
							,CUST_FCST_M
							,MEASURE
							,MKT_FCST_M
							,ISNULL(SUM([PRODUCT]),0) AS P_VALUE
							,ISNULL(SUM([SALES]),0) AS S_VALUE
							,ISNULL(SUM([INVENTORY]),0) AS I_VALUE
							,ISNULL(SUM([VPA]),0) AS V_VALUE
							,ISNULL(SUM([MODELMIX]),0) AS M_VALUE
							,ISNULL(SUM([SUPPLYISSUE]),0) AS CP_VALUE  
						FROM DM_ANL_MKT_PSI_DETAIL WITH (NOLOCK)
						PIVOT(SUM(QTY) FOR QTYCD3 IN (
									[PRODUCT]
									,[SALES]
									,[INVENTORY]
									,[VPA]
									,[MODELMIX]
									,[SUPPLYISSUE]
									)) AS PVT
						WHERE 1 = 1 
						  AND YYYYMM >= CONVERT(CHAR(6), @v_from_yyyymmdd, 112) 
						GROUP BY DIVISION_ID
							,END_CUSTOMER
							,PROJECT_CODE
							,YYYYMM
							,CUST_FCST_M
							,MEASURE
							,MKT_FCST_M
						) T1 
						INNER JOIN 
						#TMP_PROJECT_TRANSLATOR T2
					   ON T2.DIVISION_ID = T1.DIVISION_ID
					  AND T2.PROJECT_CODE = T1.PROJECT_CODE
			  )  T2
			 ON T2.DIVISION_ID = T1.DIVISION_ID
			AND T2.PROJECT_CODE = T1.PROJECT_CODE
			AND T2.END_CUSTOMER = T1.END_CUSTOMER
			AND T2.YYYYMM = T1.YYYYMM 
			AND T2.MEASURE = T1.MEASURE
			AND (T1.P_VALUE + T1.S_VALUE + T1.I_VALUE +  T1.V_VALUE + T1.M_VALUE + T1.CP_VALUE) = 0  
			AND (T1.P_VALUE + T1.S_VALUE + T1.I_VALUE +  T1.V_VALUE + T1.M_VALUE + T1.CP_VALUE) <> (T2.P_VALUE + T2.S_VALUE + T2.I_VALUE +  T2.V_VALUE + T2.M_VALUE + T2.CP_VALUE)

		END
	 

         PRINT ( 'A5--DP_RESULT(Demand Plan (final)) ' + CONVERT(NVARCHAR(30), GETDATE(), 121))
	
		/*	
		   DP_RESULT(Demand Plan (final)) ⓓMKT.FCST (DP) 에 MKTFCST 화면에 월 MKT FCST[R+P] Measure실적과 동일하게 관리
		*/
		BEGIN
	
			--SCM_MST_SITE 대상건만 추출
			BEGIN
        		-- 테이블중복제거
        		IF OBJECT_ID (N'tempdb..#TEMP_SCM_MST_SITE', N'U')			IS NOT NULL	DROP TABLE #TEMP_SCM_MST_SITE

        		-- 임시확인용테이블 중복제거
        		IF OBJECT_ID (N'dbo.#TEMP_SCM_MST_SITE', N'U')				IS NOT NULL	DROP TABLE #TEMP_SCM_MST_SITE

				SELECT DIVISION_ID
					 , SCM_SITE_ID
					 , END_CUSTOMER
				INTO #TEMP_SCM_MST_SITE
				FROM SCM_MST_SITE WITH (NOLOCK)
				WHERE DIVISION_ID  LIKE '81%'	 
			END 

			
			UPDATE T1
			SET MKT_FCST_M = T2.A_QTY
			  , LAST_UPDATED_BY  = 'BATCH SYSTEM'
			  , LAST_UPDATE_DATE = SYSDATETIME()
			FROM [dbo].[DM_ANL_MKT_PSI] T1
			JOIN 
				(SELECT X.DIVISION_ID
					  , H.END_CUSTOMER
					  , X.PROJECT_CODE
					  , SUBSTRING(X.YYYYMMDD, 1, 6) AS YYYYMM
					  , ISNULL(CEILING(SUM(X.QTY)), 0) AS A_QTY
				   FROM DM_PLN_MKT_FCST_RESULT X WITH (NOLOCK) 			   
				   JOIN SCM_MST_SITE_ITEM F WITH(NOLOCK) 
						ON	F.DIVISION_ID    = X.DIVISION_ID
					   AND	F.PROJECT_CODE   = X.PROJECT_CODE
					   AND	F.SCM_SITE_ID    = X.SCM_SITE_ID
