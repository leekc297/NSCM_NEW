CREATE PROCEDURE [dbo].[SSP0026_GET_REQUEST_DETAIL_PACK_EXCEL_DOWN]
	 @P_DIVISION_ID			VARCHAR(10)
	,@P_FROM_YYYYMMDD		NVARCHAR(8)
	,@P_TO_YYYYMMDD			NVARCHAR(8)
	,@P_PLANT_SITE_ID		NVARCHAR(MAX)
	,@P_SCM_SITE_ID			NVARCHAR(MAX)
	,@P_LOT_ID				NVARCHAR(MAX)
	,@P_ITEM_ID				NVARCHAR(MAX)
	,@P_NICK_NAME			NVARCHAR(MAX)
	,@P_USER_ID				NVARCHAR(MAX)
	,@P_REQUESTOR_ID		NVARCHAR(MAX)
	,@P_PROGRAM_ID			NVARCHAR(MAX) = 'SSP0026' 
	,@P_SHEET_NAME			NVARCHAR(MAX) = 'Shipment Request Detail Excel'
AS
BEGIN
	SET NOCOUNT ON; 
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;

-- NERP 매핑코드
    DECLARE @v_C100 NVARCHAR(10);
	SET @v_C100 = dbo.FN_GET_LOOKUP_VALUE('SSP0026_GET_REQUEST_DETAIL_PACK_EXCEL_DOWN'  ,'ESOC' );	--C100

	
	SELECT * FROM (
	SELECT 
     A.DIVISION_ID		     AS DIVISION_ID
     , A.FROM_SITE			 AS FROM_SITE
     , A.TO_SITE			 AS TO_SITE
	 , A.SHIPTO_CODE		 AS SHIPTO_CODE
     , A.ITEM_ID             AS ITEM_ID
	 , A.YYYYMMDD            AS YYYYMMDD
	 , ISNULL(B.QTY, 0)      AS Qty
	 , C.TRANSPORT_MODE      AS TRANSPORT_MODE
	 -- 20201223 incoterms 변경 작업 modify KIMYONGHO
	 , C.SSP_INCOTERMS       AS INCOTERMS
	 , C.BOD_ID
	 , B.FCST_TYPE			 AS FCST_TYPE
--	 , B.ORDER_TYPE_DETAIL   AS ORDER_TYPE_DETAIL
	 , CASE WHEN convert(varchar(8), GETDATE() + TD.SHIP_FROZEN, 112)  <  CONVERT(VARCHAR(10),   CONVERT(DATETIME, A.YYYYMMDD,112), 23) THEN 'Y' ELSE 'N' END AS EDIT_FLAG
	FROM   (
			SELECT  B.DIVISION_ID	
				 , C.FROM_SITE
				 , C.TO_SITE
				 , C.BOD_ID
				 , B.SHIPTO_CODE
				 , B.ITEM_ID

				 , A.YYYYMMDD		
			FROM   SSP_MST_SHIP_CALENDAR   A WITH(NOLOCK)
			
			JOIN [DBO].[SSP_ANL_SHIP_REQ_P] B WITH(NOLOCK)
				ON B.DIVISION_ID = @P_DIVISION_ID
				AND  A.DIVISION_ID = @P_DIVISION_ID
				AND  A.COMPANY_ID = @v_C100				--'C100'	
				AND ((@P_ITEM_ID   IS NULL OR @P_ITEM_ID ='' )	    OR B.ITEM_ID IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_ITEM_ID, ','))) 

			JOIN SCP_MST_BOD_N_V  C WITH(NOLOCK)
				ON   C.DIVISION_ID		   = B.DIVISION_ID                        
				AND  C.BOD_ID			   = B.BOD_ID
				AND  C.DIVISION_ID		   = @P_DIVISION_ID
				AND  C.BOD_TYPE			   = 'SALES'
				AND ((@P_PLANT_SITE_ID   IS NULL OR @P_PLANT_SITE_ID ='' )   OR C.FROM_SITE IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_PLANT_SITE_ID, ','))) 
				AND ((@P_SCM_SITE_ID   IS NULL OR @P_SCM_SITE_ID ='' )	    OR C.TO_SITE IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_SCM_SITE_ID, ','))) 
	   
			WHERE  1 = 1
			AND    A.DIVISION_ID = @P_DIVISION_ID
			AND    A.YYYYMMDD   >= @P_FROM_YYYYMMDD
			AND    A.YYYYMMDD   < = @P_TO_YYYYMMDD
			GROUP BY  B.DIVISION_ID	
				 , C.FROM_SITE
				 , C.TO_SITE
				 , C.BOD_ID
				 , B.SHIPTO_CODE
				 , B.ITEM_ID
				 , A.YYYYMMDD		
		   ) A

		   LEFT OUTER JOIN [DBO].[SSP_ANL_SHIP_REQ_P] B WITH(NOLOCK)
		   ON   B.DIVISION_ID = @P_DIVISION_ID
		   --AND  B.FROM_SITE   = @P_PLANT_SITE_ID
		   --AND  B.TO_SITE	  = @P_SCM_SITE_ID
		    AND ((@P_PLANT_SITE_ID   IS NULL OR @P_PLANT_SITE_ID ='' )  OR A.FROM_SITE IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_PLANT_SITE_ID, ','))) 
			AND ((@P_SCM_SITE_ID   IS NULL OR @P_SCM_SITE_ID ='' )	    OR A.TO_SITE IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_SCM_SITE_ID, ',')))    
			AND ((@P_ITEM_ID   IS NULL OR @P_ITEM_ID ='' )				OR B.ITEM_ID IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_ITEM_ID, ','))) 
			AND  A.DIVISION_ID	    = B.DIVISION_ID
			--AND  A.FROM_SITE        = C.FROM_SITE
			--AND  A.TO_SITE          = C.TO_SITE
			AND  A.SHIPTO_CODE	    = B.SHIPTO_CODE
			AND  A.ITEM_ID          = B.ITEM_ID
			AND  A.YYYYMMDD         = B.YYYYMMDD

		   LEFT OUTER JOIN SCP_MST_BOD_N_V C  WITH(NOLOCK)
		   ON   C.DIVISION_ID = A.DIVISION_ID
		   AND  C.BOD_ID      = A.BOD_ID
		   AND  C.FROM_SITE   = A.FROM_SITE
		   AND  C.TO_SITE     = A.TO_SITE

		   LEFT OUTER JOIN SCM_MST_SITE TD WITH(NOLOCK)	
		   ON A.DIVISION_ID	= TD.DIVISION_ID	
		   AND C.FROM_SITE	= TD.SCM_SITE_ID		
	WHERE  1 = 1
	) T
	WHERE T.EDIT_FLAG <> 'N'
	AND  T.QTY > 0
	ORDER BY T.ITEM_ID,T.FROM_SITE,T.TO_SITE,T.SHIPTO_CODE, T.YYYYMMDD
END

