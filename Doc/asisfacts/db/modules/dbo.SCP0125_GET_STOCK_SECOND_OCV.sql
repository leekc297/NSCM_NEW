CREATE PROCEDURE [dbo].[SCP0125_GET_STOCK_SECOND_OCV]
	@p_division_id				NVARCHAR(50)
	, @p_plan_start_yyyymmdd	NVARCHAR(8)
	, @p_version_no				NVARCHAR(50)
	, @p_nick_name				NVARCHAR(200)
	, @p_item_id				NVARCHAR(200)

AS
BEGIN
	
    SET NOCOUNT ON; 
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED


	IF OBJECT_ID('TEMPDB..#OCV_EXCEPT_LIST') IS NOT NULL
	BEGIN 
		DROP TABLE  #OCV_EXCEPT_LIST;
	END;

	IF OBJECT_ID('TEMPDB..#NICK_NAME_LIST') IS NOT NULL
	BEGIN 
		DROP TABLE  #NICK_NAME_LIST;
	END;

	SELECT DIVISION_ID, ITEM_ID, MAX(NICK_NAME) AS NICK_NAME
	INTO #NICK_NAME_LIST
	  FROM SCM_MST_ITEM_SN WITH(NOLOCK)
	 WHERE 1=1
	   AND DIVISION_ID = @p_division_id
	   AND ISNULL(NICK_NAME, '') <> ''
	 GROUP BY  DIVISION_ID, ITEM_ID

			
	SELECT BOM.DIVISION_ID
		 , MS.SCM_SITE_ID
		 , MS.PLANT_ID
         , CHILD_ITEM_ID AS ITEM_ID
	  INTO #OCV_EXCEPT_LIST
      FROM SCM_MST_BOM_SN_V BOM WITH(NOLOCK)
     INNER JOIN SCM_MST_SITE MS WITH(NOLOCK)
        ON BOM.PLANT_ID = MS.PLANT_ID
     INNER JOIN SCP_OPMZ_LOOKUP_MASTER_DETAIL LU WITH(NOLOCK)
        ON  LU.LOOKUP_TYPE = 'SCP_OPT_ENG_CONST_SECOND_OCV_MASTER'
       AND LU.VALID_YN    = 'Y'
       AND LU.SEGMENT2    = @p_division_id
       AND LU.ATTRIBUTE1  = 'B'
     WHERE   1=1
	   AND MS.SCM_SITE_ID		= LU.SEGMENT4
       AND BOM.PARENT_ITEM_ID	= LU.SEGMENT5
     GROUP BY MS.SCM_SITE_ID, CHILD_ITEM_ID, MS.PLANT_ID, BOM.DIVISION_ID


	SELECT a.*
		 , b.CHG_QTY
		 , b.CHG_RSN
		 , b.CHG_TYPE
		 , ISNULL(b.LAST_UPDATED_BY, '') AS LAST_UPDATED_BY
		 , ISNULL(b.LAST_UPDATE_DATE, NULL) AS LAST_UPDATE_DATE
		 , b.CHG_QTY AS PRE_CHG_QTY
		 , b.CHG_RSN AS PRE_CHG_RSN
	  FROM (
		   SELECT FI.DIVISION_ID
				, REPLACE(CONVERT(date, FI.CUTOFF_DATE, 112), '-', '')						AS CUTOFF_YYYYMMDD
				, CASE WHEN ISNULL(FI.WIPHOLD_YN, 'N') = 'N' THEN 'WH' ELSE 'WH_HOLD' END	AS STOCK_TYPE
				, d.SEGMENT2				AS STOCK_TYPE_NAME
				, c.NICK_NAME
				, FI.MES_ITEM_ID			AS ITEM_ID
				, FI.PLANT_ID
				, FI.MES_OPERATION_ID		AS OPERATION_ID
				, OP.OPERATION_NAME
				, CONVERT(NVARCHAR, FI.SECOND_OCV_TIME) AS SECOND_OCV_TIME
				, CONVERT(date, FI.SECOND_OCV_EXP_DATE, 112) AS SECOND_OCV_DATE
				, SUM(FI.QTY)				AS QTY
			 FROM SCM_DNM_STOCK_SN FI WITH(NOLOCK)
			INNER JOIN #OCV_EXCEPT_LIST OE WITH(NOLOCK) ON OE.DIVISION_ID = FI.DIVISION_ID AND OE.PLANT_ID = FI.PLANT_ID AND OE.ITEM_ID = FI.MES_ITEM_ID
			 LEFT JOIN SCM_MST_MMD_OPERATION_SN OP ON OP.OPERATION_ID = FI.MES_OPERATION_ID --OP.DIVISION_ID = FI.DIVISION_ID AND
			 LEFT JOIN #NICK_NAME_LIST c ON c.DIVISION_ID = FI.DIVISION_ID AND c.ITEM_ID = FI.MES_ITEM_ID
			 LEFT JOIN SCM_ADM_LOOKUP_MASTER_DETAIL d WITH(NOLOCK) ON LOOKUP_TYPE = 'STOCK_TYPE' AND d.SEGMENT1 = CASE WHEN ISNULL(FI.WIPHOLD_YN, 'N') = 'N' THEN 'WH' ELSE 'WH_HOLD' END
			WHERE 1=1
			  AND FI.DIVISION_ID = @p_division_id
			  AND REPLACE(CONVERT(date, FI.CUTOFF_DATE, 112), '-', '') = @p_plan_start_yyyymmdd
			  AND FI.MES_ITEM_ID IS NOT NULL
			GROUP BY FI.DIVISION_ID, FI.CUTOFF_DATE, FI.WIPHOLD_YN, FI.STOCK_TYPE, FI.MES_ITEM_ID, FI.PLANT_ID, FI.MES_OPERATION_ID, OP.OPERATION_NAME
				   , FI.SECOND_OCV_TIME, FI.SECOND_OCV_EXP_DATE, d.SEGMENT2, c.NICK_NAME
		 ) a
	  LEFT JOIN SCP_OPMZ_INV_SECOND_OCV b WITH(NOLOCK)
		ON b.DIVISION_ID = @p_division_id AND b.CUTOFF_YYYYMMDD = @p_plan_start_yyyymmdd
	   AND a.STOCK_TYPE = b.STOCK_TYPE AND a.ITEM_ID = b.ITEM_ID AND a.PLANT_ID = b.PLANT_ID AND a.OPERATION_ID = b.OPERATION_ID
	   AND ISNULL(b.SECOND_OCV_TIME, '') = ISNULL(a.SECOND_OCV_TIME, '') AND REPLACE(a.SECOND_OCV_DATE, '-', '') = b.SECOND_OCV_DATE
	 WHERE 1=1
	   AND ( ( @p_item_id IS NULL OR  @p_item_id = '' ) OR a.ITEM_ID LIKE '%' + @p_item_id + '%' ) 
	   AND ( ( @p_nick_name IS NULL OR  @p_nick_name = '' ) OR a.NICK_NAME LIKE '%' + @p_nick_name + '%' ) 

	--Insert 된 정보
	UNION ALL
	SELECT a.DIVISION_ID
		 , a.CUTOFF_YYYYMMDD
		 , a.STOCK_TYPE
		 , d.SEGMENT2				AS STOCK_TYPE_NAME
		 , c.NICK_NAME
		 , a.ITEM_ID
		 , a.PLANT_ID
		 , a.OPERATION_ID
		 , OP.OPERATION_NAME
		 , a.SECOND_OCV_TIME
		 , CONVERT(date, CASE WHEN SECOND_OCV_DATE = '' THEN NULL ELSE a.SECOND_OCV_DATE END, 112) AS SECOND_OCV_DATE
		 , a.QTY
		 , a.CHG_QTY
		 , a.CHG_RSN
		 , a.CHG_TYPE
		 , ISNULL(a.LAST_UPDATED_BY, '') AS LAST_UPDATED_BY
		 , ISNULL(a.LAST_UPDATE_DATE, NULL) AS LAST_UPDATE_DATE
		 , a.CHG_QTY AS PRE_CHG_QTY
		 , a.CHG_RSN AS PRE_CHG_RSN
	  FROM SCP_OPMZ_INV_SECOND_OCV a WITH(NOLOCK)
	 INNER JOIN #OCV_EXCEPT_LIST OE WITH(NOLOCK) ON OE.DIVISION_ID = a.DIVISION_ID AND OE.PLANT_ID = a.PLANT_ID AND OE.ITEM_ID = a.ITEM_ID
	  LEFT JOIN SCM_MST_MMD_OPERATION_SN OP WITH(NOLOCK) ON OP.OPERATION_ID = a.OPERATION_ID
	  LEFT JOIN #NICK_NAME_LIST c WITH(NOLOCK) ON c.DIVISION_ID = a.DIVISION_ID AND c.ITEM_ID = a.ITEM_ID
	  LEFT JOIN SCM_ADM_LOOKUP_MASTER_DETAIL d WITH(NOLOCK) ON LOOKUP_TYPE = 'STOCK_TYPE' AND d.SEGMENT1 = a.STOCK_TYPE
	 WHERE 1=1
	   AND a.CHG_TYPE = 'New'
	   AND a.DIVISION_ID = @p_division_id
	   AND a.CUTOFF_YYYYMMDD = @p_plan_start_yyyymmdd
	   AND ( ( @p_item_id IS NULL OR  @p_item_id = '' ) OR a.ITEM_ID LIKE '%' + @p_item_id + '%' ) 
	   AND ( ( @p_nick_name IS NULL OR  @p_nick_name = '' ) OR c.NICK_NAME LIKE '%' + @p_nick_name + '%' ) 
	 ORDER BY ITEM_ID, STOCK_TYPE, STOCK_TYPE_NAME, PLANT_ID, OPERATION_ID, SECOND_OCV_TIME, SECOND_OCV_DATE

  
END

