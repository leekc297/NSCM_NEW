							, @P_TO_YYYYMMDD = '20200805', @P_MODEL_ID = '', @P_ITEM_ID = 'APCAN0023A', @P_NICK_NAME = '', @P_USER_ID = 'khj79'
							, @P_PROGRAM_ID = 'SSP0023', @P_SHEET_NAME	= 'Shipment Plan(Electrode)', @P_REAL_FLAG = 'Y'
							, @P_NON_CHK ='Y', @P_MY_MODEL_CHK='N', @P_DELEGATEE_CHK = 'N', @P_PART_LEADER_CHK='N', @P_TEAM_LEADER_CHK='N'
 */

CREATE PROCEDURE [dbo].[SSP0023_GET_SHIPMENT_PLAN_NEW]
	 @P_DIVISION_ID			VARCHAR(30)
	,@P_COMPANY_ID			NVARCHAR(30)
	,@P_FROM_SITE			NVARCHAR(MAX)
	,@P_PLAN_START_YYYYMMDD	NVARCHAR(8)
	,@P_FROM_YYYYMMDD		NVARCHAR(8)
	,@P_TO_YYYYMMDD			NVARCHAR(8)
	,@P_MODEL_ID			NVARCHAR(MAX)
	,@P_ITEM_ID				NVARCHAR(MAX)
	,@P_NICK_NAME			NVARCHAR(MAX)
	,@P_USER_ID				NVARCHAR(MAX)
	,@P_PROGRAM_ID			NVARCHAR(MAX) = 'SSP0023'
	,@P_SHEET_NAME			NVARCHAR(MAX) = 'Shipment Plan(Electrode)'
	,@P_REAL_FLAG			CHAR(1)
	,@P_NON_CHK				CHAR(1)
	,@P_MY_MODEL_CHK		CHAR(1)
	,@P_DELEGATEE_CHK		CHAR(1)
	,@P_PART_LEADER_CHK		CHAR(1)
	,@P_TEAM_LEADER_CHK		CHAR(1)
AS  
  
BEGIN
	SET NOCOUNT ON; 
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;
	
	DECLARE @V_FROM_YYYYMMDD	NVARCHAR(8);
	DECLARE @V_TO_YYYYMMDD		NVARCHAR(8);

	DECLARE @MQRY_SUM			NVARCHAR(MAX);
	DECLARE @MEXEC				NVARCHAR(MAX);
	DECLARE @MDAY_QTY			NVARCHAR(MAX);

	DECLARE @P_STOCK_YYYYMMDD	NVARCHAR(8);

	DECLARE @V_SEQ				INT;

	SET @V_FROM_YYYYMMDD		= @P_FROM_YYYYMMDD;
	SET @V_TO_YYYYMMDD			= @P_TO_YYYYMMDD;

	DECLARE @V_CNT_USR_MEASURE	INT =0;

	SET @V_CNT_USR_MEASURE = (
							SELECT COUNT(*) 
							FROM SCM_MST_TITLESET_USER WITH(NOLOCK)
							WHERE 1=1
							AND PROGRAM_ID  =  @P_PROGRAM_ID
							AND SHEET_NAME  =  @P_SHEET_NAME 
							AND USER_ID     =  @P_USER_ID
						)

	/*-------------------------------------------------------------------------------------------------------------
	--------------------------------------------------------------------------------------------------------------*/ 
	-- Cutoff 용 이전 version  
	---------------------------------------------------------------------------------------------------------------------------

	DECLARE @v_frozen_yyyymmdd NVARCHAR(8) = '';

	-- 계획 구간 Start End 일자 (plan_start_yyyymmdd-1 ~ 8주)
	DECLARE @v_plan_end_yyyymmdd   NVARCHAR(8) = '';


	SET    @v_frozen_yyyymmdd   =  CONVERT(char(8), DATEADD(DD, -1, CONVERT(DATETIME, @P_PLAN_START_YYYYMMDD ,112)), 112) 
	SET    @v_plan_end_yyyymmdd =  CONVERT(VARCHAR, DATEADD( D, 56, CONVERT(DATETIME, @P_PLAN_START_YYYYMMDD ,112)) ,112) ; 
	---------------------------------------------------------------------------------------------------------------------------

	---------------------------------------------------------------------------------------------------------------------------
	-- 실적구간 Start End 일자 (plan_start_yyyymmdd-1의 전주월요일  ~ 계획구간 start일자-1) 
	DECLARE @v_result_start_yyyymmdd NVARCHAR(8) = '';
	DECLARE @v_result_end_yyyymmdd   NVARCHAR(8) = '';

	-- plan_start_yyyymmdd-1의 전주월요일
	SELECT @v_result_start_yyyymmdd  = C.BASIS_YYYYMMDD
	FROM   SCM_SYS_CALENDAR_M C WITH(NOLOCK) 
	WHERE  C.ISO_YYYYWW = ( 
					SELECT MIN(ISO_YYYYWW)  AS ISO_YYYYWW
					FROM SCM_SYS_CALENDAR_M  WITH(NOLOCK) 
					WHERE BASIS_YYYYMMDD >= CONVERT(VARCHAR, DATEADD(D, -7, CONVERT(DATETIME, @P_PLAN_START_YYYYMMDD ,112)) ,112) 
					AND   BASIS_YYYYMMDD <=  @P_PLAN_START_YYYYMMDD
					)
	AND  C.DAYOFWEEK = 'MON'
	;

	SET     @v_result_end_yyyymmdd   = CONVERT(VARCHAR, DATEADD(D, -1, CONVERT(DATETIME, @P_PLAN_START_YYYYMMDD ,112)) ,112) ;
	---------------------------------------------------------------------------------------------------------------------------

	/********************************************************************************
	* 임시테이블만들기
	********************************************************************************/

	-- 사용자 MEASURE 설정 정보
	IF OBJECT_ID('TEMPDB..#TBLDYNAMICTITLEST_SSP0023') IS NOT NULL
		DROP TABLE #TBLDYNAMICTITLEST_SSP0023;

	SELECT * INTO #TBLDYNAMICTITLEST_SSP0023
	  FROM SCM_MST_TITLESET_USER WITH(NOLOCK)
	 WHERE PROGRAM_ID	= @P_PROGRAM_ID
	   AND SHEET_NAME	= @P_SHEET_NAME
	   AND USER_ID		= @P_USER_ID;

	-- SHIPMENT ROW DATA(현재기준)
	IF OBJECT_ID('TEMPDB..#TMP_SSP0023_ROWDATA') IS NOT NULL
		DROP TABLE #TMP_SSP0023_ROWDATA;

	-- SHIPMENT ROW DATA(과거기준)
	IF OBJECT_ID('TEMPDB..#TMP_SSP0023_ROWDATA_OLD') IS NOT NULL
		DROP TABLE #TMP_SSP0023_ROWDATA_OLD;
	-- 결과 DATA(현재기준)
	
	IF OBJECT_ID('TEMPDB..#TMP_SSP0023_RESULT_TABLE') IS NOT NULL
		DROP TABLE #TMP_SSP0023_RESULT_TABLE;

	-- 결과 DATA(과거기준)
	IF OBJECT_ID('TEMPDB..#TMP_SSP0023_RESULT_TABLE_OLD') IS NOT NULL
		DROP TABLE #TMP_SSP0023_RESULT_TABLE_OLD;

	-- CUTOFF DATA
	IF OBJECT_ID('tempdb..#TMP_SSP0023_BOH_CUTOFF_EE') IS NOT NULL
		DROP TABLE #TMP_SSP0023_BOH_CUTOFF_EE

	SELECT T0.COMPANY_ID
		 , T0.DIVISION_ID
		 , T0.PLANT_ID
		 , T0.SCM_SITE_ID
		 , T0.MODEL_ID
		 , T0.ITEM_ID
		 , ISNULL(T0.TOT_BOH_QTY,0)			AS TOT_BOH_QTY
		 , ISNULL(T0.JR_BOH_QTY,0)			AS JR_BOH_QTY
		 , ISNULL(T0.PC_BOH_QTY,0)			AS PC_BOH_QTY
		 , ISNULL(T0.TOT_BOH_QTY_TO_PCM,0 )	AS TOT_BOH_QTY_PCM
		 , ISNULL(T0.JR_BOH_QTY_TO_PCM,0)	AS JR_BOH_QTY_PCM
		 , ISNULL(T0.PC_BOH_QTY_TO_PCM,0)	AS PC_BOH_QTY_PCM
		 , ISNULL(T0.TOT_BOH_QTY_TO_CELL,0)	AS TOT_BOH_QTY_CELL
		 , ISNULL(T0.JR_BOH_QTY_TO_CELL,0)	AS JR_BOH_QTY_CELL
		 , ISNULL(T0.PC_BOH_QTY_TO_CELL,0)	AS PC_BOH_QTY_CELL
		 , CUTOFF_DATE
	   INTO #TMP_SSP0023_BOH_CUTOFF_EE
	   FROM SSP_ANL_BOH_CUTOFF_EE T0 WITH(NOLOCK)
	  WHERE 1=1
		AND T0.MEASURE_TYPE = 'P'
		AND T0.CUTOFF_DATE = @P_PLAN_START_YYYYMMDD
		AND T0.DIVISION_ID = @P_DIVISION_ID
		AND T0.COMPANY_ID  = @P_COMPANY_ID
		AND (( @P_ITEM_ID IS NULL  OR @P_ITEM_ID ='')  OR T0.ITEM_ID  IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_ITEM_ID , ',')))
		AND (( @P_MODEL_ID IS NULL OR @P_MODEL_ID ='') OR T0.MODEL_ID IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_MODEL_ID, ',')))
	;

	-- 조회 기준 데이터
	IF OBJECT_ID('TEMPDB..#TMP_PLAN_ITEM_CUTOFF') IS NOT NULL
		DROP TABLE #TMP_PLAN_ITEM_CUTOFF;

	SELECT DISTINCT
			T.COMPANY_ID
		  , T.DIVISION_ID
		  , T.PLANT_ID
		  , T.SCM_SITE_ID
		  , T.MODEL_ID
		  , T.ITEM_ID
	   INTO #TMP_PLAN_ITEM_CUTOFF
	  FROM SSP_ANL_SHIP_PLAN_EE T WITH(NOLOCK)
	  LEFT OUTER JOIN SSP_MST_MODEL_USER M WITH(NOLOCK)
		ON M.DIVISION_ID	= T.DIVISION_ID
	   AND M.FROM_SITE		= T.SCM_SITE_ID
	   AND M.ITEM_ID		= T.ITEM_ID
	   AND M.VALID_YN		= 'Y'
	
	 WHERE T.MEASURE_TYPE      = 'P'
	   AND PLAN_START_YYYYMMDD =  @P_PLAN_START_YYYYMMDD 
	   AND COMPANY_ID          =  @P_COMPANY_ID				
	   AND ((@P_NON_CHK = 'Y' AND 1 = 1 OR M.USER_ID IN (SELECT CASE WHEN @P_MY_MODEL_CHK = 'Y' THEN @P_USER_ID ELSE 'X' END
														 UNION
														SELECT CASE WHEN @P_DELEGATEE_CHK = 'Y' THEN USER_ID ELSE 'X' END
														  FROM SSP_MST_DELEGATE
														 WHERE VALID_YN = 'Y'
														   AND DELEGATEE_ID = @P_USER_ID 
														 GROUP BY USER_ID)
									OR M.PART_LEADER = CASE WHEN @P_PART_LEADER_CHK = 'Y' THEN @p_user_id  ELSE 'X' END
									OR M.TEAM_LEADER = CASE WHEN @P_TEAM_LEADER_CHK = 'Y' THEN @p_user_id  ELSE 'X' END))
	;
	

	IF @P_REAL_FLAG = 'Y'  -- 현재 기준 조회
	 
		BEGIN
			--////////////////////////////////////////////////////////////////////////////////--
			--//2. DATA ROW DATA															//--
			--////////////////////////////////////////////////////////////////////////////////--
		SELECT
			 TA1.DIVISION_ID
			,TA1.PLANT_ID
			,TA1.COMPANY_ID
			,TA1.SCM_SITE_ID
			,TA1.ELECTRODE_POST_OPER_LT
			,TA1.ELECTRODE_TYPE
			,TA1.MODEL_ID
			,TA1.ITEM_ID
			,TA1.FROM_SITE
			,TA1.BOD_ID
			,TA1.MEASURE
			,TA1.YYYYMMDD
			,TA1.SEQ
			,SUM(TA1.QTY) AS QTY
			,SUM(TA1.QTY_TO_PCM) AS QTY_TO_PCM
			,SUM(TA1.QTY_TO_CELL) AS QTY_TO_CELL
			,TA1.LAST_UPDATED_BY
		INTO #TMP_SSP0023_ROWDATA
		FROM 
		(	
			SELECT 
				 TA.DIVISION_ID				AS DIVISION_ID
				,TA.PLANT_ID				AS PLANT_ID
				,TA.COMPANY_ID				AS COMPANY_ID
				,TA.SCM_SITE_ID				AS SCM_SITE_ID
				,TA.ELECTRODE_POST_OPER_LT	AS ELECTRODE_POST_OPER_LT
				,TA.ELECTRODE_TYPE			AS ELECTRODE_TYPE
				,TA.MODEL_ID				AS MODEL_ID
				,TA.ITEM_ID					AS ITEM_ID
				,TA.FROM_SITE				AS FROM_SITE
				,TA.BOD_ID					AS BOD_ID
				,TA.MEASURE					AS MEASURE
				,TA.YYYYMMDD				AS YYYYMMDD
				,TA.SEQ						AS SEQ
				, ISNULL(TA.QTY, 0)			AS QTY
				, ISNULL(TA.QTY_TO_PCM, 0)	AS QTY_TO_PCM
				, ISNULL(TA.QTY_TO_CELL, 0)	AS QTY_TO_CELL
				,TA.LAST_UPDATED_BY			AS LAST_UPDATED_BY
				,TA.LAST_UPDATE_DATE		AS LAST_UPDATE_DATE
			FROM 
			(
				/* P_SHIP_REQ_ETD Measure 추가 */
				SELECT T.DIVISION_ID						AS DIVISION_ID
					 , T.PLANT_ID							AS PLANT_ID
					 , T.COMPANY_ID							AS COMPANY_ID
					 , T.SCM_SITE_ID						AS SCM_SITE_ID
					 , ISNULL(E.ELECTRODE_POST_OPER_LT,'-')	AS ELECTRODE_POST_OPER_LT
					 , ISNULL(E.ELECTRODE_TYPE,'-')			AS ELECTRODE_TYPE
					 , T.MODEL_ID							AS MODEL_ID
					 , R.ITEM_ID							AS ITEM_ID
					 , ISNULL(T.SCM_SITE_ID,'-')			AS FROM_SITE
					 , ISNULL(R.BOD_ID,'-')					AS BOD_ID
					 , 'P_SHIP_REQ_ETD'						AS MEASURE
					 , R.ETD_DATE							AS YYYYMMDD
					 , 3									AS SEQ
					 , R.QTY								AS QTY
					 , R.QTY_TO_PCM							AS QTY_TO_PCM
					 , R.QTY_TO_CELL						AS QTY_TO_CELL
					 , R.LAST_UPDATED_BY					AS LAST_UPDATED_BY
					 , R.LAST_UPDATE_DATE
				  FROM #TMP_PLAN_ITEM_CUTOFF T WITH(NOLOCK)

				  JOIN SSP_ANL_SHIP_REQ_EE R WITH(NOLOCK)
					ON R.FROM_DIVISION_ID = T.DIVISION_ID
				   AND R.FROM_SITE        = T.SCM_SITE_ID
				   AND R.ITEM_ID          = T.ITEM_ID
				
				  JOIN SSP_MST_SITE_ITEM_EE_V E WITH(NOLOCK)
					ON T.DIVISION_ID = E.DIVISION_ID
				   AND T.SCM_SITE_ID = E.SCM_SITE_ID
				   AND T.ITEM_ID = E.ITEM_ID

				 WHERE 1=1
				   AND E.DIVISION_ID	=  @P_DIVISION_ID
				   AND E.COMPANY_ID		=  @P_COMPANY_ID
				   AND R.ETD_DATE		>= @P_FROM_YYYYMMDD
				   AND R.ETD_DATE		<= @P_TO_YYYYMMDD
				   AND (( @P_FROM_SITE IS NULL OR @P_FROM_SITE = '') OR T.SCM_SITE_ID       IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_FROM_SITE, ',')))
				   AND (( @P_ITEM_ID   IS NULL OR @P_ITEM_ID   = '') OR T.ITEM_ID           IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_ITEM_ID  , ',')))
				   AND (( @P_MODEL_ID  IS NULL OR @P_MODEL_ID  = '') OR T.MODEL_ID          IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_MODEL_ID , ',')))
				   AND (( @P_NICK_NAME IS NULL OR @P_NICK_NAME = '') OR E.ITEM_ID_NICK_NAME IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_NICK_NAME, ',')))
		
			UNION ALL	

			/* C_SCP_PROD_PLAN,P_SCP_SHIP_PLAN_ETD,P_SHIP_PLAN_SIMU_ETD',C_FP_NPC_ASSY_PLAN,C_FP_COATER_PLAN Measure 추가 */
			SELECT T.DIVISION_ID
				,T.PLANT_ID								AS PLANT_ID
				,T.COMPANY_ID							AS COMPANY_ID
				,T.SCM_SITE_ID							AS SCM_SITE_ID
				,ISNULL(E.ELECTRODE_POST_OPER_LT,'-')	AS ELECTRODE_POST_OPER_LT
				,ISNULL(T.ELECTRODE_TYPE,'-')			AS ELECTRODE_TYPE
				,T.MODEL_ID								AS MODEL_ID
				,T.ITEM_ID								AS ITEM_ID
				,ISNULL(T.SCM_SITE_ID,'-')				AS FROM_SITE
				,ISNULL(T.BOD_ID,'-')					AS BOD_ID
				,T.MEASURE								AS MEASURE
				,T.YYYYMMDD								AS YYYYMMDD
				,CASE WHEN T.MEASURE = 'P_SCP_PROD_PLAN'		THEN 1
					  WHEN T.MEASURE = 'P_SCP_SHIP_PLAN_ETD'	THEN 2
					  WHEN T.MEASURE = 'P_SHIP_PLAN_SIMU_ETD'	THEN 4
					  WHEN T.MEASURE = 'P_FP_NPC_ASSY_PLAN'		THEN 6
					  WHEN T.MEASURE = 'P_FP_COATER_PLAN'		THEN 7
				  END									AS SEQ
				,T.QTY									AS QTY
				,T.QTY_TO_PCM							AS QTY_TO_PCM
				,T.QTY_TO_CELL							AS QTY_TO_CELL
				,'-'									AS LAST_UPDATED_BY
				,T.LAST_UPDATE_DATE
			FROM #TMP_PLAN_ITEM_CUTOFF CU

			JOIN SSP_ANL_SHIP_PLAN_EE T WITH (NOLOCK)
			  ON T.DIVISION_ID = CU.DIVISION_ID
			 AND T.ITEM_ID     = CU.ITEM_ID
			 AND T.SCM_SITE_ID = CU.SCM_SITE_ID
			 AND T.COMPANY_ID  = CU.COMPANY_ID


			JOIN SSP_MST_SITE_ITEM_EE_V E WITH(NOLOCK)
			  ON T.DIVISION_ID = E.DIVISION_ID
			 AND T.ITEM_ID     = E.ITEM_ID
			 AND T.SCM_SITE_ID = E.SCM_SITE_ID

			WHERE 1=1
			  AND T.MEASURE_TYPE		= 'P'
			  AND T.DIVISION_ID			= @P_DIVISION_ID
			  AND T.COMPANY_ID			= @P_COMPANY_ID
			  AND T.PLAN_START_YYYYMMDD	= @P_PLAN_START_YYYYMMDD
			  AND T.YYYYMMDD			>= @P_FROM_YYYYMMDD
			  AND T.YYYYMMDD			<= @P_TO_YYYYMMDD
			  AND T.MEASURE IN ('P_SCP_PROD_PLAN','P_SCP_SHIP_PLAN_ETD','P_SHIP_PLAN_SIMU_ETD','P_FP_NPC_ASSY_PLAN','P_FP_COATER_PLAN')
			  AND (( @P_FROM_SITE IS NULL OR @P_FROM_SITE = '') OR T.SCM_SITE_ID       IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_FROM_SITE, ',')))
			  AND (( @P_ITEM_ID   IS NULL OR @P_ITEM_ID   = '') OR T.ITEM_ID           IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_ITEM_ID  , ',')))
			  AND (( @P_MODEL_ID  IS NULL OR @P_MODEL_ID  = '') OR T.MODEL_ID          IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_MODEL_ID , ',')))
			  AND (( @P_NICK_NAME IS NULL OR @P_NICK_NAME = '') OR E.ITEM_ID_NICK_NAME IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_NICK_NAME, ',')))

			UNION ALL

			/* C_FP_COATER_POST_PLAN Measure 추가 */
			/* ELECTRODE_POST_OPER_LT 더한 날짜가 조회 된다. */
			SELECT T.DIVISION_ID
				,T.PLANT_ID								AS PLANT_ID
				,T.COMPANY_ID							AS COMPANY_ID
				,T.SCM_SITE_ID							AS SCM_SITE_ID
				,ISNULL(E.ELECTRODE_POST_OPER_LT,'-')	AS ELECTRODE_POST_OPER_LT
				,ISNULL(T.ELECTRODE_TYPE,'-')			AS ELECTRODE_TYPE
				,T.MODEL_ID								AS MODEL_ID
				,T.ITEM_ID								AS ITEM_ID
				,ISNULL(T.SCM_SITE_ID,'-')				AS FROM_SITE
				,ISNULL(T.BOD_ID,'-')					AS BOD_ID
				,T.MEASURE								AS MEASURE
				, CONVERT(char(8), DATEADD(DD, CONVERT(INT,ISNULL(E.ELECTRODE_POST_OPER_LT,0)), CONVERT(DATETIME, T.YYYYMMDD ,112)), 112)	AS YYYYMMDD
				, 8										AS SEQ
				,T.QTY									AS QTY
				,T.QTY_TO_PCM							AS QTY_TO_PCM
				,T.QTY_TO_CELL							AS QTY_TO_CELL
				,'-'									AS LAST_UPDATED_BY
				,T.LAST_UPDATE_DATE
			FROM #TMP_PLAN_ITEM_CUTOFF CU

			JOIN SSP_ANL_SHIP_PLAN_EE T WITH (NOLOCK)
			  ON T.DIVISION_ID = CU.DIVISION_ID
			 AND T.ITEM_ID     = CU.ITEM_ID
			 AND T.SCM_SITE_ID = CU.SCM_SITE_ID
			 AND T.COMPANY_ID  = CU.COMPANY_ID


			JOIN SSP_MST_SITE_ITEM_EE_V E WITH(NOLOCK)
			  ON T.DIVISION_ID = E.DIVISION_ID
			 AND T.ITEM_ID     = E.ITEM_ID
			 AND T.SCM_SITE_ID = E.SCM_SITE_ID

			WHERE 1=1
			  AND T.MEASURE_TYPE		= 'P'
			  AND T.DIVISION_ID			= @P_DIVISION_ID
			  AND T.COMPANY_ID			= @P_COMPANY_ID
			  AND T.PLAN_START_YYYYMMDD	= @P_PLAN_START_YYYYMMDD
			  AND T.YYYYMMDD			>= @P_FROM_YYYYMMDD
			  AND T.YYYYMMDD			<= @P_TO_YYYYMMDD
			  AND T.MEASURE				 = 'P_FP_COATER_POST_PLAN'
			  AND (( @P_FROM_SITE IS NULL OR @P_FROM_SITE = '') OR T.SCM_SITE_ID       IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_FROM_SITE, ',')))
			  AND (( @P_ITEM_ID   IS NULL OR @P_ITEM_ID   = '') OR T.ITEM_ID           IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_ITEM_ID  , ',')))
			  AND (( @P_MODEL_ID  IS NULL OR @P_MODEL_ID  = '') OR T.MODEL_ID          IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_MODEL_ID , ',')))
			  AND (( @P_NICK_NAME IS NULL OR @P_NICK_NAME = '') OR E.ITEM_ID_NICK_NAME IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_NICK_NAME, ',')))
			
			UNION ALL

			/* P_INTRANSIT_ETA Measure 추가 */
			SELECT DIVISION_ID				AS DIVISION_ID
				 , PLANT_ID					AS PLANT_ID
				 , COMPANY_ID				AS COMPANY_ID
				 , SCM_SITE_ID				AS SCM_SITE_ID
				 , ELECTRODE_POST_OPER_LT	AS ELECTRODE_POST_OPER_LT
				 , ELECTRODE_TYPE			AS ELECTRODE_TYPE
				 , MODEL_ID					AS MODEL_ID
				 , ITEM_ID					AS ITEM_ID
				 , FROM_SITE				AS FROM_SITE
				 , BOD_ID					AS BOD_ID
				 , 'P_INTRANSIT_ETA'		AS MEASURE
				 , YYYYMMDD					AS YYYYMMDD
				 , 9						AS SEQ
				 , SUM(QTY)					AS QTY
				 , SUM(QTY_TO_PCM)			AS QTY_TO_PCM
				 , SUM(QTY_TO_CELL)			AS QTY_TO_CELL
				 , '-'
				 , NULL
			FROM
			(
				 SELECT T.DIVISION_ID							AS DIVISION_ID
					  , T.PLANT_ID								AS PLANT_ID
					  , T.COMPANY_ID							AS COMPANY_ID
					  , T.SCM_SITE_ID							AS SCM_SITE_ID
					  , ISNULL(E.ELECTRODE_POST_OPER_LT,'-')	AS ELECTRODE_POST_OPER_LT
					  , ISNULL(E.ELECTRODE_TYPE,'-')			AS ELECTRODE_TYPE
					  , T.MODEL_ID								AS MODEL_ID
					  , T.ITEM_ID								AS ITEM_ID
					  , ISNULL(T.SCM_SITE_ID,'-')				AS FROM_SITE
					  , '-'										AS BOD_ID
