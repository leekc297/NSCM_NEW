												WHEN T.MEASURE = 'P_FP_NPC_ASSY_PLAN'   THEN ISNULL(T.QTY_TO_PCM,0) * -1
												WHEN T.MEASURE = 'P_SHIP_CONFIRM_ETD'   THEN ISNULL(T.QTY_TO_PCM,0) * -1
											ELSE 0.0 END
											) ,0)    
						FROM #TMP_SSP0023_CONFIRM T WITH(NOLOCK)
						WHERE 1=1  
						AND T.COMPANY_ID  = Z.COMPANY_ID
						AND T.DIVISION_ID = Z.DIVISION_ID
						AND T.PLANT_ID    = Z.PLANT_ID
						AND T.SCM_SITE_ID = Z.SCM_SITE_ID
						AND T.MODEL_ID    = Z.MODEL_ID
						AND T.ITEM_ID     = Z.ITEM_ID
						AND T.MEASURE     <> 'P_FP_COATER_PLAN'
						AND T.YYYYMMDD    > @P_PLAN_START_YYYYMMDD
						AND T.YYYYMMDD    <= Z.YYYYMMDD 
					)  
					-- P_INV_CONFIRM(전일) 
					,  ISNULL(B.QTY_TO_CELL,0) 
					+ 
