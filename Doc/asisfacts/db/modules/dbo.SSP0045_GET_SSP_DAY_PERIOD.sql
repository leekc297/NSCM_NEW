CREATE PROCEDURE [dbo].[SSP0045_GET_SSP_DAY_PERIOD]
	 @p_division_id    NVARCHAR(MAX) 
AS
BEGIN
	SELECT 
			CASE WHEN A.NAME <> A.CHANGE_PLAN_START_YYYYMMDD 
					THEN  CONVERT(CHAR(8),DATEADD(WK, DATEDIFF(D, 0, A.NAME) / 7 , CONVERT(INT,SEGMENT3)),112) + ':' + CONVERT(varchar(8) , DATEADD(DAY, CONVERT(INT,SEGMENT4), GETDATE()), 112)
				 WHEN A.CHANGE_PLAN_START_YYYYMMDD IS NULL
					THEN  CONVERT(CHAR(8), GETDATE(),112) + ':' +  CONVERT(varchar(8) , DATEADD(DAY, 55, GETDATE()), 112)
				ELSE  CONVERT(CHAR(8),DATEADD(WK, DATEDIFF(D, 0, A.CHANGE_PLAN_START_YYYYMMDD ) / 7 ,  CONVERT(INT,SEGMENT3)),112) + ':' + CONVERT(varchar(8) , DATEADD(DAY, CONVERT(INT,SEGMENT4), GETDATE()), 112)
			END
	FROM 
	(
		SELECT TOP 1 PLAN_START_YYYYMMDD AS CODE
			, CONVERT(CHAR(8), DBO.FN_CHAR_TO_DATE(PLAN_START_YYYYMMDD),112) AS NAME
			, PLAN_TYPE 
			, CONVERT(CHAR(8),DATEADD(WK, DATEDIFF(D, 0, GETDATE()) / 7 , CONVERT(INT,L.SEGMENT2)) ,112)  AS CHANGE_PLAN_START_YYYYMMDD
			, L.SEGMENT3
			, L.SEGMENT4
		FROM SCP_PLAN_VERSION_V WITH(NOLOCK) 
		JOIN SCM_ADM_LOOKUP_MASTER_DETAIL L WITH(NOLOCK)
			ON L.LOOKUP_TYPE = 'SSP_GET_DAY_PERIOD' 
			AND L.VALID_YN = 'Y'
			AND L.SEGMENT1    = @p_division_id
		WHERE DIVISION_ID	  = @p_division_id
			AND PLAN_TYPE	  = 'FN'
		GROUP BY PLAN_START_YYYYMMDD, PLAN_TYPE,L.SEGMENT2,L.SEGMENT3, L.SEGMENT4
		ORDER BY PLAN_START_YYYYMMDD DESC
	) A

END
