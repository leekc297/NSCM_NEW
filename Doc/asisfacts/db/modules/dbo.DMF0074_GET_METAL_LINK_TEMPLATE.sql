CREATE PROCEDURE [dbo].[DMF0074_GET_METAL_LINK_TEMPLATE]
    @p_division_id				NVARCHAR(30)

AS  

BEGIN
  SET NOCOUNT ON;
  SET ANSI_WARNINGS OFF;

	IF OBJECT_ID('TEMPDB..#RTNTMP') IS NOT NULL
		DROP TABLE #RTNTMP;

	--[PJ2024-50461]DIV별 최신 버전
	IF OBJECT_ID('TEMPDB..#TEMP_VERSION_NO') IS NOT NULL
		DROP TABLE #TEMP_VERSION_NO;

	SELECT 	
	--[PJ2024-50461]조회시 * 가져오지 말고 구체적 필드 표시START
	A.DIVISION_ID
	,A.VERSION_NO
	, A.YYYYMMDD
	--[PJ2024-50461]조회시 * 가져오지 말고 구체적 필드 표시END
	, B.BASIS_YYYYMM AS YYYYMM

	--[PJ2024-50461]날짜조작 데이터 변수로 처리 START
	, CASE WHEN B.BASIS_YYYYMM > CONVERT(CHAR(6), DATEADD(DD, -7, dbo.FN_NEXT_DAY( A.YYYYMMDD, 'MON')), 112)
		THEN CONVERT(CHAR(8), DATEADD(MONTH, -1,CONVERT(VARCHAR, B.BASIS_YYYYMM + '01', 112) ), 112)
		ELSE CONVERT(VARCHAR, B.BASIS_YYYYMM + '01', 112) END RESULT_FROM
	, CONVERT(CHAR(8), DATEADD(DD, -7, dbo.FN_NEXT_DAY( A.YYYYMMDD, 'MON')), 112) RESULT_TO
	, CONVERT(CHAR(8), DATEADD(DD, - 1, DATEADD(WW, 52, CONVERT(CHAR(8), DATEADD(DD, -7, dbo.FN_NEXT_DAY( A.YYYYMMDD, 'MON')), 112) )),  112)  PLAN_TO
	--[PJ2024-50611]날짜조작 데이터 변수로 처리 END

	INTO #TEMP_VERSION_NO
	FROM
	(
		SELECT DIVISION_ID, MAX(VERSION_NO) VERSION_NO,  max(yyyymmdd) yyyymmdd
					FROM DM_MST_VERSION WITH(NOLOCK)
					WHERE DIVISION_ID = @p_division_id
					AND VERSION_TYPE	= 'SP_W' 
					--AND ISNULL(ATTRIBUTE7, 'N') = 'Y'
		GROUP BY DIVISION_ID
	) A
	INNER JOIN SCM_SYS_CALENDAR_M B
			ON B.BASIS_YYYYMMDD = A.yyyymmdd 

		SELECT 
			A.DIVISION_ID
			, '' PLAN_YYYYMM --날짜는 빈칸으로 내려받게
			,A.DEPT_ID
			, A.DEPT_NAME_KO DEPT_NAME
			,A.END_CUSTOMER
			, A.PROJECT_CODE
			, A.PROJECT_NAME
			, A.ITEM_ID
			, 'Y' METAL_LINK_YN
			, A.SCM_SITE_ID
			, A.CURRENCY
			, A.FCST_TYPE
			, 'N' METAL_EXCEPTION_YN
			, '' ENERGY
			,'' APPLY_PRICE_TYPE_CODE1
			,'' APPLY_PRICE_TYPE_CODE2
			,'' APPLY_PRICE_TYPE_CODE3
			,'' APPLY_PRICE_TYPE_CODE4
			,'' APPLY_PRICE_TYPE_CODE5
			,'' APPLY_PRICE_TYPE_CODE6
			,'' APPLY_PRICE_TYPE_CODE7
			,'' FROM_PERIOD1
			,'' FROM_PERIOD2
			,'' FROM_PERIOD3
			,'' FROM_PERIOD4
			,'' FROM_PERIOD5
			,'' FROM_PERIOD6
			,'' FROM_PERIOD7
			,'' TO_PERIOD1
			,'' TO_PERIOD2
			,'' TO_PERIOD3
			,'' TO_PERIOD4
			,'' TO_PERIOD5
			,'' TO_PERIOD6
			,'' TO_PERIOD7
			,'' CONTRACT_UNIT1
			,'' CONTRACT_UNIT2
			,'' CONTRACT_UNIT3
			,'' CONTRACT_UNIT4
			,'' CONTRACT_UNIT5
			,'' CONTRACT_UNIT6
			,'' CONTRACT_UNIT7
			,'' METAL_APPLY1
			,'' METAL_APPLY2
			,'' METAL_APPLY3
			,'' METAL_APPLY4
			,'' METAL_APPLY5
			,'' METAL_APPLY6
			,'' METAL_APPLY7
			,'' METAL_REQR1
			,'' METAL_REQR2
			,'' METAL_REQR3
			,'' METAL_REQR4
			,'' METAL_REQR5
			,'' METAL_REQR6
			,'' METAL_REQR7

			INTO #RTNTMP

		FROM 
		(
			SELECT
			SP.DIVISION_ID
			--[PJ2024-50461] Sales Site Project Model 의 Owner 팀 적용
			--,MS.DEPT_ID
			--, DI.DEPT_NAME_KO
			,TEAM.DEPT_ID
			, TEAM.DEPT_NAME_KO
			--[PJ2024-50461] Sales Site Project Model 의 Owner 팀 적용
			, CASE WHEN SP.DIVISION_ID = '40' THEN SP.PROJECT_CODE ELSE MS.END_CUSTOMER END END_CUSTOMER--[PJ2024-50611]소형일 경우 PROJECT_CODE로 비교. 나머지는 END_CUSTOMER로 비교
			, MP.PROJECT_CODE
			, MP.PROJECT_NAME
			, SP.ITEM_ID
			, SP.SCM_SITE_ID
			, CASE WHEN ISNULL(SP.CURRENCY, '') = '' THEN SI.CURRENCY ELSE SP.CURRENCY END CURRENCY--CURRENCY가 없을 경우 SSPM의 값을 가져옴
			, LUP.SEGMENT2 FCST_TYPE
			FROM DM_PLN_SALES_PLAN_C SP WITH(NOLOCK) 
			INNER JOIN SCM_MST_SITE MS WITH(NOLOCK) 
				ON MS.DIVISION_ID = SP.DIVISION_ID
				AND MS.SCM_SITE_ID = SP.SCM_SITE_ID
				AND MS.VALID_YN = 'Y'  
			INNER JOIN SCM_ADM_LOOKUP_MASTER_DETAIL LUP WITH(NOLOCK)
				ON LUP.LOOKUP_TYPE = 'SALES_TYPE_CODE'
				AND LUP.VALID_YN = 'Y'
				AND LUP.SEGMENT4 <> 'FREE'----FCST_TYPE_NOT_FREE
				AND LUP.SEGMENT1 = SP.FCST_TYPE
			INNER JOIN SCM_MST_SITE_ITEM SI WITH(NOLOCK)
				ON SI.DIVISION_ID = SP.DIVISION_ID 
				AND SI.PROJECT_CODE = SP.PROJECT_CODE 
				AND SI.SCM_SITE_ID = SP.SCM_SITE_ID 
				AND SI.ITEM_ID = SP.ITEM_ID 
				AND SI.VALID_YN = 'Y'
			--[PJ2024-50461]업로드 대상은 '제품(P)'만 해당START
			INNER JOIN DM_MST_ITEM_SINGLE_V SV WITH(NOLOCK)
				ON SV.DIVISION_ID = SI.DIVISION_ID
				AND SV.ITEM_ID = SI.ITEM_ID
				AND SV.Item_Type = 'P'--'제품(P)'만 해당
			--[PJ2024-50461]업로드 대상은 '제품(P)'만 해당END

			--[PJ2024-50461]DIV별 최신버전 START
			INNER JOIN #TEMP_VERSION_NO T_VER
				ON SP.DIVISION_ID = T_VER.DIVISION_ID
				AND SP.VERSION_NO = T_VER.VERSION_NO
			--[PJ2024-50461]DIV별 최신버전 END

			--[PJ2024-50461] Sales Site Project Model 의 Owner 정보 조인 START
			LEFT JOIN (
				SELECT B.USER_ID, B.USER_NAME, B.USER_NAME_EN, B.DEPT_ID, C.DEPT_NAME_KO, C.UPPER_DEPT_ID 
				FROM [SCM_MST_SSO_USER_INFO] AS B WITH(NOLOCK)
				INNER JOIN SCM_MST_SSO_DEPT_INFO AS C WITH(NOLOCK)
				ON B.DEPT_ID = C.DEPT_ID
			) AS TEAM
			ON      
			TEAM.USER_ID   IN (SELECT top 1 token FROM [dbo].[String_Split](SI.owner, ','))
			--[PJ2024-50461] Sales Site Project Model 의 Owner 정보 조인 END

			LEFT JOIN SCM_MST_PROJECT MP WITH(NOLOCK)
			ON  SP.DIVISION_ID = MP.DIVISION_ID 
			AND CASE WHEN SP.DIVISION_ID = '40' THEN '' ELSE SP.PROJECT_CODE END = MP.PROJECT_CODE--[PJ2024-50611] 소형사업부는 PROJECT_CODE가 없으므로 빈값으로 조인

			INNER JOIN SCM_ADM_LOOKUP_MASTER_DETAIL LUP2 WITH(NOLOCK)----등록된 END CUSTOMER만 처리
			ON  SP.DIVISION_ID = LUP2.SEGMENT1 
			AND LUP2.LOOKUP_TYPE = 'END_CUSTOMER'
			AND CASE WHEN SP.DIVISION_ID = '40' THEN SP.PROJECT_CODE ELSE MS.END_CUSTOMER END  = LUP2.SEGMENT2--[PJ2024-50611]소형일 경우 PROJECT_CODE로 비교. 나머지는 END_CUSTOMER로 비교

			WHERE SP.DIVISION_ID = @p_division_id
			AND SP.QTY <> 0
			AND SP.MEASURE = 'RTF_SYS_RP'
			--[PJ2024-50461]버전의 날짜로 처리 START
			AND SP.YYYYMMDD >= T_VER.RESULT_TO
			AND SP.YYYYMMDD <= T_VER.PLAN_TO
			--[PJ2024-50461]버전의 날짜로 처리 END
				
			--[PJ2024-50461]82번 사업부는 에너지 있는 모델만 추출 START
			AND (

					(@p_division_id = '82' AND EXISTS
						(
							SELECT 1 FROM SCM_MST_ITEM_SN  MIS WITH(NOLOCK)
							WHERE MIS.DIVISION_ID = '82'
							AND MIS.ITEM_ID = SP.ITEM_ID
							AND ISNULL(MIS.ENERGE, '') <> ''--Energy가 있는 모델만
							AND MIS.ACTIVE_FLAG = 'Y'
						)
					) OR
					(@p_division_id <> '82')

			)
			--[PJ2024-50461]82번 사업부는 에너지 있는 모델만 추출 END
			UNION ALL
			SELECT
			SP.DIVISION_ID
			--[PJ2024-50461] Sales Site Project Model 의 Owner 팀 적용
			--,MS.DEPT_ID
			--, DI.DEPT_NAME_KO
			,TEAM.DEPT_ID
			, TEAM.DEPT_NAME_KO
			--[PJ2024-50461] Sales Site Project Model 의 Owner 팀 적용
			, CASE WHEN SP.DIVISION_ID = '40' THEN SP.PROJECT_CODE ELSE MS.END_CUSTOMER END END_CUSTOMER--[PJ2024-50611]소형일 경우 PROJECT_CODE로 비교. 나머지는 END_CUSTOMER로 비교
			, MP.PROJECT_CODE
			, MP.PROJECT_NAME
			, SP.ITEM_ID
			, SP.SCM_SITE_ID
			, CASE WHEN ISNULL(SP.CURRENCY, '') = '' THEN SI.CURRENCY ELSE SP.CURRENCY END CURRENCY--CURRENCY가 없을 경우 SSPM의 값을 가져옴
			, LUP.SEGMENT2 FCST_TYPE
			FROM DM_PLN_SALES_PLAN_RESULT_C SP WITH(NOLOCK) 
			INNER JOIN SCM_MST_SITE MS WITH(NOLOCK) 
				ON MS.DIVISION_ID = SP.DIVISION_ID
				AND MS.SCM_SITE_ID = SP.SCM_SITE_ID
				AND MS.VALID_YN = 'Y'  
			INNER JOIN SCM_ADM_LOOKUP_MASTER_DETAIL LUP WITH(NOLOCK)
				ON LUP.LOOKUP_TYPE = 'SALES_TYPE_CODE'
				AND LUP.VALID_YN = 'Y'
				AND LUP.SEGMENT4 <> 'FREE'----FCST_TYPE_NOT_FREE
				AND LUP.SEGMENT1 = SP.FCST_TYPE
			INNER JOIN SCM_MST_SITE_ITEM SI WITH(NOLOCK)
				ON SI.DIVISION_ID = SP.DIVISION_ID 
				AND SI.PROJECT_CODE = SP.PROJECT_CODE 
				AND SI.SCM_SITE_ID = SP.SCM_SITE_ID 
				AND SI.ITEM_ID = SP.ITEM_ID
				AND SI.VALID_YN = 'Y'
			--[PJ2024-50461]업로드 대상은 '제품(P)'만 해당START
			INNER JOIN DM_MST_ITEM_SINGLE_V SV WITH(NOLOCK)
				ON SV.DIVISION_ID = SI.DIVISION_ID
				AND SV.ITEM_ID = SI.ITEM_ID
				AND SV.Item_Type = 'P'--'제품(P)'만 해당
			--[PJ2024-50461]업로드 대상은 '제품(P)'만 해당END

			--[PJ2024-50461]DIV별 최신버전 START
			INNER JOIN #TEMP_VERSION_NO T_VER
				ON SP.DIVISION_ID = T_VER.DIVISION_ID
				AND SP.VERSION_NO = T_VER.VERSION_NO
			--[PJ2024-50461]DIV별 최신버전 END	

			--[PJ2024-50461] Sales Site Project Model 의 Owner 정보 조인 START
			LEFT JOIN (
				SELECT B.USER_ID, B.USER_NAME, B.USER_NAME_EN, B.DEPT_ID, C.DEPT_NAME_KO, C.UPPER_DEPT_ID 
				FROM [SCM_MST_SSO_USER_INFO] AS B WITH(NOLOCK)
				INNER JOIN SCM_MST_SSO_DEPT_INFO AS C WITH(NOLOCK)
				ON B.DEPT_ID = C.DEPT_ID
			) AS TEAM
			ON      
			TEAM.USER_ID   IN (SELECT top 1 token FROM [dbo].[String_Split](SI.owner, ','))
			--[PJ2024-50461] Sales Site Project Model 의 Owner 정보 조인 END

			LEFT JOIN SCM_MST_PROJECT MP WITH(NOLOCK)
			ON  SP.DIVISION_ID = MP.DIVISION_ID 
			AND CASE WHEN SP.DIVISION_ID = '40' THEN '' ELSE SP.PROJECT_CODE END = MP.PROJECT_CODE--[PJ2024-50611] 소형사업부는 PROJECT_CODE가 없으므로 빈값으로 조인

			INNER JOIN SCM_ADM_LOOKUP_MASTER_DETAIL LUP2 WITH(NOLOCK)----등록된 END CUSTOMER만 처리
			ON  SP.DIVISION_ID = LUP2.SEGMENT1 
			AND LUP2.LOOKUP_TYPE = 'END_CUSTOMER'
			AND CASE WHEN SP.DIVISION_ID = '40' THEN SP.PROJECT_CODE ELSE MS.END_CUSTOMER END  = LUP2.SEGMENT2--[PJ2024-50611]소형일 경우 PROJECT_CODE로 비교. 나머지는 END_CUSTOMER로 비교

			WHERE SP.DIVISION_ID = @p_division_id
			AND SP.QTY <> 0
			AND SP.MEASURE = 'RTF_SYS_RP'
			--[PJ2024-50461]버전의 날짜로 처리 START
			AND SP.YYYYMMDD >= T_VER.RESULT_FROM
			AND SP.YYYYMMDD < T_VER.RESULT_TO
			--[PJ2024-50461]버전의 날짜로 처리 END

			--[PJ2024-50461]82번 사업부는 에너지 있는 모델만 추출 START
			AND (
					(@p_division_id = '82' AND EXISTS
						(
							SELECT 1 FROM SCM_MST_ITEM_SN  MIS WITH(NOLOCK)
							WHERE MIS.DIVISION_ID = '82'
							AND MIS.ITEM_ID = SP.ITEM_ID
							AND ISNULL(MIS.ENERGE, '') <> ''--Energy가 있는 모델만
							AND MIS.ACTIVE_FLAG = 'Y'
						)
					) OR
					(@p_division_id <> '82')
			)
			--[PJ2024-50461]82번 사업부는 에너지 있는 모델만 추출 END
		) A
		GROUP BY 
		A.DIVISION_ID
		,A.DEPT_ID
		, A.DEPT_NAME_KO
		,A.END_CUSTOMER
		, A.PROJECT_CODE
		, A.PROJECT_NAME
		, A.ITEM_ID
		, A.SCM_SITE_ID
		, A.CURRENCY
		, A.FCST_TYPE  



		SELECT 
			DIVISION_ID
			,PLAN_YYYYMM
			,DEPT_ID
			,DEPT_NAME
			,END_CUSTOMER
			, PROJECT_CODE
			, PROJECT_NAME
			, ITEM_ID
			, METAL_LINK_YN
			, SCM_SITE_ID
			, CURRENCY
			, FCST_TYPE
			, METAL_EXCEPTION_YN
			, ENERGY
			, APPLY_PRICE_TYPE_CODE1
			, APPLY_PRICE_TYPE_CODE2
			, APPLY_PRICE_TYPE_CODE3
			, APPLY_PRICE_TYPE_CODE4
			, APPLY_PRICE_TYPE_CODE5
			, APPLY_PRICE_TYPE_CODE6
			, APPLY_PRICE_TYPE_CODE7
			, FROM_PERIOD1
			, FROM_PERIOD2
			, FROM_PERIOD3
			, FROM_PERIOD4
			, FROM_PERIOD5
			, FROM_PERIOD6
			, FROM_PERIOD7
			, TO_PERIOD1
			, TO_PERIOD2
			, TO_PERIOD3
			, TO_PERIOD4
			, TO_PERIOD5
			, TO_PERIOD6
			, TO_PERIOD7
			, CONTRACT_UNIT1
			, CONTRACT_UNIT2
			, CONTRACT_UNIT3
			, CONTRACT_UNIT4
			, CONTRACT_UNIT5
			, CONTRACT_UNIT6
			, CONTRACT_UNIT7
			, METAL_APPLY1
			, METAL_APPLY2
			, METAL_APPLY3
			, METAL_APPLY4
			, METAL_APPLY5
			, METAL_APPLY6
			, METAL_APPLY7
			, METAL_REQR1
			, METAL_REQR2
			, METAL_REQR3
			, METAL_REQR4
			, METAL_REQR5
			, METAL_REQR6
			, METAL_REQR7		
		FROM #RTNTMP

END
