 2024.10.02		KJJ			[PJ2024-50461] 기능개선-	업로드 대상은 '제품(P)'만 해당
 2024.10.04		KJJ			[PJ2024-50461] 기능개선-	당주가 아니라 최신의 버전으로 처리함
 2024.10.15		KJJ			[PJ2024-50461] 기능개선-	업로드 대상 로직 수정
