CREATE PROCEDURE [dbo].[SSP0027_SAVE_SHIPMENT_REQUEST_ALLO]
     @P_ACTIVE_FLAG					NVARCHAR(MAX)
	,@P_PR_CHECK					NVARCHAR(MAX)
    ,@P_DM_REQ_NO					NVARCHAR(MAX)
	,@P_DIVISION_ID					NVARCHAR(MAX)
	,@P_PROJECT_CODE				NVARCHAR(MAX)
	,@P_ITEM_SEQ					NVARCHAR(MAX)
	,@P_ITEM_ID						NVARCHAR(MAX)
	,@P_DM_REQUEST_DATE				NVARCHAR(MAX)
	,@P_PLAN_QTY					NVARCHAR(MAX)
	,@P_ALLO_QTY					NVARCHAR(MAX)
	,@P_USER_ID						NVARCHAR(MAX)
	,@P_PROGRAM_ID					NVARCHAR(MAX) = 'SSP0027'
AS
BEGIN
	SET NOCOUNT ON; 
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;
	
	DECLARE @v_infseqno					NVARCHAR(14);
	DECLARE @v_time_for_system			DATETIME;
	DECLARE @v_time_for_timezone		DATETIME;

	DECLARE @RECV_ACTIVE_FLAG			NVARCHAR(MAX);
	DECLARE @V_ACTIVE_FLAG				NVARCHAR(MAX);
	DECLARE @V_PR_CHECK					NVARCHAR(MAX);
	DECLARE @V_DM_REQ_NO				NVARCHAR(MAX);
	DECLARE @V_ERP_PR_STATUS			NVARCHAR(MAX);
	DECLARE @V_DIVISION_ID				NVARCHAR(MAX);
	DECLARE @V_PROJECT_CODE				NVARCHAR(MAX);
	DECLARE @V_ITEM_SEQ					NVARCHAR(MAX);
	DECLARE @V_ITEM_ID					NVARCHAR(MAX);
	DECLARE @V_DM_REQUEST_DATE			NVARCHAR(MAX);
	DECLARE @V_PLAN_QTY					NVARCHAR(MAX);
	DECLARE @V_ALLO_QTY					NVARCHAR(MAX);
	DECLARE @V_USER_ID					NVARCHAR(MAX);
	DECLARE @V_PROGRAM_ID				NVARCHAR(MAX);

	DECLARE @V_HOLD_FLAG_CNT			NVARCHAR(MAX);
	DECLARE @V_NON_PR_QTY				NVARCHAR(MAX);		-- 요청수량에  자재가 전부 ALLO된 경우 Check

	DECLARE @V_CREATE_DATE				DATETIME;

	-- NERP 매핑코드
    DECLARE @v_C100 NVARCHAR(10);
    DECLARE @v_Storage_6006 NVARCHAR(20);
	SET @v_C100 = dbo.FN_GET_LOOKUP_VALUE('SSP0027_SAVE_SHIPMENT_REQUEST_ALLO'  ,'ESOC');	--C100
	SET @v_Storage_6006 = dbo.FN_GET_LOOKUP_VALUE('SSP0027_SAVE_SHIPMENT_REQUEST_ALLO'  ,'STORAGE_6006')

	SET @RECV_ACTIVE_FLAG			= @P_ACTIVE_FLAG;
	SET @V_ACTIVE_FLAG				= NULL;
	SET @V_PR_CHECK					= NULL;
	SET @V_DM_REQ_NO				= NULL;
	SET @V_DIVISION_ID				= NULL;
	SET @V_PROJECT_CODE				= NULL;
	SET @V_ITEM_SEQ					= NULL;
	SET @V_ITEM_ID					= NULL;
	SET @V_DM_REQUEST_DATE			= NULL;
	SET @V_PLAN_QTY					= NULL;
	SET @V_ALLO_QTY					= NULL;
	SET @V_USER_ID					= @P_USER_ID;
	SET @V_PROGRAM_ID				= 'SSP0027';
	SET @V_CREATE_DATE				= SYSDATETIME();

	-- LOG 용 변수 설정
    DECLARE @V_PROGRAM_NAME NVARCHAR(150) = 'SSP0027_SAVE_SHIPMENT_REQUEST_ALLO';
    DECLARE @V_LOG_TYPE     NVARCHAR(30); -- START/END/ERROR/...
    DECLARE @N_LOG_COUNT    INTEGER = 0;
    DECLARE @V_LOG_MESSAGE  NVARCHAR(1000);
    DECLARE @V_DESCRIPTION  NVARCHAR(500);
    DECLARE @D_EVENT_DATE   DATETIME;	

	DECLARE @V_DELIMITER NVARCHAR(1)
	SET @V_DELIMITER = '^' 
	DECLARE @MAX_LOOP_CNT		INTEGER = 0; 
	DECLARE @MST_LOOP_CNT		INTEGER = 0;

	DECLARE @V_SAVE_FLAG_CNT	INTEGER = 0;
	DECLARE @V_PR_CHECK_CNT		INTEGER = 0;

	DECLARE @V_PLAN_START_YYYYMMDD	NVARCHAR(MAX);


	SET @v_time_for_system   = GETDATE() ;


	DECLARE @TEST  INTEGER = 0;


	IF OBJECT_ID('tempdb..#TMP_SSP_ANL_ESS_REQ_TEMP') IS NOT NULL	
		DROP TABLE #TMP_SSP_ANL_ESS_REQ_TEMP;

	IF OBJECT_ID('tempdb..#TMP_SSP_ANL_ESS_REQ') IS NOT NULL	
		DROP TABLE #TMP_SSP_ANL_ESS_REQ;

	IF OBJECT_ID('tempdb..#TMP_MST_STOCK') IS NOT NULL	
		DROP TABLE #TMP_MST_STOCK;

	IF OBJECT_ID('tempdb..#TMP_MST_PR_COUNT') IS NOT NULL	
		DROP TABLE #TMP_MST_PR_COUNT;



	-- Measure 세팅
    CREATE TABLE #TMP_SSP_ANL_ESS_REQ_TEMP (
		 ACTIVE_FLAG			NVARCHAR(MAX)
		,PR_CHECK				NVARCHAR(MAX)
		,DM_REQ_NO				NVARCHAR(MAX)
		,DIVISION_ID			NVARCHAR(MAX)
		,PROJECT_CODE			NVARCHAR(MAX)
		,ITEM_SEQ				NVARCHAR(MAX)
        ,ITEM_ID				NVARCHAR(MAX)
    	,DM_REQUEST_DATE		NVARCHAR(MAX)
		,PLAN_QTY				NVARCHAR(MAX)
		,ALLO_QTY				NVARCHAR(MAX)
		,UPDATED_USER			NVARCHAR(MAX)
	);

	SELECT @V_PLAN_START_YYYYMMDD = X.ATTRIBUTE1 
     FROM SCM_ADM_LOOKUP_MASTER_DETAIL AS X WITH(NOLOCK) 
     WHERE X.LOOKUP_TYPE	= 'SSP_ANL_ESS_PLAN'
	  AND X.SEGMENT1		= '82'
	  AND X.VALID_YN		= 'Y'


	BEGIN TRY
		-- 시작 LOG
		SET @V_LOG_TYPE = 'START';
		SET @V_LOG_MESSAGE = '########## START OF PROCEDURE ##########';
		SET @V_DESCRIPTION = '';
		SET @D_EVENT_DATE = SYSDATETIME();
		EXEC PR_SCM_SYS_LOG_BATCH @V_PROGRAM_NAME, @V_LOG_TYPE, @N_LOG_COUNT, @V_LOG_MESSAGE, @V_DESCRIPTION, @D_EVENT_DATE;
		
		SET @MAX_LOOP_CNT = [DBO].[SCM_ARR_SPL_CNT](@P_ACTIVE_FLAG, @V_DELIMITER);
		WHILE LEN(@RECV_ACTIVE_FLAG) > 0 AND @MST_LOOP_CNT < @MAX_LOOP_CNT
		BEGIN
			SET @MST_LOOP_CNT = @MST_LOOP_CNT + 1;			

			-- 각 컬럼들에 대한 스플릿처리로직 스타트
			BEGIN

				SET @V_ACTIVE_FLAG					= DBO.SCM_ARR_SPL_VAL( @P_ACTIVE_FLAG,			@V_DELIMITER, @MST_LOOP_CNT );
				SET @V_PR_CHECK						= DBO.SCM_ARR_SPL_VAL( @P_PR_CHECK,				@V_DELIMITER, @MST_LOOP_CNT );
				SET @V_DM_REQ_NO					= DBO.SCM_ARR_SPL_VAL( @P_DM_REQ_NO,			@V_DELIMITER, @MST_LOOP_CNT );
				SET @V_DIVISION_ID					= DBO.SCM_ARR_SPL_VAL( @P_DIVISION_ID,			@V_DELIMITER, @MST_LOOP_CNT );
				SET @V_PROJECT_CODE					= DBO.SCM_ARR_SPL_VAL( @P_PROJECT_CODE,			@V_DELIMITER, @MST_LOOP_CNT );
				SET @V_ITEM_SEQ						= DBO.SCM_ARR_SPL_VAL( @P_ITEM_SEQ,				@V_DELIMITER, @MST_LOOP_CNT );
				SET @V_ITEM_ID						= DBO.SCM_ARR_SPL_VAL( @P_ITEM_ID,				@V_DELIMITER, @MST_LOOP_CNT );
				SET @V_DM_REQUEST_DATE				= DBO.SCM_ARR_SPL_VAL( @P_DM_REQUEST_DATE,		@V_DELIMITER, @MST_LOOP_CNT );
				SET @V_PLAN_QTY						= DBO.SCM_ARR_SPL_VAL( @P_PLAN_QTY,				@V_DELIMITER, @MST_LOOP_CNT );
				SET @V_ALLO_QTY						= DBO.SCM_ARR_SPL_VAL( @P_ALLO_QTY,				@V_DELIMITER, @MST_LOOP_CNT );

			END;


			---- ALLO 수량 UPDATE- 
			--UPDATE SSP_ANL_ESS_REQ
			--SET INV_ALLO_QTY		= ISNULL(@V_ALLO_QTY,0)
			--,	LAST_UPDATED_BY		= @P_USER_ID
			--,	LAST_UPDATE_DATE	= @V_CREATE_DATE
			--WHERE 1=1
			--  AND DM_REQ_NO			= @V_DM_REQ_NO
			--  AND DIVISION_ID		= @V_DIVISION_ID
			--  AND ITEM_SEQ			= @V_ITEM_SEQ
			--  AND ITEM_ID			= @V_ITEM_ID
			--  AND PROJECT_CODE		= @V_PROJECT_CODE
			--  AND YYYYMMDD			= REPLACE(@V_DM_REQUEST_DATE,'-','')
			--;


			SELECT @V_HOLD_FLAG_CNT = COUNT(*)
			  FROM SSP_ANL_ESS_REQ WITH(NOLOCK)
			 WHERE DM_REQ_NO = @V_DM_REQ_NO
			   AND ITEM_ID  = @V_ITEM_ID
			   AND HOLD_FLAG = 'Y'

			IF @V_HOLD_FLAG_CNT > 0
			BEGIN
				-- 결과코드, 결과 카운트 반환
				SELECT  'V' AS RESULT_CODE,  @MAX_LOOP_CNT AS result_cnt, @v_infseqno AS IFSEQNO ;

				RETURN; 
			END
				

			-- UPDATE & INSERT 대상 TEMP 테이블 만들기
			INSERT INTO #TMP_SSP_ANL_ESS_REQ_TEMP ( ACTIVE_FLAG, PR_CHECK, DM_REQ_NO, DIVISION_ID, PROJECT_CODE, ITEM_SEQ, ITEM_ID, DM_REQUEST_DATE, PLAN_QTY, ALLO_QTY, UPDATED_USER)
			VALUES(@V_ACTIVE_FLAG, @V_PR_CHECK, @V_DM_REQ_NO, @V_DIVISION_ID, @V_PROJECT_CODE, @V_ITEM_SEQ, @V_ITEM_ID, CONVERT(VARCHAR(8), CONVERT(DATETIME, @V_DM_REQUEST_DATE), 112), CEILING(@V_PLAN_QTY), CEILING(@V_ALLO_QTY), @V_USER_ID );

		END;


		--SELECT * FROM #TMP_SSP_ANL_ESS_REQ_TEMP;

		/* PR 대상 Check 
			PR 요청 시 동일 Request No 모두 선택하지 않으면 요청 할수 없음.
		*/
		WITH MST_PR_COUNT AS 
		(
			SELECT DM_REQ_NO, COUNT(*) AS CNT
			--FROM SSP_ANL_ESS_PR
			FROM SSP_ANL_ESS_REQ WITH(NOLOCK)
			WHERE 1=1
			AND HOLD_FLAG ='N'
			AND YYYYMMDD >= @V_PLAN_START_YYYYMMDD
			GROUP BY DM_REQ_NO

		)
		SELECT A.DM_REQ_NO, CASE WHEN A.CNT <> B.CNT THEN 'N' ELSE 'Y' END AS PR_SAVE_FLAG
		INTO #TMP_MST_PR_COUNT
		FROM MST_PR_COUNT A
		INNER JOIN (
			SELECT DM_REQ_NO, COUNT(*) CNT
			FROM #TMP_SSP_ANL_ESS_REQ_TEMP
			WHERE PR_CHECK = 'True'
			GROUP BY DM_REQ_NO
		) B
		ON A.DM_REQ_NO = B.DM_REQ_NO
		WHERE B.CNT > 0


		SELECT @V_PR_CHECK_CNT = COUNT(*)
		FROM #TMP_MST_PR_COUNT
		WHERE PR_SAVE_FLAG = 'N'

		IF @V_PR_CHECK_CNT > 0 
		BEGIN

			SET @V_LOG_TYPE = 'END';
			SET @V_LOG_MESSAGE = '########## END OF PROCEDURE ##########';
			SET @V_DESCRIPTION = N'PR 요청 시 Check되지 않은 동일 Request No가 존재합니다.';
			SET @D_EVENT_DATE = SYSDATETIME();
			EXEC PR_SCM_SYS_LOG_BATCH @V_PROGRAM_NAME, @V_LOG_TYPE, @N_LOG_COUNT, @V_LOG_MESSAGE, @V_DESCRIPTION, @D_EVENT_DATE;
					
			-- 결과코드, 결과 카운트 반환
			SELECT  'U' AS RESULT_CODE,  @MAX_LOOP_CNT AS result_cnt, @v_infseqno AS IFSEQNO ;

			RETURN;

		END 
		;

		-- ALLO 수량 대비 잔여 재고 확인 
		WITH MST_STOCK  AS 
		(
		
			SELECT  A.ITEM_ID, ISNULL(B.INV_QTY,0) AS INV_QTY
			FROM (SELECT DISTINCT A.DIVISION_ID, A.ITEM_ID
					FROM SSP_ANL_ESS_REQ A  WITH(NOLOCK)
					WHERE 1=1
					AND A.YYYYMMDD >= @V_PLAN_START_YYYYMMDD
					GROUP BY  A.DIVISION_ID, A.ITEM_ID ) A 
			LEFT OUTER JOIN  (

				SELECT ITEM_ID		AS ITEM_ID
				 , SUM(INV_QTY) AS INV_QTY				 
				FROM SSP_ANL_ESS_STOCK  WITH(NOLOCK)
				WHERE 1=1
				  AND PLAN_START_YYYYMMDD = @V_PLAN_START_YYYYMMDD
				  AND STORAGE_ID = @v_Storage_6006		--'6006'
				GROUP BY ITEM_ID
			) B
			ON A.ITEM_ID = B.ITEM_ID


		)
		--SELECT  A.ITEM_ID , A.INV_QTY, B.INV_ALLO_QTY,  CASE WHEN (A.INV_QTY - B.INV_ALLO_QTY) < 0 THEN 'N' ELSE 'Y' END AS SAVE_FLAG
		SELECT  A.ITEM_ID , A.INV_QTY, B.INV_ALLO_QTY,  CASE WHEN (A.INV_QTY - B.INV_ALLO_QTY) < 0 THEN 'Y' ELSE 'Y' END AS SAVE_FLAG    -- 임시 처리 
		INTO #TMP_MST_STOCK
		FROM MST_STOCK A WITH(NOLOCK)
		INNER JOIN (

			SELECT AA.ITEM_ID, SUM(CONVERT(INT,AA.INV_ALLO_QTY)) AS INV_ALLO_QTY
		
			FROM
			(
				-- UPDATE 대상을 제외 하고 기존 ALLO 수량 Check
				SELECT A.ITEM_ID ,SUM(CONVERT(INT,A.INV_ALLO_QTY)) AS INV_ALLO_QTY
					  FROM SSP_ANL_ESS_REQ A WITH(NOLOCK)
					  WHERE 1=1
						AND NOT EXISTS (SELECT 1 
											FROM #TMP_SSP_ANL_ESS_REQ_TEMP B WITH(NOLOCK)
											WHERE 1=1
											AND A.ITEM_ID			= B.ITEM_ID
											AND A.ITEM_SEQ			= B.ITEM_SEQ
											AND A.DM_REQ_NO			= B.DM_REQ_NO
										)
					  AND A.DM_REQUEST_DATE >= @V_PLAN_START_YYYYMMDD
					GROUP BY A.ITEM_ID

				UNION ALL

				-- UPDATE 대상 ALLO 수량 Check
				SELECT A.ITEM_ID , SUM(CONVERT(INT,A.ALLO_QTY)) AS INV_ALLO_QTY
					  FROM #TMP_SSP_ANL_ESS_REQ_TEMP A WITH(NOLOCK)
					  WHERE 1=1
					  AND A.DM_REQUEST_DATE >= @V_PLAN_START_YYYYMMDD
					GROUP BY A.ITEM_ID
			) AA
			GROUP BY AA.ITEM_ID

		) B
		ON A.ITEM_ID = B.ITEM_ID


		-- Monthly(BOH)기준 ALLO 수량 초과 Count
		SELECT @V_SAVE_FLAG_CNT  = COUNT(*)
		FROM #TMP_MST_STOCK
		WHERE 1=1 
		AND SAVE_FLAG   = 'N';

		IF @V_SAVE_FLAG_CNT > 0 
		BEGIN

			SET @V_LOG_TYPE = 'END';
			SET @V_LOG_MESSAGE = '########## END OF PROCEDURE ##########';
			SET @V_DESCRIPTION = N'Monthly(BOH)기준 ALLO 수량이 초과하였습니다.';
			SET @D_EVENT_DATE = SYSDATETIME();
			EXEC PR_SCM_SYS_LOG_BATCH @V_PROGRAM_NAME, @V_LOG_TYPE, @N_LOG_COUNT, @V_LOG_MESSAGE, @V_DESCRIPTION, @D_EVENT_DATE;
					
			-- 결과코드, 결과 카운트 반환
			SELECT  'T' AS RESULT_CODE,  @MAX_LOOP_CNT AS result_cnt, @v_infseqno AS IFSEQNO ;

			RETURN;

		END
		;

		-- ALLO 수량 UPDATE- 
		MERGE INTO SSP_ANL_ESS_REQ M
		USING
		(
			SELECT  A.ACTIVE_FLAG
			, A.PR_CHECK
			, A.DM_REQ_NO
			, A.DIVISION_ID
			, A.PROJECT_CODE
			, A.ITEM_SEQ
			, A.ITEM_ID
			, A.DM_REQUEST_DATE
			, A.PLAN_QTY
			, A.ALLO_QTY	
			, A.UPDATED_USER
			FROM #TMP_SSP_ANL_ESS_REQ_TEMP A WITH(NOLOCK)
			WHERE 1=1
		) N
		 ON	M.DM_REQ_NO	= N.DM_REQ_NO	  
		AND M.ITEM_ID	= N.ITEM_ID
		AND M.ITEM_SEQ	= N.ITEM_SEQ
		AND M.YYYYMMDD	= N.DM_REQUEST_DATE
		WHEN MATCHED THEN
		UPDATE
			SET M.INV_ALLO_QTY     = CASE WHEN N.ACTIVE_FLAG = 'D' THEN 0 ELSE N.ALLO_QTY  END 
			,	M.LAST_UPDATED_BY  = N.UPDATED_USER
			,   M.HOLD_FLAG		   = CASE WHEN N.ACTIVE_FLAG = 'D' THEN 'Y' ELSE 'N' END
			,	M.LAST_UPDATE_DATE = GETDATE()
			,   M.ATTRIBUTE2	   = CASE WHEN N.ACTIVE_FLAG = 'D' THEN 'Delete' ELSE NULL END
			
		;
			
		SELECT B.PR_CHECK 
			, A.DM_REQ_NO
			, A.ITEM_SEQ
			, A.ITEM_ID
			, A.DIVISION_ID
			, A.PROJECT_CODE
			, A.SCM_SITE_ID
			, A.PLANT_SITE_ID
			, A.DOM_EXP
			, A.FCST_TYPE
			, A.INCOTERMS
			, A.YYYYMMDD
			, A.PLAN_QTY
			, A.UOM
			, A.INV_ALLO_QTY
			, A.SLOC_ID
			, A.SLOC_PLANT_ID
			, A.PUCH_MGR
			, A.PUCH_GROUP
			, A.PR_HEADER
			, A.PR_ITEM_DETAIL
			, A.DM_REQUESTED_BY
			, CONVERT(VARCHAR(8), CONVERT(DATETIME, A.YYYYMMDD), 112) AS DM_REQUEST_DATE
			, A.BOD_ID
			, A.HOLD_FLAG
			, A.CONFIRM_ID
			, @P_USER_ID		 AS CREATED_BY	 
			, @V_CREATE_DATE     AS CREATION_DATE
			, A.LAST_UPDATED_BY
			, A.LAST_UPDATE_DATE
			, A.ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10
			, A.NET_YN
		INTO #TMP_SSP_ANL_ESS_REQ 
		FROM SSP_ANL_ESS_REQ A (NOLOCK)
		INNER JOIN #TMP_SSP_ANL_ESS_REQ_TEMP B (NOLOCK)
			ON A.DM_REQ_NO		= B.DM_REQ_NO
			AND A.DIVISION_ID	= B.DIVISION_ID
			AND A.ITEM_ID		= B.ITEM_ID
			AND A.ITEM_SEQ		= B.ITEM_SEQ
			AND A.PROJECT_CODE	= B.PROJECT_CODE
			AND A.YYYYMMDD		= B.DM_REQUEST_DATE
			-- 220829 jilee 삭제일때도 History 테이블에 남을수 있게
			--AND B.ACTIVE_FLAG	<> 'D'
		WHERE 1=1
		;

		--SELECT * FROM  #TMP_SSP_ANL_ESS_REQ
		--;
		
		------------------------------------------------------------------------------------------------------------- 
		-- ALLO 수량 UPDATE후 PR 수량 INSERT OR UPDATE-- 
		-- #TMP_SSP_ANL_ESS_REQ MERGE 처리
		-------------------------------------------------------------------------------------------------------------- 
		MERGE INTO SSP_ANL_ESS_PR M
		USING
		(
			SELECT  A.PR_CHECK
			, A.DM_REQ_NO
			, A.ITEM_SEQ
			, A.ITEM_ID
			, A.DIVISION_ID
			, A.PROJECT_CODE
			, A.SCM_SITE_ID
			, A.PLANT_SITE_ID
			, A.DOM_EXP
			, A.FCST_TYPE
			, A.INCOTERMS
			, A.YYYYMMDD
			, A.PLAN_QTY
			, A.UOM
			, A.INV_ALLO_QTY
			, A.SLOC_ID
			, A.SLOC_PLANT_ID
			, A.PUCH_MGR
			, A.PUCH_GROUP
			, A.PR_HEADER
			, A.PR_ITEM_DETAIL
			, A.DM_REQUESTED_BY
			, CONVERT(VARCHAR(8), CONVERT(DATETIME, A.YYYYMMDD), 112) AS DM_REQUEST_DATE
			, A.BOD_ID
			, A.HOLD_FLAG
			, A.CONFIRM_ID
			, A.CREATED_BY
			, A.CREATION_DATE
			, A.LAST_UPDATED_BY
			, A.LAST_UPDATE_DATE
			, A.ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10
			, A.NET_YN
			FROM #TMP_SSP_ANL_ESS_REQ A WITH(NOLOCK)
			WHERE 1=1
		) N
		 ON	M.DM_REQ_NO		= N.DM_REQ_NO	  
		AND M.PR_ITEM_ID	= N.ITEM_ID
		AND M.PR_ITEM_SEQ	= N.ITEM_SEQ
		AND M.YYYYMMDD		= N.DM_REQUEST_DATE
		AND M.PR_NO IS NULL
		WHEN MATCHED THEN
		UPDATE
			SET M.PR_REQ_QTY       = (N.PLAN_QTY - N.INV_ALLO_QTY)
			,   M.PR_CONFIRMED_BY  = @P_USER_ID
			,   M.PR_CONFIRM_DATE  = CONVERT(VARCHAR(8), CONVERT(DATETIME, GETDATE()), 112)
			,	M.LAST_UPDATED_BY  = N.LAST_UPDATED_BY  
			,	M.LAST_UPDATE_DATE = N.LAST_UPDATE_DATE   
			,	M.ATTRIBUTE1       = N.ATTRIBUTE1 
			,	M.ATTRIBUTE2       = N.ATTRIBUTE2        
			,	M.ATTRIBUTE3       = N.ATTRIBUTE3        
			,	M.ATTRIBUTE4       = N.ATTRIBUTE4        
			,	M.ATTRIBUTE5       = N.ATTRIBUTE5        
			,	M.ATTRIBUTE6       = N.ATTRIBUTE6        
			,	M.ATTRIBUTE7       = N.ATTRIBUTE7        
			,	M.ATTRIBUTE8       = N.ATTRIBUTE8        
			,	M.ATTRIBUTE9       = N.ATTRIBUTE9        
			,	M.ATTRIBUTE10      = N.ATTRIBUTE10       

		WHEN NOT MATCHED THEN
		INSERT ( 	
			  DM_REQ_NO
			, PR_NO
			, PR_ITEM_SEQ
			, PR_ITEM_ID
			--, PR_STATUS			-- 컬럼삭제 20210330
			, ERP_PR_STATUS
			, YYYYMMDD
			, PR_REQ_QTY
			, UOM
			, PR_CONFIRMED_BY
			, PR_CONFIRM_DATE
			, CREATED_BY
			, CREATION_DATE
			, LAST_UPDATED_BY
			, LAST_UPDATE_DATE
			, ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10
		)
		VALUES (
					N.DM_REQ_NO
					, NULL		--  PR NO
					, N.ITEM_SEQ
					, N.ITEM_ID
					--, 'A'		--	PR 요청		-- 컬럼삭제 20210330
					, NULL		--	ERP_PR_STATUS
					, N.DM_REQUEST_DATE
					, (N.PLAN_QTY - N.INV_ALLO_QTY)
					, N.UOM
					, @P_USER_ID		--  PR_CONFIRMED_BY 
					, CONVERT(VARCHAR(8), CONVERT(DATETIME, GETDATE()), 112)		--	PR_CONFRIM_DATE
					, N.CREATED_BY                       
					, N.CREATION_DATE                     
					, N.LAST_UPDATED_BY                   
					, N.LAST_UPDATE_DATE                  
					, N.ATTRIBUTE1, N.ATTRIBUTE2, N.ATTRIBUTE3, N.ATTRIBUTE4, N.ATTRIBUTE5, N.ATTRIBUTE6, N.ATTRIBUTE7, N.ATTRIBUTE8, N.ATTRIBUTE9, N.ATTRIBUTE10
		 );

 ------------------------------------------------------------------------------------------------------------- 
		 --Request No에 요청된 모든 자재가 재고 Allo되어 ERP에서 PR 생성이 불가 한경우
		 --1) SSP에서 PR Check Blocking
		 --2) 해당 내역 BNP IN 요청자에게 메일 전송 
		-------------------------------------------------------------------------------------------------------------- 
		-- KIMYONGHO 메일 과다 발송 확인 되어 임시 조치함
		-- CASE 1 , DM_REQ_NO 한 건인 대상에 대하여 요청수량과 ALLO수량이 동일하여 0이되는 건에 대하여 메일 발송
		/*************************************** CASE 1 START **********************************************************/
		SET @MST_LOOP_CNT = 0;
		WHILE LEN(@RECV_ACTIVE_FLAG) > 0 AND @MST_LOOP_CNT < 1
		BEGIN
			SET @MST_LOOP_CNT = @MST_LOOP_CNT + 1;			

			-- 각 컬럼들에 대한 스플릿처리로직 스타트
			BEGIN			
				SET @V_DM_REQ_NO					= DBO.SCM_ARR_SPL_VAL( @P_DM_REQ_NO,			@V_DELIMITER, @MST_LOOP_CNT );
			END;

			SELECT @V_NON_PR_QTY = COUNT(*)
			FROM #TMP_SSP_ANL_ESS_REQ N WITH(NOLOCK)
			WHERE 1=1
			  AND N.DM_REQ_NO = @V_DM_REQ_NO
			  AND (N.PLAN_QTY - N.INV_ALLO_QTY) = 0
			  HAVING COUNT(*) = 1

			--SELECT @V_NON_PR_QTY = COUNT(*)
			--FROM SSP_ANL_ESS_PR M WITH(NOLOCK)
			--JOIN #TMP_SSP_ANL_ESS_REQ N
			--		ON	M.DM_REQ_NO	= N.DM_REQ_NO	  
			--	AND M.PR_ITEM_ID	= N.ITEM_ID
			--	AND M.PR_ITEM_SEQ	= N.ITEM_SEQ
			--	AND M.YYYYMMDD		= N.DM_REQUEST_DATE
			--	AND M.PR_NO IS NULL
			--WHERE 1=1
			--  AND N.DM_REQ_NO = @V_DM_REQ_NO
			--  AND (N.PLAN_QTY - N.INV_ALLO_QTY) = 0
			;

			IF @V_NON_PR_QTY > 0
			BEGIN
--				EXEC [dbo].[PR_SSP_MAIL_SEND_PR_REQUEST] @V_PLAN_START_YYYYMMDD, 'C100', @V_DM_REQ_NO, 'KO', 76	 
				EXEC [dbo].[PR_SSP_MAIL_SEND_PR_REQUEST] @V_PLAN_START_YYYYMMDD, @v_C100, @V_DM_REQ_NO, 'KO', 76	 
			END

		END;
		
		/*************************************** CASE 1 END **********************************************************/

		-- CASE 2 , PR 요청 DM_REQ_NO에 대해서 메일 발송
		-- PR 요청은 한 개 DM_REQ_NO만 요청 가능함으로 루프 돌릴 필요없음
		/*************************************** CASE 2 START ********************************************************/

		SET @MST_LOOP_CNT = 0;
		WHILE LEN(@RECV_ACTIVE_FLAG) > 0 AND @MST_LOOP_CNT < 1
		BEGIN
			SET @MST_LOOP_CNT = @MST_LOOP_CNT + 1;			

			-- 각 컬럼들에 대한 스플릿처리로직 스타트
			BEGIN			
				SET @V_DM_REQ_NO					= DBO.SCM_ARR_SPL_VAL( @P_DM_REQ_NO,			@V_DELIMITER, @MST_LOOP_CNT );
			END;

			SELECT @V_NON_PR_QTY = COUNT(*)
			FROM SSP_ANL_ESS_PR M WITH(NOLOCK)
			JOIN #TMP_SSP_ANL_ESS_REQ N
					ON	M.DM_REQ_NO	= N.DM_REQ_NO	  
				AND M.PR_ITEM_ID	= N.ITEM_ID
				AND M.PR_ITEM_SEQ	= N.ITEM_SEQ
				AND M.YYYYMMDD		= N.DM_REQUEST_DATE
				AND N.PR_CHECK = 'True'
			WHERE 1=1
			  AND N.DM_REQ_NO = @V_DM_REQ_NO
			;

			IF @V_NON_PR_QTY > 0
			BEGIN
--				EXEC [dbo].[PR_SSP_MAIL_SEND_PR_REQUEST] @V_PLAN_START_YYYYMMDD, 'C100', @V_DM_REQ_NO, 'KO', 76	 
				EXEC [dbo].[PR_SSP_MAIL_SEND_PR_REQUEST] @V_PLAN_START_YYYYMMDD, @v_C100, @V_DM_REQ_NO, 'KO', 76	 
			END

		END;
		/*************************************** CASE 2 END ********************************************************/


		------------------------------------------------------------------------------------------------------------- 
		-- PR생성요청 I/F 정보 생성
		-- XIF_ERP_PR_REQ_S 
		-------------------------------------------------------------------------------------------------------------- 

		--IFSEQNO 생성
		SELECT @v_infseqno = CONVERT(CHAR(8),GETDATE(),112) + RIGHT( '00000'+ CONVERT(VARCHAR,ISNULL(MAX(RIGHT(IFSEQNO,6)),0)+1 ) ,6)
		FROM XIF_ERP_PR_REQ_S_SN
		WHERE IFSEQNO LIKE CONVERT(CHAR(8),GETDATE(),112) +'%' ;


		INSERT INTO XIF_ERP_PR_REQ_S_SN (
			  IF_SEQ
			, IF_TYPE
			, IF_ID
			, IF_INS_DATE
			, IF_FLAG
			, IF_SND_DATE
			, IFSEQNO
			, DM_REQ_NO
			, PR_NO
			, PR_ITEM_SEQ
			, PR_ITEM_ID
			, ERP_PR_STATUS
			, ERP_PR_MESSAGE
			, SLOC_ID
			, SLOC_PLANT_ID
			, PR_HEADER
			, PR_ITEM_DETAIL
			, YYYYMMDD
			, PR_REQ_QTY
			, UOM
			, PROJECT_CODE
			, PUCH_GROUP
			, PUCH_MGR
			, DM_REQUESTED_BY
			, PR_CONFIRM_DATE
			, ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10
		)
		SELECT 'OSCM' + CONVERT(VARCHAR,GETDATE(),12) + dbo.FN_ZERO_LPAD(CONVERT(VARCHAR,NEXT VALUE FOR dbo.SEQ1_XIF_SCS),10)   -- IF_SEQ
				, 'I'
				, 'OSCM_OERP_PR_REQ_S'
				, @v_time_for_system
				, 'N'
				, @v_time_for_system --NULL					--	IF_SND_DATE
				, @v_infseqno			--  IFSEQNO
				, A.DM_REQ_NO			
				, '-' --					--  PR_NO
				, A.PR_ITEM_SEQ
				, A.PR_ITEM_ID
				, '-'					--	ERP_PR_STATUS
				, '-'					--	ERP_PR_MESSAGE
				, ISNULL (X2.NEW_VALUE2, A.SLOC_ID)	AS SLOC_ID
				, ISNULL (X1.NEW_VALUE1, A.SLOC_PLANT_ID)	AS SLOC_PLANT_ID
				, A.PR_HEADER
				, A.PR_ITEM_DETAIL
				, A.YYYYMMDD
				, A.PR_REQ_QTY
				, A.UOM
				, A.PROJECT_CODE
				, ISNULL (X3.NEW_VALUE1, A.PUCH_GROUP)	AS PUCH_GROUP
				, A.PUCH_MGR
				, A.DM_REQUESTED_BY
				, A.PR_CONFIRM_DATE		--  PR_CONFIRM_DATE
				, A.ATTRIBUTE1, A.ATTRIBUTE2, A.ATTRIBUTE3, A.ATTRIBUTE4, A.ATTRIBUTE5 
				, A.ATTRIBUTE6, A.ATTRIBUTE7, A.ATTRIBUTE8, A.ATTRIBUTE9, A.ATTRIBUTE10 
		FROM
		(
			SELECT 
				  A.DM_REQ_NO			
				, A.PR_ITEM_SEQ
				, A.PR_ITEM_ID
				, B.SLOC_ID
				, B.SLOC_PLANT_ID
				, LEFT(B.PR_HEADER, 300)			AS PR_HEADER-- jilee PR Header, PR Detail 300자 제한
				, LEFT(B.PR_ITEM_DETAIL, 300)		AS PR_ITEM_DETAIL-- jilee PR Header, PR Detail 300자 제한
				, A.YYYYMMDD
				, ISNULL(A.PR_REQ_QTY,0)			AS PR_REQ_QTY
				, A.UOM
				, B.PROJECT_CODE
				, B.PUCH_GROUP
				, B.PUCH_MGR
				, B.DM_REQUESTED_BY
				, A.PR_CONFIRM_DATE		--  PR_CONFIRM_DATE
				, CONCAT(ROW_NUMBER() OVER(PARTITION BY A.DM_REQ_NO ORDER BY A.PR_ITEM_ID), '0') AS ATTRIBUTE1 --PR_ITEM_SEQ
				, ISNULL(A.ATTRIBUTE2,'-') AS ATTRIBUTE2
				, ISNULL(A.ATTRIBUTE3,'-') AS ATTRIBUTE3
				, ISNULL(A.ATTRIBUTE4,'-') AS ATTRIBUTE4
				, ISNULL(A.ATTRIBUTE5,'-') AS ATTRIBUTE5
				, ISNULL(A.ATTRIBUTE6,'-') AS ATTRIBUTE6
				, ISNULL(A.ATTRIBUTE7,'-') AS ATTRIBUTE7
				, ISNULL(A.ATTRIBUTE8,'-') AS ATTRIBUTE8
				, ISNULL(A.ATTRIBUTE9,'-') AS ATTRIBUTE9
				, ISNULL(A.ATTRIBUTE10,'-') AS ATTRIBUTE10
			FROM SSP_ANL_ESS_PR A WITH(NOLOCK)
		
			INNER JOIN #TMP_SSP_ANL_ESS_REQ B WITH(NOLOCK)
				ON	A.DM_REQ_NO		= B.DM_REQ_NO	  
				AND A.PR_ITEM_ID	= B.ITEM_ID
				AND A.PR_ITEM_SEQ	= B.ITEM_SEQ
				AND A.YYYYMMDD		= B.DM_REQUEST_DATE      

			WHERE 1=1
			AND B.PR_CHECK ='True'
			AND A.PR_REQ_QTY > 0
			AND A.PR_NO IS NULL
		) A
		LEFT OUTER JOIN NERP_CONV_MASTER X1 WITH(NOLOCK) ON X1.CODETYPE = 'PLANT_ID'	AND A.SLOC_PLANT_ID = X1.OLD_VALUE1
		LEFT OUTER JOIN NERP_CONV_MASTER X2 WITH(NOLOCK) ON X2.CODETYPE = 'STORAGE_ID' AND A.SLOC_PLANT_ID = X2.OLD_VALUE1 AND A.SLOC_ID = X2.OLD_VALUE2
		LEFT OUTER JOIN NERP_CONV_MASTER X3 WITH(NOLOCK) ON X3.CODETYPE = 'PURCHASE_GROUP_ID' AND A.PUCH_GROUP = X3.OLD_VALUE1

		;
					
		
		--SELECT * FROM #TMP_SSP_ANL_ESS_REQ;


		------------------------------------------------------------------------------------------------------------- 
		-- SSP_ANL_ESS_REQ_H 정보 생성
		-- #TMP_SSP_ANL_ESS_REQ 처리
		-------------------------------------------------------------------------------------------------------------- 
		INSERT INTO SSP_ANL_ESS_REQ_H (
			   HISTORY_SEQ
	          ,[DM_REQ_NO]			
			  ,[ITEM_SEQ]			
			  ,[ITEM_ID]			
			  ,[DIVISION_ID]		
			  ,[PROJECT_CODE]		
			  ,[SCM_SITE_ID]		
			  ,[PLANT_SITE_ID]		
			  ,[DOM_EXP]			
			  ,[FCST_TYPE]			
			  ,[INCOTERMS]			
			  ,[YYYYMMDD]			
			  ,[PLAN_QTY]			
			  ,[UOM]				
			  ,[INV_ALLO_QTY]		
			  ,[SLOC_ID]			
			  ,[SLOC_PLANT_ID]		
			  ,[PUCH_MGR]			
			  ,[PUCH_GROUP]		
			  ,[PR_HEADER]			
			  ,[PR_ITEM_DETAIL]	
			  ,[DM_REQUESTED_BY]	
			  ,[DM_REQUEST_DATE]	
			  ,[BOD_ID]			
			  --,[CONFIRM_FLAG]		
			  --,[CONFIRM_ID]		
			  ,[CREATED_BY]		
			  ,[CREATION_DATE]		
			  ,[LAST_UPDATED_BY]	
			  ,[LAST_UPDATE_DATE]	
			  )
		SELECT CONVERT(CHAR(8), GETDATE(), 112) + DBO.FN_ZERO_LPAD(CONVERT(VARCHAR,NEXT VALUE FOR DBO.SEQ1_SSP_ANL_ESS),6)  AS HISTORY_SEQ
	          ,[DM_REQ_NO]			
			  ,[ITEM_SEQ]			
			  ,[ITEM_ID]			
			  ,[DIVISION_ID]		
			  ,[PROJECT_CODE]		
			  ,[SCM_SITE_ID]		
			  ,[PLANT_SITE_ID]		
			  ,[DOM_EXP]			
			  ,[FCST_TYPE]			
			  ,[INCOTERMS]			
			  ,[YYYYMMDD]			
			  ,[PLAN_QTY]			
			  ,[UOM]				
			  ,[INV_ALLO_QTY]		
			  ,[SLOC_ID]			
			  ,[SLOC_PLANT_ID]		
			  ,[PUCH_MGR]			
			  ,[PUCH_GROUP]		
			  ,[PR_HEADER]			
			  ,[PR_ITEM_DETAIL]	
			  ,[DM_REQUESTED_BY]	
			  ,[DM_REQUEST_DATE]	
			  ,[BOD_ID]			
			  --,[CONFIRM_FLAG]		
			  --,[CONFIRM_ID]		
			  ,[CREATED_BY]		
			  ,[CREATION_DATE]		
			  ,[LAST_UPDATED_BY]	
			  ,[LAST_UPDATE_DATE]	
		  FROM #TMP_SSP_ANL_ESS_REQ
		;


		SET @V_LOG_TYPE = 'END';
		SET @V_LOG_MESSAGE = '########## END OF PROCEDURE ##########';
		SET @V_DESCRIPTION = '';
		SET @D_EVENT_DATE = SYSDATETIME();
		EXEC PR_SCM_SYS_LOG_BATCH @V_PROGRAM_NAME, @V_LOG_TYPE, @N_LOG_COUNT, @V_LOG_MESSAGE, @V_DESCRIPTION, @D_EVENT_DATE;
					
		-- 결과코드, 결과 카운트 반환
		SELECT  'S' AS RESULT_CODE,  @MAX_LOOP_CNT AS result_cnt, @v_infseqno AS IFSEQNO ;

		IF OBJECT_ID('tempdb..#TMP_SSP_ANL_ESS_REQ_TEMP') IS NOT NULL	
		DROP TABLE #TMP_SSP_ANL_ESS_REQ_TEMP;

		IF OBJECT_ID('tempdb..#TMP_SSP_ANL_ESS_REQ') IS NOT NULL	
			DROP TABLE #TMP_SSP_ANL_ESS_REQ;

		IF OBJECT_ID('tempdb..#TMP_MST_STOCK') IS NOT NULL	
			DROP TABLE #TMP_MST_STOCK;

		IF OBJECT_ID('tempdb..#TMP_MST_PR_COUNT') IS NOT NULL	
			DROP TABLE #TMP_MST_PR_COUNT;

	END TRY

	 BEGIN CATCH
		  BEGIN
			INSERT INTO SCM_SYS_LOG_BATCH (PROGRAM_NAME
										  ,LOG_TYPE
										  ,LOG_COUNT
										  ,LOG_MESSAGE
										  ,DESCRIPTION
										  ,EVENT_DATE
										  ,CREATION_DATE
										  ,CREATED_BY
										  ,LAST_UPDATE_DATE
										  ,LAST_UPDATED_BY)
			VALUES (ERROR_PROCEDURE()
				   ,'ERROR'
				   ,NULL
				   ,ERROR_MESSAGE()
				   ,NULL
				   ,SYSDATETIME()
				   ,SYSDATETIME()
				   ,ERROR_PROCEDURE()
				   ,SYSDATETIME()
				   ,ERROR_PROCEDURE());

			IF @@TRANCOUNT > 0
			  COMMIT WORK;
		  END;

		  -- ERROR코드, ERRROR 메시지 반환
		  SELECT 'F' AS RESULT_CODE;
		  SELECT '[' + CONVERT(NVARCHAR(10), ERROR_NUMBER()) + ']' + ERROR_MESSAGE();
		END CATCH;


END


