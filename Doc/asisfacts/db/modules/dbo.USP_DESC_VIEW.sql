
-- DROP PROC USP_DESC_VIEW
CREATE PROCEDURE [dbo].[USP_DESC_VIEW]
(
    @V_TNAME    VARCHAR(100)
)
AS

BEGIN

/*******************************************************
    **   NAME: dbo.USP_DES_VIEW
    **   DESC: 테이블 정의 보기
    **   AUTH: KTH
    **   DATE: 2018.01.03
	  **   ETC : COMMENT 확인을 위해 단축키 등록 해서 사용.
    **   (실행예제)
         EXEC USP_DESC_VIEW SCM_MST_SSO_DEPT_INFO
  *****************************************************/
-- 스키마 명에 '[',']' 제거를 위해 추가
  SET @V_TNAME = REPLACE(REPLACE(@V_TNAME,'[',''),']','')

 SELECT * INTO #TEMP_TB
 FROM
 (
  SELECT NAME, OBJECT_ID FROM sys.tables WITH (NOLOCK)
  UNION ALL
  SELECT NAME, OBJECT_ID FROM sys.synonyms WITH (NOLOCK)  -- synonyms 추가
 ) X


SELECT 
	B.NAME AS [TABLE_NAME] 
, C.value AS [COMMENT] 
FROM  #TEMP_TB AS B WITH (NOLOCK)
INNER JOIN sys.extended_properties AS C WITH (NOLOCK)
ON B.object_id = C.major_id
WHERE B.NAME =@V_TNAME
AND C.minor_id = '0'
AND C.NAME ='MS_Description'
--UNION 

SELECT 
    A.TABLE_SCHEMA AS [SCHEMA]
  , A.TABLE_NAME AS [TABLE_NAME] 
  , A.COLUMN_NAME AS [COLUMN_NAME]
  , B.ColumnDescription AS [COMMENT] 
  , A.ORDINAL_POSITION AS [ORDER]
  , CASE WHEN ISNULL(A.CHARACTER_MAXIMUM_LENGTH,'')>0 THEN A.DATA_TYPE +'(' + CONVERT(VARCHAR(10),A.CHARACTER_MAXIMUM_LENGTH) + ')' 
         WHEN A.DATA_TYPE = 'decimal' THEN A.DATA_TYPE +'(' + CONVERT(VARCHAR(10),A.NUMERIC_PRECISION) + ',' +CONVERT(VARCHAR(10),A.NUMERIC_SCALE)  + ')' 
         WHEN A.DATA_TYPE = 'numeric' THEN A.DATA_TYPE +' (' + CONVERT(VARCHAR(10),A.NUMERIC_PRECISION) + ',' +CONVERT(VARCHAR(10),A.NUMERIC_SCALE)  + ')' 
    ELSE  A.DATA_TYPE END AS [DATA_TYPE] 
  , CASE WHEN A.IS_NULLABLE='NO' THEN 'NOT NULL' ELSE 'NULL' END AS [NULLABLE]
  , ISNULL(A.COLUMN_DEFAULT, '')     AS [DEFAULT]
  , CASE WHEN (D.CONSTRAINT_NAME) IS NULL THEN '' 
    ELSE 'PK' END AS 'PK'
  , CASE WHEN (E.CONSTRAINT_NAME) IS NULL THEN '' 
    ELSE 'FK' END AS 'FK'

  FROM  INFORMATION_SCHEMA.COLUMNS AS A WITH (NOLOCK)
  INNER JOIN (
  SELECT A.name AS TableName
  , B.name AS ColumnName
  , C.Value     AS ColumnDescription
  FROM #TEMP_TB AS A WITH (NOLOCK)
  INNER JOIN sys.columns AS B WITH (NOLOCK)
  ON A.object_id = B.object_id
  LEFT OUTER  JOIN sys.extended_properties AS C WITH (NOLOCK)
  ON A.object_id = C.major_id
  AND B.column_id = c.minor_id
  AND C.NAME ='MS_Description' --OR C.NAME IS NULL
  ) AS B
  ON A.TABLE_NAME = B.TableName
  AND A.COLUMN_NAME = B.ColumnName
  OUTER APPLY (SELECT TOP 1 CONSTRAINT_NAME FROM INFORMATION_SCHEMA.KEY_COLUMN_USAGE B WITH (NOLOCK) WHERE  A.TABLE_NAME = B.TABLE_NAME AND A.COLUMN_NAME = B.COLUMN_NAME AND B.CONSTRAINT_NAME LIKE 'PK_%') D
   OUTER APPLY (SELECT TOP 1 CONSTRAINT_NAME FROM INFORMATION_SCHEMA.KEY_COLUMN_USAGE B WITH (NOLOCK) WHERE  A.TABLE_NAME = B.TABLE_NAME AND A.COLUMN_NAME = B.COLUMN_NAME AND B.CONSTRAINT_NAME LIKE 'FK_%') E
  WHERE A.TABLE_NAME = @V_TNAME
  ORDER BY A.TABLE_NAME,A.ORDINAL_POSITION
END


