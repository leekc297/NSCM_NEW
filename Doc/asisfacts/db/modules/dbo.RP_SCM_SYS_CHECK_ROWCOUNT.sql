CREATE PROCEDURE [dbo].[RP_SCM_SYS_CHECK_ROWCOUNT]
AS
  BEGIN
    SET TRANSACTION ISOLATION LEVEL READ COMMITTED;
    SET NOCOUNT ON; 
    SET XACT_ABORT ON;

    -- LOG 용 변수 설정
    DECLARE @v_batch_user NVARCHAR(150) = 'scm_batch';
	DECLARE @v_program_name NVARCHAR(150) = 'RP_SCM_SYS_CHECK_ROWCOUNT';
    DECLARE @v_log_type     NVARCHAR(30); -- START/END/ERROR/...
    DECLARE @n_log_count    INTEGER = 0;
    DECLARE @v_log_message  NVARCHAR(1000);
    DECLARE @v_description  NVARCHAR(500);
    DECLARE @d_event_date   DATETIME;
	DECLARE @v_ifseqno     NVARCHAR(30); 
	DECLARE @n_history_seq	BIGINT;

	-- 시작 LOG
    SET @v_log_type = 'START';
    SET @v_log_message = '########## Start of procedure ##########';
    SET @v_description = '';
    SET @d_event_date = SYSDATETIME();

    EXEC PR_SCM_SYS_LOG_BATCH @v_program_name, @v_log_type, @n_log_count, @v_log_message, @v_description, @d_event_date;

    BEGIN TRY
	--BEGIN TRANSACTION
      BEGIN
	   
	    INSERT INTO SCM_SYS_CHECK_INF_PROC(YYYYMMDD,TABLE_NAME,BEFORE_TARGET_CNT,CREATION_DATE,LAST_UPDATE_DATE)
		SELECT  CONVERT(CHAR(8),getdate(), 112),'DM_DNM_SALES_RESULT',COUNT(*),GETDATE(),GETDATE() FROM DM_DNM_SALES_RESULT
		UNION ALL
		SELECT  CONVERT(CHAR(8),getdate(), 112),'SCM_DNM_DELIVERY_TRACKING',COUNT(*),GETDATE(),GETDATE() FROM SCM_DNM_DELIVERY_TRACKING
		UNION ALL
		SELECT  CONVERT(CHAR(8),getdate(), 112),'SCM_DNM_EXFACTORY_RESULT',COUNT(*),GETDATE(),GETDATE() FROM SCM_DNM_EXFACTORY_RESULT
		UNION ALL
		SELECT  CONVERT(CHAR(8),getdate(), 112),'SCM_DNM_INTRANSIT',COUNT(*),GETDATE(),GETDATE() FROM SCM_DNM_INTRANSIT
		UNION ALL
		SELECT  CONVERT(CHAR(8),getdate(), 112),'SCM_DNM_MAT_DOCUMENT',COUNT(*),GETDATE(),GETDATE() FROM SCM_DNM_MAT_DOCUMENT
		UNION ALL
		SELECT  CONVERT(CHAR(8),getdate(), 112),'SCM_DNM_MAT_IMPORT_BL',COUNT(*),GETDATE(),GETDATE() FROM SCM_DNM_MAT_IMPORT_BL
		UNION ALL
		SELECT  CONVERT(CHAR(8),getdate(), 112),'SCM_DNM_MAT_INBOUND_DO',COUNT(*),GETDATE(),GETDATE() FROM SCM_DNM_MAT_INBOUND_DO
		UNION ALL
		SELECT  CONVERT(CHAR(8),getdate(), 112),'SCM_DNM_MAT_PO',COUNT(*),GETDATE(),GETDATE() FROM SCM_DNM_MAT_PO
		UNION ALL
		SELECT  CONVERT(CHAR(8),getdate(), 112),'SCM_DNM_MAT_PO_RECEIPT',COUNT(*),GETDATE(),GETDATE() FROM SCM_DNM_MAT_PO_RECEIPT
		UNION ALL
		SELECT  CONVERT(CHAR(8),getdate(), 112),'SCM_DNM_PACKER_PROD_RESULT',COUNT(*),GETDATE(),GETDATE() FROM SCM_DNM_PACKER_PROD_RESULT
		UNION ALL
		SELECT  CONVERT(CHAR(8),getdate(), 112),'SCM_DNM_PACKER_PURCHASE_ORDER',COUNT(*),GETDATE(),GETDATE() FROM SCM_DNM_PACKER_PURCHASE_ORDER
		UNION ALL
		SELECT  CONVERT(CHAR(8),getdate(), 112),'SCM_DNM_SALES_ORDER_REMAIN',COUNT(*),GETDATE(),GETDATE() FROM SCM_DNM_SALES_ORDER_REMAIN
		UNION ALL
		SELECT  CONVERT(CHAR(8),getdate(), 112),'SCM_DNM_STOCK_CUSTOMER_CONSIGN',COUNT(*),GETDATE(),GETDATE() FROM SCM_DNM_STOCK_CUSTOMER_CONSIGN
		UNION ALL
		SELECT  CONVERT(CHAR(8),getdate(), 112),'SCM_DNM_STOCK_SALES',COUNT(*),GETDATE(),GETDATE() FROM SCM_DNM_STOCK_SALES
		UNION ALL
		SELECT  CONVERT(CHAR(8),getdate(), 112),'SCM_MST_CUSTOMER',COUNT(*),GETDATE(),GETDATE() FROM SCM_MST_CUSTOMER
		UNION ALL
		SELECT  CONVERT(CHAR(8),getdate(), 112),'SCM_MST_PROJECT',COUNT(*),GETDATE(),GETDATE() FROM SCM_MST_PROJECT
		UNION ALL
		SELECT  CONVERT(CHAR(8),getdate(), 112),'SCM_MST_PROJECT_ITEM',COUNT(*),GETDATE(),GETDATE() FROM SCM_MST_PROJECT_ITEM
		UNION ALL
		SELECT  CONVERT(CHAR(8),getdate(), 112),'SCM_MST_PROJECT_MAPPING',COUNT(*),GETDATE(),GETDATE() FROM SCM_MST_PROJECT_MAPPING
		UNION ALL
		SELECT  CONVERT(CHAR(8),getdate(), 112),'SCM_MST_PROJECT_MODEL_DEMAND_QTY',COUNT(*),GETDATE(),GETDATE() FROM SCM_MST_PROJECT_MODEL_DEMAND_QTY
		UNION ALL
		SELECT  CONVERT(CHAR(8),getdate(), 112),'SCM_MST_PROJECT_SCHEDULE',COUNT(*),GETDATE(),GETDATE() FROM SCM_MST_PROJECT_SCHEDULE
		UNION ALL
		SELECT  CONVERT(CHAR(8),getdate(), 112),'SCM_MST_SITE',COUNT(*),GETDATE(),GETDATE() FROM SCM_MST_SITE
		UNION ALL
		SELECT  CONVERT(CHAR(8),getdate(), 112),'SCM_MST_SLOC',COUNT(*),GETDATE(),GETDATE() FROM SCM_MST_SLOC
		UNION ALL
		SELECT  CONVERT(CHAR(8),getdate(), 112),'SCM_MST_SSO_DEPT_INFO',COUNT(*),GETDATE(),GETDATE() FROM SCM_MST_SSO_DEPT_INFO
		UNION ALL
		SELECT  CONVERT(CHAR(8),getdate(), 112),'SCM_MST_SSO_USER_INFO',COUNT(*),GETDATE(),GETDATE() FROM SCM_MST_SSO_USER_INFO
		UNION ALL
		SELECT  CONVERT(CHAR(8),getdate(), 112),'SCM_MST_VENDOR',COUNT(*),GETDATE(),GETDATE() FROM SCM_MST_VENDOR
		;

        IF @@TRANCOUNT > 0
		  BEGIN
            COMMIT WORK;
		  END;

      END
    --COMMIT TRANSACTION
    END TRY

    BEGIN CATCH
       IF @@TRANCOUNT > 0
		  BEGIN
            ROLLBACK;
		  END;
      -- ERROR LOG
      SET @v_log_type = 'ERROR';
      SET @v_log_message = CAST(ERROR_MESSAGE() AS NVARCHAR(1000));
      SET @v_description = 'ERROR_LINE : '+ CAST(ERROR_LINE() AS nvarchar(10));;
      SET @d_event_date = SYSDATETIME();
      EXEC PR_SCM_SYS_LOG_BATCH @v_program_name, @v_log_type, @n_log_count, @v_log_message, @v_description, @d_event_date;
    END CATCH;

    -- 종료 LOG
    SET @v_log_type = 'END';
    SET @v_log_message = '########## END of procedure ##########';
    SET @v_description = '';
    SET @d_event_date = SYSDATETIME();
    EXEC PR_SCM_SYS_LOG_BATCH @v_program_name, @v_log_type, @n_log_count, @v_log_message, @v_description, @d_event_date;

  END;
