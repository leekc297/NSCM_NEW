CREATE PROCEDURE [dbo].[DMF0051_1_RTF_RATIO_DIVIDE_BIZPLAN]
--DECLARE
    @p_division_id              NVARCHAR(30),
	@p_version_no               NVARCHAR(30)
	,@P_RTF_VER		NVARCHAR(50) --2024.03.18
AS
/*
  EXEC DMF0051_1_RTF_RATIO_DIVIDE_BIZPLAN @p_division_id='82', @p_version_no = 'BP_M_20230827_V001'
 
*/

BEGIN

    SET TRANSACTION ISOLATION LEVEL READ COMMITTED;
    SET NOCOUNT ON;
    SET XACT_ABORT ON;	

	DECLARE 	@s_SEQ				INT
	DECLARE 	@s_DIVISION_ID		NVARCHAR(MAX)
	DECLARE 	@s_VERSION_NO		NVARCHAR(MAX)
	DECLARE 	@s_CUTOFF_TYPE		NVARCHAR(MAX)
	DECLARE 	@s_CUTOFF_YYYYMMDD	NVARCHAR(MAX)
	DECLARE 	@s_DEPT_ID			NVARCHAR(MAX)
	DECLARE 	@s_PROJECT_CODE		NVARCHAR(MAX)
	DECLARE 	@s_PROJECT_NAME		NVARCHAR(MAX)
	DECLARE 	@s_SCM_SITE_ID		NVARCHAR(MAX)
	DECLARE 	@s_ITEM_ID			NVARCHAR(MAX)
	DECLARE 	@s_END_CUSTOMER		NVARCHAR(MAX)
	DECLARE 	@s_BIZ_TYPE			NVARCHAR(MAX)
	DECLARE 	@s_PLANT_SITE_ID	NVARCHAR(MAX)
	DECLARE 	@s_FCST_TYPE		NVARCHAR(MAX)
	DECLARE 	@s_DOM_EXP			NVARCHAR(MAX)
	DECLARE 	@s_INCOTERMS		NVARCHAR(MAX)
	DECLARE 	@s_ITEM_USE	        NVARCHAR(MAX)
	DECLARE 	@s_UNIT_ENERGY	    NUMERIC(30,10)
	DECLARE 	@s_CURRENCY	        NVARCHAR(MAX)
	DECLARE 	@s_MEASURE	        NVARCHAR(MAX)
	DECLARE 	@s_YYYYMM	        NVARCHAR(MAX)
	DECLARE 	@s_QTY	            NUMERIC(30,10)
	DECLARE 	@s_CELL_CODE        NVARCHAR(MAX)
	DECLARE 	@s_CELL_PER_PACK	NUMERIC(30,10)
	DECLARE 	@s_CELL_PER_MODULE	NUMERIC(30,10)
	DECLARE 	@s_MODULE_PER_PACK	NUMERIC(30,10)
	DECLARE 	@s_CELL_PROD_SITE	NVARCHAR(MAX)
	DECLARE 	@s_PRODUCT_GROUP	NVARCHAR(MAX)
	DECLARE 	@s_EE_CORP_ID		NVARCHAR(MAX)
	DECLARE 	@s_CELL_CORP_ID		NVARCHAR(MAX)
	DECLARE 	@s_PACK_CORP_ID		NVARCHAR(MAX)
	DECLARE 	@s_ALT_SIM_YN		NVARCHAR(MAX)
	DECLARE 	@s_PERIOD_YYMM		NVARCHAR(MAX)
	DECLARE 	@s_SCENARIO_TYPE	NVARCHAR(MAX)
	DECLARE 	@s_BASE_PRICE		NUMERIC(30,10)
	DECLARE 	@s_METAL_LINK_PRICE	NUMERIC(30,10)
	DECLARE 	@s_OTHER_PRICE		NUMERIC(30,10)
	DECLARE 	@s_TOTAL_PRICE		NUMERIC(30,10)
	DECLARE 	@s_METAL_LINK_YN	NVARCHAR(MAX)
	DECLARE 	@s_WORK_YYYYMMDD	NVARCHAR(MAX)
	DECLARE 	@s_OSP_YN			NVARCHAR(MAX)
	DECLARE 	@s_EXT_INT			NVARCHAR(MAX)
	DECLARE 	@s_ATTRIBUTE1		NVARCHAR(MAX)
	DECLARE 	@s_ATTRIBUTE2		NVARCHAR(MAX)

	DECLARE @i INT = 1;
	DECLARE @CNT INT = 0;		

    -- LOG 용 변수 설정
    DECLARE @v_batch_user   NVARCHAR(150) = N'scm_batch';
    DECLARE @v_program_name NVARCHAR(150) = N'DMF0051_1_RTF_RATIO_DIVIDE_BIZPLAN';
    DECLARE @v_log_type     NVARCHAR(30); -- START/END/ERROR/...
    DECLARE @n_log_count    INTEGER = 0;
    DECLARE @v_log_message  NVARCHAR(1000);
    DECLARE @v_description  NVARCHAR(500);      
    DECLARE @v_table_id     NVARCHAR(150) = N'DM_PLN_BIZPLAN_C'; 
    DECLARE @d_event_date   DATETIME;

    -- 시작 LOG
    SET @v_log_type = N'START';
    SET @v_log_message = N'########## Start of procedure ##########';
    SET @v_description =  @v_table_id + ' : ' + @p_division_id;
    SET @d_event_date = SYSDATETIME();
    EXEC PR_SCP_SYS_LOG_BATCH  @p_program_name  = @v_program_name
                              ,@p_log_type      = @v_log_type
                              ,@p_log_count     = @n_log_count 
                              ,@p_log_message   = @v_log_message 
                              ,@p_description   = @v_description 
                              ,@p_event_date    = @d_event_date 
                              ,@p_user_id       = @v_batch_user
                              ;

	IF OBJECT_ID (N'tempdb..#TMP_RTF', N'U') IS NOT NULL 					DROP TABLE #TMP_RTF
	IF OBJECT_ID (N'tempdb..#SCP_TEMP', N'U') IS NOT NULL 					DROP TABLE #SCP_TEMP
	IF OBJECT_ID (N'tempdb..#TMP_DM_PLN_BIZPLAN', N'U') IS NOT NULL 		DROP TABLE #TMP_DM_PLN_BIZPLAN
	IF OBJECT_ID (N'tempdb..#TMP_RTF_RATIO', N'U') IS NOT NULL 				DROP TABLE #TMP_RTF_RATIO
	IF OBJECT_ID (N'tempdb..#TMP_BP_CONFIRM', N'U') IS NOT NULL 			DROP TABLE #TMP_BP_CONFIRM
	IF OBJECT_ID (N'tempdb..#TMP_REMAIN', N'U') IS NOT NULL 			    DROP TABLE #TMP_REMAIN
	IF OBJECT_ID (N'tempdb..#TMP_BP_RTF', N'U') IS NOT NULL 				DROP TABLE #TMP_BP_RTF
		
	CREATE TABLE #TMP_RTF_RATIO(
			 DIVISION_ID	 NVARCHAR(MAX)
			,VERSION_NO		 NVARCHAR(MAX)
			,SCM_SITE_ID	 NVARCHAR(MAX)
			,PROJECT_CODE	 NVARCHAR(MAX)
			,ITEM_ID		 NVARCHAR(MAX)
			,END_CUSTOMER		 NVARCHAR(MAX)
			,BIZ_TYPE		 NVARCHAR(MAX)
			,PLANT_SITE_ID		 NVARCHAR(MAX)
			,FCST_TYPE		 NVARCHAR(MAX)
			,DOM_EXP		 NVARCHAR(MAX)
			,INCOTERMS		 NVARCHAR(MAX)
			,CURRENCY		 NVARCHAR(MAX)
			,CELL_PROD_SITE		 NVARCHAR(MAX)
			,MEASURE		 NVARCHAR(MAX)
			,YYYYMM			 NVARCHAR(MAX)
			,EE_CORP_ID		 NVARCHAR(MAX)
			,CELL_CORP_ID	 NVARCHAR(MAX)
			,PACK_CORP_ID	 NVARCHAR(MAX)
			,OSP_YN			 NVARCHAR(MAX)
			,ATTRIBUTE1		 NVARCHAR(MAX)
			,ATTRIBUTE2		 NVARCHAR(MAX)
			,QTY			 INT
			,RATIO			 FLOAT								  
	)

 BEGIN TRY

		BEGIN

		    -- 기존 BP Conf 삭제 : SalesAmt_CUR / SalesAmt_KRW  삭제 후 재계산
			DELETE FROM DM_PLN_BIZPLAN_C 
			WHERE DIVISION_ID = @p_division_id
			AND   VERSION_NO  = @p_version_no
			AND   MEASURE    IN ('Business_Plan_Conf', 'SalesAmt_CUR', 'SalesAmt_KRW')

			/*-------------------------------------------------------------------------
			-- 1.0 : Business_Plan_Conf 생성
			-------------------------------------------------------------------------*/
			-- BIZPLAN 을 BIZPLAN_CONF로 일괄 데이터 INSERT 
			INSERT INTO DM_PLN_BIZPLAN_C (SEQ,DIVISION_ID,VERSION_NO,CUTOFF_TYPE,CUTOFF_YYYYMMDD,DEPT_ID,PROJECT_CODE,SCM_SITE_ID,ITEM_ID,END_CUSTOMER
				,BIZ_TYPE,PLANT_SITE_ID,FCST_TYPE,DOM_EXP,INCOTERMS,ITEM_USE,UNIT_ENERGY,CURRENCY,MEASURE,YYYYMM,QTY,PROJECT_NAME,CELL_PROD_SITE,EE_CORP_ID
				,CELL_CORP_ID,PACK_CORP_ID,EXT_INT,PRODUCT_GROUP,ALT_SIM_YN,CELL_CODE,CELL_PER_MODULE,MODULE_PER_PACK,CELL_PER_PACK,PERIOD_YYMM,SCENARIO_TYPE
				,BASE_PRICE,METAL_LINK_PRICE,OTHER_PRICE,TOTAL_PRICE,METAL_LINK_YN,WORK_YYYYMMDD,OSP_YN,CREATED_BY,CREATION_DATE,LAST_UPDATED_BY,LAST_UPDATE_DATE,TRANSFER_FLAG
				,TRANSFER_DATE,ATTRIBUTE1,ATTRIBUTE2,ATTRIBUTE3,ATTRIBUTE4)
			SELECT SEQ,DIVISION_ID,VERSION_NO,CUTOFF_TYPE,CUTOFF_YYYYMMDD,DEPT_ID,PROJECT_CODE,SCM_SITE_ID,ITEM_ID,END_CUSTOMER
				,BIZ_TYPE,PLANT_SITE_ID,FCST_TYPE,DOM_EXP,INCOTERMS,ITEM_USE,UNIT_ENERGY,CURRENCY,'Business_Plan_Conf' MEASURE,YYYYMM,QTY,PROJECT_NAME,CELL_PROD_SITE,EE_CORP_ID
				,CELL_CORP_ID,PACK_CORP_ID,EXT_INT,PRODUCT_GROUP,ALT_SIM_YN,CELL_CODE,CELL_PER_MODULE,MODULE_PER_PACK,CELL_PER_PACK,PERIOD_YYMM,SCENARIO_TYPE
				,BASE_PRICE,METAL_LINK_PRICE,OTHER_PRICE,TOTAL_PRICE,METAL_LINK_YN,WORK_YYYYMMDD,OSP_YN,'scm_batch' CREATED_BY,GETDATE() CREATION_DATE,'scm_batch' LAST_UPDATED_BY,GETDATE() LAST_UPDATE_DATE, NULL TRANSFER_FLAG
				,GETDATE() TRANSFER_DATE,ATTRIBUTE1,ATTRIBUTE2,ATTRIBUTE3,ATTRIBUTE4
			 FROM DM_PLN_BIZPLAN_C a WITH(NOLOCK)
	        WHERE DIVISION_ID = @p_division_id 
	          AND VERSION_NO  = @p_version_no
	          AND MEASURE     = 'Business_Plan'

			/*-------------------------------------------------------------------------
			-- 1.1 : Business_Plan_Conf SCP 생산지 분할
			-------------------------------------------------------------------------*/

			-- 분할을 위한 RTF 정보
			DECLARE @v_PLAN_ID NVARCHAR(30)
			DECLARE @v_YYYYMMDD NVARCHAR(8)
			DECLARE @v_PLAN_START_DATE NVARCHAR(6)

			--SELECT @v_PLAN_ID = MAX(PLAN_ID) FROM SCP_ANL_BUSINESS_PLAN_RTF_DM WITH(NOLOCK) WHERE DIVISION_ID = @p_division_id 
			SET @v_PLAN_ID = @P_RTF_VER--2024.03.18 넘겨준 값 사용
			SELECT @v_PLAN_START_DATE = PLAN_START_DATE FROM SCP_ANL_BUSINESS_PLAN_INFO WITH(NOLOCK) WHERE DIVISION_ID = @p_division_id AND PLAN_ID = SUBSTRING(@v_PLAN_ID, 1, 12)

			SET @v_YYYYMMDD =  SUBSTRING(@v_PLAN_ID, 1, 8);

			SELECT DIVISION_ID, VERSION_NO, CUTOFF_TYPE, CUTOFF_YYYYMMDD, DEPT_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, END_CUSTOMER, BIZ_TYPE, PLANT_SITE_ID, FCST_TYPE, DOM_EXP, INCOTERMS
			     , ITEM_USE, UNIT_ENERGY, CURRENCY, MEASURE, YYYYMM, QTY, PROJECT_NAME, CELL_PROD_SITE, EE_CORP_ID, CELL_CORP_ID, PACK_CORP_ID, EXT_INT, PRODUCT_GROUP, ALT_SIM_YN
				 , CELL_CODE, CELL_PER_MODULE, MODULE_PER_PACK, CELL_PER_PACK, PERIOD_YYMM, SCENARIO_TYPE, BASE_PRICE, METAL_LINK_PRICE, OTHER_PRICE, TOTAL_PRICE, METAL_LINK_YN, WORK_YYYYMMDD, OSP_YN
				 , ATTRIBUTE1, ATTRIBUTE2
			INTO #TMP_RTF
			FROM DM_PLN_BIZPLAN_C a WITH(NOLOCK)
	       WHERE DIVISION_ID = @p_division_id 
	         AND VERSION_NO  = @p_version_no
	         AND MEASURE     = 'RTF'

		END
	
		BEGIN

			SET @i   = 1;
			SET @CNT = 0;

			DECLARE @C_CNT		 INT
			DECLARE @DIVISION_ID NVARCHAR(30)
			DECLARE @PROJECT     NVARCHAR(30)
			DECLARE @SALES_SITE  NVARCHAR(30)
			DECLARE @MODEL_CODE  NVARCHAR(30)
			DECLARE @END_CUSTOMER   NVARCHAR(30)
			DECLARE @BIZ_TYPE   NVARCHAR(30)
			DECLARE @PLANT_SITE_ID   NVARCHAR(30)
			DECLARE @FCST_TYPE   NVARCHAR(30)
			DECLARE @DOM_EXP   NVARCHAR(30)
			DECLARE @INCOTERMS   NVARCHAR(30)
			DECLARE @CURRENCY   NVARCHAR(30)
			DECLARE @MEASURE   NVARCHAR(30)
			DECLARE @CELL_PROD_SITE   NVARCHAR(30)
			DECLARE @YYYYMM      NVARCHAR(6)
			DECLARE @PO1         FLOAT
			DECLARE @PO2         FLOAT
			DECLARE @PO3         FLOAT


			SET @C_CNT = 0;


			SELECT ROW_NUMBER() OVER(ORDER BY DIVISION_ID) AS SEQ
			     , DIVISION_ID, VERSION_NO, CUTOFF_TYPE, CUTOFF_YYYYMMDD, DEPT_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, END_CUSTOMER, BIZ_TYPE, PLANT_SITE_ID, FCST_TYPE, DOM_EXP, INCOTERMS
			     , ITEM_USE, UNIT_ENERGY, CURRENCY, 'Business_Plan_Conf' MEASURE, YYYYMM, QTY, PROJECT_NAME, CELL_PROD_SITE, EE_CORP_ID, CELL_CORP_ID, PACK_CORP_ID, EXT_INT, PRODUCT_GROUP, ALT_SIM_YN
				 , CELL_CODE, CELL_PER_MODULE, MODULE_PER_PACK, CELL_PER_PACK, PERIOD_YYMM, SCENARIO_TYPE, BASE_PRICE, METAL_LINK_PRICE, OTHER_PRICE, TOTAL_PRICE, METAL_LINK_YN, WORK_YYYYMMDD, OSP_YN
				 , ATTRIBUTE1, ATTRIBUTE2
			INTO #TMP_DM_PLN_BIZPLAN
			FROM DM_PLN_BIZPLAN_C a WITH(NOLOCK)
	       WHERE DIVISION_ID = @p_division_id 
	         AND VERSION_NO  = @p_version_no
	         AND MEASURE     = 'Business_Plan'

			SELECT @CNT = COUNT(*) FROM #TMP_DM_PLN_BIZPLAN WITH(NOLOCK)
					   
			WHILE @i <= @CNT
			BEGIN
				BEGIN
					SELECT 
						 @DIVISION_ID = DIVISION_ID
						,@PROJECT     = PROJECT_CODE    
						,@SALES_SITE  = SCM_SITE_ID
						,@MODEL_CODE  = ITEM_ID
						,@END_CUSTOMER   = END_CUSTOMER  
						,@BIZ_TYPE   = BIZ_TYPE  
						,@PLANT_SITE_ID   = PLANT_SITE_ID  
						,@FCST_TYPE   = FCST_TYPE  
						,@DOM_EXP   = DOM_EXP  
						,@INCOTERMS   = INCOTERMS  
						,@CURRENCY   = CURRENCY  
						,@MEASURE   = MEASURE  
						,@CELL_PROD_SITE   = CELL_PROD_SITE  
						,@YYYYMM      = YYYYMM     
					FROM #TMP_DM_PLN_BIZPLAN WITH(NOLOCK)
				    WHERE SEQ = @i
				END
				
--PRINT 'A1=========================================================================================================================================='

				BEGIN
					SELECT @C_CNT = COUNT(*) FROM #TMP_RTF WITH(NOLOCK)
					WHERE 1=1
					AND DIVISION_ID  = @DIVISION_ID
					AND PROJECT_CODE = @PROJECT
					AND SCM_SITE_ID  = @SALES_SITE
					AND ITEM_ID      = @MODEL_CODE
					AND END_CUSTOMER    = @END_CUSTOMER
					AND BIZ_TYPE    = @BIZ_TYPE
					AND PLANT_SITE_ID    = @PLANT_SITE_ID
					AND FCST_TYPE    = @FCST_TYPE
					AND DOM_EXP    = @DOM_EXP
					AND INCOTERMS    = @INCOTERMS
					AND CURRENCY    = @CURRENCY
					--AND MEASURE    = @MEASURE
					AND CELL_PROD_SITE    = @CELL_PROD_SITE
					AND YYYYMM       = @YYYYMM
				END

				IF (@C_CNT > 1)
				BEGIN

					INSERT INTO #TMP_RTF_RATIO
					     (DIVISION_ID, VERSION_NO, SCM_SITE_ID, PROJECT_CODE, ITEM_ID, END_CUSTOMER, BIZ_TYPE, PLANT_SITE_ID, FCST_TYPE, DOM_EXP, INCOTERMS, CURRENCY, MEASURE, CELL_PROD_SITE
					    , YYYYMM, EE_CORP_ID, CELL_CORP_ID, PACK_CORP_ID, OSP_YN, ATTRIBUTE1, ATTRIBUTE2, QTY, RATIO
						 )
					SELECT DIVISION_ID, VERSION_NO, SCM_SITE_ID, PROJECT_CODE, ITEM_ID, END_CUSTOMER, BIZ_TYPE, PLANT_SITE_ID, FCST_TYPE, DOM_EXP, INCOTERMS, CURRENCY, MEASURE, CELL_PROD_SITE
						 , YYYYMM, EE_CORP_ID, CELL_CORP_ID, PACK_CORP_ID, OSP_YN, ATTRIBUTE1, ATTRIBUTE2, QTY
						 , SUM(QTY) * 100 / SUM(SUM(QTY)) OVER()    AS RATIO
					FROM    #TMP_RTF WITH(NOLOCK)
					WHERE  1=1
					AND DIVISION_ID  = @DIVISION_ID
					AND PROJECT_CODE = @PROJECT
					AND SCM_SITE_ID  = @SALES_SITE
					AND ITEM_ID      = @MODEL_CODE
					AND END_CUSTOMER    = @END_CUSTOMER
					AND BIZ_TYPE    = @BIZ_TYPE
					AND PLANT_SITE_ID    = @PLANT_SITE_ID
					AND FCST_TYPE    = @FCST_TYPE
					AND DOM_EXP    = @DOM_EXP
					AND INCOTERMS    = @INCOTERMS
					AND CURRENCY    = @CURRENCY
					--AND MEASURE    = @MEASURE
					AND CELL_PROD_SITE    = @CELL_PROD_SITE
					AND YYYYMM       = @YYYYMM
					AND    QTY   > 0
					GROUP BY DIVISION_ID, VERSION_NO, SCM_SITE_ID, PROJECT_CODE, ITEM_ID, END_CUSTOMER, BIZ_TYPE, PLANT_SITE_ID, FCST_TYPE, DOM_EXP, INCOTERMS, CURRENCY, MEASURE, CELL_PROD_SITE
						   , YYYYMM, EE_CORP_ID, CELL_CORP_ID, PACK_CORP_ID, OSP_YN, ATTRIBUTE1, ATTRIBUTE2, QTY
				END
				ELSE -- BP Conf 가 없는 경우 100%
				BEGIN
					INSERT INTO #TMP_RTF_RATIO
					     (DIVISION_ID, VERSION_NO, SCM_SITE_ID, PROJECT_CODE, ITEM_ID, END_CUSTOMER, BIZ_TYPE, PLANT_SITE_ID, FCST_TYPE, DOM_EXP, INCOTERMS, CURRENCY, MEASURE, CELL_PROD_SITE
						   , YYYYMM, EE_CORP_ID, CELL_CORP_ID, PACK_CORP_ID, OSP_YN, ATTRIBUTE1, ATTRIBUTE2, QTY, RATIO
						 )
					SELECT DIVISION_ID, VERSION_NO, SCM_SITE_ID, PROJECT_CODE, ITEM_ID, END_CUSTOMER, BIZ_TYPE, PLANT_SITE_ID, FCST_TYPE, DOM_EXP, INCOTERMS, CURRENCY, MEASURE, CELL_PROD_SITE
						 , YYYYMM, EE_CORP_ID, CELL_CORP_ID, PACK_CORP_ID, OSP_YN, ATTRIBUTE1, ATTRIBUTE2, QTY
						 , 100    AS RATIO
					FROM   #TMP_RTF WITH(NOLOCK)
					WHERE  1=1
					AND DIVISION_ID  = @DIVISION_ID
					AND PROJECT_CODE = @PROJECT
					AND SCM_SITE_ID  = @SALES_SITE
					AND ITEM_ID      = @MODEL_CODE
					AND END_CUSTOMER    = @END_CUSTOMER
					AND BIZ_TYPE    = @BIZ_TYPE
					AND PLANT_SITE_ID    = @PLANT_SITE_ID
					AND FCST_TYPE    = @FCST_TYPE
					AND DOM_EXP    = @DOM_EXP
					AND INCOTERMS    = @INCOTERMS
					AND CURRENCY    = @CURRENCY
					--AND MEASURE    = @MEASURE
					AND CELL_PROD_SITE    = @CELL_PROD_SITE
					AND YYYYMM       = @YYYYMM
					AND    QTY   > 0
					GROUP BY DIVISION_ID, VERSION_NO, SCM_SITE_ID, PROJECT_CODE, ITEM_ID, END_CUSTOMER, BIZ_TYPE, PLANT_SITE_ID, FCST_TYPE, DOM_EXP, INCOTERMS, CURRENCY, MEASURE, CELL_PROD_SITE
						   , YYYYMM, EE_CORP_ID, CELL_CORP_ID, PACK_CORP_ID, OSP_YN, ATTRIBUTE1, ATTRIBUTE2, QTY
				END -- IF (@C_CNT > 1)

				SET @i = @i + 1
			END -- WHILE @i <= @CNT

		END
--PRINT 'A2=========================================================================================================================================='

    BEGIN

		SELECT ROW_NUMBER() OVER(ORDER BY PROJECT_CODE, SCM_SITE_ID, ITEM_ID) SN, RANK() OVER (PARTITION BY AA.VERSION_NO,AA.CUTOFF_TYPE,AA.CUTOFF_YYYYMMDD,AA.PROJECT_CODE,AA.SCM_SITE_ID
			                                                                                               ,AA.ITEM_ID,AA.INCOTERMS,AA.MEASURE,AA.YYYYMM, AA.CELL_PROD_SITE ORDER BY AA.QT DESC) SEQ
    		,AA.DIVISION_ID,AA.VERSION_NO,AA.CUTOFF_TYPE,AA.CUTOFF_YYYYMMDD
			,AA.DEPT_ID,AA.PROJECT_CODE,AA.PROJECT_NAME,AA.SCM_SITE_ID,AA.ITEM_ID,AA.END_CUSTOMER,AA.BIZ_TYPE,AA.PLANT_SITE_ID,AA.FCST_TYPE,AA.DOM_EXP,AA.INCOTERMS
			,AA.ITEM_USE,AA.UNIT_ENERGY,AA.CURRENCY,AA.MEASURE,AA.YYYYMM, AA.QTY QTY_O, AA.QT QTY, AA.RATIO, AA.RATIO1, AA.QT
			,AA.CELL_CODE,AA.CELL_PER_PACK,AA.CELL_PER_MODULE,AA.MODULE_PER_PACK,AA.CELL_PROD_SITE,AA.PRODUCT_GROUP
			,AA.EE_CORP_ID,AA.CELL_CORP_ID,AA.PACK_CORP_ID,AA.ALT_SIM_YN,AA.PERIOD_YYMM,AA.SCENARIO_TYPE,AA.BASE_PRICE,AA.METAL_LINK_PRICE,AA.OTHER_PRICE,AA.TOTAL_PRICE,AA.METAL_LINK_YN,AA.WORK_YYYYMMDD,AA.OSP_YN,AA.EXT_INT
			,AA.ATTRIBUTE1,AA.ATTRIBUTE2
			,AA.CREATED_BY,AA.CREATION_DATE,AA.LAST_UPDATED_BY,AA.LAST_UPDATE_DATE
		INTO #TMP_BP_CONFIRM
		FROM
				(
				SELECT A.SEQ, A.DIVISION_ID,A.VERSION_NO,A.CUTOFF_TYPE,A.CUTOFF_YYYYMMDD
					  ,A.DEPT_ID,A.PROJECT_CODE,A.PROJECT_NAME,A.SCM_SITE_ID,A.ITEM_ID,A.END_CUSTOMER,A.BIZ_TYPE,A.PLANT_SITE_ID,A.FCST_TYPE,A.DOM_EXP,A.INCOTERMS
					  ,A.ITEM_USE,A.UNIT_ENERGY,A.CURRENCY, 'Business_Plan_Conf' MEASURE,A.YYYYMM, A.QTY, B.RATIO, CONVERT(FLOAT, (B.RATIO/100)) RATIO1, ROUND(A.QTY * (B.RATIO/100), 0) QT
					  ,A.CELL_CODE,A.CELL_PER_PACK,A.CELL_PER_MODULE,A.MODULE_PER_PACK,A.CELL_PROD_SITE,A.PRODUCT_GROUP
					  ,B.EE_CORP_ID,B.CELL_CORP_ID,B.PACK_CORP_ID,A.ALT_SIM_YN,A.PERIOD_YYMM,A.SCENARIO_TYPE,A.BASE_PRICE,A.METAL_LINK_PRICE,A.OTHER_PRICE,A.TOTAL_PRICE,A.METAL_LINK_YN,A.WORK_YYYYMMDD,B.OSP_YN,A.EXT_INT
					  ,B.ATTRIBUTE1,B.ATTRIBUTE2
					  ,'scm_batch' CREATED_BY,GETDATE() CREATION_DATE,'scm_batch' LAST_UPDATED_BY,GETDATE() LAST_UPDATE_DATE
				FROM DM_PLN_BIZPLAN_C A WITH(NOLOCK)

				LEFT OUTER JOIN #TMP_RTF_RATIO B  WITH(NOLOCK)
