		AND cf.END_CUSTOMER   = cp.END_CUSTOMER 
		AND cf.BIZ_TYPE       = cp.BIZ_TYPE     
		AND cf.PLANT_SITE_ID  = cp.PLANT_SITE_ID
		AND cf.FCST_TYPE      = cp.FCST_TYPE    
		AND cf.DOM_EXP        = cp.DOM_EXP      
		AND cf.INCOTERMS      = cp.INCOTERMS   
		AND cf.CURRENCY       = cp.CURRENCY     
		AND cf.YYYYMM         = cp.YYYYMM 
		AND ISNULL(cf.CELL_PROD_SITE, '-') = ISNULL(cp.CELL_PROD_SITE, '-')

        SET @n_log_count = @@ROWCOUNT;

    END

