				    , MIN(SEQ) AS SEQ, MIN(CUTOFF_TYPE) AS CUTOFF_TYPE, MIN(CUTOFF_YYYYMMDD) AS CUTOFF_YYYYMMDD, MIN(DEPT_ID) AS DEPT_ID
					, MIN(ITEM_USE) AS ITEM_USE, MIN(UNIT_ENERGY) AS UNIT_ENERGY, SUM(QTY) QTY
					, MIN(PROJECT_NAME) AS PROJECT_NAME, MIN(EE_CORP_ID) AS EE_CORP_ID
