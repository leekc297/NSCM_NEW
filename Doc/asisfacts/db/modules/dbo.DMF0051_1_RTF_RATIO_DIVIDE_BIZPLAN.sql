		AND cf.DIVISION_ID    = cp.DIVISION_ID
		AND cf.VERSION_NO     = cp.VERSION_NO
		AND cf.PROJECT_CODE   = cp.PROJECT_CODE
		AND cf.SCM_SITE_ID    = cp.SCM_SITE_ID  
