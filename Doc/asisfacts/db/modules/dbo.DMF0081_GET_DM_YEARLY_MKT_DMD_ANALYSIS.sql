 --   --WHERE EV_TP_CD = @p_EV_TP_CD  AND CUST_CO_CD = @p_CUST_CO_CD AND CAR_MDL_ID = @p_CAR_MDL_ID AND PLAN_YYYYMM BETWEEN @p_FROM_YYYYMM AND @p_TO_YYYYMM
