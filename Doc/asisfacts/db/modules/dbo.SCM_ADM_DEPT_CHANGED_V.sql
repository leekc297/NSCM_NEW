 --     , V.USER_NAME
	--  , V.GROUP_ID
	--  , V.DIVISION_ID
	--  , V.APPROVAL_RESULT
	--  , V.APPROVAL_ID
	--  , V.APPROVAL_NAME
	--  , V.APPROVED_DATE
	--  , V.REMAIN_DAYS
	--  , V.ELAPSED_DAYS
	--  , V.ACTIVE_FLAG
 --  FROM (
	SELECT SU.USER_ID
	     , SU.USER_NAME
	     , UG.GROUPID AS GROUP_ID
	     , UGA.CODE AS DIVISION_ID
	     , 'APPROVED' AS APPROVAL_RESULT
	     , UGA.UPDATEUSERID AS APPROVAL_ID
	     , SU2.USER_NAME AS APPROVAL_NAME
	     , CONVERT(NVARCHAR, UGA.UPDATEDATETIME, 120) AS APPROVED_DATE
	     , DATEDIFF(DAY, GETDATE(),  DATEADD(DAY, 15, SU.ATTRIBUTE9)) AS REMAIN_DAYS
	     , DATEDIFF(DAY, SU.ATTRIBUTE9, CONVERT(NVARCHAR, GETDATE(), 112)) AS ELAPSED_DAYS
	     , SU.ACTIVE_FLAG
	  FROM TB_FX_USER AS U WITH(NOLOCK)
	       JOIN dbo.SCM_MST_SSO_USER_INFO AS SU WITH(NOLOCK)
	    ON U.USERID = SU.USER_ID 
	       JOIN [dbo].[TB_FX_USERGROUPINFO] AS UG WITH(NOLOCK)
	    ON U.USERID = UG.USERID 
	       JOIN [dbo].[TB_FX_USERGROUPAUTHEXTENTION] AS UGA WITH(NOLOCK)
	    ON UG.USERID = UGA.USERID AND UG.GROUPID = UGA.GROUPID 
	       LEFT OUTER JOIN dbo.SCM_MST_SSO_USER_INFO AS SU2 WITH(NOLOCK)
	    ON UGA.UPDATEUSERID = SU2.USER_ID
		   JOIN SCM_ADM_LOOKUP_MASTER_DETAIL AS LK WITH(NOLOCK)
		ON UG.GROUPID = LK.SEGMENT1
	   AND LK.LOOKUP_TYPE	= 'DEPT_CHANGED_AUTH_DELETE'
	   AND LK.SEGMENT2		= 'N'  --SCM
	   AND LK.VALID_YN		= 'Y'
	 WHERE 1 = 1
	   AND SU.DEPT_ID <> IIF(ISNULL(SU.ATTRIBUTE10, '') = '', SU.DEPT_ID,  SU.ATTRIBUTE10)
	   AND ISNUMERIC(SU.DEPT_ID) = 1
	   AND UGA.UPDATEDATETIME < CONVERT(DATETIME, SU.ATTRIBUTE9, 112)
	   AND SU.ACTIVE_FLAG	!= 'D'
	   AND U.USEYN			= 'Y' 
	   AND UG.USEYN			= 'Y'
	 UNION ALL
	SELECT SU.USER_ID
	     , SU.USER_NAME
	     , UG.GROUPID AS GROUP_ID
	     , UGA.CODE AS DIVISION_ID
	     , 'APPROVED' AS APPROVAL_RESULT
	     , UGA.UPDATEUSERID AS APPROVAL_ID
	     , SU2.USER_NAME AS APPROVAL_NAME
	     , CONVERT(NVARCHAR, FP.UPDATEDATETIME, 120) AS APPROVED_DATE
	     , DATEDIFF(DAY, GETDATE(),  DATEADD(DAY, 15, SU.ATTRIBUTE9)) AS REMAIN_DAYS
	     , DATEDIFF(DAY, SU.ATTRIBUTE9, CONVERT(NVARCHAR, GETDATE(), 112)) AS ELAPSED_DAYS
	     , SU.ACTIVE_FLAG
	  FROM TB_FX_USER AS U WITH(NOLOCK)
	       JOIN dbo.SCM_MST_SSO_USER_INFO AS SU WITH(NOLOCK)
	    ON U.USERID = SU.USER_ID 
	       JOIN [dbo].[TB_FX_USERGROUPINFO] AS UG WITH(NOLOCK)
	    ON U.USERID = UG.USERID 
	       JOIN [dbo].[TB_FX_USERGROUPAUTHEXTENTION] AS UGA WITH(NOLOCK)
	    ON UG.USERID = UGA.USERID AND UG.GROUPID = UGA.GROUPID
	       LEFT OUTER JOIN dbo.SCM_MST_SSO_USER_INFO AS SU2 WITH(NOLOCK)
	    ON UGA.UPDATEUSERID = SU2.USER_ID
		   JOIN SCM_ADM_LOOKUP_MASTER_DETAIL AS LK WITH(NOLOCK)
		ON UG.GROUPID = LK.SEGMENT1
	   AND LK.LOOKUP_TYPE	= 'DEPT_CHANGED_AUTH_DELETE'
	   AND LK.SEGMENT2		= 'Y'  --FP
	   AND LK.VALID_YN		= 'Y'
	       JOIN (SELECT UIR.USER_ID AS USERID
	                  , IIF(UIR.SAVE_FLAG = 'Y', 'FP Planner', 'FP Viewer') AS GroupID
	                  , RIR.DIVISION_ID AS Code
	                  , max(ISNULL(UIR.UPDATE_DTTM, UIR.INSERT_DTTM)) AS UPDATEDATETIME
	               FROM [dbo].[TH_UIS_USER_INSTANCE_RELATE_SN] AS UIR WITH(NOLOCK)
	                    JOIN [dbo].[TH_UIS_ROLE_INSTANCE_SN] AS RI WITH(NOLOCK)
	                 ON UIR.ROLE_ID		= RI.ROLE_ID  
	                    JOIN [dbo].[TH_UIS_ROLE_INSTANCE_RELATE_SN] AS RIR WITH(NOLOCK)
	                 ON RIR.ROLE_ID		= RI.ROLE_ID 
	              WHERE 1 = 1
				    AND UIR.USE_AT_FLAG = 'Y'
				    AND RIR.USE_AT_FLAG = 'Y'
					AND UIR.SAVE_FLAG	= 'Y' --FP Planner
	              GROUP BY 
				        UIR.USER_ID, UIR.SAVE_FLAG, RIR.DIVISION_ID
	            ) AS FP
	    ON UGA.USERID	= FP.USERID
	   AND UGA.GROUPID	= FP.GROUPID
	   AND UGA.CODE		= FP.CODE
	 WHERE 1 = 1
	   AND SU.DEPT_ID <> IIF(ISNULL(SU.ATTRIBUTE10, '') = '', SU.DEPT_ID,  SU.ATTRIBUTE10)
	   AND ISNUMERIC(SU.DEPT_ID) = 1
	   AND FP.UPDATEDATETIME < CONVERT(DATETIME, SU.ATTRIBUTE9, 112)
	   AND SU.ACTIVE_FLAG	!= 'D'
	   AND U.USEYN			= 'Y' 
	   AND UG.USEYN			= 'Y' 
 --    ) AS V
