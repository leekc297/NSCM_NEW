

/*
 * PROGRAM ID   : SSP0022_GET_SHIPMENT_PSI
 * DESCRIPTION  : 전극 SHIPMENT REQUEST
 * PROGRAM HISTORY
 *===================================================================================================
 *   DATE       IN CHARGE		DESCRIPTION
 *===================================================================================================
 * 2020-04-10   KIMYONGHO		신규추가
 * 2020-07-17   kimbk           Receipt(Intransit)+Shipment Plan(In)의 Plan in 값을 Shipment Plan의 Simulation값으로 표시
 *                              Division = '40' and From Site = 'A011-E' and To Site = '' 인 정보만 적용
 *                              기존 REQ 정보에서 위 정보는 제외 처리 함
 * 2024-10-29   KHJ             NERP_SSP
 */
CREATE PROCEDURE [dbo].[SSP0022_GET_SHIPMENT_PSI]
	@P_DIVISION_ID			VARCHAR(10)
	,@P_COMPANY_ID			NVARCHAR(100)
	,@P_PLANT_ID			NVARCHAR(MAX)
	,@P_CELL_TYPE			NVARCHAR(50)
	,@P_PLAN_START_YYYYMMDD	NVARCHAR(8)
	,@P_FROM_YYYYMMDD		NVARCHAR(8)
	,@P_TO_YYYYMMDD		NVARCHAR(8)
	,@P_MODEL_ID			NVARCHAR(MAX)
	,@P_ITEM_ID			NVARCHAR(MAX)
	,@P_NICK_NAME			NVARCHAR(MAX)
	,@P_USER_ID			NVARCHAR(MAX)
	,@P_PROGRAM_ID			NVARCHAR(MAX) = 'SSP0022' 
	,@P_SHEET_NAME			NVARCHAR(MAX) = 'Shipment Request(Electrode)'
	,@P_REAL_FLAG			CHAR(1)
	,@P_NON_CHK			CHAR(1)
	,@P_MY_MODEL_CHK		CHAR(1)
	,@P_DELEGATE_CHK		CHAR(1)
	,@P_PART_LEADER_CHK		CHAR(1)
	,@P_TEAM_LEADER_CHK		CHAR(1)
AS  
  
BEGIN
	SET NOCOUNT ON; 
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;	
	
	DECLARE @V_FROM_YYYYMMDD		NVARCHAR(8);
	DECLARE @V_TO_YYYYMMDD		NVARCHAR(8);

	DECLARE @MQRY_SUM			NVARCHAR(MAX);
	DECLARE @MEXEC				NVARCHAR(MAX);
	DECLARE @MDAY_QTY			NVARCHAR(MAX);

	DECLARE @P_STOCK_YYYYMMDD	NVARCHAR(8);

	DECLARE @V_SEQ				INT;

	-- NERP 매핑코드
    DECLARE @v_C100 NVARCHAR(10);
	DECLARE @v_G180 NVARCHAR(10);
	DECLARE @v_A011E NVARCHAR(10);
	DECLARE @v_G182A NVARCHAR(10);
	SET @v_C100 = dbo.FN_GET_LOOKUP_VALUE('SSP0022_GET_SHIPMENT_PSI'  ,'ESOC' );	--C100
	SET @v_G180 = dbo.FN_GET_LOOKUP_VALUE('SSP0022_GET_SHIPMENT_PSI'  ,'ESNJ' );	--G180
	SET @v_A011E = dbo.FN_GET_LOOKUP_VALUE('SSP0022_GET_SHIPMENT_PSI'  ,'A011E');	--A011-E
	SET @v_G182A = dbo.FN_GET_LOOKUP_VALUE('SSP0022_GET_SHIPMENT_PSI'  ,'G182A' );	--G182-A



	SET @V_FROM_YYYYMMDD		= @P_FROM_YYYYMMDD;
	SET @V_TO_YYYYMMDD			= @P_TO_YYYYMMDD;

	DECLARE @V_CNT_USR_MEASURE	INT =0;

	SET @V_CNT_USR_MEASURE = (
							SELECT COUNT(*) 
							FROM SCM_MST_TITLESET_USER   WITH(NOLOCK)
							WHERE 1=1
							AND PROGRAM_ID  =  @P_PROGRAM_ID
							AND SHEET_NAME  =  @P_SHEET_NAME 
							AND USER_ID     =  @P_USER_ID
						)

	---------------------------------------------------------------------------------------------------------------------------
	-- 계획 구간 Start End 일자 (plan_start_yyyymmdd-1 ~ 8주) 			
	DECLARE @P_PLAN_END_YYYYMMDD   NVARCHAR(8) = CONVERT(VARCHAR, DATEADD(D, 56, CONVERT(DATETIME, @P_PLAN_START_YYYYMMDD ,112)) ,112) ; 

	---------------------------------------------------------------------------------------------------------------------------
	-- 실적구간 Start End 일자 (plan_start_yyyymmdd-1의 전주월요일  ~ 계획구간 start일자-1) 
	DECLARE @v_result_start_yyyymmdd NVARCHAR(8) = '';
	DECLARE @v_result_end_yyyymmdd   NVARCHAR(8) = '';

	-- plan_start_yyyymmdd-1의 전주월요일
	SELECT @v_result_start_yyyymmdd  = C.BASIS_YYYYMMDD
	FROM   SCM_SYS_CALENDAR_M C WITH(NOLOCK) 
	WHERE  C.ISO_YYYYWW = ( 
					SELECT MIN(ISO_YYYYWW)  AS ISO_YYYYWW
					FROM SCM_SYS_CALENDAR_M  WITH(NOLOCK) 
					WHERE BASIS_YYYYMMDD >= CONVERT(VARCHAR, DATEADD(D, -7, CONVERT(DATETIME, @P_PLAN_START_YYYYMMDD ,112)) ,112) 
					AND   BASIS_YYYYMMDD <=  @P_PLAN_START_YYYYMMDD
					)
	AND  C.DAYOFWEEK = 'MON' 
	; 

	SET     @v_result_end_yyyymmdd   = CONVERT(VARCHAR, DATEADD(D, -1, CONVERT(DATETIME, @P_PLAN_START_YYYYMMDD ,112)) ,112) ; 
	---------------------------------------------------------------------------------------------------------------------------

	/********************************************************************************
	* 임시테이블만들기
	********************************************************************************/





	-- SHIPMENT ROW DATA
	IF OBJECT_ID('TEMPDB..#TMP_ROWDATA') IS NOT NULL	
		DROP TABLE #TMP_ROWDATA;
	
	IF OBJECT_ID('TEMPDB..#TMP_ROWDATA_OLD') IS NOT NULL	
		DROP TABLE #TMP_ROWDATA_OLD;

	IF OBJECT_ID('TEMPDB..#TMP_RESULT_PIVOT_TABLE') IS NOT NULL	
		DROP TABLE #TMP_RESULT_PIVOT_TABLE;

	IF OBJECT_ID('TEMPDB..#TMP_RESULT_PIVOT_TABLE_OLD') IS NOT NULL	
		DROP TABLE #TMP_RESULT_PIVOT_TABLE_OLD;
	
	IF OBJECT_ID('TEMPDB..#TMP_RESULT_TABLE') IS NOT NULL	
		DROP TABLE #TMP_RESULT_TABLE;

	IF OBJECT_ID('TEMPDB..#TMP_RESULT_TABLE_OLD') IS NOT NULL	
		DROP TABLE #TMP_RESULT_TABLE_OLD;
	
	-- Requestor
	IF OBJECT_ID('tempdb..#TblDynamic_REQUESTOR') IS NOT NULL
		DROP TABLE #TblDynamic_REQUESTOR;
	
	IF OBJECT_ID('tempdb..#TMP_REQ_INV') IS NOT NULL				 -- 속도 문제로 TEMP로 빼서 처리해 봄.
		DROP TABLE #TMP_REQ_INV;

	IF OBJECT_ID('tempdb..#TMP_PLAN_INV') IS NOT NULL				 -- 속도 문제로 TEMP로 빼서 처리해 봄.
		DROP TABLE #TMP_PLAN_INV;

	IF OBJECT_ID('tempdb..#TMP_SHIP_PLAN_ETD') IS NOT NULL			 -- 속도 문제로 TEMP로 빼서 처리해 봄.
		DROP TABLE #TMP_SHIP_PLAN_ETD;

	IF OBJECT_ID('tempdb..#TMP_INTRANSIT_ETA') IS NOT NULL			 -- 속도 문제로 TEMP로 빼서 처리해 봄.
		DROP TABLE #TMP_INTRANSIT_ETA;

	IF OBJECT_ID('tempdb..#TBLDYNAMICTITLEST_SSP0022') IS NOT NULL
		DROP TABLE #TBLDYNAMICTITLEST_SSP0022;

	SELECT * INTO #TBLDYNAMICTITLEST_SSP0022 
	FROM SCM_MST_TITLESET_USER WITH(NOLOCK)
	WHERE PROGRAM_ID	= @P_PROGRAM_ID
	AND SHEET_NAME		= @P_SHEET_NAME
	AND USER_ID		= @P_USER_ID;

	CREATE TABLE #TMP_RESULT_TABLE
	(
		DIVISION_ID		NVARCHAR(30)
		, ORIGIN_DIVISION_ID NVARCHAR(30)
		, PLANT_ID		NVARCHAR(10)
		, SCM_SITE_ID		NVARCHAR(10)
		, ELECTRODE_TYPE    NVARCHAR(10)
		, CELL_TYPE		NVARCHAR(50)
		, MODEL_ID	     NVARCHAR(50)
		, ITEM_ID			NVARCHAR(50)
		, FROM_SITE		NVARCHAR(30)
		, TO_SITE			NVARCHAR(30)
		, BOD_ID			NVARCHAR(30)
		, BOD_LT			NVARCHAR(10)
		, TRANSPORT_MODE	NVARCHAR(50)
		, INCOTERMS			NVARCHAR(50)
		, MEASURE			NVARCHAR(50)
		, YYYYMMDD		NVARCHAR(8)
		, SEQ			INT
		, QTY			decimal(30,3)
		, QTY_TO_PCM		decimal(30,3)
		, QTY_TO_CELL		decimal(30,3)
		, OP_LT			NVARCHAR(30)
		, TOT_BOH_QTY		decimal(30,3)
		, JR_BOH_QTY		decimal(30,3)
		, PC_BOH_QTY		decimal(30,3)
		, TOT_BOH_QTY_PCM	decimal(30,3)
		, JR_BOH_QTY_PCM	decimal(30,3)
		, PC_BOH_QTY_PCM	decimal(30,3)
		, TOT_BOH_QTY_CELL	decimal(30,3)
		, JR_BOH_QTY_CELL	decimal(30,3)
		, PC_BOH_QTY_CELL	decimal(30,3)
		, CONFIRM_DAY		INT
	);


	-- 조회 기준 데이터
	IF OBJECT_ID('TEMPDB..#TMP_PLAN_ITEM_CUTOFF') IS NOT NULL
		DROP TABLE #TMP_PLAN_ITEM_CUTOFF;

	SELECT DISTINCT
			T.COMPANY_ID
		  , T.DIVISION_ID
		  , T.PLANT_ID
		  , T.SCM_SITE_ID
		  , T.MODEL_ID
		  , T.ITEM_ID
	   INTO #TMP_PLAN_ITEM_CUTOFF
	  FROM SSP_ANL_SHIP_PLAN_EE T WITH(NOLOCK)
	  LEFT OUTER JOIN SSP_MST_MODEL_USER_EE M WITH(NOLOCK)
		ON M.DIVISION_ID	= T.DIVISION_ID
	   AND M.TO_SITE		= T.SCM_SITE_ID
	   AND M.ITEM_ID		= T.ITEM_ID
	   AND M.VALID_YN		= 'Y'
	 WHERE T.MEASURE_TYPE      = 'R'
	   AND PLAN_START_YYYYMMDD =  @P_PLAN_START_YYYYMMDD 
	   AND COMPANY_ID          =  @P_COMPANY_ID
	   AND ((@P_NON_CHK = 'Y' AND 1 = 1 OR M.USER_ID IN (SELECT CASE WHEN @P_MY_MODEL_CHK = 'Y' THEN @P_USER_ID ELSE 'X' END
														 UNION
														SELECT CASE WHEN @P_DELEGATE_CHK = 'Y' THEN USER_ID ELSE 'X' END
														  FROM SSP_MST_DELEGATE
														 WHERE VALID_YN = 'Y'
														   AND DELEGATEE_ID = @P_USER_ID 
														 GROUP BY USER_ID)
									OR M.PART_LEADER = CASE WHEN @P_PART_LEADER_CHK = 'Y' THEN @p_user_id  ELSE 'X' END
									OR M.TEAM_LEADER = CASE WHEN @P_TEAM_LEADER_CHK = 'Y' THEN @p_user_id  ELSE 'X' END))
	;

	IF OBJECT_ID('tempdb..#TMP_BOH_CUTOFF_EE') IS NOT NULL
		DROP TABLE #TMP_BOH_CUTOFF_EE 

		SELECT  T0.COMPANY_ID 
		,       T0.DIVISION_ID
		,	   T0.PLANT_ID
		,	   T0.SCM_SITE_ID
		,	   T0.MODEL_ID
		,	   T0.ITEM_ID
		,	   ISNULL(T0.TOT_BOH_QTY,0.00)					AS TOT_BOH_QTY
		,	   ISNULL(T0.JR_BOH_QTY,0.00)					AS JR_BOH_QTY
		,	   ISNULL(T0.PC_BOH_QTY,0.000)					AS PC_BOH_QTY
		,	   ISNULL(T0.TOT_BOH_QTY_TO_PCM,0.000 )			AS TOT_BOH_QTY_PCM
		,	   ISNULL(T0.JR_BOH_QTY_TO_PCM,0.000)				AS JR_BOH_QTY_PCM
		,	   ISNULL(T0.PC_BOH_QTY_TO_PCM,0.000)				AS PC_BOH_QTY_PCM
		,	   ISNULL(T0.TOT_BOH_QTY_TO_CELL,0.000)			AS TOT_BOH_QTY_CELL
		,	   ISNULL(T0.JR_BOH_QTY_TO_CELL,0.000)				AS JR_BOH_QTY_CELL
		,	   ISNULL(T0.PC_BOH_QTY_TO_CELL,0.000)				AS PC_BOH_QTY_CELL	
		,       CUTOFF_DATE
		,       MEASURE_TYPE 
		INTO   #TMP_BOH_CUTOFF_EE 
		FROM   SSP_ANL_BOH_CUTOFF_EE T0 WITH(NOLOCK)
		WHERE  T0.CUTOFF_DATE = @P_PLAN_START_YYYYMMDD
		AND	  T0.DIVISION_ID = @P_DIVISION_ID
		AND    T0.COMPANY_ID  IN  ( SELECT TOKEN FROM DBO.UF_FX_STRING_SPLIT(@P_COMPANY_ID,',') ) 
		AND    T0.MEASURE_TYPE ='R'
		AND	  (( @P_ITEM_ID  IS NULL OR @P_ITEM_ID ='')  OR T0.ITEM_ID  IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_ITEM_ID , ',')))
		AND	  (( @P_MODEL_ID IS NULL OR @P_MODEL_ID ='') OR T0.MODEL_ID IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_MODEL_ID , ',')))
		;

	IF @P_REAL_FLAG = 'Y'  -- 현재 기준 조회
	 
		BEGIN
		--////////////////////////////////////////////////////////////////////////////////--
		--//2. DATA ROW DATE												//--
		--////////////////////////////////////////////////////////////////////////////////--

		-- R_SHIP_PLAN_ETD 메져 생성
		SELECT T.DIVISION_ID
			,    T.PLANT_ID
			,    T.COMPANY_ID						
			,    T.SCM_SITE_ID
			,	 T.ELECTRODE_TYPE
			,    T.CELL_TYPE
			,    T.MODEL_ID
			,    T.ITEM_ID
			,    T.FROM_SITE
			,    T.TO_SITE
			,    T.BOD_ID
			,    T.MEASURE
			,    T.YYYYMMDD
			,    cast(T.QTY as decimal(30,3)) as QTY
			,     T.QTY_TO_PCM
			,    T.QTY_TO_CELL
			,    T.LAST_UPDATED_BY
			,    T.LAST_UPDATE_DATE		
		INTO #TMP_SHIP_PLAN_ETD
		FROM (
			-- 출하 실적(OWMS) : 실적구간
			SELECT V.DIVISION_ID
			,      MS.LOGISTIC_PLANT_ID					AS PLANT_ID
			,      MS.COMPANY_ID						AS COMPANY_ID						
			,      B.ATTRIBUTE1							AS SCM_SITE_ID
			,	  ISNULL(E.ELECTRODE_TYPE,'-')			AS ELECTRODE_TYPE
			,      E.CELL_TYPE							AS CELL_TYPE
			,      E.MODEL_ID							AS MODEL_ID
			,      V.ITEM_ID							AS ITEM_ID
			,      '-'							     AS FROM_SITE
			,      '-'							     AS TO_SITE
			,      '-'								AS BOD_ID
			,      'R_SHIP_PLAN_ETD'						AS MEASURE
			,      V.YYYYMMDD							AS YYYYMMDD
			,      cast(V.QTY as decimal(30,3)) as qty --V.QTY								AS QTY
			,      V.QTY * ISNULL(E.CONVERT_TO_PCM,  1)		AS QTY_TO_PCM
			,      V.QTY * ISNULL(E.CONVERT_TO_CELL, 1)		AS QTY_TO_CELL
			,      '-'								AS LAST_UPDATED_BY
			,      NULL								AS LAST_UPDATE_DATE							
			FROM SSP_DNM_SHIP_RESULT_OWMS_V V WITH(NOLOCK)
			LEFT JOIN  SCM_MST_SITE MS WITH(NOLOCK)
				ON  V.DIVISION_ID = MS.DIVISION_ID
				AND V.FROM_SITE = MS.SCM_SITE_ID
			JOIN SCM_ADM_LOOKUP_MASTER_DETAIL B WITH(NOLOCK)
				ON LOOKUP_TYPE			= 'ELECTRODE_ASSY_PLANT_MAPPING'
				AND B.VALID_YN			= 'Y'
				AND B.SEGMENT1			= @P_DIVISION_ID
				AND B.SEGMENT1 		=  V.DIVISION_ID
				AND B.SEGMENT4 		= MS.PLANT_ID 
				AND B.ATTRIBUTE2 		= V.FROM_SITE
			 LEFT JOIN SSP_MST_SITE_ITEM_EE_V E WITH(NOLOCK) 
				ON E.DIVISION_ID = V.DIVISION_ID
				AND E.SCM_SITE_ID = V.FROM_SITE
				AND E.ITEM_ID     = V.ITEM_ID	
			 JOIN #TMP_PLAN_ITEM_CUTOFF T
				ON V.DIVISION_ID	   = T.DIVISION_ID
				AND B.ATTRIBUTE1       = T.SCM_SITE_ID
				AND V.ITEM_ID          = T.ITEM_ID
			WHERE 1=1
				AND MS.DIVISION_ID = @P_DIVISION_ID
				AND MS.COMPANY_ID  = @P_COMPANY_ID
				AND (( @P_PLANT_ID  IS NULL OR @P_PLANT_ID ='')       OR MS.LOGISTIC_PLANT_ID  IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_PLANT_ID , ',')))
				AND ((@P_ITEM_ID   IS NULL OR @P_ITEM_ID ='' )	    OR V.ITEM_ID IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_ITEM_ID, ','))) 
				AND ((@P_MODEL_ID  IS NULL OR @P_MODEL_ID ='' )	    OR E.MODEL_ID IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_MODEL_ID, ','))) 
				AND ((@P_CELL_TYPE IS NULL OR @P_CELL_TYPE ='')	    OR E.CELL_TYPE_GROUP_CODE  IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_CELL_TYPE , ',')))
				AND ((@P_NICK_NAME IS NULL OR @P_NICK_NAME ='')	    OR E.ITEM_ID_NICK_NAME IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_NICK_NAME , ',')))
				AND MS.SITE_TYPE	   = 'PLANT' 
				AND MS.OPERATION_GROUP = 'E'	
				AND V.YYYYMMDD >= @v_result_start_yyyymmdd 
				AND V.YYYYMMDD < @P_PLAN_START_YYYYMMDD
				
			UNION ALL
			
			/* R_SHIP_PLAN_ETD Measure 추가 
				확정구간
			*/
			SELECT A.DIVISION_ID						AS DIVISION_ID
			,	  B.SEGMENT2							AS PLANT_ID								
			,	  A.FROM_SITE_COMPANY_ID					AS COMPANY_ID						
			,	  B.ATTRIBUTE1							AS SCM_SITE_ID
			,	  ISNULL(E.ELECTRODE_TYPE,'-')			AS ELECTRODE_TYPE
			,      E.CELL_TYPE							AS CELL_TYPE
			,	  E.MODEL_ID							AS MODEL_ID				
			,	  A.ITEM_ID							AS ITEM_ID
			,	  '-'								AS FROM_SITE
			,	  '-'								AS TO_SITE
			,	  '-'								AS BOD_ID
			,	  'R_SHIP_PLAN_ETD'						AS MEASURE
			,	  A.YYYYMMDD							AS YYYYMMDD
			,	  cast(A.QTY as decimal(30,3)) as qty -- A.QTY								AS QTY
			,	  A.QTY * ISNULL(E.CONVERT_TO_PCM,  1)		AS QTY_TO_PCM
			,	  A.QTY * ISNULL(E.CONVERT_TO_CELL, 1)		AS QTY_TO_CELL
			,	  '-'								AS LAST_UPDATED_BY
			,	  A.LAST_UPDATE_DATE			 
			FROM SSP_ANL_SHIP_CONFIRM A WITH(NOLOCK)
			LEFT JOIN  SCM_MST_SITE MS WITH(NOLOCK)
				ON  A.DIVISION_ID   = MS.DIVISION_ID
				AND A.FROM_SITE	= MS.SCM_SITE_ID
			JOIN SCM_ADM_LOOKUP_MASTER_DETAIL B WITH(NOLOCK)
				ON LOOKUP_TYPE = 'ELECTRODE_ASSY_PLANT_MAPPING'
				AND B.VALID_YN    = 'Y'
				AND SEGMENT1 = @P_DIVISION_ID	
				AND A.DIVISION_ID		= B.SEGMENT1 
				AND MS.PLANT_ID		= B.SEGMENT4
				AND A.FROM_SITE		= B.ATTRIBUTE2 
			LEFT JOIN SSP_MST_SITE_ITEM_EE_V E WITH(NOLOCK) 
				ON  E.DIVISION_ID = A.DIVISION_ID
				AND E.SCM_SITE_ID = A.FROM_SITE
				AND E.ITEM_ID     = A.ITEM_ID
			JOIN #TMP_PLAN_ITEM_CUTOFF T
				ON A.DIVISION_ID	   = T.DIVISION_ID
				AND B.ATTRIBUTE1       = T.SCM_SITE_ID
				AND A.ITEM_ID          = T.ITEM_ID
			WHERE 1=1
			AND  A.DIVISION_ID				= @P_DIVISION_ID
			AND  A.FROM_SITE_COMPANY_ID		= @P_COMPANY_ID
			AND  A.CHANGE_TYPE  = 'C'
			AND  A.BIZ_TYPE= 'E'
			AND  A.QTY >  0
			AND (( @P_PLANT_ID  IS NULL OR @P_PLANT_ID ='')       OR MS.PLANT_ID IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_PLANT_ID , ',')))	 
			AND (( @P_ITEM_ID IS NULL OR @P_ITEM_ID ='' )	    OR A.ITEM_ID IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_ITEM_ID, ','))) 
			AND (( @P_MODEL_ID IS NULL OR @P_MODEL_ID ='')        OR E.MODEL_ID IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_MODEL_ID , ',')))	
			AND (( @P_CELL_TYPE IS NULL OR @P_CELL_TYPE ='')	    OR E.CELL_TYPE_GROUP_CODE  IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_CELL_TYPE , ',')))
			AND (( @P_NICK_NAME IS NULL OR @P_NICK_NAME ='')	    OR E.ITEM_ID_NICK_NAME IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_NICK_NAME , ',')))
			AND A.YYYYMMDD >= @P_PLAN_START_YYYYMMDD
			AND A.YYYYMMDD <= CONVERT(VARCHAR, DATEADD(D, [DBO].[FN_GET_SSP_ANL_SHIP_FROZEN](A.ORIGIN_FROM_DIVISION_ID,A.FROM_SITE) , CONVERT(DATETIME, @P_PLAN_START_YYYYMMDD ,112)) ,112)										

			UNION ALL
			/* R_SHIP_PLAN_ETD Measure 추가 
				확정구간 이후 Ship Req 수량 합 ETD기준
			*/
			SELECT
				DIVISION_ID
				,SEGMENT2					AS PLANT_ID
				,COMPANY_ID				AS COMPANY_ID
				,ATTRIBUTE1				AS SCM_SITE_ID
				,ELECTRODE_TYPE			AS ELECTRODE_TYPE
				,CELL_TYPE				AS CELL_TYPE
				,MODEL_ID
				,ITEM_ID
				,FROM_SITE
				,TO_SITE
				,BOD_ID					AS BOD_ID
				,MEASURE					AS MEASURE
				,YYYYMMDD					AS YYYYMMDD
				,cast(QTY as decimal(30,3)) as qty --QTY						AS QTY
				,QTY_TO_PCM				AS QTY_TO_PCM
				,QTY_TO_CELL				AS QTY_TO_CELL
				,LAST_UPDATED_BY
				,LAST_UPDATE_DATE			
			FROM
			(
				SELECT T0.FROM_DIVISION_ID					AS DIVISION_ID
				,	  T0.FROM_PLANT_ID						AS PLANT_ID
				,	  T0.FROM_COMPANY_ID					AS COMPANY_ID
				,	  T0.FROM_SITE							AS SCM_SITE_ID
				,	  ISNULL(E.ELECTRODE_TYPE,'-')		     AS ELECTRODE_TYPE
				,      E.CELL_TYPE							AS CELL_TYPE
				,	  T0.MODEL_ID
				,	  T0.ITEM_ID
				,	  '-'								AS FROM_SITE
