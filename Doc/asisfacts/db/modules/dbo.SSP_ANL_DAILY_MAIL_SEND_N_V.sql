









CREATE VIEW [dbo].[SSP_ANL_DAILY_MAIL_SEND_N_V] AS
/********************************************************************************************************************************
* VIEW NAME     : [SSP_ANL_DAILY_MAIL_SEND_N_V]
* DESCRIPTION   : D-4일 BALANCE 음수 경우 메일 대상자 및 대상 아이템 추출 
               
* PROGRAM HISTORY
*-------------------------------------------------------------------------------------------------------------------------------
*  DATE      IN CHARGE           DESCRIPTION
*-------------------------------------------------------------------------------------------------------------------------------
* 2018.10.07   juhlee     Initial Release [PJ20189106] 전지.GSCM 고도화 이행-
********************************************************************************************************************************/
WITH ITEM AS (
SELECT A.DIVISION_ID          AS DIVISION_ID
,      A.COMPANY_ID           AS COMPANY_ID 
,      A.PLAN_START_YYYYMMDD  AS PLAN_START_YYYYMMDD
,      A.FROM_SITE            AS FROM_SITE 
,      A.ITEM_ID              AS ITEM_ID
,      CONVERT(VARCHAR, DATEADD(D, [DBO].[FN_GET_SSP_ANL_SHIP_FROZEN](A.DIVISION_ID,A.FROM_SITE) +1, CONVERT(DATETIME, A.PLAN_START_YYYYMMDD ,112)) ,112) AS FROM_YYYYMMDD
,      CONVERT(VARCHAR, DATEADD(D, [DBO].[FN_GET_SSP_ANL_SHIP_FROZEN](A.DIVISION_ID,A.FROM_SITE) + 4, CONVERT(DATETIME, A.PLAN_START_YYYYMMDD ,112)) ,112) AS TO_YYYYMMDD
FROM  SSP_ANL_SHIP_PLAN_C A WITH(NOLOCK) 
WHERE A.PLAN_START_YYYYMMDD =  ( SELECT MAX(PLAN_START_YYYYMMDD) 
                                 FROM SSP_ANL_SHIP_PLAN_C 
								 WHERE COMPANY_ID = A.COMPANY_ID 
								 ) 
AND   A.YYYYMMDD >= CONVERT(VARCHAR, DATEADD(D, [DBO].[FN_GET_SSP_ANL_SHIP_FROZEN](A.DIVISION_ID,A.FROM_SITE) +1 , CONVERT(DATETIME, A.PLAN_START_YYYYMMDD ,112)) ,112) 
AND   A.YYYYMMDD <= CONVERT(VARCHAR, DATEADD(D, [DBO].[FN_GET_SSP_ANL_SHIP_FROZEN](A.DIVISION_ID,A.FROM_SITE) + 4, CONVERT(DATETIME, A.PLAN_START_YYYYMMDD ,112)) ,112) 
AND   A.MEASURE  IN ( 'BALANCE' , 'SHIP_PLAN' ,  'SHIP_REQ')  
AND   [DBO].[FN_GET_SSP_ANL_SHIP_FROZEN](A.DIVISION_ID,A.FROM_SITE) > 0 --  확정일자 0이상인것만
GROUP BY A.DIVISION_ID, A.COMPANY_ID, A.PLAN_START_YYYYMMDD, A.FROM_SITE, A.ITEM_ID
, CONVERT(VARCHAR, DATEADD(D, [DBO].[FN_GET_SSP_ANL_SHIP_FROZEN](A.DIVISION_ID,A.FROM_SITE) +1 , CONVERT(DATETIME, A.PLAN_START_YYYYMMDD ,112)) ,112)
, CONVERT(VARCHAR, DATEADD(D, [DBO].[FN_GET_SSP_ANL_SHIP_FROZEN](A.DIVISION_ID,A.FROM_SITE) +4, CONVERT(DATETIME, A.PLAN_START_YYYYMMDD ,112)) ,112)
HAVING SUM(CASE WHEN A.MEASURE = 'BALANCE'   THEN A.QTY ELSE 0 END ) < 0 
   AND ( SUM(CASE WHEN A.MEASURE = 'SHIP_PLAN' THEN A.QTY ELSE 0 END ) > 0 OR SUM(CASE WHEN A.MEASURE = 'SHIP_REQ' THEN A.QTY ELSE 0 END ) > 0 )
) 

SELECT   MAX(TYPE) AS TYPE
,        T.MAIL_RECEIVER
,        T.DIVISION_ID  
,        T.COMPANY_ID        
,        T.PLAN_START_YYYYMMDD 
,        T.FROM_SITE
,        T.ITEM_ID
,        T.YYYYMMDD
FROM ( 
	-- LOOK UP에 등록된 수신자 
	SELECT M.SEGMENT1             AS TYPE
	,      M.SEGMENT2             AS MAIL_RECEIVER
	,      X.DIVISION_ID          AS DIVISION_ID
	,      X.COMPANY_ID           AS COMPANY_ID
	,      X.PLAN_START_YYYYMMDD  AS PLAN_START_YYYYMMDD
	,      X.FROM_SITE            AS FROM_SITE 
	,      X.ITEM_ID              AS ITEM_ID
	,      X.FROM_YYYYMMDD        AS YYYYMMDD
	FROM ITEM X
		  JOIN SCM_ADM_LOOKUP_MASTER_DETAIL M WITH(NOLOCK)  
			ON  M.LOOKUP_TYPE ='WARNING_MAIL_SEND'
		   AND  M.VALID_YN    ='Y'
		   AND  M.SEGMENT3    = CASE WHEN M.SEGMENT3 = 'ALL' THEN 'ALL' ELSE X.FROM_SITE END

UNION ALL  

	--MKT OWNER (DIVISION_ID, ITEM_ID, TO_SITE)
	SELECT 'MKT'                  AS TYPE
	,      U.MKT_USER             AS MAIL_RECEIVER
	,      X.DIVISION_ID          AS DIVISION_ID
	,      X.COMPANY_ID           AS COMPANY_ID
	,      X.PLAN_START_YYYYMMDD  AS PLAN_START_YYYYMMDD
	,      X.FROM_SITE            AS FROM_SITE 
	,      X.ITEM_ID              AS ITEM_ID
	,      X.FROM_YYYYMMDD        AS YYYYMMDD
	FROM SSP_ANL_SHIP_PLAN_C P WITH(NOLOCK) 
		 JOIN ITEM X WITH(NOLOCK) 
		   ON P.DIVISION_ID = X.DIVISION_ID 
          AND P.COMPANY_ID  = X.COMPANY_ID
		  AND P.PLAN_START_YYYYMMDD = X.PLAN_START_YYYYMMDD
		  AND P.FROM_SITE = X.FROM_SITE 
		  AND P.YYYYMMDD  BETWEEN X.FROM_YYYYMMDD AND  X.TO_YYYYMMDD 
		  AND P.MEASURE IN ( 'SHIP_REQ' , 'SHIP_PLAN') 
		  AND P.QTY > 0 
		 JOIN SSP_MKT_USER_V U WITH(NOLOCK) 
		   ON U.DIVISION_ID   = P.DIVISION_ID  
		  AND U.TO_SITE       = P.TO_SITE 
		  AND U.ITEM_ID       = P.ITEM_ID 
		  AND U.PROJECT_CODE  = P.PROJECT_CODE
	GROUP BY U.MKT_USER    
	,        X.DIVISION_ID      
	,        X.COMPANY_ID    
	,        X.PLAN_START_YYYYMMDD 
	,        X.FROM_SITE
	,        X.ITEM_ID
	,        X.FROM_YYYYMMDD

UNION ALL  
	--REQUESTOR
	SELECT 'REQ'                  AS TYPE
	,      P.REQUESTOR            AS MAIL_RECEIVER
	,      X.DIVISION_ID          AS DIVISION_ID
	,      X.COMPANY_ID           AS COMPANY_ID 
	,      X.PLAN_START_YYYYMMDD  AS PLAN_START_YYYYMMDD
	,      X.FROM_SITE            AS FROM_SITE 
	,      X.ITEM_ID              AS ITEM_ID
	,      X.FROM_YYYYMMDD             AS YYYYMMDD
	FROM SSP_ANL_SHIP_PLAN_C P WITH(NOLOCK) 
		 JOIN ITEM X WITH(NOLOCK) 
		   ON P.DIVISION_ID = X.DIVISION_ID 
		  AND P.PLAN_START_YYYYMMDD = X.PLAN_START_YYYYMMDD
		  AND P.FROM_SITE = X.FROM_SITE 
		  AND P.YYYYMMDD BETWEEN X.FROM_YYYYMMDD AND  X.TO_YYYYMMDD 
		  AND P.MEASURE IN ( 'SHIP_REQ' , 'SHIP_PLAN') 
		  AND P.REQUESTOR IS NOT NULL 
		  AND P.QTY > 0 
	GROUP BY P.REQUESTOR  
	,        X.DIVISION_ID     
	,        X.COMPANY_ID     
	,        X.PLAN_START_YYYYMMDD 
	,        X.FROM_SITE
	,        X.ITEM_ID
	,        X.FROM_YYYYMMDD
	) T
WHERE T.MAIL_RECEIVER ='juhlee'
GROUP BY T.MAIL_RECEIVER
,        T.DIVISION_ID  
,        T.COMPANY_ID        
,        T.PLAN_START_YYYYMMDD 
,        T.FROM_SITE
,        T.ITEM_ID
,        T.YYYYMMDD











