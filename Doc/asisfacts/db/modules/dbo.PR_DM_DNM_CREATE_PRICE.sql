/*
 *===================================================================================================
 * PROGRAM ID   : PR_DM_DNM_CREATE_PRICE
 * DESCRIPTION  : 인터페이스받은 영업이익율과 표준원가를 이용해서 PRICE 자동 생성
                  매주 월요일 아침에 PRICE 를 만들어서 52주 구간에 INSERT 하고, 
				                     52주 구간내에 비어있는 PRICE 는 마지막 PRICE 를 52주 구간까지 뿌린다.
				ESS 전용임
 * PROGRAM HISTORY
 *===================================================================================================
 *   DATE       IN CHARGE      DESCRIPTION
 *===================================================================================================
 2022.01.22		hwi1993			22년 하반기 과제
 2022.02.03		hwi1993			사용자교육 후 수정사항 반영
 2022.02.18     HWI1993			종료로그가 없어서 추가함.
 2022.04.05     HWI1993			GM JV 작업
 2024.03.27		JSSBAE			[E20240228-001118]_[영업/마케팅 PI팀] Sales Price 배치 업데이트
  *===================================================================================================
	EXEC PR_DM_DNM_CREATE_PRICE '82'
*/

CREATE PROCEDURE [dbo].[PR_DM_DNM_CREATE_PRICE]
	@P_DIVISION_ID NVARCHAR(30)				-- 사업부 확장에 대비해서 사업부별로 호출하도록 한다.
AS

BEGIN

	SET NOCOUNT ON; 
    SET TRANSACTION ISOLATION LEVEL READ COMMITTED;
    SET XACT_ABORT ON;

	-- LOG 용 변수 설정
    DECLARE @V_PROGRAM_NAME		NVARCHAR(150) = 'PR_DM_DNM_CREATE_PRICE';
    DECLARE @V_LOG_TYPE			NVARCHAR(30); -- START/END/ERROR/...
    DECLARE @N_LOG_COUNT		INTEGER = 0;
    DECLARE @V_LOG_MESSAGE		NVARCHAR(1000);
    DECLARE @V_DESCRIPTION		NVARCHAR(500);
    DECLARE @D_EVENT_DATE		DATETIME;
    DECLARE @N_DELETE_COUNT		INTEGER = 0;
    DECLARE @N_INSERT_COUNT     INTEGER = 0;
	DECLARE @V_CREATED_BY		NVARCHAR(150)	= 'SYS_PRICE';

	-- 시작 LOG
	SET @V_LOG_TYPE = 'START';
	SET @V_LOG_MESSAGE = '########## START OF PROCEDURE ##########';
	SET @V_DESCRIPTION = '';
	SET @D_EVENT_DATE = SYSDATETIME();
	EXEC  PR_DM_SYS_LOG_BATCH @V_PROGRAM_NAME, @V_LOG_TYPE, @N_LOG_COUNT, @V_LOG_MESSAGE, @V_DESCRIPTION, @D_EVENT_DATE, @V_CREATED_BY;

	-- 시작 LOG  (END)
	SET @V_LOG_MESSAGE = NULL
	
	DECLARE @V_START_YYYYMMDD	NVARCHAR(8)	-- 당주 월요일
			, @V_END_YYYYMMDD	NVARCHAR(8)	-- 52주 종료일
	
	BEGIN TRAN
	
	BEGIN TRY

		SELECT @V_START_YYYYMMDD = MIN(BASIS_START_DATE)
			, @V_END_YYYYMMDD = MAX(BASIS_END_DATE)
		FROM SCM_SYS_CALENDAR_M M WITH(NOLOCK) 
		WHERE M.BASIS_YYYYMMDD >= CONVERT(CHAR(8), DATEADD(DD, -7, DBO.FN_NEXT_DAY(GETDATE(), 'MON')), 112)  --당주 월요일부터
			AND M.BASIS_YYYYMMDD < CONVERT(CHAR(8), DATEADD(WW, 52, CONVERT(CHAR(8), DATEADD(DD, -7, DBO.FN_NEXT_DAY(GETDATE(), 'MON')), 112)),112)  -- 52주후 월요일까지

		---------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
		-- 프로젝트별 영업이익율 및 자재별 표준원가 취합
		---------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
		IF OBJECT_ID (N'tempdb..#T_PJT', N'U') IS NOT NULL 
			DROP TABLE #T_PJT
		IF OBJECT_ID (N'tempdb..#T_MODEL', N'U') IS NOT NULL 
			DROP TABLE #T_MODEL
		IF OBJECT_ID (N'tempdb..#T_SSPM', N'U') IS NOT NULL 
			DROP TABLE #T_SSPM
		IF OBJECT_ID (N'tempdb..#T_PRICE_PK', N'U') IS NOT NULL 
			DROP TABLE #T_PRICE_PK
		IF OBJECT_ID (N'tempdb..#T_INSERT', N'U') IS NOT NULL 
			DROP TABLE #T_INSERT
		IF OBJECT_ID (N'tempdb..#T_MISSING', N'U') IS NOT NULL 
			DROP TABLE #T_MISSING
		IF OBJECT_ID (N'tempdb..#T_ITEM', N'U') IS NOT NULL 
			DROP TABLE #T_ITEM

		-- 상품만 넣는 테이블
		CREATE TABLE #T_ITEM (
			DIVISION_ID		NVARCHAR(30)
			, ITEM_ID		NVARCHAR(50)
			)
		
		CREATE TABLE #T_SSPM (
			DIVISION_ID		NVARCHAR(30)
			, PROJECT_CODE	NVARCHAR(50)
			, SCM_SITE_ID	NVARCHAR(30)
			, ITEM_ID		NVARCHAR(50)
			, CURRENCY		NVARCHAR(10)
			)

		
		CREATE TABLE #T_MODEL(
			DIVISION_ID		NVARCHAR(30)
			, PROJECT_CODE	NVARCHAR(50)
			, SCM_SITE_ID	NVARCHAR(30)
			, ITEM_ID		NVARCHAR(50)
			, CURRENCY		NVARCHAR(10)
			, STD_COST		NUMERIC(20,5)
			, OPM_RATIO		NUMERIC(30,10)
			, PRICE			NUMERIC(20,10)
			)

		CREATE TABLE #T_PJT(
			DIVISION_ID		NVARCHAR(30)
			, PROJECT_CODE	NVARCHAR(50)
			, OPM_RATIO		NUMERIC(30,10)
			)
			
		CREATE TABLE #T_PRICE_PK (
			DIVISION_ID		NVARCHAR(30)
			, PROJECT_CODE	NVARCHAR(50)
			, SCM_SITE_ID	NVARCHAR(30)
			, PLANT_SITE_ID	NVARCHAR(30)
			, ITEM_ID		NVARCHAR(50)
			, CURRENCY		NVARCHAR(10)
			, DOM_EXP		NVARCHAR(3)
			, FCST_TYPE		NVARCHAR(20)
			, INCOTERMS		NVARCHAR(10)
			)

		CREATE TABLE #T_NEW_PRICE (
			DIVISION_ID		NVARCHAR(30)
			, PROJECT_CODE	NVARCHAR(50)
			, SCM_SITE_ID	NVARCHAR(30)
			, PLANT_SITE_ID	NVARCHAR(30)
			, ITEM_ID		NVARCHAR(50)
			, CURRENCY		NVARCHAR(10)
			, PRICE			NUMERIC(20,10)
			, INSERT_FLAG	NCHAR(1)
			)

		CREATE TABLE #T_INSERT (
			DIVISION_ID		NVARCHAR(30)
			, PROJECT_CODE	NVARCHAR(50)
			, SCM_SITE_ID	NVARCHAR(30)
			, PLANT_SITE_ID	NVARCHAR(30)
			, ITEM_ID		NVARCHAR(50)
			, CURRENCY		NVARCHAR(10)
			, DOM_EXP		NVARCHAR(3)
			, FCST_TYPE		NVARCHAR(20)
			, INCOTERMS		NVARCHAR(10)
			, MEASURE		NVARCHAR(30)
			, PRICE			NUMERIC(20,10)
			, GUBUN			NCHAR(1)
			)

		
			
		CREATE TABLE #T_MISSING (
			DIVISION_ID		NVARCHAR(30)
			, PROJECT_CODE	NVARCHAR(50)
			, SCM_SITE_ID	NVARCHAR(30)
			, PLANT_SITE_ID	NVARCHAR(30)
			, ITEM_ID		NVARCHAR(50)
			, CURRENCY		NVARCHAR(10)
			, DOM_EXP		NVARCHAR(3)
			, FCST_TYPE		NVARCHAR(20)
			, INCOTERMS		NVARCHAR(10)
			, YYYYMMDD		NVARCHAR(8)
			, BF_YYYYMMDD	NVARCHAR(8)
			, MEASURE		NVARCHAR(30)
			, PRICE			NUMERIC(20,10)

			)

PRINT ( 'A--00--00 : ' + CONVERT(NVARCHAR(30), GETDATE(), 121))
		--[E20240228-001118]_[영업/마케팅 PI팀] Sales Price 배치 업데이트
		--현재 DM_MST_ITEM_SINGLE_V 문제로 해당 부분으로 변경작업 진행(CSR과 연관이 없더라도, 프로시져를 수정하는 경우 해당건이 존재하면 수정하기로함.)
		SELECT DIVISION_ID,ITEM_ID,ITEM_NAME,ITEM_CLASS,ITEM_CLASS_NAME,NICK_NAME,ITEM_TYPE,MDM_PROJECT_NAME,MIN_CAPACITY,FORECAST_INFO_BIZ_TYPE,FORECAST_INFO_PRODUCT_GROUP
			,FORECAST_INFO_CELL_MODEL,FORECAST_INFO_CELL_PACK_COUNT,FORECAST_INFO_SPEC,FORECAST_INFOR_VERSION,CELL_TYPE,ENERGE, CELL_QUANTITY 
		INTO #TEMP_DM_MST_ITEM_SINGLE_V
		FROM 
		(
				SELECT	T1.DIVISION_ID,
					T1.ITEM_ID, 
					MAX(T1.ITEM_NAME)					AS ITEM_NAME,				--해당 컬럼이 NULL인 경우가 잇으므로 하나로 통일
					MAX(T1.ITEM_CLASS)					AS ITEM_CLASS,				--해당 컬럼이 NULL인 경우가 잇으므로 하나로 통일
					MAX(T1.ITEM_CLASS_NAME)					AS ITEM_CLASS_NAME,		--해당 컬럼이 NULL인 경우가 잇으므로 하나로 통일
					MAX(T1.NICK_NAME)						AS NICK_NAME,			--닉네임이 NULL인 경우가 있으므로 하나로 통일
					case  min( case when T1.item_type = 'P' then 1					--타입이 사이트와 사업부, 법인에 따라 다양하게 존재 하므로 하나로 통일
									when T1.item_type = 'H' then 2					--또한 가장 완성된 상태의 자재 타입을 판매한다고 가정, 해당 자재타입을 사용함
									when T1.item_type = 'Q' then 3
									else 4 end )  
													when 1 then 'P' 
													when 2 then 'H'
													when 3 then 'Q'
													else 'R' end	AS ITEM_TYPE,
					MAX(T1.MATERIAL_CLASS_NAME				)		AS MATERIAL_CLASS_NAME,
					MAX(T1.ITEM_UOM							)		AS ITEM_UOM,
					MAX(T1.SPEC								)		AS SPEC,
					MAX(T1.MDM_PROJECT_NAME					)		AS MDM_PROJECT_NAME,
					MAX(T1.MIN_CAPACITY						)		AS MIN_CAPACITY,
					MAX(T2.FORECAST_INFO_BIZ_TYPE			)		AS FORECAST_INFO_BIZ_TYPE,
					MAX(T2.FORECAST_INFO_PRODUCT_GROUP		)		AS FORECAST_INFO_PRODUCT_GROUP,
					MAX(T2.FORECAST_INFO_CELL_MODEL			)		AS FORECAST_INFO_CELL_MODEL,
					MAX(T2.FORECAST_INFO_CELL_PACK_COUNT	)		AS FORECAST_INFO_CELL_PACK_COUNT,
					MAX(T2.FORECAST_INFO_SPEC				)		AS FORECAST_INFO_SPEC,
					MAX(T2.FORECAST_INFOR_VERSION			)		AS FORECAST_INFOR_VERSION,
					MAX(T1.ACTIVE_FLAG						)		AS ACTIVE_FLAG,  -- 20180720 ADD 'Y'대상중 1건 추출
					MAX(T2.CELL_TYPE						)		AS CELL_TYPE,  -- 20180911 ADD cell_type
					MAX(T1.ENERGE							)  	    AS ENERGE,			-- 20200116 khsong ADD ENERGE
					MAX(T1.CELL_QUANTITY					)	    AS CELL_QUANTITY,	-- 20200116 khsong ADD CELL_QUANTITY
					MAX(T1.SCP_EXTRA_SPEC)						  AS SCP_EXTRA_SPEC		-- [20210428 SJHAN / CSR ID:C20210323-000420]
				FROM SCM_MST_ITEM_SN T1 WITH(NOLOCK)					
				INNER JOIN ( SELECT DIVISION_ID, LEFT(ITEM_ID, 12) AS ITEM_ID
								, MAX(FORECAST_INFO_BIZ_TYPE) AS FORECAST_INFO_BIZ_TYPE
								, MAX(FORECAST_INFO_PRODUCT_GROUP) AS FORECAST_INFO_PRODUCT_GROUP
								, MAX(FORECAST_INFO_CELL_MODEL) AS FORECAST_INFO_CELL_MODEL
								, MAX(FORECAST_INFO_CELL_PACK_COUNT) AS FORECAST_INFO_CELL_PACK_COUNT
								, MAX(FORECAST_INFO_SPEC) AS FORECAST_INFO_SPEC
								, MAX(FORECAST_INFOR_VERSION) AS FORECAST_INFOR_VERSION
								, MAX(CELL_TYPE) AS CELL_TYPE
							FROM  SCM_MST_ITEM_SN T2 WITH(NOLOCK) 
							GROUP BY DIVISION_ID, LEFT(ITEM_ID, 12)
						) T2 ON T1.DIVISION_ID = T2.DIVISION_ID
					AND SUBSTRING(T1.ITEM_ID,1,12) = T2.ITEM_ID
				where 1=1
				AND		T1.DIVISION_ID = @P_DIVISION_ID
				AND		T1.ACTIVE_FLAG = 'Y'
				--WHERE ACTIVE_FLAG = 'Y'  -- 20180720 ADD 'Y'대상만
				--LGCE_FPDEV_TR.DBO.SCM_ITEM_M T1
				group by T1.DIVISION_ID, T1.ITEM_ID
		) T2						
		WHERE DIVISION_ID = @p_division_id					
		GROUP BY DIVISION_ID,ITEM_ID,ITEM_NAME,ITEM_CLASS,ITEM_CLASS_NAME,NICK_NAME,ITEM_TYPE,MDM_PROJECT_NAME,MIN_CAPACITY,FORECAST_INFO_BIZ_TYPE,FORECAST_INFO_PRODUCT_GROUP
				,FORECAST_INFO_CELL_MODEL,FORECAST_INFO_CELL_PACK_COUNT,FORECAST_INFO_SPEC,FORECAST_INFOR_VERSION,CELL_TYPE,ENERGE, CELL_QUANTITY

PRINT ( 'B--00--00 : ' + CONVERT(NVARCHAR(30), GETDATE(), 121))

		--[E20240228-001118]_[영업/마케팅 PI팀] Sales Price 배치 업데이트
		--원로직은 82번 사업부만 사용하고, 타 사업부는 하단의로직만 사용하기로 함. 하여 원로직 구간은 82번만 태움.
		IF @P_DIVISION_ID = '82'
		BEGIN

		-- 상품만 뽑아서 넣는다.
		INSERT INTO #T_ITEM ( DIVISION_ID, ITEM_ID )
		SELECT DIVISION_ID, ITEM_ID
		FROM #TEMP_DM_MST_ITEM_SINGLE_V
		WHERE ITEM_TYPE = 'Q'
			AND DIVISION_ID = @P_DIVISION_ID

PRINT ( 'C--00--00 : ' + CONVERT(NVARCHAR(30), GETDATE(), 121))

		-- PRICE 테이블에서 3개의 메저로 구성되지 않은 데이터는 삭제한다.
		DELETE A
		FROM SCM_MST_FUTURE_PRICE A
		JOIN (
			SELECT A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, A.PLANT_SITE_ID, A.ITEM_ID, A.YYYYMMDD, A.CURRENCY, A.DOM_EXP, A.FCST_TYPE, A.INCOTERMS
			FROM SCM_MST_FUTURE_PRICE A WITH(NOLOCK)
			JOIN #T_ITEM B ON A.DIVISION_ID= B.DIVISION_ID AND A.ITEM_ID = B.ITEM_ID
			WHERE A.DIVISION_ID = @P_DIVISION_ID
				AND A.YYYYMMDD BETWEEN @V_START_YYYYMMDD AND @V_END_YYYYMMDD
			GROUP BY A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, A.PLANT_SITE_ID, A.ITEM_ID, A.YYYYMMDD, A.CURRENCY, A.DOM_EXP, A.FCST_TYPE, A.INCOTERMS
			HAVING COUNT(*) <> 3
			) B ON A.DIVISION_ID	= B.DIVISION_ID
				AND A.PROJECT_CODE	= B.PROJECT_CODE
				AND A.SCM_SITE_ID	= B.SCM_SITE_ID
				AND A.PLANT_SITE_ID = B.PLANT_SITE_ID
				AND A.ITEM_ID		= B.ITEM_ID
				AND A.YYYYMMDD		= B.YYYYMMDD
				AND A.CURRENCY		= B.CURRENCY
				AND A.DOM_EXP		= B.DOM_EXP
				AND A.FCST_TYPE		= B.FCST_TYPE
				AND A.INCOTERMS		= B.INCOTERMS
		JOIN #T_ITEM C ON A.DIVISION_ID= C.DIVISION_ID AND A.ITEM_ID = C.ITEM_ID
		WHERE A.DIVISION_ID = @P_DIVISION_ID
		
PRINT ( 'D--00--00 : ' + CONVERT(NVARCHAR(30), GETDATE(), 121))

		-- 대상 취합
		INSERT INTO #T_SSPM ( DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, CURRENCY )
		SELECT A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.CURRENCY
		FROM SCM_MST_SITE_ITEM A WITH(NOLOCK)
		JOIN #T_ITEM B ON A.DIVISION_ID= B.DIVISION_ID AND A.ITEM_ID = B.ITEM_ID
		WHERE A.DIVISION_ID = @P_DIVISION_ID
			AND A.VALID_YN = 'Y'
			AND ISNULL(A.CURRENCY,'') <> ''
			
PRINT ( 'E--00--00 : ' + CONVERT(NVARCHAR(30), GETDATE(), 121))

		-- PRICE 테이블의 PK ( 마지막 일자를 기준으로 통화를 한 개씩만 뽑는다 )
		INSERT INTO #T_PRICE_PK ( DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, PLANT_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, CURRENCY )
		SELECT A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, '' AS PLANT_SITE_ID, A.ITEM_ID, A.DOM_EXP, A.FCST_TYPE, A.INCOTERMS, MAX(A.CURRENCY)
		FROM SCM_MST_FUTURE_PRICE A WITH(NOLOCK)
		JOIN ( SELECT A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, A.PLANT_SITE_ID, A.ITEM_ID, A.DOM_EXP, A.FCST_TYPE, A.INCOTERMS, MAX(A.YYYYMMDD) AS MAX_YMD
				FROM SCM_MST_FUTURE_PRICE A WITH(NOLOCK)
				JOIN #T_ITEM B ON A.DIVISION_ID= B.DIVISION_ID AND A.ITEM_ID = B.ITEM_ID
				WHERE A.DIVISION_ID = @P_DIVISION_ID
					AND A.PRICE <> 0
					AND A.YYYYMMDD BETWEEN @V_START_YYYYMMDD AND @V_END_YYYYMMDD
					AND A.MEASURE = 'LOC'
				GROUP BY A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, A.PLANT_SITE_ID, A.ITEM_ID, A.DOM_EXP, A.FCST_TYPE, A.INCOTERMS
			) B ON A.DIVISION_ID = B.DIVISION_ID
				AND A.PROJECT_CODE = B.PROJECT_CODE
				AND A.SCM_SITE_ID = B.SCM_SITE_ID
				AND A.PLANT_SITE_ID = B.PLANT_SITE_ID
				AND A.ITEM_ID = B.ITEM_ID
				AND A.DOM_EXP = B.DOM_EXP
				AND A.FCST_TYPE = B.FCST_TYPE
				AND A.INCOTERMS = B.INCOTERMS
				AND A.YYYYMMDD = B.MAX_YMD
		JOIN #T_ITEM C ON A.DIVISION_ID= C.DIVISION_ID AND A.ITEM_ID = C.ITEM_ID
		WHERE A.DIVISION_ID = @P_DIVISION_ID
			AND A.PRICE <> 0
			AND A.YYYYMMDD BETWEEN @V_START_YYYYMMDD AND @V_END_YYYYMMDD
			AND A.MEASURE = 'LOC'
		GROUP BY A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.DOM_EXP, A.FCST_TYPE, A.INCOTERMS
		
PRINT ( 'F--00--00 : ' + CONVERT(NVARCHAR(30), GETDATE(), 121))

		-- 영업이익율
		INSERT INTO #T_PJT ( DIVISION_ID, PROJECT_CODE, OPM_RATIO )
		SELECT A.DIVISION_ID, A.PROJECT_CODE
			, CASE WHEN ISNULL(TRY_CAST(A.ATTRIBUTE1 AS NUMERIC(20,10)), 0) >= 0 THEN ISNULL(TRY_CAST(A.ATTRIBUTE1 AS NUMERIC(20,10)), 0) 
					ELSE 0 END	-- 양수값만 인정하고, 아니면 0으로 처리
		FROM SCM_MST_PROJECT A WITH(NOLOCK)
		JOIN (
			SELECT A.DIVISION_ID, A.PROJECT_CODE, MAX(A.PROJECT_VER_SEQ) AS SEQ
			FROM SCM_MST_PROJECT A WITH(NOLOCK)
			WHERE A.DROP_YN = 'N'
				AND A.DIVISION_ID = @P_DIVISION_ID
			GROUP BY A.DIVISION_ID, A.PROJECT_CODE
			) B ON A.DIVISION_ID = B.DIVISION_ID 
				AND A.PROJECT_CODE = B.PROJECT_CODE
				AND A.PROJECT_VER_SEQ = B.SEQ
		WHERE A.DIVISION_ID = @P_DIVISION_ID
			
PRINT ( 'G--00--00 : ' + CONVERT(NVARCHAR(30), GETDATE(), 121))

		-- 표준원가
		INSERT INTO #T_MODEL ( DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, CURRENCY, STD_COST, OPM_RATIO )
		SELECT A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, C.CURRENCY, MAX(C.STANDARD_COST), D.OPM_RATIO
		FROM #T_SSPM A
		LEFT OUTER JOIN ( 
						SELECT DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, MAX(CURRENCY) AS CURRENCY
						FROM #T_PRICE_PK 
						GROUP BY DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID
						) B ON A.DIVISION_ID = B.DIVISION_ID 
							AND A.PROJECT_CODE = B.PROJECT_CODE
							AND A.SCM_SITE_ID = B.SCM_SITE_ID
							AND A.ITEM_ID = B.ITEM_ID
		JOIN SCM_MST_ITEM_SN C ON A.DIVISION_ID = C.DIVISION_ID AND A.ITEM_ID = C.ITEM_ID 
						AND CASE WHEN B.CURRENCY IS NOT NULL THEN B.CURRENCY ELSE '' END = CASE WHEN B.CURRENCY IS NOT NULL THEN C.CURRENCY ELSE '' END 
						AND CASE WHEN B.CURRENCY IS NULL THEN A.CURRENCY ELSE '' END = CASE WHEN B.CURRENCY IS NULL THEN C.CURRENCY ELSE '' END 
						AND C.ITEM_TYPE = 'Q'
		JOIN #T_PJT D ON A.DIVISION_ID = D.DIVISION_ID AND A.PROJECT_CODE = D.PROJECT_CODE
		WHERE C.STANDARD_COST IS NOT NULL
			AND A.DIVISION_ID = @P_DIVISION_ID
		GROUP BY A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, C.CURRENCY, D.OPM_RATIO
		
PRINT ( 'H--00--00 : ' + CONVERT(NVARCHAR(30), GETDATE(), 121))

		-- 단가 생성
		UPDATE #T_MODEL
		SET PRICE = STD_COST + ( STD_COST * OPM_RATIO )


		---------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
		-- PRICE 테이블에 넣기 위해 PK 값 별로 정리
		---------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

		-- PRICE 테이블에 없는데, #T_MODEL 에만 있는 값들 취합
		-- 우선순위 적용해서 PK 값 생성
		-- 생성된 값들 INSERT
