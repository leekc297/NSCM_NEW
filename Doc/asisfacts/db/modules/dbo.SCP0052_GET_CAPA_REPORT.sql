	,@p_plant_id			NVARCHAR(MAX) = 'A040'
	,@p_factory_id			NVARCHAR(MAX) = 'A1'
	,@p_version_id			NVARCHAR(MAX) = '202110_001,202107_002'
	,@p_line_id				NVARCHAR(MAX) = 'A1A02'
	,@p_operation_id		NVARCHAR(MAX) = 'A8000'
