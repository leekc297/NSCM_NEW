ex>	DECLARE @p_today_yyyymmdd		NVARCHAR(8) = '20210203'
	,@p_from_yyyymm			NVARCHAR(6) = '202101'
	,@p_to_yyyymm			NVARCHAR(6) = '202112'
	,@p_division_id			NVARCHAR(20) = '81'
