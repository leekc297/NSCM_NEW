CREATE PROCEDURE [dbo].[SCP0132_GET_SEARCH_INFO]
AS
BEGIN
	
    SET NOCOUNT ON; 
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED

	--1. Plan Group 정보 
	select OPMZ_PLAN_GR_ID	AS CODE
		, OPMZ_PLAN_GR_NAME	AS NAME
		, DIVISION_ID
	from SCP_OPMZ_PLAN_GR_M with(nolock)
	WHERE 1=1
	 AND VALID_YN='Y'
	ORDER BY OPMZ_PLAN_GR_NAME

	--2. 재고 SCM SITE ID 
		SELECT DIVISION_ID
			 ,CODE
			 ,NAME
		FROM (
 				SELECT DISTINCT A.DIVISION_ID
					, SCM_SITE_ID AS CODE 
					, SCM_SITE_ID AS NAME
					, SITE_TYPE
				FROM   SCM_MST_SITE A WITH(NOLOCK) 
				WHERE  1 = 1
				AND A.SITE_TYPE = 'SALES'	
				AND A.DIVISION_ID != '40'
				AND A.VALID_YN = 'Y'	
				UNION ALL
				SELECT DISTINCT A.DIVISION_ID
					, A.SCM_SITE_ID AS CODE 
					, A.SCM_SITE_ID AS NAME
					, A.SITE_TYPE
				FROM   SCM_MST_SITE AS A WITH(NOLOCK) 
				LEFT JOIN SCM_MST_SITE_ITEM AS B WITH(NOLOCK) 
					ON A.DIVISION_ID = B.DIVISION_ID AND A.SCM_SITE_ID = B.SCM_SITE_ID
				WHERE  1 = 1
				AND A.SITE_TYPE = 'SALES'
				AND  A.DIVISION_ID = '40'
				AND A.VALID_YN = 'Y'
				UNION ALL
				SELECT DISTINCT A.DIVISION_ID
					, SCM_SITE_ID AS CODE 
					, SCM_SITE_ID AS NAME
					, A.SITE_TYPE
				FROM   [dbo].[SCM_MST_SITE] A
				WHERE  1 = 1
				AND    A.SITE_TYPE = 'PLANT'
			   ) X
		ORDER BY SITE_TYPE, NAME  -- A.DIVISION_ID

	--SELECT DISTINCT A.DIVISION_ID
	--	, SCM_SITE_ID AS CODE 
	--	, SCM_SITE_ID AS NAME
	--FROM   SCM_MST_SITE A WITH(NOLOCK) 
	--WHERE  1 = 1
	--AND A.SITE_TYPE = 'SALES'	
	--AND A.DIVISION_ID != '40'
	--AND A.VALID_YN = 'Y'	
	--UNION ALL
	--SELECT DISTINCT A.DIVISION_ID
	--	, A.SCM_SITE_ID AS CODE 
	--	, A.SCM_SITE_ID AS NAME
	--FROM   SCM_MST_SITE AS A WITH(NOLOCK) 
	--LEFT JOIN SCM_MST_SITE_ITEM AS B WITH(NOLOCK) 
	--	ON A.DIVISION_ID = B.DIVISION_ID AND A.SCM_SITE_ID = B.SCM_SITE_ID
	--WHERE  1 = 1
	--AND A.SITE_TYPE = 'SALES'
	--AND  A.DIVISION_ID = '40'
	--AND A.VALID_YN = 'Y'
	--UNION ALL
	--SELECT DISTINCT A.DIVISION_ID
	--	, SCM_SITE_ID AS CODE 
	--	, SCM_SITE_ID AS NAME
	--FROM   [dbo].[SCM_MST_SITE] A
	--WHERE  1 = 1
	--AND    A.SITE_TYPE = 'PLANT'
	--ORDER BY A.DIVISION_ID
	

	-- 3.PLANT_SITE_BY_DIVISION
	SELECT DISTINCT A.DIVISION_ID
		, a.SCM_SITE_ID AS CODE 
		, a.SCM_SITE_ID AS NAME
	FROM   [dbo].[SCM_MST_SITE] A  WITH(NOLOCK)
	WHERE  1 = 1
	AND    A.SITE_TYPE = 'PLANT'
	AND    A.VALID_YN  = 'Y'
	ORDER BY A.SCM_SITE_ID, A.DIVISION_ID
  

   -- 4. STAGE 최적화 
   SELECT M.SEGMENT1  AS DIVISION_ID
         ,M.SEGMENT3 AS CODE
         ,M.ATTRIBUTE1 AS NAME
   FROM dbo.SCM_ADM_LOOKUP_MASTER_DETAIL M WITH(NOLOCK)
   WHERE M.LOOKUP_TYPE LIKE 'OPMZ_STAGE_CD'
   AND   M.VALID_YN='Y'
   AND   M.ATTRIBUTE2 ='Y'

   -- 5. Model Group
   SELECT DISTINCT A.DIVISION_ID  
         ,A.MDL_GR_NM   AS CODE
		 ,A.MDL_GR_NM   AS NAME
     FROM dbo.SCP_OPMZ_CONSTRAINT_OF_SHIPMENT_QTY a  WITH(NOLOCK)
	 ORDER BY A.MDL_GR_NM

      --6.ITEM_ID 조회
   	  SELECT distinct
		   I.DIVISION_ID
		 , I.ITEM_ID	 
	  FROM   SCP_MST_FINAL_ITEM I WITH(NOLOCK)	
	  WHERE 1=1
END

