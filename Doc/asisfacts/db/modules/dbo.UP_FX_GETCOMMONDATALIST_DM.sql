CREATE PROCEDURE [dbo].[UP_FX_GETCOMMONDATALIST_DM]
	  @CODE	NVARCHAR(100)
	, @PARAM1 NVARCHAR(4000)
	, @PARAM2 NVARCHAR(4000)
	, @PARAM3 NVARCHAR(4000)
	, @PARAM4 NVARCHAR(4000)
	, @PARAM5 NVARCHAR(4000)
AS
BEGIN
	SET NOCOUNT ON;
	
	IF @CODE = 'PR_SPLANT'
	BEGIN
		SELECT DISTINCT SEGMENT1 AS CODE, SEGMENT1 AS NAME
		FROM SCM_ADM_LOOKUP_MASTER_DETAIL A (NOLOCK)
		WHERE LOOKUP_TYPE = 'DM_PR_SLOC'
			AND VALID_YN = 'Y'
	END
	ELSE IF @CODE = 'PR_SLOC'
	BEGIN
		SELECT SEGMENT2 AS CODE, ATTRIBUTE1 AS NAME
		FROM SCM_ADM_LOOKUP_MASTER_DETAIL A (NOLOCK)
		WHERE LOOKUP_TYPE = 'DM_PR_SLOC'
			AND A.SEGMENT1 LIKE '%' + @PARAM1 + '%'
			AND VALID_YN = 'Y'
		ORDER BY DISPLAY_SEQ
	END
	-- 2021.11.02		hwi1993		[PJ20209643] W/S 프로세스 -- FCST Type 권한 정리
	ELSE IF @CODE = 'FCST_TYPE'
	BEGIN
		

		IF @PARAM1 = N'DM Planner (W/S)'
		BEGIN	
			SELECT SEGMENT1 AS CODE, SEGMENT2 AS NAME
			FROM SCM_ADM_LOOKUP_MASTER_DETAIL A (NOLOCK)
			WHERE LOOKUP_TYPE = 'SALES_TYPE_CODE2'
				AND VALID_YN = 'Y'
			ORDER BY DISPLAY_SEQ
		END
		--[E20260211-001189]_AS FROM SITE 컬럼의 수정 가능 범위를 정하기 위하여 해당 부분 추가(START)
		ELSE IF @PARAM1 = N'EDIT_MODE'
		BEGIN			
			SELECT SEGMENT1 AS CODE, SEGMENT2 AS NAME
			FROM SCM_ADM_LOOKUP_MASTER_DETAIL A (NOLOCK)
			WHERE LOOKUP_TYPE = 'SALES_TYPE_CODE2'
			AND VALID_YN = 'Y'
			UNION ALL
			SELECT SEGMENT1 AS CODE, SEGMENT2 AS NAME
			FROM SCM_ADM_LOOKUP_MASTER_DETAIL A (NOLOCK)
			WHERE LOOKUP_TYPE = 'SALES_TYPE_CODE2_ADD'
			AND VALID_YN = 'Y'
		END		
		--[E20260211-001189]_AS FROM SITE 컬럼의 수정 가능 범위를 정하기 위하여 해당 부분 추가(END)
		ELSE
		BEGIN
			SELECT SEGMENT1 AS CODE, SEGMENT2 AS NAME
			FROM SCM_ADM_LOOKUP_MASTER_DETAIL A (NOLOCK)
			WHERE LOOKUP_TYPE = 'SALES_TYPE_CODE'
				AND ISNULL(ATTRIBUTE2,'') <> 'Y'
				AND VALID_YN = 'Y'
			ORDER BY DISPLAY_SEQ

		END
		
	END
	--2021.11.17		hwi1993		WS 관련 INCOTERMS 제한
	ELSE IF @CODE = 'AS_INCOTERMS'
	BEGIN
		--@PARAM1 : DIVISION
		--@PARAM2 : SCM_SITE_ID

		-- AS SITE 일 경우 AS 전용 INCOTERMS 를 사용하고, 아니면 일반 INCOTERMS 사용
		IF EXISTS (
			SELECT SEGMENT1 AS CODE, SEGMENT2 AS NAME
			FROM SCM_ADM_LOOKUP_MASTER_DETAIL A (NOLOCK)
			WHERE LOOKUP_TYPE = 'AS_SITE_PLANT'
				AND VALID_YN = 'Y'
				AND SEGMENT3 = @PARAM1
				AND SEGMENT1 = @PARAM2
				)
		BEGIN
			SELECT SEGMENT2 AS CODE, ATTRIBUTE1 AS NAME
			FROM SCM_ADM_LOOKUP_MASTER_DETAIL (NOLOCK)
			WHERE LOOKUP_TYPE = 'AS_INCOTERMS'
				AND VALID_YN = 'Y'
				AND SEGMENT1 = @PARAM1
		END
		ELSE
		BEGIN
			SELECT SEGMENT1 AS CODE, SEGMENT2 AS NAME 
			FROM SCM_ADM_LOOKUP_MASTER_DETAIL  WITH(NOLOCK) 
			WHERE LOOKUP_TYPE = 'INCOTERMS'
			AND   VALID_YN = 'Y' --[PJ20228272] NERP 대응 - INCOTERMS Valid 추가
			ORDER BY DISPLAY_SEQ
		END
		
	END
	
	-- AS에 따라 Site 취득이 달라짐(자동차, ESS)
	ELSE IF @CODE = 'SiteByEndCustomer'
	BEGIN
		Declare @AuthTypeParaSite varchar(100) = 'D'	
		
		If(@Param3 = 'JV Planner') SET @AuthTypeParaSite = 'J';

		SELECT CODE, NAME 
			FROM (
				SELECT  
						SCM_SITE_ID AS CODE 
						, SCM_SITE_ID AS NAME
						, 2 AS SORT_ORDER
				FROM   SCM_MST_SITE A WITH(NOLOCK) 
					INNER JOIN ( SELECT token FROM dbo.String_Split(@Param2,',') )AS C
					ON A.END_CUSTOMER = CASE WHEN @Param2 = 'ALL' OR @Param2 = '' THEN A.END_CUSTOMER ELSE C.token END 
				WHERE  1 = 1
				AND    A.SITE_TYPE = 'SALES'		
				AND CASE WHEN @Param1 = 'ALL' OR @Param1 = '' THEN @Param1			
							ELSE A.DIVISION_ID
 					END  IN ( SELECT token FROM dbo.String_Split(@Param1,','))						         
				AND    A.DIVISION_ID IN (SELECT CODE 
											FROM   TB_FX_UserGroupAuthExtention AS A WITH(NOLOCK) 
					    					WHERE  GroupID LIKE '%'+ @Param3 + '%'
							    			AND    UserID  LIKE '%'+ @Param4 + '%'
											AND    AuthType = @AuthTypeParaSite)
				AND A.VALID_YN = 'Y'	
				AND ISNULL(A.OPERATION_GROUP,'') <> 'W' 

				UNION ALL

				SELECT B.SCM_SITE_ID
					, B.SITE_DESCRIPTION
					, 1 AS SORT_ORDER
				FROM SCM_ADM_LOOKUP_MASTER_DETAIL A
				JOIN SCM_MST_SITE B ON A.SEGMENT3 = B.DIVISION_ID AND A.SEGMENT1 = B.SCM_SITE_ID
				WHERE A.LOOKUP_TYPE = 'AS_SITE_PLANT'
					AND A.SEGMENT3 = @Param1
					AND A.VALID_YN = 'Y'
					AND B.VALID_YN = 'Y'
					AND 1 = CASE WHEN @Param5 = 'Y' THEN 1 ELSE 0 END 
				) RESULTS
			ORDER BY SORT_ORDER, CODE
	END

	-- AS에 따라 Site 취득이 달라짐(소형)
	ELSE IF @CODE = 'SiteByEndCustomer40'
	BEGIN
		SELECT CODE, NAME 
        FROM (
			SELECT DISTINCT 
					A.SCM_SITE_ID AS CODE
					, A.SCM_SITE_ID AS NAME 
					, 2 AS SORT_ORDER
			FROM SCM_MST_SITE A WITH(NOLOCK) 
			LEFT JOIN SCM_MST_SITE_ITEM B  WITH(NOLOCK) 
			ON A.DIVISION_ID = B.DIVISION_ID AND A.SCM_SITE_ID = B.SCM_SITE_ID
			LEFT JOIN (
						SELECT DISTINCT A.USER_ID, A.DEPT_ID 
						FROM SCM_MST_SSO_USER_INFO A WITH(NOLOCK) , SCM_MST_SSO_DEPT_INFO B  WITH(NOLOCK) 
						WHERE A.DEPT_ID = B.DEPT_ID
						AND B.DEPT_ID IN ( SELECT token FROM dbo.String_Split(@Param1,','))	-- 20180801
					) C ON B.OWNER = C.USER_ID
			WHERE  1 = 1
			AND A.SITE_TYPE = 'SALES'		
			AND A.DIVISION_ID = '40'
			AND CASE WHEN @Param1 = 'ALL' OR @Param1 = '' THEN @Param1
						ELSE C.DEPT_ID
 				END  IN ( SELECT token FROM dbo.String_Split(@Param1,','))
			AND CASE WHEN @Param2 = 'ALL' OR @Param2 = '' THEN @Param2
						ELSE B.PROJECT_CODE
 				END  IN ( SELECT token FROM dbo.String_Split(@Param2,','))
			AND    A.DIVISION_ID IN (SELECT CODE 
										FROM  TB_FX_UserGroupAuthExtention AS A WITH(NOLOCK) 
					    				WHERE  GroupID LIKE '%'+ @Param3 + '%'
										AND    UserID  LIKE '%'+ @Param4 + '%'
										AND AuthType = 'D')
			AND A.VALID_YN = 'Y'
			AND ISNULL(A.OPERATION_GROUP,'') <> 'W' 
				
			UNION ALL

			SELECT B.SCM_SITE_ID
				, B.SITE_DESCRIPTION
				, 1 AS SORT_ORDER
            FROM SCM_ADM_LOOKUP_MASTER_DETAIL A
            JOIN SCM_MST_SITE B ON A.SEGMENT3 = B.DIVISION_ID AND A.SEGMENT1 = B.SCM_SITE_ID
            WHERE A.LOOKUP_TYPE = 'AS_SITE_PLANT'
                AND A.SEGMENT3 = '40'
                AND A.VALID_YN = 'Y'
                AND B.VALID_YN = 'Y'
				AND 1 = CASE WHEN @Param5 = 'Y' THEN 1 ELSE 0 END 
		) RESULTS
		ORDER BY SORT_ORDER, CODE
	END
	
	--2022.07.04		hwi1993		소형 Biz Plan 컬럼 추가
	ELSE IF @CODE = 'DM_CELL_PROD_SITE'
	BEGIN
			SELECT SEGMENT1 AS CODE, ATTRIBUTE1 AS NAME
			FROM SCM_ADM_LOOKUP_MASTER_DETAIL (NOLOCK)
			WHERE LOOKUP_TYPE = 'DM_CELL_PROD_SITE'
			--[E20240731-000845]_VALID 내용 소스에서 던지는 경우로 보여주도록 수정
			--AND VALID_YN = 'Y'
			AND VALID_YN = CASE WHEN @Param1 = 'ALL' OR @Param1 = '' THEN VALID_YN
								ELSE @Param1 END 
			ORDER BY DISPLAY_SEQ	
	END
	--2022.07.06		kdw2819		[C20220704-000441]Customer Handbook 로직 변경 요청의 건
	ELSE IF @CODE = 'DM_CUSTOMS_HANDBOOK'
	BEGIN
			SELECT SEGMENT1 AS CODE, SEGMENT2 AS NAME
			FROM SCM_ADM_LOOKUP_MASTER_DETAIL (NOLOCK)
			WHERE LOOKUP_TYPE = 'DM_CUSTOMS_HANDBOOK_40'
				AND VALID_YN = 'Y'
			ORDER BY DISPLAY_SEQ
	END
	ELSE IF @CODE = 'CUST_FCST_MEASURE'
	BEGIN
			SELECT SEGMENT2 AS CODE, ATTRIBUTE2 AS NAME
			FROM SCM_ADM_LOOKUP_MASTER_DETAIL (NOLOCK)
			WHERE LOOKUP_TYPE = @CODE
				AND VALID_YN = 'Y'
				AND SEGMENT1 = @PARAM1
				AND SEGMENT2 NOT IN (
						SELECT	DISTINCT A.COLUMN_NAME	AS CODE  
						FROM [dbo].[SCM_MST_SHEET_MEASURE] A WITH(NOLOCK)  
						WHERE 1 = 1  
						-- 5개의 화면에서 사용하는 MEASURE는 사용하지 못하도록 제외 한다.
						AND   PROGRAM_ID IN (
							'DMF0003'
							,'DMF0035'
							,'DMF0022'
							,'DMF0042'
							,'DMF0044'
						)
						AND   SHEET_NAME IN (
							'Mkt Fcst' 
							,'Mkt Fcst Waterfall'
							,'Sales Plan Waterfall'
							,'Biz Plan'
							,'MDF Reports'
						)
						AND    VALID_YN = 'Y'
			)
			ORDER BY DISPLAY_SEQ
	END
	
	--2022.11.16	HWI1993		C20221103-000432 EDI 상시 점검
	ELSE IF @CODE = 'EDI_SENDER_CODE'
	BEGIN
			SELECT SEGMENT2 AS CODE, ATTRIBUTE1 AS NAME
			FROM SCM_ADM_LOOKUP_MASTER_DETAIL (NOLOCK)
			WHERE LOOKUP_TYPE = 'EDI_SENDER_CODE'
				AND VALID_YN = 'Y'
				AND SEGMENT1 = '81'
			ORDER BY DISPLAY_SEQ
	
	END
	--2024.11.06		dsiol		[PJ2024-50647]자동차사업부 고객 수요 분석 기능 개선 - @CODE = 'DM_DEMAND_GAP_ANL_CD' 추가
	--2024.11.06 dsiol 고객수요 프로젝트 : POPUP - DMF0081_CustDemandAnalysis 에서 사용
	ELSE IF @CODE = 'DM_DEMAND_GAP_ANL_CD'
	BEGIN
		IF @PARAM1 = 'SEGMENT1' -- [ STEP 1 ]
			SELECT DISTINCT LK.SEGMENT1 AS CODE, LK.ATTRIBUTE1 AS NAME
			FROM SCM_ADM_LOOKUP_MASTER_DETAIL LK WITH(NOLOCK)
			WHERE LK.LOOKUP_TYPE = 'DM_DEMAND_GAP_ANL_CD'
			AND LK.VALID_YN = 'Y';
		ELSE IF @PARAM1 = 'SEGMENT2' -- [ STEP 2 ]
			SELECT DISTINCT LK.SEGMENT2 AS CODE, LK.ATTRIBUTE2 AS NAME
			FROM SCM_ADM_LOOKUP_MASTER_DETAIL LK WITH(NOLOCK)
			WHERE LK.LOOKUP_TYPE = 'DM_DEMAND_GAP_ANL_CD'
			AND LK.VALID_YN = 'Y' AND LK.SEGMENT1 = @PARAM2
		ELSE IF @PARAM1 = 'SEGMENT3' -- [ STEP 3 ]
			SELECT DISTINCT LK.SEGMENT3 AS CODE, LK.ATTRIBUTE3 AS NAME
			FROM SCM_ADM_LOOKUP_MASTER_DETAIL LK WITH(NOLOCK)
			WHERE LK.LOOKUP_TYPE = 'DM_DEMAND_GAP_ANL_CD'
			AND LK.VALID_YN = 'Y' AND LK.SEGMENT1 = @PARAM2 AND LK.SEGMENT2 = @PARAM3
		ELSE IF @PARAM1 = 'ALL'   
		-- 의도 : 값이 NAME으로 되어있어서 CODE를 찾기위해서 DataTable에 넣어놓고 검색하기위해 사용. 
			SELECT SEGMENT1 AS CODE , ATTRIBUTE1 AS NAME 
			FROM SCM_ADM_LOOKUP_MASTER_DETAIL LK WITH(NOLOCK) 
			WHERE LK.LOOKUP_TYPE = 'DM_DEMAND_GAP_ANL_CD' AND LK.VALID_YN = 'Y'
			UNION
			SELECT SEGMENT2 AS CODE , ATTRIBUTE2 AS NAME 
			FROM SCM_ADM_LOOKUP_MASTER_DETAIL LK WITH(NOLOCK) 
			WHERE LK.LOOKUP_TYPE = 'DM_DEMAND_GAP_ANL_CD' AND LK.VALID_YN = 'Y'
			UNION
			SELECT SEGMENT3 AS CODE , ATTRIBUTE3 AS NAME 
			FROM SCM_ADM_LOOKUP_MASTER_DETAIL LK WITH(NOLOCK) 
			WHERE LK.LOOKUP_TYPE = 'DM_DEMAND_GAP_ANL_CD' AND LK.VALID_YN = 'Y'
		ELSE  IF @PARAM1 = 'VALIDATION_CHECK'  
		-- 의도: SAVE 버튼 눌렀을 때 저장 가능한 데이터 인지 확인 하기 위함. 1 이상이면 저장 가능.
			SELECT COUNT(1) AS CNT
			FROM SCM_ADM_LOOKUP_MASTER_DETAIL LK WITH(NOLOCK)
			WHERE LK.LOOKUP_TYPE = 'DM_DEMAND_GAP_ANL_CD'
			AND LK.VALID_YN = 'Y' AND LK.SEGMENT1 = @PARAM2 AND LK.SEGMENT2 = @PARAM3 AND LK.SEGMENT3 = @PARAM4
		ELSE -- IF @PARAM1 = 'DEFAULT'  
		-- 의도: 처음 팝업창이 Load 될 시 빈값으로 Binding 하기 위함. 그래야 Edit 상태에서도 다른 값이 입력이 안됨.
			SELECT '' AS CODE , '' AS NAME 
	END
	--[PJ2024-50647]자동차사업부 고객 수요 분석 기능 개선(으로 인한 CRGE_ORG_NM,CUST_ENG_NM 2개 컬럼 추가)  
	ELSE IF @CODE = 'SSPM_CRGE_ORG_NM' -- DMF0005
	BEGIN
			SELECT DISTINCT LK.SEGMENT1 AS CODE, LK.SEGMENT2 AS NAME
			FROM SCM_ADM_LOOKUP_MASTER_DETAIL LK WITH(NOLOCK)
			WHERE LK.LOOKUP_TYPE = 'DM_ORG_NAME_DEPT_LIST' 
			--WHERE LK.LOOKUP_TYPE = 'DMF0044_DEPARTMENT_TEAM2_81' -- 에서 변경 2025.01.21
			AND LK.VALID_YN = 'Y';
	END
	--[PJ2024-50647]자동차사업부 고객 수요 분석 기능 개선(으로 인한 CRGE_ORG_NM,CUST_ENG_NM 2개 컬럼 추가)  
	ELSE IF @CODE = 'SSPM_CUST_ENG_NM' -- DMF0005
	BEGIN
			SELECT DISTINCT SEGMENT2 AS CODE, SEGMENT2 AS NAME
			FROM SCM_ADM_LOOKUP_MASTER_DETAIL LK WITH(NOLOCK)
			WHERE LK.LOOKUP_TYPE LIKE 'END_CUSTOMER'
			AND SEGMENT1 = @PARAM1 AND LK.VALID_YN = 'Y'; --@PARAM1은 Div 값
	END
	--[E20250107-000806]_SALE REPORT YYYY CALENDAR에서 나오는 YYYY로 COMBO 구성
	ELSE IF @CODE = 'CALENDAR_YYYY' 
	BEGIN
			SELECT CALENDAR_YYYY AS CODE, CALENDAR_YYYY AS NAME
			FROM SCM_SYS_CALENDAR_M WITH(NOLOCK)
			GROUP BY CALENDAR_YYYY
	END
	--[PJ2025-50017]LGES SCM DM 소형사업부 매출계획 동기화 개선 - @CODE = 'LOOKUP_COMBO'
	ELSE IF @CODE = 'LOOKUP_COMBO' --동적쿼리로 만들어서 원하는 CODE나 NAME을 지정 해서 보여 줄 수 있다.
	BEGIN
	--@PARAM1 -- 가져오려는 LOOKUP_TYPE
	--@PARAM2 -- CODE
	--@PARAM3 -- NAME
	--EXEC UP_FX_GETCOMMONDATALIST_DM 'DM_LOOKUP_VALUE','SP_CELL_PROD_SITE','SEGMENT1','ATTRIBUTE1','',''
		IF(@PARAM2 IN ('SEGMENT1','SEGMENT2','SEGMENT3','SEGMENT4','SEGMENT5','ATTRIBUTE1','ATTRIBUTE2','ATTRIBUTE3','ATTRIBUTE4','ATTRIBUTE5',
		               'ATTRIBUTE6','ATTRIBUTE7','ATTRIBUTE8','ATTRIBUTE9','ATTRIBUTE10','ATTRIBUTE11','ATTRIBUTE12','ATTRIBUTE13','ATTRIBUTE14','ATTRIBUTE15')
		  AND 
		   @PARAM3 IN ('SEGMENT1','SEGMENT2','SEGMENT3','SEGMENT4','SEGMENT5','ATTRIBUTE1','ATTRIBUTE2','ATTRIBUTE3','ATTRIBUTE4','ATTRIBUTE5',
		               'ATTRIBUTE6','ATTRIBUTE7','ATTRIBUTE8','ATTRIBUTE9','ATTRIBUTE10','ATTRIBUTE11','ATTRIBUTE12','ATTRIBUTE13','ATTRIBUTE14','ATTRIBUTE15')
		  )
		BEGIN
			DECLARE @SQL_LOOKUP			NVARCHAR(MAX)
			SET @SQL_LOOKUP = N'
			SELECT DISTINCT ' + @PARAM2 + N' AS CODE, ' + @PARAM3 + N' AS NAME
			FROM SCM_ADM_LOOKUP_MASTER_DETAIL LK WITH(NOLOCK)
			WHERE 1=1 AND LK.LOOKUP_TYPE = ''' + @PARAM1 + '''' + ' AND VALID_YN = ''Y'''
			PRINT @SQL_LOOKUP
			EXEC(@SQL_LOOKUP)
		END
	END
	--[PJ2025-50017]LGES SCM DM 소형사업부 매출계획 동기화 개선 - @CODE = 'FCST_PRICE_EDIT_MEASURE'
