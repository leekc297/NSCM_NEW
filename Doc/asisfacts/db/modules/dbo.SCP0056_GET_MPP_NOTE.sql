



 
CREATE PROCEDURE [dbo].[SCP0056_GET_MPP_NOTE]
    @P_DIVISION_ID			NVARCHAR(30),
	@P_SITE_ID				NVARCHAR(30),
	@P_OPERATION_ID			NVARCHAR(30),
	@P_LINE_ID  			NVARCHAR(30),
	@P_BASIC_CODE			NVARCHAR(30),
	@P_PLAN_DATE            NVARCHAR(20),
	@P_PROD_TYPE            NVARCHAR(100),
	@P_PROGRAM_ID			NVARCHAR(10) = 'SCP0056',
	@P_USER_ID				NVARCHAR(30)
AS
BEGIN

	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;
	SET NOCOUNT ON; 

	SELECT *
	  FROM SCM_DNM_MPP_REASON MPP WITH (NOLOCK)
	 WHERE 1=1
	   AND ((@P_DIVISION_ID IS NULL OR @P_DIVISION_ID ='') OR MPP.DIVISION_ID IN ( SELECT TOKEN FROM DBO.STRING_SPLIT(@P_DIVISION_ID, ',')))
       AND ((@P_SITE_ID IS NULL OR @P_SITE_ID ='') OR MPP.SITE_ID IN ( SELECT TOKEN FROM DBO.STRING_SPLIT(@P_SITE_ID, ',')))
       AND ((@P_OPERATION_ID IS NULL OR @P_OPERATION_ID ='') OR MPP.OPERATION_ID IN ( SELECT TOKEN FROM DBO.STRING_SPLIT(@P_OPERATION_ID, ',')))
       AND ((@P_LINE_ID IS NULL OR @P_LINE_ID ='') OR MPP.LINE_ID IN ( SELECT TOKEN FROM DBO.STRING_SPLIT(@P_LINE_ID, ',')))
	   AND ((@P_BASIC_CODE IS NULL OR @P_BASIC_CODE ='') OR MPP.BASIC_CODE IN ( SELECT TOKEN FROM DBO.STRING_SPLIT(@P_BASIC_CODE, ',')))
	   AND ((@P_PLAN_DATE IS NULL OR @P_PLAN_DATE ='') OR MPP.PLAN_DATE  = @P_PLAN_DATE)
	   AND ((@P_PROD_TYPE IS NULL OR @P_PROD_TYPE ='') OR MPP.PROD_TYPE IN ( SELECT TOKEN FROM DBO.STRING_SPLIT(@P_PROD_TYPE, ',')))
	   AND VALID = 'Y'
END
