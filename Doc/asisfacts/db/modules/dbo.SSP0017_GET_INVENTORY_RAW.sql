 */
CREATE PROCEDURE [dbo].[SSP0017_GET_INVENTORY_RAW]
	@p_division_id			NVARCHAR(MAX)
	,@p_plant_site			NVARCHAR(MAX)
	,@p_item_id				NVARCHAR(MAX)
	,@p_inventory_type		NVARCHAR(50)
	,@p_plan_start_yyyymmdd NVARCHAR(8)
	,@p_user_id				NVARCHAR(MAX)
	,@p_program_id			NVARCHAR(MAX) = 'SSP0017' 
	,@p_sheet_name			NVARCHAR(MAX) = 'Inventory Raw(Small)'
AS  
  
BEGIN
	SET NOCOUNT ON; 
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;	
	/*
	SELECT
		T1.DIVISION_ID,				T1.PLANT_SITE,				T1.INVENTORY_TYPE,			T1.MODEL,
		T1.NICK_NAME,				T1.LOT_ID,					T1.LOT,						T1.PRODUCTION_DATE,			
		T1.BUILDING,				T1.PALLET_ID,
		T1.VALTAGE,					T1.CAPACITY,				T1.SOC,						T1.INVENTORY_STATUS,
		T1.[ROUTE],					T1.ROUTE_NAME,				T1.ROUTE_TYPE,				T1.OPERATION,
		T1.OPERATION_NAME,			T1.LINE,					T1.REMAIN_LEAD_TIME,		T1.CURRENT_OP_START_DATE,
		T1.EXP_FORMATION_END_DATE,	T1.HOLD_YN,					T1.SPECIAL_YN,				T1.STOCK_QTY,
		T1.HOLD_QTY,				T1.AVAILABLE_QTY,			T1.ALLOCATION_QTY,			T1.CUSTOMER
	FROM
	(*/
		SELECT 
			T0.DIVISION_ID,							T3.SITE_DESCRIPTION AS PLANT_SITE,					T0.INV_TYPE AS INVENTORY_TYPE,				T0.ITEM_ID AS MODEL,
			(SELECT TOP 1 isnull(NULLIF(NICK_NAME,''),'-') FROM DBO.SCM_MST_ITEM_SN x WITH(NOLOCK) WHERE 1=1 AND x.ITEM_ID = T0.ITEM_ID) AS NICK_NAME,
			T0.LOT_ID,				SUBSTRING(T0.LOT_ID,4,4) AS LOT,				
			CONVERT(NVARCHAR(10),dbo.fn_char_to_date(T0.PROD_DATE),121) AS PRODUCTION_DATE,		
			CASE T0.INV_TYPE WHEN 'F' THEN CONCAT(T1.FACTORY_ID ,' ',T1.FACTORY_NAME)
							 WHEN 'O' THEN CONCAT(T2.STORAGE_ID ,' ',T2.STORAGE_DESCRIPTION)
							 ELSE ''
			END AS BUILDING,
			T0.PALLET_ID,							T0.CAPACITY_GRADE AS VALTAGE,					T0.GRADE AS CAPACITY,						T0.SOC,
			T0.STOCK_STATUS AS INVENTORY_STATUS,	T0.ROUTE_ID AS [ROUTE],							'' AS ROUTE_NAME,							'' AS ROUTE_TYPE,
			T0.OPERATION_ID AS OPERATION,			'' AS OPERATION_NAME,							T0.LINE_ID AS LINE,							T0.REMAIN_LEAD_TIME AS REMAIN_LEAD_TIME,
			CONVERT(NVARCHAR(10),dbo.fn_char_to_date(T0.OP_START_TIME),121) AS CURRENT_OP_START_DATE,
			CONVERT(NVARCHAR(10),dbo.fn_char_to_date(T0.EXP_FORMATION_END_DATE),121) AS EXP_FORMATION_END_DATE,
			T0.HOLD_YN,								T0.SPECIAL_YN,									T0.STOCK_QTY,								T0.AVAILABLE_QTY,	
			T0.HOLD_QTY,							T0.LONG_QTY,									T0.EXPIRATION_QTY,							T0.CUSTOMER_CODE AS CUSTOMER--,				MAX(T0.SEQ) AS MAX_SEQ
		FROM SSP_ANL_INVENTORY_RAW T0 WITH(NOLOCK)
		LEFT JOIN SCM_MST_FACTORY_SN T1 WITH(NOLOCK)
			ON T0.DIVISION_ID = T1.DIVISION_ID
			AND T0.PLANT_ID = T1.PLANT_ID
			AND T0.FACTORY_ID = T1.FACTORY_ID
		LEFT JOIN SCM_MST_SLOC T2 WITH(NOLOCK)
			ON T0.DIVISION_ID = T2.DIVISION_ID
			AND T0.PLANT_ID = T2.PLANT_ID
			AND T0.STORAGE_ID = T2.STORAGE_ID
		INNER JOIN SCM_MST_SITE T3 WITH(NOLOCK)
			ON T0.DIVISION_ID = T3.DIVISION_ID
			AND T0.SCM_SITE_ID = T3.SCM_SITE_ID
			AND T3.OSP_YN = 'N'
		WHERE 1 = 1
		  AND T0.DIVISION_ID = @p_division_id
		  AND ((@p_plant_site IS NULL OR @p_plant_site = '') OR T0.SCM_SITE_ID IN (SELECT TOKEN FROM dbo.UF_FX_String_Split (@p_plant_site,',')) )
		  AND ((@p_item_id IS NULL OR @p_item_id = '') OR T0.ITEM_ID IN (SELECT TOKEN FROM dbo.UF_FX_String_Split (@p_item_id,',')) )
		  AND ((@p_inventory_type IS NULL OR @p_inventory_type = '') OR T0.INV_TYPE IN (SELECT TOKEN FROM dbo.UF_FX_String_Split (@p_inventory_type,',')) )
		  AND ((@p_plan_start_yyyymmdd IS NULL OR @p_plan_start_yyyymmdd = '') OR T0.PLAN_START_YYYYMMDD IN (SELECT TOKEN FROM dbo.UF_FX_String_Split (@p_plan_start_yyyymmdd,',')) )
	/*
		GROUP BY
			T0.DIVISION_ID, T3.PLANT_NAME, T0.INV_TYPE, T0.ITEM_ID, T0.LOT_ID, T0.PROD_DATE, T1.FACTORY_ID, T1.FACTORY_NAME, T2.STORAGE_ID, T2.STORAGE_DESCRIPTION,
			T0.PALLET_ID, T0.CAPACITY_GRADE, T0.GRADE, T0.SOC, T0.STOCK_STATUS, T0.ROUTE_ID, T0.OPERATION_ID, T0.LINE_ID, T0.REMAIN_LEAD_TIME, T0.OP_START_TIME, 
			T0.EXP_FORMATION_END_DATE, T0.HOLD_YN, T0.SPECIAL_YN, T0.STOCK_QTY, T0.HOLD_QTY, T0.AVAILABLE_QTY, T0.ALLOCATION_QTY, T0.CUSTOMER_CODE
			--ROUTE_NAME, ROUTE_TYPE, OPERATION_NAME
	*/
		--ORDER BY T0.INV_TYPE, T0.ITEM_ID, T0.PALLET_ID, T0.PROD_DATE
	/*
	) AS T1 
	ORDER BY T1.INVENTORY_TYPE, T1.MODEL, T1.PALLET_ID, T1.PRODUCTION_DATE
	*/
END
