CREATE PROCEDURE [dbo].[SSP0022_GET_REQUEST_DETAIL_EXCEL_DOWN]
	@P_DIVISION_ID			VARCHAR(10)
	,@P_COMPANY_ID			NVARCHAR(100)
	,@P_PLAN_START_YYYYMMDD	NVARCHAR(8)
	,@P_FROM_YYYYMMDD		NVARCHAR(8)
	,@P_TO_YYYYMMDD		NVARCHAR(8)
	,@P_PLANT_ID			NVARCHAR(MAX)
	,@P_CELL_TYPE			NVARCHAR(MAX)
	,@P_LOT_ID			NVARCHAR(MAX)
	,@P_ITEM_ID			NVARCHAR(MAX)
	,@P_MODEL_ID			NVARCHAR(MAX)
	,@P_NICK_NAME			NVARCHAR(MAX)
	,@P_USER_ID			NVARCHAR(MAX)
	,@P_REQUESTOR_ID		NVARCHAR(MAX)
	,@P_PROGRAM_ID			NVARCHAR(MAX) = 'SSP0022' 
	,@P_SHEET_NAME			NVARCHAR(MAX) = 'Shipment Request Detail Excel'
	,@P_REAL_FLAG			CHAR(1)
	,@P_NON_CHK			CHAR(1)
	,@P_MY_MODEL_CHK		CHAR(1)
	,@P_DELEGATE_CHK		CHAR(1)
	,@P_PART_LEADER_CHK		CHAR(1)
	,@P_TEAM_LEADER_CHK		CHAR(1)
AS
BEGIN
	SET NOCOUNT ON; 
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;
	
	SELECT * FROM (
	SELECT 
        A.TO_DIVISION_ID		AS DIVISION_ID
	 , A.TO_COMPANY_ID		AS COMPANY_ID
      , A.FROM_SITE			AS FROM_SITE
      , A.TO_SITE			AS TO_SITE
      , A.ITEM_ID             AS ITEM_ID
	 , A.YYYYMMDD            AS YYYYMMDD
	 , ISNULL(B.QTY, 0)      AS Qty
	 , C.TRANSPORT_MODE      AS TRANSPORT_MODE
	 --* 2020/09/21	 KIMYONGHO      SSP INCOTERMS 변경 작업
	 --, C.INCOTERMS           AS INCOTERMS
	 , C.SSP_INCOTERMS           AS INCOTERMS
	 , CASE WHEN ISNULL(I.ELECTRODE_POST_OPER_LT,0) >  ISNULL(TD.SHIP_FROZEN,0)	
				THEN  															
				CASE WHEN CONVERT(CHAR(10), DATEADD(DD, ISNULL(DATEDIFF(DD, @P_PLAN_START_YYYYMMDD, [dbo].[FN_GET_SSP_ETA_DATE](A.FROM_DIVISION_ID, B.BOD_ID, CONVERT(CHAR(8),DATEADD(DD,ISNULL(I.ELECTRODE_POST_OPER_LT,0) + 0, @P_PLAN_START_YYYYMMDD),112))) ,0) , @P_PLAN_START_YYYYMMDD), 23)	 <=  CONVERT(VARCHAR(10),   CONVERT(DATETIME, A.YYYYMMDD,112), 23) THEN 'Y' ELSE 'N' END
				ELSE																																																														
				CASE WHEN CONVERT(CHAR(10), DATEADD(DD, ISNULL(DATEDIFF(DD, @P_PLAN_START_YYYYMMDD, [dbo].[FN_GET_SSP_ETA_DATE](A.FROM_DIVISION_ID, B.BOD_ID, CONVERT(CHAR(8),DATEADD(DD,ISNULL(TD.SHIP_FROZEN,0) + 0, @P_PLAN_START_YYYYMMDD),112))) ,0)  , @P_PLAN_START_YYYYMMDD), 23) 	 <=  CONVERT(VARCHAR(10),   CONVERT(DATETIME, A.YYYYMMDD,112), 23) THEN 'Y' ELSE 'N' END
				END AS EDIT_FLAG	
	FROM   (
			SELECT B.FROM_COMPANY_ID
				 , B.FROM_DIVISION_ID
				 , B.FROM_PLANT_ID
				 , B.FROM_SITE
				 , B.TO_COMPANY_ID
				 , B.TO_DIVISION_ID
				 , B.TO_PLANT_ID
				 , B.TO_SITE
				 , B.MODEL_ID
				 , B.ITEM_ID
				 , A.YYYYMMDD		
			FROM   SSP_MST_SHIP_CALENDAR   A WITH(NOLOCK)
				   JOIN SSP_ANL_SHIP_REQ_EE B WITH(NOLOCK)
				   ON   B.TO_COMPANY_ID  = @P_COMPANY_ID
				   AND  B.TO_DIVISION_ID = @P_DIVISION_ID
				   --AND  B.TO_PLANT_ID   = @P_PLANT_ID 
				  -- AND  B.TO_PLANT_ID   LIKE '%' + @P_PLANT_ID + '%'
				   AND ((@P_PLANT_ID   IS NULL OR @P_PLANT_ID ='' )	    OR B.TO_PLANT_ID IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_PLANT_ID, ','))) 
				   AND  B.TO_SITE        LIKE '%'
				   AND  B.MODEL_ID       LIKE '%'
				   AND ((@P_ITEM_ID   IS NULL OR @P_ITEM_ID ='' )	    OR B.ITEM_ID IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_ITEM_ID, ','))) 
				   AND  B.TO_COMPANY_ID  = A.COMPANY_ID
				   AND  B.TO_DIVISION_ID = A.DIVISION_ID
			WHERE  1 = 1
			AND    A.DIVISION_ID = @P_DIVISION_ID
			AND    A.COMPANY_ID  = @P_COMPANY_ID
			AND    A.YYYYMMDD   >= @P_FROM_YYYYMMDD
			AND    A.YYYYMMDD   < = @P_TO_YYYYMMDD
			GROUP BY B.FROM_COMPANY_ID
				 , B.FROM_DIVISION_ID
				 , B.FROM_PLANT_ID
				 , B.FROM_SITE
				 , B.TO_COMPANY_ID
				 , B.TO_DIVISION_ID
				 , B.TO_PLANT_ID
				 , B.TO_SITE
				 , B.MODEL_ID
				 , B.ITEM_ID
				 , A.YYYYMMDD
		   ) A
		   LEFT OUTER JOIN SSP_ANL_SHIP_REQ_EE B WITH(NOLOCK)
		   ON   B.TO_COMPANY_ID  = @P_COMPANY_ID
		   AND  B.TO_DIVISION_ID = @P_DIVISION_ID
		   AND  B.TO_PLANT_ID   = @P_PLANT_ID
		  -- AND  B.TO_PLANT_ID   LIKE '%' + @P_PLANT_ID + '%'
		   AND ((@P_PLANT_ID   IS NULL OR @P_PLANT_ID ='' )	    OR B.TO_PLANT_ID IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_PLANT_ID, ','))) 
		   AND  B.TO_SITE        LIKE '%'
		   AND  B.MODEL_ID       LIKE '%'
		   AND ((@P_ITEM_ID   IS NULL OR @P_ITEM_ID ='' )	    OR B.ITEM_ID IN (SELECT TOKEN FROM DBO.STRING_SPLIT(@P_ITEM_ID, ','))) 
		   AND  A.FROM_COMPANY_ID  = B.FROM_COMPANY_ID
		   AND  A.FROM_DIVISION_ID = B.FROM_DIVISION_ID
		   AND  A.FROM_PLANT_ID    = B.FROM_PLANT_ID
		   AND  A.FROM_SITE        = B.FROM_SITE
		   AND  A.TO_COMPANY_ID    = B.TO_COMPANY_ID
		   AND  A.TO_DIVISION_ID   = B.TO_DIVISION_ID
		   AND  A.TO_PLANT_ID      = B.TO_PLANT_ID
		   AND  A.TO_SITE          = B.TO_SITE
		   AND  A.MODEL_ID         = B.MODEL_ID
		   AND  A.ITEM_ID          = B.ITEM_ID
		   AND  A.YYYYMMDD         = B.ETA_DATE
		   --LEFT OUTER JOIN SCP_MST_BOD_N_V C  WITH(NOLOCK)
		   LEFT OUTER JOIN SCP_MST_BOD_N_V C  WITH(NOLOCK)
		   ON   C.DIVISION_ID = B.FROM_DIVISION_ID
		   AND  C.BOD_ID      = B.BOD_ID
		   AND  C.FROM_SITE   = B.FROM_SITE
		   AND  C.TO_SITE     = B.TO_SITE
		   LEFT OUTER JOIN SSP_MST_SITE_ITEM_EE_V I WITH(NOLOCK)	
		   ON A.FROM_DIVISION_ID = I.DIVISION_ID			
		   AND A.FROM_SITE = I.SCM_SITE_ID				
		   AND A.ITEM_ID = I.ITEM_ID
		   LEFT OUTER JOIN SCM_MST_SITE TD WITH(NOLOCK)	
		   ON A.FROM_DIVISION_ID	= TD.DIVISION_ID	
		   AND C.FROM_SITE	= TD.SCM_SITE_ID		
	WHERE  1 = 1
	) T
	WHERE T.EDIT_FLAG <> 'N'
	ORDER BY T.ITEM_ID, T.YYYYMMDD
END

