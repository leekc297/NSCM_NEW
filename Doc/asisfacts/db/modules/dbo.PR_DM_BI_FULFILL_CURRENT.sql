CREATE PROC [dbo].[PR_DM_BI_FULFILL_CURRENT]
	@P_DIVISION_ID NVARCHAR(30)
	, @P_YYYYMMDD	NVARCHAR(8)
AS
BEGIN

 	SET NOCOUNT ON; 
    SET TRANSACTION ISOLATION LEVEL READ COMMITTED;
    SET XACT_ABORT ON;

	-- LOG 용 변수 설정
    DECLARE @V_PROGRAM_NAME		NVARCHAR(150) = 'PR_DM_BI_FULFILL_CURRENT';
    DECLARE @V_LOG_TYPE			NVARCHAR(30); -- START/END/ERROR/...
    DECLARE @N_LOG_COUNT		INTEGER = 0;
    DECLARE @V_LOG_MESSAGE		NVARCHAR(1000);
    DECLARE @V_DESCRIPTION		NVARCHAR(500);
    DECLARE @D_EVENT_DATE		DATETIME;
    DECLARE @N_DELETE_COUNT		INTEGER = 0;
    DECLARE @N_INSERT_COUNT     INTEGER = 0;
	DECLARE @V_CREATED_BY		NVARCHAR(150)	= 'SYS_BI_CURRENT';

	--20231220 [SM] 모니터링 당시 정상적으로 실행되지 않는 부분이 생겨 TEMP성 테이블로 데이터를 받아서, 넣는 부분으로 수정하면서 만든 테이블들은 DROP 하는 구조 추가
	IF OBJECT_ID (N'tempdb..#T_PLAN_INFO', N'U') IS NOT NULL 
	DROP TABLE #T_PLAN_INFO	;
	IF OBJECT_ID (N'tempdb..#TEMP_DM_DNM_CURRENT', N'U') IS NOT NULL 
	DROP TABLE #TEMP_DM_DNM_CURRENT	;   
	--[E20240904-001037]_TEMP 테이블을 추가한다.
	IF OBJECT_ID (N'tempdb..#TEMP_DM_DNM_CURRENT_BEFORE', N'U') IS NOT NULL 
	DROP TABLE #TEMP_DM_DNM_CURRENT_BEFORE	;   
	
	--[E20241028-000049]_TEMP 테이블을 추가한다. START
	IF OBJECT_ID (N'tempdb..#TEMP_W_CELL_CF_DATA ', N'U') IS NOT NULL 
	DROP TABLE #TEMP_W_CELL_CF_DATA 	;   
	IF OBJECT_ID (N'tempdb..#TEMP_DM_DNM_CURRENT_BEFORE', N'U') IS NOT NULL 
	DROP TABLE #TEMP_CELL_CF	;   
	IF OBJECT_ID (N'tempdb..#SCM_MST_SITE_ITEM_CELL', N'U') IS NOT NULL 
	DROP TABLE #SCM_MST_SITE_ITEM_CELL	;   
	--[E20241028-000049]_TEMP 테이블을 추가한다. END

	-- 시작 LOG
	SET @V_LOG_TYPE = 'START';
	SET @V_LOG_MESSAGE = '########## START OF PROCEDURE ##########';
	SET @V_DESCRIPTION = '';
	SET @D_EVENT_DATE = SYSDATETIME();
	EXEC  PR_DM_SYS_LOG_BATCH @V_PROGRAM_NAME, @V_LOG_TYPE, @N_LOG_COUNT, @V_LOG_MESSAGE, @V_DESCRIPTION, @D_EVENT_DATE, @V_CREATED_BY;
	   	
	BEGIN TRY
	
		--20231220 [SM] TEMP TABLE 생성 
		CREATE TABLE #T_PLAN_INFO
		(
			DIVISION_ID			NVARCHAR(30)
		  , CUTOFF_YYYYMMDD		NVARCHAR(8)  
		  , START_YYYYWW		NVARCHAR(6)
		)

		INSERT INTO #T_PLAN_INFO ( DIVISION_ID, CUTOFF_YYYYMMDD, START_YYYYWW )
		SELECT @P_DIVISION_ID
			, A.BASIS_YYYYMMDD AS CUTOFF_YYYYMMDD
			, CONVERT(NVARCHAR(4), DATEADD(YEAR, -1, A.BASIS_YYYYMMDD), 112) + '01'
		FROM (
			SELECT MAX(BASIS_YYYYMMDD) AS BASIS_YYYYMMDD
			FROM SCM_SYS_CALENDAR_M WITH (NOLOCK) 
			WHERE BASIS_DATE <= @P_YYYYMMDD
				AND DAYOFWEEK = 'TUE'
			) A
		JOIN SCM_SYS_CALENDAR_M B ON A.BASIS_YYYYMMDD = B.BASIS_YYYYMMDD
	
		-- 기존 데이터는 지우고 시작한다.
		DELETE 
		FROM DM_DNM_FULFILL
		WHERE DIVISION_ID = @P_DIVISION_ID 
			AND DATA_TYPE = 'CURRENT'
		;
		WITH PLAN_DATE_INFO AS 
		(
			SELECT	'9999-12-31' AS PLAN_ST_DATE, A.MONTH_NAME, A.ISO_YYYYWW, CONCAT(CONCAT(A.MONTH_NAME,'-'), SUBSTRING(A.BASIS_START_DATE,7,2)) AS PARTIAL_START_DATE, B.BASIS_DATE AS TARGET_ST_DATE, CONCAT(D.KPI_MONTH,'-01') AS KPI_MONTH
			FROM	DBO.SCM_SYS_CALENDAR_M A WITH (NOLOCK) 
					LEFT OUTER JOIN (
									SELECT	ISO_YYYYWW, CONVERT(CHAR(10), BASIS_DATE, 23) AS BASIS_DATE
									FROM	DBO.SCM_SYS_CALENDAR_M WITH (NOLOCK) 
									WHERE	1=1
									AND		DAYOFWEEK = 'MON'				
									) B ON A.ISO_YYYYWW = B.ISO_YYYYWW
					LEFT OUTER JOIN (
									SELECT	ISO_YYYYWW, CALENDAR_YYYY+'-'+CALENDAR_MONTH AS KPI_MONTH
									FROM	DBO.SCM_SYS_CALENDAR_M WITH (NOLOCK) 
									WHERE	1=1
									AND		DAYOFWEEK = 'THU'					
									) D ON A.ISO_YYYYWW = D.ISO_YYYYWW
					, #T_PLAN_INFO C
			WHERE	1=1
			AND		A.END_FLAG = 'Y'
		),
		END_CUSTOMER_SEMI AS -- 59015
		(
			-- 고객사 Logic : 1) SITE, PROJECT 둘다 매핑되는 고객사 셋팅 2) 1에서 NULL 나오는 CASE는 SITE만 있으면 매핑 3) 그래도 매핑 안되는 case는 'NULL_Site' 정보 제공
			SELECT	DISTINCT 
					A.DIVISION_ID, 
					A.PROJECT_CODE, 
					A.SCM_SITE_ID, 
					B.COUNTRY,
					B.CITY,
					A.ITEM_ID, 
					A.CELL_PER_CAR,
					A.CELL_PER_MODULE,
					CASE WHEN A.CELL_PER_MODULE  <> 0 THEN A.CELL_PER_CAR / A.CELL_PER_MODULE ELSE 0 END AS MODULE_PER_CAR,
					-- 40에서 APPLICATION으로 CATEGORY 구분함(EX> 노트북 등..)
					A.CUST_GROUP, 
					A.CUST_GROUP_DTL, 
					A.APPLICATION,
					A.CELL_MODEL, 
					A.PRODUCT_GROUP,

					--[PJ2024-50461] Team Mapping------------------------------------
					/*CASE WHEN A.DIVISION_ID = '40' THEN D.DEPT_NAME_KO
							ELSE C.DEPT_NAME_KO END AS DEPT_NAME_KO,*/
					D.DEPT_NAME_KO,
					--[PJ2024-50461] Team Mapping------------------------------------

					A.VMI_YN,
					-- 40은 PROJECT_CODE가 END_CUSTOMER임.
					CASE WHEN A.DIVISION_ID = '40' THEN A.PROJECT_CODE 
							ELSE (CASE WHEN A.END_CUSTOMER IS NULL THEN B.END_CUSTOMER ELSE A.END_CUSTOMER END) END AS END_CUSTOMER,
					---CASE WHEN A.END_CUSTOMER IS NULL THEN B.END_CUSTOMER ELSE A.END_CUSTOMER END AS END_CUSTOMER
					SOLDTO_CUSTOMER
			FROM	(
					SELECT	DISTINCT A.DIVISION_ID, 
							A.PROJECT_CODE, 
							A.SCM_SITE_ID, 
							A.ITEM_ID, 
							B.END_CUSTOMER, 
							A.CELL_PER_CAR, 
							A.CELL_PER_MODULE, 
							A.CUST_GROUP, 
							A.CUST_GROUP_DTL, 
							A.APPLICATION, 
							A.ATTRIBUTE5 AS CELL_MODEL, 
							A.REPORT_GROUP3 AS PRODUCT_GROUP,
							B.VMI_YN,
							-- 81, 82의 경우 DEPT_ID는 PROJECT 정보를(SCM_MST_SITE에서) 참조하나, 40인 경우에는 OWNER의 부서정보를 참조함(공용화모델 CASE로 중복 발생 때문)
							B.DEPT_ID AS DEPT_ID,	-- 81, 82
						(	SELECT SU.DEPT_ID  
							FROM SCM_MST_SSO_USER_INFO SU WITH (NOLOCK)
							WHERE SU.USER_ID = (SELECT top 1 token FROM [dbo].[String_Split](A.owner, ',')) ) DEPT_ID_SMALL  -- 40
					FROM	SCM_MST_SITE_ITEM A WITH (NOLOCK)  , SCM_MST_SITE B WITH (NOLOCK) 
					WHERE	1=1
					AND		A.DIVISION_ID = B.DIVISION_ID
					AND		A.SCM_SITE_ID = B.SCM_SITE_ID
					-- 주석 처리한 이유 : 과거 계획/실적을 조회할 수 있으므로... (실적은 Current로 VALID 관계 없이 모두 집계 / 일 Batch)				
					--AND		A.VALID_YN = 'Y'
					--AND		B.VALID_YN = 'Y'
					AND		A.DIVISION_ID = @P_DIVISION_ID 
					) A 
					LEFT OUTER JOIN SCM_MST_SSO_DEPT_INFO C WITH (NOLOCK)  ON A.DEPT_ID = C.DEPT_ID
					LEFT OUTER JOIN SCM_MST_SSO_DEPT_INFO D WITH (NOLOCK)  ON A.DEPT_ID_SMALL = D.DEPT_ID
					, SCM_MST_SITE B WITH (NOLOCK) 
			WHERE	1=1
			AND		A.SCM_SITE_ID = B.SCM_SITE_ID
			AND		A.DIVISION_ID = B.DIVISION_ID
			--AND		B.VALID_YN = 'Y'
		),
		END_CUSTOMER as
		(
		SELECT	A.*,
				SUBSTRING(DEPT_NAME_KO, CHARINDEX('.', DEPT_NAME_KO) + 1, (CHARINDEX('.', SUBSTRING(DEPT_NAME_KO, CHARINDEX('.', DEPT_NAME_KO) + 1, LEN(DEPT_NAME_KO)))) ) AS DEPARTMENT,
				SUBSTRING(SUBSTRING(DEPT_NAME_KO, CHARINDEX('.', DEPT_NAME_KO) + 1, LEN(DEPT_NAME_KO))
						, CHARINDEX('.', SUBSTRING(DEPT_NAME_KO
												 , CHARINDEX('.', DEPT_NAME_KO) + 1
												 , LEN(SUBSTRING(DEPT_NAME_KO, CHARINDEX('.', DEPT_NAME_KO) + 1, LEN(DEPT_NAME_KO))))) + 1
						, LEN(DEPT_NAME_KO)) AS TEAM_DTL
		FROM	END_CUSTOMER_SEMI A 
		),			
		DM_MST_ITEM_SINGLE AS 
		(			
			SELECT	T1.DIVISION_ID,
				T1.ITEM_ID, 
				MAX(T1.ITEM_NAME)					AS ITEM_NAME,				--해당 컬럼이 NULL인 경우가 잇으므로 하나로 통일
				MAX(T1.ITEM_CLASS)					AS ITEM_CLASS,				--해당 컬럼이 NULL인 경우가 잇으므로 하나로 통일
				MAX(T1.ITEM_CLASS_NAME)					AS ITEM_CLASS_NAME,		--해당 컬럼이 NULL인 경우가 잇으므로 하나로 통일
				MAX(T1.NICK_NAME)						AS NICK_NAME,			--닉네임이 NULL인 경우가 있으므로 하나로 통일
				case  min( case when T1.item_type = 'P' then 1					--타입이 사이트와 사업부, 법인에 따라 다양하게 존재 하므로 하나로 통일
								when T1.item_type = 'H' then 2					--또한 가장 완성된 상태의 자재 타입을 판매한다고 가정, 해당 자재타입을 사용함
								when T1.item_type = 'Q' then 3
								else 4 end )  
												when 1 then 'P' 
												when 2 then 'H'
												when 3 then 'Q'
												else 'R' end	AS ITEM_TYPE,
				MAX(T1.MATERIAL_CLASS_NAME				)		AS MATERIAL_CLASS_NAME,
				MAX(T1.ITEM_UOM							)		AS ITEM_UOM,
				MAX(T1.SPEC								)		AS SPEC,
				MAX(T1.MDM_PROJECT_NAME					)		AS MDM_PROJECT_NAME,
				MAX(T1.MIN_CAPACITY						)		AS MIN_CAPACITY,
				MAX(T2.FORECAST_INFO_BIZ_TYPE			)		AS FORECAST_INFO_BIZ_TYPE,
				MAX(T2.FORECAST_INFO_PRODUCT_GROUP		)		AS FORECAST_INFO_PRODUCT_GROUP,
				MAX(T2.FORECAST_INFO_CELL_MODEL			)		AS FORECAST_INFO_CELL_MODEL,
				MAX(T2.FORECAST_INFO_CELL_PACK_COUNT	)		AS FORECAST_INFO_CELL_PACK_COUNT,
				MAX(T2.FORECAST_INFO_SPEC				)		AS FORECAST_INFO_SPEC,
				MAX(T2.FORECAST_INFOR_VERSION			)		AS FORECAST_INFOR_VERSION,
				MAX(T1.ACTIVE_FLAG						)		AS ACTIVE_FLAG,  -- 20180720 ADD 'Y'대상중 1건 추출
				MAX(T2.CELL_TYPE						)		AS CELL_TYPE,  -- 20180911 ADD cell_type
				MAX(T1.ENERGE							)  	    AS ENERGE,			-- 20200116 khsong ADD ENERGE
				MAX(T1.CELL_QUANTITY					)	    AS CELL_QUANTITY,	-- 20200116 khsong ADD CELL_QUANTITY
				MAX(T1.SCP_EXTRA_SPEC)						  AS SCP_EXTRA_SPEC		-- [20210428 SJHAN / CSR ID:C20210323-000420]
			FROM SCM_MST_ITEM_SN T1 WITH(NOLOCK)					
			INNER JOIN ( SELECT DIVISION_ID, LEFT(ITEM_ID, 12) AS ITEM_ID
							, MAX(FORECAST_INFO_BIZ_TYPE) AS FORECAST_INFO_BIZ_TYPE
							, MAX(FORECAST_INFO_PRODUCT_GROUP) AS FORECAST_INFO_PRODUCT_GROUP
							, MAX(FORECAST_INFO_CELL_MODEL) AS FORECAST_INFO_CELL_MODEL
							, MAX(FORECAST_INFO_CELL_PACK_COUNT) AS FORECAST_INFO_CELL_PACK_COUNT
							, MAX(FORECAST_INFO_SPEC) AS FORECAST_INFO_SPEC
							, MAX(FORECAST_INFOR_VERSION) AS FORECAST_INFOR_VERSION
							, MAX(CELL_TYPE) AS CELL_TYPE
						FROM  SCM_MST_ITEM_SN T2 WITH(NOLOCK) 
						GROUP BY DIVISION_ID, LEFT(ITEM_ID, 12)
					) T2 ON T1.DIVISION_ID = T2.DIVISION_ID
				AND SUBSTRING(T1.ITEM_ID,1,12) = T2.ITEM_ID
			where 1=1
			AND		T1.DIVISION_ID = @P_DIVISION_ID
			AND		T1.ACTIVE_FLAG = 'Y'
			--WHERE ACTIVE_FLAG = 'Y'  -- 20180720 ADD 'Y'대상만
			--LGCE_FPDEV_TR.DBO.SCM_ITEM_M T1
			group by T1.DIVISION_ID, T1.ITEM_ID
		),
		MODEL_TYPE AS 
		(
			-- 자동차 MODEL_TYPE LIST
			SELECT	C.*,
					CASE WHEN (C.FORECAST_INFO_BIZ_TYPE IS NULL AND CHARINDEX('Cell', C.ITEM_CLASS_NAME) > 0) THEN 'CELL'
							WHEN (C.FORECAST_INFO_BIZ_TYPE IS NULL AND CHARINDEX('Module', C.ITEM_CLASS_NAME) > 0) THEN 'MODULE'
							WHEN (C.FORECAST_INFO_BIZ_TYPE IS NULL AND  CHARINDEX('Pack'  , C.ITEM_CLASS_NAME) > 0) THEN 'PACK'
					ELSE C.FORECAST_INFO_BIZ_TYPE END AS MODEL_TYPE,
					CASE WHEN (C.FORECAST_INFO_BIZ_TYPE IS NULL AND CHARINDEX('Cell', C.ITEM_CLASS_NAME) > 0) THEN 'CELL'
							WHEN (C.FORECAST_INFO_BIZ_TYPE IS NULL AND CHARINDEX('Module', C.ITEM_CLASS_NAME) > 0) THEN 'MODULE'
							WHEN (C.FORECAST_INFO_BIZ_TYPE IS NULL AND  CHARINDEX('Pack'  , C.ITEM_CLASS_NAME) > 0) THEN 'PACK'
					ELSE C.FORECAST_INFO_BIZ_TYPE END AS ORI_MODEL_TYPE
			FROM	DM_MST_ITEM_SINGLE C WITH (NOLOCK) 
			WHERE	1=1
			AND		DIVISION_ID LIKE '81%'
			AND		ACTIVE_FLAG = 'Y'	
			AND		DIVISION_ID = @P_DIVISION_ID 
			UNION ALL
			-- ESS MODEL_TYPE LIST
			SELECT	C.*, 
					CASE WHEN (C.FORECAST_INFO_BIZ_TYPE IS NULL AND CHARINDEX('Cell', C.ITEM_CLASS_NAME) > 0) THEN 'CELL'
								WHEN (C.FORECAST_INFO_BIZ_TYPE IS NULL AND CHARINDEX('Module', C.ITEM_CLASS_NAME) > 0) THEN 'MODULE'
								WHEN (C.FORECAST_INFO_BIZ_TYPE IS NULL AND  CHARINDEX('House'  , C.ITEM_CLASS_NAME) > 0) THEN 'PACK'
								WHEN (C.FORECAST_INFO_BIZ_TYPE IS NULL AND  CHARINDEX('Rack'  , C.ITEM_CLASS_NAME) > 0) THEN 'PACK'
						ELSE C.FORECAST_INFO_BIZ_TYPE END AS MODEL_TYPE,
					CASE WHEN (C.FORECAST_INFO_BIZ_TYPE IS NULL AND CHARINDEX('Cell', C.ITEM_CLASS_NAME) > 0) THEN 'CELL'
								WHEN (C.FORECAST_INFO_BIZ_TYPE IS NULL AND CHARINDEX('Module', C.ITEM_CLASS_NAME) > 0) THEN 'MODULE'
								WHEN (C.FORECAST_INFO_BIZ_TYPE IS NULL AND  CHARINDEX('House'  , C.ITEM_CLASS_NAME) > 0) THEN 'HOUSE'
								WHEN (C.FORECAST_INFO_BIZ_TYPE IS NULL AND  CHARINDEX('Rack'  , C.ITEM_CLASS_NAME) > 0) THEN 'RACK'
						ELSE C.FORECAST_INFO_BIZ_TYPE END AS ORI_MODEL_TYPE
			FROM	DM_MST_ITEM_SINGLE C WITH (NOLOCK) 
			WHERE	1=1
			AND		DIVISION_ID = '82'
			AND		ACTIVE_FLAG = 'Y'
			AND		DIVISION_ID = @P_DIVISION_ID 
			UNION ALL
			-- 소형 MODEL_TYPE LIST
			SELECT	C.*, 
					CASE WHEN (C.FORECAST_INFO_BIZ_TYPE IS NULL AND CHARINDEX('Cell', C.ITEM_CLASS_NAME) > 0) THEN 'CELL'
							WHEN (C.FORECAST_INFO_BIZ_TYPE IS NULL AND CHARINDEX('Module', C.ITEM_CLASS_NAME) > 0) THEN 'MODULE'
							WHEN (C.FORECAST_INFO_BIZ_TYPE IS NULL AND  CHARINDEX('Pack'  , C.ITEM_CLASS_NAME) > 0) THEN 'PACK'
					ELSE C.FORECAST_INFO_BIZ_TYPE END AS MODEL_TYPE, 
					CASE WHEN (C.FORECAST_INFO_BIZ_TYPE IS NULL AND CHARINDEX('Cell', C.ITEM_CLASS_NAME) > 0) THEN 'CELL'
							WHEN (C.FORECAST_INFO_BIZ_TYPE IS NULL AND CHARINDEX('Module', C.ITEM_CLASS_NAME) > 0) THEN 'MODULE'
							WHEN (C.FORECAST_INFO_BIZ_TYPE IS NULL AND  CHARINDEX('Pack'  , C.ITEM_CLASS_NAME) > 0) THEN 'PACK'
					ELSE C.FORECAST_INFO_BIZ_TYPE END AS ORI_MODEL_TYPE
			FROM	DM_MST_ITEM_SINGLE C WITH (NOLOCK) 
			WHERE	1=1
			AND		DIVISION_ID = '40'
			AND		ACTIVE_FLAG = 'Y'
			AND		DIVISION_ID = @P_DIVISION_ID 
		),
		GROUP_CODE AS
		(
			SELECT	DISTINCT DIVISION_ID, ITEM_ID, DOE, MAX(SCP_EXTRA_SPEC) AS EXTRA_SPEC
			FROM	SCM_ITEM_M_SN WITH (NOLOCK) 
			WHERE	1=1
			AND		ITEM_TYPE = 'P'	
			AND		DIVISION_ID = @P_DIVISION_ID 
			GROUP	BY DIVISION_ID, ITEM_ID, DOE
		),
		SCP_MST_FINAL_ITEM_VIEW AS
		(
			SELECT	A.*, B.SEGMENT2 
			FROM	SCP_MST_FINAL_ITEM A WITH (NOLOCK) 
					LEFT OUTER JOIN SCM_ADM_LOOKUP_MASTER_DETAIL B ON A.CELL_TYPE_GROUP_CODE = B.SEGMENT1 AND B.LOOKUP_TYPE = 'CELL_TYPE_GROUP_CODE' AND B.VALID_YN = 'Y'
			WHERE	1=1
			AND		DIVISION_ID = @P_DIVISION_ID 
		),
		SALES_PLAN_KRW AS
		(
			SELECT	PLAN_WEEK, VERSION_NO, CUTOFF_TYPE, CUTOFF_YYYYMMDD, DOM_EXP, FCST_TYPE, INCOTERMS, DIVISION_ID, ISO_YYYYWW, BASIS_YYYYMM, PROJECT_CODE, SCM_SITE_ID, PLANT_SITE_ID, ITEM_ID, MEASURE, CURRENCY, TYPE, SUM(QTY) AS QTY
			FROM	(
					SELECT	'999952' AS PLAN_WEEK,
							'MF_W_999952_V001' AS VERSION_NO,
							'Current' AS CUTOFF_TYPE,
							'99991231' AS CUTOFF_YYYYMMDD, -- 실제 CUTOFF 날짜가 아닌, 구분자 기능
							A.DOM_EXP,
							A.FCST_TYPE,
							A.INCOTERMS,
							A.DIVISION_ID,
							B.ISO_YYYYWW, 
							--B.BASIS_YYYYMM, 
							CONCAT(B.MONTH_NAME,'-01') AS BASIS_YYYYMM,
							A.PROJECT_CODE, 
							A.SCM_SITE_ID, 
							A.PLANT_SITE_ID,
							A.ITEM_ID, 
							A.YYYYMMDD,
							A.QTY,
							--A.MEASURE,						
							CASE WHEN A.MEASURE = 'SalesAmt_KRW' THEN 'RTF_SYS_RP' 
								 ELSE '' END AS MEASURE,
							A.CURRENCY,
							'RESULT' AS TYPE
					FROM	DM_PLN_SALES_PLAN_RESULT A WITH (NOLOCK) , DBO.SCM_SYS_CALENDAR_M B WITH (NOLOCK) , #T_PLAN_INFO C, SCM_MST_SITE_ITEM E WITH (NOLOCK) 
					WHERE	1=1
					AND		A.DIVISION_ID = C.DIVISION_ID
					AND		A.MEASURE IN ('SalesAmt_KRW')	
