CREATE PROCEDURE [dbo].[SSP0202_GET_SSP_PLAN_PROCESSING_CHECK]
	 @p_division_id			NVARCHAR(MAX)
AS
BEGIN
	SET NOCOUNT ON; 
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;
	
	SELECT CASE WHEN D.PLAN_STATUS = 0 THEN 'Y' ELSE 'N' END  PLAN_STATUS -- Y:수행중 
	,      ISNULL( CASE WHEN D.PLAN_STATUS = 0 THEN 
				CASE WHEN (CASE 
								--WHEN P.DIVISION_ID = '81' THEN 20 - DATEDIFF(MI,D.INPUT_START_DATE, GETDATE())
								--WHEN P.DIVISION_ID = '82' THEN  6 - DATEDIFF(MI,D.INPUT_START_DATE, GETDATE())
								--WHEN P.DIVISION_ID = '40' THEN  5 - DATEDIFF(MI,D.INPUT_START_DATE, GETDATE())
								WHEN MD.ATTRIBUTE3 = '81' THEN 20 - DATEDIFF(MI,D.INPUT_START_DATE, GETDATE())
								WHEN MD.ATTRIBUTE3 = '82' THEN  6 - DATEDIFF(MI,D.INPUT_START_DATE, GETDATE())
								WHEN MD.ATTRIBUTE3 = '40' THEN  5 - DATEDIFF(MI,D.INPUT_START_DATE, GETDATE())
						   ELSE NULL 
						   END ) <= 0 THEN 1 
				ELSE 
					 CASE 
						  --WHEN P.DIVISION_ID = '81' THEN 20 - DATEDIFF(MI,D.INPUT_START_DATE, GETDATE())
						  --WHEN P.DIVISION_ID = '82' THEN  6 - DATEDIFF(MI,D.INPUT_START_DATE, GETDATE())
						  --WHEN P.DIVISION_ID = '40' THEN  5 - DATEDIFF(MI,D.INPUT_START_DATE, GETDATE())
						  WHEN MD.ATTRIBUTE3 = '81' THEN 20 - DATEDIFF(MI,D.INPUT_START_DATE, GETDATE())
						  WHEN MD.ATTRIBUTE3 = '82' THEN  6 - DATEDIFF(MI,D.INPUT_START_DATE, GETDATE())
						  WHEN MD.ATTRIBUTE3 = '40' THEN  5 - DATEDIFF(MI,D.INPUT_START_DATE, GETDATE())
					 ELSE NULL 
					 END  
				END 
		   ELSE NULL  
		   END 	,0)  AS ESTIMATED_REMAIN_MINUTE
--	,      P.DIVISION_ID
--	,      P.PLAN_NAME 
--	,      D.INPUT_START_DATE 
--	,      D.ANL_END_DATE
	FROM SCM_MST_PLAN P WITH(NOLOCK) 
	     JOIN SCM_MST_DIVISION AS MD WITH(NOLOCK)
	  ON P.DIVISION_ID = MD.DIVISION_ID
	LEFT OUTER JOIN SCM_MST_PLAN_DETAIL D WITH(NOLOCK) 
				ON D.DIVISION_ID = P.DIVISION_ID 
				AND D.PLAN_ID = P.PLAN_ID 
				AND D.PLAN_TYPE = 'SP'
				AND D.PLAN_STATUS <> -1
				AND D.PLAN_SEQ = ( SELECT MAX(Y.PLAN_SEQ)
										FROM SCM_MST_PLAN_DETAIL Y WITH(NOLOCK) 
										WHERE Y.MODELING_ID = D.MODELING_ID
										AND   Y.DIVISION_ID = D.DIVISION_ID
										AND   Y.PLAN_ID = D.PLAN_ID
										AND   Y.PLAN_TYPE = D.PLAN_TYPE
										) 

	WHERE 1=1
	  AND P.PLAN_CYCLE = 'DAILY'
	  AND P.PLAN_NAME = ( SELECT MAX(B.PLAN_NAME) 
								  FROM SCM_MST_PLAN B WITH(NOLOCK) 
								  WHERE B.DIVISION_ID = P.DIVISION_ID 
								  AND   B.PLAN_CYCLE = P.PLAN_CYCLE) 
	  AND P.DIVISION_ID = @p_division_id 

END

