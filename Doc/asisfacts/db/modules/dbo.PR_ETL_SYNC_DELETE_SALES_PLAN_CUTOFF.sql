
CREATE   PROCEDURE dbo.PR_ETL_SYNC_DELETE_SALES_PLAN_CUTOFF
(
      @P_DIVISION_ID VARCHAR(20)
    , @P_VERSION_NO  VARCHAR(100)
    , @P_APPLY       BIT = 0
)
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    IF @P_DIVISION_ID IS NULL OR @P_DIVISION_ID NOT IN ('40', '81', '82')
        THROW 50601, N'이 정의는 DIVISION_ID=40, 81, 82만 지원합니다.', 1;
    IF NULLIF(LTRIM(RTRIM(@P_VERSION_NO)), '') IS NULL
        THROW 50602, N'이번 Oracle SP_W 실행의 VERSION_NO를 입력하세요.', 1;
    IF @P_APPLY IS NULL
        THROW 50603, N'P_APPLY는 0(미리보기) 또는 1(삭제)입니다.', 1;

    DECLARE @V_NOW DATETIME = GETDATE();
    DECLARE @V_MONTH_START CHAR(8) = CONVERT(CHAR(6), @V_NOW, 112) + '01';
    DECLARE @V_TODAY CHAR(8) = CONVERT(CHAR(8), @V_NOW, 112);
    DECLARE @V_MONDAY CHAR(8) =
        CONVERT(CHAR(8), DATEADD(DAY,-7,dbo.FN_NEXT_DAY(@V_NOW,'MON')),112);
    IF @V_MONDAY IS NULL
        THROW 50604, N'당주 월요일을 계산하지 못했습니다.', 1;

    IF @P_APPLY = 0
    BEGIN
        SELECT 'PREVIEW_NO_DELETE' PHASE, @P_DIVISION_ID DIVISION_ID,
               @P_VERSION_NO VERSION_NO, @V_NOW DB_TIME, @V_MONDAY CURRENT_MONDAY,
               X.TABLE_NAME, X.EXPECTED_COUNT
        FROM (
            SELECT 'DM_PLN_SALES_ETC_PLAN' TABLE_NAME, COUNT_BIG(*) EXPECTED_COUNT
            FROM dbo.DM_PLN_SALES_ETC_PLAN
            WHERE DIVISION_ID=@P_DIVISION_ID AND YYYYMMDD>=@V_MONDAY
              AND (MEASURE IN ('SalesAmt_KRW_Catch_Up','SalesAmt_LOC_Catch_Up','SalesAmt_USD_Catch_Up')
                   OR (MEASURE IN ('SalesAmt_KRW','SalesAmt_USD') AND FCST_TYPE='ETC'))
            UNION ALL
            SELECT 'SCM_MST_FUTURE_PRICE_C', COUNT_BIG(*)
            FROM dbo.SCM_MST_FUTURE_PRICE_C
            WHERE DIVISION_ID=@P_DIVISION_ID AND VERSION_NO=@P_VERSION_NO
              AND CUTOFF_TYPE='SP_W' AND YYYYMMDD>=@V_MONDAY
            UNION ALL
            SELECT 'DM_PLN_CFM_SELLING_PRICE_C', COUNT_BIG(*)
            FROM dbo.DM_PLN_CFM_SELLING_PRICE_C
            WHERE DIVISION_ID=@P_DIVISION_ID AND VERSION_NO=@P_VERSION_NO
              AND CUTOFF_TYPE='SP_W' AND YYYYMMDD>=@V_MONDAY
            UNION ALL
            SELECT 'DM_MST_EXCHANGE_RATE_C', COUNT_BIG(*)
            FROM dbo.DM_MST_EXCHANGE_RATE_C
            WHERE DIVISION_ID=@P_DIVISION_ID AND VERSION_NO=@P_VERSION_NO AND CUTOFF_TYPE='SP_W'
            UNION ALL
            SELECT 'DM_PLN_SALES_PLAN_RESULT', COUNT_BIG(*)
            FROM dbo.DM_PLN_SALES_PLAN_RESULT
            WHERE DIVISION_ID=@P_DIVISION_ID
              AND MEASURE IN ('SalesAmt_KRW','MKT_AMT_KRW')
              AND YYYYMMDD>=@V_MONTH_START AND YYYYMMDD<@V_TODAY
        ) X
        WHERE X.TABLE_NAME <> 'DM_PLN_SALES_PLAN_RESULT' OR @P_DIVISION_ID = '40';
        RETURN;
    END;

    IF @@TRANCOUNT <> 0
        THROW 50605, N'기존 트랜잭션이 없는 별도 연결에서 실행하세요.', 1;

    DECLARE @N_ETC BIGINT, @N_PRICE BIGINT, @N_CFM_PRICE BIGINT, @N_FX BIGINT,
            @N_RESULT BIGINT;
    BEGIN TRY
        BEGIN TRANSACTION;

        /* DELETE_SEQ 1: Oracle 금액 생성의 직접 DELETE 조건. */
        DELETE FROM dbo.DM_PLN_SALES_ETC_PLAN
        WHERE DIVISION_ID=@P_DIVISION_ID AND YYYYMMDD>=@V_MONDAY
          AND (MEASURE IN ('SalesAmt_KRW_Catch_Up','SalesAmt_LOC_Catch_Up','SalesAmt_USD_Catch_Up')
               OR (MEASURE IN ('SalesAmt_KRW','SalesAmt_USD') AND FCST_TYPE='ETC'));
        SET @N_ETC = ROWCOUNT_BIG();

        /* DELETE_SEQ 2: Oracle 가격 이력 동일 버전 교체. */
        DELETE FROM dbo.SCM_MST_FUTURE_PRICE_C
        WHERE DIVISION_ID=@P_DIVISION_ID AND VERSION_NO=@P_VERSION_NO
          AND CUTOFF_TYPE='SP_W' AND YYYYMMDD>=@V_MONDAY;
        SET @N_PRICE = ROWCOUNT_BIG();

        /* DELETE_SEQ 3: Oracle 가격 프로시저의 분기 밖 동일 버전 DELETE. */
        DELETE FROM dbo.DM_PLN_CFM_SELLING_PRICE_C
        WHERE DIVISION_ID=@P_DIVISION_ID AND VERSION_NO=@P_VERSION_NO
          AND CUTOFF_TYPE='SP_W' AND YYYYMMDD>=@V_MONDAY;
        SET @N_CFM_PRICE = ROWCOUNT_BIG();

        /* DELETE_SEQ 4: Oracle 환율 이력 동일 버전 교체. 기간 조건 없음. */
        DELETE FROM dbo.DM_MST_EXCHANGE_RATE_C
        WHERE DIVISION_ID=@P_DIVISION_ID AND VERSION_NO=@P_VERSION_NO AND CUTOFF_TYPE='SP_W';
        SET @N_FX = ROWCOUNT_BIG();

        /* DELETE_SEQ 5: Oracle 금액 생성의 40 전용 환율 재계산 범위. */
        IF @P_DIVISION_ID = '40'
        BEGIN
            DELETE FROM dbo.DM_PLN_SALES_PLAN_RESULT
            WHERE DIVISION_ID=@P_DIVISION_ID
              AND MEASURE IN ('SalesAmt_KRW','MKT_AMT_KRW')
              AND YYYYMMDD>=@V_MONTH_START AND YYYYMMDD<@V_TODAY;
            SET @N_RESULT = ROWCOUNT_BIG();
        END;

        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF XACT_STATE() <> 0 ROLLBACK TRANSACTION;
        THROW;
    END CATCH;

    /* 이관 전에 확인한다. 같은 범위의 REMAIN_COUNT가 0이어야 한다. */
    SELECT 'AFTER_DELETE_COMMITTED' PHASE, @P_DIVISION_ID DIVISION_ID,
           @P_VERSION_NO VERSION_NO, @V_MONDAY CURRENT_MONDAY,
           X.TABLE_NAME, X.DELETED_COUNT, X.REMAIN_COUNT
    FROM (
        SELECT 'DM_PLN_SALES_ETC_PLAN' TABLE_NAME, @N_ETC DELETED_COUNT, COUNT_BIG(*) REMAIN_COUNT
        FROM dbo.DM_PLN_SALES_ETC_PLAN
        WHERE DIVISION_ID=@P_DIVISION_ID AND YYYYMMDD>=@V_MONDAY
          AND (MEASURE IN ('SalesAmt_KRW_Catch_Up','SalesAmt_LOC_Catch_Up','SalesAmt_USD_Catch_Up')
               OR (MEASURE IN ('SalesAmt_KRW','SalesAmt_USD') AND FCST_TYPE='ETC'))
        UNION ALL
        SELECT 'SCM_MST_FUTURE_PRICE_C', @N_PRICE, COUNT_BIG(*)
        FROM dbo.SCM_MST_FUTURE_PRICE_C
        WHERE DIVISION_ID=@P_DIVISION_ID AND VERSION_NO=@P_VERSION_NO
          AND CUTOFF_TYPE='SP_W' AND YYYYMMDD>=@V_MONDAY
        UNION ALL
        SELECT 'DM_PLN_CFM_SELLING_PRICE_C', @N_CFM_PRICE, COUNT_BIG(*)
        FROM dbo.DM_PLN_CFM_SELLING_PRICE_C
        WHERE DIVISION_ID=@P_DIVISION_ID AND VERSION_NO=@P_VERSION_NO
          AND CUTOFF_TYPE='SP_W' AND YYYYMMDD>=@V_MONDAY
        UNION ALL
        SELECT 'DM_MST_EXCHANGE_RATE_C', @N_FX, COUNT_BIG(*)
        FROM dbo.DM_MST_EXCHANGE_RATE_C
        WHERE DIVISION_ID=@P_DIVISION_ID AND VERSION_NO=@P_VERSION_NO AND CUTOFF_TYPE='SP_W'
        UNION ALL
        SELECT 'DM_PLN_SALES_PLAN_RESULT', @N_RESULT, COUNT_BIG(*)
        FROM dbo.DM_PLN_SALES_PLAN_RESULT
        WHERE DIVISION_ID=@P_DIVISION_ID
          AND MEASURE IN ('SalesAmt_KRW','MKT_AMT_KRW')
          AND YYYYMMDD>=@V_MONTH_START AND YYYYMMDD<@V_TODAY
    ) X
    WHERE X.TABLE_NAME <> 'DM_PLN_SALES_PLAN_RESULT' OR @P_DIVISION_ID = '40';
END;
