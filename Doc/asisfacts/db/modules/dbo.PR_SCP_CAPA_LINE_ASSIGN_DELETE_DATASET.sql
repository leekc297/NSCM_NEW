


/*
 * Program ID   : PR_SCP_CAPA_LINE_ASSIGN_DELETE_DATASET
 * Description  : LINE ASSIGN 삭제(TACT TIME , YIELD 삭제 동기화)
 * Program History
 *===================================================================================================
 *   Date       In Charge      Description
 *===================================================================================================
 * 2021/08/24   khj79          [PJ20209643] LGES Digital SCM Level.3 달성을 위한 개선 (Phase.2) - 최초작성
 */

 

CREATE PROCEDURE [dbo].[PR_SCP_CAPA_LINE_ASSIGN_DELETE_DATASET]
	 @SCP0049			AS DBO.SCP0049       READONLY
AS
BEGIN
	SET NOCOUNT ON;
	SET TRANSACTION ISOLATION LEVEL READ COMMITTED;

	-- 이력용 변수 설정
	DECLARE @v_job_type		NVARCHAR(10) = 'MERGE';


	BEGIN
		
		-- 1. LINE ASSIGN 월별 데이터 삭제
		DELETE X
		  FROM SCM_MST_ITEM_LINE_ASSIGN_SN X
		  JOIN @SCP0049 T
			ON T.P_DIVISION_ID		= X.DIVISION_ID
		   AND T.P_COMPANY_ID		= X.COMPANY_ID
		   AND T.P_SITE_ID			= X.SITE_ID
		   AND T.P_PLANT_ID			= X.PLANT_ID
		   AND T.P_FACTORY_ID		= X.FACTORY_ID
		   AND T.P_LINE_ID			= X.LINE_ID
		   AND T.P_OPERATION_ID		= X.OPERATION_ID
		   AND T.P_ELECTRODE_TYPE	= X.ELECTRODE_TYPE
		   AND T.P_ITEM_ID			= X.ITEM_ID
		   AND T.P_DAY_NAME			= X.MONTH
		   AND T.P_DATA_TYPE		= 'M'
		;


		-- 2. LINE ASSIGN 일별 데이터 삭제
		DELETE X
		  FROM SCM_MST_ITEM_LINE_ASSIGN_EXCEPT_SN X
		  JOIN @SCP0049 T
			ON T.P_DIVISION_ID		= X.DIVISION_ID
		   AND T.P_COMPANY_ID		= X.COMPANY_ID
		   AND T.P_SITE_ID			= X.SITE_ID
		   AND T.P_PLANT_ID			= X.PLANT_ID
		   AND T.P_FACTORY_ID		= X.FACTORY_ID
		   AND T.P_LINE_ID			= X.LINE_ID
		   AND T.P_OPERATION_ID		= X.OPERATION_ID
		   AND T.P_ELECTRODE_TYPE	= X.ELECTRODE_TYPE
		   AND T.P_ITEM_ID			= X.ITEM_ID
		   AND ( 
					(T.P_DATA_TYPE		= 'D' AND T.P_DAY_NAME	= CONVERT(VARCHAR(8), X.START_TIME, 112) )
				OR  (T.P_DATA_TYPE		= 'M' AND T.P_DAY_NAME	= CONVERT(VARCHAR(6), X.START_TIME, 112) )
				)
		;

		-- 3. TACT TIME 월별 데이터 삭제
		DELETE X
		  FROM SCM_MST_TACT_TIME_SN X
		  JOIN @SCP0049 T
			ON T.P_DIVISION_ID		= X.DIVISION_ID
		   AND T.P_COMPANY_ID		= X.COMPANY_ID
		   AND T.P_SITE_ID			= X.SITE_ID
		   AND T.P_PLANT_ID			= X.PLANT_ID
		   AND T.P_FACTORY_ID		= X.FACTORY_ID
		   AND T.P_LINE_ID			= X.LINE_ID
		   AND T.P_OPERATION_ID		= X.OPERATION_ID
		   AND T.P_ELECTRODE_TYPE	= X.ELECTRODE_TYPE
		   AND T.P_ITEM_ID			= X.ITEM_ID
		   AND T.P_DAY_NAME			= X.MONTH
		   AND T.P_DATA_TYPE		= 'M'
		;

		-- 4. TACT TIME 일별 데이터 삭제
		DELETE X
		  FROM SCM_MST_TACT_TIME_EXCEPT_SN X
		  JOIN @SCP0049 T
			ON T.P_DIVISION_ID		= X.DIVISION_ID
		   AND T.P_COMPANY_ID		= X.COMPANY_ID
		   AND T.P_SITE_ID			= X.SITE_ID
		   AND T.P_PLANT_ID			= X.PLANT_ID
		   AND T.P_FACTORY_ID		= X.FACTORY_ID
		   AND T.P_LINE_ID			= X.LINE_ID
		   AND T.P_OPERATION_ID		= X.OPERATION_ID
		   AND T.P_ELECTRODE_TYPE	= X.ELECTRODE_TYPE
		   AND T.P_ITEM_ID			= X.ITEM_ID
		   AND ( 
					(T.P_DATA_TYPE		= 'D' AND T.P_DAY_NAME	= CONVERT(VARCHAR(8), X.START_TIME, 112) )
				OR  (T.P_DATA_TYPE		= 'M' AND T.P_DAY_NAME	= CONVERT(VARCHAR(6), X.START_TIME, 112) )
				)
		;

		-- 5. YIELD 월별 데이터 삭제
		DELETE X
		  FROM SCM_MST_YIELD_SN X
		  JOIN @SCP0049 T
			ON T.P_DIVISION_ID		= X.DIVISION_ID
		   AND T.P_COMPANY_ID		= X.COMPANY_ID
		   AND T.P_SITE_ID			= X.SITE_ID
		   AND T.P_PLANT_ID			= X.PLANT_ID
		   AND T.P_FACTORY_ID		= X.FACTORY_ID
		   AND T.P_LINE_ID			= X.LINE_ID
		   AND T.P_OPERATION_ID		= X.OPERATION_ID
		   AND T.P_ITEM_ID			= X.ITEM_ID
		   AND T.P_DAY_NAME			= X.MONTH
		   AND T.P_DATA_TYPE		= 'M'
		;


		-- 6. YIELD 일별 데이터 삭제
		DELETE X
		  FROM SCM_MST_YIELD_EXCEPT_SN X
		  JOIN @SCP0049 T
			ON T.P_DIVISION_ID		= X.DIVISION_ID
		   AND T.P_COMPANY_ID		= X.COMPANY_ID
		   AND T.P_SITE_ID			= X.SITE_ID
		   AND T.P_PLANT_ID			= X.PLANT_ID
		   AND T.P_FACTORY_ID		= X.FACTORY_ID
		   AND T.P_LINE_ID			= X.LINE_ID
		   AND T.P_OPERATION_ID		= X.OPERATION_ID
		   AND T.P_ITEM_ID			= X.ITEM_ID
		   AND ( 
					(T.P_DATA_TYPE		= 'D' AND T.P_DAY_NAME	= CONVERT(VARCHAR(8), X.START_TIME, 112) )
				OR  (T.P_DATA_TYPE		= 'M' AND T.P_DAY_NAME	= CONVERT(VARCHAR(6), X.START_TIME, 112) )
				)
		;

	END
END
