   @P_TABLE          nvarchar(128)
 , @P_ROLLIN         nvarchar(30) --1ST 2ND 3RD 4TH
 , @P_RTYPE_NUM INT = 99999
 , @P_Matched   nvarchar(30) ='N'-- N: 조인되지 않은 값도 포함, Y: 조인된 값만 조회
 , @P_UseProd   nvarchar(30) ='N'-- N: 현재 QA DB사용, Y: LINKED_SERVER 운영환경 사용
 , @P_GROUP_NUM INT --그룹카운트 중 몇번째 것
 , @P_GROUP_COUNT INT 
 , @P_GR_BATCH_ID INT = -1
AS
BEGIN

    IF @P_ROLLIN NOT IN ('1ST','2ND','3RD','4TH','5TH','4N5')
    BEGIN
        PRINT CONVERT(NVARCHAR(MAX), N'@P_ROLLIN: '''+ISNULL(@P_ROLLIN,'Value is null ')+''' Please, Input Defined ROLLIN, Stop Procedure!!.');
        RETURN 1; -- 오류 코드를 반환하며 프로시저 종료
    END

--################################################################################################################
--DECLARE
--################################################################################################################
    DECLARE @CNT BIGINT;
    DECLARE @WORK_SECOND BIGINT;
    DECLARE @MAPPING_RESULT NVARCHAR(2);
    DECLARE @BATCH_RUN_TIME BIGINT;
    DECLARE @BATCH_START_TIME DATETIME;
    DECLARE @BATCH_END_TIME DATETIME;
    DECLARE @RUN_TIME BIGINT;
    DECLARE @START_TIME DATETIME;
    DECLARE @END_TIME DATETIME;
    DECLARE @YYYYMM nvarchar(10) = '';
    DECLARE @V_SCOPE_ID BIGINT;
    DECLARE @OnlyMatched BIT;
    DECLARE @DBPrefix NVARCHAR(254);
    SET @OnlyMatched = CASE WHEN ISNULL(@P_Matched, 'N') = 'Y' THEN 1 ELSE 0 END; -- 0: 조인되지 않은 값도 포함, 1: 조인된 값만 조회
    SET @DBPrefix = CASE WHEN ISNULL(@P_UseProd, 'N') = 'Y' THEN '[DBO].' ELSE '[DBO].' END; -- Y: LINKED_SERVER 운영DB 사용, N: 현재 QA DB사용
    DECLARE @V_FR_YYYYMMDD NVARCHAR(8)=(SELECT TOP 1 FR_YYYYMMDD FROM NERP_CONV_SCP_RUN_DT_RANGE WITH(NOLOCK) WHERE MODULE='DM' AND ROLLIN=@P_ROLLIN AND RTYPE_NUM = @P_RTYPE_NUM ORDER BY RTYPE_NUM DESC);
    DECLARE @V_TO_YYYYMMDD NVARCHAR(8)=(SELECT TOP 1 TO_YYYYMMDD FROM NERP_CONV_SCP_RUN_DT_RANGE WITH(NOLOCK) WHERE MODULE='DM' AND ROLLIN=@P_ROLLIN AND RTYPE_NUM = @P_RTYPE_NUM ORDER BY RTYPE_NUM DESC);

    SET @CNT = 0;
    SET @RUN_TIME = 0;

    --###########################################################################################################
    -- LOG 용 변수 설정
    --###########################################################################################################
    DECLARE @v_batch_user NVARCHAR(150) = 'NERP';
    DECLARE @v_program_name NVARCHAR(150) = 'PR_SCP_NERP_COLUMN_CONVERTER_CHECK_AFTER_ROWCNT_CUTOFF_DM';
    DECLARE @v_log_type     NVARCHAR(30); -- START/END/ERROR/...
    DECLARE @n_log_count    INTEGER = 0;
    DECLARE @v_log_message  NVARCHAR(1000);
    DECLARE @v_description  NVARCHAR(500);
    DECLARE @d_event_date   DATETIME;
    DECLARE @v_ifseqno      NVARCHAR(30);
    DECLARE @n_history_seq  BIGINT;
    DECLARE @LOOP integer = 0;


BEGIN TRY

    -- 시작 LOG
    SET @v_log_type = 'START';
    SET @v_log_message = '########## Start of procedure ##########';
    DECLARE @BATCH_ID BIGINT;
    SET @BATCH_ID = NEXT VALUE FOR [dbo].[SEQ1_NERP_CONV_ALL_TABLE];
    SET @v_description = '@P_TABLE:'+ISNULL(@P_TABLE,'NULL')+',@P_ROLLIN:'+@P_ROLLIN+',@BATCH_ID:'+CONVERT(NVARCHAR(MAX),@BATCH_ID)+',@V_FR_YYYYMMDD:'+@V_FR_YYYYMMDD+',@V_TO_YYYYMMDD:'+@V_TO_YYYYMMDD+',@P_Matched:'+@P_Matched+',@P_UseProd:'+@P_UseProd+',@P_RTYPE_NUM='+CONVERT(CHAR(23),@P_RTYPE_NUM)+',@P_GROUP_NUM='+CONVERT(CHAR(23),@P_GROUP_NUM)+',@P_GROUP_COUNT='+CONVERT(CHAR(23),@P_GROUP_COUNT)+',@P_GR_BATCH_ID='+CONVERT(CHAR(23),@P_GR_BATCH_ID);
    SET @d_event_date = SYSDATETIME();
    SET @BATCH_START_TIME = SYSDATETIME();
    SET @START_TIME = CONVERT(CHAR(23), GETDATE(), 21);
    EXEC PR_SCM_SYS_LOG_BATCH @v_program_name, 'START', 0, '0',@v_description, @START_TIME;

    DECLARE @CUTOFF_START NVARCHAR(8) =@V_FR_YYYYMMDD;
    DECLARE @Upper_Limit_Value NVARCHAR(8) = @V_TO_YYYYMMDD;
    PRINT @Upper_Limit_Value
    DECLARE @C_MAPPING_USE NVARCHAR(2)
    DECLARE @C_TABLE_NAME  NVARCHAR(128)
    DECLARE @C_DUMMY_TBL_NM NVARCHAR(128)
    DECLARE @C_COPYED_TBL_NM NVARCHAR(128) = '';
    DECLARE @C_PRINT_YN    BIT = 0; -- 1 Y, 0 N
    DECLARE @C_CUTOFF_COL  NVARCHAR(128)
    DECLARE @C_STORAGE_COL_YN NVARCHAR(1)
    DECLARE @C_CUT_COL1    NVARCHAR(128)
    DECLARE @C_CUT_COL2    NVARCHAR(128)
    DECLARE @C_CUT_COL3    NVARCHAR(128)
    DECLARE @C_CUT_COL4    NVARCHAR(128)
    DECLARE @C_C_FROM      NVARCHAR(128)
    DECLARE @C_C_TO        NVARCHAR(128)
    DECLARE @C_C_DIVISION  NVARCHAR(128)
    DECLARE @C_C_PLAN_TYPE NVARCHAR(128)
    DECLARE @C_B1          NVARCHAR(128)--BEFORE
    DECLARE @C_B2          NVARCHAR(128)
    DECLARE @C_B3          NVARCHAR(128)
    DECLARE @C_B4          NVARCHAR(128)
    DECLARE @C_B5          NVARCHAR(128)
    DECLARE @C_B6          NVARCHAR(128)
    DECLARE @C_B7          NVARCHAR(128)
    DECLARE @C_SEL_B1      NVARCHAR(128)--BEFORE
    DECLARE @C_SEL_B2      NVARCHAR(128)
    DECLARE @C_SEL_B3      NVARCHAR(128)
    DECLARE @C_SEL_B4      NVARCHAR(128)
    DECLARE @C_SEL_B5      NVARCHAR(128)
    DECLARE @C_SEL_B6      NVARCHAR(128)
    DECLARE @C_SEL_B7      NVARCHAR(128)
    DECLARE @C_A1          NVARCHAR(128)--AFTER
    DECLARE @C_A2          NVARCHAR(128)
    DECLARE @C_A3          NVARCHAR(128)
    DECLARE @C_A4          NVARCHAR(128)
    DECLARE @C_A5          NVARCHAR(128)
    DECLARE @C_A6          NVARCHAR(128)
    DECLARE @C_A7          NVARCHAR(128)
    DECLARE @C_SEL_A1      NVARCHAR(128)--AFTER
    DECLARE @C_SEL_A2      NVARCHAR(128)
    DECLARE @C_SEL_A3      NVARCHAR(128)
    DECLARE @C_SEL_A4      NVARCHAR(128)
    DECLARE @C_SEL_A5      NVARCHAR(128)
    DECLARE @C_SEL_A6      NVARCHAR(128)
    DECLARE @C_SEL_A7      NVARCHAR(128)
    DECLARE @C_RN          INT
    DECLARE @SQL_STMT      NVARCHAR(MAX);
    DECLARE @SQL_SA        NVARCHAR(MAX)='';
    DECLARE @SQL_SM        NVARCHAR(MAX)='';
    DECLARE @SQL_SW        NVARCHAR(MAX)='';
    DECLARE @SQL_ISNOTNULL NVARCHAR(MAX)='';
    DECLARE @SQL_WHERE     NVARCHAR(MAX)='';
    DECLARE @ExecutionRST  NVARCHAR(MAX);
    DECLARE @DUMMY         NVARCHAR(MAX);

    -- 커서가 이미 열려 있는지 확인
    IF CURSOR_STATUS('global', 'cur_CUTOFF_COL') >= 0
    BEGIN
        CLOSE cur_CUTOFF_COL;
        DEALLOCATE cur_CUTOFF_COL;
    END
    DECLARE cur_CUTOFF_COL CURSOR FAST_FORWARD READ_ONLY FOR
        SELECT DISTINCT D.TABLE_NAME,D.CUTOFF_FROM,D.CUTOFF_TO,D.CUTOFF_DIVISION,D.CUTOFF_PLAN_TYPE--,M.*
        FROM   NERP_CONV_DM_CUTOFF D WITH (NOLOCK)
        LEFT JOIN NERP_CONV_DM_CUTOFF_MASTER M WITH (NOLOCK) ON D.TABLE_NAME = M.TABLE_NAME
             JOIN NERP_CONV_CUTOFF_TAKES_MIN CTM WITH(NOLOCK) ON D.TABLE_NAME = CTM.TABLE_NAME
        WHERE  D.MAPPING_USE = 'Y'
        AND    CTM.RTYPE = 'DM'
        AND    CTM.GROUP_NUM = @P_GROUP_NUM
        AND    CTM.GROUP_COUNT = @P_GROUP_COUNT
        AND   (@P_TABLE IS NULL OR @P_TABLE ='' OR @P_TABLE ='ALL' OR D.TABLE_NAME = @P_TABLE)
        ORDER BY D.TABLE_NAME ASC

    OPEN cur_CUTOFF_COL

    FETCH NEXT FROM cur_CUTOFF_COL INTO @C_TABLE_NAME, @C_C_FROM, @C_C_TO, @C_C_DIVISION, @C_C_PLAN_TYPE;

    WHILE @@FETCH_STATUS = 0 BEGIN

        SET @C_CUT_COL1 = NULL;
        SET @C_CUT_COL2 = NULL;
        SET @C_CUT_COL3 = NULL;
        SET @C_CUT_COL4 = NULL;
        SET @SQL_SW     = NULL;
        SET @SQL_STMT   = N'';

            PRINT '------------------------------------------------------------------------------------------------------------------------------------------';
            SET @C_TABLE_NAME = @C_TABLE_NAME;
            SET @CNT = @CNT+1;
            SET @START_TIME = CONVERT(CHAR(23), GETDATE(), 21);
            --EXEC PR_SCM_SYS_LOG_BATCH @v_program_name, @C_TABLE_NAME, 0, '0', '', @START_TIME;
            SET @DUMMY = 'RUN -->> '+concat(
            '     @CNT = ' , @CNT
            , ' , @C_TABLE_NAME = ', @C_TABLE_NAME
            , ' , @START_TIME = ' , @START_TIME
            , ' , @P_TABLE = ' , @P_TABLE
            , ' , @P_ROLLIN = ' , @P_ROLLIN
            , ' , @BATCH_ID = ' , @BATCH_ID
            , ' , @V_FR_YYYYMMDD = ' , @V_FR_YYYYMMDD
            , ' , @V_TO_YYYYMMDD = ' , @V_TO_YYYYMMDD
            );

            PRINT @DUMMY

        SELECT TOP 1 @C_CUT_COL1 = D.CUTOFF_COLUMN1
                ,@C_CUT_COL2 = D.CUTOFF_COLUMN2
                ,@C_CUT_COL3 = D.CUTOFF_COLUMN3
                ,@C_CUT_COL4 = D.CUTOFF_COLUMN4
        FROM   NERP_CONV_DM_CUTOFF D WITH (NOLOCK)
        LEFT JOIN NERP_CONV_DM_CUTOFF_MASTER M WITH (NOLOCK) ON D.TABLE_NAME = M.TABLE_NAME
        WHERE  D.MAPPING_USE = 'Y'
        AND    D.TABLE_NAME = @C_TABLE_NAME;

        --######################################
        -- SELECT 컬럼 사용.
        --######################################
        DECLARE @ColumnsToSelect NVARCHAR(MAX)='';

        -- 2. PK 컬럼 확인
        SELECT @ColumnsToSelect = STRING_AGG('A.' + QUOTENAME(c.name), ', ') WITHIN GROUP (ORDER BY ic.key_ordinal)
        FROM sys.tables t
        INNER JOIN sys.indexes i ON t.object_id = i.object_id
        INNER JOIN sys.index_columns ic ON i.object_id = ic.object_id AND i.index_id = ic.index_id
        INNER JOIN sys.columns c ON ic.object_id = c.object_id AND ic.column_id = c.column_id
        WHERE i.is_primary_key = 1
        AND t.name = @C_TABLE_NAME
        AND SCHEMA_NAME(t.schema_id) = 'dbo';

        -- 3. PK가 없으면 전체 컬럼 사용
        IF @ColumnsToSelect IS NULL
        BEGIN
            SELECT @ColumnsToSelect = STRING_AGG('A.' + QUOTENAME(c.name), ', ') WITHIN GROUP (ORDER BY c.column_id)
            FROM sys.columns c
            JOIN sys.tables t ON c.object_id = t.object_id
            WHERE t.name = @C_TABLE_NAME
            AND SCHEMA_NAME(t.schema_id) = 'dbo';
        END

        -- 커서가 이미 열려 있는지 확인
        IF CURSOR_STATUS('global', 'cur') >= 0
        BEGIN
            CLOSE cur;
            DEALLOCATE cur;
        END
        DECLARE cur CURSOR FAST_FORWARD READ_ONLY FOR
            WITH W_RAW AS (
                SELECT MAPPING_USE
                      ,TABLE_NAME
                      ,CUTOFF_COL
                      ,SEL_COL
                      ,STRING_AGG(MAP_COL, ', ') WITHIN GROUP (ORDER BY SEL_COL ASC) AS MAP_COL
                      ,ROW_NUMBER()OVER(PARTITION BY TABLE_NAME ORDER BY SEL_COL) RNUM
                FROM (
                    SELECT NULL               AS MAPPING_USE
                          ,TID.TABLE_NAME     AS TABLE_NAME
                          ,NULL               AS CUTOFF_COL
                          ,TID.TABLE_COL      AS SEL_COL
                          ,REPLACE(REPLACE(' '+TID.MASTER_CODETYPE+' ',' SCM_SITE_ID ','SCP_SITE_ID'),' SITE_ID ','SCP_SITE_ID') AS MAP_COL
                    FROM   ZNERP_TARGET_INFO_DM TID WITH(NOLOCK)
                    WHERE  1=1
                    AND    TID.TABLE_NAME = @C_TABLE_NAME
                    AND    NOT EXISTS (SELECT 1 WHERE @P_ROLLIN <> '3RD' AND TID.MASTER_CODETYPE = 'CURRENCY_ID')

                    --2025-06-05 SCP_SITE_ID 추가, 실제 UPDATE 프로그램은 MASTER_CODETYPE이 PLANT_ID일경우 SCP_SITE_ID 값으로도 동시에 UPDATE 한다(2가지 다 함)
                    UNION
                    SELECT NULL               AS MAPPING_USE
                          ,TID.TABLE_NAME     AS TABLE_NAME
                          ,NULL               AS CUTOFF_COL
                          ,TID.TABLE_COL      AS SEL_COL
                          ,'SCP_SITE_ID'      AS MAP_COL
                    FROM   ZNERP_TARGET_INFO_DM TID WITH(NOLOCK)
                    WHERE  1=1
                    AND    TID.TABLE_NAME = @C_TABLE_NAME
                    AND    TID.MASTER_CODETYPE = 'PLANT_ID'
                    --2025-06-07 PLANT_ID,SCP_SITE_ID 추가, 실제 UPDATE 프로그램은 MASTER_CODETYPE이 SITE_ID일경우 PLANT_ID,SCP_SITE_ID 값으로도 동시에 UPDATE 한다(2가지 다 함)
                    UNION
                    SELECT NULL               AS MAPPING_USE
                          ,TID.TABLE_NAME     AS TABLE_NAME
                          ,NULL               AS CUTOFF_COL
                          ,TID.TABLE_COL      AS SEL_COL
                          ,'PLANT_ID'         AS MAP_COL
                    FROM   ZNERP_TARGET_INFO_DM TID WITH(NOLOCK)
                    WHERE  1=1
                    AND    TID.TABLE_NAME = @C_TABLE_NAME
                    AND    TID.MASTER_CODETYPE = 'SITE_ID'
                 ) X
                 GROUP BY MAPPING_USE
                      ,TABLE_NAME
                      ,CUTOFF_COL
                      ,SEL_COL

            )
            SELECT WR.MAPPING_USE
                  ,WR.TABLE_NAME
                  ,WR.CUTOFF_COL
                  ,STORAGE_COL_YN=MAX(CASE WHEN WR.MAP_COL = 'STORAGE_ID' THEN 'Y' ELSE 'N' END)
                  ,MAX(CASE WHEN WR.RNUM = 1 THEN WR.SEL_COL END) B1 --BEFORE
                  ,MAX(CASE WHEN WR.RNUM = 2 THEN WR.SEL_COL END) B2
                  ,MAX(CASE WHEN WR.RNUM = 3 THEN WR.SEL_COL END) B3
                  ,MAX(CASE WHEN WR.RNUM = 4 THEN WR.SEL_COL END) B4
                  ,MAX(CASE WHEN WR.RNUM = 5 THEN WR.SEL_COL END) B5
                  ,MAX(CASE WHEN WR.RNUM = 6 THEN WR.SEL_COL END) B6
                  ,MAX(CASE WHEN WR.RNUM = 7 THEN WR.SEL_COL END) B7
                  ,MAX(CASE WHEN WR.RNUM = 1 THEN WR.MAP_COL END) A1 --AFTER
                  ,MAX(CASE WHEN WR.RNUM = 2 THEN WR.MAP_COL END) A2
                  ,MAX(CASE WHEN WR.RNUM = 3 THEN WR.MAP_COL END) A3
                  ,MAX(CASE WHEN WR.RNUM = 4 THEN WR.MAP_COL END) A4
                  ,MAX(CASE WHEN WR.RNUM = 5 THEN WR.MAP_COL END) A5
                  ,MAX(CASE WHEN WR.RNUM = 6 THEN WR.MAP_COL END) A6
                  ,MAX(CASE WHEN WR.RNUM = 7 THEN WR.MAP_COL END) A7
                  ,MAX(WR.RNUM) RN
            FROM   W_RAW WR
            GROUP BY WR.MAPPING_USE
                  ,WR.TABLE_NAME
                  ,WR.CUTOFF_COL
            ORDER BY 1,2,3

        OPEN cur

        FETCH NEXT FROM cur INTO @C_MAPPING_USE, @C_DUMMY_TBL_NM, @C_CUTOFF_COL, @C_STORAGE_COL_YN
            ,@C_B1,@C_B2,@C_B3,@C_B4,@C_B5,@C_B6,@C_B7
            ,@C_A1,@C_A2,@C_A3,@C_A4,@C_A5,@C_A6,@C_A7,@C_RN

        WHILE @@FETCH_STATUS = 0 BEGIN

            IF @C_TABLE_NAME <> @C_COPYED_TBL_NM
                BEGIN
                    SET @C_COPYED_TBL_NM = @C_TABLE_NAME;
                    SET @C_PRINT_YN = 1;
                END
