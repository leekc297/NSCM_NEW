 *===================================================================================================
 * 20200420 HWI1993 Initial Release 전지 공급 대응력 향상을 위한 RTF 적확도 개선
 * 20200423 HWI1993 DATA_SEQ 추가 ( PK 구성을 위해서 )
 * 20200713 HWI1993 ETC 에서 PROJECT_NAME 로직 변경 
 * 2020/09/21	HWI1993	[C20200909-000188] [ESS영업관리팀] GDW 용도별 매출 수정 (프로젝트 코드 S 주택용/상업용 분리) 
 * 2020/06/17	HWI1993	2021년 상반기 과제 - 소형 Sales Report 마스터 정비
 * 2022/02/21   HWI1993 [C20220121-000258] 매출 TABLE (FN_DM_SALES_REPORT_TO_GDW)통합 및 GDW에게 I/F
 */

CREATE FUNCTION [dbo].[FN_DM_SALES_REPORT_TO_GDW]
(
@P_DIVISION_ID NVARCHAR(100)
, @P_VERSION_NO NVARCHAR(4000)
)
RETURNS @TBL TABLE
(
DATA_TYPE						NVARCHAR(1)
,DATA_SEQ						INT
,DIVISION_ID					NVARCHAR(5)
,VERSION_NO						NVARCHAR(30)
,CUTOFF_TYPE					NVARCHAR(20)
,CUTOFF_YYYYMMDD				NVARCHAR(8)
,DEPARTMENT_ID					NVARCHAR(10)
,DEPT_ID						NVARCHAR(10)
,DEPARTMENT_NAME				NVARCHAR(50)
,DEPT_NAME						NVARCHAR(50)
,END_CUST_REPORT				NVARCHAR(30)
,CUST_REPORT					NVARCHAR(30)
,PRODUCT_GROUP					NVARCHAR(30)
,PROJECT_CODE					NVARCHAR(30)
,SCM_SITE_ID					NVARCHAR(30)
,ITEM_ID						NVARCHAR(50)
,DOM_EXP						NVARCHAR(3)
,FCST_TYPE						NVARCHAR(10)
,INCOTERMS						NVARCHAR(10)
,PLANT_SITE_ID					NVARCHAR(30)
,CURRENCY						NVARCHAR(10)
,COMPANY_ID						NVARCHAR(10)
,YYYYMMDD						NVARCHAR(8)
,MEASURE						NVARCHAR(20)
,SOLDTO_CODE					NVARCHAR(30)
,SOLDTO_CUST_REPORT				NVARCHAR(50)
,PRODUCT_DETAILS				NVARCHAR(30)
,CELL_MODEL_INFO				NVARCHAR(30)
,BIZ_TYPE						NVARCHAR(20)
,APPLICATION_GR					NVARCHAR(30)
,APPLICATION					NVARCHAR(30)
,COUNTRY_CODE					NVARCHAR(2)
,PROJECT_NAME					NVARCHAR(300)
,QTY							NUMERIC(30,10)
,CREATED_BY						NVARCHAR(150)
,CREATION_DATE					DATETIME
,LAST_UPDATED_BY				NVARCHAR(150)
,LAST_UPDATE_DATE				DATETIME
,ATTRIBUTE1						NVARCHAR(150)
,ATTRIBUTE2						NVARCHAR(150)
,ATTRIBUTE3						NVARCHAR(150)
,ATTRIBUTE4						NVARCHAR(150)
,ATTRIBUTE5						NVARCHAR(150)
,ATTRIBUTE6						NVARCHAR(150)
,ATTRIBUTE7						NVARCHAR(150)
,ATTRIBUTE8						NVARCHAR(150)
,ATTRIBUTE9						NVARCHAR(150)
,ATTRIBUTE10					NVARCHAR(150)
, CELL_PACK						INT
, MODULE_PACK					INT
, MODEL_TYPE					NVARCHAR(30)
, FCST_TYPE_NAME				NVARCHAR(30)
, NICK_NAME						NVARCHAR(100)
, ITEM_USE						NVARCHAR(30)
, SoldTo_COUNTRY				NVARCHAR(30)
, ShipTo_COUNTRY				NVARCHAR(30)
, Cell_Name						NVARCHAR(30)

, OWNER_NAME					NVARCHAR(150)
, FORECAST_INFO_CELL_PACK_COUNT	NUMERIC(20,10)
, COUNTRY_KR_NAME				NVARCHAR(50)
, COMPANY_NAME					NVARCHAR(100)
, FORECAST_INFO_BIZ_TYPE		NVARCHAR(10)
, CUST_GROUP_DTL				NVARCHAR(100)
, FORECAST_INFO_CELL_MODEL		NVARCHAR(20)
, FORECAST_INFO_SPEC			NVARCHAR(30)

, ROUTE                         NVARCHAR(40)


)AS
BEGIN

	DECLARE @V_DIVISION_ID NVARCHAR(30), @V_VERSION_NO NVARCHAR(50), @V_I INT, @V_CNT INT
	DECLARE @T TABLE(
	SEQ INT IDENTITY(0,1)
	, DIVISION_ID NVARCHAR(30)
	, VERSION_NO NVARCHAR(50)
	)

	INSERT INTO @T ( DIVISION_ID, VERSION_NO )
	SELECT A.ELEMENT, B.ELEMENT
	FROM DBO.UF_FX_Split( @P_DIVISION_ID, ',') A
	JOIN DBO.UF_FX_Split( @P_VERSION_NO, ',') B ON A.POS = B.POS

	DECLARE @PJT TABLE ( 
	DIVISION_ID NVARCHAR(30)
	, PROJECT_CODE NVARCHAR(50)
	, PROJECT_NAME NVARCHAR(200)
	, PRODUCT_GROUP_NAME NVARCHAR(100)
	)

	INSERT INTO @PJT ( DIVISION_ID, PROJECT_CODE, PROJECT_NAME, PRODUCT_GROUP_NAME )
	SELECT A.DIVISION_ID, A.PROJECT_CODE, A.PROJECT_NAME, A.PRODUCT_GROUP_NAME
	FROM SCM_MST_PROJECT A
	JOIN (
		SELECT DIVISION_ID, PROJECT_CODE, MAX(PROJECT_VER_SEQ) AS SEQ 
		FROM SCM_MST_PROJECT 
		GROUP BY DIVISION_ID, PROJECT_CODE
		) B ON A.PROJECT_CODE = B.PROJECT_CODE AND A.PROJECT_VER_SEQ = B.SEQ AND A.DIVISION_ID = B.DIVISION_ID


	SELECT @V_CNT = COUNT(*), @V_I = 0
	FROM @T

	WHILE ( @V_I < @V_CNT )
	BEGIN

		SELECT @V_DIVISION_ID = DIVISION_ID, @V_VERSION_NO = VERSION_NO
		FROM @T
		WHERE SEQ = @V_I

        IF @V_DIVISION_ID = '40'
        BEGIN
            INSERT INTO @TBL ( DATA_TYPE, DIVISION_ID, VERSION_NO, CUTOFF_TYPE, CUTOFF_YYYYMMDD, DEPARTMENT_ID, DEPT_ID, DEPARTMENT_NAME, DEPT_NAME
                            , END_CUST_REPORT, CUST_REPORT, PRODUCT_GROUP, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS
                            , PLANT_SITE_ID, CURRENCY, COMPANY_ID, YYYYMMDD, MEASURE, SOLDTO_CUST_REPORT, PRODUCT_DETAILS, APPLICATION_GR
                            , APPLICATION, QTY, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE
                            , ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10
                            , NICK_NAME, OWNER_NAME, FORECAST_INFO_CELL_PACK_COUNT, COUNTRY_KR_NAME, COMPANY_NAME, FORECAST_INFO_BIZ_TYPE
                            , CUST_GROUP_DTL, FORECAST_INFO_CELL_MODEL, FORECAST_INFO_SPEC )
            SELECT DATA_TYPE, DIVISION_ID, VERSION_NO, CUTOFF_TYPE, CUTOFF_YYYYMMDD, DEPARTMENT_ID, DEPT_ID, DEPARTMENT_NAME, DEPT_NAME
                            , END_CUST_REPORT, CUST_REPORT, PRODUCT_GROUP, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS
                            , PLANT_SITE_ID, CURRENCY, COMPANY_ID, YYYYMMDD, MEASURE, SOLDTO_CUST_REPORT, PRODUCT_DETAILS, APPLICATION_GR
                            , APPLICATION, QTY, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE
                            , ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10
                            , NICK_NAME, OWNER_NAME, FORECAST_INFO_CELL_PACK_COUNT, COUNTRY_KR_NAME, COMPANY_NAME, FORECAST_INFO_BIZ_TYPE
                            , CUST_GROUP_DTL, FORECAST_INFO_CELL_MODEL, FORECAST_INFO_SPEC
            FROM DM_PLN_SALES_PLAN_REPORT_C A
            WHERE A.DIVISION_ID = @V_DIVISION_ID
			    AND A.VERSION_NO = @V_VERSION_NO
                AND A.DATA_TYPE = '1'

            INSERT INTO @TBL ( DATA_TYPE, DATA_SEQ, DIVISION_ID, VERSION_NO, CUTOFF_TYPE, CUTOFF_YYYYMMDD, DEPARTMENT_ID, DEPT_ID, DEPARTMENT_NAME
                            , DEPT_NAME, END_CUST_REPORT, CUST_REPORT, PRODUCT_GROUP, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE
                            , INCOTERMS, PLANT_SITE_ID, CURRENCY, COMPANY_ID, YYYYMMDD, MEASURE, SOLDTO_CODE, SOLDTO_CUST_REPORT, PRODUCT_DETAILS
                            , CELL_MODEL_INFO, BIZ_TYPE, APPLICATION_GR, APPLICATION, COUNTRY_CODE, PROJECT_NAME, QTY, CREATED_BY, CREATION_DATE
                            , LAST_UPDATED_BY, LAST_UPDATE_DATE, ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7
                            , ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10, NICK_NAME, ITEM_USE, SoldTo_COUNTRY, ShipTo_COUNTRY, OWNER_NAME 
                            , COUNTRY_KR_NAME, COMPANY_NAME, CUST_GROUP_DTL, FORECAST_INFO_SPEC )
            SELECT '2' AS DATA_TYPE, DATA_SEQ, DIVISION_ID, VERSION_NO, CUTOFF_TYPE, CUTOFF_YYYYMMDD, DEPARTMENT_ID, DEPT_ID, DEPARTMENT_NAME
                            , DEPT_NAME, END_CUST_REPORT, CUST_REPORT, PRODUCT_GROUP, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE
                            , INCOTERMS, PLANT_SITE_ID, CURRENCY, COMPANY_ID, YYYYMMDD, MEASURE, SOLDTO_CODE, SOLDTO_CUST_REPORT, PRODUCT_DETAILS
                            , CELL_MODEL_INFO, BIZ_TYPE, APPLICATION_GR, APPLICATION, COUNTRY_CODE, PROJECT_NAME, QTY, CREATED_BY, CREATION_DATE
                            , LAST_UPDATED_BY, LAST_UPDATE_DATE, ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7
                            , ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10, NICK_NAME, ITEM_USE, SoldTo_COUNTRY, ShipTo_COUNTRY, OWNER_NAME
                            , COUNTRY_KR_NAME, COMPANY_NAME, CUST_GROUP_DTL, FORECAST_INFO_SPEC
            FROM DM_PLN_SALES_ETC_REPORT_C A
            WHERE A.DIVISION_ID = @V_DIVISION_ID
			    AND A.VERSION_NO = @V_VERSION_NO
                
        END
        ELSE    -- 자동차 ESS
        BEGIN
		    INSERT INTO @TBL (
			    DATA_TYPE, DATA_SEQ, DIVISION_ID, VERSION_NO, CUTOFF_TYPE, CUTOFF_YYYYMMDD, DEPARTMENT_ID, DEPT_ID
			    , DEPARTMENT_NAME, DEPT_NAME, END_CUST_REPORT, CUST_REPORT, PRODUCT_GROUP, PROJECT_CODE
			    , SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, CURRENCY, COMPANY_ID, YYYYMMDD, MEASURE
			    , NICK_NAME, BIZ_TYPE, PROJECT_NAME, FCST_TYPE_NAME
			    , QTY, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE
			    , ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10
			    , CELL_PACK, MODULE_PACK, MODEL_TYPE
			    , SOLDTO_CODE, SOLDTO_COUNTRY, SHIPTO_COUNTRY, CELL_NAME, ITEM_USE, COUNTRY_CODE
			    , APPLICATION_GR, APPLICATION, CELL_MODEL_INFO, PRODUCT_DETAILS, SOLDTO_CUST_REPORT
		    )
		    SELECT A.DATA_TYPE, 1 AS DATA_SEQ, A.DIVISION_ID, A.VERSION_NO, A.CUTOFF_TYPE, A.CUTOFF_YYYYMMDD, A.DEPARTMENT_ID, A.DEPT_ID
			    , A.DEPARTMENT_NAME, A.DEPT_NAME
			    , CASE WHEN A.DIVISION_ID ='40' THEN A.END_CUST_REPORT
				    ELSE ST.END_CUSTOMER
				    END AS END_CUSTOMER
			    , A.CUST_REPORT
			    , CASE WHEN A.DIVISION_ID = '40' THEN A.PRODUCT_GROUP
				       WHEN A.DIVISION_ID = '81' THEN PJT.PRODUCT_GROUP_NAME
				       END AS PRODUCT_GROUP
			    , CASE WHEN LEN(A.PROJECT_CODE) > 1 THEN A.PROJECT_CODE ELSE '' END
			    , A.SCM_SITE_ID, A.ITEM_ID, A.DOM_EXP, A.FCST_TYPE, A.INCOTERMS, A.PLANT_SITE_ID, A.CURRENCY, A.COMPANY_ID, A.YYYYMMDD, A.MEASURE
			    , SINGLE.NICK_NAME
			    , CASE WHEN A.Division_id = '40' THEN SINGLE.FORECAST_INFO_BIZ_TYPE 
					    WHEN A.Division_id = '81' THEN CASE WHEN SINGLE.ITEM_CLASS_NAME LIKE '%CELL%' THEN 'Cell'
													       WHEN SINGLE.ITEM_CLASS_NAME LIKE '%PACK%' THEN 'Pack'
													       WHEN SINGLE.ITEM_CLASS_NAME LIKE '%MODULE%' THEN 'Module'
													       END 
					    END
				       AS BIZ_TYPE
			    , PJT.PROJECT_NAME, LK1.SEGMENT2 AS FCST_TYPE_NAME
			    , A.QTY, A.CREATED_BY, A.CREATION_DATE, A.LAST_UPDATED_BY, A.LAST_UPDATE_DATE
			    , A.ATTRIBUTE1, A.ATTRIBUTE2, A.ATTRIBUTE3, A.ATTRIBUTE4, A.ATTRIBUTE5, A.ATTRIBUTE6, A.ATTRIBUTE7, A.ATTRIBUTE8, A.ATTRIBUTE9, A.ATTRIBUTE10
			    , SI.CELL_PER_CAR AS CELL_PACK
			    , CASE WHEN SI.CELL_PER_MODULE <> 0 THEN SI.CELL_PER_CAR / SI.CELL_PER_MODULE ELSE NULL END AS MODULE_PACK
			    , CASE WHEN SINGLE.ITEM_CLASS_NAME LIKE '%CELL%' THEN 'Cell'
				       WHEN SINGLE.ITEM_CLASS_NAME LIKE '%PACK%' THEN 'Pack'
				       WHEN SINGLE.ITEM_CLASS_NAME LIKE '%MODULE%' THEN 'Module'
				       END AS MODEL_TYPE
			    , CS.SOLDTO_CODE
			    , ISNULL(LEFT(CS.SOLDTO_CODE, 2),'') AS SOLDTO_COUNTRY
			    , ISNULL(LEFT(CS.SHIPTO_CODE, 2),'') AS SHIPTO_COUNTRY
			    , ISNULL(SI.ATTRIBUTE9,'') AS CELL_NAME
			    -- C20200909-000188
			    , CASE WHEN LK2.SEGMENT1 IS NOT NULL THEN LK2.SEGMENT2
					    ELSE ISNULL(LEFT(A.PROJECT_CODE, 1),'') END AS ITEM_USE 
			    , ISNULL(ST.COUNTRY,'') AS COUNTRY
			    , ISNULL(SI.APPLICATION,'') AS APPLICATION
			    , ISNULL(SI.REPORT_GROUP1, '') AS APPLICATION_GR
			    , ISNULL(SI.REPORT_GROUP6, '') AS CELL_MODEL_INFO
			    , ISNULL(SI.REPORT_GROUP4, '') AS PRODUCT_DETAILS
			    , ISNULL(SI.ATTRIBUTE1, '') AS SOLDTO_CUST_REPORT
		    FROM DM_PLN_SALES_PLAN_REPORT_C A
		    LEFT OUTER JOIN SCM_MST_SITE ST (NOLOCK) ON A.SCM_SITE_ID = ST.SCM_SITE_ID AND A.DIVISION_ID = ST.DIVISION_ID
		    LEFT OUTER JOIN @PJT PJT  ON A.DIVISION_ID= PJT.DIVISION_ID AND A.PROJECT_CODE = PJT.PROJECT_CODE
		    LEFT JOIN SCM_MST_SITE_ITEM AS SI WITH(NOLOCK) ON A.DIVISION_ID = SI.DIVISION_ID AND A.PROJECT_CODE = SI.PROJECT_CODE AND A.SCM_SITE_ID = SI.SCM_SITE_ID AND A.ITEM_ID = SI.ITEM_ID
		    LEFT JOIN DM_MST_ITEM_SINGLE_V AS SINGLE WITH(NOLOCK) ON SI.DIVISION_ID = SINGLE.DIVISION_ID AND SI.ITEM_ID = SINGLE.ITEM_ID
		    LEFT OUTER JOIN SCM_ADM_LOOKUP_MASTER_DETAIL LK1 WITH(NOLOCK) ON A.FCST_TYPE = LK1.SEGMENT1 AND LK1.LOOKUP_TYPE = 'SALES_TYPE_CODE' 
		    LEFT OUTER JOIN SCM_MST_SITE_CUSTOMER CS (NOLOCK) ON A.DIVISION_ID = CS.DIVISION_ID AND A.SCM_SITE_ID = CS.SCM_SITE_ID AND CS.REP_YN = N'Y' AND CS.VALID_YN = N'Y'
		    LEFT OUTER JOIN SCM_ADM_LOOKUP_MASTER_DETAIL LK2 WITH(NOLOCK) ON A.PROJECT_CODE = LK2.SEGMENT1 AND LK2.LOOKUP_TYPE = 'DM_ITEM_USE_EX' 
		    WHERE A.DIVISION_ID = @V_DIVISION_ID
			    AND A.VERSION_NO = @V_VERSION_NO

		    INSERT INTO @TBL (
			    DATA_TYPE, DATA_SEQ, DIVISION_ID, VERSION_NO, CUTOFF_TYPE, CUTOFF_YYYYMMDD, DEPARTMENT_ID, DEPT_ID
			    , DEPARTMENT_NAME, DEPT_NAME, END_CUST_REPORT, CUST_REPORT, PRODUCT_GROUP, PROJECT_CODE
			    , SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, CURRENCY, COMPANY_ID, YYYYMMDD, MEASURE
			    , SOLDTO_CODE, SOLDTO_CUST_REPORT, PRODUCT_DETAILS, CELL_MODEL_INFO, BIZ_TYPE, APPLICATION_GR, APPLICATION, COUNTRY_CODE, PROJECT_NAME
			    , QTY, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE
			    , ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10
		    )
		    SELECT '2' AS DATA_TYPE, A.DATA_SEQ, A.DIVISION_ID, A.VERSION_NO, A.CUTOFF_TYPE, A.CUTOFF_YYYYMMDD, A.DEPARTMENT_ID, A.DEPT_ID
			    , '' AS DEPARTMENT_NAME, '' AS DEPT_NAME
			    , ISNULL( CASE WHEN A.DIVISION_ID = '40' THEN A.END_CUST_REPORT ELSE A.END_CUSTOMER END,'') AS END_CUST_REPORT
			    , ISNULL(A.CUST_REPORT,'') AS CUST_REPORT
			    , ISNULL(CASE WHEN A.DIVISION_ID = '40' THEN A.PRODUCT_GROUP
					       WHEN A.DIVISION_ID = '81' THEN PJT.PRODUCT_GROUP_NAME
					       END, '') AS PRODUCT_GROUP

			    , ISNULL(A.PROJECT_CODE,'') AS PROJECT_CODE
			    , ISNULL(A.SCM_SITE_ID,'') AS SCM_SITE_ID, ISNULL(A.ITEM_ID,'') AS ITEM_ID, A.DOM_EXP, A.FCST_TYPE, A.INCOTERMS, A.PLANT_SITE_ID
			    , ISNULL(A.CURRENCY,'') AS CURRENCY, ISNULL(A.COMPANY_ID,'') AS COMPANY_ID, A.YYYYMMDD, A.MEASURE
			    , A.SOLDTO_CODE, A.SOLDTO_CUST_REPORT, A.PRODUCT_DETAILS, A.CELL_MODEL_INFO
			    , A.BIZ_TYPE
			    , A.APPLICATION_GR, A.APPLICATION, A.COUNTRY_CODE, ISNULL(LK3.SEGMENT3, PJT.PROJECT_NAME ) AS PROJECT_NAME
			    , A.QTY, A.CREATED_BY, A.CREATION_DATE, A.LAST_UPDATED_BY, A.LAST_UPDATE_DATE
			    , A.ATTRIBUTE1, A.ATTRIBUTE2, A.ATTRIBUTE3, A.ATTRIBUTE4, A.ATTRIBUTE5, A.ATTRIBUTE6, A.ATTRIBUTE7, A.ATTRIBUTE8, A.ATTRIBUTE9, A.ATTRIBUTE10
		    FROM DM_PLN_SALES_ETC_REPORT_C A
		    LEFT OUTER JOIN @PJT PJT ON A.DIVISION_ID= PJT.DIVISION_ID AND A.PROJECT_CODE = PJT.PROJECT_CODE
		    LEFT OUTER JOIN SCM_ADM_LOOKUP_MASTER_DETAIL LK3 (NOLOCK) ON A.PROJECT_CODE = LK3.SEGMENT2 AND LK3.LOOKUP_TYPE = 'DM_ETC_PROJECT' AND LK3.SEGMENT1 = A.DIVISION_ID
		    WHERE A.DIVISION_ID = @V_DIVISION_ID
			    AND A.VERSION_NO = @V_VERSION_NO
        END

		SET @V_I = @V_I + 1
	END

	RETURN;
END







