CREATE PROCEDURE [dbo].[SCP0130_GET_SEARCH_INFO]
	 @p_division_id		NVARCHAR(MAX)
	,@p_site_id         NVARCHAR(MAX)
AS
BEGIN
	
    SET NOCOUNT ON; 
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED
 
 	DECLARE @v_division_id   NVARCHAR(200)   = @p_division_id
	DECLARE @v_site_id       NVARCHAR(200)   = @p_site_id

	--1. Plan Group 정보 
	select OPMZ_PLAN_GR_ID	AS CODE
		, OPMZ_PLAN_GR_NAME	AS NAME
		, DIVISION_ID
	from SCP_OPMZ_PLAN_GR_M with(nolock)
	WHERE 1=1
	 AND VALID_YN='Y'
	ORDER BY OPMZ_PLAN_GR_NAME


	--2. 재고 SCM SITE ID 
	   SELECT DIVISION_ID
			 ,CODE
			 ,NAME
		FROM (
 				SELECT DISTINCT A.DIVISION_ID
					, SCM_SITE_ID AS CODE 
					, SCM_SITE_ID AS NAME
					, SITE_TYPE
				FROM   SCM_MST_SITE A WITH(NOLOCK) 
				WHERE  1 = 1
				AND A.SITE_TYPE = 'SALES'	
				AND A.DIVISION_ID != '40'
				AND A.VALID_YN = 'Y'	
				UNION ALL
				SELECT DISTINCT A.DIVISION_ID
					, A.SCM_SITE_ID AS CODE 
					, A.SCM_SITE_ID AS NAME
					, A.SITE_TYPE
				FROM   SCM_MST_SITE AS A WITH(NOLOCK) 
				LEFT JOIN SCM_MST_SITE_ITEM AS B WITH(NOLOCK) 
					ON A.DIVISION_ID = B.DIVISION_ID AND A.SCM_SITE_ID = B.SCM_SITE_ID
				WHERE  1 = 1
				AND A.SITE_TYPE = 'SALES'
				AND  A.DIVISION_ID = '40'
				AND A.VALID_YN = 'Y'
				UNION ALL
				SELECT DISTINCT A.DIVISION_ID
					, SCM_SITE_ID AS CODE 
					, SCM_SITE_ID AS NAME
					, A.SITE_TYPE
				FROM   [dbo].[SCM_MST_SITE] A
				WHERE  1 = 1
				AND    A.SITE_TYPE = 'PLANT'
			   ) X
		ORDER BY SITE_TYPE, NAME  -- A.DIVISION_ID

	--SELECT DISTINCT A.DIVISION_ID
	--	, SCM_SITE_ID AS CODE 
	--	, SCM_SITE_ID AS NAME
	--FROM   SCM_MST_SITE A WITH(NOLOCK) 
	--WHERE  1 = 1
	--AND A.SITE_TYPE = 'SALES'	
	--AND A.DIVISION_ID != '40'
	--AND A.VALID_YN = 'Y'	
	--UNION ALL
	--SELECT DISTINCT A.DIVISION_ID
	--	, A.SCM_SITE_ID AS CODE 
	--	, A.SCM_SITE_ID AS NAME
	--FROM   SCM_MST_SITE AS A WITH(NOLOCK) 
	--LEFT JOIN SCM_MST_SITE_ITEM AS B WITH(NOLOCK) 
	--	ON A.DIVISION_ID = B.DIVISION_ID AND A.SCM_SITE_ID = B.SCM_SITE_ID
	--WHERE  1 = 1
	--AND A.SITE_TYPE = 'SALES'
	--AND  A.DIVISION_ID = '40'
	--AND A.VALID_YN = 'Y'
	--UNION ALL
	--SELECT DISTINCT A.DIVISION_ID
	--	, SCM_SITE_ID AS CODE 
	--	, SCM_SITE_ID AS NAME
	--FROM   [dbo].[SCM_MST_SITE] A
	--WHERE  1 = 1
	--AND    A.SITE_TYPE = 'PLANT'
	--ORDER BY A.DIVISION_ID
	
  

   -- 3. STAGE 최적화 
   SELECT M.SEGMENT1  AS DIVISION_ID
         ,M.SEGMENT3 AS CODE
         ,M.ATTRIBUTE1 AS NAME
   FROM dbo.SCM_ADM_LOOKUP_MASTER_DETAIL M WITH(NOLOCK)
   WHERE M.LOOKUP_TYPE LIKE 'OPMZ_STAGE_CD'
   AND   M.VALID_YN='Y'
	

	-- 4. TYPE (COVER_DAY_TYPE : MIN/MAX) 호출
	SELECT M.SEGMENT1 AS CODE
		,M.SEGMENT2 AS NAME
	FROM   dbo.SCM_ADM_LOOKUP_MASTER_DETAIL M WITH(NOLOCK)
	WHERE  LOOKUP_TYPE = 	 'COVER_DAY_TYPE'
    ORDER BY M.DISPLAY_SEQ
  
    -- 5. valid YN
    SELECT M.SEGMENT1 AS CODE
		,M.SEGMENT2 AS NAME
	FROM   dbo.SCM_ADM_LOOKUP_MASTER_DETAIL M WITH(NOLOCK)
	WHERE  LOOKUP_TYPE = 	'DM_YN' -- 'DEFAULT_FLAG'
    ORDER BY M.DISPLAY_SEQ



	-- 6. MATERIAL ID/ Vitual BOM에서 생성한 Child ID
	SELECT DISTINCT 
	       M.ITEM_ID_CHILD AS CODE
	      ,M.ITEM_ID_CHILD AS NAME
		  ,M.DIVISION_ID   AS DIVISION_ID
		  ,M.OPMZ_PLAN_GR_ID
	      ,M.PLANT_SITE_ID
		  ,M.TO_YYYYMMDD
	FROM SCP_OPMZ_VIRTUAL_BOM  M WITH(NOLOCK)
    WHERE 1=1
	  AND   M.VALID_YN ='Y'
	ORDER BY M.ITEM_ID_CHILD

	-- 7.Item정보 Operation Group 조회용
	SELECT T.DIVISION_ID
	      ,T.ITEM_ID
		  ,T.OPERATION_GROUP 
    FROM SCP_MST_FINAL_ITEM T WITH(NOLOCK)


	-- 8.PLANT_SITE_BY_DIVISION
	SELECT DISTINCT A.DIVISION_ID
		, a.SCM_SITE_ID AS CODE 
		, a.SCM_SITE_ID AS NAME
		, B.OPMZ_PLAN_GR_ID
	FROM   [dbo].[SCM_MST_SITE] A  WITH(NOLOCK)
	LEFT  OUTER JOIN SCP_OPMZ_VIRTUAL_BOM B
	    ON A.SCM_SITE_ID = B.PLANT_SITE_ID
	WHERE  1 = 1
	AND    A.SITE_TYPE = 'PLANT'
	AND    A.VALID_YN  = 'Y'
	ORDER BY A.DIVISION_ID, a.SCM_SITE_ID

	--SELECT DISTINCT A.DIVISION_ID
	--	, SCM_SITE_ID AS CODE 
	--	, SCM_SITE_ID AS NAME
	--FROM   [dbo].[SCM_MST_SITE] A  WITH(NOLOCK)
	--WHERE  1 = 1
	--AND    A.SITE_TYPE = 'PLANT'
	--AND    A.VALID_YN  = 'Y'
	--ORDER BY A.DIVISION_ID
    
	-- 9.vIRTUAL등록된 PLANG Group
SELECT DISTINCT
         a.OPMZ_PLAN_GR_ID	  AS CODE
		,b.OPMZ_PLAN_GR_NAME  AS NAME
		,a.DIVISION_ID
    FROM DBO.SCP_OPMZ_VIRTUAL_BOM a  with(nolock)
	    ,SCP_OPMZ_PLAN_GR_M  b with(nolock)
	WHERE a.OPMZ_PLAN_GR_ID = b.OPMZ_PLAN_GR_ID
	  AND a.DIVISION_ID = b.DIVISION_ID
	ORDER BY B.OPMZ_PLAN_GR_NAME

END

