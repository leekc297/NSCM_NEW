
CREATE FUNCTION [dbo].[FN_GET_PIVOT_STRING]
(
@T TAB_PIVOT_STRING READONLY 
, @p_delim			VARCHAR(1)
)
RETURNS NVARCHAR(MAX)
AS
BEGIN
	DECLARE @List TABLE
	(
	KEY_VAL NVARCHAR(MAX)
	, SEQ INT IDENTITY(0,1)
	)

	INSERT INTO @LIST ( KEY_VAL )
	SELECT KEY_VAL FROM @T

	DECLARE @CNT INT, @I INT, @RETVAL NVARCHAR(MAX)

	SELECT @CNT = COUNT(*), @I = 0, @RETVAL = ''
	FROM @LIST

	WHILE ( @I < @CNT )
	BEGIN
		SELECT @RETVAL = @RETVAL + CASE WHEN @I > 0 THEN @p_delim ELSE '' END + RTRIM(KEY_VAL)
		FROM @LIST
		WHERE SEQ = @I

		SET @I = @I + 1
	END

	--SET @RETVAL = REPLACE(@RETVAL, '|^', '|')
	RETURN @RETVAL

END

