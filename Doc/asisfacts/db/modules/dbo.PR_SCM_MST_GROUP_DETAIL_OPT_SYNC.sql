/*
 *===================================================================================================
 * PROGRAM ID   : PR_SCM_MST_GROUP_DETAIL_OPT_SYNC
 * DESCRIPTION  : 최적화 룩업 DEMAND GROUP 룩업(SCP_OPT_ENG_CONST_DEMAND_GROUP) 을 DEMAND GROUP MASTER UI (상세) 데이터로 동기화
 * PROGRAM HISTORY
 *===================================================================================================
 *   DATE       IN CHARGE		DESCRIPTION
 *	2026.09.01	YMH				E20260828-002065 Demand Grouping 데이터 동기화 요청 INIT
 *===================================================================================================
 *===================================================================================================     
*/
CREATE PROC [dbo].[PR_SCM_MST_GROUP_DETAIL_OPT_SYNC]
AS
	SET NOCOUNT ON; 
    SET TRANSACTION ISOLATION LEVEL READ COMMITTED;
    SET XACT_ABORT ON;

	-- LOG 용 변수 설정
    DECLARE @V_PROGRAM_NAME		NVARCHAR(150) = 'PR_SCM_MST_GROUP_DETAIL_OPT_SYNC';
    DECLARE @V_LOG_TYPE			NVARCHAR(30); -- START/END/ERROR/...
    DECLARE @N_LOG_COUNT		INTEGER = 0;
    DECLARE @V_LOG_MESSAGE		NVARCHAR(1000);
    DECLARE @V_DESCRIPTION		NVARCHAR(500);
    DECLARE @D_EVENT_DATE		DATETIME;
    DECLARE @N_DELETE_COUNT		INTEGER = 0;
    DECLARE @N_INSERT_COUNT     INTEGER = 0;

	-- 시작 LOG
	SET @V_LOG_TYPE = 'START';
	SET @V_LOG_MESSAGE = '########## START OF PROCEDURE ##########';
	SET @V_DESCRIPTION = '';
	SET @D_EVENT_DATE = SYSDATETIME();
	EXEC  PR_SCM_SYS_LOG_BATCH @V_PROGRAM_NAME, @V_LOG_TYPE, @N_LOG_COUNT, @V_LOG_MESSAGE, @V_DESCRIPTION, @D_EVENT_DATE;

	BEGIN TRY

		-- Master 데이터 중 룩업과 매핑되지 않는 데이터는 VALID_YN = 'N' 처리
		UPDATE GD
			SET LAST_UPDATED_BY = @V_PROGRAM_NAME
				,LAST_UPDATE_DATE = GETDATE()
				,VALID_YN = 'N'
				,GROUP_ID = NULL
		FROM SCP_MST_ITEM_GROUP_DETAIL AS GD WITH(NOLOCK)
			JOIN SCP_MST_ITEM_GROUP AS IG WITH(NOLOCK)
			ON	GD.DIVISION_ID = IG.DIVISION_ID
			AND GD.GROUP_ID = IG.GROUP_ID
		WHERE 1=1
		AND GD.DIVISION_ID	= '82'
		AND	GD.ITEM_ID		LIKE 'ET%'
		AND GD.VALID_YN		= 'Y'
		AND IG.VALID_YN		= 'Y'
		-- 룩업에 프로젝트 코드가 등록된것이 대상.
		AND EXISTS
		(
			SELECT * FROM 
			(
				SELECT
						A.SEGMENT2		AS DIVISION_ID
					, A.SEGMENT3		AS ITEM_ID
					, A.SEGMENT4		AS GROUP_NM
					, A.SEGMENT5		AS PROJECT_CODE
					, B.GROUP_ID		AS GROUP_ID
					, A.VALID_YN		AS VALID_YN
				FROM SCP_OPMZ_LOOKUP_MASTER_DETAIL AS A WITH(NOLOCK)
					JOIN SCP_MST_ITEM_GROUP AS B
					ON	A.SEGMENT2		= B.DIVISION_ID
					AND A.SEGMENT4		= B.GROUP_NAME
				WHERE	A.LOOKUP_TYPE = 'SCP_OPT_ENG_CONST_DEMAND_GROUP' 
				AND		A.SEGMENT2	= '82'
				AND		A.SEGMENT3	LIKE 'ET%'
			) AS C
			WHERE C.PROJECT_CODE = GD.PROJECT_CODE
		)

		AND NOT EXISTS
		(
			SELECT * FROM 
			(
				SELECT
					  A.SEGMENT2		AS DIVISION_ID
					, A.SEGMENT3		AS ITEM_ID
					, A.SEGMENT4		AS GROUP_NM
					, A.SEGMENT5		AS PROJECT_CODE
					, B.GROUP_ID		AS GROUP_ID
					, A.VALID_YN		AS VALID_YN
				FROM SCP_OPMZ_LOOKUP_MASTER_DETAIL AS A WITH(NOLOCK)
					JOIN SCP_MST_ITEM_GROUP AS B
					ON	A.SEGMENT2		= B.DIVISION_ID
					AND A.SEGMENT4		= B.GROUP_NAME
				WHERE	A.LOOKUP_TYPE = 'SCP_OPT_ENG_CONST_DEMAND_GROUP' 
				AND		A.SEGMENT2	= '82'
				AND		A.SEGMENT3	LIKE 'ET%'
			) AS B
			WHERE	GD.DIVISION_ID	= B.DIVISION_ID
			AND		GD.ITEM_ID		= B.ITEM_ID
			AND		IG.GROUP_NAME	= B.GROUP_NM
			AND		GD.PROJECT_CODE	= B.PROJECT_CODE
		)

		

		MERGE INTO SCP_MST_ITEM_GROUP_DETAIL AS T
		USING 
		(
			SELECT
				  A.SEGMENT2		AS DIVISION_ID
				, A.SEGMENT3		AS ITEM_ID
				, A.SEGMENT4		AS GROUP_NM
				, A.SEGMENT5		AS PROJECT_CODE
				, B.GROUP_ID		AS GROUP_ID
				, A.VALID_YN		AS VALID_YN
			FROM SCP_OPMZ_LOOKUP_MASTER_DETAIL AS A WITH(NOLOCK)
				JOIN SCP_MST_ITEM_GROUP AS B
				ON	A.SEGMENT2		= B.DIVISION_ID
				AND A.SEGMENT4		= B.GROUP_NAME
			WHERE	A.LOOKUP_TYPE = 'SCP_OPT_ENG_CONST_DEMAND_GROUP' 
			AND		A.SEGMENT2	= '82'
			AND		A.SEGMENT3	LIKE 'ET%'
			-- AND		A.VALID_YN	= 'Y'		
		) AS S
		ON	T.DIVISION_ID	= S.DIVISION_ID
		AND T.PROJECT_CODE	= S.PROJECT_CODE
		AND T.ITEM_ID		= S.ITEM_ID
		WHEN MATCHED THEN
			UPDATE 
				SET   T.GROUP_ID			= CASE WHEN S.VALID_YN = 'N' THEN NULL ELSE S.GROUP_ID END -- VALID N처리도는것들은 GROUP지움.
					, T.VALID_YN			= S.VALID_YN
					, T.LAST_UPDATED_BY		= @V_PROGRAM_NAME
					, T.LAST_UPDATE_DATE	= GETDATE()
		WHEN NOT MATCHED THEN
			INSERT (DIVISION_ID,PROJECT_CODE,ITEM_ID,GROUP_ID,VALID_YN,CREATED_BY,CREATION_DATE,LAST_UPDATED_BY,LAST_UPDATE_DATE) -- VALID N처리도는것들은 GROUP지움.
			VALUES (S.DIVISION_ID,S.PROJECT_CODE,S.ITEM_ID,CASE WHEN S.VALID_YN = 'N' THEN NULL ELSE S.GROUP_ID END,S.VALID_YN ,@V_PROGRAM_NAME,GETDATE(),@V_PROGRAM_NAME,GETDATE())
		;
		
	END TRY
	BEGIN CATCH
	    		
		-- ERROR LOG
		SET @V_LOG_TYPE = 'ERROR';
		SET @V_LOG_MESSAGE = CAST(ERROR_MESSAGE() AS NVARCHAR(1000));
		SET @V_DESCRIPTION = 'ERROR_LINE : ' + STR(ERROR_LINE());
		SET @D_EVENT_DATE = SYSDATETIME();

		EXEC PR_SCM_SYS_LOG_BATCH @V_PROGRAM_NAME, @V_LOG_TYPE, @N_LOG_COUNT, @V_LOG_MESSAGE, @V_DESCRIPTION, @D_EVENT_DATE;
		
    END CATCH;

	-- 시작 LOG
	SET @V_LOG_TYPE = 'END';
	SET @V_LOG_MESSAGE = '########## END OF PROCEDURE ##########';
	SET @V_DESCRIPTION = '';
	SET @D_EVENT_DATE = SYSDATETIME();
	EXEC  PR_SCM_SYS_LOG_BATCH @V_PROGRAM_NAME, @V_LOG_TYPE, @N_LOG_COUNT, @V_LOG_MESSAGE, @V_DESCRIPTION, @D_EVENT_DATE;

