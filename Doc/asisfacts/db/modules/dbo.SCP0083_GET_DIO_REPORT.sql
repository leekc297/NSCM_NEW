 * 2022/05/09   vadabi3			ATTRIBUTE1 = Safety Stock > 내부 (=SAFETY_STOCK_PIN_HOUSE)
 * 2022/06/10   vadabi3			VERSION 추가
 * 2022/10/24   vadabi3			SHIPMENT SUM 컬럼 추가
 */

CREATE PROCEDURE [dbo].[SCP0083_GET_DIO_REPORT]
--chaan  @p_division_id            NVARCHAR(5),
    @p_division_id          NVARCHAR(30),--chaan
	@p_plan_start_yyyymmdd	NVARCHAR(8),
	@p_plan_type			NVARCHAR(5),
	@p_seq					NVARCHAR(2),
 	@p_ver					INT,
	@p_user_id				NVARCHAR(30),
	@debug_mode				NVARCHAR(1) = 'T'

AS
BEGIN
    
	SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;
	SET NOCOUNT ON; 

	DECLARE @mEXEC NVARCHAR(MAX);
	

		WITH AA AS (		
			
			SELECT 
				RTRIM(DIVISION_ID) AS DIVISION_ID
				, PLAN_START_YYYYMMDD
				, RTRIM(PLAN_TYPE) AS PLAN_TYPE
				, SEQ
				, VER
				, RTRIM(NICK_NAME) AS NICK_NAME
				, RTRIM(FROM_SITE) AS FROM_SITE
				, ISNULL(CUTOFF_FLAG, 'N') AS VERSION
				, FROM_SITE_DESCRIPTION
				, END_CUSTOMER -- TO_SITE
				, TO_SITE
				, PRODUCTION_TYPE
				, EXTRA_SPEC
				, RTRIM(ITEM_ID) AS ITEM_ID
				, CELL_ITEM_ID
				, RTRIM(BIZ_TYPE) AS BIZ_TYPE
				, INCOTERMS
				, ISNULL(CELL_AGING_LT, 0) AS CELL_AGING_LT
				, ISNULL(CELL_EOL_SHIPPING_LOT, 0) AS CELL_EOL_SHIPPING_LOT
				--, 0 AS CELL_SUM
				, ISNULL(PACK_INCOMMING, 0) AS PACK_INCOMMING
				, ISNULL(PACK_OPERATION_LT, 0) AS PACK_OPERATION_LT
				--, 0 AS PACK_SUM
				, ISNULL(SHIPMENT_CELL_INSPECTION_LOAD, 0) AS SHIPMENT_CELL_INSPECTION_LOAD
				, ISNULL(SHIPMENT_CELL_INSPECTION_WAITING, 0) AS SHIPMENT_CELL_INSPECTION_WAITING
				--, 0 AS SHIPMENT_CELL_SUM
				, ISNULL(SHIPMENT_PACK_INSPECTION_LOAD, 0) AS SHIPMENT_PACK_INSPECTION_LOAD
				, ISNULL(SHIPMENT_PACK_INSPECTION_WAITING, 0) AS SHIPMENT_PACK_INSPECTION_WAITING
				--, 0 AS SHIPMENT_PACK_SUM
				--, 0 AS SHIPMENT_INSPECTION_LOAD_SUM
				--, 0 AS SHIPMENT_INSPECTION_WAITING_SUM
				--, 0 AS SHIPMENT_SUM
				, ISNULL(DNI_CELL_DEPARTURE_DAYS, 0) AS DNI_CELL_DEPARTURE_DAYS
				, ISNULL(DNI_CELL_DEPARTURE_INLAND, 0) AS DNI_CELL_DEPARTURE_INLAND
				, ISNULL(DNI_CELL_WAITING_FOR_SHIPPING, 0) AS DNI_CELL_WAITING_FOR_SHIPPING
				, ISNULL(DNI_CELL_VOYAGE, 0) AS DNI_CELL_VOYAGE
				, ISNULL(DNI_CELL_LAY_OFF_CUSTOMS_CLEARANCE, 0) AS DNI_CELL_LAY_OFF_CUSTOMS_CLEARANCE
				, ISNULL(DNI_CELL_ARRIVAL_INLAND, 0) AS DNI_CELL_ARRIVAL_INLAND
				--, 0 AS DNI_CELL_SUM
				, ISNULL(DNI_PACK_DEPARTURE_DAYS, 0) AS DNI_PACK_DEPARTURE_DAYS
				, ISNULL(DNI_PACK_DEPARTURE_INLAND, 0) AS DNI_PACK_DEPARTURE_INLAND
				, ISNULL(DNI_PACK_WAITING_FOR_SHIPPING, 0) AS DNI_PACK_WAITING_FOR_SHIPPING
				, ISNULL(DNI_PACK_VOYAGE, 0) AS DNI_PACK_VOYAGE
				, ISNULL(DNI_PACK_LAY_OFF_CUSTOMS_CLEARANCE, 0) AS DNI_PACK_LAY_OFF_CUSTOMS_CLEARANCE
				, ISNULL(DNI_PACK_ARRIVAL_INLAND, 0) AS DNI_PACK_ARRIVAL_INLAND
				--, 0 AS DNI_PACK_SUM
				--, 0 AS DNI_DEPARTURE_DAYS_SUM
				--, 0 AS DNI_DEPARTURE_INLAND_SUM
				--, 0 AS DNI_WAITING_FOR_SHIPPING_SUM
				--, 0 AS DNI_VOYAGE_SUM
				--, 0 AS DNI_LAY_OFF_CUSTOMS_CLEARANCE_SUM
				--, 0 AS DNI_ARRIVAL_INLAND_SUM
				--, 0 AS DNI_SUM
				, ISNULL(PRE_INSPECTION_CELL, 0) AS PRE_INSPECTION_CELL
				, ISNULL(PRE_INSPECTION_PACK, 0) AS PRE_INSPECTION_PACK
				--, 0 AS PRE_INSPECTION_SUM
				, ISNULL(VMI_CELL, 0) AS VMI_CELL
				, ISNULL(VMI_PACK, 0) AS VMI_PACK
				--, 0 AS VMI_SUM
				, ISNULL(FOREIGN_CORP, 0) AS FOREIGN_CORP
				, ISNULL(RACK_BIZ, 0) AS RACK_BIZ
				, ISNULL(DEPARTURE_INTRANSIT_VMI, 0) AS DEPARTURE_INTRANSIT_VMI_AUTO
				, ISNULL(SAFETY_STOCK_CELL, 0) AS SAFETY_STOCK_CELL
				, ISNULL(SAFETY_STOCK_PACK, 0) AS SAFETY_STOCK_PACK
				--, 0 AS SAFETY_STOCK_SUM
				, ISNULL(OTHER_STOCK_CELL, 0) AS OTHER_STOCK_CELL
				, ISNULL(OTHER_STOCK_PACK, 0) AS OTHER_STOCK_PACK
				--, 0 AS OTHER_STOCK_SUM
				, ISNULL(PRODUCTION_CYCLE_CELL, 0) AS PRODUCTION_CYCLE_CELL
				, ISNULL(PRODUCTION_CYCLE_PACK, 0) AS PRODUCTION_CYCLE_PACK
				--, 0 AS PRODUCTION_CYCLE_SUM
				, ISNULL(STANDARD_DIO, 0) AS STANDARD_DIO_AUTO
				, ISNULL(ASSEMBLY_QTY, 0) AS ASSEMBLY_QTY
				, ISNULL(ASSEMBLY_TYPE_RATIO, 0) AS ASSEMBLY_TYPE_RATIO
				, ISNULL(ASSEMBLY_TOTAL_RATIO, 0) AS ASSEMBLY_TOTAL_RATIO
				, ISNULL(WEIGHT_DIO, 0) AS WEIGHT_DIO_AUTO
				--, 0 AS OP_LT_TOTAL_AUTO
				--, 0 AS CYCLE_TOTAL_AUTO
				--, 0 AS INTRANSIT_TOTAL_AUTO
				--, 0 AS WEIGHT_OPEARTION_TYPE_AUTO
				--, 0 AS WEIGHT_OPEARTION_TOTAL_AUTO
				--, 0 AS WEIGHT_CYCLE_TYPE_AUTO
				--, 0 AS WEIGHT_CYCLE_TOTAL_AUTO
				--, 0 AS WEIGHT_INTRANSIT_TYPE_AUTO
				--, 0 AS WEIGHT_INTRANSIT_TOTAL_AUTO
				, RTRIM(TRANSPORT_MODE_LINE) AS TRANSPORT_MODE_LINE
				, RTRIM(OPERATION_GROUP) AS OPERATION_GROUP
				, RTRIM(PLANT_ID) AS PLANT_ID
				, CONVERT(numeric, ISNULL(ATTRIBUTE1, 0)) AS SAFETY_STOCK_PIN_HOUSE -- 20220509 추가
				, SHIPMENT_CELL_SUM 
				, SHIPMENT_PACK_SUM 
				, SHIPMENT_SUM		 
			FROM SCP_ANL_DIO_REPORT A WITH(NOLOCK)
			WHERE 1=1
			AND A.DIVISION_ID			= @p_division_id
			AND A.PLAN_START_YYYYMMDD	= @p_plan_start_yyyymmdd
			AND A.PLAN_TYPE				= @p_plan_type
			AND A.SEQ					= @p_seq
			AND A.VER					= @p_ver
	
		)
		SELECT 
			DIVISION_ID
			, PLAN_START_YYYYMMDD
			, PLAN_TYPE
			, SEQ
			, VER
			, NICK_NAME
			, FROM_SITE
			, VERSION -- CUTOFF_FLAG // 'N' -> UI 수정 O, 'Y' -> UI 수정 X
			, FROM_SITE_DESCRIPTION
			, END_CUSTOMER -- TO_SITE
			, TO_SITE
			, PRODUCTION_TYPE
			, EXTRA_SPEC
			, ITEM_ID
			, CELL_ITEM_ID
			, BIZ_TYPE
			, INCOTERMS
			, CELL_AGING_LT
			, CELL_EOL_SHIPPING_LOT
			, (CELL_AGING_LT + CELL_EOL_SHIPPING_LOT) AS CELL_SUM
			, PACK_INCOMMING
			, PACK_OPERATION_LT
			, (PACK_INCOMMING + PACK_OPERATION_LT) AS PACK_SUM
			, SHIPMENT_CELL_INSPECTION_LOAD
			, SHIPMENT_CELL_INSPECTION_WAITING
			, CASE WHEN SHIPMENT_CELL_SUM IS NOT NULL THEN SHIPMENT_CELL_SUM
			       ELSE (SHIPMENT_CELL_INSPECTION_LOAD + SHIPMENT_CELL_INSPECTION_WAITING)
				   END AS SHIPMENT_CELL_SUM
			, SHIPMENT_PACK_INSPECTION_LOAD
			, SHIPMENT_PACK_INSPECTION_WAITING
			, CASE WHEN SHIPMENT_PACK_SUM IS NOT NULL THEN SHIPMENT_PACK_SUM
			       ELSE (SHIPMENT_PACK_INSPECTION_LOAD + SHIPMENT_PACK_INSPECTION_WAITING) 
				   END AS SHIPMENT_PACK_SUM
			, (SHIPMENT_CELL_INSPECTION_LOAD + SHIPMENT_PACK_INSPECTION_LOAD) AS SHIPMENT_INSPECTION_LOAD_SUM
			, (SHIPMENT_CELL_INSPECTION_WAITING + SHIPMENT_PACK_INSPECTION_WAITING) AS SHIPMENT_INSPECTION_WAITING_SUM
			, CASE WHEN SHIPMENT_SUM IS NOT NULL THEN SHIPMENT_SUM
			       ELSE (SHIPMENT_CELL_INSPECTION_LOAD + SHIPMENT_CELL_INSPECTION_WAITING + SHIPMENT_PACK_INSPECTION_LOAD + SHIPMENT_PACK_INSPECTION_WAITING)
				   END AS SHIPMENT_SUM
			, DNI_CELL_DEPARTURE_DAYS
			, DNI_CELL_DEPARTURE_INLAND
			, DNI_CELL_WAITING_FOR_SHIPPING
			, DNI_CELL_VOYAGE
			, DNI_CELL_LAY_OFF_CUSTOMS_CLEARANCE
			, DNI_CELL_ARRIVAL_INLAND
			, (DNI_CELL_DEPARTURE_DAYS + DNI_CELL_DEPARTURE_INLAND + DNI_CELL_WAITING_FOR_SHIPPING + DNI_CELL_VOYAGE + DNI_CELL_LAY_OFF_CUSTOMS_CLEARANCE + DNI_CELL_ARRIVAL_INLAND) AS DNI_CELL_SUM
			, DNI_PACK_DEPARTURE_DAYS
			, DNI_PACK_DEPARTURE_INLAND
			, DNI_PACK_WAITING_FOR_SHIPPING
			, DNI_PACK_VOYAGE
			, DNI_PACK_LAY_OFF_CUSTOMS_CLEARANCE
			, DNI_PACK_ARRIVAL_INLAND
			, (DNI_PACK_DEPARTURE_DAYS + DNI_PACK_DEPARTURE_INLAND + DNI_PACK_WAITING_FOR_SHIPPING + DNI_PACK_VOYAGE + DNI_PACK_LAY_OFF_CUSTOMS_CLEARANCE + DNI_PACK_ARRIVAL_INLAND) AS DNI_PACK_SUM
			, (DNI_CELL_DEPARTURE_DAYS + DNI_PACK_DEPARTURE_DAYS) AS DNI_DEPARTURE_DAYS_SUM
			, (DNI_CELL_DEPARTURE_INLAND + DNI_PACK_DEPARTURE_INLAND) AS DNI_DEPARTURE_INLAND_SUM
			, (DNI_CELL_WAITING_FOR_SHIPPING + DNI_PACK_WAITING_FOR_SHIPPING) AS DNI_WAITING_FOR_SHIPPING_SUM
			, (DNI_CELL_VOYAGE + DNI_PACK_VOYAGE) AS DNI_VOYAGE_SUM
			, (DNI_CELL_LAY_OFF_CUSTOMS_CLEARANCE + DNI_PACK_LAY_OFF_CUSTOMS_CLEARANCE) AS DNI_LAY_OFF_CUSTOMS_CLEARANCE_SUM
			, (DNI_CELL_ARRIVAL_INLAND + DNI_PACK_ARRIVAL_INLAND) AS DNI_ARRIVAL_INLAND_SUM
			, (DNI_CELL_DEPARTURE_DAYS + DNI_CELL_DEPARTURE_INLAND + DNI_CELL_WAITING_FOR_SHIPPING + DNI_CELL_VOYAGE + DNI_CELL_LAY_OFF_CUSTOMS_CLEARANCE + DNI_CELL_ARRIVAL_INLAND + DNI_PACK_DEPARTURE_DAYS + DNI_PACK_DEPARTURE_INLAND + DNI_PACK_WAITING_FOR_SHIPPING + DNI_PACK_VOYAGE + DNI_PACK_LAY_OFF_CUSTOMS_CLEARANCE + DNI_PACK_ARRIVAL_INLAND) AS DNI_SUM
			, PRE_INSPECTION_CELL
			, PRE_INSPECTION_PACK
			, (PRE_INSPECTION_CELL + PRE_INSPECTION_PACK) AS PRE_INSPECTION_SUM
			, VMI_CELL
			, VMI_PACK
			, (VMI_CELL + VMI_PACK) AS VMI_SUM
			, FOREIGN_CORP
			, RACK_BIZ
			, DEPARTURE_INTRANSIT_VMI_AUTO
			, SAFETY_STOCK_CELL
			, SAFETY_STOCK_PACK
			, (SAFETY_STOCK_CELL + SAFETY_STOCK_PACK + SAFETY_STOCK_PIN_HOUSE) AS SAFETY_STOCK_SUM
			, OTHER_STOCK_CELL
			, OTHER_STOCK_PACK
			, (OTHER_STOCK_CELL + OTHER_STOCK_PACK) AS OTHER_STOCK_SUM
			, PRODUCTION_CYCLE_CELL
			, PRODUCTION_CYCLE_PACK
			, (PRODUCTION_CYCLE_CELL + PRODUCTION_CYCLE_PACK) AS PRODUCTION_CYCLE_SUM
			, STANDARD_DIO_AUTO
			, ASSEMBLY_QTY
			, ASSEMBLY_TYPE_RATIO
			, ASSEMBLY_TOTAL_RATIO
			, WEIGHT_DIO_AUTO
			, 0.0 AS OP_LT_TOTAL_AUTO
			, 0.0 AS CYCLE_TOTAL_AUTO
			, 0.0 AS INTRANSIT_TOTAL_AUTO
			, 0.0 AS WEIGHT_OPEARTION_TYPE_AUTO
			, 0.0 AS WEIGHT_OPEARTION_TOTAL_AUTO
			, 0.0 AS WEIGHT_CYCLE_TYPE_AUTO
			, 0.0 AS WEIGHT_CYCLE_TOTAL_AUTO
			, 0.0 AS WEIGHT_INTRANSIT_TYPE_AUTO
			, 0.0 AS WEIGHT_INTRANSIT_TOTAL_AUTO
			, TRANSPORT_MODE_LINE
			, OPERATION_GROUP
			, PLANT_ID
			, SAFETY_STOCK_PIN_HOUSE
		FROM AA
		ORDER BY PLANT_ID, END_CUSTOMER, NICK_NAME, ITEM_ID, BIZ_TYPE, INCOTERMS
		;
	


END

