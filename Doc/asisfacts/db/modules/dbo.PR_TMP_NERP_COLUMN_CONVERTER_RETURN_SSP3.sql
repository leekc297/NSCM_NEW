CREATE PROCEDURE [dbo].[PR_TMP_NERP_COLUMN_CONVERTER_RETURN_SSP3]
AS
BEGIN
	DECLARE @TABLE_NAME   NVARCHAR(150) = N''; 
	DECLARE @TABLE_NAME_NEW   NVARCHAR(150) = N''; 
	DECLARE @COL_INFO   NVARCHAR(150) = N''; 
	DECLARE @TABLE_COL   NVARCHAR(150) = N''; 
	DECLARE @TABLE_COL2   NVARCHAR(150) = N''; 
	DECLARE @TABLE_COL3   NVARCHAR(150) = N''; 
	DECLARE @MASTER_CODETYPE   NVARCHAR(150) = N''; 
	DECLARE @MASTER_CODETYPE2   NVARCHAR(150) = N''; 
	DECLARE @MASTER_CODETYPE3   NVARCHAR(150) = N''; 
	DECLARE @CNT INT;
	DECLARE @SELECT_COL NVARCHAR(MAX);
	DECLARE @mEXEC NVARCHAR(MAX);

	--------------------------------------------------
	--STEP 1. CREATE TABLE CRIPT
	--------------------------------------------------
	DECLARE @mEXEC_DEL NVARCHAR(MAX);
	DECLARE @mEXEC_DROP NVARCHAR(MAX);
	DECLARE @mEXEC_NEW NVARCHAR(MAX);
	DECLARE @mEXECSelInto NVARCHAR(MAX);
	DECLARE @mEXEC_UPDATE NVARCHAR(MAX);
	BEGIN
		DECLARE LOOKUP_CURSOR_N CURSOR FOR
			SELECT DISTINCT B.TABLE_NAME
			FROM ZNERP_XLS_CHANGE_MASTER_CODE_SSP3 A WITH(NOLOCK)
			INNER JOIN ZNERP_TARGET_INFO_SSP3 B WITH(NOLOCK)
			ON A.PROGRAM_NAME = B.TABLE_NAME
			;
		OPEN LOOKUP_CURSOR_N;
		FETCH NEXT FROM LOOKUP_CURSOR_N
		INTO @TABLE_NAME

		WHILE @@FETCH_STATUS = 0
		BEGIN
			SET @mEXEC_DEL = '';
			SET @mEXEC_DEL = @mEXEC_DEL + 'DELETE FROM ' + @TABLE_NAME + ';' +CHAR(10);	

			EXEC sp_executesql @mEXEC_DEL;

		--SET @mEXEC_DEL = '';
		--SET @mEXEC_DEL = @mEXEC_DEL + 'DROP TABLE DBO.NEW_' + @TABLE_NAME_NEW + ';' +CHAR(10);	
     
		--EXEC sp_executesql @mEXEC_DEL;

		SET @mEXEC_NEW = '';
		SET @mEXEC_NEW = @mEXEC_NEW + 'INSERT INTO ' + @TABLE_NAME + ''+CHAR(10);	
		SET @mEXEC_NEW = @mEXEC_NEW + 'SELECT *  FROM DBO.BACKUP_' + @TABLE_NAME + '' +CHAR(10);	
		
		PRINT @mEXEC_NEW;         
		EXEC sp_executesql @mEXEC_NEW;


			SET @mEXEC_DROP = '';
			SET @mEXEC_DROP = @mEXEC_DROP + 'DROP TABLE DBO.BACKUP_' + @TABLE_NAME + ';' +CHAR(10);	

			EXEC sp_executesql @mEXEC_DROP;

		FETCH NEXT FROM LOOKUP_CURSOR_N
		INTO @TABLE_NAME;
		END
		CLOSE LOOKUP_CURSOR_N;
		DEALLOCATE LOOKUP_CURSOR_N;
	END


	
END
