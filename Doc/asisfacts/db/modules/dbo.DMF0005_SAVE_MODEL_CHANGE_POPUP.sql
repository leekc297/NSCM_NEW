CREATE PROCEDURE [dbo].[DMF0005_SAVE_MODEL_CHANGE_POPUP]
	@p_item_id_before		NVARCHAR(MAX),
	@p_item_id_after		NVARCHAR(MAX),
	@p_last_updated_by		NVARCHAR(MAX)
AS

BEGIN
print '1--' + convert(varchar(30), getdate(), 121)
	SET NOCOUNT ON; 
    SET TRANSACTION ISOLATION LEVEL READ COMMITTED;
    SET XACT_ABORT ON;

	-- 스플릿관련 변수
	DECLARE @s_item_id_before		NVARCHAR(MAX);
	DECLARE @s_item_id_after		NVARCHAR(MAX);
	DECLARE @s_last_updated_by		NVARCHAR(MAX);

	-- 변수 초기화
