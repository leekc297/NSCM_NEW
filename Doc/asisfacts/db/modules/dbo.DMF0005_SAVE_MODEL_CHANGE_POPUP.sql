			SET @v_log_type = 'INVALID';
			GOTO ERR_RTN;	
		END
		
		---------VALIDATION CHECK END----------------------------------------

print '4--' + convert(varchar(30), getdate(), 121)

		---------TABLE UPDATE START------------------------------------------
		
