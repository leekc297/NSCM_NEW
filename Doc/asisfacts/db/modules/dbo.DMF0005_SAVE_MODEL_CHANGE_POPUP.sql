											 ,item_id_after	
											 ,last_updated_by
					) VALUES (
											  @s_item_id_before
											 ,@s_item_id_after
											 ,@s_last_updated_by
					)
			---------------------------(1)
				END
			---------------------------(1)
		---------------------------(2)
		END  -- WHILE
		---------------------------(2)

