 --EXEC PR_DM_DNM_EDI_CALLOFF_STATUS
CREATE PROCEDURE [dbo].[PR_DM_DNM_EDI_CALLOFF_STATUS]
AS
  BEGIN
	--CHECKPOINT
	---- 버퍼 풀 초기화
	--DBCC DROPCLEANBUFFERS
	---- 프로시저 캐시 초기화
	--DBCC FREEPROCCACHE

    SET TRANSACTION ISOLATION LEVEL READ COMMITTED;
    SET NOCOUNT ON; 
    SET XACT_ABORT ON;

    -- LOG 용 변수 설정
    DECLARE @v_batch_user			NVARCHAR(150) = 'scm_batch';
	DECLARE @v_program_name			NVARCHAR(150) = 'PR_DM_DNM_EDI_CALLOFF_STATUS';
	DECLARE @V_BATCH_CHK_MSG		NVARCHAR(150) = N' '

    DECLARE @v_log_type				NVARCHAR(30); -- START/END/ERROR/...
    DECLARE @n_log_count			INTEGER = 0;
    DECLARE @v_log_message			NVARCHAR(1000);
    DECLARE @v_description			NVARCHAR(500);
    DECLARE @d_event_date			DATETIME;
	DECLARE @n_history_seq			BIGINT;
	DECLARE @V_DIVISION_ID			NVARCHAR(30);
	
	--SET @V_DIVISION_ID = '81'

	-- 시작 LOG
    SET @v_log_type = 'START';
    SET @v_log_message = '########## Start of procedure ##########';
    SET @v_description = '';
    SET @d_event_date = SYSDATETIME();
    EXEC PR_SCM_SYS_LOG_BATCH @v_program_name, @v_log_type, @n_log_count, @v_log_message, @v_description, @d_event_date;
	
    ------------------------------------------------------------------------------------------------------------------- ◇◇◇◇◇
	BEGIN TRY	
    ------------------------------------------------------------------------------------------------------------------- ◇◇◇◇◇
	
	---- 테이블중복제거  
	IF OBJECT_ID (N'tempdb..#TEMP_SCM_MST_ITEM_SN', N'U')		IS NOT NULL DROP TABLE #TEMP_SCM_MST_ITEM_SN  
	IF OBJECT_ID (N'tempdb..#TEMP_SCM_MST_SITE_ITEM', N'U')		IS NOT NULL DROP TABLE #TEMP_SCM_MST_SITE_ITEM  
	IF OBJECT_ID (N'tempdb..#TEMP_EDI_INVALID_DATA', N'U')		IS NOT NULL DROP TABLE #TEMP_EDI_INVALID_DATA  
  
	---- 임시확인용테이블 중복제거  
	IF OBJECT_ID (N'dbo.#TEMP_SCM_MST_ITEM_SN', N'U')			IS NOT NULL DROP TABLE #TEMP_SCM_MST_ITEM_SN  
	IF OBJECT_ID (N'dbo.#TEMP_SCM_MST_SITE_ITEM', N'U')			IS NOT NULL DROP TABLE #TEMP_SCM_MST_SITE_ITEM  
	IF OBJECT_ID (N'dbo.#TEMP_EDI_INVALID_DATA', N'U')			IS NOT NULL DROP TABLE #TEMP_EDI_INVALID_DATA 
 
	DECLARE @v_FROM_YYYYMMDD    NVARCHAR(MAX);
	--오늘 기준 52주 전까지 정의함.
	SET @v_FROM_YYYYMMDD = CONVERT(CHAR(8), DATEADD(WEEK,-52, DATEADD(WEEK, DATEDIFF(WEEK,0,GETDATE()), 0)), 112)
	-- CONVERT(CHAR(8), DATEADD(WW,-52, GETDATE()), 112) ;  



	 -- ITEM_RECORD 입력용 TEMP TABLE 생성
	CREATE TABLE #TEMP_EDI_INVALID_DATA
	(    EDI_IF_SEQ			NVARCHAR(35)	NOT NULL 
	   , SUB_NO				SMALLINT		NOT NULL 
	   , YYYYMMDD			NVARCHAR(8)		NOT NULL 
	   , IFSEQNO			NVARCHAR(10)	NULL 
	   , DIVISION_ID		NVARCHAR(5)		NULL
	   , COMPANY_ID			NVARCHAR(30)	NULL
	   , SENDER_CODE		NVARCHAR(30)	NULL
	   , SENDER_NAME		NVARCHAR(200)	NULL
	   , SOLDTO_CODE		NVARCHAR(30)	NULL
	   , UNLOADING_POINT	NVARCHAR(30)	NULL
	   , SHIPTO_CODE		NVARCHAR(30)	NULL
	   , CUSTOMER_PLANT		NVARCHAR(30)	NULL
	   , PROJECT_CODE		NVARCHAR(30)	NULL
	   , CUST_MATERIAL_CODE	NVARCHAR(30)	NULL
	   , ITEM_ID			NVARCHAR(30)	NULL
	   , SCM_SITE_ID		NVARCHAR(30)	NULL
	   , SALES_PLANT_SITE_ID	NVARCHAR(30)	NULL
	   , EDI_INCOTERMS		NVARCHAR(30)	NULL
	   , STATUS_CODE		NVARCHAR(10)	NULL
	   , BOM_STATUS			NVARCHAR(10)	NULL
	   , SALES_SITE_STATUS	NVARCHAR(10)	NULL
	   , PROJECT_STATUS		NVARCHAR(10)	NULL
	   , ITEM_STATUS		NVARCHAR(10)	NULL
	   , SSPM_STATUS		NVARCHAR(10)	NULL
	   , PLANT_SITE_STATUS	NVARCHAR(10)	NULL
	   , INCOTERMS_STATUS	NVARCHAR(10)	NULL
	   , SALES_PLANT_SITE_STATUS	NVARCHAR(100)	NULL
	   , ERP_STATUS			NVARCHAR(100)	NULL
	   , PRIMARY KEY (EDI_IF_SEQ, SUB_NO, YYYYMMDD)
	);

	CREATE TABLE #TEMP_SCM_MST_ITEM_SN
	(    DIVISION_ID         NVARCHAR(30)	NOT NULL  
	   , COMPANY_ID          NVARCHAR(30)	NOT NULL
	   , ITEM_ID             NVARCHAR(150)	NOT NULL
	   , SITE_ID             NVARCHAR(30)	NOT NULL
	   , ITEM_TYPE			 NVARCHAR(30)	NULL
	   , PRIMARY KEY (DIVISION_ID, COMPANY_ID, ITEM_ID, SITE_ID)
	);   

	CREATE TABLE #TEMP_SCM_MST_SITE_ITEM
	(    DIVISION_ID         NVARCHAR(30)	NOT NULL  
	   , SCM_SITE_ID         NVARCHAR(30)	NOT NULL
	   , ITEM_ID             NVARCHAR(50)	NOT NULL
	   , PROJECT_CODE        NVARCHAR(50)	NULL
	   , SALES_PLANT		 NVARCHAR(100)	NULL
	   , EDI_INCOTERMS		 NVARCHAR(150)	NULL
	   , VALID_YN			 NVARCHAR(1)	NULL
	   , PRIMARY KEY (DIVISION_ID, SCM_SITE_ID, ITEM_ID)
	);   

	 ------------------------------------------------------------------------------------------------------------------- ◇◇◇◇◇
	BEGIN

		BEGIN				
		/*
		0. 점검대상 테이블 추출
		*/
			-- #TEMP_EDI_INVALID_DATA 생성
			INSERT INTO #TEMP_EDI_INVALID_DATA
			( EDI_IF_SEQ, SUB_NO, YYYYMMDD, IFSEQNO
			, DIVISION_ID, COMPANY_ID
			, SENDER_CODE, SENDER_NAME, SOLDTO_CODE, SHIPTO_CODE		
			, UNLOADING_POINT, CUSTOMER_PLANT, PROJECT_CODE, CUST_MATERIAL_CODE, ITEM_ID			
			, SCM_SITE_ID, SALES_PLANT_SITE_ID, EDI_INCOTERMS
			, STATUS_CODE, BOM_STATUS, SALES_SITE_STATUS, PROJECT_STATUS, ITEM_STATUS, SSPM_STATUS, PLANT_SITE_STATUS, INCOTERMS_STATUS, SALES_PLANT_SITE_STATUS, ERP_STATUS			
			)
			SELECT EDI_IF_SEQ, SUB_NO, YYYYMMDD, IFSEQNO
				, DIVISION_ID, COMPANY_ID
				, SENDER_CODE, SENDER_NAME, SOLDTO_CODE, SHIPTO_CODE
				, UNLOADING_POINT, CUSTOMER_PLANT, PROJECT_CODE, CUST_MATERIAL_CODE, ITEM_ID
				, SCM_SITE_ID , SALES_PLANT_SITE_ID , EDI_INCOTERMS 
				, STATUS_CODE, BOM_STATUS, SALES_SITE_STATUS, PROJECT_STATUS, ITEM_STATUS, SSPM_STATUS, PLANT_SITE_STATUS, INCOTERMS_STATUS, SALES_PLANT_SITE_STATUS, ERP_STATUS					   
			FROM DM_DNM_EDI_CALLOFF_ITEM A WITH(NOLOCK)
			WHERE STATUS_CODE IN ('U', 'E')		-- U : CALL_OFF_DATA 기반 신규 생성 / E : 기 점검되었으나 기준정보 부족으로 인해 보류된 건. 
			--오늘 기준 전전월(M-2 월의 1일)부터 현재까지 데이터만 변경
			AND A.CREATE_DATE >= @v_FROM_YYYYMMDD
			;

			-- #TEMP_SCM_MST_ITEM_SN 생성 (데이터사이즈 고려하여 필요한 데이터만 추출함.)
			INSERT INTO #TEMP_SCM_MST_ITEM_SN (DIVISION_ID, COMPANY_ID, ITEM_ID, SITE_ID, ITEM_TYPE)
			SELECT DISTINCT DIVISION_ID, COMPANY_ID, ITEM_ID, SITE_ID, ITEM_TYPE
			FROM SCM_MST_ITEM_SN	WITH(NOLOCK)
			WHERE DIVISION_ID IN (SELECT DISTINCT DIVISION_ID FROM #TEMP_EDI_INVALID_DATA)
			;

			-- #TEMP_SCM_MST_SITE_ITEM 생성 (데이터사이즈 고려하여 필요한 데이터만 추출함.)
			INSERT INTO #TEMP_SCM_MST_SITE_ITEM (DIVISION_ID, SCM_SITE_ID, ITEM_ID, PROJECT_CODE, SALES_PLANT, EDI_INCOTERMS, VALID_YN)
			SELECT A.DIVISION_ID, A.SCM_SITE_ID, A.ITEM_ID
				,  A.PROJECT_CODE
				,  A.SALES_PLANT
				,  A.ATTRIBUTE6				AS EDI_INCOTERMS
				,  A.VALID_YN
			FROM 
			(
				SELECT A.DIVISION_ID, A.SCM_SITE_ID, A.ITEM_ID, A.PROJECT_CODE, A.SALES_PLANT, A.ATTRIBUTE6, A.VALID_YN 
						, ROW_NUMBER() OVER (PARTITION BY A.DIVISION_ID, A.SCM_SITE_ID, A.ITEM_ID ORDER BY A.CREATION_DATE DESC, A.PROJECT_CODE DESC) AS RN	--PROJECT 코드가 중복이므로 가장 최근의 프로젝트로 선정함
				FROM SCM_MST_SITE_ITEM	A WITH(NOLOCK)
				WHERE DIVISION_ID IN (SELECT DISTINCT DIVISION_ID FROM #TEMP_EDI_INVALID_DATA)
				AND	  VALID_YN = 'Y'
			) A
			WHERE RN = 1
			;


		END


		BEGIN
		/*
		1. SALES_SITE_STATUS
		SoldTo, Shipto 정보를 기반으로 SCM_SITE_ID 찾아서 업데이트.
			. 정보 있을 시,SALES_SITE_STATUS = 'S'로 반영.
			. 정보 없을 시 SALES_SITE_STATUS = 'E'로 반영, STATUS_CODE = 'E'로 반영
		*/
			-- SCM_SITE_ID, SALES_SITE_STATUS 업데이트
			UPDATE  A
			SET		A.SCM_SITE_ID		= CASE WHEN B.SCM_SITE_ID IS NOT NULL	THEN B.SCM_SITE_ID				END
				,	A.SALES_SITE_STATUS = CASE WHEN B.SCM_SITE_ID IS NOT NULL	THEN 'S'			ELSE 'E'	END
				,	A.STATUS_CODE		= CASE WHEN B.SCM_SITE_ID IS NULL		THEN 'E'						END
			FROM #TEMP_EDI_INVALID_DATA A WITH(NOLOCK)
			LEFT OUTER JOIN 
			(
				SELECT A1.DIVISION_ID, A1.SCM_SITE_ID, A1.SOLDTO_CODE, A1.SHIPTO_CODE
						, A2.PLANT_ID, A2.OPERATION_GROUP, A2.SITE_TYPE 
				FROM SCM_MST_SITE_CUSTOMER A1 WITH(NOLOCK)
				INNER JOIN SCM_MST_SITE A2 WITH(NOLOCK)
				ON	A1.DIVISION_ID	= A2.DIVISION_ID
				AND	A1.SCM_SITE_ID	= A2.SCM_SITE_ID
				AND A2.SITE_TYPE    = 'SALES'
				AND A2.VALID_YN		= 'Y'
				AND A1.DIVISION_ID IN (SELECT DISTINCT DIVISION_ID FROM #TEMP_EDI_INVALID_DATA)
				WHERE A1.VALID_YN	= 'Y'
			) B
			ON	A.DIVISION_ID	= B.DIVISION_ID
			AND A.SOLDTO_CODE	= B.SOLDTO_CODE
			AND A.SHIPTO_CODE	= B.SHIPTO_CODE
			;
		END


        BEGIN
		/*
		2. SSPM_STATUS / ITEM_STATUS
			. DIVISION_ID, SCM_SITE_ID, ITEM_ID 기반으로 SSPM 정보 존재 여부를 확인한다.
			. 정보가 있다면 MAX 기준으로 프로젝트 코드 데이터 정비
			. 정보 있을 시, SSPM_STATUS, ITEM_STATUS S로 반영
			. 정보 없을 시, SSPM_STATUS, ITEM_STATUS E로 반영, STATUS_CODE = 'E'로 반영
		*/
			-- SSPM_STATUS / ITEM_ID 업데이트
			UPDATE  A
			SET		A.SSPM_STATUS	= CASE WHEN B.ITEM_ID	IS NOT NULL				THEN 'S'				ELSE 'E'	END
				,	A.ITEM_STATUS	= CASE WHEN B.ITEM_ID	IS NOT NULL				THEN 'S'				ELSE 'E'	END
                ,	A.STATUS_CODE	= CASE WHEN B.ITEM_ID	IS NULL					THEN 'E'							END
				,	A.PROJECT_CODE	= CASE WHEN LEN(ISNULL(B.PROJECT_CODE, '')) > 0	THEN B.PROJECT_CODE		ELSE ''		END		--Project_Code는 Division_id, Scm_Site_ID, Item까지만 비교하여 가장 최근 Project_Code로 생성함.
			FROM #TEMP_EDI_INVALID_DATA A WITH(NOLOCK)
			LEFT OUTER JOIN #TEMP_SCM_MST_SITE_ITEM B WITH(NOLOCK)
			ON	A.DIVISION_ID	= B.DIVISION_ID
			AND A.SCM_SITE_ID	= B.SCM_SITE_ID
			AND A.ITEM_ID		= B.ITEM_ID
			AND B.VALID_YN		= 'Y'
			;
		
		END

        BEGIN
		/*
		3. PROJECT_CODE 
			. DIVISION_ID, SCM_SITE_ID, ITEM_ID, PROJECT_CODE 기반으로 PROJECT_CODE 정보 존재 여부를 확인한다.
			. 정보 있을 시, PROJECT_STATUS = S로 반영
			. 정보 없을 시, PROJECT_STATUS = E로 반영, STATUS_CODE = 'E'로 반영
		*/
			-- PROJECT_CODE / PROJECT_STATUS 업데이트
			UPDATE  A
			SET		A.PROJECT_STATUS	= CASE WHEN LEN(ISNULL(B.PROJECT_CODE, '')) > 0	THEN 'S'				ELSE 'E'	END
                ,	A.STATUS_CODE		= CASE WHEN LEN(ISNULL(B.PROJECT_CODE, '')) = 0	THEN 'E'							END
			FROM #TEMP_EDI_INVALID_DATA A WITH(NOLOCK)
			LEFT OUTER JOIN #TEMP_SCM_MST_SITE_ITEM B WITH(NOLOCK)
			ON	A.DIVISION_ID	= B.DIVISION_ID
			AND A.SCM_SITE_ID	= B.SCM_SITE_ID
			AND A.ITEM_ID		= B.ITEM_ID
			AND A.PROJECT_CODE	= B.PROJECT_CODE
			AND B.VALID_YN		= 'Y'
			;
		
		END

		
		BEGIN
		/*
		4. INCOTERMS_STATUS / SALES_PLAN_SITE_STATUS
			. DIVISION_ID, SCM_SITE_ID, ITEM_ID 기반으로 PROJECT_CODE, EDI_INCOTERMS, SALES_PLAN_SITE_ID 를 찾는다.
			. 각각의 정보 있을 시, PROJECT_CODE, EDI_INCOTERMS, SALES_PLANT_SITE_ID 업데이트, PROJECT_STATUS, INCOTERMS_STATUS, SALES_PLAN_SITE_STATUS S로 반영
			. 각각의 정보 없을 시, PROJECT_STATUS, INCOTERMS_STATUS, SALES_PLAN_SITE_STATUS E로 반영, STATUS_CODE = 'E'로 반영
			. incoterms 및 Sales_Plant_Site_ID는 빈칸일 수도 있기 때문에 길이로 판단함. 
 		*/
			-- INCOTERMS / SALES_PLANT_SITE_ID 업데이트
			UPDATE  A
			SET		A.EDI_INCOTERMS				= CASE WHEN LEN(ISNULL(B.EDI_INCOTERMS, '')) > 0    THEN B.EDI_INCOTERMS	ELSE 'E'	END
				,	A.INCOTERMS_STATUS			= CASE WHEN LEN(ISNULL(B.EDI_INCOTERMS, '')) > 0    THEN 'S'				ELSE 'E'	END
				,	A.SALES_PLANT_SITE_STATUS	= CASE WHEN LEN(ISNULL(B.SALES_PLANT, '')) > 0	    THEN 'S'				ELSE 'E'	END
				,   A.SALES_PLANT_SITE_ID		= CASE WHEN LEN(ISNULL(B.SALES_PLANT, '')) > 0		THEN 
														CONCAT(B.SALES_PLANT, CASE WHEN SUBSTRING(B.ITEM_ID, 2, 1) IN ('M', 'P') THEN '-P' ELSE '-A' END)
													   ELSE ''
												  END
                ,	A.STATUS_CODE				= CASE WHEN (LEN(ISNULL(B.EDI_INCOTERMS, '')) = 0 OR LEN(ISNULL(B.SALES_PLANT, '')) = 0)		THEN 'E'							
                                                  END
			FROM #TEMP_EDI_INVALID_DATA A WITH(NOLOCK)
			LEFT OUTER JOIN #TEMP_SCM_MST_SITE_ITEM B WITH(NOLOCK)
			ON	A.DIVISION_ID	= B.DIVISION_ID
			AND A.SCM_SITE_ID	= B.SCM_SITE_ID
			AND A.PROJECT_CODE	= B.PROJECT_CODE
            AND A.ITEM_ID		= B.ITEM_ID
            AND B.VALID_YN		= 'Y'
			;
		END


		BEGIN
		/*
		5.  SALES_SITE_STATUS / SSPM_STATUS / PROJECT_STATUS / ITEM_STATUS / INCOTERMS_STATUS / SALES_PLANT_SITE_STATUS 모두 S ==> STATUS_CODE ='S'
		* 참고로 BOM_STATUS는 체크로직 제외됨.
 		*/

			UPDATE #TEMP_EDI_INVALID_DATA
			SET STATUS_CODE = 'S'
			WHERE 1=1
			AND (SALES_SITE_STATUS = 'S' AND SSPM_STATUS = 'S' AND PROJECT_STATUS = 'S' AND ITEM_STATUS = 'S' AND INCOTERMS_STATUS = 'S' AND SALES_PLANT_SITE_STATUS = 'S')

		END

		BEGIN
		/*
		6.  최종 점검 데이터 원테이블에 UPDATE
 		*/

			UPDATE DM_DNM_EDI_CALLOFF_ITEM 
			SET   DM_DNM_EDI_CALLOFF_ITEM.PROJECT_CODE				= ISNULL(A.PROJECT_CODE, '')
				, DM_DNM_EDI_CALLOFF_ITEM.SCM_SITE_ID				= ISNULL(A.SCM_SITE_ID, '')
				, DM_DNM_EDI_CALLOFF_ITEM.SALES_PLANT_SITE_ID		= ISNULL(A.SALES_PLANT_SITE_ID, '')
				, DM_DNM_EDI_CALLOFF_ITEM.STATUS_CODE				= ISNULL(A.STATUS_CODE, 'E')
				, DM_DNM_EDI_CALLOFF_ITEM.SALES_SITE_STATUS			= ISNULL(A.SALES_SITE_STATUS, 'E')
   				, DM_DNM_EDI_CALLOFF_ITEM.BOM_STATUS				= ISNULL(A.BOM_STATUS, 'E')
				, DM_DNM_EDI_CALLOFF_ITEM.SSPM_STATUS				= ISNULL(A.ITEM_STATUS, 'E')
				, DM_DNM_EDI_CALLOFF_ITEM.PROJECT_STATUS			= ISNULL(A.PROJECT_STATUS, 'E')
				, DM_DNM_EDI_CALLOFF_ITEM.ITEM_STATUS				= ISNULL(A.ITEM_STATUS, 'E')
				, DM_DNM_EDI_CALLOFF_ITEM.INCOTERMS_STATUS			= ISNULL(A.INCOTERMS_STATUS, 'E')
				, DM_DNM_EDI_CALLOFF_ITEM.EDI_INCOTERMS				= ISNULL(A.EDI_INCOTERMS, '')
				, DM_DNM_EDI_CALLOFF_ITEM.SALES_PLANT_SITE_STATUS	= A.SALES_PLANT_SITE_STATUS
				, DM_DNM_EDI_CALLOFF_ITEM.LAST_UPDATE_DATE			= GETDATE()
				, DM_DNM_EDI_CALLOFF_ITEM.LAST_UPDATED_BY			= 'scm_batch'
			FROM #TEMP_EDI_INVALID_DATA A WITH(NOLOCK)
			WHERE DM_DNM_EDI_CALLOFF_ITEM.EDI_IF_SEQ	= A.EDI_IF_SEQ
			AND DM_DNM_EDI_CALLOFF_ITEM.SUB_NO			= A.SUB_NO
			AND DM_DNM_EDI_CALLOFF_ITEM.YYYYMMDD		= A.YYYYMMDD
			AND DM_DNM_EDI_CALLOFF_ITEM.CREATE_DATE		>= @v_FROM_YYYYMMDD
		END


		BEGIN
		/*
		7.  예외로직 적용
		*   예외라 함은 NERP로부터 EDI 접수받더라도 집계에서는 제외한다는 의미로.
		*   EXCEPTION_FLAG = 'Y' 라 함은 CALL_OFF_STATUS에서 점검 제외 ==> MKT_FCST(CUST_FCST_EDI) 집계도 제외 함.
		*   EXCEPTION_FLAG 는 'Y'와 NULL 2중 1개로만 존재함.
 		*/
			UPDATE A
			SET   EXCEPTION_FLAG = 'Y'
				, EXCEPTION_DATE = GETDATE()
				, LAST_UPDATE_DATE = GETDATE()
				, LAST_UPDATED_BY = 'scm_batch_exception_1'
			FROM DM_DNM_EDI_CALLOFF_ITEM A
			WHERE 1=1
			AND A.CREATE_DATE >= @v_FROM_YYYYMMDD
			--AND ISNULL(A.EXCEPTION_FLAG , '') <> 'Y'
			AND EXISTS
			(
				SELECT 1
				FROM SCM_ADM_LOOKUP_MASTER_DETAIL Z WITH(NOLOCK)	
				WHERE Z.LOOKUP_TYPE = 'DM_DNM_EDI_CALLOFF_ITEM_EXCLUDE'									
				AND Z.SEGMENT1  = A.DIVISION_ID
