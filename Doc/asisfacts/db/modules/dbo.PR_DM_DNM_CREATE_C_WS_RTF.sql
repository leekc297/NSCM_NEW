CREATE PROCEDURE [dbo].[PR_DM_DNM_CREATE_C_WS_RTF]
	@P_DIVISION_ID	NVARCHAR(30)				
	, @P_VERSION_NO	NVARCHAR(50)	
AS

BEGIN

	SET NOCOUNT ON; 
    SET TRANSACTION ISOLATION LEVEL READ COMMITTED;
    SET XACT_ABORT ON;

	-- LOG 용 변수 설정
    DECLARE @V_PROGRAM_NAME		NVARCHAR(150) = 'PR_DM_DNM_CREATE_C_WS_RTF';
    DECLARE @V_LOG_TYPE			NVARCHAR(30); -- START/END/ERROR/...
    DECLARE @N_LOG_COUNT		INTEGER = 0;
    DECLARE @V_LOG_MESSAGE		NVARCHAR(1000);
    DECLARE @V_DESCRIPTION		NVARCHAR(500);
    DECLARE @D_EVENT_DATE		DATETIME;
    DECLARE @N_DELETE_COUNT		INTEGER = 0;
    DECLARE @N_INSERT_COUNT     INTEGER = 0;
	DECLARE @V_CREATED_BY		NVARCHAR(150)	= 'SYSTEM_WS';

	-- 시작 LOG
	SET @V_LOG_TYPE = 'START';
	SET @V_LOG_MESSAGE = '########## START OF PROCEDURE ##########';
	--[E20260212-001318]_추적가능하도록 로그에 Parameter 추가 (START)
	--SET @V_DESCRIPTION = '';
	SET @V_DESCRIPTION = '@P_DIVISION_ID: ' + @P_DIVISION_ID + ' / @P_VERSION_NO: ' + @P_VERSION_NO;
	--[E20260212-001318]_추적가능하도록 로그에 Parameter 추가 (END)
	SET @D_EVENT_DATE = SYSDATETIME();
	EXEC  PR_SCM_SYS_LOG_BATCH @V_PROGRAM_NAME, @V_LOG_TYPE, @N_LOG_COUNT, @V_LOG_MESSAGE, @V_DESCRIPTION, @D_EVENT_DATE;

	-- 시작 LOG  (END)
	SET @V_LOG_MESSAGE = NULL
	
	DECLARE @V_START_YYYYMMDD		NVARCHAR(8)	-- 당주 월요일
		, @V_SHIP_START_YYYYMMDD	NVARCHAR(8)
		, @V_CUTOFF_TYPE			NVARCHAR(50)
		, @V_CUTOFF_YYYYMMDD		NVARCHAR(8)
		--, @V_SHIP_END_YYYYMMDD	NVARCHAR(8)

	BEGIN TRAN
	
	BEGIN TRY

		SELECT @V_START_YYYYMMDD = CONVERT(CHAR(8), DATEADD(DD, -7, dbo.FN_NEXT_DAY(GETDATE(), 'MON')), 112) 
		
		SELECT @V_CUTOFF_TYPE = VERSION_TYPE
			, @V_CUTOFF_YYYYMMDD = YYYYMMDD
		FROM DM_MST_VERSION A
		WHERE A.DIVISION_ID = @P_DIVISION_ID
			AND A.VERSION_NO = @P_VERSION_NO

		

		---------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
		-- 1. 동기화할 SSP 데이터를 가져온다.
		---------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
		-- SSP 데이터를 가져온다. START
							
			SELECT @V_SHIP_START_YYYYMMDD = CONVERT(CHAR(8), DATEADD(DD, -7, dbo.FN_NEXT_DAY(GETDATE(), 'MON')), 112) 
					--, @V_SHIP_END_YYYYMMDD = CONVERT(CHAR(8), DATEADD(DAY, 7*8, GETDATE()), 112)

			
			IF OBJECT_ID (N'tempdb..#T_SSP', N'U') IS NOT NULL 
					DROP TABLE #T_SSP
			IF OBJECT_ID (N'tempdb..#T_AS_INV', N'U') IS NOT NULL 
					DROP TABLE #T_AS_INV
			IF OBJECT_ID (N'tempdb..#T_RTF', N'U') IS NOT NULL 
					DROP TABLE #T_RTF
			IF OBJECT_ID (N'tempdb..#T_AS_LOOP', N'U') IS NOT NULL 
					DROP TABLE #T_AS_LOOP
			IF OBJECT_ID (N'tempdb..#T_RCV', N'U') IS NOT NULL 
					DROP TABLE #T_RCV
			IF OBJECT_ID (N'tempdb..#T_END_RTF_RAW', N'U') IS NOT NULL 
					DROP TABLE #T_END_RTF_RAW
			IF OBJECT_ID (N'tempdb..#T_END_RTF_LOOP', N'U') IS NOT NULL 
					DROP TABLE #T_END_RTF_LOOP
			IF OBJECT_ID (N'tempdb..#T_RTF_SITE', N'U') IS NOT NULL 
					DROP TABLE #T_RTF_SITE
								
			CREATE TABLE #T_SSP (
				DIVISION_ID		NVARCHAR(30)
				, PROJECT_CODE	NVARCHAR(50)
				, SCM_SITE_ID	NVARCHAR(30)
				, ITEM_ID		NVARCHAR(50)
				, DOM_EXP		NVARCHAR(3)
				, FCST_TYPE		NVARCHAR(20)
				, INCOTERMS		NVARCHAR(10)
				, MEASURE		NVARCHAR(50)
				, PLANT_SITE_ID	NVARCHAR(30)
				, AS_SITE		NVARCHAR(30)
				, ETA_YYYYMMDD	NVARCHAR(8)
				, SHIP_YYYYMMDD	NVARCHAR(8)
				, QTY			NUMERIC(30,10)
				, GUBUN			NVARCHAR(10)
				, AS_FROM_PLANT	NVARCHAR(30)
			)

			-- 고객향 사이트의 RTF 등 집계
			CREATE TABLE #T_END_RTF_RAW (
				DIVISION_ID		NVARCHAR(30)
				, PROJECT_CODE	NVARCHAR(50)
				, SCM_SITE_ID	NVARCHAR(30)
				, ITEM_ID		NVARCHAR(50)
				, DOM_EXP		NVARCHAR(3)
				, FCST_TYPE		NVARCHAR(20)
				, INCOTERMS		NVARCHAR(10)
				, MEASURE		NVARCHAR(50)
				, PLANT_SITE_ID	NVARCHAR(30)
				, YYYYMMDD		NVARCHAR(8)
				, QTY			NUMERIC(30,10)
				, FROM_SITE		NVARCHAR(30)
				, AS_PLANT		NVARCHAR(30)	-- FROM SITE 의 PLANT ID
				, LT_DAYS		INT
				, SEQ			INT
				, MF_SEQ		INT				-- MKT FCST 에 RTF 를 나눠주기 위한 순번
				, MF_QTY		NUMERIC(30,10)	-- 당초요구 수량, 메저가 MF 인 건들을 읽어서 RTF 로 만들때 당초 요구대비 얼만큼 RTF 를 할당 했는지 확인 용도
				, RTF_QTY		NUMERIC(30,10)	-- RTF 할당 수량, 메저가 MF 인 건들을 읽어서 RTF 로 만들때 당초 요구대비 얼만큼 RTF 를 할당 했는지 확인 용도
				, KEY_VAL		INT		IDENTITY(1, 1)	-- UNIQUE 값( JOIN 용도 )
				, ALLOC_SCD_RTF	NCHAR(1)		-- 확정이후 구간의 RTF 배정대상여부
				, LT_YYYYMMDD	NVARCHAR(8)
				, SCD_ALLOC_START_DATE NVARCHAR(8)	-- 확정이후 구간의 RTF 배정시작일 ( SITE 단위임 )
			)
			
			CREATE TABLE #T_AS_INV (
			DIVISION_ID		NVARCHAR(30)
			, PROJECT_CODE	NVARCHAR(50)
			, SCM_SITE_ID	NVARCHAR(30)
			, ITEM_ID		NVARCHAR(50)
			, DOM_EXP		NVARCHAR(3)
			, FCST_TYPE		NVARCHAR(20)
			, INCOTERMS		NVARCHAR(10)
			, MEASURE		NVARCHAR(50)
			, PLANT_SITE_ID	NVARCHAR(30)
			, YYYYMMDD		NVARCHAR(8)
			, QTY			NUMERIC(30,10)
			, SITE_SEQ		INT				-- SITE 별 우선순위 ( 1위에만 INV 를 몰아준다. )
			, FROM_SITE		NVARCHAR(30)
			, ADD_YN		CHAR(1)			-- 8주 이후 구간의 RTF 에만 'Y' 를 넣어서 MKT FCST 테이블에 INSERT 할 때 활용.
			, AS_PLANT		NVARCHAR(30)	-- FROM SITE 의 PLANT ID
			, KEY_VAL		INT		IDENTITY(1, 1)	-- UNIQUE 값( JOIN 용도 )
			)
					
			-- cutoff 버전에는 created_by 가 모두 system 이므로 last_updated_by 를 이용해야 함
			-- 고객향
			DELETE A
			FROM DM_PLN_MKT_FCST_C A
			-- JOIN SCM_ADM_LOOKUP_MASTER_DETAIL B WITH(NOLOCK) ON A.ATTRIBUTE10 = B.SEGMENT2 AND A.DIVISION_ID = B.SEGMENT3 AND B.LOOKUP_TYPE = 'AS_SITE_PLANT' AND B.SEGMENT2 <> '-' AND B.VALID_YN = 'Y'
			WHERE  A.DIVISION_ID = @P_DIVISION_ID
				AND A.VERSION_NO = @P_VERSION_NO
				AND A.LAST_UPDATED_BY = @V_CREATED_BY		-- rtf 계열 메저에는 attr10 이 없으므로 생성자를 이용해서 삭제한다.
				AND A.YYYYMMDD >= @V_START_YYYYMMDD
				AND A.MEASURE IN ( 'RTF_SYS_RP', 'RTF_SCP', 'RTF', 'AS_SHIP_PLAN', 'RTF_PR' )  -- [PJ2025-50017] RTF_PR 추가
		

			-- AS Plant 향	
			DELETE A
			FROM DM_PLN_MKT_FCST_C A
			JOIN SCM_MST_SITE B WITH(NOLOCK) ON A.DIVISION_ID = B.DIVISION_ID AND A.SCM_SITE_ID = B.SCM_SITE_ID AND B.OPERATION_GROUP = 'W' AND B.SITE_TYPE = 'SALES'
			WHERE A.DIVISION_ID = @P_DIVISION_ID
				AND A.VERSION_NO = @P_VERSION_NO
				AND A.LAST_UPDATED_BY = @V_CREATED_BY
				AND A.YYYYMMDD >= @V_START_YYYYMMDD
				AND A.MEASURE IN ( 'RTF_SYS_RP', 'RTF_SCP', 'RTF', 'AS_SHIP_PLAN', 'RTF_PR' )  -- [PJ2025-50017] RTF_PR 추가
				

			--[PJ2025-50017] 소형 매출계획 동기화 개선 - DM_PLN_CFM_MKT_DEMAND_PLAN 동기화 Start
			-- 고객향
			DELETE A
			FROM DM_PLN_CFM_MKT_DEMAND_PLAN_C A
			-- JOIN SCM_ADM_LOOKUP_MASTER_DETAIL B WITH(NOLOCK) ON A.ATTRIBUTE10 = B.SEGMENT2 AND A.DIVISION_ID = B.SEGMENT3 AND B.LOOKUP_TYPE = 'AS_SITE_PLANT' AND B.SEGMENT2 <> '-' AND B.VALID_YN = 'Y'
			WHERE  A.DIVISION_ID = @P_DIVISION_ID
				AND A.VERSION_NO = @P_VERSION_NO
				AND A.CREATED_BY = @V_CREATED_BY		-- rtf 계열 메저에는 attr10 이 없으므로 생성자를 이용해서 삭제한다.
				AND A.YYYYMMDD >= @V_START_YYYYMMDD
				AND A.MEASURE IN ( 'RTF_SYS_RP', 'RTF_SCP', 'RTF', 'AS_SHIP_PLAN', 'RTF_PR' )  -- [PJ2025-50017] RTF_PR 추가

			-- AS Plant 향	
			DELETE A
			FROM DM_PLN_CFM_MKT_DEMAND_PLAN_C A
			JOIN SCM_MST_SITE B WITH(NOLOCK)
			  ON A.DIVISION_ID = B.DIVISION_ID AND A.SCM_SITE_ID = B.SCM_SITE_ID AND B.OPERATION_GROUP = 'W' AND B.SITE_TYPE = 'SALES'
			WHERE A.DIVISION_ID = @P_DIVISION_ID
				AND A.VERSION_NO = @P_VERSION_NO
				AND A.CREATED_BY = @V_CREATED_BY
				AND A.YYYYMMDD >= @V_START_YYYYMMDD
				AND A.MEASURE IN ( 'RTF_SYS_RP', 'RTF_SCP', 'RTF', 'AS_SHIP_PLAN' , 'RTF_PR' )  -- [PJ2025-50017] RTF_PR 추가
			--[PJ2025-50017] 소형 매출계획 동기화 개선 - DM_PLN_CFM_MKT_DEMAND_PLAN 동기화 End
			-- Ship Comfirm
			INSERT INTO #T_SSP ( DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE
				, INCOTERMS, MEASURE, PLANT_SITE_ID, AS_SITE, ETA_YYYYMMDD, SHIP_YYYYMMDD, QTY, GUBUN, AS_FROM_PLANT )
			SELECT
				T0.DIVISION_ID
				, T0.PROJECT_CODE
				, T0.TO_SITE
				, T0.ITEM_ID
				, N'E' AS DOM_EXP
				, T0.FCST_TYPE
				, T1.INCOTERMS
				, N'SSP_RTF' AS MEASURE	-- 최종 RTF 가 아니라서 SSP_RTF 로 넣는다.
				, CASE WHEN T0.DIVISION_ID LIKE '81%' THEN T0.FROM_SITE_PLANT_ID ELSE '' END AS PLANT_SITE_ID
				, T3.SEGMENT1
				, T0.ETA_DATE    AS ETA
				, T0.YYYYMMDD	AS SHIP_YYYYMMDD
				, SUM(T0.QTY)    AS CONFIRM_QTY
				, 'CONFIRM'
				, T3.SEGMENT2
			FROM SSP_ANL_SHIP_CONFIRM T0 WITH(NOLOCK)
			JOIN SCP_MST_BOD_N_V T1 WITH(NOLOCK) ON T0.DIVISION_ID = T1.DIVISION_ID AND T0.BOD_ID = T1.BOD_ID
			JOIN SCP_MST_DISTRIBUTION_ROUTE T2 WITH(NOLOCK) ON T2.ROUTE_ID = T1.ROUTE_ID
			JOIN SCM_ADM_LOOKUP_MASTER_DETAIL T3 WITH(NOLOCK) ON T0.FROM_SITE = T3.SEGMENT2 AND T3.LOOKUP_TYPE = 'AS_SITE_PLANT' AND T3.SEGMENT2 <> '-' AND T3.SEGMENT3 = @P_DIVISION_ID  AND T3.VALID_YN = 'Y'
			JOIN SCM_MST_SITE T4 WITH(NOLOCK) ON T0.TO_SITE = T4.SCM_SITE_ID AND T0.DIVISION_ID = T4.DIVISION_ID AND T4.SITE_TYPE = 'SALES'
			JOIN SCM_ADM_LOOKUP_MASTER_DETAIL T5 WITH(NOLOCK) ON T0.FCST_TYPE = T5.SEGMENT1 AND T5.LOOKUP_TYPE = 'SALES_TYPE_CODE2' AND T5.VALID_YN = 'Y'
			JOIN SCM_MST_SITE T6 (NOLOCK) ON T0.FROM_SITE = T6.SCM_SITE_ID AND T0.DIVISION_ID = T6.DIVISION_ID
			WHERE 1=1
			AND   (	--[E20250120-000036]_81사업부인 경우에는 SHIP_FROZEN을 적용하지 않도록 수정
					--T0.YYYYMMDD BETWEEN @V_SHIP_START_YYYYMMDD AND CONVERT(NCHAR(8), DATEADD(DAY, T6.SHIP_FROZEN, @V_SHIP_START_YYYYMMDD), 112)
						T0.YYYYMMDD BETWEEN @V_SHIP_START_YYYYMMDD AND CASE WHEN @P_DIVISION_ID LIKE '81%' THEN @V_SHIP_START_YYYYMMDD ELSE CONVERT(NCHAR(8), DATEADD(DAY, T6.SHIP_FROZEN, @V_SHIP_START_YYYYMMDD), 112) END
					OR (T0.YYYYMMDD < CONVERT(CHAR(8), DATEADD(DD, -7, dbo.FN_NEXT_DAY(GETDATE(), 'MON')), 112) 
							AND T0.ETA_DATE >= CONVERT(CHAR(8), DATEADD(DD, -7, dbo.FN_NEXT_DAY(GETDATE(), 'MON')), 112) )
					)
			AND T0.QTY <> 0
			AND T0.DIVISION_ID   = @P_DIVISION_ID
			AND FCST_TYPE <> '-'	-- MKT_FCST 없는 경우
			AND SHIPMENT_STATUS = 'C'
			AND T0.CHANGE_TYPE = 'C'
			AND T0.ETA_DATE IS NOT NULL
			GROUP BY T0.DIVISION_ID
				, T0.PROJECT_CODE
				, T0.TO_SITE
				, T0.ITEM_ID
				, T0.FCST_TYPE
				, T1.INCOTERMS
				, CASE WHEN T0.DIVISION_ID LIKE '81%' THEN T0.FROM_SITE_PLANT_ID ELSE '' END
				, T3.SEGMENT1
				, T0.ETA_DATE
				, T0.YYYYMMDD
				, T3.SEGMENT2

			-- 소형은 키값 중 DOM_EXP 를 제외하고는 일치함.
			-- DOM_EXP 가 두 개가 걸리는 경우는 한 개의 값으로 SSP 에 세팅
			UPDATE A
			SET DOM_EXP = B.DOM_EXP
			FROM #T_SSP A
			JOIN (
				SELECT A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.FCST_TYPE, A.INCOTERMS, A.YYYYMMDD
						, MAX(A.DOM_EXP) AS DOM_EXP
				FROM DM_PLN_MKT_FCST_C A WITH(NOLOCK)
				WHERE  A.DIVISION_ID = @P_DIVISION_ID
				AND A.VERSION_NO = @P_VERSION_NO
				AND A.YYYYMMDD BETWEEN @V_START_YYYYMMDD AND CONVERT(NCHAR(8), DATEADD(MONTH,3, @V_START_YYYYMMDD), 112)
				AND	A.MEASURE IN ( 'RTF_SCP', 'MKT_FCST' )
				GROUP BY A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.FCST_TYPE, A.INCOTERMS, A.YYYYMMDD
				) B ON B.DIVISION_ID		 = A.DIVISION_ID
						AND B.PROJECT_CODE	 = A.PROJECT_CODE	
						AND B.SCM_SITE_ID	 = A.SCM_SITE_ID	
						AND B.ITEM_ID		 = A.ITEM_ID		
						AND B.FCST_TYPE		 = A.FCST_TYPE		
						AND B.INCOTERMS		 = A.INCOTERMS		
						AND B.YYYYMMDD		 = A.ETA_YYYYMMDD


			-- 동일한 날짜의 값이 없는 건들은 YYYYMMDD 를 빼고 다시 처리해준다.
			UPDATE A
			SET DOM_EXP = B.DOM_EXP
			FROM #T_SSP A
			JOIN (
				SELECT A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.FCST_TYPE, A.INCOTERMS
						, MAX(A.DOM_EXP) AS DOM_EXP
				FROM DM_PLN_MKT_FCST_C A WITH(NOLOCK)
				WHERE  A.DIVISION_ID = @P_DIVISION_ID
				AND A.VERSION_NO = @P_VERSION_NO
				AND A.YYYYMMDD BETWEEN @V_START_YYYYMMDD AND CONVERT(NCHAR(8), DATEADD(MONTH,3, @V_START_YYYYMMDD), 112)
				AND	A.MEASURE IN ( 'RTF_SCP', 'MKT_FCST' )
				GROUP BY A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.FCST_TYPE, A.INCOTERMS
				) B ON B.DIVISION_ID		 = A.DIVISION_ID
						AND B.PROJECT_CODE	 = A.PROJECT_CODE	
						AND B.SCM_SITE_ID	 = A.SCM_SITE_ID	
						AND B.ITEM_ID		 = A.ITEM_ID		
						AND B.FCST_TYPE		 = A.FCST_TYPE		
						AND B.INCOTERMS		 = A.INCOTERMS		
