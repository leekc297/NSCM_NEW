				 , PROJECT_CODE
				 , END_CUSTOMER
				 , SCM_SITE_ID, ITEM_ID, DOM_EXP
				 , FCST_TYPE, INCOTERMS, MEASURE, PLANT_SITE_ID
				 , CELL_PROD_SITE_ID
				 , YYYYMMDD
