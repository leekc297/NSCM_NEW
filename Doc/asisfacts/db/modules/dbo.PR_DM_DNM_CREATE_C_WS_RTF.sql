				WHILE ( @V_DATE <= @V_MAX_DATE )
				BEGIN
					
					-- 재고는 V_DATE 의 전날짜 재고이므로 당일 입고를 감안해야 함 
					SET @V_INV_QTY = @V_INV_QTY + ( SELECT ISNULL(SUM(QTY),0)
													FROM #T_AS_INV 
													WHERE MEASURE = 'AS_In_Plan' 
														AND DIVISION_ID = @V_DIVISION_ID
														AND SCM_SITE_ID = @V_FROM_SITE
														AND ITEM_ID = @V_ITEM_ID
														AND YYYYMMDD = @V_DATE  )
					
					SELECT @V_SUM_REQ_QTY = ISNULL(SUM(ISNULL(MF_QTY, 0)-ISNULL(RTF_QTY, 0)),0)
					FROM #T_END_RTF_RAW
					WHERE AS_PLANT = @V_FROM_PLANT
						AND ITEM_ID = @V_ITEM_ID
						AND DIVISION_ID = @V_DIVISION_ID
						AND LT_YYYYMMDD <= @V_DATE
						AND MEASURE = 'MKT_FCST'
						AND ISNULL(MF_QTY, 0) > ISNULL(RTF_QTY, 0)
						--AND SCD_ALLOC_START_DATE < CONVERT(NCHAR(8), DATEADD(DAY, LT_DAYS, @V_DATE), 112)

