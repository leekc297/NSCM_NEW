					, @V_INV_ADJ_QTY = 0
					, @V_SUM_REQ_QTY = 0
				FROM #T_AS_LOOP A
				LEFT OUTER JOIN #T_AS_INV B ON A.DIVISION_ID = B.DIVISION_ID AND A.SCM_SITE_ID = B.SCM_SITE_ID AND A.ITEM_ID = B.ITEM_ID 
