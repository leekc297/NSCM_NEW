			JOIN SCM_MST_SITE B ON A.AS_PLANT = B.SCM_SITE_ID AND B.DIVISION_ID = @P_DIVISION_ID
			JOIN ( SELECT FROM_SITE, TO_SITE, LT_TOTAL
							, ROW_NUMBER() OVER ( PARTITION BY FROM_SITE, TO_SITE, INCOTERMS ORDER BY PRIORITY ) AS PRT
					FROM SCP_MST_BOD_N_V
					WHERE DIVISION_ID = @P_DIVISION_ID
						AND CONVERT(NCHAR(8), GETDATE(), 112) BETWEEN FROM_YYYYMMDD AND TO_YYYYMMDD
				) C ON A.AS_PLANT = C.FROM_SITE AND A.SCM_SITE_ID = C.TO_SITE AND C.PRT = 1
			LEFT OUTER JOIN (
					SELECT FROM_SITE, SCM_SITE_ID, MAX(YYYYMMDD) AS MAX_YMD
					FROM #T_END_RTF_RAW 
					WHERE MEASURE = 'RTF'
					GROUP BY FROM_SITE, SCM_SITE_ID
					) D ON A.FROM_SITE = D.FROM_SITE AND A.SCM_SITE_ID = D.SCM_SITE_ID

			UPDATE A
			SET SCD_ALLOC_START_DATE = B.MAX_YMD
			FROM #T_END_RTF_RAW A
			JOIN #T_RTF_SITE B ON A.SCM_SITE_ID = B.SCM_SITE_ID AND A.FROM_SITE = B.FROM_SITE

			UPDATE #T_END_RTF_RAW
			SET LT_YYYYMMDD = CONVERT(NCHAR(8), DATEADD(DAY, ISNULL(LT_DAYS,0)*-1, YYYYMMDD), 112)
			WHERE MEASURE = 'MKT_FCST'

			DECLARE
				 @V_SUM_REQ_QTY	NUMERIC(30,10)		-- 수신 SITE 들의 MKT FCST 합계
				 , @V_REQ_QTY	NUMERIC(30,10)		-- 개별 SITE의 MKT FCST 
				 , @V_REM_QTY	NUMERIC(30,10)		-- 배부하고 남은 수량
				 , @I_RCV		INT					--- RCV SITE LOOP 에서 사용할 변수
				 , @CNT_RCV		INT					--- RCV SITE LOOP 에서 사용할 변수 (COUNT)
				 , @V_INV_ADJ_QTY	NUMERIC(30,10)	-- 각 날짜에서 실제 RTF 에 배부되어서 재고차감해야 할 수량
				 , @V_KEY_VAL	INT

			SELECT @I = 1, @CNT = COUNT(*)
			FROM #T_AS_LOOP
			
			WHILE ( @I <= @CNT )
			BEGIN
			
			 -- 비축용 사이트의 확정구간이 끝난 다음날부터 배부 시작
				SELECT @V_DIVISION_ID	= A.DIVISION_ID
					, @V_FROM_PLANT		= A.FROM_PLANT
					, @V_FROM_SITE		= A.SCM_SITE_ID
					, @V_ITEM_ID		= A.ITEM_ID
					, @V_INV_QTY		= ISNULL(B.QTY,0)			-- 마지막 날짜의 재고
					, @V_DATE			= CALC_START_DATE
					
