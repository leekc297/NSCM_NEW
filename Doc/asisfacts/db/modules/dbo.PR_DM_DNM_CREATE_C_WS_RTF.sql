				, A.PROJECT_CODE
				, CASE WHEN A.DIVISION_ID='40'	THEN A.PROJECT_CODE	ELSE ''				END				AS END_CUSTOMER
				 , A.SCM_SITE_ID, A.ITEM_ID, A.DOM_EXP
				 , A.FCST_TYPE, A.INCOTERMS, A.MEASURE, A.PLANT_SITE_ID, A.FROM_SITE_ID --[PJ2024-50611] FROM_SITE_ID 추가
