			JOIN SCM_ADM_LOOKUP_MASTER_DETAIL B ON A.DIVISION_ID = B.SEGMENT3 AND A.SCM_SITE_ID = B.SEGMENT1 AND B.LOOKUP_TYPE = 'AS_SITE_PLANT' AND B.VALID_YN = 'Y'
