						UNION ALL
						SELECT 'RTF_SCP' AS MEASURE
						UNION ALL
						SELECT 'RTF_SYS_RP' AS MEASURE 
						UNION ALL
						SELECT 'RTF_PR' AS MEASURE				-- [PJ2025-50017] RTF_PR 추가
					) B ON 1=1
