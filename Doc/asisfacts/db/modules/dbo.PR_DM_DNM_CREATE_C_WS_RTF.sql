				, A.PROJECT_CODE
				, CASE WHEN A.DIVISION_ID='40'	THEN A.PROJECT_CODE	ELSE ''				END				AS END_CUSTOMER
				, A.SCM_SITE_ID, A.ITEM_ID, A.DOM_EXP
				 , A.FCST_TYPE, A.INCOTERMS, A.MEASURE, CASE WHEN A.DIVISION_ID LIKE '81%' THEN A.PLANT_SITE_ID ELSE '' END
