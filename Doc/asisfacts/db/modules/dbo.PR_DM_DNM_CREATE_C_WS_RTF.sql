					 , A.FCST_TYPE, A.INCOTERMS, B.MEASURE, CASE WHEN A.DIVISION_ID LIKE '81%' THEN A.PLANT_SITE_ID ELSE '' END, A.YYYYMMDD, FROM_SITE
				) A
			LEFT OUTER JOIN DBO.DM_PLN_CFM_MKT_DEMAND_PLAN_C B ON A.DIVISION_ID		= B.DIVISION_ID
											AND A.PROJECT_CODE		= CASE WHEN B.DIVISION_ID='40'	THEN B.END_CUSTOMER ELSE B.PROJECT_CODE END
											AND A.SCM_SITE_ID		= B.SCM_SITE_ID
											AND A.ITEM_ID			= B.ITEM_ID
											AND A.DOM_EXP			= B.DOM_EXP
											AND A.FCST_TYPE			= B.FCST_TYPE
											AND A.INCOTERMS			= B.INCOTERMS
											AND A.MEASURE			= B.MEASURE
											AND A.PLANT_SITE_ID		= B.PLANT_SITE_ID
											AND A.YYYYMMDD			= B.YYYYMMDD
