						SELECT A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.DOM_EXP, A.FCST_TYPE, A.INCOTERMS, 'RTF_SCP' AS MEASURE
							, CONVERT(NCHAR(8), DATEADD(DAY, ISNULL(LT_DAYS,0), @V_DATE), 112) AS YYYYMMDD, A.PLANT_SITE_ID, SUM(ISNULL(MF_QTY,0) - ISNULL(RTF_QTY,0)), NULL AS SITE_SEQ, A.AS_PLANT, 'Y'
