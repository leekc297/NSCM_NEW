					--, @V_MAX_DATE = CONVERT(NCHAR(8), DATEADD(DAY, 7*54, @V_SHIP_START_YYYYMMDD), 112)
					, @V_MAX_DATE = CONVERT(NCHAR(8), DATEADD(DAY, 7*82, @V_SHIP_START_YYYYMMDD), 112)
