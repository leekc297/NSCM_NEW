			-- #T_END_RTF_RAW 에 확정이후 구간의 rtf 배정을 적용받을 데이터들에 플래그를 달아준다.
			-- MAX[ 출발지의 확정구간 + 도착지의 BOD LT를 적용한 일자, 도착지의 SSP_RTF ]
			--INSERT INTO #T_RTF_SITE ( FROM_SITE, 
			SELECT A.FROM_SITE, A.SCM_SITE_ID
				--[E20250120-000036]_81사업부인 경우에는 SHIP_FROZEN을 적용하지 않도록 수정
				--, CASE WHEN ISNULL(D.MAX_YMD, '19000101') > CONVERT(NVARCHAR(8), DATEADD(DAY, ISNULL(LT_TOTAL,0), DATEADD(DAY, ISNULL(B.SHIP_FROZEN,0), @V_START_YYYYMMDD)), 112)
				, CASE WHEN ISNULL(D.MAX_YMD, '19000101') > CASE WHEN @P_DIVISION_ID LIKE '81%' THEN CONVERT(NVARCHAR(8), DATEADD(DAY, ISNULL(LT_TOTAL,0), @V_START_YYYYMMDD), 112)
																								ELSE CONVERT(NVARCHAR(8), DATEADD(DAY, ISNULL(LT_TOTAL,0), DATEADD(DAY, ISNULL(B.SHIP_FROZEN,0), @V_START_YYYYMMDD)), 112)  END 
							THEN D.MAX_YMD
						--[E20250120-000036]_81사업부인 경우에는 SHIP_FROZEN을 적용하지 않도록 수정
						--ELSE CONVERT(NVARCHAR(8), DATEADD(DAY, ISNULL(LT_TOTAL,0), DATEADD(DAY, ISNULL(B.SHIP_FROZEN,0), @V_START_YYYYMMDD)), 112) 
						ELSE CASE WHEN @P_DIVISION_ID LIKE '81%' THEN CONVERT(NVARCHAR(8), DATEADD(DAY, ISNULL(LT_TOTAL,0), @V_START_YYYYMMDD), 112)
																 ELSE CONVERT(NVARCHAR(8), DATEADD(DAY, ISNULL(LT_TOTAL,0), DATEADD(DAY, ISNULL(B.SHIP_FROZEN,0), @V_START_YYYYMMDD)), 112)  END
						END
						AS MAX_YMD
			INTO #T_RTF_SITE
			FROM ( 
					SELECT DISTINCT FROM_SITE, SCM_SITE_ID, AS_PLANT
					FROM #T_END_RTF_RAW 
