				 , A.YYYYMMDD
				 , A.QTY, @V_CREATED_BY AS CREATED_BY, GETDATE() AS CREATION_DATE, @V_CREATED_BY AS LAST_UPDATED_BY, GETDATE() AS LAST_UPDATE_DATE
				 , '' AS ATTRIBUTE1, null AS ATTRIBUTE2, '' AS ATTRIBUTE3, '' AS ATTRIBUTE4, '' AS ATTRIBUTE5
				 , '' AS ATTRIBUTE6, '' AS ATTRIBUTE7, '' AS ATTRIBUTE8, '' AS ATTRIBUTE9, '' AS ATTRIBUTE10
			FROM   #T_AS_INV A
			WHERE MEASURE = 'AS_Inv'

