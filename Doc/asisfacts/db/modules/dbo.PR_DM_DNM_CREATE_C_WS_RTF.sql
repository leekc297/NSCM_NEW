					UPDATE #T_AS_INV 
					SET QTY = @V_INV_QTY
					WHERE DIVISION_ID = @V_DIVISION_ID 
						AND SCM_SITE_ID = @V_FROM_SITE 
						AND ITEM_ID = @V_ITEM_ID 
						AND YYYYMMDD = @V_DATE
						AND MEASURE  = 'AS_Inv'

					IF @@ROWCOUNT = 0
					BEGIN
						INSERT INTO #T_AS_INV ( DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, MEASURE, YYYYMMDD, PLANT_SITE_ID, QTY, SITE_SEQ)
						SELECT TOP 1 A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.DOM_EXP, A.FCST_TYPE, A.INCOTERMS, 'AS_Inv' AS MEASURE, @V_DATE AS YYYYMMDD, A.PLANT_SITE_ID
							, @V_INV_QTY AS QTY, 1 AS SITE_SEQ
						FROM #T_AS_INV A
						WHERE A.DIVISION_ID = @V_DIVISION_ID 
							AND A.SCM_SITE_ID = @V_FROM_SITE 
							AND A.ITEM_ID = @V_ITEM_ID 
							AND A.MEASURE = 'AS_INV'
							AND SITE_SEQ = 1
					END

					SET @V_DATE = CONVERT(NCHAR(8), DATEADD(DAY, 1, @V_DATE), 112)

				END

				SET @I += 1
			END

