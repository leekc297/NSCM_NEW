								, A.PLANT_SITE_ID
								, SUM(CASE WHEN @V_REQ_QTY <= @V_INV_QTY THEN @V_REQ_QTY ELSE @V_INV_QTY END) AS QTY
								, A.SITE_SEQ, A.FROM_SITE, 'Y'
							FROM #T_RCV A
							WHERE SITE_SEQ = @I_RCV
							GROUP BY A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.DOM_EXP, A.FCST_TYPE, A.INCOTERMS
								, A.YYYYMMDD, A.PLANT_SITE_ID, A.SITE_SEQ, A.FROM_SITE
															
							UPDATE A
							SET RTF_QTY = A.RTF_QTY + CASE WHEN @V_REQ_QTY <= @V_INV_QTY THEN @V_REQ_QTY ELSE @V_INV_QTY END
							FROM #T_END_RTF_RAW A
							JOIN #T_RCV B ON A.KEY_VAL = B.RTF_RAW_KEY_VAL
							WHERE A.KEY_VAL = @V_KEY_VAL
							
							SET @V_INV_QTY = CASE WHEN @V_REQ_QTY <= @V_INV_QTY THEN @V_INV_QTY - @V_REQ_QTY ELSE 0 END 
							
							SET @I_RCV = @I_RCV + 1
						END

					END

