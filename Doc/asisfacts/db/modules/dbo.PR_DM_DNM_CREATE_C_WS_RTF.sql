											AND B.CUTOFF_TYPE		= @V_CUTOFF_TYPE
											AND B.CUTOFF_YYYYMMDD	= @V_CUTOFF_YYYYMMDD
			WHERE B.DIVISION_ID IS NULL
			--[PJ2025-50017] 소형 매출계획 동기화 개선 - DM_PLN_CFM_MKT_DEMAND_PLAN 동기화 End

													
		
