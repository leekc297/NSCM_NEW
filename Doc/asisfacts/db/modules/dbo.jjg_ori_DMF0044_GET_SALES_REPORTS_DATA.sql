create PROCEDURE [dbo].[jjg_ori_DMF0044_GET_SALES_REPORTS_DATA]
	@division_id			NVARCHAR(MAX),
	@p_mdf_type				NVARCHAR(MAX),
	@p_yyyy					NVARCHAR(MAX),
	@p_sp_version_no		NVARCHAR(MAX),
	@p_data_type			NVARCHAR(MAX),
	@p_user_group			NVARCHAR(MAX),
	@p_created_by			NVARCHAR(MAX) 
with recompile
AS 
BEGIN
	
    SET NOCOUNT ON;

	DECLARE @PROD NVARCHAR(MAX)=''
	DECLARE @SQL NVARCHAR(MAX)=''
	DECLARE @v_group_id nvarchar(max)='';
	DECLARE @v_team_id nvarchar(max)='';
    DECLARE @v_user_mea_cnt      AS INT;


	-- 임시 테이블 삭제
	IF OBJECT_ID (N'tempdb..#temp', N'U') IS NOT NULL 
		DROP TABLE #temp;

	IF OBJECT_ID('tempdb..#SELECT_MEASURE') IS NOT NULL	
		DROP TABLE #SELECT_MEASURE;
		
	IF OBJECT_ID('tempdb..#PJT') IS NOT NULL	
		DROP TABLE #PJT;

	-- 권한 그룹
	--IF @p_user_group = 'ADMIN' OR @p_user_group = 'DM ADMIN'
	--	SET @v_group_id = 'ADMIN';

	---------------------------------------------------------------------------------
	--            20200313 KHSONG C20200103-000586 권한그룹을 LOOKUP관리 (BEGIN)
	---------------------------------------------------------------------------------
	IF ISNULL((
				SELECT COUNT(1) FROM SCM_ADM_LOOKUP_MASTER_DETAIL WITH(NOLOCK) 
					where LOOKUP_TYPE = 'GET_ADMIN_GROUP' 
						AND VALID_YN = 'Y'
						AND SEGMENT2 = 'ALL'  -- 'ALL'인경우 기본값(특정화면에서 추가된 그룹을 제외)
						AND SEGMENT1 = @p_user_group
			  ),0) > 0
		BEGIN
			SET @v_group_id = 'ADMIN'
		END
	---------------------------------------------------------------------------------
	--            20200313 KHSONG C20200103-000586 권한그룹을 LOOKUP관리 (END)
	---------------------------------------------------------------------------------

	-- 팀 권한
	select @v_team_id = Dept_ID from [dbo].[TB_FX_User] WITH(NOLOCK) where UserID = @p_created_by;
	SET @v_user_mea_cnt = 0;

	
	-- MEASURE JOIN 처리용

	-- 사용자메저 처리
	SELECT @V_USER_MEA_CNT = COUNT(*)
	FROM   [dbo].[SCM_MST_TITLESET_USER] U WITH(NOLOCK)
	WHERE  U.PROGRAM_ID = 'DMF0044'
    AND    U.SHEET_NAME = 'MDF Reports'
	AND    U.USER_INQUIRY_COLUMN_TYPE_CODE = 'M'
    AND    U.USER_ID    = @p_created_by;


	IF @V_USER_MEA_CNT = 0
	BEGIN	    
		INSERT INTO [dbo].[SCM_MST_TITLESET_USER]
		( USER_ID
		, PROGRAM_ID
		, SHEET_NAME
		, USER_INQUIRY_COLUMN_TYPE_CODE
		, COLUMN_NAME
		, SORT_ORDER_NO
		, SUB_TOTAL_FLAG
		, DATA_SORT_METHOD_CODE
		, CREATED_BY
		, CREATION_DATE
		, LAST_UPDATED_BY
		, LAST_UPDATE_DATE
		)
		SELECT @p_created_by
		     , C.PROGRAM_ID
			 , C.SHEET_NAME
			 , 'M'
			 , C.COLUMN_NAME
			 , C.SORT_ORDER_NO
			 , 'N'
			 , ''
			 , @p_created_by
			 , CONVERT(varchar(19), GETDATE(), 121)
			 , @p_created_by
			 , CONVERT(varchar(19), GETDATE(), 121)
		FROM   [dbo].[SCM_MST_SHEET_MEASURE] C WITH(NOLOCK)
		WHERE  1 = 1
		AND    C.PROGRAM_ID  = 'DMF0044'
		AND    C.SHEET_NAME  = 'MDF Reports'
		AND    C.DEFAULT_FLAG = 'Y'
		AND    C.VALID_YN     = 'Y'	;			
	END;
	
	

		SELECT U.PROGRAM_ID
				, U.SHEET_NAME
				, U.USER_ID
				, U.COLUMN_NAME AS MEASURE
				, U.SORT_ORDER_NO
		INTO #SELECT_MEASURE
		FROM [dbo].[SCM_MST_TITLESET_USER] U  WITH(NOLOCK,INDEX (PK_SCM_MST_TITLESET_USER))
		WHERE 1 = 1
		AND U.USER_INQUIRY_COLUMN_TYPE_CODE = 'M'
		AND U.PROGRAM_ID   = 'DMF0044'
		AND U.USER_ID      = @p_created_by


	CREATE TABLE #T (
	DATA_TYPE				NVARCHAR(1)
	, DIVISION_ID			NVARCHAR(30)
	, VERSION_NO			NVARCHAR(30)
	, CUTOFF_TYPE			NVARCHAR(20)
	, CUTOFF_YYYYMMDD		NVARCHAR(8)
	, DEPARTMENT_ID			NVARCHAR(10)
	, DEPARTMENT_NAME		NVARCHAR(50)
	, DEPT_ID				NVARCHAR(10)
	, DEPT_NAME				NVARCHAR(50)
	, END_CUST_REPORT		NVARCHAR(30)
	, END_CUSTOMER			NVARCHAR(30)
	, CUST_REPORT			NVARCHAR(30)
	, PRODUCT_GROUP			NVARCHAR(30)
	, PROJECT_CODE			NVARCHAR(30)
	, SCM_SITE_ID			NVARCHAR(30)
	, ITEM_ID				NVARCHAR(50)
	, NICK_NAME				NVARCHAR(50)
	, DOM_EXP				NVARCHAR(3)
	, FCST_TYPE				NVARCHAR(10)
	, INCOTERMS				NVARCHAR(10)
	, MEASURE				NVARCHAR(20)
	, PLANT_SITE_ID			NVARCHAR(30)
	, COMPANY_ID			NVARCHAR(10)
	, YYYYMM				NVARCHAR(8)
	, CURRENCY				NVARCHAR(5)
	, QTY					NUMERIC(30,10)
	, EDIT_FLAG				NCHAR(1)
	, APP					NVARCHAR(50)
	, SOLDTO_CUST_REPORT	NVARCHAR(50)
	, DMS_CUSTOMER			NVARCHAR(50)
	, BIZ_TYPE_NAME40		NVARCHAR(50)
	, APPLICATION_GR		NVARCHAR(50)
	, PRODUCT_DETAILS		NVARCHAR(50)
	, CELL_MODEL_INFO		NVARCHAR(50)
	, CELL_MODEL			NVARCHAR(50)  --[C20211112-000213]GSCM의 Cell Model 컬럼 관련 요청의 건
	, DISPLAY_SEQ1			NVARCHAR(50)
	, DISPLAY_SEQ2			NVARCHAR(50)
	, COUNTRY_CODE			NVARCHAR(50)
	, SOLDTO_CODE			NVARCHAR(50)
	, ITEM_NAME				NVARCHAR(50)
	, PROJECT_NAME			NVARCHAR(150)
	, CELL_PER_CAR			NVARCHAR(50)
	, MODULE_PER_CAR		NVARCHAR(50)
	, MODEL_TYPE			NVARCHAR(40)
	, SOLDTO_COUNTRY		NVARCHAR(50)
	, SHIPTO_COUNTRY		NVARCHAR(50)
	, CELL_NAME				NVARCHAR(50)
	, ITEM_USE				NVARCHAR(50)
	, CUST_GROUP_DTL		NVARCHAR(30)
	)


	SELECT A.DIVISION_ID, A.PROJECT_CODE, A.PROJECT_NAME, A.PRODUCT_GROUP_NAME
	INTO #PJT
	FROM SCM_MST_PROJECT A
	JOIN (
		SELECT PROJECT_CODE, MAX(PROJECT_VER_SEQ) AS SEQ 
		FROM SCM_MST_PROJECT 
		WHERE DIVISION_ID = @division_id
		GROUP BY PROJECT_CODE
		) B ON A.PROJECT_CODE = B.PROJECT_CODE AND A.PROJECT_VER_SEQ = B.SEQ
	WHERE A.DIVISION_ID = @division_id



	-- 단계1. 데이터 쿼리 ########################################################
	
	-- CUTOFF_DATA
	IF @p_data_type <> '2'
	BEGIN
	--select 2 , @p_data_type  return;
		INSERT INTO #T
			 ( DATA_TYPE, DIVISION_ID, VERSION_NO, CUTOFF_TYPE, CUTOFF_YYYYMMDD
			 , DEPARTMENT_ID, DEPARTMENT_NAME, DEPT_ID, DEPT_NAME, END_CUST_REPORT
			 , END_CUSTOMER, CUST_REPORT, PRODUCT_GROUP, PROJECT_CODE, SCM_SITE_ID
			 , ITEM_ID, NICK_NAME, DOM_EXP, FCST_TYPE, INCOTERMS
			 , MEASURE, PLANT_SITE_ID, COMPANY_ID, YYYYMM, CURRENCY
			 , QTY, EDIT_FLAG, APP, SOLDTO_CUST_REPORT, DMS_CUSTOMER
			 , BIZ_TYPE_NAME40, APPLICATION_GR, PRODUCT_DETAILS, CELL_MODEL_INFO, CELL_MODEL, DISPLAY_SEQ1
			 , DISPLAY_SEQ2, COUNTRY_CODE, SOLDTO_CODE, ITEM_NAME, PROJECT_NAME
			 , CELL_PER_CAR, MODULE_PER_CAR, MODEL_TYPE
			 , SOLDTO_COUNTRY, SHIPTO_COUNTRY, CELL_NAME, ITEM_USE, CUST_GROUP_DTL )
		SELECT
			R.DATA_TYPE,R.DIVISION_ID,R.VERSION_NO,R.CUTOFF_TYPE,R.CUTOFF_YYYYMMDD
			, R.DEPARTMENT_ID
			, CASE WHEN ISNULL(R.DEPARTMENT_NAME,'') <> '' THEN R.DEPARTMENT_NAME ELSE LK1.SEGMENT2 END AS DEPARTMENT_NAME
			, R.DEPT_ID
			, CASE WHEN ISNULL(R.DEPT_NAME, '') <> '' THEN R.DEPT_NAME ELSE LK2.SEGMENT2 END AS DEPT_NAME
			, R.END_CUST_REPORT
			, CASE WHEN R.DIVISION_ID LIKE '81%' AND R.CUTOFF_TYPE LIKE 'REPORT_BP%' THEN R.END_CUST_REPORT 
					ELSE ISNULL(ST.END_CUSTOMER,'') END AS END_CUSTOMER
			, R.CUST_REPORT
			, CASE WHEN R.DIVISION_ID = '40' THEN R.PRODUCT_GROUP
				   WHEN R.DIVISION_ID LIKE '81%' THEN PJT.PRODUCT_GROUP_NAME
				   END AS PRODUCT_GROUP
			, CASE WHEN LEN(R.PROJECT_CODE) > 1 THEN R.PROJECT_CODE ELSE '' END AS PROJECT_CODE
			, R.SCM_SITE_ID, R.ITEM_ID
			, CASE WHEN ISNULL(R.NICK_NAME,'') <> '' THEN R.NICK_NAME ELSE SINGLE.NICK_NAME END, NULL AS DOM_EXP, R.FCST_TYPE, R.INCOTERMS
			, R.MEASURE, R.PLANT_SITE_ID, R.COMPANY_ID
			, 'M_' + SUBSTRING(R.YYYYMMDD, 1, 6) AS YYYYMM, R.CURRENCY, SUM(R.QTY) AS QTY
			, CASE WHEN (@v_group_id = 'ADMIN') AND (DATA_TYPE = '2') THEN 'Y' ELSE 'N' END AS EDIT_FLAG
			, CASE WHEN ISNULL(R.APPLICATION,'') <> '' THEN R.APPLICATION ELSE SI.APPLICATION END AS APP
			, CASE WHEN ISNULL(R.SOLDTO_CUST_REPORT,'') <> '' THEN R.SOLDTO_CUST_REPORT ELSE ISNULL(SI.attribute1,'') END AS SOLDTO_CUST_REPORT
			, ISNULL(SI.attribute2,'') DMS_CUSTOMER
			, CASE WHEN ISNULL(R.FORECAST_INFO_BIZ_TYPE,'') <> '' THEN R.FORECAST_INFO_BIZ_TYPE ELSE SINGLE.FORECAST_INFO_BIZ_TYPE END AS BIZ_TYPE_NAME40 
			, CASE WHEN ISNULL(R.APPLICATION_GR, '') <> '' THEN R.APPLICATION_GR ELSE SI.REPORT_GROUP1 END AS APPLICATION_GR
			, CASE WHEN ISNULL(R.PRODUCT_DETAILS, '') <> '' THEN R.PRODUCT_DETAILS ELSE SI.REPORT_GROUP4 END AS PRODUCT_DETAILS
			, ISNULL(R.FORECAST_INFO_CELL_MODEL,'') AS CELL_MODEL_INFO --[C20211112-000213]GSCM의 Cell Model 컬럼 관련 요청의 건
			, ISNULL(R.ATTRIBUTE3, '') AS CELL_MODEL --[C20211112-000213]GSCM의 Cell Model 컬럼 관련 요청의 건
			, LK1.DISPLAY_SEQ AS DISPLAY_SEQ1, LK2.DISPLAY_SEQ AS DISPLAY_SEQ2
			, ST.COUNTRY
			, CS.SOLDTO_CODE
			, SINGLE.ITEM_NAME

			-- 자동차
			, PJT.PROJECT_NAME, SI.CELL_PER_CAR, CASE WHEN SI.CELL_PER_MODULE <> 0 THEN SI.CELL_PER_CAR / SI.CELL_PER_MODULE ELSE NULL END AS MODULE_PER_CAR
			, CASE WHEN SINGLE.ITEM_CLASS_NAME LIKE '%CELL%' THEN 'Cell'
				   WHEN SINGLE.ITEM_CLASS_NAME LIKE '%PACK%' THEN 'Pack'
				   WHEN SINGLE.ITEM_CLASS_NAME LIKE '%MODULE%' THEN 'Module'
				   END AS MODEL_TYPE

			-- ESS
			, ISNULL(LEFT(CS.SOLDTO_CODE, 2),'') AS SOLDTO_COUNTRY
			, ISNULL(LEFT(CS.SHIPTO_CODE, 2),'') AS SHIPTO_COUNTRY
			, ISNULL(SI.ATTRIBUTE9,'') AS CELL_NAME	
			-- C20200909-000188
			, CASE WHEN LK3.SEGMENT1 IS NOT NULL THEN LK3.SEGMENT2
					ELSE ISNULL(LEFT(R.PROJECT_CODE, 1),'') END AS ITEM_USE 
			, R.CUST_GROUP_DTL
		FROM DM_PLN_SALES_PLAN_REPORT_C AS R WITH(NOLOCK)
		LEFT JOIN SCM_MST_SITE_ITEM AS SI WITH(NOLOCK)
			ON R.DIVISION_ID = SI.DIVISION_ID
				AND R.PROJECT_CODE = SI.PROJECT_CODE
				AND R.SCM_SITE_ID = SI.SCM_SITE_ID
				AND R.ITEM_ID = SI.ITEM_ID
			LEFT JOIN DM_MST_ITEM_SINGLE_V AS SINGLE WITH(NOLOCK)
			ON SI.DIVISION_ID = SINGLE.DIVISION_ID AND SI.ITEM_ID = SINGLE.ITEM_ID
		LEFT OUTER JOIN SCM_ADM_LOOKUP_MASTER_DETAIL LK1 (NOLOCK) ON R.DEPARTMENT_ID = LK1.SEGMENT1 AND LK1.LOOKUP_TYPE = 'MDF_DEPARTMENT'+ CASE WHEN R.DIVISION_ID= '40' THEN '' ELSE '_' + R.DIVISION_ID END
		LEFT OUTER JOIN SCM_ADM_LOOKUP_MASTER_DETAIL LK2 (NOLOCK) ON R.DEPT_ID = LK2.SEGMENT1 AND LK2.LOOKUP_TYPE = 'DMF0044_DEPARTMENT_TEAM2'+ CASE WHEN R.DIVISION_ID= '40' THEN '' ELSE '_' + R.DIVISION_ID END
		LEFT OUTER JOIN SCM_MST_SITE ST (NOLOCK) ON R.SCM_SITE_ID = ST.SCM_SITE_ID AND R.DIVISION_ID = ST.DIVISION_ID
		LEFT OUTER JOIN SCM_MST_SITE_CUSTOMER CS (NOLOCK) ON R.DIVISION_ID = CS.DIVISION_ID AND R.SCM_SITE_ID = CS.SCM_SITE_ID AND CS.REP_YN = N'Y' AND CS.VALID_YN = N'Y'
		LEFT OUTER JOIN #PJT PJT (NOLOCK) ON R.DIVISION_ID = PJT.DIVISION_ID AND R.PROJECT_CODE = PJT.PROJECT_CODE
		LEFT OUTER JOIN SCM_ADM_LOOKUP_MASTER_DETAIL LK3 WITH(NOLOCK) ON R.PROJECT_CODE = LK3.SEGMENT1 AND LK3.LOOKUP_TYPE = 'DM_ITEM_USE_EX' 
		WHERE R.DIVISION_ID = @division_id
			AND R.CUTOFF_TYPE = @p_mdf_type
			AND SUBSTRING(R.YYYYMMDD, 1, 4) = @p_yyyy
			AND R.VERSION_NO = @p_sp_version_no
		GROUP BY
			R.DATA_TYPE, R.DIVISION_ID, R.VERSION_NO, R.CUTOFF_TYPE, R.CUTOFF_YYYYMMDD, R.DEPARTMENT_ID
			, CASE WHEN ISNULL(R.DEPARTMENT_NAME,'') <> '' THEN R.DEPARTMENT_NAME ELSE LK1.SEGMENT2 END
			, R.DEPT_ID
			, CASE WHEN ISNULL(R.DEPT_NAME, '') <> '' THEN R.DEPT_NAME ELSE LK2.SEGMENT2 END, R.END_CUST_REPORT
			, ST.END_CUSTOMER , R.CUST_REPORT, R.PRODUCT_GROUP
			, CASE WHEN LEN(R.PROJECT_CODE) > 1 THEN R.PROJECT_CODE ELSE '' END, R.SCM_SITE_ID
			, R.ITEM_ID, R.FCST_TYPE, R.INCOTERMS, R.MEASURE, R.PLANT_SITE_ID, R.COMPANY_ID, R.CURRENCY
			, CASE WHEN ISNULL(R.NICK_NAME,'') <> '' THEN R.NICK_NAME ELSE SINGLE.NICK_NAME END
			, SUBSTRING(R.YYYYMMDD, 1, 6)
			, CASE WHEN ISNULL(R.APPLICATION,'') <> '' THEN R.APPLICATION ELSE SI.APPLICATION END 
			, CASE WHEN ISNULL(R.SOLDTO_CUST_REPORT,'') <> '' THEN R.SOLDTO_CUST_REPORT ELSE ISNULL(SI.attribute1,'') END
			, ISNULL(SI.attribute2,'')
			, CASE WHEN ISNULL(R.FORECAST_INFO_BIZ_TYPE,'') <> '' THEN R.FORECAST_INFO_BIZ_TYPE ELSE SINGLE.FORECAST_INFO_BIZ_TYPE END
			, CASE WHEN ISNULL(R.APPLICATION_GR, '') <> '' THEN R.APPLICATION_GR ELSE SI.REPORT_GROUP1 END
			, CASE WHEN ISNULL(R.PRODUCT_DETAILS, '') <> '' THEN R.PRODUCT_DETAILS ELSE SI.REPORT_GROUP4 END
			, ISNULL(R.FORECAST_INFO_CELL_MODEL,'') --[C20211112-000213]GSCM의 Cell Model 컬럼 관련 요청의 건
			, ISNULL(R.ATTRIBUTE3, '') --[C20211112-000213]GSCM의 Cell Model 컬럼 관련 요청의 건
			, LK1.SEGMENT2, LK2.SEGMENT2, LK1.DISPLAY_SEQ, LK2.DISPLAY_SEQ
			, ST.COUNTRY, CS.SOLDTO_CODE, PJT.PROJECT_NAME, SI.CELL_PER_CAR
			, CASE WHEN SI.CELL_PER_MODULE <> 0 THEN SI.CELL_PER_CAR / SI.CELL_PER_MODULE ELSE NULL END
			, LEFT(CS.SOLDTO_CODE, 2), LEFT(CS.SHIPTO_CODE, 2), SI.ATTRIBUTE9
			, CASE WHEN LK3.SEGMENT1 IS NOT NULL THEN LK3.SEGMENT2
					ELSE ISNULL(LEFT(R.PROJECT_CODE, 1),'') END
			, SINGLE.ITEM_NAME
			, CASE WHEN R.DIVISION_ID = '40' THEN R.PRODUCT_GROUP
				   WHEN R.DIVISION_ID LIKE '81%' THEN PJT.PRODUCT_GROUP_NAME
				   END
			, CASE WHEN SINGLE.ITEM_CLASS_NAME LIKE '%CELL%' THEN 'Cell'
				   WHEN SINGLE.ITEM_CLASS_NAME LIKE '%PACK%' THEN 'Pack'
				   WHEN SINGLE.ITEM_CLASS_NAME LIKE '%MODULE%' THEN 'Module'
				   END
			, CASE WHEN R.DIVISION_ID LIKE '81%' AND R.CUTOFF_TYPE LIKE 'REPORT_BP%' THEN R.END_CUST_REPORT ELSE ISNULL(ST.END_CUSTOMER,'') END
			, R.CUST_GROUP_DTL
		END

		IF @p_data_type <> '1'
		BEGIN
		
		--select 1 , @p_data_type  return;
		INSERT INTO #T
			 ( DATA_TYPE, DIVISION_ID, VERSION_NO, CUTOFF_TYPE, CUTOFF_YYYYMMDD
			 , DEPARTMENT_ID, DEPARTMENT_NAME, DEPT_ID, DEPT_NAME, END_CUST_REPORT
			 , END_CUSTOMER, CUST_REPORT, PRODUCT_GROUP, PROJECT_CODE, SCM_SITE_ID
			 , ITEM_ID, NICK_NAME, DOM_EXP, FCST_TYPE, INCOTERMS
			 , MEASURE, PLANT_SITE_ID, COMPANY_ID, YYYYMM, CURRENCY
			 , QTY, EDIT_FLAG, APP, SOLDTO_CUST_REPORT, DMS_CUSTOMER
			 , BIZ_TYPE_NAME40, APPLICATION_GR, PRODUCT_DETAILS, CELL_MODEL_INFO, CELL_MODEL, DISPLAY_SEQ1
			 , DISPLAY_SEQ2, COUNTRY_CODE, SOLDTO_CODE, ITEM_NAME, PROJECT_NAME
			 , CELL_PER_CAR, MODULE_PER_CAR, MODEL_TYPE
			 , SOLDTO_COUNTRY, SHIPTO_COUNTRY, CELL_NAME, ITEM_USE, CUST_GROUP_DTL )
		SELECT
			'2' AS DATA_TYPE, R.DIVISION_ID, R.VERSION_NO, R.CUTOFF_TYPE, R.CUTOFF_YYYYMMDD
			, R.DEPARTMENT_ID
			, CASE WHEN ISNULL(R.DEPARTMENT_NAME,'') <> '' THEN R.DEPARTMENT_NAME ELSE LK1.SEGMENT2 END AS DEPARTMENT_NAME
			, R.DEPT_ID
			, CASE WHEN ISNULL(R.DEPT_NAME,'') <> '' THEN R.DEPT_NAME ELSE LK2.SEGMENT2 END AS DEPT_NAME
			, R.END_CUST_REPORT
			, ISNULL(R.END_CUSTOMER,'') AS END_CUSTOMER
			, R.CUST_REPORT
			, CASE WHEN R.DIVISION_ID = '40' THEN R.PRODUCT_GROUP
				   WHEN R.DIVISION_ID LIKE '81%' THEN PJT.PRODUCT_GROUP_NAME
				   END AS PRODUCT_GROUP
			, R.PROJECT_CODE, R.SCM_SITE_ID
			, R.ITEM_ID
			, CASE WHEN ISNULL(R.NICK_NAME,'') <> '' THEN R.NICK_NAME ELSE SINGLE.NICK_NAME END AS NICK_NAME
			, NULL AS DOM_EXP, R.FCST_TYPE, R.INCOTERMS
			, R.MEASURE, R.PLANT_SITE_ID, R.COMPANY_ID, 'M_' + LEFT(R.YYYYMMDD, 6) AS YYYYMM, R.CURRENCY
			, SUM(R.QTY) AS QTY, CASE WHEN (@v_group_id = 'ADMIN') THEN 'Y' ELSE 'N' END AS EDIT_FLAG
			, R.APPLICATION AS APP, R.SOLDTO_CUST_REPORT, ISNULL(SI.attribute2,'') DMS_CUSTOMER
			, R.BIZ_TYPE as BIZ_TYPE, R.APPLICATION_GR AS APPLICATION_GR, R.PRODUCT_DETAILS AS PRODUCT_DETAILS
			, ISNULL(R.CELL_MODEL_INFO, '') AS CELL_MODEL_INFO--, SI.REPORT_GROUP6 AS CELL_MODEL_INFO --[C20210125-000207] ETC Report에서 입력한 40사업부 CELL_MODEL_INFO 적용
			, ISNULL(R.ATTRIBUTE3, '') AS CELL_MODEL --[C20211112-000213]GSCM의 Cell Model 컬럼 관련 요청의 건
			, LK1.DISPLAY_SEQ AS DISPLAY_SEQ1
			, LK2.DISPLAY_SEQ AS DISPLAY_SEQ2, R.COUNTRY_CODE, R.SOLDTO_CODE
			, NULL AS ITEM_NAME, ISNULL(LK3.SEGMENT3, PJT.PROJECT_NAME ) AS PROJECT_NAME

			, SI.CELL_PER_CAR, CASE WHEN SI.CELL_PER_MODULE <> 0 THEN SI.CELL_PER_CAR / SI.CELL_PER_MODULE END AS MODULE_PER_CAR
			, CASE WHEN SINGLE.ITEM_CLASS_NAME LIKE '%CELL%' THEN 'Cell'
				   WHEN SINGLE.ITEM_CLASS_NAME LIKE '%PACK%' THEN 'Pack'
				   WHEN SINGLE.ITEM_CLASS_NAME LIKE '%MODULE%' THEN 'Module'
				   END AS MODEL_TYPE

			, ISNULL(R.SOLDTO_COUNTRY,'') AS SOLDTOCOUNTRY, ISNULL(R.SHIPTO_COUNTRY,'') AS SHIPTOCOUNTRY
			, ISNULL(SI.ATTRIBUTE9,'') AS CELL_NAME
			, ISNULL(R.ITEM_USE,'') AS ITEM_USE
			, R.CUST_GROUP_DTL
	FROM DM_PLN_SALES_ETC_REPORT_C AS R WITH(NOLOCK)
	LEFT JOIN SCM_MST_SITE_ITEM AS SI WITH(NOLOCK)
		ON R.DIVISION_ID = SI.DIVISION_ID
			AND R.PROJECT_CODE = SI.PROJECT_CODE
			AND R.SCM_SITE_ID = SI.SCM_SITE_ID
			AND R.ITEM_ID = SI.ITEM_ID
		LEFT JOIN DM_MST_ITEM_SINGLE_V AS SINGLE WITH(NOLOCK)
		ON SI.DIVISION_ID = SINGLE.DIVISION_ID
			AND SI.ITEM_ID = SINGLE.ITEM_ID
	LEFT OUTER JOIN SCM_ADM_LOOKUP_MASTER_DETAIL LK1 (NOLOCK) ON R.DEPARTMENT_ID = LK1.SEGMENT1 AND LK1.LOOKUP_TYPE = 'MDF_DEPARTMENT' + CASE WHEN R.DIVISION_ID= '40' THEN '' ELSE '_' + R.DIVISION_ID END
	LEFT OUTER JOIN SCM_ADM_LOOKUP_MASTER_DETAIL LK2 (NOLOCK) ON R.DEPT_ID = LK2.SEGMENT1 AND LK2.LOOKUP_TYPE = 'DMF0044_DEPARTMENT_TEAM2'+ CASE WHEN R.DIVISION_ID= '40' THEN '' ELSE '_' + R.DIVISION_ID END
	LEFT OUTER JOIN SCM_ADM_LOOKUP_MASTER_DETAIL LK3 (NOLOCK) ON R.PROJECT_CODE = LK3.SEGMENT2 AND LK3.LOOKUP_TYPE = 'DM_ETC_PROJECT' AND LK3.SEGMENT1 = R.DIVISION_ID
	LEFT OUTER JOIN SCM_MST_SITE ST (NOLOCK) ON R.SCM_SITE_ID = ST.SCM_SITE_ID AND R.DIVISION_ID = ST.DIVISION_ID
	LEFT OUTER JOIN SCM_MST_SITE_CUSTOMER CS (NOLOCK) ON R.DIVISION_ID = CS.DIVISION_ID AND R.SCM_SITE_ID = CS.SCM_SITE_ID AND CS.REP_YN = N'Y' AND CS.VALID_YN = N'Y'
	LEFT OUTER JOIN #PJT PJT (NOLOCK) ON R.DIVISION_ID= PJT.DIVISION_ID AND R.PROJECT_CODE = PJT.PROJECT_CODE
	LEFT OUTER JOIN DM_MST_ITEM_SINGLE_V ITEM_V WITH(NOLOCK) ON	R.DIVISION_ID = ITEM_V.DIVISION_ID AND	R.ITEM_ID = ITEM_V.ITEM_ID
	WHERE R.DIVISION_ID = @division_id
		AND R.CUTOFF_TYPE = @p_mdf_type
		AND SUBSTRING(R.YYYYMMDD, 1, 4) = @p_yyyy
		AND R.VERSION_NO = @p_sp_version_no
	GROUP BY
		R.DIVISION_ID, R.VERSION_NO, R.CUTOFF_TYPE, R.CUTOFF_YYYYMMDD
		, R.DEPARTMENT_ID, R.DEPT_ID, R.END_CUST_REPORT
		, R.END_CUST_REPORT 
		, R.CUST_REPORT, R.PROJECT_CODE, R.SCM_SITE_ID
		, R.ITEM_ID, CASE WHEN ISNULL(R.NICK_NAME,'') <> '' THEN R.NICK_NAME ELSE SINGLE.NICK_NAME END
		, R.FCST_TYPE, R.INCOTERMS
		, R.MEASURE, R.PLANT_SITE_ID, R.COMPANY_ID, LEFT(R.YYYYMMDD, 6), R.CURRENCY
		, R.APPLICATION, R.SOLDTO_CUST_REPORT, ISNULL(SI.attribute2,'')
		, R.BIZ_TYPE, R.APPLICATION_GR, R.PRODUCT_DETAILS
		, R.CELL_MODEL_INFO --, SI.REPORT_GROUP6 --[C20210125-000207] ETC Report에서 입력한 40사업부 CELL_MODEL_INFO 적용
		, R.ATTRIBUTE3
		, LK1.DISPLAY_SEQ
		, LK2.DISPLAY_SEQ, R.COUNTRY_CODE, R.SOLDTO_CODE, ISNULL(LK3.SEGMENT3, PJT.PROJECT_NAME )
		, R.END_CUSTOMER
		, SI.CELL_PER_CAR, CASE WHEN SI.CELL_PER_MODULE <> 0 THEN SI.CELL_PER_CAR / SI.CELL_PER_MODULE END
		, R.SOLDTO_COUNTRY, R.SHIPTO_COUNTRY
		, SI.ATTRIBUTE9, R.ITEM_USE
		, CASE WHEN R.DIVISION_ID = '40' THEN R.PRODUCT_GROUP
				   WHEN R.DIVISION_ID LIKE '81%' THEN PJT.PRODUCT_GROUP_NAME
				   END
		, CASE WHEN SINGLE.ITEM_CLASS_NAME LIKE '%CELL%' THEN 'Cell'
				   WHEN SINGLE.ITEM_CLASS_NAME LIKE '%PACK%' THEN 'Pack'
				   WHEN SINGLE.ITEM_CLASS_NAME LIKE '%MODULE%' THEN 'Module'
				   END
		, CASE WHEN ISNULL(R.DEPT_NAME,'') <> '' THEN R.DEPT_NAME ELSE LK2.SEGMENT2 END
		, CASE WHEN ISNULL(R.DEPARTMENT_NAME,'') <> '' THEN R.DEPARTMENT_NAME ELSE LK1.SEGMENT2 END
		, R.CUST_GROUP_DTL

	END

	-- 단계3. PIVOT 기간 쿼리 ########################################################
	SELECT @PROD = @PROD + '[M_' + BASIS_YYYYMM + '],'
	FROM (
		SELECT 
		DISTINCT BASIS_YYYYMM
		FROM [DBO].[SCM_SYS_CALENDAR_M] WITH(NOLOCK) 
		WHERE CALENDAR_YYYY = @p_yyyy		
	) A				
	ORDER BY BASIS_YYYYMM
	IF @PROD <> ''
	BEGIN
		SELECT @PROD = LEFT(@PROD, LEN(@PROD)-1)
