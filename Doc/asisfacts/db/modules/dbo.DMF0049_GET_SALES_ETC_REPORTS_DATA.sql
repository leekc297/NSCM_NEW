 * 2021/01/26     P.C.I		[C20210125-000207] 40사업부 RTF Measure, CELL_MODEL_INFO 컬럼 추가
 * 2022/01/12	rosia27		[C20220105-000064]ETC Report 구버전 조회시 조직 명칭 오류의 건
 * 2022/01/21	rosia27		[C20211112-000213]GSCM의 Cell Model 컬럼 관련 요청의 건
 */
CREATE PROCEDURE [dbo].[DMF0049_GET_SALES_ETC_REPORTS_DATA]
	@division_id				NVARCHAR(MAX),
	@p_mdf_type				NVARCHAR(MAX),
	@p_yyyy					NVARCHAR(MAX),
	@p_sp_version_no		NVARCHAR(MAX),
	@p_user_group			NVARCHAR(MAX),
	@p_created_by			NVARCHAR(MAX)
AS 
BEGIN
	
    SET NOCOUNT ON;

	DECLARE @PROD NVARCHAR(MAX)=''
	DECLARE @SQL NVARCHAR(MAX)=''
	DECLARE @v_group_id nvarchar(max)='';
	DECLARE @v_team_id nvarchar(max)='';
    DECLARE @v_user_mea_cnt      AS INT;


	-- 임시 테이블 삭제
	IF OBJECT_ID (N'tempdb..#temp', N'U') IS NOT NULL 
		DROP TABLE #temp;
	IF OBJECT_ID('tempdb..#SELECT_MEASURE') IS NOT NULL	
		DROP TABLE #SELECT_MEASURE;
	IF OBJECT_ID('tempdb..#PJT') IS NOT NULL	
		DROP TABLE #PJT;

	-- 권한 그룹
	--IF @p_user_group = 'ADMIN' OR @p_user_group = 'DM ADMIN'
	--	SET @v_group_id = 'ADMIN';

	---------------------------------------------------------------------------------
	--            20200313 KHSONG C20200103-000586 권한그룹을 LOOKUP관리 (BEGIN)
	---------------------------------------------------------------------------------
	IF ISNULL((
				SELECT COUNT(1) FROM SCM_ADM_LOOKUP_MASTER_DETAIL WITH(NOLOCK) 
					where LOOKUP_TYPE = 'GET_ADMIN_GROUP' 
						AND VALID_YN = 'Y'
						AND SEGMENT2 = 'ALL'  -- 'ALL'인경우 기본값(특정화면에서 추가된 그룹을 제외)
						AND SEGMENT1 = @p_user_group
			  ),0) > 0
		BEGIN
			SET @v_group_id = 'ADMIN'
		END
	---------------------------------------------------------------------------------
	--            20200313 KHSONG C20200103-000586 권한그룹을 LOOKUP관리 (END)
	---------------------------------------------------------------------------------

	-- 팀 권한
	select @v_team_id = Dept_ID from [dbo].[TB_FX_User] WITH(NOLOCK) where UserID = @p_created_by;
	SET @v_user_mea_cnt = 0;

	
	-- MEASURE JOIN 처리용
	IF OBJECT_ID('tempdb..#SELECT_MEASURE') IS NOT NULL	
		DROP TABLE #SELECT_MEASURE;

	-- 사용자메저 처리
	SELECT @V_USER_MEA_CNT = COUNT(*)
	FROM   [dbo].[SCM_MST_TITLESET_USER] U WITH(NOLOCK)
	WHERE  U.PROGRAM_ID = 'DMF0049'
    AND    U.SHEET_NAME = 'MDF Reports'
	AND    U.USER_INQUIRY_COLUMN_TYPE_CODE = 'M'
    AND    U.USER_ID    = @p_created_by;


	IF @V_USER_MEA_CNT = 0
	BEGIN	    
		INSERT INTO [dbo].[SCM_MST_TITLESET_USER]
		( USER_ID
		, PROGRAM_ID
		, SHEET_NAME
		, USER_INQUIRY_COLUMN_TYPE_CODE
		, COLUMN_NAME
		, SORT_ORDER_NO
		, SUB_TOTAL_FLAG
		, DATA_SORT_METHOD_CODE
		, CREATED_BY
		, CREATION_DATE
		, LAST_UPDATED_BY
		, LAST_UPDATE_DATE
		)
		SELECT @p_created_by
		     , C.PROGRAM_ID
			 , C.SHEET_NAME
			 , 'M'
			 , C.COLUMN_NAME
			 , C.SORT_ORDER_NO
			 , 'N'
			 , ''
			 , @p_created_by
			 , CONVERT(varchar(19), GETDATE(), 121)
			 , @p_created_by
			 , CONVERT(varchar(19), GETDATE(), 121)
		FROM   [dbo].[SCM_MST_SHEET_MEASURE] C WITH(NOLOCK)
		WHERE  1 = 1
		AND    C.PROGRAM_ID  = 'DMF0049'
		AND    C.SHEET_NAME  = 'MDF Reports'
		AND    C.DEFAULT_FLAG = 'Y'
		AND    C.VALID_YN     = 'Y'	;			
	END;
	
	

		SELECT U.PROGRAM_ID
				, U.SHEET_NAME
				, U.USER_ID
				, U.COLUMN_NAME AS MEASURE
				, U.SORT_ORDER_NO
		INTO #SELECT_MEASURE
		FROM [dbo].[SCM_MST_TITLESET_USER] U  WITH(NOLOCK,INDEX (PK_SCM_MST_TITLESET_USER))
		WHERE 1 = 1
		AND U.USER_INQUIRY_COLUMN_TYPE_CODE = 'M'
		AND U.PROGRAM_ID   = 'DMF0049'
		AND U.USER_ID      = @p_created_by




	SELECT A.DIVISION_ID, A.PROJECT_CODE, A.PROJECT_NAME, A.PRODUCT_GROUP_NAME
	INTO #PJT
	FROM SCM_MST_PROJECT A
	JOIN (
		SELECT PROJECT_CODE, MAX(PROJECT_VER_SEQ) AS SEQ 
		FROM SCM_MST_PROJECT 
		WHERE DIVISION_ID = @division_id
		GROUP BY PROJECT_CODE
		) B ON A.PROJECT_CODE = B.PROJECT_CODE AND A.PROJECT_VER_SEQ = B.SEQ
	WHERE A.DIVISION_ID = @division_id



	-- 단계1. 데이터 쿼리 ########################################################

	SELECT
		R.DIVISION_ID
		,R.VERSION_NO
		,R.CUTOFF_TYPE
		,R.CUTOFF_YYYYMMDD
		,R.DEPARTMENT_ID
		,R.DEPARTMENT_ID AS T_DEPARTMENT_ID
		, CASE WHEN ISNULL(R.DEPARTMENT_NAME,'') <> '' THEN R.DEPARTMENT_NAME ELSE LK1.SEGMENT2 END AS T_DEPARTMENT_NAME
		,R.DEPT_ID
		,R.DEPT_ID AS T_DEPT_ID
		, CASE WHEN ISNULL(R.DEPT_NAME,'') <> '' THEN R.DEPT_NAME ELSE LK2.SEGMENT2 END AS T_DEPT_NAME
		,R.END_CUST_REPORT
		,R.CUST_REPORT
		,R.PRODUCT_GROUP
		,R.PROJECT_CODE
		,R.SCM_SITE_ID
		,R.ITEM_ID
		,SINGLE.NICK_NAME
		--,SI.APPLICATION
		--,R.DOM_EXP
		--,R.FCST_TYPE
		--,R.INCOTERMS
		,R.MEASURE
		,R.PLANT_SITE_ID
		,R.COMPANY_ID
		,'M_' + LEFT(R.YYYYMMDD, 6) AS YYYYMM
		,R.CURRENCY
		,SUM(R.QTY) AS QTY
		,CASE WHEN (@v_group_id = 'ADMIN') THEN 'Y' ELSE 'N' END AS EDIT_FLAG
		, R.APPLICATION AS APP
		, R.SOLDTO_CUST_REPORT -- 20190213 KHSONG [CSR ID:3912438] 고객군, 판매처 컬럼 정규화 요청의 건 --20190322 KHSONG 고객군, 판매처 컬럼 NULL처리조건 추가
		,ISNULL(SI.attribute2,'') DMS_CUSTOMER  -- 20190213 KHSONG [CSR ID:3912438] 고객군, 판매처 컬럼 정규화 요청의 건 --20190322 KHSONG 고객군, 판매처 컬럼 NULL처리조건 추가
		--, SINGLE.FORECAST_INFO_BIZ_TYPE AS BIZ_TYPE_NAME40 
		, R.BIZ_TYPE as BIZ_TYPE
		, R.APPLICATION_GR AS APPLICATION_GR
		, R.PRODUCT_DETAILS AS PRODUCT_DETAILS
		--, SI.REPORT_GROUP6 AS CELL_MODEL_INFO --[C20210125-000207] Master 대신 ETC Report에서 입력한 40사업부 CELL_MODEL_INFO 적용
		, LK1.DISPLAY_SEQ AS DISPLAY_SEQ1
		, LK2.DISPLAY_SEQ AS DISPLAY_SEQ2
		, R.COUNTRY_CODE
		, R.SOLDTO_CODE
		, SI.CELL_PER_CAR
		, '' AS CELL_NAME
		, R.FCST_TYPE
		, R.DATA_SEQ
		, R.INCOTERMS
		, ISNULL(R.ITEM_USE,'') AS ITEM_USE
		, ITEM_V.ITEM_CLASS_NAME AS MODEL_TYPE
		, CASE WHEN SI.CELL_PER_MODULE <> 0 THEN SI.CELL_PER_CAR / SI.CELL_PER_MODULE END AS MODULE_PER_CAR
		, LK3.SEGMENT3 AS PROJECT_NAME
		, ISNULL(R.SOLDTO_COUNTRY,'') AS SOLDTO_COUNTRY
		, ISNULL(R.SHIPTO_COUNTRY,'') AS SHIPTO_COUNTRY
		, ISNULL(R.END_CUSTOMER,'') AS END_CUSTOMER
		, ISNULL(R.ATTRIBUTE3,'') AS CELL_MODEL --[C20211112-000213]
		, ISNULL(R.CELL_MODEL_INFO, '') AS CELL_MODEL_INFO --[C20211112-000213]
	INTO #temp
	FROM DM_PLN_SALES_ETC_REPORT_C AS R WITH(NOLOCK)
	LEFT JOIN SCM_MST_SITE_ITEM AS SI WITH(NOLOCK)
		ON R.DIVISION_ID = SI.DIVISION_ID
			AND R.PROJECT_CODE = SI.PROJECT_CODE
			AND R.SCM_SITE_ID = SI.SCM_SITE_ID
			AND R.ITEM_ID = SI.ITEM_ID
		LEFT JOIN DM_MST_ITEM_SINGLE_V AS SINGLE WITH(NOLOCK)
		ON SI.DIVISION_ID = SINGLE.DIVISION_ID
			AND SI.ITEM_ID = SINGLE.ITEM_ID
		
	LEFT OUTER JOIN SCM_ADM_LOOKUP_MASTER_DETAIL LK1 (NOLOCK) ON R.DEPARTMENT_ID = LK1.SEGMENT1 AND LK1.LOOKUP_TYPE = 'MDF_DEPARTMENT' + CASE WHEN R.DIVISION_ID= '40' THEN '' ELSE '_' + R.DIVISION_ID END
	LEFT OUTER JOIN SCM_ADM_LOOKUP_MASTER_DETAIL LK2 (NOLOCK) ON R.DEPT_ID = LK2.SEGMENT1 AND LK2.LOOKUP_TYPE = 'DMF0049_DEPARTMENT_TEAM2' + CASE WHEN R.DIVISION_ID= '40' THEN '' ELSE '_' + R.DIVISION_ID END
	LEFT OUTER JOIN SCM_ADM_LOOKUP_MASTER_DETAIL LK3 (NOLOCK) ON R.PROJECT_CODE = LK3.SEGMENT2 AND LK3.LOOKUP_TYPE = 'DM_ETC_PROJECT' AND LK3.SEGMENT1 = R.DIVISION_ID
	LEFT OUTER JOIN SCM_MST_SITE ST (NOLOCK) ON R.SCM_SITE_ID = ST.SCM_SITE_ID AND R.DIVISION_ID = ST.DIVISION_ID
	LEFT OUTER JOIN SCM_MST_COUNTRY CO (NOLOCK) ON ST.COUNTRY = CO.COUNTRY
	LEFT OUTER JOIN SCM_MST_SITE_CUSTOMER CS (NOLOCK) ON R.DIVISION_ID = CS.DIVISION_ID AND R.SCM_SITE_ID = CS.SCM_SITE_ID AND CS.REP_YN = N'Y' AND CS.VALID_YN = N'Y'
	LEFT OUTER JOIN #PJT PJT (NOLOCK) ON R.DIVISION_ID= PJT.DIVISION_ID AND R.PROJECT_CODE = PJT.PROJECT_CODE

	LEFT OUTER JOIN DM_MST_ITEM_SINGLE_V ITEM_V WITH(NOLOCK) ON	R.DIVISION_ID = ITEM_V.DIVISION_ID AND	R.ITEM_ID = ITEM_V.ITEM_ID
	WHERE R.DIVISION_ID = @division_id
		AND R.CUTOFF_TYPE = @p_mdf_type
		AND SUBSTRING(R.YYYYMMDD, 1, 4) = @p_yyyy
		AND R.VERSION_NO = @p_sp_version_no
		--AND R.MEASURE <> 'RTF'
		--AND @p_mdf_type = 'REPORT_SP_W'
	GROUP BY
		R.DIVISION_ID
		,R.VERSION_NO
		,R.CUTOFF_TYPE
		,R.CUTOFF_YYYYMMDD
		,R.DEPARTMENT_ID
		,R.DEPT_ID
		,R.END_CUST_REPORT
		,R.CUST_REPORT
		,R.PRODUCT_GROUP
		,R.PROJECT_CODE
		,R.SCM_SITE_ID
		,R.ITEM_ID
		,SINGLE.NICK_NAME
		,R.MEASURE
		,R.PLANT_SITE_ID
		,R.COMPANY_ID
		,LEFT(R.YYYYMMDD, 6)
		,R.CURRENCY
		, R.APPLICATION
		, R.SOLDTO_CUST_REPORT
		,ISNULL(SI.attribute2,'')
		, R.BIZ_TYPE
		, R.APPLICATION_GR
		, R.PRODUCT_DETAILS
		--, SI.REPORT_GROUP6 --[C20210125-000207] Master 대신 ETC Report에서 입력한 40사업부 CELL_MODEL_INFO 적용
		, LK1.DISPLAY_SEQ
		, LK2.DISPLAY_SEQ
		, R.COUNTRY_CODE
		, R.SOLDTO_CODE
		, SI.CELL_PER_CAR
		, R.FCST_TYPE
		, R.DATA_SEQ
		, R.INCOTERMS
		, LEFT(R.PROJECT_CODE, 1)
		, ITEM_V.ITEM_CLASS_NAME
		, CASE WHEN SI.CELL_PER_MODULE <> 0 THEN SI.CELL_PER_CAR / SI.CELL_PER_MODULE END
		, LK3.SEGMENT3
		, ISNULL(R.SOLDTO_COUNTRY, '')
		, ISNULL(R.SHIPTO_COUNTRY, '')
		, ISNULL(R.END_CUSTOMER, '')
		, ISNULL(R.ITEM_USE, '')
		, ISNULL(R.ATTRIBUTE3,'') --[C20211112-000213]
		, ISNULL(R.CELL_MODEL_INFO, '')  --[C20211112-000213]
		, CASE WHEN ISNULL(R.DEPT_NAME,'') <> '' THEN R.DEPT_NAME ELSE LK2.SEGMENT2 END
		, CASE WHEN ISNULL(R.DEPARTMENT_NAME,'') <> '' THEN R.DEPARTMENT_NAME ELSE LK1.SEGMENT2 END
--SELECT * FROM #temp
--select * from #SELECT_MEASURE

	

	-- 단계3. PIVOT 기간 쿼리 ########################################################
	SELECT @PROD = @PROD + '[M_' + BASIS_YYYYMM + '],'
	FROM (
		SELECT 
		DISTINCT BASIS_YYYYMM
		FROM [DBO].[SCM_SYS_CALENDAR_M] WITH(NOLOCK) 
		WHERE CALENDAR_YYYY = @p_yyyy		
	) A				
	ORDER BY BASIS_YYYYMM
	IF @PROD <> ''
	BEGIN
		SELECT @PROD = LEFT(@PROD, LEN(@PROD)-1)
	END

PRINT 'B'
	--SELECT  @PROD


	-- 단계4. 실행 쿼리 ########################################################
	SELECT  @SQL = '
SELECT  
	 DIVISION_ID
	,VERSION_NO
	,DEPARTMENT_ID
	,T_DEPARTMENT_ID
	,T_DEPARTMENT_NAME
	,DEPT_ID
	,T_DEPT_ID
	,T_DEPT_NAME
	,ISNULL(END_CUST_REPORT,'''') as END_CUST_REPORT
	,CUST_REPORT
	,PRODUCT_GROUP
	,PROJECT_CODE
	,SCM_SITE_ID
	,ITEM_ID
	,ISNULL(NICK_NAME,'''') as NICK_NAME
	--,DOM_EXP
	,FCST_TYPE
	,INCOTERMS
	,MEASURE
	,PLANT_SITE_ID
	,COMPANY_ID
	,CURRENCY
	,ISNULL(APP, '''') AS APPLICATION
	,EDIT_FLAG
	,SOLDTO_CUST_REPORT
	,BIZ_TYPE
	, APPLICATION_GR
	, PRODUCT_DETAILS
	, CELL_MODEL_INFO
	, CELL_MODEL
	, COUNTRY_CODE
	, SOLDTO_CODE
	, CELL_PER_CAR
	, Cell_Name
	, DATA_SEQ
	, FCST_TYPE
	, INCOTERMS
	, ITEM_USE
	, MODEL_TYPE
	, MODULE_PER_CAR
	, PROJECT_NAME
	, SOLDTO_COUNTRY
	, SHIPTO_COUNTRY
	, END_CUSTOMER
	,' + @PROD + '
From(
	SELECT 
		A.*
	FROM #temp A
	JOIN #SELECT_MEASURE B ON A.Measure = B.Measure
	) T
PIVOT (SUM(QTY) FOR YYYYMM IN (' + @PROD + ')
) AS PVT
ORDER BY
	DIVISION_ID
	,VERSION_NO
	,DISPLAY_SEQ1
	,DISPLAY_SEQ2
	,CUST_REPORT
	,END_CUST_REPORT
	,SOLDTO_CODE
	,SOLDTO_CUST_REPORT
	,PRODUCT_GROUP
	,ITEM_ID
	,NICK_NAME
	, PRODUCT_DETAILS
	, CELL_MODEL_INFO
	, CELL_MODEL
	,CURRENCY
	,COMPANY_ID -- 정렬추가
	,BIZ_TYPE -- 정렬추가
	,APPLICATION_GR
	,ISNULL(APP, '''')
	,COUNTRY_CODE
	,DATA_SEQ
	, CASE WHEN MEASURE IN (''LOC'') THEN 1
			WHEN MEASURE IN ( ''RTF'',''Business_Plan'') THEN 2 
			WHEN MEASURE IN (''SalesAmt_LOC'') THEN 3
			WHEN MEASURE IN (''SalesAmt_KRW'') THEN 4-- [C20210125-000207]RTF_SYS_RP Sort 마지막
			ELSE 5
			END
	, END_CUSTOMER
';
execute dbo. SP_executesql @SQL 

