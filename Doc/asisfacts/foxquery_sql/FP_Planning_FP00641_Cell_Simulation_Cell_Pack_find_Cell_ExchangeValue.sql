SELECT MCT.PLANT_ID, MCT.MODEL_ID, MCT.CHILD_ITEM_ID
           , SUM(MCT.ACCUMULATED_CHILD_QTY) AS ACCUM_QTY
      FROM (
          SELECT MCT.PLANT_ID, MCT.MODEL_ID, MCT.CHILD_ITEM_ID, MCT.ACCUMULATED_CHILD_QTY
               , DENSE_RANK() OVER( PARTITION BY MCT.PLANT_ID, MCT.MODEL_ID, MCT.CHILD_ITEM_ID ORDER BY MCT.ALT_PRIORITY ) AS RANK_VAL
          FROM   SCM_MODEL_COMP_EFFECTIVE_DATE MCT WITH(NOLOCK)
          WHERE  1=1
          AND    MCT.EFF_START_DATE <= @PLAN_DATE
          AND    MCT.EFF_END_DATE    > @PLAN_DATE
          AND    MCT.MODEL_ID = MCT.CHILD_ITEM_ID -- 화면 특성상 각 SHOP별 최상위공정의 품번들만 가지고 수정하므로 이 조건이 유효함
          -- cell 계획 테이블 품번 기준으로만 가져온다.
          AND EXISTS (
            	SELECT 1
            	FROM (
              		SELECT DISTINCT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.ITEM_ID
              		FROM   @CELL_AMEND_TABLE A WITH(NOLOCK)
              		WHERE  A.INSTANCE_ID  = @ASSY_INSTANCE_ID               --->  UI FILTER: INSTANCE_ID
              		AND	   A.FP_PLAN_ID IN ( @ASSY_PLAN_LT )   --->  UI FILTER: PLAN_ID
              		AND	   A.PLAN_DATE BETWEEN CONVERT(DATETIME,@PLAN_DATE) AND CONVERT(DATETIME,@BUCKET_TO)
              		AND	   A.CATEGORY_ID  = 'PLAN'
              		AND    A.OPERATION_ID = 'A9000'
              		--AND	  (A.OUT_QTY > 0 OR A.RESULT_OUT_QTY > 0 )
              		AND   A.DIVISION_ID  IN (CASE WHEN INSTANCE_ID = @ASSY_INSTANCE_ID THEN '81' ELSE A.DIVISION_ID END )
            	) A
            	WHERE MCT.COMPANY_ID    = A.COMPANY_ID
            	AND   MCT.DIVISION_ID   = A.DIVISION_ID
            	AND   MCT.SITE_ID       = A.SITE_ID
            	AND   MCT.PLANT_ID      = A.PLANT_ID
            	AND   MCT.CHILD_ITEM_ID = A.ITEM_ID
          )
      ) MCT
      WHERE MCT.RANK_VAL = 1
      GROUP BY MCT.PLANT_ID, MCT.MODEL_ID, MCT.CHILD_ITEM_ID
      ORDER BY MCT.PLANT_ID, MCT.MODEL_ID, MCT.CHILD_ITEM_ID