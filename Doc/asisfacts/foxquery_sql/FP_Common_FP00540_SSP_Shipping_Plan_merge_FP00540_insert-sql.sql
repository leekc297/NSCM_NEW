BEGIN 
      
			        MERGE INTO FP_WEEKLY_DEMAND_SHIPMENT_H A
			        USING (SELECT RTRIM(LTRIM(@COMPANY_ID)) AS COMPANY_ID      , RTRIM(LTRIM(@DIVISION_ID)) AS DIVISION_ID    , RTRIM(LTRIM(@SITE_ID)) AS SITE_ID,
			                      RTRIM(LTRIM(@PLANT_ID)) AS PLANT_ID          , RTRIM(LTRIM(@SHOP_GROUP_ID)) AS SHOP_GROUP_ID, RTRIM(LTRIM(@SCP_PLAN_ID)) AS SCP_PLAN_ID,
			                      RTRIM(LTRIM(@SCP_TARGET_ID)) AS SCP_TARGET_ID, RTRIM(LTRIM(@FP_TARGET_ID)) AS FP_TARGET_ID) B
			        ON (    A.COMPANY_ID    = B.COMPANY_ID    AND A.DIVISION_ID   = B.DIVISION_ID   AND A.SITE_ID     = B.SITE_ID
			            AND A.PLANT_ID      = B.PLANT_ID      AND A.SHOP_GROUP_ID = B.SHOP_GROUP_ID AND A.SCP_PLAN_ID = B.SCP_PLAN_ID
			            AND A.SCP_TARGET_ID = B.SCP_TARGET_ID AND A.FP_TARGET_ID  = B.FP_TARGET_ID)
			        WHEN MATCHED THEN
			        UPDATE SET ITEM_ID    = RTRIM(LTRIM(@ITEM_ID)), TO_SITE_ID = RTRIM(LTRIM(@TO_SITE_ID)), TO_PLANT_ID = RTRIM(LTRIM(@TO_PLANT_ID)), CUSTOMER_ID = RTRIM(LTRIM(@CUSTOMER_ID)),
			                   SHIP_DATE  = CASE WHEN RTRIM(LTRIM(@SHIP_WEEK))<>'999999' AND LEN(ISNULL(RTRIM(LTRIM(@SHIP_DATE)),''))<>10 THEN (SELECT DT FROM TH_UIS_CAL A(NOLOCK) WHERE ISO_YYYYWW=RTRIM(LTRIM(@SHIP_WEEK)) AND DATEPART(DW, DT) = 1) ELSE (SELECT DT FROM TH_UIS_CAL A(NOLOCK) WHERE YYYYMMDD=REPLACE(RTRIM(LTRIM(@SHIP_DATE)),'-','')) END,
			        		       SHIP_WEEK  = CASE WHEN RTRIM(LTRIM(@SHIP_WEEK))='999999' AND LEN(ISNULL(RTRIM(LTRIM(@SHIP_DATE)),''))=10 THEN (SELECT ISO_YYYYWW FROM TH_UIS_CAL A(NOLOCK) WHERE YYYYMMDD=REPLACE(RTRIM(LTRIM(@SHIP_DATE)),'-','')) ELSE RTRIM(LTRIM(@SHIP_WEEK)) END,
			                   SHIP_QTY   = RTRIM(LTRIM(@SHIP_QTY)), PRODUCTION_TYPE = RTRIM(LTRIM(@PRODUCTION_TYPE)), TRANSPORT_MODE = RTRIM(LTRIM(@TRANSPORT_MODE)), 
			                   BIZ_TYPE   = RTRIM(LTRIM(@BIZ_TYPE)), CONFIRM_TYPE = RTRIM(LTRIM(@CONFIRM_TYPE)),
			        		   UPDATE_ID = @USER_ID, UPDATE_TIME = dbo.SYSDATE1()
			        WHEN NOT MATCHED THEN
			        INSERT (
			                COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, SHOP_GROUP_ID, SCP_PLAN_ID, SCP_TARGET_ID, FP_TARGET_ID,
			            		ITEM_ID,TO_SITE_ID,TO_PLANT_ID,CUSTOMER_ID,
			            		SHIP_DATE,
			            		SHIP_WEEK,
			            		SHIP_QTY,
			            		PRODUCTION_TYPE,TRANSPORT_MODE,BIZ_TYPE,CONFIRM_TYPE,
			            		INSERT_ID, INSERT_TIME, UPDATE_ID, UPDATE_TIME
			        )
			        VALUES (
			                RTRIM(LTRIM(@COMPANY_ID)), RTRIM(LTRIM(@DIVISION_ID)), RTRIM(LTRIM(@SITE_ID)), RTRIM(LTRIM(@PLANT_ID)), RTRIM(LTRIM(@SHOP_GROUP_ID)), RTRIM(LTRIM(@SCP_PLAN_ID)), RTRIM(LTRIM(@SCP_TARGET_ID)), RTRIM(LTRIM(@FP_TARGET_ID)),
			                RTRIM(LTRIM(@ITEM_ID)), RTRIM(LTRIM(@TO_SITE_ID)), RTRIM(LTRIM(@TO_PLANT_ID)), RTRIM(LTRIM(@CUSTOMER_ID)),
			            		CASE WHEN RTRIM(LTRIM(@SHIP_WEEK))<>'999999' AND LEN(ISNULL(RTRIM(LTRIM(@SHIP_DATE)),''))<>10 THEN (SELECT DT FROM TH_UIS_CAL A(NOLOCK) WHERE ISO_YYYYWW=RTRIM(LTRIM(@SHIP_WEEK)) AND DATEPART(DW, DT) = 1) ELSE (SELECT DT FROM TH_UIS_CAL A(NOLOCK) WHERE YYYYMMDD=REPLACE(RTRIM(LTRIM(@SHIP_DATE)),'-','')) END,
			            		CASE WHEN RTRIM(LTRIM(@SHIP_WEEK))='999999' AND LEN(ISNULL(RTRIM(LTRIM(@SHIP_DATE)),''))=10 THEN (SELECT ISO_YYYYWW FROM TH_UIS_CAL A(NOLOCK) WHERE YYYYMMDD=REPLACE(RTRIM(LTRIM(@SHIP_DATE)),'-','')) ELSE RTRIM(LTRIM(@SHIP_WEEK)) END,
			            		RTRIM(LTRIM(@SHIP_QTY)),
			            		RTRIM(LTRIM(@PRODUCTION_TYPE)), RTRIM(LTRIM(@TRANSPORT_MODE)), RTRIM(LTRIM(@BIZ_TYPE)), RTRIM(LTRIM(@CONFIRM_TYPE)),
			            		@USER_ID, dbo.SYSDATE1(), @USER_ID, dbo.SYSDATE1()
			        )
			        ;
			      
			        INSERT INTO HIS_WEEKLY_DEMAND_SHIPMENT_H (
			              COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, SHOP_GROUP_ID, SCP_PLAN_ID, SCP_TARGET_ID, FP_TARGET_ID,
			              ITEM_ID,TO_SITE_ID,TO_PLANT_ID,CUSTOMER_ID,
			              SHIP_DATE,SHIP_WEEK,SHIP_QTY,
			              PRODUCTION_TYPE,TRANSPORT_MODE,BIZ_TYPE,CONFIRM_TYPE,
			              INSERT_ID, INSERT_TIME, UPDATE_ID, UPDATE_TIME,
			              JOB_USER_ID, JOB_TIME, JOB_TYPE
			        )
			        SELECT COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, SHOP_GROUP_ID, SCP_PLAN_ID, SCP_TARGET_ID, FP_TARGET_ID,
			               ITEM_ID,TO_SITE_ID,TO_PLANT_ID,CUSTOMER_ID,
			               SHIP_DATE,SHIP_WEEK,SHIP_QTY,
			               PRODUCTION_TYPE,TRANSPORT_MODE,BIZ_TYPE,CONFIRM_TYPE,
			               INSERT_ID, INSERT_TIME, UPDATE_ID, UPDATE_TIME,
			               @USER_ID, dbo.SYSDATE1(), 'EXCEL'
			        FROM   FP_WEEKLY_DEMAND_SHIPMENT_H A(NOLOCK)
			        WHERE  COMPANY_ID     = RTRIM(LTRIM(@COMPANY_ID))
			        AND    DIVISION_ID    = RTRIM(LTRIM(@DIVISION_ID))
			        AND    SITE_ID        = RTRIM(LTRIM(@SITE_ID))
			        AND    PLANT_ID       = RTRIM(LTRIM(@PLANT_ID))
			        AND    SHOP_GROUP_ID  = RTRIM(LTRIM(@SHOP_GROUP_ID))
			        AND    SCP_PLAN_ID    = RTRIM(LTRIM(@SCP_PLAN_ID))
			        AND    SCP_TARGET_ID  = RTRIM(LTRIM(@SCP_TARGET_ID))
			        AND    FP_TARGET_ID   = RTRIM(LTRIM(@FP_TARGET_ID))
			        ;
			      
				END;