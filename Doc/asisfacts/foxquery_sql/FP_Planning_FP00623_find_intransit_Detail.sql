if object_id('tempdb..#COATER_SITE') is not null
	DROP TABLE #COATER_SITE
if object_id('tempdb..#ITEM_CALC') is not null
	DROP TABLE #ITEM_CALC
if object_id('tempdb..#INS_PLANT') is not null
	DROP TABLE #INS_PLANT
if object_id('tempdb..#SHIP_INFO') is not null
	DROP TABLE #SHIP_INFO

SELECT DISTINCT A.DIVISION_ID, A.SITE_ID
INTO #COATER_SITE
FROM   FP_INSTANCE_LINE_V A WITH(NOLOCK)
WHERE  A.OPERATION_ID = 'E2000'
AND    A.INSTANCE_ID  = @INSTANCE_ID
;

SELECT A.*
INTO #ITEM_CALC
FROM (
	SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, ITEM_ID, VERSION, A.VALUE
			, ROW_NUMBER() OVER(PARTITION BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, ITEM_ID
	                            ORDER BY     PLANT_ID, FACTORY_ID, (CASE WHEN A.VERSION LIKE 'Z%' THEN 9999 ELSE 1 END), VERSION DESC) AS ROW_NUM
	FROM   SCM_ITEM_CONV_CALC_M A WITH(NOLOCK)
	WHERE  1=1
	AND    A.MAX_VER_FLAG = 'Y'
	AND    A.VALUE > 0
	AND    A.CATEGORY = 'Pancake (cell/m)'
	AND    A.OPERATION = 'E2000'
	AND    EXISTS (
		SELECT 1
		FROM   #COATER_SITE WW WITH(NOLOCK)
		WHERE  A.DIVISION_ID = WW.DIVISION_ID
		AND    A.SITE_ID     = WW.SITE_ID
	)
) A
WHERE 1=1
AND   ROW_NUM = 1
;

SELECT A.INSTANCE_ID, A.DIVISION_ID, A.COMPANY_ID, A.SITE_ID, A.PLANT_ID, B.PLANT_ID AS ASSY_PLANT_ID, B.DIVISION_ID AS ASSY_DIVISION_ID 
INTO #INS_PLANT 
FROM ( 
	SELECT DISTINCT INSTANCE_ID ,COMPANY_ID ,DIVISION_ID ,SITE_ID ,PLANT_ID 
	FROM   FP_INSTANCE_INFO_V A WITH(NOLOCK) 
	WHERE  INSTANCE_TYPE = 'E' 
) A 
INNER JOIN ( 
	SELECT DISTINCT COMPANY_ID ,SITE_ID ,PLANT_ID , DIVISION_ID 
	FROM   FP_INSTANCE_INFO_V A WITH(NOLOCK) 
	WHERE  INSTANCE_TYPE = 'A' 
) B 
ON    A.COMPANY_ID  =  B.COMPANY_ID 
AND   A.SITE_ID     =  B.SITE_ID 
WHERE A.INSTANCE_ID =  @INSTANCE_ID 
;

SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.ITEM_ID, C.NICK_NAME
     , CONVERT(VARCHAR,A.PLAN_DATE,112) AS PLAN_DATE , CONVERT(VARCHAR,A.PLAN_DATE2,112) AS PLAN_DATE2
	 , A.SHIP_IN_QTY, A.INTRANSIT_TYPE, '(' + A.FROM_PLANT_ID + ')' + D.PLANT_NAME AS PLANT_NAME
FROM (
	SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.ITEM_ID, A.ETA_DATE AS PLAN_DATE, A.ETA_DATE2 AS PLAN_DATE2
		 , ISNULL(A.QTY,0) AS SHIP_IN_QTY, A.INTRANSIT_TYPE, A.FROM_PLANT_ID
	FROM ( 
			SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.ITEM_ID, CONVERT(VARCHAR,A.ETA_DATE,112) AS ETA_DATE, CONVERT(VARCHAR,A.ETA_DATE2,112) AS ETA_DATE2, A.QTY, A.INTRANSIT_TYPE, A.FROM_PLANT_ID
			FROM   (
				--= Shipment_In List: 미래의 선적계획 =--
				SELECT V.COMPANY_ID, V.DIVISION_ID, A.TO_SITE_ID AS SITE_ID, V.PLANT_ID 
					 , A.ITEM_ID, A.RECEIVE_YYYYMMDD AS ETA_DATE, A.RECEIVE_YYYYMMDD AS ETA_DATE2
					 , A.SHIP_QTY AS QTY 
					 , 'SHIPMENT_IN' AS INTRANSIT_TYPE
					 , A.PLANT_ID AS FROM_PLANT_ID
				FROM   FP_WEEKLY_DEMAND_SHIPMENT_H A WITH(NOLOCK)
				INNER JOIN #INS_PLANT V 
				ON  1=1 
				AND A.TO_SITE_ID  = V.SITE_ID 
				AND A.TO_PLANT_ID = V.ASSY_PLANT_ID 
				WHERE	1=1 
				AND		EXISTS ( 
					SELECT 1 
					FROM   ( 
						SELECT A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, MAX(SCP_PLAN_ID) AS SCP_PLAN_ID 
						FROM	 FP_WEEKLY_DEMAND_SHIPMENT_H A WITH(NOLOCK) 
						WHERE	 1=1 
						AND		 A.SHOP_GROUP_ID = 'E' 
						GROUP BY A.DIVISION_ID, A.SITE_ID, A.PLANT_ID 
					) X 
					WHERE	1=1 
					AND		X.DIVISION_ID = A.DIVISION_ID 
					AND		X.SITE_ID     = A.SITE_ID 
					AND		X.PLANT_ID    = A.PLANT_ID 
					AND		X.SCP_PLAN_ID = A.SCP_PLAN_ID 
				) 
				AND		A.PLANT_ID <> A.TO_PLANT_ID -- 같은건 to 가 외주로 가기 때문에 제외한다.
				AND		A.SHIP_QTY > 0 
				AND		A.RECEIVE_YYYYMMDD >= @PLAN_DATE ---+ 미래의 선적계획만 가져온다.
				-- SCP INTRANSIT 정보 추가... 20200722
				UNION ALL 
				SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, V.PLANT_ID, A.ITEM_ID 
					 , CASE WHEN A.ETA_DATE < CONVERT(VARCHAR, @PLAN_DATE,112) THEN CONVERT(VARCHAR, @PLAN_DATE,112) ELSE A.ETA_DATE END ETA_DATE --+ 만약 도착일자가 과거면 오늘날짜로 강제보정
					 , CONVERT(VARCHAR, A.ETA_DATE, 112) AS ETA_DATE2
					 , DELIVERY_QTY AS QTY 
					 , 'SCP_INTRANSIT' AS INTRANSIT_TYPE
					 , A.FROM_PLANT_ID
				FROM   FP_SCM_IN_TRANSIT_H A WITH(NOLOCK) 
					 , SCM_ITEM_M B WITH(NOLOCK) 
					 , SCM_ITEM_CLASS_M C WITH(NOLOCK) 
					 , #INS_PLANT V 
				WHERE  A.DELIVERY_QTY > 0 
				AND    A.RESULT_DATE  = CONVERT(VARCHAR, DATEADD(DD, -1, CONVERT(DATE, @PLAN_DATE) ),112) --> D-1일로 조회해야 함.
				AND    A.COMPANY_ID   = B.COMPANY_ID 
				AND    A.DIVISION_ID  = B.DIVISION_ID 
				AND    A.SITE_ID      = B.SITE_ID 
				AND    A.ITEM_ID      = B.ITEM_ID 
				AND    B.ACTIVE_FLAG  = 'Y' 
				AND    B.ITEM_CLASS   = C.CLASS_ID 
				AND    C.LEVEL_2_NAME = 'Pancake' 
				AND    A.COMPANY_ID   = V.COMPANY_ID 
				AND    A.SITE_ID      = V.SITE_ID 
				AND    A.PLANT_ID     = V.ASSY_PLANT_ID 
			) A
			WHERE 1=1 
	) A 
) A 
LEFT OUTER JOIN SCM_ITEM_M C WITH(NOLOCK)
ON  1=1
AND   A.COMPANY_ID  = C.COMPANY_ID
AND   A.DIVISION_ID = C.DIVISION_ID
AND   A.SITE_ID     = C.SITE_ID
AND   A.ITEM_ID     = C.ITEM_ID
LEFT OUTER JOIN (
	SELECT A.PLANT_ID, MAX(A.PLANT_NAME) AS PLANT_NAME
	FROM   SCM_PLANT_M A WITH(NOLOCK)
	GROUP BY PLANT_ID
) D
ON  A.FROM_PLANT_ID = D.PLANT_ID
WHERE 1=1
AND   A.DIVISION_ID = @DIVISION_ID
AND   A.SITE_ID     = @SITE_ID
AND   A.ITEM_ID     = @ITEM_ID
AND   A.PLAN_DATE   = @DAY_VALUE
ORDER BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.ITEM_ID, A.PLAN_DATE, A.PLAN_DATE2