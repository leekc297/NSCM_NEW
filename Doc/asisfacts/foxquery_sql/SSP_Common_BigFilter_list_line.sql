SELECT 
	--ISNULL(CASE WHEN V.INSTANCE_ID IS NULL THEN 'N' ELSE 'Y' END, 'N') AS INSTANCE_AUTH,
	ISNULL(CASE WHEN V.LINE_ID IS NULL THEN 'N' ELSE 'Y' END, 'N') AS LINE_AUTH,
	ISNULL(CASE WHEN LV.LINE_ID IS NULL THEN 'N' ELSE 'Y' END, 'N') AS PLANNER_AUTH,
	--ISNULL(CASE WHEN V.OPERATION_ID IS NULL THEN 'N' ELSE 'Y' END, 'N') AS OPERATION_AUTH,

	FL.INSTANCE_ID,FL.INSTANCE_NAME,
	FL.COMPANY_ID, FL.COMPANY_NAME,
	FL.LINE_ID, FL.LINE_NAME, 
	FL.DIVISION_ID, FL.DIVISION_NAME,
	FL.SITE_ID, FL.SITE_NAME,
	FL.PLANT_ID, FL.PLANT_NAME,
	FL.FACTORY_ID, FL.FACTORY_NAME,
	FL.OPERATION_ID, FL.OPERATION_NAME,
	FL.ELECTRODE_TYPE, 
	FL.MODEL_TYPE, 
	--FL.LINE_SETUP_GROUP_ID,
	AMEND_FLAG,
	AMEND_MAIN_FLAG
, V.CONFIRM_AREA
--, L.SEGMENT2 AS INSTANCE_NAME2
, L.ATTRIBUTE2 AS IS_SAME_PLAN_ID
, L.ATTRIBUTE4 AS USE_WOW_STATUS
, L.SORT_ORDER AS SORT_ORDER
, SHOP_GROUP_ID
, FL.ACTIVE_FLAG
,VERSION_YN
FROM
 (

SELECT 
--ISNULL(CASE WHEN V.COMPANY_ID IS NULL THEN 'N' ELSE 'Y' END, 'N') AS SAVE_FLAG,
SL.LINE_NAME,LK.SEGMENT2 AS INSTANCE_NAME, FL.INSTANCE_ID, FL.
COMPANY_ID, C.COMPANY_NAME,
FL.DIVISION_ID, D.DIVISION_NAME,
FL.SITE_ID, S.SITE_NAME,
FL.PLANT_ID, P.PLANT_NAME,
FL.FACTORY_ID, F.FACTORY_NAME,
FL.OPERATION_ID, O.OPERATION_NAME,
OV.AMEND_FLAG, OV.AMEND_MAIN_FLAG,
FV.SHOP_GROUP_ID,SL.ACTIVE_FLAG,
FL.LINE_ID, FL.ELECTRODE_TYPE, FL.MODEL_TYPE,
ISNULL(VK.VERSION_YN,'N') AS VERSION_YN
--, FL.LINE_SETUP_GROUP_ID,SL.ACTIVE_FLAG
FROM FP_INSTANCE_LINE_V FL WITH(NOLOCK) 

LEFT OUTER JOIN SCM_LINE_M SL  WITH(NOLOCK)
ON 1=1
AND FL.LINE_ID = SL.LINE_ID AND FL.COMPANY_ID = SL.COMPANY_ID ANd FL.SITE_ID = SL.SITE_ID AND FL.PLANT_ID = SL.PLANT_ID AND FL.FACTORY_ID = SL.FACTORY_ID 
AND FL.OPERATION_ID = SL.OPERATION_ID AND FL.ELECTRODE_TYPE = SL.ELECTRODE_TYPE

LEFT OUTER JOIN SCM_SYS_LOOKUP_VALUE LK WITH(NOLOCK)
ON 1=1
AND LK.LOOKUP_TYPE_CODE='INSTANCE_ID'
AND FL.INSTANCE_ID = LK.SEGMENT1

--VERSION_YN
LEFT OUTER JOIN
				(SELECT SEGMENT1 AS INSTANCE_ID, ATTRIBUTE1 AS VERSION_YN
				FROM   SCM_SYS_LOOKUP_VALUE B WITH(NOLOCK)
				WHERE  1=1
				AND    LOOKUP_TYPE_CODE = 'ELEC_INSTANCE_OPTION'
				AND    ACTIVE_FLAG = 'Y'
				) VK
				ON 1=1
				AND FL.INSTANCE_ID = VK.INSTANCE_ID

INNER JOIN SCM_FACTORY_M  F WITH(NOLOCK)
ON FL.FACTORY_ID = F.FACTORY_ID

INNER JOIN SCM_COMPANY_M C WITH(NOLOCK)
ON FL.COMPANY_ID = C.COMPANY_ID

INNER JOIN SCM_DIVISION_M D WITH(NOLOCK)
ON FL.DIVISION_ID = D.DIVISION_ID
AND FL.COMPANY_ID = D.COMPANY_ID

INNER JOIN SCM_SITE_M S WITH(NOLOCK)
ON FL.SITE_ID = S.SITE_ID
AND FL.COMPANY_ID = S.COMPANY_ID

INNER JOIN SCM_PLANT_M P WITH(NOLOCK)
ON FL.SITE_ID = P.SITE_ID
AND FL.COMPANY_ID = P.COMPANY_ID
AND FL.PLANT_ID = P.PLANT_ID
AND FL.DIVISION_ID = P.DIVISION_ID

INNER JOIN SCM_OPERATION_M O WITH(NOLOCK)
ON FL.SITE_ID = O.SITE_ID
AND FL.COMPANY_ID = O.COMPANY_ID
AND FL.DIVISION_ID = O.DIVISION_ID
AND FL.OPERATION_ID = O.OPERATION_ID

LEFT OUTER JOIN FP_INSTANCE_OPERATION_V OV WITH(NOLOCK)
ON FL.SITE_ID = OV.SITE_ID
AND FL.COMPANY_ID = OV.COMPANY_ID
AND FL.DIVISION_ID = OV.DIVISION_ID
AND FL.OPERATION_ID = OV.OPERATION_ID

LEFT OUTER JOIN FP_INSTANCE_FACTORY_M FV WITH(NOLOCK)
ON FL.INSTANCE_ID = FV.INSTANCE_ID
AND FL.FACTORY_ID = FV.FACTORY_ID

WHERE FV.FACTORY_ID IS NOT NULL
GROUP by 
FL.LINE_ID, SL.LINE_NAME,--V.SAVE_FLAG,
FL.INSTANCE_ID, LK.SEGMENT2,
FL.COMPANY_ID, C.COMPANY_NAME,
FL.DIVISION_ID,D.DIVISION_NAME,
FL.SITE_ID,S.SITE_NAME,
FL.PLANT_ID, P.PLANT_NAME,
FL.FACTORY_ID,F.FACTORY_NAME, 
FL.OPERATION_ID, O.OPERATION_NAME,
OV.AMEND_FLAG,OV.AMEND_MAIN_FLAG,
FV.SHOP_GROUP_ID, SL.ACTIVE_FLAG,
FL.ELECTRODE_TYPE, FL.MODEL_TYPE,VK.VERSION_YN
) FL

LEFT OUTER JOIN FP_USER_ROLE_INFO_V V WITH(NOLOCK)
ON 1=1
AND V.USER_ID = @USER_ID  AND FL.INSTANCE_ID = V.INSTANCE_ID AND FL.LINE_ID = V.LINE_ID AND FL.COMPANY_ID = V.COMPANY_ID ANd FL.SITE_ID = V.SITE_ID AND FL.PLANT_ID = V.PLANT_ID AND FL.FACTORY_ID = V.FACTORY_ID 
AND FL.OPERATION_ID = V.OPERATION_ID AND FL.ELECTRODE_TYPE = V.ELECTRODE_TYPE 

LEFT OUTER JOIN SCM_SYS_LOOKUP_VALUE L WITH(NOLOCK)
ON 1=1
AND L.LOOKUP_TYPE_CODE = 'INSTANCE_ID'
AND FL.INSTANCE_ID = L.SEGMENT1

LEFT OUTER JOIN FP_USER_LINE_GROUP_M LV WITH(NOLOCK)
ON FL.LINE_ID = LV.LINE_ID
AND LV.ACTIVE_FLAG = 'Y'


ORDER BY DIVISION_NAME,FL.COMPANY_ID, FL.SITE_ID, FL.PLANT_ID, FL.FACTORY_ID, FL.OPERATION_ID,FL.LINE_ID