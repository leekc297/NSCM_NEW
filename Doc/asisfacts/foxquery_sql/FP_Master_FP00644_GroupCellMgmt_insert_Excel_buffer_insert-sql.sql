INSERT INTO BUF_FCS_TRAY_M (
				 COMPANY_ID
				,DIVISION_ID
				,SITE_ID
				,PLANT_ID
				,FACTORY_ID
				,TRAY_TYPE_CODE
				,TRAY_TYPE_NAME
				,DEGAS_BEFORE_TYPE
				,CELL_CNT
				,LOAD_YIELD
				,BUFFER_DAY
				,TRAY_CNT
				,INTRANSIT_CNT
				,DESCRIPTION
				,USE_YN
				,INSERT_ID
				,INSERT_DATE
				,UPDATE_ID
				,UPDATE_DATE
				,TRAY_TYPE_GROUP
				,JOB_USER_ID, JOB_TIME, JOB_TYPE, JOB_ORDER
			)
			VALUES (
				 @COMPANY_ID, @DIVISION_ID, @SITE_ID, @PLANT_ID, @FACTORY_ID, @TRAY_ID
				,@TRAY_NAME
				, (	SELECT 	DISTINCT DEGAS_BEFORE_TYPE 
					FROM	SCM_FCS_TRAY_M B WITH(NOLOCK) 
					WHERE	@COMPANY_ID = B.COMPANY_ID
					AND		@DIVISION_ID = B.DIVISION_ID
					AND		@SITE_ID = B.SITE_ID
					AND		@PLANT_ID = B.PLANT_ID
					AND		@TRAY_ID = B.TRAY_TYPE_CODE
				  )
				,REPLACE(ISNULL(@CELL_CNT,0),' ','0')
				,@LOAD_YIELD
				,@BUFFER_DAY, REPLACE(@INVENTORY_CNT,',',''), REPLACE(ISNULL(@INTRANSIT_CNT,0),' ','0')
				,@DESCRIPTION, @ACTIVE_FLAG
				,@USER_ID, dbo.SYSDATE1()
				,@USER_ID, dbo.SYSDATE1()
				,@GROUP_TRAY_ID
				,@USER_ID, dbo.SYSDATE1(), '-', @JOB_ORDER
			)