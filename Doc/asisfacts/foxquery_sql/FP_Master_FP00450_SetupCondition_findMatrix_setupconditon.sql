SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID
            ,A.OPERATION_ID, A.LINE_SETUP_GROUP_ID
            ,A.SETUP_CATEGORY_ID, A.SETUP_KEY_ID
            ,A.SETUP_CONDITION_ID, A.SETUP_TIME,A.SETUP_CONDITION_ID AS CODE,A.SETUP_CONDITION_ID AS NAME
      FROM   SCM_SETUP_CONDITION_M A WITH(NOLOCK)
      ORDER BY A.SETUP_CONDITION_ID