WITH _INSTANCELIST AS (
          	SELECT A.SEGMENT2 AS INSTANCE_ID, A.SEGMENT3 AS SITE_ID, @PLAN_DATE AS PLAN_DATE, @USER_ID AS USER_ID, A.SEGMENT1 AS TOTAL_INSTANCE_ID
          	FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
          	WHERE  A.LOOKUP_TYPE_CODE = 'TOTAL_INSTANCE_INFO'
          	AND    A.ACTIVE_FLAG      = 'Y'
          	AND    A.SEGMENT1         = @TOTAL_INSTANCE_ID
          )
          , _SEQ AS (
          	SELECT ISNULL(REPLICATE ('0',2-LEN(A.SEQ)) + CAST (A.SEQ AS VARCHAR ), '01') AS SEQ
          	FROM (
          		SELECT CONVERT(NUMERIC, (CASE WHEN A.SEQ > A.SEQ2 THEN A.SEQ ELSE A.SEQ2 END)) + 1 AS SEQ
          		FROM   (
          			--SELECT MAX(RIGHT(A.PLAN_ID, 2)) AS SEQ, MAX(RIGHT(A.INTG_PLAN_ID, 2)) AS SEQ2
          			--SELECT MAX(RIGHT(A.PLAN_ID, 2)) AS SEQ, ISNULL(MAX(RIGHT(A.INTG_PLAN_ID, 2)),'01') AS SEQ2
          			SELECT ISNULL(MAX(RIGHT(A.PLAN_ID, 2)), '00') AS SEQ, ISNULL(MAX(RIGHT(A.INTG_PLAN_ID, 2)),'00') AS SEQ2
          			FROM   SCM_FP_PLAN_H A WITH(NOLOCK), _INSTANCELIST B WITH(NOLOCK)
          			WHERE  1=1
          			AND    A.INSTANCE_ID = B.INSTANCE_ID
          			AND    CONVERT(VARCHAR(8), A.PLAN_START_TIME, 112) = @PLAN_DATE
          			AND    A.PLAN_TYPE <> 'RELEASE'
          		) A
          	) A
          )
          INSERT INTO SCM_FP_PLAN_H (
               INSTANCE_ID,        PLAN_ID,           PLAN_TYPE,          SITE_ID
             , PLAN_START_TIME,    PLAN_HORIZON,      PLAN_HORIZON_UOM,   DEMAND_HORIZON
             , DEMAND_HORIZON_UOM, CONFIG_SET_ID,     BASIS_PLAN_ID,      DEMAND_PLAN_ID
             , SCP_PLAN_ID,        PLAN_WEEK,         CONFIRM_FLAG,       PRE_FIX_FLAG
             , PRE_FIX_TARGET_ID,  SYNC_OPERATION_ID, DESCRIPTION,        INSERT_ID
             , INSERT_TIME,        UPDATE_ID,         UPDATE_TIME,        PRE_FIX_DATE
             , PRE_FIX_TYPE,       PRE_FIX_DATE1,     PRE_FIX_TYPE1,      PRE_FIX_DATE2
             , PRE_FIX_TYPE2,      INTG_PLAN_ID
          )
          SELECT A.INSTANCE_ID, A.PLAN_ID, 'PRE' AS PLAN_TYPE, A.SITE_ID
               , dbo.FN_GET_BASISTIME(A.INSTANCE_ID, A.PLAN_ID) AS PLAN_START_TIME, A.FIX_DAY AS PLAN_HORIZON, 'DAY' AS PLAN_HORIZON_UOM, A.FIX_DAY AS DEMAND_HORIZON
               , 'DAY' AS DEMAND_HORIZON_UOM, 'LG_CHEM' AS CONFIG_SET_ID, A.PLAN_ID AS BASIS_PLAN_ID,  NULL AS DEMAND_PLAN_ID
               , NULL AS SCP_PLAN_ID, (SELECT ISO_YYYYWW FROM TH_UIS_CAL(NOLOCK) WHERE YYYYMMDD=A.PLAN_DATE) AS PLAN_WEEK, 'N' AS CONFIRM_FLAG, 'N' AS PRE_FIX_FLAG
               , NULL AS PRE_FIX_TARGET_ID,  NULL AS SYNC_OPERATION_ID, A.DESCRIPTION, A.USER_ID AS INSERT_ID
               , dbo.FN_SITE_TIME(A.SITE_ID) AS INSERT_TIME, A.USER_ID AS UPDATE_ID, dbo.FN_SITE_TIME(A.SITE_ID) AS UPDATE_TIME, CONVERT(DATE,@FIX_DATE) AS PRE_FIX_DATE
               , @FIX_TYPE AS PRE_FIX_TYPE, CONVERT(DATE,@FIX_DATE) AS PRE_FIX_DATE1, @FIX_TYPE AS PRE_FIX_TYPE1, NULL AS PRE_FIX_DATE2
               , NULL AS PRE_FIX_TYPE2, A.INTG_PLAN_ID
          FROM   (
          	SELECT A.INSTANCE_ID, (A.INSTANCE_ID + '-' + A.PLAN_DATE + '-' + B.SEQ) AS PLAN_ID, (A.TOTAL_INSTANCE_ID + '-' + A.PLAN_DATE + '-' + B.SEQ) AS INTG_PLAN_ID, A.SITE_ID, A.PLAN_DATE, A.USER_ID
          	     , DATEDIFF(DAY, CONVERT(DATETIME, @PLAN_DATE), CONVERT(DATETIME, @FIX_DATE)) AS FIX_DAY
          	     , (CASE WHEN CHARINDEX('CELL', A.INSTANCE_ID) > 0 THEN @DESC_CELL
		                     WHEN CHARINDEX('FORM', A.INSTANCE_ID) > 0 THEN @DESC_FORM
				                 WHEN CHARINDEX('E_PRE', A.INSTANCE_ID) > 0 THEN @DESC_ELEC
				                 ELSE '' END) AS DESCRIPTION
          	FROM   _INSTANCELIST A, _SEQ B
          ) A