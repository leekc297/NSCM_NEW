SELECT DISTINCT A.FACTORY_ID, A.ITEM_ID, A.PROD_VERSION_TYPE
							, CASE WHEN B.PROD_VERSION_TYPE IS NOT NULL THEN 1 ELSE 2 END IDX1
							, CASE WHEN A.PROD_VERSION_TYPE='GENERAL' THEN 1
									 WHEN A.PROD_VERSION_TYPE='WIDE' THEN 2
								 	 WHEN A.PROD_VERSION_TYPE='PREWET_UNIT2' THEN 3
								 	 WHEN A.PROD_VERSION_TYPE='PREWET_UNIT3' THEN 4
								 	 WHEN A.PROD_VERSION_TYPE='UNIT2' THEN 5
									 ELSE 6 
							  END AS IDX2
					FROM   	SCM_ITEM_CONV_CALC_M A WITH(NOLOCK)
							INNER JOIN FP_INSTANCE_FACTORY_M C WITH(NOLOCK)
							ON 1=1
							AND		A.FACTORY_ID = C.FACTORY_ID
							AND		C.INSTANCE_ID = @MASTER_ID
							AND		C.ACTIVE_FLAG = 'Y'
							LEFT OUTER JOIN (
									SELECT  DISTINCT A.SEGMENT4 AS FACTORY_ID, A.ATTRIBUTE1 AS PROD_VERSION_TYPE
									FROM   SCM_SYS_LOOKUP_VALUE A
									WHERE  A.LOOKUP_TYPE_CODE = 'LINE_PROD_VERSION_TYPE'
							) B
							ON A.FACTORY_ID = B.FACTORY_ID
							AND A.PROD_VERSION_TYPE = B.PROD_VERSION_TYPE
					WHERE  	1=1
					@CTRL_DIVISION_LT
					@CTRL_SITE_LT
					AND		A.OPERATION = 'E2000'
					AND		A.MAX_VER_FLAG = 'Y'
					AND		A.CATEGORY IN ('cell/batch','Pancake (m/batch)','Jumbo Roll (m/batch)')
					ORDER BY A.FACTORY_ID, A.ITEM_ID, IDX1, IDX2