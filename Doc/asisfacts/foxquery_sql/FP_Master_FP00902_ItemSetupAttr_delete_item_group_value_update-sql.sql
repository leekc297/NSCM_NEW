BEGIN
		        BEGIN TRAN
			
           MERGE INTO FP_INSTANCE_ITEM_SETUP_ATTR_VALUE_M A
        USING
        (
            SELECT @INSTANCE_ID AS INSTANCE_ID, @OPERATION_ID AS OPERATION_ID, 
			@ITEM_ID AS ITEM_ID

        ) B ON 1=1 
		AND A.INSTANCE_ID = B.INSTANCE_ID 
		AND A.OPERATION_ID = B.OPERATION_ID 
		AND A.ITEM_ID = B.ITEM_ID 
		
		WHEN MATCHED THEN
			DELETE;			

		        COMMIT;		       
		      END;