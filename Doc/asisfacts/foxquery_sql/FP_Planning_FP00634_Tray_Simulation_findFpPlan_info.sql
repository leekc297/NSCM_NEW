WITH RELEASE_PLAN AS (
          SELECT DISTINCT 
                 A.INSTANCE_ID
                ,A.RELEASE_PLAN_ID AS PLAN_ID
                ,STUFF(( SELECT ',' + FACTORY_ID
                         FROM   FP_RELEASE_PLAN_INFO_H B
                         WHERE  A.INSTANCE_ID     = B.INSTANCE_ID
                         AND    A.INSTANCE_DATE   = B.INSTANCE_DATE
                         AND    A.RELEASE_PLAN_ID = B.RELEASE_PLAN_ID
                         FOR XML PATH('') ),1,1,'') AS FACTORY_LT
                ,A.PLAN_GROUP_ID
                ,A.INSTANCE_DATE AS PLAN_DATE
          FROM   FP_RELEASE_PLAN_INFO_H A
          WHERE  1=1
          @CTRL_INSTANCE
          @CTRL_INSTANCE_DATE

      )
      SELECT A.PLAN_ID AS CODE, SUBSTRING(A.PLAN_ID,CHARINDEX('-',A.PLAN_ID)+1,11) AS NAME
            ,A.PLAN_ID
            ,A.PLAN_TYPE
            ,A.PLAN_START_TIME
            ,A.PLAN_HORIZON
            ,A.PLAN_HORIZON_UOM
            ,A.DEMAND_HORIZON
            ,A.DEMAND_HORIZON_UOM
            ,A.CONFIG_SET_ID
            ,A.BASIS_PLAN_ID
            ,A.DEMAND_PLAN_ID
            ,A.SCP_PLAN_ID
            ,A.PLAN_WEEK
            --,(SELECT DATED1 FROM TH_UIS_CALENDAR WHERE D0 = (SELECT ISO_YYYYWW FROM TH_UIS_CAL A WITH(NOLOCK) WHERE  YYYYMMDD = PLAN_DATE)) AS PLAN_START_DATE
            ,@PLAN_DATE AS PLAN_START_DATE
            ,CONVERT(VARCHAR, DATEADD(DD, 27, CONVERT(DATE,(SELECT DATED1 FROM TH_UIS_CALENDAR WHERE D0 = (SELECT ISO_YYYYWW FROM TH_UIS_CAL A WITH(NOLOCK) WHERE YYYYMMDD = @PLAN_DATE)))), 112) AS PLAN_END_DATE
            --,(SELECT DATED1 FROM TH_UIS_CALENDAR WHERE D0 = (SELECT ISO_YYYYWW FROM TH_UIS_CAL A WITH(NOLOCK) WHERE  YYYYMMDD = PLAN_DATE)) AS DEFAULT_START_DATE
            ,@PLAN_DATE AS DEFAULT_START_DATE
            ,CONVERT(VARCHAR, DATEADD(DD, 27, CONVERT(DATE,(SELECT DATED1 FROM TH_UIS_CALENDAR WHERE D0 = (SELECT ISO_YYYYWW FROM TH_UIS_CAL A WITH(NOLOCK) WHERE YYYYMMDD = @PLAN_DATE)))), 112) AS DEFAULT_END_DATE
            ,A.INSTANCE_ID
            ,A.SITE_ID
            ,A.DESCRIPTION
            ,A.PLAN_TYPE
            ,CASE WHEN A.RELEASE_FLAG = 'Y' THEN A.RELEASE_ID ELSE A.INSERT_ID END AS INSERT_ID
            ,CONVERT(VARCHAR, A.INSERT_TIME, 120) AS INSERT_TIME
            ,CASE WHEN A.RELEASE_FLAG = 'Y' 
            	  THEN (SELECT DISTINCT SA.DESCRIPTION FROM SCM_FP_PLAN_H SA WHERE A.INSTANCE_ID = SA.INSTANCE_ID AND A.BASIS_PLAN_ID = SA.PLAN_ID ) 
            	  ELSE A.DESCRIPTION END AS DESCS
            ,SUBSTRING(BASIS_PLAN_ID,CHARINDEX('-',BASIS_PLAN_ID)+1,11) AS BASIC_VERSION
            ,C.FACTORY_LT
            ,(CASE WHEN PLAN_TYPE = 'RELEASE' THEN 'N' -- input MPP WPP
				           WHEN RIGHT(A.PLAN_ID,2) = '00' THEN 'Y' ELSE 'N' END) READ_ONLY
      FROM   SCM_FP_PLAN_H A WITH(NOLOCK)
    	LEFT OUTER JOIN RELEASE_PLAN C WITH(NOLOCK)
  		ON  A.INSTANCE_ID = C.INSTANCE_ID
  		AND A.PLAN_ID     = C.PLAN_ID
      WHERE 1=1
     -- AND   A.PLAN_TYPE <> 'RELEASE'
      AND 	CHARINDEX('-00',A.PLAN_ID) = 0
      @CTRL_INSTANCE
	    @CTRL_START_TIME
 
      ORDER BY CONVERT(VARCHAR,A.PLAN_START_TIME,112) DESC, A.PLAN_ID DESC