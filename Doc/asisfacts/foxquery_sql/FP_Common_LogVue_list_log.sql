SELECT * FROM TH_UIS_SQL_LOG  WITH(NOLOCK)
      WHERE (ISNULL(@INSERT_USER,'')='' OR insert_id = @INSERT_USER)
    AND  INSERT_TIME >= CONVERT(DATETIME, @INSERT_FROM, 112)
    AND  INSERT_TIME <= CONVERT(DATETIME, @INSERT_TO, 112)
    AND (ISNULL(@JOB_TYPE,'')='' OR  JOB_TYPE=@JOB_TYPE)
    AND (ISNULL(@LOG_TYPE,'')='' OR  LOG_TYPE=@LOG_TYPE)
    AND (ISNULL(@PROG_ID,'')='' OR PROG_ID = @PROG_ID)
    ORDER BY INSERT_TIME DESC