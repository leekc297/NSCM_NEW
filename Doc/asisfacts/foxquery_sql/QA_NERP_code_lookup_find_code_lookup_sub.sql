SELECT A.LOOKUP_TYPE_CODE, A.LOOKUP_TYPE_CODE AS ORG_LOOKUP_TYPE_CODE 
            ,A.VALUE_DESCRIPTION 
    --,A.SYSTEM_TYPE_CODE 
    ,A.ACTIVE_FLAG 
    ,A.SEGMENT1 
    ,A.SEGMENT2 
    ,A.SEGMENT3 
    ,A.SEGMENT4 
    ,A.SEGMENT5 
    ,A.CREATE_USER_ID 
    ,CONVERT(VARCHAR, A.CREATE_DATE, 120) AS CREATE_DATE 
    ,A.MODIFY_USER_ID 
    ,ISNULL(CONVERT(VARCHAR, A.MODIFY_DATE, 120),CONVERT(VARCHAR, A.CREATE_DATE, 120)) AS MODIFY_DATE 
    ,A.ATTRIBUTE1 
    ,A.ATTRIBUTE2 
    ,A.ATTRIBUTE3 
    ,A.ATTRIBUTE4	
    ,A.ATTRIBUTE5	
    ,A.ATTRIBUTE6	
    ,A.ATTRIBUTE7	
    ,A.ATTRIBUTE8	
    ,A.ATTRIBUTE9	
    ,A.ATTRIBUTE10	
    ,A.ATTRIBUTE11	
    ,A.ATTRIBUTE12	
    ,A.ATTRIBUTE13	
    ,A.ATTRIBUTE14	
    ,A.ATTRIBUTE15	
    ,A.SORT_ORDER
     FROM   LGCE_SCMDEV.dbo.SCM_CODE_LOOKUP_VALUE A WITH(NOLOCK) 
     WHERE  1 = 1  
	AND (UPPER(A.LOOKUP_TYPE_CODE) LIKE (N'%' + @p_lookup_type_code +  '%')  OR ISNULL(@p_lookup_type_code,'') ='')
			 AND (A.ACTIVE_FLAG = @v_active_flag  OR ISNULL(@v_active_flag,'') ='')
		 AND (UPPER(A.SEGMENT1) LIKE (N'%' + @P_SEGMENT1+ '%') 	OR ISNULL(@P_SEGMENT1,'')='')
		 AND (UPPER(A.SEGMENT2) LIKE (N'%' + @P_SEGMENT2+ '%') OR ISNULL(@P_SEGMENT2,'')='')
		 AND (UPPER(A.SEGMENT3) LIKE (N'%' + @P_SEGMENT3+ '%') OR ISNULL(@P_SEGMENT3,'')='')
		 AND (UPPER(A.SEGMENT4) LIKE (N'%' + @P_SEGMENT4+ '%') OR ISNULL(@P_SEGMENT4,'')='')
		 AND (UPPER(A.SEGMENT5) LIKE (N'%' + @P_SEGMENT5+ '%') OR ISNULL(@P_SEGMENT5,'')='')
	
	 ORDER BY A.SORT_ORDER,LOOKUP_TYPE_CODE