BEGIN
		        BEGIN TRAN
				
MERGE INTO fp_line_setup_group_m A
-- KEY
using 
(
	SELECT 
	@INSTANCE_ID AS INSTANCE_ID,
  	@OPERATION_ID AS OPERATION_ID,
	@SETUP_CATEGORY_ID AS SETUP_CATEGORY_ID
	@SETUP_KEY_ID AS SETUP_KEY_ID
	@FROM_ITEM_SETUP_GROUP_ID AS FROM_SETUP_GROUP_ID
	@TO_ITEM_SETUP_GROUP_ID AS TO_SETUP_GROUP_ID	
) B
ON 1=1
AND A.INSTANCE_ID = B.INSTANCE_ID
AND A.OPERATION_ID = B.OPERATION_ID
AND A.SETUP_CATEGORY_ID = B.SETUP_CATEGORY_ID
AND A.SETUP_KEY_ID = B.SETUP_KEY_ID
AND A.FROM_SETUP_GROUP_ID = B.FROM_SETUP_GROUP_ID
AND A.TO_SETUP_GROUP_ID = B.TO_SETUP_GROUP_ID
WHEN MATCHED THEN
UPDATE SET ACTIVE_FLAG = ISNULL(@ACTIVE_FLAG,'Y')
        ,SETUP_TIME = @SETUP_TIME
		,SETUP_TIME_UOM = @SETUP_TIME_UOM
		,UPDATE_ID = @USER_ID
		,UPDATE_TIME =GETDATE()
WHEN NOT MATCHED THEN
INSERT (
 INSTANCE_ID,  OPERATION_ID,
 SETUP_CATEGORY_ID, SETUP_KEY_ID,
 FROM_SETUP_GROUP_ID,TO_SETUP_GROUP_ID,
 SETUP_TIME,SETUP_TIME_UOM,
 ACTIVE_FLAG, DESCRIPTION,
 INSERT_ID, INSERT_TIME, UPDATE_ID,   UPDATE_TIME                             
) VALUES (
 @INSTANCE_ID,  @OPERATION_ID,
 @SETUP_CATEGORY_ID, ISNULL(@SETUP_KEY_ID,'-'),
 @FROM_SETUP_GROUP_ID,@TO_SETUP_GROUP_ID,
 @SETUP_TIME,ISNULL(@SETUP_TIME_UOM,'minute'),
 ISNULL(@ACTIVE_FLAG,'Y'), @DESCRIPTION,
 @USER_ID,GetDATE(),@USER_ID,GetDate()
);

INSERT INTO his_fp_line_setup_group_m
(
 INSTANCE_ID,  OPERATION_ID,
 SETUP_CATEGORY_ID, SETUP_KEY_ID,
 FROM_SETUP_GROUP_ID,TO_SETUP_GROUP_ID,
 SETUP_TIME,SETUP_TIME_UOM,
 ACTIVE_FLAG, DESCRIPTION,
 INSERT_ID, INSERT_TIME, UPDATE_ID,   UPDATE_TIME,
 JOB_USER_ID, JOB_TIME,JOB_TYPE, JOB_SEQ
) VALUES
{
 @INSTANCE_ID,  @OPERATION_ID,
 @SETUP_CATEGORY_ID, ISNULL(@SETUP_KEY_ID,'-'),
 @FROM_SETUP_GROUP_ID,@TO_SETUP_GROUP_ID,
 @SETUP_TIME,ISNULL(@SETUP_TIME_UOM,'minute'),
 ISNULL(@ACTIVE_FLAG,'Y'), @DESCRIPTION,
 @USER_ID,GetDATE(),@USER_ID,GetDate(),
 @USER_ID, GetDate(),'U',0
)

		        COMMIT;		       
		      END;