BEGIN
    		INSERT INTO FP_MPP_WPP_BASE_PLAN_M (
               PLAN_WEEK, PLAN_REVISION
              ,COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, FACTORY_ID
              ,LINE_ID, OPERATION_ID, EQUIPMENT_ID, ITEM_ID, PRODUCTION_TYPE, MARKET
              ,PLAN_DATE
              ,PLAN_QTY
            	,INSERT_ID,INSERT_TIME,UPDATE_ID,UPDATE_TIME
    		)
    		VALUES (
               RTRIM(LTRIM(@PLAN_WEEK)), RTRIM(LTRIM(@PLAN_REVISION))
              ,RTRIM(LTRIM(@COMPANY_ID)), RTRIM(LTRIM(@DIVISION_ID)), RTRIM(LTRIM(@SITE_ID)), RTRIM(LTRIM(@PLANT_ID)), RTRIM(LTRIM(@FACTORY_ID))
              ,RTRIM(LTRIM(@LINE_ID)), RTRIM(LTRIM(@OPERATION_ID)), RTRIM(LTRIM(@EQUIPMENT_ID)), RTRIM(LTRIM(@ITEM_ID)), UPPER(RTRIM(LTRIM(@PRODUCTION_TYPE))), UPPER(RTRIM(LTRIM(@MARKET)))
              ,CONVERT(DATE,RTRIM(LTRIM(@PLAN_DATE))),(CASE WHEN RTRIM(LTRIM(@PLAN_QTY)) = '' THEN 0 ELSE CONVERT(NUMERIC(20,10),RTRIM(LTRIM(@PLAN_QTY))) END)
          		,@USER_ID, dbo.SYSDATE1(), @USER_ID, dbo.SYSDATE1()
    		)
    		;
      	
      	INSERT INTO HIS_MPP_WPP_BASE_PLAN_M (
               PLAN_WEEK, PLAN_REVISION
              ,COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, FACTORY_ID
              ,LINE_ID, OPERATION_ID, EQUIPMENT_ID, ITEM_ID, PRODUCTION_TYPE
              ,PLAN_DATE, PLAN_QTY
            	,INSERT_ID,INSERT_TIME,UPDATE_ID,UPDATE_TIME
              ,JOB_USER_ID, JOB_TIME,JOB_TYPE
      	)
      	SELECT PLAN_WEEK, PLAN_REVISION
      	      ,COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, FACTORY_ID
              ,LINE_ID, OPERATION_ID, EQUIPMENT_ID, ITEM_ID, PRODUCTION_TYPE
              ,PLAN_DATE, PLAN_QTY
            	,INSERT_ID,INSERT_TIME,UPDATE_ID,UPDATE_TIME
           		,@USER_ID AS JOB_USER_ID, GETDATE() AS JOB_TIME, 'EXCEL' AS JOB_TYPE
      	FROM   FP_MPP_WPP_BASE_PLAN_M A
      	WHERE  A.PLAN_WEEK        = @PLAN_WEEK
        AND    A.PLAN_REVISION    = @PLAN_REVISION
        AND    A.FACTORY_ID       = @FACTORY_ID
        AND    A.LINE_ID          = @LINE_ID
        AND    A.OPERATION_ID     = @OPERATION_ID
        AND    A.EQUIPMENT_ID     = @EQUIPMENT_ID
        AND    A.ITEM_ID          = @ITEM_ID
        AND    A.PRODUCTION_TYPE  = @PRODUCTION_TYPE
        AND    A.MARKET           = @MARKET
        AND    A.PLAN_DATE        = CONVERT(DATE,@PLAN_DATE)
      	;
      	
      END;