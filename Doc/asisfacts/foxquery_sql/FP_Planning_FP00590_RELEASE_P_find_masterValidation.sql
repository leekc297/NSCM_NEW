SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID
             , A.PLAN_DATE
             , A.CHECK_CATEGORY
             , A.CHECK_TABLE
             , A.PROBLEM_TYPE
             , A.CHECK_DATA
             , A.PROBLEM_DATA, B.NICK_NAME AS PROBLEM_DATA_NICK
             , A.PROBLEM_LIST
             , A.REFERENCE_TABLE
             , A.CHECK_UI
             , A.PROBLEM_DESCRIPTION
             , A.TOP_ITEM_ID, C.NICK_NAME AS TOP_ITEM_ID_NICK
             , A.INSTANCE_ID, D.INSTANCE_NAME
             , A.INSERT_ID, CONVERT(VARCHAR, A.INSERT_TIME, 120) AS INSERT_TIME
        FROM   FP_MASTER_VALIDATION_H A WITH(NOLOCK)
        LEFT OUTER JOIN SCM_ITEM_M B WITH(NOLOCK)
        ON  A.COMPANY_ID   = B.COMPANY_ID
        AND A.DIVISION_ID  = B.DIVISION_ID
        AND A.SITE_ID      = B.SITE_ID
        AND A.PROBLEM_DATA = B.ITEM_ID
        LEFT OUTER JOIN SCM_ITEM_M C WITH(NOLOCK)
        ON  A.COMPANY_ID   = C.COMPANY_ID
        AND A.DIVISION_ID  = C.DIVISION_ID
        AND A.SITE_ID      = C.SITE_ID
        AND A.TOP_ITEM_ID  = C.ITEM_ID
        LEFT OUTER JOIN (
        	SELECT A.SEGMENT1 AS INSTANCE_ID,A.SEGMENT2 AS INSTANCE_NAME
        	FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
        	WHERE  A.LOOKUP_TYPE_CODE = 'INSTANCE_ID'
        	AND    A.ACTIVE_FLAG = 'Y'
        ) D
        ON  A.INSTANCE_ID = D.INSTANCE_ID
        WHERE 1=1
        AND   A.INSTANCE_ID = @INSTANCE_ID
        AND   A.PLAN_DATE   = CONVERT(DATETIME, @PLAN_DATE)
        ORDER BY A.INSTANCE_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.TOP_ITEM_ID, A.PROBLEM_TYPE, A.CHECK_UI, A.PROBLEM_DATA