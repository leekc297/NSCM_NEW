SELECT SEGMENT1 AS INSTNACE_ID, ATTRIBUTE7 AS CREATE_PLAN_FIX_DATE_YN, ATTRIBUTE8 AS CREATE_PLAN_FIX_DATE,* from scm_sys_lookup_value with(nolock)
where 1=1
AND lookup_type_code = 'CONTROL_PLAN_CREATE_RELEASE_BY_INSTANCE'
AND SEGMENT1 = @INSTANCE_ID
AND ATTRIBUTE7 = 'Y' -- CREATE_PLAN_FIX_DATE_YN
AND ACTIVE_FLAG = 'Y'