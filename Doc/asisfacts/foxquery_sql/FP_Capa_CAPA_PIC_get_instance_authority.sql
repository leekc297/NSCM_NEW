WITH WITH_ROLE_FACTORY AS (
    SELECT ROLE_ID, ROLE_NAME, UPPER_ROLE_ID, ROLE_DETAIL_ORDER, ROLE_DESCR, APPROVAL_EXCEPTION_FLAG,
        	INSERT_ID, INSERT_DTTM, UPDATE_ID, UPDATE_DTTM, 
        	1 AS LEVEL,CONVERT(NVARCHAR(255), REPLICATE('0',(3-LEN(CAST(ROLE_DETAIL_ORDER AS VARCHAR)))) + CAST(ROLE_DETAIL_ORDER AS VARCHAR)) AS SORT
    FROM   TH_UIS_ROLE_INSTANCE T WITH(NOLOCK)
    WHERE UPPER_ROLE_ID IS NULL
    UNION ALL
    SELECT C.ROLE_ID, C.ROLE_NAME, C.UPPER_ROLE_ID, C.ROLE_DETAIL_ORDER, C.ROLE_DESCR, C.APPROVAL_EXCEPTION_FLAG,
        	C.INSERT_ID, C.INSERT_DTTM, C.UPDATE_ID, C.UPDATE_DTTM, 
        	LEVEL+1,CONVERT(NVARCHAR(255), RTRIM(P.SORT) + REPLICATE('0',(3-LEN(CAST(C.ROLE_DETAIL_ORDER AS VARCHAR)))) + CAST(C.ROLE_DETAIL_ORDER AS VARCHAR)) AS SORT
    FROM   TH_UIS_ROLE_INSTANCE C WITH(NOLOCK)
    INNER JOIN WITH_ROLE_FACTORY P ON C.UPPER_ROLE_ID = P.ROLE_ID
)
SELECT A.ROLE_ID
    , A.ROLE_NAME
    , A.UPPER_ROLE_ID
    , ( SELECT ROLE_NAME FROM TH_UIS_ROLE_INSTANCE B WITH(NOLOCK) WHERE B.ROLE_ID=A.UPPER_ROLE_ID) AS UPPER_ROLE_NAME
    , A.ROLE_DESCR
    , A.ROLE_DETAIL_ORDER
    , A.APPROVAL_EXCEPTION_FLAG
    , A.INSERT_ID
    , CONVERT(VARCHAR(8),A.INSERT_DTTM,112) INSERT_DTTM
    , A.UPDATE_ID
    , CONVERT(VARCHAR(8),A.UPDATE_DTTM,112) UPDATE_DTTM
    , LEVEL AS LVL
    , CASE LEVEL WHEN '3' THEN '2' ELSE '1' END IMG
FROM   WITH_ROLE_FACTORY A
ORDER BY SORT		    

   		      --  COMMIT;
