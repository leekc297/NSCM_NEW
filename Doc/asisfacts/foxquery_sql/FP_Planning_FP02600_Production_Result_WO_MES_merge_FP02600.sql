BEGIN
        
        MERGE INTO FP_MES_WORK_ORDER_STATUS_H A
          USING (SELECT RTRIM(LTRIM(@COMPANY_ID)) AS COMPANY_ID, RTRIM(LTRIM(@DIVISION_ID)) AS DIVISION_ID, RTRIM(LTRIM(@SITE_ID)) AS SITE_ID, RTRIM(LTRIM(@PLANT_ID)) AS PLANT_ID,
                        RTRIM(LTRIM(@FACTORY_ID)) AS FACTORY_ID, RTRIM(LTRIM(@CUTOFF_DATE)) AS CUTOFF_DATE, RTRIM(LTRIM(@WORK_ORDER_SPL_ID)) AS WORK_ORDER_SPL_ID) B
          ON (A.COMPANY_ID        = B.COMPANY_ID
          AND A.DIVISION_ID       = B.DIVISION_ID
          AND A.SITE_ID           = B.SITE_ID
          AND A.PLANT_ID          = B.PLANT_ID
          AND A.FACTORY_ID        = B.FACTORY_ID
          AND CONVERT(VARCHAR, A.CUTOFF_DATE, 112) = B.CUTOFF_DATE
          AND A.WORK_ORDER_SPL_ID = B.WORK_ORDER_SPL_ID)
        WHEN MATCHED THEN
          UPDATE SET
                WORK_ORDER_ID     = RTRIM(LTRIM(@WORK_ORDER_ID))
              , ORDER_TYPE        = RTRIM(LTRIM(@ORDER_TYPE))
              , ITEM_ID           = RTRIM(LTRIM(@ITEM_ID))
              , TOP_ITEM_ID       = RTRIM(LTRIM(@TOP_ITEM_ID))
              , OPERATION_ID      = RTRIM(LTRIM(@OPERATION_ID))
              , LINE_ID           = RTRIM(LTRIM(@LINE_ID))
              , WORK_CENTER_ID    = RTRIM(LTRIM(@WORK_CENTER_ID))
              , EQUIPMENT_ID      = RTRIM(LTRIM(@EQUIPMENT_ID))
              , PLAN_DATE         = CONVERT(DATETIME, RTRIM(LTRIM(@PLAN_DATE)))
              , PLAN_START_TIME   = CONVERT(DATETIME, RTRIM(LTRIM(@PLAN_START_TIME)))
              , PLAN_END_TIME     = CONVERT(DATETIME, RTRIM(LTRIM(@PLAN_END_TIME)))
              , PLAN_QTY          = RTRIM(LTRIM(@PLAN_QTY))
              , ACTUAL_START_TIME = CONVERT(DATETIME, RTRIM(LTRIM(@ACTUAL_START_TIME)))
              , ACTUAL_END_TIME   = CONVERT(DATETIME, RTRIM(LTRIM(@ACTUAL_END_TIME)))
              , ACTUAL_QTY        = RTRIM(LTRIM(@ACTUAL_QTY))
              , ACTUAL_GOOD_QTY   = RTRIM(LTRIM(@ACTUAL_GOOD_QTY))
              , ACTUAL_SCRAP_QTY  = RTRIM(LTRIM(@ACTUAL_SCRAP_QTY))
              , RUNNING_FLAG      = RTRIM(LTRIM(@RUNNING_FLAG))
              , WO_STATUS         = RTRIM(LTRIM(@WO_STATUS))
        WHEN NOT MATCHED THEN
          INSERT (
              COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, FACTORY_ID, CUTOFF_DATE, WORK_ORDER_SPL_ID,
              WORK_ORDER_ID, ORDER_TYPE, ITEM_ID, TOP_ITEM_ID, OPERATION_ID, LINE_ID, 
              WORK_CENTER_ID, EQUIPMENT_ID, PLAN_DATE, PLAN_START_TIME, PLAN_END_TIME, PLAN_QTY, 
              ACTUAL_START_TIME, ACTUAL_END_TIME, ACTUAL_QTY, ACTUAL_GOOD_QTY, ACTUAL_SCRAP_QTY,
              RUNNING_FLAG, WO_STATUS, INSERT_ID, INSERT_TIME
          )
          VALUES (
              RTRIM(LTRIM(@COMPANY_ID)), RTRIM(LTRIM(@DIVISION_ID)), RTRIM(LTRIM(@SITE_ID)), RTRIM(LTRIM(@PLANT_ID)), RTRIM(LTRIM(@FACTORY_ID)), CONVERT(DATETIME, RTRIM(LTRIM(@CUTOFF_DATE))), RTRIM(LTRIM(@WORK_ORDER_SPL_ID)),
              RTRIM(LTRIM(@WORK_ORDER_ID)), RTRIM(LTRIM(@ORDER_TYPE)), RTRIM(LTRIM(@ITEM_ID)), RTRIM(LTRIM(@TOP_ITEM_ID)), RTRIM(LTRIM(@OPERATION_ID)), RTRIM(LTRIM(@LINE_ID)),
              RTRIM(LTRIM(@WORK_CENTER_ID)), RTRIM(LTRIM(@EQUIPMENT_ID)), CONVERT(DATETIME, RTRIM(LTRIM(@PLAN_DATE))),
              CONVERT(DATETIME, RTRIM(LTRIM(@PLAN_START_TIME))), CONVERT(DATETIME, RTRIM(LTRIM(@PLAN_END_TIME))), RTRIM(LTRIM(@PLAN_QTY)),
              CONVERT(DATETIME, RTRIM(LTRIM(@ACTUAL_START_TIME))), CONVERT(DATETIME, RTRIM(LTRIM(@ACTUAL_END_TIME))), RTRIM(LTRIM(@ACTUAL_QTY)), RTRIM(LTRIM(@ACTUAL_GOOD_QTY)), RTRIM(LTRIM(@ACTUAL_SCRAP_QTY)),
              RTRIM(LTRIM(@RUNNING_FLAG)), RTRIM(LTRIM(@WO_STATUS)), @USER_ID, dbo.SYSDATE1()
          )
          ;
      
        INSERT INTO HIS_MES_WORK_ORDER_STATUS_H (
               COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, FACTORY_ID, 
               CUTOFF_DATE, WORK_ORDER_SPL_ID, WORK_ORDER_ID, ORDER_TYPE, ITEM_ID, TOP_ITEM_ID, 
               OPERATION_ID, LINE_ID, WORK_CENTER_ID, EQUIPMENT_ID, PLAN_DATE, PLAN_START_TIME, 
               PLAN_END_TIME, PLAN_QTY, ACTUAL_START_TIME, ACTUAL_END_TIME, ACTUAL_QTY, ACTUAL_GOOD_QTY, ACTUAL_SCRAP_QTY,
               RUNNING_FLAG, WO_STATUS, INSERT_ID, INSERT_TIME, 
               JOB_USER_ID, JOB_TIME, JOB_TYPE
        )
        SELECT COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, FACTORY_ID, 
               CUTOFF_DATE, WORK_ORDER_SPL_ID, WORK_ORDER_ID, ORDER_TYPE, ITEM_ID, TOP_ITEM_ID, 
               OPERATION_ID, LINE_ID, WORK_CENTER_ID, EQUIPMENT_ID, PLAN_DATE, PLAN_START_TIME, 
               PLAN_END_TIME, PLAN_QTY, ACTUAL_START_TIME, ACTUAL_END_TIME, ACTUAL_QTY, ACTUAL_GOOD_QTY, ACTUAL_SCRAP_QTY,
               RUNNING_FLAG, WO_STATUS, INSERT_ID, INSERT_TIME, 
               @USER_ID, dbo.SYSDATE1(), 'EXCEL'
        FROM   FP_MES_WORK_ORDER_STATUS_H A(NOLOCK)
        WHERE  COMPANY_ID        = RTRIM(LTRIM(@COMPANY_ID))
        AND    DIVISION_ID       = RTRIM(LTRIM(@DIVISION_ID))
        AND    SITE_ID           = RTRIM(LTRIM(@SITE_ID))
        AND    PLANT_ID          = RTRIM(LTRIM(@PLANT_ID))
        AND    FACTORY_ID        = RTRIM(LTRIM(@FACTORY_ID))
        AND    CUTOFF_DATE       = CONVERT(DATE, RTRIM(LTRIM(@CUTOFF_DATE)))
        AND    WORK_ORDER_SPL_ID = RTRIM(LTRIM(@WORK_ORDER_SPL_ID))
        ;
      
      END;