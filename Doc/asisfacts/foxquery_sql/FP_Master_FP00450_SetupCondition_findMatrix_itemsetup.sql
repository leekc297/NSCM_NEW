SELECT '-' AS COMPANY_ID, '-' AS DIVISION_ID, '-' AS SITE_ID, '-' AS PLANT_ID, '-' AS OPERATION_ID
           , '-' AS LINE_SETUP_GROUP_ID, '-' AS SETUP_CATEGORY_ID, '-' AS SETUP_KEY_ID, 'ALL' AS ITEM_SETUP_GROUP_ID
           , 'ALL' AS CODE, 'ALL' AS NAME, 1 AS ORDERBY
      UNION ALL
      SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, B.PLANT_ID, A.OPERATION_ID
           , B.LINE_SETUP_GROUP_ID, A.SETUP_CATEGORY_ID, A.SETUP_KEY_ID, A.ITEM_SETUP_GROUP_ID
           , A.ITEM_SETUP_GROUP_ID AS CODE_ID, A.ITEM_SETUP_GROUP_ID AS CODE_NAME, 2 AS ORDERBY
      FROM   SCM_ITEM_SETUP_GROUP_M A WITH(NOLOCK) INNER JOIN SCM_LINE_SETUP_GROUP_M B WITH(NOLOCK)
      ON  A.COMPANY_ID   = B.COMPANY_ID
      AND A.DIVISION_ID  = B.DIVISION_ID
      AND A.SITE_ID      = B.SITE_ID
      AND A.OPERATION_ID = B.OPERATION_ID
      GROUP BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, B.PLANT_ID, A.OPERATION_ID
             , B.LINE_SETUP_GROUP_ID, A.SETUP_CATEGORY_ID, A.SETUP_KEY_ID, A.ITEM_SETUP_GROUP_ID
      ORDER BY ORDERBY, CODE