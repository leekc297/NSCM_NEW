WITH _PLAN_INFO AS (
          	SELECT INSTANCE_ID, PLAN_ID
          	FROM   SCM_FP_PLAN_H A WITH(NOLOCK)
          	WHERE  A.INTG_PLAN_ID  = @INTG_PLAN_ID
          )
          SELECT A.*
          	 , CASE WHEN A.STATUS_FLAG = 'R' THEN 'Ready'
          		    WHEN A.STATUS_FLAG = 'P' THEN 'Processing'+CASE WHEN A.STATUS_START IS NOT NULL THEN ' ('+CONVERT(VARCHAR,DATEDIFF(SECOND,A.STATUS_START,GETDATE())/60) + ':' + CONVERT(VARCHAR,DATEDIFF(SECOND,A.STATUS_START,GETDATE())-(DATEDIFF(SECOND,A.STATUS_START,GETDATE())/60)*60) + ')' END
          		    --WHEN A.STATUS_FLAG = 'C' THEN 'Completed' +CASE WHEN A.STATUS_END   IS NOT NULL THEN ' ('+CONVERT(VARCHAR, A.STATUS_START, 20) + '  /  '  + CONVERT(VARCHAR,DATEDIFF(SECOND,A.STATUS_START,A.STATUS_END)/60) + ':' + CONVERT(VARCHAR,DATEDIFF(SECOND,A.STATUS_START,A.STATUS_END)-(DATEDIFF(SECOND,A.STATUS_START,A.STATUS_END)/60)*60) + ')' END
          		    WHEN A.STATUS_FLAG = 'C' THEN 'Completed' +CASE WHEN A.STATUS_END   IS NOT NULL THEN ' ('+CONVERT(VARCHAR, A.STATUS_START, 20) + ' / ' +CONVERT(VARCHAR, A.STATUS_END, 20) + '(' + CONVERT(VARCHAR,DATEDIFF(SECOND,A.STATUS_START,A.STATUS_END)/60) + ':' + CONVERT(VARCHAR,DATEDIFF(SECOND,A.STATUS_START,A.STATUS_END)-(DATEDIFF(SECOND,A.STATUS_START,A.STATUS_END)/60)*60) + '))' END
          		    WHEN A.STATUS_FLAG = 'E' THEN 'Error'
          	        ELSE NULL END AS STATUS_MSG
          FROM (
          	SELECT MAX(ENGINE_STATUS) AS ENGINE_STATUS
          		 , MAX(STATUS_NAME) AS STATUS_NAME 
          		 , MAX(STATUS_FLAG) AS STATUS_FLAG
          		 , MAX(STATUS_STEP) AS STATUS_STEP
          		 , MAX(STATUS_START) AS STATUS_START, MIN(STATUS_END) AS STATUS_END
          	FROM (
          		SELECT (CASE WHEN RNUM = 1 THEN ENGINE_STATUS ELSE '' END) AS ENGINE_STATUS
          			 , (CASE WHEN RNUM = 1 THEN STATUS_NAME   ELSE '' END) AS STATUS_NAME
          			 , (CASE WHEN RNUM = 1 THEN STATUS_FLAG   ELSE '' END) AS STATUS_FLAG
          			 , (CASE WHEN RNUM = 1 THEN STATUS_STEP   ELSE '' END) AS STATUS_STEP
          			 , (CASE WHEN RNUM = 1 THEN STATUS_START  ELSE CONVERT(DATETIME, '1990-01-01') END) AS STATUS_START
          			 , (CASE WHEN RNUM2 = 1 THEN STATUS_END   ELSE CONVERT(DATETIME, '2999-01-01') END) AS STATUS_END
          			 , RNUM, RNUM2
          		FROM (
          			SELECT A.*
          				 , ROW_NUMBER() OVER ( PARTITION BY A.ENGINE_STATUS, A.STATUS_NAME ORDER BY A.STATUS_STEP, A.STATUS_START ) AS RNUM
          				 , ROW_NUMBER() OVER ( PARTITION BY A.ENGINE_STATUS, A.STATUS_NAME ORDER BY A.STATUS_STEP DESC, A.STATUS_END DESC ) AS RNUM2
          			FROM (
          			   SELECT 'INBOUND' AS ENGINE_STATUS, 'Input Data Create' AS STATUS_NAME, 
          				   A.INBOUND_FLAG AS STATUS_FLAG, A.INBOUND_STEP AS STATUS_STEP ,      
          				   FORMAT(A.INBOUND_START ,'yyyy-MM-dd HH:mm:ss') AS STATUS_START ,  
          				   FORMAT(A.INBOUND_END   ,'yyyy-MM-dd HH:mm:ss') AS STATUS_END
          			   FROM   FP_PLAN_STATUS_H A(NOLOCK), _PLAN_INFO B with(nolock)
          			   WHERE  A.INSTANCE_ID = B.INSTANCE_ID
          			   AND    A.PLAN_ID     = B.PLAN_ID
          			) A
          		) A
          	) A
          	UNION ALL
          	SELECT MAX(ENGINE_STATUS) AS ENGINE_STATUS
          		 , MAX(STATUS_NAME) AS STATUS_NAME 
          		 , MAX(STATUS_FLAG) AS STATUS_FLAG
          		 , MAX(STATUS_STEP) AS STATUS_STEP
          		 , MAX(STATUS_START) AS STATUS_START, MIN(STATUS_END) AS STATUS_END
          	FROM (
          		SELECT (CASE WHEN RNUM = 1 THEN ENGINE_STATUS ELSE '' END) AS ENGINE_STATUS
          			 , (CASE WHEN RNUM = 1 THEN STATUS_NAME   ELSE '' END) AS STATUS_NAME
          			 , (CASE WHEN RNUM = 1 THEN STATUS_FLAG   ELSE '' END) AS STATUS_FLAG
          			 , (CASE WHEN RNUM = 1 THEN STATUS_STEP   ELSE '' END) AS STATUS_STEP
          			 , (CASE WHEN RNUM = 1 THEN STATUS_START  ELSE CONVERT(DATETIME, '1990-01-01') END) AS STATUS_START
          			 , (CASE WHEN RNUM2 = 1 THEN STATUS_END   ELSE CONVERT(DATETIME, '2999-01-01') END) AS STATUS_END
          			 , RNUM, RNUM2
          		FROM (
          			SELECT A.*
          				 --, ROW_NUMBER() OVER ( PARTITION BY A.ENGINE_STATUS, A.STATUS_NAME ORDER BY A.STATUS_STEP, A.STATUS_START ) AS RNUM
          				 , ROW_NUMBER() OVER ( PARTITION BY A.ENGINE_STATUS, A.STATUS_NAME ORDER BY A.STATUS_STEP DESC, A.STATUS_START DESC ) AS RNUM
          				 , ROW_NUMBER() OVER ( PARTITION BY A.ENGINE_STATUS, A.STATUS_NAME ORDER BY A.STATUS_STEP DESC, A.STATUS_END DESC ) AS RNUM2
          			FROM (
          			   SELECT 'ENGINE' AS ENGINE_STATUS, 'Engine Running' AS STATUS_NAME, 
          				   A.ENGINE_FLAG AS STATUS_FLAG, A.ENGINE_STEP AS STATUS_STEP ,      
          				   FORMAT(A.ENGINE_START ,'yyyy-MM-dd HH:mm:ss') AS STATUS_START ,
          				   FORMAT(A.ENGINE_END   ,'yyyy-MM-dd HH:mm:ss') AS STATUS_END
          			   FROM   FP_PLAN_STATUS_H A(NOLOCK), _PLAN_INFO B with(nolock)
          			   WHERE  A.INSTANCE_ID = B.INSTANCE_ID
          			   AND    A.PLAN_ID     = B.PLAN_ID
          			) A
          		) A
          	) A
          	UNION ALL
          	SELECT MAX(ENGINE_STATUS) AS ENGINE_STATUS
          		 , MAX(STATUS_NAME) AS STATUS_NAME 
          		 , MAX(STATUS_FLAG) AS STATUS_FLAG
          		 , MAX(STATUS_STEP) AS STATUS_STEP
          		 , MAX(STATUS_START) AS STATUS_START, MIN(STATUS_END) AS STATUS_END
          	FROM (
          		SELECT (CASE WHEN RNUM = 1 THEN ENGINE_STATUS ELSE '' END) AS ENGINE_STATUS
          			 , (CASE WHEN RNUM = 1 THEN STATUS_NAME   ELSE '' END) AS STATUS_NAME
          			 , (CASE WHEN RNUM = 1 THEN STATUS_FLAG   ELSE '' END) AS STATUS_FLAG
          			 , (CASE WHEN RNUM = 1 THEN STATUS_STEP   ELSE '' END) AS STATUS_STEP
          			 , (CASE WHEN RNUM = 1 THEN STATUS_START  ELSE CONVERT(DATETIME, '1990-01-01') END) AS STATUS_START
          			 , (CASE WHEN RNUM2 = 1 THEN STATUS_END   ELSE CONVERT(DATETIME, '2999-01-01') END) AS STATUS_END
          			 , RNUM, RNUM2
          		FROM (
          			SELECT A.*
          				 --, ROW_NUMBER() OVER ( PARTITION BY A.ENGINE_STATUS, A.STATUS_NAME ORDER BY A.STATUS_STEP, A.STATUS_START ) AS RNUM
          				 , ROW_NUMBER() OVER ( PARTITION BY A.ENGINE_STATUS, A.STATUS_NAME ORDER BY A.STATUS_STEP DESC, A.STATUS_START DESC ) AS RNUM
          				 , ROW_NUMBER() OVER ( PARTITION BY A.ENGINE_STATUS, A.STATUS_NAME ORDER BY A.STATUS_STEP DESC, A.STATUS_END DESC ) AS RNUM2
          			FROM (
          			   SELECT 'OUTBOUND' AS ENGINE_STATUS, 'Output Data Create' AS STATUS_NAME, 
          				   A.OUTBOUND_FLAG AS STATUS_FLAG, A.OUTBOUND_STEP AS STATUS_STEP ,      
          				   FORMAT(A.OUTBOUND_START ,'yyyy-MM-dd HH:mm:ss') AS STATUS_START ,  
          				   FORMAT(A.OUTBOUND_END   ,'yyyy-MM-dd HH:mm:ss') AS STATUS_END
          			   FROM   FP_PLAN_STATUS_H A(NOLOCK), _PLAN_INFO B with(nolock)
          			   WHERE  A.INSTANCE_ID = B.INSTANCE_ID
          			   AND    A.PLAN_ID     = B.PLAN_ID
          			) A
          		) A
          	) A
          ) A