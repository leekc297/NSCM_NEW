-- BOM 전개 코드 :  1순위 --
    	SELECT DISTINCT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID
    			, A.PARENT_ITEM_ID, A.PARENT_UOM
    			, A.CHILD_ITEM_ID AS P5000_ITEM_ID, A.CHILD_UOM
    			, A.CHILD_QTY/A.PARENT_QTY AS BOM_RATE_P5000 
    			, B.CHILD_ITEM_ID AS CELL_ITEM_ID , B.BOM_RATE_CELL 
    			, B.MONTH 
    			, RANK() OVER(  PARTITION BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.PARENT_ITEM_ID , A.EFF_START_DATE, A.EFF_END_DATE 
            							ORDER BY    CASE WHEN B.PRIORITY IS NULL THEN 99 ELSE B.PRIORITY END
            									,	CASE WHEN B.ALT_PRIORITY IS NULL THEN 99 ELSE B.ALT_PRIORITY END
            									,	CASE WHEN A.ALT_PRIORITY IS NULL THEN 99 ELSE A.ALT_PRIORITY END
            					 ) RNK
    	FROM	SCM_BOM_M A WITH(NOLOCK)
    	INNER HASH JOIN ( --: PACK쪽 인스턴스만 필터링
    			SELECT DISTINCT B.COMPANY_ID, B.DIVISION_ID, B.SITE_ID, B.PLANT_ID
    			FROM   FP_INSTANCE_FACTORY_M A WITH(NOLOCK), SCM_FACTORY_M B WITH(NOLOCK)
    			WHERE  A.FACTORY_ID = B.FACTORY_ID
    			AND    A.ACTIVE_FLAG = 'Y'
    			AND    B.ACTIVE_FLAG = 'Y'
    			AND    A.INSTANCE_ID = @PACK_INSTANCE_ID -- pack instance 기준 plant
    	) E
    	ON   1=1
    	AND  A.COMPANY_ID = E.COMPANY_ID
    	AND  A.DIVISION_ID = E.DIVISION_ID
    	AND  A.SITE_ID     = E.SITE_ID
    	AND  A.PLANT_ID    = E.PLANT_ID
    	INNER HASH JOIN ( --: PACK ITEM 필터조건
    			SELECT CC.COMPANY_ID, CC.DIVISION_ID, CC.SITE_ID, CC.ITEM_ID, CC.ITEM_CLASS, DD.LEVEL_3_CODE, DD.LEVEL_3_NAME, CC.FLOW_ID
    			FROM   SCM_ITEM_M CC WITH(NOLOCK),	SCM_ITEM_CLASS_M DD WITH(NOLOCK)
    			WHERE  1=1
    			AND    CC.ITEM_CLASS  = DD.CLASS_ID
    			AND    CC.ACTIVE_FLAG = 'Y'
    			AND    DD.USE_FLAG    = 'Y'
    			AND    DD.LEVEL_3_NAME IN ('Pack', 'Module' )
    			AND    LEFT(ISNULL(CC.FLOW_ID,'Z'),5)  IN ( 'P9500','P5500')
    	) CC
    	ON   1=1
    	AND  A.COMPANY_ID  = CC.COMPANY_ID
    	AND  A.DIVISION_ID = CC.DIVISION_ID
    	AND  A.SITE_ID     = CC.SITE_ID
    	AND  A.PARENT_ITEM_ID = CC.ITEM_ID 
    	INNER HASH JOIN ( ---B: CELL ITEM 검색
    			SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID , A.PLANT_ID , A.PARENT_ITEM_ID , A.CHILD_ITEM_ID , A.CHILD_QTY/A.PARENT_QTY AS BOM_RATE_CELL , A.ALT_ID, A.ALT_PRIORITY, A.ALT_RATE, A.EFF_START_DATE , A.EFF_END_DATE
    				 , B1.FACTORY_ID, B1.MONTH , B1.PRIORITY
    			FROM    SCM_BOM_M A WITH(NOLOCK)
    			INNER HASH JOIN  (
    					SELECT CC.COMPANY_ID , CC.DIVISION_ID , CC.SITE_ID, CC.ITEM_ID , CC.ITEM_CLASS , DD.LEVEL_3_CODE, DD.LEVEL_3_NAME, CC.FLOW_ID 
    					FROM   SCM_ITEM_M CC WITH(NOLOCK), SCM_ITEM_CLASS_M DD WITH(NOLOCK)
    					WHERE  1=1
    					AND    CC.ITEM_CLASS  = DD.CLASS_ID
    					AND    CC.ACTIVE_FLAG = 'Y'
    					AND    DD.USE_FLAG    = 'Y'
    					AND    LEFT(ISNULL(CC.FLOW_ID,'Z'),5) IN ('A9000')
    					AND    DD.LEVEL_3_NAME = 'Cell'
    			) EE 
    			ON   1=1
    			AND  A.COMPANY_ID  = EE.COMPANY_ID
    			AND  A.DIVISION_ID = EE.DIVISION_ID
    			AND  A.SITE_ID     = EE.SITE_ID
    			AND  A.CHILD_ITEM_ID = EE.ITEM_ID
    			LEFT OUTER HASH JOIN ( --- 자품목이 LINE ASSIGN에 있는 것 조회용.
    						SELECT DISTINCT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.FACTORY_ID, A.ITEM_ID,  A.MONTH, A.PRIORITY--, B.ASSY_FACTORY_ID
              	FROM   SCM_ITEM_LINE_ASSIGN_M A WITH(NOLOCK)
    						INNER HASH JOIN (
    								SELECT DISTINCT B.COMPANY_ID, B.DIVISION_ID, B.SITE_ID, B.PLANT_ID
    								FROM   FP_INSTANCE_FACTORY_M A WITH(NOLOCK), SCM_FACTORY_M B WITH(NOLOCK)
    								WHERE  A.FACTORY_ID  = B.FACTORY_ID
    								AND    A.ACTIVE_FLAG = 'Y'
    								AND    B.ACTIVE_FLAG = 'Y'
    								AND    A.INSTANCE_ID = @ASSY_INSTANCE_ID
    						) B
    						ON    A.COMPANY_ID  = B.COMPANY_ID
    						AND   A.DIVISION_ID = B.DIVISION_ID
    						AND   A.SITE_ID     = B.SITE_ID
    						AND   A.PLANT_ID    = B.PLANT_ID
    						WHERE 1=1
        				AND   A.ACTIVE_FLAG = 'Y'
        				AND   A.MONTH BETWEEN SUBSTRING(@BUCKET_FROM,1,6) AND SUBSTRING(@BUCKET_TO,1,6)
        				AND   A.PRIORITY NOT IN (0,9)
          		) B1
          		ON    1=1
          		AND   A.COMPANY_ID     = B1.COMPANY_ID
          		AND   A.DIVISION_ID    = B1.DIVISION_ID
          		AND   A.SITE_ID        = B1.SITE_ID
          		AND   A.CHILD_ITEM_ID  = B1.ITEM_ID
          		AND   B1.MONTH <   = CONVERT(VARCHAR(6),A.EFF_END_DATE,112)
    			WHERE 1=1
    			AND   CONVERT(NVARCHAR(8),A.EFF_START_DATE,112) <= @PLAN_DATE
    			AND   CONVERT(NVARCHAR(8),A.EFF_END_DATE,112) > @PLAN_DATE  --- INSTANCE_DATE
      ) B
      ON    1=1
      AND   A.COMPANY_ID     = B.COMPANY_ID
      AND   A.DIVISION_ID    = B.DIVISION_ID
      AND   A.SITE_ID        = B.SITE_ID
      AND   A.CHILD_ITEM_ID  = B.PARENT_ITEM_ID
      WHERE 1=1
      AND   CONVERT(NVARCHAR(8),A.EFF_START_DATE,112) <= @PLAN_DATE
      AND   CONVERT(NVARCHAR(8),A.EFF_END_DATE,112) > @PLAN_DATE  --- INSTANCE_DATE