WITH LINE_SETUP_INSTANCE
AS
( SELECT a.segment1 as INSTANCE_ID, a.segment2 as NAME
                ,a.segment1,a.segment2,a.segment3,a.segment4,a.segment5
                ,a.sort_order                                
                FROM   scm_sys_lookup_value a WITH(NOLOCK)        
                WHERE  a.lookup_type_code = 'INSTANCE_SETUP_OPTION' 
                --AND    a.active_flag='Y'        
                AND a.attribute1 = 'Y'
                )

