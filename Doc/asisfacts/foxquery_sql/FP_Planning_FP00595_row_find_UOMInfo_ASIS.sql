SELECT A.*
FROM (
	SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID
		 , A.OPERATION, A.ITEM_ID
		 , UPPER(A.CATEGORY) AS CATEGORY
		 , A.PROD_VERSION_TYPE, A.VERSION_TYPE
		 , A.MODEL_ID
		 , MAX(A.VALUE) AS VALUE
		 , A.APPLY_DATE
		 , A.VERSION
		 , A.MAX_VER_FLAG
	FROM   SCM_ITEM_CONV_CALC_M A WITH(NOLOCK)
	INNER JOIN (
		SELECT DISTINCT A.ATTRIBUTE1 AS E_CATEGORY
		FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
		WHERE  A.LOOKUP_TYPE_CODE = 'ITEM_CONV_CALC'
		AND    A.ATTRIBUTE2 = 'Y'
	) D
	ON     A.CATEGORY = D.E_CATEGORY
	INNER JOIN (
		SELECT COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, FACTORY_ID, OPERATION, ITEM_ID, PROD_VERSION_TYPE, A.VERSION_TYPE , A.VERSION
		FROM (
			SELECT COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, FACTORY_ID, MODEL_ID, OPERATION, ITEM_ID, PROD_VERSION_TYPE, A.VERSION_TYPE , A.VERSION
			FROM   SCM_ITEM_CONV_CALC_M A WITH(NOLOCK)
			WHERE  1=1
			--AND    A.MAX_VER_FLAG = 'Y'
			AND    A.VALUE > 0
			AND    A.CATEGORY IN ( 'Jumbo Roll (cell/m)', 'Lane Number', 'Pancake (m/batch)', 'cell/batch', 'Jumbo Roll (m/batch)', 'Pancake (cell/m)' )
			GROUP BY COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, FACTORY_ID, MODEL_ID, OPERATION, ITEM_ID, PROD_VERSION_TYPE, A.VERSION_TYPE , A.VERSION
			HAVING COUNT(1) = 6
		) A
		GROUP BY COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, FACTORY_ID, OPERATION, ITEM_ID, PROD_VERSION_TYPE, A.VERSION_TYPE , A.VERSION
	) E
	ON     A.COMPANY_ID        = E.COMPANY_ID
	AND    A.DIVISION_ID       = E.DIVISION_ID
	AND    A.SITE_ID           = E.SITE_ID
	AND    A.PLANT_ID          = E.PLANT_ID
	AND    A.FACTORY_ID        = E.FACTORY_ID
	AND    A.OPERATION         = E.OPERATION
	AND    A.ITEM_ID           = E.ITEM_ID
	AND    A.PROD_VERSION_TYPE = E.PROD_VERSION_TYPE
	AND    A.VERSION_TYPE      = E.VERSION_TYPE
	AND    A.VERSION           = E.VERSION
	WHERE  1=1
  @CTRL_DIVISION_LT
  @CTRL_SITE_LT
  @CTRL_PLANT_LT
  @CTRL_FACTORY_LT
	--AND    A.MAX_VER_FLAG = 'Y'
	AND    A.OPERATION = 'E2000'
	AND    A.CATEGORY IN ('cell/batch','Pancake (m/batch)','Jumbo Roll (m/batch)')
	GROUP BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID
		   , A.OPERATION, A.ITEM_ID, A.MODEL_ID
		   , A.CATEGORY, A.PROD_VERSION_TYPE, A.VERSION_TYPE, A.VERSION, A.APPLY_DATE, A.MAX_VER_FLAG
) A
WHERE 1=1
ORDER BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID
       , A.OPERATION, A.ITEM_ID, A.MAX_VER_FLAG DESC, A.APPLY_DATE DESC, A.VERSION DESC
       , A.PROD_VERSION_TYPE, A.VERSION_TYPE
       , A.CATEGORY, A.MODEL_ID