;WITH BASE_SCM AS
(
SELECT A.DIVISION_ID,A.SITE_ID,ISNULL(B.PARENT_ITEM_ID,A.ITEM_ID) AS TOP_ITEM_ID, A.ITEM_ID,A.ITEM_NAME, A.NICK_NAME FRoM SCM_ITEM_M A WITH(NOLOCK)--,SCM_BOM_M B WITH(NOLOCK), SCM_ITEM_CONV_CALC_M WITH(NOLOCK)
LEFT OUTER JOIN SCM_BOM_M B WITH(NOLOCK)
ON B.CHILD_ITEM_ID = A.ITEM_ID
AND B.DIVISION_ID = A.DIVISION_ID
AND B.SITE_ID = A.SITE_ID
WHERE 1=1
AND (ISNULL(@DIVISION_ID,'') = '' OR A.DIVISION_ID =@DIVISION_ID) 
AND (ISNULL(@SITE_ID,'') = '' OR A.SITE_ID =@SITE_ID) 
AND (ISNULL(@ITEM_ID,'') = '' OR A.ITEM_ID LIKE '%'+ @ITEM_ID+'%' OR A.ITEM_NAME LIKE '%' + @ITEM_ID + '%') 
AND (ISNULL(B.PARENT_ITEM_ID,'') = '' OR B.PARENT_ITEM_ID LIKE '%' + @TOP_ITEM_ID + '%') 
AND (ISNULL(A.NICK_NAME,'-') = '-' OR A.NICK_NAME LIKE '%' + @NICK_NAME + '%') 
GROUP By A.DIVISION_ID,A.SITE_ID,A.ITEM_ID,A.ITEM_NAME, A.NICK_NAME,B.PARENT_ITEM_ID
),
LOOK_UP AS
(
SELECT SEGMENT1 AS DIVISION_ID, SEGMENT2 AS SITE_ID,SEGMENT3 AS ITEM_ID, SEGMENT4 AS DIO
,create_user_id as insert_id, create_date as insert_time
,modify_user_id as update_id, modify_date as update_time

FROM SCM_SYS_LOOKUP_VALUE WITH(NOLOCK)
WHERE  LOOKUP_TYPE_CODE = 'MATERIAL_DIO_DAY'
)
SELECT S.DIVISION_ID, S.SITE_ID, S.ITEM_ID,ISNULL(MAX(S.NICK_NAME),'-') AS NICK_NAME ,S.ITEM_NAME, ISNULL(L.DIO,5) AS DIO, CASE WHEN ISNULL(L.DIO,'')='' THEN 'Y' ELSE 'N' END AS DEFAULT_YN,
L.insert_id, L.insert_time, L.update_id, L.update_time
FROM BASE_SCM S WITH(NOLOCK) 
LEFT OUTER JOIN  LOOK_UP L WITH(NOLOCK) 
ON 1=1
AND L.DIVISION_ID = S.DIVISION_ID
AND L.SITE_ID = S.SITE_ID
AND L.ITEM_ID = S.ITEM_ID
GROUP BY S.DIVISION_ID, S.SITE_ID, S.ITEM_ID,S.ITEM_NAME, DIO, L.insert_id, L.insert_time, L.update_id, L.update_time