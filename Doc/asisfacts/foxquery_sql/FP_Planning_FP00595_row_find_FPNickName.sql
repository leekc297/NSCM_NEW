SELECT DISTINCT ISNULL(B.NICK_NAME,'-') AS CODE, ISNULL(B.NICK_NAME,'-') AS NAME
    	FROM (
    			  SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.TOP_ITEM_ID AS ITEM_ID
    			  FROM   @AMEND_TABLE A WITH(NOLOCK)
			      WHERE  INSTANCE_ID      = @INSTANCE_ID
			      AND    FP_PLAN_ID       = @PLAN_ID
			      AND    CONVERT(VARCHAR, A.PLAN_DATE, 112) BETWEEN @BUCKET_FROM AND @BUCKET_TO
			      
			@CTRL_DIVISION_LT
      @CTRL_SITE_LT
      @CTRL_PLANT_LT
      @CTRL_FACTORY_LT
      @CTRL_OPERATION_LT
      @CTRL_PRODTYPE_LT
      @CTRL_LINE_LT
      
      @CTRL_TOP_ITEM_ID
      @CTRL_ITEM_ID
			      
			) A
			INNER JOIN SCM_ITEM_M B WITH(NOLOCK)
			ON     A.COMPANY_ID     = B.COMPANY_ID
			AND    A.DIVISION_ID    = B.DIVISION_ID
			AND    A.SITE_ID        = B.SITE_ID
			AND    A.ITEM_ID        = B.ITEM_ID
			ORDER BY ISNULL(B.NICK_NAME,'-')