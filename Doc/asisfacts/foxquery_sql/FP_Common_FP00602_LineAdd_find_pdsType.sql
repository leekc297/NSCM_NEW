SELECT DISTINCT IV.COMPANY_ID, IV.DIVISION_ID, IV.SITE_ID, IV.PLANT_ID, SS.PRODUCTION_TYPE, SS.FP_PRODUCTION_TYPE 
        FROM   FP_INSTANCE_INFO_V IV WITH(NOLOCK), SCM_SYS_LOOKUP_VALUE SV WITH(NOLOCK)
        , (
          SELECT DISTINCT SEGMENT1 AS DIVISION_ID, SEGMENT2 AS PRODUCTION_TYPE, ATTRIBUTE2 AS FP_PRODUCTION_TYPE 
          FROM   SCM_SYS_LOOKUP_VALUE SS WITH(NOLOCK)
          WHERE 1=1
          AND SS.LOOKUP_TYPE_CODE = 'DIVISION_DEMAND_TYPE'
          AND SS.ACTIVE_FLAG  = 'Y'
          AND SS.ATTRIBUTE5   = 'Y' -- PDA TARGET FLAG
          --AND SV.ATTRIBUTE6 = 'Y' -- VERSION ONLY
        ) SS
        WHERE	1=1
        AND		SV.LOOKUP_TYPE_CODE = 'PDS_INSTANCE'
        AND		SV.ACTIVE_FLAG	= 'Y'
        AND		SV.SEGMENT1	  	= IV.INSTANCE_ID
        AND		IV.INSTANCE_ID	= @INSTANCE_ID
        AND		IV.DIVISION_ID	= SS.DIVISION_ID