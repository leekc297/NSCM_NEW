SELECT A.SETUP_CATEGORY_ID AS CODE, A.SETUP_CATEGORY_ID AS NAME
      FROM   SCM_ITEM_SETUP_GROUP_M A WITH(NOLOCK) INNER JOIN SCM_LINE_SETUP_GROUP_M B WITH(NOLOCK)
      ON     A.COMPANY_ID          = B.COMPANY_ID
      AND    A.DIVISION_ID         = B.DIVISION_ID
      AND    A.SITE_ID             = B.SITE_ID
      AND    A.OPERATION_ID        = B.OPERATION_ID
      AND    A.COMPANY_ID          = @COMPANY_ID
      AND    A.DIVISION_ID         = @DIVISION_ID
      AND    A.SITE_ID             = @SITE_ID
      AND    B.PLANT_ID            = @PLANT_ID
      AND    A.OPERATION_ID        = @OPERATION_ID
      AND    B.LINE_SETUP_GROUP_ID = @LINE_SETUP_GROUP_ID
      GROUP BY A.SETUP_CATEGORY_ID
      ORDER BY CODE