SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.TRAY_TYPE_CODE AS TRAY_ID
			,A.TRAY_TYPE_NAME AS TRAY_NAME, ISNULL(B.ATTRIBUTE1, A.DEGAS_BEFORE_TYPE) AS TRAY_TYPE, A.CELL_CNT, A.LOAD_YIELD
			,A.BUFFER_DAY, A.TRAY_CNT AS INVENTORY_CNT, A.INTRANSIT_CNT, A.DESCRIPTION
			,A.USE_YN AS ACTIVE_FLAG, A.TRAY_TYPE_GROUP AS GROUP_TRAY_ID
            ,CASE WHEN __MSG = ' Not Found' THEN (CASE WHEN MSG99 = '' THEN '' ELSE MSG99 END)
                  ELSE (CASE WHEN MSG99 = '' THEN __MSG ELSE __MSG + ' AND ' + MSG99 END)
                  END AS _MSG
            ,CASE WHEN __MSG = ' Not Found' AND MSG99 = '' THEN 'Y' ELSE 'N' END AS _VALID
      FROM (
		        SELECT A.* 
		              ,MSG1
		              +(CASE WHEN (MSG1 = '')                             THEN MSG2 ELSE (CASE WHEN MSG2 = '' THEN '' ELSE ',' + MSG2 END) END)
		              +(CASE WHEN (MSG1 = '' AND MSG2 = '')               THEN MSG3 ELSE (CASE WHEN MSG3 = '' THEN '' ELSE ',' + MSG3 END) END)
		              + ' Not Found' AS __MSG
		        FROM (
		          SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.TRAY_TYPE_CODE
						,A.TRAY_TYPE_NAME, A.DEGAS_BEFORE_TYPE, A.CELL_CNT, A.LOAD_YIELD
						,A.BUFFER_DAY, A.TRAY_CNT, A.INTRANSIT_CNT, A.DESCRIPTION
						,A.USE_YN, A.TRAY_TYPE_GROUP
						,A.JOB_USER_ID, A.JOB_TIME, A.JOB_TYPE, A.JOB_ORDER
		                ,CASE WHEN B.TRAY_TYPE_CODE IS NULL THEN 'Tray ID' ELSE '' END AS MSG1
		                --,CASE WHEN C.DEGAS_BEFORE_TYPE IS NULL OR A.DEGAS_BEFORE_TYPE <> C.DEGAS_BEFORE_TYPE THEN 'Tray Type' ELSE '' END AS MSG2
		                , '' AS MSG2
		                ,CASE WHEN R.PLANT_ID IS NULL THEN 'Permissions' ELSE '' END AS MSG3
						,CASE WHEN ROW_NUMBER() OVER(PARTITION BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.TRAY_TYPE_CODE
						                             ORDER BY     A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.TRAY_TYPE_CODE)>1 THEN 'Data Overlap'
						      ELSE '' END AS MSG99
		          FROM   BUF_FCS_TRAY_M A(NOLOCK)
				          LEFT OUTER JOIN SCM_FCS_TRAY_M B WITH(NOLOCK)
				          ON  A.COMPANY_ID   = B.COMPANY_ID
				          AND A.DIVISION_ID  = B.DIVISION_ID
				          AND A.SITE_ID      = B.SITE_ID
				          AND A.PLANT_ID     = B.PLANT_ID
				          AND A.TRAY_TYPE_CODE	= B.TRAY_TYPE_CODE
						 LEFT OUTER JOIN SCM_FCS_TRAY_M C WITH(NOLOCK)
				          ON  A.COMPANY_ID   = C.COMPANY_ID
				          AND A.DIVISION_ID  = C.DIVISION_ID
				          AND A.SITE_ID      = C.SITE_ID
				          AND A.PLANT_ID     = C.PLANT_ID
				          AND A.TRAY_TYPE_GROUP	= C.TRAY_TYPE_CODE
			          	LEFT OUTER JOIN (
								           	SELECT DISTINCT R.COMPANY_ID, R.DIVISION_ID, R.SITE_ID, R.PLANT_ID
											FROM   FP_USER_ROLE_INFO_V R WITH(NOLOCK)
											WHERE  R.USER_ID   = @USER_ID
											AND    R.SAVE_FLAG = 'Y'
						) R
						ON   A.COMPANY_ID  = R.COMPANY_ID
						AND  A.DIVISION_ID = R.DIVISION_ID
						AND  A.SITE_ID     = R.SITE_ID
						AND  A.PLANT_ID    = R.PLANT_ID
		    	WHERE A.JOB_USER_ID = @USER_ID
        	) A
      ) A
			LEFT OUTER JOIN SCM_SYS_LOOKUP_VALUE B WITH(NOLOCK)
			ON 1=1
			AND B.LOOKUP_TYPE_CODE = 'FORMATION_TRAY_TYPE'
			AND B.ACTIVE_FLAG = 'Y'
			AND A.PLANT_ID = B.SEGMENT1
			AND A.DEGAS_BEFORE_TYPE = B.SEGMENT2
      ORDER BY A.JOB_ORDER