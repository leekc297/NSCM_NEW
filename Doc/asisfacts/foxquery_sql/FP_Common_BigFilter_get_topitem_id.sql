SELECT DISTINCT TOP_ITEM_ID AS CODE, TOP_ITEM_ID AS NAME,  LINE_ID
FROM(
SELECT  A.TOP_ITEM_ID            ,LINE_ID                
                FROM   FP_DAILY_PRODUCTIOIN_PLAN_H A WITH(NOLOCK)  
                WHERE  CONVERT(VARCHAR,A.PLAN_DATE,112) BETWEEN @BUCKET_FROM AND @BUCKET_TO
                AND    A.PLAN_TYPE IN ('RELEASE','MPP','WPP')

UNION ALL SELECT A.TOP_ITEM_ID    ,LINE_ID
                FROM   SCM_DAILY_PRODUCT_RESULT_H A WITH(NOLOCK)  
                WHERE  CONVERT(VARCHAR,A.PLAN_DATE,112) BETWEEN @BUCKET_FROM AND @BUCKET_TO
                )A