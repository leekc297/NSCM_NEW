SELECT DISTINCT E.INSTANCE_ID FROM 
		FP_INSTANCE_FACTORY_M E
		INNER JOIN
		FP_INSTANCE_OPERATION_V B
		ON 
	1=1
AND 	E.INSTANCE_ID = B.INSTANCE_ID
AND E.ACTIVE_FLAG = 'Y'
WHERE B.COMPANY_ID =@COMPANY_ID
AND B.DIVISION_ID = @DIVISION_ID
AND B.SITE_ID = @SITE_ID
AND B.OPERATION_ID = @OPERATION_ID
AND E.FACTORY_ID = @FACTORY_ID