SELECT DISTINCT A.USER_ID AS CODE_ID, ISNULL(B.USER_NAME,'-') + ' (' + A.USER_ID + ')' AS CODE_NAME
           , (CASE WHEN A.USER_ID = @USER_ID THEN 'Y' ELSE 'N' END) AS DEFAULT_CHECK,A.INSTANCE_ID
      FROM   FP_USER_LINE_GROUP_M A WITH(NOLOCK)
      LEFT OUTER JOIN TH_UIS_USER_DETAIL B WITH(NOLOCK)
      ON     A.USER_ID = B.USER_ID
      WHERE  A.INSTANCE_ID = @INSTANCE_ID
      ORDER BY CODE_NAME