SELECT A.INSTANCE_ID, A.FP_PLAN_ID
           , A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID
           , A.LOCATION, A.OPERATION_ID, A.LINE_ID, A.ELECTRODE_TYPE, A.EQUIPMENT_ID
           , CONVERT(VARCHAR, A.PLAN_DATE, 112) AS PLAN_DATE
           , A.TOP_ITEM_ID, A.ITEM_ID
           , A.PRODUCTION_TYPE, A.MARKET
           , A.SEQ
           , A.WORK_REQUEST_MODEL_ID, A.VERSION, A.PLM_EC_NO
           , A.PLAN_IN_QTY_BATCH, A.PLAN_IN_QTY, A.PLAN_IN_QTY_M, A.PLAN_IN_QTY_CELL
           , A.PLAN_OUT_QTY_BATCH, A.PLAN_OUT_QTY, A.PLAN_OUT_QTY_M, A.PLAN_OUT_QTY_CELL
           
           , CASE WHEN B.RELEASE_TYPE = 'DPP' THEN ROUND(A.ADJUST_IN_QTY_BATCH,@ROUND_POINT)
           		  WHEN B.RELEASE_TYPE = 'MPP' THEN ROUND(A.MPP_IN_QTY_BATCH,@ROUND_POINT)
           		  ELSE ROUND(A.WPP_IN_QTY_BATCH,@ROUND_POINT) END AS ADJUST_IN_QTY_BATCH
		   , CASE WHEN B.RELEASE_TYPE = 'DPP' THEN CEILING(A.ADJUST_IN_QTY)
           		  WHEN B.RELEASE_TYPE = 'MPP' THEN CEILING(A.MPP_IN_QTY)
           		  ELSE CEILING(A.WPP_IN_QTY) END AS ADJUST_IN_QTY
           , CASE WHEN B.RELEASE_TYPE = 'DPP' THEN CEILING(A.ADJUST_IN_QTY_M)
           		  WHEN B.RELEASE_TYPE = 'MPP' THEN CEILING(A.MPP_IN_QTY_M)
           		  ELSE CEILING(A.WPP_IN_QTY_M) END AS ADJUST_IN_QTY_M
           , CASE WHEN B.RELEASE_TYPE = 'DPP' THEN CEILING(A.ADJUST_IN_QTY_CELL)
           		  WHEN B.RELEASE_TYPE = 'MPP' THEN CEILING(A.MPP_IN_QTY_CELL)
           		  ELSE CEILING(A.WPP_IN_QTY_CELL) END AS ADJUST_IN_QTY_CELL
           , CASE WHEN B.RELEASE_TYPE = 'DPP' THEN CEILING(A.ADJUST_IN_QTY_JR)
           		  WHEN B.RELEASE_TYPE = 'MPP' THEN CEILING(A.MPP_IN_QTY_JR)
           		  ELSE CEILING(A.WPP_IN_QTY_JR) END AS ADJUST_IN_QTY_JR
           
           , CASE WHEN B.RELEASE_TYPE = 'DPP' THEN ROUND(A.ADJUST_OUT_QTY_BATCH,@ROUND_POINT)
           		  WHEN B.RELEASE_TYPE = 'MPP' THEN ROUND(A.MPP_OUT_QTY_BATCH,@ROUND_POINT)
           		  ELSE ROUND(A.WPP_OUT_QTY_BATCH,@ROUND_POINT) END AS ADJUST_OUT_QTY_BATCH
           , CASE WHEN B.RELEASE_TYPE = 'DPP' THEN CEILING(A.ADJUST_OUT_QTY)
           		  WHEN B.RELEASE_TYPE = 'MPP' THEN CEILING(A.MPP_OUT_QTY)
           		  ELSE CEILING(A.WPP_OUT_QTY) END AS ADJUST_OUT_QTY
           , CASE WHEN B.RELEASE_TYPE = 'DPP' THEN CEILING(A.ADJUST_OUT_QTY_M)
           		  WHEN B.RELEASE_TYPE = 'MPP' THEN CEILING(A.MPP_OUT_QTY_M)
           		  ELSE CEILING(A.WPP_OUT_QTY_M) END AS ADJUST_OUT_QTY_M
           , CASE WHEN B.RELEASE_TYPE = 'DPP' THEN CEILING(A.ADJUST_OUT_QTY_CELL)
           		  WHEN B.RELEASE_TYPE = 'MPP' THEN CEILING(A.MPP_OUT_QTY_CELL)
           		  ELSE CEILING(A.WPP_OUT_QTY_CELL) END AS ADJUST_OUT_QTY_CELL
           , CASE WHEN B.RELEASE_TYPE = 'DPP' THEN CEILING(A.ADJUST_OUT_QTY_JR)
           		  WHEN B.RELEASE_TYPE = 'MPP' THEN CEILING(A.MPP_OUT_QTY_JR)
           		  ELSE CEILING(A.WPP_OUT_QTY_JR) END AS ADJUST_OUT_QTY_JR
           , B.RELEASE_TYPE
           , A.WORK_REQUEST_MODEL_ID, A.VERSION, A.PROD_SEQ, A.PLM_EC_NO
      FROM   @AMEND_TABLE A WITH(NOLOCK)
      INNER JOIN (
      	SELECT 'DPP' AS RELEASE_TYPE
      	UNION ALL
      	SELECT 'MPP' AS RELEASE_TYPE
      	UNION ALL
      	SELECT 'WPP' AS RELEASE_TYPE
      ) B
      ON 1=1
      WHERE 1=1
      AND	 A.INSTANCE_ID = @MASTER_ID
      AND    A.FP_PLAN_ID  = @PLAN_ID
      AND    CONVERT(VARCHAR, A.PLAN_DATE, 112) BETWEEN @BUCKET_FROM AND @BUCKET_TO
      @CTRL_DIVISION_LT
      @CTRL_SITE_LT
      @CTRL_PLANT_LT
      @CTRL_FACTORY_LT
      @CTRL_OPERATION_LT
      @CTRL_LINE_LT
      ORDER BY COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, FACTORY_ID
             , LOCATION, OPERATION_ID, LINE_ID, ELECTRODE_TYPE, EQUIPMENT_ID
             , TOP_ITEM_ID, ITEM_ID, PRODUCTION_TYPE, MARKET
             , PLAN_DATE