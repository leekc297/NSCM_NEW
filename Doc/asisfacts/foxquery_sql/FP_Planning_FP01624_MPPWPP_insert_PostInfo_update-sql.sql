BEGIN
    		
    		INSERT INTO FP_MPP_WPP_BASE_PLAN_M (
               PLAN_WEEK, PLAN_REVISION
              ,COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, FACTORY_ID
              ,LINE_ID, OPERATION_ID, EQUIPMENT_ID, ITEM_ID, PRODUCTION_TYPE, MARKET
              ,PLAN_DATE
              ,PLAN_QTY
            	,INSERT_ID,INSERT_TIME,UPDATE_ID,UPDATE_TIME
    		)
        SELECT @PLAN_WEEK AS PLAN_WEEK, A.NEW_PLAN_REVISION
        	   , B.COMPANY_ID, B.DIVISION_ID, B.SITE_ID, B.PLANT_ID, B.FACTORY_ID
        	   , B.LINE_ID, B.OPERATION_ID, B.EQUIPMENT_ID, B.ITEM_ID, B.PRODUCTION_TYPE, B.MARKET
        	   , B.PLAN_DATE
        	   , MAX(B.PLAN_QTY) AS PLAN_QTY
        	   , @USER_ID AS INSERT_ID, GETDATE() AS INSERT_TIME
        	   , @USER_ID AS UPDATE_ID, GETDATE() AS UPDATE_TIME
        FROM   (
        	SELECT DISTINCT A.*
        	FROM (
        	  @SELECT_LIST
        	) A
        ) A
        , FP_DAILY_PRODUCTIOIN_PLAN_H B WITH(NOLOCK)
        , FP_INSTANCE_LINE_V C WITH(NOLOCK)
        WHERE  1=1
        AND    (CASE WHEN A.CONFIRM_AREA = 'PLAN GROUP' THEN A.PLAN_GROUP_ID ELSE A.FACTORY_ID END) = (CASE WHEN A.CONFIRM_AREA = 'PLAN GROUP' THEN B.PLAN_GROUP_ID ELSE B.FACTORY_ID END)
        AND    A.INSTANCE_ID    = C.INSTANCE_ID
        AND    B.COMPANY_ID     = C.COMPANY_ID
        AND    B.DIVISION_ID    = C.DIVISION_ID
        AND    B.SITE_ID        = C.SITE_ID
        AND    B.PLANT_ID       = C.PLANT_ID
        AND    B.FACTORY_ID     = C.FACTORY_ID
        AND    B.OPERATION_ID   = C.OPERATION_ID
        AND    B.LINE_ID        = C.LINE_ID
        AND    B.ELECTRODE_TYPE = C.ELECTRODE_TYPE
        AND    B.PLAN_TYPE      = @REV_TYPE
        AND    CONVERT(VARCHAR,B.PLAN_DATE,112) > @BUCKET_TO
	      GROUP BY A.NEW_PLAN_REVISION, B.COMPANY_ID, B.DIVISION_ID, B.SITE_ID, B.PLANT_ID, B.FACTORY_ID
      		     , B.LINE_ID, B.OPERATION_ID, B.EQUIPMENT_ID, B.ITEM_ID, B.PRODUCTION_TYPE, B.MARKET
      		     , B.PLAN_DATE
    		;
      	
      END;