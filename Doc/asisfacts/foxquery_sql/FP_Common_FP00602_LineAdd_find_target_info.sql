SELECT A.*
      		, '' AS MSG1
          , ( CASE --WHEN (A.OPERATION_ID IN ('A3000','A9000','P5500','P9500') AND A.PRODUCTION_TYPE = 'TEST') THEN 'SCP or Test Target-Market'
                   WHEN I.DIVISION_ID IS NOT NULL THEN ''
                   WHEN (A.OPERATION_ID IN ('A3000','A9000') AND H.MARKET IS NULL AND (@INSTANCE_ID NOT IN ('KR_CELL_A2','KR_CELL_M2'))) THEN 'SCP or Test Target-Market'
                   --WHEN H.ITEM_ID IS NULL THEN 'SCP or Test Target-Market' -- target 필수 조건 추가... 20210125
                   ELSE '' END ) AS MSG2
          , CASE WHEN R.FACTORY_ID IS NULL THEN 'Permissions' ELSE '' END AS MSG3
      FROM (
          SELECT @INSTANCE_ID AS INSTANCE_ID
              , (SELECT COMPANY_ID FROM SCM_FACTORY_M FF WHERE FF.FACTORY_ID = @FACTORY_ID) AS COMPANY_ID
              , @DIVISION_ID AS DIVISION_ID, @SITE_ID AS SITE_ID, @PLANT_ID AS PLANT_ID
              , @ITEM_ID AS ITEM_ID, @OPERATION_ID AS OPERATION_ID, @FACTORY_ID AS FACTORY_ID, @LOCATION AS LOCATION
              , @PRODUCTION_TYPE AS PRODUCTION_TYPE, @MARKET AS MARKET
              , @LINE_ID AS LINE_ID, @ELECTRODE_TYPE AS ELECTRODE_TYPE
              , @TOP_ITEM_ID AS TOP_ITEM_ID
      ) A
      LEFT OUTER HASH JOIN (
          SELECT DISTINCT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.MARKET, A.ITEM_ID, (CASE WHEN A.PRODUCTION_TYPE = 'TEST' THEN 'S-TEST' ELSE A.PRODUCTION_TYPE END) AS PRODUCTION_TYPE
					FROM   FP_WEEKLY_DEMAND_PRODUCT_H A WITH(NOLOCK)
					WHERE  1=1 --(A.DIVISION_ID+A.SHOP_GROUP_ID+A.SCP_PLAN_ID) IN (SELECT A.DIVISION_ID+A.SHOP_GROUP_ID+MAX(SCP_PLAN_ID) AS SCP_PLAN_ID FROM FP_WEEKLY_DEMAND_PRODUCT_H A WITH(NOLOCK) GROUP BY A.DIVISION_ID, A.SHOP_GROUP_ID)
					AND    EXISTS (
							SELECT 1
							FROM (
									SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.SHOP_GROUP_ID, MAX(SCP_PLAN_ID) AS SCP_PLAN_ID 
									FROM   FP_WEEKLY_DEMAND_PRODUCT_H A WITH(NOLOCK), (
											SELECT DISTINCT B.COMPANY_ID, B.DIVISION_ID, B.SITE_ID, B.PLANT_ID, A.SHOP_GROUP_ID
											FROM   FP_INSTANCE_FACTORY_M A WITH(NOLOCK), SCM_FACTORY_M B WITH(NOLOCK)
											WHERE  A.FACTORY_ID  = B.FACTORY_ID
											AND    A.ACTIVE_FLAG = 'Y'
											AND    B.ACTIVE_FLAG = 'Y'
											AND    A.INSTANCE_ID = @INSTANCE_ID
									) B
									WHERE  A.COMPANY_ID    = B.COMPANY_ID
									AND    A.DIVISION_ID   = B.DIVISION_ID
									AND    A.SITE_ID       = B.SITE_ID
									AND    A.PLANT_ID      = B.PLANT_ID
									AND    A.SHOP_GROUP_ID = B.SHOP_GROUP_ID
									GROUP BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.SHOP_GROUP_ID
							) BB
							WHERE A.COMPANY_ID    = BB.COMPANY_ID
							AND   A.DIVISION_ID   = BB.DIVISION_ID
							AND   A.SITE_ID       = BB.SITE_ID
							AND   A.SHOP_GROUP_ID = BB.SHOP_GROUP_ID
							AND   A.SCP_PLAN_ID   = BB.SCP_PLAN_ID
					)
					AND    A.MFG_WEEK IN (
					    SELECT DISTINCT ISO_YYYYWW
					    FROM   TH_UIS_CAL A WITH(NOLOCK)
					    WHERE  A.YYYYMMDD <= CONVERT(VARCHAR, (CONVERT(DATETIME,@PLAN_DATE) + (((SELECT MAX(ISNULL(A.ATTRIBUTE13,10)) AS ENGINE_PLAN_PER_WEEK FROM SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK) WHERE A.LOOKUP_TYPE_CODE = 'INSTANCE_ID' AND A.SEGMENT1 = @INSTANCE_ID)-1)*7) ), 112)
					)
					UNION ALL
					SELECT DISTINCT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, ISNULL(A.MARKET,'D') AS MARKET, A.ITEM_ID, A.PRODUCTION_TYPE
					FROM   FP_WEEKLY_DEMAND_PRODUCT_TEST_H A WITH(NOLOCK)
					WHERE  A.DUE_DATE <= CONVERT(DATETIME, CONVERT(DATETIME,@PLAN_DATE) + (((SELECT MAX(ISNULL(A.ATTRIBUTE13,10)) AS ENGINE_PLAN_PER_WEEK FROM SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK) WHERE A.LOOKUP_TYPE_CODE = 'INSTANCE_ID' AND A.SEGMENT1 = @INSTANCE_ID)-1)*7), 112)
      ) H
      ON  A.COMPANY_ID  = H.COMPANY_ID
      AND A.DIVISION_ID = H.DIVISION_ID
      AND A.SITE_ID     = H.SITE_ID
      AND A.PLANT_ID    = H.PLANT_ID
      AND A.MARKET      = H.MARKET
      AND A.TOP_ITEM_ID = H.ITEM_ID
      AND A.PRODUCTION_TYPE = H.PRODUCTION_TYPE
  	  LEFT OUTER JOIN (
    			SELECT DISTINCT A.SEGMENT1 AS INSTANCE_ID, A.SEGMENT2 AS DIVISION_ID, A.SEGMENT3 AS SITE_ID, A.SEGMENT4 AS PLANT_ID, A.SEGMENT5 AS MODEL_ID
    			FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
    			WHERE  A.LOOKUP_TYPE_CODE = 'AMEND_VALIDATION_EXCEPTION'
    			AND    A.ACTIVE_FLAG      = 'Y'
    			AND    A.SEGMENT1         = @INSTANCE_ID
  	  ) I
  	  ON  A.DIVISION_ID = I.DIVISION_ID
  	  AND A.SITE_ID     = I.SITE_ID
  	  AND A.PLANT_ID    = I.PLANT_ID
  	  AND A.TOP_ITEM_ID = I.MODEL_ID
			LEFT OUTER JOIN (
						SELECT	DISTINCT R.COMPANY_ID, R.DIVISION_ID, R.SITE_ID, R.PLANT_ID, R.FACTORY_ID, R.OPERATION_ID, R.LINE_ID
						FROM	FP_USER_ROLE_INFO_V R WITH(NOLOCK)
						WHERE	1=1
						AND		R.USER_ID	= @USER_ID
						AND		R.SAVE_FLAG	= 'Y'
						AND		R.INSTANCE_ID = @INSTANCE_ID
			) R
			ON		1=1
			AND		A.COMPANY_ID	 = R.COMPANY_ID
			AND		A.DIVISION_ID	 = R.DIVISION_ID
			AND		A.SITE_ID			 = R.SITE_ID
			AND		A.PLANT_ID		 = R.PLANT_ID
			AND		A.FACTORY_ID	 = R.FACTORY_ID
			AND		A.OPERATION_ID = R.OPERATION_ID
			AND		A.LINE_ID		   = R.LINE_ID