SELECT MAX(B.SEGMENT1) AS INSTANCE_ID, (CASE WHEN MAX(B.SEGMENT1) IS NULL THEN 'N' ELSE 'Y' END) AS IS_CELL_ASSY
          FROM   SCM_SYS_LOOKUP_VALUE  B WITH(NOLOCK)
          WHERE  B.ACTIVE_FLAG = 'Y'
          AND    B.LOOKUP_TYPE_CODE = 'CELL_PRODUCT_ASSY_INSTANCE'
          AND    B.SEGMENT1 = @INSTANCE_ID