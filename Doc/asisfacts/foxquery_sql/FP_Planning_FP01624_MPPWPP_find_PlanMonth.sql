SELECT DISTINCT A.MONTH AS CODE, A.MONTH AS NAME
      FROM (
        SELECT B.DATED1 AS WEEK_START_DATE, B.MONTH
        FROM   FP_MPP_WPP_BASE_PLAN_H A
        LEFT OUTER JOIN TH_UIS_CALENDAR B
        ON A.PLAN_WEEK = B.D0
        WHERE A.MPP = 'Y'
        UNION ALL
        SELECT B.DATED1 AS WEEK_START_DATE, B.CAL_YEAR_MON AS MONTH
        FROM   FP_MPP_WPP_BASE_PLAN_H A
        LEFT OUTER JOIN TH_UIS_CALENDAR B
        ON A.PLAN_WEEK = B.D0
        WHERE A.MPP = 'Y'
      ) A
      ORDER BY A.MONTH DESC