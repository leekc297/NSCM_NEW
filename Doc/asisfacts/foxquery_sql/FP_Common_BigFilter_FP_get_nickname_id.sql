SELECT DISTINCT B.NICK_NAME AS CODE, B.NICK_NAME AS NAME, A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.OPERATION_ID,A.FACTORY_ID,A.LINE_ID,A.FP_PRODUCTION_TYPE AS PRODUCTION_TYPE
FROM(
SELECT  A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.TOP_ITEM_ID AS ITEM_ID,A.OPERATION_ID,A.LINE_ID,A.FP_PRODUCTION_TYPE
                FROM   FP_DAILY_PRODUCTIOIN_PLAN_H A WITH(NOLOCK)  
                WHERE  CONVERT(VARCHAR,A.PLAN_DATE,112) BETWEEN  @BUCKET_FROM AND @BUCKET_TO
                AND    A.PLAN_TYPE IN ('RELEASE','MPP','WPP')

UNION ALL SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.TOP_ITEM_ID AS ITEM_ID ,A.OPERATION_ID,A.LINE_ID,A.FP_PRODUCTION_TYPE
                FROM   SCM_DAILY_PRODUCT_RESULT_H A WITH(NOLOCK)  
                WHERE  1=1
				AND CONVERT(VARCHAR,A.PLAN_DATE,112) BETWEEN  @BUCKET_FROM AND @BUCKET_TO
                )A
				INNER JOIN SCM_ITEM_M B WITH(NOLOCK)
 ON     A.COMPANY_ID     = B.COMPANY_ID 
                AND    A.DIVISION_ID    = B.DIVISION_ID 
                AND    A.SITE_ID        = B.SITE_ID    
                AND    A.ITEM_ID        = B.ITEM_ID  
				AND  ISNULL(B.NICK_NAME,'') <> ''
                ORDER BY B.NICK_NAME