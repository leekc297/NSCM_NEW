         PLAN_WEEK, PLAN_REVISION
        ,COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, FACTORY_ID
        ,OPERATION_ID, LINE_ID, EQUIPMENT_ID, ITEM_ID, PRODUCTION_TYPE, MARKET
        ,PLAN_DATE, PLAN_QTY
        ,JOB_USER_ID, JOB_TIME, JOB_TYPE, JOB_ORDER
      )
      VALUES (
         RTRIM(LTRIM(UPPER(@PLAN_WEEK))), RTRIM(LTRIM(UPPER(@PLAN_REVISION)))
        ,RTRIM(LTRIM(UPPER(@COMPANY_ID))), RTRIM(LTRIM(UPPER(@DIVISION_ID))), RTRIM(LTRIM(UPPER(@SITE_ID))), RTRIM(LTRIM(UPPER(@PLANT_ID))), RTRIM(LTRIM(UPPER(@FACTORY_ID)))
        ,RTRIM(LTRIM(UPPER(@OPERATION_ID))), RTRIM(LTRIM(UPPER(@LINE_ID))), RTRIM(LTRIM(UPPER(@EQUIPMENT_ID))), RTRIM(LTRIM(UPPER(@ITEM_ID))), RTRIM(LTRIM(UPPER(@PRODUCTION_TYPE))), RTRIM(LTRIM(UPPER(@MARKET)))
        ,CONVERT(DATE,RTRIM(LTRIM(@PLAN_DATE))), CEILING( REPLACE(RTRIM(LTRIM(@PLAN_QTY)),CHAR(9),0) )
        ,@USER_ID, dbo.SYSDATE1(), '-', @JOB_ORDER
      )