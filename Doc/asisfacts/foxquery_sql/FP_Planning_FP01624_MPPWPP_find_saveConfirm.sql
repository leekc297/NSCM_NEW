WITH MAIN AS (
          SELECT DISTINCT A.PLAN_WEEK, A.PLAN_REVISION
          FROM (
              SELECT A.*
                    , ROW_NUMBER( ) OVER( PARTITION BY A.FACTORY_ID, A.INSTANCE_ID, A.PLAN_GROUP_ID ORDER BY A.PLAN_WEEK DESC, A.INSERT_TIME DESC ) AS ROW_NUM
              FROM   FP_MPP_WPP_BASE_PLAN_H A WITH(NOLOCK)
              WHERE  1=1
              AND  @REV_TYPE = 'Y'
              AND (
								@REV_LIST
              )
              AND A.PLAN_WEEK <= @PLAN_WEEK
          ) A
          WHERE A.ROW_NUM = 1
      )
      SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID
           , A.OPERATION_ID, A.LINE_ID, ISNULL(C.LINE_NAME,'-') AS LINE_NAME, A.EQUIPMENT_ID, A.ITEM_ID, ISNULL(B.NICK_NAME,'-') AS NICK_NAME, A.PRODUCTION_TYPE, A.MARKET
          @BUCKET_SQL
      FROM (
          SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID
               , A.OPERATION_ID, A.LINE_ID, A.EQUIPMENT_ID
               , A.PRODUCTION_TYPE, A.MARKET
               , A.ITEM_ID, CONVERT(VARCHAR,A.PLAN_DATE,112) AS PLAN_DATE, A.PLAN_QTY
               , 'Y' AS IS_PAST
          FROM   FP_MPP_WPP_BASE_PLAN_M A WITH(NOLOCK)
          INNER JOIN MAIN B
          ON  A.PLAN_WEEK     = B.PLAN_WEEK
          AND A.PLAN_REVISION = B.PLAN_REVISION
          WHERE CONVERT(VARCHAR,A.PLAN_DATE,112) <  @_MIN_DATE
          AND   CONVERT(VARCHAR,A.PLAN_DATE,112) >= @BUCKET_FROM
          UNION ALL
          SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID
               , A.OPERATION_ID, A.LINE_ID, A.EQUIPMENT_ID
               , A.PRODUCTION_TYPE, A.MARKET
               , A.ITEM_ID, CONVERT(VARCHAR,A.PLAN_DATE,112) AS PLAN_DATE, A.PLAN_QTY
               , 'N' AS IS_PAST
          FROM   BUF_MPP_WPP_BASE_PLAN_M A WITH(NOLOCK)
          WHERE  A.JOB_USER_ID = @USER_ID
      ) A
      LEFT OUTER JOIN SCM_ITEM_M B WITH(NOLOCK)
      ON     A.COMPANY_ID   = B.COMPANY_ID
      AND    A.DIVISION_ID  = B.DIVISION_ID
      AND    A.SITE_ID      = B.SITE_ID
      AND    A.ITEM_ID      = B.ITEM_ID
      LEFT OUTER JOIN (
        SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.OPERATION_ID, A.LINE_ID, MAX(LINE_NAME) AS LINE_NAME
        FROM   SCM_LINE_M A WITH(NOLOCK)
        GROUP BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.OPERATION_ID, A.LINE_ID
      ) C
      ON     A.COMPANY_ID   = C.COMPANY_ID
      AND    A.DIVISION_ID  = C.DIVISION_ID
      AND    A.SITE_ID      = C.SITE_ID
      AND    A.PLANT_ID     = C.PLANT_ID
      AND    A.FACTORY_ID   = C.FACTORY_ID
      AND    A.OPERATION_ID = C.OPERATION_ID
      AND    A.LINE_ID      = C.LINE_ID
      GROUP BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID
             , A.OPERATION_ID, A.LINE_ID, ISNULL(C.LINE_NAME,'-'), A.EQUIPMENT_ID, A.ITEM_ID, ISNULL(B.NICK_NAME,'-'), A.PRODUCTION_TYPE, A.MARKET
      ORDER BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID
             , A.OPERATION_ID, A.LINE_ID, ISNULL(C.LINE_NAME,'-'), A.EQUIPMENT_ID, A.ITEM_ID, ISNULL(B.NICK_NAME,'-'), A.PRODUCTION_TYPE, A.MARKET