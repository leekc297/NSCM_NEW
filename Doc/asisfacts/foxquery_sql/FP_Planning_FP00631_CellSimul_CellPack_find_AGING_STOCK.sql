SELECT CONVERT(VARCHAR, A.RECEIVING_DTTM, 112) AS PLAN_DATE
           , A.ROUTE_ID AS LINE_ID
           , A.ITEM_ID -- form item
           , ISNULL(A.QTY,0) AS AGING_STOCK 
      FROM   TH_MST_STOCK_PLAN_V A WITH(NOLOCK)
      WHERE  A.MASTER_ID    = @FORM_INSTANCE_ID
      AND    A.PLAN_ID IN (@PLAN_ID_SCRIPT
 
      )
      AND    A.STOCK_STATUS = 'AGING_STOCK'