SELECT A.RELEASE_VALUE, B._VALUE
					FROM (
							SELECT (CASE WHEN A.FACTORY_ID = '-' THEN A.PLAN_GROUP_ID ELSE A.FACTORY_ID END) AS RELEASE_VALUE
							FROM   FP_RELEASE_PLAN_INFO_H A WITH(NOLOCK)
							WHERE  INSTANCE_ID     = @INSTANCE_ID
							AND    INSTANCE_DATE   = @PLAN_DATE
							AND    RELEASE_PLAN_ID = @PLAN_ID
						) A
						LEFT OUTER JOIN (
											-- 전송 가능 기준은 배포기준이 된 동 혹은 PLAN GROUP 기준으로 저장권한 있는지 여부로 확인한다.
											SELECT DISTINCT (CASE WHEN B.ATTRIBUTE1 = 'PLAN GROUP' THEN A.PLAN_GROUP_ID ELSE A.FACTORY_ID END) AS _VALUE
											FROM   FP_USER_ROLE_INFO_V A WITH(NOLOCK), SCM_SYS_LOOKUP_VALUE B WITH(NOLOCK)
											WHERE  A.INSTANCE_ID = B.SEGMENT1
											AND    A.USER_ID     = @USER_ID
											AND    A.INSTANCE_ID = @INSTANCE_ID
											AND    A.SAVE_FLAG   = 'Y'
											AND    B.ACTIVE_FLAG = 'Y'
											AND    B.LOOKUP_TYPE_CODE = 'INSTANCE_ID'
						) B
						ON A.RELEASE_VALUE = B._VALUE