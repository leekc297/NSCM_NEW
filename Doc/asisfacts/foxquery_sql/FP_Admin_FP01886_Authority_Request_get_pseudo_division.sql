SELECT US.USER_ID, PD.COMPANY_ID, PD.PSEUDO_DIVISION_ID AS DIVISION_ID FROM TH_UIS_USER_DETAIL US (NOLOCK)
LEFT OUTER JOIN (
SELECT COMPANY_ID,PSEUDO_DIVISION_ID  FROM SCM_PSEUDO_DIVISION_M PD (NOLOCK)
GROUP BY COMPANY_ID, PSEUDO_DIVISION_ID) PD
ON US.COMPANY = PD.COMPANY_ID
WHERE ISNULL( PD.COMPANY_ID,'') <> ''
AND USER_ID = @USER_ID