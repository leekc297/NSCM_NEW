AND L.LOOKUP_TYPE_CODE = 'INSTANCE_ID'
AND FL.INSTANCE_ID = L.SEGMENT1

LEFT OUTER JOIN FP_USER_LINE_GROUP_M LV WITH(NOLOCK)
ON FL.LINE_ID = LV.LINE_ID
AND LV.ACTIVE_FLAG = 'Y'
