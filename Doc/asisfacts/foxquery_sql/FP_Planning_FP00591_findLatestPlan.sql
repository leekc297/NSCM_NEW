WITH _INSTANCELIST AS (
          	SELECT A.SEGMENT2 AS INSTANCE_ID, A.SEGMENT3 AS SITE_ID, @PLAN_DATE AS PLAN_DATE
          	FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
          	WHERE  A.LOOKUP_TYPE_CODE = 'TOTAL_INSTANCE_INFO'
          	AND    A.ACTIVE_FLAG      = 'Y'
          	AND    A.SEGMENT1         = @INSTANCE_ID
          )
          SELECT A.INSTANCE_ID, MAX(A.PLAN_ID) AS PLAN_ID
          FROM   SCM_FP_PLAN_H A WITH(NOLOCK), _INSTANCELIST B WITH(NOLOCK)
          WHERE  A.INSTANCE_ID = B.INSTANCE_ID
          AND    CONVERT(VARCHAR(8), A.PLAN_START_TIME, 112) = @PLAN_DATE
          AND    A.PLAN_TYPE <> 'RELEASE'
          GROUP BY A.INSTANCE_ID