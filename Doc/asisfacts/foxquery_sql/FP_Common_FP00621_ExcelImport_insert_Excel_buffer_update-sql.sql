INSERT INTO BUF_AMEND_PLAN_FORM_R (
         INSTANCE_ID, FP_PLAN_ID
        ,DIVISION_ID, SITE_ID, PLANT_ID
        ,ITEM_ID, OPERATION_ID, FACTORY_ID
        ,LOCATION, PRODUCTION_TYPE, MARKET
        ,LINE_ID, ELECTRODE_TYPE
        ,CUSTOMER_ID, PLAN_DATE
        ,TOP_ITEM_ID
        ,CELL_GROUP_CODE
        ,QTY
        ,JOB_USER_ID, JOB_TIME, JOB_TYPE, JOB_ORDER
      )
      VALUES (
         UPPER(RTRIM(LTRIM(@INSTANCE_ID))), UPPER(RTRIM(LTRIM(@PLAN_ID)))
        ,UPPER(RTRIM(LTRIM(@DIVISION_ID))), UPPER(RTRIM(LTRIM(@SITE_ID))), UPPER(RTRIM(LTRIM(@PLANT_ID)))
        ,UPPER(RTRIM(LTRIM(@ITEM_ID))), UPPER(RTRIM(LTRIM(@OPERATION_ID))), UPPER(RTRIM(LTRIM(@FACTORY_ID)))
        ,'-', '-', 'D'
        ,UPPER(RTRIM(LTRIM(@LINE_ID))), '-'
        ,'-' ,CONVERT(DATE, RTRIM(LTRIM(@PLAN_DATE)))
        ,UPPER(RTRIM(LTRIM(@ITEM_ID)))
        ,UPPER(ISNULL( (	SELECT DISTINCT A.SEGMENT3 AS GROUP_ITEM_ID
          FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
          WHERE  A.LOOKUP_TYPE_CODE = 'MODULE_CELL_GROUP'
          AND    A.ACTIVE_FLAG = 'Y'
          AND    A.SEGMENT2 = RTRIM(LTRIM(@DIVISION_ID))
          AND    A.SEGMENT1 = RTRIM(LTRIM(@SITE_ID))
          AND    A.SEGMENT4 = RTRIM(LTRIM(@ITEM_ID))
          ), RTRIM(LTRIM(@ITEM_ID)) ))
        ,RTRIM(LTRIM(@QTY))
        ,@USER_ID, dbo.SYSDATE1(), '-', @JOB_ORDER
      )