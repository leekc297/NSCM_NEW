SELECT DISTINCT A.OPERATION_ID AS CODE, '(' + A.OPERATION_ID + ')' + B.OPERATION_NAME AS NAME
           , A.AMEND_MAIN_FLAG
      FROM   FP_INSTANCE_OPERATION_V A
			, SCM_OPERATION_M B
      WHERE  A.COMPANY_ID   = B.COMPANY_ID
      AND    A.DIVISION_ID  = B.DIVISION_ID
      AND    A.SITE_ID      = B.SITE_ID
      AND    A.OPERATION_ID = B.OPERATION_ID
      AND    A.INSTANCE_ID  = @INSTANCE_ID
      AND    EXISTS (
			        	SELECT 1
			        	FROM   FP_USER_ROLE_INFO_V B WITH(NOLOCK)
			        	WHERE  A.COMPANY_ID  = B.COMPANY_ID
			        	AND    A.DIVISION_ID = B.DIVISION_ID
			        	AND    A.SITE_ID     = B.SITE_ID
			        	AND    A.OPERATION_ID = B.OPERATION_ID
			        	AND    B.USER_ID     = @USER_ID
			      	)
@CTRL_DIVISION_LT
@CTRL_SITE_ID

      AND   A.AMEND_FLAG = 'Y'
@CTRL_AMEND

      ORDER BY A.OPERATION_ID DESC