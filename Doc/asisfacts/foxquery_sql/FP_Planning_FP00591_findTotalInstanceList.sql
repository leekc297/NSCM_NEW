SELECT A.SEGMENT1 AS CODE, A.SEGMENT1 AS NAME, MAX(A.SEGMENT2) AS INSTANCE_ID
          FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
          WHERE  A.LOOKUP_TYPE_CODE = 'TOTAL_INSTANCE_INFO'
          AND    A.ACTIVE_FLAG      = 'Y'
          AND    A.SEGMENT3         = @SITE_ID
          GROUP BY A.SEGMENT1
          ORDER BY A.SEGMENT1