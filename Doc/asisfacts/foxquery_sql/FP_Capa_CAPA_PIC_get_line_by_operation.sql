--BEGIN
		    --    BEGIN TRAN
		    
	  SELECT A.LINE_ID AS CODE
	  , '(' + A.LINE_ID + ')' + CASE WHEN A.LINE_NAME = '' OR A.LINE_NAME IS NULL THEN A.LINE_ID ELSE A.LINE_NAME END AS NAME
	  ,A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.OPERATION_ID, A.LINE_ID, A.LINE_NAME FROM SCM_LINE_M A
	  WHERE 
	  A.ACTIVE_FLAG = 'Y'
	        AND   EXISTS (
            SELECT 1 FROM (
              SELECT DISTINCT A.COMPANY_ID,A.DIVISION_ID,A.SITE_ID,A.PLANT_ID,A.FACTORY_ID
              FROM  SCM_FACTORY_M A WITH(NOLOCK)
              INNER JOIN FP_INSTANCE_FACTORY_M B WITH(NOLOCK)
              ON    A.FACTORY_ID  = B.FACTORY_ID
              AND   B.ACTIVE_FLAG = 'Y'
              WHERE A.ACTIVE_FLAG = 'Y'
              --AND A@CTRL_INSTANCE_ID -- [AND B.INSTANCE_ID = @INSTANCE_ID]
            ) C
            WHERE C.COMPANY_ID=A.COMPANY_ID AND C.DIVISION_ID=A.DIVISION_ID AND C.SITE_ID=A.SITE_ID AND C.PLANT_ID=A.PLANT_ID AND C.FACTORY_ID=A.FACTORY_ID
      )
				AND ( (@DIVISION_ID IS NULL OR @DIVISION_ID ='') OR A.DIVISION_ID IN ( SELECT token FROM dbo.String_Split(@DIVISION_ID,',')) )
				AND ( (@PLANT_ID IS NULL OR @PLANT_ID ='') OR A.PLANT_ID IN ( SELECT token FROM dbo.String_Split(SUBSTRING(@PLANT_ID,1,4),','))   )
				AND ( (@FACTORY_ID IS NULL OR @FACTORY_ID ='') OR A.FACTORY_ID IN ( SELECT token FROM dbo.String_Split(@FACTORY_ID,','))   )
				AND ( (@OPERATION_ID IS NULL OR @OPERATION_ID ='') OR A.OPERATION_ID IN ( SELECT token FROM dbo.String_Split(@OPERATION_ID,','))   )
				AND ( (@SITE_ID IS NULL OR @SITE_ID ='') OR A.SITE_ID IN ( SELECT token FROM dbo.String_Split(@SITE_ID,','))   )
				UNION
				SELECT 
					'-'  AS CODE
					,'-'  AS NAME
					,'-'  AS COMPANY_ID
					,'-' AS DIVISION_ID
					,'-' AS SITE_ID
					,'-' AS PLANT_ID
					,'-' AS FACTORY_ID
					,'-' AS OPERATION_ID
					,'-' AS LINE_ID
					,'-' AS LINE_NAME
				ORDER BY NAME   
   		      --  COMMIT;
		     -- END;