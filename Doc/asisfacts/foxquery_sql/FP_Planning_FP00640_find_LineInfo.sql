SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.OPERATION_ID
             , A.LINE_ID, A.ELECTRODE_TYPE, ISNULL(A.PROD_VERSION_TYPE,'GENERAL') AS PROD_VERSION_TYPE
        FROM SCM_LINE_M A WITH(NOLOCK)
        WHERE 1=1
        AND A.ACTIVE_FLAG = 'Y'
        ORDER BY A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.OPERATION_ID, A.LINE_ID, A.ELECTRODE_TYPE