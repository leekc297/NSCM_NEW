SELECT @DIVISION_ID + '_' + REPLICATE('0', 4 - LEN(CONVERT(NUMERIC(4), ISNULL(MAX(RIGHT(GROUP_ID, 4)), '0'))+1)) + CAST(CONVERT(NUMERIC(4), ISNULL(MAX(RIGHT(GROUP_ID, 4)), '0')) + 1 AS VARCHAR) AS GROUP_ID
          FROM  JOB_SCHEDULE_MASTER A WITH(NOLOCK)
          WHERE DIVISION_ID = @DIVISION_ID
          AND   GROUP_ID LIKE @DIVISION_ID + '_%'