SELECT *
      FROM (
        SELECT D0 AS CODE, D0 AS NAME
             , DATED1 AS START_DATE
             , CONVERT(VARCHAR, CONVERT(DATETIME, A.DATED1)+27, 112) AS END_DATE
             , DATED1 AS MIN_DATE
        FROM   TH_UIS_CALENDAR A WITH(NOLOCK)
        WHERE  D0 BETWEEN (SELECT ISO_YYYYWW FROM TH_UIS_CAL A WITH(NOLOCK) WHERE YYYYMMDD = CONVERT(VARCHAR,GETDATE()-(7*(SELECT CONVERT(NUMERIC, A.SEGMENT1) AS MIN_WEEK_RANGE FROM SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK) WHERE A.LOOKUP_TYPE_CODE = 'WPP_WEEK_RANGE')),112))
                  AND     (SELECT ISO_YYYYWW FROM TH_UIS_CAL A WITH(NOLOCK) WHERE YYYYMMDD = CONVERT(VARCHAR,GETDATE()-7,112))
        UNION ALL
        SELECT ISO_YYYYWW AS CODE, ISO_YYYYWW AS NAME
             --, (CASE WHEN CONVERT(VARCHAR,GETDATE(),112) > MIN(YYYYMMDD) THEN CONVERT(VARCHAR,GETDATE(),112) ELSE MIN(YYYYMMDD) END) AS START_DATE
             , MIN(YYYYMMDD) AS START_DATE
             --, (CASE WHEN TODAY > MIN(YYYYMMDD) THEN TODAY ELSE MIN(YYYYMMDD) END) AS START_DATE
             , CONVERT(VARCHAR, (MIN(DT)+27), 112) AS END_DATE
             , MIN(YYYYMMDD) AS MIN_DATE
        FROM   TH_UIS_CAL
        WHERE  YYYYMMDD BETWEEN (SELECT DATED1 FROM TH_UIS_CALENDAR WHERE D0 = (SELECT ISO_YYYYWW FROM TH_UIS_CAL A WITH(NOLOCK) WHERE YYYYMMDD = @TODAY))
        AND     CONVERT(VARCHAR, DATEADD(DD, 13, CONVERT(DATE,(SELECT DATED1 FROM TH_UIS_CALENDAR WHERE D0 = (SELECT ISO_YYYYWW FROM TH_UIS_CAL A WITH(NOLOCK) WHERE YYYYMMDD = CONVERT(VARCHAR,GETDATE(),112))))), 112)
        
        --WHERE  YYYYMMDD BETWEEN (SELECT DATED1 FROM TH_UIS_CALENDAR WHERE D0 = (SELECT ISO_YYYYWW FROM TH_UIS_CAL A WITH(NOLOCK) WHERE YYYYMMDD = CONVERT(VARCHAR,GETDATE(),112)))
        --                AND     CONVERT(VARCHAR, DATEADD(DD, 13, CONVERT(DATE,(SELECT DATED1 FROM TH_UIS_CALENDAR WHERE D0 = (SELECT ISO_YYYYWW FROM TH_UIS_CAL A WITH(NOLOCK) WHERE YYYYMMDD = CONVERT(VARCHAR,GETDATE(),112))))), 112)
        
        GROUP BY ISO_YYYYWW
      ) A
      ORDER BY CODE