SELECT A.INSTANCE_ID, CONVERT(VARCHAR,A.PLAN_DATE,112) AS PLAN_DATE, A.FP_PLAN_ID
             , A.COMPANY_ID, A.DIVISION_ID , A.CATEGORY_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID
             , A.LINE_ID, A.OPERATION_ID, A.ITEM_ID, A.TOP_ITEM_ID, A.ITEM_TYPE, A.PLM_EC_NO, A.VERSION
             , A.LOCATION, A.PRODUCTION_TYPE, A.MARKET, A.ELECTRODE_TYPE
             , A.IN_QTY, A.OUT_QTY
        FROM   FP_AMEND_PLAN_CELL_R A WITH(NOLOCK)
        WHERE  A.INSTANCE_ID  = @INSTANCE_ID
        AND    A.FP_PLAN_ID   = @PLAN_ID
        AND    A.CATEGORY_ID  = 'PLAN'
        ORDER BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.OPERATION_ID, A.LINE_ID
               , A.ELECTRODE_TYPE, A.ITEM_ID, A.ITEM_TYPE, A.PLM_EC_NO, A.PRODUCTION_TYPE, A.MARKET, A.PLAN_DATE