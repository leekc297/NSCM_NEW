BEGIN
        BEGIN TRAN
          MERGE INTO FP_THEORY_STOCK_M AS A
          USING ( SELECT (SELECT MAX(COMPANY_ID) FROM SCM_FACTORY_M CC WITH(NOLOCK) WHERE CC.FACTORY_ID = RTRIM(LTRIM(@FACTORY_ID))) AS COMPANY_ID, RTRIM(LTRIM(@DIVISION_ID)) AS DIVISION_ID, RTRIM(LTRIM(@SITE_ID)) AS SITE_ID, RTRIM(LTRIM(@PLANT_ID)) AS PLANT_ID, RTRIM(LTRIM(@FACTORY_ID)) AS FACTORY_ID
                       , RTRIM(LTRIM(@OPERATION_ID)) AS OPERATION_ID, RTRIM(LTRIM(@LINE_ID)) AS LINE_ID, RTRIM(LTRIM(@ELECTRODE_TYPE)) AS ELECTRODE_TYPE, RTRIM(LTRIM(@ITEM_ID)) AS ITEM_ID
                       , @THEORY_STOCK_QTY AS THEORY_STOCK_QTY, (CASE WHEN @ACTIVE_FLAG IS NULL OR @ACTIVE_FLAG = '' THEN 'Y' ELSE @ACTIVE_FLAG END) AS ACTIVE_FLAG
                       , RTRIM(LTRIM(@USER_ID)) AS UPDATE_ID, dbo.FN_SITE_TIME(@SITE_ID) AS UPDATE_TIME
          ) AS B
          ON (A.FACTORY_ID     = B.FACTORY_ID
          AND A.OPERATION_ID   = B.OPERATION_ID
          AND A.LINE_ID        = B.LINE_ID
          AND A.ELECTRODE_TYPE = B.ELECTRODE_TYPE
          AND A.OPERATION_ID   = B.OPERATION_ID
          AND A.ITEM_ID        = B.ITEM_ID )
          WHEN MATCHED THEN 
          	UPDATE SET 
          		  THEORY_STOCK_QTY = B.THEORY_STOCK_QTY
          		, ACTIVE_FLAG      = B.ACTIVE_FLAG
          		, UPDATE_ID        = B.UPDATE_ID
          		, UPDATE_TIME      = B.UPDATE_TIME
          WHEN NOT MATCHED THEN 
          	INSERT (
          		  COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, FACTORY_ID
          		, OPERATION_ID, LINE_ID, ELECTRODE_TYPE, ITEM_ID
          		, THEORY_STOCK_QTY, ACTIVE_FLAG
          		, INSERT_ID, INSERT_TIME
          		, UPDATE_ID, UPDATE_TIME
          	) VALUES (
          		  B.COMPANY_ID, B.DIVISION_ID, B.SITE_ID, B.PLANT_ID, B.FACTORY_ID
          		, B.OPERATION_ID, B.LINE_ID, B.ELECTRODE_TYPE, B.ITEM_ID
          		, B.THEORY_STOCK_QTY, B.ACTIVE_FLAG
          		, B.UPDATE_ID, B.UPDATE_TIME
          		, B.UPDATE_ID, B.UPDATE_TIME
          	)
          ;
        
        COMMIT;
        
        
      END;