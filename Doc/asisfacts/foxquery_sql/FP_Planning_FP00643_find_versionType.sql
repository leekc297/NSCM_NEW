SELECT A.SEGMENT3 AS PRODUCTION_TYPE
      	   , A.ATTRIBUTE1 AS VERSION_TYPE_1
      	   , A.ATTRIBUTE2 AS VERSION_TYPE_2
      	   , A.ATTRIBUTE3 AS VERSION_TYPE_3
      	   , A.ATTRIBUTE4 AS VERSION_TYPE_4
      	   , A.ATTRIBUTE5 AS VERSION_TYPE_5
      FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
      WHERE  A.LOOKUP_TYPE_CODE = 'INSTANCE_CONV_PRIORITY'
      AND    A.ACTIVE_FLAG = 'Y'
      AND    A.SEGMENT1    = @MASTER_ID
      AND    A.SEGMENT3   <> 'DEFAULT'
      ORDER BY A.SORT_ORDER