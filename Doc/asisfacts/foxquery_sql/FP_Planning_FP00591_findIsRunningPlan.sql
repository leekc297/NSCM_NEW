SELECT ISNULL(MAX(A.ACTIVE_FLAG),0) AS CNT
               , MAX(A.PLAN_ID) AS PLAN_ID
               , MAX(A.INSERT_ID) AS INSERT_ID
          FROM   FP_PLAN_STATUS_H A(NOLOCK)
          WHERE  A.ACTIVE_FLAG = '1'
          AND    A.INSTANCE_ID IN (
          	SELECT A.SEGMENT2 AS INSTANCE_ID
          	FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
          	WHERE  A.LOOKUP_TYPE_CODE = 'TOTAL_INSTANCE_INFO'
          	AND    A.ACTIVE_FLAG = 'Y'
          	AND    A.SEGMENT1 = @INSTANCE_ID
          )