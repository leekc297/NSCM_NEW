SELECT CONVERT(VARCHAR, A.RECEIVING_DTTM, 112) AS PLAN_DATE
           , A.ROUTE_ID AS LINE_ID
           --, A.ITEM_ID -- form item
           , B.CELL_PRODUCT_ITEM_ID AS ITEM_ID -- cell product
           , ISNULL(A.QTY,0) AS AGING_STOCK 
      FROM   TH_MST_STOCK_PLAN_V A WITH(NOLOCK)
      INNER JOIN (
    			SELECT C.FACTORY_ID AS SITE_ID, B.CELL_ASSY_ITEM_ID, B.CELL_PRODUCT_ITEM_ID
    			FROM   FP_CELL_ASSY_PRODUCT_MAP_V B WITH(NOLOCK)
    			, (
      				SELECT C.COMPANY_ID, C.DIVISION_ID, C.SITE_ID, C.FACTORY_ID
      				FROM   FP_INSTANCE_LINE_V C WITH(NOLOCK)
      				WHERE  1=1
      				AND    C.INSTANCE_ID = @FORM_INSTANCE_ID
      				GROUP BY C.COMPANY_ID, C.DIVISION_ID, C.SITE_ID, C.FACTORY_ID
    			) C
    			WHERE  1=1
    			AND    B.COMPANY_ID  = C.COMPANY_ID
    			AND    B.DIVISION_ID = C.DIVISION_ID
    			AND    B.SITE_ID     = C.SITE_ID
    			GROUP BY C.FACTORY_ID, B.CELL_ASSY_ITEM_ID, B.CELL_PRODUCT_ITEM_ID
      ) B
      ON  1=1 
      AND A.SITE_ID     = B.SITE_ID -- factory_id
      AND A.ITEM_ID     = B.CELL_ASSY_ITEM_ID 
      WHERE  A.MASTER_ID    = @FORM_INSTANCE_ID
      AND    A.PLAN_ID IN (@PLAN_ID_SCRIPT
 
      )
      AND    A.STOCK_STATUS = 'AGING_STOCK'