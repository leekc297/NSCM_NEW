SELECT @PLAN_DATE AS PLAN_DATE, A.INSTANCE_ID, NULL AS FACTORY_ID, A.PLAN_ID
        	 , NULL AS CONFIRM_ID, NULL AS CONFIRM_TIME, NULL AS CONFIRM_FLAG
        	 , NULL AS RELEASE_TIME, NULL AS RELEASE_FLAG
        	 , 'ENGINE' AS _TYPE
      FROM   FP_PLAN_STATUS_H A WITH(NOLOCK)
      WHERE  A.INSTANCE_ID = @MASTER_ID
      AND    A.PLAN_ID	   = @PLAN_ID
      AND    A.ACTIVE_FLAG = '1'
      UNION ALL
      SELECT A.PLAN_DATE, A.INSTANCE_ID, A.FACTORY_ID, A.PLAN_ID
        	 , A.CONFIRM_ID, CONVERT(VARCHAR,A.CONFIRM_TIME,20) AS CONFIRM_TIME, A.CONFIRM_FLAG
        	 , CONVERT(VARCHAR,A.RELEASE_TIME,20) AS RELEASE_TIME, A.RELEASE_FLAG
        	 , 'FACTORY' AS _TYPE
      FROM   SCM_FP_PLAN_DETAIL_H A WITH(NOLOCK)
      WHERE  A.PLAN_DATE		= @PLAN_DATE
      AND    A.INSTANCE_ID  = @MASTER_ID
      AND    A.PLAN_ID	    = @PLAN_ID
      AND    (A.CONFIRM_FLAG = 'P' OR A.RELEASE_FLAG = 'P')
      UNION ALL
      SELECT A.PLAN_DATE, A.INSTANCE_ID, A.PLAN_GROUP_ID AS FACTORY_ID, A.PLAN_ID
        	 , A.CONFIRM_ID, CONVERT(VARCHAR,A.CONFIRM_TIME,20) AS CONFIRM_TIME, A.CONFIRM_FLAG
        	 , CONVERT(VARCHAR,A.RELEASE_TIME,20) AS RELEASE_TIME, A.RELEASE_FLAG
        	 , 'PLAN_GROUP' AS _TYPE
      FROM   SCM_FP_PLAN_GROUP_DETAIL_H A WITH(NOLOCK)
      WHERE  A.PLAN_DATE		= @PLAN_DATE
      AND    A.INSTANCE_ID	= @MASTER_ID
      AND    A.PLAN_ID	  	= @PLAN_ID
      AND    (A.CONFIRM_FLAG = 'P' OR A.RELEASE_FLAG = 'P')
      UNION ALL
      SELECT @PLAN_DATE AS PLAN_DATE
           , A.INSTANCE_ID
           , '' AS FACTORY_ID
           , '' AS PLAN_ID
           , '' AS CONFIRM_ID
           , CONVERT(VARCHAR, A.EVENT_TIME, 20) AS CONFIRM_TIME
           , (CASE WHEN A.EVENT_TIME IS NOT NULL THEN 'Y' ELSE 'N' END) AS CONFIRM_FLAG
           , CONVERT(VARCHAR, A.CALCULATION_END, 20) AS RELEASE_TIME
           , (CASE WHEN A.CALCULATION_START IS NOT NULL AND A.CALCULATION_END IS NOT NULL THEN 'Y' ELSE 'N' END) AS RELEASE_FLAG
           , 'CONFIRM' AS _TYPE
      FROM   FP_RELEASE_CALCULATION_STATUS_H A WITH(NOLOCK)
      WHERE  A.INSTANCE_ID = @MASTER_ID
      AND    A.CALCULATION_STATUS IN ('RUN','WAIT')