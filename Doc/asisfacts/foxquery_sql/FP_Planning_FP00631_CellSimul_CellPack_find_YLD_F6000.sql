SELECT A.*
      	 , D1.LINE_ID
      	 , D1.ITEM_ID
      	 , CASE WHEN ISNULL(ISNULL(D2.YIELD, D1.YIELD), 1) = 0 THEN 1
      		    ELSE ISNULL(ISNULL(D2.YIELD, D1.YIELD), 1)
      		    END  AS YIELD
      FROM (
        	SELECT DISTINCT A.*, 'F6000' AS OPERATION_ID, CONVERT(VARCHAR, B.DATE_ID, 112) AS PLAN_DATE, B.YEAR+B.MONTH AS MONTH
        	FROM (
          		SELECT DISTINCT B.COMPANY_ID, B.DIVISION_ID, B.SITE_ID, B.PLANT_ID, B.FACTORY_ID
          		FROM   FP_INSTANCE_FACTORY_M A WITH(NOLOCK), SCM_FACTORY_M B WITH(NOLOCK)
          		WHERE  A.FACTORY_ID  = B.FACTORY_ID
          		AND    A.ACTIVE_FLAG = 'Y'
          		AND    B.ACTIVE_FLAG = 'Y'
          		AND    A.INSTANCE_ID = @FORM_INSTANCE_ID
        	) A, SCM_SYS_CALENDAR_M B WITH(NOLOCK)
        	WHERE 1=1
        	AND   B.DATE_ID BETWEEN CONVERT(DATETIME,@BUCKET_FROM) AND CONVERT(DATETIME,@BUCKET_TO)
      ) A
      LEFT OUTER JOIN SCM_YIELD_M AS D1 WITH(NOLOCK)
      ON     A.COMPANY_ID     = D1.COMPANY_ID
      AND    A.DIVISION_ID    = D1.DIVISION_ID
      AND    A.SITE_ID        = D1.SITE_ID
      AND    A.PLANT_ID       = D1.PLANT_ID
      AND    A.FACTORY_ID     = D1.FACTORY_ID
      AND    A.OPERATION_ID   = D1.OPERATION_ID
      AND    A.MONTH          = D1.MONTH
      LEFT OUTER JOIN SCM_YIELD_EXCEPT_M D2 WITH(NOLOCK)
      ON     A.COMPANY_ID     = D2.COMPANY_ID
      AND    A.DIVISION_ID    = D2.DIVISION_ID
      AND    A.SITE_ID        = D2.SITE_ID
      AND    A.PLANT_ID       = D2.PLANT_ID
      AND    A.FACTORY_ID     = D2.FACTORY_ID
      AND    A.OPERATION_ID   = D2.OPERATION_ID
      AND    D1.OPERATION_ID  = D2.OPERATION_ID 
      AND    A.PLAN_DATE     >= D2.START_TIME
      AND    A.PLAN_DATE     <= D2.END_TIME
      AND    D2.ACTIVE_FLAG   = 'Y'
      WHERE  D1.LINE_ID IS NOT NULL
      ORDER BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.OPERATION_ID, D1.LINE_ID, D1.ITEM_ID, A.PLAN_DATE, A.MONTH, YIELD