SELECT DISTINCT AA.SEGMENT1 AS INSTANCE_ID, AA.SEGMENT2 AS MODEL_TYPE,AA.ATTRIBUTE6 AS GROUP_ID FROM SCM_SYS_LOOKUP_VALUE AA WITH(NOLOCK)
WHERE 1=1
AND AA.LOOKUP_TYPE_CODE = 'INSTANCE_PLANNING_GROUP'
AND ISNULL(AA.SEGMENT2,'') <> ''
AND ISNULL(AA.ATTRIBUTE6,'') <> ''
AND ISNULL(AA.SEGMENT1,'') = 'PL_FORM_A'