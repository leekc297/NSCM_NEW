         INSTANCE_ID, FP_PLAN_ID, COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID
        ,ITEM_ID, OPERATION_ID, FACTORY_ID
        ,LOCATION, PRODUCTION_TYPE, MARKET
        ,LINE_ID, ELECTRODE_TYPE
        ,TOP_ITEM_ID, ITEM_TYPE, CATEGORY_ID
        ,PLAN_DATE
        ,CELL_OUT_QTY
        ,OUT_QTY
        ,DATE_SEQ
        ,JOB_USER_ID, JOB_TIME, JOB_TYPE, JOB_ORDER
        ,PLM_EC_NO
        ,VERSION
      )
      VALUES (
         UPPER(RTRIM(LTRIM(@INSTANCE_ID))), UPPER(RTRIM(LTRIM(@FP_PLAN_ID))), UPPER(RTRIM(LTRIM(@COMPANY_ID))), UPPER(RTRIM(LTRIM(@DIVISION_ID))), UPPER(RTRIM(LTRIM(@SITE_ID))), UPPER(RTRIM(LTRIM(@PLANT_ID)))
        ,UPPER(RTRIM(LTRIM(@ITEM_ID))), UPPER(RTRIM(LTRIM(@OPERATION_ID))), UPPER(RTRIM(LTRIM(@FACTORY_ID)))
        ,UPPER(RTRIM(LTRIM(@LOCATION))), UPPER(RTRIM(LTRIM(@PRODUCTION_TYPE))), UPPER(RTRIM(LTRIM(@MARKET)))
        ,UPPER(RTRIM(LTRIM(@LINE_ID))), RTRIM(LTRIM(@ELECTRODE_TYPE))
        ,UPPER(RTRIM(LTRIM(@TOP_ITEM_ID))), RTRIM(LTRIM(@ITEM_TYPE)), 'PLAN'
        ,CONVERT(DATE, RTRIM(LTRIM(@PLAN_DATE)))
        ,RTRIM(LTRIM(@CELL))
        ,RTRIM(LTRIM(@QTY))
        ,CASE WHEN CONVERT(NUMERIC(25,10),ISNULL(RTRIM(LTRIM(@QTY)),0)) = 0 THEN 0 ELSE 1 END 
        ,@USER_ID, dbo.SYSDATE1(), '-', @JOB_ORDER
        ,@PLM_EC_NO
        ,@VERSION
      )