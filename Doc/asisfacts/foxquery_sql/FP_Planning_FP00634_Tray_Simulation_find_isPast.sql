SELECT AA.*
           , (SELECT DATED1 FROM TH_UIS_CALENDAR T1 WITH(NOLOCK) WHERE D0 = (SELECT ISO_YYYYWW FROM TH_UIS_CAL A WITH(NOLOCK) WHERE YYYYMMDD = AA.CURR_DATE)) AS PLAN_START_DATE
           , CONVERT(VARCHAR, DATEADD(DD, 27, CONVERT(DATE,(SELECT DATED1 FROM TH_UIS_CALENDAR _T2 WITH(NOLOCK) WHERE D0 = (SELECT ISO_YYYYWW FROM TH_UIS_CAL A WITH(NOLOCK) WHERE YYYYMMDD = AA.CURR_DATE)))), 112) AS PLAN_END_DATE
      FROM (
          SELECT A.BASIS_START_TIME
        		   , CASE WHEN FORMAT(dbo.FN_SITE_TIME(B.SITE_ID) ,'yyyyMMddHHmmss') < CONVERT(VARCHAR,dbo.FN_SITE_TIME(B.SITE_ID),112) + A.BASIS_START_TIME 
        				  THEN CONVERT(VARCHAR, DATEADD(DD,-1,dbo.FN_SITE_TIME(B.SITE_ID)), 112)
        				  ELSE CONVERT(VARCHAR, dbo.FN_SITE_TIME(B.SITE_ID), 112) END AS CURR_DATE
          FROM   FP_INSTANCE_START_TIME_V A, (
          		SELECT MAX(B.SITE_ID) AS SITE_ID
          		FROM   FP_INSTANCE_FACTORY_M A WITH(NOLOCK), SCM_FACTORY_M B WITH(NOLOCK)
          		WHERE  A.FACTORY_ID = B.FACTORY_ID
          		AND    A.ACTIVE_FLAG = 'Y'
          		AND    B.ACTIVE_FLAG = 'Y'
          		AND    A.INSTANCE_ID = @INSTANCE_ID
      	  ) B
          WHERE  A.INSTANCE_ID = @INSTANCE_ID
      ) AA