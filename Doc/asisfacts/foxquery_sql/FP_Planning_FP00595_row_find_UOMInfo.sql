SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID
     , A.OPERATION, A.ITEM_ID
     , UPPER(A.CATEGORY) AS CATEGORY
     , A.PROD_VERSION_TYPE, A.VERSION_TYPE
     , A.MODEL_ID, A.VALUE, A.APPLY_DATE
     , A.VERSION
FROM   SCM_ITEM_CONV_CALC_M A WITH(NOLOCK)
INNER JOIN (
	SELECT DISTINCT A.ATTRIBUTE1 AS E_CATEGORY
	FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
	WHERE  A.LOOKUP_TYPE_CODE = 'ITEM_CONV_CALC'
	AND    A.ATTRIBUTE2 = 'Y'
) D
ON     A.CATEGORY = D.E_CATEGORY
INNER JOIN (
	SELECT COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, FACTORY_ID, MODEL_ID, OPERATION, ITEM_ID, VERSION
	FROM   SCM_ITEM_CONV_CALC_M A WITH(NOLOCK)
	WHERE  1=1
	AND    A.VALUE > 0
	AND    A.CATEGORY IN (  'Jumbo Roll (cell/m)'
    						, 'Lane Number'
    						, 'Pancake (m/batch)'
    						, 'cell/batch'
    						, 'Jumbo Roll (m/batch)'
    						, 'Pancake (cell/m)' )
	GROUP BY COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, FACTORY_ID, MODEL_ID, OPERATION, ITEM_ID, VERSION
	HAVING COUNT(1) = 6
) E
ON     A.COMPANY_ID         = E.COMPANY_ID
AND    A.DIVISION_ID        = E.DIVISION_ID
AND    A.SITE_ID            = E.SITE_ID
AND    A.PLANT_ID           = E.PLANT_ID
AND    A.FACTORY_ID         = E.FACTORY_ID
AND    A.OPERATION          = E.OPERATION
AND    A.ITEM_ID            = E.ITEM_ID
AND    A.MODEL_ID           = E.MODEL_ID
AND    A.VERSION            = E.VERSION
WHERE  1=1
AND    A.OPERATION = 'E2000'
AND    A.CATEGORY IN ('cell/batch','Pancake (m/batch)','Jumbo Roll (m/batch)')
@CTRL_DIVISION_LT
@CTRL_SITE_LT
@CTRL_PLANT_LT
@CTRL_FACTORY_LT
--ORDER BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID
--       , A.MODEL_ID, A.ITEM_ID, A.APPLY_DATE DESC
--       , A.CATEGORY, A.PROD_VERSION_TYPE, A.VERSION_TYPE
ORDER BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID
       , A.OPERATION, A.ITEM_ID, A.MAX_VER_FLAG DESC, A.APPLY_DATE DESC, A.VERSION DESC
       , A.PROD_VERSION_TYPE, A.VERSION_TYPE
       , A.CATEGORY, A.MODEL_ID