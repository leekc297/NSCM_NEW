SELECT A.LOOKUP_TYPE_CODE, A.LOOKUP_TYPE_CODE AS ORG_LOOKUP_TYPE_CODE 
            ,MAX(A.VALUE_DESCRIPTION) AS VALUE_DESCRIPTION
    --,A.SYSTEM_TYPE_CODE 
    ,@v_active_flag As ACTIVE_FLAG-- MAX(A.ACTIVE_FLAG)
    ,'USAGE TYPE' AS SEGMENT1--,A.SEGMENT1 
    ,'VALUE' AS SEGMENT2--,A.SEGMENT2 
    ,'' AS SEGMENT3--,A.SEGMENT3 
    ,'' AS SEGMENT4--,A.SEGMENT4 
    ,'' AS SEGMENT5--,A.SEGMENT5 
    ,MAX(A.CREATE_USER_ID )
    ,MAX(CONVERT(VARCHAR, A.CREATE_DATE, 120)) AS CREATE_DATE 
    ,MAX(A.MODIFY_USER_ID )
    ,MAX(ISNULL(CONVERT(VARCHAR, A.MODIFY_DATE, 120),CONVERT(VARCHAR, A.CREATE_DATE, 120))) AS MODIFY_DATE 
    ,'REFERENCE TYPE' AS ATTRIBUTE1--,A.ATTRIBUTE1 
    ,'REFERENCE VALUE' AS ATTRIBUTE2--,A.ATTRIBUTE2 
    ,'MIN-MAX ATTRIBUTE' AS ATTRIBUTE3--,A.ATTRIBUTE3 
    ,'' AS ATTRIBUTE4--,A.ATTRIBUTE4	
    ,'' AS ATTRIBUTE5--,A.ATTRIBUTE5	
    ,'' AS ATTRIBUTE6--,A.ATTRIBUTE6	
    ,'' AS ATTRIBUTE7--,A.ATTRIBUTE7	
    ,'' AS ATTRIBUTE8--,A.ATTRIBUTE8	
    ,'' AS ATTRIBUTE9--,A.ATTRIBUTE9	
    ,'' AS ATTRIBUTE10--,A.ATTRIBUTE10	
    ,'' AS ATTRIBUTE11--,A.ATTRIBUTE11	
    ,'' AS ATTRIBUTE12--,A.ATTRIBUTE12	
    ,'' AS ATTRIBUTE13--,A.ATTRIBUTE13	
    ,'' AS ATTRIBUTE14--,A.ATTRIBUTE14	
    ,'' AS ATTRIBUTE15--,A.ATTRIBUTE15	
     FROM   SCM_CODE_LOOKUP_VALUE A WITH(NOLOCK) 
     WHERE  1 = 1  
	AND (UPPER(A.LOOKUP_TYPE_CODE) LIKE (N'%' + @p_lookup_type_code +  '%')  OR ISNULL(@p_lookup_type_code,'') ='')
			 AND (A.ACTIVE_FLAG = @v_active_flag  OR ISNULL(@v_active_flag,'') ='')
		 AND (UPPER(A.SEGMENT1) LIKE (N'%' + @P_SEGMENT1+ '%') 	OR ISNULL(@P_SEGMENT1,'')='')
		 AND (UPPER(A.SEGMENT2) LIKE (N'%' + @P_SEGMENT2+ '%') OR ISNULL(@P_SEGMENT2,'')='')
		 AND (UPPER(A.SEGMENT3) LIKE (N'%' + @P_SEGMENT3+ '%') OR ISNULL(@P_SEGMENT3,'')='')
		 AND (UPPER(A.SEGMENT4) LIKE (N'%' + @P_SEGMENT4+ '%') OR ISNULL(@P_SEGMENT4,'')='')
		 AND (UPPER(A.SEGMENT5) LIKE (N'%' + @P_SEGMENT5+ '%') OR ISNULL(@P_SEGMENT5,'')='')
		GROUP BY A.LOOKUP_TYPE_CODE
	 ORDER BY A.LOOKUP_TYPE_CODE