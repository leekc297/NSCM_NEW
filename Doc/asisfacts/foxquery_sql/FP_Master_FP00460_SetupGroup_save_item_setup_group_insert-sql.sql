BEGIN
		        BEGIN TRAN
				

MERGE INTO FP_ITEM_SETUP_GROUP_M A
using 
(
	SELECT 
	@INSTANCE_ID AS INSTANCE_ID,
  	@OPERATION_ID AS OPERATION_ID,
	@SETUP_CATEGORY_ID AS SETUP_CATEGORY_ID,
	@SETUP_KEY_ID AS SETUP_KEY_ID
) B
ON 1=1
AND A.INSTANCE_ID = B.INSTANCE_ID
AND A.OPERATION_ID = B.OPERATION_ID
AND A.SETUP_CATEGORY_ID = B.SETUP_CATEGORY_ID
AND A.SETUP_KEY_ID = B.SETUP_KEY_ID
WHEN MATCHED THEN
UPDATE SET ACTIVE_FLAG = ISNULL(@ACTIVE_FLAG,'Y')
        ,CALCULATION = @CALCULATION
		,DESCRIPTION = @DESCRIPTION
		,UPDATE_ID = @USER_ID
		,UPDATE_TIME =GETDATE();


INSERT INTO his_fp_item_setup_group_m
(
 INSTANCE_ID
   , OPERATION_ID,        SETUP_CATEGORY_ID ,SETUP_KEY_ID,DESCRIPTION--,ACTIVE_FLAG-- ,CALCULATION
, INSERT_ID,           INSERT_TIME        
, UPDATE_ID,   UPDATE_TIME    ,JOB_USER_ID,JOB_TIME, JOB_TYPE
)
VALUES
(
@INSTANCE_ID
,@OPERATION_ID
,@SETUP_CATEGORY_ID
,@SETUP_KEY_ID
,@DESCRIPTION
--,@ACTIVE_FLAG
,@USER_ID
,GetDATE()
,@USER_ID
,GetDate()
,@USER_ID
,GetDate()
,'UPDATE'
)
		        COMMIT;
		      END;