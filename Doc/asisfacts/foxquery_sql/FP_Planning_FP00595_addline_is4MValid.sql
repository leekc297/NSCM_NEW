--  PDS_TARGET_FLAG가 Y이면 TARGET_PDS(ATTR5)에서 사용하는 DEMAND_TYPE임, 4MCC_TARGET_FLAG(ATTR6)가 Y이면 TARGET_PDS에서 들어온 버전을 사용하다.
  SELECT CASE WHEN COUNT(*) > 0 THEN 'Y' ELSE 'N' end AS IS_4M_VALID FROM SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK) 
  WHERE  A.LOOKUP_TYPE_CODE = 'DIVISION_DEMAND_TYPE'
AND ISNULL(A.SEGMENT1,'') =  @DIVISION_ID
AND ISNULL(A.ATTRIBUTE2,'') = '4M-VALID'--FP PRODUCTION_TYPE
AND ISNULL(A.ATTRIBUTE5,'') = 'Y' -- _4MCC_TARGET_FLAG-> PDS_TARGET_FLAG
AND ISNULL(A.ATTRIBUTE6,'') = 'Y' -- _4MCC_TARGET_FLAG 
AND    A.ACTIVE_FLAG = 'Y'

SELECT DISTINCT A.SEGMENT1 AS DIVISION_ID
, A.SEGMENT2 AS PRODUCTION_TYPE
,A.ATTRIBUTE2 AS FP_PRODUCTION_TYPE
--, (CASE WHEN A.ATTRIBUTE5 IS NULL OR A.ATTRIBUTE5 = '' THEN 'N' ELSE A.ATTRIBUTE5 END) AS _PDS_TARGET_FLAG -- 향후 5는 PDS_TARGET_FLAG
, (CASE WHEN A.ATTRIBUTE5 IS NULL OR A.ATTRIBUTE5 = '' THEN 'N' ELSE A.ATTRIBUTE5 END) AS _4MCC_TARGET_FLAG -- 향후 6이 4MCC_TARGET_FLAG로
FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
WHERE  A.LOOKUP_TYPE_CODE = 'DIVISION_DEMAND_TYPE'
AND ISNULL(A.SEGMENT1,'') =  @DIVISION_ID
AND ISNULL(A.ATTRIBUTE2,'') = '4M-VALID'
AND ISNULL(A.ATTRIBUTE5,'') = 'Y'
AND ISNULL(A.ATTRIBUTE6,'') = 'Y'
AND    A.ACTIVE_FLAG = 'Y'