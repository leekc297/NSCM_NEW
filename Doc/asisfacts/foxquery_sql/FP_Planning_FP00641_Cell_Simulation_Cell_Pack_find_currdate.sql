WITH SITE_T AS (
          SELECT DISTINCT INSTANCE_ID, SITE_ID
          FROM   FP_INSTANCE_OPERATION_V A WITH(NOLOCK)
          WHERE  INSTANCE_ID IN ( @INSTANCE_LT )
      )
      SELECT MIN(A.CURR_DATE) AS CURR_DATE
      FROM (
      	SELECT (CASE WHEN FORMAT(dbo.FN_SITE_TIME(B.SITE_ID) ,'yyyyMMddHHmmss') < (FORMAT(dbo.FN_SITE_TIME(B.SITE_ID) ,'yyyyMMdd') + A.BASIS_START_TIME)
      					THEN CONVERT(VARCHAR,DATEADD(DD,-1,FORMAT(dbo.FN_SITE_TIME(B.SITE_ID) ,'yyyyMMdd')),112) 
      				 ELSE FORMAT(dbo.FN_SITE_TIME(B.SITE_ID) ,'yyyyMMdd') END) AS CURR_DATE
      	FROM   FP_INSTANCE_START_TIME_V A, SITE_T B
      	WHERE  A.INSTANCE_ID = B.INSTANCE_ID
      ) A