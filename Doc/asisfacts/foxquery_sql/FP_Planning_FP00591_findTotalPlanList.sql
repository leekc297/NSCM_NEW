SELECT A.INTG_PLAN_ID AS CODE, A.INTG_PLAN_ID AS NAME
          FROM   SCM_FP_PLAN_H A WITH(NOLOCK)
          WHERE  A.INTG_PLAN_ID LIKE '%' + @INSTANCE_ID + '%'
          AND    CONVERT(VARCHAR(8), A.PLAN_START_TIME, 112) = @PLAN_DATE
          AND    PLAN_TYPE <> 'RELEASE'
          AND    RIGHT(A.PLAN_ID,2) <> '00'
          GROUP BY A.INTG_PLAN_ID
          ORDER BY A.INTG_PLAN_ID DESC