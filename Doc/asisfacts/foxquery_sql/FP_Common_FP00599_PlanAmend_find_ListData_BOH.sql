SELECT A.INSTANCE_ID, A.FP_PLAN_ID
           , A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID
           , A.PLANT_ID, A.ITEM_ID, A.TOP_ITEM_ID
           , A.OPERATION_ID, A.FACTORY_ID, A.LOCATION
           , ISNULL(ISNULL(A.MODIFY_QTY, A.QTY), 0) AS QTY
           , @PLAN_DATE AS PLAN_DATE
      FROM   @AMEND_CUTOFF_BOH_TABLE@ A WITH(NOLOCK)
      WHERE  A.INSTANCE_ID  = @MASTER_ID
      AND    A.FP_PLAN_ID   = @PLAN_ID
      ORDER BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.OPERATION_ID, A.LOCATION