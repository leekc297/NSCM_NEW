SELECT DISTINCT A.INSTANCE_ID, B.COMPANY_ID, B.DIVISION_ID, B.SITE_ID, B.PLANT_ID, B.FACTORY_ID, B.FACTORY_NAME
           , (CASE WHEN A.CONFIRM_AREA = 'PLAN GROUP' THEN C.PLAN_GROUP_ID
                   WHEN A.CONFIRM_AREA = 'BUILDING'   THEN '-' ELSE '-' END) AS PLAN_GROUP_ID
        	 , A.INSTANCE_ID + '_' + B.FACTORY_ID + (CASE WHEN A.CONFIRM_AREA = 'PLAN GROUP' THEN '_' + C.PLAN_GROUP_ID
                                                        WHEN A.CONFIRM_AREA = 'BUILDING'   THEN '' ELSE '' END) AS ROLE_NAME
           , B.SHOP_GROUP_ID
      FROM (
        	SELECT SEGMENT1 AS INSTANCE_ID, ATTRIBUTE1 AS CONFIRM_AREA
        	FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
        	WHERE  A.LOOKUP_TYPE_CODE = 'INSTANCE_ID'
        	AND    A.ACTIVE_FLAG = 'Y'
      ) A
      LEFT OUTER JOIN (
        	SELECT DISTINCT A.INSTANCE_ID, B.COMPANY_ID, B.DIVISION_ID, B.SITE_ID, B.PLANT_ID, A.FACTORY_ID, B.FACTORY_NAME, A.SHOP_GROUP_ID
        	FROM   FP_INSTANCE_FACTORY_M A WITH(NOLOCK), SCM_FACTORY_M B WITH(NOLOCK)
        	WHERE  A.FACTORY_ID = B.FACTORY_ID
        	AND    B.ACTIVE_FLAG = 'Y'
      ) B
      ON  A.INSTANCE_ID = B.INSTANCE_ID
      LEFT OUTER JOIN (
        	SELECT SEGMENT1 AS INSTANCE_ID, SEGMENT2 AS PLAN_GROUP_ID
        	FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
        	WHERE  A.LOOKUP_TYPE_CODE = 'INSTANCE_PLANNING_GROUP'
        	AND    A.ACTIVE_FLAG = 'Y'
      ) C
      ON    A.INSTANCE_ID = C.INSTANCE_ID
      WHERE 1=1
      AND   B.COMPANY_ID IS NOT NULL
      ORDER BY SITE_ID, INSTANCE_ID, FACTORY_ID, PLAN_GROUP_ID