BEGIN
		        BEGIN TRAN
				

MERGE INTO fp_line_setup_group_m A
using 
(
	SELECT 
	@INSTANCE_ID AS INSTANCE_ID,
  	@OPERATION_ID AS OPERATION_ID,
	@ORG_LINE_SETUP_GROUP_ID AS LINE_SETUP_GROUP_ID
) B
ON 1=1
AND A.INSTANCE_ID = B.INSTANCE_ID
AND A.OPERATION_ID = B.OPERATION_ID
AND A.LINE_SETUP_GROUP_ID = B.LINE_SETUP_GROUP_ID
WHEN MATCHED THEN
UPDATE SET ACTIVE_FLAG = ISNULL(@ACTIVE_FLAG,'Y')
        ,LINE_SETUP_GROUP_ID = @LINE_SETUP_GROUP_ID
		,DESCRIPTION = @DESCRIPTION
		,UPDATE_ID = @USER_ID
		,UPDATE_TIME =GETDATE()
WHEN NOT MATCHED THEN
INSERT (
 INSTANCE_ID
   , OPERATION_ID,        LINE_SETUP_GROUP_ID 
, DESCRIPTION, ACTIVE_FLAG, INSERT_ID,           INSERT_TIME        
, UPDATE_ID,   UPDATE_TIME                             
) VALUES (
@instance_id
,@operation_ID
,@LINE_SETUP_GROUP_ID
,@DESCRIPTION,ISNULL(@ACTIVE_FLAG,'Y')
,@USER_ID
,GetDATE()
,@USER_ID
,GetDate()
);

INSERT INTO his_fp_line_setup_group_m
(
 INSTANCE_ID
   , OPERATION_ID,        LINE_SETUP_GROUP_ID 
, DESCRIPTION,ACTIVE_FLAG, INSERT_ID,           INSERT_TIME        
, UPDATE_ID,   UPDATE_TIME    
)
VALUES
(
@instance_id
,@operation_ID
,@LINE_SETUP_GROUP_ID
,@DESCRIPTION,ISNULL(@ACTIVE_FLAG,'Y')
,@USER_ID
,GetDATE()
,@USER_ID
,GetDate()
)		        

IF ISNULL(@LINE_SETUP_GROUP_ID,'')  <> ISNULL(@ORG_LINE_SETUP_GROUP_ID,'') 
BEGIN
  UPdate FP_SETUP_MATRIX_M SET
  LINE_SETUP_GROUP_ID = @LINE_SETUP_GROUP_ID,
  UPDATE_ID = @USER_ID,
  UPDATE_TIME = GetDate()
  WHERE 1=1
  AND INSTANCE_ID = @INSTANCE_ID
  AND OPERATION_ID = @OPERATION_ID
  AND LINE_SETUP_GROUP_ID = @ORG_LINE_SETUP_GROUP_ID
  
  INSERT INTO his_fp_setup_matrix_m
(
 INSTANCE_ID,  OPERATION_ID,LINE_SETUP_GROUP_ID,
 SETUP_CATEGORY_ID, SETUP_KEY_ID,
 FROM_ITEM_SETUP_GROUP_ID,TO_ITEM_SETUP_GROUP_ID,
 SETUP_TIME,SETUP_TIME_UOM,
 DESCRIPTION,
 INSERT_ID, INSERT_TIME, UPDATE_ID,   UPDATE_TIME,
 JOB_USER_ID, JOB_TIME,JOB_TYPE--, JOB_SEQ
) VALUES
(
 @INSTANCE_ID,  @OPERATION_ID,@LINE_SETUP_GROUP_ID,
@ORG_LINE_SETUP_GROUP_ID, '-',
 '-','-',
 0,'-',
'-',
 @USER_ID,GetDATE(),@USER_ID,GetDate(),
 @USER_ID, GetDate(),'U'--,0
)
  
END


		        COMMIT;		       
		      END;