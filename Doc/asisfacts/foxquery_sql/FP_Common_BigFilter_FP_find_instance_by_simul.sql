SELECT A.SEGMENT1 AS SITE_ID
            , A.SEGMENT2 AS INSTANCE_ID
            , A.SEGMENT3 AS INSTANCE_NAME
            , A.SEGMENT4 AS PLAN_GROUP
            , A.SEGMENT5 AS PLAN_GROUP_NAME
            , A.ATTRIBUTE1 AS PACK_INSTANCE_ID
            , A.ATTRIBUTE2 AS DIVISION
            , A.ATTRIBUTE3 AS CELL_INSTANCE_ID
            , B.INSTANCE_NAME AS PACK_INSTANCE_NAME
            , C.INSTANCE_NAME AS CELL_INSTANCE_NAME
      FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
      LEFT OUTER JOIN (
          SELECT A.SEGMENT1 AS INSTANCE_ID, A.SEGMENT2 AS INSTANCE_NAME
          FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
          WHERE  A.LOOKUP_TYPE_CODE = 'INSTANCE_ID'
          AND    A.ACTIVE_FLAG = 'Y'
      ) B
      ON A.ATTRIBUTE1 = B.INSTANCE_ID
      LEFT OUTER JOIN (
          SELECT A.SEGMENT1 AS INSTANCE_ID, A.SEGMENT2 AS INSTANCE_NAME
          FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
          WHERE  A.LOOKUP_TYPE_CODE = 'INSTANCE_ID'
          AND    A.ACTIVE_FLAG = 'Y'
      ) C
      ON A.ATTRIBUTE3 = C.INSTANCE_ID
      WHERE  A.LOOKUP_TYPE_CODE = 'FORMATION_ID_MAPPING'
      AND    A.ACTIVE_FLAG      = 'Y'
      --AND    A.SEGMENT1         = @SITE_ID
      ORDER BY A.SORT_ORDER