SELECT A.*
	 , B.NICK_NAME, B.ITEM_UOM
	 , C.OPERATION_NAME
	 , (CASE WHEN A.AVAILABLE_DATE = '1999-01-01' THEN NULL ELSE A.AVAILABLE_DATE END) AS AVAILABLE_DATE_CPY
	 , A.QMS_HOLD_YN AS QMS_HOLD_YN_CPY
	 , A.WIPHOLD_YN AS WIPHOLD_YN_CPY
	 , A.LONG_TERM_FLAG AS LONG_TERM_FLAG_CPY
	 , A.OPERATION_ID AS OPERATION_ID_CPY
	 , (CASE WHEN A.STOCK_TYPE = 'INVENTORY' THEN 'DW(oWMS)' WHEN A.STOCK_TYPE = 'WIP' THEN 'GMES' ELSE A.STOCK_TYPE END) AS STOCK_TYPE_CPY
FROM (
	--- Good
	SELECT A.*
		 , ROUND((CASE WHEN A.OPERATION_ID NOT IN ('E4100','A5000') THEN A.QTY ELSE 0 END),0) AS GOOD_ELEC_QTY 
		 , ROUND((CASE WHEN A.OPERATION_ID = 'E4100' THEN A.QTY ELSE 0 END),0) AS GOOD_RW_QTY
		 , ROUND((CASE WHEN A.OPERATION_ID = 'A5000' THEN A.QTY ELSE 0 END),0) AS GOOD_ASSY_QTY
		 , 0 AS QMS_ELEC_QTY, 0 AS QMS_RW_QTY, 0 AS QMS_ASSY_QTY
		 , 0 AS GMES_ELEC_QTY, 0 AS GMES_RW_QTY, 0 AS GMES_ASSY_QTY
	FROM   #FP_STOCH_H A WITH(NOLOCK)
	, SCM_ITEM_CLASS_M C WITH(NOLOCK)
	, SCM_ITEM_M B WITH(NOLOCK)
	WHERE 1=1
	AND   A.CUTOFF_DATE = @PLAN_DATE
	AND   A.STOCK_TYPE  = 'WIP'
	AND   A.COMPANY_ID  = B.COMPANY_ID
	AND   A.DIVISION_ID = B.DIVISION_ID
	AND   A.SITE_ID     = B.SITE_ID
	AND   A.ITEM_ID     = B.ITEM_ID
	AND   B.ITEM_CLASS  = C.CLASS_ID
	AND   C.LEVEL_2_CODE = 'APC'
	AND   C.LEVEL_3_NAME != 'APCSR'
	AND   A.WIPHOLD_YN = 'N'
	--- QMS Hold
	UNION ALL
	SELECT A.*
		 , 0 AS GOOD_ELEC_QTY , 0 AS GOOD_RW_QTY, 0 AS GOOD_ASSY_QTY
		 , ROUND((CASE WHEN A.OPERATION_ID NOT IN ('E4100','A5000') THEN A.QTY ELSE 0 END),0) AS QMS_ELEC_QTY
		 , ROUND((CASE WHEN A.OPERATION_ID = 'E4100' THEN A.QTY ELSE 0 END),0) AS QMS_RW_QTY
		 , ROUND((CASE WHEN A.OPERATION_ID = 'A5000' THEN A.QTY ELSE 0 END),0) AS QMS_ASSY_QTY
		 , 0 AS GMES_ELEC_QTY, 0 AS GMES_RW_QTY, 0 AS GMES_ASSY_QTY
	FROM 	#FP_STOCH_H A WITH(NOLOCK)
	, SCM_ITEM_M B WITH(NOLOCK)
	, SCM_ITEM_CLASS_M C WITH(NOLOCK)
	WHERE 	1=1
	AND    A.CUTOFF_DATE = @PLAN_DATE
	AND 	A.STOCK_TYPE = 'WIP'
	AND 	A.COMPANY_ID = B.COMPANY_ID
	AND 	A.DIVISION_ID = B.DIVISION_ID
	AND 	A.SITE_ID = B.SITE_ID
	AND 	A.ITEM_ID = B.ITEM_ID
	AND 	B.ITEM_CLASS = C.CLASS_ID
	AND 	C.LEVEL_2_CODE = 'APC'
	AND 	C.LEVEL_3_NAME != 'APCSR'
	AND 	A.WIPHOLD_YN = 'Y'
	AND 	A.QMS_HOLD_YN = 'Y'
	--- GMES
	UNION ALL
	SELECT A.*
		 , 0 AS GOOD_ELEC_QTY , 0 AS GOOD_RW_QTY, 0 AS GOOD_ASSY_QTY
		 , 0 AS QMS_ELEC_QTY, 0 AS QMS_RW_QTY, 0 AS QMS_ASSY_QTY
		 , ROUND((CASE WHEN A.OPERATION_ID NOT IN ('E4100','A5000') THEN A.QTY ELSE 0 END),0) AS GMES_ELEC_QTY
		 , ROUND((CASE WHEN A.OPERATION_ID = 'E4100' THEN A.QTY ELSE 0 END),0) AS GMES_RW_QTY
		 , ROUND((CASE WHEN A.OPERATION_ID = 'A5000' THEN A.QTY ELSE 0 END),0) AS GMES_ASSY_QTY
	FROM 	#FP_STOCH_H A WITH(NOLOCK)
	, SCM_ITEM_M B WITH(NOLOCK)
	, SCM_ITEM_CLASS_M C WITH(NOLOCK)
	WHERE  1=1
	AND    A.CUTOFF_DATE = @PLAN_DATE
	AND    EXISTS (
		SELECT 1
		FROM   #COATER_SITE WW WITH(NOLOCK)
		WHERE  A.DIVISION_ID = WW.DIVISION_ID
		AND    A.SITE_ID     = WW.SITE_ID
	)
	AND 	A.STOCK_TYPE = 'WIP'
	AND 	A.COMPANY_ID = B.COMPANY_ID
	AND 	A.DIVISION_ID = B.DIVISION_ID
	AND 	A.SITE_ID = B.SITE_ID
	AND 	A.ITEM_ID = B.ITEM_ID
	AND 	B.ITEM_CLASS = C.CLASS_ID
	AND 	C.LEVEL_2_CODE = 'APC'
	AND 	C.LEVEL_3_NAME != 'APCSR'
	AND 	A.WIPHOLD_YN = 'Y'
	AND 	A.QMS_HOLD_YN != 'Y'
	AND 	A.MES_HOLD_YN = 'Y'
) A
INNER JOIN SCM_ITEM_M B WITH(NOLOCK)
ON  1=1
AND A.COMPANY_ID  = B.COMPANY_ID
AND A.DIVISION_ID = B.DIVISION_ID
AND A.SITE_ID     = B.SITE_ID
AND A.ITEM_ID     = B.ITEM_ID
LEFT OUTER JOIN ( 
	SELECT DISTINCT A.SEGMENT1 AS OPERATION_ID, A.ATTRIBUTE1 AS OPERATION_NAME
	FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
	WHERE  1=1 
	AND    A.LOOKUP_TYPE_CODE = 'FP_OPERATION'
) C 
ON  1=1 
AND A.OPERATION_ID = C.OPERATION_ID
WHERE 1=1
AND   A.DIVISION_ID = @DIVISION_ID
AND   A.SITE_ID = @SITE_ID
AND   A.ITEM_ID = @ITEM_ID
@CTRL_QTY_CONDITION_LT
@CTRL_VERSION_LT
ORDER BY A.STOCK_TYPE, A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.FP_APPLY_OPERATION_ID, A.LINE_ID, A.STORAGE_ID, A.CUTOFF_DATE 
	   , A.FP_APPLY_ITEM_ID, A.LANE