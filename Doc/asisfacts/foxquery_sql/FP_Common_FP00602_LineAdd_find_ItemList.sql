WITH INST_OP AS (
        	SELECT DISTINCT B.COMPANY_ID, B.DIVISION_ID, B.SITE_ID, B.OPERATION_ID
        	FROM   FP_INSTANCE_OPERATION_V A WITH(NOLOCK), SCM_OPERATION_M B WITH(NOLOCK)
        	WHERE  A.COMPANY_ID   = B.COMPANY_ID
        	AND    A.DIVISION_ID  = B.DIVISION_ID
        	AND    A.SITE_ID      = B.SITE_ID
        	AND    A.OPERATION_ID = B.OPERATION_ID
        	AND    A.INSTANCE_ID  = @INSTANCE_ID
        	AND    A.AMEND_FLAG   = 'Y'
        	AND    B.ACTIVE_FLAG  = 'Y'
      )
      , CTE_NODE(COMPANY_ID,DIVISION_ID,SITE_ID,PLANT_ID,PARENT_ITEM_ID,CHILD_ITEM_ID,KEY_DATE,EFF_START_DATE,EFF_END_DATE,PARENT_QTY,PARENT_UOM,CHILD_QTY,CHILD_UOM
      	,PARENT_ITEM_TYPE,PARENT_ITEM_CLASS,PARENT_NICK_NAME,PARENT_LEVEL_2_CODE,PARENT_LEVEL_3_NAME,PARENT_LEVEL_4_NAME
      	,CHILD_ITEM_TYPE,CHILD_ITEM_CLASS,CHILD_NICK_NAME,CHILD_LEVEL_2_CODE,CHILD_LEVEL_3_NAME,CHILD_LEVEL_4_NAME
      	,NLEVEL,NPATH,ROOT, FLOW_ID)
      AS (
        	SELECT A.COMPANY_ID,A.DIVISION_ID,A.SITE_ID,A.PLANT_ID,A.PARENT_ITEM_ID,A.CHILD_ITEM_ID,A.KEY_DATE,A.EFF_START_DATE,A.EFF_END_DATE,A.PARENT_QTY,A.PARENT_UOM,A.CHILD_QTY,A.CHILD_UOM
        		 , PD1.ITEM_TYPE AS PARENT_ITEM_TYPE
        		 , PD1.ITEM_CLASS AS PARENT_ITEM_CLASS
        		 , PD1.NICK_NAME AS PARENT_NICK_NAME
        		 , PDC1.LEVEL_2_CODE AS PARENT_LEVEL_2_CODE
        		 , PDC1.LEVEL_3_NAME AS PARENT_LEVEL_3_NAME
        		 , PDC1.LEVEL_4_NAME AS PARENT_LEVEL_4_NAME
        		 , PD2.ITEM_TYPE AS CHILD_ITEM_TYPE
        		 , PD2.ITEM_CLASS AS CHILD_ITEM_CLASS
        		 , PD2.NICK_NAME AS CHILD_NICK_NAME
        		 , PDC2.LEVEL_2_CODE AS CHILD_LEVEL_2_CODE
        		 , PDC2.LEVEL_3_NAME AS CHILD_LEVEL_3_NAME
        		 , PDC2.LEVEL_4_NAME AS CHILD_LEVEL_4_NAME
        		 , 1 AS NLEVEL,CONVERT(VARCHAR(100),PARENT_ITEM_ID+'/'+CHILD_ITEM_ID) AS NPATH,PARENT_ITEM_ID AS ROOT 
        		 , PD1.FLOW_ID
        	FROM SCM_BOM_M A WITH(NOLOCK)
        	INNER JOIN SCM_ITEM_M PD1 WITH(NOLOCK)
        	ON  A.COMPANY_ID     = PD1.COMPANY_ID
        	AND A.DIVISION_ID    = PD1.DIVISION_ID
        	AND A.SITE_ID        = PD1.SITE_ID
        	AND A.PARENT_ITEM_ID = PD1.ITEM_ID
        	INNER JOIN SCM_ITEM_CLASS_M PDC1 WITH(NOLOCK)
        	ON PD1.ITEM_CLASS = PDC1.CLASS_ID
        	INNER JOIN SCM_ITEM_M PD2 WITH(NOLOCK)
        	ON  A.COMPANY_ID    = PD2.COMPANY_ID
        	AND A.DIVISION_ID   = PD2.DIVISION_ID
        	AND A.SITE_ID       = PD2.SITE_ID
        	AND A.CHILD_ITEM_ID = PD2.ITEM_ID
        	INNER JOIN SCM_ITEM_CLASS_M PDC2 WITH(NOLOCK)
        	ON PD2.ITEM_CLASS=PDC2.CLASS_ID
          , INST_OP D
        	WHERE 1=1
        	AND   A.COMPANY_ID  = D.COMPANY_ID
        	AND   A.DIVISION_ID = D.DIVISION_ID
        	AND   A.SITE_ID     = D.SITE_ID
        	AND   PD1.FLOW_ID LIKE '%' + D.OPERATION_ID + '%'
        	AND   A.EFF_START_DATE <= @DATE
        	AND   A.EFF_END_DATE   >  @DATE
        	AND   A.ACTIVE_FLAG    = 'Y'
        	AND   PD1.ACTIVE_FLAG  = 'Y'
        	AND   PDC1.USE_FLAG    = 'Y'
        	AND   PD2.ACTIVE_FLAG  = 'Y'
        	AND   PDC2.USE_FLAG    = 'Y'
        	UNION ALL
        	SELECT A.COMPANY_ID,A.DIVISION_ID,A.SITE_ID,A.PLANT_ID,A.PARENT_ITEM_ID,A.CHILD_ITEM_ID,A.KEY_DATE,A.EFF_START_DATE,A.EFF_END_DATE,A.PARENT_QTY,A.PARENT_UOM,A.CHILD_QTY,A.CHILD_UOM
        		 , PD1.ITEM_TYPE AS PARENT_ITEM_TYPE
        		 , PD1.ITEM_CLASS AS PARENT_ITEM_CLASS
        		 , PD1.NICK_NAME AS PARENT_NICK_NAME
        		 , PDC1.LEVEL_2_CODE AS PARENT_LEVEL_2_CODE
        		 , PDC1.LEVEL_3_NAME AS PARENT_LEVEL_3_NAME
        		 , PDC1.LEVEL_4_NAME AS PARENT_LEVEL_4_NAME
        		 , PD2.ITEM_TYPE AS CHILD_ITEM_TYPE
        		 , PD2.ITEM_CLASS AS CHILD_ITEM_CLASS
        		 , PD2.NICK_NAME AS CHILD_NICK_NAME
        		 , PDC2.LEVEL_2_CODE AS CHILD_LEVEL_2_CODE
        		 , PDC2.LEVEL_3_NAME AS CHILD_LEVEL_3_NAME
        		 , PDC2.LEVEL_4_NAME AS CHILD_LEVEL_4_NAME
        		 , NLEVEL+1 AS NLEVEL ,CONVERT(VARCHAR(100),NPATH+'/'+A.CHILD_ITEM_ID) AS NPATH,ROOT
        		 , PD1.FLOW_ID
        	FROM SCM_BOM_M A WITH(NOLOCK)
        	INNER JOIN CTE_NODE B
        	ON  A.PARENT_ITEM_ID = B.CHILD_ITEM_ID
        	AND A.COMPANY_ID     = B.COMPANY_ID
        	AND A.DIVISION_ID    = B.DIVISION_ID
        	AND A.SITE_ID        = B.SITE_ID
        	INNER JOIN SCM_ITEM_M PD1 WITH(NOLOCK)
        	ON  A.COMPANY_ID     = PD1.COMPANY_ID
        	AND A.DIVISION_ID    = PD1.DIVISION_ID
        	AND A.SITE_ID        = PD1.SITE_ID
        	AND A.PARENT_ITEM_ID = PD1.ITEM_ID
        	INNER JOIN SCM_ITEM_CLASS_M PDC1 WITH(NOLOCK)
        	ON  PD1.ITEM_CLASS = PDC1.CLASS_ID
        	INNER JOIN SCM_ITEM_M PD2 WITH(NOLOCK)
        	ON  A.COMPANY_ID    = PD2.COMPANY_ID
        	AND A.DIVISION_ID   = PD2.DIVISION_ID
        	AND A.SITE_ID       = PD2.SITE_ID
        	AND A.CHILD_ITEM_ID = PD2.ITEM_ID
        	INNER JOIN SCM_ITEM_CLASS_M PDC2 WITH(NOLOCK)
        	ON  PD2.ITEM_CLASS=PDC2.CLASS_ID
          , INST_OP D
        	WHERE 1=1
        	AND   A.COMPANY_ID  = D.COMPANY_ID
        	AND   A.DIVISION_ID = D.DIVISION_ID
        	AND   A.SITE_ID     = D.SITE_ID
        	AND   PD1.FLOW_ID LIKE '%' + D.OPERATION_ID + '%'
        	AND   A.EFF_START_DATE <= @DATE -- 입력일자 기준으로 ECO 일자 지정
        	AND   A.EFF_END_DATE   >  @DATE
        	AND   PD1.ACTIVE_FLAG  = 'Y'
        	AND   PDC1.USE_FLAG    = 'Y'
        	AND   PD2.ACTIVE_FLAG  = 'Y'
        	AND   PDC2.USE_FLAG    = 'Y'
      )
      SELECT DISTINCT A.*
      FROM (
          SELECT DISTINCT A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.ROOT AS MODEL_ID, A.PARENT_ITEM_ID AS ITEM_ID
          	 , A.PARENT_NICK_NAME AS NICK_NAME
          	 , (CASE WHEN LEFT(A.FLOW_ID,5) = 'A9000' AND  ISNULL(A.PARENT_LEVEL_4_NAME, '-') = '-' THEN A.PARENT_LEVEL_3_NAME
          			 WHEN LEFT(A.FLOW_ID,5) = 'A9000' THEN ISNULL(A.PARENT_LEVEL_4_NAME, '-')
          			 ELSE A.PARENT_LEVEL_3_NAME END) AS ITEM_TYPE
          FROM   CTE_NODE A WITH(NOLOCK), SCM_ITEM_M B WITH(NOLOCK)
          WHERE  1=1
          AND    A.COMPANY_ID  = B.COMPANY_ID
          AND    A.DIVISION_ID = B.DIVISION_ID
          AND    A.SITE_ID     = B.SITE_ID
          AND    A.ROOT        = B.ITEM_ID
          --AND    B.ITEM_TYPE   = 'P'
          AND    RIGHT(B.FLOW_ID,5) IN ('A3000','A9000')
          AND    EXISTS ( SELECT 1
                  				FROM   FP_USER_ROLE_INFO_V B WITH(NOLOCK)
                  				WHERE  A.COMPANY_ID  = B.COMPANY_ID
                  				AND    A.DIVISION_ID = B.DIVISION_ID
                  				AND    A.SITE_ID     = B.SITE_ID
                  				AND    B.USER_ID     = @USER_ID
                  				AND	   B.SAVE_FLAG	 = 'Y' )
          AND     
		 
              (ISNULL(@MODEL_ID,'')='' AND A.ROOT LIKE @MODEL_ID)
              (ISNULL(@ITEM_ID,'')='' AND A.PARENT_ITEM_ID LIKE @ITEM_ID)
              (ISNULL(@ITEM_ID,'')='' AND A.PARENT_NICK_NAME LIKE @ITEM_ID)
          --[AND    A.ROOT LIKE '%' +  @MODEL_ID + '%']
          --[AND    A.PARENT_ITEM_ID LIKE '%' + @ITEM_ID + '%']
          --[AND    A.PARENT_NICK_NAME LIKE '%' + @NICK_NAME + '%']
      ) A
      ORDER BY DIVISION_ID, SITE_ID, PLANT_ID, MODEL_ID, ITEM_ID, NICK_NAME, ITEM_TYPE