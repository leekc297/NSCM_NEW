SELECT A.PLAN_ID AS CODE, A.PLAN_ID AS NAME
               , A.INSTANCE_ID, A.PLAN_ID, A.PLAN_TYPE, A.SITE_ID
          	   , CONVERT(VARCHAR(8), A.PLAN_START_TIME, 112) AS PLAN_START_TIME
          	   , A.PLAN_HORIZON, A.DEMAND_HORIZON, A.CONFIG_SET_ID, A.BASIS_PLAN_ID  
          	   , A.DESCRIPTION, A.CONFIRM_ID, A.INSERT_ID
          	   , CONVERT(VARCHAR, A.CONFIRM_TIME, 120) AS CONFIRM_TIME
          	   , CONVERT(VARCHAR, A.INSERT_TIME , 120) AS INSERT_TIME
          	   , CONVERT(VARCHAR,A.PRE_FIX_DATE,112) AS PRE_FIX_DATE
          FROM   SCM_FP_PLAN_H A WITH(NOLOCK)
          WHERE  A.INTG_PLAN_ID = @INTG_PLAN_ID
          AND    CONVERT(VARCHAR(8), A.PLAN_START_TIME, 112) = @PLAN_DATE
          AND    PLAN_TYPE <> 'RELEASE'
          AND    RIGHT(A.PLAN_ID,2) <> '00'
          ORDER BY CODE DESC