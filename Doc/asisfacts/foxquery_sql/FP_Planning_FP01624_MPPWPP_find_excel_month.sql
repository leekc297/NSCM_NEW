SELECT A.YYYYMM AS CODE, SUBSTRING(A.YYYYMM,1,4) + '-' + SUBSTRING(A.YYYYMM,5,2) AS NAME
            ,MIN(YYYYMMDD) AS START_DATE
            --,(CASE WHEN TODAY > MIN(YYYYMMDD) THEN TODAY ELSE MIN(YYYYMMDD) END) AS START_DATE
            ,MAX(YYYYMMDD) AS END_DATE
            ,MIN(YYYYMMDD) AS MIN_DATE
      FROM   TH_UIS_CAL A WITH(NOLOCK)
      WHERE  YYYYMMDD BETWEEN (SUBSTRING(@TODAY,1,6)+'01')
      AND    (SELECT MAX(YYYYMMDD) FROM TH_UIS_CAL B WITH(NOLOCK) WHERE YYYYMM = SUBSTRING(CONVERT(VARCHAR,DATEADD(MM,1,CONVERT(DATETIME,SUBSTRING(CONVERT(VARCHAR,GETDATE(),112),1,6)+'01')),112),1,6))
      --/*
      --WHERE  YYYYMMDD BETWEEN (SUBSTRING(CONVERT(VARCHAR,GETDATE(),112),1,6)+'01')
      --                AND     (SELECT MAX(YYYYMMDD) FROM TH_UIS_CAL B WITH(NOLOCK) WHERE YYYYMM = SUBSTRING(CONVERT(VARCHAR,DATEADD(MM,1,CONVERT(DATETIME,SUBSTRING(CONVERT(VARCHAR,GETDATE(),112),1,6)+'01')),112),1,6))
      --*/
      GROUP BY A.YYYYMM
      ORDER BY A.YYYYMM