INSERT into BUF_WEEKLY_DEMAND_SHIPMENT_H (
			         COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, SHOP_GROUP_ID
			        ,SCP_PLAN_ID, SCP_TARGET_ID, FP_TARGET_ID
			        ,ITEM_ID, TO_SITE_ID, TO_PLANT_ID, CUSTOMER_ID
			        ,SHIP_DATE, SHIP_WEEK, SHIP_QTY
			        ,PRODUCTION_TYPE, TRANSPORT_MODE, BIZ_TYPE, CONFIRM_TYPE
			        ,JOB_USER_ID, JOB_TIME, JOB_TYPE, JOB_ORDER
			      )
			      VALUES (
					         UPPER(RTRIM(LTRIM(@COMPANY_ID))), UPPER(RTRIM(LTRIM(@DIVISION_ID))), UPPER(RTRIM(LTRIM(@SITE_ID))), UPPER(RTRIM(LTRIM(@PLANT_ID))), UPPER(RTRIM(LTRIM(@SHOP_GROUP_ID)))
					        ,UPPER(RTRIM(LTRIM(@SCP_PLAN_ID))), UPPER(RTRIM(LTRIM(@SCP_TARGET_ID))), UPPER(RTRIM(LTRIM(@FP_TARGET_ID)))
					        ,UPPER(RTRIM(LTRIM(@ITEM_ID))), UPPER(RTRIM(LTRIM(@TO_SITE_ID))), UPPER(RTRIM(LTRIM(@TO_PLANT_ID))), @CUSTOMER_ID
					        ,CONVERT(DATETIME, @SHIP_DATE), @SHIP_WEEK, @SHIP_QTY
					        ,UPPER(RTRIM(LTRIM(@PRODUCTION_TYPE))), UPPER(RTRIM(LTRIM(@TRANSPORT_MODE))), UPPER(RTRIM(LTRIM(@BIZ_TYPE))), UPPER(RTRIM(LTRIM(@CONFIRM_TYPE)))
					        ,@USER_ID, dbo.SYSDATE1(), '-', @JOB_ORDER
			      		)