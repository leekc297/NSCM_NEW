SELECT A.SEGMENT1 AS CODE, A.SEGMENT2 AS NAME
               , A.ATTRIBUTE1 AS CONFIRM_AREA, A.ATTRIBUTE2 AS IS_SAME_PLAN_ID
               , A.ATTRIBUTE3 AS USE_WOW_STATUS
               , ISNULL(C.AMEND_TYPE,'AMEND UI' ) AS AMEND_TYPE
               , A.ATTRIBUTE10 AS FIX_DATE_SYNC, A.ATTRIBUTE12 AS SYNC_YN
          	   , A.SEGMENT1 AS INSTANCE_ID
          FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
          LEFT OUTER JOIN (
               SELECT A.SEGMENT1 AS INSTANCE_ID, ATTRIBUTE1 AS AMEND_TYPE
               FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
               WHERE  A.LOOKUP_TYPE_CODE = 'INSTANCE AMEND UI'
          ) C
          ON     A.SEGMENT1         = C.INSTANCE_ID
          WHERE  A.LOOKUP_TYPE_CODE = 'INSTANCE_ID'
          AND    A.ACTIVE_FLAG      = 'Y'
          AND   ( A.SEGMENT1 LIKE '%CELL%' OR A.SEGMENT1 LIKE '%PACK%' OR A.SEGMENT1 LIKE '%FORM%' OR A.SEGMENT1 LIKE '%PMIX%' OR A.SEGMENT1 LIKE '%PRE%' OR  A.SEGMENT1 LIKE 'PL_E_%')
          AND    A.SEGMENT1 NOT IN ( 'CN_FORM_T' )
          AND    EXISTS (
          	SELECT 1
          	FROM   FP_USER_ROLE_INFO_V B WITH(NOLOCK)
          	WHERE  A.SEGMENT1 = B.INSTANCE_ID
          	AND    B.SITE_ID  = @SITE_ID
          	AND    B.USER_ID  = @USER_ID
          )
          AND   A.SEGMENT1 IN (
          	SELECT A.SEGMENT2
          	FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
          	WHERE  A.LOOKUP_TYPE_CODE = 'TOTAL_INSTANCE_INFO'
          	AND    A.ACTIVE_FLAG	    = 'Y'
          	AND    A.SEGMENT1         = @INTG_PLAN_ID
          )
          GROUP BY A.SEGMENT1, A.SEGMENT2, A.ATTRIBUTE1, A.ATTRIBUTE2
                 , A.ATTRIBUTE3, ISNULL(C.AMEND_TYPE,'AMEND UI')
                 , A.ATTRIBUTE10, A.ATTRIBUTE12
                 , A.ATTRIBUTE10, A.ATTRIBUTE12  ,A.SORT_ORDER
          ORDER BY A.SORT_ORDER