SELECT B.TARGET_WEEK
	 , A.DATED1 AS START_DATE
	 , CONVERT(VARCHAR, CONVERT(DATETIME,DATED7)+(7*(C.PLAN_WEEK)), 112) AS END_DATE
	 , (7*(C.PLAN_WEEK+1)) AS WEEK_RANGE
	 , 2 AS _RNK 
FROM   TH_UIS_CALENDAR A WITH(NOLOCK)
, (
		SELECT ISO_YYYYWW AS TARGET_WEEK
		FROM   TH_UIS_CAL A WITH(NOLOCK)
		, (
				SELECT SUBSTRING(A.SCP_PLAN_ID,1,8) AS TARGET_DATE
				FROM 	(
						SELECT MAX(A.SCP_PLAN_ID) AS SCP_PLAN_ID
						FROM   FP_WEEKLY_DEMAND_PRODUCT_H A WITH(NOLOCK)
						WHERE  1=1
						AND    (A.DIVISION_ID+A.SHOP_GROUP_ID+A.SITE_ID) IN (
																			SELECT DISTINCT A.DIVISION_ID+B.SHOP_GROUP_ID+A.SITE_ID AS CODE
																			FROM  SCM_FACTORY_M A WITH(NOLOCK)
																			INNER JOIN FP_INSTANCE_FACTORY_M B WITH(NOLOCK)
																			ON    A.FACTORY_ID=B.FACTORY_ID
																			AND   B.ACTIVE_FLAG = 'Y'
																			WHERE 1=1
																			AND   A.ACTIVE_FLAG = 'Y'
																			AND B.INSTANCE_ID = @INSTANCE_ID
																		)
				) A
		) B
		WHERE A.YYYYMMDD = B.TARGET_DATE
) B
, (
		--SELECT CONVERT(NUMERIC, ISNULL(AA.ATTRIBUTE15,8)) AS PLAN_WEEK
		SELECT (CASE WHEN CONVERT(NUMERIC, ISNULL(AA.ATTRIBUTE15,12)) > 12 THEN 8 ELSE CONVERT(NUMERIC, ISNULL(AA.ATTRIBUTE15,8)) END ) AS PLAN_WEEK -- control over week... 20241106
		FROM   SCM_SYS_LOOKUP_VALUE AA WITH(NOLOCK)
		WHERE  AA.LOOKUP_TYPE_CODE = 'INSTANCE_ID'
		AND    AA.ACTIVE_FLAG = 'Y'
		AND AA.SEGMENT1 = @INSTANCE_ID
) C
WHERE A.D0 = B.TARGET_WEEK
UNION ALL
SELECT B.TARGET_WEEK 
	 , A.DATED1 AS START_DATE
	 , CONVERT(VARCHAR, CONVERT(DATETIME,DATED7)+(7*(C.PLAN_WEEK)), 112) AS END_DATE 
	 , (7*(C.PLAN_WEEK+1)) AS WEEK_RANGE 
	 , 1 AS _RNK 
FROM   TH_UIS_CALENDAR A WITH(NOLOCK) 
, ( 
	SELECT ISO_YYYYWW AS TARGET_WEEK 
	FROM   TH_UIS_CAL A WITH(NOLOCK) 
	WHERE  A.YYYYMMDD =  CONVERT(VARCHAR, (DBO.FN_SITE_TIME( (SELECT MAX(SITE_ID) FROM FP_INSTANCE_INFO_V A WITH(NOLOCK) 
															  WHERE 1=1 
															  AND A.INSTANCE_ID = @INSTANCE_ID
															  ) )), 112) 
) B 
, (
	--SELECT CONVERT(NUMERIC, ISNULL(AA.ATTRIBUTE15,8)) AS PLAN_WEEK 
	SELECT (CASE WHEN CONVERT(NUMERIC, ISNULL(AA.ATTRIBUTE15,12)) > 12 THEN 8 ELSE CONVERT(NUMERIC, ISNULL(AA.ATTRIBUTE15,8)) END )-1 AS PLAN_WEEK -- control over week... 20241106
	FROM   SCM_SYS_LOOKUP_VALUE AA WITH(NOLOCK) 
	WHERE  AA.LOOKUP_TYPE_CODE = 'INSTANCE_ID' 
	AND    AA.ACTIVE_FLAG = 'Y' 
	AND    AA.SEGMENT1 = @INSTANCE_ID
) C 
WHERE A.D0 = B.TARGET_WEEK 
ORDER BY _RNK