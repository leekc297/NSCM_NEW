SELECT ROW_NUMBER() OVER ( ORDER BY SEQ, JOB_ID ) AS NUM,
                 GROUP_ID, DIVISION_ID, JOB_ID, JOB_DESC, JOB_TYPE, NO, NO AS ORG_NO, SEQ, JOB_ID AS ORG_JOB_ID,
                 VALID, STATUS, ERROR_MSG, @GROUP_NAME AS GROUP_NAME,
                 CONVERT(VARCHAR, START_DATE, 120) AS START_DATE,
                 CONVERT(VARCHAR, END_DATE, 120) AS END_DATE,
                 PARAMETER1, PARAMETER2, PARAMETER3, PARAMETER4, PARAMETER5,
                 CREATE_USER_ID, CONVERT(VARCHAR, CREATE_DATE, 120) CREATE_DATE,
                 MODIFY_USER_ID, CONVERT(VARCHAR, MODIFY_DATE, 120) MODIFY_DATE,
                 (SELECT ERROR_MSG
                 FROM (
                     SELECT ERROR_MSG, ROW_NUMBER() OVER(ORDER BY IF_SEQ DESC) AS RSEQ
                     FROM JOB_SCHEDULE_HISTORY T WITH(NOLOCK)
                     WHERE T.DIVISION_ID = A.DIVISION_ID
                     AND T.JOB_ID = A.JOB_ID
                     AND T.GROUP_ID = A.GROUP_ID
                     AND ERROR_MSG IS NOT NULL
                 ) AS B
                 WHERE B.RSEQ <= 1) AS HIS_ERROR_MSG
          FROM  JOB_SCHEDULE_DETAIL A WITH(NOLOCK)
          
          WHERE GROUP_ID    = @GROUP_ID
          AND   DIVISION_ID = @DIVISION_ID
          AND (VALID = ISNULL(@VALID_YN,'') OR ISNULL(@VALID_YN,'')='ALL' OR ISNULL(@VALID_YN,'')='')
          ORDER BY SEQ, JOB_ID