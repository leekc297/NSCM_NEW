SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, B.PLANT_ID, A.OPERATION_ID
           , B.LINE_SETUP_GROUP_ID, A.SETUP_CATEGORY_ID
           , A.SETUP_CATEGORY_ID AS CODE, A.SETUP_CATEGORY_ID AS NAME
      FROM   SCM_ITEM_SETUP_GROUP_M A WITH(NOLOCK) INNER JOIN SCM_LINE_SETUP_GROUP_M B WITH(NOLOCK)
      ON     A.COMPANY_ID   = B.COMPANY_ID
      AND    A.DIVISION_ID  = B.DIVISION_ID
      AND    A.SITE_ID      = B.SITE_ID
      AND    A.OPERATION_ID = B.OPERATION_ID
      GROUP BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, B.PLANT_ID, A.OPERATION_ID
             , B.LINE_SETUP_GROUP_ID, A.SETUP_CATEGORY_ID