SELECT SITE_ID AS CODE,
        	   '(' + SITE_ID + ')' + CASE WHEN SITE_NAME = '' OR SITE_NAME IS NULL THEN SITE_ID ELSE SITE_NAME END AS NAME		
        FROM   SCM_SITE_M A WITH(NOLOCK)
        WHERE  1 = 1
        AND    A.SITE_ID IN (
        	SELECT DISTINCT A.SEGMENT3 AS SITE_ID
        	FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
        	WHERE  A.LOOKUP_TYPE_CODE = 'TOTAL_INSTANCE_INFO'
        	AND    A.ACTIVE_FLAG	    = 'Y'
        )
        AND    EXISTS (
        	SELECT 1
        	FROM   FP_USER_ROLE_INFO_V B WITH(NOLOCK)
        	WHERE  A.COMPANY_ID  = B.COMPANY_ID
        	AND    A.SITE_ID     = B.SITE_ID
        	AND    B.USER_ID	   = @USER_ID
        )
        GROUP BY SITE_ID, SITE_NAME
        ORDER BY SITE_ID ASC