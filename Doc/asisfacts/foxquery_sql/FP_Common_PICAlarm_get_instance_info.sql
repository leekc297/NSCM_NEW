SELECT DISTINCT A.INSTANCE_ID AS CODE,B.SEGMENT2 AS NAME, A.INSTANCE_TYPE  FROM FP_INSTANCE_FACTORY_M  A WITH(NOLOCK) 
INNER JOIN ( SELECT * FROM SCM_SYS_LOOKUP_VALUE WITH(NOLOCK) WHERE LOOKUP_TYPE_CODE='INSTANCE_ID') B
ON B.SEGMENT1 = A.INSTANCE_ID
AND B.LOOKUP_TYPE_CODE = 'INSTANCE_ID'
WHERE A.INSTANCE_ID = @INSTANCE_ID