SELECT  SUM(CNT) AS CNT
		FROM(
				SELECT  COUNT(1) AS CNT
				FROM   	SCM_ITEM_LINE_ASSIGN_M A WITH(NOLOCK)
				WHERE  	A.DIVISION_ID    = @DIVISION_ID
			    AND    	A.SITE_ID        = @SITE_ID
			    AND    	A.ITEM_ID        = @ITEM_ID
			    AND    	A.LINE_ID 		 = @LINE_ID
			    AND    	A.ACTIVE_FLAG    = 'Y'
			    AND	 	A.PRIORITY IN ('0','9')
      			AND    	A.MONTH          BETWEEN CONVERT(VARCHAR(6),@BUCKET_FROM,112) AND CONVERT(VARCHAR(6),@BUCKET_TO,112)
				UNION ALL
				SELECT  COUNT(1) AS CNT
				FROM   SCM_ITEM_LINE_ASSIGN_EXCEPT_M A WITH(NOLOCK)
				INNER JOIN (
					SELECT DT
					FROM TH_UIS_CAL
					WHERE CONVERT(VARCHAR, DT, 112) BETWEEN  @BUCKET_FROM AND @BUCKET_TO
				) B
				ON 1=1
				WHERE  	A.DIVISION_ID    = @DIVISION_ID
			    AND    	A.SITE_ID        = @SITE_ID
			    AND    	A.ITEM_ID        = @ITEM_ID
			    AND    	A.LINE_ID 		 = @LINE_ID
			    AND    	A.ACTIVE_FLAG    = 'Y'
				AND	  	A.PRIORITY IN ('0','9')
				AND    	B.DT BETWEEN A.START_TIME AND A.END_TIME
			) A