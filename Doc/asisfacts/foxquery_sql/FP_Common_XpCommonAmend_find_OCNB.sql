SELECT SEGMENT1 AS MENU_KEY
               , SEGMENT2 AS INSTANCE_ID
               , SEGMENT3, SEGMENT4, SEGMENT5
          FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
          WHERE  1=1
          AND    A.LOOKUP_TYPE_CODE = @LOOKUP_TYPE_CODE
          AND    A.SEGMENT1 = (CASE WHEN @MENU_KEY != '' AND @MENU_KEY IS NOT NULL THEN @MENU_KEY ELSE A.SEGMENT1 END)
          AND    A.ACTIVE_FLAG = 'Y'