SELECT DISTINCT A.INSTANCE_ID, A.OPERATION_ID, B.OPERATION_NAME, B.OPERATION_GROUP_ID, B.OPERATION_GROUP_NAME
	,a.operation_id as CODE, '(' + a.operation_id + ')' + b.operation_name as NAME  
	FROM FP_INSTANCE_LINE_V A WITH(NOLOCK)
	LEFT OUTER JOIN FP_USER_ROLE_INFO_V C WITH(NOLOCK)
	ON 	A.OPERATION_ID = C.OPERATION_ID
	AND A.DIVISION_ID = C.DIVISION_ID
	AND A.SITE_ID = C.SITE_ID
	AND A.COMPANY_ID = C.COMPANY_ID
	AND C.USER_ID = @USER_ID

	INNER JOIN SCM_OPERATION_M B WITH(NOLOCK)
	ON A.OPERATION_ID = B.OPERATION_ID
	AND A.DIVISION_ID = B.DIVISION_ID
	AND A.SITE_ID = B.SITE_ID
	AND A.COMPANY_ID = B.COMPANY_ID