BEGIN
									MERGE INTO SCM_PACK_WORKER_M AS A
									USING (
													SELECT COMPANY_ID,DIVISION_ID,SITE_ID,PLANT_ID,FACTORY_ID,OPERATION_ID,
																	LINE_ID,ITEM_ID,WORKER_QTY,JOB_USER_ID 
													FROM BUF_PACK_WORKER_M(NOLOCK) 
													WHERE JOB_USER_ID = @USER_ID
												) AS B
												ON A.COMPANY_ID = B.COMPANY_ID 
												AND A.DIVISION_ID = B.DIVISION_ID 
												AND A.SITE_ID = B.SITE_ID 
												AND A.PLANT_ID = B.PLANT_ID 
												AND A.FACTORY_ID = B.FACTORY_ID
												AND A.LINE_ID = B.LINE_ID 
												AND A.OPERATION_ID = B.OPERATION_ID  
												AND A.ITEM_ID = B.ITEM_ID
									WHEN MATCHED AND (A.ITEM_ID = B.ITEM_ID  AND A.LINE_ID = B.LINE_ID) THEN
										UPDATE SET WORKER_QTY = B.WORKER_QTY
													, UPDATE_ID = B.JOB_USER_ID
													, UPDATE_TIME = dbo.SYSDATE1()
									WHEN NOT MATCHED BY TARGET THEN
										INSERT (COMPANY_ID,DIVISION_ID,SITE_ID,PLANT_ID,FACTORY_ID,OPERATION_ID, 
															LINE_ID,ITEM_ID,WORKER_QTY,
															INSERT_ID,INSERT_TIME,UPDATE_ID,UPDATE_TIME
										)
										VALUES (
															B.COMPANY_ID, B.DIVISION_ID, B.SITE_ID, B.PLANT_ID, B.FACTORY_ID,B.OPERATION_ID,
															 B.LINE_ID, B.ITEM_ID, B.WORKER_QTY,
															B.JOB_USER_ID, dbo.SYSDATE1(), B.JOB_USER_ID, dbo.SYSDATE1()
										);
										
									INSERT INTO HIS_PACK_WORKER_M
										(COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, FACTORY_ID, OPERATION_ID, LINE_ID, ITEM_ID,WORKER_QTY, INSERT_ID, INSERT_TIME, UPDATE_ID, UPDATE_TIME
										, JOB_USER_ID, JOB_TIME, JOB_TYPE)
									SELECT 
										COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, FACTORY_ID, OPERATION_ID, LINE_ID, ITEM_ID, WORKER_QTY, INSERT_ID, INSERT_TIME, UPDATE_ID, UPDATE_TIME
										,@USER_ID AS JOB_USER_ID, GETDATE() AS JOB_TIME, 'EXCEL' AS JOB_TYPE
									FROM SCM_PACK_WORKER_M A(NOLOCK)
									WHERE EXISTS (SELECT 1 FROM BUF_PACK_WORKER_M B(NOLOCK)
										WHERE	A.COMPANY_ID = B.COMPANY_ID AND A.DIVISION_ID = B.DIVISION_ID AND A.SITE_ID = B.SITE_ID AND A.PLANT_ID = B.PLANT_ID AND A.FACTORY_ID = B.FACTORY_ID
										  AND A.OPERATION_ID = B.OPERATION_ID  
											AND A.LINE_ID = B.LINE_ID  AND A.ITEM_ID = B.ITEM_ID
											AND B.JOB_USER_ID = @USER_ID
										);
								END