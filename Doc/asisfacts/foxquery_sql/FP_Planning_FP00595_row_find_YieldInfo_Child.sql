SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID
           , A.LOCATION, A.OPERATION_ID, A.LINE_ID, A.ELECTRODE_TYPE
           , A.EQUIPMENT_ID
           , A.ITEM_ID
           , CONVERT(VARCHAR,A.START_DATE,112) AS START_DATE
           , CONVERT(VARCHAR,A.END_DATE,112) AS END_DATE
           , A.YIELD AS YIELD
           , A.CHILD_YIELD AS CHILD_YIELD
           , A.UTILIZATION
		   , A.CHILD_UTILIZATION
		   , A.LANE_TACT_TIME
      FROM   @AMEND_BOR_TABLE A WITH(NOLOCK)
      WHERE  A.INSTANCE_ID = @MASTER_ID
      AND    A.FP_PLAN_ID  = @PLAN_ID
      
      @CTRL_DIVISION_LT
      @CTRL_SITE_LT
      @CTRL_PLANT_LT
      @CTRL_FACTORY_LT
      @CTRL_OPERATION_LT
      @CTRL_LINE_LT
      @CTRL_ITEM_LK
      ORDER BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID
           , A.LOCATION, A.OPERATION_ID, A.LINE_ID, A.ELECTRODE_TYPE
           , A.EQUIPMENT_ID, A.ITEM_ID, START_DATE