BEGIN
			        MERGE INTO SCM_ITEM_LANE_M A
			        USING (SELECT RTRIM(LTRIM(@COMPANY_ID)) AS COMPANY_ID, RTRIM(LTRIM(@DIVISION_ID)) AS DIVISION_ID,
			                      RTRIM(LTRIM(@SITE_ID)) AS SITE_ID, RTRIM(LTRIM(@PLANT_ID)) AS PLANT_ID, RTRIM(LTRIM(@FACTORY_ID)) AS FACTORY_ID, RTRIM(LTRIM(@ITEM_ID)) AS ITEM_ID,
			                      (CONVERT(NUMERIC, RTRIM(LTRIM(@MAIN_LANE_QTY)))+CONVERT(NUMERIC, RTRIM(LTRIM(ISNULL(@SUB_LANE_QTY,0))))) AS LANE_QTY,
			                      UPPER(RTRIM(LTRIM(@PROD_VERSION_TYPE))) AS PROD_VERSION_TYPE) B
			        ON (    A.COMPANY_ID  = B.COMPANY_ID
			            AND A.DIVISION_ID = B.DIVISION_ID
			            AND A.SITE_ID     = B.SITE_ID
			            AND A.PLANT_ID    = B.PLANT_ID
			            AND A.FACTORY_ID  = B.FACTORY_ID
			            AND A.ITEM_ID     = B.ITEM_ID
			            AND A.LANE_QTY    = B.LANE_QTY
			            AND A.PROD_VERSION_TYPE = B.PROD_VERSION_TYPE
			        )
			        WHEN MATCHED THEN
			          UPDATE SET
			              A.MAIN_LANE_QTY       = RTRIM(LTRIM(@MAIN_LANE_QTY)),
			              A.SUB_LANE_QTY        = RTRIM(LTRIM(@SUB_LANE_QTY)),
			              A.PATTERN_QTY         = RTRIM(LTRIM(@PATTERN_QTY)),
			              A.HALF_SLIT_FLAG      = RTRIM(LTRIM(@HALF_SLIT_FLAG)),
			              A.ACTIVE_FLAG         = RTRIM(LTRIM(@ACTIVE_FLAG)),
			              A.DESCRIPTION         = RTRIM(LTRIM(@DESCRIPTION)),
			              A.SLIT_WIDTH          = RTRIM(LTRIM(@SLIT_WIDTH)),
			              A.PC_ROLL_LENGTH      = RTRIM(LTRIM(@PC_ROLL_LENGTH)),
			              A.PC_ROLL_LENGTH_UOM  = RTRIM(LTRIM(@PC_ROLL_LENGTH_UOM)),
			              A.PROD_VERSION_TYPE  	= CASE WHEN A.FACTORY_ID = 'E7' THEN  UPPER(RTRIM(LTRIM(@PROD_VERSION_TYPE))) 
			              							   ELSE A.PROD_VERSION_TYPE
			              							   END ,
			              A.UPDATE_ID           = @USER_ID,
			              A.UPDATE_TIME         = dbo.SYSDATE1()
			        WHEN NOT MATCHED THEN
			          INSERT(
			              COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, FACTORY_ID, ITEM_ID, 
			              LANE_QTY,
			              MAIN_LANE_QTY, SUB_LANE_QTY, PATTERN_QTY, HALF_SLIT_FLAG, DESCRIPTION, ACTIVE_FLAG, SLIT_WIDTH,
			              PC_ROLL_LENGTH, PC_ROLL_LENGTH_UOM,PROD_VERSION_TYPE,
			              INSERT_ID, INSERT_TIME, UPDATE_ID, UPDATE_TIME
			          )
			          VALUES (
			              RTRIM(LTRIM(@COMPANY_ID)), RTRIM(LTRIM(@DIVISION_ID)), RTRIM(LTRIM(@SITE_ID)), RTRIM(LTRIM(@PLANT_ID)), RTRIM(LTRIM(@FACTORY_ID)), RTRIM(LTRIM(@ITEM_ID)), 
			              (CONVERT(NUMERIC, RTRIM(LTRIM(@MAIN_LANE_QTY)))+CONVERT(NUMERIC, RTRIM(LTRIM(ISNULL(@SUB_LANE_QTY,0))))),
			              RTRIM(LTRIM(@MAIN_LANE_QTY)), RTRIM(LTRIM(@SUB_LANE_QTY)), RTRIM(LTRIM(@PATTERN_QTY)), RTRIM(LTRIM(@HALF_SLIT_FLAG)), RTRIM(LTRIM(@DESCRIPTION)), RTRIM(LTRIM(@ACTIVE_FLAG)), RTRIM(LTRIM(@SLIT_WIDTH)),
			              RTRIM(LTRIM(@PC_ROLL_LENGTH)), RTRIM(LTRIM(@PC_ROLL_LENGTH_UOM)), UPPER(RTRIM(LTRIM(@PROD_VERSION_TYPE))),
			              @USER_ID, dbo.SYSDATE1(), @USER_ID, dbo.SYSDATE1()
			          )
			        ;
			        
			        INSERT INTO HIS_ITEM_LANE_M (
			               COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, FACTORY_ID, ITEM_ID, LANE_QTY,
			               MAIN_LANE_QTY, SUB_LANE_QTY, PATTERN_QTY, HALF_SLIT_FLAG, DESCRIPTION, ACTIVE_FLAG, SLIT_WIDTH,
			               PC_ROLL_LENGTH, PC_ROLL_LENGTH_UOM,PROD_VERSION_TYPE,
			               INSERT_ID, INSERT_TIME, UPDATE_ID, UPDATE_TIME,
			               JOB_USER_ID, JOB_TIME, JOB_TYPE
			        )
			        SELECT COMPANY_ID, DIVISION_ID, SITE_ID, PLANT_ID, FACTORY_ID, ITEM_ID, LANE_QTY,
			               MAIN_LANE_QTY, SUB_LANE_QTY, PATTERN_QTY, HALF_SLIT_FLAG, DESCRIPTION, ACTIVE_FLAG, SLIT_WIDTH,
			               PC_ROLL_LENGTH, PC_ROLL_LENGTH_UOM,PROD_VERSION_TYPE,
			               INSERT_ID, INSERT_TIME, UPDATE_ID, UPDATE_TIME, 
			               @USER_ID, dbo.SYSDATE1(), 'EXCEL'
			        FROM   SCM_ITEM_LANE_M A WITH(NOLOCK)
			        WHERE  A.COMPANY_ID   = RTRIM(LTRIM(@COMPANY_ID))
			        AND    A.DIVISION_ID  = RTRIM(LTRIM(@DIVISION_ID))
			        AND    A.SITE_ID      = RTRIM(LTRIM(@SITE_ID))
			        AND    A.PLANT_ID     = RTRIM(LTRIM(@PLANT_ID))
			        AND    A.FACTORY_ID   = RTRIM(LTRIM(@FACTORY_ID))
			        AND    A.ITEM_ID      = RTRIM(LTRIM(@ITEM_ID))
			        AND    A.LANE_QTY     = (CONVERT(NUMERIC, RTRIM(LTRIM(@MAIN_LANE_QTY)))+CONVERT(NUMERIC, RTRIM(LTRIM(ISNULL(@SUB_LANE_QTY,0)))))
			        ;
			        
			        
			      
			      END;