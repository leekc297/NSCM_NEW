BEGIN
		        BEGIN TRAN
				
        
        MERGE INTO FP_INSTANCE_ITEM_SETUP_ATTR_LIST_M A
        USING
        (
            SELECT @INSTANCE_ID AS INSTANCE_ID, @OPERATION_ID AS OPERATION_ID, 
			@ATTRIBUTE_TYPE  AS ATTRIBUTE_TYPE, @ATTRIBUTE_LIST AS ATTRIBUTE_LIST
        ) B ON 1=1 AND A.INSTANCE_ID = B.INSTANCE_ID AND A.OPERATION_ID = B.OPERATION_ID 
		AND A.ATTRIBUTE_TYPE = B.ATTRIBUTE_TYPE AND A.ATTRIBUTE_LIST = B.ATTRIBUTE_LIST
		WHEN MATCHED THEN
		UPDATE SET DESCRIPTION = @DESCRIPTION,
		ACTIVE_FLAG = @ACTIVE_FLAG
        WHEN NOT MATCHED THEN
        INSERT (INSTANCE_ID, OPERATION_ID, ATTRIBUTE_TYPE, ATTRIBUTE_LIST,
		ACTIVE_FLAG,DESCRIPTION,INSERT_ID,UPDATE_ID, INSERT_TIME, UPDATE_TIME)
		VALUES (@INSTANCE_ID, @OPERATION_ID, @ATTRIBUTE_TYPE, @ATTRIBUTE_LIST,
		@ACTIVE_FLAG,@DESCRIPTION,@USER_ID, @USER_ID, GetDate(),GetDate());

		DELETE FROM FP_INSTANCE_ITEM_SETUP_ATTR_LIST_M 
		WHERE  INSTANCE_ID = @INSTANCE_ID AND OPERATION_ID = @OPERATION_ID 
		AND ATTRIBUTE_TYPE = @ATTRIBUTE_TYPE AND ATTRIBUTE_LIST = @OLD_ATTRIBUTE_LIST


		        COMMIT;		       
		      END;