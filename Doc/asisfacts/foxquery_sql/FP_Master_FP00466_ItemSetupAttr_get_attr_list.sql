select distinct a.instance_id,lk.SEGMENT2 as instance_name, a.operation_id
             ,a.attribute_type as ATTRIBUTE_TYPE,
			 CASE 
				 WHEN ATTRIBUTE_TYPE = 'ATTRIBUTE1' THEN B.ATTRIBUTE1 
				 WHEN ATTRIBUTE_TYPE = 'ATTRIBUTE2' THEN B.ATTRIBUTE2 
				 WHEN ATTRIBUTE_TYPE = 'ATTRIBUTE3' THEN B.ATTRIBUTE3 
				 WHEN ATTRIBUTE_TYPE = 'ATTRIBUTE4' THEN B.ATTRIBUTE4 
				 WHEN ATTRIBUTE_TYPE = 'ATTRIBUTE5' THEN B.ATTRIBUTE5
				 WHEN ATTRIBUTE_TYPE = 'ATTRIBUTE6' THEN B.ATTRIBUTE6
				 WHEN ATTRIBUTE_TYPE = 'ATTRIBUTE7' THEN B.ATTRIBUTE7
				 WHEN ATTRIBUTE_TYPE = 'ATTRIBUTE8' THEN B.ATTRIBUTE8
				 WHEN ATTRIBUTE_TYPE = 'ATTRIBUTE9' THEN B.ATTRIBUTE9
				 WHEN ATTRIBUTE_TYPE = 'ATTRIBUTE10' THEN B.ATTRIBUTE10
				 WHEN ATTRIBUTE_TYPE = 'ATTRIBUTE11' THEN B.ATTRIBUTE11
				 WHEN ATTRIBUTE_TYPE = 'ATTRIBUTE12' THEN B.ATTRIBUTE12
				 WHEN ATTRIBUTE_TYPE = 'ATTRIBUTE13' THEN B.ATTRIBUTE13
				 WHEN ATTRIBUTE_TYPE = 'ATTRIBUTE14' THEN B.ATTRIBUTE14
				 WHEN ATTRIBUTE_TYPE = 'ATTRIBUTE15' THEN B.ATTRIBUTE15
				 ELSE ''
			 END AS ATTRIBUTE_NAME
			 ,a.attribute_list as ATTRIBUTE_LIST
             ,a.active_flag	as 	ACTIVE_FLAG							
             ,a.description as DESCRIPTION
             ,a.insert_id, a.update_id																				   
             ,a.insert_time,a.update_time															   
       from   FP_INSTANCE_ITEM_SETUP_ATTR_LIST_M   a WITH(NOLOCK)   		
	   LEFT OUTER JOIN SCM_SYS_LOOKUP_VALUE LK WITH(NOLOCK)
ON 1=1
AND LK.LOOKUP_TYPE_CODE='INSTANCE_ID'
AND A.INSTANCE_ID = LK.SEGMENT1
	   INNER JOIN FP_INSTANCE_ITEM_SETUP_ATTR_TYPE_M B WITH(NOLOCK)
	   ON 
	   A.INSTANCE_ID = B.INSTANCE_ID
	   AND A.operation_id = B.operation_id
	   
       where  1=1
                AND (A.INSTANCE_ID = ISNULL(@INSTANCE_ID,'') OR ISNULL(@INSTANCE_ID,'') = '')
                AND (A.OPERATION_ID = ISNULL(@OPERATION_ID,'') OR ISNULL(@OPERATION_ID,'') = '')