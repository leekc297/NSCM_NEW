SELECT (CASE WHEN C.ACTIVE_FLAG = 'Y' THEN '1' ELSE '' END) AS ACTIVE_FLAG
           , A.INSTANCE_ID, @FP_PLAN_ID AS FP_PLAN_ID
           , A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID
           , A.OPERATION_ID, A.LINE_ID, ISNULL(B.LINE_NAME, '-') AS LINE_NAME, A.ELECTRODE_TYPE
           , C.START_DATE, C.END_DATE
      FROM   FP_INSTANCE_LINE_V A WITH(NOLOCK)
      LEFT OUTER JOIN SCM_LINE_M B WITH(NOLOCK)
      ON    A.FACTORY_ID     = B.FACTORY_ID
      AND   A.OPERATION_ID   = B.OPERATION_ID
      AND   A.LINE_ID        = B.LINE_ID
      AND   A.ELECTRODE_TYPE = B.ELECTRODE_TYPE
      LEFT OUTER JOIN (
        	SELECT A.FACTORY_ID, A.LINE_ID, A.ELECTRODE_TYPE, A.OPERATION_ID
                , CONVERT(VARCHAR,A.START_DATE,112) AS START_DATE, CONVERT(VARCHAR,A.END_DATE,112) AS END_DATE
                , A.ACTIVE_FLAG
        	FROM   FP_LINE_CAPA_SYNC_H A WITH(NOLOCK)
        	WHERE  1=1
        	AND    A.INSTANCE_ID  = @INSTANCE_ID
        	AND    A.FP_PLAN_ID   = @FP_PLAN_ID
        	AND    A.OPERATION_ID = 'E2000'
      ) C
      ON    A.FACTORY_ID     = C.FACTORY_ID
      AND   A.OPERATION_ID   = C.OPERATION_ID
      AND   A.LINE_ID        = C.LINE_ID
      AND   A.ELECTRODE_TYPE = C.ELECTRODE_TYPE
      WHERE 1=1
      AND   A.INSTANCE_ID  = @INSTANCE_ID
      AND   A.OPERATION_ID = 'E2000'
      ORDER BY FACTORY_ID, LINE_ID, ELECTRODE_TYPE