SELECT LOOKUP_TYPE_CODE, SEGMENT1, SEGMENT2, SEGMENT3, SEGMENT4, SEGMENT5
               , ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10, ATTRIBUTE11, ATTRIBUTE12, ATTRIBUTE13, ATTRIBUTE14, ATTRIBUTE15
               , SORT_ORDER, ACTIVE_FLAG, VALUE_DESCRIPTION, PLANT_ID
               , CREATE_USER_ID, CREATE_DATE
               , MODIFY_USER_ID, MODIFY_DATE
          FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
          WHERE  1=1
          AND    A.LOOKUP_TYPE_CODE = @LOOKUP_TYPE_CODE
          AND    A.SEGMENT1 = (CASE WHEN @SEGMENT1 != '' AND @SEGMENT1 IS NOT NULL THEN @SEGMENT1 ELSE A.SEGMENT1 END)
          AND    A.SEGMENT2 = (CASE WHEN @SEGMENT2 != '' AND @SEGMENT2 IS NOT NULL THEN @SEGMENT2 ELSE A.SEGMENT2 END)
          AND    A.SEGMENT3 = (CASE WHEN @SEGMENT3 != '' AND @SEGMENT3 IS NOT NULL THEN @SEGMENT3 ELSE A.SEGMENT3 END)
          AND    A.SEGMENT4 = (CASE WHEN @SEGMENT4 != '' AND @SEGMENT4 IS NOT NULL THEN @SEGMENT4 ELSE A.SEGMENT4 END)
          AND    A.SEGMENT5 = (CASE WHEN @SEGMENT5 != '' AND @SEGMENT5 IS NOT NULL THEN @SEGMENT5 ELSE A.SEGMENT5 END)
          AND    A.ACTIVE_FLAG = 'Y'
          ORDER BY SORT_ORDER