SELECT ROW_NUMBER() OVER ( ORDER BY A.INSTANCE_ID, A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.PLAN_GROUP_ID ) AS NUM, A.ROLE_ID,
      	     A.INSTANCE_ID, A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.PLAN_GROUP_ID,
      	     dbo.FN_GETNAME_FACTORY_ID(A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID) AS FACTORY_NAME,
      	     (CASE A.USE_AT_FLAG WHEN 'Y' THEN 'True' WHEN 'True' THEN 'True' ELSE 'False' END) AS USE_AT_FLAG,
      	     A.INSERT_ID, CONVERT(varchar(max), A.INSERT_DTTM, 112) AS INSERT_DTTM,
      	     A.UPDATE_ID, CONVERT(varchar(max), A.UPDATE_DTTM, 112) AS UPDATE_DTTM
      FROM   TH_UIS_ROLE_INSTANCE_RELATE A WITH(NOLOCK)
      WHERE  A.ROLE_ID = @ROLE_ID
      ORDER BY A.INSTANCE_ID, A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.PLAN_GROUP_ID