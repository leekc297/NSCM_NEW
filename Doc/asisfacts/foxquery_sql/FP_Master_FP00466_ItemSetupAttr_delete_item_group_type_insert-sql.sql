BEGIN
		        BEGIN TRAN
				MERGE INTO FP_INSTANCE_ITEM_SETUP_ATTR_TYPE_M A
				using

				(SELECT @INSTANCE_ID AS INSTANCE_ID, @OPERATION_ID AS OPERATION_ID) B
				ON 1=1 AND A.INSTANCE_ID = B.INSTANCE_ID AND A.OPERATION_ID = B.OPERATION_ID
				WHEN MATCHED THEN
          DELETE;

        MERGE INTO FP_ITEM_SETUP_GROUP_M A
        USING
        (
            SELECT @INSTANCE_ID AS INSTANCE_ID, @OPERATION_ID AS OPERATION_ID, 'ATTRIBUTE' AS SETUP_CATEGORY_ID
        ) B ON 1=1 AND A.INSTANCE_ID = B.INSTANCE_ID AND A.OPERATION_ID = B.OPERATION_ID AND A.SETUP_CATEGORY_ID = B.SETUP_CATEGORY_ID 
        WHEN MATCHED THEN 
		DELETE;

		        COMMIT;		       
		      END;