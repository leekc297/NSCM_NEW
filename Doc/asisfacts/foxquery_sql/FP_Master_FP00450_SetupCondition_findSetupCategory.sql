SELECT A.SEGMENT1 AS CODE, A.SEGMENT1 AS NAME
            ,A.SEGMENT1,A.SEGMENT2,A.SEGMENT3,A.SEGMENT4,A.SEGMENT5
            ,A.SORT_ORDER
      FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
      WHERE  A.LOOKUP_TYPE_CODE = 'SETUP_CATEGORY'
      AND    A.ACTIVE_FLAG      = 'Y'
      ORDER BY A.SORT_ORDER