SELECT TT.DIVISION_ID
	,TT.SITE_ID
	,TT.PLANT_ID
	,TT.OPERATION_ID
	,TT.FACTORY_ID
	,TT.LINE_ID
	,TT.ITEM_ID
	,TT.ELECTRODE_TYPE
	,TT.PRODUCTION_TYPE
	,TT.EQUIPMENT_ID
	,TT.MARKET
	,TT.PLAN_DATE
	,TT.TOP_ITEM_ID
	,TT.INSTANCE_ID
	,TT.MEMO_RANGE 
	,CASE WHEN __MSG = ' Not Found' THEN '' ELSE __MSG END as _MSG
	,CASE WHEN __MSG = ' Not Found' THEN 'Y' ELSE 'N' END AS _VALID
  FROM
(
      SELECT 
	  msg1 
	  + CASE WHEN (MSG1 = '') THEN msg2 ELSE (CASE WHEN MSG2 = '' THEN '' ELSE ','+MSG2 END) END
      + CASE WHEN (MSG1 = '' AND MSG2 = '') THEN MSG3 ELSE (CASE WHEN MSG3 = '' THEN '' ELSE ',' + MSG3 END) END
      + CASE WHEN (MSG1 = '' AND MSG2 = '' and msg3='') THEN MSG4 ELSE (CASE WHEN MSG4 = '' THEN '' ELSE ',' + MSG4 END) END
      + CASE WHEN (MSG1 = '' AND MSG2 = '' and msg3='' and msg4='') THEN MSG5 ELSE (CASE WHEN MSG5 = '' THEN '' ELSE ',' + MSG5 END) END
      + ' Not Found' AS __MSG
	  ,tt.*
FROM
(

SELECT DISTINCT TT.DIVISION_ID
	,TT.SITE_ID
	,TT.PLANT_ID
	,TT.OPERATION_ID
	,TT.FACTORY_ID
	,TT.LINE_ID
	,TT.ITEM_ID
	,TT.ELECTRODE_TYPE
	,TT.PRODUCTION_TYPE
	,TT.EQUIPMENT_ID
	,TT.MARKET
	,TT.PLAN_DATE
	,TT.TOP_ITEM_ID
	,TT.INSTANCE_ID
	,CASE WHEN ISNULL(TT.ITEM_ID,'-') = '-' THEN 'LINE' ELSE 'MATERIAL' END AS MEMO_RANGE
	,CASE WHEN ISNULL(TT.OPERATION_ID,'') = '' THEN 'Operation' ELSE '' END AS MSG1
	,CASE WHEN ISNULL(TT.FACTORY_ID,'') = '' THEN 'Factory' ELSE '' END AS MSG2
	,CASE WHEN ISNULL(TT.LINE_ID,'') = ''THEN 'Line' ELSE '' END AS MSG3
	,CASE WHEN (ISNULL(TT.INSTANCE_TYPE,'') NOT LIKE 'E%' AND ISNULL(TT.EQUIPMENT_ID,'-') <> '-') THEN 'Equipment' ELSE '' END AS MSG4
	,'' AS MSG5
	FROM (
SELECT	A.DIVISION_ID
	,A.SITE_ID
	,A.PLANT_ID
	,A.OPERATION_ID
	,A.FACTORY_ID
	,A.LINE_ID
	,A.ITEM_ID
	,A.ELECTRODE_TYPE
	,A.PRODUCTION_TYPE
	,A.EQUIPMENT_ID
	,A.MARKET
	,A.PLAN_DATE
	,A.TOP_ITEM_ID
	,A.INSTANCE_ID
	,FI.INSTANCE_TYPE
--,A.INSERT_ID, CONVERT(VARCHAR, A.INSERT_TIME, 120) AS INSERT_TIME
--	,B.NICK_NAME AS PROBLEM_DATA_NICK
--,C.NICK_NAME AS TOP_ITEM_ID_NICK
FROM	BUF_FP_AMEND_MEMO_VALIDATION A WITH(NOLOCK)

--- VALIDATION EQUIMPMENT_ID
LEFT OUTER JOIN FP_INSTANCE_INFO_V FI WITH(NOLOCK)
ON A.INSTANCE_ID = FI.INSTANCE_ID

--- VALIDATION LINE_ID
LEFT OUTER JOIN SCM_LINE_M D WITH(NOLOCK)
ON  A.DIVISION_ID     = D.DIVISION_ID
AND A.SITE_ID   = D.SITE_ID
AND A.PLANT_ID  = D.PLANT_ID
AND A.FACTORY_ID      = D.FACTORY_ID
AND A.OPERATION_ID    = D.OPERATION_ID
AND A.LINE_ID   = D.LINE_ID
AND A.ELECTRODE_TYPE  = D.ELECTRODE_TYPE
AND D.ACTIVE_FLAG     = 'Y'

--- VALIDATION ITEM_ID
LEFT OUTER HASH JOIN SCM_ITEM_M B WITH(NOLOCK)
ON  
A.DIVISION_ID = B.DIVISION_ID
AND A.SITE_ID     = B.SITE_ID
AND A.ITEM_ID = B.ITEM_ID

--- VALIDATION FACTORY_ID
LEFT OUTER JOIN SCM_FACTORY_M F WITH(NOLOCK)
ON    A.DIVISION_ID = F.DIVISION_ID
AND   A.SITE_ID     = F.SITE_ID
AND   A.PLANT_ID    = F.PLANT_ID
AND 	A.FACTORY_ID  = F.FACTORY_ID
AND   F.ACTIVE_FLAG = 'Y'
--- VALIDATION OPERATION_ID
LEFT OUTER JOIN SCM_OPERATION_M C WITH(NOLOCK)
ON
A.DIVISION_ID     = C.DIVISION_ID
AND A.SITE_ID   = C.SITE_ID
AND A.OPERATION_ID    = C.OPERATION_ID
AND C.ACTIVE_FLAG     = 'Y'
---DIVISION_ID
