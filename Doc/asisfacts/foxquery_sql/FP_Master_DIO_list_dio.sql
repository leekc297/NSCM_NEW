;WITH LOOK_UP AS
(
SELECT SEGMENT1 AS DIVISION_ID, SEGMENT2 AS SITE_ID,SEGMENT3 AS ITEM_ID, SEGMENT4 AS DIO

FROM SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
WHERE  LOOKUP_TYPE_CODE = 'MATERIAL_DIO_DAY'
AND (ISNULL(@DIVISION_ID,'') = '' OR A.SEGMENT1 =@DIVISION_ID) 
AND (ISNULL(@SITE_ID,'') = '' OR A.SEGMENT2 =@SITE_ID) 
AND (ISNULL(@ITEM_ID,'') = '' OR A.SEGMENT3 =@ITEM_ID) 
)
SELECT * FROM LOOK_UP