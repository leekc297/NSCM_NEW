SELECT ROW_NUMBER() OVER ( ORDER BY CASE WHEN START_DATE > dbo.SYSDATE1() THEN 1 ELSE 2 END, START_DATE ) AS NO,
                 GROUP_ID, DIVISION_ID, VALID,
                 CREATE_USER_ID, CONVERT(VARCHAR, CREATE_DATE, 120) CREATE_DATE,
          	     MODIFY_USER_ID, CONVERT(VARCHAR, MODIFY_DATE, 120) MODIFY_DATE,
          	     CONVERT(VARCHAR, START_DATE, 120) START_DATE, CONVERT(VARCHAR, START_DATE, 120) AS ORG_START_DATE,
          	     CONVERT(VARCHAR, END_DATE, 120) END_DATE, CONVERT(VARCHAR, END_DATE, 120) AS ORG_END_DATE,
          	     CONVERT(VARCHAR, START_DATE, 112) START_YMD,
          	     CONVERT(VARCHAR, END_DATE, 112) END_YMD,
          	     CONVERT(VARCHAR(2), START_DATE, 108) START_HOUR,
          	     CONVERT(VARCHAR(2), END_DATE, 108) END_HOUR,
          	     RIGHT(CONVERT(VARCHAR(5), START_DATE, 108), 2) START_MIN,
          	     RIGHT(CONVERT(VARCHAR(5), END_DATE, 108), 2) END_MIN,
          	     CASE WHEN START_DATE > dbo.SYSDATE1() THEN 'Y' ELSE 'N' END AS VIEW_FLAG
          FROM  JOB_SCHEDULE_EXCEPTION A WITH(NOLOCK)
          WHERE GROUP_ID    = @GROUP_ID
          AND   DIVISION_ID = @DIVISION_ID
          AND   START_DATE > dbo.SYSDATE1()
          ORDER BY CASE WHEN START_DATE > dbo.SYSDATE1() THEN 1 ELSE 2 END, START_DATE