SELECT ISO_YYYYWW AS WEEK
           , (SUBSTRING(ISO_YYYYWW,1,4) + 'W' + SUBSTRING(ISO_YYYYWW,5,2)) AS WEEK_NAME
           , COUNT(*) AS WEEK_COUNT
           , 'W' + CONVERT(VARCHAR,(ROW_NUMBER() OVER(ORDER BY ISO_YYYYWW))-1) AS W_VALUE
           , '1' AS IS_DAY_VIEW
      FROM   TH_UIS_CAL AS CAL WITH(NOLOCK)
      WHERE  CAL.DT >= CONVERT(DATETIME, @BUCKET_FROM, 112)
      AND    CAL.DT <= CONVERT(DATETIME, @BUCKET_TO, 112)
      GROUP BY ISO_YYYYWW
      ORDER BY ISO_YYYYWW