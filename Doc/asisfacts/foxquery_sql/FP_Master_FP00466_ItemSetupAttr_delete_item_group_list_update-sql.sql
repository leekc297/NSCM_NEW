BEGIN
		        BEGIN TRAN
				
        
        MERGE INTO FP_INSTANCE_ITEM_SETUP_ATTR_LIST_M A
        USING
        (
            SELECT @INSTANCE_ID AS INSTANCE_ID, @OPERATION_ID AS OPERATION_ID, 
			@ATTRIBUTE_TYPE  AS ATTRIBUTE_TYPE, @ATTRIBUTE_LIST AS ATTRIBUTE_LIST
        ) B ON 1=1 AND A.INSTANCE_ID = B.INSTANCE_ID AND A.OPERATION_ID = B.OPERATION_ID 
		AND A.ATTRIBUTE_TYPE = B.ATTRIBUTE_TYPE AND A.ATTRIBUTE_LIST = B.ATTRIBUTE_LIST
		WHEN MATCHED THEN
    DELETE;   

		        COMMIT;		       
		      END;