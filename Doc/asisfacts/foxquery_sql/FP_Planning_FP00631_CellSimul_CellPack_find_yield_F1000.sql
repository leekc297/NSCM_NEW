SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, LINE_ID, ITEM_ID, A.MONTH
            , (CASE WHEN A.YIELD_F1000 = 0 THEN 1 ELSE A.YIELD_F1000 END) AS YIELD_F1000
            , (CASE WHEN A.YIELD_F4000 = 0 THEN 1 ELSE A.YIELD_F4000 END) AS YIELD_F4000
            , (CASE WHEN A.YIELD_F4500 = 0 THEN 1 ELSE A.YIELD_F4500 END) AS YIELD_F4500
            , (CASE WHEN A.YIELD_F4700 = 0 THEN 1 ELSE A.YIELD_F4700 END) AS YIELD_F4700
            , (CASE WHEN A.YIELD_F1000 = 0 THEN 1 ELSE A.YIELD_F1000 END)
             *(CASE WHEN A.YIELD_F4000 = 0 THEN 1 ELSE A.YIELD_F4000 END)
             *(CASE WHEN A.YIELD_F4500 = 0 THEN 1 ELSE A.YIELD_F4500 END)
             *(CASE WHEN A.YIELD_F4700 = 0 THEN 1 ELSE A.YIELD_F4700 END) AS YIELD
      FROM (
      	SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, LINE_ID, ITEM_ID, A.MONTH
      		 , MAX(CASE WHEN A.OPERATION_ID = 'F1000' THEN A.YIELD ELSE 0 END) AS YIELD_F1000
      		 , MAX(CASE WHEN A.OPERATION_ID = 'F4000' THEN A.YIELD ELSE 0 END) AS YIELD_F4000
      		 , MAX(CASE WHEN A.OPERATION_ID = 'F4500' THEN A.YIELD ELSE 0 END) AS YIELD_F4500
      		 , MAX(CASE WHEN A.OPERATION_ID = 'F4700' THEN A.YIELD ELSE 0 END) AS YIELD_F4700
      	FROM (
      		SELECT *
      		FROM   SCM_YIELD_M A WITH(NOLOCK)
      		WHERE  1=1
      		AND    OPERATION_ID IN ('F1000', 'F4000', 'F4500', 'F4700')
      		AND    A.MONTH BETWEEN SUBSTRING(@PLAN_DATE,1,6) AND SUBSTRING(@BUCKET_TO,1,6) -- INSTANCE DATE ~ END DATE
      		AND EXISTS (
      				SELECT 1
      				FROM (
      					SELECT DISTINCT B.COMPANY_ID, B.DIVISION_ID, B.SITE_ID, B.PLANT_ID, B.FACTORY_ID
      					FROM   FP_INSTANCE_FACTORY_M A WITH(NOLOCK), SCM_FACTORY_M B WITH(NOLOCK)
      					WHERE  A.FACTORY_ID = B.FACTORY_ID
      					AND    A.ACTIVE_FLAG = 'Y'
      					AND    B.ACTIVE_FLAG = 'Y'
      					AND    A.INSTANCE_ID = @FORM_INSTANCE_ID -- FORM INSTANCE 기준 PLANT
      				) BB
      				WHERE A.COMPANY_ID  = BB.COMPANY_ID
      				AND   A.DIVISION_ID = BB.DIVISION_ID
      				AND   A.SITE_ID     = BB.SITE_ID
      				AND   A.PLANT_ID    = BB.PLANT_ID
      				AND   A.FACTORY_ID  = BB.FACTORY_ID
      		)
      	) A
      	GROUP BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, LINE_ID, ITEM_ID, A.MONTH
      ) A
      ORDER BY A.FACTORY_ID, LINE_ID, ITEM_ID, A.MONTH