SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID 
             , A.OPERATION_ID, A.LINE_ID, C.ELECTRODE_TYPE, F.LINE_NAME, F.LOCATION
             , A.ITEM_ID AS TOP_ITEM_ID, A.ITEM_ID, E.NICK_NAME, E.ITEM_TYPE
             , A.MARKET, A.PRODUCTION_TYPE, D.FP_PRODUCTION_TYPE
        	   , A.PLM_EC_NO, A.VERSION, G.EQUIPMENT_ID
        	   , H.MODEL_ID, H.PROD_VERSION_TYPE, H.MAX_VER_FLAG, H.VERSION_TYPE, H.PROD_SEQ
        FROM   FP_WEEKLY_DEMAND_PRODUCT_PDS_H A WITH(NOLOCK) 
        , (
            SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.OPERATION_ID, A.LINE_ID 
            FROM   FP_INSTANCE_LINE_V A WITH(NOLOCK) 
            WHERE  A.INSTANCE_ID  = @INSTANCE_ID
            GROUP BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.OPERATION_ID, A.LINE_ID 
        ) B
        , SCM_ITEM_LINE_ASSIGN_M C WITH(NOLOCK)
        , (
        	SELECT DISTINCT IV.COMPANY_ID, IV.DIVISION_ID, IV.SITE_ID, IV.PLANT_ID, SS.PRODUCTION_TYPE, SS.FP_PRODUCTION_TYPE 
        	FROM   FP_INSTANCE_INFO_V IV WITH(NOLOCK), SCM_SYS_LOOKUP_VALUE SV WITH(NOLOCK)
        	, (
        			SELECT DISTINCT SEGMENT1 AS DIVISION_ID, SEGMENT2 AS PRODUCTION_TYPE, ATTRIBUTE2 AS FP_PRODUCTION_TYPE 
        			FROM   SCM_SYS_LOOKUP_VALUE SS WITH(NOLOCK)
        			WHERE 1=1
        			AND SS.LOOKUP_TYPE_CODE = 'DIVISION_DEMAND_TYPE'
        			AND SS.ACTIVE_FLAG = 'Y'
        			AND SS.ATTRIBUTE5 = 'Y' -- PDA TARGET FLAG
        			--AND SV.ATTRIBUTE6 = 'Y' -- VERSION ONLY
        	) SS
        	WHERE	1=1
        	AND		SV.LOOKUP_TYPE_CODE = 'PDS_INSTANCE'
        	AND		SV.ACTIVE_FLAG	= 'Y'
        	AND		SV.SEGMENT1		  = IV.INSTANCE_ID
        	AND		IV.INSTANCE_ID	= @INSTANCE_ID
        	AND		IV.DIVISION_ID	=  SS.DIVISION_ID
        ) D
        , (
            SELECT DISTINCT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, B.PLANT_ID, A.ITEM_ID
                ,ISNULL(A.NICK_NAME,'-') AS NICK_NAME, A.FLOW_ID
                ,(CASE WHEN LEFT(A.FLOW_ID,5) = 'A9000' AND ISNULL(C.LEVEL_4_NAME, '-') = '-' THEN C.LEVEL_3_NAME
                       WHEN LEFT(A.FLOW_ID,5) = 'A9000' THEN ISNULL(C.LEVEL_4_NAME, '-')
                       ELSE C.LEVEL_3_NAME END) AS ITEM_TYPE
            FROM SCM_ITEM_M A WITH(NOLOCK),
                 SCM_MODEL_COMP_EFFECTIVE_DATE B WITH(NOLOCK),
                 SCM_ITEM_CLASS_M C WITH(NOLOCK),
            (
        		SELECT DISTINCT B.COMPANY_ID, B.DIVISION_ID, B.SITE_ID, B.OPERATION_ID
        		FROM   FP_INSTANCE_OPERATION_V A WITH(NOLOCK), SCM_OPERATION_M B WITH(NOLOCK)
        		WHERE  A.COMPANY_ID   = B.COMPANY_ID
        		AND    A.DIVISION_ID  = B.DIVISION_ID
        		AND    A.SITE_ID      = B.SITE_ID
        		AND    A.OPERATION_ID = B.OPERATION_ID
        		AND    A.INSTANCE_ID  = @INSTANCE_ID
        		AND    A.AMEND_FLAG   = 'Y'
        		AND    B.ACTIVE_FLAG  = 'Y'
            ) D
            WHERE A.COMPANY_ID  = B.COMPANY_ID
            AND	  A.DIVISION_ID = B.DIVISION_ID
            AND	  A.SITE_ID     = B.SITE_ID
            AND	  A.ITEM_ID     = B.CHILD_ITEM_ID
            AND	  A.ITEM_CLASS  = C.CLASS_ID
            AND   A.COMPANY_ID  = D.COMPANY_ID
            AND   A.DIVISION_ID = D.DIVISION_ID
            AND   A.SITE_ID     = D.SITE_ID
            AND   A.FLOW_ID LIKE '%' + D.OPERATION_ID + '%'
            AND   A.ACTIVE_FLAG = 'Y'
            AND   C.USE_FLAG = 'Y'
            AND   B.EFF_END_DATE >= GETDATE()
        ) E 
        , SCM_LINE_M F WITH(NOLOCK)
        , SCM_EQUIPMENT_M G WITH(NOLOCK)
        , (
          	SELECT DISTINCT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.OPERATION AS OPERATION_ID 
          		   , A.MODEL_ID, A.ITEM_ID, A.VERSION, A.PROD_VERSION_TYPE, A.MAX_VER_FLAG, A.VERSION_TYPE, A.PROD_SEQ
          	FROM   SCM_ITEM_CONV_CALC_M A WITH(NOLOCK)
          	, (
            		SELECT DISTINCT B.COMPANY_ID, B.DIVISION_ID, B.SITE_ID, B.PLANT_ID, B.FACTORY_ID, B.OPERATION_ID
            		FROM   FP_INSTANCE_LINE_V B WITH(NOLOCK)
            		WHERE  B.INSTANCE_ID = @INSTANCE_ID
            		AND    B.OPERATION_ID = 'E2000'
          	) B
          	WHERE  1=1 
          	AND    A.COMPANY_ID  = B.COMPANY_ID
          	AND    A.DIVISION_ID = B.DIVISION_ID
          	AND    A.SITE_ID     = B.SITE_ID
          	AND    A.PLANT_ID    = B.PLANT_ID
          	AND    A.FACTORY_ID  = B.FACTORY_ID
          	AND    A.OPERATION   = B.OPERATION_ID
          	AND    A.OPERATION = 'E2000' 
          	AND    A.CATEGORY IN ( 'cell/batch', 'Jumbo Roll (cell/m)', 'Jumbo Roll (m/batch)', 'Lane Number', 'Pancake (cell/m)', 'Pancake (m/batch)' )
        ) H
        WHERE  1=1
        AND    A.COMPANY_ID   = B.COMPANY_ID 
        AND    A.DIVISION_ID  = B.DIVISION_ID 
        AND    A.SITE_ID      = B.SITE_ID 
        AND    A.PLANT_ID     = B.PLANT_ID 
        AND    A.FACTORY_ID   = B.FACTORY_ID 
        AND    A.OPERATION_ID = B.OPERATION_ID 
        AND    A.LINE_ID      = B.LINE_ID 
        AND    A.MFG_WEEK >= (SELECT (ISO_YYYYWW) FROM TH_UIS_CAL B WITH(NOLOCK) WHERE YYYYMMDD = @PLAN_DATE)
        AND    A.COMPANY_ID   = C.COMPANY_ID 
        AND    A.DIVISION_ID  = C.DIVISION_ID 
        AND    A.SITE_ID      = C.SITE_ID 
        AND    A.PLANT_ID     = C.PLANT_ID 
        AND    A.FACTORY_ID   = C.FACTORY_ID 
        AND    A.OPERATION_ID = C.OPERATION_ID 
        AND    A.LINE_ID      = C.LINE_ID 
        AND    A.ITEM_ID      = C.ITEM_ID 
        AND    C.MONTH >= CONVERT(VARCHAR(6), @PLAN_DATE)
        AND    A.COMPANY_ID   = D.COMPANY_ID 
        AND    A.DIVISION_ID  = D.DIVISION_ID 
        AND    A.SITE_ID      = D.SITE_ID 
        AND    A.PLANT_ID     = D.PLANT_ID
        AND    A.PRODUCTION_TYPE = D.PRODUCTION_TYPE -- DEMAND_TYPE
        AND    A.COMPANY_ID   = E.COMPANY_ID 
        AND    A.DIVISION_ID  = E.DIVISION_ID 
        AND    A.SITE_ID      = E.SITE_ID 
        AND    A.ITEM_ID      = E.ITEM_ID 
        AND    A.COMPANY_ID   = F.COMPANY_ID 
        AND    A.DIVISION_ID  = F.DIVISION_ID 
        AND    A.SITE_ID      = F.SITE_ID 
        AND    A.PLANT_ID     = F.PLANT_ID 
        AND    A.FACTORY_ID   = F.FACTORY_ID 
        AND    A.OPERATION_ID = F.OPERATION_ID 
        AND    A.LINE_ID      = F.LINE_ID 
        AND    C.ELECTRODE_TYPE = F.ELECTRODE_TYPE
        AND    A.COMPANY_ID     = G.COMPANY_ID
        AND    A.DIVISION_ID    = G.DIVISION_ID
        AND    A.SITE_ID        = G.SITE_ID
        AND    A.PLANT_ID       = G.PLANT_ID
        AND    A.FACTORY_ID     = G.FACTORY_ID
        AND    A.OPERATION_ID   = G.OPERATION_ID
        AND    A.LINE_ID        = G.LINE_ID
        AND    C.ELECTRODE_TYPE = G.ELECTRODE_TYPE
        AND    A.COMPANY_ID   = H.COMPANY_ID 
        AND    A.DIVISION_ID  = H.DIVISION_ID 
        AND    A.SITE_ID      = H.SITE_ID 
        AND    A.PLANT_ID     = H.PLANT_ID 
        AND    A.FACTORY_ID   = H.FACTORY_ID 
        AND    A.OPERATION_ID = H.OPERATION_ID 
        AND    A.MODEL        = H.MODEL_ID
        AND    A.ITEM_ID      = H.ITEM_ID 
        AND    A.VERSION      = H.VERSION 
        AND    F.PROD_VERSION_TYPE = H.PROD_VERSION_TYPE
        AND    D.FP_PRODUCTION_TYPE = @PRODUCTION_TYPE
        @CTRL_LINE
        @CTRL_ITEM
        @CTRL_NICK
        GROUP BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID 
               , A.OPERATION_ID, A.LINE_ID, C.ELECTRODE_TYPE, A.ITEM_ID
               , A.MARKET, A.PRODUCTION_TYPE, D.FP_PRODUCTION_TYPE
        	     , A.PLM_EC_NO, A.VERSION, E.NICK_NAME, F.LINE_NAME, F.LOCATION
               , E.ITEM_TYPE, G.EQUIPMENT_ID
               , H.MODEL_ID, H.PROD_VERSION_TYPE, H.MAX_VER_FLAG, H.VERSION_TYPE, H.PROD_SEQ
        ORDER BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID 
               , A.OPERATION_ID, A.LINE_ID, C.ELECTRODE_TYPE, G.EQUIPMENT_ID, A.ITEM_ID
               , A.MARKET, A.PRODUCTION_TYPE, D.FP_PRODUCTION_TYPE
        	     , A.PLM_EC_NO, A.VERSION 
        	     , E.NICK_NAME, F.LINE_NAME, F.LOCATION