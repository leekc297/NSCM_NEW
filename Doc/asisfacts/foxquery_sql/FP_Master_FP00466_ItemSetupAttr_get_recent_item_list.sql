SELECT DISTINCT C.ITEM_ID,C.ITEM_ID AS ITEM_NAME  FROM 
(
SELECT DISTINCT ITEM_ID,LEFT(A.SCP_PLAN_ID,8) AS LDATE
FROm FP_WEEKLY_DEMAND_PRODUCT_H A WITH(NOLOCK)
INNER JOIN FP_INSTANCE_LINE_V B WITH(NOLOCK)
ON A.LINE_ID = B.LINE_ID
AND A.OPERATION_ID = B.OPERATION_ID
WHERE
LEFT(A.SCP_PLAN_ID,8) >= CONVERT(varchar(8), DATEADD(month, -3, GETDATE()), 112)
AND B.INSTANCE_ID = @INSTANCE_ID
AND B.OPERATION_ID = @OPERATION_ID
UNION ALL

SELECT DISTINCT ITEM_ID,CONVERT(varchar(8), A.PLAN_DATE, 112) AS LDATE -- LEFT(A.PLAN_DATE,8),  B.INSTANCE_ID, B.OPERATION_ID, A.OPERATION_ID, * 
FROm SCM_DAILY_PRODUCT_RESULT_H  A WITH(NOLOCK)
INNER JOIN FP_INSTANCE_LINE_V B WITH(NOLOCK)
ON A.LINE_ID = B.LINE_ID
AND A.OPERATION_ID = B.OPERATION_ID
WHERE
A.PLAN_DATE > DATEADD(month, -3, GETDATE())
AND B.INSTANCE_ID = @INSTANCE_ID 
AND B.OPERATION_ID =@OPERATION_ID


UNION ALL 

SELECT DISTINCT FROM_ITEM_SETUP_GROUP_ID AS ITEM_ID, FROM_ITEM_SETUP_GROUP_ID AS ITEM_NAME 
from   FP_SETUP_MATRIX_M B WITH(NOLOCK)
WHERE 1=1
AND B.SETUP_CATEGORY_ID = 'ITEM'
AND B.INSTANCE_ID = @INSTANCE_ID 
AND B.OPERATION_ID =@OPERATION_ID
AND ISNULL(FROM_ITEM_SETUP_GROUP_ID,'') <> 'ALL'
UNION ALL
SELECT DISTINCT TO_ITEM_SETUP_GROUP_ID AS ITEM_ID, FROM_ITEM_SETUP_GROUP_ID AS ITEM_NAME 
from   FP_SETUP_MATRIX_M B WITH(NOLOCK)
WHERE 1=1
AND B.SETUP_CATEGORY_ID = 'ITEM'
AND B.INSTANCE_ID = @INSTANCE_ID 
AND B.OPERATION_ID =@OPERATION_ID
AND ISNULL(TO_ITEM_SETUP_GROUP_ID,'') <> 'ALL'
) C

--LEFT OUTER JOIN SCM_ITEM_M D WITH(NOLOCK)
--ON C.ITEM_ID = D.ITEM_ID
ORDER BY ITEM_ID