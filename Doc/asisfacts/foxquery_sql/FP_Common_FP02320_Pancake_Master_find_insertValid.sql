SELECT COUNT(*) AS CNT
						FROM   SCM_ITEM_LANE_M A WITH(NOLOCK)
						WHERE  1=1
						AND    UPDATE_ID   = 'PR_XIF_PLM_CONVERSION_RATE_R'
						AND    COMPANY_ID  = @COMPANY_ID
						AND    DIVISION_ID = @DIVISION_ID
						AND    SITE_ID     = @SITE_ID
						AND    PLANT_ID    = @PLANT_ID
						AND    FACTORY_ID  = @FACTORY_ID
						AND    ITEM_ID     = @ITEM_ID
						AND    LANE_QTY    = @LANE_QTY
						AND    PROD_VERSION_TYPE = @PROD_VERSION_TYPE