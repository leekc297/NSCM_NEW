SELECT ROW_NUMBER() OVER ( ORDER BY A.USER_ID ) AS NUM, A.USER_ID AS USER_ID_ALTER, B.USER_NAME,
      	     A.ROLE_ID,
      	     CASE A.USE_AT_FLAG WHEN 'Y' THEN 'True' WHEN 'True' THEN 'True' ELSE 'False' END AS USE_AT_FLAG,
      	     CASE A.SAVE_FLAG WHEN 'Y' THEN 'True' WHEN 'True' THEN 'True' ELSE 'False' END AS SAVE_FLAG,
      	     A.INSERT_ID, CONVERT(varchar(max), A.INSERT_DTTM, 112) AS INSERT_DTTM,
      	     A.UPDATE_ID, CONVERT(varchar(max), A.UPDATE_DTTM, 112) AS UPDATE_DTTM
      FROM   TH_UIS_USER_INSTANCE_RELATE A WITH(NOLOCK), TH_UIS_USER_DETAIL B WITH(NOLOCK)
      WHERE  A.USER_ID = B.USER_ID
      AND    A.ROLE_ID = @ROLE_ID
      ORDER BY A.USER_ID