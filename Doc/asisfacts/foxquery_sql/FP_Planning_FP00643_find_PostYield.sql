if object_id('tempdb..#COATER_SITE') is not null
	DROP TABLE #COATER_SITE

SELECT DISTINCT A.DIVISION_ID, A.SITE_ID
INTO #COATER_SITE
FROM   FP_INSTANCE_LINE_V A WITH(NOLOCK)
WHERE  A.OPERATION_ID = 'E2000'
AND    A.INSTANCE_ID  = @INSTANCE_ID
;

SELECT A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.ITEM_ID, A.OPERATION_ID, MIN(YIELD) AS YIELD
FROM   SCM_YIELD_M A WITH(NOLOCK)
WHERE  1=1
AND    A.OPERATION_ID IN ('E3000','E4000')
AND    EXISTS (
	SELECT 1
	FROM   #COATER_SITE WW WITH(NOLOCK)
	WHERE  A.DIVISION_ID = WW.DIVISION_ID
	AND    A.SITE_ID     = WW.SITE_ID
)
AND A.MONTH BETWEEN CONVERT(VARCHAR(6),@BUCKET_FROM) AND CONVERT(VARCHAR(6),@BUCKET_TO)
GROUP BY A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, ITEM_ID, A.OPERATION_ID