SELECT A.SEGMENT1 AS CODE_ID, A.SEGMENT2 AS CODE_NAME
           , A.ATTRIBUTE1 AS CONFIRM_AREA, A.ATTRIBUTE2 AS IS_SAME_PLAN_ID, A.ATTRIBUTE3 AS USE_WOW_STATUS
           , ISNULL(C.AMEND_TYPE,'AMEND UI') AS AMEND_TYPE
           , A.ATTRIBUTE10 AS FIX_DATE_SYNC, A.ATTRIBUTE12 AS SYNC_YN
           , D.SITE_ID
      FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
      LEFT OUTER JOIN (
          SELECT A.SEGMENT1 AS INSTANCE_ID, ATTRIBUTE1 AS AMEND_TYPE
          FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
          WHERE  A.LOOKUP_TYPE_CODE = 'INSTANCE AMEND UI'
      ) C
      ON     A.SEGMENT1 = C.INSTANCE_ID
  	  INNER JOIN (
      		SELECT A.INSTANCE_ID, MAX(B.SITE_ID) AS SITE_ID
      		FROM   FP_INSTANCE_FACTORY_M A WITH(NOLOCK)
      		INNER JOIN SCM_FACTORY_M B WITH(NOLOCK)
      		ON    A.FACTORY_ID = B.FACTORY_ID
      		WHERE A.ACTIVE_FLAG = 'Y'
      		AND   B.ACTIVE_FLAG = 'Y'
      		GROUP BY A.INSTANCE_ID
  	  ) D
  	  ON     A.SEGMENT1 = D.INSTANCE_ID
      WHERE  A.LOOKUP_TYPE_CODE = 'INSTANCE_ID'
      AND    A.ACTIVE_FLAG = 'Y'
      AND    A.SEGMENT1 = @INSTANCE_ID
      GROUP BY A.SEGMENT1, A.SEGMENT2, A.ATTRIBUTE1, A.ATTRIBUTE2, A.ATTRIBUTE3, ISNULL(C.AMEND_TYPE,'AMEND UI')
             , A.ATTRIBUTE10, A.ATTRIBUTE12, D.SITE_ID