if object_id('tempdb..#COATER_SITE') is not null
	DROP TABLE #COATER_SITE
if object_id('tempdb..#FP_STOCH_H') is not null
	DROP TABLE #FP_STOCH_H

SELECT DISTINCT A.DIVISION_ID, A.SITE_ID
INTO #COATER_SITE
FROM   FP_INSTANCE_LINE_V A WITH(NOLOCK)
WHERE  A.OPERATION_ID = 'E2000'
AND    A.INSTANCE_ID  = @INSTANCE_ID
;

SELECT COMPANY_ID,DIVISION_ID,SITE_ID,PLANT_ID,FACTORY_ID,STORAGE_ID,CUTOFF_DATE,SEQ
	 , STOCK_TYPE,ITEM_ID,LANE,PRODUCTION_TYPE,AVAILABLE_DATE,REMAIN_LEAD_TIME
	 , HOLDING_DATE,QTY,QTY_UOM,STOCK_STATUS,OPERATION_ID,LINE_ID,OUTSOURCING_FLAG
	 , OUTSOURCING_FACTORY,DESCRIPTION,FP_APPLY_OPERATION_ID
	 , FP_APPLY_ITEM_ID,FP_APPLY_WIPQTY,WIPHOLD_YN,WIP_TYPE_CODE,QTY2,MODIFY_FP_APPLY_WIPQTY
	 , MODIFY_DESCRIPTION,CAL_QTY,FORMATION_REWORK_TYPE,INSERT_ID,INSERT_TIME,UPDATE_ID,UPDATE_TIME
	 , LOCATION,RELEASE_DUE_DATE,SHIP_AVAILABLE_DATE,LONG_TERM_QTY,MOVING_QTY
	 , CAPA_GRD_CODE,VLTG_GRD_CODE,RSST_GRD_CODE,DEFECT_QTY,PACK_MOVE_QTY,UNHOLD_EXP_DATE
	 , QMS_HOLD_YN,MES_MAP_SLOC,MES_HOLD_YN,MES_UNHOLD_DATE,QMS_HOLD_DATE,QMS_UNHOLD_EXP_DATE
	 , QMS_UNHOLD_DATE,SECOND_OCV_TIME,SECOND_OCV_EXP_DATE,LONG_TERM_FLAG,QLTY_NO_INSP_FLAG
	 , LOT_PACKING_TYPE,POSITION_CATEGORY,DETAIL_POSITION,LOT_COUNT,COATING_LINE_ID
	 , PACK_MOVE_FLAG,ELEC_POST_HOLD_YN,FROM_PLANT_ID
	 , A.WORK_REQUEST_MODEL_ID,A.VERSION
	 , PROD_SEQ
	 , PLM_EC_NO
INTO #FP_STOCH_H
FROM   SCM_STOCK_H_V A WITH(NOLOCK)
WHERE  1=1
AND    A.ITEM_ID = @ITEM_ID
AND    A.CUTOFF_DATE = @PLAN_DATE
AND    EXISTS (
	SELECT 1
	FROM   #COATER_SITE WW WITH(NOLOCK)
	WHERE  A.DIVISION_ID = WW.DIVISION_ID
	AND    A.SITE_ID     = WW.SITE_ID
)
;

SELECT A.*
    -- 팝업 기본 컬럼만 생성
    , 0 AS GOOD_ELEC_QTY , 0 AS GOOD_RW_QTY, 0 AS GOOD_ASSY_QTY
    , 0 AS QMS_ELEC_QTY, 0 AS QMS_RW_QTY, 0 AS QMS_ASSY_QTY
    , 0 AS GMES_ELEC_QTY, 0 AS GMES_RW_QTY, 0 AS GMES_ASSY_QTY
    , BB.NICK_NAME, BB.ITEM_UOM
    , C.OPERATION_NAME
    , (CASE WHEN A.AVAILABLE_DATE = '1999-01-01' THEN NULL ELSE A.AVAILABLE_DATE END) AS AVAILABLE_DATE_CPY
    , A.QMS_HOLD_YN AS QMS_HOLD_YN_CPY
    , A.WIPHOLD_YN AS WIPHOLD_YN_CPY
    , A.LONG_TERM_FLAG AS LONG_TERM_FLAG_CPY
    , A.OPERATION_ID AS OPERATION_ID_CPY
    --, (CASE WHEN A.STOCK_TYPE = 'INVENTORY' THEN 'DW(oWMS)' WHEN A.STOCK_TYPE = 'WIP' THEN 'GMES' ELSE A.STOCK_TYPE END) AS STOCK_TYPE_CPY
    , 'ERP' AS STOCK_TYPE_CPY
FROM   #FP_STOCH_H A WITH(NOLOCK) 
LEFT OUTER JOIN ( 
	SELECT DISTINCT A.SEGMENT1 AS OPERATION_ID, A.ATTRIBUTE1 AS OPERATION_NAME
	FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK)
	WHERE  1=1 
	AND    A.LOOKUP_TYPE_CODE = 'FP_OPERATION'
) C 
ON  1=1 
AND A.OPERATION_ID = C.OPERATION_ID
, ( 
	SELECT A.SEGMENT2 AS SITE_ID, A.SEGMENT3 AS DIVISION_ID, A.SEGMENT4 AS PLANT_ID 
			, A.SEGMENT5 AS STORAGE_ID, A.ATTRIBUTE11 AS STOCK_TYPE 
	FROM   SCM_SYS_LOOKUP_VALUE A WITH(NOLOCK) 
	WHERE  1=1 
	AND    A.LOOKUP_TYPE_CODE = 'SIMULATION_BOH' 
	AND    A.SEGMENT1 = 'CELL_SIMULATION' 
	--AND    A.ACTIVE_FLAG = 'Y' 
	AND    A.ATTRIBUTE11 IN ('GOOD','HOLD') 
) B 
, SCM_ITEM_M BB WITH(NOLOCK)
WHERE 1=1 
AND   A.DIVISION_ID = B.DIVISION_ID 
AND   A.SITE_ID     = B.SITE_ID 
AND   A.PLANT_ID    = B.PLANT_ID 
AND   A.STORAGE_ID  = B.STORAGE_ID 
AND   A.COMPANY_ID  = BB.COMPANY_ID
AND   A.DIVISION_ID = BB.DIVISION_ID
AND   A.SITE_ID     = BB.SITE_ID
AND   A.ITEM_ID     = BB.ITEM_ID
@CTRL_QTY_CONDITION_LT
ORDER BY A.STOCK_TYPE, A.COMPANY_ID, A.DIVISION_ID, A.SITE_ID, A.PLANT_ID, A.FACTORY_ID, A.FP_APPLY_OPERATION_ID, A.LINE_ID, A.STORAGE_ID, A.CUTOFF_DATE 
	   , A.FP_APPLY_ITEM_ID, A.LANE