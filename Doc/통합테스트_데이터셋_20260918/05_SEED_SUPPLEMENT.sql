--     근거: 권한메타 GET_ADMIN_GROUP_MEASURE 에 DMF0082/81/SCP Planner/SCM_FCST(TUE) 등재
--           그러나 DM_PLN_MKT_FCST 에 81 SCM_FCST 0건 → 테스트 불가
--     방식: **같은 키의 MKT_FCST 행을 그대로 복제**해 MEASURE 만 SCM_FCST 로
