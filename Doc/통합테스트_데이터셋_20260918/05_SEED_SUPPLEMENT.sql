-- §0. 사전 확인 — 대상 키가 실존하고 SCM_FCST 가 없는지
SELECT DIVISION_ID, ITEM_ID, SCM_SITE_ID,
       SUM(CASE WHEN MEASURE='MKT_FCST' THEN 1 ELSE 0 END) MKT_CNT,
       SUM(CASE WHEN MEASURE='SCM_FCST' THEN 1 ELSE 0 END) SCM_CNT
  FROM SCM_MGR.DM_PLN_MKT_FCST
 WHERE (DIVISION_ID, ITEM_ID) IN (
       ('81','ACLN1007I-A1'), ('81','ACHP2005I-A1'), ('81','ACLF1015I-A2'), ('81','ACLF1015I-B1'), ('81','AMFMCC727-D1-010')
       )
 GROUP BY DIVISION_ID, ITEM_ID, SCM_SITE_ID ORDER BY 1,2,3;

