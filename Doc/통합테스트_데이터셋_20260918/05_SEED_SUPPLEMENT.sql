-- 81 / ACLN1007I-A1 / site=HLGP_KR_CHU
MERGE INTO SCM_MGR.DM_PLN_MKT_FCST TGT
USING (
    SELECT DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE,
           INCOTERMS, 'SCM_FCST' AS MEASURE, PLANT_SITE_ID, YYYYMMDD, QTY
      FROM SCM_MGR.DM_PLN_MKT_FCST
     WHERE DIVISION_ID   = '81'
       AND ITEM_ID       = 'ACLN1007I-A1'
       AND SCM_SITE_ID   = 'HLGP_KR_CHU'
       AND PROJECT_CODE  = 'A15HC2001'
       AND DOM_EXP       = 'E'
       AND FCST_TYPE     = 'MPS'
       AND INCOTERMS     = 'Z02'
       AND PLANT_SITE_ID = 'HQ07-A'
       AND MEASURE       = 'MKT_FCST'
       AND QTY <> 0
) SRC
ON ( TGT.DIVISION_ID = SRC.DIVISION_ID AND TGT.PROJECT_CODE = SRC.PROJECT_CODE
 AND TGT.SCM_SITE_ID = SRC.SCM_SITE_ID AND TGT.ITEM_ID = SRC.ITEM_ID
 AND TGT.DOM_EXP = SRC.DOM_EXP AND TGT.FCST_TYPE = SRC.FCST_TYPE
 AND TGT.INCOTERMS = SRC.INCOTERMS AND TGT.MEASURE = SRC.MEASURE
 AND TGT.PLANT_SITE_ID = SRC.PLANT_SITE_ID AND TGT.YYYYMMDD = SRC.YYYYMMDD )
WHEN NOT MATCHED THEN INSERT (
    DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE,
    INCOTERMS, MEASURE, PLANT_SITE_ID, YYYYMMDD, QTY,
    CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES (
    SRC.DIVISION_ID, SRC.PROJECT_CODE, SRC.SCM_SITE_ID, SRC.ITEM_ID, SRC.DOM_EXP,
    SRC.FCST_TYPE, SRC.INCOTERMS, SRC.MEASURE, SRC.PLANT_SITE_ID, SRC.YYYYMMDD,
    SRC.QTY, 'TESTDATA_20260918', SYSDATE, 'TESTDATA_20260918', SYSDATE);

