-- §2. 40 BIZ PLAN 보완 — **자동 생성하지 않음**
--     대상: MCCM134010A1, MCCM350415B1
--     사유: DM_PLN_BIZPLAN 은 DEPT_ID·BIZ_TYPE·ITEM_USE·UNIT_ENERGY 등
--           MKT_FCST 에 없는 업무 속성을 요구한다. 파생 불가 = 임의값이 되므로 금지.
--     조치: DMF0042 화면에서 **직접 입력**하거나, 해당 ITEM 대신
--           BIZPLAN 실데이터 보유 ITEM 으로 교체할 것 (아래 조회로 후보 확인)
SELECT DIVISION_ID, ITEM_ID, SCM_SITE_ID, COUNT(*) CNT
  FROM SCM_MGR.DM_PLN_BIZPLAN WHERE DIVISION_ID='40'
 GROUP BY DIVISION_ID, ITEM_ID, SCM_SITE_ID
 ORDER BY CNT DESC FETCH FIRST 10 ROWS ONLY;

