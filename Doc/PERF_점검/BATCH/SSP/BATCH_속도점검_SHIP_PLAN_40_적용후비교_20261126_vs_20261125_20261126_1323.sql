-- ==============================================================================================================
-- [E3] 회차별 소요(기준일, 적용 뒤 실행일)
-- 확인 : GRP = BEFORE(기준일), AFTER(적용 뒤). USE_IN_COMPARE = Y 인 회차가 [E4] ~ [E10] 비교 대상
-- 기준일은 END 로 끝난 회차만 비교(11-25 SHIP_PLAN_40 1회차는 16zd7hkh15tk1 지연 회차라 제외). 적용 뒤는 전 회차
-- END 가 없는 회차의 구간 끝 = 다음 START 또는 START + 1일 중 이른 값
-- ==============================================================================================================
WITH PRM AS (SELECT TO_DATE('20261126', 'YYYYMMDD') AS P_DAY, TO_DATE('20261125', 'YYYYMMDD') AS B_DAY FROM DUAL)   /* P_DAY = 패키지 적용 뒤 실행일, B_DAY = 적용 전 기준일. 이 줄의 값만 바꿔 실행 */
, LG AS (
SELECT L.PROGRAM_NAME
     , L.EVENT_DATE
     , L.LOG_TYPE
     , L.IN_PARA_DATA
     , LEAD(L.EVENT_DATE)  OVER (PARTITION BY L.PROGRAM_NAME ORDER BY L.EVENT_DATE, DECODE(L.LOG_TYPE, 'START', 1, 'TXN', 2, 'ERROR', 3, 'END', 4)) AS NEXT_DATE
     , LEAD(L.LOG_TYPE)    OVER (PARTITION BY L.PROGRAM_NAME ORDER BY L.EVENT_DATE, DECODE(L.LOG_TYPE, 'START', 1, 'TXN', 2, 'ERROR', 3, 'END', 4)) AS NEXT_TYPE
     , LEAD(L.DESCRIPTION) OVER (PARTITION BY L.PROGRAM_NAME ORDER BY L.EVENT_DATE, DECODE(L.LOG_TYPE, 'START', 1, 'TXN', 2, 'ERROR', 3, 'END', 4)) AS NEXT_DESC
  FROM SCM_SYS_LOG_BATCH L
     , PRM
 WHERE L.PROGRAM_NAME IN ('PR_SSP_ANL_SHIP_PLAN_40', 'PR_SSP_ANL_SHIP_PLAN_40_BALANCE', 'PR_SSP_MAIL_SHIP_REQ_MINUS_BALANCE_40')
   AND L.LOG_TYPE IN ('START', 'END', 'ERROR')
   AND L.EVENT_DATE >= PRM.B_DAY
   AND L.EVENT_DATE <  PRM.P_DAY + 2
)
, RUNS AS (
SELECT /*+ MATERIALIZE */ LG.PROGRAM_NAME
     , CASE WHEN TRUNC(LG.EVENT_DATE) = PRM.P_DAY THEN 'AFTER' ELSE 'BEFORE' END AS GRP
     , TRUNC(LG.EVENT_DATE) AS RUN_DAY
     , ROW_NUMBER() OVER (PARTITION BY LG.PROGRAM_NAME, TRUNC(LG.EVENT_DATE) ORDER BY LG.EVENT_DATE) AS RUN_NO
     , LG.EVENT_DATE AS START_DATE
     , CASE WHEN LG.NEXT_TYPE IN ('END', 'ERROR') THEN LG.NEXT_DATE END AS END_DATE
     , CASE WHEN LG.NEXT_TYPE IN ('END', 'ERROR') THEN LG.NEXT_TYPE END AS END_TYPE
     , CASE WHEN LG.NEXT_TYPE IN ('END', 'ERROR') THEN LG.NEXT_DESC END AS END_DESC
     , CASE WHEN LG.NEXT_TYPE IN ('END', 'ERROR') THEN LG.NEXT_DATE
            ELSE LEAST(NVL(LG.NEXT_DATE, LG.EVENT_DATE + 1), LG.EVENT_DATE + 1) END AS WIN_END
     , SUBSTR(LG.IN_PARA_DATA, 1, 200) AS IN_PARA_DATA
  FROM LG
     , PRM
 WHERE LG.LOG_TYPE = 'START'
   AND TRUNC(LG.EVENT_DATE) IN (PRM.P_DAY, PRM.B_DAY)
)
SELECT R.GRP
     , R.PROGRAM_NAME
     , R.RUN_NO
     , R.START_DATE
     , R.END_DATE
     , R.END_TYPE
     , ROUND((NVL(R.END_DATE, R.WIN_END) - R.START_DATE) * 1440, 1) AS ELAPSED_MIN
     , CASE WHEN (R.GRP = 'AFTER' OR R.END_TYPE = 'END') THEN 'Y' ELSE 'N' END AS USE_IN_COMPARE
     , R.IN_PARA_DATA
     , SUBSTR(R.END_DESC, 1, 200) AS END_DESC
  FROM RUNS R
 ORDER BY R.PROGRAM_NAME
        , R.START_DATE;

-- ==============================================================================================================
-- [E4] SHIP_PLAN_40 단계별 회차당 소요 비교(ASH)
-- 확인 : DIFF_SEC 가 큰 단계가 늘어난 곳. STEP_NAME = SP 안 /* n-n. */ 단계. CALL_OBJECT 가 FN_* 이면 함수 안 SQL
-- B_AWR, A_AWR = AWR 표본(10초) 합, B_MEM, A_MEM = 메모리 표본(1초) 합. 회차당 값은 AWR 값, AWR 이 아직 없으면 MEM 값으로 계산
-- STEP_NAME 이 비면 SQL 이 공유 풀에서 나간 문장. [E5] 의 SQL_ID, SQL_TEXT 로 봄
-- ==============================================================================================================
WITH PRM AS (SELECT TO_DATE('20261126', 'YYYYMMDD') AS P_DAY, TO_DATE('20261125', 'YYYYMMDD') AS B_DAY FROM DUAL)   /* P_DAY = 패키지 적용 뒤 실행일, B_DAY = 적용 전 기준일. 이 줄의 값만 바꿔 실행 */
, OBJ AS (
SELECT /*+ MATERIALIZE */ O.OBJECT_ID
     , O.OBJECT_NAME
  FROM ALL_OBJECTS O
 WHERE O.OWNER = 'SCM_MGR'
   AND O.OBJECT_TYPE IN ('PROCEDURE', 'FUNCTION', 'PACKAGE', 'PACKAGE BODY')
   AND O.OBJECT_NAME IN ('PR_SSP_ANL_SHIP_PLAN_40', 'PR_SSP_ANL_SHIP_PLAN_40_BALANCE', 'PR_SSP_MAIL_SHIP_REQ_MINUS_BALANCE_40'
                       , 'FN_GET_ITEM_OPERATION_GROUP', 'FN_GET_LOOKUP_VALUE', 'FN_GET_SCM_SITE_ID_PLANT', 'FN_GET_SSP_ANL_SHIP_FROZEN'
                       , 'FN_GET_SSP_ETA_DATE', 'FN_GET_SSP_SITE_INFO', 'FN_GET_SSP_SITE_INFO_EXCEPTION', 'FN_LIST_LOOKUP_VALUE'
                       , 'FN_CHAR_TO_DATE', 'FN_GET_ITEM_NICKNAME', 'FN_GET_SCM_SITE_DESCRIPTION', 'FN_GET_SSP_PROJECT_OWNER'
                       , 'FN_NEXT_DAY', 'FN_SCM_SPLIT', 'STRING_SPLIT', 'PR_SCP_SYS_LOG_BATCH'
                       , 'PR_SCM_SYS_LOG_BATCH', 'PKG_SEND_MAIL', 'SCM_ADM_SAVE_MAIL_SEND_BATCH_LOG', 'SCM_ADM_SMS_SEND_BATCH')
)
, STEP AS (
SELECT /*+ MATERIALIZE */ C.NAME
     , C.LINE AS FROM_LINE
     , NVL(LEAD(C.LINE) OVER (PARTITION BY C.NAME ORDER BY C.LINE) - 1, 999999) AS TO_LINE
     , RTRIM(LTRIM(C.TEXT), ' ' || CHR(9) || CHR(10) || CHR(13)) AS STEP_NAME
  FROM ALL_SOURCE C
 WHERE C.OWNER = 'SCM_MGR'
   AND C.NAME IN ('PR_SSP_ANL_SHIP_PLAN_40', 'PR_SSP_ANL_SHIP_PLAN_40_BALANCE', 'PR_SSP_MAIL_SHIP_REQ_MINUS_BALANCE_40')
   AND C.TYPE = 'PROCEDURE'
   AND REGEXP_LIKE(C.TEXT, '^\s*/\*\s*[0-9](-[0-9]+)*(\.|\s)')
)
, LG AS (
SELECT L.PROGRAM_NAME
     , L.EVENT_DATE
     , L.LOG_TYPE
     , L.IN_PARA_DATA
     , LEAD(L.EVENT_DATE)  OVER (PARTITION BY L.PROGRAM_NAME ORDER BY L.EVENT_DATE, DECODE(L.LOG_TYPE, 'START', 1, 'TXN', 2, 'ERROR', 3, 'END', 4)) AS NEXT_DATE
     , LEAD(L.LOG_TYPE)    OVER (PARTITION BY L.PROGRAM_NAME ORDER BY L.EVENT_DATE, DECODE(L.LOG_TYPE, 'START', 1, 'TXN', 2, 'ERROR', 3, 'END', 4)) AS NEXT_TYPE
     , LEAD(L.DESCRIPTION) OVER (PARTITION BY L.PROGRAM_NAME ORDER BY L.EVENT_DATE, DECODE(L.LOG_TYPE, 'START', 1, 'TXN', 2, 'ERROR', 3, 'END', 4)) AS NEXT_DESC
  FROM SCM_SYS_LOG_BATCH L
     , PRM
 WHERE L.PROGRAM_NAME IN ('PR_SSP_ANL_SHIP_PLAN_40', 'PR_SSP_ANL_SHIP_PLAN_40_BALANCE', 'PR_SSP_MAIL_SHIP_REQ_MINUS_BALANCE_40')
   AND L.LOG_TYPE IN ('START', 'END', 'ERROR')
   AND L.EVENT_DATE >= PRM.B_DAY
   AND L.EVENT_DATE <  PRM.P_DAY + 2
)
, RUNS AS (
SELECT /*+ MATERIALIZE */ LG.PROGRAM_NAME
     , CASE WHEN TRUNC(LG.EVENT_DATE) = PRM.P_DAY THEN 'AFTER' ELSE 'BEFORE' END AS GRP
     , TRUNC(LG.EVENT_DATE) AS RUN_DAY
     , ROW_NUMBER() OVER (PARTITION BY LG.PROGRAM_NAME, TRUNC(LG.EVENT_DATE) ORDER BY LG.EVENT_DATE) AS RUN_NO
     , LG.EVENT_DATE AS START_DATE
     , CASE WHEN LG.NEXT_TYPE IN ('END', 'ERROR') THEN LG.NEXT_DATE END AS END_DATE
     , CASE WHEN LG.NEXT_TYPE IN ('END', 'ERROR') THEN LG.NEXT_TYPE END AS END_TYPE
     , CASE WHEN LG.NEXT_TYPE IN ('END', 'ERROR') THEN LG.NEXT_DESC END AS END_DESC
     , CASE WHEN LG.NEXT_TYPE IN ('END', 'ERROR') THEN LG.NEXT_DATE
            ELSE LEAST(NVL(LG.NEXT_DATE, LG.EVENT_DATE + 1), LG.EVENT_DATE + 1) END AS WIN_END
     , SUBSTR(LG.IN_PARA_DATA, 1, 200) AS IN_PARA_DATA
  FROM LG
     , PRM
 WHERE LG.LOG_TYPE = 'START'
   AND TRUNC(LG.EVENT_DATE) IN (PRM.P_DAY, PRM.B_DAY)
)
, ASHD AS (
SELECT 'AWR' AS SRC
     , R.GRP
     , R.PROGRAM_NAME
     , R.RUN_NO
     , A.SQL_ID
     , A.SQL_PLAN_HASH_VALUE
     , A.SQL_PLAN_LINE_ID
     , A.SQL_PLAN_OPERATION || ' ' || A.SQL_PLAN_OPTIONS AS PLAN_OP
     , A.CURRENT_OBJ#
     , A.PLSQL_OBJECT_ID
     , A.IN_PARSE
     , A.IN_HARD_PARSE
     , NVL(A.EVENT, 'ON CPU') AS EVENT
     , 10 AS SEC
  FROM DBA_HIST_ACTIVE_SESS_HISTORY A
  JOIN RUNS R
    ON A.SAMPLE_TIME >= CAST(R.START_DATE AS TIMESTAMP)
   AND A.SAMPLE_TIME <  CAST(R.WIN_END AS TIMESTAMP) + INTERVAL '1' SECOND
  JOIN OBJ SP
    ON SP.OBJECT_ID   = A.PLSQL_ENTRY_OBJECT_ID
   AND SP.OBJECT_NAME = R.PROGRAM_NAME
 WHERE A.DBID = (SELECT D.DBID FROM V$DATABASE D)
   AND A.SNAP_ID IN (SELECT S.SNAP_ID FROM DBA_HIST_SNAPSHOT S, PRM P
                      WHERE S.END_INTERVAL_TIME >= CAST(P.B_DAY AS TIMESTAMP) AND S.BEGIN_INTERVAL_TIME < CAST(P.P_DAY + 2 AS TIMESTAMP))
   AND A.SAMPLE_TIME >= (SELECT CAST(P.B_DAY AS TIMESTAMP) FROM PRM P)
   AND A.SAMPLE_TIME <  (SELECT CAST(P.P_DAY + 2 AS TIMESTAMP) FROM PRM P)
   AND R.PROGRAM_NAME = 'PR_SSP_ANL_SHIP_PLAN_40'
   AND (R.GRP = 'AFTER' OR R.END_TYPE = 'END')
UNION ALL
SELECT 'MEM'
     , R.GRP
     , R.PROGRAM_NAME
     , R.RUN_NO
     , A.SQL_ID
     , A.SQL_PLAN_HASH_VALUE
     , A.SQL_PLAN_LINE_ID
     , A.SQL_PLAN_OPERATION || ' ' || A.SQL_PLAN_OPTIONS
     , A.CURRENT_OBJ#
     , A.PLSQL_OBJECT_ID
     , A.IN_PARSE
     , A.IN_HARD_PARSE
     , NVL(A.EVENT, 'ON CPU')
     , 1
  FROM GV$ACTIVE_SESSION_HISTORY A
  JOIN RUNS R
    ON A.SAMPLE_TIME >= CAST(R.START_DATE AS TIMESTAMP)
   AND A.SAMPLE_TIME <  CAST(R.WIN_END AS TIMESTAMP) + INTERVAL '1' SECOND
  JOIN OBJ SP
    ON SP.OBJECT_ID   = A.PLSQL_ENTRY_OBJECT_ID
   AND SP.OBJECT_NAME = R.PROGRAM_NAME
 WHERE A.SAMPLE_TIME >= (SELECT CAST(P.B_DAY AS TIMESTAMP) FROM PRM P)
   AND A.SAMPLE_TIME <  (SELECT CAST(P.P_DAY + 2 AS TIMESTAMP) FROM PRM P)
   AND R.PROGRAM_NAME = 'PR_SSP_ANL_SHIP_PLAN_40'
   AND (R.GRP = 'AFTER' OR R.END_TYPE = 'END')
)
, RC AS (
SELECT R.GRP
     , COUNT(*) AS RUN_CNT
  FROM RUNS R
 WHERE R.PROGRAM_NAME = 'PR_SSP_ANL_SHIP_PLAN_40'
   AND (R.GRP = 'AFTER' OR R.END_TYPE = 'END')
 GROUP BY R.GRP
)
, SQLSRC AS (
SELECT /*+ MATERIALIZE */ Q.SQL_ID
     , MAX(Q.PROGRAM_LINE#) AS SRC_LINE
     , MAX(SUBSTR(Q.SQL_TEXT, 1, 120)) AS SQL_TEXT
  FROM GV$SQL Q
 WHERE Q.PROGRAM_ID IN (SELECT OBJ.OBJECT_ID FROM OBJ)
 GROUP BY Q.SQL_ID
)
, X AS (
SELECT A.GRP
     , A.SRC
     , NVL((SELECT MAX(OBJ.OBJECT_NAME) FROM OBJ WHERE OBJ.OBJECT_ID = A.PLSQL_OBJECT_ID), '(SP 본문 SQL)') AS CALL_OBJECT
     , (SELECT MAX(ST.STEP_NAME) FROM STEP ST, SQLSRC SS
         WHERE ST.NAME = 'PR_SSP_ANL_SHIP_PLAN_40' AND SS.SQL_ID = A.SQL_ID AND SS.SRC_LINE BETWEEN ST.FROM_LINE AND ST.TO_LINE) AS STEP_NAME
     , A.SEC
  FROM ASHD A
)
SELECT Y.STEP_NAME
     , Y.CALL_OBJECT
     , ROUND(NVL(NULLIF(Y.B_AWR, 0), NVL(Y.B_MEM, 0)) / NULLIF((SELECT RC.RUN_CNT FROM RC WHERE RC.GRP = 'BEFORE'), 0), 1) AS BEFORE_SEC_PER_RUN
     , ROUND(NVL(NULLIF(Y.A_AWR, 0), NVL(Y.A_MEM, 0)) / NULLIF((SELECT RC.RUN_CNT FROM RC WHERE RC.GRP = 'AFTER'), 0), 1) AS AFTER_SEC_PER_RUN
     , ROUND(NVL(NULLIF(Y.A_AWR, 0), NVL(Y.A_MEM, 0)) / NULLIF((SELECT RC.RUN_CNT FROM RC WHERE RC.GRP = 'AFTER'), 0)
           - NVL(NVL(NULLIF(Y.B_AWR, 0), NVL(Y.B_MEM, 0)) / NULLIF((SELECT RC.RUN_CNT FROM RC WHERE RC.GRP = 'BEFORE'), 0), 0), 1) AS DIFF_SEC
     , Y.B_AWR
     , Y.B_MEM
     , Y.A_AWR
     , Y.A_MEM
     , (SELECT LISTAGG(RC.GRP || ' ' || RC.RUN_CNT, ', ') WITHIN GROUP (ORDER BY RC.GRP) FROM RC) AS RUN_CNT
  FROM (SELECT X.STEP_NAME
             , X.CALL_OBJECT
             , SUM(CASE WHEN X.GRP = 'BEFORE' AND X.SRC = 'AWR' THEN X.SEC END) AS B_AWR
     , SUM(CASE WHEN X.GRP = 'BEFORE' AND X.SRC = 'MEM' THEN X.SEC END) AS B_MEM
     , SUM(CASE WHEN X.GRP = 'AFTER'  AND X.SRC = 'AWR' THEN X.SEC END) AS A_AWR
     , SUM(CASE WHEN X.GRP = 'AFTER'  AND X.SRC = 'MEM' THEN X.SEC END) AS A_MEM
          FROM X
         GROUP BY X.STEP_NAME
                , X.CALL_OBJECT) Y
 ORDER BY DIFF_SEC DESC NULLS LAST;

