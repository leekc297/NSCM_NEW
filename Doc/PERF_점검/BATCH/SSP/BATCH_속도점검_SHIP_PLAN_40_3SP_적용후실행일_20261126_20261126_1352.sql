-- ==============================================================================================================
-- BATCHJOB 속도 점검 쿼리(실행일 회차 기준, 패키지 적용 뒤). 1차(11-25) 와 같은 블록 번호 · Oracle(클라우드 QA) · 조회만 수행
-- 대상 : PR_SSP_ANL_SHIP_PLAN_40, PR_SSP_ANL_SHIP_PLAN_40_BALANCE, PR_SSP_MAIL_SHIP_REQ_MINUS_BALANCE_40
-- 실행일 : 20261126. 쿼리마다 첫 줄 PRM 의 날짜만 바꾸면 다른 날 회차를 봄
-- 방식 : SCM_SYS_LOG_BATCH 의 실행일 START ~ END(또는 ERROR) 구간을 회차로 잡고, 그 구간의 ASH, SQL 모니터를 회차별로 묶음. END 가 없는 회차는 START + 1일까지
-- JOB : JOB_PR_SSP_PLN_SHIP_PLAN_40(HQ00 : BALANCE → CONFIRM_BATCH_40 → SHIP_PLAN_40 → MAIL) · _AZ(AZ00) · _C(NJ00, INVENTORY_RAW 포함)
-- 원문 기준 : 사내 ZIOUI1 2026-11-26 13:52 조회. 패키지 SSP_SHIP_PLAN_40_BATCH_PERF_CLOUD_20261126 적용본(사내 2026-11-26 11:26:43)
-- 실행 : DBeaver 에서 [C0] 먼저, 그 뒤 쿼리 하나씩(커서를 쿼리 안에 두고 Ctrl+Enter). 결과를 블록 번호와 함께 회신
-- 권한 : [C7] ~ [C12-1] 은 V$, DBA_HIST 조회 권한 필요. [C7] = Tuning Pack, [C8] ~ [C10] [C12-1] = Diagnostics Pack. ORA-00942 면 DBA 에 실행 요청
-- 같은 폴더 BATCH_속도점검_PR_SSP_ANL_SHIP_PLAN_40_외2_20261126_1011.sql = 지금 실행 중인 회차 점검용(L4 실행 중 세션, L6 잠금)
-- ==============================================================================================================

-- ==============================================================================================================
-- [C0] 현재 스키마 고정(파일 첫 쿼리)
-- 클라우드 접속 창의 현재 스키마가 SCM_MGR 가 아니면 이름만 쓴 테이블이 다른 스키마에서 찾아짐(2026-11-25 회신 : 로그인 SCM_MGR, 현재 스키마 FP_MGR)
-- 파일의 다른 쿼리보다 먼저 1회 실행. 새 접속 창을 열면 그 창에서도 다시 실행
-- ==============================================================================================================
ALTER SESSION SET CURRENT_SCHEMA = SCM_MGR;

-- ==============================================================================================================
-- [C1] 패키지 적용 상태(3개 SP, FP 뷰), 설정
-- 기대값 : 3개 SP VALID, MARK_DS2 1, BALANCE MARK_BALCUM 7. LAST_DDL_TIME 이 오늘 회차 START 보다 앞이어야 오늘 회차가 적용본으로 실행됨
-- FP_MGR.IF_SSP_FP_RELEASE_PLAN_V : 사내 원본 LAST_DDL 2026-11-17 17:17:28. SSP_FP_RELEASE_PLAN_V_PERF_CLOUD_20261125_1413 적용 시 그 뒤 일시
-- ==============================================================================================================
SELECT O.OWNER
     , O.OBJECT_NAME
     , O.OBJECT_TYPE
     , O.STATUS
     , O.LAST_DDL_TIME
     , (SELECT COUNT(*) FROM ALL_SOURCE S WHERE S.OWNER = O.OWNER AND S.NAME = O.OBJECT_NAME AND S.TYPE = O.OBJECT_TYPE) AS LINE_CNT
     , (SELECT COUNT(*) FROM ALL_SOURCE S WHERE S.OWNER = O.OWNER AND S.NAME = O.OBJECT_NAME AND S.TYPE = O.OBJECT_TYPE AND S.TEXT LIKE '%E20261126-DS2%') AS MARK_DS2
     , (SELECT COUNT(*) FROM ALL_SOURCE S WHERE S.OWNER = O.OWNER AND S.NAME = O.OBJECT_NAME AND S.TYPE = O.OBJECT_TYPE AND S.TEXT LIKE '%E20261126-BALCUM%') AS MARK_BALCUM
     , NULL AS MARK_FPRELV
  FROM ALL_OBJECTS O
 WHERE O.OWNER = 'SCM_MGR'
   AND O.OBJECT_TYPE = 'PROCEDURE'
   AND O.OBJECT_NAME IN ('PR_SSP_ANL_SHIP_PLAN_40', 'PR_SSP_ANL_SHIP_PLAN_40_BALANCE', 'PR_SSP_MAIL_SHIP_REQ_MINUS_BALANCE_40')
UNION ALL
SELECT O.OWNER
     , O.OBJECT_NAME
     , O.OBJECT_TYPE
     , O.STATUS
     , O.LAST_DDL_TIME
     , V.TEXT_LENGTH
     , NULL
     , NULL
     , CASE WHEN V.TEXT_VC LIKE '%E20261125-FPRELV%' THEN 1 ELSE 0 END
  FROM ALL_OBJECTS O
  JOIN ALL_VIEWS V
    ON V.OWNER     = O.OWNER
   AND V.VIEW_NAME = O.OBJECT_NAME
 WHERE O.OWNER = 'FP_MGR'
   AND O.OBJECT_NAME = 'IF_SSP_FP_RELEASE_PLAN_V'
   AND O.OBJECT_TYPE = 'VIEW'
UNION ALL
SELECT 'PARAM'
     , P.NAME
     , P.VALUE
     , P.ISDEFAULT
     , NULL
     , NULL
     , NULL
     , NULL
     , NULL
  FROM V$PARAMETER P
 WHERE P.NAME IN ('optimizer_dynamic_sampling', 'optimizer_adaptive_plans', 'optimizer_adaptive_statistics', 'optimizer_features_enable');

-- ==============================================================================================================
-- [C2] DB 시각 기준 확인
-- 로그 EVENT_DATE(SYSDATE)와 ASH SAMPLE_TIME 이 같은 시간대인지 확인. JOB 이력은 TZR 로 바꿔 대조함
-- ==============================================================================================================
SELECT TO_CHAR(SYSDATE, 'YYYY-MM-DD HH24:MI:SS') AS DB_SYSDATE
     , TO_CHAR(SYSTIMESTAMP, 'YYYY-MM-DD HH24:MI:SS TZR') AS DB_SYSTIMESTAMP
     , DBTIMEZONE
     , SESSIONTIMEZONE
  FROM DUAL;

-- ==============================================================================================================
-- [C3] 실행일 실행 로그 전체(3개 SP + 같은 JOB 앞뒤 단계)
-- 확인 : 회차마다 START 뒤 END 또는 ERROR. ERROR 면 LOG_MESSAGE, DESCRIPTION(오류 줄)
-- SHIP_PLAN_40 END 의 DESCRIPTION = [PLAN_ID][분:초]. 100분 이상이면 [분:초] 가 빈 값. MAIL 은 오류도 END 로 남김
-- ==============================================================================================================
WITH PRM AS (SELECT TO_DATE('20261126', 'YYYYMMDD') AS P_DAY FROM DUAL)   /* 실행일. 이 줄의 값만 바꿔 실행 */
SELECT L.EVENT_DATE
     , L.PROGRAM_NAME
     , L.LOG_TYPE
     , L.LOG_COUNT
     , SUBSTR(L.LOG_MESSAGE, 1, 200) AS LOG_MESSAGE
     , SUBSTR(L.DESCRIPTION, 1, 300) AS DESCRIPTION
     , L.SQL_ERR_CODE
     , SUBSTR(L.IN_PARA_DATA, 1, 200) AS IN_PARA_DATA
     , L.CREATED_BY
  FROM SCM_SYS_LOG_BATCH L
     , PRM
 WHERE L.PROGRAM_NAME IN ('PR_SSP_ANL_SHIP_PLAN_40', 'PR_SSP_ANL_SHIP_PLAN_40_BALANCE'
                         , 'PR_SSP_MAIL_SHIP_REQ_MINUS_BALANCE_40', 'PR_SSP_ANL_SHIP_CONFIRM_BATCH_40'
                         , 'PR_SSP_ANL_INVENTORY_RAW')
   AND L.EVENT_DATE >= PRM.P_DAY
   AND L.EVENT_DATE <  PRM.P_DAY + 2
 ORDER BY L.EVENT_DATE;

-- ==============================================================================================================
-- [C4] 실행일 회차별 소요 시간, JOB 매핑
-- 확인 : PROGRAM_NAME, RUN_NO 별 시작, 종료, 소요 분. JOB_NAME 으로 법인 구분(_40 = HQ00, _AZ = AZ00, _C = NJ00). JOB_NAME 이 비면 JOB 밖 직접 실행 회차
-- 이 RUN_NO 가 아래 [C7] ~ [C12-1] 의 회차 번호
-- ==============================================================================================================
WITH PRM AS (SELECT TO_DATE('20261126', 'YYYYMMDD') AS P_DAY FROM DUAL)   /* 실행일. 이 줄의 값만 바꿔 실행 */
, LG AS (
SELECT L.PROGRAM_NAME
     , L.EVENT_DATE
     , L.LOG_TYPE
     , LEAD(L.EVENT_DATE)  OVER (PARTITION BY L.PROGRAM_NAME ORDER BY L.EVENT_DATE, DECODE(L.LOG_TYPE, 'START', 1, 'TXN', 2, 'ERROR', 3, 'END', 4)) AS NEXT_DATE
     , LEAD(L.LOG_TYPE)    OVER (PARTITION BY L.PROGRAM_NAME ORDER BY L.EVENT_DATE, DECODE(L.LOG_TYPE, 'START', 1, 'TXN', 2, 'ERROR', 3, 'END', 4)) AS NEXT_TYPE
     , LEAD(L.DESCRIPTION) OVER (PARTITION BY L.PROGRAM_NAME ORDER BY L.EVENT_DATE, DECODE(L.LOG_TYPE, 'START', 1, 'TXN', 2, 'ERROR', 3, 'END', 4)) AS NEXT_DESC
  FROM SCM_SYS_LOG_BATCH L
     , PRM
 WHERE L.PROGRAM_NAME IN ('PR_SSP_ANL_SHIP_PLAN_40', 'PR_SSP_ANL_SHIP_PLAN_40_BALANCE', 'PR_SSP_MAIL_SHIP_REQ_MINUS_BALANCE_40')
   AND L.LOG_TYPE IN ('START', 'END', 'ERROR')
   AND L.EVENT_DATE >= PRM.P_DAY
   AND L.EVENT_DATE <  PRM.P_DAY + 2
)
, JR AS (
SELECT /*+ MATERIALIZE */ D.JOB_NAME
     , CAST(D.ACTUAL_START_DATE AT TIME ZONE TO_CHAR(SYSTIMESTAMP, 'TZR') AS DATE) AS JOB_START
     , CAST((D.ACTUAL_START_DATE + D.RUN_DURATION) AT TIME ZONE TO_CHAR(SYSTIMESTAMP, 'TZR') AS DATE) AS JOB_END
  FROM ALL_SCHEDULER_JOB_RUN_DETAILS D
     , PRM
 WHERE D.OWNER = 'SCM_MGR'
   AND D.JOB_NAME LIKE 'JOB\_PR\_SSP\_PLN\_SHIP\_PLAN\_40%' ESCAPE '\'
   AND D.LOG_DATE >= CAST(PRM.P_DAY - 1 AS TIMESTAMP)
)
, RUNS AS (
SELECT /*+ MATERIALIZE */ LG.PROGRAM_NAME
     , ROW_NUMBER() OVER (PARTITION BY LG.PROGRAM_NAME ORDER BY LG.EVENT_DATE) AS RUN_NO
     , LG.EVENT_DATE AS START_DATE
     , CASE WHEN LG.NEXT_TYPE IN ('END', 'ERROR') THEN LG.NEXT_DATE END AS END_DATE
     , CASE WHEN LG.NEXT_TYPE IN ('END', 'ERROR') THEN LG.NEXT_TYPE END AS END_TYPE
     , CASE WHEN LG.NEXT_TYPE IN ('END', 'ERROR') THEN LG.NEXT_DESC END AS END_DESC
     , (SELECT MAX(JR.JOB_NAME) FROM JR WHERE LG.EVENT_DATE BETWEEN JR.JOB_START AND JR.JOB_END) AS JOB_NAME
  FROM LG
     , PRM
 WHERE LG.LOG_TYPE = 'START'
   AND LG.EVENT_DATE < PRM.P_DAY + 1
)
SELECT R.PROGRAM_NAME
     , R.RUN_NO
     , R.JOB_NAME
     , CASE WHEN R.JOB_NAME LIKE '%\_AZ' ESCAPE '\' THEN 'AZ00'
            WHEN R.JOB_NAME LIKE '%\_C' ESCAPE '\' THEN 'NJ00'
            WHEN R.JOB_NAME IS NOT NULL THEN 'HQ00' END AS COMPANY_ID
     , R.START_DATE
     , R.END_DATE
     , R.END_TYPE
     , ROUND((NVL(R.END_DATE, SYSDATE) - R.START_DATE) * 1440, 1) AS ELAPSED_MIN
     , SUBSTR(R.END_DESC, 1, 200) AS END_DESC
  FROM RUNS R
 ORDER BY R.START_DATE;

