-- SCM_MGR.SCM_ADM_DEPT_CHANGED_V source

CREATE OR REPLACE FORCE EDITIONABLE VIEW "SCM_MGR"."SCM_ADM_DEPT_CHANGED_V" ("USER_ID", "USER_NAME", "GROUP_ID", "DIVISION_ID", "APPROVAL_RESULT", "APPROVAL_ID", "APPROVAL_NAME", "APPROVED_DATE", "REMAIN_DAYS", "ELAPSED_DAYS", "ACTIVE_FLG") AS 
  SELECT SU.USER_ID
	     , MAX(SU.USER_NAME) AS USER_NAME
	     , GRP.USER_GR_ID AS GROUP_ID
	     , AUTH.UNIT_ID   AS DIVISION_ID
	     , 'APPROVED'     AS APPROVAL_RESULT
	     , MAX(AUTH.LAST_UPDATED_BY) AS APPROVAL_ID
	     , MAX(SU2.USER_NAME)        AS APPROVAL_NAME
	     , TO_CHAR(MAX(AUTH.LAST_UPDATE_DATE), 'YYYY-MM-DD HH24:MI:SS') AS APPROVED_DATE
	     , TRUNC(MAX(TO_DATE(SU.ATTRIBUTE9, 'YYYYMMDD')) + 15) - TRUNC(SYSDATE) AS REMAIN_DAYS
	     , TRUNC(SYSDATE) - TRUNC(MAX(TO_DATE(SU.ATTRIBUTE9, 'YYYYMMDD'))) AS ELAPSED_DAYS
	     , MAX(SU.ACTIVE_FLAG) AS ACTIVE_FLG
	  FROM SCM_ADM_USER_M U
	       JOIN SCM_MST_SSO_USER_INFO SU
	         ON U.USER_ID = SU.USER_ID
           JOIN SCM_MGR.SCM_ADM_USER_GR_MPG_M          GRP   -- 그룹-사용자 매핑
             ON U.USER_ID = GRP.USER_ID
           JOIN SCM_MGR.SCM_ADM_USER_GR_UNIT_AUTH_MPG_M  AUTH  -- 그룹-조직 권한
             ON AUTH.USER_GR_ID = GRP.USER_GR_ID
            AND AUTH.USER_ID    = GRP.USER_ID
	       LEFT OUTER JOIN SCM_MST_SSO_USER_INFO SU2
	         ON AUTH.LAST_UPDATED_BY = SU2.USER_ID
	       JOIN SCM_ADM_LOOKUP_MASTER_DETAIL LK
             ON GRP.USER_GR_ID = LK.SEGMENT1
            AND LK.LOOKUP_TYPE = 'DEPT_CHANGED_AUTH_DELETE'
           --AND LK.SEGMENT2    = ''  --SCM, 조건 제거. SCM,FP 권한 체계 통합에 따른 조건 제거
            AND LK.VALID_YN    = 'Y'
	 WHERE 1 = 1
	   AND SU.DEPT_ID <> CASE WHEN NVL(SU.ATTRIBUTE10, '') = '' OR SU.ATTRIBUTE10 IS NULL THEN SU.DEPT_ID ELSE SU.ATTRIBUTE10 END
	   AND REGEXP_LIKE(SU.DEPT_ID, '^[0-9]+$')
	   AND AUTH.LAST_UPDATE_DATE < TO_DATE(SU.ATTRIBUTE9, 'YYYYMMDD')
	   AND SU.ACTIVE_FLAG != 'D'
	   AND U.USE_YN        = 'Y'
       AND GRP.USE_YN      = 'Y'
       AND AUTH.USE_YN     = 'Y'
       AND AUTH.UNIT_TP_CD = 'D'
	 GROUP BY SU.USER_ID, GRP.USER_GR_ID, AUTH.UNIT_ID
	 /* Next SCM 에서는 FP 권한 체계를 SCM과 통합하여 주석 처리함
     UNION ALL
	SELECT SU.USER_ID
	     , SU.USER_NAME
	     , UG.GROUPID AS GROUP_ID
	     , UGA.CODE AS DIVISION_ID
	     , 'APPROVED' AS APPROVAL_RESULT
	     , UGA.UPDATEUSERID AS APPROVAL_ID
	     , SU2.USER_NAME AS APPROVAL_NAME
	     , TO_CHAR(FP.UPDATEDATETIME, 'YYYY-MM-DD HH24:MI:SS') AS APPROVED_DATE
	     , TRUNC(SU.ATTRIBUTE9 + 15) - TRUNC(SYSDATE) AS REMAIN_DAYS
	     , TRUNC(SYSDATE) - TRUNC(SU.ATTRIBUTE9) AS ELAPSED_DAYS
	     , SU.ACTIVE_FLAG
	  FROM SCM_ADM_USER_M U
	       JOIN SCM_MST_SSO_USER_INFO SU
	    ON U.USER_ID = SU.USER_ID
	       JOIN SCM_ADM_USER_GR_M UG
	    ON U.USER_ID = UG.USERID
	       JOIN TB_FX_USERGROUPAUTHEXTENTION UGA
	    ON UG.USERID = UGA.USERID AND UG.GROUPID = UGA.GROUPID
	       LEFT OUTER JOIN SCM_MST_SSO_USER_INFO SU2
	    ON UGA.UPDATEUSERID = SU2.USER_ID
	       JOIN SCM_ADM_LOOKUP_MASTER_DETAIL LK
	    ON UG.GROUPID = LK.SEGMENT1
	   AND LK.LOOKUP_TYPE = 'DEPT_CHANGED_AUTH_DELETE'
	   AND LK.SEGMENT2    = 'Y'  --FP
	   AND LK.VALID_YN    = 'Y'
	       JOIN (SELECT UIR.USER_ID AS USERID
	                  , CASE WHEN UIR.SAVE_FLAG = 'Y' THEN 'FP Planner' ELSE 'FP Viewer' END AS GroupID
	                  , RIR.DIVISION_ID AS Code
	                  , MAX(NVL(UIR.UPDATE_DTTM, UIR.INSERT_DTTM)) AS UPDATEDATETIME
	               FROM TH_UIS_USER_INSTANCE_RELATE_SN UIR
	                    JOIN TH_UIS_ROLE_INSTANCE_SN RI
	                 ON UIR.ROLE_ID     = RI.ROLE_ID
	                    JOIN TH_UIS_ROLE_INSTANCE_RELATE_SN RIR
	                 ON RIR.ROLE_ID     = RI.ROLE_ID
	              WHERE 1 = 1
	                AND UIR.USE_AT_FLAG = 'Y'
	                AND RIR.USE_AT_FLAG = 'Y'
	                AND UIR.SAVE_FLAG   = 'Y' --FP Planner
	              GROUP BY
	                    UIR.USER_ID, UIR.SAVE_FLAG, RIR.DIVISION_ID
	            ) FP
	    ON UGA.USERID  = FP.USERID
	   AND UGA.GROUPID = FP.GROUPID
	   AND UGA.CODE    = FP.CODE
	 WHERE 1 = 1
	   AND SU.DEPT_ID <> CASE WHEN NVL(SU.ATTRIBUTE10, '') = '' OR SU.ATTRIBUTE10 IS NULL THEN SU.DEPT_ID ELSE SU.ATTRIBUTE10 END
	   AND REGEXP_LIKE(SU.DEPT_ID, '^[0-9]+$')
	   AND FP.UPDATEDATETIME < TO_DATE(SU.ATTRIBUTE9, 'YYYYMMDD')
	   AND SU.ACTIVE_FLAG != 'D'
	   AND U.USEYN         = 'Y'
	   AND UG.USEYN        = 'Y'*/
 --    ) AS V
 --WHERE
