--==============================================================================
-- 68_SYS0013_remaining_PROC_M_resync.sql
--
-- 목적: SYS0013 의 나머지 GET SP 3종 PROC_M 정정 (columns/parameters/history)
--       + EXECUTE SP 1종 (history insert)
--
-- 사고 위험:
--   각 GET SP 실제 sig 와 PROC_M 등록 mismatch 시 PLS-00306 발생 가능.
--   사용자가 query row 클릭 시 columns/parameters/history tab 호출 → 오류 가능.
--
-- 매핑:
--   DMF0027_GET_DM_TMP_DYNAMIC_QUERY_COLUMNS (1 IN + 2 OUT):
--     P_DQ_ID → dqId / O_RC1 → o_rc1 / O_RESULT_CURSOR
--   DMF0027_GET_DM_TMP_DYNAMIC_QUERY_PARAMETERS (1 IN + 2 OUT):
--     P_DQ_ID → dqId / O_RC1 → o_rc1 / O_RESULT_CURSOR
--   P_SCM0005_GET_HISTORY (1 IN + 1 OUT):
--     P_QUERYID → queryId / O_RC1 → o_rc1
--   PR_DM_ADM_DQ_EXECUTE_HIST (4 IN + 0 OUT) — INSERT only:
--     P_DQ_ID → dqId / P_DQ_TEXT → dqText / P_CREATED_BY → sesUserId / P_LAST_UPDATED_BY → sesUserId
--     ⚠️ same param name 'sesUserId' 2회 — MyBatis position binding 가능 (PROC_M COL_NM 중복 안 됨)
--     → P_LAST_UPDATED_BY 는 다른 키 'updatedBy' 사용 (FE 가 sesUserId 같은 값 전달 필요)
--
-- 작성: 2026-06-09
--==============================================================================
SET DEFINE OFF
SET SERVEROUTPUT ON
SET FEEDBACK ON
WHENEVER SQLERROR EXIT FAILURE

PROMPT === DELETE 기존 PROC_M (4 SP) ===
DELETE FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM IN (
   'DMF0027_GET_DM_TMP_DYNAMIC_QUERY_COLUMNS',
   'DMF0027_GET_DM_TMP_DYNAMIC_QUERY_PARAMETERS',
   'P_SCM0005_GET_HISTORY',
   'PR_DM_ADM_DQ_EXECUTE_HIST'
 );

PROMPT === INSERT 정정 PROC_M ===
INSERT INTO SCM_MGR.SCM_ADM_PROC_M (PROC_NM, COL_NM, COL_TP_CD, DATA_TP_CD, SORT_ORD, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT NEW.PROC_NM, NEW.COL_NM, NEW.COL_TP_CD, NEW.DATA_TP_CD, NEW.SORT_ORD, NEW.CREATED_BY, NEW.CREATION_DATE, NEW.LAST_UPDATED_BY, NEW.LAST_UPDATE_DATE
  FROM (
    -- COLUMNS (1 IN + 2 OUT)
    SELECT 'DMF0027_GET_DM_TMP_DYNAMIC_QUERY_COLUMNS' AS PROC_NM, 'dqId' AS COL_NM, 'IN'  AS COL_TP_CD, 'VARCHAR'     AS DATA_TP_CD, 1 AS SORT_ORD, 'system' AS CREATED_BY, SYSDATE AS CREATION_DATE, 'system' AS LAST_UPDATED_BY, SYSDATE AS LAST_UPDATE_DATE FROM DUAL UNION ALL
    SELECT 'DMF0027_GET_DM_TMP_DYNAMIC_QUERY_COLUMNS', 'o_rc1',           'OUT', 'CURSOR',      2, 'system', SYSDATE, 'system', SYSDATE FROM DUAL UNION ALL
    SELECT 'DMF0027_GET_DM_TMP_DYNAMIC_QUERY_COLUMNS', 'O_RESULT_CURSOR', 'OUT', 'PROC_RESULT', 3, 'system', SYSDATE, 'system', SYSDATE FROM DUAL UNION ALL
    -- PARAMETERS (1 IN + 2 OUT)
    SELECT 'DMF0027_GET_DM_TMP_DYNAMIC_QUERY_PARAMETERS', 'dqId',            'IN',  'VARCHAR',     1, 'system', SYSDATE, 'system', SYSDATE FROM DUAL UNION ALL
    SELECT 'DMF0027_GET_DM_TMP_DYNAMIC_QUERY_PARAMETERS', 'o_rc1',           'OUT', 'CURSOR',      2, 'system', SYSDATE, 'system', SYSDATE FROM DUAL UNION ALL
    SELECT 'DMF0027_GET_DM_TMP_DYNAMIC_QUERY_PARAMETERS', 'O_RESULT_CURSOR', 'OUT', 'PROC_RESULT', 3, 'system', SYSDATE, 'system', SYSDATE FROM DUAL UNION ALL
    -- HISTORY (1 IN + 1 OUT)
    SELECT 'P_SCM0005_GET_HISTORY', 'queryId', 'IN',  'VARCHAR',     1, 'system', SYSDATE, 'system', SYSDATE FROM DUAL UNION ALL
    SELECT 'P_SCM0005_GET_HISTORY', 'o_rc1',   'OUT', 'CURSOR',      2, 'system', SYSDATE, 'system', SYSDATE FROM DUAL UNION ALL
    -- EXECUTE_HIST (4 IN + 0 OUT — INSERT history record)
    SELECT 'PR_DM_ADM_DQ_EXECUTE_HIST', 'dqId',      'IN', 'VARCHAR', 1, 'system', SYSDATE, 'system', SYSDATE FROM DUAL UNION ALL
    SELECT 'PR_DM_ADM_DQ_EXECUTE_HIST', 'dqText',    'IN', 'VARCHAR', 2, 'system', SYSDATE, 'system', SYSDATE FROM DUAL UNION ALL
    SELECT 'PR_DM_ADM_DQ_EXECUTE_HIST', 'sesUserId', 'IN', 'VARCHAR', 3, 'system', SYSDATE, 'system', SYSDATE FROM DUAL UNION ALL
    SELECT 'PR_DM_ADM_DQ_EXECUTE_HIST', 'updatedBy', 'IN', 'VARCHAR', 4, 'system', SYSDATE, 'system', SYSDATE FROM DUAL
  ) NEW;

PROMPT === VERIFY ===
SELECT PROC_NM, COUNT(*) AS PARAM_CNT
  FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM IN (
   'DMF0027_GET_DM_TMP_DYNAMIC_QUERY_COLUMNS',
   'DMF0027_GET_DM_TMP_DYNAMIC_QUERY_PARAMETERS',
   'P_SCM0005_GET_HISTORY',
   'PR_DM_ADM_DQ_EXECUTE_HIST'
 )
 GROUP BY PROC_NM
 ORDER BY PROC_NM;

COMMIT;
PROMPT === COMPLETE ===
EXIT;
