--==============================================================================
-- 85_axis3a_dmf0020_dmf0043_proc_m_fix.sql
-- AXIS 3-A SP1+SP2 fix — BE auto-fill key 확장 (createdBy/lastUpdatedBy 추가) 후
-- PROC_M 메타에 누락 row INSERT
--
-- BE 변경 (NDaoInterface.java:430-438):
--   기존: sesUserId / sesLangCd 만 채움
--   변경: sesUserId / sesLangCd / createdBy / lastUpdatedBy 채움
--         (createdBy + lastUpdatedBy 둘 다 sesUserId 와 동일 값)
--
-- SP1 — DMF0020_SAVE_DM_MST_EXCHANGE_RATE_ALL (PROC_M=8 vs SP=9):
--   SP 8번째 인자 P_LAST_UPDATED_BY (VARCHAR2 IN) 누락 → COL_NM='lastUpdatedBy' position=8 추가
--   기존 9번 'O_RESULT_CURSOR' 는 그대로 (POSITION 안 바뀌어도 됨)
--   실제 SORT_ORD 정합: P_CREATED_BY (pos 7) = 'sesUserId' (기존 등록), P_LAST_UPDATED_BY (pos 8) = 'lastUpdatedBy' (신규), O_RESULT_CURSOR (pos 9, 기존 SORT_ORD=8 → 9 로 재정렬)
--
-- SP2 — DMF0043_GET_MAIN_SPREAD_TITLE (PROC_M=7 vs SP=8):
--   SP 3번째 인자 P_CREATED_BY (VARCHAR2 IN) 누락 → COL_NM='createdBy' position=3 추가
--   기존 4~7 (sesUserId/mnuId/o_rc1~3) SORT_ORD shift 4~7 → 5~8 (단 BE 는 positional binding 이라 SORT_ORD 가 SP POSITION 과 일치 의무)
--==============================================================================
SET DEFINE OFF
SET SERVEROUTPUT ON
SET FEEDBACK ON
WHENEVER SQLERROR EXIT FAILURE

PROMPT === BEFORE SP1 (DMF0020_SAVE_DM_MST_EXCHANGE_RATE_ALL) ===
SELECT SORT_ORD, COL_NM, COL_TP_CD, DATA_TP_CD FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM='DMF0020_SAVE_DM_MST_EXCHANGE_RATE_ALL' ORDER BY SORT_ORD;

PROMPT === SP1 fix: O_RESULT_CURSOR SORT_ORD 8 -> 9, lastUpdatedBy SORT_ORD 8 추가 ===
-- O_RESULT_CURSOR 를 일시 다른 SORT_ORD 로 이동 (PK 충돌 회피)
UPDATE SCM_MGR.SCM_ADM_PROC_M SET SORT_ORD = 99
 WHERE PROC_NM='DMF0020_SAVE_DM_MST_EXCHANGE_RATE_ALL' AND COL_NM='O_RESULT_CURSOR';

-- lastUpdatedBy SORT_ORD=8 INSERT (NOT EXISTS 멱등)
INSERT INTO SCM_MGR.SCM_ADM_PROC_M
  (PROC_NM, COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'DMF0020_SAVE_DM_MST_EXCHANGE_RATE_ALL', 'lastUpdatedBy', 'VARCHAR2', 'IN', 8, 'SYSTEM', SYSDATE, 'SYSTEM', SYSDATE FROM DUAL
 WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_PROC_M
                    WHERE PROC_NM='DMF0020_SAVE_DM_MST_EXCHANGE_RATE_ALL' AND COL_NM='lastUpdatedBy' AND COL_TP_CD='IN');

-- O_RESULT_CURSOR SORT_ORD 99 -> 9
UPDATE SCM_MGR.SCM_ADM_PROC_M SET SORT_ORD = 9
 WHERE PROC_NM='DMF0020_SAVE_DM_MST_EXCHANGE_RATE_ALL' AND COL_NM='O_RESULT_CURSOR' AND SORT_ORD=99;

COMMIT;

PROMPT === AFTER SP1 ===
SELECT SORT_ORD, COL_NM, COL_TP_CD, DATA_TP_CD FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM='DMF0020_SAVE_DM_MST_EXCHANGE_RATE_ALL' ORDER BY SORT_ORD;

PROMPT === BEFORE SP2 (DMF0043_GET_MAIN_SPREAD_TITLE) ===
SELECT SORT_ORD, COL_NM, COL_TP_CD, DATA_TP_CD FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM='DMF0043_GET_MAIN_SPREAD_TITLE' ORDER BY SORT_ORD;

PROMPT === SP2 fix: sesUserId/mnuId/o_rc1~3 SORT_ORD 3~7 -> 4~8 shift, createdBy SORT_ORD 3 추가 ===
-- shift up: 기존 3~7 일시 99~103 (PK 충돌 회피)
UPDATE SCM_MGR.SCM_ADM_PROC_M SET SORT_ORD = SORT_ORD + 96
 WHERE PROC_NM='DMF0043_GET_MAIN_SPREAD_TITLE' AND SORT_ORD BETWEEN 3 AND 7;

-- createdBy SORT_ORD=3 INSERT (NOT EXISTS 멱등)
INSERT INTO SCM_MGR.SCM_ADM_PROC_M
  (PROC_NM, COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'DMF0043_GET_MAIN_SPREAD_TITLE', 'createdBy', 'VARCHAR2', 'IN', 3, 'SYSTEM', SYSDATE, 'SYSTEM', SYSDATE FROM DUAL
 WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_PROC_M
                    WHERE PROC_NM='DMF0043_GET_MAIN_SPREAD_TITLE' AND COL_NM='createdBy' AND COL_TP_CD='IN');

-- shift back down: 99~103 -> 4~8
UPDATE SCM_MGR.SCM_ADM_PROC_M SET SORT_ORD = SORT_ORD - 95
 WHERE PROC_NM='DMF0043_GET_MAIN_SPREAD_TITLE' AND SORT_ORD BETWEEN 99 AND 103;

COMMIT;

PROMPT === AFTER SP2 ===
SELECT SORT_ORD, COL_NM, COL_TP_CD, DATA_TP_CD FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM='DMF0043_GET_MAIN_SPREAD_TITLE' ORDER BY SORT_ORD;

PROMPT === VERIFY AXIS 3-A 2 SP signature match ===
SELECT P.PROC_NM,
       COUNT(*) AS PROC_M_ROWS,
       NVL((SELECT COUNT(*) FROM ALL_ARGUMENTS A
              WHERE A.OWNER='SCM_MGR' AND A.OBJECT_NAME = P.PROC_NM AND A.PACKAGE_NAME IS NULL), 0) AS SP_ARGS
  FROM SCM_MGR.SCM_ADM_PROC_M P
 WHERE P.PROC_NM IN ('DMF0020_SAVE_DM_MST_EXCHANGE_RATE_ALL', 'DMF0043_GET_MAIN_SPREAD_TITLE')
 GROUP BY P.PROC_NM;
EXIT;
