SELECT DISTINCT B.DEPT_ID AS CODE, B.DEPT_NAME_KO AS NAME
  FROM (SELECT A.DIVISION_ID, A.SCM_SITE_ID
             , (SELECT MAX(SA.DEPT_ID) FROM SCM_MST_SITE_ITEM SA, SCM_MST_SSO_DEPT_INFO SD
                 WHERE SA.DIVISION_ID = A.DIVISION_ID AND SA.SCM_SITE_ID = A.SCM_SITE_ID AND SA.DEPT_ID = SD.DEPT_ID) AS DEPT_ID
          FROM SCM_MST_SITE A
         WHERE A.SITE_TYPE = 'SALES'
           AND (:B1 = 'ALL' OR A.DIVISION_ID IN (SELECT TOKEN FROM TABLE(FN_STRING_SPLIT(:B1, ','))))) IA
     , SCM_MST_SSO_DEPT_INFO B
 WHERE IA.DEPT_ID = B.DEPT_ID
