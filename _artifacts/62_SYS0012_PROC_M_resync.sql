SET DEFINE OFF
SET SERVEROUTPUT ON
SET FEEDBACK ON
WHENEVER SQLERROR EXIT FAILURE

PROMPT === DELETE 기존 APPROVE/REJECT PROC_M ===
DELETE FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM IN ('P_SYS0012_APPROVE','P_SYS0012_REJECT');

PROMPT === INSERT 정정 PROC_M ===
INSERT INTO SCM_MGR.SCM_ADM_PROC_M (PROC_NM, COL_NM, COL_TP_CD, DATA_TP_CD, SORT_ORD, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT NEW.PROC_NM, NEW.COL_NM, NEW.COL_TP_CD, NEW.DATA_TP_CD, NEW.SORT_ORD, NEW.CREATED_BY, NEW.CREATION_DATE, NEW.LAST_UPDATED_BY, NEW.LAST_UPDATE_DATE
  FROM (
  SELECT 'P_SYS0012_APPROVE' AS PROC_NM, 'sesUserId' AS COL_NM,'IN' AS COL_TP_CD,'VARCHAR' AS DATA_TP_CD, 1 AS SORT_ORD,'system' AS CREATED_BY,SYSDATE AS CREATION_DATE,'system' AS LAST_UPDATED_BY,SYSDATE AS LAST_UPDATE_DATE FROM DUAL UNION ALL
  SELECT 'P_SYS0012_APPROVE','data',          'IN', 'CLOB',        2,'system',SYSDATE,'system',SYSDATE FROM DUAL UNION ALL
  SELECT 'P_SYS0012_APPROVE','O_RESULT_CURSOR','OUT','PROC_RESULT', 3,'system',SYSDATE,'system',SYSDATE FROM DUAL UNION ALL
  SELECT 'P_SYS0012_REJECT', 'sesUserId',      'IN', 'VARCHAR',     1,'system',SYSDATE,'system',SYSDATE FROM DUAL UNION ALL
  SELECT 'P_SYS0012_REJECT', 'data',           'IN', 'CLOB',        2,'system',SYSDATE,'system',SYSDATE FROM DUAL UNION ALL
  SELECT 'P_SYS0012_REJECT', 'O_RESULT_CURSOR','OUT','PROC_RESULT', 3,'system',SYSDATE,'system',SYSDATE FROM DUAL
) NEW;

PROMPT === VERIFY ===
SELECT PROC_NM, COL_NM, COL_TP_CD, DATA_TP_CD, SORT_ORD
  FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM IN ('P_SYS0012_APPROVE','P_SYS0012_REJECT')
 ORDER BY PROC_NM, SORT_ORD;

COMMIT;
EXIT;
