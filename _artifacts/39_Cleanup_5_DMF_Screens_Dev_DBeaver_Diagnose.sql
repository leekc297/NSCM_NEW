-- 1. 5 화면 메뉴 row (삭제 전: 5 / 후: 0)
SELECT MNU_ID, UPPR_MNU_ID, MNU_URL, MNU_MSG_ID, USE_YN
  FROM SCM_MGR.SCM_ADM_MNU_M
 WHERE MNU_ID IN ('DMF0008','DMF0020','DMF0043','DMF0043_01','DMF0072');

-- 2. 메타 footprint 카운트 (삭제 전: 331 / 후: 0)
WITH M AS (
  SELECT 'DMF0008' MNU FROM DUAL UNION ALL SELECT 'DMF0020' FROM DUAL
  UNION ALL SELECT 'DMF0043' FROM DUAL UNION ALL SELECT 'DMF0043_01' FROM DUAL
  UNION ALL SELECT 'DMF0072' FROM DUAL
)
SELECT 'MNU_M' TBL, COUNT(*) CNT FROM SCM_MGR.SCM_ADM_MNU_M WHERE MNU_ID IN (SELECT MNU FROM M)
UNION ALL SELECT 'USER_GR_MNU_MPG', COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_MPG_M WHERE MNU_ID IN (SELECT MNU FROM M)
UNION ALL SELECT 'USER_GR_MNU_BTN_MPG', COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE MNU_ID IN (SELECT MNU FROM M)
UNION ALL SELECT 'MNU_BTN_MPG', COUNT(*) FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID IN (SELECT MNU FROM M)
UNION ALL SELECT 'API_M (간접)', COUNT(*) FROM SCM_MGR.SCM_ADM_API_M WHERE API_ID IN (SELECT API_ID FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID IN (SELECT MNU FROM M))
UNION ALL SELECT 'PROC_M', COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M WHERE REGEXP_LIKE(PROC_NM, '^PKG_DMF(0008|0020|0043|0072)\.');

-- 3. Oracle PKG body 상태 (보존되어야 함)
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS
  FROM USER_OBJECTS
 WHERE OBJECT_NAME IN ('PKG_DMF0043','PKG_DMF0072','PKG_DMF0020','PKG_DMF0008')
 ORDER BY OBJECT_NAME, OBJECT_TYPE;

-- 4. Master 진짜 트리 (5 화면 삭제 후 13 row 예상 — 16 자식 중 5 삭제 + Master + Demand_Master = 18 → 13)
SELECT LPAD(' ', (MNU_LV_NO-1)*2) || MNU_ID AS PATH,
       UPPR_MNU_ID, MNU_LV_NO, MNU_URL, USE_YN
  FROM SCM_MGR.SCM_ADM_MNU_M
 START WITH MNU_ID = 'Master'
 CONNECT BY PRIOR MNU_ID = UPPR_MNU_ID
 ORDER SIBLINGS BY MNU_ID;
