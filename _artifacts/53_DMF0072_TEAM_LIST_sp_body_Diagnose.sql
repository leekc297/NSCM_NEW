-- D1: 현재 TEAM_LIST body 소스 전체
SELECT 'D1: L' || LINE AS LN, TEXT
  FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='DMF0072_GET_TEAM_LIST'
 ORDER BY LINE;

-- D2: SCM_MST_SITE 의 SITE_TYPE='SALES' + DEPT_ID NOT NULL 카운트 + DIVISION 별
SELECT 'D2: SITE SALES + DEPT_ID NOT NULL by division (top 10)' AS K,
       DIVISION_ID, COUNT(*) AS CNT
  FROM SCM_MGR.SCM_MST_SITE
 WHERE SITE_TYPE='SALES' AND DEPT_ID IS NOT NULL AND DEPT_ID <> '-'
 GROUP BY DIVISION_ID
 ORDER BY 3 DESC
 FETCH FIRST 10 ROWS ONLY;

-- D3: As-Is logic 시뮬레이션 결과 (Division 별 expected row 수)
SELECT 'D3: TEAM by DIV expected (top 10)' AS K,
       A.DIVISION_ID, COUNT(DISTINCT B.DEPT_ID) AS EXPECTED_CNT
  FROM SCM_MGR.SCM_MST_SITE A,
       SCM_MGR.SCM_MST_SSO_DEPT_INFO B
 WHERE A.SITE_TYPE='SALES' AND A.DEPT_ID=B.DEPT_ID
 GROUP BY A.DIVISION_ID
 ORDER BY 3 DESC
 FETCH FIRST 10 ROWS ONLY;

-- D4: DIV=40 의 DEPT_ID 분포 (확인 — '-' 단일)
SELECT 'D4: DIV=40 DEPT_ID distinct' AS K,
       NVL(DEPT_ID, '<NULL>') AS DEPT_ID, COUNT(*) AS CNT
  FROM SCM_MGR.SCM_MST_SITE
 WHERE SITE_TYPE='SALES' AND DIVISION_ID='40'
 GROUP BY DEPT_ID;

-- D5: DIV=81 (전지) sample dept name 확인
SELECT 'D5: DIV=81 sample TEAM' AS K,
       DEPT_ID, DEPT_NAME_KO
  FROM (SELECT DISTINCT B.DEPT_ID, B.DEPT_NAME_KO
          FROM SCM_MGR.SCM_MST_SITE A, SCM_MGR.SCM_MST_SSO_DEPT_INFO B
         WHERE A.SITE_TYPE='SALES' AND A.DEPT_ID=B.DEPT_ID AND A.DIVISION_ID='81'
         ORDER BY 1)
 WHERE ROWNUM <= 10;
