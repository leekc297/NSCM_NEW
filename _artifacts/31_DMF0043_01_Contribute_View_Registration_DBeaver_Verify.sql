--==============================================================================
-- DMF0043_01_Contribute_View — 메타 등록 검증 (DBeaver 단일 SELECT UNION ALL)
--==============================================================================

SELECT 'BLOCK 1 MSG_M (MNU 3 + API 4×3=12 = 15)' BLOCK_NAME,
       (SELECT COUNT(*) FROM SCM_ADM_MSG_M WHERE MSG_ID IN (
          'MNU_DMF0043_01',
          'MSG_API_DMF0043_VIEW_SEARCH','MSG_API_DMF0043_VIEW_TITLE_SEARCH','MSG_API_DMF0043_VIEW_VERSION_SEARCH')) ACTUAL,
       15 EXPECT_MIN, 'rows' UNIT FROM DUAL
UNION ALL
SELECT 'BLOCK 2 MNU_M (DMF0043_01)',
       (SELECT COUNT(*) FROM SCM_ADM_MNU_M WHERE MNU_ID = 'DMF0043_01'),
       1, 'rows' FROM DUAL
UNION ALL
SELECT 'BLOCK 4 API_M (DMF0043_01_* 4)',
       (SELECT COUNT(*) FROM SCM_ADM_API_M WHERE API_ID LIKE 'DMF0043_01_%'),
       4, 'rows' FROM DUAL
UNION ALL
SELECT 'BLOCK 5 MNU_BTN_MPG_M (DMF0043_01 routing 8 = 4 own + 4 shared)',
       (SELECT COUNT(*) FROM SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID = 'DMF0043_01'),
       8, 'rows' FROM DUAL
UNION ALL
SELECT 'BLOCK 6 SHEET_COLUMNS (DMF0043_01 main 8 + version 5 = 13)',
       (SELECT COUNT(*) FROM SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID = 'DMF0043_01'),
       13, 'rows' FROM DUAL
UNION ALL
SELECT 'BLOCK 7a USER_GR_MNU_MPG_M (DMF0043_01)',
       (SELECT COUNT(*) FROM SCM_ADM_USER_GR_MNU_MPG_M WHERE MNU_ID = 'DMF0043_01' AND USE_YN = 'Y'),
       (SELECT COUNT(*) FROM SCM_ADM_USER_GR_MNU_MPG_M WHERE MNU_ID = 'DMF0043' AND USE_YN = 'Y'),
       'rows' FROM DUAL
UNION ALL
SELECT 'BLOCK 7b USER_GR_MNU_BTN_MPG_M (DMF0043_01 BTN)',
       (SELECT COUNT(*) FROM SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE MNU_ID = 'DMF0043_01' AND USE_YN = 'Y'),
       (SELECT COUNT(DISTINCT USER_GR_ID) FROM SCM_ADM_USER_GR_MNU_MPG_M WHERE MNU_ID = 'DMF0043' AND USE_YN = 'Y') * 8,
       'rows (GR × 8 routing)' FROM DUAL
ORDER BY BLOCK_NAME;
