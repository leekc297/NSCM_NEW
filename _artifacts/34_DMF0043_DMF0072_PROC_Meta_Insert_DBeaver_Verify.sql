SELECT 'BLOCK 1 PKG_DMF0043 PROC_M total rows' BLOCK_NAME,
       (SELECT COUNT(*) FROM SCM_ADM_PROC_M WHERE PROC_NM LIKE 'PKG_DMF0043.%') ACTUAL,
       (SELECT COUNT(*) FROM ALL_ARGUMENTS WHERE PACKAGE_NAME = 'PKG_DMF0043' AND POSITION > 0) EXPECT,
       'rows' UNIT FROM DUAL
UNION ALL
SELECT 'BLOCK 2 PKG_DMF0072 PROC_M total rows',
       (SELECT COUNT(*) FROM SCM_ADM_PROC_M WHERE PROC_NM LIKE 'PKG_DMF0072.%'),
       (SELECT COUNT(*) FROM ALL_ARGUMENTS WHERE PACKAGE_NAME = 'PKG_DMF0072' AND POSITION > 0),
       'rows' FROM DUAL
UNION ALL
SELECT 'BLOCK 3 P_DMF0043_GET_MAIN_VARSION_DATA (=4)',
       (SELECT COUNT(*) FROM SCM_ADM_PROC_M WHERE PROC_NM = 'PKG_DMF0043.P_DMF0043_GET_MAIN_VARSION_DATA'),
       4,
       'rows' FROM DUAL
UNION ALL
SELECT 'BLOCK 4 sesUserId 매핑 정상 (DMF0043 IN P_USER_ID)',
       (SELECT COUNT(*) FROM SCM_ADM_PROC_M WHERE PROC_NM LIKE 'PKG_DMF0043.%' AND COL_NM = 'sesUserId' AND COL_TP_CD = 'IN'),
       (SELECT COUNT(*) FROM ALL_ARGUMENTS WHERE PACKAGE_NAME = 'PKG_DMF0043' AND ARGUMENT_NAME = 'P_USER_ID' AND IN_OUT = 'IN'),
       'rows' FROM DUAL
UNION ALL
SELECT 'BLOCK 5 menuId 매핑 정상 (DMF0043 IN P_MENU_ID)',
       (SELECT COUNT(*) FROM SCM_ADM_PROC_M WHERE PROC_NM LIKE 'PKG_DMF0043.%' AND COL_NM = 'menuId' AND COL_TP_CD = 'IN'),
       (SELECT COUNT(*) FROM ALL_ARGUMENTS WHERE PACKAGE_NAME = 'PKG_DMF0043' AND ARGUMENT_NAME = 'P_MENU_ID' AND IN_OUT = 'IN'),
       'rows' FROM DUAL
UNION ALL
SELECT 'BLOCK 6 O_RESULT_CURSOR PROC_RESULT 매핑',
       (SELECT COUNT(*) FROM SCM_ADM_PROC_M WHERE PROC_NM IN (SELECT PROC_NM FROM SCM_ADM_PROC_M WHERE PROC_NM LIKE 'PKG_DMF0043.%' OR PROC_NM LIKE 'PKG_DMF0072.%') AND COL_NM = 'O_RESULT_CURSOR' AND DATA_TP_CD = 'PROC_RESULT'),
       (SELECT COUNT(DISTINCT PACKAGE_NAME || '.' || OBJECT_NAME) FROM ALL_ARGUMENTS WHERE PACKAGE_NAME IN ('PKG_DMF0043','PKG_DMF0072') AND ARGUMENT_NAME = 'O_RESULT_CURSOR'),
       'rows' FROM DUAL
ORDER BY BLOCK_NAME;
