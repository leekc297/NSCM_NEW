-- DMF0007 PSI 데이터 + 메타 진단

-- D1. customerPSI sheet 메타 정렬 상태
SELECT COLUMN_NAME, COLUMN_LABEL_NAME, SMALL_CLASS_LABEL_NAME,
       CASE WHEN COLUMN_LABEL_NAME = SMALL_CLASS_LABEL_NAME THEN 'EQ_MERGE_OK'
            WHEN COLUMN_NAME IN ('MEASURE_GROUP','MEASURE') THEN 'GROUPED_MEASURE'
            ELSE 'DIFF_NO_MERGE' END AS MERGE_STATUS
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID='DMF0007' AND SHEET_NAME='customerPSI' AND VALID_YN='Y'
 ORDER BY SORT_ORDER_NO;

-- D2. PSI 데이터 PLAN_WEEK / DIVISION_ID 분포
SELECT PLAN_WEEK, DIVISION_ID, COUNT(*)
  FROM SCM_MGR.DM_MST_CUSTOMER_FCST
 WHERE MEASURE_GROUP='PSI'
 GROUP BY PLAN_WEEK, DIVISION_ID
 ORDER BY PLAN_WEEK DESC, DIVISION_ID;

-- D3. PSI 의 SUMMARY_BUCKET_VALUE 범위 확인 (FE dateColumns 와 매칭되어야 화면에 보임)
SELECT MIN(SUMMARY_BUCKET_VALUE) AS MIN_BUCKET, MAX(SUMMARY_BUCKET_VALUE) AS MAX_BUCKET, COUNT(*) AS CNT
  FROM SCM_MGR.DM_MST_CUSTOMER_FCST
 WHERE MEASURE_GROUP='PSI' AND DIVISION_ID='81' AND PLAN_WEEK IN ('202622','202623','202624','202625');
