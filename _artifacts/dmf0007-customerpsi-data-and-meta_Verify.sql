-- DMF0007 PSI 데이터 + 메타 정정 검증 (단일 UNION ALL SELECT)

SELECT '1.customerPSI 머지 비호환 행 (colLbl != sCls, Measure 그룹 외)' AS check_item,
       TO_CHAR(COUNT(*)) AS actual,
       '0' AS expected,
       CASE WHEN COUNT(*) = 0 THEN 'OK' ELSE 'FAIL' END AS result
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID='DMF0007' AND SHEET_NAME='customerPSI' AND VALID_YN='Y'
   AND COLUMN_NAME NOT IN ('MEASURE_GROUP', 'MEASURE')
   AND (SMALL_CLASS_LABEL_NAME IS NULL OR SMALL_CLASS_LABEL_NAME <> COLUMN_LABEL_NAME)
UNION ALL
SELECT '2.customerPSI Measure 그룹핑 보존 (MEASURE_GROUP/MEASURE 의 sCls=Measure)',
       TO_CHAR(COUNT(*)),
       '2',
       CASE WHEN COUNT(*) = 2 THEN 'OK' ELSE 'FAIL' END
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID='DMF0007' AND SHEET_NAME='customerPSI' AND VALID_YN='Y'
   AND COLUMN_NAME IN ('MEASURE_GROUP', 'MEASURE')
   AND SMALL_CLASS_LABEL_NAME = 'Measure'
UNION ALL
SELECT '3.PSI Division=81 PLAN_WEEK=202622 데이터',
       TO_CHAR(COUNT(*)),
       '2320',
       CASE WHEN COUNT(*) = 2320 THEN 'OK' ELSE 'FAIL' END
  FROM SCM_MGR.DM_MST_CUSTOMER_FCST
 WHERE MEASURE_GROUP='PSI' AND DIVISION_ID='81' AND PLAN_WEEK='202622'
UNION ALL
SELECT '4.PSI Division=81 PLAN_WEEK=202623 데이터',
       TO_CHAR(COUNT(*)),
       '2320',
       CASE WHEN COUNT(*) = 2320 THEN 'OK' ELSE 'FAIL' END
  FROM SCM_MGR.DM_MST_CUSTOMER_FCST
 WHERE MEASURE_GROUP='PSI' AND DIVISION_ID='81' AND PLAN_WEEK='202623'
UNION ALL
SELECT '5.PSI Division=81 PLAN_WEEK=202624 데이터',
       TO_CHAR(COUNT(*)),
       '2320',
       CASE WHEN COUNT(*) = 2320 THEN 'OK' ELSE 'FAIL' END
  FROM SCM_MGR.DM_MST_CUSTOMER_FCST
 WHERE MEASURE_GROUP='PSI' AND DIVISION_ID='81' AND PLAN_WEEK='202624'
UNION ALL
SELECT '6.PSI Division=81 PLAN_WEEK=202625 데이터',
       TO_CHAR(COUNT(*)),
       '2320',
       CASE WHEN COUNT(*) = 2320 THEN 'OK' ELSE 'FAIL' END
  FROM SCM_MGR.DM_MST_CUSTOMER_FCST
 WHERE MEASURE_GROUP='PSI' AND DIVISION_ID='81' AND PLAN_WEEK='202625'
UNION ALL
SELECT '7.PSI 전체 데이터 건수 (기대 14 + 9280 = 9294)',
       TO_CHAR(COUNT(*)),
       '9294',
       CASE WHEN COUNT(*) = 9294 THEN 'OK' ELSE 'FAIL' END
  FROM SCM_MGR.DM_MST_CUSTOMER_FCST
 WHERE MEASURE_GROUP='PSI'
ORDER BY 1;
