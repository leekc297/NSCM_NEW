SET DEFINE OFF FEEDBACK OFF SERVEROUTPUT ON SIZE 1000000 PAGES 0 LINES 200
DECLARE
  c1 SYS_REFCURSOR; c2 SYS_REFCURSOR; c3 SYS_REFCURSOR;
  v_s TIMESTAMP := SYSTIMESTAMP;
  v_t1 TIMESTAMP;
  v_cnt NUMBER := 0;
  v_rec SYS.ODCIVARCHAR2LIST;
BEGIN
  DMF0043_GET_CONTRIBUTION_SALES_LIST('40', '1', 'R_S_20250609_V001_C', '', '', '', 'N', 'N', 'minyonglee1', c1, c2, c3);
  v_t1 := SYSTIMESTAMP;
  DBMS_OUTPUT.PUT_LINE('SP_CALL_MS=' || ROUND((EXTRACT(SECOND FROM (v_t1 - v_s)) + EXTRACT(MINUTE FROM (v_t1 - v_s))*60) * 1000));
  LOOP
    FETCH c1 BULK COLLECT INTO v_rec LIMIT 1000;
    v_cnt := v_cnt + v_rec.COUNT;
    EXIT WHEN v_rec.COUNT < 1000;
  END LOOP;
  CLOSE c1;
  DBMS_OUTPUT.PUT_LINE('ROWS=' || v_cnt || ' / TOTAL_MS=' || ROUND((EXTRACT(SECOND FROM (SYSTIMESTAMP - v_s)) + EXTRACT(MINUTE FROM (SYSTIMESTAMP - v_s))*60) * 1000));
EXCEPTION WHEN OTHERS THEN
  DBMS_OUTPUT.PUT_LINE('ERR=' || SQLERRM);
  DBMS_OUTPUT.PUT_LINE('BT=' || DBMS_UTILITY.FORMAT_ERROR_BACKTRACE);
END;
/
EXIT
