VALUES (s.SQL_ID, s.MDU_DIVS_CD, s.SQL_NM, s.SQL_DTL_CTN, s.USE_YN, s.CREATED_BY, s.CREATION_DATE, s.LAST_UPDATED_BY, s.LAST_UPDATE_DATE);

MERGE INTO SCM_ADM_CMBO_SQL_M t
USING (SELECT 'DOM_EXP' AS SQL_ID,
         'CM' AS MDU_DIVS_CD,
         'DOM/EXP (Domestic/Export)' AS SQL_NM,
         'SELECT B.SEGMENT1 AS CODE, B.SEGMENT2 AS NAME FROM SCM_ADM_LOOKUP_MASTER A INNER JOIN SCM_ADM_LOOKUP_MASTER_DETAIL B ON A.LOOKUP_TYPE = B.LOOKUP_TYPE AND B.VALID_YN = ''Y'' WHERE A.LOOKUP_TYPE = ''DOM/EXP'' AND A.VALID_YN = ''Y'' ORDER BY B.DISPLAY_SEQ' AS SQL_DTL_CTN,
         'Y' AS USE_YN,
         'admin' AS CREATED_BY,
         SYSDATE AS CREATION_DATE,
         'admin' AS LAST_UPDATED_BY,
         SYSDATE AS LAST_UPDATE_DATE
       FROM DUAL) s
ON (t.SQL_ID = s.SQL_ID AND t.MDU_DIVS_CD = s.MDU_DIVS_CD)
WHEN MATCHED THEN UPDATE SET
       t.SQL_NM = s.SQL_NM,
       t.SQL_DTL_CTN = s.SQL_DTL_CTN,
       t.USE_YN = s.USE_YN,
       t.LAST_UPDATED_BY = s.LAST_UPDATED_BY,
       t.LAST_UPDATE_DATE = s.LAST_UPDATE_DATE
WHEN NOT MATCHED THEN INSERT (SQL_ID, MDU_DIVS_CD, SQL_NM, SQL_DTL_CTN, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES (s.SQL_ID, s.MDU_DIVS_CD, s.SQL_NM, s.SQL_DTL_CTN, s.USE_YN, s.CREATED_BY, s.CREATION_DATE, s.LAST_UPDATED_BY, s.LAST_UPDATE_DATE);


