-- [1] PKG_DMF0043 + PKG_DMF0072 의 SCM_ADM_PROC_M 등록 현황
SELECT SUBSTR(PROC_NM, 1, 60) PROC_NM, COUNT(*) META_ROWS
  FROM SCM_ADM_PROC_M
 WHERE PROC_NM LIKE 'PKG_DMF0043.%' OR PROC_NM LIKE 'PKG_DMF0072.%'
 GROUP BY SUBSTR(PROC_NM, 1, 60)
 ORDER BY 1;

-- [2] 실제 SP 시그니처 (ALL_ARGUMENTS) 비교용
SELECT PACKAGE_NAME || '.' || OBJECT_NAME PROC_NM, COUNT(*) ARG_CNT
  FROM ALL_ARGUMENTS
 WHERE PACKAGE_NAME IN ('PKG_DMF0043','PKG_DMF0072')
   AND POSITION > 0
 GROUP BY PACKAGE_NAME, OBJECT_NAME
 ORDER BY 1;

-- [3] P_DMF0043_GET_MAIN_VARSION_DATA 정확한 매핑 (DMF0043 main SEARCH 사용)
SELECT PROC_NM, COL_NM, COL_TP_CD, DATA_TP_CD, SORT_ORD
  FROM SCM_ADM_PROC_M
 WHERE PROC_NM = 'PKG_DMF0043.P_DMF0043_GET_MAIN_VARSION_DATA'
 ORDER BY SORT_ORD;

-- [4] 누락 검증 — ALL_ARGUMENTS 에 있지만 SCM_ADM_PROC_M 에 없는 row
SELECT S.PACKAGE_NAME || '.' || S.OBJECT_NAME PROC_NM,
       S.ARGUMENT_NAME, S.IN_OUT, S.POSITION
  FROM ALL_ARGUMENTS S
 WHERE S.PACKAGE_NAME IN ('PKG_DMF0043','PKG_DMF0072')
   AND S.POSITION > 0
   AND NOT EXISTS (
     SELECT 1 FROM SCM_ADM_PROC_M T
      WHERE T.PROC_NM = S.PACKAGE_NAME || '.' || S.OBJECT_NAME
        AND T.SORT_ORD = S.POSITION
   )
 ORDER BY 1, 4;

-- [5] DMF0043 / DMF0043_01 / DMF0072 API → PROC 매핑 점검
SELECT A.API_ID, A.API_URL,
       (SELECT COUNT(*) FROM SCM_ADM_PROC_M P WHERE P.PROC_NM = A.API_URL) PROC_META_CNT,
       (SELECT COUNT(*) FROM ALL_ARGUMENTS X
         WHERE X.PACKAGE_NAME || '.' || X.OBJECT_NAME = A.API_URL AND X.POSITION > 0) ACTUAL_ARG_CNT
  FROM SCM_ADM_API_M A
 WHERE A.API_ID LIKE 'DMF0043_%' OR A.API_ID LIKE 'DMF0072_%'
 ORDER BY A.API_ID;
