--==============================================================================
-- 84_axis3a_sp3_sys0005_proc_rename.sql
-- AXIS 3-A SP3 fix — PKG_SYS0005.SYS0005_SAVE_PROC_DATA (메타 잘못 등록)
--
-- 현황:
--   API_M.SYS0005_INFO_SAVE.API_URL = 'PKG_SYS0005.SYS0005_SAVE_PROC_DATA_BLK' (실 SP)
--   PROC_M.PROC_NM = 'PKG_SYS0005.SYS0005_SAVE_PROC_DATA' (오타, _BLK 누락)
--   실 SP signature: P_DATA(CLOB IN) + P_USER_ID(VARCHAR2 IN) + O_RESULT_CURSOR(REF CURSOR OUT)
--
-- fix:
--   1. 잘못된 PROC_NM 7 row DELETE
--   2. 실 SP signature 3 row INSERT
--==============================================================================
SET DEFINE OFF
SET SERVEROUTPUT ON
SET FEEDBACK ON
WHENEVER SQLERROR EXIT FAILURE

PROMPT === BEFORE ===
SELECT PROC_NM, COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM LIKE 'PKG_SYS0005.SYS0005_SAVE_PROC_DATA%' GROUP BY PROC_NM;

PROMPT === DELETE wrong PROC_NM ===
DELETE FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM = 'PKG_SYS0005.SYS0005_SAVE_PROC_DATA';

PROMPT === INSERT correct PROC_M (3 row, NOT EXISTS 멱등) ===
INSERT INTO SCM_MGR.SCM_ADM_PROC_M
  (PROC_NM, COL_NM, COL_TP_CD, SORT_ORD, DATA_TP_CD, DATA_LEN, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'PKG_SYS0005.SYS0005_SAVE_PROC_DATA_BLK', 'p_data', 'IN', 1, 'CLOB', NULL, 'Y', 'SYSTEM', SYSDATE, 'SYSTEM', SYSDATE FROM DUAL
 WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_PROC_M
                    WHERE PROC_NM='PKG_SYS0005.SYS0005_SAVE_PROC_DATA_BLK' AND COL_NM='p_data' AND COL_TP_CD='IN');

INSERT INTO SCM_MGR.SCM_ADM_PROC_M
  (PROC_NM, COL_NM, COL_TP_CD, SORT_ORD, DATA_TP_CD, DATA_LEN, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'PKG_SYS0005.SYS0005_SAVE_PROC_DATA_BLK', 'sesUserId', 'IN', 2, 'VARCHAR2', 50, 'Y', 'SYSTEM', SYSDATE, 'SYSTEM', SYSDATE FROM DUAL
 WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_PROC_M
                    WHERE PROC_NM='PKG_SYS0005.SYS0005_SAVE_PROC_DATA_BLK' AND COL_NM='sesUserId' AND COL_TP_CD='IN');

INSERT INTO SCM_MGR.SCM_ADM_PROC_M
  (PROC_NM, COL_NM, COL_TP_CD, SORT_ORD, DATA_TP_CD, DATA_LEN, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'PKG_SYS0005.SYS0005_SAVE_PROC_DATA_BLK', 'O_RESULT_CURSOR', 'OUT', 3, 'REF CURSOR', NULL, 'Y', 'SYSTEM', SYSDATE, 'SYSTEM', SYSDATE FROM DUAL
 WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_PROC_M
                    WHERE PROC_NM='PKG_SYS0005.SYS0005_SAVE_PROC_DATA_BLK' AND COL_NM='O_RESULT_CURSOR' AND COL_TP_CD='OUT');

COMMIT;

PROMPT === AFTER ===
SELECT PROC_NM, SORT_ORD, COL_NM, COL_TP_CD, DATA_TP_CD FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM LIKE 'PKG_SYS0005.SYS0005_SAVE_PROC_DATA%' ORDER BY PROC_NM, SORT_ORD;
EXIT;
