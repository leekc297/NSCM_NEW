-- A-1) 'Measure' 그룹핑 (MEASURE_GROUP/MEASURE) 외 모든 customerPSI 행에서 SMALL_CLASS_LABEL_NAME = COLUMN_LABEL_NAME 으로 통일
UPDATE SCM_MGR.SCM_MST_SHEET_COLUMNS
   SET SMALL_CLASS_LABEL_NAME = COLUMN_LABEL_NAME
