-- D1. customerPSI sheet column 메타 현황
SELECT COLUMN_NAME, COLUMN_LABEL_NAME, SMALL_CLASS_LABEL_NAME, LARGE_CLASS_LABEL_NAME,
       VISIBLE_FLAG, DEFAULT_FLAG, FIXED_FLAG, VALID_YN, SORT_ORDER_NO
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID='DMF0007' AND SHEET_NAME='customerPSI'
 ORDER BY SORT_ORDER_NO;

-- D2. customerFcst 와 customerPSI 의 COLUMN_NAME 비교 (집합 차이)
SELECT 'ONLY_FCST' AS side, COLUMN_NAME
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID='DMF0007' AND SHEET_NAME='customerFcst' AND VALID_YN='Y'
MINUS
SELECT 'ONLY_FCST', COLUMN_NAME
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID='DMF0007' AND SHEET_NAME='customerPSI' AND VALID_YN='Y'
UNION ALL
SELECT 'ONLY_PSI', COLUMN_NAME
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID='DMF0007' AND SHEET_NAME='customerPSI' AND VALID_YN='Y'
MINUS
SELECT 'ONLY_PSI', COLUMN_NAME
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID='DMF0007' AND SHEET_NAME='customerFcst' AND VALID_YN='Y'
ORDER BY 1, 2;

-- D3. SCM_ADM_API_M DMF0007 API 등록 현황
SELECT API_ID, API_TP_CD, API_URL, USE_YN
  FROM SCM_MGR.SCM_ADM_API_M
 WHERE API_ID LIKE '%DMF0007%';

-- D4. SCM_ADM_MNU_BTN_MPG_M DMF0007 매핑 현황 (customerFcst + customerPSI)
SELECT MNU_ID, SHT_NM, MNU_BTN_CD, API_ID, USE_YN
  FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M
 WHERE MNU_ID='DMF0007'
 ORDER BY SHT_NM, MNU_BTN_CD;

-- D5. SCM_ADM_USER_GR_MNU_BTN_MPG_M DMF0007 권한 현황
SELECT USER_GR_ID, SHT_NM, MNU_BTN_CD, USE_YN
  FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M
 WHERE MNU_ID='DMF0007'
 ORDER BY USER_GR_ID, SHT_NM, MNU_BTN_CD;

-- D6. SCM_ADM_PROC_M PSI SP 파라미터 메타
SELECT COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD
  FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM='PKG_DMF0007.P_DMF0007_GET_CUST_PSI_DATA'
 ORDER BY SORT_ORD;

