-- 원인 : 사내 DB SCM_ADM_CMBO_SQL_M 에 아래 3개 SQL_ID 미존재 → 콤보 옵션 empty
-- 소스 : AS-IS(LGCE_SCMDEV, MSSQL) 프로시저 [dbo].[UP_FX_GetCommonDataList] 내
--        IF @Code = '...' 블록의 SELECT 를 그대로 추출.
--        파일 : Doc/_legacy_source/DB_DDL/AsIs_LGCE_SCMDEV_SP10_DDL.sql
--          - BizTypeByDivision  : L12159~12180 (DIVISION 필터는 원본에서 주석처리 → active 는 단순 SELECT)
--          - DOM_EXP            : L12307~12316
--          - FCST_TYPE_NOT_FREE : L15788~15798
-- 변환 : MSSQL→Oracle — WITH(NOLOCK) 제거(그 외 구문 Oracle 호환). WHERE/필터 로직은 원본 그대로 보존.
--        FCST_TYPE_NOT_FREE 는 원본 SELECT 3컬럼(CODE,NAME,DISPLAY_SEQ) → 콤보 계약(CODE,NAME) 2컬럼으로 정규화
--        (DISPLAY_SEQ 는 ORDER BY 로 유지, 필터 로직 SEGMENT4<>'FREE' 그대로).
-- 검증 : 사내 OCGSCMD_P01 에서 변환 쿼리 직접 실행 → BizTypeByDivision 12행 / FCST_TYPE_NOT_FREE 8행 / DOM_EXP 2행 (2026-07-01)
--        의존 룩업 데이터(BIZ_TYPE_BPMS 12 / SALES_TYPE_CODE 14 / DOM/EXP 2, SCM_ADM_LOOKUP_MASTER 존재) 확인 완료.
-- 멱등 : NOT EXISTS (재실행 안전). DBeaver/SQL*Plus 공통 (SET / '/' / EXIT 미사용).
-- NOT NULL 전수: SQL_ID, MDU_DIVS_CD, SQL_DTL_CTN, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE
-- 비고 : MDU_DIVS_CD 는 서술 메타(콤보 해석은 SQL_ID 로만) — 'CM' 사용.
-- =====================================================================================

-- 1) BizTypeByDivision  (AS-IS L12159~12180, LOOKUP_TYPE='BIZ_TYPE_BPMS' — 원본 VALID_YN 미필터 그대로 보존)
INSERT INTO SCM_ADM_CMBO_SQL_M (
  SQL_ID, MDU_DIVS_CD, SQL_NM, SQL_DTL_CTN, USE_YN,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE
)
SELECT
  'BizTypeByDivision', 'CM', 'Biz Type by Division (BIZ_TYPE_BPMS)',
  'SELECT SEGMENT1 AS CODE, SEGMENT2 AS NAME FROM SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = ''BIZ_TYPE_BPMS'' ORDER BY DISPLAY_SEQ',
  'Y', 'admin', SYSDATE, 'admin', SYSDATE
FROM DUAL
WHERE NOT EXISTS (SELECT 1 FROM SCM_ADM_CMBO_SQL_M WHERE SQL_ID = 'BizTypeByDivision');

-- 2) FCST_TYPE_NOT_FREE  (AS-IS L15788~15798, LOOKUP_TYPE='SALES_TYPE_CODE' AND SEGMENT4<>'FREE')
INSERT INTO SCM_ADM_CMBO_SQL_M (
  SQL_ID, MDU_DIVS_CD, SQL_NM, SQL_DTL_CTN, USE_YN,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE
)
SELECT
  'FCST_TYPE_NOT_FREE', 'CM', 'FCST Type excl. FREE (SALES_TYPE_CODE)',
  'SELECT SEGMENT1 AS CODE, SEGMENT2 AS NAME FROM SCM_ADM_LOOKUP_MASTER_DETAIL WHERE VALID_YN = ''Y'' AND LOOKUP_TYPE = ''SALES_TYPE_CODE'' AND SEGMENT4 <> ''FREE'' ORDER BY DISPLAY_SEQ',
  'Y', 'admin', SYSDATE, 'admin', SYSDATE
FROM DUAL
WHERE NOT EXISTS (SELECT 1 FROM SCM_ADM_CMBO_SQL_M WHERE SQL_ID = 'FCST_TYPE_NOT_FREE');

-- 3) DOM_EXP  (AS-IS L12307~12316, MASTER+DETAIL JOIN, LOOKUP_TYPE='DOM/EXP')
INSERT INTO SCM_ADM_CMBO_SQL_M (
  SQL_ID, MDU_DIVS_CD, SQL_NM, SQL_DTL_CTN, USE_YN,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE
)
SELECT
  'DOM_EXP', 'CM', 'DOM/EXP (Domestic/Export)',
  'SELECT B.SEGMENT1 AS CODE, B.SEGMENT2 AS NAME FROM SCM_ADM_LOOKUP_MASTER A INNER JOIN SCM_ADM_LOOKUP_MASTER_DETAIL B ON A.LOOKUP_TYPE = B.LOOKUP_TYPE AND B.VALID_YN = ''Y'' WHERE A.LOOKUP_TYPE = ''DOM/EXP'' AND A.VALID_YN = ''Y'' ORDER BY B.DISPLAY_SEQ',
  'Y', 'admin', SYSDATE, 'admin', SYSDATE
FROM DUAL
WHERE NOT EXISTS (SELECT 1 FROM SCM_ADM_CMBO_SQL_M WHERE SQL_ID = 'DOM_EXP');

COMMIT;

-- 검증 (3건 조회되어야 함)
SELECT SQL_ID, MDU_DIVS_CD, USE_YN, SQL_DTL_CTN
FROM   SCM_ADM_CMBO_SQL_M
WHERE  SQL_ID IN ('BizTypeByDivision', 'FCST_TYPE_NOT_FREE', 'DOM_EXP')
ORDER  BY SQL_ID;
