PROMPT === BLOCK 2 : DMF0072_GET_ITEM_POPUP_LIST — As-Is DMF0002_GET_ITEM_BY_DIVISION_POPUPEx 1:1 (3-UNION 분기 보존) ===
CREATE OR REPLACE PROCEDURE SCM_MGR.DMF0072_GET_ITEM_POPUP_LIST (
    P_DIVISION_ID    VARCHAR2,
    P_DEPT_ID        VARCHAR2,
    P_END_CUSTOMER   VARCHAR2,
    P_PROJECT_CODE   VARCHAR2,
