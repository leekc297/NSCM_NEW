-- SSP0003 Shipment Change Request Confirm 조회 중복 행 점검 (클라우드용)
-- 작성 2026-11-25 · 사내 ZIOUI1 에서 문법·결과 검증 끝
-- 조회 전용. 전체 F5 실행 가능. 요청번호는 각 쿼리 첫 줄 WITH P 의 값만 바꿔 쓴다.
-- 조회 SP = PKG_SSP0003.P_SSP0003_GET_CHG_REQ_CONFIRM
--   헤더 SSP_ANL_SHIP_CONFIRM_CHG_REQ 1행에 위임 SSP_MST_DELEGATE 를 (DIVISION_ID, USER_ID = APPROVAL_USER,
--   VALID_YN = 'Y', 오늘이 FROM_DATE~TO_DATE 안) 조건으로 OUTER JOIN 한다. AS-IS SP 와 같은 조인임.
--   위임 테이블에 PK 가 없어 결재자 1명에게 유효 위임이 2행이면 조회 행이 2배가 됨.

-- [1] 헤더 행 수. 1 이면 헤더 중복 없음
WITH P AS (SELECT 'R20261125542412' AS REQ_NO FROM DUAL)
SELECT A.DIVISION_ID, A.CHANGE_REQ_NO, A.CHANGE_REQ_STATUS, A.VALID_YN
     , A.REQUEST_USER, A.APPROVAL_USER, A.DELEGATEE_USER
     , TO_CHAR(A.REQUEST_TIME, 'YYYY-MM-DD HH24:MI:SS') AS REQUEST_TIME
     , COUNT(*) OVER () AS HEADER_CNT
  FROM SSP_ANL_SHIP_CONFIRM_CHG_REQ A, P
 WHERE A.CHANGE_REQ_NO = P.REQ_NO;

-- [2] SP 와 같은 조인으로 센 행 수. 2 이상이면 어느 조인이 늘렸는지 열별 건수로 본다
WITH P AS (SELECT 'R20261125542412' AS REQ_NO FROM DUAL)
SELECT A.CHANGE_REQ_NO
     , COUNT(*)                        AS SP_ROWS
     , COUNT(DISTINCT B.ROWID)         AS REQ_USER_ROWS
     , COUNT(DISTINCT C.ROWID)         AS APPR_USER_ROWS
     , COUNT(DISTINCT D.ROWID)         AS DELEG_USER_ROWS
     , COUNT(DISTINCT E.ROWID)         AS DELEGATE_ROWS
     , LISTAGG(E.DELEGATEE_ID, ',') WITHIN GROUP (ORDER BY E.FROM_DATE) AS DELEGATEE_IDS
  FROM SSP_ANL_SHIP_CONFIRM_CHG_REQ A
     , SCM_ADM_USER_M B
     , SCM_ADM_USER_M C
     , SCM_ADM_USER_M D
     , SSP_MST_DELEGATE E
     , SCM_ADM_USER_M F
     , P
 WHERE A.CHANGE_REQ_NO = P.REQ_NO
   AND B.USER_ID(+) = A.REQUEST_USER    AND B.USE_YN(+) = 'Y'
   AND C.USER_ID(+) = A.APPROVAL_USER   AND C.USE_YN(+) = 'Y'
   AND D.USER_ID(+) = A.DELEGATEE_USER  AND D.USE_YN(+) = 'Y'
   AND E.DIVISION_ID(+) = A.DIVISION_ID
   AND E.USER_ID(+) = A.APPROVAL_USER
   AND E.VALID_YN(+) = 'Y'
   AND TO_CHAR(SYSDATE, 'YYYYMMDD') BETWEEN E.FROM_DATE(+) AND E.TO_DATE(+)
   AND F.USER_ID(+) = E.DELEGATEE_ID    AND F.USE_YN(+) = 'Y'
 GROUP BY A.CHANGE_REQ_NO;

-- [3] 해당 요청 결재자의 위임 이력 전체. TODAY_VALID = 'Y' 가 2행 이상이면 데이터 원인
WITH P AS (SELECT 'R20261125542412' AS REQ_NO FROM DUAL)
SELECT E.DIVISION_ID, E.USER_ID, E.DELEGATEE_ID, E.FROM_DATE, E.TO_DATE, E.VALID_YN
     , CASE WHEN E.VALID_YN = 'Y' AND TO_CHAR(SYSDATE, 'YYYYMMDD') BETWEEN E.FROM_DATE AND E.TO_DATE
            THEN 'Y' ELSE 'N' END AS TODAY_VALID
     , E.CREATED_BY, TO_CHAR(E.CREATION_DATE, 'YYYY-MM-DD HH24:MI:SS') AS CREATION_DATE
     , E.LAST_UPDATED_BY, TO_CHAR(E.LAST_UPDATE_DATE, 'YYYY-MM-DD HH24:MI:SS') AS LAST_UPDATE_DATE
  FROM SSP_MST_DELEGATE E
 WHERE (E.DIVISION_ID, E.USER_ID) IN (SELECT A.DIVISION_ID, A.APPROVAL_USER
                                        FROM SSP_ANL_SHIP_CONFIRM_CHG_REQ A, P
                                       WHERE A.CHANGE_REQ_NO = P.REQ_NO)
 ORDER BY E.DIVISION_ID, E.USER_ID, E.FROM_DATE, E.CREATION_DATE;

-- [4] 오늘 유효 위임이 2행 이상인 결재자 전체 (조회 중복을 만드는 데이터 목록)
SELECT E.DIVISION_ID, E.USER_ID
     , COUNT(*) AS VALID_CNT
     , LISTAGG(E.DELEGATEE_ID || ':' || E.FROM_DATE || '~' || E.TO_DATE || '@' || TO_CHAR(E.CREATION_DATE, 'YYYYMMDD HH24MISS'), ' | ')
           WITHIN GROUP (ORDER BY E.CREATION_DATE) AS DETAIL
  FROM SSP_MST_DELEGATE E
 WHERE E.VALID_YN = 'Y'
   AND TO_CHAR(SYSDATE, 'YYYYMMDD') BETWEEN E.FROM_DATE AND E.TO_DATE
 GROUP BY E.DIVISION_ID, E.USER_ID
HAVING COUNT(*) > 1
 ORDER BY E.DIVISION_ID, E.USER_ID;

-- [5] 위임 대상자가 '/' 또는 사용자 마스터에 없는 ID 인 유효 위임 행
SELECT E.DIVISION_ID, E.USER_ID, E.DELEGATEE_ID, E.FROM_DATE, E.TO_DATE
     , TO_CHAR(E.CREATION_DATE, 'YYYY-MM-DD HH24:MI:SS') AS CREATION_DATE
  FROM SSP_MST_DELEGATE E
 WHERE E.VALID_YN = 'Y'
   AND TO_CHAR(SYSDATE, 'YYYYMMDD') BETWEEN E.FROM_DATE AND E.TO_DATE
   AND NOT EXISTS (SELECT 1 FROM SCM_ADM_USER_M U WHERE U.USER_ID = E.DELEGATEE_ID)
 ORDER BY E.DIVISION_ID, E.USER_ID;

-- [6] 영향 범위: 최근 30일 요청 중 위임 중복 결재자에게 걸린 요청 수
SELECT A.DIVISION_ID, A.APPROVAL_USER, COUNT(*) AS REQ_CNT
  FROM SSP_ANL_SHIP_CONFIRM_CHG_REQ A
 WHERE A.VALID_YN = 'Y'
   AND A.REQUEST_TIME >= TRUNC(SYSDATE) - 30
   AND (A.DIVISION_ID, A.APPROVAL_USER) IN (SELECT E.DIVISION_ID, E.USER_ID
                                              FROM SSP_MST_DELEGATE E
                                             WHERE E.VALID_YN = 'Y'
                                               AND TO_CHAR(SYSDATE, 'YYYYMMDD') BETWEEN E.FROM_DATE AND E.TO_DATE
                                             GROUP BY E.DIVISION_ID, E.USER_ID
                                            HAVING COUNT(*) > 1)
 GROUP BY A.DIVISION_ID, A.APPROVAL_USER
 ORDER BY 1, 2;

-- [7] 키 제약 확인. 헤더 PK = CHANGE_REQ_NO, 사용자 PK = USER_ID, 위임 테이블 PK·UNIQUE 없음 (사내 결과)
SELECT C.TABLE_NAME, C.CONSTRAINT_NAME, C.CONSTRAINT_TYPE
     , LISTAGG(CC.COLUMN_NAME, ',') WITHIN GROUP (ORDER BY CC.POSITION) AS COLS
  FROM ALL_CONSTRAINTS C
  JOIN ALL_CONS_COLUMNS CC ON CC.OWNER = C.OWNER AND CC.CONSTRAINT_NAME = C.CONSTRAINT_NAME
 WHERE C.TABLE_NAME IN ('SSP_ANL_SHIP_CONFIRM_CHG_REQ', 'SSP_MST_DELEGATE', 'SCM_ADM_USER_M')
   AND C.CONSTRAINT_TYPE IN ('P', 'U')
 GROUP BY C.TABLE_NAME, C.CONSTRAINT_NAME, C.CONSTRAINT_TYPE
 ORDER BY 1, 2;

