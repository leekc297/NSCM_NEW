     , TO_CHAR(LAST_DDL_TIME, 'YYYY-MM-DD HH24:MI:SS') AS LAST_DDL_TIME
  FROM ALL_OBJECTS
 WHERE OBJECT_NAME = 'PKG_SSP0003'
