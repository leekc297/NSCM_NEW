SET LINESIZE 250
SET PAGESIZE 500
SET TRIMSPOOL ON
SET VERIFY OFF
SET DEFINE ON
DEFINE P_DIV  = '40'
DEFINE P_SITE = 'AJ상사_AB_TES'
DEFINE P_ITEM = 'MCCM356015A2'
COLUMN AT FORMAT A14
COLUMN ST FORMAT A14
COLUMN WHO FORMAT A14
COLUMN CELL FORMAT A10
COLUMN MEASURE FORMAT A12
COLUMN KEYS FORMAT A46
COLUMN LOG_TYPE FORMAT A8
COLUMN LOG_MESSAGE FORMAT A40
COLUMN DESCRIPTION FORMAT A110
COLUMN IN_PARA FORMAT A110
COLUMN OTHER_CELL_PRICE FORMAT A30
COLUMN JUDGE FORMAT A44
COLUMN MSG FORMAT A240
COLUMN SEGMENT1 FORMAT A12
COLUMN SEGMENT2 FORMAT A14
COLUMN PROJECT_CODE FORMAT A16
SPOOL V06_SAVE_UNITPRICE_CHECK2_OUT.txt

PROMPT ################ [T1] ⭐ 판가 LOC 원장 — Cell Prod Site × 날짜 · 누가 언제 넣고 고쳤나 ################
SELECT SUBSTR(P.CELL_PROD_SITE_ID,1,10) CELL, P.YYYYMMDD, P.CURRENCY CUR, P.PRICE,
       SUBSTR(P.CREATED_BY,1,14) WHO, TO_CHAR(P.CREATION_DATE,'MM-DD HH24:MI:SS') AT,
       SUBSTR(P.LAST_UPDATED_BY,1,14) UPD_WHO, TO_CHAR(P.LAST_UPDATE_DATE,'MM-DD HH24:MI:SS') UPD_AT,
       SUBSTR('PJ[' || P.PROJECT_CODE || '] EC[' || P.END_CUSTOMER || '] PL[' || P.PLANT_SITE_ID || '] ' || P.DOM_EXP || '/' || P.FCST_TYPE || '/' || P.INCOTERMS,1,46) KEYS
  FROM DM_PLN_CFM_SELLING_PRICE P
 WHERE P.DIVISION_ID = '&P_DIV' AND P.SCM_SITE_ID = '&P_SITE' AND P.ITEM_ID = '&P_ITEM' AND P.MEASURE = 'LOC'
   AND P.YYYYMMDD >= TO_CHAR(SYSDATE - 14,'YYYYMMDD')
 ORDER BY P.YYYYMMDD, P.CELL_PROD_SITE_ID;

PROMPT ################ [T2] ⭐ 수요 원장 — 검증 대상 메저만 · Cell Prod Site × 날짜 · 누가 언제 ################
SELECT SUBSTR(A.MEASURE,1,12) MEASURE, SUBSTR(A.CELL_PROD_SITE_ID,1,10) CELL, A.YYYYMMDD, A.QTY,
       SUBSTR(A.CREATED_BY,1,14) WHO, TO_CHAR(A.CREATION_DATE,'MM-DD HH24:MI:SS') AT,
       SUBSTR(A.LAST_UPDATED_BY,1,14) UPD_WHO, TO_CHAR(A.LAST_UPDATE_DATE,'MM-DD HH24:MI:SS') UPD_AT,
       SUBSTR('PJ[' || A.PROJECT_CODE || '] EC[' || A.END_CUSTOMER || '] PL[' || A.PLANT_SITE_ID || '] ' || A.DOM_EXP || '/' || A.FCST_TYPE || '/' || A.INCOTERMS,1,46) KEYS
  FROM DM_PLN_CFM_MKT_DEMAND_PLAN A
 WHERE A.DIVISION_ID = '&P_DIV' AND A.SCM_SITE_ID = '&P_SITE' AND A.ITEM_ID = '&P_ITEM'
   AND A.MEASURE IN (SELECT SEGMENT2 FROM SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = 'MKT_FCST_VALIDATION_PRICE' AND SEGMENT1 = 'MEASURE' AND VALID_YN = 'Y')
   AND A.YYYYMMDD >= TO_CHAR(SYSDATE - 14,'YYYYMMDD') AND A.QTY <> 0
 ORDER BY A.MEASURE, A.YYYYMMDD, A.CELL_PROD_SITE_ID;

PROMPT ################ [T3] ⭐ 판정 — 수요 행별 '그 주 · 같은 Cell Prod Site' 판가 유무 (검증 대상 메저만) ################
PROMPT --  SAME_CELL_PRICE 가 비어 있고 JUDGE 가 '없음' 인 행 = 지금 원장 기준으로는 단가 검증에 걸려야 하는 수요
SELECT SUBSTR(A.MEASURE,1,12) MEASURE, SUBSTR(A.CELL_PROD_SITE_ID,1,10) CELL, A.YYYYMMDD, C.BASIS_START_DATE WEEK_START, A.QTY,
       (SELECT MAX(P.PRICE) FROM DM_PLN_CFM_SELLING_PRICE P
         WHERE P.DIVISION_ID = A.DIVISION_ID AND P.SCM_SITE_ID = A.SCM_SITE_ID AND P.ITEM_ID = A.ITEM_ID AND P.MEASURE = 'LOC' AND P.PRICE > 0
           AND P.PROJECT_CODE = A.PROJECT_CODE AND P.END_CUSTOMER = A.END_CUSTOMER AND P.PLANT_SITE_ID = A.PLANT_SITE_ID
           AND P.DOM_EXP = A.DOM_EXP AND P.FCST_TYPE = A.FCST_TYPE AND P.INCOTERMS = A.INCOTERMS
           AND P.CELL_PROD_SITE_ID = A.CELL_PROD_SITE_ID AND P.YYYYMMDD = C.BASIS_START_DATE) SAME_CELL_PRICE,
       (SELECT SUBSTR(LISTAGG(P.CELL_PROD_SITE_ID || '=' || P.PRICE, ', ') WITHIN GROUP (ORDER BY P.CELL_PROD_SITE_ID),1,30) FROM DM_PLN_CFM_SELLING_PRICE P
         WHERE P.DIVISION_ID = A.DIVISION_ID AND P.SCM_SITE_ID = A.SCM_SITE_ID AND P.ITEM_ID = A.ITEM_ID AND P.MEASURE = 'LOC' AND P.PRICE > 0
           AND P.PROJECT_CODE = A.PROJECT_CODE AND P.DOM_EXP = A.DOM_EXP AND P.FCST_TYPE = A.FCST_TYPE AND P.INCOTERMS = A.INCOTERMS
           AND P.CELL_PROD_SITE_ID <> A.CELL_PROD_SITE_ID AND P.YYYYMMDD = C.BASIS_START_DATE) OTHER_CELL_PRICE,
       CASE WHEN EXISTS (SELECT 1 FROM DM_PLN_CFM_SELLING_PRICE P
                          WHERE P.DIVISION_ID = A.DIVISION_ID AND P.SCM_SITE_ID = A.SCM_SITE_ID AND P.ITEM_ID = A.ITEM_ID AND P.MEASURE = 'LOC' AND P.PRICE > 0
                            AND P.PROJECT_CODE = A.PROJECT_CODE AND P.END_CUSTOMER = A.END_CUSTOMER AND P.PLANT_SITE_ID = A.PLANT_SITE_ID
                            AND P.DOM_EXP = A.DOM_EXP AND P.FCST_TYPE = A.FCST_TYPE AND P.INCOTERMS = A.INCOTERMS
                            AND P.CELL_PROD_SITE_ID = A.CELL_PROD_SITE_ID AND P.YYYYMMDD = C.BASIS_START_DATE)
            THEN '있음 — 검증 통과가 정상' ELSE '없음 — 검증에 걸려야 함' END JUDGE
  FROM DM_PLN_CFM_MKT_DEMAND_PLAN A
  JOIN SCM_SYS_CALENDAR_M C ON C.BASIS_YYYYMMDD = A.YYYYMMDD
 WHERE A.DIVISION_ID = '&P_DIV' AND A.SCM_SITE_ID = '&P_SITE' AND A.ITEM_ID = '&P_ITEM'
   AND A.MEASURE IN (SELECT SEGMENT2 FROM SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = 'MKT_FCST_VALIDATION_PRICE' AND SEGMENT1 = 'MEASURE' AND VALID_YN = 'Y')
   AND A.YYYYMMDD >= TO_CHAR(SYSDATE - 14,'YYYYMMDD') AND A.QTY <> 0
 ORDER BY A.MEASURE, A.YYYYMMDD, A.CELL_PROD_SITE_ID;

PROMPT ################ [T4] ⭐ 오늘 DMF0082 저장 SP 실행 이력 (최근 30건) ################
PROMPT --  START = 저장 시작(IN_PARA = 입력 앞부분) · END + 'FAIL-2' = 검증 차단(DESCRIPTION = 화면 메시지) · 그 외 END = 저장 완료
SELECT TO_CHAR(CREATION_DATE,'MM-DD HH24:MI:SS') AT, SUBSTR(CREATED_BY,1,14) WHO, SUBSTR(LOG_TYPE,1,8) LOG_TYPE, LOG_COUNT CNT,
       SUBSTR(LOG_MESSAGE,1,40) LOG_MESSAGE
  FROM SCM_SYS_LOG_BATCH
 WHERE PROGRAM_NAME = 'PKG_DMF0082' AND CREATION_DATE >= TRUNC(SYSDATE)
   AND LOG_TYPE IN ('START','END','INVALID','ERROR','error')
 ORDER BY CREATION_DATE DESC FETCH FIRST 30 ROWS ONLY;
SELECT TO_CHAR(CREATION_DATE,'MM-DD HH24:MI:SS') AT, SUBSTR(REPLACE(DESCRIPTION, CHR(10), ' / '),1,110) DESCRIPTION
  FROM SCM_SYS_LOG_BATCH
 WHERE PROGRAM_NAME = 'PKG_DMF0082' AND CREATION_DATE >= TRUNC(SYSDATE)
   AND LOG_TYPE IN ('END','INVALID','ERROR','error') AND DESCRIPTION IS NOT NULL
 ORDER BY CREATION_DATE DESC FETCH FIRST 15 ROWS ONLY;

PROMPT ################ [T5] ⭐ 오늘 화면 저장 호출 — 화면이 실제로 보낸 값 (최근 6건, 호출당 3줄) ################
PROMPT --  cellProdSiteId · measure · qtyPrice · yyyymmdd 가 줄바꿈('^' 또는 ',')으로 이어진다 — 오창A(HQ06-A)·남경A(NJ01-A) 가 어느 메저에 실렸는지 확인
SELECT TO_CHAR(L.TRNM_ST_DTM,'MM-DD HH24:MI:SS') ST, SUBSTR(L.CREATED_BY,1,14) WHO, N.PART,
       SUBSTR(L.SYS_LOG_MSG_CTN, (N.PART - 1) * 240 + 1, 240) MSG
  FROM (SELECT X.*, ROW_NUMBER() OVER (ORDER BY X.TRNM_ST_DTM DESC) RN
          FROM SCM_COM_SYS_LOG X
         WHERE X.MNU_ID = 'DMF0082' AND X.CREATION_DATE >= TRUNC(SYSDATE)
           AND X.SYS_LOG_MSG_CTN LIKE '%P_DMF0082_SAVE_MAIN_DATA%') L
 CROSS JOIN (SELECT LEVEL PART FROM DUAL CONNECT BY LEVEL <= 16) N
 WHERE L.RN <= 6
   AND (N.PART - 1) * 240 < LENGTH(L.SYS_LOG_MSG_CTN)
   AND SUBSTR(L.SYS_LOG_MSG_CTN, (N.PART - 1) * 240 + 1, 240) NOT LIKE '%jdbcType=%'
 ORDER BY L.TRNM_ST_DTM DESC, N.PART;

PROMPT ################ [T6] 검증 대상/제외 룩업 · Site-Item 조정 제외 여부 ################
SELECT SEGMENT1, SEGMENT2, VALID_YN
  FROM SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE = 'MKT_FCST_VALIDATION_PRICE'
 ORDER BY SEGMENT1, SEGMENT2;
SELECT SUBSTR(PROJECT_CODE,1,16) PROJECT_CODE, VALID_YN, SALES_PLAN_ADJUST_YN,
       CASE WHEN VALID_YN = 'Y' AND SALES_PLAN_ADJUST_YN = 'N' THEN '단가 검증 제외 대상' ELSE '단가 검증 대상' END JUDGE
  FROM SCM_MST_SITE_ITEM
 WHERE DIVISION_ID = '&P_DIV' AND SCM_SITE_ID = '&P_SITE' AND ITEM_ID = '&P_ITEM'
 ORDER BY PROJECT_CODE;

