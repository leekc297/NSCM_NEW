--   V05 는 BALANCE 메저 행(2027년까지 수십 주)과 넓은 컬럼 폭 때문에 출력이 잘려 핵심 구간이 전달되지 않았다.
--   이 파일은 ① 핵심 구간을 앞에 두고 ② 검증 대상 메저만 ③ 컬럼 폭을 줄여 한 화면에 들어오게 했다.
--   대상: Division 40 · Sales Site 'AJ상사_AB_TES' · Item 'MCCM356015A2' (DEFINE 3줄만 바꾸면 다른 건도 동일 점검)
