-- V05_SAVE_UNITPRICE_CHECK.sql — DMF0082 저장 시 '단가 없음(Unit Price Not Found)' 검증이 왜 통과했는지 판정 (READ-ONLY, 전체 F5)
--   계정: SCM_MGR · BE 가 붙은 클라우드 DB
--   신고(2026-10-12): Cell Prod Site 오창A 에 MKT_FCST, 남경A 에 LOC 를 입력했는데 오창A 단가 없음 검증 없이 정상 저장됨
--   대상: Division 40 · Sales Site 'AJ상사_AB_TES' · Item 'MCCM356015A2' (DEFINE 3줄만 바꾸면 다른 건도 동일 점검)
--   전체 F5 시 실행되는 것은 SELECT 뿐 · 값 입력 프롬프트 없음
--   저장 SP 의 단가 검증(P_DMF0082_SAVE_MAIN_DATA #10) 통과 조건 — 입력한 수량 행마다 아래 중 하나면 차단하지 않는다
--     ㉮ 같은 키(Project·End Customer·Site·Plant·**Cell Prod Site**·Model·Dom/Exp·Fcst Type·Incoterms)로 **그 주 시작일**에 LOC 판가 > 0 이
--        판가 원장(DM_PLN_CFM_SELLING_PRICE)에 이미 있거나, 같은 저장에 함께 들어옴
--     ㉯ 그 메저가 검증 대상 메저 목록(룩업 MKT_FCST_VALIDATION_PRICE / MEASURE)에 없음
--     ㉰ 그 Fcst Type 이 검증 제외 목록(룩업 MKT_FCST_VALIDATION_PRICE / FCST_TYPE)에 있음
--     ㉱ Site-Item 마스터가 판매계획 조정 제외(SALES_PLAN_ADJUST_YN='N')
--     ㉲ 입력 수량이 0
-- =============================================================================
SET LINESIZE 400
SET PAGESIZE 500
SET TRIMSPOOL ON
SET VERIFY OFF
SET DEFINE ON
DEFINE P_DIV  = '40'
DEFINE P_SITE = 'AJ상사_AB_TES'
DEFINE P_ITEM = 'MCCM356015A2'
COLUMN JUDGE FORMAT A80
COLUMN MSG FORMAT A200
COLUMN DESCRIPTION FORMAT A120
COLUMN IN_PARA FORMAT A120
SPOOL V05_SAVE_UNITPRICE_CHECK_OUT.txt

PROMPT ################ [S0] 접속 DB · 시각 ################
SELECT SYS_CONTEXT('USERENV','DB_NAME') DB_NAME, USER USR, TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI:SS') NOW FROM DUAL;

PROMPT ################ [S1] ⭐ 주차별 대조 — 수요 원장(Cell Prod Site 별) vs 판가 LOC(Cell Prod Site 별) ################
PROMPT --  수요는 40 계획 원장 DM_PLN_CFM_MKT_DEMAND_PLAN 기준. PRICE_SAME_CELL = 같은 Cell Prod Site 의 그 주 LOC 판가, PRICE_OTHER_CELL = 다른 Cell Prod Site 의 그 주 LOC 판가
PROMPT --  JUDGE '판가 있음' = 검증 통과가 정상 / '같은 사이트 판가 없음' = 저장 시점에 이 상태였다면 차단됐어야 함
WITH D AS (SELECT A.PROJECT_CODE, A.END_CUSTOMER, A.PLANT_SITE_ID, A.CELL_PROD_SITE_ID, A.DOM_EXP, A.FCST_TYPE, A.INCOTERMS, A.MEASURE,
                  C.BASIS_START_DATE WEEK_START, COUNT(*) ROW_CNT, SUM(A.QTY) QTY, MIN(A.YYYYMMDD) YMD_MIN, MAX(A.YYYYMMDD) YMD_MAX,
                  MAX(A.LAST_UPDATED_BY) KEEP (DENSE_RANK LAST ORDER BY A.LAST_UPDATE_DATE) UPD_BY,
                  TO_CHAR(MAX(A.LAST_UPDATE_DATE),'MM-DD HH24:MI:SS') UPD_AT
             FROM DM_PLN_CFM_MKT_DEMAND_PLAN A
             JOIN SCM_SYS_CALENDAR_M C ON C.BASIS_YYYYMMDD = A.YYYYMMDD
            WHERE A.DIVISION_ID = '&P_DIV' AND A.SCM_SITE_ID = '&P_SITE' AND A.ITEM_ID = '&P_ITEM'
              AND A.YYYYMMDD >= TO_CHAR(SYSDATE - 14,'YYYYMMDD') AND A.QTY <> 0
            GROUP BY A.PROJECT_CODE, A.END_CUSTOMER, A.PLANT_SITE_ID, A.CELL_PROD_SITE_ID, A.DOM_EXP, A.FCST_TYPE, A.INCOTERMS, A.MEASURE, C.BASIS_START_DATE)
SELECT D.MEASURE, D.WEEK_START, '[' || D.CELL_PROD_SITE_ID || ']' DEMAND_CELL, D.QTY, D.YMD_MIN, D.YMD_MAX, D.UPD_BY DEMAND_BY, D.UPD_AT DEMAND_AT,
       (SELECT MAX(P.PRICE) FROM DM_PLN_CFM_SELLING_PRICE P
         WHERE P.DIVISION_ID = '&P_DIV' AND P.SCM_SITE_ID = '&P_SITE' AND P.ITEM_ID = '&P_ITEM' AND P.MEASURE = 'LOC' AND P.PRICE > 0
           AND P.PROJECT_CODE = D.PROJECT_CODE AND P.END_CUSTOMER = D.END_CUSTOMER AND P.PLANT_SITE_ID = D.PLANT_SITE_ID
           AND P.DOM_EXP = D.DOM_EXP AND P.FCST_TYPE = D.FCST_TYPE AND P.INCOTERMS = D.INCOTERMS
           AND P.CELL_PROD_SITE_ID = D.CELL_PROD_SITE_ID AND P.YYYYMMDD = D.WEEK_START) PRICE_SAME_CELL,
       (SELECT LISTAGG(P.CELL_PROD_SITE_ID || '=' || P.PRICE, ', ') WITHIN GROUP (ORDER BY P.CELL_PROD_SITE_ID) FROM DM_PLN_CFM_SELLING_PRICE P
         WHERE P.DIVISION_ID = '&P_DIV' AND P.SCM_SITE_ID = '&P_SITE' AND P.ITEM_ID = '&P_ITEM' AND P.MEASURE = 'LOC' AND P.PRICE > 0
           AND P.PROJECT_CODE = D.PROJECT_CODE AND P.DOM_EXP = D.DOM_EXP AND P.FCST_TYPE = D.FCST_TYPE AND P.INCOTERMS = D.INCOTERMS
           AND P.CELL_PROD_SITE_ID <> D.CELL_PROD_SITE_ID AND P.YYYYMMDD = D.WEEK_START) PRICE_OTHER_CELL,
       CASE WHEN EXISTS (SELECT 1 FROM DM_PLN_CFM_SELLING_PRICE P
                          WHERE P.DIVISION_ID = '&P_DIV' AND P.SCM_SITE_ID = '&P_SITE' AND P.ITEM_ID = '&P_ITEM' AND P.MEASURE = 'LOC' AND P.PRICE > 0
                            AND P.PROJECT_CODE = D.PROJECT_CODE AND P.END_CUSTOMER = D.END_CUSTOMER AND P.PLANT_SITE_ID = D.PLANT_SITE_ID
                            AND P.DOM_EXP = D.DOM_EXP AND P.FCST_TYPE = D.FCST_TYPE AND P.INCOTERMS = D.INCOTERMS
                            AND P.CELL_PROD_SITE_ID = D.CELL_PROD_SITE_ID AND P.YYYYMMDD = D.WEEK_START)
            THEN '판가 있음 (같은 Cell Prod Site · 그 주)' ELSE '같은 사이트 판가 없음' END JUDGE
  FROM D
 ORDER BY D.MEASURE, D.WEEK_START, D.CELL_PROD_SITE_ID;

PROMPT ################ [S2] ⭐ 판가 LOC 원장 — Cell Prod Site × 주차별 행 · 누가 언제 넣었나 ################
PROMPT --  CREATED_AT 이 수요 저장 시각([S1] DEMAND_AT · [S5]) 보다 **앞**이면 = 저장 당시 이미 판가가 있어 검증 통과가 정상
SELECT '[' || P.CELL_PROD_SITE_ID || ']' CELL_PROD, P.YYYYMMDD, P.CURRENCY, P.PRICE,
       '[' || P.PROJECT_CODE || ']' PROJECT_CODE, '[' || P.END_CUSTOMER || ']' END_CUSTOMER, '[' || P.PLANT_SITE_ID || ']' PLANT,
       '[' || P.DOM_EXP || ']' DOM_EXP, '[' || P.FCST_TYPE || ']' FCST_TYPE, '[' || P.INCOTERMS || ']' INCOTERMS,
       P.CREATED_BY, TO_CHAR(P.CREATION_DATE,'MM-DD HH24:MI:SS') CREATED_AT,
       P.LAST_UPDATED_BY, TO_CHAR(P.LAST_UPDATE_DATE,'MM-DD HH24:MI:SS') UPDATED_AT
  FROM DM_PLN_CFM_SELLING_PRICE P
 WHERE P.DIVISION_ID = '&P_DIV' AND P.SCM_SITE_ID = '&P_SITE' AND P.ITEM_ID = '&P_ITEM' AND P.MEASURE = 'LOC'
   AND P.YYYYMMDD >= TO_CHAR(SYSDATE - 14,'YYYYMMDD')
 ORDER BY P.YYYYMMDD, P.CELL_PROD_SITE_ID;

PROMPT ################ [S3] 검증 대상/제외 룩업 (MKT_FCST_VALIDATION_PRICE) — ㉯ ㉰ ################
PROMPT --  SEGMENT1='MEASURE' 목록에 MKT_FCST 가 없으면 MKT_FCST 입력은 단가 검증을 타지 않는다. SEGMENT1='FCST_TYPE' 목록의 유형은 검증 제외
SELECT SEGMENT1, SEGMENT2, VALID_YN, LAST_UPDATED_BY, TO_CHAR(LAST_UPDATE_DATE,'YYYY-MM-DD HH24:MI') UPD
  FROM SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE = 'MKT_FCST_VALIDATION_PRICE'
 ORDER BY SEGMENT1, SEGMENT2;

PROMPT ################ [S4] Site-Item 마스터 — 판매계획 조정 제외 여부 ㉱ ################
SELECT '[' || PROJECT_CODE || ']' PROJECT_CODE, VALID_YN, SALES_PLAN_ADJUST_YN,
       CASE WHEN VALID_YN = 'Y' AND SALES_PLAN_ADJUST_YN = 'N' THEN '단가 검증 제외 대상 (㉱) — 이 품목은 판가 없이 저장된다' ELSE '단가 검증 대상' END JUDGE
  FROM SCM_MST_SITE_ITEM
 WHERE DIVISION_ID = '&P_DIV' AND SCM_SITE_ID = '&P_SITE' AND ITEM_ID = '&P_ITEM'
 ORDER BY PROJECT_CODE;

PROMPT ################ [S5] ⭐ 오늘 DMF0082 저장 SP 실행 이력 — 시작/종료/검증 차단 ################
PROMPT --  LOG_TYPE START = 저장 시작(IN_PARA = 입력 앞부분) · END + 'FAIL-2' = 검증 차단(DESCRIPTION = 화면 메시지) · END 정상 = 저장 완료
SELECT TO_CHAR(CREATION_DATE,'MM-DD HH24:MI:SS') AT, CREATED_BY, LOG_TYPE, LOG_COUNT, SUBSTR(LOG_MESSAGE,1,60) LOG_MESSAGE,
       SUBSTR(REPLACE(DESCRIPTION, CHR(10), ' / '),1,120) DESCRIPTION, SUBSTR(IN_PARA_DATA,1,120) IN_PARA
  FROM SCM_SYS_LOG_BATCH
 WHERE PROGRAM_NAME = 'PKG_DMF0082' AND CREATION_DATE >= TRUNC(SYSDATE)
   AND LOG_TYPE IN ('START','END','INVALID','ERROR','error')
 ORDER BY CREATION_DATE DESC FETCH FIRST 60 ROWS ONLY;

PROMPT ################ [S6] ⭐ 오늘 화면 저장 호출 — 실제 전송된 입력 (BE 로그, 앞 3,900자) ################
PROMPT --  cellProdSiteId / measure / qtyPrice 순서로 화면이 보낸 값이 그대로 보인다 — 오창A·남경A 가 각각 어느 메저 행에 실려 갔는지 확인
SELECT TO_CHAR(TRNM_ST_DTM,'MM-DD HH24:MI:SS') ST, CREATED_BY, SHT_NM,
       SUBSTR(SYS_LOG_MSG_CTN, 1, 1300) MSG
  FROM SCM_COM_SYS_LOG
 WHERE MNU_ID = 'DMF0082' AND CREATION_DATE >= TRUNC(SYSDATE)
   AND SYS_LOG_MSG_CTN LIKE '%P_DMF0082_SAVE_MAIN_DATA%'
 ORDER BY TRNM_ST_DTM DESC FETCH FIRST 10 ROWS ONLY;
SELECT TO_CHAR(TRNM_ST_DTM,'MM-DD HH24:MI:SS') ST, SUBSTR(SYS_LOG_MSG_CTN, 1301, 1300) MSG_2
  FROM SCM_COM_SYS_LOG
 WHERE MNU_ID = 'DMF0082' AND CREATION_DATE >= TRUNC(SYSDATE)
   AND SYS_LOG_MSG_CTN LIKE '%P_DMF0082_SAVE_MAIN_DATA%'
 ORDER BY TRNM_ST_DTM DESC FETCH FIRST 10 ROWS ONLY;
SELECT TO_CHAR(TRNM_ST_DTM,'MM-DD HH24:MI:SS') ST, SUBSTR(SYS_LOG_MSG_CTN, 2601, 1300) MSG_3
  FROM SCM_COM_SYS_LOG
 WHERE MNU_ID = 'DMF0082' AND CREATION_DATE >= TRUNC(SYSDATE)
   AND SYS_LOG_MSG_CTN LIKE '%P_DMF0082_SAVE_MAIN_DATA%'
 ORDER BY TRNM_ST_DTM DESC FETCH FIRST 10 ROWS ONLY;

