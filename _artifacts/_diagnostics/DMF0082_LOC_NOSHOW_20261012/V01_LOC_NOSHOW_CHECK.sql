PROMPT ################ [V0] 접속 DB · 시각 · PKG 판본 ################
SELECT SYS_CONTEXT('USERENV','DB_NAME') DB_NAME, SYS_CONTEXT('USERENV','SERVER_HOST') HOST, USER USR,
