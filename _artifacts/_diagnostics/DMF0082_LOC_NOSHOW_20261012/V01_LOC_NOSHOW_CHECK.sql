--   대상: Division 40 · Sales Site 'AJ상사_AB_TES' · Item 'MCCM356015A2' · 사용자 k0101  (아래 DEFINE 4줄만 바꾸면 다른 건도 동일 점검)
--   전체 F5 시 실행되는 것은 SELECT 뿐 (INSERT/UPDATE/DELETE/DDL 없음 · 값 입력 프롬프트 없음)
--   기준 원문: 사내 ZIOUI1 PKG_DMF0082 BODY (LAST_DDL 2026-10-12 10:46:19, 조회 2026-10-12 15:56) P_DMF0082_GET_MAIN_DATA
--     LOC(40) 행이 조회되려면 아래 5 조건을 모두 통과해야 한다 (괄호 = BODY 줄번호)
--       ① 사용자 메저 선택에 LOC 존재  : SCM_MST_TITLESET_USER(USER_ID·'DMF0082'·'FcstNPrice'·'M'·'LOC') + SHEET_MEASURE VALID_YN='Y' (L1128~1145)
--          → 없으면 LOC 는 'DM_ADMIN' 강제 포함분(L1194)으로만 들어가고 최종 단계에서 전량 삭제된다 (L3646)
--       ② 판가 원장에 MEASURE='LOC' 행  : DM_PLN_CFM_SELLING_PRICE (L1930)
--       ③ 계획구간 안의 날짜           : YYYYMMDD BETWEEN 당주 월요일 AND 조회 To (L1963 · 경계 계산 L564~599)
--       ④ 조회 대상 Site-Item 과 키 일치 : DIVISION_ID·PROJECT_CODE·SCM_SITE_ID·ITEM_ID (L1948~1953)
--       ⑤ FCST_TYPE 이 판매유형 룩업에 존재 : SCM_ADM_LOOKUP_MASTER_DETAIL LOOKUP_TYPE='SALES_TYPE_CODE' SEGMENT1 (L545 · L1959)
--     추가: 화면 'Qty >= 0' 체크 시 9축 키(END_CUSTOMER·CELL_PROD_SITE_ID 포함)에 MKT_FCST/SCM_FCST 합계<>0 이 없으면 삭제 (L3763)
-- =============================================================================
