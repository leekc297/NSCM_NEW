SELECT OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL
  FROM USER_OBJECTS WHERE OBJECT_NAME = 'PKG_DMF0082' ORDER BY OBJECT_TYPE;

PROMPT ################ [V1] ⭐ 조건① 사용자 메저 선택 — &P_USER 의 DMF0082 메저(M) 목록 ################
PROMPT --  SP 는 USER_ID·PROGRAM_ID·SHEET_NAME 을 대소문자 그대로 비교한다. EXACT_MATCH=N 인 행은 SP 가 읽지 못한다.
SELECT U.USER_ID, U.PROGRAM_ID, U.SHEET_NAME, U.COLUMN_NAME, U.SORT_ORDER_NO,
       TO_CHAR(U.LAST_UPDATE_DATE,'MM-DD HH24:MI:SS') UPD, M.VALID_YN MEASURE_VALID,
       CASE WHEN U.USER_ID = '&P_USER' AND U.PROGRAM_ID = 'DMF0082' AND U.SHEET_NAME = 'FcstNPrice' THEN 'Y' ELSE 'N' END EXACT_MATCH
  FROM SCM_MST_TITLESET_USER U
  LEFT JOIN SCM_MST_SHEET_MEASURE M
    ON M.PROGRAM_ID = U.PROGRAM_ID AND M.SHEET_NAME = U.SHEET_NAME AND M.COLUMN_NAME = U.COLUMN_NAME
 WHERE UPPER(U.USER_ID) = UPPER('&P_USER')
   AND UPPER(U.PROGRAM_ID) = 'DMF0082'
   AND U.USER_INQUIRY_COLUMN_TYPE_CODE = 'M'
 ORDER BY U.SHEET_NAME, U.SORT_ORDER_NO;
SELECT CASE WHEN COUNT(*) > 0 THEN 'PASS — LOC 선택 저장됨 (' || COUNT(*) || '행)'
            ELSE 'FAIL — LOC 가 사용자 메저 선택에 없음 → SP 가 LOC 행을 최종 삭제 (L3646). 화면 메저 선택 저장이 DB 에 안 들어간 것' END JUDGE
  FROM SCM_MST_TITLESET_USER U
  JOIN SCM_MST_SHEET_MEASURE M
    ON M.PROGRAM_ID = U.PROGRAM_ID AND M.SHEET_NAME = U.SHEET_NAME AND M.COLUMN_NAME = U.COLUMN_NAME AND M.VALID_YN = 'Y'
 WHERE U.USER_ID = '&P_USER' AND U.PROGRAM_ID = 'DMF0082' AND U.SHEET_NAME = 'FcstNPrice'
   AND U.USER_INQUIRY_COLUMN_TYPE_CODE = 'M' AND U.COLUMN_NAME = 'LOC';

PROMPT ################ [V2] 메저 마스터 — LOC/KRW/USD 등록 상태 (사내 기준: 3행 모두 SHEET_NAME='FcstNPrice' · VALID_YN='Y') ################
SELECT PROGRAM_ID, SHEET_NAME, COLUMN_NAME, SORT_ORDER_NO, VALID_YN, USER_SELECTABLE_FLAG, DEFAULT_FLAG, DIVISION_ID, INPUT_TP_CD
  FROM SCM_MST_SHEET_MEASURE
 WHERE UPPER(PROGRAM_ID) = 'DMF0082' AND COLUMN_NAME IN ('LOC','KRW','USD','MKT_FCST')
 ORDER BY SHEET_NAME, SORT_ORDER_NO;

PROMPT ################ [V3] 조건③ 기준 — 실적/계획 경계 = 당주 월요일 (판가 LOC 는 이 날짜 이후 분만 조회된다) ################
SELECT TO_CHAR(SYSDATE,'YYYYMMDD') TODAY, MIN(C.BASIS_YYYYMMDD) THIS_MONDAY
  FROM SCM_SYS_CALENDAR_M C
 WHERE C.ISO_YYYYWW = (SELECT MIN(ISO_YYYYWW) FROM SCM_SYS_CALENDAR_M WHERE BASIS_YYYYMMDD = TO_CHAR(SYSDATE,'YYYYMMDD'));
PROMPT --  THIS_MONDAY 가 NULL = 캘린더에 오늘 없음. 조회 From 이 이번 주 이후면 경계는 19000101(전 기간 계획)로 바뀐다.

PROMPT ################ [V4] ⭐ 조건②③ 판가 원장 — 메저·통화별 건수와 기간 (PLAN_ROWS = 당주 월요일 이후 행수) ################
WITH MON AS (SELECT MIN(C.BASIS_YYYYMMDD) D FROM SCM_SYS_CALENDAR_M C
              WHERE C.ISO_YYYYWW = (SELECT MIN(ISO_YYYYWW) FROM SCM_SYS_CALENDAR_M WHERE BASIS_YYYYMMDD = TO_CHAR(SYSDATE,'YYYYMMDD')))
SELECT P.MEASURE, P.CURRENCY, COUNT(*) ROWS_ALL, MIN(P.YYYYMMDD) YMD_MIN, MAX(P.YYYYMMDD) YMD_MAX,
       SUM(CASE WHEN P.YYYYMMDD >= (SELECT D FROM MON) THEN 1 ELSE 0 END) PLAN_ROWS,
       SUM(CASE WHEN P.YYYYMMDD >= (SELECT D FROM MON) AND P.PRICE <> 0 THEN 1 ELSE 0 END) PLAN_NONZERO,
       TO_CHAR(MAX(P.LAST_UPDATE_DATE),'MM-DD HH24:MI') LAST_UPD
  FROM DM_PLN_CFM_SELLING_PRICE P
 WHERE P.DIVISION_ID = '&P_DIV' AND P.SCM_SITE_ID = '&P_SITE' AND P.ITEM_ID = '&P_ITEM'
 GROUP BY P.MEASURE, P.CURRENCY
 ORDER BY P.MEASURE, P.CURRENCY;
PROMPT --  MEASURE='LOC' 행이 없다 = 조건② 탈락 (원장에 KRW/USD 만 있음). LOC 의 PLAN_ROWS=0 = 조건③ 탈락 (과거 판가만 있음).
PROMPT --  0 rows = 이 Site-Item 판가 자체가 없음 (DEFINE 값의 공백·전각문자 확인)

PROMPT ################ [V5] ⭐ 조건④ 키 대조 — 수요(MKT_FCST) 키 vs 판가(LOC) 키 · 값이 한 글자라도 다르면 다른 행으로 갈린다 ################
PROMPT --  SIDE: BOTH = 양쪽 일치 · FCST_ONLY = 수요만 · PRICE_ONLY = 판가만.  '-' 와 '/' 차이(빈값 표기) 도 불일치다.
WITH MON AS (SELECT MIN(C.BASIS_YYYYMMDD) D FROM SCM_SYS_CALENDAR_M C
              WHERE C.ISO_YYYYWW = (SELECT MIN(ISO_YYYYWW) FROM SCM_SYS_CALENDAR_M WHERE BASIS_YYYYMMDD = TO_CHAR(SYSDATE,'YYYYMMDD'))),
F AS (SELECT PROJECT_CODE, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, COUNT(*) CNT, MIN(YYYYMMDD) YMD_MIN, MAX(YYYYMMDD) YMD_MAX
        FROM DM_PLN_MKT_FCST
       WHERE DIVISION_ID = '&P_DIV' AND SCM_SITE_ID = '&P_SITE' AND ITEM_ID = '&P_ITEM' AND MEASURE = 'MKT_FCST'
         AND YYYYMMDD >= (SELECT D FROM MON)
       GROUP BY PROJECT_CODE, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID),
P AS (SELECT PROJECT_CODE, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, COUNT(*) CNT, MIN(YYYYMMDD) YMD_MIN, MAX(YYYYMMDD) YMD_MAX,
             MIN(END_CUSTOMER) END_CUST_MIN, MAX(END_CUSTOMER) END_CUST_MAX, MIN(CELL_PROD_SITE_ID) CELL_MIN, MAX(CELL_PROD_SITE_ID) CELL_MAX
        FROM DM_PLN_CFM_SELLING_PRICE
       WHERE DIVISION_ID = '&P_DIV' AND SCM_SITE_ID = '&P_SITE' AND ITEM_ID = '&P_ITEM' AND MEASURE = 'LOC'
         AND YYYYMMDD >= (SELECT D FROM MON)
       GROUP BY PROJECT_CODE, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID)
SELECT CASE WHEN F.CNT IS NOT NULL AND P.CNT IS NOT NULL THEN 'BOTH' WHEN F.CNT IS NOT NULL THEN 'FCST_ONLY' ELSE 'PRICE_ONLY' END SIDE,
       '[' || NVL(F.PROJECT_CODE, P.PROJECT_CODE) || ']' PROJECT_CODE,
       '[' || NVL(F.DOM_EXP, P.DOM_EXP) || ']' DOM_EXP,
       '[' || NVL(F.FCST_TYPE, P.FCST_TYPE) || ']' FCST_TYPE,
       '[' || NVL(F.INCOTERMS, P.INCOTERMS) || ']' INCOTERMS,
       '[' || NVL(F.PLANT_SITE_ID, P.PLANT_SITE_ID) || ']' PLANT_SITE_ID,
       F.CNT FCST_ROWS, F.YMD_MIN FCST_FROM, F.YMD_MAX FCST_TO,
       P.CNT LOC_ROWS, P.YMD_MIN LOC_FROM, P.YMD_MAX LOC_TO,
       '[' || P.END_CUST_MIN || ']~[' || P.END_CUST_MAX || ']' LOC_END_CUSTOMER,
       '[' || P.CELL_MIN || ']~[' || P.CELL_MAX || ']' LOC_CELL_PROD_SITE
  FROM F FULL OUTER JOIN P
    ON  P.PROJECT_CODE = F.PROJECT_CODE AND P.DOM_EXP = F.DOM_EXP AND P.FCST_TYPE = F.FCST_TYPE
    AND P.INCOTERMS = F.INCOTERMS AND P.PLANT_SITE_ID = F.PLANT_SITE_ID
 ORDER BY 2, 3, 4, 5, 6, 1;
PROMPT --  BOTH 가 없고 FCST_ONLY / PRICE_ONLY 로 갈려 있으면 = 판가는 조회돼도 수요 행과 다른 줄로 나오거나('Qty >= 0' 체크 시) 삭제된다.

PROMPT ################ [V6] 조건④ Site-Item 마스터 — 판가(LOC)·수요의 PROJECT_CODE 가 마스터에 있는가 ################
SELECT X.SRC, '[' || X.PROJECT_CODE || ']' PROJECT_CODE, S.VALID_YN, S.DEPT_ID, S.OWNER,
       CASE WHEN S.PROJECT_CODE IS NULL THEN 'FAIL — SCM_MST_SITE_ITEM 에 이 PROJECT_CODE 조합 없음 → 해당 원장 행 조회 제외'
            ELSE 'PASS' END JUDGE
  FROM (SELECT DISTINCT 'PRICE_LOC' SRC, PROJECT_CODE FROM DM_PLN_CFM_SELLING_PRICE
         WHERE DIVISION_ID = '&P_DIV' AND SCM_SITE_ID = '&P_SITE' AND ITEM_ID = '&P_ITEM' AND MEASURE = 'LOC'
        UNION ALL
        SELECT DISTINCT 'MKT_FCST', PROJECT_CODE FROM DM_PLN_MKT_FCST
         WHERE DIVISION_ID = '&P_DIV' AND SCM_SITE_ID = '&P_SITE' AND ITEM_ID = '&P_ITEM' AND MEASURE = 'MKT_FCST') X
  LEFT JOIN SCM_MST_SITE_ITEM S
    ON S.DIVISION_ID = '&P_DIV' AND S.SCM_SITE_ID = '&P_SITE' AND S.ITEM_ID = '&P_ITEM' AND S.PROJECT_CODE = X.PROJECT_CODE
 ORDER BY X.SRC, X.PROJECT_CODE;

PROMPT ################ [V7] 조건⑤ 판가(LOC) 의 FCST_TYPE 이 판매유형 룩업(SALES_TYPE_CODE)에 있는가 ################
SELECT '[' || P.FCST_TYPE || ']' FCST_TYPE, COUNT(*) LOC_ROWS,
       CASE WHEN EXISTS (SELECT 1 FROM SCM_ADM_LOOKUP_MASTER_DETAIL L WHERE L.LOOKUP_TYPE = 'SALES_TYPE_CODE' AND L.SEGMENT1 = P.FCST_TYPE)
            THEN 'PASS' ELSE 'FAIL — 룩업에 없는 FCST_TYPE → 판가 행 조회 제외 (L1959)' END JUDGE
  FROM DM_PLN_CFM_SELLING_PRICE P
 WHERE P.DIVISION_ID = '&P_DIV' AND P.SCM_SITE_ID = '&P_SITE' AND P.ITEM_ID = '&P_ITEM' AND P.MEASURE = 'LOC'
 GROUP BY P.FCST_TYPE
 ORDER BY 1;

PROMPT ################ [V8] ⭐⭐ 종합 판정 — 조건 ①~⑤ 한 줄 요약 (FAIL 이 나온 조건이 원인) ################
WITH MON AS (SELECT MIN(C.BASIS_YYYYMMDD) D FROM SCM_SYS_CALENDAR_M C
              WHERE C.ISO_YYYYWW = (SELECT MIN(ISO_YYYYWW) FROM SCM_SYS_CALENDAR_M WHERE BASIS_YYYYMMDD = TO_CHAR(SYSDATE,'YYYYMMDD'))),
P AS (SELECT P.*, CASE WHEN P.YYYYMMDD >= (SELECT D FROM MON) THEN 1 ELSE 0 END IN_PLAN
        FROM DM_PLN_CFM_SELLING_PRICE P
       WHERE P.DIVISION_ID = '&P_DIV' AND P.SCM_SITE_ID = '&P_SITE' AND P.ITEM_ID = '&P_ITEM' AND P.MEASURE = 'LOC')
SELECT (SELECT CASE WHEN COUNT(*) > 0 THEN 'PASS' ELSE 'FAIL' END
          FROM SCM_MST_TITLESET_USER U JOIN SCM_MST_SHEET_MEASURE M
            ON M.PROGRAM_ID = U.PROGRAM_ID AND M.SHEET_NAME = U.SHEET_NAME AND M.COLUMN_NAME = U.COLUMN_NAME AND M.VALID_YN = 'Y'
         WHERE U.USER_ID = '&P_USER' AND U.PROGRAM_ID = 'DMF0082' AND U.SHEET_NAME = 'FcstNPrice'
           AND U.USER_INQUIRY_COLUMN_TYPE_CODE = 'M' AND U.COLUMN_NAME = 'LOC') C1_USER_MEASURE,
       (SELECT CASE WHEN COUNT(*) > 0 THEN 'PASS (' || COUNT(*) || ')' ELSE 'FAIL' END FROM P) C2_LOC_ROWS,
       (SELECT CASE WHEN NVL(SUM(IN_PLAN),0) > 0 THEN 'PASS (' || SUM(IN_PLAN) || ')' ELSE 'FAIL' END FROM P) C3_IN_PLAN_PERIOD,
       (SELECT CASE WHEN COUNT(*) > 0 THEN 'PASS (' || COUNT(*) || ')' ELSE 'FAIL' END
          FROM P JOIN SCM_MST_SITE_ITEM S
            ON S.DIVISION_ID = P.DIVISION_ID AND S.PROJECT_CODE = P.PROJECT_CODE AND S.SCM_SITE_ID = P.SCM_SITE_ID AND S.ITEM_ID = P.ITEM_ID
         WHERE P.IN_PLAN = 1) C4_SITE_ITEM_KEY,
       (SELECT CASE WHEN COUNT(*) > 0 THEN 'PASS (' || COUNT(*) || ')' ELSE 'FAIL' END
          FROM P
         WHERE P.IN_PLAN = 1
           AND EXISTS (SELECT 1 FROM SCM_ADM_LOOKUP_MASTER_DETAIL L WHERE L.LOOKUP_TYPE = 'SALES_TYPE_CODE' AND L.SEGMENT1 = P.FCST_TYPE)) C5_FCST_TYPE,
       (SELECT CASE WHEN COUNT(*) > 0 THEN 'PASS (' || COUNT(*) || ')' ELSE 'FAIL' END
          FROM P JOIN SCM_MST_SITE_ITEM S
            ON S.DIVISION_ID = P.DIVISION_ID AND S.PROJECT_CODE = P.PROJECT_CODE AND S.SCM_SITE_ID = P.SCM_SITE_ID AND S.ITEM_ID = P.ITEM_ID
         WHERE P.IN_PLAN = 1
           AND EXISTS (SELECT 1 FROM SCM_ADM_LOOKUP_MASTER_DETAIL L WHERE L.LOOKUP_TYPE = 'SALES_TYPE_CODE' AND L.SEGMENT1 = P.FCST_TYPE)) ALL_2_TO_5
  FROM DUAL;
PROMPT --  C1 FAIL                = 메저 선택이 DB 에 저장되지 않음 (화면 메저 팝업 저장 경로 확인)
PROMPT --  C2 FAIL                = 판가 원장에 LOC 메저 행 없음 (KRW/USD 만 존재 — [V4])
PROMPT --  C3 FAIL                = LOC 판가가 당주 월요일 이전 날짜뿐
PROMPT --  C4 FAIL                = 판가의 PROJECT_CODE 가 Site-Item 마스터와 불일치 ([V5][V6])
PROMPT --  전부 PASS 인데 안 보임 = DB 원인 아님 → [V9] 의 실제 조회 파라미터(기간·Qty 체크·버전) 와 화면 표시 쪽 확인
PROMPT --  ※ C4 는 마스터 원본(SCM_MST_SITE_ITEM) 존재만 본다. SP 는 여기에 품목 유효·조회조건 필터를 더 건다 — MKT_FCST 가 화면에 보이면 그 필터는 통과한 것.

PROMPT ################ [V9] 최근 120 분 &P_USER 의 DMF0082 호출 이력 — 실제 전달된 조회 파라미터 ################
SELECT TO_CHAR(TRNM_ST_DTM,'MM-DD HH24:MI:SS') ST, SHT_NM,
       ROUND((CAST(TRNM_END_DTM AS DATE) - CAST(TRNM_ST_DTM AS DATE))*86400, 1) SERVER_S,
       SUBSTR(SYS_LOG_MSG_CTN,1,200) MSG, SUBSTR(EXCT_MSG_CTN,1,120) ERR
  FROM SCM_COM_SYS_LOG
 WHERE MNU_ID = 'DMF0082' AND CREATION_DATE >= SYSDATE - 120/1440
   AND UPPER(CREATED_BY) = UPPER('&P_USER')
 ORDER BY TRNM_ST_DTM DESC FETCH FIRST 20 ROWS ONLY;

