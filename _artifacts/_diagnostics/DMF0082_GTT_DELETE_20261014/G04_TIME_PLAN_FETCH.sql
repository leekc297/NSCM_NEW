PROMPT ################ [I0] ⭐ 시각 기준 확인 — DB 시각 vs 화면 로그 시각 (시간대 차이 판정) ################
SELECT TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI:SS') DB_SYSDATE, TO_CHAR(SYSTIMESTAMP,'YYYY-MM-DD HH24:MI:SS TZH:TZM') DB_SYSTIMESTAMP,
       DBTIMEZONE DB_TZ, SESSIONTIMEZONE SESS_TZ FROM DUAL;
SELECT COUNT(*) DMF0082_SEARCH_24H,
       TO_CHAR(MAX(L.CREATION_DATE),'YYYY-MM-DD HH24:MI:SS') MAX_CREATION_DATE,
       TO_CHAR(MAX(L.LOG_ST_DTM),'YYYY-MM-DD HH24:MI:SS') MAX_LOG_ST,
       TO_CHAR(MAX(L.DB_TRNM_ST_DTM),'YYYY-MM-DD HH24:MI:SS') MAX_DB_TRNM_ST,
       ROUND((SYSDATE - MAX(L.CREATION_DATE)) * 24, 2) HOURS_BEHIND_SYSDATE
  FROM SCM_COM_SYS_LOG L
 WHERE L.MNU_ID = 'DMF0082' AND L.SHT_NM = 'FcstNPrice' AND L.MNU_BTN_CD = 'SEARCH'
   AND L.CREATION_DATE >= SYSDATE - 2;
PROMPT --  HOURS_BEHIND_SYSDATE 가 약 9 (또는 -9) 이면 로그가 UTC/KST 다른 시간대로 기록됨 → [I1] 은 시간 조건 없이 최근 10건으로 본다
SELECT TO_CHAR(MAX(H.SAMPLE_TIME),'YYYY-MM-DD HH24:MI:SS') ASH_LAST_PKG_SAMPLE
  FROM GV$ACTIVE_SESSION_HISTORY H
 WHERE H.PLSQL_ENTRY_OBJECT_ID = (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME = 'PKG_DMF0082' AND OBJECT_TYPE = 'PACKAGE');
PROMPT --  ASH_LAST_PKG_SAMPLE(마지막 조회 시각, DB 기준) 와 MAX_LOG_ST 의 차이 = 로그 시각 오프셋

PROMPT ################ [I1] ⭐⭐ 최근 DMF0082 조회 10건 (시간 조건 없음) — DB 구간 / BE 구간 (초) ################
PROMPT --  DB_SEC = SP 실행 + 결과 커서 수신(fetch). [I3] 의 SP 1회(9~11초) 와 비교해 DB_SEC 가 훨씬 크면 fetch 가 병목
SELECT TO_CHAR(L.LOG_ST_DTM,'MM-DD HH24:MI:SS') LOG_ST, L.CREATED_BY USR,
       REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"divisionId":"([^"]*)"',1,1,NULL,1) DIV,
       REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"versionType":"([^"]*)"',1,1,NULL,1) VER,
       NVL(RTRIM(CASE WHEN NVL(REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"projectCode":"([^"]*)"',1,1,NULL,1),'ALL') <> 'ALL' THEN 'Project,' END ||
                 CASE WHEN NVL(REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"owner":"([^"]*)"',1,1,NULL,1),'ALL') <> 'ALL' THEN 'Owner,' END ||
                 CASE WHEN NVL(REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"deptId":"([^"]*)"',1,1,NULL,1),'ALL') <> 'ALL' THEN 'Team,' END ||
                 CASE WHEN NVL(REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"salesSite":"([^"]*)"',1,1,NULL,1),'ALL') <> 'ALL' THEN 'SalesSite,' END, ','), '(미지정)') FILTERS,
       ROUND((CAST(L.LOG_END_DTM AS DATE) - CAST(L.LOG_ST_DTM AS DATE)) * 86400, 1) TOTAL,
       ROUND((CAST(L.DB_TRNM_ST_DTM AS DATE) - CAST(L.LOG_ST_DTM AS DATE)) * 86400, 1) PRE_DB,
       ROUND((CAST(L.DB_TRNM_END_DTM AS DATE) - CAST(L.DB_TRNM_ST_DTM AS DATE)) * 86400, 1) DB_SEC,
       ROUND((CAST(L.LOG_END_DTM AS DATE) - CAST(L.DB_TRNM_END_DTM AS DATE)) * 86400, 1) POST_DB
  FROM SCM_COM_SYS_LOG L
 WHERE L.MNU_ID = 'DMF0082' AND L.SHT_NM = 'FcstNPrice' AND L.MNU_BTN_CD = 'SEARCH'
   AND L.CREATION_DATE >= SYSDATE - 2
 ORDER BY L.LOG_ST_DTM DESC
 FETCH FIRST 10 ROWS ONLY;

PROMPT ################ [I2] ⭐⭐ 최근 180분 PKG_DMF0082 상위 6 문장 — 실행계획 라인별 활성 초 (#129 0-b) ################
PROMPT --  OBJ 가 영구 테이블 + IO 대기 = 원장 물리 읽기 / GT_DMF0082_* + NESTED LOOPS 대량 = GTT 추정 / HASH JOIN + temp = PGA 부족
WITH P AS (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME = 'PKG_DMF0082' AND OBJECT_TYPE = 'PACKAGE'),
A AS (SELECT H.* FROM GV$ACTIVE_SESSION_HISTORY H, P
       WHERE H.SAMPLE_TIME >= SYSTIMESTAMP - NUMTODSINTERVAL(180,'MINUTE') AND H.PLSQL_ENTRY_OBJECT_ID = P.OBJECT_ID AND H.SQL_ID IS NOT NULL),
TOPS AS (SELECT SQL_ID FROM A GROUP BY SQL_ID ORDER BY COUNT(*) DESC FETCH FIRST 6 ROWS ONLY)
SELECT A.SQL_ID, (SELECT MAX(Q.PROGRAM_LINE#) FROM GV$SQL Q WHERE Q.SQL_ID = A.SQL_ID) LINE,
       A.SQL_PLAN_LINE_ID PLAN_LINE, A.SQL_PLAN_OPERATION || ' ' || A.SQL_PLAN_OPTIONS OP,
       (SELECT O.OBJECT_NAME FROM ALL_OBJECTS O WHERE O.OBJECT_ID = A.CURRENT_OBJ# AND ROWNUM = 1) OBJ,
       NVL(A.EVENT,'ON CPU') EVT, COUNT(*) SAMPLES_SEC
  FROM A WHERE A.SQL_ID IN (SELECT SQL_ID FROM TOPS)
 GROUP BY A.SQL_ID, A.SQL_PLAN_LINE_ID, A.SQL_PLAN_OPERATION, A.SQL_PLAN_OPTIONS, A.CURRENT_OBJ#, NVL(A.EVENT,'ON CPU')
HAVING COUNT(*) >= 2
 ORDER BY A.SQL_ID, SAMPLES_SEC DESC;
PROMPT --  상위 6 문장의 텍스트
WITH P AS (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME = 'PKG_DMF0082' AND OBJECT_TYPE = 'PACKAGE'),
A AS (SELECT H.SQL_ID, COUNT(*) N FROM GV$ACTIVE_SESSION_HISTORY H, P
       WHERE H.SAMPLE_TIME >= SYSTIMESTAMP - NUMTODSINTERVAL(180,'MINUTE') AND H.PLSQL_ENTRY_OBJECT_ID = P.OBJECT_ID AND H.SQL_ID IS NOT NULL
       GROUP BY H.SQL_ID ORDER BY COUNT(*) DESC FETCH FIRST 6 ROWS ONLY)
SELECT A.SQL_ID, A.N SAMPLES_SEC, (SELECT MAX(Q.PROGRAM_LINE#) FROM GV$SQL Q WHERE Q.SQL_ID = A.SQL_ID) LINE,
       (SELECT MIN(SUBSTR(REGEXP_REPLACE(Q.SQL_TEXT,'\s+',' '),1,90)) FROM GV$SQL Q WHERE Q.SQL_ID = A.SQL_ID) TXT
  FROM A ORDER BY A.N DESC;

PROMPT ################ [I3] ⭐⭐ 최종 결과 커서(O_RC1) — fetch 왕복 수 (#129 §8) · SP 1회 평균 ################
PROMPT --  ROWS_PER_FETCH = BE 의 fetchSize 근사. 10 근처면 9천 행에 왕복 900회 → fetchSize 상향(F2) 후보. 수백 이상이면 fetch 왕복은 병목 아님
SELECT S.SQL_ID, S.PROGRAM_LINE# LINE, S.EXECUTIONS EX, S.FETCHES, S.END_OF_FETCH_COUNT EOF_CNT,
       ROUND(S.ROWS_PROCESSED/GREATEST(S.EXECUTIONS,1)) ROWS_PER_EX,
       ROUND(S.FETCHES/GREATEST(S.EXECUTIONS,1),1) FETCHES_PER_EX,
       ROUND(S.ROWS_PROCESSED/GREATEST(S.FETCHES,1),1) ROWS_PER_FETCH,
       ROUND(S.ELAPSED_TIME/1e6/GREATEST(S.EXECUTIONS,1),2) SEC_PER_EX,
       ROUND(S.USER_IO_WAIT_TIME/1e6/GREATEST(S.EXECUTIONS,1),2) IO_SEC_PER_EX,
       TO_CHAR(S.LAST_ACTIVE_TIME,'MM-DD HH24:MI:SS') LAST_ACT
  FROM GV$SQL S
 WHERE S.PROGRAM_ID = (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME = 'PKG_DMF0082' AND OBJECT_TYPE = 'PACKAGE BODY')
   AND S.COMMAND_TYPE = 3
   AND UPPER(S.SQL_TEXT) LIKE '%GT_DMF0082_MF_SP%'
   AND S.LAST_ACTIVE_TIME >= SYSDATE - 180/1440
 ORDER BY S.LAST_ACTIVE_TIME DESC
 FETCH FIRST 10 ROWS ONLY;
SELECT S.EXECUTIONS EX, ROUND(S.ELAPSED_TIME/1e6/GREATEST(S.EXECUTIONS,1),2) SP_SEC_PER_EX,
       ROUND(S.USER_IO_WAIT_TIME/1e6/GREATEST(S.EXECUTIONS,1),2) IO_SEC_PER_EX,
       ROUND(S.CPU_TIME/1e6/GREATEST(S.EXECUTIONS,1),2) CPU_SEC_PER_EX,
       TO_CHAR(S.LAST_ACTIVE_TIME,'MM-DD HH24:MI:SS') LAST_ACT
  FROM GV$SQL S
 WHERE UPPER(S.SQL_TEXT) LIKE 'BEGIN PKG_DMF0082.P_DMF0082_GET_MAIN_DATA(%' AND S.COMMAND_TYPE = 47
 ORDER BY S.LAST_ACTIVE_TIME DESC FETCH FIRST 5 ROWS ONLY;

PROMPT ################ [I4] 최근 180분 PKG_DMF0082 진입 활성 초 — 대기 이벤트 구성 (CPU vs 디스크 읽기) ################
WITH P AS (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME = 'PKG_DMF0082' AND OBJECT_TYPE = 'PACKAGE')
SELECT NVL(H.WAIT_CLASS,'CPU') WAIT_CLASS, NVL(H.EVENT,'ON CPU') EVT, COUNT(*) SAMPLES_SEC,
       ROUND(100 * RATIO_TO_REPORT(COUNT(*)) OVER (), 1) PCT
  FROM GV$ACTIVE_SESSION_HISTORY H, P
 WHERE H.SAMPLE_TIME >= SYSTIMESTAMP - NUMTODSINTERVAL(180,'MINUTE') AND H.PLSQL_ENTRY_OBJECT_ID = P.OBJECT_ID
 GROUP BY NVL(H.WAIT_CLASS,'CPU'), NVL(H.EVENT,'ON CPU')
 ORDER BY SAMPLES_SEC DESC FETCH FIRST 12 ROWS ONLY;
PROMPT --  User I/O(cell single block / db file sequential read) 지배 = 원장 랜덤 읽기(캐시 미적중) / ON CPU 지배 = 연산량

