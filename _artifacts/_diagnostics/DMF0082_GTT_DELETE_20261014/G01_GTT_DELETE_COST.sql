PROMPT ################ [G1] ⭐⭐ GV$SQL — PKG_DMF0082 의 DELETE 문장별 1회 비용 (커서 캐시 전체) ################
PROMPT --  CLS: 초기화(WHERE 없음) / 조회조건 필터 / 보조메저 / 중복제거 / 기타. ROWS_PER_EX = 1회 삭제 행수
WITH B AS (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0082' AND OBJECT_TYPE='PACKAGE BODY'),
S AS (SELECT S.*, UPPER(REGEXP_REPLACE(S.SQL_TEXT,'\s+',' ')) T FROM GV$SQL S JOIN B ON S.PROGRAM_ID = B.OBJECT_ID WHERE S.COMMAND_TYPE = 7)
SELECT S.INST_ID INST, S.SQL_ID, S.PROGRAM_LINE# LINE, S.EXECUTIONS EX,
       ROUND(S.ELAPSED_TIME/1e6/GREATEST(S.EXECUTIONS,1),3) SEC_PER_EX, ROUND(S.CPU_TIME/1e6/GREATEST(S.EXECUTIONS,1),3) CPU_PER_EX,
       ROUND(S.BUFFER_GETS/GREATEST(S.EXECUTIONS,1)) BG_PER_EX, ROUND(S.ROWS_PROCESSED/GREATEST(S.EXECUTIONS,1)) ROWS_PER_EX,
       ROUND(S.ELAPSED_TIME/1e6,1) ELAP_TOT_S,
       CASE WHEN REGEXP_LIKE(S.T,'^DELETE FROM SCM_MGR\.GTT?_[A-Z0-9_]+ ?$') THEN '초기화(WHERE 없음)'
            WHEN S.T LIKE '%PARAM_NM = ''P_PROJECT_CODE''%' THEN '필터 Project'
            WHEN S.T LIKE '%PARAM_NM = ''P_OWNER''%' THEN '필터 Owner'
            WHEN S.T LIKE '%PARAM_NM = ''P_TEAM_ID''%' THEN '필터 Team'
            WHEN S.T LIKE '%PARAM_NM = ''P_PLANT_SITE_ID''%' THEN '필터 Plant'
            WHEN S.T LIKE '%PARAM_NM = ''P_SENDER_CODE''%' THEN '필터 Sender'
            WHEN S.T LIKE '%PARAM_NM = ''P_SCM_SITE_ID''%' THEN '필터 SCM Site'
            WHEN S.T LIKE '%PARAM_NM = ''P_CUSTOMER''%' THEN '필터 Customer'
            WHEN S.T LIKE '%PARAM_NM = ''P_BIZ_TYPE''%' THEN '필터 Biz Type'
            WHEN S.T LIKE '%PARAM_NM = ''P_ITEM_ID''%' THEN '필터 Item'
            WHEN S.T LIKE '%DM_ADMIN%' THEN '보조메저(Unit Price)'
            WHEN S.T LIKE '%ROW_NUMBER%' THEN '중복제거'
            ELSE '기타(로직)' END CLS,
       SUBSTR(REGEXP_REPLACE(S.SQL_TEXT,'\s+',' '),1,90) TXT
  FROM S
 ORDER BY S.ELAPSED_TIME DESC
 FETCH FIRST 40 ROWS ONLY;

PROMPT ################ [G2] ⭐ GV$SQL — 스테이징 INSERT/MERGE (TEMP_FCST_N_PRICE · TEMP_SITE_ITEM) 1회 비용 — 넣고 지우는 양 대조 ################
WITH B AS (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0082' AND OBJECT_TYPE='PACKAGE BODY')
SELECT S.INST_ID INST, S.SQL_ID, S.PROGRAM_LINE# LINE, S.EXECUTIONS EX,
       ROUND(S.ELAPSED_TIME/1e6/GREATEST(S.EXECUTIONS,1),3) SEC_PER_EX, ROUND(S.BUFFER_GETS/GREATEST(S.EXECUTIONS,1)) BG_PER_EX,
       ROUND(S.DISK_READS/GREATEST(S.EXECUTIONS,1)) DR_PER_EX, ROUND(S.ROWS_PROCESSED/GREATEST(S.EXECUTIONS,1)) ROWS_PER_EX,
       CASE WHEN UPPER(S.SQL_TEXT) LIKE '%X_ONEREAD_YMD%' THEN '판가 ONEREAD'
            WHEN UPPER(S.SQL_TEXT) LIKE '%SCM_MST_FUTURE_PRICE%' THEN '판가'
            WHEN UPPER(S.SQL_TEXT) LIKE '%DM_PLN_CFM_SELLING_PRICE%' THEN '판가(CFM)'
            WHEN UPPER(S.SQL_TEXT) LIKE '%_RESULT%' THEN '실적'
            WHEN UPPER(S.SQL_TEXT) LIKE '%DM_PLN_SALES_PLAN%' THEN 'Sales Plan'
            WHEN UPPER(S.SQL_TEXT) LIKE '%DM_PLN_MKT_FCST%' OR UPPER(S.SQL_TEXT) LIKE '%DM_PLN_CFM_MKT_DEMAND_PLAN%' THEN '수요'
            WHEN UPPER(S.SQL_TEXT) LIKE '%SCM_MST_SITE_ITEM%' THEN 'SITE_ITEM_ALL 적재'
            WHEN UPPER(S.SQL_TEXT) LIKE 'MERGE%' THEN 'CURRENCY MERGE'
            ELSE '파생' END CLS,
       SUBSTR(REGEXP_REPLACE(S.SQL_TEXT,'\s+',' '),1,90) TXT
  FROM GV$SQL S JOIN B ON S.PROGRAM_ID = B.OBJECT_ID
 WHERE S.COMMAND_TYPE IN (2, 189)
