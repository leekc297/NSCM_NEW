PROMPT ################ [G3] ⭐⭐ 분류별 합계 — DELETE 전체가 조회 1회에서 차지하는 비중 (GV$SQL 누적 기준) ################
PROMPT --  GET_CALL_SEC_PER_EX = 최상위 호출(BEGIN … P_DMF0082_GET_MAIN_DATA) 1회 평균. 분류 SEC 는 [G1] 의 SEC_PER_EX 합 (같은 호출 안 1회씩 실행된다고 보고 합산)
WITH B AS (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0082' AND OBJECT_TYPE='PACKAGE BODY'),
S AS (SELECT S.ELAPSED_TIME, S.EXECUTIONS, UPPER(REGEXP_REPLACE(S.SQL_TEXT,'\s+',' ')) T, S.COMMAND_TYPE
        FROM GV$SQL S JOIN B ON S.PROGRAM_ID = B.OBJECT_ID WHERE S.PROGRAM_LINE# < 5200),
C AS (SELECT CASE WHEN COMMAND_TYPE = 7 AND REGEXP_LIKE(T,'^DELETE FROM SCM_MGR\.GTT?_[A-Z0-9_]+ ?$') THEN '1 DELETE 초기화'
                  WHEN COMMAND_TYPE = 7 AND T LIKE '%PARAM_TOKEN%' THEN '2 DELETE 조회조건 필터'
                  WHEN COMMAND_TYPE = 7 THEN '3 DELETE 기타(보조메저·중복제거·로직)'
                  WHEN COMMAND_TYPE IN (2,189) THEN '4 INSERT/MERGE'
                  WHEN COMMAND_TYPE = 3 THEN '5 SELECT'
                  ELSE '6 기타' END CLS,
             ELAPSED_TIME/1e6/GREATEST(EXECUTIONS,1) SEC_PER_EX, ELAPSED_TIME/1e6 ELAP
        FROM S)
SELECT CLS, COUNT(*) STMTS, ROUND(SUM(SEC_PER_EX),3) SUM_SEC_PER_EX, ROUND(SUM(ELAP),1) ELAP_TOT_S
  FROM C GROUP BY CLS ORDER BY CLS;
SELECT S.INST_ID INST, S.EXECUTIONS EX, ROUND(S.ELAPSED_TIME/1e6/GREATEST(S.EXECUTIONS,1),2) GET_CALL_SEC_PER_EX,
       TO_CHAR(S.LAST_ACTIVE_TIME,'MM-DD HH24:MI') LAST_ACT, SUBSTR(REGEXP_REPLACE(S.SQL_TEXT,'\s+',' '),1,70) TXT
  FROM GV$SQL S
 WHERE UPPER(S.SQL_TEXT) LIKE '%P_DMF0082_GET_MAIN_DATA(%' AND S.COMMAND_TYPE = 47
   AND UPPER(S.SQL_TEXT) NOT LIKE '%GV$SQL%'
 ORDER BY S.LAST_ACTIVE_TIME DESC FETCH FIRST 5 ROWS ONLY;

