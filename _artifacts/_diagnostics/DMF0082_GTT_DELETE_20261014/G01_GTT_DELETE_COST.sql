PROMPT ################ [G6] ⭐⭐ 실사용 — 최근 45 일 DMF0082 조회(FcstNPrice SEARCH) 를 조회조건 사용 여부별로 · 건수 · DB 소요(초) ################
PROMPT --  FILTERS = 지정된 조건(ALL/빈값 제외). 선행축소 대상 = Project·Owner·Team(·Plant·Sender). 비율이 낮으면 이번 보완의 체감 효과도 그만큼 제한적
WITH L AS (
  SELECT DBMS_LOB.SUBSTR(L.SYS_LOG_MSG_CTN, 4000, 1) M,
         (CAST(L.DB_TRNM_END_DTM AS DATE) - CAST(L.DB_TRNM_ST_DTM AS DATE)) * 86400 SEC
    FROM SCM_COM_SYS_LOG L
   WHERE L.MNU_ID = 'DMF0082' AND L.SHT_NM = 'FcstNPrice' AND L.MNU_BTN_CD = 'SEARCH'
     AND L.CREATION_DATE >= SYSDATE - 45),
V AS (
  SELECT REGEXP_SUBSTR(M,'"divisionId":"([^"]*)"',1,1,NULL,1) DIV,
         REGEXP_SUBSTR(M,'"projectCode":"([^"]*)"',1,1,NULL,1) PJT,
         REGEXP_SUBSTR(M,'"owner":"([^"]*)"',1,1,NULL,1) OWN,
         REGEXP_SUBSTR(M,'"deptId":"([^"]*)"',1,1,NULL,1) TEAM,
         REGEXP_SUBSTR(M,'"plantSiteId":"([^"]*)"',1,1,NULL,1) PLNT,
         REGEXP_SUBSTR(M,'"senderCode":"([^"]*)"',1,1,NULL,1) SND,
         REGEXP_SUBSTR(M,'"salesSite":"([^"]*)"',1,1,NULL,1) SITE,
         SEC FROM L)
SELECT DIV,
       NVL(RTRIM(CASE WHEN NVL(PJT,'ALL')  <> 'ALL' THEN 'Project,' END ||
                 CASE WHEN NVL(OWN,'ALL')  <> 'ALL' THEN 'Owner,' END ||
                 CASE WHEN NVL(TEAM,'ALL') <> 'ALL' THEN 'Team,' END ||
                 CASE WHEN NVL(PLNT,'ALL') <> 'ALL' THEN 'Plant,' END ||
                 CASE WHEN NVL(SND,'ALL')  <> 'ALL' THEN 'Sender,' END ||
                 CASE WHEN NVL(SITE,'ALL') <> 'ALL' THEN 'SalesSite,' END, ','), '(미지정)') FILTERS,
       COUNT(*) CALLS, ROUND(AVG(SEC),1) AVG_SEC, ROUND(MEDIAN(SEC),1) MED_SEC, ROUND(MAX(SEC),1) MAX_SEC
  FROM V
 GROUP BY DIV,
       NVL(RTRIM(CASE WHEN NVL(PJT,'ALL')  <> 'ALL' THEN 'Project,' END ||
                 CASE WHEN NVL(OWN,'ALL')  <> 'ALL' THEN 'Owner,' END ||
                 CASE WHEN NVL(TEAM,'ALL') <> 'ALL' THEN 'Team,' END ||
                 CASE WHEN NVL(PLNT,'ALL') <> 'ALL' THEN 'Plant,' END ||
                 CASE WHEN NVL(SND,'ALL')  <> 'ALL' THEN 'Sender,' END ||
                 CASE WHEN NVL(SITE,'ALL') <> 'ALL' THEN 'SalesSite,' END, ','), '(미지정)')
 ORDER BY DIV, CALLS DESC;

PROMPT ################ [G7] 실데이터 프로파일 — 최근 45 일 실제로 조회된 Project 상위 10 의 '정확 필터' vs '완화 선행축소(같은 SITE+ITEM 유지)' 판가·수요 행수 ################
PROMPT --  완화 선행축소 = 선택 Project 의 (DIV, SCM_SITE, ITEM) 을 가진 행은 Project 가 달라도 남김 (CURRENCY 3차 MERGE 등가 보존용)
PROMPT --  ALL_* = 해당 division 의 기간 내 전체 = 현행 스테이징 적재량 근사. 사내 81 실측: 판가 190,317 → 정확 30~11,970 / 완화 30~12,330
WITH L AS (
  SELECT REGEXP_SUBSTR(DBMS_LOB.SUBSTR(L.SYS_LOG_MSG_CTN,4000,1),'"divisionId":"([^"]*)"',1,1,NULL,1) DIV,
         REGEXP_SUBSTR(DBMS_LOB.SUBSTR(L.SYS_LOG_MSG_CTN,4000,1),'"projectCode":"([^"]*)"',1,1,NULL,1) PJT,
         REGEXP_SUBSTR(DBMS_LOB.SUBSTR(L.SYS_LOG_MSG_CTN,4000,1),'"fromYyyymmdd":"([^"]*)"',1,1,NULL,1) FR,
         REGEXP_SUBSTR(DBMS_LOB.SUBSTR(L.SYS_LOG_MSG_CTN,4000,1),'"toYyyymmdd":"([^"]*)"',1,1,NULL,1) TOO
    FROM SCM_COM_SYS_LOG L
   WHERE L.MNU_ID = 'DMF0082' AND L.SHT_NM = 'FcstNPrice' AND L.MNU_BTN_CD = 'SEARCH'
     AND L.CREATION_DATE >= SYSDATE - 45),
Q AS (SELECT DIV, PJT, MIN(FR) FR, MAX(TOO) TOO, COUNT(*) CALLS FROM L
       WHERE NVL(PJT,'ALL') <> 'ALL' AND DIV IS NOT NULL GROUP BY DIV, PJT ORDER BY COUNT(*) DESC FETCH FIRST 10 ROWS ONLY),
TK AS (SELECT DISTINCT Q.DIV, Q.PJT, Q.FR, Q.TOO, Q.CALLS, TRIM(REGEXP_SUBSTR(Q.PJT,'[^,]+',1,N.LV)) TOK
         FROM Q, (SELECT LEVEL LV FROM DUAL CONNECT BY LEVEL <= 30) N
        WHERE N.LV <= REGEXP_COUNT(Q.PJT, ',') + 1),
SI AS (SELECT F.DIVISION_ID, F.PROJECT_CODE, F.SCM_SITE_ID, F.ITEM_ID
         FROM SCM_MST_SITE_ITEM F JOIN SCM_MST_SITE S ON S.DIVISION_ID = F.DIVISION_ID AND S.SCM_SITE_ID = F.SCM_SITE_ID AND S.SITE_TYPE = 'SALES'
        WHERE F.VALID_YN = 'Y' AND F.DIVISION_ID IN (SELECT DIV FROM Q)
        GROUP BY F.DIVISION_ID, F.PROJECT_CODE, F.SCM_SITE_ID, F.ITEM_ID),
HIT AS (SELECT DISTINCT TK.DIV, TK.PJT, SI.SCM_SITE_ID, SI.ITEM_ID
          FROM TK JOIN SI ON SI.DIVISION_ID = TK.DIV AND SI.PROJECT_CODE = TK.TOK),
FP AS (SELECT A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.YYYYMMDD
         FROM SCM_MST_FUTURE_PRICE A
        WHERE A.DIVISION_ID IN (SELECT DIV FROM Q)
          AND A.YYYYMMDD BETWEEN (SELECT MIN(FR) FROM Q) AND (SELECT MAX(TOO) FROM Q)
          AND (A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID) IN (SELECT DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID FROM SI))
SELECT Q.DIV, SUBSTR(Q.PJT,1,40) PJT, Q.CALLS, Q.FR, Q.TOO,
       (SELECT COUNT(*) FROM FP WHERE FP.DIVISION_ID = Q.DIV AND FP.YYYYMMDD BETWEEN Q.FR AND Q.TOO) ALL_PRICE,
       (SELECT COUNT(*) FROM FP JOIN TK ON TK.DIV = FP.DIVISION_ID AND TK.TOK = FP.PROJECT_CODE
         WHERE TK.PJT = Q.PJT AND FP.DIVISION_ID = Q.DIV AND FP.YYYYMMDD BETWEEN Q.FR AND Q.TOO) EXACT_PRICE,
       (SELECT COUNT(*) FROM FP JOIN HIT H ON H.DIV = FP.DIVISION_ID AND H.SCM_SITE_ID = FP.SCM_SITE_ID AND H.ITEM_ID = FP.ITEM_ID
         WHERE H.PJT = Q.PJT AND FP.DIVISION_ID = Q.DIV AND FP.YYYYMMDD BETWEEN Q.FR AND Q.TOO) RELAXED_PRICE
  FROM Q ORDER BY Q.CALLS DESC;
PROMPT --  RELAXED_PRICE / ALL_PRICE = 선행축소 후 판가 스테이징 잔존 비율 근사 (사내 81: 0.02%~6.5%)

