PROMPT ################ [H3] GV$SQL — PKG_DMF0082 문장 중 1회 0.5초 이상 (최근 120분 활동분) ################
WITH B AS (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME = 'PKG_DMF0082' AND OBJECT_TYPE = 'PACKAGE BODY')
SELECT S.SQL_ID, S.PROGRAM_LINE# LINE, S.PLAN_HASH_VALUE PHV, S.EXECUTIONS EX,
       ROUND(S.ELAPSED_TIME/1e6/GREATEST(S.EXECUTIONS,1),2) SEC_PER_EX, ROUND(S.CPU_TIME/1e6/GREATEST(S.EXECUTIONS,1),2) CPU_PER_EX,
       ROUND(S.BUFFER_GETS/GREATEST(S.EXECUTIONS,1)) BG_PER_EX, ROUND(S.DISK_READS/GREATEST(S.EXECUTIONS,1)) DR_PER_EX,
       ROUND(S.ROWS_PROCESSED/GREATEST(S.EXECUTIONS,1)) ROWS_PER_EX, TO_CHAR(S.LAST_ACTIVE_TIME,'HH24:MI:SS') LAST_ACT,
       SUBSTR(REGEXP_REPLACE(S.SQL_TEXT,'\s+',' '),1,90) TXT
  FROM GV$SQL S JOIN B ON S.PROGRAM_ID = B.OBJECT_ID
 WHERE S.LAST_ACTIVE_TIME >= SYSDATE - 120/1440
   AND S.ELAPSED_TIME/1e6/GREATEST(S.EXECUTIONS,1) >= 0.5
 ORDER BY S.ELAPSED_TIME/GREATEST(S.EXECUTIONS,1) DESC
 FETCH FIRST 30 ROWS ONLY;

