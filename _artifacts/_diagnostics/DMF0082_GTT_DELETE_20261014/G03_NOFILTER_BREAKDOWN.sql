  FROM GV$SQL S
 WHERE UPPER(S.SQL_TEXT) LIKE 'BEGIN PKG_DMF0082.P_DMF0082_GET_MAIN_DATA(%' AND S.COMMAND_TYPE = 47
 ORDER BY S.LAST_ACTIVE_TIME DESC FETCH FIRST 5 ROWS ONLY;

