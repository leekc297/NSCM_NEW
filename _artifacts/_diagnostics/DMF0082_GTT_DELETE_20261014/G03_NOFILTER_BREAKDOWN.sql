PROMPT ################ [H0] 접속 DB · 시각 · PKG_DMF0082 상태 · RLXPRE 적용 여부 ################
SELECT SYS_CONTEXT('USERENV','DB_NAME') DB_NAME, SYS_CONTEXT('USERENV','SERVER_HOST') SERVER_HOST, TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI:SS') NOW FROM DUAL;
SELECT O.OBJECT_TYPE, O.STATUS, TO_CHAR(O.LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL,
       (SELECT COUNT(*) FROM USER_SOURCE S WHERE S.NAME = O.OBJECT_NAME AND S.TYPE = O.OBJECT_TYPE AND S.TEXT LIKE '%E20261014-DMF0082RLXPRE%') RLXPRE_MARK
  FROM USER_OBJECTS O WHERE O.OBJECT_NAME = 'PKG_DMF0082' ORDER BY O.OBJECT_TYPE;

PROMPT ################ [H1] ⭐⭐ 최근 120분 DMF0082 조회 1건씩 — 구간 분해 (초) ################
PROMPT --  FETCH_EST 가 크면 SP 가 아니라 결과 수신(행수 × 컬럼수) 이 병목 → #129 §8 fetch 축. SP_ASH 가 크면 SP 문장 → [H2]
WITH P AS (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME = 'PKG_DMF0082' AND OBJECT_TYPE = 'PACKAGE'),
L AS (
  SELECT L.SYS_LOG_ID, L.CREATED_BY USR, L.LOG_ST_DTM, L.DB_TRNM_ST_DTM, L.DB_TRNM_END_DTM,
         REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"divisionId":"([^"]*)"',1,1,NULL,1) DIV,
         REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"versionType":"([^"]*)"',1,1,NULL,1) VER,
         NVL(RTRIM(CASE WHEN NVL(REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"projectCode":"([^"]*)"',1,1,NULL,1),'ALL') <> 'ALL' THEN 'Project,' END ||
                   CASE WHEN NVL(REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"owner":"([^"]*)"',1,1,NULL,1),'ALL') <> 'ALL' THEN 'Owner,' END ||
                   CASE WHEN NVL(REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"deptId":"([^"]*)"',1,1,NULL,1),'ALL') <> 'ALL' THEN 'Team,' END ||
                   CASE WHEN NVL(REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"salesSite":"([^"]*)"',1,1,NULL,1),'ALL') <> 'ALL' THEN 'SalesSite,' END, ','), '(미지정)') FILTERS,
         (CAST(L.LOG_END_DTM AS DATE) - CAST(L.LOG_ST_DTM AS DATE)) * 86400 TOTAL,
         (CAST(L.DB_TRNM_END_DTM AS DATE) - CAST(L.DB_TRNM_ST_DTM AS DATE)) * 86400 DB_SEC,
         (CAST(L.TRNM_END_DTM AS DATE) - CAST(L.DB_TRNM_END_DTM AS DATE)) * 86400 POST_DB
    FROM SCM_COM_SYS_LOG L
   WHERE L.MNU_ID = 'DMF0082' AND L.SHT_NM = 'FcstNPrice' AND L.MNU_BTN_CD = 'SEARCH'
     AND L.CREATION_DATE >= SYSDATE - 120/1440),
A AS (
  SELECT L.SYS_LOG_ID, COUNT(DISTINCT H.SAMPLE_ID) SP_ASH, COUNT(DISTINCT H.INST_ID || ',' || H.SESSION_ID) SESS
    FROM L, GV$ACTIVE_SESSION_HISTORY H, P
   WHERE H.SAMPLE_TIME BETWEEN L.DB_TRNM_ST_DTM AND L.DB_TRNM_END_DTM
     AND H.PLSQL_ENTRY_OBJECT_ID = P.OBJECT_ID
   GROUP BY L.SYS_LOG_ID)
SELECT TO_CHAR(L.LOG_ST_DTM,'MM-DD HH24:MI:SS') ST, L.USR, L.DIV, L.VER, L.FILTERS,
       ROUND(L.TOTAL,1) TOTAL, ROUND(L.DB_SEC,1) DB_SEC, NVL(A.SP_ASH,0) SP_ASH,
       ROUND(L.DB_SEC - NVL(A.SP_ASH,0),1) FETCH_EST, ROUND(L.POST_DB,1) POST_DB,
       CASE WHEN NVL(A.SESS,0) > 1 THEN 'OVERLAP(' || A.SESS || '세션)' END NOTE
  FROM L LEFT JOIN A ON A.SYS_LOG_ID = L.SYS_LOG_ID
 ORDER BY L.LOG_ST_DTM DESC
 FETCH FIRST 30 ROWS ONLY;

PROMPT ################ [H2] ⭐⭐ 위 조회 창 안의 SP 문장별 활성 초 (division 별 상위) — 미지정 조회의 다음 튜닝 대상 ################
WITH P AS (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME = 'PKG_DMF0082' AND OBJECT_TYPE = 'PACKAGE'),
W AS (
  SELECT REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"divisionId":"([^"]*)"',1,1,NULL,1) DIV, L.DB_TRNM_ST_DTM T0, L.DB_TRNM_END_DTM T1
    FROM SCM_COM_SYS_LOG L
   WHERE L.MNU_ID = 'DMF0082' AND L.SHT_NM = 'FcstNPrice' AND L.MNU_BTN_CD = 'SEARCH'
     AND L.CREATION_DATE >= SYSDATE - 120/1440
     AND NVL(REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"projectCode":"([^"]*)"',1,1,NULL,1),'ALL') = 'ALL'
     AND NVL(REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"owner":"([^"]*)"',1,1,NULL,1),'ALL') = 'ALL'
     AND NVL(REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"deptId":"([^"]*)"',1,1,NULL,1),'ALL') = 'ALL'),
A AS (
  SELECT DISTINCT W.DIV, H.SAMPLE_ID, H.INST_ID, H.SESSION_ID, H.SQL_ID, H.SQL_OPNAME, H.EVENT
    FROM W, GV$ACTIVE_SESSION_HISTORY H, P
   WHERE H.SAMPLE_TIME BETWEEN W.T0 AND W.T1 AND H.PLSQL_ENTRY_OBJECT_ID = P.OBJECT_ID),
T AS (SELECT SQL_ID, MAX(PROGRAM_LINE#) LN, MIN(SUBSTR(REGEXP_REPLACE(SQL_TEXT,'\s+',' '),1,90)) TXT
        FROM GV$SQL WHERE SQL_ID IN (SELECT SQL_ID FROM A) GROUP BY SQL_ID)
SELECT A.DIV, NVL(A.SQL_ID,'(PL/SQL·파싱)') SQL_ID, T.LN LINE, NVL(A.SQL_OPNAME,'-') OP, COUNT(*) SAMPLES_SEC,
       ROUND(100 * RATIO_TO_REPORT(COUNT(*)) OVER (PARTITION BY A.DIV), 1) PCT,
       STATS_MODE(NVL(A.EVENT,'ON CPU')) TOP_EVT,
       CASE WHEN T.TXT LIKE '%X_ONEREAD_YMD%' OR T.TXT LIKE '%SCM_MST_FUTURE_PRICE%' THEN '판가'
            WHEN T.TXT LIKE '%DM_PLN_CFM_SELLING_PRICE%' THEN '판가(CFM)'
            WHEN T.TXT LIKE '%RESULT%' THEN '실적'
            WHEN T.TXT LIKE '%DM_PLN_SALES_PLAN%' THEN 'Sales Plan'
            WHEN T.TXT LIKE '%DM_PLN_MKT_FCST%' OR T.TXT LIKE '%DM_PLN_CFM_MKT_DEMAND_PLAN%' THEN '수요'
            WHEN T.TXT LIKE '%SCM_MST_SITE_ITEM%' THEN 'SITE_ITEM 적재'
            WHEN T.TXT LIKE '%GT_DMF0082_MF_SP%' THEN 'MF_SP/결과'
            WHEN T.TXT LIKE 'MERGE%' THEN 'MERGE' END TAG,
       T.TXT
  FROM A LEFT JOIN T ON T.SQL_ID = A.SQL_ID
 GROUP BY A.DIV, NVL(A.SQL_ID,'(PL/SQL·파싱)'), T.LN, NVL(A.SQL_OPNAME,'-'), T.TXT
HAVING COUNT(*) >= 1
 ORDER BY A.DIV, SAMPLES_SEC DESC;
