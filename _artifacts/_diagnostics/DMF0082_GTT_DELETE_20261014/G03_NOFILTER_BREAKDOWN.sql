--   목적: hook #129 0-a/0-b — Division 만 넣은 조회(조회조건 미지정, 클라우드 조회의 90% 이상)가
--         어디에서 시간을 쓰는지 실측한다. RLXPRE(Project/Owner/Team 선행축소)는 이 경로에서 실행되지 않는다.
--   순서: 클라우드 화면에서 Division 40 → 81 → 82 를 조건 없이 각 1회 Search → 바로 이 파일 실행.
--   조회 창: 최근 120분 (숫자 직접 수정 가능). 치환변수·바인드 없음. 변경 없음(SELECT 만).
--   구간 정의 (SCM_COM_SYS_LOG 시각):
--     TOTAL   = LOG_ST → LOG_END   (BE 가 받은 요청 전체)
--     DB_SEC  = DB_TRNM_ST → DB_TRNM_END  (SP 실행 + 결과 커서 수신(fetch))
--     POST_DB = DB_TRNM_END → TRNM_END    (BE 가공·직렬화)
--     SP_ASH  = 같은 DB 창 안에서 PKG_DMF0082 를 실행 중이던 활성 세션 샘플 수 (≈ SP 실행 초)
--     FETCH_EST = DB_SEC - SP_ASH  (결과 수신·전송 추정. 같은 창에 다른 사용자의 DMF0082 호출이 겹치면 SP_ASH 가 커진다 → OVERLAP 표시)
-- =============================================================================
