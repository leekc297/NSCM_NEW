PROMPT ============ [E] BE 로그 — 오늘 발생 예외 (CLOB LIKE 미사용) ============
PROMPT (SQL_ID 는 VARCHAR2 이고 값이 'com.lgcns.nscm.callProc' 고정이라 먼저 좁힌다.
PROMPT  프로시저명은 CLOB(PARAMS) 안에 있으므로 좁혀진 뒤에만 DBMS_LOB.INSTR 를 건다)
SELECT * FROM (
  SELECT TO_CHAR(CREATE_DATE,'YYYY-MM-DD HH24:MI:SS') T, CREATED_BY,
         SUBSTR(EXCEPTION,1,600) EXCEPTION
  FROM   SCM_COM_SQL_LOG
  WHERE  CREATE_DATE >= TRUNC(SYSDATE)
  AND    SQL_ID = 'com.lgcns.nscm.callProc'
  AND    EXCEPTION IS NOT NULL
  AND    DBMS_LOB.INSTR(PARAMS,'DMF0022') > 0
  ORDER  BY CREATE_DATE DESC )
WHERE ROWNUM <= 15;

