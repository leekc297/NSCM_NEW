PROMPT ============ [C] ★핵심★ 컬럼사전 미등재 (기대: 0행) ============
PROMPT (여기 나오는 컬럼이 ORDER BY 에만 남아 ORA-00904 를 일으킨다)
WITH DIC AS (
  SELECT UPPER(REGEXP_SUBSTR(TEXT,'GT_DM22_T_COLUMN_SETUP\s+VALUES\s*\(\s*''[^'']*''\s*,\s*''([^'']+)''',1,1,'i',1)) COL
  FROM   USER_SOURCE
  WHERE  NAME='PKG_DMF0022' AND TYPE='PACKAGE BODY'
  AND    INSTR(TEXT,'GT_DM22_T_COLUMN_SETUP')>0
  AND    LTRIM(TEXT) NOT LIKE '--%'
), NEED AS (
  SELECT DISTINCT UPPER(COLUMN_NAME) COL, '개인화(C)' SRC, USER_ID
  FROM   SCM_MST_TITLESET_USER
  WHERE  PROGRAM_ID='DMF0035' AND SHEET_NAME='Sales Plan Waterfall' AND USER_INQUIRY_COLUMN_TYPE_CODE='C'
  UNION ALL
  SELECT DISTINCT UPPER(COLUMN_NAME), '시트기본', NULL
  FROM   SCM_MST_SHEET_COLUMNS
  WHERE  PROGRAM_ID='DMF0035' AND SHEET_NAME='Sales Plan Waterfall'
  AND    ( DEFAULT_FLAG='Y' OR (VISIBLE_FLAG='N' AND DEFAULT_FLAG=' ' AND VALID_YN='Y') )
)
SELECT N.SRC, N.COL, N.USER_ID
FROM   NEED N WHERE N.COL NOT IN (SELECT COL FROM DIC WHERE COL IS NOT NULL)
ORDER  BY N.SRC, N.COL, N.USER_ID;

