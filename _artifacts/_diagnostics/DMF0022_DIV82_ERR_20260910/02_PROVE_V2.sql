PROMPT ############ [P2] IF 분기 컬럼목록 (개인화 0 일 때 SP 가 쓰는 목록)
PROMPT 사내: DIVISION_ID,DEPT_ID,END_CUSTOMER,END_CUSTOMER40,SCM_SITE_ID,PROJECT_CODE,GROUP_ID,ITEM_ID,TEXT,ITEM_NAME,INCOTERMS,FCST_TYPE,DOM_EXP,PLANT_SITE_ID,CELL_PROD_SITE_ID,FROM_SITE_ID,CURRENCY,COMPANY_ID,VERSION_NO
