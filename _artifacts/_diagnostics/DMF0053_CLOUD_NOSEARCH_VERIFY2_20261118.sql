-- V0. 접속 확인
SELECT SYS_CONTEXT('USERENV', 'DB_NAME') AS DB_NAME, SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AS CUR_SCHEMA
     , TO_CHAR(SYSDATE, 'YYYY-MM-DD HH24:MI:SS') AS NOW_DT
     , TO_CHAR(TRUNC(SYSDATE) - 1, 'YYYYMMDD') AS RECORD_FROM_DATE
  FROM DUAL;

-- V1. 이력 테이블 통계와 적재 SP 버전. NUM_ROWS, LAST_ANALYZED 로 이관 때 데이터가 있었는지 확인
SELECT T.TABLE_NAME, T.NUM_ROWS, TO_CHAR(T.LAST_ANALYZED, 'YYYY-MM-DD HH24:MI:SS') AS LAST_ANALYZED
     , (SELECT COUNT(*) FROM DM_PLN_CUST_FCST_H) AS REAL_ROWS
  FROM ALL_TABLES T
 WHERE T.TABLE_NAME = 'DM_PLN_CUST_FCST_H'
   AND T.OWNER = SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA');

SELECT S.NAME, COUNT(*) AS LINE_CNT, SUM(LENGTH(S.TEXT)) AS TEXT_LEN, SUM(ORA_HASH(S.TEXT)) AS TEXT_HASH
     , 952 AS CORP_LINE_CNT, 50430 AS CORP_TEXT_LEN, 2122525068537 AS CORP_TEXT_HASH
  FROM ALL_SOURCE S
 WHERE S.NAME = 'PR_DM_PLN_CUST_FCST_RECORD'
