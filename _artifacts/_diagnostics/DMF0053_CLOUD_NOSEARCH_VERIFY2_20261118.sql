-- V2. 잡 정의 전문. step 2 의 사업부, 업무구분 목록 확인
SELECT J.JOB_NAME, J.ENABLED, J.STATE, J.JOB_TYPE, J.JOB_ACTION
  FROM ALL_SCHEDULER_JOBS J
 WHERE J.JOB_NAME = 'JOB_PR_DM_DNM_EDI_CALLOFF';

-- E1. EDI 원장 사업부별 현황. RECENT_CNT 가 0 이면 그 사업부 EDI 경로는 0건 적재
SELECT A.DIVISION_ID
     , COUNT(*)                     AS TOTAL_CNT
     , MIN(A.CREATE_DATE)           AS MIN_CREATE_DATE
     , MAX(A.CREATE_DATE)           AS MAX_CREATE_DATE
     , SUM(CASE WHEN A.CREATE_DATE >= TO_CHAR(TRUNC(SYSDATE) - 1, 'YYYYMMDD') THEN 1 ELSE 0 END) AS RECENT_CNT
     , COUNT(DISTINCT CASE WHEN A.CREATE_DATE >= TO_CHAR(TRUNC(SYSDATE) - 1, 'YYYYMMDD') THEN A.IFSEQNO END) AS RECENT_IFSEQ
     , TO_CHAR(MAX(A.LAST_UPDATE_DATE), 'YYYY-MM-DD HH24:MI:SS') AS LAST_UPDATE
  FROM DM_DNM_EDI_CALLOFF_ITEM A
 GROUP BY A.DIVISION_ID
 ORDER BY A.DIVISION_ID;

-- E1-2. EDI 원장 최근 30일 CREATE_DATE 별 건수
SELECT A.DIVISION_ID, A.CREATE_DATE, COUNT(*) AS CNT, COUNT(DISTINCT A.IFSEQNO) AS IFSEQ_CNT
  FROM DM_DNM_EDI_CALLOFF_ITEM A
 WHERE A.CREATE_DATE >= TO_CHAR(TRUNC(SYSDATE) - 30, 'YYYYMMDD')
 GROUP BY A.DIVISION_ID, A.CREATE_DATE
 ORDER BY A.DIVISION_ID, A.CREATE_DATE DESC;

-- E2. 고객 모델 매핑 사업부별 현황 (ACTIVE_YN 'Y', MAPPING_ITEM_ID 있음)
SELECT M.DIVISION_ID, M.ACTIVE_YN
     , COUNT(*) AS CNT
     , SUM(CASE WHEN M.MAPPING_ITEM_ID IS NOT NULL THEN 1 ELSE 0 END) AS MAPPED_CNT
     , MIN(M.VALID_START_DATE) AS MIN_VALID_START
     , MAX(M.VALID_END_DATE)   AS MAX_VALID_END
  FROM DM_CUST_MODEL_MAPPING_M M
 GROUP BY M.DIVISION_ID, M.ACTIVE_YN
 ORDER BY M.DIVISION_ID, M.ACTIVE_YN;

-- E3. EDI 경로 단계별 남는 건수 (최근 30일 EDI 행 기준). SP 의 어제 이후 조건은 RECENT 열
WITH MAP AS (
    SELECT DISTINCT A.DIVISION_ID, A.SCM_SITE_ID, A.PROJECT_CODE, A.INCOTERMS, A.ITEM_ID, A.MAPPING_ITEM_ID
         , NVL(NULLIF(NULLIF(NULLIF(RTRIM(LTRIM(A.UNLOADING_POINT)), '-'), '--'), '/'), '/')  AS UNLOADING_POINT
         , NVL(NULLIF(NULLIF(NULLIF(RTRIM(LTRIM(A.CUSTOMER_PLANT)), '-'), '--'), '/'), '/')   AS CUSTOMER_PLANT
         , NVL(NULLIF(NULLIF(NULLIF(RTRIM(LTRIM(A.CUSTOMER_ITEM_ID)), '-'), '--'), '/'), '/') AS CUSTOMER_ITEM_ID
         , A.VALID_START_DATE, A.VALID_END_DATE
      FROM DM_CUST_MODEL_MAPPING_M A
     WHERE A.ACTIVE_YN = 'Y'
), EDI AS (
    SELECT X.*
         , CASE WHEN X.CREATE_DATE >= TO_CHAR(TRUNC(SYSDATE) - 1, 'YYYYMMDD') THEN 1 ELSE 0 END AS RECENT_YN
      FROM DM_DNM_EDI_CALLOFF_ITEM X
     WHERE X.CREATE_DATE >= TO_CHAR(TRUNC(SYSDATE) - 30, 'YYYYMMDD')
)
SELECT X.DIVISION_ID
     , COUNT(*)                                                         AS S1_EDI_30D
     , SUM(X.RECENT_YN)                                                 AS S1_EDI_RECENT
     , SUM(CASE WHEN B.ITEM_ID IS NOT NULL THEN 1 ELSE 0 END)           AS S2_MAP_KEY_MATCH
     , SUM(CASE WHEN B.ITEM_ID IS NOT NULL
                 AND X.BASIS_YYYYMMDD BETWEEN B.VALID_START_DATE AND B.VALID_END_DATE
                 AND B.MAPPING_ITEM_ID IS NOT NULL THEN 1 ELSE 0 END)   AS S3_MAP_VALID
     , SUM(CASE WHEN B.ITEM_ID IS NOT NULL
                 AND X.BASIS_YYYYMMDD BETWEEN B.VALID_START_DATE AND B.VALID_END_DATE
                 AND B.MAPPING_ITEM_ID IS NOT NULL
                 AND X.SCHEDULING_TYPE <> '83' THEN 1 ELSE 0 END)       AS S4_SCHED_OK
     , SUM(CASE WHEN B.ITEM_ID IS NOT NULL
                 AND X.BASIS_YYYYMMDD BETWEEN B.VALID_START_DATE AND B.VALID_END_DATE
                 AND B.MAPPING_ITEM_ID IS NOT NULL
                 AND X.SCHEDULING_TYPE <> '83' THEN X.RECENT_YN ELSE 0 END) AS S4_SCHED_OK_RECENT
     , SUM(CASE WHEN X.SCHEDULING_TYPE IS NULL THEN 1 ELSE 0 END)       AS SCHED_NULL_CNT
  FROM EDI X
  LEFT OUTER JOIN MAP B
    ON X.DIVISION_ID   = B.DIVISION_ID
   AND X.SCM_SITE_ID   = B.SCM_SITE_ID
   AND X.PROJECT_CODE  = B.PROJECT_CODE
   AND X.EDI_INCOTERMS = B.INCOTERMS
   AND X.ITEM_ID       = B.ITEM_ID
   AND NVL(NULLIF(NULLIF(NULLIF(RTRIM(LTRIM(X.UNLOADING_POINT)), '-'), '--'), '/'), '/')    = B.UNLOADING_POINT
   AND NVL(NULLIF(NULLIF(NULLIF(RTRIM(LTRIM(X.CUSTOMER_PLANT)), '-'), '--'), '/'), '/')     = B.CUSTOMER_PLANT
   AND NVL(NULLIF(NULLIF(NULLIF(RTRIM(LTRIM(X.CUST_MATERIAL_CODE)), '-'), '--'), '/'), '/') = B.CUSTOMER_ITEM_ID
 GROUP BY X.DIVISION_ID
 ORDER BY X.DIVISION_ID;

-- E4. EDI 원장 SCHEDULING_TYPE 분포 (최근 30일)
SELECT A.DIVISION_ID, NVL(A.SCHEDULING_TYPE, '(NULL)') AS SCHEDULING_TYPE, COUNT(*) AS CNT
  FROM DM_DNM_EDI_CALLOFF_ITEM A
 WHERE A.CREATE_DATE >= TO_CHAR(TRUNC(SYSDATE) - 30, 'YYYYMMDD')
 GROUP BY A.DIVISION_ID, NVL(A.SCHEDULING_TYPE, '(NULL)')
 ORDER BY A.DIVISION_ID, 2;

-- R1. RPA 경로 원천 DM_PLN_MKT_FCST (CUST_FCST, Customer FCST). RECENT_CNT 가 0 이면 RPA 경로는 0건 적재
SELECT A.DIVISION_ID, A.MEASURE
     , COUNT(*) AS TOTAL_CNT
     , TO_CHAR(MAX(A.LAST_UPDATE_DATE), 'YYYY-MM-DD HH24:MI:SS') AS LAST_UPDATE
     , SUM(CASE WHEN A.LAST_UPDATE_DATE >= TRUNC(SYSDATE) - 1 THEN 1 ELSE 0 END) AS RECENT_CNT
  FROM DM_PLN_MKT_FCST A
 WHERE A.MEASURE IN ('CUST_FCST', 'Customer FCST')
 GROUP BY A.DIVISION_ID, A.MEASURE
 ORDER BY A.DIVISION_ID, A.MEASURE;

-- L1. 이력 적재 SP 로그 최근 7일 전부 (사업부·업무구분, 건수, 오류)
SELECT * FROM (
SELECT L.LOG_TYPE, L.LOG_COUNT, SUBSTR(L.LOG_MESSAGE, 1, 200) AS LOG_MESSAGE
     , SUBSTR(L.DESCRIPTION, 1, 200) AS DESCRIPTION, L.SQL_ERR_CODE, SUBSTR(L.SQL_ERR_MSG, 1, 300) AS SQL_ERR_MSG
     , TO_CHAR(L.EVENT_DATE, 'YYYY-MM-DD HH24:MI:SS') AS EVENT_DATE
  FROM SCM_SYS_LOG_BATCH L
 WHERE L.PROGRAM_NAME = 'PR_DM_PLN_CUST_FCST_RECORD'
   AND L.EVENT_DATE >= TRUNC(SYSDATE) - 7
 ORDER BY L.EVENT_DATE DESC
) WHERE ROWNUM <= 60;

