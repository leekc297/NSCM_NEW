SELECT DIVISION_ID, SUBSTR(SALES_POSTING_DATE,1,6) YM, CURRENCY, COUNT(*) N,
  SUM(CASE WHEN SALES_AMOUNT_SUM = SALES_AMOUNT_FOR AND SALES_AMOUNT_FOR<>0 THEN 1 ELSE 0 END) SUM_EQ_FOR,
  MAX(CREATED_BY) CB, TO_CHAR(MAX(CREATION_DATE),'YYYY-MM-DD HH24:MI') CRT
FROM DM_DNM_SALES_RESULT_IF
WHERE DIVISION_ID IN ('81','82','81_HG','81_UC') AND SALES_POSTING_DATE BETWEEN '20260801' AND '20261130'
GROUP BY DIVISION_ID, SUBSTR(SALES_POSTING_DATE,1,6), CURRENCY ORDER BY 1,2,3
