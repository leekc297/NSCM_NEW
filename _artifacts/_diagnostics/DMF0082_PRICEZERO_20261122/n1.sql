SELECT COMPANY_ID, LEFT(SALES_POSTING_DATE,6) YM, COUNT(*) N,
 SUM(CASE WHEN SALES_AMOUNT_SUM = SALES_AMOUNT_FOR THEN 1 ELSE 0 END) SUM_EQ_FOR,
 SUM(CASE WHEN DOC_AMT_KRW <> 0 AND DOC_AMT_FOR <> 0 THEN 1 ELSE 0 END) DOC_BOTH,
 MIN(CASE WHEN DOC_AMT_FOR<>0 THEN ROUND(DOC_AMT_KRW/DOC_AMT_FOR,1) END) DOCRATE_MIN, MAX(CASE WHEN DOC_AMT_FOR<>0 THEN ROUND(DOC_AMT_KRW/DOC_AMT_FOR,1) END) DOCRATE_MAX,
 MIN(CASE WHEN SALES_AMOUNT_FOR<>0 THEN ROUND(SALES_AMOUNT_SUM/SALES_AMOUNT_FOR,1) END) SUMRATE_MIN, MAX(CASE WHEN SALES_AMOUNT_FOR<>0 THEN ROUND(SALES_AMOUNT_SUM/SALES_AMOUNT_FOR,1) END) SUMRATE_MAX,
 MIN(TRANSFER_DATE) TR_MIN, MAX(TRANSFER_DATE) TR_MAX
FROM XIF_ERP_SALES_RESULT_R_SN WITH(NOLOCK)
WHERE SALES_POSTING_DATE BETWEEN '20260601' AND '20261031' AND SALES_AMOUNT_FOR <> 0 AND CURRENCY='USD' AND COMPANY_ID='MI00'
GROUP BY COMPANY_ID, LEFT(SALES_POSTING_DATE,6) ORDER BY 2
