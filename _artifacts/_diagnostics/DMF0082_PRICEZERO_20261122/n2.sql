FROM XIF_ERP_SALES_RESULT_R_SN WITH(NOLOCK)
WHERE COMPANY_ID='MI00' AND CURRENCY='USD' AND SALES_POSTING_DATE BETWEEN '20261001' AND '20261031' AND SALES_AMOUNT_FOR<>0
