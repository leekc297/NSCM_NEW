SELECT DIVISION_ID, SUBSTR(SALES_POSTING_DATE,1,6) YM, COMPANY_ID, COUNT(*) N, SUM(CASE WHEN SALES_AMOUNT_SUM = SALES_AMOUNT_FOR THEN 1 ELSE 0 END) EQ
FROM DM_DNM_SALES_RESULT_IF WHERE DIVISION_ID IN ('81','82') AND CURRENCY='USD' AND SALES_POSTING_DATE BETWEEN '20260801' AND '20261031' AND SALES_AMOUNT_FOR<>0
GROUP BY DIVISION_ID, SUBSTR(SALES_POSTING_DATE,1,6), COMPANY_ID ORDER BY 1,2,3
