SELECT K.DIVISION_ID, COUNT(*) KEYS, SUM(CASE WHEN K.KRW = K.LOC THEN 1 ELSE 0 END) KRW_EQ_LOC, MIN(K.YYYYMMDD) MN, MAX(K.YYYYMMDD) MX
FROM (SELECT DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, FCST_TYPE, DOM_EXP, INCOTERMS, PLANT_SITE_ID, YYYYMMDD,
        SUM(CASE WHEN MEASURE='MKT_AMT_KRW' THEN QTY END) KRW, SUM(CASE WHEN MEASURE='MKT_AMT_LOC' THEN QTY END) LOC
      FROM DM_PLN_SALES_PLAN_RESULT WHERE YYYYMMDD >= '20260101' AND MEASURE IN ('MKT_AMT_KRW','MKT_AMT_LOC')
      GROUP BY DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, FCST_TYPE, DOM_EXP, INCOTERMS, PLANT_SITE_ID, YYYYMMDD) K
WHERE K.LOC <> 0
GROUP BY K.DIVISION_ID ORDER BY 1
