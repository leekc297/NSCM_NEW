SELECT 'PLAN' SRC, DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, INCOTERMS, FCST_TYPE, MEASURE, COUNT(*) N, MIN(YYYYMMDD) MN, MAX(YYYYMMDD) MX, ROUND(SUM(QTY),2) Q
FROM DM_PLN_SALES_PLAN WHERE ITEM_ID='MIP474586B11' AND DIVISION_ID LIKE '81%' AND YYYYMMDD BETWEEN '20261001' AND '20261231' AND QTY<>0
GROUP BY DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, INCOTERMS, FCST_TYPE, MEASURE
UNION ALL
SELECT 'PRICE', DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, INCOTERMS, FCST_TYPE, MEASURE||':'||CURRENCY, COUNT(*), MIN(YYYYMMDD), MAX(YYYYMMDD), MAX(PRICE)
FROM SCM_MST_FUTURE_PRICE WHERE ITEM_ID='MIP474586B11' AND DIVISION_ID LIKE '81%' AND YYYYMMDD BETWEEN '20261001' AND '20261231'
GROUP BY DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, INCOTERMS, FCST_TYPE, MEASURE||':'||CURRENCY
UNION ALL
SELECT 'MKTFCST', DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, INCOTERMS, FCST_TYPE, MEASURE, COUNT(*), MIN(YYYYMMDD), MAX(YYYYMMDD), SUM(QTY)
FROM DM_PLN_MKT_FCST WHERE ITEM_ID='MIP474586B11' AND DIVISION_ID LIKE '81%' AND YYYYMMDD BETWEEN '20261001' AND '20261231' AND QTY<>0 AND MEASURE<>'BALANCE'
GROUP BY DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, INCOTERMS, FCST_TYPE, MEASURE
ORDER BY 1,2,3,4,7
