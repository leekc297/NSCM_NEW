SELECT SUBSTR(YYYYMMDD,1,8) D, MEASURE, COUNT(*) N, ROUND(SUM(QTY),2) QTY, MAX(LAST_UPDATED_BY) KEEP (DENSE_RANK LAST ORDER BY LAST_UPDATE_DATE) UPD_BY, TO_CHAR(MAX(LAST_UPDATE_DATE),'YYYY-MM-DD HH24:MI') UPD
FROM DM_PLN_SALES_PLAN
WHERE DIVISION_ID LIKE '81%' AND YYYYMMDD BETWEEN '20261026' AND '20261130' AND MEASURE IN ('RTF_SYS_RP','MKT_AMT_LOC','MKT_AMT_KRW')
GROUP BY SUBSTR(YYYYMMDD,1,8), MEASURE ORDER BY 1,2
