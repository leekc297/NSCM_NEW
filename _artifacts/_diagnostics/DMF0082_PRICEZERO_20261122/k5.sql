SELECT COMPANY_ID, LEFT(SALES_POSTING_DATE,6) YM, COUNT(*) N,
 SUM(CASE WHEN SALES_AMOUNT_SUM = SALES_AMOUNT_FOR THEN 1 ELSE 0 END) SUM_EQ_FOR,
 SUM(CASE WHEN DOC_AMT_KRW = DOC_AMT_FOR THEN 1 ELSE 0 END) DOCKRW_EQ_FOR, MAX(TRANSFER_DATE) TR
FROM XIF_ERP_SALES_RESULT_R_SN WITH(NOLOCK)
WHERE SALES_POSTING_DATE BETWEEN '20260801' AND '20261031' AND SALES_AMOUNT_FOR <> 0 AND CURRENCY='USD' AND COMPANY_ID IN ('MI00','GM00','HD00','ST00','VT00','WA00','HQ00')
GROUP BY COMPANY_ID, LEFT(SALES_POSTING_DATE,6) ORDER BY 1,2
