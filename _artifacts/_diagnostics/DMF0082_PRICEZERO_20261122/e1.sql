SELECT DIVISION_ID, LEFT(SALES_POSTING_DATE,6) YM, CURRENCY, COUNT(*) N,
  SUM(CASE WHEN SALES_AMOUNT_SUM = SALES_AMOUNT_FOR AND SALES_AMOUNT_FOR<>0 THEN 1 ELSE 0 END) SUM_EQ_FOR, MAX(CREATION_DATE) CRT
FROM DM_DNM_SALES_RESULT_IF WITH(NOLOCK)
WHERE DIVISION_ID IN ('81','82') AND SALES_POSTING_DATE >= '20260601' AND CURRENCY='USD'
GROUP BY DIVISION_ID, LEFT(SALES_POSTING_DATE,6), CURRENCY ORDER BY 1,2
