SELECT COMPANY_ID, DOC_CURRENCY, CURRENCY, COUNT(*) N,
 SUM(CASE WHEN SALES_AMOUNT_SUM = SALES_AMOUNT_FOR THEN 1 ELSE 0 END) SUM_EQ_FOR,
 SUM(CASE WHEN DOC_AMT_KRW = DOC_AMT_FOR THEN 1 ELSE 0 END) DOCKRW_EQ_FOR,
 MIN(SALES_POSTING_DATE) MN, MAX(SALES_POSTING_DATE) MX, MAX(TRANSFER_DATE) TR
FROM XIF_ERP_SALES_RESULT_R_SN WITH(NOLOCK)
WHERE SALES_POSTING_DATE BETWEEN '20260901' AND '20261031' AND SALES_AMOUNT_FOR <> 0 AND CURRENCY='USD'
GROUP BY COMPANY_ID, DOC_CURRENCY, CURRENCY ORDER BY 5 DESC
