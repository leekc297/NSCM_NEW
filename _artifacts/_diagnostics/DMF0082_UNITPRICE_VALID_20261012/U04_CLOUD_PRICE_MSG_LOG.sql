-- U04_CLOUD_PRICE_MSG_LOG.sql — 10-09 '단가 없음' 메시지를 낸 화면·SP 식별 (READ-ONLY, 전체 F5, 값 입력 없음)
--   계정: SCM_MGR · 클라우드 QA.
--   단가 없음 계열 메시지를 내는 SP 전수(사내 ALL_SOURCE 실측): PKG_DMF0082 · PKG_DMF0003 (Unit Price Not Found)
--     · PKG_DMF0021 Sales Plan (MSG00462 동일 주차 Price 미등록 · MSG00328 판가 미입력) · PKG_SSP0200/0201 (판가 13주)
SET LINESIZE 400 PAGESIZE 300
PROMPT ################ [V1] 10-08 ~ 현재 — 검증 실패 로그 전체 (화면 무관) ################
SELECT TO_CHAR(EVENT_DATE,'MM-DD HH24:MI:SS') T, PROGRAM_NAME, LOG_TYPE, CREATED_BY
     , REPLACE(SUBSTR(DESCRIPTION,1,300),CHR(10),' | ') D
  FROM SCM_SYS_LOG_BATCH
 WHERE EVENT_DATE >= TO_DATE('20261008','YYYYMMDD')
   AND (   LOG_TYPE = 'INVALID'
        OR (LOG_TYPE = 'END' AND LOG_MESSAGE LIKE '%FAIL%')
        OR DESCRIPTION LIKE '%MSG00462%' OR DESCRIPTION LIKE '%MSG00328%' OR DESCRIPTION LIKE '%MSG01325%'
        OR UPPER(DESCRIPTION) LIKE '%PRICE%NOT%' OR DESCRIPTION LIKE '%단가%' OR DESCRIPTION LIKE '%판가%')
 ORDER BY EVENT_DATE DESC FETCH FIRST 80 ROWS ONLY;

PROMPT ################ [V2] Sales Plan(PKG_DMF0021) 판가 검증 실패 — 최근 30일, 입력값 포함 ################
SELECT TO_CHAR(EVENT_DATE,'MM-DD HH24:MI:SS') T, CREATED_BY
     , REPLACE(SUBSTR(DESCRIPTION,1,330),CHR(10),' | ') D
     , SUBSTR(IN_PARA_DATA,1,500) P
  FROM SCM_SYS_LOG_BATCH
 WHERE PROGRAM_NAME LIKE '%DMF0021%' AND EVENT_DATE >= SYSDATE-30
   AND (DESCRIPTION LIKE '%MSG00462%' OR DESCRIPTION LIKE '%MSG00328%')
 ORDER BY EVENT_DATE DESC FETCH FIRST 30 ROWS ONLY;
PROMPT --  판정: D 의 Project Code / Plant Site / Cell Prod Site / Week 가 판가(LOC) 원장과 대조된 값이다
