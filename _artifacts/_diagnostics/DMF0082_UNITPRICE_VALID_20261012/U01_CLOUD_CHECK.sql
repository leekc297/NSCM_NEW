-- U01_CLOUD_CHECK.sql — DMF0082 40 저장 'Unit Price Not Found' 오탐 원인 확인 (READ-ONLY, 전체 F5, 값 입력 없음)
--   계정: SCM_MGR · 클라우드 QA/DEV. 사내 ZIOUI1 2026-10-12 검증 기준값을 주석으로 병기.
--   가설: 저장 스테이징 GTT(GT_PRDM1_T_MAIN)의 DEFAULT ON NULL 이 아직 '-' 인데 원장 데이터·DEFAULT 는 '/' 로 전환됨
--         → 화면이 빈값으로 보낸 키 컬럼(40 의 Plant Site 등)이 스테이징에서 '-' 가 되어 '/' 원장 판가와 조인 불일치 → 당주 LOC 가 있어도 차단
SET LINESIZE 300 PAGESIZE 200
PROMPT ################ [U1] 스테이징 GTT vs 원장 — 키 컬럼 DEFAULT (사내: GTT '-' / 원장 '/') ################
SELECT TABLE_NAME, COLUMN_NAME, DEFAULT_ON_NULL
  FROM USER_TAB_COLUMNS
 WHERE TABLE_NAME IN ('GT_PRDM1_T_MAIN','DM_PLN_CFM_SELLING_PRICE','DM_PLN_CFM_MKT_DEMAND_PLAN','SCM_MST_FUTURE_PRICE','DM_PLN_MKT_FCST')
   AND COLUMN_NAME IN ('PLANT_SITE_ID','CELL_PROD_SITE_ID','END_CUSTOMER','DOM_EXP','INCOTERMS','FCST_TYPE')
 ORDER BY 1, 2;
PROMPT --  DATA_DEFAULT 는 LONG 이라 아래 XML 변환으로 값 표시 (권한 없으면 이 문장만 오류 — 무시)
SELECT X.T, X.C, X.D
  FROM XMLTABLE('/ROWSET/ROW' PASSING DBMS_XMLGEN.GETXMLTYPE(
        'SELECT TABLE_NAME T, COLUMN_NAME C, DATA_DEFAULT D FROM USER_TAB_COLUMNS WHERE TABLE_NAME IN (''GT_PRDM1_T_MAIN'',''DM_PLN_CFM_SELLING_PRICE'',''DM_PLN_CFM_MKT_DEMAND_PLAN'') AND COLUMN_NAME IN (''PLANT_SITE_ID'',''CELL_PROD_SITE_ID'',''END_CUSTOMER'',''DOM_EXP'',''INCOTERMS'',''FCST_TYPE'')')
        COLUMNS T VARCHAR2(40) PATH 'T', C VARCHAR2(40) PATH 'C', D VARCHAR2(40) PATH 'D') X
 ORDER BY 1, 2;
PROMPT --  판정: GT_PRDM1_T_MAIN 이 '-' 이고 원장이 '/' 면 가설 성립

PROMPT ################ [U2] 40 판가·수요 원장의 센티널 표기 분포 — 금주 이후 (사내: 전부 '-') ################
SELECT 'PRICE' TB, 'PLANT' C, PLANT_SITE_ID V, COUNT(*) N FROM DM_PLN_CFM_SELLING_PRICE WHERE DIVISION_ID='40' AND YYYYMMDD >= TO_CHAR(TRUNC(SYSDATE,'IW'),'YYYYMMDD') AND PLANT_SITE_ID IN ('-','/',' ') GROUP BY PLANT_SITE_ID
UNION ALL SELECT 'PRICE','CELLPROD', CELL_PROD_SITE_ID, COUNT(*) FROM DM_PLN_CFM_SELLING_PRICE WHERE DIVISION_ID='40' AND YYYYMMDD >= TO_CHAR(TRUNC(SYSDATE,'IW'),'YYYYMMDD') AND CELL_PROD_SITE_ID IN ('-','/',' ') GROUP BY CELL_PROD_SITE_ID
UNION ALL SELECT 'PRICE','ENDCUST', END_CUSTOMER, COUNT(*) FROM DM_PLN_CFM_SELLING_PRICE WHERE DIVISION_ID='40' AND YYYYMMDD >= TO_CHAR(TRUNC(SYSDATE,'IW'),'YYYYMMDD') AND END_CUSTOMER IN ('-','/',' ') GROUP BY END_CUSTOMER
UNION ALL SELECT 'DEMAND','PLANT', PLANT_SITE_ID, COUNT(*) FROM DM_PLN_CFM_MKT_DEMAND_PLAN WHERE DIVISION_ID='40' AND YYYYMMDD >= TO_CHAR(TRUNC(SYSDATE,'IW'),'YYYYMMDD') AND PLANT_SITE_ID IN ('-','/',' ') GROUP BY PLANT_SITE_ID
UNION ALL SELECT 'DEMAND','CELLPROD', CELL_PROD_SITE_ID, COUNT(*) FROM DM_PLN_CFM_MKT_DEMAND_PLAN WHERE DIVISION_ID='40' AND YYYYMMDD >= TO_CHAR(TRUNC(SYSDATE,'IW'),'YYYYMMDD') AND CELL_PROD_SITE_ID IN ('-','/',' ') GROUP BY CELL_PROD_SITE_ID
 ORDER BY 1, 2, 3;
PROMPT --  판정: 같은 컬럼에 '-' 와 '/' 가 함께 있으면, 전환 뒤 저장된 행이 '-' 로 다시 들어온 것 (스테이징 DEFAULT '-' 의 결과)

PROMPT ################ [U3] 전환 뒤 '-' 로 새로 들어온 행 — 누가 언제 (최근 14일) ################
SELECT 'DEMAND' TB, TO_CHAR(TRUNC(LAST_UPDATE_DATE),'MM-DD') D, LAST_UPDATED_BY, COUNT(*) N
  FROM DM_PLN_CFM_MKT_DEMAND_PLAN WHERE DIVISION_ID='40' AND LAST_UPDATE_DATE >= SYSDATE-14 AND (PLANT_SITE_ID='-' OR CELL_PROD_SITE_ID='-' OR END_CUSTOMER='-')
 GROUP BY TO_CHAR(TRUNC(LAST_UPDATE_DATE),'MM-DD'), LAST_UPDATED_BY
UNION ALL
SELECT 'PRICE', TO_CHAR(TRUNC(LAST_UPDATE_DATE),'MM-DD'), LAST_UPDATED_BY, COUNT(*)
  FROM DM_PLN_CFM_SELLING_PRICE WHERE DIVISION_ID='40' AND LAST_UPDATE_DATE >= SYSDATE-14 AND (PLANT_SITE_ID='-' OR CELL_PROD_SITE_ID='-' OR END_CUSTOMER='-')
 GROUP BY TO_CHAR(TRUNC(LAST_UPDATE_DATE),'MM-DD'), LAST_UPDATED_BY
 ORDER BY 1, 2;

PROMPT ################ [U4] 실제 차단 이력 — 저장 SP 로그의 Unit Price Not Found (최근 14일, 메시지에 Plant/Cell Prod 값 표시) ################
SELECT TO_CHAR(EVENT_DATE,'MM-DD HH24:MI:SS') T, CREATED_BY, REPLACE(SUBSTR(DESCRIPTION,1,260),CHR(10),' | ') D
  FROM SCM_SYS_LOG_BATCH
 WHERE PROGRAM_NAME LIKE '%DMF0082%' AND LOG_TYPE='INVALID' AND DESCRIPTION LIKE '%Unit Price Not Found%' AND EVENT_DATE >= SYSDATE-14
 ORDER BY EVENT_DATE DESC FETCH FIRST 30 ROWS ONLY;
PROMPT --  판정: 메시지의 'Plant Site : -' 또는 'Cell Prod Site : -' 인데 원장([U2])은 '/' 이면 표기 불일치 오탐 확정
