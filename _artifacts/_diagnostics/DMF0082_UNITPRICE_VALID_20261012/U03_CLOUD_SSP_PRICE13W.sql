-- U03_CLOUD_SSP_PRICE13W.sql — SSP 출하 신규 저장의 "판가 미입력" 검사(13주) 오탐 확인 (READ-ONLY, 전체 F5, 값 입력 없음)
--   계정: SCM_MGR · 클라우드 QA.
--   대상 검사: PKG_SSP0200 / PKG_SSP0201 .P_..._SAVE_SHIPMENT_CONFIRM_NEW 의 판가 입력 정보 조회
--     = SCM_MST_FUTURE_PRICE(MEASURE='KRW') 의 **월요일 행**이 당주 월요일부터 13주 전부 있어야 통과.
--       단, (PLANT_SITE_ID, DOM_EXP) 별로 GROUP BY 해서 한 그룹이 13 이어야 한다  ← 표기가 섞이면 13주가 다 있어도 탈락
SET LINESIZE 300 PAGESIZE 300
PROMPT ################ [S1] 40 판가 마스터(KRW) 13주 구간 — Plant Site / DOM_EXP 표기 분포 ################
SELECT 'PLANT' C, NVL(A.PLANT_SITE_ID,'(null)') V, COUNT(*) N, TO_CHAR(MIN(A.LAST_UPDATE_DATE),'MM-DD HH24:MI') FIRST_UPD, TO_CHAR(MAX(A.LAST_UPDATE_DATE),'MM-DD HH24:MI') LAST_UPD
  FROM SCM_MST_FUTURE_PRICE A
 WHERE A.DIVISION_ID = '40' AND A.MEASURE = 'KRW'
   AND A.YYYYMMDD BETWEEN TO_CHAR(TRUNC(SYSDATE,'IW'),'YYYYMMDD') AND TO_CHAR(TRUNC(SYSDATE,'IW')+90,'YYYYMMDD')
   AND (A.PLANT_SITE_ID IN ('-','/',' ','--') OR A.PLANT_SITE_ID IS NULL)
 GROUP BY NVL(A.PLANT_SITE_ID,'(null)')
UNION ALL
SELECT 'DOM_EXP', NVL(A.DOM_EXP,'(null)'), COUNT(*), TO_CHAR(MIN(A.LAST_UPDATE_DATE),'MM-DD HH24:MI'), TO_CHAR(MAX(A.LAST_UPDATE_DATE),'MM-DD HH24:MI')
  FROM SCM_MST_FUTURE_PRICE A
 WHERE A.DIVISION_ID = '40' AND A.MEASURE = 'KRW'
   AND A.YYYYMMDD BETWEEN TO_CHAR(TRUNC(SYSDATE,'IW'),'YYYYMMDD') AND TO_CHAR(TRUNC(SYSDATE,'IW')+90,'YYYYMMDD')
 GROUP BY NVL(A.DOM_EXP,'(null)')
 ORDER BY 1, 2;
PROMPT --  판정: PLANT 에 '-' 와 '/' 가 함께 있으면 표기 혼재 (같은 키의 13주가 두 그룹으로 갈라질 수 있음)

PROMPT ################ [S2] 13주가 다 있는데도 검사에서 탈락하는 키 (오탐) — 요약 ################
WITH W AS (
    SELECT TO_CHAR(TRUNC(SYSDATE,'IW') + 7*(LEVEL-1),'YYYYMMDD') AS MON FROM DUAL CONNECT BY LEVEL <= 13
), P AS (
    SELECT A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.FCST_TYPE, A.INCOTERMS, A.PLANT_SITE_ID, A.DOM_EXP, A.YYYYMMDD
      FROM SCM_MST_FUTURE_PRICE A
      JOIN W ON W.MON = A.YYYYMMDD
     WHERE A.DIVISION_ID = '40' AND A.MEASURE = 'KRW'
), G AS (
    SELECT PROJECT_CODE, SCM_SITE_ID, ITEM_ID, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, DOM_EXP, COUNT(*) AS CNT
      FROM P GROUP BY PROJECT_CODE, SCM_SITE_ID, ITEM_ID, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, DOM_EXP
), K AS (
    SELECT PROJECT_CODE, SCM_SITE_ID, ITEM_ID, FCST_TYPE, INCOTERMS
         , (SELECT COUNT(DISTINCT P.YYYYMMDD) FROM P WHERE P.PROJECT_CODE = G.PROJECT_CODE AND P.SCM_SITE_ID = G.SCM_SITE_ID AND P.ITEM_ID = G.ITEM_ID AND P.FCST_TYPE = G.FCST_TYPE AND P.INCOTERMS = G.INCOTERMS) AS WEEKS
         , MAX(CNT) AS MAX_GRP, COUNT(*) AS GRPS
         , COUNT(DISTINCT PLANT_SITE_ID) AS PLANTS, COUNT(DISTINCT DOM_EXP) AS DOMS
         , LISTAGG(PLANT_SITE_ID || ':' || DOM_EXP || '=' || CNT, ', ') WITHIN GROUP (ORDER BY PLANT_SITE_ID, DOM_EXP) AS DETAIL
      FROM G GROUP BY PROJECT_CODE, SCM_SITE_ID, ITEM_ID, FCST_TYPE, INCOTERMS
)
SELECT CASE WHEN WEEKS = 13 AND MAX_GRP = 13 THEN '1.통과'
            WHEN WEEKS = 13 AND MAX_GRP < 13 AND PLANTS > 1 THEN '2.오탐-Plant 표기 갈림'
            WHEN WEEKS = 13 AND MAX_GRP < 13 THEN '3.오탐-DOM_EXP 갈림'
            ELSE '4.13주 미충족(정상 차단)' END AS VERDICT
     , COUNT(*) AS KEYS
  FROM K GROUP BY CASE WHEN WEEKS = 13 AND MAX_GRP = 13 THEN '1.통과'
            WHEN WEEKS = 13 AND MAX_GRP < 13 AND PLANTS > 1 THEN '2.오탐-Plant 표기 갈림'
            WHEN WEEKS = 13 AND MAX_GRP < 13 THEN '3.오탐-DOM_EXP 갈림'
            ELSE '4.13주 미충족(정상 차단)' END
 ORDER BY 1;

PROMPT ################ [S3] 오탐 키 목록 (최대 60) — DETAIL = Plant:DOM_EXP=주 수 ################
WITH W AS (
    SELECT TO_CHAR(TRUNC(SYSDATE,'IW') + 7*(LEVEL-1),'YYYYMMDD') AS MON FROM DUAL CONNECT BY LEVEL <= 13
), P AS (
    SELECT A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.FCST_TYPE, A.INCOTERMS, A.PLANT_SITE_ID, A.DOM_EXP, A.YYYYMMDD, A.LAST_UPDATE_DATE, A.LAST_UPDATED_BY
      FROM SCM_MST_FUTURE_PRICE A
      JOIN W ON W.MON = A.YYYYMMDD
     WHERE A.DIVISION_ID = '40' AND A.MEASURE = 'KRW'
), G AS (
    SELECT PROJECT_CODE, SCM_SITE_ID, ITEM_ID, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, DOM_EXP, COUNT(*) AS CNT
         , MAX(LAST_UPDATE_DATE) AS UPD, MAX(LAST_UPDATED_BY) KEEP (DENSE_RANK LAST ORDER BY LAST_UPDATE_DATE) AS UPD_BY
      FROM P GROUP BY PROJECT_CODE, SCM_SITE_ID, ITEM_ID, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, DOM_EXP
), T AS (
    SELECT PROJECT_CODE, SCM_SITE_ID, ITEM_ID, FCST_TYPE, INCOTERMS, COUNT(DISTINCT YYYYMMDD) AS WEEKS
      FROM P GROUP BY PROJECT_CODE, SCM_SITE_ID, ITEM_ID, FCST_TYPE, INCOTERMS
)
SELECT G.PROJECT_CODE, G.SCM_SITE_ID, G.ITEM_ID, G.FCST_TYPE, G.INCOTERMS
     , LISTAGG('[' || G.PLANT_SITE_ID || ']:' || G.DOM_EXP || '=' || G.CNT || '(' || TO_CHAR(G.UPD,'MM-DD') || ' ' || G.UPD_BY || ')', ', ')
         WITHIN GROUP (ORDER BY G.PLANT_SITE_ID, G.DOM_EXP) AS DETAIL
  FROM G JOIN T ON T.PROJECT_CODE = G.PROJECT_CODE AND T.SCM_SITE_ID = G.SCM_SITE_ID AND T.ITEM_ID = G.ITEM_ID AND T.FCST_TYPE = G.FCST_TYPE AND T.INCOTERMS = G.INCOTERMS
 WHERE T.WEEKS = 13
 GROUP BY G.PROJECT_CODE, G.SCM_SITE_ID, G.ITEM_ID, G.FCST_TYPE, G.INCOTERMS
HAVING MAX(G.CNT) < 13
 ORDER BY 1, 2, 3
 FETCH FIRST 60 ROWS ONLY;

PROMPT ################ [S4] 당주에 판가(KRW)가 있으나 월요일 행이 아닌 키 — 주 중간일 저장 (최대 40) ################
SELECT A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.FCST_TYPE, A.INCOTERMS, A.PLANT_SITE_ID
     , LISTAGG(A.YYYYMMDD, ',') WITHIN GROUP (ORDER BY A.YYYYMMDD) AS DAYS
     , TO_CHAR(MAX(A.LAST_UPDATE_DATE),'MM-DD HH24:MI') AS UPD, MAX(A.LAST_UPDATED_BY) AS UPD_BY
  FROM SCM_MST_FUTURE_PRICE A
 WHERE A.DIVISION_ID = '40' AND A.MEASURE = 'KRW'
   AND A.YYYYMMDD BETWEEN TO_CHAR(TRUNC(SYSDATE,'IW')-7,'YYYYMMDD') AND TO_CHAR(TRUNC(SYSDATE,'IW')+6,'YYYYMMDD')
 GROUP BY A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.FCST_TYPE, A.INCOTERMS, A.PLANT_SITE_ID
HAVING SUM(CASE WHEN TO_CHAR(TO_DATE(A.YYYYMMDD,'YYYYMMDD'),'DY','NLS_DATE_LANGUAGE=ENGLISH') = 'MON' THEN 1 ELSE 0 END) = 0
 ORDER BY MAX(A.LAST_UPDATE_DATE) DESC
 FETCH FIRST 40 ROWS ONLY;

PROMPT ################ [S5] SSP 출하 신규 저장 호출 이력 — 최근 7일 ################
SELECT TO_CHAR(EVENT_DATE,'MM-DD HH24:MI:SS') T, PROGRAM_NAME, LOG_TYPE, SUBSTR(LOG_MESSAGE,1,140) M, CREATED_BY
  FROM SCM_SYS_LOG_BATCH
 WHERE (PROGRAM_NAME LIKE '%SSP0200%' OR PROGRAM_NAME LIKE '%SSP0201%' OR PROGRAM_NAME LIKE '%SHIPMENT_CONFIRM_NEW%')
   AND EVENT_DATE >= SYSDATE-7 AND LOG_TYPE IN ('END','ERROR','E')
 ORDER BY EVENT_DATE DESC FETCH FIRST 40 ROWS ONLY;
