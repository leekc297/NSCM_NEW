    V_LOG_TYPE    := 'START';
    V_LOG_MESSAGE := '########## Start of procedure ##########';
    V_DESCRIPTION := 'p_division_id :' || P_DIVISION_ID || '/p_version_no :' || P_VERSION_NO || '/p_created_by :' || P_CREATED_BY || '/ 소형 중장기';
    D_EVENT_DATE  := SYSDATE;
    PR_SCM_SYS_LOG_BATCH(V_PROGRAM_NAME, V_LOG_TYPE, N_LOG_COUNT, V_LOG_MESSAGE, V_DESCRIPTION, D_EVENT_DATE);
    V_LOG_MESSAGE := NULL;

    BEGIN
        /* 1. 입력제한일 룩업 */
        SELECT MAX(ATTRIBUTE1), MAX(SUBSTR(ATTRIBUTE1,1,6)), MAX(ATTRIBUTE2), MAX(SUBSTR(ATTRIBUTE2,1,6))
          INTO V_RESTRICT_START_YYYYMMDD, V_RESTRICT_START_YYYYMM, V_RESTRICT_END_YYYYMMDD, V_RESTRICT_END_YYYYMM
          FROM SCM_ADM_LOOKUP_MASTER_DETAIL
         WHERE LOOKUP_TYPE = 'DM_LONG_PLAN_START_YYYYMMDD' AND SEGMENT1 = P_DIVISION_ID AND VALID_YN = 'Y';

