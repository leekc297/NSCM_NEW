PROCEDURE           "PR_DM_LONGPLAN_40_DELETE_IMPORT" 

(
      P_DIVISION_ID   IN VARCHAR2
    , P_VERSION_NO    IN VARCHAR2
    , P_CREATED_BY    IN VARCHAR2
)
/*
 * Program ID   : PR_DM_LONGPLAN_40_DELETE_IMPORT (소형 중장기 - BP_FCST → MKT/CFM 적재)
 * Called by    : 필요에 의해 직접 수행(수동 유틸리티)
 * 변환(MSSQL->Oracle) 2026-07-01 SCMADM : 구 기계번역 파손(BEGIN TRY·본문중DECLARE) 전면 재작성. 객체15(RESTORE) 형제 패턴
 *   - #TEMP_LOOK_UP_DATA → GTT GT_LP40DI_LOOKUP(PRESERVE, 시작 DELETE). CROSS APPLY STRING_SPLIT → CROSS JOIN TABLE(STRING_SPLIT(..))
 *   - ISDATE(x)<1 → NULL체크+TO_DATE블록.  GETDATE→SYSDATE, YYYYMM||'01', LTRIM(RTRIM)→TRIM, ISNULL(x,'')<>''→TRIM(x) IS NOT NULL
 *   - 검증 결과셋(DIFF COUNT) → DBMS_OUTPUT(수동 유틸, H-9). 원본 raw 데이터조회 SELECT(진단 나열)는 보류(주석) — 수동 조회 가능
 *   - RAISERROR+TRY/CATCH(비재발생) → RAISE_APPLICATION_ERROR + EXCEPTION WHEN OTHERS(swallow+log)
 *   - 의존 co-call: PR_DM_ANL_SALES_PLAN_AMT_CREATE_LOCAL_KRW(SP 재계산, 현재 VALID)
 * 2026.07.06	ZIONEX		[PJ202650304] NextSCM Migration
 */
AS
    V_PROGRAM_NAME             VARCHAR2(150 CHAR) := 'PR_DM_LONGPLAN_40_DELETE_IMPORT';
    V_LOG_TYPE                 VARCHAR2(30 CHAR);
    N_LOG_COUNT                INTEGER := 0;
    V_LOG_MESSAGE              VARCHAR2(1000 CHAR);
    V_DESCRIPTION              VARCHAR2(500 CHAR);
    V_ERRMSG                   VARCHAR2(1000 CHAR);
    D_EVENT_DATE               DATE;
    V_RESTRICT_START_YYYYMMDD  VARCHAR2(8 CHAR);
    V_RESTRICT_START_YYYYMM    VARCHAR2(6 CHAR);
    V_RESTRICT_END_YYYYMMDD    VARCHAR2(8 CHAR);
    V_RESTRICT_END_YYYYMM      VARCHAR2(6 CHAR);
    V_DUMMY                    DATE;
    V_CHK                      INTEGER;
    V_CNT                      NUMBER;
BEGIN
