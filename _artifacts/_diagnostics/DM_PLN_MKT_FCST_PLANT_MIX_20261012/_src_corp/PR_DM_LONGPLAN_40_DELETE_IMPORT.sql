        SELECT A.SEGMENT1, A.SEGMENT2, S.COLUMN_VALUE
          FROM ( SELECT SEGMENT1, SEGMENT2, ATTRIBUTE1
                   FROM SCM_ADM_LOOKUP_MASTER_DETAIL
                  WHERE LOOKUP_TYPE = 'MAPPING_CELL_PROD_SITE' AND VALID_YN = 'Y' ) A
               CROSS JOIN TABLE(STRING_SPLIT(A.ATTRIBUTE1, ',')) S;


