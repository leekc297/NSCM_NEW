         WHERE DIVISION_ID = P_DIVISION_ID AND YYYYMMDD >= V_RESTRICT_START_YYYYMMDD AND YYYYMMDD <= V_RESTRICT_END_YYYYMMDD;
        DELETE FROM DM_PLN_CFM_MKT_DEMAND_PLAN
         WHERE DIVISION_ID = P_DIVISION_ID AND YYYYMMDD >= V_RESTRICT_START_YYYYMMDD AND YYYYMMDD <= V_RESTRICT_END_YYYYMMDD;

