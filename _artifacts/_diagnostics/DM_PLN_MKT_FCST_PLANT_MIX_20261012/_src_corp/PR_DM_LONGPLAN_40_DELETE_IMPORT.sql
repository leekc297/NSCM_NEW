                   ( DIVISION_ID, PROJECT_CODE, END_CUSTOMER, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, MEASURE, PLANT_SITE_ID, CELL_PROD_SITE_ID, YYYYMMDD, QTY
                   , CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE
                   , ATTRIBUTE1,ATTRIBUTE2,ATTRIBUTE3,ATTRIBUTE4,ATTRIBUTE5,ATTRIBUTE6,ATTRIBUTE7,ATTRIBUTE8,ATTRIBUTE9,ATTRIBUTE10 )
            SELECT T.DIVISION_ID, T.PROJECT_CODE, T.END_CUSTOMER, T.SCM_SITE_ID, T.ITEM_ID, T.DOM_EXP, T.FCST_TYPE, T.INCOTERMS, T.MEASURE, T.PLANT_SITE_ID, T.CELL_PROD_SITE_ID, T.YYYYMM||'01', SUM(T.QTY)
                 , P_CREATED_BY, SYSDATE, P_CREATED_BY, SYSDATE
                 , NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL
              FROM ( SELECT A.DIVISION_ID, A.PROJECT_CODE, A.PROJECT_CODE AS END_CUSTOMER, A.SCM_SITE_ID, TRIM(A.ITEM_ID) AS ITEM_ID, 'E' AS DOM_EXP, A.FCST_TYPE, A.INCOTERMS
                          , 'VMI_In_Req' AS MEASURE, A.PLANT_SITE_ID, A.YYYYMM, A.QTY
                          , CASE WHEN D.ITEM_ID IS NOT NULL AND E.MGMT_CELL_PROD_SITE_ID IS NOT NULL THEN E.MGMT_CELL_PROD_SITE_ID
--                                 WHEN D.ITEM_ID IS NOT NULL AND E.MGMT_CELL_PROD_SITE_ID IS NULL THEN '-' ELSE '-' END AS CELL_PROD_SITE_ID    --  2026.10.11 AJS
                                 WHEN D.ITEM_ID IS NOT NULL AND E.MGMT_CELL_PROD_SITE_ID IS NULL THEN '/' ELSE '/' END AS CELL_PROD_SITE_ID    --  2026.10.11 AJS
                       FROM DM_PLN_BP_FCST_C A
                       INNER JOIN SCM_MST_SITE B ON A.DIVISION_ID=B.DIVISION_ID AND A.SCM_SITE_ID=B.SCM_SITE_ID
                       INNER JOIN SCM_MST_SITE_ITEM C ON A.DIVISION_ID=C.DIVISION_ID AND A.SCM_SITE_ID=C.SCM_SITE_ID AND A.PROJECT_CODE=C.PROJECT_CODE AND TRIM(A.ITEM_ID)=C.ITEM_ID
                       LEFT OUTER JOIN ( SELECT ITEM_ID FROM SCM_MST_ITEM_SN WHERE DIVISION_ID='40' AND FORECAST_INFO_BIZ_TYPE='CELL' AND ACTIVE_FLAG='Y' GROUP BY ITEM_ID ) D ON A.ITEM_ID=D.ITEM_ID
                       LEFT OUTER JOIN GT_LP40DI_LOOKUP E ON A.CELL_PROD_SITE=E.BP_CELL_PROD_SITE_ID AND C.REPORT_GROUP4 = CASE WHEN E.PRODUCT_DETAILS IS NULL THEN C.REPORT_GROUP4 ELSE E.PRODUCT_DETAILS END
                      WHERE A.DIVISION_ID=P_DIVISION_ID AND A.VERSION_NO=P_VERSION_NO AND A.YYYYMM>=V_RESTRICT_START_YYYYMM AND A.YYYYMM<=V_RESTRICT_END_YYYYMM
--                      AND A.MEASURE='BUSINESS_PLAN' AND TRIM(A.INCOTERMS) IS NOT NULL AND TRIM(A.FCST_TYPE) IS NOT NULL AND B.VMI_YN='Y' AND A.QTY<>0 ) T   --  2026.10.08 AJS
                        AND A.MEASURE='Business_Plan' AND TRIM(A.INCOTERMS) IS NOT NULL AND TRIM(A.FCST_TYPE) IS NOT NULL AND B.VMI_YN='Y' AND A.QTY<>0 ) T   --  2026.10.08 AJS
             GROUP BY T.DIVISION_ID, T.PROJECT_CODE, T.END_CUSTOMER, T.SCM_SITE_ID, T.ITEM_ID, T.DOM_EXP, T.FCST_TYPE, T.INCOTERMS, T.MEASURE, T.PLANT_SITE_ID, T.CELL_PROD_SITE_ID, T.YYYYMM;
        END IF;

        COMMIT;

        /* 6. SP 재계산 */
        PR_DM_ANL_SALES_PLAN_AMT_CREATE_LOCAL_KRW(P_DIVISION_ID, 'SYSTEM');


        IF P_VERSION_NO IS NOT NULL THEN
            SELECT COUNT(*) INTO V_CNT FROM (
                SELECT YYYYMM, ITEM_ID, SUM(QTY) AS BP_QTYSUM FROM DM_PLN_BP_FCST_C A
                 WHERE DIVISION_ID=P_DIVISION_ID AND VERSION_NO=P_VERSION_NO AND YYYYMM>=V_RESTRICT_START_YYYYMM AND YYYYMM<=V_RESTRICT_END_YYYYMM
--                 AND MEASURE='BUSINESS_PLAN' AND QTY<>0 AND TRIM(A.INCOTERMS) IS NOT NULL AND TRIM(A.FCST_TYPE) IS NOT NULL   --  2026.10.08 AJS
                   AND MEASURE='Business_Plan' AND QTY<>0 AND TRIM(A.INCOTERMS) IS NOT NULL AND TRIM(A.FCST_TYPE) IS NOT NULL   --  2026.10.08 AJS
                 GROUP BY YYYYMM, ITEM_ID ) A
            FULL OUTER JOIN (
                SELECT SUBSTR(YYYYMMDD,1,6) AS YYYYMM, ITEM_ID, SUM(QTY) AS IMPORT_QTYSUM FROM DM_PLN_MKT_FCST A
                 LEFT OUTER JOIN SCM_MST_SITE B ON A.DIVISION_ID=B.DIVISION_ID AND A.SCM_SITE_ID=B.SCM_SITE_ID
                 WHERE A.DIVISION_ID=P_DIVISION_ID AND YYYYMMDD>=V_RESTRICT_START_YYYYMMDD AND YYYYMMDD<=V_RESTRICT_END_YYYYMMDD
--                 AND MEASURE = CASE WHEN NVL(B.VMI_YN,'x')='Y' THEN 'VMI_IN_REQ' ELSE 'MKT_FCST' END AND QTY<>0   --  2026.10.08 AJS
                   AND MEASURE = CASE WHEN NVL(B.VMI_YN,'x')='Y' THEN 'VMI_In_Req' ELSE 'MKT_FCST' END AND QTY<>0   --  2026.10.08 AJS
                 GROUP BY SUBSTR(YYYYMMDD,1,6), ITEM_ID ) B
              ON A.ITEM_ID=B.ITEM_ID AND A.YYYYMM=B.YYYYMM
            WHERE (A.BP_QTYSUM <> B.IMPORT_QTYSUM) OR (A.ITEM_ID IS NULL) OR (B.ITEM_ID IS NULL);
            DBMS_OUTPUT.PUT_LINE('DM_PLN_BP_FCST_C vs DM_PLN_MKT_FCST DIFF 건 : ' || V_CNT);
        END IF;

    EXCEPTION
        WHEN OTHERS THEN
            V_ERRMSG      := SUBSTR(SQLERRM, 1, 1000);
            V_LOG_TYPE    := 'ERROR';
            V_LOG_MESSAGE := V_ERRMSG;
            V_DESCRIPTION := 'ERROR_LINE : ' || SUBSTR(DBMS_UTILITY.FORMAT_ERROR_BACKTRACE, 1, 400);
            D_EVENT_DATE  := SYSDATE;
            DBMS_OUTPUT.PUT_LINE('[' || TO_CHAR(SQLCODE) || ']' || V_ERRMSG);
            PR_SCM_SYS_LOG_BATCH(V_PROGRAM_NAME, V_LOG_TYPE, N_LOG_COUNT, V_LOG_MESSAGE, V_DESCRIPTION, D_EVENT_DATE);
    END;

    /* 종료 LOG */
    V_LOG_TYPE    := 'END';
    V_LOG_MESSAGE := '########## END of procedure ##########';
    V_DESCRIPTION := 'p_division_id :' || P_DIVISION_ID || '/p_version_no :' || P_VERSION_NO || '/p_created_by :' || P_CREATED_BY || '/ 소형 중장기';
    D_EVENT_DATE  := SYSDATE;
    PR_SCM_SYS_LOG_BATCH(V_PROGRAM_NAME, V_LOG_TYPE, N_LOG_COUNT, V_LOG_MESSAGE, V_DESCRIPTION, D_EVENT_DATE);
