PROCEDURE           "PR_DM_PLN_MKT_FCST_QTY_BALANCE_CREATE_BATCH" 

(
    P_DIVISION_ID  IN  VARCHAR2   /* '40'/'81'/'82' 단건 또는 'ALL'(데이터 존재 division 순차) */
)
AS
/*
 * Program ID   : PR_DM_PLN_MKT_FCST_QTY_BALANCE_CREATE_BATCH (DMF SAVE 후 VMI/BALANCE 생성 1시간단위 배치)
 * Program History
 *============================================================================================================
 *   Date       In Charge              Description
 *============================================================================================================
 * 2018.07.30   KHSONG   Initial Release [PJ20170278] 전지본부 자동차 GSCM(DM/SCP) 구축 프로젝트
 * -----------------------------------------------------------------------------------------------------------
 * 20180805  KHSONG 작업대상을 현재시간기준 2시간내 수정된 데이터를 기준으로함
 * 20180806  KHSONG 2018년 10월 scp오픈전까지 vmi값이 존재하지않아 주석처리함 (ui에서 vmi RTF를 수동으로 입력가능하도록함)
 * 20180807  KHSONG item_id 단위로 LOOP수행되도록 로직 수정
 * 20181002  KHSONG PR_DM_PLN_MKT_FCST_QTY_BALANCE_CREATE 프로시져 호출전용으로 대상만 전달하는 방식으로 수정
 * 2020/09/09     P.C.I		[C20200909-000203] LOG 표준화 적용
 * 2022.12.02		hwi1993		[C20221104-000430] UC법인 MKT FCST화면의 'Balance' Measure 로직 변경 요청의 件
 * 2023-01-17   chano0612   [E20230112-000310] GSCM 자동차사업부 시스템 상 MKT FCST 입력을 위한 기능변경 건 - 선박BIZ건
 * 2025-01-21   KANG.H.J    [PJ2024-50611] DM_PLN_RTF_ALLOCATION 동기화 - 선박BIZ건
 * 2025-04-08	KANG.H.J	[PJ2025-50017] 소형 매출계획 동기화 개선 - DM_PLN_RTF_ALLOCATION 삭제처리
 * 2025-05-21   KANG.H.J	[PJ2025-00188] CELL_PROD_SITE_ID 추가 - RTF_BALANCE 계산시 40 사업부와 통일 필요 (40 : CELL_PROD_SITE_ID / 그 외 : '-' )
 * 변환(MSSQL->Oracle) 2026-07-01 SCMADM (held 초대형 → 전용 재구성)
 *   - ★결합쌍(§0.8): #SEND_TARGET_DATA → 공유 GTT SCM_MGR.GT_PRDM_SEND_TARGET_DATA(SYS$SESSION=PRESERVE ROWS, 객체31이 참조).
 *     신규 GTT 아님. division 반복마다 DELETE로 초기화 후 적재 → 객체31 호출(그 GTT 읽음).
 *   - @division 테이블변수 → 커서 인라인(ALL이면 데이터존재 division UNION, 아니면 p_division_id 단건)
 *   - CURSOR1_PLAN DIVISION LOOP → FOR LOOP. WHILE @i(ROW_NUMBER row iterator) → FOR r 행루프(동치)
 *   - EXEC PR_DM_PLN_MKT_FCST_QTY_BALANCE_CREATE @div,@p_plan_id='CALL' → (div,'CALL',v_rc OUT REF CURSOR)
 *   - FN_NEXT_DAY 관용구 객체31과 동일: TO_CHAR(FN_NEXT_DAY(SYSDATE,'MON')-7,'YYYYMMDD'). 52주말=+52*7일
 *   - DATEADD(hour,-2,GETDATE())→SYSDATE-2/24. GETDATE()→SYSDATE. CONVERT(,112)→TO_CHAR YYYYMMDD
 *   - ★H-5: CFM의 END_CUSTOMER/CELL_PROD_SITE_ID NOT NULL인데 MSSQL ''(=NULL) → 객체31 관례대로 ' '(공백)
 *   - BEGIN TRAN/COMMIT/ROLLBACK → SAVEPOINT/COMMIT/ROLLBACK TO. PRINT 제거. return -1/1 → OUT 없음(배치)
 *   - 4.MDF(판매장려금)는 원본에서 전체 주석(NERP 미사용) → 미포함
 *   - 운영테이블 DM_PLN_MKT_FCST/DM_PLN_CFM_MKT_DEMAND_PLAN INSERT(스모크는 CTAS백업 후 26ai)
 * 2026.07.06	ZIONEX		[PJ202650304] NextSCM Migration
 */
    V_PROGRAM_NAME          VARCHAR2(150 CHAR) := 'PR_DM_PLN_MKT_FCST_QTY_BALANCE_CREATE_BATCH';
    V_LOG_TYPE              VARCHAR2(30 CHAR);
    N_LOG_COUNT             INTEGER := 0;
    V_LOG_MESSAGE           VARCHAR2(1000 CHAR);
    V_DESCRIPTION           VARCHAR2(500 CHAR);
    D_EVENT_DATE            DATE;
    V_C_TARGET_DATE         DATE;
    V_PLAN_START_YYYYMMDD   VARCHAR2(8 CHAR);
    V_PLAN_END_YYYYMMDD     VARCHAR2(8 CHAR);
    V_RC                    SYS_REFCURSOR;
    V_ERRMSG                VARCHAR2(1000 CHAR);
    V_MKT_FCST_CNT          NUMBER;
    V_RTF_SCP_CNT           NUMBER;
    V_RTF_SCP               NUMBER;
    V_RTF_SYS_RP            NUMBER;
    V_RTF                   NUMBER;
BEGIN
    V_C_TARGET_DATE       := SYSDATE - 2/24;  /* 현재시간 기준 2시간내 수정데이터 대상 */
    V_PLAN_START_YYYYMMDD := TO_CHAR(FN_NEXT_DAY(SYSDATE, 'MON') - 7, 'YYYYMMDD');  /* 월요일 */
    V_PLAN_END_YYYYMMDD   := TO_CHAR(TO_DATE(V_PLAN_START_YYYYMMDD,'YYYYMMDD') + 52*7, 'YYYYMMDD');  /* SCP PLANNING 52주 */

    /* 시작 LOG */
    V_LOG_TYPE := 'START';
    V_LOG_MESSAGE := '########## Start of procedure ##########';
    V_DESCRIPTION := NULL;
    D_EVENT_DATE := SYSDATE;
    PR_SCM_SYS_LOG_BATCH(V_PROGRAM_NAME, V_LOG_TYPE, N_LOG_COUNT, V_LOG_MESSAGE, V_DESCRIPTION, D_EVENT_DATE);
    V_LOG_MESSAGE := NULL;

    /* 트랜잭션 START */
    SAVEPOINT BALANCE_CREATE_BATCH;

    BEGIN
        /* ============================ CURSOR1_PLAN : 대상 DIVISION 순차 LOOP ============================ */
        FOR DIV IN (
            SELECT DISTINCT DIVISION_ID FROM (
                /* 'ALL' : 데이터가 존재하는 대상 DIVISION_ID */
                SELECT DIVISION_ID
                  FROM DM_PLN_CFM_MKT_DEMAND_PLAN
                 WHERE UPPER(P_DIVISION_ID) = 'ALL'
                   AND YYYYMMDD BETWEEN V_PLAN_START_YYYYMMDD AND V_PLAN_END_YYYYMMDD
                   AND MEASURE IN ('MKT_FCST', 'RTF_SCP')
                   AND LAST_UPDATE_DATE > V_C_TARGET_DATE
                UNION
                SELECT DIVISION_ID
                  FROM DM_PLN_MKT_FCST
                 WHERE UPPER(P_DIVISION_ID) = 'ALL'
                   AND YYYYMMDD BETWEEN V_PLAN_START_YYYYMMDD AND V_PLAN_END_YYYYMMDD
                   AND MEASURE IN ('MKT_FCST', 'RTF_SCP')
                   AND LAST_UPDATE_DATE > V_C_TARGET_DATE
                UNION ALL
                /* 단건 : p_division_id */
                SELECT P_DIVISION_ID AS DIVISION_ID FROM DUAL
                 WHERE UPPER(P_DIVISION_ID) <> 'ALL'
            )
            ORDER BY DIVISION_ID
        ) LOOP

            /* ---- #SEND_TARGET_DATA(공유 GTT) 초기화 : division 반복마다 clear ---- */
            DELETE FROM GT_PRDM_SEND_TARGET_DATA;

            /* ---- 대상추출 ---- */
            IF DIV.DIVISION_ID = '40' THEN
                INSERT INTO GT_PRDM_SEND_TARGET_DATA
                    ( DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, CELL_PROD_SITE_ID, VMI_YN )
                SELECT DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, CELL_PROD_SITE_ID, 'N'
                  FROM DM_PLN_CFM_MKT_DEMAND_PLAN
                 WHERE YYYYMMDD BETWEEN V_PLAN_START_YYYYMMDD AND V_PLAN_END_YYYYMMDD
                   AND MEASURE = 'MKT_FCST'
                   AND DIVISION_ID = DIV.DIVISION_ID
                   AND LAST_UPDATE_DATE > V_C_TARGET_DATE
                 GROUP BY DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, CELL_PROD_SITE_ID;
            ELSE
                INSERT INTO GT_PRDM_SEND_TARGET_DATA
                    ( DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, CELL_PROD_SITE_ID, VMI_YN )
                SELECT DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, '-', 'N'
                  FROM DM_PLN_MKT_FCST
                 WHERE YYYYMMDD BETWEEN V_PLAN_START_YYYYMMDD AND V_PLAN_END_YYYYMMDD
                   AND MEASURE = 'MKT_FCST'
                   AND DIVISION_ID = DIV.DIVISION_ID
                   AND LAST_UPDATE_DATE > V_C_TARGET_DATE
                 GROUP BY DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID;
            END IF;

            /* ---- 선박biz사업부 BALANCE MEASURE 배제 [E20230112-000310] ---- */
            DELETE FROM GT_PRDM_SEND_TARGET_DATA
             WHERE DIVISION_ID IN (SELECT SEGMENT1 FROM SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = 'DM_NET_DEMAND_EXCEPTION' AND VALID_YN = 'Y')
               AND SCM_SITE_ID IN (SELECT SEGMENT2 FROM SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = 'DM_NET_DEMAND_EXCEPTION' AND VALID_YN = 'Y');

            /* ---- PR_DM_PLN_MKT_FCST_QTY_BALANCE_CREATE 호출 (공유 GTT 읽음) ---- */
            PR_DM_PLN_MKT_FCST_QTY_BALANCE_CREATE(DIV.DIVISION_ID, 'CALL', V_RC);

            /* ================================================================================= */
            /* 선박biz사업부 BALANCE 재조정 (A) : DM_PLN_MKT_FCST 기준 RTF_SCP/RTF_SYS_RP/RTF 보정 */
            /* ================================================================================= */
            SELECT COUNT(*) INTO V_MKT_FCST_CNT
              FROM DM_PLN_MKT_FCST
             WHERE YYYYMMDD BETWEEN V_PLAN_START_YYYYMMDD AND V_PLAN_END_YYYYMMDD
               AND MEASURE = 'MKT_FCST'
               AND DIVISION_ID IN (SELECT SEGMENT1 FROM SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = 'DM_NET_DEMAND_EXCEPTION' AND VALID_YN = 'Y')
               AND SCM_SITE_ID IN (SELECT SEGMENT2 FROM SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = 'DM_NET_DEMAND_EXCEPTION' AND VALID_YN = 'Y');

            SELECT COUNT(*) INTO V_RTF_SCP_CNT
              FROM DM_PLN_MKT_FCST
             WHERE YYYYMMDD BETWEEN V_PLAN_START_YYYYMMDD AND V_PLAN_END_YYYYMMDD
               AND MEASURE = 'RTF_SCP'
               AND DIVISION_ID IN (SELECT SEGMENT1 FROM SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = 'DM_NET_DEMAND_EXCEPTION' AND VALID_YN = 'Y')
               AND SCM_SITE_ID IN (SELECT SEGMENT2 FROM SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = 'DM_NET_DEMAND_EXCEPTION' AND VALID_YN = 'Y');

            IF V_MKT_FCST_CNT <> V_RTF_SCP_CNT THEN
                FOR R IN (
                    SELECT PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, YYYYMMDD
                      FROM DM_PLN_MKT_FCST
                     WHERE YYYYMMDD BETWEEN V_PLAN_START_YYYYMMDD AND V_PLAN_END_YYYYMMDD
                       AND MEASURE = 'MKT_FCST'
                       AND DIVISION_ID IN (SELECT SEGMENT1 FROM SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = 'DM_NET_DEMAND_EXCEPTION' AND VALID_YN = 'Y')
                       AND SCM_SITE_ID IN (SELECT SEGMENT2 FROM SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = 'DM_NET_DEMAND_EXCEPTION' AND VALID_YN = 'Y')
                ) LOOP

                    SELECT COUNT(*) INTO V_RTF_SCP FROM DM_PLN_MKT_FCST A
                     WHERE A.PROJECT_CODE = R.PROJECT_CODE AND A.SCM_SITE_ID = R.SCM_SITE_ID AND A.ITEM_ID = R.ITEM_ID
                       AND A.DOM_EXP = R.DOM_EXP AND A.FCST_TYPE = R.FCST_TYPE AND A.INCOTERMS = R.INCOTERMS
                       AND A.MEASURE = 'RTF_SCP' AND A.PLANT_SITE_ID = R.PLANT_SITE_ID AND A.YYYYMMDD = R.YYYYMMDD;
                    IF V_RTF_SCP = 0 THEN
                        INSERT INTO DM_PLN_MKT_FCST
                            ( DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, MEASURE, PLANT_SITE_ID, YYYYMMDD, QTY, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY
                            , LAST_UPDATE_DATE, ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10 )
                        SELECT DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, 'RTF_SCP', PLANT_SITE_ID, YYYYMMDD, QTY, 'SYSTEM', SYSDATE, 'SYSTEM'
                             , SYSDATE, ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10
                          FROM DM_PLN_MKT_FCST
                         WHERE PROJECT_CODE = R.PROJECT_CODE AND SCM_SITE_ID = R.SCM_SITE_ID AND ITEM_ID = R.ITEM_ID
                           AND DOM_EXP = R.DOM_EXP AND FCST_TYPE = R.FCST_TYPE AND INCOTERMS = R.INCOTERMS
                           AND MEASURE = 'MKT_FCST' AND PLANT_SITE_ID = R.PLANT_SITE_ID AND YYYYMMDD = R.YYYYMMDD;
                    END IF;

                    /* RTF_SYS_RP */
                    SELECT COUNT(*) INTO V_RTF_SYS_RP FROM DM_PLN_MKT_FCST A
                     WHERE A.PROJECT_CODE = R.PROJECT_CODE AND A.SCM_SITE_ID = R.SCM_SITE_ID AND A.ITEM_ID = R.ITEM_ID
                       AND A.DOM_EXP = R.DOM_EXP AND A.FCST_TYPE = R.FCST_TYPE AND A.INCOTERMS = R.INCOTERMS
                       AND A.MEASURE = 'RTF_SYS_RP' AND A.PLANT_SITE_ID = R.PLANT_SITE_ID AND A.YYYYMMDD = R.YYYYMMDD;
                    IF V_RTF_SYS_RP = 0 THEN
                        INSERT INTO DM_PLN_MKT_FCST
                            ( DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, MEASURE, PLANT_SITE_ID, YYYYMMDD, QTY, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY
                            , LAST_UPDATE_DATE, ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10 )
                        SELECT DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, 'RTF_SYS_RP', PLANT_SITE_ID, YYYYMMDD, QTY, 'SYSTEM', SYSDATE, 'SYSTEM'
                             , SYSDATE, ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10
                          FROM DM_PLN_MKT_FCST
                         WHERE PROJECT_CODE = R.PROJECT_CODE AND SCM_SITE_ID = R.SCM_SITE_ID AND ITEM_ID = R.ITEM_ID
                           AND DOM_EXP = R.DOM_EXP AND FCST_TYPE = R.FCST_TYPE AND INCOTERMS = R.INCOTERMS
                           AND MEASURE = 'MKT_FCST' AND PLANT_SITE_ID = R.PLANT_SITE_ID AND YYYYMMDD = R.YYYYMMDD;
                    END IF;

                    /* RTF */
                    SELECT COUNT(*) INTO V_RTF FROM DM_PLN_MKT_FCST A
                     WHERE A.PROJECT_CODE = R.PROJECT_CODE AND A.SCM_SITE_ID = R.SCM_SITE_ID AND A.ITEM_ID = R.ITEM_ID
                       AND A.DOM_EXP = R.DOM_EXP AND A.FCST_TYPE = R.FCST_TYPE AND A.INCOTERMS = R.INCOTERMS
                       AND A.MEASURE = 'RTF' AND A.PLANT_SITE_ID = R.PLANT_SITE_ID AND A.YYYYMMDD = R.YYYYMMDD;
                    IF V_RTF = 0 THEN
                        INSERT INTO DM_PLN_MKT_FCST
                            ( DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, MEASURE, PLANT_SITE_ID, YYYYMMDD, QTY, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY
                            , LAST_UPDATE_DATE, ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10 )
                        SELECT DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, 'RTF', PLANT_SITE_ID, YYYYMMDD, QTY, 'SYSTEM', SYSDATE, 'SYSTEM'
                             , SYSDATE, ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10
                          FROM DM_PLN_MKT_FCST
                         WHERE PROJECT_CODE = R.PROJECT_CODE AND SCM_SITE_ID = R.SCM_SITE_ID AND ITEM_ID = R.ITEM_ID
                           AND DOM_EXP = R.DOM_EXP AND FCST_TYPE = R.FCST_TYPE AND INCOTERMS = R.INCOTERMS
                           AND MEASURE = 'MKT_FCST' AND PLANT_SITE_ID = R.PLANT_SITE_ID AND YYYYMMDD = R.YYYYMMDD;
                    END IF;
                END LOOP;
            END IF;

            /* ================================================================================= */
            /* [PJ2025-50017] 소형 매출계획 동기화 (B) : DM_PLN_CFM_MKT_DEMAND_PLAN 기준 보정 */

            /* ================================================================================= */
            SELECT COUNT(*) INTO V_MKT_FCST_CNT
              FROM DM_PLN_MKT_FCST
             WHERE YYYYMMDD BETWEEN V_PLAN_START_YYYYMMDD AND V_PLAN_END_YYYYMMDD
               AND MEASURE = 'MKT_FCST'
               AND DIVISION_ID IN (SELECT SEGMENT1 FROM SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = 'DM_NET_DEMAND_EXCEPTION' AND VALID_YN = 'Y')
               AND SCM_SITE_ID IN (SELECT SEGMENT2 FROM SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = 'DM_NET_DEMAND_EXCEPTION' AND VALID_YN = 'Y');

            SELECT COUNT(*) INTO V_RTF_SCP_CNT
              FROM DM_PLN_CFM_MKT_DEMAND_PLAN
             WHERE YYYYMMDD BETWEEN V_PLAN_START_YYYYMMDD AND V_PLAN_END_YYYYMMDD
               AND MEASURE = 'RTF_SYS_RP'
               AND DIVISION_ID IN (SELECT SEGMENT1 FROM SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = 'DM_NET_DEMAND_EXCEPTION' AND VALID_YN = 'Y')
               AND SCM_SITE_ID IN (SELECT SEGMENT2 FROM SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = 'DM_NET_DEMAND_EXCEPTION' AND VALID_YN = 'Y');

            IF V_MKT_FCST_CNT <> V_RTF_SCP_CNT THEN
                FOR R IN (
                    SELECT PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, YYYYMMDD
                      FROM DM_PLN_MKT_FCST
                     WHERE YYYYMMDD BETWEEN V_PLAN_START_YYYYMMDD AND V_PLAN_END_YYYYMMDD
                       AND MEASURE = 'MKT_FCST'
                       AND DIVISION_ID IN (SELECT SEGMENT1 FROM SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = 'DM_NET_DEMAND_EXCEPTION' AND VALID_YN = 'Y')
                       AND SCM_SITE_ID IN (SELECT SEGMENT2 FROM SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = 'DM_NET_DEMAND_EXCEPTION' AND VALID_YN = 'Y')
                ) LOOP

                    SELECT COUNT(*) INTO V_RTF_SCP FROM DM_PLN_CFM_MKT_DEMAND_PLAN A
                     WHERE A.PROJECT_CODE = R.PROJECT_CODE AND A.SCM_SITE_ID = R.SCM_SITE_ID AND A.ITEM_ID = R.ITEM_ID
                       AND A.DOM_EXP = R.DOM_EXP AND A.FCST_TYPE = R.FCST_TYPE AND A.INCOTERMS = R.INCOTERMS
                       AND A.MEASURE = 'RTF_SCP' AND A.PLANT_SITE_ID = R.PLANT_SITE_ID AND A.YYYYMMDD = R.YYYYMMDD;
                    IF V_RTF_SCP = 0 THEN
                        INSERT INTO DM_PLN_CFM_MKT_DEMAND_PLAN
                            ( DIVISION_ID, PROJECT_CODE, END_CUSTOMER, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, MEASURE, PLANT_SITE_ID, CELL_PROD_SITE_ID, YYYYMMDD, QTY
                            , CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE
                            , ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10 )
                        SELECT DIVISION_ID, PROJECT_CODE
--                             , CASE WHEN DIVISION_ID = '40' THEN PROJECT_CODE ELSE ' ' END    --  2026.10.12 AJS
                             , CASE WHEN DIVISION_ID = '40' THEN PROJECT_CODE ELSE '/' END    --  2026.10.12 AJS
--                             , SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, 'RTF_SCP', PLANT_SITE_ID, ' ', YYYYMMDD, QTY    --  2026.10.12 AJS
                             , SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, 'RTF_SCP', PLANT_SITE_ID, '/', YYYYMMDD, QTY    --  2026.10.12 AJS
                             , 'SYSTEM', SYSDATE, 'SYSTEM', SYSDATE
                             , ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10
                          FROM DM_PLN_MKT_FCST
                         WHERE PROJECT_CODE = R.PROJECT_CODE AND SCM_SITE_ID = R.SCM_SITE_ID AND ITEM_ID = R.ITEM_ID
                           AND DOM_EXP = R.DOM_EXP AND FCST_TYPE = R.FCST_TYPE AND INCOTERMS = R.INCOTERMS
                           AND MEASURE = 'MKT_FCST' AND PLANT_SITE_ID = R.PLANT_SITE_ID AND YYYYMMDD = R.YYYYMMDD;
                    END IF;

                    /* RTF_SYS_RP (CFM) */
                    SELECT COUNT(*) INTO V_RTF_SYS_RP FROM DM_PLN_CFM_MKT_DEMAND_PLAN A
                     WHERE A.PROJECT_CODE = R.PROJECT_CODE AND A.SCM_SITE_ID = R.SCM_SITE_ID AND A.ITEM_ID = R.ITEM_ID
