-- P02_DATA_MIX.sql — DM_PLN_MKT_FCST / DM_PLN_CFM_MKT_DEMAND_PLAN 의 PLANT_SITE_ID 표기 혼재 실측 (READ-ONLY, 전체 F5, 값 입력 없음)
--   계정: SCM_MGR · 클라우드 QA/DEV. 범위 = 당주 월요일 이후.
SET LINESIZE 300 PAGESIZE 500
PROMPT ################ [B1] DM_PLN_MKT_FCST — 사업부 × 메저 × 표기 × 작성자(사용자 저장은 (user) 로 합침) · 최초/최종 수정 ################
SELECT DIVISION_ID DV, MEASURE
     , CASE WHEN PLANT_SITE_ID = ' ' THEN '(space)' WHEN PLANT_SITE_ID IN ('-','/','--') THEN PLANT_SITE_ID ELSE 'real' END P
     , CASE WHEN LAST_UPDATED_BY IN ('SYSTEM','BALANCE_MAKE','CUTOFF') OR LAST_UPDATED_BY LIKE 'BATCH%' OR LAST_UPDATED_BY LIKE 'FILLFIX%' OR LAST_UPDATED_BY LIKE 'DMF%' THEN LAST_UPDATED_BY ELSE '(user)' END WRITER
     , COUNT(*) N, TO_CHAR(MIN(LAST_UPDATE_DATE),'MM-DD HH24:MI') FIRST_UPD, TO_CHAR(MAX(LAST_UPDATE_DATE),'MM-DD HH24:MI') LAST_UPD
  FROM DM_PLN_MKT_FCST
 WHERE DIVISION_ID IN ('40','82') AND YYYYMMDD >= TO_CHAR(TRUNC(SYSDATE,'IW'),'YYYYMMDD')
 GROUP BY DIVISION_ID, MEASURE
     , CASE WHEN PLANT_SITE_ID = ' ' THEN '(space)' WHEN PLANT_SITE_ID IN ('-','/','--') THEN PLANT_SITE_ID ELSE 'real' END
     , CASE WHEN LAST_UPDATED_BY IN ('SYSTEM','BALANCE_MAKE','CUTOFF') OR LAST_UPDATED_BY LIKE 'BATCH%' OR LAST_UPDATED_BY LIKE 'FILLFIX%' OR LAST_UPDATED_BY LIKE 'DMF%' THEN LAST_UPDATED_BY ELSE '(user)' END
 ORDER BY 1, 2, 3, 4;

