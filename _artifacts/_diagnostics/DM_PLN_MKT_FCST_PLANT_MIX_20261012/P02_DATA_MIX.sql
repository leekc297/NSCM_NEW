PROMPT ################ [B3] 같은 키가 표기로 갈라진 규모 — DM_PLN_MKT_FCST ################
SELECT DIVISION_ID DV, COUNT(*) SPLIT_KEYS
     , SUM(CASE WHEN BAL_ROWS >= 2 AND BAL_SUM = 0 AND BAL_ABS <> 0 THEN 1 ELSE 0 END) BALANCE_CANCEL_PAIRS
  FROM (
    SELECT DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, YYYYMMDD
         , COUNT(DISTINCT PLANT_SITE_ID) NOTATIONS
         , SUM(CASE WHEN MEASURE = 'BALANCE' THEN 1 ELSE 0 END) BAL_ROWS
         , SUM(CASE WHEN MEASURE = 'BALANCE' THEN QTY ELSE 0 END) BAL_SUM
         , SUM(CASE WHEN MEASURE = 'BALANCE' THEN ABS(QTY) ELSE 0 END) BAL_ABS
      FROM DM_PLN_MKT_FCST
     WHERE DIVISION_ID IN ('40','82') AND YYYYMMDD >= TO_CHAR(TRUNC(SYSDATE,'IW'),'YYYYMMDD')
       AND PLANT_SITE_ID IN (' ','/','-','--')
     GROUP BY DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, YYYYMMDD
    HAVING COUNT(DISTINCT PLANT_SITE_ID) >= 2 )
 GROUP BY DIVISION_ID ORDER BY 1;
PROMPT --  판정: SPLIT_KEYS = 표기가 2종 이상인 (키,일자) 수 · BALANCE_CANCEL_PAIRS = +/- 로 상쇄되는 BALANCE 쌍 수

