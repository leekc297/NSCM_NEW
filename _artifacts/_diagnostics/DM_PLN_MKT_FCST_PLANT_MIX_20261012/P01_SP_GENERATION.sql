-- P01_SP_GENERATION.sql — PLANT_SITE_ID ' '(공백) 을 만드는 SP 문장이 이 DB 에 남아 있는지 (READ-ONLY, 전체 F5, 값 입력 없음)
--   계정: SCM_MGR · 클라우드 QA/DEV.
--   사내 ZIOUI1 2026-10-12 기준: PR_DM_PLN_MKT_FCST_QTY_BALANCE_CREATE 의 6곳이 10-11 에 ' ' → '/' 로 바뀌어 [A2] 0행.
SET LINESIZE 300 PAGESIZE 300
PROMPT ################ [A1] 관련 SP 세대 — 최종 컴파일 시각 · 상태 · 줄 수 ################
SELECT O.OBJECT_NAME, O.OBJECT_TYPE, TO_CHAR(O.LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL, O.STATUS
     , (SELECT COUNT(*) FROM USER_SOURCE S WHERE S.NAME = O.OBJECT_NAME AND S.TYPE = O.OBJECT_TYPE) LINES
     , (SELECT COUNT(*) FROM USER_SOURCE S WHERE S.NAME = O.OBJECT_NAME AND S.TYPE = O.OBJECT_TYPE AND S.TEXT LIKE '%2026.10.11 POJ%') POJ_1011
     , (SELECT COUNT(*) FROM USER_SOURCE S WHERE S.NAME = O.OBJECT_NAME AND S.TYPE = O.OBJECT_TYPE AND S.TEXT LIKE '%2026.10.12 AJS%') AJS_1012
  FROM USER_OBJECTS O
 WHERE O.OBJECT_NAME IN ('PR_DM_PLN_MKT_FCST_QTY_BALANCE_CREATE','PR_DM_PLN_MKT_FCST_C_QTY_BALANCE_CREATE','PR_DM_PLN_MKT_FCST_QTY_BALANCE_CREATE_BATCH'
                        ,'PR_DM_PLN_CFM_TO_MKT_FCST_ALL','PR_DM_PLN_MKT_FCST_TO_NET_DEMAND','PR_DM_SSP_CONFIRM_SYNC','PR_DM_LONGPLAN_40_DELETE_IMPORT')
   AND O.OBJECT_TYPE = 'PROCEDURE'
 ORDER BY 1;
PROMPT --  판정: PR_DM_PLN_MKT_FCST_QTY_BALANCE_CREATE 의 POJ_1011 = 0 이면 ' ' 를 쓰는 구판

PROMPT ################ [A2] 40/82 생산지를 ' '(공백) 상수로 넣는 문장 — 전 객체 ################
SELECT S.NAME, S.TYPE, S.LINE, SUBSTR(TRIM(RTRIM(S.TEXT, CHR(10))), 1, 170) TEXT
  FROM USER_SOURCE S
 WHERE S.TYPE IN ('PROCEDURE','PACKAGE BODY','FUNCTION','TRIGGER')
   AND REGEXP_LIKE(S.TEXT, 'THEN\s+'' ''\s+ELSE\s+([A-Z_0-9]+\.)?PLANT_SITE_ID', 'i')
   AND LTRIM(S.TEXT) NOT LIKE '--%' AND LTRIM(S.TEXT) NOT LIKE '/*%'
 ORDER BY S.NAME, S.LINE
;
PROMPT --  판정: 행이 나오면 그 문장이 RTF 계열을 ' ' 로 적재한다 (사내는 0행)

PROMPT ################ [A3] 생산지에 ' ' 또는 '' 를 직접 쓰는 그 밖의 문장 — 전 객체 ################
SELECT S.NAME, S.TYPE, S.LINE, SUBSTR(TRIM(RTRIM(S.TEXT, CHR(10))), 1, 170) TEXT
  FROM USER_SOURCE S
 WHERE S.TYPE IN ('PROCEDURE','PACKAGE BODY','FUNCTION','TRIGGER')
   AND REGEXP_LIKE(S.TEXT, '('' ''|'''')\s+(AS\s+)?PLANT_SITE_ID', 'i')
   AND LTRIM(S.TEXT) NOT LIKE '--%' AND LTRIM(S.TEXT) NOT LIKE '/*%'
 ORDER BY S.NAME, S.LINE
;

PROMPT ################ [A4] 테이블 기본값 — PLANT_SITE_ID ################
SELECT X.T, X.C, X.D
  FROM XMLTABLE('/ROWSET/ROW' PASSING DBMS_XMLGEN.GETXMLTYPE(
        'SELECT TABLE_NAME T, COLUMN_NAME C, DATA_DEFAULT D FROM USER_TAB_COLUMNS WHERE COLUMN_NAME = ''PLANT_SITE_ID'' AND TABLE_NAME IN (''DM_PLN_MKT_FCST'',''DM_PLN_CFM_MKT_DEMAND_PLAN'',''GT_PRDM2_MKT_FCST_INSERT'',''GT_PRDM2_CFM_DEMAND_INSERT'',''GT_PRDM2_RESULTS'',''GT_PRDM2_MF_RTF_ALLOCATION'',''GT_PRDM2_MF_BALANCE_MKT_FCST'',''GT_PRDM2_MST'',''GT_PRDM2_TEMPX'')')
        COLUMNS T VARCHAR2(40) PATH 'T', C VARCHAR2(40) PATH 'C', D VARCHAR2(40) PATH 'D') X
 ORDER BY 1;
