PROMPT === [1] SCM_MST_SITE / SCM_MST_SSO_DEPT_INFO 존재 + 컬럼 ===
SELECT OWNER||'.'||TABLE_NAME AS T, COUNT(*) AS COL_CNT
  FROM ALL_TAB_COLUMNS
 WHERE OWNER='SCM_MGR' AND TABLE_NAME IN ('SCM_MST_SITE','SCM_MST_SSO_DEPT_INFO')
 GROUP BY OWNER, TABLE_NAME;

PROMPT === [2] SCM_MST_SITE 의 SITE_TYPE/DEPT_ID/DIVISION_ID 컬럼 검증 ===
SELECT COLUMN_NAME||'|'||DATA_TYPE||'|'||NULLABLE AS COL
  FROM ALL_TAB_COLUMNS
 WHERE OWNER='SCM_MGR' AND TABLE_NAME='SCM_MST_SITE'
   AND COLUMN_NAME IN ('SITE_TYPE','DEPT_ID','DIVISION_ID','SCM_SITE_ID','VALID_YN','END_CUSTOMER','SITE_DESCRIPTION')
 ORDER BY COLUMN_ID;

PROMPT === [3] SCM_MST_SSO_DEPT_INFO 의 DEPT_ID/DEPT_NAME_KO 컬럼 검증 ===
SELECT COLUMN_NAME||'|'||DATA_TYPE||'|'||NULLABLE AS COL
  FROM ALL_TAB_COLUMNS
 WHERE OWNER='SCM_MGR' AND TABLE_NAME='SCM_MST_SSO_DEPT_INFO'
   AND COLUMN_NAME IN ('DEPT_ID','DEPT_NAME_KO','DEPT_NAME_EN','UPPER_DEPT_ID')
 ORDER BY COLUMN_ID;

PROMPT === [4] SCM_MST_SITE 데이터 카운트 by SITE_TYPE / DIVISION_ID ===
SELECT 'SITE total' AS K, COUNT(*) AS CNT FROM SCM_MGR.SCM_MST_SITE
UNION ALL SELECT 'SITE SALES', COUNT(*) FROM SCM_MGR.SCM_MST_SITE WHERE SITE_TYPE='SALES'
UNION ALL SELECT 'SITE SALES + DEPT_ID NOT NULL', COUNT(*) FROM SCM_MGR.SCM_MST_SITE WHERE SITE_TYPE='SALES' AND DEPT_ID IS NOT NULL
UNION ALL SELECT 'SITE SALES + div=40', COUNT(*) FROM SCM_MGR.SCM_MST_SITE WHERE SITE_TYPE='SALES' AND DIVISION_ID='40';

PROMPT === [5] SCM_MST_SSO_DEPT_INFO 데이터 카운트 ===
SELECT 'DEPT total' AS K, COUNT(*) AS CNT FROM SCM_MGR.SCM_MST_SSO_DEPT_INFO;

PROMPT === [6] As-Is SP body 실행 시뮬레이션 (Division=40) — 결과 row 수 미리 확인 ===
SELECT 'TEAM by DIV=40 expected' AS K, COUNT(*) AS CNT
  FROM (SELECT DISTINCT B.DEPT_ID, B.DEPT_NAME_KO
          FROM SCM_MGR.SCM_MST_SITE A, SCM_MGR.SCM_MST_SSO_DEPT_INFO B
         WHERE A.SITE_TYPE='SALES' AND A.DEPT_ID=B.DEPT_ID AND A.DIVISION_ID='40');

