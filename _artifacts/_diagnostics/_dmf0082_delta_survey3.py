#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""DMF0082 클라우드 이관 — 기준선(DMF0082_CLOUD_20260818) 이후 변경분 전수 서베이 (v3).
축 = survey v2 + EXCEL_COLUMNS + BTN 배선/권한 + GTT 참조 인벤토리 + DDL(DEFAULT_ON_NULL) 상태."""
import sys, io, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")
from ora import conn_info
import oracledb

CUT = "2026-08-18"

u, p, d = conn_info()
con = oracledb.connect(user=u, password=p, dsn=d)
cur = con.cursor()


def q(title, sql, binds=None):
    print("\n" + "=" * 100)
    print(f"## {title}")
    cur.execute(sql, binds or {})
    cols = [c[0] for c in cur.description]
    rows = cur.fetchall()
    if not rows:
        print("   (변경 없음)")
    else:
        print("   " + " | ".join(cols))
        for r in rows:
            print("   " + " | ".join("" if v is None else str(v) for v in r))
    print(f"   ({len(rows)} rows)")
    return rows


q("PKG 객체 DDL 시각", """
  SELECT OBJECT_NAME, OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI') LAST_DDL
  FROM ALL_OBJECTS WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_DMF0082' ORDER BY 2""")

q(f"BODY 내 신규 마커 (E20260819~20)", """
  SELECT REGEXP_SUBSTR(TEXT,'E202608(19|20)-[A-Z0-9]+') MARKER, COUNT(*) CNT FROM ALL_SOURCE
  WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY'
  AND REGEXP_LIKE(TEXT,'E202608(19|20)-')
  GROUP BY REGEXP_SUBSTR(TEXT,'E202608(19|20)-[A-Z0-9]+') ORDER BY 1""")

q(f"LOOKUP 변경 ({CUT}~)", """
  SELECT LOOKUP_TYPE, COUNT(*) CNT, TO_CHAR(MAX(LAST_UPDATE_DATE),'YYYY-MM-DD HH24:MI') LAST_UPD
  FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
  WHERE LAST_UPDATE_DATE >= TO_DATE(:c,'YYYY-MM-DD')
  GROUP BY LOOKUP_TYPE ORDER BY 1""", {"c": CUT})

q(f"CMBO 변경 ({CUT}~)", """
  SELECT SQL_ID, USE_YN, LAST_UPDATED_BY, TO_CHAR(LAST_UPDATE_DATE,'YYYY-MM-DD HH24:MI') UPD
  FROM SCM_MGR.SCM_ADM_CMBO_SQL_M WHERE LAST_UPDATE_DATE >= TO_DATE(:c,'YYYY-MM-DD') ORDER BY 4""", {"c": CUT})

q(f"SHEET_COLUMNS 변경 ({CUT}~, DMF0082)", """
  SELECT SHEET_NAME, COLUMN_NAME, LAST_UPDATED_BY, TO_CHAR(LAST_UPDATE_DATE,'YYYY-MM-DD HH24:MI') UPD
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
  WHERE PROGRAM_ID='DMF0082' AND LAST_UPDATE_DATE >= TO_DATE(:c,'YYYY-MM-DD') ORDER BY 1,2""", {"c": CUT})

q(f"SHEET_MEASURE 변경 ({CUT}~, DMF0082)", """
  SELECT SHEET_NAME, COLUMN_NAME, DIVISION_ID, TO_CHAR(LAST_UPDATE_DATE,'YYYY-MM-DD HH24:MI') UPD
  FROM SCM_MGR.SCM_MST_SHEET_MEASURE
  WHERE PROGRAM_ID='DMF0082' AND LAST_UPDATE_DATE >= TO_DATE(:c,'YYYY-MM-DD') ORDER BY 1,2""", {"c": CUT})

q(f"EXCEL_COLUMNS 변경 ({CUT}~)", """
  SELECT PROGRAM_ID, SHEET_NAME, TO_CHAR(LAST_UPDATE_DATE,'YYYY-MM-DD HH24:MI') UPD
  FROM SCM_MGR.SCM_ADM_EXCEL_COLUMNS WHERE LAST_UPDATE_DATE >= TO_DATE(:c,'YYYY-MM-DD')""", {"c": CUT})

q(f"PROC_M / API_M 변경 ({CUT}~, DMF0082)", """
  SELECT 'PROC_M' SRC, PROC_ID ID, TO_CHAR(LAST_UPDATE_DATE,'YYYY-MM-DD HH24:MI') UPD
  FROM SCM_MGR.SCM_ADM_PROC_M WHERE PROC_ID LIKE '%DMF0082%' AND LAST_UPDATE_DATE >= TO_DATE(:c,'YYYY-MM-DD')
  UNION ALL
  SELECT 'API_M', API_ID, TO_CHAR(LAST_UPDATE_DATE,'YYYY-MM-DD HH24:MI')
  FROM SCM_MGR.SCM_ADM_API_M WHERE API_ID LIKE '%DMF0082%' AND LAST_UPDATE_DATE >= TO_DATE(:c,'YYYY-MM-DD')
  ORDER BY 1,2""", {"c": CUT})

q(f"BTN 배선/권한 변경 ({CUT}~, DMF0082)", """
  SELECT 'BTN_MPG' SRC, MNU_ID||'/'||SHT_NM||'/'||MNU_BTN_CD ID, TO_CHAR(LAST_UPDATE_DATE,'YYYY-MM-DD HH24:MI') UPD
  FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID='DMF0082' AND LAST_UPDATE_DATE >= TO_DATE(:c,'YYYY-MM-DD')
  UNION ALL
  SELECT 'GR_BTN', USER_GR_ID||'/'||MNU_BTN_CD, TO_CHAR(LAST_UPDATE_DATE,'YYYY-MM-DD HH24:MI')
  FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE MNU_ID='DMF0082' AND LAST_UPDATE_DATE >= TO_DATE(:c,'YYYY-MM-DD')
  ORDER BY 1,2""", {"c": CUT})

q(f"MSG 변경 ({CUT}~)", """
  SELECT MSG_ID, LANG_CD, SUBSTR(MSG_NM,1,40) NM, TO_CHAR(LAST_UPDATE_DATE,'YYYY-MM-DD HH24:MI') UPD
  FROM SCM_MGR.SCM_ADM_MSG_M WHERE LAST_UPDATE_DATE >= TO_DATE(:c,'YYYY-MM-DD') ORDER BY MSG_ID, LANG_CD""", {"c": CUT})

q("BODY 참조 GT_/GTT_ 전수 + 존재 여부", """
  WITH REF AS (
    SELECT DISTINCT UPPER(REGEXP_SUBSTR(TEXT, '(GTT?_[A-Z0-9_]+)', 1, 1, 'i', 1)) GNAME
    FROM ALL_SOURCE
    WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY'
      AND REGEXP_LIKE(TEXT, 'GTT?_[A-Z0-9_]+', 'i'))
  SELECT R.GNAME, CASE WHEN T.TABLE_NAME IS NULL THEN 'MISSING' ELSE 'EXISTS/'||T.TEMPORARY END STATUS
  FROM REF R LEFT JOIN ALL_TABLES T ON T.OWNER='SCM_MGR' AND T.TABLE_NAME=R.GNAME
  WHERE R.GNAME IS NOT NULL ORDER BY 2, 1""")

q("DEFAULT_ON_NULL 적용 현황 (이관 DDL 대상)", """
  SELECT TABLE_NAME, COUNT(*) CNT FROM ALL_TAB_COLUMNS
  WHERE OWNER='SCM_MGR' AND DEFAULT_ON_NULL='YES'
  AND TABLE_NAME IN ('DM_PLN_CFM_MKT_DEMAND_PLAN','DM_PLN_CFM_MKT_DEMAND_PLAN_H',
                     'DM_PLN_CFM_SELLING_PRICE','SCM_MST_FUTURE_PRICE','GT_PRDM1_T_MAIN')
  GROUP BY TABLE_NAME ORDER BY 1""")

con.close()
