--   계정: SCM_MGR · BE 가 붙는 DB (D01 [E0])
--   목적: "81 만 느리다" 가 데이터량 때문인지(사내 81 ≈ 40 의 0.5~2배) 판단. 기간 = FE 기본값(당월 1일 ~ +6개월 -1일)
--   사내 기준 = ZIOUI1 2026-10-09 15:00 채취 (인라인). 변경 없음: SELECT 만 수행.
