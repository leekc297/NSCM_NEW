PROMPT ################ [V1] ⭐ 조회 기간 안 원천 행수 — division 별 · 사내 대조 (CNT_X = 클라우드÷사내) ################
PROMPT --  81 분기가 읽는 표: DM_PLN_MKT_FCST(수요) · DM_PLN_SALES_PLAN(10-02 금액 arm, MKT_AMT 2메저만) · SCM_MST_FUTURE_PRICE(판가, 계획구간)
PROMPT --  40 분기가 읽는 표: DM_PLN_CFM_MKT_DEMAND_PLAN(수요) · DM_PLN_CFM_SELLING_PRICE(판가)
WITH W AS (SELECT TO_CHAR(TRUNC(SYSDATE,'MM'),'YYYYMMDD') F, TO_CHAR(ADD_MONTHS(TRUNC(SYSDATE,'MM'),6)-1,'YYYYMMDD') T FROM DUAL),
CORP AS (
  SELECT 'DM_PLN_CFM_MKT_DEMAND_PLAN' T, '40' D, 105330 R FROM DUAL UNION ALL SELECT 'DM_PLN_CFM_MKT_DEMAND_PLAN','81',10497 FROM DUAL UNION ALL SELECT 'DM_PLN_CFM_MKT_DEMAND_PLAN','82',10116 FROM DUAL
  UNION ALL SELECT 'DM_PLN_MKT_FCST','40',101454 FROM DUAL UNION ALL SELECT 'DM_PLN_MKT_FCST','81',46878 FROM DUAL UNION ALL SELECT 'DM_PLN_MKT_FCST','82',33272 FROM DUAL
  UNION ALL SELECT 'DM_PLN_SALES_PLAN','40',22076 FROM DUAL UNION ALL SELECT 'DM_PLN_SALES_PLAN','81',34735 FROM DUAL UNION ALL SELECT 'DM_PLN_SALES_PLAN','82',3123 FROM DUAL
  UNION ALL SELECT 'DM_PLN_SALES_PLAN MKT_AMT','40',6194 FROM DUAL UNION ALL SELECT 'DM_PLN_SALES_PLAN MKT_AMT','81',9488 FROM DUAL UNION ALL SELECT 'DM_PLN_SALES_PLAN MKT_AMT','82',1446 FROM DUAL
  UNION ALL SELECT 'SCM_MST_FUTURE_PRICE','40',155631 FROM DUAL UNION ALL SELECT 'SCM_MST_FUTURE_PRICE','81',190287 FROM DUAL UNION ALL SELECT 'SCM_MST_FUTURE_PRICE','82',224965 FROM DUAL
  UNION ALL SELECT 'SCM_MST_SITE_ITEM VALID','40',22651 FROM DUAL UNION ALL SELECT 'SCM_MST_SITE_ITEM VALID','81',51692 FROM DUAL UNION ALL SELECT 'SCM_MST_SITE_ITEM VALID','82',38341 FROM DUAL
),
CL AS (
  SELECT 'DM_PLN_CFM_MKT_DEMAND_PLAN' T, DIVISION_ID D, COUNT(*) CNT, COUNT(DISTINCT MEASURE) MEAS FROM DM_PLN_CFM_MKT_DEMAND_PLAN, W WHERE DIVISION_ID IN ('40','81','82') AND YYYYMMDD BETWEEN W.F AND W.T GROUP BY DIVISION_ID
  UNION ALL SELECT 'DM_PLN_MKT_FCST', DIVISION_ID, COUNT(*), COUNT(DISTINCT MEASURE) FROM DM_PLN_MKT_FCST, W WHERE DIVISION_ID IN ('40','81','82') AND YYYYMMDD BETWEEN W.F AND W.T GROUP BY DIVISION_ID
  UNION ALL SELECT 'DM_PLN_SALES_PLAN', DIVISION_ID, COUNT(*), COUNT(DISTINCT MEASURE) FROM DM_PLN_SALES_PLAN, W WHERE DIVISION_ID IN ('40','81','82') AND YYYYMMDD BETWEEN W.F AND W.T GROUP BY DIVISION_ID
  UNION ALL SELECT 'DM_PLN_SALES_PLAN MKT_AMT', DIVISION_ID, COUNT(*), COUNT(DISTINCT MEASURE) FROM DM_PLN_SALES_PLAN, W WHERE DIVISION_ID IN ('40','81','82') AND MEASURE IN ('MKT_AMT_KRW','MKT_AMT_LOC') AND YYYYMMDD BETWEEN W.F AND W.T GROUP BY DIVISION_ID
  UNION ALL SELECT 'SCM_MST_FUTURE_PRICE', DIVISION_ID, COUNT(*), COUNT(DISTINCT MEASURE) FROM SCM_MST_FUTURE_PRICE, W WHERE DIVISION_ID IN ('40','81','82') AND YYYYMMDD BETWEEN W.F AND W.T GROUP BY DIVISION_ID
  UNION ALL SELECT 'SCM_MST_SITE_ITEM VALID', DIVISION_ID, COUNT(*), 0 FROM SCM_MST_SITE_ITEM WHERE DIVISION_ID IN ('40','81','82') AND VALID_YN='Y' GROUP BY DIVISION_ID
)
SELECT CORP.T, CORP.D DIV, CL.CNT CLOUD_CNT, CORP.R CORP_CNT, ROUND(CL.CNT / NULLIF(CORP.R,0), 1) CNT_X, CL.MEAS CLOUD_MEASURES,
       CASE WHEN CL.CNT IS NULL THEN '0건 (해당 division 데이터 없음)'
            WHEN CL.CNT / NULLIF(CORP.R,0) >= 5 THEN '⚠ 사내 5배↑ — 데이터량이 시간 차이의 일부'
            WHEN CL.CNT / NULLIF(CORP.R,0) >= 2 THEN 'ℹ 사내 2배↑' ELSE 'ok' END JUDGE
  FROM CORP LEFT JOIN CL ON CL.T = CORP.T AND CL.D = CORP.D
 ORDER BY CORP.T, CORP.D;
PROMPT --  판정: 81 의 CNT_X 가 40 의 CNT_X 와 비슷하면 데이터량 아님(계획 문제) · 81 만 수십 배면 데이터량 (그래도 타임아웃 = 계획 동반)

PROMPT ################ [V2] 81 판가 원장 전체 폭 — ONEREAD 통합 문장(L1771)이 읽는 범위: LEAST(실적끝, from) ~ GREATEST(계획끝, to) ################
PROMPT --  사내 81 190,287행(계획구간 6개월). 통합 문장은 윈도 MAX 를 위해 이 범위를 1회 읽고 PK/IDX02 로 접근 — 클라우드 행수가 수백만이면 이 문장이 1순위
SELECT A.DIVISION_ID DIV, COUNT(*) CNT, COUNT(DISTINCT A.YYYYMMDD) DAYS, MIN(A.YYYYMMDD) MIN_YMD, MAX(A.YYYYMMDD) MAX_YMD,
       SUM(CASE WHEN A.YYYYMMDD >= TO_CHAR(TRUNC(SYSDATE,'IW'),'YYYYMMDD') THEN 1 ELSE 0 END) FROM_THIS_WEEK
  FROM SCM_MST_FUTURE_PRICE A
 WHERE A.DIVISION_ID IN ('40','81','82')
   AND A.YYYYMMDD BETWEEN TO_CHAR(ADD_MONTHS(TRUNC(SYSDATE,'MM'),-1),'YYYYMMDD') AND TO_CHAR(ADD_MONTHS(TRUNC(SYSDATE,'MM'),6)-1,'YYYYMMDD')
 GROUP BY A.DIVISION_ID ORDER BY 1;

PROMPT ################ [V3] ⭐ 사용자별 선택 메저 수 (SCM_MST_TITLESET_USER) — 메저가 많을수록 arm 이 늘어난다 (09-30 k0101 사례) ################
PROMPT --  사내 상위: k0101 9메저(CUST 1) · 7메저 9명 · AMT(MKT_AMT) 선택 = eunah.koo 1명. 타임아웃을 본 사용자 ID 의 행을 찾아라
SELECT USER_ID, COUNT(*) MEASURES,
       SUM(CASE WHEN COLUMN_NAME IN ('MKT_AMT_KRW','MKT_AMT_LOC') THEN 1 ELSE 0 END) AMT_SEL,
       SUM(CASE WHEN UPPER(COLUMN_NAME) LIKE 'CUST%' THEN 1 ELSE 0 END) CUST_SEL,
       LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY SORT_ORDER_NO) MEASURE_LIST
  FROM SCM_MST_TITLESET_USER
 WHERE PROGRAM_ID='DMF0082' AND SHEET_NAME='FcstNPrice' AND USER_INQUIRY_COLUMN_TYPE_CODE='M'
 GROUP BY USER_ID ORDER BY 2 DESC, 1 FETCH FIRST 30 ROWS ONLY;

PROMPT ################ [V4] 메저 메타 — DMF0082 FcstNPrice 메저의 DIVISION 적용 범위 (81 에서 쓰이는 메저 집합) ################
SELECT COLUMN_NAME, DIVISION_ID, VALID_YN, USER_SELECTABLE_FLAG, DEFAULT_FLAG, LARGE_CLASS_LABEL_NAME, SMALL_CLASS_LABEL_NAME
  FROM SCM_MST_SHEET_MEASURE
 WHERE PROGRAM_ID='DMF0082' AND SHEET_NAME='FcstNPrice' AND VALID_YN='Y'
 ORDER BY DIVISION_ID, COLUMN_NAME;

PROMPT ################ [V5] 81 수요 원장 메저 분포 (계획구간) — 어느 메저가 몫을 차지하나 ################
SELECT A.MEASURE, COUNT(*) CNT, COUNT(DISTINCT A.PROJECT_CODE||A.SCM_SITE_ID||A.ITEM_ID) KEYS
  FROM DM_PLN_MKT_FCST A
 WHERE A.DIVISION_ID = '81'
   AND A.YYYYMMDD BETWEEN TO_CHAR(TRUNC(SYSDATE,'MM'),'YYYYMMDD') AND TO_CHAR(ADD_MONTHS(TRUNC(SYSDATE,'MM'),6)-1,'YYYYMMDD')
 GROUP BY A.MEASURE ORDER BY 2 DESC;

PROMPT ################ [V6] 81 실적 원장 (DM_PLN_MKT_FCST_RESULT · DM_PLN_SALES_PLAN_RESULT) 최근 13주 행수 — CUST 종속 실적 arm(L2089) 원천 ################
SELECT 'DM_PLN_MKT_FCST_RESULT' T, DIVISION_ID DIV, COUNT(*) CNT, COUNT(DISTINCT MEASURE) MEAS
  FROM DM_PLN_MKT_FCST_RESULT
 WHERE DIVISION_ID IN ('40','81','82') AND YYYYMMDD >= TO_CHAR(TRUNC(SYSDATE,'IW') - 7*13,'YYYYMMDD')
 GROUP BY DIVISION_ID
UNION ALL
SELECT 'DM_PLN_SALES_PLAN_RESULT', DIVISION_ID, COUNT(*), COUNT(DISTINCT MEASURE)
  FROM DM_PLN_SALES_PLAN_RESULT
 WHERE DIVISION_ID IN ('40','81','82') AND YYYYMMDD >= TO_CHAR(TRUNC(SYSDATE,'IW') - 7*13,'YYYYMMDD')
 GROUP BY DIVISION_ID
 ORDER BY 1, 2;

