PROMPT --  631pzfvq8r0ut(40 판가 INSERT L1850) · 20xrvz802rfsy(DELETE dedup L3643) · 19mfxqb34sbky(SITE_ITEM_ALL L855) · 56fkh52zfndm7(결과 L4705) · 3d2xnx839ksnt(09-30 구 판가, ONEREAD 뒤 사라져야 정상)
SELECT TO_CHAR(N.BEGIN_INTERVAL_TIME,'MM-DD HH24') SNAP, S.SQL_ID, S.PLAN_HASH_VALUE PHV, SUM(S.EXECUTIONS_DELTA) EX,
       ROUND(SUM(S.ELAPSED_TIME_DELTA)/1e6/GREATEST(SUM(S.EXECUTIONS_DELTA),1),1) SEC_PER_EX,
       ROUND(SUM(S.CPU_TIME_DELTA)/1e6/GREATEST(SUM(S.EXECUTIONS_DELTA),1),1) CPU_PER_EX,
       ROUND(SUM(S.DISK_READS_DELTA)/GREATEST(SUM(S.EXECUTIONS_DELTA),1)) DR_PER_EX, ROUND(SUM(S.BUFFER_GETS_DELTA)/GREATEST(SUM(S.EXECUTIONS_DELTA),1)) BG_PER_EX,
       ROUND(SUM(S.ROWS_PROCESSED_DELTA)/GREATEST(SUM(S.EXECUTIONS_DELTA),1)) ROWS_PER_EX
  FROM DBA_HIST_SQLSTAT S JOIN DBA_HIST_SNAPSHOT N ON N.SNAP_ID=S.SNAP_ID AND N.INSTANCE_NUMBER=S.INSTANCE_NUMBER AND N.DBID=S.DBID
 WHERE N.BEGIN_INTERVAL_TIME >= DATE '2026-10-01'
   AND S.SQL_ID IN ('d019r0hbb0muh','c3bg6q8n39195','6bucw2kzuc0nt','18xg1y5298qgq','4svg4dhnqxh8f','631pzfvq8r0ut','20xrvz802rfsy','19mfxqb34sbky','fk3tvpkzsq2vx','56fkh52zfndm7','3d2xnx839ksnt','12v19yag54ut1')
 GROUP BY TO_CHAR(N.BEGIN_INTERVAL_TIME,'MM-DD HH24'), S.SQL_ID, S.PLAN_HASH_VALUE
HAVING SUM(S.EXECUTIONS_DELTA) > 0 ORDER BY 1, 5 DESC;
PROMPT --  판정: 같은 SQL_ID 의 SEC_PER_EX 가 뛰는 시각 / PHV 가 바뀌는 시각이 [X1] 이벤트 전인가 후인가. SQL_ID 가 같다 = 문장 텍스트가 '/' 변경과 무관

PROMPT ################ [X4] AWR — PKG_DMF0082 전체 문장(GT_DMF0082 포함) 일자별 총 경과·실행·DR·CPU ################
SELECT TO_CHAR(N.BEGIN_INTERVAL_TIME,'MM-DD') D, COUNT(DISTINCT S.SQL_ID) SQLS, SUM(S.EXECUTIONS_DELTA) EX, ROUND(SUM(S.ELAPSED_TIME_DELTA)/1e6) ELAP_S,
       ROUND(SUM(S.DISK_READS_DELTA)) DR, ROUND(SUM(S.CPU_TIME_DELTA)/1e6) CPU_S
  FROM DBA_HIST_SQLSTAT S JOIN DBA_HIST_SNAPSHOT N ON N.SNAP_ID=S.SNAP_ID AND N.INSTANCE_NUMBER=S.INSTANCE_NUMBER AND N.DBID=S.DBID
 WHERE N.BEGIN_INTERVAL_TIME >= DATE '2026-09-29'
   AND S.SQL_ID IN (SELECT SQL_ID FROM DBA_HIST_SQLTEXT WHERE DBMS_LOB.INSTR(UPPER(SQL_TEXT),'GT_DMF0082')>0)
 GROUP BY TO_CHAR(N.BEGIN_INTERVAL_TIME,'MM-DD') ORDER BY 1;

PROMPT ################ [X5] AWR ASH — 일자 × SQL_ID: PKG_DMF0082 진입 샘플(≈10초 단위) 상위 — 어느 날부터 어느 문장이 시간을 먹었나 ################
WITH P AS (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0082' AND OBJECT_TYPE='PACKAGE'),
A AS (SELECT TO_CHAR(H.SAMPLE_TIME,'MM-DD') D, NVL(H.SQL_ID,'(PL/SQL)') SQL_ID, H.SQL_PLAN_HASH_VALUE PHV, NVL(H.EVENT,'ON CPU') EVT
        FROM DBA_HIST_ACTIVE_SESS_HISTORY H, P WHERE H.SAMPLE_TIME >= DATE '2026-09-29' AND H.PLSQL_ENTRY_OBJECT_ID = P.OBJECT_ID)
SELECT D, SQL_ID, PHV, COUNT(*)*10 APPROX_SEC, STATS_MODE(EVT) TOP_EVT,
       (SELECT SUBSTR(REGEXP_REPLACE(DBMS_LOB.SUBSTR(T.SQL_TEXT,120,1),'\s+',' '),1,70) FROM DBA_HIST_SQLTEXT T WHERE T.SQL_ID = A.SQL_ID AND ROWNUM = 1) TXT
  FROM A GROUP BY D, SQL_ID, PHV
HAVING COUNT(*) >= 3
 ORDER BY D, APPROX_SEC DESC;

