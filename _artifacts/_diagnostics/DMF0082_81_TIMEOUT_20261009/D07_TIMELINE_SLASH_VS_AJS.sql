PROMPT ################ [X1] ⭐ 이 DB 의 이벤트 시각 — '/' DEFAULT(테이블 ALTER) · '/' 객체 변경(PKG 줄 존재) · AJS 변경(마커) · PKG LAST_DDL ################
SELECT 'SLASHDEF: DM_PLN_MKT_FCST 테이블 LAST_DDL' K, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') T, (SELECT COUNT(*) FROM USER_TAB_COLUMNS WHERE TABLE_NAME='DM_PLN_MKT_FCST' AND DATA_DEFAULT IS NOT NULL) N FROM USER_OBJECTS WHERE OBJECT_NAME='DM_PLN_MKT_FCST' AND OBJECT_TYPE='TABLE'
UNION ALL SELECT 'SLASHDEF: SCM_MST_FUTURE_PRICE 테이블 LAST_DDL', TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS'), NULL FROM USER_OBJECTS WHERE OBJECT_NAME='SCM_MST_FUTURE_PRICE' AND OBJECT_TYPE='TABLE'
UNION ALL SELECT 'SLASHDEF: DM_PLN_SALES_PLAN 테이블 LAST_DDL', TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS'), NULL FROM USER_OBJECTS WHERE OBJECT_NAME='DM_PLN_SALES_PLAN' AND OBJECT_TYPE='TABLE'
UNION ALL SELECT 'PKG_DMF0082 BODY LAST_DDL', TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS'), NULL FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0082' AND OBJECT_TYPE='PACKAGE BODY'
UNION ALL SELECT 'SLASHOBJ 적용 여부: PKG_DMF0082 ''/'' 줄 수 (사내 69)', NULL, COUNT(*) FROM USER_SOURCE WHERE NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND (TEXT LIKE '%NVL(PLANT_SITE_ID, ''/'')%' OR TEXT LIKE '%NVL(B.USER_ID, ''/'')%' OR TEXT LIKE '%''/'' AS PLANT_SITE_ID%' OR TEXT LIKE '%''/'' AS CURRENCY%' OR TEXT LIKE '%= ''/''%')
UNION ALL SELECT 'AJS 10-08 적용 여부: PKG_DMF0082 ''2026.10.08 AJS'' 줄 수 (사내 4)', NULL, COUNT(*) FROM USER_SOURCE WHERE NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%2026.10.08 AJS%'
UNION ALL SELECT 'PR_DM_DNM_CREATE_WS_RTF LAST_DDL (82 AS_Inv ''/'' 작성자)', TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS'), (SELECT COUNT(*) FROM USER_SOURCE WHERE NAME='PR_DM_DNM_CREATE_WS_RTF' AND TEXT LIKE '%ELSE ''/'' END%') FROM USER_OBJECTS WHERE OBJECT_NAME='PR_DM_DNM_CREATE_WS_RTF' AND OBJECT_TYPE='PROCEDURE'
UNION ALL SELECT '82 DM_PLN_MKT_FCST PLANT_SITE_ID=''/'' 행 수 · 최초 생성', TO_CHAR(MIN(CREATION_DATE),'YYYY-MM-DD HH24:MI:SS'), COUNT(*) FROM DM_PLN_MKT_FCST WHERE DIVISION_ID='82' AND PLANT_SITE_ID='/';
PROMPT --  '/' 줄 수 0 = SLASHOBJ 미적용 DB. AJS 줄 수 0 = AJS 10-08 미반영. 두 시각을 아래 [X2]~[X4] 의 날짜와 대조

PROMPT ################ [X2] ⭐ 화면 호출 이력 14일 — 일자 × division: 호출수 · DB 초 최소/중앙/최대 · 호출별(시각:초) ################
SELECT TO_CHAR(TRNM_ST_DTM,'MM-DD') D, REGEXP_SUBSTR(SYS_LOG_MSG_CTN,'"divisionId":"([^"]*)"',1,1,NULL,1) DIV, COUNT(*) N,
       ROUND(MIN((CAST(DB_TRNM_END_DTM AS DATE)-CAST(DB_TRNM_ST_DTM AS DATE))*86400),1) MIN_S,
       ROUND(MEDIAN((CAST(DB_TRNM_END_DTM AS DATE)-CAST(DB_TRNM_ST_DTM AS DATE))*86400),1) MED_S,
       ROUND(MAX((CAST(DB_TRNM_END_DTM AS DATE)-CAST(DB_TRNM_ST_DTM AS DATE))*86400),1) MAX_S,
       SUM(CASE WHEN DB_TRNM_END_DTM IS NULL OR EXCT_MSG_CTN IS NOT NULL THEN 1 ELSE 0 END) ERR_OR_NOEND,
       SUBSTR(LISTAGG(TO_CHAR(TRNM_ST_DTM,'HH24:MI')||':'||ROUND((CAST(DB_TRNM_END_DTM AS DATE)-CAST(DB_TRNM_ST_DTM AS DATE))*86400), ' ' ON OVERFLOW TRUNCATE) WITHIN GROUP (ORDER BY TRNM_ST_DTM),1,120) CALLS
  FROM SCM_COM_SYS_LOG WHERE MNU_ID='DMF0082' AND SHT_NM='FcstNPrice' AND CREATION_DATE >= SYSDATE-14
 GROUP BY TO_CHAR(TRNM_ST_DTM,'MM-DD'), REGEXP_SUBSTR(SYS_LOG_MSG_CTN,'"divisionId":"([^"]*)"',1,1,NULL,1) ORDER BY 1,2;
PROMPT --  판정: MED_S 가 뛰는 첫 날짜가 [X1] 의 어느 시각 뒤인가. ERR_OR_NOEND = 타임아웃 호출(END 미기록)

PROMPT ################ [X3] ⭐ AWR — 주요 문장 1회 소요(초) 시간대별 · PHV (10-01~) — 느려진 첫 시각과 계획 변경 시각 ################
