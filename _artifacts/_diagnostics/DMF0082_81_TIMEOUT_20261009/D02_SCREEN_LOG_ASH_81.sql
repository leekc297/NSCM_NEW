PROMPT ################ [S2c] 호출(세션×실행) 단위 소요 — 어느 호출이 길었고 그 안에서 어느 SQL 이 지배했나 ################
WITH P AS (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0082' AND OBJECT_TYPE='PACKAGE'),
A AS (SELECT A.* FROM GV$ACTIVE_SESSION_HISTORY A, P
       WHERE A.SAMPLE_TIME >= SYSTIMESTAMP - NUMTODSINTERVAL(&MIN,'MINUTE') AND A.PLSQL_ENTRY_OBJECT_ID = P.OBJECT_ID),
X AS (SELECT INST_ID, SESSION_ID, SESSION_SERIAL#, MIN(SAMPLE_TIME) T0, MAX(SAMPLE_TIME) T1, COUNT(*) SAMPLES, MAX(USER_ID) UID_, MAX(MACHINE) MACHINE
        FROM A GROUP BY INST_ID, SESSION_ID, SESSION_SERIAL#),
D AS (SELECT A.INST_ID, A.SESSION_ID, A.SESSION_SERIAL#, A.SQL_ID, COUNT(*) N,
             ROW_NUMBER() OVER (PARTITION BY A.INST_ID, A.SESSION_ID, A.SESSION_SERIAL# ORDER BY COUNT(*) DESC) RN
        FROM A GROUP BY A.INST_ID, A.SESSION_ID, A.SESSION_SERIAL#, A.SQL_ID)
SELECT X.INST_ID INST, X.SESSION_ID SID, X.SESSION_SERIAL# SER, (SELECT USERNAME FROM ALL_USERS U WHERE U.USER_ID = X.UID_) USR, X.MACHINE,
       TO_CHAR(X.T0,'MM-DD HH24:MI:SS') T_FROM, TO_CHAR(X.T1,'HH24:MI:SS') T_TO, X.SAMPLES ACTIVE_SEC,
       D1.SQL_ID TOP1_SQL, D1.N TOP1_SEC, D2.SQL_ID TOP2_SQL, D2.N TOP2_SEC
  FROM X LEFT JOIN D D1 ON D1.INST_ID = X.INST_ID AND D1.SESSION_ID = X.SESSION_ID AND D1.SESSION_SERIAL# = X.SESSION_SERIAL# AND D1.RN = 1
         LEFT JOIN D D2 ON D2.INST_ID = X.INST_ID AND D2.SESSION_ID = X.SESSION_ID AND D2.SESSION_SERIAL# = X.SESSION_SERIAL# AND D2.RN = 2
 ORDER BY X.SAMPLES DESC FETCH FIRST 20 ROWS ONLY;
PROMPT --  ACTIVE_SEC 가 수백 = 그 세션의 조회가 타임아웃 건. TOP1_SQL 이 범인 후보 → D04

