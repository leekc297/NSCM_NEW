W AS (
  SELECT CAST(L.TRNM_ST_DTM AS TIMESTAMP) T0,
         NVL(CAST(L.TRNM_END_DTM AS TIMESTAMP), CAST(L.TRNM_ST_DTM AS TIMESTAMP) + NUMTODSINTERVAL(10,'MINUTE')) T1
    FROM SCM_COM_SYS_LOG L
   WHERE L.MNU_ID = 'DMF0082' AND L.SHT_NM = 'FcstNPrice' AND L.CREATION_DATE >= SYSDATE - &MIN/1440
     AND REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"divisionId":"([^"]*)"',1,1,NULL,1) LIKE '81%'
