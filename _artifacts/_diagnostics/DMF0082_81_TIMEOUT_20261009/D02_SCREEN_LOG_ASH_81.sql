PROMPT ################ [S4] 상위 5 문장의 실행계획 라인별 핫스팟 (어느 오퍼레이션·어느 테이블에서 시간을 썼나) ################
WITH P AS (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0082' AND OBJECT_TYPE='PACKAGE'),
A AS (SELECT A.* FROM GV$ACTIVE_SESSION_HISTORY A, P
       WHERE A.SAMPLE_TIME >= SYSTIMESTAMP - NUMTODSINTERVAL(&MIN,'MINUTE') AND A.PLSQL_ENTRY_OBJECT_ID = P.OBJECT_ID AND A.SQL_ID IS NOT NULL),
TOPS AS (SELECT SQL_ID FROM A GROUP BY SQL_ID ORDER BY COUNT(*) DESC FETCH FIRST 5 ROWS ONLY)
SELECT A.SQL_ID, A.SQL_PLAN_HASH_VALUE PHV, A.SQL_PLAN_LINE_ID PLAN_LINE,
       A.SQL_PLAN_OPERATION || ' ' || A.SQL_PLAN_OPTIONS OP,
       (SELECT O.OBJECT_NAME FROM ALL_OBJECTS O WHERE O.OBJECT_ID = A.CURRENT_OBJ# AND ROWNUM = 1) OBJ,
       NVL(A.EVENT,'ON CPU') EVT, COUNT(*) SAMPLES
  FROM A WHERE A.SQL_ID IN (SELECT SQL_ID FROM TOPS)
 GROUP BY A.SQL_ID, A.SQL_PLAN_HASH_VALUE, A.SQL_PLAN_LINE_ID, A.SQL_PLAN_OPERATION, A.SQL_PLAN_OPTIONS, A.CURRENT_OBJ#, NVL(A.EVENT,'ON CPU')
HAVING COUNT(*) >= 2
 ORDER BY A.SQL_ID, SAMPLES DESC;
