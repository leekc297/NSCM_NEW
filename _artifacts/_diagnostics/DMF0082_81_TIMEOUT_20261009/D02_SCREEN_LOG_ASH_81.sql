PROMPT ################ [S1] ⭐ 화면 Search 호출 이력 — division 별 DB / SERVER / TOTAL 구간 (SCM_COM_SYS_LOG, 최근 &MIN 분) ################
PROMPT --  DB_S = SP 호출+fetch+BE 결과로그 / SERVER_S = BE 전체 / TOTAL_S = FE 왕복. ERR 에 timeout·cancel 류가 있으면 그 행이 타임아웃 호출
PROMPT --  ⚠ 타임아웃 호출은 BE 가 END 시각을 못 남겨 DB_S 가 NULL 또는 비정상일 수 있다 — ST 시각과 [S2] ASH 구간을 맞춰 본다
PROMPT --  사내 기준(10-09, ZIOUI1 SYS_LOG 7일): 40 평균 DB 169.7s(최대 793s, 사내 DB 부하일) — 사내는 81 화면 호출 이력 없음
WITH L AS (
  SELECT L.*,
         REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"divisionId":"([^"]*)"',1,1,NULL,1) DIV,
         REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"userGroup":"([^"]*)"',1,1,NULL,1) USER_GROUP,
         REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"versionType":"([^"]*)"',1,1,NULL,1) VER,
         REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"fromYyyymmdd":"([^"]*)"',1,1,NULL,1) || '~' ||
         REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"toYyyymmdd":"([^"]*)"',1,1,NULL,1) PERIOD,
         REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"plantSiteId":"([^"]*)"',1,1,NULL,1) PLANT,
         REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"qtyYn":"([^"]*)"',1,1,NULL,1) QTY
    FROM SCM_COM_SYS_LOG L
   WHERE L.MNU_ID = 'DMF0082' AND L.SHT_NM = 'FcstNPrice' AND L.CREATION_DATE >= SYSDATE - &MIN/1440
)
SELECT TO_CHAR(TRNM_ST_DTM,'MM-DD HH24:MI:SS') ST, DIV, USER_GROUP, VER, PERIOD, PLANT, QTY, CREATED_BY,
       ROUND((CAST(DB_TRNM_END_DTM AS DATE) - CAST(DB_TRNM_ST_DTM AS DATE))*86400, 1) DB_S,
       ROUND((CAST(TRNM_END_DTM AS DATE) - CAST(TRNM_ST_DTM AS DATE))*86400, 1) SERVER_S,
       ROUND((CAST(LOG_END_DTM AS DATE) - CAST(LOG_ST_DTM AS DATE))*86400, 1) TOTAL_S,
       ROUND((CAST(DB_TRNM_ST_DTM AS DATE) - CAST(TRNM_ST_DTM AS DATE))*86400, 1) PRE_DB_S,
       SUBSTR(EXCT_MSG_CTN,1,100) ERR
  FROM L
 ORDER BY TRNM_ST_DTM DESC
 FETCH FIRST 60 ROWS ONLY;

PROMPT ################ [S1b] division 별 요약 (최근 &MIN 분) — 81 vs 40 ################
WITH L AS (
  SELECT REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"divisionId":"([^"]*)"',1,1,NULL,1) DIV,
         (CAST(DB_TRNM_END_DTM AS DATE) - CAST(DB_TRNM_ST_DTM AS DATE))*86400 DB_S,
         (CAST(TRNM_END_DTM AS DATE) - CAST(TRNM_ST_DTM AS DATE))*86400 SERVER_S, EXCT_MSG_CTN ERR
    FROM SCM_COM_SYS_LOG L
   WHERE L.MNU_ID = 'DMF0082' AND L.SHT_NM = 'FcstNPrice' AND L.CREATION_DATE >= SYSDATE - &MIN/1440
)
SELECT DIV, COUNT(*) CALLS, ROUND(AVG(DB_S),1) AVG_DB_S, ROUND(MAX(DB_S),1) MAX_DB_S, ROUND(AVG(SERVER_S),1) AVG_SERVER_S,
       SUM(CASE WHEN ERR IS NOT NULL THEN 1 ELSE 0 END) ERRS, SUM(CASE WHEN DB_S IS NULL THEN 1 ELSE 0 END) NO_END,
       CASE WHEN MAX(DB_S) >= 120 OR SUM(CASE WHEN DB_S IS NULL THEN 1 ELSE 0 END) > 0 THEN '❌ 타임아웃급 (DB 구간)'
            WHEN AVG(DB_S) >= 20 THEN '⚠ 느림' ELSE 'ok' END JUDGE
  FROM L GROUP BY DIV ORDER BY DIV;

