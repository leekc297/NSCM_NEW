A AS (
  SELECT DISTINCT A.SAMPLE_ID, A.SESSION_ID, A.SQL_EXEC_ID, A.SQL_ID, A.SQL_PLAN_HASH_VALUE, A.EVENT, A.IN_HARD_PARSE,
         A.SQL_PLAN_LINE_ID, A.SQL_PLAN_OPERATION, A.SQL_PLAN_OPTIONS, A.CURRENT_OBJ#
    FROM GV$ACTIVE_SESSION_HISTORY A, P, W
   WHERE A.SAMPLE_TIME BETWEEN W.T0 AND W.T1
     AND A.PLSQL_ENTRY_OBJECT_ID = P.OBJECT_ID
),
T AS (SELECT SQL_ID, MAX(PROGRAM_LINE#) LN, MIN(SUBSTR(REGEXP_REPLACE(SQL_TEXT,'\s+',' '),1,90)) TXT
        FROM GV$SQL WHERE SQL_ID IN (SELECT SQL_ID FROM A) GROUP BY SQL_ID)
SELECT NVL(A.SQL_ID,'(PL/SQL·파싱)') SQL_ID, T.LN LINE, COUNT(*) SAMPLES,
       ROUND(100 * RATIO_TO_REPORT(COUNT(*)) OVER (), 1) PCT,
       COUNT(DISTINCT A.SQL_PLAN_HASH_VALUE) PHV_CNT, MAX(A.SQL_PLAN_HASH_VALUE) PHV,
       STATS_MODE(NVL(A.EVENT,'ON CPU')) TOP_EVT,
       SUM(CASE WHEN A.IN_HARD_PARSE = 'Y' THEN 1 ELSE 0 END) HARD_PARSE,
       COUNT(DISTINCT A.SESSION_ID || ',' || A.SQL_EXEC_ID) EXECS,
       CASE WHEN T.TXT LIKE '%DM_PLN_SALES_PLAN S%' OR T.TXT LIKE '%DM_PLN_SALES_PLAN_C S%' THEN '81MKTAMT arm(10-02)'
            WHEN T.TXT LIKE '%SCM_MST_FUTURE_PRICE%' THEN '판가(ONEREAD)'
            WHEN T.TXT LIKE '%DM_PLN_MKT_FCST_RESULT%' THEN '실적 arm' END TAG,
       T.TXT
  FROM A LEFT JOIN T ON T.SQL_ID = A.SQL_ID
 GROUP BY NVL(A.SQL_ID,'(PL/SQL·파싱)'), T.LN, T.TXT
 ORDER BY SAMPLES DESC
 FETCH FIRST 25 ROWS ONLY;
