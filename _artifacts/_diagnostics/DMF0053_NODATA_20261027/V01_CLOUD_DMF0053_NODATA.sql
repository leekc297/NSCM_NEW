-- V01_CLOUD_DMF0053_NODATA — DMF0014 에서 보이는 Customer FCST 가 DMF0053(Cust FCST Waterfall)에서 안 보이는 원인 확인
-- 클라우드 · SCM_MGR · 조회 전용 (마지막 블록은 조회 프로시저 호출 후 ROLLBACK) · 전체 F5 · 값 입력은 C6 블록 맨 위 c_user 1곳만
--
-- 데이터 흐름 (사내 ZIOUI1 · AS-IS LGCE_SCMDEV 원문 확인 2026-10-27)
--   ① DMF0014 업로드   → DM_PLN_CUSTOMER_PSI            (DMF0014 조회 원천)
--   ② 업로드 후속      → DM_PLN_MKT_FCST  MEASURE IN ('CUST_FCST','Customer FCST')   (PKG_DMF0014.P_PR_DM_PLN_CUST_FCST_TO_MKT_FCST)
--   ③ 배치 잡          JOB_PR_DM_DNM_EDI_CALLOFF  step2 = PR_DM_PLN_CUST_FCST_RECORD('81','EDI') ('81_UC','EDI') ('81','RPA') ('40','RPA')
--                      RPA 분기 = DM_PLN_MKT_FCST 의 위 메저 중 LAST_UPDATE_DATE ≥ 어제 인 행을 이력으로 복사 (AS-IS 동일 · 잡에서만 호출)
--   ④ DM_PLN_CUST_FCST_H                                    (DMF0053 조회 원천 · CREATE_DATE = MKT_FCST.CREATION_DATE 의 YYYYMMDD)
--   ⑤ DMF0053 : H 를 사용자 Measure 설정 · 기간(YYYYMMDD) · 생성일(CREATE_DATE) · 조회조건으로 거른다
--   ⇒ 업로드 직후에는 ③ 배치가 돌기 전까지 DMF0053 에 안 나온다. 잡이 꺼져 있거나 실패하면 계속 안 나온다.
--
-- 표본 키 = 사용자 제공 DMF0014 조회 결과 8행 (81)
SET SERVEROUTPUT ON SIZE UNLIMITED
SET LINESIZE 250 PAGESIZE 500
SET DEFINE OFF

-- C0 접속 · 객체 상태
SELECT 'C0' CHK, SYS_CONTEXT('USERENV','DB_NAME') DB_NAME, TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI:SS') NOW FROM DUAL;
SELECT 'C0 객체' CHK, OBJECT_NAME, OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL
  FROM USER_OBJECTS
 WHERE OBJECT_NAME IN ('PKG_DMF0014','PKG_DMF0053','PR_DM_PLN_CUST_FCST_RECORD','PR_DM_DNM_EDI_CALLOFF')
 ORDER BY 2, 3;

-- C1 ③ 배치 잡 상태 (꺼짐·실패·최근 실행 시각)
SELECT 'C1 잡' CHK, JOB_NAME, ENABLED, STATE, RUN_COUNT, FAILURE_COUNT
     , TO_CHAR(LAST_START_DATE, 'YYYY-MM-DD HH24:MI') LAST_START, TO_CHAR(NEXT_RUN_DATE, 'YYYY-MM-DD HH24:MI') NEXT_RUN, REPEAT_INTERVAL
  FROM USER_SCHEDULER_JOBS
 WHERE UPPER(JOB_ACTION) LIKE '%PR_DM_PLN_CUST_FCST_RECORD%';
SELECT 'C1 실행이력' CHK, JOB_NAME, TO_CHAR(ACTUAL_START_DATE, 'YYYY-MM-DD HH24:MI') STARTED, STATUS, RUN_DURATION, SUBSTR(ADDITIONAL_INFO, 1, 150) INFO
  FROM USER_SCHEDULER_JOB_RUN_DETAILS
 WHERE JOB_NAME IN (SELECT JOB_NAME FROM USER_SCHEDULER_JOBS WHERE UPPER(JOB_ACTION) LIKE '%PR_DM_PLN_CUST_FCST_RECORD%')
 ORDER BY ACTUAL_START_DATE DESC FETCH FIRST 10 ROWS ONLY;
SELECT 'C1 배치로그' CHK, TO_CHAR(EVENT_DATE, 'YYYY-MM-DD HH24:MI:SS') EVENT_TIME, LOG_TYPE, SUBSTR(LOG_MESSAGE, 1, 80) MSG, SUBSTR(DESCRIPTION, 1, 60) DESCR, SUBSTR(SQL_ERR_MSG, 1, 120) ERR
  FROM SCM_SYS_LOG_BATCH
 WHERE UPPER(PROGRAM_NAME) LIKE '%PR_DM_PLN_CUST_FCST_RECORD%'
 ORDER BY EVENT_DATE DESC FETCH FIRST 20 ROWS ONLY;

-- C2 ④ 이력 테이블 최신성 — 사업부별 마지막 CREATE_DATE · 최근 14일 적재 건수
SELECT 'C2 이력' CHK, DIVISION_ID, MAX(CREATE_DATE) MAX_CREATE_DATE, TO_CHAR(MAX(LAST_UPDATE_DATE), 'YYYY-MM-DD HH24:MI') MAX_LAST_UPD
     , SUM(CASE WHEN CREATE_DATE >= TO_CHAR(SYSDATE - 14, 'YYYYMMDD') THEN 1 ELSE 0 END) ROWS_LAST_14D, COUNT(*) TOTAL
  FROM DM_PLN_CUST_FCST_H
 WHERE MEASURE IN ('CUST_FCST', 'Customer FCST')
 GROUP BY DIVISION_ID ORDER BY 2;

-- C3 표본 키 단계별 존재 — ① PSI / ② MKT_FCST / ④ 이력 (같은 Sales Site · Model)
WITH K AS (
          SELECT '81' DIV, 'Ampere Electricity_FR_DOI' SITE, 'AMRSAEV20-A2' ITEM FROM DUAL
UNION ALL SELECT '81', 'Ampere Electricity_FR_DOI', 'AMRSAEV20-B2' FROM DUAL
UNION ALL SELECT '81', 'Ampere Electricity_FR_DOI', 'AMRSAEV20-C1' FROM DUAL
UNION ALL SELECT '81', 'CS Enertech_KR_OSN_KR_OSN', 'AMCOME782-A1-0A0' FROM DUAL
UNION ALL SELECT '81', 'FCA_CA_WND', 'APFCAPHEV-B5-000' FROM DUAL
UNION ALL SELECT '81', 'FCA_US_HLM', 'APFCAPHEV-B5-020' FROM DUAL
UNION ALL SELECT '81', 'FCA_US_HLM', 'APFCA48V0-C1-020' FROM DUAL
UNION ALL SELECT '81', 'FCA_US_SEH', 'APFCA48V0-C1' FROM DUAL )
SELECT 'C3' CHK, K.SITE, K.ITEM
     , (SELECT COUNT(*) FROM DM_PLN_CUSTOMER_PSI P WHERE P.DIVISION_ID = K.DIV AND P.SCM_SITE_ID = K.SITE AND P.ITEM_ID = K.ITEM AND P.MEASURE_GROUP = 'CUST_FCST') PSI_ROWS
     , (SELECT TO_CHAR(MAX(P.LAST_UPDATE_DATE), 'YYYY-MM-DD HH24:MI') FROM DM_PLN_CUSTOMER_PSI P WHERE P.DIVISION_ID = K.DIV AND P.SCM_SITE_ID = K.SITE AND P.ITEM_ID = K.ITEM AND P.MEASURE_GROUP = 'CUST_FCST') PSI_LAST_UPD
     , (SELECT COUNT(*) FROM DM_PLN_MKT_FCST M WHERE M.DIVISION_ID = K.DIV AND M.SCM_SITE_ID = K.SITE AND M.ITEM_ID = K.ITEM AND M.MEASURE IN ('CUST_FCST', 'Customer FCST')) MKT_ROWS
     , (SELECT TO_CHAR(MAX(M.LAST_UPDATE_DATE), 'YYYY-MM-DD HH24:MI') FROM DM_PLN_MKT_FCST M WHERE M.DIVISION_ID = K.DIV AND M.SCM_SITE_ID = K.SITE AND M.ITEM_ID = K.ITEM AND M.MEASURE IN ('CUST_FCST', 'Customer FCST')) MKT_LAST_UPD
     , (SELECT COUNT(*) FROM DM_PLN_CUST_FCST_H H WHERE H.DIVISION_ID = K.DIV AND H.SCM_SITE_ID = K.SITE AND H.ITEM_ID = K.ITEM AND H.MEASURE IN ('CUST_FCST', 'Customer FCST')) H_ROWS
     , (SELECT MAX(H.CREATE_DATE) FROM DM_PLN_CUST_FCST_H H WHERE H.DIVISION_ID = K.DIV AND H.SCM_SITE_ID = K.SITE AND H.ITEM_ID = K.ITEM AND H.MEASURE IN ('CUST_FCST', 'Customer FCST')) H_MAX_CREATE
     , (SELECT MIN(H.YYYYMMDD) || '~' || MAX(H.YYYYMMDD) FROM DM_PLN_CUST_FCST_H H WHERE H.DIVISION_ID = K.DIV AND H.SCM_SITE_ID = K.SITE AND H.ITEM_ID = K.ITEM AND H.MEASURE IN ('CUST_FCST', 'Customer FCST')) H_YMD_RANGE
     , (SELECT COUNT(*) FROM SCM_MST_SITE_ITEM S WHERE S.DIVISION_ID = K.DIV AND S.SCM_SITE_ID = K.SITE AND S.ITEM_ID = K.ITEM) SITE_ITEM_ROWS
  FROM K ORDER BY 2, 3;

-- C4 표본 키 메저 표기 — 단계마다 MEASURE 값이 무엇으로 들어가는지 (DMF0053 은 H.MEASURE = 선택 Measure 정확 일치로 읽는다)
WITH K AS (
          SELECT '81' DIV, 'Ampere Electricity_FR_DOI' SITE, 'AMRSAEV20-A2' ITEM FROM DUAL
UNION ALL SELECT '81', 'FCA_US_SEH', 'APFCA48V0-C1' FROM DUAL )
SELECT 'C4' CHK, SRC, MEASURE, CNT, YMD_FROM, YMD_TO, LAST_UPD FROM (
  SELECT 'PSI' SRC, P.MEASURE, COUNT(*) CNT, MIN(P.YYYYMMDD) YMD_FROM, MAX(P.YYYYMMDD) YMD_TO, TO_CHAR(MAX(P.LAST_UPDATE_DATE), 'YYYY-MM-DD HH24:MI') LAST_UPD
    FROM DM_PLN_CUSTOMER_PSI P JOIN K ON P.DIVISION_ID = K.DIV AND P.SCM_SITE_ID = K.SITE AND P.ITEM_ID = K.ITEM GROUP BY P.MEASURE
  UNION ALL
  SELECT 'MKT_FCST', M.MEASURE, COUNT(*), MIN(M.YYYYMMDD), MAX(M.YYYYMMDD), TO_CHAR(MAX(M.LAST_UPDATE_DATE), 'YYYY-MM-DD HH24:MI')
    FROM DM_PLN_MKT_FCST M JOIN K ON M.DIVISION_ID = K.DIV AND M.SCM_SITE_ID = K.SITE AND M.ITEM_ID = K.ITEM
   WHERE UPPER(M.MEASURE) LIKE '%CUST%' GROUP BY M.MEASURE
  UNION ALL
  SELECT 'HISTORY', H.MEASURE, COUNT(*), MIN(H.YYYYMMDD), MAX(H.YYYYMMDD), MAX(H.CREATE_DATE)
    FROM DM_PLN_CUST_FCST_H H JOIN K ON H.DIVISION_ID = K.DIV AND H.SCM_SITE_ID = K.SITE AND H.ITEM_ID = K.ITEM GROUP BY H.MEASURE )
 ORDER BY 2, 3;

-- C5 ⑤ DMF0053 Measure 설정 — 사용자 'M' 설정 · 고객수요 Measure 마스터 (CUST_FCST 를 고르면 DM_MST_CUSTOMER_FCST 의 Measure 로 펼친다)
SELECT 'C5 사용자M' CHK, U.USER_ID, U.COLUMN_NAME, U.SORT_ORDER_NO
  FROM SCM_MST_TITLESET_USER U
 WHERE U.PROGRAM_ID = 'DMF0053' AND U.USER_INQUIRY_COLUMN_TYPE_CODE = 'M'
   AND U.USER_ID IN ('minyonglee1')            -- ★ 화면에서 조회한 계정
 ORDER BY 2, 4;
SELECT 'C5 메저마스터' CHK, C.DIVISION_ID, C.MEASURE_GROUP, C.MEASURE, C.VALID_YN, COUNT(*) ROWS_
  FROM DM_MST_CUSTOMER_FCST C
 WHERE C.MEASURE_GROUP = 'CUST_FCST' AND C.DIVISION_ID IN ('81')
 GROUP BY C.DIVISION_ID, C.MEASURE_GROUP, C.MEASURE, C.VALID_YN ORDER BY 2, 4;

-- C6 DMF0053 조회 프로시저 직접 호출 — 넓은 기간·생성일로 표본 Model 이 결과에 나오는지 (끝에 ROLLBACK)
DECLARE
    c_user  CONSTANT VARCHAR2(100) := 'minyonglee1';   -- ★ 화면에서 조회한 계정
    rc1 SYS_REFCURSOR; rc2 SYS_REFCURSOR; rc3 SYS_REFCURSOR; rcr SYS_REFCURSOR;
    v_cur INTEGER; v_cnt INTEGER; v_desc DBMS_SQL.DESC_TAB2; v_val VARCHAR2(4000);
    i_item INTEGER; v_rows PLS_INTEGER := 0; v_hit PLS_INTEGER := 0; v_code VARCHAR2(100); v_msg VARCHAR2(4000);
BEGIN
    PKG_DMF0053.P_DMF0053_GET_CUST_FCST_WATERFALL(
        '81', 'ALL', 'ALL', 'ALL', NULL, NULL, 'ALL',
        '20260101', '20271231',                 -- 수요 기간 (YYYYMMDD)
        c_user, 'ALL', 'ALL', NULL, 'WEEKLY', 'ALL', 'ADMIN', NULL,
        '20260101', '20271231',                 -- 생성일(CREATE_DATE) 범위 — 화면 'Create Date' 조건
        c_user, 'DMF0053', rc1, rc2, rc3, rcr);
    DBMS_OUTPUT.PUT_LINE('== C6 DMF0053 조회 (수요 20260101~20271231 · 생성일 20260101~20271231 · 사용자 ' || c_user || ')');
    v_cur := DBMS_SQL.TO_CURSOR_NUMBER(rc1);
    DBMS_SQL.DESCRIBE_COLUMNS2(v_cur, v_cnt, v_desc);
    FOR i IN 1 .. v_cnt LOOP IF v_desc(i).col_name = 'ITEM_ID' THEN i_item := i; DBMS_SQL.DEFINE_COLUMN(v_cur, i, v_val, 4000); END IF; END LOOP;
    WHILE DBMS_SQL.FETCH_ROWS(v_cur) > 0 LOOP
        v_rows := v_rows + 1;
        IF i_item IS NOT NULL THEN
            DBMS_SQL.COLUMN_VALUE(v_cur, i_item, v_val);
            IF v_val IN ('AMRSAEV20-A2','AMRSAEV20-B2','AMRSAEV20-C1','AMCOME782-A1-0A0','APFCAPHEV-B5-000','APFCAPHEV-B5-020','APFCA48V0-C1-020','APFCA48V0-C1') THEN
                v_hit := v_hit + 1;
            END IF;
        END IF;
    END LOOP;
    DBMS_SQL.CLOSE_CURSOR(v_cur);
    DBMS_OUTPUT.PUT_LINE('   결과 전체 ' || v_rows || '줄 · 표본 Model 줄 ' || v_hit || CASE WHEN i_item IS NULL THEN ' (결과에 ITEM_ID 컬럼 없음 — 사용자 Column 설정 확인)' END);
    -- 원천 임시 테이블에 표본이 들어왔는지 (필터 전 · 후 구분은 C3/C4 와 대조)
    EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM GT_DMF0053_RAW_DATA WHERE ITEM_ID IN (''AMRSAEV20-A2'',''AMRSAEV20-B2'',''AMRSAEV20-C1'',''AMCOME782-A1-0A0'',''APFCAPHEV-B5-000'',''APFCAPHEV-B5-020'',''APFCA48V0-C1-020'',''APFCA48V0-C1'')' INTO v_cnt;
    DBMS_OUTPUT.PUT_LINE('   필터 후 원천 임시 테이블(GT_DMF0053_RAW_DATA) 표본 행 ' || v_cnt);
    EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM GT_DMF0053_SELECT_MEASURE' INTO v_cnt;
    DBMS_OUTPUT.PUT_LINE('   선택 Measure 펼침(GT_DMF0053_SELECT_MEASURE) ' || v_cnt || '건');
    FOR r IN (SELECT MEASURE_GROUP, MEASURE FROM GT_DMF0053_SELECT_MEASURE ORDER BY SORT_ORDER_NO) LOOP
        DBMS_OUTPUT.PUT_LINE('     ' || r.MEASURE_GROUP || ' / ' || r.MEASURE);
    END LOOP;
    ROLLBACK;
EXCEPTION WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('== C6 오류 ' || SQLERRM);
    ROLLBACK;
END;
