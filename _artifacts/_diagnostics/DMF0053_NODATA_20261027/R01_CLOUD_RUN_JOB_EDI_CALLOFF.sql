-- R01_CLOUD_RUN_JOB_EDI_CALLOFF — JOB_PR_DM_DNM_EDI_CALLOFF 1회 수동 실행 (클라우드 · SCM_MGR · 전체 F5 · 값 입력 없음)
--
-- 목적: DMF0014 업로드분이 DMF0053(Cust FCST Waterfall)에 보이려면 이 잡의 step2(PR_DM_PLN_CUST_FCST_RECORD)가
--       DM_PLN_MKT_FCST → DM_PLN_CUST_FCST_H 로 이력을 쌓아야 한다 (AS-IS 동일 구조 · 화면 SP 는 이 배치를 부르지 않는다).
-- 방식: 이 DB 의 잡 정의(USER_SCHEDULER_JOBS.JOB_ACTION)를 그대로 읽어 현재 세션에서 실행한다 — 잡 활성/비활성과 무관.
--       잡 자체의 ENABLED 상태·스케줄은 바꾸지 않는다.
-- 잡 내용 (사내 ZIOUI1 정의 기준 · 클라우드 실제 내용은 R0 에 출력):
--   step1 PR_DM_DNM_EDI_CALLOFF                (EDI Calloff 처리 · 실패해도 다음 단계 진행)
--   step2 PR_DM_PLN_CUST_FCST_RECORD('81','EDI') ('81_UC','EDI') ('81','RPA') ('40','RPA')
-- ⚠ 이력 적재 범위 = RECORD 안에서 '어제(TRUNC(SYSDATE)-1) 이후 수정분'으로 고정. 그보다 전에 업로드한 행은 이번 실행으로 들어가지 않는다
--   → R1 에서 표본 키의 MKT_FCST 최종 수정일이 어제 이전인지 먼저 본다 (이전이면 별도 조치 필요 — 회신).
-- ⚠ 82 · 81_HM · 81_ST · 81_HD · 81_HG 는 잡 대상이 아니다 (RECORD 호출 목록에 없음).
-- 실행 시간: step1·step2 데이터량에 따라 수 분 — 끝날 때까지 다른 F5 금지.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET LINESIZE 250 PAGESIZE 500
SET DEFINE OFF

-- R0 잡 정의 · 상태 (실행할 내용 확인)
SELECT 'R0' CHK, SYS_CONTEXT('USERENV','DB_NAME') DB_NAME, USER, TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI:SS') NOW, TO_CHAR(TRUNC(SYSDATE) - 1, 'YYYYMMDD') RECORD_FROM_DATE FROM DUAL;
SELECT 'R0 잡' CHK, JOB_NAME, ENABLED, STATE, RUN_COUNT, FAILURE_COUNT, TO_CHAR(LAST_START_DATE,'YYYY-MM-DD HH24:MI') LAST_START, REPEAT_INTERVAL
  FROM USER_SCHEDULER_JOBS WHERE JOB_NAME = 'JOB_PR_DM_DNM_EDI_CALLOFF';
SELECT 'R0 내용' CHK, JOB_ACTION FROM USER_SCHEDULER_JOBS WHERE JOB_NAME = 'JOB_PR_DM_DNM_EDI_CALLOFF';
SELECT 'R0 객체' CHK, OBJECT_NAME, STATUS, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI') LAST_DDL FROM USER_OBJECTS
 WHERE OBJECT_NAME IN ('PR_DM_DNM_EDI_CALLOFF','PR_DM_PLN_CUST_FCST_RECORD') ORDER BY 2;

-- R1 실행 전 — 사업부별 이력 최신성 · 표본 키(MKT_FCST 최종 수정일이 RECORD 적재 범위 안인지)
SELECT 'R1 이력' CHK, DIVISION_ID, MAX(CREATE_DATE) MAX_CREATE_DATE, TO_CHAR(MAX(LAST_UPDATE_DATE), 'YYYY-MM-DD HH24:MI') MAX_LAST_UPD, COUNT(*) TOTAL
  FROM DM_PLN_CUST_FCST_H WHERE MEASURE IN ('CUST_FCST', 'Customer FCST') GROUP BY DIVISION_ID ORDER BY 2;
WITH K AS (
          SELECT '81' DIV, 'Ampere Electricity_FR_DOI' SITE, 'AMRSAEV20-A2' ITEM FROM DUAL
UNION ALL SELECT '81', 'Ampere Electricity_FR_DOI', 'AMRSAEV20-B2' FROM DUAL
UNION ALL SELECT '81', 'Ampere Electricity_FR_DOI', 'AMRSAEV20-C1' FROM DUAL
UNION ALL SELECT '81', 'CS Enertech_KR_OSN_KR_OSN', 'AMCOME782-A1-0A0' FROM DUAL
UNION ALL SELECT '81', 'FCA_CA_WND', 'APFCAPHEV-B5-000' FROM DUAL
UNION ALL SELECT '81', 'FCA_US_HLM', 'APFCAPHEV-B5-020' FROM DUAL
UNION ALL SELECT '81', 'FCA_US_HLM', 'APFCA48V0-C1-020' FROM DUAL
UNION ALL SELECT '81', 'FCA_US_SEH', 'APFCA48V0-C1' FROM DUAL )
SELECT 'R1 표본' CHK, K.SITE, K.ITEM
     , (SELECT TO_CHAR(MAX(M.LAST_UPDATE_DATE), 'YYYY-MM-DD HH24:MI') FROM DM_PLN_MKT_FCST M
         WHERE M.DIVISION_ID = K.DIV AND M.SCM_SITE_ID = K.SITE AND M.ITEM_ID = K.ITEM AND M.MEASURE IN ('CUST_FCST', 'Customer FCST')) MKT_LAST_UPD
     , (SELECT CASE WHEN MAX(M.LAST_UPDATE_DATE) >= TRUNC(SYSDATE) - 1 THEN '이번 실행으로 적재됨' WHEN MAX(M.LAST_UPDATE_DATE) IS NULL THEN 'MKT_FCST 에 없음 — 업로드 후속 단계 확인'
                    ELSE '어제 이전 수정 — 이번 실행으로 안 들어감' END
          FROM DM_PLN_MKT_FCST M WHERE M.DIVISION_ID = K.DIV AND M.SCM_SITE_ID = K.SITE AND M.ITEM_ID = K.ITEM AND M.MEASURE IN ('CUST_FCST', 'Customer FCST')) JUDGE
     , (SELECT COUNT(*) FROM DM_PLN_CUST_FCST_H H WHERE H.DIVISION_ID = K.DIV AND H.SCM_SITE_ID = K.SITE AND H.ITEM_ID = K.ITEM AND H.MEASURE IN ('CUST_FCST', 'Customer FCST')) H_ROWS_BEFORE
     , (SELECT MAX(H.CREATE_DATE) FROM DM_PLN_CUST_FCST_H H WHERE H.DIVISION_ID = K.DIV AND H.SCM_SITE_ID = K.SITE AND H.ITEM_ID = K.ITEM AND H.MEASURE IN ('CUST_FCST', 'Customer FCST')) H_MAX_CREATE_BEFORE
  FROM K ORDER BY 2, 3;

-- R2 실행 — 이 DB 의 잡 정의를 그대로 현재 세션에서 1회 실행
DECLARE
    v_action CLOB;
    v_t0     DATE := SYSDATE;
BEGIN
    SELECT JOB_ACTION INTO v_action FROM USER_SCHEDULER_JOBS WHERE JOB_NAME = 'JOB_PR_DM_DNM_EDI_CALLOFF';
    DBMS_OUTPUT.PUT_LINE('== R2 실행 시작 ' || TO_CHAR(v_t0, 'YYYY-MM-DD HH24:MI:SS'));
    EXECUTE IMMEDIATE v_action;
    COMMIT;
    DBMS_OUTPUT.PUT_LINE('== R2 실행 완료 ' || TO_CHAR(SYSDATE, 'YYYY-MM-DD HH24:MI:SS') || ' (' || ROUND((SYSDATE - v_t0) * 86400) || '초)');
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('== R2 중단 — JOB_PR_DM_DNM_EDI_CALLOFF 잡이 이 DB 에 없음 (회신)');
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('== R2 오류 ' || TO_CHAR(SYSDATE, 'HH24:MI:SS') || ' ' || SQLERRM);
        DBMS_OUTPUT.PUT_LINE(DBMS_UTILITY.FORMAT_ERROR_BACKTRACE);
        ROLLBACK;
END;
/

-- R3 실행 후 — 배치 로그 · 이력 최신성 · 표본 키 적재 여부
SELECT 'R3 로그' CHK, TO_CHAR(EVENT_DATE, 'YYYY-MM-DD HH24:MI:SS') EVENT_TIME, LOG_TYPE, SUBSTR(LOG_MESSAGE, 1, 60) MSG
     , SUBSTR(DESCRIPTION, 1, 60) DESCR, SUBSTR(SQL_ERR_MSG, 1, 150) ERR
  FROM SCM_SYS_LOG_BATCH
 WHERE (UPPER(PROGRAM_NAME) LIKE '%PR_DM_PLN_CUST_FCST_RECORD%' OR UPPER(PROGRAM_NAME) LIKE '%PR_DM_DNM_EDI_CALLOFF%')
   AND EVENT_DATE >= SYSDATE - 1/24
 ORDER BY EVENT_DATE DESC FETCH FIRST 30 ROWS ONLY;
SELECT 'R3 이력' CHK, DIVISION_ID, MAX(CREATE_DATE) MAX_CREATE_DATE, TO_CHAR(MAX(LAST_UPDATE_DATE), 'YYYY-MM-DD HH24:MI') MAX_LAST_UPD
     , SUM(CASE WHEN LAST_UPDATE_DATE >= TRUNC(SYSDATE) - 1 THEN 1 ELSE 0 END) ROWS_FROM_YESTERDAY, COUNT(*) TOTAL
  FROM DM_PLN_CUST_FCST_H WHERE MEASURE IN ('CUST_FCST', 'Customer FCST') GROUP BY DIVISION_ID ORDER BY 2;
WITH K AS (
          SELECT '81' DIV, 'Ampere Electricity_FR_DOI' SITE, 'AMRSAEV20-A2' ITEM FROM DUAL
UNION ALL SELECT '81', 'Ampere Electricity_FR_DOI', 'AMRSAEV20-B2' FROM DUAL
UNION ALL SELECT '81', 'Ampere Electricity_FR_DOI', 'AMRSAEV20-C1' FROM DUAL
UNION ALL SELECT '81', 'CS Enertech_KR_OSN_KR_OSN', 'AMCOME782-A1-0A0' FROM DUAL
UNION ALL SELECT '81', 'FCA_CA_WND', 'APFCAPHEV-B5-000' FROM DUAL
UNION ALL SELECT '81', 'FCA_US_HLM', 'APFCAPHEV-B5-020' FROM DUAL
UNION ALL SELECT '81', 'FCA_US_HLM', 'APFCA48V0-C1-020' FROM DUAL
UNION ALL SELECT '81', 'FCA_US_SEH', 'APFCA48V0-C1' FROM DUAL )
SELECT 'R3 표본' CHK, K.SITE, K.ITEM
     , (SELECT COUNT(*) FROM DM_PLN_CUST_FCST_H H WHERE H.DIVISION_ID = K.DIV AND H.SCM_SITE_ID = K.SITE AND H.ITEM_ID = K.ITEM AND H.MEASURE IN ('CUST_FCST', 'Customer FCST')) H_ROWS_AFTER
     , (SELECT MAX(H.CREATE_DATE) FROM DM_PLN_CUST_FCST_H H WHERE H.DIVISION_ID = K.DIV AND H.SCM_SITE_ID = K.SITE AND H.ITEM_ID = K.ITEM AND H.MEASURE IN ('CUST_FCST', 'Customer FCST')) H_MAX_CREATE_AFTER
     , (SELECT TO_CHAR(MAX(H.LAST_UPDATE_DATE), 'YYYY-MM-DD HH24:MI') FROM DM_PLN_CUST_FCST_H H WHERE H.DIVISION_ID = K.DIV AND H.SCM_SITE_ID = K.SITE AND H.ITEM_ID = K.ITEM AND H.MEASURE IN ('CUST_FCST', 'Customer FCST')) H_LAST_UPD_AFTER
  FROM K ORDER BY 2, 3;
