-- DMF0074 Excel Upload — Model 공란 행 자동 확장(AS-IS "2-1 ITEMID 없는것 처리") 진단 (읽기 전용)
--   로직 위치: PKG_DMF0074.P_DMF0074_EXCEL_UPLOAD "2-1)ITEMID 없는것 처리(전체)" (AS-IS DMF0074_EXCEL_UPLOAD L1763~1884 와 동일 조건)
--   공란 행 1건이 확장되려면 아래 [3]~[7] 조건을 "모두" 만족하는 모델이 1개 이상 있어야 한다. 하나라도 0건이면 오류 없이 0행.
--   사용: 아래 DEFINE 5개를 테스트 엑셀 행 값으로 바꾸고 클라우드(QA/DEV, BE 가 붙는 쪽) SCM_MGR 로 실행
-- =====================================================================================================
DEFINE P_DIV   = '81'
DEFINE P_PJT   = 'A15FD5002'      -- Excel Project Code
DEFINE P_SITE  = 'Ford_MX_CTN'    -- Excel Sales Site
DEFINE P_CUR   = 'USD'            -- Excel Currency
DEFINE P_FCST  = 'Mass'           -- Excel FCST type (표시명 — SALES_TYPE_CODE.SEGMENT2)

-- [0] 패키지 판본 (공란 판정식이 '@#@#@#' 판본인지)
SELECT LINE, TRIM(TEXT) TEXT FROM ALL_SOURCE
 WHERE OWNER = 'SCM_MGR' AND NAME = 'PKG_DMF0074' AND TYPE = 'PACKAGE BODY' AND TEXT LIKE '%NVL(TMP.ITEM_ID%';

-- [1] 마지막 업로드 원장 — 공란 행의 상태·메시지 (오류로 끝났다면 그 메시지가 원인)
SELECT TO_CHAR(CREATION_DATE,'MM-DD HH24:MI:SS') CRE, UPLOAD_STATUS_CODE, ATTRIBUTE1 DIV, ATTRIBUTE5 PJT, '['||ATTRIBUTE7||']' MODEL,
       ATTRIBUTE9 SITE, ATTRIBUTE10 CUR, ATTRIBUTE11 FCST, SUBSTR(MESSAGE_TEXT,1,120) MSG
  FROM SCM_ADM_EXCEL_UPLOAD
 WHERE PROGRAM_ID LIKE 'DMF0074%' AND CREATION_DATE >= SYSDATE - 1
 ORDER BY CREATION_DATE DESC, UPLOAD_ID FETCH FIRST 30 ROWS ONLY;

-- [2] 대상 Sales Plan 버전 (MRF='Y' 최신 SP_W) — 없으면 확장 원천이 비고, 금주 버전이 없으면 업로드 자체가
--     'There is no version of Monthly Rolling Forest:Y ...' 로 오류
SELECT DIVISION_ID, MAX(VERSION_NO) VERSION_NO, MAX(YYYYMMDD) YYYYMMDD
  FROM DM_MST_VERSION WHERE VERSION_TYPE = 'SP_W' AND NVL(ATTRIBUTE7,'N') = 'Y' AND DIVISION_ID = '&P_DIV'
 GROUP BY DIVISION_ID;

-- [3] 마스터 — 같은 Project·Sales Site 의 유효 모델
SELECT ITEM_ID, SALES_PLANT, VALID_YN FROM SCM_MST_SITE_ITEM
 WHERE DIVISION_ID = '&P_DIV' AND PROJECT_CODE = '&P_PJT' AND SCM_SITE_ID = '&P_SITE' ORDER BY ITEM_ID;

-- [4] FCST type 표시명 → 코드 (FREE 제외)
SELECT SEGMENT1 FCST_CODE, SEGMENT2 FCST_NAME, SEGMENT4, VALID_YN FROM SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE = 'SALES_TYPE_CODE' AND SEGMENT2 = '&P_FCST';

-- [5]~[7] 조건별 통과 모델 수 (어느 단계에서 0 이 되는지)
WITH TMP AS (SELECT '&P_DIV' DIVISION_ID, '&P_PJT' PROJECT_CODE, '&P_SITE' SCM_SITE_ID, '&P_CUR' CURRENCY, '&P_FCST' FCST_TYPE FROM DUAL),
VER AS (SELECT A.DIVISION_ID, A.VERSION_NO,
               TO_CHAR(FN_NEXT_DAY(TO_DATE(A.YYYYMMDD,'YYYYMMDD'),'MON') - 7, 'YYYYMMDD') RESULT_TO,
               TO_CHAR(FN_NEXT_DAY(TO_DATE(A.YYYYMMDD,'YYYYMMDD'),'MON') - 7 + 52*7 - 1, 'YYYYMMDD') PLAN_TO
          FROM (SELECT DIVISION_ID, MAX(VERSION_NO) VERSION_NO, MAX(YYYYMMDD) YYYYMMDD FROM DM_MST_VERSION
                 WHERE VERSION_TYPE = 'SP_W' AND NVL(ATTRIBUTE7,'N') = 'Y' GROUP BY DIVISION_ID) A),
SPI AS (SELECT DISTINCT PC.DIVISION_ID, PC.PROJECT_CODE, PC.SCM_SITE_ID, PC.ITEM_ID, PC.FCST_TYPE, PC.CURRENCY
          FROM DM_PLN_SALES_PLAN_C PC JOIN VER ON VER.DIVISION_ID = PC.DIVISION_ID AND VER.VERSION_NO = PC.VERSION_NO
         WHERE PC.QTY <> 0 AND PC.MEASURE = 'RTF_SYS_RP' AND PC.YYYYMMDD BETWEEN VER.RESULT_TO AND VER.PLAN_TO),
M AS (SELECT ITM.ITEM_ID FROM TMP JOIN SCM_MST_SITE_ITEM ITM
         ON ITM.DIVISION_ID = TMP.DIVISION_ID AND ITM.PROJECT_CODE = TMP.PROJECT_CODE AND ITM.SCM_SITE_ID = TMP.SCM_SITE_ID AND ITM.VALID_YN = 'Y'),
L AS (SELECT LUP.SEGMENT1 FROM TMP JOIN SCM_ADM_LOOKUP_MASTER_DETAIL LUP
         ON LUP.LOOKUP_TYPE = 'SALES_TYPE_CODE' AND LUP.VALID_YN = 'Y' AND LUP.SEGMENT4 <> 'FREE' AND LUP.SEGMENT2 = TMP.FCST_TYPE),
P AS (SELECT M.ITEM_ID FROM M JOIN (SELECT DISTINCT DIVISION_ID, ITEM_ID FROM DM_MST_ITEM_SINGLE_V WHERE ITEM_TYPE = 'P' AND ACTIVE_FLAG = 'Y') SV
         ON SV.DIVISION_ID = '&P_DIV' AND SV.ITEM_ID = M.ITEM_ID)
SELECT (SELECT COUNT(*) FROM M) "③마스터 유효모델",
       (SELECT COUNT(*) FROM L) "④FCST 코드(1이어야)",
       (SELECT COUNT(*) FROM P) "⑤제품(P)·활성",
       (SELECT COUNT(*) FROM P WHERE P.ITEM_ID IN (SELECT ITEM_ID FROM SPI, TMP WHERE SPI.DIVISION_ID = TMP.DIVISION_ID
                AND SPI.PROJECT_CODE = TMP.PROJECT_CODE AND SPI.SCM_SITE_ID = TMP.SCM_SITE_ID)) "⑥SalesPlan RTF(통화·FCST 무관)",
       (SELECT COUNT(*) FROM P WHERE P.ITEM_ID IN (SELECT ITEM_ID FROM SPI, TMP, L WHERE SPI.DIVISION_ID = TMP.DIVISION_ID
                AND SPI.PROJECT_CODE = TMP.PROJECT_CODE AND SPI.SCM_SITE_ID = TMP.SCM_SITE_ID
                AND SPI.CURRENCY = TMP.CURRENCY AND SPI.FCST_TYPE = L.SEGMENT1)) "⑦최종 확장 모델수"
  FROM DUAL;
