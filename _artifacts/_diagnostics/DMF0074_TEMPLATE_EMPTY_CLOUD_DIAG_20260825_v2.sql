PROMPT ===== D0. (0순위) PKG_DMF0074 세대 판정 =====
PROMPT ===== 기대(사내 실측): MRFPARITY_MARK=1 / MRF_FILTER_ACTIVE=5 (UPLOAD 쪽 활성분 정상) =====
PROMPT ===== MARK=0 (대개 ACTIVE=6) = 구세대 BODY = 원인 확정 =====
SELECT
    (SELECT COUNT(*) FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0074' AND TYPE='PACKAGE BODY'
      AND INSTR(TEXT,'MRFPARITY') > 0)                                             AS MRFPARITY_MARK,
    (SELECT COUNT(*) FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0074' AND TYPE='PACKAGE BODY'
      AND REGEXP_LIKE(TEXT, '^\s*AND\s+NVL\(ATTRIBUTE7'))                          AS MRF_FILTER_ACTIVE,
    (SELECT STATUS FROM ALL_OBJECTS WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_DMF0074'
      AND OBJECT_TYPE='PACKAGE BODY')                                              AS BODY_STATUS,
    (SELECT TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI') FROM ALL_OBJECTS WHERE OWNER='SCM_MGR'
      AND OBJECT_NAME='PKG_DMF0074' AND OBJECT_TYPE='PACKAGE BODY')                AS BODY_LAST_DDL
FROM DUAL;

PROMPT ===== D1. 버전 선정 (81/SP_W) — 신·구 로직 각각 + 캘린더 행 유무 병기 (CAL_ROW=0 = 캘린더 원인) =====
WITH PICK AS (
  SELECT 'NEW(MRF 무관 최신)' AS LOGIC, MAX(VERSION_NO) AS VNO, MAX(YYYYMMDD) AS VDT
  FROM SCM_MGR.DM_MST_VERSION WHERE DIVISION_ID='81' AND VERSION_TYPE='SP_W'
  UNION ALL
  SELECT 'OLD(구세대: MRF=Y 만)', MAX(VERSION_NO), MAX(YYYYMMDD)
  FROM SCM_MGR.DM_MST_VERSION WHERE DIVISION_ID='81' AND VERSION_TYPE='SP_W' AND NVL(ATTRIBUTE7,'N')='Y')
SELECT P.LOGIC, P.VNO, P.VDT,
       (SELECT COUNT(*) FROM SCM_MGR.SCM_SYS_CALENDAR_M B WHERE B.BASIS_YYYYMMDD=P.VDT) AS CAL_ROW
FROM PICK P;

PROMPT ===== D1b. 참고 — 81 SP_W 최근 5버전 + MRF + 원장 유무 병기 (구 D8b 통합: 버전-원장 불일치 한눈 판정) =====
PROMPT ===== 사내 실측: 버전마스터 최신 SP_W_20260821_V001 은 PLAN_RTF_ROWS=0, 보유 최신은 SP_W_20260817_V001(9행) =====
SELECT V.VERSION_NO, V.YYYYMMDD, NVL(V.ATTRIBUTE7,'(NULL)') AS MRF_YN,
       (SELECT /*+ INDEX(C (VERSION_NO DIVISION_ID)) */ COUNT(*) FROM SCM_MGR.DM_PLN_SALES_PLAN_C C
         WHERE C.VERSION_NO=V.VERSION_NO AND C.DIVISION_ID='81'
           AND C.MEASURE='RTF_SYS_RP' AND C.QTY<>0) AS PLAN_RTF_ROWS,
       (SELECT /*+ INDEX(R (VERSION_NO DIVISION_ID)) */ COUNT(*) FROM SCM_MGR.DM_PLN_SALES_PLAN_RESULT_C R
         WHERE R.VERSION_NO=V.VERSION_NO AND R.DIVISION_ID='81'
           AND R.MEASURE='RTF_SYS_RP' AND R.QTY<>0) AS RESULT_RTF_ROWS
FROM (SELECT VERSION_NO, YYYYMMDD, ATTRIBUTE7 FROM SCM_MGR.DM_MST_VERSION
      WHERE DIVISION_ID='81' AND VERSION_TYPE='SP_W' ORDER BY VERSION_NO DESC) V
WHERE ROWNUM <= 5;

PROMPT ===== D2. (구 D3+D4 통합) 신·구 버전별 원장 행수 + NEW 버전 날짜창 적용 행수 — 원장 각 1회 인덱스 접근 =====
PROMPT ===== NEW_PLAN>0 AND OLD 계열=0 = 구세대 BODY 원인 / NEW 계열 전부 0 = 원장 미적재 원인 =====
WITH V AS (
  SELECT MAX(VERSION_NO) AS NEW_VNO, MAX(YYYYMMDD) AS NEW_VDT
  FROM SCM_MGR.DM_MST_VERSION WHERE DIVISION_ID='81' AND VERSION_TYPE='SP_W'),
VO AS (
  SELECT MAX(VERSION_NO) AS OLD_VNO
  FROM SCM_MGR.DM_MST_VERSION WHERE DIVISION_ID='81' AND VERSION_TYPE='SP_W' AND NVL(ATTRIBUTE7,'N')='Y'),
W AS (  -- SP 의 날짜창 산출 (NEW 버전 기준)
  SELECT V.NEW_VNO, VO.OLD_VNO,
         CASE WHEN B.BASIS_YYYYMM > TO_CHAR(SCM_MGR.FN_NEXT_DAY(V.NEW_VDT,'MON')-7,'YYYYMM')
              THEN TO_CHAR(ADD_MONTHS(TO_DATE(B.BASIS_YYYYMM||'01','YYYYMMDD'),-1),'YYYYMMDD')
              ELSE B.BASIS_YYYYMM||'01' END                                    AS RESULT_FROM,
         TO_CHAR(SCM_MGR.FN_NEXT_DAY(V.NEW_VDT,'MON')-7,'YYYYMMDD')            AS RESULT_TO,
         TO_CHAR(SCM_MGR.FN_NEXT_DAY(V.NEW_VDT,'MON')-7+(52*7)-1,'YYYYMMDD')   AS PLAN_TO
  FROM V CROSS JOIN VO
  LEFT JOIN SCM_MGR.SCM_SYS_CALENDAR_M B ON B.BASIS_YYYYMMDD = V.NEW_VDT)
SELECT W.NEW_VNO, W.OLD_VNO, W.RESULT_FROM, W.RESULT_TO, W.PLAN_TO,
       NVL((SELECT /*+ INDEX(SP (VERSION_NO DIVISION_ID)) */ COUNT(*)
              FROM SCM_MGR.DM_PLN_SALES_PLAN_C SP
             WHERE SP.VERSION_NO=W.NEW_VNO AND SP.DIVISION_ID='81'
               AND SP.MEASURE='RTF_SYS_RP' AND SP.QTY<>0), 0)                  AS NEW_PLAN,
       NVL((SELECT /*+ INDEX(SP (VERSION_NO DIVISION_ID)) */ COUNT(*)
              FROM SCM_MGR.DM_PLN_SALES_PLAN_C SP
             WHERE SP.VERSION_NO=W.NEW_VNO AND SP.DIVISION_ID='81'
               AND SP.MEASURE='RTF_SYS_RP' AND SP.QTY<>0
               AND SP.YYYYMMDD>=W.RESULT_TO AND SP.YYYYMMDD<=W.PLAN_TO), 0)    AS NEW_PLAN_IN_WINDOW,
       NVL((SELECT /*+ INDEX(SP (VERSION_NO DIVISION_ID)) */ COUNT(*)
              FROM SCM_MGR.DM_PLN_SALES_PLAN_C SP
             WHERE SP.VERSION_NO=W.OLD_VNO AND SP.DIVISION_ID='81'
               AND SP.MEASURE='RTF_SYS_RP' AND SP.QTY<>0), 0)                  AS OLD_PLAN,
       NVL((SELECT /*+ INDEX(SP (VERSION_NO DIVISION_ID)) */ COUNT(*)
              FROM SCM_MGR.DM_PLN_SALES_PLAN_RESULT_C SP
             WHERE SP.VERSION_NO=W.NEW_VNO AND SP.DIVISION_ID='81'
               AND SP.MEASURE='RTF_SYS_RP' AND SP.QTY<>0
               AND SP.YYYYMMDD>=W.RESULT_FROM AND SP.YYYYMMDD<W.RESULT_TO), 0) AS NEW_RESULT_IN_WINDOW,
       NVL((SELECT /*+ INDEX(SP (VERSION_NO DIVISION_ID)) */ COUNT(*)
              FROM SCM_MGR.DM_PLN_SALES_PLAN_RESULT_C SP
             WHERE SP.VERSION_NO=W.OLD_VNO AND SP.DIVISION_ID='81'
               AND SP.MEASURE='RTF_SYS_RP' AND SP.QTY<>0), 0)                  AS OLD_RESULT
FROM W;

PROMPT ===== D3. INNER JOIN 5축 분모 (81) — 0 인 축 = 그 메타 미이관/미적재가 원인 =====
SELECT 'SCM_MST_SITE(81,VALID=Y)' AS AXIS, COUNT(*) AS CNT FROM SCM_MGR.SCM_MST_SITE
 WHERE DIVISION_ID='81' AND VALID_YN='Y'
UNION ALL
SELECT 'SCM_MST_SITE_ITEM(81,VALID=Y)', COUNT(*) FROM SCM_MGR.SCM_MST_SITE_ITEM
 WHERE DIVISION_ID='81' AND VALID_YN='Y'
UNION ALL
SELECT 'DM_MST_ITEM_SINGLE_V(81,ITEM_TYPE=P)', COUNT(*) FROM SCM_MGR.DM_MST_ITEM_SINGLE_V
 WHERE DIVISION_ID='81' AND ITEM_TYPE='P'
UNION ALL
SELECT '룩업 SALES_TYPE_CODE(VALID=Y,SEG4<>FREE)', COUNT(*) FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE='SALES_TYPE_CODE' AND VALID_YN='Y' AND SEGMENT4<>'FREE'
UNION ALL
SELECT '룩업 END_CUSTOMER(SEG1=81)', COUNT(*) FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE='END_CUSTOMER' AND SEGMENT1='81';

PROMPT ===== D4. (구 D6 재설계) 조인 단계별 누적 생존수 — 원장 1스캔 + 행별 EXISTS 플래그 집계 1행 =====
PROMPT ===== 판독: STEP1 → STEP6 으로 갈수록 줄어든다. 처음 0 이 되는 STEP 의 조인축이 원인 =====
PROMPT ===== (STEP1=버전+날짜창 원장 / 2=+SITE / 3=+SALES_TYPE / 4=+SITE_ITEM / 5=+ITEM_V(P) / 6=+END_CUSTOMER) =====
WITH V AS (
  SELECT MAX(VERSION_NO) AS VNO, MAX(YYYYMMDD) AS VDT
  FROM SCM_MGR.DM_MST_VERSION WHERE DIVISION_ID='81' AND VERSION_TYPE='SP_W'),
W AS (
  SELECT V.VNO,
         TO_CHAR(SCM_MGR.FN_NEXT_DAY(V.VDT,'MON')-7,'YYYYMMDD')          AS RESULT_TO,
         TO_CHAR(SCM_MGR.FN_NEXT_DAY(V.VDT,'MON')-7+(52*7)-1,'YYYYMMDD') AS PLAN_TO
  FROM V),
BASE AS (
  SELECT /*+ MATERIALIZE INDEX(SP (VERSION_NO DIVISION_ID)) */
         SP.SCM_SITE_ID, SP.PROJECT_CODE, SP.ITEM_ID, SP.FCST_TYPE
  FROM SCM_MGR.DM_PLN_SALES_PLAN_C SP, W
  WHERE SP.VERSION_NO=W.VNO AND SP.DIVISION_ID='81'
    AND SP.MEASURE='RTF_SYS_RP' AND SP.QTY<>0
    AND SP.YYYYMMDD>=W.RESULT_TO AND SP.YYYYMMDD<=W.PLAN_TO),
FLAG AS (
  SELECT B.SCM_SITE_ID, B.PROJECT_CODE, B.ITEM_ID, B.FCST_TYPE,
         CASE WHEN EXISTS (SELECT 1 FROM SCM_MGR.SCM_MST_SITE MS
                            WHERE MS.DIVISION_ID='81' AND MS.SCM_SITE_ID=B.SCM_SITE_ID
                              AND MS.VALID_YN='Y') THEN 1 ELSE 0 END AS F_SITE,
         CASE WHEN EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL LUP
                            WHERE LUP.LOOKUP_TYPE='SALES_TYPE_CODE' AND LUP.VALID_YN='Y'
                              AND LUP.SEGMENT4<>'FREE' AND LUP.SEGMENT1=B.FCST_TYPE) THEN 1 ELSE 0 END AS F_STC,
         CASE WHEN EXISTS (SELECT 1 FROM SCM_MGR.SCM_MST_SITE_ITEM SI
                            WHERE SI.DIVISION_ID='81' AND SI.PROJECT_CODE=B.PROJECT_CODE
                              AND SI.SCM_SITE_ID=B.SCM_SITE_ID AND SI.ITEM_ID=B.ITEM_ID
                              AND SI.VALID_YN='Y') THEN 1 ELSE 0 END AS F_SI,
         CASE WHEN EXISTS (SELECT 1 FROM SCM_MGR.DM_MST_ITEM_SINGLE_V SV
                            WHERE SV.DIVISION_ID='81' AND SV.ITEM_ID=B.ITEM_ID
                              AND SV.ITEM_TYPE='P') THEN 1 ELSE 0 END AS F_ITEMV,
         CASE WHEN EXISTS (SELECT 1 FROM SCM_MGR.SCM_MST_SITE MS
                            INNER JOIN SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL LUP2
                               ON LUP2.LOOKUP_TYPE='END_CUSTOMER' AND LUP2.SEGMENT1='81'
                              AND LUP2.SEGMENT2=MS.END_CUSTOMER
                            WHERE MS.DIVISION_ID='81' AND MS.SCM_SITE_ID=B.SCM_SITE_ID
                              AND MS.VALID_YN='Y') THEN 1 ELSE 0 END AS F_EC
  FROM BASE B)
SELECT COUNT(*)                                                                AS STEP1_원장,
       NVL(SUM(F_SITE),0)                                                             AS STEP2_SITE,
       NVL(SUM(F_SITE*F_STC),0)                                                       AS STEP3_SALES_TYPE,
       NVL(SUM(F_SITE*F_STC*F_SI),0)                                                  AS STEP4_SITE_ITEM,
       NVL(SUM(F_SITE*F_STC*F_SI*F_ITEMV),0)                                          AS STEP5_ITEM_P,
       NVL(SUM(F_SITE*F_STC*F_SI*F_ITEMV*F_EC),0)                                     AS STEP6_END_CUSTOMER
FROM FLAG;

PROMPT ===== D5. (보조 — 느리면 생략 가능) SP 실행 로그: 최근 7일만 =====
SELECT * FROM (
  SELECT TO_CHAR(EVENT_DATE,'MM-DD HH24:MI') AS T, LOG_TYPE, LOG_MESSAGE, DESCRIPTION
  FROM   SCM_MGR.SCM_SYS_LOG_BATCH
  WHERE  EVENT_DATE >= TRUNC(SYSDATE) - 7
    AND  PROGRAM_NAME LIKE '%METAL_LINK_TEMPLATE%'
  ORDER BY EVENT_DATE DESC)
WHERE ROWNUM <= 10;

PROMPT ===== D6. (제2 용의 보강) RTF_SYS_RP 보유 SP_W 버전 상위 10 — 인덱스 선두(VERSION_NO LIKE) 경로 =====
SELECT * FROM (
  SELECT /*+ INDEX(SP (VERSION_NO DIVISION_ID)) */ 'PLAN_C' AS SRC, SP.VERSION_NO, COUNT(*) AS CNT
  FROM SCM_MGR.DM_PLN_SALES_PLAN_C SP
  WHERE SP.VERSION_NO LIKE 'SP\_W\_%' ESCAPE '\' AND SP.DIVISION_ID='81'
    AND SP.MEASURE='RTF_SYS_RP' AND SP.QTY<>0
  GROUP BY SP.VERSION_NO ORDER BY SP.VERSION_NO DESC)
WHERE ROWNUM <= 10;

SELECT * FROM (
  SELECT /*+ INDEX(SP (VERSION_NO DIVISION_ID)) */ 'RESULT_C' AS SRC, SP.VERSION_NO, COUNT(*) AS CNT
  FROM SCM_MGR.DM_PLN_SALES_PLAN_RESULT_C SP
  WHERE SP.VERSION_NO LIKE 'SP\_W\_%' ESCAPE '\' AND SP.DIVISION_ID='81'
    AND SP.MEASURE='RTF_SYS_RP' AND SP.QTY<>0
  GROUP BY SP.VERSION_NO ORDER BY SP.VERSION_NO DESC)
WHERE ROWNUM <= 10;
