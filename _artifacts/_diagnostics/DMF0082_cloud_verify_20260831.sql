-- §0. 오류 원문 — BE 가 남긴 실제 예외 텍스트 (가장 결정적. ORA-코드가 여기서 확정됩니다)
SELECT '§0 오류원문' AS SECTION, EXECUTE_TIME, SQL_ID, ELAPSED_MS, CREATED_BY,
       SUBSTR(EXCEPTION, 1, 500) AS EXCEPTION_TEXT
  FROM SCM_MGR.SCM_COM_SQL_LOG
 WHERE (UPPER(SQL_ID) LIKE '%DMF0082%' OR UPPER(SQL_TEXT) LIKE '%DMF0082%')
   AND EXCEPTION IS NOT NULL
   AND EXECUTE_TIME >= SYSDATE - 3
 ORDER BY EXECUTE_TIME DESC
 FETCH FIRST 20 ROWS ONLY;

-- §0-B. 오류 없는 최근 호출 (성공/실패 경계 시각 파악)
SELECT '§0B 최근호출' AS SECTION, EXECUTE_TIME, SQL_ID, ELAPSED_MS, RESULT_COUNT,
       CASE WHEN EXCEPTION IS NULL THEN 'OK' ELSE 'ERR' END AS ST
  FROM SCM_MGR.SCM_COM_SQL_LOG
 WHERE UPPER(SQL_ID) LIKE '%DMF0082%'
   AND EXECUTE_TIME >= SYSDATE - 3
 ORDER BY EXECUTE_TIME DESC
 FETCH FIRST 30 ROWS ONLY;

-- §1. PKG_DMF0082 상태 + 컴파일 오류 (INVALID 이면 여기서 종결)
SELECT '§1 객체상태' AS SECTION, OBJECT_NAME, OBJECT_TYPE, STATUS,
       TO_CHAR(LAST_DDL_TIME, 'YYYY-MM-DD HH24:MI:SS') AS LAST_DDL
  FROM ALL_OBJECTS
 WHERE OWNER = 'SCM_MGR'
   AND OBJECT_NAME IN ('PKG_DMF0082', 'PKG_DMF0003', 'PKG_SCM_USER_MNU')
 ORDER BY OBJECT_NAME, OBJECT_TYPE;

SELECT '§1 컴파일오류' AS SECTION, NAME, TYPE, LINE, POSITION, SUBSTR(TEXT, 1, 300) AS ERR
  FROM ALL_ERRORS
 WHERE OWNER = 'SCM_MGR'
   AND NAME LIKE 'PKG_DMF00%'
   AND ATTRIBUTE = 'ERROR'
 ORDER BY NAME, SEQUENCE;

-- §1-B. SCM_MGR 전체 INVALID (연쇄 무효화 파악)
SELECT '§1B INVALID전수' AS SECTION, OBJECT_TYPE, OBJECT_NAME,
       TO_CHAR(LAST_DDL_TIME, 'YYYY-MM-DD HH24:MI') AS LAST_DDL
  FROM ALL_OBJECTS
 WHERE OWNER = 'SCM_MGR' AND STATUS = 'INVALID'
 ORDER BY OBJECT_TYPE, OBJECT_NAME;

-- §2. 버전 드리프트 — 사내(정본) 최신 마커의 클라우드 존재 여부.
--     기대값: 사내는 아래 전부 CNT>=1. 클라우드에서 0 인 마커 = 그 이관분 미적용.
SELECT '§2 마커드리프트' AS SECTION, M.MARKER,
       (SELECT COUNT(*) FROM ALL_SOURCE S
         WHERE S.OWNER='SCM_MGR' AND S.NAME='PKG_DMF0082' AND S.TYPE='PACKAGE BODY'
           AND INSTR(S.TEXT, M.MARKER) > 0) AS CNT
  FROM (
        SELECT 'E20260831-QTYKEY'       AS MARKER FROM DUAL UNION ALL
        SELECT 'E20260826-SCPVMI'       FROM DUAL UNION ALL
        SELECT 'E20260826-CUSTSUBR'     FROM DUAL UNION ALL
        SELECT 'E20260826-CUSTSUBORPH'  FROM DUAL UNION ALL
        SELECT 'E20260826-AUTHVIEW'     FROM DUAL UNION ALL
        SELECT 'E20260826-ASINSREQ'     FROM DUAL UNION ALL
        SELECT 'E20260825-XLSPRJ'       FROM DUAL UNION ALL
        SELECT 'E20260825-SAVEPOPPERF'  FROM DUAL UNION ALL
        SELECT 'E20260825-CUSTSUB'      FROM DUAL UNION ALL
        SELECT 'E20260825-CURRNORM'     FROM DUAL UNION ALL
        SELECT 'E20260825-81AUTH'       FROM DUAL UNION ALL
        SELECT 'E20260822-LOCWEEKSUM'   FROM DUAL UNION ALL
        SELECT 'E20260822-KEYCOL'       FROM DUAL UNION ALL
        SELECT 'E20260820-XLSWEEKLY'    FROM DUAL
       ) M
 ORDER BY M.MARKER DESC;

