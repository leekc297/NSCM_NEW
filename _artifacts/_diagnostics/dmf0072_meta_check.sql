PROMPT === [6] MY_DIVISION SP 존재 여부 ===
SELECT OBJECT_NAME || '|' || OBJECT_TYPE || '|' || STATUS
  FROM ALL_OBJECTS WHERE OWNER='SCM_MGR' AND OBJECT_NAME LIKE '%MY_DIVISION%' ORDER BY OBJECT_NAME;

PROMPT === [7] DMF0072 USER_TEAM/EndCustomer/UserSite SP 존재 여부 (As-Is L154~186 의 SetChangeControl 대상) ===
SELECT OBJECT_NAME || '|' || OBJECT_TYPE || '|' || STATUS
  FROM ALL_OBJECTS WHERE OWNER='SCM_MGR'
   AND (   OBJECT_NAME LIKE '%USER_TEAM_BY_DIVISION%'
        OR OBJECT_NAME LIKE '%ENDCUSTOMER_BY_DIVISION%'
        OR OBJECT_NAME LIKE '%END_CUSTOMER_BY_DIV%'
        OR OBJECT_NAME LIKE '%USER_SITE_BY_ENDCUSTOMER%'
        OR OBJECT_NAME LIKE '%USER_SITE_BY_END_CUSTOMER%'
        OR OBJECT_NAME LIKE 'DMF0072%'
        OR OBJECT_NAME LIKE 'PKG_DMF0072%')
   ORDER BY OBJECT_NAME;

