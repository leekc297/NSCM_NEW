PROMPT === [9] DMF0008 GET_MY_DIVISION_LIST source body 일부 (CODE/NAME 컬럼명 확인) ===
SELECT LINE || ':' || REPLACE(TEXT, CHR(13), '')
  FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME LIKE '%MY_DIVISION%' AND LINE BETWEEN 1 AND 60
 ORDER BY NAME, LINE;

