PROMPT ################ [S1b] Redo 전송 대상 (Data Guard/스탠바이) — SYNC 전송이면 커밋마다 원격 대기 ################
SELECT INST_ID, DEST_ID, DEST_NAME, STATUS, TARGET, TRANSMIT_MODE, AFFIRM, DESTINATION,
       CASE WHEN TARGET='STANDBY' AND TRANSMIT_MODE LIKE 'SYNC%' THEN '⚠ SYNC 전송 — log file sync 지연 원인 후보'
            WHEN TARGET='STANDBY' THEN 'ASYNC 스탠바이 전송' ELSE '로컬 아카이브' END JUDGE
