PROMPT ################ [S5g] 1억 건 추가 시 예상 데이터량 (현재 통계 기준 단순 비례 — 참고치) ################
WITH T AS (SELECT OWNER, NUM_ROWS, BLOCKS, AVG_ROW_LEN FROM ALL_TABLES WHERE TABLE_NAME='SCP_ANL_SHIPMENT_PLAN_FG_C'),
     I AS (SELECT OWNER, SUM(LEAF_BLOCKS) LEAF FROM ALL_INDEXES WHERE TABLE_NAME='SCP_ANL_SHIPMENT_PLAN_FG_C' GROUP BY OWNER),
     B AS (SELECT TO_NUMBER(VALUE) BS FROM V$PARAMETER WHERE NAME='db_block_size')
SELECT T.OWNER, T.NUM_ROWS, T.AVG_ROW_LEN,
       ROUND(T.BLOCKS*B.BS/NULLIF(T.NUM_ROWS,0)) TBL_BYTES_PER_ROW,
       ROUND(I.LEAF*B.BS/NULLIF(T.NUM_ROWS,0)) IDX_BYTES_PER_ROW,
       ROUND(100000000*T.BLOCKS*B.BS/NULLIF(T.NUM_ROWS,0)/1024/1024/1024,1) ADD_TBL_GB_PER_1E8,
       ROUND(100000000*I.LEAF*B.BS/NULLIF(T.NUM_ROWS,0)/1024/1024/1024,1) ADD_IDX_GB_PER_1E8,
       '사내: 행당 테이블 약 234B + 인덱스 약 182B / 1억 건당 약 22GB + 17GB' CORP_NOTE
  FROM T LEFT JOIN I ON I.OWNER=T.OWNER CROSS JOIN B;

