PROMPT ################ [S2] ⭐ Redo 로그 구성 — 사내 2,048MB x 3그룹 x 1멤버 (1억 건 적재에 작음) ################
SELECT L.INST_ID, L.THREAD#, L.GROUP#, ROUND(L.BYTES/1024/1024) MB, L.MEMBERS, L.STATUS, L.ARCHIVED,
       (SELECT COUNT(*) FROM GV$LOG X WHERE X.INST_ID=L.INST_ID AND X.THREAD#=L.THREAD#) GROUPS_IN_THREAD
  FROM GV$LOG L
 ORDER BY L.INST_ID, L.THREAD#, L.GROUP#;

PROMPT ################ [S2b] 로그 스위치 시간대별 (최근 3일, 시간당 4회 이상만) — 15분 미만 간격이면 Redo 과소 ################
SELECT THREAD#, TO_CHAR(FIRST_TIME,'YYYY-MM-DD HH24') HR, COUNT(*) SWITCHES,
       ROUND(60/COUNT(*),1) AVG_GAP_MIN,
       CASE WHEN COUNT(*) >= 12 THEN '⚠ 5분 이하 간격 — checkpoint incomplete 위험 큼'
            WHEN COUNT(*) >= 4 THEN '⚠ 15분 이하 간격' ELSE '' END JUDGE
  FROM V$LOG_HISTORY
 WHERE FIRST_TIME > SYSDATE - 3
 GROUP BY THREAD#, TO_CHAR(FIRST_TIME,'YYYY-MM-DD HH24')
HAVING COUNT(*) >= 4
 ORDER BY 2 DESC, 1;

PROMPT ################ [S2c] 아카이브 생성량 일별 (최근 7일) — NOARCHIVELOG 면 0행 ################
SELECT TO_CHAR(TRUNC(COMPLETION_TIME),'YYYY-MM-DD') DAY, COUNT(DISTINCT THREAD#||'-'||SEQUENCE#) LOGS,
       ROUND(SUM(BLOCKS*BLOCK_SIZE)/1024/1024/1024,1) GB
  FROM V$ARCHIVED_LOG
 WHERE COMPLETION_TIME > SYSDATE - 7 AND DEST_ID = (SELECT MIN(DEST_ID) FROM V$ARCHIVED_LOG WHERE COMPLETION_TIME > SYSDATE - 7)
 GROUP BY TRUNC(COMPLETION_TIME)
 ORDER BY 1 DESC;

