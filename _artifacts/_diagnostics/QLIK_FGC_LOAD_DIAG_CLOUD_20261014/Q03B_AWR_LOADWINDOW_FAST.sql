PROMPT ################ [B4] ⭐ FG_C 테이블·인덱스 객체에서 대기한 세션의 이벤트 분포 (구간) ################
WITH R AS (SELECT MIN(SNAP_ID) S1, MAX(SNAP_ID) S2 FROM DBA_HIST_SNAPSHOT
            WHERE BEGIN_INTERVAL_TIME >= TIMESTAMP '2026-10-11 18:00:00' AND END_INTERVAL_TIME <= TIMESTAMP '2026-10-13 12:00:00'),
     O AS (SELECT OBJECT_ID, OBJECT_NAME FROM ALL_OBJECTS
            WHERE OWNER='SCM_MGR' AND (OBJECT_NAME='SCP_ANL_SHIPMENT_PLAN_FG_C'
               OR OBJECT_NAME IN (SELECT INDEX_NAME FROM ALL_INDEXES WHERE OWNER='SCM_MGR' AND TABLE_NAME='SCP_ANL_SHIPMENT_PLAN_FG_C')))
SELECT O.OBJECT_NAME, H.PROGRAM, H.SQL_OPNAME, NVL(H.EVENT,'ON CPU') EVENT, COUNT(*)*10 SEC,
       ROUND(100*RATIO_TO_REPORT(COUNT(*)) OVER (),1) PCT
  FROM DBA_HIST_ACTIVE_SESS_HISTORY H CROSS JOIN R JOIN O ON O.OBJECT_ID=H.CURRENT_OBJ#
 WHERE H.SNAP_ID BETWEEN R.S1 AND R.S2
