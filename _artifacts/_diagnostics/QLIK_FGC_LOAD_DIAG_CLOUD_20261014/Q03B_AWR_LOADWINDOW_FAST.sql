PROMPT ################ [B5] FG_C 대상 DML 문장 — 시간대별 처리 행수·1만 행당 초 (구간 SQLSTAT 기준) ################
PROMPT --  'SYS_DL_CURSOR' 문장 = direct path 적재 (행 수가 0 으로 집계될 수 있음 — 그 경우 [B1b] TBL_ALLOC_MB 로 진행량 판단)
WITH R AS (SELECT MIN(SNAP_ID) S1, MAX(SNAP_ID) S2 FROM DBA_HIST_SNAPSHOT
            WHERE BEGIN_INTERVAL_TIME >= TIMESTAMP '2026-10-11 18:00:00' AND END_INTERVAL_TIME <= TIMESTAMP '2026-10-13 12:00:00'),
     Q AS (SELECT DISTINCT Q.SQL_ID FROM DBA_HIST_SQLSTAT Q CROSS JOIN R WHERE Q.SNAP_ID BETWEEN R.S1 AND R.S2),
     T AS (SELECT X.SQL_ID, DBMS_LOB.SUBSTR(X.SQL_TEXT,100,1) SQL_HEAD FROM DBA_HIST_SQLTEXT X
            WHERE X.SQL_ID IN (SELECT SQL_ID FROM Q) AND X.COMMAND_TYPE IN (2,6,7,189)
              AND UPPER(DBMS_LOB.SUBSTR(X.SQL_TEXT,300,1)) LIKE '%SCP_ANL_SHIPMENT_PLAN_FG_C%'),
     SN AS (SELECT DISTINCT SNAP_ID, TRUNC(BEGIN_INTERVAL_TIME,'HH24') HR FROM DBA_HIST_SNAPSHOT CROSS JOIN R WHERE SNAP_ID BETWEEN R.S1 AND R.S2)
SELECT TO_CHAR(SN.HR,'MM-DD HH24') HR, Q.SQL_ID, SUM(Q.EXECUTIONS_DELTA) EX, SUM(Q.ROWS_PROCESSED_DELTA) RWS,
       ROUND(SUM(Q.ELAPSED_TIME_DELTA)/1e6,1) ELA_S, ROUND(SUM(Q.CPU_TIME_DELTA)/1e6,1) CPU_S, ROUND(SUM(Q.IOWAIT_DELTA)/1e6,1) IO_S,
       ROUND(SUM(Q.CCWAIT_DELTA)/1e6,1) CONC_S, ROUND(SUM(Q.CLWAIT_DELTA)/1e6,1) CLU_S, SUM(Q.PHYSICAL_READ_REQUESTS_DELTA) PHY_RD_REQ,
       ROUND(10000*SUM(Q.ELAPSED_TIME_DELTA)/1e6/NULLIF(SUM(Q.ROWS_PROCESSED_DELTA),0),2) SEC_PER_10K_ROWS,
       MAX(T.SQL_HEAD) SQL_HEAD
  FROM DBA_HIST_SQLSTAT Q CROSS JOIN R JOIN T ON T.SQL_ID=Q.SQL_ID JOIN SN ON SN.SNAP_ID=Q.SNAP_ID
 WHERE Q.SNAP_ID BETWEEN R.S1 AND R.S2
 GROUP BY SN.HR, Q.SQL_ID
 ORDER BY SN.HR, Q.SQL_ID;

PROMPT ################ [B6] 구간 Redo·쓰기·클러스터 대기 증가분 (스냅샷별 5초 이상, 상위 40) ################
WITH R AS (SELECT MIN(SNAP_ID) S1, MAX(SNAP_ID) S2 FROM DBA_HIST_SNAPSHOT
            WHERE BEGIN_INTERVAL_TIME >= TIMESTAMP '2026-10-11 18:00:00' AND END_INTERVAL_TIME <= TIMESTAMP '2026-10-13 12:00:00'),
     E AS (SELECT E.SNAP_ID, E.INSTANCE_NUMBER INST, E.EVENT_NAME,
                  E.TOTAL_WAITS - LAG(E.TOTAL_WAITS) OVER (PARTITION BY E.DBID, E.INSTANCE_NUMBER, E.EVENT_ID ORDER BY E.SNAP_ID) DW,
                  (E.TIME_WAITED_MICRO - LAG(E.TIME_WAITED_MICRO) OVER (PARTITION BY E.DBID, E.INSTANCE_NUMBER, E.EVENT_ID ORDER BY E.SNAP_ID))/1e6 DSEC
             FROM DBA_HIST_SYSTEM_EVENT E CROSS JOIN R
            WHERE E.SNAP_ID BETWEEN R.S1 - 1 AND R.S2
              AND E.EVENT_NAME IN ('log file switch (checkpoint incomplete)','log file switch completion','log file sync','log file parallel write',
                                   'log buffer space','db file parallel write','db file sequential read','cell single block physical read',
                                   'direct path write','free buffer waits','enq: TX - index contention','enq: HW - contention',
                                   'gc buffer busy acquire','gc buffer busy release','gc current block busy','resmgr:cpu quantum'))
SELECT E.SNAP_ID, (SELECT TO_CHAR(MIN(S.BEGIN_INTERVAL_TIME),'MM-DD HH24:MI') FROM DBA_HIST_SNAPSHOT S WHERE S.SNAP_ID=E.SNAP_ID) SNAP_BEGIN,
       E.INST, E.EVENT_NAME EVENT, E.DW WAITS, ROUND(E.DSEC,1) SEC, ROUND(1000*E.DSEC/NULLIF(E.DW,0),2) AVG_MS
  FROM E CROSS JOIN R
 WHERE E.SNAP_ID BETWEEN R.S1 AND R.S2 AND E.DSEC >= 5
 ORDER BY E.DSEC DESC
 FETCH FIRST 40 ROWS ONLY;

PROMPT ################ [B7] 구간 Redo 생성량 — 스레드별 시간당 로그 스위치 x 로그 크기 ################
SELECT H.THREAD#, TO_CHAR(TRUNC(H.FIRST_TIME,'HH24'),'MM-DD HH24') HR, COUNT(*) SWITCHES,
       ROUND(COUNT(*)*(SELECT MAX(BYTES) FROM V$LOG)/1024/1024/1024,1) REDO_GB_APPROX
  FROM V$LOG_HISTORY H
 WHERE H.FIRST_TIME >= TIMESTAMP '2026-10-11 18:00:00' AND H.FIRST_TIME < TIMESTAMP '2026-10-13 12:00:00'
 GROUP BY H.THREAD#, TRUNC(H.FIRST_TIME,'HH24')
 ORDER BY 2, 1;

