PROMPT ################ [B0] 구간 스냅샷 범위 (2026-10-11 18:00 ~ 2026-10-13 12:00) ################
SELECT MIN(SNAP_ID) SNAP_FROM, MAX(SNAP_ID) SNAP_TO, COUNT(DISTINCT SNAP_ID) SNAPS,
       TO_CHAR(MIN(BEGIN_INTERVAL_TIME),'YYYY-MM-DD HH24:MI') T_FROM, TO_CHAR(MAX(END_INTERVAL_TIME),'YYYY-MM-DD HH24:MI') T_TO
  FROM DBA_HIST_SNAPSHOT
 WHERE BEGIN_INTERVAL_TIME >= TIMESTAMP '2026-10-11 18:00:00' AND END_INTERVAL_TIME <= TIMESTAMP '2026-10-13 12:00:00';

PROMPT ################ [B1] ⭐⭐ 세그먼트별 작업량 (구간 합계) — 테이블·PK·IX01·IX02 물리 읽기/쓰기/블록 변경 ################
PROMPT --  INSERT 는 원래 테이블을 "읽지" 않는다. PK/IX 의 PHY_READS 가 크면 = 인덱스 리프 블록을 디스크에서 읽어 오며 INSERT (캐시 부족)
WITH R AS (SELECT MIN(SNAP_ID) S1, MAX(SNAP_ID) S2 FROM DBA_HIST_SNAPSHOT
            WHERE BEGIN_INTERVAL_TIME >= TIMESTAMP '2026-10-11 18:00:00' AND END_INTERVAL_TIME <= TIMESTAMP '2026-10-13 12:00:00'),
     O AS (SELECT OBJECT_ID, OBJECT_NAME, OBJECT_TYPE FROM ALL_OBJECTS
            WHERE OWNER='SCM_MGR' AND (OBJECT_NAME='SCP_ANL_SHIPMENT_PLAN_FG_C'
               OR OBJECT_NAME IN (SELECT INDEX_NAME FROM ALL_INDEXES WHERE OWNER='SCM_MGR' AND TABLE_NAME='SCP_ANL_SHIPMENT_PLAN_FG_C')))
SELECT O.OBJECT_NAME, O.OBJECT_TYPE,
       SUM(S.PHYSICAL_READS_DELTA) PHY_READS, SUM(S.PHYSICAL_WRITES_DELTA) PHY_WRITES,
       SUM(S.PHYSICAL_WRITES_DIRECT_DELTA) DIRECT_WRITES, SUM(S.DB_BLOCK_CHANGES_DELTA) BLOCK_CHANGES,
       SUM(S.LOGICAL_READS_DELTA) LOGICAL_READS, ROUND(SUM(S.SPACE_ALLOCATED_DELTA)/1024/1024/1024,2) ALLOC_GB,
       SUM(S.BUFFER_BUSY_WAITS_DELTA) BUF_BUSY, SUM(S.ITL_WAITS_DELTA) ITL_WAITS, SUM(S.GC_BUFFER_BUSY_DELTA) GC_BUF_BUSY
  FROM DBA_HIST_SEG_STAT S CROSS JOIN R JOIN O ON O.OBJECT_ID=S.OBJ#
 WHERE S.SNAP_ID BETWEEN R.S1 AND R.S2
 GROUP BY O.OBJECT_NAME, O.OBJECT_TYPE
 ORDER BY PHY_READS DESC NULLS LAST;

PROMPT ################ [B1b] 세그먼트별 시간대 추이 — 테이블이 커질수록 인덱스 물리 읽기가 늘었는지 ################
WITH R AS (SELECT MIN(SNAP_ID) S1, MAX(SNAP_ID) S2 FROM DBA_HIST_SNAPSHOT
            WHERE BEGIN_INTERVAL_TIME >= TIMESTAMP '2026-10-11 18:00:00' AND END_INTERVAL_TIME <= TIMESTAMP '2026-10-13 12:00:00'),
     O AS (SELECT OBJECT_ID, OBJECT_NAME FROM ALL_OBJECTS
            WHERE OWNER='SCM_MGR' AND (OBJECT_NAME='SCP_ANL_SHIPMENT_PLAN_FG_C'
               OR OBJECT_NAME IN (SELECT INDEX_NAME FROM ALL_INDEXES WHERE OWNER='SCM_MGR' AND TABLE_NAME='SCP_ANL_SHIPMENT_PLAN_FG_C'))),
     SN AS (SELECT DISTINCT SNAP_ID, TRUNC(BEGIN_INTERVAL_TIME,'HH24') HR FROM DBA_HIST_SNAPSHOT CROSS JOIN R WHERE SNAP_ID BETWEEN R.S1 AND R.S2)
SELECT TO_CHAR(SN.HR,'MM-DD HH24') HR,
       SUM(CASE WHEN O.OBJECT_NAME='SCP_ANL_SHIPMENT_PLAN_FG_C' THEN S.DB_BLOCK_CHANGES_DELTA END) TBL_BLK_CHG,
       SUM(CASE WHEN O.OBJECT_NAME='SCP_ANL_SHIPMENT_PLAN_FG_C' THEN S.PHYSICAL_WRITES_DIRECT_DELTA END) TBL_DIRECT_WR,
       ROUND(SUM(CASE WHEN O.OBJECT_NAME='SCP_ANL_SHIPMENT_PLAN_FG_C' THEN S.SPACE_ALLOCATED_DELTA END)/1024/1024) TBL_ALLOC_MB,
       SUM(CASE WHEN O.OBJECT_NAME LIKE 'PK%' THEN S.PHYSICAL_READS_DELTA END) PK_PHY_RD,
       SUM(CASE WHEN O.OBJECT_NAME LIKE 'IX01%' THEN S.PHYSICAL_READS_DELTA END) IX01_PHY_RD,
       SUM(CASE WHEN O.OBJECT_NAME LIKE 'IX02%' THEN S.PHYSICAL_READS_DELTA END) IX02_PHY_RD,
       SUM(CASE WHEN O.OBJECT_NAME<>'SCP_ANL_SHIPMENT_PLAN_FG_C' THEN S.DB_BLOCK_CHANGES_DELTA END) IDX_BLK_CHG
  FROM DBA_HIST_SEG_STAT S CROSS JOIN R JOIN O ON O.OBJECT_ID=S.OBJ# JOIN SN ON SN.SNAP_ID=S.SNAP_ID
 WHERE S.SNAP_ID BETWEEN R.S1 AND R.S2
 GROUP BY SN.HR
 ORDER BY SN.HR;

PROMPT ################ [B2] 구간 DB 전체 세그먼트 상위 15 (블록 변경) — FG_C 외에 무엇이 Redo 를 만들었나 ################
WITH R AS (SELECT MIN(SNAP_ID) S1, MAX(SNAP_ID) S2 FROM DBA_HIST_SNAPSHOT
            WHERE BEGIN_INTERVAL_TIME >= TIMESTAMP '2026-10-11 18:00:00' AND END_INTERVAL_TIME <= TIMESTAMP '2026-10-13 12:00:00')
SELECT NVL(O.OWNER||'.'||O.OBJECT_NAME, '(obj# '||S.OBJ#||')') OBJECT_NAME, O.OBJECT_TYPE,
       SUM(S.DB_BLOCK_CHANGES_DELTA) BLOCK_CHANGES, SUM(S.PHYSICAL_READS_DELTA) PHY_READS, SUM(S.PHYSICAL_WRITES_DELTA) PHY_WRITES,
       ROUND(100*RATIO_TO_REPORT(SUM(S.DB_BLOCK_CHANGES_DELTA)) OVER (),1) PCT_CHG
  FROM DBA_HIST_SEG_STAT S CROSS JOIN R LEFT JOIN ALL_OBJECTS O ON O.OBJECT_ID=S.OBJ#
 WHERE S.SNAP_ID BETWEEN R.S1 AND R.S2
 GROUP BY NVL(O.OWNER||'.'||O.OBJECT_NAME, '(obj# '||S.OBJ#||')'), O.OBJECT_TYPE
 ORDER BY BLOCK_CHANGES DESC NULLS LAST
 FETCH FIRST 15 ROWS ONLY;

PROMPT ################ [B3] 구간 활성 프로그램 상위 15 — Qlik 프로그램명 확인 ################
WITH R AS (SELECT MIN(SNAP_ID) S1, MAX(SNAP_ID) S2 FROM DBA_HIST_SNAPSHOT
            WHERE BEGIN_INTERVAL_TIME >= TIMESTAMP '2026-10-11 18:00:00' AND END_INTERVAL_TIME <= TIMESTAMP '2026-10-13 12:00:00')
