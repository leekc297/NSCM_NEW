PROMPT ################ [H0] 실행 시각 / AWR 보관 범위 ################
SELECT SYS_CONTEXT('USERENV','DB_NAME') DB_NAME, SYS_CONTEXT('USERENV','CON_NAME') CON_NAME,
       TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI:SS') NOW FROM DUAL;
SELECT TO_CHAR(MIN(BEGIN_INTERVAL_TIME),'YYYY-MM-DD HH24:MI') AWR_FROM, TO_CHAR(MAX(END_INTERVAL_TIME),'YYYY-MM-DD HH24:MI') AWR_TO,
       COUNT(*) SNAPS
  FROM DBA_HIST_SNAPSHOT;

PROMPT ################ [H1] ⭐ 최근 4시간 활성 프로그램 상위 — Qlik 프로그램명 식별용 (이름 패턴 무관 전체) ################
SELECT A.PROGRAM, A.MODULE, A.MACHINE, COUNT(*) SAMPLES, TO_CHAR(MIN(A.SAMPLE_TIME),'MM-DD HH24:MI') FIRST_SEEN,
       TO_CHAR(MAX(A.SAMPLE_TIME),'MM-DD HH24:MI') LAST_SEEN
  FROM GV$ACTIVE_SESSION_HISTORY A
 WHERE A.SAMPLE_TIME > SYSTIMESTAMP - INTERVAL '240' MINUTE AND A.SESSION_TYPE='FOREGROUND'
 GROUP BY A.PROGRAM, A.MODULE, A.MACHINE
 ORDER BY SAMPLES DESC
 FETCH FIRST 20 ROWS ONLY;

PROMPT ################ [H2] 최근 4시간 — 대상 테이블 적재 세션 대기 분포 (Qlik 이름 패턴 / 테이블·인덱스 객체 / 테이블 DML SQL) ################
WITH OBJ AS (SELECT OBJECT_ID FROM ALL_OBJECTS WHERE OBJECT_NAME='SCP_ANL_SHIPMENT_PLAN_FG_C' AND OBJECT_TYPE='TABLE'
             UNION ALL
             SELECT O.OBJECT_ID FROM ALL_OBJECTS O JOIN ALL_INDEXES I ON I.OWNER=O.OWNER AND I.INDEX_NAME=O.OBJECT_NAME
              WHERE I.TABLE_NAME='SCP_ANL_SHIPMENT_PLAN_FG_C' AND O.OBJECT_TYPE='INDEX'),
     SQ  AS (SELECT DISTINCT SQL_ID FROM GV$SQL WHERE REGEXP_LIKE(SQL_TEXT, '^\s*(INSERT|UPDATE|DELETE|MERGE)\s+(/\*.*?\*/\s*)?(INTO\s+|FROM\s+)?(RELATIONAL\s*\(\s*)?("?[A-Z0-9_$#]+"?\.)?"?SCP_ANL_SHIPMENT_PLAN_FG_C"?', 'in') AND COMMAND_TYPE IN (2,6,7,189))
SELECT A.PROGRAM, A.SQL_ID, A.SQL_OPNAME, NVL(A.EVENT,'ON CPU') EVENT, NVL(A.WAIT_CLASS,'CPU') WAIT_CLASS, COUNT(*) SAMPLES,
       ROUND(100*RATIO_TO_REPORT(COUNT(*)) OVER (),1) PCT,
       TO_CHAR(MIN(A.SAMPLE_TIME),'MM-DD HH24:MI') FIRST_SEEN, TO_CHAR(MAX(A.SAMPLE_TIME),'MM-DD HH24:MI') LAST_SEEN
  FROM GV$ACTIVE_SESSION_HISTORY A
 WHERE A.SAMPLE_TIME > SYSTIMESTAMP - INTERVAL '240' MINUTE
   AND ( A.SQL_ID IN (SELECT SQL_ID FROM SQ)
      OR A.CURRENT_OBJ# IN (SELECT OBJECT_ID FROM OBJ)
      OR LOWER(A.PROGRAM||' '||A.MODULE) LIKE '%repctl%' OR LOWER(A.PROGRAM||' '||A.MODULE) LIKE '%replicat%'
      OR LOWER(A.PROGRAM||' '||A.MODULE) LIKE '%qlik%' OR LOWER(A.PROGRAM||' '||A.MODULE) LIKE '%attunity%'
      OR LOWER(A.PROGRAM||' '||A.MODULE) LIKE '%attrep%' )
 GROUP BY A.PROGRAM, A.SQL_ID, A.SQL_OPNAME, NVL(A.EVENT,'ON CPU'), NVL(A.WAIT_CLASS,'CPU')
 ORDER BY SAMPLES DESC
 FETCH FIRST 40 ROWS ONLY;

PROMPT ################ [H3] AWR 8일 — 시간대별 활성 프로그램 상위 (Qlik 적재 시간대 식별) ################
SELECT TO_CHAR(H.SAMPLE_TIME,'YYYY-MM-DD HH24') HR, H.PROGRAM, H.MACHINE, COUNT(*)*10 ACTIVE_SEC
  FROM DBA_HIST_ACTIVE_SESS_HISTORY H
 WHERE H.SAMPLE_TIME > SYSTIMESTAMP - INTERVAL '8' DAY AND H.SESSION_TYPE='FOREGROUND'
 GROUP BY TO_CHAR(H.SAMPLE_TIME,'YYYY-MM-DD HH24'), H.PROGRAM, H.MACHINE
HAVING COUNT(*) >= 30
 ORDER BY 1 DESC, ACTIVE_SEC DESC
 FETCH FIRST 150 ROWS ONLY;

PROMPT ################ [H4] ⭐ AWR 8일 — 대상 테이블 적재 세션 대기 분포 (시간대별) ################
WITH OBJ AS (SELECT OBJECT_ID FROM ALL_OBJECTS WHERE OBJECT_NAME='SCP_ANL_SHIPMENT_PLAN_FG_C' AND OBJECT_TYPE='TABLE'
             UNION ALL
             SELECT O.OBJECT_ID FROM ALL_OBJECTS O JOIN ALL_INDEXES I ON I.OWNER=O.OWNER AND I.INDEX_NAME=O.OBJECT_NAME
              WHERE I.TABLE_NAME='SCP_ANL_SHIPMENT_PLAN_FG_C' AND O.OBJECT_TYPE='INDEX'),
     SQ  AS (SELECT DISTINCT SQL_ID FROM DBA_HIST_SQLTEXT WHERE REGEXP_LIKE(SQL_TEXT, '^\s*(INSERT|UPDATE|DELETE|MERGE)\s+(/\*.*?\*/\s*)?(INTO\s+|FROM\s+)?(RELATIONAL\s*\(\s*)?("?[A-Z0-9_$#]+"?\.)?"?SCP_ANL_SHIPMENT_PLAN_FG_C"?', 'in')
                                                          AND COMMAND_TYPE IN (2,6,7,189))
SELECT TO_CHAR(H.SAMPLE_TIME,'YYYY-MM-DD HH24') HR, H.PROGRAM, H.SQL_OPNAME, NVL(H.EVENT,'ON CPU') EVENT,
       NVL(H.WAIT_CLASS,'CPU') WAIT_CLASS, COUNT(*)*10 SEC
  FROM DBA_HIST_ACTIVE_SESS_HISTORY H
 WHERE H.SAMPLE_TIME > SYSTIMESTAMP - INTERVAL '8' DAY
   AND ( H.SQL_ID IN (SELECT SQL_ID FROM SQ)
      OR H.CURRENT_OBJ# IN (SELECT OBJECT_ID FROM OBJ)
      OR LOWER(H.PROGRAM||' '||H.MODULE) LIKE '%repctl%' OR LOWER(H.PROGRAM||' '||H.MODULE) LIKE '%replicat%'
      OR LOWER(H.PROGRAM||' '||H.MODULE) LIKE '%qlik%' OR LOWER(H.PROGRAM||' '||H.MODULE) LIKE '%attunity%'
      OR LOWER(H.PROGRAM||' '||H.MODULE) LIKE '%attrep%' )
 GROUP BY TO_CHAR(H.SAMPLE_TIME,'YYYY-MM-DD HH24'), H.PROGRAM, H.SQL_OPNAME, NVL(H.EVENT,'ON CPU'), NVL(H.WAIT_CLASS,'CPU')
 ORDER BY 1 DESC, SEC DESC;

PROMPT ################ [H5] AWR 8일 — 대상 테이블 DML 문장 실적 (일별) — 실행당 행수·1만 행당 초 ################
PROMPT --  'INSERT /*+ SYS_DL_CURSOR */ INTO RELATIONAL(...)' = direct path 적재(OCI·SQL*Loader·Data Pump) — 실행/행 수가 0 으로 집계될 수 있음
WITH SQ AS (SELECT SQL_ID, DBMS_LOB.SUBSTR(SQL_TEXT,120,1) SQL_HEAD FROM DBA_HIST_SQLTEXT
             WHERE REGEXP_LIKE(SQL_TEXT, '^\s*(INSERT|UPDATE|DELETE|MERGE)\s+(/\*.*?\*/\s*)?(INTO\s+|FROM\s+)?(RELATIONAL\s*\(\s*)?("?[A-Z0-9_$#]+"?\.)?"?SCP_ANL_SHIPMENT_PLAN_FG_C"?', 'in') AND COMMAND_TYPE IN (2,6,7,189)),
     ST AS (SELECT Q.SQL_ID, TRUNC(S.BEGIN_INTERVAL_TIME) DAY, SUM(Q.EXECUTIONS_DELTA) EX, SUM(Q.ROWS_PROCESSED_DELTA) RWS,
                   SUM(Q.ELAPSED_TIME_DELTA)/1e6 ELA, SUM(Q.CPU_TIME_DELTA)/1e6 CPU, SUM(Q.IOWAIT_DELTA)/1e6 IO,
                   SUM(Q.CCWAIT_DELTA)/1e6 CC, SUM(Q.APWAIT_DELTA)/1e6 AP, SUM(Q.DIRECT_WRITES_DELTA) DW
              FROM DBA_HIST_SQLSTAT Q JOIN DBA_HIST_SNAPSHOT S ON S.SNAP_ID=Q.SNAP_ID AND S.DBID=Q.DBID AND S.INSTANCE_NUMBER=Q.INSTANCE_NUMBER
             WHERE Q.SQL_ID IN (SELECT SQL_ID FROM SQ) AND S.BEGIN_INTERVAL_TIME > SYSTIMESTAMP - INTERVAL '8' DAY
             GROUP BY Q.SQL_ID, TRUNC(S.BEGIN_INTERVAL_TIME))
SELECT TO_CHAR(ST.DAY,'YYYY-MM-DD') DAY, ST.SQL_ID, ST.EX, ST.RWS, ROUND(ST.RWS/NULLIF(ST.EX,0)) ROWS_PER_EX,
       ROUND(ST.ELA,1) ELA_S, ROUND(ST.CPU,1) CPU_S, ROUND(ST.IO,1) IO_S, ROUND(ST.CC,1) CONC_S, ROUND(ST.AP,1) APP_S, ST.DW,
       ROUND(10000*ST.ELA/NULLIF(ST.RWS,0),2) SEC_PER_10K_ROWS, SQ.SQL_HEAD
  FROM ST JOIN SQ ON SQ.SQL_ID=ST.SQL_ID
 ORDER BY ST.DAY DESC, ST.ELA DESC;

PROMPT ################ [H6] AWR 8일 — 스냅샷별 Redo/초·CPU·쓰기량 (Redo 상위 30구간, SRC=CDB/PDB 뷰) ################
WITH M AS (SELECT 'SYSMETRIC' SRC, BEGIN_TIME, METRIC_NAME, AVERAGE, MAXVAL FROM DBA_HIST_SYSMETRIC_SUMMARY
            WHERE BEGIN_TIME > SYSDATE - 8
              AND METRIC_NAME IN ('Redo Generated Per Sec','Host CPU Utilization (%)','Physical Write Total Bytes Per Sec','Average Active Sessions')
           UNION ALL
           SELECT 'CON_SYSMETRIC', BEGIN_TIME, METRIC_NAME, AVERAGE, MAXVAL FROM DBA_HIST_CON_SYSMETRIC_SUMM
            WHERE BEGIN_TIME > SYSDATE - 8
              AND METRIC_NAME IN ('Redo Generated Per Sec','Host CPU Utilization (%)','Physical Write Total Bytes Per Sec','Average Active Sessions'))
SELECT SRC, TO_CHAR(BEGIN_TIME,'YYYY-MM-DD HH24:MI') BEGIN_TIME,
       ROUND(MAX(DECODE(METRIC_NAME,'Redo Generated Per Sec',AVERAGE))/1024/1024,2) REDO_MB_PER_SEC,
       ROUND(MAX(DECODE(METRIC_NAME,'Redo Generated Per Sec',MAXVAL))/1024/1024,2) REDO_MB_PER_SEC_MAX,
       ROUND(MAX(DECODE(METRIC_NAME,'Host CPU Utilization (%)',AVERAGE)),1) HOST_CPU_PCT,
       ROUND(MAX(DECODE(METRIC_NAME,'Physical Write Total Bytes Per Sec',AVERAGE))/1024/1024,1) WRITE_MB_PER_SEC,
       ROUND(MAX(DECODE(METRIC_NAME,'Average Active Sessions',AVERAGE)),1) AAS
  FROM M
 GROUP BY SRC, BEGIN_TIME
 ORDER BY REDO_MB_PER_SEC DESC NULLS LAST
 FETCH FIRST 30 ROWS ONLY;

PROMPT ################ [H7] ⭐ AWR 8일 — 스냅샷별 Redo·쓰기 관련 대기 증가분 (log file switch 정지 시간 확인) ################
WITH E AS (SELECT S.BEGIN_INTERVAL_TIME BT, E.INSTANCE_NUMBER INST, E.EVENT_NAME,
                  E.TOTAL_WAITS - LAG(E.TOTAL_WAITS) OVER (PARTITION BY E.DBID, E.INSTANCE_NUMBER, E.EVENT_ID ORDER BY E.SNAP_ID) DW,
                  (E.TIME_WAITED_MICRO - LAG(E.TIME_WAITED_MICRO) OVER (PARTITION BY E.DBID, E.INSTANCE_NUMBER, E.EVENT_ID ORDER BY E.SNAP_ID))/1e6 DSEC
             FROM DBA_HIST_SYSTEM_EVENT E JOIN DBA_HIST_SNAPSHOT S ON S.SNAP_ID=E.SNAP_ID AND S.DBID=E.DBID AND S.INSTANCE_NUMBER=E.INSTANCE_NUMBER
            WHERE S.BEGIN_INTERVAL_TIME > SYSTIMESTAMP - INTERVAL '8' DAY
              AND E.EVENT_NAME IN ('log file switch (checkpoint incomplete)','log file switch completion','log file switch (archiving needed)',
                                   'log file sync','log file parallel write','log buffer space','db file parallel write','direct path write',
                                   'free buffer waits','enq: TX - index contention','enq: HW - contention','enq: TM - contention','resmgr:cpu quantum'))
SELECT TO_CHAR(BT,'YYYY-MM-DD HH24:MI') SNAP_BEGIN, INST, EVENT_NAME EVENT, DW WAITS, ROUND(DSEC,1) SEC,
       ROUND(1000*DSEC/NULLIF(DW,0),2) AVG_MS
  FROM E
 WHERE DSEC >= 5
 ORDER BY DSEC DESC
 FETCH FIRST 40 ROWS ONLY;

PROMPT ################ [H8] 로그 스위치 시간대별 (8일, 시간당 4회 이상) ################
SELECT THREAD#, TO_CHAR(FIRST_TIME,'YYYY-MM-DD HH24') HR, COUNT(*) SWITCHES, ROUND(60/COUNT(*),1) AVG_GAP_MIN
  FROM V$LOG_HISTORY
 WHERE FIRST_TIME > SYSDATE - 8
 GROUP BY THREAD#, TO_CHAR(FIRST_TIME,'YYYY-MM-DD HH24')
HAVING COUNT(*) >= 4
 ORDER BY 2 DESC, 1;

