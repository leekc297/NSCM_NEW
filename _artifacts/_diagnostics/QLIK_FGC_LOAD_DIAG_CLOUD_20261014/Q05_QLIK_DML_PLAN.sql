PROMPT ################ [P5] DELETE 0zfz07pka9ysv 실행 시 대기 분포 (AWR ASH, 계획 라인별) ################
SELECT H.SQL_PLAN_HASH_VALUE PHV, H.SQL_PLAN_LINE_ID LINE, H.SQL_PLAN_OPERATION||' '||H.SQL_PLAN_OPTIONS OP,
       NVL(H.EVENT,'ON CPU') EVENT, COUNT(*)*10 SEC, ROUND(100*RATIO_TO_REPORT(COUNT(*)) OVER (),1) PCT
  FROM DBA_HIST_ACTIVE_SESS_HISTORY H
 WHERE H.SQL_ID='0zfz07pka9ysv'
   AND H.SNAP_ID >= (SELECT MIN(SNAP_ID) FROM DBA_HIST_SQLSTAT WHERE SQL_ID='0zfz07pka9ysv')
 GROUP BY H.SQL_PLAN_HASH_VALUE, H.SQL_PLAN_LINE_ID, H.SQL_PLAN_OPERATION||' '||H.SQL_PLAN_OPTIONS, NVL(H.EVENT,'ON CPU')
 ORDER BY SEC DESC
 FETCH FIRST 20 ROWS ONLY;

PROMPT ################ [P6] ⭐ Qlik 변경분 테이블(attrep_changes*) 컬럼 형식 — FG_C 컬럼과 형식이 다르면 암묵 형변환으로 인덱스 미사용 ################
SELECT C.TABLE_NAME, C.COLUMN_ID, C.COLUMN_NAME, C.DATA_TYPE, C.DATA_LENGTH, C.NULLABLE
  FROM ALL_TAB_COLUMNS C
 WHERE C.OWNER='SCM_MGR'
   AND C.TABLE_NAME = (SELECT MIN(TABLE_NAME) FROM ALL_TABLES WHERE OWNER='SCM_MGR' AND TABLE_NAME LIKE 'attrep_changes%')
 ORDER BY C.COLUMN_ID;
SELECT T.TABLE_NAME, T.NUM_ROWS, TO_CHAR(T.LAST_ANALYZED,'MM-DD HH24:MI') LAST_ANALYZED, T.TEMPORARY, T.LOGGING,
       (SELECT COUNT(*) FROM ALL_INDEXES I WHERE I.OWNER=T.OWNER AND I.TABLE_NAME=T.TABLE_NAME) IDX_CNT,
       (SELECT COUNT(*) FROM ALL_TAB_COLUMNS C WHERE C.OWNER=T.OWNER AND C.TABLE_NAME=T.TABLE_NAME) COL_CNT
  FROM ALL_TABLES T
 WHERE T.OWNER='SCM_MGR' AND T.TABLE_NAME LIKE 'attrep_changes%'
 ORDER BY T.TABLE_NAME;

PROMPT ################ [P7] ⭐ FG_C 변경 이력 테이블(__ct, Qlik Store Changes) — 크기·인덱스 (CDC 마다 같은 양을 추가 적재) ################
SELECT T.TABLE_NAME, T.NUM_ROWS, T.BLOCKS, TO_CHAR(T.LAST_ANALYZED,'MM-DD HH24:MI') LAST_ANALYZED, T.PARTITIONED,
       (SELECT ROUND(SUM(S.BYTES)/1024/1024/1024,2) FROM USER_SEGMENTS S WHERE S.SEGMENT_NAME=T.TABLE_NAME) TBL_GB,
       (SELECT COUNT(*) FROM ALL_INDEXES I WHERE I.OWNER=T.OWNER AND I.TABLE_NAME=T.TABLE_NAME) IDX_CNT
  FROM ALL_TABLES T
 WHERE T.OWNER='SCM_MGR' AND T.TABLE_NAME LIKE 'SCP_ANL_SHIPMENT_PLAN_FG_C%'
 ORDER BY T.TABLE_NAME;

PROMPT ################ [P8] FG_C 컬럼 형식 (P6 과 대조용) ################
SELECT COLUMN_ID, COLUMN_NAME, DATA_TYPE, DATA_LENGTH, NULLABLE
  FROM ALL_TAB_COLUMNS
 WHERE OWNER='SCM_MGR' AND TABLE_NAME='SCP_ANL_SHIPMENT_PLAN_FG_C' AND COLUMN_ID <= 16
