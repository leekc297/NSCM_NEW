PROMPT ################ [P1] ⭐ 문장 원문 (AWR) — DELETE 0zfz07pka9ysv / INSERT fr8a4mu383uwp ################
SELECT SQL_ID, DBMS_LOB.GETLENGTH(SQL_TEXT) LEN,
       DBMS_LOB.SUBSTR(SQL_TEXT,2000,1) TXT_1, DBMS_LOB.SUBSTR(SQL_TEXT,2000,2001) TXT_2, DBMS_LOB.SUBSTR(SQL_TEXT,2000,4001) TXT_3
  FROM DBA_HIST_SQLTEXT
 WHERE SQL_ID IN ('0zfz07pka9ysv','fr8a4mu383uwp','drxd1y8d336nr','gn59mxj6ngncj');

PROMPT ################ [P2] ⭐ 계획별 실적 (AWR 전체 보관분) — 같은 문장이 계획에 따라 시간이 달랐는지 ################
SELECT Q.SQL_ID, Q.PLAN_HASH_VALUE PHV, SUM(Q.EXECUTIONS_DELTA) EX, SUM(Q.ROWS_PROCESSED_DELTA) RWS,
       ROUND(SUM(Q.ELAPSED_TIME_DELTA)/1e6) ELA_S, ROUND(SUM(Q.CPU_TIME_DELTA)/1e6) CPU_S, ROUND(SUM(Q.IOWAIT_DELTA)/1e6) IO_S,
       SUM(Q.BUFFER_GETS_DELTA) BG, SUM(Q.PHYSICAL_READ_REQUESTS_DELTA) PHY_RD_REQ,
       ROUND(SUM(Q.ELAPSED_TIME_DELTA)/1e6/NULLIF(SUM(Q.EXECUTIONS_DELTA),0),1) SEC_PER_EX,
       TO_CHAR(MIN(S.BEGIN_INTERVAL_TIME),'MM-DD HH24:MI') FIRST_SEEN, TO_CHAR(MAX(S.END_INTERVAL_TIME),'MM-DD HH24:MI') LAST_SEEN
  FROM DBA_HIST_SQLSTAT Q JOIN DBA_HIST_SNAPSHOT S ON S.SNAP_ID=Q.SNAP_ID AND S.DBID=Q.DBID AND S.INSTANCE_NUMBER=Q.INSTANCE_NUMBER
 WHERE Q.SQL_ID IN ('0zfz07pka9ysv','fr8a4mu383uwp','drxd1y8d336nr','gn59mxj6ngncj')
 GROUP BY Q.SQL_ID, Q.PLAN_HASH_VALUE
 ORDER BY Q.SQL_ID, ELA_S DESC;

PROMPT ################ [P3] ⭐⭐ DELETE 0zfz07pka9ysv 실행계획 (AWR, 계획별) — FG_C 를 FULL 로 읽는지 / 조인 방식 ################
SELECT P.PLAN_HASH_VALUE PHV, P.ID, LPAD(' ',P.DEPTH*2)||P.OPERATION||' '||P.OPTIONS OP, P.OBJECT_OWNER||'.'||P.OBJECT_NAME OBJECT_NAME,
       P.CARDINALITY CARD, P.COST, SUBSTR(P.ACCESS_PREDICATES,1,120) ACCESS_PRED, SUBSTR(P.FILTER_PREDICATES,1,120) FILTER_PRED
  FROM DBA_HIST_SQL_PLAN P
 WHERE P.SQL_ID='0zfz07pka9ysv'
 ORDER BY P.PLAN_HASH_VALUE, P.ID;

PROMPT ################ [P3b] DELETE 0zfz07pka9ysv 현재 커서 계획 (메모리에 남아 있을 때만) ################
SELECT P.INST_ID, P.CHILD_NUMBER CH, P.PLAN_HASH_VALUE PHV, P.ID, LPAD(' ',P.DEPTH*2)||P.OPERATION||' '||P.OPTIONS OP,
       P.OBJECT_OWNER||'.'||P.OBJECT_NAME OBJECT_NAME, P.CARDINALITY CARD, P.COST,
       SUBSTR(P.ACCESS_PREDICATES,1,120) ACCESS_PRED, SUBSTR(P.FILTER_PREDICATES,1,120) FILTER_PRED
  FROM GV$SQL_PLAN P
