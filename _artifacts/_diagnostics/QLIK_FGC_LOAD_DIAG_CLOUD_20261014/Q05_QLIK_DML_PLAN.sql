PROMPT ################ [P4] Full Load INSERT fr8a4mu383uwp 실행계획 (AWR) — 1행씩 VALUES 인지 확인 ################
SELECT P.PLAN_HASH_VALUE PHV, P.ID, LPAD(' ',P.DEPTH*2)||P.OPERATION||' '||P.OPTIONS OP, P.OBJECT_OWNER||'.'||P.OBJECT_NAME OBJECT_NAME
  FROM DBA_HIST_SQL_PLAN P
