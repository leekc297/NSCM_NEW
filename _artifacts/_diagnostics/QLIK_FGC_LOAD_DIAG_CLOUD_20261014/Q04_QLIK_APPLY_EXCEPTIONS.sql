-- Q04_QLIK_APPLY_EXCEPTIONS.sql — Qlik 적재 지연 진단 ④ Qlik 적용 오류(attrep_apply_exceptions) 집계 (READ-ONLY, 전체 F5)
--   배경  : Q01 [S6] 에서 클라우드 QA SCM_MGR."attrep_apply_exceptions" 287,194행 확인 (2026-10-14 19:49)
--           Qlik 은 일괄 적용(Batch optimized apply) 중 오류가 나면 그 묶음을 1건씩(one-by-one) 다시 적용하므로
--           오류가 많으면 적용 속도가 크게 떨어진다 → 어느 테이블·어떤 오류가 언제 몰렸는지 확인
--   계정  : SCM_MGR
--   실행  : SQL Developer = 스크립트 실행(F5) / sqlplus = @Q04_QLIK_APPLY_EXCEPTIONS.sql
--   변경  : 없음. SELECT 만 수행. 값 입력 없음.
--   컬럼  : TASK_NAME, TABLE_OWNER, TABLE_NAME, ERROR_TIME, STATEMENT(CLOB), ERROR(CLOB) — 사내 동일 테이블 구조로 확인
-- =============================================================================
SET DEFINE OFF
SET LINESIZE 400
SET PAGESIZE 500
SET TRIMSPOOL ON
SET FEEDBACK ON
SET VERIFY OFF
COLUMN TASK_NAME FORMAT A30
COLUMN TABLE_OWNER FORMAT A16
COLUMN TABLE_NAME FORMAT A40
COLUMN ORA FORMAT A10
COLUMN ERR_HEAD FORMAT A120
COLUMN STMT_HEAD FORMAT A160
COLUMN SEGMENT_NAME FORMAT A40
SPOOL Q04_QLIK_APPLY_EXCEPTIONS_OUT.txt

PROMPT ################ [X0] 실행 시각 / 전체 건수·기간 ################
SELECT TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI:SS') NOW, COUNT(*) TOTAL_ROWS,
       TO_CHAR(MIN(ERROR_TIME),'YYYY-MM-DD HH24:MI') FIRST_ERR, TO_CHAR(MAX(ERROR_TIME),'YYYY-MM-DD HH24:MI') LAST_ERR
  FROM SCM_MGR."attrep_apply_exceptions";

PROMPT ################ [X1] ⭐ 테이블별 오류 건수 (상위 30) — SCP_ANL_SHIPMENT_PLAN_FG_C 가 있는지 ################
SELECT TASK_NAME, TABLE_OWNER, TABLE_NAME, COUNT(*) CNT,
       TO_CHAR(MIN(ERROR_TIME),'MM-DD HH24:MI') FIRST_ERR, TO_CHAR(MAX(ERROR_TIME),'MM-DD HH24:MI') LAST_ERR
  FROM SCM_MGR."attrep_apply_exceptions"
 GROUP BY TASK_NAME, TABLE_OWNER, TABLE_NAME
 ORDER BY CNT DESC
 FETCH FIRST 30 ROWS ONLY;

PROMPT ################ [X2] ⭐ 오류 코드별 건수 (ORA 번호 + 첫 100자) — 상위 30 ################
SELECT NVL(REGEXP_SUBSTR(DBMS_LOB.SUBSTR(ERROR,1000,1),'ORA-[0-9]{5}'),'(ORA 없음)') ORA,
       SUBSTR(REPLACE(REPLACE(DBMS_LOB.SUBSTR(ERROR,300,1),CHR(10),' '),CHR(13),' '),1,100) ERR_HEAD,
       COUNT(*) CNT, COUNT(DISTINCT TABLE_NAME) TABLES,
       TO_CHAR(MIN(ERROR_TIME),'MM-DD HH24:MI') FIRST_ERR, TO_CHAR(MAX(ERROR_TIME),'MM-DD HH24:MI') LAST_ERR
  FROM SCM_MGR."attrep_apply_exceptions"
 GROUP BY NVL(REGEXP_SUBSTR(DBMS_LOB.SUBSTR(ERROR,1000,1),'ORA-[0-9]{5}'),'(ORA 없음)'),
          SUBSTR(REPLACE(REPLACE(DBMS_LOB.SUBSTR(ERROR,300,1),CHR(10),' '),CHR(13),' '),1,100)
 ORDER BY CNT DESC
 FETCH FIRST 30 ROWS ONLY;

PROMPT ################ [X3] 시간대별 오류 건수 (최근 14일, 시간당 100건 이상) — 느렸던 시간대와 겹치는지 ################
SELECT TO_CHAR(ERROR_TIME,'YYYY-MM-DD HH24') HR, COUNT(*) CNT, COUNT(DISTINCT TABLE_NAME) TABLES
  FROM SCM_MGR."attrep_apply_exceptions"
 WHERE ERROR_TIME > SYSTIMESTAMP - INTERVAL '14' DAY
 GROUP BY TO_CHAR(ERROR_TIME,'YYYY-MM-DD HH24')
HAVING COUNT(*) >= 100
 ORDER BY 1 DESC;

PROMPT ################ [X4] ⭐ SCP_ANL_SHIPMENT_PLAN_FG_C 오류 — 코드별 건수·기간 ################
SELECT TASK_NAME, NVL(REGEXP_SUBSTR(DBMS_LOB.SUBSTR(ERROR,1000,1),'ORA-[0-9]{5}'),'(ORA 없음)') ORA,
       COUNT(*) CNT, TO_CHAR(MIN(ERROR_TIME),'MM-DD HH24:MI:SS') FIRST_ERR, TO_CHAR(MAX(ERROR_TIME),'MM-DD HH24:MI:SS') LAST_ERR
  FROM SCM_MGR."attrep_apply_exceptions"
 WHERE TABLE_NAME = 'SCP_ANL_SHIPMENT_PLAN_FG_C'
 GROUP BY TASK_NAME, NVL(REGEXP_SUBSTR(DBMS_LOB.SUBSTR(ERROR,1000,1),'ORA-[0-9]{5}'),'(ORA 없음)')
 ORDER BY CNT DESC;

PROMPT ################ [X5] SCP_ANL_SHIPMENT_PLAN_FG_C 오류 표본 (최근 10건 — 문장·오류 앞부분) ################
SELECT * FROM (
  SELECT TO_CHAR(ERROR_TIME,'MM-DD HH24:MI:SS') ERR_TIME,
         SUBSTR(REPLACE(REPLACE(DBMS_LOB.SUBSTR(ERROR,400,1),CHR(10),' '),CHR(13),' '),1,120) ERR_HEAD,
         SUBSTR(REPLACE(REPLACE(DBMS_LOB.SUBSTR(STATEMENT,600,1),CHR(10),' '),CHR(13),' '),1,160) STMT_HEAD
    FROM SCM_MGR."attrep_apply_exceptions"
   WHERE TABLE_NAME = 'SCP_ANL_SHIPMENT_PLAN_FG_C'
   ORDER BY ERROR_TIME DESC)
 WHERE ROWNUM <= 10;

PROMPT ################ [X6] 전체 오류 표본 (최근 10건) ################
SELECT * FROM (
  SELECT TO_CHAR(ERROR_TIME,'MM-DD HH24:MI:SS') ERR_TIME, TABLE_NAME,
         SUBSTR(REPLACE(REPLACE(DBMS_LOB.SUBSTR(ERROR,400,1),CHR(10),' '),CHR(13),' '),1,120) ERR_HEAD,
         SUBSTR(REPLACE(REPLACE(DBMS_LOB.SUBSTR(STATEMENT,600,1),CHR(10),' '),CHR(13),' '),1,160) STMT_HEAD
    FROM SCM_MGR."attrep_apply_exceptions"
   ORDER BY ERROR_TIME DESC)
 WHERE ROWNUM <= 10;

PROMPT ################ [X7] Qlik 변경분 임시 테이블(attrep_changes*) 크기 — SCM_MGR ################
SELECT S.SEGMENT_NAME, S.SEGMENT_TYPE, ROUND(S.BYTES/1024/1024,1) MB,
       TO_CHAR(O.CREATED,'MM-DD HH24:MI:SS') CREATED, TO_CHAR(O.LAST_DDL_TIME,'MM-DD HH24:MI:SS') LAST_DDL
  FROM USER_SEGMENTS S LEFT JOIN USER_OBJECTS O ON O.OBJECT_NAME=S.SEGMENT_NAME AND O.OBJECT_TYPE=S.SEGMENT_TYPE
 WHERE UPPER(S.SEGMENT_NAME) LIKE 'ATTREP%'
 ORDER BY S.BYTES DESC;

