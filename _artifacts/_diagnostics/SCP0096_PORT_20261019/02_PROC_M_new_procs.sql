-- 사전 조회(2026-10-19 22:45): SCM_ADM_PROC_M 에 PKG_SCP0096.P_DM0003_GET_BUCKET_TYPE_CODE / P_SCP0009_GET_SHEET_CALENDAR_3SPAN 행 0건
-- 전체 registration.sql 은 SHEET_COLUMNS·API_M·MNU_BTN_MPG_M(사내 5행 → 2행)·USER_GR 매핑을 DELETE 후 재삽입하므로 사내 현행 메타를 덮는다 → 여기서는 PROC_M 만 적용
DECLARE
  v_n NUMBER;
  v_rows NUMBER;
BEGIN
  FOR p IN (SELECT 'P_DM0003_GET_BUCKET_TYPE_CODE' AS OBJ FROM DUAL UNION ALL SELECT 'P_SCP0009_GET_SHEET_CALENDAR_3SPAN' FROM DUAL) LOOP
    v_n := 0;
    FOR r IN (SELECT ARGUMENT_NAME, IN_OUT, DATA_TYPE, POSITION
                FROM ALL_ARGUMENTS
               WHERE OWNER = 'SCM_MGR' AND PACKAGE_NAME = 'PKG_SCP0096' AND OBJECT_NAME = p.OBJ
                 AND DATA_LEVEL = 0 AND ARGUMENT_NAME IS NOT NULL
               ORDER BY POSITION) LOOP
      v_n := v_n + 1;
      INSERT INTO SCM_ADM_PROC_M (PROC_NM, COL_NM, COL_TP_CD, DATA_TP_CD, SORT_ORD, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
      SELECT 'PKG_SCP0096.' || p.OBJ,
             CASE WHEN r.IN_OUT LIKE '%OUT%' THEN LOWER(r.ARGUMENT_NAME) ELSE PKG_NSCM_UI_COMM.FN_TO_CAMEL_CASE(REGEXP_REPLACE(r.ARGUMENT_NAME, '^P_', '')) END,
             CASE WHEN r.IN_OUT LIKE '%OUT%' THEN 'OUT' ELSE 'IN' END,
             CASE WHEN r.ARGUMENT_NAME = 'O_RESULT_CURSOR' THEN 'PROC_RESULT' ELSE PKG_NSCM_UI_COMM.FN_GET_SYSTEM_DATA_TP(r.DATA_TYPE) END,
             v_n, 'harness', SYSDATE, 'harness', SYSDATE
        FROM DUAL
       WHERE NOT EXISTS (SELECT 1 FROM SCM_ADM_PROC_M M WHERE M.PROC_NM = 'PKG_SCP0096.' || p.OBJ AND M.SORT_ORD = v_n);
    END LOOP;
    SELECT COUNT(*) INTO v_rows FROM SCM_ADM_PROC_M M WHERE M.PROC_NM = 'PKG_SCP0096.' || p.OBJ;
    DBMS_OUTPUT.PUT_LINE('PKG_SCP0096.' || p.OBJ || ' ALL_ARGUMENTS ' || v_n || '건 → PROC_M 행수 ' || v_rows);
  END LOOP;
END;
/
-- 검증: PROC_M 행수 = ALL_ARGUMENTS 행수 (4 프로시저 전부)
SELECT A.OBJECT_NAME, A.ARGS, NVL(M.ROWS_, 0) AS PROC_M_ROWS
  FROM (SELECT OBJECT_NAME, COUNT(*) ARGS FROM ALL_ARGUMENTS WHERE OWNER = 'SCM_MGR' AND PACKAGE_NAME = 'PKG_SCP0096' AND DATA_LEVEL = 0 AND ARGUMENT_NAME IS NOT NULL GROUP BY OBJECT_NAME) A
  LEFT JOIN (SELECT REGEXP_REPLACE(PROC_NM, '^PKG_SCP0096\.', '') OBJ, COUNT(*) ROWS_ FROM SCM_ADM_PROC_M WHERE PROC_NM LIKE 'PKG_SCP0096.%' GROUP BY PROC_NM) M ON M.OBJ = A.OBJECT_NAME
 ORDER BY 1;
