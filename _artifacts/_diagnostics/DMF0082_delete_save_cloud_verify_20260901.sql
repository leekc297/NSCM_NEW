-- DMF0082 클라우드 "조회 ROW DELETE 후 저장 시 SQL ERROR" 검증 스크립트 (2026-09-01)
-- 실행: 클라우드 DB 에서 순서대로 실행 후 결과 전체 회신 (SELECT-only, 무해).
-- 판독 우선순위: §0 오류원문 > §1 컴파일/마커 > §2 SAVE 경로 마커 > §3 대상 객체 > §4 제약/트리거
-- 사내 실측 기반: 저장 SP = PKG_DMF0082.P_DMF0082_SAVE_MAIN_DATA (L11555~14651),
--   DELETE 분기(ACTION='D') 대상 원장 = DM_PLN_MKT_FCST / DM_PLN_CFM_MKT_DEMAND_PLAN /
--   DM_PLN_CFM_SELLING_PRICE / SCM_MST_FUTURE_PRICE + 스테이징 GT_PRDM1_* 9본
-- ============================================================================

-- §0. 오류 원문 — 가장 결정적 (재현 직후 실행 권장. ORA-코드가 그대로 나옵니다)
SELECT '§0 SAVE오류원문' AS SECTION, EXECUTE_TIME, SQL_ID, ELAPSED_MS, CREATED_BY,
       SUBSTR(EXCEPTION, 1, 800) AS EXCEPTION_TEXT
  FROM SCM_MGR.SCM_COM_SQL_LOG
 WHERE (UPPER(SQL_TEXT) LIKE '%DMF0082%SAVE%' OR UPPER(PARAMS) LIKE '%SAVE_MAIN_DATA%'
        OR (UPPER(SQL_TEXT) LIKE '%DMF0082%' AND EXCEPTION IS NOT NULL))
   AND EXCEPTION IS NOT NULL
   AND EXECUTE_TIME >= SYSDATE - 1
 ORDER BY EXECUTE_TIME DESC
 FETCH FIRST 10 ROWS ONLY;

-- §0-B. 같은 시각의 요청 파라미터 요약 (ACTION 'D' 행이 실려 갔는지 — payload 앞부분)
SELECT '§0B 요청파라미터' AS SECTION, EXECUTE_TIME, SUBSTR(PARAMS, 1, 1200) AS PARAMS_HEAD
  FROM SCM_MGR.SCM_COM_SQL_LOG
 WHERE UPPER(PARAMS) LIKE '%SAVE_MAIN_DATA%'
   AND EXECUTE_TIME >= SYSDATE - 1
 ORDER BY EXECUTE_TIME DESC
 FETCH FIRST 3 ROWS ONLY;

-- §1. PKG 상태 + 어제 패키지(CLOUD_ORA12704_NCHARUNION_20260831) 적용 확인
SELECT '§1 상태' AS SECTION, OBJECT_NAME, OBJECT_TYPE, STATUS,
       TO_CHAR(LAST_DDL_TIME, 'YYYY-MM-DD HH24:MI:SS') AS LAST_DDL
  FROM ALL_OBJECTS
 WHERE OWNER = 'SCM_MGR' AND OBJECT_NAME = 'PKG_DMF0082';

SELECT '§1 컴파일오류' AS SECTION, LINE, POSITION, SUBSTR(TEXT, 1, 300) AS ERR
  FROM ALL_ERRORS
 WHERE OWNER = 'SCM_MGR' AND NAME = 'PKG_DMF0082' AND ATTRIBUTE = 'ERROR'
 ORDER BY SEQUENCE;

-- §2. SAVE 경로 정정 마커 드리프트 — 전부 CNT>=1 이어야 사내 정본과 동일
SELECT '§2 SAVE마커' AS SECTION, M.MARKER,
       (SELECT COUNT(*) FROM ALL_SOURCE S
         WHERE S.OWNER='SCM_MGR' AND S.NAME='PKG_DMF0082' AND S.TYPE='PACKAGE BODY'
           AND INSTR(S.TEXT, M.MARKER) > 0) AS CNT
  FROM (
        SELECT 'E20260831-NCHARUNION'  AS MARKER FROM DUAL UNION ALL
        SELECT 'E20260831-QTYKEY'      FROM DUAL UNION ALL
        SELECT 'E20260825-SAVEPOPPERF' FROM DUAL UNION ALL
        SELECT 'E20260825-SAVEPOPCLOB' FROM DUAL UNION ALL
        SELECT 'E20260822-DIV81DEL'    FROM DUAL UNION ALL
        SELECT 'E20260822-KEYCOL'      FROM DUAL
       ) M
 ORDER BY M.MARKER DESC;

-- §3. DELETE 분기 대상 객체 실존 — 나오는 행 = 클라우드에 없는 객체 (0행 = 통과)
WITH REQ (NM) AS (
  SELECT 'DM_PLN_MKT_FCST' FROM DUAL UNION ALL
  SELECT 'DM_PLN_CFM_MKT_DEMAND_PLAN' FROM DUAL UNION ALL
  SELECT 'DM_PLN_CFM_SELLING_PRICE' FROM DUAL UNION ALL
  SELECT 'SCM_MST_FUTURE_PRICE' FROM DUAL UNION ALL
  SELECT 'GT_PRDM1_T_MAIN' FROM DUAL UNION ALL
  SELECT 'GT_PRDM1_T_PRICE' FROM DUAL UNION ALL
  SELECT 'GT_PRDM1_T_FCST' FROM DUAL UNION ALL
  SELECT 'GT_PRDM1_TEMP_EXCEPTION_BIZ_TYPE' FROM DUAL UNION ALL
  SELECT 'GT_PRDM1_TEMP_EXCEPTION_ITEM_LIST' FROM DUAL UNION ALL
  SELECT 'GT_PRDM1_TEMP_DAYINFO' FROM DUAL UNION ALL
  SELECT 'GT_PRDM1_TEMP_EXCH' FROM DUAL UNION ALL
  SELECT 'GT_PRDM1_MSHYCHU1' FROM DUAL UNION ALL
  SELECT 'GT_PRDM1_MSHYCHU2' FROM DUAL
)
SELECT '§3 부재객체' AS SECTION, R.NM
  FROM REQ R
 WHERE NOT EXISTS (SELECT 1 FROM ALL_OBJECTS O WHERE O.OWNER='SCM_MGR' AND O.OBJECT_NAME = R.NM)
 ORDER BY R.NM;

-- §4. DELETE 를 막을 수 있는 제약 — 대상 원장 4본을 부모로 참조(FK)하는 자식 테이블 (ORA-02292 축)
SELECT '§4 자식FK' AS SECTION, C.TABLE_NAME AS CHILD_TABLE, C.CONSTRAINT_NAME,
       P.TABLE_NAME AS PARENT_TABLE
  FROM ALL_CONSTRAINTS C
  JOIN ALL_CONSTRAINTS P ON P.OWNER = C.R_OWNER AND P.CONSTRAINT_NAME = C.R_CONSTRAINT_NAME
 WHERE C.CONSTRAINT_TYPE = 'R' AND P.OWNER = 'SCM_MGR'
   AND P.TABLE_NAME IN ('DM_PLN_MKT_FCST','DM_PLN_CFM_MKT_DEMAND_PLAN',
                        'DM_PLN_CFM_SELLING_PRICE','SCM_MST_FUTURE_PRICE')
 ORDER BY P.TABLE_NAME, C.TABLE_NAME;

-- §4-B. 대상 원장 4본의 트리거 (사내 부재 트리거가 클라우드에만 있으면 원인 후보)
SELECT '§4B 트리거' AS SECTION, TABLE_NAME, TRIGGER_NAME, TRIGGERING_EVENT, STATUS
  FROM ALL_TRIGGERS
 WHERE OWNER = 'SCM_MGR'
   AND TABLE_NAME IN ('DM_PLN_MKT_FCST','DM_PLN_CFM_MKT_DEMAND_PLAN',
                      'DM_PLN_CFM_SELLING_PRICE','SCM_MST_FUTURE_PRICE')
 ORDER BY TABLE_NAME, TRIGGER_NAME;

-- §5. (재현 직후 재실행) §0 과 동일 — 방금 발생분의 ORA 원문 확보
SELECT '§5 재발확인' AS SECTION, EXECUTE_TIME, SUBSTR(EXCEPTION, 1, 800) AS EXCEPTION_TEXT
  FROM SCM_MGR.SCM_COM_SQL_LOG
 WHERE UPPER(PARAMS) LIKE '%SAVE_MAIN_DATA%' AND EXCEPTION IS NOT NULL
   AND EXECUTE_TIME >= SYSDATE - 1/24
 ORDER BY EXECUTE_TIME DESC
 FETCH FIRST 5 ROWS ONLY;
