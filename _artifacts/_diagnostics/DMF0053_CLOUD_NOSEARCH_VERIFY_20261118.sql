UNION ALL SELECT 'UF_FX_STRING_SPLIT'           , 'FUNCTION' FROM DUAL
UNION ALL SELECT 'SCM_MST_ITEM_SN'              , 'SYNONYM'  FROM DUAL
UNION ALL SELECT 'DM_DNM_EDI_CALLOFF_ITEM'      , 'TABLE'    FROM DUAL
UNION ALL SELECT 'DM_MST_CUSTOMER_FCST'         , 'TABLE'    FROM DUAL
UNION ALL SELECT 'DM_PLN_CUST_FCST_H'           , 'TABLE'    FROM DUAL
UNION ALL SELECT 'GT_DMF0053_COLUMN_SETUP'      , 'TABLE'    FROM DUAL
UNION ALL SELECT 'GT_DMF0053_EDI_CALLOFF'       , 'TABLE'    FROM DUAL
UNION ALL SELECT 'GT_DMF0053_ITEM_SINGLE_V'     , 'TABLE'    FROM DUAL
UNION ALL SELECT 'GT_DMF0053_ITEM_SINGLE_V_T'   , 'TABLE'    FROM DUAL
UNION ALL SELECT 'GT_DMF0053_RAW_DATA'          , 'TABLE'    FROM DUAL
UNION ALL SELECT 'GT_DMF0053_SCM_MST_SITE'      , 'TABLE'    FROM DUAL
UNION ALL SELECT 'GT_DMF0053_SCM_MST_SITE_ITEM' , 'TABLE'    FROM DUAL
