-- Q3-1. 원천 DM_PLN_CUST_FCST_H 사업부별 현황. THIS_MONTH_CNT = 화면 기본 Create Date(이번 달) 안에 드는 행 수
SELECT A.DIVISION_ID
     , COUNT(*)                                                     AS TOTAL_CNT
     , MIN(A.CREATE_DATE)                                           AS MIN_CREATE_DATE
     , MAX(A.CREATE_DATE)                                           AS MAX_CREATE_DATE
     , TO_CHAR(MAX(A.LAST_UPDATE_DATE), 'YYYY-MM-DD HH24:MI:SS')    AS LAST_LOADED
     , SUM(CASE WHEN A.CREATE_DATE >= TO_CHAR(TRUNC(SYSDATE, 'MM'), 'YYYYMMDD')
                 AND A.CREATE_DATE <= TO_CHAR(LAST_DAY(SYSDATE), 'YYYYMMDD') THEN 1 ELSE 0 END) AS THIS_MONTH_CNT
     , SUM(CASE WHEN A.CREATE_DATE >= TO_CHAR(TRUNC(SYSDATE, 'MM'), 'YYYYMMDD')
                 AND A.CREATE_DATE <= TO_CHAR(LAST_DAY(SYSDATE), 'YYYYMMDD')
                 AND A.YYYYMMDD    >= TO_CHAR(TRUNC(SYSDATE, 'MM'), 'YYYYMMDD')
                 AND A.YYYYMMDD    <= TO_CHAR(LAST_DAY(ADD_MONTHS(SYSDATE, 5)), 'YYYYMMDD') THEN 1 ELSE 0 END) AS DEFAULT_COND_CNT
  FROM DM_PLN_CUST_FCST_H A
 GROUP BY A.DIVISION_ID
 ORDER BY A.DIVISION_ID;

-- Q3-2. CREATE_DATE 값 형식. 화면은 'YYYYMMDD' 8자리로 비교함. LEN 8, HYPHEN 0 외의 행은 화면 조건과 맞지 않음
SELECT A.DIVISION_ID
     , LENGTH(A.CREATE_DATE)       AS LEN
     , INSTR(A.CREATE_DATE, '-')   AS HYPHEN_POS
     , COUNT(*)                    AS CNT
     , MIN(A.CREATE_DATE)          AS SAMPLE_MIN
     , MAX(A.CREATE_DATE)          AS SAMPLE_MAX
  FROM DM_PLN_CUST_FCST_H A
 GROUP BY A.DIVISION_ID, LENGTH(A.CREATE_DATE), INSTR(A.CREATE_DATE, '-')
 ORDER BY A.DIVISION_ID, 2, 3;

-- Q3-3. 최근 30일 Create Date 별 적재 건수 (사업부별). 마지막 적재일 이후로 행이 없으면 이력 적재가 멈춘 것
SELECT A.DIVISION_ID, A.CREATE_DATE, COUNT(*) AS CNT
     , TO_CHAR(MAX(A.LAST_UPDATE_DATE), 'YYYY-MM-DD HH24:MI:SS') AS LAST_LOADED
  FROM DM_PLN_CUST_FCST_H A
 WHERE A.CREATE_DATE >= TO_CHAR(TRUNC(SYSDATE) - 30, 'YYYYMMDD')
 GROUP BY A.DIVISION_ID, A.CREATE_DATE
 ORDER BY A.DIVISION_ID, A.CREATE_DATE DESC;

