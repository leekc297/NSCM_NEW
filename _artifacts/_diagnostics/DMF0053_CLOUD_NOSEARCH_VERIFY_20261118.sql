/* ===================================================================================================
 * S1. SP 직접 실행 (선택 실행)
 *   화면과 같은 기본 조건으로 두 SP 를 호출해 결과 코드, 오류 메시지, 행 수를 출력함
 *   사용법
 *     1) 아래 블록에서 V_DIV(사업부), V_USER(화면에서 조회한 사용자 ID) 두 값을 넣음
 *     2) 주석 시작 줄과 끝 줄을 지우고 BEGIN ~ END; 블록만 선택해 실행함
 *     3) DBeaver 는 Server Output 창(Ctrl+Shift+O)을 켜고 실행함
 *   데이터 변경
 *     SP 는 COMMIT 하지 않음. GTT(세션 전용)에 쓰고, 사용자 Measure 설정이 0건이면 SCM_MST_TITLESET_USER 에 기본 Measure 를 넣음
 *     블록 끝 ROLLBACK 으로 모두 되돌림
 *   결과 읽기
 *     TITLE CODE/MSG, MAIN CODE/MSG 가 '1' 이면 MSG 가 오류 원인
 *     MAIN CODE '0' 이고 RC1 ROWS 0 이면 데이터 조건 문제. Q3, Q5 로 확인
 *   사내 실행 기록 2026-11-18 11:06 (사업부 81, 40)
 *     TITLE CODE 0, RC1 52행(81), 54행(40). MAIN CODE 0, RC1 0행, 56열. ROLLBACK 후 SCM_MST_TITLESET_USER 609건 변화 없음
 *     사내 MAIN 0행 원인 = 이력 CREATE_DATE 최신 20260914, 기본 Create Date 20261101~20261130 밖
 *
DECLARE
    V_DIV    VARCHAR2(30)  := '사업부 입력';
    V_USER   VARCHAR2(100) := '사용자 ID 입력';
    V_FROM   VARCHAR2(8)   := TO_CHAR(TRUNC(SYSDATE, 'MM'), 'YYYYMMDD');
    V_TO     VARCHAR2(8)   := TO_CHAR(LAST_DAY(ADD_MONTHS(SYSDATE, 5)), 'YYYYMMDD');
    V_CFROM  VARCHAR2(8)   := TO_CHAR(TRUNC(SYSDATE, 'MM'), 'YYYYMMDD');
    V_CTO    VARCHAR2(8)   := TO_CHAR(LAST_DAY(SYSDATE), 'YYYYMMDD');
    RC1 SYS_REFCURSOR; RC2 SYS_REFCURSOR; RC3 SYS_REFCURSOR; RRES SYS_REFCURSOR;
    V_CODE VARCHAR2(10); V_MSG VARCHAR2(4000); V_EVT VARCHAR2(100);
    V_CNT  NUMBER;
    V_CUR  INTEGER;
    V_DESC DBMS_SQL.DESC_TAB;
    V_COLS INTEGER;
BEGIN
    PKG_DMF0053.P_DMF0053_GET_SPREAD_TITLE(V_FROM, V_TO, V_USER, V_DIV, 'MONTHLY', V_USER, 'DMF0053', RC1, RRES);
    FETCH RRES INTO V_CODE, V_MSG, V_EVT;
    DBMS_OUTPUT.PUT_LINE('TITLE CODE=' || V_CODE || ' MSG=' || V_MSG);
    CLOSE RRES;
    V_CUR := DBMS_SQL.TO_CURSOR_NUMBER(RC1);
    V_CNT := 0;
    DBMS_SQL.DESCRIBE_COLUMNS(V_CUR, V_COLS, V_DESC);
    WHILE DBMS_SQL.FETCH_ROWS(V_CUR) > 0 LOOP V_CNT := V_CNT + 1; END LOOP;
    DBMS_SQL.CLOSE_CURSOR(V_CUR);
    DBMS_OUTPUT.PUT_LINE('TITLE RC1 ROWS=' || V_CNT);

    PKG_DMF0053.P_DMF0053_GET_CUST_FCST_WATERFALL(
        V_DIV, 'ALL', 'ALL', 'ALL', NULL, NULL, 'ALL', V_FROM, V_TO, V_USER,
        'ALL', 'ALL', NULL, 'MONTHLY', NULL, NULL, NULL, V_CFROM, V_CTO, V_USER, 'DMF0053',
        RC1, RC2, RC3, RRES);
    FETCH RRES INTO V_CODE, V_MSG, V_EVT;
    DBMS_OUTPUT.PUT_LINE('MAIN CODE=' || V_CODE || ' MSG=' || V_MSG);
    CLOSE RRES;
    V_CUR := DBMS_SQL.TO_CURSOR_NUMBER(RC1);
    V_CNT := 0;
    DBMS_SQL.DESCRIBE_COLUMNS(V_CUR, V_COLS, V_DESC);
    WHILE DBMS_SQL.FETCH_ROWS(V_CUR) > 0 LOOP V_CNT := V_CNT + 1; END LOOP;
    DBMS_SQL.CLOSE_CURSOR(V_CUR);
    DBMS_OUTPUT.PUT_LINE('MAIN RC1 ROWS=' || V_CNT || ' COLS=' || V_COLS);
    SELECT COUNT(*) INTO V_CNT FROM GT_DMF0053_SELECT_MEASURE;
    DBMS_OUTPUT.PUT_LINE('GT SELECT_MEASURE ROWS=' || V_CNT);
    ROLLBACK;
EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('BLOCK ERROR ' || SQLERRM);
        ROLLBACK;
END;
