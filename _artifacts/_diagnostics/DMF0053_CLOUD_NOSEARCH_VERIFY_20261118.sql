UNION ALL SELECT 'SCM_MST_COUNTRY'              , 'TABLE'    FROM DUAL
UNION ALL SELECT 'SCM_MST_PROJECT'              , 'TABLE'    FROM DUAL
UNION ALL SELECT 'SCM_MST_SHEET_COLUMNS'        , 'TABLE'    FROM DUAL
UNION ALL SELECT 'SCM_MST_SHEET_MEASURE'        , 'TABLE'    FROM DUAL
UNION ALL SELECT 'SCM_MST_SITE'                 , 'TABLE'    FROM DUAL
UNION ALL SELECT 'SCM_MST_SITE_CUSTOMER'        , 'TABLE'    FROM DUAL
UNION ALL SELECT 'SCM_MST_SITE_ITEM'            , 'TABLE'    FROM DUAL
UNION ALL SELECT 'SCM_MST_TITLESET_USER'        , 'TABLE'    FROM DUAL
UNION ALL SELECT 'SCM_SYS_CALENDAR_M'           , 'TABLE'    FROM DUAL
)
SELECT R.NM AS OBJECT_NAME, R.TP AS EXPECT_TYPE
     , NVL(MAX(O.STATUS), '없음') AS STATUS
     , MAX(O.OWNER)             AS OWNER
     , MAX(T.TEMPORARY)         AS GTT_YN
     , MAX(T.DURATION)          AS GTT_DURATION
  FROM REQ R
  LEFT OUTER JOIN ALL_OBJECTS O
    ON O.OBJECT_NAME = R.NM
   AND O.OBJECT_TYPE = R.TP
   AND O.OWNER       = SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA')
  LEFT OUTER JOIN ALL_TABLES T
    ON T.TABLE_NAME = R.NM
   AND T.OWNER      = O.OWNER
 GROUP BY R.NM, R.TP
 ORDER BY CASE WHEN NVL(MAX(O.STATUS), '없음') = 'VALID' THEN 1 ELSE 0 END, R.TP, R.NM;

