DEFINE DIV = '81'
DEFINE USR = 'minyonglee1'
SET LINESIZE 300
SET PAGESIZE 200

PROMPT [P] 적용 중인 SP 세대 — XLSFORMASIS 마커(09-21 적용본) 있어야 함 / BODY LAST_DDL
SELECT TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') BODY_LAST_DDL
     , (SELECT COUNT(*) FROM USER_SOURCE WHERE NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%E20260921-XLSFORMASIS%') XLSFORMASIS_MARK
  FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0082' AND OBJECT_TYPE='PACKAGE BODY';

PROMPT [S0] SP 가 고르는 기준 버전 (MAX(VERSION_NO) / MAX(YYYYMMDD) — 문자열 MAX)
SELECT DIVISION_ID, MAX(VERSION_NO) VERSION_NO, MAX(YYYYMMDD) YYYYMMDD
  FROM DM_MST_VERSION WHERE DIVISION_ID = '&DIV' AND VERSION_TYPE = 'SP_W' GROUP BY DIVISION_ID;

PROMPT [S1] 기준 버전의 스냅샷 건수 (RTF_SYS_RP, QTY<>0) — 여기서 적으면 원장 스냅샷 부족이 원인
WITH V AS (SELECT MAX(VERSION_NO) VERSION_NO FROM DM_MST_VERSION WHERE DIVISION_ID='&DIV' AND VERSION_TYPE='SP_W')
SELECT 'SALES_PLAN_C' SRC, COUNT(*) ROWS_ALL, COUNT(DISTINCT PROJECT_CODE||'|'||SCM_SITE_ID||'|'||ITEM_ID) KEYS
  FROM DM_PLN_SALES_PLAN_C SP, V WHERE SP.DIVISION_ID='&DIV' AND SP.VERSION_NO=V.VERSION_NO AND SP.MEASURE='RTF_SYS_RP' AND SP.QTY<>0
UNION ALL
SELECT 'SALES_PLAN_RESULT_C', COUNT(*), COUNT(DISTINCT PROJECT_CODE||'|'||SCM_SITE_ID||'|'||ITEM_ID)
  FROM DM_PLN_SALES_PLAN_RESULT_C SP, V WHERE SP.DIVISION_ID='&DIV' AND SP.VERSION_NO=V.VERSION_NO AND SP.MEASURE='RTF_SYS_RP' AND SP.QTY<>0;

PROMPT [S1-b] 버전별 스냅샷 적재 현황 (최근 SP_W 8개) — 최신 버전만 비어 있으면 스냅샷 미적재
SELECT V.VERSION_NO, V.YYYYMMDD
     , (SELECT COUNT(*) FROM DM_PLN_SALES_PLAN_C C WHERE C.DIVISION_ID=V.DIVISION_ID AND C.VERSION_NO=V.VERSION_NO AND C.MEASURE='RTF_SYS_RP' AND C.QTY<>0) PLAN_C
     , (SELECT COUNT(*) FROM DM_PLN_SALES_PLAN_RESULT_C C WHERE C.DIVISION_ID=V.DIVISION_ID AND C.VERSION_NO=V.VERSION_NO AND C.MEASURE='RTF_SYS_RP' AND C.QTY<>0) RESULT_C
  FROM DM_MST_VERSION V WHERE V.DIVISION_ID='&DIV' AND V.VERSION_TYPE='SP_W'
 ORDER BY V.VERSION_NO DESC FETCH FIRST 8 ROWS ONLY;

PROMPT [S2] 사용자 편집권한 뷰 (없으면 0건) — USER/MNU/UNIT_TP_CD='D'
SELECT USER_ID, MNU_ID, UNIT_ID, EDIT_YN FROM SCM_ADM_USER_MNU_EDIT_AUTH_V
 WHERE USER_ID='&USR' AND MNU_ID='DMF0082' AND UNIT_TP_CD='D' AND UNIT_ID='&DIV';

PROMPT [S3~S6] 단계별 누적 키 수 (PLAN_C 분기 — 52주 창 적용 후)
WITH V AS (SELECT A.DIVISION_ID, A.VERSION_NO, A.YYYYMMDD FROM (SELECT DIVISION_ID, MAX(VERSION_NO) VERSION_NO, MAX(YYYYMMDD) YYYYMMDD FROM DM_MST_VERSION WHERE DIVISION_ID='&DIV' AND VERSION_TYPE='SP_W' GROUP BY DIVISION_ID) A)
, B AS (SELECT SP.* FROM DM_PLN_SALES_PLAN_C SP JOIN V ON V.DIVISION_ID=SP.DIVISION_ID AND V.VERSION_NO=SP.VERSION_NO
         WHERE SP.MEASURE='RTF_SYS_RP' AND SP.QTY<>0
           AND SP.YYYYMMDD >= TO_CHAR(FN_NEXT_DAY(TO_DATE(V.YYYYMMDD,'YYYYMMDD'),'MON')-7,'YYYYMMDD')
           AND SP.YYYYMMDD <= TO_CHAR(FN_NEXT_DAY(TO_DATE(V.YYYYMMDD,'YYYYMMDD'),'MON')-7+364-1,'YYYYMMDD'))
SELECT 'S3 창 내 스냅샷 키' STEP, COUNT(DISTINCT PROJECT_CODE||'|'||SCM_SITE_ID||'|'||ITEM_ID) KEYS FROM B
UNION ALL SELECT 'S4 +SCM_MST_SITE(VALID)', COUNT(DISTINCT B.PROJECT_CODE||'|'||B.SCM_SITE_ID||'|'||B.ITEM_ID) FROM B
  JOIN SCM_MST_SITE MS ON MS.DIVISION_ID=B.DIVISION_ID AND MS.SCM_SITE_ID=B.SCM_SITE_ID AND MS.VALID_YN='Y'
UNION ALL SELECT 'S5 +SITE 대표 DEPT(SSO VALID)', COUNT(DISTINCT B.PROJECT_CODE||'|'||B.SCM_SITE_ID||'|'||B.ITEM_ID) FROM B
  JOIN SCM_MST_SITE MS ON MS.DIVISION_ID=B.DIVISION_ID AND MS.SCM_SITE_ID=B.SCM_SITE_ID AND MS.VALID_YN='Y'
  JOIN (SELECT SA.DIVISION_ID, SA.SCM_SITE_ID, MAX(SA.DEPT_ID) DEPT_ID FROM SCM_MST_SITE_ITEM SA JOIN SCM_MST_SSO_DEPT_INFO SD ON SD.DEPT_ID=SA.DEPT_ID AND SD.VALID_YN='Y' WHERE SA.DEPT_ID IS NOT NULL GROUP BY SA.DIVISION_ID, SA.SCM_SITE_ID) IM
    ON IM.DIVISION_ID=MS.DIVISION_ID AND IM.SCM_SITE_ID=MS.SCM_SITE_ID
UNION ALL SELECT 'S6 +PROJECT +SITE_ITEM(VALID)', COUNT(DISTINCT B.PROJECT_CODE||'|'||B.SCM_SITE_ID||'|'||B.ITEM_ID) FROM B
  JOIN SCM_MST_SITE MS ON MS.DIVISION_ID=B.DIVISION_ID AND MS.SCM_SITE_ID=B.SCM_SITE_ID AND MS.VALID_YN='Y'
  JOIN (SELECT SA.DIVISION_ID, SA.SCM_SITE_ID, MAX(SA.DEPT_ID) DEPT_ID FROM SCM_MST_SITE_ITEM SA JOIN SCM_MST_SSO_DEPT_INFO SD ON SD.DEPT_ID=SA.DEPT_ID AND SD.VALID_YN='Y' WHERE SA.DEPT_ID IS NOT NULL GROUP BY SA.DIVISION_ID, SA.SCM_SITE_ID) IM
    ON IM.DIVISION_ID=MS.DIVISION_ID AND IM.SCM_SITE_ID=MS.SCM_SITE_ID
  JOIN SCM_MST_PROJECT MP ON MP.DIVISION_ID=B.DIVISION_ID AND MP.PROJECT_CODE=B.PROJECT_CODE
  JOIN SCM_MST_SITE_ITEM SI ON SI.DIVISION_ID=B.DIVISION_ID AND SI.PROJECT_CODE=B.PROJECT_CODE AND SI.SCM_SITE_ID=B.SCM_SITE_ID AND SI.ITEM_ID=B.ITEM_ID AND SI.VALID_YN='Y';
