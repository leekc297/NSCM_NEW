--   대상 SP : PKG_DMF0082.P_DMF0082_GET_EXCEL_FORM_DATA (행 원천 = DIV 최신 SP_W 버전의
--             DM_PLN_SALES_PLAN_C ∪ DM_PLN_SALES_PLAN_RESULT_C, RTF_SYS_RP, QTY<>0, 52주 창)
--   사용법 : 아래 두 치환값만 바꿔 실행 — &DIV (예 81) / &USR (클라우드 로그인 사용자 ID)
--   판정 : [S0]~[S6] 단계별 건수 중 급감하는 단계가 원인이다.
