-- Q8. ④ 화면 기간 조건 — 이력 행의 YYYYMMDD / CREATE_DATE 가 조회조건 기간 안에 있는지
--     (FROM/TO 를 화면에서 넣은 값으로 바꿔서 실행. CREATE_DATE 는 'YYYYMMDD' 문자 비교)
WITH P AS (SELECT '81' DIV, 'STB_DE_MUC' SITE, 'A24ST4001-000' PRJ, 'AMRSAEV20-A2-010' ITEM
                , '20260901' FROM_YMD, '20271231' TO_YMD          /* 조회 기간 */
                , '20261001' FROM_CRT, '20261031' TO_CRT          /* Create Date 기간 */
             FROM DUAL)
SELECT A.MEASURE, A.YYYYMMDD, A.CREATE_DATE, A.QTY
     , CASE WHEN A.YYYYMMDD BETWEEN P.FROM_YMD AND P.TO_YMD THEN 'IN' ELSE 'OUT' END AS PERIOD_CHECK
     , CASE WHEN A.CREATE_DATE BETWEEN P.FROM_CRT AND P.TO_CRT THEN 'IN' ELSE 'OUT' END AS CREATE_DATE_CHECK
  FROM DM_PLN_CUST_FCST_H A, P
 WHERE A.DIVISION_ID  = P.DIV
   AND A.SCM_SITE_ID  = P.SITE
   AND A.PROJECT_CODE = P.PRJ
   AND A.ITEM_ID      = P.ITEM
   AND A.MEASURE IN ('CUST_FCST', 'Customer FCST')
 ORDER BY A.YYYYMMDD;

-- Q9. 요약 — 단계별 건수 (0 이 처음 나오는 단계가 원인)
WITH P AS (SELECT '81' DIV, 'STB_DE_MUC' SITE, 'A24ST4001-000' PRJ, 'AMRSAEV20-A2-010' ITEM, 'Customer FCST' MEA FROM DUAL)
SELECT '1 업로드 원장 DM_PLN_CUSTOMER_PSI' AS STAGE
     , (SELECT COUNT(*) FROM DM_PLN_CUSTOMER_PSI A WHERE A.DIVISION_ID = P.DIV AND A.SCM_SITE_ID = P.SITE AND A.PROJECT_CODE = P.PRJ AND A.ITEM_ID = P.ITEM AND A.MEASURE = P.MEA) AS CNT
     , '' AS NOTE
  FROM P
UNION ALL
SELECT '2 계획 원장 DM_PLN_MKT_FCST (DMF0082)'
     , (SELECT COUNT(*) FROM DM_PLN_MKT_FCST A WHERE A.DIVISION_ID = P.DIV AND A.SCM_SITE_ID = P.SITE AND A.PROJECT_CODE = P.PRJ AND A.ITEM_ID = P.ITEM AND A.MEASURE IN ('CUST_FCST', 'Customer FCST'))
     , '어제 이후 갱신 ' || (SELECT COUNT(*) FROM DM_PLN_MKT_FCST A WHERE A.DIVISION_ID = P.DIV AND A.SCM_SITE_ID = P.SITE AND A.PROJECT_CODE = P.PRJ AND A.ITEM_ID = P.ITEM AND A.MEASURE IN ('CUST_FCST', 'Customer FCST') AND A.LAST_UPDATE_DATE >= TRUNC(SYSDATE) - 1) || '건'
  FROM P
UNION ALL
SELECT '3 Waterfall 원천 DM_PLN_CUST_FCST_H'
     , (SELECT COUNT(*) FROM DM_PLN_CUST_FCST_H A WHERE A.DIVISION_ID = P.DIV AND A.SCM_SITE_ID = P.SITE AND A.PROJECT_CODE = P.PRJ AND A.ITEM_ID = P.ITEM AND A.MEASURE IN ('CUST_FCST', 'Customer FCST'))
     , '0 이면 이력 적재 배치(PR_DM_PLN_CUST_FCST_RECORD 81 RPA) 미실행/실패 — Q4·Q5'
  FROM P
UNION ALL
SELECT '3-1 이력 적재 잡 활성'
     , (SELECT COUNT(*) FROM ALL_SCHEDULER_JOBS J WHERE (J.JOB_NAME LIKE '%EDI_CALLOFF%' OR UPPER(J.JOB_ACTION) LIKE '%PR_DM_PLN_CUST_FCST_RECORD%') AND J.ENABLED = 'TRUE')
     , '0 이면 잡이 꺼져 있음(ENABLED=FALSE)'
  FROM P
UNION ALL
SELECT '3-2 이력 적재 배치 오늘 실행 로그(END)'
     , (SELECT COUNT(*) FROM SCM_SYS_LOG_BATCH L WHERE L.PROGRAM_NAME = 'PR_DM_PLN_CUST_FCST_RECORD' AND L.LOG_TYPE = 'END' AND L.EVENT_DATE >= TRUNC(SYSDATE))
     , 'ERROR 로그 ' || (SELECT COUNT(*) FROM SCM_SYS_LOG_BATCH L WHERE L.PROGRAM_NAME = 'PR_DM_PLN_CUST_FCST_RECORD' AND L.LOG_TYPE = 'ERROR' AND L.EVENT_DATE >= TRUNC(SYSDATE)) || '건'
  FROM P
UNION ALL
SELECT '4 고객 FCST 마스터 (CUST_FCST 그룹·유효)'
     , (SELECT COUNT(*) FROM DM_MST_CUSTOMER_FCST C WHERE C.DIVISION_ID = P.DIV AND C.SCM_SITE_ID = P.SITE AND C.MEASURE = P.MEA AND C.MEASURE_GROUP = 'CUST_FCST' AND C.VALID_YN = 'Y')
     , '0 이면 Waterfall Measure 펼침 대상 아님'
  FROM P
 ORDER BY 1;

