-- Q1. ① 업로드 원장 DM_PLN_CUSTOMER_PSI — 행이 있어야 한다 (QTY 777 주차 확인)
WITH P AS (SELECT '81' DIV, 'STB_DE_MUC' SITE, 'A24ST4001-000' PRJ, 'AMRSAEV20-A2-010' ITEM, 'Customer FCST' MEA FROM DUAL)
SELECT A.DIVISION_ID, A.SCM_SITE_ID, A.PLANT_SITE_ID, A.PROJECT_CODE, A.ITEM_ID, A.INCOTERMS, A.FCST_TYPE, A.DOM_EXP
     , A.MEASURE_GROUP, A.MEASURE, A.UPLOAD_UOM, A.YYYYMMDD, A.QTY, A.BATCH_RESULT
     , A.CREATED_BY, TO_CHAR(A.CREATION_DATE, 'YYYY-MM-DD HH24:MI:SS') AS CREATION_DATE
     , TO_CHAR(A.LAST_UPDATE_DATE, 'YYYY-MM-DD HH24:MI:SS') AS LAST_UPDATE_DATE
  FROM DM_PLN_CUSTOMER_PSI A, P
 WHERE A.DIVISION_ID  = P.DIV
   AND A.SCM_SITE_ID  = P.SITE
   AND A.PROJECT_CODE = P.PRJ
   AND A.ITEM_ID      = P.ITEM
   AND A.MEASURE      = P.MEA
 ORDER BY A.YYYYMMDD;

-- Q2. ② 계획 원장 DM_PLN_MKT_FCST — DMF0082 가 읽는 행. LAST_UPDATE_DATE 가 '어제 이후' 여야 ③ 배치 대상이 된다
WITH P AS (SELECT '81' DIV, 'STB_DE_MUC' SITE, 'A24ST4001-000' PRJ, 'AMRSAEV20-A2-010' ITEM FROM DUAL)
SELECT A.DIVISION_ID, A.SCM_SITE_ID, A.PLANT_SITE_ID, A.PROJECT_CODE, A.ITEM_ID, A.INCOTERMS, A.FCST_TYPE, A.DOM_EXP
     , A.MEASURE, A.YYYYMMDD, A.QTY, A.ATTRIBUTE1 AS SYNC_RESULT
     , A.CREATED_BY, TO_CHAR(A.CREATION_DATE, 'YYYY-MM-DD HH24:MI:SS') AS CREATION_DATE
     , TO_CHAR(A.LAST_UPDATE_DATE, 'YYYY-MM-DD HH24:MI:SS') AS LAST_UPDATE_DATE
     , CASE WHEN TO_CHAR(A.LAST_UPDATE_DATE, 'YYYYMMDD') >= TO_CHAR(TRUNC(SYSDATE) - 1, 'YYYYMMDD')
            THEN 'Y (배치 대상)' ELSE 'N (어제 이전 갱신 — 배치가 다시 옮기지 않음)' END AS RECORD_TARGET_YN
  FROM DM_PLN_MKT_FCST A, P
 WHERE A.DIVISION_ID  = P.DIV
   AND A.SCM_SITE_ID  = P.SITE
   AND A.PROJECT_CODE = P.PRJ
   AND A.ITEM_ID      = P.ITEM
   AND A.MEASURE IN ('CUST_FCST', 'Customer FCST')
 ORDER BY A.MEASURE, A.YYYYMMDD;

-- Q3. ③ Waterfall 원천 DM_PLN_CUST_FCST_H — 0건이면 원인은 ③ (이력 적재 배치 미실행/실패)
WITH P AS (SELECT '81' DIV, 'STB_DE_MUC' SITE, 'A24ST4001-000' PRJ, 'AMRSAEV20-A2-010' ITEM FROM DUAL)
SELECT A.HISTORY_SEQ, A.DIVISION_ID, A.SCM_SITE_ID, A.PLANT_SITE_ID, A.PROJECT_CODE, A.ITEM_ID
     , A.INCOTERMS, A.FCST_TYPE, A.DOM_EXP, A.MEASURE, A.YYYYMMDD, A.QTY
     , A.CREATE_DATE                                   AS CREATE_DATE_YYYYMMDD   /* 화면 Create Date 기간과 비교되는 값 */
     , A.CREATED_BY
     , TO_CHAR(A.CREATION_DATE, 'YYYY-MM-DD HH24:MI:SS')    AS CREATION_DATE
     , TO_CHAR(A.LAST_UPDATE_DATE, 'YYYY-MM-DD HH24:MI:SS') AS LAST_UPDATE_DATE
  FROM DM_PLN_CUST_FCST_H A, P
 WHERE A.DIVISION_ID  = P.DIV
   AND A.SCM_SITE_ID  = P.SITE
   AND A.PROJECT_CODE = P.PRJ
   AND A.ITEM_ID      = P.ITEM
   AND A.MEASURE IN ('CUST_FCST', 'Customer FCST')
 ORDER BY A.LAST_UPDATE_DATE DESC, A.YYYYMMDD;

-- Q3-2. ③ 81 이력 전체의 마지막 적재 시각 — 오늘 적재가 하나도 없으면 배치가 돌지 않은 것
SELECT A.DIVISION_ID, A.MEASURE, COUNT(*) AS CNT
     , TO_CHAR(MAX(A.LAST_UPDATE_DATE), 'YYYY-MM-DD HH24:MI:SS') AS LAST_LOADED
  FROM DM_PLN_CUST_FCST_H A
 WHERE A.DIVISION_ID IN ('81', '40')
   AND A.MEASURE IN ('CUST_FCST', 'Customer FCST')
   AND A.LAST_UPDATE_DATE >= TRUNC(SYSDATE) - 7
 GROUP BY A.DIVISION_ID, A.MEASURE
 ORDER BY 1, 2;

-- Q4. ③ 스케줄러 잡 상태 — ENABLED=FALSE 또는 STATE=DISABLED 면 이력이 생기지 않는다
SELECT J.OWNER, J.JOB_NAME, J.ENABLED, J.STATE, J.SCHEDULE_NAME, J.REPEAT_INTERVAL
     , TO_CHAR(J.LAST_START_DATE, 'YYYY-MM-DD HH24:MI:SS') AS LAST_START
     , TO_CHAR(J.NEXT_RUN_DATE, 'YYYY-MM-DD HH24:MI:SS')   AS NEXT_RUN
     , J.RUN_COUNT, J.FAILURE_COUNT
  FROM ALL_SCHEDULER_JOBS J
 WHERE J.JOB_NAME LIKE '%EDI_CALLOFF%'
    OR UPPER(J.JOB_ACTION) LIKE '%PR_DM_PLN_CUST_FCST_RECORD%';

-- Q4-2. ③ 잡 스케줄 정의 (AS-IS = 매일 03:20 + 06:20~23:20 30분 간격)
SELECT S.OWNER, S.SCHEDULE_NAME, S.REPEAT_INTERVAL, TO_CHAR(S.START_DATE, 'YYYY-MM-DD HH24:MI:SS') AS START_DATE
  FROM ALL_SCHEDULER_SCHEDULES S
 WHERE S.SCHEDULE_NAME LIKE 'SCH_JOB_PR_DM_DNM_EDI_CALLOFF%';

-- Q4-3. ③ 잡 최근 실행 이력 (최근 20회) — STATUS/ERROR# 확인
SELECT * FROM (
SELECT R.JOB_NAME, R.STATUS, R.ERROR#
     , TO_CHAR(R.ACTUAL_START_DATE, 'YYYY-MM-DD HH24:MI:SS') AS STARTED
     , R.RUN_DURATION, SUBSTR(R.ADDITIONAL_INFO, 1, 300) AS INFO
  FROM ALL_SCHEDULER_JOB_RUN_DETAILS R
 WHERE R.JOB_NAME LIKE '%EDI_CALLOFF%'
 ORDER BY R.ACTUAL_START_DATE DESC
) WHERE ROWNUM <= 20;

-- Q5. ③ 이력 적재 프로시저 실행 로그 (최근 3일) — START/END 가 없으면 실행 안 됨, ERROR 면 실패 사유
SELECT * FROM (
SELECT L.PROGRAM_NAME, L.LOG_TYPE, L.LOG_COUNT, SUBSTR(L.LOG_MESSAGE, 1, 200) AS LOG_MESSAGE
     , L.DESCRIPTION, L.SQL_ERR_CODE, SUBSTR(L.SQL_ERR_MSG, 1, 300) AS SQL_ERR_MSG
     , TO_CHAR(L.EVENT_DATE, 'YYYY-MM-DD HH24:MI:SS') AS EVENT_DATE
  FROM SCM_SYS_LOG_BATCH L
 WHERE L.PROGRAM_NAME IN ('PR_DM_PLN_CUST_FCST_RECORD', 'PR_DM_DNM_EDI_CALLOFF')
   AND L.EVENT_DATE >= TRUNC(SYSDATE) - 3
 ORDER BY L.EVENT_DATE DESC
) WHERE ROWNUM <= 60;

-- Q6. ④ 조회 사용자의 Measure 설정 — CUST_FCST 행이 있어야 'Customer FCST' 가 펼쳐진다
--     (USER_ID 를 Waterfall 을 조회한 사용자 ID 로 바꿔서 실행)
WITH P AS (SELECT 'minyonglee1' USR FROM DUAL)
SELECT U.USER_ID, U.PROGRAM_ID, U.SHEET_NAME, U.COLUMN_NAME, U.USER_INQUIRY_COLUMN_TYPE_CODE
     , M.VALID_YN AS SHEET_MEASURE_VALID_YN
  FROM SCM_MST_TITLESET_USER U
  LEFT OUTER JOIN SCM_MST_SHEET_MEASURE M
    ON M.PROGRAM_ID = U.PROGRAM_ID AND M.SHEET_NAME = U.SHEET_NAME AND M.COLUMN_NAME = U.COLUMN_NAME
     , P
 WHERE U.PROGRAM_ID = 'DMF0053'
   AND U.SHEET_NAME = 'CUST Fcst Waterfall'
   AND U.USER_INQUIRY_COLUMN_TYPE_CODE = 'M'
   AND U.USER_ID    = P.USR
 ORDER BY U.COLUMN_NAME;

-- Q7. ④ 고객 FCST 마스터 — 'Customer FCST' 가 MEASURE_GROUP='CUST_FCST', VALID_YN='Y' 로 있어야 펼침 대상
