-- =====================================================================================
-- DMF0005 81 조회 — Sales Site 'Alte_AB_TES' 동일 Model 7회 반복 진단 (클라우드 실행용 · 읽기 전용)
-- 2026-10-16 · Oracle 19c 호환 · SELECT 만 (DML/DDL 없음) · 전체 F5 실행 가능
-- 사내 ZIOUI1 / AS-IS LGCE_SCMDEV 에는 'Alte_AB_TES' 가 없어 재현 불가 → 클라우드 데이터로 판정
-- 조회 SP 결과 1행 = SCM_MST_SITE_ITEM 1행 × 아래 조인들. 어느 조인이 2건 이상 붙는지 본다.
-- =====================================================================================

-- D00. 클라우드 조회 SP 본문 버전 (사내 BODY 2026-10-14 12:13 · 1992줄 · SPEC 44줄 과 비교)
SELECT O.OBJECT_TYPE, O.STATUS, TO_CHAR(O.LAST_DDL_TIME,'YYYY-MM-DD HH24:MI') LAST_DDL,
       (SELECT COUNT(*) FROM ALL_SOURCE S WHERE S.OWNER = O.OWNER AND S.NAME = O.OBJECT_NAME AND S.TYPE = O.OBJECT_TYPE) LINES
  FROM ALL_OBJECTS O
 WHERE O.OWNER = 'SCM_MGR' AND O.OBJECT_NAME = 'PKG_DMF0005';

-- D01. 원장 행 — 같은 Model 이 프로젝트·팀별로 실제 여러 행인지
SELECT SUBSTR(SI.ITEM_ID,1,25) ITEM_ID, SUBSTR(SI.SCM_SITE_ID,1,20) SITE, SUBSTR(SI.PROJECT_CODE,1,15) PROJECT,
       SUBSTR(SI.DEPT_ID,1,10) DEPT_ID, SI.VALID_YN
  FROM SCM_MST_SITE_ITEM SI
 WHERE SI.DIVISION_ID = '81'
   AND UPPER(SI.SCM_SITE_ID) = UPPER('Alte_AB_TES')
 ORDER BY 1, 3;

-- D02. 원장 1행당 조인별 붙는 건수 (조회 SP BASE 조인 조건과 같음) — 2 이상인 열이 원인
SELECT SUBSTR(SI.ITEM_ID,1,25) ITEM_ID, SUBSTR(SI.PROJECT_CODE,1,15) PROJECT,
       (SELECT COUNT(*) FROM SCM_MST_SITE ST
         WHERE ST.DIVISION_ID = SI.DIVISION_ID AND ST.SCM_SITE_ID = SI.SCM_SITE_ID AND ST.SITE_TYPE = 'SALES') N_SITE,
       (SELECT COUNT(*) FROM SCM_MST_SITE_CUSTOMER SC
         WHERE SC.DIVISION_ID = SI.DIVISION_ID AND UPPER(SC.SCM_SITE_ID) = UPPER(SI.SCM_SITE_ID)
           AND SC.REP_YN = 'Y' AND SC.VALID_YN = 'Y') N_SITE_CUST,
       (SELECT COUNT(*) FROM SCM_MST_SITE_CUSTOMER SC
          JOIN SCM_MST_CUSTOMER CU
            ON CU.DIVISION_ID = SC.DIVISION_ID AND CU.SOLDTO_CODE = SC.SOLDTO_CODE AND CU.SHIPTO_CODE = SC.SHIPTO_CODE
         WHERE SC.DIVISION_ID = SI.DIVISION_ID AND UPPER(SC.SCM_SITE_ID) = UPPER(SI.SCM_SITE_ID)
           AND SC.REP_YN = 'Y' AND SC.VALID_YN = 'Y') N_SC_X_CUST,
       (SELECT COUNT(*) FROM SCM_MST_PROJECT PRJ
         WHERE PRJ.DIVISION_ID = SI.DIVISION_ID AND UPPER(PRJ.PROJECT_CODE) = UPPER(SI.PROJECT_CODE)) N_PROJECT,
       (SELECT COUNT(*) FROM SCM_MST_SSO_DEPT_INFO DI WHERE DI.DEPT_ID = SI.DEPT_ID) N_DEPT,
       (SELECT COUNT(DISTINCT T.ITEM_ID) FROM SCM_MST_ITEM_SN T
         WHERE T.DIVISION_ID = SI.DIVISION_ID
           AND UPPER(RTRIM(T.ITEM_ID, ' ' || UNISTR('\3000'))) = UPPER(RTRIM(SI.ITEM_ID, ' ' || UNISTR('\3000')))) N_ITEM_AGG,
       (SELECT COUNT(*) FROM SCM_ADM_LOOKUP_MASTER_DETAIL L
         WHERE L.LOOKUP_TYPE = 'CELL_TYPE' AND L.VALID_YN = 'Y'
           AND L.SEGMENT1 = (SELECT MAX(T.CELL_TYPE) FROM SCM_MST_ITEM_SN T
                              WHERE T.DIVISION_ID = SI.DIVISION_ID AND T.ITEM_ID = SI.ITEM_ID)) N_CELL_TYPE
  FROM SCM_MST_SITE_ITEM SI
 WHERE SI.DIVISION_ID = '81'
   AND UPPER(SI.SCM_SITE_ID) = UPPER('Alte_AB_TES')
 ORDER BY 1, 2;

-- D03. Site Customer 원장 — N_SITE_CUST 가 7 이면 여기 대표(REP_YN='Y') 행이 7건
SELECT SUBSTR(SC.SCM_SITE_ID,1,20) SITE, SUBSTR(SC.SOLDTO_CODE,1,15) SOLDTO, SUBSTR(SC.SHIPTO_CODE,1,15) SHIPTO,
       SC.REP_YN, SC.VALID_YN, TO_CHAR(SC.LAST_UPDATE_DATE,'YYYY-MM-DD HH24:MI') LAST_UPD, SUBSTR(SC.LAST_UPDATED_BY,1,15) UPD_BY
  FROM SCM_MST_SITE_CUSTOMER SC
 WHERE SC.DIVISION_ID = '81'
   AND UPPER(SC.SCM_SITE_ID) = UPPER('Alte_AB_TES')
 ORDER BY SC.REP_YN DESC, 2, 3;

-- D04. Site 원장 — 같은 사이트가 대소문자/공백 변형으로 여러 건인지
SELECT SUBSTR(ST.SCM_SITE_ID,1,25) SITE, LENGTH(ST.SCM_SITE_ID) LEN, ST.SITE_TYPE, SUBSTR(ST.END_CUSTOMER,1,20) END_CUST
  FROM SCM_MST_SITE ST
 WHERE ST.DIVISION_ID = '81'
   AND UPPER(TRIM(ST.SCM_SITE_ID)) = UPPER('Alte_AB_TES');
