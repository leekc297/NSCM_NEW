SELECT DISTINCT C.DEPT_ID AS CODE
       , CASE @langCd WHEN 'EN' THEN C.DEPT_NAME_EN
                      WHEN 'CN' THEN C.DEPT_NAME_CN
                      ELSE C.DEPT_NAME_KO END AS NAME
  FROM (
        SELECT B.DEPT_ID AS DEPT_ID
          FROM SCM_MST_SITE_ITEM A
             , SCM_MST_SSO_USER_INFO B
         WHERE A.OWNER = B.USER_ID
        UNION
        SELECT A.DEPT_ID AS DEPT_ID
          FROM SCM_MST_SITE A
         WHERE A.SITE_TYPE = 'SALES'
       ) S
  JOIN SCM_MST_SSO_DEPT_INFO C ON C.DEPT_ID = S.DEPT_ID
 ORDER BY NAME