-- 82 사업부 — Sales Plan 의 RTF 수량이 실제로 바뀌었는가 (클라우드 확인용 4차)
--   읽기 전용(SELECT 만) · 전체 실행(F5) 가능 · 값 입력 없음 · 글자 컬럼은 잘라서 출력
--   작성 2026-10-13 · 사내오라클(59.19.252.148 ZIOUI1)에서 4문장 실행 확인 (사내는 82 최근 데이터가 없어 0건 위주)
--   확인 방법 2가지
--     (가) 지금 Sales Plan 과 수요 원장을 행 단위로 대조 — 동기화가 원장을 그대로 옮겼는지
--     (나) 지금 Sales Plan 과 가장 최근 마감 스냅샷(DM_PLN_SALES_PLAN_C)을 행 단위로 대조 — 저장 전과 비교
--   범위 = 82 · 당주 월요일 이후 · 품목 마스터(SCM_MST_ITEM_SN)에 있는 품목 (동기화 프로시저와 같은 범위)
-- =====================================================================================================

-- W1. (가) Sales Plan ↔ 수요 원장 — 메저별 일치 / 수량 다름 / 한쪽에만 있음
SELECT 'W1' AS Q, NVL(P.MEASURE, L.MEASURE) AS MEASURE
     , SUM(CASE WHEN P.K_YMD IS NOT NULL AND L.K_YMD IS NOT NULL AND P.QTY = L.QTY THEN 1 ELSE 0 END) AS SAME_ROWS
     , SUM(CASE WHEN P.K_YMD IS NOT NULL AND L.K_YMD IS NOT NULL AND P.QTY <> L.QTY THEN 1 ELSE 0 END) AS QTY_DIFF_ROWS
     , SUM(CASE WHEN L.K_YMD IS NULL THEN 1 ELSE 0 END) AS ONLY_SALES_PLAN
     , SUM(CASE WHEN P.K_YMD IS NULL THEN 1 ELSE 0 END) AS ONLY_LEDGER
     , SUM(P.QTY) AS SALES_PLAN_QTY, SUM(L.QTY) AS LEDGER_QTY
FROM   ( SELECT S.PROJECT_CODE, S.SCM_SITE_ID, S.ITEM_ID, S.DOM_EXP, S.FCST_TYPE, S.INCOTERMS, S.PLANT_SITE_ID, S.MEASURE, S.YYYYMMDD AS K_YMD, SUM(S.QTY) AS QTY
         FROM   SCM_MGR.DM_PLN_SALES_PLAN S
         WHERE  S.DIVISION_ID = '82' AND S.MEASURE IN ('RTF', 'RTF_SYS_RP', 'MKT_FCST')
         AND    S.YYYYMMDD >= TO_CHAR(TRUNC(SYSDATE, 'IW'), 'YYYYMMDD')
         AND    S.ITEM_ID IN ( SELECT N.ITEM_ID FROM SCM_MGR.SCM_MST_ITEM_SN N )
         GROUP BY S.PROJECT_CODE, S.SCM_SITE_ID, S.ITEM_ID, S.DOM_EXP, S.FCST_TYPE, S.INCOTERMS, S.PLANT_SITE_ID, S.MEASURE, S.YYYYMMDD ) P
FULL OUTER JOIN
       ( SELECT F.PROJECT_CODE, F.SCM_SITE_ID, F.ITEM_ID, F.DOM_EXP, F.FCST_TYPE, F.INCOTERMS, F.PLANT_SITE_ID, F.MEASURE, F.YYYYMMDD AS K_YMD, SUM(F.QTY) AS QTY
         FROM   SCM_MGR.DM_PLN_MKT_FCST F
         WHERE  F.DIVISION_ID = '82' AND F.MEASURE IN ('RTF', 'RTF_SYS_RP', 'MKT_FCST')
         AND    F.YYYYMMDD >= TO_CHAR(TRUNC(SYSDATE, 'IW'), 'YYYYMMDD')
         AND    F.ITEM_ID IN ( SELECT N.ITEM_ID FROM SCM_MGR.SCM_MST_ITEM_SN N )
         GROUP BY F.PROJECT_CODE, F.SCM_SITE_ID, F.ITEM_ID, F.DOM_EXP, F.FCST_TYPE, F.INCOTERMS, F.PLANT_SITE_ID, F.MEASURE, F.YYYYMMDD ) L
       ON  L.PROJECT_CODE = P.PROJECT_CODE AND L.SCM_SITE_ID = P.SCM_SITE_ID AND L.ITEM_ID = P.ITEM_ID AND L.DOM_EXP = P.DOM_EXP
       AND L.FCST_TYPE = P.FCST_TYPE AND L.INCOTERMS = P.INCOTERMS AND L.PLANT_SITE_ID = P.PLANT_SITE_ID
       AND L.MEASURE = P.MEASURE AND L.K_YMD = P.K_YMD
GROUP BY NVL(P.MEASURE, L.MEASURE)
ORDER BY 2;

-- W2. 원장의 82 RTF 계열이 마지막으로 기록된 시각 (당주 이후 전 행) — 저장(10-13 13:42) 이후 기록이 있는지
SELECT 'W2' AS Q, SUBSTR(F.MEASURE, 1, 14) AS MEASURE, SUBSTR(F.LAST_UPDATED_BY, 1, 14) AS UPD_BY
     , TO_CHAR(MIN(F.LAST_UPDATE_DATE), 'MM-DD HH24:MI:SS') AS FIRST_AT, TO_CHAR(MAX(F.LAST_UPDATE_DATE), 'MM-DD HH24:MI:SS') AS LAST_AT
     , COUNT(*) AS CNT, SUM(F.QTY) AS QTY_SUM
FROM   SCM_MGR.DM_PLN_MKT_FCST F
WHERE  F.DIVISION_ID = '82' AND F.MEASURE IN ('RTF', 'RTF_SYS_RP')
AND    F.YYYYMMDD >= TO_CHAR(TRUNC(SYSDATE, 'IW'), 'YYYYMMDD')
GROUP BY F.MEASURE, F.LAST_UPDATED_BY
ORDER BY 2, 3;

-- W3. 82 Sales Plan 마감 스냅샷 버전 최근 10일 — (나) 비교에 쓸 버전 확인
SELECT 'W3' AS Q, SUBSTR(C.VERSION_NO, 1, 30) AS VERSION_NO, SUBSTR(C.CUTOFF_TYPE, 1, 10) AS CUTOFF_TYPE, C.CUTOFF_YYYYMMDD
     , COUNT(*) AS CNT, SUM(CASE WHEN C.MEASURE IN ('RTF', 'RTF_SYS_RP') THEN 1 ELSE 0 END) AS RTF_ROWS
     , TO_CHAR(MAX(C.LAST_UPDATE_DATE), 'MM-DD HH24:MI:SS') AS SRC_LAST_UPD
FROM   SCM_MGR.DM_PLN_SALES_PLAN_C C
WHERE  C.DIVISION_ID = '82'
AND    C.CUTOFF_YYYYMMDD_DATE >= TRUNC(SYSDATE) - 10
GROUP BY C.VERSION_NO, C.CUTOFF_TYPE, C.CUTOFF_YYYYMMDD
ORDER BY C.CUTOFF_YYYYMMDD DESC, C.VERSION_NO DESC
FETCH FIRST 20 ROWS ONLY;

-- W4. (나) 지금 Sales Plan ↔ 가장 최근 마감 스냅샷 — RTF · RTF_SYS_RP 행 단위 대조 (당주 월요일 이후)
--     SRC_LAST_UPD 가 10-13 13:42 보다 앞이면 그 스냅샷은 저장 전 상태다 (W3 에서 확인)
SELECT 'W4' AS Q, NVL(P.MEASURE, C.MEASURE) AS MEASURE, MAX(C.VERSION_NO) AS SNAPSHOT_VERSION
     , SUM(CASE WHEN P.K_YMD IS NOT NULL AND C.K_YMD IS NOT NULL AND P.QTY = C.QTY THEN 1 ELSE 0 END) AS SAME_ROWS
     , SUM(CASE WHEN P.K_YMD IS NOT NULL AND C.K_YMD IS NOT NULL AND P.QTY <> C.QTY THEN 1 ELSE 0 END) AS QTY_DIFF_ROWS
     , SUM(CASE WHEN C.K_YMD IS NULL THEN 1 ELSE 0 END) AS ONLY_NOW
     , SUM(CASE WHEN P.K_YMD IS NULL THEN 1 ELSE 0 END) AS ONLY_SNAPSHOT
     , SUM(P.QTY) AS NOW_QTY, SUM(C.QTY) AS SNAPSHOT_QTY
FROM   ( SELECT S.PROJECT_CODE, S.SCM_SITE_ID, S.ITEM_ID, S.DOM_EXP, S.FCST_TYPE, S.INCOTERMS, S.PLANT_SITE_ID, S.MEASURE, S.YYYYMMDD AS K_YMD, SUM(S.QTY) AS QTY
         FROM   SCM_MGR.DM_PLN_SALES_PLAN S
         WHERE  S.DIVISION_ID = '82' AND S.MEASURE IN ('RTF', 'RTF_SYS_RP')
         AND    S.YYYYMMDD >= TO_CHAR(TRUNC(SYSDATE, 'IW'), 'YYYYMMDD')
         GROUP BY S.PROJECT_CODE, S.SCM_SITE_ID, S.ITEM_ID, S.DOM_EXP, S.FCST_TYPE, S.INCOTERMS, S.PLANT_SITE_ID, S.MEASURE, S.YYYYMMDD ) P
FULL OUTER JOIN
       ( SELECT X.VERSION_NO, X.PROJECT_CODE, X.SCM_SITE_ID, X.ITEM_ID, X.DOM_EXP, X.FCST_TYPE, X.INCOTERMS, X.PLANT_SITE_ID, X.MEASURE, X.YYYYMMDD AS K_YMD, SUM(X.QTY) AS QTY
         FROM   SCM_MGR.DM_PLN_SALES_PLAN_C X
         WHERE  X.DIVISION_ID = '82' AND X.MEASURE IN ('RTF', 'RTF_SYS_RP')
         AND    X.CUTOFF_YYYYMMDD_DATE >= TRUNC(SYSDATE) - 10
         AND    X.YYYYMMDD >= TO_CHAR(TRUNC(SYSDATE, 'IW'), 'YYYYMMDD')
         AND    X.VERSION_NO = ( SELECT MAX(V.VERSION_NO) KEEP (DENSE_RANK LAST ORDER BY V.CUTOFF_YYYYMMDD, V.VERSION_NO)
                                 FROM   SCM_MGR.DM_PLN_SALES_PLAN_C V
                                 WHERE  V.DIVISION_ID = '82' AND V.CUTOFF_YYYYMMDD_DATE >= TRUNC(SYSDATE) - 10 )
         GROUP BY X.VERSION_NO, X.PROJECT_CODE, X.SCM_SITE_ID, X.ITEM_ID, X.DOM_EXP, X.FCST_TYPE, X.INCOTERMS, X.PLANT_SITE_ID, X.MEASURE, X.YYYYMMDD ) C
       ON  C.PROJECT_CODE = P.PROJECT_CODE AND C.SCM_SITE_ID = P.SCM_SITE_ID AND C.ITEM_ID = P.ITEM_ID AND C.DOM_EXP = P.DOM_EXP
       AND C.FCST_TYPE = P.FCST_TYPE AND C.INCOTERMS = P.INCOTERMS AND C.PLANT_SITE_ID = P.PLANT_SITE_ID
       AND C.MEASURE = P.MEASURE AND C.K_YMD = P.K_YMD
GROUP BY NVL(P.MEASURE, C.MEASURE)
ORDER BY 2;
