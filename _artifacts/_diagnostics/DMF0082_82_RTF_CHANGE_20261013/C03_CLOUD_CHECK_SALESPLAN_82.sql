-- 82 사업부 — 저장 1건이 Sales Plan 을 어디까지 다시 쓰는가 (클라우드 확인용 3차)
--   읽기 전용(SELECT 만) · 전체 실행(F5) 가능 · 값 입력 없음 · 글자 컬럼은 잘라서 출력
--   작성 2026-10-13 · 사내오라클(59.19.252.148 ZIOUI1)에서 4문장 실행 확인
--   2차(C02) 결과: 13:42:52 k0101 저장 때 다른 사용자가 저장한 다른 품목(ABB_US_RIC)의 Sales Plan 행까지
--                 수정자 k0101 로 다시 기록됐다. 사내 원문의 동기화 프로시저에는 82 분기가 없다 → 클라우드 실제 동작 확인.
-- =====================================================================================================

-- U1. 82 Sales Plan 이 최근 3일 사이 다시 기록된 묶음 — 초 단위 · 수정자 · 메저별로 몇 품목이 함께 쓰였는가
SELECT 'U1' AS Q, TO_CHAR(S.LAST_UPDATE_DATE, 'MM-DD HH24:MI:SS') AS UPD_AT, SUBSTR(S.LAST_UPDATED_BY, 1, 14) AS UPD_BY, SUBSTR(S.MEASURE, 1, 14) AS MEASURE
     , COUNT(*) AS CNT, COUNT(DISTINCT S.PROJECT_CODE || '|' || S.SCM_SITE_ID || '|' || S.ITEM_ID || '|' || S.FCST_TYPE) AS ITEMS
     , MIN(S.YYYYMMDD) AS YMD_FROM, MAX(S.YYYYMMDD) AS YMD_TO
FROM   SCM_MGR.DM_PLN_SALES_PLAN S
WHERE  S.DIVISION_ID = '82' AND S.LAST_UPDATE_DATE >= TRUNC(SYSDATE) - 3
GROUP BY S.LAST_UPDATE_DATE, S.LAST_UPDATED_BY, S.MEASURE
ORDER BY S.LAST_UPDATE_DATE DESC, S.MEASURE
FETCH FIRST 80 ROWS ONLY;

-- U2. 가장 최근 82 Sales Plan 기록 묶음에 들어 있는 품목 (같은 초에 함께 다시 쓰인 품목 전부)
SELECT 'U2' AS Q, SUBSTR(S.PROJECT_CODE, 1, 20) AS PROJECT_CODE, SUBSTR(S.SCM_SITE_ID, 1, 22) AS SCM_SITE_ID, SUBSTR(S.ITEM_ID, 1, 20) AS ITEM_ID, S.FCST_TYPE
     , SUBSTR(S.MEASURE, 1, 14) AS MEASURE, SUBSTR(S.LAST_UPDATED_BY, 1, 14) AS UPD_BY, COUNT(*) AS CNT, MIN(S.YYYYMMDD) AS YMD_FROM, MAX(S.YYYYMMDD) AS YMD_TO, SUM(S.QTY) AS QTY_SUM
     , TO_CHAR(MAX(S.CREATION_DATE), 'MM-DD HH24:MI:SS') AS CREATED_AT, SUBSTR(MAX(S.CREATED_BY), 1, 14) AS CREATED_BY
FROM   SCM_MGR.DM_PLN_SALES_PLAN S
WHERE  S.DIVISION_ID = '82'
AND    S.LAST_UPDATE_DATE >= ( SELECT MAX(X.LAST_UPDATE_DATE) - 10 / 86400 FROM SCM_MGR.DM_PLN_SALES_PLAN X
                               WHERE X.DIVISION_ID = '82' AND X.LAST_UPDATE_DATE >= TRUNC(SYSDATE) - 3 )
GROUP BY S.PROJECT_CODE, S.SCM_SITE_ID, S.ITEM_ID, S.FCST_TYPE, S.MEASURE, S.LAST_UPDATED_BY
ORDER BY S.SCM_SITE_ID, S.ITEM_ID, S.MEASURE
FETCH FIRST 100 ROWS ONLY;

-- U3. 그 저장 시각 전후로 기록을 남긴 프로시저 (어떤 프로시저가 Sales Plan 을 썼는지 · 단계별 건수)
SELECT 'U3' AS Q, TO_CHAR(B.EVENT_DATE, 'MM-DD HH24:MI:SS') AS T, SUBSTR(B.PROGRAM_NAME, 1, 56) AS PROGRAM_NAME, SUBSTR(B.LOG_TYPE, 1, 8) AS LOG_TYPE
     , B.LOG_COUNT AS CNT, SUBSTR(REPLACE(B.LOG_MESSAGE, CHR(10), ' '), 1, 70) AS MSG, SUBSTR(B.IN_PARA_DATA, 1, 50) AS PARAMS
FROM   SCM_MGR.SCM_SYS_LOG_BATCH B
WHERE  B.EVENT_DATE BETWEEN ( SELECT MAX(X.LAST_UPDATE_DATE) - 15 / 86400 FROM SCM_MGR.DM_PLN_SALES_PLAN X
                              WHERE X.DIVISION_ID = '82' AND X.LAST_UPDATE_DATE >= TRUNC(SYSDATE) - 3 )
                        AND ( SELECT MAX(X.LAST_UPDATE_DATE) + 5 / 86400 FROM SCM_MGR.DM_PLN_SALES_PLAN X
                              WHERE X.DIVISION_ID = '82' AND X.LAST_UPDATE_DATE >= TRUNC(SYSDATE) - 3 )
AND    B.PROGRAM_NAME NOT LIKE 'PKG_DMF0082%'
ORDER BY B.EVENT_DATE, B.PROGRAM_NAME
FETCH FIRST 120 ROWS ONLY;

-- U4. 동기화 프로시저 · 저장 패키지의 클라우드 원문 — 사업부 분기 줄과 마지막 변경 시각
--     사내: 동기화 프로시저는 40 과 81 분기만 있다 (108행 IF 40 · 248행 ELSIF 81). 82 를 처리하는 줄이 있는지 본다.
SELECT 'U4' AS Q, SUBSTR(S.NAME, 1, 56) AS NAME, S.LINE
     , ( SELECT TO_CHAR(MAX(O.LAST_DDL_TIME), 'MM-DD HH24:MI') FROM ALL_OBJECTS O WHERE O.OWNER = S.OWNER AND O.OBJECT_NAME = S.NAME AND O.OBJECT_TYPE = S.TYPE ) AS LAST_DDL
     , SUBSTR(LTRIM(REPLACE(RTRIM(S.TEXT, CHR(10)), CHR(9), ' ')), 1, 120) AS TEXT
FROM   ALL_SOURCE S
WHERE  S.OWNER = 'SCM_MGR'
AND    (    ( S.NAME IN ('PR_DM_ANL_SALES_PLAN_AMT_CREATE_LOCAL_KRW_MKT_FCST_SAVE') AND S.TYPE = 'PROCEDURE'
              AND REGEXP_LIKE(S.TEXT, '^\s*(IF|ELSIF)\s*\(.*V_DIVISION_ID|^\s*ELSE\s*$|FROM\s+GT_PRDM_RESULTS|E20260930-DMF0082-81SP', 'i') )
         OR ( S.NAME = 'PKG_DMF0082' AND S.TYPE = 'PACKAGE BODY'
              AND REGEXP_LIKE(S.TEXT, 'SALES_PLAN_AMT_CREATE|DELETE FROM SCM_MGR.GT_PRDM_RESULTS|INSERT INTO SCM_MGR.GT_PRDM_RESULTS|v_is_81\s*:=|E20260930-DMF0082-81SP', 'i') ) )
ORDER BY S.NAME, S.LINE
FETCH FIRST 80 ROWS ONLY;
