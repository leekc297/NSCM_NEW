-- =====================================================================================================
-- 82 사업부 — MKT_FCST 수정 뒤 RTF 계열 메저가 바뀐 주체 확인 (클라우드 확인용)
--   읽기 전용(SELECT 만) · 전체 실행(F5) 가능 · 값 입력 없음 · 글자 컬럼은 잘라서 출력
--   작성 2026-10-13 · 사내오라클(59.19.252.148 ZIOUI1)에서 4문장 실행 확인 (사내는 최근 82 저장이 없어 S1~S3 0건)
--   대상 = 최근 3일 안에 사람이 MKT_FCST 를 저장한 82 품목 (자동으로 고른다)
-- =====================================================================================================

-- S1. 최근 3일 사람이 저장한 82 MKT_FCST 품목 — 언제 · 누가 · VMI 사이트 여부 · RMA 여부
SELECT 'S1' AS Q, SUBSTR(K.PROJECT_CODE, 1, 24) AS PROJECT_CODE, SUBSTR(K.SCM_SITE_ID, 1, 26) AS SCM_SITE_ID, SUBSTR(K.ITEM_ID, 1, 22) AS ITEM_ID
     , K.FCST_TYPE, K.SAVED_BY, K.SAVED_AT, K.ROWS_SAVED
     , ( SELECT MAX(S.VMI_YN) FROM SCM_MGR.SCM_MST_SITE S WHERE S.DIVISION_ID = '82' AND S.SCM_SITE_ID = K.SCM_SITE_ID ) AS VMI_YN
FROM   ( SELECT A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.FCST_TYPE
              , MAX(A.LAST_UPDATED_BY) KEEP (DENSE_RANK LAST ORDER BY A.LAST_UPDATE_DATE) AS SAVED_BY
              , TO_CHAR(MAX(A.LAST_UPDATE_DATE), 'MM-DD HH24:MI:SS') AS SAVED_AT
              , COUNT(*) AS ROWS_SAVED
         FROM   SCM_MGR.DM_PLN_MKT_FCST A
         WHERE  A.DIVISION_ID = '82' AND A.MEASURE = 'MKT_FCST'
         AND    A.LAST_UPDATE_DATE >= TRUNC(SYSDATE) - 3
         AND    UPPER(A.LAST_UPDATED_BY) NOT IN ('SYSTEM', 'CUTOFF', 'BALANCE_MAKE', 'SCM_BATCH', 'DMF0082_SYSTEM')
         GROUP BY A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.FCST_TYPE ) K
ORDER BY K.SAVED_AT DESC
FETCH FIRST 30 ROWS ONLY;

-- S2. 위 품목의 RTF 계열 · BALANCE 메저가 언제 · 누구 이름으로 다시 기록됐는가 (분 단위 묶음)
--     수정자 SYSTEM = 배치(밸런스 프로시저의 비화면 경로) 또는 RMA 복사 / BALANCE_MAKE = 밸런스 재계산
SELECT 'S2' AS Q, SUBSTR(F.SCM_SITE_ID, 1, 26) AS SCM_SITE_ID, SUBSTR(F.ITEM_ID, 1, 22) AS ITEM_ID, F.FCST_TYPE, F.MEASURE
     , F.LAST_UPDATED_BY AS UPD_BY, TO_CHAR(TRUNC(F.LAST_UPDATE_DATE, 'MI'), 'MM-DD HH24:MI') AS UPD_AT
     , COUNT(*) AS CNT, MIN(F.YYYYMMDD) AS YMD_FROM, MAX(F.YYYYMMDD) AS YMD_TO, SUM(F.QTY) AS QTY_SUM
FROM   SCM_MGR.DM_PLN_MKT_FCST F
WHERE  F.DIVISION_ID = '82'
AND    ( F.MEASURE LIKE 'RTF%' OR F.MEASURE IN ('MKT_FCST', 'BALANCE', 'VMI_Inv', 'VMI_In_Plan') )
AND    F.YYYYMMDD >= TO_CHAR(TRUNC(SYSDATE, 'IW'), 'YYYYMMDD')
AND    ( F.PROJECT_CODE, F.SCM_SITE_ID, F.ITEM_ID, F.FCST_TYPE ) IN
       ( SELECT A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.FCST_TYPE
         FROM   SCM_MGR.DM_PLN_MKT_FCST A
         WHERE  A.DIVISION_ID = '82' AND A.MEASURE = 'MKT_FCST'
         AND    A.LAST_UPDATE_DATE >= TRUNC(SYSDATE) - 3
         AND    UPPER(A.LAST_UPDATED_BY) NOT IN ('SYSTEM', 'CUTOFF', 'BALANCE_MAKE', 'SCM_BATCH', 'DMF0082_SYSTEM') )
GROUP BY F.SCM_SITE_ID, F.ITEM_ID, F.FCST_TYPE, F.MEASURE, F.LAST_UPDATED_BY, TRUNC(F.LAST_UPDATE_DATE, 'MI')
ORDER BY F.SCM_SITE_ID, F.ITEM_ID, F.FCST_TYPE, TRUNC(F.LAST_UPDATE_DATE, 'MI'), F.MEASURE
FETCH FIRST 200 ROWS ONLY;

-- S3. 밸런스 프로시저 실행 기록 최근 3일 — 82 로 돈 것 (p_plan_id 가 CALL = 화면 저장 / 그 외 = 배치)
SELECT 'S3' AS Q, TO_CHAR(B.EVENT_DATE, 'MM-DD HH24:MI:SS') AS T, B.LOG_TYPE, SUBSTR(B.IN_PARA_DATA, 1, 60) AS PARAMS, SUBSTR(B.CREATED_BY, 1, 20) AS RUN_BY
FROM   SCM_MGR.SCM_SYS_LOG_BATCH B
WHERE  B.PROGRAM_NAME = 'PR_DM_PLN_MKT_FCST_QTY_BALANCE_CREATE'
AND    B.LOG_TYPE IN ('START', 'END', 'ERROR')
AND    B.EVENT_DATE >= TRUNC(SYSDATE) - 3
AND    B.IN_PARA_DATA LIKE '%"82"%'
ORDER BY B.EVENT_DATE DESC
FETCH FIRST 60 ROWS ONLY;

-- S4. DMF0082 저장 프로시저 실행 기록 최근 3일 (시작 · 종료 · 오류) — S2 의 갱신 시각과 맞춰 본다
SELECT 'S4' AS Q, TO_CHAR(B.EVENT_DATE, 'MM-DD HH24:MI:SS') AS T, B.LOG_TYPE, SUBSTR(B.LOG_MESSAGE, 1, 60) AS MSG, SUBSTR(B.CREATED_BY, 1, 20) AS RUN_BY
FROM   SCM_MGR.SCM_SYS_LOG_BATCH B
WHERE  B.PROGRAM_NAME = 'PKG_DMF0082'
AND    B.LOG_TYPE IN ('START', 'END', 'ERROR', 'INVALID')
AND    B.EVENT_DATE >= TRUNC(SYSDATE) - 3
ORDER BY B.EVENT_DATE DESC
FETCH FIRST 60 ROWS ONLY;
