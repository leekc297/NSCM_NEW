-- 82 사업부 — MKT_FCST 를 저장한 품목의 전체 메저 현황 (클라우드 확인용 2차)
--   읽기 전용(SELECT 만) · 전체 실행(F5) 가능 · 값 입력 없음 · 글자 컬럼은 잘라서 출력
--   작성 2026-10-13 · 사내오라클(59.19.252.148 ZIOUI1)에서 2문장 실행 확인 (사내는 최근 82 저장이 없어 0건)
--   1차(C01) 결과: 저장한 두 품목은 당주 이후 원장에 RTF 계열 행이 아예 없었다 → 과거 일자 · 다른 테이블까지 넓혀 본다.
--   대상 = 최근 3일 안에 사람이 MKT_FCST 를 저장한 82 품목 (자동으로 고른다)
-- =====================================================================================================

-- T1. 세 테이블(수요 원장 · 40형 수요 원장 · Sales Plan)에서 그 품목의 메저별 현황 — 일자 제한 없음
--     UPD_DAY = 마지막으로 기록된 날 / RTF 계열이 어느 테이블에, 언제, 누구 이름으로 있는지 본다
SELECT 'T1' AS Q, X.TBL, SUBSTR(X.SCM_SITE_ID, 1, 22) AS SCM_SITE_ID, SUBSTR(X.ITEM_ID, 1, 20) AS ITEM_ID, X.FCST_TYPE, SUBSTR(X.MEASURE, 1, 14) AS MEASURE
     , SUBSTR(X.LAST_UPDATED_BY, 1, 14) AS UPD_BY, TO_CHAR(TRUNC(X.LAST_UPDATE_DATE), 'MM-DD') AS UPD_DAY
     , COUNT(*) AS CNT, MIN(X.YYYYMMDD) AS YMD_FROM, MAX(X.YYYYMMDD) AS YMD_TO, SUM(X.QTY) AS QTY_SUM
     , TO_CHAR(MAX(X.LAST_UPDATE_DATE), 'MM-DD HH24:MI:SS') AS LAST_AT
FROM   ( SELECT 'MKT_FCST' AS TBL, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, FCST_TYPE, MEASURE, YYYYMMDD, QTY, LAST_UPDATED_BY, LAST_UPDATE_DATE
         FROM   SCM_MGR.DM_PLN_MKT_FCST WHERE DIVISION_ID = '82'
         UNION ALL
         SELECT 'CFM_DEMAND', PROJECT_CODE, SCM_SITE_ID, ITEM_ID, FCST_TYPE, MEASURE, YYYYMMDD, QTY, LAST_UPDATED_BY, LAST_UPDATE_DATE
         FROM   SCM_MGR.DM_PLN_CFM_MKT_DEMAND_PLAN WHERE DIVISION_ID = '82'
         UNION ALL
         SELECT 'SALES_PLAN', PROJECT_CODE, SCM_SITE_ID, ITEM_ID, FCST_TYPE, MEASURE, YYYYMMDD, QTY, LAST_UPDATED_BY, LAST_UPDATE_DATE
         FROM   SCM_MGR.DM_PLN_SALES_PLAN WHERE DIVISION_ID = '82' ) X
WHERE  ( X.PROJECT_CODE, X.SCM_SITE_ID, X.ITEM_ID, X.FCST_TYPE ) IN
       ( SELECT A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.FCST_TYPE
         FROM   SCM_MGR.DM_PLN_MKT_FCST A
         WHERE  A.DIVISION_ID = '82' AND A.MEASURE = 'MKT_FCST'
         AND    A.LAST_UPDATE_DATE >= TRUNC(SYSDATE) - 3
         AND    UPPER(A.LAST_UPDATED_BY) NOT IN ('SYSTEM', 'CUTOFF', 'BALANCE_MAKE', 'SCM_BATCH', 'DMF0082_SYSTEM') )
GROUP BY X.TBL, X.SCM_SITE_ID, X.ITEM_ID, X.FCST_TYPE, X.MEASURE, X.LAST_UPDATED_BY, TRUNC(X.LAST_UPDATE_DATE)
ORDER BY X.SCM_SITE_ID, X.ITEM_ID, X.FCST_TYPE, X.TBL, X.MEASURE, TRUNC(X.LAST_UPDATE_DATE)
FETCH FIRST 300 ROWS ONLY;

-- T2. 82 수요 원장에서 RTF 계열 메저가 최근 7일 사이 기록된 내역 (품목 무관 · 날짜별 · 수정자별)
--     RTF 계열을 실제로 쓰고 있는 주체와 시각을 본다 (C01 의 S3 배치 실행 시각 10-12 09:57 · 17:49 와 맞춰 본다)
SELECT 'T2' AS Q, SUBSTR(F.MEASURE, 1, 14) AS MEASURE, SUBSTR(F.LAST_UPDATED_BY, 1, 14) AS UPD_BY
     , TO_CHAR(TRUNC(F.LAST_UPDATE_DATE, 'HH24'), 'MM-DD HH24') AS UPD_HOUR
     , COUNT(*) AS CNT, COUNT(DISTINCT F.SCM_SITE_ID || '|' || F.ITEM_ID) AS ITEMS, MIN(F.YYYYMMDD) AS YMD_FROM, MAX(F.YYYYMMDD) AS YMD_TO
FROM   SCM_MGR.DM_PLN_MKT_FCST F
WHERE  F.DIVISION_ID = '82' AND F.MEASURE LIKE 'RTF%'
AND    F.LAST_UPDATE_DATE >= TRUNC(SYSDATE) - 7
GROUP BY F.MEASURE, F.LAST_UPDATED_BY, TRUNC(F.LAST_UPDATE_DATE, 'HH24')
ORDER BY TRUNC(F.LAST_UPDATE_DATE, 'HH24') DESC, F.MEASURE
FETCH FIRST 100 ROWS ONLY;
