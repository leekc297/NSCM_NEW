SET SERVEROUTPUT ON SIZE UNLIMITED FEEDBACK ON DEFINE OFF
SET LINESIZE 32767 PAGESIZE 0 LONG 100000000 LONGCHUNKSIZE 32767 TRIMSPOOL ON
SET HEADING OFF
SPOOL /tmp/vsql_dump.txt
DECLARE
  v_src CLOB;
  v_patched CLOB;
  v_pl NUMBER;
  v_al NUMBER;
BEGIN
  DBMS_LOB.CREATETEMPORARY(v_src, TRUE);
  FOR rec IN (SELECT TEXT FROM USER_SOURCE WHERE NAME='DMF0043_GET_CONTRIBUTION_SALES_LIST' AND TYPE='PROCEDURE' ORDER BY LINE) LOOP
    DBMS_LOB.APPEND(v_src, rec.TEXT);
  END LOOP;
  v_pl := DBMS_LOB.GETLENGTH(v_src);
  v_patched := REPLACE(v_src, 'OPEN p_cursor_main FOR v_sql_text;', 'INSERT INTO SCM_MGR.DBG_VSQL_DUMP(ID, TS, BODY) VALUES (1, SYSTIMESTAMP, v_sql_text); COMMIT; OPEN p_cursor_main FOR v_sql_text;');
  v_al := DBMS_LOB.GETLENGTH(v_patched);
  DBMS_OUTPUT.PUT_LINE('s=' || v_pl || ' p=' || v_al);
  IF v_al > v_pl THEN
    EXECUTE IMMEDIATE 'CREATE OR REPLACE ' || v_patched;
    DBMS_OUTPUT.PUT_LINE('PATCHED');
  END IF;
END;
/
SPOOL OFF
EXIT
