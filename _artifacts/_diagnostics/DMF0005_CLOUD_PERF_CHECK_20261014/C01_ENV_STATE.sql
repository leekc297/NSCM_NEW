PROMPT ################ [E7b] 조인 상대 원장 행 수 — 사업부별 ################
SELECT 'SCM_MST_ITEM_SN' TABLE_NAME, DIVISION_ID, COUNT(*) ROWS_, COUNT(DISTINCT ITEM_ID) KEYS FROM SCM_MST_ITEM_SN GROUP BY DIVISION_ID
UNION ALL SELECT 'SCM_MST_SITE_CUSTOMER', DIVISION_ID, COUNT(*), SUM(CASE WHEN REP_YN = 'Y' AND VALID_YN = 'Y' THEN 1 ELSE 0 END) FROM SCM_MST_SITE_CUSTOMER GROUP BY DIVISION_ID
UNION ALL SELECT 'SCM_MST_SITE', DIVISION_ID, COUNT(*), SUM(CASE WHEN SITE_TYPE = 'SALES' THEN 1 ELSE 0 END) FROM SCM_MST_SITE GROUP BY DIVISION_ID
UNION ALL SELECT 'SCM_MST_PROJECT', DIVISION_ID, COUNT(*), COUNT(DISTINCT UPPER(PROJECT_CODE)) FROM SCM_MST_PROJECT GROUP BY DIVISION_ID
UNION ALL SELECT 'SCM_MST_CUSTOMER', DIVISION_ID, COUNT(*), COUNT(DISTINCT SOLDTO_CODE || '/' || SHIPTO_CODE) FROM SCM_MST_CUSTOMER GROUP BY DIVISION_ID
UNION ALL SELECT 'DM_MST_CUSTOMER_MODEL', DIVISION_ID, COUNT(*), SUM(CASE WHEN VALID_YN = 'Y' THEN 1 ELSE 0 END) FROM DM_MST_CUSTOMER_MODEL GROUP BY DIVISION_ID
UNION ALL SELECT 'SCM_MST_SSO_USER_INFO', '-', COUNT(*), COUNT(DISTINCT UPPER(USER_ID)) FROM SCM_MST_SSO_USER_INFO
UNION ALL SELECT 'SCM_MST_SSO_DEPT_INFO', '-', COUNT(*), COUNT(DISTINCT DEPT_ID) FROM SCM_MST_SSO_DEPT_INFO
ORDER BY 1, 2;
PROMPT --  KEYS 열: ITEM_SN = 품목 종류 · SITE_CUSTOMER = 대표 · 유효 행 · SITE = SALES 사이트 · PROJECT = 프로젝트 종류 · CUSTOMER = Sold-To / Ship-To 쌍 · CUSTOMER_MODEL = 유효 행

PROMPT ################ [E7c] ⭐ 조인 키 중복 — 결과 행을 불리는 조인이 있나 (0행이 정상에 가깝다) ################
PROMPT --  SITE_CUSTOMER 대표(REP_YN = Y · VALID_YN = Y)가 사이트당 2행 이상이면 그 사이트의 SITE_ITEM 행이 그만큼 불어난다
SELECT 'SITE_CUSTOMER 대표 2행 이상' CHK, DIVISION_ID, COUNT(*) SITES, MAX(C) MAX_ROWS_PER_SITE, SUM(C) ROWS_ FROM (
  SELECT DIVISION_ID, UPPER(SCM_SITE_ID) S, COUNT(*) C FROM SCM_MST_SITE_CUSTOMER WHERE REP_YN = 'Y' AND VALID_YN = 'Y'
   GROUP BY DIVISION_ID, UPPER(SCM_SITE_ID) HAVING COUNT(*) > 1) GROUP BY DIVISION_ID
UNION ALL
SELECT 'PROJECT 대소문자 무시 2행 이상', DIVISION_ID, COUNT(*), MAX(C), SUM(C) FROM (
  SELECT DIVISION_ID, UPPER(PROJECT_CODE) P, COUNT(*) C FROM SCM_MST_PROJECT GROUP BY DIVISION_ID, UPPER(PROJECT_CODE) HAVING COUNT(*) > 1) GROUP BY DIVISION_ID
UNION ALL
SELECT 'CUSTOMER Sold-To / Ship-To 2행 이상', DIVISION_ID, COUNT(*), MAX(C), SUM(C) FROM (
  SELECT DIVISION_ID, SOLDTO_CODE, SHIPTO_CODE, COUNT(*) C FROM SCM_MST_CUSTOMER GROUP BY DIVISION_ID, SOLDTO_CODE, SHIPTO_CODE HAVING COUNT(*) > 1) GROUP BY DIVISION_ID
ORDER BY 1, 2;

