  UNION ALL SELECT 'parallel_degree_policy', 'MANUAL' FROM DUAL
  UNION ALL SELECT 'result_cache_mode', 'MANUAL' FROM DUAL
  UNION ALL SELECT 'cpu_count', '8' FROM DUAL
  UNION ALL SELECT 'pga_aggregate_target', '34359738368' FROM DUAL
  UNION ALL SELECT 'sga_target', '0' FROM DUAL
)
SELECT C.N NAME, P.VALUE, C.V CORP, P.ISDEFAULT DFLT,
       CASE WHEN P.NAME IS NULL THEN '(조회 안 됨)'
            WHEN C.N IN ('cpu_count','pga_aggregate_target','sga_target','optimizer_features_enable') THEN '(참고)'
            WHEN P.VALUE = C.V THEN 'same'
            ELSE '≠ 사내와 다름' END JUDGE
  FROM C LEFT JOIN V$PARAMETER P ON P.NAME = C.N
 ORDER BY CASE WHEN P.VALUE = C.V THEN 1 ELSE 0 END, C.N;

