-- =============================================================================
-- C02_SCREEN_CALL_SESSIONS.sql — DMF0005 조회 속도 점검 ② ⭐ 화면 호출별 소요시간 전수 (READ-ONLY, 전체 F5)
--   계정: SCM_MGR · BE 가 붙는 DB(QA 또는 DEV)에서 실행. 값 입력 없음.
--   원천: SCM_COM_SYS_LOG (BE 가 call-proc 1회마다 1행 기록)
--   시트: production(메인 그리드 조회) · purchase(하단 구매 그리드 — 메인 행 선택 시) · modelChange(팝업 저장)
--   액션: MNU_BTN_CD = SEARCH / SAVE …  — [C0][C1] 은 전체 액션, [C2]~[C6] 은 SEARCH 만
--   구간: DB_S = 프로시저 호출 + 결과 fetch / SERVER_S = BE 전체 / TOTAL_S = FE 왕복 /
--         PRE_DB_S = 권한 · 커넥션 대기 / BE_POST_S = DB 뒤 BE 처리(결과 직렬화 · 결과 로그)
--   기준: 호출별 전수 측정 뒤 2초 이상인 호출만 튜닝 대상. 2초 미만은 시간만 남기고 제외.
--   조회 창: 기본 최근 14일 (DEFINE DAYS). SCM_COM_SYS_LOG 는 로그가 크면 절마다 수십 초 걸릴 수 있다.
--   변경 없음: SELECT 만 수행
-- =============================================================================
SET LINESIZE 400
SET PAGESIZE 500
SET TRIMSPOOL ON
SET VERIFY OFF
DEFINE DAYS = 14
COLUMN JUDGE FORMAT A46
COLUMN SHT_NM FORMAT A14
COLUMN ACT FORMAT A12
COLUMN DIV FORMAT A6
COLUMN USR FORMAT A16
COLUMN FILTERS FORMAT A60
COLUMN ERR FORMAT A80
COLUMN CALLS_LIST FORMAT A120
SPOOL C02_SCREEN_CALL_SESSIONS_OUT.txt

PROMPT ################ [C0] 시트 × 액션 인벤토리 — 최근 &DAYS 일 DMF0005 가 쏜 call-proc 전부 ################
PROMPT --  사내 30일: production SEARCH 348회(중앙 3초 · 최대 7,780초) · purchase SEARCH 218회(중앙 0초 · 최대 29초) · production SAVE 71회 · modelChange SAVE 7회
SELECT SHT_NM, MNU_BTN_CD ACT, COUNT(*) CALLS, COUNT(DISTINCT CREATED_BY) USERS,
       TO_CHAR(MIN(TRNM_ST_DTM),'MM-DD HH24:MI') FIRST_CALL, TO_CHAR(MAX(TRNM_ST_DTM),'MM-DD HH24:MI') LAST_CALL,
       ROUND(MEDIAN((CAST(DB_TRNM_END_DTM AS DATE)-CAST(DB_TRNM_ST_DTM AS DATE))*86400),1) MED_DB_S,
       ROUND(MAX((CAST(DB_TRNM_END_DTM AS DATE)-CAST(DB_TRNM_ST_DTM AS DATE))*86400),1) MAX_DB_S,
       SUM(CASE WHEN (CAST(DB_TRNM_END_DTM AS DATE)-CAST(DB_TRNM_ST_DTM AS DATE))*86400 >= 2 THEN 1 ELSE 0 END) GE2S_CALLS,
       SUM(CASE WHEN DB_TRNM_END_DTM IS NULL OR EXCT_MSG_CTN IS NOT NULL THEN 1 ELSE 0 END) ERR_OR_NOEND
  FROM SCM_COM_SYS_LOG
 WHERE MNU_ID = 'DMF0005' AND CREATION_DATE >= TRUNC(SYSDATE) - &DAYS
 GROUP BY SHT_NM, MNU_BTN_CD ORDER BY CALLS DESC;

PROMPT ################ [C1] ⭐⭐ 호출별 전수 상세 — 최근 &DAYS 일, 최신순 300건 ################
PROMPT --  JUDGE: '대상(>=2s)' = 튜닝 대상 / 'NO_END' = BE 가 종료를 못 남김(타임아웃 · 취소) / 'ERR' = 예외 / '-' = 2초 미만
PROMPT --  BE_POST_S 가 DB_S 와 비슷하거나 더 크면 SQL 이 아니라 BE 결과 처리 구간이다 (82 는 한 번에 3만 8천 행 × 53칸을 내려준다)
PROMPT --  FILTERS: 화면 기본값(dept · cust · site = ALL, pjt · item · owner = 빈칸, active = ALL)과 다른 조건만 표시
WITH L AS (
  SELECT L.SHT_NM, L.MNU_BTN_CD ACT, L.CREATED_BY, L.TRNM_ST_DTM, L.EXCT_MSG_CTN,
         REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"divisionId":"([^"]*)"',1,1,NULL,1) DIV,
         RTRIM(CASE WHEN REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"deptId":"([^"]*)"',1,1,NULL,1) <> 'ALL' THEN 'dept ' END
            || CASE WHEN REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"endCustomer":"([^"]*)"',1,1,NULL,1) <> 'ALL' THEN 'cust ' END
            || CASE WHEN REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"salesSite":"([^"]*)"',1,1,NULL,1) <> 'ALL' THEN 'site=' || SUBSTR(REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"salesSite":"([^"]*)"',1,1,NULL,1),1,14) || ' ' END
            || CASE WHEN REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"projectCode":"([^"]*)"',1,1,NULL,1) IS NOT NULL THEN 'pjt=' || SUBSTR(REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"projectCode":"([^"]*)"',1,1,NULL,1),1,14) || ' ' END
            || CASE WHEN REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"itemId":"([^"]*)"',1,1,NULL,1) IS NOT NULL THEN 'item=' || SUBSTR(REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"itemId":"([^"]*)"',1,1,NULL,1),1,14) || ' ' END
            || CASE WHEN REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"owner":"([^"]*)"',1,1,NULL,1) IS NOT NULL THEN 'owner ' END
            || CASE WHEN REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"activeFlag":"([^"]*)"',1,1,NULL,1) <> 'ALL' THEN 'active=' || REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"activeFlag":"([^"]*)"',1,1,NULL,1) END) FILTERS,
         (CAST(L.DB_TRNM_END_DTM AS DATE) - CAST(L.DB_TRNM_ST_DTM AS DATE))*86400
           + (EXTRACT(SECOND FROM L.DB_TRNM_END_DTM) - FLOOR(EXTRACT(SECOND FROM L.DB_TRNM_END_DTM))) - (EXTRACT(SECOND FROM L.DB_TRNM_ST_DTM) - FLOOR(EXTRACT(SECOND FROM L.DB_TRNM_ST_DTM))) DB_S,
         (CAST(L.TRNM_END_DTM AS DATE) - CAST(L.TRNM_ST_DTM AS DATE))*86400
           + (EXTRACT(SECOND FROM L.TRNM_END_DTM) - FLOOR(EXTRACT(SECOND FROM L.TRNM_END_DTM))) - (EXTRACT(SECOND FROM L.TRNM_ST_DTM) - FLOOR(EXTRACT(SECOND FROM L.TRNM_ST_DTM))) SERVER_S,
         (CAST(L.LOG_END_DTM AS DATE) - CAST(L.LOG_ST_DTM AS DATE))*86400
           + (EXTRACT(SECOND FROM L.LOG_END_DTM) - FLOOR(EXTRACT(SECOND FROM L.LOG_END_DTM))) - (EXTRACT(SECOND FROM L.LOG_ST_DTM) - FLOOR(EXTRACT(SECOND FROM L.LOG_ST_DTM))) TOTAL_S,
         (CAST(L.DB_TRNM_ST_DTM AS DATE) - CAST(L.TRNM_ST_DTM AS DATE))*86400
           + (EXTRACT(SECOND FROM L.DB_TRNM_ST_DTM) - FLOOR(EXTRACT(SECOND FROM L.DB_TRNM_ST_DTM))) - (EXTRACT(SECOND FROM L.TRNM_ST_DTM) - FLOOR(EXTRACT(SECOND FROM L.TRNM_ST_DTM))) PRE_DB_S,
         (CAST(L.TRNM_END_DTM AS DATE) - CAST(L.DB_TRNM_END_DTM AS DATE))*86400
           + (EXTRACT(SECOND FROM L.TRNM_END_DTM) - FLOOR(EXTRACT(SECOND FROM L.TRNM_END_DTM))) - (EXTRACT(SECOND FROM L.DB_TRNM_END_DTM) - FLOOR(EXTRACT(SECOND FROM L.DB_TRNM_END_DTM))) BE_POST_S,
         L.DB_TRNM_END_DTM
    FROM SCM_COM_SYS_LOG L
   WHERE L.MNU_ID = 'DMF0005' AND L.CREATION_DATE >= TRUNC(SYSDATE) - &DAYS
)
SELECT TO_CHAR(TRNM_ST_DTM,'MM-DD HH24:MI:SS') ST, SHT_NM, ACT, DIV, CREATED_BY USR, FILTERS,
       ROUND(DB_S,2) DB_S, ROUND(SERVER_S,2) SERVER_S, ROUND(TOTAL_S,2) TOTAL_S, ROUND(PRE_DB_S,2) PRE_DB_S, ROUND(BE_POST_S,2) BE_POST_S,
       CASE WHEN DB_TRNM_END_DTM IS NULL THEN '❌ NO_END (타임아웃 · 취소 — 종료 미기록)'
            WHEN EXCT_MSG_CTN IS NOT NULL THEN '❌ ERR'
            WHEN ACT <> 'SEARCH' AND DB_S >= 2 THEN 'ℹ 비조회 액션 >=2s (저장 — 별건)'
            WHEN DB_S >= 2 THEN '⭐ 대상(>=2s)'
            WHEN SERVER_S >= 2 THEN '⚠ BE 구간 >=2s (DB 는 미달)'
            ELSE '-' END JUDGE,
       SUBSTR(EXCT_MSG_CTN,1,80) ERR
  FROM L
 ORDER BY TRNM_ST_DTM DESC
 FETCH FIRST 300 ROWS ONLY;

PROMPT ################ [C2] ⭐⭐ 시트 × 사업부 요약 (SEARCH 만) — 튜닝 대상 선정표 ################
PROMPT --  사내 30일 production: 중앙 3초. MED_BE_POST 가 MED_DB 보다 크면 BE 결과 처리 구간이 주범
WITH L AS (
  SELECT L.SHT_NM, REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"divisionId":"([^"]*)"',1,1,NULL,1) DIV, L.EXCT_MSG_CTN, L.DB_TRNM_END_DTM,
         (CAST(L.DB_TRNM_END_DTM AS DATE) - CAST(L.DB_TRNM_ST_DTM AS DATE))*86400 DB_S,
         (CAST(L.TRNM_END_DTM AS DATE) - CAST(L.TRNM_ST_DTM AS DATE))*86400 SERVER_S,
         (CAST(L.LOG_END_DTM AS DATE) - CAST(L.LOG_ST_DTM AS DATE))*86400 TOTAL_S,
         (CAST(L.TRNM_END_DTM AS DATE) - CAST(L.DB_TRNM_END_DTM AS DATE))*86400 BE_POST_S
    FROM SCM_COM_SYS_LOG L
   WHERE L.MNU_ID = 'DMF0005' AND L.MNU_BTN_CD = 'SEARCH' AND L.CREATION_DATE >= TRUNC(SYSDATE) - &DAYS
)
SELECT SHT_NM, DIV, COUNT(*) CALLS,
       ROUND(MIN(DB_S),1) MIN_DB, ROUND(MEDIAN(DB_S),1) MED_DB, ROUND(PERCENTILE_CONT(0.9) WITHIN GROUP (ORDER BY DB_S),1) P90_DB, ROUND(MAX(DB_S),1) MAX_DB,
       ROUND(MEDIAN(SERVER_S),1) MED_SERVER, ROUND(MEDIAN(TOTAL_S),1) MED_TOTAL, ROUND(MEDIAN(BE_POST_S),1) MED_BE_POST, ROUND(MAX(BE_POST_S),1) MAX_BE_POST,
       SUM(CASE WHEN DB_S >= 2 THEN 1 ELSE 0 END) GE2S, ROUND(100*SUM(CASE WHEN DB_S >= 2 THEN 1 ELSE 0 END)/COUNT(*)) GE2S_PCT,
       SUM(CASE WHEN DB_TRNM_END_DTM IS NULL THEN 1 ELSE 0 END) NO_END, SUM(CASE WHEN EXCT_MSG_CTN IS NOT NULL THEN 1 ELSE 0 END) ERRS,
       CASE WHEN SUM(CASE WHEN DB_TRNM_END_DTM IS NULL THEN 1 ELSE 0 END) > 0 OR MAX(DB_S) >= 120 THEN '❌ 타임아웃급 — 1순위 대상'
            WHEN MEDIAN(DB_S) >= 2 THEN '⭐ 대상 (중앙값 >=2s)'
            WHEN MAX(DB_S) >= 2 THEN '⚠ 간헐 대상 (일부 호출만 >=2s — [C4][C5] 확인)'
            WHEN MEDIAN(BE_POST_S) >= 2 THEN '⚠ BE 결과 처리 구간 대상'
            ELSE '- 제외 (<2s)' END JUDGE
  FROM L
 GROUP BY SHT_NM, DIV
 ORDER BY CASE WHEN SUM(CASE WHEN DB_TRNM_END_DTM IS NULL THEN 1 ELSE 0 END) > 0 THEN 0 ELSE 1 END, MEDIAN(DB_S) DESC NULLS LAST, SHT_NM, DIV;

PROMPT ################ [C3] ⭐⭐ 일자 × 사업부 추이 — production SEARCH : 어느 날부터 느려졌나 ################
PROMPT --  C01 [E2] 의 BODY LAST_DDL · [E2b] 마커(10-08 · 10-09 변경)가 들어온 날과 맞춘다. CALLS_LIST = 시:분:DB초
WITH L AS (
  SELECT TO_CHAR(L.TRNM_ST_DTM,'MM-DD') D, REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"divisionId":"([^"]*)"',1,1,NULL,1) DIV, L.TRNM_ST_DTM, L.EXCT_MSG_CTN, L.DB_TRNM_END_DTM,
         (CAST(L.DB_TRNM_END_DTM AS DATE) - CAST(L.DB_TRNM_ST_DTM AS DATE))*86400 DB_S,
         (CAST(L.TRNM_END_DTM AS DATE) - CAST(L.DB_TRNM_END_DTM AS DATE))*86400 BE_POST_S
    FROM SCM_COM_SYS_LOG L
   WHERE L.MNU_ID = 'DMF0005' AND L.SHT_NM = 'production' AND L.MNU_BTN_CD = 'SEARCH' AND L.CREATION_DATE >= TRUNC(SYSDATE) - &DAYS
)
SELECT D, DIV, COUNT(*) N, ROUND(MIN(DB_S),1) MIN_S, ROUND(MEDIAN(DB_S),1) MED_S, ROUND(PERCENTILE_CONT(0.9) WITHIN GROUP (ORDER BY DB_S),1) P90_S, ROUND(MAX(DB_S),1) MAX_S,
       ROUND(MEDIAN(BE_POST_S),1) MED_BE_POST,
       SUM(CASE WHEN DB_TRNM_END_DTM IS NULL OR EXCT_MSG_CTN IS NOT NULL THEN 1 ELSE 0 END) ERR_OR_NOEND,
       SUBSTR(LISTAGG(TO_CHAR(TRNM_ST_DTM,'HH24:MI') || ':' || NVL(TO_CHAR(ROUND(DB_S)),'NOEND'), ' ' ON OVERFLOW TRUNCATE) WITHIN GROUP (ORDER BY TRNM_ST_DTM),1,120) CALLS_LIST
  FROM L GROUP BY D, DIV ORDER BY D, DIV;

PROMPT ################ [C4] ⭐ 조회조건 유무별 — production SEARCH (조건 없는 전체 조회 vs 조건 있는 조회) ################
PROMPT --  조건 없는 전체 조회만 느리면 행 수 · 결과 처리 문제, 조건을 줘도 느리면 조인 · 접근경로 문제
WITH L AS (
  SELECT REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"divisionId":"([^"]*)"',1,1,NULL,1) DIV,
         CASE WHEN REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"deptId":"([^"]*)"',1,1,NULL,1) <> 'ALL'
                OR REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"endCustomer":"([^"]*)"',1,1,NULL,1) <> 'ALL'
                OR REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"salesSite":"([^"]*)"',1,1,NULL,1) <> 'ALL'
                OR REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"projectCode":"([^"]*)"',1,1,NULL,1) IS NOT NULL
                OR REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"itemId":"([^"]*)"',1,1,NULL,1) IS NOT NULL
                OR REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"owner":"([^"]*)"',1,1,NULL,1) IS NOT NULL THEN '조건 있음' ELSE '조건 없음(전체)' END KIND,
         REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"activeFlag":"([^"]*)"',1,1,NULL,1) ACTIVE,
         (CAST(L.DB_TRNM_END_DTM AS DATE) - CAST(L.DB_TRNM_ST_DTM AS DATE))*86400 DB_S,
         (CAST(L.TRNM_END_DTM AS DATE) - CAST(L.DB_TRNM_END_DTM AS DATE))*86400 BE_POST_S,
         (CAST(L.LOG_END_DTM AS DATE) - CAST(L.LOG_ST_DTM AS DATE))*86400 TOTAL_S
    FROM SCM_COM_SYS_LOG L
   WHERE L.MNU_ID = 'DMF0005' AND L.SHT_NM = 'production' AND L.MNU_BTN_CD = 'SEARCH' AND L.CREATION_DATE >= TRUNC(SYSDATE) - &DAYS
)
SELECT DIV, KIND, ACTIVE, COUNT(*) CALLS, ROUND(MEDIAN(DB_S),1) MED_DB, ROUND(MAX(DB_S),1) MAX_DB,
       ROUND(MEDIAN(BE_POST_S),1) MED_BE_POST, ROUND(MAX(BE_POST_S),1) MAX_BE_POST, ROUND(MEDIAN(TOTAL_S),1) MED_TOTAL, ROUND(MAX(TOTAL_S),1) MAX_TOTAL
  FROM L GROUP BY DIV, KIND, ACTIVE ORDER BY DIV, KIND, ACTIVE;

PROMPT ################ [C5] 사용자 × 사업부 — production SEARCH (특정 사용자만 느린가) ################
WITH L AS (
  SELECT L.CREATED_BY, REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"divisionId":"([^"]*)"',1,1,NULL,1) DIV, L.TRNM_ST_DTM,
         (CAST(L.DB_TRNM_END_DTM AS DATE) - CAST(L.DB_TRNM_ST_DTM AS DATE))*86400 DB_S,
         (CAST(L.LOG_END_DTM AS DATE) - CAST(L.LOG_ST_DTM AS DATE))*86400 TOTAL_S
    FROM SCM_COM_SYS_LOG L
   WHERE L.MNU_ID = 'DMF0005' AND L.SHT_NM = 'production' AND L.MNU_BTN_CD = 'SEARCH' AND L.CREATION_DATE >= TRUNC(SYSDATE) - &DAYS
)
SELECT CREATED_BY USR, DIV, COUNT(*) CALLS, ROUND(MIN(DB_S),1) MIN_DB, ROUND(MEDIAN(DB_S),1) MED_DB, ROUND(MAX(DB_S),1) MAX_DB,
       ROUND(MEDIAN(TOTAL_S),1) MED_TOTAL, TO_CHAR(MAX(TRNM_ST_DTM),'MM-DD HH24:MI') LAST_CALL
  FROM L GROUP BY CREATED_BY, DIV ORDER BY MEDIAN(DB_S) DESC NULLS LAST, CALLS DESC;

PROMPT ################ [C6] 오류 · 종료 미기록 호출 — 최근 &DAYS 일 (타임아웃 흔적) ################
SELECT TO_CHAR(TRNM_ST_DTM,'MM-DD HH24:MI:SS') ST, SHT_NM, MNU_BTN_CD ACT, CREATED_BY USR,
       REGEXP_SUBSTR(SYS_LOG_MSG_CTN,'"divisionId":"([^"]*)"',1,1,NULL,1) DIV,
       CASE WHEN DB_TRNM_END_DTM IS NULL THEN 'NO_END' ELSE 'ERR' END KIND, SUBSTR(EXCT_MSG_CTN,1,80) ERR
  FROM SCM_COM_SYS_LOG
 WHERE MNU_ID = 'DMF0005' AND CREATION_DATE >= TRUNC(SYSDATE) - &DAYS AND (DB_TRNM_END_DTM IS NULL OR EXCT_MSG_CTN IS NOT NULL)
 ORDER BY TRNM_ST_DTM DESC FETCH FIRST 50 ROWS ONLY;

