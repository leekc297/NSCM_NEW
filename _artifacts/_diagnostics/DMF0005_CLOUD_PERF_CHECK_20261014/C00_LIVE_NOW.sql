PROMPT ################ [L5] ⭐⭐ 조회 문장의 계획 줄별 실제 행 수 — 최근 2시간 실행분 전부 (SQL Monitor · 5초 넘게 돈 실행만 잡힌다 · 멈춘 실행 포함) ################
PROMPT --  STARTS 가 수만 이상인 줄 = 행마다 반복되는 구간. EST_ROWS(추정)와 OUT_ROWS(실제)가 크게 다른 줄 = 추정이 틀린 곳. STATUS EXECUTING = 지금 도는 중
SELECT M.SID, TO_CHAR(M.SQL_EXEC_START,'HH24:MI:SS') EXEC_ST, M.STATUS, M.SQL_ID, M.SQL_PLAN_HASH_VALUE PHV, M.PLAN_LINE_ID LN,
       LPAD(' ', LEAST(M.PLAN_DEPTH, 20)) || M.PLAN_OPERATION || ' ' || M.PLAN_OPTIONS OP, M.PLAN_OBJECT_NAME OBJ,
       M.PLAN_CARDINALITY EST_ROWS, M.STARTS, M.OUTPUT_ROWS OUT_ROWS, M.PHYSICAL_READ_REQUESTS PHY_RD, ROUND(M.WORKAREA_TEMPSEG/1048576) TEMP_MB,
       TO_CHAR(M.LAST_CHANGE_TIME,'HH24:MI:SS') LAST_CHG
  FROM GV$SQL_MONITOR R JOIN GV$SQL_PLAN_MONITOR M ON M.INST_ID = R.INST_ID AND M.KEY = R.KEY
 WHERE R.SQL_EXEC_START >= SYSDATE - 2/24
   AND R.SQL_TEXT LIKE 'WITH ITEM_AGG AS%'
 ORDER BY M.SQL_EXEC_START DESC, M.SID, M.SQL_ID, M.PLAN_LINE_ID
 FETCH FIRST 400 ROWS ONLY;

