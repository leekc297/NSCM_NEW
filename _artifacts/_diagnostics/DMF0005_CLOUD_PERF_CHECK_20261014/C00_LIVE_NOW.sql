PROMPT ################ [L2] ⭐⭐ 지금 실행 중인 세션 전부 (내 세션 제외) — 어느 문장에서 몇 초째, 무엇을 기다리나 ################
PROMPT --  PROG = 그 문장이 속한 패키지 · 함수. SEC = 그 문장 실행 시작 뒤 초. EVT 가 library cache … 이면 패키지 교체에 물린 것([L3])
SELECT S.INST_ID INST, S.SID, S.SERIAL# SER, S.USERNAME USR, S.MACHINE, S.MODULE, S.STATUS,
       ROUND((SYSDATE - S.SQL_EXEC_START) * 86400) SEC, S.LAST_CALL_ET CALL_SEC,
       CASE WHEN S.STATE = 'WAITING' THEN S.EVENT ELSE 'ON CPU' END EVT, S.BLOCKING_SESSION BLK_SID,
       S.SQL_ID, S.SQL_CHILD_NUMBER CH,
       (SELECT MAX(O.OBJECT_NAME) FROM GV$SQL Q JOIN USER_OBJECTS O ON O.OBJECT_ID = Q.PROGRAM_ID
         WHERE Q.INST_ID = S.INST_ID AND Q.SQL_ID = S.SQL_ID) PROG,
       (SELECT MAX(Q.PROGRAM_LINE#) FROM GV$SQL Q WHERE Q.INST_ID = S.INST_ID AND Q.SQL_ID = S.SQL_ID) LINE,
       (SELECT MAX(O.OBJECT_NAME) FROM USER_OBJECTS O WHERE O.OBJECT_ID = S.PLSQL_ENTRY_OBJECT_ID) ENTRY_OBJ,
       (SELECT MAX(SUBSTR(REGEXP_REPLACE(Q.SQL_TEXT,'\s+',' '),1,90)) FROM GV$SQL Q WHERE Q.INST_ID = S.INST_ID AND Q.SQL_ID = S.SQL_ID) TXT
  FROM GV$SESSION S
 WHERE S.TYPE = 'USER' AND S.STATUS = 'ACTIVE'
   AND NOT (S.INST_ID = SYS_CONTEXT('USERENV','INSTANCE') AND S.SID = SYS_CONTEXT('USERENV','SID'))
 ORDER BY SEC DESC NULLS LAST;

PROMPT ################ [L3] ⭐⭐ 대기 사슬 — 잠금 · 라이브러리 캐시 대기 (0행 = 막힌 세션 없음) ################
PROMPT --  패키지를 교체(CREATE OR REPLACE)하는 세션이 실행 중인 세션에 물려 끝나지 않으면, 그 뒤 모든 조회가 library cache lock / pin 으로 줄을 선다
SELECT W.INST_ID INST, W.SID, W.SERIAL# SER, W.USERNAME USR, W.MACHINE, W.MODULE, W.STATUS, W.EVENT EVT, W.SECONDS_IN_WAIT WAIT_SEC,
       W.BLOCKING_INSTANCE BLK_INST, W.BLOCKING_SESSION BLK_SID, W.FINAL_BLOCKING_SESSION FINAL_BLK_SID,
       (SELECT MAX(B.USERNAME || ' / ' || B.MACHINE || ' / ' || B.MODULE || ' / ' || B.STATUS || ' / last call ' || B.LAST_CALL_ET || 's')
          FROM GV$SESSION B WHERE B.INST_ID = W.FINAL_BLOCKING_INSTANCE AND B.SID = W.FINAL_BLOCKING_SESSION) JUDGE,
       W.SQL_ID
  FROM GV$SESSION W
 WHERE W.TYPE = 'USER'
   AND (W.BLOCKING_SESSION IS NOT NULL OR W.EVENT LIKE 'library cache%' OR W.EVENT LIKE 'cursor: pin%' OR W.EVENT LIKE 'enq:%')
   AND W.STATE = 'WAITING' AND W.WAIT_CLASS <> 'Idle'
 ORDER BY W.SECONDS_IN_WAIT DESC;

