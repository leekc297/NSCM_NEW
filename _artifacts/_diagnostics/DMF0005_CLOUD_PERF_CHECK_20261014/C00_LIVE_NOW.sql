PROMPT ################ [L6] ⭐ 최근 2시간 화면 호출 이력 (BE 로그) — 사업부 · 소요 · 종료 여부 ################
PROMPT --  DB_S 빈칸 + NO_END = BE 가 프로시저 호출에서 아직 못 돌아옴(지금 도는 호출 또는 타임아웃). 교체 전 호출의 DB_S 와 비교
SELECT TO_CHAR(L.TRNM_ST_DTM,'MM-DD HH24:MI:SS') ST, L.SHT_NM, L.MNU_BTN_CD ACT, L.CREATED_BY USR,
       REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"divisionId":"([^"]*)"',1,1,NULL,1) DIV,
       ROUND((CAST(L.DB_TRNM_END_DTM AS DATE) - CAST(L.DB_TRNM_ST_DTM AS DATE))*86400) DB_S,
       ROUND((CAST(L.TRNM_END_DTM AS DATE) - CAST(L.TRNM_ST_DTM AS DATE))*86400) SERVER_S,
       ROUND((CAST(L.LOG_END_DTM AS DATE) - CAST(L.LOG_ST_DTM AS DATE))*86400) TOTAL_S,
       CASE WHEN L.DB_TRNM_END_DTM IS NULL THEN '❌ NO_END (' || ROUND((SYSDATE - CAST(L.TRNM_ST_DTM AS DATE))*86400) || '초 전 시작)'
            WHEN L.EXCT_MSG_CTN IS NOT NULL THEN '❌ ERR' ELSE 'ok' END JUDGE,
       SUBSTR(L.EXCT_MSG_CTN,1,90) ERR
  FROM SCM_COM_SYS_LOG L
 WHERE L.MNU_ID = 'DMF0005' AND L.CREATION_DATE >= SYSDATE - 2/24
 ORDER BY L.TRNM_ST_DTM DESC FETCH FIRST 60 ROWS ONLY;

PROMPT ################ [L7] ⭐ 최근 2시간 ASH — PKG_DMF0005 · Owner 이름 함수 문장 × 대기 × 계획 줄 (표본 1 ≈ 1초) ################
PROMPT --  한 줄에 표본이 몰려 있으면 그 계획 줄이 병목. PROG 가 함수면 행마다 불리는 내부 SQL
WITH P AS (SELECT OBJECT_ID, OBJECT_NAME FROM USER_OBJECTS
            WHERE (OBJECT_NAME = 'PKG_DMF0005' AND OBJECT_TYPE = 'PACKAGE BODY')
               OR (OBJECT_NAME IN ('FN_GET_MULTI_OWNER_NAME','FN_SPLITSTRING','FN_GET_DEPT_LIST') AND OBJECT_TYPE = 'FUNCTION')),
Q AS (
  SELECT Q.INST_ID, Q.SQL_ID, MAX(P.OBJECT_NAME) PROG, MAX(Q.PROGRAM_LINE#) LN
    FROM GV$SQL Q JOIN P ON P.OBJECT_ID = Q.PROGRAM_ID
   GROUP BY Q.INST_ID, Q.SQL_ID
)
SELECT Q.PROG, Q.LN LINE, A.SQL_ID, A.SQL_PLAN_HASH_VALUE PHV, A.SQL_PLAN_LINE_ID PLAN_LN,
       MAX(A.SQL_PLAN_OPERATION || ' ' || A.SQL_PLAN_OPTIONS) OP, NVL(A.EVENT,'ON CPU') EVT,
       COUNT(*) SAMPLES, COUNT(DISTINCT A.SESSION_ID || ',' || A.SESSION_SERIAL#) SESSIONS,
       TO_CHAR(MIN(A.SAMPLE_TIME),'HH24:MI:SS') T_FROM, TO_CHAR(MAX(A.SAMPLE_TIME),'HH24:MI:SS') T_TO
  FROM GV$ACTIVE_SESSION_HISTORY A JOIN Q ON Q.INST_ID = A.INST_ID AND Q.SQL_ID = A.SQL_ID
 WHERE A.SAMPLE_TIME >= SYSTIMESTAMP - NUMTODSINTERVAL(120,'MINUTE')
 GROUP BY Q.PROG, Q.LN, A.SQL_ID, A.SQL_PLAN_HASH_VALUE, A.SQL_PLAN_LINE_ID, NVL(A.EVENT,'ON CPU')
 ORDER BY SAMPLES DESC FETCH FIRST 40 ROWS ONLY;

PROMPT ################ [L7b] 최근 2시간 ASH — 패키지 진입 세션의 대기 이벤트 전체 (라이브러리 캐시 · 잠금 대기 포함) ################
SELECT NVL(A.EVENT,'ON CPU') EVT, A.WAIT_CLASS, COUNT(*) SAMPLES, COUNT(DISTINCT A.SESSION_ID || ',' || A.SESSION_SERIAL#) SESSIONS,
       TO_CHAR(MIN(A.SAMPLE_TIME),'HH24:MI:SS') T_FROM, TO_CHAR(MAX(A.SAMPLE_TIME),'HH24:MI:SS') T_TO
  FROM GV$ACTIVE_SESSION_HISTORY A
 WHERE A.SAMPLE_TIME >= SYSTIMESTAMP - NUMTODSINTERVAL(120,'MINUTE')
   AND (A.PLSQL_ENTRY_OBJECT_ID IN (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME = 'PKG_DMF0005')
        OR A.EVENT LIKE 'library cache%')
 GROUP BY NVL(A.EVENT,'ON CPU'), A.WAIT_CLASS ORDER BY SAMPLES DESC;

PROMPT ################ [L8] ⭐ PKG_DMF0005 조회 문장의 자식 커서 — 1회당 시간 · 계획 · 올라온 시각 ################
PROMPT --  LOADED 가 패키지 LAST_DDL 뒤인 줄 = 교체 뒤 새로 만들어진 커서. NOW_RUN > 0 = 지금 실행 중. SEC_PER_EX 가 수백이면 그 계획이 문제
SELECT Q.INST_ID INST, Q.SQL_ID, Q.CHILD_NUMBER CH, Q.PROGRAM_LINE# LINE, Q.PLAN_HASH_VALUE PHV, Q.EXECUTIONS EX, Q.USERS_EXECUTING NOW_RUN,
       ROUND(Q.ELAPSED_TIME/1e6/GREATEST(Q.EXECUTIONS,1),1) SEC_PER_EX, ROUND(Q.CPU_TIME/1e6/GREATEST(Q.EXECUTIONS,1),1) CPU_PER_EX,
       ROUND(Q.BUFFER_GETS/GREATEST(Q.EXECUTIONS,1)) BG_PER_EX, ROUND(Q.DISK_READS/GREATEST(Q.EXECUTIONS,1)) DR_PER_EX,
       ROUND(Q.ROWS_PROCESSED/GREATEST(Q.EXECUTIONS,1)) ROWS_PER_EX,
       Q.LAST_LOAD_TIME LOADED, TO_CHAR(Q.LAST_ACTIVE_TIME,'MM-DD HH24:MI:SS') LAST_ACT,
       SUBSTR(REGEXP_REPLACE(Q.SQL_TEXT,'\s+',' '),1,60) TXT
  FROM GV$SQL Q
 WHERE Q.PROGRAM_ID IN (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME = 'PKG_DMF0005' AND OBJECT_TYPE = 'PACKAGE BODY')
   AND (Q.SQL_TEXT LIKE 'WITH %' OR Q.ELAPSED_TIME/GREATEST(Q.EXECUTIONS,1) >= 1e6 OR Q.USERS_EXECUTING > 0)
 ORDER BY Q.LAST_ACTIVE_TIME DESC FETCH FIRST 30 ROWS ONLY;

PROMPT ################ [L8b] Owner 이름 함수 내부 SQL — 실행 횟수 · 1회당 읽기량 (BG_PER_EX 가 수천이면 인덱스 없이 전체를 읽는 중) ################
SELECT Q.INST_ID INST, Q.SQL_ID, Q.CHILD_NUMBER CH, Q.PLAN_HASH_VALUE PHV, Q.EXECUTIONS EX,
       ROUND(Q.ELAPSED_TIME/1e6,1) TOTAL_SEC, ROUND(Q.ELAPSED_TIME/1e3/GREATEST(Q.EXECUTIONS,1),2) MS_PER_EX,
       ROUND(Q.BUFFER_GETS/GREATEST(Q.EXECUTIONS,1)) BG_PER_EX, Q.LAST_LOAD_TIME LOADED, TO_CHAR(Q.LAST_ACTIVE_TIME,'MM-DD HH24:MI:SS') LAST_ACT,
       SUBSTR(REGEXP_REPLACE(Q.SQL_TEXT,'\s+',' '),1,80) TXT
  FROM GV$SQL Q
 WHERE Q.PROGRAM_ID IN (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME IN ('FN_GET_MULTI_OWNER_NAME','FN_GET_DEPT_LIST'))
 ORDER BY Q.ELAPSED_TIME DESC FETCH FIRST 12 ROWS ONLY;

