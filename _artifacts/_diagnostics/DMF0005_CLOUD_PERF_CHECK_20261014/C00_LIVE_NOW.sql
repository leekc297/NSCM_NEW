PROMPT ################ [L4b] ⭐⭐ 조회 문장의 실행계획 — 지금 돌고 있지 않아도 출력 (가장 최근에 실행된 자식 커서 · 1회당 시간이 가장 긴 자식 커서) ################
PROMPT --  방금 멈춘 실행(C03 · 화면 조회)의 계획이 여기 나온다. Peeked Binds = 이 계획이 만들어질 때의 조회조건
WITH B AS (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME = 'PKG_DMF0005' AND OBJECT_TYPE = 'PACKAGE BODY'),
Q AS (
  SELECT Q.SQL_ID, Q.CHILD_NUMBER CH, Q.PLAN_HASH_VALUE PHV, Q.EXECUTIONS EX, Q.ELAPSED_TIME EL, Q.LAST_ACTIVE_TIME LA,
         ROW_NUMBER() OVER (ORDER BY Q.LAST_ACTIVE_TIME DESC, Q.CHILD_NUMBER DESC) R_LAST,
         ROW_NUMBER() OVER (ORDER BY Q.ELAPSED_TIME / GREATEST(Q.EXECUTIONS, 1) DESC) R_SLOW
    FROM V$SQL Q, B
   WHERE Q.PROGRAM_ID = B.OBJECT_ID AND Q.SQL_TEXT LIKE 'WITH ITEM_AGG AS%' AND Q.SQL_TEXT LIKE '%OWNER_NM%'
)
SELECT '### ' || Q.SQL_ID || ' child ' || Q.CH || ' phv ' || Q.PHV || ' ex ' || Q.EX || ' total ' || ROUND(Q.EL/1e6) || 's last '
       || TO_CHAR(Q.LA,'HH24:MI:SS') || '  ' || X.PLAN_TABLE_OUTPUT PLAN_TABLE_OUTPUT
  FROM Q, TABLE(DBMS_XPLAN.DISPLAY_CURSOR(Q.SQL_ID, Q.CH, 'TYPICAL +PEEKED_BINDS +NOTE')) X
 WHERE Q.R_LAST = 1 OR Q.R_SLOW = 1;
