PROMPT ################ [L4] ⭐ 지금 도는 문장의 실행계획 — PKG_DMF0005 · Owner 이름 함수 문장만 자동 (없으면 0행) ################
WITH R AS (
  SELECT DISTINCT S.SQL_ID, S.SQL_CHILD_NUMBER CH
    FROM GV$SESSION S
   WHERE S.TYPE = 'USER' AND S.STATUS = 'ACTIVE' AND S.SQL_ID IS NOT NULL
     AND S.INST_ID = SYS_CONTEXT('USERENV','INSTANCE')
     AND EXISTS (SELECT 1 FROM GV$SQL Q JOIN USER_OBJECTS O ON O.OBJECT_ID = Q.PROGRAM_ID
                  WHERE Q.INST_ID = S.INST_ID AND Q.SQL_ID = S.SQL_ID
                    AND O.OBJECT_NAME IN ('PKG_DMF0005','FN_GET_MULTI_OWNER_NAME','FN_SPLITSTRING','FN_GET_DEPT_LIST'))
)
SELECT '### ' || R.SQL_ID || ' child ' || R.CH || '  ' || X.PLAN_TABLE_OUTPUT PLAN_TABLE_OUTPUT
