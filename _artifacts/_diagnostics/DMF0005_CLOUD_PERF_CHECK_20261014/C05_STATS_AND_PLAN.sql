SELECT SYS_CONTEXT('USERENV','DB_NAME') DB_NAME, SYS_CONTEXT('USERENV','INSTANCE_NAME') INST, TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI:SS') NOW FROM DUAL;

PROMPT ################ [S1] ⭐ 조회 문장 커서 목록 — 교체 전 문장(다른 SQL_ID)의 커서가 남아 있나 ################
PROMPT --  8pn2cpba1y5v8 = 10-14 교체 뒤 문장. 2zurcv8akt27v = 교체 전 사내 문장(Partial Plan YN 2줄 없는 원문).
PROMPT --  다른 SQL_ID 가 SEC_PER_EX 몇 초로 남아 있으면 = 교체 전에는 빠른 계획이었고, 그 문장으로 되돌리면 그 커서를 다시 쓴다
SELECT Q.SQL_ID, Q.CHILD_NUMBER CH, Q.PLAN_HASH_VALUE PHV, Q.EXECUTIONS EX, Q.USERS_EXECUTING NOW_RUN,
       ROUND(Q.ELAPSED_TIME/1e6/GREATEST(Q.EXECUTIONS,1),1) SEC_PER_EX, ROUND(Q.BUFFER_GETS/GREATEST(Q.EXECUTIONS,1)) BG_PER_EX,
       ROUND(Q.ROWS_PROCESSED/GREATEST(Q.EXECUTIONS,1)) ROWS_PER_EX, Q.FIRST_LOAD_TIME FIRST_LOAD, Q.LAST_LOAD_TIME LOADED,
       TO_CHAR(Q.LAST_ACTIVE_TIME,'MM-DD HH24:MI:SS') LAST_ACT, Q.OBJECT_STATUS OBJ_ST, Q.IS_BIND_SENSITIVE BS, Q.IS_BIND_AWARE BA
  FROM V$SQL Q
 WHERE Q.SQL_TEXT LIKE 'WITH ITEM_AGG AS%'
 ORDER BY Q.LAST_ACTIVE_TIME DESC;

PROMPT ################ [S2] ⭐⭐ 컬럼 통계 — 히스토그램 유무 (CORP = 사내: 히스토그램 종류 / 버킷 수) ################
PROMPT --  HISTOGRAM 이 NONE 인데 CORP 가 FREQUENCY 인 줄 = 그 컬럼의 값 분포를 이 DB 는 모른다 (사업부별 행 수를 평균으로 추정)
WITH C AS (
            SELECT 'SCM_MST_SITE_ITEM' T, 'DIVISION_ID' C, 'FREQUENCY / 8' H FROM DUAL
  UNION ALL SELECT 'SCM_MST_SITE_ITEM', 'VALID_YN', 'FREQUENCY / 2' FROM DUAL
  UNION ALL SELECT 'SCM_MST_SITE_ITEM', 'DEPT_ID', 'FREQUENCY / 162' FROM DUAL
  UNION ALL SELECT 'SCM_MST_SITE_ITEM', 'OWNER', 'HYBRID / 254' FROM DUAL
  UNION ALL SELECT 'SCM_MST_SITE_ITEM', 'SCM_SITE_ID', 'HYBRID / 254' FROM DUAL
  UNION ALL SELECT 'SCM_MST_SITE_ITEM', 'PROJECT_CODE', 'HYBRID / 254' FROM DUAL
  UNION ALL SELECT 'SCM_MST_SITE_ITEM', 'ITEM_ID', 'HYBRID / 254' FROM DUAL
  UNION ALL SELECT 'SCM_MST_SITE', 'DIVISION_ID', 'FREQUENCY / 8' FROM DUAL
  UNION ALL SELECT 'SCM_MST_SITE', 'SITE_TYPE', 'FREQUENCY / 3' FROM DUAL
  UNION ALL SELECT 'SCM_MST_SITE', 'VALID_YN', 'FREQUENCY / 2' FROM DUAL
  UNION ALL SELECT 'SCM_MST_SITE', 'SCM_SITE_ID', 'HYBRID / 254' FROM DUAL
  UNION ALL SELECT 'SCM_MST_PROJECT', 'DIVISION_ID', 'FREQUENCY / 7' FROM DUAL
  UNION ALL SELECT 'SCM_MST_PROJECT', 'PROJECT_CODE', 'HYBRID / 254' FROM DUAL
  UNION ALL SELECT 'SCM_MST_SITE_CUSTOMER', 'DIVISION_ID', 'FREQUENCY / 8' FROM DUAL
  UNION ALL SELECT 'SCM_MST_SITE_CUSTOMER', 'REP_YN', 'FREQUENCY / 2' FROM DUAL
  UNION ALL SELECT 'SCM_MST_SITE_CUSTOMER', 'VALID_YN', 'FREQUENCY / 2' FROM DUAL
  UNION ALL SELECT 'DM_MST_CUSTOMER_MODEL', 'DIVISION_ID', 'FREQUENCY / 4' FROM DUAL
  UNION ALL SELECT 'DM_MST_CUSTOMER_MODEL', 'VALID_YN', 'FREQUENCY / 2' FROM DUAL
  UNION ALL SELECT 'SCM_ITEM_M', 'DIVISION_ID', 'FREQUENCY / 9' FROM DUAL
  UNION ALL SELECT 'SCM_ITEM_M', 'ITEM_TYPE', 'FREQUENCY / 4' FROM DUAL
  UNION ALL SELECT 'SCM_ITEM_M', 'ITEM_ID', 'HYBRID / 254' FROM DUAL
)
SELECT C.T TABLE_NAME, C.C COLUMN_NAME, S.NUM_DISTINCT NDV, S.HISTOGRAM, S.NUM_BUCKETS BKT, S.NUM_NULLS NULLS, S.SAMPLE_SIZE SMP,
       TO_CHAR(S.LAST_ANALYZED,'MM-DD HH24:MI') ANALYZED, C.H CORP,
       CASE WHEN S.COLUMN_NAME IS NULL THEN '(통계 없음)'
            WHEN S.HISTOGRAM = 'NONE' AND C.H NOT LIKE 'NONE%' THEN '≠ 히스토그램 없음'
            WHEN S.HISTOGRAM || ' / ' || S.NUM_BUCKETS = C.H THEN 'same' ELSE '(종류 · 버킷 다름)' END JUDGE
  FROM C LEFT JOIN ALL_TAB_COL_STATISTICS S ON S.TABLE_NAME = C.T AND S.COLUMN_NAME = C.C AND S.OWNER IN ('SCM_MGR','FP_MGR')
 ORDER BY CASE C.T WHEN 'SCM_MST_SITE_ITEM' THEN 1 WHEN 'SCM_MST_SITE' THEN 2 ELSE 3 END, C.T, C.C;

PROMPT ################ [S2b] 테이블별 히스토그램 보유 컬럼 수 — 조회가 읽는 원장 전체 ################
SELECT S.OWNER, S.TABLE_NAME, COUNT(*) COLS, SUM(CASE WHEN S.HISTOGRAM <> 'NONE' THEN 1 ELSE 0 END) HIST_COLS,
       TO_CHAR(MAX(S.LAST_ANALYZED),'MM-DD HH24:MI') ANALYZED
  FROM ALL_TAB_COL_STATISTICS S
 WHERE S.OWNER IN ('SCM_MGR','FP_MGR')
   AND S.TABLE_NAME IN ('SCM_MST_SITE_ITEM','SCM_MST_SITE','SCM_MST_SITE_CUSTOMER','SCM_MST_CUSTOMER','SCM_MST_PROJECT','SCM_MST_SSO_DEPT_INFO',
                        'SCM_ITEM_M','DM_MST_CUSTOMER_MODEL','SCM_ADM_LOOKUP_MASTER_DETAIL','SCM_ADM_USER_M','SCM_MST_SSO_USER_INFO')
 GROUP BY S.OWNER, S.TABLE_NAME ORDER BY 1, 2;
PROMPT --  사내: SCM_MST_SITE_ITEM · SCM_MST_SITE · SCM_MST_PROJECT · SCM_MST_SITE_CUSTOMER · DM_MST_CUSTOMER_MODEL · SCM_ITEM_M 모두 히스토그램 보유

PROMPT ################ [S3] 통계 수집 설정 — METHOD_OPT (히스토그램을 만들지 여부를 정한다) ################
PROMPT --  FOR ALL COLUMNS SIZE AUTO = 기본(필요한 컬럼에 히스토그램 생성). SIZE 1 = 히스토그램을 만들지 않음
SELECT '(전역)' TABLE_NAME, DBMS_STATS.GET_PREFS('METHOD_OPT') PREF FROM DUAL
UNION ALL SELECT 'SCM_MST_SITE_ITEM', DBMS_STATS.GET_PREFS('METHOD_OPT', USER, 'SCM_MST_SITE_ITEM') FROM DUAL
UNION ALL SELECT 'SCM_MST_SITE', DBMS_STATS.GET_PREFS('METHOD_OPT', USER, 'SCM_MST_SITE') FROM DUAL
UNION ALL SELECT 'SCM_MST_PROJECT', DBMS_STATS.GET_PREFS('METHOD_OPT', USER, 'SCM_MST_PROJECT') FROM DUAL
UNION ALL SELECT 'SCM_MST_SITE_CUSTOMER', DBMS_STATS.GET_PREFS('METHOD_OPT', USER, 'SCM_MST_SITE_CUSTOMER') FROM DUAL;
PROMPT --  사내: 전부 FOR ALL COLUMNS SIZE AUTO

PROMPT ################ [S4] 통계 수집 이력 — 최근 30일 (언제 통계가 바뀌었나) ################
SELECT TABLE_NAME, TO_CHAR(STATS_UPDATE_TIME,'YYYY-MM-DD HH24:MI:SS') STATS_UPDATED
  FROM USER_TAB_STATS_HISTORY
 WHERE TABLE_NAME IN ('SCM_MST_SITE_ITEM','SCM_MST_SITE','SCM_MST_PROJECT','SCM_MST_SITE_CUSTOMER') AND PARTITION_NAME IS NULL
   AND STATS_UPDATE_TIME >= SYSTIMESTAMP - INTERVAL '30' DAY
 ORDER BY TABLE_NAME, STATS_UPDATE_TIME DESC;

PROMPT ################ [S4b] 컬럼 사용 기록 — 히스토그램 자동 생성의 근거 (등치 조건으로 쓰인 적이 있어야 만들어진다) ################
SELECT TABLE_NAME, COLUMN_NAME, NUM_DISTINCT NDV, DENSITY, LOW_VALUE, HIGH_VALUE
  FROM USER_TAB_COLUMNS
 WHERE (TABLE_NAME = 'SCM_MST_SITE_ITEM' AND COLUMN_NAME IN ('DIVISION_ID','VALID_YN'))
    OR (TABLE_NAME = 'SCM_MST_SITE' AND COLUMN_NAME IN ('DIVISION_ID','SITE_TYPE'))
 ORDER BY 1, 2;

