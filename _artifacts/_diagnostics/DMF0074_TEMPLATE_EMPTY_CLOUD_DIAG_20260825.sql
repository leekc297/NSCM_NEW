-- ====================================================================================================
-- DMF0074 Excel Form "다운로드할 템플릿 대상 데이터가 없습니다" 클라우드 발생 사유 진단
-- 대상: division 81 / (메인화면 Version=Current — 단, 템플릿 SP 는 내부적으로 SP_W 최신버전을 스스로 선정)
-- 실행: 클라우드 QA/DEV 의 SCM_MGR (또는 SELECT 권한 계정). 전부 SELECT — 데이터 무변경.
-- 판독: 각 단계 주석의 "0 이면 = 원인" 을 위에서부터 순서대로 본다. 첫 번째로 0 이 되는 단계가 원인이다.
--
-- 배경(사내 실측 2026-08-25): 메시지는 FE(MetalLinkTemplateModal)가
--   PKG_DMF0074.P_DMF0074_GET_METAL_LINK_TEMPLATE 의 O_RC1 = 0건일 때 띄운다.
--   이 SP 는 (1)DM_MST_VERSION(81/SP_W 최신버전) -> (2)SCM_SYS_CALENDAR_M INNER JOIN
--   -> (3)원장 2본(DM_PLN_SALES_PLAN_C 계획 + DM_PLN_SALES_PLAN_RESULT_C 실적,
--       MEASURE='RTF_SYS_RP', QTY<>0, 버전 날짜창)
--   -> (4)INNER JOIN 5축(SITE / SITE_ITEM / ITEM_SINGLE_V 'P' / 룩업 SALES_TYPE_CODE / 룩업 END_CUSTOMER)
--   로 좁힌다. 이 중 어느 하나라도 0 이면 전체가 0건이 된다.
--
--   ** 동일 증상 기왕력 (0순위 용의) **: 사내에서 2026-08-18 [MRFPARITY] 마커로 정정된 결함 —
--   구세대 BODY 는 버전 선정에 AND NVL(ATTRIBUTE7,'N')='Y' (MRF 필터)가 "활성"이라
--   금주 SP_W(ATTRIBUTE7=NULL)를 건너뛰고 과거 MRF='Y' 버전을 집는데, 81 은 그 버전의 원장이
--   0행이라 정확히 이 메시지가 났다. 클라우드는 DMF0074_CLOUD_20260823 패키지 미적용 상태라
--   구세대 BODY 일 가능성이 가장 크다. D0 + D3 조합이 이를 확정한다.
-- ====================================================================================================

SET LINESIZE 220 PAGESIZE 200

PROMPT ===== D0. (0순위) 클라우드 PKG_DMF0074 세대 판정 =====
PROMPT ===== 기대(사내 실측 2026-08-25): MRFPARITY_MARK=1, MRF_FILTER_ACTIVE=5 (UPLOAD 쪽 활성분 정상) =====
PROMPT ===== MARK=0 (대개 ACTIVE=6) = 구세대 BODY = 원인 확정 (08-18 MRFPARITY 미반영) =====
SELECT
    (SELECT COUNT(*) FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0074' AND TYPE='PACKAGE BODY'
      AND INSTR(TEXT,'MRFPARITY') > 0)                                             AS MRFPARITY_MARK,
    (SELECT COUNT(*) FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0074' AND TYPE='PACKAGE BODY'
      AND REGEXP_LIKE(TEXT, '^\s*AND\s+NVL\(ATTRIBUTE7'))                          AS MRF_FILTER_ACTIVE,
    (SELECT STATUS FROM ALL_OBJECTS WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_DMF0074'
      AND OBJECT_TYPE='PACKAGE BODY')                                              AS BODY_STATUS,
    (SELECT TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI') FROM ALL_OBJECTS WHERE OWNER='SCM_MGR'
      AND OBJECT_NAME='PKG_DMF0074' AND OBJECT_TYPE='PACKAGE BODY')                AS BODY_LAST_DDL
FROM DUAL;

PROMPT ===== D1. 버전 선정 — DM_MST_VERSION (81 / SP_W): 신·구 로직이 각각 집는 버전 =====
PROMPT ===== OLD 가 NULL 또는 옛날 버전이면 구세대 BODY 에서 그 버전을 씀 (D3 에서 원장 0 확인) =====
SELECT 'NEW(현행: MRF 무관 최신)' AS LOGIC, MAX(VERSION_NO) AS PICK_VERSION, MAX(YYYYMMDD) AS PICK_YYYYMMDD
FROM   SCM_MGR.DM_MST_VERSION
WHERE  DIVISION_ID='81' AND VERSION_TYPE='SP_W'
UNION ALL
SELECT 'OLD(구세대: MRF=Y 만)', MAX(VERSION_NO), MAX(YYYYMMDD)
FROM   SCM_MGR.DM_MST_VERSION
WHERE  DIVISION_ID='81' AND VERSION_TYPE='SP_W' AND NVL(ATTRIBUTE7,'N')='Y';

PROMPT ===== D1b. 참고 — 81 SP_W 최근 5버전과 ATTRIBUTE7(MRF) 분포 =====
SELECT VERSION_NO, YYYYMMDD, NVL(ATTRIBUTE7,'(NULL)') AS MRF_YN
FROM (SELECT VERSION_NO, YYYYMMDD, ATTRIBUTE7 FROM SCM_MGR.DM_MST_VERSION
      WHERE DIVISION_ID='81' AND VERSION_TYPE='SP_W' ORDER BY VERSION_NO DESC)
WHERE ROWNUM <= 5;

PROMPT ===== D2. 캘린더 조인 — 선정 버전 YYYYMMDD 가 SCM_SYS_CALENDAR_M 에 있는가 (CAL_ROW=0 = INNER JOIN 전멸 = 원인) =====
SELECT V.LOGIC, V.PICK_YYYYMMDD,
       (SELECT COUNT(*) FROM SCM_MGR.SCM_SYS_CALENDAR_M B WHERE B.BASIS_YYYYMMDD=V.PICK_YYYYMMDD) AS CAL_ROW
FROM ( SELECT 'NEW' AS LOGIC, MAX(YYYYMMDD) AS PICK_YYYYMMDD FROM SCM_MGR.DM_MST_VERSION
        WHERE DIVISION_ID='81' AND VERSION_TYPE='SP_W'
       UNION ALL
       SELECT 'OLD', MAX(YYYYMMDD) FROM SCM_MGR.DM_MST_VERSION
        WHERE DIVISION_ID='81' AND VERSION_TYPE='SP_W' AND NVL(ATTRIBUTE7,'N')='Y' ) V;

PROMPT ===== D3. 원장 존재 — 신·구 각 버전으로 계획/실적 행수 (날짜창 적용 전) =====
PROMPT ===== NEW>0 AND OLD=0 이면 "구세대 BODY(MRF 필터)" 원인 확정. NEW=0 이면 원장 자체 미이관/미적재 =====
WITH PICK AS (
  SELECT 'NEW' AS LOGIC, MAX(VERSION_NO) AS VNO FROM SCM_MGR.DM_MST_VERSION
   WHERE DIVISION_ID='81' AND VERSION_TYPE='SP_W'
  UNION ALL
  SELECT 'OLD', MAX(VERSION_NO) FROM SCM_MGR.DM_MST_VERSION
   WHERE DIVISION_ID='81' AND VERSION_TYPE='SP_W' AND NVL(ATTRIBUTE7,'N')='Y')
SELECT P.LOGIC, P.VNO,
       (SELECT COUNT(*) FROM SCM_MGR.DM_PLN_SALES_PLAN_C SP
         WHERE SP.DIVISION_ID='81' AND SP.VERSION_NO=P.VNO
           AND SP.MEASURE='RTF_SYS_RP' AND SP.QTY<>0)                              AS PLAN_ROWS,
       (SELECT COUNT(*) FROM SCM_MGR.DM_PLN_SALES_PLAN_RESULT_C SP
         WHERE SP.DIVISION_ID='81' AND SP.VERSION_NO=P.VNO
           AND SP.MEASURE='RTF_SYS_RP' AND SP.QTY<>0)                              AS RESULT_ROWS
FROM PICK P;

PROMPT ===== D4. 날짜창 적용 후 행수 (SP 의 RESULT_FROM/RESULT_TO/PLAN_TO 재현 — NEW 버전 기준) =====
PROMPT ===== D3 은 >0 인데 여기서 0 이면 날짜창(캘린더 FN_NEXT_DAY 산출) 문제 =====
WITH TEMP_VERSION_NO AS (
    SELECT A.DIVISION_ID, A.VERSION_NO, A.YYYYMMDD
         , CASE WHEN B.BASIS_YYYYMM > TO_CHAR(SCM_MGR.FN_NEXT_DAY(A.YYYYMMDD,'MON')-7,'YYYYMM')
                THEN TO_CHAR(ADD_MONTHS(TO_DATE(B.BASIS_YYYYMM||'01','YYYYMMDD'),-1),'YYYYMMDD')
                ELSE B.BASIS_YYYYMM||'01' END                                      AS RESULT_FROM
         , TO_CHAR(SCM_MGR.FN_NEXT_DAY(A.YYYYMMDD,'MON')-7,'YYYYMMDD')             AS RESULT_TO
         , TO_CHAR(SCM_MGR.FN_NEXT_DAY(A.YYYYMMDD,'MON')-7+(52*7)-1,'YYYYMMDD')    AS PLAN_TO
    FROM (SELECT DIVISION_ID, MAX(VERSION_NO) AS VERSION_NO, MAX(YYYYMMDD) AS YYYYMMDD
          FROM SCM_MGR.DM_MST_VERSION
          WHERE DIVISION_ID='81' AND VERSION_TYPE='SP_W' GROUP BY DIVISION_ID) A
    INNER JOIN SCM_MGR.SCM_SYS_CALENDAR_M B ON B.BASIS_YYYYMMDD=A.YYYYMMDD)
SELECT T.VERSION_NO, T.RESULT_FROM, T.RESULT_TO, T.PLAN_TO,
       (SELECT COUNT(*) FROM SCM_MGR.DM_PLN_SALES_PLAN_C SP
         WHERE SP.DIVISION_ID='81' AND SP.VERSION_NO=T.VERSION_NO AND SP.MEASURE='RTF_SYS_RP'
           AND SP.QTY<>0 AND SP.YYYYMMDD>=T.RESULT_TO AND SP.YYYYMMDD<=T.PLAN_TO)  AS PLAN_IN_WINDOW,
       (SELECT COUNT(*) FROM SCM_MGR.DM_PLN_SALES_PLAN_RESULT_C SP
         WHERE SP.DIVISION_ID='81' AND SP.VERSION_NO=T.VERSION_NO AND SP.MEASURE='RTF_SYS_RP'
           AND SP.QTY<>0 AND SP.YYYYMMDD>=T.RESULT_FROM AND SP.YYYYMMDD<T.RESULT_TO) AS RESULT_IN_WINDOW
FROM TEMP_VERSION_NO T;

PROMPT ===== D5. INNER JOIN 5축 분모 (81) — 0 인 축 = 그 메타 미이관/미적재가 원인 =====
SELECT 'SCM_MST_SITE(81,VALID=Y)' AS AXIS, COUNT(*) AS CNT FROM SCM_MGR.SCM_MST_SITE
 WHERE DIVISION_ID='81' AND VALID_YN='Y'
UNION ALL
SELECT 'SCM_MST_SITE_ITEM(81,VALID=Y)', COUNT(*) FROM SCM_MGR.SCM_MST_SITE_ITEM
 WHERE DIVISION_ID='81' AND VALID_YN='Y'
UNION ALL
SELECT 'DM_MST_ITEM_SINGLE_V(81,ITEM_TYPE=P)', COUNT(*) FROM SCM_MGR.DM_MST_ITEM_SINGLE_V
 WHERE DIVISION_ID='81' AND ITEM_TYPE='P'
UNION ALL
SELECT '룩업 SALES_TYPE_CODE(VALID=Y,SEG4<>FREE)', COUNT(*) FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE='SALES_TYPE_CODE' AND VALID_YN='Y' AND SEGMENT4<>'FREE'
UNION ALL
SELECT '룩업 END_CUSTOMER(SEG1=81)', COUNT(*) FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE='END_CUSTOMER' AND SEGMENT1='81';

PROMPT ===== D6. 조인 단계별 누적 카운트 (계획 arm, NEW 버전) — 처음으로 0 이 되는 단계가 원인 조인 =====
WITH TEMP_VERSION_NO AS (
    SELECT A.DIVISION_ID, A.VERSION_NO
         , TO_CHAR(SCM_MGR.FN_NEXT_DAY(A.YYYYMMDD,'MON')-7,'YYYYMMDD')             AS RESULT_TO
         , TO_CHAR(SCM_MGR.FN_NEXT_DAY(A.YYYYMMDD,'MON')-7+(52*7)-1,'YYYYMMDD')    AS PLAN_TO
    FROM (SELECT DIVISION_ID, MAX(VERSION_NO) AS VERSION_NO, MAX(YYYYMMDD) AS YYYYMMDD
          FROM SCM_MGR.DM_MST_VERSION
          WHERE DIVISION_ID='81' AND VERSION_TYPE='SP_W' GROUP BY DIVISION_ID) A
    INNER JOIN SCM_MGR.SCM_SYS_CALENDAR_M B ON B.BASIS_YYYYMMDD=A.YYYYMMDD),
BASE AS (
    SELECT SP.SCM_SITE_ID, SP.PROJECT_CODE, SP.ITEM_ID, SP.FCST_TYPE
    FROM SCM_MGR.DM_PLN_SALES_PLAN_C SP
    INNER JOIN TEMP_VERSION_NO T ON SP.DIVISION_ID=T.DIVISION_ID AND SP.VERSION_NO=T.VERSION_NO
    WHERE SP.DIVISION_ID='81' AND SP.QTY<>0 AND SP.MEASURE='RTF_SYS_RP'
      AND SP.YYYYMMDD>=T.RESULT_TO AND SP.YYYYMMDD<=T.PLAN_TO)
SELECT '1) 원장(버전+날짜창)' AS STEP, COUNT(*) AS CNT FROM BASE
UNION ALL
SELECT '2) +SITE', COUNT(*) FROM BASE SP
  INNER JOIN SCM_MGR.SCM_MST_SITE MS
     ON MS.DIVISION_ID='81' AND MS.SCM_SITE_ID=SP.SCM_SITE_ID AND MS.VALID_YN='Y'
UNION ALL
SELECT '3) +SALES_TYPE_CODE 룩업', COUNT(*) FROM BASE SP
  INNER JOIN SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL LUP
     ON LUP.LOOKUP_TYPE='SALES_TYPE_CODE' AND LUP.VALID_YN='Y' AND LUP.SEGMENT4<>'FREE'
    AND LUP.SEGMENT1=SP.FCST_TYPE
UNION ALL
SELECT '4) +SITE_ITEM', COUNT(*) FROM BASE SP
  INNER JOIN SCM_MGR.SCM_MST_SITE_ITEM SI
     ON SI.DIVISION_ID='81' AND SI.PROJECT_CODE=SP.PROJECT_CODE AND SI.SCM_SITE_ID=SP.SCM_SITE_ID
    AND SI.ITEM_ID=SP.ITEM_ID AND SI.VALID_YN='Y'
UNION ALL
SELECT '5) +ITEM_SINGLE_V(P)', COUNT(*) FROM BASE SP
  INNER JOIN SCM_MGR.SCM_MST_SITE_ITEM SI
     ON SI.DIVISION_ID='81' AND SI.PROJECT_CODE=SP.PROJECT_CODE AND SI.SCM_SITE_ID=SP.SCM_SITE_ID
    AND SI.ITEM_ID=SP.ITEM_ID AND SI.VALID_YN='Y'
  INNER JOIN SCM_MGR.DM_MST_ITEM_SINGLE_V SV
     ON SV.DIVISION_ID=SI.DIVISION_ID AND SV.ITEM_ID=SI.ITEM_ID AND SV.ITEM_TYPE='P'
UNION ALL
SELECT '6) +END_CUSTOMER 룩업(최종 게이트)', COUNT(*) FROM BASE SP
  INNER JOIN SCM_MGR.SCM_MST_SITE MS
     ON MS.DIVISION_ID='81' AND MS.SCM_SITE_ID=SP.SCM_SITE_ID AND MS.VALID_YN='Y'
  INNER JOIN SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL LUP2
     ON LUP2.LOOKUP_TYPE='END_CUSTOMER' AND LUP2.SEGMENT1='81' AND LUP2.SEGMENT2=MS.END_CUSTOMER;

PROMPT ===== D7. (보조) SP 실행 로그 — 최근 템플릿 호출 이력 (호출 도달/에러 여부) =====
SELECT * FROM (
  SELECT TO_CHAR(EVENT_DATE,'MM-DD HH24:MI') AS T, LOG_TYPE, LOG_MESSAGE, DESCRIPTION
  FROM   SCM_MGR.SCM_SYS_LOG_BATCH
  WHERE  PROGRAM_NAME LIKE '%METAL_LINK_TEMPLATE%'
  ORDER BY EVENT_DATE DESC)
WHERE ROWNUM <= 10;

PROMPT ===== D8. (제2 용의) 버전-원장 불일치 — RTF_SYS_RP 데이터를 실제 보유한 SP_W 버전 상위 10 =====
PROMPT ===== D1 의 NEW PICK_VERSION 이 이 목록에 없으면 = "최신 버전 원장 미적재" 가 원인 =====
PROMPT ===== (사내 실측 2026-08-25: 버전마스터 최신은 SP_W_20260821_V001 인데 PLAN_C 보유 최신은 SP_W_20260817_V001 — 동형 사례) =====
SELECT * FROM (
  SELECT 'PLAN_C' AS SRC, VERSION_NO, COUNT(*) AS CNT
  FROM SCM_MGR.DM_PLN_SALES_PLAN_C
  WHERE DIVISION_ID='81' AND MEASURE='RTF_SYS_RP' AND QTY<>0 AND VERSION_NO LIKE 'SP_W%'
  GROUP BY VERSION_NO ORDER BY VERSION_NO DESC)
WHERE ROWNUM <= 10;

SELECT * FROM (
  SELECT 'RESULT_C' AS SRC, VERSION_NO, COUNT(*) AS CNT
  FROM SCM_MGR.DM_PLN_SALES_PLAN_RESULT_C
  WHERE DIVISION_ID='81' AND MEASURE='RTF_SYS_RP' AND QTY<>0 AND VERSION_NO LIKE 'SP_W%'
  GROUP BY VERSION_NO ORDER BY VERSION_NO DESC)
WHERE ROWNUM <= 10;

PROMPT ===== D8b. 버전마스터 최신 5건에 원장 유무 병기 (한눈 대조) =====
SELECT V.VERSION_NO, V.YYYYMMDD, NVL(V.ATTRIBUTE7,'(NULL)') AS MRF_YN,
       (SELECT COUNT(*) FROM SCM_MGR.DM_PLN_SALES_PLAN_C C
         WHERE C.DIVISION_ID='81' AND C.VERSION_NO=V.VERSION_NO
           AND C.MEASURE='RTF_SYS_RP' AND C.QTY<>0) AS PLAN_RTF_ROWS
FROM (SELECT VERSION_NO, YYYYMMDD, ATTRIBUTE7 FROM SCM_MGR.DM_MST_VERSION
      WHERE DIVISION_ID='81' AND VERSION_TYPE='SP_W' ORDER BY VERSION_NO DESC) V
WHERE ROWNUM <= 5;
