PROMPT === [1] COM0008 itemByDivisionPopup column 정의 (정확 컬럼명 적용) ===
SELECT COUNT(*) AS CNT
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID='COM0008' AND SHEET_NAME='itemByDivisionPopup';

SELECT COLUMN_NAME || '|' || COLUMN_LABEL_NAME || '|' || SORT_ORDER_NO || '|' || NVL(DIVISION_ID,'(NULL)') AS COL
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID='COM0008' AND SHEET_NAME='itemByDivisionPopup'
 ORDER BY SORT_ORDER_NO
 FETCH FIRST 20 ROWS ONLY;

