  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID='COM0005' AND SHEET_NAME='projectByDivisionPopup';

PROMPT === [3] PKG_COM0000 body 안에서 P_COM0008 SP 위치 검색 ===
SELECT NAME || '|' || TYPE || '|' || LINE AS L, REPLACE(TEXT, CHR(13), '') AS TXT
  FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_COM0000' AND TYPE='PACKAGE BODY'
   AND UPPER(TEXT) LIKE '%P_COM0008%'
 ORDER BY LINE
 FETCH FIRST 20 ROWS ONLY;

