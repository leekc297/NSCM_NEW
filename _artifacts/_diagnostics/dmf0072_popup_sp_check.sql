PROMPT === [1] SCM0002_GET_PROJECT_BY_DIVISION_POPUPEX / DMF0002_GET_ITEM_BY_DIVISION_POPUPEX 존재 ===
SELECT OBJECT_NAME||'|'||OBJECT_TYPE||'|'||STATUS AS O
  FROM ALL_OBJECTS
 WHERE OWNER='SCM_MGR'
   AND (   UPPER(OBJECT_NAME) LIKE '%GET_PROJECT_BY_DIVISION_POPUPEX%'
        OR UPPER(OBJECT_NAME) LIKE '%GET_ITEM_BY_DIVISION_POPUPEX%'
        OR UPPER(OBJECT_NAME) LIKE 'PKG_SCM0002%'
        OR UPPER(OBJECT_NAME) LIKE 'PKG_DMF0002%'
        OR UPPER(OBJECT_NAME) LIKE '%PROJECT%POPUP%'
        OR UPPER(OBJECT_NAME) LIKE '%ITEM%POPUP%')
   ORDER BY OBJECT_NAME;

PROMPT === [2] SCM_MST_SITE_ITEM / SCM_MST_PROJECT 기반 lookup 가능 데이터 카운트 ===
SELECT 'SCM_MST_PROJECT total' AS K, COUNT(*) AS V FROM ALL_TABLES WHERE OWNER='SCM_MGR' AND TABLE_NAME='SCM_MST_PROJECT';

PROMPT === [3] SCM_MST_SITE_ITEM 컬럼 (ITEM_ID 등) ===
SELECT 'SCM_MST_SITE_ITEM' AS T, COLUMN_NAME||'|'||DATA_TYPE AS COL
  FROM ALL_TAB_COLUMNS
 WHERE OWNER='SCM_MGR' AND TABLE_NAME='SCM_MST_SITE_ITEM'
   AND COLUMN_NAME IN ('DIVISION_ID','PROJECT_CODE','SCM_SITE_ID','ITEM_ID','OWNER','VALID_YN')
 ORDER BY COLUMN_ID;

PROMPT === [4] SCM_MST_ITEM 등 ITEM 마스터 테이블 존재 ===
SELECT TABLE_NAME FROM ALL_TABLES
 WHERE OWNER='SCM_MGR'
   AND (TABLE_NAME LIKE '%ITEM%MASTER%' OR TABLE_NAME LIKE 'SCM_MST_ITEM%' OR TABLE_NAME LIKE 'SCM_MST_PROJECT%')
 ORDER BY TABLE_NAME;
EXIT;
