PROMPT === [1] SCM_MST_ITEM_SN 전체 컬럼 ===
SELECT COLUMN_ID || '|' || COLUMN_NAME || '|' || DATA_TYPE AS COL
  FROM ALL_TAB_COLUMNS
 WHERE OWNER='SCM_MGR' AND TABLE_NAME='SCM_MST_ITEM_SN'
 ORDER BY COLUMN_ID;

PROMPT === [2] SCM_MST_SSO_DEPT_INFO VALID_YN 컬럼 존재? ===
SELECT COLUMN_NAME FROM ALL_TAB_COLUMNS WHERE OWNER='SCM_MGR' AND TABLE_NAME='SCM_MST_SSO_DEPT_INFO' AND COLUMN_NAME='VALID_YN';

PROMPT === [3] SCM_MST_DIVISION VALID_YN 데이터 ===
SELECT 'DIV total/VALID_YN=Y' AS K, COUNT(*) AS TOTAL, SUM(CASE WHEN VALID_YN='Y' THEN 1 ELSE 0 END) AS VALID FROM SCM_MGR.SCM_MST_DIVISION;

PROMPT === [4] LOOKUP_MASTER_DETAIL DM_ETC_Project + ITEM_TYPE_CODE 데이터 ===
SELECT LOOKUP_TYPE||'|'||SEGMENT1||'|'||SEGMENT2 AS L
  FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE IN ('ITEM_TYPE_CODE','BIZ_TYPE_BPMS','DM_ETC_Project') AND VALID_YN='Y'
 ORDER BY LOOKUP_TYPE, SEGMENT1
 FETCH FIRST 30 ROWS ONLY;

PROMPT === [5] SCM_MST_SITE_ITEM 의 OWNER 컬럼 sample ===
SELECT DISTINCT OWNER FROM SCM_MGR.SCM_MST_SITE_ITEM WHERE OWNER IS NOT NULL AND DIVISION_ID='81' AND ROWNUM <= 5;

