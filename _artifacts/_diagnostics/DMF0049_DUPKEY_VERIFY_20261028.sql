-- Q7. 저장 로그 — MOBILE 중복 검증 발생 직후 DMF0049 가 END(=COMMIT) 로 끝났는지 시간순 확인
--     DUPLICATION VALIDATION(MOBILE) 바로 뒤에 DMF0049_SAVE_SALES_ETC_REPORT_C 의 END 가 있으면 = 중복이 커밋된 저장
SELECT EVENT_DATE, PROGRAM_NAME, LOG_TYPE, CREATED_BY
     , SUBSTR(LOG_MESSAGE, 1, 300) AS LOG_MESSAGE
     , SUBSTR(DESCRIPTION, 1, 200) AS DESCRIPTION
  FROM SCM_SYS_LOG_BATCH
 WHERE PROGRAM_NAME IN ('DMF0044_MOBILE_REPORT_CREATE', 'DMF0049_SAVE_SALES_ETC_REPORT_C')
   AND EVENT_DATE >= TRUNC(SYSDATE) - 14
 ORDER BY EVENT_DATE, PROGRAM_NAME;

-- Q8. 대상 버전의 전송 상태 — SEND_YN='Y' 일 때만 MOBILE(전체 중복 검증)이 돈다. 'N' 이면 두 번째 저장은 어떤 검증에도 걸리지 않는다
WITH P AS (SELECT '40' DIV, 'EBL' ITEM, 'USD' CUR, 'LGESKR' COMP FROM DUAL)
SELECT V.DIVISION_ID, V.VERSION_NO, V.VERSION_TYPE, V.SEND_YN, V.ORI_CUTOFF_VERSION_NO
     , V.LAST_UPDATED_BY, V.LAST_UPDATE_DATE
  FROM DM_MDF_VERSION V
 WHERE (V.DIVISION_ID, V.VERSION_NO) IN (SELECT A.DIVISION_ID, A.VERSION_NO FROM DM_PLN_SALES_ETC_REPORT_C A, P
                                          WHERE A.DIVISION_ID = P.DIV AND A.ITEM_ID = P.ITEM
                                            AND A.CURRENCY = P.CUR AND A.COMPANY_ID = P.COMP)
 ORDER BY V.VERSION_NO DESC;

-- =====================================================================================================
-- [ATTRIBUTE2 '-' 확인] 사내 원문 기준 DMF0049 저장은 ATTRIBUTE2 를 항상 '' (= NULL) 로 넣는다(INSERT 2곳).
--   ETC 원장 ATTRIBUTE2 는 MOBILE_REPORT_CREATE 가 Sales Report 원장(DM_PLN_SALES_PLAN_REPORT_C, DATA_TYPE='2')으로 복사하며
--   FORECAST_INFO_CELL_MODEL = CASE WHEN ATTRIBUTE2 IS NOT NULL THEN ATTRIBUTE2 ELSE CELL_MODEL_INFO END 로 쓴다
--   → ATTRIBUTE2 가 '-' 이면 Cell Model 이 실제 값(CELL_MODEL_INFO) 대신 '-' 로 바뀐다 (NULL 허용 컬럼이라 '-' 초기값 불필요)
-- =====================================================================================================

-- Q9. ETC 원장 ATTRIBUTE2 값 분포 + '-' 행을 누가 언제 넣었는지
SELECT DIVISION_ID, NVL(ATTRIBUTE2, '<NULL>') AS ATTRIBUTE2, COUNT(*) AS CNT
     , MIN(CREATION_DATE) AS FIRST_CREATED, MAX(LAST_UPDATE_DATE) AS LAST_UPD
     , MAX(LAST_UPDATED_BY) AS LAST_UPD_BY
  FROM DM_PLN_SALES_ETC_REPORT_C
 GROUP BY DIVISION_ID, NVL(ATTRIBUTE2, '<NULL>')
 ORDER BY DIVISION_ID, CNT DESC;

-- Q10. Sales Report 원장(ETC 병합분 DATA_TYPE='2') — ATTRIBUTE2 '-' 와 Cell Model '-' 로 바뀐 행
SELECT VERSION_NO, NVL(ATTRIBUTE2, '<NULL>') AS ATTRIBUTE2
     , SUM(CASE WHEN FORECAST_INFO_CELL_MODEL = '-' THEN 1 ELSE 0 END) AS CELL_MODEL_DASH
     , COUNT(*) AS CNT, MAX(CREATED_BY) AS CREATED_BY, MAX(CREATION_DATE) AS CREATED
  FROM DM_PLN_SALES_PLAN_REPORT_C
 WHERE DIVISION_ID = '40' AND DATA_TYPE = '2'
   AND (ATTRIBUTE2 IN ('-', '/') OR FORECAST_INFO_CELL_MODEL IN ('-', '/'))
 GROUP BY VERSION_NO, NVL(ATTRIBUTE2, '<NULL>')
 ORDER BY VERSION_NO DESC;

-- Q11. 클라우드 원문에서 ETC 원장·Sales Report 원장에 ATTRIBUTE2 를 '-' 로 넣는 코드가 있는지 (사내 원문과 다른지 확인)
SELECT S.NAME, S.TYPE, S.LINE, SUBSTR(TRIM(S.TEXT), 1, 200) AS TEXT
     , O.LAST_DDL_TIME
  FROM ALL_SOURCE S
  JOIN ALL_OBJECTS O ON O.OWNER = S.OWNER AND O.OBJECT_NAME = S.NAME AND O.OBJECT_TYPE = S.TYPE
 WHERE S.OWNER = 'SCM_MGR'
   AND S.NAME IN ('PKG_DMF0049', 'PKG_DMF0044')
   AND S.TYPE = 'PACKAGE BODY'
   AND REGEXP_LIKE(S.TEXT, '''-''\s*(AS\s+)?ATTRIBUTE2|ATTRIBUTE2\s*=\s*''-''|NVL\s*\(\s*\w*\.?ATTRIBUTE2\s*,\s*''-''', 'i')
 ORDER BY S.NAME, S.LINE;

-- Q12. DM_PLN_SALES_PLAN_C.ATTRIBUTE2 = '-' 를 누가·언제 넣었는지 (사업부·생성자·월)
--     사내 실측(2026-10-28 15:49): 81계열·82 만, 생성자 = CUTOFF·MAKE_CUST_FCST 배치와 81 사용자 저장(2026-08~09).
--     사내 원문에서 '-' AS ATTRIBUTE2 를 쓰는 곳 = PR_DM_PLN_MKT_FCST_C_QTY_BALANCE_CREATE L2584 · PR_DM_PLN_MKT_FCST_QTY_BALANCE_CREATE L2609.
--     이 컬럼을 읽는 PR_DM_BPS_SALES_PLAN_S L391 은 40 사업부일 때만 ATTRIBUTE2 를 FROM_SITE_ID 로 쓴다.
SELECT DIVISION_ID, CREATED_BY, TO_CHAR(TRUNC(CREATION_DATE, 'MM'), 'YYYY-MM') AS CREATED_MONTH
     , MAX(LAST_UPDATED_BY) AS LAST_UPD_BY, MAX(LAST_UPDATE_DATE) AS LAST_UPD, COUNT(*) AS CNT
  FROM DM_PLN_SALES_PLAN_C
 WHERE ATTRIBUTE2 = '-'
 GROUP BY DIVISION_ID, CREATED_BY, TRUNC(CREATION_DATE, 'MM')
 ORDER BY CREATED_MONTH DESC, CNT DESC;
