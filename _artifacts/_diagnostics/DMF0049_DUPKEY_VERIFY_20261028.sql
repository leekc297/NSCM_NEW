--     → MOBILE 이 원장 전체를 12개 키로 묶어 중복을 찾으면 메시지를 커서로 돌려주고 RETURN (ROLLBACK 없음, L7398~7405)
--     → DMF0049 가 이어서 COMMIT (L1319) → 중복 행이 그대로 저장된다
--   AS-IS: DMF0044_MOBILE_REPORT_CREATE 가 중복이면 ROLLBACK TRANSACTION (AS-IS DB 원문 L470~473, modify 2026-02-09)
--     → 바깥 DMF0049 트랜잭션까지 전부 취소 → 저장 안 됨
