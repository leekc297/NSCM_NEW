-- 작성 2026-10-28 · 원장 DM_PLN_SALES_ETC_REPORT_C (PK = VERSION_NO, DIVISION_ID, DATA_SEQ, MEASURE, YYYYMMDD)
-- 기준 원문: 사내 ZIOUI1 ALL_SOURCE 2026-10-28 15:20~15:25 조회 (PKG_DMF0049 BODY LAST_DDL 2026-10-22 11:44:39 /
--            PKG_DMF0044 BODY LAST_DDL 2026-10-27 13:14:01). 클라우드 원문이 다르면 아래 키 설명도 달라질 수 있다.
--
-- 이 원장에 쓰는 저장 경로는 2개이고, "같은 행" 판정 키가 서로 다르다
--   ① DMF0049 저장  PKG_DMF0049.P_DMF0049_SAVE_SALES_ETC_REPORT_C
--        - 신규 DATA_SEQ 채번 키 19개 : DEPARTMENT_ID, DEPT_ID, CUST_REPORT, END_CUST_REPORT, SOLDTO_CODE, SOLDTO_CUST_REPORT,
--          PRODUCT_GROUP, ITEM_ID, PRODUCT_DETAILS, CURRENCY, COMPANY_ID, BIZ_TYPE, APPLICATION_GR, APPLICATION,
--          COUNTRY_CODE, ITEM_USE, SOLDTO_COUNTRY, SHIPTO_COUNTRY, END_CUSTOMER   (NVL 없음 — NULL·'-'·'/' 는 서로 다른 값)
--        - 저장 전 중복 검증 키 12개 : VERSION_NO, DIVISION_ID, DEPARTMENT_ID, DEPT_ID, ITEM_ID, MEASURE, YYYYMMDD, CURRENCY,
--          COMPANY_ID, END_CUST_REPORT, CUST_REPORT, PRODUCT_GROUP, COUNTRY_CODE
--   ② DMF0044 저장(ETC)  PKG_DMF0044.P_DMF0044_SAVE_SALES_PLAN_REPORT_C  MERGE (L4471~)
--        - 기존 DATA_SEQ 재사용 키 : CUTOFF_TYPE, ITEM_ID, MEASURE, CURRENCY, 월, DEPARTMENT_ID, DEPT_ID, END_CUST_REPORT,
--          CUST_REPORT, PRODUCT_GROUP, COMPANY_ID, CELL_MODEL_INFO, ATTRIBUTE3(CELL_MODEL)  — Sold-To·Biz Type·Application 은 키 아님
--        - 못 찾으면 MAX(DATA_SEQ) + DENSE_RANK 로 새 DATA_SEQ
-- → 화면에서 같아 보이는 두 세트는 (a) 숨은 컬럼 값이 다르거나 (b) 빈 값 표기(NULL / '-' / '/' / 공백)가 다르거나
--   (c) 두 저장 경로가 서로 다른 키로 각자 채번한 경우에 생긴다. 아래 Q1~Q6 이 셋 중 무엇인지 가린다.
--
-- 실행: 문장별 실행(Ctrl+Enter) 또는 스크립트 실행(Alt+X). 대상 행 조건은 Q2~Q4 의 WITH P 블록에서 바꾼다.
--   (화면의 Department·Team·Cust·Biz Type·Application 칸은 이름 표시일 수 있어 조건에서 뺐다 — 코드가 확실한 칸만 사용)
