-- Q1. 원장 전체에서 "화면 키가 같은데 DATA_SEQ 가 2개 이상" 인 묶음 — 버전·사업부별 건수
--     화면 키 = 채번 키 19개 + CELL_MODEL_INFO + ATTRIBUTE3, 빈 값(NULL·공백·'-'·'/')은 같은 값으로 본다
SELECT VERSION_NO, DIVISION_ID
     , COUNT(*)                     AS DUP_GROUPS
     , SUM(SEQ_CNT)                 AS DATA_SEQ_TOTAL
     , MIN(SEQS)                    AS SAMPLE_DATA_SEQS
  FROM (
        SELECT A.VERSION_NO, A.DIVISION_ID, A.MEASURE, A.YYYYMMDD
             , COUNT(DISTINCT A.DATA_SEQ) AS SEQ_CNT
             , LISTAGG(DISTINCT A.DATA_SEQ, ',') WITHIN GROUP (ORDER BY A.DATA_SEQ) AS SEQS
          FROM DM_PLN_SALES_ETC_REPORT_C A
         GROUP BY A.VERSION_NO, A.DIVISION_ID, A.MEASURE, A.YYYYMMDD
             , DECODE(TRIM(A.DEPARTMENT_ID),      NULL,'/','-','/',TRIM(A.DEPARTMENT_ID))
             , DECODE(TRIM(A.DEPT_ID),            NULL,'/','-','/',TRIM(A.DEPT_ID))
             , DECODE(TRIM(A.CUST_REPORT),        NULL,'/','-','/',TRIM(A.CUST_REPORT))
             , DECODE(TRIM(A.END_CUST_REPORT),    NULL,'/','-','/',TRIM(A.END_CUST_REPORT))
             , DECODE(TRIM(A.SOLDTO_CODE),        NULL,'/','-','/',TRIM(A.SOLDTO_CODE))
             , DECODE(TRIM(A.SOLDTO_CUST_REPORT), NULL,'/','-','/',TRIM(A.SOLDTO_CUST_REPORT))
             , DECODE(TRIM(A.PRODUCT_GROUP),      NULL,'/','-','/',TRIM(A.PRODUCT_GROUP))
             , DECODE(TRIM(A.ITEM_ID),            NULL,'/','-','/',TRIM(A.ITEM_ID))
             , DECODE(TRIM(A.PRODUCT_DETAILS),    NULL,'/','-','/',TRIM(A.PRODUCT_DETAILS))
             , DECODE(TRIM(A.CURRENCY),           NULL,'/','-','/',TRIM(A.CURRENCY))
             , DECODE(TRIM(A.COMPANY_ID),         NULL,'/','-','/',TRIM(A.COMPANY_ID))
             , DECODE(TRIM(A.BIZ_TYPE),           NULL,'/','-','/',TRIM(A.BIZ_TYPE))
             , DECODE(TRIM(A.APPLICATION_GR),     NULL,'/','-','/',TRIM(A.APPLICATION_GR))
             , DECODE(TRIM(A.APPLICATION),        NULL,'/','-','/',TRIM(A.APPLICATION))
             , DECODE(TRIM(A.COUNTRY_CODE),       NULL,'/','-','/',TRIM(A.COUNTRY_CODE))
             , DECODE(TRIM(A.ITEM_USE),           NULL,'/','-','/',TRIM(A.ITEM_USE))
             , DECODE(TRIM(A.SOLDTO_COUNTRY),     NULL,'/','-','/',TRIM(A.SOLDTO_COUNTRY))
             , DECODE(TRIM(A.SHIPTO_COUNTRY),     NULL,'/','-','/',TRIM(A.SHIPTO_COUNTRY))
             , DECODE(TRIM(A.END_CUSTOMER),       NULL,'/','-','/',TRIM(A.END_CUSTOMER))
             , DECODE(TRIM(A.CELL_MODEL_INFO),    NULL,'/','-','/',TRIM(A.CELL_MODEL_INFO))
             , DECODE(TRIM(A.ATTRIBUTE3),         NULL,'/','-','/',TRIM(A.ATTRIBUTE3))
        HAVING COUNT(DISTINCT A.DATA_SEQ) > 1
       )
 GROUP BY VERSION_NO, DIVISION_ID
 ORDER BY VERSION_NO DESC, DIVISION_ID;

-- Q2. 대상 행 후보 — 코드가 확실한 칸(Model·Currency·Company·Product Gr.)으로 찾고, 이름 칸은 결과로 확인
WITH P AS (SELECT '40' DIV, 'EBL' ITEM, 'USD' CUR, 'LGESKR' COMP, '원통형' PGRP FROM DUAL)
SELECT A.VERSION_NO, A.DATA_SEQ, A.MEASURE
     , COUNT(*) AS MONTH_CNT, MIN(A.YYYYMMDD) AS FROM_YMD, MAX(A.YYYYMMDD) AS TO_YMD, SUM(A.QTY) AS QTY_SUM
     , MAX(A.DEPARTMENT_ID) DEPARTMENT_ID, MAX(A.DEPARTMENT_NAME) DEPARTMENT_NAME
     , MAX(A.DEPT_ID) DEPT_ID, MAX(A.DEPT_NAME) DEPT_NAME
     , MAX(A.CUST_REPORT) CUST_REPORT, MAX(A.END_CUST_REPORT) END_CUST_REPORT
     , MAX(A.SOLDTO_CODE) SOLDTO_CODE, MAX(A.SOLDTO_CUST_REPORT) SOLDTO_CUST_REPORT
     , MAX(A.BIZ_TYPE) BIZ_TYPE, MAX(A.APPLICATION_GR) APPLICATION_GR, MAX(A.APPLICATION) APPLICATION
     , MAX(A.CUTOFF_TYPE) CUTOFF_TYPE
     , MIN(A.CREATED_BY) CREATED_BY, MIN(A.CREATION_DATE) FIRST_CREATED
     , MAX(A.LAST_UPDATED_BY) LAST_UPD_BY, MAX(A.LAST_UPDATE_DATE) LAST_UPD
  FROM DM_PLN_SALES_ETC_REPORT_C A, P
 WHERE A.DIVISION_ID = P.DIV AND A.ITEM_ID = P.ITEM AND A.CURRENCY = P.CUR
   AND A.COMPANY_ID = P.COMP AND A.PRODUCT_GROUP = P.PGRP
 GROUP BY A.VERSION_NO, A.DATA_SEQ, A.MEASURE
 ORDER BY A.VERSION_NO DESC, A.MEASURE, A.DATA_SEQ;

-- Q3. 대상 행 — 같은 (버전·메저·월)에 DATA_SEQ 가 2개 이상인 것만, 컬럼 원값을 DUMP 로 나란히 (어느 칸이 달라서 따로 채번됐는지)
--     DUMP 결과: NULL / Len=1: 45('-') / Len=1: 47('/') / Len=1: 32(공백) 로 빈 값 표기 차이가 보인다
WITH P AS (SELECT '40' DIV, 'EBL' ITEM, 'USD' CUR, 'LGESKR' COMP, '원통형' PGRP FROM DUAL)
, T AS (
SELECT A.*
     , COUNT(DISTINCT A.DATA_SEQ) OVER (PARTITION BY A.VERSION_NO, A.MEASURE, A.YYYYMMDD) AS SEQ_CNT
  FROM DM_PLN_SALES_ETC_REPORT_C A, P
 WHERE A.DIVISION_ID = P.DIV AND A.ITEM_ID = P.ITEM AND A.CURRENCY = P.CUR
   AND A.COMPANY_ID = P.COMP AND A.PRODUCT_GROUP = P.PGRP )
SELECT VERSION_NO, DATA_SEQ, MEASURE, MIN(YYYYMMDD) AS SAMPLE_YMD
     , MAX(DUMP(DEPARTMENT_ID))      D_DEPARTMENT_ID
     , MAX(DUMP(DEPT_ID))            D_DEPT_ID
     , MAX(DUMP(CUST_REPORT))        D_CUST_REPORT
     , MAX(DUMP(END_CUST_REPORT))    D_END_CUST_REPORT
     , MAX(DUMP(SOLDTO_CODE))        D_SOLDTO_CODE
     , MAX(DUMP(SOLDTO_CUST_REPORT)) D_SOLDTO_CUST_REPORT
     , MAX(DUMP(PRODUCT_GROUP))      D_PRODUCT_GROUP
     , MAX(DUMP(PRODUCT_DETAILS))    D_PRODUCT_DETAILS
     , MAX(DUMP(BIZ_TYPE))           D_BIZ_TYPE
     , MAX(DUMP(APPLICATION_GR))     D_APPLICATION_GR
     , MAX(DUMP(APPLICATION))        D_APPLICATION
     , MAX(DUMP(COUNTRY_CODE))       D_COUNTRY_CODE
     , MAX(DUMP(ITEM_USE))           D_ITEM_USE
     , MAX(DUMP(SOLDTO_COUNTRY))     D_SOLDTO_COUNTRY
     , MAX(DUMP(SHIPTO_COUNTRY))     D_SHIPTO_COUNTRY
     , MAX(DUMP(END_CUSTOMER))       D_END_CUSTOMER
     , MAX(DUMP(CELL_MODEL_INFO))    D_CELL_MODEL_INFO
     , MAX(DUMP(ATTRIBUTE3))         D_ATTRIBUTE3_CELL_MODEL
     , MAX(DUMP(ATTRIBUTE2))         D_ATTRIBUTE2
     , MAX(CUTOFF_TYPE)              CUTOFF_TYPE
     , MAX(CUTOFF_YYYYMMDD)          CUTOFF_YYYYMMDD
     , MIN(CREATED_BY)               CREATED_BY
     , MIN(CREATION_DATE)            FIRST_CREATED
     , MAX(LAST_UPDATED_BY)          LAST_UPD_BY
     , MAX(LAST_UPDATE_DATE)         LAST_UPD
  FROM T
 WHERE SEQ_CNT > 1
 GROUP BY VERSION_NO, DATA_SEQ, MEASURE
 ORDER BY VERSION_NO DESC, MEASURE, DATA_SEQ;

-- Q4. 이력 — DATA_SEQ 별 최초 적재 시각·사용자 (어느 DATA_SEQ 가 나중에 생겼는지, 같은 사람이 같은 시각에 넣었는지)
WITH P AS (SELECT '40' DIV, 'EBL' ITEM, 'USD' CUR, 'LGESKR' COMP, '원통형' PGRP FROM DUAL)
SELECT H.VERSION_NO, H.DATA_SEQ
     , COUNT(*) HIST_ROWS
     , MIN(H.HISTORY_SEQ) FIRST_HIST_SEQ, MAX(H.HISTORY_SEQ) LAST_HIST_SEQ
     , MIN(H.CREATION_DATE) FIRST_DATE, MAX(H.LAST_UPDATE_DATE) LAST_DATE
     , LISTAGG(DISTINCT H.CREATED_BY, ',') WITHIN GROUP (ORDER BY H.CREATED_BY) USERS
     , LISTAGG(DISTINCT H.MEASURE, ',') WITHIN GROUP (ORDER BY H.MEASURE) MEASURES
     , LISTAGG(DISTINCT NVL(H.SOLDTO_CODE,'<NULL>'), ',') WITHIN GROUP (ORDER BY 1) SOLDTO_CODE_VALUES
     , LISTAGG(DISTINCT NVL(H.ATTRIBUTE3,'<NULL>'), ',') WITHIN GROUP (ORDER BY 1) ATTRIBUTE3_VALUES
  FROM DM_PLN_SALES_ETC_REPORT_H H, P
 WHERE H.DIVISION_ID = P.DIV AND H.ITEM_ID = P.ITEM AND H.CURRENCY = P.CUR
   AND H.COMPANY_ID = P.COMP AND H.PRODUCT_GROUP = P.PGRP
 GROUP BY H.VERSION_NO, H.DATA_SEQ
 ORDER BY H.VERSION_NO DESC, H.DATA_SEQ;

-- Q5. DMF0049 저장 전 중복 검증(12개 키)으로 다시 묶었을 때 2건 이상인 묶음
--     SP 검증은 "원장 × 이번 저장분" 을 12개 키로 조인해 COUNT>1 을 본다 → 저장분에 없는 기존 세트와 겹치는 신규 세트는 1건으로 세어져 통과한다.
--     여기서 나오면: 중복 검증 키 기준으로도 중복인데 저장이 통과한 것
SELECT A.VERSION_NO, A.DIVISION_ID, A.DEPARTMENT_ID, A.DEPT_ID, A.ITEM_ID, A.MEASURE, A.YYYYMMDD, A.CURRENCY
     , A.COMPANY_ID, A.END_CUST_REPORT, A.CUST_REPORT, A.PRODUCT_GROUP, A.COUNTRY_CODE
     , COUNT(*) ROW_CNT
     , LISTAGG(A.DATA_SEQ, ',') WITHIN GROUP (ORDER BY A.DATA_SEQ) DATA_SEQS
  FROM DM_PLN_SALES_ETC_REPORT_C A
 WHERE A.DIVISION_ID = '40' AND A.ITEM_ID = 'EBL' AND A.CURRENCY = 'USD' AND A.COMPANY_ID = 'LGESKR'
 GROUP BY A.VERSION_NO, A.DIVISION_ID, A.DEPARTMENT_ID, A.DEPT_ID, A.ITEM_ID, A.MEASURE, A.YYYYMMDD, A.CURRENCY
        , A.COMPANY_ID, A.END_CUST_REPORT, A.CUST_REPORT, A.PRODUCT_GROUP, A.COUNTRY_CODE
HAVING COUNT(*) > 1
 ORDER BY A.VERSION_NO DESC, A.MEASURE, A.YYYYMMDD;

-- Q6. (요청 추가분) DM_PLN_SALES_PLAN_C.ATTRIBUTE2 의 빈 값 표기 분포 — 사업부별
--     사내 실측(2026-10-28 15:23): '-' 는 81계열·82 에만 있고 40 은 0건. DMF0049 조회 SP 는 이 테이블을 읽지 않는다(원장 ETC_REPORT_C 만).
SELECT DIVISION_ID
     , SUM(CASE WHEN ATTRIBUTE2 IS NULL THEN 1 ELSE 0 END) CNT_NULL
     , SUM(CASE WHEN ATTRIBUTE2 = '-'   THEN 1 ELSE 0 END) CNT_DASH
     , SUM(CASE WHEN ATTRIBUTE2 = '/'   THEN 1 ELSE 0 END) CNT_SLASH
     , SUM(CASE WHEN ATTRIBUTE2 IS NOT NULL AND TRIM(ATTRIBUTE2) IS NULL THEN 1 ELSE 0 END) CNT_BLANK
     , COUNT(*) CNT_ALL
  FROM DM_PLN_SALES_PLAN_C
 GROUP BY DIVISION_ID
 ORDER BY DIVISION_ID;

