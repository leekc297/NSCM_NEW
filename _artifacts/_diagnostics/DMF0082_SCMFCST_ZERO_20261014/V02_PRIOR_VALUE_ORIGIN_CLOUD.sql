/* =====================================================================================================
 * DMF0082 SCM_FCST 0 저장 후속 — 0 으로 바뀐 3일(10/16 · 11/06 · 11/18)에 "저장 전 값"이 어디서 왔는지 (클라우드 · 조회 전용)
 * 대상: 40 / NT / Foxlink_CN_DGG / MCSS22531-B1 / E / MPS / DAP / SCM_FCST / PLANT '/'
 *
 * 배경 (V01 클라우드 결과 + 사내 소스 기준):
 *  - V01-V2: 이력(_H)에 8행(999999 5 + 0 3) = 화면이 0 을 보낸 것 확정
 *  - FE EditTracker 는 "조회 시 값이 있던 셀"만 0 을 변경으로 잡는다 (빈칸→0 은 미전송)
 *    → 조회 시점에 3일에 값이 있었다
 *  - V01-V3: 그 값이 DMF0082 저장 이력에 없음. 사내 전체 소스상 DM_PLN_CFM_MKT_DEMAND_PLAN_H 를 쓰는 곳은
 *    PKG_DMF0082 저장뿐 → 다른 경로(이력 미기록)로 들어간 값
 *    SCM_FCST 를 DM_PLN_CFM_MKT_DEMAND_PLAN 에 쓰는 객체(사내 실측): PKG_DMF0021 · PR_DM_PLN_MKT_FCST_WEEKLY_ROLLING
 *    · PR_DM_PLN_MKT_FCST_QTY_BALANCE_CREATE · PR_DM_ANL_SALES_PLAN_AMT_CREATE_LOCAL_KRW
 *
 * 실행: 전체 F5 가능 (SELECT 만)
 * ===================================================================================================== */

/* P1. 저장 시각(초 단위) — V03 플래시백 조회에 넣을 시각 */
SELECT TO_CHAR(MIN(H.CREATION_DATE), 'YYYY-MM-DD HH24:MI:SS') AS SAVED_AT_SEC
     , COUNT(*)                                             AS H_ROWS
FROM SCM_MGR.DM_PLN_CFM_MKT_DEMAND_PLAN_H H
WHERE H.DIVISION_ID = '40' AND H.PROJECT_CODE = 'NT' AND H.SCM_SITE_ID = 'Foxlink_CN_DGG'
  AND H.ITEM_ID = 'MCSS22531-B1' AND H.MEASURE = 'SCM_FCST' AND H.PLANT_SITE_ID = '/'
  AND H.CREATED_BY = 'k0101' AND H.CREATION_DATE >= TRUNC(SYSDATE);

/* P2. DM_PLN_MKT_FCST 쪽 이력(_H) — 3일 값이 MKT_FCST 이력에 남아 있는지 (DMF0003/DMF0005 등 경로) */
SELECT H.YYYYMMDD, H.QTY, H.CREATED_BY, H.CREATION_DATE, H.LAST_UPDATED_BY, H.HISTORY_SEQ
FROM SCM_MGR.DM_PLN_MKT_FCST_H H
WHERE H.DIVISION_ID = '40' AND H.PROJECT_CODE = 'NT' AND H.SCM_SITE_ID = 'Foxlink_CN_DGG'
  AND H.ITEM_ID = 'MCSS22531-B1' AND H.DOM_EXP = 'E' AND H.FCST_TYPE = 'MPS' AND H.INCOTERMS = 'DAP'
  AND H.MEASURE = 'SCM_FCST' AND H.PLANT_SITE_ID = '/'
  AND H.YYYYMMDD IN ('20261016', '20261106', '20261118')
ORDER BY H.YYYYMMDD, H.CREATION_DATE;

/* P3. 스냅샷 2종 — 저장 전 시점 값이 스냅샷에 남아 있는지 (값 · 생성자 = 원천 경로 단서) */
SELECT 'CFM_SNAPSHOT' AS SRC, S.SNAPSHOT_DTM, S.YYYYMMDD, S.QTY, S.CREATED_BY, S.CREATION_DATE, S.LAST_UPDATED_BY, S.LAST_UPDATE_DATE
FROM SCM_MGR.DM_PLN_CFM_MKT_DEMAND_PLAN_SNAPSHOT S
WHERE S.DIVISION_ID = '40' AND S.PROJECT_CODE = 'NT' AND S.SCM_SITE_ID = 'Foxlink_CN_DGG'
  AND S.ITEM_ID = 'MCSS22531-B1' AND S.MEASURE = 'SCM_FCST' AND S.PLANT_SITE_ID = '/'
  AND S.YYYYMMDD IN ('20261016', '20261106', '20261118')
UNION ALL
SELECT 'MKT_FCST_SNAPSHOT', S.SNAPSHOT_DTM, S.YYYYMMDD, S.QTY, S.CREATED_BY, S.CREATION_DATE, S.LAST_UPDATED_BY, S.LAST_UPDATE_DATE
FROM SCM_MGR.DM_PLN_MKT_FCST_SNAPSHOT S
WHERE S.DIVISION_ID = '40' AND S.PROJECT_CODE = 'NT' AND S.SCM_SITE_ID = 'Foxlink_CN_DGG'
  AND S.ITEM_ID = 'MCSS22531-B1' AND S.MEASURE = 'SCM_FCST' AND S.PLANT_SITE_ID = '/'
  AND S.YYYYMMDD IN ('20261016', '20261106', '20261118')
ORDER BY 1, 2, 3;

/* P4. 같은 품목의 다른 SCM_FCST 중 "월요일이 아닌 날" 행 — 어떤 작성자/경로가 비월요일 SCM_FCST 를 만드는지
 *  (V01-V4 에 jenny.k 가 오늘 수정한 일요일 행 20261206 · 20270103 존재) */
SELECT C.YYYYMMDD
     , TO_CHAR(TO_DATE(C.YYYYMMDD, 'YYYYMMDD'), 'DY', 'NLS_DATE_LANGUAGE=ENGLISH') AS DOW
     , C.QTY, C.CREATED_BY, C.CREATION_DATE
     , TO_CHAR(C.LAST_UPDATE_DATE, 'YYYY-MM-DD HH24:MI:SS') AS LAST_UPD, C.LAST_UPDATED_BY
FROM SCM_MGR.DM_PLN_CFM_MKT_DEMAND_PLAN C
WHERE C.DIVISION_ID = '40' AND C.PROJECT_CODE = 'NT' AND C.SCM_SITE_ID = 'Foxlink_CN_DGG'
  AND C.ITEM_ID = 'MCSS22531-B1' AND C.MEASURE = 'SCM_FCST' AND C.PLANT_SITE_ID = '/'
  AND TO_CHAR(TO_DATE(C.YYYYMMDD, 'YYYYMMDD'), 'DY', 'NLS_DATE_LANGUAGE=ENGLISH') <> 'MON'
ORDER BY C.YYYYMMDD;

/* P5. 오늘 이 품목을 건드린 다른 프로그램/사용자 — k0101 저장 이전에 jenny.k 등 다른 경로가 3일 값을 넣었는지
 *  IN_PARA 에 품목코드가 들어간 실행 + 배치(작성자 BATCH%/SYSTEM) 시작·종료 */
SELECT TO_CHAR(L.EVENT_DATE, 'YYYY-MM-DD HH24:MI:SS') AS EVENT_AT, L.PROGRAM_NAME, L.LOG_TYPE
     , SUBSTR(L.LOG_MESSAGE, 1, 80) AS LOG_MESSAGE, L.CREATED_BY
     , DBMS_LOB.SUBSTR(L.IN_PARA_DATA, 300, 1) AS IN_PARA
FROM SCM_MGR.SCM_SYS_LOG_BATCH L
WHERE L.EVENT_DATE >= TRUNC(SYSDATE) - 3
  AND L.LOG_TYPE IN ('START', 'END', 'ERROR')
  AND (   DBMS_LOB.INSTR(L.IN_PARA_DATA, 'MCSS22531-B1') > 0
       OR L.CREATED_BY = 'jenny.k'
       OR L.CREATED_BY LIKE 'BATCH%'
       OR L.PROGRAM_NAME IN ('PR_DM_PLN_MKT_FCST_WEEKLY_ROLLING', 'PR_DM_PLN_CFM_TO_MKT_FCST_ALL', 'PKG_DMF0021') )
ORDER BY L.EVENT_DATE;
