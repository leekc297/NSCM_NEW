WITH DICT AS (
  SELECT DISTINCT
         REGEXP_SUBSTR(TEXT, 'GT_DM22_T_COLUMN_SETUP +VALUES *\( *''[^'']*'' *, *''([^'']+)''', 1, 1, NULL, 1) AS COLUMN_NAME
  FROM   USER_SOURCE
  WHERE  NAME='PKG_DMF0022' AND TYPE='PACKAGE BODY'
  AND    INSTR(TEXT,'GT_DM22_T_COLUMN_SETUP') > 0
  AND    INSTR(TEXT,'VALUES') > 0
