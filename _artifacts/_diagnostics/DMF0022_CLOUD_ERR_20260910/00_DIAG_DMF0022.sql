SELECT TO_CHAR(CREATE_DATE,'YYYY-MM-DD HH24:MI:SS') AS T,
       CREATED_BY, SUBSTR(EXCEPTION,1,400) AS EXCEPTION
FROM  (SELECT * FROM SCM_COM_SQL_LOG
        WHERE CREATE_DATE <  TRUNC(SYSDATE)          -- 오늘 이전만
        AND   CREATE_DATE >= TRUNC(SYSDATE) - 7      -- 최근 7일 (스캔 범위 한정)
        AND   SQL_TEXT LIKE '%P_DMF0022_GET_DM_PLN_SALES_PLAN_WATERFALL%'
        ORDER BY CREATE_DATE DESC)
WHERE ROWNUM <= 5;

