SELECT U.USER_ID, U.COLUMN_NAME, U.SORT_ORDER_NO
FROM   SCM_MST_TITLESET_USER U
WHERE  U.PROGRAM_ID = 'DMF0035'
AND    U.SHEET_NAME = 'Sales Plan Waterfall'
AND    U.USER_INQUIRY_COLUMN_TYPE_CODE = 'C'
AND    U.COLUMN_NAME NOT IN ('MEASURE','VERSION_NO')
AND    EXISTS (SELECT 1 FROM SCM_MST_SHEET_COLUMNS C
                WHERE C.PROGRAM_ID='DMF0035' AND C.SHEET_NAME='Sales Plan Waterfall'
                  AND C.COLUMN_NAME = U.COLUMN_NAME)
AND    NOT EXISTS (SELECT 1 FROM DICT D WHERE D.COLUMN_NAME = U.COLUMN_NAME)
ORDER  BY U.USER_ID, TO_NUMBER(U.SORT_ORDER_NO);

