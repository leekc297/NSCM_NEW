-- =====================================================================================================
-- DMF0082 조회 — LOC 와 다른 메저의 CURRENCY 가 달라 병합이 갈리는 현상 확인 (클라우드 확인용)
--   읽기 전용(SELECT 만) · 전체 실행(F5) 가능 · 값 입력 없음 · 글자 컬럼은 잘라서 출력
--   작성 2026-10-13 · 사내오라클(59.19.252.148 ZIOUI1)에서 5문장 실행 확인 (사내는 이 사이트 데이터가 없어 0건)
--   대상 = Division 40 · Sales Site 'AJ상사_AB_TES' (한글 깨짐을 피하려고 LIKE 'AJ%AB_TES' 로 찾는다) · 당주 월요일 이후
--
--   조회 프로시저의 통화 채움 규칙 (사내 원문 · AS-IS 동일)
--     · 통화가 빈 행은 같은 키의 LOC 행 통화로 채운다. 키 = Project · Site · Plant · Item · Incoterms · Dom/Exp · Fcst Type · Cell Prod Site
--     · 메저가 VMI 로 시작하면(VMI_In_Req 등) 채우지 않고 항상 빈값으로 둔다  ← AS-IS IIF(MEASURE LIKE 'VMI%','',CURRENCY)
--     · TO-BE 는 1차(전 키)로 못 찾으면 2차(Cell Prod Site 제외) · 3차(Site · Item · Dom/Exp · Fcst Type)로 다시 찾는다
--   값 양끝의 [ ] 는 공백 · 빈값 표기('-' '/' ' ')를 눈으로 구분하려고 붙였다.
-- =====================================================================================================

-- A1. 수요 원장(DM_PLN_CFM_MKT_DEMAND_PLAN) — 키 · 메저별 행 (조회 화면 수량 메저의 원천)
SELECT 'A1' AS Q, SUBSTR(D.SCM_SITE_ID, 1, 16) AS SITE, SUBSTR(D.ITEM_ID, 1, 16) AS ITEM_ID
     , '[' || SUBSTR(D.PROJECT_CODE, 1, 14) || ']' AS PROJECT, '[' || SUBSTR(D.END_CUSTOMER, 1, 14) || ']' AS END_CUST
     , D.DOM_EXP AS DE, SUBSTR(D.FCST_TYPE, 1, 6) AS FTYPE, '[' || D.INCOTERMS || ']' AS INCO
     , '[' || D.PLANT_SITE_ID || ']' AS PLANT, '[' || D.CELL_PROD_SITE_ID || ']' AS CELL_PROD
     , SUBSTR(D.MEASURE, 1, 12) AS MEASURE, COUNT(*) AS CNT, MIN(D.YYYYMMDD) AS YMD_FROM, MAX(D.YYYYMMDD) AS YMD_TO
     , SUBSTR(MAX(D.LAST_UPDATED_BY) KEEP (DENSE_RANK LAST ORDER BY D.LAST_UPDATE_DATE), 1, 12) AS UPD_BY
     , TO_CHAR(MAX(D.LAST_UPDATE_DATE), 'MM-DD HH24:MI') AS UPD_AT
FROM   SCM_MGR.DM_PLN_CFM_MKT_DEMAND_PLAN D
WHERE  D.DIVISION_ID = '40' AND D.SCM_SITE_ID LIKE 'AJ%AB_TES'
AND    D.YYYYMMDD >= TO_CHAR(TRUNC(SYSDATE, 'IW'), 'YYYYMMDD')
GROUP BY D.SCM_SITE_ID, D.ITEM_ID, D.PROJECT_CODE, D.END_CUSTOMER, D.DOM_EXP, D.FCST_TYPE, D.INCOTERMS, D.PLANT_SITE_ID, D.CELL_PROD_SITE_ID, D.MEASURE
ORDER BY D.ITEM_ID, D.FCST_TYPE, D.INCOTERMS, D.PLANT_SITE_ID, D.CELL_PROD_SITE_ID, D.MEASURE
FETCH FIRST 150 ROWS ONLY;

-- A2. 판가 원장(DM_PLN_CFM_SELLING_PRICE) — 키 · 메저 · 통화별 행 (LOC 통화의 원천)
SELECT 'A2' AS Q, SUBSTR(P.SCM_SITE_ID, 1, 16) AS SITE, SUBSTR(P.ITEM_ID, 1, 16) AS ITEM_ID
     , '[' || SUBSTR(P.PROJECT_CODE, 1, 14) || ']' AS PROJECT, '[' || SUBSTR(P.END_CUSTOMER, 1, 14) || ']' AS END_CUST
     , P.DOM_EXP AS DE, SUBSTR(P.FCST_TYPE, 1, 6) AS FTYPE, '[' || P.INCOTERMS || ']' AS INCO
     , '[' || P.PLANT_SITE_ID || ']' AS PLANT, '[' || P.CELL_PROD_SITE_ID || ']' AS CELL_PROD
     , SUBSTR(P.MEASURE, 1, 6) AS MEASURE, '[' || P.CURRENCY || ']' AS CURRENCY
     , COUNT(*) AS CNT, MIN(P.YYYYMMDD) AS YMD_FROM, MAX(P.YYYYMMDD) AS YMD_TO
     , SUBSTR(MAX(P.LAST_UPDATED_BY) KEEP (DENSE_RANK LAST ORDER BY P.LAST_UPDATE_DATE), 1, 12) AS UPD_BY
     , TO_CHAR(MAX(P.LAST_UPDATE_DATE), 'MM-DD HH24:MI') AS UPD_AT
FROM   SCM_MGR.DM_PLN_CFM_SELLING_PRICE P
WHERE  P.DIVISION_ID = '40' AND P.SCM_SITE_ID LIKE 'AJ%AB_TES'
AND    P.YYYYMMDD >= TO_CHAR(TRUNC(SYSDATE, 'IW'), 'YYYYMMDD')
GROUP BY P.SCM_SITE_ID, P.ITEM_ID, P.PROJECT_CODE, P.END_CUSTOMER, P.DOM_EXP, P.FCST_TYPE, P.INCOTERMS, P.PLANT_SITE_ID, P.CELL_PROD_SITE_ID, P.MEASURE, P.CURRENCY
ORDER BY P.ITEM_ID, P.FCST_TYPE, P.INCOTERMS, P.PLANT_SITE_ID, P.CELL_PROD_SITE_ID, P.MEASURE
FETCH FIRST 150 ROWS ONLY;

-- A3. 판정 — 수요 원장의 키 · 메저마다 LOC 통화를 어느 단계에서 찾을 수 있는가
--     K9 = 전 키 일치(1차) / K8 = Cell Prod Site 만 빼고 일치(2차) / K5 = Site · Item · Dom/Exp · Fcst Type 만 일치(3차)
--     각 칸 = 그 조건으로 찾은 LOC 통화 종류 (없으면 빈칸, 2종 이상이면 'A,B' — 2차 · 3차는 1종일 때만 채운다)
--     JUDGE: VMI 계열은 규칙상 채우지 않는다 / 그 외에 세 칸이 다 비면 조회 화면에서도 통화가 빈다
SELECT 'A3' AS Q, SUBSTR(K.ITEM_ID, 1, 16) AS ITEM_ID, SUBSTR(K.FTYPE, 1, 6) AS FTYPE, '[' || K.INCO || ']' AS INCO
     , '[' || K.PLANT || ']' AS PLANT, '[' || K.CELL_PROD || ']' AS CELL_PROD, SUBSTR(K.MEASURE, 1, 12) AS MEASURE
     , K.K9 AS CUR_K9, K.K8 AS CUR_K8, K.K5 AS CUR_K5
     , CASE WHEN K.MEASURE LIKE 'VMI%' THEN 'VMI 계열 — 규칙상 빈값'
            WHEN K.K9 IS NOT NULL THEN '1차에서 채움'
            WHEN K.K8 IS NOT NULL AND INSTR(K.K8, ',') = 0 THEN '2차에서 채움 (Cell Prod Site 다름)'
            WHEN K.K5 IS NOT NULL AND INSTR(K.K5, ',') = 0 THEN '3차에서 채움 (다른 키 다름)'
            WHEN K.K8 IS NOT NULL OR K.K5 IS NOT NULL THEN '못 채움 — 통화 2종 이상'
            ELSE '못 채움 — 같은 Site · Item 의 LOC 없음' END AS JUDGE
FROM   ( SELECT D.ITEM_ID, D.FCST_TYPE AS FTYPE, D.INCOTERMS AS INCO, D.PLANT_SITE_ID AS PLANT, D.CELL_PROD_SITE_ID AS CELL_PROD, D.MEASURE
              , ( SELECT LISTAGG(DISTINCT P.CURRENCY, ',') WITHIN GROUP (ORDER BY P.CURRENCY) FROM SCM_MGR.DM_PLN_CFM_SELLING_PRICE P
                  WHERE  P.DIVISION_ID = '40' AND P.MEASURE = 'LOC' AND P.YYYYMMDD >= TO_CHAR(TRUNC(SYSDATE, 'IW'), 'YYYYMMDD')
                  AND    P.SCM_SITE_ID = D.SCM_SITE_ID AND P.ITEM_ID = D.ITEM_ID AND P.DOM_EXP = D.DOM_EXP AND P.FCST_TYPE = D.FCST_TYPE
                  AND    P.PROJECT_CODE = D.PROJECT_CODE AND P.END_CUSTOMER = D.END_CUSTOMER AND P.INCOTERMS = D.INCOTERMS
                  AND    P.PLANT_SITE_ID = D.PLANT_SITE_ID AND P.CELL_PROD_SITE_ID = D.CELL_PROD_SITE_ID ) AS K9
              , ( SELECT LISTAGG(DISTINCT P.CURRENCY, ',') WITHIN GROUP (ORDER BY P.CURRENCY) FROM SCM_MGR.DM_PLN_CFM_SELLING_PRICE P
                  WHERE  P.DIVISION_ID = '40' AND P.MEASURE = 'LOC' AND P.YYYYMMDD >= TO_CHAR(TRUNC(SYSDATE, 'IW'), 'YYYYMMDD')
                  AND    P.SCM_SITE_ID = D.SCM_SITE_ID AND P.ITEM_ID = D.ITEM_ID AND P.DOM_EXP = D.DOM_EXP AND P.FCST_TYPE = D.FCST_TYPE
                  AND    P.PROJECT_CODE = D.PROJECT_CODE AND P.END_CUSTOMER = D.END_CUSTOMER AND P.INCOTERMS = D.INCOTERMS
                  AND    P.PLANT_SITE_ID = D.PLANT_SITE_ID ) AS K8
              , ( SELECT LISTAGG(DISTINCT P.CURRENCY, ',') WITHIN GROUP (ORDER BY P.CURRENCY) FROM SCM_MGR.DM_PLN_CFM_SELLING_PRICE P
                  WHERE  P.DIVISION_ID = '40' AND P.MEASURE = 'LOC' AND P.YYYYMMDD >= TO_CHAR(TRUNC(SYSDATE, 'IW'), 'YYYYMMDD')
                  AND    P.SCM_SITE_ID = D.SCM_SITE_ID AND P.ITEM_ID = D.ITEM_ID AND P.DOM_EXP = D.DOM_EXP AND P.FCST_TYPE = D.FCST_TYPE ) AS K5
         FROM   ( SELECT DISTINCT SCM_SITE_ID, ITEM_ID, PROJECT_CODE, END_CUSTOMER, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, CELL_PROD_SITE_ID, MEASURE
                  FROM   SCM_MGR.DM_PLN_CFM_MKT_DEMAND_PLAN
                  WHERE  DIVISION_ID = '40' AND SCM_SITE_ID LIKE 'AJ%AB_TES'
                  AND    YYYYMMDD >= TO_CHAR(TRUNC(SYSDATE, 'IW'), 'YYYYMMDD') ) D ) K
ORDER BY K.ITEM_ID, K.FTYPE, K.INCO, K.PLANT, K.CELL_PROD, K.MEASURE
FETCH FIRST 150 ROWS ONLY;

-- A4. 클라우드 조회 프로시저의 통화 채움 구간 — 2차 · 3차 보완과 VMI 제외 조건이 들어 있는지, 빈값 표기가 무엇인지
--     사내: 1차 MERGE(3234행) · 2차 [E20260918-CURRCELLPROD] · 3차 [E20260918-CURRSITEITEM] · 표시 통일 [E20260901-CURRKEEP](빈값 표기 '/')
SELECT 'A4' AS Q, S.LINE
     , ( SELECT TO_CHAR(MAX(O.LAST_DDL_TIME), 'MM-DD HH24:MI') FROM ALL_OBJECTS O
         WHERE O.OWNER = 'SCM_MGR' AND O.OBJECT_NAME = 'PKG_DMF0082' AND O.OBJECT_TYPE = 'PACKAGE BODY' ) AS LAST_DDL
     , SUBSTR(LTRIM(REPLACE(RTRIM(S.TEXT, CHR(10)), CHR(9), ' ')), 1, 130) AS TEXT
FROM   ALL_SOURCE S
WHERE  S.OWNER = 'SCM_MGR' AND S.NAME = 'PKG_DMF0082' AND S.TYPE = 'PACKAGE BODY'
AND    (    S.TEXT LIKE '%CURRCELLPROD%' OR S.TEXT LIKE '%CURRSITEITEM%' OR S.TEXT LIKE '%CURRNULLKEY%' OR S.TEXT LIKE '%CURRKEEP%'
         OR S.TEXT LIKE '%MEASURE NOT LIKE ''VMI\%''%' ESCAPE '\'
         OR S.TEXT LIKE '%WHEN MATCHED THEN UPDATE SET A.CURRENCY = B.CURRENCY%'
         OR S.TEXT LIKE '%OR CURRENCY IS NULL OR TRIM(CURRENCY) IS NULL%'
         OR S.TEXT LIKE '%NVL(PLANT_SITE_ID, %AS PLANT_SITE_ID%' )
ORDER BY S.LINE
FETCH FIRST 60 ROWS ONLY;

-- A5. 이 사이트의 품목 마스터 · 사이트 품목 등록 상태 (조회 대상에 들어오는 품목인지, 통화 관련 속성)
SELECT 'A5' AS Q, SUBSTR(I.SCM_SITE_ID, 1, 16) AS SITE, SUBSTR(I.ITEM_ID, 1, 16) AS ITEM_ID, '[' || SUBSTR(I.PROJECT_CODE, 1, 14) || ']' AS PROJECT
     , I.VALID_YN, I.SALES_PLAN_ADJUST_YN AS ADJ_YN, SUBSTR(I.CREATED_BY, 1, 12) AS CREATED_BY
     , TO_CHAR(I.CREATION_DATE, 'MM-DD HH24:MI') AS CREATED_AT, TO_CHAR(I.LAST_UPDATE_DATE, 'MM-DD HH24:MI') AS UPD_AT
FROM   SCM_MGR.SCM_MST_SITE_ITEM I
WHERE  I.DIVISION_ID = '40' AND I.SCM_SITE_ID LIKE 'AJ%AB_TES'
ORDER BY I.ITEM_ID, I.PROJECT_CODE
FETCH FIRST 60 ROWS ONLY;
