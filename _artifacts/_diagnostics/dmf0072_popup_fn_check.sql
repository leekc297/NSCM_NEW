PROMPT === [1] UF_FX_STRING_SPLIT* 함수 가용성 ===
SELECT OBJECT_NAME||'|'||OBJECT_TYPE||'|'||STATUS AS O
  FROM ALL_OBJECTS
 WHERE OWNER='SCM_MGR'
   AND (UPPER(OBJECT_NAME) LIKE '%STRING_SPLIT%')
 ORDER BY OBJECT_NAME;

PROMPT === [2] SCM_MST_ITEM_SN / SITE_ITEM / PROJECT 데이터 카운트 ===
SELECT 'SCM_MST_ITEM_SN' AS T, COUNT(*) AS V FROM SCM_MGR.SCM_MST_ITEM_SN;
SELECT 'SCM_MST_SITE_ITEM' AS T, COUNT(*) AS V FROM SCM_MGR.SCM_MST_SITE_ITEM;
SELECT 'SCM_MST_SITE_ITEM by VALID_YN=Y' AS T, COUNT(*) AS V FROM SCM_MGR.SCM_MST_SITE_ITEM WHERE VALID_YN='Y';
SELECT 'SCM_MST_PROJECT' AS T, COUNT(*) AS V FROM SCM_MGR.SCM_MST_PROJECT;
SELECT 'SCM_ADM_LOOKUP_MASTER_DETAIL ITEM_TYPE_CODE' AS T, COUNT(*) AS V FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE='ITEM_TYPE_CODE';
SELECT 'SCM_ADM_LOOKUP_MASTER_DETAIL BIZ_TYPE_BPMS' AS T, COUNT(*) AS V FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE='BIZ_TYPE_BPMS';

PROMPT === [3] SCM_MST_ITEM_SN 의 컬럼 (ITEM_TYPE/ACTIVE_FLAG/ITEM_CLASS_NAME/NICK_NAME) ===
SELECT COLUMN_NAME||'|'||DATA_TYPE AS COL
  FROM ALL_TAB_COLUMNS
 WHERE OWNER='SCM_MGR' AND TABLE_NAME='SCM_MST_ITEM_SN'
   AND COLUMN_NAME IN ('DIVISION_ID','ITEM_ID','ITEM_NAME','ITEM_TYPE','ITEM_CLASS_NAME','NICK_NAME','ACTIVE_FLAG')
 ORDER BY COLUMN_ID;

PROMPT === [4] SCM_MST_PROJECT 컬럼 ===
SELECT COLUMN_NAME||'|'||DATA_TYPE AS COL
  FROM ALL_TAB_COLUMNS
 WHERE OWNER='SCM_MGR' AND TABLE_NAME='SCM_MST_PROJECT'
   AND COLUMN_NAME IN ('DIVISION_ID','PROJECT_CODE','PROJECT_NAME','PROJECT_STATUS','BIZ_TYPE','BIZ_TYPE_NAME','CURRENCY','PROJECT_VER_SEQ','PROJECT_OWNER','DROP_YN')
 ORDER BY COLUMN_ID;

PROMPT === [5] SCM_MST_DIVISION 컬럼 (VALID_YN/DIVISION_NAME) ===
SELECT COLUMN_NAME||'|'||DATA_TYPE AS COL
  FROM ALL_TAB_COLUMNS
 WHERE OWNER='SCM_MGR' AND TABLE_NAME='SCM_MST_DIVISION'
   AND COLUMN_NAME IN ('DIVISION_ID','DIVISION_NAME','VALID_YN')
 ORDER BY COLUMN_ID;

