PROMPT ================= §5 ⭐ Model 빈칸 → 프로젝트 하위 품목 펼침 조건 (품목별 · 하나라도 N 이면 그 품목은 저장 안 됨) =================
PROMPT  SITE_OK=고객사 사이트 VALID · ITEM_OK=품목 VALID · DEPT_OK=품목 부서명=엑셀 Team · LOC_FP=기존 LOC 가격 행 · RTF_PLAN=RTF_SYS_RP 계획 행
WITH P AS (SELECT '81' AS DIV, 'AI/빅데이터1.빅데이터분석팀' AS TEAM, 'Alte' AS CUST, 'A21BW2003' AS PRJ, 'USD' AS CUR FROM DUAL)
, I AS (   -- 프로젝트에 걸린 전 품목 (사이트·고객 무관 — SSPM 화면에서 보이는 범위)
  SELECT ITM.SCM_SITE_ID, ITM.ITEM_ID, ITM.DEPT_ID, ITM.VALID_YN AS ITEM_VALID
       , MS.END_CUSTOMER, MS.VALID_YN AS SITE_VALID
    FROM SCM_MST_SITE_ITEM ITM
    CROSS JOIN P
    LEFT JOIN SCM_MST_SITE MS ON MS.DIVISION_ID = ITM.DIVISION_ID AND MS.SCM_SITE_ID = ITM.SCM_SITE_ID
   WHERE ITM.DIVISION_ID = P.DIV AND ITM.PROJECT_CODE = P.PRJ
)
SELECT I.SCM_SITE_ID, I.ITEM_ID, I.DEPT_ID
     , SUBSTR(DI.DEPT_NAME_KO,1,30) AS DEPT_NAME
     , CASE WHEN I.END_CUSTOMER = P.CUST AND I.SITE_VALID = 'Y' THEN 'Y' ELSE 'N(' || NVL(I.END_CUSTOMER,'-') || '/' || NVL(I.SITE_VALID,'-') || ')' END AS SITE_OK
     , CASE WHEN I.ITEM_VALID = 'Y' THEN 'Y' ELSE 'N' END AS ITEM_OK
     , CASE WHEN DI.DEPT_NAME_KO = P.TEAM AND DI.VALID_YN = 'Y' THEN 'Y' ELSE 'N' END AS DEPT_OK
     , (SELECT COUNT(*) FROM SCM_MST_FUTURE_PRICE FP
         WHERE FP.DIVISION_ID = P.DIV AND FP.PROJECT_CODE = P.PRJ AND FP.SCM_SITE_ID = I.SCM_SITE_ID
           AND FP.ITEM_ID = I.ITEM_ID AND FP.MEASURE = 'LOC') AS LOC_FP
     , (SELECT COUNT(*) FROM DM_PLN_SALES_PLAN PN
         WHERE PN.DIVISION_ID = P.DIV AND PN.PROJECT_CODE = P.PRJ AND PN.SCM_SITE_ID = I.SCM_SITE_ID
           AND PN.ITEM_ID = I.ITEM_ID AND PN.MEASURE = 'RTF_SYS_RP') AS RTF_PLAN
     , CASE WHEN NOT (I.END_CUSTOMER = P.CUST AND I.SITE_VALID = 'Y') THEN '✗ 사이트가 End Customer(Alte) 아님/무효'
            WHEN I.ITEM_VALID <> 'Y' THEN '✗ 품목 VALID_YN<>Y'
            WHEN NOT (DI.DEPT_NAME_KO = P.TEAM AND DI.VALID_YN = 'Y') THEN '✗ 품목 부서명 ≠ 엑셀 Team'
            WHEN (SELECT COUNT(*) FROM SCM_MST_FUTURE_PRICE FP
                   WHERE FP.DIVISION_ID = P.DIV AND FP.PROJECT_CODE = P.PRJ AND FP.SCM_SITE_ID = I.SCM_SITE_ID
                     AND FP.ITEM_ID = I.ITEM_ID AND FP.MEASURE = 'LOC') = 0
             AND (SELECT COUNT(*) FROM DM_PLN_SALES_PLAN PN
                   WHERE PN.DIVISION_ID = P.DIV AND PN.PROJECT_CODE = P.PRJ AND PN.SCM_SITE_ID = I.SCM_SITE_ID
                     AND PN.ITEM_ID = I.ITEM_ID AND PN.MEASURE = 'RTF_SYS_RP') = 0
                 THEN '✗ 기존 LOC 가격·RTF 계획 모두 없음'
            ELSE '✓ 저장 대상' END AS VERDICT
  FROM I CROSS JOIN P
  LEFT JOIN SCM_MST_SSO_DEPT_INFO DI ON DI.DEPT_ID = I.DEPT_ID
 ORDER BY I.SCM_SITE_ID, I.ITEM_ID;

PROMPT  -- 5-2 ⭐ 펼침 조건 단계별 집계 (FINAL_OK = 0 이면 검증 SUCCESS 여도 저장 0행 — 화면에 아무것도 안 보임)
WITH P AS (SELECT '81' AS DIV, 'AI/빅데이터1.빅데이터분석팀' AS TEAM, 'Alte' AS CUST, 'A21BW2003' AS PRJ FROM DUAL)
, I AS (
  SELECT ITM.SCM_SITE_ID, ITM.ITEM_ID, ITM.DEPT_ID, ITM.VALID_YN AS ITEM_VALID, MS.END_CUSTOMER, MS.VALID_YN AS SITE_VALID
    FROM SCM_MST_SITE_ITEM ITM CROSS JOIN P
    LEFT JOIN SCM_MST_SITE MS ON MS.DIVISION_ID = ITM.DIVISION_ID AND MS.SCM_SITE_ID = ITM.SCM_SITE_ID
   WHERE ITM.DIVISION_ID = P.DIV AND ITM.PROJECT_CODE = P.PRJ
), F AS (
  SELECT I.*
       , CASE WHEN I.END_CUSTOMER = P.CUST AND I.SITE_VALID = 'Y' AND I.ITEM_VALID = 'Y' THEN 1 ELSE 0 END AS S1
       , CASE WHEN EXISTS (SELECT 1 FROM SCM_MST_SSO_DEPT_INFO DI WHERE DI.DEPT_ID = I.DEPT_ID AND DI.DEPT_NAME_KO = P.TEAM AND DI.VALID_YN = 'Y') THEN 1 ELSE 0 END AS S2
       , CASE WHEN EXISTS (SELECT 1 FROM SCM_MST_FUTURE_PRICE FP WHERE FP.DIVISION_ID = P.DIV AND FP.PROJECT_CODE = P.PRJ
                             AND FP.SCM_SITE_ID = I.SCM_SITE_ID AND FP.ITEM_ID = I.ITEM_ID AND FP.MEASURE = 'LOC')
                OR EXISTS (SELECT 1 FROM DM_PLN_SALES_PLAN PN WHERE PN.DIVISION_ID = P.DIV AND PN.PROJECT_CODE = P.PRJ
                             AND PN.SCM_SITE_ID = I.SCM_SITE_ID AND PN.ITEM_ID = I.ITEM_ID AND PN.MEASURE = 'RTF_SYS_RP') THEN 1 ELSE 0 END AS S3
    FROM I CROSS JOIN P
)
SELECT COUNT(*) AS PRJ_ITEMS
     , SUM(S1) AS SITE_ALTE_OK
     , SUM(S2) AS DEPT_TEAM_OK
     , SUM(S3) AS LOC_OR_RTF_OK
     , SUM(S1 * S2) AS SITE_AND_DEPT
     , SUM(S1 * S2 * S3) AS FINAL_OK
     , CASE WHEN SUM(S1 * S2 * S3) = 0 THEN '⛔ 저장 대상 품목 0 — 검증 SUCCESS 여도 저장 0행'
            ELSE '저장 대상 ' || SUM(S1 * S2 * S3) || '품목' END AS JUDGE
  FROM F;

PROMPT  -- 5-3 End Customer = Alte 인 81 사이트 목록 (엑셀 End Customer 가 가리키는 사이트)
SELECT MS.SCM_SITE_ID, MS.END_CUSTOMER, MS.VALID_YN AS SITE_OK, SUBSTR(MS.SITE_DESCRIPTION,1,40) AS SITE_DESC
     , (SELECT COUNT(*) FROM SCM_MST_SITE_ITEM ITM WHERE ITM.DIVISION_ID = MS.DIVISION_ID AND ITM.SCM_SITE_ID = MS.SCM_SITE_ID
           AND ITM.PROJECT_CODE = 'A21BW2003') AS PRJ_ITEMS_ON_SITE
  FROM SCM_MST_SITE MS
 WHERE MS.DIVISION_ID = '81' AND MS.END_CUSTOMER = 'Alte'
 ORDER BY MS.SCM_SITE_ID;

PROMPT ================= §6 달력 — M2 월(업로드 당일 기준 +2개월)의 주 시작일이 52주 범위에 있는가 =================
SELECT TO_CHAR(ADD_MONTHS(SYSDATE,2),'YYYYMM') AS K
     , TO_CHAR(COUNT(DISTINCT CAL.BASIS_START_DATE)) AS V
     , CASE WHEN COUNT(DISTINCT CAL.BASIS_START_DATE) = 0 THEN '⛔ 주 시작일 없음 → 저장 행 0' ELSE 'OK' END AS JUDGE
  FROM SCM_SYS_CALENDAR_M CAL
 WHERE CAL.BASIS_YYYYMMDD >= TO_CHAR(SYSDATE,'YYYYMMDD')
   AND CAL.BASIS_YYYYMMDD <  TO_CHAR(SYSDATE + 52 * 7,'YYYYMMDD')
   AND SUBSTR(CAL.BASIS_START_DATE,1,6) = TO_CHAR(ADD_MONTHS(SYSDATE,2),'YYYYMM');

