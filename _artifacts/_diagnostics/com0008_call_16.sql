DECLARE
    V_RC SYS_REFCURSOR;
    V_RC2 SYS_REFCURSOR;
    V_DIV VARCHAR2(50); V_DN VARCHAR2(50);
    V_PC VARCHAR2(100); V_PN VARCHAR2(300);
    V_SS VARCHAR2(50); V_SD VARCHAR2(300);
    V_IID VARCHAR2(100); V_INM VARCHAR2(300);
    V_TY VARCHAR2(10); V_TYN VARCHAR2(100);
    V_NICK VARCHAR2(300); V_CLS VARCHAR2(300);
    V_DEPT VARCHAR2(50); V_DEPN VARCHAR2(200);
    V_EC VARCHAR2(100); V_CUR VARCHAR2(20);
    V_CNT PLS_INTEGER;

    PROCEDURE TST(P1 VARCHAR2, P2 VARCHAR2, P3 VARCHAR2, P4 VARCHAR2, P5 VARCHAR2, P6 VARCHAR2, P7 VARCHAR2) AS
    BEGIN
        V_CNT := 0;
        SCM_MGR.PKG_COM0000.P_COM0008_GET_ITEM_BY_DIVISION_POPUP(
            P1, P2, P3, P4, P5, P6, P7, V_RC, V_RC2
        );
        LOOP
            FETCH V_RC INTO V_DIV, V_DN, V_PC, V_PN, V_SS, V_SD, V_IID, V_INM, V_TY, V_TYN, V_NICK, V_CLS, V_DEPT, V_DEPN, V_EC, V_CUR;
            EXIT WHEN V_RC%NOTFOUND;
            V_CNT := V_CNT + 1;
        END LOOP;
        CLOSE V_RC;
        DBMS_OUTPUT.PUT_LINE('CALL(' || P1 || ',' || P2 || ',' || P3 || ',' || P4 || ',' || P5 || ',' || P6 || ',' || P7 || ') = ' || V_CNT || ' rows');
    EXCEPTION WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('FAIL ' || SQLCODE || ' ' || SUBSTR(SQLERRM, 1, 150));
    END;
BEGIN
    TST('40', 'ALL', 'ALL', 'ALL', '', '', '');
    TST('40', 'ALL', 'ALL', 'ALL', '', '', 'Y');
    TST('81', 'ALL', 'ALL', 'ALL', '', '', '');
    TST('82', 'ALL', 'ALL', 'ALL', '', '', '');
END;
/

