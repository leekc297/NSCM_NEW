PROCEDURE         P_SYS0014_GET_AUTH_LIST_M (
    P_USER_GR_ID     IN  VARCHAR2,
    P_USER_ID        IN  VARCHAR2,
    P_UNIT_TP_CD     IN  VARCHAR2,
    O_RC1            OUT SYS_REFCURSOR,
    O_RESULT_CURSOR  OUT SYS_REFCURSOR
)
AS
BEGIN
    -- AS-IS SCM0005 FindData_Division (UP_FX_GetUserGroupAuthExtentionList): 그룹 조건부 AuthType
    --   비 JV 그룹 → AuthType='D' (부문권한, JV_PLANT 빈값) / 'JV Planner' 그룹 → AuthType='J' (DIVISION + JV_PLANT)
    --   * 컬럼 추가 없이 J 데이터는 TB_FX_USERGROUPAUTHEXTENTION.JV_PLANT_ID(기존 컬럼) JOIN 으로 동시 출력
    -- 표시: Name(UNIT_ID) + JV Plant(JV_PLANT_ID). 저장용 UPPR_UNIT_ID/EDIT_YN/USE_YN 동반.
    OPEN O_RC1 FOR
    SELECT A.UNIT_ID,
           D.DIVISION_NAME AS UNIT_NM,
           CAST(NULL AS VARCHAR2(4000)) AS JV_PLANT_ID,
           A.UPPR_UNIT_ID, A.EDIT_YN, A.USE_YN
      FROM SCM_MGR.SCM_ADM_USER_GR_UNIT_AUTH_MPG_M A
      LEFT JOIN SCM_MGR.SCM_MST_DIVISION D ON D.DIVISION_ID = A.UNIT_ID
     WHERE A.USER_GR_ID = P_USER_GR_ID
       AND A.USER_ID    = P_USER_ID
       AND A.UNIT_TP_CD = P_UNIT_TP_CD
       AND P_USER_GR_ID <> 'JV Planner'
    UNION ALL
    SELECT DISTINCT
           B.CODE        AS UNIT_ID,
           D.DIVISION_NAME AS UNIT_NM,
           B.JV_PLANT_ID,
           '-' AS UPPR_UNIT_ID, 'Y' AS EDIT_YN, 'Y' AS USE_YN
      FROM SCM_MGR.TB_FX_USERGROUPAUTHEXTENTION B
      LEFT JOIN SCM_MGR.SCM_MST_DIVISION D ON D.DIVISION_ID = B.CODE
     WHERE B.AUTHTYPE = 'J'
       AND B.GROUPID  = P_USER_GR_ID
       AND B.USERID   = P_USER_ID
       AND P_USER_GR_ID = 'JV Planner'
     ORDER BY 1;

    OPEN O_RESULT_CURSOR FOR
    SELECT '0' AS CODE, 'SUCCESS' AS MSG FROM DUAL;
EXCEPTION
    WHEN OTHERS THEN
        DECLARE V_ERR VARCHAR2(4000) := SUBSTR(SQLERRM, 1, 4000);
        BEGIN
            OPEN O_RC1 FOR SELECT NULL AS DUMMY FROM DUAL WHERE 1=0;
            OPEN O_RESULT_CURSOR FOR SELECT '-1' AS CODE, V_ERR AS MSG FROM DUAL;
        END;
END P_SYS0014_GET_AUTH_LIST_M;