PACKAGE BODY           "PKG_SYS0006"
AS

	PROCEDURE SYS0006_GET_MAIN_DATA (
		P_LANG_CD		IN 		VARCHAR2,
		P_API_TP_CD		IN      VARCHAR2,
		P_API_ID		IN      VARCHAR2,
		P_USE_YN		IN      VARCHAR2,
		P_USER_ID		IN      VARCHAR2,
		P_MENU_ID		IN      VARCHAR2,

		O_CURSOR		OUT		SYS_REFCURSOR,
		O_RESULT_CURSOR	OUT		SYS_REFCURSOR
    ) IS

    	V_ROW_CNT	NUMBER := 0;
    	V_ERR_MSG 	VARCHAR2(4000);

	BEGIN

		OPEN O_CURSOR FOR
		 SELECT  API_ID, API_TP_CD, NVL2(MSG.MSG_NM, API_MSG_ID, '-') AS API_MSG_ID,  NVL(MSG.MSG_NM, API_MSG_DESC) API_MSG_NM, API.API_MSG_DESC
		 	   , API_URL, API.USE_YN, API.CREATED_BY, API.CREATION_DATE, API.LAST_UPDATED_BY, API.LAST_UPDATE_DATE
	       FROM  SCM_ADM_API_M API
	  LEFT JOIN  SCM_ADM_MSG_M MSG
	         ON  API.API_MSG_ID = MSG.MSG_ID
	        AND  MSG.LANG_CD = P_LANG_CD
	      WHERE  1=1
	        AND  (NVL(P_API_TP_CD, 'ALL') = 'ALL' OR API.API_TP_CD IN (SELECT VALUE FROM TABLE(SCM_MGR.FN_SPLITSTRING(P_API_TP_CD, ','))))
	        AND  API_ID LIKE '%'||P_API_ID||'%'
	        AND  (NVL(P_USE_YN, 'ALL') = 'ALL' OR API.USE_YN = P_USE_YN)
	        ;

	 	OPEN O_RESULT_CURSOR FOR
		 SELECT '0' CODE, 'SUSSESS' MSG, V_ROW_CNT EVENT FROM DUAL;

	EXCEPTION
	  WHEN OTHERS THEN
	    RAISE_APPLICATION_ERROR(-20001,
	      ' SQLCODE=' || SQLCODE ||
	      ' / SQLERRM=' || SQLERRM
	    );
	    RAISE;

	END;



	PROCEDURE SYS0006_SAVE_MAIN_DATA (
		P_DATA			IN 		CLOB,
		P_USER_ID		IN 		VARCHAR2,

		O_RESULT_CURSOR	OUT		SYS_REFCURSOR
	) IS

		V_ROW_CNT	NUMBER := 0;
		V_ROW_CNT2	NUMBER := 0;
		V_ERR_MSG 	VARCHAR2(4000);

	BEGIN


		DELETE SCM_ADM_API_M
		WHERE API_ID IN (SELECT  V_API_ID
						   FROM  JSON_TABLE(P_DATA, '$[*]'
						    	 	COLUMNS (
						    	 		V_CRUD_TYPE VARCHAR(10) PATH '$."CRUD_TYPE"',
						    	 		V_API_ID VARCHAR(100) PATH '$."API_ID"',
						    	 		V_API_TP_CD VARCHAR(150) PATH '$."API_TP_CD"',
						    	 		V_API_MSG_ID VARCHAR(150) PATH '$."API_MSG_ID"',
						    	 		V_API_MSG_DESC VARCHAR(150) PATH '$."API_MSG_DESC"',
						    	 		V_API_URL VARCHAR(400) PATH '$."API_URL"',
						    	 		V_USE_YN VARCHAR(10) PATH '$."USE_YN"'
						    	 	))
			    	 	   WHERE  V_CRUD_TYPE = 'D');

		V_ROW_CNT := SQL%ROWCOUNT;


		MERGE INTO  SCM_ADM_API_M TGT
			 USING  ( SELECT  V_CRUD_TYPE CRUD_TYPE
			 				, V_API_ID API_ID
			                , V_API_TP_CD API_TP_CD
			                , V_API_URL API_URL
			                , V_API_MSG_ID API_MSG_ID
			                , V_API_MSG_DESC API_MSG_DESC
			                , V_USE_YN USE_YN
			                , P_USER_ID USER_ID
						FROM JSON_TABLE(P_DATA, '$[*]'
			    	 	COLUMNS (
			    	 		V_CRUD_TYPE VARCHAR(10) PATH '$."CRUD_TYPE"',
			    	 		V_API_ID VARCHAR(100) PATH '$."API_ID"',
			    	 		V_API_TP_CD VARCHAR(150) PATH '$."API_TP_CD"',
			    	 		V_API_MSG_ID VARCHAR(150) PATH '$."API_MSG_ID"',
			    	 		V_API_MSG_DESC VARCHAR(150) PATH '$."API_MSG_DESC"',
			    	 		V_API_URL VARCHAR(400) PATH '$."API_URL"',
			    	 		V_USE_YN VARCHAR(10) PATH '$."USE_YN"'
			    	 	))
			    	 	WHERE V_CRUD_TYPE IN ('M', 'I')
			    	 	) SRC
		        ON  (TGT.API_ID = SRC.API_ID)
		WHEN MATCHED THEN
	  			UPDATE SET
	  				TGT.API_TP_CD = SRC.API_TP_CD
	  				, TGT.API_MSG_ID = SRC.API_MSG_ID
	  				, TGT.API_MSG_DESC = SRC.API_MSG_DESC
	  				, TGT.API_URL = SRC.API_URL
	  				, TGT.USE_YN = SRC.USE_YN
	  				, TGT.LAST_UPDATED_BY = SRC.USER_ID
	  				, TGT.LAST_UPDATE_DATE = SYSDATE

		WHEN NOT MATCHED THEN
				INSERT (API_ID, API_TP_CD, API_MSG_ID, API_MSG_DESC, API_URL, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
				VALUES (SRC.API_ID, SRC.API_TP_CD, SRC.API_MSG_ID, SRC.API_MSG_DESC, SRC.API_URL, SRC.USE_YN, SRC.USER_ID, SYSDATE, SRC.USER_ID, SYSDATE);

		V_ROW_CNT2 := SQL%ROWCOUNT;


		OPEN O_RESULT_CURSOR FOR
		 SELECT '0' CODE, 'SUSSESS' MSG, V_ROW_CNT+V_ROW_CNT2 EVENT FROM DUAL;

	EXCEPTION
	  WHEN OTHERS THEN
	    RAISE_APPLICATION_ERROR(-20001,
	      ' SQLCODE=' || SQLCODE ||
	      ' / SQLERRM=' || SQLERRM
	    );
	    RAISE;

	END;

END PKG_SYS0006;