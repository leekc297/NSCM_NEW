PROCEDURE           "P_SYS0015_SAVE_PROGRAM_M" (
    P_SES_USER_ID    IN  VARCHAR2,
    P_DATA           IN  CLOB,
    O_RESULT_CURSOR  OUT SYS_REFCURSOR
)
AS
    V_INSERT_CNT NUMBER := 0;
    V_UPDATE_CNT NUMBER := 0;
    V_DELETE_CNT NUMBER := 0;
BEGIN
    -- INSERT (CRUD_TYPE='I')
    INSERT INTO SCM_MGR.SCM_ADM_PROGRAM
        (PROGRAM_ID, PROGRAM_NAME, PROGRAM_PATH, CLASS_NAME, USE_YN, REGT_USER_ID,
         CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
    SELECT V_PROGRAM_ID, V_PROGRAM_NAME, V_PROGRAM_PATH, V_CLASS_NAME, NVL(V_USE_YN,'Y'), P_SES_USER_ID,
           P_SES_USER_ID, SYSDATE, P_SES_USER_ID, SYSDATE
      FROM JSON_TABLE(P_DATA, '$[*]'
          COLUMNS (
              V_CRUD_TYPE    VARCHAR2(1)   PATH '$.CRUD_TYPE',
              V_PROGRAM_ID   VARCHAR2(50)  PATH '$.PROGRAM_ID',
              V_PROGRAM_NAME VARCHAR2(200) PATH '$.PROGRAM_NAME',
              V_PROGRAM_PATH VARCHAR2(500) PATH '$.PROGRAM_PATH',
              V_CLASS_NAME   VARCHAR2(500) PATH '$.CLASS_NAME',
              V_USE_YN       VARCHAR2(1)   PATH '$.USE_YN'
          ))
     WHERE V_CRUD_TYPE = 'I';
    V_INSERT_CNT := SQL%ROWCOUNT;

    -- UPDATE (CRUD_TYPE='M')
    MERGE INTO SCM_MGR.SCM_ADM_PROGRAM T
    USING (
        SELECT V_PROGRAM_ID AS PROGRAM_ID, V_PROGRAM_NAME AS PROGRAM_NAME,
               V_PROGRAM_PATH AS PROGRAM_PATH, V_CLASS_NAME AS CLASS_NAME, V_USE_YN AS USE_YN
          FROM JSON_TABLE(P_DATA, '$[*]'
              COLUMNS (
                  V_CRUD_TYPE    VARCHAR2(1)   PATH '$.CRUD_TYPE',
                  V_PROGRAM_ID   VARCHAR2(50)  PATH '$.PROGRAM_ID',
                  V_PROGRAM_NAME VARCHAR2(200) PATH '$.PROGRAM_NAME',
                  V_PROGRAM_PATH VARCHAR2(500) PATH '$.PROGRAM_PATH',
                  V_CLASS_NAME   VARCHAR2(500) PATH '$.CLASS_NAME',
                  V_USE_YN       VARCHAR2(1)   PATH '$.USE_YN'
              ))
         WHERE V_CRUD_TYPE = 'M'
    ) S
    ON (T.PROGRAM_ID = S.PROGRAM_ID)
    WHEN MATCHED THEN UPDATE
        SET T.PROGRAM_NAME = S.PROGRAM_NAME,
            T.PROGRAM_PATH = S.PROGRAM_PATH,
            T.CLASS_NAME = S.CLASS_NAME,
            T.USE_YN = NVL(S.USE_YN, 'Y'),
            T.LAST_UPDATED_BY = P_SES_USER_ID,
            T.LAST_UPDATE_DATE = SYSDATE;
    V_UPDATE_CNT := SQL%ROWCOUNT;

    -- DELETE (CRUD_TYPE='D')
    DELETE FROM SCM_MGR.SCM_ADM_PROGRAM T
     WHERE T.PROGRAM_ID IN (
         SELECT V_PROGRAM_ID FROM JSON_TABLE(P_DATA, '$[*]'
             COLUMNS (
                 V_CRUD_TYPE  VARCHAR2(1)  PATH '$.CRUD_TYPE',
                 V_PROGRAM_ID VARCHAR2(50) PATH '$.PROGRAM_ID'
             ))
          WHERE V_CRUD_TYPE = 'D'
     );
    V_DELETE_CNT := SQL%ROWCOUNT;

    COMMIT;

    OPEN O_RESULT_CURSOR FOR
    SELECT '0' AS CODE, 'SUCCESS' AS MSG,
           TO_CHAR(V_INSERT_CNT + V_UPDATE_CNT + V_DELETE_CNT) AS EVENT FROM DUAL;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        DECLARE V_ERR VARCHAR2(4000) := SUBSTR(SQLERRM, 1, 4000);
        BEGIN
            OPEN O_RESULT_CURSOR FOR SELECT '-1' AS CODE, V_ERR AS MSG, '0' AS EVENT FROM DUAL;
        END;
END P_SYS0015_SAVE_PROGRAM_M;