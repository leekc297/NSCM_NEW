    FROM SCM_COM_SYS_LOG L
   WHERE L.MNU_ID = 'DMF0082' AND L.SHT_NM = 'FcstNPrice' AND L.MNU_BTN_CD = 'SEARCH' AND L.CREATION_DATE >= SYSDATE - &MIN/1440
),
