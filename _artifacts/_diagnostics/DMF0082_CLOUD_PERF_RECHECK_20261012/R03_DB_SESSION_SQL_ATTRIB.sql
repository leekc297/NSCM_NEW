    FROM GV$ACTIVE_SESSION_HISTORY A, P, W
   WHERE A.SAMPLE_TIME BETWEEN W.T0 AND W.T1 AND A.PLSQL_ENTRY_OBJECT_ID = P.OBJECT_ID
),
T AS (SELECT SQL_ID, MAX(PROGRAM_LINE#) LN, MIN(SUBSTR(REGEXP_REPLACE(SQL_TEXT,'\s+',' '),1,80)) TXT
