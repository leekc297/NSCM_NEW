--   계정: SCM_MGR
--   [P0] 값 입력 없이 실행 — 최근 &MIN 분 PKG_DMF0082 진입 ASH 상위 3 SQL_ID 의 계획을 자동 출력
--   [P1]~[P6] R03 [D2]/[D1] 또는 R04 (B) 의 SQL_ID 를 아래 DEFINE SQL_ID 에 넣고 다시 실행 (기본값 '-' 는 "못 찾음" 메시지만 내고 오류 없음)
--   A-Rows(실측 행수)까지 보려면: R04 를 c_rowstats := 'Y' 로 한 번 돌린 뒤 이 스크립트 실행
--   ⚠ RAC: DBMS_XPLAN.DISPLAY_CURSOR 는 접속 인스턴스의 커서만 보인다. [P1] INST 열이 다른 인스턴스면 그 인스턴스로 접속해 재실행(또는 BE 가 붙는 인스턴스에서 실행)
--   변경 없음: SELECT 만 수행
-- =============================================================================
SET LINESIZE 300
SET PAGESIZE 0
SET TRIMSPOOL ON
SET VERIFY OFF
SET LONG 100000
DEFINE MIN = 240
DEFINE SQL_ID = '-'
SPOOL R05_PLAN_OUT.txt

PROMPT ################ [P0] ⭐ 자동 — 최근 &MIN 분 PKG_DMF0082 진입 ASH 상위 3 SQL_ID 의 계획 (ALLSTATS LAST) ################
WITH P AS (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0082' AND OBJECT_TYPE='PACKAGE'),
TOPS AS (
  SELECT A.SQL_ID, COUNT(*) SAMPLES, MAX(A.SQL_PLAN_HASH_VALUE) PHV
    FROM GV$ACTIVE_SESSION_HISTORY A, P
   WHERE A.SAMPLE_TIME >= SYSTIMESTAMP - NUMTODSINTERVAL(&MIN,'MINUTE') AND A.PLSQL_ENTRY_OBJECT_ID = P.OBJECT_ID AND A.SQL_ID IS NOT NULL
   GROUP BY A.SQL_ID ORDER BY COUNT(*) DESC FETCH FIRST 3 ROWS ONLY
)
SELECT '### ' || T.SQL_ID || '  samples=' || T.SAMPLES || '  phv=' || T.PHV || '  line=' ||
       (SELECT MAX(PROGRAM_LINE#) FROM GV$SQL Q WHERE Q.SQL_ID = T.SQL_ID) || ' ' || X.PLAN_TABLE_OUTPUT PLAN_TABLE_OUTPUT
  FROM TOPS T, TABLE(DBMS_XPLAN.DISPLAY_CURSOR(T.SQL_ID, NULL, 'ALLSTATS LAST +COST +PEEKED_BINDS +PREDICATE +NOTE')) X;
PROMPT --  확인 포인트:
PROMPT --   ① GT_DMF0082_* 의 E-Rows 가 1 인데 실제(A-Rows/ROWS_PER_EX)는 수만 = 파싱 시점 GTT 추정 붕괴 (07-31 DMF0003 유형) — GTTSTATS 적용본이면 TEMP_SITE_ITEM E-Rows 39070 근처
PROMPT --   ② SCM_MST_FUTURE_PRICE / DM_PLN_SALES_PLAN / DM_PLN_MKT_FCST 에 TABLE ACCESS FULL 또는 NESTED LOOPS 안쪽 INDEX RANGE SCAN 반복 = 접근경로 문제
PROMPT --   ③ MERGE JOIN CARTESIAN / NESTED LOOPS 아래 대용량 = 조인 순서 오류
PROMPT --   ④ Note 절: dynamic statistics used: dynamic sampling (level=2) 표기 여부 — 없으면 DS=0 으로 파싱된 커서
PROMPT --   ⑤ Peeked Binds: :B1 (p_division_id) 가 '82' 인데 81 조회가 이 커서를 재사용 중이면 82 기준 계획

SET PAGESIZE 500
PROMPT ################ [P1] 지정 SQL_ID = &SQL_ID — 자식 커서 목록 (계획별 1회당 비용 · 공유 사유) ################
SELECT S.INST_ID INST, S.CHILD_NUMBER CH, S.PLAN_HASH_VALUE PHV, S.EXECUTIONS EX,
       ROUND(S.ELAPSED_TIME/1e6/GREATEST(S.EXECUTIONS,1), 2) SEC_PER_EX,
       ROUND(S.BUFFER_GETS/GREATEST(S.EXECUTIONS,1)) BG_PER_EX,
       ROUND(S.DISK_READS/GREATEST(S.EXECUTIONS,1)) DR_PER_EX,
       ROUND(S.ROWS_PROCESSED/GREATEST(S.EXECUTIONS,1)) ROWS_PER_EX,
       S.OPTIMIZER_COST COST, S.PROGRAM_LINE# LINE, S.USERS_EXECUTING NOW_RUN,
       S.LAST_LOAD_TIME LOADED, TO_CHAR(S.LAST_ACTIVE_TIME,'MM-DD HH24:MI') LAST_ACT,
       S.IS_BIND_SENSITIVE BS, S.IS_SHAREABLE SH, S.SQL_PLAN_BASELINE BASELINE, S.SQL_PROFILE PROFILE
  FROM GV$SQL S WHERE S.SQL_ID = '&SQL_ID'
 ORDER BY S.INST_ID, S.CHILD_NUMBER;

PROMPT ################ [P2] SQL 전문 (앞 4000자) ################
SELECT SUBSTR(SQL_FULLTEXT, 1, 4000) SQL_TEXT FROM GV$SQL WHERE SQL_ID = '&SQL_ID' AND ROWNUM = 1;

SET PAGESIZE 0
PROMPT ################ [P3] ⭐ 실행계획 — 가장 최근 실행된 자식 (E-Rows vs A-Rows · 접근경로 · Peeked Binds) ################
SELECT PLAN_TABLE_OUTPUT FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR('&SQL_ID',
       (SELECT MAX(CHILD_NUMBER) KEEP (DENSE_RANK LAST ORDER BY LAST_ACTIVE_TIME) FROM GV$SQL WHERE SQL_ID = '&SQL_ID'),
       'ALLSTATS LAST +COST +PEEKED_BINDS +PREDICATE +NOTE'));

PROMPT ################ [P4] 다른 계획(PHV)의 자식이 있으면 그 계획도 (가장 빠른 자식 — 계획 간 비교) ################
SELECT PLAN_TABLE_OUTPUT FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR('&SQL_ID',
       (SELECT MIN(CHILD_NUMBER) KEEP (DENSE_RANK FIRST ORDER BY ELAPSED_TIME/GREATEST(EXECUTIONS,1)) FROM GV$SQL WHERE SQL_ID = '&SQL_ID'),
       'TYPICAL +COST +NOTE'));
PROMPT --  (P3 와 PHV 가 같으면 동일 계획 — 무시)

SET PAGESIZE 500
PROMPT ################ [P5] 계획에 등장하는 영구 테이블·인덱스 통계 (계획 안의 객체만) ################
WITH O AS (SELECT DISTINCT OBJECT_OWNER, OBJECT_NAME, OBJECT_TYPE FROM GV$SQL_PLAN WHERE SQL_ID = '&SQL_ID' AND OBJECT_NAME IS NOT NULL)
SELECT O.OBJECT_TYPE, O.OBJECT_NAME,
       NVL(T.NUM_ROWS, I.NUM_ROWS) NUM_ROWS, NVL(T.BLOCKS, I.LEAF_BLOCKS) BLOCKS_OR_LEAF,
       TO_CHAR(NVL(T.LAST_ANALYZED, I.LAST_ANALYZED),'YYYY-MM-DD') ANALYZED, I.CLUSTERING_FACTOR CLUF,
       T.TEMPORARY TMP, NVL(I.STATUS, '-') IDX_STATUS
  FROM O LEFT JOIN ALL_TABLES T ON T.OWNER = O.OBJECT_OWNER AND T.TABLE_NAME = O.OBJECT_NAME
         LEFT JOIN ALL_INDEXES I ON I.OWNER = O.OBJECT_OWNER AND I.INDEX_NAME = O.OBJECT_NAME
 ORDER BY 1, 2;

PROMPT ################ [P6] AWR 14일 실행 이력 — PHV 변화 시점 ('/' 재컴파일 · GTTSTATS 전후) (권한 없으면 오류 — 무시) ################
SELECT S.SNAP_ID, TO_CHAR(N.BEGIN_INTERVAL_TIME,'MM-DD HH24:MI') SNAP, S.PLAN_HASH_VALUE PHV, S.EXECUTIONS_DELTA EX,
       ROUND(S.ELAPSED_TIME_DELTA/1e6/GREATEST(S.EXECUTIONS_DELTA,1), 2) SEC_PER_EX,
       ROUND(S.BUFFER_GETS_DELTA/GREATEST(S.EXECUTIONS_DELTA,1)) BG_PER_EX, ROUND(S.ROWS_PROCESSED_DELTA/GREATEST(S.EXECUTIONS_DELTA,1)) ROWS_PER_EX
  FROM DBA_HIST_SQLSTAT S JOIN DBA_HIST_SNAPSHOT N ON N.SNAP_ID = S.SNAP_ID AND N.INSTANCE_NUMBER = S.INSTANCE_NUMBER
 WHERE S.SQL_ID = '&SQL_ID' AND N.BEGIN_INTERVAL_TIME > SYSDATE - 14
 ORDER BY S.SNAP_ID DESC FETCH FIRST 30 ROWS ONLY;

