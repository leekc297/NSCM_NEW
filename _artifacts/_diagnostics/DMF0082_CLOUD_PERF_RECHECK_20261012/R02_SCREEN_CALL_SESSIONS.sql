-- R02_SCREEN_CALL_SESSIONS.sql — DMF0082 조회 속도 재점검 ② ⭐ 화면 호출 세션별 소요시간 전수 (READ-ONLY, 전체 F5)
--   계정: SCM_MGR · ⚠ BE 가 붙는 DB(QA 또는 DEV — R01 [E0] 참조)에서 실행
--   원천: SCM_COM_SYS_LOG (BE 가 call-proc 1회마다 1행 기록). 화면 [Search] 1회 = 시트 호출 여러 개
--         (titleSet · version · spreadTitle · buttonAuth · FcstNPrice(메인) · futurePriceInfo · savePriceTitle · savePriceData)
--   액션: MNU_BTN_CD = SEARCH / SAVE / FORM_DATA / UPLOAD / UPLOAD_SAVE / IF — 같은 시트명이라도 SAVE·UPLOAD 는 조회가 아니다.
--         [C0][C1][C8] 은 전체 액션(ACT 열), [C2]~[C7][C9] 는 **SEARCH 만** 집계 (사내 FcstNPrice 최대 868초 행은 SAVE 였음)
--   구간: DB_S = SP 호출+fetch+결과로그 / SERVER_S = BE 전체 / TOTAL_S = FE 왕복 / PRE_DB_S = 권한·커넥션 대기 / BE_POST_S = DB 뒤 BE 처리(직렬화)
--   룰: hook #129 §0.4 — 호출별 전수 측정 뒤 **>= 2초 인 호출만** 튜닝 대상. 2초 미만은 시간만 남기고 제외.
--   조회 창: 기본 최근 14일 (DEFINE DAYS). ⚠ SCM_COM_SYS_LOG 는 PK 외 인덱스가 없어 섹션마다 테이블을 1회 읽는다 — 로그가 크면 수 분. 값 입력 없이 전체 F5 가능.
--   변경 없음: SELECT 만 수행
-- =============================================================================
SET LINESIZE 400
SET PAGESIZE 500
SET TRIMSPOOL ON
SET VERIFY OFF
DEFINE DAYS = 14
COLUMN JUDGE FORMAT A52
COLUMN SHT_NM FORMAT A16
COLUMN DIV FORMAT A6
COLUMN USR FORMAT A14
COLUMN GRP FORMAT A10
COLUMN VER FORMAT A10
COLUMN PERIOD FORMAT A18
COLUMN FILTERS FORMAT A40
COLUMN ERR FORMAT A80
COLUMN SHEETS FORMAT A120
COLUMN MEASURE_LIST FORMAT A100
COLUMN EVENT_K FORMAT A50
SPOOL R02_SCREEN_CALL_SESSIONS_OUT.txt

PROMPT ################ [C0] 시트 × 액션 인벤토리 — 최근 &DAYS 일 DMF0082 가 쏜 call-proc 전부 (사내 30일 SEARCH: titleSet 466 · FcstNPrice 242 · spreadTitle 221 · version 128 · buttonAuth 54 · futurePriceInfo 23 · savePriceData 2 · savePriceTitle 2) ################
SELECT SHT_NM, MNU_BTN_CD ACT, COUNT(*) CALLS, COUNT(DISTINCT CREATED_BY) USERS,
       TO_CHAR(MIN(TRNM_ST_DTM),'MM-DD HH24:MI') FIRST_CALL, TO_CHAR(MAX(TRNM_ST_DTM),'MM-DD HH24:MI') LAST_CALL,
       ROUND(MEDIAN((CAST(DB_TRNM_END_DTM AS DATE)-CAST(DB_TRNM_ST_DTM AS DATE))*86400),1) MED_DB_S,
       ROUND(MAX((CAST(DB_TRNM_END_DTM AS DATE)-CAST(DB_TRNM_ST_DTM AS DATE))*86400),1) MAX_DB_S,
       SUM(CASE WHEN (CAST(DB_TRNM_END_DTM AS DATE)-CAST(DB_TRNM_ST_DTM AS DATE))*86400 >= 2 THEN 1 ELSE 0 END) GE2S_CALLS,
       SUM(CASE WHEN DB_TRNM_END_DTM IS NULL OR EXCT_MSG_CTN IS NOT NULL THEN 1 ELSE 0 END) ERR_OR_NOEND
  FROM SCM_COM_SYS_LOG
 WHERE MNU_ID = 'DMF0082' AND CREATION_DATE >= TRUNC(SYSDATE) - &DAYS
 GROUP BY SHT_NM, MNU_BTN_CD ORDER BY CALLS DESC;
PROMPT --  GE2S_CALLS 가 0 인 시트·액션 = 이번 범위 제외(#129 §0.4). 사내에서 SEARCH 2초↑ 가 상시인 것은 FcstNPrice 만 (titleSet·spreadTitle·buttonAuth 는 간헐 1~7초)

PROMPT ################ [C1] ⭐⭐ 호출별 전수 상세 — 최근 &DAYS 일, 최신순 300건 (모든 시트) ################
PROMPT --  JUDGE: '대상(>=2s)' = 튜닝 대상 / 'NO_END' = BE 가 END 를 못 남김(타임아웃·취소) / 'ERR' = 예외 / '-' = 2초 미만 제외
PROMPT --  BE_POST_S 가 DB_S 와 비슷하거나 더 크면 SQL 이 아니라 BE 직렬화·결과로그 구간(#129 §8 fetch 축)
WITH L AS (
  SELECT L.SHT_NM, L.MNU_BTN_CD ACT, L.CREATED_BY, L.TRNM_ST_DTM, L.EXCT_MSG_CTN,
         REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"divisionId":"([^"]*)"',1,1,NULL,1) DIV,
         REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"userGroup":"([^"]*)"',1,1,NULL,1) GRP,
         REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"versionType":"([^"]*)"',1,1,NULL,1) VER,
         REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"fromYyyymmdd":"([^"]*)"',1,1,NULL,1) || '~' || REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"toYyyymmdd":"([^"]*)"',1,1,NULL,1) PERIOD,
         RTRIM(CASE WHEN REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"plantSiteId":"([^"]*)"',1,1,NULL,1) NOT IN ('ALL') THEN 'plant ' END
            || CASE WHEN REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"projectCode":"([^"]*)"',1,1,NULL,1) NOT IN ('ALL') THEN 'pjt ' END
            || CASE WHEN REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"owner":"([^"]*)"',1,1,NULL,1) NOT IN ('ALL') THEN 'owner ' END
            || CASE WHEN REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"salesSite":"([^"]*)"',1,1,NULL,1) NOT IN ('ALL') THEN 'site ' END
            || CASE WHEN REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"itemId":"([^"]*)"',1,1,NULL,1) NOT IN ('ALL') THEN 'item ' END
            || CASE WHEN REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"deptId":"([^"]*)"',1,1,NULL,1) NOT IN ('ALL') THEN 'dept ' END
            || CASE WHEN REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"endCustomer":"([^"]*)"',1,1,NULL,1) NOT IN ('ALL') THEN 'cust ' END
            || CASE WHEN REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"qtyYn":"Y"') IS NOT NULL THEN 'qtyY ' END) FILTERS,
         (CAST(L.DB_TRNM_END_DTM AS DATE) - CAST(L.DB_TRNM_ST_DTM AS DATE))*86400
           + (EXTRACT(SECOND FROM L.DB_TRNM_END_DTM) - FLOOR(EXTRACT(SECOND FROM L.DB_TRNM_END_DTM))) - (EXTRACT(SECOND FROM L.DB_TRNM_ST_DTM) - FLOOR(EXTRACT(SECOND FROM L.DB_TRNM_ST_DTM))) DB_S,
         (CAST(L.TRNM_END_DTM AS DATE) - CAST(L.TRNM_ST_DTM AS DATE))*86400
           + (EXTRACT(SECOND FROM L.TRNM_END_DTM) - FLOOR(EXTRACT(SECOND FROM L.TRNM_END_DTM))) - (EXTRACT(SECOND FROM L.TRNM_ST_DTM) - FLOOR(EXTRACT(SECOND FROM L.TRNM_ST_DTM))) SERVER_S,
         (CAST(L.LOG_END_DTM AS DATE) - CAST(L.LOG_ST_DTM AS DATE))*86400
           + (EXTRACT(SECOND FROM L.LOG_END_DTM) - FLOOR(EXTRACT(SECOND FROM L.LOG_END_DTM))) - (EXTRACT(SECOND FROM L.LOG_ST_DTM) - FLOOR(EXTRACT(SECOND FROM L.LOG_ST_DTM))) TOTAL_S,
         (CAST(L.DB_TRNM_ST_DTM AS DATE) - CAST(L.TRNM_ST_DTM AS DATE))*86400
           + (EXTRACT(SECOND FROM L.DB_TRNM_ST_DTM) - FLOOR(EXTRACT(SECOND FROM L.DB_TRNM_ST_DTM))) - (EXTRACT(SECOND FROM L.TRNM_ST_DTM) - FLOOR(EXTRACT(SECOND FROM L.TRNM_ST_DTM))) PRE_DB_S,
         (CAST(L.TRNM_END_DTM AS DATE) - CAST(L.DB_TRNM_END_DTM AS DATE))*86400
           + (EXTRACT(SECOND FROM L.TRNM_END_DTM) - FLOOR(EXTRACT(SECOND FROM L.TRNM_END_DTM))) - (EXTRACT(SECOND FROM L.DB_TRNM_END_DTM) - FLOOR(EXTRACT(SECOND FROM L.DB_TRNM_END_DTM))) BE_POST_S,
         L.DB_TRNM_END_DTM
    FROM SCM_COM_SYS_LOG L
   WHERE L.MNU_ID = 'DMF0082' AND L.CREATION_DATE >= TRUNC(SYSDATE) - &DAYS
)
SELECT TO_CHAR(TRNM_ST_DTM,'MM-DD HH24:MI:SS') ST, SHT_NM, ACT, DIV, CREATED_BY USR, GRP, VER, PERIOD, FILTERS,
       ROUND(DB_S,2) DB_S, ROUND(SERVER_S,2) SERVER_S, ROUND(TOTAL_S,2) TOTAL_S, ROUND(PRE_DB_S,2) PRE_DB_S, ROUND(BE_POST_S,2) BE_POST_S,
       CASE WHEN DB_TRNM_END_DTM IS NULL THEN '❌ NO_END (타임아웃·취소 — END 미기록)'
            WHEN EXCT_MSG_CTN IS NOT NULL THEN '❌ ERR'
            WHEN ACT <> 'SEARCH' AND DB_S >= 2 THEN 'ℹ 비조회 액션 >=2s (저장·업로드 — 별건)'
            WHEN DB_S >= 2 THEN '⭐ 대상(>=2s)'
            WHEN SERVER_S >= 2 THEN '⚠ BE 구간 >=2s (DB 는 미달)'
            ELSE '-' END JUDGE,
       SUBSTR(EXCT_MSG_CTN,1,80) ERR
  FROM L
 ORDER BY TRNM_ST_DTM DESC
 FETCH FIRST 300 ROWS ONLY;

PROMPT ################ [C2] ⭐⭐ 화면 [Search] 1회 묶음 — FcstNPrice 호출마다 같은 사용자의 전후 시트 호출을 묶어 "한 번의 조회 = 몇 초" ################
PROMPT --  MAIN_DB_S = FcstNPrice DB 구간 · OTHER_DB_S = 나머지 시트 DB 합 · SHEETS = 시트:DB초 목록 (시작순). 묶음 창 = FcstNPrice 시작 -60초 ~ 종료(없으면 +10분)
PROMPT --  사내 기준(10-12 SYS_LOG): 40 FcstNPrice 중앙 14~56s(10-06 최대 793s = 사내 DB 부하일) · 부속 시트 전부 1초 미만
WITH L AS (
  SELECT L.SHT_NM, L.CREATED_BY, L.TRNM_ST_DTM, L.TRNM_END_DTM, L.DB_TRNM_END_DTM, L.EXCT_MSG_CTN,
         REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"divisionId":"([^"]*)"',1,1,NULL,1) DIV,
         REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"userGroup":"([^"]*)"',1,1,NULL,1) GRP,
         REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"versionType":"([^"]*)"',1,1,NULL,1) VER,
         (CAST(L.DB_TRNM_END_DTM AS DATE) - CAST(L.DB_TRNM_ST_DTM AS DATE))*86400
           + (EXTRACT(SECOND FROM L.DB_TRNM_END_DTM) - FLOOR(EXTRACT(SECOND FROM L.DB_TRNM_END_DTM))) - (EXTRACT(SECOND FROM L.DB_TRNM_ST_DTM) - FLOOR(EXTRACT(SECOND FROM L.DB_TRNM_ST_DTM))) DB_S,
         (CAST(L.TRNM_END_DTM AS DATE) - CAST(L.TRNM_ST_DTM AS DATE))*86400
           + (EXTRACT(SECOND FROM L.TRNM_END_DTM) - FLOOR(EXTRACT(SECOND FROM L.TRNM_END_DTM))) - (EXTRACT(SECOND FROM L.TRNM_ST_DTM) - FLOOR(EXTRACT(SECOND FROM L.TRNM_ST_DTM))) SERVER_S,
         (CAST(L.LOG_END_DTM AS DATE) - CAST(L.LOG_ST_DTM AS DATE))*86400 TOTAL_S
    FROM SCM_COM_SYS_LOG L
   WHERE L.MNU_ID = 'DMF0082' AND L.MNU_BTN_CD = 'SEARCH' AND L.CREATION_DATE >= TRUNC(SYSDATE) - &DAYS
),
M AS (SELECT * FROM L WHERE SHT_NM = 'FcstNPrice'),
O AS (
  SELECT M.TRNM_ST_DTM M_ST, M.CREATED_BY, L.SHT_NM, L.TRNM_ST_DTM, L.DB_S
    FROM M JOIN L ON L.CREATED_BY = M.CREATED_BY AND L.SHT_NM <> 'FcstNPrice'
                 AND L.TRNM_ST_DTM BETWEEN M.TRNM_ST_DTM - NUMTODSINTERVAL(60,'SECOND')
                                        AND NVL(M.TRNM_END_DTM, M.TRNM_ST_DTM + NUMTODSINTERVAL(10,'MINUTE'))
)
SELECT TO_CHAR(M.TRNM_ST_DTM,'MM-DD HH24:MI:SS') ST, M.DIV, M.CREATED_BY USR, M.GRP, M.VER,
       ROUND(M.DB_S,1) MAIN_DB_S, ROUND(M.SERVER_S,1) MAIN_SERVER_S, ROUND(M.TOTAL_S,1) MAIN_TOTAL_S,
       (SELECT COUNT(*) FROM O WHERE O.M_ST = M.TRNM_ST_DTM AND O.CREATED_BY = M.CREATED_BY) OTHER_CALLS,
       (SELECT ROUND(SUM(O.DB_S),1) FROM O WHERE O.M_ST = M.TRNM_ST_DTM AND O.CREATED_BY = M.CREATED_BY) OTHER_DB_S,
       ROUND(M.DB_S + NVL((SELECT SUM(O.DB_S) FROM O WHERE O.M_ST = M.TRNM_ST_DTM AND O.CREATED_BY = M.CREATED_BY),0),1) SEARCH_DB_S,
       CASE WHEN M.DB_TRNM_END_DTM IS NULL OR M.EXCT_MSG_CTN IS NOT NULL THEN '❌ 메인 NO_END/ERR'
            WHEN M.DB_S >= 60 THEN '❌ 메인 60s↑'
            WHEN M.DB_S >= 2 THEN '⭐ 메인 대상(>=2s)'
            WHEN NVL((SELECT MAX(O.DB_S) FROM O WHERE O.M_ST = M.TRNM_ST_DTM AND O.CREATED_BY = M.CREATED_BY),0) >= 2 THEN '⚠ 부속 시트 2s↑ (SHEETS 확인)'
            ELSE 'ok' END JUDGE,
       (SELECT LISTAGG(O.SHT_NM || ':' || ROUND(O.DB_S,1), ' ' ON OVERFLOW TRUNCATE) WITHIN GROUP (ORDER BY O.TRNM_ST_DTM)
          FROM O WHERE O.M_ST = M.TRNM_ST_DTM AND O.CREATED_BY = M.CREATED_BY) SHEETS
  FROM M
 ORDER BY M.TRNM_ST_DTM DESC
 FETCH FIRST 120 ROWS ONLY;
PROMPT --  OTHER_DB_S 가 MAIN_DB_S 에 견줄 만큼 크면 부속 시트(titleSet/spreadTitle/version/buttonAuth)도 대상에 넣는다

PROMPT ################ [C3] ⭐⭐ 시트 × division 요약 (SEARCH 만) — 튜닝 대상 선정표 (#129 §0.4: >=2초 인 호출만) ################
PROMPT --  사내 14일(10-12): FcstNPrice 40 중앙 14s/P90 78s · 81 중앙 7.5s/P90 197s · 82 중앙 7s/P90 241s — 사내도 P90 은 타임아웃급(콜드 판가 랜덤읽기)
WITH L AS (
  SELECT L.SHT_NM, REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"divisionId":"([^"]*)"',1,1,NULL,1) DIV, L.EXCT_MSG_CTN, L.DB_TRNM_END_DTM,
         (CAST(L.DB_TRNM_END_DTM AS DATE) - CAST(L.DB_TRNM_ST_DTM AS DATE))*86400 DB_S,
         (CAST(L.TRNM_END_DTM AS DATE) - CAST(L.TRNM_ST_DTM AS DATE))*86400 SERVER_S,
         (CAST(L.TRNM_END_DTM AS DATE) - CAST(L.DB_TRNM_END_DTM AS DATE))*86400 BE_POST_S
    FROM SCM_COM_SYS_LOG L
   WHERE L.MNU_ID = 'DMF0082' AND L.MNU_BTN_CD = 'SEARCH' AND L.CREATION_DATE >= TRUNC(SYSDATE) - &DAYS
)
SELECT SHT_NM, DIV, COUNT(*) CALLS,
       ROUND(MIN(DB_S),1) MIN_DB, ROUND(MEDIAN(DB_S),1) MED_DB, ROUND(PERCENTILE_CONT(0.9) WITHIN GROUP (ORDER BY DB_S),1) P90_DB, ROUND(MAX(DB_S),1) MAX_DB,
       ROUND(MEDIAN(SERVER_S),1) MED_SERVER, ROUND(MEDIAN(BE_POST_S),1) MED_BE_POST,
       SUM(CASE WHEN DB_S >= 2 THEN 1 ELSE 0 END) GE2S, ROUND(100*SUM(CASE WHEN DB_S >= 2 THEN 1 ELSE 0 END)/COUNT(*)) GE2S_PCT,
       SUM(CASE WHEN DB_TRNM_END_DTM IS NULL THEN 1 ELSE 0 END) NO_END, SUM(CASE WHEN EXCT_MSG_CTN IS NOT NULL THEN 1 ELSE 0 END) ERRS,
       CASE WHEN SUM(CASE WHEN DB_TRNM_END_DTM IS NULL THEN 1 ELSE 0 END) > 0 OR MAX(DB_S) >= 120 THEN '❌ 타임아웃급 — 1순위 대상'
            WHEN MEDIAN(DB_S) >= 2 THEN '⭐ 대상 (중앙값 >=2s)'
            WHEN MAX(DB_S) >= 2 THEN '⚠ 간헐 대상 (일부 호출만 >=2s — 조건·사용자 의존, [C6] 확인)'
            WHEN MEDIAN(BE_POST_S) >= 2 THEN '⚠ BE 후처리 구간 대상 (#129 §8 fetch 축)'
            ELSE '- 제외 (<2s)' END JUDGE
  FROM L
 GROUP BY SHT_NM, DIV
 ORDER BY CASE WHEN SUM(CASE WHEN DB_TRNM_END_DTM IS NULL THEN 1 ELSE 0 END) > 0 THEN 0 ELSE 1 END, MEDIAN(DB_S) DESC NULLS LAST, SHT_NM, DIV;

PROMPT ################ [C4] ⭐⭐ 일자 × division 추이 — FcstNPrice (메인) : '/' 전환·재컴파일 전후 어느 날부터 뛰었나 ################
PROMPT --  R01 [E2] 의 이벤트 시각(SLASHDEF 테이블 ALTER · PKG BODY LAST_DDL · GTTSTATS · 82 '/' 행 최초 생성)과 D 열을 맞춘다
WITH L AS (
  SELECT TO_CHAR(L.TRNM_ST_DTM,'MM-DD') D, REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"divisionId":"([^"]*)"',1,1,NULL,1) DIV, L.TRNM_ST_DTM, L.EXCT_MSG_CTN, L.DB_TRNM_END_DTM,
         (CAST(L.DB_TRNM_END_DTM AS DATE) - CAST(L.DB_TRNM_ST_DTM AS DATE))*86400 DB_S
    FROM SCM_COM_SYS_LOG L
   WHERE L.MNU_ID = 'DMF0082' AND L.SHT_NM = 'FcstNPrice' AND L.MNU_BTN_CD = 'SEARCH' AND L.CREATION_DATE >= TRUNC(SYSDATE) - &DAYS
)
SELECT D, DIV, COUNT(*) N, ROUND(MIN(DB_S),1) MIN_S, ROUND(MEDIAN(DB_S),1) MED_S, ROUND(PERCENTILE_CONT(0.9) WITHIN GROUP (ORDER BY DB_S),1) P90_S, ROUND(MAX(DB_S),1) MAX_S,
       SUM(CASE WHEN DB_TRNM_END_DTM IS NULL OR EXCT_MSG_CTN IS NOT NULL THEN 1 ELSE 0 END) ERR_OR_NOEND,
       SUBSTR(LISTAGG(TO_CHAR(TRNM_ST_DTM,'HH24:MI') || ':' || NVL(TO_CHAR(ROUND(DB_S)),'NOEND'), ' ' ON OVERFLOW TRUNCATE) WITHIN GROUP (ORDER BY TRNM_ST_DTM),1,120) SHEETS
  FROM L GROUP BY D, DIV ORDER BY D, DIV;

PROMPT ################ [C4b] 일자 × 시트 추이 — 부속 시트도 느려졌나 (FcstNPrice 제외, 중앙값·최대) ################
WITH L AS (
  SELECT TO_CHAR(L.TRNM_ST_DTM,'MM-DD') D, L.SHT_NM, (CAST(L.DB_TRNM_END_DTM AS DATE) - CAST(L.DB_TRNM_ST_DTM AS DATE))*86400 DB_S
    FROM SCM_COM_SYS_LOG L
   WHERE L.MNU_ID = 'DMF0082' AND L.SHT_NM <> 'FcstNPrice' AND L.MNU_BTN_CD = 'SEARCH' AND L.CREATION_DATE >= TRUNC(SYSDATE) - &DAYS
)
SELECT D, SHT_NM, COUNT(*) N, ROUND(MEDIAN(DB_S),2) MED_S, ROUND(MAX(DB_S),2) MAX_S,
       SUM(CASE WHEN DB_S >= 2 THEN 1 ELSE 0 END) GE2S
  FROM L GROUP BY D, SHT_NM ORDER BY D, SHT_NM;

PROMPT ################ [C5] ⭐⭐ 이벤트 전/후 비교 — 기준점 자동: ① PKG_DMF0082 BODY LAST_DDL ('/' 객체 재컴파일) ② DM_PLN_MKT_FCST 테이블 LAST_DDL ('/' DEFAULT) ################
PROMPT --  같은 시트·division 의 BEFORE/AFTER 중앙값·P90 배수. RATIO >= 1.5 = 그 이벤트 뒤 악화. (BEFORE 창 = 이벤트 전 &DAYS 일)
WITH EV AS (
  SELECT 'PKG_DMF0082 BODY LAST_DDL' EVENT_K, CAST(LAST_DDL_TIME AS TIMESTAMP) T FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0082' AND OBJECT_TYPE='PACKAGE BODY'
  UNION ALL
  SELECT 'DM_PLN_MKT_FCST 테이블 LAST_DDL (SLASHDEF)', CAST(LAST_DDL_TIME AS TIMESTAMP) FROM USER_OBJECTS WHERE OBJECT_NAME='DM_PLN_MKT_FCST' AND OBJECT_TYPE='TABLE'
  UNION ALL
  SELECT '82 ''/'' 행 최초 생성 (데이터 유입)', CAST(MIN(CREATION_DATE) AS TIMESTAMP) FROM DM_PLN_MKT_FCST WHERE DIVISION_ID='82' AND PLANT_SITE_ID='/'
),
L AS (
  SELECT L.SHT_NM, REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"divisionId":"([^"]*)"',1,1,NULL,1) DIV, L.TRNM_ST_DTM,
         (CAST(L.DB_TRNM_END_DTM AS DATE) - CAST(L.DB_TRNM_ST_DTM AS DATE))*86400 DB_S
    FROM SCM_COM_SYS_LOG L
   WHERE L.MNU_ID = 'DMF0082' AND L.SHT_NM IN ('FcstNPrice','titleSet','spreadTitle','version','buttonAuth') AND L.MNU_BTN_CD = 'SEARCH'
     AND L.CREATION_DATE >= TRUNC(SYSDATE) - 2*&DAYS
),
X AS (
  SELECT EV.EVENT_K, EV.T, L.SHT_NM, L.DIV, CASE WHEN L.TRNM_ST_DTM < EV.T THEN 'B' ELSE 'A' END BA, L.DB_S
    FROM EV, L
   WHERE EV.T IS NOT NULL AND L.TRNM_ST_DTM >= EV.T - NUMTODSINTERVAL(&DAYS,'DAY')
)
SELECT EVENT_K, TO_CHAR(MAX(T),'MM-DD HH24:MI') EVENT_T, SHT_NM, DIV,
       SUM(CASE WHEN BA='B' THEN 1 ELSE 0 END) N_BEFORE, ROUND(MEDIAN(CASE WHEN BA='B' THEN DB_S END),1) MED_BEFORE, ROUND(PERCENTILE_CONT(0.9) WITHIN GROUP (ORDER BY CASE WHEN BA='B' THEN DB_S END),1) P90_BEFORE,
       SUM(CASE WHEN BA='A' THEN 1 ELSE 0 END) N_AFTER,  ROUND(MEDIAN(CASE WHEN BA='A' THEN DB_S END),1) MED_AFTER,  ROUND(PERCENTILE_CONT(0.9) WITHIN GROUP (ORDER BY CASE WHEN BA='A' THEN DB_S END),1) P90_AFTER,
       ROUND(MEDIAN(CASE WHEN BA='A' THEN DB_S END) / NULLIF(MEDIAN(CASE WHEN BA='B' THEN DB_S END),0),2) RATIO,
       CASE WHEN SUM(CASE WHEN BA='B' THEN 1 ELSE 0 END) = 0 OR SUM(CASE WHEN BA='A' THEN 1 ELSE 0 END) = 0 THEN 'ℹ 한쪽 표본 없음'
            WHEN MEDIAN(CASE WHEN BA='A' THEN DB_S END) / NULLIF(MEDIAN(CASE WHEN BA='B' THEN DB_S END),0) >= 1.5 AND MEDIAN(CASE WHEN BA='A' THEN DB_S END) >= 2 THEN '❌ 이벤트 뒤 악화 (1.5배↑)'
            WHEN MEDIAN(CASE WHEN BA='A' THEN DB_S END) / NULLIF(MEDIAN(CASE WHEN BA='B' THEN DB_S END),0) <= 0.67 THEN '✅ 이벤트 뒤 개선'
            ELSE '- 변화 없음' END JUDGE
  FROM X
 GROUP BY EVENT_K, SHT_NM, DIV
HAVING SHT_NM = 'FcstNPrice' OR (SUM(CASE WHEN BA='B' THEN 1 ELSE 0 END) > 0 AND SUM(CASE WHEN BA='A' THEN 1 ELSE 0 END) > 0)
 ORDER BY EVENT_K, CASE SHT_NM WHEN 'FcstNPrice' THEN 0 ELSE 1 END, SHT_NM, DIV;
PROMPT --  판정: 어느 EVENT 에서만 RATIO 가 뛰는지로 원인 계통을 가른다 — BODY 재컴파일 뒤면 계획(재파싱) · SLASHDEF 뒤면 데이터/DEFAULT · '/' 데이터 유입 뒤면 행 분리

