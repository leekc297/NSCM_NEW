         LAG(L.TRNM_ST_DTM) OVER (PARTITION BY L.SHT_NM, L.CREATED_BY, REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"divisionId":"([^"]*)"',1,1,NULL,1) ORDER BY L.TRNM_ST_DTM) PREV_ST
