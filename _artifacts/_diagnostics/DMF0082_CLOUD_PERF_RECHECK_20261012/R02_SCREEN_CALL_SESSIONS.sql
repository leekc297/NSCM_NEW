                OR REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"deptId":"([^"]*)"',1,1,NULL,1) NOT IN ('ALL')
                OR REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"endCustomer":"([^"]*)"',1,1,NULL,1) NOT IN ('ALL') THEN 'Y' ELSE 'N' END FILTERED,
