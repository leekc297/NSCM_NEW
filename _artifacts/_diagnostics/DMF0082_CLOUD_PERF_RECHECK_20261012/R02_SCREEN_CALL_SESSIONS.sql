PROMPT ################ [C9] 조회 조건별 — versionType · qtyYn · 필터 유무 가 소요를 갈라놓나 (FcstNPrice) ################
WITH L AS (
  SELECT REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"divisionId":"([^"]*)"',1,1,NULL,1) DIV,
         REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"versionType":"([^"]*)"',1,1,NULL,1) VER,
         NVL(REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"qtyYn":"([^"]*)"',1,1,NULL,1),'-') QTY,
         CASE WHEN REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"plantSiteId":"([^"]*)"',1,1,NULL,1) NOT IN ('ALL')
