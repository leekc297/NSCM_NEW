PROMPT ################ [T0] 접속 DB · 시각 ################
SELECT SYS_CONTEXT('USERENV','DB_NAME') DB_NAME, SYS_CONTEXT('USERENV','SERVER_HOST') HOST,
       SYS_CONTEXT('USERENV','INSTANCE_NAME') INST, TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI:SS') NOW FROM DUAL;

PROMPT ################ [T1] ⭐ 지금 PKG_DMF0082 를 실행 중인 세션 — 어느 문장에서 무엇을 기다리나 ################
PROMPT --  EVT 판정: ON CPU / cell·db file read = 계획 문제(느린 문장) · enq: TX/TM = 잠금 · library cache pin/lock · cursor: pin S = PKG 재컴파일 충돌
PROMPT --           direct path write temp = TEMP 유출 · PX Deq = 병렬 대기. LINE = BODY 줄번호 (사내 BODY 기준 L1612/L2390/L2805 = 81MKTAMT · L1771 = ONEREAD 판가 · L2089 = 실적 arm)
SELECT S.INST_ID INST, S.SID, S.SERIAL#, S.USERNAME, S.MACHINE, S.MODULE, S.STATUS, S.LAST_CALL_ET CALL_SEC,
       S.SQL_ID, S.SQL_CHILD_NUMBER CH, Q.PLAN_HASH_VALUE PHV, S.SQL_EXEC_START,
       NVL(S.EVENT,'-') EVT, S.WAIT_CLASS, S.SECONDS_IN_WAIT WAIT_SEC,
       S.BLOCKING_SESSION BLK_SID, S.FINAL_BLOCKING_SESSION FINAL_BLK,
       (SELECT MAX(PROGRAM_LINE#) FROM GV$SQL X WHERE X.SQL_ID = S.SQL_ID) LINE,
       (SELECT ROUND(MAX(X.ELAPSED_TIME/1e6/GREATEST(X.EXECUTIONS,1)),1) FROM GV$SQL X WHERE X.SQL_ID = S.SQL_ID) HIST_SEC_PER_EX,
       SUBSTR(REGEXP_REPLACE(Q.SQL_TEXT,'\s+',' '),1,80) TXT
  FROM GV$SESSION S
  LEFT JOIN GV$SQL Q ON Q.INST_ID = S.INST_ID AND Q.SQL_ID = S.SQL_ID AND Q.CHILD_NUMBER = S.SQL_CHILD_NUMBER
 WHERE S.TYPE = 'USER'
   AND (S.PLSQL_ENTRY_OBJECT_ID = (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0082' AND OBJECT_TYPE='PACKAGE')
        OR UPPER(Q.SQL_TEXT) LIKE '%GT_DMF0082%' OR UPPER(Q.SQL_TEXT) LIKE '%PKG_DMF0082%')
 ORDER BY S.LAST_CALL_ET DESC;
PROMPT --  0 rows = 지금 도는 조회 없음 (타임아웃 이후라면 [T5]~ 로)

PROMPT ################ [T1b] 지금 도는 문장의 실행계획 (자동 — [T1] 의 SQL_ID 전부, 바인드 포함) ################
WITH R AS (
  SELECT DISTINCT S.SQL_ID, S.SQL_CHILD_NUMBER CH
    FROM GV$SESSION S
   WHERE S.TYPE = 'USER' AND S.SQL_ID IS NOT NULL AND S.SID <> SYS_CONTEXT('USERENV','SID')
     AND S.INST_ID = SYS_CONTEXT('USERENV','INSTANCE')   -- DISPLAY_CURSOR 는 접속 인스턴스 커서만 보인다 (RAC: 다른 인스턴스 세션은 그 인스턴스에 접속해 실행)
     AND S.PLSQL_ENTRY_OBJECT_ID = (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0082' AND OBJECT_TYPE='PACKAGE')
)
SELECT '### ' || R.SQL_ID || '/' || R.CH || ' ' || X.PLAN_TABLE_OUTPUT PLAN_TABLE_OUTPUT
  FROM R, TABLE(DBMS_XPLAN.DISPLAY_CURSOR(R.SQL_ID, R.CH, 'TYPICAL +PEEKED_BINDS +NOTE')) X;
PROMPT --  NESTED LOOPS 안쪽에 SCM_MST_FUTURE_PRICE / DM_PLN_SALES_PLAN / DM_PLN_MKT_FCST INDEX RANGE SCAN 이 있고 GT_DMF0082_* Rows=1 이면 GTT 1행 추정 NL 함정

PROMPT ################ [T2] ⭐ 잠금 대기 사슬 — 누가 막고 있나 (DB 전체) ################
SELECT W.INST_ID INST, W.SID WAIT_SID, W.USERNAME WAIT_USER, W.MODULE WAIT_MODULE, W.EVENT EVT, W.SECONDS_IN_WAIT WAIT_SEC,
       W.BLOCKING_SESSION BLK_SID, B.USERNAME BLK_USER, B.MACHINE BLK_MACHINE, B.MODULE BLK_MODULE,
       B.STATUS BLK_STATUS, B.LAST_CALL_ET BLK_CALL_SEC, B.SQL_ID BLK_SQL_ID, B.PREV_SQL_ID BLK_PREV_SQL,
       SUBSTR(REGEXP_REPLACE(BQ.SQL_TEXT,'\s+',' '),1,80) TXT
  FROM GV$SESSION W
  JOIN GV$SESSION B ON B.SID = W.BLOCKING_SESSION AND B.INST_ID = NVL(W.BLOCKING_INSTANCE, W.INST_ID)
  LEFT JOIN GV$SQL BQ ON BQ.INST_ID = B.INST_ID AND BQ.SQL_ID = NVL(B.SQL_ID, B.PREV_SQL_ID) AND BQ.CHILD_NUMBER = NVL(B.SQL_CHILD_NUMBER, B.PREV_CHILD_NUMBER)
 WHERE W.BLOCKING_SESSION IS NOT NULL AND W.TYPE = 'USER'
 ORDER BY W.SECONDS_IN_WAIT DESC FETCH FIRST 30 ROWS ONLY;
PROMPT --  BLK_STATUS=INACTIVE + BLK_CALL_SEC 큼 = 커밋 안 한 채 방치된 세션(SQL Developer 등)이 잡고 있음

PROMPT ################ [T3] PKG_DMF0082 · 81 원천 테이블에 걸린 DML 잠금 ################
SELECT L.SESSION_ID SID, S.USERNAME, S.MACHINE, S.MODULE, S.STATUS, S.LAST_CALL_ET CALL_SEC,
       O.OBJECT_NAME OBJ, O.OBJECT_TYPE,
       DECODE(L.LOCKED_MODE,0,'None',1,'Null',2,'Row-S',3,'Row-X',4,'Share',5,'S/Row-X',6,'Exclusive',L.LOCKED_MODE) LMODE
  FROM GV$LOCKED_OBJECT L
  JOIN ALL_OBJECTS O ON O.OBJECT_ID = L.OBJECT_ID
  JOIN GV$SESSION S ON S.SID = L.SESSION_ID AND S.INST_ID = L.INST_ID
 WHERE O.OBJECT_NAME IN ('DM_PLN_MKT_FCST','DM_PLN_SALES_PLAN','DM_PLN_SALES_PLAN_C','SCM_MST_FUTURE_PRICE','DM_PLN_MKT_FCST_RESULT',
                         'DM_PLN_SALES_PLAN_RESULT','SCM_MST_SITE_ITEM','SCM_COM_SYS_LOG','SCM_SYS_LOG','SCM_MST_TITLESET_USER')
 ORDER BY S.LAST_CALL_ET DESC;

PROMPT ################ [T4] 지금 도는 조회 세션의 실행 중 문장 진행 (SQL Monitor — 5초 이상 문장 · 권한 없으면 오류 무시) ################
SELECT M.INST_ID INST, M.SID, M.SQL_ID, M.SQL_PLAN_HASH_VALUE PHV, M.STATUS, ROUND(M.ELAPSED_TIME/1e6,1) ELAP_S,
       ROUND(M.CPU_TIME/1e6,1) CPU_S, ROUND(M.USER_IO_WAIT_TIME/1e6,1) IO_S, ROUND(M.CONCURRENCY_WAIT_TIME/1e6,1) CONC_S,
       ROUND(M.APPLICATION_WAIT_TIME/1e6,1) APP_S, M.BUFFER_GETS BG, ROUND(M.PHYSICAL_READ_BYTES/1048576) READ_MB,
       TO_CHAR(M.SQL_EXEC_START,'HH24:MI:SS') STARTED,
       SUBSTR(REGEXP_REPLACE(M.SQL_TEXT,'\s+',' '),1,80) TXT
  FROM GV$SQL_MONITOR M
 WHERE M.SQL_EXEC_START > SYSDATE - 60/1440
   AND (UPPER(M.SQL_TEXT) LIKE '%GT_DMF0082%' OR M.PLSQL_ENTRY_OBJECT_ID = (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0082' AND OBJECT_TYPE='PACKAGE'))
 ORDER BY M.ELAPSED_TIME DESC FETCH FIRST 20 ROWS ONLY;

PROMPT ################ [T5] ⭐ 최근 120 분 화면 호출 이력 (BE 로그) — division · 소요 · 오류 ################
SELECT TO_CHAR(TRNM_ST_DTM,'MM-DD HH24:MI:SS') ST, SHT_NM, MNU_BTN_CD ACT,
       REGEXP_SUBSTR(SYS_LOG_MSG_CTN,'"divisionId":"([^"]*)"',1,1,NULL,1) DIV,
       REGEXP_SUBSTR(SYS_LOG_MSG_CTN,'"userGroup":"([^"]*)"',1,1,NULL,1) GRP, CREATED_BY,
       ROUND((CAST(DB_TRNM_END_DTM AS DATE) - CAST(DB_TRNM_ST_DTM AS DATE))*86400, 1) DB_S,
       ROUND((CAST(TRNM_END_DTM AS DATE) - CAST(TRNM_ST_DTM AS DATE))*86400, 1) SERVER_S,
       SUBSTR(EXCT_MSG_CTN,1,120) ERR
  FROM SCM_COM_SYS_LOG
 WHERE MNU_ID = 'DMF0082' AND CREATION_DATE >= SYSDATE - 120/1440
 ORDER BY TRNM_ST_DTM DESC FETCH FIRST 40 ROWS ONLY;
PROMPT --  타임아웃 호출은 BE 가 END 를 못 남겨 빠질 수 있다 — 40 이 정상(수 초)이고 81 만 없거나 수 분이면 81 조건 문제

PROMPT ################ [T6] ⭐ 최근 120 분 PKG_DMF0082 진입 ASH — 호출(세션×실행) × 문장 × 대기 (샘플 1 ≈ 1초, 10 샘플↑) ################
WITH P AS (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0082' AND OBJECT_TYPE='PACKAGE'),
A AS (SELECT A.* FROM GV$ACTIVE_SESSION_HISTORY A, P
       WHERE A.SAMPLE_TIME >= SYSTIMESTAMP - NUMTODSINTERVAL(120,'MINUTE') AND A.PLSQL_ENTRY_OBJECT_ID = P.OBJECT_ID)
SELECT A.INST_ID INST, A.SESSION_ID SID, A.SESSION_SERIAL# SER, NVL(A.SQL_ID,'(PL/SQL)') SQL_ID, A.SQL_PLAN_HASH_VALUE PHV,
       NVL(A.EVENT,'ON CPU') EVT, COUNT(*) SAMPLES,
       TO_CHAR(MIN(A.SAMPLE_TIME),'HH24:MI:SS') T_FROM, TO_CHAR(MAX(A.SAMPLE_TIME),'HH24:MI:SS') T_TO,
       MAX(A.BLOCKING_SESSION) BLK_SID,
       (SELECT MAX(PROGRAM_LINE#) FROM GV$SQL Q WHERE Q.SQL_ID = A.SQL_ID) LINE,
       (SELECT MIN(SUBSTR(REGEXP_REPLACE(Q.SQL_TEXT,'\s+',' '),1,70)) FROM GV$SQL Q WHERE Q.SQL_ID = A.SQL_ID) TXT
  FROM A
 GROUP BY A.INST_ID, A.SESSION_ID, A.SESSION_SERIAL#, NVL(A.SQL_ID,'(PL/SQL)'), A.SQL_PLAN_HASH_VALUE, NVL(A.EVENT,'ON CPU'), A.SQL_ID
HAVING COUNT(*) >= 10
 ORDER BY SAMPLES DESC FETCH FIRST 25 ROWS ONLY;
PROMPT --  한 SQL_ID 가 수십~수백 샘플 = 그 문장이 타임아웃 원인. EVT 로 계통 판정([T1] 과 동일 기준)

PROMPT ################ [T7] ⭐ 계획 이탈 후보 — 1회 10초↑ 또는 지금 실행 중인 자식 커서 (PKG_DMF0082 문장 + GT_DMF0082 동적) ################
WITH B AS (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0082' AND OBJECT_TYPE='PACKAGE BODY')
SELECT S.INST_ID INST, S.SQL_ID, S.CHILD_NUMBER CH, S.PROGRAM_LINE# LINE, S.PLAN_HASH_VALUE PHV, S.EXECUTIONS EX,
       ROUND(S.ELAPSED_TIME/1e6/GREATEST(S.EXECUTIONS,1),1) SEC_PER_EX,
       ROUND(S.BUFFER_GETS/GREATEST(S.EXECUTIONS,1)) BG_PER_EX,
       ROUND(S.ROWS_PROCESSED/GREATEST(S.EXECUTIONS,1)) ROWS_PER_EX,
       S.USERS_EXECUTING NOW_RUN, S.PARSING_SCHEMA_NAME SCH,
       S.LAST_LOAD_TIME LOADED, TO_CHAR(S.LAST_ACTIVE_TIME,'MM-DD HH24:MI') LAST_ACT,
       (SELECT E.VALUE FROM GV$SQL_OPTIMIZER_ENV E WHERE E.INST_ID=S.INST_ID AND E.SQL_ID=S.SQL_ID AND E.CHILD_NUMBER=S.CHILD_NUMBER AND E.ADDRESS=S.ADDRESS
          AND E.NAME='optimizer_dynamic_sampling') DS,
       CASE WHEN UPPER(S.SQL_TEXT) LIKE '%DM_PLN_SALES_PLAN S%' OR UPPER(S.SQL_TEXT) LIKE '%DM_PLN_SALES_PLAN_C S%' THEN '81MKTAMT'
            WHEN UPPER(S.SQL_TEXT) LIKE '%X_ONEREAD_YMD%' THEN 'ONEREAD' END TAG,
       SUBSTR(REGEXP_REPLACE(S.SQL_TEXT,'\s+',' '),1,70) TXT
  FROM GV$SQL S
 WHERE (S.PROGRAM_ID = (SELECT OBJECT_ID FROM B) OR UPPER(S.SQL_TEXT) LIKE '%GT_DMF0082%')
   AND S.PARSING_SCHEMA_NAME NOT IN ('SYS')
   AND (S.ELAPSED_TIME/GREATEST(S.EXECUTIONS,1) > 10e6 OR S.USERS_EXECUTING > 0)
 ORDER BY S.ELAPSED_TIME/GREATEST(S.EXECUTIONS,1) DESC FETCH FIRST 25 ROWS ONLY;
PROMPT --  사내 정상 구간 최대 1회 1초 미만 — 10초 넘는 자식이 있으면 그 SQL_ID 를 R05 DEFINE SQL_ID 에 넣어 계획 확인

PROMPT ################ [T8] 객체 상태 — PKG 무효·재컴파일 중이면 조회가 library cache 대기 ################
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL
  FROM USER_OBJECTS
 WHERE OBJECT_NAME IN ('PKG_DMF0082','PR_SCM_SYS_LOG_BATCH','PR_DM_SYS_LOG_BATCH','PKG_DMF0000')
    OR (STATUS <> 'VALID' AND OBJECT_NAME IN (SELECT REFERENCED_NAME FROM USER_DEPENDENCIES WHERE NAME = 'PKG_DMF0082'))
 ORDER BY OBJECT_NAME, OBJECT_TYPE;
PROMPT --  LAST_DDL 이 조회 시각과 겹치거나 STATUS INVALID = 패키지 적용(CREATE OR REPLACE) 과 조회 충돌

PROMPT ################ [T9] TEMP · 병렬 자원 (TEMP 부족·병렬 대기형 정체 판정 · DBA_ 권한 없으면 오류 무시) ################
SELECT S.SID, S.USERNAME, S.MODULE, U.TABLESPACE, ROUND(U.BLOCKS * (SELECT VALUE FROM GV$PARAMETER WHERE NAME='db_block_size')/1048576) TEMP_MB, U.SEGTYPE
  FROM GV$TEMPSEG_USAGE U JOIN GV$SESSION S ON S.SADDR = U.SESSION_ADDR AND S.INST_ID = U.INST_ID
 ORDER BY U.BLOCKS DESC FETCH FIRST 10 ROWS ONLY;
SELECT TABLESPACE_NAME, ROUND(TABLESPACE_SIZE/1048576) SIZE_MB, ROUND(ALLOCATED_SPACE/1048576) ALLOC_MB, ROUND(FREE_SPACE/1048576) FREE_MB
  FROM DBA_TEMP_FREE_SPACE;

PROMPT ################ [T10] ⭐⭐ 1행 추정 NESTED LOOPS 함정 — GTT(TEMP_SITE_ITEM 등)를 1행으로 보고 대형표를 행마다 인덱스 범위 스캔 ################
PROMPT --  대상: GT_DMF0082_TEMP_SITE_ITEM 을 조인하는 모든 문장 (81 수요·판가·금액·실적 arm 전부 해당)
PROMPT --  NL_RISK=Y 자식이 EX>0 이고 ROWS_PER_EX=0 · BG 큼 · SEC 큼 이면 = 중간 취소(타임아웃) 된 실행 → 원인 확정
WITH B AS (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0082' AND OBJECT_TYPE='PACKAGE BODY'),
C AS (SELECT S.INST_ID, S.SQL_ID, S.CHILD_NUMBER, S.ADDRESS, S.PLAN_HASH_VALUE, S.PROGRAM_LINE#, S.EXECUTIONS, S.ELAPSED_TIME, S.BUFFER_GETS,
             S.ROWS_PROCESSED, S.USERS_EXECUTING, S.LAST_ACTIVE_TIME, S.SQL_TEXT
        FROM GV$SQL S
       WHERE (S.PROGRAM_ID = (SELECT OBJECT_ID FROM B) OR UPPER(S.SQL_TEXT) LIKE 'INSERT INTO SCM_MGR.GT_DMF0082%')
         AND UPPER(S.SQL_TEXT) LIKE '%GT_DMF0082_TEMP_SITE_ITEM%')
SELECT C.INST_ID INST, C.SQL_ID, C.CHILD_NUMBER CH, C.PROGRAM_LINE# LINE, C.PLAN_HASH_VALUE PHV, C.EXECUTIONS EX,
       ROUND(C.ELAPSED_TIME/1e6,1) ELAP_S_TOT, ROUND(C.ELAPSED_TIME/1e6/GREATEST(C.EXECUTIONS,1),1) SEC_PER_EX,
       ROUND(C.BUFFER_GETS/GREATEST(C.EXECUTIONS,1)) BG_PER_EX, ROUND(C.ROWS_PROCESSED/GREATEST(C.EXECUTIONS,1)) ROWS_PER_EX,
       C.USERS_EXECUTING NOW_RUN, TO_CHAR(C.LAST_ACTIVE_TIME,'MM-DD HH24:MI') LAST_ACT,
       CASE WHEN EXISTS (SELECT 1 FROM GV$SQL_PLAN P WHERE P.INST_ID=C.INST_ID AND P.ADDRESS=C.ADDRESS AND P.SQL_ID=C.SQL_ID AND P.CHILD_NUMBER=C.CHILD_NUMBER AND P.OPERATION='NESTED LOOPS')
             AND EXISTS (SELECT 1 FROM GV$SQL_PLAN P WHERE P.INST_ID=C.INST_ID AND P.ADDRESS=C.ADDRESS AND P.SQL_ID=C.SQL_ID AND P.CHILD_NUMBER=C.CHILD_NUMBER
                           AND P.OBJECT_NAME LIKE 'GT_DMF0082%' AND P.CARDINALITY <= 1)
            THEN 'Y' ELSE 'N' END NL_RISK,
       (SELECT LISTAGG(DISTINCT P.OBJECT_NAME, ',') WITHIN GROUP (ORDER BY P.OBJECT_NAME) FROM GV$SQL_PLAN P
         WHERE P.ADDRESS=C.ADDRESS AND P.SQL_ID=C.SQL_ID AND P.CHILD_NUMBER=C.CHILD_NUMBER AND P.OBJECT_NAME IS NOT NULL
           AND P.OBJECT_NAME NOT LIKE 'GT_DMF0082%' AND P.OPERATION IN ('TABLE ACCESS','INDEX')) PERM_OBJS,
       SUBSTR(REGEXP_REPLACE(C.SQL_TEXT,'\s+',' '),1,70) TXT
  FROM C
 ORDER BY C.ELAPSED_TIME DESC
 FETCH FIRST 30 ROWS ONLY;
PROMPT --  NL_RISK=Y 이면서 ROWS 0 · SEC 0 인 자식 = 빈 GTT 로 실행돼 무해. 위험 = NL_RISK=Y 이면서 SEC/BG 가 큰 자식 (PERM_OBJS 의 표를 행마다 스캔)

