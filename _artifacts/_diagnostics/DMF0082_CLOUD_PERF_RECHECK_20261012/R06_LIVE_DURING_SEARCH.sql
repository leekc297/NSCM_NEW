--   ⭐ 사용법: 화면에서 느린 Division [Search] 를 누른 뒤 **조회가 돌고 있는 동안** F5 로 실행 → 1회 (수 초 안에 끝나는 조회면 [T5]~ 만 의미 있음)
--      조회가 끝난(또는 타임아웃 난) 뒤 다시 1회 ([T5]~[T10] 이력 판정). [T1]~[T4] 는 '지금 도는 세션' 을 보므로 조회가 살아 있을 때만 값이 나온다.
--   정상 기준(사내 10-12 R04 2회차, README §4): 40/81/82 SP 수 초 + fetch 1초 미만. 수십 초~수 분 = 대기 또는 계획 이탈.
