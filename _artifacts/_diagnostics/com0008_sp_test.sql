DECLARE
    V_RC SYS_REFCURSOR;
    V_RC2 SYS_REFCURSOR;
    V_CNT PLS_INTEGER := 0;
    V_DIV VARCHAR2(50); V_DN VARCHAR2(50);
    V_PC VARCHAR2(100); V_PN VARCHAR2(200);
    V_SS VARCHAR2(50); V_SD VARCHAR2(200);
    V_IID VARCHAR2(100); V_IN VARCHAR2(300); V_TY VARCHAR2(10); V_TYN VARCHAR2(100);
    V_NN VARCHAR2(300); V_CN VARCHAR2(300);
    V_DP VARCHAR2(50); V_DPN VARCHAR2(200); V_EC VARCHAR2(100); V_CUR VARCHAR2(20); V_EC40 VARCHAR2(100);
BEGIN
    -- 사용자 시나리오: div='40' (자동차 — DMF0072 첫 기본값)
    SCM_MGR.PKG_COM0000.P_COM0008_GET_ITEM_BY_DIVISION_POPUP(
        '40', 'ALL', 'ALL', 'ALL', '', '', '', V_RC, V_RC2
    );
    LOOP
        FETCH V_RC INTO V_DIV, V_DN, V_PC, V_PN, V_SS, V_SD, V_IID, V_IN, V_TY, V_TYN, V_NN, V_CN, V_DP, V_DPN, V_EC, V_CUR, V_EC40;
        EXIT WHEN V_RC%NOTFOUND;
        V_CNT := V_CNT + 1;
        EXIT WHEN V_CNT >= 5;
    END LOOP;
    CLOSE V_RC;
    DBMS_OUTPUT.PUT_LINE('Direct SP call (40,ALL,ALL,ALL,,,) rows (max 5) = ' || V_CNT);

    -- div='81' 시나리오
    SCM_MGR.PKG_COM0000.P_COM0008_GET_ITEM_BY_DIVISION_POPUP(
        '81', 'ALL', 'ALL', 'ALL', '', '', '', V_RC, V_RC2
    );
    V_CNT := 0;
    LOOP
        FETCH V_RC INTO V_DIV, V_DN, V_PC, V_PN, V_SS, V_SD, V_IID, V_IN, V_TY, V_TYN, V_NN, V_CN, V_DP, V_DPN, V_EC, V_CUR, V_EC40;
        EXIT WHEN V_RC%NOTFOUND;
        V_CNT := V_CNT + 1;
        EXIT WHEN V_CNT >= 5;
    END LOOP;
    CLOSE V_RC;
    DBMS_OUTPUT.PUT_LINE('Direct SP call (81,ALL,ALL,ALL,,,) rows (max 5) = ' || V_CNT);
EXCEPTION WHEN OTHERS THEN
