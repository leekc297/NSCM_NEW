--   계정: SCM_MGR · C02 [S2] / C03 (B) 에서 가장 느린 SQL_ID 를 아래 DEFINE SQL_ID 에 넣고 실행
--   A-Rows(실측 행수)까지 보려면: C03 을 c_rowstats := 'Y' 로 한 번 돌린 뒤 이 스크립트 실행
