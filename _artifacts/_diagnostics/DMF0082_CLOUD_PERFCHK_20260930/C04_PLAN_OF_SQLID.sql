SET LINESIZE 300
SET PAGESIZE 0
SET TRIMSPOOL ON
SET VERIFY OFF
SET LONG 100000
DEFINE SQL_ID = 'b6wn3kx02pryu'
SPOOL C04_PLAN_&SQL_ID._OUT.txt

SET PAGESIZE 500
PROMPT ################ [P1] 자식 커서 목록 — 계획별 1회당 비용 · 공유 사유 ################
SELECT S.CHILD_NUMBER CH, S.PLAN_HASH_VALUE PHV, S.EXECUTIONS EX,
       ROUND(S.ELAPSED_TIME/1e6/GREATEST(S.EXECUTIONS,1), 2) SEC_PER_EX,
       ROUND(S.BUFFER_GETS/GREATEST(S.EXECUTIONS,1)) BG_PER_EX,
       ROUND(S.DISK_READS/GREATEST(S.EXECUTIONS,1)) DR_PER_EX,
       ROUND(S.ROWS_PROCESSED/GREATEST(S.EXECUTIONS,1)) ROWS_PER_EX,
       S.OPTIMIZER_COST COST, S.PROGRAM_LINE# LINE,
       S.LAST_LOAD_TIME LOADED, TO_CHAR(S.LAST_ACTIVE_TIME,'MM-DD HH24:MI') LAST_ACT,
       S.IS_BIND_SENSITIVE BS, S.IS_SHAREABLE SH, S.SQL_PLAN_BASELINE BASELINE, S.SQL_PROFILE PROFILE, S.SQL_PATCH PATCH
  FROM V$SQL S WHERE S.SQL_ID = '&SQL_ID'
 ORDER BY S.CHILD_NUMBER;

PROMPT ################ [P2] SQL 전문 (앞 4000자) ################
SELECT SUBSTR(SQL_FULLTEXT, 1, 4000) SQL_TEXT FROM V$SQL WHERE SQL_ID = '&SQL_ID' AND ROWNUM = 1;

SET PAGESIZE 0
PROMPT ################ [P3] ⭐ 실행계획 — 가장 최근 실행된 자식 (E-Rows vs A-Rows · 접근경로) ################
PROMPT --  확인 포인트:
PROMPT --   ① GT_DMF0082_* 의 E-Rows 가 1 인데 실제(A-Rows/ROWS_PER_EX)는 수만 = 파싱 시점 GTT 추정 붕괴 (07-31 DMF0003 유형)
PROMPT --   ② SCM_MST_FUTURE_PRICE / DM_PLN_* 에 TABLE ACCESS FULL = 인덱스 미사용 (IDX02 힌트 무시·인덱스 결손)
PROMPT --   ③ MERGE JOIN CARTESIAN / NESTED LOOPS 아래 대용량 = 조인 순서 오류
PROMPT --   ④ Note 절: dynamic statistics used: dynamic sampling (level=2) 표기 여부 — 없으면 DS=0 으로 파싱된 커서
SELECT PLAN_TABLE_OUTPUT FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR('&SQL_ID',
       (SELECT MAX(CHILD_NUMBER) KEEP (DENSE_RANK LAST ORDER BY LAST_ACTIVE_TIME) FROM V$SQL WHERE SQL_ID = '&SQL_ID'),
       'ALLSTATS LAST +COST +PEEKED_BINDS +PREDICATE +NOTE'));

PROMPT ################ [P4] 다른 계획(PHV)의 자식이 있으면 그 계획도 (계획 간 비교) ################
SELECT PLAN_TABLE_OUTPUT FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR('&SQL_ID',
       (SELECT MIN(CHILD_NUMBER) KEEP (DENSE_RANK FIRST ORDER BY ELAPSED_TIME/GREATEST(EXECUTIONS,1)) FROM V$SQL WHERE SQL_ID = '&SQL_ID'),
       'TYPICAL +COST +NOTE'));
PROMPT --  (P3 와 PHV 가 같으면 동일 계획 — 무시)

SET PAGESIZE 500
PROMPT ################ [P5] 계획에 등장하는 영구 테이블·인덱스 통계 (계획 안의 객체만) ################
WITH O AS (SELECT DISTINCT OBJECT_OWNER, OBJECT_NAME, OBJECT_TYPE FROM V$SQL_PLAN
            WHERE SQL_ID = '&SQL_ID' AND OBJECT_NAME IS NOT NULL)
SELECT O.OBJECT_TYPE, O.OBJECT_NAME,
       NVL(T.NUM_ROWS, I.NUM_ROWS) NUM_ROWS, NVL(T.BLOCKS, I.LEAF_BLOCKS) BLOCKS_OR_LEAF,
       TO_CHAR(NVL(T.LAST_ANALYZED, I.LAST_ANALYZED),'YYYY-MM-DD') ANALYZED, I.CLUSTERING_FACTOR CLUF,
       T.TEMPORARY TMP, NVL(I.STATUS, '-') IDX_STATUS
  FROM O LEFT JOIN ALL_TABLES T ON T.OWNER = O.OBJECT_OWNER AND T.TABLE_NAME = O.OBJECT_NAME
         LEFT JOIN ALL_INDEXES I ON I.OWNER = O.OBJECT_OWNER AND I.INDEX_NAME = O.OBJECT_NAME
 ORDER BY 1, 2;

PROMPT ################ [P6] AWR 과거 실행 이력 (Diagnostics Pack 미허용·권한 없음이면 오류 — 무시) ################
SELECT S.SNAP_ID, TO_CHAR(N.BEGIN_INTERVAL_TIME,'MM-DD HH24:MI') SNAP, S.PLAN_HASH_VALUE PHV, S.EXECUTIONS_DELTA EX,
       ROUND(S.ELAPSED_TIME_DELTA/1e6/GREATEST(S.EXECUTIONS_DELTA,1), 2) SEC_PER_EX,
       ROUND(S.BUFFER_GETS_DELTA/GREATEST(S.EXECUTIONS_DELTA,1)) BG_PER_EX
  FROM DBA_HIST_SQLSTAT S JOIN DBA_HIST_SNAPSHOT N ON N.SNAP_ID = S.SNAP_ID AND N.INSTANCE_NUMBER = S.INSTANCE_NUMBER
 WHERE S.SQL_ID = '&SQL_ID' AND N.BEGIN_INTERVAL_TIME > SYSDATE - 14
 ORDER BY S.SNAP_ID DESC FETCH FIRST 20 ROWS ONLY;

