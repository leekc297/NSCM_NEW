PROMPT ################ [S1] ⭐ 화면 Search 1회의 구간 분해 (SCM_COM_SYS_LOG · BE 가 매 호출 기록) ################
PROMPT --  TOTAL = 브라우저 요청 ~ 응답 도착 / DB = SP 호출 + 결과 fetch + BE 결과 JSON 로그 직렬화 / BE = 그 외 서버 처리
PROMPT --  NET_FE = TOTAL - SERVER (네트워크 전송·프록시·FE 수신). ⚠ LOG_END 는 FE 가 응답 받은 뒤 갱신 — 미갱신이면 TOTAL=SERVER
PROMPT --  사내 기준(09-30, ADMIN, 당월~+6개월): 40 = DB 4.1 / SERVER 5.1 / TOTAL 5.3초 · 82 = DB 5.7 / SERVER 6.9 / TOTAL 7.0초
WITH L AS (
  SELECT L.*,
         REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"divisionId":"([^"]*)"',1,1,NULL,1) DIV,
         REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"userGroup":"([^"]*)"',1,1,NULL,1) USER_GROUP,
         REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"versionType":"([^"]*)"',1,1,NULL,1) VER,
         REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"fromYyyymmdd":"([^"]*)"',1,1,NULL,1) || '~' ||
         REGEXP_SUBSTR(L.SYS_LOG_MSG_CTN,'"toYyyymmdd":"([^"]*)"',1,1,NULL,1) PERIOD
    FROM SCM_COM_SYS_LOG L
   WHERE L.MNU_ID = 'DMF0082' AND L.CREATION_DATE >= SYSDATE - &MIN/1440
)
SELECT TO_CHAR(TRNM_ST_DTM,'MM-DD HH24:MI:SS') ST, SHT_NM, DIV, USER_GROUP, VER, PERIOD, CREATED_BY,
       ROUND(EXTRACT(DAY FROM (DB_TRNM_END_DTM - DB_TRNM_ST_DTM))*86400 + EXTRACT(HOUR FROM (DB_TRNM_END_DTM - DB_TRNM_ST_DTM))*3600
           + EXTRACT(MINUTE FROM (DB_TRNM_END_DTM - DB_TRNM_ST_DTM))*60 + EXTRACT(SECOND FROM (DB_TRNM_END_DTM - DB_TRNM_ST_DTM)), 2) DB_S,
       ROUND(EXTRACT(DAY FROM (TRNM_END_DTM - TRNM_ST_DTM))*86400 + EXTRACT(HOUR FROM (TRNM_END_DTM - TRNM_ST_DTM))*3600
           + EXTRACT(MINUTE FROM (TRNM_END_DTM - TRNM_ST_DTM))*60 + EXTRACT(SECOND FROM (TRNM_END_DTM - TRNM_ST_DTM)), 2) SERVER_S,
       ROUND(EXTRACT(DAY FROM (LOG_END_DTM - LOG_ST_DTM))*86400 + EXTRACT(HOUR FROM (LOG_END_DTM - LOG_ST_DTM))*3600
           + EXTRACT(MINUTE FROM (LOG_END_DTM - LOG_ST_DTM))*60 + EXTRACT(SECOND FROM (LOG_END_DTM - LOG_ST_DTM)), 2) TOTAL_S,
       ROUND(EXTRACT(DAY FROM (DB_TRNM_ST_DTM - TRNM_ST_DTM))*86400 + EXTRACT(HOUR FROM (DB_TRNM_ST_DTM - TRNM_ST_DTM))*3600
           + EXTRACT(MINUTE FROM (DB_TRNM_ST_DTM - TRNM_ST_DTM))*60 + EXTRACT(SECOND FROM (DB_TRNM_ST_DTM - TRNM_ST_DTM)), 2) PRE_DB_S,
       SUBSTR(EXCT_MSG_CTN,1,80) ERR
  FROM L
 ORDER BY TRNM_ST_DTM DESC
 FETCH FIRST 40 ROWS ONLY;
PROMPT --  판정: DB_S 가 TOTAL_S 대부분 → DB 병목 (아래 S2~S6) / SERVER_S - DB_S 큼 → BE (JSON 매핑·로그) / TOTAL_S - SERVER_S 큼 → 네트워크·FE
PROMPT --        PRE_DB_S 큼 → 권한체크·커넥션 획득 대기(풀 고갈) / ERR 있음 → 타임아웃·오류

PROMPT ################ [S2] ⭐ 병목 문장 — 실제 화면 세션(BE)의 ASH, PKG_DMF0082 진입분 (샘플 1개 ≈ 1초) ################
PROMPT --  같은 SQL_ID 를 사내 C03 기준값(README §4)과 대조: 사내 1초 미만인데 여기서 수십 샘플이면 그 문장이 범인
WITH P AS (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0082' AND OBJECT_TYPE='PACKAGE'),
A AS (
  SELECT A.* FROM V$ACTIVE_SESSION_HISTORY A, P
   WHERE A.SAMPLE_TIME >= SYSTIMESTAMP - NUMTODSINTERVAL(&MIN,'MINUTE')
     AND A.PLSQL_ENTRY_OBJECT_ID = P.OBJECT_ID
),
T AS (SELECT SQL_ID, MAX(PROGRAM_LINE#) LN, MIN(SUBSTR(REGEXP_REPLACE(SQL_TEXT,'\s+',' '),1,90)) TXT
        FROM V$SQL WHERE SQL_ID IN (SELECT SQL_ID FROM A) GROUP BY SQL_ID)
SELECT NVL(A.SQL_ID,'(PL/SQL·파싱)') SQL_ID, T.LN LINE, COUNT(*) SAMPLES,
       ROUND(100 * RATIO_TO_REPORT(COUNT(*)) OVER (), 1) PCT,
       COUNT(DISTINCT A.SQL_PLAN_HASH_VALUE) PHV_CNT, MAX(A.SQL_PLAN_HASH_VALUE) PHV,
       STATS_MODE(NVL(A.EVENT,'ON CPU')) TOP_EVT,
       SUM(CASE WHEN A.IN_HARD_PARSE = 'Y' THEN 1 ELSE 0 END) HARD_PARSE,
       COUNT(DISTINCT A.SESSION_ID || ',' || A.SQL_EXEC_ID) EXECS,
       T.TXT
  FROM A LEFT JOIN T ON T.SQL_ID = A.SQL_ID
 GROUP BY NVL(A.SQL_ID,'(PL/SQL·파싱)'), T.LN, T.TXT
 ORDER BY SAMPLES DESC
 FETCH FIRST 25 ROWS ONLY;
PROMPT --  0 rows = ASH 창 밖(너무 늦게 실행) 이거나 조회가 매우 빨랐음 → DEFINE MIN 늘리거나 화면 재조회 직후 재실행

PROMPT ################ [S3] 대기 이벤트 구성 — 무엇을 기다렸나 (PKG_DMF0082 진입분 전체) ################
PROMPT --  ON CPU 지배 = 행별 연산·논리IO 과다(계획 비효율) / db file sequential read·cell single block = Nested Loop 랜덤IO(추정오류)
PROMPT --  direct path read = 풀스캔 / direct path write·read temp = PGA 부족 TEMP 유출 / library cache·cursor: pin = 하드파싱·경합
PROMPT --  PX Deq·enq: = 병렬 대기 / enq: TX·TM = 락 대기
WITH P AS (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0082' AND OBJECT_TYPE='PACKAGE')
SELECT NVL(A.WAIT_CLASS,'CPU') WAIT_CLASS, NVL(A.EVENT,'ON CPU') EVT, COUNT(*) SAMPLES,
       ROUND(100 * RATIO_TO_REPORT(COUNT(*)) OVER (), 1) PCT
  FROM V$ACTIVE_SESSION_HISTORY A, P
 WHERE A.SAMPLE_TIME >= SYSTIMESTAMP - NUMTODSINTERVAL(&MIN,'MINUTE')
   AND A.PLSQL_ENTRY_OBJECT_ID = P.OBJECT_ID
 GROUP BY NVL(A.WAIT_CLASS,'CPU'), NVL(A.EVENT,'ON CPU')
 ORDER BY SAMPLES DESC
 FETCH FIRST 15 ROWS ONLY;

PROMPT ################ [S4] 상위 문장의 실행계획 라인별 핫스팟 (어느 오퍼레이션·어느 테이블에서 시간을 썼나) ################
WITH P AS (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0082' AND OBJECT_TYPE='PACKAGE'),
A AS (
  SELECT A.* FROM V$ACTIVE_SESSION_HISTORY A, P
   WHERE A.SAMPLE_TIME >= SYSTIMESTAMP - NUMTODSINTERVAL(&MIN,'MINUTE')
     AND A.PLSQL_ENTRY_OBJECT_ID = P.OBJECT_ID AND A.SQL_ID IS NOT NULL
),
TOPS AS (SELECT SQL_ID FROM A GROUP BY SQL_ID ORDER BY COUNT(*) DESC FETCH FIRST 5 ROWS ONLY)
SELECT A.SQL_ID, A.SQL_PLAN_HASH_VALUE PHV, A.SQL_PLAN_LINE_ID PLAN_LINE,
       A.SQL_PLAN_OPERATION || ' ' || A.SQL_PLAN_OPTIONS OP,
       (SELECT O.OBJECT_NAME FROM ALL_OBJECTS O WHERE O.OBJECT_ID = A.CURRENT_OBJ# AND ROWNUM = 1) OBJ,
       NVL(A.EVENT,'ON CPU') EVT, COUNT(*) SAMPLES
  FROM A WHERE A.SQL_ID IN (SELECT SQL_ID FROM TOPS)
 GROUP BY A.SQL_ID, A.SQL_PLAN_HASH_VALUE, A.SQL_PLAN_LINE_ID, A.SQL_PLAN_OPERATION, A.SQL_PLAN_OPTIONS, A.CURRENT_OBJ#, NVL(A.EVENT,'ON CPU')
HAVING COUNT(*) >= 2
 ORDER BY A.SQL_ID, SAMPLES DESC;
PROMPT --  OBJ 가 SCM_/DM_ 영구 테이블 + TABLE ACCESS FULL 또는 INDEX RANGE SCAN 대량 = 접근경로 문제 → C04 로 계획 확인
PROMPT --  OBJ 가 GT_DMF0082_* + NESTED LOOPS / MERGE JOIN CARTESIAN = GTT 카디널리티 오추정 (07-31 유형)

PROMPT ################ [S5] V$SQL 누적 — PKG_DMF0082 문장별 1회당 비용 (최근 활동분, 자식 커서 단위) ################
WITH B AS (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0082' AND OBJECT_TYPE='PACKAGE BODY')
SELECT S.SQL_ID, S.CHILD_NUMBER CH, S.PROGRAM_LINE# LINE, S.PLAN_HASH_VALUE PHV, S.EXECUTIONS EX,
       ROUND(S.ELAPSED_TIME/1e6/GREATEST(S.EXECUTIONS,1), 2) SEC_PER_EX,
       ROUND(S.CPU_TIME/1e6/GREATEST(S.EXECUTIONS,1), 2) CPU_PER_EX,
       ROUND(S.BUFFER_GETS/GREATEST(S.EXECUTIONS,1)) BG_PER_EX,
       ROUND(S.DISK_READS/GREATEST(S.EXECUTIONS,1)) DR_PER_EX,
       ROUND(S.ROWS_PROCESSED/GREATEST(S.EXECUTIONS,1)) ROWS_PER_EX,
       ROUND(S.USER_IO_WAIT_TIME/1e6/GREATEST(S.EXECUTIONS,1), 2) IO_PER_EX,
       S.PX_SERVERS_EXECUTIONS PX, TO_CHAR(S.LAST_ACTIVE_TIME,'HH24:MI:SS') LAST_ACT,
       SUBSTR(REGEXP_REPLACE(S.SQL_TEXT,'\s+',' '),1,90) TXT
  FROM V$SQL S, B
 WHERE S.PROGRAM_ID = B.OBJECT_ID
   AND S.LAST_ACTIVE_TIME >= SYSDATE - &MIN/1440
 ORDER BY S.ELAPSED_TIME/GREATEST(S.EXECUTIONS,1) DESC
 FETCH FIRST 30 ROWS ONLY;
PROMPT --  사내 기준: 1회당 1초 넘는 문장 없음(최대 18xg1y5298qgq 0.8s · fk3tvpkzsq2vx 0.6s · 12v19yag54ut1 0.6s)

PROMPT ################ [S6] 계획 불안정 — 같은 SQL_ID 에 실행계획이 여러 개 (나쁜 자식 커서 재사용 의심) ################
WITH B AS (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0082' AND OBJECT_TYPE='PACKAGE BODY')
SELECT S.SQL_ID, MAX(S.PROGRAM_LINE#) LINE, COUNT(*) CHILDREN, COUNT(DISTINCT S.PLAN_HASH_VALUE) PHV_CNT,
       LISTAGG(DISTINCT S.PLAN_HASH_VALUE || ':' || ROUND(S.ELAPSED_TIME/1e6/GREATEST(S.EXECUTIONS,1),1) || 's', ' / ' ON OVERFLOW TRUNCATE)
         WITHIN GROUP (ORDER BY S.PLAN_HASH_VALUE) PHV_SEC_PER_EX,
       MIN(SUBSTR(REGEXP_REPLACE(S.SQL_TEXT,'\s+',' '),1,70)) TXT
  FROM V$SQL S, B
 WHERE S.PROGRAM_ID = B.OBJECT_ID
 GROUP BY S.SQL_ID
HAVING COUNT(DISTINCT S.PLAN_HASH_VALUE) > 1
 ORDER BY MAX(S.ELAPSED_TIME/GREATEST(S.EXECUTIONS,1)) DESC
 FETCH FIRST 20 ROWS ONLY;
PROMPT --  PHV 별 1회당 초가 크게 갈리면 → 느린 PHV 가 굳은 커서. 파싱 시점 GTT 빈 상태 추정(E-Rows=1) 유형

PROMPT ################ [S7] ⭐ 커서가 어떤 옵티마이저 설정으로 만들어졌나 (dynamic_sampling 0 으로 굳은 커서 탐지) ################
WITH B AS (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0082' AND OBJECT_TYPE='PACKAGE BODY')
SELECT E.NAME, E.VALUE, COUNT(*) CURSORS,
       ROUND(SUM(S.ELAPSED_TIME)/1e6/GREATEST(SUM(S.EXECUTIONS),1), 3) AVG_SEC_PER_EX,
       CASE WHEN E.NAME = 'optimizer_dynamic_sampling' AND E.VALUE = '0' THEN '❌ DS=0 커서 — 나쁜 계획 고정 위험'
            WHEN E.NAME = 'statistics_level' AND E.VALUE = 'all' THEN 'ℹ 진단 세션(C03 rowstats) 커서' END JUDGE
  FROM V$SQL S JOIN B ON S.PROGRAM_ID = B.OBJECT_ID
  JOIN V$SQL_OPTIMIZER_ENV E ON E.SQL_ID = S.SQL_ID AND E.CHILD_NUMBER = S.CHILD_NUMBER AND E.ADDRESS = S.ADDRESS
 WHERE E.NAME IN ('optimizer_dynamic_sampling','parallel_degree_limit','statistics_level','optimizer_features_enable',
                  'cursor_sharing','optimizer_mode','_pga_max_size','pga_aggregate_target')
 GROUP BY E.NAME, E.VALUE
 ORDER BY E.NAME, CURSORS DESC;

PROMPT ################ [S8] BE 커넥션 세션의 현재 optimizer_dynamic_sampling (풀에 남은 세션 설정) ################
SELECT S.USERNAME, S.MACHINE, S.PROGRAM, E.VALUE DYN_SAMPLING, COUNT(*) SESSIONS
  FROM V$SESSION S JOIN V$SES_OPTIMIZER_ENV E ON E.SID = S.SID
 WHERE E.NAME = 'optimizer_dynamic_sampling' AND S.TYPE = 'USER'
   AND S.USERNAME NOT IN ('SYS','SYSTEM') AND S.SID <> SYS_CONTEXT('USERENV','SID')
 GROUP BY S.USERNAME, S.MACHINE, S.PROGRAM, E.VALUE
 ORDER BY SESSIONS DESC
 FETCH FIRST 20 ROWS ONLY;
PROMPT --  BE 계정(SCMD_APP/SCMP_APP 등) 세션이 0 이어도 SP 첫 줄이 2 로 바꾸므로 조회 SP 에는 무해. 참고용.

