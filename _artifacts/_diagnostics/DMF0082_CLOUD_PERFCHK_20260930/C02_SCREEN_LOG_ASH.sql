--   계정: SCM_MGR · ⚠ BE 가 붙는 DB(QA 또는 DEV — C01 [E0] 참조)에서 실행
--   순서: ① 클라우드 화면에서 Division 40 / 81 / 82 를 각각 Search (가능하면 각 2회)
--         ② 끝나면 바로 이 스크립트 실행 (ASH 는 메모리 보관 — 수십 분~수 시간 내 실행)
--   조회 창: 기본 최근 120분. 바꾸려면 아래 DEFINE MIN 수정
--   변경 없음: SELECT 만 수행
