SET LINESIZE 400
SET PAGESIZE 500
SET TRIMSPOOL ON
SET VERIFY OFF
DEFINE MIN = 120
COLUMN JUDGE FORMAT A40
COLUMN TXT FORMAT A90
COLUMN EVT FORMAT A40
COLUMN OP FORMAT A50
