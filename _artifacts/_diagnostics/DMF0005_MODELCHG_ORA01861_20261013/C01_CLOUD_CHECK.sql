-- Q1. 패키지 상태 · 마지막 변경 시각 · 줄 수
SELECT 'Q1' AS Q, O.OBJECT_TYPE, O.STATUS, TO_CHAR(O.LAST_DDL_TIME, 'YYYY-MM-DD HH24:MI:SS') AS LAST_DDL
     , (SELECT COUNT(*) FROM ALL_SOURCE S WHERE S.OWNER = O.OWNER AND S.NAME = O.OBJECT_NAME AND S.TYPE = O.OBJECT_TYPE) AS LINE_CNT
FROM   ALL_OBJECTS O
WHERE  O.OWNER = 'SCM_MGR' AND O.OBJECT_NAME = 'PKG_DMF0005'
ORDER BY O.OBJECT_TYPE;

-- Q2. 오류 줄 주변 원문 (1704 = 오류 발생 줄, 1837 = 예외 처리부)
SELECT 'Q2' AS Q, S.LINE, CASE WHEN S.LINE IN (1704, 1837) THEN '<<<' END AS MARK, RTRIM(S.TEXT, CHR(10)) AS TEXT
FROM   ALL_SOURCE S
WHERE  S.OWNER = 'SCM_MGR' AND S.NAME = 'PKG_DMF0005' AND S.TYPE = 'PACKAGE BODY'
AND    ( S.LINE BETWEEN 1680 AND 1725 OR S.LINE BETWEEN 1826 AND 1842 )
ORDER BY S.LINE;

-- Q3. 프로시저 시작 줄 (1704 가 어느 프로시저 · 어느 내부 프로시저 안인지)
SELECT 'Q3' AS Q, S.LINE, RTRIM(S.TEXT, CHR(10)) AS TEXT
FROM   ALL_SOURCE S
WHERE  S.OWNER = 'SCM_MGR' AND S.NAME = 'PKG_DMF0005' AND S.TYPE = 'PACKAGE BODY'
AND    REGEXP_LIKE(S.TEXT, '^\s*(PROCEDURE|FUNCTION)\s', 'i')
ORDER BY S.LINE;

-- Q4. Model Code Change 저장 프로시저 안의 날짜·형변환 관련 줄 전체
