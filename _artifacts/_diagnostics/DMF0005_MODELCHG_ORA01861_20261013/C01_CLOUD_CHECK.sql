FROM   ALL_SOURCE S
WHERE  S.OWNER = 'SCM_MGR' AND S.NAME = 'PKG_DMF0005' AND S.TYPE = 'PACKAGE BODY'
AND    S.LINE >= ( SELECT MIN(X.LINE) FROM ALL_SOURCE X
                   WHERE  X.OWNER = 'SCM_MGR' AND X.NAME = 'PKG_DMF0005' AND X.TYPE = 'PACKAGE BODY'
                   AND    REGEXP_LIKE(X.TEXT, '^\s*PROCEDURE\s+P_DMF0005_SAVE_MODEL_CHANGE_POPUP', 'i') )
