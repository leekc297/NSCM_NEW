-- R1. 본문 지문 — 사내 값: LINE_CNT 1906 / HASH_SUM 4107528171263 / LAST_DDL 2026-10-12 19:18:19
SELECT 'R1' AS Q, SYS_CONTEXT('USERENV', 'DB_NAME') AS DB, SYS_CONTEXT('USERENV', 'SERVER_HOST') AS HOST
     , ( SELECT TO_CHAR(O.LAST_DDL_TIME, 'YYYY-MM-DD HH24:MI:SS') FROM ALL_OBJECTS O
         WHERE  O.OWNER = 'SCM_MGR' AND O.OBJECT_NAME = 'PKG_DMF0005' AND O.OBJECT_TYPE = 'PACKAGE BODY' ) AS LAST_DDL
     , V.LINE_CNT, V.HASH_SUM
FROM   ( SELECT COUNT(*) AS LINE_CNT, SUM(ORA_HASH(S.TEXT)) AS HASH_SUM
         FROM   ALL_SOURCE S
         WHERE  S.OWNER = 'SCM_MGR' AND S.NAME = 'PKG_DMF0005' AND S.TYPE = 'PACKAGE BODY' ) V;

-- R2. 오류 메시지의 줄(1704 · 1837)과 현재 본문의 실제 예외 처리 줄
SELECT 'R2' AS Q, S.LINE, SUBSTR(LTRIM(RTRIM(S.TEXT, CHR(10))), 1, 110) AS TEXT
FROM   ALL_SOURCE S
WHERE  S.OWNER = 'SCM_MGR' AND S.NAME = 'PKG_DMF0005' AND S.TYPE = 'PACKAGE BODY'
AND    ( S.LINE IN (1704, 1837) OR UPPER(S.TEXT) LIKE '%RAISE_APPLICATION_ERROR%'
         OR REGEXP_LIKE(S.TEXT, '^\s*(PROCEDURE|FUNCTION)\s', 'i') )
ORDER BY S.LINE;

-- R3. 저장 프로시저 실행 기록 최근 15건 (오류 시각 · 오류 원문 · 오류 줄)
SELECT 'R3' AS Q, L.T, L.LOG_TYPE, L.LOG_COUNT AS CNT, L.MSG, L.DESCR
FROM   ( SELECT TO_CHAR(B.EVENT_DATE, 'MM-DD HH24:MI:SS') AS T, B.LOG_TYPE, B.LOG_COUNT
              , SUBSTR(REPLACE(B.LOG_MESSAGE, CHR(10), ' '), 1, 90)  AS MSG
              , SUBSTR(REPLACE(B.DESCRIPTION, CHR(10), ' '), 1, 160) AS DESCR
         FROM   SCM_MGR.SCM_SYS_LOG_BATCH B
         WHERE  B.PROGRAM_NAME = 'PKG_DMF0005'
         ORDER BY B.EVENT_DATE DESC ) L
WHERE  ROWNUM <= 15;

-- R4. 화면 오류 기록 최근 5건 (언제 · 누가 · 어느 호출에서)
SELECT 'R4' AS Q, L.T, L.CREATED_BY, L.MNU_ID, L.SHT_NM, L.URL, L.EXC
FROM   ( SELECT TO_CHAR(G.CREATION_DATE, 'MM-DD HH24:MI:SS') AS T, G.CREATED_BY, G.MNU_ID, G.SHT_NM
              , SUBSTR(G.CALL_PGM_URL, 1, 50) AS URL
              , SUBSTR(REPLACE(G.EXCT_MSG_CTN, CHR(10), ' '), 1, 230) AS EXC
         FROM   SCM_MGR.SCM_COM_SYS_LOG G
         WHERE  G.EXCT_MSG_CTN LIKE '%PKG_DMF0005%'
         ORDER BY G.CREATION_DATE DESC ) L
WHERE  ROWNUM <= 5;

-- R5. 구조 차이 후보 — 사내는 2행(가상 컬럼 1 · 로그 프로시저 날짜 인자 1)만 나옵니다
--     (날짜 컬럼 기본값은 길이 6 이하만 표시 = SYSDATE 가 아닌 짧은 문자 기본값 후보)
