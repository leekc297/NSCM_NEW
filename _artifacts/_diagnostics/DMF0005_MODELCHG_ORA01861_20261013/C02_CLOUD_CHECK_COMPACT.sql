       , 'DM_DNM_EDI_CALLOFF_ITEM', 'DM_DNM_SALES_RESULT_IF', 'DM_HI_CUST_FCST_INPUT', 'DM_HI_MKT_FCST_CHANGE'
       , 'DM_HI_SALES_INPUT', 'DM_HI_SITE_ITEM_MAPPING', 'DM_HI_SITE_ITEM_MAPPING_ROWDATA'
       , 'DM_MST_BUCKET_CONVERSION', 'DM_MST_BUCKET_CONVERSION_H', 'DM_MST_CAPACITY_ALLOCATION', 'DM_MST_CAPACITY_ALLOCATION_H'
       , 'DM_MST_CUSTOMER_MODEL', 'DM_MST_CUSTOMER_MODEL_H', 'DM_MST_EDI_CUST_MATERIAL_INFO'
       , 'DM_PLN_BP_FCST', 'DM_PLN_BP_FCST_H', 'DM_PLN_CUSTOMER_PSI', 'DM_PLN_CUSTOMER_PSI_H'
       , 'DM_PLN_MKT_FCST', 'DM_PLN_MKT_FCST_CONFIRM', 'DM_PLN_MKT_FCST_H', 'DM_PLN_MKT_FCST_PK_DATA_UPDATE_H'
       , 'DM_PLN_MKT_FCST_RESULT', 'DM_PLN_PR_DETAIL', 'DM_PLN_SALES_PLAN', 'DM_PLN_SALES_PLAN_H'
       , 'DM_PLN_SALES_PLAN_REPORT_H', 'DM_PLN_SALES_PLAN_RESULT', 'SCM_MST_FUTURE_PRICE', 'SCM_MST_FUTURE_PRICE_H'
       , 'SCM_MST_SITE_ITEM', 'SCM_MST_SITE_ITEM_H', 'SCM_MST_SITE_ITEM_PRIORITY', 'SCM_MST_SITE_ITEM_PRIORITY_H' )
AND    (    ( C.COLUMN_NAME IN ('ITEM_ID', 'LAST_UPDATED_BY', 'CREATED_BY', 'BEFORE_CODE', 'AFTER_CODE', 'TABLE_NAME')
              AND C.DATA_TYPE NOT IN ('VARCHAR2', 'NVARCHAR2', 'CHAR') )
         OR ( C.COLUMN_NAME IN ('LAST_UPDATE_DATE', 'CREATION_DATE') AND C.DATA_TYPE <> 'DATE' )
         OR C.VIRTUAL_COLUMN = 'YES'
         OR ( ( C.DATA_TYPE = 'DATE' OR C.DATA_TYPE LIKE 'TIMESTAMP%' ) AND C.DEFAULT_LENGTH BETWEEN 1 AND 6 ) )
UNION ALL
SELECT 'R5', 'TRIGGER', T.TABLE_NAME, T.TRIGGER_NAME, T.STATUS, SUBSTR(T.TRIGGERING_EVENT, 1, 60)
FROM   ALL_TRIGGERS T
WHERE  T.TABLE_OWNER = 'SCM_MGR'
AND    T.TABLE_NAME IN ( 'DM_DNM_ITEM_CODE_CHANGE_HISTORY'
       , 'DM_ANL_KPI_RTF_DEMAND', 'DM_ANL_KPI_RTF_SALES', 'DM_ANL_KPI_SALES_ACCURACY', 'DM_ANL_KPI_SUMMARY'
       , 'DM_DNM_EDI_CALLOFF_ITEM', 'DM_DNM_SALES_RESULT_IF', 'DM_HI_CUST_FCST_INPUT', 'DM_HI_MKT_FCST_CHANGE'
       , 'DM_HI_SALES_INPUT', 'DM_HI_SITE_ITEM_MAPPING', 'DM_HI_SITE_ITEM_MAPPING_ROWDATA'
       , 'DM_MST_BUCKET_CONVERSION', 'DM_MST_BUCKET_CONVERSION_H', 'DM_MST_CAPACITY_ALLOCATION', 'DM_MST_CAPACITY_ALLOCATION_H'
       , 'DM_MST_CUSTOMER_MODEL', 'DM_MST_CUSTOMER_MODEL_H', 'DM_MST_EDI_CUST_MATERIAL_INFO'
       , 'DM_PLN_BP_FCST', 'DM_PLN_BP_FCST_H', 'DM_PLN_CUSTOMER_PSI', 'DM_PLN_CUSTOMER_PSI_H'
       , 'DM_PLN_MKT_FCST', 'DM_PLN_MKT_FCST_CONFIRM', 'DM_PLN_MKT_FCST_H', 'DM_PLN_MKT_FCST_PK_DATA_UPDATE_H'
       , 'DM_PLN_MKT_FCST_RESULT', 'DM_PLN_PR_DETAIL', 'DM_PLN_SALES_PLAN', 'DM_PLN_SALES_PLAN_H'
       , 'DM_PLN_SALES_PLAN_REPORT_H', 'DM_PLN_SALES_PLAN_RESULT', 'SCM_MST_FUTURE_PRICE', 'SCM_MST_FUTURE_PRICE_H'
       , 'SCM_MST_SITE_ITEM', 'SCM_MST_SITE_ITEM_H', 'SCM_MST_SITE_ITEM_PRIORITY', 'SCM_MST_SITE_ITEM_PRIORITY_H' )
UNION ALL
SELECT 'R5', 'LOG_PROC_ARG', A.OBJECT_NAME, TO_CHAR(A.POSITION) || ' ' || A.ARGUMENT_NAME, A.DATA_TYPE, NULL
FROM   ALL_ARGUMENTS A
WHERE  A.OWNER = 'SCM_MGR' AND A.OBJECT_NAME = 'PR_SCM_SYS_LOG_BATCH' AND A.PACKAGE_NAME IS NULL
AND    A.DATA_TYPE NOT IN ('VARCHAR2', 'NUMBER');
