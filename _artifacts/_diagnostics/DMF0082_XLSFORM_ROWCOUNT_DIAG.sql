-- DMF0082 Excel Form (division 81) 조회 건수 축소 원인 진단 — 조회 전용 (SCM_MGR)
--   대상 SP : PKG_DMF0082.P_DMF0082_GET_EXCEL_FORM_DATA
--   방법    : SP 본문의 필터·조인을 **순서대로 누적 적용**하며 행수를 재서, 어느 단계에서 줄어드는지 특정한다.
--   사용법  : 아래 P_USER_ID 한 줄만 조회 계정으로 바꾸고 전체 실행 (치환변수 &  없음 — DBeaver/SQL Developer 그대로 실행).
--   판정    : CORP_REF(사내 2026-09-23 실측)와 CNT 를 비교 — **처음으로 크게 벌어지는 STEP 이 원인**.
-- ============================================================================
WITH P AS (SELECT 'minyonglee1' AS USER_ID FROM DUAL)        -- ★ 여기만 바꾸세요 (화면에서 Excel Form 을 연 계정)
, V AS (
    SELECT A.DIVISION_ID, A.VERSION_NO, A.YYYYMMDD, B.BASIS_YYYYMM AS YYYYMM
      FROM (SELECT DIVISION_ID, MAX(VERSION_NO) AS VERSION_NO, MAX(YYYYMMDD) AS YYYYMMDD
              FROM DM_MST_VERSION WHERE DIVISION_ID = '81' AND VERSION_TYPE = 'SP_W' GROUP BY DIVISION_ID) A
     INNER JOIN SCM_SYS_CALENDAR_M B ON B.BASIS_YYYYMMDD = A.YYYYMMDD)
, W AS (
    SELECT V.*, TO_CHAR(FN_NEXT_DAY(TO_DATE(V.YYYYMMDD,'YYYYMMDD'),'MON') - 7, 'YYYYMMDD') AS WIN_FROM,
           TO_CHAR(TO_DATE(TO_CHAR(FN_NEXT_DAY(TO_DATE(V.YYYYMMDD,'YYYYMMDD'),'MON') - 7,'YYYYMMDD'),'YYYYMMDD') + (52*7) - 1, 'YYYYMMDD') AS WIN_TO
      FROM V)
, BASE_C AS (
    SELECT SP.DIVISION_ID, SP.SCM_SITE_ID, SP.PROJECT_CODE, SP.ITEM_ID, SP.CURRENCY
      FROM DM_PLN_SALES_PLAN_C SP INNER JOIN W ON SP.VERSION_NO = W.VERSION_NO
     WHERE SP.DIVISION_ID = '81' AND SP.MEASURE = 'RTF_SYS_RP' AND SP.QTY <> 0
       AND SP.YYYYMMDD >= W.WIN_FROM AND SP.YYYYMMDD <= W.WIN_TO)
, IM AS (
    SELECT SA.DIVISION_ID, SA.SCM_SITE_ID, MAX(SA.DEPT_ID) AS DEPT_ID
      FROM SCM_MST_SITE_ITEM SA INNER JOIN SCM_MST_SSO_DEPT_INFO SD ON SD.DEPT_ID = SA.DEPT_ID AND SD.VALID_YN = 'Y'
     WHERE SA.DEPT_ID IS NOT NULL GROUP BY SA.DIVISION_ID, SA.SCM_SITE_ID)
, T2 AS (
    SELECT AU.UNIT_ID, AU.EDIT_YN FROM SCM_ADM_USER_MNU_EDIT_AUTH_V AU, P
     WHERE AU.USER_ID = P.USER_ID AND AU.MNU_ID = 'DMF0082' AND AU.UNIT_TP_CD = 'D')
SELECT * FROM (
  SELECT 01 AS STEP, '기준버전 SP_W 존재 (DM_MST_VERSION)'                    AS ITEM, TO_CHAR(COUNT(*)) AS CNT, '1' AS CORP_REF FROM V
  UNION ALL SELECT 02, '  └ VERSION_NO / 기준일',            MAX(VERSION_NO)||' / '||MAX(YYYYMMDD), 'SP_W_20260827_V001 / 20260827' FROM V
  UNION ALL SELECT 03, '  └ 52주 창 (FROM ~ TO)',            MAX(WIN_FROM)||' ~ '||MAX(WIN_TO),     '20260824 ~ 20270822' FROM W
  UNION ALL SELECT 04, 'SALES_PLAN_C  div 81 전체',          TO_CHAR(COUNT(*)), '4157562' FROM DM_PLN_SALES_PLAN_C WHERE DIVISION_ID='81'
  UNION ALL SELECT 05, '  + 최신 SP_W 버전',                 TO_CHAR(COUNT(*)), '68463'
              FROM DM_PLN_SALES_PLAN_C SP INNER JOIN W ON SP.VERSION_NO=W.VERSION_NO WHERE SP.DIVISION_ID='81'
  UNION ALL SELECT 06, '  + MEASURE=RTF_SYS_RP',             TO_CHAR(COUNT(*)), '5709'
              FROM DM_PLN_SALES_PLAN_C SP INNER JOIN W ON SP.VERSION_NO=W.VERSION_NO WHERE SP.DIVISION_ID='81' AND SP.MEASURE='RTF_SYS_RP'
  UNION ALL SELECT 07, '  + QTY<>0',                         TO_CHAR(COUNT(*)), '5709'
              FROM DM_PLN_SALES_PLAN_C SP INNER JOIN W ON SP.VERSION_NO=W.VERSION_NO WHERE SP.DIVISION_ID='81' AND SP.MEASURE='RTF_SYS_RP' AND SP.QTY<>0
  UNION ALL SELECT 08, '  + 52주 창  = BASE_C',              TO_CHAR(COUNT(*)), '5130' FROM BASE_C
  UNION ALL SELECT 09, '  + 편집권한 뷰(EDIT_AUTH_V)',       TO_CHAR(COUNT(*)), '5130'
              FROM BASE_C B INNER JOIN T2 ON B.DIVISION_ID = T2.UNIT_ID
  UNION ALL SELECT 10, '  + SCM_MST_SITE (VALID_YN=Y)',      TO_CHAR(COUNT(*)), '5130'
              FROM BASE_C B INNER JOIN T2 ON B.DIVISION_ID=T2.UNIT_ID
                            INNER JOIN SCM_MST_SITE MS ON MS.DIVISION_ID=B.DIVISION_ID AND MS.SCM_SITE_ID=B.SCM_SITE_ID AND MS.VALID_YN='Y'
  UNION ALL SELECT 11, '  + SITE_ITEM 대표부서 IM(#150)',    TO_CHAR(COUNT(*)), '5046'
              FROM BASE_C B INNER JOIN T2 ON B.DIVISION_ID=T2.UNIT_ID
                            INNER JOIN SCM_MST_SITE MS ON MS.DIVISION_ID=B.DIVISION_ID AND MS.SCM_SITE_ID=B.SCM_SITE_ID AND MS.VALID_YN='Y'
                            INNER JOIN IM ON IM.DIVISION_ID=MS.DIVISION_ID AND IM.SCM_SITE_ID=MS.SCM_SITE_ID
  UNION ALL SELECT 12, '  + SSO_DEPT(대표부서 유효)',        TO_CHAR(COUNT(*)), '5046'
              FROM BASE_C B INNER JOIN T2 ON B.DIVISION_ID=T2.UNIT_ID
                            INNER JOIN SCM_MST_SITE MS ON MS.DIVISION_ID=B.DIVISION_ID AND MS.SCM_SITE_ID=B.SCM_SITE_ID AND MS.VALID_YN='Y'
                            INNER JOIN IM ON IM.DIVISION_ID=MS.DIVISION_ID AND IM.SCM_SITE_ID=MS.SCM_SITE_ID
                            INNER JOIN SCM_MST_SSO_DEPT_INFO DI ON DI.DEPT_ID=IM.DEPT_ID AND DI.VALID_YN='Y'
  UNION ALL SELECT 13, '  + SCM_MST_PROJECT',                TO_CHAR(COUNT(*)), '5046'
              FROM BASE_C B INNER JOIN T2 ON B.DIVISION_ID=T2.UNIT_ID
                            INNER JOIN SCM_MST_SITE MS ON MS.DIVISION_ID=B.DIVISION_ID AND MS.SCM_SITE_ID=B.SCM_SITE_ID AND MS.VALID_YN='Y'
                            INNER JOIN IM ON IM.DIVISION_ID=MS.DIVISION_ID AND IM.SCM_SITE_ID=MS.SCM_SITE_ID
                            INNER JOIN SCM_MST_SSO_DEPT_INFO DI ON DI.DEPT_ID=IM.DEPT_ID AND DI.VALID_YN='Y'
                            INNER JOIN SCM_MST_PROJECT MP ON MP.DIVISION_ID=B.DIVISION_ID AND MP.PROJECT_CODE=B.PROJECT_CODE
  UNION ALL SELECT 14, '  + SITE_ITEM(4키, VALID_YN=Y)',     TO_CHAR(COUNT(*)), '5046'
              FROM BASE_C B INNER JOIN T2 ON B.DIVISION_ID=T2.UNIT_ID
                            INNER JOIN SCM_MST_SITE MS ON MS.DIVISION_ID=B.DIVISION_ID AND MS.SCM_SITE_ID=B.SCM_SITE_ID AND MS.VALID_YN='Y'
                            INNER JOIN IM ON IM.DIVISION_ID=MS.DIVISION_ID AND IM.SCM_SITE_ID=MS.SCM_SITE_ID
                            INNER JOIN SCM_MST_SSO_DEPT_INFO DI ON DI.DEPT_ID=IM.DEPT_ID AND DI.VALID_YN='Y'
                            INNER JOIN SCM_MST_PROJECT MP ON MP.DIVISION_ID=B.DIVISION_ID AND MP.PROJECT_CODE=B.PROJECT_CODE
                            INNER JOIN SCM_MST_SITE_ITEM SI ON SI.DIVISION_ID=B.DIVISION_ID AND SI.PROJECT_CODE=B.PROJECT_CODE
                                                           AND SI.SCM_SITE_ID=B.SCM_SITE_ID AND SI.ITEM_ID=B.ITEM_ID AND SI.VALID_YN='Y'
  UNION ALL SELECT 15, '  + GROUP BY 그룹 수 (SP 내부)',      TO_CHAR(COUNT(*)), '155' FROM (
              SELECT B.DIVISION_ID, TEAM.DEPT_ID, TEAM.DEPT_NAME_KO, MS.END_CUSTOMER, B.PROJECT_CODE, MP.PROJECT_NAME,
                     B.ITEM_ID, B.SCM_SITE_ID, T2.EDIT_YN,
                     MAX(CASE WHEN NVL(B.CURRENCY,'-')='-' THEN SI.CURRENCY ELSE B.CURRENCY END) AS CURRENCY
                FROM BASE_C B INNER JOIN T2 ON B.DIVISION_ID=T2.UNIT_ID
                            INNER JOIN SCM_MST_SITE MS ON MS.DIVISION_ID=B.DIVISION_ID AND MS.SCM_SITE_ID=B.SCM_SITE_ID AND MS.VALID_YN='Y'
                            INNER JOIN IM ON IM.DIVISION_ID=MS.DIVISION_ID AND IM.SCM_SITE_ID=MS.SCM_SITE_ID
                            INNER JOIN SCM_MST_SSO_DEPT_INFO DI ON DI.DEPT_ID=IM.DEPT_ID AND DI.VALID_YN='Y'
                            INNER JOIN SCM_MST_PROJECT MP ON MP.DIVISION_ID=B.DIVISION_ID AND MP.PROJECT_CODE=B.PROJECT_CODE
                            INNER JOIN SCM_MST_SITE_ITEM SI ON SI.DIVISION_ID=B.DIVISION_ID AND SI.PROJECT_CODE=B.PROJECT_CODE
                                                           AND SI.SCM_SITE_ID=B.SCM_SITE_ID AND SI.ITEM_ID=B.ITEM_ID AND SI.VALID_YN='Y'
                            LEFT  JOIN SCM_MST_SSO_DEPT_INFO TEAM ON TEAM.DEPT_ID = SI.DEPT_ID
               GROUP BY B.DIVISION_ID, TEAM.DEPT_ID, TEAM.DEPT_NAME_KO, MS.END_CUSTOMER, B.PROJECT_CODE, MP.PROJECT_NAME,
                        B.ITEM_ID, B.SCM_SITE_ID, T2.EDIT_YN)
  UNION ALL SELECT 16, '★ 최종 양식 행수 (DISTINCT 표시축)',    TO_CHAR(COUNT(*)), '116' FROM (
              SELECT DISTINCT B.DIVISION_ID, TEAM.DEPT_NAME_KO, MS.END_CUSTOMER, B.PROJECT_CODE, B.ITEM_ID, T2.EDIT_YN,
                     MAX(CASE WHEN NVL(B.CURRENCY,'-')='-' THEN SI.CURRENCY ELSE B.CURRENCY END) AS CURRENCY
                FROM BASE_C B INNER JOIN T2 ON B.DIVISION_ID=T2.UNIT_ID
                            INNER JOIN SCM_MST_SITE MS ON MS.DIVISION_ID=B.DIVISION_ID AND MS.SCM_SITE_ID=B.SCM_SITE_ID AND MS.VALID_YN='Y'
                            INNER JOIN IM ON IM.DIVISION_ID=MS.DIVISION_ID AND IM.SCM_SITE_ID=MS.SCM_SITE_ID
                            INNER JOIN SCM_MST_SSO_DEPT_INFO DI ON DI.DEPT_ID=IM.DEPT_ID AND DI.VALID_YN='Y'
                            INNER JOIN SCM_MST_PROJECT MP ON MP.DIVISION_ID=B.DIVISION_ID AND MP.PROJECT_CODE=B.PROJECT_CODE
                            INNER JOIN SCM_MST_SITE_ITEM SI ON SI.DIVISION_ID=B.DIVISION_ID AND SI.PROJECT_CODE=B.PROJECT_CODE
                                                           AND SI.SCM_SITE_ID=B.SCM_SITE_ID AND SI.ITEM_ID=B.ITEM_ID AND SI.VALID_YN='Y'
                            LEFT  JOIN SCM_MST_SSO_DEPT_INFO TEAM ON TEAM.DEPT_ID = SI.DEPT_ID
               GROUP BY B.DIVISION_ID, TEAM.DEPT_ID, TEAM.DEPT_NAME_KO, MS.END_CUSTOMER, B.PROJECT_CODE, MP.PROJECT_NAME,
                        B.ITEM_ID, B.SCM_SITE_ID, T2.EDIT_YN)
  UNION ALL SELECT 17, 'RESULT_C 분기 행수(보조)',           TO_CHAR(COUNT(*)), '0'
              FROM DM_PLN_SALES_PLAN_RESULT_C SP INNER JOIN W ON SP.VERSION_NO=W.VERSION_NO
             WHERE SP.DIVISION_ID='81' AND SP.MEASURE='RTF_SYS_RP' AND SP.QTY<>0
               AND SP.YYYYMMDD >= W.YYYYMM||'01' AND SP.YYYYMMDD < W.WIN_FROM
  -- ── 마스터 보유량 (조인 감소 시 어느 마스터가 빈약한지) ─────────────────────
  UNION ALL SELECT 20, '[마스터] 권한 뷰 행수(이 계정·DMF0082·D)', TO_CHAR(COUNT(*)), '14' FROM T2
  UNION ALL SELECT 21, '[마스터] 그중 81 계열',              TO_CHAR(COUNT(*)), '6' FROM T2 WHERE UNIT_ID LIKE '81%'
  UNION ALL SELECT 22, '[마스터] SCM_MST_SITE  81 유효',     TO_CHAR(COUNT(*)), '475' FROM SCM_MST_SITE WHERE DIVISION_ID='81' AND VALID_YN='Y'
  UNION ALL SELECT 23, '[마스터] SCM_MST_SITE_ITEM 81 유효', TO_CHAR(COUNT(*)), '51688' FROM SCM_MST_SITE_ITEM WHERE DIVISION_ID='81' AND VALID_YN='Y'
  UNION ALL SELECT 24, '[마스터] SCM_MST_PROJECT 81',        TO_CHAR(COUNT(*)), '1158' FROM SCM_MST_PROJECT WHERE DIVISION_ID='81'
  UNION ALL SELECT 25, '[마스터] IM 대표부서 81',            TO_CHAR(COUNT(*)), '430' FROM IM WHERE DIVISION_ID='81'
  UNION ALL SELECT 26, '[마스터] SALES_PLAN_C 버전종류(81)', TO_CHAR(COUNT(DISTINCT VERSION_NO)), '50' FROM DM_PLN_SALES_PLAN_C WHERE DIVISION_ID='81'
) ORDER BY STEP;
