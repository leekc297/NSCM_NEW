PROMPT === [3] PROJECT_POPUP_LIST 호출 다양화 ===
SET SERVEROUTPUT ON
DECLARE
    V_RC SYS_REFCURSOR;
    V_DIV VARCHAR2(50); V_DN VARCHAR2(50); V_PC VARCHAR2(100); V_PN VARCHAR2(200);
    V_PS VARCHAR2(50); V_BIZ VARCHAR2(50); V_BN VARCHAR2(200);
    V_CUR VARCHAR2(20); V_VER VARCHAR2(50); V_OWN VARCHAR2(50);
    V_DP VARCHAR2(50); V_DPN VARCHAR2(200); V_EC VARCHAR2(100);
    V_CNT PLS_INTEGER;

    PROCEDURE TST(P1 VARCHAR2, P2 VARCHAR2, P3 VARCHAR2, P4 VARCHAR2, P5 VARCHAR2, P6 VARCHAR2) AS
    BEGIN
        V_CNT := 0;
        SCM_MGR.DMF0072_GET_PROJECT_POPUP_LIST(P1, P2, P3, P4, P5, P6, V_RC);
        LOOP
            FETCH V_RC INTO V_DIV, V_DN, V_PC, V_PN, V_PS, V_BIZ, V_BN, V_CUR, V_VER, V_OWN, V_DP, V_DPN, V_EC;
            EXIT WHEN V_RC%NOTFOUND;
            V_CNT := V_CNT + 1;
        END LOOP;
        CLOSE V_RC;
        DBMS_OUTPUT.PUT_LINE('PROJECT(' || P1 || ',' || P2 || ',' || P3 || ',' || P4 || ',' || P5 || ',' || P6 || ') = ' || V_CNT || ' rows');
    END;
BEGIN
    TST('ALL', 'ALL', 'ALL', 'ALL', '',  'N');     -- 전부 ALL + project 빈
    TST('ALL', 'ALL', 'ALL', 'ALL', NULL,'N');     -- project NULL
    TST('81',  'ALL', 'ALL', 'ALL', '',  'N');     -- div=81
    TST('40',  'ALL', 'ALL', 'ALL', '',  'N');     -- div=40
    TST('81',  'ALL', 'ALL', 'ALL', 'A', 'N');     -- A* 검색
END;
/

PROMPT === [4] 정밀 진단 — TEAM.DEPT_ID 매칭 확인 (Project SP body 의 핵심 필터) ===
SELECT 'P-debug TEAM.DEPT_ID 매칭' AS K, COUNT(*) AS CNT
  FROM SCM_MGR.SCM_MST_PROJECT A
  LEFT JOIN (SELECT * FROM SCM_MGR.SCM_MST_SITE_ITEM WHERE VALID_YN='Y') B
    ON A.DIVISION_ID = B.DIVISION_ID AND A.PROJECT_CODE = B.PROJECT_CODE
  LEFT JOIN SCM_MGR.SCM_MST_SSO_USER_INFO SU
    ON SU.USER_ID = (SELECT TOKEN FROM TABLE(SCM_MGR.UF_FX_STRING_SPLIT(B.OWNER, ',')) WHERE ROWNUM=1)
  LEFT JOIN (SELECT * FROM SCM_MGR.SCM_MST_SSO_DEPT_INFO WHERE VALID_YN='Y') TEAM ON SU.DEPT_ID = TEAM.DEPT_ID
 WHERE TEAM.DEPT_ID IS NOT NULL
   AND A.DROP_YN = 'N';

EXIT;
