PROMPT === [1] ITEM 관련 테이블 검색 ===
SELECT OWNER||'.'||TABLE_NAME AS T
  FROM ALL_TABLES
 WHERE TABLE_NAME LIKE 'SCM_MST_ITEM%'
 ORDER BY 1;

PROMPT === [2] SCM_MST_ITEM 컬럼 (있다면) ===
SELECT COLUMN_NAME||'|'||DATA_TYPE AS COL
  FROM ALL_TAB_COLUMNS
 WHERE OWNER='SCM_MGR' AND TABLE_NAME='SCM_MST_ITEM'
 ORDER BY COLUMN_ID;

PROMPT === [3] item_sn 의 row 가 있다는 카운트 검증 — 직접 ===
SELECT COUNT(*) AS ITEM_SN_CNT FROM SCM_MGR.SCM_MST_ITEM_SN WHERE ROWNUM <= 100;

PROMPT === [4] SCM_MST_ITEM_SN 시노님 / 별칭 ===
SELECT * FROM ALL_SYNONYMS WHERE SYNONYM_NAME='SCM_MST_ITEM_SN' OR TABLE_NAME='SCM_MST_ITEM_SN'
 FETCH FIRST 5 ROWS ONLY;

