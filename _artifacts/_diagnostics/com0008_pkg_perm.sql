PROMPT === [1] PKG_COM0000 + 관련 PKG VALID 여부 ===
SELECT OBJECT_NAME || '|' || OBJECT_TYPE || '|' || STATUS
  FROM ALL_OBJECTS
 WHERE OWNER='SCM_MGR'
   AND OBJECT_NAME LIKE 'PKG_COM%'
 ORDER BY OBJECT_NAME, OBJECT_TYPE;

PROMPT === [2] COM0005 GUEST 권한 (Project — 동작하는 비교군) ===
SELECT USER_GR_ID || '|' || MNU_ID || '|' || SHT_NM || '|' || MNU_BTN_CD
  FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M
 WHERE MNU_ID='COM0005' AND USER_GR_ID='GUEST';

PROMPT === [3] COM0005 의 API_M URL (PKG 사용 비교) ===
SELECT API_ID || '|' || API_URL FROM SCM_MGR.SCM_ADM_API_M WHERE API_ID='COM0005_GET';

PROMPT === [4] COM0005 PROC_M (Project popup signature) ===
SELECT PROC_NM || '|' || COL_NM || '|' || COL_TP_CD || '|' || SORT_ORD
  FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM IN (SELECT API_URL FROM SCM_MGR.SCM_ADM_API_M WHERE API_ID='COM0005_GET')
 ORDER BY SORT_ORD;

PROMPT === [5] minyonglee1 의 COM0008 권한 직접 확인 ===
SELECT 'minyonglee1 GR_MPG' AS K, USER_GR_ID
  FROM SCM_MGR.SCM_ADM_USER_GR_MPG_M WHERE USER_ID='minyonglee1';

SELECT 'minyonglee1 COM0008 BTN 권한' AS K, USER_GR_ID || '|' || SHT_NM || '|' || MNU_BTN_CD AS V
  FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M
