PROMPT ################ [V3] 키 단위 _C(대상버전) vs 원장(현재값) MKT_AMT_KRW 비교 — 차이 분류 ################
WITH LAST_RUN AS (SELECT MAX(CREATION_DATE) MAX_CD FROM DM_MST_VERSION WHERE VERSION_TYPE = 'SP_D'),
TV AS (SELECT DIVISION_ID, VERSION_NO
         FROM (SELECT V.DIVISION_ID, V.VERSION_NO,
                      ROW_NUMBER() OVER (PARTITION BY V.DIVISION_ID ORDER BY V.CREATION_DATE DESC, V.VERSION_NO DESC) RN
                 FROM DM_MST_VERSION V, LAST_RUN L
                WHERE V.VERSION_TYPE = 'SP_D' AND V.CREATION_DATE >= L.MAX_CD - 1)
        WHERE RN = 1),
C AS (SELECT A.* FROM DM_PLN_SALES_PLAN_C A, TV
       WHERE A.DIVISION_ID = TV.DIVISION_ID AND A.VERSION_NO = TV.VERSION_NO AND A.MEASURE = 'MKT_AMT_KRW'
         AND A.SCM_SITE_ID NOT IN ('acer_CN_CKG') AND A.ITEM_ID NOT IN ('MPCHPPHS042C')),
CR AS (SELECT DIVISION_ID, MIN(YYYYMMDD) MIN_YMD FROM C GROUP BY DIVISION_ID),
S AS (SELECT A.* FROM DM_PLN_SALES_PLAN A, CR
       WHERE A.DIVISION_ID = CR.DIVISION_ID AND A.YYYYMMDD >= CR.MIN_YMD AND A.MEASURE = 'MKT_AMT_KRW'
         AND A.SCM_SITE_ID NOT IN ('acer_CN_CKG') AND A.ITEM_ID NOT IN ('MPCHPPHS042C')),
J AS (SELECT NVL(C.DIVISION_ID, S.DIVISION_ID) DIVISION_ID, C.QTY C_QTY, S.QTY S_QTY
        FROM C FULL OUTER JOIN S
          ON C.DIVISION_ID = S.DIVISION_ID AND C.PROJECT_CODE = S.PROJECT_CODE AND C.SCM_SITE_ID = S.SCM_SITE_ID
         AND C.ITEM_ID = S.ITEM_ID AND C.DOM_EXP = S.DOM_EXP AND C.FCST_TYPE = S.FCST_TYPE AND C.INCOTERMS = S.INCOTERMS
         AND C.PLANT_SITE_ID = S.PLANT_SITE_ID AND C.CELL_PROD_SITE_ID = S.CELL_PROD_SITE_ID AND C.YYYYMMDD = S.YYYYMMDD)
SELECT DIVISION_ID,
       CASE WHEN C_QTY IS NULL THEN '4 원장에만 있음(컷오프 후 생성)'
            WHEN S_QTY IS NULL THEN '5 _C 에만 있음(컷오프 후 삭제)'
            WHEN C_QTY = S_QTY THEN '1 동일'
            WHEN ABS(C_QTY - S_QTY) < 0.001 THEN '2 차이 < 0.001 (소수 4자리 이하 차이)'
            ELSE '3 차이 >= 0.001 (컷오프 후 재계산·수정)' END CMP,
       COUNT(*) CNT,
       SUM(CASE WHEN C_QTY <> ROUND(C_QTY,3) THEN 1 ELSE 0 END) C_GT3,
       SUM(CASE WHEN S_QTY <> ROUND(S_QTY,3) THEN 1 ELSE 0 END) S_GT3,
       TO_CHAR(SUM(NVL(C_QTY,0) - NVL(S_QTY,0)),'FM999,999,999,999,990.0000000000') SUM_DIFF
  FROM J
 GROUP BY DIVISION_ID,
       CASE WHEN C_QTY IS NULL THEN '4 원장에만 있음(컷오프 후 생성)'
            WHEN S_QTY IS NULL THEN '5 _C 에만 있음(컷오프 후 삭제)'
            WHEN C_QTY = S_QTY THEN '1 동일'
            WHEN ABS(C_QTY - S_QTY) < 0.001 THEN '2 차이 < 0.001 (소수 4자리 이하 차이)'
            ELSE '3 차이 >= 0.001 (컷오프 후 재계산·수정)' END
 ORDER BY 1, 2;

PROMPT ################ [V4] ⭐ _C 대상버전 MKT_AMT_KRW 소수 3자리 초과 행 — 수량 × 단가 재계산 원인 판정 (최대 500행) ################
PROMPT   Q_QTY = 같은 버전 _C 의 MKT_FCST 수량 · KRW/LOC 단가 = 현재 단가원장의 해당 주 시작일 값(40=CFM_SELLING_PRICE, 그 외=FUTURE_PRICE)
PROMPT   P_CNT > 1 = 같은 키에 단가가 여러 건(40 은 PROJECT_CODE 별 판가가 END_CUSTOMER 로 합쳐짐) · LOCxFX = ROUND 없이 LOC 단가 × 월 환율
PROMPT   RECALC = TO-BE 식 ROUND(수량x단가,5) · ASIS_STR = AS-IS 식 CAST(STR(수량x단가,20,5)) 재현(float 경유) · IMPLIED_PRICE = 금액/수량(기록 당시 단가 추정)
WITH LAST_RUN AS (SELECT MAX(CREATION_DATE) MAX_CD FROM DM_MST_VERSION WHERE VERSION_TYPE = 'SP_D'),
TV AS (SELECT DIVISION_ID, VERSION_NO
         FROM (SELECT V.DIVISION_ID, V.VERSION_NO,
                      ROW_NUMBER() OVER (PARTITION BY V.DIVISION_ID ORDER BY V.CREATION_DATE DESC, V.VERSION_NO DESC) RN
                 FROM DM_MST_VERSION V, LAST_RUN L
                WHERE V.VERSION_TYPE = 'SP_D' AND V.CREATION_DATE >= L.MAX_CD - 1)
        WHERE RN = 1),
AMT AS (SELECT A.*, CAL.BASIS_START_DATE WEEK_START
          FROM DM_PLN_SALES_PLAN_C A, TV, SCM_SYS_CALENDAR_M CAL
         WHERE A.DIVISION_ID = TV.DIVISION_ID AND A.VERSION_NO = TV.VERSION_NO AND A.MEASURE = 'MKT_AMT_KRW'
           AND A.SCM_SITE_ID NOT IN ('acer_CN_CKG') AND A.ITEM_ID NOT IN ('MPCHPPHS042C')
           AND A.QTY <> ROUND(A.QTY,3)
           AND CAL.BASIS_YYYYMMDD(+) = A.YYYYMMDD),
QF AS (SELECT Q.DIVISION_ID, Q.PROJECT_CODE, Q.SCM_SITE_ID, Q.ITEM_ID, Q.DOM_EXP, Q.FCST_TYPE, Q.INCOTERMS,
              Q.PLANT_SITE_ID, Q.CELL_PROD_SITE_ID, Q.YYYYMMDD, Q.QTY
         FROM DM_PLN_SALES_PLAN_C Q, TV
        WHERE Q.DIVISION_ID = TV.DIVISION_ID AND Q.VERSION_NO = TV.VERSION_NO AND Q.MEASURE = 'MKT_FCST'),
PR AS (SELECT P.DIVISION_ID, P.END_CUSTOMER PROJECT_CODE, P.SCM_SITE_ID, P.ITEM_ID, P.DOM_EXP, P.FCST_TYPE, P.INCOTERMS,
              P.PLANT_SITE_ID, P.CELL_PROD_SITE_ID, P.YYYYMMDD, P.MEASURE,
              COUNT(*) P_CNT, MAX(P.PRICE) PRICE, MIN(P.PRICE) PRICE_MIN, MAX(P.CURRENCY) CURRENCY,
              MAX(P.LAST_UPDATED_BY) P_UPD_BY, MAX(P.LAST_UPDATE_DATE) P_UPD_DT, 'CFM_SELLING_PRICE' P_SRC
         FROM DM_PLN_CFM_SELLING_PRICE P
        WHERE P.DIVISION_ID = '40' AND P.MEASURE IN ('KRW','LOC')
          AND P.YYYYMMDD >= (SELECT NVL(MIN(WEEK_START),'99991231') FROM AMT WHERE DIVISION_ID = '40')
        GROUP BY P.DIVISION_ID, P.END_CUSTOMER, P.SCM_SITE_ID, P.ITEM_ID, P.DOM_EXP, P.FCST_TYPE, P.INCOTERMS,
                 P.PLANT_SITE_ID, P.CELL_PROD_SITE_ID, P.YYYYMMDD, P.MEASURE
       UNION ALL
       SELECT P.DIVISION_ID, P.PROJECT_CODE, P.SCM_SITE_ID, P.ITEM_ID, P.DOM_EXP, P.FCST_TYPE, P.INCOTERMS,
              P.PLANT_SITE_ID, '*' CELL_PROD_SITE_ID, P.YYYYMMDD, P.MEASURE,
              COUNT(*), MAX(P.PRICE), MIN(P.PRICE), MAX(P.CURRENCY),
              MAX(P.LAST_UPDATED_BY), MAX(P.LAST_UPDATE_DATE), 'FUTURE_PRICE'
         FROM SCM_MST_FUTURE_PRICE P
        WHERE P.DIVISION_ID <> '40' AND P.MEASURE IN ('KRW','LOC')
          AND P.DIVISION_ID IN (SELECT DIVISION_ID FROM AMT)
          AND P.YYYYMMDD >= (SELECT NVL(MIN(WEEK_START),'99991231') FROM AMT WHERE DIVISION_ID <> '40')
        GROUP BY P.DIVISION_ID, P.PROJECT_CODE, P.SCM_SITE_ID, P.ITEM_ID, P.DOM_EXP, P.FCST_TYPE, P.INCOTERMS,
                 P.PLANT_SITE_ID, P.YYYYMMDD, P.MEASURE),
T AS (SELECT A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.DOM_EXP, A.FCST_TYPE, A.INCOTERMS,
             A.PLANT_SITE_ID, A.CELL_PROD_SITE_ID, A.YYYYMMDD, A.WEEK_START, A.CURRENCY AMT_CUR,
             A.QTY AMT, A.LAST_UPDATED_BY A_UPD_BY, A.LAST_UPDATE_DATE A_UPD_DT,
             Q.QTY Q_QTY,
             K.PRICE KRW_PRICE, K.PRICE_MIN KRW_PRICE_MIN, K.P_CNT, K.CURRENCY K_CUR, K.P_UPD_BY, K.P_UPD_DT, K.P_SRC,
             L.PRICE LOC_PRICE, L.CURRENCY LOC_CUR
        FROM AMT A
        LEFT JOIN QF Q
          ON Q.DIVISION_ID = A.DIVISION_ID AND Q.PROJECT_CODE = A.PROJECT_CODE AND Q.SCM_SITE_ID = A.SCM_SITE_ID
         AND Q.ITEM_ID = A.ITEM_ID AND Q.DOM_EXP = A.DOM_EXP AND Q.FCST_TYPE = A.FCST_TYPE AND Q.INCOTERMS = A.INCOTERMS
         AND Q.PLANT_SITE_ID = A.PLANT_SITE_ID AND Q.CELL_PROD_SITE_ID = A.CELL_PROD_SITE_ID AND Q.YYYYMMDD = A.YYYYMMDD
        LEFT JOIN PR K
          ON K.MEASURE = 'KRW' AND K.DIVISION_ID = A.DIVISION_ID AND K.PROJECT_CODE = A.PROJECT_CODE AND K.SCM_SITE_ID = A.SCM_SITE_ID
         AND K.ITEM_ID = A.ITEM_ID AND K.DOM_EXP = A.DOM_EXP AND K.FCST_TYPE = A.FCST_TYPE AND K.INCOTERMS = A.INCOTERMS
         AND K.PLANT_SITE_ID = A.PLANT_SITE_ID AND K.YYYYMMDD = A.WEEK_START
         AND (K.CELL_PROD_SITE_ID = '*' OR K.CELL_PROD_SITE_ID = A.CELL_PROD_SITE_ID)
        LEFT JOIN PR L
