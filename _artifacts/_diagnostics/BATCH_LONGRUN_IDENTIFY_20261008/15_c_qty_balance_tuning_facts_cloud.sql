     , B.BASIS_YYYYMMDD AS YYYYMMDD
     , CASE WHEN A.DIVISION_ID = '40' THEN
                CASE WHEN B.BASIS_YYYYMMDD = '20261005' AND A.MEASURE IN ('Vmi_In_Plan')
                     THEN NVL(C.QTY, 0) + NVL((SELECT SUM(S.QTY) FROM SCM_MGR.GT_DPMFCQB_FP_STOCK_QTY S WHERE S.SCM_SITE_ID = A.SCM_SITE_ID AND S.DIVISION_ID = A.DIVISION_ID AND S.ITEM_ID LIKE (CASE WHEN SUBSTR(A.ITEM_ID, 1, 2) = 'MP' THEN SUBSTR(A.ITEM_ID, 1, 11) ELSE A.ITEM_ID END) || '%'), 0)
                     ELSE NVL(C.QTY, 0) END
            ELSE
                CASE WHEN B.BASIS_YYYYMMDD = '20261005' AND A.MEASURE IN ('Vmi_In_Plan')
                     THEN NVL(C.QTY, 0) + NVL((SELECT SUM(S.QTY) FROM SCM_MGR.GT_DPMFCQB_FP_STOCK_QTY S WHERE S.SCM_SITE_ID = A.SCM_SITE_ID AND S.DIVISION_ID = A.DIVISION_ID AND S.ITEM_ID = A.ITEM_ID), 0)
                     ELSE NVL(C.QTY, 0) END
       END AS QTY
     , A.CELL_PROD_SITE_ID, A.FROM_SITE_ID
  FROM (SELECT DISTINCT W.DIVISION_ID, W.PROJECT_CODE, W.SCM_SITE_ID, W.ITEM_ID, W.DOM_EXP, W.FCST_TYPE, W.INCOTERMS, W.MEASURE, W.PLANT_SITE_ID, W.CELL_PROD_SITE_ID, W.ATTRIBUTE2 AS FROM_SITE_ID, W.END_CUSTOMER
          FROM SCM_MGR.DM_PLN_CFM_MKT_DEMAND_PLAN_C W
          INNER JOIN SCM_MGR.SCM_MST_SITE ST ON W.DIVISION_ID = ST.DIVISION_ID AND W.SCM_SITE_ID = ST.SCM_SITE_ID AND ST.VMI_YN = 'Y'
           AND W.DIVISION_ID = '40' AND W.VERSION_NO = 'MF_W_20261005_V001' AND W.CUTOFF_TYPE = 'MF_W' AND W.CUTOFF_YYYYMMDD = '20261005'
           AND W.CUTOFF_YYYYMMDD_DATE = TO_DATE('20261005', 'YYYYMMDD')                       /* ★ 추가: 파티션 키 */
         WHERE W.YYYYMMDD BETWEEN '20261005' AND TO_CHAR(TO_DATE('20261005', 'YYYYMMDD') + 54 * 7, 'YYYYMMDD')) A
  INNER JOIN SCM_MGR.SCM_SYS_CALENDAR_M B ON B.BASIS_YYYYMMDD BETWEEN '20261005' AND TO_CHAR(TO_DATE('20261005', 'YYYYMMDD') + 54 * 7, 'YYYYMMDD')
  LEFT JOIN SCM_MGR.DM_PLN_CFM_MKT_DEMAND_PLAN_C C
    ON A.DIVISION_ID = C.DIVISION_ID AND A.PROJECT_CODE = C.PROJECT_CODE AND A.SCM_SITE_ID = C.SCM_SITE_ID AND A.ITEM_ID = C.ITEM_ID AND A.DOM_EXP = C.DOM_EXP
   AND A.FCST_TYPE = C.FCST_TYPE AND A.INCOTERMS = C.INCOTERMS AND A.PLANT_SITE_ID = C.PLANT_SITE_ID AND A.MEASURE = C.MEASURE AND A.CELL_PROD_SITE_ID = C.CELL_PROD_SITE_ID
   AND A.END_CUSTOMER = C.END_CUSTOMER AND B.BASIS_YYYYMMDD = C.YYYYMMDD
   AND C.DIVISION_ID = '40' AND C.VERSION_NO = 'MF_W_20261005_V001' AND C.CUTOFF_TYPE = 'MF_W' AND C.CUTOFF_YYYYMMDD = '20261005'
   AND C.CUTOFF_YYYYMMDD_DATE = TO_DATE('20261005', 'YYYYMMDD')                               /* ★ 추가: 파티션 키 */
