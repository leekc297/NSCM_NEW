/* =====================================================================================================
 * 15 — 클라우드 실행용 (조회만 · 쓰기 0): C_QTY_BALANCE 회당 30초 목표 설계를 위한 **구조 사실 측정**
 *      14 K1~K6 (2026-10-08 14:04 실행 1초 ASH) 로 확정된 분포:
 *        C 회당 평균 169초 = ① _C BALANCE 삭제+재삽입 4문장 84초(49%) · ② VMI_MST_MAIN INSERT 43초(25%) · ③ GTT 초기화 DELETE 14~18초(2회차만) · ④ 기타 ≈25초
 *      사내(ZIOUI1) 에서 확인된 DDL 사실 (클라우드 동일 여부를 L1 로 확인):
 *        - DM_PLN_MKT_FCST_C / DM_PLN_CFM_MKT_DEMAND_PLAN_C = RANGE INTERVAL(7일) 파티션, 파티션 키 = 가상컬럼 CUTOFF_YYYYMMDD_DATE = TO_DATE("CUTOFF_YYYYMMDD",'YYYYMMDD')
 *        - SP 는 문자 CUTOFF_YYYYMMDD 로만 조건 → 파티션 프루닝 0 (K4 PARTITION RANGE ALL, Pstop 1048575). 사내 109 / 17 파티션
 *        - DM_PLN_MKT_FCST_C 인덱스 6개(PK + N1 + N3 + SUPPLY + SUPPLY_VERSION + IX03), 인덱스 합계 17.5GB > 테이블 6.9GB
 *        - GTT 22개 ON COMMIT PRESERVE ROWS(SYS$SESSION), 인덱스 0. GTT TRUNCATE 는 사내 실측으로 **COMMIT 유발 확인** → 부모 트랜잭션 설계상 사용 불가
 *      L2~L4 의 버전/일자 리터럴은 L0 결과로 맞춘다 (기본값: 40 / MF_W_20261005_V001 / SCM_FCST).
 * ===================================================================================================== */
SET SQLFORMAT ansiconsole
SET PAGESIZE 5000
SET LINESIZE 400
SET FEEDBACK ON
SET TIMING ON

/* ---------- L0. 파라미터 확인 — SP 가 쓰는 값 그대로 (C_CUTOFF_YYYYMMDD = DM_MST_VERSION.YYYYMMDD · 월요일 · 주차수) ---------- */
SELECT v.DIVISION_ID, v.VERSION_NO, v.YYYYMMDD AS cutoff_yyyymmdd
     , TO_CHAR(SCM_MGR.FN_NEXT_DAY(TO_DATE(v.YYYYMMDD, 'YYYYMMDD'), 'MON') - 7, 'YYYYMMDD') AS plan_start_mon
     , SUBSTR(v.VERSION_NO, 1, 4) AS cutoff_type
     , NVL((SELECT ATTRIBUTE1 FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = 'DM_LONG_PLAN_WEEK_CNT' AND VALID_YN = 'Y' AND SEGMENT1 = v.DIVISION_ID), '54(default)') AS plan_week_cnt
  FROM SCM_MGR.DM_MST_VERSION v
 WHERE v.DIVISION_ID = '40' AND v.VERSION_NO IN ('MF_W_20261005_V001', 'SF_W_20261005_V001', 'MF_W_20260928_V001');


/* ---------- L1. 클라우드 DDL 사실 — 파티션 키·가상컬럼 식·파티션 수·병렬도·인덱스 (사내와 동일한지) ---------- */
SELECT t.table_name, t.partitioning_type, t.interval, k.column_name AS part_key
     , (SELECT COUNT(*) FROM all_tab_partitions p WHERE p.table_owner = t.owner AND p.table_name = t.table_name) AS parts
     , TRIM((SELECT degree FROM all_tables a WHERE a.owner = t.owner AND a.table_name = t.table_name)) AS degree_
     , (SELECT num_rows FROM all_tables a WHERE a.owner = t.owner AND a.table_name = t.table_name) AS num_rows
  FROM all_part_tables t JOIN all_part_key_columns k ON k.owner = t.owner AND k.name = t.table_name AND k.object_type = 'TABLE'
 WHERE t.owner = 'SCM_MGR' AND t.table_name IN ('DM_PLN_MKT_FCST_C', 'DM_PLN_CFM_MKT_DEMAND_PLAN_C')
 ORDER BY 1;

-- L1-b. 가상컬럼 식 (기대: TO_DATE("CUTOFF_YYYYMMDD",'YYYYMMDD') · VIRTUAL=YES). 식이 다르면 L3/L4 의 추가 조건을 그 식에 맞춘다
SELECT c.table_name, c.column_name, c.data_type, c.virtual_column, c.nullable
     , EXTRACTVALUE(DBMS_XMLGEN.GETXMLTYPE('SELECT data_default FROM all_tab_cols WHERE owner = ''SCM_MGR'' AND table_name = ''' || c.table_name || ''' AND column_name = ''CUTOFF_YYYYMMDD_DATE'''), '/ROWSET/ROW/DATA_DEFAULT') AS expr
  FROM all_tab_cols c
 WHERE c.owner = 'SCM_MGR' AND c.table_name IN ('DM_PLN_MKT_FCST_C', 'DM_PLN_CFM_MKT_DEMAND_PLAN_C') AND c.column_name = 'CUTOFF_YYYYMMDD_DATE';

-- L1-c. 인덱스 목록·크기 (삭제/재삽입 42만 행 × 인덱스 수 = ① 비용의 본질)
SELECT i.table_name, i.index_name, i.uniqueness, i.leaf_blocks, i.distinct_keys
     , (SELECT ROUND(SUM(bytes) / 1048576) FROM dba_segments s WHERE s.owner = i.owner AND s.segment_name = i.index_name) AS mb
     , (SELECT LISTAGG(column_name, ',') WITHIN GROUP (ORDER BY column_position) FROM all_ind_columns ic WHERE ic.index_owner = i.owner AND ic.index_name = i.index_name) AS cols
  FROM all_indexes i
 WHERE i.owner = 'SCM_MGR' AND i.table_name IN ('DM_PLN_MKT_FCST_C', 'DM_PLN_CFM_MKT_DEMAND_PLAN_C')
 ORDER BY 1, 2;

-- L1-d. 인덱스 사용 이력 (19c DBA_INDEX_USADE) — 접근 0 인 인덱스가 있으면 ① 의 인덱스 유지비 축소 후보(결정은 사용자)
SELECT u.name, u.total_access_count, u.total_exec_count, u.total_rows_returned, TO_CHAR(u.last_used, 'YYYY-MM-DD') AS last_used
  FROM dba_index_usage u
 WHERE u.owner = 'SCM_MGR'
   AND u.name IN (SELECT index_name FROM all_indexes WHERE owner = 'SCM_MGR' AND table_name IN ('DM_PLN_MKT_FCST_C', 'DM_PLN_CFM_MKT_DEMAND_PLAN_C'))
 ORDER BY 1;

-- L1-e. 최신 파티션 통계 (K4 E-Rows=1 의 원인 확인: 이번 주 파티션 num_rows 가 실제와 동떨어지면 NL + CARTESIAN 선택의 근거가 된다)
SELECT p.table_name, p.partition_name, p.partition_position, p.num_rows, TO_CHAR(p.last_analyzed, 'MM-DD HH24:MI') AS last_analyzed
  FROM all_tab_partitions p
 WHERE p.table_owner = 'SCM_MGR' AND p.table_name IN ('DM_PLN_MKT_FCST_C', 'DM_PLN_CFM_MKT_DEMAND_PLAN_C')
   AND p.partition_position >= (SELECT MAX(partition_position) - 3 FROM all_tab_partitions p2 WHERE p2.table_owner = p.table_owner AND p2.table_name = p.table_name)
 ORDER BY 1, 3;


/* ---------- L2. ② VMI INSERT 의 탐색 부피 — W(기준행) × 달력일 × 파티션 수 = PK 탐색 횟수 (K5: 2회 1억 854만 버퍼, 출력 1만 4천 행) ---------- */
WITH p AS (SELECT '40' AS div, 'MF_W_20261005_V001' AS ver, 'MF_W' AS ctype, '20261005' AS cutoff, '20261005' AS mon, 54 AS wk, 'SCM_FCST' AS msr FROM dual)
SELECT (SELECT COUNT(*) FROM SCM_MGR.DM_PLN_CFM_MKT_DEMAND_PLAN_C w, p
         WHERE w.DIVISION_ID = p.div AND w.VERSION_NO = p.ver AND w.CUTOFF_TYPE = p.ctype AND w.CUTOFF_YYYYMMDD = p.cutoff) AS c_rows_version
     , (SELECT COUNT(*) FROM SCM_MGR.DM_PLN_CFM_MKT_DEMAND_PLAN_C w JOIN SCM_MGR.SCM_MST_SITE st ON st.DIVISION_ID = w.DIVISION_ID AND st.SCM_SITE_ID = w.SCM_SITE_ID AND st.VMI_YN = 'Y', p
         WHERE w.DIVISION_ID = p.div AND w.VERSION_NO = p.ver AND w.CUTOFF_TYPE = p.ctype AND w.CUTOFF_YYYYMMDD = p.cutoff
           AND w.YYYYMMDD BETWEEN p.mon AND TO_CHAR(TO_DATE(p.mon, 'YYYYMMDD') + p.wk * 7, 'YYYYMMDD')
           AND w.MEASURE IN (p.msr, 'Vmi_In_Plan')) AS w_rows_vmi_filtered
     , (SELECT COUNT(*) FROM (SELECT DISTINCT w.DIVISION_ID, w.PROJECT_CODE, w.SCM_SITE_ID, w.ITEM_ID, w.DOM_EXP, w.FCST_TYPE, w.INCOTERMS, w.MEASURE, w.PLANT_SITE_ID, w.CELL_PROD_SITE_ID, w.ATTRIBUTE2, w.END_CUSTOMER
                                 FROM SCM_MGR.DM_PLN_CFM_MKT_DEMAND_PLAN_C w JOIN SCM_MGR.SCM_MST_SITE st ON st.DIVISION_ID = w.DIVISION_ID AND st.SCM_SITE_ID = w.SCM_SITE_ID AND st.VMI_YN = 'Y', p
                                WHERE w.DIVISION_ID = p.div AND w.VERSION_NO = p.ver AND w.CUTOFF_TYPE = p.ctype AND w.CUTOFF_YYYYMMDD = p.cutoff
                                  AND w.YYYYMMDD BETWEEN p.mon AND TO_CHAR(TO_DATE(p.mon, 'YYYYMMDD') + p.wk * 7, 'YYYYMMDD')
                                  AND w.MEASURE IN (p.msr, 'Vmi_In_Plan'))) AS a_distinct_rows
     , (SELECT COUNT(*) FROM SCM_MGR.SCM_SYS_CALENDAR_M b, p WHERE b.BASIS_YYYYMMDD BETWEEN p.mon AND TO_CHAR(TO_DATE(p.mon, 'YYYYMMDD') + p.wk * 7, 'YYYYMMDD')) AS calendar_days
     , (SELECT COUNT(*) FROM all_tab_partitions WHERE table_owner = 'SCM_MGR' AND table_name = 'DM_PLN_CFM_MKT_DEMAND_PLAN_C') AS parts_probed_each
  FROM dual;
-- 해석: PK 탐색 ≈ a_distinct_rows × calendar_days, 각 탐색이 parts_probed_each 파티션의 로컬 인덱스를 전부 두드린다. 파티션 키 조건을 넣으면 1 파티션만.


/* ---------- L3. ② 실행계획 비교 — (a) SP 원문 그대로 vs (b) 파티션 키 조건(가상컬럼) 추가. 결과 동치는 L4 로 확인 ---------- */
