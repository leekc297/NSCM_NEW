/* ---------- L5. ① BALANCE 전량 삭제+재삽입(42.6만 → 37.7만) 을 "차이분만 반영" 으로 바꿀 수 있는가 — 변화율 측정 ---------- */
-- L5-a. 대리 지표: 이번 주 MF_W BALANCE vs 지난 주 MF_W BALANCE 를 키 단위로 비교 (주간 변화 ≥ 일간 변화이므로 보수적 상한)
WITH cur AS (SELECT PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, YYYYMMDD, QTY
               FROM SCM_MGR.DM_PLN_MKT_FCST_C WHERE DIVISION_ID = '40' AND VERSION_NO = 'MF_W_20261005_V001' AND CUTOFF_TYPE = 'MF_W' AND CUTOFF_YYYYMMDD = '20261005'
                AND CUTOFF_YYYYMMDD_DATE = TO_DATE('20261005', 'YYYYMMDD') AND MEASURE = 'BALANCE')
   , prv AS (SELECT PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, YYYYMMDD, QTY
               FROM SCM_MGR.DM_PLN_MKT_FCST_C WHERE DIVISION_ID = '40' AND VERSION_NO = 'MF_W_20260928_V001' AND CUTOFF_TYPE = 'MF_W' AND CUTOFF_YYYYMMDD = '20260928'
                AND CUTOFF_YYYYMMDD_DATE = TO_DATE('20260928', 'YYYYMMDD') AND MEASURE = 'BALANCE')
SELECT SUM(CASE WHEN c.QTY IS NOT NULL AND p.QTY IS NOT NULL AND c.QTY = p.QTY THEN 1 ELSE 0 END) AS same_qty
     , SUM(CASE WHEN c.QTY IS NOT NULL AND p.QTY IS NOT NULL AND c.QTY <> p.QTY THEN 1 ELSE 0 END) AS diff_qty
     , SUM(CASE WHEN p.QTY IS NULL THEN 1 ELSE 0 END) AS only_in_cur
     , SUM(CASE WHEN c.QTY IS NULL THEN 1 ELSE 0 END) AS only_in_prv
     , COUNT(*) AS total_keys
  FROM cur c FULL OUTER JOIN prv p
    ON p.PROJECT_CODE = c.PROJECT_CODE AND p.SCM_SITE_ID = c.SCM_SITE_ID AND p.ITEM_ID = c.ITEM_ID AND p.DOM_EXP = c.DOM_EXP AND p.FCST_TYPE = c.FCST_TYPE
   AND p.INCOTERMS = c.INCOTERMS AND p.PLANT_SITE_ID = c.PLANT_SITE_ID AND p.YYYYMMDD = c.YYYYMMDD;
