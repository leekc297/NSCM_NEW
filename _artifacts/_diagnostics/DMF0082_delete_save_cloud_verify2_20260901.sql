  SELECT 'cellProdSiteId','VARCHAR','IN',12 FROM DUAL UNION ALL
  SELECT 'yyyymmdd','VARCHAR','IN',13 FROM DUAL UNION ALL
  SELECT 'currency','VARCHAR','IN',14 FROM DUAL UNION ALL
