  SELECT 12,'P_CELL_PROD_SITE_ID','VARCHAR2' FROM DUAL UNION ALL
  SELECT 13,'P_YYYYMMDD','VARCHAR2' FROM DUAL UNION ALL
  SELECT 14,'P_CURRENCY','VARCHAR2' FROM DUAL UNION ALL
  SELECT 15,'P_QTY','VARCHAR2' FROM DUAL UNION ALL
  SELECT 16,'P_CREATED_BY','VARCHAR2' FROM DUAL UNION ALL
