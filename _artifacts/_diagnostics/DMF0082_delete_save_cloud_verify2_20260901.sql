    FROM SCM_MGR.SCM_ADM_PROC_M
   WHERE PROC_NM = 'PKG_DMF0082.P_DMF0082_SAVE_MAIN_DATA'
  MINUS SELECT '클라우드에만', COL_NM, TP, IO, ORD FROM EXPW
) UNION ALL
SELECT '§7 배선차이', SRC, COL_NM, TP, IO, ORD FROM (
  SELECT '기대(사내)에만' AS SRC, COL_NM, TP, IO, ORD FROM EXPW
  MINUS
  SELECT '기대(사내)에만', COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD
    FROM SCM_MGR.SCM_ADM_PROC_M
   WHERE PROC_NM = 'PKG_DMF0082.P_DMF0082_SAVE_MAIN_DATA'
