-- §8. 32K 바인드 한계 축 — 오늘 발생분만 (로그 테이블 볼륨 큼 — 전 기간 스캔 금지, 2026-09-01 축소).
--     판독: 실패(ERR) 건만 32,767 초과이고 성공(OK — 신규 소량 저장) 건은 작으면 (B) 확정 계보.
SELECT '§8 payload크기(오늘)' AS SECTION, EXECUTE_TIME,
       CASE WHEN EXCEPTION IS NULL THEN 'OK' ELSE 'ERR' END AS ST,
       DBMS_LOB.GETLENGTH(PARAMS) AS PARAMS_LEN, ELAPSED_MS
  FROM SCM_MGR.SCM_COM_SQL_LOG
 WHERE UPPER(PARAMS) LIKE '%SAVE_MAIN_DATA%'
   AND EXECUTE_TIME >= TRUNC(SYSDATE)
 ORDER BY EXECUTE_TIME DESC
 FETCH FIRST 20 ROWS ONLY;
