SELECT '§6 시그니처차이' AS SECTION, SRC, POS, ARG, TP FROM (
  SELECT '클라우드에만' AS SRC, POSITION AS POS, ARGUMENT_NAME AS ARG, DATA_TYPE AS TP
    FROM ALL_ARGUMENTS
   WHERE OWNER='SCM_MGR' AND PACKAGE_NAME='PKG_DMF0082' AND OBJECT_NAME='P_DMF0082_SAVE_MAIN_DATA'
  MINUS SELECT '클라우드에만', POS, ARG, TP FROM EXP
) UNION ALL
SELECT '§6 시그니처차이', SRC, POS, ARG, TP FROM (
  SELECT '기대(사내)에만' AS SRC, POS, ARG, TP FROM EXP
  MINUS
  SELECT '기대(사내)에만', POSITION, ARGUMENT_NAME, DATA_TYPE
    FROM ALL_ARGUMENTS
   WHERE OWNER='SCM_MGR' AND PACKAGE_NAME='PKG_DMF0082' AND OBJECT_NAME='P_DMF0082_SAVE_MAIN_DATA'
