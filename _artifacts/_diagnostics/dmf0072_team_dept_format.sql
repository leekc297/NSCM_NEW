PROMPT === [1] SCM_MST_SITE.DEPT_ID sample (DIV=40, SALES, NOT NULL, 20행) ===
SELECT * FROM (
  SELECT DISTINCT DEPT_ID
    FROM SCM_MGR.SCM_MST_SITE
   WHERE SITE_TYPE='SALES' AND DEPT_ID IS NOT NULL AND DIVISION_ID='40'
   ORDER BY DEPT_ID
) WHERE ROWNUM <= 20;

PROMPT === [2] SCM_MST_SSO_DEPT_INFO.DEPT_ID sample (20행) ===
SELECT * FROM (
  SELECT DEPT_ID, DEPT_NAME_KO
    FROM SCM_MGR.SCM_MST_SSO_DEPT_INFO
   ORDER BY DEPT_ID
) WHERE ROWNUM <= 20;

PROMPT === [3] DEPT_ID 길이 분포 비교 (양쪽 테이블) ===
SELECT 'SITE.DEPT_ID' AS T, LENGTH(DEPT_ID) AS LEN, COUNT(*) AS CNT
  FROM SCM_MGR.SCM_MST_SITE WHERE DEPT_ID IS NOT NULL
 GROUP BY LENGTH(DEPT_ID) ORDER BY 2;

SELECT 'DEPT.DEPT_ID' AS T, LENGTH(DEPT_ID) AS LEN, COUNT(*) AS CNT
  FROM SCM_MGR.SCM_MST_SSO_DEPT_INFO
 GROUP BY LENGTH(DEPT_ID) ORDER BY 2;

PROMPT === [4] EXISTS 매칭 시도 — LEFT/RIGHT trim 적용 ===
SELECT 'Direct match' AS K, COUNT(*) AS CNT
  FROM SCM_MGR.SCM_MST_SITE A
 WHERE A.SITE_TYPE='SALES' AND A.DEPT_ID IS NOT NULL
   AND EXISTS (SELECT 1 FROM SCM_MGR.SCM_MST_SSO_DEPT_INFO B WHERE B.DEPT_ID=A.DEPT_ID);

SELECT 'TRIM match' AS K, COUNT(*) AS CNT
  FROM SCM_MGR.SCM_MST_SITE A
 WHERE A.SITE_TYPE='SALES' AND A.DEPT_ID IS NOT NULL
   AND EXISTS (SELECT 1 FROM SCM_MGR.SCM_MST_SSO_DEPT_INFO B WHERE TRIM(B.DEPT_ID)=TRIM(A.DEPT_ID));

PROMPT === [5] SCM_MST_SITE.DEPT_ID 의 distinct 갯수 ===
SELECT 'SITE distinct DEPT_ID' AS K, COUNT(DISTINCT DEPT_ID) AS CNT FROM SCM_MGR.SCM_MST_SITE WHERE DEPT_ID IS NOT NULL;

