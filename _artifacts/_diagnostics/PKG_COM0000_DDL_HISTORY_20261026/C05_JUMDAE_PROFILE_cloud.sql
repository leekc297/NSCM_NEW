PROMPT ================= §1 신원 정보 — OS 계정 · PC · 접속 IP · DB 계정 · 프로그램 =================
PROMPT  WORK_TYPE : 사람(GUI 도구) / AI·자동화 추정(스크립트 런타임) / 구분 불가
SELECT A.OS_USERNAME, A.USERHOST
     , REGEXP_SUBSTR(A.AUTHENTICATION_TYPE, 'HOST=([0-9A-Fa-f.:]+)', 1, 1, NULL, 1) AS CLIENT_IP
     , A.TERMINAL, A.DBUSERNAME
     , SUBSTR(A.CLIENT_PROGRAM_NAME,1,62) AS PROGRAM
     , CASE WHEN UPPER(A.CLIENT_PROGRAM_NAME) LIKE '%PYTHON%' OR UPPER(A.CLIENT_PROGRAM_NAME) LIKE '%POWERSHELL%'
              OR UPPER(A.CLIENT_PROGRAM_NAME) LIKE '%NODE%' THEN 'AI·자동화 추정(스크립트)'
            WHEN UPPER(A.CLIENT_PROGRAM_NAME) LIKE '%DBEAVER%' OR UPPER(A.CLIENT_PROGRAM_NAME) LIKE '%SQL DEVELOPER%'
              OR UPPER(A.CLIENT_PROGRAM_NAME) LIKE '%TOAD%' OR UPPER(A.CLIENT_PROGRAM_NAME) LIKE '%ORANGE%' THEN '사람(GUI 도구)'
            ELSE '구분 불가' END AS WORK_TYPE
     , TO_CHAR(MIN(A.EVENT_TIMESTAMP),'YYYY-MM-DD HH24:MI:SS') AS T_FIRST
     , TO_CHAR(MAX(A.EVENT_TIMESTAMP),'YYYY-MM-DD HH24:MI:SS') AS T_LAST
     , COUNT(*) AS CNT
  FROM UNIFIED_AUDIT_TRAIL A
 WHERE UPPER(A.OS_USERNAME) LIKE '%JUMDAE%' OR UPPER(A.USERHOST) LIKE '%LESP03D5114%'
 GROUP BY A.OS_USERNAME, A.USERHOST
        , REGEXP_SUBSTR(A.AUTHENTICATION_TYPE, 'HOST=([0-9A-Fa-f.:]+)', 1, 1, NULL, 1)
        , A.TERMINAL, A.DBUSERNAME, SUBSTR(A.CLIENT_PROGRAM_NAME,1,62)
        , CASE WHEN UPPER(A.CLIENT_PROGRAM_NAME) LIKE '%PYTHON%' OR UPPER(A.CLIENT_PROGRAM_NAME) LIKE '%POWERSHELL%'
                 OR UPPER(A.CLIENT_PROGRAM_NAME) LIKE '%NODE%' THEN 'AI·자동화 추정(스크립트)'
               WHEN UPPER(A.CLIENT_PROGRAM_NAME) LIKE '%DBEAVER%' OR UPPER(A.CLIENT_PROGRAM_NAME) LIKE '%SQL DEVELOPER%'
                 OR UPPER(A.CLIENT_PROGRAM_NAME) LIKE '%TOAD%' OR UPPER(A.CLIENT_PROGRAM_NAME) LIKE '%ORANGE%' THEN '사람(GUI 도구)'
               ELSE '구분 불가' END
 ORDER BY MIN(A.EVENT_TIMESTAMP);

