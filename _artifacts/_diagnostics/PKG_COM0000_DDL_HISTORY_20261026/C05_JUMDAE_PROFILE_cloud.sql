PROMPT ================= §3 일자별 활동 (언제 무엇을 몇 건) =================
SELECT TO_CHAR(A.EVENT_TIMESTAMP,'YYYY-MM-DD') AS DAY
     , A.DBUSERNAME, A.ACTION_NAME
     , CASE WHEN UPPER(A.CLIENT_PROGRAM_NAME) LIKE '%PYTHON%' THEN 'AI·자동화 추정(python)'
            WHEN UPPER(A.CLIENT_PROGRAM_NAME) LIKE '%DBEAVER%' OR UPPER(A.CLIENT_PROGRAM_NAME) LIKE '%SQL DEVELOPER%' THEN '사람(GUI 도구)'
            ELSE '구분 불가' END AS WORK_TYPE
     , TO_CHAR(MIN(A.EVENT_TIMESTAMP),'HH24:MI:SS') || '~' || TO_CHAR(MAX(A.EVENT_TIMESTAMP),'HH24:MI:SS') AS T_FIRST
     , COUNT(*) AS CNT, COUNT(DISTINCT A.OBJECT_NAME) AS OBJ_CNT
     , SUM(CASE WHEN A.RETURN_CODE <> 0 THEN 1 ELSE 0 END) AS FAIL_CNT
  FROM UNIFIED_AUDIT_TRAIL A
 WHERE UPPER(A.OS_USERNAME) LIKE '%JUMDAE%' OR UPPER(A.USERHOST) LIKE '%LESP03D5114%'
 GROUP BY TO_CHAR(A.EVENT_TIMESTAMP,'YYYY-MM-DD'), A.DBUSERNAME, A.ACTION_NAME
        , CASE WHEN UPPER(A.CLIENT_PROGRAM_NAME) LIKE '%PYTHON%' THEN 'AI·자동화 추정(python)'
               WHEN UPPER(A.CLIENT_PROGRAM_NAME) LIKE '%DBEAVER%' OR UPPER(A.CLIENT_PROGRAM_NAME) LIKE '%SQL DEVELOPER%' THEN '사람(GUI 도구)'
               ELSE '구분 불가' END
 ORDER BY 1, MIN(A.EVENT_TIMESTAMP);

PROMPT ================= §4 작업한 객체 (DDL 대상 · 같은 배포 묶음 파악) =================
SELECT A.OBJECT_SCHEMA || '.' || A.OBJECT_NAME AS OBJ, A.ACTION_NAME
     , TO_CHAR(MIN(A.EVENT_TIMESTAMP),'YYYY-MM-DD HH24:MI:SS') AS T_FIRST
     , TO_CHAR(MAX(A.EVENT_TIMESTAMP),'YYYY-MM-DD HH24:MI:SS') AS T_LAST
     , COUNT(*) AS CNT
  FROM UNIFIED_AUDIT_TRAIL A
 WHERE (UPPER(A.OS_USERNAME) LIKE '%JUMDAE%' OR UPPER(A.USERHOST) LIKE '%LESP03D5114%')
   AND A.OBJECT_NAME IS NOT NULL
   AND (A.ACTION_NAME LIKE 'CREATE%' OR A.ACTION_NAME LIKE 'ALTER%' OR A.ACTION_NAME LIKE 'DROP%'
        OR A.ACTION_NAME IN ('GRANT','REVOKE','TRUNCATE TABLE'))
 GROUP BY A.OBJECT_SCHEMA || '.' || A.OBJECT_NAME, A.ACTION_NAME
 ORDER BY MIN(A.EVENT_TIMESTAMP);

PROMPT ================= §5 ⭐ AI 작업 흔적 — DDL 원문 속 AI 작업 마커 / 생성기 표식 =================
PROMPT  AI_MARKER : [E2026xxxx-...] 작업 마커 · SOURCE-FRESH/FRESH-GATE 스탬프 · Claude/Generated/AUTO 표기
SELECT TO_CHAR(A.EVENT_TIMESTAMP,'YYYY-MM-DD HH24:MI:SS') AS T_FIRST
     , A.DBUSERNAME, A.ACTION_NAME, A.OBJECT_NAME AS OBJ
     , DBMS_LOB.SUBSTR(REGEXP_SUBSTR(A.SQL_TEXT,
         '(\[E20\d{6}[^]]{0,40}\]|SOURCE-FRESH[^' || CHR(10) || ']{0,40}|FRESH-GATE|CLAUDE[^' || CHR(10) || ']{0,30}|GENERATED BY[^' || CHR(10) || ']{0,30})', 1, 1, 'i'), 60, 1) AS AI_MARKER
  FROM UNIFIED_AUDIT_TRAIL A
 WHERE (UPPER(A.OS_USERNAME) LIKE '%JUMDAE%' OR UPPER(A.USERHOST) LIKE '%LESP03D5114%')
   AND A.SQL_TEXT IS NOT NULL
   AND REGEXP_INSTR(A.SQL_TEXT,
         '(\[E20\d{6}|SOURCE-FRESH|FRESH-GATE|CLAUDE|GENERATED BY)', 1, 1, 0, 'i') > 0
 ORDER BY A.EVENT_TIMESTAMP;

PROMPT  -- 5-2 PKG_COM0000 재배포(10-13 등) DDL 원문 머리 300자 (작성자·생성기 주석 확인용)
SELECT TO_CHAR(A.EVENT_TIMESTAMP,'YYYY-MM-DD HH24:MI:SS') AS T_FIRST, A.ACTION_NAME
     , REPLACE(REPLACE(DBMS_LOB.SUBSTR(A.SQL_TEXT, 300, 1), CHR(10), ' '), CHR(13), ' ') AS HEAD
  FROM UNIFIED_AUDIT_TRAIL A
 WHERE (UPPER(A.OS_USERNAME) LIKE '%JUMDAE%' OR UPPER(A.USERHOST) LIKE '%LESP03D5114%')
   AND UPPER(A.OBJECT_NAME) = 'PKG_COM0000'
   AND A.ACTION_NAME IN ('CREATE PACKAGE','CREATE PACKAGE BODY')
 ORDER BY A.EVENT_TIMESTAMP;

