    ELSIF V LIKE '%DATAGRIP%'  THEN RETURN '사람 — DataGrip 직접 실행';
    ELSIF V LIKE '%PLSQLDEV%' OR V LIKE '%PL/SQL DEVELOPER%' THEN RETURN '사람 — PL/SQL Developer 직접 실행';
    ELSIF V LIKE '%PYTHON%'    THEN RETURN 'AI·자동화 추정 — python 스크립트 실행' || V_PC;
    ELSIF V LIKE '%POWERSHELL%' OR V LIKE '%PWSH%' THEN RETURN 'AI·자동화 추정 — PowerShell 스크립트 실행' || V_PC;
    ELSIF V LIKE '%NODE%' OR V LIKE '%BASH%' OR V LIKE '%CMD.EXE%' THEN RETURN 'AI·자동화 추정 — 스크립트 런타임 실행' || V_PC;
    ELSIF V LIKE '%SQLPLUS%' AND UPPER(P_USR) = 'SYS' THEN
      RETURN '구분 불가 — DB 서버 콘솔 SYS sqlplus 스크립트 (DBA·배치 적용)';
    ELSIF V LIKE '%SQLPLUS%' OR V LIKE '%SQLCL%' OR V LIKE '%SQL.EXE%' THEN RETURN '구분 불가 — sqlplus/sqlcl 스크립트';
    ELSIF V LIKE '%JDBC%'      THEN RETURN '구분 불가 — JDBC 앱/도구';
    ELSIF TRIM(V) IS NULL      THEN RETURN '구분 불가 — 실행 프로그램 정보 없음';
    ELSE RETURN '구분 불가 — ' || SUBSTR(NVL(P_PROG, P_MOD), 1, 60);
    END IF;
  END;

  PROCEDURE ADD_SUM(S VARCHAR2) IS BEGIN N_SUM := N_SUM + 1; G_SUM(N_SUM) := SUBSTR(S, 1, 4000); END;
  PROCEDURE ADD_DET(S VARCHAR2) IS BEGIN N_DET := N_DET + 1; G_DET(N_DET) := SUBSTR(S, 1, 4000); END;

  FUNCTION NORM(S VARCHAR2) RETURN VARCHAR2 IS
  BEGIN
    RETURN SUBSTRB(REGEXP_REPLACE(TRIM(REPLACE(REPLACE(S, CHR(13)), CHR(9), ' ')), ' +', ' '), 1, 2000);
  END;

  -- 원문(CLOB)에서 대상 멤버 구간 추출 — BODY = 정의부(IS/AS)~다음 멤버 직전 / SPEC = 선언부~';'
  PROCEDURE GET_SEG(P_TXT IN CLOB, P_KIND IN VARCHAR2, O_SEG OUT VARCHAR2, O_TRUNC OUT BOOLEAN) IS
    V_FROM PLS_INTEGER; V_TO PLS_INTEGER; V_POS PLS_INTEGER;
  BEGIN
    O_SEG := NULL; O_TRUNC := FALSE;
    IF P_KIND = 'BODY' THEN
      V_FROM := REGEXP_INSTR(P_TXT, 'PROCEDURE\s+P_COM0003_GET_STORAGE_BY_DIVISION_POPUP\s*(\([^;]*?\))?\s*(IS|AS)\s', 1, 1, 0, 'in');
      IF V_FROM = 0 THEN RETURN; END IF;
      V_TO := REGEXP_INSTR(P_TXT, CHR(10) || '\s*(PROCEDURE|FUNCTION)\s+\w+', V_FROM + 10, 1, 0, 'in');
      IF V_TO = 0 THEN V_TO := DBMS_LOB.GETLENGTH(P_TXT) + 1; END IF;
    ELSE
      V_FROM := REGEXP_INSTR(P_TXT, 'PROCEDURE\s+P_COM0003_GET_STORAGE_BY_DIVISION_POPUP(\s|\()', 1, 1, 0, 'i');
      IF V_FROM = 0 THEN RETURN; END IF;
      V_TO := DBMS_LOB.INSTR(P_TXT, ';', V_FROM);
      IF V_TO = 0 THEN V_TO := DBMS_LOB.GETLENGTH(P_TXT); END IF;
      V_TO := V_TO + 1;
    END IF;
    V_POS := V_FROM;
    WHILE V_POS < V_TO LOOP
      BEGIN
        O_SEG := O_SEG || DBMS_LOB.SUBSTR(P_TXT, LEAST(1000, V_TO - V_POS), V_POS);  -- 한글 4000 단위 ORA-06502 회피
      EXCEPTION
        WHEN VALUE_ERROR THEN O_TRUNC := TRUE; EXIT;
      END;
      V_POS := V_POS + 1000;
    END LOOP;
  END;

  PROCEDURE SPLIT(P_S IN VARCHAR2, O_L OUT T_STR, O_N OUT PLS_INTEGER) IS
    V_P PLS_INTEGER := 1; V_E PLS_INTEGER; V_LINE VARCHAR2(4000);
  BEGIN
    O_N := 0;
    IF P_S IS NULL THEN RETURN; END IF;
    LOOP
      V_E := INSTR(P_S, CHR(10), V_P);
      V_LINE := NORM(SUBSTR(P_S, V_P, CASE WHEN V_E = 0 THEN LENGTH(P_S) - V_P + 1 ELSE V_E - V_P END));
      IF V_LINE IS NOT NULL THEN O_N := O_N + 1; O_L(O_N) := V_LINE; END IF;
      EXIT WHEN V_E = 0;
      V_P := V_E + 1;
    END LOOP;
  END;

  -- 줄 다중집합 비교: 이전에만 있는 줄 = '-' / 현재에만 있는 줄 = '+'
  PROCEDURE DIFF(P_L IN T_STR, P_N IN PLS_INTEGER, C_L IN T_STR, C_N IN PLS_INTEGER
               , O_ADD OUT PLS_INTEGER, O_DEL OUT PLS_INTEGER) IS
    PC T_CNT; CC T_CNT; K VARCHAR2(2000);
  BEGIN
    O_ADD := 0; O_DEL := 0;
    FOR I IN 1 .. P_N LOOP K := P_L(I); IF PC.EXISTS(K) THEN PC(K) := PC(K) + 1; ELSE PC(K) := 1; END IF; END LOOP;
    FOR I IN 1 .. C_N LOOP K := C_L(I); IF CC.EXISTS(K) THEN CC(K) := CC(K) + 1; ELSE CC(K) := 1; END IF; END LOOP;
    FOR I IN 1 .. P_N LOOP
      K := P_L(I);
      IF CC.EXISTS(K) AND CC(K) > 0 THEN CC(K) := CC(K) - 1;
      ELSE O_DEL := O_DEL + 1; ADD_DET('      - ' || K); END IF;
    END LOOP;
    FOR I IN 1 .. C_N LOOP
      K := C_L(I);
      IF PC.EXISTS(K) AND PC(K) > 0 THEN PC(K) := PC(K) - 1;
      ELSE
        O_ADD := O_ADD + 1; ADD_DET('      + ' || K);
        IF G_TAG_AI IS NULL THEN G_TAG_AI := REGEXP_SUBSTR(K, '\[E20\d{6}[^]]*\]'); END IF;
        IF G_TAG_H IS NULL THEN
          G_TAG_H := NVL(REGEXP_SUBSTR(K, '\[\d{4}[./-]\d{2}[./-]\d{2}\]\s*[A-Za-z]{2,6}')
                       , REGEXP_SUBSTR(K, '\d{2}\.\d{2}\.\d{2}\s+[A-Za-z]{2,6}'));
        END IF;
      END IF;
    END LOOP;
  END;

  PROCEDURE HANDLE_TEXT(P_TXT IN CLOB, P_KIND IN VARCHAR2, P_HDR IN VARCHAR2
                      , P_L IN OUT T_STR, P_N IN OUT PLS_INTEGER, O_WHAT OUT VARCHAR2) IS
    V_SEG VARCHAR2(32767); V_TRUNC BOOLEAN; C_L T_STR; C_N PLS_INTEGER;
    V_ADD PLS_INTEGER; V_DEL PLS_INTEGER; V_MARK PLS_INTEGER;
  BEGIN
    GET_SEG(P_TXT, P_KIND, V_SEG, V_TRUNC);
    IF V_SEG IS NULL THEN
      O_WHAT := '⚠ 대상 멤버 없음 — 전체본 교체로 멤버가 빠졌을 수 있음';
      P_L.DELETE; P_N := 0;
      RETURN;
    END IF;
    SPLIT(V_SEG, C_L, C_N);
    IF P_N = -1 THEN
      O_WHAT := '기준본 (기간 내 첫 원문 · 비교 대상 없음) · 멤버 ' || C_N || '줄';
    ELSIF P_N = 0 THEN
      O_WHAT := '★ 멤버 재등장 (직전 원문에는 없음) · ' || C_N || '줄';
    ELSE
      V_MARK := N_DET;
      ADD_DET(P_HDR);
      DIFF(P_L, P_N, C_L, C_N, V_ADD, V_DEL);
      IF V_ADD + V_DEL = 0 THEN
        N_DET  := V_MARK;
        O_WHAT := '멤버 변경 없음 (다른 멤버 수정 또는 동일본 재생성)';
      ELSE
        O_WHAT := '★ 멤버 변경 : -' || V_DEL || '줄 / +' || V_ADD || '줄 → [C] 상세';
      END IF;
    END IF;
    IF V_TRUNC THEN O_WHAT := O_WHAT || ' · 32KB 초과로 앞부분만 비교'; END IF;
    P_L := C_L; P_N := C_N;
  END;
BEGIN
  FOR R IN (
    WITH ASH AS (
      SELECT SQL_ID, SAMPLE_TIME, USER_ID, MACHINE, PROGRAM, MODULE, SQL_OPCODE, SESSION_ID, SESSION_SERIAL#, CURRENT_OBJ#
        FROM GV$ACTIVE_SESSION_HISTORY
       WHERE SQL_OPCODE BETWEEN 94 AND 99
      UNION ALL
      SELECT SQL_ID, SAMPLE_TIME, USER_ID, MACHINE, PROGRAM, MODULE, SQL_OPCODE, SESSION_ID, SESSION_SERIAL#, CURRENT_OBJ#
        FROM DBA_HIST_ACTIVE_SESS_HISTORY
       WHERE SQL_OPCODE BETWEEN 94 AND 99
         AND SAMPLE_TIME >= CAST(ADD_MONTHS(SYSDATE,-1) AS TIMESTAMP)
    ), G AS (
      SELECT SQL_ID, USER_ID, MACHINE, PROGRAM, MODULE, SQL_OPCODE, SESSION_ID, SESSION_SERIAL#
           , MIN(SAMPLE_TIME) AS T_FROM, MAX(SAMPLE_TIME) AS T_TO, MAX(CURRENT_OBJ#) AS OBJ_NO
        FROM ASH
       GROUP BY SQL_ID, USER_ID, MACHINE, PROGRAM, MODULE, SQL_OPCODE, SESSION_ID, SESSION_SERIAL#
    ), X AS (
      SELECT SQL_ID, SQL_TEXT
        FROM (SELECT T.SQL_ID, T.SQL_TEXT
                   , ROW_NUMBER() OVER (PARTITION BY T.SQL_ID ORDER BY T.DBID) AS RN
                FROM DBA_HIST_SQLTEXT T
               WHERE T.SQL_ID IN (SELECT SQL_ID FROM G))
       WHERE RN = 1
    ), SM AS (   -- ASH 세션(SID,SERIAL#)이 지금도 접속 중이면 그 OSUSER = 확정 근거
      SELECT SID, SERIAL#, MAX(OSUSER) AS OSU FROM GV$SESSION GROUP BY SID, SERIAL#
    ), HM AS (   -- PC(호스트) → OS 사용자 : 현재 세션 + 감사 기록 (도메인 접두 제거·대문자)
      SELECT H, MAX(OSU) AS OSU
        FROM (SELECT UPPER(REGEXP_SUBSTR(MACHINE, '[^\\]+$')) AS H, OSUSER AS OSU FROM GV$SESSION
              UNION ALL
              SELECT UPPER(REGEXP_SUBSTR(USERHOST, '[^\\]+$')), OS_USERNAME
                FROM UNIFIED_AUDIT_TRAIL
               WHERE EVENT_TIMESTAMP >= CAST(ADD_MONTHS(SYSDATE,-1) AS TIMESTAMP))
       WHERE H IS NOT NULL AND OSU IS NOT NULL
       GROUP BY H
    )
    SELECT 'AUDIT' AS SRC, CAST(A.EVENT_TIMESTAMP AS TIMESTAMP) AS TS, CAST(NULL AS TIMESTAMP) AS TS2
         , A.DBUSERNAME AS USR, A.OS_USERNAME AS OSU, A.USERHOST AS HOST
         , A.CLIENT_PROGRAM_NAME AS PROG, CAST(NULL AS VARCHAR2(64)) AS MDL, A.ACTION_NAME AS ACT
         , 'PKG_COM0000' AS OBJ, A.SQL_TEXT AS TXT
      FROM UNIFIED_AUDIT_TRAIL A
     WHERE A.EVENT_TIMESTAMP >= CAST(ADD_MONTHS(SYSDATE,-1) AS TIMESTAMP)
       AND UPPER(A.OBJECT_SCHEMA) = 'SCM_MGR'
       AND UPPER(A.OBJECT_NAME)   = 'PKG_COM0000'
       AND A.ACTION_NAME IN ('CREATE PACKAGE','CREATE PACKAGE BODY','ALTER PACKAGE','ALTER PACKAGE BODY'
                           , 'DROP PACKAGE','DROP PACKAGE BODY')
    UNION ALL
    SELECT 'AWR', CAST(G.T_FROM AS TIMESTAMP), CAST(G.T_TO AS TIMESTAMP)
         , U.USERNAME
         , NVL2(SM.OSU, SM.OSU || '(동일세션)', NVL2(HM.OSU, HM.OSU || '(PC기준)', NULL))
         , G.MACHINE, G.PROGRAM, G.MODULE, AA.NAME
         , 'PKG_COM0000', X.SQL_TEXT
      FROM G
      JOIN X ON X.SQL_ID = G.SQL_ID
      LEFT JOIN DBA_USERS U      ON U.USER_ID = G.USER_ID
      LEFT JOIN AUDIT_ACTIONS AA ON AA.ACTION = G.SQL_OPCODE
      LEFT JOIN SM ON SM.SID = G.SESSION_ID AND SM.SERIAL# = G.SESSION_SERIAL#
      LEFT JOIN HM ON HM.H = UPPER(REGEXP_SUBSTR(G.MACHINE, '[^\\]+$'))
     WHERE UPPER(REGEXP_SUBSTR(DBMS_LOB.SUBSTR(X.SQL_TEXT, 400, 1)
                 , 'PACKAGE\s+(BODY\s+)?("?\w+"?\.)?"?(\w+)', 1, 1, 'i', 3)) = 'PKG_COM0000'
    UNION ALL
    SELECT 'ASH', CAST(G.T_FROM AS TIMESTAMP), CAST(G.T_TO AS TIMESTAMP)
         , U.USERNAME
         , NVL2(SM.OSU, SM.OSU || '(동일세션)', NVL2(HM.OSU, HM.OSU || '(PC기준)', NULL))
         , G.MACHINE, G.PROGRAM, G.MODULE, AA.NAME
         , NVL(O.OBJECT_NAME, '(대상 미확인)'), TO_CLOB(NULL)
      FROM G
      LEFT JOIN DBA_USERS U      ON U.USER_ID   = G.USER_ID
      LEFT JOIN AUDIT_ACTIONS AA ON AA.ACTION   = G.SQL_OPCODE
      -- CURRENT_OBJ# 는 DDL 중 접근한 딕셔너리(USER$·KOTTD$ 등)일 수 있음 → 패키지일 때만 대상명으로 인정
      LEFT JOIN DBA_OBJECTS O    ON O.OBJECT_ID = G.OBJ_NO AND O.OBJECT_TYPE LIKE 'PACKAGE%'
      LEFT JOIN SM ON SM.SID = G.SESSION_ID AND SM.SERIAL# = G.SESSION_SERIAL#
      LEFT JOIN HM ON HM.H = UPPER(REGEXP_SUBSTR(G.MACHINE, '[^\\]+$'))
     WHERE NOT EXISTS (SELECT 1 FROM X WHERE X.SQL_ID = G.SQL_ID)
       AND (O.OBJECT_NAME IS NULL OR O.OBJECT_NAME = 'PKG_COM0000')
     ORDER BY 2
  ) LOOP
    N_EVT := N_EVT + 1;
    G_EVT(N_EVT) := CAST(R.TS AS DATE);
    G_TAG_H := NULL; G_TAG_AI := NULL;
    V_KIND := CASE WHEN R.ACT LIKE '%BODY%' THEN 'BODY' ELSE 'SPEC' END;
    V_HDR  := '#' || N_EVT || '  ' || TO_CHAR(R.TS,'YYYY-MM-DD HH24:MI:SS') || '  [' || R.SRC || '] '
           || R.ACT || '  누가=' || R.USR || ' / OS=' || NVL(R.OSU,'-') || ' / PC=' || NVL(R.HOST,'-')
           || ' / ' || NVL(SUBSTR(R.PROG,1,40),'-');

    IF R.TXT IS NULL THEN
      V_WHAT := '원문 미보존 — 변경 내용 확인 불가'
             || CASE WHEN R.OBJ = '(대상 미확인)' THEN ' · 대상 패키지 미확인(다른 패키지일 수 있음)' END;
    ELSIF R.ACT LIKE 'ALTER%' THEN
      V_WHAT := '재컴파일 (소스 변경 없음)';
    ELSIF R.ACT LIKE 'DROP%' THEN
      V_WHAT := '⚠ 패키지 삭제';
      IF V_KIND = 'BODY' THEN P_BODY_L.DELETE; P_BODY_N := 0; ELSE P_SPEC_L.DELETE; P_SPEC_N := 0; END IF;
    ELSIF V_KIND = 'BODY' THEN
      HANDLE_TEXT(R.TXT, 'BODY', V_HDR, P_BODY_L, P_BODY_N, V_WHAT);
    ELSE
      HANDLE_TEXT(R.TXT, 'SPEC', V_HDR, P_SPEC_L, P_SPEC_N, V_WHAT);
    END IF;

    V_WHO := CLASSIFY(R.PROG, R.MDL, R.HOST, R.USR);
    IF V_WHO LIKE '사람%' THEN N_HUMAN := N_HUMAN + 1;
    ELSIF V_WHO LIKE 'AI%' THEN N_AI := N_AI + 1;
    ELSE N_UNK := N_UNK + 1; END IF;
    IF G_TAG_H IS NOT NULL THEN
      V_WHAT := V_WHAT || ' · 내용 작성 태그 ' || G_TAG_H || '(실행자와 다를 수 있음)';
    END IF;

    ADD_SUM(RPAD('#' || N_EVT, 4) || ' | '
         || TO_CHAR(R.TS,'YYYY-MM-DD HH24:MI:SS')
         || CASE WHEN R.TS2 IS NOT NULL AND CAST(R.TS2 AS DATE) <> CAST(R.TS AS DATE)
                 THEN '~' || TO_CHAR(R.TS2,'HH24:MI:SS') ELSE '         ' END || ' | '
         || RPAD(R.SRC, 5) || ' | '
         || RPAD(NVL(R.USR,'-'), 10) || ' | ' || RPAD(NVL(R.OSU,'-'), 24) || ' | '
         || RPAD(NVL(SUBSTR(R.HOST,1,24),'-'), 24) || ' | '
         || RPAD(NVL(SUBSTR(R.PROG,1,48),'-'), 48) || ' | '
         || RPAD(NVL(R.ACT,'-'), 19) || ' | '
         || RPAD(SUBSTR(V_WHO,1,70), 70) || ' | ' || V_WHAT);
  END LOOP;

  DBMS_OUTPUT.PUT_LINE('[A] 이벤트 정리표 — PKG_COM0000 · 대상 멤버 P_COM0003_GET_STORAGE_BY_DIVISION_POPUP');
  DBMS_OUTPUT.PUT_LINE('    수행 주체 = 실행 프로그램·원문 흔적 기준 추정 — 사람(GUI DB 도구 직접 실행) / AI·자동화(스크립트 런타임·AI 마커) / 구분 불가(sqlplus·JDBC 등)');
  DBMS_OUTPUT.PUT_LINE(RPAD('No', 4) || ' | ' || RPAD('언제', 28) || ' | ' || RPAD('출처', 5) || ' | '
                    || RPAD('DB계정', 10) || ' | ' || RPAD('OS사용자', 24) || ' | ' || RPAD('PC', 24) || ' | '
                    || RPAD('프로그램', 48) || ' | ' || RPAD('DDL', 19) || ' | '
                    || RPAD('수행 주체(근거)', 70) || ' | 무엇을');
  DBMS_OUTPUT.PUT_LINE(RPAD('-', 300, '-'));
  IF N_SUM = 0 THEN
    DBMS_OUTPUT.PUT_LINE('(기간 내 감사·AWR·ASH 어디에도 PKG_COM0000 DDL 이벤트 없음)');
  END IF;
  FOR I IN 1 .. N_SUM LOOP DBMS_OUTPUT.PUT_LINE(G_SUM(I)); END LOOP;
  DBMS_OUTPUT.PUT_LINE(RPAD('-', 300, '-'));
  DBMS_OUTPUT.PUT_LINE('    수행 주체 집계 : 사람 ' || N_HUMAN || '건 / AI·자동화 추정 ' || N_AI || '건 / 구분 불가 ' || N_UNK || '건 (전체 ' || N_SUM || '건)');

  DBMS_OUTPUT.PUT_LINE(' ');
  DBMS_OUTPUT.PUT_LINE('[B] 현재 LAST_DDL 대조 (±10초 이내 이벤트가 있으면 그 이벤트가 마지막 변경)');
  FOR O IN (SELECT OBJECT_TYPE, LAST_DDL_TIME FROM ALL_OBJECTS
             WHERE OWNER = 'SCM_MGR' AND OBJECT_NAME = 'PKG_COM0000' ORDER BY OBJECT_TYPE) LOOP
    V_HIT := NULL;
    FOR I IN 1 .. N_EVT LOOP
      IF ABS(G_EVT(I) - O.LAST_DDL_TIME) * 86400 <= 10 THEN V_HIT := I; END IF;
    END LOOP;
    DBMS_OUTPUT.PUT_LINE('    ' || RPAD(O.OBJECT_TYPE, 13) || ' LAST_DDL=' || TO_CHAR(O.LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS')
                      || CASE WHEN V_HIT IS NOT NULL THEN '  → 이벤트 #' || V_HIT || ' 와 일치'
                              ELSE '  → 일치 이벤트 없음 (감사·ASH 미포착 — 실행자·내용 DB 로 확인 불가 · GRANT/재컴파일도 갱신됨)' END);
  END LOOP;

  DBMS_OUTPUT.PUT_LINE(' ');
  DBMS_OUTPUT.PUT_LINE('[C] 대상 멤버 변경 상세 (직전 버전 대비 · - 삭제된 줄 / + 추가된 줄)');
  IF N_DET = 0 THEN
    DBMS_OUTPUT.PUT_LINE('    (원문이 보존된 이벤트 사이에서 대상 멤버 내용 변경 없음, 또는 비교할 원문이 2건 미만)');
  END IF;
  FOR I IN 1 .. N_DET LOOP DBMS_OUTPUT.PUT_LINE(G_DET(I)); END LOOP;
EXCEPTION
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('§7 ERROR: ' || SQLERRM || ' / ' || DBMS_UTILITY.FORMAT_ERROR_BACKTRACE);
END;
