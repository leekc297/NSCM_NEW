PROMPT ================= §6 ⭐ DDL 원문(감사 + AWR)에서 대상 멤버 구간만 시점별 출력 =================
PROMPT  ※ ★ = 직전 이벤트 대비 멤버 구간 길이 변경 = 내용이 바뀐 시점
DECLARE
  V_FROM PLS_INTEGER;
  V_TO   PLS_INTEGER;
  V_POS  PLS_INTEGER;
  V_LEN  PLS_INTEGER;
  V_PREV PLS_INTEGER := -1;
  V_CNT  PLS_INTEGER := 0;
BEGIN
  FOR R IN (
    SELECT 'AUDIT' AS SRC, CAST(A.EVENT_TIMESTAMP AS TIMESTAMP) AS TS
         , A.DBUSERNAME AS USR, A.OS_USERNAME AS OSU, A.USERHOST AS HOST
         , A.CLIENT_PROGRAM_NAME AS PROG, A.ACTION_NAME AS ACT, A.SQL_TEXT AS TXT
      FROM UNIFIED_AUDIT_TRAIL A
     WHERE A.EVENT_TIMESTAMP >= CAST(ADD_MONTHS(SYSDATE,-1) AS TIMESTAMP)
       AND DBMS_LOB.INSTR(UPPER(A.SQL_TEXT), 'PKG_COM0000') > 0
       AND DBMS_LOB.INSTR(UPPER(A.SQL_TEXT), 'P_COM0003_GET_STORAGE_BY_DIVISION_POPUP') > 0
    UNION ALL
    SELECT 'AWR:' || G.SQL_ID, CAST(G.T_FROM AS TIMESTAMP)
         , U.USERNAME, NULL, G.MACHINE, G.PROGRAM, AA.NAME, X.SQL_TEXT
      FROM (SELECT SQL_ID, MIN(SAMPLE_TIME) AS T_FROM, MAX(USER_ID) AS USER_ID
                 , MAX(MACHINE) AS MACHINE, MAX(PROGRAM) AS PROGRAM, MAX(SQL_OPCODE) AS SQL_OPCODE
              FROM (SELECT SQL_ID, SAMPLE_TIME, USER_ID, MACHINE, PROGRAM, SQL_OPCODE
                      FROM GV$ACTIVE_SESSION_HISTORY WHERE SQL_OPCODE BETWEEN 94 AND 99
                    UNION ALL
                    SELECT SQL_ID, SAMPLE_TIME, USER_ID, MACHINE, PROGRAM, SQL_OPCODE
                      FROM DBA_HIST_ACTIVE_SESS_HISTORY WHERE SQL_OPCODE BETWEEN 94 AND 99)
             GROUP BY SQL_ID) G
      JOIN (SELECT SQL_ID, SQL_TEXT
              FROM (SELECT T.SQL_ID, T.SQL_TEXT
                         , ROW_NUMBER() OVER (PARTITION BY T.SQL_ID ORDER BY T.DBID) AS RN
                      FROM DBA_HIST_SQLTEXT T)
             WHERE RN = 1) X ON X.SQL_ID = G.SQL_ID
      LEFT JOIN DBA_USERS U ON U.USER_ID = G.USER_ID
      LEFT JOIN AUDIT_ACTIONS AA ON AA.ACTION = G.SQL_OPCODE
     WHERE DBMS_LOB.INSTR(UPPER(X.SQL_TEXT), 'PKG_COM0000') > 0
       AND DBMS_LOB.INSTR(UPPER(X.SQL_TEXT), 'P_COM0003_GET_STORAGE_BY_DIVISION_POPUP') > 0
     ORDER BY 2
  ) LOOP
    V_CNT  := V_CNT + 1;
    V_FROM := REGEXP_INSTR(R.TXT
               , 'PROCEDURE\s+P_COM0003_GET_STORAGE_BY_DIVISION_POPUP\s*(\([^;]*?\))?\s*(IS|AS)\s'
               , 1, 1, 0, 'in');
    IF V_FROM = 0 THEN
      V_FROM := DBMS_LOB.INSTR(UPPER(R.TXT), 'P_COM0003_GET_STORAGE_BY_DIVISION_POPUP');
    END IF;
    V_TO := REGEXP_INSTR(R.TXT, CHR(10) || '\s*(PROCEDURE|FUNCTION)\s+\w+', V_FROM + 10, 1, 0, 'in');
    IF V_TO = 0 THEN
      V_TO := DBMS_LOB.GETLENGTH(R.TXT) + 1;
    END IF;
    V_LEN := V_TO - V_FROM;

    DBMS_OUTPUT.PUT_LINE('==================================================================');
    DBMS_OUTPUT.PUT_LINE('#' || V_CNT || ' [' || R.SRC || '] ' || TO_CHAR(R.TS,'YYYY-MM-DD HH24:MI:SS')
                         || '  DB=' || R.USR || '  OS=' || R.OSU || '  HOST=' || R.HOST
                         || '  PROG=' || R.PROG || '  ACTION=' || R.ACT);
    DBMS_OUTPUT.PUT_LINE('    MEMBER_LEN=' || V_LEN
                         || CASE WHEN V_PREV >= 0 AND V_PREV <> V_LEN
                                 THEN '  ★ 직전 대비 길이 변경(' || V_PREV || '→' || V_LEN || ')' END);
    DBMS_OUTPUT.PUT_LINE('------------------------------------------------------------------');
    V_POS := V_FROM;
    WHILE V_POS < V_TO LOOP
      -- 한글 CLOB 은 4000 단위에서 ORA-06502 → 1000자 단위
      DBMS_OUTPUT.PUT_LINE(DBMS_LOB.SUBSTR(R.TXT, LEAST(1000, V_TO - V_POS), V_POS));
      V_POS := V_POS + 1000;
    END LOOP;
    V_PREV := V_LEN;
  END LOOP;
  IF V_CNT = 0 THEN
    DBMS_OUTPUT.PUT_LINE('§6: 대상 멤버를 포함한 DDL 원문이 감사·AWR 어디에도 보존되지 않음');
  END IF;
EXCEPTION
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('§6 ERROR: ' || SQLERRM);
END;
