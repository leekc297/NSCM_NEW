PROMPT ================= §3 ⭐ 패키지 DDL 실행 세션 전수 (메모리 ASH + AWR) =================
PROMPT  HIT_PKG = Y 인 행이 PKG_COM0000 DDL / NO_TEXT = 원문 미보존(CURRENT_OBJ 로 보조 판정)
PROMPT  ※ ASH 는 샘플링 — 1초 미만 DDL 은 누락될 수 있다. "없음" ≠ "변경 없음"
WITH ASH AS (
  SELECT SAMPLE_TIME, USER_ID, SESSION_ID, SESSION_SERIAL#, SQL_ID, SQL_OPCODE
       , MACHINE, PROGRAM, MODULE, CURRENT_OBJ#
    FROM GV$ACTIVE_SESSION_HISTORY
   WHERE SQL_OPCODE BETWEEN 94 AND 99
  UNION ALL
  SELECT SAMPLE_TIME, USER_ID, SESSION_ID, SESSION_SERIAL#, SQL_ID, SQL_OPCODE
       , MACHINE, PROGRAM, MODULE, CURRENT_OBJ#
    FROM DBA_HIST_ACTIVE_SESS_HISTORY
   WHERE SQL_OPCODE BETWEEN 94 AND 99
     AND SAMPLE_TIME >= CAST(ADD_MONTHS(SYSDATE,-1) AS TIMESTAMP)
), G AS (
  SELECT SQL_ID, SQL_OPCODE, USER_ID, MACHINE, PROGRAM, SESSION_ID, SESSION_SERIAL#
       , MIN(SAMPLE_TIME) AS T_FROM, MAX(SAMPLE_TIME) AS T_TO, MAX(CURRENT_OBJ#) AS OBJ_NO
    FROM ASH
   GROUP BY SQL_ID, SQL_OPCODE, USER_ID, MACHINE, PROGRAM, SESSION_ID, SESSION_SERIAL#
), X AS (
  SELECT SQL_ID, SQL_TEXT
    FROM (SELECT T.SQL_ID, T.SQL_TEXT
               , ROW_NUMBER() OVER (PARTITION BY T.SQL_ID ORDER BY T.DBID) AS RN
            FROM DBA_HIST_SQLTEXT T
           WHERE T.SQL_ID IN (SELECT SQL_ID FROM G))
   WHERE RN = 1
)
SELECT TO_CHAR(G.T_FROM,'YYYY-MM-DD HH24:MI:SS') AS T_FROM
     , TO_CHAR(G.T_TO,  'YYYY-MM-DD HH24:MI:SS') AS T_TO
     , U.USERNAME, G.MACHINE, SUBSTR(G.PROGRAM,1,30) AS PROGRAM
     , G.SESSION_ID || ',' || G.SESSION_SERIAL# AS SID_SERIAL
     , G.SQL_ID, AA.NAME AS DDL_TYPE
     , REGEXP_SUBSTR(DBMS_LOB.SUBSTR(X.SQL_TEXT,400,1)
                   , 'PACKAGE\s+(BODY\s+)?("?\w+"?\.)?"?(\w+)', 1, 1, 'i', 3) AS PKG_IN_TEXT
     , O.OBJECT_NAME AS CURRENT_OBJ
     , CASE WHEN X.SQL_ID IS NULL THEN 'NO_TEXT'
            WHEN DBMS_LOB.INSTR(UPPER(X.SQL_TEXT),'PKG_COM0000') > 0 THEN 'Y' ELSE 'N' END AS HIT_PKG
     , CASE WHEN DBMS_LOB.INSTR(UPPER(X.SQL_TEXT),'P_COM0003_GET_STORAGE_BY_DIVISION_POPUP') > 0
            THEN 'Y' ELSE 'N' END AS HIT_MEMBER
     , DBMS_LOB.GETLENGTH(X.SQL_TEXT) AS SQL_LEN
  FROM G
  LEFT JOIN X                ON X.SQL_ID    = G.SQL_ID
  LEFT JOIN DBA_USERS U      ON U.USER_ID   = G.USER_ID
  LEFT JOIN AUDIT_ACTIONS AA ON AA.ACTION   = G.SQL_OPCODE
  LEFT JOIN DBA_OBJECTS O    ON O.OBJECT_ID = G.OBJ_NO
 ORDER BY G.T_FROM;

