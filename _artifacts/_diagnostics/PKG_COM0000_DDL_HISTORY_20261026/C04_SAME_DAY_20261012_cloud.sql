PROMPT ================= §1 10-12 PKG_COM0000 감사 이벤트 (있으면 원문 보존) =================
SELECT TO_CHAR(EVENT_TIMESTAMP,'YYYY-MM-DD HH24:MI:SS') AS T_FIRST
     , DBUSERNAME, OS_USERNAME, USERHOST, SUBSTR(CLIENT_PROGRAM_NAME,1,40) AS PROGRAM
     , ACTION_NAME, OBJECT_NAME, RETURN_CODE
  FROM UNIFIED_AUDIT_TRAIL
 WHERE EVENT_TIMESTAMP >= TIMESTAMP '2026-10-12 00:00:00'
   AND EVENT_TIMESTAMP <  TIMESTAMP '2026-10-13 00:00:00'
   AND (UPPER(OBJECT_NAME) = 'PKG_COM0000' OR DBMS_LOB.INSTR(UPPER(SQL_TEXT), 'PKG_COM0000') > 0)
 ORDER BY EVENT_TIMESTAMP;

PROMPT ================= §2 10-12 감사 이벤트 전체 요약 (누가 그날 DB 에 있었나 · 시간대 18~21시 강조) =================
SELECT TO_CHAR(MIN(EVENT_TIMESTAMP),'YYYY-MM-DD HH24:MI:SS') AS T_FIRST
     , TO_CHAR(MAX(EVENT_TIMESTAMP),'YYYY-MM-DD HH24:MI:SS') AS T_LAST
     , DBUSERNAME, OS_USERNAME, USERHOST, SUBSTR(CLIENT_PROGRAM_NAME,1,40) AS PROGRAM, ACTION_NAME
     , COUNT(*) AS CNT
     , SUM(CASE WHEN EVENT_TIMESTAMP >= TIMESTAMP '2026-10-12 18:00:00'
                 AND EVENT_TIMESTAMP <  TIMESTAMP '2026-10-12 21:00:00' THEN 1 ELSE 0 END) AS CNT_18_21
  FROM UNIFIED_AUDIT_TRAIL
 WHERE EVENT_TIMESTAMP >= TIMESTAMP '2026-10-12 00:00:00'
   AND EVENT_TIMESTAMP <  TIMESTAMP '2026-10-13 00:00:00'
 GROUP BY DBUSERNAME, OS_USERNAME, USERHOST, SUBSTR(CLIENT_PROGRAM_NAME,1,40), ACTION_NAME
 ORDER BY MIN(EVENT_TIMESTAMP);

PROMPT ================= §3 SCM_MGR 객체 중 마지막 DDL 이 10-12 인 것 (그날 DDL 작업 흔적) =================
SELECT OBJECT_NAME, OBJECT_TYPE
     , TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') AS LAST_DDL, TIMESTAMP
  FROM ALL_OBJECTS
 WHERE OWNER = 'SCM_MGR'
   AND LAST_DDL_TIME >= DATE '2026-10-12' AND LAST_DDL_TIME < DATE '2026-10-13'
 ORDER BY LAST_DDL_TIME;

PROMPT ================= §4 AWR/ASH 보존 시작 (10-12 이 보존 범위 밖이면 세션 기록 확인 불가) =================
SELECT TO_CHAR(MIN(BEGIN_INTERVAL_TIME),'YYYY-MM-DD HH24:MI:SS') AS AWR_FROM
     , CASE WHEN MIN(BEGIN_INTERVAL_TIME) > TIMESTAMP '2026-10-12 00:00:00'
            THEN '10-12 은 AWR 보존 범위 밖 — 세션·DDL 원문 확인 불가' ELSE '10-12 포함' END AS NOTE
  FROM DBA_HIST_SNAPSHOT
 WHERE DBID = (SELECT DBID FROM V$DATABASE);

SELECT TO_CHAR(MIN(H.SAMPLE_TIME),'YYYY-MM-DD HH24:MI:SS') AS T_FIRST
     , TO_CHAR(MAX(H.SAMPLE_TIME),'YYYY-MM-DD HH24:MI:SS') AS T_LAST
     , U.USERNAME AS DBUSERNAME, H.MACHINE AS USERHOST, SUBSTR(H.PROGRAM,1,40) AS PROGRAM, H.SQL_OPCODE
  FROM DBA_HIST_ACTIVE_SESS_HISTORY H
  LEFT JOIN DBA_USERS U ON U.USER_ID = H.USER_ID
 WHERE H.SAMPLE_TIME >= TIMESTAMP '2026-10-12 00:00:00'
   AND H.SAMPLE_TIME <  TIMESTAMP '2026-10-13 00:00:00'
   AND H.SQL_OPCODE BETWEEN 94 AND 99
 GROUP BY U.USERNAME, H.MACHINE, SUBSTR(H.PROGRAM,1,40), H.SQL_OPCODE
 ORDER BY MIN(H.SAMPLE_TIME);

