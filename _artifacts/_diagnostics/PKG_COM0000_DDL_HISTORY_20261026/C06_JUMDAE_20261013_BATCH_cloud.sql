PROMPT ================= §B ⭐ 10-13 객체별 — 직전 jumdae 실행본과 원문 동일 여부 =================
PROMPT  SAME = 바이트 동일(옛 배포본 그대로 재실행) / DIFF = 내용 다름(새 소스) / NEW = 이전 실행 기록 없음
DECLARE /*TRACE_SELF*/
  V_PREV_T  TIMESTAMP;
  V_PREV    CLOB;
  V_RES     VARCHAR2(60);
  V_N       PLS_INTEGER := 0;
BEGIN
  DBMS_OUTPUT.PUT_LINE(RPAD('10-13 시각',10) || ' | ' || RPAD('DDL',20) || ' | ' || RPAD('객체',44) || ' | ' || RPAD('길이',8) || ' | 직전 jumdae 실행본 대비');
  DBMS_OUTPUT.PUT_LINE(RPAD('-',150,'-'));
  FOR R IN (
    SELECT A.EVENT_TIMESTAMP, A.ACTION_NAME, A.OBJECT_SCHEMA, A.OBJECT_NAME, A.SQL_TEXT
      FROM UNIFIED_AUDIT_TRAIL A
     WHERE (UPPER(A.OS_USERNAME) LIKE '%JUMDAE%' OR UPPER(A.USERHOST) LIKE '%LESP03D5114%')
       AND A.EVENT_TIMESTAMP >= TIMESTAMP '2026-10-13 10:50:00'
       AND A.EVENT_TIMESTAMP <  TIMESTAMP '2026-10-13 11:40:00'
       AND A.ACTION_NAME LIKE 'CREATE%'
       AND A.SQL_TEXT IS NOT NULL
     ORDER BY A.EVENT_TIMESTAMP, A.OBJECT_NAME
  ) LOOP
    V_N := V_N + 1;
    V_PREV := NULL; V_PREV_T := NULL;
    BEGIN
      SELECT P.SQL_TEXT, P.EVENT_TIMESTAMP INTO V_PREV, V_PREV_T
        FROM (SELECT B.SQL_TEXT, B.EVENT_TIMESTAMP
                FROM UNIFIED_AUDIT_TRAIL B
               WHERE (UPPER(B.OS_USERNAME) LIKE '%JUMDAE%' OR UPPER(B.USERHOST) LIKE '%LESP03D5114%')
                 AND B.ACTION_NAME   = R.ACTION_NAME
                 AND B.OBJECT_SCHEMA = R.OBJECT_SCHEMA
                 AND B.OBJECT_NAME   = R.OBJECT_NAME
                 AND B.EVENT_TIMESTAMP < R.EVENT_TIMESTAMP - INTERVAL '10' MINUTE
                 AND B.SQL_TEXT IS NOT NULL
               ORDER BY B.EVENT_TIMESTAMP DESC) P
       WHERE ROWNUM = 1;
      V_RES := CASE WHEN DBMS_LOB.COMPARE(R.SQL_TEXT, V_PREV) = 0 THEN 'SAME'
                    ELSE 'DIFF (길이 ' || DBMS_LOB.GETLENGTH(V_PREV) || '→' || DBMS_LOB.GETLENGTH(R.SQL_TEXT) || ')' END
            || ' · 직전 ' || TO_CHAR(V_PREV_T,'MM-DD HH24:MI:SS');
    EXCEPTION WHEN NO_DATA_FOUND THEN V_RES := 'NEW (이전 jumdae 실행 기록 없음)';
    END;
    DBMS_OUTPUT.PUT_LINE(TO_CHAR(R.EVENT_TIMESTAMP,'HH24:MI:SS') || '   | ' || RPAD(R.ACTION_NAME,20) || ' | '
                      || RPAD(R.OBJECT_SCHEMA || '.' || R.OBJECT_NAME,44) || ' | ' || RPAD(DBMS_LOB.GETLENGTH(R.SQL_TEXT),8) || ' | ' || V_RES);
  END LOOP;
  IF V_N = 0 THEN DBMS_OUTPUT.PUT_LINE('(10-13 10:50~11:40 jumdae CREATE 원문 없음)'); END IF;
EXCEPTION WHEN OTHERS THEN DBMS_OUTPUT.PUT_LINE('§B 오류: ' || SQLERRM);
END;
