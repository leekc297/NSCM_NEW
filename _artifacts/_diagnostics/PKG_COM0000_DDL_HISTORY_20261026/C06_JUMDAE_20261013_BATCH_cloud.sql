PROMPT ================= §C PKG_COM0000 원문 지문 — jumdae 실행별 =================
PROMPT  SLASHOBJ = 우리 팀 10-08 '/' 센티널 일괄본 마커 [E20261008-SLASHOBJ] 포함 여부 · P_COM0003_FILTER = 대상 필터 상태
SELECT TO_CHAR(A.EVENT_TIMESTAMP,'YYYY-MM-DD HH24:MI:SS') AS T, A.ACTION_NAME
     , DBMS_LOB.GETLENGTH(A.SQL_TEXT) AS TXT_LEN
     , REGEXP_COUNT(A.SQL_TEXT, CHR(10)) + 1 AS LINES
     , CASE WHEN DBMS_LOB.INSTR(A.SQL_TEXT, 'E20261008-SLASHOBJ') > 0 THEN 'Y' ELSE 'N' END AS SLASHOBJ
     , REGEXP_COUNT(A.SQL_TEXT, '\[E2026\d{4}-[A-Z]', 1, 'i') AS N_AI_MARKER
     , CASE WHEN A.ACTION_NAME <> 'CREATE PACKAGE BODY' THEN '-'
            WHEN REGEXP_INSTR(A.SQL_TEXT, '--[^' || CHR(10) || ']*STORAGE_ID\s+LIKE\s+''A%''', 1, 1, 0, 'i') > 0 THEN 'COMMENTED'
            WHEN REGEXP_INSTR(A.SQL_TEXT, 'STORAGE_ID\s+LIKE\s+''A%''', 1, 1, 0, 'i') > 0 THEN 'ACTIVE'
            ELSE '(없음)' END AS P_COM0003_FILTER
     , REPLACE(REPLACE(DBMS_LOB.SUBSTR(A.SQL_TEXT, 120, 1), CHR(10), ' '), CHR(13), ' ') AS HEAD
  FROM UNIFIED_AUDIT_TRAIL A
 WHERE (UPPER(A.OS_USERNAME) LIKE '%JUMDAE%' OR UPPER(A.USERHOST) LIKE '%LESP03D5114%')
   AND UPPER(A.OBJECT_NAME) = 'PKG_COM0000'
   AND A.ACTION_NAME IN ('CREATE PACKAGE','CREATE PACKAGE BODY')
 ORDER BY A.EVENT_TIMESTAMP, A.ACTION_NAME;

PROMPT ================= §D jumdae 배포 묶음 요약 — PKG_COM0000 이 포함된 실행일별 함께 만든 객체 =================
SELECT TO_CHAR(A.EVENT_TIMESTAMP,'YYYY-MM-DD') AS DAY
     , TO_CHAR(MIN(A.EVENT_TIMESTAMP),'HH24:MI:SS') || '~' || TO_CHAR(MAX(A.EVENT_TIMESTAMP),'HH24:MI:SS') AS T
     , COUNT(DISTINCT A.OBJECT_NAME) AS N_OBJ
     , SUBSTR(LISTAGG(DISTINCT A.OBJECT_NAME || '(' || REPLACE(A.ACTION_NAME,'CREATE ','') || ')', ', ' ON OVERFLOW TRUNCATE)
              WITHIN GROUP (ORDER BY A.OBJECT_NAME), 1, 160) AS OBJ_LIST
  FROM UNIFIED_AUDIT_TRAIL A
 WHERE (UPPER(A.OS_USERNAME) LIKE '%JUMDAE%' OR UPPER(A.USERHOST) LIKE '%LESP03D5114%')
   AND A.ACTION_NAME IN ('CREATE PACKAGE','CREATE PACKAGE BODY','CREATE FUNCTION','CREATE PROCEDURE','CREATE VIEW')
   AND EXISTS (SELECT 1 FROM UNIFIED_AUDIT_TRAIL P
                WHERE (UPPER(P.OS_USERNAME) LIKE '%JUMDAE%' OR UPPER(P.USERHOST) LIKE '%LESP03D5114%')
                  AND UPPER(P.OBJECT_NAME) = 'PKG_COM0000' AND P.ACTION_NAME = 'CREATE PACKAGE BODY'
                  AND A.EVENT_TIMESTAMP BETWEEN P.EVENT_TIMESTAMP - INTERVAL '5' MINUTE AND P.EVENT_TIMESTAMP + INTERVAL '5' MINUTE)
 GROUP BY TO_CHAR(A.EVENT_TIMESTAMP,'YYYY-MM-DD'), TRUNC(A.EVENT_TIMESTAMP,'HH24')
 ORDER BY 1, 2;

