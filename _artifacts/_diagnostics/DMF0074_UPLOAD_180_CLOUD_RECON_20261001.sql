-- DMF0074 Excel Upload — 18:54:40 재업로드(249행) 후 조회 180건 대사 (클라우드 SCM_MGR · 읽기 전용)
--   배치 시각이 미리 들어 있음 — 그대로 실행 ([2] 상태 · [3] 사유별 예상 · [4] 실제 저장 · [7] 화면 건수 대사)
--   읽는 법: [3] 합계 PRED_MODEL_ROWS_EMPTYASIS ≈ [4] MODEL_ROWS ≈ [7] BY_THIS_BATCH 이면 정상 확장 결과
--            [7] GRID_ROWS 합계 = 화면 180건 (조회 기간 202610~202612 · 필터 ALL 기준)
-- =====================================================================================================
SET PAGESIZE 200 LINESIZE 220
COLUMN REASON FORMAT A50
COLUMN MSG FORMAT A60
DEFINE P_BATCH = '2026-10-01 18:54:40'
DEFINE P_DIV   = '81'

-- [2] 업로드 원장 — P_BATCH 배치의 상태·메시지별 건수 (SUCCESS 249 이어야 (가)(나)(다) 분석 대상)
SELECT TO_CHAR(CREATION_DATE, 'YYYY-MM-DD HH24:MI:SS') BATCH, UPLOAD_STATUS_CODE, SUBSTR(MESSAGE_TEXT, 1, 60) MSG, COUNT(*) CNT
  FROM SCM_ADM_EXCEL_UPLOAD
 WHERE PROGRAM_ID LIKE 'DMF0074%' 
   AND CREATION_DATE = TO_DATE('&P_BATCH', 'YYYY-MM-DD HH24:MI:SS')
 GROUP BY TO_CHAR(CREATION_DATE, 'YYYY-MM-DD HH24:MI:SS'), UPLOAD_STATUS_CODE, SUBSTR(MESSAGE_TEXT, 1, 60)
 ORDER BY 2, 3;

-- [3] 행별 예측 — P_BATCH 배치 SUCCESS 행마다 (가) 확장 모델 수 · (나) 완전/부분 금속 수 → 저장 예상 모델 수
--     PRED_OLD_BODY = 클라우드 현행(EMPTYASIS 미적용) 기준 / PRED_EMPTYASIS = 사내 보완 적용 시
WITH B AS (
    SELECT U.*
      FROM SCM_ADM_EXCEL_UPLOAD U
     WHERE U.PROGRAM_ID LIKE 'DMF0074%' AND U.UPLOAD_STATUS_CODE = 'SUCCESS'
       AND U.CREATION_DATE = TO_DATE('&P_BATCH', 'YYYY-MM-DD HH24:MI:SS')),
MET AS (   -- 행 × 금속 7종 (비 40 사업부 배치: Key 14~20 / Fr 21~27 / To 28~34 / Contract 35~41 / Change 42~48 / Index 49~55)
    SELECT B.UPLOAD_ID, M.N,
           CASE M.N WHEN 1 THEN B.ATTRIBUTE14 WHEN 2 THEN B.ATTRIBUTE15 WHEN 3 THEN B.ATTRIBUTE16 WHEN 4 THEN B.ATTRIBUTE17
                    WHEN 5 THEN B.ATTRIBUTE18 WHEN 6 THEN B.ATTRIBUTE19 ELSE B.ATTRIBUTE20 END K,
           CASE WHEN CASE M.N WHEN 1 THEN B.ATTRIBUTE21 WHEN 2 THEN B.ATTRIBUTE22 WHEN 3 THEN B.ATTRIBUTE23 WHEN 4 THEN B.ATTRIBUTE24 WHEN 5 THEN B.ATTRIBUTE25 WHEN 6 THEN B.ATTRIBUTE26 ELSE B.ATTRIBUTE27 END IS NULL
                  OR CASE M.N WHEN 1 THEN B.ATTRIBUTE28 WHEN 2 THEN B.ATTRIBUTE29 WHEN 3 THEN B.ATTRIBUTE30 WHEN 4 THEN B.ATTRIBUTE31 WHEN 5 THEN B.ATTRIBUTE32 WHEN 6 THEN B.ATTRIBUTE33 ELSE B.ATTRIBUTE34 END IS NULL
                  OR CASE M.N WHEN 1 THEN B.ATTRIBUTE35 WHEN 2 THEN B.ATTRIBUTE36 WHEN 3 THEN B.ATTRIBUTE37 WHEN 4 THEN B.ATTRIBUTE38 WHEN 5 THEN B.ATTRIBUTE39 WHEN 6 THEN B.ATTRIBUTE40 ELSE B.ATTRIBUTE41 END IS NULL
                  OR CASE M.N WHEN 1 THEN B.ATTRIBUTE42 WHEN 2 THEN B.ATTRIBUTE43 WHEN 3 THEN B.ATTRIBUTE44 WHEN 4 THEN B.ATTRIBUTE45 WHEN 5 THEN B.ATTRIBUTE46 WHEN 6 THEN B.ATTRIBUTE47 ELSE B.ATTRIBUTE48 END IS NULL
                  OR CASE M.N WHEN 1 THEN B.ATTRIBUTE49 WHEN 2 THEN B.ATTRIBUTE50 WHEN 3 THEN B.ATTRIBUTE51 WHEN 4 THEN B.ATTRIBUTE52 WHEN 5 THEN B.ATTRIBUTE53 WHEN 6 THEN B.ATTRIBUTE54 ELSE B.ATTRIBUTE55 END IS NULL
                THEN 'PARTIAL' ELSE 'FULL' END VALS
      FROM B CROSS JOIN (SELECT LEVEL N FROM DUAL CONNECT BY LEVEL <= 7) M),
MS AS (SELECT UPLOAD_ID,
              SUM(CASE WHEN K IS NOT NULL AND VALS = 'FULL' THEN 1 ELSE 0 END)    FULL_METALS,
              SUM(CASE WHEN K IS NOT NULL AND VALS = 'PARTIAL' THEN 1 ELSE 0 END) PARTIAL_METALS
         FROM MET GROUP BY UPLOAD_ID),
VER AS (SELECT A.DIVISION_ID, A.VERSION_NO,
               TO_CHAR(FN_NEXT_DAY(TO_DATE(A.YYYYMMDD, 'YYYYMMDD'), 'MON') - 7, 'YYYYMMDD') RESULT_TO,
               TO_CHAR(FN_NEXT_DAY(TO_DATE(A.YYYYMMDD, 'YYYYMMDD'), 'MON') - 7 + 52 * 7 - 1, 'YYYYMMDD') PLAN_TO
          FROM (SELECT DIVISION_ID, MAX(VERSION_NO) VERSION_NO, MAX(YYYYMMDD) YYYYMMDD FROM DM_MST_VERSION
                 WHERE VERSION_TYPE = 'SP_W' AND NVL(ATTRIBUTE7, 'N') = 'Y' AND DIVISION_ID = '&P_DIV' GROUP BY DIVISION_ID) A),
SPI AS (SELECT DISTINCT PC.DIVISION_ID, PC.PROJECT_CODE, PC.SCM_SITE_ID, PC.ITEM_ID, PC.FCST_TYPE, PC.CURRENCY
          FROM DM_PLN_SALES_PLAN_C PC JOIN VER ON VER.DIVISION_ID = PC.DIVISION_ID AND VER.VERSION_NO = PC.VERSION_NO
         WHERE PC.QTY <> 0 AND PC.MEASURE = 'RTF_SYS_RP' AND PC.YYYYMMDD BETWEEN VER.RESULT_TO AND VER.PLAN_TO),
EXP AS (SELECT B.UPLOAD_ID, COUNT(DISTINCT I.ITEM_ID) EXPANDED_MODELS
          FROM B
          JOIN SCM_MST_SITE_ITEM I ON I.DIVISION_ID = B.ATTRIBUTE1 AND I.PROJECT_CODE = B.ATTRIBUTE5 AND I.SCM_SITE_ID = B.ATTRIBUTE9 AND I.VALID_YN = 'Y'
          JOIN SCM_ADM_LOOKUP_MASTER_DETAIL L ON L.LOOKUP_TYPE = 'SALES_TYPE_CODE' AND L.VALID_YN = 'Y' AND L.SEGMENT4 <> 'FREE' AND L.SEGMENT2 = B.ATTRIBUTE11
          JOIN (SELECT DISTINCT DIVISION_ID, ITEM_ID FROM DM_MST_ITEM_SINGLE_V WHERE ITEM_TYPE = 'P' AND ACTIVE_FLAG = 'Y') PV
            ON PV.DIVISION_ID = B.ATTRIBUTE1 AND PV.ITEM_ID = I.ITEM_ID
          JOIN SPI ON SPI.DIVISION_ID = B.ATTRIBUTE1 AND SPI.PROJECT_CODE = B.ATTRIBUTE5 AND SPI.SCM_SITE_ID = B.ATTRIBUTE9
                  AND SPI.ITEM_ID = I.ITEM_ID AND SPI.CURRENCY = B.ATTRIBUTE10 AND SPI.FCST_TYPE = L.SEGMENT1
         WHERE B.ATTRIBUTE7 IS NULL
         GROUP BY B.UPLOAD_ID),
R AS (SELECT B.UPLOAD_ID, B.ATTRIBUTE2 PLAN_YYYYMM, B.ATTRIBUTE5 PROJECT_CODE, B.ATTRIBUTE9 SCM_SITE_ID, B.ATTRIBUTE10 CURRENCY, B.ATTRIBUTE11 FCST_TYPE,
             B.ATTRIBUTE7 MODEL, NVL(EXP.EXPANDED_MODELS, 0) EXPANDED_MODELS, MS.FULL_METALS, MS.PARTIAL_METALS,
             CASE WHEN B.ATTRIBUTE7 IS NOT NULL THEN 1 ELSE NVL(EXP.EXPANDED_MODELS, 0) END
               * CASE WHEN MS.FULL_METALS > 0 THEN 1 ELSE 0 END                                    PRED_OLD_BODY,
             CASE WHEN B.ATTRIBUTE7 IS NOT NULL THEN 1 ELSE NVL(EXP.EXPANDED_MODELS, 0) END
               * CASE WHEN MS.FULL_METALS + MS.PARTIAL_METALS > 0 OR B.ATTRIBUTE8 = 'N' OR B.ATTRIBUTE12 = 'Y' THEN 1 ELSE 0 END PRED_EMPTYASIS,
             CASE WHEN B.ATTRIBUTE7 IS NULL AND NVL(EXP.EXPANDED_MODELS, 0) = 0 THEN '(가) 모델 확장 0'
                  WHEN MS.FULL_METALS = 0 AND MS.PARTIAL_METALS > 0 THEN '(나) 금속 전부 부분입력 → 현행 BODY 에서 탈락'
                  WHEN MS.FULL_METALS = 0 THEN '(라) 금속 키 전부 공란 → 저장 대상 없음'
                  ELSE 'OK' END REASON
        FROM B LEFT JOIN EXP ON EXP.UPLOAD_ID = B.UPLOAD_ID JOIN MS ON MS.UPLOAD_ID = B.UPLOAD_ID)
SELECT PLAN_YYYYMM, REASON, COUNT(*) FILE_ROWS, SUM(EXPANDED_MODELS) EXPANDED_MODELS,
       SUM(PRED_OLD_BODY) PRED_MODEL_ROWS_OLD_BODY, SUM(PRED_EMPTYASIS) PRED_MODEL_ROWS_EMPTYASIS
  FROM R
 GROUP BY ROLLUP(PLAN_YYYYMM, REASON)
 ORDER BY PLAN_YYYYMM NULLS LAST, REASON NULLS LAST;

-- [4] 실제 저장 결과 — 배치 시각 이후 그 배치 계정이 저장한 메탈링크 원장 (모델 1건 = 금속 행 여러 개)
SELECT PLAN_YYYYMM,
       COUNT(*) METAL_ROWS,
       COUNT(DISTINCT END_CUSTOMER || '|' || PROJECT_CODE || '|' || ITEM_ID || '|' || SCM_SITE_ID || '|' || CURRENCY || '|' || FCST_TYPE) MODEL_ROWS,
       COUNT(DISTINCT PROJECT_CODE || '|' || SCM_SITE_ID || '|' || CURRENCY || '|' || FCST_TYPE) COMBOS
  FROM DM_BPS_METAL_LINK_PRICE
 WHERE DIVISION_ID = '&P_DIV'
   AND LAST_UPDATED_BY = (SELECT MAX(CREATED_BY) FROM SCM_ADM_EXCEL_UPLOAD WHERE PROGRAM_ID LIKE 'DMF0074%' AND CREATION_DATE = TO_DATE('&P_BATCH', 'YYYY-MM-DD HH24:MI:SS'))
   AND LAST_UPDATE_DATE >= TO_DATE('&P_BATCH', 'YYYY-MM-DD HH24:MI:SS')
 GROUP BY ROLLUP(PLAN_YYYYMM)
 ORDER BY PLAN_YYYYMM NULLS LAST;

-- [7] 화면 조회 건수 대사 — 조회 그리드 1행 = 원장 그룹(Plan·EndCustomer·Project·Plant·Model·Site·Currency·FCST·Exception·Energy)
--     조회 기간(파일 Plan 202610~202612) 원장 전체를 그리드 단위로 세고, 이번 배치 계정·시각 이후 갱신분과 그 외로 나눔
--     GRID_ROWS 합계 = 화면 조회 건수(필터 ALL 기준) / BY_THIS_BATCH = 이번 업로드가 만들거나 갱신한 행 / OTHER = 기존 행
SELECT PLAN_YYYYMM,
       COUNT(*) GRID_ROWS,
       SUM(CASE WHEN UPD_BY = (SELECT MAX(CREATED_BY) FROM SCM_ADM_EXCEL_UPLOAD WHERE PROGRAM_ID LIKE 'DMF0074%' AND CREATION_DATE = TO_DATE('&P_BATCH', 'YYYY-MM-DD HH24:MI:SS'))
                 AND UPD_AT >= TO_DATE('&P_BATCH', 'YYYY-MM-DD HH24:MI:SS') THEN 1 ELSE 0 END) BY_THIS_BATCH,
       SUM(CASE WHEN UPD_BY = (SELECT MAX(CREATED_BY) FROM SCM_ADM_EXCEL_UPLOAD WHERE PROGRAM_ID LIKE 'DMF0074%' AND CREATION_DATE = TO_DATE('&P_BATCH', 'YYYY-MM-DD HH24:MI:SS'))
                 AND UPD_AT >= TO_DATE('&P_BATCH', 'YYYY-MM-DD HH24:MI:SS') THEN 0 ELSE 1 END) OTHER_EXISTING
  FROM (SELECT PLAN_YYYYMM, END_CUSTOMER, PROJECT_CODE, PLANT_SITE_ID, ITEM_ID, METAL_LINK_YN, SCM_SITE_ID, CURRENCY, FCST_TYPE,
               METAL_EXCEPTION_YN, ENERGY, MAX(LAST_UPDATED_BY) UPD_BY, MAX(LAST_UPDATE_DATE) UPD_AT
          FROM DM_BPS_METAL_LINK_PRICE
         WHERE DIVISION_ID = '&P_DIV' AND PLAN_YYYYMM BETWEEN '202610' AND '202612'
         GROUP BY PLAN_YYYYMM, END_CUSTOMER, PROJECT_CODE, PLANT_SITE_ID, ITEM_ID, METAL_LINK_YN, SCM_SITE_ID, CURRENCY, FCST_TYPE,
                  METAL_EXCEPTION_YN, ENERGY)
 GROUP BY ROLLUP(PLAN_YYYYMM)
 ORDER BY PLAN_YYYYMM NULLS LAST;

-- [8] 원장 → 화면 탈락 확인 — 조회 SP(P_DMF0074_GET_METAL_LINK_PRICE) 최종 SELECT 의
--     INNER JOIN SCM_MST_SSO_DEPT_INFO DI ON DI.DEPT_ID = SITE_ITEM.DEPT_ID  (팀 = Sales Site·Project·Model 의 DEPT_ID)
--     → SITE_ITEM.DEPT_ID 가 비었거나 부서 마스터에 없는 모델은 원장에 있어도 조회되지 않음
--     SCREEN_VISIBLE = 'N' 행이 192 - 180 = 12 와 일치하면 원인 확정
SELECT G.PLAN_YYYYMM, G.PROJECT_CODE, G.SCM_SITE_ID, G.ITEM_ID, G.CURRENCY, G.FCST_TYPE,
       SI.DEPT_ID SITE_ITEM_DEPT_ID,
       CASE WHEN SI.ITEM_ID IS NULL THEN 'SITE_ITEM 없음'
            WHEN SI.DEPT_ID IS NULL THEN 'SITE_ITEM.DEPT_ID 공란'
            WHEN DI.DEPT_ID IS NULL THEN '부서 마스터(SSO_DEPT_INFO)에 없음'
            ELSE 'OK' END DEPT_CHECK,
       CASE WHEN DI.DEPT_ID IS NOT NULL AND LUP.SEGMENT1 IS NOT NULL THEN 'Y' ELSE 'N' END SCREEN_VISIBLE
  FROM (SELECT DISTINCT DIVISION_ID, PLAN_YYYYMM, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, CURRENCY, FCST_TYPE
          FROM DM_BPS_METAL_LINK_PRICE
         WHERE DIVISION_ID = '&P_DIV' AND PLAN_YYYYMM BETWEEN '202610' AND '202612') G
  LEFT JOIN SCM_MST_SITE_ITEM SI
         ON SI.DIVISION_ID = G.DIVISION_ID AND SI.PROJECT_CODE = G.PROJECT_CODE
        AND SI.SCM_SITE_ID = G.SCM_SITE_ID AND SI.ITEM_ID = G.ITEM_ID
  LEFT JOIN SCM_MST_SSO_DEPT_INFO DI ON DI.DEPT_ID = SI.DEPT_ID
  LEFT JOIN SCM_ADM_LOOKUP_MASTER_DETAIL LUP
         ON LUP.LOOKUP_TYPE = 'SALES_TYPE_CODE' AND LUP.VALID_YN = 'Y' AND LUP.SEGMENT4 <> 'FREE' AND LUP.SEGMENT1 = G.FCST_TYPE
 ORDER BY SCREEN_VISIBLE, G.PROJECT_CODE, G.SCM_SITE_ID, G.ITEM_ID, G.PLAN_YYYYMM;
