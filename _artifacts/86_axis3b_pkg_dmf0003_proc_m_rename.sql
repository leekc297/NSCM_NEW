--==============================================================================
-- 86_axis3b_pkg_dmf0003_proc_m_rename.sql
-- AXIS 3-B PKG_DMF0003 fix — PROC_M COL_NM rename (O_ prefix 누락)
--
-- 현황:
--   SP signature: O_RC1 (OUT) + O_RESULT_CURSOR (OUT) — dual cursor ✓
--   PROC_M COL_NM: 'RC1' / 'RESULT_CURSOR' (O_ prefix 누락 — 비표준)
--   API_M routing: 없음 (dead SP) — 다만 표준 정합 차원에서 fix
--
-- fix:
--   UPDATE COL_NM: 'RC1' → 'o_rc1' / 'RESULT_CURSOR' → 'O_RESULT_CURSOR'
--==============================================================================
SET DEFINE OFF
SET SERVEROUTPUT ON
SET FEEDBACK ON
WHENEVER SQLERROR EXIT FAILURE

PROMPT === BEFORE ===
SELECT SORT_ORD, COL_NM, COL_TP_CD, DATA_TP_CD FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM='PKG_DMF0003.P_DMF0003_GET_BUCKET_TYPE_CODE' ORDER BY SORT_ORD;

PROMPT === UPDATE PROC_M COL_NM ===
UPDATE SCM_MGR.SCM_ADM_PROC_M SET COL_NM='o_rc1'
 WHERE PROC_NM='PKG_DMF0003.P_DMF0003_GET_BUCKET_TYPE_CODE' AND COL_NM='RC1';

UPDATE SCM_MGR.SCM_ADM_PROC_M SET COL_NM='O_RESULT_CURSOR'
 WHERE PROC_NM='PKG_DMF0003.P_DMF0003_GET_BUCKET_TYPE_CODE' AND COL_NM='RESULT_CURSOR';

COMMIT;

PROMPT === AFTER ===
SELECT SORT_ORD, COL_NM, COL_TP_CD, DATA_TP_CD FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM='PKG_DMF0003.P_DMF0003_GET_BUCKET_TYPE_CODE' ORDER BY SORT_ORD;
EXIT;
