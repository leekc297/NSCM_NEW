-- BLOCK 4: PROC_M
-- ---------------------------------------------------------------------------
PROMPT === BLOCK 4: PROC_M ===
DELETE FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM IN ('P_SYS0015_GET_PROGRAM_LIST_M', 'P_SYS0015_SAVE_PROGRAM_M');

INSERT INTO SCM_MGR.SCM_ADM_PROC_M (PROC_NM, COL_NM, COL_TP_CD, DATA_TP_CD, SORT_ORD, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT NEW.PROC_NM, NEW.COL_NM, NEW.COL_TP_CD, NEW.DATA_TP_CD, NEW.SORT_ORD, NEW.CREATED_BY, NEW.CREATION_DATE, NEW.LAST_UPDATED_BY, NEW.LAST_UPDATE_DATE
  FROM (
  -- GET LIST: 1 IN (search) + 2 OUT (o_rc1, O_RESULT_CURSOR)
  SELECT 'P_SYS0015_GET_PROGRAM_LIST_M' AS PROC_NM, 'search' AS COL_NM, 'IN' AS COL_TP_CD, 'VARCHAR' AS DATA_TP_CD, 1 AS SORT_ORD, 'system' AS CREATED_BY, SYSDATE AS CREATION_DATE, 'system' AS LAST_UPDATED_BY, SYSDATE AS LAST_UPDATE_DATE FROM DUAL UNION ALL
  SELECT 'P_SYS0015_GET_PROGRAM_LIST_M', 'o_rc1',           'OUT', 'CURSOR',      2, 'system', SYSDATE, 'system', SYSDATE FROM DUAL UNION ALL
  SELECT 'P_SYS0015_GET_PROGRAM_LIST_M', 'O_RESULT_CURSOR', 'OUT', 'PROC_RESULT', 3, 'system', SYSDATE, 'system', SYSDATE FROM DUAL UNION ALL
  -- SAVE: 2 IN (sesUserId, data CLOB) + 1 OUT (O_RESULT_CURSOR)
  SELECT 'P_SYS0015_SAVE_PROGRAM_M',     'sesUserId',       'IN',  'VARCHAR',     1, 'system', SYSDATE, 'system', SYSDATE FROM DUAL UNION ALL
  SELECT 'P_SYS0015_SAVE_PROGRAM_M',     'data',            'IN',  'CLOB',        2, 'system', SYSDATE, 'system', SYSDATE FROM DUAL UNION ALL
  SELECT 'P_SYS0015_SAVE_PROGRAM_M',     'O_RESULT_CURSOR', 'OUT', 'PROC_RESULT', 3, 'system', SYSDATE, 'system', SYSDATE FROM DUAL
) NEW;

