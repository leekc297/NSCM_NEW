SET DEFINE OFF
SET SERVEROUTPUT ON
SET FEEDBACK ON
WHENEVER SQLERROR EXIT FAILURE

-- ---------------------------------------------------------------------------
-- BLOCK 1: SCM_ADM_PROGRAM 테이블 (신규)
-- ---------------------------------------------------------------------------
PROMPT === BLOCK 1: DDL ===
DECLARE
    V_CNT NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_CNT FROM ALL_TABLES WHERE OWNER='SCM_MGR' AND TABLE_NAME='SCM_ADM_PROGRAM';
    IF V_CNT = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE SCM_MGR.SCM_ADM_PROGRAM (
            PROGRAM_ID       VARCHAR2(50)   NOT NULL,
            PROGRAM_NAME     VARCHAR2(200)  NOT NULL,
            PROGRAM_PATH     VARCHAR2(500)  NOT NULL,
            CLASS_NAME       VARCHAR2(500)  NOT NULL,
            USE_YN           CHAR(1)        DEFAULT ''Y'' NOT NULL,
            REGT_USER_ID     VARCHAR2(100),
            CREATED_BY       VARCHAR2(100)  DEFAULT ''system'' NOT NULL,
            CREATION_DATE    DATE           DEFAULT SYSDATE NOT NULL,
            LAST_UPDATED_BY  VARCHAR2(100)  DEFAULT ''system'' NOT NULL,
            LAST_UPDATE_DATE DATE           DEFAULT SYSDATE NOT NULL,
            CONSTRAINT PK_SCM_ADM_PROGRAM PRIMARY KEY (PROGRAM_ID)
        )';
        DBMS_OUTPUT.PUT_LINE('Created SCM_ADM_PROGRAM');
    ELSE
        DBMS_OUTPUT.PUT_LINE('SCM_ADM_PROGRAM already exists');
    END IF;
END;
/

-- ---------------------------------------------------------------------------
-- BLOCK 2: SHEET_COLUMNS (main 5 col)
-- ---------------------------------------------------------------------------
PROMPT === BLOCK 2: SHEET_COLUMNS ===
INSERT INTO SCM_MGR.SCM_MST_SHEET_COLUMNS
