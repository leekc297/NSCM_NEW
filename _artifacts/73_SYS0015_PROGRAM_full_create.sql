WHERE NOT EXISTS (
  SELECT 1 FROM SCM_MGR.SCM_MST_SHEET_COLUMNS X
   WHERE X.PROGRAM_ID = NEW.PROGRAM_ID AND X.SHEET_NAME = NEW.SHEET_NAME AND X.COLUMN_NAME = NEW.COLUMN_NAME
