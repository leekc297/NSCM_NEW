   VALID_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT NEW.PROGRAM_ID, NEW.SHEET_NAME, NEW.COLUMN_NAME, NEW.COLUMN_LABEL_NAME, NEW.SORT_ORDER_NO, NEW.COLUMN_WIDTH,
       NEW.FIXED_FLAG, NEW.VISIBLE_FLAG, NEW.HORIZONTAL_ALIGN_CODE, NEW.CELL_CONTROL_OBJECT_TYPE_CODE,
       NEW.VALID_YN, NEW.CREATED_BY, NEW.CREATION_DATE, NEW.LAST_UPDATED_BY, NEW.LAST_UPDATE_DATE
  FROM (
  SELECT 'SYS0015' AS PROGRAM_ID, 'main' AS SHEET_NAME, 'PROGRAM_ID' AS COLUMN_NAME, 'Program ID' AS COLUMN_LABEL_NAME, 10 AS SORT_ORDER_NO, 150 AS COLUMN_WIDTH, 'N' AS FIXED_FLAG, 'Y' AS VISIBLE_FLAG, 'Left' AS HORIZONTAL_ALIGN_CODE, 'S' AS CELL_CONTROL_OBJECT_TYPE_CODE, 'Y' AS VALID_YN, 'system' AS CREATED_BY, SYSDATE AS CREATION_DATE, 'system' AS LAST_UPDATED_BY, SYSDATE AS LAST_UPDATE_DATE FROM DUAL UNION ALL
  SELECT 'SYS0015','main','PROGRAM_NAME','Program Name', 20, 200,'N','Y','Left',  'S','Y','system',SYSDATE,'system',SYSDATE FROM DUAL UNION ALL
  SELECT 'SYS0015','main','PROGRAM_PATH','Program Path', 30, 250,'N','Y','Left',  'S','Y','system',SYSDATE,'system',SYSDATE FROM DUAL UNION ALL
  SELECT 'SYS0015','main','CLASS_NAME',  'Class Name',   40, 350,'N','Y','Left',  'S','Y','system',SYSDATE,'system',SYSDATE FROM DUAL UNION ALL
  SELECT 'SYS0015','main','USE_YN',      'Use Y/N',      50,  80,'N','Y','Center','S','Y','system',SYSDATE,'system',SYSDATE FROM DUAL
