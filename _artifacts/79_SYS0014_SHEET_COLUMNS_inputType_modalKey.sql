--==============================================================================
-- 79_SYS0014_SHEET_COLUMNS_inputType_modalKey.sql
-- 목적: SYS0014 SHEET_COLUMNS 의 INPUT_TP_CD (필수/선택) + ATTRIBUTE1 (modalKey) 보강
--
-- INPUT_TP_CD 표준:
--   'MI' = MANDATORY_INSERT_ONLY (신규 input only — PK 같은 필드, INSERT 시만 편집)
--   'M'  = MANDATORY (always required)
--   'OI' = OPTIONAL_INSERT_ONLY
--   'O'  = OPTIONAL (always editable)
--   'S'  = STATIC (조회 전용)
--
-- ATTRIBUTE1 = modal key (popup cell)
-- CELL_CONTROL_OBJECT_TYPE_CODE: 'FPModal' for popup cell
--==============================================================================
SET DEFINE OFF
SET SERVEROUTPUT ON
SET FEEDBACK ON
WHENEVER SQLERROR EXIT FAILURE

-- main (Group)
UPDATE SCM_MGR.SCM_MST_SHEET_COLUMNS SET INPUT_TP_CD='MI' WHERE PROGRAM_ID='SYS0014' AND SHEET_NAME='main' AND COLUMN_NAME='USER_GR_ID';
UPDATE SCM_MGR.SCM_MST_SHEET_COLUMNS SET INPUT_TP_CD='M'  WHERE PROGRAM_ID='SYS0014' AND SHEET_NAME='main' AND COLUMN_NAME='USER_GR_NM';
UPDATE SCM_MGR.SCM_MST_SHEET_COLUMNS SET INPUT_TP_CD='O'  WHERE PROGRAM_ID='SYS0014' AND SHEET_NAME='main' AND COLUMN_NAME='USE_YN';

-- userInfo (USER popup cell on USER_ID via FPModal)
UPDATE SCM_MGR.SCM_MST_SHEET_COLUMNS SET INPUT_TP_CD='MI', CELL_CONTROL_OBJECT_TYPE_CODE='FPModal', ATTRIBUTE1='SsoUser'
 WHERE PROGRAM_ID='SYS0014' AND SHEET_NAME='userInfo' AND COLUMN_NAME='USER_ID';
UPDATE SCM_MGR.SCM_MST_SHEET_COLUMNS SET INPUT_TP_CD='S' WHERE PROGRAM_ID='SYS0014' AND SHEET_NAME='userInfo' AND COLUMN_NAME='USER_NM';
UPDATE SCM_MGR.SCM_MST_SHEET_COLUMNS SET INPUT_TP_CD='S' WHERE PROGRAM_ID='SYS0014' AND SHEET_NAME='userInfo' AND COLUMN_NAME='DEPT_NM';
UPDATE SCM_MGR.SCM_MST_SHEET_COLUMNS SET INPUT_TP_CD='O' WHERE PROGRAM_ID='SYS0014' AND SHEET_NAME='userInfo' AND COLUMN_NAME='USE_YN';

-- division/plant/customer
UPDATE SCM_MGR.SCM_MST_SHEET_COLUMNS SET INPUT_TP_CD='MI' WHERE PROGRAM_ID='SYS0014' AND SHEET_NAME IN ('division','plant','customer') AND COLUMN_NAME='UNIT_ID';
UPDATE SCM_MGR.SCM_MST_SHEET_COLUMNS SET INPUT_TP_CD='O'  WHERE PROGRAM_ID='SYS0014' AND SHEET_NAME IN ('division','plant','customer') AND COLUMN_NAME IN ('UPPR_UNIT_ID','EDIT_YN','USE_YN');

COMMIT;

SELECT SHEET_NAME, COLUMN_NAME, INPUT_TP_CD, CELL_CONTROL_OBJECT_TYPE_CODE, ATTRIBUTE1
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID='SYS0014'
 ORDER BY SHEET_NAME, SORT_ORDER_NO;
EXIT;
