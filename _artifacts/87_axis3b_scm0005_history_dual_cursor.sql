PROMPT === ALTER SP body (single -> dual cursor) ===
CREATE OR REPLACE EDITIONABLE PROCEDURE SCM_MGR.P_SCM0005_GET_HISTORY
(
    p_queryId        IN  VARCHAR2,
    O_RC1            OUT SYS_REFCURSOR,
    O_RESULT_CURSOR  OUT SYS_REFCURSOR
)
/*
 * Program ID   : P_SCM0005_GET_HISTORY
 * Description  : Dynamic Query 실행 history 조회 (SCM_ADM_DQ_EXECUTE_H)
 *                AS-IS 대응 SP 없음 — TO-BE 신규 (PR_DM_ADM_DQ_EXECUTE_HIST 가 INSERT 한 history 의 조회).
 * History
 * 2026.06.04   gyucheollee   Initial — TO-BE 신규
 * 2026.06.06   gyucheollee   Dual cursor 표준화 (O_RESULT_CURSOR 추가) — AXIS 3-B audit fix
 */
AS
BEGIN
    OPEN O_RC1 FOR
        SELECT h.HISTORY_SEQ,
               h.DQ_ID,
               h.DQ_TEXT,
               h.CREATED_BY,
               h.CREATION_DATE,
               h.LAST_UPDATED_BY,
               h.LAST_UPDATE_DATE
          FROM SCM_ADM_DQ_EXECUTE_H h
         WHERE (p_queryId IS NULL OR p_queryId = '' OR TO_CHAR(h.DQ_ID) = p_queryId)
         ORDER BY h.CREATION_DATE DESC, h.HISTORY_SEQ DESC;

    OPEN O_RESULT_CURSOR FOR
        SELECT '0' AS CODE, 'SUCCESS' AS MSG FROM DUAL;
END P_SCM0005_GET_HISTORY;
/

PROMPT === ADD PROC_M O_RESULT_CURSOR row (NOT EXISTS 멱등) ===
INSERT INTO SCM_MGR.SCM_ADM_PROC_M
  (PROC_NM, COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'P_SCM0005_GET_HISTORY', 'O_RESULT_CURSOR', 'PROC_RESULT', 'OUT', 3, 'SYSTEM', SYSDATE, 'SYSTEM', SYSDATE FROM DUAL
 WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_PROC_M
                    WHERE PROC_NM='P_SCM0005_GET_HISTORY' AND COL_NM='O_RESULT_CURSOR' AND COL_TP_CD='OUT');

COMMIT;

