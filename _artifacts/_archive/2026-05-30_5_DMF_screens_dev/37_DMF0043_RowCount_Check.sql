PROMPT === SITE_ITEM_BASE rows (분류 unique combos) ===
WITH SITE_ITEM_BASE AS (
    SELECT A.DIVISION_ID, TEAM.DEPARTMENT_ID, TEAM.DEPT_ID,
           NVL(A.CUST_GROUP, ' ') AS END_CUST_REPORT,
           NVL(A.CUST_GROUP_DTL, ' ') AS SOLDTO_CUST_REPORT,
           NVL(C.FORECAST_INFO_PRODUCT_GROUP, ' ') AS PRODUCT_GROUP,
           NVL(C.FORECAST_INFO_BIZ_TYPE, ' ') AS DM_BIZ_TYPE
      FROM SCM_MST_SITE_ITEM A
        INNER JOIN SCM_MST_SITE B ON A.DIVISION_ID = B.DIVISION_ID AND A.SCM_SITE_ID = B.SCM_SITE_ID
        INNER JOIN DM_MST_ITEM_SINGLE_V C ON A.DIVISION_ID = C.DIVISION_ID AND A.ITEM_ID = C.ITEM_ID
        LEFT JOIN (SELECT U.USER_ID, CC.DEPT_ID, DD.DEPT_ID AS DEPARTMENT_ID
                     FROM SCM_MST_SSO_USER_INFO U
                       INNER JOIN SCM_MST_SSO_DEPT_INFO CC ON U.DEPT_ID = CC.DEPT_ID
                       INNER JOIN SCM_MST_SSO_DEPT_INFO DD ON CC.UPPER_DEPT_ID = DD.DEPT_ID) TEAM
          ON TEAM.USER_ID IN (SELECT TOKEN FROM TABLE(FN_STRING_SPLIT(A.OWNER, ',')))
     WHERE A.DIVISION_ID = '40' AND B.SITE_TYPE = 'SALES' AND A.VALID_YN = 'Y'
     GROUP BY A.DIVISION_ID, TEAM.DEPARTMENT_ID, TEAM.DEPT_ID,
              NVL(A.CUST_GROUP, ' '), NVL(A.CUST_GROUP_DTL, ' '),
              NVL(C.FORECAST_INFO_PRODUCT_GROUP, ' '), NVL(C.FORECAST_INFO_BIZ_TYPE, ' ')
)
SELECT 'A-SITE_ITEM_combos' nm, COUNT(*) cnt FROM SITE_ITEM_BASE
UNION ALL
SELECT 'B-WITH_DTL_long', COUNT(*) FROM SITE_ITEM_BASE SI
  LEFT JOIN DM_MST_CONTRIBUTE_RATIO_DTL DT ON DT.VER_SEQ = 12
   AND DT.DEPARTMENT_ID = SI.DEPARTMENT_ID AND DT.DEPT_ID = SI.DEPT_ID
   AND DT.END_CUST_REPORT = SI.END_CUST_REPORT AND DT.SOLDTO_CUST_REPORT = SI.SOLDTO_CUST_REPORT
   AND DT.PRODUCT_GROUP = SI.PRODUCT_GROUP AND DT.DM_BIZ_TYPE = SI.DM_BIZ_TYPE
UNION ALL
SELECT 'C-MATCHED_dtl_only', COUNT(*) FROM SITE_ITEM_BASE SI
  INNER JOIN DM_MST_CONTRIBUTE_RATIO_DTL DT ON DT.VER_SEQ = 12
   AND DT.DEPARTMENT_ID = SI.DEPARTMENT_ID AND DT.DEPT_ID = SI.DEPT_ID
   AND DT.END_CUST_REPORT = SI.END_CUST_REPORT AND DT.SOLDTO_CUST_REPORT = SI.SOLDTO_CUST_REPORT
   AND DT.PRODUCT_GROUP = SI.PRODUCT_GROUP AND DT.DM_BIZ_TYPE = SI.DM_BIZ_TYPE;
EXIT
