-- 1) DMF0043 의 모든 sheet → API_URL 매핑
SELECT 'A-BTN_MAP' SECT, T1.SHT_NM SHT, T1.MNU_BTN_CD BTN,
       T1.API_ID, T2.API_URL
  FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M T1
  LEFT JOIN SCM_MGR.SCM_ADM_API_M T2 ON T1.API_ID = T2.API_ID
 WHERE T1.MNU_ID = 'DMF0043'
 ORDER BY T1.SHT_NM, T1.MNU_BTN_CD;

-- 2) standalone SP 의 PROC 메타
SELECT 'B-PROC_META' SECT, COL_NM, COL_TP_CD, DATA_TP_CD, SORT_ORD
  FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM = 'P_DMF0043_GET_CONTRIBUTE_MAIN_DATA'
 ORDER BY SORT_ORD;

-- 3) DB SP 존재 + STATUS
SELECT 'C-PROC_OBJ' SECT, OBJECT_TYPE, STATUS, CREATED, LAST_DDL_TIME
  FROM ALL_OBJECTS
 WHERE OWNER = 'SCM_MGR'
   AND OBJECT_NAME = 'P_DMF0043_GET_CONTRIBUTE_MAIN_DATA'
   AND OBJECT_TYPE = 'PROCEDURE';

-- 4) DM_MST_CONTRIBUTE_VER (Year 콤보 데이터)
SELECT 'D-VER' SECT, VER_SEQ, YYYY, VERSION_NM, VALID_YN
  FROM SCM_MGR.DM_MST_CONTRIBUTE_VER
 ORDER BY YYYY DESC;

-- 5) DM_MST_CONTRIBUTE_RATIO_DTL 의 VER_SEQ 별 행수
SELECT 'E-DTL_CNT' SECT, VER_SEQ, COUNT(*) ROW_CNT
  FROM SCM_MGR.DM_MST_CONTRIBUTE_RATIO_DTL
 GROUP BY VER_SEQ
 ORDER BY VER_SEQ;
