PROMPT === 2. PROC_M RESYNC (o_rc + O_RESULT_CURSOR) ===

DELETE FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM = 'P_SYS0012_GET_APPROVAL_LIST';

INSERT INTO SCM_MGR.SCM_ADM_PROC_M (PROC_NM, COL_NM, COL_TP_CD, DATA_TP_CD, SORT_ORD, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT NEW.PROC_NM, NEW.COL_NM, NEW.COL_TP_CD, NEW.DATA_TP_CD, NEW.SORT_ORD, NEW.CREATED_BY, NEW.CREATION_DATE, NEW.LAST_UPDATED_BY, NEW.LAST_UPDATE_DATE
  FROM (
  SELECT 'P_SYS0012_GET_APPROVAL_LIST' AS PROC_NM, 'sesUserId' AS COL_NM,'IN' AS COL_TP_CD,'VARCHAR' AS DATA_TP_CD, 1 AS SORT_ORD,'system' AS CREATED_BY,SYSDATE AS CREATION_DATE,'system' AS LAST_UPDATED_BY,SYSDATE AS LAST_UPDATE_DATE FROM DUAL UNION ALL
  SELECT 'P_SYS0012_GET_APPROVAL_LIST','userId',         'IN', 'VARCHAR',     2,'system',SYSDATE,'system',SYSDATE FROM DUAL UNION ALL
  SELECT 'P_SYS0012_GET_APPROVAL_LIST','startDate',      'IN', 'VARCHAR',     3,'system',SYSDATE,'system',SYSDATE FROM DUAL UNION ALL
  SELECT 'P_SYS0012_GET_APPROVAL_LIST','endDate',        'IN', 'VARCHAR',     4,'system',SYSDATE,'system',SYSDATE FROM DUAL UNION ALL
  SELECT 'P_SYS0012_GET_APPROVAL_LIST','status',         'IN', 'VARCHAR',     5,'system',SYSDATE,'system',SYSDATE FROM DUAL UNION ALL
  SELECT 'P_SYS0012_GET_APPROVAL_LIST','o_rc',           'OUT','CURSOR',      6,'system',SYSDATE,'system',SYSDATE FROM DUAL UNION ALL
  SELECT 'P_SYS0012_GET_APPROVAL_LIST','O_RESULT_CURSOR','OUT','PROC_RESULT', 7,'system',SYSDATE,'system',SYSDATE FROM DUAL
) NEW;

