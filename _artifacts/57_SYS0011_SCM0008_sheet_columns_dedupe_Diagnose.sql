-- A. sheet 별 TOT / DISTINCT
SELECT SHEET_NAME,
       COUNT(*) AS TOT,
       COUNT(DISTINCT COLUMN_NAME) AS DISTINCT_CNT
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID = 'SYS0011'
 GROUP BY SHEET_NAME
 ORDER BY SHEET_NAME;

-- B. duplicate column 인벤토리 (어떤 COLUMN_NAME 이 2번인지)
SELECT SHEET_NAME, COLUMN_NAME, COUNT(*) AS CNT
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID = 'SYS0011'
 GROUP BY SHEET_NAME, COLUMN_NAME
HAVING COUNT(*) > 1
 ORDER BY SHEET_NAME, COLUMN_NAME;

-- C. duplicate row 의 ROWID + 핵심 attr (어떤 row 가 유지되고 어떤 row 가 삭제될지 미리 확인)
SELECT ROWID, SHEET_NAME, COLUMN_NAME, SORT_ORDER_NO, COLUMN_WIDTH, VISIBLE_FLAG,
       (CASE WHEN ROWID = (
          SELECT MIN(Y.ROWID) FROM SCM_MGR.SCM_MST_SHEET_COLUMNS Y
           WHERE Y.PROGRAM_ID = 'SYS0011'
             AND Y.SHEET_NAME = X.SHEET_NAME
             AND Y.COLUMN_NAME = X.COLUMN_NAME
       ) THEN 'KEEP' ELSE 'DELETE' END) AS ACTION
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS X
 WHERE PROGRAM_ID = 'SYS0011'
   AND (SHEET_NAME, COLUMN_NAME) IN (
     SELECT SHEET_NAME, COLUMN_NAME
       FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
      WHERE PROGRAM_ID = 'SYS0011'
      GROUP BY SHEET_NAME, COLUMN_NAME
     HAVING COUNT(*) > 1
   )
 ORDER BY SHEET_NAME, COLUMN_NAME, ROWID;

-- D. KEEP / DELETE 카운트 사전 확인
SELECT SHEET_NAME,
       SUM(CASE WHEN ROWID = (
          SELECT MIN(Y.ROWID) FROM SCM_MGR.SCM_MST_SHEET_COLUMNS Y
           WHERE Y.PROGRAM_ID = 'SYS0011'
             AND Y.SHEET_NAME = X.SHEET_NAME
             AND Y.COLUMN_NAME = X.COLUMN_NAME
       ) THEN 1 ELSE 0 END) AS KEEP_CNT,
       SUM(CASE WHEN ROWID <> (
          SELECT MIN(Y.ROWID) FROM SCM_MGR.SCM_MST_SHEET_COLUMNS Y
           WHERE Y.PROGRAM_ID = 'SYS0011'
             AND Y.SHEET_NAME = X.SHEET_NAME
             AND Y.COLUMN_NAME = X.COLUMN_NAME
       ) THEN 1 ELSE 0 END) AS DELETE_CNT
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS X
 WHERE PROGRAM_ID = 'SYS0011'
 GROUP BY SHEET_NAME
 ORDER BY SHEET_NAME;
