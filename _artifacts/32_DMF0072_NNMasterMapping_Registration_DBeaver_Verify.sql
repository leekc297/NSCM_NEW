--==============================================================================
-- DMF0072_NNMasterMapping — 메타 등록 검증 (DBeaver 단일 SELECT UNION ALL)
--==============================================================================

SELECT 'BLOCK 1 MSG_M (MNU 3 + API 3×3=9 = 12)' BLOCK_NAME,
       (SELECT COUNT(*) FROM SCM_ADM_MSG_M WHERE MSG_ID IN (
          'MNU_DMF0072',
          'MSG_API_DMF0072_MAIN_SEARCH','MSG_API_DMF0072_MAIN_SAVE','MSG_API_DMF0072_TITLE_SEARCH')) ACTUAL,
       12 EXPECT_MIN, 'rows' UNIT FROM DUAL
UNION ALL
SELECT 'BLOCK 2 MNU_M (DMF0072)',
       (SELECT COUNT(*) FROM SCM_ADM_MNU_M WHERE MNU_ID = 'DMF0072'),
       1, 'rows' FROM DUAL
UNION ALL
SELECT 'BLOCK 4 API_M (DMF0072_* 3)',
       (SELECT COUNT(*) FROM SCM_ADM_API_M WHERE API_ID LIKE 'DMF0072_%'),
       3, 'rows' FROM DUAL
UNION ALL
SELECT 'BLOCK 5 MNU_BTN_MPG_M (DMF0072 routing 3)',
       (SELECT COUNT(*) FROM SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID = 'DMF0072'),
       3, 'rows' FROM DUAL
UNION ALL
SELECT 'BLOCK 6 SHEET_COLUMNS (DMF0072 main 22)',
       (SELECT COUNT(*) FROM SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID = 'DMF0072'),
       22, 'rows' FROM DUAL
UNION ALL
SELECT 'BLOCK 7a USER_GR_MNU_MPG_M (DMF0072)',
       (SELECT COUNT(*) FROM SCM_ADM_USER_GR_MNU_MPG_M WHERE MNU_ID = 'DMF0072' AND USE_YN = 'Y'),
       (SELECT COUNT(*) FROM SCM_ADM_USER_GR_MNU_MPG_M WHERE MNU_ID = 'DMF0020' AND USE_YN = 'Y'),
       'rows' FROM DUAL
UNION ALL
SELECT 'BLOCK 7b USER_GR_MNU_BTN_MPG_M (DMF0072 BTN)',
       (SELECT COUNT(*) FROM SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE MNU_ID = 'DMF0072' AND USE_YN = 'Y'),
       (SELECT COUNT(DISTINCT USER_GR_ID) FROM SCM_ADM_USER_GR_MNU_MPG_M WHERE MNU_ID = 'DMF0020' AND USE_YN = 'Y') * 3,
       'rows (GR × 3 routing)' FROM DUAL
ORDER BY BLOCK_NAME;
