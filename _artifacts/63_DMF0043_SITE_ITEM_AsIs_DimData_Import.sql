--       REPORT_GROUP3) 18 row 를 로컬 Docker Oracle 로 import.
--
-- 사고: 2026-05-26 CSV bulk load 시 ATTRIBUTE1/2 컬럼 빈값 + REPORT_GROUP3 컬럼 자체 누락
--       → DMF0043 화면 JOIN 매칭 0건 → 빈 grid.
--
-- 작성: 2026-06-01 / minyonglee1 (As-Is SP body 직접 분석 후)
--==============================================================================
SET DEFINE OFF
SET SERVEROUTPUT ON
SET FEEDBACK ON
WHENEVER SQLERROR EXIT FAILURE

PROMPT === BLOCK 1 : REPORT_GROUP3 컬럼 추가 (없는 경우) ===
DECLARE
    v_cnt NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_cnt FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME='SCM_MST_SITE_ITEM' AND COLUMN_NAME='REPORT_GROUP3';
    IF v_cnt = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE SCM_MGR.SCM_MST_SITE_ITEM ADD REPORT_GROUP3 VARCHAR2(100 CHAR)';
        DBMS_OUTPUT.PUT_LINE('REPORT_GROUP3 column added');
    ELSE
        DBMS_OUTPUT.PUT_LINE('REPORT_GROUP3 already exists');
    END IF;
END;
/

PROMPT === BLOCK 2 : MERGE — As-Is 18 row dim 데이터 ===
-- (DIVISION_ID, SCM_SITE_ID, ITEM_ID) 가 PK
MERGE INTO SCM_MGR.SCM_MST_SITE_ITEM T
USING (
  SELECT '40' AS DIVISION_ID, 'Acell_TW_NTC' AS SCM_SITE_ID, 'MCCM120010A1-GF' AS ITEM_ID, 'Acell' AS A1, 'Acell' AS A2, NULL AS RG3 FROM DUAL UNION ALL
  SELECT '40', 'BAE Systems_US_ENC', 'MCCH350040A1T002', 'BAE Systems', 'BAE Systems', '원통형' FROM DUAL UNION ALL
  SELECT '40', 'Boston Dynamics_US_WLM', 'MPCBDIQRPJ1E', 'Boston Dynamics', 'Boston Dynamics', '원통형' FROM DUAL UNION ALL
  SELECT '40', 'C-Tech_TW_TPE', 'MCCH335080B1T000', 'C-TECH', 'C-Tech_01', '원통형' FROM DUAL UNION ALL
  SELECT '40', 'EATON_HK_YUE', 'MCCH335080B1T000', 'EATON', 'EATON_01', '원통형' FROM DUAL UNION ALL
  SELECT '40', 'Desay_CN_HUI', 'MCU556172C10T000', 'Desay_CN', 'NT', '파우치형' FROM DUAL UNION ALL
  SELECT '40', 'ReBuild_US_NKP', 'MCCH350040A1T002', 'ReBuild', 'ReBuild', '원통형' FROM DUAL UNION ALL
  SELECT '40', 'Rivian Automotive_US_TUN', 'MCMM9314U0A1-014', 'RIVIAN AUTOMOTIVE', 'RIVIAN AUTOMOTIVE', '원통형' FROM DUAL UNION ALL
  SELECT '40', 'STL_TW_KHH', 'MCCH335080B1T000', 'STL', 'STL_01', '원통형' FROM DUAL UNION ALL
  SELECT '40', 'Trend Power Singapore_TW_HSZ', 'MCCH335080B1T000', 'Trend Power Singapore', 'Trend Power_01', '원통형' FROM DUAL
) S
ON (T.DIVISION_ID=S.DIVISION_ID AND T.SCM_SITE_ID=S.SCM_SITE_ID AND T.ITEM_ID=S.ITEM_ID)
WHEN MATCHED THEN UPDATE SET
    T.ATTRIBUTE1 = S.A1,
    T.ATTRIBUTE2 = S.A2,
    T.REPORT_GROUP3 = S.RG3;

COMMIT;

PROMPT === BLOCK 3 : 검증 ===
SELECT COUNT(*) AS A1_FILLED FROM SCM_MGR.SCM_MST_SITE_ITEM WHERE DIVISION_ID='40' AND ATTRIBUTE1 IS NOT NULL;
SELECT COUNT(*) AS A2_FILLED FROM SCM_MGR.SCM_MST_SITE_ITEM WHERE DIVISION_ID='40' AND ATTRIBUTE2 IS NOT NULL;
SELECT COUNT(*) AS RG3_FILLED FROM SCM_MGR.SCM_MST_SITE_ITEM WHERE DIVISION_ID='40' AND REPORT_GROUP3 IS NOT NULL;

PROMPT === BLOCK 4 : Sample ===
SELECT SCM_SITE_ID, ITEM_ID, ATTRIBUTE1, ATTRIBUTE2, REPORT_GROUP3
  FROM SCM_MGR.SCM_MST_SITE_ITEM
 WHERE DIVISION_ID='40' AND ATTRIBUTE1 IS NOT NULL
 ORDER BY SCM_SITE_ID;

EXIT;
