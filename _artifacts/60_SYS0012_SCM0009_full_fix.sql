-- ---------------------------------------------------------------------------
-- BLOCK 2: API_M — 3 API (SEARCH / APPROVE / REJECT) — Oracle SP routing
-- ---------------------------------------------------------------------------
PROMPT === BLOCK 2: API_M ===

INSERT INTO SCM_MGR.SCM_ADM_API_M (API_ID, API_URL, API_TP_CD, API_MSG_ID, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT NEW.API_ID, NEW.API_URL, NEW.API_TP_CD, NEW.API_MSG_ID, NEW.USE_YN, NEW.CREATED_BY, NEW.CREATION_DATE, NEW.LAST_UPDATED_BY, NEW.LAST_UPDATE_DATE
  FROM (
  SELECT 'API_SYS0012_GET_APPROVAL_LIST' AS API_ID,'P_SYS0012_GET_APPROVAL_LIST' AS API_URL,'POST' AS API_TP_CD,'MSG_API_SYS0012_MAIN_SEARCH' AS API_MSG_ID,'Y' AS USE_YN,'system' AS CREATED_BY,SYSDATE AS CREATION_DATE,'system' AS LAST_UPDATED_BY,SYSDATE AS LAST_UPDATE_DATE FROM DUAL UNION ALL
  SELECT 'API_SYS0012_APPROVE',          'P_SYS0012_APPROVE',          'POST','MSG_API_SYS0012_MAIN_APPROVE','Y','system',SYSDATE,'system',SYSDATE FROM DUAL UNION ALL
  SELECT 'API_SYS0012_REJECT',           'P_SYS0012_REJECT',           'POST','MSG_API_SYS0012_MAIN_REJECT', 'Y','system',SYSDATE,'system',SYSDATE FROM DUAL
) NEW
WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_API_M X WHERE X.API_ID = NEW.API_ID);

-- ---------------------------------------------------------------------------
-- BLOCK 3: MNU_BTN_MPG_M — SEARCH/APPROVE/REJECT 정정
--   기존 RETRIEVE → SEARCH 로 통일 (FE useTabProcQuery default 와 매칭)
--   기존 잘못된 API_ID (API_SCM0009_*) 를 새로운 API_ID (API_SYS0012_*) 로 정정
-- ---------------------------------------------------------------------------
PROMPT === BLOCK 3: MNU_BTN_MPG_M 정정 ===

-- 3.1 기존 RETRIEVE → SEARCH 로 update (없으면 INSERT)
MERGE INTO SCM_MGR.SCM_ADM_MNU_BTN_MPG_M T
USING (
  SELECT 'SYS0012' AS MNU_ID, 'main' AS SHT_NM, 'SEARCH' AS MNU_BTN_CD, 'API_SYS0012_GET_APPROVAL_LIST' AS API_ID FROM DUAL UNION ALL
  SELECT 'SYS0012',           'main',           'APPROVE',              'API_SYS0012_APPROVE'                     FROM DUAL UNION ALL
  SELECT 'SYS0012',           'main',           'REJECT',               'API_SYS0012_REJECT'                      FROM DUAL
) S
ON (T.MNU_ID = S.MNU_ID AND T.SHT_NM = S.SHT_NM AND T.MNU_BTN_CD = S.MNU_BTN_CD)
WHEN MATCHED THEN UPDATE SET T.API_ID = S.API_ID, T.USE_YN = 'Y', T.LAST_UPDATED_BY='system', T.LAST_UPDATE_DATE=SYSDATE
WHEN NOT MATCHED THEN INSERT (MNU_ID, SHT_NM, MNU_BTN_CD, API_ID, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
  VALUES (S.MNU_ID, S.SHT_NM, S.MNU_BTN_CD, S.API_ID, 'Y', 'system', SYSDATE, 'system', SYSDATE);

-- 3.2 기존 RETRIEVE row 삭제 (SEARCH 로 통합되었으므로)
DELETE FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M
 WHERE MNU_ID='SYS0012' AND SHT_NM='main' AND MNU_BTN_CD='RETRIEVE';

-- ---------------------------------------------------------------------------
-- BLOCK 4: PROC_M — 3 SP 시그니처 (BE 동적 SP 호출 인자 매핑)
-- ---------------------------------------------------------------------------
PROMPT === BLOCK 4: PROC_M ===

-- 4.1 P_SYS0012_GET_APPROVAL_LIST (3 IN: userId, startDate, endDate, status / 1 OUT)
--     주의: COL_NM 은 BE 자동 채움 키. sesUserId/sesLangCd/mnuId 는 자동 + camelCase JSON key.
INSERT INTO SCM_MGR.SCM_ADM_PROC_M (PROC_NM, COL_NM, COL_TP_CD, DATA_TP_CD, SORT_ORD, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT NEW.PROC_NM, NEW.COL_NM, NEW.COL_TP_CD, NEW.DATA_TP_CD, NEW.SORT_ORD, NEW.CREATED_BY, NEW.CREATION_DATE, NEW.LAST_UPDATED_BY, NEW.LAST_UPDATE_DATE
  FROM (
  SELECT 'P_SYS0012_GET_APPROVAL_LIST' AS PROC_NM,'sesUserId' AS COL_NM,'IN' AS COL_TP_CD,'VARCHAR' AS DATA_TP_CD, 1 AS SORT_ORD,'system' AS CREATED_BY,SYSDATE AS CREATION_DATE,'system' AS LAST_UPDATED_BY,SYSDATE AS LAST_UPDATE_DATE FROM DUAL UNION ALL
  SELECT 'P_SYS0012_GET_APPROVAL_LIST','userId',         'IN', 'VARCHAR',     2,'system',SYSDATE,'system',SYSDATE FROM DUAL UNION ALL
  SELECT 'P_SYS0012_GET_APPROVAL_LIST','startDate',      'IN', 'VARCHAR',     3,'system',SYSDATE,'system',SYSDATE FROM DUAL UNION ALL
  SELECT 'P_SYS0012_GET_APPROVAL_LIST','endDate',        'IN', 'VARCHAR',     4,'system',SYSDATE,'system',SYSDATE FROM DUAL UNION ALL
  SELECT 'P_SYS0012_GET_APPROVAL_LIST','status',         'IN', 'VARCHAR',     5,'system',SYSDATE,'system',SYSDATE FROM DUAL UNION ALL
  SELECT 'P_SYS0012_GET_APPROVAL_LIST','O_RESULT_CURSOR','OUT','PROC_RESULT', 6,'system',SYSDATE,'system',SYSDATE FROM DUAL UNION ALL
  SELECT 'P_SYS0012_APPROVE',          'sesUserId',      'IN', 'VARCHAR',     1,'system',SYSDATE,'system',SYSDATE FROM DUAL UNION ALL
  SELECT 'P_SYS0012_APPROVE',          'requestIds',     'IN', 'CLOB',        2,'system',SYSDATE,'system',SYSDATE FROM DUAL UNION ALL
  SELECT 'P_SYS0012_APPROVE',          'O_RESULT_CURSOR','OUT','PROC_RESULT', 3,'system',SYSDATE,'system',SYSDATE FROM DUAL UNION ALL
  SELECT 'P_SYS0012_REJECT',           'sesUserId',      'IN', 'VARCHAR',     1,'system',SYSDATE,'system',SYSDATE FROM DUAL UNION ALL
  SELECT 'P_SYS0012_REJECT',           'requestIds',     'IN', 'CLOB',        2,'system',SYSDATE,'system',SYSDATE FROM DUAL UNION ALL
  SELECT 'P_SYS0012_REJECT',           'rejectReason',   'IN', 'VARCHAR',     3,'system',SYSDATE,'system',SYSDATE FROM DUAL UNION ALL
  SELECT 'P_SYS0012_REJECT',           'O_RESULT_CURSOR','OUT','PROC_RESULT', 4,'system',SYSDATE,'system',SYSDATE FROM DUAL
) NEW
WHERE NOT EXISTS (
  SELECT 1 FROM SCM_MGR.SCM_ADM_PROC_M X
   WHERE X.PROC_NM = NEW.PROC_NM AND X.COL_NM = NEW.COL_NM AND X.COL_TP_CD = NEW.COL_TP_CD
);

-- ---------------------------------------------------------------------------
-- BLOCK 5: USER_GR_MNU_BTN_MPG_M — 권한 SEARCH (RETRIEVE 대체)
