WHENEVER SQLERROR CONTINUE;
SET DEFINE OFF;

-- 1. SCM_MST_FUTURE_PRICE -----------------------------------
DROP TABLE SCM_MST_FUTURE_PRICE CASCADE CONSTRAINTS;

CREATE TABLE SCM_MST_FUTURE_PRICE
( DIVISION_ID       VARCHAR2(30 CHAR) NOT NULL,
  PROJECT_CODE      VARCHAR2(50 CHAR) NOT NULL,
  SCM_SITE_ID       VARCHAR2(30 CHAR) NOT NULL,
  PLANT_SITE_ID     VARCHAR2(30 CHAR) NOT NULL,
  ITEM_ID           VARCHAR2(50 CHAR) NOT NULL,
  YYYYMMDD          VARCHAR2(8  CHAR) NOT NULL,
  CURRENCY          VARCHAR2(10 CHAR) NOT NULL,
  MEASURE           VARCHAR2(50 CHAR) NOT NULL,
  DOM_EXP           VARCHAR2(3  CHAR) NOT NULL,
  FCST_TYPE         VARCHAR2(20 CHAR) NOT NULL,
  INCOTERMS         VARCHAR2(10 CHAR) NOT NULL,
  PRICE             NUMBER(30,10)     NOT NULL,
  CREATED_BY        VARCHAR2(150 CHAR) NOT NULL,
  CREATION_DATE     DATE NOT NULL,
  LAST_UPDATED_BY   VARCHAR2(150 CHAR) NOT NULL,
  LAST_UPDATE_DATE  DATE NOT NULL,
  ATTRIBUTE1 VARCHAR2(150 CHAR), ATTRIBUTE2 VARCHAR2(150 CHAR),
  ATTRIBUTE3 VARCHAR2(150 CHAR), ATTRIBUTE4 VARCHAR2(150 CHAR),
  ATTRIBUTE5 VARCHAR2(150 CHAR), ATTRIBUTE6 VARCHAR2(150 CHAR),
  ATTRIBUTE7 VARCHAR2(150 CHAR), ATTRIBUTE8 VARCHAR2(150 CHAR),
  ATTRIBUTE9 VARCHAR2(150 CHAR), ATTRIBUTE10 VARCHAR2(150 CHAR)
);

CREATE UNIQUE INDEX PK_SCM_MST_FUTURE_PRICE ON SCM_MST_FUTURE_PRICE
  (DIVISION_ID,PROJECT_CODE,SCM_SITE_ID,PLANT_SITE_ID,ITEM_ID,YYYYMMDD,CURRENCY,MEASURE,DOM_EXP,FCST_TYPE,INCOTERMS);

ALTER TABLE SCM_MST_FUTURE_PRICE ADD CONSTRAINT PK_SCM_MST_FUTURE_PRICE PRIMARY KEY
  (DIVISION_ID,PROJECT_CODE,SCM_SITE_ID,PLANT_SITE_ID,ITEM_ID,YYYYMMDD,CURRENCY,MEASURE,DOM_EXP,FCST_TYPE,INCOTERMS) USING INDEX PK_SCM_MST_FUTURE_PRICE;

CREATE INDEX IX_YYYYMMDD_SCM_MST_FUTURE_PRICE ON SCM_MST_FUTURE_PRICE (YYYYMMDD,DIVISION_ID);

