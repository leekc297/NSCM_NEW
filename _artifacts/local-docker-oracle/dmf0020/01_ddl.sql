  BASIS_YYYYMM          VARCHAR2(6 CHAR),
  WEEK_NO               NUMBER(10,0),
  ISO_YYYYWW            VARCHAR2(6 CHAR),
  ISO_WEEK              VARCHAR2(2 CHAR),
