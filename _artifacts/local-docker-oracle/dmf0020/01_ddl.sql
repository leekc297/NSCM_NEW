CREATE UNIQUE INDEX PK_SCM_SYS_CALENDAR_U1 ON SCM_SYS_CALENDAR_M (BASIS_DATE);
ALTER TABLE SCM_SYS_CALENDAR_M ADD CONSTRAINT PK_SCM_SYS_CALENDAR_U1 PRIMARY KEY (BASIS_DATE) USING INDEX PK_SCM_SYS_CALENDAR_U1;
CREATE INDEX IDX_SCM_SYS_CALENDAR_N5 ON SCM_SYS_CALENDAR_M (CALENDAR_YYYY);
CREATE INDEX IDX_SCM_SYS_CALENDAR_N1 ON SCM_SYS_CALENDAR_M (BASIS_YYYYMM,WEEK_NO,ISO_YYYYWW);
