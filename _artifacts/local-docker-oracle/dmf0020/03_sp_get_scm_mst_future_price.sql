-- =====================================================================================
-- DMF0020 메인 그리드 SP — B 옵션 (AS-IS 결과 컬럼 동등 + To-Be 데이터 흐름)
-- AS-IS: dbo.DMF0020_GET_SCM_MST_FUTURE_PRICE (1,898 lines, MSSQL T-SQL)
-- To-Be: P_DMF0020_GET_SCM_MST_FUTURE_PRICE_M (Oracle 19c+, 동적 PIVOT)
--
-- 결과: 28 fixed cols + 동적 PIVOT W_yyyymmdd / M_yyyymm cols
-- 데이터 SOURCE: SCM_MST_FUTURE_PRICE + SCM_MST_SITE_ITEM + SCM_MST_PROJECT
--             + SCM_MST_SITE + SCM_SYS_CALENDAR_M
--
-- 사고 fix (2026-06-03):
--   ① V_PROD_IN (PIVOT IN list `'20260105' AS "W_20260105"`)
--   ② V_PROD_SEL (SELECT 절 column reference `"W_20260105"`)
--   2 변수 분리 — 이전 통합 시 SELECT 절에 일자 literal 표시 버그
-- =====================================================================================
WHENEVER SQLERROR EXIT SQL.SQLCODE;

CREATE OR REPLACE PROCEDURE SCM_MGR.P_DMF0020_GET_SCM_MST_FUTURE_PRICE_M
( P_DIVISION_ID         IN VARCHAR2,
  P_DEPT_ID             IN VARCHAR2,
  P_END_CUSTOMER        IN VARCHAR2,
  P_SCM_SITE_ID         IN VARCHAR2,
  P_PLANT_SITE_ID       IN VARCHAR2,
  P_PROJECT_CODE        IN VARCHAR2,
  P_ITEM_ID             IN VARCHAR2,
  P_FROM_YYYYMMDD       IN VARCHAR2,
  P_TO_YYYYMMDD         IN VARCHAR2,
  P_BIZTYPE             IN VARCHAR2,
  P_OWNER               IN VARCHAR2,
  P_OVER_RANGE          IN VARCHAR2,
  P_INVALID_EXEC        IN VARCHAR2,
  P_VERSION_TYPE        IN VARCHAR2,
  P_BUCKET_TYPE         IN VARCHAR2,
  P_USER_ID             IN VARCHAR2,
  P_MNU_ID              IN VARCHAR2,
  O_RC1                 OUT SYS_REFCURSOR
)
AS
  V_PROD_IN   CLOB := EMPTY_CLOB();   -- PIVOT IN list — `'20260105' AS "W_20260105"`
  V_PROD_SEL  CLOB := EMPTY_CLOB();   -- SELECT 절 reference — `"W_20260105"`
  V_SQL       CLOB := EMPTY_CLOB();
  V_SEP       VARCHAR2(2) := '';
BEGIN
  DBMS_LOB.CREATETEMPORARY(V_PROD_IN,TRUE);
  DBMS_LOB.CREATETEMPORARY(V_PROD_SEL,TRUE);
  DBMS_LOB.CREATETEMPORARY(V_SQL,TRUE);

  -- ===== 1. PIVOT IN list + SELECT col list =====
  IF P_BUCKET_TYPE = 'W' THEN
    FOR R IN (
      SELECT DISTINCT BASIS_START_DATE AS WK
      FROM SCM_SYS_CALENDAR_M
      WHERE BASIS_YYYYMMDD BETWEEN P_FROM_YYYYMMDD AND P_TO_YYYYMMDD
        AND BASIS_START_DATE IS NOT NULL
      ORDER BY WK
    ) LOOP
      DBMS_LOB.APPEND(V_PROD_IN,  V_SEP || '''' || R.WK || ''' AS "W_' || R.WK || '"');
      DBMS_LOB.APPEND(V_PROD_SEL, V_SEP || '"W_' || R.WK || '"');
      V_SEP := ',';
    END LOOP;
  ELSE
    FOR R IN (
      SELECT DISTINCT BASIS_YYYYMM AS YM
      FROM SCM_SYS_CALENDAR_M
      WHERE BASIS_YYYYMMDD BETWEEN P_FROM_YYYYMMDD AND P_TO_YYYYMMDD
        AND BASIS_YYYYMM IS NOT NULL
      ORDER BY YM
    ) LOOP
      DBMS_LOB.APPEND(V_PROD_IN,  V_SEP || '''' || R.YM || '01'' AS "M_' || R.YM || '"');
      DBMS_LOB.APPEND(V_PROD_SEL, V_SEP || '"M_' || R.YM || '"');
      V_SEP := ',';
    END LOOP;
  END IF;

  IF DBMS_LOB.GETLENGTH(V_PROD_IN) = 0 THEN
    OPEN O_RC1 FOR SELECT 1 AS DUMMY FROM DUAL WHERE 1=0;
    RETURN;
  END IF;

  -- ===== 2. 동적 PIVOT SQL =====
  -- SELECT 절: 28 fixed cols (PIVOT 결과 grouping cols + hardcoded placeholder) + 동적 ref
  DBMS_LOB.APPEND(V_SQL, '
SELECT
  DIVISION_ID,
  '''' AS DIVISION_NAME,
  '''' AS UPPER_DEPT_ID,
  DEPT_ID,
  SCM_SITE_ID,
  PLANT_SITE_ID,
  SITE_DESCRIPTION,
  END_CUSTOMER,
  '''' AS END_CUSTOMER40,
  PROJECT_CODE,
  PROJECT_NAME,
  BIZ_TYPE_NAME,
  PROJECT_STATUS,
  ITEM_ID AS GROUP_ID,
  ITEM_ID,
  '''' AS ITEM_CLASS_NAME,
  ITEM_NAME,
  INCOTERMS,
  CURRENCY,
  FCST_TYPE,
  DOM_EXP,
  AUTHORITY_YN,
  0 AS DISPLAY_SEQ,
  '''' AS NICK_NAME,
  '''' AS COL_LIST,
  ''N'' AS NEW_FLAG,
  ''Y'' AS PRICE_EXIST,
  MEASURE,
  ');
  DBMS_LOB.APPEND(V_SQL, V_PROD_SEL);   -- 동적 cols reference (`"W_xxx"`)
  -- AS-IS #tmpOutputOmission 동등 — distinct group × 4 measure (RTF/LOC/KRW/USD) cartesian
  --   missing measure row 강제 생성 (PRICE = NULL → PIVOT 결과 셀 빈값)
  DBMS_LOB.APPEND(V_SQL, '
FROM (
  SELECT
    BASE.DIVISION_ID,
    BASE.DEPT_ID,
    BASE.SCM_SITE_ID,
    BASE.PLANT_SITE_ID,
    BASE.SITE_DESCRIPTION,
    BASE.END_CUSTOMER,
    BASE.PROJECT_CODE,
    BASE.PROJECT_NAME,
    BASE.BIZ_TYPE_NAME,
    BASE.PROJECT_STATUS,
    BASE.ITEM_ID,
    BASE.ITEM_NAME,
    BASE.INCOTERMS,
    BASE.CURRENCY,
    BASE.FCST_TYPE,
    BASE.DOM_EXP,
    BASE.AUTHORITY_YN,
    M.MEASURE_CD AS MEASURE,
    FP.PRICE,
    ');
  IF P_BUCKET_TYPE = 'W' THEN
    DBMS_LOB.APPEND(V_SQL, '
    NVL((SELECT BASIS_START_DATE FROM SCM_SYS_CALENDAR_M C WHERE C.BASIS_YYYYMMDD = BASE.YYYYMMDD), BASE.YYYYMMDD) AS YYYYMMDD');
  ELSE
    DBMS_LOB.APPEND(V_SQL, '
    SUBSTR(BASE.YYYYMMDD,1,6) || ''01'' AS YYYYMMDD');
  END IF;
  DBMS_LOB.APPEND(V_SQL, '
  FROM (
    SELECT DISTINCT
      FP1.DIVISION_ID,
      NVL(SI.DEPT_ID, '''') AS DEPT_ID,
      FP1.SCM_SITE_ID,
      FP1.PLANT_SITE_ID,
      NVL(ST.SITE_DESCRIPTION, '''') AS SITE_DESCRIPTION,
      NVL(SI.CUST_GROUP, '''') AS END_CUSTOMER,
      FP1.PROJECT_CODE,
      NVL(PR.PROJECT_NAME, '''') AS PROJECT_NAME,
      NVL(PR.BIZ_TYPE_NAME, '''') AS BIZ_TYPE_NAME,
      NVL(PR.PROJECT_STATUS, '''') AS PROJECT_STATUS,
      FP1.ITEM_ID,
      '''' AS ITEM_NAME,
      FP1.INCOTERMS,
      FP1.CURRENCY,
      FP1.FCST_TYPE,
      FP1.DOM_EXP,
      ''Y'' AS AUTHORITY_YN,
      FP1.YYYYMMDD
    FROM SCM_MST_FUTURE_PRICE FP1
    LEFT JOIN SCM_MST_SITE_ITEM SI
      ON  SI.DIVISION_ID    = FP1.DIVISION_ID
      AND SI.SCM_SITE_ID    = FP1.SCM_SITE_ID
      AND SI.PROJECT_CODE   = FP1.PROJECT_CODE
      AND SI.ITEM_ID        = FP1.ITEM_ID
      AND SI.VALID_YN       = ''Y''
    LEFT JOIN SCM_MST_PROJECT PR
      ON  PR.DIVISION_ID    = FP1.DIVISION_ID
      AND PR.PROJECT_CODE   = FP1.PROJECT_CODE
    LEFT JOIN SCM_MST_SITE ST
      ON  ST.SCM_SITE_ID    = FP1.SCM_SITE_ID
    WHERE FP1.YYYYMMDD BETWEEN :v_from AND :v_to
      AND FP1.DIVISION_ID = :v_div
      AND (:v_dept_a = ''ALL'' OR :v_dept_b IS NULL OR :v_dept_c = '''' OR SI.DEPT_ID IN (SELECT REGEXP_SUBSTR(:v_dept_d,''[^\^]+'',1,LEVEL) FROM DUAL CONNECT BY REGEXP_SUBSTR(:v_dept_e,''[^\^]+'',1,LEVEL) IS NOT NULL))
      AND (:v_ss_a = ''ALL'' OR :v_ss_b IS NULL OR :v_ss_c = '''' OR FP1.SCM_SITE_ID IN (SELECT REGEXP_SUBSTR(:v_ss_d,''[^\^]+'',1,LEVEL) FROM DUAL CONNECT BY REGEXP_SUBSTR(:v_ss_e,''[^\^]+'',1,LEVEL) IS NOT NULL))
      AND (:v_ps_a = ''ALL'' OR :v_ps_b IS NULL OR :v_ps_c = '''' OR FP1.PLANT_SITE_ID IN (SELECT REGEXP_SUBSTR(:v_ps_d,''[^\^]+'',1,LEVEL) FROM DUAL CONNECT BY REGEXP_SUBSTR(:v_ps_e,''[^\^]+'',1,LEVEL) IS NOT NULL))
      AND (:v_pc_a = ''ALL'' OR :v_pc_b IS NULL OR :v_pc_c = '''' OR FP1.PROJECT_CODE IN (SELECT REGEXP_SUBSTR(:v_pc_d,''[^\^]+'',1,LEVEL) FROM DUAL CONNECT BY REGEXP_SUBSTR(:v_pc_e,''[^\^]+'',1,LEVEL) IS NOT NULL))
      AND (:v_im_a = ''ALL'' OR :v_im_b IS NULL OR :v_im_c = '''' OR FP1.ITEM_ID IN (SELECT REGEXP_SUBSTR(:v_im_d,''[^\^]+'',1,LEVEL) FROM DUAL CONNECT BY REGEXP_SUBSTR(:v_im_e,''[^\^]+'',1,LEVEL) IS NOT NULL))
      AND (:v_bt_a = ''ALL'' OR :v_bt_b IS NULL OR :v_bt_c = '''' OR PR.BIZ_TYPE IN (SELECT REGEXP_SUBSTR(:v_bt_d,''[^\^]+'',1,LEVEL) FROM DUAL CONNECT BY REGEXP_SUBSTR(:v_bt_e,''[^\^]+'',1,LEVEL) IS NOT NULL))
  ) BASE
  CROSS JOIN (
    SELECT ''RTF'' AS MEASURE_CD, 1 AS MEASURE_ORD FROM DUAL UNION ALL
    SELECT ''KRW''        AS MEASURE_CD, 2 AS MEASURE_ORD FROM DUAL UNION ALL
    SELECT ''USD''        AS MEASURE_CD, 3 AS MEASURE_ORD FROM DUAL UNION ALL
    SELECT ''LOC''        AS MEASURE_CD, 4 AS MEASURE_ORD FROM DUAL
  ) M
  LEFT JOIN SCM_MST_FUTURE_PRICE FP
    ON  FP.DIVISION_ID   = BASE.DIVISION_ID
    AND FP.SCM_SITE_ID   = BASE.SCM_SITE_ID
    AND FP.PLANT_SITE_ID = BASE.PLANT_SITE_ID
    AND FP.PROJECT_CODE  = BASE.PROJECT_CODE
    AND FP.ITEM_ID       = BASE.ITEM_ID
    AND FP.YYYYMMDD      = BASE.YYYYMMDD
    AND FP.CURRENCY      = BASE.CURRENCY
    AND FP.INCOTERMS     = BASE.INCOTERMS
    AND FP.FCST_TYPE     = BASE.FCST_TYPE
    AND FP.DOM_EXP       = BASE.DOM_EXP
    AND FP.MEASURE       = M.MEASURE_CD
)
PIVOT (
  MAX(PRICE) FOR YYYYMMDD IN (');
  DBMS_LOB.APPEND(V_SQL, V_PROD_IN);
  DBMS_LOB.APPEND(V_SQL, ')
)
ORDER BY DIVISION_ID, DEPT_ID, END_CUSTOMER, SCM_SITE_ID, PROJECT_CODE, PROJECT_STATUS, BIZ_TYPE_NAME, GROUP_ID, ITEM_ID, INCOTERMS, FCST_TYPE, DOM_EXP, CURRENCY, PLANT_SITE_ID, CASE MEASURE WHEN ''RTF'' THEN 1 WHEN ''KRW'' THEN 2 WHEN ''USD'' THEN 3 WHEN ''LOC'' THEN 4 ELSE 5 END');

  OPEN O_RC1 FOR V_SQL
    USING P_FROM_YYYYMMDD, P_TO_YYYYMMDD, P_DIVISION_ID,
          P_DEPT_ID, P_DEPT_ID, P_DEPT_ID, P_DEPT_ID, P_DEPT_ID,
          P_SCM_SITE_ID, P_SCM_SITE_ID, P_SCM_SITE_ID, P_SCM_SITE_ID, P_SCM_SITE_ID,
          P_PLANT_SITE_ID, P_PLANT_SITE_ID, P_PLANT_SITE_ID, P_PLANT_SITE_ID, P_PLANT_SITE_ID,
          P_PROJECT_CODE, P_PROJECT_CODE, P_PROJECT_CODE, P_PROJECT_CODE, P_PROJECT_CODE,
          P_ITEM_ID, P_ITEM_ID, P_ITEM_ID, P_ITEM_ID, P_ITEM_ID,
          P_BIZTYPE, P_BIZTYPE, P_BIZTYPE, P_BIZTYPE, P_BIZTYPE;

  DBMS_LOB.FREETEMPORARY(V_PROD_IN);
  DBMS_LOB.FREETEMPORARY(V_PROD_SEL);
  DBMS_LOB.FREETEMPORARY(V_SQL);
END P_DMF0020_GET_SCM_MST_FUTURE_PRICE_M;
/

SHOW ERRORS;
EXIT;
