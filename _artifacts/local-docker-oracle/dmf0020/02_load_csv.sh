#!/usr/bin/env bash
# DMF0020 데이터 적재 — div=40,80 필터 + SHEET_MEASURE/CALENDAR 는 전체
# Usage: docker exec nscm-oracle bash /tmp/02_load_csv.sh
set -e

DBC="SCM_MGR/\"!SCMroqkf2026\"@//localhost:1521/FREEPDB1"
LOG_DIR=/tmp/dmf0020_log
mkdir -p $LOG_DIR

# ========== 1. SCM_MST_FUTURE_PRICE (필터: div=40,80) =====================
# 원본 284 MB → div=40 + div=80 만 sed 필터 (1열 따옴표 포함)
awk -F',' 'NR==1 || $1=="\"40\"" || $1=="\"81\""' /tmp/SCM_MST_FUTURE_PRICE.csv > /tmp/FUTURE_PRICE_filtered.csv
echo "FUTURE_PRICE filtered rows:"
wc -l /tmp/FUTURE_PRICE_filtered.csv

cat > /tmp/future_price.ctl <<'CTL'
LOAD DATA
CHARACTERSET AL32UTF8
INFILE '/tmp/FUTURE_PRICE_filtered.csv'
APPEND
INTO TABLE SCM_MST_FUTURE_PRICE
FIELDS TERMINATED BY ',' OPTIONALLY ENCLOSED BY '"'
TRAILING NULLCOLS
( DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, PLANT_SITE_ID, ITEM_ID,
  YYYYMMDD, CURRENCY, MEASURE, DOM_EXP, FCST_TYPE, INCOTERMS, PRICE,
  CREATED_BY, CREATION_DATE  "TO_DATE(SUBSTR(:CREATION_DATE,1,19),'YYYY-MM-DD HH24:MI:SS')",
  LAST_UPDATED_BY, LAST_UPDATE_DATE "TO_DATE(SUBSTR(:LAST_UPDATE_DATE,1,19),'YYYY-MM-DD HH24:MI:SS')",
  ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5,
  ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10
)
CTL

# Skip 헤더 row
sqlldr userid=$DBC control=/tmp/future_price.ctl data=/tmp/FUTURE_PRICE_filtered.csv \
  log=$LOG_DIR/future_price.log bad=$LOG_DIR/future_price.bad \
  errors=1000 skip=1 silent=HEADER readsize=20971520 bindsize=20971520 rows=10000
echo "FUTURE_PRICE load done. Log: $LOG_DIR/future_price.log"

# ========== 2. SCM_SYS_CALENDAR_M =====================
cat > /tmp/calendar.ctl <<'CTL'
LOAD DATA
CHARACTERSET AL32UTF8
INFILE '/tmp/SCM_SYS_CALENDAR_M.csv'
APPEND
INTO TABLE SCM_SYS_CALENDAR_M
FIELDS TERMINATED BY ',' OPTIONALLY ENCLOSED BY '"'
TRAILING NULLCOLS
( BASIS_YYYYMMDD, BASIS_DATE "TO_DATE(SUBSTR(:BASIS_DATE,1,19),'YYYY-MM-DD HH24:MI:SS')",
  BASIS_YYYYMM, WEEK_NO, ISO_YYYYWW, ISO_WEEK, WEEK_NAME, PARTIAL_WEEK_NAME, PARTIAL_YN,
  BASIS_START_DATE, BASIS_END_DATE, END_FLAG, DAYOFWEEK, DAYOFWEEK_NAME, DAYOFWEEK_NO,
  CALENDAR_YYYY, CALENDAR_MONTH, CALENDAR_DAY, CALENDAR_YYYYQQ, MONTH_CODE, MONTH_NAME,
  ENGLISH_MONTH_NAME, MONTH_FULL_NAME, DATE_FULL_NAME, DATE_SHORT1_NAME, DATE_SHORT2_NAME,
  DATE_SHORT3_NAME, LAST_WEEK_FLAG, ISO_YYYYMM
)
CTL

sqlldr userid=$DBC control=/tmp/calendar.ctl data=/tmp/SCM_SYS_CALENDAR_M.csv \
  log=$LOG_DIR/calendar.log bad=$LOG_DIR/calendar.bad \
  errors=1000 skip=1 silent=HEADER
echo "CALENDAR load done."

# ========== 3. SCM_MST_SHEET_MEASURE =====================
cat > /tmp/sheet_measure.ctl <<'CTL'
LOAD DATA
CHARACTERSET AL32UTF8
INFILE '/tmp/SCM_MST_SHEET_MEASURE.csv'
APPEND
INTO TABLE SCM_MST_SHEET_MEASURE
FIELDS TERMINATED BY ',' OPTIONALLY ENCLOSED BY '"'
TRAILING NULLCOLS
( PROGRAM_ID, SHEET_NAME, COLUMN_NAME, COLUMN_LABEL_NAME, SORT_ORDER_NO,
  SMALL_CLASS_LABEL_NAME, LARGE_CLASS_LABEL_NAME, DEFAULT_FLAG, USER_SELECTABLE_FLAG,
  DIVISION_ID, VALID_YN,
  CREATED_BY, CREATION_DATE "TO_DATE(SUBSTR(:CREATION_DATE,1,19),'YYYY-MM-DD HH24:MI:SS')",
  LAST_UPDATED_BY, LAST_UPDATE_DATE "TO_DATE(SUBSTR(:LAST_UPDATE_DATE,1,19),'YYYY-MM-DD HH24:MI:SS')",
  ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5,
  ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10, INPUT_TP_CD
)
CTL

sqlldr userid=$DBC control=/tmp/sheet_measure.ctl data=/tmp/SCM_MST_SHEET_MEASURE.csv \
  log=$LOG_DIR/sheet_measure.log bad=$LOG_DIR/sheet_measure.bad \
  errors=1000 skip=1 silent=HEADER
echo "SHEET_MEASURE load done."

echo "==========================="
echo "All loads complete. Check logs at $LOG_DIR/"
