-- =====================================================================================
-- DMF0020 메인 SAVE SP — B 옵션 (AS-IS 핵심 CRUD + DELETE-INSERT 패턴)
-- AS-IS: dbo.DMF0020_SAVE_SCM_MST_FUTURE_PRICE_ALL (1,279 lines)
-- To-Be: SCM_MGR.P_DMF0020_SAVE_SCM_MST_FUTURE_PRICE_ALL_M
--
-- UF_FX_STRING_SPLIT 의 row type = T_UF_FX_STRING_SPLIT_ROW (IDX, TOKEN)
-- =====================================================================================
WHENEVER SQLERROR EXIT SQL.SQLCODE;

CREATE OR REPLACE PROCEDURE SCM_MGR.P_DMF0020_SAVE_SCM_MST_FUTURE_PRICE_ALL_M
( P_ACTIVE_FLAG         IN CLOB,
  P_DIVISION_ID         IN CLOB,
  P_PROJECT_CODE        IN CLOB,
  P_SCM_SITE_ID         IN CLOB,
  P_PLANT_SITE_ID       IN CLOB,
  P_ITEM_ID             IN CLOB,
  P_YYYYMMDD            IN CLOB,
  P_CURRENCY            IN CLOB,
  P_MEASURE             IN CLOB,
  P_DOM_EXP             IN CLOB,
  P_FCST_TYPE           IN CLOB,
  P_INCOTERMS           IN CLOB,
  P_PRICE               IN CLOB,
  P_CREATED_BY          IN CLOB,
  P_CREATION_DATE       IN CLOB,
  P_LAST_UPDATED_BY     IN CLOB,
  P_ROWNUM              IN CLOB,
  P_USER_ID             IN VARCHAR2,
  P_MNU_ID              IN VARCHAR2,
  O_RC1                 OUT SYS_REFCURSOR
)
AS
  V_INS NUMBER := 0;
  V_UPD NUMBER := 0;
  V_DEL NUMBER := 0;
  V_USR VARCHAR2(150);
  V_ERR VARCHAR2(4000);
BEGIN
  V_USR := NVL(P_USER_ID, USER);

  -- 17 ^-delim CLOB → 17 column 매칭 (IDX 기준 JOIN)
  FOR RS IN (
    WITH
    AF AS (SELECT NR AS IDX, TOKEN AS V FROM TABLE(SCM_MGR.UF_FX_STRING_SPLIT(P_ACTIVE_FLAG,    '^'))),
    DV AS (SELECT NR AS IDX, TOKEN AS V FROM TABLE(SCM_MGR.UF_FX_STRING_SPLIT(P_DIVISION_ID,    '^'))),
    PC AS (SELECT NR AS IDX, TOKEN AS V FROM TABLE(SCM_MGR.UF_FX_STRING_SPLIT(P_PROJECT_CODE,   '^'))),
    SS AS (SELECT NR AS IDX, TOKEN AS V FROM TABLE(SCM_MGR.UF_FX_STRING_SPLIT(P_SCM_SITE_ID,    '^'))),
    PS AS (SELECT NR AS IDX, TOKEN AS V FROM TABLE(SCM_MGR.UF_FX_STRING_SPLIT(P_PLANT_SITE_ID,  '^'))),
    IT AS (SELECT NR AS IDX, TOKEN AS V FROM TABLE(SCM_MGR.UF_FX_STRING_SPLIT(P_ITEM_ID,        '^'))),
    YD AS (SELECT NR AS IDX, TOKEN AS V FROM TABLE(SCM_MGR.UF_FX_STRING_SPLIT(P_YYYYMMDD,       '^'))),
    CU AS (SELECT NR AS IDX, TOKEN AS V FROM TABLE(SCM_MGR.UF_FX_STRING_SPLIT(P_CURRENCY,       '^'))),
    ME AS (SELECT NR AS IDX, TOKEN AS V FROM TABLE(SCM_MGR.UF_FX_STRING_SPLIT(P_MEASURE,        '^'))),
    DE AS (SELECT NR AS IDX, TOKEN AS V FROM TABLE(SCM_MGR.UF_FX_STRING_SPLIT(P_DOM_EXP,        '^'))),
    FC AS (SELECT NR AS IDX, TOKEN AS V FROM TABLE(SCM_MGR.UF_FX_STRING_SPLIT(P_FCST_TYPE,      '^'))),
    IC AS (SELECT NR AS IDX, TOKEN AS V FROM TABLE(SCM_MGR.UF_FX_STRING_SPLIT(P_INCOTERMS,      '^'))),
    PR AS (SELECT NR AS IDX, TOKEN AS V FROM TABLE(SCM_MGR.UF_FX_STRING_SPLIT(P_PRICE,          '^')))
    SELECT AF.IDX,
           AF.V  AS ACTIVE_FLAG,
           DV.V  AS DIVISION_ID,
           PC.V  AS PROJECT_CODE,
           SS.V  AS SCM_SITE_ID,
           PS.V  AS PLANT_SITE_ID,
           IT.V  AS ITEM_ID,
           YD.V  AS YYYYMMDD,
           CU.V  AS CURRENCY,
           ME.V  AS MEASURE,
           DE.V  AS DOM_EXP,
           FC.V  AS FCST_TYPE,
           IC.V  AS INCOTERMS,
           PR.V  AS PRICE
    FROM AF
    JOIN DV ON DV.IDX = AF.IDX
    JOIN PC ON PC.IDX = AF.IDX
    JOIN SS ON SS.IDX = AF.IDX
    JOIN PS ON PS.IDX = AF.IDX
    JOIN IT ON IT.IDX = AF.IDX
    JOIN YD ON YD.IDX = AF.IDX
    JOIN CU ON CU.IDX = AF.IDX
    JOIN ME ON ME.IDX = AF.IDX
    JOIN DE ON DE.IDX = AF.IDX
    JOIN FC ON FC.IDX = AF.IDX
    JOIN IC ON IC.IDX = AF.IDX
    JOIN PR ON PR.IDX = AF.IDX
  ) LOOP
    -- AS-IS L1820 KHSONG : DELETE-INSERT 패턴 (MERGE 오류 대응)
    IF RS.ACTIVE_FLAG = 'D' THEN
      DELETE FROM SCM_MST_FUTURE_PRICE
        WHERE DIVISION_ID=RS.DIVISION_ID AND PROJECT_CODE=RS.PROJECT_CODE
          AND SCM_SITE_ID=RS.SCM_SITE_ID AND PLANT_SITE_ID=RS.PLANT_SITE_ID
          AND ITEM_ID=RS.ITEM_ID AND YYYYMMDD=RS.YYYYMMDD
          AND CURRENCY=RS.CURRENCY AND MEASURE=RS.MEASURE
          AND DOM_EXP=RS.DOM_EXP AND FCST_TYPE=RS.FCST_TYPE AND INCOTERMS=RS.INCOTERMS;
      V_DEL := V_DEL + SQL%ROWCOUNT;

    ELSIF RS.ACTIVE_FLAG IN ('I','U') THEN
      DELETE FROM SCM_MST_FUTURE_PRICE
        WHERE DIVISION_ID=RS.DIVISION_ID AND PROJECT_CODE=RS.PROJECT_CODE
          AND SCM_SITE_ID=RS.SCM_SITE_ID AND PLANT_SITE_ID=RS.PLANT_SITE_ID
          AND ITEM_ID=RS.ITEM_ID AND YYYYMMDD=RS.YYYYMMDD
          AND CURRENCY=RS.CURRENCY AND MEASURE=RS.MEASURE
          AND DOM_EXP=RS.DOM_EXP AND FCST_TYPE=RS.FCST_TYPE AND INCOTERMS=RS.INCOTERMS;

      INSERT INTO SCM_MST_FUTURE_PRICE
       ( DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, PLANT_SITE_ID, ITEM_ID,
         YYYYMMDD, CURRENCY, MEASURE, DOM_EXP, FCST_TYPE, INCOTERMS, PRICE,
         CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE )
       VALUES
       ( RS.DIVISION_ID, RS.PROJECT_CODE, RS.SCM_SITE_ID, RS.PLANT_SITE_ID, RS.ITEM_ID,
         RS.YYYYMMDD, RS.CURRENCY, RS.MEASURE, RS.DOM_EXP, RS.FCST_TYPE, RS.INCOTERMS,
         TO_NUMBER(NVL(RS.PRICE,'0')),
         V_USR, SYSDATE, V_USR, SYSDATE );
      IF RS.ACTIVE_FLAG = 'I' THEN V_INS := V_INS + 1; ELSE V_UPD := V_UPD + 1; END IF;
    END IF;
  END LOOP;

  COMMIT;

  OPEN O_RC1 FOR
    SELECT V_INS AS INSERTED, V_UPD AS UPDATED, V_DEL AS DELETED, 'SUCCESS' AS STATUS FROM DUAL;
EXCEPTION
  WHEN OTHERS THEN
    ROLLBACK;
    V_ERR := SUBSTR(SQLERRM, 1, 4000);
    OPEN O_RC1 FOR
      SELECT 0 AS INSERTED, 0 AS UPDATED, 0 AS DELETED, V_ERR AS STATUS FROM DUAL;
END P_DMF0020_SAVE_SCM_MST_FUTURE_PRICE_ALL_M;
/

SHOW ERRORS;
EXIT;
