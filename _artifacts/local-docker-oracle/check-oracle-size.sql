-- NSCM Local Oracle Free Edition 23ai 용량 측정
-- 출력 형식 (PowerShell 파서 의존):
--   TOTAL_USER_GB:5.34
--   TS:USERS:3.21
--   TOP:SCM_MGR.SCM_MST_SITE_ITEM:TABLE:850MB
--   END
SET HEADING OFF
SET PAGESIZE 0
SET LINESIZE 200
SET FEEDBACK OFF
SET TRIMSPOOL ON
SET TERMOUT ON
SET SERVEROUTPUT ON

-- 1. user_data 총량 (Oracle Free 12GB 한도 적용 대상)
SELECT 'TOTAL_USER_GB:' || TO_CHAR(NVL(ROUND(SUM(bytes)/1024/1024/1024, 2),0), 'FM9990.00')
  FROM dba_segments
 WHERE owner NOT IN (
   'SYS','SYSTEM','SYSAUX','OUTLN','DBSNMP','APPQOSSYS','DBSFWUSER',
   'GSMADMIN_INTERNAL','GSMUSER','GSMROOTUSER','AUDSYS','XDB','WMSYS',
   'ORDDATA','ORDSYS','MDSYS','CTXSYS','OLAPSYS','DVSYS','DVF','LBACSYS',
   'SI_INFORMTN_SCHEMA','ANONYMOUS','APEX_PUBLIC_USER','FLOWS_FILES',
   'APEX_030200','OJVMSYS','REMOTE_SCHEDULER_AGENT','SYSBACKUP','SYSDG',
   'SYSKM','SYSRAC','SYS$UMF','GGSYS','PDBADMIN'
 );

-- 2. tablespace 별 분포 (사용자 스키마만)
SELECT 'TS:' || tablespace_name || ':' ||
       TO_CHAR(ROUND(SUM(bytes)/1024/1024/1024, 2), 'FM9990.00')
  FROM dba_segments
 WHERE owner NOT IN (
   'SYS','SYSTEM','SYSAUX','OUTLN','DBSNMP','APPQOSSYS','DBSFWUSER',
   'GSMADMIN_INTERNAL','GSMUSER','GSMROOTUSER','AUDSYS','XDB','WMSYS',
   'ORDDATA','ORDSYS','MDSYS','CTXSYS','OLAPSYS','DVSYS','DVF','LBACSYS',
   'SI_INFORMTN_SCHEMA','ANONYMOUS','APEX_PUBLIC_USER','FLOWS_FILES',
   'APEX_030200','OJVMSYS','REMOTE_SCHEDULER_AGENT','SYSBACKUP','SYSDG',
   'SYSKM','SYSRAC','SYS$UMF','GGSYS','PDBADMIN'
 )
 GROUP BY tablespace_name
 ORDER BY 1;

-- 3. Top 15 큰 segment (테이블 + 인덱스)
SELECT 'TOP:' || owner || '.' || segment_name || ':' || segment_type || ':' ||
       TO_CHAR(ROUND(bytes/1024/1024, 0), 'FM999990') || 'MB'
  FROM (SELECT owner, segment_name, segment_type, bytes
          FROM dba_segments
         WHERE owner NOT IN (
            'SYS','SYSTEM','SYSAUX','OUTLN','DBSNMP','APPQOSSYS','DBSFWUSER',
            'GSMADMIN_INTERNAL','GSMUSER','GSMROOTUSER','AUDSYS','XDB','WMSYS',
            'ORDDATA','ORDSYS','MDSYS','CTXSYS','OLAPSYS','DVSYS','DVF','LBACSYS',
            'SI_INFORMTN_SCHEMA','ANONYMOUS','APEX_PUBLIC_USER','FLOWS_FILES',
            'APEX_030200','OJVMSYS','REMOTE_SCHEDULER_AGENT','SYSBACKUP','SYSDG',
            'SYSKM','SYSRAC','SYS$UMF','GGSYS','PDBADMIN'
         )
         ORDER BY bytes DESC)
 WHERE ROWNUM <= 15;

SELECT 'END' FROM DUAL;

EXIT;
