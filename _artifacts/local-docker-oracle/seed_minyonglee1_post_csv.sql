-- minyonglee1 USER_M 보강 + ADMIN 그룹 매핑 보강 + UGA 복제
-- CSV import 후 minyonglee1 의 USER_M 누락 + ADMIN/DM 그룹 매핑 누락 fix
ALTER SESSION SET CONTAINER = FREEPDB1;
SET SERVEROUTPUT ON SIZE UNLIMITED

-- 1. SCM_ADM_USER_M : minyonglee1 INSERT
DECLARE v_cnt NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_cnt FROM SCM_MGR.SCM_ADM_USER_M WHERE USER_ID='minyonglee1';
  IF v_cnt = 0 THEN
    INSERT INTO SCM_MGR.SCM_ADM_USER_M (USER_ID, USER_NM, USER_ENG_NM, DEPT_ID, LANG_CD, ACNT_LOK_YN, TMZ_CD, USE_YN,
      CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE, PERM_KEP_CNC_YN)
    VALUES ('minyonglee1', '이민용', 'MINYONG LEE', 'LESIC', 'KO', 'Y', 'AS054', 'Y',
      'SYSTEM', SYSDATE, 'SYSTEM', SYSDATE, 'N');
    DBMS_OUTPUT.PUT_LINE('Inserted minyonglee1 into USER_M');
  END IF;
END;
/

-- 2. SCM_ADM_USER_GR_MPG_M : minyonglee1 + ADMIN/DM Viewer/DM ADMIN (보유 그룹은 skip)
INSERT INTO SCM_MGR.SCM_ADM_USER_GR_MPG_M (USER_GR_ID, USER_ID, USE_YN,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT g.USER_GR_ID, 'minyonglee1', 'Y', 'SYSADMIN', SYSDATE, 'SYSADMIN', SYSDATE
FROM   (SELECT 'ADMIN' AS USER_GR_ID FROM dual UNION ALL
        SELECT 'DM Viewer' FROM dual UNION ALL
        SELECT 'DM ADMIN' FROM dual) g
WHERE  NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_USER_GR_MPG_M t WHERE t.USER_GR_ID=g.USER_GR_ID AND t.USER_ID='minyonglee1');

-- 3. SCM_ADM_USER_GR_UNIT_AUTH_MPG_M : ADMIN UGA 를 minyonglee1 으로 복제
INSERT INTO SCM_MGR.SCM_ADM_USER_GR_UNIT_AUTH_MPG_M (USER_GR_ID, USER_ID, UNIT_TP_CD, UNIT_ID, UPPR_UNIT_ID,
  EDIT_YN, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'ADMIN', 'minyonglee1', u.UNIT_TP_CD, u.UNIT_ID, '-',
       'Y', 'Y', 'SYSTEM', SYSDATE, 'SYSTEM', SYSDATE
FROM   (SELECT DISTINCT UNIT_TP_CD, UNIT_ID FROM SCM_MGR.SCM_ADM_USER_GR_UNIT_AUTH_MPG_M WHERE USER_GR_ID='ADMIN') u
WHERE  NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_USER_GR_UNIT_AUTH_MPG_M x
                   WHERE x.USER_GR_ID='ADMIN' AND x.USER_ID='minyonglee1'
                     AND x.UNIT_TP_CD=u.UNIT_TP_CD AND x.UNIT_ID=u.UNIT_ID);

COMMIT;

-- 4. Verify
SELECT 'USER_M.minyonglee1='||COUNT(*) FROM SCM_MGR.SCM_ADM_USER_M WHERE USER_ID='minyonglee1';
SELECT 'GR_MPG.minyonglee1='||COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MPG_M WHERE USER_ID='minyonglee1';
SELECT 'UGA.minyonglee1='||COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_UNIT_AUTH_MPG_M WHERE USER_ID='minyonglee1';

EXIT
