CREATE OR REPLACE PROCEDURE           "P_DMF0020_GET_OWNER_DATA" (
    P_DIVISION_ID   IN  VARCHAR2,
    P_DEPT_ID       IN  VARCHAR2,
    P_END_CUSTOMER  IN  VARCHAR2,
    P_SCM_SITE_ID   IN  VARCHAR2,
    P_PROJECT_CODE  IN  VARCHAR2,
    P_OWNER_ID      IN  VARCHAR2,
    O_RC1           OUT SYS_REFCURSOR
) IS
BEGIN
    OPEN O_RC1 FOR
    WITH
    ADMIN_GROUP AS (
        SELECT SEGMENT1 AS ADMIN_GROUP
        FROM SCM_ADM_LOOKUP_MASTER_DETAIL
        WHERE LOOKUP_TYPE = 'GET_ADMIN_GROUP'
          AND VALID_YN    = 'Y'
          AND ATTRIBUTE1 = 'Y'
    ),
    LEVEL2_DEPT AS (
        SELECT SEGMENT1 AS DEPT_ID
        FROM SCM_ADM_LOOKUP_MASTER_DETAIL
        WHERE LOOKUP_TYPE = 'DM_OWNER_DEPT' AND VALID_YN='Y' AND SEGMENT2='LEVEL_2'
    ),
    LEVEL1_DEPT AS (
        SELECT SEGMENT1 AS DEPT_ID
        FROM SCM_ADM_LOOKUP_MASTER_DETAIL
        WHERE LOOKUP_TYPE = 'DM_OWNER_DEPT' AND VALID_YN='Y' AND SEGMENT2='LEVEL_1'
    ),
    TMP_DEPT AS (
        -- 40, 82 사업부
        SELECT DISTINCT C.DEPT_ID
        FROM   SCM_MST_SITE_ITEM     A
             --, SCM_MST_SSO_USER_INFO B
             , SCM_MST_SSO_DEPT_INFO C
        WHERE  1=1 --A.OWNER       = B.USER_ID
          AND  A.DEPT_ID     = C.DEPT_ID
          AND  A.DIVISION_ID = P_DIVISION_ID
          AND  P_DIVISION_ID IN ('40', '82')

        UNION ALL

        -- 81% 사업부: Owner DEPT
        SELECT DISTINCT C.DEPT_ID
        FROM   SCM_MST_SITE_ITEM     A
             --, SCM_MST_SSO_USER_INFO B
             , SCM_MST_SSO_DEPT_INFO C
        WHERE  1=1 --A.OWNER       = B.USER_ID
          AND  A.DEPT_ID     = C.DEPT_ID
          AND  A.DIVISION_ID = P_DIVISION_ID
          AND  P_DIVISION_ID LIKE '81%'

        UNION ALL

        -- 81% 사업부: PM_TEAM_MAPPING 매핑 DEPT
        SELECT DISTINCT LOOKUP.SEGMENT1 AS DEPT_ID
        FROM   SCM_ADM_LOOKUP_MASTER_DETAIL LOOKUP
        WHERE  LOOKUP.LOOKUP_TYPE = 'PM_TEAM_MAPPING'
          AND  LOOKUP.VALID_YN   = 'Y'
          AND  P_DIVISION_ID LIKE '81%'
          AND  LOOKUP.SEGMENT3 IN (
                   SELECT DISTINCT C.DEPT_ID
                   FROM   SCM_MST_SITE_ITEM     A
                        --, SCM_MST_SSO_USER_INFO B
                        , SCM_MST_SSO_DEPT_INFO C
                   WHERE  1=1 --A.OWNER       = B.USER_ID
                     AND  A.DEPT_ID     = C.DEPT_ID
                     AND  A.DIVISION_ID = P_DIVISION_ID
               )
    ),
    DEPT_INFO AS (
        SELECT T.DEPT_ID, T.DEPT_NAME_KO, T.VALID_YN
        FROM   SCM_MST_SSO_DEPT_INFO D
             , SCM_MST_SSO_DEPT_INFO T
        WHERE  T.UPPER_DEPT_ID    = D.DEPT_ID
          AND  T."2LEVEL_DEPT_ID" IN (SELECT DEPT_ID FROM LEVEL2_DEPT)

        UNION ALL

        SELECT T.DEPT_ID, T.DEPT_NAME_KO, T.VALID_YN
        FROM   SCM_MST_SSO_DEPT_INFO D
             , SCM_MST_SSO_DEPT_INFO T
        WHERE  T.UPPER_DEPT_ID = D.DEPT_ID
          AND  T.DEPT_ID      IN (SELECT DEPT_ID FROM LEVEL1_DEPT)
          AND  D.VALID_YN      = 'Y'
          AND  T.VALID_YN      = 'Y'
    )
    SELECT
          FxUGA.UNIT_ID          AS DIVISION_ID
        , FxU.DEPT_ID
        , DI.DEPT_NAME_KO
        , FxU.USER_NM         AS USER_NAME
        , FxU.USER_ID          AS OWNER_NAME
        , ROW_NUMBER() OVER (ORDER BY FxU.USER_ID, FxU.USER_NM) * 100 AS SORT_ORDER_NO
    FROM (SELECT * FROM SCM_ADM_USER_M WHERE USE_YN='Y') FxU
    INNER JOIN DEPT_INFO DI
            ON FxU.DEPT_ID = DI.DEPT_ID AND DI.VALID_YN='Y'
    INNER JOIN SCM_MST_SSO_USER_INFO USER_INFO
            ON FxU.USER_ID = USER_INFO.USER_ID
    INNER JOIN SCM_ADM_USER_GR_UNIT_AUTH_MPG_M FxUGA
            ON FxU.USER_ID    = FxUGA.USER_ID
           AND FxUGA.USER_GR_ID IN (SELECT ADMIN_GROUP FROM ADMIN_GROUP)
           AND FxUGA.Unit_Tp_Cd = 'D'
    WHERE FxUGA.UNIT_ID = P_DIVISION_ID
      AND (
            P_DEPT_ID = 'ALL'
            OR FxU.DEPT_ID IN (SELECT VALUE FROM TABLE(SCM_MGR.FN_SPLITSTRING(P_DEPT_ID, ',')))
          )
      AND (
            NVL(TRIM(P_OWNER_ID), 'ALL') = 'ALL'
            OR EXISTS (
               (SELECT 1
                FROM TABLE(SCM_MGR.FN_SPLITSTRING(P_OWNER_ID, ',') O
                WHERE FxU.USER_ID LIKE O.VALUE || '%' ))
            --OR FxU.USER_ID             IN (SELECT VALUE FROM TABLE(SCM_MGR.FN_SPLITSTRING(P_OWNER_ID, ',')))
            --OR FxU.USER_NM           IN (SELECT VALUE FROM TABLE(SCM_MGR.FN_SPLITSTRING(P_OWNER_ID, ',')))
            --OR USER_INFO.USER_NAME_EN IN (SELECT VALUE FROM TABLE(SCM_MGR.FN_SPLITSTRING(P_OWNER_ID, ',')))
          )

          )

      AND FxU.DEPT_ID IN (SELECT DEPT_ID FROM TMP_DEPT)
    GROUP BY
          FxUGA.UNIT_ID, FxU.USER_ID, FxU.USER_NM
        , USER_INFO.USER_NAME_EN, FxU.DEPT_ID
        , DI.DEPT_NAME_KO, USER_INFO.JOB_NAME
    ORDER BY DI.DEPT_NAME_KO, FxU.USER_NM, FxU.USER_ID;

END P_DMF0020_GET_OWNER_DATA;
