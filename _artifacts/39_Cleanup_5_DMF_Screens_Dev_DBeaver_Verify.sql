SELECT 'MNU_M (5 화면) — DELETED' AS CHK,
       0 AS EXPECT,
       (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_MNU_M
         WHERE MNU_ID IN ('DMF0008','DMF0020','DMF0043','DMF0043_01','DMF0072')) AS ACTUAL
  FROM DUAL
UNION ALL
SELECT 'USER_GR_MNU_MPG_M (5 화면) — DELETED',
       0,
       (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_MPG_M
         WHERE MNU_ID IN ('DMF0008','DMF0020','DMF0043','DMF0043_01','DMF0072'))
  FROM DUAL
UNION ALL
SELECT 'USER_GR_MNU_BTN_MPG_M (5 화면) — DELETED',
       0,
       (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M
         WHERE MNU_ID IN ('DMF0008','DMF0020','DMF0043','DMF0043_01','DMF0072'))
  FROM DUAL
UNION ALL
SELECT 'MNU_BTN_MPG_M (5 화면) — DELETED',
       0,
       (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M
         WHERE MNU_ID IN ('DMF0008','DMF0020','DMF0043','DMF0043_01','DMF0072'))
  FROM DUAL
UNION ALL
SELECT 'PROC_M (PKG_DMF{0008,0020,0043,0072}) — DELETED',
       0,
       (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M
         WHERE REGEXP_LIKE(PROC_NM, '^PKG_DMF(0008|0020|0043|0072)\.'))
  FROM DUAL
UNION ALL
SELECT 'Master 트리 (5 화면 삭제 후 13 row)',
       13,
       (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_MNU_M
        START WITH MNU_ID = 'Master'
        CONNECT BY PRIOR MNU_ID = UPPR_MNU_ID)
  FROM DUAL
UNION ALL
SELECT 'PKG_DMF0008 BODY VALID 보존',
       1,
       (SELECT COUNT(*) FROM USER_OBJECTS
         WHERE OBJECT_NAME='PKG_DMF0008' AND OBJECT_TYPE='PACKAGE BODY' AND STATUS='VALID')
  FROM DUAL
UNION ALL
SELECT 'PKG_DMF0043 BODY VALID 보존',
       1,
       (SELECT COUNT(*) FROM USER_OBJECTS
         WHERE OBJECT_NAME='PKG_DMF0043' AND OBJECT_TYPE='PACKAGE BODY' AND STATUS='VALID')
  FROM DUAL
UNION ALL
SELECT 'PKG_DMF0072 BODY VALID 보존',
       1,
       (SELECT COUNT(*) FROM USER_OBJECTS
         WHERE OBJECT_NAME='PKG_DMF0072' AND OBJECT_TYPE='PACKAGE BODY' AND STATUS='VALID')
  FROM DUAL;
