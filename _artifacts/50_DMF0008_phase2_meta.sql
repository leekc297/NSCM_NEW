--==============================================================================
-- 50_DMF0008_phase2_meta.sql
--
-- 목적: DMF0008 Phase 2 — REPAIR + SALES_SITE + SSPM sheet 메타 등록
--   - REPAIR  : DMF0008_GET_EDI_MST_REPAIR (5 IN + 2 OUT, O_RESULT_CURSOR 제거 fix 적용)
--   - SALES_SITE : DMF0008_GET_SALES_SITE (4 IN + O_RESULT_CURSOR 메인 cursor)
--   - SSPM    : DMF0008_GET_SALES_SITE_PROJECT_MODEL (5 IN + 1 OUT cursor)
--
-- 멱등성: NOT EXISTS 가드
-- 작성: 2026-06-02 (DMF0008 3단 구조 사용자 요구 — Summary/Repair/Sub(2tab))
--==============================================================================
SET DEFINE OFF
SET SERVEROUTPUT ON
SET FEEDBACK ON
SET LINESIZE 200
WHENEVER SQLERROR EXIT FAILURE

PROMPT === BLOCK 1 : SCM_ADM_MSG_M (3 API msg) ===
INSERT INTO SCM_MGR.SCM_ADM_MSG_M (MSG_ID, LANG_CD, MSG_TP_CD, MSG_NM, MSG_DESC, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT NEW.MSG_ID, 'KO', 'API', NEW.MSG_NM, NEW.MSG_NM, 'Y', 'admin', SYSDATE, 'admin', SYSDATE
  FROM (
    SELECT 'MSG_API_DMF0008_REPAIR_GET'      AS MSG_ID, 'ERP EDI 마스터 REPAIR 조회'           AS MSG_NM FROM DUAL UNION ALL
    SELECT 'MSG_API_DMF0008_SALES_SITE_GET',           'ERP EDI 마스터 Sales Site 조회'                  FROM DUAL UNION ALL
    SELECT 'MSG_API_DMF0008_SSPM_GET',                 'ERP EDI 마스터 SSPM 조회'                        FROM DUAL
  ) NEW
 WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_MSG_M X WHERE X.MSG_ID = NEW.MSG_ID AND X.LANG_CD='KO');

PROMPT === BLOCK 2 : SCM_ADM_API_M (3) ===
INSERT INTO SCM_MGR.SCM_ADM_API_M (API_ID, API_TP_CD, API_MSG_ID, API_MSG_DESC, API_URL, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT NEW.API_ID, 'PROC_SELECT', NEW.MSG_ID, NEW.MSG_DESC, NEW.API_URL, 'Y', 'admin', SYSDATE, 'admin', SYSDATE
  FROM (
    SELECT 'P_DMF0008_REPAIR_GET'    AS API_ID, 'MSG_API_DMF0008_REPAIR_GET'      AS MSG_ID, 'ERP EDI REPAIR'        AS MSG_DESC, 'DMF0008_GET_EDI_MST_REPAIR'             AS API_URL FROM DUAL UNION ALL
    SELECT 'P_DMF0008_SALES_SITE_GET',         'MSG_API_DMF0008_SALES_SITE_GET',             'ERP EDI Sales Site',                'DMF0008_GET_SALES_SITE'                            FROM DUAL UNION ALL
    SELECT 'P_DMF0008_SSPM_GET',               'MSG_API_DMF0008_SSPM_GET',                   'ERP EDI SSPM',                      'DMF0008_GET_SALES_SITE_PROJECT_MODEL'              FROM DUAL
  ) NEW
 WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_API_M X WHERE X.API_ID = NEW.API_ID);

PROMPT === BLOCK 3 : SCM_ADM_MNU_BTN_MPG_M (DMF0008 — 3 sheet) ===
INSERT INTO SCM_MGR.SCM_ADM_MNU_BTN_MPG_M (MNU_ID, SHT_NM, MNU_BTN_CD, API_ID, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'DMF0008', NEW.SHT_NM, 'SEARCH', NEW.API_ID, 'Y', 'admin', SYSDATE, 'admin', SYSDATE
  FROM (
    SELECT 'repair'    AS SHT_NM, 'P_DMF0008_REPAIR_GET'      AS API_ID FROM DUAL UNION ALL
    SELECT 'salesSite',            'P_DMF0008_SALES_SITE_GET'            FROM DUAL UNION ALL
    SELECT 'sspm',                 'P_DMF0008_SSPM_GET'                  FROM DUAL
  ) NEW
 WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M X
    WHERE X.MNU_ID='DMF0008' AND X.SHT_NM=NEW.SHT_NM AND X.MNU_BTN_CD='SEARCH');

PROMPT === BLOCK 4 : SCM_ADM_USER_GR_MNU_BTN_MPG_M (GUEST × 3) ===
INSERT INTO SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M (USER_GR_ID, MNU_ID, SHT_NM, MNU_BTN_CD, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'GUEST', 'DMF0008', BTN.SHT_NM, BTN.MNU_BTN_CD, 'Y', 'admin', SYSDATE, 'admin', SYSDATE
  FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M BTN
 WHERE BTN.MNU_ID='DMF0008' AND BTN.SHT_NM IN ('repair','salesSite','sspm') AND BTN.USE_YN='Y'
   AND NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M X
     WHERE X.USER_GR_ID='GUEST' AND X.MNU_ID='DMF0008' AND X.SHT_NM=BTN.SHT_NM AND X.MNU_BTN_CD=BTN.MNU_BTN_CD);

PROMPT === BLOCK 5 : SCM_ADM_PROC_M ===
INSERT INTO SCM_MGR.SCM_ADM_PROC_M (PROC_NM, COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT NEW.PROC_NM, NEW.COL_NM, NEW.DATA_TP_CD, NEW.COL_TP_CD, NEW.SORT_ORD, 'admin', SYSDATE, 'admin', SYSDATE
  FROM (
    -- REPAIR: (5 IN + sesUserId + mnuId + o_rc1) = 8 args (O_RESULT_CURSOR fix 적용 후)
    SELECT 'DMF0008_GET_EDI_MST_REPAIR' AS PROC_NM, 'divisionId'  AS COL_NM, 'VARCHAR' AS DATA_TP_CD, 'IN'  AS COL_TP_CD, 1 AS SORT_ORD FROM DUAL UNION ALL
    SELECT 'DMF0008_GET_EDI_MST_REPAIR',           'fromYyyymmdd',            'VARCHAR',               'IN',                2 FROM DUAL UNION ALL
    SELECT 'DMF0008_GET_EDI_MST_REPAIR',           'toYyyymmdd',              'VARCHAR',               'IN',                3 FROM DUAL UNION ALL
    SELECT 'DMF0008_GET_EDI_MST_REPAIR',           'senderName',              'VARCHAR',               'IN',                4 FROM DUAL UNION ALL
    SELECT 'DMF0008_GET_EDI_MST_REPAIR',           'flag',                    'VARCHAR',               'IN',                5 FROM DUAL UNION ALL
    SELECT 'DMF0008_GET_EDI_MST_REPAIR',           'sesUserId',               'VARCHAR',               'IN',                6 FROM DUAL UNION ALL
    SELECT 'DMF0008_GET_EDI_MST_REPAIR',           'mnuId',                   'VARCHAR',               'IN',                7 FROM DUAL UNION ALL
    SELECT 'DMF0008_GET_EDI_MST_REPAIR',           'o_rc1',                   'CURSOR',                'OUT',               8 FROM DUAL UNION ALL
    -- SALES_SITE: (4 IN + O_RESULT_CURSOR) = 5 args (O_RESULT_CURSOR = 메인 결과 cursor, 대문자)
    SELECT 'DMF0008_GET_SALES_SITE',               'divisionId',              'VARCHAR',               'IN',                1 FROM DUAL UNION ALL
    SELECT 'DMF0008_GET_SALES_SITE',               'soldTo',                  'VARCHAR',               'IN',                2 FROM DUAL UNION ALL
    SELECT 'DMF0008_GET_SALES_SITE',               'shipTo',                  'VARCHAR',               'IN',                3 FROM DUAL UNION ALL
    SELECT 'DMF0008_GET_SALES_SITE',               'scmSiteId',               'VARCHAR',               'IN',                4 FROM DUAL UNION ALL
    SELECT 'DMF0008_GET_SALES_SITE',               'O_RESULT_CURSOR',         'PROC_RESULT',           'OUT',               5 FROM DUAL UNION ALL
    -- SSPM: (3 IN + sesUserId + mnuId + o_rc1) = 6 args
    SELECT 'DMF0008_GET_SALES_SITE_PROJECT_MODEL', 'divisionId',              'VARCHAR',               'IN',                1 FROM DUAL UNION ALL
    SELECT 'DMF0008_GET_SALES_SITE_PROJECT_MODEL', 'itemId',                  'VARCHAR',               'IN',                2 FROM DUAL UNION ALL
    SELECT 'DMF0008_GET_SALES_SITE_PROJECT_MODEL', 'scmSiteId',               'VARCHAR',               'IN',                3 FROM DUAL UNION ALL
    SELECT 'DMF0008_GET_SALES_SITE_PROJECT_MODEL', 'sesUserId',               'VARCHAR',               'IN',                4 FROM DUAL UNION ALL
    SELECT 'DMF0008_GET_SALES_SITE_PROJECT_MODEL', 'mnuId',                   'VARCHAR',               'IN',                5 FROM DUAL UNION ALL
    SELECT 'DMF0008_GET_SALES_SITE_PROJECT_MODEL', 'o_rc1',                   'CURSOR',                'OUT',               6 FROM DUAL
  ) NEW
 WHERE NOT EXISTS (
   SELECT 1 FROM SCM_MGR.SCM_ADM_PROC_M X
    WHERE X.PROC_NM = NEW.PROC_NM AND X.COL_NM = NEW.COL_NM AND X.COL_TP_CD = NEW.COL_TP_CD
 );

COMMIT;

PROMPT === POST ===
SELECT 'POST: API_M (DMF0008)' AS K, COUNT(*) AS V FROM SCM_MGR.SCM_ADM_API_M WHERE API_ID LIKE 'P_DMF0008%'
UNION ALL SELECT 'POST: BTN_MPG (DMF0008)', COUNT(*) FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID='DMF0008'
UNION ALL SELECT 'POST: GUEST PERM (DMF0008)', COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE USER_GR_ID='GUEST' AND MNU_ID='DMF0008'
UNION ALL SELECT 'POST: PROC_M DMF0008_*', COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M WHERE PROC_NM LIKE 'DMF0008_%';

PROMPT === COMPLETE ===
EXIT;
