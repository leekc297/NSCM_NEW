PROMPT === BLOCK 8: Master / Demand_Master 트리 보존 검증 ===

SELECT 'POST: Master tree (변경 없음)' AS K, COUNT(*) AS V
  FROM SCM_MGR.SCM_ADM_MNU_M
 START WITH MNU_ID = 'Master'
 CONNECT BY PRIOR MNU_ID = UPPR_MNU_ID;

