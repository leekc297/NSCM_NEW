PROMPT === BLOCK 0: 사전 카운트 ===

WITH M AS (
  SELECT 'DMF0008' MNU FROM DUAL UNION ALL SELECT 'DMF0020' FROM DUAL
  UNION ALL SELECT 'DMF0043' FROM DUAL UNION ALL SELECT 'DMF0043_01' FROM DUAL
  UNION ALL SELECT 'DMF0072' FROM DUAL
)
SELECT 'PRE: USER_GR_BTN_MPG' AS K, COUNT(*) AS V FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE MNU_ID IN (SELECT MNU FROM M) UNION ALL
SELECT 'PRE: USER_GR_MNU_MPG', COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_MPG_M WHERE MNU_ID IN (SELECT MNU FROM M) UNION ALL
SELECT 'PRE: MNU_BTN_MPG', COUNT(*) FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID IN (SELECT MNU FROM M) UNION ALL
SELECT 'PRE: API_M (간접)', COUNT(*) FROM SCM_MGR.SCM_ADM_API_M WHERE API_ID IN (SELECT API_ID FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID IN (SELECT MNU FROM M)) UNION ALL
SELECT 'PRE: PROC_M', COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M WHERE REGEXP_LIKE(PROC_NM, '^PKG_DMF(0008|0020|0043|0072)\.') UNION ALL
SELECT 'PRE: MNU_M', COUNT(*) FROM SCM_MGR.SCM_ADM_MNU_M WHERE MNU_ID IN (SELECT MNU FROM M);

PROMPT
PROMPT === BLOCK 1: 사용자 그룹별 버튼 권한 매핑 삭제 ===
DELETE FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M
 WHERE MNU_ID IN ('DMF0008','DMF0020','DMF0043','DMF0043_01','DMF0072');

PROMPT
PROMPT === BLOCK 2: 사용자 그룹별 메뉴 권한 매핑 삭제 ===
DELETE FROM SCM_MGR.SCM_ADM_USER_GR_MNU_MPG_M
 WHERE MNU_ID IN ('DMF0008','DMF0020','DMF0043','DMF0043_01','DMF0072');

PROMPT
PROMPT === BLOCK 3: API_M 삭제 (MNU_BTN_MPG 의 API_ID 경유, 자식 테이블 우선) ===
DELETE FROM SCM_MGR.SCM_ADM_API_M
 WHERE API_ID IN (
   SELECT DISTINCT API_ID
     FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M
    WHERE MNU_ID IN ('DMF0008','DMF0020','DMF0043','DMF0043_01','DMF0072')
 );

PROMPT
PROMPT === BLOCK 4: MNU_BTN_MPG_M 삭제 ===
DELETE FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M
 WHERE MNU_ID IN ('DMF0008','DMF0020','DMF0043','DMF0043_01','DMF0072');

PROMPT
PROMPT === BLOCK 5: PROC_M 삭제 (PKG_DMF{0008,0020,0043,0072}.*) ===
DELETE FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE REGEXP_LIKE(PROC_NM, '^PKG_DMF(0008|0020|0043|0072)\.');

