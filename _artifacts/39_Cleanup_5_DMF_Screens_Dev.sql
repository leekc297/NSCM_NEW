WITH M AS (
  SELECT 'DMF0008' MNU FROM DUAL UNION ALL SELECT 'DMF0020' FROM DUAL
  UNION ALL SELECT 'DMF0043' FROM DUAL UNION ALL SELECT 'DMF0043_01' FROM DUAL
  UNION ALL SELECT 'DMF0072' FROM DUAL
)
SELECT 'POST: USER_GR_BTN_MPG' AS K, COUNT(*) AS V FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE MNU_ID IN (SELECT MNU FROM M) UNION ALL
SELECT 'POST: USER_GR_MNU_MPG', COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_MPG_M WHERE MNU_ID IN (SELECT MNU FROM M) UNION ALL
SELECT 'POST: MNU_BTN_MPG', COUNT(*) FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID IN (SELECT MNU FROM M) UNION ALL
SELECT 'POST: PROC_M', COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M WHERE REGEXP_LIKE(PROC_NM, '^PKG_DMF(0008|0020|0043|0072)\.') UNION ALL
SELECT 'POST: MNU_M', COUNT(*) FROM SCM_MGR.SCM_ADM_MNU_M WHERE MNU_ID IN (SELECT MNU FROM M);

