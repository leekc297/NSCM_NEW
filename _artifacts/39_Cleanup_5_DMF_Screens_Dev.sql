PROMPT === BLOCK 6: 메뉴 자체 삭제 ===
DELETE FROM SCM_MGR.SCM_ADM_MNU_M
 WHERE MNU_ID IN ('DMF0008','DMF0020','DMF0043','DMF0043_01','DMF0072');

