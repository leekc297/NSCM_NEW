-- =====================================================================
-- DMF0003 — TitleSet(Column/Measure) 영구 저장 배선 (DMF0048 패턴 복제)
-- 목적: Column/Measure 선택이 sessionStorage 만이라 탭 재오픈 시 분실되던 것을,
--       SCM0002_SET_TITLESET_POPUP(SCM_MST_TITLESET_USER) 서버 영구 저장으로 전환.
-- SP/PROC_M: SCM0002_SET_TITLESET_POPUP + PROC_M 은 이미 등록/VALID (조회 확인). 신규 배선 = API_M/BTN_MPG/USER_GR 3종.
-- 참조: DMF0048_titleSet_SAVE (동일 API_URL). 멱등 MERGE. 감사 'admin'.
-- =====================================================================

-- 1) API_M — DMF0003_titleSet_SAVE → SCM0002_SET_TITLESET_POPUP
MERGE INTO SCM_MGR.SCM_ADM_API_M t
USING (SELECT 'DMF0003_titleSet_SAVE' API_ID FROM DUAL) s
ON (t.API_ID = s.API_ID)
WHEN MATCHED THEN UPDATE SET t.API_TP_CD='PROC', t.API_URL='SCM0002_SET_TITLESET_POPUP',
  t.API_MSG_DESC='DMF0003 Column/Measure TitleSet Save', t.USE_YN='Y',
  t.LAST_UPDATED_BY='admin', t.LAST_UPDATE_DATE=SYSDATE
WHEN NOT MATCHED THEN INSERT (API_ID, API_TP_CD, API_MSG_ID, API_MSG_DESC, API_URL, USE_YN,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES ('DMF0003_titleSet_SAVE','PROC','MSG_API_DMF0003_TITLESET_SAVE',
  'DMF0003 Column/Measure TitleSet Save','SCM0002_SET_TITLESET_POPUP','Y',
  'admin', SYSDATE, 'admin', SYSDATE);

-- 2) BTN_MPG — DMF0003 / titleSet / SAVE → DMF0003_titleSet_SAVE
MERGE INTO SCM_MGR.SCM_ADM_MNU_BTN_MPG_M t
USING (SELECT 'DMF0003' MNU_ID, 'titleSet' SHT_NM, 'SAVE' MNU_BTN_CD FROM DUAL) s
ON (t.MNU_ID=s.MNU_ID AND t.SHT_NM=s.SHT_NM AND t.MNU_BTN_CD=s.MNU_BTN_CD)
WHEN MATCHED THEN UPDATE SET t.API_ID='DMF0003_titleSet_SAVE', t.USE_YN='Y',
  t.LAST_UPDATED_BY='admin', t.LAST_UPDATE_DATE=SYSDATE
WHEN NOT MATCHED THEN INSERT (MNU_ID, SHT_NM, MNU_BTN_CD, API_ID, USE_YN,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES ('DMF0003','titleSet','SAVE','DMF0003_titleSet_SAVE','Y',
  'admin', SYSDATE, 'admin', SYSDATE);

-- 3) USER_GR — DMF0048 titleSet/SAVE 권한 그룹(ADMIN / DM ADMIN / DM Viewer) 복제
MERGE INTO SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M t
USING (
  SELECT g.USER_GR_ID, 'DMF0003' MNU_ID, 'titleSet' SHT_NM, 'SAVE' MNU_BTN_CD
  FROM (SELECT 'ADMIN' USER_GR_ID FROM DUAL
        UNION ALL SELECT 'DM ADMIN' FROM DUAL
        UNION ALL SELECT 'DM Viewer' FROM DUAL) g
) s
ON (t.USER_GR_ID=s.USER_GR_ID AND t.MNU_ID=s.MNU_ID AND t.SHT_NM=s.SHT_NM AND t.MNU_BTN_CD=s.MNU_BTN_CD)
WHEN MATCHED THEN UPDATE SET t.USE_YN='Y',
  t.LAST_UPDATED_BY='admin', t.LAST_UPDATE_DATE=SYSDATE
WHEN NOT MATCHED THEN INSERT (USER_GR_ID, MNU_ID, SHT_NM, MNU_BTN_CD, USE_YN,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES (s.USER_GR_ID, s.MNU_ID, s.SHT_NM, s.MNU_BTN_CD, 'Y',
  'admin', SYSDATE, 'admin', SYSDATE);

COMMIT;

