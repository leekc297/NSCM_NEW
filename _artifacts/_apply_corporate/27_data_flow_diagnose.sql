-- A. DM_PLN_SALES_PLAN_C 의 Division 40 / Version 분포 (마스터 row)
SELECT VERSION_NO, COUNT(*) AS C FROM DM_PLN_SALES_PLAN_C WHERE DIVISION_ID='40' GROUP BY VERSION_NO ORDER BY C DESC FETCH FIRST 20 ROWS ONLY;

-- B. DM_PLN_SALES_PLAN_C 전체 분포 (Division + VERSION_NO 매칭)
SELECT DIVISION_ID, VERSION_NO, COUNT(*) AS C FROM DM_PLN_SALES_PLAN_C WHERE VERSION_NO IN ('R_B_20250820_V008_C','R_S_20260205_V005_C','R_S_20250820_V012_C','R_B_20250523_V010','R_S_20250820_V010') GROUP BY DIVISION_ID, VERSION_NO ORDER BY DIVISION_ID, VERSION_NO;

-- C. SCM_MST_SSO_USER_INFO 의 minyonglee1 매핑
SELECT USER_ID, USER_NAME, DEPT_ID FROM SCM_MST_SSO_USER_INFO WHERE USER_ID='minyonglee1';

-- D. SCM_MST_SITE_ITEM 의 OWNER 컬럼에 minyonglee1 token 있는 row 수
SELECT COUNT(*) AS OWNER_MATCH FROM SCM_MST_SITE_ITEM WHERE OWNER LIKE '%minyonglee1%';

-- E. SCM_MST_SITE_ITEM 의 OWNER row 분포 (전체 + Division 40)
SELECT 'OWNER_TOTAL' AS K, COUNT(*) AS C FROM SCM_MST_SITE_ITEM WHERE OWNER IS NOT NULL;
SELECT 'OWNER_DIV40' AS K, COUNT(*) AS C FROM SCM_MST_SITE_ITEM WHERE OWNER IS NOT NULL AND DIVISION_ID='40';

-- F. minyonglee1 의 DEPT_ID 'LESIC' 가 SCM_MST_SSO_DEPT_INFO 에 있는지
SELECT DEPT_ID, DEPT_NAME_KO, UPPER_DEPT_ID FROM SCM_MST_SSO_DEPT_INFO WHERE DEPT_ID='LESIC' OR UPPER_DEPT_ID='LESIC';

