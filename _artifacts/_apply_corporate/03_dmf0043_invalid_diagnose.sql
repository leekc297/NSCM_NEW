SET PAGESIZE 500
SET LINESIZE 300

-- A. INVALID SP 인벤토리 (DMF0043 / CONTRIBUTE)
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM USER_OBJECTS WHERE STATUS='INVALID' AND (OBJECT_NAME LIKE '%DMF0043%' OR OBJECT_NAME LIKE '%CONTRIBUTE%') ORDER BY OBJECT_NAME;

-- B. USER_ERRORS 상세 (DMF0043 / CONTRIBUTE)
SELECT NAME, LINE, POSITION, SUBSTR(TEXT, 1, 200) AS ERR_TEXT FROM USER_ERRORS WHERE NAME LIKE '%DMF0043%' OR NAME LIKE '%CONTRIBUTE%' ORDER BY NAME, SEQUENCE FETCH FIRST 100 ROWS ONLY;

-- C. 의존 객체 chain
SELECT NAME, TYPE, REFERENCED_NAME, REFERENCED_TYPE FROM USER_DEPENDENCIES WHERE (NAME LIKE '%DMF0043%' OR REFERENCED_NAME LIKE '%DMF0043%') AND REFERENCED_TYPE IN ('PROCEDURE','PACKAGE','PACKAGE BODY','FUNCTION') ORDER BY NAME, REFERENCED_NAME;

-- D. 메타 chain
SELECT 'API_P_DMF0043' AS K, COUNT(*) AS C FROM SCM_ADM_API_M WHERE API_ID LIKE 'P_DMF0043_%';
SELECT 'PROC_DMF0043' AS K, COUNT(*) AS C FROM SCM_ADM_PROC_M WHERE PROC_NM LIKE 'DMF0043_%' OR PROC_NM LIKE 'P_DMF0043_%';
SELECT 'BTN_DMF0043' AS K, MNU_ID, COUNT(*) AS C FROM SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID IN ('DMF0043','DMF0043_01') GROUP BY MNU_ID;
SELECT 'SHEET_DMF0043' AS K, PROGRAM_ID, COUNT(*) AS C FROM SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID IN ('DMF0043','DMF0043_01') GROUP BY PROGRAM_ID;

-- E. 데이터 row count (DM 마스터)
SELECT 'CONTRIBUTE_MST' AS K, COUNT(*) AS C FROM DM_MST_CONTRIBUTE_RATIO_MST;
SELECT 'CONTRIBUTE_DTL' AS K, COUNT(*) AS C FROM DM_MST_CONTRIBUTE_RATIO_DTL;
SELECT 'MDF_VERSION' AS K, COUNT(*) AS C FROM DM_MDF_VERSION;

-- F. PKG_DMF0043 의 BODY STATUS
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM USER_OBJECTS WHERE OBJECT_NAME = 'PKG_DMF0043' ORDER BY OBJECT_TYPE;

EXIT;
