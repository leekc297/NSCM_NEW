import json, pathlib, datetime

HERE = pathlib.Path(__file__).parent
DEPLOY = pathlib.Path(r'C:\Projects\NSCM\_artifacts\_deploy_packages\DMF0053_GAP379_TITLESET_CLOUD_20261015\A_DB')
