SET SERVEROUTPUT ON
DECLARE
  v_rc1 SYS_REFCURSOR;
  v_rc2 SYS_REFCURSOR;
  v_before NUMBER;
  v_after NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_before FROM DM_MST_CONTRIBUTE_VER;
  DBMS_OUTPUT.PUT_LINE('BEFORE: ' || v_before);

  -- Test A: INSERT 'I' (사용자 동일 payload)
  DMF0043_SAVE_DM_MST_CONTRIBUTE_VER('I','','2029','29년_USER_TEST','desc test','Y','minyonglee1',v_rc1,v_rc2);
  IF v_rc1 IS NOT NULL THEN CLOSE v_rc1; END IF;
  IF v_rc2 IS NOT NULL THEN CLOSE v_rc2; END IF;
  COMMIT;

  SELECT COUNT(*) INTO v_after FROM DM_MST_CONTRIBUTE_VER;
  DBMS_OUTPUT.PUT_LINE('AFTER INSERT I: ' || v_after || ' (delta ' || (v_after - v_before) || ')');
END;
/

SELECT VER_SEQ, YYYY, VERSION_NM, VALID_YN, DESCRIPTION, CREATED_BY,
       TO_CHAR(CREATION_DATE,'YYYY-MM-DD HH24:MI:SS') AS CD
  FROM DM_MST_CONTRIBUTE_VER
 WHERE YYYY = '2029' OR VERSION_NM LIKE '%USER_TEST%'
 ORDER BY VER_SEQ DESC;
