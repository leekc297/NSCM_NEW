-- DMF0035 'C' 축 정정 검증 — [E20260904-TSCAXIS] 2026-09-04

-- V1. 패키지 상태 (VALID 필수)
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI') LAST_DDL
  FROM ALL_OBJECTS WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_DMF0035';

-- V2. 마커 실장 확인 (기대 = 4행: TITLE 상수 1 + MAIN 3)
SELECT LINE, TRIM(SUBSTR(TEXT,1,90)) TXT
  FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0035' AND TYPE='PACKAGE BODY'
   AND INSTR(TEXT,'E20260904-TSCAXIS')>0
 ORDER BY LINE;

-- V3. 'M' 축 무수정 확인 (기대 = 'mktFcstWaterfall' 선언 1 + 사용 4행: L317/327/401/425)
SELECT LINE, TRIM(SUBSTR(TEXT,1,80)) TXT
  FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0035' AND TYPE='PACKAGE BODY'
   AND INSTR(TEXT,'V_P_SHEET_NAME')>0
 ORDER BY LINE;

-- V4. 이행 결과 (기대 = 'Mkt Fcst Waterfall'/'C' 가 원본 축 이상, 원본 축 328행 그대로)
SELECT SHEET_NAME, USER_INQUIRY_COLUMN_TYPE_CODE TP,
       COUNT(*) ROWS_CNT, COUNT(DISTINCT USER_ID) USERS
  FROM SCM_MGR.SCM_MST_TITLESET_USER
 WHERE PROGRAM_ID='DMF0035'
 GROUP BY SHEET_NAME, USER_INQUIRY_COLUMN_TYPE_CODE
 ORDER BY 1,2;

-- V5. 고아 없음 (개인화 행 중 SHEET_COLUMNS 에 없는 컬럼 = 0 기대)
SELECT COUNT(*) ORPHAN
  FROM SCM_MGR.SCM_MST_TITLESET_USER U
 WHERE U.PROGRAM_ID='DMF0035' AND U.SHEET_NAME='Mkt Fcst Waterfall'
   AND U.USER_INQUIRY_COLUMN_TYPE_CODE='C'
   AND NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_MST_SHEET_COLUMNS C
                    WHERE C.PROGRAM_ID='DMF0035' AND C.SHEET_NAME='Mkt Fcst Waterfall'
                      AND C.COLUMN_NAME=U.COLUMN_NAME);
