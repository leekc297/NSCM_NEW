-- A. minyonglee1 의 그룹 매핑
SELECT 'GR_MPG' AS K, USER_GR_ID, USER_ID FROM SCM_ADM_USER_GR_MPG_M WHERE USER_ID='minyonglee1';

-- B. minyonglee1 의 모든 UNIT_AUTH row (Division 40 / 81 / 82 권한)
SELECT UA.USER_GR_ID, UA.UNIT_TP_CD, UA.UNIT_ID FROM SCM_ADM_USER_GR_UNIT_AUTH_MPG_M UA WHERE UA.USER_GR_ID IN (SELECT USER_GR_ID FROM SCM_ADM_USER_GR_MPG_M WHERE USER_ID='minyonglee1') AND UA.UNIT_TP_CD='D' ORDER BY UA.USER_GR_ID, UA.UNIT_ID;

-- C. minyonglee1 의 DMF0043 메뉴 권한
SELECT MM.USER_GR_ID, MM.MNU_ID FROM SCM_ADM_USER_GR_MNU_MPG_M MM WHERE MM.MNU_ID='DMF0043' AND MM.USER_GR_ID IN (SELECT USER_GR_ID FROM SCM_ADM_USER_GR_MPG_M WHERE USER_ID='minyonglee1');

-- D. DMF0043_GET_CONTRIBUTION_SALES_LIST 의 WHERE 절 안 권한 필터 확인 (line 80~250)
SELECT LINE, SUBSTR(TEXT, 1, 200) AS SRC FROM USER_SOURCE WHERE NAME='DMF0043_GET_CONTRIBUTION_SALES_LIST' AND TYPE='PROCEDURE' AND (UPPER(TEXT) LIKE '%USER_GR%' OR UPPER(TEXT) LIKE '%UNIT_AUTH%' OR UPPER(TEXT) LIKE '%USER_ID%' OR UPPER(TEXT) LIKE '%P_CREATED_BY%' OR UPPER(TEXT) LIKE '%DIVISION_ID%') ORDER BY LINE FETCH FIRST 30 ROWS ONLY;

