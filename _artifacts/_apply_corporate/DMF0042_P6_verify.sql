-- =====================================================================
-- DMF0042 P6 — 적용 후 일괄 검증 (전부 SELECT — 2026-07-15)
-- 적용 순서: P0a(조회 SP measure IS NULL OR) → P0b(standalone SAVE alias) → P1 → P2 → P3 → P4 → P5 → 본 P6
-- =====================================================================

-- 0) SP 상태 (기대: P0b 적용 후 INVALID 0건 — standalone SAVE 포함 전체 VALID)
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM USER_OBJECTS
WHERE OBJECT_NAME LIKE '%DMF0042%' AND OBJECT_TYPE IN ('PROCEDURE','PACKAGE','PACKAGE BODY')
  AND STATUS = 'INVALID';

-- 1a) PROC_M ↔ ALL_ARGUMENTS positional 대조 — standalone 11본 (기대: 0행)
SELECT NVL(p.PROC_NM, a.OBJECT_NAME) NM, NVL(p.SORT_ORD, a.POSITION) POS, p.COL_NM, a.ARGUMENT_NAME, a.IN_OUT
FROM (SELECT * FROM SCM_ADM_PROC_M WHERE PROC_NM LIKE 'DMF0042_%') p
FULL OUTER JOIN (SELECT * FROM ALL_ARGUMENTS WHERE OWNER='SCM_MGR' AND PACKAGE_NAME IS NULL
      AND OBJECT_NAME LIKE 'DMF0042_%'
      AND OBJECT_NAME <> 'DMF0042_SAVE_DM_PLN_BP_FCST') a  -- standalone SAVE = 의도적 미배선 (PKG 판 사용)
  ON a.OBJECT_NAME = p.PROC_NM AND a.POSITION = p.SORT_ORD
WHERE p.COL_NM IS NULL OR a.ARGUMENT_NAME IS NULL;

-- 1b) PROC_M ↔ ALL_ARGUMENTS positional 대조 — PKG SAVE (기대: 0행)
SELECT NVL(p.SORT_ORD, a.POSITION) POS, p.COL_NM, a.ARGUMENT_NAME, a.IN_OUT
FROM (SELECT * FROM SCM_ADM_PROC_M WHERE PROC_NM = 'PKG_DMF0042.P_DMF0042_SAVE_DM_PLN_BP_FCST') p
FULL OUTER JOIN (SELECT * FROM ALL_ARGUMENTS WHERE OWNER='SCM_MGR'
      AND PACKAGE_NAME = 'PKG_DMF0042' AND OBJECT_NAME = 'P_DMF0042_SAVE_DM_PLN_BP_FCST') a
  ON a.POSITION = p.SORT_ORD
WHERE p.COL_NM IS NULL OR a.ARGUMENT_NAME IS NULL;

-- 2) 건수 (기대: PROC_M 116 / API 23 / BTN 23 / USER_GR 60)
SELECT 'PROC_M' T, COUNT(*) CNT FROM SCM_ADM_PROC_M WHERE PROC_NM LIKE '%DMF0042%'
UNION ALL SELECT 'API_M', COUNT(*) FROM SCM_ADM_API_M WHERE API_ID LIKE 'DMF0042_%'
UNION ALL SELECT 'BTN_MPG', COUNT(*) FROM SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID = 'DMF0042'
UNION ALL SELECT 'USER_GR', COUNT(*) FROM SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE MNU_ID = 'DMF0042';

-- 2b) USER_GR 그룹별 (기대: ADMIN 23 / DM ADMIN 21 / DM Viewer 16)
SELECT USER_GR_ID, COUNT(*) CNT FROM SCM_ADM_USER_GR_MNU_BTN_MPG_M
WHERE MNU_ID = 'DMF0042' GROUP BY USER_GR_ID ORDER BY USER_GR_ID;

-- 3) MNU_URL (기대: business-plan / 전역 중복 1건 = 본인)
SELECT MNU_ID, MNU_URL, USE_YN FROM SCM_ADM_MNU_M WHERE MNU_ID = 'DMF0042';
SELECT COUNT(*) URL_DUP FROM SCM_ADM_MNU_M WHERE MNU_URL = 'business-plan';

-- 4) TITLESET (기대: 'bizPlan' 0건 / 'Biz Plan' 168건)
SELECT SHEET_NAME, COUNT(*) FROM SCM_MST_TITLESET_USER WHERE PROGRAM_ID = 'DMF0042' GROUP BY SHEET_NAME;

-- 5) MSG 신규 6종 (기대: 6 ID × 3 LANG = 18행, [TODO] 0건)
SELECT MSG_ID, COUNT(*) LANGS FROM SCM_ADM_MSG_M
WHERE MSG_ID BETWEEN 'MSG00675' AND 'MSG00680' GROUP BY MSG_ID ORDER BY MSG_ID;

-- 6) CMBO (기대: 1건)
SELECT SQL_ID, USE_YN, LENGTH(SQL_DTL_CTN) FROM SCM_ADM_CMBO_SQL_M WHERE SQL_ID = 'BizPlanUserAuthGroup';

-- 7) API_URL → 실존 SP 대조 (기대: 0행 — 참조 무결성.
--    PKG 판·PR_GET_DAY_RANGE·DMF0002/SCM0002 재사용분 포함 전수)
SELECT a.API_ID, a.API_URL FROM SCM_ADM_API_M a
WHERE a.API_ID LIKE 'DMF0042_%'
  AND NOT EXISTS (
    SELECT 1 FROM ALL_PROCEDURES pr
    WHERE pr.OWNER = 'SCM_MGR'
      AND (   (pr.OBJECT_NAME = a.API_URL AND pr.PROCEDURE_NAME IS NULL)                 -- standalone
           OR (pr.OBJECT_NAME || '.' || pr.PROCEDURE_NAME = a.API_URL) ) );              -- PKG.PROC

-- 8) BTN_MPG.API_ID → API_M 참조 무결성 (기대: 0행)
SELECT b.SHT_NM, b.MNU_BTN_CD, b.API_ID FROM SCM_ADM_MNU_BTN_MPG_M b
WHERE b.MNU_ID = 'DMF0042'
  AND NOT EXISTS (SELECT 1 FROM SCM_ADM_API_M a WHERE a.API_ID = b.API_ID AND a.USE_YN = 'Y');

-- 9) P0a 반영 확인 (기대: 조회 SP body 에 'IS NULL OR' measure 필터 존재 = 1행 이상)
SELECT LINE, SUBSTR(TEXT,1,100) FROM USER_SOURCE
WHERE NAME = 'DMF0042_GET_DM_PLN_BUSINESS_PLAN_DATA' AND TYPE = 'PROCEDURE'
  AND UPPER(TEXT) LIKE '%DIVISION_ID IS NULL OR%';
