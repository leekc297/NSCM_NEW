PROMPT [3/4] PR_SCM_ADM_NOTICE_CONTENT_MASTER_HIST : P_CONTENT CLOB, 로그 JSON 에 본문 길이만 기록
DECLARE
    V_SRC   CLOB;
    V_NEW   CLOB;
    N_ERR   NUMBER;
    C_OLD_PARAM CONSTANT VARCHAR2(100) := 'P_CONTENT         VARCHAR2';
    C_NEW_PARAM CONSTANT VARCHAR2(100) := 'P_CONTENT         CLOB';
    C_OLD_LOG   CONSTANT VARCHAR2(100) := '''P_CONTENT'' VALUE P_CONTENT';
    C_NEW_LOG   CONSTANT VARCHAR2(100) := '''P_CONTENT_LEN'' VALUE DBMS_LOB.GETLENGTH(P_CONTENT)';
BEGIN
    FOR R IN (SELECT TEXT FROM ALL_SOURCE
               WHERE OWNER = 'SCM_MGR' AND NAME = 'PR_SCM_ADM_NOTICE_CONTENT_MASTER_HIST' AND TYPE = 'PROCEDURE'
               ORDER BY LINE) LOOP
        V_SRC := V_SRC || R.TEXT;
    END LOOP;

    IF V_SRC IS NULL THEN
        RAISE_APPLICATION_ERROR(-20002, 'PR_SCM_ADM_NOTICE_CONTENT_MASTER_HIST not found');
    END IF;

    IF INSTR(V_SRC, C_NEW_PARAM) > 0 AND INSTR(V_SRC, C_NEW_LOG) > 0 THEN
        DBMS_OUTPUT.PUT_LINE('SKIP PR_SCM_ADM_NOTICE_CONTENT_MASTER_HIST (already patched)');
    ELSE
        IF INSTR(V_SRC, C_OLD_PARAM) = 0 OR INSTR(V_SRC, C_OLD_LOG) = 0 THEN
            RAISE_APPLICATION_ERROR(-20003, 'anchor not found in PR_SCM_ADM_NOTICE_CONTENT_MASTER_HIST');
        END IF;
        V_NEW := REPLACE(V_SRC, C_OLD_PARAM, C_NEW_PARAM);
        V_NEW := REPLACE(V_NEW, C_OLD_LOG, C_NEW_LOG);
        V_NEW := REGEXP_REPLACE(V_NEW, '^\s*PROCEDURE\s+("?SCM_MGR"?\.)?"?PR_SCM_ADM_NOTICE_CONTENT_MASTER_HIST"?',
                                'CREATE OR REPLACE PROCEDURE SCM_MGR.PR_SCM_ADM_NOTICE_CONTENT_MASTER_HIST', 1, 1, 'i');
        BEGIN
            EXECUTE IMMEDIATE V_NEW;
        EXCEPTION
            WHEN OTHERS THEN
                IF SQLCODE <> -24344 THEN RAISE; END IF;
        END;
        SELECT COUNT(*) INTO N_ERR FROM ALL_ERRORS
         WHERE OWNER = 'SCM_MGR' AND NAME = 'PR_SCM_ADM_NOTICE_CONTENT_MASTER_HIST';
        IF N_ERR > 0 THEN
            RAISE_APPLICATION_ERROR(-20004, 'PR_SCM_ADM_NOTICE_CONTENT_MASTER_HIST compile errors ' || N_ERR);
        END IF;
        DBMS_OUTPUT.PUT_LINE('DONE PR_SCM_ADM_NOTICE_CONTENT_MASTER_HIST');
    END IF;
END;
