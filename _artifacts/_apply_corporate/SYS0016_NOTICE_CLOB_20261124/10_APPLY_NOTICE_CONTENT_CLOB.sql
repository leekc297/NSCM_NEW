PROMPT [2/4] NOTICE_CONTENT -> CLOB (임시 컬럼 추가, 값 복사, 대조, 기존 컬럼 삭제, 이름 변경)
DECLARE
    PROCEDURE TO_CLOB_COL(P_TAB VARCHAR2) IS
        V_TYPE  VARCHAR2(30);
        N_TMP   NUMBER;
        N_DIFF  NUMBER;
    BEGIN
        SELECT MAX(DATA_TYPE) INTO V_TYPE FROM ALL_TAB_COLUMNS
         WHERE OWNER = 'SCM_MGR' AND TABLE_NAME = P_TAB AND COLUMN_NAME = 'NOTICE_CONTENT';
        SELECT COUNT(*) INTO N_TMP FROM ALL_TAB_COLUMNS
         WHERE OWNER = 'SCM_MGR' AND TABLE_NAME = P_TAB AND COLUMN_NAME = 'NOTICE_CONTENT_CLOB';

        IF V_TYPE = 'CLOB' AND N_TMP = 0 THEN
            DBMS_OUTPUT.PUT_LINE('SKIP ' || P_TAB || ' (already CLOB)');
            RETURN;
        END IF;

        IF V_TYPE = 'VARCHAR2' THEN
            IF N_TMP = 0 THEN
                EXECUTE IMMEDIATE 'ALTER TABLE SCM_MGR.' || P_TAB || ' ADD (NOTICE_CONTENT_CLOB CLOB)';
            END IF;
            EXECUTE IMMEDIATE 'UPDATE SCM_MGR.' || P_TAB || ' SET NOTICE_CONTENT_CLOB = TO_CLOB(NOTICE_CONTENT)';
            EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM SCM_MGR.' || P_TAB
                || ' WHERE (NOTICE_CONTENT IS NULL AND NOTICE_CONTENT_CLOB IS NOT NULL)'
                || '    OR (NOTICE_CONTENT IS NOT NULL AND NOTICE_CONTENT_CLOB IS NULL)'
                || '    OR (NOTICE_CONTENT IS NOT NULL AND DBMS_LOB.COMPARE(NOTICE_CONTENT_CLOB, TO_CLOB(NOTICE_CONTENT)) <> 0)'
                INTO N_DIFF;
            IF N_DIFF > 0 THEN
                ROLLBACK;
                RAISE_APPLICATION_ERROR(-20001, P_TAB || ' copy mismatch ' || N_DIFF);
            END IF;
            COMMIT;
            EXECUTE IMMEDIATE 'ALTER TABLE SCM_MGR.' || P_TAB || ' DROP COLUMN NOTICE_CONTENT';
        ELSIF V_TYPE IS NOT NULL THEN
            RAISE_APPLICATION_ERROR(-20006, P_TAB || '.NOTICE_CONTENT unexpected type ' || V_TYPE);
        END IF;

        EXECUTE IMMEDIATE 'ALTER TABLE SCM_MGR.' || P_TAB || ' RENAME COLUMN NOTICE_CONTENT_CLOB TO NOTICE_CONTENT';
        EXECUTE IMMEDIATE 'COMMENT ON COLUMN SCM_MGR.' || P_TAB || '.NOTICE_CONTENT IS ''공지내용''';
        DBMS_OUTPUT.PUT_LINE('DONE ' || P_TAB || ' -> CLOB');
    END;
BEGIN
    TO_CLOB_COL('SCM_ADM_NOTICE_CONTENT_MASTER');
    TO_CLOB_COL('SCM_ADM_NOTICE_CONTENT_MASTER_H');
END;
