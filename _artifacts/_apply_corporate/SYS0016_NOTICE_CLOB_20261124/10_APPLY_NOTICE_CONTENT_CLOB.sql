DECLARE
    PROCEDURE BAK(P_SRC VARCHAR2, P_BAK VARCHAR2) IS
        N NUMBER;
    BEGIN
        SELECT COUNT(*) INTO N FROM ALL_TABLES WHERE OWNER = 'SCM_MGR' AND TABLE_NAME = P_BAK;
        IF N = 0 THEN
            EXECUTE IMMEDIATE 'CREATE TABLE SCM_MGR.' || P_BAK || ' AS SELECT * FROM SCM_MGR.' || P_SRC;
            DBMS_OUTPUT.PUT_LINE('BACKUP CREATED ' || P_BAK);
        ELSE
            DBMS_OUTPUT.PUT_LINE('BACKUP SKIP ' || P_BAK);
        END IF;
    END;
BEGIN
    BAK('SCM_ADM_NOTICE_CONTENT_MASTER',   'SCM_ADM_NOTICE_CONTENT_MASTER_BAK20261124');
    BAK('SCM_ADM_NOTICE_CONTENT_MASTER_H', 'SCM_ADM_NOTICE_CONTENT_MASTER_H_BAK20261124');
END;
