PROMPT ===== V1. PKG 상태 (기대 VALID/VALID) =====
SELECT OBJECT_TYPE, STATUS FROM ALL_OBJECTS
WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_DMF0020' ORDER BY 1;

PROMPT ===== V2. PKG 내부 프로시저 20개 (16 + 편입 4) =====
SELECT COUNT(*) ACTUAL, 20 EXPECTED, CASE WHEN COUNT(*)=20 THEN 'PASS' ELSE 'FAIL ⛔' END RESULT
FROM ALL_PROCEDURES WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_DMF0020' AND PROCEDURE_NAME IS NOT NULL;

PROMPT ===== V3. 편입 4본 실존 + 인자수 (단독본과 동일해야 한다) =====
WITH exp (NM, CNT) AS (
  SELECT 'P_DMF0020_GET_SCM_MST_FUTURE_PRICE',20 FROM DUAL UNION ALL
  SELECT 'P_DMF0020_SAVE_SCM_MST_FUTURE_PRICE_ALL',19 FROM DUAL UNION ALL
  SELECT 'P_DMF0020_SAVE_SCM_MST_FUTURE_PRICE_POPUP',17 FROM DUAL UNION ALL
  SELECT 'P_DMF0020_GET_SCM_MST_FUTURE_PRICE_SAVE_PRICE_POPUP',18 FROM DUAL)
SELECT e.NM, e.CNT EXPECTED,
       (SELECT COUNT(*) FROM ALL_ARGUMENTS a WHERE a.OWNER='SCM_MGR' AND a.PACKAGE_NAME='PKG_DMF0020'
         AND a.OBJECT_NAME=e.NM) ACTUAL,
       CASE WHEN (SELECT COUNT(*) FROM ALL_ARGUMENTS a WHERE a.OWNER='SCM_MGR' AND a.PACKAGE_NAME='PKG_DMF0020'
                   AND a.OBJECT_NAME=e.NM) = e.CNT THEN 'PASS' ELSE 'FAIL ⛔' END RESULT
FROM exp e ORDER BY 4 DESC, 1;

PROMPT ===== V4. ⭐ 배선에 DMF0020 단독 SP 잔존 0 (공용 2건 제외) =====
SELECT COUNT(*) STANDALONE_LEFT, 0 EXPECTED,
       CASE WHEN COUNT(*)=0 THEN 'PASS' ELSE 'FAIL ⛔' END RESULT
FROM   SCM_ADM_MNU_BTN_MPG_M B JOIN SCM_ADM_API_M A ON A.API_ID=B.API_ID
WHERE  B.MNU_ID LIKE 'DMF0020%' AND A.API_URL LIKE '%DMF0020%' AND A.API_URL NOT LIKE 'PKG!_%' ESCAPE '!';

PROMPT ===== V5. PROC_M 계약 키도 PKG 표기 =====
SELECT PROC_NM, COUNT(*) ROWS_CNT FROM SCM_ADM_PROC_M
WHERE PROC_NM LIKE '%DMF0020%' GROUP BY PROC_NM ORDER BY 1;
-- 기대 4종 전부 'PKG_DMF0020.' 접두

PROMPT ===== V6. 배선 체인 끊김 (API_URL 이 가리키는 객체 실존) =====
SELECT A.API_ID, A.API_URL
FROM   SCM_ADM_API_M A
WHERE  A.API_ID LIKE '%DMF0020%'
AND    NOT EXISTS (
        SELECT 1 FROM ALL_PROCEDURES P
         WHERE P.OWNER='SCM_MGR'
           AND ( (INSTR(A.API_URL,'.') > 0
                  AND P.OBJECT_NAME = SUBSTR(A.API_URL,1,INSTR(A.API_URL,'.')-1)
                  AND P.PROCEDURE_NAME = SUBSTR(A.API_URL,INSTR(A.API_URL,'.')+1))
              OR (INSTR(A.API_URL,'.') = 0 AND P.OBJECT_NAME = A.API_URL) ));
-- 기대 0행
