SET PAGESIZE 500
SET LINESIZE 300

-- A. USERS tablespace 사용량
SELECT TABLESPACE_NAME, ROUND(USED_SPACE * 8192 / 1024 / 1024 / 1024, 2) AS USED_GB, ROUND(TABLESPACE_SIZE * 8192 / 1024 / 1024 / 1024, 2) AS SIZE_GB, ROUND(USED_PERCENT, 2) AS PCT FROM DBA_TABLESPACE_USAGE_METRICS WHERE TABLESPACE_NAME='USERS';

-- B. SCM_COM_SYS_LOG / SCM_COM_SQL_LOG row count + size
SELECT 'SCM_COM_SYS_LOG' AS TBL, COUNT(*) AS ROWS_CNT FROM SCM_COM_SYS_LOG;
SELECT 'SCM_COM_SQL_LOG' AS TBL, COUNT(*) AS ROWS_CNT FROM SCM_COM_SQL_LOG;

-- C. 가장 큰 user_segments (SCM_MGR schema, USERS tablespace, Top 15)
SELECT SEGMENT_NAME, SEGMENT_TYPE, ROUND(BYTES/1024/1024,2) AS MB FROM USER_SEGMENTS WHERE TABLESPACE_NAME='USERS' ORDER BY BYTES DESC FETCH FIRST 15 ROWS ONLY;

EXIT;
