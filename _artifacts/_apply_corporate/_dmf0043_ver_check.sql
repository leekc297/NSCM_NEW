PROMPT === 1. SCM_MST_CONTRIBUTE_VER 의 2025 신규 row 확인 ===
SELECT VER_SEQ, YYYY, VERSION_NM, VALID_YN, DESCRIPTION, CREATED_BY, TO_CHAR(CREATION_DATE,'YYYY-MM-DD HH24:MI:SS') AS CD
  FROM SCM_MST_CONTRIBUTE_VER
 WHERE YYYY = '2025' OR VERSION_NM LIKE '25년%'
 ORDER BY CREATION_DATE DESC;

PROMPT === 2. 전체 row 카운트 (시계열) ===
SELECT YYYY, COUNT(*) AS CNT
  FROM SCM_MST_CONTRIBUTE_VER
 GROUP BY YYYY
 ORDER BY YYYY DESC;

PROMPT === 3. DMF0043_SAVE_DM_MST_CONTRIBUTE_VER SP body 의 INSERT 분기 (line 1~80) ===
SELECT LINE, TEXT
  FROM USER_SOURCE
 WHERE NAME = 'DMF0043_SAVE_DM_MST_CONTRIBUTE_VER'
   AND TYPE = 'PROCEDURE'
   AND LINE BETWEEN 1 AND 100
 ORDER BY LINE;
