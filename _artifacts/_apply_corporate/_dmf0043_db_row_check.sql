PROMPT === 1. DM_MST_CONTRIBUTE_VER 2025/최근 row ===
SELECT VER_SEQ, YYYY, VERSION_NM, VALID_YN, DESCRIPTION,
       TO_CHAR(CREATION_DATE,'YYYY-MM-DD HH24:MI:SS') AS CD,
       CREATED_BY
  FROM DM_MST_CONTRIBUTE_VER
 WHERE YYYY IN ('2025','2024') OR VERSION_NM LIKE '25년%' OR VERSION_NM LIKE '%25년%'
 ORDER BY CREATION_DATE DESC NULLS LAST;

PROMPT === 2. DM_MST_CONTRIBUTE_RATIO_MST 최근 row (Y=2024 VER_SEQ=12) ===
SELECT COUNT(*) AS CNT,
       MAX(TO_CHAR(LAST_UPDATE_DATE,'YYYY-MM-DD HH24:MI:SS')) AS LAST_UPD
  FROM DM_MST_CONTRIBUTE_RATIO_MST
 WHERE VER_SEQ = 12 AND YYYYMM = '202401';

