-- ① MSG 3종 (MSG00476/00477 = .cs 주석 원문 / MSG00478 = 잠정)
MERGE INTO SCM_MGR.SCM_ADM_MSG_M t
USING (
  SELECT 'MSG00476' MSG_ID, 'KO' LANG_CD, '고객향 사이트로 Fcst Type을 AS 또는 WS로 등록하시는 경우 AS FROM SITE는 필수로 입력이 필요합니다.' MSG_NM, '[E20260402-001736] .cs 주석 원문' MSG_DESC FROM DUAL
  UNION ALL SELECT 'MSG00476', 'EN', 'When registering Fcst Type AS or WS for a customer-facing site, AS FROM SITE is required.', '[E20260402-001736]' FROM DUAL
  UNION ALL SELECT 'MSG00476', 'CN', '以面向客户的站点登记 Fcst Type 为 AS 或 WS 时, AS FROM SITE 为必填项.', '[E20260402-001736]' FROM DUAL
  UNION ALL SELECT 'MSG00477', 'KO', 'SCP Planner 권한사용자의 수정 가능한 시간이 아닙니다.', '[E20260604-000994] .cs 주석 원문' FROM DUAL
  UNION ALL SELECT 'MSG00477', 'EN', 'This is not an editable time window for the SCP Planner role.', '[E20260604-000994]' FROM DUAL
  UNION ALL SELECT 'MSG00477', 'CN', '当前不在 SCP Planner 权限用户可修改的时间段内.', '[E20260604-000994]' FROM DUAL
  UNION ALL SELECT 'MSG00478', 'KO', '{0} 권한의 수정 가능 시간({1} {2}~{3}) 동안에는 {4} 권한으로 수정할 수 없습니다.', '[E20260604-000994] AS-IS 원문 미확보 잠정 문구 — 협의 후 확정 필요 (파라미터: LIMIT_AUTH/EDIT_DAYS/FROM_TIME/TO_TIME/AUTH)' FROM DUAL
  UNION ALL SELECT 'MSG00478', 'EN', 'Editing with the {4} role is not allowed during the edit window of the {0} role ({1} {2}~{3}).', '[E20260604-000994] provisional' FROM DUAL
  UNION ALL SELECT 'MSG00478', 'CN', '在 {0} 权限的可修改时间({1} {2}~{3})内, 不能以 {4} 权限进行修改.', '[E20260604-000994] provisional' FROM DUAL
) s
ON (t.MSG_ID = s.MSG_ID AND t.LANG_CD = s.LANG_CD)
WHEN MATCHED THEN UPDATE SET t.MSG_NM = s.MSG_NM, t.MSG_DESC = s.MSG_DESC, t.MSG_TP_CD = 'MSG', t.USE_YN = 'Y',
  t.LAST_UPDATED_BY = 'admin', t.LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (MSG_ID, LANG_CD, MSG_NM, MSG_DESC, MSG_TP_CD, USE_YN,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES (s.MSG_ID, s.LANG_CD, s.MSG_NM, s.MSG_DESC, 'MSG', 'Y', 'admin', SYSDATE, 'admin', SYSDATE);

-- ② CMBO 4종 (관례: @camelCase bind, MDU_DIVS_CD='DM')
MERGE INTO SCM_MGR.SCM_ADM_CMBO_SQL_M t
USING (
  SELECT 'FcstTypeEditMode' SQL_ID, 'DM' MDU_DIVS_CD, 'DMF0003 W/S FcstType 편집 6종' SQL_NM,
         'SELECT SEGMENT1 AS CODE, SEGMENT2 AS NAME FROM SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE IN (''SALES_TYPE_CODE2'', ''SALES_TYPE_CODE2_ADD'') AND VALID_YN = ''Y'' ORDER BY LOOKUP_TYPE, DISPLAY_SEQ' SQL_DTL_CTN
  FROM DUAL
  UNION ALL
  SELECT 'FcstTypeWs', 'DM', 'DMF0003 W/S FcstType 4종',
         'SELECT SEGMENT1 AS CODE, SEGMENT2 AS NAME FROM SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = ''SALES_TYPE_CODE2'' AND VALID_YN = ''Y'' ORDER BY DISPLAY_SEQ'
  FROM DUAL
  UNION ALL
  SELECT 'Dmf0003ScpPlannerEditFlag', 'DM', 'DMF0003 SCP 시간창(MSG00477)',
         'SELECT SEGMENT2 AS CODE, SEGMENT3 AS NAME FROM SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = ''SCP_PLANNER_EDIT_FLAG'' AND SEGMENT1 = ''DMF0003'' AND SEGMENT2 = @divisionId AND SEGMENT3 = @userGroup AND VALID_YN = ''Y'' AND TO_CHAR(SYSDATE, ''DY'', ''NLS_DATE_LANGUAGE=ENGLISH'') = SEGMENT4 AND TO_CHAR(SYSDATE, ''HH24MI'') BETWEEN ATTRIBUTE1 AND ATTRIBUTE2'
  FROM DUAL
  UNION ALL
  SELECT 'MktFcstUserGroups', 'ALL', 'DMF0003 사용자 소속 그룹 전수',
         'SELECT USER_GR_ID AS CODE, USER_GR_ID AS NAME FROM SCM_ADM_USER_GR_MPG_M WHERE USER_ID = @sesUserId'
  FROM DUAL
  UNION ALL
  SELECT 'Dmf0003DmPlannerEditFlag', 'DM', 'DMF0003 DM 시간창(MSG00478)',
         'SELECT ATTRIBUTE3 || ''^'' || SEGMENT4 || ''^'' || ATTRIBUTE1 || ''^'' || ATTRIBUTE2 || ''^'' || SEGMENT3 AS CODE, ''DM_PLANNER_EDIT_FLAG'' AS NAME FROM SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = ''DM_PLANNER_EDIT_FLAG'' AND SEGMENT1 = ''DMF0003'' AND SEGMENT2 = @divisionId AND SEGMENT3 = @userGroup AND VALID_YN = ''Y'' AND TO_CHAR(SYSDATE, ''DY'', ''NLS_DATE_LANGUAGE=ENGLISH'') = SEGMENT4 AND TO_CHAR(SYSDATE, ''HH24MI'') BETWEEN ATTRIBUTE1 AND ATTRIBUTE2'
  FROM DUAL
) s
ON (t.SQL_ID = s.SQL_ID AND t.MDU_DIVS_CD = s.MDU_DIVS_CD)
WHEN MATCHED THEN UPDATE SET t.SQL_NM = s.SQL_NM, t.SQL_DTL_CTN = s.SQL_DTL_CTN, t.USE_YN = 'Y',
  t.LAST_UPDATED_BY = 'admin', t.LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (SQL_ID, MDU_DIVS_CD, SQL_NM, SQL_DTL_CTN, USE_YN,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES (s.SQL_ID, s.MDU_DIVS_CD, s.SQL_NM, s.SQL_DTL_CTN, 'Y', 'admin', SYSDATE, 'admin', SYSDATE);

-- ③ PROC_M — DMF0003_SAVE_MKT_FCST 에 authority(IN, 16) 추가 + OUT 2건 17/18 로 이동
--    (SP 시그니처 P_AUTHORITY 16번째와 positional 일치 — feedback_proc_meta_must_match_sp_signature)
UPDATE SCM_MGR.SCM_ADM_PROC_M
   SET SORT_ORD = SORT_ORD + 1, LAST_UPDATED_BY = 'admin', LAST_UPDATE_DATE = SYSDATE
 WHERE PROC_NM = 'DMF0003_SAVE_MKT_FCST'
   AND COL_TP_CD = 'OUT'
   AND NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_PROC_M
                    WHERE PROC_NM = 'DMF0003_SAVE_MKT_FCST' AND COL_NM = 'authority');

MERGE INTO SCM_MGR.SCM_ADM_PROC_M t
USING (SELECT 'DMF0003_SAVE_MKT_FCST' PROC_NM, 'authority' COL_NM, 'VARCHAR' DATA_TP_CD, 'IN' COL_TP_CD, 16 SORT_ORD FROM DUAL) s
ON (t.PROC_NM = s.PROC_NM AND t.COL_NM = s.COL_NM)
WHEN MATCHED THEN UPDATE SET t.DATA_TP_CD = s.DATA_TP_CD, t.COL_TP_CD = s.COL_TP_CD, t.SORT_ORD = s.SORT_ORD,
  t.LAST_UPDATED_BY = 'admin', t.LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (PROC_NM, COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES (s.PROC_NM, s.COL_NM, s.DATA_TP_CD, s.COL_TP_CD, s.SORT_ORD, 'admin', SYSDATE, 'admin', SYSDATE);

COMMIT;
