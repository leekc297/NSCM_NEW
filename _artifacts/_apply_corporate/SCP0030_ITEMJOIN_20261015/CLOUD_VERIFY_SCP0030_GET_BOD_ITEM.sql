PROMPT ===== C02. PKG 원문 판정 — 이번 보완 반영 여부 + 클라우드 원문이 사내와 같은 계열인지 =====
-- ITEMJOIN_MARK > 0          : 이번 보완 반영됨
-- OLD_EXISTS_FORM = 1        : 보완 전 문장(OR EXISTS) 존재 → 보완 대상
-- AJS_1007_MARK / AJS_1006_MARK / ZIONEX_POPUP_MARK : 사내 원문에 있는 다른 작업 마커 (0 이면 클라우드는 그 이전 원문)
SELECT OWNER
     , SUM(CASE WHEN TEXT LIKE '%E20261015-SCP0030ITEMJOIN%' THEN 1 ELSE 0 END)                         AS ITEMJOIN_MARK
     , SUM(CASE WHEN TEXT LIKE '%OR EXISTS (SELECT 1%' AND TEXT NOT LIKE '--%' AND TEXT NOT LIKE '%--%OR EXISTS%' THEN 1 ELSE 0 END) AS OLD_EXISTS_FORM
     , SUM(CASE WHEN TEXT LIKE '%, TABLE(V_ITEM_TAB) SA%' THEN 1 ELSE 0 END)                             AS NEW_JOIN_FORM
     , SUM(CASE WHEN TEXT LIKE '%2026.10.07 AJS Model/Nickname 검색 (START)%' THEN 1 ELSE 0 END)          AS AJS_1007_MARK
     , SUM(CASE WHEN TEXT LIKE '%2026.10.06 AJS 비활성 품목 제외 성능 개선 (START)%' THEN 1 ELSE 0 END)     AS AJS_1006_MARK
     , SUM(CASE WHEN TEXT LIKE '%PJ202650304%' THEN 1 ELSE 0 END)                                          AS ZIONEX_POPUP_MARK
     , COUNT(*)                                                                                             AS BODY_LINES
  FROM ALL_SOURCE
 WHERE NAME = 'PKG_SCP0030'
   AND TYPE = 'PACKAGE BODY'
 GROUP BY OWNER;

PROMPT ===== C03. 클라우드 BE 가 실제로 쓴 fetch 단위 + 과거 실행 소요 (V$SQL — 공유 풀에 남아 있는 동안만) =====
-- ROWS_PER_FETCH : BE 가 REF CURSOR 를 1회 왕복에 몇 행씩 받았는지 (100 근처 = NDBConnection defaultRowPrefetch 100)
-- HAS_CONCAT     : 1 = OR 확장으로 조인 2회 수행 중(보완 전 형태)
SELECT S.SQL_ID, S.CHILD_NUMBER, S.PLAN_HASH_VALUE, S.EXECUTIONS
     , ROUND(S.ELAPSED_TIME / 1e6 / GREATEST(S.EXECUTIONS, 1), 2)       AS ELA_S_PER_EXEC
     , ROUND(S.CPU_TIME / 1e6 / GREATEST(S.EXECUTIONS, 1), 2)           AS CPU_S_PER_EXEC
     , ROUND(S.BUFFER_GETS / GREATEST(S.EXECUTIONS, 1))                 AS BUFFER_GETS_PER_EXEC
     , S.ROWS_PROCESSED, S.FETCHES
     , ROUND(S.ROWS_PROCESSED / NULLIF(S.FETCHES, 0))                   AS ROWS_PER_FETCH
     , (SELECT COUNT(*) FROM V$SQL_PLAN P
         WHERE P.SQL_ID = S.SQL_ID AND P.CHILD_NUMBER = S.CHILD_NUMBER
           AND P.OPERATION = 'CONCATENATION')                           AS HAS_CONCAT
     , TO_CHAR(S.LAST_ACTIVE_TIME, 'YYYY-MM-DD HH24:MI:SS')            AS LAST_ACTIVE
  FROM V$SQL S
 WHERE S.SQL_TEXT LIKE 'SELECT IA.SEQ%'
   AND S.SQL_TEXT LIKE '%BOD_ITEM_VALID%'
 ORDER BY S.LAST_ACTIVE_TIME;

PROMPT ===== C04. 클라우드 SQL 로그 — SCP0030 호출별 소요 (최근 50건) =====
-- PARAMS_LEN 이 MB 단위(예 210,000,000)면 클라우드 BE 에 [E20260824-LOGPARAM] 미반영 — 결과셋 전체를 로그에 적재 중
SELECT LOG_SEQ
     , TO_CHAR(EXECUTE_TIME, 'YYYY-MM-DD HH24:MI:SS')                   AS EXEC_TIME
     , ELAPSED_MS
     , RESULT_COUNT
     , CREATED_BY
     , REGEXP_SUBSTR(DBMS_LOB.SUBSTR(SQL_TEXT, 300, 1), 'P_SCP0030_[A-Z_]+') AS PROC
     , DBMS_LOB.SUBSTR(SQL_TEXT, 200, INSTR(DBMS_LOB.SUBSTR(SQL_TEXT, 300, 1), '(')) AS ARGS
     , DBMS_LOB.GETLENGTH(PARAMS)                                       AS PARAMS_LEN
     , ROUND((CREATE_DATE - CAST(EXECUTE_TIME AS DATE)) * 86400)        AS LOG_WRITE_LAG_S
     , DBMS_LOB.SUBSTR(EXCEPTION, 200, 1)                               AS EXCEPTION
  FROM SCM_COM_SQL_LOG
 WHERE DBMS_LOB.INSTR(SQL_TEXT, 'PKG_SCP0030') > 0
 ORDER BY LOG_SEQ DESC
 FETCH FIRST 50 ROWS ONLY;

PROMPT ===== C05. DB 단독 소요 실측 — 전체 조회 1회 (BE·네트워크 제외) =====
ALTER SESSION SET STATISTICS_LEVEL = ALL;
DECLARE
    V_RC1  SYS_REFCURSOR;
    V_RC2  SYS_REFCURSOR;
    V_CUR  INTEGER;
    V_CNT  NUMBER := 0;
    V_T0   NUMBER;
    V_T1   NUMBER;
    V_T2   NUMBER;
BEGIN
    V_T0 := DBMS_UTILITY.GET_TIME;
    SCM_MGR.PKG_SCP0030.P_SCP0030_GET_BOD_ITEM('ALL','ALL','ALL','ALL','ALL','','','ALL','CLOUD_VERIFY','SCP0030', V_RC1, V_RC2);
    V_T1 := DBMS_UTILITY.GET_TIME;
    V_CUR := DBMS_SQL.TO_CURSOR_NUMBER(V_RC1);
    WHILE DBMS_SQL.FETCH_ROWS(V_CUR) > 0 LOOP
        V_CNT := V_CNT + 1;
    END LOOP;
    DBMS_SQL.CLOSE_CURSOR(V_CUR);
    V_T2 := DBMS_UTILITY.GET_TIME;
    DBMS_OUTPUT.PUT_LINE('C05 GET_BOD_ITEM FULL : OPEN=' || (V_T1 - V_T0) / 100 || 's  FETCH(DB내부)=' || (V_T2 - V_T1) / 100
                         || 's  TOTAL=' || (V_T2 - V_T0) / 100 || 's  ROWS=' || V_CNT);
END;
