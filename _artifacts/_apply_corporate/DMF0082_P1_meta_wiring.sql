-- =====================================================================
-- DMF0082 (Fcst&Price MGMT) 신규 생성 P1 — 메타 배선 통합 (2026-07-12)
-- 구성: ① MSG00667~671 신규 5종 (AS-IS TB_FX_MessageInfo 원문, 3언어)
--       ② PROC_M 2종 (GET_SPREAD_TITLE / POPUP_GET_FUTUREPRICE_INFO — ALL_ARGUMENTS positional 대조)
--       ③ API_M 4종 (spreadTitle/version/futurePriceInfo SEARCH + titleSet SAVE)
--       ④ BTN_MPG 4종 + ⑤ USER_GR 3그룹×4버튼
-- 근거: 사내 실측 — BTN_MPG 는 fcstNPrice SEARCH/SAVE 만 존재. spreadTitle 조회(FE 필수),
--       Version 팝업(DMF0073_GET_VERSION_SALESPRICE 공유 계약 9-arg), Exchange Rate 팝업,
--       Column/Measure 설정 영구저장(SCM0002_SET_TITLESET_POPUP — DMF0003/0048 선례) 배선 부재.
-- 멱등 MERGE / 감사 'admin' / 채번 근거: MAX(MSG0%)=MSG00666 실측 (2026-07-12).
-- =====================================================================

-- ① 신규 MSG 5종 (AS-IS 원문 — TB_FX_MessageInfo Ko/En 실측, CN 은 EN 준용 번역)
MERGE INTO SCM_MGR.SCM_ADM_MSG_M t
USING (
  SELECT 'MSG00667' MSG_ID, 'KO' LANG_CD, '권한을 가진 Division이 없습니다.' MSG_NM FROM DUAL
  UNION ALL SELECT 'MSG00667', 'EN', 'No authority assigned.' FROM DUAL
  UNION ALL SELECT 'MSG00667', 'CN', '没有拥有权限的 Division.' FROM DUAL
  UNION ALL SELECT 'MSG00668', 'KO', 'Edit Mode 에서는 수행할 수 없습니다.' FROM DUAL
  UNION ALL SELECT 'MSG00668', 'EN', 'No alterations are allowed in Edit Mode.' FROM DUAL
  UNION ALL SELECT 'MSG00668', 'CN', '在编辑模式下无法执行.' FROM DUAL
  UNION ALL SELECT 'MSG00669', 'KO', '수정모드에서는 입력할 수 없습니다.' FROM DUAL
  UNION ALL SELECT 'MSG00669', 'EN', 'Input is not allowed in edit mode.' FROM DUAL
  UNION ALL SELECT 'MSG00669', 'CN', '在修改模式下无法输入.' FROM DUAL
  UNION ALL SELECT 'MSG00670', 'KO', '추가된 행에 입력된 수량 또는 가격이 없습니다. 각 행 별로 하루 이상의 일자에 수량 또는 가격이 입력되어야 합니다.' FROM DUAL
  UNION ALL SELECT 'MSG00670', 'EN', 'There is no quantity or price entered in the added row. Quantity or price must be entered for at least one day per row.' FROM DUAL
  UNION ALL SELECT 'MSG00670', 'CN', '新增行未输入数量或价格. 每行至少需在一天输入数量或价格.' FROM DUAL
  UNION ALL SELECT 'MSG00671', 'KO', '수정할 수 없는 메져입니다.' FROM DUAL
  UNION ALL SELECT 'MSG00671', 'EN', 'This is an unmodifiable Measure.' FROM DUAL
  UNION ALL SELECT 'MSG00671', 'CN', '这是无法修改的 Measure.' FROM DUAL
) s
ON (t.MSG_ID = s.MSG_ID AND t.LANG_CD = s.LANG_CD)
WHEN MATCHED THEN UPDATE SET t.MSG_NM = s.MSG_NM, t.MSG_TP_CD = 'MSG', t.USE_YN = 'Y',
  t.LAST_UPDATED_BY = 'admin', t.LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (MSG_ID, LANG_CD, MSG_NM, MSG_DESC, MSG_TP_CD, USE_YN,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES (s.MSG_ID, s.LANG_CD, s.MSG_NM, NULL, 'MSG', 'Y',
  'admin', SYSDATE, 'admin', SYSDATE);

-- ② PROC_M — DMF0082_GET_SPREAD_TITLE (ALL_ARGUMENTS 실측: P_START_YYYYMMDD/P_END_YYYYMMDD/
--    P_CREATED_BY/P_DIVISION_ID + O_RC1. COL_NM 은 FE titleFilters 키(procedures.d.ts 정합) —
--    3번째 sesUserId = BE 세션 자동 주입)
DELETE FROM SCM_MGR.SCM_ADM_PROC_M WHERE PROC_NM = 'DMF0082_GET_SPREAD_TITLE';
INSERT INTO SCM_MGR.SCM_ADM_PROC_M (PROC_NM, COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'DMF0082_GET_SPREAD_TITLE', COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD,
  'admin', SYSDATE, 'admin', SYSDATE
FROM (
  SELECT 'startYyyymmdd' COL_NM, 'VARCHAR' DATA_TP_CD, 'IN' COL_TP_CD, 1 SORT_ORD FROM DUAL
  UNION ALL SELECT 'endYyyymmdd', 'VARCHAR', 'IN', 2 FROM DUAL
  UNION ALL SELECT 'sesUserId', 'VARCHAR', 'IN', 3 FROM DUAL
  UNION ALL SELECT 'divisionId', 'VARCHAR', 'IN', 4 FROM DUAL
  UNION ALL SELECT 'data', 'CURSOR', 'OUT', 5 FROM DUAL
);

-- ② PROC_M — DMF0082_POPUP_GET_FUTUREPRICE_INFO (실측: P_START_YYYYMMDD/P_END_YYYYMMDD/
--    P_USER_ID/P_MNU_ID + O_RC1 + O_RESULT_CURSOR)
DELETE FROM SCM_MGR.SCM_ADM_PROC_M WHERE PROC_NM = 'DMF0082_POPUP_GET_FUTUREPRICE_INFO';
INSERT INTO SCM_MGR.SCM_ADM_PROC_M (PROC_NM, COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'DMF0082_POPUP_GET_FUTUREPRICE_INFO', COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD,
  'admin', SYSDATE, 'admin', SYSDATE
FROM (
  SELECT 'startYyyymmdd' COL_NM, 'VARCHAR' DATA_TP_CD, 'IN' COL_TP_CD, 1 SORT_ORD FROM DUAL
  UNION ALL SELECT 'endYyyymmdd', 'VARCHAR', 'IN', 2 FROM DUAL
  UNION ALL SELECT 'sesUserId', 'VARCHAR', 'IN', 3 FROM DUAL
  UNION ALL SELECT 'mnuId', 'VARCHAR', 'IN', 4 FROM DUAL
  UNION ALL SELECT 'o_rc1', 'CURSOR', 'OUT', 5 FROM DUAL
  UNION ALL SELECT 'o_result_cursor', 'PROC_RESULT', 'OUT', 6 FROM DUAL
);

-- ③ API_M 4종
MERGE INTO SCM_MGR.SCM_ADM_API_M t
USING (
  SELECT 'DMF0082_spreadTitle_SEARCH' API_ID, 'PROC_SELECT' API_TP_CD,
         'DMF0082_GET_SPREAD_TITLE' API_URL, 'DMF0082 동적 시간축 컬럼 조회' API_MSG_DESC FROM DUAL
  UNION ALL SELECT 'DMF0082_version_SEARCH', 'PROC_SELECT',
         'DMF0073_GET_VERSION_SALESPRICE', 'DMF0082 Version 팝업 조회 (DMF0073 공유 계약)' FROM DUAL
  UNION ALL SELECT 'DMF0082_futurePriceInfo_SEARCH', 'PROC_SELECT',
         'DMF0082_POPUP_GET_FUTUREPRICE_INFO', 'DMF0082 환율(Exchange Rate) 팝업 조회' FROM DUAL
  UNION ALL SELECT 'DMF0082_titleSet_SAVE', 'PROC_SAVE',
         'SCM0002_SET_TITLESET_POPUP', 'DMF0082 Column/Measure TitleSet 영구 저장' FROM DUAL
) s
ON (t.API_ID = s.API_ID)
WHEN MATCHED THEN UPDATE SET t.API_TP_CD = s.API_TP_CD, t.API_URL = s.API_URL,
  t.API_MSG_DESC = s.API_MSG_DESC, t.USE_YN = 'Y',
  t.LAST_UPDATED_BY = 'admin', t.LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (API_ID, API_TP_CD, API_MSG_ID, API_MSG_DESC, API_URL, USE_YN,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES (s.API_ID, s.API_TP_CD, 'MSG_API_' || s.API_ID, s.API_MSG_DESC, s.API_URL, 'Y',
  'admin', SYSDATE, 'admin', SYSDATE);

-- ④ BTN_MPG 4종 (SHT_NM = FE SHEETS value 그대로)
MERGE INTO SCM_MGR.SCM_ADM_MNU_BTN_MPG_M t
USING (
  SELECT 'DMF0082' MNU_ID, 'spreadTitle' SHT_NM, 'SEARCH' MNU_BTN_CD, 'DMF0082_spreadTitle_SEARCH' API_ID FROM DUAL
  UNION ALL SELECT 'DMF0082', 'version', 'SEARCH', 'DMF0082_version_SEARCH' FROM DUAL
  UNION ALL SELECT 'DMF0082', 'futurePriceInfo', 'SEARCH', 'DMF0082_futurePriceInfo_SEARCH' FROM DUAL
  UNION ALL SELECT 'DMF0082', 'titleSet', 'SAVE', 'DMF0082_titleSet_SAVE' FROM DUAL
) s
ON (t.MNU_ID = s.MNU_ID AND t.SHT_NM = s.SHT_NM AND t.MNU_BTN_CD = s.MNU_BTN_CD)
WHEN MATCHED THEN UPDATE SET t.API_ID = s.API_ID, t.USE_YN = 'Y',
  t.LAST_UPDATED_BY = 'admin', t.LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (MNU_ID, SHT_NM, MNU_BTN_CD, API_ID, USE_YN,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES (s.MNU_ID, s.SHT_NM, s.MNU_BTN_CD, s.API_ID, 'Y',
  'admin', SYSDATE, 'admin', SYSDATE);

-- ⑤ USER_GR — 기존 DMF0082 권한 3그룹(ADMIN / DM ADMIN / DM Viewer) × 신규 4버튼
--    (DM Viewer 는 SEARCH 만 — 기존 fcstNPrice 패턴과 동일하게 titleSet SAVE 는 부여,
--     화면 표시설정은 조회권한 사용자도 저장 가능 — DMF0003/0048 선례)
MERGE INTO SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M t
USING (
  SELECT g.USER_GR_ID, 'DMF0082' MNU_ID, b.SHT_NM, b.MNU_BTN_CD
  FROM (SELECT 'ADMIN' USER_GR_ID FROM DUAL
        UNION ALL SELECT 'DM ADMIN' FROM DUAL
        UNION ALL SELECT 'DM Viewer' FROM DUAL) g
  CROSS JOIN (
    SELECT 'spreadTitle' SHT_NM, 'SEARCH' MNU_BTN_CD FROM DUAL
    UNION ALL SELECT 'version', 'SEARCH' FROM DUAL
    UNION ALL SELECT 'futurePriceInfo', 'SEARCH' FROM DUAL
    UNION ALL SELECT 'titleSet', 'SAVE' FROM DUAL
  ) b
) s
ON (t.USER_GR_ID = s.USER_GR_ID AND t.MNU_ID = s.MNU_ID AND t.SHT_NM = s.SHT_NM AND t.MNU_BTN_CD = s.MNU_BTN_CD)
WHEN MATCHED THEN UPDATE SET t.USE_YN = 'Y',
  t.LAST_UPDATED_BY = 'admin', t.LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (USER_GR_ID, MNU_ID, SHT_NM, MNU_BTN_CD, USE_YN,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES (s.USER_GR_ID, s.MNU_ID, s.SHT_NM, s.MNU_BTN_CD, 'Y',
  'admin', SYSDATE, 'admin', SYSDATE);

COMMIT;

