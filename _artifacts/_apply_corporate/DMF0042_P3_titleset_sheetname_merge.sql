--   SHEET_COLUMNS(63) / SHEET_MEASURE(9) = 'Biz Plan' 정본과 표기 통일 (DMF0021 P2 선례).
-- 복합키: USER_ID + PROGRAM_ID + SHEET_NAME + USER_INQUIRY_COLUMN_TYPE_CODE + COLUMN_NAME
