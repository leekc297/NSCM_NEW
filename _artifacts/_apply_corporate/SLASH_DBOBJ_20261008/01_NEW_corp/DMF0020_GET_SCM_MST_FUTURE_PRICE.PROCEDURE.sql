    IF P_BIZTYPE IS NOT NULL AND P_BIZTYPE <> 'ALL' THEN
        SELECT TRIM(REGEXP_SUBSTR(P_BIZTYPE, '[^^]+', 1, LEVEL))
        BULK COLLECT INTO T_BIZTYPE
        FROM DUAL CONNECT BY REGEXP_SUBSTR(P_BIZTYPE, '[^^]+', 1, LEVEL) IS NOT NULL;
