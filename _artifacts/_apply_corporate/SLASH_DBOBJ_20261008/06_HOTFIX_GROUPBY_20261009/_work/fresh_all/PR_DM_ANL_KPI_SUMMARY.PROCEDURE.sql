                AND BB.ISO_YYYYWW = CC.ISO_YYYYWW
              GROUP BY AA.DIVISION_ID, BB.BASIS_YYYYMMDD ) Y
         , SCM_SYS_CALENDAR_M Z
     WHERE 1=1
