       AND X.VERSION_NO = Y.VERSION_NO
       AND X.YYYYMMDD = Z.BASIS_YYYYMMDD
       AND X.MEASURE IN ('MKT_FCST','CUST_FCST','RTF')
       AND X.VERSION_NO LIKE 'MF_W%'
