     GROUP BY DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, YYYYMMDD, CELL_PROD_SITE_ID, FROM_SITE_ID;

    DBMS_STATS.GATHER_TABLE_STATS(OWNNAME => 'SCM_MGR', TABNAME => 'GT_PRDM2_TEMPX');

    /* DELETE BALANCE from DM_PLN_MKT_FCST */
    DELETE FROM DM_PLN_MKT_FCST
     WHERE MEASURE = 'BALANCE'
       AND EXISTS (SELECT 1 FROM GT_PRDM2_TEMPX
                    WHERE DM_PLN_MKT_FCST.DIVISION_ID   = GT_PRDM2_TEMPX.DIVISION_ID
                      AND DM_PLN_MKT_FCST.PROJECT_CODE  = GT_PRDM2_TEMPX.PROJECT_CODE
                      AND DM_PLN_MKT_FCST.SCM_SITE_ID   = GT_PRDM2_TEMPX.SCM_SITE_ID
                      AND DM_PLN_MKT_FCST.ITEM_ID       = GT_PRDM2_TEMPX.ITEM_ID
                      AND DM_PLN_MKT_FCST.DOM_EXP       = GT_PRDM2_TEMPX.DOM_EXP
                      AND DM_PLN_MKT_FCST.FCST_TYPE     = GT_PRDM2_TEMPX.FCST_TYPE
                      AND DM_PLN_MKT_FCST.INCOTERMS     = GT_PRDM2_TEMPX.INCOTERMS
                      AND DM_PLN_MKT_FCST.PLANT_SITE_ID = GT_PRDM2_TEMPX.PLANT_SITE_ID
                      AND DM_PLN_MKT_FCST.YYYYMMDD     >= V_PLAN_START_YYYYMMDD);


    V_LOG_TYPE    := 'ING';
    V_LOG_MESSAGE := 'step - A019 ';
    V_DESCRIPTION := '';
    D_EVENT_DATE  := SYSDATE;
    BEGIN PR_DM_SYS_LOG_BATCH($$PLSQL_UNIT, V_LOG_TYPE, N_LOG_COUNT, V_LOG_MESSAGE, V_DESCRIPTION, D_EVENT_DATE, USER, V_PROC_INPUT, NULL, NULL, NULL); END;
    V_LOG_MESSAGE := NULL;

    /* INSERT BALANCE into DM_PLN_MKT_FCST */
    INSERT INTO DM_PLN_MKT_FCST
    ( DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, MEASURE, PLANT_SITE_ID, YYYYMMDD, QTY
    , CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE )
    SELECT DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, 'BALANCE' AS MEASURE, PLANT_SITE_ID, YYYYMMDD
         , SUM(ACCUM_X) AS ACCUM_X
         , 'BALANCE_MAKE', SYSDATE, 'BALANCE_MAKE', SYSDATE
      FROM GT_PRDM2_TEMPX
     WHERE YYYYMMDD >= V_PLAN_START_YYYYMMDD
       AND ACCUM_X BETWEEN -9999999999 AND 9999999999
       AND ACCUM_X <> 0
     GROUP BY DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, YYYYMMDD;

    /* 40사업부 BALANCE → DM_PLN_CFM_MKT_DEMAND_PLAN */
    IF P_DIVISION_ID = '40' THEN
        DELETE FROM DM_PLN_CFM_MKT_DEMAND_PLAN
         WHERE MEASURE = 'BALANCE'
           AND EXISTS (SELECT 1 FROM GT_PRDM2_TEMPX
                        WHERE DM_PLN_CFM_MKT_DEMAND_PLAN.DIVISION_ID   = GT_PRDM2_TEMPX.DIVISION_ID
                          AND CASE WHEN DM_PLN_CFM_MKT_DEMAND_PLAN.DIVISION_ID = '40'
                                   THEN DM_PLN_CFM_MKT_DEMAND_PLAN.END_CUSTOMER
                                   ELSE DM_PLN_CFM_MKT_DEMAND_PLAN.PROJECT_CODE END = GT_PRDM2_TEMPX.PROJECT_CODE
                          AND DM_PLN_CFM_MKT_DEMAND_PLAN.SCM_SITE_ID       = GT_PRDM2_TEMPX.SCM_SITE_ID
                          AND DM_PLN_CFM_MKT_DEMAND_PLAN.ITEM_ID           = GT_PRDM2_TEMPX.ITEM_ID
                          AND DM_PLN_CFM_MKT_DEMAND_PLAN.DOM_EXP           = GT_PRDM2_TEMPX.DOM_EXP
                          AND DM_PLN_CFM_MKT_DEMAND_PLAN.FCST_TYPE         = GT_PRDM2_TEMPX.FCST_TYPE
                          AND DM_PLN_CFM_MKT_DEMAND_PLAN.INCOTERMS         = GT_PRDM2_TEMPX.INCOTERMS
                          AND DM_PLN_CFM_MKT_DEMAND_PLAN.PLANT_SITE_ID     = GT_PRDM2_TEMPX.PLANT_SITE_ID
                          AND DM_PLN_CFM_MKT_DEMAND_PLAN.YYYYMMDD         >= V_PLAN_START_YYYYMMDD
                          AND DM_PLN_CFM_MKT_DEMAND_PLAN.CELL_PROD_SITE_ID = GT_PRDM2_TEMPX.CELL_PROD_SITE_ID);

        INSERT INTO DM_PLN_CFM_MKT_DEMAND_PLAN
        ( DIVISION_ID, PROJECT_CODE, END_CUSTOMER, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, MEASURE, PLANT_SITE_ID, CELL_PROD_SITE_ID
        , YYYYMMDD, QTY, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE )
        SELECT DIVISION_ID, PROJECT_CODE
             , CASE WHEN DIVISION_ID = '40' THEN PROJECT_CODE ELSE ' ' END AS END_CUSTOMER
             , SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, 'BALANCE' AS MEASURE, PLANT_SITE_ID, CELL_PROD_SITE_ID
             , YYYYMMDD, ACCUM_X
             , 'BALANCE_MAKE', SYSDATE, 'BALANCE_MAKE', SYSDATE
          FROM GT_PRDM2_TEMPX
         WHERE YYYYMMDD >= V_PLAN_START_YYYYMMDD
           AND ACCUM_X BETWEEN -9999999999 AND 9999999999
           AND ACCUM_X <> 0;
    END IF;
    /* ================================================================================================================ */
    /* MKT_FCST_QTY_BALANCE_CREATE (END) */
    /* ================================================================================================================ */

    /* ================================================================================================================ */
    /* SALES_PLAN_AMT_CREATE_LOCAL_KRW 호출 (START) */
    /* ================================================================================================================ */
    IF V_P_PLAN_ID <> 'CALL' THEN
        /* MSSQL L3015 EXEC [dbo].[PR_DM_ANL_SALES_PLAN_AMT_CREATE_LOCAL_KRW] @c_division_id, 'SYSTEM' (활성문) */
        PR_DM_ANL_SALES_PLAN_AMT_CREATE_LOCAL_KRW(C_DIVISION_ID, 'SYSTEM');


        V_LOG_TYPE    := 'ING';
        V_LOG_MESSAGE := 'step - A020 ';
        V_DESCRIPTION := '';
        D_EVENT_DATE  := SYSDATE;
        BEGIN PR_DM_SYS_LOG_BATCH($$PLSQL_UNIT, V_LOG_TYPE, N_LOG_COUNT, V_LOG_MESSAGE, V_DESCRIPTION, D_EVENT_DATE, USER, V_PROC_INPUT, NULL, NULL, NULL); END;
        V_LOG_MESSAGE := NULL;
    END IF;

    /* ================================================================================================================ */
    /* CUTOFF 관련작업 (batch_call_yn = 'N'인 경우만 — UI 호출) */
    /* ================================================================================================================ */
    IF V_P_PLAN_ID <> 'CALL' AND V_BATCH_CALL_YN = 'N' THEN

        V_LOG_TYPE    := 'ING';
        V_LOG_MESSAGE := 'step - A021 ';
        V_DESCRIPTION := '';
        D_EVENT_DATE  := SYSDATE;
        BEGIN PR_DM_SYS_LOG_BATCH($$PLSQL_UNIT, V_LOG_TYPE, N_LOG_COUNT, V_LOG_MESSAGE, V_DESCRIPTION, D_EVENT_DATE, USER, V_PROC_INPUT, NULL, NULL, NULL); END;
        V_LOG_MESSAGE := NULL;

        /* Cutoff VERSION_NO insert */
        INSERT INTO GT_PRDM2_CUTOFF ( VERSION_NO )
        SELECT VERSION_NO
          FROM DM_MST_VERSION
         WHERE DIVISION_ID = C_DIVISION_ID
           AND YYYYMMDD   >= V_PLAN_START_YYYYMMDD
           AND VERSION_TYPE IN ('MF_W', 'SF_W')
         ORDER BY VERSION_NO;

        DBMS_STATS.GATHER_TABLE_STATS(OWNNAME => 'SCM_MGR', TABNAME => 'GT_PRDM2_CUTOFF');

        /* CURSOR2_CUTOFF : CUTOFF VERSION_NO 별 RTF_SCP MEASURE 작업 호출 (MSSQL L3057~3113) */
        FOR R_CUTOFF IN CUR_CUTOFF LOOP
            C_VERSION_NO := R_CUTOFF.VERSION_NO;
            /* MSSQL L3084 EXEC [dbo].[PR_DM_PLN_MKT_FCST_C_QTY_BALANCE_CREATE] @c_division_id, @c_VERSION_NO (활성문) */
            PR_DM_PLN_MKT_FCST_C_QTY_BALANCE_CREATE(C_DIVISION_ID, C_VERSION_NO);
        END LOOP;

        /* ================================================================================================================ */
        /* [E20250210-000219] SCP 엔진 재수행에 따른 Sales Plan Cutoff 재수행 자동화 */
        /* ================================================================================================================ */
        IF V_P_PLAN_ID IS NOT NULL AND V_P_PLAN_ID <> 'CALL' THEN
            BEGIN
                SELECT COUNT(*)
                  INTO N_SP_VERSION_CNT
                  FROM DM_MST_VERSION
                 WHERE DIVISION_ID  = C_DIVISION_ID
                   AND YYYYMMDD    >= V_PLAN_START_YYYYMMDD
                   AND VERSION_TYPE = 'SP_W';
            EXCEPTION WHEN NO_DATA_FOUND THEN
                N_SP_VERSION_CNT := 0;
            END;

            IF N_SP_VERSION_CNT > 0 THEN
                BEGIN
                    SELECT COUNT(*)
                      INTO N_TIME_EXCLUDE_CNT
                      FROM SCM_MST_DIVISION A
                     WHERE A.ATTRIBUTE3 IN ('40','81','82')
                       AND A.DIVISION_ID NOT IN (
                               SELECT SEGMENT1
                                 FROM SCM_ADM_LOOKUP_MASTER_DETAIL
                                WHERE LOOKUP_TYPE = 'CUTOFF_EXCLUDE_TIME_DIVISION'
                                  AND SEGMENT1    = C_DIVISION_ID
                                  AND SEGMENT2 IN (SELECT DAYOFWEEK
                                                     FROM SCM_SYS_CALENDAR_M
                                                    WHERE BASIS_YYYYMMDD = TO_CHAR(SYSDATE,'YYYYMMDD')
                                                      AND TO_NUMBER(TO_CHAR(SYSDATE,'HH24') || TO_CHAR(SYSDATE,'MI'))
                                                          BETWEEN TO_NUMBER(SEGMENT3) AND TO_NUMBER(SEGMENT4))
                                  AND VALID_YN = 'Y')
                       AND A.DIVISION_ID = C_DIVISION_ID;
                EXCEPTION WHEN NO_DATA_FOUND THEN
                    N_TIME_EXCLUDE_CNT := 0;
                END;

                IF N_TIME_EXCLUDE_CNT > 0 THEN
                    /* Sales Plan 비교 (GT_PRDM2_TEMP_SALES_PLAN_C vs GT_PRDM2_TEMP_MKT_FCST_C) */
                    INSERT INTO GT_PRDM2_TEMP_SALES_PLAN_C
                    ( DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, MEASURE, PLANT_SITE_ID, YYYYMMDD, CELL_PROD_SITE_ID, QTY )
                    SELECT DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, MEASURE, PLANT_SITE_ID, YYYYMMDD, CELL_PROD_SITE_ID, QTY
                      FROM DM_PLN_SALES_PLAN_C
                     WHERE DIVISION_ID = C_DIVISION_ID
                       AND VERSION_NO  = (SELECT MAX(VERSION_NO) FROM DM_MST_VERSION WHERE VERSION_TYPE = 'SP_W' AND DIVISION_ID = C_DIVISION_ID)
                       AND MEASURE     = 'RTF_SYS_RP'
                       AND YYYYMMDD   >= V_PLAN_START_YYYYMMDD;

                    DBMS_STATS.GATHER_TABLE_STATS(OWNNAME => 'SCM_MGR', TABNAME => 'GT_PRDM2_TEMP_SALES_PLAN_C');

                    INSERT INTO GT_PRDM2_TEMP_MKT_FCST_C
                    ( DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, MEASURE, PLANT_SITE_ID, YYYYMMDD, CELL_PROD_SITE_ID, QTY )
                    SELECT DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, MEASURE, PLANT_SITE_ID, YYYYMMDD, CELL_PROD_SITE_ID, QTY
                      FROM DM_PLN_CFM_MKT_DEMAND_PLAN_C
                     WHERE DIVISION_ID = C_DIVISION_ID
                       AND VERSION_NO  = (SELECT MAX(VERSION_NO) FROM DM_MST_VERSION WHERE VERSION_TYPE = 'MF_W' AND DIVISION_ID = C_DIVISION_ID)
                       AND MEASURE     = 'RTF_SYS_RP'
                       AND YYYYMMDD   >= V_PLAN_START_YYYYMMDD;

                    DBMS_STATS.GATHER_TABLE_STATS(OWNNAME => 'SCM_MGR', TABNAME => 'GT_PRDM2_TEMP_MKT_FCST_C');


                    SELECT COUNT(*)
                      INTO N_DIFF_CNT
                      FROM (
                        SELECT DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, MEASURE, PLANT_SITE_ID, YYYYMMDD, CELL_PROD_SITE_ID, QTY
                          FROM GT_PRDM2_TEMP_SALES_PLAN_C
                      ) A
                      /* FULL OUTER JOIN → Oracle (+)는 완전 외부조인(FULL OUTER) 미지원 → H-3 ANSI JOIN 유지 */
                      FULL OUTER JOIN (
                        SELECT DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, MEASURE, PLANT_SITE_ID, YYYYMMDD, CELL_PROD_SITE_ID, QTY
                          FROM GT_PRDM2_TEMP_MKT_FCST_C
                      ) B
                          ON A.DIVISION_ID       = B.DIVISION_ID
                         AND A.PROJECT_CODE      = B.PROJECT_CODE
                         AND A.SCM_SITE_ID       = B.SCM_SITE_ID
                         AND A.ITEM_ID           = B.ITEM_ID
                         AND A.DOM_EXP           = B.DOM_EXP
                         AND A.FCST_TYPE         = B.FCST_TYPE
                         AND A.INCOTERMS         = B.INCOTERMS
                         AND A.MEASURE           = B.MEASURE
                         AND A.PLANT_SITE_ID     = B.PLANT_SITE_ID
                         AND A.YYYYMMDD          = B.YYYYMMDD
                         AND A.CELL_PROD_SITE_ID = B.CELL_PROD_SITE_ID
                     WHERE ((A.QTY <> B.QTY) OR (A.DIVISION_ID IS NULL) OR (B.DIVISION_ID IS NULL));

                    IF N_DIFF_CNT > 0 THEN
                        /*                                        @c_division_id, @p_cutoff_yyyymmdd = '', @p_creation_type = 'IRREGULAR' (활성문)
                           2번째 인자 '' 는 Oracle 에서 NULL. 피호출측이 IF L_CUTOFF_YYYYMMDD IS NULL THEN SYSDATE 로 처리하므로 MSSQL 과 동일. */
                        PR_DM_PLN_SALES_PLAN_C_QTY_BALANCE_CREATE(C_DIVISION_ID, '', 'IRREGULAR');
                    END IF;
                END IF;
            END IF;
        END IF;


        V_LOG_TYPE    := 'ING';
        V_LOG_MESSAGE := 'step - A024 ';
        V_DESCRIPTION := '';
        D_EVENT_DATE  := SYSDATE;
        BEGIN PR_DM_SYS_LOG_BATCH($$PLSQL_UNIT, V_LOG_TYPE, N_LOG_COUNT, V_LOG_MESSAGE, V_DESCRIPTION, D_EVENT_DATE, USER, V_PROC_INPUT, NULL, NULL, NULL); END;
        V_LOG_MESSAGE := NULL;
    END IF;

    /* ================================================================================================================ */
    /* 종료 LOG (END) */
    /* ================================================================================================================ */
    V_LOG_TYPE    := 'END';
    V_LOG_MESSAGE := '########## END of procedure ##########';
    V_DESCRIPTION := 'p_division_id : ' || NVL(P_DIVISION_ID,'NULL') || ' / ' || 'p_plan_id : ' || NVL(P_PLAN_ID,'NULL');
    D_EVENT_DATE  := SYSDATE;
    BEGIN PR_DM_SYS_LOG_BATCH($$PLSQL_UNIT, V_LOG_TYPE, N_LOG_COUNT, V_LOG_MESSAGE, V_DESCRIPTION, D_EVENT_DATE, USER, V_PROC_INPUT, NULL, NULL, NULL); END;

    /* 트랜잭션 COMMIT 미신설: 원본은 COMMIT WORK;(비활성)로 호출자 위임 */
    OPEN O_RESULT_CURSOR FOR SELECT '0' AS CODE, 'SUCCESS' AS MESSAGE FROM DUAL;

EXCEPTION
    WHEN OTHERS THEN
        /* 트랜잭션 ROLLBACK 미신설: 원본은 ROLLBACK(비활성)로 호출자 위임 */
        V_SQL_CODE   := TO_CHAR(SQLCODE);
        V_SQL_ERRMSG := SQLERRM;
        V_BACKTRACE  := DBMS_UTILITY.FORMAT_ERROR_BACKTRACE;
        V_LOG_MESSAGE := SUBSTR(V_SQL_ERRMSG, 1, 1000);
        V_DESCRIPTION := SUBSTR(V_BACKTRACE, 1, 500);
        BEGIN
            PR_DM_SYS_LOG_BATCH($$PLSQL_UNIT, 'ERROR', N_LOG_COUNT, V_LOG_MESSAGE, V_DESCRIPTION, SYSDATE, USER, V_PROC_INPUT, V_SQL_CODE, V_SQL_ERRMSG, V_BACKTRACE);
        EXCEPTION WHEN OTHERS THEN NULL;
        END;

        OPEN O_RESULT_CURSOR FOR SELECT '0' AS CODE, '[[[' || V_SQL_CODE || ']' || V_SQL_ERRMSG AS MESSAGE FROM DUAL;
END PR_DM_PLN_MKT_FCST_QTY_BALANCE_CREATE;
