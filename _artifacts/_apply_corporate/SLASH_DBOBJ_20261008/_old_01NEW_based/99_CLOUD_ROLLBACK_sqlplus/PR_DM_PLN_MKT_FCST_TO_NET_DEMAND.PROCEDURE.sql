                        INSERT INTO GT_DM_NET_TEMP3
                            (DIVISION_ID, VERSION_NO, CUTOFF_YYYYMMDD, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, CELL_PROD_SITE_ID, DEMAND_TYPE, YYYYMMDD, DEMAND_PRIORITY, QTY, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE, ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10)
                        VALUES (N_DIVISION_ID, N_VERSION_NO, N_CUTOFF_YYYYMMDD, N_PROJECT_CODE, N_SCM_SITE_ID, N_ITEM_ID, N_DOM_EXP, N_FCST_TYPE, N_INCOTERMS, N_PLANT_SITE_ID, N_CELL_PROD_SITE_ID, V_DEMAND_TYPE, N_YYYYMMDD, TO_CHAR(V_PRIORITY_COUNT), V_INSERT_CALC, 'dm_batch', SYSDATE, 'dm_batch', SYSDATE, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL);
                        V_DEMAND_TYPE := '';
                    END IF;

                    IF V_DEMAND_TYPE2 = 'NF' THEN
                        V_PRIORITY_COUNT := V_PRIORITY_COUNT + 1;
                        INSERT INTO GT_DM_NET_TEMP3
                            (DIVISION_ID, VERSION_NO, CUTOFF_YYYYMMDD, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, CELL_PROD_SITE_ID, DEMAND_TYPE, YYYYMMDD, DEMAND_PRIORITY, QTY, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE, ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10)
                        VALUES (N_DIVISION_ID, N_VERSION_NO, N_CUTOFF_YYYYMMDD, N_PROJECT_CODE, N_SCM_SITE_ID, N_ITEM_ID, N_DOM_EXP, N_FCST_TYPE, N_INCOTERMS, N_PLANT_SITE_ID, N_CELL_PROD_SITE_ID, V_DEMAND_TYPE2, N_YYYYMMDD, TO_CHAR(V_PRIORITY_COUNT), V_INSERT_CALC2, 'dm_batch', SYSDATE, 'dm_batch', SYSDATE, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL);
                    END IF;
                END IF;

                V_MATCH_ROWS := V_MATCH_ROWS + 1;

                /* CF 잔량이 있으나 당주 데이터가 끝난 경우 잔여 NF 생성 */
                IF V_MAX_ROWS < V_MATCH_ROWS AND V_CALC_CF > 0 THEN
                    IF N_QTY > 0 THEN
                        V_PRIORITY_COUNT := V_PRIORITY_COUNT + 1;
                        INSERT INTO GT_DM_NET_TEMP3
                            (DIVISION_ID, VERSION_NO, CUTOFF_YYYYMMDD, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, CELL_PROD_SITE_ID, DEMAND_TYPE, YYYYMMDD, DEMAND_PRIORITY, QTY, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE, ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10)
                        VALUES (N_DIVISION_ID, N_VERSION_NO, N_CUTOFF_YYYYMMDD, N_PROJECT_CODE, N_SCM_SITE_ID, N_ITEM_ID, N_DOM_EXP, N_FCST_TYPE, N_INCOTERMS, N_PLANT_SITE_ID, N_CELL_PROD_SITE_ID, 'NF', N_YYYYMMDD, TO_CHAR(V_PRIORITY_COUNT), V_CALC_CF, 'dm_batch', SYSDATE, 'dm_batch', SYSDATE, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL);
                    END IF;
                    V_CALC_CF := 0;
                END IF;
            END LOOP;
            CLOSE CUR_ROW;
        END LOOP;
        /* CURSOR_1 CLOSE */

        /* 전주 CutOff 없어도 당주 CutOff 있으면 DEMAND_TYPE='NF' 생성 */
        INSERT INTO GT_DM_NET_TEMP3
            (DIVISION_ID, VERSION_NO, CUTOFF_YYYYMMDD, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, CELL_PROD_SITE_ID, DEMAND_TYPE, YYYYMMDD, QTY, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE, ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10)
        SELECT DIVISION_ID, VERSION_NO, CUTOFF_YYYYMMDD, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, CELL_PROD_SITE_ID
             , 'NF', YYYYMMDD, QTY, 'dm_batch', SYSDATE, 'dm_batch', SYSDATE, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL
          FROM GT_DM_NET_TEMP2;

        /* customer_LT 적용 -> #TEMP4 */
        INSERT INTO GT_DM_NET_TEMP4
            (DIVISION_ID, VERSION_NO, CUTOFF_YYYYMMDD, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, CELL_PROD_SITE_ID, DEMAND_TYPE, YYYYMMDD, DEMAND_PRIORITY, QTY, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE, ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10)
        SELECT A.DIVISION_ID, A.VERSION_NO, A.CUTOFF_YYYYMMDD, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.DOM_EXP, A.FCST_TYPE, A.INCOTERMS, A.PLANT_SITE_ID, A.CELL_PROD_SITE_ID, A.DEMAND_TYPE
             , CASE
                   WHEN A.DIVISION_ID IN (SELECT DIVISION_ID FROM SCM_MST_DIVISION WHERE ATTRIBUTE3 IN ('40', '81')) THEN
                        TO_CHAR(TO_DATE(A.YYYYMMDD, 'YYYYMMDD')
                                - NVL((SELECT MAX(LT_TOTAL) FROM SCP_MST_BOD_V BOD WHERE BOD.DIVISION_ID = A.DIVISION_ID AND BOD.FROM_SITE = A.PLANT_SITE_ID AND BOD.TO_SITE = A.SCM_SITE_ID AND BOD.INCOTERMS = A.INCOTERMS), 0)
                                , 'YYYYMMDD')
                   WHEN A.DIVISION_ID = '82' THEN
                        TO_CHAR(TO_DATE(A.YYYYMMDD, 'YYYYMMDD') - NVL(BOD_V.LT_TOTAL, 0), 'YYYYMMDD')
                   ELSE A.YYYYMMDD
               END   AS YYYYMMDD
             , A.DEMAND_PRIORITY
             , A.QTY, A.CREATED_BY, A.CREATION_DATE, A.LAST_UPDATED_BY, A.LAST_UPDATE_DATE
             , A.YYYYMMDD   AS ATTRIBUTE1
             , CASE
                   WHEN A.DIVISION_ID IN (SELECT DIVISION_ID FROM SCM_MST_DIVISION WHERE ATTRIBUTE3 IN ('40', '81')) THEN
                        TO_CHAR(NVL((SELECT MAX(LT_TOTAL) FROM SCP_MST_BOD_V BOD WHERE BOD.DIVISION_ID = A.DIVISION_ID AND BOD.FROM_SITE = A.PLANT_SITE_ID AND BOD.TO_SITE = A.SCM_SITE_ID AND BOD.INCOTERMS = A.INCOTERMS), 0))
                   WHEN A.DIVISION_ID = '82' THEN
                        TO_CHAR(NVL(BOD_V.LT_TOTAL, 0))
               END   AS ATTRIBUTE2
             , CASE WHEN A.DEMAND_TYPE = 'CF' THEN '1' WHEN A.DEMAND_TYPE = 'UF' THEN '2' WHEN A.DEMAND_TYPE = 'NF' THEN '3' ELSE '0' END   AS ATTRIBUTE3
             , NVL(
                   CASE
                       WHEN A.DIVISION_ID = '40' THEN
                            (SELECT ATTRIBUTE7 FROM SCM_MST_SITE_ITEM M WHERE 1 = 1 AND M.DIVISION_ID = A.DIVISION_ID AND M.PROJECT_CODE = A.PROJECT_CODE AND M.SCM_SITE_ID = A.SCM_SITE_ID AND M.ITEM_ID = A.ITEM_ID AND ROWNUM = 1)
                       WHEN A.DIVISION_ID = '82' THEN
                            TO_CHAR((SELECT PRIORITY FROM DM_MST_SHIPMENT_PRIORITY P
                              WHERE 1 = 1 AND P.DIVISION_ID = A.DIVISION_ID AND P.PROJECT_CODE = A.PROJECT_CODE AND P.ITEM_ID = A.ITEM_ID AND P.SCM_SITE_ID = A.SCM_SITE_ID
                                AND P.YYYYMMDD = TO_CHAR(FN_NEXT_DAY(TO_DATE(A.YYYYMMDD, 'YYYYMMDD') - NVL(BOD_V.LT_TOTAL, 0), 'MON') - 7, 'YYYYMMDD')
                                AND ROWNUM = 1))
                       ELSE '' END
                 , '99')   AS ATTRIBUTE4
             , A.ATTRIBUTE5, A.ATTRIBUTE6, A.ATTRIBUTE7, A.ATTRIBUTE8, A.ATTRIBUTE9, A.ATTRIBUTE10

          FROM GT_DM_NET_TEMP3 A
             , (
                    SELECT DIVISION_ID, TO_SITE, INCOTERMS, PRIORITY, LT_TOTAL
                         , ROW_NUMBER() OVER (PARTITION BY TO_SITE, INCOTERMS ORDER BY PRIORITY ASC, LT_TOTAL ASC) AS SEQ
                      FROM SCP_MST_BOD_V B
               ) BOD_V
         WHERE A.DIVISION_ID = BOD_V.DIVISION_ID(+)
           AND A.SCM_SITE_ID = BOD_V.TO_SITE(+)
           AND A.INCOTERMS   = BOD_V.INCOTERMS(+)
           AND BOD_V.SEQ(+)  = 1;

        /* CURSOR_3 : #TEMP4 -> #TEMP5 */
        SELECT COUNT(*)        INTO V_DEMAND_SORT_MAX     FROM GT_DM_NET_TEMP4;
        SELECT MIN(ATTRIBUTE1) INTO V_DEMAND_MIN_YYYYMMDD FROM GT_DM_NET_TEMP4;
        -- 2026.09.18 AJS PLANT_SITE_ID 첫 행 판정 - 초기값 NULL 로 첫 행 진입 보장 (START)
--        V_FL_PLANT_SITE_ID := ' ';
        -- 2026.09.18 AJS PLANT_SITE_ID 첫 행 판정 (END)

        FOR C3 IN (
            SELECT DIVISION_ID, VERSION_NO, CUTOFF_YYYYMMDD, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, CELL_PROD_SITE_ID, DEMAND_TYPE, YYYYMMDD, DEMAND_PRIORITY, QTY, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE, ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10
              FROM GT_DM_NET_TEMP4
             ORDER BY CASE WHEN P_DIVISION_ID = '82' THEN ATTRIBUTE4 END
                    , CASE WHEN P_DIVISION_ID = '82' THEN YYYYMMDD END
                    , CASE WHEN P_DIVISION_ID <> '82' THEN PLANT_SITE_ID END
                    , CASE WHEN P_DIVISION_ID <> '82' THEN CELL_PROD_SITE_ID END
                    , CASE WHEN P_DIVISION_ID <> '82' THEN ATTRIBUTE3 END
                    , CASE WHEN P_DIVISION_ID <> '82' THEN YYYYMMDD END
        ) LOOP
            IF C3.DIVISION_ID = '82' THEN
                IF V_FL_YYYYMMDD IS NULL THEN
                    V_FL_YYYYMMDD := C3.YYYYMMDD;
                END IF;
                IF V_FL_YYYYMMDD <> NVL(C3.YYYYMMDD, ' ') THEN
                    V_ESS_COUNT := V_ESS_COUNT + 1;
                    V_FL_YYYYMMDD := C3.YYYYMMDD;
                END IF;
                V_INST_COUNT := V_ESS_COUNT;
            ELSE
                -- 2026.09.18 AJS PLANT_SITE_ID 첫 행 판정 (START)
--                IF V_FL_PLANT_SITE_ID <> NVL(C3.PLANT_SITE_ID, ' ') THEN
                IF V_FL_PLANT_SITE_ID IS NULL OR V_FL_PLANT_SITE_ID <> NVL(C3.PLANT_SITE_ID, ' ') THEN
                -- 2026.09.18 AJS PLANT_SITE_ID 첫 행 판정 (END)
                    V_FL_PLANT_SITE_ID := C3.PLANT_SITE_ID;
                    V_FL_DEMAND_TYPE   := C3.DEMAND_TYPE;
                    V_FL_YYYYMMDD      := C3.YYYYMMDD;
                    V_CF_COUNT := 1001;
                    V_UF_COUNT := 2001;
                    V_NF_COUNT := 3001;
                END IF;
                IF V_FL_DEMAND_TYPE = NVL(C3.DEMAND_TYPE, ' ') THEN
                    IF V_FL_DEMAND_TYPE = 'CF' THEN
                        IF V_FL_YYYYMMDD <> NVL(C3.YYYYMMDD, ' ') THEN
                            V_CF_COUNT := V_CF_COUNT + 1;
                            V_FL_YYYYMMDD := C3.YYYYMMDD;
                        END IF;
                        V_INST_COUNT := V_CF_COUNT;
                    END IF;
                    IF V_FL_DEMAND_TYPE = 'UF' THEN
                        IF V_FL_YYYYMMDD <> NVL(C3.YYYYMMDD, ' ') THEN
                            V_UF_COUNT := V_UF_COUNT + 1;
                            V_FL_YYYYMMDD := C3.YYYYMMDD;
                        END IF;
                        V_INST_COUNT := V_UF_COUNT;
                    END IF;
                    IF V_FL_DEMAND_TYPE = 'NF' THEN
                        IF V_FL_YYYYMMDD <> NVL(C3.YYYYMMDD, ' ') THEN
                            V_NF_COUNT := V_NF_COUNT + 1;
                            V_FL_YYYYMMDD := C3.YYYYMMDD;
                        END IF;
                        V_INST_COUNT := V_NF_COUNT;
                    END IF;
                ELSE
                    V_FL_DEMAND_TYPE := C3.DEMAND_TYPE;
                    V_FL_YYYYMMDD    := C3.YYYYMMDD;
                    IF V_FL_DEMAND_TYPE = 'CF' THEN
                        V_CF_COUNT := 1001;
                        V_INST_COUNT := V_CF_COUNT;
                    END IF;
                    IF V_FL_DEMAND_TYPE = 'UF' THEN
                        V_UF_COUNT := 2001;
                        V_INST_COUNT := V_UF_COUNT;
                    END IF;
                    IF V_FL_DEMAND_TYPE = 'NF' THEN
                        V_NF_COUNT := 3001;
                        V_INST_COUNT := V_NF_COUNT;
                    END IF;
                END IF;
            END IF;

            /* DEMAND_PRIORITY 산출 */
            V_X4_PAD := CASE WHEN 2 - LENGTH(C3.ATTRIBUTE4) < 0 THEN NULL
                             ELSE SUBSTR('00', 1, 2 - LENGTH(C3.ATTRIBUTE4)) || C3.ATTRIBUTE4 END;
            V_DEMAND_PRIORITY := CASE
                WHEN C3.DIVISION_ID LIKE '81%' THEN TO_CHAR(TO_DATE(C3.ATTRIBUTE1, 'YYYYMMDD') - TO_DATE(V_DEMAND_MIN_YYYYMMDD, 'YYYYMMDD') + 1) || C3.ATTRIBUTE3
                WHEN C3.DIVISION_ID = '40' THEN V_X4_PAD || TO_CHAR(V_INST_COUNT)
                WHEN C3.DIVISION_ID = '82' THEN '1' || V_X4_PAD || TO_CHAR(V_INST_COUNT) || C3.ATTRIBUTE3
                ELSE TO_CHAR(V_INST_COUNT)
            END;

            INSERT INTO GT_DM_NET_TEMP5
                (DIVISION_ID, VERSION_NO, CUTOFF_YYYYMMDD, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, CELL_PROD_SITE_ID, DEMAND_TYPE, YYYYMMDD, DEMAND_PRIORITY, QTY, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE, ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10)
            VALUES (C3.DIVISION_ID, C3.VERSION_NO, C3.CUTOFF_YYYYMMDD, C3.PROJECT_CODE, C3.SCM_SITE_ID, C3.ITEM_ID, C3.DOM_EXP, C3.FCST_TYPE, C3.INCOTERMS, C3.PLANT_SITE_ID, C3.CELL_PROD_SITE_ID, C3.DEMAND_TYPE, C3.YYYYMMDD
                  , V_DEMAND_PRIORITY
                  , C3.QTY, C3.CREATED_BY, C3.CREATION_DATE, C3.LAST_UPDATED_BY, C3.LAST_UPDATE_DATE, C3.ATTRIBUTE1, C3.ATTRIBUTE2, C3.ATTRIBUTE3
                  , V_X4_PAD
                  , C3.ATTRIBUTE5, C3.ATTRIBUTE6, C3.ATTRIBUTE7, C3.ATTRIBUTE8, C3.ATTRIBUTE9, C3.ATTRIBUTE10);
        END LOOP;
        /* CURSOR_3 CLOSE */

        /* 선박biz사업부 NET DEMAND 제거 [E20230112-000310] */
        DELETE FROM GT_DM_NET_TEMP5 A
         WHERE EXISTS (SELECT 1 FROM SCM_MST_SITE B WHERE A.DIVISION_ID = B.DIVISION_ID AND A.SCM_SITE_ID = B.SCM_SITE_ID AND NVL(B.OPERATION_GROUP, 'X') <> 'W')
           AND A.DIVISION_ID IN (SELECT SEGMENT1 FROM SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = 'DM_NET_DEMAND_EXCEPTION' AND VALID_YN = 'Y')
           AND A.SCM_SITE_ID IN (SELECT SEGMENT2 FROM SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = 'DM_NET_DEMAND_EXCEPTION' AND VALID_YN = 'Y');

        /* DM_PLN_NET_DEMAND insert전 중복제거, insert */
        DELETE FROM DM_PLN_NET_DEMAND D
         WHERE EXISTS (
                SELECT 1 FROM GT_DM_NET_TEMP5 B
                 WHERE D.VERSION_NO        = B.VERSION_NO
                   AND D.CUTOFF_YYYYMMDD   = B.CUTOFF_YYYYMMDD
                   AND D.DIVISION_ID       = B.DIVISION_ID
                   AND B.DIVISION_ID       = P_DIVISION_ID);

        INSERT INTO DM_PLN_NET_DEMAND
            (DIVISION_ID, VERSION_NO, CUTOFF_YYYYMMDD, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, CELL_PROD_SITE_ID, DEMAND_TYPE, YYYYMMDD, DEMAND_PRIORITY, QTY, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE, ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5, ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10)
        SELECT DIVISION_ID, VERSION_NO, CUTOFF_YYYYMMDD, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, CELL_PROD_SITE_ID, DEMAND_TYPE, YYYYMMDD
             , MAX(DEMAND_PRIORITY)   AS DEMAND_PRIORITY
             , SUM(QTY)               AS QTY
             , MAX(CREATED_BY)
             , MAX(CREATION_DATE)
             , MAX(LAST_UPDATED_BY)
             , SYSDATE
             , MAX(ATTRIBUTE1), MAX(ATTRIBUTE2), MAX(ATTRIBUTE3), MAX(ATTRIBUTE4), MAX(ATTRIBUTE5)
             , MAX(ATTRIBUTE6), MAX(ATTRIBUTE7), MAX(ATTRIBUTE8), MAX(ATTRIBUTE9), MAX(ATTRIBUTE10)
          FROM GT_DM_NET_TEMP5
         GROUP BY DIVISION_ID, VERSION_NO, CUTOFF_YYYYMMDD, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, CELL_PROD_SITE_ID, DEMAND_TYPE, YYYYMMDD;

        /* 트랜잭션 COMMIT */
        COMMIT;

    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            V_LOG_TYPE    := 'ERROR';
            V_LOG_MESSAGE := SUBSTR(SQLERRM, 1, 1000);
            V_DESCRIPTION := 'ERROR_LINE : ' || DBMS_UTILITY.FORMAT_ERROR_BACKTRACE;
            D_EVENT_DATE  := SYSDATE;
            PR_SCM_SYS_LOG_BATCH(V_PROGRAM_NAME, V_LOG_TYPE, N_LOG_COUNT, V_LOG_MESSAGE, V_DESCRIPTION, D_EVENT_DATE);
    END;

    /* 종료 LOG */
    V_LOG_TYPE    := 'END';
    V_LOG_MESSAGE := '########## END of procedure ##########';
    V_DESCRIPTION := '@p_division_id : ' || P_DIVISION_ID || ' / ' || '전주CUTOFF VERSION : ' || NVL(V_INPUT_VERSION1, 'NULL')
                     || ' / ' || '당주CUTOFF VERSION : ' || NVL(V_INPUT_VERSION2, 'NULL') || ' / ' || '@MAX_PLAN_ID : ' || NVL(V_MAX_PLAN_ID, 'NULL')
                     || ' / ' || '@CF_count : ' || TO_CHAR(V_CF_COUNT) || ' / ' || '@UF_count : ' || TO_CHAR(V_UF_COUNT)
                     || ' / ' || '@NF_count : ' || TO_CHAR(V_NF_COUNT) || ' / ' || '@ESS_count : ' || TO_CHAR(V_ESS_COUNT);
    D_EVENT_DATE  := SYSDATE;
    PR_SCM_SYS_LOG_BATCH(V_PROGRAM_NAME, V_LOG_TYPE, N_LOG_COUNT, V_LOG_MESSAGE, V_DESCRIPTION, D_EVENT_DATE);
END PR_DM_PLN_MKT_FCST_TO_NET_DEMAND;
