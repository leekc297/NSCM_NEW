 * 2018.12.10 	KHSONG 		ESS인경우 DM_MST_SHIPMENT_PRIORITY.PRIORITY 값을 저장, DEMAND_PRIORITY 컬럼값에 고객 Priority(2자리) 추가
 * 2018.12.11 	KHSONG 		ESS 출하기준으로 DEMAND SEQ 설정
 * 2019.08.09 	KHSONG 		[CSR ID:4059971] VMI-In Request 로직 변경
 * 2019.08.30 	KHSONG 		[CSR ID:4074696] Demand 우선순위 개선의 건 (1차수정) ESS SORT 기준  [ 일련번호(4자리)+고객Priority(2자리)+demand type(1자리)] → 총 7자리
 * 2019.09.20 	KHSONG 		[CSR ID:4074696] Demand 우선순위 개선의 건 (2차수정) ESS SORT 기준  [ 고정값(1자리) + 고객Priority(2자리)+일련번호(4자리)+demand type(1자리) ] → 총 8자리
 * 2019.09.25 	KHSONG 		[CSR ID:4077124] ESS Shipment Priority 화면 변경요청 (월단위 → 주단위)
 * 2020.09.09   P.C.I		[C20200909-000203] LOG 표준화 적용
 * 2021.09.29	hwi1993		[PJ20209643] W/S 프로세스 - AS_In_Plan, Req 추가
 * 2021.11.04	HWI1993		[PJ20209643] W/S 프로세스 - AS 최종고객향 제거로직 추가
 * 2022.03.29   kdw2819     [C20220224-000448] ESS 사업부 VMI 기능 자동차사업부 확산 전개 요청 (VMI_IN_PLAN 으로 RTF 생성)
  *2022.04.05   hwi1993     GM JV 작업
 * 2023.01.17   chano0612	[E20230112-000310] GSCM 자동차사업부 시스템 상 MKT FCST 입력을 위한 기능변경 건 - 선박BIZ건
 * 2023.02.14	HEESUN		[E20230207-000127] SALES PLAN CUT OFF 시 데이터 중복으로 인한 CUT OFF 가 되지 않았던 케이스 해소
 * 2025.02.05	KANG.H.J	[PJ2025-50017] 소형 매출계획 동기화 개선
 * 2025.04.28	KANG.H.J	[PJ2025-50017] 소형 매출계획 동기화 개선 - NUMERIC(20,10)의 OVERFLOW 발생 - MEASURE 조건절 추가
 * 2025.05.07	KANG.H.J	[PJ2025-50188] 기준수요 (SCM_FCST 기반 NET_DEMAND 생성)
 * 2025.05.14	KANG.H.J	[PJ2025-50188] DM_PLN_NET_DEMAND 생성 기준을 가장 최근의 버젼을 기반으로 생성하도록 정의
 * 2025.05.29	KANG.H.J	[PJ2025-50188] #T_MKT_FCST$ 임시테이블 시작/끝 부분에 DROP 기능 추가
 * 2026.07.06   ZIONEX          [PJ202650304] NextSCM Migration
 * 2026.09.18   AJS             40·82 PLANT_SITE_ID 채움값 '-' 통일, ATTRIBUTE10 빈값 판정 MSSQL 과 동일 범위, #ROW_TABLE 커서 정렬(IDX_ROW_TABLE 키), PLANT_SITE_ID 첫 행 판정
 *===================================================================================================================================================*/
AS
    /* LOG */
    V_PROGRAM_NAME        VARCHAR2(150 CHAR) := 'PR_DM_PLN_MKT_FCST_TO_NET_DEMAND';
    V_LOG_TYPE            VARCHAR2(30 CHAR);
    N_LOG_COUNT           NUMBER := 0;
    V_LOG_MESSAGE         VARCHAR2(1000 CHAR);
    V_DESCRIPTION         VARCHAR2(500 CHAR);
    D_EVENT_DATE          DATE;

    /* 계산용 */
    V_MATCH_ROWS          NUMBER := 0;
    V_MAX_ROWS            NUMBER := 0;
    V_DEMAND_SORT_ROWS    NUMBER := 0;
    V_DEMAND_SORT_MAX     NUMBER := 0;
    V_DEMAND_MIN_YYYYMMDD VARCHAR2(8 CHAR);
    V_PRIORITY_COUNT      NUMBER := 0;
    V_ESS_COUNT           NUMBER := 1001;
    V_CF_COUNT            NUMBER := 1001;
    V_UF_COUNT            NUMBER := 2001;
    V_NF_COUNT            NUMBER := 3001;
    V_INST_COUNT          NUMBER := 0;
    V_DEMAND_TYPE         VARCHAR2(50 CHAR);
    V_DEMAND_TYPE2        VARCHAR2(50 CHAR);
    V_DEMAND_FLAG         VARCHAR2(50 CHAR) := 'CF';
    V_FL_PLANT_SITE_ID    VARCHAR2(120 CHAR);
    V_FL_DEMAND_TYPE      VARCHAR2(50 CHAR);
    V_FL_YYYYMMDD         VARCHAR2(8 CHAR);

    V_CALC_CF             NUMBER(20,10);
    V_CALC_UF             NUMBER(20,10);
    V_CALC_NF             NUMBER(20,10);
    V_INSERT_CALC         NUMBER(20,10);
    V_INSERT_CALC2        NUMBER(20,10);

    V_MAX_PLAN_ID         VARCHAR2(120 CHAR);
    V_YYYYMMDD            VARCHAR2(8 CHAR);

    /* [PJ2025-50188] 기준수요 */
    V_INPUT_VERSION1          VARCHAR2(50 CHAR);
    V_CUTOFF_VERSION_TYPE1    VARCHAR2(10 CHAR);
    V_MEASURE_FCST_TYPE1      VARCHAR2(10 CHAR);
    V_INPUT_VERSION2          VARCHAR2(50 CHAR);
    V_CUTOFF_VERSION_TYPE2    VARCHAR2(10 CHAR);
    V_MEASURE_FCST_TYPE2      VARCHAR2(10 CHAR);


    N_DIVISION_ID         VARCHAR2(120 CHAR);
    N_VERSION_NO          VARCHAR2(50 CHAR);
    N_CUTOFF_YYYYMMDD     VARCHAR2(8 CHAR);
    N_PROJECT_CODE        VARCHAR2(200 CHAR);
    N_SCM_SITE_ID         VARCHAR2(120 CHAR);
    N_ITEM_ID             VARCHAR2(200 CHAR);
    N_DOM_EXP             VARCHAR2(12 CHAR);
    N_FCST_TYPE           VARCHAR2(80 CHAR);
    N_INCOTERMS           VARCHAR2(40 CHAR);
    N_PLANT_SITE_ID       VARCHAR2(120 CHAR);
    N_CELL_PROD_SITE_ID   VARCHAR2(600 CHAR);
    N_YYYYMMDD            VARCHAR2(10 CHAR);
    N_QTY                 NUMBER(20,10);

    /* DEMAND_PRIORITY 산출 보조 */
    V_X4_PAD              VARCHAR2(150 CHAR);
    V_DEMAND_PRIORITY     VARCHAR2(40 CHAR);

    /* #ROW_TABLE 커서 (CURSOR2) */
    CURSOR CUR_ROW IS
        SELECT DIVISION_ID, VERSION_NO, CUTOFF_YYYYMMDD, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP
             , FCST_TYPE, INCOTERMS, PLANT_SITE_ID, CELL_PROD_SITE_ID, YYYYMMDD, QTY
          -- 2026.09.18 AJS #ROW_TABLE 커서 정렬 추가 - MSSQL CLUSTERED INDEX IDX_ROW_TABLE 키 순서 (START)
          --FROM GT_DM_NET_ROW_TABLE;
          FROM GT_DM_NET_ROW_TABLE
          ORDER BY DIVISION_ID, VERSION_NO, CUTOFF_YYYYMMDD, PROJECT_CODE, SCM_SITE_ID, ITEM_ID
                 , DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, CELL_PROD_SITE_ID, YYYYMMDD;
          -- 2026.09.18 AJS #ROW_TABLE 커서 정렬 추가 (END)
BEGIN
    /* 수정가능 변수값 */
    V_YYYYMMDD := TO_CHAR(FN_NEXT_DAY(SYSDATE, 'MON') - 7 * 1, 'YYYYMMDD');

    /* 시작 LOG (START) */
    V_LOG_TYPE    := 'START';
    V_LOG_MESSAGE := '########## Start of procedure ##########';
    V_DESCRIPTION := '@p_division_id : ' || P_DIVISION_ID || ' / ' || '전주CUTOFF VERSION : ' || NVL(V_INPUT_VERSION1, 'NULL')
                     || ' / ' || '당주CUTOFF VERSION : ' || NVL(V_INPUT_VERSION2, 'NULL') || ' / ' || '@MAX_PLAN_ID : ' || NVL(V_MAX_PLAN_ID, 'NULL');
    D_EVENT_DATE  := SYSDATE;
    PR_SCM_SYS_LOG_BATCH(V_PROGRAM_NAME, V_LOG_TYPE, N_LOG_COUNT, V_LOG_MESSAGE, V_DESCRIPTION, D_EVENT_DATE);
    V_LOG_MESSAGE := NULL;

    /* 전주/당주 CUTOFF VERSION, PLAN_ID Validation */
    /* [PJ2025-50188] 전주 기준 VERSION_NO / CUTOFF_TYPE / MEASURE */
    BEGIN
        SELECT VERSION_NO, VERSION_TYPE
             , CASE WHEN VERSION_TYPE = 'MF_W' THEN 'MKT_FCST' WHEN VERSION_TYPE = 'SF_W' THEN 'SCM_FCST' ELSE '' END
          INTO V_INPUT_VERSION1, V_CUTOFF_VERSION_TYPE1, V_MEASURE_FCST_TYPE1
          FROM (
                SELECT VERSION_NO, VERSION_TYPE
                     , RANK() OVER (ORDER BY YYYYMMDD DESC, VER_CRE_SEQ DESC, VERSION_TYPE DESC) AS RN
                  FROM DM_MST_VERSION
                 WHERE DIVISION_ID = P_DIVISION_ID
                   AND VERSION_TYPE IN ('MF_W', 'SF_W')
                   AND YYYYMMDD >= TO_CHAR(FN_NEXT_DAY(SYSDATE, 'MON') - 7 * 2, 'YYYYMMDD')   /* 전주 월요일부터 */
                   AND YYYYMMDD <= TO_CHAR(FN_NEXT_DAY(SYSDATE, 'SUN') - 7 * 1, 'YYYYMMDD')   /* 전주 일요일까지 */
               )
         WHERE RN = 1 AND ROWNUM = 1;
    EXCEPTION WHEN NO_DATA_FOUND THEN NULL;
    END;

    /* [PJ2025-50188] 당주 기준 VERSION_NO / CUTOFF_TYPE / MEASURE */
    BEGIN
        SELECT VERSION_NO, VERSION_TYPE
             , CASE WHEN VERSION_TYPE = 'MF_W' THEN 'MKT_FCST' WHEN VERSION_TYPE = 'SF_W' THEN 'SCM_FCST' ELSE '' END
          INTO V_INPUT_VERSION2, V_CUTOFF_VERSION_TYPE2, V_MEASURE_FCST_TYPE2
          FROM (
                SELECT VERSION_NO, VERSION_TYPE
                     , RANK() OVER (ORDER BY YYYYMMDD DESC, VER_CRE_SEQ DESC, VERSION_TYPE DESC) AS RN
                  FROM DM_MST_VERSION
                 WHERE DIVISION_ID = P_DIVISION_ID
                   AND VERSION_TYPE IN ('MF_W', 'SF_W')
                   AND YYYYMMDD >= TO_CHAR(FN_NEXT_DAY(SYSDATE, 'MON') - 7 * 1, 'YYYYMMDD')   /* 당주 월요일부터 */
                   AND YYYYMMDD <= TO_CHAR(FN_NEXT_DAY(SYSDATE, 'SUN'), 'YYYYMMDD')   /* 당주 일요일까지 */
               )
         WHERE RN = 1 AND ROWNUM = 1;
    EXCEPTION WHEN NO_DATA_FOUND THEN NULL;
    END;

    SELECT MAX(PLAN_ID) INTO V_MAX_PLAN_ID
      FROM SCP_PLN_RTF_ALLOCATION_V
     WHERE DIVISION_ID = P_DIVISION_ID;

    /* 당주 CUTOFF VERSION 값이 없으면 수행하지 않음 (GOTO ERR_RTN) */
    IF V_INPUT_VERSION2 IS NULL THEN
        V_LOG_TYPE    := 'INVALID';
        V_DESCRIPTION := '@p_division_id : ' || P_DIVISION_ID || ' / ' || '전주CUTOFF VERSION : ' || NVL(V_INPUT_VERSION1, 'NULL')
                         || ' / ' || '당주CUTOFF VERSION : ' || NVL(V_INPUT_VERSION2, 'NULL') || ' / ' || '@MAX_PLAN_ID : ' || NVL(V_MAX_PLAN_ID, 'NULL');
        ROLLBACK;
        V_LOG_MESSAGE := '########## END of procedure ##########';
        D_EVENT_DATE  := SYSDATE;
        PR_SCM_SYS_LOG_BATCH(V_PROGRAM_NAME, V_LOG_TYPE, N_LOG_COUNT, V_LOG_MESSAGE, V_DESCRIPTION, D_EVENT_DATE);
        RETURN;
    END IF;


    BEGIN

        DELETE FROM GT_DM_NET_RTF_ALLOC;
        DELETE FROM GT_DM_NET_MKT_FCST;
        DELETE FROM GT_DM_NET_ROW_TABLE;
        DELETE FROM GT_DM_NET_TEMP1;
        DELETE FROM GT_DM_NET_TEMP2;
        DELETE FROM GT_DM_NET_TEMP3;
        DELETE FROM GT_DM_NET_TEMP4;
        DELETE FROM GT_DM_NET_TEMP5;

        /* #TMP_SCP_PLN_RTF_ALLOCATION */
        INSERT INTO GT_DM_NET_RTF_ALLOC
            (DIVISION_ID, PROJECT_CODE, SALES_SITE_ID, ITEM_ID, INCOTERMS, PLANT_SITE_ID, CELL_PROD_SITE_ID, DOM_EXP, FCST_TYPE, DUE_DATE, ALLOCATION_QTY, PLAN_ID)
        SELECT DIVISION_ID, PROJECT_CODE, SALES_SITE_ID, ITEM_ID, INCOTERMS, PLANT_SITE_ID, CELL_PROD_SITE_ID, DOM_EXP, FCST_TYPE, DUE_DATE, ALLOCATION_QTY, PLAN_ID
          FROM SCP_PLN_RTF_ALLOCATION_V A
         WHERE A.DIVISION_ID = P_DIVISION_ID
           AND A.PLAN_ID     = V_MAX_PLAN_ID;

        /* 각 사업부별 공통정보 #T_MKT_FCST$ 적재 */
        IF (P_DIVISION_ID = '40') THEN
            INSERT INTO GT_DM_NET_MKT_FCST
                (DIVISION_ID, VERSION_NO, CUTOFF_TYPE, CUTOFF_YYYYMMDD, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, CELL_PROD_SITE_ID, MEASURE, YYYYMMDD, QTY, ATTRIBUTE10)
            SELECT DIVISION_ID, VERSION_NO, CUTOFF_TYPE, CUTOFF_YYYYMMDD
                 , END_CUSTOMER  AS PROJECT_CODE
                 , SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, CELL_PROD_SITE_ID, MEASURE, YYYYMMDD, QTY, ATTRIBUTE10
              FROM DM_PLN_CFM_MKT_DEMAND_PLAN_C
             WHERE DIVISION_ID = P_DIVISION_ID
               AND VERSION_NO  IN (V_INPUT_VERSION1, V_INPUT_VERSION2)
               AND QTY         > 0
               AND YYYYMMDD    >= V_YYYYMMDD
               AND MEASURE IN ('MKT_FCST', 'SCM_FCST', 'VMI_In_Req', 'AS_In_Req');
        ELSE
            INSERT INTO GT_DM_NET_MKT_FCST
                (DIVISION_ID, VERSION_NO, CUTOFF_TYPE, CUTOFF_YYYYMMDD, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, CELL_PROD_SITE_ID, MEASURE, YYYYMMDD, QTY, ATTRIBUTE10)
            SELECT DIVISION_ID, VERSION_NO, CUTOFF_TYPE, CUTOFF_YYYYMMDD, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID
                 , '-'  AS CELL_PROD_SITE_ID
                 , MEASURE, YYYYMMDD, QTY, ATTRIBUTE10
              FROM DM_PLN_MKT_FCST_C
             WHERE DIVISION_ID = P_DIVISION_ID
               AND VERSION_NO  IN (V_INPUT_VERSION1, V_INPUT_VERSION2)
               AND QTY         > 0
               AND YYYYMMDD    >= V_YYYYMMDD
               AND MEASURE IN ('MKT_FCST', 'SCM_FCST', 'VMI_In_Req', 'AS_In_Req');
        END IF;

        /* 전주 마지막 WEEKLY CUTOFF -> #TEMP1 */
        INSERT INTO GT_DM_NET_TEMP1
            (DIVISION_ID, VERSION_NO, CUTOFF_TYPE, CUTOFF_YYYYMMDD, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, PLANT_SITE_ID, CELL_PROD_SITE_ID, YYYYMM, BATCH_RESULT, QTY, RTF, MKT_FCST, CF, UF, NF)
        WITH ALL_DATA AS (
            SELECT A.DIVISION_ID, A.VERSION_NO, A.CUTOFF_TYPE, A.CUTOFF_YYYYMMDD, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.DOM_EXP, A.FCST_TYPE, A.INCOTERMS
                 -- 2026.09.18 AJS 40·82 PLANT_SITE_ID 이관 채움값 '-' 로 통일 (START)
--                 , CASE WHEN A.DIVISION_ID IN ('82', '40') THEN ' ' ELSE A.PLANT_SITE_ID END   AS PLANT_SITE_ID
                 , CASE WHEN A.DIVISION_ID IN ('82', '40') THEN '-' ELSE A.PLANT_SITE_ID END   AS PLANT_SITE_ID
                 -- 2026.09.18 AJS 40·82 PLANT_SITE_ID 이관 채움값 '-' 로 통일 (END)
                 , A.CELL_PROD_SITE_ID
                 , A.MEASURE
                 , SUBSTR(A.YYYYMMDD, 1, 6)   AS YYYYMM
                 , 'ING'                      AS BATCH_RESULT
                 , SUM(A.QTY)                 AS QTY
                 , 0 AS RTF, 0 AS MKT_FCST, 0 AS CF, 0 AS UF, 0 AS NF
              FROM GT_DM_NET_MKT_FCST       A
                 , DM_MST_ITEM_SINGLE_V     ITEM
                 , SCM_MST_SITE             ST
                 , SCM_MST_SITE_ITEM        STM
             WHERE 1 = 1
               AND A.DIVISION_ID  = ITEM.DIVISION_ID
               AND A.DIVISION_ID  = STM.DIVISION_ID
               AND A.PROJECT_CODE = STM.PROJECT_CODE
               AND A.SCM_SITE_ID  = STM.SCM_SITE_ID
               AND A.ITEM_ID      = STM.ITEM_ID
               AND STM.VALID_YN   = 'Y'
               AND A.ITEM_ID      = ITEM.ITEM_ID
               AND ITEM.ACTIVE_FLAG = 'Y'
               AND ST.VALID_YN    = 'Y'
               AND A.DIVISION_ID  = ST.DIVISION_ID
               AND A.SCM_SITE_ID  = ST.SCM_SITE_ID
               AND A.MEASURE      = CASE WHEN A.DIVISION_ID IN ('40', '82') AND ST.VMI_YN = 'Y' THEN 'VMI_In_Req'
                                         WHEN ST.OPERATION_GROUP = 'W' THEN 'AS_In_Req'
                                         ELSE V_MEASURE_FCST_TYPE1 END
               AND A.DIVISION_ID  = P_DIVISION_ID
               AND A.VERSION_NO   = V_INPUT_VERSION1
               AND A.QTY          > 0
               AND A.YYYYMMDD     >= V_YYYYMMDD
               -- 2026.09.18 AJS ATTRIBUTE10 빈값 판정 - MSSQL ISNULL(A.ATTRIBUTE10,'') = '' 와 같은 범위 (START)
--               AND A.ATTRIBUTE10  IS NULL
               AND (A.ATTRIBUTE10 IS NULL OR TRIM(A.ATTRIBUTE10) IS NULL OR A.ATTRIBUTE10 = '-')
               -- 2026.09.18 AJS ATTRIBUTE10 빈값 판정 (END)
               AND A.MEASURE IN ('MKT_FCST', 'SCM_FCST', 'VMI_In_Req', 'AS_In_Req')
             GROUP BY A.DIVISION_ID, A.VERSION_NO, A.CUTOFF_TYPE, A.CUTOFF_YYYYMMDD, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.DOM_EXP
                    , A.FCST_TYPE, A.INCOTERMS
                    -- 2026.09.18 AJS 40·82 PLANT_SITE_ID 이관 채움값 '-' 로 통일 (START)
--                    , CASE WHEN A.DIVISION_ID IN ('82', '40') THEN ' ' ELSE A.PLANT_SITE_ID END
                    , CASE WHEN A.DIVISION_ID IN ('82', '40') THEN '-' ELSE A.PLANT_SITE_ID END
                    -- 2026.09.18 AJS 40·82 PLANT_SITE_ID 이관 채움값 '-' 로 통일 (END)
                    , A.CELL_PROD_SITE_ID
                    , A.MEASURE, SUBSTR(A.YYYYMMDD, 1, 6)
            UNION ALL
            SELECT A.DIVISION_ID
                 , V_INPUT_VERSION1                        AS VERSION_NO
                 , V_CUTOFF_VERSION_TYPE1                  AS CUTOFF_TYPE
                 , SUBSTR(V_INPUT_VERSION1, 6, 8)          AS CUTOFF_YYYYMMDD
                 , A.PROJECT_CODE, A.SALES_SITE_ID, A.ITEM_ID, A.DOM_EXP, A.FCST_TYPE, A.INCOTERMS
                 -- 2026.09.18 AJS 40·82 PLANT_SITE_ID 이관 채움값 '-' 로 통일 (START)
--                 , CASE WHEN A.DIVISION_ID IN ('82', '40') THEN ' ' ELSE A.PLANT_SITE_ID END   AS PLANT_SITE_ID
                 , CASE WHEN A.DIVISION_ID IN ('82', '40') THEN '-' ELSE A.PLANT_SITE_ID END   AS PLANT_SITE_ID
                 -- 2026.09.18 AJS 40·82 PLANT_SITE_ID 이관 채움값 '-' 로 통일 (END)
                 , A.CELL_PROD_SITE_ID
                 , CASE WHEN A.DIVISION_ID IN ('40', '82') AND ST.VMI_YN = 'Y' THEN 'VMI_IN_PLAN'
                        WHEN ST.OPERATION_GROUP = 'W' THEN 'AS_IN_PLAN'
                        ELSE 'RTF' END                     AS MEASURE
                 , SUBSTR(A.DUE_DATE, 1, 6)                AS YYYYMM
                 , 'ING'                                   AS BATCH_RESULT
                 , SUM(A.ALLOCATION_QTY)                   AS QTY
                 , 0 AS RTF, 0 AS MKT_FCST, 0 AS CF, 0 AS UF, 0 AS NF
              FROM GT_DM_NET_RTF_ALLOC      A
                 , DM_MST_ITEM_SINGLE_V     ITEM
                 , SCM_MST_SITE             ST
                 , SCM_MST_SITE_ITEM        STM
             WHERE 1 = 1
               AND A.DIVISION_ID   = STM.DIVISION_ID
               AND A.PROJECT_CODE  = STM.PROJECT_CODE
