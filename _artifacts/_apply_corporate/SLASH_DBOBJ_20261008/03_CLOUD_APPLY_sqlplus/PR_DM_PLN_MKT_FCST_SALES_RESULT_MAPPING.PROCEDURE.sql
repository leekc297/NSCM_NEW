    V_LOG_MESSAGE             VARCHAR2(1000 CHAR);
    V_DESCRIPTION             VARCHAR2(500 CHAR);
    D_EVENT_DATE              DATE;

    /* 날짜변수 (20180912 KHSONG 날짜조건 변수로 설정) */
    V_START_YYYYMM            VARCHAR2(6 CHAR);
    V_END_YYYYMM              VARCHAR2(6 CHAR);
    V_START_YYYYMMDD          VARCHAR2(8 CHAR);
    V_START_YYYYMMDD_EXCHANGE VARCHAR2(8 CHAR);   /* [PJ2025-50188] 환율 AMT 기준일 : 당월 1일 */
    V_END_YYYYMMDD            VARCHAR2(8 CHAR);

    N_UPDATE_CNT              INTEGER := 0;
    N_ROWCNT                  INTEGER := 0;
    N_CHK_CNT                 INTEGER := 0;
    V_VERSION                 VARCHAR2(20 CHAR);
    V_DEDUCTED_DIVISION_ID    VARCHAR2(30 CHAR);
    V_STATES                  VARCHAR2(50 CHAR);
BEGIN
    /* 날짜변수설정 : 매월 1일인 경우 전전월(-2)부터, 그 외 전월(-1)부터 대상 */
    V_START_YYYYMM            := TO_CHAR(ADD_MONTHS(SYSDATE, CASE WHEN TO_CHAR(SYSDATE,'DD') = '01' THEN -2 ELSE -1 END), 'YYYYMM');
    V_START_YYYYMMDD          := SUBSTR(TO_CHAR(ADD_MONTHS(SYSDATE, CASE WHEN TO_CHAR(SYSDATE,'DD') = '01' THEN -2 ELSE -1 END), 'YYYYMM'), 1, 6) || '01';
    V_START_YYYYMMDD_EXCHANGE := TO_CHAR(SYSDATE, 'YYYYMM') || '01';   /* [PJ2025-50188] 당월 1일 */
    V_END_YYYYMM              := TO_CHAR(SYSDATE, 'YYYYMM');
    V_END_YYYYMMDD            := TO_CHAR(SYSDATE, 'YYYYMMDD');

    /* 시작 LOG START */
    V_LOG_TYPE    := 'START';
    V_LOG_MESSAGE := '########## Start of procedure ##########';
    V_DESCRIPTION := '';
    D_EVENT_DATE  := SYSDATE;
