    /* [E20240806-000678] 소형사업부 매출실적 스케줄 - 월요일 13시. 하드코딩 대신 룩업(RESULT_MAPPING_SCHEDULE)에서 현재시점 작동 DIVISION 추출 */
    /* [E20250404-001534] RESULT MODE 추가 (SEGMENT4 = 'RESULT'). #TEMP_DAYINFO(당일 요일) 은 SCM_SYS_CALENDAR_M 1행 조회로 인라인화 */
    INSERT INTO GT_MFSRM_I_DIVISION (DIVISION_ID)
    SELECT SEGMENT1 AS DIVISION_ID
      FROM SCM_ADM_LOOKUP_MASTER_DETAIL
     WHERE LOOKUP_TYPE = 'RESULT_MAPPING_SCHEDULE'
       AND (SEGMENT2 = 'ALL' OR SEGMENT2 IN (SELECT DAYOFWEEK FROM SCM_SYS_CALENDAR_M WHERE BASIS_YYYYMMDD = TO_CHAR(SYSDATE,'YYYYMMDD')))
       AND (CASE WHEN ATTRIBUTE1 IS NOT NULL
                  AND ATTRIBUTE1 IN (SELECT DAYOFWEEK FROM SCM_SYS_CALENDAR_M WHERE BASIS_YYYYMMDD = TO_CHAR(SYSDATE,'YYYYMMDD'))
                 THEN SEGMENT1 ELSE '1' END) = '1'
       AND SUBSTR(SEGMENT3,1,2) BETWEEN TO_CHAR(SYSDATE - 1/24,'HH24') AND TO_CHAR(SYSDATE,'HH24')
       AND VALID_YN = 'Y'
       AND SEGMENT4 = 'RESULT'
     GROUP BY SEGMENT1;
    N_UPDATE_CNT := SQL%ROWCOUNT;

    /* Log에 작업하는 Division_id 표기 (TAB_PIVOT_STRING + FN_GET_PIVOT_STRING -> LISTAGG) */
    SELECT LISTAGG(DIVISION_ID, ',') WITHIN GROUP (ORDER BY DIVISION_ID)
      INTO V_DESCRIPTION
      FROM GT_MFSRM_I_DIVISION;

    V_LOG_TYPE    := 'APPEND';
    V_LOG_MESSAGE := 'TARGET DIVISION';
    D_EVENT_DATE  := SYSDATE;
    N_LOG_COUNT   := N_UPDATE_CNT;
    PR_SCM_SYS_LOG_BATCH(V_PROGRAM_NAME, V_LOG_TYPE, N_LOG_COUNT, V_LOG_MESSAGE, V_DESCRIPTION, D_EVENT_DATE);


