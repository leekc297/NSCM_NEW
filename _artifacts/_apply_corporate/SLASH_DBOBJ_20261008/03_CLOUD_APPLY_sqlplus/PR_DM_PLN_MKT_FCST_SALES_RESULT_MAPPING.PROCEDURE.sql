        INSERT INTO GT_MFSRM_TEMP_DM_RESULT
        ( DIVISION_ID, COMPANY_ID, PROJECT_CODE, SALES_SITE_ID, PLANT_SITE_ID, ITEM_ID, ORIGIN_ITEM_ID
        , DOM_EXP, INCOTERMS, MEASURE, CURRENCY, YYYYMMDD, FCST_TYPE, QTY, SOLDTO_CODE, SHIPTO_CODE, VALID_YN
        , CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE, ATTRIBUTE1, INTERNAL_TYPE
        , ATTRIBUTE3, ATTRIBUTE4, SO_NO, SO_QTY, FROM_COMPANY_ID, PLANT_ID )
        SELECT  A.DIVISION_ID, A.COMPANY_ID, A.PROJECT_CODE, A.SALES_SITE_ID, A.PLANT_SITE_ID, A.ITEM_ID, A.ORIGIN_ITEM_ID
              , A.DOM_EXP, A.INCOTERMS, B.MEASURE, A.CURRENCY, A.YYYYMMDD, A.FCST_TYPE
              , CASE WHEN B.MEASURE = 'SALES_RESULT_AMOUNT'     THEN SUM(A.SALES_AMOUNT_FOR)
                     WHEN B.MEASURE = 'SALES_RESULT_AMOUNT_KRW' THEN SUM(A.SALES_AMOUNT_SUM)
                     WHEN B.MEASURE = 'SALES_RESULT'            THEN SUM(A.SALES_QTY)
                END AS QTY
              , A.SOLDTO_CODE, A.SHIPTO_CODE, A.VALID_YN
              , MAX(A.CREATED_BY), MAX(A.CREATION_DATE), MAX(A.LAST_UPDATED_BY), MAX(A.LAST_UPDATE_DATE), MAX(A.ATTRIBUTE1)
              , A.INTERNAL_TYPE
              , SUM(CASE WHEN VALIDATE_CONVERSION(A.ATTRIBUTE3 AS NUMBER) = 1 THEN TO_NUMBER(A.ATTRIBUTE3) ELSE 0 END) AS ATTRIBUTE3
              , MAX(A.ATTRIBUTE4) AS ATTRIBUTE4
              , A.SO_NO, A.SO_QTY, A.FROM_COMPANY_ID, A.PLANT_ID
        FROM (
                /* 81% 사업부 ([E20251029-000963] 40 외 CELL_PROD_SITE_ID 는 '-') */
                SELECT  DIVISION_ID, COMPANY_ID, PROJECT_CODE, SALES_SITE_ID, PLANT_SITE_ID, ITEM_ID, ORIGIN_ITEM_ID
                      , FN_SCM_SYS_NVL(FN_GET_LOOKUP_CODE_DESC('DISTRIBUTION_CHANNEL', DISTRIBUTION_CHANNEL), 'E') AS DOM_EXP
                      , INCOTERMS, SALES_AMOUNT_FOR, SALES_AMOUNT_SUM, SALES_QTY, CURRENCY
                      , SALES_POSTING_DATE AS YYYYMMDD, FCST_TYPE
                      , CUSTOMER_CODE AS SOLDTO_CODE, SHIPTO_CODE, 'Y' AS VALID_YN
                      , 'scm_batch' AS CREATED_BY, SYSDATE AS CREATION_DATE, 'scm_batch' AS LAST_UPDATED_BY, SYSDATE AS LAST_UPDATE_DATE
                      , ATTRIBUTE1, INTERNAL_TYPE, ATTRIBUTE3, ATTRIBUTE4, SO_NO, SO_QTY
--                      , '-' AS FROM_COMPANY_ID, PLANT_ID
                      , '-' AS FROM_COMPANY_ID, '-' AS PLANT_ID          -- 2026.09.11 AJS
                  FROM DM_DNM_SALES_RESULT_IF
                 WHERE 1 = 1
                   AND DIVISION_ID LIKE '81%'
                   AND DIVISION_ID IN (SELECT DIVISION_ID FROM GT_MFSRM_I_DIVISION)
                   AND SALES_YYYYMM BETWEEN V_START_YYYYMM AND V_END_YYYYMM
                   AND ( CUSTOMER_CODE IS NOT NULL
                         OR (CUSTOMER_CODE IS NULL AND PROFIT_CENTER_ID = 'A40012' AND PARTNER_PROFIT_CENTER_ID = 'A50101') )
                UNION ALL

                SELECT  DIVISION_ID, COMPANY_ID, PROJECT_CODE, SALES_SITE_ID, PLANT_SITE_ID, ITEM_ID, ORIGIN_ITEM_ID
                      , FN_SCM_SYS_NVL(FN_GET_LOOKUP_CODE_DESC('DISTRIBUTION_CHANNEL', DISTRIBUTION_CHANNEL), 'E') AS DOM_EXP
                      , INCOTERMS, SALES_AMOUNT_FOR, SALES_AMOUNT_SUM, SALES_QTY, CURRENCY
                      , SALES_POSTING_DATE AS YYYYMMDD, FCST_TYPE
                      , CUSTOMER_CODE AS SOLDTO_CODE, SHIPTO_CODE, 'Y' AS VALID_YN
                      , 'scm_batch' AS CREATED_BY, SYSDATE AS CREATION_DATE, 'scm_batch' AS LAST_UPDATED_BY, SYSDATE AS LAST_UPDATE_DATE
                      , ATTRIBUTE1, INTERNAL_TYPE, ATTRIBUTE3, ATTRIBUTE4, SO_NO, SO_QTY
--                      , '-' AS FROM_COMPANY_ID, PLANT_ID
                      , '-' AS FROM_COMPANY_ID, '-' AS PLANT_ID          -- 2026.09.11 AJS
                  FROM DM_DNM_SALES_RESULT_IF
                 WHERE 1 = 1
                   AND DIVISION_ID = '82'
                   AND DIVISION_ID IN (SELECT DIVISION_ID FROM GT_MFSRM_I_DIVISION)
                   AND SALES_YYYYMM BETWEEN V_START_YYYYMM AND V_END_YYYYMM
                UNION ALL
                /* 40 사업부 (소형 예외 매핑 : 전력저장전지 공통/오창 전력저장 전지 -> Peopleworks, ETC 처리) */
                SELECT  X.DIVISION_ID, X.COMPANY_ID
                      , CASE WHEN DISTRIBUTION_CHANNEL = '70' AND PARTNER_PROFIT_CENTER_NAME IN (u'\c804\b825\c800\c7a5\c804\c9c0 \acf5\d1b5', u'\c624\cc3d \c804\b825\c800\c7a5 \c804\c9c0') THEN 'Peopleworks'
                             WHEN DISTRIBUTION_CHANNEL = '70' AND PARTNER_PROFIT_CENTER_NAME NOT IN (u'\c804\b825\c800\c7a5\c804\c9c0 \acf5\d1b5', u'\c624\cc3d \c804\b825\c800\c7a5 \c804\c9c0') THEN ' '
                             ELSE PROJECT_CODE END AS PROJECT_CODE
                      , CASE WHEN CUSTOMER_CODE = 'G450' THEN 'N'
                             WHEN DISTRIBUTION_CHANNEL = '70' AND PARTNER_PROFIT_CENTER_NAME IN (u'\c804\b825\c800\c7a5\c804\c9c0 \acf5\d1b5', u'\c624\cc3d \c804\b825\c800\c7a5 \c804\c9c0') THEN 'Peopleworks_KR_KUM'
                             WHEN DISTRIBUTION_CHANNEL = '70' AND PARTNER_PROFIT_CENTER_NAME NOT IN (u'\c804\b825\c800\c7a5\c804\c9c0 \acf5\d1b5', u'\c624\cc3d \c804\b825\c800\c7a5 \c804\c9c0') THEN ' '
                             ELSE SALES_SITE_ID END AS SALES_SITE_ID
                      , PLANT_SITE_ID
                      , CASE WHEN ( DISTRIBUTION_CHANNEL = '70' AND PARTNER_PROFIT_CENTER_NAME NOT IN (u'\c804\b825\c800\c7a5\c804\c9c0 \acf5\d1b5', u'\c624\cc3d \c804\b825\c800\c7a5 \c804\c9c0') )
                                   OR (COMPANY_ID = 'G180' AND CUSTOMER_CODE IN ('G450','G630'))
                             THEN
                                CASE (SELECT CELL_TYPE FROM DM_MST_ITEM_SINGLE_V V WHERE V.DIVISION_ID = '40' AND V.ITEM_ID = X.ITEM_ID)
                                     WHEN 'POUCH'                 THEN 'ETC_P'
                                     WHEN 'CYLINDRICAL'           THEN 'ETC_C'
                                     WHEN 'PRISMATIC'             THEN 'ETC_R'
                                     WHEN 'POLYMER'               THEN 'ETC_P'
                                     WHEN 'SPIN-TYPE CYLINDRICAL' THEN 'ETC_C'
                                     WHEN 'CCYLINDRICAL'          THEN 'ETC_C'
                                     ELSE 'ETC' END
                             ELSE ITEM_ID END AS ITEM_ID
                      , ORIGIN_ITEM_ID
                      , FN_SCM_SYS_NVL(FN_GET_LOOKUP_CODE_DESC('DISTRIBUTION_CHANNEL', DISTRIBUTION_CHANNEL), 'E') AS DOM_EXP
                      , CASE WHEN DISTRIBUTION_CHANNEL = '70' AND PARTNER_PROFIT_CENTER_NAME IN (u'\c804\b825\c800\c7a5\c804\c9c0 \acf5\d1b5', u'\c624\cc3d \c804\b825\c800\c7a5 \c804\c9c0') THEN 'EXW'
                             ELSE INCOTERMS END AS INCOTERMS
                      , SALES_AMOUNT_FOR, SALES_AMOUNT_SUM
                      , CASE WHEN DISTRIBUTION_CHANNEL = '70' AND PARTNER_PROFIT_CENTER_NAME NOT IN (u'\c804\b825\c800\c7a5\c804\c9c0 \acf5\d1b5', u'\c624\cc3d \c804\b825\c800\c7a5 \c804\c9c0') THEN 0 ELSE SALES_QTY END AS SALES_QTY
                      , CURRENCY, SALES_POSTING_DATE AS YYYYMMDD, FCST_TYPE
                      , CUSTOMER_CODE AS SOLDTO_CODE, SHIPTO_CODE, 'Y' AS VALID_YN
                      , 'scm_batch' AS CREATED_BY, SYSDATE AS CREATION_DATE, 'scm_batch' AS LAST_UPDATED_BY, SYSDATE AS LAST_UPDATE_DATE
                      , ATTRIBUTE1, INTERNAL_TYPE, ATTRIBUTE3, ATTRIBUTE4, SO_NO, SO_QTY
                      , FROM_COMPANY_ID, PLANT_ID
                  FROM DM_DNM_SALES_RESULT_IF X
                 WHERE 1 = 1
                   AND DIVISION_ID = '40'
                   AND DIVISION_ID IN (SELECT DIVISION_ID FROM GT_MFSRM_I_DIVISION)
                   AND SALES_YYYYMM BETWEEN V_START_YYYYMM AND V_END_YYYYMM
                   AND SALES_AMOUNT_SUM <> 0
                   AND SALES_GROUP NOT IN ('A10','A11')   /* 유상사급 수출공통 / 40 유상사급 제외 */
             ) A
           , ( SELECT 'SALES_RESULT' AS MEASURE FROM DUAL
               UNION SELECT 'SALES_RESULT_AMOUNT' FROM DUAL
