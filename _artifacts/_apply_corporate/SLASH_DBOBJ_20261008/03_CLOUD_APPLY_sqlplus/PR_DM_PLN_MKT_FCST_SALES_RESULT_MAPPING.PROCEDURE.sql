    DELETE FROM GT_MFSRM_TEMP_DM_RESULT;
    DELETE FROM GT_MFSRM_DM_RESULT;
    DELETE FROM GT_MFSRM_DM_RESULT_BEFORE;
    DELETE FROM GT_MFSRM_AS_TMPDATA;
    DELETE FROM GT_MFSRM_VMI_TMPDATA;
    DELETE FROM GT_MFSRM_VMI_RESULT;
