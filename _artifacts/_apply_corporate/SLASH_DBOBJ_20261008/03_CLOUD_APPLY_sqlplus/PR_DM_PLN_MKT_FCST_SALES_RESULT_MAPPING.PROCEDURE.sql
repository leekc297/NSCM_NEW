                SELECT A.DIVISION_ID, V_VERSION, 'MF_D', TO_CHAR(SYSDATE,'YYYYMMDD'), A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.DOM_EXP, A.FCST_TYPE, A.INCOTERMS, A.MEASURE
                     --, A.PLANT_SITE_ID, A.YYYYMMDD, A.QTY, A.CREATED_BY, A.CREATION_DATE, A.LAST_UPDATED_BY, A.LAST_UPDATE_DATE, A.ATTRIBUTE1, A.ATTRIBUTE2, A.ATTRIBUTE3, A.ATTRIBUTE4
                     , A.PLANT_SITE_ID, A.YYYYMMDD, A.QTY, A.CREATED_BY, A.CREATION_DATE, A.LAST_UPDATED_BY, SYSDATE, A.ATTRIBUTE1, A.ATTRIBUTE2, A.ATTRIBUTE3, A.ATTRIBUTE4
                     , A.ATTRIBUTE5, A.ATTRIBUTE6, A.ATTRIBUTE7, A.ATTRIBUTE8, A.ATTRIBUTE9, A.ATTRIBUTE10, A.CELL_PROD_SITE_ID
                FROM DM_PLN_MKT_FCST_RESULT A
                INNER JOIN GT_MFSRM_DEDUCTED_ITEM B
                        ON A.DIVISION_ID = B.DIVISION_ID AND A.SCM_SITE_ID = B.SCM_SITE_ID AND A.PROJECT_CODE = B.PROJECT_CODE AND A.ITEM_ID = B.ITEM_ID
                WHERE A.MEASURE = 'RTF_SYS_RP'
                  AND A.YYYYMMDD >= TO_CHAR(FN_NEXT_DAY(SYSDATE,'MON')-14,'YYYYMMDD')   /* 전주 월요일 */
                  AND A.YYYYMMDD <  TO_CHAR(FN_NEXT_DAY(SYSDATE,'MON')-7,'YYYYMMDD');   /* 당주 월요일 이전 */
                N_ROWCNT := SQL%ROWCOUNT;

                V_LOG_TYPE    := 'APPEND';
                V_LOG_MESSAGE := u'\c9c0\c5f0\be4c\b9c1 VERSION CUTOFF';
                V_DESCRIPTION := u'\c9c0\c5f0\be4c\b9c1 VERSION CUTOFF: ' || TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI:SS') || u'  \c0ac\c5c5\bd80: ' || V_DEDUCTED_DIVISION_ID || u' VERSION_NO: ' || V_VERSION;
                D_EVENT_DATE  := SYSDATE;
                N_LOG_COUNT   := N_ROWCNT;
                PR_SCM_SYS_LOG_BATCH(V_PROGRAM_NAME, V_LOG_TYPE, N_LOG_COUNT, V_LOG_MESSAGE, V_DESCRIPTION, D_EVENT_DATE);
            END IF;

            /* 23시 : 13시 대비 실적 변동 시 MKT FCST 차감 */
            IF (V_STATES = 'DEDUCTED') THEN
                V_LOG_TYPE    := 'APPEND';
