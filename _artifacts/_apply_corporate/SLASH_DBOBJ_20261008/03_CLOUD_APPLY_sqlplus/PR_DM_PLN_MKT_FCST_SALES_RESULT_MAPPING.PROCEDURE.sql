                V_DESCRIPTION := u'\c9c0\c5f0\be4c\b9c1 \cc28\ac10\b85c\c9c1 \c2dc\c791: ' || TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI:SS') || u'  \c0ac\c5c5\bd80: ' || V_DEDUCTED_DIVISION_ID || u' \c694\ccad\c0c1\d0dc: ' || V_STATES;
                D_EVENT_DATE  := SYSDATE;
                N_LOG_COUNT   := N_ROWCNT;
                PR_SCM_SYS_LOG_BATCH(V_PROGRAM_NAME, V_LOG_TYPE, N_LOG_COUNT, V_LOG_MESSAGE, V_DESCRIPTION, D_EVENT_DATE);

                SELECT COUNT(1) INTO N_CHK_CNT
                  FROM DM_PLN_MKT_FCST_RESULT A
                  INNER JOIN GT_MFSRM_DEDUCTED_ITEM B
                          ON A.DIVISION_ID = B.DIVISION_ID AND A.SCM_SITE_ID = B.SCM_SITE_ID AND A.PROJECT_CODE = B.PROJECT_CODE AND A.ITEM_ID = B.ITEM_ID
                 WHERE A.MEASURE = 'RTF_SYS_RP'
                   AND A.YYYYMMDD >= TO_CHAR(FN_NEXT_DAY(SYSDATE,'MON')-14,'YYYYMMDD')
                   AND A.YYYYMMDD <  TO_CHAR(FN_NEXT_DAY(SYSDATE,'MON')-7,'YYYYMMDD');

                IF N_CHK_CNT > 0 THEN
                    PR_DM_PLN_MKT_FCST_DELAY_BILLING_AUTO_DEDUCTED(V_DEDUCTED_DIVISION_ID);
                END IF;
            END IF;
        END LOOP;

        V_LOG_TYPE    := 'APPEND';
        V_LOG_MESSAGE := u'\c9c0\c5f0\be4c\b9c1 \c218\d589\c885\b8cc';
        V_DESCRIPTION := u'\c9c0\c5f0\be4c\b9c1 \c218\d589\c885\b8cc: ' || TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI:SS') || u'  \c0ac\c5c5\bd80: ' || V_DEDUCTED_DIVISION_ID || u' \c694\ccad\c0c1\d0dc: ' || V_STATES;
        D_EVENT_DATE  := SYSDATE;
        N_LOG_COUNT   := N_ROWCNT;
        PR_SCM_SYS_LOG_BATCH(V_PROGRAM_NAME, V_LOG_TYPE, N_LOG_COUNT, V_LOG_MESSAGE, V_DESCRIPTION, D_EVENT_DATE);
        V_DESCRIPTION := '';


        IF SYS_CONTEXT('USERENV','DB_NAME')  = 'OCGSCMP_P01' THEN
            EXECUTE IMMEDIATE 'BEGIN PR_DM_ANL_KPI_SALES_ACCURACY; END;';   /* 20181019 KPI_SALES_ACCURACY */
            EXECUTE IMMEDIATE 'BEGIN PR_DM_ANL_KPI_SUMMARY; END;';   /* 20181128 KHSONG */
        END IF;

        COMMIT;
    EXCEPTION
        WHEN OTHERS THEN

            ROLLBACK;
            V_LOG_TYPE    := 'ERROR';
            V_LOG_MESSAGE := SUBSTR(SQLERRM, 1, 1000);
            V_DESCRIPTION := SUBSTR('ERROR_BACKTRACE : ' || DBMS_UTILITY.FORMAT_ERROR_BACKTRACE, 1, 500);
            D_EVENT_DATE  := SYSDATE;
            PR_SCM_SYS_LOG_BATCH(V_PROGRAM_NAME
                , V_LOG_TYPE
                , N_LOG_COUNT
                , V_LOG_MESSAGE
                , V_DESCRIPTION
                , D_EVENT_DATE
                , JSON_OBJECT('p_division_id' VALUE P_DIVISION_ID RETURNING VARCHAR2(4000 CHAR))
                , SQLCODE
                , SQLERRM
                , DBMS_UTILITY.FORMAT_ERROR_BACKTRACE);
    END;


    V_LOG_TYPE    := 'END';
    V_LOG_MESSAGE := '########## END of procedure ##########';
    D_EVENT_DATE  := SYSDATE;
    PR_SCM_SYS_LOG_BATCH(V_PROGRAM_NAME, V_LOG_TYPE, N_LOG_COUNT, V_LOG_MESSAGE, V_DESCRIPTION, D_EVENT_DATE);
END;
