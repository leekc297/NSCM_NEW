-- [E20261009-GRPBYFIX] 02_VERIFY — 적용 후 검증(조회 전용, 9객체) · 생성 2026-10-09 · SCM_MGR 접속 후 파일 전체 실행(F5), 바인드·DEFINE 없음
--   V1 상태/오류 · V2 마커 수 = 기대치(MISMATCH 0행) · V3 마커 줄 원문. PKG_DMF0044 를 01b 로 올리지 않았으면 V2 에서 PKG_DMF0044 만 MISMATCH 로 나오는 것이 정상.
SET DEFINE OFF
SET SERVEROUTPUT ON SIZE UNLIMITED

SELECT 'V1 | ' || object_type || ' ' || object_name || ' | ' || status || ' | ddl=' || TO_CHAR(last_ddl_time,'YYYY-MM-DD HH24:MI:SS') AS line
  FROM all_objects WHERE owner='SCM_MGR' AND object_name IN ('DMF0020_GET_SCM_MST_FUTURE_PRICE','PKG_DMF0021','PKG_DMF0044','PKG_DMF0045','PKG_SCP0013','PKG_SSP0045','PR_DM_DNM_EDI_CALLOFF_MKT_FCST','PR_DM_PLN_SALES_PLAN_RESULT_MOVE','PR_SSP_ANL_SHIPMENT_PLAN_FG') AND object_type IN ('PACKAGE BODY','PROCEDURE') ORDER BY object_name, object_type;
SELECT 'V1 ERR | ' || type || ' ' || name || ' L' || line || ' | ' || SUBSTR(REPLACE(text,CHR(10),' '),1,200) AS line
  FROM all_errors WHERE owner='SCM_MGR' AND name IN ('DMF0020_GET_SCM_MST_FUTURE_PRICE','PKG_DMF0021','PKG_DMF0044','PKG_DMF0045','PKG_SCP0013','PKG_SSP0045','PR_DM_DNM_EDI_CALLOFF_MKT_FCST','PR_DM_PLN_SALES_PLAN_RESULT_MOVE','PR_SSP_ANL_SHIPMENT_PLAN_FG') AND attribute='ERROR' ORDER BY name, sequence;
WITH exp AS (
SELECT 'PROCEDURE' t, 'DMF0020_GET_SCM_MST_FUTURE_PRICE' n, 3 exp FROM dual
UNION ALL
SELECT 'PACKAGE BODY' t, 'PKG_DMF0021' n, 1 exp FROM dual
UNION ALL
SELECT 'PACKAGE BODY' t, 'PKG_DMF0044' n, 17 exp FROM dual
UNION ALL
SELECT 'PACKAGE BODY' t, 'PKG_DMF0045' n, 1 exp FROM dual
UNION ALL
SELECT 'PACKAGE BODY' t, 'PKG_SCP0013' n, 1 exp FROM dual
UNION ALL
SELECT 'PACKAGE BODY' t, 'PKG_SSP0045' n, 1 exp FROM dual
UNION ALL
SELECT 'PROCEDURE' t, 'PR_DM_DNM_EDI_CALLOFF_MKT_FCST' n, 4 exp FROM dual
UNION ALL
SELECT 'PROCEDURE' t, 'PR_DM_PLN_SALES_PLAN_RESULT_MOVE' n, 1 exp FROM dual
UNION ALL
SELECT 'PROCEDURE' t, 'PR_SSP_ANL_SHIPMENT_PLAN_FG' n, 2 exp FROM dual
), act AS (
    SELECT type t, name n, COUNT(*) cnt FROM all_source WHERE owner='SCM_MGR' AND name IN ('DMF0020_GET_SCM_MST_FUTURE_PRICE','PKG_DMF0021','PKG_DMF0044','PKG_DMF0045','PKG_SCP0013','PKG_SSP0045','PR_DM_DNM_EDI_CALLOFF_MKT_FCST','PR_DM_PLN_SALES_PLAN_RESULT_MOVE','PR_SSP_ANL_SHIPMENT_PLAN_FG') AND type IN ('PACKAGE BODY','PROCEDURE') AND text LIKE '%[E20261009-GRPBYFIX]%' GROUP BY type, name
)
SELECT 'V2 | ' || e.t || ' ' || e.n || ' | markers=' || NVL(a.cnt,0) || ' expected=' || e.exp || CASE WHEN NVL(a.cnt,0) = e.exp THEN '' ELSE '  <== MISMATCH' END AS line
  FROM exp e LEFT JOIN act a ON a.t = e.t AND a.n = e.n ORDER BY e.n;
SELECT 'V3 | ' || type || ' ' || name || ' L' || line || ' | ' || SUBSTR(TRIM(REPLACE(text,CHR(10),'')),1,140) AS line
  FROM all_source WHERE owner='SCM_MGR' AND name IN ('DMF0020_GET_SCM_MST_FUTURE_PRICE','PKG_DMF0021','PKG_DMF0044','PKG_DMF0045','PKG_SCP0013','PKG_SSP0045','PR_DM_DNM_EDI_CALLOFF_MKT_FCST','PR_DM_PLN_SALES_PLAN_RESULT_MOVE','PR_SSP_ANL_SHIPMENT_PLAN_FG') AND type IN ('PACKAGE BODY','PROCEDURE') AND text LIKE '%[E20261009-GRPBYFIX]%' ORDER BY name, type, line;
