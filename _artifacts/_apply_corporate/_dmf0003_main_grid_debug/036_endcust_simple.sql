--   동일 결과 단순 SQL EndCustomer 시도.
UPDATE SCM_MGR.SCM_MST_SHEET_COLUMNS
   SET CELL_COMBO_DATA_TYPE = 'EndCustomer',
       LAST_UPDATED_BY  = 'system',
       LAST_UPDATE_DATE = SYSDATE
 WHERE PROGRAM_ID = 'DMF0003'
   AND SHEET_NAME = 'main'
   AND COLUMN_NAME = 'END_CUSTOMER';

