-- EndCustomerByDivisionDept 직접 실행 (row 수 확인)
SELECT COUNT(*) AS ROW_CNT
FROM (
  SELECT DISTINCT 	A.DIVISION_ID AS DIVISION_ID,
    A.END_CUSTOMER AS CODE,
    NVL(D.SEGMENT3, A.END_CUSTOMER) AS NAME
  FROM ( 	SELECT DISTINCT
        site.DIVISION_ID
      , site.END_CUSTOMER
      , item.DEPT_ID, item.PROJECT_CODE
      , site.SCM_SITE_ID AS CODE
      , site.SCM_SITE_ID AS NAME
    FROM      SCM_MST_SITE site
    LEFT JOIN SCM_MST_SITE_ITEM item
           ON site.DIVISION_ID = item.DIVISION_ID
          AND site.SCM_SITE_ID = item.SCM_SITE_ID
  ) A LEFT OUTER JOIN SCM_ADM_LOOKUP_MASTER_DETAIL D
      ON A.DIVISION_ID = D.SEGMENT1
     AND A.END_CUSTOMER = D.SEGMENT2
     AND D.LOOKUP_TYPE = 'END_CUSTOMER'
     AND D.VALID_YN = 'Y'
  WHERE 1 = 1
    AND A.DIVISION_ID IS NOT NULL
    AND A.DEPT_ID IS NOT NULL
    AND A.END_CUSTOMER IS NOT NULL
);
