-- ── SHEET_COLUMNS: '_40' 중복 삭제 + 'fcstNPrice'→'FcstNPrice' ──
DELETE FROM SCM_MGR.SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID='DMF0082' AND SHEET_NAME='fcstNPrice_40';
UPDATE SCM_MGR.SCM_MST_SHEET_COLUMNS SET SHEET_NAME='FcstNPrice'
 WHERE PROGRAM_ID='DMF0082' AND SHEET_NAME='fcstNPrice';

-- ── SHEET_MEASURE: rename ──
UPDATE SCM_MGR.SCM_MST_SHEET_MEASURE SET SHEET_NAME='FcstNPrice'
 WHERE PROGRAM_ID='DMF0082' AND SHEET_NAME='fcstNPrice';

-- ── TITLESET_USER: rename ('fcstNPrice_40' 은 미존재) ──
UPDATE SCM_MGR.SCM_MST_TITLESET_USER SET SHEET_NAME='FcstNPrice'
 WHERE PROGRAM_ID='DMF0082' AND SHEET_NAME='fcstNPrice';

-- ── MNU_BTN_MPG_M: '_40' 중복 삭제 + rename ──
DELETE FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID='DMF0082' AND SHT_NM='fcstNPrice_40';
UPDATE SCM_MGR.SCM_ADM_MNU_BTN_MPG_M SET SHT_NM='FcstNPrice'
 WHERE MNU_ID='DMF0082' AND SHT_NM='fcstNPrice';

-- ── USER_GR_MNU_BTN_MPG_M: '_40' 중복 삭제 + rename ──
DELETE FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE MNU_ID='DMF0082' AND SHT_NM='fcstNPrice_40';
UPDATE SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M SET SHT_NM='FcstNPrice'
 WHERE MNU_ID='DMF0082' AND SHT_NM='fcstNPrice';

-- ── MEASURE 필수컬럼 titleset 통합 추가 (이제 'FcstNPrice' 아래. DISPLAY_FLAG='N'→'Y' 근본해소) ──
