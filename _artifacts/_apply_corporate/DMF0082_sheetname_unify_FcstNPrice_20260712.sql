   'N', 'ASC', 'admin', SYSDATE, 'admin', SYSDATE
  FROM SCM_MGR.SCM_MST_TITLESET_USER T
 WHERE T.PROGRAM_ID='DMF0082' AND T.SHEET_NAME='FcstNPrice' AND T.USER_INQUIRY_COLUMN_TYPE_CODE='C'
   AND NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_MST_TITLESET_USER X
                    WHERE X.USER_ID=T.USER_ID AND X.PROGRAM_ID='DMF0082' AND X.SHEET_NAME='FcstNPrice'
