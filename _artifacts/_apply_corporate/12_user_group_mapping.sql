-- A. USER↔GR 매핑 테이블 후보 검색
SELECT TABLE_NAME FROM USER_TABLES WHERE TABLE_NAME LIKE '%USER%GR%' OR TABLE_NAME LIKE '%GR%USER%' OR TABLE_NAME LIKE '%USR%GR%' OR TABLE_NAME LIKE '%GR%USR%' ORDER BY TABLE_NAME;

-- B. SCM_ADM_USER_GR_M 의 컬럼 (그룹 정의 테이블)
SELECT TABLE_NAME, COLUMN_NAME FROM USER_TAB_COLUMNS WHERE TABLE_NAME LIKE '%GR%' AND COLUMN_NAME='USER_ID' ORDER BY TABLE_NAME;

-- C. minyonglee1 의 그룹 매핑 (각 후보 테이블에서)
SELECT 'USR_MPG' AS K, USER_GR_ID, USER_ID FROM SCM_ADM_USER_GR_USR_MPG_M WHERE USER_ID='minyonglee1';

-- D. UNIT_AUTH 에서 Division 40 권한 가진 그룹 (UNIT_ID = 40)
SELECT USER_GR_ID, UNIT_TP_CD, UNIT_ID, COUNT(*) AS C FROM SCM_ADM_USER_GR_UNIT_AUTH_MPG_M WHERE UNIT_TP_CD='D' AND UNIT_ID='40' GROUP BY USER_GR_ID, UNIT_TP_CD, UNIT_ID ORDER BY USER_GR_ID;

-- E. minyonglee1 이 속한 그룹의 모든 UNIT_AUTH row
SELECT UA.USER_GR_ID, UA.UNIT_TP_CD, UA.UNIT_ID FROM SCM_ADM_USER_GR_UNIT_AUTH_MPG_M UA WHERE UA.USER_GR_ID IN (SELECT USER_GR_ID FROM SCM_ADM_USER_GR_USR_MPG_M WHERE USER_ID='minyonglee1') ORDER BY UA.USER_GR_ID, UA.UNIT_ID FETCH FIRST 30 ROWS ONLY;

