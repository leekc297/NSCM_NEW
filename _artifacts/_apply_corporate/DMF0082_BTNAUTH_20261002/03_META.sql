-- [E20261002-BTNAUTH] DMF0082 버튼 활성화 조회 SP 호출 등록 4종 (사내 ZIOUI1 · SCM_MGR 로 실행)
--   FE 호출 계약: menuId='DMF0082' / sheetName='buttonAuth' / 버튼코드 SEARCH
--                 filters = { divisionId, userGroup }  (sesUserId 는 BE 가 세션에서 주입 — 기존 SP 들과 동일)
--                 응답    = { buttonAuth: [1행], measureAuth: [메저별] }
--   전부 멱등 MERGE (ON = PK 실측: API_M(API_ID) / PROC_M(PROC_NM,COL_NM,COL_TP_CD) /
--                    MNU_BTN_MPG_M(MNU_ID,SHT_NM,MNU_BTN_CD) / USER_GR_MNU_BTN_MPG_M(USER_GR_ID,MNU_ID,SHT_NM,MNU_BTN_CD))
--   문장 구분 = 단독 '/' 줄

-- 1) API_M — 형제 행(DMF0082_spreadTitle_SEARCH) 과 같은 형식
MERGE INTO SCM_MGR.SCM_ADM_API_M T
USING (SELECT 'DMF0082_buttonAuth_SEARCH' AS API_ID FROM DUAL) S
   ON (T.API_ID = S.API_ID)
 WHEN MATCHED THEN UPDATE SET
      T.API_TP_CD        = 'PROC_SELECT'
    , T.API_MSG_ID       = 'MSG_API_DMF0082_buttonAuth_SEARCH'
    , T.API_MSG_DESC     = 'DMF0082 버튼 활성화 여부 조회 (화면 오픈·Division 변경 시)'
    , T.API_URL          = 'PKG_DMF0082.P_DMF0082_GET_BUTTON_AUTH'
    , T.USE_YN           = 'Y'
    , T.LAST_UPDATED_BY  = 'admin'
    , T.LAST_UPDATE_DATE = SYSDATE
 WHEN NOT MATCHED THEN INSERT
      (API_ID, API_TP_CD, API_MSG_ID, API_MSG_DESC, API_URL, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
      VALUES
      (S.API_ID, 'PROC_SELECT', 'MSG_API_DMF0082_buttonAuth_SEARCH', 'DMF0082 버튼 활성화 여부 조회 (화면 오픈·Division 변경 시)'
     , 'PKG_DMF0082.P_DMF0082_GET_BUTTON_AUTH', 'Y', 'admin', SYSDATE, 'admin', SYSDATE)
/

-- 2) PROC_M — SP 인자 순서 그대로 (IN 3 + CURSOR 2 + PROC_RESULT 1)
MERGE INTO SCM_MGR.SCM_ADM_PROC_M T
USING (
    SELECT 'PKG_DMF0082.P_DMF0082_GET_BUTTON_AUTH' AS PROC_NM, 'divisionId'      AS COL_NM, 'VARCHAR'     AS DATA_TP_CD, 'IN'  AS COL_TP_CD, 1 AS SORT_ORD FROM DUAL UNION ALL
    SELECT 'PKG_DMF0082.P_DMF0082_GET_BUTTON_AUTH', 'sesUserId'      , 'VARCHAR'    , 'IN' , 2 FROM DUAL UNION ALL
    SELECT 'PKG_DMF0082.P_DMF0082_GET_BUTTON_AUTH', 'userGroup'      , 'VARCHAR'    , 'IN' , 3 FROM DUAL UNION ALL
    SELECT 'PKG_DMF0082.P_DMF0082_GET_BUTTON_AUTH', 'buttonAuth'     , 'CURSOR'     , 'OUT', 4 FROM DUAL UNION ALL
    SELECT 'PKG_DMF0082.P_DMF0082_GET_BUTTON_AUTH', 'measureAuth'    , 'CURSOR'     , 'OUT', 5 FROM DUAL UNION ALL
    SELECT 'PKG_DMF0082.P_DMF0082_GET_BUTTON_AUTH', 'o_result_cursor', 'PROC_RESULT', 'OUT', 6 FROM DUAL
) S
   ON (T.PROC_NM = S.PROC_NM AND T.COL_NM = S.COL_NM AND T.COL_TP_CD = S.COL_TP_CD)
 WHEN MATCHED THEN UPDATE SET
      T.DATA_TP_CD       = S.DATA_TP_CD
    , T.SORT_ORD         = S.SORT_ORD
    , T.LAST_UPDATED_BY  = 'admin'
    , T.LAST_UPDATE_DATE = SYSDATE
 WHEN NOT MATCHED THEN INSERT
      (PROC_NM, COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
      VALUES
      (S.PROC_NM, S.COL_NM, S.DATA_TP_CD, S.COL_TP_CD, S.SORT_ORD, 'admin', SYSDATE, 'admin', SYSDATE)
/

-- 3) MNU_BTN_MPG_M — 메뉴 × 시트 × 버튼 → API
MERGE INTO SCM_MGR.SCM_ADM_MNU_BTN_MPG_M T
USING (SELECT 'DMF0082' AS MNU_ID, 'buttonAuth' AS SHT_NM, 'SEARCH' AS MNU_BTN_CD FROM DUAL) S
   ON (T.MNU_ID = S.MNU_ID AND T.SHT_NM = S.SHT_NM AND T.MNU_BTN_CD = S.MNU_BTN_CD)
 WHEN MATCHED THEN UPDATE SET
      T.API_ID           = 'DMF0082_buttonAuth_SEARCH'
    , T.USE_YN           = 'Y'
    , T.LAST_UPDATED_BY  = 'admin'
    , T.LAST_UPDATE_DATE = SYSDATE
 WHEN NOT MATCHED THEN INSERT
      (MNU_ID, SHT_NM, MNU_BTN_CD, API_ID, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
      VALUES
      (S.MNU_ID, S.SHT_NM, S.MNU_BTN_CD, 'DMF0082_buttonAuth_SEARCH', 'Y', 'admin', SYSDATE, 'admin', SYSDATE)
/

-- 4) USER_GR_MNU_BTN_MPG_M — 이 화면을 조회할 수 있는 그룹 전부 (형제 시트 spreadTitle/SEARCH 의 그룹 집합을 그대로 따른다)
MERGE INTO SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M T
USING (
    SELECT G.USER_GR_ID, G.MNU_ID, 'buttonAuth' AS SHT_NM, 'SEARCH' AS MNU_BTN_CD, G.USE_YN
    FROM   SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M G
    WHERE  G.MNU_ID     = 'DMF0082'
    AND    G.SHT_NM     = 'spreadTitle'
    AND    G.MNU_BTN_CD = 'SEARCH'
) S
   ON (T.USER_GR_ID = S.USER_GR_ID AND T.MNU_ID = S.MNU_ID AND T.SHT_NM = S.SHT_NM AND T.MNU_BTN_CD = S.MNU_BTN_CD)
 WHEN MATCHED THEN UPDATE SET
      T.USE_YN           = S.USE_YN
    , T.LAST_UPDATED_BY  = 'admin'
    , T.LAST_UPDATE_DATE = SYSDATE
 WHEN NOT MATCHED THEN INSERT
      (USER_GR_ID, MNU_ID, SHT_NM, MNU_BTN_CD, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
      VALUES
      (S.USER_GR_ID, S.MNU_ID, S.SHT_NM, S.MNU_BTN_CD, S.USE_YN, 'admin', SYSDATE, 'admin', SYSDATE)
/
