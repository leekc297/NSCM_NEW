             V_SMP_B      VARCHAR2(8)   PATH '$.SAMPLE_B_DATE',
             V_SMP_C      VARCHAR2(8)   PATH '$.SAMPLE_C_DATE',
             V_SMP_D      VARCHAR2(8)   PATH '$.SAMPLE_D_DATE')) J
     WHERE J.V_CRUD_TYPE = 'I';
    V_INSERT_CNT := SQL%ROWCOUNT;

    -- UPDATE (CRUD_TYPE='M') — '작성중' 상태만 (P-15 서버측 재가드)
    MERGE INTO SCM_MGR.SDM_MST_DPJT_M T
    USING ( SELECT J.V_DPJT_KEY, J.V_CLASS, J.V_CUSTOMER, J.V_NAME, J.V_CELL_TYPE, J.V_STACK,
                   J.V_BIZ, J.V_SOP_DATE, J.V_SOP_PLANT, J.V_SMP_A, J.V_SMP_B, J.V_SMP_C, J.V_SMP_D
              FROM JSON_TABLE(P_DATA, '$[*]' COLUMNS (
                     V_CRUD_TYPE  VARCHAR2(1)   PATH '$.CRUD_TYPE',
                     V_DPJT_KEY   VARCHAR2(50)  PATH '$.DPJT_KEY',
                     V_CLASS      VARCHAR2(30)  PATH '$.DPJT_CLASS',
                     V_CUSTOMER   VARCHAR2(100) PATH '$.END_CUSTOMER',
                     V_NAME       VARCHAR2(200) PATH '$.DPJT_NAME',
                     V_CELL_TYPE  VARCHAR2(30)  PATH '$.CELL_TYPE',
                     V_STACK      VARCHAR2(30)  PATH '$.STACK_METHOD',
                     V_BIZ        VARCHAR2(50)  PATH '$.BIZ_TYPE',
                     V_SOP_DATE   VARCHAR2(8)   PATH '$.SOP_DATE',
                     V_SOP_PLANT  VARCHAR2(30)  PATH '$.SOP_PLANT_ID',
                     V_SMP_A      VARCHAR2(8)   PATH '$.SAMPLE_A_DATE',
                     V_SMP_B      VARCHAR2(8)   PATH '$.SAMPLE_B_DATE',
                     V_SMP_C      VARCHAR2(8)   PATH '$.SAMPLE_C_DATE',
                     V_SMP_D      VARCHAR2(8)   PATH '$.SAMPLE_D_DATE')) J
             WHERE J.V_CRUD_TYPE = 'M' ) S
    ON (T.DPJT_KEY = S.V_DPJT_KEY AND T.DPJT_REG_STATUS = 'DRAFT')
    WHEN MATCHED THEN UPDATE
