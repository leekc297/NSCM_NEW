        OPEN O_RESULT_CURSOR FOR SELECT '-1' AS CODE, V_ERR AS MSG, '0' AS EVENT FROM DUAL;
      END;
  END P_SDM1010_SAVE_POP_PJT_AUTH_REQ;

  /* ------------------------------------ 팝업: My Work 조회 (POP2_GRID5 — 15컬럼) */
  PROCEDURE P_SDM1010_GET_POP_MY_WORK (
      P_DPJT_KEY          IN VARCHAR2,
      P_USER_ID           IN VARCHAR2,
      O_RC1               OUT SYS_REFCURSOR,
      O_RESULT_CURSOR     OUT SYS_REFCURSOR)
  AS
    V_IS_ADMIN NUMBER := F_IS_ADMIN(P_USER_ID);  -- 패키지 로컬 함수 = SQL 내 직접 호출 불가(PLS-00231)
  BEGIN
    -- 설계서 My Work_GRID 목업 + POP2_GRID5 정의 컬럼 전수 (정오표 #6: SOP_PLANT 콤보=PlantByDivisionCompany)
    OPEN O_RC1 FOR
      SELECT M.DPJT_KEY,
             M.DPJT_CODE,
             M.DIVISION_ID,
             NVL(DV.DIVISION_NAME, M.DIVISION_ID)   AS DIVISION_NAME,
             M.DPJT_CLASS,
             NVL(LC.SEGMENT2, M.DPJT_CLASS)         AS DPJT_CLASS_NAME,
             M.END_CUSTOMER,
             M.DPJT_NAME,
             M.SAMPLE_A_DATE,
             M.SAMPLE_B_DATE,
             M.SAMPLE_C_DATE,
             M.SAMPLE_D_DATE,
             M.SOP_DATE,
             M.SOP_PLANT_ID,
             M.SOP_PLANT_ID                         AS SOP_PLANT_NAME
        FROM SCM_MGR.SDM_MST_DPJT_M M
        LEFT JOIN SCM_MGR.SCM_MST_DIVISION DV ON DV.DIVISION_ID = M.DIVISION_ID
        LEFT JOIN SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL LC
               ON LC.LOOKUP_TYPE = 'SPMS_DPJT_CLASS' AND LC.SEGMENT1 = M.DPJT_CLASS AND LC.VALID_YN = 'Y'
       WHERE M.DPJT_KEY = P_DPJT_KEY
         -- 조회 권한 가드: 관리자 그룹 / 프로젝트 관리자 / 권한 보유자만
         AND ( V_IS_ADMIN > 0
               OR M.MGMT_USER_ID = P_USER_ID
               OR M.CREATED_BY = P_USER_ID
               OR EXISTS (SELECT 1 FROM SCM_MGR.SDM_MST_DPJT_AUTH_M A
                           WHERE A.DPJT_KEY = M.DPJT_KEY AND A.USER_ID = P_USER_ID) );
    OPEN O_RESULT_CURSOR FOR SELECT '0' AS CODE, 'SUCCESS' AS MSG FROM DUAL;
  EXCEPTION
    WHEN OTHERS THEN
      DECLARE V_ERR VARCHAR2(4000) := SUBSTR(SQLERRM, 1, 4000);
      BEGIN
        P_LOG_ERR($$PLSQL_UNIT || '.GET_MY_WORK', JSON_OBJECT('p_dpjt_key' VALUE P_DPJT_KEY, 'p_user_id' VALUE P_USER_ID));
        OPEN O_RC1 FOR SELECT NULL AS DUMMY FROM DUAL WHERE 1 = 0;
        OPEN O_RESULT_CURSOR FOR SELECT '-1' AS CODE, V_ERR AS MSG FROM DUAL;
      END;
  END P_SDM1010_GET_POP_MY_WORK;

