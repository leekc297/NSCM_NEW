    DELETE FROM SCM_MGR.SDM_MST_DPJT_AUTH_M A
     WHERE A.DPJT_KEY IN (
        SELECT M.DPJT_KEY FROM SCM_MGR.SDM_MST_DPJT_M M
         WHERE M.DPJT_REG_STATUS = 'DRAFT'
           AND M.DPJT_KEY IN (SELECT V_DPJT_KEY FROM JSON_TABLE(P_DATA, '$[*]' COLUMNS (
                 V_CRUD_TYPE VARCHAR2(1) PATH '$.CRUD_TYPE',
                 V_DPJT_KEY  VARCHAR2(50) PATH '$.DPJT_KEY')) WHERE V_CRUD_TYPE = 'D'));
    DELETE FROM SCM_MGR.SDM_MST_DPJT_AUTH_REQ_M Q
     WHERE Q.DPJT_KEY IN (
        SELECT M.DPJT_KEY FROM SCM_MGR.SDM_MST_DPJT_M M
         WHERE M.DPJT_REG_STATUS = 'DRAFT'
           AND M.DPJT_KEY IN (SELECT V_DPJT_KEY FROM JSON_TABLE(P_DATA, '$[*]' COLUMNS (
                 V_CRUD_TYPE VARCHAR2(1) PATH '$.CRUD_TYPE',
                 V_DPJT_KEY  VARCHAR2(50) PATH '$.DPJT_KEY')) WHERE V_CRUD_TYPE = 'D'));
    DELETE FROM SCM_MGR.SDM_MST_DPJT_M M
     WHERE M.DPJT_REG_STATUS = 'DRAFT'
       AND M.DPJT_KEY IN (SELECT V_DPJT_KEY FROM JSON_TABLE(P_DATA, '$[*]' COLUMNS (
             V_CRUD_TYPE VARCHAR2(1) PATH '$.CRUD_TYPE',
             V_DPJT_KEY  VARCHAR2(50) PATH '$.DPJT_KEY')) WHERE V_CRUD_TYPE = 'D');
    V_DELETE_CNT := SQL%ROWCOUNT;

    COMMIT;
    OPEN O_RESULT_CURSOR FOR
      SELECT '0' AS CODE, 'SUCCESS' AS MSG,
             TO_CHAR(V_INSERT_CNT + V_UPDATE_CNT + V_DELETE_CNT) AS EVENT FROM DUAL;
  EXCEPTION
    WHEN OTHERS THEN
