  /* ------------------------------- 팝업: 권한관리 조회 (POP1_GRID2/3 — I/R 통합) */
  PROCEDURE P_SDM1010_GET_POP_PJT_AUTH_MGMT (
      P_DPJT_KEY          IN VARCHAR2,
      O_RC1               OUT SYS_REFCURSOR,
      O_RESULT_CURSOR     OUT SYS_REFCURSOR)
  AS
  BEGIN
    OPEN O_RC1 FOR
      SELECT A.DPJT_AUTH_TYPE,                              -- FE 가 I/R 로 입력/조회 리스트 분리
             A.USER_ID,
             NVL(U.USER_NAME, A.USER_ID) AS USER_NAME,
             U.JOB_CODE,
             U.JOB_NAME,
             U.DEPT_ID,
             NVL(D.DEPT_NAME_KO, U.DEPT_ID) AS DEPT_NAME,
             -- P-23: 미처리 요청의 권한 유형이 보유 권한과 다르면 구분 표시
             CASE WHEN Q.REQ_AUTH_TYPE IS NOT NULL AND Q.REQ_AUTH_TYPE <> A.DPJT_AUTH_TYPE
                  THEN '요청(' || NVL(LQ.SEGMENT2, Q.REQ_AUTH_TYPE) || ')'
             END AS AUTH_REQ_STATUS
        FROM SCM_MGR.SDM_MST_DPJT_AUTH_M A
        LEFT JOIN SCM_MGR.SCM_MST_SSO_USER_INFO U ON U.USER_ID = A.USER_ID
        LEFT JOIN SCM_MGR.SCM_MST_SSO_DEPT_INFO D ON D.DEPT_ID = U.DEPT_ID
        LEFT JOIN (SELECT Q1.DPJT_KEY, Q1.USER_ID, MAX(Q1.REQ_AUTH_TYPE) AS REQ_AUTH_TYPE
                     FROM SCM_MGR.SDM_MST_DPJT_AUTH_REQ_M Q1
                    WHERE Q1.REQ_STATUS = 'REQUEST'
                    GROUP BY Q1.DPJT_KEY, Q1.USER_ID) Q
               ON Q.DPJT_KEY = A.DPJT_KEY AND Q.USER_ID = A.USER_ID
        LEFT JOIN SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL LQ
               ON LQ.LOOKUP_TYPE = 'SPMS_DPJT_AUTH_TYPE' AND LQ.SEGMENT1 = Q.REQ_AUTH_TYPE AND LQ.VALID_YN = 'Y'
       WHERE A.DPJT_KEY = P_DPJT_KEY
         AND A.DPJT_AUTH_TYPE IN ('I','R')
       ORDER BY A.DPJT_AUTH_TYPE, USER_NAME;
    OPEN O_RESULT_CURSOR FOR SELECT '0' AS CODE, 'SUCCESS' AS MSG FROM DUAL;
  EXCEPTION
    WHEN OTHERS THEN
      DECLARE V_ERR VARCHAR2(4000) := SUBSTR(SQLERRM, 1, 4000);
      BEGIN
        OPEN O_RC1 FOR SELECT NULL AS DUMMY FROM DUAL WHERE 1 = 0;
        OPEN O_RESULT_CURSOR FOR SELECT '-1' AS CODE, V_ERR AS MSG FROM DUAL;
      END;
  END P_SDM1010_GET_POP_PJT_AUTH_MGMT;

  /* --------------------------------------- 팝업: 권한요청 조회 (POP1_GRID4) */
  PROCEDURE P_SDM1010_GET_POP_PJT_AUTH_REQ (
      P_DPJT_KEY          IN VARCHAR2,
      O_RC1               OUT SYS_REFCURSOR,
      O_RESULT_CURSOR     OUT SYS_REFCURSOR)
  AS
  BEGIN
    OPEN O_RC1 FOR
      SELECT Q.REQ_SEQ,
             CASE Q.REQ_STATUS WHEN 'REQUEST' THEN '요청' WHEN 'APPROVE' THEN '승인' ELSE '반려' END AS STATUS,
             Q.REQ_STATUS,
             Q.USER_ID,
             NVL(U.USER_NAME, Q.USER_ID) AS USER_NAME,
             U.JOB_CODE,
             U.JOB_NAME,
             U.DEPT_ID,
             NVL(D.DEPT_NAME_KO, U.DEPT_ID) AS DEPT_NAME,
             Q.REQ_AUTH_TYPE,
             NVL(LA.SEGMENT2, Q.REQ_AUTH_TYPE) AS REQUEST,
             TO_CHAR(Q.REQ_DATE, 'YYYY.MM.DD') AS REQ_DATE
        FROM SCM_MGR.SDM_MST_DPJT_AUTH_REQ_M Q
        LEFT JOIN SCM_MGR.SCM_MST_SSO_USER_INFO U ON U.USER_ID = Q.USER_ID
        LEFT JOIN SCM_MGR.SCM_MST_SSO_DEPT_INFO D ON D.DEPT_ID = U.DEPT_ID
        LEFT JOIN SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL LA
               ON LA.LOOKUP_TYPE = 'SPMS_DPJT_AUTH_TYPE' AND LA.SEGMENT1 = Q.REQ_AUTH_TYPE AND LA.VALID_YN = 'Y'
       WHERE Q.DPJT_KEY = P_DPJT_KEY
         AND Q.REQ_STATUS IN ('REQUEST','REJECT')   -- 승인 완료분은 권한 리스트로 이동 표시
       ORDER BY Q.REQ_DATE DESC, Q.REQ_SEQ;
    OPEN O_RESULT_CURSOR FOR SELECT '0' AS CODE, 'SUCCESS' AS MSG FROM DUAL;
  EXCEPTION
    WHEN OTHERS THEN
      DECLARE V_ERR VARCHAR2(4000) := SUBSTR(SQLERRM, 1, 4000);
      BEGIN
        OPEN O_RC1 FOR SELECT NULL AS DUMMY FROM DUAL WHERE 1 = 0;
        OPEN O_RESULT_CURSOR FOR SELECT '-1' AS CODE, V_ERR AS MSG FROM DUAL;
      END;
  END P_SDM1010_GET_POP_PJT_AUTH_REQ;

  /* ----------------------------- 팝업 OK: 권한관리 저장 (전량 교체 + P-24 반려) */
  PROCEDURE P_SDM1010_SAVE_POP_PJT_AUTH_MGMT (
      P_SES_USER_ID       IN VARCHAR2,
      P_DPJT_KEY          IN VARCHAR2,
      P_DATA              IN CLOB,
      O_RESULT_CURSOR     OUT SYS_REFCURSOR)
  AS
    V_DEL_CNT NUMBER := 0;
    V_INS_CNT NUMBER := 0;
  BEGIN
    -- P-24: 리스트에서 제외되는 사용자의 미처리 요청 → 반려 처리
    UPDATE SCM_MGR.SDM_MST_DPJT_AUTH_REQ_M Q
       SET Q.REQ_STATUS = 'REJECT', Q.PROC_USER_ID = P_SES_USER_ID, Q.PROC_DATE = SYSDATE,
           Q.LAST_UPDATED_BY = P_SES_USER_ID, Q.LAST_UPDATE_DATE = SYSDATE
     WHERE Q.DPJT_KEY = P_DPJT_KEY AND Q.REQ_STATUS = 'REQUEST'
       AND EXISTS (SELECT 1 FROM SCM_MGR.SDM_MST_DPJT_AUTH_M A
                    WHERE A.DPJT_KEY = P_DPJT_KEY AND A.USER_ID = Q.USER_ID AND A.DPJT_AUTH_TYPE IN ('I','R'))
       AND NOT EXISTS (SELECT 1 FROM JSON_TABLE(P_DATA, '$[*]' COLUMNS (
             V_USER_ID VARCHAR2(50) PATH '$.USER_ID')) J WHERE J.V_USER_ID = Q.USER_ID);

    -- 전량 교체: payload 에 없는 I/R 권한 삭제
    DELETE FROM SCM_MGR.SDM_MST_DPJT_AUTH_M A
     WHERE A.DPJT_KEY = P_DPJT_KEY AND A.DPJT_AUTH_TYPE IN ('I','R')
       AND NOT EXISTS (SELECT 1 FROM JSON_TABLE(P_DATA, '$[*]' COLUMNS (
             V_USER_ID   VARCHAR2(50) PATH '$.USER_ID',
             V_AUTH_TYPE VARCHAR2(10) PATH '$.DPJT_AUTH_TYPE')) J
            WHERE J.V_USER_ID = A.USER_ID AND J.V_AUTH_TYPE = A.DPJT_AUTH_TYPE);
    V_DEL_CNT := SQL%ROWCOUNT;

    -- payload 신규분 INSERT (기존재 skip — 멱등)
    INSERT INTO SCM_MGR.SDM_MST_DPJT_AUTH_M
        (DPJT_KEY, USER_ID, DPJT_AUTH_TYPE, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
    SELECT P_DPJT_KEY, J.V_USER_ID, J.V_AUTH_TYPE, P_SES_USER_ID, SYSDATE, P_SES_USER_ID, SYSDATE
      FROM (SELECT DISTINCT V_USER_ID, V_AUTH_TYPE
              FROM JSON_TABLE(P_DATA, '$[*]' COLUMNS (
                     V_USER_ID   VARCHAR2(50) PATH '$.USER_ID',
                     V_AUTH_TYPE VARCHAR2(10) PATH '$.DPJT_AUTH_TYPE'))
             WHERE V_USER_ID IS NOT NULL AND V_AUTH_TYPE IN ('I','R')) J
     WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SDM_MST_DPJT_AUTH_M A
                        WHERE A.DPJT_KEY = P_DPJT_KEY AND A.USER_ID = J.V_USER_ID AND A.DPJT_AUTH_TYPE = J.V_AUTH_TYPE);
    V_INS_CNT := SQL%ROWCOUNT;

    COMMIT;
    OPEN O_RESULT_CURSOR FOR
      SELECT '0' AS CODE, 'SUCCESS' AS MSG, TO_CHAR(V_INS_CNT + V_DEL_CNT) AS EVENT FROM DUAL;
  EXCEPTION
    WHEN OTHERS THEN
      ROLLBACK;
      DECLARE V_ERR VARCHAR2(4000) := SUBSTR(SQLERRM, 1, 4000);
      BEGIN
        P_LOG_ERR($$PLSQL_UNIT || '.SAVE_POP_AUTH', JSON_OBJECT('p_dpjt_key' VALUE P_DPJT_KEY, 'p_ses_user_id' VALUE P_SES_USER_ID));
        OPEN O_RESULT_CURSOR FOR SELECT '-1' AS CODE, V_ERR AS MSG, '0' AS EVENT FROM DUAL;
      END;
  END P_SDM1010_SAVE_POP_PJT_AUTH_MGMT;

  /* ------------------------------- 팝업 OK: 권한요청 처리 저장 (승인/반려 확정) */
  PROCEDURE P_SDM1010_SAVE_POP_PJT_AUTH_REQ (
      P_SES_USER_ID       IN VARCHAR2,
      P_DPJT_KEY          IN VARCHAR2,
      P_DATA              IN CLOB,
      O_RESULT_CURSOR     OUT SYS_REFCURSOR)
  AS
    V_CNT NUMBER := 0;
  BEGIN
    -- 요청 상태 확정 (P-21/P-22 — OK 시점 일괄)
    MERGE INTO SCM_MGR.SDM_MST_DPJT_AUTH_REQ_M T
    USING ( SELECT TO_NUMBER(J.V_REQ_SEQ) AS REQ_SEQ, J.V_REQ_STATUS
              FROM JSON_TABLE(P_DATA, '$[*]' COLUMNS (
                     V_REQ_SEQ    VARCHAR2(20) PATH '$.REQ_SEQ',
                     V_REQ_STATUS VARCHAR2(20) PATH '$.REQ_STATUS')) J
             WHERE J.V_REQ_STATUS IN ('APPROVE','REJECT') ) S
    ON (T.DPJT_KEY = P_DPJT_KEY AND T.REQ_SEQ = S.REQ_SEQ)
    WHEN MATCHED THEN UPDATE
       SET T.REQ_STATUS = S.V_REQ_STATUS,
           T.PROC_USER_ID = P_SES_USER_ID, T.PROC_DATE = SYSDATE,
           T.LAST_UPDATED_BY = P_SES_USER_ID, T.LAST_UPDATE_DATE = SYSDATE
     WHERE T.REQ_STATUS = 'REQUEST';  -- ORA-38104: ON 절 참조 컬럼 갱신 불가 → WHERE 이동 [E20260813-MERGEON]
    V_CNT := SQL%ROWCOUNT;

    -- 승인분 → 권한 리스트 반영 (P-21, 멱등)
    INSERT INTO SCM_MGR.SDM_MST_DPJT_AUTH_M
        (DPJT_KEY, USER_ID, DPJT_AUTH_TYPE, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
    SELECT Q.DPJT_KEY, Q.USER_ID, Q.REQ_AUTH_TYPE, P_SES_USER_ID, SYSDATE, P_SES_USER_ID, SYSDATE
      FROM SCM_MGR.SDM_MST_DPJT_AUTH_REQ_M Q
     WHERE Q.DPJT_KEY = P_DPJT_KEY AND Q.REQ_STATUS = 'APPROVE'
       AND NOT EXISTS (SELECT 1 FROM SCM_MGR.SDM_MST_DPJT_AUTH_M A
                        WHERE A.DPJT_KEY = Q.DPJT_KEY AND A.USER_ID = Q.USER_ID AND A.DPJT_AUTH_TYPE = Q.REQ_AUTH_TYPE);

    COMMIT;
    OPEN O_RESULT_CURSOR FOR SELECT '0' AS CODE, 'SUCCESS' AS MSG, TO_CHAR(V_CNT) AS EVENT FROM DUAL;
  EXCEPTION
    WHEN OTHERS THEN
