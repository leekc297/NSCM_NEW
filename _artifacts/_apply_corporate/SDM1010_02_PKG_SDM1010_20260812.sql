  /* ---------------------------------------------------------------- 공통 */
  FUNCTION F_IS_ADMIN (P_USER_ID IN VARCHAR2) RETURN NUMBER IS
    V_CNT NUMBER;
  BEGIN
    -- hook #128: 권한 = USER_ID 기준 보유 그룹 합집합 (전달 그룹 단독 판정 금지)
    SELECT COUNT(*) INTO V_CNT
      FROM SCM_MGR.SCM_ADM_USER_GR_MPG_M
     WHERE USER_ID = P_USER_ID AND USE_YN = 'Y'
       AND USER_GR_ID IN ('ADMIN', 'SPMS Administrator');
    RETURN V_CNT;
  END F_IS_ADMIN;

  PROCEDURE P_LOG_ERR (P_UNIT IN VARCHAR2, P_INPUT IN VARCHAR2) IS
    PRAGMA AUTONOMOUS_TRANSACTION;
    V_SQL_CODE   VARCHAR2(100)  := TO_CHAR(SQLCODE);
    V_SQL_ERRMSG VARCHAR2(1000) := SUBSTR(SQLERRM, 1, 1000);
    V_BACKTRACE  VARCHAR2(4000) := SUBSTR(DBMS_UTILITY.FORMAT_ERROR_BACKTRACE, 1, 4000);
  BEGIN
    PR_SCM_SYS_LOG_BATCH(P_UNIT, 'E', 0, 'EXCEPTION', NULL, SYSDATE, P_INPUT,
                         V_SQL_CODE, V_SQL_ERRMSG, V_BACKTRACE);
    COMMIT;
  EXCEPTION WHEN OTHERS THEN NULL;
  END P_LOG_ERR;

  /* ------------------------------------------------- TAB1 프로젝트 등록 조회 */
  PROCEDURE P_SDM1010_GET_TAB1_PJT_REG (
      P_DIVISION_ID       IN VARCHAR2,
      P_END_CUSTOMER      IN VARCHAR2,
      P_DPJT_AUTH_TYPE    IN VARCHAR2,
      P_DPJT_REG_STATUS   IN VARCHAR2,
      P_REG_COMP_DATE_FR  IN VARCHAR2,
      P_REG_COMP_DATE_TO  IN VARCHAR2,
      P_USER_ID           IN VARCHAR2,
      P_MENU_ID           IN VARCHAR2,
      P_USER_GR_ID        IN VARCHAR2,
      O_RC1               OUT SYS_REFCURSOR,
      O_RESULT_CURSOR     OUT SYS_REFCURSOR)
  AS
    V_IS_ADMIN NUMBER := F_IS_ADMIN(P_USER_ID);
  BEGIN
    OPEN O_RC1 FOR
      SELECT M.DPJT_KEY,
             M.DPJT_CODE,
             M.DIVISION_ID,
             NVL(DV.DIVISION_NAME, M.DIVISION_ID)                          AS DIVISION_NAME,
             M.DPJT_CLASS,
             NVL(LC.SEGMENT2, M.DPJT_CLASS)                                AS DPJT_CLASS_NAME,
             M.END_CUSTOMER,
             M.DPJT_NAME,
             M.CELL_TYPE,
             NVL(LT.SEGMENT2, M.CELL_TYPE)                                 AS CELL_TYPE_NAME,
             M.STACK_METHOD,
             NVL(LS.SEGMENT2, M.STACK_METHOD)                              AS STACK_METHOD_NAME,
             M.BIZ_TYPE,
             NVL(BZ.BIZ_TYPE_NAME, M.BIZ_TYPE)                             AS BIZ_TYPE_NAME,
             M.SOP_DATE,
             M.SOP_PLANT_ID,
             M.SOP_PLANT_ID                                                AS SOP_PLANT_NAME,
             '권한등록'                                                    AS DPJT_AUTH_REG_STR,
             CASE WHEN EXISTS (SELECT 1 FROM SCM_MGR.SDM_MST_DPJT_AUTH_REQ_M Q
                                WHERE Q.DPJT_KEY = M.DPJT_KEY AND Q.REQ_STATUS = 'REQUEST') THEN '승인대기'
                  WHEN EXISTS (SELECT 1 FROM SCM_MGR.SDM_MST_DPJT_AUTH_M A
                                WHERE A.DPJT_KEY = M.DPJT_KEY AND A.DPJT_AUTH_TYPE IN ('I','R')) THEN '완료'
                  ELSE '작성중'
             END                                                           AS DPJT_AUTH_REG_STATUS,
             M.DEPT_ID,
             NVL(DP.DEPT_NAME_KO, M.DEPT_ID)                               AS DEPT_NAME,
             M.MGMT_USER_ID,
             NVL(SU.USER_NAME, M.MGMT_USER_ID)                             AS USER_NAME,
             M.DPJT_REG_STATUS,
             NVL(LR.SEGMENT2, M.DPJT_REG_STATUS)                           AS DPJT_REG_STATUS_NAME,
             M.PROJECT_REG_REQ_DATE
        FROM SCM_MGR.SDM_MST_DPJT_M M
        LEFT JOIN SCM_MGR.SCM_MST_DIVISION DV ON DV.DIVISION_ID = M.DIVISION_ID
        LEFT JOIN SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL LC
               ON LC.LOOKUP_TYPE = 'SPMS_DPJT_CLASS' AND LC.SEGMENT1 = M.DPJT_CLASS AND LC.VALID_YN = 'Y'
        LEFT JOIN SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL LT
               ON LT.LOOKUP_TYPE = 'SPMS_CELL_TYPE' AND LT.SEGMENT1 = M.CELL_TYPE AND LT.VALID_YN = 'Y'
        LEFT JOIN SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL LS
               ON LS.LOOKUP_TYPE = 'SPMS_STACK_METHOD' AND LS.SEGMENT1 = M.STACK_METHOD AND LS.VALID_YN = 'Y'
        LEFT JOIN SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL LR
               ON LR.LOOKUP_TYPE = 'SPMS_DPJT_REG_STATUS' AND LR.SEGMENT1 = M.DPJT_REG_STATUS AND LR.VALID_YN = 'Y'
        LEFT JOIN (SELECT BIZ_TYPE, MAX(BIZ_TYPE_NAME) AS BIZ_TYPE_NAME
                     FROM SCM_MGR.SCM_MST_PROJECT WHERE BIZ_TYPE IS NOT NULL GROUP BY BIZ_TYPE) BZ
               ON BZ.BIZ_TYPE = M.BIZ_TYPE
        LEFT JOIN SCM_MGR.SCM_MST_SSO_DEPT_INFO DP ON DP.DEPT_ID = M.DEPT_ID
        LEFT JOIN SCM_MGR.SCM_MST_SSO_USER_INFO SU ON SU.USER_ID = M.MGMT_USER_ID
       WHERE M.DIVISION_ID = P_DIVISION_ID
         AND ( NVL(TRIM(P_END_CUSTOMER),'ALL') = 'ALL'
               OR INSTR(',' || P_END_CUSTOMER || ',', ',' || M.END_CUSTOMER || ',') > 0 )
         AND ( NVL(TRIM(P_DPJT_REG_STATUS),'ALL') = 'ALL'
               OR INSTR(',' || P_DPJT_REG_STATUS || ',', ',' || M.DPJT_REG_STATUS || ',') > 0 )
         -- 등록 완료일: 완료 행은 구간 필터, 미완료(작성중 등) 행은 포함 (등록 화면 특성)
         AND ( M.REG_COMP_DATE IS NULL
               OR M.REG_COMP_DATE BETWEEN NVL(P_REG_COMP_DATE_FR,'00000101') AND NVL(P_REG_COMP_DATE_TO,'99991231') )
         -- 나의 권한 필터 (ALL=전체)
         AND ( NVL(TRIM(P_DPJT_AUTH_TYPE),'ALL') = 'ALL'
               OR ( INSTR(',' || P_DPJT_AUTH_TYPE || ',', ',M,') > 0 AND M.MGMT_USER_ID = P_USER_ID )
               OR EXISTS (SELECT 1 FROM SCM_MGR.SDM_MST_DPJT_AUTH_M A
                           WHERE A.DPJT_KEY = M.DPJT_KEY AND A.USER_ID = P_USER_ID
                             AND INSTR(',' || P_DPJT_AUTH_TYPE || ',', ',' || A.DPJT_AUTH_TYPE || ',') > 0) )
         -- 서버측 권한 필터: 관리자 그룹=Division 전체 / 그 외=본인 관련 프로젝트만
         AND ( V_IS_ADMIN > 0
               OR M.MGMT_USER_ID = P_USER_ID
               OR M.CREATED_BY = P_USER_ID
               OR EXISTS (SELECT 1 FROM SCM_MGR.SDM_MST_DPJT_AUTH_M A
                           WHERE A.DPJT_KEY = M.DPJT_KEY AND A.USER_ID = P_USER_ID) )
       ORDER BY M.CREATION_DATE DESC, M.DPJT_KEY;

    OPEN O_RESULT_CURSOR FOR SELECT '0' AS CODE, 'SUCCESS' AS MSG FROM DUAL;
  EXCEPTION
    WHEN OTHERS THEN
      DECLARE V_ERR VARCHAR2(4000) := SUBSTR(SQLERRM, 1, 4000);
      BEGIN
        P_LOG_ERR($$PLSQL_UNIT || '.GET_TAB1', JSON_OBJECT('p_division_id' VALUE P_DIVISION_ID, 'p_user_id' VALUE P_USER_ID));
        OPEN O_RC1 FOR SELECT NULL AS DUMMY FROM DUAL WHERE 1 = 0;
        OPEN O_RESULT_CURSOR FOR SELECT '-1' AS CODE, V_ERR AS MSG FROM DUAL;
      END;
  END P_SDM1010_GET_TAB1_PJT_REG;

  /* --------------------------------------------- TAB2 나의 프로젝트 현황 조회 */
  PROCEDURE P_SDM1010_GET_TAB2_PJT_LIST (
      P_DIVISION_ID       IN VARCHAR2,
      P_END_CUSTOMER      IN VARCHAR2,
      P_DPJT_AUTH_TYPE    IN VARCHAR2,
      P_DPJT_REG_STATUS   IN VARCHAR2,
      P_REG_COMP_DATE_FR  IN VARCHAR2,
      P_REG_COMP_DATE_TO  IN VARCHAR2,
      P_USER_ID           IN VARCHAR2,
      O_RC1               OUT SYS_REFCURSOR,
      O_RESULT_CURSOR     OUT SYS_REFCURSOR)
  AS
  BEGIN
    OPEN O_RC1 FOR
      WITH MY_AUTH AS (
        -- 본인 보유 권한 (관리자 M = 원장 MGMT_USER_ID, 우선순위 M > I > R)
        SELECT DPJT_KEY, MIN(AUTH_ORD) AS AUTH_ORD
          FROM ( SELECT M.DPJT_KEY, 1 AS AUTH_ORD
                   FROM SCM_MGR.SDM_MST_DPJT_M M WHERE M.MGMT_USER_ID = P_USER_ID
                 UNION ALL
                 SELECT A.DPJT_KEY, CASE A.DPJT_AUTH_TYPE WHEN 'M' THEN 1 WHEN 'I' THEN 2 ELSE 3 END
                   FROM SCM_MGR.SDM_MST_DPJT_AUTH_M A WHERE A.USER_ID = P_USER_ID )
         GROUP BY DPJT_KEY )
      SELECT M.DPJT_KEY,
             M.DPJT_CODE,
             ''                                                            AS MY_WORK,
             M.DIVISION_ID,
             NVL(DV.DIVISION_NAME, M.DIVISION_ID)                          AS DIVISION_NAME,
             M.DPJT_CLASS,
             NVL(LC.SEGMENT2, M.DPJT_CLASS)                                AS DPJT_CLASS_NAME,
             M.END_CUSTOMER,
             M.DPJT_NAME,
             M.CELL_TYPE,
             NVL(LT.SEGMENT2, M.CELL_TYPE)                                 AS CELL_TYPE_NAME,
             M.STACK_METHOD,
             NVL(LS.SEGMENT2, M.STACK_METHOD)                              AS STACK_METHOD_NAME,
             M.BIZ_TYPE,
             NVL(BZ.BIZ_TYPE_NAME, M.BIZ_TYPE)                             AS BIZ_TYPE_NAME,
             M.SOP_DATE,
             M.SOP_PLANT_ID,
             M.SOP_PLANT_ID                                                AS SOP_PLANT_NAME,
             M.DEPT_ID,
             NVL(DP.DEPT_NAME_KO, M.DEPT_ID)                               AS DEPT_NAME,
             M.MGMT_USER_ID,
             NVL(SU.USER_NAME, M.MGMT_USER_ID)                             AS USER_NAME,
             CASE MA.AUTH_ORD WHEN 1 THEN 'M' WHEN 2 THEN 'I' ELSE 'R' END AS DPJT_AUTH_TYPE,
             NVL(LA.SEGMENT2,
                 CASE MA.AUTH_ORD WHEN 1 THEN 'M' WHEN 2 THEN 'I' ELSE 'R' END) AS DPJT_AUTH_TYPE_NAME,
             M.DPJT_REG_STATUS,
             NVL(LR.SEGMENT2, M.DPJT_REG_STATUS)                           AS DPJT_REG_STATUS_NAME,
             M.REG_COMP_DATE,
             M.DPJT_DEVELOP_STATUS,
             NVL(M.DPJT_DEVELOP_STATUS, '')                                AS DPJT_DEVELOP_STATUS_NAME
        FROM SCM_MGR.SDM_MST_DPJT_M M
        JOIN MY_AUTH MA ON MA.DPJT_KEY = M.DPJT_KEY
        LEFT JOIN SCM_MGR.SCM_MST_DIVISION DV ON DV.DIVISION_ID = M.DIVISION_ID
        LEFT JOIN SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL LC
               ON LC.LOOKUP_TYPE = 'SPMS_DPJT_CLASS' AND LC.SEGMENT1 = M.DPJT_CLASS AND LC.VALID_YN = 'Y'
        LEFT JOIN SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL LT
               ON LT.LOOKUP_TYPE = 'SPMS_CELL_TYPE' AND LT.SEGMENT1 = M.CELL_TYPE AND LT.VALID_YN = 'Y'
        LEFT JOIN SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL LS
               ON LS.LOOKUP_TYPE = 'SPMS_STACK_METHOD' AND LS.SEGMENT1 = M.STACK_METHOD AND LS.VALID_YN = 'Y'
        LEFT JOIN SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL LR
               ON LR.LOOKUP_TYPE = 'SPMS_DPJT_REG_STATUS' AND LR.SEGMENT1 = M.DPJT_REG_STATUS AND LR.VALID_YN = 'Y'
        LEFT JOIN SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL LA
               ON LA.LOOKUP_TYPE = 'SPMS_DPJT_AUTH_TYPE' AND LA.VALID_YN = 'Y'
              AND LA.SEGMENT1 = CASE MA.AUTH_ORD WHEN 1 THEN 'M' WHEN 2 THEN 'I' ELSE 'R' END
        LEFT JOIN (SELECT BIZ_TYPE, MAX(BIZ_TYPE_NAME) AS BIZ_TYPE_NAME
                     FROM SCM_MGR.SCM_MST_PROJECT WHERE BIZ_TYPE IS NOT NULL GROUP BY BIZ_TYPE) BZ
               ON BZ.BIZ_TYPE = M.BIZ_TYPE
        LEFT JOIN SCM_MGR.SCM_MST_SSO_DEPT_INFO DP ON DP.DEPT_ID = M.DEPT_ID
        LEFT JOIN SCM_MGR.SCM_MST_SSO_USER_INFO SU ON SU.USER_ID = M.MGMT_USER_ID
       WHERE M.DIVISION_ID = P_DIVISION_ID
         AND ( NVL(TRIM(P_END_CUSTOMER),'ALL') = 'ALL'
               OR INSTR(',' || P_END_CUSTOMER || ',', ',' || M.END_CUSTOMER || ',') > 0 )
         AND ( NVL(TRIM(P_DPJT_REG_STATUS),'ALL') = 'ALL'
               OR INSTR(',' || P_DPJT_REG_STATUS || ',', ',' || M.DPJT_REG_STATUS || ',') > 0 )
         AND ( M.REG_COMP_DATE IS NULL
               OR M.REG_COMP_DATE BETWEEN NVL(P_REG_COMP_DATE_FR,'00000101') AND NVL(P_REG_COMP_DATE_TO,'99991231') )
         AND ( NVL(TRIM(P_DPJT_AUTH_TYPE),'ALL') = 'ALL'
               OR INSTR(',' || P_DPJT_AUTH_TYPE || ',',
                        ',' || CASE MA.AUTH_ORD WHEN 1 THEN 'M' WHEN 2 THEN 'I' ELSE 'R' END || ',') > 0 )
       ORDER BY M.CREATION_DATE DESC, M.DPJT_KEY;

    OPEN O_RESULT_CURSOR FOR SELECT '0' AS CODE, 'SUCCESS' AS MSG FROM DUAL;
  EXCEPTION
    WHEN OTHERS THEN
      DECLARE V_ERR VARCHAR2(4000) := SUBSTR(SQLERRM, 1, 4000);
      BEGIN
        P_LOG_ERR($$PLSQL_UNIT || '.GET_TAB2', JSON_OBJECT('p_division_id' VALUE P_DIVISION_ID, 'p_user_id' VALUE P_USER_ID));
        OPEN O_RC1 FOR SELECT NULL AS DUMMY FROM DUAL WHERE 1 = 0;
        OPEN O_RESULT_CURSOR FOR SELECT '-1' AS CODE, V_ERR AS MSG FROM DUAL;
      END;
  END P_SDM1010_GET_TAB2_PJT_LIST;

  /* ------------------------------------------------------ TAB1 저장 (I/M/D) */
  PROCEDURE P_SDM1010_SAVE_TAB1_PJT_REG (
      P_SES_USER_ID       IN VARCHAR2,
      P_DATA              IN CLOB,
      O_RESULT_CURSOR     OUT SYS_REFCURSOR)
  AS
    V_REQUIRED_CNT NUMBER := 0;
    V_DUP_LIST     VARCHAR2(2000);
    V_INSERT_CNT   NUMBER := 0;
    V_UPDATE_CNT   NUMBER := 0;
    V_DELETE_CNT   NUMBER := 0;
    V_DEPT_ID      VARCHAR2(30);
  BEGIN
    -- [가드 1] 필수값: Project Class / Customer / Project Name (P-04, MSG00113)
    SELECT COUNT(*) INTO V_REQUIRED_CNT
      FROM JSON_TABLE(P_DATA, '$[*]' COLUMNS (
             V_CRUD_TYPE  VARCHAR2(1)   PATH '$.CRUD_TYPE',
             V_CLASS      VARCHAR2(30)  PATH '$.DPJT_CLASS',
             V_CUSTOMER   VARCHAR2(100) PATH '$.END_CUSTOMER',
             V_NAME       VARCHAR2(200) PATH '$.DPJT_NAME'))
     WHERE V_CRUD_TYPE IN ('I','M')
       AND (V_CLASS IS NULL OR V_CUSTOMER IS NULL OR V_NAME IS NULL);
    IF V_REQUIRED_CNT > 0 THEN
      OPEN O_RESULT_CURSOR FOR SELECT '-1' AS CODE, 'REQUIRED' AS MSG, TO_CHAR(V_REQUIRED_CNT) AS EVENT FROM DUAL;
      RETURN;
    END IF;

    -- [가드 2] 중복: 논리키 DIVISION+CLASS+CUSTOMER+NAME (P-05, 정오표 #9 — payload 내부 + 원장 대조)
    SELECT SUBSTR(LISTAGG(DUP_NAME, ',') WITHIN GROUP (ORDER BY DUP_NAME), 1, 2000) INTO V_DUP_LIST
      FROM (
        SELECT J.V_NAME AS DUP_NAME
          FROM JSON_TABLE(P_DATA, '$[*]' COLUMNS (
                 V_CRUD_TYPE  VARCHAR2(1)   PATH '$.CRUD_TYPE',
                 V_DPJT_KEY   VARCHAR2(50)  PATH '$.DPJT_KEY',
                 V_DIVISION   VARCHAR2(10)  PATH '$.DIVISION_ID',
                 V_CLASS      VARCHAR2(30)  PATH '$.DPJT_CLASS',
                 V_CUSTOMER   VARCHAR2(100) PATH '$.END_CUSTOMER',
                 V_NAME       VARCHAR2(200) PATH '$.DPJT_NAME')) J
         WHERE J.V_CRUD_TYPE IN ('I','M')
         GROUP BY J.V_DIVISION, J.V_CLASS, J.V_CUSTOMER, J.V_NAME
        HAVING COUNT(*) > 1
        UNION
        SELECT J.V_NAME
          FROM JSON_TABLE(P_DATA, '$[*]' COLUMNS (
                 V_CRUD_TYPE  VARCHAR2(1)   PATH '$.CRUD_TYPE',
                 V_DPJT_KEY   VARCHAR2(50)  PATH '$.DPJT_KEY',
                 V_DIVISION   VARCHAR2(10)  PATH '$.DIVISION_ID',
                 V_CLASS      VARCHAR2(30)  PATH '$.DPJT_CLASS',
                 V_CUSTOMER   VARCHAR2(100) PATH '$.END_CUSTOMER',
                 V_NAME       VARCHAR2(200) PATH '$.DPJT_NAME')) J
          JOIN SCM_MGR.SDM_MST_DPJT_M M
            ON M.DIVISION_ID = J.V_DIVISION
           AND NVL(M.DPJT_CLASS,'-') = NVL(J.V_CLASS,'-')
           AND NVL(M.END_CUSTOMER,'-') = NVL(J.V_CUSTOMER,'-')
           AND M.DPJT_NAME = J.V_NAME
           AND M.DPJT_KEY <> NVL(J.V_DPJT_KEY, '-')
         WHERE J.V_CRUD_TYPE IN ('I','M') );
    IF V_DUP_LIST IS NOT NULL THEN
      OPEN O_RESULT_CURSOR FOR SELECT '-1' AS CODE, 'DUPLICATE:' || V_DUP_LIST AS MSG, '0' AS EVENT FROM DUAL;
      RETURN;
    END IF;

    -- 세션 사용자 부서 (프로젝트 관리자 = 등록자)
    BEGIN
      SELECT DEPT_ID INTO V_DEPT_ID FROM SCM_MGR.SCM_MST_SSO_USER_INFO WHERE USER_ID = P_SES_USER_ID AND ROWNUM = 1;
    EXCEPTION WHEN NO_DATA_FOUND THEN V_DEPT_ID := NULL;
    END;

    -- INSERT (CRUD_TYPE='I') — 상태 DRAFT, DPJT_KEY/CODE 채번(채번 규칙 미정의 — 정오표 부기)
    INSERT INTO SCM_MGR.SDM_MST_DPJT_M
        (DPJT_KEY, DPJT_CODE, DIVISION_ID, DPJT_CLASS, END_CUSTOMER, DPJT_NAME,
         CELL_TYPE, STACK_METHOD, BIZ_TYPE, SOP_DATE, SOP_PLANT_ID,
         SAMPLE_A_DATE, SAMPLE_B_DATE, SAMPLE_C_DATE, SAMPLE_D_DATE,
         DEPT_ID, MGMT_USER_ID, DPJT_REG_STATUS,
