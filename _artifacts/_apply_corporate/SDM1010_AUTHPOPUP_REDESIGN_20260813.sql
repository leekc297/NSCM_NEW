-- [1] PROC_M — GET_POP_USER_BY_DEPT (deptId, userName IN + data/result OUT)
DELETE FROM SCM_MGR.SCM_ADM_PROC_M WHERE PROC_NM = 'PKG_SDM1010.P_SDM1010_GET_POP_USER_BY_DEPT';
INSERT INTO SCM_MGR.SCM_ADM_PROC_M (PROC_NM, COL_NM, COL_TP_CD, DATA_TP_CD, SORT_ORD, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT T.PN, T.CN, T.IO, T.DT, T.SO, 'admin', SYSDATE, 'admin', SYSDATE
  FROM (
    SELECT 'PKG_SDM1010.P_SDM1010_GET_POP_USER_BY_DEPT' PN, 'deptId' CN, 'IN' IO, 'VARCHAR' DT, 1 SO FROM DUAL
    UNION ALL
    SELECT 'PKG_SDM1010.P_SDM1010_GET_POP_USER_BY_DEPT' PN, 'userName' CN, 'IN' IO, 'VARCHAR' DT, 2 SO FROM DUAL
    UNION ALL
    SELECT 'PKG_SDM1010.P_SDM1010_GET_POP_USER_BY_DEPT' PN, 'data' CN, 'OUT' IO, 'CURSOR' DT, 3 SO FROM DUAL
    UNION ALL
    SELECT 'PKG_SDM1010.P_SDM1010_GET_POP_USER_BY_DEPT' PN, 'result' CN, 'OUT' IO, 'PROC_RESULT' DT, 4 SO FROM DUAL
  ) T;

