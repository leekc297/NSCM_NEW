-- 90_DIAG_DMF0049_SAVE_CLOUD.sql — 클라우드 DMF0049 저장 오류 진단 (2026-08-12)
-- 클라우드 QA/DEV 각각 실행 후 결과 전체 회신 요청. (오늘 적용한 DS2 BODY 2본과 직결된 축 우선)

-- [1] PKG 컴파일 상태 — 기대: 0044/0049 모두 PACKAGE/BODY VALID
--     INVALID = 저장 호출 시 ORA-04063 (DS2 BODY 적용 시 컴파일 실패가 최유력 후보)
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS, LAST_DDL_TIME
  FROM ALL_OBJECTS
 WHERE OWNER='SCM_MGR' AND OBJECT_NAME IN ('PKG_DMF0049','PKG_DMF0044')
 ORDER BY OBJECT_NAME, OBJECT_TYPE;

-- [2] 컴파일 오류 원문 — 기대: 0행 (있으면 부재 객체/라인이 그대로 보임)
SELECT NAME, LINE, POSITION, TEXT
  FROM ALL_ERRORS
 WHERE OWNER='SCM_MGR' AND NAME IN ('PKG_DMF0049','PKG_DMF0044')
 ORDER BY NAME, SEQUENCE;

-- [3] BODY 참조 객체 중 클라우드 부재분 — 기대: 0행 (사내 재덤프본의 사내 전용 참조 검출)
SELECT d.NAME, d.REFERENCED_NAME, d.REFERENCED_TYPE
  FROM ALL_DEPENDENCIES d
 WHERE d.OWNER='SCM_MGR' AND d.NAME IN ('PKG_DMF0049','PKG_DMF0044') AND d.TYPE='PACKAGE BODY'
   AND d.REFERENCED_OWNER='SCM_MGR'
   AND NOT EXISTS (SELECT 1 FROM ALL_OBJECTS o
                    WHERE o.OWNER=d.REFERENCED_OWNER AND o.OBJECT_NAME=d.REFERENCED_NAME)
 ORDER BY 1, 2;

-- [4] DS2 적용 확인 — 기대: 0049 = 2 / 0044 = 10(기존 1 포함)
SELECT NAME, COUNT(*) AS DS2_CNT FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME IN ('PKG_DMF0049','PKG_DMF0044') AND TYPE='PACKAGE BODY'
   AND UPPER(TEXT) LIKE '%OPTIMIZER_DYNAMIC_SAMPLING = 2%'
 GROUP BY NAME;

-- [5] 저장 경로 GTT 자급 — 기대: 0행(부재 GTT 없음)
SELECT d.REFERENCED_NAME
  FROM ALL_DEPENDENCIES d
 WHERE d.OWNER='SCM_MGR' AND d.NAME IN ('PKG_DMF0049','PKG_DMF0044') AND d.TYPE='PACKAGE BODY'
   AND d.REFERENCED_TYPE='TABLE'
   AND (d.REFERENCED_NAME LIKE 'GT!_%' ESCAPE '!' OR d.REFERENCED_NAME LIKE 'GTT%')
   AND NOT EXISTS (SELECT 1 FROM ALL_TABLES t WHERE t.OWNER='SCM_MGR' AND t.TABLE_NAME=d.REFERENCED_NAME);

-- [6] UI 계정 실행 권한 — 기대: 두 PKG 모두 EXECUTE
SELECT TABLE_NAME, PRIVILEGE FROM DBA_TAB_PRIVS
 WHERE GRANTEE='SCMP_APP' AND OWNER='SCM_MGR' AND TABLE_NAME IN ('PKG_DMF0049','PKG_DMF0044');

