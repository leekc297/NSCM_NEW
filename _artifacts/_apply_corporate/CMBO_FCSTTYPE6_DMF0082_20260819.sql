-- CMBO_FCSTTYPE6_DMF0082_20260819.sql — [E20260819-FCSTTYPE6] DMF0082 신규 행 FCST Type 콤보 보완
--   사용자 지시(2026-08-19 통합테스트): ①40 Div 는 W/S(Chargable)/W/S(Free) 미표시
--   ②기준 = SALES_TYPE_CODE 에서 전용플래그 'Y' 2건 제외 전 항목(실측: ATTRIBUTE2='Y' = WS/WSF 2건 유일)
--   ③SALES_TYPE_CODE2·SALES_TYPE_CODE2_ADD 는 81·81_Div 의 'DM Planner (W/S)' 권한일 경우에만.
--   기존 [E20260814-WSDIV] 상호배타 UNION ALL 구조가 ①②③ 골격 기충족 — 격차는 W/S 분기의
--   SALES_TYPE_CODE2_ADD(Recall/RMA) 누락(4종→6종, AS-IS DMF0003 FcstTypeEditMode 동형)뿐이라 그 확장.
--   소비자 실측: 두 콤보 모두 DMF0082 전용(SCM_MST_SHEET_COLUMNS FcstNPrice/FCST_TYPE + forecast-price FE 1곳).
--   백업: CMBO_FCSTTYPE6_DMF0082_20260819_BACKUP.sql

UPDATE SCM_MGR.SCM_ADM_CMBO_SQL_M
SET    SQL_DTL_CTN = q'{SELECT CODE, NAME, DISPLAY_SEQ FROM (
  /* [E20260814-WSDIV → E20260819-FCSTTYPE6] 81 계열 + DM Planner(W/S)
     → SALES_TYPE_CODE2 ∪ SALES_TYPE_CODE2_ADD 6종 (2026-08-19 통합테스트 —
     AS-IS DMF0003 FcstTypeEditMode 동형. 구 4종엔 CODE2_ADD(Recall/RMA) 누락) */
  SELECT SEGMENT1 AS CODE, SEGMENT2 AS NAME
       , CASE LOOKUP_TYPE WHEN 'SALES_TYPE_CODE2' THEN DISPLAY_SEQ ELSE 100 + DISPLAY_SEQ END AS DISPLAY_SEQ
  FROM   SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
  WHERE  LOOKUP_TYPE IN ('SALES_TYPE_CODE2', 'SALES_TYPE_CODE2_ADD')
  AND    VALID_YN = 'Y'
  AND    NVL(TRIM(@divisionId), '-') LIKE '81%'
  AND    EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_USER_GR_MPG_M G
                 WHERE G.USER_ID = @sesUserId AND G.USER_GR_ID = 'DM Planner (W/S)' AND G.USE_YN = 'Y')
  UNION ALL
  /* division 전달 + W/S 자격 아님 → SALES_TYPE_CODE 에서 전용플래그(ATTRIBUTE2='Y' — 실측 WS/WSF 2건 유일) 제외 = 12종 */
  SELECT SEGMENT1 AS CODE, SEGMENT2 AS NAME, DISPLAY_SEQ
  FROM   SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
  WHERE  LOOKUP_TYPE = 'SALES_TYPE_CODE'
  AND    VALID_YN = 'Y'
  AND    NVL(ATTRIBUTE2, ' ') <> 'Y'
  AND    NVL(TRIM(@divisionId), '-') <> '-'
  AND    NOT ( NVL(TRIM(@divisionId), '-') LIKE '81%'
               AND EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_USER_GR_MPG_M G
                           WHERE G.USER_ID = @sesUserId AND G.USER_GR_ID = 'DM Planner (W/S)' AND G.USE_YN = 'Y') )
  UNION ALL
  /* division 미전달(메타 셀 콤보 = CODE->NAME 표시 매핑) → 전 코드 1행씩 (중복 없음) */
  SELECT SEGMENT1 AS CODE, SEGMENT2 AS NAME, DISPLAY_SEQ
  FROM   SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
  WHERE  LOOKUP_TYPE = 'SALES_TYPE_CODE'
  AND    VALID_YN = 'Y'
  AND    NVL(TRIM(@divisionId), '-') = '-'
) ORDER BY DISPLAY_SEQ, CODE}'
     , LAST_UPDATED_BY = 'admin', LAST_UPDATE_DATE = SYSDATE
WHERE  SQL_ID = 'FcstTypeByUserGroupDMF0082';

