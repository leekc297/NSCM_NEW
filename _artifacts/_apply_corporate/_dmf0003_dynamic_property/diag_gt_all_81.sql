DECLARE
  c1 SYS_REFCURSOR; c2 SYS_REFCURSOR; c3 SYS_REFCURSOR; c4 SYS_REFCURSOR;
  v_sm    PLS_INTEGER := 0;
  v_si    PLS_INTEGER := 0;
  v_isv   PLS_INTEGER := 0;
  v_data  PLS_INTEGER := 0;
  v_dst   PLS_INTEGER := 0;
BEGIN
  DMF0003_GET_MKT_FCST_DATA(
    '81', 'ALL','ALL','ALL','ALL','ALL','ALL','ALL',
    TO_CHAR(SYSDATE,'YYYYMMDD'), TO_CHAR(SYSDATE+90,'YYYYMMDD'),
    'minyonglee1', 'ADMIN', 'ALL','ALL','N','N','N','N','ALL','ALL',
    'minyonglee1','DMF0003',
    c1, c2, c3, c4);
  SELECT COUNT(*) INTO v_sm   FROM SCM_MGR.GT_GGET_SELECT_MEASURE;
  SELECT COUNT(*) INTO v_si   FROM SCM_MGR.GT_GGET_SITE_ITEM;
  SELECT COUNT(*) INTO v_isv  FROM SCM_MGR.GT_GGET_ITEM_SINGLE_V;
  SELECT COUNT(*) INTO v_data FROM SCM_MGR.GT_GGET_MKT_FCST_DATA;
  SELECT COUNT(*) INTO v_dst  FROM SCM_MGR.GT_GGET_MKT_FCST_DST;
  RAISE_APPLICATION_ERROR(-20999,
    'DIV=81 SELECT_MEASURE=' || v_sm || ' SITE_ITEM=' || v_si
    || ' ITEM_SINGLE_V=' || v_isv || ' MKT_DATA=' || v_data || ' MKT_DST=' || v_dst);
END;
