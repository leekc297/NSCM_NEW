--   자매 화면 DMF0020 표준: SHT_NM='titleSet' MNU_BTN_CD='SEARCH' API_URL='DMF0002_GET_TITLESET_POPUP' 공용 SP.
--   사내 DMF0003 에 동일 등록 (멱등 NOT EXISTS).

INSERT INTO SCM_ADM_API_M (API_ID, API_TP_CD, API_MSG_ID, API_MSG_DESC, API_URL, USE_YN,
                            CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'DMF0003_titleSet_SEARCH', 'PROC', 'MSG_API_DMF0003_MAIN_COLUMN_SETUP',
       'DMF0003 TitleSet (Column Setting) Search', 'DMF0002_GET_TITLESET_POPUP', 'Y',
       'admin', SYSDATE, 'admin', SYSDATE
  FROM DUAL
 WHERE NOT EXISTS (SELECT 1 FROM SCM_ADM_API_M WHERE API_ID = 'DMF0003_titleSet_SEARCH');

INSERT INTO SCM_ADM_MNU_BTN_MPG_M (MNU_ID, SHT_NM, MNU_BTN_CD, API_ID, USE_YN,
                                    CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'DMF0003', 'titleSet', 'SEARCH', 'DMF0003_titleSet_SEARCH', 'Y',
       'admin', SYSDATE, 'admin', SYSDATE
  FROM DUAL
 WHERE NOT EXISTS (
   SELECT 1 FROM SCM_ADM_MNU_BTN_MPG_M
    WHERE MNU_ID = 'DMF0003' AND SHT_NM = 'titleSet' AND MNU_BTN_CD = 'SEARCH'
 );

-- 권한 부여 (자매 DMF0020 의 titleSet 권한 동적 복사 + ADMIN/DEMAND_USER/GUEST fallback)
INSERT INTO SCM_ADM_USER_GR_MNU_BTN_MPG_M (USER_GR_ID, MNU_ID, SHT_NM, MNU_BTN_CD, USE_YN,
                                            CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT u.USER_GR_ID, 'DMF0003', 'titleSet', 'SEARCH', 'Y',
       'admin', SYSDATE, 'admin', SYSDATE
  FROM (SELECT 'ADMIN' USER_GR_ID FROM DUAL UNION ALL
        SELECT 'DEMAND_USER'      FROM DUAL UNION ALL
        SELECT 'GUEST'            FROM DUAL) u
 WHERE NOT EXISTS (
   SELECT 1 FROM SCM_ADM_USER_GR_MNU_BTN_MPG_M e
    WHERE e.USER_GR_ID = u.USER_GR_ID AND e.MNU_ID = 'DMF0003'
      AND e.SHT_NM = 'titleSet' AND e.MNU_BTN_CD = 'SEARCH'
 );

COMMIT;
