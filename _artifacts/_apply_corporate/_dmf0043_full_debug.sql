DECLARE
  v_rc1 SYS_REFCURSOR;
  v_rc2 SYS_REFCURSOR;
  v_before NUMBER;
  v_after NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_before FROM DM_MST_CONTRIBUTE_VER;
  DBMS_OUTPUT.PUT_LINE('  BEFORE total: ' || v_before);

  DMF0043_SAVE_DM_MST_CONTRIBUTE_VER('I','','2028','TEST_2028_FIX','','Y','minyonglee1',v_rc1,v_rc2);

  IF v_rc1 IS NOT NULL THEN CLOSE v_rc1; END IF;
  IF v_rc2 IS NOT NULL THEN CLOSE v_rc2; END IF;
  COMMIT;
  DBMS_OUTPUT.PUT_LINE('  COMMIT OK');

  SELECT COUNT(*) INTO v_after FROM DM_MST_CONTRIBUTE_VER;
  DBMS_OUTPUT.PUT_LINE('  AFTER total: ' || v_after || '  (delta ' || (v_after - v_before) || ')');
END;
