-- =====================================================================
-- DMF0003 MKT Forecast — 편집 가능 Division 등록 (사용자 지시 2026-07-11)
-- 규칙: 40/81 = 수정불가(EDIT_YN='N', 기존 유지) / 82 = 수정가능(EDIT_YN='Y', 신규)
-- 구조: SCM_ADM_LOOKUP_MASTER_DETAIL.ATTRIBUTE1 = EDIT_YN (소비 SP UP_FX_GETCOMMONDATALIST_DM L553)
--       현재 DMF0003 에 (40,'N')·(81,'N') 존재, (82) 행 없음 → 82 행만 신규 INSERT.
-- 불가침: WHERE SEGMENT1='DMF0003' 강제 — DMF0020 / DMF0082 행 절대 미변경.
-- 멱등: NOT EXISTS 가드 (재실행 안전).
-- =====================================================================

INSERT INTO SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
  (LOOKUP_TYPE, SEGMENT1, SEGMENT2, SEGMENT3, SEGMENT4, SEGMENT5,
   ATTRIBUTE1, VALID_YN, DISPLAY_SEQ, DESCRIPTION,
   CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'DM_UI_EDITABLE_DIVISION', 'DMF0003', '82', '-', '-', '-',
       'Y', 'Y', 300, 'MKT FCST',
       'admin', SYSDATE, 'admin', SYSDATE
FROM DUAL
WHERE NOT EXISTS (
  SELECT 1 FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
  WHERE LOOKUP_TYPE = 'DM_UI_EDITABLE_DIVISION'
  AND   SEGMENT1 = 'DMF0003'
  AND   SEGMENT2 = '82'
);

COMMIT;

