-- [3] Lookup 5종 (SCM_ADM_LOOKUP_MASTER / _DETAIL — SEGMENT1=CODE, SEGMENT2=NAME) -----
-- 설계서 명시 2종(SPMS_DPJT_AUTH_TYPE / SPMS_DPJT_REG_STATUS) + 그리드 콤보 원천 3종
-- SEGMENT1~5 = NOT NULL — 센티널 '-' (hook #119 규약, desc 실측 2026-08-12)
INSERT INTO SCM_MGR.SCM_ADM_LOOKUP_MASTER (LOOKUP_TYPE, DESCRIPTION, LOOKUP_GROUP, VALID_YN, SEGMENT1, SEGMENT2, SEGMENT3, SEGMENT4, SEGMENT5, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT T.LT, T.DS, 'SDM', 'Y', '-', '-', '-', '-', '-', 'admin', SYSDATE, 'admin', SYSDATE
  FROM (SELECT 'SPMS_DPJT_AUTH_TYPE'  AS LT, 'SDM1010 프로젝트 권한 유형'  AS DS FROM DUAL UNION ALL
        SELECT 'SPMS_DPJT_REG_STATUS', 'SDM1010 프로젝트 등록 상태' FROM DUAL UNION ALL
        SELECT 'SPMS_DPJT_CLASS',      'SDM1010 프로젝트 유형' FROM DUAL UNION ALL
        SELECT 'SPMS_CELL_TYPE',       'SDM1010 셀 유형 (Division 스코프=ATTRIBUTE1)' FROM DUAL UNION ALL
        SELECT 'SPMS_STACK_METHOD',    'SDM1010 Stack 공법' FROM DUAL) T
 WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER X WHERE X.LOOKUP_TYPE = T.LT);

INSERT INTO SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL (LOOKUP_TYPE, SEGMENT1, SEGMENT2, SEGMENT3, SEGMENT4, SEGMENT5, DISPLAY_SEQ, VALID_YN, DESCRIPTION, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE, ATTRIBUTE1)
SELECT T.LT, T.S1, T.S2, '-', '-', '-', T.SEQ, 'Y', T.DS, 'admin', SYSDATE, 'admin', SYSDATE, T.A1
  FROM (
    -- 권한 유형 (TAB2 나의 권한 콤보·팝업 TAG)
    SELECT 'SPMS_DPJT_AUTH_TYPE' AS LT, 'M' AS S1, '관리자'   AS S2, 10 AS SEQ, '프로젝트 관리자' AS DS, NULL AS A1 FROM DUAL UNION ALL
    SELECT 'SPMS_DPJT_AUTH_TYPE', 'I', '입력 권한', 20, '입력 권한', NULL FROM DUAL UNION ALL
    SELECT 'SPMS_DPJT_AUTH_TYPE', 'R', '조회 권한', 30, '조회 권한', NULL FROM DUAL UNION ALL
    -- 등록 상태 (상태머신 6종 — TAB1_GRID 범례)
    SELECT 'SPMS_DPJT_REG_STATUS', 'DRAFT',       '작성중',   10, '작성중', NULL FROM DUAL UNION ALL
    SELECT 'SPMS_DPJT_REG_STATUS', 'REQUEST',     '승인대기', 20, '등록요청 후 승인대기', NULL FROM DUAL UNION ALL
    SELECT 'SPMS_DPJT_REG_STATUS', 'COMPLETE',    '등록완료', 30, '등록완료', NULL FROM DUAL UNION ALL
    SELECT 'SPMS_DPJT_REG_STATUS', 'REJECT',      '반려',     40, '반려', NULL FROM DUAL UNION ALL
    SELECT 'SPMS_DPJT_REG_STATUS', 'CHG_DRAFT',   '변경등록', 50, '변경등록 (후속 설계 — 정오표 #12)', NULL FROM DUAL UNION ALL
    SELECT 'SPMS_DPJT_REG_STATUS', 'CHG_REQUEST', '변경요청', 60, '변경요청 (후속 설계 — 정오표 #12)', NULL FROM DUAL UNION ALL
    -- 프로젝트 유형 (DpjtClass 콤보 — 목업: 개발/제품검증)
    SELECT 'SPMS_DPJT_CLASS', 'DEV', '개발',     10, '개발', NULL FROM DUAL UNION ALL
    SELECT 'SPMS_DPJT_CLASS', 'VRF', '제품검증', 20, '제품검증', NULL FROM DUAL UNION ALL
    -- 셀 유형 (CellTypeByDivision 콤보 — 목업: 파우치/각형. ATTRIBUTE1=Division 스코프(NULL=전체))
    SELECT 'SPMS_CELL_TYPE', 'POUCH', '파우치', 10, '파우치', NULL FROM DUAL UNION ALL
    SELECT 'SPMS_CELL_TYPE', 'PRISM', '각형',   20, '각형', NULL FROM DUAL UNION ALL
    SELECT 'SPMS_CELL_TYPE', 'CYL',   '원통',   30, '원통', NULL FROM DUAL UNION ALL
    -- Stack 공법 (StackMethod 콤보 — 목업: ALS/AZS)
    SELECT 'SPMS_STACK_METHOD', 'ALS', 'ALS', 10, 'ALS', NULL FROM DUAL UNION ALL
    SELECT 'SPMS_STACK_METHOD', 'AZS', 'AZS', 20, 'AZS', NULL FROM DUAL
  ) T
 WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL X
                    WHERE X.LOOKUP_TYPE = T.LT AND X.SEGMENT1 = T.S1);

-- [4] 콤보 3본 (SCM_ADM_CMBO_SQL_M — SQL_DTL_CTN VARCHAR2(4000), @토큰=따옴표 전달 계약) --
INSERT INTO SCM_MGR.SCM_ADM_CMBO_SQL_M (SQL_ID, MDU_DIVS_CD, SQL_NM, SQL_DTL_CTN, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'DpjtClass', 'CM', 'SDM Project Class (lookup SPMS_DPJT_CLASS)',
q'[SELECT L.SEGMENT1 AS CODE, L.SEGMENT2 AS NAME
FROM SCM_ADM_LOOKUP_MASTER_DETAIL L
WHERE L.LOOKUP_TYPE = 'SPMS_DPJT_CLASS' AND L.VALID_YN = 'Y'
ORDER BY L.DISPLAY_SEQ]',
'Y', 'admin', SYSDATE, 'admin', SYSDATE
  FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_CMBO_SQL_M X WHERE X.SQL_ID = 'DpjtClass');

INSERT INTO SCM_MGR.SCM_ADM_CMBO_SQL_M (SQL_ID, MDU_DIVS_CD, SQL_NM, SQL_DTL_CTN, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'StackMethod', 'CM', 'SDM Stack Method (lookup SPMS_STACK_METHOD)',
q'[SELECT L.SEGMENT1 AS CODE, L.SEGMENT2 AS NAME
FROM SCM_ADM_LOOKUP_MASTER_DETAIL L
WHERE L.LOOKUP_TYPE = 'SPMS_STACK_METHOD' AND L.VALID_YN = 'Y'
ORDER BY L.DISPLAY_SEQ]',
'Y', 'admin', SYSDATE, 'admin', SYSDATE
  FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_CMBO_SQL_M X WHERE X.SQL_ID = 'StackMethod');

INSERT INTO SCM_MGR.SCM_ADM_CMBO_SQL_M (SQL_ID, MDU_DIVS_CD, SQL_NM, SQL_DTL_CTN, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'CellTypeByDivision', 'CM', 'SDM Cell Type by Division (lookup SPMS_CELL_TYPE, ATTRIBUTE1=division 스코프 NULL=전체)',
q'[SELECT L.SEGMENT1 AS CODE, L.SEGMENT2 AS NAME
FROM SCM_ADM_LOOKUP_MASTER_DETAIL L
WHERE L.LOOKUP_TYPE = 'SPMS_CELL_TYPE' AND L.VALID_YN = 'Y'
  AND ( NVL(TRIM(@divisionId),'ALL') = 'ALL'
        OR L.ATTRIBUTE1 IS NULL
        OR INSTR(',' || L.ATTRIBUTE1 || ',', ',' || @divisionId || ',') > 0 )
ORDER BY L.DISPLAY_SEQ]',
'Y', 'admin', SYSDATE, 'admin', SYSDATE
  FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_CMBO_SQL_M X WHERE X.SQL_ID = 'CellTypeByDivision');

COMMIT;

