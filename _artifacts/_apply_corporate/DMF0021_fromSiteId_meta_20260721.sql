-- DMF0021 (Sales Plan) #5 — [E20260512-000502] FROM_SITE_ID 컬럼 81 표시 등록
--   (2026-07-21 — 자동차(81) 사업부 From Site ID 컬럼. 최신분석 2026-07-20 반영)
--
-- 배경: [E20260512-000502] 81 division 에 FROM_SITE_ID 컬럼 추가.
--   - GET SP(DMF0021_GET_DM_PLN_SALES_PLAN_DATAEX L1575-1576)는 이미 FROM_SITE_ID 출력(실측 확인) → SP 무변경.
--   - SAVE 는 p_cell_prod_site_id 슬롯으로 FROM_SITE_ID 수신(AS-IS L2474 sCellProdSiteId 덮어쓰기) → FE 치환(#1)로 처리.
--   - 다만 SCM_MST_SHEET_COLUMNS 에 FROM_SITE_ID 는 **div 40(VISIBLE_FLAG='N') 만** 존재, 81 없음 →
--     81 그리드에 컬럼 미표시 + AS-IS 컬럼-존재 체크(MSG00113 L723/L2043) 미충족. 본 SQL 로 81 표시행 등록.
--
-- 방식: 기존 FROM_SITE_ID(div 40) 행을 **전 컬럼 클론**(36컬럼, NOT NULL 전수 — hook #98) 후 아래만 override:
--   DIVISION_ID → 81 계열(PLANT_SITE_ID 81 과 동일 토큰) / VISIBLE_FLAG='Y' / DEFAULT_FLAG='Y' / VALID_YN='Y'
--   / 라벨 3종 → 'From Site' / SORT_ORDER_NO=168(Cell Prod Site*167 인접) / 감사 'admin'.
--   INPUT_TP_CD='S'(read) + insert R5 화이트리스트 미포함 = display-only(잠금) 자동 충족.
--
-- 멱등 MERGE. 스키마 SCM_MGR.
-- =====================================================================

MERGE INTO SCM_MGR.SCM_MST_SHEET_COLUMNS t
USING (
  SELECT PROGRAM_ID, SHEET_NAME, COLUMN_NAME,
         'From Site'                          AS COLUMN_LABEL_NAME,
         168                                  AS SORT_ORDER_NO,
         DATA_SORT_METHOD_CODE,
         'From Site'                          AS SMALL_CLASS_LABEL_NAME,
         'From Site'                          AS LARGE_CLASS_LABEL_NAME,
         FIXED_FLAG, COLUMN_WIDTH, CELL_CONTROL_OBJECT_TYPE_CODE, CELL_COMBO_DATA_TYPE,
         DATA_SCALE_NUMBER, DATA_MAX_LENGTH, HORIZONTAL_ALIGN_CODE, UPPERCASE_APPLY_FLAG,
         'Y'                                  AS VISIBLE_FLAG,
         '81,81_UC,81_HM,81_ST,81_HD,81_HG'   AS DIVISION_ID,
         'Y'                                  AS DEFAULT_FLAG,
         USER_SELECTABLE_FLAG,
         'Y'                                  AS VALID_YN,
         'admin'                              AS CREATED_BY,
         SYSDATE                              AS CREATION_DATE,
         'admin'                              AS LAST_UPDATED_BY,
         SYSDATE                              AS LAST_UPDATE_DATE,
         ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5,
         ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10,
         INPUT_TP_CD
  FROM   SCM_MGR.SCM_MST_SHEET_COLUMNS
  WHERE  PROGRAM_ID='DMF0021' AND SHEET_NAME='Sales Plan'
    AND  COLUMN_NAME='FROM_SITE_ID' AND DIVISION_ID='40'
) s
ON ( t.PROGRAM_ID=s.PROGRAM_ID AND t.SHEET_NAME=s.SHEET_NAME
     AND t.COLUMN_NAME=s.COLUMN_NAME AND t.DIVISION_ID=s.DIVISION_ID )
WHEN MATCHED THEN UPDATE SET
  t.COLUMN_LABEL_NAME=s.COLUMN_LABEL_NAME, t.SORT_ORDER_NO=s.SORT_ORDER_NO,
  t.SMALL_CLASS_LABEL_NAME=s.SMALL_CLASS_LABEL_NAME, t.LARGE_CLASS_LABEL_NAME=s.LARGE_CLASS_LABEL_NAME,
  t.VISIBLE_FLAG='Y', t.DEFAULT_FLAG='Y', t.VALID_YN='Y',
  t.LAST_UPDATED_BY='admin', t.LAST_UPDATE_DATE=SYSDATE
WHEN NOT MATCHED THEN INSERT (
  PROGRAM_ID, SHEET_NAME, COLUMN_NAME, COLUMN_LABEL_NAME, SORT_ORDER_NO, DATA_SORT_METHOD_CODE,
  SMALL_CLASS_LABEL_NAME, LARGE_CLASS_LABEL_NAME, FIXED_FLAG, COLUMN_WIDTH,
  CELL_CONTROL_OBJECT_TYPE_CODE, CELL_COMBO_DATA_TYPE, DATA_SCALE_NUMBER, DATA_MAX_LENGTH,
  HORIZONTAL_ALIGN_CODE, UPPERCASE_APPLY_FLAG, VISIBLE_FLAG, DIVISION_ID, DEFAULT_FLAG,
  USER_SELECTABLE_FLAG, VALID_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE,
  ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5,
  ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10, INPUT_TP_CD
) VALUES (
  s.PROGRAM_ID, s.SHEET_NAME, s.COLUMN_NAME, s.COLUMN_LABEL_NAME, s.SORT_ORDER_NO, s.DATA_SORT_METHOD_CODE,
  s.SMALL_CLASS_LABEL_NAME, s.LARGE_CLASS_LABEL_NAME, s.FIXED_FLAG, s.COLUMN_WIDTH,
  s.CELL_CONTROL_OBJECT_TYPE_CODE, s.CELL_COMBO_DATA_TYPE, s.DATA_SCALE_NUMBER, s.DATA_MAX_LENGTH,
  s.HORIZONTAL_ALIGN_CODE, s.UPPERCASE_APPLY_FLAG, s.VISIBLE_FLAG, s.DIVISION_ID, s.DEFAULT_FLAG,
  s.USER_SELECTABLE_FLAG, s.VALID_YN, s.CREATED_BY, s.CREATION_DATE, s.LAST_UPDATED_BY, s.LAST_UPDATE_DATE,
  s.ATTRIBUTE1, s.ATTRIBUTE2, s.ATTRIBUTE3, s.ATTRIBUTE4, s.ATTRIBUTE5,
  s.ATTRIBUTE6, s.ATTRIBUTE7, s.ATTRIBUTE8, s.ATTRIBUTE9, s.ATTRIBUTE10, s.INPUT_TP_CD
);

COMMIT;

