-- ============================================================================
-- [E20260922-VERMRF] DMF0035 Version 팝업 MRF 저장 — 배선 메타 (멱등 MERGE · 비파괴 · 감사컬럼 admin)
--   API_M → BTN_MPG(version/SAVE) → PROC_M(5행) → USER_GR_MNU_BTN_MPG_M(4그룹)
--   ON 키 = 각 테이블 PK 실측 (2026-09-22 ZIOUI1)
--   권한 그룹: DMF0035 조회 5그룹 중 DM Viewer 제외 4그룹 (Viewer = 조회 전용 관례).
--     AS-IS 는 팝업 버튼 권한이 없어 화면 진입자 전원 편집 가능이었다 — 그룹을 바꾸려면 아래 4번만 조정.
-- ============================================================================

-- 1. API_M
MERGE INTO SCM_ADM_API_M T
USING (SELECT 'DMF0035_version_SAVE' API_ID, 'PROC_SAVE' API_TP_CD, 'MSG_API_DMF0035_version_SAVE' API_MSG_ID
            , 'DMF0035 Version 팝업(SALES) Monthly Rolling Forecast 저장 (AS-IS DMF0073_SAVE_VERSION_SALESPRICE)' API_MSG_DESC
            , 'PKG_DMF0035.P_DMF0035_SAVE_VERSION_MRF' API_URL
         FROM DUAL) S
   ON (T.API_ID = S.API_ID)
 WHEN MATCHED THEN UPDATE SET T.API_TP_CD = S.API_TP_CD, T.API_URL = S.API_URL, T.API_MSG_DESC = S.API_MSG_DESC, T.USE_YN = 'Y'
                            , T.LAST_UPDATED_BY = 'admin', T.LAST_UPDATE_DATE = SYSDATE
 WHEN NOT MATCHED THEN INSERT (API_ID, API_TP_CD, API_MSG_ID, API_MSG_DESC, API_URL, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
      VALUES (S.API_ID, S.API_TP_CD, S.API_MSG_ID, S.API_MSG_DESC, S.API_URL, 'Y', 'admin', SYSDATE, 'admin', SYSDATE);

-- 2. MNU_BTN_MPG — DMF0035 / version / SAVE
MERGE INTO SCM_ADM_MNU_BTN_MPG_M T
USING (SELECT 'DMF0035' MNU_ID, 'version' SHT_NM, 'SAVE' MNU_BTN_CD, 'DMF0035_version_SAVE' API_ID FROM DUAL) S
   ON (T.MNU_ID = S.MNU_ID AND T.SHT_NM = S.SHT_NM AND T.MNU_BTN_CD = S.MNU_BTN_CD)
 WHEN MATCHED THEN UPDATE SET T.API_ID = S.API_ID, T.USE_YN = 'Y', T.LAST_UPDATED_BY = 'admin', T.LAST_UPDATE_DATE = SYSDATE
 WHEN NOT MATCHED THEN INSERT (MNU_ID, SHT_NM, MNU_BTN_CD, API_ID, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
      VALUES (S.MNU_ID, S.SHT_NM, S.MNU_BTN_CD, S.API_ID, 'Y', 'admin', SYSDATE, 'admin', SYSDATE);

-- 3. PROC_M — positional 시그니처 (P_DIVISION_ID / P_VERSION_NO / P_MONTHLY_ROLLING_FCST / P_USER_ID / O_RESULT_CURSOR)
--    P_USER_ID = sesUserId (BE 가 로그인 세션으로 자동 주입 — 조회 SP DMF0035_version_SEARCH 와 같은 키.
--    클라이언트 값을 받지 않으므로 사용자 위조 불가). E2E 실측: 'createdBy' 는 BE 가 치환하지 않아 요청값이 그대로 들어왔다.
-- 1차 배선 잔재 정리 (본 작업이 신설했던 행 — 타 PROC 무영향)
DELETE FROM SCM_ADM_PROC_M
 WHERE PROC_NM = 'PKG_DMF0035.P_DMF0035_SAVE_VERSION_MRF' AND COL_NM = 'createdBy';
MERGE INTO SCM_ADM_PROC_M T
USING (SELECT 'PKG_DMF0035.P_DMF0035_SAVE_VERSION_MRF' PROC_NM, 'divisionId' COL_NM, 'VARCHAR' DATA_TP_CD, 'IN' COL_TP_CD, 1 SORT_ORD FROM DUAL
       UNION ALL SELECT 'PKG_DMF0035.P_DMF0035_SAVE_VERSION_MRF', 'versionNo', 'VARCHAR', 'IN', 2 FROM DUAL
       UNION ALL SELECT 'PKG_DMF0035.P_DMF0035_SAVE_VERSION_MRF', 'monthlyRollingFcst', 'VARCHAR', 'IN', 3 FROM DUAL
       UNION ALL SELECT 'PKG_DMF0035.P_DMF0035_SAVE_VERSION_MRF', 'sesUserId', 'VARCHAR', 'IN', 4 FROM DUAL
       UNION ALL SELECT 'PKG_DMF0035.P_DMF0035_SAVE_VERSION_MRF', 'o_result_cursor', 'PROC_RESULT', 'OUT', 5 FROM DUAL) S
   ON (T.PROC_NM = S.PROC_NM AND T.COL_NM = S.COL_NM AND T.COL_TP_CD = S.COL_TP_CD)
 WHEN MATCHED THEN UPDATE SET T.DATA_TP_CD = S.DATA_TP_CD, T.SORT_ORD = S.SORT_ORD, T.LAST_UPDATED_BY = 'admin', T.LAST_UPDATE_DATE = SYSDATE
 WHEN NOT MATCHED THEN INSERT (PROC_NM, COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
      VALUES (S.PROC_NM, S.COL_NM, S.DATA_TP_CD, S.COL_TP_CD, S.SORT_ORD, 'admin', SYSDATE, 'admin', SYSDATE);

-- 4. USER_GR_MNU_BTN_MPG_M — SAVE 권한 그룹 (DM Viewer 제외)
MERGE INTO SCM_ADM_USER_GR_MNU_BTN_MPG_M T
USING (SELECT G.USER_GR_ID, 'DMF0035' MNU_ID, 'version' SHT_NM, 'SAVE' MNU_BTN_CD
         FROM (SELECT 'ADMIN' USER_GR_ID FROM DUAL UNION ALL SELECT 'DM ADMIN' FROM DUAL
               UNION ALL SELECT 'DM Planner' FROM DUAL UNION ALL SELECT 'SCP Planner' FROM DUAL) G) S
   ON (T.USER_GR_ID = S.USER_GR_ID AND T.MNU_ID = S.MNU_ID AND T.SHT_NM = S.SHT_NM AND T.MNU_BTN_CD = S.MNU_BTN_CD)
 WHEN MATCHED THEN UPDATE SET T.USE_YN = 'Y', T.LAST_UPDATED_BY = 'admin', T.LAST_UPDATE_DATE = SYSDATE
 WHEN NOT MATCHED THEN INSERT (USER_GR_ID, MNU_ID, SHT_NM, MNU_BTN_CD, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
      VALUES (S.USER_GR_ID, S.MNU_ID, S.SHT_NM, S.MNU_BTN_CD, 'Y', 'admin', SYSDATE, 'admin', SYSDATE);

COMMIT;
