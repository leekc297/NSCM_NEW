-- D1. SenderCode 콤보 미등록 확인 (0행이면 결함 확정)
SELECT SQL_ID, USE_YN FROM SCM_MGR.SCM_ADM_CMBO_SQL_M WHERE UPPER(SQL_ID) LIKE '%SENDER%';

-- D2. EDI_SENDER_CODE lookup 소스 (SEGMENT1=division / SEGMENT2=code)
SELECT SEGMENT1, SEGMENT2, VALID_YN FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE='EDI_SENDER_CODE' ORDER BY SEGMENT1, SEGMENT2;

-- D3. minyonglee1 titleset 'C' 목록 — ITEM_NAME 부재 확인
SELECT COLUMN_NAME, SORT_ORDER_NO FROM SCM_MGR.SCM_MST_TITLESET_USER
 WHERE USER_ID='minyonglee1' AND PROGRAM_ID='DMF0003' AND SHEET_NAME='Mkt Fcst'
   AND USER_INQUIRY_COLUMN_TYPE_CODE='C' ORDER BY SORT_ORDER_NO;

-- D4. ITEM_NAME 메타 (DEFAULT_FLAG='N' → SP 기본집합 제외 = 누락 근본원인)
SELECT SHEET_NAME, COLUMN_NAME, DEFAULT_FLAG, VISIBLE_FLAG, VALID_YN, SORT_ORDER_NO
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID='DMF0003' AND COLUMN_NAME IN ('ITEM_NAME','EDIT_FLAG','SORT_KEY')
 ORDER BY SHEET_NAME, COLUMN_NAME;

EXIT;
