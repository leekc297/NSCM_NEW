-- GRANT_FN_STRING_SPLIT_SCMP_APP_20260812.sql — UI/BE 계정(SCMP_APP) 함수 실행 권한 (클라우드 적용용)
-- 배경: 콤보 TeambyDivision(2) 의 SCM_MGR.FN_STRING_SPLIT 호출이 클라우드에서 -9994 —
--   ①스키마 접두(정정 완료) ②EXECUTE 권한 부재(본 파일). 사내 로컬 BE 는 SCM_MGR 직결이라 미검출됐던 갭.
--   TABLE() 연산자는 반환 타입(T_TOKEN_ROW/TAB)에도 EXECUTE 가 필요하다. SCM_MGR(또는 DBA)로 실행.
GRANT EXECUTE ON SCM_MGR.FN_STRING_SPLIT TO SCMP_APP;
GRANT EXECUTE ON SCM_MGR.T_TOKEN_ROW TO SCMP_APP;
GRANT EXECUTE ON SCM_MGR.T_TOKEN_TAB TO SCMP_APP;

-- VERIFY (기대: 3행 EXECUTE)
SELECT TABLE_NAME, PRIVILEGE FROM DBA_TAB_PRIVS
 WHERE GRANTEE='SCMP_APP' AND OWNER='SCM_MGR'
   AND TABLE_NAME IN ('FN_STRING_SPLIT','T_TOKEN_ROW','T_TOKEN_TAB');
