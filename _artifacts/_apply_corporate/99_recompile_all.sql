SET PAGESIZE 500
SET LINESIZE 250
SET SERVEROUTPUT ON SIZE UNLIMITED

BEGIN
  FOR r IN (SELECT OBJECT_NAME, OBJECT_TYPE FROM USER_OBJECTS WHERE STATUS='INVALID' AND OBJECT_TYPE IN ('PROCEDURE','FUNCTION','PACKAGE','PACKAGE BODY','TRIGGER','VIEW')) LOOP
    BEGIN
      IF r.OBJECT_TYPE='PACKAGE BODY' THEN
        EXECUTE IMMEDIATE 'ALTER PACKAGE "'||r.OBJECT_NAME||'" COMPILE BODY';
      ELSE
        EXECUTE IMMEDIATE 'ALTER '||r.OBJECT_TYPE||' "'||r.OBJECT_NAME||'" COMPILE';
      END IF;
      DBMS_OUTPUT.PUT_LINE('OK '||r.OBJECT_TYPE||' '||r.OBJECT_NAME);
    EXCEPTION WHEN OTHERS THEN
      DBMS_OUTPUT.PUT_LINE('ERR '||r.OBJECT_TYPE||' '||r.OBJECT_NAME||' : '||SQLERRM);
    END;
  END LOOP;
END;
/

SELECT OBJECT_TYPE, STATUS, COUNT(*) AS CNT FROM USER_OBJECTS WHERE OBJECT_TYPE IN ('PROCEDURE','FUNCTION','PACKAGE','PACKAGE BODY','TRIGGER','VIEW') GROUP BY OBJECT_TYPE, STATUS ORDER BY OBJECT_TYPE, STATUS;

SELECT OBJECT_NAME, OBJECT_TYPE FROM USER_OBJECTS WHERE STATUS='INVALID' AND OBJECT_TYPE IN ('PROCEDURE','FUNCTION','PACKAGE','PACKAGE BODY') ORDER BY OBJECT_TYPE, OBJECT_NAME;

EXIT;
