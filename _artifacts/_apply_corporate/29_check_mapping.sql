-- A. DM_MDF_VERSION 의 ORI_VERSION_NO 패턴 (SP_W_/SP_D_ 매핑 컬럼?)
SELECT DIVISION_ID, VERSION_NO, ORI_VERSION_NO, ORI_CUTOFF_VERSION_NO, VERSION_TYPE FROM DM_MDF_VERSION WHERE DIVISION_ID='40' AND VERSION_NO LIKE 'R_B_20250820%' FETCH FIRST 10 ROWS ONLY;

-- B. SP body 의 v_sql_text 안 DM_PLN_SALES_PLAN_C 의 WHERE 조건 (line 220~290)
SELECT LINE, SUBSTR(TEXT, 1, 250) AS SRC FROM USER_SOURCE WHERE NAME='DMF0043_GET_CONTRIBUTION_SALES_LIST' AND TYPE='PROCEDURE' AND UPPER(TEXT) LIKE '%DM_PLN_SALES_PLAN_C%' ORDER BY LINE;

-- C. SP body 의 p_version_no 사용 위치
SELECT LINE, SUBSTR(TEXT, 1, 250) AS SRC FROM USER_SOURCE WHERE NAME='DMF0043_GET_CONTRIBUTION_SALES_LIST' AND TYPE='PROCEDURE' AND UPPER(TEXT) LIKE '%P_VERSION_NO%' ORDER BY LINE;

-- D. 매핑 가능한 ORI_VERSION_NO 확인 (Div40 + Plan 실제 매칭)
SELECT V.VERSION_NO, V.ORI_VERSION_NO, V.VER_CRE_SEQ, COUNT(P.VERSION_NO) AS PLAN_ROWS FROM DM_MDF_VERSION V LEFT JOIN DM_PLN_SALES_PLAN_C P ON V.DIVISION_ID = P.DIVISION_ID AND V.ORI_VERSION_NO = P.VERSION_NO WHERE V.DIVISION_ID = '40' AND V.ORI_VERSION_NO IS NOT NULL GROUP BY V.VERSION_NO, V.ORI_VERSION_NO, V.VER_CRE_SEQ HAVING COUNT(P.VERSION_NO) > 100 ORDER BY PLAN_ROWS DESC FETCH FIRST 15 ROWS ONLY;

