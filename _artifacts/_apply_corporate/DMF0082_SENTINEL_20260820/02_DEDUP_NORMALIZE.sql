       SUM(CASE WHEN PLANT_SITE_ID = ' ' OR PLANT_SITE_ID = '--' OR INSTR(PLANT_SITE_ID, CHR(0)) > 0 OR PLANT_SITE_ID <> TRIM(PLANT_SITE_ID) THEN 1 ELSE 0 END) VARIANTS
  FROM SCM_MGR.DM_PLN_CFM_MKT_DEMAND_PLAN
UNION ALL
SELECT 'SELL', SUM(CASE WHEN PLANT_SITE_ID = ' ' OR PLANT_SITE_ID = '--' OR INSTR(PLANT_SITE_ID, CHR(0)) > 0 OR PLANT_SITE_ID <> TRIM(PLANT_SITE_ID) THEN 1 ELSE 0 END)
  FROM SCM_MGR.DM_PLN_CFM_SELLING_PRICE
UNION ALL
SELECT 'FUT', SUM(CASE WHEN PLANT_SITE_ID = ' ' OR PLANT_SITE_ID = '--' OR INSTR(PLANT_SITE_ID, CHR(0)) > 0 OR PLANT_SITE_ID <> TRIM(PLANT_SITE_ID) THEN 1 ELSE 0 END)
  FROM SCM_MGR.SCM_MST_FUTURE_PRICE;
