-- DMF0082 센티널 정리 — 중복 삭제 + PLANT_SITE_ID '-' 정규화 (2026-08-20)
-- ⚠ 01_BACKUP 완료 후에만 실행. 생존자 규칙 = 최신(NVL(LAST_UPDATE_DATE,CREATION_DATE)) →
--   shape 우선('-'>'--'>CHR0>' ') → ROWID  (README 결정 1 — 사용자 승인 필요)
-- 정규화 판정식은 PKG 기존 동일 처리(TRIM/REPLACE CHR(0)/IN('-','--'))와 동일 (hook #119 §1.5)

--------------------------------------------------------------------------------
-- 공통 정규화식: CASE WHEN TRIM(REPLACE(PLANT_SITE_ID,CHR(0),'')) IS NULL
--                     OR TRIM(REPLACE(PLANT_SITE_ID,CHR(0),'')) IN ('-','--')
--                THEN '-' ELSE TRIM(PLANT_SITE_ID) END
--------------------------------------------------------------------------------

-- 1) DM_PLN_CFM_MKT_DEMAND_PLAN (PK: DIV,PROJ,ENDCUST,SITE,ITEM,DOM,FCST,INCO,MEAS,YYYYMMDD,PLANT,CELLPROD)
DELETE FROM SCM_MGR.DM_PLN_CFM_MKT_DEMAND_PLAN
WHERE ROWID IN (
  SELECT RID FROM (
    SELECT ROWID RID, ROW_NUMBER() OVER (
      PARTITION BY DIVISION_ID, PROJECT_CODE, END_CUSTOMER, SCM_SITE_ID, ITEM_ID,
                   DOM_EXP, FCST_TYPE, INCOTERMS, MEASURE, YYYYMMDD, CELL_PROD_SITE_ID,
                   CASE WHEN TRIM(REPLACE(PLANT_SITE_ID,CHR(0),'')) IS NULL OR TRIM(REPLACE(PLANT_SITE_ID,CHR(0),'')) IN ('-','--') THEN '-' ELSE TRIM(PLANT_SITE_ID) END
      ORDER BY NVL(LAST_UPDATE_DATE, CREATION_DATE) DESC,
               CASE WHEN PLANT_SITE_ID = '-' THEN 0 WHEN PLANT_SITE_ID = '--' THEN 1
                    WHEN INSTR(PLANT_SITE_ID, CHR(0)) > 0 THEN 2 ELSE 3 END,
               ROWID) RN
    FROM SCM_MGR.DM_PLN_CFM_MKT_DEMAND_PLAN
  ) WHERE RN > 1
);

UPDATE SCM_MGR.DM_PLN_CFM_MKT_DEMAND_PLAN
   SET PLANT_SITE_ID = '-'
 WHERE (PLANT_SITE_ID = ' ' OR PLANT_SITE_ID = '--' OR INSTR(PLANT_SITE_ID, CHR(0)) > 0 OR PLANT_SITE_ID <> TRIM(PLANT_SITE_ID));

-- 2) DM_PLN_CFM_SELLING_PRICE (PK: DIV,PROJ,ENDCUST,SITE,PLANT,CELLPROD,ITEM,YYYYMMDD,MEAS,DOM,FCST,INCO)
DELETE FROM SCM_MGR.DM_PLN_CFM_SELLING_PRICE
WHERE ROWID IN (
  SELECT RID FROM (
    SELECT ROWID RID, ROW_NUMBER() OVER (
      PARTITION BY DIVISION_ID, PROJECT_CODE, END_CUSTOMER, SCM_SITE_ID, CELL_PROD_SITE_ID,
                   ITEM_ID, YYYYMMDD, MEASURE, DOM_EXP, FCST_TYPE, INCOTERMS,
                   CASE WHEN TRIM(REPLACE(PLANT_SITE_ID,CHR(0),'')) IS NULL OR TRIM(REPLACE(PLANT_SITE_ID,CHR(0),'')) IN ('-','--') THEN '-' ELSE TRIM(PLANT_SITE_ID) END
      ORDER BY NVL(LAST_UPDATE_DATE, CREATION_DATE) DESC,
               CASE WHEN PLANT_SITE_ID = '-' THEN 0 WHEN PLANT_SITE_ID = '--' THEN 1
                    WHEN INSTR(PLANT_SITE_ID, CHR(0)) > 0 THEN 2 ELSE 3 END,
               ROWID) RN
    FROM SCM_MGR.DM_PLN_CFM_SELLING_PRICE
  ) WHERE RN > 1
);

UPDATE SCM_MGR.DM_PLN_CFM_SELLING_PRICE
   SET PLANT_SITE_ID = '-'
 WHERE (PLANT_SITE_ID = ' ' OR PLANT_SITE_ID = '--' OR INSTR(PLANT_SITE_ID, CHR(0)) > 0 OR PLANT_SITE_ID <> TRIM(PLANT_SITE_ID));

-- 3) SCM_MST_FUTURE_PRICE (PK: DIV,PROJ,SITE,PLANT,ITEM,YYYYMMDD,CURRENCY,MEAS,DOM,FCST,INCO)
DELETE FROM SCM_MGR.SCM_MST_FUTURE_PRICE
WHERE ROWID IN (
  SELECT RID FROM (
    SELECT ROWID RID, ROW_NUMBER() OVER (
      PARTITION BY DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, YYYYMMDD,
                   CURRENCY, MEASURE, DOM_EXP, FCST_TYPE, INCOTERMS,
                   CASE WHEN TRIM(REPLACE(PLANT_SITE_ID,CHR(0),'')) IS NULL OR TRIM(REPLACE(PLANT_SITE_ID,CHR(0),'')) IN ('-','--') THEN '-' ELSE TRIM(PLANT_SITE_ID) END
      ORDER BY NVL(LAST_UPDATE_DATE, CREATION_DATE) DESC,
               CASE WHEN PLANT_SITE_ID = '-' THEN 0 WHEN PLANT_SITE_ID = '--' THEN 1
                    WHEN INSTR(PLANT_SITE_ID, CHR(0)) > 0 THEN 2 ELSE 3 END,
               ROWID) RN
    FROM SCM_MGR.SCM_MST_FUTURE_PRICE
  ) WHERE RN > 1
);

UPDATE SCM_MGR.SCM_MST_FUTURE_PRICE
   SET PLANT_SITE_ID = '-'
 WHERE (PLANT_SITE_ID = ' ' OR PLANT_SITE_ID = '--' OR INSTR(PLANT_SITE_ID, CHR(0)) > 0 OR PLANT_SITE_ID <> TRIM(PLANT_SITE_ID));

COMMIT;

-- 검증: 변형 0 + 중복 그룹 0
