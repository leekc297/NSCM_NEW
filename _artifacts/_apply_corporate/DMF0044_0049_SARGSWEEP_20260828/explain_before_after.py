#!/usr/bin/env python3
"""SARGSWEEP 정정 전/후 실행계획 대조 (EXPLAIN PLAN — 실행 없음)."""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[2] / "_diagnostics"))
import oracledb  # noqa: E402
from ora import conn_info  # noqa: E402

CASES = {
    # DMF0044 L4023 — ETC save 'D' DELETE (PLAN_REPORT_C 3.93M)
    "ETCDEL_BEFORE": """
DELETE FROM SCM_MGR.DM_PLN_SALES_PLAN_REPORT_C A
WHERE A.DATA_TYPE = '2'
AND EXISTS (SELECT 1 FROM SCM_MGR.GT_0044_RESULTS_MST B
    WHERE B.ACTIVE_FLAG = 'D' AND A.VERSION_NO = B.VERSION_NO AND A.DIVISION_ID = B.DIVISION_ID
    AND A.DEPARTMENT_ID = B.DEPARTMENT_ID AND A.DEPT_ID = B.DEPT_ID AND A.END_CUST_REPORT = B.END_CUST_REPORT
    AND A.CUST_REPORT = B.CUST_REPORT AND A.PRODUCT_GROUP = B.PRODUCT_GROUP AND A.ITEM_ID = B.ITEM_ID
    AND A.MEASURE = B.MEASURE AND A.YYYYMMDD = B.YYYYMMDD AND A.CURRENCY = B.CURRENCY AND A.COMPANY_ID = B.COMPANY_ID)
""",
    "ETCDEL_AFTER": """
DELETE FROM SCM_MGR.DM_PLN_SALES_PLAN_REPORT_C A
WHERE A.DATA_TYPE = '2'
AND A.DIVISION_ID = '40' AND A.VERSION_NO = 'R_S_20260715_V002_C'
AND EXISTS (SELECT 1 FROM SCM_MGR.GT_0044_RESULTS_MST B
    WHERE B.ACTIVE_FLAG = 'D' AND A.VERSION_NO = B.VERSION_NO AND A.DIVISION_ID = B.DIVISION_ID
    AND A.DEPARTMENT_ID = B.DEPARTMENT_ID AND A.DEPT_ID = B.DEPT_ID AND A.END_CUST_REPORT = B.END_CUST_REPORT
    AND A.CUST_REPORT = B.CUST_REPORT AND A.PRODUCT_GROUP = B.PRODUCT_GROUP AND A.ITEM_ID = B.ITEM_ID
    AND A.MEASURE = B.MEASURE AND A.YYYYMMDD = B.YYYYMMDD AND A.CURRENCY = B.CURRENCY AND A.COMPANY_ID = B.COMPANY_ID)
""",
    # DMF0044 L9531 — 버전 COPY 내 BIZ_TYPE 보강 MERGE
    "VCMERGE_BEFORE": """
MERGE INTO SCM_MGR.DM_PLN_SALES_PLAN_REPORT_C A
USING ( SELECT A.MODEL, A.BIZ_TYPE, A.CELL_PACK_COUNT, A.MODEL_RANK, A.DIVISION_ID
        FROM ( SELECT SEGMENT2 AS MODEL, SEGMENT3 AS BIZ_TYPE, SEGMENT4 AS CELL_PACK_COUNT, SEGMENT1 AS DIVISION_ID
                    , RANK() OVER (PARTITION BY SEGMENT2 ORDER BY DISPLAY_SEQ DESC) MODEL_RANK
               FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = 'DM_BIZ_TYPE_40' ) A
        WHERE MODEL_RANK = '1' ) LOOKA
ON ( LOOKA.MODEL = A.ITEM_ID AND LOOKA.DIVISION_ID = A.DIVISION_ID )
WHEN MATCHED THEN UPDATE SET A.FORECAST_INFO_CELL_PACK_COUNT = LOOKA.CELL_PACK_COUNT
    , A.FORECAST_INFO_BIZ_TYPE = LOOKA.BIZ_TYPE
    WHERE A.DIVISION_ID = '40' AND A.VERSION_NO = 'R_S_20260715_V002_C'
""",
    "VCMERGE_AFTER": """
MERGE INTO SCM_MGR.DM_PLN_SALES_PLAN_REPORT_C A
USING ( SELECT A.MODEL, A.BIZ_TYPE, A.CELL_PACK_COUNT, A.MODEL_RANK, A.DIVISION_ID
        FROM ( SELECT SEGMENT2 AS MODEL, SEGMENT3 AS BIZ_TYPE, SEGMENT4 AS CELL_PACK_COUNT, SEGMENT1 AS DIVISION_ID
                    , RANK() OVER (PARTITION BY SEGMENT2 ORDER BY DISPLAY_SEQ DESC) MODEL_RANK
               FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = 'DM_BIZ_TYPE_40' ) A
        WHERE MODEL_RANK = '1' ) LOOKA
ON ( LOOKA.MODEL = A.ITEM_ID AND LOOKA.DIVISION_ID = A.DIVISION_ID
     AND A.DIVISION_ID = '40' AND A.VERSION_NO = 'R_S_20260715_V002_C' )
WHEN MATCHED THEN UPDATE SET A.FORECAST_INFO_CELL_PACK_COUNT = LOOKA.CELL_PACK_COUNT
    , A.FORECAST_INFO_BIZ_TYPE = LOOKA.BIZ_TYPE
    WHERE A.DIVISION_ID = '40' AND A.VERSION_NO = 'R_S_20260715_V002_C'
""",
}


def main() -> None:
    u, p, d = conn_info()
    with oracledb.connect(user=u, password=p, dsn=d) as con:
        cur = con.cursor()
        for tag, sql in CASES.items():
            cur.execute(f"EXPLAIN PLAN SET STATEMENT_ID='{tag}' FOR " + sql)
            cur.execute(
                "SELECT plan_table_output FROM TABLE(DBMS_XPLAN.DISPLAY(NULL, :t, 'BASIC ROWS COST'))",
                t=tag,
            )
            print(f"===== {tag} =====")
            for (line,) in cur.fetchall():
                print(line)
            print()


if __name__ == "__main__":
    main()
