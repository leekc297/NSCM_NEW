-- DMF0044 P4 — CMBO_SQL_M 신규 4건 (2026-07-22)
-- 기등록 실측(재사용): MyDivision / MDF_TYPE / DM_COMPANY / DMF0044_MDF_DEPARTMENT /
--   DMF0044_MDF_MEASURE / DMF0044_DEPARTMENT_TEAM2
-- 신규 4건: MDF_TYPE2(Data Type) / CALENDAR_YYYY(Year) / MDF_TYPE_SP_POPUP / MDF_TYPE_BP_POPUP
--   — 전부 lookup 실데이터 확인(MDF_TYPE2 3/SP_POPUP 3/BP_POPUP 2 VALID). MDF_TYPE 템플릿 1:1.
-- 멱등 MERGE. 감사 'admin'.
-- =====================================================================
MERGE INTO SCM_MGR.SCM_ADM_CMBO_SQL_M t
USING (
  SELECT 'MDF_TYPE2' SQL_ID, 'DM' MDU_DIVS_CD, 'DMF0044 Data Type (ALL/1=Cutoff/2=ETC)' SQL_NM,
'SELECT SEGMENT1 AS CODE, SEGMENT2 AS NAME FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = ''MDF_TYPE2'' AND VALID_YN = ''Y'' ORDER BY DISPLAY_SEQ' SQL_DTL_CTN FROM DUAL
  UNION ALL
  SELECT 'MDF_TYPE_SP_POPUP', 'DM', 'DMF0044 United 팝업 Report Type (SP 계열)',
'SELECT SEGMENT1 AS CODE, SEGMENT2 AS NAME FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = ''MDF_TYPE_SP_POPUP'' AND VALID_YN = ''Y'' ORDER BY DISPLAY_SEQ' FROM DUAL
  UNION ALL
  SELECT 'MDF_TYPE_BP_POPUP', 'DM', 'DMF0044 United 팝업 Report Type (BP 계열)',
'SELECT SEGMENT1 AS CODE, SEGMENT2 AS NAME FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = ''MDF_TYPE_BP_POPUP'' AND VALID_YN = ''Y'' ORDER BY DISPLAY_SEQ' FROM DUAL
  UNION ALL
  SELECT 'CALENDAR_YYYY', 'DM', 'DMF0044 Year 콤보 (SCM_SYS_CALENDAR_M 연도 — AS-IS UP_FX CALENDAR_YYYY)',
'SELECT DISTINCT CALENDAR_YYYY AS CODE, CALENDAR_YYYY AS NAME FROM SCM_MGR.SCM_SYS_CALENDAR_M ORDER BY CALENDAR_YYYY' FROM DUAL
) s
ON (t.SQL_ID = s.SQL_ID)
WHEN MATCHED THEN UPDATE SET t.MDU_DIVS_CD = s.MDU_DIVS_CD, t.SQL_NM = s.SQL_NM,
  t.SQL_DTL_CTN = s.SQL_DTL_CTN, t.USE_YN = 'Y',
  t.LAST_UPDATED_BY = 'admin', t.LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (SQL_ID, MDU_DIVS_CD, SQL_NM, SQL_DTL_CTN, USE_YN,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES (s.SQL_ID, s.MDU_DIVS_CD, s.SQL_NM, s.SQL_DTL_CTN, 'Y', 'admin', SYSDATE, 'admin', SYSDATE);

COMMIT;

