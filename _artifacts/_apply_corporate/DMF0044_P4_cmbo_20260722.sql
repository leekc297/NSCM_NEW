-- 원복: DELETE FROM SCM_MGR.SCM_ADM_CMBO_SQL_M WHERE SQL_ID IN ('MDF_TYPE2','CALENDAR_YYYY','MDF_TYPE_SP_POPUP','MDF_TYPE_BP_POPUP'); COMMIT;
