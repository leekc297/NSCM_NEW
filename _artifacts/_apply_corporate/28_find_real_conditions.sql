-- A. DM_MDF_VERSION ↔ DM_PLN_SALES_PLAN_C 의 VERSION_NO 정확 매칭 + VER_CRE_SEQ
SELECT V.DIVISION_ID, V.VERSION_NO, V.VER_CRE_SEQ, V.VERSION_TYPE, COUNT(P.VERSION_NO) AS PLAN_ROWS FROM DM_MDF_VERSION V INNER JOIN DM_PLN_SALES_PLAN_C P ON V.DIVISION_ID = P.DIVISION_ID AND V.VERSION_NO = P.VERSION_NO WHERE V.DIVISION_ID = '40' GROUP BY V.DIVISION_ID, V.VERSION_NO, V.VER_CRE_SEQ, V.VERSION_TYPE ORDER BY PLAN_ROWS DESC FETCH FIRST 15 ROWS ONLY;

-- B. DM_MDF_VERSION 의 VERSION_NO 패턴 분포 (SP_W_/SP_D_/R_B_/R_S_)
SELECT SUBSTR(VERSION_NO, 1, 5) AS PREFIX, DIVISION_ID, COUNT(*) AS C FROM DM_MDF_VERSION GROUP BY SUBSTR(VERSION_NO, 1, 5), DIVISION_ID ORDER BY DIVISION_ID, PREFIX;

-- C. DM_PLN_SALES_PLAN_C 의 VERSION_NO 패턴 분포
SELECT SUBSTR(VERSION_NO, 1, 5) AS PREFIX, DIVISION_ID, COUNT(*) AS C FROM DM_PLN_SALES_PLAN_C GROUP BY SUBSTR(VERSION_NO, 1, 5), DIVISION_ID ORDER BY DIVISION_ID, PREFIX;

EXIT;
