SET PAGESIZE 500
SET LINESIZE 300

-- A. DMF0043 화면이 호출하는 모든 SP 의 STATUS
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM USER_OBJECTS WHERE OBJECT_NAME IN ('DMF0043_GET_CONTRIBUTION_SALES_LIST','DMF0043_GET_SALES_LIST_SPREAD_TITLE','DMF0043_GET_MAIN_VARSION_DATA','DMF0043_GET_CONTRIBUTE_MAIN_DATA','DMF0043_GET_MAIN_SPREAD_TITLE','DMF0043_GET_CONTRIBUTE_RATE_POPUP','DMF0043_GET_CONT_VIEW_VERSIONPOPUP','DMF0043_GET_CONTRIBUTE_YEAR_POPUP','DMF0043_SAVE_DM_MST_CONTRIBUTE_RATIO','DMF0043_SAVE_DM_MST_CONTRIBUTE_VER','PKG_DMF0043') ORDER BY OBJECT_TYPE, OBJECT_NAME;

-- B. INVALID 인 모든 DMF0043 관련
SELECT NAME, LINE, POSITION, SUBSTR(TEXT, 1, 200) AS ERR_TEXT FROM USER_ERRORS WHERE NAME LIKE '%DMF0043%' ORDER BY NAME, SEQUENCE FETCH FIRST 50 ROWS ONLY;

-- C. DMF0043_GET_CONTRIBUTION_SALES_LIST 에 REPORT_GROUP3 reference 잔존 여부 (메인 SP, 사용자가 조회 시 호출)
SELECT LINE, SUBSTR(TEXT, 1, 200) AS SRC FROM USER_SOURCE WHERE NAME='DMF0043_GET_CONTRIBUTION_SALES_LIST' AND TYPE='PROCEDURE' AND UPPER(TEXT) LIKE '%REPORT_GROUP3%' ORDER BY LINE;

-- D. DMF0043_GET_SALES_LIST_SPREAD_TITLE 에 REPORT_GROUP3 reference
SELECT LINE, SUBSTR(TEXT, 1, 200) AS SRC FROM USER_SOURCE WHERE NAME='DMF0043_GET_SALES_LIST_SPREAD_TITLE' AND TYPE='PROCEDURE' AND UPPER(TEXT) LIKE '%REPORT_GROUP3%' ORDER BY LINE;

-- E. PKG_DMF0043 BODY 에 REPORT_GROUP3 reference
SELECT LINE, SUBSTR(TEXT, 1, 200) AS SRC FROM USER_SOURCE WHERE NAME='PKG_DMF0043' AND TYPE='PACKAGE BODY' AND UPPER(TEXT) LIKE '%REPORT_GROUP3%' ORDER BY LINE FETCH FIRST 30 ROWS ONLY;

-- F. DMF0043 메뉴 / 권한 / API / PROC 메타 확인
SELECT 'MNU_DMF0043' AS K, COUNT(*) AS C FROM SCM_ADM_MNU_M WHERE MNU_ID='DMF0043';
SELECT 'API_DMF0043' AS K, API_ID FROM SCM_ADM_API_M WHERE API_ID LIKE 'P_DMF0043_%' ORDER BY API_ID;
SELECT 'PROC_DMF0043' AS K, COUNT(*) AS C FROM SCM_ADM_PROC_M WHERE PROC_NM LIKE 'DMF0043_%' OR PROC_NM LIKE 'P_DMF0043_%';
SELECT 'BTN_DMF0043_main_SEARCH' AS K, COUNT(*) AS C FROM SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID='DMF0043' AND MNU_BTN_CD='SEARCH';

-- G. GUEST 메뉴 권한
SELECT USER_GR_ID, MNU_ID FROM SCM_ADM_USER_GR_MNU_MPG_M WHERE MNU_ID='DMF0043' ORDER BY USER_GR_ID;

EXIT;
