-- [EXCEL-HEADER-MSG 2026-09-22] MSG01151 문구 변경 — Excel Upload 헤더 불일치 안내 (DMF0014 / DMF0074 / DMF0082)
--   BE FileServiceImpl.validateExcelHeader 가 대상 화면 헤더 불일치 시 이 문구를 세션 언어로 조회해 내려보낸다.
--   i18n KO=EN=CN 동일 문구 (사용자 지정). 멱등 MERGE — 없으면 INSERT, 있으면 문구만 보정. 감사컬럼 admin.
MERGE INTO SCM_ADM_MSG_M T
USING (SELECT 'MSG01151' MSG_ID, L.LANG_CD, 'Invalid Column Header Title' MSG_NM
         FROM (SELECT 'KO' LANG_CD FROM DUAL UNION ALL SELECT 'EN' FROM DUAL UNION ALL SELECT 'CN' FROM DUAL) L) S
   ON (T.MSG_ID = S.MSG_ID AND T.LANG_CD = S.LANG_CD)
 WHEN MATCHED THEN UPDATE SET T.MSG_NM = S.MSG_NM, T.USE_YN = 'Y', T.LAST_UPDATED_BY = 'admin', T.LAST_UPDATE_DATE = SYSDATE
      WHERE NVL(T.MSG_NM, '#') <> S.MSG_NM OR T.USE_YN <> 'Y'
 WHEN NOT MATCHED THEN INSERT (MSG_ID, LANG_CD, MSG_NM, MSG_TP_CD, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
      VALUES (S.MSG_ID, S.LANG_CD, S.MSG_NM, 'MSG', 'Y', 'admin', SYSDATE, 'admin', SYSDATE);
COMMIT;
