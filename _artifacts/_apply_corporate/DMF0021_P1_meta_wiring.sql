  UNION ALL SELECT 'DMF0021_main_SAVE',    'PROC_SAVE',   'DMF0021_SAVE_DM_PLN_SALES_PLAN_ALL',   'DMF0021 Sales Plan 저장 (^ bulk)' FROM DUAL
  UNION ALL SELECT 'DMF0021_main_EXCEL',   'PROC_SELECT', 'DMF0021_GET_DM_PLN_SALES_PLAN_DATAEX', 'DMF0021 Excel Export' FROM DUAL
  UNION ALL SELECT 'DMF0021_main_FILTER',  'PROC_SELECT', 'DMF0021_GET_DM_PLN_SALES_PLAN_DATAEX', 'DMF0021 Filter' FROM DUAL
  UNION ALL SELECT 'DMF0021_main_SORT',    'PROC_SELECT', 'DMF0021_GET_DM_PLN_SALES_PLAN_DATAEX', 'DMF0021 Sort' FROM DUAL
  UNION ALL SELECT 'DMF0021_main_COLUMN_SETUP',   'PROC_SELECT', 'DMF0002_GET_TITLESET_POPUP', 'DMF0021 Column Setting 팝업' FROM DUAL
  UNION ALL SELECT 'DMF0021_main_MEASURE_SELECT', 'PROC_SELECT', 'DMF0002_GET_TITLESET_POPUP', 'DMF0021 Measure Select 팝업' FROM DUAL
  UNION ALL SELECT 'DMF0021_spreadTitle_SEARCH', 'PROC_SELECT', 'DMF0021_GET_SPREAD_TITLE', 'DMF0021 동적 3단 헤더 조회' FROM DUAL
  UNION ALL SELECT 'DMF0021_measureInfo_SEARCH', 'PROC_SELECT', 'DMF0021_GET_SALES_PLAN_MEASUREINFO', 'DMF0021 Insert 행 Measure 콤보' FROM DUAL
