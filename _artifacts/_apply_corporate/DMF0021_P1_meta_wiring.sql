-- ⑤ USER_GR — ADMIN/DM ADMIN = 14버튼 전체 / DM Viewer = 편집 3종(INSERT/DELETE/SAVE) 제외 11버튼
--    (titleSet SAVE 는 Viewer 부여 — 표시설정 저장, DMF0003/0048/0082 선례)
MERGE INTO SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M t
USING (
  SELECT g.USER_GR_ID, 'DMF0021' MNU_ID, b.SHT_NM, b.MNU_BTN_CD
  FROM (SELECT 'ADMIN' USER_GR_ID FROM DUAL
        UNION ALL SELECT 'DM ADMIN' FROM DUAL
        UNION ALL SELECT 'DM Viewer' FROM DUAL) g
  CROSS JOIN (
    SELECT 'Sales Plan' SHT_NM, 'SEARCH' MNU_BTN_CD FROM DUAL
    UNION ALL SELECT 'Sales Plan', 'INSERT' FROM DUAL
    UNION ALL SELECT 'Sales Plan', 'DELETE' FROM DUAL
    UNION ALL SELECT 'Sales Plan', 'SAVE' FROM DUAL
    UNION ALL SELECT 'Sales Plan', 'EXCEL' FROM DUAL
    UNION ALL SELECT 'Sales Plan', 'FILTER' FROM DUAL
    UNION ALL SELECT 'Sales Plan', 'SORT' FROM DUAL
    UNION ALL SELECT 'Sales Plan', 'COLUMN_SETUP' FROM DUAL
    UNION ALL SELECT 'Sales Plan', 'MEASURE_SELECT' FROM DUAL
    UNION ALL SELECT 'spreadTitle', 'SEARCH' FROM DUAL
    UNION ALL SELECT 'measureInfo', 'SEARCH' FROM DUAL
    UNION ALL SELECT 'dayRange', 'SEARCH' FROM DUAL
    UNION ALL SELECT 'titleSet', 'SEARCH' FROM DUAL
    UNION ALL SELECT 'titleSet', 'SAVE' FROM DUAL
  ) b
  WHERE NOT (g.USER_GR_ID = 'DM Viewer'
             AND b.SHT_NM = 'Sales Plan' AND b.MNU_BTN_CD IN ('INSERT', 'DELETE', 'SAVE'))
) s
ON (t.USER_GR_ID = s.USER_GR_ID AND t.MNU_ID = s.MNU_ID AND t.SHT_NM = s.SHT_NM AND t.MNU_BTN_CD = s.MNU_BTN_CD)
WHEN MATCHED THEN UPDATE SET t.USE_YN = 'Y',
  t.LAST_UPDATED_BY = 'admin', t.LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (USER_GR_ID, MNU_ID, SHT_NM, MNU_BTN_CD, USE_YN,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES (s.USER_GR_ID, s.MNU_ID, s.SHT_NM, s.MNU_BTN_CD, 'Y',
  'admin', SYSDATE, 'admin', SYSDATE);

COMMIT;

