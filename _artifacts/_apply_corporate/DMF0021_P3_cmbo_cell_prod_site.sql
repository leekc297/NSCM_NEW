-- 원천: AS-IS UP_FX_GETCOMMONDATALIST @Code='CELL_PROD_SITE_ID' (AsIs_LGCE_SCMDEV_SP10_DDL.sql L16418~16525)
--   = LOOKUP 'SP_CELL_PROD_SITE' 의 '-'(Common) 행 + FORECAST_INFO_BIZ_TYPE='CELL' 아이템의
--     생산지(SCM_MST_SITE SITE_TYPE='PLANT'/OPERATION_GROUP='A'/OSP_YN='N') — 3분기 케이스를 단일 SQL 등가 축약.
-- 사전 게이트 실측 (2026-07-14): LOOKUP 'SP_CELL_PROD_SITE' VALID_YN='Y' 45건 존재 ✓
-- 파라미터 규약: @divisionId / @itemId (기존 CMBO 'Division'/'TeambyDivision' @camelCase 실측 준용)
-- SHEET_COLUMNS 정합: 'Sales Plan'/CELL_PROD_SITE_ID 의 CELL_COMBO_DATA_TYPE='CELL_PROD_SITE_ID' 와 SQL_ID 일치
-- =====================================================================
MERGE INTO SCM_MGR.SCM_ADM_CMBO_SQL_M t
USING (
  SELECT 'CELL_PROD_SITE_ID' SQL_ID, 'DM' MDU_DIVS_CD,
         'DMF0021 Cell Prod Site 셀 콤보 (div40 Catch_Up)' SQL_NM,
'SELECT SEGMENT1 AS CODE, ATTRIBUTE1 AS NAME
FROM SCM_ADM_LOOKUP_MASTER_DETAIL
WHERE LOOKUP_TYPE = ''SP_CELL_PROD_SITE'' AND SEGMENT1 = ''-'' AND VALID_YN = ''Y''
  AND NOT EXISTS (SELECT 1 FROM SCM_MST_ITEM_SN I
                   WHERE I.ACTIVE_FLAG = ''Y'' AND I.FORECAST_INFO_BIZ_TYPE = ''CELL''
                     AND I.DIVISION_ID = @divisionId AND I.ITEM_ID = @itemId
                     AND @itemId IS NOT NULL AND @itemId <> ''ALL'')
UNION ALL
SELECT DISTINCT S.SCM_SITE_ID AS CODE, M.ATTRIBUTE1 AS NAME
FROM SCM_MST_SITE S
JOIN (SELECT DISTINCT I.DIVISION_ID, I.COMPANY_ID, I.SCP_OPERATION_GROUP
        FROM SCM_MST_ITEM_SN I
       WHERE I.ACTIVE_FLAG = ''Y'' AND I.ITEM_TYPE IS NOT NULL
         AND I.FORECAST_INFO_BIZ_TYPE = ''CELL''
         AND (@divisionId IS NULL OR I.DIVISION_ID = @divisionId)
         AND (@itemId IS NULL OR @itemId = ''ALL'' OR I.ITEM_ID = @itemId)) SS
  ON S.DIVISION_ID = SS.DIVISION_ID AND S.OPERATION_GROUP = SS.SCP_OPERATION_GROUP
 AND S.COMPANY_ID = SS.COMPANY_ID
JOIN SCM_ADM_LOOKUP_MASTER_DETAIL M
  ON M.LOOKUP_TYPE = ''SP_CELL_PROD_SITE'' AND M.SEGMENT1 = S.SCM_SITE_ID AND M.VALID_YN = ''Y''
WHERE S.SITE_TYPE = ''PLANT'' AND S.OPERATION_GROUP = ''A'' AND S.OSP_YN = ''N''' SQL_DTL_CTN
  FROM DUAL
) s
ON (t.SQL_ID = s.SQL_ID)
WHEN MATCHED THEN UPDATE SET t.MDU_DIVS_CD = s.MDU_DIVS_CD, t.SQL_NM = s.SQL_NM,
  t.SQL_DTL_CTN = s.SQL_DTL_CTN, t.USE_YN = 'Y',
  t.LAST_UPDATED_BY = 'admin', t.LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (SQL_ID, MDU_DIVS_CD, SQL_NM, SQL_DTL_CTN, USE_YN,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES (s.SQL_ID, s.MDU_DIVS_CD, s.SQL_NM, s.SQL_DTL_CTN, 'Y',
  'admin', SYSDATE, 'admin', SYSDATE);

COMMIT;

SELECT SQL_ID, MDU_DIVS_CD, USE_YN, LENGTH(SQL_DTL_CTN) LEN FROM SCM_MGR.SCM_ADM_CMBO_SQL_M WHERE SQL_ID = 'CELL_PROD_SITE_ID';

