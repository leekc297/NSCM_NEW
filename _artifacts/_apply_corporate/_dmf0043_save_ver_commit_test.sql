-- SP 호출 + COMMIT + 새 row 확인 (실 INSERT 동작 검증)
SET SERVEROUTPUT ON SIZE UNLIMITED
SET LINESIZE 250

DECLARE
  v_rc1 SYS_REFCURSOR;
  v_rc2 SYS_REFCURSOR;
  v_a VARCHAR2(4000);
  v_b VARCHAR2(4000);
  v_c VARCHAR2(4000);
BEGIN
  DMF0043_SAVE_DM_MST_CONTRIBUTE_VER(
    'I', '', '2026', 'TEST_VER_2026', '', 'Y', 'minyonglee1', v_rc1, v_rc2
  );
  -- v_rc1 fetch
  IF v_rc1 IS NOT NULL THEN
    LOOP
      FETCH v_rc1 INTO v_a, v_b, v_c;
      EXIT WHEN v_rc1%NOTFOUND;
      DBMS_OUTPUT.PUT_LINE('  RC1: ' || v_a || ' | ' || v_b || ' | ' || v_c);
    END LOOP;
    CLOSE v_rc1;
  END IF;
  COMMIT;
  DBMS_OUTPUT.PUT_LINE('  COMMIT OK');
EXCEPTION WHEN OTHERS THEN
  DBMS_OUTPUT.PUT_LINE('  ERR ' || SQLCODE || ': ' || SQLERRM);
  ROLLBACK;
END;
/

-- 직후 DB row 확인
SELECT MAX(VER_SEQ) AS MAX_VER, COUNT(*) AS TOTAL
  FROM DM_MST_CONTRIBUTE_VER;
SELECT VER_SEQ, YYYY, VERSION_NM, CREATED_BY,
       TO_CHAR(CREATION_DATE,'YYYY-MM-DD HH24:MI:SS') AS CD
  FROM DM_MST_CONTRIBUTE_VER
 WHERE YYYY = '2026' OR VERSION_NM LIKE '%TEST%';
