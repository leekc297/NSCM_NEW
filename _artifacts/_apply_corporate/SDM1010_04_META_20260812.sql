UNION ALL SELECT 'PROC', COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M WHERE PROC_NM LIKE 'PKG_SDM1010.%'
UNION ALL SELECT 'API', COUNT(*) FROM SCM_MGR.SCM_ADM_API_M WHERE API_ID LIKE 'SDM1010_%'
UNION ALL SELECT 'BTN', COUNT(*) FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID='SDM1010'
UNION ALL SELECT 'GR', COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_M WHERE USER_GR_ID LIKE 'SPMS%'
UNION ALL SELECT 'GR_MNU', COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_MPG_M WHERE MNU_ID IN ('SDM','SDM_Project','SDM1010')
UNION ALL SELECT 'GR_BTN', COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE MNU_ID='SDM1010'
UNION ALL SELECT 'MSG', COUNT(*) FROM SCM_MGR.SCM_ADM_MSG_M WHERE MSG_ID LIKE 'MNU_SDM%' OR (MSG_ID BETWEEN 'MSG00706' AND 'MSG00717') OR (MSG_ID BETWEEN 'LBL00855' AND 'LBL00862') OR MSG_ID LIKE 'MSG_API_SDM1010%'
UNION ALL SELECT 'ROUTE', COUNT(*) FROM SCM_MGR.SCM_ADM_MNU_M WHERE MNU_ID='SDM1010' AND ROUTE_PATH='sdm/project-reg';
