-- DMF0082 환율 Modal BPS I/F 버튼 (2026-07-12)
--   AS-IS: DMF0000_ExchangeRatePopup.btnBPS_Click → PR_SCM_MST_EXCHANGE_RATE(p_batch_yn='N') (ADMIN/DM ADMIN만).
--   Oracle 변환분은 성공/실패 output 누락(AS-IS 2025.06.24 이력의 화면호출 output 미이관) + P_BATCH_YN DEFAULT 'Y'.
--   → 공유 배치 proc 시그니처 변경(배치 호출 파손) 회피 위해 OUT 커서 보유 래퍼 proc 신설.
--       화면('N')=division 40 최신 I/F / 배치('Y')=81,82 전체. 성공=inner COMMIT / 실패=inner RAISE -20001 → 래퍼가 분류.

-- ── 래퍼 proc (OUT 커서: 표준 PROC_RESULT '0'/success | '9'/fail) ──
CREATE OR REPLACE PROCEDURE SCM_MGR.PR_SCM_MST_EXCHANGE_RATE_UI (
    P_BATCH_YN      IN  VARCHAR2 DEFAULT 'N',
    O_RESULT_CURSOR OUT SYS_REFCURSOR
) AS
    V_ERR VARCHAR2(200 CHAR);
BEGIN
    SCM_MGR.PR_SCM_MST_EXCHANGE_RATE(P_BATCH_YN);   -- 성공 시 inner 가 COMMIT
    OPEN O_RESULT_CURSOR FOR
        SELECT '0' AS CODE, 'success' AS RESULT_MSG, CAST(NULL AS VARCHAR2(200 CHAR)) AS EVENT FROM DUAL;
EXCEPTION
    WHEN OTHERS THEN
        V_ERR := SUBSTR(SQLERRM, 1, 200);            -- SQLERRM 은 순수 SQL 커서에서 직접 불가 → 변수 캡처
        ROLLBACK;                                    -- inner 는 RAISE 전 ROLLBACK 없음 → 부분 DML 정리
        OPEN O_RESULT_CURSOR FOR
            SELECT '9' AS CODE, 'fail' AS RESULT_MSG, V_ERR AS EVENT FROM DUAL;
END PR_SCM_MST_EXCHANGE_RATE_UI;
/
-- ⚠️ SCMD_APP 시노님은 SCM_MGR 권한 부족(ORA-01031)으로 미생성 — 로컬 BE(SCM_MGR 직결)는 불필요.
--    클라우드/SCMD_APP 접속 환경 배포 시 DBA 가 아래 실행:
--    CREATE OR REPLACE SYNONYM SCMD_APP.PR_SCM_MST_EXCHANGE_RATE_UI FOR SCM_MGR.PR_SCM_MST_EXCHANGE_RATE_UI;

