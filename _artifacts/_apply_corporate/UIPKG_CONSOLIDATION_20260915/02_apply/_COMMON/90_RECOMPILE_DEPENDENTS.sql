-- STEP 2 후처리 — PKG/호출부 교체 후 무효화된 의존 객체 재컴파일 (SCM_MGR · 멱등)
-- 사내 2026-09-15 18:59: DMF0043_GET_CONTRIBUTE_MAIN_DATA (래퍼 standalone 보정 후) 재컴파일 → VALID
BEGIN
  FOR r IN (SELECT OBJECT_NAME, OBJECT_TYPE FROM USER_OBJECTS WHERE STATUS='INVALID' AND OBJECT_TYPE IN ('PROCEDURE','PACKAGE','PACKAGE BODY','FUNCTION')
             AND OBJECT_NAME IN ('DMF0043_GET_CONTRIBUTE_MAIN_DATA','DMF0043_GET_MAIN_SPREAD_TITLE')) LOOP
    BEGIN
      IF r.OBJECT_TYPE = 'PACKAGE BODY' THEN EXECUTE IMMEDIATE 'ALTER PACKAGE "'||r.OBJECT_NAME||'" COMPILE BODY';
      ELSE EXECUTE IMMEDIATE 'ALTER '||r.OBJECT_TYPE||' "'||r.OBJECT_NAME||'" COMPILE'; END IF;
    EXCEPTION WHEN OTHERS THEN NULL; END;
  END LOOP;
END;
/
