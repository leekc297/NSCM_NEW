CREATE OR REPLACE PROCEDURE SCM_MGR."P_SYS0014_GET_USER_BY_GROUP_M" (
    P_USER_GR_ID     IN  VARCHAR2,
    O_RC1            OUT SYS_REFCURSOR,
    O_RESULT_CURSOR  OUT SYS_REFCURSOR
)
AS
BEGIN
    -- UserInfo 컬럼 (2026-06-26 조정): UserID/UserName/EnglishName/Email/Dept_Name/UseYN + 감사 4종 (Dept_ID 제외)
    OPEN O_RC1 FOR
    SELECT M.USER_ID,
           NVL(U.USER_NM, M.USER_ID)         AS USER_NM,
           U.USER_ENG_NM,
           U.USER_EML,
           (SELECT D.DEPT_NAME_KO FROM SCM_MGR.SCM_MST_SSO_DEPT_INFO D WHERE D.DEPT_ID = U.DEPT_ID) AS DEPT_NM,
