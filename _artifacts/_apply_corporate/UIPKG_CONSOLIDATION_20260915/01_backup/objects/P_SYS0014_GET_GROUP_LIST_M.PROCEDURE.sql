CREATE OR REPLACE PROCEDURE SCM_MGR."P_SYS0014_GET_GROUP_LIST_M" (
    P_SEARCH         IN  VARCHAR2,
    O_RC1            OUT SYS_REFCURSOR,
    O_RESULT_CURSOR  OUT SYS_REFCURSOR
)
AS
BEGIN
    OPEN O_RC1 FOR
    SELECT USER_GR_ID, USER_GR_NM, USE_YN
      FROM SCM_MGR.SCM_ADM_USER_GR_M
     WHERE P_SEARCH IS NULL OR P_SEARCH = ''
        OR UPPER(USER_GR_ID) LIKE '%' || UPPER(P_SEARCH) || '%'
        OR UPPER(USER_GR_NM) LIKE '%' || UPPER(P_SEARCH) || '%'
     ORDER BY USER_GR_ID;

    OPEN O_RESULT_CURSOR FOR
    SELECT '0' AS CODE, 'SUCCESS' AS MSG FROM DUAL;
EXCEPTION
    WHEN OTHERS THEN
        DECLARE V_ERR VARCHAR2(4000) := SUBSTR(SQLERRM, 1, 4000);
        BEGIN
            OPEN O_RC1 FOR SELECT NULL AS DUMMY FROM DUAL WHERE 1=0;
            OPEN O_RESULT_CURSOR FOR SELECT '-1' AS CODE, V_ERR AS MSG FROM DUAL;
        END;
END P_SYS0014_GET_GROUP_LIST_M;
