-- ① 접속 대상 (2026-09-14 16:30 기준: zioui1 / ZIOUI1 / ol9-db / PDB CREATION 09-14 14:10)
SELECT SYS_CONTEXT('USERENV','SERVICE_NAME') SVC, SYS_CONTEXT('USERENV','CON_NAME') CON,
       SYS_CONTEXT('USERENV','SERVER_HOST') HOST, SYS_CONTEXT('USERENV','DB_UNIQUE_NAME') DB
  FROM DUAL;

-- ② 대상 객체 상태 + 오늘 마커 존재 여부 (적용 전 기대: DMF0040·DMF0053 마커 0 / NSCM_UI_EXCEL 마커 1)
SELECT O.OBJECT_NAME, O.OBJECT_TYPE, O.STATUS, TO_CHAR(O.LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL,
       (SELECT COUNT(*) FROM ALL_SOURCE S
         WHERE S.OWNER = O.OWNER AND S.NAME = O.OBJECT_NAME AND S.TYPE = O.OBJECT_TYPE
           AND (S.TEXT LIKE '%E20260914-MULTISEL%' OR S.TEXT LIKE '%E20260914-DMF0053FLT%' OR S.TEXT LIKE '%E20260914-EXCELROW%')) MARKER_LINES
  FROM ALL_OBJECTS O
 WHERE O.OWNER = 'SCM_MGR'
   AND O.OBJECT_NAME IN ('PKG_DMF0040', 'PKG_DMF0053', 'PKG_NSCM_UI_EXCEL')
   AND O.OBJECT_TYPE = 'PACKAGE BODY'
 ORDER BY O.OBJECT_NAME;

-- 03 대상: SCMP_APP 시노님 (적용 전 기대 0)
SELECT COUNT(*) SYN_PKG_DMF0053 FROM ALL_SYNONYMS WHERE OWNER = 'SCMP_APP' AND SYNONYM_NAME = 'PKG_DMF0053';

-- ③ 데이터
-- 04 SYS0005: 기대(적용 전) = PKG_SYS0005|PKG_SYS0005 1행, SCM_MGR|PKG_ 행 없음
SELECT SEGMENT1, SEGMENT2, VALID_YN, CREATED_BY FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = 'UI_PKG_NM';
-- 05 DMF0074: 기대(이미 반영) = HEADER 가 'Period(Fr)_Ni' 형태 (구값은 'PeriodFr_Ni')
SELECT PROGRAM_ID, INSTR(HEADER_CONTENT, 'Period(Fr)_Ni') NEW_FORM, INSTR(HEADER_CONTENT, 'PeriodFr_Ni') OLD_FORM
  FROM SCM_MGR.SCM_ADM_EXCEL_COLUMNS WHERE PROGRAM_ID IN ('DMF0074', 'DMF0074_40') AND SHEET_NAME = 'Metal Link Price';
-- 07 SYS0006: 기대(이미 반영) = 5 코드 SEGMENT2 LBL/명칭
SELECT SEGMENT1, SEGMENT2, DISPLAY_SEQ FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = 'API_TP_CD' ORDER BY DISPLAY_SEQ;
