-- 컴파일 상태: 전부 VALID, 오류 0 기대
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL
  FROM ALL_OBJECTS
 WHERE OWNER = 'SCM_MGR' AND OBJECT_NAME IN ('PKG_DMF0040', 'PKG_DMF0053', 'PKG_NSCM_UI_EXCEL')
 ORDER BY OBJECT_NAME, OBJECT_TYPE;
SELECT NAME, TYPE, LINE, POSITION, TEXT FROM ALL_ERRORS
 WHERE OWNER = 'SCM_MGR' AND NAME IN ('PKG_DMF0040', 'PKG_DMF0053', 'PKG_NSCM_UI_EXCEL');

-- 마커 행수 기대: PKG_DMF0040 MULTISEL ≥ 6 곳 / PKG_DMF0053 DMF0053FLT ≥ 3 곳 / PKG_NSCM_UI_EXCEL EXCELROW ≥ 1
SELECT NAME,
       SUM(CASE WHEN TEXT LIKE '%E20260914-MULTISEL%'   THEN 1 ELSE 0 END) MULTISEL,
       SUM(CASE WHEN TEXT LIKE '%E20260914-DMF0053FLT%' THEN 1 ELSE 0 END) DMF0053FLT,
       SUM(CASE WHEN TEXT LIKE '%E20260914-EXCELROW%'   THEN 1 ELSE 0 END) EXCELROW
  FROM ALL_SOURCE
 WHERE OWNER = 'SCM_MGR' AND TYPE = 'PACKAGE BODY' AND NAME IN ('PKG_DMF0040', 'PKG_DMF0053', 'PKG_NSCM_UI_EXCEL')
 GROUP BY NAME ORDER BY NAME;

-- 결함 원문 잔존 0 기대 (Oracle ''=NULL 사문화 조건)
SELECT NAME, LINE, TRIM(TEXT) TXT FROM ALL_SOURCE
 WHERE OWNER = 'SCM_MGR' AND TYPE = 'PACKAGE BODY' AND NAME IN ('PKG_DMF0040', 'PKG_DMF0053')
   AND REGEXP_LIKE(TEXT, 'IS NOT NULL AND P_[A-Z_]+ <> ''''');

-- 시노님 1 기대
SELECT OWNER, SYNONYM_NAME, TABLE_OWNER, TABLE_NAME FROM ALL_SYNONYMS WHERE OWNER = 'SCMP_APP' AND SYNONYM_NAME = 'PKG_DMF0053';

-- SYS0005: SCM_MGR|PKG_|Y 행 존재 기대 (기존 PKG_SYS0005 행은 그대로)
SELECT SEGMENT1, SEGMENT2, VALID_YN, CREATED_BY FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = 'UI_PKG_NM';

-- DMF0074: NEW_FORM > 0, OLD_FORM = 0 기대
SELECT PROGRAM_ID, INSTR(HEADER_CONTENT, 'Period(Fr)_Ni') NEW_FORM, INSTR(HEADER_CONTENT, 'PeriodFr_Ni') OLD_FORM
  FROM SCM_MGR.SCM_ADM_EXCEL_COLUMNS WHERE PROGRAM_ID IN ('DMF0074', 'DMF0074_40') AND SHEET_NAME = 'Metal Link Price';

-- SYS0006: 5 코드 각 1행 기대
SELECT SEGMENT1, COUNT(*) CNT, MAX(SEGMENT2) SEGMENT2 FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE = 'API_TP_CD' GROUP BY SEGMENT1 ORDER BY SEGMENT1;

