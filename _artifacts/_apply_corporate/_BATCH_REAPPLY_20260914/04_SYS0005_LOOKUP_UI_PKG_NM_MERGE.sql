-- [E20260914-SYS0005LKP] SYS0005 Procedure Setting — UI_PKG_NM 룩업에 'SCM_MGR' + 'PKG_'(SCM_MGR 소유 PKG 전체) 등록 (사용자 확정 2026-09-14)
-- PKG_SYS0005.SYS0005_GET_MAIN_DATA 는 ALL_ARGUMENTS.OWNER = SEGMENT1 AND PACKAGE_NAME LIKE SEGMENT2||'%' (EXISTS — 행이 여러 개면 합집합, 중복 없음).
-- ⚠ 멱등·비파괴: 목표 행만 MERGE 한다. 기존 행은 지우지 않는다
--   (원설계 = 접두어별 다건 행: PKG_SYS/SCM/COM/DMF/SCP/SSP — 클라우드 미러 SCM_ADM_LOOKUP_MASTER_DETAIL_BAK 04-13).
--   구판(1차)은 WHERE 를 사내 적용 전 값에 고정해 클라우드(SCM_MGR+PKG_SYS0005)에서 0건 갱신 — 2026-09-14 정정.

-- [사전 확인]
SELECT SEGMENT1, SEGMENT2, VALID_YN, DESCRIPTION FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = 'UI_PKG_NM' ORDER BY DISPLAY_SEQ, SEGMENT2;

MERGE INTO SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL T
USING (SELECT 'UI_PKG_NM' AS LOOKUP_TYPE, 'SCM_MGR' AS SEGMENT1, 'PKG_' AS SEGMENT2, '-' AS SEGMENT3, '-' AS SEGMENT4, '-' AS SEGMENT5 FROM DUAL) S
   ON (T.LOOKUP_TYPE = S.LOOKUP_TYPE AND T.SEGMENT1 = S.SEGMENT1 AND T.SEGMENT2 = S.SEGMENT2
       AND T.SEGMENT3 = S.SEGMENT3 AND T.SEGMENT4 = S.SEGMENT4 AND T.SEGMENT5 = S.SEGMENT5)
 WHEN MATCHED THEN UPDATE SET T.VALID_YN = 'Y', T.LAST_UPDATED_BY = 'admin', T.LAST_UPDATE_DATE = SYSDATE
 WHEN NOT MATCHED THEN INSERT (LOOKUP_TYPE, SEGMENT1, SEGMENT2, SEGMENT3, SEGMENT4, SEGMENT5, DISPLAY_SEQ, VALID_YN, DESCRIPTION, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
      VALUES (S.LOOKUP_TYPE, S.SEGMENT1, S.SEGMENT2, S.SEGMENT3, S.SEGMENT4, S.SEGMENT5, 0, 'Y', 'All UI Package', 'admin', SYSDATE, 'admin', SYSDATE);

COMMIT;

-- [사후 확인] 기대: SCM_MGR | PKG_ | Y 행 존재 (기존 행은 그대로)
SELECT SEGMENT1, SEGMENT2, VALID_YN, DESCRIPTION FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE = 'UI_PKG_NM' ORDER BY DISPLAY_SEQ, SEGMENT2;
