-- DMF0082 [E20260904-SCPLIMIT] 검증

-- V1. 패키지 상태 (기대: VALID / 에러 0)
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI') LAST_DDL
  FROM ALL_OBJECTS WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_DMF0082';
SELECT COUNT(*) ERR FROM ALL_ERRORS WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082';

-- V2. 마커 실장 (기대 2곳: 일반 GET / CURRENT) + 81AUTH 보다 앞인지 (SCPLIMIT < 81AUTH)
SELECT LINE, TRIM(SUBSTR(TEXT,1,60)) TXT FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY'
   AND (INSTR(TEXT,'E20260904-SCPLIMIT')>0 OR INSTR(TEXT,'[E20260825-81AUTH] LIMIT_AUTH')>0)
 ORDER BY LINE;

-- V3. 규칙 대상 룩업 행 (기대: 시간창 정의 행 = 40/SCM_FCST 3건, LIMIT=MKT_FCST)
SELECT SEGMENT1, SEGMENT3, SEGMENT4, ATTRIBUTE1 DAYS, ATTRIBUTE2 FROM_T, ATTRIBUTE3 TO_T, ATTRIBUTE4 LIMIT_MEASURE
  FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE='GET_ADMIN_GROUP_MEASURE' AND VALID_YN='Y' AND SEGMENT2='DMF0082'
   AND REPLACE(ATTRIBUTE4,' ','') IS NOT NULL AND REPLACE(ATTRIBUTE1,' ','') IS NOT NULL
 ORDER BY SEGMENT3, SEGMENT1;

-- V4. 지금 시각 기준 발동 여부 (시간창 밖이면 0 = 동작 불변)
SELECT TO_CHAR(SYSDATE,'YYYY-MM-DD DY HH24MI','NLS_DATE_LANGUAGE=ENGLISH') NOW_INFO, COUNT(*) HIT_NOW
  FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL L
 WHERE L.LOOKUP_TYPE='GET_ADMIN_GROUP_MEASURE' AND L.VALID_YN='Y' AND L.SEGMENT2='DMF0082'
   AND REPLACE(L.ATTRIBUTE4,' ','') IS NOT NULL AND REPLACE(L.ATTRIBUTE1,' ','') IS NOT NULL
   AND REPLACE(L.ATTRIBUTE2,' ','') IS NOT NULL AND REPLACE(L.ATTRIBUTE3,' ','') IS NOT NULL
   AND INSTR(','||REPLACE(L.ATTRIBUTE1,' ','')||',', ','||TO_CHAR(SYSDATE,'DY','NLS_DATE_LANGUAGE=ENGLISH')||',')>0
   AND L.ATTRIBUTE2<=TO_CHAR(SYSDATE,'HH24MI') AND L.ATTRIBUTE3>=TO_CHAR(SYSDATE,'HH24MI')
 GROUP BY TO_CHAR(SYSDATE,'YYYY-MM-DD DY HH24MI','NLS_DATE_LANGUAGE=ENGLISH');

-- V5. 시간창 안(월 16:00) 가정 시 어떤 메저가 잠기는지 — 배포 문장과 동일 조건
WITH M AS (SELECT DISTINCT SEGMENT4 AS MEASURE FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
            WHERE LOOKUP_TYPE='GET_ADMIN_GROUP_MEASURE' AND SEGMENT2='DMF0082')
SELECT M.MEASURE,
       CASE WHEN EXISTS (
         SELECT 1 FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL L
         CROSS JOIN LATERAL (SELECT REGEXP_SUBSTR(L.ATTRIBUTE4,'[^,]+',1,LEVEL) AS TOKEN
                             FROM DUAL CONNECT BY LEVEL <= NVL(REGEXP_COUNT(L.ATTRIBUTE4,','),0)+1) LM
         WHERE L.LOOKUP_TYPE='GET_ADMIN_GROUP_MEASURE' AND L.VALID_YN='Y'
           AND L.SEGMENT2='DMF0082' AND L.SEGMENT3='40'
           AND REPLACE(L.ATTRIBUTE4,' ','') IS NOT NULL AND REPLACE(L.ATTRIBUTE1,' ','') IS NOT NULL
           AND REPLACE(L.ATTRIBUTE2,' ','') IS NOT NULL AND REPLACE(L.ATTRIBUTE3,' ','') IS NOT NULL
           AND INSTR(','||REPLACE(L.ATTRIBUTE1,' ','')||',', ',MON,')>0
           AND L.ATTRIBUTE2<='1600' AND L.ATTRIBUTE3>='1600'
           AND TRIM(LM.TOKEN)=M.MEASURE) THEN 'N' ELSE '(불변)' END AS AT_MON_1600
  FROM M ORDER BY 1;
