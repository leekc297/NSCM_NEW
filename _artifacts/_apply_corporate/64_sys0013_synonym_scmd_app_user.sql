-- ============================================================================
-- 64. SYS0013 — SCMD_APP SYNONYM 생성 (⚠ SCMD_APP user 로 접속 후 실행)
-- ----------------------------------------------------------------------------
-- 사유: SCM_MGR 는 SYNONYM 생성 권한 없음 (CREATE ANY SYNONYM 없음)
-- 적용: DBA 또는 SCMD_APP user 로 직접 접속 후 실행
--
-- 사내 DB 접속:
--   sqlplus SCMD_APP/<password>@121.162.245.167:2521/ESSCMD
-- ============================================================================

CREATE OR REPLACE SYNONYM SYS0013_GET_QUERY_LIST           FOR SCM_MGR.SYS0013_GET_QUERY_LIST;
CREATE OR REPLACE SYNONYM SYS0013_GET_COLUMNS              FOR SCM_MGR.SYS0013_GET_COLUMNS;
CREATE OR REPLACE SYNONYM SYS0013_GET_PARAMETERS           FOR SCM_MGR.SYS0013_GET_PARAMETERS;
CREATE OR REPLACE SYNONYM SYS0013_EXECUTE_QUERY            FOR SCM_MGR.SYS0013_EXECUTE_QUERY;
CREATE OR REPLACE SYNONYM SYS0013_GET_QUERY_LIST_COMMON    FOR SCM_MGR.SYS0013_GET_QUERY_LIST_COMMON;
CREATE OR REPLACE SYNONYM SYS0013_GET_DYNAMIC_QUERYS       FOR SCM_MGR.SYS0013_GET_DYNAMIC_QUERYS;
CREATE OR REPLACE SYNONYM SYS0013_GET_ROLE_DATA            FOR SCM_MGR.SYS0013_GET_ROLE_DATA;
CREATE OR REPLACE SYNONYM PKG_SYS0013                      FOR SCM_MGR.PKG_SYS0013;

-- 검증
SELECT SYNONYM_NAME, TABLE_OWNER, TABLE_NAME
  FROM USER_SYNONYMS
 WHERE SYNONYM_NAME LIKE 'SYS0013_%' OR SYNONYM_NAME='PKG_SYS0013'
 ORDER BY SYNONYM_NAME;
