SET PAGESIZE 100
SET LINESIZE 200

-- V1. SenderCode 콤보 등록 1행
SELECT 'V1 CMBO SenderCode' AS CHK,
       CASE WHEN COUNT(*)=1 THEN 'PASS' ELSE 'FAIL('||COUNT(*)||')' END AS RESULT
  FROM SCM_MGR.SCM_ADM_CMBO_SQL_M WHERE SQL_ID='SenderCode' AND USE_YN='Y';

-- V2. SenderCode SQL 실행 가능 + 행수 (VALID_YN='Y' lookup 15행 기대)
SELECT 'V2 EDI_SENDER_CODE rows' AS CHK,
       CASE WHEN COUNT(*)>=1 THEN 'PASS('||COUNT(*)||')' ELSE 'FAIL(0)' END AS RESULT
  FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE='EDI_SENDER_CODE' AND VALID_YN='Y';

-- V3. titleset ITEM_NAME 1행
SELECT 'V3 TITLESET ITEM_NAME' AS CHK,
       CASE WHEN COUNT(*)=1 THEN 'PASS' ELSE 'FAIL('||COUNT(*)||')' END AS RESULT
  FROM SCM_MGR.SCM_MST_TITLESET_USER
 WHERE USER_ID='minyonglee1' AND PROGRAM_ID='DMF0003' AND SHEET_NAME='Mkt Fcst'
   AND USER_INQUIRY_COLUMN_TYPE_CODE='C' AND COLUMN_NAME='ITEM_NAME';

-- V4. SHEET_COLUMNS 정합 (SP c_title JOIN 대상 — ITEM_NAME 메타 유효)
SELECT 'V4 SHEET_COLUMNS ITEM_NAME' AS CHK,
       CASE WHEN COUNT(*)>=1 THEN 'PASS' ELSE 'FAIL' END AS RESULT
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID='DMF0003' AND SHEET_NAME='Mkt Fcst' AND COLUMN_NAME='ITEM_NAME' AND VALID_YN='Y';

EXIT;
