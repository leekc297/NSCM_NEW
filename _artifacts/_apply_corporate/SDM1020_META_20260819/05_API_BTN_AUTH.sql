-- API_ID 시트 토큰: 시트명 'Project List' 는 공백 포함 → API_ID 공백 사용 전례 0건 실측,
--   공백 시트 화면 전례(DMF0003 'Mkt Fcst'→DMF0003_main_*) 그대로 'main' 토큰 채택. SHT_NM 은 실명 'Project List'.
-- 액션 구성(SDM1010 참조 — SDM1020 은 SAVE/INSERT/DELETE/CANCEL 없음, 설계서 저장/삭제=<해당없음>):
--   SEARCH/EXCEL/FILTER/SORT → P_SDM1020_GET_PJT_LIST (PROC_SELECT)
--   REQ(등록요청)            → P_SDM1020_BTN_REQ_PJT_REG (PROC_SAVE)
--   AUTHREQ(권한요청 링크)   → P_SDM1020_REQ_PJT_AUTH (PROC_SAVE)
--   period/SEARCH            → PR_GET_DAY_RANGE (PROC_SELECT, 실존 확인 — SDM1010 period 시트 관례)
--   CONDITION 코드는 전 DB 사용 전례 0건(SDM1010 미등재) — 등재하지 않음.
-- 권한관리 팝업(POP1_*)은 SDM1010 메뉴 소유 메타 재사용 — SDM1020 쪽 등재 없음.
-- 멱등: NOT EXISTS (SDM1010 템플릿 방식)
-- =====================================================================================

-- [5-1] MSG_API (7 API × 3언어 = 21)
INSERT INTO SCM_MGR.SCM_ADM_MSG_M (MSG_ID, LANG_CD, MSG_NM, MSG_DESC, MSG_TP_CD, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'MSG_API_' || T.AI, L.LC, T.NM, 'SDM1020 API', 'MSG', 'Y', 'admin', SYSDATE, 'admin', SYSDATE
  FROM (
    SELECT 'SDM1020_main_SEARCH' AI, 'SDM1020 MAIN SEARCH' NM FROM DUAL
    UNION ALL
    SELECT 'SDM1020_main_EXCEL' AI, 'SDM1020 MAIN EXCEL' NM FROM DUAL
    UNION ALL
    SELECT 'SDM1020_main_FILTER' AI, 'SDM1020 MAIN FILTER' NM FROM DUAL
    UNION ALL
    SELECT 'SDM1020_main_SORT' AI, 'SDM1020 MAIN SORT' NM FROM DUAL
    UNION ALL
    SELECT 'SDM1020_main_REQ' AI, 'SDM1020 MAIN REQ' NM FROM DUAL
    UNION ALL
    SELECT 'SDM1020_main_AUTHREQ' AI, 'SDM1020 MAIN AUTHREQ' NM FROM DUAL
    UNION ALL
    SELECT 'SDM1020_period_SEARCH' AI, 'SDM1020 PERIOD SEARCH' NM FROM DUAL
  ) T
 CROSS JOIN (SELECT 'KO' LC FROM DUAL UNION ALL SELECT 'EN' FROM DUAL UNION ALL SELECT 'CN' FROM DUAL) L
 WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_MSG_M X WHERE X.MSG_ID = 'MSG_API_' || T.AI AND X.LANG_CD = L.LC);

-- [5-2] API_M (7)
INSERT INTO SCM_MGR.SCM_ADM_API_M (API_ID, API_TP_CD, API_MSG_ID, API_URL, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT T.AI, T.AT, 'MSG_API_' || T.AI, T.AU, 'Y', 'admin', SYSDATE, 'admin', SYSDATE
  FROM (
    SELECT 'SDM1020_main_SEARCH' AI, 'PROC_SELECT' AT, 'PKG_SDM1020.P_SDM1020_GET_PJT_LIST' AU FROM DUAL
    UNION ALL
    SELECT 'SDM1020_main_EXCEL' AI, 'PROC_SELECT' AT, 'PKG_SDM1020.P_SDM1020_GET_PJT_LIST' AU FROM DUAL
    UNION ALL
    SELECT 'SDM1020_main_FILTER' AI, 'PROC_SELECT' AT, 'PKG_SDM1020.P_SDM1020_GET_PJT_LIST' AU FROM DUAL
    UNION ALL
    SELECT 'SDM1020_main_SORT' AI, 'PROC_SELECT' AT, 'PKG_SDM1020.P_SDM1020_GET_PJT_LIST' AU FROM DUAL
    UNION ALL
    SELECT 'SDM1020_main_REQ' AI, 'PROC_SAVE' AT, 'PKG_SDM1020.P_SDM1020_BTN_REQ_PJT_REG' AU FROM DUAL
    UNION ALL
    SELECT 'SDM1020_main_AUTHREQ' AI, 'PROC_SAVE' AT, 'PKG_SDM1020.P_SDM1020_REQ_PJT_AUTH' AU FROM DUAL
    UNION ALL
    SELECT 'SDM1020_period_SEARCH' AI, 'PROC_SELECT' AT, 'PR_GET_DAY_RANGE' AU FROM DUAL
  ) T
 WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_API_M X WHERE X.API_ID = T.AI);

-- [5-3] MNU_BTN_MPG_M (7)
INSERT INTO SCM_MGR.SCM_ADM_MNU_BTN_MPG_M (MNU_ID, SHT_NM, MNU_BTN_CD, API_ID, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'SDM1020', T.SH, T.BC, T.AI, 'Y', 'admin', SYSDATE, 'admin', SYSDATE
  FROM (
    SELECT 'Project List' SH, 'SEARCH' BC, 'SDM1020_main_SEARCH' AI FROM DUAL
    UNION ALL
    SELECT 'Project List' SH, 'EXCEL' BC, 'SDM1020_main_EXCEL' AI FROM DUAL
    UNION ALL
    SELECT 'Project List' SH, 'FILTER' BC, 'SDM1020_main_FILTER' AI FROM DUAL
    UNION ALL
    SELECT 'Project List' SH, 'SORT' BC, 'SDM1020_main_SORT' AI FROM DUAL
    UNION ALL
    SELECT 'Project List' SH, 'REQ' BC, 'SDM1020_main_REQ' AI FROM DUAL
    UNION ALL
    SELECT 'Project List' SH, 'AUTHREQ' BC, 'SDM1020_main_AUTHREQ' AI FROM DUAL
    UNION ALL
    SELECT 'period' SH, 'SEARCH' BC, 'SDM1020_period_SEARCH' AI FROM DUAL
  ) T
 WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M X
                    WHERE X.MNU_ID = 'SDM1020' AND X.SHT_NM = T.SH AND X.MNU_BTN_CD = T.BC);

-- [5-4] 권한그룹 → 메뉴 매핑 (3그룹 × SDM1020 = 3. 상위 SDM/SDM_Project 는 3그룹 기존재 실측 확인 — 추가 없음)
INSERT INTO SCM_MGR.SCM_ADM_USER_GR_MNU_MPG_M (USER_GR_ID, MNU_ID, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT G.GI, 'SDM1020', 'Y', 'admin', SYSDATE, 'admin', SYSDATE
  FROM (SELECT 'ADMIN' GI FROM DUAL UNION ALL SELECT 'SPMS Administrator' FROM DUAL UNION ALL SELECT 'SPMS Planner' FROM DUAL) G
 WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_USER_GR_MNU_MPG_M X WHERE X.USER_GR_ID = G.GI AND X.MNU_ID = 'SDM1020');

-- [5-5] 권한그룹 → 버튼 매핑 (3그룹 × 7버튼 = 21)
INSERT INTO SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M (USER_GR_ID, MNU_ID, SHT_NM, MNU_BTN_CD, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT G.GI, B.MNU_ID, B.SHT_NM, B.MNU_BTN_CD, 'Y', 'admin', SYSDATE, 'admin', SYSDATE
  FROM (SELECT 'ADMIN' GI FROM DUAL UNION ALL SELECT 'SPMS Administrator' FROM DUAL UNION ALL SELECT 'SPMS Planner' FROM DUAL) G
 CROSS JOIN (SELECT MNU_ID, SHT_NM, MNU_BTN_CD FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID = 'SDM1020') B
 WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M X
                    WHERE X.USER_GR_ID = G.GI AND X.MNU_ID = B.MNU_ID AND X.SHT_NM = B.SHT_NM AND X.MNU_BTN_CD = B.MNU_BTN_CD);

COMMIT;
