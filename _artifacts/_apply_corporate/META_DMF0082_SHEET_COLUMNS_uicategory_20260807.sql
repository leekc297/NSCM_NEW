-- [1] 필수 키 5컬럼 토큰 확장 (FcstNPrice 표기 순서: 40,81,...,82)
UPDATE SCM_MGR.SCM_MST_SHEET_COLUMNS
SET    DIVISION_ID      = '40,81,81_UC,81_HM,81_ST,81_HD,81_HG,82'
     , LAST_UPDATED_BY  = 'admin'
     , LAST_UPDATE_DATE = SYSDATE
WHERE  PROGRAM_ID  = 'DMF0082'
AND    SHEET_NAME  = 'FcstNPrice'
AND    COLUMN_NAME IN ('DIVISION_ID','END_CUSTOMER','SCM_SITE_ID','ITEM_ID','CELL_PROD_SITE_ID')
AND    DIVISION_ID = '40';

-- [2] 신규 17컬럼 — DMF0003 'Mkt Fcst' 행 변환 복제 (NOT EXISTS 멱등)
INSERT INTO SCM_MGR.SCM_MST_SHEET_COLUMNS
    ( PROGRAM_ID, SHEET_NAME, COLUMN_NAME, COLUMN_LABEL_NAME, SORT_ORDER_NO
    , DATA_SORT_METHOD_CODE, SMALL_CLASS_LABEL_NAME, LARGE_CLASS_LABEL_NAME
    , FIXED_FLAG, COLUMN_WIDTH, CELL_CONTROL_OBJECT_TYPE_CODE, CELL_COMBO_DATA_TYPE
    , DATA_SCALE_NUMBER, DATA_MAX_LENGTH, HORIZONTAL_ALIGN_CODE, UPPERCASE_APPLY_FLAG
    , VISIBLE_FLAG, DIVISION_ID, DEFAULT_FLAG, USER_SELECTABLE_FLAG, VALID_YN
    , CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE
    , ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5
    , ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10
    , INPUT_TP_CD )
SELECT 'DMF0082', 'FcstNPrice', S.COLUMN_NAME, S.COLUMN_LABEL_NAME
     , CASE S.COLUMN_NAME                       -- FcstNPrice 배치 (DMF0003 상대 순서 승계)
           WHEN 'TEAM_NAME_KO'        THEN 22   -- TEAM_ID(20) 뒤
           WHEN 'PROJECT_S_OP_REPORT' THEN 23
           WHEN 'BIZ_TYPE'            THEN 32   -- END_CUSTOMER(30) 뒤
           WHEN 'PROJECT_CODE'        THEN 71   -- SCM_SITE_ID(70) 뒤
           WHEN 'PROJECT_NAME'        THEN 72
           WHEN 'PROJECT_STATUS'      THEN 73
           WHEN 'PROJECT_OWNER'       THEN 74
           WHEN 'PLANT_SITE_ID'       THEN 121  -- ITEM_TYPE(120) 뒤
           WHEN 'CELL_PER_CAR'        THEN 291  -- CELL_MODEL_NICK_NAME(290) 뒤
           WHEN 'CELL_PER_MODULE'     THEN 292
           WHEN 'MODULE_PER_CAR'      THEN 293
           WHEN 'ENERGE'              THEN 294
           WHEN 'CELL_QUANTITY'       THEN 295
           WHEN 'NEW_FLAG'            THEN 434  -- SORT_KEY(430) 뒤 캐리어 구간
           WHEN 'ATTR1'               THEN 435
           WHEN 'VMI_STD_DIO'         THEN 436
           WHEN 'AS_YN'               THEN 437
       END
     , S.DATA_SORT_METHOD_CODE, S.SMALL_CLASS_LABEL_NAME
     , CASE WHEN S.COLUMN_NAME = 'AS_YN' THEN 'AS_YN' ELSE S.LARGE_CLASS_LABEL_NAME END
     , S.FIXED_FLAG, S.COLUMN_WIDTH, S.CELL_CONTROL_OBJECT_TYPE_CODE, S.CELL_COMBO_DATA_TYPE
     , S.DATA_SCALE_NUMBER, S.DATA_MAX_LENGTH, S.HORIZONTAL_ALIGN_CODE, S.UPPERCASE_APPLY_FLAG
     , CASE WHEN S.COLUMN_NAME IN ('NEW_FLAG','ATTR1','VMI_STD_DIO','AS_YN') THEN 'N' ELSE 'Y' END
     , S.DIVISION_ID, S.DEFAULT_FLAG, S.USER_SELECTABLE_FLAG, S.VALID_YN
     , 'admin', SYSDATE, 'admin', SYSDATE
     , S.ATTRIBUTE1, S.ATTRIBUTE2, S.ATTRIBUTE3, S.ATTRIBUTE4, S.ATTRIBUTE5
     , S.ATTRIBUTE6, S.ATTRIBUTE7, S.ATTRIBUTE8, S.ATTRIBUTE9, S.ATTRIBUTE10
     , S.INPUT_TP_CD
FROM   SCM_MGR.SCM_MST_SHEET_COLUMNS S
WHERE  S.PROGRAM_ID  = 'DMF0003'
AND    S.SHEET_NAME  = 'Mkt Fcst'
AND    S.COLUMN_NAME IN ('PROJECT_CODE','PROJECT_NAME','PROJECT_STATUS','PROJECT_OWNER'
                        ,'PLANT_SITE_ID','BIZ_TYPE','ENERGE','CELL_QUANTITY'
                        ,'CELL_PER_CAR','CELL_PER_MODULE','MODULE_PER_CAR'
                        ,'PROJECT_S_OP_REPORT','TEAM_NAME_KO','AS_YN','ATTR1','VMI_STD_DIO','NEW_FLAG')
AND    NOT EXISTS (
           SELECT 1 FROM SCM_MGR.SCM_MST_SHEET_COLUMNS T
           WHERE  T.PROGRAM_ID  = 'DMF0082'
           AND    T.SHEET_NAME  = 'FcstNPrice'
           AND    T.COLUMN_NAME = S.COLUMN_NAME);

COMMIT;

