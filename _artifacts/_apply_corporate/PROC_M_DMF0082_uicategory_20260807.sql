-- GET / CURRENT 2종: IN 1~13 유지 + 신규 IN 14~16(projectCode/owner/senderCode) + OUT 6행 17~22 shift
-- 원천 = ADM_PROC_M_BAK_DMF0082_0807 (38행 백업). BE makeProcedure = SORT_ORD positional.
-- ⚠️ PKG 시그니처 확장 직후 즉시 적용 의무 (구 PROC_M = PLS-00306 화면 파손 구간)
-- =====================================================================

DELETE FROM SCM_MGR.SCM_ADM_PROC_M
WHERE PROC_NM LIKE 'PKG_DMF0082.P_DMF0082_GET_MAIN_DATA%';

-- [1] 기존 IN 1~13 원복사 (감사 갱신만)
INSERT INTO SCM_MGR.SCM_ADM_PROC_M
    (PROC_NM, COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT PROC_NM, COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD, CREATED_BY, CREATION_DATE, 'admin', SYSDATE
FROM   SCM_MGR.ADM_PROC_M_BAK_DMF0082_0807
WHERE  SORT_ORD <= 13;

-- [2] 신규 IN 14~16 (plantSiteId(13) 행과 동일 타입 — VARCHAR/IN)
INSERT INTO SCM_MGR.SCM_ADM_PROC_M
    (PROC_NM, COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT P.PROC_NM, N.COL_NM, 'VARCHAR', 'IN', N.ORD, 'admin', SYSDATE, 'admin', SYSDATE
FROM   (SELECT DISTINCT PROC_NM FROM SCM_MGR.ADM_PROC_M_BAK_DMF0082_0807) P
CROSS JOIN (
    SELECT 'projectCode' AS COL_NM, 14 AS ORD FROM DUAL
    UNION ALL SELECT 'owner',      15 FROM DUAL
    UNION ALL SELECT 'senderCode', 16 FROM DUAL
) N;

-- [3] OUT 6행 17~22 shift (원 14~19)
INSERT INTO SCM_MGR.SCM_ADM_PROC_M
    (PROC_NM, COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT PROC_NM, COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD + 3, CREATED_BY, CREATION_DATE, 'admin', SYSDATE
FROM   SCM_MGR.ADM_PROC_M_BAK_DMF0082_0807
WHERE  SORT_ORD >= 14;

COMMIT;

-- [검증] 기대: SP 당 22행 (IN 16 + OUT 6) × 2 = 44
SELECT PROC_NM, COUNT(*) CNT,
       SUM(CASE WHEN COL_TP_CD='IN' THEN 1 ELSE 0 END) IN_CNT,
       SUM(CASE WHEN COL_TP_CD='OUT' THEN 1 ELSE 0 END) OUT_CNT
FROM   SCM_MGR.SCM_ADM_PROC_M
WHERE  PROC_NM LIKE 'PKG_DMF0082.P_DMF0082_GET_MAIN_DATA%'
GROUP BY PROC_NM;
