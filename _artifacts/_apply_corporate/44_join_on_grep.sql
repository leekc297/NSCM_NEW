SET LINESIZE 300

-- SP body 의 SITE_ITEM = RATIO JOIN ON 부분
SELECT LINE, SUBSTR(TEXT, 1, 250) AS SRC FROM USER_SOURCE WHERE NAME='DMF0043_GET_CONTRIBUTE_MAIN_DATA' AND TYPE='PROCEDURE' AND (UPPER(TEXT) LIKE '%SITE_ITEM.DEPARTMENT_ID%RATIO.DEPARTMENT_ID%' OR UPPER(TEXT) LIKE '%SITE_ITEM%=%RATIO%' OR (UPPER(TEXT) LIKE '%RATIO%' AND UPPER(TEXT) LIKE '%ON %')) ORDER BY LINE;

-- v_Query close ('; 로 끝나는 line)
SELECT LINE, SUBSTR(TEXT, 1, 250) AS SRC FROM USER_SOURCE WHERE NAME='DMF0043_GET_CONTRIBUTE_MAIN_DATA' AND TYPE='PROCEDURE' AND TEXT LIKE '%'';%' AND LINE BETWEEN 365 AND 580 ORDER BY LINE FETCH FIRST 5 ROWS ONLY;

