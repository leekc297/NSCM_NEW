SELECT LINE, SUBSTR(TEXT, 1, 250) AS SRC FROM USER_SOURCE WHERE NAME='DMF0043_GET_CONTRIBUTE_MAIN_DATA' AND TYPE='PROCEDURE' AND LINE BETWEEN 555 AND 585 ORDER BY LINE;

