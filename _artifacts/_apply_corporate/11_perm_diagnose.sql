-- A. SCM_ADM_USER_M 컬럼 (NM_KO 가 아닌 다른 컬럼명 사용)
SELECT COLUMN_NAME FROM USER_TAB_COLUMNS WHERE TABLE_NAME='SCM_ADM_USER_M' AND COLUMN_NAME LIKE '%NM%' ORDER BY COLUMN_NAME;

-- B. minyonglee1 의 USER 정보 (모든 컬럼)
SELECT * FROM SCM_ADM_USER_M WHERE USER_ID='minyonglee1' FETCH FIRST 1 ROWS ONLY;

-- C. ADMIN / DM ADMIN 그룹의 UNIT_AUTH 모든 row (UNIT_TP_CD 별)
SELECT USER_GR_ID, UNIT_TP_CD, COUNT(*) AS C FROM SCM_ADM_USER_GR_UNIT_AUTH_MPG_M WHERE USER_GR_ID IN ('ADMIN', 'DM ADMIN', 'DMADMIN', 'DM_ADMIN') GROUP BY USER_GR_ID, UNIT_TP_CD ORDER BY USER_GR_ID, UNIT_TP_CD;

-- D. UNIT_AUTH 의 전체 row 분포 (가장 많은 그룹 Top 10)
SELECT USER_GR_ID, COUNT(*) AS C FROM SCM_ADM_USER_GR_UNIT_AUTH_MPG_M GROUP BY USER_GR_ID ORDER BY C DESC FETCH FIRST 10 ROWS ONLY;

-- E. UNIT_AUTH 의 UNIT_TP_CD 전체 분포
SELECT UNIT_TP_CD, COUNT(*) AS C FROM SCM_ADM_USER_GR_UNIT_AUTH_MPG_M GROUP BY UNIT_TP_CD ORDER BY C DESC;

-- F. SCM_ADM_USER_M 에 등록된 ADMIN 그룹 사용자 5명 (cross-check)
SELECT USER_ID, USER_GR_ID FROM SCM_ADM_USER_M WHERE USER_GR_ID IN ('ADMIN', 'DM ADMIN') FETCH FIRST 5 ROWS ONLY;

