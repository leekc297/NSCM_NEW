-- [8] 콤보 원천 갱신 — 신 lookup 구조 정합 (SQL_DTL_CTN VARCHAR2 4000 — 단문 유지)
UPDATE SCM_MGR.SCM_ADM_CMBO_SQL_M
   SET SQL_DTL_CTN = 'SELECT L.SEGMENT2 AS CODE, L.SEGMENT3 AS NAME
FROM SCM_ADM_LOOKUP_MASTER_DETAIL L
WHERE L.LOOKUP_TYPE = ''SPMS_CELL_TYPE'' AND L.VALID_YN = ''Y''
  AND ( NVL(TRIM(@divisionId),''ALL'') = ''ALL'' OR L.SEGMENT1 = @divisionId )
ORDER BY L.DISPLAY_SEQ',
       LAST_UPDATED_BY='admin', LAST_UPDATE_DATE=SYSDATE
 WHERE SQL_ID = 'CellTypeByDivision';

