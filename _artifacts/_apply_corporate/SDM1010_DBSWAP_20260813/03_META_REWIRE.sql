  FROM (
    SELECT 'SDM1010_POP1_GRID3_SAVE' AI, 'PKG_SDM1010.P_SDM1010_SAVE_POP_PJT_AUTH_READ' AU, 'PROC_SAVE' AT FROM DUAL
