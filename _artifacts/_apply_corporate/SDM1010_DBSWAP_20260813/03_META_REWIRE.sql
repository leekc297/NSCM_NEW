  FROM (
    SELECT 'MSG_API_SDM1010_POP1_GRID3_SAVE' MI, L.LC LC, 'SDM1010 POP1 GRID3 SAVE' NM
      FROM (SELECT 'KO' LC FROM DUAL UNION ALL SELECT 'EN' FROM DUAL UNION ALL SELECT 'CN' FROM DUAL) L
    UNION ALL
    SELECT 'MSG_API_SDM1010_period_SEARCH', L.LC, 'SDM1010 PERIOD SEARCH'
      FROM (SELECT 'KO' LC FROM DUAL UNION ALL SELECT 'EN' FROM DUAL UNION ALL SELECT 'CN' FROM DUAL) L
