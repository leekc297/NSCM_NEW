-- [0] 접속 DB
SELECT USER, SYS_CONTEXT('USERENV','DB_NAME') DB, SYS_CONTEXT('USERENV','SERVER_HOST') HOST,
       TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI:SS') NOW FROM DUAL;

-- [1] 판본 지문 — 사내 현행: BODY 3925줄 / HSUM 8821458631142 · 9/22 배포본: BODY 약 3872줄
SELECT O.OBJECT_TYPE, O.STATUS, TO_CHAR(O.LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL,
       COUNT(S.LINE) LINES, SUM(ORA_HASH(S.TEXT)) HSUM
  FROM ALL_OBJECTS O JOIN ALL_SOURCE S ON S.OWNER = O.OWNER AND S.NAME = O.OBJECT_NAME AND S.TYPE = O.OBJECT_TYPE
 WHERE O.OWNER = 'SCM_MGR' AND O.OBJECT_NAME = 'PKG_DMF0021'
 GROUP BY O.OBJECT_TYPE, O.STATUS, O.LAST_DDL_TIME;

-- [2] ⭐ 원인 판정 — 선삭제 사업부 조건
--     DIV40_ONLY = 3  /  DIV40_81 = 0  → 원인 확정 (81 선삭제 없음 = 9/22 판본)
--     DIV40_ONLY = 0  /  DIV40_81 = 3  → 사내 현행본과 동일 (다른 원인 — [4] 로 진행)
SELECT SUM(CASE WHEN REGEXP_LIKE(TEXT, '^\s*AND\s+A\.DIVISION_ID\s*=\s*''40''\s*$') THEN 1 ELSE 0 END) DIV40_ONLY,
       SUM(CASE WHEN TEXT LIKE '%A.DIVISION_ID = ''40'' OR A.DIVISION_ID LIKE ''81%''%' AND TEXT NOT LIKE '%--%' THEN 1 ELSE 0 END) DIV40_81,
       SUM(CASE WHEN TEXT LIKE '%V_CELL_PROD_SITE_ID = ''N/A''%' THEN 1 ELSE 0 END) NA_TO_DASH   -- 사내 현행본 1
  FROM ALL_SOURCE
 WHERE OWNER = 'SCM_MGR' AND NAME = 'PKG_DMF0021' AND TYPE = 'PACKAGE BODY';

-- [3] 오류 줄 확인 — 3551 부근이 INSERT INTO DM_PLN_SALES_PLAN 인지
SELECT LINE, SUBSTR(TEXT,1,150) TEXT
  FROM ALL_SOURCE
 WHERE OWNER = 'SCM_MGR' AND NAME = 'PKG_DMF0021' AND TYPE = 'PACKAGE BODY'
   AND LINE BETWEEN 3545 AND 3556
 ORDER BY LINE;

-- [4] 실패 흐름 로그 (k0101 저장 시도)
SELECT TO_CHAR(EVENT_DATE,'YYYY-MM-DD HH24:MI:SS') EV, LOG_TYPE, SUBSTR(LOG_MESSAGE,1,200) LOG_MESSAGE,
       SUBSTR(SQL_ERR_MSG,1,500) SQL_ERR_MSG, SUBSTR(SQL_BACKTRACE,1,300) BACKTRACE, SUBSTR(IN_PARA_DATA,1,500) IN_PARA
  FROM SCM_SYS_LOG_BATCH
 WHERE PROGRAM_NAME = 'PKG_DMF0021' AND EVENT_DATE >= SYSDATE - 1
 ORDER BY EVENT_DATE DESC FETCH FIRST 20 ROWS ONLY;

-- [5] 81 원장 상태 — 저장 대상 메저 행이 이미 있으면(선삭제가 안 되면) 같은 키 INSERT 가 바로 PK 위반
SELECT DIVISION_ID, MEASURE, COUNT(*) ROWS_, MIN(YYYYMMDD) MIN_YMD, MAX(YYYYMMDD) MAX_YMD,
       MAX(LAST_UPDATED_BY) KEEP (DENSE_RANK LAST ORDER BY LAST_UPDATE_DATE) LAST_BY,
       TO_CHAR(MAX(LAST_UPDATE_DATE),'YYYY-MM-DD HH24:MI') LAST_UPD
  FROM DM_PLN_SALES_PLAN
 WHERE DIVISION_ID LIKE '81%'
   AND MEASURE IN ('RTF_SYS_RP','RTF','RTF_SCP','SalesAmt_KRW','SalesAmt_LOC','SalesAmt_USD')
   AND YYYYMMDD >= TO_CHAR(SYSDATE,'YYYYMM') || '01'
 GROUP BY DIVISION_ID, MEASURE
 ORDER BY 1, 2;
