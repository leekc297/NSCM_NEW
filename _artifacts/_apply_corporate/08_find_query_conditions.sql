-- A. DM_MST_CONTRIBUTE_RATIO_DTL Top 10 VER_SEQ (row 가장 많은)
SELECT VER_SEQ, COUNT(*) AS DTL_ROWS FROM DM_MST_CONTRIBUTE_RATIO_DTL GROUP BY VER_SEQ ORDER BY DTL_ROWS DESC FETCH FIRST 10 ROWS ONLY;

-- B. DM_MST_CONTRIBUTE_RATIO_DTL 의 YYYYMM 분포 Top 10 (어떤 년월에 데이터)
SELECT SUBSTR(YYYYMM, 1, 4) AS YYYY, COUNT(*) AS DTL_ROWS FROM DM_MST_CONTRIBUTE_RATIO_DTL GROUP BY SUBSTR(YYYYMM, 1, 4) ORDER BY YYYY DESC FETCH FIRST 10 ROWS ONLY;

-- C. DM_MDF_VERSION 의 DIVISION_ID + VERSION_TYPE 분포
SELECT DIVISION_ID, VERSION_TYPE, COUNT(*) AS V_ROWS FROM DM_MDF_VERSION GROUP BY DIVISION_ID, VERSION_TYPE ORDER BY DIVISION_ID, VERSION_TYPE;

-- D. DM_MDF_VERSION 의 YYYYMMDD 의 YYYY 분포
SELECT SUBSTR(YYYYMMDD, 1, 4) AS YYYY, DIVISION_ID, COUNT(*) AS V_ROWS FROM DM_MDF_VERSION GROUP BY SUBSTR(YYYYMMDD, 1, 4), DIVISION_ID ORDER BY YYYY DESC, DIVISION_ID;

-- E. CRITICAL JOIN: DTL row 가 있는 VER_SEQ 에 대응되는 VERSION_NO (DM_MDF_VERSION) — Top 10
SELECT V.DIVISION_ID, V.VERSION_TYPE, V.VERSION_NO, V.YYYYMMDD, V.VER_CRE_SEQ, COUNT(DTL.VER_SEQ) AS DTL_MATCH FROM DM_MDF_VERSION V LEFT JOIN DM_MST_CONTRIBUTE_RATIO_DTL DTL ON V.VER_CRE_SEQ = DTL.VER_SEQ GROUP BY V.DIVISION_ID, V.VERSION_TYPE, V.VERSION_NO, V.YYYYMMDD, V.VER_CRE_SEQ HAVING COUNT(DTL.VER_SEQ) > 0 ORDER BY DTL_MATCH DESC FETCH FIRST 10 ROWS ONLY;

-- F. 추천 조회 조합 (FE 에서 사용 가능): Division + Year + Version + DTL row 수
SELECT V.DIVISION_ID AS DIV, SUBSTR(V.YYYYMMDD, 1, 4) AS YYYY, V.VERSION_NO AS VER, V.VERSION_TYPE AS V_TYPE, V.VER_CRE_SEQ AS VER_SEQ, COUNT(DTL.VER_SEQ) AS DTL_ROWS FROM DM_MDF_VERSION V LEFT JOIN DM_MST_CONTRIBUTE_RATIO_DTL DTL ON V.VER_CRE_SEQ = DTL.VER_SEQ GROUP BY V.DIVISION_ID, SUBSTR(V.YYYYMMDD, 1, 4), V.VERSION_NO, V.VERSION_TYPE, V.VER_CRE_SEQ HAVING COUNT(DTL.VER_SEQ) > 100 ORDER BY DIV, YYYY DESC, DTL_ROWS DESC FETCH FIRST 20 ROWS ONLY;

