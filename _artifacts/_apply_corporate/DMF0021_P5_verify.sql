-- 0) SP 상태 (기대: 5 PROC + PKG 2 = VALID)
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM USER_OBJECTS
WHERE OBJECT_NAME LIKE '%DMF0021%' AND OBJECT_TYPE IN ('PROCEDURE','PACKAGE','PACKAGE BODY')
ORDER BY OBJECT_NAME;

-- 1) PROC_M ↔ ALL_ARGUMENTS positional 대조 (기대: 0행)
SELECT NVL(p.PROC_NM, a.OBJECT_NAME) NM, NVL(p.SORT_ORD, a.POSITION) POS, p.COL_NM, a.ARGUMENT_NAME, a.IN_OUT
FROM (SELECT * FROM SCM_ADM_PROC_M WHERE PROC_NM IN
      ('DMF0021_GET_DM_PLN_SALES_PLAN_DATAEX','DMF0021_SAVE_DM_PLN_SALES_PLAN_ALL',
       'DMF0021_GET_SPREAD_TITLE','DMF0021_GET_SALES_PLAN_MEASUREINFO')) p
FULL OUTER JOIN (SELECT * FROM ALL_ARGUMENTS WHERE OWNER='SCM_MGR' AND PACKAGE_NAME IS NULL
      AND OBJECT_NAME IN ('DMF0021_GET_DM_PLN_SALES_PLAN_DATAEX','DMF0021_SAVE_DM_PLN_SALES_PLAN_ALL',
       'DMF0021_GET_SPREAD_TITLE','DMF0021_GET_SALES_PLAN_MEASUREINFO')) a
  ON a.OBJECT_NAME = p.PROC_NM AND a.POSITION = p.SORT_ORD
WHERE p.COL_NM IS NULL OR a.ARGUMENT_NAME IS NULL;

-- 2) 건수 (기대: PROC_M 21+19+7+2=49 / API 14 / BTN 14 / USER_GR 39)
SELECT 'PROC_M' T, COUNT(*) CNT FROM SCM_ADM_PROC_M WHERE PROC_NM LIKE 'DMF0021_%'
UNION ALL SELECT 'API_M', COUNT(*) FROM SCM_ADM_API_M WHERE API_ID LIKE 'DMF0021_%'
UNION ALL SELECT 'BTN_MPG', COUNT(*) FROM SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID = 'DMF0021'
UNION ALL SELECT 'USER_GR', COUNT(*) FROM SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE MNU_ID = 'DMF0021';

-- 3) MNU_URL (기대: sales-plan)
SELECT MNU_ID, MNU_URL FROM SCM_ADM_MNU_M WHERE MNU_ID = 'DMF0021';

-- 4) TITLESET (기대: salesPlan 0건)
SELECT SHEET_NAME, COUNT(*) FROM SCM_MST_TITLESET_USER WHERE PROGRAM_ID = 'DMF0021' GROUP BY SHEET_NAME;

-- 5) MSG placeholder 해소 (기대: [TODO] 0건)
SELECT MSG_ID, LANG_CD, SUBSTR(MSG_NM,1,60) FROM SCM_ADM_MSG_M
WHERE MSG_ID IN ('MSG00085','MSG00146','MSG00361') AND MSG_NM LIKE '[TODO]%';

-- 6) CMBO (기대: 1건 + 스모크는 치환 후 별도)
SELECT SQL_ID, USE_YN, LENGTH(SQL_DTL_CTN) FROM SCM_ADM_CMBO_SQL_M WHERE SQL_ID = 'CELL_PROD_SITE_ID';
