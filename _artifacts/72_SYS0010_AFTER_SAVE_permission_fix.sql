--==============================================================================
-- 72_SYS0010_AFTER_SAVE_permission_fix.sql
-- 목적: SYS0010 lookupDetail AFTER_SAVE 그룹 권한 누락 fix
-- 사고: MNU_BTN_MPG_M 에 AFTER_SAVE 등록되어 있으나 USER_GR_MNU_BTN_MPG_M 에는 없음
--       → FE Lookup detail save 후 post-process API 호출 시 "권한없음" 가능성
--==============================================================================
SET DEFINE OFF
SET SERVEROUTPUT ON
SET FEEDBACK ON
WHENEVER SQLERROR EXIT FAILURE

INSERT INTO SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M
  (USER_GR_ID, MNU_ID, SHT_NM, MNU_BTN_CD, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT NEW.USER_GR_ID, NEW.MNU_ID, NEW.SHT_NM, NEW.MNU_BTN_CD, NEW.USE_YN, NEW.CREATED_BY, NEW.CREATION_DATE, NEW.LAST_UPDATED_BY, NEW.LAST_UPDATE_DATE
  FROM (
    SELECT 'ADMIN' AS USER_GR_ID, 'SYS0010' AS MNU_ID, 'lookupDetail' AS SHT_NM, 'AFTER_SAVE' AS MNU_BTN_CD, 'Y' AS USE_YN, 'system' AS CREATED_BY, SYSDATE AS CREATION_DATE, 'system' AS LAST_UPDATED_BY, SYSDATE AS LAST_UPDATE_DATE FROM DUAL UNION ALL
    SELECT 'SCM PI Admin', 'SYS0010', 'lookupDetail', 'AFTER_SAVE', 'Y', 'system', SYSDATE, 'system', SYSDATE FROM DUAL
  ) NEW
WHERE NOT EXISTS (
  SELECT 1 FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M X
   WHERE X.USER_GR_ID = NEW.USER_GR_ID AND X.MNU_ID = NEW.MNU_ID
     AND X.SHT_NM = NEW.SHT_NM AND X.MNU_BTN_CD = NEW.MNU_BTN_CD
);

SELECT MNU_ID, SHT_NM, MNU_BTN_CD, USER_GR_ID FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M
 WHERE MNU_ID='SYS0010' AND MNU_BTN_CD='AFTER_SAVE';

COMMIT;
EXIT;
