-- BLOCK 1: MNU_BTN_CD RETRIEVE → SEARCH (FE 기본 sheet/SEARCH 와 매칭)
UPDATE SCM_ADM_MNU_BTN_MPG_M
   SET MNU_BTN_CD = 'SEARCH',
       LAST_UPDATED_BY = 'SYSTEM',
       LAST_UPDATE_DATE = SYSDATE
 WHERE MNU_ID = 'SYS0013' AND MNU_BTN_CD = 'RETRIEVE';

-- BLOCK 2: API_URL placeholder → 실제 Oracle SP (VALID 4개)
UPDATE SCM_ADM_API_M SET API_URL = 'DMF0027_GET_DM_TMP_DYNAMIC_QUERY_LIST',
       API_MSG_DESC = 'AS-IS DMF0027_GET_DM_TMP_DYNAMIC_QUERY_LIST (Oracle 이미 배포 VALID)',
       LAST_UPDATED_BY = 'SYSTEM', LAST_UPDATE_DATE = SYSDATE
 WHERE API_ID = 'API_SCM0005_GET_QUERY_LIST';

UPDATE SCM_ADM_API_M SET API_URL = 'PR_DM_ADM_DQ_EXECUTE_HIST',
       API_MSG_DESC = 'AS-IS PR_DM_ADM_DQ_EXECUTE_HIST (Oracle 이미 배포 VALID)',
       LAST_UPDATED_BY = 'SYSTEM', LAST_UPDATE_DATE = SYSDATE
 WHERE API_ID = 'API_SCM0005_EXECUTE_QUERY';

UPDATE SCM_ADM_API_M SET API_URL = 'DMF0027_GET_DM_TMP_DYNAMIC_QUERY_COLUMNS',
       API_MSG_DESC = 'AS-IS DMF0027_GET_DM_TMP_DYNAMIC_QUERY_COLUMNS (Oracle 이미 배포 VALID)',
       LAST_UPDATED_BY = 'SYSTEM', LAST_UPDATE_DATE = SYSDATE
 WHERE API_ID = 'API_SCM0005_GET_COLUMNS';

UPDATE SCM_ADM_API_M SET API_URL = 'DMF0027_GET_DM_TMP_DYNAMIC_QUERY_PARAMETERS',
       API_MSG_DESC = 'AS-IS DMF0027_GET_DM_TMP_DYNAMIC_QUERY_PARAMETERS (Oracle 이미 배포 VALID)',
       LAST_UPDATED_BY = 'SYSTEM', LAST_UPDATE_DATE = SYSDATE
 WHERE API_ID = 'API_SCM0005_GET_PARAMETERS';

-- BLOCK 3: PROC_M 정리 (placeholder + 신규 등록)
--   각 SP 의 실제 param signature 는 별도 단계에서 USER_ARGUMENTS 로 확인 후 정확히 등록
--   현재는 placeholder PROC_NM 삭제만
DELETE FROM SCM_ADM_PROC_M
 WHERE PROC_NM IN ('P_SCM0005_GET_QUERY_LIST', 'P_SCM0005_EXECUTE_QUERY',
                   'P_SCM0005_GET_COLUMNS', 'P_SCM0005_GET_PARAMETERS');

