-- DMF0007 PSI 데이터 + 메타 정정 (DBeaver 호환)

-- A-1: SMALL_CLASS_LABEL_NAME = COLUMN_LABEL_NAME 통일 (Measure 그룹 제외)
UPDATE SCM_MGR.SCM_MST_SHEET_COLUMNS
   SET SMALL_CLASS_LABEL_NAME = COLUMN_LABEL_NAME
     , LAST_UPDATED_BY = 'minyonglee1'
     , LAST_UPDATE_DATE = SYSDATE
 WHERE PROGRAM_ID = 'DMF0007'
   AND SHEET_NAME = 'customerPSI'
   AND COLUMN_NAME NOT IN ('MEASURE_GROUP', 'MEASURE')
   AND (SMALL_CLASS_LABEL_NAME IS NULL OR SMALL_CLASS_LABEL_NAME <> COLUMN_LABEL_NAME);

-- B: PSI 데이터 4주 분 INSERT (FCST 202621/Division=81 → PSI 4주)
INSERT INTO SCM_MGR.DM_MST_CUSTOMER_FCST (
  DIVISION_ID, PLAN_WEEK, CUSTOMER_CODE, SCM_SITE_ID, SUMMARY_BUCKET_VALUE,
  MEASURE_GROUP, CUSTOMER_PSI, MEASURE, VALID_YN, UPLOAD_UOM, UPLOAD_BUCKET_TYPE,
  SUMMARY_BUCKET_TYPE, EDI_FCST_YN, UPLOAD_USER_ID,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE,
  ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, ATTRIBUTE4, ATTRIBUTE5,
  ATTRIBUTE6, ATTRIBUTE7, ATTRIBUTE8, ATTRIBUTE9, ATTRIBUTE10
)
SELECT CF.DIVISION_ID, w.NEW_WEEK, CF.CUSTOMER_CODE, CF.SCM_SITE_ID, CF.SUMMARY_BUCKET_VALUE,
       'PSI', 'S', CF.MEASURE, CF.VALID_YN, CF.UPLOAD_UOM, CF.UPLOAD_BUCKET_TYPE,
       CF.SUMMARY_BUCKET_TYPE, CF.EDI_FCST_YN, CF.UPLOAD_USER_ID,
       'minyonglee1', SYSDATE, 'minyonglee1', SYSDATE,
       CF.ATTRIBUTE1, CF.ATTRIBUTE2, CF.ATTRIBUTE3, CF.ATTRIBUTE4, CF.ATTRIBUTE5,
       CF.ATTRIBUTE6, CF.ATTRIBUTE7, CF.ATTRIBUTE8, CF.ATTRIBUTE9, CF.ATTRIBUTE10
  FROM SCM_MGR.DM_MST_CUSTOMER_FCST CF
 CROSS JOIN (SELECT '202622' AS NEW_WEEK FROM DUAL
             UNION ALL SELECT '202623' FROM DUAL
             UNION ALL SELECT '202624' FROM DUAL
             UNION ALL SELECT '202625' FROM DUAL) w
 WHERE CF.PLAN_WEEK = '202621'
   AND CF.DIVISION_ID = '81'
   AND CF.MEASURE_GROUP = 'CUST_FCST'
   AND NOT EXISTS (
     SELECT 1 FROM SCM_MGR.DM_MST_CUSTOMER_FCST X
      WHERE X.DIVISION_ID = CF.DIVISION_ID
        AND X.PLAN_WEEK = w.NEW_WEEK
        AND X.CUSTOMER_CODE = CF.CUSTOMER_CODE
        AND X.SCM_SITE_ID = CF.SCM_SITE_ID
        AND X.SUMMARY_BUCKET_VALUE = CF.SUMMARY_BUCKET_VALUE
        AND X.MEASURE_GROUP = 'PSI'
        AND X.CUSTOMER_PSI = 'S'
        AND X.MEASURE = CF.MEASURE
   );

COMMIT;
