-- 01_FIND_DMF0082_BULK_SAVE — 조회 전용 (전체 F5, 값 입력 없음)
-- 목적: 클라우드 SCM_COM_SQL_LOG 에서 DMF0082 저장(PKG_DMF0082.P_DMF0082_SAVE_MAIN_DATA) 중 1,000건 이상 일괄 저장 호출 목록
-- 근거: BE callProc 로그의 SQL_TEXT = 값이 채워진 실행 문장 전체(한 줄, 문자열 인자 17개 + OUT 커서 NULL)
--       PARAMS(JSON) 는 4,000자 근처에서 잘려 재현에 쓸 수 없음 (사내 실측 SQL_TEXT 4,736,060자 / PARAMS 4,029자)
-- 건수 = 첫 인자(P_ACTIVE_FLAG, 'M^M^…') 의 '^' 개수 + 1
SET LINESIZE 260 PAGESIZE 500
SET DEFINE OFF

SELECT 'F0' CHK, SYS_CONTEXT('USERENV','DB_NAME') DB_NAME, TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI:SS') NOW FROM DUAL;

WITH L AS (
    SELECT LOG_SEQ, CREATE_DATE, CREATED_BY, ELAPSED_MS, RESULT_COUNT, SQL_TEXT, EXCEPTION,
           DBMS_LOB.GETLENGTH(SQL_TEXT) SQL_LEN,
           DBMS_LOB.INSTR(SQL_TEXT, '( ''') + 3 P1_START,
           DBMS_LOB.INSTR(SQL_TEXT, ''', ', 1, 1) P1_END
      FROM SCM_MGR.SCM_COM_SQL_LOG
     WHERE SQL_ID = 'com.lgcns.nscm.callProc'
       AND DBMS_LOB.INSTR(SQL_TEXT, 'PKG_DMF0082.P_DMF0082_SAVE_MAIN_DATA') > 0
)
SELECT 'F1' CHK, LOG_SEQ, TO_CHAR(CREATE_DATE,'YYYY-MM-DD HH24:MI:SS') CREATED, CREATED_BY, ELAPSED_MS, SQL_LEN,
       REGEXP_COUNT(SUBSTR(SQL_TEXT, P1_START, P1_END - P1_START), '\^') + 1 SAVE_ROWS,
       CASE WHEN EXCEPTION IS NULL THEN 'OK' ELSE 'EXCEPTION: ' || DBMS_LOB.SUBSTR(EXCEPTION, 150, 1) END RESULT
  FROM L
 WHERE P1_END > P1_START
   AND REGEXP_COUNT(SUBSTR(SQL_TEXT, P1_START, P1_END - P1_START), '\^') + 1 >= 1000
 ORDER BY CREATE_DATE DESC;
