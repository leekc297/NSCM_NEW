-- 03_FIND_BULK_SAVE_3SCREENS — 조회 전용 (전체 F5, 값 입력 없음) · 사내/클라우드 공용
-- 대상: DMF0082 P_DMF0082_SAVE_MAIN_DATA · DMF0003 P_DMF0003_SAVE_MKT_FCST · DMF0021 P_DMF0021_SAVE_DM_PLN_SALES_PLAN_ALL
-- 근거: BE callProc 로그(SCM_COM_SQL_LOG, SQL_ID='com.lgcns.nscm.callProc') SQL_TEXT = 값이 채워진 실행 문장
--       세 SP 모두 첫 인자 P_ACTIVE_FLAG = 'M^M^…' (행별 CRUD) → 저장 건수 = '^' 개수 + 1
--       ELAPSED_MS = BE 가 잰 SP 호출 시간(DB 실행). 화면 전체 시간은 B3(SCM_COM_SYS_LOG) 참고
-- 판정
--   B0  접속 DB · 로그 보존 기간(가장 오래된/최근 로그) — 클라우드 0건이면 보존 기간부터 확인
--   B1  화면(SP)별 전체 저장 호출 요약 — 호출 수 · 최대 건수 · 최대 소요 · 1,000건 이상 호출 수
--   B2  1,000건 이상 저장 목록 — 화면 · LOG_SEQ · 시각 · 사용자 · 건수 · 소요(ms/초) · 결과
--   B3  화면 저장 이벤트(SYS_LOG) 소요 상위 — SQL_LOG 와 별개로 화면 단위 시간 확인
SET LINESIZE 260 PAGESIZE 1000
SET DEFINE OFF

SELECT 'B0' CHK, SYS_CONTEXT('USERENV','DB_NAME') DB_NAME, TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI:SS') NOW,
       (SELECT TO_CHAR(MIN(CREATE_DATE),'YYYY-MM-DD HH24:MI') FROM SCM_MGR.SCM_COM_SQL_LOG) SQL_LOG_FROM,
       (SELECT TO_CHAR(MAX(CREATE_DATE),'YYYY-MM-DD HH24:MI') FROM SCM_MGR.SCM_COM_SQL_LOG) SQL_LOG_TO,
       (SELECT COUNT(*) FROM SCM_MGR.SCM_COM_SQL_LOG) SQL_LOG_ROWS
  FROM DUAL;

-- B1 화면별 저장 호출 요약 (건수 제한 없음)
WITH L AS (
    SELECT CASE WHEN DBMS_LOB.INSTR(SQL_TEXT, 'PKG_DMF0082.P_DMF0082_SAVE_MAIN_DATA(') > 0 THEN 'DMF0082'
                WHEN DBMS_LOB.INSTR(SQL_TEXT, 'PKG_DMF0003.P_DMF0003_SAVE_MKT_FCST(') > 0 THEN 'DMF0003'
                ELSE 'DMF0021' END SCREEN,
           CREATE_DATE, ELAPSED_MS, EXCEPTION, DBMS_LOB.GETLENGTH(SQL_TEXT) SQL_LEN,
           REGEXP_COUNT(SUBSTR(SQL_TEXT, DBMS_LOB.INSTR(SQL_TEXT, '( ''') + 3,
                               DBMS_LOB.INSTR(SQL_TEXT, ''', ', 1, 1) - DBMS_LOB.INSTR(SQL_TEXT, '( ''') - 3), '\^') + 1 SAVE_ROWS
      FROM SCM_MGR.SCM_COM_SQL_LOG
     WHERE SQL_ID = 'com.lgcns.nscm.callProc'
       AND (   DBMS_LOB.INSTR(SQL_TEXT, 'PKG_DMF0082.P_DMF0082_SAVE_MAIN_DATA(') > 0
            OR DBMS_LOB.INSTR(SQL_TEXT, 'PKG_DMF0003.P_DMF0003_SAVE_MKT_FCST(') > 0
            OR DBMS_LOB.INSTR(SQL_TEXT, 'PKG_DMF0021.P_DMF0021_SAVE_DM_PLN_SALES_PLAN_ALL(') > 0)
)
SELECT 'B1' CHK, SCREEN, COUNT(*) CALLS, MAX(SAVE_ROWS) MAX_ROWS, ROUND(MAX(ELAPSED_MS)/1000,1) MAX_SEC,
       SUM(CASE WHEN SAVE_ROWS >= 1000 THEN 1 ELSE 0 END) CALLS_GE_1000,
       SUM(CASE WHEN EXCEPTION IS NOT NULL THEN 1 ELSE 0 END) EXC_CALLS,
       MAX(SQL_LEN) MAX_SQL_LEN,
       TO_CHAR(MIN(CREATE_DATE),'YYYY-MM-DD') FIRST_DAY, TO_CHAR(MAX(CREATE_DATE),'YYYY-MM-DD') LAST_DAY
  FROM L
 GROUP BY SCREEN
 ORDER BY SCREEN;

-- B2 1,000건 이상 저장 목록
WITH L AS (
    SELECT CASE WHEN DBMS_LOB.INSTR(SQL_TEXT, 'PKG_DMF0082.P_DMF0082_SAVE_MAIN_DATA(') > 0 THEN 'DMF0082'
                WHEN DBMS_LOB.INSTR(SQL_TEXT, 'PKG_DMF0003.P_DMF0003_SAVE_MKT_FCST(') > 0 THEN 'DMF0003'
                ELSE 'DMF0021' END SCREEN,
           LOG_SEQ, CREATE_DATE, CREATED_BY, ELAPSED_MS, EXCEPTION, DBMS_LOB.GETLENGTH(SQL_TEXT) SQL_LEN,
           REGEXP_COUNT(SUBSTR(SQL_TEXT, DBMS_LOB.INSTR(SQL_TEXT, '( ''') + 3,
                               DBMS_LOB.INSTR(SQL_TEXT, ''', ', 1, 1) - DBMS_LOB.INSTR(SQL_TEXT, '( ''') - 3), '\^') + 1 SAVE_ROWS
      FROM SCM_MGR.SCM_COM_SQL_LOG
     WHERE SQL_ID = 'com.lgcns.nscm.callProc'
       AND (   DBMS_LOB.INSTR(SQL_TEXT, 'PKG_DMF0082.P_DMF0082_SAVE_MAIN_DATA(') > 0
            OR DBMS_LOB.INSTR(SQL_TEXT, 'PKG_DMF0003.P_DMF0003_SAVE_MKT_FCST(') > 0
            OR DBMS_LOB.INSTR(SQL_TEXT, 'PKG_DMF0021.P_DMF0021_SAVE_DM_PLN_SALES_PLAN_ALL(') > 0)
       AND DBMS_LOB.GETLENGTH(SQL_TEXT) > 3000
)
SELECT 'B2' CHK, SCREEN, LOG_SEQ, TO_CHAR(CREATE_DATE,'YYYY-MM-DD HH24:MI:SS') CREATED, CREATED_BY,
       SAVE_ROWS, ELAPSED_MS, ROUND(ELAPSED_MS/1000,1) ELAPSED_SEC,
       ROUND(ELAPSED_MS / NULLIF(SAVE_ROWS,0), 2) MS_PER_ROW, SQL_LEN,
       CASE WHEN EXCEPTION IS NULL THEN 'OK' ELSE 'EXCEPTION: ' || DBMS_LOB.SUBSTR(EXCEPTION, 120, 1) END RESULT
  FROM L
 WHERE SAVE_ROWS >= 1000
 ORDER BY SCREEN, CREATE_DATE DESC;

-- B3 화면 저장 이벤트(SYS_LOG) — 소요 상위 10 / 화면·시트별
SELECT 'B3' CHK, MNU_ID, MNU_BTN_CD, SHT_NM, CREATED, CREATED_BY, ELAPSED_SEC, RESULT
  FROM (SELECT MNU_ID, MNU_BTN_CD, SHT_NM, TO_CHAR(LOG_ST_DTM,'YYYY-MM-DD HH24:MI:SS') CREATED, CREATED_BY,
               ROUND(EXTRACT(DAY FROM (LOG_END_DTM - LOG_ST_DTM)) * 86400 + EXTRACT(HOUR FROM (LOG_END_DTM - LOG_ST_DTM)) * 3600
                   + EXTRACT(MINUTE FROM (LOG_END_DTM - LOG_ST_DTM)) * 60 + EXTRACT(SECOND FROM (LOG_END_DTM - LOG_ST_DTM)), 1) ELAPSED_SEC,
               CASE WHEN EXCT_MSG_CTN IS NULL THEN 'OK' ELSE 'EXCEPTION: ' || SUBSTR(EXCT_MSG_CTN, 1, 100) END RESULT,
               ROW_NUMBER() OVER (PARTITION BY MNU_ID, MNU_BTN_CD, SHT_NM ORDER BY (LOG_END_DTM - LOG_ST_DTM) DESC NULLS LAST) RN
          FROM SCM_MGR.SCM_COM_SYS_LOG
         WHERE MNU_ID IN ('DMF0082','DMF0003','DMF0021')
           AND UPPER(MNU_BTN_CD) LIKE '%SAVE%')
 WHERE RN <= 10
 ORDER BY MNU_ID, MNU_BTN_CD, SHT_NM, ELAPSED_SEC DESC;
