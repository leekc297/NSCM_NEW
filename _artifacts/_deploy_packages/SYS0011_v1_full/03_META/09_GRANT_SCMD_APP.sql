CREATE OR REPLACE SYNONYM SCMD_APP.P_SYS0011_SAVE_MY_AUTH_DATA FOR SCM_MGR.P_SYS0011_SAVE_MY_AUTH_DATA;
GRANT EXECUTE ON SCM_MGR.P_SYS0011_SAVE_USER_INFO_DATA TO SCMD_APP;
CREATE OR REPLACE SYNONYM SCMD_APP.P_SYS0011_SAVE_USER_INFO_DATA FOR SCM_MGR.P_SYS0011_SAVE_USER_INFO_DATA;
