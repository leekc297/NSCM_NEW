-- 90 VERIFY — [GAP418 2026-10-15] GAP 418 조회 전용 (전체 F5, 값 입력 없음)
-- * 기대: V1 마커 2 PASS · V2 VALID / 오류 0 / 의존 INVALID 0 · V3 저장 SP 안 활성 END_CUSTOMER 조건 0 PASS
SET LINESIZE 220 PAGESIZE 500
SET DEFINE OFF
COLUMN CHK FORMAT A10
COLUMN KIND FORMAT A50
COLUMN JUDGE FORMAT A60
SELECT 'V1 마커' CHK, COUNT(*) N, CASE WHEN COUNT(*) = 2 THEN 'PASS' ELSE 'FAIL (미적용 또는 마커 수 불일치)' END JUDGE
  FROM USER_SOURCE WHERE NAME='PKG_DMF0072' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%GAP418 2026-10-15%';
SELECT 'V2 상태' CHK, O.OBJECT_TYPE, O.STATUS, TO_CHAR(O.LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL,
       (SELECT COUNT(*) FROM USER_ERRORS E WHERE E.NAME=O.OBJECT_NAME AND E.TYPE=O.OBJECT_TYPE) ERR_CNT,
       (SELECT COUNT(*) FROM USER_OBJECTS X WHERE X.STATUS<>'VALID' AND X.OBJECT_NAME IN (SELECT NAME FROM USER_DEPENDENCIES WHERE REFERENCED_NAME='PKG_DMF0072')) DEP_INVALID
  FROM USER_OBJECTS O WHERE O.OBJECT_NAME='PKG_DMF0072' ORDER BY O.OBJECT_TYPE;
SELECT 'V3 잔존' CHK, '활성 END_CUSTOMER = REC.END_CUSTOMER 조건' KIND, COUNT(*) N, CASE WHEN COUNT(*) = 0 THEN 'PASS' ELSE 'FAIL — 회신' END JUDGE
  FROM USER_SOURCE S WHERE S.NAME='PKG_DMF0072' AND S.TYPE='PACKAGE BODY'
   AND REGEXP_LIKE(S.TEXT, '^ *AND +A\.END_CUSTOMER += REC\.END_CUSTOMER')
   AND S.LINE BETWEEN (SELECT MIN(LINE) FROM USER_SOURCE WHERE NAME='PKG_DMF0072' AND TYPE='PACKAGE BODY' AND TEXT LIKE 'PROCEDURE P_DMF0072_SAVE_NNMASTER_MAPPING%')
                  AND (SELECT MIN(LINE) FROM USER_SOURCE WHERE NAME='PKG_DMF0072' AND TYPE='PACKAGE BODY' AND TEXT LIKE 'END P_DMF0072_SAVE_NNMASTER_MAPPING;%');
