-- [E20260901-GRPMEAS81] 원복 — 적용 전 상태로 되돌린다
-- ① 추가분 제거
DELETE FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE='GET_ADMIN_GROUP_MEASURE' AND SEGMENT2='DMF0082'
   AND SEGMENT1='SCM PI Admin' AND SEGMENT3 LIKE '81%' AND SEGMENT4='MKT_FCST';

-- ② 제거분 복원 (ADMIN / SCM PI Admin / SCP Planner × 81계열 6 × SCM_FCST = 18행)
INSERT INTO SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
  (LOOKUP_TYPE, SEGMENT1, SEGMENT2, SEGMENT3, SEGMENT4, SEGMENT5, VALID_YN,
   CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'GET_ADMIN_GROUP_MEASURE', G.GRP, 'DMF0082', D.DV, 'SCM_FCST', '-', 'Y',
       'admin', SYSDATE, 'admin', SYSDATE
  FROM (SELECT 'ADMIN' GRP FROM DUAL UNION ALL SELECT 'SCM PI Admin' FROM DUAL
        UNION ALL SELECT 'SCP Planner' FROM DUAL) G,
       (SELECT '81' DV FROM DUAL UNION ALL SELECT '81_HD' FROM DUAL UNION ALL SELECT '81_HG' FROM DUAL
        UNION ALL SELECT '81_HM' FROM DUAL UNION ALL SELECT '81_ST' FROM DUAL
        UNION ALL SELECT '81_UC' FROM DUAL) D
 WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL X
                    WHERE X.LOOKUP_TYPE='GET_ADMIN_GROUP_MEASURE' AND X.SEGMENT1=G.GRP
                      AND X.SEGMENT2='DMF0082' AND X.SEGMENT3=D.DV AND X.SEGMENT4='SCM_FCST' AND X.SEGMENT5='-');

COMMIT;
