-- [E20260901-GRPMEAS81] 적용 후 검증 (SELECT-only)
-- P1: 추가 확인 — SCM PI Admin × 81계열 MKT_FCST = **6행** 이어야 통과
SELECT 'P1 추가' S, COUNT(*) CNT FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE='GET_ADMIN_GROUP_MEASURE' AND SEGMENT2='DMF0082'
   AND SEGMENT1='SCM PI Admin' AND SEGMENT3 LIKE '81%' AND SEGMENT4='MKT_FCST' AND VALID_YN='Y';

-- P2: 제거 확인 — 81계열 SCM_FCST = **0행** 이어야 통과
SELECT 'P2 제거' S, COUNT(*) CNT FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE='GET_ADMIN_GROUP_MEASURE' AND SEGMENT2='DMF0082'
   AND SEGMENT3 LIKE '81%' AND SEGMENT4='SCM_FCST';

-- P3: 40 무영향 확인 — 40 은 종전대로 (LOC/MKT_FCST/SCM_FCST/VMI_In_Req 조합 15행 유지)
SELECT 'P3 40무영향' S, SEGMENT1, SEGMENT4 FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE='GET_ADMIN_GROUP_MEASURE' AND SEGMENT2='DMF0082' AND SEGMENT3='40'
 ORDER BY SEGMENT1, SEGMENT4;

-- P4: 81계열 최종 분포 (그룹×메저) — MKT_FCST/LOC 중심, SCM_FCST 0
SELECT 'P4 81분포' S, SEGMENT1, SEGMENT4, COUNT(*) DIVS FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE='GET_ADMIN_GROUP_MEASURE' AND SEGMENT2='DMF0082' AND SEGMENT3 LIKE '81%'
 GROUP BY SEGMENT1, SEGMENT4 ORDER BY SEGMENT1, SEGMENT4;
