        DBMS_OUTPUT.PUT_LINE('  현재  ' || v);
        DBMS_OUTPUT.PUT_LINE('  기준  ' || p_sig);
        run('DROP TABLE ' || p_tab || ' PURGE', p_tab);
        run(p_ddl, p_tab); v_rebld := v_rebld + 1;
        DBMS_OUTPUT.PUT_LINE('REBUILD ' || p_tab); RETURN TRUE;
    END;

