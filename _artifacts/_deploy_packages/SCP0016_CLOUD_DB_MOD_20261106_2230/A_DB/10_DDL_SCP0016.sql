    v_skip  PLS_INTEGER := 0;
    FUNCTION cur_sig(p_tab VARCHAR2) RETURN VARCHAR2 IS
        v VARCHAR2(4000);
    BEGIN
        SELECT LISTAGG(COLUMN_NAME||'|'||DATA_TYPE||'|'||CHAR_LENGTH||'|'||DATA_PRECISION||'|'||DATA_SCALE||'|'||NULLABLE, ';')
                 WITHIN GROUP (ORDER BY COLUMN_ID) INTO v
          FROM USER_TAB_COLUMNS WHERE TABLE_NAME = p_tab;
        RETURN v;
    END;

    PROCEDURE run(p_sql VARCHAR2, p_tab VARCHAR2) IS
    BEGIN
        IF c_dry THEN
            RAISE_APPLICATION_ERROR(-20901, 'DRY: ' || p_tab || ' 에 DDL 필요 — ' || SUBSTR(p_sql, 1, 120));
        END IF;
        EXECUTE IMMEDIATE p_sql;
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE IN (-14452, -14450) THEN
            DBMS_OUTPUT.PUT_LINE('ERROR   ' || p_tab || ' : ' || SQLERRM || ' -> 사용 중 세션 존재, BE 재기동 후 재실행');
        ELSIF SQLCODE <> -20901 THEN
            DBMS_OUTPUT.PUT_LINE('ERROR   ' || p_tab || ' : ' || SQLERRM || ' :: ' || SUBSTR(p_sql, 1, 200));
        END IF;
        RAISE;
    END;

    PROCEDURE grant_to(p_tab VARCHAR2, p_grantee VARCHAR2, p_privs VARCHAR2) IS
    BEGIN
        IF c_dry THEN RETURN; END IF;
        EXECUTE IMMEDIATE 'GRANT ' || p_privs || ' ON ' || p_tab || ' TO ' || p_grantee;
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE IN (-1917, -1919) THEN DBMS_OUTPUT.PUT_LINE('  WARN  ' || p_grantee || ' 없음, GRANT 생략 (' || p_tab || ')');
        ELSE RAISE; END IF;
    END;

    FUNCTION exists_tab(p_tab VARCHAR2) RETURN BOOLEAN IS n PLS_INTEGER;
