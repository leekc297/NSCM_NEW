/* 사전 확인 (조회만) */
ALTER SESSION SET CURRENT_SCHEMA = SCM_MGR;
/* [P1] 원문 상태. BASE = A, B, FINAL, OTHER. 20(패치판)은 OTHER 여도 보완 3곳 문장이 그대로면 적용됨. OTHER 면 15 결과 함께 회신 */
SELECT S.NAME
     , (SELECT MAX(O.STATUS) FROM ALL_OBJECTS O WHERE O.OWNER = 'SCM_MGR' AND O.OBJECT_NAME = S.NAME AND O.OBJECT_TYPE = 'PROCEDURE') AS STATUS
     , (SELECT TO_CHAR(MAX(O.LAST_DDL_TIME), 'YYYY-MM-DD HH24:MI:SS') FROM ALL_OBJECTS O WHERE O.OWNER = 'SCM_MGR' AND O.OBJECT_NAME = S.NAME AND O.OBJECT_TYPE = 'PROCEDURE') AS LAST_DDL_TIME
     , S.CLOUD_LINES
     , CASE WHEN S.CLOUD_LINES = 3582 AND S.CLOUD_HASH = 8002014763396 THEN 'A'
            WHEN S.CLOUD_LINES = 3583 AND S.CLOUD_HASH = 8003242559807 THEN 'B'
            WHEN S.M_WHSTKHD > 0 THEN 'FINAL'
            ELSE 'OTHER' END AS BASE
     , S.M_DS2
     , S.M_OWMSMAX
     , S.M_AGINGCUT
     , S.M_WHSTKHD
  FROM (SELECT NAME
             , COUNT(*) AS CLOUD_LINES
             , SUM(ORA_HASH(TEXT)) AS CLOUD_HASH
     , COUNT(CASE WHEN INSTR(TEXT, 'E20261126-DS2') > 0 THEN 1 END) AS M_DS2
     , COUNT(CASE WHEN INSTR(TEXT, 'E20261126-OWMSMAX') > 0 THEN 1 END) AS M_OWMSMAX
     , COUNT(CASE WHEN INSTR(TEXT, 'E20261126-AGINGCUT') > 0 THEN 1 END) AS M_AGINGCUT
     , COUNT(CASE WHEN INSTR(TEXT, 'E20261126-WHSTKHD') > 0 THEN 1 END) AS M_WHSTKHD
          FROM ALL_SOURCE
         WHERE OWNER = 'SCM_MGR'
           AND NAME  = 'PR_SSP_ANL_SHIP_PLAN_40'
           AND TYPE  = 'PROCEDURE'
         GROUP BY NAME) S;

/* [P2] 지금 SHIP_PLAN_40 을 실행 중인 세션. 0행일 때 진행 */
SELECT S.SID, S.SERIAL#, S.USERNAME, S.MODULE, S.STATUS, S.SQL_ID, S.LAST_CALL_ET
  FROM GV$SESSION S
 WHERE S.PLSQL_ENTRY_OBJECT_ID IN (SELECT O.OBJECT_ID FROM ALL_OBJECTS O
                                    WHERE O.OWNER = 'SCM_MGR' AND O.OBJECT_NAME = 'PR_SSP_ANL_SHIP_PLAN_40' AND O.OBJECT_TYPE = 'PROCEDURE');
