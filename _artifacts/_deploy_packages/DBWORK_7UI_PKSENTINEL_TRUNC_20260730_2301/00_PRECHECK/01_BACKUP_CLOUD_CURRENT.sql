-- 01_BACKUP_CLOUD_CURRENT.sql  —  ⭐ 덮어쓰기 **전에** 클라우드 현재본을 백업
--   본 패키지는 클라우드의 9 오브젝트를 CREATE OR REPLACE 로 덮어쓴다.
--   원복하려면 **클라우드 자신의 현재본**이 필요하다 (사내 백업으로는 원복 불가 —
--   두 환경의 BODY 가 동일하다는 보장이 없음).
--
--   실행: SCM_MGR 세션. spool 결과 파일을 안전한 곳에 보관한 뒤 적용을 진행할 것.
-- =============================================================================
SET LINESIZE 32767
SET LONG 200000000
SET LONGCHUNKSIZE 200000
SET PAGESIZE 0
SET TRIMSPOOL ON
SET FEEDBACK OFF
SET ECHO OFF
SET VERIFY OFF

BEGIN
  DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM,'SQLTERMINATOR',FALSE);
  DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM,'PRETTY',TRUE);
END;
/

SPOOL BACKUP_CLOUD_9OBJ_before_apply.sql

PROMPT -- ================================================================
PROMPT -- 클라우드 적용 전 백업 (자동 생성) — 원복 시 이 파일을 그대로 실행
PROMPT -- ================================================================
PROMPT SET DEFINE OFF

-- PACKAGE SPEC → BODY 순 (의존순), 그다음 standalone PROCEDURE
SELECT DBMS_METADATA.GET_DDL('PACKAGE_SPEC', OBJECT_NAME, 'SCM_MGR') || CHR(10) || '/'
  FROM USER_OBJECTS
 WHERE OBJECT_TYPE='PACKAGE'
   AND OBJECT_NAME IN ('PKG_DMF0003','PKG_DMF0020','PKG_DMF0021','PKG_DMF0042',
                       'PKG_DMF0044','PKG_DMF0049','PKG_DMF0082')
 ORDER BY OBJECT_NAME;

SELECT DBMS_METADATA.GET_DDL('PACKAGE_BODY', OBJECT_NAME, 'SCM_MGR') || CHR(10) || '/'
  FROM USER_OBJECTS
 WHERE OBJECT_TYPE='PACKAGE BODY'
   AND OBJECT_NAME IN ('PKG_DMF0003','PKG_DMF0020','PKG_DMF0021','PKG_DMF0042',
                       'PKG_DMF0044','PKG_DMF0049','PKG_DMF0082')
 ORDER BY OBJECT_NAME;

SELECT DBMS_METADATA.GET_DDL('PROCEDURE', OBJECT_NAME, 'SCM_MGR') || CHR(10) || '/'
  FROM USER_OBJECTS
 WHERE OBJECT_TYPE='PROCEDURE'
   AND OBJECT_NAME IN ('DMF0020_SAVE_SCM_MST_FUTURE_PRICE_ALL',
                       'DMF0020_SAVE_SCM_MST_FUTURE_PRICE_POPUP')
 ORDER BY OBJECT_NAME;

SPOOL OFF

-- ── 메타 백업 (본 패키지가 DELETE/UPDATE 하는 범위) ──────────────────────
-- ⭐ 전 컬럼 보존은 CTAS 가 확실하다 (아래 3본을 먼저 실행할 것)
CREATE TABLE BK_PROC_M_20260730 AS
  SELECT * FROM SCM_ADM_PROC_M
   WHERE PROC_NM LIKE 'PKG_DMF0044.%' OR PROC_NM LIKE 'PKG_DMF0049.%';

CREATE TABLE BK_SHEET_MEASURE_20260730 AS
  SELECT * FROM SCM_MST_SHEET_MEASURE WHERE PROGRAM_ID='DMF0082';

CREATE TABLE BK_SHEET_COLUMNS_20260730 AS
  SELECT * FROM SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID='DMF0082';

CREATE TABLE BK_MSG_M_20260730 AS
  SELECT * FROM SCM_ADM_MSG_M
   WHERE MSG_ID IN ('LBL00783','LBL00794','LBL00795','LBL00796','LBL00797','LBL00798',
                    'LBL00799','LBL00800','LBL00844','LBL00845','LBL00846','LBL00847',
                    'LBL00848','LBL00849','LBL00850','LBL00851');

SET FEEDBACK ON
SET PAGESIZE 100

SELECT 'BK_PROC_M_20260730' AS BK, COUNT(*) AS CNT FROM BK_PROC_M_20260730
UNION ALL SELECT 'BK_SHEET_MEASURE_20260730', COUNT(*) FROM BK_SHEET_MEASURE_20260730
UNION ALL SELECT 'BK_SHEET_COLUMNS_20260730', COUNT(*) FROM BK_SHEET_COLUMNS_20260730
UNION ALL SELECT 'BK_MSG_M_20260730', COUNT(*) FROM BK_MSG_M_20260730;

