/* DMF0082 환율 모달 [BPS I/F] 반영 여부 — 종합 판정 1쿼리 (클라우드 SCM_MGR · 조회 전용)
   :CLICK_TIME 대신 아래 WITH 절 P.CLICK_TIME 에 BPS I/F 클릭 시각을 넣어 실행 (기본값 = 최근 1시간) */
WITH P AS (
    SELECT SYSDATE - 1/24 AS CLICK_TIME FROM DUAL          /* 예: TO_DATE('2026-09-15 20:30:00','YYYY-MM-DD HH24:MI:SS') */
), SRC AS (
    SELECT E.*
      FROM SCM_MGR.XIF_GSC_MOVE_EXCHANGE_RATE_SN E
     WHERE E.SCENARIO_TYPE_CD IN ('ML', 'RF')
       AND E.TRANSF_DATE = (SELECT MAX(A.TRANSF_DATE) FROM SCM_MGR.XIF_GSC_MOVE_EXCHANGE_RATE_SN A WHERE A.SCENARIO_TYPE_CD IN ('ML', 'RF'))
), DIV40 AS (
    SELECT DIVISION_ID FROM SCM_MGR.SCM_MST_DIVISION WHERE ATTRIBUTE3 = '40'
), TGT AS (
    SELECT R.*,
           CASE WHEN R.EXCHANGE_PRICE = DECODE(R.CURRENCY, 'KRW', S.KRW_CNVT_RATE, 'USD', S.USD_CNVT_RATE, 'EUR', S.EUR_CNVT_RATE) THEN 1 ELSE 0 END SAME_AS_IF
      FROM SCM_MGR.DM_MST_EXCHANGE_RATE R
      JOIN SRC S ON S.PLN_YYYYMM || '01' = R.YYYYMMDD AND S.CURRENCY_CD = R.UNIT_CURRENCY
     WHERE R.DIVISION_ID IN (SELECT DIVISION_ID FROM DIV40)
       AND R.CURRENCY IN ('KRW', 'USD', 'EUR')
), LOGS AS (
    SELECT L.*
      FROM SCM_MGR.SCM_SYS_LOG_BATCH L, P
     WHERE L.CREATION_DATE >= P.CLICK_TIME - 1/1440
       AND (L.PROGRAM_NAME = 'PR_SCM_MST_EXCHANGE_RATE'
            OR (L.PROGRAM_NAME = 'PKG_DMF0082' AND (L.DESCRIPTION = 'P_BATCH_YN = N' OR L.LOG_MESSAGE LIKE '##########%of procedure%' OR L.LOG_TYPE = 'ERROR')))
)
SELECT '1. 버튼 호출 객체' CHECK_ITEM,
       (SELECT MAX(T2.API_URL) FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M T1 JOIN SCM_MGR.SCM_ADM_API_M T2 ON T1.API_ID = T2.API_ID
         WHERE T1.MNU_ID = 'DMF0082' AND T1.SHT_NM = 'futurePriceInfo' AND T1.MNU_BTN_CD = 'IF') RESULT_VALUE,
       '표시된 객체가 실제 호출 대상' VERDICT
  FROM DUAL
UNION ALL
SELECT '2. 래퍼 버전(0건 안내 보완)',
       TO_CHAR((SELECT COUNT(*) FROM ALL_SOURCE WHERE OWNER = 'SCM_MGR' AND NAME IN ('PR_SCM_MST_EXCHANGE_RATE_UI', 'PKG_DMF0082') AND TEXT LIKE '%E20260915-BPSIFNODATA%')),
       CASE WHEN (SELECT COUNT(*) FROM ALL_SOURCE WHERE OWNER = 'SCM_MGR' AND NAME IN ('PR_SCM_MST_EXCHANGE_RATE_UI', 'PKG_DMF0082') AND TEXT LIKE '%E20260915-BPSIFNODATA%') = 0
            THEN '구버전 — 대상 0건이어도 성공 메시지가 나옴(메시지로 판단 불가)' ELSE '보완본 — 대상 0건이면 안내 메시지' END
  FROM DUAL
UNION ALL
SELECT '3. I/F 원천 최신 묶음',
       (SELECT COUNT(*) || '건 · 수신 ' || TO_CHAR(MAX(TRANSF_DATE), 'YYYY-MM-DD HH24:MI') || ' · 월 ' || MIN(PLN_YYYYMM) || '~' || MAX(PLN_YYYYMM) FROM SRC),
       CASE WHEN (SELECT COUNT(*) FROM SRC) = 0 THEN '❌ 원천 0건 — 반영할 환율 자체가 없음' ELSE '원천 있음' END
  FROM DUAL
UNION ALL
SELECT '4. 실행 로그(클릭 이후)',
       (SELECT LISTAGG(PROGRAM_NAME || ':' || LOG_TYPE || ' ' || TO_CHAR(CREATION_DATE, 'HH24:MI:SS'), ' / ') WITHIN GROUP (ORDER BY CREATION_DATE) FROM LOGS),
       CASE WHEN EXISTS (SELECT 1 FROM LOGS WHERE LOG_TYPE = 'ERROR') THEN '❌ 오류 — SCM_SYS_LOG_BATCH.SQL_ERR_MSG 확인'
            WHEN EXISTS (SELECT 1 FROM LOGS WHERE LOG_TYPE = 'END') AND EXISTS (SELECT 1 FROM LOGS WHERE LOG_TYPE = 'START') THEN '배치 끝까지 수행됨'
            ELSE '⚠ 배치 실행 기록 없음 — 호출 안 됨(0건 안내 경로) 또는 클릭 시각 재확인' END
  FROM DUAL
UNION ALL
SELECT '5. Div40 반영 대상 행',
       (SELECT COUNT(*) || '행 · SYSTEM 갱신 ' || SUM(CASE WHEN T.LAST_UPDATED_BY = 'SYSTEM' AND T.LAST_UPDATE_DATE >= P.CLICK_TIME THEN 1 ELSE 0 END)
               || '행 · 원천값 일치 ' || SUM(T.SAME_AS_IF) || '행 · 최종수정 ' || TO_CHAR(MAX(T.LAST_UPDATE_DATE), 'YYYY-MM-DD HH24:MI:SS') FROM TGT T, P),
       CASE WHEN (SELECT COUNT(*) FROM TGT) = 0 THEN '반영 대상 행 없음(원천 0건 또는 Div40 행 없음)'
            WHEN (SELECT COUNT(*) FROM TGT T, P WHERE T.LAST_UPDATED_BY = 'SYSTEM' AND T.LAST_UPDATE_DATE >= P.CLICK_TIME) = (SELECT COUNT(*) FROM TGT)
             AND (SELECT SUM(SAME_AS_IF) FROM TGT) = (SELECT COUNT(*) FROM TGT) THEN '✅ 반영 성공'
            ELSE '❌ 미반영 또는 일부 반영 — 3·4 항목 확인' END
  FROM DUAL
UNION ALL
SELECT '6. 최근 SYSTEM 갱신 사업부',
       (SELECT LISTAGG(DIVISION_ID || ':' || CNT, ', ') WITHIN GROUP (ORDER BY DIVISION_ID)
          FROM (SELECT R.DIVISION_ID, COUNT(*) CNT FROM SCM_MGR.DM_MST_EXCHANGE_RATE R, P
                 WHERE R.LAST_UPDATED_BY = 'SYSTEM' AND R.LAST_UPDATE_DATE >= P.CLICK_TIME GROUP BY R.DIVISION_ID)),
       '화면 I/F 는 ATTRIBUTE3=''40'' 사업부만 갱신 — 모달에서 81·82 행을 보고 있으면 변화 없음이 정상'
  FROM DUAL;
