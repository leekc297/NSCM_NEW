/* ============================================================================
   DMF0082 환율 모달 [BPS I/F] 실제 반영 여부 확인 — 클라우드 SCM_MGR 조회 전용 (DB 변경 없음)
   작성 2026-09-15 · 근거: 사내 ZIOUI1 원문 (PR_SCM_MST_EXCHANGE_RATE_UI / PR_SCM_MST_EXCHANGE_RATE / P_DMF0082_POPUP_GET_FUTUREPRICE_INFO)

   화면 BPS I/F 동작 요약 (P_BATCH_YN = 'N')
     원천  : XIF_GSC_MOVE_EXCHANGE_RATE_SN 중 TRANSF_DATE 가 가장 최근인 묶음(SCENARIO ML·RF)
     대상  : SCM_MST_DIVISION.ATTRIBUTE3 = '40' 사업부만  ← 81·82 행은 화면 I/F 로 바뀌지 않음(야간 배치 담당)
     반영  : DM_MST_EXCHANGE_RATE MERGE — 일자 = 원천 PLN_YYYYMM||'01' · KRW/USD/EUR 3행
             갱신 시 LAST_UPDATED_BY = 'SYSTEM', LAST_UPDATE_DATE = SYSDATE (값이 같아도 갱신)
     로그  : SCM_SYS_LOG_BATCH (START 'P_BATCH_YN = N' → END, 실패 시 ERROR)
   [BPS I/F] 클릭한 시각을 기억해 두고 아래를 순서대로 실행
   ============================================================================ */

/* ① 버튼이 부르는 객체 (META 전환 전 = PR_SCM_MST_EXCHANGE_RATE_UI / 전환 후 = PKG_DMF0082.P_PR_SCM_MST_EXCHANGE_RATE_UI) */
SELECT T1.MNU_BTN_CD, T2.API_ID, T2.API_URL
  FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M T1
  JOIN SCM_MGR.SCM_ADM_API_M T2 ON T1.API_ID = T2.API_ID
 WHERE T1.MNU_ID = 'DMF0082' AND T1.SHT_NM = 'futurePriceInfo'
 ORDER BY 1;

/* ② 래퍼 버전 — 0건이면 "대상 0건이어도 success" 를 돌려주는 구버전 (정상 메시지만으로는 반영 여부 판단 불가)
      1건 이상 = [E20260915-BPSIFNODATA] 반영본: 대상 0건이면 '반영할 환율 정보가 없습니다' 안내 */
SELECT NAME, TYPE, COUNT(*) MARKER_LINES
  FROM ALL_SOURCE
 WHERE OWNER = 'SCM_MGR'
   AND NAME IN ('PR_SCM_MST_EXCHANGE_RATE_UI', 'PKG_DMF0082')
   AND TEXT LIKE '%E20260915-BPSIFNODATA%'
 GROUP BY NAME, TYPE;

/* ③ 실행 로그 — 클릭 시각 근처에 START(P_BATCH_YN = N) → END 가 있으면 배치가 끝까지 수행됨
      ERROR 행이 있으면 실패(SQL_ERR_MSG 확인) · 행이 없으면 배치 미호출(대상 0건 안내 경로 또는 호출 실패)
      PKG 취합(UIPKG) 적용 환경에서는 PROGRAM_NAME 이 'PKG_DMF0082' 로 기록됨 */
SELECT PROGRAM_NAME, LOG_TYPE, DESCRIPTION, LOG_MESSAGE, SQL_ERR_MSG,
       TO_CHAR(CREATION_DATE, 'YYYY-MM-DD HH24:MI:SS') CREATION_DATE, CREATED_BY
  FROM SCM_MGR.SCM_SYS_LOG_BATCH
 WHERE (PROGRAM_NAME = 'PR_SCM_MST_EXCHANGE_RATE'
        OR (PROGRAM_NAME = 'PKG_DMF0082' AND (LOG_MESSAGE LIKE '##########%of procedure%' OR DESCRIPTION LIKE 'P_BATCH_YN%' OR LOG_TYPE = 'ERROR')))
   AND CREATION_DATE >= SYSDATE - 1          /* 최근 1일 */
 ORDER BY CREATION_DATE DESC;

/* ④ 원천(I/F 테이블) — 화면 I/F 가 가져가는 최신 묶음. 0행이면 반영할 원천 자체가 없음 */
SELECT TO_CHAR(E.TRANSF_DATE, 'YYYY-MM-DD HH24:MI:SS') TRANSF_DATE, E.SCENARIO_TYPE_CD, E.PLN_PERIOD_YYYYMM, E.PLN_YYYYMM,
       E.CURRENCY_CD, E.IF_SEQ, E.KRW_CNVT_RATE, E.USD_CNVT_RATE, E.EUR_CNVT_RATE
  FROM SCM_MGR.XIF_GSC_MOVE_EXCHANGE_RATE_SN E
 WHERE E.TRANSF_DATE = (SELECT MAX(A.TRANSF_DATE) FROM SCM_MGR.XIF_GSC_MOVE_EXCHANGE_RATE_SN A WHERE A.SCENARIO_TYPE_CD IN ('ML', 'RF'))
   AND E.SCENARIO_TYPE_CD IN ('ML', 'RF')
 ORDER BY E.PLN_YYYYMM, E.CURRENCY_CD, E.SCENARIO_TYPE_CD;

/* ⑤ 반영 결과 — 원천 최신 묶음의 월·통화에 해당하는 Division 40 환율 행
      LAST_UPDATED_BY = 'SYSTEM' 이고 LAST_UPDATE_DATE 가 클릭 시각 이후 → 반영 성공
      SAME_AS_IF = 'Y' → 원천 환율과 값 일치 */
SELECT R.DIVISION_ID, R.YYYYMMDD, R.CURRENCY, R.UNIT_CURRENCY, R.EXCHANGE_PRICE,
       R.LAST_UPDATED_BY, TO_CHAR(R.LAST_UPDATE_DATE, 'YYYY-MM-DD HH24:MI:SS') LAST_UPDATE_DATE,
       CASE WHEN R.EXCHANGE_PRICE = DECODE(R.CURRENCY, 'KRW', E.KRW_CNVT_RATE, 'USD', E.USD_CNVT_RATE, 'EUR', E.EUR_CNVT_RATE) THEN 'Y' ELSE 'N' END SAME_AS_IF
  FROM SCM_MGR.DM_MST_EXCHANGE_RATE R
  JOIN SCM_MGR.XIF_GSC_MOVE_EXCHANGE_RATE_SN E
    ON E.PLN_YYYYMM || '01' = R.YYYYMMDD
   AND E.CURRENCY_CD = R.UNIT_CURRENCY
   AND E.SCENARIO_TYPE_CD IN ('ML', 'RF')
   AND E.TRANSF_DATE = (SELECT MAX(A.TRANSF_DATE) FROM SCM_MGR.XIF_GSC_MOVE_EXCHANGE_RATE_SN A WHERE A.SCENARIO_TYPE_CD IN ('ML', 'RF'))
 WHERE R.DIVISION_ID IN (SELECT D.DIVISION_ID FROM SCM_MGR.SCM_MST_DIVISION D WHERE D.ATTRIBUTE3 = '40')
   AND R.CURRENCY IN ('KRW', 'USD', 'EUR')
 ORDER BY R.YYYYMMDD, R.UNIT_CURRENCY, R.CURRENCY;

/* ⑥ 화면 기간 대조 — 반영된 월 범위. 모달 조회기간(From~To)이 이 범위를 포함하지 않으면 화면에 변화가 안 보임 */
SELECT MIN(E.PLN_YYYYMM) FROM_YYYYMM, MAX(E.PLN_YYYYMM) TO_YYYYMM, COUNT(DISTINCT E.CURRENCY_CD) CURRENCY_CNT
  FROM SCM_MGR.XIF_GSC_MOVE_EXCHANGE_RATE_SN E
 WHERE E.TRANSF_DATE = (SELECT MAX(A.TRANSF_DATE) FROM SCM_MGR.XIF_GSC_MOVE_EXCHANGE_RATE_SN A WHERE A.SCENARIO_TYPE_CD IN ('ML', 'RF'))
   AND E.SCENARIO_TYPE_CD IN ('ML', 'RF');

/* ⑦ 최근 1시간 안에 SYSTEM 으로 갱신된 환율 행 (사업부별 건수) — 40 에만 행이 있으면 정상 동작 */
SELECT DIVISION_ID, COUNT(*) CNT, MIN(YYYYMMDD) FROM_YMD, MAX(YYYYMMDD) TO_YMD,
       TO_CHAR(MAX(LAST_UPDATE_DATE), 'YYYY-MM-DD HH24:MI:SS') LAST_UPDATE_DATE
  FROM SCM_MGR.DM_MST_EXCHANGE_RATE
 WHERE LAST_UPDATED_BY = 'SYSTEM'
   AND LAST_UPDATE_DATE >= SYSDATE - 1/24
 GROUP BY DIVISION_ID
 ORDER BY DIVISION_ID;
