-- =====================================================================
-- DMF0074 이관 검증 — 적용 후 단일 SELECT 로 전 항목 확인 (DBeaver 실행 가능)
-- 기대값이 어긋나면 해당 행의 RESULT 가 'NG' 로 표시된다.
-- =====================================================================
SELECT 'META HEADER_CONTENT DMF0074 (55 tokens)' CHECK_ITEM,
       TO_CHAR(REGEXP_COUNT(HEADER_CONTENT,'\|')+1) ACTUAL, '55' EXPECTED,
       CASE WHEN REGEXP_COUNT(HEADER_CONTENT,'\|')+1 = 55 THEN 'OK' ELSE 'NG' END RESULT
FROM   SCM_MGR.SCM_ADM_EXCEL_COLUMNS
WHERE  PROGRAM_ID = 'DMF0074' AND SHEET_NAME = 'Metal Link Price'
UNION ALL
SELECT 'META HEADER_CONTENT DMF0074_40 (53 tokens)',
       TO_CHAR(REGEXP_COUNT(HEADER_CONTENT,'\|')+1), '53',
       CASE WHEN REGEXP_COUNT(HEADER_CONTENT,'\|')+1 = 53 THEN 'OK' ELSE 'NG' END
FROM   SCM_MGR.SCM_ADM_EXCEL_COLUMNS
WHERE  PROGRAM_ID = 'DMF0074_40' AND SHEET_NAME = 'Metal Link Price'
UNION ALL
SELECT 'META token#12 (DMF0074_40) = Key_Ni',
       REGEXP_SUBSTR(HEADER_CONTENT,'[^|]+',1,12), 'Key_Ni',
       CASE WHEN REGEXP_SUBSTR(HEADER_CONTENT,'[^|]+',1,12) = 'Key_Ni' THEN 'OK' ELSE 'NG' END
FROM   SCM_MGR.SCM_ADM_EXCEL_COLUMNS
WHERE  PROGRAM_ID = 'DMF0074_40' AND SHEET_NAME = 'Metal Link Price'
UNION ALL
SELECT 'META token#14 (DMF0074) = Key_Ni',
       REGEXP_SUBSTR(HEADER_CONTENT,'[^|]+',1,14), 'Key_Ni',
       CASE WHEN REGEXP_SUBSTR(HEADER_CONTENT,'[^|]+',1,14) = 'Key_Ni' THEN 'OK' ELSE 'NG' END
FROM   SCM_MGR.SCM_ADM_EXCEL_COLUMNS
WHERE  PROGRAM_ID = 'DMF0074' AND SHEET_NAME = 'Metal Link Price'
UNION ALL
SELECT 'PKG_DMF0074 PACKAGE BODY STATUS', STATUS, 'VALID',
       CASE WHEN STATUS = 'VALID' THEN 'OK' ELSE 'NG' END
FROM   ALL_OBJECTS
WHERE  OWNER='SCM_MGR' AND OBJECT_NAME='PKG_DMF0074' AND OBJECT_TYPE='PACKAGE BODY'
UNION ALL
SELECT 'SP FIX: 버전분기 UPPER(P_VERSION_TYPE)', TO_CHAR(COUNT(*)), '1',
       CASE WHEN COUNT(*) = 1 THEN 'OK' ELSE 'NG' END
FROM   ALL_SOURCE
WHERE  OWNER='SCM_MGR' AND NAME='PKG_DMF0074' AND TYPE='PACKAGE BODY'
AND    TEXT LIKE '%UPPER(P_VERSION_TYPE) LIKE ''%CURRENT%''%'
UNION ALL
-- 템플릿 SP 의 MRF 필터가 주석 처리되어 있으면 업로드 검증과 다른 버전을 보게 된다 → 0건이어야 함
SELECT 'SP FIX: 주석 처리된 MRF 필터 (0건이어야 함)', TO_CHAR(COUNT(*)), '0',
       CASE WHEN COUNT(*) = 0 THEN 'OK' ELSE 'NG' END
FROM   ALL_SOURCE
WHERE  OWNER='SCM_MGR' AND NAME='PKG_DMF0074' AND TYPE='PACKAGE BODY'
AND    REGEXP_LIKE(TEXT, '^\s*--\s*AND\s+NVL\(ATTRIBUTE7')
UNION ALL
SELECT 'SP FIX: D14 NULL-safe 조인 10줄', TO_CHAR(COUNT(*)), '10',
       CASE WHEN COUNT(*) = 10 THEN 'OK' ELSE 'NG' END
FROM   ALL_SOURCE
WHERE  OWNER='SCM_MGR' AND NAME='PKG_DMF0074' AND TYPE='PACKAGE BODY'
AND    (TEXT LIKE '%NVL(APPLY_PRICE_TYPE.PROJECT_CODE%' OR TEXT LIKE '%NVL(APPLY_PRICE_TYPE.PLANT_SITE_ID%')
UNION ALL
SELECT 'SP FIX: NVL(B.PROJECT_CODE,''-'') 3곳', TO_CHAR(COUNT(*)), '3',
       CASE WHEN COUNT(*) = 3 THEN 'OK' ELSE 'NG' END
FROM   ALL_SOURCE
WHERE  OWNER='SCM_MGR' AND NAME='PKG_DMF0074' AND TYPE='PACKAGE BODY'
AND    TEXT LIKE '%NVL(B.PROJECT_CODE,''-'')%'
UNION ALL
SELECT 'SP: 잔존 원시 = 비교 (D14, 0건이어야 함)', TO_CHAR(COUNT(*)), '0',
       CASE WHEN COUNT(*) = 0 THEN 'OK' ELSE 'NG' END
FROM   ALL_SOURCE
WHERE  OWNER='SCM_MGR' AND NAME='PKG_DMF0074' AND TYPE='PACKAGE BODY'
AND    LINE BETWEEN 3612 AND 3749
AND    REGEXP_LIKE(TEXT, '^\s*AND\s+APPLY_PRICE_TYPE\.(PROJECT_CODE|PLANT_SITE_ID)\s*=')
UNION ALL
SELECT 'DATA: MRF ''Y'' 최신 버전이 워터폴 데이터 보유 (div 40)',
       NVL(V.VERSION_NO,'(none)'), '데이터 있는 버전',
       CASE WHEN (SELECT COUNT(*) FROM SCM_MGR.DM_PLN_SALES_PLAN_C P
                  WHERE P.DIVISION_ID='40' AND P.VERSION_NO = V.VERSION_NO) > 0
            THEN 'OK' ELSE 'NG' END
FROM   (SELECT MAX(VERSION_NO) VERSION_NO
        FROM   SCM_MGR.DM_MST_VERSION
        WHERE  VERSION_TYPE='SP_W' AND DIVISION_ID='40' AND NVL(ATTRIBUTE7,'N')='Y') V
