/* 99_ROLLBACK — 문제 시에만. 05_BACKUP 의 ZB_DMF0082_DIVCUTC_20261124_SRC 원문으로 PACKAGE BODY 복원 */
SET SERVEROUTPUT ON SIZE UNLIMITED
DECLARE
    v CLOB;
BEGIN
    FOR r IN (SELECT TEXT FROM ZB_DMF0082_DIVCUTC_20261124_SRC WHERE NAME = 'PKG_DMF0082' AND TYPE = 'PACKAGE BODY' ORDER BY LINE) LOOP v := v || r.TEXT; END LOOP;
    IF v IS NULL THEN
        RAISE_APPLICATION_ERROR(-20020, '백업 없음 — 05_BACKUP 미실행. 복원 안 함');
    END IF;
    EXECUTE IMMEDIATE 'CREATE OR REPLACE ' || v;
    DBMS_OUTPUT.PUT_LINE('> RESTORE PACKAGE BODY PKG_DMF0082 완료');
END;
/
SELECT OBJECT_TYPE, STATUS FROM USER_OBJECTS WHERE OBJECT_NAME = 'PKG_DMF0082' ORDER BY 1;
