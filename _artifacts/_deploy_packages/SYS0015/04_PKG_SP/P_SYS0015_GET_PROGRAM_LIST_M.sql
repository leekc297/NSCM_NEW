ALTER SESSION SET DDL_LOCK_TIMEOUT=120;
CREATE OR REPLACE PROCEDURE         P_SYS0015_GET_PROGRAM_LIST_M (
    P_SEARCH         IN  VARCHAR2,
    O_RC1            OUT SYS_REFCURSOR,
    O_RESULT_CURSOR  OUT SYS_REFCURSOR
)
AS
BEGIN
    OPEN O_RC1 FOR
    SELECT
        PROGRAM_ID,
        PROGRAM_NAME,
        PROGRAM_PATH,
        CLASS_NAME,
        USE_YN
    FROM SCM_MGR.SCM_ADM_PROGRAM
    WHERE P_SEARCH IS NULL
       OR P_SEARCH = ''
       OR PROGRAM_ID LIKE '%' || P_SEARCH || '%'
       OR PROGRAM_NAME LIKE '%' || P_SEARCH || '%'
    ORDER BY PROGRAM_ID;

    OPEN O_RESULT_CURSOR FOR
    SELECT '0' AS CODE, 'SUCCESS' AS MSG FROM DUAL;
EXCEPTION
    WHEN OTHERS THEN
        DECLARE V_ERR VARCHAR2(4000) := SUBSTR(SQLERRM, 1, 4000);
        BEGIN
            OPEN O_RC1 FOR SELECT NULL AS DUMMY FROM DUAL WHERE 1=0;
            OPEN O_RESULT_CURSOR FOR SELECT '-1' AS CODE, V_ERR AS MSG FROM DUAL;
        END;
END P_SYS0015_GET_PROGRAM_LIST_M;
/
SHOW ERRORS;
