MERGE INTO SCM_MGR.SCM_ADM_EXCEL_COLUMNS T
USING (SELECT 'DMF0082' AS PROGRAM_ID, 'FcstNPrice' AS SHEET_NAME FROM DUAL) S
ON (T.PROGRAM_ID=S.PROGRAM_ID AND T.SHEET_NAME=S.SHEET_NAME)
WHEN MATCHED THEN UPDATE SET STORAGE_SQL_ID='PKG_DMF0082.P_DMF0082_EXCEL_UPLOAD', HEADER_CONTENT='Div|End Customer|Sales Site|Model|Incoterms|FCST Type|Customs Handbook|Cell Prod Site|Currency|Measure|M4|M5|M6|M7|M8|M9|M10|M11|M12|M13|M14|M15|M16',
     OPTION_ATTRIBUTE_COLUMN_NUMBER=70, VALID_YN='Y', LAST_UPDATED_BY='admin', LAST_UPDATE_DATE=SYSDATE
WHEN NOT MATCHED THEN INSERT (PROGRAM_ID, SHEET_NAME, STORAGE_SQL_ID, HEADER_CONTENT, OPTION_ATTRIBUTE_COLUMN_NUMBER, VALID_YN,
     CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES ('DMF0082', 'FcstNPrice', 'PKG_DMF0082.P_DMF0082_EXCEL_UPLOAD', 'Div|End Customer|Sales Site|Model|Incoterms|FCST Type|Customs Handbook|Cell Prod Site|Currency|Measure|M4|M5|M6|M7|M8|M9|M10|M11|M12|M13|M14|M15|M16', 70, 'Y', 'admin', SYSDATE, 'admin', SYSDATE);
COMMIT;
