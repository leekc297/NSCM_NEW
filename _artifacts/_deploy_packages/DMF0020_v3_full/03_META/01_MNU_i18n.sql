-- DMF0020 메뉴 등록 + i18n (Sales Price)
MERGE INTO SCM_ADM_MNU_M t USING (SELECT 'DMF0020' MNU_ID FROM DUAL) s ON (t.MNU_ID=s.MNU_ID)
 WHEN MATCHED THEN UPDATE SET MNU_DESC='Sales Price', LAST_UPDATED_BY='admin', LAST_UPDATE_DATE=SYSDATE
 WHEN NOT MATCHED THEN INSERT (MNU_ID, UPPR_MNU_ID, MNU_URL, MNU_MSG_ID, MNU_DESC, SORT_ORD, MNU_LV_NO, MNU_TP_CD, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
   VALUES ('DMF0020','Demand_Master','sales-future-price','MNU_DMF0020','Sales Price', 1, 3, 'SCREEN','Y','admin',SYSDATE,'admin',SYSDATE);

