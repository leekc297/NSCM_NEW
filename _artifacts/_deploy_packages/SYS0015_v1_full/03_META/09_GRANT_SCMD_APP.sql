-- SYS0015 SCMD_APP 권한 (BE 사용계정)
-- ⚠ 신규 화면 작성 시 반드시 SCM_MGR (DDL owner) 에서 실행
-- ⚠ 누락 시 BE 호출 -9994 'Sql Error' (PLS-00201 권한없음)

-- 1) SP EXECUTE GRANT + PUBLIC SYNONYM
GRANT EXECUTE ON SCM_MGR.P_SYS0015_GET_PROGRAM_LIST_M TO SCMD_APP;
CREATE OR REPLACE SYNONYM SCMD_APP.P_SYS0015_GET_PROGRAM_LIST_M FOR SCM_MGR.P_SYS0015_GET_PROGRAM_LIST_M;
GRANT EXECUTE ON SCM_MGR.P_SYS0015_SAVE_PROGRAM_M TO SCMD_APP;
CREATE OR REPLACE SYNONYM SCMD_APP.P_SYS0015_SAVE_PROGRAM_M FOR SCM_MGR.P_SYS0015_SAVE_PROGRAM_M;

-- 2) 신규 테이블 GRANT (SELECT/INSERT/UPDATE/DELETE) + SYNONYM
GRANT SELECT ON SCM_MGR.SCM_ADM_PROGRAM TO SCMD_APP;
GRANT INSERT ON SCM_MGR.SCM_ADM_PROGRAM TO SCMD_APP;
GRANT UPDATE ON SCM_MGR.SCM_ADM_PROGRAM TO SCMD_APP;
GRANT DELETE ON SCM_MGR.SCM_ADM_PROGRAM TO SCMD_APP;
CREATE OR REPLACE SYNONYM SCMD_APP.SCM_ADM_PROGRAM FOR SCM_MGR.SCM_ADM_PROGRAM;

-- 3) 검증
SELECT GRANTEE, PRIVILEGE, TABLE_NAME FROM DBA_TAB_PRIVS
 WHERE GRANTEE='SCMD_APP' AND OWNER='SCM_MGR' AND TABLE_NAME LIKE '%SYS0015%'
 ORDER BY TABLE_NAME, PRIVILEGE;
