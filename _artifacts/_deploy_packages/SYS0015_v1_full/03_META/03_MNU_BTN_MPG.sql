MERGE INTO SCM_ADM_MNU_BTN_MPG_M t USING (SELECT 'SYS0015' MNU_ID, 'main' SHT_NM, 'SAVE' MNU_BTN_CD FROM DUAL) s
   ON (t.MNU_ID=s.MNU_ID AND t.SHT_NM=s.SHT_NM AND t.MNU_BTN_CD=s.MNU_BTN_CD)
 WHEN MATCHED THEN UPDATE SET API_ID='API_SYS0015_SAVE_PROGRAM', USE_YN='Y', LAST_UPDATED_BY='admin', LAST_UPDATE_DATE=SYSDATE
