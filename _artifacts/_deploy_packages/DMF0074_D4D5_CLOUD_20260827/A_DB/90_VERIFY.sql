-- 90_VERIFY.sql — DMF0074 D4/D5 적용 확인 (클라우드)
-- 1) 컴파일 상태
SELECT OBJECT_TYPE, STATUS, LAST_DDL_TIME FROM ALL_OBJECTS WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_DMF0074';
SELECT COUNT(*) AS ERR_CNT FROM ALL_ERRORS WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0074';
-- 2) 마커 3곳 (D4 2 + D5 1) 기대 = 3
SELECT COUNT(*) AS MARKER_CNT FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0074' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%E20260827-D%';
-- 3) 순서: C21/C22/C23 LINE < C19 LINE 기대
SELECT REGEXP_SUBSTR(TEXT, 'C(19|21|22|23)') AS BLK, LINE FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0074' AND TYPE='PACKAGE BODY' AND REGEXP_LIKE(TEXT, 'V_LOG_TYPE\s*:=\s*''C(19|21|22|23)'';') ORDER BY LINE;