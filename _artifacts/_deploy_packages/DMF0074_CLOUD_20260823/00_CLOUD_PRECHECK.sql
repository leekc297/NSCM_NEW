PROMPT ===== C5. HISTORY_SEQ identity 시퀀스 뒤처짐 (다건 업로드 ORA-00001 의 원인) =====
SELECT (SELECT MAX(HISTORY_SEQ) FROM SCM_MGR.DM_BPS_METAL_LINK_PRICE_H) AS MAX_SEQ,
       (SELECT LAST_NUMBER FROM ALL_SEQUENCES s
         WHERE s.SEQUENCE_OWNER='SCM_MGR'
           AND s.SEQUENCE_NAME = (SELECT REGEXP_SUBSTR(i.SEQUENCE_NAME,'[^.]+$') FROM ALL_TAB_IDENTITY_COLS i
                                   WHERE i.OWNER='SCM_MGR' AND i.TABLE_NAME='DM_BPS_METAL_LINK_PRICE_H'
                                     AND i.COLUMN_NAME='HISTORY_SEQ')) AS SEQ_LAST_NUMBER
FROM DUAL;
-- SEQ_LAST_NUMBER <= MAX_SEQ 이면 **A_DB/05_FIX_HISTORY_SEQ_RESEED.sql 필수**.
-- 클라우드도 같은 이관 계보라 동일 상태일 가능성이 높다(사내 실측 전력: MAX 1564 vs LAST 61).

PROMPT ===== C6. Excel Form 0건(=SP_W 빈 버전) 여부 — 오늘 사내에서 실제로 터진 축 =====
SELECT V.VERSION_NO, V.DIVISION_ID, TO_CHAR(V.CREATION_DATE,'YYYY-MM-DD') CREATED,
       (SELECT COUNT(*) FROM SCM_MGR.DM_PLN_SALES_PLAN_C C
         WHERE C.VERSION_NO = V.VERSION_NO AND C.DIVISION_ID = V.DIVISION_ID) AS LEDGER_ROWS
FROM   SCM_MGR.DM_MST_VERSION V
WHERE  V.VERSION_NO LIKE 'SP!_W!_%' ESCAPE '!'
ORDER  BY V.VERSION_NO DESC FETCH FIRST 10 ROWS ONLY;
-- LEDGER_ROWS = 0 인 최신 SP_W 버전이 선택되면 화면은 "다운로드할 템플릿 대상 데이터가 없습니다."(MSG01015).
-- 사내 2026-08-23 실측: SP_W_20260820_V002(W34) 가 0행 → 원장 28,085행을 그 버전으로 재지정해 해소(div 40).
--   백업 = BAK_DMF0074_SPC_W34_20260823 (사내 전용, 이관 대상 아님).
-- 진단 상세 = 94_DIAG_CLOUD_SPW_LEDGER.sql / 조치안 = 95_FIX_CLOUD_EMPTY_SPW_VERSION.sql
