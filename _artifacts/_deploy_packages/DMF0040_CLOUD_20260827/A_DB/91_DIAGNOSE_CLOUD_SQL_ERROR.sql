-- 91_DIAGNOSE_CLOUD_SQL_ERROR.sql — DMF0040 클라우드 "조회 시 SQL ERROR" 원인 진단 (SCM_MGR 로 실행, 읽기 전용)
-- 순서대로 실행해 결과를 그대로 회신해 주세요. ①이 곧 정답(SQLCODE/SQLERRM/BACKTRACE)이고 ②~⑧은 원인 축 대조입니다.

-- ① SP 예외 로그 — PKG_DMF0040 / DMF0040_GET_SPREAD_TITLE 의 최근 ERROR (진짜 오류 코드·역추적 위치)
SELECT PROGRAM_NAME, LOG_TYPE, TO_CHAR(EVENT_DATE,'MM-DD HH24:MI:SS') DT, SQL_ERR_CODE, SUBSTR(SQL_ERR_MSG,1,300) ERR, SUBSTR(SQL_BACKTRACE,1,200) BT, SUBSTR(IN_PARA_DATA,1,300) PARAMS
  FROM SCM_MGR.SCM_SYS_LOG_BATCH
 WHERE PROGRAM_NAME LIKE '%DMF0040%' AND (LOG_TYPE='ERROR' OR SQL_ERR_CODE IS NOT NULL)
 ORDER BY EVENT_DATE DESC FETCH FIRST 10 ROWS ONLY;

-- ② 실행 흔적 — 어느 SP 까지 START/END 가 찍혔는지 (END 없이 끊긴 지점 = 실패 SP)
SELECT PROGRAM_NAME, LOG_TYPE, TO_CHAR(EVENT_DATE,'MM-DD HH24:MI:SS') DT, SUBSTR(LOG_MESSAGE,1,60) MSG
  FROM SCM_MGR.SCM_SYS_LOG_BATCH WHERE PROGRAM_NAME LIKE '%DMF0040%' ORDER BY EVENT_DATE DESC FETCH FIRST 20 ROWS ONLY;

-- ③ 객체 실존·상태 — 기대: PKG_DMF0040 SPEC/BODY VALID, DMF0040_GET_SPREAD_TITLE PROCEDURE VALID, PKG_DMF0007 VALID, FN_MULTY_TIME VALID
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'MM-DD HH24:MI') LDDL FROM ALL_OBJECTS
 WHERE OWNER='SCM_MGR' AND OBJECT_NAME IN ('PKG_DMF0040','DMF0040_GET_SPREAD_TITLE','PKG_DMF0007','FN_MULTY_TIME','PKG_SCM0002','DMF0002_GET_TITLESET_POPUP','SCM0002_SET_TITLESET_POPUP') ORDER BY 1,2;
SELECT NAME, TYPE, LINE, TEXT FROM ALL_ERRORS WHERE OWNER='SCM_MGR' AND NAME IN ('PKG_DMF0040','DMF0040_GET_SPREAD_TITLE','PKG_DMF0007') ORDER BY 1,2,SEQUENCE;

-- ④ GTT 6본 실존 — 기대 6
SELECT TABLE_NAME FROM ALL_TABLES WHERE OWNER='SCM_MGR' AND TEMPORARY='Y' AND TABLE_NAME LIKE 'GT_DM40%' ORDER BY 1;

-- ⑤ 시노님 SCM_MST_ITEM_SN → FP_MGR.SCM_ITEM_M 실존 + SCM_MGR 접근권한 (사내: 시노님 → FP_MGR.SCM_ITEM_M)
SELECT SYNONYM_NAME, TABLE_OWNER, TABLE_NAME FROM ALL_SYNONYMS WHERE OWNER='SCM_MGR' AND SYNONYM_NAME='SCM_MST_ITEM_SN';
SELECT OWNER, OBJECT_NAME, OBJECT_TYPE, STATUS FROM ALL_OBJECTS WHERE OBJECT_NAME='SCM_ITEM_M';
SELECT GRANTEE, OWNER, TABLE_NAME, PRIVILEGE FROM ALL_TAB_PRIVS WHERE TABLE_NAME='SCM_ITEM_M';

-- ⑥ 앱 계정 EXECUTE 권한 (UI/BE 계정 ≠ SCM_MGR) — 기대: SCMP_APP/SCMD_APP 에 PKG_DMF0040·PKG_DMF0007·FN_MULTY_TIME·DMF0040_GET_SPREAD_TITLE EXECUTE
SELECT GRANTEE, TABLE_NAME, PRIVILEGE FROM ALL_TAB_PRIVS WHERE OWNER='SCM_MGR'
   AND TABLE_NAME IN ('PKG_DMF0040','PKG_DMF0007','FN_MULTY_TIME','DMF0040_GET_SPREAD_TITLE') ORDER BY 2,1;

-- ⑦ 배선 계약 — PROC_M 인자 수 vs 실제 SP 인자 수 (기대 main 20 / spreadTitle 7 — 불일치 = 바인딩 어긋남 → PLS-306/ORA-06550)
SELECT P.PROC_NM, COUNT(*) PROC_M_CNT,
       (SELECT COUNT(*) FROM ALL_ARGUMENTS A WHERE A.OWNER='SCM_MGR'
          AND NVL(A.PACKAGE_NAME||'.','')||A.OBJECT_NAME = P.PROC_NM AND A.ARGUMENT_NAME IS NOT NULL) ARG_CNT
  FROM SCM_MGR.SCM_ADM_PROC_M P
 WHERE P.PROC_NM IN (SELECT API_URL FROM SCM_MGR.SCM_ADM_API_M WHERE API_ID LIKE 'DMF0040%') GROUP BY P.PROC_NM;
SELECT API_ID, API_TP_CD, API_URL, USE_YN FROM SCM_MGR.SCM_ADM_API_M WHERE API_ID LIKE 'DMF0040%';

-- ⑧ 시트 메타 — SHEET_COLUMNS 'Mkt Fcst Waterfall' 48 / SHEET_MEASURE 3 (SP 가 이 메타로 동적 SELECT 목록을 만든다 — 0행이면 PIVOT 컬럼 부재 ORA-00904/00918)
SELECT PROGRAM_ID, SHEET_NAME, COUNT(*) FROM SCM_MGR.SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID='DMF0040' GROUP BY PROGRAM_ID, SHEET_NAME;
SELECT PROGRAM_ID, SHEET_NAME, COLUMN_NAME FROM SCM_MGR.SCM_MST_SHEET_MEASURE WHERE PROGRAM_ID='DMF0040';

