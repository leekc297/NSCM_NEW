DEFINE V_CB = 'minyonglee1'

PROMPT ===== [D0] 세션 NLS — 사내와 다른 값이 있는지 =====
SELECT PARAMETER, VALUE FROM NLS_SESSION_PARAMETERS
WHERE  PARAMETER IN ('NLS_DATE_FORMAT','NLS_DATE_LANGUAGE','NLS_NUMERIC_CHARACTERS','NLS_LANGUAGE','NLS_TERRITORY')
ORDER  BY PARAMETER;
-- 사내 실측(2026-08-23): NLS_DATE_FORMAT=RR/MM/DD · NLS_NUMERIC_CHARACTERS='.,' · KOREAN/KOREA
-- ⚠ NLS_NUMERIC_CHARACTERS 의 첫 글자(소수점)가 ',' 이면 구 코드의 TO_NUMBER('20260803.0') 가 ORA-01722.

PROMPT ===== [D1] 최신 업로드 배치의 헤더행 실값 (여기가 핵심) =====
SELECT UPLOAD_STATUS_CODE ST, NVL(ATTRIBUTE1,'(null)') A1,
       ATTRIBUTE14, ATTRIBUTE15, ATTRIBUTE16, ATTRIBUTE17, ATTRIBUTE18
FROM   SCM_MGR.SCM_ADM_EXCEL_UPLOAD
WHERE  PROGRAM_ID='DMF0014' AND CREATED_BY='&V_CB'
AND    CREATION_DATE = (SELECT MAX(CREATION_DATE) FROM SCM_MGR.SCM_ADM_EXCEL_UPLOAD
                         WHERE PROGRAM_ID='DMF0014' AND CREATED_BY='&V_CB')
AND    (ATTRIBUTE1 IS NULL OR UPPER(ATTRIBUTE1)='DIVISION*' OR UPLOAD_STATUS_CODE='V_TITLE');
-- 기대: 8자리 숫자('20260803'). '2026-08-03' / '20260803.0' / '2.0260803E7' / 앞뒤 공백이면 파싱 축이 원인.

PROMPT ===== [D2] 종전 코드의 행 채택 조건이 통과하는가 (0 이면 전건 반려의 직접 원인) =====
SELECT COUNT(*) AS OLD_RULE_ROWS
FROM   SCM_MGR.SCM_ADM_EXCEL_UPLOAD Z
WHERE  Z.PROGRAM_ID='DMF0014' AND Z.CREATED_BY='&V_CB'
AND    Z.CREATION_DATE = (SELECT MAX(CREATION_DATE) FROM SCM_MGR.SCM_ADM_EXCEL_UPLOAD
                           WHERE PROGRAM_ID='DMF0014' AND CREATED_BY='&V_CB')
AND    (Z.ATTRIBUTE1 IS NULL OR UPPER(Z.ATTRIBUTE1)='DIVISION*')
AND    Z.ATTRIBUTE15 IS NOT NULL
AND    REGEXP_LIKE(Z.ATTRIBUTE15, '^[0-9.eE+-]+$');   -- 구 조건(표기 기반)

PROMPT ===== [D3] 정정 코드의 채택 조건 + 버킷 판정 결과 =====
WITH Z AS (
  SELECT * FROM SCM_MGR.SCM_ADM_EXCEL_UPLOAD
   WHERE PROGRAM_ID='DMF0014' AND CREATED_BY='&V_CB'
     AND CREATION_DATE = (SELECT MAX(CREATION_DATE) FROM SCM_MGR.SCM_ADM_EXCEL_UPLOAD
                           WHERE PROGRAM_ID='DMF0014' AND CREATED_BY='&V_CB')
     AND (ATTRIBUTE1 IS NULL OR UPPER(ATTRIBUTE1)='DIVISION*')
     AND LENGTH(REGEXP_REPLACE(TRIM(ATTRIBUTE15),'[^0-9]','')) >= 8),
H AS (
  SELECT TO_DATE(CASE WHEN LENGTH(REGEXP_REPLACE(TRIM(ATTRIBUTE14),'[^0-9]','')) >= 8
                      THEN SUBSTR(REGEXP_REPLACE(TRIM(ATTRIBUTE14),'[^0-9]',''),1,8) END,'YYYYMMDD') D14,
         TO_DATE(CASE WHEN LENGTH(REGEXP_REPLACE(TRIM(ATTRIBUTE15),'[^0-9]','')) >= 8
                      THEN SUBSTR(REGEXP_REPLACE(TRIM(ATTRIBUTE15),'[^0-9]',''),1,8) END,'YYYYMMDD') D15,
         TO_DATE(CASE WHEN LENGTH(REGEXP_REPLACE(TRIM(ATTRIBUTE16),'[^0-9]','')) >= 8
                      THEN SUBSTR(REGEXP_REPLACE(TRIM(ATTRIBUTE16),'[^0-9]',''),1,8) END,'YYYYMMDD') D16,
         TO_DATE(CASE WHEN LENGTH(REGEXP_REPLACE(TRIM(ATTRIBUTE17),'[^0-9]','')) >= 8
                      THEN SUBSTR(REGEXP_REPLACE(TRIM(ATTRIBUTE17),'[^0-9]',''),1,8) END,'YYYYMMDD') D17
    FROM Z)
SELECT TO_CHAR(D14,'YYYY-MM-DD') D14, TO_CHAR(D15,'YYYY-MM-DD') D15,
       TO_CHAR(D16,'YYYY-MM-DD') D16, TO_CHAR(D17,'YYYY-MM-DD') D17,
       CASE NVL(NVL(D16-D15, D15-D14), D17-D16)
            WHEN 1 THEN 'DAILY' WHEN 7 THEN 'WEEKLY' ELSE 'MONTHLY' END AS BUCKET_NEW
FROM   H;
-- BUCKET_NEW 가 나오는데 D2 가 0 이었다면 → **원인 확정: 표기 기반 채택 조건**(정정본이 해소).

PROMPT ===== [D4] 마스터가 기대하는 버킷 타입 (판정값과 대조) =====
SELECT UPLOAD_BUCKET_TYPE, COUNT(*) CNT
FROM   SCM_MGR.DM_MST_CUSTOMER_FCST WHERE VALID_YN='Y'
GROUP  BY UPLOAD_BUCKET_TYPE ORDER BY 2 DESC;
-- D3 의 BUCKET_NEW 와 여기에 값이 겹쳐야 통과한다. 겹치는데도 반려면 division/site/measure 축을 볼 것(D5).

PROMPT ===== [D5] 반려된 행의 키가 마스터에 있는가 (축 불일치 확인) =====
SELECT E.ATTRIBUTE1 DIV, E.ATTRIBUTE2 SITE, E.ATTRIBUTE10 MEASURE, COUNT(*) ROWS_CNT,
       SUM(CASE WHEN EXISTS (SELECT 1 FROM SCM_MGR.DM_MST_CUSTOMER_FCST D, SCM_MGR.SCM_MST_DIVISION D2
                              WHERE D.VALID_YN='Y' AND D.DIVISION_ID=D2.DIVISION_ID
                                AND (D2.DIVISION_ID=E.ATTRIBUTE1 OR D2.DIVISION_NAME=E.ATTRIBUTE1)
                                AND D.SCM_SITE_ID=E.ATTRIBUTE2 AND D.MEASURE=E.ATTRIBUTE10)
                THEN 1 ELSE 0 END) MASTER_HIT
FROM   SCM_MGR.SCM_ADM_EXCEL_UPLOAD E
WHERE  E.PROGRAM_ID='DMF0014' AND E.CREATED_BY='&V_CB'
AND    E.CREATION_DATE = (SELECT MAX(CREATION_DATE) FROM SCM_MGR.SCM_ADM_EXCEL_UPLOAD
                           WHERE PROGRAM_ID='DMF0014' AND CREATED_BY='&V_CB')
AND    E.UPLOAD_STATUS_CODE <> 'V_TITLE'
GROUP  BY E.ATTRIBUTE1, E.ATTRIBUTE2, E.ATTRIBUTE10
ORDER  BY 5, 4 DESC;
-- MASTER_HIT=0 인 조합 = 버킷 이전에 site/measure 자체가 마스터에 없다(데이터 축 문제).

