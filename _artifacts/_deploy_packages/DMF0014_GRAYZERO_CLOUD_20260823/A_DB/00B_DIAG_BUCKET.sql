--   증상: 파일 선택(mode=0 검증) 단계에서 전건 ERROR 분류. 사내는 정상.
--   ⭐ 위에서부터 순서대로. **먼저 걸리는 곳이 원인**이다.
--   ⚠ :V_CB(업로드한 사용자ID) 를 바꿔 실행할 것. 최신 배치를 자동으로 잡는다.
