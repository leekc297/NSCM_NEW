-- 05_BACKUP_CLOUD_SOURCE.sql — 적용 직전 클라우드 SPEC+BODY 원문 보관 (비파괴 · 멱등) [E20261006-ASISPARITY]
SET SERVEROUTPUT ON
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='BAK_SRC_DMF0044_ASISPARITY';
  IF n = 0 THEN
    EXECUTE IMMEDIATE q'[CREATE TABLE BAK_SRC_DMF0044_ASISPARITY AS
      SELECT NAME, TYPE, LINE, TEXT, SYSDATE AS BAK_DATE FROM USER_SOURCE WHERE NAME='PKG_DMF0044' AND TYPE IN ('PACKAGE','PACKAGE BODY')]';
    DBMS_OUTPUT.PUT_LINE('PKG_DMF0044 SOURCE BACKUP CREATED');
  ELSE
    DBMS_OUTPUT.PUT_LINE('PKG_DMF0044 SOURCE BACKUP EXISTS - SKIP');
  END IF;
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='BAK_SRC_DMF0049_ASISPARITY';
  IF n = 0 THEN
    EXECUTE IMMEDIATE q'[CREATE TABLE BAK_SRC_DMF0049_ASISPARITY AS
      SELECT NAME, TYPE, LINE, TEXT, SYSDATE AS BAK_DATE FROM USER_SOURCE WHERE NAME='PKG_DMF0049' AND TYPE IN ('PACKAGE','PACKAGE BODY')]';
    DBMS_OUTPUT.PUT_LINE('PKG_DMF0049 SOURCE BACKUP CREATED');
  ELSE
    DBMS_OUTPUT.PUT_LINE('PKG_DMF0049 SOURCE BACKUP EXISTS - SKIP');
  END IF;
END;
/
SELECT 'PKG_DMF0044' PKG, TYPE, COUNT(*) LINES FROM BAK_SRC_DMF0044_ASISPARITY GROUP BY TYPE
UNION ALL SELECT 'PKG_DMF0049', TYPE, COUNT(*) FROM BAK_SRC_DMF0049_ASISPARITY GROUP BY TYPE;
