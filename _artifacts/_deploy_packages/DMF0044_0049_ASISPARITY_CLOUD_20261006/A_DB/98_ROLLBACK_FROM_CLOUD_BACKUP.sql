-- 98_ROLLBACK_FROM_CLOUD_BACKUP.sql — 05 보관본으로 SPEC→BODY 복원 (롤백 전용) [E20261006-ASISPARITY]
SET SERVEROUTPUT ON
DECLARE
  v CLOB;
BEGIN
  FOR t IN (SELECT 'PACKAGE' TYP FROM DUAL UNION ALL SELECT 'PACKAGE BODY' FROM DUAL) LOOP
    DBMS_LOB.CREATETEMPORARY(v, TRUE);
    FOR r IN (SELECT TEXT FROM BAK_SRC_DMF0044_ASISPARITY WHERE NAME='PKG_DMF0044' AND TYPE=t.TYP ORDER BY LINE) LOOP
      DBMS_LOB.APPEND(v, r.TEXT);
    END LOOP;
    IF DBMS_LOB.GETLENGTH(v) > 0 THEN
      EXECUTE IMMEDIATE 'CREATE OR REPLACE ' || v;
      DBMS_OUTPUT.PUT_LINE('REBUILT PKG_DMF0044 ' || t.TYP);
    ELSE
      DBMS_OUTPUT.PUT_LINE('SKIP PKG_DMF0044 ' || t.TYP || ' (no backup)');
    END IF;
    DBMS_LOB.FREETEMPORARY(v);
  END LOOP;
  FOR t IN (SELECT 'PACKAGE' TYP FROM DUAL UNION ALL SELECT 'PACKAGE BODY' FROM DUAL) LOOP
    DBMS_LOB.CREATETEMPORARY(v, TRUE);
    FOR r IN (SELECT TEXT FROM BAK_SRC_DMF0049_ASISPARITY WHERE NAME='PKG_DMF0049' AND TYPE=t.TYP ORDER BY LINE) LOOP
      DBMS_LOB.APPEND(v, r.TEXT);
    END LOOP;
    IF DBMS_LOB.GETLENGTH(v) > 0 THEN
      EXECUTE IMMEDIATE 'CREATE OR REPLACE ' || v;
      DBMS_OUTPUT.PUT_LINE('REBUILT PKG_DMF0049 ' || t.TYP);
    ELSE
      DBMS_OUTPUT.PUT_LINE('SKIP PKG_DMF0049 ' || t.TYP || ' (no backup)');
    END IF;
    DBMS_LOB.FREETEMPORARY(v);
  END LOOP;
END;
/
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM USER_OBJECTS WHERE OBJECT_NAME IN ('PKG_DMF0044', 'PKG_DMF0049') ORDER BY 1, 2;
