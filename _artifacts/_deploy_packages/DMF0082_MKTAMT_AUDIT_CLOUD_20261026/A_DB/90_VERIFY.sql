-- 90_VERIFY — 조회 전용 (전체 F5). [E20261026-DMF0082-MKTAMTAUDIT] 적용 결과
--   V1 BODY VALID · 오류 0 / V2 표식 줄 수 = 9 / V3 금액 arm 4곳에 NULL 고정 잔존 0
SELECT 'V1' CHK, OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL
     , (SELECT COUNT(*) FROM USER_ERRORS E WHERE E.NAME = O.OBJECT_NAME AND E.TYPE = O.OBJECT_TYPE) N_ERR
  FROM USER_OBJECTS O WHERE OBJECT_NAME = 'PKG_DMF0082' ORDER BY OBJECT_TYPE;
SELECT 'V2' CHK, COUNT(*) TAG_LINES, CASE WHEN COUNT(*) = 9 THEN 'PASS' ELSE 'FAIL (기대 9)' END JUDGE
  FROM USER_SOURCE WHERE NAME = 'PKG_DMF0082' AND TYPE = 'PACKAGE BODY' AND INSTR(TEXT, 'MKTAMTAUDIT') > 0;
