SET SERVEROUTPUT ON
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='BAK_SRC_DMF0082_81MKTAMT';
  IF n = 0 THEN
    EXECUTE IMMEDIATE q'[CREATE TABLE BAK_SRC_DMF0082_81MKTAMT AS
      SELECT NAME, TYPE, LINE, TEXT, SYSDATE AS BAK_DATE FROM USER_SOURCE WHERE NAME='PKG_DMF0082' AND TYPE IN ('PACKAGE','PACKAGE BODY')]';
    DBMS_OUTPUT.PUT_LINE('SOURCE BACKUP CREATED');
  ELSE
    DBMS_OUTPUT.PUT_LINE('SOURCE BACKUP EXISTS - SKIP');
  END IF;
END;
/
SELECT TYPE, COUNT(*) LINES FROM BAK_SRC_DMF0082_81MKTAMT GROUP BY TYPE;
