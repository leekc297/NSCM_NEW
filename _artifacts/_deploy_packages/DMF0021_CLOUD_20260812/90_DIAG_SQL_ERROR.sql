-- 클라우드 QA/DEV 각각에서 그대로 실행 후 결과 전체를 회신해 주세요.

-- [1] PKG 컴파일 상태 — 기대: PACKAGE / PACKAGE BODY 모두 VALID
--     INVALID 면 조회 시 ORA-04063/06508 이 난다 (최유력 후보: BODY 가 참조하는
--     객체가 클라우드에 없어 컴파일 실패 — [2] 가 원인 행을 알려줌)
SELECT OBJECT_TYPE, STATUS, LAST_DDL_TIME
  FROM ALL_OBJECTS
 WHERE OWNER = 'SCM_MGR' AND OBJECT_NAME = 'PKG_DMF0021'
 ORDER BY OBJECT_TYPE;

-- [2] 컴파일 오류 원문 — 기대: 0행. 있으면 부재 객체/컬럼이 그대로 찍힌다
SELECT LINE, POSITION, TEXT
  FROM ALL_ERRORS
 WHERE OWNER = 'SCM_MGR' AND NAME = 'PKG_DMF0021'
 ORDER BY SEQUENCE;

-- [3] BODY 가 참조하는 객체 중 클라우드에 없는 것 — 기대: 0행
--     (사내 BODY 재덤프본이라 사내에만 있는 참조가 섞였는지 검출)
SELECT d.REFERENCED_NAME, d.REFERENCED_TYPE
  FROM ALL_DEPENDENCIES d
 WHERE d.OWNER = 'SCM_MGR' AND d.NAME = 'PKG_DMF0021' AND d.TYPE = 'PACKAGE BODY'
   AND d.REFERENCED_OWNER = 'SCM_MGR'
   AND NOT EXISTS (SELECT 1 FROM ALL_OBJECTS o
                    WHERE o.OWNER = d.REFERENCED_OWNER AND o.OBJECT_NAME = d.REFERENCED_NAME)
 ORDER BY 1;

-- [4] GTT 자급 확인 (01_GTT_DDL 실행 여부) — 기대: 19행
SELECT COUNT(*) AS GTT_CNT
  FROM ALL_TABLES
 WHERE OWNER = 'SCM_MGR' AND TEMPORARY = 'Y'
   AND TABLE_NAME IN (SELECT DISTINCT REFERENCED_NAME FROM ALL_DEPENDENCIES
                       WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0021' AND TYPE='PACKAGE BODY'
                         AND REFERENCED_TYPE='TABLE'
                         AND (REFERENCED_NAME LIKE 'GT!_%' ESCAPE '!' OR REFERENCED_NAME LIKE 'GTT%'));

-- [5] 메타 적용 상태 요약 — SHEET_COLUMNS('Sales Plan'/DMF0021) / MEASURE / lookup
SELECT 'SHEET_COLUMNS' AS T, COUNT(*) AS CNT, MAX(LAST_UPDATE_DATE) AS LAST_UPD
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID='DMF0021'
UNION ALL
SELECT 'SHEET_MEASURE', COUNT(*), MAX(LAST_UPDATE_DATE)
  FROM SCM_MGR.SCM_MST_SHEET_MEASURE WHERE PROGRAM_ID='DMF0021'
UNION ALL
SELECT 'LOOKUP_RTFGATE', COUNT(*), MAX(LAST_UPDATE_DATE)
  FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE='GET_ADMIN_GROUP_MEASURE' AND SEGMENT2='DMF0021'
UNION ALL
SELECT 'LOOKUP_ITEM_ID', COUNT(*), MAX(LAST_UPDATE_DATE)
  FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE='SALES_PLAN_ITEM_ID'
UNION ALL
SELECT 'CMBO_SalesPlanItemId', COUNT(*), MAX(LAST_UPDATE_DATE)
  FROM SCM_MGR.SCM_ADM_CMBO_SQL_M WHERE SQL_ID='SalesPlanItemId';

-- [6] 07 정정본(v2) 적용 후 논리키 상태 — 기대: 중복 0행
SELECT SEGMENT1, SEGMENT2, SEGMENT3, SEGMENT4, COUNT(*)
  FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE IN ('GET_ADMIN_GROUP_MEASURE','SALES_PLAN_ITEM_ID')
 GROUP BY SEGMENT1, SEGMENT2, SEGMENT3, SEGMENT4
HAVING COUNT(*) > 1;

