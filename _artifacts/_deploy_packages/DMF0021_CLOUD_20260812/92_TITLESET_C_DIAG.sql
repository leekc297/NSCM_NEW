-- 92_TITLESET_C_DIAG.sql — DMF0021 클라우드 titleset 'C' 오염 진단·정리 (2026-08-12)
-- ORA-00960(조회 SQL ERROR)의 오염원 확인용. ⭐ 03_BODY(COLDEDUP 가드) 재적용만으로 조회는 복구된다 —
-- 본 파일은 오염 데이터 자체를 정리하고 싶을 때만 [2] 를 실행 (표적 DELETE — 사용자 판단).

-- [1] 오염 행 진단 — titleset 'C' 에 저장된 고정컬럼(화면 비표시 계열) = 오염
SELECT U.USER_ID, U.COLUMN_NAME, U.SORT_ORDER_NO, U.LAST_UPDATE_DATE
  FROM SCM_MGR.SCM_MST_TITLESET_USER U
  JOIN SCM_MGR.SCM_MST_SHEET_COLUMNS C
    ON C.PROGRAM_ID = U.PROGRAM_ID AND C.SHEET_NAME = U.SHEET_NAME AND C.COLUMN_NAME = U.COLUMN_NAME
 WHERE U.PROGRAM_ID = 'DMF0021' AND U.SHEET_NAME = 'Sales Plan'
   AND U.USER_INQUIRY_COLUMN_TYPE_CODE = 'C'
   AND C.VISIBLE_FLAG = 'N' AND NVL(C.DEFAULT_FLAG,'N') <> 'Y' AND C.VALID_YN = 'Y'
 ORDER BY U.USER_ID, U.COLUMN_NAME;

-- [1-2] FROM_SITE_ID 계열 — titleset 에 있으면 SHEET_COLUMNS DIVISION 스코프 2행과 곱해져 중복되던 축
SELECT U.USER_ID, U.COLUMN_NAME
  FROM SCM_MGR.SCM_MST_TITLESET_USER U
 WHERE U.PROGRAM_ID = 'DMF0021' AND U.SHEET_NAME = 'Sales Plan'
   AND U.USER_INQUIRY_COLUMN_TYPE_CODE = 'C' AND U.COLUMN_NAME = 'FROM_SITE_ID';

-- [2] 표적 정리 (선택 — [1] 결과 확인 후 실행. COLDEDUP 가드가 방어하므로 필수는 아님)
DELETE FROM SCM_MGR.SCM_MST_TITLESET_USER U
 WHERE U.PROGRAM_ID = 'DMF0021' AND U.SHEET_NAME = 'Sales Plan'
   AND U.USER_INQUIRY_COLUMN_TYPE_CODE = 'C'
   AND EXISTS (SELECT 1 FROM SCM_MGR.SCM_MST_SHEET_COLUMNS C
                WHERE C.PROGRAM_ID = U.PROGRAM_ID AND C.SHEET_NAME = U.SHEET_NAME
                  AND C.COLUMN_NAME = U.COLUMN_NAME
                  AND C.VISIBLE_FLAG = 'N' AND NVL(C.DEFAULT_FLAG,'N') <> 'Y' AND C.VALID_YN = 'Y');
COMMIT;
