-- 1) 컴파일 상태
SELECT OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS')
FROM   ALL_OBJECTS WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_DMF0082';
-- 2) 컴파일 에러 0 확인
SELECT * FROM ALL_ERRORS WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082';
-- 3) 마커 2행 확인 (GET_MAIN_DATA / GET_MAIN_DATA_CURRENT)
SELECT LINE, RTRIM(TEXT) FROM ALL_SOURCE
WHERE  OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY'
AND    INSTR(TEXT,'E20260908-GETRANGE')>0 ORDER BY LINE;
-- 4) D_ 버킷 확장 확인 (조회종료일까지 나와야 함 — 구 구현은 시작일+50주에서 끊김)
--    아래는 2026-09-01 ~ 2027-09-01(1년) 예시: D_ 최대일자가 20270901 이어야 정상(구=20270817)
SELECT MAX(A.BASIS_YYYYMMDD) AS D_MAX
FROM   SCM_MGR.SCM_SYS_CALENDAR_M A
WHERE  A.BASIS_YYYYMMDD >= '20260901'
AND    A.BASIS_YYYYMMDD <= GREATEST(TO_CHAR(TO_DATE('20260901','YYYYMMDD')+(50*7),'YYYYMMDD'),'20270901');
