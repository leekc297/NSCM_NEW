-- 90 VERIFY — [GAP446 2026-10-15] GAP 446 조회 전용 (전체 F5, 값 입력 없음)
-- * 기대: V1 마커 9줄 PASS · V2 VALID / 오류 0 / 의존 INVALID 0 · V3 연산별 신 줄 PASS · V4 구 줄 잔존 0 PASS
-- * 화면 확인(README 4단계): 과거 SF·MF·SP 버전 조회 행 구성이 AS-IS 와 같다.
SET LINESIZE 220 PAGESIZE 500
SET DEFINE OFF
COLUMN CHK FORMAT A10
COLUMN KIND FORMAT A40
COLUMN JUDGE FORMAT A60
SELECT 'V1 마커' CHK, COUNT(*) N, LISTAGG(LINE, ',') WITHIN GROUP (ORDER BY LINE) LINES,
       CASE WHEN COUNT(*) = 9 THEN 'PASS' ELSE 'FAIL (미적용 또는 마커 수 불일치)' END JUDGE
  FROM USER_SOURCE WHERE NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%GAP446 2026-10-15%';
SELECT 'V2 상태' CHK, O.OBJECT_TYPE, O.STATUS, TO_CHAR(O.LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL,
       (SELECT COUNT(*) FROM USER_ERRORS E WHERE E.NAME=O.OBJECT_NAME AND E.TYPE=O.OBJECT_TYPE) ERR_CNT,
       (SELECT COUNT(*) FROM USER_OBJECTS X WHERE X.STATUS<>'VALID' AND X.OBJECT_NAME IN (SELECT NAME FROM USER_DEPENDENCIES WHERE REFERENCED_NAME='PKG_DMF0082')) DEP_INVALID
  FROM USER_OBJECTS O WHERE O.OBJECT_NAME='PKG_DMF0082' ORDER BY O.OBJECT_TYPE;
SELECT 'V3 신 줄' CHK, K.KIND, COUNT(S.LINE) N, K.EXPECT,
       CASE WHEN COUNT(S.LINE) = K.EXPECT THEN 'PASS' ELSE 'FAIL — 회신' END JUDGE
  FROM ( SELECT 'C1 NOW 산식' KIND, '             , TO_CHAR(SCM_MGR.FN_NEXT_DAY(TO_DATE(B.YYYYMMDD, ''YYYYMMDD''), ''MON'') - 7, ''YYYYMMDD'') AS NOW_YYYYMMDD  --[GAP446 2026-10-15]' TXT, 1 EXPECT FROM DUAL UNION ALL
         SELECT 'C2 MF·SF 계획 NOW (MF 2 + SF 2)', '        AND    A.YYYYMMDD >= F.NOW_YYYYMMDD  --[GAP446 2026-10-15]', 4 FROM DUAL UNION ALL
         SELECT 'C3 MF 판가 NOW', '        AND    A.YYYYMMDD >= F.NOW_YYYYMMDD;  --[GAP446 2026-10-15]', 2 FROM DUAL UNION ALL
         SELECT 'C5 SP 3종 삭제', '     WHERE A.MEASURE IN (''MKT_AMT_KRW'', ''MKT_AMT_LOC'', ''RTF_SYS_RP'');', 1 FROM DUAL ) K
  LEFT JOIN USER_SOURCE S
    ON S.NAME = 'PKG_DMF0082' AND S.TYPE = 'PACKAGE BODY' AND S.TEXT LIKE K.TXT || '%'
   AND S.LINE BETWEEN (SELECT MIN(LINE) FROM USER_SOURCE WHERE NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND RTRIM(TEXT, CHR(10)||CHR(13)) = 'PROCEDURE P_DMF0082_GET_MAIN_DATA')
                  AND (SELECT MIN(LINE) FROM USER_SOURCE WHERE NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND TEXT LIKE 'PROCEDURE P_DMF0082_GET_MAIN_DATA_CURRENT%')
 GROUP BY K.KIND, K.EXPECT
 ORDER BY K.KIND;
SELECT 'V4 구 줄' CHK, K.KIND, COUNT(S.LINE) N,
       CASE WHEN COUNT(S.LINE) = 0 THEN 'PASS' ELSE 'FAIL — 구 줄 잔존' END JUDGE
  FROM ( SELECT 'C1 구 NOW 산식' KIND, '             , TO_CHAR(TO_DATE(B.YYYYMMDD, ''YYYYMMDD'') - 7, ''YYYYMMDD'') AS NOW_YYYYMMDD' TXT FROM DUAL UNION ALL
         SELECT 'C4 SF 실적 원장(구)', '        FROM   SCM_MGR.DM_PLN_MKT_FCST_RESULT_C A' FROM DUAL ) K
  LEFT JOIN USER_SOURCE S
    ON S.NAME = 'PKG_DMF0082' AND S.TYPE = 'PACKAGE BODY' AND RTRIM(S.TEXT, CHR(10)||CHR(13)) = K.TXT
   AND S.LINE BETWEEN (SELECT MIN(LINE) FROM USER_SOURCE WHERE NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND RTRIM(TEXT, CHR(10)||CHR(13)) = 'IF p_version_type LIKE ''%SF%'' THEN')
                  AND (SELECT MIN(LINE) FROM USER_SOURCE WHERE NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND TEXT LIKE 'PROCEDURE P_DMF0082_GET_MAIN_DATA_CURRENT%')
 GROUP BY K.KIND
 ORDER BY K.KIND;
