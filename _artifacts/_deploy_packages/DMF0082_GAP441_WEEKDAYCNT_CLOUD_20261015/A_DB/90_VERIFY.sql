-- 90 VERIFY — [GAP441 2026-10-15] GAP 441 조회 전용 (전체 F5, 값 입력 없음)
-- * 기대: V1 마커 PASS(1줄) · V2 VALID / 오류 0 / 의존 INVALID 0 · V3 구 줄 0 + 신 줄 1 PASS
--         · V4 참고: 오늘~+6개월 캘린더에서 월 경계 부분 주 때문에 주 일수가 바뀌는 날 수 · 2027-03 3,100 배분 합계(구식/신식)
SET LINESIZE 220 PAGESIZE 500
SET DEFINE OFF
COLUMN CHK FORMAT A10
COLUMN JUDGE FORMAT A60
SELECT 'V1 마커' CHK, COUNT(*) N, MIN(LINE) LINE,
       CASE WHEN COUNT(*) = 1 THEN 'PASS' ELSE 'FAIL (미적용 또는 마커 수 불일치)' END JUDGE
  FROM USER_SOURCE WHERE NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%GAP441 2026-10-15%';
SELECT 'V2 상태' CHK, O.OBJECT_TYPE, O.STATUS, TO_CHAR(O.LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL,
       (SELECT COUNT(*) FROM USER_ERRORS E WHERE E.NAME=O.OBJECT_NAME AND E.TYPE=O.OBJECT_TYPE) ERR_CNT,
       (SELECT COUNT(*) FROM USER_OBJECTS X WHERE X.STATUS<>'VALID' AND X.OBJECT_NAME IN (SELECT NAME FROM USER_DEPENDENCIES WHERE REFERENCED_NAME='PKG_DMF0082')) DEP_INVALID
  FROM USER_OBJECTS O WHERE O.OBJECT_NAME='PKG_DMF0082' ORDER BY O.OBJECT_TYPE;
SELECT 'V3 문장' CHK,
       SUM(CASE WHEN RTRIM(S.TEXT, CHR(10)||CHR(13)) = '             , COUNT(*) OVER (PARTITION BY A.ISO_WEEK) AS WEEK_DAY_CNT' THEN 1 ELSE 0 END) OLD_N,
       SUM(CASE WHEN RTRIM(S.TEXT, CHR(10)||CHR(13)) = '             , COUNT(*) OVER (PARTITION BY A.ISO_YYYYWW || A.PARTIAL_WEEK_NAME) AS WEEK_DAY_CNT' THEN 1 ELSE 0 END) NEW_N,
       CASE WHEN SUM(CASE WHEN RTRIM(S.TEXT, CHR(10)||CHR(13)) = '             , COUNT(*) OVER (PARTITION BY A.ISO_WEEK) AS WEEK_DAY_CNT' THEN 1 ELSE 0 END) = 0
             AND SUM(CASE WHEN RTRIM(S.TEXT, CHR(10)||CHR(13)) = '             , COUNT(*) OVER (PARTITION BY A.ISO_YYYYWW || A.PARTIAL_WEEK_NAME) AS WEEK_DAY_CNT' THEN 1 ELSE 0 END) = 1
            THEN 'PASS' ELSE 'FAIL — 구 줄 잔존 또는 신 줄 수 이상' END JUDGE
  FROM USER_SOURCE S
 WHERE S.NAME = 'PKG_DMF0082' AND S.TYPE = 'PACKAGE BODY'
   AND S.LINE BETWEEN (SELECT MIN(LINE) FROM USER_SOURCE WHERE NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND RTRIM(TEXT, CHR(10)||CHR(13)) = 'PROCEDURE P_DMF0082_GET_MAIN_DATA')
                  AND (SELECT MIN(LINE) FROM USER_SOURCE WHERE NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND TEXT LIKE 'PROCEDURE P_DMF0082_GET_MAIN_DATA_CURRENT%');
SELECT 'V4 참고' CHK, COUNT(*) DAYS, SUM(CASE WHEN OLD_CNT <> NEW_CNT THEN 1 ELSE 0 END) CHANGED_DAYS
  FROM ( SELECT COUNT(*) OVER (PARTITION BY ISO_WEEK) OLD_CNT
              , COUNT(*) OVER (PARTITION BY ISO_YYYYWW || PARTIAL_WEEK_NAME) NEW_CNT
           FROM SCM_SYS_CALENDAR_M
          WHERE BASIS_YYYYMMDD BETWEEN TO_CHAR(TRUNC(SYSDATE,'MM'),'YYYYMMDD') AND TO_CHAR(LAST_DAY(ADD_MONTHS(SYSDATE,6)),'YYYYMMDD') );
SELECT 'V4 배분' CHK, SUM(FLOOR(3100 / 31 * OLD_CNT)) OLD_SUM_3100, SUM(FLOOR(3100 / 31 * NEW_CNT)) NEW_SUM_3100,
       CASE WHEN SUM(FLOOR(3100 / 31 * NEW_CNT)) = 3100 THEN 'PASS' ELSE 'FAIL — 회신' END JUDGE
  FROM ( SELECT BASIS_YYYYMMDD, BASIS_YYYYMM
              , COUNT(*) OVER (PARTITION BY ISO_WEEK) OLD_CNT
              , COUNT(*) OVER (PARTITION BY ISO_YYYYWW || PARTIAL_WEEK_NAME) NEW_CNT
              , ROW_NUMBER() OVER (PARTITION BY ISO_YYYYWW || PARTIAL_WEEK_NAME ORDER BY BASIS_YYYYMMDD) RN
           FROM SCM_SYS_CALENDAR_M
          WHERE BASIS_YYYYMMDD BETWEEN '20260901' AND '20270430' )
 WHERE BASIS_YYYYMM = '202703' AND RN = 1;
