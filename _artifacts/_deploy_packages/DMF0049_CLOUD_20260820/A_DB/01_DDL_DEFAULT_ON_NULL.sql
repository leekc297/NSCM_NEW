-- NOT NULL 컬럼 DEFAULT ON NULL — 2026-08-20 사용자 확정 "NOT NULL 컬럼은 DEFAULT ON NULL 설정".
--   사내에는 이미 적용 완료(VARCHAR2 10 x 2표 = '-', QTY x 2표 = 0). 클라우드는 미확인 →
--   **현재 사내 상태를 ALL_TAB_COLUMNS 로 실측해 멱등 DDL 로 동봉**한다(추정 금지).
-- 멱등 방식: DEFAULT_ON_NULL='YES' 면 skip. 이미 적용된 클라우드에서도 무해하다.
-- ⚠ 의도적 제외 (README §3-1):
--   · DATA_SEQ / HISTORY_SEQ = 키·시퀀스. 0 기본값은 PK 충돌·유령행을 **조용히** 만든다.
--   · 감사컬럼 4종(CREATED_BY/CREATION_DATE/LAST_UPDATED_BY/LAST_UPDATE_DATE) = 확정 제외 계보.
--   두 축 모두 '비면 즉시 실패' 가 정상 동작이다 — 조용한 오류 은폐 방지.

-- ── DM_PLN_SALES_ETC_REPORT_C : 대상 11 컬럼 (NOT NULL ∧ 사내 DEFAULT_ON_NULL='YES' ∧ 제외축 밖)
-- DM_PLN_SALES_ETC_REPORT_C.VERSION_NO (VARCHAR2) DEFAULT ON NULL '-'
DECLARE v_n NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_n FROM ALL_TAB_COLUMNS
   WHERE OWNER='SCM_MGR' AND TABLE_NAME='DM_PLN_SALES_ETC_REPORT_C' AND COLUMN_NAME='VERSION_NO'
     AND DEFAULT_ON_NULL='YES';
  IF v_n = 0 THEN
    EXECUTE IMMEDIATE q'[ALTER TABLE SCM_MGR.DM_PLN_SALES_ETC_REPORT_C MODIFY (VERSION_NO DEFAULT ON NULL '-')]';
  END IF;
END;
/

