-- 90_VERIFY — [E20261028-DUPKEYMSG] 적용 후 확인 (조회 전용 · 전체 F5 안전)
--   V1 PKG_DMF0049 BODY VALID · 오류 0
--   V2 NEW-BEGIN / NEW-END 각 2줄 (중복 검증 2곳 교체됨) · ORIG_LINES = 원래 줄 주석 보존 수(사내 50, 0 보다 커야 원복 가능)
SET DEFINE OFF

SELECT 'V1' CHK, O.OBJECT_TYPE, O.STATUS, TO_CHAR(O.LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL
     , (SELECT COUNT(*) FROM USER_ERRORS E WHERE E.NAME = O.OBJECT_NAME AND E.TYPE = O.OBJECT_TYPE) ERR_CNT
  FROM USER_OBJECTS O WHERE O.OBJECT_NAME = 'PKG_DMF0049' ORDER BY O.OBJECT_TYPE;

SELECT 'V2' CHK
     , SUM(CASE WHEN TEXT LIKE '%[E20261028-DUPKEYMSG] NEW-BEGIN%' THEN 1 ELSE 0 END) NEW_BEGIN
     , SUM(CASE WHEN TEXT LIKE '%[E20261028-DUPKEYMSG] NEW-END%' THEN 1 ELSE 0 END) NEW_END
     , SUM(CASE WHEN TEXT LIKE '--[E20261028-DUPKEYMSG]ORIG %' THEN 1 ELSE 0 END) ORIG_LINES
  FROM USER_SOURCE WHERE NAME = 'PKG_DMF0049' AND TYPE = 'PACKAGE BODY';
