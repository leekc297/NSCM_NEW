-- 00_PRECHECK_CLOUD — [E20261028-DUPKEYMSG] 적용 전 확인 (조회 전용 · 전체 F5 안전 · 값 입력 없음)
--   P1 PKG_DMF0049 상태·LAST_DDL      → BODY VALID 이어야 진행
--   P2 마커 [E20261028-DUPKEYMSG] 줄 수 → 0 = 미적용(10 실행 대상) / 0 보다 크면 이미 적용
--   P3 교체 대상 블록 시작 줄            → 2행(건수 블록 'SELECT COUNT(*) INTO v_chk FROM (' · 안내문 블록 'FROM ( SELECT A.VERSION_NO, …')이어야 10_APPLY 가 동작
SET DEFINE OFF

SELECT 'P1' CHK, OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL
  FROM USER_OBJECTS WHERE OBJECT_NAME = 'PKG_DMF0049' ORDER BY OBJECT_TYPE;

SELECT 'P2' CHK, COUNT(*) MARKER_LINES
  FROM USER_SOURCE WHERE NAME = 'PKG_DMF0049' AND TYPE = 'PACKAGE BODY' AND TEXT LIKE '%[E20261028-DUPKEYMSG]%';

WITH S AS (SELECT LINE, TEXT FROM USER_SOURCE WHERE NAME = 'PKG_DMF0049' AND TYPE = 'PACKAGE BODY')
SELECT 'P3' CHK, S.LINE, SUBSTR(TRIM(S.TEXT), 1, 90) TXT, SUBSTR(TRIM(S2.TEXT), 1, 60) LINE_PLUS_2
  FROM S
  LEFT JOIN S S2 ON S2.LINE = S.LINE + 2
 WHERE ( REGEXP_LIKE(S.TEXT, '^\s*SELECT\s+COUNT\(\*\)\s+INTO\s+v_chk\s+FROM\s+\(\s*$', 'i') AND S2.TEXT LIKE '%DM_PLN_SALES_ETC_REPORT_C A%' )
    OR REGEXP_LIKE(S.TEXT, '^\s*FROM\s+\(\s*SELECT\s+A\.VERSION_NO,\s*A\.DIVISION_ID,\s*A\.DEPARTMENT_ID', 'i')
 ORDER BY S.LINE;
