-- DMF0082_CLOUD_20260826_PENDING / Excel Upload 메타 (SCM_ADM_EXCEL_COLUMNS) — 단가 테이블 컬럼 축 전환
-- [E20260825-XLSPRICECOL] 슬롯2 End Customer->Project Code / 슬롯8 Cell Prod Site->Plant Site (위치 보존)
-- 2026-08-26 재작성: 구 UPDATE 단문은 클라우드에 행 부재 시 0건 무효(실측) — 멱등 MERGE 로 전환.
--   ON 키 = (PROGRAM_ID, SHEET_NAME) 논리키 / 값 = 사내 정본 행 전 컬럼 실측 (DDL NOT NULL 6컬럼 전부 명시:
--   STORAGE_SQL_ID·HEADER_CONTENT·OPTION_ATTRIBUTE_COLUMN_NUMBER=70·VALID_YN·CREATION_DATE·LAST_UPDATE_DATE)
-- ⚠ 02_(BODY) 와 같은 배포창에서 연속 적용 필수 — 한쪽만 적용 시 업로드 슬롯 계약(ATTRIBUTE2/8) 불일치.
MERGE INTO SCM_MGR.SCM_ADM_EXCEL_COLUMNS T
USING (SELECT 'DMF0082' P, 'FcstNPrice' S FROM DUAL) X
ON (T.PROGRAM_ID = X.P AND T.SHEET_NAME = X.S)
WHEN MATCHED THEN UPDATE SET
       T.STORAGE_SQL_ID = 'PKG_DMF0082.P_DMF0082_EXCEL_UPLOAD'
     , T.HEADER_CONTENT = 'Div|Project Code|Sales Site|Model|Incoterms|FCST Type|Customs Handbook|Plant Site|Currency|Measure'
     , T.OPTION_ATTRIBUTE_COLUMN_NUMBER = 70
     , T.VALID_YN = 'Y'
     , T.LAST_UPDATED_BY = 'admin'
     , T.LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT
     ( PROGRAM_ID, SHEET_NAME, STORAGE_SQL_ID, HEADER_CONTENT, OPTION_ATTRIBUTE_COLUMN_NUMBER
     , VALID_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE )
VALUES ( 'DMF0082', 'FcstNPrice', 'PKG_DMF0082.P_DMF0082_EXCEL_UPLOAD'
     , 'Div|Project Code|Sales Site|Model|Incoterms|FCST Type|Customs Handbook|Plant Site|Currency|Measure'
     , 70, 'Y', 'admin', SYSDATE, 'admin', SYSDATE );
COMMIT;

-- 검증 (기대 1행 · HEADER 신본 · validProc 배선)
SELECT PROGRAM_ID, SHEET_NAME, STORAGE_SQL_ID, HEADER_CONTENT, OPTION_ATTRIBUTE_COLUMN_NUMBER, VALID_YN
FROM   SCM_MGR.SCM_ADM_EXCEL_COLUMNS
WHERE  PROGRAM_ID = 'DMF0082' AND SHEET_NAME = 'FcstNPrice';
