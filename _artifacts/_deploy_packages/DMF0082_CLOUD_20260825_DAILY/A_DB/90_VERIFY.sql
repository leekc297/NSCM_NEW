  SELECT 'E20260825-AFSBLANK', 2 FROM DUAL UNION ALL
  SELECT 'E20260825-AFSNVL', 1 FROM DUAL UNION ALL
  SELECT 'E20260825-81AUTH', 3 FROM DUAL UNION ALL
  SELECT 'E20260825-CUSTSUB', 1 FROM DUAL UNION ALL
  SELECT 'E20260825-CURRNORM', 2 FROM DUAL UNION ALL
  SELECT 'E20260825-XLSMASTER', 3 FROM DUAL UNION ALL
  SELECT 'E20260825-XLSBATCH', 1 FROM DUAL UNION ALL
  SELECT 'E20260825-XLSBATCH2', 1 FROM DUAL UNION ALL
  SELECT 'E20260825-XLSPRJ', 1 FROM DUAL UNION ALL
