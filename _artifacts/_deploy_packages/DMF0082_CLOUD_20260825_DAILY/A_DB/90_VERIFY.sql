  SELECT 'E20260825-SAVEPOPCLOB', 1 FROM DUAL UNION ALL
  SELECT 'E20260825-SAVEPOPCLOB2', 3 FROM DUAL UNION ALL
  SELECT 'E20260825-SAVEPOPPERF', 1 FROM DUAL)
SELECT e.MARKER, e.CNT EXPECTED,
       (SELECT COUNT(*) FROM ALL_SOURCE s
         WHERE s.OWNER='SCM_MGR' AND s.NAME='PKG_DMF0082' AND s.TYPE='PACKAGE BODY'
           AND INSTR(s.TEXT, e.MARKER) > 0) ACTUAL,
       CASE WHEN e.CNT = (SELECT COUNT(*) FROM ALL_SOURCE s
                           WHERE s.OWNER='SCM_MGR' AND s.NAME='PKG_DMF0082' AND s.TYPE='PACKAGE BODY'
                             AND INSTR(s.TEXT, e.MARKER) > 0)
            THEN 'PASS' ELSE 'FAIL' END VERDICT
