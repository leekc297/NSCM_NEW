-- SYS0012 SCMD_APP 권한 (BE 사용계정)
-- ⚠ 신규 화면 작성 시 반드시 SCM_MGR (DDL owner) 에서 실행
-- ⚠ 누락 시 BE 호출 -9994 'Sql Error' (PLS-00201 권한없음)

-- 1) SP EXECUTE GRANT + PUBLIC SYNONYM
GRANT EXECUTE ON SCM_MGR.P_SYS0012_APPROVE TO SCMD_APP;
CREATE OR REPLACE SYNONYM SCMD_APP.P_SYS0012_APPROVE FOR SCM_MGR.P_SYS0012_APPROVE;
GRANT EXECUTE ON SCM_MGR.P_SYS0012_GET_APPROVAL_LIST TO SCMD_APP;
CREATE OR REPLACE SYNONYM SCMD_APP.P_SYS0012_GET_APPROVAL_LIST FOR SCM_MGR.P_SYS0012_GET_APPROVAL_LIST;
GRANT EXECUTE ON SCM_MGR.P_SYS0012_REJECT TO SCMD_APP;
CREATE OR REPLACE SYNONYM SCMD_APP.P_SYS0012_REJECT FOR SCM_MGR.P_SYS0012_REJECT;

-- 3) 검증
SELECT GRANTEE, PRIVILEGE, TABLE_NAME FROM DBA_TAB_PRIVS
 WHERE GRANTEE='SCMD_APP' AND OWNER='SCM_MGR' AND TABLE_NAME LIKE '%SYS0012%'
 ORDER BY TABLE_NAME, PRIVILEGE;
