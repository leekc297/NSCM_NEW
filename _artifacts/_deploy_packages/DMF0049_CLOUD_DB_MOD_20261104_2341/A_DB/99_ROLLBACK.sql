            IF k = 0 THEN ddl(v_ddl, 'INDEX ' || v_ix); END IF;
        END LOOP; CLOSE c;
    EXCEPTION WHEN OTHERS THEN IF SQLCODE = -942 THEN NULL; ELSE RAISE; END IF;
    END;
    /* 3) 코드 — 백업 때 없던 객체 DROP, 있던 객체는 백업 원문으로 CREATE OR REPLACE (스펙 → 본문 순) */
    SELECT COUNT(*) INTO n FROM ZB_DMF0049_202611042341_OBJ WHERE NAME = 'PKG_DMF0049' AND OBJECT_TYPE IS NOT NULL;
    IF n = 0 THEN
        SELECT COUNT(*) INTO n FROM USER_OBJECTS WHERE OBJECT_NAME = 'PKG_DMF0049' AND OBJECT_TYPE = 'PACKAGE';
        IF n > 0 THEN ddl('DROP PACKAGE PKG_DMF0049', 'DROP PKG_DMF0049 (백업 시 없었음)'); END IF;
    ELSE
        v := NULL;
        FOR r IN (SELECT TEXT FROM ZB_DMF0049_202611042341_SRC WHERE NAME = 'PKG_DMF0049' AND TYPE = 'PACKAGE' ORDER BY LINE) LOOP v := v || r.TEXT; END LOOP;
        IF v IS NOT NULL THEN ddl('CREATE OR REPLACE ' || v, 'RESTORE PACKAGE PKG_DMF0049'); END IF;
        v := NULL;
        FOR r IN (SELECT TEXT FROM ZB_DMF0049_202611042341_SRC WHERE NAME = 'PKG_DMF0049' AND TYPE = 'PACKAGE BODY' ORDER BY LINE) LOOP v := v || r.TEXT; END LOOP;
        IF v IS NOT NULL THEN ddl('CREATE OR REPLACE ' || v, 'RESTORE PACKAGE BODY PKG_DMF0049'); END IF;
    END IF;
    DBMS_OUTPUT.PUT_LINE('ROLLBACK 완료' || CASE WHEN c_dry THEN ' (DRY)' END);
END;
