-- ============================================================
-- PKG_DMF0040 배포 검증 (읽기 전용)
-- SCM_MGR 로 접속해 실행. 모든 게이트가 PASS 여야 한다.
-- ============================================================
SET DEFINE OFF
SET SQLBLANKLINES ON
SET LINESIZE 200
SET PAGESIZE 100

PROMPT === G1. 객체 상태 (기대: PACKAGE / PACKAGE BODY 둘 다 VALID = 2행) ===
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS,
       TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') AS LAST_DDL
FROM   USER_OBJECTS
WHERE  OBJECT_NAME = 'PKG_DMF0040'
ORDER  BY OBJECT_TYPE;

PROMPT === G2. 컴파일 오류 (기대: 0행) ===
SELECT LINE, POSITION, TEXT
FROM   USER_ERRORS
WHERE  NAME = 'PKG_DMF0040'
ORDER  BY SEQUENCE;

PROMPT === G3. 표시축/판정축 분리 마커 (기대: 5행) ===
SELECT LINE, TEXT
FROM   USER_SOURCE
WHERE  NAME = 'PKG_DMF0040'
AND    TYPE = 'PACKAGE BODY'
AND    INSTR(TEXT, 'E20260909-VERLABEL') > 0
ORDER  BY LINE;

PROMPT === G4. 구 판정 잔존 여부 (기대: 0행 — A.MEASURE 기반 VERSION_SORT 가 남아있으면 FAIL) ===
SELECT LINE, TEXT
FROM   USER_SOURCE
WHERE  NAME = 'PKG_DMF0040'
AND    TYPE = 'PACKAGE BODY'
AND    INSTR(TEXT, 'A.MEASURE = ''Version(') > 0
AND    LTRIM(TEXT) NOT LIKE '--%'
ORDER  BY LINE;

PROMPT === G5. Owner 필터 P53 정정 (기대: 각 1행) ===
SELECT 'DIVISION_ID 조인키' AS ITEM, COUNT(*) AS CNT
FROM   USER_SOURCE
WHERE  NAME='PKG_DMF0040' AND TYPE='PACKAGE BODY'
AND    INSTR(TEXT,'A.DIVISION_ID  = B.DIVISION_ID') > 0
UNION ALL
SELECT 'P_OWNER IS NOT NULL (<> '''' 제거)', COUNT(*)
FROM   USER_SOURCE
WHERE  NAME='PKG_DMF0040' AND TYPE='PACKAGE BODY'
AND    REGEXP_LIKE(TEXT, 'IF +P_OWNER +IS +NOT +NULL +THEN');

PROMPT === G6. 의존 객체 INVALID 연쇄 (기대: 0행) ===
SELECT O.OBJECT_NAME, O.OBJECT_TYPE, O.STATUS
FROM   USER_OBJECTS O
JOIN   USER_DEPENDENCIES D
       ON D.NAME = O.OBJECT_NAME AND D.TYPE = O.OBJECT_TYPE
WHERE  D.REFERENCED_NAME = 'PKG_DMF0040'
AND    O.STATUS <> 'VALID';

PROMPT === G7. 앱계정 시노님/권한 (기대: 시노님 1행 + EXECUTE 권한 1행) ===
SELECT 'SYNONYM' AS AXIS, OWNER, SYNONYM_NAME
FROM   ALL_SYNONYMS
WHERE  TABLE_NAME = 'PKG_DMF0040' AND OWNER IN ('PUBLIC','SCMP_APP');

SELECT 'GRANT' AS AXIS, GRANTEE, PRIVILEGE
FROM   ALL_TAB_PRIVS
WHERE  TABLE_NAME = 'PKG_DMF0040' AND PRIVILEGE = 'EXECUTE';
