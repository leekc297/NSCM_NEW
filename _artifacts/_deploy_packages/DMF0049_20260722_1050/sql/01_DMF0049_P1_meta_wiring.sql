-- ── ① MNU_URL 'dmf0049' → 'etc-sales-reports' (충돌 0 실측) + ROUTE_PATH 재파생 ──
UPDATE SCM_MGR.SCM_ADM_MNU_M
   SET MNU_URL = 'etc-sales-reports', LAST_UPDATED_BY = 'admin', LAST_UPDATE_DATE = SYSDATE
 WHERE MNU_ID = 'DMF0049' AND MNU_URL = 'dmf0049';

UPDATE SCM_MGR.SCM_ADM_MNU_M t
   SET t.ROUTE_PATH = (
         SELECT LTRIM(SYS_CONNECT_BY_PATH(s.MNU_URL, '/'), '/')
         FROM   SCM_MGR.SCM_ADM_MNU_M s
         WHERE  s.MNU_ID = t.MNU_ID
         START WITH s.UPPR_MNU_ID IS NULL OR TRIM(s.UPPR_MNU_ID) IS NULL
         CONNECT BY PRIOR s.MNU_ID = s.UPPR_MNU_ID
       ),
       t.LAST_UPDATED_BY = 'admin', t.LAST_UPDATE_DATE = SYSDATE
 WHERE t.MNU_ID = 'DMF0049';

-- ── ② API_M 19종 ──
MERGE INTO SCM_MGR.SCM_ADM_API_M t
USING (
  SELECT 'DMF0049_main_SEARCH' API_ID, 'PROC_SELECT' API_TP_CD,
         'DMF0049_GET_SALES_ETC_REPORTS_DATA' API_URL, 'DMF0049 Etc Sales Reports 메인 조회 (8 IN — EDIT_AUTH_V 조인)' API_MSG_DESC FROM DUAL
  UNION ALL SELECT 'DMF0049_main_INSERT', 'PROC_SELECT', 'DMF0049_GET_SALES_ETC_REPORTS_DATA', 'DMF0049 행 추가 (division 세트 40=3/81=2/82=1)' FROM DUAL
  UNION ALL SELECT 'DMF0049_main_DELETE', 'PROC_SELECT', 'DMF0049_GET_SALES_ETC_REPORTS_DATA', 'DMF0049 행 삭제 (신규 세트 블록)' FROM DUAL
  UNION ALL SELECT 'DMF0049_main_SAVE',   'PROC_SAVE',   'DMF0049_SAVE_SALES_ETC_REPORT_C', 'DMF0049 저장 (36 IN — DB POSITION 정본, ^ bulk 35키)' FROM DUAL
  UNION ALL SELECT 'DMF0049_main_EXCEL',  'PROC_SELECT', 'DMF0049_GET_SALES_ETC_REPORTS_DATA', 'DMF0049 Excel Export' FROM DUAL
  UNION ALL SELECT 'DMF0049_main_FILTER', 'PROC_SELECT', 'DMF0049_GET_SALES_ETC_REPORTS_DATA', 'DMF0049 Filter' FROM DUAL
  UNION ALL SELECT 'DMF0049_main_SORT',   'PROC_SELECT', 'DMF0049_GET_SALES_ETC_REPORTS_DATA', 'DMF0049 Sort' FROM DUAL
  UNION ALL SELECT 'DMF0049_main_SP_VER', 'PROC_SELECT', 'PKG_DMF0044.P_DMF0044_GET_SALES_VERSION_POPUP', 'DMF0049 Version ... 버튼 (United 팝업 공유 — DMF0044 SP)' FROM DUAL
  UNION ALL SELECT 'DMF0049_main_COLUMN_SETUP',   'PROC_SELECT', 'DMF0002_GET_TITLESET_POPUP', 'DMF0049 Column Setting (공유)' FROM DUAL
  UNION ALL SELECT 'DMF0049_main_MEASURE_SELECT', 'PROC_SELECT', 'DMF0002_GET_TITLESET_POPUP', 'DMF0049 Measure Setting (공유 — TitleSet M 모드)' FROM DUAL
  UNION ALL SELECT 'DMF0049_spreadTitle_SEARCH', 'PROC_SELECT', 'PKG_DMF0049.P_DMF0049_GET_SPREAD_TITLE', 'DMF0049 동적 월 헤더 (PKG 판 — 커서 2)' FROM DUAL
  UNION ALL SELECT 'DMF0049_measure_SEARCH',     'PROC_SELECT', 'PKG_DMF0049.P_DMF0049_GET_MEASURE', 'DMF0049 Measure 세트 정의 (PKG 판)' FROM DUAL
  UNION ALL SELECT 'DMF0049_unitedVersion_SEARCH',    'PROC_SELECT', 'PKG_DMF0044.P_DMF0044_GET_SALES_VERSION_POPUP', 'DMF0049 United 버전 목록 (DMF0044 SP 공유)' FROM DUAL
  UNION ALL SELECT 'DMF0049_unitedVersion_TITLE',     'PROC_SELECT', 'PKG_DMF0000.P_DMF0000_GET_COMMON_SPREAD_TITLE', 'DMF0049 United 팝업 헤더 (공유)' FROM DUAL
  UNION ALL SELECT 'DMF0049_unitedVersion_ACTION',    'PROC_SAVE',   'DMF0044_SAVE_SALES_PLAN_VERSION_COPY', 'DMF0049 United 액션 D/CP/CR (SP_W 계열 — DMF0044 SP 공유)' FROM DUAL
  UNION ALL SELECT 'DMF0049_unitedVersion_ACTION_BP', 'PROC_SAVE',   'PKG_DMF0044.P_DMF0044_SAVE_BIZ_PLAN_VERSION_COPY', 'DMF0049 United 액션 (BP 계열 분기 — 공유)' FROM DUAL
  UNION ALL SELECT 'DMF0049_unitedVersion_TRANSFER',  'PROC_SAVE',   'DMF0044_MOBILE_REPORT_CREATE', 'DMF0049 United Transfer/Cancel (공유)' FROM DUAL
  UNION ALL SELECT 'DMF0049_titleSet_SEARCH', 'PROC_SELECT', 'DMF0002_GET_TITLESET_POPUP', 'DMF0049 TitleSet 조회 (공유)' FROM DUAL
  UNION ALL SELECT 'DMF0049_titleSet_SAVE',   'PROC_SAVE',   'SCM0002_SET_TITLESET_POPUP', 'DMF0049 TitleSet 저장 (공유)' FROM DUAL
) s
ON (t.API_ID = s.API_ID)
WHEN MATCHED THEN UPDATE SET t.API_TP_CD = s.API_TP_CD, t.API_URL = s.API_URL,
  t.API_MSG_DESC = s.API_MSG_DESC, t.USE_YN = 'Y',
  t.LAST_UPDATED_BY = 'admin', t.LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (API_ID, API_TP_CD, API_MSG_ID, API_MSG_DESC, API_URL, USE_YN,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES (s.API_ID, s.API_TP_CD, 'MSG_API_' || s.API_ID, s.API_MSG_DESC, s.API_URL, 'Y',
  'admin', SYSDATE, 'admin', SYSDATE);

-- ── ③ MNU_BTN_MPG 19행 (시트 5종 — 'MDF Reports' 등록명 그대로) ──
MERGE INTO SCM_MGR.SCM_ADM_MNU_BTN_MPG_M t
USING (
  SELECT 'DMF0049' MNU_ID, 'MDF Reports' SHT_NM, 'SEARCH' MNU_BTN_CD, 'DMF0049_main_SEARCH' API_ID FROM DUAL
  UNION ALL SELECT 'DMF0049', 'MDF Reports', 'INSERT',         'DMF0049_main_INSERT' FROM DUAL
  UNION ALL SELECT 'DMF0049', 'MDF Reports', 'DELETE',         'DMF0049_main_DELETE' FROM DUAL
  UNION ALL SELECT 'DMF0049', 'MDF Reports', 'SAVE',           'DMF0049_main_SAVE' FROM DUAL
  UNION ALL SELECT 'DMF0049', 'MDF Reports', 'EXCEL',          'DMF0049_main_EXCEL' FROM DUAL
  UNION ALL SELECT 'DMF0049', 'MDF Reports', 'FILTER',         'DMF0049_main_FILTER' FROM DUAL
  UNION ALL SELECT 'DMF0049', 'MDF Reports', 'SORT',           'DMF0049_main_SORT' FROM DUAL
  UNION ALL SELECT 'DMF0049', 'MDF Reports', 'SP_VER',         'DMF0049_main_SP_VER' FROM DUAL
  UNION ALL SELECT 'DMF0049', 'MDF Reports', 'COLUMN_SETUP',   'DMF0049_main_COLUMN_SETUP' FROM DUAL
  UNION ALL SELECT 'DMF0049', 'MDF Reports', 'MEASURE_SELECT', 'DMF0049_main_MEASURE_SELECT' FROM DUAL
  UNION ALL SELECT 'DMF0049', 'spreadTitle',   'SEARCH',    'DMF0049_spreadTitle_SEARCH' FROM DUAL
  UNION ALL SELECT 'DMF0049', 'measure',       'SEARCH',    'DMF0049_measure_SEARCH' FROM DUAL
  UNION ALL SELECT 'DMF0049', 'unitedVersion', 'SEARCH',    'DMF0049_unitedVersion_SEARCH' FROM DUAL
  UNION ALL SELECT 'DMF0049', 'unitedVersion', 'TITLE',     'DMF0049_unitedVersion_TITLE' FROM DUAL
  UNION ALL SELECT 'DMF0049', 'unitedVersion', 'ACTION',    'DMF0049_unitedVersion_ACTION' FROM DUAL
  UNION ALL SELECT 'DMF0049', 'unitedVersion', 'ACTION_BP', 'DMF0049_unitedVersion_ACTION_BP' FROM DUAL
  UNION ALL SELECT 'DMF0049', 'unitedVersion', 'TRANSFER',  'DMF0049_unitedVersion_TRANSFER' FROM DUAL
  UNION ALL SELECT 'DMF0049', 'titleSet', 'SEARCH', 'DMF0049_titleSet_SEARCH' FROM DUAL
  UNION ALL SELECT 'DMF0049', 'titleSet', 'SAVE',   'DMF0049_titleSet_SAVE' FROM DUAL
) s
ON (t.MNU_ID = s.MNU_ID AND t.SHT_NM = s.SHT_NM AND t.MNU_BTN_CD = s.MNU_BTN_CD)
WHEN MATCHED THEN UPDATE SET t.API_ID = s.API_ID, t.USE_YN = 'Y',
  t.LAST_UPDATED_BY = 'admin', t.LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (MNU_ID, SHT_NM, MNU_BTN_CD, API_ID, USE_YN,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES (s.MNU_ID, s.SHT_NM, s.MNU_BTN_CD, s.API_ID, 'Y',
  'admin', SYSDATE, 'admin', SYSDATE);

-- ── ④ USER_GR_BTN — ADMIN/DM ADMIN=전 19 / DM Viewer=조회계 13 (INSERT/DELETE/SAVE/ACTION/ACTION_BP/TRANSFER 제외) ──
MERGE INTO SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M t
USING (
  SELECT g.USER_GR_ID, b.MNU_ID, b.SHT_NM, b.MNU_BTN_CD
  FROM (SELECT 'ADMIN' USER_GR_ID FROM DUAL
        UNION ALL SELECT 'DM ADMIN' FROM DUAL
        UNION ALL SELECT 'DM Viewer' FROM DUAL) g
  CROSS JOIN (SELECT MNU_ID, SHT_NM, MNU_BTN_CD FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID = 'DMF0049') b
  WHERE NOT (g.USER_GR_ID = 'DM Viewer' AND (
          (b.SHT_NM = 'MDF Reports'  AND b.MNU_BTN_CD IN ('INSERT','DELETE','SAVE'))
       OR (b.SHT_NM = 'unitedVersion' AND b.MNU_BTN_CD IN ('ACTION','ACTION_BP','TRANSFER'))
  ))
) s
ON (t.USER_GR_ID = s.USER_GR_ID AND t.MNU_ID = s.MNU_ID AND t.SHT_NM = s.SHT_NM AND t.MNU_BTN_CD = s.MNU_BTN_CD)
WHEN MATCHED THEN UPDATE SET t.USE_YN = 'Y', t.LAST_UPDATED_BY = 'admin', t.LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (USER_GR_ID, MNU_ID, SHT_NM, MNU_BTN_CD, USE_YN,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES (s.USER_GR_ID, s.MNU_ID, s.SHT_NM, s.MNU_BTN_CD, 'Y', 'admin', SYSDATE, 'admin', SYSDATE);

-- ── ⑤ CMBO 신규 1건 — DMF0049_DEPARTMENT_TEAM (C1 cascade: SEGMENT3=DEPARTMENT_ID 포함) ──
MERGE INTO SCM_MGR.SCM_ADM_CMBO_SQL_M t
USING (
  SELECT 'DMF0049_DEPARTMENT_TEAM' SQL_ID, 'DM' MDU_DIVS_CD,
         'DMF0049 Team 콤보 (부서 cascade — SEGMENT3=DEPARTMENT_ID)' SQL_NM,
'SELECT SEGMENT1 AS CODE
      , SEGMENT2 AS NAME
      , SEGMENT3 AS DEPARTMENT_ID
FROM   SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
WHERE  LOOKUP_TYPE IN (''DMF0044_DEPARTMENT_TEAM2'', ''DMF0044_DEPARTMENT_TEAM2_81'', ''DMF0044_DEPARTMENT_TEAM2_82'')
AND    VALID_YN = ''Y''
ORDER BY DISPLAY_SEQ' SQL_DTL_CTN
  FROM DUAL
) s
ON (t.SQL_ID = s.SQL_ID)
WHEN MATCHED THEN UPDATE SET t.MDU_DIVS_CD = s.MDU_DIVS_CD, t.SQL_NM = s.SQL_NM,
  t.SQL_DTL_CTN = s.SQL_DTL_CTN, t.USE_YN = 'Y',
  t.LAST_UPDATED_BY = 'admin', t.LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (SQL_ID, MDU_DIVS_CD, SQL_NM, SQL_DTL_CTN, USE_YN,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES (s.SQL_ID, s.MDU_DIVS_CD, s.SQL_NM, s.SQL_DTL_CTN, 'Y', 'admin', SYSDATE, 'admin', SYSDATE);

COMMIT;

