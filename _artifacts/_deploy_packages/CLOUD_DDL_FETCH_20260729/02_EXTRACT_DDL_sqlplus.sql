-- =============================================================================
-- 02_EXTRACT_DDL_sqlplus.sql — 클라우드 Oracle 에서 sqlplus/SQLcl 로 실행
-- 산출: C1~C5_*.sql 5파일 (spool, 실행 디렉터리에 생성)
-- 원칙: DBMS_METADATA 원문 추출 — 산출물 1바이트 수정 금지
-- 사전: 01_PRECHECK_CLOUD.sql 의 [1]에서 OWNER 확인 — SCM_MGR 아니면 아래 DEFINE 수정
-- =============================================================================
DEFINE OWNER = 'SCM_MGR'

SET LONG 2000000 LONGCHUNKSIZE 32767 PAGESIZE 0 LINESIZE 32767
SET TRIMSPOOL ON TRIMOUT ON HEADING OFF FEEDBACK OFF VERIFY OFF ECHO OFF TERMOUT ON

-- 이관용 transform: 세그먼트/스토리지/테이블스페이스 제거 + 문장 종결자 포함
BEGIN
    DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM, 'SQLTERMINATOR', TRUE);
    DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM, 'PRETTY', TRUE);
    DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM, 'SEGMENT_ATTRIBUTES', FALSE);
    DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM, 'STORAGE', FALSE);
    DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM, 'TABLESPACE', FALSE);
END;
/

-- ── C1 ──────────────────────────────────────────────────────────────────────
SPOOL C1_P_SCM0008_ADD_MY_AUTH.sql
SELECT DBMS_METADATA.GET_DDL('PROCEDURE', 'P_SCM0008_ADD_MY_AUTH', '&OWNER') FROM DUAL;
SPOOL OFF

-- ── C2 ──────────────────────────────────────────────────────────────────────
SPOOL C2_P_SCM0008_REQUEST_AUTH.sql
SELECT DBMS_METADATA.GET_DDL('PROCEDURE', 'P_SCM0008_REQUEST_AUTH', '&OWNER') FROM DUAL;
SPOOL OFF

-- ── C3 ──────────────────────────────────────────────────────────────────────
SPOOL C3_P_SCM0008_DELETE_MY_AUTH.sql
SELECT DBMS_METADATA.GET_DDL('PROCEDURE', 'P_SCM0008_DELETE_MY_AUTH', '&OWNER') FROM DUAL;
SPOOL OFF

-- ── C4: PACKAGE = SPEC + BODY (사내 스펙 INVALID → 양쪽 모두 원문 확보) ──────
SPOOL C4_PKG_SYS0014.sql
SELECT DBMS_METADATA.GET_DDL('PACKAGE_SPEC', 'PKG_SYS0014', '&OWNER') FROM DUAL;
SELECT DBMS_METADATA.GET_DDL('PACKAGE_BODY', 'PKG_SYS0014', '&OWNER') FROM DUAL;
SPOOL OFF

-- ── C5: TABLE + 종속 (INDEX/COMMENT/REF제약/TRIGGER/GRANT) ──────────────────
-- ※ 종속 DDL 은 해당 종류가 없으면 ORA-31608 이 출력됨 = "없음" 의미로 정상.
--    spool 파일에 ORA-31608 줄이 섞이면 그 블록만 제거하지 말고 "없음" 으로 기록.
SPOOL C5_SCM_SYS_FILE.sql
SELECT DBMS_METADATA.GET_DDL('TABLE', 'SCM_SYS_FILE', '&OWNER') FROM DUAL;
SELECT DBMS_METADATA.GET_DEPENDENT_DDL('INDEX', 'SCM_SYS_FILE', '&OWNER') FROM DUAL;
SELECT DBMS_METADATA.GET_DEPENDENT_DDL('COMMENT', 'SCM_SYS_FILE', '&OWNER') FROM DUAL;
SELECT DBMS_METADATA.GET_DEPENDENT_DDL('REF_CONSTRAINT', 'SCM_SYS_FILE', '&OWNER') FROM DUAL;
SELECT DBMS_METADATA.GET_DEPENDENT_DDL('TRIGGER', 'SCM_SYS_FILE', '&OWNER') FROM DUAL;
SELECT DBMS_METADATA.GET_DEPENDENT_DDL('OBJECT_GRANT', 'SCM_SYS_FILE', '&OWNER') FROM DUAL;
SPOOL OFF

