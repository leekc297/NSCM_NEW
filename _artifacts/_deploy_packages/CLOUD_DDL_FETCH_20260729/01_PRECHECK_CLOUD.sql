SET PAGESIZE 200 LINESIZE 200 TRIMSPOOL ON
COLUMN OWNER FORMAT A15
COLUMN OBJECT_NAME FORMAT A40
COLUMN OBJECT_TYPE FORMAT A14
COLUMN STATUS FORMAT A8

PROMPT === [1] 대상 5객체 존재/상태 (5객체 모두 나와야 함 — C4 는 PACKAGE+PACKAGE BODY 2행 기대) ===
SELECT OWNER, OBJECT_NAME, OBJECT_TYPE, STATUS
  FROM ALL_OBJECTS
 WHERE OBJECT_NAME IN ('P_SCM0008_ADD_MY_AUTH',
                       'P_SCM0008_REQUEST_AUTH',
                       'P_SCM0008_DELETE_MY_AUTH',
                       'PKG_SYS0014',
                       'SCM_SYS_FILE')
 ORDER BY OBJECT_NAME, OBJECT_TYPE;

PROMPT === [2] 미존재 객체 검출 (0행이어야 정상 — 행이 나오면 중단 후 보고) ===
SELECT COLUMN_VALUE AS MISSING_ON_CLOUD
  FROM TABLE(SYS.ODCIVARCHAR2LIST('P_SCM0008_ADD_MY_AUTH',
                                  'P_SCM0008_REQUEST_AUTH',
                                  'P_SCM0008_DELETE_MY_AUTH',
                                  'PKG_SYS0014',
                                  'SCM_SYS_FILE'))
 WHERE COLUMN_VALUE NOT IN (SELECT OBJECT_NAME FROM ALL_OBJECTS
                             WHERE OBJECT_NAME IN ('P_SCM0008_ADD_MY_AUTH',
                                                   'P_SCM0008_REQUEST_AUTH',
                                                   'P_SCM0008_DELETE_MY_AUTH',
                                                   'PKG_SYS0014',
                                                   'SCM_SYS_FILE'));

PROMPT === [3] PKG_SYS0014 BODY 존재 + 멤버 목록 (P_SYS0014_GET_DIVISION_DATA 포함 기대) ===
SELECT OWNER, OBJECT_NAME, PROCEDURE_NAME
  FROM ALL_PROCEDURES
 WHERE OBJECT_NAME = 'PKG_SYS0014'
 ORDER BY SUBPROGRAM_ID;

PROMPT === [4] 3 SP 시그니처 (사내 PROC_M 대조용 — README 검증표 기준) ===
COLUMN ARGUMENT_NAME FORMAT A20
COLUMN DATA_TYPE FORMAT A16
SELECT OBJECT_NAME, POSITION, ARGUMENT_NAME, DATA_TYPE, IN_OUT
  FROM ALL_ARGUMENTS
 WHERE OBJECT_NAME IN ('P_SCM0008_ADD_MY_AUTH', 'P_SCM0008_REQUEST_AUTH', 'P_SCM0008_DELETE_MY_AUTH')
   AND PACKAGE_NAME IS NULL
 ORDER BY OBJECT_NAME, POSITION;

PROMPT === [5] SCM_SYS_FILE 종속객체 사전 파악 (추출 범위 확정) ===
SELECT 'INDEX' KIND, OWNER, INDEX_NAME NAME FROM ALL_INDEXES WHERE TABLE_NAME = 'SCM_SYS_FILE'
UNION ALL
SELECT 'TRIGGER', OWNER, TRIGGER_NAME FROM ALL_TRIGGERS WHERE TABLE_NAME = 'SCM_SYS_FILE'
UNION ALL
SELECT 'CONSTRAINT', OWNER, CONSTRAINT_NAME FROM ALL_CONSTRAINTS WHERE TABLE_NAME = 'SCM_SYS_FILE'
UNION ALL
SELECT 'SYNONYM', OWNER, SYNONYM_NAME FROM ALL_SYNONYMS WHERE TABLE_NAME = 'SCM_SYS_FILE'
UNION ALL
SELECT 'SEQUENCE(추정)', SEQUENCE_OWNER, SEQUENCE_NAME FROM ALL_SEQUENCES
 WHERE SEQUENCE_NAME LIKE '%SYS_FILE%';

PROMPT === [6] SCM_SYS_FILE 컬럼 (BE File.xml 12컬럼 포함 여부 육안 대조) ===
SELECT COLUMN_ID, COLUMN_NAME, DATA_TYPE, DATA_LENGTH, NULLABLE, DATA_DEFAULT
  FROM ALL_TAB_COLUMNS
 WHERE TABLE_NAME = 'SCM_SYS_FILE'
 ORDER BY COLUMN_ID;

PROMPT === [7] 5객체 대상 GRANT 현황 (사내 SCMD_APP GRANT 재현 참고) ===
SELECT TABLE_NAME OBJ, GRANTEE, PRIVILEGE
  FROM ALL_TAB_PRIVS
 WHERE TABLE_NAME IN ('P_SCM0008_ADD_MY_AUTH', 'P_SCM0008_REQUEST_AUTH',
                      'P_SCM0008_DELETE_MY_AUTH', 'PKG_SYS0014', 'SCM_SYS_FILE')
 ORDER BY 1, 2, 3;
