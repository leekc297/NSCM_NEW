ALTER SESSION SET DDL_LOCK_TIMEOUT=120;
CREATE OR REPLACE PROCEDURE         P_SYS0014_GET_AUTH_LIST_M (
    P_USER_GR_ID     IN  VARCHAR2,
    P_USER_ID        IN  VARCHAR2,
    P_UNIT_TP_CD     IN  VARCHAR2,
    O_RC1            OUT SYS_REFCURSOR,
    O_RESULT_CURSOR  OUT SYS_REFCURSOR
)
AS
BEGIN
    OPEN O_RC1 FOR
    SELECT UNIT_ID, UPPR_UNIT_ID, EDIT_YN, USE_YN
      FROM SCM_MGR.SCM_ADM_USER_GR_UNIT_AUTH_MPG_M
     WHERE USER_GR_ID = P_USER_GR_ID
       AND USER_ID    = P_USER_ID
       AND UNIT_TP_CD = P_UNIT_TP_CD
     ORDER BY UNIT_ID;

    OPEN O_RESULT_CURSOR FOR
    SELECT '0' AS CODE, 'SUCCESS' AS MSG FROM DUAL;
EXCEPTION
    WHEN OTHERS THEN
        DECLARE V_ERR VARCHAR2(4000) := SUBSTR(SQLERRM, 1, 4000);
        BEGIN
            OPEN O_RC1 FOR SELECT NULL AS DUMMY FROM DUAL WHERE 1=0;
            OPEN O_RESULT_CURSOR FOR SELECT '-1' AS CODE, V_ERR AS MSG FROM DUAL;
        END;
END P_SYS0014_GET_AUTH_LIST_M;
/
SHOW ERRORS;
