-- SYS0016 NOTICE_CONTENT CLOB 전환 사전 확인 (조회만, 데이터 변경 없음)
-- 기대값 : 두 테이블 NOTICE_CONTENT = VARCHAR2 (이미 CLOB 이면 10 실행 시 SKIP),
--          PR_SCM_ADM_NOTICE_CONTENT_MASTER_HIST 앵커 2건 있음, PKG_SYS0016 VALID
-- 작성 : 2026-11-24
-- SOURCE-FRESH: SCM_MGR.PR_SCM_ADM_NOTICE_CONTENT_MASTER_HIST PROCEDURE LAST_DDL=2026-11-23 17:36:12 FETCHED=2026-11-24 14:49 DB=ZIOUI1
SET SERVEROUTPUT ON SIZE UNLIMITED
SET DEFINE OFF

PROMPT [PRECHECK] SYS0016 NOTICE_CONTENT
DECLARE
    V      VARCHAR2(4000);
    N      NUMBER;
    V_SRC  CLOB;
BEGIN
    FOR T IN (SELECT 'SCM_ADM_NOTICE_CONTENT_MASTER' TAB FROM DUAL
              UNION ALL SELECT 'SCM_ADM_NOTICE_CONTENT_MASTER_H' FROM DUAL) LOOP
        SELECT MAX(DATA_TYPE || '(' || CHAR_LENGTH || ')') INTO V FROM ALL_TAB_COLUMNS
         WHERE OWNER = 'SCM_MGR' AND TABLE_NAME = T.TAB AND COLUMN_NAME = 'NOTICE_CONTENT';
        DBMS_OUTPUT.PUT_LINE(T.TAB || '.NOTICE_CONTENT = ' || NVL(V, 'NOT FOUND'));
        EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM SCM_MGR.' || T.TAB INTO N;
        DBMS_OUTPUT.PUT_LINE(T.TAB || ' rows = ' || N);
    END LOOP;

    FOR R IN (SELECT TEXT FROM ALL_SOURCE
               WHERE OWNER = 'SCM_MGR' AND NAME = 'PR_SCM_ADM_NOTICE_CONTENT_MASTER_HIST' AND TYPE = 'PROCEDURE'
               ORDER BY LINE) LOOP
        V_SRC := V_SRC || R.TEXT;
    END LOOP;
    DBMS_OUTPUT.PUT_LINE('HIST anchor param VARCHAR2 = ' || SIGN(INSTR(V_SRC, 'P_CONTENT         VARCHAR2'))
        || ', param CLOB = ' || SIGN(INSTR(V_SRC, 'P_CONTENT         CLOB')));
    DBMS_OUTPUT.PUT_LINE('HIST anchor log body = ' || SIGN(INSTR(V_SRC, '''P_CONTENT'' VALUE P_CONTENT'))
        || ', log length = ' || SIGN(INSTR(V_SRC, '''P_CONTENT_LEN'' VALUE DBMS_LOB.GETLENGTH(P_CONTENT)')));

    FOR O IN (SELECT OBJECT_NAME, OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME, 'YYYY-MM-DD HH24:MI:SS') LDT
                FROM ALL_OBJECTS
               WHERE OWNER = 'SCM_MGR'
                 AND OBJECT_NAME IN ('PKG_SYS0016', 'PR_SCM_ADM_NOTICE_CONTENT_MASTER_HIST')
               ORDER BY 1, 2) LOOP
        DBMS_OUTPUT.PUT_LINE(O.OBJECT_NAME || ' ' || O.OBJECT_TYPE || ' ' || O.STATUS || ' ' || O.LDT);
    END LOOP;
END;
