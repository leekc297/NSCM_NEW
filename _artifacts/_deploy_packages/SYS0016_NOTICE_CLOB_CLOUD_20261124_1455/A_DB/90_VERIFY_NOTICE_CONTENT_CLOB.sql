-- SYS0016 NOTICE_CONTENT CLOB 적용 확인 (조회만, 데이터 변경 없음)
-- 확인 1 : 두 테이블 NOTICE_CONTENT = CLOB, 임시 컬럼 NOTICE_CONTENT_CLOB 없음, 컬럼 주석 '공지내용'
-- 확인 2 : PR_SCM_ADM_NOTICE_CONTENT_MASTER_HIST.P_CONTENT = CLOB
-- 확인 3 : PKG_SYS0016, PR_SCM_ADM_NOTICE_CONTENT_MASTER_HIST VALID, ALL_ERRORS 0
-- 확인 4 : 백업 테이블(_BAK20261124)과 행 수, 본문 값 일치
SET SERVEROUTPUT ON SIZE UNLIMITED
SET DEFINE OFF

PROMPT [VERIFY] NOTICE_CONTENT CLOB
DECLARE
    N_FAIL NUMBER := 0;
    N      NUMBER;
    V      VARCHAR2(4000);
    PROCEDURE CHK(P_OK BOOLEAN, P_MSG VARCHAR2) IS
    BEGIN
        IF P_OK THEN
            DBMS_OUTPUT.PUT_LINE('PASS ' || P_MSG);
        ELSE
            DBMS_OUTPUT.PUT_LINE('FAIL ' || P_MSG);
            N_FAIL := N_FAIL + 1;
        END IF;
    END;
BEGIN
    FOR T IN (SELECT 'SCM_ADM_NOTICE_CONTENT_MASTER' TAB, 'SCM_ADM_NOTICE_CONTENT_MASTER_BAK20261124' BAK FROM DUAL
              UNION ALL
              SELECT 'SCM_ADM_NOTICE_CONTENT_MASTER_H', 'SCM_ADM_NOTICE_CONTENT_MASTER_H_BAK20261124' FROM DUAL) LOOP
        SELECT MAX(DATA_TYPE) INTO V FROM ALL_TAB_COLUMNS
         WHERE OWNER = 'SCM_MGR' AND TABLE_NAME = T.TAB AND COLUMN_NAME = 'NOTICE_CONTENT';
        CHK(V = 'CLOB', T.TAB || '.NOTICE_CONTENT type=' || V);

        SELECT COUNT(*) INTO N FROM ALL_TAB_COLUMNS
         WHERE OWNER = 'SCM_MGR' AND TABLE_NAME = T.TAB AND COLUMN_NAME = 'NOTICE_CONTENT_CLOB';
        CHK(N = 0, T.TAB || ' temp column count=' || N);

        SELECT MAX(COMMENTS) INTO V FROM ALL_COL_COMMENTS
         WHERE OWNER = 'SCM_MGR' AND TABLE_NAME = T.TAB AND COLUMN_NAME = 'NOTICE_CONTENT';
        CHK(V = '공지내용', T.TAB || '.NOTICE_CONTENT comment=' || V);

        SELECT COUNT(*) INTO N FROM ALL_TABLES WHERE OWNER = 'SCM_MGR' AND TABLE_NAME = T.BAK;
        IF N = 1 THEN
            EXECUTE IMMEDIATE
                'SELECT (SELECT COUNT(*) FROM SCM_MGR.' || T.TAB || ') - (SELECT COUNT(*) FROM SCM_MGR.' || T.BAK || ') FROM DUAL'
                INTO N;
            CHK(N = 0, T.TAB || ' row count diff vs backup=' || N);
            IF T.TAB = 'SCM_ADM_NOTICE_CONTENT_MASTER' THEN
                EXECUTE IMMEDIATE
                    'SELECT COUNT(*) FROM SCM_MGR.' || T.BAK || ' B LEFT JOIN SCM_MGR.' || T.TAB || ' A'
                    || ' ON A.NOTICE_ID = B.NOTICE_ID AND A.LANGUAGE_CODE = B.LANGUAGE_CODE'
                    || ' WHERE NVL(DBMS_LOB.COMPARE(A.NOTICE_CONTENT, TO_CLOB(B.NOTICE_CONTENT)), -1) <> 0'
                    || '   AND NOT (A.NOTICE_CONTENT IS NULL AND B.NOTICE_CONTENT IS NULL)'
                    INTO N;
            ELSE
                EXECUTE IMMEDIATE
                    'SELECT COUNT(*) FROM SCM_MGR.' || T.BAK || ' B LEFT JOIN SCM_MGR.' || T.TAB || ' A'
                    || ' ON A.HISTORY_SEQ = B.HISTORY_SEQ'
                    || ' WHERE NVL(DBMS_LOB.COMPARE(A.NOTICE_CONTENT, TO_CLOB(B.NOTICE_CONTENT)), -1) <> 0'
                    || '   AND NOT (A.NOTICE_CONTENT IS NULL AND B.NOTICE_CONTENT IS NULL)'
                    INTO N;
            END IF;
            CHK(N = 0, T.TAB || ' content mismatch vs backup=' || N);
        ELSE
            DBMS_OUTPUT.PUT_LINE('INFO ' || T.BAK || ' not found, backup compare skipped');
        END IF;
    END LOOP;

    SELECT MAX(DATA_TYPE) INTO V FROM ALL_ARGUMENTS
     WHERE OWNER = 'SCM_MGR' AND OBJECT_NAME = 'PR_SCM_ADM_NOTICE_CONTENT_MASTER_HIST'
       AND PACKAGE_NAME IS NULL AND ARGUMENT_NAME = 'P_CONTENT';
    CHK(V = 'CLOB', 'PR_SCM_ADM_NOTICE_CONTENT_MASTER_HIST.P_CONTENT type=' || V);

    SELECT COUNT(*) INTO N FROM ALL_OBJECTS
     WHERE OWNER = 'SCM_MGR' AND OBJECT_NAME IN ('PKG_SYS0016', 'PR_SCM_ADM_NOTICE_CONTENT_MASTER_HIST')
       AND STATUS <> 'VALID';
    CHK(N = 0, 'INVALID object count=' || N);

    SELECT COUNT(*) INTO N FROM ALL_ERRORS
     WHERE OWNER = 'SCM_MGR' AND NAME IN ('PKG_SYS0016', 'PR_SCM_ADM_NOTICE_CONTENT_MASTER_HIST');
    CHK(N = 0, 'ALL_ERRORS count=' || N);

    IF N_FAIL > 0 THEN
        RAISE_APPLICATION_ERROR(-20090, 'VERIFY FAIL ' || N_FAIL);
    END IF;
    DBMS_OUTPUT.PUT_LINE('VERIFY OK');
END;
