DECLARE
    PROCEDURE TO_VC(P_TAB VARCHAR2) IS
        V_TYPE  VARCHAR2(30);
        N_TMP   NUMBER;
        N_MAX   NUMBER;
        N_DIFF  NUMBER;
    BEGIN
        SELECT MAX(DATA_TYPE) INTO V_TYPE FROM ALL_TAB_COLUMNS
         WHERE OWNER = 'SCM_MGR' AND TABLE_NAME = P_TAB AND COLUMN_NAME = 'NOTICE_CONTENT';
        SELECT COUNT(*) INTO N_TMP FROM ALL_TAB_COLUMNS
         WHERE OWNER = 'SCM_MGR' AND TABLE_NAME = P_TAB AND COLUMN_NAME = 'NOTICE_CONTENT_VC';

        IF V_TYPE = 'VARCHAR2' AND N_TMP = 0 THEN
            DBMS_OUTPUT.PUT_LINE('SKIP ' || P_TAB || ' (already VARCHAR2)');
            RETURN;
        END IF;

        IF V_TYPE = 'CLOB' THEN
            EXECUTE IMMEDIATE 'SELECT NVL(MAX(LENGTHB(DBMS_LOB.SUBSTR(NOTICE_CONTENT, 4001, 1))), 0)'
                || ' + NVL(MAX(CASE WHEN DBMS_LOB.GETLENGTH(NOTICE_CONTENT) > 4000 THEN 1 END), 0) * 100000'
                || ' FROM SCM_MGR.' || P_TAB INTO N_MAX;
            IF N_MAX > 4000 THEN
                RAISE_APPLICATION_ERROR(-20091, P_TAB || ' content over 4000 byte, rollback stopped');
            END IF;
            IF N_TMP = 0 THEN
                EXECUTE IMMEDIATE 'ALTER TABLE SCM_MGR.' || P_TAB || ' ADD (NOTICE_CONTENT_VC VARCHAR2(4000 CHAR))';
            END IF;
            EXECUTE IMMEDIATE 'UPDATE SCM_MGR.' || P_TAB || ' SET NOTICE_CONTENT_VC = DBMS_LOB.SUBSTR(NOTICE_CONTENT, 4000, 1)';
            EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM SCM_MGR.' || P_TAB
                || ' WHERE (NOTICE_CONTENT IS NULL AND NOTICE_CONTENT_VC IS NOT NULL)'
                || '    OR (NOTICE_CONTENT IS NOT NULL AND NOTICE_CONTENT_VC IS NULL)'
                || '    OR (NOTICE_CONTENT IS NOT NULL AND DBMS_LOB.COMPARE(NOTICE_CONTENT, TO_CLOB(NOTICE_CONTENT_VC)) <> 0)'
                INTO N_DIFF;
            IF N_DIFF > 0 THEN
                ROLLBACK;
                RAISE_APPLICATION_ERROR(-20092, P_TAB || ' copy mismatch ' || N_DIFF);
            END IF;
            COMMIT;
            EXECUTE IMMEDIATE 'ALTER TABLE SCM_MGR.' || P_TAB || ' DROP COLUMN NOTICE_CONTENT';
        ELSIF V_TYPE IS NOT NULL THEN
            RAISE_APPLICATION_ERROR(-20093, P_TAB || '.NOTICE_CONTENT unexpected type ' || V_TYPE);
        END IF;

        EXECUTE IMMEDIATE 'ALTER TABLE SCM_MGR.' || P_TAB || ' RENAME COLUMN NOTICE_CONTENT_VC TO NOTICE_CONTENT';
        EXECUTE IMMEDIATE 'COMMENT ON COLUMN SCM_MGR.' || P_TAB || '.NOTICE_CONTENT IS ''공지내용''';
        DBMS_OUTPUT.PUT_LINE('DONE ' || P_TAB || ' -> VARCHAR2(4000 CHAR)');
    END;
BEGIN
    TO_VC('SCM_ADM_NOTICE_CONTENT_MASTER');
    TO_VC('SCM_ADM_NOTICE_CONTENT_MASTER_H');
END;
