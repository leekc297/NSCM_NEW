-- 90_VERIFY — [GAP291 2026-10-15] DMF0043 기여율 버전관리 팝업 버튼 권한 검증 (전체 F5, 조회 전용, 값 입력 없음)
-- 기대: V1 3 PASS · V2 6 PASS · V3 0 PASS (ADMIN · DM ADMIN 외 SAVE 활성 0) · V4 그룹별 상세
SET DEFINE OFF

-- V1 메뉴 버튼 마스터 EDIT/INSERT/DELETE = 3
SELECT 'V1 MNU_BTN' AS CHK, COUNT(*) AS CNT, CASE WHEN COUNT(*) = 3 THEN 'PASS' ELSE 'FAIL' END AS RES
  FROM SCM_ADM_MNU_BTN_MPG_M
 WHERE MNU_ID = 'DMF0043' AND SHT_NM = 'version' AND MNU_BTN_CD IN ('EDIT', 'INSERT', 'DELETE') AND USE_YN = 'Y';

-- V2 ADMIN · DM ADMIN × EDIT/INSERT/DELETE = 6, 그 외 그룹 0
SELECT 'V2 GR_BTN' AS CHK,
       SUM(CASE WHEN USER_GR_ID IN ('ADMIN', 'DM ADMIN') THEN 1 ELSE 0 END) AS ADMIN_CNT,
       SUM(CASE WHEN USER_GR_ID NOT IN ('ADMIN', 'DM ADMIN') THEN 1 ELSE 0 END) AS OTHER_CNT,
       CASE WHEN SUM(CASE WHEN USER_GR_ID IN ('ADMIN', 'DM ADMIN') THEN 1 ELSE 0 END) = 6
             AND SUM(CASE WHEN USER_GR_ID NOT IN ('ADMIN', 'DM ADMIN') THEN 1 ELSE 0 END) = 0
            THEN 'PASS' ELSE 'FAIL' END AS RES
  FROM SCM_ADM_USER_GR_MNU_BTN_MPG_M
 WHERE MNU_ID = 'DMF0043' AND SHT_NM = 'version' AND MNU_BTN_CD IN ('EDIT', 'INSERT', 'DELETE') AND USE_YN = 'Y';

-- V3 version|SAVE 활성 = ADMIN · DM ADMIN 외 0
SELECT 'V3 SAVE_OTHER' AS CHK, COUNT(*) AS CNT, CASE WHEN COUNT(*) = 0 THEN 'PASS' ELSE 'FAIL' END AS RES
  FROM SCM_ADM_USER_GR_MNU_BTN_MPG_M
 WHERE MNU_ID = 'DMF0043' AND SHT_NM = 'version' AND MNU_BTN_CD = 'SAVE'
   AND USER_GR_ID NOT IN ('ADMIN', 'DM ADMIN') AND USE_YN = 'Y';

-- V4 상세
SELECT 'V4 DETAIL' AS CHK, USER_GR_ID, MNU_BTN_CD, USE_YN FROM SCM_ADM_USER_GR_MNU_BTN_MPG_M
 WHERE MNU_ID = 'DMF0043' AND SHT_NM = 'version' ORDER BY USER_GR_ID, MNU_BTN_CD;
