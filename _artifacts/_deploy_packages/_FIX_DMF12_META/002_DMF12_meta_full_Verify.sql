-- Verify (DDL/DML 없음, SELECT 만, 5 BLOCK)
-- DBeaver 호환 (SET/PROMPT 0건)

SELECT 'BLOCK 1: MSG_M' AS chk,
       COUNT(*) AS actual, 52 AS expect,
       CASE WHEN COUNT(*)>=52 THEN 'PASS' ELSE 'FAIL' END AS result
FROM SCM_MGR.SCM_ADM_MSG_M
WHERE MSG_ID LIKE 'P_DMF%' AND REGEXP_LIKE(MSG_ID, 'P_DMF(0014|0021|0042|0044|0048|0049|0074|0081|0082)')
  AND LANG_CD='KO' AND MSG_TP_CD='API';

SELECT 'BLOCK 2: API_M' AS chk,
       COUNT(*) AS actual, 52 AS expect,
       CASE WHEN COUNT(*)>=52 THEN 'PASS' ELSE 'FAIL' END AS result
FROM SCM_MGR.SCM_ADM_API_M
WHERE API_URL LIKE 'PKG_DMF%' AND REGEXP_LIKE(API_URL, 'PKG_DMF(0014|0021|0042|0044|0048|0049|0074|0081|0082)');

SELECT 'BLOCK 3: BTN_MPG' AS chk,
       COUNT(*) AS actual, 52 AS expect,
       CASE WHEN COUNT(*)>=52 THEN 'PASS' ELSE 'FAIL' END AS result
FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M
WHERE MNU_ID IN ('DMF0014','DMF0021','DMF0042','DMF0044','DMF0048','DMF0049','DMF0074','DMF0081','DMF0082');

SELECT 'BLOCK 4: PROC_M' AS chk,
       COUNT(*) AS actual, 484 AS expect,
       CASE WHEN COUNT(*)=484 THEN 'PASS' ELSE 'FAIL' END AS result
FROM SCM_MGR.SCM_ADM_PROC_M
WHERE PROC_NM LIKE 'P_DMF%' AND REGEXP_LIKE(PROC_NM, 'P_DMF(0014|0021|0042|0044|0048|0049|0074|0081|0082)');

SELECT 'BLOCK 5: GR_BTN' AS chk,
       COUNT(*) AS actual, 208 AS expect,
       CASE WHEN COUNT(*)>=208 THEN 'PASS' ELSE 'FAIL' END AS result
FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M
WHERE MNU_ID IN ('DMF0014','DMF0021','DMF0042','DMF0044','DMF0048','DMF0049','DMF0074','DMF0081','DMF0082');

-- 화면별 카운트 표
SELECT
  M.MNU_ID,
  (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_API_M A WHERE A.API_URL LIKE 'PKG_'||M.MNU_ID||'%')        AS api_cnt,
  (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M P WHERE P.PROC_NM LIKE 'P_'||M.MNU_ID||'%')          AS proc_cnt,
  (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M B WHERE B.MNU_ID=M.MNU_ID)                    AS btn_cnt,
  (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M G WHERE G.MNU_ID=M.MNU_ID)            AS gr_btn_cnt
FROM (
  SELECT 'DMF0014' AS MNU_ID FROM DUAL UNION ALL SELECT 'DMF0021' FROM DUAL UNION ALL
  SELECT 'DMF0042' FROM DUAL UNION ALL SELECT 'DMF0044' FROM DUAL UNION ALL
  SELECT 'DMF0048' FROM DUAL UNION ALL SELECT 'DMF0049' FROM DUAL UNION ALL
  SELECT 'DMF0074' FROM DUAL UNION ALL SELECT 'DMF0081' FROM DUAL UNION ALL
  SELECT 'DMF0082' FROM DUAL
) M
ORDER BY MNU_ID;
