-- 008_DMF12_proc_nm_pkg_prefix.sql
-- 근본 사고: BE 가 PROC_M lookup 시 PROC_NM 으로 매칭. 우리 PROC_NM 이 PKG 없는 form
--   - 자매 표준: PKG_SYS0003.SYS0003_GET_LEVEL_ONE_DATA
--   - 우리 fix:  P_DMF0021_GET_SALES_PLAN_MEASUREINFO (PKG 누락)
-- → API_URL (PKG_DMF0021.P_DMF0021_xxx) 과 매칭 fail → BE 가 인자 0 으로 호출 → PLS-00306
-- 또한 O_RESULT_CURSOR 의 DATA_TP_CD 'CURSOR' → 'PROC_RESULT' (자매 표준)

-- BLOCK 1: PROC_NM 에 PKG_XXX. prefix 추가
UPDATE SCM_MGR.SCM_ADM_PROC_M
SET PROC_NM = REGEXP_REPLACE(PROC_NM, '^P_(DMF\d+)', 'PKG_\1.P_\1') || ''  -- e.g. P_DMF0021_GET → PKG_DMF0021.P_DMF0021_GET
    , LAST_UPDATED_BY='minyonglee1', LAST_UPDATE_DATE=SYSDATE
WHERE PROC_NM LIKE 'P_DMF%'
  AND PROC_NM NOT LIKE 'PKG_%'
  AND REGEXP_LIKE(PROC_NM, '^P_DMF(0014|0021|0042|0044|0048|0049|0074|0081|0082)_');

COMMIT;

-- BLOCK 2: O_RESULT_CURSOR 의 DATA_TP_CD = 'PROC_RESULT' (자매 표준 — BE 가 cursor type 인식)
UPDATE SCM_MGR.SCM_ADM_PROC_M
SET DATA_TP_CD = 'PROC_RESULT',
    LAST_UPDATED_BY='minyonglee1', LAST_UPDATE_DATE=SYSDATE
WHERE PROC_NM LIKE 'PKG_DMF%'
  AND REGEXP_LIKE(PROC_NM, 'PKG_DMF(0014|0021|0042|0044|0048|0049|0074|0081|0082)')
  AND COL_NM = 'O_RESULT_CURSOR'
  AND COL_TP_CD = 'OUT'
  AND DATA_TP_CD = 'CURSOR';

COMMIT;

-- Verify
SELECT 'PROC_NM PKG prefix' AS chk, COUNT(*) AS cnt
FROM SCM_MGR.SCM_ADM_PROC_M
WHERE PROC_NM LIKE 'PKG_DMF%' AND REGEXP_LIKE(PROC_NM, 'PKG_DMF(0014|0021|0042|0044|0048|0049|0074|0081|0082)')
UNION ALL
SELECT 'O_RESULT_CURSOR PROC_RESULT', COUNT(*)
FROM SCM_MGR.SCM_ADM_PROC_M
WHERE PROC_NM LIKE 'PKG_DMF%' AND COL_NM='O_RESULT_CURSOR' AND DATA_TP_CD='PROC_RESULT'
UNION ALL
SELECT 'PROC_NM 잔존 PKG 누락', COUNT(*)
FROM SCM_MGR.SCM_ADM_PROC_M
WHERE PROC_NM LIKE 'P_DMF%' AND PROC_NM NOT LIKE 'PKG_%'
  AND REGEXP_LIKE(PROC_NM, '^P_DMF(0014|0021|0042|0044|0048|0049|0074|0081|0082)');

-- DMF0021 sample
SELECT PROC_NM, COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD
FROM SCM_MGR.SCM_ADM_PROC_M
WHERE PROC_NM LIKE 'PKG_DMF0021%'
ORDER BY PROC_NM, SORT_ORD;
