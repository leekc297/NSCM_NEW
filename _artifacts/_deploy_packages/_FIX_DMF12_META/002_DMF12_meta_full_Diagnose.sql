-- Diagnose (재발 진단) — 사고 패턴 점검 시 사용
-- DBeaver 호환 (SET/PROMPT 0건)

-- Diag 1: 9 PKG 의 SP 인벤토리 (= 52 SP 의무)
SELECT 'Diag 1: PKG procedure 인벤토리' AS chk,
       COUNT(DISTINCT OBJECT_NAME) AS sp_cnt,
       52 AS expect,
       CASE WHEN COUNT(DISTINCT OBJECT_NAME)=52 THEN 'PASS' ELSE 'FAIL' END AS result
FROM ALL_ARGUMENTS
WHERE OWNER='SCM_MGR'
  AND PACKAGE_NAME IN ('PKG_DMF0014','PKG_DMF0021','PKG_DMF0042','PKG_DMF0044','PKG_DMF0048','PKG_DMF0049','PKG_DMF0074','PKG_DMF0081','PKG_DMF0082')
  AND OBJECT_NAME LIKE 'P_DMF%' AND DATA_LEVEL=0;

-- Diag 2: PROC_M 와 ALL_ARGUMENTS 의 row count 1:1 매핑 (= 484 = 484)
SELECT 'Diag 2: PROC_M vs ALL_ARGS' AS chk,
       (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M WHERE PROC_NM LIKE 'P_DMF%' AND REGEXP_LIKE(PROC_NM, 'P_DMF(0014|0021|0042|0044|0048|0049|0074|0081|0082)')) AS proc_m_cnt,
       (SELECT COUNT(*) FROM ALL_ARGUMENTS WHERE OWNER='SCM_MGR' AND PACKAGE_NAME IN ('PKG_DMF0014','PKG_DMF0021','PKG_DMF0042','PKG_DMF0044','PKG_DMF0048','PKG_DMF0049','PKG_DMF0074','PKG_DMF0081','PKG_DMF0082') AND OBJECT_NAME LIKE 'P_DMF%' AND DATA_LEVEL=0) AS args_cnt,
       CASE WHEN (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M WHERE PROC_NM LIKE 'P_DMF%' AND REGEXP_LIKE(PROC_NM, 'P_DMF(0014|0021|0042|0044|0048|0049|0074|0081|0082)'))
                = (SELECT COUNT(*) FROM ALL_ARGUMENTS WHERE OWNER='SCM_MGR' AND PACKAGE_NAME IN ('PKG_DMF0014','PKG_DMF0021','PKG_DMF0042','PKG_DMF0044','PKG_DMF0048','PKG_DMF0049','PKG_DMF0074','PKG_DMF0081','PKG_DMF0082') AND OBJECT_NAME LIKE 'P_DMF%' AND DATA_LEVEL=0)
            THEN 'PASS' ELSE 'FAIL' END AS result
FROM DUAL;

-- Diag 3: SP 별 PROC_M 카운트 detail (mismatch 찾기)
SELECT
  A.OBJECT_NAME,
  COUNT(*) AS args_cnt,
  (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M P WHERE P.PROC_NM = A.OBJECT_NAME) AS proc_m_cnt,
  CASE WHEN COUNT(*) = (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M P WHERE P.PROC_NM = A.OBJECT_NAME) THEN 'PASS' ELSE 'FAIL' END AS result
FROM ALL_ARGUMENTS A
WHERE A.OWNER='SCM_MGR'
  AND A.PACKAGE_NAME IN ('PKG_DMF0014','PKG_DMF0021','PKG_DMF0042','PKG_DMF0044','PKG_DMF0048','PKG_DMF0049','PKG_DMF0074','PKG_DMF0081','PKG_DMF0082')
  AND A.OBJECT_NAME LIKE 'P_DMF%' AND A.DATA_LEVEL=0
GROUP BY A.OBJECT_NAME
HAVING COUNT(*) <> (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M P WHERE P.PROC_NM = A.OBJECT_NAME)
ORDER BY A.OBJECT_NAME;

-- Diag 4: PKG body STATUS = INVALID 화면 (메타 등록되어 있어도 호출 실패 화면)
SELECT 'Diag 4: PKG body INVALID' AS chk, OBJECT_NAME, STATUS
FROM ALL_OBJECTS
WHERE OWNER='SCM_MGR' AND OBJECT_TYPE='PACKAGE BODY' AND STATUS='INVALID'
  AND OBJECT_NAME IN ('PKG_DMF0014','PKG_DMF0021','PKG_DMF0042','PKG_DMF0044','PKG_DMF0048','PKG_DMF0049','PKG_DMF0074','PKG_DMF0081','PKG_DMF0082')
ORDER BY OBJECT_NAME;

-- Diag 5: PKG body 자체 없음 (DMF0048/0082)
SELECT 'Diag 5: PKG body 없음' AS chk, NEED.PKG, CASE WHEN B.OBJECT_NAME IS NULL THEN 'FAIL: BODY 없음' ELSE 'PASS' END AS result
FROM (
  SELECT 'PKG_DMF0014' AS PKG FROM DUAL UNION ALL SELECT 'PKG_DMF0021' FROM DUAL UNION ALL
  SELECT 'PKG_DMF0042' FROM DUAL UNION ALL SELECT 'PKG_DMF0044' FROM DUAL UNION ALL
  SELECT 'PKG_DMF0048' FROM DUAL UNION ALL SELECT 'PKG_DMF0049' FROM DUAL UNION ALL
  SELECT 'PKG_DMF0074' FROM DUAL UNION ALL SELECT 'PKG_DMF0081' FROM DUAL UNION ALL
  SELECT 'PKG_DMF0082' FROM DUAL
) NEED
LEFT JOIN ALL_OBJECTS B ON B.OWNER='SCM_MGR' AND B.OBJECT_NAME=NEED.PKG AND B.OBJECT_TYPE='PACKAGE BODY'
ORDER BY NEED.PKG;
