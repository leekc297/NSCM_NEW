-- 004_DMF0021_btn_sheet_quick_fix.sql
-- DMF0021 SalesPlan 화면 진입 사고 fix:
--   1. BTN_CD 'SEARCH_P_xxx' → 'SEARCH' (자매 표준 짧은 이름, FE/BE 매핑 가능)
--   2. SHEET_COLUMNS.SHEET_NAME 'Sales Plan' → 'main' (FE SHEETS.MAIN 매칭)
--   3. 권한 (USER_GR_MNU_BTN_MPG_M) 도 같이 UPDATE
-- 멱등성: WHERE 절로 안전. UPDATE 이므로 재실행 OK.

-- BLOCK 1: 메인 SEARCH (P_DMF0021_GET_SALES_PLAN_MEASUREINFO) → 'SEARCH'
UPDATE SCM_MGR.SCM_ADM_MNU_BTN_MPG_M
SET MNU_BTN_CD='SEARCH', LAST_UPDATED_BY='minyonglee1', LAST_UPDATE_DATE=SYSDATE
WHERE MNU_ID='DMF0021' AND SHT_NM='main'
  AND MNU_BTN_CD='SEARCH_P_DMF0021_GET_SALES_PLAN_MEASUREINFO';

UPDATE SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M
SET MNU_BTN_CD='SEARCH', LAST_UPDATED_BY='minyonglee1', LAST_UPDATE_DATE=SYSDATE
WHERE MNU_ID='DMF0021' AND SHT_NM='main'
  AND MNU_BTN_CD='SEARCH_P_DMF0021_GET_SALES_PLAN_MEASUREINFO';

-- BLOCK 2: SAVE (P_DMF0021_SAVE_DM_PLN_SALES_PLAN_ALL) → 'SAVE'
UPDATE SCM_MGR.SCM_ADM_MNU_BTN_MPG_M
SET MNU_BTN_CD='SAVE', LAST_UPDATED_BY='minyonglee1', LAST_UPDATE_DATE=SYSDATE
WHERE MNU_ID='DMF0021' AND SHT_NM='main'
  AND MNU_BTN_CD='SAVE_P_DMF0021_SAVE_DM_PLN_SALES_PLAN_ALL';

UPDATE SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M
SET MNU_BTN_CD='SAVE', LAST_UPDATED_BY='minyonglee1', LAST_UPDATE_DATE=SYSDATE
WHERE MNU_ID='DMF0021' AND SHT_NM='main'
  AND MNU_BTN_CD='SAVE_P_DMF0021_SAVE_DM_PLN_SALES_PLAN_ALL';

-- BLOCK 3: SHEET_COLUMNS.SHEET_NAME 'Sales Plan' → 'main'
UPDATE SCM_MGR.SCM_MST_SHEET_COLUMNS
SET SHEET_NAME='main', LAST_UPDATED_BY='minyonglee1', LAST_UPDATE_DATE=SYSDATE
WHERE PROGRAM_ID='DMF0021' AND SHEET_NAME='Sales Plan';

COMMIT;

-- Verify
SELECT 'BTN_CD SEARCH' AS chk, COUNT(*) FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID='DMF0021' AND MNU_BTN_CD='SEARCH'
UNION ALL SELECT 'BTN_CD SAVE',  COUNT(*) FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID='DMF0021' AND MNU_BTN_CD='SAVE'
UNION ALL SELECT 'GR_BTN SEARCH', COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE MNU_ID='DMF0021' AND MNU_BTN_CD='SEARCH'
UNION ALL SELECT 'GR_BTN SAVE', COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE MNU_ID='DMF0021' AND MNU_BTN_CD='SAVE'
UNION ALL SELECT 'SHEET main', COUNT(*) FROM SCM_MGR.SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID='DMF0021' AND SHEET_NAME='main';
