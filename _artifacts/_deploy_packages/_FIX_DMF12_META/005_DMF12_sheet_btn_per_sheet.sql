-- 권한 — 4 그룹 × 모든 BTN_MPG row
INSERT INTO SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M (USER_GR_ID, MNU_ID, SHT_NM, MNU_BTN_CD, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT GR.USER_GR_ID, BTN.MNU_ID, BTN.SHT_NM, BTN.MNU_BTN_CD, 'Y',
       'minyonglee1', SYSDATE, 'minyonglee1', SYSDATE
FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M BTN
CROSS JOIN (
  SELECT 'ADMIN' AS USER_GR_ID FROM DUAL UNION ALL
  SELECT 'DM ADMIN' FROM DUAL UNION ALL
  SELECT 'DM Viewer' FROM DUAL UNION ALL
  SELECT 'GUEST' FROM DUAL
) GR
WHERE BTN.MNU_ID IN ('DMF0014','DMF0021','DMF0042','DMF0042_1','DMF0042_2','DMF0042_3','DMF0044','DMF0048','DMF0049','DMF0074','DMF0081','DMF0082')
  AND BTN.USE_YN='Y' AND BTN.MNU_BTN_CD IN ('SEARCH','SAVE')
  AND NOT EXISTS (
    SELECT 1 FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M E
    WHERE E.USER_GR_ID = GR.USER_GR_ID AND E.MNU_ID = BTN.MNU_ID AND E.SHT_NM = BTN.SHT_NM AND E.MNU_BTN_CD = BTN.MNU_BTN_CD
  );

