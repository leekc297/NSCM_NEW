INSERT INTO SCM_MGR.SCM_ADM_MSG_M (MSG_ID, LANG_CD, MSG_TP_CD, MSG_NM, MSG_DESC, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT
  SUBSTR(A.OBJECT_NAME, 1, 50) AS MSG_ID,
  'KO', 'API',
  A.OBJECT_NAME,
  CASE
    WHEN A.OBJECT_NAME LIKE '%_GET_%'   OR A.OBJECT_NAME LIKE '%_POPUP%' THEN A.OBJECT_NAME || ' 조회'
    WHEN A.OBJECT_NAME LIKE '%_SAVE_%'                                    THEN A.OBJECT_NAME || ' 저장'
    WHEN A.OBJECT_NAME LIKE '%_UPLOAD%'                                   THEN A.OBJECT_NAME || ' 업로드'
    WHEN A.OBJECT_NAME LIKE '%_CREATE'                                    THEN A.OBJECT_NAME || ' 생성'
    ELSE A.OBJECT_NAME
  END,
  'Y', 'minyonglee1', SYSDATE, 'minyonglee1', SYSDATE
FROM (
  SELECT DISTINCT OBJECT_NAME FROM ALL_ARGUMENTS
  WHERE OWNER='SCM_MGR'
    AND PACKAGE_NAME IN ('PKG_DMF0014','PKG_DMF0021','PKG_DMF0042','PKG_DMF0044','PKG_DMF0048','PKG_DMF0049','PKG_DMF0074','PKG_DMF0081','PKG_DMF0082')
    AND OBJECT_NAME LIKE 'P_DMF%' AND DATA_LEVEL = 0
) A
WHERE NOT EXISTS (
  SELECT 1 FROM SCM_MGR.SCM_ADM_MSG_M E
  WHERE E.MSG_ID = SUBSTR(A.OBJECT_NAME, 1, 50) AND E.LANG_CD = 'KO'
);

