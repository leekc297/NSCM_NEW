INSERT INTO SCM_MGR.SCM_ADM_API_M (API_ID, API_TP_CD, API_MSG_ID, API_MSG_DESC, API_URL, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT
  SUBSTR(A.OBJECT_NAME, 1, 50) AS API_ID,
  CASE
    WHEN A.OBJECT_NAME LIKE '%_GET_%'   THEN 'PROC_SELECT'
    WHEN A.OBJECT_NAME LIKE '%_POPUP%'  THEN 'PROC_SELECT'
    WHEN A.OBJECT_NAME LIKE '%_SAVE_%'  THEN 'PROC_SAVE'
    WHEN A.OBJECT_NAME LIKE '%_CREATE'  THEN 'PROC_SAVE'
    WHEN A.OBJECT_NAME LIKE '%_UPLOAD%' THEN 'EXCELUPLOAD'
    ELSE 'PROC'
  END,
  SUBSTR(A.OBJECT_NAME, 1, 50),
  A.OBJECT_NAME,
  A.PACKAGE_NAME || '.' || A.OBJECT_NAME,
  'Y', 'minyonglee1', SYSDATE, 'minyonglee1', SYSDATE
FROM (
  SELECT DISTINCT PACKAGE_NAME, OBJECT_NAME FROM ALL_ARGUMENTS
  WHERE OWNER='SCM_MGR'
    AND PACKAGE_NAME IN ('PKG_DMF0014','PKG_DMF0021','PKG_DMF0042','PKG_DMF0044','PKG_DMF0048','PKG_DMF0049','PKG_DMF0074','PKG_DMF0081','PKG_DMF0082')
    AND OBJECT_NAME LIKE 'P_DMF%' AND DATA_LEVEL = 0
) A
WHERE NOT EXISTS (
  SELECT 1 FROM SCM_MGR.SCM_ADM_API_M E WHERE E.API_ID = SUBSTR(A.OBJECT_NAME, 1, 50)
);

