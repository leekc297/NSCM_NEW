INSERT INTO SCM_MGR.SCM_ADM_MNU_BTN_MPG_M (MNU_ID, SHT_NM, MNU_BTN_CD, API_ID, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT
  REGEXP_SUBSTR(A.OBJECT_NAME, 'DMF[0-9]+'),
  'main',
  -- MNU_BTN_CD = ACTION + '_' + SP_LAST_PART (50 max) — 자매 화면별 unique
  SUBSTR(
    CASE
      WHEN A.OBJECT_NAME LIKE '%_SPREAD_TITLE'    THEN 'SPREAD_TITLE'
      WHEN A.OBJECT_NAME LIKE '%_GET_MEASURE'     THEN 'MEASURE'
      WHEN A.OBJECT_NAME LIKE '%_GET_%' OR A.OBJECT_NAME LIKE '%_POPUP%' THEN 'SEARCH'
      WHEN A.OBJECT_NAME LIKE '%_SAVE_%'          THEN 'SAVE'
      WHEN A.OBJECT_NAME LIKE '%_CREATE'          THEN 'SAVE'
      WHEN A.OBJECT_NAME LIKE '%_UPLOAD%'         THEN 'EXCELUPLOAD'
      ELSE 'EXECUTE'
    END || '_' || A.OBJECT_NAME, 1, 50
  ),
  SUBSTR(A.OBJECT_NAME, 1, 50),
  'Y', 'minyonglee1', SYSDATE, 'minyonglee1', SYSDATE
FROM (
  SELECT DISTINCT OBJECT_NAME FROM ALL_ARGUMENTS
  WHERE OWNER='SCM_MGR'
    AND PACKAGE_NAME IN ('PKG_DMF0014','PKG_DMF0021','PKG_DMF0042','PKG_DMF0044','PKG_DMF0048','PKG_DMF0049','PKG_DMF0074','PKG_DMF0081','PKG_DMF0082')
    AND OBJECT_NAME LIKE 'P_DMF%' AND DATA_LEVEL = 0
) A
WHERE NOT EXISTS (
  SELECT 1 FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M E
  WHERE E.MNU_ID = REGEXP_SUBSTR(A.OBJECT_NAME, 'DMF[0-9]+')
    AND E.SHT_NM = 'main'
    AND E.API_ID = SUBSTR(A.OBJECT_NAME, 1, 50)
);

