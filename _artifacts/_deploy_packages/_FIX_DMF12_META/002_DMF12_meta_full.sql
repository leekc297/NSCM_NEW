INSERT INTO SCM_MGR.SCM_ADM_PROC_M (PROC_NM, COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT
  A.OBJECT_NAME AS PROC_NM,
  CASE UPPER(A.ARGUMENT_NAME)
    WHEN 'P_USER_ID'        THEN 'sesUserId'
    WHEN 'P_MENU_ID'        THEN 'mnuId'
    WHEN 'P_LANG_CD'        THEN 'sesLangCd'
    WHEN 'P_CREATED_BY'     THEN 'createdBy'
    WHEN 'P_USERINFO'       THEN 'userInfo'
    WHEN 'O_RESULT_CURSOR'  THEN 'O_RESULT_CURSOR'
    WHEN 'O_ERROR_CURSOR'   THEN 'O_ERROR_CURSOR'
    ELSE
      CASE
        WHEN UPPER(A.ARGUMENT_NAME) LIKE 'O_%' THEN LOWER(A.ARGUMENT_NAME)
        WHEN UPPER(A.ARGUMENT_NAME) LIKE 'P_%' THEN
          LOWER(SUBSTR(REPLACE(INITCAP(LOWER(REPLACE(SUBSTR(A.ARGUMENT_NAME,3),'_',' '))),' ',''),1,1)) ||
          SUBSTR(REPLACE(INITCAP(LOWER(REPLACE(SUBSTR(A.ARGUMENT_NAME,3),'_',' '))),' ',''),2)
        ELSE LOWER(A.ARGUMENT_NAME)
      END
  END AS COL_NM,
  CASE A.DATA_TYPE
    WHEN 'VARCHAR2'   THEN 'VARCHAR'
    WHEN 'REF CURSOR' THEN 'CURSOR'
    ELSE A.DATA_TYPE
  END AS DATA_TP_CD,
  A.IN_OUT AS COL_TP_CD,
  A.POSITION AS SORT_ORD,
  'minyonglee1', SYSDATE, 'minyonglee1', SYSDATE
FROM ALL_ARGUMENTS A
WHERE A.OWNER='SCM_MGR'
  AND A.PACKAGE_NAME IN ('PKG_DMF0014','PKG_DMF0021','PKG_DMF0042','PKG_DMF0044','PKG_DMF0048','PKG_DMF0049','PKG_DMF0074','PKG_DMF0081','PKG_DMF0082')
  AND A.OBJECT_NAME LIKE 'P_DMF%'
  AND A.DATA_LEVEL = 0
  AND NOT EXISTS (
    SELECT 1 FROM SCM_MGR.SCM_ADM_PROC_M P
    WHERE P.PROC_NM = A.OBJECT_NAME
      AND P.COL_TP_CD = A.IN_OUT
      AND P.SORT_ORD = A.POSITION
  );

