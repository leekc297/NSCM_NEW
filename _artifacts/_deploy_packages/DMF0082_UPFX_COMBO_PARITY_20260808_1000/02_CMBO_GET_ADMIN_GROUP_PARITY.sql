-- AS-IS 는 combo SP 상단(모든 @Code 분기 이전)에서 두 변형을 수행한다:
--   ① @v_dept_id  = 사용자 DEPT_ID (PM_TEAM_MAPPING 후순위 폴백)
--   ② @v_group_id = 'ADMIN'  ← 사용자 그룹이 lookup GET_ADMIN_GROUP(SEGMENT2 IN 'ALL','DMF0003')에 등재된 경우
-- 소비 분기 3종: TeambyDivisionAuth / SiteByEndCustomerAuth / Auth_Dept(+EndCustomerByDivisionDeptAuth)
--
-- TO-BE 현황: ①PM_TEAM_MAPPING 은 이식됨. ②**권한 변형이 리터럴 그룹 'ADMIN' 검사로 축소**되어
--   GET_ADMIN_GROUP 에 등재된 DM ADMIN·DM Planner·SCM PI Admin·SCP Planner·DM Planner (W/S) 가
--   ADMIN 으로 인정되지 않았다 → 해당 사용자의 Team/Site/EndCustomer 셀 콤보가 과도하게 좁아짐(0행 다발).
--
-- 다중 그룹 보유 사용자는 **보유 그룹 중 하나라도** 등재되면 ADMIN (AUTHUNION 정책, 2026-08-04 사용자 확정).
-- 소비 화면: DMF0003 'Mkt Fcst' 3컬럼 (전수 grep — 타 화면 소비 0).
--
-- ⚠️ 원복: 아래 백업 CTAS 로 되돌린다.
--   CREATE TABLE SCM_MGR.CMBO_BAK_GAG_20260808 AS SELECT * FROM SCM_MGR.SCM_ADM_CMBO_SQL_M
--    WHERE SQL_ID IN ('TeambyDivisionAuth','SiteByEndCustomerAuth','EndCustomerByDivisionDeptAuth');
