UPDATE SCM_MGR.SCM_ADM_CMBO_SQL_M
   SET SQL_DTL_CTN = 'WITH ME AS (SELECT DEPT_ID FROM TB_FX_USER WHERE USERID = @sesUserId),
MAPSET AS (SELECT L.SEGMENT3 AS DEPT_ID FROM SCM_ADM_LOOKUP_MASTER_DETAIL L
           WHERE L.LOOKUP_TYPE = ''PM_TEAM_MAPPING'' AND L.VALID_YN = ''Y''
             AND L.SEGMENT1 IN (SELECT DEPT_ID FROM ME)
           UNION SELECT DEPT_ID FROM ME),
F AS (SELECT (SELECT COUNT(*) FROM MAPSET) AS TEAM_CNT,
             (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL L JOIN SCM_MGR.SCM_ADM_USER_GR_MPG_M G ON G.USER_GR_ID = L.SEGMENT1 WHERE L.LOOKUP_TYPE = ''GET_ADMIN_GROUP'' AND L.VALID_YN = ''Y'' AND L.SEGMENT2 IN (''ALL'',''DMF0003'') AND G.USER_ID = @sesUserId AND G.USE_YN = ''Y'') AS IS_ADMIN
      FROM DUAL)
SELECT DISTINCT DIVISION_ID, CODE, NAME FROM (
SELECT A.DIVISION_ID, B.DEPT_ID AS CODE, B.DEPT_NAME_KO AS NAME
FROM SCM_MST_SITE A JOIN SCM_MST_SSO_DEPT_INFO B ON A.DEPT_ID = B.DEPT_ID CROSS JOIN F
WHERE A.SITE_TYPE = ''SALES'' AND A.DIVISION_ID <> ''40'' AND F.TEAM_CNT <= 1
  AND A.DIVISION_ID IN (SELECT UNIT_ID FROM SCM_ADM_USER_GR_UNIT_AUTH_MPG_M
                        WHERE USER_ID = @sesUserId AND UNIT_TP_CD = ''D'' AND USE_YN = ''Y'')
  AND (F.IS_ADMIN > 0 OR B.DEPT_ID IN (SELECT DEPT_ID FROM ME))
UNION
SELECT ''40'', C.DEPT_ID, C.DEPT_NAME_KO
FROM SCM_MST_SITE_ITEM A JOIN SCM_MST_SSO_USER_INFO B ON A.OWNER = B.USER_ID
JOIN SCM_MST_SSO_DEPT_INFO C ON B.DEPT_ID = C.DEPT_ID CROSS JOIN F
WHERE A.DIVISION_ID = ''40'' AND F.TEAM_CNT <= 1
  AND (F.IS_ADMIN > 0 OR C.DEPT_ID IN (SELECT DEPT_ID FROM ME))
UNION
SELECT A.DIVISION_ID, B.DEPT_ID, B.DEPT_NAME_KO
FROM SCM_MST_SITE A JOIN SCM_MST_SSO_DEPT_INFO B ON A.DEPT_ID = B.DEPT_ID CROSS JOIN F
WHERE A.SITE_TYPE = ''SALES'' AND A.DIVISION_ID <> ''40'' AND F.TEAM_CNT > 1
  AND B.DEPT_ID IN (SELECT DEPT_ID FROM MAPSET)
UNION
SELECT A.DIVISION_ID, B2.DEPT_ID, B2.DEPT_NAME_KO
FROM SCM_MST_SITE A
JOIN SCM_MST_SITE_ITEM I ON A.DIVISION_ID = I.DIVISION_ID AND A.SCM_SITE_ID = I.SCM_SITE_ID
JOIN SCM_MST_SSO_USER_INFO SU ON SU.USER_ID = I.OWNER
JOIN SCM_MST_SSO_DEPT_INFO B2 ON B2.DEPT_ID = SU.DEPT_ID CROSS JOIN F
WHERE A.SITE_TYPE = ''SALES'' AND A.DIVISION_ID = ''40'' AND F.TEAM_CNT > 1
  AND B2.DEPT_ID IN (SELECT DEPT_ID FROM MAPSET)
) ORDER BY CODE',
       LAST_UPDATED_BY = 'admin', LAST_UPDATE_DATE = SYSDATE
 WHERE SQL_ID = 'TeambyDivisionAuth';

UPDATE SCM_MGR.SCM_ADM_CMBO_SQL_M
   SET SQL_DTL_CTN = 'SELECT DISTINCT A.DIVISION_ID, A.END_CUSTOMER, A.SCM_SITE_ID AS CODE, A.SCM_SITE_ID AS NAME
FROM SCM_MST_SITE A
WHERE A.SITE_TYPE = ''SALES''
  AND A.VALID_YN = ''Y''
  AND A.DIVISION_ID IN (SELECT UNIT_ID FROM SCM_ADM_USER_GR_UNIT_AUTH_MPG_M
                        WHERE USER_ID = @sesUserId AND UNIT_TP_CD = ''D'' AND USE_YN = ''Y'')
  AND ( EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL L JOIN SCM_MGR.SCM_ADM_USER_GR_MPG_M G ON G.USER_GR_ID = L.SEGMENT1 WHERE L.LOOKUP_TYPE = ''GET_ADMIN_GROUP'' AND L.VALID_YN = ''Y'' AND L.SEGMENT2 IN (''ALL'',''DMF0003'') AND G.USER_ID = @sesUserId AND G.USE_YN = ''Y'')
     OR A.DEPT_ID IN (
          SELECT L.SEGMENT3 FROM SCM_ADM_LOOKUP_MASTER_DETAIL L
          WHERE L.LOOKUP_TYPE = ''PM_TEAM_MAPPING'' AND L.VALID_YN = ''Y''
            AND L.SEGMENT1 IN (SELECT U.DEPT_ID FROM TB_FX_USER U WHERE U.USERID = @sesUserId)
          UNION
          SELECT U.DEPT_ID FROM TB_FX_USER U WHERE U.USERID = @sesUserId))
ORDER BY CODE',
       LAST_UPDATED_BY = 'admin', LAST_UPDATE_DATE = SYSDATE
 WHERE SQL_ID = 'SiteByEndCustomerAuth';

UPDATE SCM_MGR.SCM_ADM_CMBO_SQL_M
   SET SQL_DTL_CTN = 'SELECT DISTINCT A.DIVISION_ID, A.DEPT_ID, A.END_CUSTOMER AS CODE,
       NVL(D.SEGMENT3, A.END_CUSTOMER) AS NAME
FROM SCM_MST_SITE A
LEFT JOIN SCM_ADM_LOOKUP_MASTER_DETAIL D
  ON A.DIVISION_ID = D.SEGMENT1 AND A.END_CUSTOMER = D.SEGMENT2
 AND D.LOOKUP_TYPE = ''END_CUSTOMER'' AND D.VALID_YN = ''Y''
WHERE A.END_CUSTOMER IS NOT NULL
  AND A.DIVISION_ID IN (SELECT UNIT_ID FROM SCM_ADM_USER_GR_UNIT_AUTH_MPG_M
                        WHERE USER_ID = @sesUserId AND UNIT_TP_CD = ''D'' AND USE_YN = ''Y'')
  AND ( EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL L JOIN SCM_MGR.SCM_ADM_USER_GR_MPG_M G ON G.USER_GR_ID = L.SEGMENT1 WHERE L.LOOKUP_TYPE = ''GET_ADMIN_GROUP'' AND L.VALID_YN = ''Y'' AND L.SEGMENT2 IN (''ALL'',''DMF0003'') AND G.USER_ID = @sesUserId AND G.USE_YN = ''Y'')
     OR A.DEPT_ID IN (
          SELECT L.SEGMENT3 FROM SCM_ADM_LOOKUP_MASTER_DETAIL L
          WHERE L.LOOKUP_TYPE = ''PM_TEAM_MAPPING'' AND L.VALID_YN = ''Y''
            AND L.SEGMENT1 IN (SELECT U.DEPT_ID FROM TB_FX_USER U WHERE U.USERID = @sesUserId)
          UNION
          SELECT U.DEPT_ID FROM TB_FX_USER U WHERE U.USERID = @sesUserId))
ORDER BY CODE',
       LAST_UPDATED_BY = 'admin', LAST_UPDATE_DATE = SYSDATE
 WHERE SQL_ID = 'EndCustomerByDivisionDeptAuth';

COMMIT;