-- [A] 핵심 행 메타 (사내 기대값 — MEASURE/EDIT_FLAG: DEFAULT_FLAG=' '(공백1), VISIBLE_FLAG='N',
--     VALID_YN='Y', DATA_SORT_METHOD_CODE=' ', DIVISION_ID='40,82,81,81_UC,81_HM,81_ST,81_HD,81_HG')
SELECT COLUMN_NAME,
       '['||NVL(DEFAULT_FLAG,'~NULL~')||']'          AS DEFAULT_FLAG,
       VISIBLE_FLAG, VALID_YN,
       '['||NVL(DATA_SORT_METHOD_CODE,'~NULL~')||']' AS SORT_METHOD,
       NVL(DIVISION_ID,'~NULL~')                     AS DIVISION_ID,
       TO_CHAR(LAST_UPDATE_DATE,'YYYY-MM-DD')        AS UPD
FROM   SCM_MGR.SCM_MST_SHEET_COLUMNS
WHERE  PROGRAM_ID='DMF0042' AND SHEET_NAME='Biz Plan'
  AND  COLUMN_NAME IN ('MEASURE','EDIT_FLAG','CURRENCY','SORT_ORDER_NO');

-- [B] branch① 시뮬 — titleset 없는 사용자의 v_ColList (기대: 23행 + MEASURE 포함)
SELECT C.COLUMN_NAME, '['||NVL(C.DEFAULT_FLAG,'~NULL~')||']' AS DF, C.VISIBLE_FLAG, C.SORT_ORDER_NO
FROM   SCM_MGR.SCM_MST_SHEET_COLUMNS C
WHERE  C.PROGRAM_ID='DMF0042' AND C.SHEET_NAME='Biz Plan'
  AND  ( C.DEFAULT_FLAG='Y' OR
         ( C.VISIBLE_FLAG='N' AND RTRIM(C.DEFAULT_FLAG) IS NULL AND C.VALID_YN='Y' ) )
ORDER  BY C.SORT_ORDER_NO;

-- [C] 오류 사용자(minyonglee1) titleset 'C' + branch② 시뮬 div40 (기대: MEASURE 포함.
--     titleset 0행이면 branch① 사용 — [B]가 판정 기준)
SELECT COLUMN_NAME, SORT_ORDER_NO FROM SCM_MGR.SCM_MST_TITLESET_USER
WHERE  PROGRAM_ID='DMF0042' AND SHEET_NAME='Biz Plan'
  AND  USER_ID='minyonglee1' AND USER_INQUIRY_COLUMN_TYPE_CODE='C'
ORDER  BY SORT_ORDER_NO;

SELECT COLUMN_NAME FROM (
    SELECT U.SORT_ORDER_NO, C.COLUMN_NAME
    FROM SCM_MGR.SCM_MST_TITLESET_USER U, SCM_MGR.SCM_MST_SHEET_COLUMNS C
    WHERE U.PROGRAM_ID=C.PROGRAM_ID AND U.SHEET_NAME=C.SHEET_NAME AND U.COLUMN_NAME=C.COLUMN_NAME
      AND U.PROGRAM_ID='DMF0042' AND U.SHEET_NAME='Biz Plan'
      AND U.USER_ID='minyonglee1' AND U.USER_INQUIRY_COLUMN_TYPE_CODE='C'
      AND '40' IN (SELECT TOKEN FROM TABLE(SCM_MGR.FN_STRING_SPLIT(C.DIVISION_ID,',')))
    UNION ALL
    SELECT SORT_ORDER_NO, COLUMN_NAME FROM (
      SELECT C.SORT_ORDER_NO, C.COLUMN_NAME
      FROM SCM_MGR.SCM_MST_SHEET_COLUMNS C
      WHERE C.PROGRAM_ID='DMF0042' AND C.SHEET_NAME='Biz Plan'
        AND C.VISIBLE_FLAG='N' AND RTRIM(C.DEFAULT_FLAG) IS NULL AND C.VALID_YN='Y'
        AND '40' IN (SELECT TOKEN FROM TABLE(SCM_MGR.FN_STRING_SPLIT(C.DIVISION_ID,','))))
    WHERE ROWNUM <= 100 )
ORDER BY SORT_ORDER_NO;

-- [D] 63행 분포 checksum (사내 기대: 총63 / DEFAULT_Y 21 / VISIBLE_N 3 / RTRIM_NULL 41)
SELECT COUNT(*)                                              AS TOTAL,
       SUM(CASE WHEN DEFAULT_FLAG='Y' THEN 1 ELSE 0 END)     AS DEFAULT_Y,
       SUM(CASE WHEN VISIBLE_FLAG='N' THEN 1 ELSE 0 END)     AS VISIBLE_N,
       SUM(CASE WHEN RTRIM(DEFAULT_FLAG) IS NULL THEN 1 ELSE 0 END) AS RTRIM_NULL
FROM   SCM_MGR.SCM_MST_SHEET_COLUMNS
WHERE  PROGRAM_ID='DMF0042' AND SHEET_NAME='Biz Plan';
