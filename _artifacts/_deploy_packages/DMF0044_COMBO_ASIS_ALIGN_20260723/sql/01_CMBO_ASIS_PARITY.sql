-- DMF0044 콤보 AS-IS 정합 — CMBO 멱등 MERGE (사내 2026-07-23 적용 완료분 재현)
-- 대상: FcstType, DmBizType

MERGE INTO SCM_MGR.SCM_ADM_CMBO_SQL_M t USING (SELECT 'FcstType' SQL_ID FROM DUAL) s ON (t.SQL_ID=s.SQL_ID)
WHEN MATCHED THEN UPDATE SET t.SQL_DTL_CTN='SELECT SEGMENT1 AS CODE, SEGMENT2 AS NAME
FROM SCM_ADM_LOOKUP_MASTER_DETAIL
WHERE LOOKUP_TYPE = ''SALES_TYPE_CODE'' AND VALID_YN = ''Y''
ORDER BY DISPLAY_SEQ', t.LAST_UPDATED_BY='admin', t.LAST_UPDATE_DATE=SYSDATE
WHEN NOT MATCHED THEN INSERT (SQL_ID,MDU_DIVS_CD,SQL_NM,SQL_DTL_CTN,USE_YN,CREATED_BY,CREATION_DATE,LAST_UPDATED_BY,LAST_UPDATE_DATE)
VALUES ('FcstType','DM','FCST Type by Division','SELECT SEGMENT1 AS CODE, SEGMENT2 AS NAME
FROM SCM_ADM_LOOKUP_MASTER_DETAIL
WHERE LOOKUP_TYPE = ''SALES_TYPE_CODE'' AND VALID_YN = ''Y''
ORDER BY DISPLAY_SEQ','Y','admin',SYSDATE,'admin',SYSDATE);

MERGE INTO SCM_MGR.SCM_ADM_CMBO_SQL_M t USING (SELECT 'DmBizType' SQL_ID FROM DUAL) s ON (t.SQL_ID=s.SQL_ID)
WHEN MATCHED THEN UPDATE SET t.SQL_DTL_CTN='SELECT SEGMENT1 AS CODE, SEGMENT2 AS NAME
FROM SCM_ADM_LOOKUP_MASTER_DETAIL
WHERE LOOKUP_TYPE = ''DM_BIZ_TYPE''
ORDER BY DISPLAY_SEQ', t.LAST_UPDATED_BY='admin', t.LAST_UPDATE_DATE=SYSDATE
WHEN NOT MATCHED THEN INSERT (SQL_ID,MDU_DIVS_CD,SQL_NM,SQL_DTL_CTN,USE_YN,CREATED_BY,CREATION_DATE,LAST_UPDATED_BY,LAST_UPDATE_DATE)
VALUES ('DmBizType','DM','DM_BIZ_TYPE','SELECT SEGMENT1 AS CODE, SEGMENT2 AS NAME
FROM SCM_ADM_LOOKUP_MASTER_DETAIL
WHERE LOOKUP_TYPE = ''DM_BIZ_TYPE''
ORDER BY DISPLAY_SEQ','Y','admin',SYSDATE,'admin',SYSDATE);

COMMIT;