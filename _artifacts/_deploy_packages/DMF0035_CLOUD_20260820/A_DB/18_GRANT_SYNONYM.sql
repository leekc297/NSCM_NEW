 WHERE TABLE_NAME IN ('PKG_DMF0035','PKG_DMF0022','PKG_DMF0051','PKG_SCM0002')
   AND GRANTEE IN ('SCMD_APP','SCMP_APP') ORDER BY 2, 1;
