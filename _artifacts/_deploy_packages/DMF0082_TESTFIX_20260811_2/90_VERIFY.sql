PROMPT == 1. PKG 컴파일 상태 (기대: PACKAGE / PACKAGE BODY 둘 다 VALID)
SELECT OBJECT_TYPE, STATUS FROM ALL_OBJECTS
 WHERE OWNER = 'SCM_MGR' AND OBJECT_NAME = 'PKG_DMF0082' ORDER BY OBJECT_TYPE;

PROMPT == 2. TEAMFILTER 마커 실재 (기대: 1)
SELECT COUNT(*) AS TEAMFILTER_MARKER FROM ALL_SOURCE
 WHERE OWNER = 'SCM_MGR' AND NAME = 'PKG_DMF0082' AND TYPE = 'PACKAGE BODY'
   AND TEXT LIKE '%TEAMFILTER 2026-08-11%';

PROMPT == 3. SHEET_MEASURE (기대: TOTAL_22 = 22 / NEW_8 = 8)
SELECT COUNT(*) AS TOTAL_22,
       SUM(CASE WHEN COLUMN_NAME IN ('TMM_FCST','RTF_SCP','IN_TRANSIT','CUST_FCST','VMI_DIO',
                                     'AS_In_Req','AS_In_Plan','AS_Inv') THEN 1 ELSE 0 END) AS NEW_8
  FROM SCM_MST_SHEET_MEASURE WHERE PROGRAM_ID = 'DMF0082' AND SHEET_NAME = 'FcstNPrice';

PROMPT == 4. No.39 — CELL_PROD_SITE_ID 는 81 에서 제외 (기대: DIVISION_ID = '40,82')
SELECT COLUMN_NAME, DIVISION_ID, VISIBLE_FLAG
  FROM SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID = 'DMF0082' AND COLUMN_NAME = 'CELL_PROD_SITE_ID';

PROMPT == 4-1. No.63-② — AS From Site 편집 개방 (기대: INPUT_TP_CD = 'IO')
SELECT COLUMN_NAME, DIVISION_ID, INPUT_TP_CD
  FROM SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID = 'DMF0082' AND SHEET_NAME = 'FcstNPrice' AND COLUMN_NAME = 'AS_FROM_SITE';
-- ⚠ 40 에도 'IO' 로 열리지만 FE 가 division(81 계열/82) × Sales Site 향 × FCST Type 3축으로 좁힌다.
--    판정식·근거 = `utils/forecast-price.asFromSite.ts` (AS-IS DMF0003_MktFcst.cs [E20260211-001189] 1:1).

PROMPT == 4-2. No.63-② 활성 판정 기준 콤보 (기대: FcstTypeWs USE_YN='Y' / SALES_TYPE_CODE2 4종)
SELECT SQL_ID, USE_YN FROM SCM_MGR.SCM_ADM_CMBO_SQL_M WHERE SQL_ID = 'FcstTypeWs';
SELECT COUNT(*) AS SALES_TYPE_CODE2_4 FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE = 'SALES_TYPE_CODE2' AND VALID_YN = 'Y';

PROMPT == 5. No.63 — 편집 measure 콤보 + 3분기 lookup (기대: 콤보 1건 / lookup 14건 이상)
SELECT COUNT(*) AS CMBO_FCSTPRICEEDITMEASURE FROM SCM_MGR.SCM_ADM_CMBO_SQL_M
 WHERE SQL_ID = 'FcstPriceEditMeasure';
SELECT LOOKUP_TYPE, COUNT(*) AS CNT FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE IN ('DM_UI_EDITABLE_MEASURE','GET_ADMIN_GROUP_MEASURE')
   AND (SEGMENT1 = 'DMF0082' OR SEGMENT2 = 'DMF0082')
 GROUP BY LOOKUP_TYPE ORDER BY 1;

PROMPT == 6. 신규 measure 가 division 81 원장에 실재하는가 (CUST_FCST > 0 이면 화면 산출 가능)
SELECT MEASURE, COUNT(*) AS CNT
  FROM SCM_MGR.DM_PLN_MKT_FCST_C
 WHERE DIVISION_ID = '81' AND QTY <> 0
   AND MEASURE IN ('CUST_FCST','RTF_SCP','TMM_FCST','IN_TRANSIT','VMI_DIO',
                   'AS_In_Req','AS_In_Plan','AS_Inv')
 GROUP BY MEASURE ORDER BY 2 DESC;
-- ⚠ TMM_FCST·IN_TRANSIT·VMI_DIO·AS_* 는 사내에서도 현행 버전 데이터가 없어 0행이 정상이다.
--    조인 경로는 열려 있으므로 원장에 데이터가 들어오면 자동 산출된다(명세 §3 참조).
