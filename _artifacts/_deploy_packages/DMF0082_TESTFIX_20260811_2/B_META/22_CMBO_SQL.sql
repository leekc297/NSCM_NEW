-- DMF0082 통합테스트 보완 — 콤보 SQL (No.63 3분기 등)
--   SQL_DTL_CTN 은 CLOB — 1800자 청크 누적 후 MERGE (ORA-01704 회피)
SET DEFINE OFF;

DECLARE
  v_sql CLOB;
BEGIN
  v_sql := 'SELECT 	DIVISION_ID AS CODE 	  , DIVISION_ID AS NAME FROM 	SCM_MST_DIVISION WHERE  (@divisionId IS NULL OR DIVISION_ID LIKE ''%'' || @divisionId || ''%'') 	OR (@divisionId IS NULL OR DIVISION_NAME LIKE ''%'' || @divisionId || ''%'') GROUP BY DIVISION_ID ORDER BY DIVISION_ID      ';
  MERGE INTO SCM_MGR.SCM_ADM_CMBO_SQL_M T
  USING (SELECT 'Division' SQL_ID FROM DUAL) S
     ON (T.SQL_ID = S.SQL_ID)
   WHEN MATCHED THEN UPDATE SET T.SQL_DTL_CTN = v_sql, T.SQL_NM = 'Division 조회', T.USE_YN = 'Y',
          T.LAST_UPDATED_BY = 'admin', T.LAST_UPDATE_DATE = SYSDATE
   WHEN NOT MATCHED THEN INSERT (SQL_ID, MDU_DIVS_CD, SQL_NM, SQL_DTL_CTN, USE_YN,
          CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
        VALUES ('Division', 'ALL', 'Division 조회', v_sql, 'Y', 'admin', SYSDATE, 'admin', SYSDATE);
END;
/

