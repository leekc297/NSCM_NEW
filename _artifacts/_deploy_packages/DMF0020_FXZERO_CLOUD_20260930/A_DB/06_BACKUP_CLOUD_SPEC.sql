--  05 를 구버전(BODY 만 보관)으로 이미 실행한 DB 에서 10 을 적용할 때만 사용. 05 신버전(SPEC+BODY 보관)을 처음 실행하는 DB 는 불요.
SET SERVEROUTPUT ON
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='BAK_SRC_DMF0020_FXZERO_SPEC';
  IF n = 0 THEN
    EXECUTE IMMEDIATE q'[CREATE TABLE BAK_SRC_DMF0020_FXZERO_SPEC AS
      SELECT NAME, TYPE, LINE, TEXT, SYSDATE AS BAK_DATE FROM USER_SOURCE WHERE NAME='PKG_DMF0020' AND TYPE='PACKAGE']';
    DBMS_OUTPUT.PUT_LINE('SPEC BACKUP CREATED');
  ELSE
    DBMS_OUTPUT.PUT_LINE('SPEC BACKUP EXISTS - SKIP');
  END IF;
END;
/
SELECT TYPE, COUNT(*) LINES FROM BAK_SRC_DMF0020_FXZERO_SPEC GROUP BY TYPE;
