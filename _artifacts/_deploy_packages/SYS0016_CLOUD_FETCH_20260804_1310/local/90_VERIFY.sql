-- 90_VERIFY.sql — 로컬(사내) 적용 후 검증 (조회 전용)
-- 기대값 = 클라우드 DISCOVER_&UI_ID..txt 의 [B]/[C]/[D] 결과와 1:1 대조
-- =============================================================================
DEFINE UI_ID = 'SYS0016'
SET PAGESIZE 200 LINESIZE 200

-- 1) 객체 존재/상태 — 기대: DISCOVER [B]+[C] 의 SCM_MGR 소유 객체 전부 VALID
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM ALL_OBJECTS
WHERE OWNER='SCM_MGR' AND OBJECT_NAME LIKE '%&UI_ID%'
ORDER BY OBJECT_TYPE, OBJECT_NAME;

-- 2) 컴파일 에러 — 기대: 0행
SELECT NAME, TYPE, LINE, TEXT FROM ALL_ERRORS
WHERE OWNER='SCM_MGR' AND NAME LIKE '%&UI_ID%' ORDER BY NAME, SEQUENCE;

-- 3) 배선 메타 카운트 — 기대: DISCOVER [D] 와 동일
SELECT 'MNU_M' T, COUNT(*) C FROM SCM_MGR.SCM_ADM_MNU_M WHERE MNU_ID='&UI_ID'
UNION ALL SELECT 'BTN_MPG', COUNT(*) FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID='&UI_ID'
UNION ALL SELECT 'API_M', COUNT(*) FROM SCM_MGR.SCM_ADM_API_M
  WHERE API_ID IN (SELECT API_ID FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID='&UI_ID')
UNION ALL SELECT 'USER_GR_MNU_MPG', COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_MPG_M WHERE MNU_ID='&UI_ID'
UNION ALL SELECT 'USER_GR_MNU_BTN_MPG', COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE MNU_ID='&UI_ID'
UNION ALL SELECT 'PROC_M', COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M
  WHERE PROC_NM IN (SELECT API_URL FROM SCM_MGR.SCM_ADM_API_M
                    WHERE API_ID IN (SELECT API_ID FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID='&UI_ID'))
UNION ALL SELECT 'SHEET_COLUMNS', COUNT(*) FROM SCM_MGR.SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID='&UI_ID'
UNION ALL SELECT 'SHEET_MEASURE', COUNT(*) FROM SCM_MGR.SCM_MST_SHEET_MEASURE WHERE PROGRAM_ID='&UI_ID';

-- 4) PROC_M positional 정합 — 기대: SP별 PROC_M 행수 = ALL_ARGUMENTS 인자수 (PLS-00306 차단)
--    (proc-meta-signature-match — PROC_NM 'PKG.PROC' 형식은 PACKAGE_NAME.OBJECT_NAME 결합 대조)
SELECT P.PROC_NM, COUNT(*) PROC_M_CNT,
       (SELECT COUNT(*) FROM ALL_ARGUMENTS A
         WHERE A.OWNER='SCM_MGR'
           AND NVL(A.PACKAGE_NAME || '.', '') || A.OBJECT_NAME = P.PROC_NM
           AND A.ARGUMENT_NAME IS NOT NULL) ARG_CNT
FROM SCM_MGR.SCM_ADM_PROC_M P
WHERE P.PROC_NM IN (SELECT API_URL FROM SCM_MGR.SCM_ADM_API_M
                    WHERE API_ID IN (SELECT API_ID FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID='&UI_ID'))
GROUP BY P.PROC_NM ORDER BY 1;

-- 5) SCMD_APP GRANT/SYNONYM — 기대: 배선 코드 객체 전부 존재
SELECT TABLE_NAME OBJ, PRIVILEGE FROM ALL_TAB_PRIVS
WHERE GRANTEE='SCMD_APP' AND TABLE_NAME LIKE '%&UI_ID%';
SELECT SYNONYM_NAME FROM ALL_SYNONYMS WHERE OWNER='SCMD_APP' AND SYNONYM_NAME LIKE '%&UI_ID%';

