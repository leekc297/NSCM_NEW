-- 01_DISCOVER_UI_OBJECTS.sql — 클라우드 Oracle 에서 sqlplus/SQLcl 로 실행
-- 목적: UI 기준 DB 객체 전수 발견 (4축) → DISCOVER_&UI_ID..txt 보고서
--   축A(권위): SCM_ADM_MNU_BTN_MPG_M(MNU_ID=UI) → API_M.API_URL → 배선 SP/PKG
--   축B(명칭): ALL_OBJECTS LIKE '%UI_ID%'
--   축C(폐포): 축A∪B 유닛의 ALL_DEPENDENCIES 재귀 (TABLE/GTT/SEQ/TYPE/VIEW/FN)
--   축D(메타): 배선 메타 8테이블 카운트
-- 재사용: DEFINE 2개만 바꾸면 다른 UI 에 그대로 사용 (hook cloud-ui-db-object-fetch)
-- =============================================================================
DEFINE UI_ID      = 'SYS0016'
DEFINE OWNER      = 'SCM_MGR'
DEFINE META_SINCE = '20260728'  -- MSG/LBL 신규 등록분 탐지 시작일 (클라우드 작업 시작일로 조정)

SET PAGESIZE 200 LINESIZE 200 TRIMSPOOL ON FEEDBACK OFF VERIFY OFF
SPOOL DISCOVER_&UI_ID..txt

PROMPT ===== [A] 메타 배선 기반 (권위 축) — BTN_MPG -> API_M =====
COLUMN SHT_NM FORMAT A22
COLUMN MNU_BTN_CD FORMAT A14
COLUMN API_ID FORMAT A32
COLUMN API_URL FORMAT A60
SELECT B.SHT_NM, B.MNU_BTN_CD, B.API_ID, A.API_TP_CD, A.API_URL
FROM   &OWNER..SCM_ADM_MNU_BTN_MPG_M B
LEFT JOIN &OWNER..SCM_ADM_API_M A ON A.API_ID = B.API_ID
WHERE  B.MNU_ID = '&UI_ID'
ORDER BY B.SHT_NM, B.MNU_BTN_CD;

PROMPT ===== [B] 명칭 기반 객체 =====
COLUMN OBJECT_NAME FORMAT A40
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS, TO_CHAR(CREATED,'YYYY-MM-DD HH24:MI') CREATED
FROM   ALL_OBJECTS
WHERE  OWNER = '&OWNER' AND OBJECT_NAME LIKE '%&UI_ID%'
ORDER BY OBJECT_TYPE, OBJECT_NAME;

PROMPT ===== [C] 직접 의존 1단 (축A+B 유닛 -> 참조 객체; SYS/표준 제외) =====
PROMPT ===== (전체 폐포는 02_EXTRACT_DDL 이 BFS 로 산출 — 재귀 CTE 는 경로 폭발 hang 으로 금지, 2026-08-04) =====
WITH units (NAME) AS (
    SELECT DISTINCT REGEXP_SUBSTR(A.API_URL, '[^.]+', 1, 1)
    FROM   &OWNER..SCM_ADM_MNU_BTN_MPG_M B
    JOIN   &OWNER..SCM_ADM_API_M A ON A.API_ID = B.API_ID
    WHERE  B.MNU_ID = '&UI_ID' AND A.API_URL IS NOT NULL
    UNION
    SELECT OBJECT_NAME FROM ALL_OBJECTS
    WHERE  OWNER='&OWNER' AND OBJECT_NAME LIKE '%&UI_ID%'
    AND    OBJECT_TYPE IN ('PACKAGE','PACKAGE BODY','PROCEDURE','FUNCTION','TRIGGER')
)
SELECT DISTINCT D.REFERENCED_OWNER OWNER, D.REFERENCED_NAME NAME, D.REFERENCED_TYPE TYPE,
       NVL((SELECT MAX(T.TEMPORARY) FROM ALL_TABLES T
            WHERE T.OWNER=D.REFERENCED_OWNER AND T.TABLE_NAME=D.REFERENCED_NAME),'-') GTT_YN
FROM   ALL_DEPENDENCIES D JOIN units U ON D.NAME = U.NAME
WHERE  D.OWNER = '&OWNER' AND D.REFERENCED_OWNER NOT IN ('SYS','PUBLIC','SYSTEM')
ORDER BY TYPE, NAME;

PROMPT ===== [D] 배선 메타 카운트 (로컬 90_VERIFY 대조 기준값) =====
SELECT 'MNU_M' T, COUNT(*) C FROM &OWNER..SCM_ADM_MNU_M WHERE MNU_ID='&UI_ID'
UNION ALL SELECT 'BTN_MPG', COUNT(*) FROM &OWNER..SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID='&UI_ID'
UNION ALL SELECT 'API_M', COUNT(*) FROM &OWNER..SCM_ADM_API_M
  WHERE API_ID IN (SELECT API_ID FROM &OWNER..SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID='&UI_ID')
UNION ALL SELECT 'USER_GR_MNU_MPG', COUNT(*) FROM &OWNER..SCM_ADM_USER_GR_MNU_MPG_M WHERE MNU_ID='&UI_ID'
UNION ALL SELECT 'USER_GR_MNU_BTN_MPG', COUNT(*) FROM &OWNER..SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE MNU_ID='&UI_ID'
UNION ALL SELECT 'PROC_M', COUNT(*) FROM &OWNER..SCM_ADM_PROC_M
  WHERE PROC_NM IN (SELECT API_URL FROM &OWNER..SCM_ADM_API_M
                    WHERE API_ID IN (SELECT API_ID FROM &OWNER..SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID='&UI_ID'))
UNION ALL SELECT 'SHEET_COLUMNS', COUNT(*) FROM &OWNER..SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID='&UI_ID'
UNION ALL SELECT 'SHEET_MEASURE', COUNT(*) FROM &OWNER..SCM_MST_SHEET_MEASURE WHERE PROGRAM_ID='&UI_ID';

PROMPT ===== [D-2] MSG/LBL 후보 (작업 기간 신규 등록분 — 03 스크립트 DEFINE 과 동일 기준) =====
SELECT MSG_ID, MSG_TP_CD, LANG_CD, CREATED_BY, TO_CHAR(CREATION_DATE,'YYYY-MM-DD') DT
FROM   &OWNER..SCM_ADM_MSG_M
WHERE  CREATION_DATE >= TO_DATE('&META_SINCE','YYYYMMDD')
ORDER BY MSG_ID, LANG_CD;

