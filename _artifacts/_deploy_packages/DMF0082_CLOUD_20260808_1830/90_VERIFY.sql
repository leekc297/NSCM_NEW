-- ── A. UICATEGORY (2026-08-07) ─────────────────────────────────────────────────────
-- [A1] PKG 컴파일 (기대: PACKAGE / PACKAGE BODY 모두 VALID)
SELECT OBJECT_TYPE, STATUS FROM ALL_OBJECTS
WHERE  OWNER='SCM_MGR' AND OBJECT_NAME='PKG_DMF0082';

-- [A2] GTT 컬럼 수 (기대: GT_DMF0082_MF_SP=79 / GTT_MF_SP=72)
SELECT TABLE_NAME, COUNT(*) COLS FROM ALL_TAB_COLUMNS
WHERE  OWNER='SCM_MGR' AND TABLE_NAME IN ('GT_DMF0082_MF_SP','GTT_MF_SP') GROUP BY TABLE_NAME;

-- [A3] SPEC 신규 파라미터 (기대: 4종 존재)
SELECT OBJECT_NAME, ARGUMENT_NAME FROM ALL_ARGUMENTS
WHERE  OWNER='SCM_MGR' AND PACKAGE_NAME='PKG_DMF0082'
AND    ARGUMENT_NAME IN ('P_PROJECT_CODE','P_OWNER','P_SENDER_CODE','P_AS_FROM_SITE')
ORDER BY 1, POSITION;

-- [A4] PROC_M (기대: GET 22 / CURRENT 22 / SAVE 18)
SELECT PROC_NM, COUNT(*) CNT FROM SCM_MGR.SCM_ADM_PROC_M
WHERE  PROC_NM IN ('PKG_DMF0082.P_DMF0082_GET_MAIN_DATA',
                   'PKG_DMF0082.P_DMF0082_GET_MAIN_DATA_CURRENT',
                   'PKG_DMF0082.P_DMF0082_SAVE_MAIN_DATA')
GROUP BY PROC_NM ORDER BY 1;

-- [A5] SHEET_COLUMNS (기대: TOTAL 61 / D40 49 / D81 42 / D82 41)
SELECT COUNT(*) TOTAL,
       SUM(CASE WHEN ','||DIVISION_ID||',' LIKE '%,40,%' THEN 1 ELSE 0 END) D40,
       SUM(CASE WHEN ','||DIVISION_ID||',' LIKE '%,81,%' THEN 1 ELSE 0 END) D81,
       SUM(CASE WHEN ','||DIVISION_ID||',' LIKE '%,82,%' THEN 1 ELSE 0 END) D82
FROM   SCM_MGR.SCM_MST_SHEET_COLUMNS
WHERE  PROGRAM_ID='DMF0082' AND SHEET_NAME='FcstNPrice';

-- [A6] 필수 키 5컬럼 토큰 (기대: 5행 전부 '40,81,81_UC,81_HM,81_ST,81_HD,81_HG,82')
SELECT COLUMN_NAME, DIVISION_ID FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
WHERE  PROGRAM_ID='DMF0082' AND SHEET_NAME='FcstNPrice'
AND    COLUMN_NAME IN ('DIVISION_ID','END_CUSTOMER','SCM_SITE_ID','ITEM_ID','CELL_PROD_SITE_ID')
ORDER BY SORT_ORDER_NO;

-- [A7] W/S 지원 (기대: CMBO 1 / FCST_TYPE 셀 = FcstTypeByUserGroupDMF0082 / W/S measure 6)
SELECT (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_CMBO_SQL_M WHERE SQL_ID='FcstTypeByUserGroupDMF0082') CMBO,
       (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
         WHERE LOOKUP_TYPE='GET_ADMIN_GROUP_MEASURE' AND SEGMENT1='DM Planner (W/S)'
           AND SEGMENT2='DMF0082') WS_MEASURE,
       (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_CMBO_SQL_M WHERE SQL_ID='FcstPriceUserAuthGroup') AUTH_GRP
FROM DUAL;

-- ── B. UP_FX 정합 (2026-08-08) ─────────────────────────────────────────────────────
-- [B1] CMBO DefaultBucketDay (기대: 1)
SELECT COUNT(*) DEFAULTBUCKETDAY FROM SCM_MGR.SCM_ADM_CMBO_SQL_M WHERE SQL_ID='DefaultBucketDay';

-- [B2] DefaultBucketDay 치환 실행 — 사내 실측: 40/W=MON · 81/M=FRI · 82/D=FRI
SELECT '40' DIV, 'W' BKT, L.SEGMENT3 CODE FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL L
WHERE  L.LOOKUP_TYPE='DEFAULT_BUCKET_DAY' AND L.VALID_YN='Y' AND L.SEGMENT1='40'
AND    L.SEGMENT2 = CASE WHEN 'W' IN ('D','DAILY','M','MONTHLY') THEN 'MONTHLY' ELSE 'WEEKLY' END
UNION ALL
SELECT '81','M', L.SEGMENT3 FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL L
WHERE  L.LOOKUP_TYPE='DEFAULT_BUCKET_DAY' AND L.VALID_YN='Y' AND L.SEGMENT1='81'
AND    L.SEGMENT2 = CASE WHEN 'M' IN ('D','DAILY','M','MONTHLY') THEN 'MONTHLY' ELSE 'WEEKLY' END
UNION ALL
SELECT '82','D', L.SEGMENT3 FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL L
WHERE  L.LOOKUP_TYPE='DEFAULT_BUCKET_DAY' AND L.VALID_YN='Y' AND L.SEGMENT1='82'
AND    L.SEGMENT2 = CASE WHEN 'D' IN ('D','DAILY','M','MONTHLY') THEN 'MONTHLY' ELSE 'WEEKLY' END;

-- [B3] 권한 변형 이식 (기대: 3행 전부 GET_ADMIN_GROUP 보유)
SELECT SQL_ID,
       CASE WHEN UPPER(SQL_DTL_CTN) LIKE '%GET_ADMIN_GROUP%' THEN 'O' ELSE '⛔ X' END AS GAG
FROM   SCM_MGR.SCM_ADM_CMBO_SQL_M
WHERE  SQL_ID IN ('TeambyDivisionAuth','SiteByEndCustomerAuth','EndCustomerByDivisionDeptAuth')
ORDER BY 1;

-- [B4] 리터럴 축소 잔존 탐지 (기대: **0건**)
SELECT SQL_ID FROM SCM_MGR.SCM_ADM_CMBO_SQL_M
WHERE  REGEXP_LIKE(UPPER(SQL_DTL_CTN), 'USER_GR_ID\s*=\s*''ADMIN''')
AND    UPPER(SQL_DTL_CTN) NOT LIKE '%GET_ADMIN_GROUP%';

-- ── 공통 회귀 ───────────────────────────────────────────────────────────────────────
-- [3] ⭐ 공유 CMBO 소비 시트 수 — 00_PRECHECK [1-1] 과 **완전히 동일**해야 한다
--     (본 패키지는 시트 메타의 CELL_COMBO_DATA_TYPE 을 바꾸지 않는다. 줄었다면 잘못 적용 → 즉시 원복)
SELECT CELL_COMBO_DATA_TYPE, COUNT(DISTINCT PROGRAM_ID || '|' || SHEET_NAME) AS SHEETS
FROM   SCM_MGR.SCM_MST_SHEET_COLUMNS
WHERE  CELL_COMBO_DATA_TYPE IN ('Incoterms','DOM_EXP','DeptId') AND NVL(VALID_YN,'Y')='Y'
GROUP BY CELL_COMBO_DATA_TYPE ORDER BY 1;

-- [4] DMF0082 셀 콤보 배선 무변경 (기대: INCOTERMS=Incoterms / DOM_EXP=DOM_EXP / TEAM_ID=DeptId)
--     편집판 교체는 **FE 스왑**이므로 메타는 표시용 그대로여야 한다.
SELECT COLUMN_NAME, CELL_COMBO_DATA_TYPE FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
WHERE  PROGRAM_ID='DMF0082' AND SHEET_NAME='FcstNPrice'
AND    COLUMN_NAME IN ('INCOTERMS','DOM_EXP','TEAM_ID','MEASURE','CELL_PROD_SITE_ID',
                       'SCM_SITE_ID','PLANT_SITE_ID')
ORDER BY 1;

-- [5] TITLESET (05 재시드 직후 기대 0 — 이후 사용자 조회마다 증가 = 자동 재시드 정상)
SELECT COUNT(*) TITLESET FROM SCM_MGR.SCM_MST_TITLESET_USER
WHERE  PROGRAM_ID='DMF0082' AND SHEET_NAME='FcstNPrice';

