-- 원천: 사내 OCGSCMD_P01 라이브 덤프 (본문 무수정)


-- V1) 객체 VALID (기대: 8행 전부 VALID)
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM ALL_OBJECTS WHERE OWNER='SCM_MGR'
 AND OBJECT_NAME IN ('PKG_DMF0000','PKG_DMF0020','PKG_DMF0082','PR_SCM_MST_EXCHANGE_RATE','PR_SCM_MST_EXCHANGE_RATE_UI')
 ORDER BY 1,2;

-- V2) -8 가드·-12/-13 마커 (기대: 전부 >= 1)
SELECT 'PKG_DMF0020: 12841 guard' CHK, COUNT(*) CNT, CASE WHEN COUNT(*)>=1 THEN 'PASS' ELSE 'FAIL' END R
  FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0020' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%-12841%'
UNION ALL SELECT 'V#10 52주 게이트(FCSTNAME 정정)', COUNT(*), CASE WHEN COUNT(*)>=1 THEN 'PASS' ELSE 'FAIL' END
  FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%E20260814-FCSTNAME%'
UNION ALL SELECT 'V#11 RMA 음수', COUNT(*), CASE WHEN COUNT(*)>=1 THEN 'PASS' ELSE 'FAIL' END
  FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%RMA%음수값만%'
UNION ALL SELECT 'V#12 비RMA 음수 차단', COUNT(*), CASE WHEN COUNT(*)>=1 THEN 'PASS' ELSE 'FAIL' END
  FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%정수값만 입력가능%'
UNION ALL SELECT 'V#13 QTYKEY(9축 키 필터)', COUNT(*), CASE WHEN COUNT(*)>=2 THEN 'PASS' ELSE 'FAIL' END
  FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%E20260831-QTYKEY%';

-- V3) V#10 룩업 arm (기대: MEASURE>=4, FCST_TYPE>=6)
SELECT SEGMENT1, COUNT(*) CNT FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE='MKT_FCST_VALIDATION_PRICE' AND VALID_YN='Y' GROUP BY SEGMENT1;

-- V4) -9 배선 체인 (기대: GRANT SCMP_APP 2 / 시노님 2 / API 1 / PROC_M 2 / BTN 1 / 권한 2)
SELECT 'GRANT' CHK, COUNT(*) CNT FROM ALL_TAB_PRIVS WHERE TABLE_SCHEMA='SCM_MGR' AND GRANTEE='SCMP_APP'
   AND TABLE_NAME IN ('PR_SCM_MST_EXCHANGE_RATE','PR_SCM_MST_EXCHANGE_RATE_UI') AND PRIVILEGE='EXECUTE'
UNION ALL SELECT '시노님', COUNT(*) FROM ALL_SYNONYMS WHERE OWNER='SCMP_APP'
   AND TABLE_NAME IN ('PR_SCM_MST_EXCHANGE_RATE','PR_SCM_MST_EXCHANGE_RATE_UI')
UNION ALL SELECT 'API_M', COUNT(*) FROM SCM_MGR.SCM_ADM_API_M WHERE API_ID='DMF0082_futurePriceInfo_IF' AND USE_YN='Y'
UNION ALL SELECT 'PROC_M', COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M WHERE PROC_NM='PR_SCM_MST_EXCHANGE_RATE_UI'
UNION ALL SELECT 'BTN_MPG', COUNT(*) FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID='DMF0082' AND SHT_NM='futurePriceInfo' AND MNU_BTN_CD='IF'
UNION ALL SELECT 'GR_BTN', COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE MNU_ID='DMF0082' AND SHT_NM='futurePriceInfo' AND MNU_BTN_CD='IF';

-- V5) PROC_M ↔ ALL_ARGUMENTS 위치·이름 대조 (기대: 0행)
SELECT A.POSITION, A.ARGUMENT_NAME, P.COL_NM
  FROM ALL_ARGUMENTS A FULL OUTER JOIN SCM_MGR.SCM_ADM_PROC_M P
    ON P.PROC_NM='PR_SCM_MST_EXCHANGE_RATE_UI' AND P.SORT_ORD=A.POSITION
 WHERE A.OWNER='SCM_MGR' AND A.OBJECT_NAME='PR_SCM_MST_EXCHANGE_RATE_UI'
   AND (P.COL_NM IS NULL OR A.ARGUMENT_NAME IS NULL);

-- V6) -13 양성 테스트 (세션 GTT 모의행 — 실데이터 무접촉. 기대: V11=1, V12=1 출력)
SET SERVEROUTPUT ON
DECLARE n11 PLS_INTEGER; n12 PLS_INTEGER;
BEGIN
  INSERT INTO SCM_MGR.GT_PRDM1_T_MAIN (DIVISION_ID, FCST_TYPE, MEASURE, QTY_PRICE) VALUES ('40','RMA','MKT_FCST',100);
  INSERT INTO SCM_MGR.GT_PRDM1_T_MAIN (DIVISION_ID, FCST_TYPE, MEASURE, QTY_PRICE) VALUES ('40','Mass','MKT_FCST',-5);
  SELECT COUNT(*) INTO n11 FROM SCM_MGR.GT_PRDM1_T_MAIN
   WHERE FCST_TYPE='RMA' AND MEASURE IN ('MKT_FCST','SCM_FCST') AND NVL(CAST(QTY_PRICE AS NUMBER(30,10)),0) > 0;
  SELECT COUNT(*) INTO n12 FROM SCM_MGR.GT_PRDM1_T_MAIN
   WHERE FCST_TYPE <> 'RMA' AND NVL(CAST(QTY_PRICE AS NUMBER(30,10)),0) < 0;
  DBMS_OUTPUT.PUT_LINE('V11(RMA 양수 적발)='||n11||' V12(비RMA 음수 적발)='||n12||' -> '||
    CASE WHEN n11=1 AND n12=1 THEN 'PASS' ELSE 'FAIL' END);
  ROLLBACK;
END;
