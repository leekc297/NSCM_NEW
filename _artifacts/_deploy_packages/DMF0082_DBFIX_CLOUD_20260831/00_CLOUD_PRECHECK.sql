-- 패키지: DMF0082_DBFIX_CLOUD_20260831 / 마커 E20260831-DBFIX4
-- 원천: 사내 OCGSCMD_P01 라이브 덤프 (본문 무수정)


-- [A] 대상 객체 현행 상태 (적용 전 스냅샷)
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI') LDDL
  FROM ALL_OBJECTS WHERE OWNER='SCM_MGR'
   AND OBJECT_NAME IN ('PKG_DMF0000','PKG_DMF0020','PKG_DMF0082','PR_SCM_MST_EXCHANGE_RATE','PR_SCM_MST_EXCHANGE_RATE_UI')
 ORDER BY OBJECT_NAME, OBJECT_TYPE;

-- [B] -8 가드/-12/-13 마커 현행 세대 판정 (0 = 구본 → 본 패키지 적용 필요)
SELECT 'PKG_DMF0020: 12841 guard' CHK, COUNT(*) CNT FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0020' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%-12841%'
UNION ALL SELECT 'PKG_DMF0082: E20260814-FCSTNAME', COUNT(*) FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%E20260814-FCSTNAME%'
UNION ALL SELECT 'PKG_DMF0082: V#11 RMA 음수', COUNT(*) FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%RMA%음수값만%'
UNION ALL SELECT 'PKG_DMF0082: V#12 정수값', COUNT(*) FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%정수값만 입력가능%'
UNION ALL SELECT '룩업 MEASURE arm (V#10)', COUNT(*) FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE='MKT_FCST_VALIDATION_PRICE' AND SEGMENT1='MEASURE' AND VALID_YN='Y';

-- [C] -8 실오류 실측 (최근 14일 — SQL Error 의 정체 확정. 반드시 결과 확보 후 적용)
SELECT TO_CHAR(CREATION_DATE,'MM-DD HH24:MI') DT, PROGRAM_NAME, SQL_ERR_CODE,
       SUBSTR(SQL_ERR_MSG,1,200) ERR, SUBSTR(SQL_BACKTRACE,1,150) BT
  FROM SCM_MGR.SCM_SYS_LOG_BATCH
 WHERE PROGRAM_NAME IN ('PKG_DMF0000','PKG_DMF0020','PKG_DMF0082') AND LOG_TYPE='ERROR'
   AND CREATION_DATE >= SYSDATE-14 ORDER BY CREATION_DATE DESC FETCH FIRST 30 ROWS ONLY;

-- [D] 외부 의존 객체 실존 (누락 = PLS-00201 — 결과에 MISSING 있으면 적용 중단·보고)
SELECT X.NM, NVL(O.STATUS,'MISSING') STATUS FROM (
  SELECT COLUMN_VALUE NM FROM TABLE(SYS.ODCIVARCHAR2LIST('FN_GET_DEPT_LIST','FN_GET_DIVISION_YN','FN_GET_MULTI_OWNER_NAME','FN_MULTY_TIME','FN_NEXT_DAY','FN_STRING_SPLIT','PKG_DMF0003','PKG_DMF0020_GTT_DDL','PKG_DMF0074','PKG_DMF0200','PR_DETAIL_AUTO','PR_DM_ANL_SALES_PLAN_AMT_CREATE_LOCAL_KRW','PR_DM_ANL_SALES_PLAN_AMT_CREATE_LOCAL_KRW_SINGLE','PR_DM_ANL_SALES_PRICE_HIST','PR_DM_DNM_EDI_CALLOFF_STATUS','PR_DM_PLN_CFM_TO_MKT_FCST','PR_DM_PLN_MKT_FCST_SALES_RESULT_MAPPING','PR_DM_SYS_LOG_BATCH'))
) X LEFT JOIN (SELECT OBJECT_NAME, MAX(STATUS) STATUS FROM ALL_OBJECTS WHERE OWNER='SCM_MGR' GROUP BY OBJECT_NAME) O
  ON O.OBJECT_NAME = X.NM ORDER BY 2 DESC, 1;

-- [E] V11: 메뉴 행 + (샘플) 권한 뷰 (hook #148)
SELECT 'MNU_M row' CHK, COUNT(*) CNT FROM SCM_MGR.SCM_ADM_MNU_M WHERE MNU_ID='DMF0082' AND USE_YN='Y';

-- [F] GTT/SEQ 존재 판정 (본 패키지는 GTT DDL 미동봉 — 기존 패키지 기이관 전제. MISSING 시 중단·보고)
--     스윕 원천: 동봉 PKG 2본 + PROC 2본 본문 기계 추출
SELECT X.NM, CASE WHEN T.TABLE_NAME IS NOT NULL THEN 'OK' ELSE 'MISSING' END STATUS
FROM (
  SELECT COLUMN_VALUE NM FROM TABLE(SYS.ODCIVARCHAR2LIST(
    'GT_D000_RESULTS','GT_F020_FUTURE_PRICE_TEMP2','GT_F020_CFM_SELLING_PRICE_TEMP2',
    'GT_PRDM1_T_MAIN','GT_PRDM1_T_PRICE','GT_PRDM1_MSHYCHU1','GT_PRDM1_MSHYCHU2'))
) X LEFT JOIN ALL_TABLES T ON T.OWNER='SCM_MGR' AND T.TABLE_NAME=X.NM ORDER BY 2 DESC, 1;
SELECT 'SEQ1_DM_MST_EXCHANGE_RATE' NM,
       CASE WHEN COUNT(*)>0 THEN 'OK' ELSE 'MISSING' END STATUS
  FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER='SCM_MGR' AND SEQUENCE_NAME='SEQ1_DM_MST_EXCHANGE_RATE';

-- [G] PR_SCM_MST_EXCHANGE_RATE 세대 판정 — REPOINT(PKG 멤버 호출) 여부 (0 = 구본 → 03 적용 필수)
SELECT 'base REPOINT(PKG_DMF0020 호출)' CHK, COUNT(*) CNT FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PR_SCM_MST_EXCHANGE_RATE' AND TYPE='PROCEDURE'
   AND TEXT LIKE '%PKG_DMF0020.%';
