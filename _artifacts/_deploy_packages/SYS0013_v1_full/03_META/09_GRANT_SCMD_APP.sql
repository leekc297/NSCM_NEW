-- SYS0013 SCMD_APP 권한 (BE 사용계정)
-- ⚠ 신규 화면 작성 시 반드시 SCM_MGR (DDL owner) 에서 실행
-- ⚠ 누락 시 BE 호출 -9994 'Sql Error' (PLS-00201 권한없음)

-- 1) SP EXECUTE GRANT + PUBLIC SYNONYM
GRANT EXECUTE ON SCM_MGR.P_SCM0005_EXECUTE_QUERY TO SCMD_APP;
CREATE OR REPLACE SYNONYM SCMD_APP.P_SCM0005_EXECUTE_QUERY FOR SCM_MGR.P_SCM0005_EXECUTE_QUERY;
GRANT EXECUTE ON SCM_MGR.P_SCM0005_GET_COLUMNS TO SCMD_APP;
CREATE OR REPLACE SYNONYM SCMD_APP.P_SCM0005_GET_COLUMNS FOR SCM_MGR.P_SCM0005_GET_COLUMNS;
GRANT EXECUTE ON SCM_MGR.P_SCM0005_GET_HISTORY TO SCMD_APP;
CREATE OR REPLACE SYNONYM SCMD_APP.P_SCM0005_GET_HISTORY FOR SCM_MGR.P_SCM0005_GET_HISTORY;
GRANT EXECUTE ON SCM_MGR.P_SCM0005_GET_PARAMETERS TO SCMD_APP;
CREATE OR REPLACE SYNONYM SCMD_APP.P_SCM0005_GET_PARAMETERS FOR SCM_MGR.P_SCM0005_GET_PARAMETERS;
GRANT EXECUTE ON SCM_MGR.P_SCM0005_GET_QUERY_LIST TO SCMD_APP;
CREATE OR REPLACE SYNONYM SCMD_APP.P_SCM0005_GET_QUERY_LIST FOR SCM_MGR.P_SCM0005_GET_QUERY_LIST;
GRANT EXECUTE ON SCM_MGR.P_SCM0005_SAVE_COLUMNS TO SCMD_APP;
CREATE OR REPLACE SYNONYM SCMD_APP.P_SCM0005_SAVE_COLUMNS FOR SCM_MGR.P_SCM0005_SAVE_COLUMNS;
GRANT EXECUTE ON SCM_MGR.P_SCM0005_SAVE_PARAMETERS TO SCMD_APP;
CREATE OR REPLACE SYNONYM SCMD_APP.P_SCM0005_SAVE_PARAMETERS FOR SCM_MGR.P_SCM0005_SAVE_PARAMETERS;
GRANT EXECUTE ON SCM_MGR.P_SCM0005_SAVE_QUERY TO SCMD_APP;
CREATE OR REPLACE SYNONYM SCMD_APP.P_SCM0005_SAVE_QUERY FOR SCM_MGR.P_SCM0005_SAVE_QUERY;

-- 3) 검증
SELECT GRANTEE, PRIVILEGE, TABLE_NAME FROM DBA_TAB_PRIVS
 WHERE GRANTEE='SCMD_APP' AND OWNER='SCM_MGR' AND TABLE_NAME LIKE '%SYS0013%'
 ORDER BY TABLE_NAME, PRIVILEGE;
