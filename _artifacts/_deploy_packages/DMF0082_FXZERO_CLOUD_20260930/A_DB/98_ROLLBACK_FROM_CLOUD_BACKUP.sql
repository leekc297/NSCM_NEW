-- 98_ROLLBACK_FROM_CLOUD_BACKUP.sql — 05 보관본으로 SPEC→BODY 복원 (롤백 전용) [E20260930-DMF0082FXZERO]
SET SERVEROUTPUT ON
DECLARE
  v CLOB;
BEGIN
  FOR t IN (SELECT 'PACKAGE' TYP FROM DUAL UNION ALL SELECT 'PACKAGE BODY' FROM DUAL) LOOP
    DBMS_LOB.CREATETEMPORARY(v, TRUE);
    FOR r IN (SELECT TEXT FROM BAK_SRC_DMF0082_FXZERO WHERE NAME='PKG_DMF0082' AND TYPE=t.TYP ORDER BY LINE) LOOP
      DBMS_LOB.APPEND(v, r.TEXT);
    END LOOP;
    IF DBMS_LOB.GETLENGTH(v) > 0 THEN
      EXECUTE IMMEDIATE 'CREATE OR REPLACE ' || v;
      DBMS_OUTPUT.PUT_LINE('REBUILT ' || t.TYP);
    ELSE
      DBMS_OUTPUT.PUT_LINE('SKIP ' || t.TYP || ' (no backup)');
    END IF;
    DBMS_LOB.FREETEMPORARY(v);
  END LOOP;
END;
/
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0082';
