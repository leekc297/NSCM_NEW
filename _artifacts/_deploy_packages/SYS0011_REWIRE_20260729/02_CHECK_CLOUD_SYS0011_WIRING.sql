PROMPT === [1] SYS0011 메뉴 등록 상태 ===
SELECT MNU_ID, MNU_URL, MNU_TP_CD, USE_YN
  FROM SCM_ADM_MNU_M
 WHERE MNU_ID = 'SYS0011';

PROMPT === [2] SYS0011 버튼 배선 (BTN_MPG 전 행 — 사내는 9행: 정규 6 + myAuth ADD/REQUEST/DELETE 3) ===
SELECT MNU_ID, SHT_NM, MNU_BTN_CD, API_ID, USE_YN
  FROM SCM_ADM_MNU_BTN_MPG_M
 WHERE MNU_ID = 'SYS0011'
 ORDER BY SHT_NM, MNU_BTN_CD;

PROMPT === [3] SYS0011 관련 API 정의 (SYS0011% + SCM0008%) — API_URL 이 무엇을 지향하는지 ===
SELECT API_ID, API_TP_CD, API_URL, USE_YN, LAST_UPDATED_BY,
       TO_CHAR(LAST_UPDATE_DATE, 'YYYY-MM-DD') UPD
  FROM SCM_ADM_API_M
 WHERE API_ID LIKE 'SYS0011%' OR API_ID LIKE '%SCM0008%'
 ORDER BY API_ID;

PROMPT === [4] [2]의 버튼이 가리키는 API 의 URL 첫 토큰(SP/PKG) 실체 존재 여부 — EXISTS='N' 행 = dangling ===
WITH btn_api AS (
    SELECT DISTINCT b.API_ID, a.API_URL,
           UPPER(REGEXP_SUBSTR(a.API_URL, '^[^.]+')) AS ROOT_NAME
      FROM SCM_ADM_MNU_BTN_MPG_M b
      JOIN SCM_ADM_API_M a ON a.API_ID = b.API_ID
     WHERE b.MNU_ID = 'SYS0011'
)
SELECT b.API_ID, b.API_URL, b.ROOT_NAME,
       NVL((SELECT MAX('Y') FROM ALL_OBJECTS o
             WHERE o.OBJECT_NAME = b.ROOT_NAME
               AND o.OBJECT_TYPE IN ('PACKAGE', 'PROCEDURE', 'FUNCTION')), 'N') AS EXISTS_REAL,
       NVL((SELECT MAX(o.OWNER || ':' || o.OBJECT_TYPE) FROM ALL_OBJECTS o
             WHERE o.OBJECT_NAME = b.ROOT_NAME
               AND o.OBJECT_TYPE IN ('PACKAGE', 'PROCEDURE', 'FUNCTION', 'SYNONYM')), '(없음)') AS FOUND_AS
  FROM btn_api b
 ORDER BY b.API_ID;

PROMPT === [5] PKG 멤버 대조 — API_URL 이 PKG.멤버 형식인 경우 멤버 실존 여부 ===
SELECT OBJECT_NAME PKG, PROCEDURE_NAME MEMBER_NAME
  FROM ALL_PROCEDURES
 WHERE OBJECT_NAME = 'PKG_SYS0011'
 ORDER BY SUBPROGRAM_ID;

PROMPT === [6] PROC_M 메타 — 위 API_URL 들의 파라미터 정의 존재 여부 (generic call-proc 필수) ===
SELECT PROC_NM, COL_NM, COL_TP_CD, SORT_ORD
  FROM SCM_ADM_PROC_M
 WHERE PROC_NM IN (SELECT API_URL FROM SCM_ADM_API_M
                    WHERE API_ID IN (SELECT API_ID FROM SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID = 'SYS0011'))
    OR PROC_NM LIKE 'PKG_SYS0011.%'
    OR PROC_NM LIKE 'P_SCM0008%'
 ORDER BY PROC_NM, TO_NUMBER(SORT_ORD);

PROMPT === [7] PKG_SYS0011 상태 + GRANT/SYNONYM (app 계정 실행 가능 여부) ===
SELECT OWNER, OBJECT_NAME, OBJECT_TYPE, STATUS
  FROM ALL_OBJECTS
 WHERE OBJECT_NAME = 'PKG_SYS0011'
 ORDER BY OWNER, OBJECT_TYPE;

SELECT TABLE_NAME OBJ, GRANTEE, PRIVILEGE
  FROM ALL_TAB_PRIVS
 WHERE TABLE_NAME = 'PKG_SYS0011'
 ORDER BY GRANTEE;

