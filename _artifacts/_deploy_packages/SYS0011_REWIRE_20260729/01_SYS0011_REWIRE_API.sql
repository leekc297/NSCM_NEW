-- =============================================================================
-- 01_SYS0011_REWIRE_API.sql — SYS0011 버튼 3종(ADD/REQUEST/DELETE) 재배선
-- 대상: SCM_ADM_API_M 3행 (API_SCM0008_ADD/REQUEST/DELETE_MY_AUTH)
--   변경: API_URL 'P_SCM0008_*'(미존재 dangling) → 'PKG_SYS0011.P_SYS0011_SAVE_MY_AUTH_DATA'
--         API_TP_CD 'POST' → 'PROC_SAVE' (기존 SYS0011_SAVE_MY_AUTH_DATA 와 동일 타입)
-- 근거: 사용자 확정 2026-07-29 "PKG_SYS0011 로 재배선"
--   - FE auth-request ROW_STATUS ADD='I'/REQUEST='M'/DELETE='D' → 단일 SAVE SP 로 전달 구조
--   - PROC_M 'PKG_SYS0011.P_SYS0011_SAVE_MY_AUTH_DATA' 기존재 (data/sesUserId/O_RESULT_CURSOR)
-- 멱등: 이미 재배선된 행은 0 rows updated. BTN_MPG/PROC_M 무변경.
-- =============================================================================
SET SERVEROUTPUT ON

PROMPT === BEFORE (3행 기대) ===
SELECT API_ID, API_TP_CD, API_URL, LAST_UPDATED_BY
  FROM SCM_ADM_API_M
 WHERE API_ID IN ('API_SCM0008_ADD_MY_AUTH', 'API_SCM0008_REQUEST_AUTH', 'API_SCM0008_DELETE_MY_AUTH');

UPDATE SCM_ADM_API_M
   SET API_URL          = 'PKG_SYS0011.P_SYS0011_SAVE_MY_AUTH_DATA',
       API_TP_CD        = 'PROC_SAVE',
       LAST_UPDATED_BY  = 'admin',
       LAST_UPDATE_DATE = SYSDATE
 WHERE API_ID IN ('API_SCM0008_ADD_MY_AUTH', 'API_SCM0008_REQUEST_AUTH', 'API_SCM0008_DELETE_MY_AUTH')
   AND (API_URL <> 'PKG_SYS0011.P_SYS0011_SAVE_MY_AUTH_DATA' OR API_TP_CD <> 'PROC_SAVE');

COMMIT;

PROMPT === AFTER (3행 모두 PKG_SYS0011.P_SYS0011_SAVE_MY_AUTH_DATA / PROC_SAVE 기대) ===
SELECT API_ID, API_TP_CD, API_URL, LAST_UPDATED_BY, TO_CHAR(LAST_UPDATE_DATE,'YYYY-MM-DD HH24:MI') UPD
  FROM SCM_ADM_API_M
 WHERE API_ID IN ('API_SCM0008_ADD_MY_AUTH', 'API_SCM0008_REQUEST_AUTH', 'API_SCM0008_DELETE_MY_AUTH');

PROMPT === 정합 검증: 잔여 dangling(P_SCM0008_* 지향 API) 0행 기대 — GET 4행은 축외로 별도(무변경) ===
SELECT API_ID, API_URL
  FROM SCM_ADM_API_M
 WHERE API_URL LIKE 'P_SCM0008%'
   AND API_ID IN ('API_SCM0008_ADD_MY_AUTH', 'API_SCM0008_REQUEST_AUTH', 'API_SCM0008_DELETE_MY_AUTH');
