-- 1. 메뉴 (1 row 예상)
SELECT 'MNU_M' AS CHK_KEY, COUNT(*) AS ROW_CNT, 1 AS EXPECT
  FROM SCM_MGR.SCM_ADM_MNU_M
 WHERE MNU_ID='DMF0048';

-- 2. API_M (2 endpoint)
SELECT 'API_M' AS CHK_KEY, COUNT(*) AS ROW_CNT, 2 AS EXPECT
  FROM SCM_MGR.SCM_ADM_API_M
 WHERE API_ID LIKE 'P_DMF0048%';

-- 3. MNU_BTN_MPG (2 row)
SELECT 'MNU_BTN_MPG' AS CHK_KEY, COUNT(*) AS ROW_CNT, 2 AS EXPECT
  FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M
 WHERE MNU_ID='DMF0048';

-- 4. PROC_M (30 row — 23 main SP + 7 title SP)
SELECT 'PROC_M' AS CHK_KEY, COUNT(*) AS ROW_CNT, 30 AS EXPECT
  FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM LIKE 'DMF0048%';

-- 5. SHEET_COLUMNS (51 cols)
SELECT 'SHEET_COLUMNS' AS CHK_KEY, COUNT(*) AS ROW_CNT, 51 AS EXPECT
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID='DMF0048';

-- 6. MSG (2 API 메시지)
SELECT 'MSG_M' AS CHK_KEY, COUNT(*) AS ROW_CNT, 2 AS EXPECT
  FROM SCM_MGR.SCM_ADM_MSG_M
 WHERE MSG_ID LIKE 'MSG_API_DMF0048%';

-- 7. GUEST 메뉴 권한 (1 row)
SELECT 'GUEST_MNU' AS CHK_KEY, COUNT(*) AS ROW_CNT, 1 AS EXPECT
  FROM SCM_MGR.SCM_ADM_USER_GR_MNU_MPG_M
 WHERE USER_GR_ID='GUEST' AND MNU_ID='DMF0048';

-- 8. GUEST 버튼 권한 (2 row)
SELECT 'GUEST_BTN' AS CHK_KEY, COUNT(*) AS ROW_CNT, 2 AS EXPECT
  FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M
 WHERE USER_GR_ID='GUEST' AND MNU_ID='DMF0048';

-- 9. minyonglee1 그룹 메뉴 권한 (≥1 row 예상)
SELECT 'minyonglee1_MNU' AS CHK_KEY, COUNT(*) AS ROW_CNT, 1 AS EXPECT_MIN
  FROM SCM_MGR.SCM_ADM_USER_GR_MNU_MPG_M
 WHERE MNU_ID='DMF0048'
   AND USER_GR_ID IN (SELECT USER_GR_ID FROM SCM_MGR.SCM_ADM_USER_GR_MPG_M WHERE USER_ID='minyonglee1' AND USE_YN='Y');

-- 10. PROC_M ↔ SP signature 매치 검증 (PROC_NM 별 row 수 = SP ALL_ARGUMENTS 수)
SELECT P.PROC_NM,
       COUNT(*) AS PROC_M_ROWS,
       (SELECT COUNT(*) FROM ALL_ARGUMENTS A WHERE A.OWNER='SCM_MGR' AND A.OBJECT_NAME=P.PROC_NM AND A.PACKAGE_NAME IS NULL) AS SP_ARGS,
       CASE
         WHEN COUNT(*) = (SELECT COUNT(*) FROM ALL_ARGUMENTS A WHERE A.OWNER='SCM_MGR' AND A.OBJECT_NAME=P.PROC_NM AND A.PACKAGE_NAME IS NULL)
         THEN 'MATCH'
         ELSE 'MISMATCH ⚠️'
       END AS STATUS
  FROM SCM_MGR.SCM_ADM_PROC_M P
 WHERE P.PROC_NM LIKE 'DMF0048%'
 GROUP BY P.PROC_NM
 ORDER BY P.PROC_NM;
