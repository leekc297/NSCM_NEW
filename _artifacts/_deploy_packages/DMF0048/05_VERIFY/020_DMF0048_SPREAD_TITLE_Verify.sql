-- 1. Standalone SP P_DMF0048_GET_SPREAD_TITLE VALID
SELECT 'Step1: standalone SP VALID' AS CHK,
       OBJECT_NAME, OBJECT_TYPE, STATUS
  FROM ALL_OBJECTS
 WHERE OWNER='SCM_MGR'
   AND OBJECT_NAME='P_DMF0048_GET_SPREAD_TITLE'
   AND OBJECT_TYPE='PROCEDURE';

-- 2. PKG_DMF0048 SPEC VALID (SPREAD_TITLE 제거 후)
SELECT 'Step2: PKG_DMF0048 VALID' AS CHK,
       OBJECT_NAME, OBJECT_TYPE, STATUS
  FROM ALL_OBJECTS
 WHERE OWNER='SCM_MGR'
   AND OBJECT_NAME='PKG_DMF0048'
 ORDER BY OBJECT_TYPE;

-- 3. ALL_ARGUMENTS — standalone SP signature 검증 (8 row 예상)
SELECT 'Step3: ALL_ARGUMENTS' AS CHK, POSITION, ARGUMENT_NAME, DATA_TYPE, IN_OUT
  FROM ALL_ARGUMENTS
 WHERE OWNER='SCM_MGR'
   AND OBJECT_NAME='P_DMF0048_GET_SPREAD_TITLE'
   AND PACKAGE_NAME IS NULL
 ORDER BY POSITION;

-- 4. PROC_M ↔ ALL_ARGUMENTS 매치 (proc-meta-signature-match hook)
SELECT 'Step4: PROC_M signature match' AS CHK,
       P.PROC_NM,
       COUNT(*) AS PROC_M_ROWS,
       (SELECT COUNT(*) FROM ALL_ARGUMENTS A
         WHERE A.OWNER='SCM_MGR' AND A.OBJECT_NAME=P.PROC_NM AND A.PACKAGE_NAME IS NULL) AS SP_ARGS,
       CASE
         WHEN COUNT(*) = (SELECT COUNT(*) FROM ALL_ARGUMENTS A
                           WHERE A.OWNER='SCM_MGR' AND A.OBJECT_NAME=P.PROC_NM AND A.PACKAGE_NAME IS NULL)
         THEN 'MATCH'
         ELSE 'MISMATCH'
       END AS STATUS
  FROM SCM_MGR.SCM_ADM_PROC_M P
 WHERE P.PROC_NM = 'DMF0048_GET_SPREAD_TITLE'
 GROUP BY P.PROC_NM;

-- 5. API_M 정정 확인 (PKG_DMF0048. 접두 제거 검증)
SELECT 'Step5: API_M URL' AS CHK, API_ID, API_URL,
       CASE WHEN API_URL = 'P_DMF0048_GET_SPREAD_TITLE' THEN 'OK' ELSE 'NEED FIX' END AS STATUS
  FROM SCM_MGR.SCM_ADM_API_M
 WHERE API_ID = 'P_DMF0048_TITLE_RETRIEVE';

-- 6. 기존 PKG_DMF0048 의 SALES_MONITORING 보존 검증 (body 그대로)
SELECT 'Step6: PKG SALES_MONITORING preserved' AS CHK,
       OBJECT_NAME, PROCEDURE_NAME
  FROM ALL_PROCEDURES
 WHERE OWNER='SCM_MGR'
   AND OBJECT_NAME='PKG_DMF0048'
 ORDER BY PROCEDURE_NAME;

