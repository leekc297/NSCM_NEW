-- 99_ROLLBACK_DATA — [E20261028-DUPROLLBACK] 20_DATA_DEDUP 원복 (전체 F5, 값 입력 없음, 멱등)
-- 내용: BAK_DMF0049_DUP_20261028 의 백업 행을 원장(DM_PLN_SALES_ETC_REPORT_C)으로 되돌린 뒤 백업 테이블에서 지운다.
--       원장에 같은 PK 행이 이미 있으면 되돌리지 않는다(PK 충돌 방지). 컬럼 목록은 이 DB 의 원장 컬럼으로 만든다.
-- 백업 테이블이 없으면 아무것도 하지 않는다.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET DEFINE OFF
DECLARE
    v_cnt   PLS_INTEGER;
    v_cols  VARCHAR2(32767);
    n_ins   PLS_INTEGER := 0;
    n_del   PLS_INTEGER := 0;
    c_pk    CONSTANT VARCHAR2(400) := 'T.VERSION_NO = B.VERSION_NO AND T.DIVISION_ID = B.DIVISION_ID AND T.DATA_SEQ = B.DATA_SEQ AND T.MEASURE = B.MEASURE AND T.YYYYMMDD = B.YYYYMMDD';
BEGIN
    SELECT COUNT(*) INTO v_cnt FROM USER_TABLES WHERE TABLE_NAME = 'BAK_DMF0049_DUP_20261028';
    IF v_cnt = 0 THEN
        DBMS_OUTPUT.PUT_LINE('SKIP — 백업 테이블 없음 (20_DATA 미실행)');
        RETURN;
    END IF;
    SELECT LISTAGG(COLUMN_NAME, ', ') WITHIN GROUP (ORDER BY COLUMN_ID) INTO v_cols
      FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'DM_PLN_SALES_ETC_REPORT_C';
    EXECUTE IMMEDIATE 'INSERT INTO DM_PLN_SALES_ETC_REPORT_C (' || v_cols || ') SELECT ' || v_cols
                   || ' FROM BAK_DMF0049_DUP_20261028 B WHERE NOT EXISTS (SELECT 1 FROM DM_PLN_SALES_ETC_REPORT_C T WHERE ' || c_pk || ')';
    n_ins := SQL%ROWCOUNT;
    EXECUTE IMMEDIATE 'DELETE FROM BAK_DMF0049_DUP_20261028 B WHERE EXISTS (SELECT 1 FROM DM_PLN_SALES_ETC_REPORT_C T WHERE ' || c_pk || ')';
    n_del := SQL%ROWCOUNT;
    COMMIT;
    DBMS_OUTPUT.PUT_LINE('RESTORED — 원장 복원 ' || n_ins || '건 · 백업에서 제거 ' || n_del || '건 · ' || TO_CHAR(SYSDATE, 'YYYY-MM-DD HH24:MI:SS'));
END;
