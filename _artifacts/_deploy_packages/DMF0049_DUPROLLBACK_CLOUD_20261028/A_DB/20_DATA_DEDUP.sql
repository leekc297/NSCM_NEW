-- 20_DATA_DEDUP — [E20261028-DUPROLLBACK] ETC 원장 같은 키 중복 행 정리 (전체 F5, 값 입력 없음, 멱등)
-- 대상: DM_PLN_SALES_ETC_REPORT_C 에서 같은 (버전·사업부·메저·월) + 화면 키 21개(빈 값 NULL·공백·'-'·'/' 동일 취급)에
--       DATA_SEQ 가 2개 이상인 묶음 → 가장 먼저 저장된 DATA_SEQ(최소값)만 남기고 나중 DATA_SEQ 행을 삭제
--       (AS-IS 라면 두 번째 저장이 취소되었을 것이므로 먼저 저장된 세트가 정본)
--   화면 키 21개 = DMF0049 저장 DATA_SEQ 채번 키 19개(DEPARTMENT_ID, DEPT_ID, CUST_REPORT, END_CUST_REPORT, SOLDTO_CODE,
--                 SOLDTO_CUST_REPORT, PRODUCT_GROUP, ITEM_ID, PRODUCT_DETAILS, CURRENCY, COMPANY_ID, BIZ_TYPE, APPLICATION_GR,
--                 APPLICATION, COUNTRY_CODE, ITEM_USE, SOLDTO_COUNTRY, SHIPTO_COUNTRY, END_CUSTOMER) + CELL_MODEL_INFO + ATTRIBUTE3
-- 안전장치: QTY 가 남길 행과 같은 행만 삭제. QTY 가 다른 행은 삭제하지 않고 남겨 90_VERIFY 에 표시(업무 판단 필요).
--           삭제 행은 먼저 BAK_DMF0049_DUP_20261028 에 백업(처음 실행 시 테이블 생성) — 백업 건수 ≠ 삭제 건수면 ROLLBACK 후 중단.
-- 원복: 99_ROLLBACK_DATA.sql (백업 행을 원장으로 되돌림)
-- 후속: 버전이 전송 상태(SEND_YN='Y')면 Sales Report 재생성이 필요할 수 있음 → 25_REGEN_SALES_REPORT.sql 참고
SET SERVEROUTPUT ON SIZE UNLIMITED
SET DEFINE OFF
DECLARE
    v_cnt   PLS_INTEGER;
    n_bak   PLS_INTEGER := 0;
    n_del   PLS_INTEGER := 0;
    c_dup   CONSTANT VARCHAR2(8000) := q'[
        SELECT RID, KEEP_SEQ FROM (
            SELECT N.*
                 , MIN(DATA_SEQ) OVER (PARTITION BY VERSION_NO, DIVISION_ID, MEASURE, YYYYMMDD, K) KEEP_SEQ
                 , COUNT(DISTINCT DATA_SEQ) OVER (PARTITION BY VERSION_NO, DIVISION_ID, MEASURE, YYYYMMDD, K) SEQ_CNT
                 , MIN(QTY) OVER (PARTITION BY VERSION_NO, DIVISION_ID, MEASURE, YYYYMMDD, K) MIN_QTY
                 , MAX(QTY) OVER (PARTITION BY VERSION_NO, DIVISION_ID, MEASURE, YYYYMMDD, K) MAX_QTY
              FROM (SELECT A.ROWID RID, A.VERSION_NO, A.DIVISION_ID, A.DATA_SEQ, A.MEASURE, A.YYYYMMDD, A.QTY
                         , DECODE(TRIM(A.DEPARTMENT_ID),NULL,'/','-','/',TRIM(A.DEPARTMENT_ID))||'|'||DECODE(TRIM(A.DEPT_ID),NULL,'/','-','/',TRIM(A.DEPT_ID))||'|'||
                           DECODE(TRIM(A.CUST_REPORT),NULL,'/','-','/',TRIM(A.CUST_REPORT))||'|'||DECODE(TRIM(A.END_CUST_REPORT),NULL,'/','-','/',TRIM(A.END_CUST_REPORT))||'|'||
                           DECODE(TRIM(A.SOLDTO_CODE),NULL,'/','-','/',TRIM(A.SOLDTO_CODE))||'|'||DECODE(TRIM(A.SOLDTO_CUST_REPORT),NULL,'/','-','/',TRIM(A.SOLDTO_CUST_REPORT))||'|'||
                           DECODE(TRIM(A.PRODUCT_GROUP),NULL,'/','-','/',TRIM(A.PRODUCT_GROUP))||'|'||DECODE(TRIM(A.ITEM_ID),NULL,'/','-','/',TRIM(A.ITEM_ID))||'|'||
                           DECODE(TRIM(A.PRODUCT_DETAILS),NULL,'/','-','/',TRIM(A.PRODUCT_DETAILS))||'|'||DECODE(TRIM(A.CURRENCY),NULL,'/','-','/',TRIM(A.CURRENCY))||'|'||
                           DECODE(TRIM(A.COMPANY_ID),NULL,'/','-','/',TRIM(A.COMPANY_ID))||'|'||DECODE(TRIM(A.BIZ_TYPE),NULL,'/','-','/',TRIM(A.BIZ_TYPE))||'|'||
                           DECODE(TRIM(A.APPLICATION_GR),NULL,'/','-','/',TRIM(A.APPLICATION_GR))||'|'||DECODE(TRIM(A.APPLICATION),NULL,'/','-','/',TRIM(A.APPLICATION))||'|'||
                           DECODE(TRIM(A.COUNTRY_CODE),NULL,'/','-','/',TRIM(A.COUNTRY_CODE))||'|'||DECODE(TRIM(A.ITEM_USE),NULL,'/','-','/',TRIM(A.ITEM_USE))||'|'||
                           DECODE(TRIM(A.SOLDTO_COUNTRY),NULL,'/','-','/',TRIM(A.SOLDTO_COUNTRY))||'|'||DECODE(TRIM(A.SHIPTO_COUNTRY),NULL,'/','-','/',TRIM(A.SHIPTO_COUNTRY))||'|'||
                           DECODE(TRIM(A.END_CUSTOMER),NULL,'/','-','/',TRIM(A.END_CUSTOMER))||'|'||DECODE(TRIM(A.CELL_MODEL_INFO),NULL,'/','-','/',TRIM(A.CELL_MODEL_INFO))||'|'||
                           DECODE(TRIM(A.ATTRIBUTE3),NULL,'/','-','/',TRIM(A.ATTRIBUTE3)) AS K
                      FROM DM_PLN_SALES_ETC_REPORT_C A) N )
         WHERE SEQ_CNT > 1 AND DATA_SEQ > KEEP_SEQ AND MIN_QTY = MAX_QTY ]';
BEGIN
    SELECT COUNT(*) INTO v_cnt FROM USER_TABLES WHERE TABLE_NAME = 'BAK_DMF0049_DUP_20261028';
    IF v_cnt = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE BAK_DMF0049_DUP_20261028 AS SELECT A.*, CAST(NULL AS DATE) BAK_AT, CAST(NULL AS NUMBER) BAK_KEEP_SEQ FROM DM_PLN_SALES_ETC_REPORT_C A WHERE 1 = 0';
        DBMS_OUTPUT.PUT_LINE('백업 테이블 생성 — BAK_DMF0049_DUP_20261028');
    END IF;
    EXECUTE IMMEDIATE 'INSERT INTO BAK_DMF0049_DUP_20261028 SELECT A.*, SYSDATE, D.KEEP_SEQ FROM DM_PLN_SALES_ETC_REPORT_C A JOIN (' || c_dup || ') D ON D.RID = A.ROWID';
    n_bak := SQL%ROWCOUNT;
    EXECUTE IMMEDIATE 'DELETE FROM DM_PLN_SALES_ETC_REPORT_C WHERE ROWID IN (SELECT RID FROM (' || c_dup || '))';
    n_del := SQL%ROWCOUNT;
    IF n_bak <> n_del THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20001, '중단 — 백업 ' || n_bak || '건 ≠ 삭제 ' || n_del || '건. ROLLBACK 함(데이터 무변경)');
    END IF;
    COMMIT;
    DBMS_OUTPUT.PUT_LINE('DEDUP — 백업 ' || n_bak || '건 · 삭제 ' || n_del || '건 · ' || TO_CHAR(SYSDATE, 'YYYY-MM-DD HH24:MI:SS'));
END;
/
SELECT 'BAK' CHK, VERSION_NO, DIVISION_ID, COUNT(*) DELETED_ROWS
     , LISTAGG(DISTINCT DATA_SEQ || '<-' || BAK_KEEP_SEQ, ',') WITHIN GROUP (ORDER BY DATA_SEQ || '<-' || BAK_KEEP_SEQ) DEL_SEQ_KEEP_SEQ
     , TO_CHAR(MAX(BAK_AT),'YYYY-MM-DD HH24:MI:SS') BAK_AT
  FROM BAK_DMF0049_DUP_20261028
 GROUP BY VERSION_NO, DIVISION_ID
 ORDER BY VERSION_NO DESC;
