-- 90_VERIFY — [E20261028-DUPROLLBACK] 적용 후 확인 (조회 전용 · 전체 F5 안전)
--   V1 PKG_DMF0044 BODY VALID · 오류 0
--   V2 마커 6줄 — 모두 MOBILE_REPORT_CREATE 안, 바로 다음 줄이 검증 실패 분기(V_LOG_TYPE 대입)여야 함
--   V3 남은 같은 키 중복 — SAME_QTY 0 이어야 정리 완료. QTY_DIFF 는 업무 판단 대상(자동 삭제 안 함)
--   V4 백업 테이블 건수(버전별)
SET DEFINE OFF

SELECT 'V1' CHK, O.OBJECT_TYPE, O.STATUS, TO_CHAR(O.LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL
     , (SELECT COUNT(*) FROM USER_ERRORS E WHERE E.NAME = O.OBJECT_NAME AND E.TYPE = O.OBJECT_TYPE) ERR_CNT
  FROM USER_OBJECTS O WHERE O.OBJECT_NAME = 'PKG_DMF0044' ORDER BY O.OBJECT_TYPE;

WITH S AS (SELECT LINE, TEXT FROM USER_SOURCE WHERE NAME = 'PKG_DMF0044' AND TYPE = 'PACKAGE BODY')
, R AS (SELECT MAX(CASE WHEN REGEXP_LIKE(TEXT, '^\s*PROCEDURE\s+P_DMF0044_MOBILE_REPORT_CREATE(\s|\(|$)', 'i') THEN LINE END) S_LINE
             , MAX(CASE WHEN REGEXP_LIKE(TEXT, '^\s*END\s+P_DMF0044_MOBILE_REPORT_CREATE\s*;', 'i') THEN LINE END) E_LINE FROM S)
SELECT 'V2' CHK, M.LINE MARK_LINE
     , CASE WHEN M.LINE BETWEEN R.S_LINE AND R.E_LINE THEN 'IN' ELSE 'OUT' END IN_MOBILE
     , SUBSTR(TRIM(NX.TEXT), 1, 70) NEXT_LINE
  FROM S M, S NX, R
 WHERE M.TEXT LIKE '%[E20261028-DUPROLLBACK]%' AND NX.LINE = M.LINE + 1
 ORDER BY M.LINE;

WITH N AS (
SELECT A.VERSION_NO, A.DIVISION_ID, A.DATA_SEQ, A.MEASURE, A.YYYYMMDD, A.QTY
     , DECODE(TRIM(A.DEPARTMENT_ID),NULL,'/','-','/',TRIM(A.DEPARTMENT_ID))||'|'||DECODE(TRIM(A.DEPT_ID),NULL,'/','-','/',TRIM(A.DEPT_ID))||'|'||
       DECODE(TRIM(A.CUST_REPORT),NULL,'/','-','/',TRIM(A.CUST_REPORT))||'|'||DECODE(TRIM(A.END_CUST_REPORT),NULL,'/','-','/',TRIM(A.END_CUST_REPORT))||'|'||
       DECODE(TRIM(A.SOLDTO_CODE),NULL,'/','-','/',TRIM(A.SOLDTO_CODE))||'|'||DECODE(TRIM(A.SOLDTO_CUST_REPORT),NULL,'/','-','/',TRIM(A.SOLDTO_CUST_REPORT))||'|'||
       DECODE(TRIM(A.PRODUCT_GROUP),NULL,'/','-','/',TRIM(A.PRODUCT_GROUP))||'|'||DECODE(TRIM(A.ITEM_ID),NULL,'/','-','/',TRIM(A.ITEM_ID))||'|'||
       DECODE(TRIM(A.PRODUCT_DETAILS),NULL,'/','-','/',TRIM(A.PRODUCT_DETAILS))||'|'||DECODE(TRIM(A.CURRENCY),NULL,'/','-','/',TRIM(A.CURRENCY))||'|'||
       DECODE(TRIM(A.COMPANY_ID),NULL,'/','-','/',TRIM(A.COMPANY_ID))||'|'||DECODE(TRIM(A.BIZ_TYPE),NULL,'/','-','/',TRIM(A.BIZ_TYPE))||'|'||
       DECODE(TRIM(A.APPLICATION_GR),NULL,'/','-','/',TRIM(A.APPLICATION_GR))||'|'||DECODE(TRIM(A.APPLICATION),NULL,'/','-','/',TRIM(A.APPLICATION))||'|'||
       DECODE(TRIM(A.COUNTRY_CODE),NULL,'/','-','/',TRIM(A.COUNTRY_CODE))||'|'||DECODE(TRIM(A.ITEM_USE),NULL,'/','-','/',TRIM(A.ITEM_USE))||'|'||
       DECODE(TRIM(A.SOLDTO_COUNTRY),NULL,'/','-','/',TRIM(A.SOLDTO_COUNTRY))||'|'||DECODE(TRIM(A.SHIPTO_COUNTRY),NULL,'/','-','/',TRIM(A.SHIPTO_COUNTRY))||'|'||
       DECODE(TRIM(A.END_CUSTOMER),NULL,'/','-','/',TRIM(A.END_CUSTOMER))||'|'||DECODE(TRIM(A.CELL_MODEL_INFO),NULL,'/','-','/',TRIM(A.CELL_MODEL_INFO))||'|'||
       DECODE(TRIM(A.ATTRIBUTE3),NULL,'/','-','/',TRIM(A.ATTRIBUTE3)) AS K
  FROM DM_PLN_SALES_ETC_REPORT_C A )
, R AS (
SELECT N.*
     , MIN(DATA_SEQ) OVER (PARTITION BY VERSION_NO, DIVISION_ID, MEASURE, YYYYMMDD, K) KEEP_SEQ
     , COUNT(DISTINCT DATA_SEQ) OVER (PARTITION BY VERSION_NO, DIVISION_ID, MEASURE, YYYYMMDD, K) SEQ_CNT
     , MIN(QTY) OVER (PARTITION BY VERSION_NO, DIVISION_ID, MEASURE, YYYYMMDD, K) MIN_QTY
     , MAX(QTY) OVER (PARTITION BY VERSION_NO, DIVISION_ID, MEASURE, YYYYMMDD, K) MAX_QTY
  FROM N )
SELECT 'V3' CHK
     , SUM(CASE WHEN SEQ_CNT > 1 AND DATA_SEQ > KEEP_SEQ AND MIN_QTY = MAX_QTY THEN 1 ELSE 0 END) DUP_SAME_QTY_LEFT
     , SUM(CASE WHEN SEQ_CNT > 1 AND DATA_SEQ > KEEP_SEQ AND MIN_QTY <> MAX_QTY THEN 1 ELSE 0 END) DUP_QTY_DIFF_LEFT
  FROM R;

SET SERVEROUTPUT ON SIZE UNLIMITED
DECLARE
    v_cnt PLS_INTEGER;
    rc    SYS_REFCURSOR;
    v_ver VARCHAR2(100);
    v_div VARCHAR2(30);
    v_n   PLS_INTEGER;
BEGIN
    SELECT COUNT(*) INTO v_cnt FROM USER_TABLES WHERE TABLE_NAME = 'BAK_DMF0049_DUP_20261028';
    IF v_cnt = 0 THEN
        DBMS_OUTPUT.PUT_LINE('V4 백업 테이블 없음 (20_DATA 미실행)');
        RETURN;
    END IF;
    OPEN rc FOR 'SELECT VERSION_NO, DIVISION_ID, COUNT(*) FROM BAK_DMF0049_DUP_20261028 GROUP BY VERSION_NO, DIVISION_ID ORDER BY VERSION_NO DESC';
    LOOP
        FETCH rc INTO v_ver, v_div, v_n;
        EXIT WHEN rc%NOTFOUND;
        DBMS_OUTPUT.PUT_LINE('V4 ' || v_ver || ' | ' || v_div || ' | 백업 ' || v_n || '건');
    END LOOP;
    CLOSE rc;
END;
