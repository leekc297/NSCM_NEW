--==============================================================================
-- 110_DMF0008_SHEET_COLUMNS_null_flags_fix.sql
--
-- DMF0008 SHEET_COLUMNS 의 5 flag NULL → BE NullPointerException -9999 fix
--
-- 배경 (2026-06-10):
--   화면 진입 시 fetchStaticColumns → BE retrieveGridColumns → GridColumn.of 호출
--   data.get("FIXED_FLAG").equals("Y") / UPPERCASE_APPLY_FLAG / USER_SELECTABLE_FLAG
--   해당 컬럼이 NULL 시 NullPointerException → BE catch 후 code='-9999' 반환
--   화면에 4 grid 의 column 헤더 표시 안 됨.
--
--   진단: NVL 결과 모든 5 row (summary) + 22 (repair) + 25 (salesSite) + 69 (sspm)
--   = 총 121 row 의 FIXED_FLAG/UPPERCASE_APPLY_FLAG/USER_SELECTABLE_FLAG NULL.
--
-- Fix:
--   - FIXED_FLAG, UPPERCASE_APPLY_FLAG → 'N' default
--   - USER_SELECTABLE_FLAG, DEFAULT_FLAG, VISIBLE_FLAG → 'Y' default
--
-- 멱등성: NVL 사용 — 재실행 시 영향 없음 (이미 'Y'/'N' 인 row 변경 안 됨)
--==============================================================================
SET DEFINE OFF
SET SERVEROUTPUT ON
SET FEEDBACK ON
WHENEVER SQLERROR EXIT FAILURE

PROMPT === PRE-CHECK: NULL flag counts ===
SELECT SHEET_NAME,
       COUNT(*) ROW_CNT,
       SUM(CASE WHEN FIXED_FLAG IS NULL THEN 1 ELSE 0 END) FF_NULL,
       SUM(CASE WHEN UPPERCASE_APPLY_FLAG IS NULL THEN 1 ELSE 0 END) UAF_NULL,
       SUM(CASE WHEN VISIBLE_FLAG IS NULL THEN 1 ELSE 0 END) VF_NULL,
       SUM(CASE WHEN USER_SELECTABLE_FLAG IS NULL THEN 1 ELSE 0 END) USF_NULL,
       SUM(CASE WHEN DEFAULT_FLAG IS NULL THEN 1 ELSE 0 END) DF_NULL
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID='DMF0008'
   AND SHEET_NAME IN ('summary','repair','salesSite','sspm')
 GROUP BY SHEET_NAME ORDER BY 1;

PROMPT === FIX: UPDATE NVL ===
UPDATE SCM_MGR.SCM_MST_SHEET_COLUMNS
   SET FIXED_FLAG = NVL(FIXED_FLAG, 'N'),
       UPPERCASE_APPLY_FLAG = NVL(UPPERCASE_APPLY_FLAG, 'N'),
       USER_SELECTABLE_FLAG = NVL(USER_SELECTABLE_FLAG, 'Y'),
       DEFAULT_FLAG = NVL(DEFAULT_FLAG, 'Y'),
       VISIBLE_FLAG = NVL(VISIBLE_FLAG, 'Y'),
       LAST_UPDATED_BY = 'admin',
       LAST_UPDATE_DATE = SYSDATE
 WHERE PROGRAM_ID='DMF0008'
   AND SHEET_NAME IN ('summary','repair','salesSite','sspm')
   AND (FIXED_FLAG IS NULL
        OR UPPERCASE_APPLY_FLAG IS NULL
        OR USER_SELECTABLE_FLAG IS NULL
        OR DEFAULT_FLAG IS NULL
        OR VISIBLE_FLAG IS NULL);

PROMPT === POST-CHECK: NULL counts (모두 0 기대) ===
SELECT SHEET_NAME,
       COUNT(*) ROW_CNT,
       SUM(CASE WHEN FIXED_FLAG IS NULL THEN 1 ELSE 0 END) FF_NULL,
       SUM(CASE WHEN UPPERCASE_APPLY_FLAG IS NULL THEN 1 ELSE 0 END) UAF_NULL,
       SUM(CASE WHEN USER_SELECTABLE_FLAG IS NULL THEN 1 ELSE 0 END) USF_NULL
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID='DMF0008'
   AND SHEET_NAME IN ('summary','repair','salesSite','sspm')
 GROUP BY SHEET_NAME ORDER BY 1;

COMMIT;
PROMPT === 110_DMF0008_SHEET_COLUMNS_null_flags_fix.sql 완료 ===
