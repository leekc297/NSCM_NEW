PROMPT === FIX 4 : 사후 검증 ===

SELECT 'A. division chain' AS check_item,
       BTN.MNU_ID || '/' || BTN.SHT_NM || '/' || BTN.MNU_BTN_CD AS path,
       BTN.API_ID, API.API_URL,
       (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M WHERE PROC_NM = API.API_URL) AS proc_cnt,
       (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M
         WHERE USER_GR_ID='GUEST' AND MNU_ID=BTN.MNU_ID AND SHT_NM=BTN.SHT_NM AND MNU_BTN_CD=BTN.MNU_BTN_CD) AS guest_perm
  FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M BTN
  LEFT JOIN SCM_MGR.SCM_ADM_API_M API ON API.API_ID = BTN.API_ID
 WHERE BTN.MNU_ID = 'DMF0008' AND BTN.SHT_NM IN ('division', 'updateHistory')
   AND BTN.MNU_BTN_CD = 'SEARCH'
 ORDER BY 1;

