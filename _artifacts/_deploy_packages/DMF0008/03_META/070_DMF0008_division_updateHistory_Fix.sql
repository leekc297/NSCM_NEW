PROMPT === FIX 1.4 : DMF0008_GET_MY_DIVISION_LIST PROC_M (signature) ===

-- DMF0008_GET_MY_DIVISION_LIST 의 시그니처 기반 (DIAG 2 결과 확인 후 보강)
-- 일반적인 패턴: P_USER_ID IN + P_MENU_ID IN + O_RC1 OUT (3 args)
INSERT INTO SCM_MGR.SCM_ADM_PROC_M
  (PROC_NM, COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD,
   CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'DMF0008_GET_MY_DIVISION_LIST', NEW.COL_NM, NEW.DATA_TP_CD, NEW.COL_TP_CD, NEW.SORT_ORD,
       'admin', SYSDATE, 'admin', SYSDATE
  FROM (
    SELECT 'sesUserId' AS COL_NM, 'VARCHAR' AS DATA_TP_CD, 'IN' AS COL_TP_CD, 1 AS SORT_ORD FROM DUAL UNION ALL
    SELECT 'mnuId',                'VARCHAR',               'IN',                2          FROM DUAL UNION ALL
    SELECT 'o_rc1',                'CURSOR',                'OUT',               3          FROM DUAL
  ) NEW
 WHERE NOT EXISTS (
   SELECT 1 FROM SCM_MGR.SCM_ADM_PROC_M
    WHERE PROC_NM = 'DMF0008_GET_MY_DIVISION_LIST' AND COL_NM = NEW.COL_NM
 );

