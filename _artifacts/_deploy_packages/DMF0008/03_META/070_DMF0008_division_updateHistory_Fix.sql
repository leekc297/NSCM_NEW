PROMPT === FIX 2 : updateHistory PROC_M 정합 (DELETE 후 정확 3 row INSERT) ===

-- DMF0008_GET_UPDATE_HISTORY 실제 시그니처 (DIAG 4): P_USER_ID + P_MENU_ID + O_RC1 = 3 args
-- 현재 PROC_M 5 row → mismatch → 500 (PLS-00306)
-- 안전: DELETE 후 정확 3 row INSERT

DELETE FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM = 'DMF0008_GET_UPDATE_HISTORY';

INSERT INTO SCM_MGR.SCM_ADM_PROC_M
  (PROC_NM, COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD,
   CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'DMF0008_GET_UPDATE_HISTORY', NEW.COL_NM, NEW.DATA_TP_CD, NEW.COL_TP_CD, NEW.SORT_ORD,
       'admin', SYSDATE, 'admin', SYSDATE
  FROM (
    -- BE 자동 채움 키: sesUserId → P_USER_ID, mnuId → P_MENU_ID
    SELECT 'sesUserId' AS COL_NM, 'VARCHAR' AS DATA_TP_CD, 'IN' AS COL_TP_CD, 1 AS SORT_ORD FROM DUAL UNION ALL
    SELECT 'mnuId',                'VARCHAR',               'IN',                2          FROM DUAL UNION ALL
    SELECT 'o_rc1',                'CURSOR',                'OUT',               3          FROM DUAL
  ) NEW;

