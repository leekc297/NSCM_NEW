PROMPT === BLOCK 4 : SCM_ADM_USER_GR_MNU_BTN_MPG_M (minyonglee1 4 그룹 자동 매핑) ===

-- minyonglee1 의 모든 USER_GR (GUEST/ADMIN/DM Viewer/DM ADMIN) 에 자동 부여
INSERT INTO SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M (USER_GR_ID, MNU_ID, SHT_NM, MNU_BTN_CD, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT DISTINCT gr.USER_GR_ID, 'DMF0008', NEW.SHT_NM, NEW.MNU_BTN_CD, 'Y',
       'admin', SYSDATE, 'admin', SYSDATE
  FROM SCM_MGR.SCM_ADM_USER_GR_MPG_M gr
 CROSS JOIN (
    SELECT 'updateHistory' AS SHT_NM, 'SEARCH'        AS MNU_BTN_CD FROM DUAL UNION ALL
    SELECT 'main',                    'STATUS_UPDATE'               FROM DUAL
 ) NEW
 WHERE gr.USER_ID = 'minyonglee1' AND (gr.USE_YN='Y' OR gr.USE_YN IS NULL)
   AND NOT EXISTS (
     SELECT 1 FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M e
      WHERE e.USER_GR_ID = gr.USER_GR_ID AND e.MNU_ID = 'DMF0008'
        AND e.SHT_NM = NEW.SHT_NM AND e.MNU_BTN_CD = NEW.MNU_BTN_CD
   );

-- GUEST 도 보강 (login 전 default)
INSERT INTO SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M (USER_GR_ID, MNU_ID, SHT_NM, MNU_BTN_CD, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'GUEST', 'DMF0008', NEW.SHT_NM, NEW.MNU_BTN_CD, 'Y', 'admin', SYSDATE, 'admin', SYSDATE
  FROM (
    SELECT 'updateHistory' AS SHT_NM, 'SEARCH'        AS MNU_BTN_CD FROM DUAL UNION ALL
    SELECT 'main',                    'STATUS_UPDATE'               FROM DUAL
  ) NEW
 WHERE NOT EXISTS (
   SELECT 1 FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M X
    WHERE X.USER_GR_ID='GUEST' AND X.MNU_ID='DMF0008'
      AND X.SHT_NM=NEW.SHT_NM AND X.MNU_BTN_CD=NEW.MNU_BTN_CD
 );

PROMPT === BLOCK 5 : SCM_ADM_PROC_M (SP 인자 매핑 — BE 가 채워줄 값) ===

-- DMF0008_GET_UPDATE_HISTORY (P_USER_ID, P_MENU_ID, O_RC1)
--   BE 표준 매핑: sesUserId / mnuId / o_rc1 + O_RESULT_CURSOR
INSERT INTO SCM_MGR.SCM_ADM_PROC_M (PROC_NM, COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'DMF0008_GET_UPDATE_HISTORY', NEW.COL_NM, NEW.DATA_TP, NEW.COL_TP, NEW.SORT_ORD, 'admin', SYSDATE, 'admin', SYSDATE
  FROM (
    SELECT 'sesUserId'       AS COL_NM, 'VARCHAR'     AS DATA_TP, 'IN'  AS COL_TP, 1 AS SORT_ORD FROM DUAL UNION ALL
    SELECT 'mnuId',                     'VARCHAR',                 'IN',              2          FROM DUAL UNION ALL
    SELECT 'o_rc1',                     'CURSOR',                  'OUT',             3          FROM DUAL UNION ALL
    SELECT 'O_RESULT_CURSOR',           'PROC_RESULT',             'OUT',             4          FROM DUAL
  ) NEW
 WHERE NOT EXISTS (
   SELECT 1 FROM SCM_MGR.SCM_ADM_PROC_M P
    WHERE P.PROC_NM = 'DMF0008_GET_UPDATE_HISTORY'
      AND P.COL_NM = NEW.COL_NM AND P.COL_TP_CD = NEW.COL_TP
 );

-- PR_DM_DNM_EDI_CALLOFF_STATUS 인자는 ALL_ARGUMENTS 결과 보고 동적 매핑.
-- AS-IS .cs L3027: var request = new FoxDataRequest("DM.PR_DM_DNM_EDI_CALLOFF_STATUS") — 인자 없음
-- To-Be SP 가 사내 환경에 어떤 시그니처로 컴파일되어 있는지 DIAG 출력 참조.
-- 일반적으로 표준 (sesUserId / mnuId / O_RESULT_CURSOR) 패턴.
INSERT INTO SCM_MGR.SCM_ADM_PROC_M (PROC_NM, COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'PR_DM_DNM_EDI_CALLOFF_STATUS', NEW.COL_NM, NEW.DATA_TP, NEW.COL_TP, NEW.SORT_ORD, 'admin', SYSDATE, 'admin', SYSDATE
  FROM (
    SELECT 'sesUserId'       AS COL_NM, 'VARCHAR'     AS DATA_TP, 'IN'  AS COL_TP, 1 AS SORT_ORD FROM DUAL UNION ALL
    SELECT 'mnuId',                     'VARCHAR',                 'IN',              2          FROM DUAL UNION ALL
    SELECT 'O_RESULT_CURSOR',           'PROC_RESULT',             'OUT',             3          FROM DUAL
  ) NEW
 WHERE NOT EXISTS (
   SELECT 1 FROM SCM_MGR.SCM_ADM_PROC_M P
    WHERE P.PROC_NM = 'PR_DM_DNM_EDI_CALLOFF_STATUS'
      AND P.COL_NM = NEW.COL_NM AND P.COL_TP_CD = NEW.COL_TP
 );

COMMIT;

