 WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_MSG_M X WHERE X.MSG_ID='MSG_API_DMF0008_UPDATE_HISTORY_GET' AND X.LANG_CD='KO');

PROMPT === BLOCK 2 : API_M (1 건) ===
INSERT INTO SCM_MGR.SCM_ADM_API_M (API_ID, API_TP_CD, API_MSG_ID, API_MSG_DESC, API_URL, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'P_DMF0008_UPDATE_HISTORY_GET', 'PROC_SELECT', 'MSG_API_DMF0008_UPDATE_HISTORY_GET', 'Update History 조회', 'DMF0008_GET_UPDATE_HISTORY', 'Y', 'admin', SYSDATE, 'admin', SYSDATE FROM DUAL
 WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_API_M X WHERE X.API_ID='P_DMF0008_UPDATE_HISTORY_GET');

PROMPT === BLOCK 3 : BTN_MPG (1 건) ===
INSERT INTO SCM_MGR.SCM_ADM_MNU_BTN_MPG_M (MNU_ID, SHT_NM, MNU_BTN_CD, API_ID, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'DMF0008', 'updateHistory', 'SEARCH', 'P_DMF0008_UPDATE_HISTORY_GET', 'Y', 'admin', SYSDATE, 'admin', SYSDATE FROM DUAL
 WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M X WHERE X.MNU_ID='DMF0008' AND X.SHT_NM='updateHistory' AND X.MNU_BTN_CD='SEARCH');

PROMPT === BLOCK 4 : PROC_M (3 row) ===
INSERT INTO SCM_MGR.SCM_ADM_PROC_M (PROC_NM, COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT NEW.PROC_NM, NEW.COL_NM, NEW.DATA_TP_CD, NEW.COL_TP_CD, NEW.SORT_ORD, 'admin', SYSDATE, 'admin', SYSDATE
  FROM (
    SELECT 'DMF0008_GET_UPDATE_HISTORY' AS PROC_NM, 'sesUserId' AS COL_NM, 'VARCHAR' AS DATA_TP_CD, 'IN'  AS COL_TP_CD, 1 AS SORT_ORD FROM DUAL UNION ALL
    SELECT 'DMF0008_GET_UPDATE_HISTORY',           'mnuId',                'VARCHAR',              'IN',                2                FROM DUAL UNION ALL
    SELECT 'DMF0008_GET_UPDATE_HISTORY',           'o_rc1',                'CURSOR',               'OUT',               3                FROM DUAL
  ) NEW
 WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_PROC_M X WHERE X.PROC_NM=NEW.PROC_NM AND X.COL_NM=NEW.COL_NM AND X.COL_TP_CD=NEW.COL_TP_CD);

PROMPT === BLOCK 5 : GUEST 권한 (1 건) ===
INSERT INTO SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M (USER_GR_ID, MNU_ID, SHT_NM, MNU_BTN_CD, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
