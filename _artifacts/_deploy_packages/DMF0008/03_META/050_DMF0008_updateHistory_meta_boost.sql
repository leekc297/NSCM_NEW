UNION ALL SELECT 'API_M',   COUNT(*) FROM SCM_MGR.SCM_ADM_API_M WHERE API_ID='P_DMF0008_UPDATE_HISTORY_GET'
UNION ALL SELECT 'BTN_MPG', COUNT(*) FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID='DMF0008' AND SHT_NM='updateHistory'
UNION ALL SELECT 'PROC_M',  COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M WHERE PROC_NM='DMF0008_GET_UPDATE_HISTORY'
UNION ALL SELECT 'GUEST',   COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE USER_GR_ID='GUEST' AND MNU_ID='DMF0008' AND SHT_NM='updateHistory';

