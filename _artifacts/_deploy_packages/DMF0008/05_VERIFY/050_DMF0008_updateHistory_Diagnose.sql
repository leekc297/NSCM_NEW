PROMPT === [D1] SP 본문 위임 chain 확인 (wrapper → DMF0000) ===
SELECT NAME, LINE, TEXT
  FROM USER_SOURCE
 WHERE NAME='DMF0008_GET_UPDATE_HISTORY'
   AND TEXT LIKE '%DMF0000%';
-- 기대: 'SCM_MGR.DMF0000_GET_UPDATE_HISTORY' 호출 라인 발견

PROMPT === [D2] 위임 대상 DMF0000_GET_UPDATE_HISTORY 존재 + VALID ===
SELECT OBJECT_NAME, STATUS FROM USER_OBJECTS WHERE OBJECT_TYPE='PROCEDURE' AND OBJECT_NAME='DMF0000_GET_UPDATE_HISTORY';
-- 기대: 1 row + VALID

PROMPT === [D3] SCM_SYS_LOG_BATCH 데이터 존재 (조회 결과 의존) ===
SELECT COUNT(*) AS CNT, MIN(LAST_UPDATE_DATE) AS MIN_DT, MAX(LAST_UPDATE_DATE) AS MAX_DT
  FROM SCM_MGR.SCM_SYS_LOG_BATCH
 WHERE PROGRAM_NAME='PR_DM_DNM_EDI_CALLOFF_STATUS';

PROMPT === [D4] FE sheetName ↔ BTN_MPG SHT_NM 매칭 ===
SELECT BTN.SHT_NM, BTN.MNU_BTN_CD, A.API_URL
  FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M BTN, SCM_MGR.SCM_ADM_API_M A
 WHERE BTN.MNU_ID='DMF0008' AND BTN.SHT_NM='updateHistory' AND A.API_ID=BTN.API_ID;
-- 기대: SHT_NM=updateHistory / MNU_BTN_CD=SEARCH / API_URL=DMF0008_GET_UPDATE_HISTORY

PROMPT === [D5] 실행 sanity ===
DECLARE
  C SYS_REFCURSOR;
  V_SDATE VARCHAR2(50); V_EDATE VARCHAR2(50); V_BY VARCHAR2(100);
BEGIN
  DMF0008_GET_UPDATE_HISTORY('minyonglee1', 'DMF0008', C);
  FETCH C INTO V_SDATE, V_EDATE, V_BY;
  CLOSE C;
  DBMS_OUTPUT.PUT_LINE('SDATE='||NVL(V_SDATE,'(null)'));
  DBMS_OUTPUT.PUT_LINE('EDATE='||NVL(V_EDATE,'(null)'));
  DBMS_OUTPUT.PUT_LINE('UPDATED_BY='||NVL(V_BY,'(null)'));
END;
