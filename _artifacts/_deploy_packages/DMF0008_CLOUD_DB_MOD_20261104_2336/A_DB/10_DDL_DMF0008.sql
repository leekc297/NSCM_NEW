        ELSIF SQLCODE <> -20901 THEN
            DBMS_OUTPUT.PUT_LINE('ERROR   ' || p_tab || ' : ' || SQLERRM || ' :: ' || SUBSTR(p_sql, 1, 200));
        END IF;
        RAISE;
    END;

