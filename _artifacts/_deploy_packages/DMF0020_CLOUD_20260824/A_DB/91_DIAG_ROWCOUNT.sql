--        GTT 는 세션 전용이라 §2 를 다른 세션에서 돌리면 전부 0 이 나온다.
--     ⚠ 조회 전용이다. 원장을 바꾸지 않는다.
--     ⚠ 아래 UI_USER 를 **실제로 화면에서 조회한 계정**으로 바꿀 것.
--        DB 접속 계정(SCM_MGR 등)을 쓰면 부서권한 집합이 비어 GT_DMF0020_DEPT_AUTH 가 0 이 된다.
