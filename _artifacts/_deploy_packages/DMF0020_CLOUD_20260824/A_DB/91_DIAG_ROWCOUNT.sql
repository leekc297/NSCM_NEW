--     "조회가 몇 건이냐" 가 아니라 **어느 단계에서 줄어드느냐** 를 본다.
--     EXPECTED 열 = 사내 실측값(2026-08-24). ACTUAL 이 크게 다른 첫 행이 원인 지점이다.
--
--   실행 방법
