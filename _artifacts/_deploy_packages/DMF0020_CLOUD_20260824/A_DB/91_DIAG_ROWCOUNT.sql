WITH exp (ORD, K, V) AS (
  SELECT  1, 'SCM_MST_FUTURE_PRICE (기간내)'          , 421731 FROM DUAL UNION ALL
  SELECT  2, 'SCM_MST_FUTURE_PRICE (LOC, 기간내)'     , 140577 FROM DUAL UNION ALL
  SELECT  3, 'SCM_MST_SITE_ITEM'                      ,  39538 FROM DUAL UNION ALL
  SELECT  4, 'SCM_MST_SITE_ITEM (VALID_YN=Y)'         ,  38306 FROM DUAL UNION ALL
  SELECT  5, 'SCM_MST_SITE'                           ,   1001 FROM DUAL UNION ALL
  SELECT  6, 'SCM_MST_SITE (VALID_YN=Y)'              ,    785 FROM DUAL UNION ALL
  SELECT  7, 'SCM_MST_SITE (SITE_TYPE<>PLANT)'        ,    970 FROM DUAL UNION ALL
  SELECT  8, 'SCM_MST_PROJECT'                        ,   4776 FROM DUAL UNION ALL
  SELECT  9, 'DM_MST_ITEM_SINGLE_V'                   ,  52044 FROM DUAL UNION ALL
  SELECT 10, 'SCM_MST_ITEM_SN (전체)'                 , 789067 FROM DUAL UNION ALL
  SELECT 11, 'DM_MST_CUSTOMER_MODEL (VALID_YN=Y)'     ,     25 FROM DUAL UNION ALL
  SELECT 12, 'SCM_MST_SITE_CUSTOMER (REP_YN=Y)'       ,    645 FROM DUAL UNION ALL
  SELECT 13, 'SCM_MST_SSO_DEPT_INFO (전체)'           ,  21159 FROM DUAL UNION ALL
  SELECT 14, 'SCM_MST_SSO_USER_INFO (전체)'           , 128611 FROM DUAL UNION ALL
  SELECT 15, 'SHEET_MEASURE (DMF0020/Sales Price)'    ,      4 FROM DUAL UNION ALL
  SELECT 16, 'SHEET_COLUMNS (DMF0020)'                ,     77 FROM DUAL UNION ALL
  SELECT 17, 'LOOKUP PM_TEAM_MAPPING (VALID_YN=Y)'    ,    370 FROM DUAL UNION ALL
  SELECT 18, 'LOOKUP GET_ADMIN_GROUP (VALID_YN=Y)'    ,      8 FROM DUAL),
act (K, V) AS (
  SELECT 'SCM_MST_FUTURE_PRICE (기간내)', COUNT(*) FROM SCM_MGR.SCM_MST_FUTURE_PRICE
    WHERE DIVISION_ID='82' AND YYYYMMDD BETWEEN '20260701' AND '20270630'
  UNION ALL SELECT 'SCM_MST_FUTURE_PRICE (LOC, 기간내)', COUNT(*) FROM SCM_MGR.SCM_MST_FUTURE_PRICE
    WHERE DIVISION_ID='82' AND MEASURE='LOC' AND YYYYMMDD BETWEEN '20260701' AND '20270630'
  UNION ALL SELECT 'SCM_MST_SITE_ITEM', COUNT(*) FROM SCM_MGR.SCM_MST_SITE_ITEM WHERE DIVISION_ID='82'
  UNION ALL SELECT 'SCM_MST_SITE_ITEM (VALID_YN=Y)', COUNT(*) FROM SCM_MGR.SCM_MST_SITE_ITEM
    WHERE DIVISION_ID='82' AND VALID_YN='Y'
  UNION ALL SELECT 'SCM_MST_SITE', COUNT(*) FROM SCM_MGR.SCM_MST_SITE WHERE DIVISION_ID='82'
  UNION ALL SELECT 'SCM_MST_SITE (VALID_YN=Y)', COUNT(*) FROM SCM_MGR.SCM_MST_SITE
    WHERE DIVISION_ID='82' AND VALID_YN='Y'
  UNION ALL SELECT 'SCM_MST_SITE (SITE_TYPE<>PLANT)', COUNT(*) FROM SCM_MGR.SCM_MST_SITE
    WHERE DIVISION_ID='82' AND SITE_TYPE<>'PLANT'
  UNION ALL SELECT 'SCM_MST_PROJECT', COUNT(*) FROM SCM_MGR.SCM_MST_PROJECT WHERE DIVISION_ID='82'
  UNION ALL SELECT 'DM_MST_ITEM_SINGLE_V', COUNT(*) FROM SCM_MGR.DM_MST_ITEM_SINGLE_V WHERE DIVISION_ID='82'
  UNION ALL SELECT 'SCM_MST_ITEM_SN (전체)', COUNT(*) FROM SCM_MGR.SCM_MST_ITEM_SN
  UNION ALL SELECT 'DM_MST_CUSTOMER_MODEL (VALID_YN=Y)', COUNT(*) FROM SCM_MGR.DM_MST_CUSTOMER_MODEL
    WHERE DIVISION_ID='82' AND VALID_YN='Y'
  UNION ALL SELECT 'SCM_MST_SITE_CUSTOMER (REP_YN=Y)', COUNT(*) FROM SCM_MGR.SCM_MST_SITE_CUSTOMER
    WHERE DIVISION_ID='82' AND REP_YN='Y'
  UNION ALL SELECT 'SCM_MST_SSO_DEPT_INFO (전체)', COUNT(*) FROM SCM_MGR.SCM_MST_SSO_DEPT_INFO
  UNION ALL SELECT 'SCM_MST_SSO_USER_INFO (전체)', COUNT(*) FROM SCM_MGR.SCM_MST_SSO_USER_INFO
  UNION ALL SELECT 'SHEET_MEASURE (DMF0020/Sales Price)', COUNT(*) FROM SCM_MGR.SCM_MST_SHEET_MEASURE
    WHERE PROGRAM_ID='DMF0020' AND SHEET_NAME='Sales Price'
  UNION ALL SELECT 'SHEET_COLUMNS (DMF0020)', COUNT(*) FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
    WHERE PROGRAM_ID='DMF0020'
  UNION ALL SELECT 'LOOKUP PM_TEAM_MAPPING (VALID_YN=Y)', COUNT(*) FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
    WHERE LOOKUP_TYPE='PM_TEAM_MAPPING' AND VALID_YN='Y'
  UNION ALL SELECT 'LOOKUP GET_ADMIN_GROUP (VALID_YN=Y)', COUNT(*) FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
    WHERE LOOKUP_TYPE='GET_ADMIN_GROUP' AND VALID_YN='Y')
SELECT e.ORD, e.K AS ITEM, e.V AS EXPECTED_사내, a.V AS ACTUAL_클라우드,
       CASE WHEN a.V = 0                        THEN '⛔ 비어있음'
            WHEN a.V < e.V * 0.5                THEN '⛔ 절반 미만'
            WHEN a.V < e.V * 0.9                THEN '△ 10% 이상 적음'
            ELSE 'OK' END AS 판정
  FROM exp e JOIN act a ON a.K = e.K
 ORDER BY CASE WHEN a.V = 0 THEN 0 WHEN a.V < e.V*0.5 THEN 1 WHEN a.V < e.V*0.9 THEN 2 ELSE 3 END, e.ORD;


