       CASE WHEN a.V = 0         THEN '⛔ 여기서 끊김'
            WHEN a.V < e.V * 0.5 THEN '⛔ 절반 미만'
            ELSE 'OK' END AS 판정
  FROM exp e JOIN act a ON a.K = e.K ORDER BY e.ORD;


