SELECT B.SHT_NM, B.MNU_BTN_CD, A.API_URL,
       (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M P WHERE P.PROC_NM = A.API_URL) AS PROC_M_CNT
  FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M B
  JOIN SCM_MGR.SCM_ADM_API_M A ON A.API_ID = B.API_ID
 WHERE B.MNU_ID = 'DMF0020' AND B.MNU_BTN_CD = 'SEARCH'
 ORDER BY 1;


