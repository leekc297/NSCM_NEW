-- 03_CMBO_DMF0082_20260818.sql — 콤보 3본 (사내 원장 실값 스냅샷, 2026-08-18)
--  ① EndCustomerByDivisionDMF0082 : 그리드 End Customer 셀 콤보 — division 3분기
--     ((1) lookup 축 / (2) 40 SITE_ITEM owner 축 / (3) 81·82 = 조회조건과 동일한
--      SCM_MST_SITE.END_CUSTOMER 축 [E20260818-ENDCUST81])
--  ② SiteEndCustomerMapDMF0082 : 신규 — FE 표시/키 분리용 site→End Customer 맵
--     (그리드 END_CUSTOMER 표시값을 조회조건 축으로 파생 — ForecastPrice.tsx ENDCUSTDISP)
--  ③ (공유 ⚠) EndCustomer : 조회조건 콤보 정렬 — ORDER BY DIVISION_ID, DEPT_ID, CODE
--     → DIVISION_ID, NAME, CODE (팀 우선 정렬이 드롭다운에서 무작위로 보이던 신고 정정).
--     ⚠ 20개 화면 공유 — 적용 전 클라우드 등록본과 대조 권장.

MERGE INTO SCM_MGR.SCM_ADM_CMBO_SQL_M T
USING (SELECT 'EndCustomerByDivisionDMF0082' AS SQL_ID FROM DUAL) S ON (T.SQL_ID = S.SQL_ID)
WHEN MATCHED THEN UPDATE SET SQL_DTL_CTN = 'SELECT DISTINCT CODE, NAME FROM (
  /* (1) END_CUSTOMER lookup axis - div 40 표기 원천 [E20260814-ENDCUST] */
  SELECT L.SEGMENT2 AS CODE, NVL(L.SEGMENT3, L.SEGMENT2) AS NAME
  FROM   SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL L
  WHERE  L.LOOKUP_TYPE = ''END_CUSTOMER'' AND L.VALID_YN = ''Y'' AND L.SEGMENT2 <> ''-''
  AND    ( NVL(TRIM(@divisionId), ''-'') = ''-'' OR L.SEGMENT1 = TRIM(@divisionId) )
  UNION ALL
  /* (2) div 40 : SITE_ITEM owner axis (AS-IS EndCustomerByDivision40) */
  SELECT A.PROJECT_CODE AS CODE, NVL(D.SEGMENT3, A.PROJECT_CODE) AS NAME
  FROM   SCM_MGR.SCM_MST_SITE_ITEM A
  JOIN   SCM_MGR.SCM_MST_SSO_USER_INFO B ON B.USER_ID = TRIM(REGEXP_SUBSTR(A.OWNER, ''[^,]+'', 1, 1))
  JOIN   SCM_MGR.SCM_MST_SSO_DEPT_INFO C ON C.DEPT_ID = B.DEPT_ID
  LEFT JOIN SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL D
         ON A.DIVISION_ID = D.SEGMENT1 AND A.PROJECT_CODE = D.SEGMENT2
        AND D.LOOKUP_TYPE = ''END_CUSTOMER'' AND D.VALID_YN = ''Y''
  WHERE  A.VALID_YN = ''Y'' AND TRIM(@divisionId) = ''40'' AND A.DIVISION_ID = ''40''
  UNION ALL
  /* (3) div 81/82 : 조회조건과 동일 축 = SCM_MST_SITE.END_CUSTOMER (AS-IS BigFilter
         EndCustomerByDivision 의 비40 분기 원문과 동일) [E20260818-ENDCUST81] */
  SELECT S.END_CUSTOMER AS CODE, NVL(D.SEGMENT3, S.END_CUSTOMER) AS NAME
  FROM   SCM_MGR.SCM_MST_SITE S
  LEFT JOIN SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL D
         ON D.SEGMENT1 = S.DIVISION_ID AND D.SEGMENT2 = S.END_CUSTOMER
        AND D.LOOKUP_TYPE = ''END_CUSTOMER'' AND D.VALID_YN = ''Y''
  WHERE  S.END_CUSTOMER IS NOT NULL AND NVL(TRIM(@divisionId), ''-'') <> ''-''
  AND    S.DIVISION_ID = TRIM(@divisionId) AND TRIM(@divisionId) <> ''40''
) ORDER BY NAME', USE_YN = 'Y',
  LAST_UPDATED_BY = 'admin', LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (SQL_ID, MDU_DIVS_CD, SQL_NM, SQL_DTL_CTN, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES ('EndCustomerByDivisionDMF0082', 'DM', 'DMF0082 End Customer by division (END_CUSTOMER lookup)', 'SELECT DISTINCT CODE, NAME FROM (
  /* (1) END_CUSTOMER lookup axis - div 40 표기 원천 [E20260814-ENDCUST] */
  SELECT L.SEGMENT2 AS CODE, NVL(L.SEGMENT3, L.SEGMENT2) AS NAME
  FROM   SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL L
  WHERE  L.LOOKUP_TYPE = ''END_CUSTOMER'' AND L.VALID_YN = ''Y'' AND L.SEGMENT2 <> ''-''
  AND    ( NVL(TRIM(@divisionId), ''-'') = ''-'' OR L.SEGMENT1 = TRIM(@divisionId) )
  UNION ALL
  /* (2) div 40 : SITE_ITEM owner axis (AS-IS EndCustomerByDivision40) */
  SELECT A.PROJECT_CODE AS CODE, NVL(D.SEGMENT3, A.PROJECT_CODE) AS NAME
  FROM   SCM_MGR.SCM_MST_SITE_ITEM A
  JOIN   SCM_MGR.SCM_MST_SSO_USER_INFO B ON B.USER_ID = TRIM(REGEXP_SUBSTR(A.OWNER, ''[^,]+'', 1, 1))
  JOIN   SCM_MGR.SCM_MST_SSO_DEPT_INFO C ON C.DEPT_ID = B.DEPT_ID
  LEFT JOIN SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL D
         ON A.DIVISION_ID = D.SEGMENT1 AND A.PROJECT_CODE = D.SEGMENT2
        AND D.LOOKUP_TYPE = ''END_CUSTOMER'' AND D.VALID_YN = ''Y''
  WHERE  A.VALID_YN = ''Y'' AND TRIM(@divisionId) = ''40'' AND A.DIVISION_ID = ''40''
  UNION ALL
  /* (3) div 81/82 : 조회조건과 동일 축 = SCM_MST_SITE.END_CUSTOMER (AS-IS BigFilter
         EndCustomerByDivision 의 비40 분기 원문과 동일) [E20260818-ENDCUST81] */
  SELECT S.END_CUSTOMER AS CODE, NVL(D.SEGMENT3, S.END_CUSTOMER) AS NAME
  FROM   SCM_MGR.SCM_MST_SITE S
  LEFT JOIN SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL D
         ON D.SEGMENT1 = S.DIVISION_ID AND D.SEGMENT2 = S.END_CUSTOMER
        AND D.LOOKUP_TYPE = ''END_CUSTOMER'' AND D.VALID_YN = ''Y''
  WHERE  S.END_CUSTOMER IS NOT NULL AND NVL(TRIM(@divisionId), ''-'') <> ''-''
  AND    S.DIVISION_ID = TRIM(@divisionId) AND TRIM(@divisionId) <> ''40''
) ORDER BY NAME', 'Y', 'admin', SYSDATE, 'admin', SYSDATE);

