USING (SELECT 'EndCustomer' AS SQL_ID FROM DUAL) S ON (T.SQL_ID = S.SQL_ID)
WHEN MATCHED THEN UPDATE SET SQL_DTL_CTN = 'SELECT DISTINCT A.DIVISION_ID, B.DEPT_ID,        CASE WHEN A.DIVISION_ID = ''40'' THEN B.PROJECT_CODE             ELSE A.END_CUSTOMER        END AS CODE,        NVL(D.SEGMENT3, CASE WHEN A.DIVISION_ID = ''40'' THEN B.PROJECT_CODE                             ELSE A.END_CUSTOMER                        END) AS NAME FROM SCM_MGR.SCM_MST_SITE A LEFT OUTER JOIN SCM_MGR.SCM_MST_SITE_ITEM B              ON A.DIVISION_ID = B.DIVISION_ID             AND A.SCM_SITE_ID = B.SCM_SITE_ID LEFT OUTER JOIN SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL D              ON A.DIVISION_ID = D.SEGMENT1             AND A.END_CUSTOMER = D.SEGMENT2             AND D.LOOKUP_TYPE = ''END_CUSTOMER''             AND D.VALID_YN = ''Y'' WHERE A.DIVISION_ID IN (     SELECT DISTINCT UNIT_ID AS DIVISION_ID     FROM SCM_MGR.SCM_ADM_USER_GR_UNIT_AUTH_MPG_M     WHERE USER_ID = @sesUserId       AND UNIT_TP_CD = ''D'' ) AND A.END_CUSTOMER IS NOT NULL ORDER BY DIVISION_ID, NAME, CODE', USE_YN = 'Y',
  LAST_UPDATED_BY = 'admin', LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (SQL_ID, MDU_DIVS_CD, SQL_NM, SQL_DTL_CTN, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES ('EndCustomer', 'DM', 'EndCustomer', 'SELECT DISTINCT A.DIVISION_ID, B.DEPT_ID,        CASE WHEN A.DIVISION_ID = ''40'' THEN B.PROJECT_CODE             ELSE A.END_CUSTOMER        END AS CODE,        NVL(D.SEGMENT3, CASE WHEN A.DIVISION_ID = ''40'' THEN B.PROJECT_CODE                             ELSE A.END_CUSTOMER                        END) AS NAME FROM SCM_MGR.SCM_MST_SITE A LEFT OUTER JOIN SCM_MGR.SCM_MST_SITE_ITEM B              ON A.DIVISION_ID = B.DIVISION_ID             AND A.SCM_SITE_ID = B.SCM_SITE_ID LEFT OUTER JOIN SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL D              ON A.DIVISION_ID = D.SEGMENT1             AND A.END_CUSTOMER = D.SEGMENT2             AND D.LOOKUP_TYPE = ''END_CUSTOMER''             AND D.VALID_YN = ''Y'' WHERE A.DIVISION_ID IN (     SELECT DISTINCT UNIT_ID AS DIVISION_ID     FROM SCM_MGR.SCM_ADM_USER_GR_UNIT_AUTH_MPG_M     WHERE USER_ID = @sesUserId       AND UNIT_TP_CD = ''D'' ) AND A.END_CUSTOMER IS NOT NULL ORDER BY DIVISION_ID, NAME, CODE', 'Y', 'admin', SYSDATE, 'admin', SYSDATE);

