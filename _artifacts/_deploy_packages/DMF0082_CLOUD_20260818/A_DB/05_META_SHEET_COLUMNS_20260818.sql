--   오늘 왕복 수정(EndCustomer 시도 후 원복) 결과 값은 종전과 동일(EndCustomerByDivisionDMF0082).
--   클라우드가 08-14 패키지 미적용 상태일 가능성 대비 UPDATE 로 동봉 (INSERT 불요 — 기존재 화면).
UPDATE SCM_MGR.SCM_MST_SHEET_COLUMNS
   SET CELL_COMBO_DATA_TYPE = 'EndCustomerByDivisionDMF0082',
       LAST_UPDATED_BY = 'admin', LAST_UPDATE_DATE = SYSDATE
 WHERE PROGRAM_ID = 'DMF0082' AND SHEET_NAME = 'FcstNPrice' AND COLUMN_NAME = 'END_CUSTOMER';
COMMIT;
