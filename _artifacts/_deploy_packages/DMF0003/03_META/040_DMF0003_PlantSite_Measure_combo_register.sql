 *              : DMF0003 Insert row 의 SetCellTypeCombo dtPlantSite / dtMeasure 변환
 * 사용자 보고  : 2026-06-07 입력 항목 dropdown 전체 적용 안 됨
 * AS-IS 매핑   : DMF0003_1_MktFcst.cs L1884 dtPlantSite / L1928 dtMeasure
