-- PlantSite : SCM_MST_SITE 의 SITE_TYPE='PLANT' + 권한 div
MERGE INTO SCM_MGR.SCM_ADM_CMBO_SQL_M T
USING (SELECT 'PlantSite' AS SQL_ID FROM DUAL) S
   ON (T.SQL_ID = S.SQL_ID)
 WHEN NOT MATCHED THEN
   INSERT (SQL_ID, MDU_DIVS_CD, SQL_NM, SQL_DTL_CTN, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
   VALUES ('PlantSite', '40', 'Plant Site by Division',
           'SELECT DISTINCT A.DIVISION_ID, A.SCM_SITE_ID AS CODE, A.SCM_SITE_ID AS NAME FROM SCM_MGR.SCM_MST_SITE A WHERE A.SITE_TYPE = ''PLANT'' AND A.DIVISION_ID IN (SELECT UNIT_ID FROM SCM_MGR.SCM_ADM_USER_GR_UNIT_AUTH_MPG_M WHERE USER_ID = @sesUserId AND UNIT_TP_CD = ''D'') AND A.VALID_YN = ''Y'' ORDER BY DIVISION_ID, CODE',
           'Y', 'admin', SYSDATE, 'admin', SYSDATE)
 WHEN MATCHED THEN
   UPDATE SET T.SQL_DTL_CTN = 'SELECT DISTINCT A.DIVISION_ID, A.SCM_SITE_ID AS CODE, A.SCM_SITE_ID AS NAME FROM SCM_MGR.SCM_MST_SITE A WHERE A.SITE_TYPE = ''PLANT'' AND A.DIVISION_ID IN (SELECT UNIT_ID FROM SCM_MGR.SCM_ADM_USER_GR_UNIT_AUTH_MPG_M WHERE USER_ID = @sesUserId AND UNIT_TP_CD = ''D'') AND A.VALID_YN = ''Y'' ORDER BY DIVISION_ID, CODE',
                 T.LAST_UPDATED_BY = 'admin',
                 T.LAST_UPDATE_DATE = SYSDATE;

-- Measure : DMF0003 MKT FCST 의 12개 Measure (AS-IS DMF0003_1_MktFcst.cs L4916 분석 기반)
MERGE INTO SCM_MGR.SCM_ADM_CMBO_SQL_M T
USING (SELECT 'Measure' AS SQL_ID FROM DUAL) S
   ON (T.SQL_ID = S.SQL_ID)
 WHEN NOT MATCHED THEN
   INSERT (SQL_ID, MDU_DIVS_CD, SQL_NM, SQL_DTL_CTN, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
   VALUES ('Measure', '40', 'Measure list for MKT FCST',
           'SELECT ''MKT_FCST'' AS CODE, ''MKT FCST'' AS NAME FROM DUAL UNION ALL SELECT ''MKT_FCST_RP'', ''MKT FCST (Result)'' FROM DUAL UNION ALL SELECT ''RTF'', ''RTF'' FROM DUAL UNION ALL SELECT ''RTF_RP'', ''RTF (Result)'' FROM DUAL UNION ALL SELECT ''IMM'', ''Immediate'' FROM DUAL UNION ALL SELECT ''CUST_FCST'', ''Customer FCST'' FROM DUAL UNION ALL SELECT ''CUST_FCST_EDI'', ''Customer FCST EDI'' FROM DUAL UNION ALL SELECT ''CUST_FCST_ORG'', ''Customer FCST Org'' FROM DUAL UNION ALL SELECT ''CUST_PSI'', ''Customer PSI'' FROM DUAL UNION ALL SELECT ''MKT_PSI'', ''MKT PSI'' FROM DUAL UNION ALL SELECT ''CAR_FCST'', ''Car FCST'' FROM DUAL UNION ALL SELECT ''VMI'', ''VMI Inv'' FROM DUAL',
           'Y', 'admin', SYSDATE, 'admin', SYSDATE)
 WHEN MATCHED THEN
   UPDATE SET T.SQL_DTL_CTN = 'SELECT ''MKT_FCST'' AS CODE, ''MKT FCST'' AS NAME FROM DUAL UNION ALL SELECT ''MKT_FCST_RP'', ''MKT FCST (Result)'' FROM DUAL UNION ALL SELECT ''RTF'', ''RTF'' FROM DUAL UNION ALL SELECT ''RTF_RP'', ''RTF (Result)'' FROM DUAL UNION ALL SELECT ''IMM'', ''Immediate'' FROM DUAL UNION ALL SELECT ''CUST_FCST'', ''Customer FCST'' FROM DUAL UNION ALL SELECT ''CUST_FCST_EDI'', ''Customer FCST EDI'' FROM DUAL UNION ALL SELECT ''CUST_FCST_ORG'', ''Customer FCST Org'' FROM DUAL UNION ALL SELECT ''CUST_PSI'', ''Customer PSI'' FROM DUAL UNION ALL SELECT ''MKT_PSI'', ''MKT PSI'' FROM DUAL UNION ALL SELECT ''CAR_FCST'', ''Car FCST'' FROM DUAL UNION ALL SELECT ''VMI'', ''VMI Inv'' FROM DUAL',
                 T.LAST_UPDATED_BY = 'admin',
                 T.LAST_UPDATE_DATE = SYSDATE;

COMMIT;

