-- 00_PRECHECK — 조회 전용. [E20261014-DMF0005SCONM] 적용 전 상태 판정 (전체 F5, 값 입력 없음)
-- * [L0] 접속 DB · PKG_DMF0005 상태 · LAST_DDL · BODY 줄 수 / 글자 수
-- * [L1] 선행 패치 NOPUSH 마커 = 1 이어야 한다 (없으면 DMF0005_NOPUSH_CLOUD_20261014 먼저)
-- * [L2] 앵커 2곳 — ① BASE 시작 `BASE AS (` 다음 줄 `SELECT` ② Sold-To ON 절 `AND (P_DIVISION_ID = '82' OR NVL(SC.VALID_YN, 'Y') = 'Y')` — 각각 정확히 1곳
-- * [L3] 이 패치 마커 — 적용 전 0 (적용 뒤 2)
-- * [L4] 지금 조회 문장을 실행 중인 세션 · 패키지 안에 있는 세션 (있으면 끝나거나 멈춘 뒤 10 실행)
SET LINESIZE 300 PAGESIZE 200
SELECT 'L0' CHK, SYS_CONTEXT('USERENV','DB_NAME') DB_NAME, SYS_CONTEXT('USERENV','INSTANCE_NAME') INST, TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI:SS') NOW FROM DUAL;
SELECT 'L0' CHK, O.OBJECT_TYPE, O.STATUS, TO_CHAR(O.LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL,
       (SELECT COUNT(*) || '줄 / ' || SUM(LENGTH(TEXT)) || '자' FROM USER_SOURCE S WHERE S.NAME = O.OBJECT_NAME AND S.TYPE = O.OBJECT_TYPE) BODY_FP
  FROM USER_OBJECTS O WHERE O.OBJECT_NAME = 'PKG_DMF0005' ORDER BY O.OBJECT_TYPE;
SELECT 'L1 선행 NOPUSH' CHK, COUNT(*) N, CASE WHEN COUNT(*) = 1 THEN 'PASS' ELSE '❌ 선행 패치(DMF0005_NOPUSH_CLOUD_20261014) 먼저 적용' END JUDGE
  FROM USER_SOURCE WHERE NAME = 'PKG_DMF0005' AND TYPE = 'PACKAGE BODY' AND TEXT LIKE '%E20261014-DMF0005NOPUSH%';
SELECT 'L2 앵커① BASE' CHK, COUNT(*) N, MIN(S.LINE) LINE, CASE WHEN COUNT(*) = 1 THEN 'PASS' ELSE '❌ 1곳이 아님 → 중단' END JUDGE
  FROM USER_SOURCE S
 WHERE S.NAME = 'PKG_DMF0005' AND S.TYPE = 'PACKAGE BODY' AND RTRIM(S.TEXT, CHR(10) || CHR(13)) = '        SELECT'
   AND EXISTS (SELECT 1 FROM USER_SOURCE P WHERE P.NAME = S.NAME AND P.TYPE = S.TYPE AND P.LINE = S.LINE - 1 AND RTRIM(P.TEXT, CHR(10) || CHR(13)) = '    BASE AS (')
   AND EXISTS (SELECT 1 FROM USER_SOURCE P WHERE P.NAME = S.NAME AND P.TYPE = S.TYPE AND P.LINE = S.LINE + 1 AND RTRIM(P.TEXT, CHR(10) || CHR(13)) = '              SI.DIVISION_ID');
SELECT 'L2 앵커② ON절' CHK, COUNT(*) N, MIN(LINE) LINE, CASE WHEN COUNT(*) = 1 THEN 'PASS' ELSE '❌ 1곳이 아님 → 중단' END JUDGE
  FROM USER_SOURCE WHERE NAME = 'PKG_DMF0005' AND TYPE = 'PACKAGE BODY'
   AND RTRIM(TEXT, CHR(10) || CHR(13)) = '         AND (P_DIVISION_ID = ''82'' OR NVL(SC.VALID_YN, ''Y'') = ''Y'')';
SELECT 'L2 앵커② 문맥' CHK, LINE, RTRIM(TEXT, CHR(10) || CHR(13)) TXT FROM USER_SOURCE WHERE NAME = 'PKG_DMF0005' AND TYPE = 'PACKAGE BODY'
   AND LINE BETWEEN (SELECT MIN(LINE) - 6 FROM USER_SOURCE WHERE NAME = 'PKG_DMF0005' AND TYPE = 'PACKAGE BODY' AND TEXT LIKE '%NVL(SC.VALID_YN, ''Y'') = ''Y''%')
                AND (SELECT MIN(LINE) + 1 FROM USER_SOURCE WHERE NAME = 'PKG_DMF0005' AND TYPE = 'PACKAGE BODY' AND TEXT LIKE '%NVL(SC.VALID_YN, ''Y'') = ''Y''%')
 ORDER BY LINE;
SELECT 'L3 마커' CHK, COUNT(*) N, CASE WHEN COUNT(*) = 0 THEN '미적용 (기대)' WHEN COUNT(*) = 2 THEN '적용됨 — 10 재실행은 가드로 무동작' ELSE '⚠ 부분 적용 — 99 원복 후 재시도' END JUDGE
  FROM USER_SOURCE WHERE NAME = 'PKG_DMF0005' AND TYPE = 'PACKAGE BODY' AND TEXT LIKE '%E20261014-DMF0005SCONM%';
SELECT 'L4 실행중' CHK, S.INST_ID, S.SID, S.SERIAL#, S.USERNAME, S.MACHINE, S.MODULE, S.LAST_CALL_ET CALL_SEC, S.SQL_ID
  FROM GV$SESSION S
 WHERE S.TYPE = 'USER' AND S.STATUS = 'ACTIVE'
   AND (S.PLSQL_ENTRY_OBJECT_ID IN (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME = 'PKG_DMF0005')
        OR S.SQL_ID IN (SELECT SQL_ID FROM GV$SQL WHERE SQL_TEXT LIKE 'WITH ITEM_AGG AS%'))
 ORDER BY S.LAST_CALL_ET DESC;
