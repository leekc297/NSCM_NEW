-- 02_CMBO_SALESPLANITEMID.sql — Insert Model = SALES_PLAN_ITEM_ID lookup (통합테스트 1st No.61-③, 멱등 MERGE)
SET DEFINE OFF
MERGE INTO SCM_MGR.SCM_ADM_CMBO_SQL_M T
USING (SELECT 'SalesPlanItemId' AS SQL_ID FROM DUAL) S ON (T.SQL_ID = S.SQL_ID)
WHEN MATCHED THEN UPDATE SET SQL_NM = 'DMF0021 Insert Model — SALES_PLAN_ITEM_ID lookup (No.61-3)', USE_YN = 'Y',
     SQL_DTL_CTN = TO_CLOB('SELECT CODE, NAME, DIVISION_ID
  FROM (
    SELECT B.SEGMENT1 AS CODE
         , B.SEGMENT2 AS NAME
         , B.SEGMENT3 AS DIVISION_ID
         , B.DISPLAY_SEQ
         , ROW_NUMBER() OVER (PARTITION BY B.SEGMENT1
               ORDER BY CASE WHEN B.SEGMENT3 = @divisionId THEN 0 ELSE 1 END, B.DISPLAY_SEQ) AS RN
      FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL B
     WHERE B.LOOKUP_TYPE = ''SALES_PLAN_ITEM_ID''
       AND B.VALID_YN    = ''Y''
       AND (B.SEGMENT3 = @divisionId OR B.SEGMENT3 = SUBSTR(@divisionId, 1, 2))
  )
 WHERE RN = 1
 ORDER BY DISPLAY_SEQ, CODE'),
     LAST_UPDATED_BY = 'admin', LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (SQL_ID, MDU_DIVS_CD, SQL_NM, SQL_DTL_CTN, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES ('SalesPlanItemId', 'DM', 'DMF0021 Insert Model — SALES_PLAN_ITEM_ID lookup (No.61-3)', TO_CLOB('SELECT CODE, NAME, DIVISION_ID
  FROM (
    SELECT B.SEGMENT1 AS CODE
         , B.SEGMENT2 AS NAME
         , B.SEGMENT3 AS DIVISION_ID
         , B.DISPLAY_SEQ
         , ROW_NUMBER() OVER (PARTITION BY B.SEGMENT1
               ORDER BY CASE WHEN B.SEGMENT3 = @divisionId THEN 0 ELSE 1 END, B.DISPLAY_SEQ) AS RN
      FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL B
     WHERE B.LOOKUP_TYPE = ''SALES_PLAN_ITEM_ID''
       AND B.VALID_YN    = ''Y''
       AND (B.SEGMENT3 = @divisionId OR B.SEGMENT3 = SUBSTR(@divisionId, 1, 2))
  )
 WHERE RN = 1
 ORDER BY DISPLAY_SEQ, CODE'), 'Y', 'admin', SYSDATE, 'admin', SYSDATE);
COMMIT;
