/* SCP0096 저장 ORA-01407 보완 — 사전 확인(읽기 전용). 전체 F5 기준 오류 0.
 *  기대: SAVE PROC_M 9행 · SORT_ORD=8 = (COL_NM 'userIdList' 또는 'userId', VARCHAR, IN)
 *        ALL_ARGUMENTS 8번째 = P_USER_ID VARCHAR2 IN · API 'P_SCP0096_SAVE' 배선 1건(SCP0096/Shipment Working Day OSP/SAVE) */
SELECT PROC_NM, SORT_ORD, COL_NM, DATA_TP_CD, COL_TP_CD, LAST_UPDATED_BY, LAST_UPDATE_DATE
  FROM SCM_ADM_PROC_M
 WHERE PROC_NM = 'PKG_SCP0096.P_SCP0096_SAVE_SHIPMENT_WORKING_DAY_OSP'
 ORDER BY SORT_ORD;

SELECT POSITION, ARGUMENT_NAME, DATA_TYPE, IN_OUT
  FROM ALL_ARGUMENTS
 WHERE OWNER = 'SCM_MGR' AND PACKAGE_NAME = 'PKG_SCP0096'
   AND OBJECT_NAME = 'P_SCP0096_SAVE_SHIPMENT_WORKING_DAY_OSP' AND DATA_LEVEL = 0
 ORDER BY POSITION;

SELECT A.API_ID, A.API_URL, A.USE_YN, M.MNU_ID, M.SHT_NM, M.MNU_BTN_CD
  FROM SCM_ADM_API_M A
  LEFT JOIN SCM_ADM_MNU_BTN_MPG_M M ON M.API_ID = A.API_ID
 WHERE UPPER(A.API_URL) = 'PKG_SCP0096.P_SCP0096_SAVE_SHIPMENT_WORKING_DAY_OSP';
