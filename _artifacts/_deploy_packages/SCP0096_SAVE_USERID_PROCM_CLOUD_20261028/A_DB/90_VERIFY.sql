/* SCP0096 저장 ORA-01407 보완 — 적용 후 확인(읽기 전용). 전체 F5 기준 오류 0.
 *  PASS 조건: RESULT = 'PASS' (SORT_ORD=8 COL_NM='userId' · 'userIdList' 잔존 0 · SAVE PROC_M 9행 유지) */
SELECT CASE WHEN SUM(CASE WHEN SORT_ORD = 8 AND COL_NM = 'userId' AND DATA_TP_CD = 'VARCHAR' AND COL_TP_CD = 'IN' THEN 1 ELSE 0 END) = 1
             AND SUM(CASE WHEN COL_NM = 'userIdList' THEN 1 ELSE 0 END) = 0
             AND COUNT(*) = 9
            THEN 'PASS' ELSE 'FAIL' END AS RESULT
     , COUNT(*) AS PROC_M_ROWS
     , MAX(CASE WHEN SORT_ORD = 8 THEN COL_NM END) AS SORT8_COL_NM
  FROM SCM_ADM_PROC_M
 WHERE PROC_NM = 'PKG_SCP0096.P_SCP0096_SAVE_SHIPMENT_WORKING_DAY_OSP';
