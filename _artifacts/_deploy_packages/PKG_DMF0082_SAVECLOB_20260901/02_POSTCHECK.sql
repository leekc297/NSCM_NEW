-- [E20260901-SAVECLOB] 적용 후 검증 (SELECT-only)
-- P1: BODY VALID + 마커 (SAVECLOB>=17, STATELESS>=4, NCHARUNION=1)
SELECT 'P1' S,
  (SELECT STATUS FROM ALL_OBJECTS WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_DMF0082' AND OBJECT_TYPE='PACKAGE BODY') BODY_STATUS,
  (SELECT COUNT(*) FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND INSTR(TEXT,'E20260901-SAVECLOB')>0) SAVECLOB_CNT,
  (SELECT COUNT(*) FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND INSTR(TEXT,'E20260901-STATELESS')>0) STATELESS_CNT,
  (SELECT COUNT(*) FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND INSTR(TEXT,'E20260831-NCHARUNION')>0) NCHARUNION_CNT
 FROM DUAL;

-- P2: ⭐ 핵심 — 홀더 17종이 전부 CLOB 인지 (VARCHAR2(4000) 잔존 0 이어야 함)
SELECT 'P2 홀더잔존' S, COUNT(*) VARCHAR2_4000_CNT FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY'
   AND REGEXP_LIKE(TEXT,'^\s*(v_p_active_flag|v_p_division_id|v_p_project_code|v_p_end_customer|v_p_scm_site_id|v_p_item_id|v_p_dom_exp|v_p_fcst_type|v_p_incoterms|v_p_measure|v_p_plant_site_id|v_p_cell_prod_site_id|v_p_yyyymmdd|v_p_currency|v_p_qty|v_p_created_by_raw|v_p_as_from_site_raw)\s+VARCHAR2','i');

-- P3: 단일토큰은 VARCHAR2 유지 확인 (2행이어야 정상 — 무분별 CLOB화 방지)
SELECT 'P3 토큰유지' S, COUNT(*) CNT FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY'
   AND REGEXP_LIKE(TEXT,'^\s*(v_p_division_id_val|v_p_created_by_val)\s+VARCHAR2','i');

-- P3-B: CURRKEEP 적용 확인 — 마커 2 (GET 2벌) + 구 조건 잔존 0
SELECT 'P3B CURRKEEP' S,
  (SELECT COUNT(*) FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY'
     AND INSTR(TEXT,'E20260901-CURRKEEP')>0) CURRKEEP_CNT,
  (SELECT COUNT(*) FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY'
     AND INSTR(TEXT,'(CURRENCY IS NULL OR CURRENCY <> '' '')')>0) OLD_COND_CNT
 FROM DUAL;

-- P3-C: MEASORDER 적용 확인 — 마커 2 (GET 2벌)
SELECT 'P3C MEASORDER' S, COUNT(*) CNT FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY'
   AND INSTR(TEXT,'E20260901-MEASORDER')>0;

-- P4: 컴파일 오류 0
SELECT 'P4 오류' S, LINE, SUBSTR(TEXT,1,200) ERR FROM ALL_ERRORS
 WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND ATTRIBUTE='ERROR' ORDER BY SEQUENCE;
