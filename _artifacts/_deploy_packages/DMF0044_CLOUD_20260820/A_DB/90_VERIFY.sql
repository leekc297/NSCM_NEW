-- ── V2. 2026-08-20 적용분 마커 카운트 ────────────────────────────────────────
--   기대: CFMERGE 2 / CFSETBASED 2 / CFNOSTATS 1 / EXAUTH 4  (총 9)
--   CFMERGE     = Cutoff 저장 MERGE 필터를 UPDATE WHERE → ON 절로 이동
--   CFSETBASED  = 행별 ROWID 커서 루프 2블록 → 등가 set-based MERGE 2문
--   CFNOSTATS   = 저장 SP 본문의 GTT 통계수집(DBMS_STATS.GATHER_TABLE_STATS) 제거
--   EXAUTH      = 환율 팝업 권한 뷰 INNER JOIN → LEFT JOIN (4지점, P_DIVISION_ID='ALL' 분기 포함)
SELECT CHK, EXPECTED, ACTUAL, CASE WHEN ACTUAL = EXPECTED THEN 'PASS' ELSE 'FAIL' END RESULT
  FROM (
    SELECT 'V2-1 CFMERGE' CHK, 2 EXPECTED,
           (SELECT COUNT(*) FROM ALL_SOURCE
             WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0044' AND TYPE='PACKAGE BODY'
               AND INSTR(TEXT, 'E20260820-CFMERGE') > 0) ACTUAL FROM DUAL
    UNION ALL
    SELECT 'V2-2 CFSETBASED', 2,
           (SELECT COUNT(*) FROM ALL_SOURCE
             WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0044' AND TYPE='PACKAGE BODY'
               AND INSTR(TEXT, 'E20260820-CFSETBASED') > 0) FROM DUAL
    UNION ALL
    SELECT 'V2-3 CFNOSTATS', 1,
           (SELECT COUNT(*) FROM ALL_SOURCE
             WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0044' AND TYPE='PACKAGE BODY'
               AND INSTR(TEXT, 'E20260820-CFNOSTATS') > 0) FROM DUAL
    UNION ALL
    SELECT 'V2-4 EXAUTH', 4,
           (SELECT COUNT(*) FROM ALL_SOURCE
             WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0044' AND TYPE='PACKAGE BODY'
               AND INSTR(TEXT, 'E20260820-EXAUTH') > 0) FROM DUAL
  ) ORDER BY CHK;

--   V2-5 부수 검증: **Cutoff 저장 SP 한 곳만** 통계수집 0 (CFNOSTATS 의 실효 확인)
--   ⚠ 범위를 좁히지 않으면 오탐이다 — CFNOSTATS 는 P_DMF0044_SAVE_SALES_PLAN_REPORT_C_CF
--     1곳에만 적용된 조치이고, PKG 전체에는 다른 SP 소관 GATHER_TABLE_STATS 호출이
--     사내 실측 10건 남아 있다(정상). 그래서 프로시저 구간으로 잘라서 센다.
--   기대: 0
SELECT 'V2-5 CF저장SP GATHER_TABLE_STATS' CHK, COUNT(*) ACTUAL,
       CASE WHEN COUNT(*) = 0 THEN 'PASS' ELSE 'FAIL' END RESULT
  FROM ALL_SOURCE s
 WHERE s.OWNER='SCM_MGR' AND s.NAME='PKG_DMF0044' AND s.TYPE='PACKAGE BODY'
   AND INSTR(UPPER(s.TEXT), 'GATHER_TABLE_STATS') > 0
   AND LTRIM(s.TEXT) NOT LIKE '--%'
   AND s.LINE > (SELECT MIN(LINE) FROM ALL_SOURCE
                  WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0044' AND TYPE='PACKAGE BODY'
                    AND REGEXP_LIKE(TEXT, '^[[:space:]]*PROCEDURE[[:space:]]+P_DMF0044_SAVE_SALES_PLAN_REPORT_C_CF'))
   AND s.LINE < (SELECT MIN(LINE) FROM ALL_SOURCE
                  WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0044' AND TYPE='PACKAGE BODY'
                    AND REGEXP_LIKE(TEXT, '^PROCEDURE[[:space:]]')
                    AND LINE > (SELECT MIN(LINE) FROM ALL_SOURCE
                                 WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0044' AND TYPE='PACKAGE BODY'
                                   AND REGEXP_LIKE(TEXT, '^[[:space:]]*PROCEDURE[[:space:]]+P_DMF0044_SAVE_SALES_PLAN_REPORT_C_CF')));

-- ── V3. ⭐ PROC_M 역추적 — 0행·인자수 불일치 적출 (PLS-00306 방지) ───────────
--   축 = MNU_BTN_MPG_M ⋈ API_M 로 화면이 실제 부르는 SP 를 뽑고,
--        SCM_ADM_PROC_M 행수와 ALL_ARGUMENTS 인자수를 비교한다.
--   기대: **0행** (적출 없음). 1행이라도 나오면 그 SP 는 호출 즉시 PLS-00306 으로 죽는다.
SELECT 'V3-1 PROC_M 결손/불일치' CHK, x.API_URL, x.PROC_ROWS, x.ARG_CNT,
       CASE WHEN x.PROC_ROWS = 0 THEN 'FAIL(0행)' ELSE 'FAIL(인자수 불일치)' END RESULT
  FROM (
    SELECT u.API_URL,
           (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M p
             WHERE UPPER(p.PROC_NM) = UPPER(u.API_URL)) PROC_ROWS,
           (SELECT COUNT(*) FROM ALL_ARGUMENTS a
             WHERE a.OWNER = 'SCM_MGR'
               AND a.ARGUMENT_NAME IS NOT NULL
               AND NVL(a.PACKAGE_NAME, '~') ||'.'|| a.OBJECT_NAME =
                   CASE WHEN INSTR(u.API_URL, '.') > 0 THEN UPPER(u.API_URL)
                        ELSE '~.' || UPPER(u.API_URL) END) ARG_CNT
      FROM (SELECT DISTINCT a.API_URL
              FROM SCM_MGR.SCM_ADM_API_M a
             WHERE a.API_ID IN (SELECT API_ID FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M
                                 WHERE MNU_ID = 'DMF0044' AND API_ID IS NOT NULL)) u
  ) x
 WHERE x.PROC_ROWS = 0 OR x.PROC_ROWS <> x.ARG_CNT
 ORDER BY x.API_URL;

--   V3-2 요약 — 기대: API_URL 18본 / PROC_M 합계 180행 / 불일치 0
SELECT 'V3-2 PROC_M 요약' CHK, COUNT(*) API_URLS, SUM(PROC_ROWS) PROC_ROWS_TOT,
       SUM(CASE WHEN PROC_ROWS = ARG_CNT AND PROC_ROWS > 0 THEN 0 ELSE 1 END) BAD,
       CASE WHEN COUNT(*) = 18 AND SUM(PROC_ROWS) = 180
                 AND SUM(CASE WHEN PROC_ROWS = ARG_CNT AND PROC_ROWS > 0 THEN 0 ELSE 1 END) = 0
            THEN 'PASS' ELSE 'FAIL' END RESULT
  FROM (
    SELECT u.API_URL,
           (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M p
             WHERE UPPER(p.PROC_NM) = UPPER(u.API_URL)) PROC_ROWS,
           (SELECT COUNT(*) FROM ALL_ARGUMENTS a
             WHERE a.OWNER = 'SCM_MGR'
               AND a.ARGUMENT_NAME IS NOT NULL
               AND NVL(a.PACKAGE_NAME, '~') ||'.'|| a.OBJECT_NAME =
                   CASE WHEN INSTR(u.API_URL, '.') > 0 THEN UPPER(u.API_URL)
                        ELSE '~.' || UPPER(u.API_URL) END) ARG_CNT
      FROM (SELECT DISTINCT a.API_URL
              FROM SCM_MGR.SCM_ADM_API_M a
             WHERE a.API_ID IN (SELECT API_ID FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M
