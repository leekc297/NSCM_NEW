-- ── C1. 객체 실존/상태 ───────────────────────────────────────────────────────
--   사내: PKG_DMF0044 PACKAGE VALID / PACKAGE BODY VALID (2026-08-20 19:17)
--         DMF0002_GET_TITLESET_POPUP PROCEDURE VALID
--         SCM0002_SET_TITLESET_POPUP PROCEDURE VALID
--         PKG_DMF0000 PACKAGE VALID / PACKAGE BODY **INVALID**
SELECT 'C1' CHK, OBJECT_NAME, OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI') LAST_DDL
  FROM ALL_OBJECTS
 WHERE OWNER='SCM_MGR'
   AND OBJECT_NAME IN ('PKG_DMF0044','DMF0002_GET_TITLESET_POPUP','SCM0002_SET_TITLESET_POPUP','PKG_DMF0000')
 ORDER BY OBJECT_NAME, OBJECT_TYPE;

-- ── C2. ⭐ GTT 구조 시그니처 대조 (-955 skip 맹점 방어) ─────────────────────
--   01_DDL_GTT.sql 은 기존재 시 -955 를 무시한다. 이름만 같고 컬럼이 다른 구세대 GTT 가 남아 있으면
--   조용히 통과한 뒤 런타임 ORA-00904/00932 로 터진다. 아래 컬럼수/DURATION 을 사내값과 대조할 것.
--   사내 실측(18본): GT_0044_BP_FCST_01=16 / GT_0044_BP_FCST_02=25 / GT_0044_RESULTS=11 /
--     GT_0044_RESULTS_MST=26 / GT_0044_RESULTS_MST_C=27 / GT_DMF0044_DEPT_RPT_C=11 /
--     GT_DMF0044_ITEM_SINGLE_V=9 / GT_DMF0_MEASURE=6 / GT_DMF0_PLAN_C_CATCHUP=19 /
--     GT_DMF0_REPORT=30 / GT_DMF0_SCM_MST_SITE_ITEM=6 / GT_DMF0_VERSION_COPY=21 /
--     GT_F044_DM_MST_ITEM_SINGLE_V=10 / GT_F044_EXCHANGE_C=6 / GT_F044_PJT=4 /
--     GT_F044_REPORT_C=12 / GT_F044_SELECT_MEASURE=5 / GT_F044_T=52
--   DURATION: 위 중 GT_DMF0044_ITEM_SINGLE_V / GT_DMF0_* 6본 = SYS$TRANSACTION, 나머지 = SYS$SESSION
SELECT 'C2' CHK, t.TABLE_NAME, t.DURATION,
       (SELECT COUNT(*) FROM ALL_TAB_COLUMNS c
         WHERE c.OWNER=t.OWNER AND c.TABLE_NAME=t.TABLE_NAME) COL_CNT
  FROM ALL_TABLES t
 WHERE t.OWNER='SCM_MGR' AND t.TEMPORARY='Y'
   AND t.TABLE_NAME IN ('GT_0044_BP_FCST_01','GT_0044_BP_FCST_02','GT_0044_RESULTS',
       'GT_0044_RESULTS_MST','GT_0044_RESULTS_MST_C','GT_DMF0044_DEPT_RPT_C','GT_DMF0044_ITEM_SINGLE_V',
       'GT_DMF0_MEASURE','GT_DMF0_PLAN_C_CATCHUP','GT_DMF0_REPORT','GT_DMF0_SCM_MST_SITE_ITEM',
       'GT_DMF0_VERSION_COPY','GT_F044_DM_MST_ITEM_SINGLE_V','GT_F044_EXCHANGE_C','GT_F044_PJT',
       'GT_F044_REPORT_C','GT_F044_SELECT_MEASURE','GT_F044_T')
 ORDER BY t.TABLE_NAME;

-- ── C3. 메타 축별 현재 카운트 (클라우드) — 사내 실측치와 대조 ────────────────
--   사내: MNU_M 1 / PROGRAM 1 / API_M 28 / MNU_BTN_MPG_M 29 / USER_GR_MNU_MPG_M 3 /
--         USER_GR_MNU_BTN_MPG_M 77 / PROC_M(PKG_DMF0044.*) 151 /
--         SHEET_COLUMNS(PROGRAM_ID) 62 / SHEET_MEASURE(PROGRAM_ID) 18 / EXCEL_COLUMNS 0
SELECT 'C3' CHK, AXIS, CORP_EXPECTED, CLOUD_ACTUAL FROM (
    SELECT 'SCM_ADM_MNU_M' AXIS, 1 CORP_EXPECTED,
           (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_MNU_M WHERE MNU_ID='DMF0044') CLOUD_ACTUAL FROM DUAL
    UNION ALL SELECT 'SCM_ADM_PROGRAM', 1,
           (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_PROGRAM WHERE PROGRAM_ID='DMF0044') FROM DUAL
    UNION ALL SELECT 'SCM_ADM_MNU_BTN_MPG_M', 29,
           (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID='DMF0044') FROM DUAL
    UNION ALL SELECT 'SCM_ADM_USER_GR_MNU_MPG_M', 3,
           (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_MPG_M WHERE MNU_ID='DMF0044') FROM DUAL
    UNION ALL SELECT 'SCM_ADM_USER_GR_MNU_BTN_MPG_M', 77,
           (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE MNU_ID='DMF0044') FROM DUAL
    UNION ALL SELECT 'SCM_ADM_PROC_M (PKG_DMF0044.*)', 151,
           (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M WHERE PROC_NM LIKE 'PKG_DMF0044.%') FROM DUAL
    UNION ALL SELECT 'SCM_MST_SHEET_COLUMNS (DMF0044)', 62,
           (SELECT COUNT(*) FROM SCM_MGR.SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID='DMF0044') FROM DUAL
    UNION ALL SELECT 'SCM_MST_SHEET_MEASURE (DMF0044)', 18,
           (SELECT COUNT(*) FROM SCM_MGR.SCM_MST_SHEET_MEASURE WHERE PROGRAM_ID='DMF0044') FROM DUAL
    UNION ALL SELECT 'SCM_ADM_EXCEL_COLUMNS (DMF0044)', 0,
           (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_EXCEL_COLUMNS WHERE PROGRAM_ID='DMF0044') FROM DUAL
) ORDER BY AXIS;

-- ── C4. ⭐ 공유 콤보 본문 diff 판단용 (덮어쓰기 충돌 사전 확인) ──────────────
--   21_CMBO_SYNC.sql 은 23종을 MERGE 한다. 그중 다수가 타 화면과 공유되는 콤보다.
--   클라우드 본문이 사내와 다르면 **타 화면 회귀**가 된다 — 길이/해시로 1차 판별하고,
--   차이가 있으면 해당 SQL_ID 는 MERGE 문을 주석 처리한 뒤 개별 판단할 것.
SELECT 'C4' CHK, SQL_ID, LENGTH(SQL_DTL_CTN) LEN,
       RAWTOHEX(STANDARD_HASH(SQL_DTL_CTN, 'MD5')) MD5
  FROM SCM_MGR.SCM_ADM_CMBO_SQL_M
 WHERE SQL_ID IN ('APPLICATION','CALENDAR_YYYY','COUNTRY_MST','CUST_GROUP_DTL','CurrencyList',
                  'DMF0005_REPORT_GROUP1','DMF0005_REPORT_GROUP2','DMF0005_REPORT_GROUP3',
                  'DMF0005_REPORT_GROUP4','DMF0005_REPORT_GROUP6','DMF0044_DEPARTMENT_TEAM',
                  'DMF0044_DEPARTMENT_TEAM2','DMF0044_ETC_SALE_RESULT_TYPE_40','DMF0044_MDF_MEASURE',
                  'DM_COMPANY','DM_LOOKUP_DIV','Division','DmBizType','END_CUST_REPORT','FcstType',
                  'MDF_TYPE','MDF_TYPE2','SOLD_TO_CUST_REPORT')
 ORDER BY SQL_ID;

-- ── C5. ⭐ 공유 시트 메타 — 삭제 범위 확인 (타 PROGRAM_ID 동봉 필수) ─────────
--   22_SHEET_META_SYNC.sql 은 SHEET_NAME 단위로 DELETE 후 재적재한다.
--   'MDF Reports' 는 DMF0049 와, 'MDFVerpopup' 은 DMF0041 과 공유한다.
--   ⚠ 클라우드의 타 PROGRAM_ID 행수가 사내와 다르면 **그 차이만큼 소실**된다.
--     사내: SHEET_COLUMNS 'MDF Reports' = DMF0044 46 + DMF0049 44 = 90
--                          'MDFVerpopup' = DMF0041 8 + DMF0044 12 = 20
--                          'exchangeRate' = DMF0044 4
--           SHEET_MEASURE 'MDF Reports' = DMF0044 18 + DMF0049 3 = 21
SELECT 'C5-COL' CHK, SHEET_NAME, PROGRAM_ID, COUNT(*) CNT
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
 WHERE SHEET_NAME IN ('MDF Reports','MDFVerpopup','exchangeRate')
 GROUP BY SHEET_NAME, PROGRAM_ID ORDER BY SHEET_NAME, PROGRAM_ID;

SELECT 'C5-MSR' CHK, SHEET_NAME, PROGRAM_ID, COUNT(*) CNT
  FROM SCM_MGR.SCM_MST_SHEET_MEASURE
 WHERE SHEET_NAME IN ('MDF Reports')
 GROUP BY SHEET_NAME, PROGRAM_ID ORDER BY SHEET_NAME, PROGRAM_ID;

-- ── C6. ⭐ PROC_M 공유 3본 현황 (24_PROC_M_SYNC §2 실행 여부 판단) ───────────
--   사내: DMF0002_GET_TITLESET_POPUP 7 / PKG_DMF0000.P_DMF0000_GET_COMMON_SPREAD_TITLE 8 /
--         SCM0002_SET_TITLESET_POPUP 14  (전부 ALL_ARGUMENTS 와 일치)
--   클라우드가 0행이거나 인자수와 다르면 §2 를 실행한다. 정상이면 **건드리지 말 것**(타 화면 소관).
SELECT 'C6' CHK, x.PROC_NM, x.PROC_ROWS, x.ARG_CNT,
       CASE WHEN x.PROC_ROWS = 0 THEN '§2 실행 필요(0행)'
            WHEN x.PROC_ROWS <> x.ARG_CNT THEN '§2 실행 필요(인자수 불일치)'
            ELSE '정상 — 손대지 말 것' END JUDGE
  FROM (
    SELECT p.PROC_NM,
           (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M m WHERE UPPER(m.PROC_NM)=UPPER(p.PROC_NM)) PROC_ROWS,
           (SELECT COUNT(*) FROM ALL_ARGUMENTS a
             WHERE a.OWNER='SCM_MGR' AND a.ARGUMENT_NAME IS NOT NULL
               AND NVL(a.PACKAGE_NAME,'~')||'.'||a.OBJECT_NAME =
                   CASE WHEN INSTR(p.PROC_NM,'.')>0 THEN UPPER(p.PROC_NM) ELSE '~.'||UPPER(p.PROC_NM) END) ARG_CNT
      FROM (SELECT 'DMF0002_GET_TITLESET_POPUP' PROC_NM FROM DUAL
            UNION ALL SELECT 'SCM0002_SET_TITLESET_POPUP' FROM DUAL
            UNION ALL SELECT 'PKG_DMF0000.P_DMF0000_GET_COMMON_SPREAD_TITLE' FROM DUAL) p
  ) x ORDER BY x.PROC_NM;

