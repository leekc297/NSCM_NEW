-- ── C8. PKG_DMF0044 가 참조하는 비-GTT 선행 객체 실존 (PREREQ) ──────────────
--   ALL_DEPENDENCIES 실측 — 이 중 하나라도 클라우드에 없으면 BODY 가 INVALID 로 컴파일된다.
--   사내 실측: FUNCTION 6 / PROCEDURE 2 / SEQUENCE 1 / SYNONYM 2 / VIEW 1 / TABLE 35(GTT 제외)
SELECT 'C8' CHK, e.OBJ, e.TYP,
       (SELECT COUNT(*) FROM ALL_OBJECTS o
         WHERE o.OWNER='SCM_MGR' AND o.OBJECT_NAME=e.OBJ) FOUND
  FROM (
    SELECT 'FN_CHAR_TO_DATE' OBJ, 'FUNCTION' TYP FROM DUAL
    UNION ALL SELECT 'FN_GET_COUNTRY_KR_NAME','FUNCTION' FROM DUAL
    UNION ALL SELECT 'FN_GET_DM_MKT_OWNER_NAME','FUNCTION' FROM DUAL
    UNION ALL SELECT 'FN_NEXT_DAY','FUNCTION' FROM DUAL
    UNION ALL SELECT 'FN_SCM_SPLIT','FUNCTION' FROM DUAL
    UNION ALL SELECT 'FN_STRING_SPLIT','FUNCTION' FROM DUAL
    UNION ALL SELECT 'PR_DM_SYS_LOG_BATCH','PROCEDURE' FROM DUAL
    UNION ALL SELECT 'PR_SCM_SYS_LOG_BATCH','PROCEDURE' FROM DUAL
    UNION ALL SELECT 'SEQ1_DM_PLN_SALES_PLAN_REPORT_H','SEQUENCE' FROM DUAL
    UNION ALL SELECT 'SCM_MST_COMPANY_SN','SYNONYM' FROM DUAL
    UNION ALL SELECT 'SCM_MST_ITEM_SN','SYNONYM' FROM DUAL
    UNION ALL SELECT 'SCM_ADM_USER_MNU_EDIT_AUTH_V','VIEW' FROM DUAL
  ) e ORDER BY e.TYP, e.OBJ;
