-- 00_PRECHECK — 조회 전용 (전체 F5, 값 입력 없음). DMF0082 조회 ORA-00904 "SORT_KEY" — 컬럼 메타 시스템 컬럼 DEFAULT_FLAG 복원 전 상태
-- * [P1] 시스템 컬럼 10개의 DEFAULT_FLAG 현재 값 — 'N' 이면 복원 대상, 공백 1칸이면 정상
-- * [P2] 판정 — 이 DB 의 조회 SP 판정식(센티널)으로 SORT_KEY 가 잡히는가 (FAIL = 지금 조회가 ORA-00904)
-- * [P3] DEFAULT_FLAG 값 분포 (DMF0082 · FcstNPrice)
-- * [P4] 지금 PKG_DMF0082 실행 중 세션 (참고 — 10 은 메타 10행 UPDATE 라 대기 없음)
SET LINESIZE 220 PAGESIZE 200
COLUMN CHK FORMAT A6
COLUMN COLUMN_NAME FORMAT A16
COLUMN FLAG FORMAT A6
COLUMN FLAG_DUMP FORMAT A20
COLUMN WHO FORMAT A14
COLUMN JUDGE FORMAT A100
SELECT 'P0' CHK, SYS_CONTEXT('USERENV','DB_NAME') DB_NAME, TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI:SS') NOW FROM DUAL;
SELECT 'P1' CHK, C.COLUMN_NAME, '[' || C.DEFAULT_FLAG || ']' FLAG, SUBSTR(DUMP(C.DEFAULT_FLAG),1,20) FLAG_DUMP,
       SUBSTR(C.LAST_UPDATED_BY,1,14) WHO, TO_CHAR(C.LAST_UPDATE_DATE,'YYYY-MM-DD HH24:MI') UPD,
       CASE WHEN TRIM(C.DEFAULT_FLAG) IS NULL THEN '정상 (빈 값)' WHEN C.DEFAULT_FLAG = 'N' THEN '복원 대상' ELSE '확인 필요 — N 도 빈 값도 아님' END JUDGE
  FROM SCM_MST_SHEET_COLUMNS C
 WHERE C.PROGRAM_ID = 'DMF0082' AND C.SHEET_NAME = 'FcstNPrice'
   AND C.COLUMN_NAME IN ('AS_YN','ATTR1','BUCKET','EDIT_FLAG','GROUP_ID','MEASURE_GROUP','NEW_FLAG','SORT_KEY','VERSION_NO','VMI_STD_DIO')
 ORDER BY C.COLUMN_NAME;
SELECT 'P2' CHK, X.SENTINEL,
       (SELECT COUNT(*) FROM USER_SOURCE S WHERE S.NAME = 'PKG_DMF0082' AND S.TYPE = 'PACKAGE BODY'
           AND REPLACE(S.TEXT,' ','') LIKE '%ANDNVL(TRIM(C.DEFAULT_FLAG),''' || X.SENTINEL || ''')=''' || X.SENTINEL || '''%'
           AND LTRIM(S.TEXT) NOT LIKE '--%') SP_USES,
       (SELECT COUNT(*) FROM SCM_MST_SHEET_COLUMNS C WHERE C.PROGRAM_ID = 'DMF0082' AND C.SHEET_NAME = 'FcstNPrice'
           AND NVL(TRIM(C.DEFAULT_FLAG), X.SENTINEL) = X.SENTINEL) SYS_COLS,
       CASE WHEN (SELECT COUNT(*) FROM USER_SOURCE S WHERE S.NAME = 'PKG_DMF0082' AND S.TYPE = 'PACKAGE BODY'
                     AND REPLACE(S.TEXT,' ','') LIKE '%ANDNVL(TRIM(C.DEFAULT_FLAG),''' || X.SENTINEL || ''')=''' || X.SENTINEL || '''%'
                     AND LTRIM(S.TEXT) NOT LIKE '--%') = 0 THEN '(이 DB 의 SP 는 이 센티널을 쓰지 않음)'
            WHEN (SELECT COUNT(*) FROM SCM_MST_SHEET_COLUMNS C WHERE C.PROGRAM_ID = 'DMF0082' AND C.SHEET_NAME = 'FcstNPrice'
                     AND NVL(TRIM(C.DEFAULT_FLAG), X.SENTINEL) = X.SENTINEL AND C.COLUMN_NAME = 'SORT_KEY') = 0
                 THEN 'FAIL — SORT_KEY 가 안 잡힌다 (조회 ORA-00904 상태) → 10 적용'
            ELSE 'PASS — SORT_KEY 가 잡힌다 (정상 상태)' END JUDGE
  FROM (SELECT '-' SENTINEL FROM DUAL UNION ALL SELECT '/' FROM DUAL) X ORDER BY X.SENTINEL;
SELECT 'P3' CHK, '[' || C.DEFAULT_FLAG || ']' FLAG, COUNT(*) CNT FROM SCM_MST_SHEET_COLUMNS C
 WHERE C.PROGRAM_ID = 'DMF0082' AND C.SHEET_NAME = 'FcstNPrice' GROUP BY C.DEFAULT_FLAG ORDER BY 2;
SELECT 'P4' CHK, S.INST_ID, S.SID, S.SERIAL#, S.USERNAME, S.LAST_CALL_ET CALL_SEC
  FROM GV$SESSION S WHERE S.TYPE='USER' AND S.STATUS='ACTIVE'
   AND S.PLSQL_ENTRY_OBJECT_ID = (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0082' AND OBJECT_TYPE='PACKAGE');
