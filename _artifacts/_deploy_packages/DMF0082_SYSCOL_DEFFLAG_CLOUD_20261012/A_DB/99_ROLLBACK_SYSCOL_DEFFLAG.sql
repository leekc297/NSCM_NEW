-- 99 ROLLBACK — 10_APPLY 가 공백으로 복원한 10개 컬럼의 DEFAULT_FLAG 를 다시 'N' 으로 (전체 F5, 멱등)
-- ⚠ 실행하면 DMF0082 조회가 다시 ORA-00904 "SORT_KEY" 로 실패한다. 10 적용으로 다른 문제가 생겼을 때만 사용.
SET SERVEROUTPUT ON SIZE UNLIMITED
DECLARE
    n PLS_INTEGER;
BEGIN
    UPDATE SCM_MGR.SCM_MST_SHEET_COLUMNS C
       SET C.DEFAULT_FLAG = 'N', C.LAST_UPDATED_BY = 'admin', C.LAST_UPDATE_DATE = SYSDATE
     WHERE C.PROGRAM_ID = 'DMF0082' AND C.SHEET_NAME = 'FcstNPrice'
       AND C.COLUMN_NAME IN ('AS_YN','ATTR1','BUCKET','EDIT_FLAG','GROUP_ID','MEASURE_GROUP','NEW_FLAG','SORT_KEY','VERSION_NO','VMI_STD_DIO')
       AND TRIM(C.DEFAULT_FLAG) IS NULL;
    n := SQL%ROWCOUNT;
    COMMIT;
    DBMS_OUTPUT.PUT_LINE('ROLLED BACK — ' || n || '행을 N 으로 되돌림 · COMMIT · ' || TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI:SS'));
END;
/
