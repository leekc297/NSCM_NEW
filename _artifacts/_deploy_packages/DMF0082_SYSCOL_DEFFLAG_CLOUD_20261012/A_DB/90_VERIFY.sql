-- 90 VERIFY — V1·V2 조회 전용 · V3 = 40 조회 SP 1회 호출(세션 작업 테이블만, ROLLBACK)
-- * 기대: V1 10행 모두 '정상 (빈 값)' · V2 SP 가 쓰는 센티널 줄이 PASS · V3 'OK … SORT_KEY 포함 Y'
SET SERVEROUTPUT ON SIZE UNLIMITED
SET LINESIZE 220 PAGESIZE 200
COLUMN CHK FORMAT A6
COLUMN COLUMN_NAME FORMAT A16
COLUMN FLAG FORMAT A6
COLUMN JUDGE FORMAT A100
SELECT 'V1' CHK, C.COLUMN_NAME, '[' || C.DEFAULT_FLAG || ']' FLAG,
       CASE WHEN TRIM(C.DEFAULT_FLAG) IS NULL THEN '정상 (빈 값)' ELSE 'FAIL — 빈 값 아님' END JUDGE
  FROM SCM_MST_SHEET_COLUMNS C
 WHERE C.PROGRAM_ID = 'DMF0082' AND C.SHEET_NAME = 'FcstNPrice'
   AND C.COLUMN_NAME IN ('AS_YN','ATTR1','BUCKET','EDIT_FLAG','GROUP_ID','MEASURE_GROUP','NEW_FLAG','SORT_KEY','VERSION_NO','VMI_STD_DIO')
 ORDER BY C.COLUMN_NAME;
SELECT 'V2' CHK, X.SENTINEL,
       (SELECT COUNT(*) FROM SCM_MST_SHEET_COLUMNS C WHERE C.PROGRAM_ID = 'DMF0082' AND C.SHEET_NAME = 'FcstNPrice'
           AND NVL(TRIM(C.DEFAULT_FLAG), X.SENTINEL) = X.SENTINEL) SYS_COLS,
       CASE WHEN (SELECT COUNT(*) FROM USER_SOURCE S WHERE S.NAME = 'PKG_DMF0082' AND S.TYPE = 'PACKAGE BODY'
                     AND REPLACE(S.TEXT,' ','') LIKE '%ANDNVL(TRIM(C.DEFAULT_FLAG),''' || X.SENTINEL || ''')=''' || X.SENTINEL || '''%'
                     AND LTRIM(S.TEXT) NOT LIKE '--%') = 0 THEN '(이 DB 의 SP 는 이 센티널을 쓰지 않음)'
            WHEN (SELECT COUNT(*) FROM SCM_MST_SHEET_COLUMNS C WHERE C.PROGRAM_ID = 'DMF0082' AND C.SHEET_NAME = 'FcstNPrice'
                     AND NVL(TRIM(C.DEFAULT_FLAG), X.SENTINEL) = X.SENTINEL AND C.COLUMN_NAME = 'SORT_KEY') = 0
                 THEN 'FAIL — SORT_KEY 가 안 잡힌다' ELSE 'PASS — SORT_KEY 가 잡힌다' END JUDGE
  FROM (SELECT '-' SENTINEL FROM DUAL UNION ALL SELECT '/' FROM DUAL) X ORDER BY X.SENTINEL;
DECLARE
  rc1 SYS_REFCURSOR; rc2 SYS_REFCURSOR; rc3 SYS_REFCURSOR; rc4 SYS_REFCURSOR; rc5 SYS_REFCURSOR; rr SYS_REFCURSOR;
  v_from VARCHAR2(8) := TO_CHAR(TRUNC(SYSDATE,'MM'),'YYYYMMDD'); v_to VARCHAR2(8) := TO_CHAR(ADD_MONTHS(TRUNC(SYSDATE,'MM'),6)-1,'YYYYMMDD');
  c INTEGER; n INTEGER; k PLS_INTEGER := 0; dt DBMS_SQL.DESC_TAB; v_sk VARCHAR2(1) := 'N';
BEGIN
  SCM_MGR.PKG_DMF0082.P_DMF0082_GET_MAIN_DATA('40', 'ALL', 'ALL', 'ALL', v_from, v_to, 'ALL', NULL, 'Current', 'N', 'minyonglee1', 'ADMIN', 'ALL', 'ALL', 'ALL', 'ALL', rc1, rc2, rc3, rc4, rc5, rr);
  c := DBMS_SQL.TO_CURSOR_NUMBER(rc1);
  DBMS_SQL.DESCRIBE_COLUMNS(c, n, dt);
  FOR i IN 1 .. n LOOP IF dt(i).col_name = 'SORT_KEY' THEN v_sk := 'Y'; END IF; END LOOP;
  WHILE DBMS_SQL.FETCH_ROWS(c) > 0 LOOP k := k + 1; END LOOP;
  DBMS_SQL.CLOSE_CURSOR(c);
  CLOSE rc2; CLOSE rc3; CLOSE rc4; CLOSE rc5; CLOSE rr;
  DBMS_OUTPUT.PUT_LINE('V3 div 40 OK — 그리드 ' || k || ' 행 · 결과 컬럼 ' || n || '개 · SORT_KEY 포함 ' || v_sk);
  ROLLBACK;
EXCEPTION WHEN OTHERS THEN
  DBMS_OUTPUT.PUT_LINE('V3 FAIL — ' || REPLACE(SQLERRM, CHR(10), ' / '));
  ROLLBACK;
END;
