-- 97_DIAG_HISTORY_SEQ.sql — ORA-00001 대상 테이블 확정 + 이력 시퀀스 뒤처짐 판정 (READ-ONLY) [E20260930-DMF0049SETFULL]
SET LINESIZE 250 PAGESIZE 200
COLUMN P1 FORMAT A120
COLUMN P2 FORMAT A120
COLUMN P3 FORMAT A120
COLUMN P4 FORMAT A120
PROMPT [1] 최근 오류 메시지 전문 (제약명 · BACKTRACE 줄번호 포함)
SELECT TO_CHAR(TRNM_ST_DTM,'MM-DD HH24:MI:SS') ST,
       SUBSTR(EXCT_MSG_CTN, 1, 120) P1, SUBSTR(EXCT_MSG_CTN, 121, 120) P2, SUBSTR(EXCT_MSG_CTN, 241, 120) P3, SUBSTR(EXCT_MSG_CTN, 361, 120) P4
  FROM SCM_COM_SYS_LOG
 WHERE MNU_ID='DMF0049' AND EXCT_MSG_CTN LIKE '%ORA-00001%' AND CREATION_DATE >= SYSDATE - 1
 ORDER BY TRNM_ST_DTM DESC FETCH FIRST 3 ROWS ONLY;
PROMPT [2] 이력 시퀀스 vs 이력 테이블 최대 HISTORY_SEQ  (LAST_NUMBER <= MAX_HIST 이면 시퀀스 뒤처짐 = 원인 확정)
SELECT S.SEQUENCE_NAME, S.LAST_NUMBER, S.CACHE_SIZE, S.INCREMENT_BY,
       (SELECT MAX(HISTORY_SEQ) FROM DM_PLN_SALES_ETC_REPORT_H) MAX_HIST,
       (SELECT COUNT(*) FROM DM_PLN_SALES_ETC_REPORT_H WHERE HISTORY_SEQ >= S.LAST_NUMBER) ROWS_AT_OR_AFTER_SEQ,
       CASE WHEN (SELECT MAX(HISTORY_SEQ) FROM DM_PLN_SALES_ETC_REPORT_H) >= S.LAST_NUMBER THEN '⚠ 시퀀스 뒤처짐 — 충돌 원인' ELSE 'OK' END JUDGE
  FROM USER_SEQUENCES S WHERE S.SEQUENCE_NAME = 'SEQ1_DM_PLN_SALES_ETC_REPORT_H';
PROMPT [3] 이력 테이블 HISTORY_SEQ 분포 (최근 이관/적재 흔적)
SELECT MIN(HISTORY_SEQ) MIN_SEQ, MAX(HISTORY_SEQ) MAX_SEQ, COUNT(*) CNT, TO_CHAR(MAX(CREATION_DATE),'YYYY-MM-DD HH24:MI') LAST_CREATED
  FROM DM_PLN_SALES_ETC_REPORT_H;
