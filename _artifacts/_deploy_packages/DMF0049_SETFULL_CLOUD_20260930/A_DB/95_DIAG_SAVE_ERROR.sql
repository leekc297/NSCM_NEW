-- 95_DIAG_SAVE_ERROR.sql — 클라우드 DMF0049 저장 오류 원문·전송 파라미터 채취 (READ-ONLY) [E20260930-DMF0049SETFULL]
--  SCM_MGR 로 오류 재현 직후 실행 → 결과 회신
SET LINESIZE 300 PAGESIZE 200 LONG 20000 LONGCHUNKSIZE 20000
COLUMN ERR FORMAT A150
COLUMN PARAMS FORMAT A200
PROMPT [1] 최근 2시간 DMF0049 저장 호출 — 오류 메시지
SELECT TO_CHAR(TRNM_ST_DTM,'MM-DD HH24:MI:SS') ST, CREATED_BY, SUBSTR(EXCT_MSG_CTN,1,150) ERR
  FROM SCM_COM_SYS_LOG
 WHERE MNU_ID='DMF0049' AND CREATION_DATE >= SYSDATE - 2/24 AND UPPER(SYS_LOG_MSG_CTN) LIKE '%SAVE_SALES_ETC%'
 ORDER BY TRNM_ST_DTM DESC FETCH FIRST 5 ROWS ONLY;
PROMPT [2] 그 호출의 measure / qty / activeFlag / yyyymmdd / dataSeq 토큰 (최근 1건)
SELECT REGEXP_SUBSTR(SYS_LOG_MSG_CTN,'"measure":"([^"]*)"',1,1,NULL,1) MEASURE_TOKENS,
       REGEXP_SUBSTR(SYS_LOG_MSG_CTN,'"qty":"([^"]*)"',1,1,NULL,1) QTY_TOKENS,
       REGEXP_SUBSTR(SYS_LOG_MSG_CTN,'"activeFlag":"([^"]*)"',1,1,NULL,1) FLAG_TOKENS,
       REGEXP_SUBSTR(SYS_LOG_MSG_CTN,'"yyyymmdd":"([^"]*)"',1,1,NULL,1) YM_TOKENS,
       REGEXP_SUBSTR(SYS_LOG_MSG_CTN,'"dataSeq":"([^"]*)"',1,1,NULL,1) SEQ_TOKENS,
       REGEXP_SUBSTR(SYS_LOG_MSG_CTN,'"versionNo":"([^"]*)"',1,1,NULL,1) VER_TOKENS
  FROM SCM_COM_SYS_LOG
 WHERE MNU_ID='DMF0049' AND CREATION_DATE >= SYSDATE - 2/24 AND UPPER(SYS_LOG_MSG_CTN) LIKE '%SAVE_SALES_ETC%'
 ORDER BY TRNM_ST_DTM DESC FETCH FIRST 1 ROWS ONLY;
PROMPT [3] SP 내부 로그 (PR_DM_SYS_LOG_BATCH → SCM_SYS_LOG) — 최근 2시간 DMF0049 SAVE 단계·오류
SELECT TO_CHAR(EVENT_DATE,'MM-DD HH24:MI:SS') T, LOG_TYPE, SUBSTR(LOG_MESSAGE,1,120) MSG, SUBSTR(DESCRIPTION,1,120) DESCR
  FROM SCM_SYS_LOG
 WHERE PROGRAM_NAME LIKE '%DMF0049%' AND EVENT_DATE >= SYSDATE - 2/24
 ORDER BY EVENT_DATE DESC FETCH FIRST 30 ROWS ONLY;
PROMPT [4] 원장 PK · 적용 상태
SELECT C.COLUMN_NAME FROM USER_CONSTRAINTS K JOIN USER_CONS_COLUMNS C ON C.CONSTRAINT_NAME=K.CONSTRAINT_NAME
 WHERE K.TABLE_NAME='DM_PLN_SALES_ETC_REPORT_C' AND K.CONSTRAINT_TYPE='P' ORDER BY C.POSITION;
SELECT (SELECT COUNT(*) FROM USER_SOURCE WHERE NAME='PKG_DMF0049' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%E20260930-DMF0049SETFULL%') MARK,
       (SELECT STATUS FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0049' AND OBJECT_TYPE='PACKAGE BODY') STATUS FROM DUAL;
