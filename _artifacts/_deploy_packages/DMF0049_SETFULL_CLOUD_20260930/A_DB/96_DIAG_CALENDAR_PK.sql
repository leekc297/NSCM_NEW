SET LINESIZE 250 PAGESIZE 200
PROMPT [1] 저장 SP 와 같은 식으로 202609 / 202610 → YYYYMMDD 변환 (NULL 이면 원장에 '-' 로 들어가 PK 충돌)
SELECT '202609' YM, ( SELECT MIN(BASIS_START_DATE) FROM SCM_SYS_CALENDAR_M C
                      WHERE SUBSTR(C.BASIS_YYYYMMDD,1,6) = '202609' AND C.DAYOFWEEK IN ('MON','TUE','WED','THU','FRI') ) FIRST_BIZ_DAY FROM DUAL
UNION ALL
SELECT '202610', ( SELECT MIN(BASIS_START_DATE) FROM SCM_SYS_CALENDAR_M C
                   WHERE SUBSTR(C.BASIS_YYYYMMDD,1,6) = '202610' AND C.DAYOFWEEK IN ('MON','TUE','WED','THU','FRI') ) FROM DUAL;
PROMPT [2] 달력 2026 월별 행수 (0 인 달이 있으면 그 달 저장은 전부 '-' 날짜)
SELECT SUBSTR(BASIS_YYYYMMDD,1,6) YM, COUNT(*) CNT, MIN(BASIS_START_DATE) MIN_START, SUM(CASE WHEN DAYOFWEEK IN ('MON','TUE','WED','THU','FRI') THEN 1 ELSE 0 END) WEEKDAYS
  FROM SCM_SYS_CALENDAR_M WHERE BASIS_YYYYMMDD BETWEEN '20260101' AND '20261231' GROUP BY SUBSTR(BASIS_YYYYMMDD,1,6) ORDER BY 1;
PROMPT [3] 대상 버전 원장 — 이미 있는 행 (실패한 저장이 남긴 것은 없어야 정상 · '-' 날짜 행 유무)
SELECT DATA_SEQ, MEASURE, YYYYMMDD, QTY, CREATED_BY, TO_CHAR(CREATION_DATE,'MM-DD HH24:MI') C
  FROM DM_PLN_SALES_ETC_REPORT_C WHERE VERSION_NO = 'R_S_20260930_V001' AND DIVISION_ID = '40'
 ORDER BY DATA_SEQ, YYYYMMDD, MEASURE;
PROMPT [4] '-' 날짜로 들어간 행이 원장 전체에 있는지 (있으면 달력 결손이 이전부터)
SELECT VERSION_NO, DIVISION_ID, COUNT(*) FROM DM_PLN_SALES_ETC_REPORT_C WHERE YYYYMMDD = '-' GROUP BY VERSION_NO, DIVISION_ID ORDER BY 1;
