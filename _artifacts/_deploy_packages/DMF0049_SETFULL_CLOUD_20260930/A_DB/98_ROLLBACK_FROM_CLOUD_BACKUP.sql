-- 98_ROLLBACK_FROM_CLOUD_BACKUP.sql — 05 보관본으로 BODY 복원 (롤백 전용) [E20260930-DMF0049SETFULL]
SET SERVEROUTPUT ON
DECLARE
  v CLOB;
BEGIN
  DBMS_LOB.CREATETEMPORARY(v, TRUE);
  FOR r IN (SELECT TEXT FROM BAK_SRC_DMF0049_SETFULL WHERE NAME='PKG_DMF0049' AND TYPE='PACKAGE BODY' ORDER BY LINE) LOOP
    DBMS_LOB.APPEND(v, r.TEXT);
  END LOOP;
  IF DBMS_LOB.GETLENGTH(v) > 0 THEN
    EXECUTE IMMEDIATE 'CREATE OR REPLACE ' || v;
    DBMS_OUTPUT.PUT_LINE('REBUILT PACKAGE BODY');
  ELSE
    DBMS_OUTPUT.PUT_LINE('SKIP (no backup)');
  END IF;
END;
/
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0049';
