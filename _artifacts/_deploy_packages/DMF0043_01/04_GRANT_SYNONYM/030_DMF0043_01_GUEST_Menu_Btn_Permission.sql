--
-- 목적: DMF0043_01 의 GUEST 그룹 메뉴/버튼 권한 등록
-- 실행: SCM_MGR 세션
-- 멱등: NOT EXISTS 가드
-- 작성: 2026-06-05
--==============================================================================
SET DEFINE OFF
SET SERVEROUTPUT ON
SET FEEDBACK ON

PROMPT === BLOCK 1 : DMF0043_01 GUEST 메뉴 권한 ===

INSERT INTO SCM_MGR.SCM_ADM_USER_GR_MNU_MPG_M
  (USER_GR_ID, MNU_ID, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'GUEST', 'DMF0043_01', 'Y', 'admin', SYSDATE, 'admin', SYSDATE FROM DUAL
 WHERE NOT EXISTS (
   SELECT 1 FROM SCM_MGR.SCM_ADM_USER_GR_MNU_MPG_M
    WHERE USER_GR_ID = 'GUEST' AND MNU_ID = 'DMF0043_01'
 );

PROMPT === BLOCK 2 : DMF0043_01 GUEST 버튼 권한 (마스터 정의 복제) ===

INSERT INTO SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M
  (USER_GR_ID, MNU_ID, SHT_NM, MNU_BTN_CD, USE_YN,
   CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'GUEST', BTN.MNU_ID, BTN.SHT_NM, BTN.MNU_BTN_CD, 'Y',
       'admin', SYSDATE, 'admin', SYSDATE
  FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M BTN
 WHERE BTN.MNU_ID = 'DMF0043_01'
   AND NOT EXISTS (
     SELECT 1 FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M X
      WHERE X.USER_GR_ID = 'GUEST' AND X.MNU_ID = BTN.MNU_ID
        AND X.SHT_NM = BTN.SHT_NM AND X.MNU_BTN_CD = BTN.MNU_BTN_CD
   );

PROMPT === BLOCK 3 : 검증 ===

SELECT 'MENU_PERM' AS type,
       (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_MPG_M
         WHERE USER_GR_ID = 'GUEST' AND MNU_ID = 'DMF0043_01') AS cnt,
       'expect 1' AS expected
  FROM DUAL
UNION ALL
SELECT 'BTN_PERM',
       (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M
         WHERE USER_GR_ID = 'GUEST' AND MNU_ID = 'DMF0043_01'),
       'expect > 0 (5+ buttons)'
  FROM DUAL;

COMMIT;
