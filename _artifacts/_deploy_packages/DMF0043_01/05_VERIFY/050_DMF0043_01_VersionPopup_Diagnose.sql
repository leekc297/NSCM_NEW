--==============================================================================
-- 47_DMF0043_01_VersionPopup_Diagnose.sql
--
-- 목적:
--   ContributeVersionModal (sheet 'versionPopup') 데이터 미조회 진단.
--   SP body: PKG_DMF0043.P_DMF0043_GET_CONT_VIEW_VERSIONPOPUP
--   WHERE 절: DIVISION_ID 정확 일치 + YYYYMMDD BETWEEN + VERSION_TYPE 정확 일치
--             + VERSION_DESCRIPTION LIKE '%...%' + SEND_YN <> 'D' + ATTRIBUTE1 <> 'MOVE'
--             + INNER JOIN PKG_SCM_USER_MNU.PR_SCM_EDIT_YN(P_USER_ID, P_MENU_ID)
--
-- 진단 시나리오 (가능한 5 원인):
--   D1  DM_MDF_VERSION 테이블 자체에 row 존재?
--   D2  DIVISION_ID='40' AND SEND_YN<>'D' 조건만 적용한 후 row 수?
--   D3  VERSION_TYPE 별 분포 (어떤 type 이 등록되어 있는지)
--   D4  YYYYMMDD 분포 (FE 의 -3M~+3M 범위에 row 있는지)
--   D5  ATTRIBUTE1 ='MOVE' 로 제외된 row 수
--   D6  PR_SCM_EDIT_YN(minyonglee1, 'DMF0043_01') 결과 (= 메뉴 권한 함수)
--   D7  PR_SCM_EDIT_YN(minyonglee1, 'DMF0043')    결과 (parent fallback)
--   D8  최종 SP 호출 시뮬레이션 (sample input)
--
-- 작성: 2026-06-01
--==============================================================================

-- D1 : DM_MDF_VERSION 테이블 row 수
SELECT 'D1: DM_MDF_VERSION 전체' AS K, COUNT(*) AS V FROM SCM_MGR.DM_MDF_VERSION;

-- D2 : DIVISION_ID='40' AND SEND_YN<>'D' 만 적용
SELECT 'D2: DIVISION_ID=40 AND SEND_YN<>D' AS K, COUNT(*) AS V
  FROM SCM_MGR.DM_MDF_VERSION
 WHERE DIVISION_ID = '40' AND SEND_YN <> 'D';

-- D3 : DIVISION_ID='40' 의 VERSION_TYPE 분포
SELECT 'D3: VERSION_TYPE 분포' AS K, VERSION_TYPE, COUNT(*) AS V
  FROM SCM_MGR.DM_MDF_VERSION
 WHERE DIVISION_ID = '40' AND SEND_YN <> 'D'
 GROUP BY VERSION_TYPE
 ORDER BY COUNT(*) DESC;

-- D4 : YYYYMMDD 최소/최대 (FE 가 -3M~+3M 의 범위로 호출 — 약 20260301~20260901)
SELECT 'D4: YYYYMMDD 범위' AS K, MIN(YYYYMMDD) AS MIN_DATE, MAX(YYYYMMDD) AS MAX_DATE
  FROM SCM_MGR.DM_MDF_VERSION
 WHERE DIVISION_ID = '40' AND SEND_YN <> 'D';

-- D5 : ATTRIBUTE1='MOVE' 로 제외되는 row 수
SELECT 'D5: ATTRIBUTE1=MOVE 제외' AS K, COUNT(*) AS V
  FROM SCM_MGR.DM_MDF_VERSION
 WHERE DIVISION_ID = '40' AND SEND_YN <> 'D'
   AND NVL(ATTRIBUTE1, NULL) = 'MOVE';

-- D6 : PR_SCM_EDIT_YN(minyonglee1, 'DMF0043_01') — 메뉴 권한 함수 결과
SELECT 'D6: EDIT_YN for DMF0043_01' AS K, COUNT(*) AS V
  FROM TABLE(SCM_MGR.PKG_SCM_USER_MNU.PR_SCM_EDIT_YN('minyonglee1', 'DMF0043_01'));

-- D7 : PR_SCM_EDIT_YN(minyonglee1, 'DMF0043') — parent fallback
SELECT 'D7: EDIT_YN for DMF0043' AS K, COUNT(*) AS V
  FROM TABLE(SCM_MGR.PKG_SCM_USER_MNU.PR_SCM_EDIT_YN('minyonglee1', 'DMF0043'));

-- D6/D7 의 UNIT_ID 값들 (= DIVISION_ID 와 매칭되어야 함 — '40' 포함 여부)
SELECT 'D6.unit_ids' AS K, UNIT_ID, EDIT_YN FROM TABLE(SCM_MGR.PKG_SCM_USER_MNU.PR_SCM_EDIT_YN('minyonglee1', 'DMF0043_01'));
SELECT 'D7.unit_ids' AS K, UNIT_ID, EDIT_YN FROM TABLE(SCM_MGR.PKG_SCM_USER_MNU.PR_SCM_EDIT_YN('minyonglee1', 'DMF0043'));

-- D8 : SP 호출 시뮬레이션 — 최종 WHERE 절 그대로 적용
SELECT 'D8: 최종 매칭' AS K, COUNT(*) AS V
  FROM SCM_MGR.DM_MDF_VERSION A
  INNER JOIN TABLE(SCM_MGR.PKG_SCM_USER_MNU.PR_SCM_EDIT_YN('minyonglee1', 'DMF0043_01')) TEI
    ON TEI.UNIT_ID = A.DIVISION_ID
 WHERE A.DIVISION_ID = '40'
   AND A.YYYYMMDD BETWEEN '20260301' AND '20260901'
   AND A.VERSION_TYPE = 'SP'
   AND A.VERSION_DESCRIPTION LIKE '%' || '' || '%'
   AND A.SEND_YN <> 'D'
   AND NVL(A.ATTRIBUTE1, NULL) <> 'MOVE';

-- D8.B : 범위 확장 (전체 기간 + 모든 VERSION_TYPE)
SELECT 'D8.B: 범위 확장 (모든 type)' AS K, COUNT(*) AS V
  FROM SCM_MGR.DM_MDF_VERSION A
  INNER JOIN TABLE(SCM_MGR.PKG_SCM_USER_MNU.PR_SCM_EDIT_YN('minyonglee1', 'DMF0043_01')) TEI
    ON TEI.UNIT_ID = A.DIVISION_ID
 WHERE A.DIVISION_ID = '40'
   AND A.SEND_YN <> 'D'
   AND NVL(A.ATTRIBUTE1, NULL) <> 'MOVE';

-- D8.C : EDIT_YN INNER JOIN 제거 — 권한 외 데이터 자체 존재 검증
SELECT 'D8.C: EDIT_YN JOIN 제외' AS K, COUNT(*) AS V
  FROM SCM_MGR.DM_MDF_VERSION A
 WHERE A.DIVISION_ID = '40'
   AND A.YYYYMMDD BETWEEN '20260301' AND '20260901'
   AND A.VERSION_TYPE = 'SP'
   AND A.SEND_YN <> 'D'
   AND NVL(A.ATTRIBUTE1, NULL) <> 'MOVE';

-- D9 : BE PROC_M 매핑 검증
SELECT 'D9: PROC_M (DMF0043_GET_CONT_VIEW_VERSIONPOPUP)' AS K, COL_NM, COL_TP_CD, SORT_ORD
  FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM = 'DMF0043_GET_CONT_VIEW_VERSIONPOPUP'
 ORDER BY SORT_ORD;

-- D10 : BTN_MPG 매핑 (DMF0043_01.versionPopup)
SELECT 'D10: BTN_MPG (DMF0043_01.versionPopup)' AS K, BTN.API_ID, API.API_URL
  FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M BTN
  LEFT JOIN SCM_MGR.SCM_ADM_API_M API ON API.API_ID = BTN.API_ID
 WHERE BTN.MNU_ID = 'DMF0043_01' AND BTN.SHT_NM = 'versionPopup';

-- D11 : GUEST 권한 매핑 (DMF0043_01.versionPopup)
SELECT 'D11: GUEST PERM (DMF0043_01.versionPopup)' AS K, COUNT(*) AS V
  FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M
 WHERE USER_GR_ID = 'GUEST' AND MNU_ID = 'DMF0043_01' AND SHT_NM = 'versionPopup';

-- D12 : DM_MDF_VERSION 샘플 5 row (실제 데이터 직접 확인)
SELECT VERSION_NO, VERSION_DESCRIPTION, VERSION_TYPE, DIVISION_ID, YYYYMMDD, SEND_YN, ATTRIBUTE1, CREATED_BY
  FROM SCM_MGR.DM_MDF_VERSION
 WHERE ROWNUM <= 5
 ORDER BY YYYYMMDD DESC;
