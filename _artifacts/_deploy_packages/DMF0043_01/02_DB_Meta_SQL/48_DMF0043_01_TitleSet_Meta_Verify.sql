-- 목적: DMF0002 TitleSet 메타 등록 검증
-- 작성: 2026-06-01

SELECT
  CASE WHEN MSG.MSG_NM IS NOT NULL  THEN 'PASS' ELSE 'FAIL' END AS BLOCK1_MSG,
  CASE WHEN API.API_ID IS NOT NULL  THEN 'PASS' ELSE 'FAIL' END AS BLOCK2_API,
  CASE WHEN BTN.MNU_ID IS NOT NULL  THEN 'PASS' ELSE 'FAIL' END AS BLOCK3_BTN,
  CASE WHEN PERM.MNU_ID IS NOT NULL THEN 'PASS' ELSE 'FAIL' END AS BLOCK4_PERM,
  (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M WHERE PROC_NM='DMF0002_GET_TITLESET_POPUP') AS BLOCK5_PROC_CNT
  FROM (SELECT 1 AS X FROM DUAL) ROOT
  LEFT JOIN SCM_MGR.SCM_ADM_MSG_M MSG  ON MSG.MSG_ID = 'MSG_API_DMF0002_TITLESET_POPUP' AND MSG.LANG_CD='KO'
  LEFT JOIN SCM_MGR.SCM_ADM_API_M API  ON API.API_ID = 'P_DMF0002_GET_TITLESET_POPUP'
  LEFT JOIN SCM_MGR.SCM_ADM_MNU_BTN_MPG_M BTN
         ON BTN.MNU_ID='DMF0043_01' AND BTN.SHT_NM='titleSet' AND BTN.MNU_BTN_CD='SEARCH'
  LEFT JOIN SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M PERM
         ON PERM.USER_GR_ID='GUEST' AND PERM.MNU_ID='DMF0043_01' AND PERM.SHT_NM='titleSet';
