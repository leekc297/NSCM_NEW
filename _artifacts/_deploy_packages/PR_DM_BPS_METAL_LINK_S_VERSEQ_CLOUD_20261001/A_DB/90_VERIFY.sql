SET PAGESIZE 200 LINESIZE 300

-- [1] VALID / 오류 0
SELECT STATUS, TO_CHAR(LAST_DDL_TIME, 'YYYY-MM-DD HH24:MI:SS') LAST_DDL
  FROM USER_OBJECTS WHERE OBJECT_NAME = 'PR_DM_BPS_METAL_LINK_S';
SELECT LINE, POSITION, TEXT FROM USER_ERRORS WHERE NAME = 'PR_DM_BPS_METAL_LINK_S' ORDER BY SEQUENCE;

-- [2] 채번 줄 — 'FM00' 식 1줄
SELECT LINE, TRIM(TEXT) TEXT FROM USER_SOURCE
 WHERE NAME = 'PR_DM_BPS_METAL_LINK_S' AND INSTR(TEXT, 'E20261001-VERSEQ2D') > 0;

-- [3] 식 재현 — V01 / V02 / V10 (NUMBER 값 기준, 공백 없음)
SELECT '26RF_DM_2026_W40_V' || NVL(TO_CHAR(CAST(NULL AS NUMBER), 'FM00'), '01') FIRST_RUN
     , '26RF_DM_2026_W40_V' || NVL(TO_CHAR(2, 'FM00'), '01')                     SECOND_RUN
     , '26RF_DM_2026_W40_V' || NVL(TO_CHAR(10, 'FM00'), '01')                    TENTH_RUN
  FROM DUAL;
