-- 99_ROLLBACK_PR_DM_BPS_METAL_LINK_S.sql — 원복 필요 시에만 실행 (클라우드 SCM_MGR)
--   01 이 넣은 식+주석을 원래 식 NVL(Y.VERSION_SEQ, '01') 로 되돌린다 (자기 원문 치환 방식 · 멱등)
SET SERVEROUTPUT ON
DECLARE
    C_NAME CONSTANT VARCHAR2(30)  := 'PR_DM_BPS_METAL_LINK_S';
    C_PAT  CONSTANT VARCHAR2(300) := 'NVL\(TO_CHAR\(Y\.VERSION_SEQ, ''FM00''\), ''01''\) /\*\[E20261001-VERSEQ2D\][^*]*\*/';
    V_SRC  CLOB;
    V_CNT  PLS_INTEGER;
    V_ST   VARCHAR2(10);
BEGIN
    DBMS_LOB.CREATETEMPORARY(V_SRC, TRUE);
    FOR R IN (SELECT TEXT FROM USER_SOURCE WHERE NAME = C_NAME AND TYPE = 'PROCEDURE' ORDER BY LINE) LOOP
        DBMS_LOB.APPEND(V_SRC, TO_CLOB(R.TEXT));
    END LOOP;
    V_CNT := REGEXP_COUNT(V_SRC, C_PAT);
    IF V_CNT = 0 THEN
        DBMS_OUTPUT.PUT_LINE('NOTHING — 패치 흔적 없음, 변경 없음');
        RETURN;
    ELSIF V_CNT <> 1 THEN
        RAISE_APPLICATION_ERROR(-20002, '패치 식 일치 ' || V_CNT || '곳 — 중단, 무변경');
    END IF;
    V_SRC := REGEXP_REPLACE(V_SRC, C_PAT, 'NVL(Y.VERSION_SEQ, ''01'')');
    EXECUTE IMMEDIATE 'CREATE OR REPLACE ' || V_SRC;
    SELECT STATUS INTO V_ST FROM USER_OBJECTS WHERE OBJECT_NAME = C_NAME AND OBJECT_TYPE = 'PROCEDURE';
    DBMS_OUTPUT.PUT_LINE('ROLLED BACK — STATUS=' || V_ST);
END;
/
