-- 01_PATCH_PR_DM_BPS_METAL_LINK_S.sql — 클라우드 SCM_MGR 에서 실행
--   [E20261001-VERSEQ2D] VERSION_NO 가 '..._V1' 로 생성되는 결함 수정
--   클라우드 판본(LAST_DDL 2026-08-14)이 사내(2026-09-02)와 다르므로 전문 교체 대신
--   "클라우드 자기 원문"을 읽어 채번식 1곳만 치환 후 재컴파일한다 (나머지 원문 보존).
--     NVL(Y.VERSION_SEQ, '01')  →  NVL(TO_CHAR(Y.VERSION_SEQ, 'FM00'), '01')
--   이미 적용된 경우 'ALREADY' 출력 후 종료(멱등) / 일치 1곳이 아니면 오류로 중단(무변경).
SET SERVEROUTPUT ON
DECLARE
    C_NAME CONSTANT VARCHAR2(30)  := 'PR_DM_BPS_METAL_LINK_S';
    C_MARK CONSTANT VARCHAR2(40)  := '[E20261001-VERSEQ2D]';
    C_PAT  CONSTANT VARCHAR2(200) := 'NVL\(\s*Y\.VERSION_SEQ\s*,\s*''01''\s*\)';
    C_NEW  CONSTANT VARCHAR2(400) := 'NVL(TO_CHAR(Y.VERSION_SEQ, ''FM00''), ''01'') /*[E20261001-VERSEQ2D] GTT VERSION_SEQ=NUMBER → NVL 결과 NUMBER 로 ''_V1'' 생성되던 결함. ''FM00'' = 공백 없는 2자리*/';
    V_SRC  CLOB;
    V_CNT  PLS_INTEGER;
    V_ST   VARCHAR2(10);
BEGIN
    DBMS_LOB.CREATETEMPORARY(V_SRC, TRUE);
    FOR R IN (SELECT TEXT FROM USER_SOURCE WHERE NAME = C_NAME AND TYPE = 'PROCEDURE' ORDER BY LINE) LOOP
        DBMS_LOB.APPEND(V_SRC, TO_CLOB(R.TEXT));
    END LOOP;
    IF DBMS_LOB.GETLENGTH(V_SRC) IS NULL OR DBMS_LOB.GETLENGTH(V_SRC) = 0 THEN
        RAISE_APPLICATION_ERROR(-20001, C_NAME || ' 원문 없음 — 중단');
    END IF;
    IF DBMS_LOB.INSTR(V_SRC, C_MARK) > 0 THEN
        DBMS_OUTPUT.PUT_LINE('ALREADY — ' || C_MARK || ' 이미 적용됨, 변경 없음');
        RETURN;
    END IF;
    V_CNT := REGEXP_COUNT(V_SRC, C_PAT);
    IF V_CNT <> 1 THEN
        RAISE_APPLICATION_ERROR(-20002, '채번식 일치 ' || V_CNT || '곳 (1곳이어야 함) — 중단, 무변경. 결과 공유 바랍니다');
    END IF;
    V_SRC := REGEXP_REPLACE(V_SRC, C_PAT, C_NEW);
    EXECUTE IMMEDIATE 'CREATE OR REPLACE ' || V_SRC;
    SELECT STATUS INTO V_ST FROM USER_OBJECTS WHERE OBJECT_NAME = C_NAME AND OBJECT_TYPE = 'PROCEDURE';
    DBMS_OUTPUT.PUT_LINE('PATCHED — STATUS=' || V_ST);
END;
