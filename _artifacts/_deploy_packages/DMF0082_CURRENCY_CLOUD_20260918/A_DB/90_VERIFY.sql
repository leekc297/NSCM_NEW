-- §2. 결손 대상 키 존재 여부 (적용 전 사전 확인용 — 클라우드 실데이터 기준)
--     수요 원장과 단가 원장이 CELL_PROD_SITE_ID 만 다른 키 = 본 보완의 대상
WITH DEM AS (
  SELECT DISTINCT DIVISION_ID d1, PROJECT_CODE d2, SCM_SITE_ID d3, PLANT_SITE_ID d4,
         ITEM_ID d5, INCOTERMS d6, DOM_EXP d7, FCST_TYPE d8, CELL_PROD_SITE_ID d9
    FROM SCM_MGR.DM_PLN_CFM_MKT_DEMAND_PLAN
   WHERE DIVISION_ID = '40' AND YYYYMMDD >= TO_CHAR(SYSDATE, 'YYYY') || '0101' AND QTY <> 0
), PRC AS (
  SELECT DISTINCT DIVISION_ID p1, PROJECT_CODE p2, SCM_SITE_ID p3, PLANT_SITE_ID p4,
         ITEM_ID p5, INCOTERMS p6, DOM_EXP p7, FCST_TYPE p8, CELL_PROD_SITE_ID p9
    FROM SCM_MGR.DM_PLN_CFM_SELLING_PRICE
   WHERE DIVISION_ID = '40' AND YYYYMMDD >= TO_CHAR(SYSDATE, 'YYYY') || '0101' AND MEASURE = 'LOC'
)
SELECT D.d5 ITEM_ID, D.d3 SCM_SITE, D.d2 PROJECT,
       D.d9 DEMAND_CELLPROD, P.p9 PRICE_CELLPROD, D.d6 INCOTERMS, D.d8 FCST_TYPE
  FROM DEM D
  JOIN PRC P ON P.p1=D.d1 AND P.p2=D.d2 AND P.p3=D.d3 AND P.p4=D.d4 AND P.p5=D.d5
            AND P.p6=D.d6 AND P.p7=D.d7 AND P.p8=D.d8
 WHERE P.p9 <> D.d9
   AND NOT EXISTS (SELECT 1 FROM PRC P2
                    WHERE P2.p1=D.d1 AND P2.p2=D.d2 AND P2.p3=D.d3 AND P2.p4=D.d4
                      AND P2.p5=D.d5 AND P2.p6=D.d6 AND P2.p7=D.d7 AND P2.p8=D.d8
                      AND P2.p9=D.d9)
 ORDER BY 1, 2;
-- 여기 나오는 키가 적용 전에는 CURRENCY 가 비고, 적용 후에는 채워져야 한다.
-- (사내 ZIOUI1 2026-09-18 기준 3건 — MIF489266C11/NT_CN_SZX 등)


-- §3. 오배정 차단 게이트 확인
--     8키 안에서 통화가 2종 이상인 키는 보완 대상에서 제외된다. 그 규모를 먼저 본다.
SELECT DIVISION_ID, COUNT(*) AS MULTI_CURRENCY_KEYS
  FROM ( SELECT DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, PLANT_SITE_ID, ITEM_ID,
                INCOTERMS, DOM_EXP, FCST_TYPE
           FROM SCM_MGR.DM_PLN_CFM_SELLING_PRICE
          WHERE MEASURE = 'LOC' AND YYYYMMDD >= TO_CHAR(SYSDATE, 'YYYY') || '0101'
          GROUP BY DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, PLANT_SITE_ID, ITEM_ID,
                   INCOTERMS, DOM_EXP, FCST_TYPE
         HAVING COUNT(DISTINCT CURRENCY) > 1 )
 GROUP BY DIVISION_ID
 UNION ALL
SELECT DIVISION_ID, COUNT(*)
  FROM ( SELECT DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, PLANT_SITE_ID, ITEM_ID,
                INCOTERMS, DOM_EXP, FCST_TYPE
           FROM SCM_MGR.SCM_MST_FUTURE_PRICE
          WHERE MEASURE = 'LOC' AND YYYYMMDD >= TO_CHAR(SYSDATE, 'YYYY') || '0101'
          GROUP BY DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, PLANT_SITE_ID, ITEM_ID,
                   INCOTERMS, DOM_EXP, FCST_TYPE
         HAVING COUNT(DISTINCT CURRENCY) > 1 )
 GROUP BY DIVISION_ID;
-- 이 키들은 CURRENCY 가 비어 있어도 보완이 채우지 않는다(오배정 방지). 정상이다.
