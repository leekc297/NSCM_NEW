-- 기대: PACKAGE / PACKAGE BODY 모두 STATUS = VALID

SELECT COUNT(*) AS MARKER_LINES
  FROM ALL_SOURCE
 WHERE OWNER = 'SCM_MGR' AND NAME = 'PKG_DMF0082' AND TYPE = 'PACKAGE BODY'
   AND TEXT LIKE '%E20260918-CURRCELLPROD%';
