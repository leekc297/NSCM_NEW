-- 90_VERIFY.sql — DMF0074 Excel Form 2단 양식 + Upload 보완 적용 확인 (클라우드, SCM_MGR)

-- [사전] 02 적용 전 — 클라우드 PKG_NSCM_UI_EXCEL BODY 가 사내 변경 전 본문과 같은지 확인
--   기대: ERROR 필터가 안쪽 SELECT 에 있는 구 로직 1줄 (T.UPLOAD_STATUS_CODE = ''ERROR'') = 1
--   0 이거나 다른 마커가 보이면 02 전체 교체 대신 PR_GET_EXCEL_UPLOAD_RESULT 구간만 병합할 것
SELECT COUNT(*) AS OLD_LOGIC_LINE FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_NSCM_UI_EXCEL' AND TYPE='PACKAGE BODY'
   AND TEXT LIKE '%T.UPLOAD_STATUS_CODE = ''''ERROR''''%';
SELECT LINE, TEXT FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_NSCM_UI_EXCEL' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%[E2026%' ORDER BY LINE;

-- [01] HEADER_CONTENT — 기대: DMF0074=55 / DMF0074_40=53 토큰, 메탈 토큰 '그룹명_하위명'
SELECT PROGRAM_ID,
       REGEXP_COUNT(HEADER_CONTENT, '\|') + 1 AS TOKEN_CNT,
       CASE WHEN INSTR(HEADER_CONTENT, 'Period(Fr)_Ni') > 0 AND INSTR(HEADER_CONTENT, 'Metal Index (kg/Biz type)_Cu') > 0
            THEN 'OK' ELSE 'NG' END AS NEW_TOKEN,
       CASE WHEN INSTR(HEADER_CONTENT, 'PeriodFr_Ni') > 0 THEN 'NG(구토큰 잔존)' ELSE 'OK' END AS OLD_TOKEN
  FROM SCM_MGR.SCM_ADM_EXCEL_COLUMNS
 WHERE PROGRAM_ID IN ('DMF0074', 'DMF0074_40') AND SHEET_NAME = 'Metal Link Price'
 ORDER BY 1;

-- [02] PKG_NSCM_UI_EXCEL — 기대: PACKAGE/PACKAGE BODY VALID · ERR 0 · 마커 1 · 구 로직 라인 0
SELECT OBJECT_TYPE, STATUS, LAST_DDL_TIME FROM ALL_OBJECTS WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_NSCM_UI_EXCEL';
SELECT COUNT(*) AS ERR_CNT FROM ALL_ERRORS WHERE OWNER='SCM_MGR' AND NAME='PKG_NSCM_UI_EXCEL';
SELECT COUNT(*) AS MARKER_CNT FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_NSCM_UI_EXCEL' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%E20260914-EXCELROW%';
SELECT COUNT(*) AS OLD_LOGIC_LINE FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_NSCM_UI_EXCEL' AND TYPE='PACKAGE BODY'
   AND TEXT LIKE '%T.UPLOAD_STATUS_CODE = ''''ERROR''''%';

-- [업로드 후] 최신 배치 스테이징 — 기대: 1행 @TITLE / 2행 SKIP(2단 헤더 자리) / 3행부터 데이터
SELECT ROW_NUMBER() OVER (ORDER BY UPLOAD_ID) AS EXCEL_ROW, UPLOAD_STATUS_CODE, ATTRIBUTE1, ATTRIBUTE2, ATTRIBUTE3, MESSAGE_TEXT
  FROM SCM_MGR.SCM_ADM_EXCEL_UPLOAD
 WHERE PROGRAM_ID LIKE 'DMF0074%' AND SHEET_NAME = 'Metal Link Price' AND CREATED_BY = :USER_ID
   AND CREATION_DATE = (SELECT MAX(CREATION_DATE) FROM SCM_MGR.SCM_ADM_EXCEL_UPLOAD
                         WHERE PROGRAM_ID LIKE 'DMF0074%' AND SHEET_NAME = 'Metal Link Price' AND CREATED_BY = :USER_ID)
 ORDER BY UPLOAD_ID;
