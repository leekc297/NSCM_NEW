-- 00_CLOUD_PRECHECK.sql — 클라우드 반영 **전** 선행 확인 (QA / DEV 2개 DB 각각 실행)
--
-- ⚠ 이 스크립트는 조회만 한다. 결과를 보고 적용 여부·범위를 결정한 뒤 A_DB 를 적용할 것.
--   RTFGATE2 는 "Cutoff 원장 실존"으로 판정하므로, 클라우드에 ①lookup 시각값과 ②SP_W 적재가
--   없으면 **RTF 편집이 전면 차단**된다. 이 2가지가 이번 이관의 최대 리스크다.

PROMPT ===== C1) 게이트 기준 시점 — lookup GET_ADMIN_GROUP_MEASURE (DMF0021 · RTF_SYS_RP)
PROMPT   기대: division 별 행 존재 + ATTRIBUTE1(요일) / ATTRIBUTE2(HHMM) 값 있음
PROMPT   ⚠ ATTRIBUTE1 이 NULL 이면 게이트가 "상시 허용"으로 무력화된다 (차단이 아예 안 걸림)
PROMPT   ⚠ 행 자체가 없으면 그 division 은 RTF 편집 불가 (권한 축에서 탈락)
SELECT SEGMENT3 AS DIVISION_ID, SEGMENT1 AS GRP, SEGMENT4 AS MEASURE,
       ATTRIBUTE1 AS DAY_OF_WEEK, ATTRIBUTE2 AS HHMM, VALID_YN
  FROM SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE = 'GET_ADMIN_GROUP_MEASURE' AND SEGMENT2 = 'DMF0021'
 ORDER BY SEGMENT4, SEGMENT3, SEGMENT1;
-- 사내 실측 참고값(2026-08-18): RTF_SYS_RP = 40/81_HD/81_HG/81_HM/81_ST/81_UC 는 MON 1600,
--   81 은 SAT 1600. 그룹 = ADMIN / SCM PI Admin / SCP Planner. SalesAmt_LOC 는 ATTRIBUTE1 NULL(상시).

PROMPT ===== C2) Cutoff 원장 — DM_MST_VERSION SP_W 적재 실태 (최근 8주)
PROMPT   기대: division 별로 주 1회 이상 SP_W(SALES_PLAN WEEKLY CUTOFF) 가 쌓이고 있을 것
PROMPT   ⚠ 0행이면 RTFGATE2 는 "Cutoff 미완료"로 판단해 전면 차단한다 → 배치 적재부터 확인
SELECT DIVISION_ID, VERSION_TYPE, MAX(VERSION_DESCRIPTION) AS DESCR, COUNT(*) AS CNT,
       COUNT(DISTINCT YYYYMMDD) AS DAYS,
       TO_CHAR(MAX(CREATION_DATE), 'YYYY-MM-DD HH24:MI') AS LAST_CRE
  FROM DM_MST_VERSION
 WHERE VERSION_TYPE = 'SP_W' AND CREATION_DATE >= TRUNC(SYSDATE, 'IW') - 56
 GROUP BY DIVISION_ID, VERSION_TYPE
 ORDER BY 1;

PROMPT ===== C3) 지금 시각 기준 게이트 판정 시뮬 (적용 후 어떻게 될지 미리 보기)
PROMPT   CUTOFF_DAYS = 1 → 편집 허용 / 0 → 차단(미완료) / 2 이상 → 차단(2차 Cutoff 완료)
SELECT DISTINCT L.SEGMENT3 AS DIVISION_ID, L.ATTRIBUTE1 AS A1, L.ATTRIBUTE2 AS A2,
       TO_CHAR((CASE WHEN TRUNC(SYSDATE,'IW')
                          + DECODE(L.ATTRIBUTE1,'MON',0,'TUE',1,'WED',2,'THU',3,'FRI',4,'SAT',5,'SUN',6)
                          + NVL(TO_NUMBER(SUBSTR(L.ATTRIBUTE2,1,2)),0)/24
                          + NVL(TO_NUMBER(SUBSTR(L.ATTRIBUTE2,3,2)),0)/1440 > SYSDATE
                     THEN TRUNC(SYSDATE,'IW')-7 ELSE TRUNC(SYSDATE,'IW') END)
               + DECODE(L.ATTRIBUTE1,'MON',0,'TUE',1,'WED',2,'THU',3,'FRI',4,'SAT',5,'SUN',6)
               + NVL(TO_NUMBER(SUBSTR(L.ATTRIBUTE2,1,2)),0)/24
               + NVL(TO_NUMBER(SUBSTR(L.ATTRIBUTE2,3,2)),0)/1440, 'YYYY-MM-DD HH24:MI DY') AS ANCHOR_AT,
       (SELECT COUNT(DISTINCT V.YYYYMMDD) FROM DM_MST_VERSION V
         WHERE V.VERSION_TYPE = 'SP_W' AND V.DIVISION_ID = L.SEGMENT3
           AND V.CREATION_DATE >
               (CASE WHEN TRUNC(SYSDATE,'IW')
                          + DECODE(L.ATTRIBUTE1,'MON',0,'TUE',1,'WED',2,'THU',3,'FRI',4,'SAT',5,'SUN',6)
                          + NVL(TO_NUMBER(SUBSTR(L.ATTRIBUTE2,1,2)),0)/24
                          + NVL(TO_NUMBER(SUBSTR(L.ATTRIBUTE2,3,2)),0)/1440 > SYSDATE
                     THEN TRUNC(SYSDATE,'IW')-7 ELSE TRUNC(SYSDATE,'IW') END)
               + DECODE(L.ATTRIBUTE1,'MON',0,'TUE',1,'WED',2,'THU',3,'FRI',4,'SAT',5,'SUN',6)
               + NVL(TO_NUMBER(SUBSTR(L.ATTRIBUTE2,1,2)),0)/24
               + NVL(TO_NUMBER(SUBSTR(L.ATTRIBUTE2,3,2)),0)/1440) AS CUTOFF_DAYS
  FROM SCM_ADM_LOOKUP_MASTER_DETAIL L
 WHERE L.LOOKUP_TYPE = 'GET_ADMIN_GROUP_MEASURE' AND L.SEGMENT2 = 'DMF0021'
   AND L.SEGMENT4 = 'RTF_SYS_RP' AND L.VALID_YN = 'Y'
 ORDER BY 1;

PROMPT ===== C4) MSG 코드 충돌 확인 — MSG00704 는 **손대지 말 것**
PROMPT   클라우드 MSG00704 = 사용자 생성 문구("수정 중인 데이터가 있습니다. 조회 하시겠습니까?")
PROMPT   이번 이관은 MSG01001 **신규 INSERT 만** 한다. MSG00704 UPDATE 금지.
SELECT MSG_ID, LANG_CD, SUBSTR(MSG_NM,1,70) AS MSG_NM, CREATED_BY, USE_YN
  FROM SCM_ADM_MSG_M WHERE MSG_ID IN ('MSG00703','MSG00704','MSG01001') ORDER BY MSG_ID, LANG_CD;

PROMPT ===== C5) 01001+ 대역 선점 여부 (MSG01001 이 이미 다른 뜻으로 쓰이는지)
PROMPT   ⚠ 행이 있으면 채번 충돌 — 다음 번호로 재채번하고 PKG BODY 의 V_S_CODE 도 함께 바꿀 것
SELECT MSG_ID, LANG_CD, SUBSTR(MSG_NM,1,70) AS MSG_NM
  FROM SCM_ADM_MSG_M WHERE MSG_ID >= 'MSG01001' AND MSG_ID <> 'MSG99999' ORDER BY MSG_ID, LANG_CD;

