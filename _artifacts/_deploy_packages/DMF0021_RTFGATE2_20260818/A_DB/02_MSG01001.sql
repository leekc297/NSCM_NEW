-- MSG01001_RTF_CUTOFF_20260818.sql — RTF[R+P] Cutoff 차단 메시지 신규 채번
--   구 MSG00704 는 클라우드에 이미 다른 뜻으로 존재해 2026-08-15 사내 원장이 그 문구로 덮였다.
--   채번 규약(2026-08-14 사용자 확정): 기존 코드 문구 덮어쓰기 금지 / 신규는 01001+ 대역.
--   현재 01001+ 대역 MAX 없음 → MSG01001 이 최초 채번.
--   감사컬럼 = 'admin' 고정 (메타 감사컬럼 규약).

MERGE INTO SCM_MGR.SCM_ADM_MSG_M T
USING (SELECT 'MSG01001' AS MSG_ID, 'KO' AS LANG_CD FROM DUAL) S
ON (T.MSG_ID = S.MSG_ID AND T.LANG_CD = S.LANG_CD)
WHEN MATCHED THEN UPDATE SET MSG_NM = 'Sales Plan Cutoff 완료 후에만 RTF[R+P] 수정이 가능합니다.', USE_YN = 'Y', LAST_UPDATED_BY = 'admin', LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (MSG_ID, LANG_CD, MSG_NM, MSG_TP_CD, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES ('MSG01001', 'KO', 'Sales Plan Cutoff 완료 후에만 RTF[R+P] 수정이 가능합니다.', 'MSG', 'Y', 'admin', SYSDATE, 'admin', SYSDATE);

MERGE INTO SCM_MGR.SCM_ADM_MSG_M T
USING (SELECT 'MSG01001' AS MSG_ID, 'EN' AS LANG_CD FROM DUAL) S
ON (T.MSG_ID = S.MSG_ID AND T.LANG_CD = S.LANG_CD)
WHEN MATCHED THEN UPDATE SET MSG_NM = 'RTF[R+P] can be modified only after Sales Plan Cutoff is completed.', USE_YN = 'Y', LAST_UPDATED_BY = 'admin', LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (MSG_ID, LANG_CD, MSG_NM, MSG_TP_CD, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES ('MSG01001', 'EN', 'RTF[R+P] can be modified only after Sales Plan Cutoff is completed.', 'MSG', 'Y', 'admin', SYSDATE, 'admin', SYSDATE);

MERGE INTO SCM_MGR.SCM_ADM_MSG_M T
USING (SELECT 'MSG01001' AS MSG_ID, 'CN' AS LANG_CD FROM DUAL) S
ON (T.MSG_ID = S.MSG_ID AND T.LANG_CD = S.LANG_CD)
WHEN MATCHED THEN UPDATE SET MSG_NM = '只有在Sales Plan Cutoff完成后才能修改RTF[R+P]。', USE_YN = 'Y', LAST_UPDATED_BY = 'admin', LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (MSG_ID, LANG_CD, MSG_NM, MSG_TP_CD, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES ('MSG01001', 'CN', '只有在Sales Plan Cutoff完成后才能修改RTF[R+P]。', 'MSG', 'Y', 'admin', SYSDATE, 'admin', SYSDATE);

COMMIT;
