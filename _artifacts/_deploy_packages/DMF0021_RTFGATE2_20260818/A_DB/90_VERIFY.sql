-- 90_VERIFY.sql — DMF0021 RTFGATE2 배포 검증 (대상 객체 실측만 — 룰 #136)
-- 기대: BODY VALID / ALL_ERRORS 0행 / RTFGATE2 마커 2행 / MSG01001 3언어 / 비주석 MSG00704 0행

PROMPT === 1) 객체 상태 (PACKAGE BODY = VALID 이어야 함)
SELECT OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL
  FROM ALL_OBJECTS WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_DMF0021' ORDER BY OBJECT_TYPE;

PROMPT === 2) 컴파일 오류 (0행 이어야 함)
SELECT LINE, POSITION, SUBSTR(TEXT,1,120) TXT FROM ALL_ERRORS
 WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0021' ORDER BY SEQUENCE;

PROMPT === 3) RTFGATE2 마커 (GET/SAVE 2행 이어야 함)
SELECT LINE, RTRIM(SUBSTR(TEXT,1,90)) SRC FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0021' AND TYPE='PACKAGE BODY'
   AND TEXT LIKE '%[RTFGATE2 2026-08-18]%' ORDER BY LINE;

PROMPT === 4) 차단 메시지 코드 (V_S_CODE := 'MSG01001' 1행 / 비주석 MSG00704 0행)
SELECT LINE, RTRIM(SUBSTR(TEXT,1,110)) SRC FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0021' AND TYPE='PACKAGE BODY'
   AND TEXT LIKE '%V_S_CODE := ''MSG01001''%' ORDER BY LINE;
SELECT COUNT(*) NONCOMMENT_MSG00704 FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0021' AND TYPE='PACKAGE BODY'
   AND TEXT LIKE '%MSG00704%' AND LTRIM(TEXT) NOT LIKE '--%';

PROMPT === 5) MSG01001 원장 (KO/EN/CN 3행 · CREATED_BY=admin)
SELECT MSG_ID, LANG_CD, SUBSTR(MSG_NM,1,70) MSG_NM, CREATED_BY, USE_YN
  FROM SCM_ADM_MSG_M WHERE MSG_ID='MSG01001' ORDER BY LANG_CD;

PROMPT === 6) 게이트 판정 현황 (division 별 — CUTOFF_DAYS=1 이면 ALLOW)
SELECT DISTINCT B.SEGMENT3 DIVISION_ID, B.ATTRIBUTE1 A1, B.ATTRIBUTE2 A2,
       (SELECT COUNT(DISTINCT V.YYYYMMDD) FROM DM_MST_VERSION V
         WHERE V.VERSION_TYPE='SP_W' AND V.DIVISION_ID=B.SEGMENT3
           AND V.CREATION_DATE >
               (CASE WHEN TRUNC(SYSDATE,'IW')
                          + DECODE(B.ATTRIBUTE1,'MON',0,'TUE',1,'WED',2,'THU',3,'FRI',4,'SAT',5,'SUN',6)
                          + NVL(TO_NUMBER(SUBSTR(B.ATTRIBUTE2,1,2)),0)/24
                          + NVL(TO_NUMBER(SUBSTR(B.ATTRIBUTE2,3,2)),0)/1440 > SYSDATE
                     THEN TRUNC(SYSDATE,'IW')-7 ELSE TRUNC(SYSDATE,'IW') END)
               + DECODE(B.ATTRIBUTE1,'MON',0,'TUE',1,'WED',2,'THU',3,'FRI',4,'SAT',5,'SUN',6)
               + NVL(TO_NUMBER(SUBSTR(B.ATTRIBUTE2,1,2)),0)/24
               + NVL(TO_NUMBER(SUBSTR(B.ATTRIBUTE2,3,2)),0)/1440) CUTOFF_DAYS
  FROM SCM_ADM_LOOKUP_MASTER_DETAIL B
 WHERE B.LOOKUP_TYPE='GET_ADMIN_GROUP_MEASURE' AND B.SEGMENT2='DMF0021'
   AND B.SEGMENT4='RTF_SYS_RP' AND B.VALID_YN='Y'
 ORDER BY 1;
