 * 2025.07.30       jssbae       [E20250729-000433]_[공급/생산SCM PI팀] 월요일 SCM FCST 입력 시 MKT FCST 수정 불가하도록 시스템 개선
 * 2026.01.30       jssbae       [E20260130-001907]_FCST&PRICE MGMT Cutoff 버전 조회 대상 테이블 변경
 *===================================================================================================================================================*/
IS
    /* 사용자 컬럼 및 메저 세팅 관련 변수 */
    V_USER_COL_CNT      NUMBER := 0;
    V_USER_MEA_CNT      NUMBER := 0;
    VA_PROGRAM_ID       VARCHAR2(50) := 'DMF0082';
    VA_SHEET_NAME       VARCHAR2(50) := 'fcstNPrice_'||P_DIVISION_ID;

    /* BUCKET 관련 변수 */
    V_EXP_YYYYMMDD      VARCHAR2(8);
    V_BUCKET_CASE_COLS  CLOB;

    /* 동적쿼리 관련 변수 */
    V_SQL_TEXT          CLOB;
    V_PARAM_JSON        CLOB;

    V_ROWCOUNT          NUMBER;

    V_PROGRAM_NAME     VARCHAR2(150) := 'P_DMF0082_GET_MAIN_DATA';
    V_LOG_TYPE         VARCHAR2(30);
    N_LOG_COUNT        NUMBER := 0;
    V_LOG_MESSAGE      VARCHAR2(1000);
    V_LOG_DESC         VARCHAR2(500);
    D_EVENT_DATE       DATE;


    V_USER_TIME_ZONE   VARCHAR2(50);
    V_FROM_YYYYMMDD    VARCHAR2(8);
    V_TO_YYYYMMDD      VARCHAR2(8);
    V_FROM_RESULT      VARCHAR2(8);
    V_TO_RESULT        VARCHAR2(8);


BEGIN
    --EXECUTE IMMEDIATE 'ALTER SESSION ENABLE PARALLEL DML';

    V_LOG_TYPE    := 'START';
    V_LOG_MESSAGE := '########## Start of procedure ##########';
    V_LOG_DESC    := '';
    D_EVENT_DATE  := SYSDATE;

    PR_SCM_SYS_LOG_BATCH(V_PROGRAM_NAME, V_LOG_TYPE, N_LOG_COUNT, V_LOG_MESSAGE, V_LOG_DESC, D_EVENT_DATE);






    BEGIN
        SELECT U.TMZ_CD
          INTO V_USER_TIME_ZONE
          FROM SCM_ADM_USER_M U
         WHERE U.USER_ID = P_USER_ID;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            V_USER_TIME_ZONE := 'UTC';
    END;

    -- @V_FROM_YYYYMMDD : (USER 시차를 고려한) 당주 월요일
    SELECT MIN(C.BASIS_YYYYMMDD)
      INTO V_FROM_YYYYMMDD
      FROM SCM_SYS_CALENDAR_M C
      JOIN (
            SELECT DISTINCT ISO_YYYYWW
              FROM SCM_SYS_CALENDAR_M
             WHERE BASIS_YYYYMMDD = TO_CHAR(FN_MULTY_TIME(V_USER_TIME_ZONE), 'YYYYMMDD')
           ) T
        ON C.ISO_YYYYWW = T.ISO_YYYYWW;

    -- FROM 실적 : FROM 조회 구간 월요일부터
    SELECT C.BASIS_START_DATE
      INTO V_FROM_RESULT
      FROM SCM_SYS_CALENDAR_M C
     WHERE C.BASIS_YYYYMMDD = P_FROM_YYYYMMDD;

    -- TO 실적 : TO 조회 구간 월요일 전까지
    SELECT C.BASIS_START_DATE
      INTO V_TO_RESULT
      FROM SCM_SYS_CALENDAR_M C
     WHERE C.BASIS_YYYYMMDD = P_TO_YYYYMMDD;

    IF V_FROM_YYYYMMDD > V_FROM_RESULT THEN
        -- 실적 보여줌
        V_TO_YYYYMMDD := P_TO_YYYYMMDD;
        V_TO_RESULT   := V_FROM_YYYYMMDD; -- TO 실적 : 당주 월요일 전까지
    ELSIF V_FROM_YYYYMMDD <= V_FROM_RESULT THEN
        -- 실적 없음
        V_TO_YYYYMMDD := P_TO_YYYYMMDD;
        V_FROM_RESULT := '19000101';
        V_TO_RESULT   := '19000101';
    ELSIF V_FROM_YYYYMMDD > V_TO_RESULT THEN
        -- 실적만 보여줌
        V_FROM_YYYYMMDD := '19000101';
        V_TO_YYYYMMDD   := '19000101';
        V_FROM_RESULT   := P_FROM_YYYYMMDD; -- FROM 실적 : FROM 조회 구간부터
        V_TO_RESULT     := P_TO_YYYYMMDD;   -- TO 실적 : TO 조회 구간까지
    ELSIF V_FROM_YYYYMMDD = V_TO_RESULT THEN
        -- 실적 없음
        V_TO_YYYYMMDD := V_FROM_YYYYMMDD;
        V_FROM_RESULT := P_FROM_YYYYMMDD;
        V_TO_RESULT   := P_TO_YYYYMMDD;
    END IF;



    /* 동적쿼리에서만 사용 하는 임시테이블 */
    EXECUTE IMMEDIATE 'TRUNCATE TABLE GT_DMF0082_SITE_ITEM';
    EXECUTE IMMEDIATE 'TRUNCATE TABLE GT_DMF0082_SELECT_MEASURE';
    EXECUTE IMMEDIATE 'TRUNCATE TABLE GT_DMF0082_FCST_N_PRICE';
    EXECUTE IMMEDIATE 'TRUNCATE TABLE GT_DMF0082_ADMIN_GROUP_MEASURE';



    /* 사용자 컬럼 및 메저 세팅 시작 */
    /* 사용자 컬럼 처리 */
    SELECT COUNT(*)
      INTO V_USER_COL_CNT
      FROM SCM_MST_TITLESET_USER U
     WHERE U.PROGRAM_ID = VA_PROGRAM_ID
       AND U.SHEET_NAME = VA_SHEET_NAME
       AND U.USER_INQUIRY_COLUMN_TYPE_CODE = 'C'
       AND U.USER_ID = P_USER_ID;

    IF V_USER_COL_CNT = 0 THEN
        INSERT INTO SCM_MST_TITLESET_USER
        (
              USER_ID, PROGRAM_ID, SHEET_NAME, USER_INQUIRY_COLUMN_TYPE_CODE
            , COLUMN_NAME, SORT_ORDER_NO, SUB_TOTAL_FLAG, DATA_SORT_METHOD_CODE
            , CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE
        )
        SELECT P_USER_ID, C.PROGRAM_ID, C.SHEET_NAME, 'C',
               C.COLUMN_NAME, C.SORT_ORDER_NO, 'N', '',
               P_USER_ID, SYSTIMESTAMP, P_USER_ID, SYSTIMESTAMP
          FROM SCM_MST_SHEET_COLUMNS C
         WHERE C.PROGRAM_ID = VA_PROGRAM_ID
           AND C.SHEET_NAME = VA_SHEET_NAME
           AND C.DEFAULT_FLAG = 'Y'
           AND C.VALID_YN = 'Y';
    END IF;

    /* 메저 처리 */
    SELECT COUNT(*)
      INTO V_USER_MEA_CNT
      FROM SCM_MST_TITLESET_USER U
     WHERE U.PROGRAM_ID = VA_PROGRAM_ID
       AND U.SHEET_NAME = VA_SHEET_NAME
       AND U.USER_INQUIRY_COLUMN_TYPE_CODE = 'M'
       AND U.USER_ID = P_USER_ID;

    IF V_USER_MEA_CNT = 0 THEN
        INSERT INTO SCM_MST_TITLESET_USER
        (
              USER_ID, PROGRAM_ID, SHEET_NAME, USER_INQUIRY_COLUMN_TYPE_CODE
            , COLUMN_NAME, SORT_ORDER_NO, SUB_TOTAL_FLAG, DATA_SORT_METHOD_CODE
            , CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE
        )
        SELECT P_USER_ID, C.PROGRAM_ID, C.SHEET_NAME, 'M',
               C.COLUMN_NAME, C.SORT_ORDER_NO, 'N', '',
               P_USER_ID, SYSTIMESTAMP, P_USER_ID, SYSTIMESTAMP
          FROM SCM_MST_SHEET_MEASURE C
         WHERE C.PROGRAM_ID = VA_PROGRAM_ID
           AND C.SHEET_NAME = VA_SHEET_NAME
           AND C.DEFAULT_FLAG = 'Y'
           AND C.VALID_YN = 'Y';
    END IF;
    /* 사용자 컬럼 및 메저 세팅 종료 */

    /* #TempSelectMeasure 만들기 시작 */
    INSERT INTO GT_DMF0082_SELECT_MEASURE
    (
          PROGRAM_ID, SHEET_NAME, USER_ID, MEASURE_GROUP, MEASURE, RESULT_MEASURE, PLAN_MEASURE, SORT_ORDER_NO
    )
    SELECT DISTINCT
          U.PROGRAM_ID
        , U.SHEET_NAME
        , U.USER_ID
        , U.COLUMN_NAME
        , U.COLUMN_NAME
        , COALESCE(SMSM.ATTRIBUTE5, U.COLUMN_NAME) AS RESULT_MEASURE
        , COALESCE(SMSM.ATTRIBUTE6, U.COLUMN_NAME) AS PLAN_MEASURE
        , U.SORT_ORDER_NO
      FROM SCM_MST_TITLESET_USER U
      JOIN SCM_MST_SHEET_MEASURE SMSM
        ON U.PROGRAM_ID = SMSM.PROGRAM_ID
       AND U.SHEET_NAME = SMSM.SHEET_NAME
       AND U.COLUMN_NAME = SMSM.COLUMN_NAME
     WHERE U.USER_INQUIRY_COLUMN_TYPE_CODE = 'M'
       AND U.PROGRAM_ID = VA_PROGRAM_ID
       AND U.SHEET_NAME = VA_SHEET_NAME
       AND U.USER_ID = P_USER_ID
       AND SMSM.VALID_YN = 'Y';
    /* #TempSelectMeasure 만들기 종료 */

    SELECT COUNT(*) INTO V_ROWCOUNT FROM GT_DMF0082_SELECT_MEASURE;
    IF V_ROWCOUNT >= 1000 THEN
        DBMS_STATS.GATHER_TABLE_STATS(USER, 'GT_DMF0082_SELECT_MEASURE');
    END IF;

    /* #TempSiteItem 만들기 시작 */
    INSERT INTO GT_DMF0082_SITE_ITEM
    (
          DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, NICK_NAME, PROJECT_NAME, CELL_MODEL
        , BIZ_TYPE, END_CUSTOMER, SOLDTO_CUSTOMER, COUNTRY_NAME, CITY_NAME, OWNER, PROJECT_OWNER
        , ITEM_NAME, ITEM_TYPE, PROJECT_STATUS, CUST_GROUP, CUST_GROUP_DTL, APPLICATION, ROUTE
        , MDM_PROJECT_NAME, MIN_CAPACITY, FORECAST_INFO_BIZ_TYPE, FORECAST_INFO_PRODUCT_GROUP
        , CELL_TYPE, FORECAST_INFO_CELL_PACK_COUNT, FORECAST_INFO_ALL, FORECAST_INFO_SPEC
        , FORECAST_INFOR_VERSION, CELL_MODEL_NICK_NAME, VMI_YN, DMS_SALES, DMS_CUSTOMER, DEPT_ID
        , DEPT_NAME_KO, CELL_PER_CAR, CELL_PER_MODULE, MODULE_PER_CAR, ITEM_CLASS_NAME, ENERGE
        , CELL_QUANTITY, ITEM_VALID_YN, PROJECT_S_OP_REPORT
    )
    SELECT
          F.DIVISION_ID
        , F.PROJECT_CODE
        , F.SCM_SITE_ID
        , F.ITEM_ID
        , I.NICK_NAME
        , F.PROJECT_CODE
        , F.ATTRIBUTE5
        , I.FORECAST_INFO_BIZ_TYPE
        , S.END_CUSTOMER
        , S.SOLDTO_CUSTOMER
        , CT.COUNTRY_NAME
        , CY.CITY_NAME
        , F.OWNER
        , U1.USER_NAME_EN
        , I.ITEM_NAME
        , I.ITEM_TYPE
        , ''
        , F.CUST_GROUP
        , F.CUST_GROUP_DTL
        , F.APPLICATION
        , F.ROUTE
        , I.MDM_PROJECT_NAME
        , I.MIN_CAPACITY
        , I.FORECAST_INFO_BIZ_TYPE
        , I.FORECAST_INFO_PRODUCT_GROUP
        , I.CELL_TYPE
        , I.FORECAST_INFO_CELL_PACK_COUNT
        , I.FORECAST_INFO_SPEC || I.FORECAST_INFOR_VERSION
        , I.FORECAST_INFO_SPEC
        , I.FORECAST_INFOR_VERSION
        , I.NICK_NAME
        , S.VMI_YN
        , F.ATTRIBUTE1
        , F.ATTRIBUTE2
        , F.DEPT_ID
        , D1.DEPT_NAME_KO
        , F.CELL_PER_CAR
        , F.CELL_PER_MODULE
        , CASE WHEN F.CELL_PER_MODULE = 0 OR F.CELL_PER_MODULE IS NULL THEN F.CELL_PER_CAR ELSE F.CELL_PER_CAR / F.CELL_PER_MODULE END
        , I.ITEM_CLASS_NAME
        , I.ENERGE
        , I.CELL_QUANTITY
        , F.VALID_YN
        , ''
        --, F.PROJECT_S_OP_REPORT
      FROM SCM_MST_SITE_ITEM F
      JOIN SCM_ITEM_M_SN I
        ON F.DIVISION_ID = I.DIVISION_ID
       AND F.ITEM_ID = I.ITEM_ID
      JOIN SCM_MST_SITE S
        ON F.DIVISION_ID = S.DIVISION_ID
       AND F.SCM_SITE_ID = S.SCM_SITE_ID
       AND S.SITE_TYPE = 'SALES'
 LEFT JOIN SCM_MST_COUNTRY CT
        ON S.COUNTRY = CT.COUNTRY
 LEFT JOIN SCM_MST_CITY CY
        ON S.CITY = CY.CITY
 LEFT JOIN SCM_MST_SSO_USER_INFO U1
        ON U1.USER_ID = SUBSTR(F.OWNER, 1, CASE WHEN INSTR(F.OWNER, ',') > 0 THEN INSTR(F.OWNER, ',') - 1 ELSE LENGTH(F.OWNER) END)
 LEFT JOIN SCM_MST_SSO_DEPT_INFO D1
        ON D1.DEPT_ID = F.DEPT_ID
     WHERE F.DIVISION_ID = P_DIVISION_ID;
    /* #TempSiteItem 만들기 종료 */

    SELECT COUNT(*) INTO V_ROWCOUNT FROM GT_DMF0082_SITE_ITEM;
    IF V_ROWCOUNT >= 1000 THEN
        DBMS_STATS.GATHER_TABLE_STATS(USER, 'GT_DMF0082_SITE_ITEM');
    END IF;


    /* #TempFcstNPrice 임시테이블 */

    IF P_VERSION_TYPE = 'CURRENT' THEN

      INSERT INTO GT_DMF0082_FCST_N_PRICE
      (
            DIVISION_ID, PROJECT_CODE, END_CUSTOMER, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS
          , MEASURE, PLANT_SITE_ID, CELL_PROD_SITE_ID, YYYYMMDD, QTY, SOLDTO_CUSTOMER, MEASURE_GROUP
          , CELL_MODEL, NICK_NAME, DMS_SALES, DMS_CUSTOMER, OWNER, DEPT_ID, DEPT_NAME_KO
          , FORECAST_INFO_CELL_PACK_COUNT, ITEM_TYPE, PROJECT_NAME, PROJECT_OWNER, BIZ_TYPE, COUNTRY_NAME
          , CITY_NAME, PROJECT_STATUS, ITEM_NAME, VMI_YN, CUST_GROUP, CUST_GROUP_DTL, APPLICATION, ROUTE
          , MDM_PROJECT_NAME, MIN_CAPACITY, FORECAST_INFO_BIZ_TYPE, CELL_TYPE, FORECAST_INFO_ALL
          , FORECAST_INFO_SPEC, FORECAST_INFOR_VERSION, CELL_MODEL_NICK_NAME, CELL_PER_CAR, CELL_PER_MODULE
          , MODULE_PER_CAR, SORT_ORDER_NO, ENERGE, CELL_QUANTITY, AS_FROM_SITE, CREATE_DATE, LAST_UPDATED_BY
          , SENDER_CODE, SENDER_NAME, PROJECT_S_OP_REPORT, NOTATION, CURRENCY, VERSION_NO, CUTOFF_YYYYMMDD
      )
      SELECT
            A.DIVISION_ID, A.PROJECT_CODE, A.END_CUSTOMER, A.SCM_SITE_ID, A.ITEM_ID, A.DOM_EXP, A.FCST_TYPE, A.INCOTERMS
          , CASE WHEN A.MEASURE IN ('MKT_FCST_RP_CAR', 'MKT_FCST_RP_CELL') THEN 'MKT_FCST_PP' ELSE A.MEASURE END
          , A.PLANT_SITE_ID, A.CELL_PROD_SITE_ID, A.YYYYMMDD, A.QTY, S.SOLDTO_CUSTOMER, M.MEASURE_GROUP
          , S.CELL_MODEL, S.NICK_NAME, S.DMS_SALES, S.DMS_CUSTOMER, S.OWNER, S.DEPT_ID, S.DEPT_NAME_KO
          , S.FORECAST_INFO_CELL_PACK_COUNT, S.ITEM_TYPE, S.PROJECT_NAME, S.PROJECT_OWNER, S.BIZ_TYPE
          , S.COUNTRY_NAME, S.CITY_NAME, S.PROJECT_STATUS, S.ITEM_NAME, S.VMI_YN, S.CUST_GROUP, S.CUST_GROUP_DTL
          , S.APPLICATION, S.ROUTE, S.MDM_PROJECT_NAME, S.MIN_CAPACITY, S.FORECAST_INFO_BIZ_TYPE, S.CELL_TYPE
          , S.FORECAST_INFO_ALL, S.FORECAST_INFO_SPEC, S.FORECAST_INFOR_VERSION, S.CELL_MODEL_NICK_NAME
          , S.CELL_PER_CAR, S.CELL_PER_MODULE, S.MODULE_PER_CAR, M.SORT_ORDER_NO, S.ENERGE, S.CELL_QUANTITY
          , A.ATTRIBUTE10, TO_CHAR(A.LAST_UPDATE_DATE, 'YYYYMMDD'), A.LAST_UPDATED_BY, '', '', S.PROJECT_S_OP_REPORT
          , CASE WHEN A.MEASURE IN ('KRW', 'USD', 'LOC', 'MKT_AMT_LOC', 'MKT_AMT_KRW') THEN 'POINT3' ELSE 'INTEGER' END
          , '', P_VERSION_TYPE, NULL
        FROM DM_PLN_CFM_MKT_DEMAND_PLAN A
        JOIN GT_DMF0082_SELECT_MEASURE M
          ON A.MEASURE = M.PLAN_MEASURE
        JOIN GT_DMF0082_SITE_ITEM S
          ON A.DIVISION_ID = S.DIVISION_ID
         AND A.PROJECT_CODE = S.PROJECT_CODE
         AND A.SCM_SITE_ID = S.SCM_SITE_ID
         AND A.ITEM_ID = S.ITEM_ID
       WHERE A.DIVISION_ID = P_DIVISION_ID
         AND A.YYYYMMDD BETWEEN P_FROM_YYYYMMDD AND P_TO_YYYYMMDD
         AND ((A.MEASURE <> 'SCM_FCST' AND A.QTY <> 0) OR A.MEASURE = 'SCM_FCST');

    ELSE


      INSERT INTO GT_DMF0082_FCST_N_PRICE
      (
            DIVISION_ID, PROJECT_CODE, END_CUSTOMER, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS
          , MEASURE, PLANT_SITE_ID, CELL_PROD_SITE_ID, YYYYMMDD, QTY, SOLDTO_CUSTOMER, MEASURE_GROUP
          , CELL_MODEL, NICK_NAME, DMS_SALES, DMS_CUSTOMER, OWNER, DEPT_ID, DEPT_NAME_KO
          , FORECAST_INFO_CELL_PACK_COUNT, ITEM_TYPE, PROJECT_NAME, PROJECT_OWNER, BIZ_TYPE, COUNTRY_NAME
          , CITY_NAME, PROJECT_STATUS, ITEM_NAME, VMI_YN, CUST_GROUP, CUST_GROUP_DTL, APPLICATION, ROUTE
          , MDM_PROJECT_NAME, MIN_CAPACITY, FORECAST_INFO_BIZ_TYPE, CELL_TYPE, FORECAST_INFO_ALL
          , FORECAST_INFO_SPEC, FORECAST_INFOR_VERSION, CELL_MODEL_NICK_NAME, CELL_PER_CAR, CELL_PER_MODULE
          , MODULE_PER_CAR, SORT_ORDER_NO, ENERGE, CELL_QUANTITY, AS_FROM_SITE, CREATE_DATE, LAST_UPDATED_BY
          , SENDER_CODE, SENDER_NAME, PROJECT_S_OP_REPORT, NOTATION, CURRENCY, VERSION_NO, CUTOFF_YYYYMMDD
      )
      SELECT
            A.DIVISION_ID, A.PROJECT_CODE, A.END_CUSTOMER, A.SCM_SITE_ID, A.ITEM_ID, A.DOM_EXP, A.FCST_TYPE, A.INCOTERMS
          , CASE WHEN A.MEASURE IN ('MKT_FCST_RP_CAR', 'MKT_FCST_RP_CELL') THEN 'MKT_FCST_PP' ELSE A.MEASURE END
          , A.PLANT_SITE_ID, A.CELL_PROD_SITE_ID, A.YYYYMMDD, A.QTY, S.SOLDTO_CUSTOMER, M.MEASURE_GROUP
          , S.CELL_MODEL, S.NICK_NAME, S.DMS_SALES, S.DMS_CUSTOMER, S.OWNER, S.DEPT_ID, S.DEPT_NAME_KO
          , S.FORECAST_INFO_CELL_PACK_COUNT, S.ITEM_TYPE, S.PROJECT_NAME, S.PROJECT_OWNER, S.BIZ_TYPE
          , S.COUNTRY_NAME, S.CITY_NAME, S.PROJECT_STATUS, S.ITEM_NAME, S.VMI_YN, S.CUST_GROUP, S.CUST_GROUP_DTL
          , S.APPLICATION, S.ROUTE, S.MDM_PROJECT_NAME, S.MIN_CAPACITY, S.FORECAST_INFO_BIZ_TYPE, S.CELL_TYPE
