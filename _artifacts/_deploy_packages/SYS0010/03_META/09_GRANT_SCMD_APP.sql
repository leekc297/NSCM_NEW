-- SYS0010 SCMD_APP 권한 (BE 사용계정)
-- ⚠ 신규 화면 작성 시 반드시 SCM_MGR (DDL owner) 에서 실행
-- ⚠ 누락 시 BE 호출 -9994 'Sql Error' (PLS-00201 권한없음)

-- 1) SP EXECUTE GRANT + PUBLIC SYNONYM
GRANT EXECUTE ON SCM_MGR.P_SYS0010_GET_LOOKUP_MASTER TO SCMD_APP;
CREATE OR REPLACE SYNONYM SCMD_APP.P_SYS0010_GET_LOOKUP_MASTER FOR SCM_MGR.P_SYS0010_GET_LOOKUP_MASTER;
GRANT EXECUTE ON SCM_MGR.P_SYS0010_GET_LOOKUP_MASTER_DETAIL TO SCMD_APP;
CREATE OR REPLACE SYNONYM SCMD_APP.P_SYS0010_GET_LOOKUP_MASTER_DETAIL FOR SCM_MGR.P_SYS0010_GET_LOOKUP_MASTER_DETAIL;
GRANT EXECUTE ON SCM_MGR.P_SYS0010_SAVE_LOOKUP_MASTER TO SCMD_APP;
CREATE OR REPLACE SYNONYM SCMD_APP.P_SYS0010_SAVE_LOOKUP_MASTER FOR SCM_MGR.P_SYS0010_SAVE_LOOKUP_MASTER;
GRANT EXECUTE ON SCM_MGR.P_SYS0010_SAVE_LOOKUP_MASTER_DETAIL TO SCMD_APP;
CREATE OR REPLACE SYNONYM SCMD_APP.P_SYS0010_SAVE_LOOKUP_MASTER_DETAIL FOR SCM_MGR.P_SYS0010_SAVE_LOOKUP_MASTER_DETAIL;

-- 3) 검증
SELECT GRANTEE, PRIVILEGE, TABLE_NAME FROM DBA_TAB_PRIVS
 WHERE GRANTEE='SCMD_APP' AND OWNER='SCM_MGR' AND TABLE_NAME LIKE '%SYS0010%'
 ORDER BY TABLE_NAME, PRIVILEGE;
