-- 목적: 한글 메뉴명 변경 결과 검증
-- 기대: MNU_DMF0043_01/KO MSG_NM = '해외법인 기여매출'
-- 작성: 2026-06-01

-- BLOCK 1 : KO 한글명 일치 검증
SELECT
  CASE WHEN MSG_NM = '해외법인 기여매출' THEN 'PASS' ELSE 'FAIL' END AS RESULT,
  MSG_ID,
  LANG_CD,
  MSG_NM
  FROM SCM_MGR.SCM_ADM_MSG_M
 WHERE MSG_ID = 'MNU_DMF0043_01' AND LANG_CD = 'KO';

-- BLOCK 2 : 3 lang row 모두 존재 검증 (KO + EN + CN)
SELECT
  CASE WHEN COUNT(*) = 3 THEN 'PASS' ELSE 'FAIL: ' || COUNT(*) || ' rows' END AS RESULT,
  COUNT(*) AS LANG_CNT
  FROM SCM_MGR.SCM_ADM_MSG_M
 WHERE MSG_ID = 'MNU_DMF0043_01';

-- BLOCK 3 : 메뉴 트리 (실제 로그인 사용자 view) 시뮬레이션
SELECT M.MNU_ID, M.MNU_URL, M.UPPR_MNU_ID, MSG.MSG_NM AS DISPLAY_NAME
  FROM SCM_MGR.SCM_ADM_MNU_M M
  LEFT JOIN SCM_MGR.SCM_ADM_MSG_M MSG
    ON MSG.MSG_ID = M.MNU_MSG_ID AND MSG.LANG_CD = 'KO'
 WHERE M.MNU_ID = 'DMF0043_01';
