-- 원인 추적:
--   1) GT_DMF0043_TITLE 에 COLUMN_NAME='EDIT_FLAG' 2 rows 적재
--   2) SCM_MST_SHEET_COLUMNS PROGRAM='DMF0043'/SHEET='ContributeMain' 가 8개 컬럼 각 2건씩 중복
--   3) PK_SCM_MST_SHEET_COLUMNS = UNIQUE(PROGRAM_ID, SHEET_NAME, COLUMN_NAME) 상태=UNUSABLE
--   4) 전 테이블 dup 키 15,277건 (CSV bulk load 후 multi-DIVISION_ID 데이터가 unique key 형식 위배)
--
-- 결정:
--   A) 본 인덱스는 진정한 자연키가 (PROGRAM_ID, SHEET_NAME, COLUMN_NAME, DIVISION_ID) 인데
--      UNIQUE 3-컬럼 정의가 잘못됨 (설계 결함). 우선 NON-UNIQUE 로 재생성하여 쿼리 성능 보존.
--   B) DMF0043/ContributeMain 의 8개 컬럼 중복만 dedupe (다른 화면 영향 0).
--      (다른 화면 dup 정리는 별건 작업으로 분리)
--
-- 작성: 2026-06-01 / minyonglee1
