SET DEFINE OFF
SET SERVEROUTPUT ON
SET FEEDBACK ON
WHENEVER SQLERROR EXIT FAILURE

PROMPT === BLOCK 1 : 사고 정황 확인 ===
SELECT 'IDX_STATUS' AS KEY, STATUS VAL FROM USER_INDEXES WHERE INDEX_NAME='PK_SCM_MST_SHEET_COLUMNS'
UNION ALL
SELECT 'DMF0043_BEFORE', TO_CHAR(COUNT(*)) FROM SCM_MGR.SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID='DMF0043' AND SHEET_NAME='ContributeMain';

PROMPT === BLOCK 2 : DROP unique index → CREATE non-unique (same columns) ===
DROP INDEX SCM_MGR.PK_SCM_MST_SHEET_COLUMNS;
CREATE INDEX SCM_MGR.PK_SCM_MST_SHEET_COLUMNS
  ON SCM_MGR.SCM_MST_SHEET_COLUMNS (PROGRAM_ID, SHEET_NAME, COLUMN_NAME);

PROMPT === BLOCK 3 : DMF0043/ContributeMain 8 중복 컬럼 dedupe (keep MIN ROWID) ===
DELETE FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
WHERE PROGRAM_ID='DMF0043' AND SHEET_NAME='ContributeMain'
  AND ROWID IN (
    SELECT R FROM (
      SELECT ROWID R,
             ROW_NUMBER() OVER (PARTITION BY COLUMN_NAME, DIVISION_ID ORDER BY ROWID) rn
        FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
       WHERE PROGRAM_ID='DMF0043' AND SHEET_NAME='ContributeMain'
    ) WHERE rn > 1
  );
COMMIT;

PROMPT === BLOCK 4 : Verify dedupe ===
SELECT 'DMF0043_AFTER' AS KEY, COUNT(*) AS CNT
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID='DMF0043' AND SHEET_NAME='ContributeMain';

SELECT COLUMN_NAME, DIVISION_ID, COUNT(*) DUP_CNT
FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
WHERE PROGRAM_ID='DMF0043' AND SHEET_NAME='ContributeMain'
GROUP BY COLUMN_NAME, DIVISION_ID
HAVING COUNT(*) > 1;

PROMPT === BLOCK 5 : Caller execute verify ===
