PROMPT === [1] MSG_M lookup 5건 ===
SELECT MSG_ID FROM SCM_MGR.SCM_ADM_MSG_M WHERE MSG_ID LIKE 'MSG_API_DMF0072_%' AND LANG_CD='KO' ORDER BY MSG_ID;

PROMPT === [2] API_M lookup 5건 + URL 정합 ===
SELECT API_ID, API_TP_CD, API_URL FROM SCM_MGR.SCM_ADM_API_M
 WHERE API_ID IN ('P_DMF0072_DATATYPE_GET','P_DMF0072_DIVISION_GET','P_DMF0072_TEAM_GET','P_DMF0072_ENDCUST_GET','P_DMF0072_SALESSITE_GET')
 ORDER BY API_ID;

PROMPT === [3] BTN_MPG lookup 5건 (DMF0072 5 SHT_NM 모두 SEARCH) ===
SELECT SHT_NM, MNU_BTN_CD, API_ID FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M
 WHERE MNU_ID='DMF0072' AND SHT_NM IN ('dataType','division','team','endCustomer','salesSite')
 ORDER BY SHT_NM;

PROMPT === [4] PROC_M lookup 9 row (4 SP) ===
SELECT PROC_NM, COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD
  FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM IN ('DMF0072_GET_DATA_TYPE_LIST','DMF0072_GET_TEAM_LIST','DMF0072_GET_END_CUSTOMER_LIST','DMF0072_GET_SALES_SITE_LIST')
 ORDER BY PROC_NM, SORT_ORD;

PROMPT === [5] GUEST 권한 lookup 5건 ===
SELECT SHT_NM, MNU_BTN_CD FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M
 WHERE USER_GR_ID='GUEST' AND MNU_ID='DMF0072' AND SHT_NM IN ('dataType','division','team','endCustomer','salesSite')
 ORDER BY SHT_NM;

PROMPT === [6] 사후 통합 카운트 (5/5/5/9/5 기대) ===
SELECT 'MSG_M'      AS K, COUNT(*) AS V FROM SCM_MGR.SCM_ADM_MSG_M WHERE MSG_ID LIKE 'MSG_API_DMF0072_%' AND LANG_CD='KO' AND MSG_ID NOT IN ('MSG_API_DMF0072_GET','MSG_API_DMF0072_SAVE')
UNION ALL SELECT 'API_M',  COUNT(*) FROM SCM_MGR.SCM_ADM_API_M WHERE API_ID IN ('P_DMF0072_DATATYPE_GET','P_DMF0072_DIVISION_GET','P_DMF0072_TEAM_GET','P_DMF0072_ENDCUST_GET','P_DMF0072_SALESSITE_GET')
UNION ALL SELECT 'BTN_MPG',COUNT(*) FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID='DMF0072' AND SHT_NM IN ('dataType','division','team','endCustomer','salesSite')
UNION ALL SELECT 'PROC_M', COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M WHERE PROC_NM IN ('DMF0072_GET_DATA_TYPE_LIST','DMF0072_GET_TEAM_LIST','DMF0072_GET_END_CUSTOMER_LIST','DMF0072_GET_SALES_SITE_LIST')
UNION ALL SELECT 'GUEST',  COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE USER_GR_ID='GUEST' AND MNU_ID='DMF0072' AND SHT_NM IN ('dataType','division','team','endCustomer','salesSite');
