PROMPT === [D1] FE sheetName ↔ BTN_MPG SHT_NM 매핑 정합 (camelCase) ===
SELECT 'EXPECTED' AS K, 'dataType / division / team / endCustomer / salesSite' AS V FROM DUAL
UNION ALL
SELECT 'ACTUAL', LISTAGG(SHT_NM, ' / ') WITHIN GROUP (ORDER BY SHT_NM)
  FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M
 WHERE MNU_ID='DMF0072' AND SHT_NM IN ('dataType','division','team','endCustomer','salesSite');

PROMPT === [D2] PROC body INVALID 검출 ===
SELECT OBJECT_NAME, STATUS FROM SCM_MGR.USER_OBJECTS
 WHERE OBJECT_TYPE='PROCEDURE'
   AND OBJECT_NAME IN ('DMF0072_GET_DATA_TYPE_LIST','DMF0072_GET_TEAM_LIST','DMF0072_GET_END_CUSTOMER_LIST','DMF0072_GET_SALES_SITE_LIST');

PROMPT === [D3] PROC_M COL_NM 정합 (BE 자동 채움 키 - camelCase) ===
SELECT PROC_NM, LISTAGG(COL_NM, ',') WITHIN GROUP (ORDER BY SORT_ORD) AS COLS
  FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM IN ('DMF0072_GET_DATA_TYPE_LIST','DMF0072_GET_TEAM_LIST','DMF0072_GET_END_CUSTOMER_LIST','DMF0072_GET_SALES_SITE_LIST')
 GROUP BY PROC_NM ORDER BY PROC_NM;
-- 기대: TEAM_LIST=divisionId,o_rc1 / END_CUSTOMER_LIST=divisionId,deptId,o_rc1 / SALES_SITE_LIST=divisionId,endCustomer,o_rc1 / DATA_TYPE_LIST=o_rc1

PROMPT === [D4] USER_GR 권한 — minyonglee1 의 모든 그룹 ===
SELECT G.USER_ID, G.USER_GR_ID, U.USE_YN
  FROM SCM_MGR.SCM_ADM_USER_GR_MPG_M G, SCM_MGR.SCM_ADM_USER_GR_MNU_MPG_M U
 WHERE G.USER_ID='minyonglee1' AND U.USER_GR_ID=G.USER_GR_ID AND U.MNU_ID='DMF0072';

PROMPT === [D5] BTN 권한 미할당 (minyonglee1 그룹 기준) ===
SELECT BTN.SHT_NM, BTN.MNU_BTN_CD
  FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M BTN
 WHERE BTN.MNU_ID='DMF0072' AND BTN.USE_YN='Y'
   AND NOT EXISTS (
     SELECT 1 FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M X, SCM_MGR.SCM_ADM_USER_GR_MPG_M G
      WHERE X.USER_GR_ID=G.USER_GR_ID AND G.USER_ID='minyonglee1'
        AND X.MNU_ID=BTN.MNU_ID AND X.SHT_NM=BTN.SHT_NM AND X.MNU_BTN_CD=BTN.MNU_BTN_CD
   );
-- 기대: 0 row (모든 BTN 이 사용자 그룹에 매핑되어야 함)
