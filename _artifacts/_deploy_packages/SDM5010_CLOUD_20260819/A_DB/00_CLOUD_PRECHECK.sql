-- 이관 범위 기준(사용자 확정 2026-08-19): 무수정 객체(TABLE DDL)는 동봉하지 않음 — 클라우드
--   기생성 전제. 본 파일이 그 실존을 확인한다. 부재 시 즉시 중단·회신(임의 생성 금지).
--   PKG_SDM5010 은 신규 배포물 — SPEC+BODY 모두 01 로 동봉(기존재 여부 무관 CREATE OR REPLACE).
-- 선행 의존: SDM1010_CLOUD_20260813 + SDM1020_CLOUD_20260819 패키지 기적용 (README §의존성)
-- =====================================================================================

-- [P0] 환경 식별 (QA/DEV 어느 쪽인지 기록 — 실행 결과를 적용 로그에 남길 것)
SELECT USER APPLIED_AS, SYS_CONTEXT('USERENV','SERVICE_NAME') SERVICE_NAME,
       SYS_CONTEXT('USERENV','SERVER_HOST') SERVER_HOST FROM DUAL;

-- [P1] 원장 테이블 실존 + 컬럼수 (무수정 객체 — 사내 실측 2026-08-19: MST 37 / USER_MAP 22)
--      기대: 2행 — SPMS_PROJECT_MST=37 / SPMS_PROJECT_USER_MAP=22 (불일치 = 세대 상이 -> 회신)
SELECT TABLE_NAME, COUNT(*) COLS FROM ALL_TAB_COLUMNS
 WHERE OWNER='SCM_MGR' AND TABLE_NAME IN ('SPMS_PROJECT_MST','SPMS_PROJECT_USER_MAP')
 GROUP BY TABLE_NAME ORDER BY 1;

-- [P2] 상위 메뉴 + 권한그룹 실존 (SDM1010 기동봉분 — 본 패키지는 SDM_Admin/SDM5010 만 신설)
--      기대: MNU 'SDM' 1행 USE_YN='Y' / 그룹 'SPMS Administrator' 1행
SELECT MNU_ID, UPPR_MNU_ID, USE_YN FROM SCM_MGR.SCM_ADM_MNU_M WHERE MNU_ID='SDM';
SELECT USER_GR_ID FROM SCM_MGR.SCM_ADM_USER_GR_M WHERE USER_GR_ID='SPMS Administrator';

-- [P3] 공유 SP PKG_SDM1010.P_SDM1010_GET_PERIOD 실존(VALID) + PROC_M 기등재 9행
--      (period 시트 = 공유 배선 SDM5010_period_SEARCH — SDM1010 패키지 기동봉 전제)
--      기대: PACKAGE/PACKAGE BODY 2행 VALID / PROC_M 9행
SELECT OBJECT_TYPE, STATUS FROM ALL_OBJECTS
 WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_SDM1010' ORDER BY 1;
SELECT COUNT(*) PROC_PERIOD_EXPECT_9 FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM='PKG_SDM1010.P_SDM1010_GET_PERIOD';

-- [P4] 기존 공용 콤보 기존재 (본 패키지 미동봉 — 부재 시 회신. 공유 콤보 임의 수정/신설 금지)
--      기대: 부재 0행 (DpjtDevelopStatus 는 본 패키지 04 신설분이라 미포함)
SELECT COLUMN_VALUE MISSING_COMBO FROM TABLE(SYS.ODCIVARCHAR2LIST(
  'Division','DpjtClass','EndCustomerByDivisionDept','CellTypeByDivision',
  'StackMethodByCellType','BizTypeByDivision','PlantByDivisionCompany'))
MINUS
SELECT SQL_ID FROM SCM_MGR.SCM_ADM_CMBO_SQL_M WHERE USE_YN='Y';

-- [P5] LOOKUP 선행 상태 (SDM1010/1020 기적용 전제 — SPMS_DPJT_REG_STATUS 확정 10코드)
--      기대: ① 부재 0행 ② SPMS_DPJT_DEVELOP_STATUS 는 0행(본 패키지 03 신설) 또는 3행(재이관) — 기록만
SELECT COLUMN_VALUE MISSING_REG_STATUS FROM TABLE(SYS.ODCIVARCHAR2LIST(
  'DRAFT','WRITING','WAITING','COMPLETE','REJECT','CHG_REG','MODIFYING','REQ_MOD','CHG_COMPLETE','CHG_REJECT'))
MINUS
SELECT SEGMENT1 FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE='SPMS_DPJT_REG_STATUS' AND VALID_YN='Y';
SELECT COUNT(*) DEVELOP_STATUS_PRE FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE='SPMS_DPJT_DEVELOP_STATUS';

-- [P6] 신규 MSG/LBL 채번 충돌 가드 (MSG00704->MSG01001 재채번 사고 계보)
--      기대: 0행. 행이 나오면 그 코드가 클라우드에서 선점된 것 —
--            문구가 06 파일과 동일하면 무해(멱등 skip), 다르면 ⛔ 중단 -> 재채번 회신.
SELECT MSG_ID, LANG_CD, MSG_NM FROM SCM_MGR.SCM_ADM_MSG_M
 WHERE MSG_ID IN ('MSG01008','MSG01009','MSG01010','MSG01011','MSG01012','MSG01013',
                  'LBL00863','MNU_SDM_Admin','MNU_SDM5010')
    OR MSG_ID LIKE 'MSG_API_SDM5010%';

-- [P7] 재사용 MSG/LBL 기존재 확인 (이관 제외분 — 부재 코드 발견 시 회신, 임의 INSERT 금지)
--      기대: 부재 0행 (15코드 x 3언어 = 45행 전부 기존재)
SELECT M.MI || '/' || L.LC MISSING_REUSE_CODE
  FROM (SELECT COLUMN_VALUE MI FROM TABLE(SYS.ODCIVARCHAR2LIST(
          'LBL00001','LBL00643','LBL00046','LBL00607','LBL00857','LBL00623','LBL00624',
          'MSG00097','MSG00108','MSG00164','MSG00716','MSG00717','MSG01007','MSG00002','MSG00003'))) M
 CROSS JOIN (SELECT 'KO' LC FROM DUAL UNION ALL SELECT 'EN' FROM DUAL UNION ALL SELECT 'CN' FROM DUAL) L
 WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_MSG_M X WHERE X.MSG_ID = M.MI AND X.LANG_CD = L.LC);

-- [P8] 재이관 여부 확인 (기존 SDM5010 흔적 — 있으면 05 가 대상 한정 DELETE 후 재적재하므로 무해, 기록만)
SELECT 'MNU' AXIS, COUNT(*) CNT FROM SCM_MGR.SCM_ADM_MNU_M WHERE MNU_ID IN ('SDM_Admin','SDM5010')
UNION ALL SELECT 'SHEET', COUNT(*) FROM SCM_MGR.SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID='SDM5010'
UNION ALL SELECT 'PROC', COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M WHERE PROC_NM LIKE 'PKG_SDM5010.%'
UNION ALL SELECT 'API', COUNT(*) FROM SCM_MGR.SCM_ADM_API_M WHERE API_ID LIKE 'SDM5010%'
UNION ALL SELECT 'PKG', COUNT(*) FROM ALL_OBJECTS WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_SDM5010';
