-- [V1] PKG 상태 — 기대: PACKAGE=VALID / PACKAGE BODY=VALID (2행 모두 VALID — spec 조용한 실패 계보)
SELECT OBJECT_TYPE, STATUS FROM ALL_OBJECTS
 WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_SDM5010' ORDER BY OBJECT_TYPE;

-- [V2] 정정 마커 실측 — 기대: BODY 합계 14 / SPEC 1 (사내 실측 2026-08-19)
--      BODY 내역: D1=2 / D3=1 / D4=1 / D5=1 / D6=4 / D10=1 / D11=1 / DISABLED=2 / REGSTS=1
SELECT TYPE, COUNT(*) MARKER_LINES FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_SDM5010' AND TEXT LIKE '%[E20260819-SDM5010-%'
 GROUP BY TYPE ORDER BY TYPE;   -- 기대: PACKAGE=1 / PACKAGE BODY=14
SELECT M.TAG, NVL(S.CNT,0) CNT, M.EXPECT
  FROM (SELECT 'D1' TAG, 2 EXPECT FROM DUAL UNION ALL SELECT 'D3',1 FROM DUAL
        UNION ALL SELECT 'D4',1 FROM DUAL UNION ALL SELECT 'D5',1 FROM DUAL
        UNION ALL SELECT 'D6',4 FROM DUAL UNION ALL SELECT 'D10',1 FROM DUAL
        UNION ALL SELECT 'D11',1 FROM DUAL UNION ALL SELECT 'DISABLED',2 FROM DUAL
        UNION ALL SELECT 'REGSTS',1 FROM DUAL) M
  LEFT JOIN (SELECT REGEXP_SUBSTR(TEXT, '\[E20260819-SDM5010-([A-Z0-9]+)\]', 1, 1, NULL, 1) TAG, COUNT(*) CNT
               FROM ALL_SOURCE
              WHERE OWNER='SCM_MGR' AND NAME='PKG_SDM5010' AND TYPE='PACKAGE BODY'
                AND TEXT LIKE '%[E20260819-SDM5010-%' GROUP BY REGEXP_SUBSTR(TEXT, '\[E20260819-SDM5010-([A-Z0-9]+)\]', 1, 1, NULL, 1)) S
    ON S.TAG = M.TAG ORDER BY 1;

-- [V3] GRANT + 시노님 — 기대: EXECUTE grantee 에 앱계정(SCMP_APP 또는 환경별 SCMD_APP) / 시노님 1행
--      (사내 실측: SCMP_APP EXECUTE 1행 + ALL_SYNONYMS SCMP_APP.PKG_SDM5010 1행 — DBA 실행분)
SELECT GRANTEE, PRIVILEGE FROM DBA_TAB_PRIVS WHERE OWNER='SCM_MGR' AND TABLE_NAME='PKG_SDM5010';
SELECT OWNER, SYNONYM_NAME, TABLE_OWNER FROM ALL_SYNONYMS WHERE TABLE_NAME='PKG_SDM5010';

-- [V4] 메타 축별 카운트 — 기대(사내 실측): MNU 2 / SHEET TAB1 24 + TAB2 24 / PROC 44 / API 12 /
--      MSG_API 36 / BTN 12 / UGR_MNU 3 / UGR_BTN 12 / LOOKUP 1+3 / CMBO 1
SELECT 'MNU_M' AXIS, COUNT(*) CNT, 2 EXPECT FROM SCM_MGR.SCM_ADM_MNU_M WHERE MNU_ID IN ('SDM_Admin','SDM5010')
UNION ALL SELECT 'SHEET_TAB1', COUNT(*), 24 FROM SCM_MGR.SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID='SDM5010' AND SHEET_NAME='TAB1'
UNION ALL SELECT 'SHEET_TAB2', COUNT(*), 24 FROM SCM_MGR.SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID='SDM5010' AND SHEET_NAME='TAB2'
UNION ALL SELECT 'PROC_M', COUNT(*), 44 FROM SCM_MGR.SCM_ADM_PROC_M WHERE PROC_NM LIKE 'PKG_SDM5010.%'
UNION ALL SELECT 'API_M', COUNT(*), 12 FROM SCM_MGR.SCM_ADM_API_M WHERE API_ID LIKE 'SDM5010%'
UNION ALL SELECT 'MSG_API', COUNT(*), 36 FROM SCM_MGR.SCM_ADM_MSG_M WHERE MSG_ID LIKE 'MSG_API_SDM5010%'
UNION ALL SELECT 'MNU_BTN', COUNT(*), 12 FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID='SDM5010'
UNION ALL SELECT 'UGR_MNU', COUNT(*), 3 FROM SCM_MGR.SCM_ADM_USER_GR_MNU_MPG_M WHERE MNU_ID IN ('SDM','SDM_Admin','SDM5010') AND USER_GR_ID='SPMS Administrator'
UNION ALL SELECT 'UGR_BTN', COUNT(*), 12 FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE MNU_ID='SDM5010'
UNION ALL SELECT 'LOOKUP_M', COUNT(*), 1 FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER WHERE LOOKUP_TYPE='SPMS_DPJT_DEVELOP_STATUS'
UNION ALL SELECT 'LOOKUP_D', COUNT(*), 3 FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE='SPMS_DPJT_DEVELOP_STATUS'
UNION ALL SELECT 'CMBO', COUNT(*), 1 FROM SCM_MGR.SCM_ADM_CMBO_SQL_M WHERE SQL_ID='DpjtDevelopStatus';

-- [V5] PROC_M = ALL_ARGUMENTS positional 대조 — 기대: 5 SP 모두 PROC=ARGS (6/6/16/10/6 — 합 44)
SELECT P.PROC_NM, P.CNT PROC_M_CNT, A.CNT ALL_ARGS_CNT
  FROM (SELECT PROC_NM, COUNT(*) CNT FROM SCM_MGR.SCM_ADM_PROC_M
         WHERE PROC_NM LIKE 'PKG_SDM5010.%' GROUP BY PROC_NM) P
  LEFT JOIN (SELECT 'PKG_SDM5010.'||OBJECT_NAME PROC_NM, COUNT(*) CNT FROM ALL_ARGUMENTS
              WHERE OWNER='SCM_MGR' AND PACKAGE_NAME='PKG_SDM5010' GROUP BY OBJECT_NAME) A
    ON A.PROC_NM = P.PROC_NM
 ORDER BY 1;

-- [V6] MSG/LBL 신규분 — 기대: MNU 2코드=6 / MSG01008~13=18 / LBL00863=3 (합 27, 전부 3언어)
SELECT 'MNU_MSG' GRP, COUNT(*) CNT, 6 EXPECT FROM SCM_MGR.SCM_ADM_MSG_M WHERE MSG_ID IN ('MNU_SDM_Admin','MNU_SDM5010')
UNION ALL SELECT 'MSG01008~13', COUNT(*), 18 FROM SCM_MGR.SCM_ADM_MSG_M WHERE MSG_ID IN ('MSG01008','MSG01009','MSG01010','MSG01011','MSG01012','MSG01013')
UNION ALL SELECT 'LBL00863', COUNT(*), 3 FROM SCM_MGR.SCM_ADM_MSG_M WHERE MSG_ID='LBL00863';

-- [V7] CMBO 원문 길이 — 기대: 174 (사내 SQL_DTL_CTN 실측 — 원문 변형 감지)
SELECT SQL_ID, LENGTH(SQL_DTL_CTN) LEN_EXPECT_174, MDU_DIVS_CD, USE_YN
  FROM SCM_MGR.SCM_ADM_CMBO_SQL_M WHERE SQL_ID='DpjtDevelopStatus';

-- [V8] LOOKUP 시드 값 — 기대: DEV(개발,1)/PROD(양산,2)/DROP(Drop,3) VALID 'Y' (임시 시드 — 사용자 확정 대기)
SELECT SEGMENT1, SEGMENT2, DISPLAY_SEQ, VALID_YN FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE='SPMS_DPJT_DEVELOP_STATUS' ORDER BY DISPLAY_SEQ;

-- [V9] ROUTE_PATH — 99 실행 전 기대: SDM5010=NULL / 99(FE 배포 후) 실행 후 기대: 'sdm/project-master'
--      (SDM_Admin 은 MENU 노드 — 항상 NULL)
SELECT MNU_ID, ROUTE_PATH FROM SCM_MGR.SCM_ADM_MNU_M WHERE MNU_ID IN ('SDM_Admin','SDM5010') ORDER BY 1;
