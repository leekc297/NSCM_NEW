-- 00_PRECHECK — 조회 전용. [E20261014-DMF0005NOPUSH] 적용 전 상태 판정 (전체 F5, 값 입력 없음)
-- * [L0] 접속 DB · PKG_DMF0005 상태 · LAST_DDL · BODY 줄 수 / 글자 수 (QA 10-14 C01 실측 = 10:17:32, 1,992줄 · 103,725자)
-- * [L1] 패치 앵커 = 조회 프로시저 최종 SELECT 의 `, NVL(SC.CNT, 0) AS SC_CNT` 줄과 바로 앞 두 줄(`SELECT` / `B.*`) — 정확히 1곳이어야 10 적용 가능
-- * [L2] 마커 — 적용 전 0 (적용 뒤 1)
-- * [L3] 지금 커서에 남은 조회 문장 계획 — 적용 전 PUSHED > 0 · SEC_PER_EX 수백 초가 정상(= 고칠 대상)
-- * [L4] 지금 조회 문장을 실행 중인 세션 · 패키지 안에 있는 세션 (있으면 끝나거나 멈춘 뒤 10 실행 — 교체가 대기할 수 있다)
SET LINESIZE 300 PAGESIZE 200
SELECT 'L0' CHK, SYS_CONTEXT('USERENV','DB_NAME') DB_NAME, SYS_CONTEXT('USERENV','INSTANCE_NAME') INST, TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI:SS') NOW FROM DUAL;
SELECT 'L0' CHK, O.OBJECT_TYPE, O.STATUS, TO_CHAR(O.LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL,
       (SELECT COUNT(*) || '줄 / ' || SUM(LENGTH(TEXT)) || '자' FROM USER_SOURCE S WHERE S.NAME = O.OBJECT_NAME AND S.TYPE = O.OBJECT_TYPE) BODY_FP
  FROM USER_OBJECTS O WHERE O.OBJECT_NAME = 'PKG_DMF0005' ORDER BY O.OBJECT_TYPE;
SELECT 'L1 앵커' CHK, COUNT(*) N, MIN(S.LINE) LINE,
       CASE WHEN COUNT(*) = 1 THEN 'PASS → 10 적용 가능' WHEN COUNT(*) = 0 THEN '❌ 앵커 없음 — 이미 적용(L2 확인) 또는 원문 상이 → 중단' ELSE '❌ 앵커 2곳↑ — 원문 상이 → 중단' END JUDGE
  FROM USER_SOURCE S
 WHERE S.NAME = 'PKG_DMF0005' AND S.TYPE = 'PACKAGE BODY' AND RTRIM(S.TEXT, CHR(10) || CHR(13)) = '            , NVL(SC.CNT, 0) AS SC_CNT'
   AND EXISTS (SELECT 1 FROM USER_SOURCE P WHERE P.NAME = S.NAME AND P.TYPE = S.TYPE AND P.LINE = S.LINE - 1 AND RTRIM(P.TEXT, CHR(10) || CHR(13)) = '              B.*')
   AND EXISTS (SELECT 1 FROM USER_SOURCE P WHERE P.NAME = S.NAME AND P.TYPE = S.TYPE AND P.LINE = S.LINE - 2 AND RTRIM(P.TEXT, CHR(10) || CHR(13)) = '        SELECT');
SELECT 'L1 앵커 문맥' CHK, LINE, RTRIM(TEXT, CHR(10) || CHR(13)) TXT FROM USER_SOURCE WHERE NAME = 'PKG_DMF0005' AND TYPE = 'PACKAGE BODY'
   AND LINE BETWEEN (SELECT MIN(LINE) - 3 FROM USER_SOURCE WHERE NAME = 'PKG_DMF0005' AND TYPE = 'PACKAGE BODY' AND TEXT LIKE '%NVL(SC.CNT, 0) AS SC_CNT%')
                AND (SELECT MIN(LINE) + 3 FROM USER_SOURCE WHERE NAME = 'PKG_DMF0005' AND TYPE = 'PACKAGE BODY' AND TEXT LIKE '%NVL(SC.CNT, 0) AS SC_CNT%')
 ORDER BY LINE;
SELECT 'L2 마커' CHK, COUNT(*) N, CASE WHEN COUNT(*) = 0 THEN '미적용 (기대)' WHEN COUNT(*) = 1 THEN '적용됨 — 10 재실행은 가드로 무동작' ELSE '⚠ 마커 2곳↑ — 확인 필요' END JUDGE
  FROM USER_SOURCE WHERE NAME = 'PKG_DMF0005' AND TYPE = 'PACKAGE BODY' AND TEXT LIKE '%E20261014-DMF0005NOPUSH%';
SELECT 'L3 조회 계획' CHK, S.INST_ID, S.SQL_ID, S.CHILD_NUMBER CH, S.PLAN_HASH_VALUE PHV, S.EXECUTIONS EX, S.USERS_EXECUTING NOW_RUN,
       ROUND(S.ELAPSED_TIME/1e6/GREATEST(S.EXECUTIONS,1),1) SEC_PER_EX, ROUND(S.ROWS_PROCESSED/GREATEST(S.EXECUTIONS,1)) ROWS_PER_EX,
       (SELECT COUNT(*) FROM GV$SQL_PLAN P WHERE P.INST_ID = S.INST_ID AND P.SQL_ID = S.SQL_ID AND P.CHILD_NUMBER = S.CHILD_NUMBER AND P.OPERATION = 'VIEW' AND P.OPTIONS = 'PUSHED PREDICATE') PUSHED,
       CASE WHEN DBMS_LOB.INSTR(S.SQL_FULLTEXT, 'NO_PUSH_PRED') > 0 THEN 'Y' ELSE 'N' END PATCHED_TXT, S.LAST_LOAD_TIME LOADED
  FROM GV$SQL S WHERE S.SQL_TEXT LIKE 'WITH ITEM_AGG AS%'
 ORDER BY S.LAST_ACTIVE_TIME DESC FETCH FIRST 8 ROWS ONLY;
SELECT 'L4 실행중' CHK, S.INST_ID, S.SID, S.SERIAL#, S.USERNAME, S.MACHINE, S.MODULE, S.LAST_CALL_ET CALL_SEC, S.SQL_ID
  FROM GV$SESSION S
 WHERE S.TYPE = 'USER' AND S.STATUS = 'ACTIVE'
   AND (S.PLSQL_ENTRY_OBJECT_ID IN (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME = 'PKG_DMF0005')
        OR S.SQL_ID IN (SELECT SQL_ID FROM GV$SQL WHERE SQL_TEXT LIKE 'WITH ITEM_AGG AS%'))
 ORDER BY S.LAST_CALL_ET DESC;
