SELECT 'V4' CHK, S.INST_ID, S.SQL_ID, S.CHILD_NUMBER CH, S.PLAN_HASH_VALUE PHV, S.EXECUTIONS EX,
       ROUND(S.ELAPSED_TIME/1e6/GREATEST(S.EXECUTIONS,1),2) SEC_PER_EX, ROUND(S.ROWS_PROCESSED/GREATEST(S.EXECUTIONS,1)) ROWS_PER_EX,
       (SELECT COUNT(*) FROM GV$SQL_PLAN P WHERE P.INST_ID = S.INST_ID AND P.SQL_ID = S.SQL_ID AND P.CHILD_NUMBER = S.CHILD_NUMBER AND P.OPERATION = 'VIEW' AND P.OPTIONS = 'PUSHED PREDICATE') PUSHED,
       CASE WHEN DBMS_LOB.INSTR(S.SQL_FULLTEXT, 'NO_PUSH_PRED') > 0 THEN 'Y' ELSE 'N' END PATCHED_TXT, S.LAST_LOAD_TIME LOADED
  FROM GV$SQL S WHERE S.SQL_TEXT LIKE 'WITH ITEM_AGG AS%'
 ORDER BY S.LAST_ACTIVE_TIME DESC FETCH FIRST 8 ROWS ONLY;
