SELECT 'V1' CHK, O.OBJECT_TYPE, O.STATUS, TO_CHAR(O.LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL,
       (SELECT COUNT(*) FROM USER_ERRORS E WHERE E.NAME = O.OBJECT_NAME AND E.TYPE = O.OBJECT_TYPE) ERRS,
       (SELECT COUNT(*) FROM USER_SOURCE S WHERE S.NAME = O.OBJECT_NAME AND S.TYPE = O.OBJECT_TYPE AND S.TEXT LIKE '%E20261014-DMF0005NOPUSH%') MARKER
  FROM USER_OBJECTS O WHERE O.OBJECT_NAME = 'PKG_DMF0005' ORDER BY O.OBJECT_TYPE;
SELECT 'V2' CHK, LINE, SUBSTR(RTRIM(TEXT, CHR(10) || CHR(13)), 1, 160) TXT FROM USER_SOURCE WHERE NAME = 'PKG_DMF0005' AND TYPE = 'PACKAGE BODY'
   AND LINE BETWEEN (SELECT MIN(LINE) - 2 FROM USER_SOURCE WHERE NAME = 'PKG_DMF0005' AND TYPE = 'PACKAGE BODY' AND TEXT LIKE '%E20261014-DMF0005NOPUSH%')
                AND (SELECT MIN(LINE) + 4 FROM USER_SOURCE WHERE NAME = 'PKG_DMF0005' AND TYPE = 'PACKAGE BODY' AND TEXT LIKE '%E20261014-DMF0005NOPUSH%')
 ORDER BY LINE;
DECLARE
    rc1 SYS_REFCURSOR; rcr SYS_REFCURSOR;
    t0 NUMBER; n NUMBER; c INTEGER;
    TYPE t_v IS TABLE OF VARCHAR2(10);
    v t_v := t_v('82', '81', '40');
BEGIN
    FOR i IN 1 .. v.COUNT LOOP
        t0 := DBMS_UTILITY.GET_TIME;
        PKG_DMF0005.P_DMF0005_GET_SALES_SITE_MODEL_PRODUCTION(
            P_DIVISION_ID => v(i), P_DEPT_ID => 'ALL', P_END_CUSTOMER => 'ALL', P_SCM_SITE_ID => 'ALL',
            P_PROJECT_CODE => NULL, P_ITEM_ID => NULL, P_VALID_YN => 'ALL', P_OWNER => NULL, P_USER_ID => 'minyonglee1',
            O_RC1 => rc1, O_RESULT_CURSOR => rcr);
        c := DBMS_SQL.TO_CURSOR_NUMBER(rc1); n := 0;
        WHILE DBMS_SQL.FETCH_ROWS(c) > 0 LOOP n := n + 1; END LOOP;
        DBMS_SQL.CLOSE_CURSOR(c);
        CLOSE rcr;
        ROLLBACK;
        DBMS_OUTPUT.PUT_LINE('V3 | div ' || RPAD(v(i), 3) || ' | ' || TO_CHAR((DBMS_UTILITY.GET_TIME - t0) / 100, 'FM99990.00') || 's | ' || n || '행');
    END LOOP;
END;
