-- DMF0074 메타 배선 검증 (기대치: API 7 / PROC 14+5 / BTN 7 / USER_GR 20 / EXCEL 2(PKG) / MSG 3+3 / MNU_URL)
SELECT 'API_M' CHK, COUNT(*) CNT FROM SCM_ADM_API_M WHERE API_ID LIKE 'DMF0074%'
UNION ALL SELECT 'PROC_M main(14)', COUNT(*) FROM SCM_ADM_PROC_M WHERE PROC_NM = 'PKG_DMF0074.P_DMF0074_GET_METAL_LINK_PRICE'
UNION ALL SELECT 'PROC_M template(5)', COUNT(*) FROM SCM_ADM_PROC_M WHERE PROC_NM = 'PKG_DMF0074.P_DMF0074_GET_METAL_LINK_TEMPLATE'
UNION ALL SELECT 'PROC_M version 공유(9)', COUNT(*) FROM SCM_ADM_PROC_M WHERE PROC_NM = 'DMF0073_GET_VERSION_SALESPRICE'
UNION ALL SELECT 'BTN_MPG(7+40업로드1=8)', COUNT(*) FROM SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID IN ('DMF0074','DMF0074_40')
UNION ALL SELECT 'USER_GR_BTN(20+40업로드2=22)', COUNT(*) FROM SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE MNU_ID IN ('DMF0074','DMF0074_40')
UNION ALL SELECT 'EXCEL_COLUMNS PKG(2)', COUNT(*) FROM SCM_ADM_EXCEL_COLUMNS WHERE PROGRAM_ID IN ('DMF0074','DMF0074_40') AND STORAGE_SQL_ID = 'PKG_DMF0074.P_DMF0074_EXCEL_UPLOAD'
UNION ALL SELECT 'MSG00656(3)', COUNT(*) FROM SCM_ADM_MSG_M WHERE MSG_ID = 'MSG00656'
UNION ALL SELECT 'LBL00762(3)', COUNT(*) FROM SCM_ADM_MSG_M WHERE MSG_ID = 'LBL00762'
UNION ALL SELECT 'MNU_URL=metal-link-price(1)', COUNT(*) FROM SCM_ADM_MNU_M WHERE MNU_ID = 'DMF0074' AND MNU_URL = 'metal-link-price'
UNION ALL SELECT 'ATTRIBUTE3 원복(0 기대 — #92 개정 DIVISION_ID 직접)', COUNT(*) FROM SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID = 'DMF0074' AND SHEET_NAME = 'Metal Link Price' AND ATTRIBUTE3 IS NOT NULL
-- 2-Step 저장 배선 (02_upload_save.sql)
UNION ALL SELECT 'API_M SAVE(1)', COUNT(*) FROM SCM_ADM_API_M WHERE API_ID = 'DMF0074_main_SAVE'
UNION ALL SELECT 'PROC_M EXCEL_UPLOAD(5)', COUNT(*) FROM SCM_ADM_PROC_M WHERE PROC_NM = 'PKG_DMF0074.P_DMF0074_EXCEL_UPLOAD'
UNION ALL SELECT 'BTN_MPG SAVE(1)', COUNT(*) FROM SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID = 'DMF0074' AND MNU_BTN_CD = 'SAVE'
UNION ALL SELECT 'USER_GR SAVE(2)', COUNT(*) FROM SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE MNU_ID = 'DMF0074' AND MNU_BTN_CD = 'SAVE'
UNION ALL SELECT 'MSG00657~659(9)', COUNT(*) FROM SCM_ADM_MSG_M WHERE MSG_ID IN ('MSG00657','MSG00658','MSG00659');

-- 체인 검증: PR_GET_PROC_INFO_LIST 가 소비하는 BTN→API→PROC 조인 (main SEARCH)
SELECT b.MNU_BTN_CD, a.API_URL, p.COL_NM, p.SORT_ORD, p.COL_TP_CD
FROM SCM_ADM_MNU_BTN_MPG_M b
JOIN SCM_ADM_API_M a ON a.API_ID = b.API_ID
JOIN SCM_ADM_PROC_M p ON p.PROC_NM = a.API_URL
WHERE b.MNU_ID = 'DMF0074' AND b.SHT_NM = 'Metal Link Price' AND b.MNU_BTN_CD = 'SEARCH'
ORDER BY p.SORT_ORD;
