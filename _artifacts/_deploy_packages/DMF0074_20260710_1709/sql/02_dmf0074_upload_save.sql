USING (
  SELECT 'MSG00657' MSG_ID, 'KO' LANG_CD, '오류 행이 존재하여 저장할 수 없습니다. 파일을 수정 후 다시 업로드하세요.' MSG_NM, 'MSG' MSG_TP_CD FROM DUAL
  UNION ALL SELECT 'MSG00657', 'EN', '오류 행이 존재하여 저장할 수 없습니다. 파일을 수정 후 다시 업로드하세요.', 'MSG' FROM DUAL
  UNION ALL SELECT 'MSG00657', 'CN', '오류 행이 존재하여 저장할 수 없습니다. 파일을 수정 후 다시 업로드하세요.', 'MSG' FROM DUAL
  UNION ALL SELECT 'MSG00658', 'KO', '먼저 파일을 업로드하여 검증하세요.', 'MSG' FROM DUAL
  UNION ALL SELECT 'MSG00658', 'EN', '먼저 파일을 업로드하여 검증하세요.', 'MSG' FROM DUAL
  UNION ALL SELECT 'MSG00658', 'CN', '먼저 파일을 업로드하여 검증하세요.', 'MSG' FROM DUAL
  UNION ALL SELECT 'MSG00659', 'KO', '검증이 완료되었습니다. 결과 확인 후 OK 를 눌러 저장하세요.', 'MSG' FROM DUAL
  UNION ALL SELECT 'MSG00659', 'EN', '검증이 완료되었습니다. 결과 확인 후 OK 를 눌러 저장하세요.', 'MSG' FROM DUAL
  UNION ALL SELECT 'MSG00659', 'CN', '검증이 완료되었습니다. 결과 확인 후 OK 를 눌러 저장하세요.', 'MSG' FROM DUAL
) s
ON (t.MSG_ID = s.MSG_ID AND t.LANG_CD = s.LANG_CD)
WHEN MATCHED THEN UPDATE SET t.MSG_NM = s.MSG_NM, t.MSG_TP_CD = s.MSG_TP_CD, t.USE_YN = 'Y',
  t.LAST_UPDATED_BY = 'admin', t.LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (MSG_ID, LANG_CD, MSG_NM, MSG_DESC, MSG_TP_CD, USE_YN,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES (s.MSG_ID, s.LANG_CD, s.MSG_NM, NULL, s.MSG_TP_CD, 'Y',
  'admin', SYSDATE, 'admin', SYSDATE);

COMMIT;
