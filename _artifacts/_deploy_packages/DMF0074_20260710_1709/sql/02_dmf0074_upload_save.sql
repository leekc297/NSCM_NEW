-- =====================================================================
-- DMF0074 Metal Link Price — Excel Upload 2-Step 저장 배선 (2026-07-10 추가)
-- [Upload]=검증·분류(FileController excel-upload, P_MODE=0) / [OK]=저장(call-proc, P_MODE=1).
-- P_DMF0074_EXCEL_UPLOAD(P_MODE=1) 은 최신 스테이징 배치(V_CREATION_DATE=MAX) 자동 선택 +
--   ERROR=0 전량 게이트(SP BODY L2649) → 검증 통과분만 DM_BPS_METAL_LINK_PRICE 반영.
-- BE 코드 변경 0 — 기존 call-proc(GeneralController) 체계 재사용. 멱등 MERGE.
-- =====================================================================

-- BLOCK 1. API_M — DMF0074_main_SAVE → PKG_DMF0074.P_DMF0074_EXCEL_UPLOAD
MERGE INTO SCM_ADM_API_M t
USING (
  SELECT 'DMF0074_main_SAVE' API_ID, 'PROC' API_TP_CD, 'MSG_API_DMF0074_MAIN_SAVE' API_MSG_ID,
         'DMF0074 Metal Link Price Upload Save' API_MSG_DESC, 'PKG_DMF0074.P_DMF0074_EXCEL_UPLOAD' API_URL FROM DUAL
) s
ON (t.API_ID = s.API_ID)
WHEN MATCHED THEN UPDATE SET t.API_TP_CD = s.API_TP_CD, t.API_URL = s.API_URL,
  t.API_MSG_DESC = s.API_MSG_DESC, t.USE_YN = 'Y',
  t.LAST_UPDATED_BY = 'admin', t.LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (API_ID, API_TP_CD, API_MSG_ID, API_MSG_DESC, API_URL, USE_YN,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES (s.API_ID, s.API_TP_CD, s.API_MSG_ID, s.API_MSG_DESC, s.API_URL, 'Y',
  'admin', SYSDATE, 'admin', SYSDATE);

-- BLOCK 2. PROC_M — PKG_DMF0074.P_DMF0074_EXCEL_UPLOAD 5행 (ALL_ARGUMENTS 실측 positional)
--   mode(NUMBER — P_MODE PLS_INTEGER, jdbcType=NUMERIC) / createdBy(BE 세션 자동) / programId / sheetName
MERGE INTO SCM_ADM_PROC_M t
USING (
  SELECT 'PKG_DMF0074.P_DMF0074_EXCEL_UPLOAD' PROC_NM, 'mode' COL_NM, 'NUMBER' DATA_TP_CD, 'IN' COL_TP_CD, 1 SORT_ORD FROM DUAL
  UNION ALL SELECT 'PKG_DMF0074.P_DMF0074_EXCEL_UPLOAD', 'createdBy',       'VARCHAR',     'IN',  2 FROM DUAL
  UNION ALL SELECT 'PKG_DMF0074.P_DMF0074_EXCEL_UPLOAD', 'programId',       'VARCHAR',     'IN',  3 FROM DUAL
  UNION ALL SELECT 'PKG_DMF0074.P_DMF0074_EXCEL_UPLOAD', 'sheetName',       'VARCHAR',     'IN',  4 FROM DUAL
  UNION ALL SELECT 'PKG_DMF0074.P_DMF0074_EXCEL_UPLOAD', 'o_result_cursor', 'PROC_RESULT', 'OUT', 5 FROM DUAL
) s
ON (t.PROC_NM = s.PROC_NM AND t.COL_NM = s.COL_NM)
WHEN MATCHED THEN UPDATE SET t.DATA_TP_CD = s.DATA_TP_CD, t.COL_TP_CD = s.COL_TP_CD, t.SORT_ORD = s.SORT_ORD,
  t.LAST_UPDATED_BY = 'admin', t.LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (PROC_NM, COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES (s.PROC_NM, s.COL_NM, s.DATA_TP_CD, s.COL_TP_CD, s.SORT_ORD,
  'admin', SYSDATE, 'admin', SYSDATE);

-- BLOCK 3. BTN_MPG — DMF0074 / 'Metal Link Price' / 'SAVE' (call-proc auth 키)
MERGE INTO SCM_ADM_MNU_BTN_MPG_M t
USING (
  SELECT 'DMF0074' MNU_ID, 'Metal Link Price' SHT_NM, 'SAVE' MNU_BTN_CD, 'DMF0074_main_SAVE' API_ID FROM DUAL
) s
ON (t.MNU_ID = s.MNU_ID AND t.SHT_NM = s.SHT_NM AND t.MNU_BTN_CD = s.MNU_BTN_CD)
WHEN MATCHED THEN UPDATE SET t.API_ID = s.API_ID, t.USE_YN = 'Y',
  t.LAST_UPDATED_BY = 'admin', t.LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (MNU_ID, SHT_NM, MNU_BTN_CD, API_ID, USE_YN,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES (s.MNU_ID, s.SHT_NM, s.MNU_BTN_CD, s.API_ID, 'Y',
  'admin', SYSDATE, 'admin', SYSDATE);

-- BLOCK 4. USER_GR_BTN — ADMIN / DM ADMIN 만 SAVE (DM Viewer = 저장 write op 제외, UPLOAD 와 동일)
MERGE INTO SCM_ADM_USER_GR_MNU_BTN_MPG_M t
USING (
  SELECT g.USER_GR_ID, 'DMF0074' MNU_ID, 'Metal Link Price' SHT_NM, 'SAVE' MNU_BTN_CD
  FROM (SELECT 'ADMIN' USER_GR_ID FROM DUAL UNION ALL SELECT 'DM ADMIN' FROM DUAL) g
) s
ON (t.USER_GR_ID = s.USER_GR_ID AND t.MNU_ID = s.MNU_ID AND t.SHT_NM = s.SHT_NM AND t.MNU_BTN_CD = s.MNU_BTN_CD)
WHEN MATCHED THEN UPDATE SET t.USE_YN = 'Y',
  t.LAST_UPDATED_BY = 'admin', t.LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (USER_GR_ID, MNU_ID, SHT_NM, MNU_BTN_CD, USE_YN,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES (s.USER_GR_ID, s.MNU_ID, s.SHT_NM, s.MNU_BTN_CD, 'Y',
  'admin', SYSDATE, 'admin', SYSDATE);

-- BLOCK 5. MSG — 2-Step 안내 문구 (신규 채번 MSG00657~00659, KO=EN=CN)
