-- DMF0035_CLOUD_20260904 / 배포 후 검증 (전 축)
-- 기대값은 **사내 실측 기준선**이다. 클라우드 값이 다르면 원인을 규명하기 전에 완료 선언 금지.

-- V1. PKG 3종 상태 + 이번 정정 마커 (기대: 전부 VALID / TSCAXIS 4 · FORCEDAXIS 1)
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI') LAST_DDL
  FROM ALL_OBJECTS WHERE OWNER='SCM_MGR'
   AND OBJECT_NAME IN ('PKG_DMF0035','PKG_DMF0022','PKG_DMF0051') ORDER BY 1,2;

SELECT NAME, COUNT(*) CNT FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0035' AND TYPE='PACKAGE BODY'
   AND (INSTR(TEXT,'E20260904-TSCAXIS')>0 OR INSTR(TEXT,'E20260904-FORCEDAXIS')>0)
 GROUP BY NAME;

-- V2. 시트 메타 행수 (기대: DMF0035 C71/M49 · DMF0022 C66+C65/M31 · DMF0051 C61/M9)
SELECT 'COLUMNS' T, PROGRAM_ID, SHEET_NAME, COUNT(*) CNT
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID IN ('DMF0035','DMF0022','DMF0051')
 GROUP BY PROGRAM_ID, SHEET_NAME
UNION ALL
SELECT 'MEASURE', PROGRAM_ID, SHEET_NAME, COUNT(*)
  FROM SCM_MGR.SCM_MST_SHEET_MEASURE WHERE PROGRAM_ID IN ('DMF0035','DMF0022','DMF0051')
 GROUP BY PROGRAM_ID, SHEET_NAME ORDER BY 1,2,3;

-- V3. 메뉴·버튼·API·PROC_M 배선 (기대: MNU_M 1 / BTN_MPG 8 / API 9 / PROC_M 32)
SELECT 'MNU_M' AXIS, COUNT(*) CNT FROM SCM_MGR.SCM_ADM_MNU_M WHERE MNU_ID='DMF0035'
UNION ALL SELECT 'MNU_BTN_MPG_M', COUNT(*) FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID='DMF0035'
UNION ALL SELECT 'API_M', COUNT(*) FROM SCM_MGR.SCM_ADM_API_M WHERE API_ID LIKE 'DMF0035%'
UNION ALL SELECT 'PROC_M', COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M
       WHERE PROC_NM LIKE 'PKG_DMF0035%' OR PROC_NM LIKE '%DMF0035%';

-- V4. 권한 (기대: 메뉴권한 5그룹 / 버튼권한 40행) — ⚠ 0 이면 권한뷰가 오류 없이 0행이 된다(#148 §4.7-B)
SELECT 'USER_GR_MNU_MPG_M' AXIS, COUNT(*) CNT FROM SCM_MGR.SCM_ADM_USER_GR_MNU_MPG_M WHERE MNU_ID='DMF0035'
UNION ALL SELECT 'USER_GR_MNU_BTN_MPG_M', COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE MNU_ID='DMF0035';

-- V5. 화면이 소비하는 MSG/LBL 코드 등록 여부 (미등록 = 화면에 '_' 노출)
SELECT MSG_ID, COUNT(DISTINCT LANG_CD) LANGS FROM SCM_MGR.SCM_ADM_MSG_M
 WHERE MSG_ID IN ('MNU00691','MSG00013','MSG00097','MSG00108','MSG00109','MSG00137','MSG00164',
                  'MSG00283','MSG00606','MSG00618','LBL00605','LBL00711','LBL00712','LBL00764','LBL00765')
 GROUP BY MSG_ID ORDER BY 1;

-- V6. titleset 'C' 축 (13_MIGRATE 적용 전/후 대조) — camel 축 행이 spaced 축으로 복사됐는지
SELECT SHEET_NAME, USER_INQUIRY_COLUMN_TYPE_CODE TP, COUNT(*) ROWS_CNT, COUNT(DISTINCT USER_ID) USERS
  FROM SCM_MGR.SCM_MST_TITLESET_USER WHERE PROGRAM_ID='DMF0035'
 GROUP BY SHEET_NAME, USER_INQUIRY_COLUMN_TYPE_CODE ORDER BY 1,2;

-- V7. 고아 개인화 (기대 0) — 새 축 'C' 행 중 SHEET_COLUMNS 에 없는 컬럼
SELECT COUNT(*) ORPHAN FROM SCM_MGR.SCM_MST_TITLESET_USER U
 WHERE U.PROGRAM_ID='DMF0035' AND U.SHEET_NAME='Mkt Fcst Waterfall'
   AND U.USER_INQUIRY_COLUMN_TYPE_CODE='C'
   AND NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_MST_SHEET_COLUMNS C
                    WHERE C.PROGRAM_ID='DMF0035' AND C.SHEET_NAME='Mkt Fcst Waterfall'
                      AND C.COLUMN_NAME=U.COLUMN_NAME);

-- V8. 실행 권한/시노님 (hook #148 — 앱계정이 PKG 를 못 부르면 -9994)
SELECT TABLE_NAME OBJ, GRANTEE, PRIVILEGE FROM ALL_TAB_PRIVS
 WHERE TABLE_SCHEMA='SCM_MGR' AND TABLE_NAME IN ('PKG_DMF0035','PKG_DMF0022','PKG_DMF0051')
 ORDER BY 1,2;
