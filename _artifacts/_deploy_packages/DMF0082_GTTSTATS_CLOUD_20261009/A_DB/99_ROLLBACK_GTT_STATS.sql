-- 99 ROLLBACK — [E20261009-DMF0082GTTSTATS] 고정 통계 삭제 + PREF SESSION 복원 (적용 전 상태). 커서 무효화 포함
BEGIN
  FOR r IN (SELECT COLUMN_VALUE t FROM TABLE(SYS.ODCIVARCHAR2LIST('GT_DMF0082_TEMP_SITE_ITEM','GT_DMF0082_TEMP_SELECT_MEASURE','GT_DMF0082_T_WS_FCST','GT_DMF0082_TEMP_FCST_N_PRICE','GT_DMF0082_T_LAST_DATA_SETUP_FCST','GT_DMF0082_MF_SP'))) LOOP
    DBMS_STATS.DELETE_TABLE_STATS(ownname => 'SCM_MGR', tabname => r.t, no_invalidate => FALSE);
    DBMS_STATS.SET_TABLE_PREFS('SCM_MGR', r.t, 'GLOBAL_TEMP_TABLE_STATS', 'SESSION');
  END LOOP;
  COMMIT;
END;
/
SELECT 'ROLLED' CHK, T.TABLE_NAME, T.NUM_ROWS, DBMS_STATS.GET_PREFS('GLOBAL_TEMP_TABLE_STATS', 'SCM_MGR', T.TABLE_NAME) GTT_PREF
  FROM USER_TABLES T
 WHERE T.TABLE_NAME IN ('GT_DMF0082_TEMP_SITE_ITEM','GT_DMF0082_TEMP_SELECT_MEASURE','GT_DMF0082_T_WS_FCST','GT_DMF0082_TEMP_FCST_N_PRICE','GT_DMF0082_T_LAST_DATA_SETUP_FCST','GT_DMF0082_MF_SP')
 ORDER BY T.TABLE_NAME;
