-- SYS0014 SCMD_APP 권한 (BE 사용계정)
-- ⚠ 신규 화면 작성 시 반드시 SCM_MGR (DDL owner) 에서 실행
-- ⚠ 누락 시 BE 호출 -9994 'Sql Error' (PLS-00201 권한없음)

-- 1) SP EXECUTE GRANT + PUBLIC SYNONYM
GRANT EXECUTE ON SCM_MGR.P_SYS0014_GET_AUTH_LIST_M TO SCMD_APP;
CREATE OR REPLACE SYNONYM SCMD_APP.P_SYS0014_GET_AUTH_LIST_M FOR SCM_MGR.P_SYS0014_GET_AUTH_LIST_M;
GRANT EXECUTE ON SCM_MGR.P_SYS0014_GET_GROUP_LIST_M TO SCMD_APP;
CREATE OR REPLACE SYNONYM SCMD_APP.P_SYS0014_GET_GROUP_LIST_M FOR SCM_MGR.P_SYS0014_GET_GROUP_LIST_M;
GRANT EXECUTE ON SCM_MGR.P_SYS0014_GET_USER_BY_GROUP_M TO SCMD_APP;
CREATE OR REPLACE SYNONYM SCMD_APP.P_SYS0014_GET_USER_BY_GROUP_M FOR SCM_MGR.P_SYS0014_GET_USER_BY_GROUP_M;
GRANT EXECUTE ON SCM_MGR.P_SYS0014_SAVE_GROUP_USER_M TO SCMD_APP;
CREATE OR REPLACE SYNONYM SCMD_APP.P_SYS0014_SAVE_GROUP_USER_M FOR SCM_MGR.P_SYS0014_SAVE_GROUP_USER_M;

-- 3) 검증
SELECT GRANTEE, PRIVILEGE, TABLE_NAME FROM DBA_TAB_PRIVS
 WHERE GRANTEE='SCMD_APP' AND OWNER='SCM_MGR' AND TABLE_NAME LIKE '%SYS0014%'
 ORDER BY TABLE_NAME, PRIVILEGE;
