MERGE INTO SCM_ADM_MNU_M t USING (SELECT 'SYS0014' MNU_ID FROM DUAL) s ON (t.MNU_ID=s.MNU_ID)
 WHEN MATCHED THEN UPDATE SET MNU_DESC='Group User', UPPR_MNU_ID='System', MNU_URL='group-user', LAST_UPDATED_BY='admin', LAST_UPDATE_DATE=SYSDATE
