-- DMF0082 PRICEWEEK 검증 — 01(SPEC) → 02(BODY) 실행 후 전 항목 통과 의무
-- ⚠ 코드행 판정은 주석 제외 (LTRIM(TEXT) NOT LIKE '--%')

-- V1. 객체 상태 (기대: PACKAGE / PACKAGE BODY 모두 VALID)
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL
  FROM ALL_OBJECTS WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_DMF0082' ORDER BY 2;

-- V2. 컴파일 오류 (기대: 0)
SELECT COUNT(*) ERR FROM ALL_ERRORS WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY';

-- V3. 52주 CROSS JOIN 소멸 (기대: 0) / 주차 조인 실재 (기대: 2 — SAVE 검증10 + 업로드 게이트)
SELECT SUM(CASE WHEN REPLACE(TEXT,' ','') LIKE '%MON1=1%' THEN 1 ELSE 0 END) OLD_CROSSJOIN,
       SUM(CASE WHEN TEXT LIKE '%M.BASIS_YYYYMMDD = A.YYYYMMDD%' THEN 1 ELSE 0 END) NEW_WEEKJOIN
  FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY'
   AND LTRIM(TEXT) NOT LIKE '--%';

-- V4. 52주 산식 잔존 (기대: 2 — 엑셀 양식 기간(M0~M12) 전개 전용. 단가 RULE 아님)
SELECT LINE, TRIM(TEXT) FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY'
   AND LTRIM(TEXT) NOT LIKE '--%' AND TEXT LIKE '%52 * 7%' ORDER BY LINE;

-- V5. 삭제 가드 — 구 '52주 이내' 블록 소멸 (기대: 0)
SELECT COUNT(*) OLD_WITHIN52 FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY'
   AND TEXT LIKE '%52주 이내의 데이터의 FLAG%';

-- V6. 메시지 — 52주 문구 소멸 (기대: 0)
SELECT COUNT(*) OLD_MSG FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY'
   AND TEXT LIKE '%미래구간 52주차까지%';

-- V7. 런타임 A/B (사내 실측 방식) — 동일 키·동일 52주 구간에서 판가가 일부 주차만 있는 데이터로
--     MKT FCST 를 2주차에 입력했을 때:
--       판가 있는 주차 → 통과 / 판가 없는 주차 → 'Unit Price Not Found' 1건만 차단.
--     사내 실측(2026-09-16): 판가 25주분 보유 키 기준
--       AS-IS 판정 = 20260914·20270208 **둘 다 차단** / TO-BE 판정 = 20270208 **만 차단**.

-- V8. SPEC ↔ BODY 정합 (SPEC 을 함께 배포했으므로 필수)
--   (a) 둘 다 VALID 인지는 V1 에서 확인. 여기서는 선언·구현 카운트를 대조한다.
SELECT (SELECT COUNT(DISTINCT OBJECT_NAME) FROM ALL_ARGUMENTS
         WHERE OWNER='SCM_MGR' AND PACKAGE_NAME='PKG_DMF0082') AS PUBLIC_SUBPROGRAMS
  FROM DUAL;
-- 기대: 17 (사내 실측 2026-09-16 — SPEC 선언 PROCEDURE 수와 동일)

--   (b) SPEC 배포 직후 BODY 미실행 상태를 잡아내는 가드 (기대: 0행)
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM ALL_OBJECTS
 WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_DMF0082' AND STATUS <> 'VALID';
