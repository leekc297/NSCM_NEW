SET LINESIZE 200 PAGESIZE 200 TRIMSPOOL ON VERIFY OFF
DEFINE DIV = '40'          -- ← 화면에서 조회한 사업부로 수정 ('40' / '81' / '81_UC' / '82' ...)

PROMPT ===== [0] 환경 + 진단 대상 division =====
SELECT SYS_CONTEXT('USERENV','DB_NAME') AS DB_NAME, '&DIV' AS DIV FROM DUAL;

PROMPT ===== [F1] DM_MST_VERSION SP_W 버전 (기대: 행수>0. 0 이면 여기가 원인 — 이번 주 SP_W 버전 자체 부재) =====
SELECT COUNT(*) AS SP_W_ROWS, MAX(VERSION_NO) AS MAX_VER, MAX(YYYYMMDD) AS MAX_YYYYMMDD
  FROM SCM_MGR.DM_MST_VERSION
 WHERE DIVISION_ID  = '&DIV'
   AND VERSION_TYPE = 'SP_W';

PROMPT ----- [F1b] 최근 SP_W 5건 (ATTRIBUTE7 상태 참고) -----
SELECT * FROM (
  SELECT VERSION_NO, YYYYMMDD, ATTRIBUTE7,
         TO_CHAR(CREATION_DATE,'MM-DD HH24:MI') AS CREATED
    FROM SCM_MGR.DM_MST_VERSION
   WHERE DIVISION_ID='&DIV' AND VERSION_TYPE='SP_W'
   ORDER BY VERSION_NO DESC
) WHERE ROWNUM <= 5;

PROMPT ===== [F2] 최신 버전 YYYYMMDD 의 달력 행 (기대: 1. 0 이면 SCM_SYS_CALENDAR_M 미적재가 원인) =====
SELECT COUNT(*) AS CAL_ROWS
  FROM SCM_MGR.SCM_SYS_CALENDAR_M B
 WHERE B.BASIS_YYYYMMDD = (SELECT MAX(YYYYMMDD) FROM SCM_MGR.DM_MST_VERSION
                            WHERE DIVISION_ID='&DIV' AND VERSION_TYPE='SP_W');

PROMPT ===== [F3] TEMP_VERSION_NO 산출 (SP CTE 원문 — RESULT_TO~PLAN_TO 기간 확인) =====
WITH TEMP_VERSION_NO AS (
    SELECT A.DIVISION_ID, A.VERSION_NO, A.YYYYMMDD, B.BASIS_YYYYMM AS YYYYMM
         , CASE WHEN B.BASIS_YYYYMM > TO_CHAR(SCM_MGR.FN_NEXT_DAY(A.YYYYMMDD, 'MON') - 7, 'YYYYMM')
                THEN TO_CHAR(ADD_MONTHS(TO_DATE(B.BASIS_YYYYMM || '01', 'YYYYMMDD'), -1), 'YYYYMMDD')
                ELSE B.BASIS_YYYYMM || '01' END AS RESULT_FROM
         , TO_CHAR(SCM_MGR.FN_NEXT_DAY(A.YYYYMMDD, 'MON') - 7, 'YYYYMMDD')                AS RESULT_TO
         , TO_CHAR(SCM_MGR.FN_NEXT_DAY(A.YYYYMMDD, 'MON') - 7 + (52 * 7) - 1, 'YYYYMMDD') AS PLAN_TO
    FROM (SELECT DIVISION_ID, MAX(VERSION_NO) AS VERSION_NO, MAX(YYYYMMDD) AS YYYYMMDD
            FROM SCM_MGR.DM_MST_VERSION
           WHERE DIVISION_ID='&DIV' AND VERSION_TYPE='SP_W'
           GROUP BY DIVISION_ID) A
    INNER JOIN SCM_MGR.SCM_SYS_CALENDAR_M B ON B.BASIS_YYYYMMDD = A.YYYYMMDD
)
SELECT * FROM TEMP_VERSION_NO;

PROMPT ===== [F4] 원장 깔때기 — DM_PLN_SALES_PLAN_C (SP 분기 1) =====
PROMPT   s1=버전·MEASURE·QTY·기간 / s2=+SITE / s3=+SALES_TYPE_CODE / s4=+SITE_ITEM / s5=+ITEM_SINGLE_V(P) / s6=+END_CUSTOMER lookup(+82 ENERGE)
WITH TEMP_VERSION_NO AS (
    SELECT A.DIVISION_ID, A.VERSION_NO, A.YYYYMMDD
         , TO_CHAR(SCM_MGR.FN_NEXT_DAY(A.YYYYMMDD, 'MON') - 7, 'YYYYMMDD')                AS RESULT_TO
         , TO_CHAR(SCM_MGR.FN_NEXT_DAY(A.YYYYMMDD, 'MON') - 7 + (52 * 7) - 1, 'YYYYMMDD') AS PLAN_TO
    FROM (SELECT DIVISION_ID, MAX(VERSION_NO) AS VERSION_NO, MAX(YYYYMMDD) AS YYYYMMDD
            FROM SCM_MGR.DM_MST_VERSION
           WHERE DIVISION_ID='&DIV' AND VERSION_TYPE='SP_W'
           GROUP BY DIVISION_ID) A
    INNER JOIN SCM_MGR.SCM_SYS_CALENDAR_M B ON B.BASIS_YYYYMMDD = A.YYYYMMDD
),
S1 AS (
    SELECT SP.* FROM SCM_MGR.DM_PLN_SALES_PLAN_C SP
    INNER JOIN TEMP_VERSION_NO T_VER
            ON SP.DIVISION_ID = T_VER.DIVISION_ID AND SP.VERSION_NO = T_VER.VERSION_NO
     WHERE SP.DIVISION_ID='&DIV' AND SP.QTY <> 0 AND SP.MEASURE = 'RTF_SYS_RP'
       AND SP.YYYYMMDD >= T_VER.RESULT_TO AND SP.YYYYMMDD <= T_VER.PLAN_TO
)
SELECT
  (SELECT COUNT(*) FROM S1) AS s1_ledger,
  (SELECT COUNT(*) FROM S1 SP INNER JOIN SCM_MGR.SCM_MST_SITE MS
     ON MS.DIVISION_ID=SP.DIVISION_ID AND MS.SCM_SITE_ID=SP.SCM_SITE_ID AND MS.VALID_YN='Y') AS s2_site,
  (SELECT COUNT(*) FROM S1 SP
     INNER JOIN SCM_MGR.SCM_MST_SITE MS
       ON MS.DIVISION_ID=SP.DIVISION_ID AND MS.SCM_SITE_ID=SP.SCM_SITE_ID AND MS.VALID_YN='Y'
     INNER JOIN SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL LUP
       ON LUP.LOOKUP_TYPE='SALES_TYPE_CODE' AND LUP.VALID_YN='Y' AND LUP.SEGMENT4<>'FREE'
      AND LUP.SEGMENT1=SP.FCST_TYPE) AS s3_fcsttype,
  (SELECT COUNT(*) FROM S1 SP
     INNER JOIN SCM_MGR.SCM_MST_SITE MS
       ON MS.DIVISION_ID=SP.DIVISION_ID AND MS.SCM_SITE_ID=SP.SCM_SITE_ID AND MS.VALID_YN='Y'
     INNER JOIN SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL LUP
       ON LUP.LOOKUP_TYPE='SALES_TYPE_CODE' AND LUP.VALID_YN='Y' AND LUP.SEGMENT4<>'FREE'
      AND LUP.SEGMENT1=SP.FCST_TYPE
     INNER JOIN SCM_MGR.SCM_MST_SITE_ITEM SI
       ON SI.DIVISION_ID=SP.DIVISION_ID AND SI.PROJECT_CODE=SP.PROJECT_CODE
      AND SI.SCM_SITE_ID=SP.SCM_SITE_ID AND SI.ITEM_ID=SP.ITEM_ID AND SI.VALID_YN='Y') AS s4_siteitem,
  (SELECT COUNT(*) FROM S1 SP
     INNER JOIN SCM_MGR.SCM_MST_SITE MS
       ON MS.DIVISION_ID=SP.DIVISION_ID AND MS.SCM_SITE_ID=SP.SCM_SITE_ID AND MS.VALID_YN='Y'
     INNER JOIN SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL LUP
       ON LUP.LOOKUP_TYPE='SALES_TYPE_CODE' AND LUP.VALID_YN='Y' AND LUP.SEGMENT4<>'FREE'
      AND LUP.SEGMENT1=SP.FCST_TYPE
     INNER JOIN SCM_MGR.SCM_MST_SITE_ITEM SI
       ON SI.DIVISION_ID=SP.DIVISION_ID AND SI.PROJECT_CODE=SP.PROJECT_CODE
      AND SI.SCM_SITE_ID=SP.SCM_SITE_ID AND SI.ITEM_ID=SP.ITEM_ID AND SI.VALID_YN='Y'
     INNER JOIN SCM_MGR.DM_MST_ITEM_SINGLE_V SV
       ON SV.DIVISION_ID=SI.DIVISION_ID AND SV.ITEM_ID=SI.ITEM_ID AND SV.ITEM_TYPE='P') AS s5_itemP,
  (SELECT COUNT(*) FROM S1 SP
     INNER JOIN SCM_MGR.SCM_MST_SITE MS
       ON MS.DIVISION_ID=SP.DIVISION_ID AND MS.SCM_SITE_ID=SP.SCM_SITE_ID AND MS.VALID_YN='Y'
     INNER JOIN SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL LUP
       ON LUP.LOOKUP_TYPE='SALES_TYPE_CODE' AND LUP.VALID_YN='Y' AND LUP.SEGMENT4<>'FREE'
      AND LUP.SEGMENT1=SP.FCST_TYPE
     INNER JOIN SCM_MGR.SCM_MST_SITE_ITEM SI
       ON SI.DIVISION_ID=SP.DIVISION_ID AND SI.PROJECT_CODE=SP.PROJECT_CODE
      AND SI.SCM_SITE_ID=SP.SCM_SITE_ID AND SI.ITEM_ID=SP.ITEM_ID AND SI.VALID_YN='Y'
     INNER JOIN SCM_MGR.DM_MST_ITEM_SINGLE_V SV
       ON SV.DIVISION_ID=SI.DIVISION_ID AND SV.ITEM_ID=SI.ITEM_ID AND SV.ITEM_TYPE='P'
     INNER JOIN SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL LUP2
       ON SP.DIVISION_ID=LUP2.SEGMENT1 AND LUP2.LOOKUP_TYPE='END_CUSTOMER'
      AND CASE WHEN SP.DIVISION_ID='40' THEN SP.PROJECT_CODE ELSE MS.END_CUSTOMER END = LUP2.SEGMENT2
     WHERE (('&DIV'='82' AND EXISTS (SELECT 1 FROM SCM_MGR.SCM_MST_ITEM_SN MIS
                                      WHERE MIS.DIVISION_ID='82' AND MIS.ITEM_ID=SP.ITEM_ID
                                        AND NVL(MIS.ENERGE,'@#@#@#') <> '@#@#@#'
                                        AND MIS.ACTIVE_FLAG='Y'))
            OR ('&DIV' <> '82'))) AS s6_final
FROM DUAL;

PROMPT ===== [F5] 원장 깔때기 — DM_PLN_SALES_PLAN_RESULT_C (SP 분기 2 — 실적. s1 만: 0 이어도 분기 1 이 있으면 정상) =====
WITH TEMP_VERSION_NO AS (
    SELECT A.DIVISION_ID, A.VERSION_NO
    FROM (SELECT DIVISION_ID, MAX(VERSION_NO) AS VERSION_NO, MAX(YYYYMMDD) AS YYYYMMDD
            FROM SCM_MGR.DM_MST_VERSION
           WHERE DIVISION_ID='&DIV' AND VERSION_TYPE='SP_W'
           GROUP BY DIVISION_ID) A
    INNER JOIN SCM_MGR.SCM_SYS_CALENDAR_M B ON B.BASIS_YYYYMMDD = A.YYYYMMDD
)
SELECT COUNT(*) AS result_c_ledger
  FROM SCM_MGR.DM_PLN_SALES_PLAN_RESULT_C SP
 INNER JOIN TEMP_VERSION_NO T_VER
         ON SP.DIVISION_ID=T_VER.DIVISION_ID AND SP.VERSION_NO=T_VER.VERSION_NO
 WHERE SP.DIVISION_ID='&DIV';

