CREATE OR REPLACE PACKAGE BODY SCM_MGR.PKG_NSCM_UI_COM_AUTH 
AS


	PROCEDURE PR_CHECK_MNU_AUTH (
		P_USER_ID	IN VARCHAR2,
		P_MNU_ID	IN VARCHAR2,
		DATA		OUT	SYS_REFCURSOR
	) IS

	BEGIN
		OPEN DATA FOR
			SELECT CASE WHEN EXISTS (
				SELECT	*
				FROM	SCM_ADM_USER_GR_MPG_M UG
					INNER JOIN SCM_ADM_USER_GR_MNU_MPG_M GM
						ON	UG.USER_GR_ID = GM.USER_GR_ID
				WHERE 	1=1
				AND		UG.USER_ID = P_USER_ID
				AND		GM.MNU_ID = P_MNU_ID
			) THEN 'Y' ELSE 'N' END AS HAS_AUTH_YN
			FROM DUAL
			;
	END;

	PROCEDURE PR_CHECK_MNU_BTN_AUTH (
		P_USER_ID		IN VARCHAR2,
		P_MNU_ID		IN VARCHAR2,
		P_SHT_NM		IN VARCHAR2,
		P_MNU_BTN_CD 	IN VARCHAR2,
		DATA			OUT	SYS_REFCURSOR
	) IS

	BEGIN
		OPEN DATA FOR
			SELECT CASE WHEN EXISTS (
				SELECT	*
				  FROM	SCM_ADM_USER_GR_MPG_M UG
			INNER JOIN SCM_ADM_USER_GR_MNU_BTN_MPG_M GMB
					ON	UG.USER_GR_ID = GMB.USER_GR_ID
				 WHERE 	1=1
				   AND	UG.USER_ID = P_USER_ID
				   AND	GMB.MNU_ID = P_MNU_ID
				   AND	GMB.SHT_NM = P_SHT_NM
				   AND	GMB.MNU_BTN_CD = P_MNU_BTN_CD
				   AND	UG.USE_YN = 'Y'    --[E20260826-BTNUSEYN] 회수(USE_YN='N') 행 실효화 — 버튼 숨김과 API 게이트 동기
				   AND	GMB.USE_YN = 'Y'   --[E20260826-BTNUSEYN]
			) THEN 'Y' ELSE 'N' END AS HAS_AUTH_YN
			FROM DUAL
			;
	END;

	PROCEDURE PR_GET_MNU_BTN_AUTH (
		P_USER_ID		IN VARCHAR2,
		P_MNU_ID		IN VARCHAR2,
		DATA			OUT	SYS_REFCURSOR
	) IS

	BEGIN
		OPEN DATA FOR
			SELECT  DISTINCT GM.MNU_ID, GMB.SHT_NM, GMB.MNU_BTN_CD
			  FROM	SCM_ADM_USER_GR_MPG_M UG
		INNER JOIN  SCM_ADM_USER_GR_MNU_MPG_M GM
				ON	GM.USER_GR_ID = UG.USER_GR_ID
		INNER JOIN SCM_ADM_USER_GR_MNU_BTN_MPG_M GMB
				ON	GMB.USER_GR_ID = UG.USER_GR_ID
			   AND  GMB.MNU_ID = GM.MNU_ID
			 WHERE 	1=1
			   AND 	UG.USER_ID = P_USER_ID
			   AND	GM.MNU_ID = P_MNU_ID
			   AND	UG.USE_YN = 'Y'
			   AND	GMB.USE_YN = 'Y'   --[E20260826-BTNUSEYN] 회수(USE_YN='N') 행 실효화 — admin 회수 의도 반영 (2026-08-26)
			;
	END;


	PROCEDURE PR_GET_UNIT_AUTH (
		P_USER_ID		IN VARCHAR2,
		P_MNU_ID		IN VARCHAR2,
		DATA			OUT	SYS_REFCURSOR
	) IS

	BEGIN
		OPEN DATA FOR
			SELECT	AA.UNIT_TP_CD, AA.UNIT_ID, AA.EDIT_YN
			FROM	(
			    	SELECT	A.UNIT_TP_CD
			    		  , A.UNIT_ID
			    		  , A.EDIT_YN
			    		  , ROW_NUMBER() OVER(
			               		PARTITION BY A.UNIT_TP_CD, A.UNIT_ID
			               		ORDER BY A.EDIT_YN DESC
				           	) AS RN
			    	FROM	(
							SELECT	UG.USER_ID		AS USER_ID
								  , UG.USER_GR_ID	AS USER_GR_ID
								  , GM.MNU_ID		AS MNU_ID
								  , UGU.UNIT_TP_CD	AS UNIT_TP_CD
								  , UGU.UNIT_ID		AS UNIT_ID
								  , UGU.EDIT_YN		AS EDIT_YN
							FROM 	SCM_ADM_USER_GR_MPG_M UG
								INNER JOIN SCM_ADM_USER_GR_MNU_MPG_M GM
									ON	GM.USER_GR_ID = UG.USER_GR_ID
								INNER JOIN SCM_ADM_USER_GR_UNIT_AUTH_MPG_M UGU
									ON 	UGU.USER_ID = UG.USER_ID
									AND UGU.USER_GR_ID = UG.USER_GR_ID
							WHERE 	1=1
							AND		UG.USER_ID = P_USER_ID
							AND		GM.MNU_ID = P_MNU_ID
							AND		UG.USE_YN = 'Y'
							AND 	UGU.USE_YN = 'Y'
							) A
					) AA
			WHERE RN = 1
			;
	END;

	PROCEDURE PR_GET_MNU_BTN_AUTH_DIV (
		P_USER_ID		IN VARCHAR2,
		P_MNU_ID		IN VARCHAR2,
		P_DIVISION_ID	IN VARCHAR2,
		DATA			OUT	SYS_REFCURSOR
	) IS
		--[E20261026-BTNDIV] 공통버튼(Insert/Delete/Save/Upload) 노출 = 사용자 × 선택 Division 권한 (2026-10-26 사용자 지시)
		--  P_DIVISION_ID 가 NULL/'ALL'/복수(',' 포함)면 PR_GET_MNU_BTN_AUTH 와 같은 그룹 합집합(기존 동작).
		--  단일 Division 이면 ① 그 Division 단위권한(SCM_ADM_USER_GR_UNIT_AUTH_MPG_M UNIT_TP_CD='D')을 가진 그룹
		--                  ② Division 단위권한이 전혀 없는 전역 그룹(ADMIN 직접 부여·GUEST 등) 만 인정한다.
		--  Division 콤보(SCM_ADM_CMBO_SQL_M MyDivision/Division_SCP)와 같은 원천이라 "조회 가능한 Division" 과 "그 Division 의 버튼" 이 한 축으로 움직인다.
		V_DIV	VARCHAR2(100) := NVL(TRIM(P_DIVISION_ID), 'ALL');
	BEGIN
		OPEN DATA FOR
			SELECT  DISTINCT GM.MNU_ID, GMB.SHT_NM, GMB.MNU_BTN_CD
			  FROM	SCM_ADM_USER_GR_MPG_M UG
		INNER JOIN  SCM_ADM_USER_GR_MNU_MPG_M GM
				ON	GM.USER_GR_ID = UG.USER_GR_ID
		INNER JOIN SCM_ADM_USER_GR_MNU_BTN_MPG_M GMB
				ON	GMB.USER_GR_ID = UG.USER_GR_ID
			   AND  GMB.MNU_ID = GM.MNU_ID
			 WHERE 	1=1
			   AND 	UG.USER_ID = P_USER_ID
			   AND	GM.MNU_ID = P_MNU_ID
			   AND	UG.USE_YN = 'Y'
			   AND	GMB.USE_YN = 'Y'
			   AND	(	V_DIV = 'ALL'
					 OR	INSTR(V_DIV, ',') > 0
					 OR	NOT EXISTS (SELECT 1 FROM SCM_ADM_USER_GR_UNIT_AUTH_MPG_M U0
									 WHERE U0.USER_ID = UG.USER_ID AND U0.USER_GR_ID = UG.USER_GR_ID
									   AND U0.UNIT_TP_CD = 'D' AND U0.USE_YN = 'Y')
					 OR	EXISTS (SELECT 1 FROM SCM_ADM_USER_GR_UNIT_AUTH_MPG_M U
								 WHERE U.USER_ID = UG.USER_ID AND U.USER_GR_ID = UG.USER_GR_ID
								   AND U.UNIT_TP_CD = 'D' AND U.USE_YN = 'Y' AND U.UNIT_ID = V_DIV)
					)
			;
	END;

END ;
