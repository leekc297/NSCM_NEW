-- * 기대: V1 마커 1 PASS · V2 VALID / 오류 0 / 의존 INVALID 0 · V3 CF 안 TODO 주석 0 PASS · V4 CF 안 활성 호출 1 PASS
SET LINESIZE 220 PAGESIZE 500
SET DEFINE OFF
COLUMN CHK FORMAT A10
COLUMN KIND FORMAT A50
COLUMN JUDGE FORMAT A60
SELECT 'V1 마커' CHK, COUNT(*) N, CASE WHEN COUNT(*) = 1 THEN 'PASS' ELSE 'FAIL (미적용 또는 마커 수 불일치)' END JUDGE
  FROM USER_SOURCE WHERE NAME='PKG_DMF0044' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%GAP313 2026-10-15%';
SELECT 'V2 상태' CHK, O.OBJECT_TYPE, O.STATUS, TO_CHAR(O.LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL,
       (SELECT COUNT(*) FROM USER_ERRORS E WHERE E.NAME=O.OBJECT_NAME AND E.TYPE=O.OBJECT_TYPE) ERR_CNT,
       (SELECT COUNT(*) FROM USER_OBJECTS X WHERE X.STATUS<>'VALID' AND X.OBJECT_NAME IN (SELECT NAME FROM USER_DEPENDENCIES WHERE REFERENCED_NAME='PKG_DMF0044')) DEP_INVALID
  FROM USER_OBJECTS O WHERE O.OBJECT_NAME='PKG_DMF0044' ORDER BY O.OBJECT_TYPE;
SELECT 'V3 잔존' CHK, 'CF TODO 주석 시작줄' KIND, COUNT(*) N, CASE WHEN COUNT(*) = 0 THEN 'PASS' ELSE 'FAIL — 회신' END JUDGE
  FROM USER_SOURCE S WHERE S.NAME='PKG_DMF0044' AND S.TYPE='PACKAGE BODY'
   AND RTRIM(S.TEXT, CHR(10)||CHR(13)) = '    /* TODO DMF0044_MOBILE_REPORT_CREATE'
   AND S.LINE BETWEEN (SELECT MIN(LINE) FROM USER_SOURCE WHERE NAME='PKG_DMF0044' AND TYPE='PACKAGE BODY' AND TEXT LIKE 'PROCEDURE P_DMF0044_SAVE_SALES_PLAN_REPORT_C_CF%')
                  AND (SELECT MIN(LINE) FROM USER_SOURCE WHERE NAME='PKG_DMF0044' AND TYPE='PACKAGE BODY' AND TEXT LIKE 'END P_DMF0044_SAVE_SALES_PLAN_REPORT_C_CF;%');
SELECT 'V4 활성' CHK, 'CF 안 P_DMF0044_MOBILE_REPORT_CREATE 호출줄' KIND, COUNT(*) N, CASE WHEN COUNT(*) = 1 THEN 'PASS' ELSE 'FAIL — 회신' END JUDGE
  FROM USER_SOURCE S WHERE S.NAME='PKG_DMF0044' AND S.TYPE='PACKAGE BODY'
   AND TRIM(RTRIM(S.TEXT, CHR(10)||CHR(13))) = 'P_DMF0044_MOBILE_REPORT_CREATE(V_DIVISION_ID, V_VERSION_NO, V_CUTOFF_TYPE, ''T'', V_CREATED_BY, L_MOB_RC);'
   AND S.LINE BETWEEN (SELECT MIN(LINE) FROM USER_SOURCE WHERE NAME='PKG_DMF0044' AND TYPE='PACKAGE BODY' AND TEXT LIKE 'PROCEDURE P_DMF0044_SAVE_SALES_PLAN_REPORT_C_CF%')
                  AND (SELECT MIN(LINE) FROM USER_SOURCE WHERE NAME='PKG_DMF0044' AND TYPE='PACKAGE BODY' AND TEXT LIKE 'END P_DMF0044_SAVE_SALES_PLAN_REPORT_C_CF;%');
