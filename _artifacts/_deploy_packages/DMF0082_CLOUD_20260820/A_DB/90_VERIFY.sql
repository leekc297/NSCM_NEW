-- DMF0082_CLOUD_20260820 / 적용 후 검증 (룰 #136 — 대상 객체 실측)

-- V1. PKG 컴파일 상태 (기대: PACKAGE/BODY 둘 다 VALID)
SELECT OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI') LAST_DDL
FROM   ALL_OBJECTS WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_DMF0082' ORDER BY 1;

-- V2. 신규 마커 10계보 (기대: LIMITMEAS 5 / MULTIJOIN 10 / PJTNAME 4 / SENDERJOIN 5 / XLS81LOC 16
--     / AFSNULL 11 / MEASRULE 1 / SENTINELDDL 12 / XLSSAVEPERF 2 / XLSWEEKLY 14)
SELECT REGEXP_SUBSTR(TEXT,'E202608(19|20)-[A-Z0-9]+') MARKER, COUNT(*) CNT
FROM   ALL_SOURCE
WHERE  OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY'
AND    REGEXP_LIKE(TEXT,'E202608(19|20)-')
GROUP  BY REGEXP_SUBSTR(TEXT,'E202608(19|20)-[A-Z0-9]+') ORDER BY 1;

-- V3. DEFAULT_ON_NULL (기대: MKT 12 / _H 12 / SELL 13 / FUT 11 / GT_PRDM1_T_MAIN 13)
SELECT TABLE_NAME, COUNT(*) CNT
FROM   ALL_TAB_COLUMNS
WHERE  OWNER='SCM_MGR' AND DEFAULT_ON_NULL='YES'
AND    TABLE_NAME IN ('DM_PLN_CFM_MKT_DEMAND_PLAN','DM_PLN_CFM_MKT_DEMAND_PLAN_H',
                      'DM_PLN_CFM_SELLING_PRICE','SCM_MST_FUTURE_PRICE','GT_PRDM1_T_MAIN')
GROUP  BY TABLE_NAME ORDER BY 1;

-- V4. 변형 동일 처리 삭제 확인 (기대: 0행 — BODY 에 IN ('-','--') 패턴 잔존 없음)
SELECT COUNT(*) REMAIN_EQUIV
FROM   ALL_SOURCE
WHERE  OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY'
AND    (TEXT LIKE q'[%IN ('-','--')%]' OR INSTR(TEXT,'CHR(0)') > 0)
AND    TEXT NOT LIKE '%--%변형%';  -- 주석 언급 제외

-- V5. CMBO 5본 (기대: 5행, USE_YN='Y')
SELECT SQL_ID, USE_YN, TO_CHAR(LAST_UPDATE_DATE,'YYYY-MM-DD HH24:MI') UPD
FROM   SCM_MGR.SCM_ADM_CMBO_SQL_M
WHERE  SQL_ID IN ('EndCustomer','SiteEndCustomerMapDMF0082','EndCustomerByDivisionDMF0082',
                  'FcstTypeByUserGroupDMF0082','FcstTypeEditDMF0082') ORDER BY 1;

-- V6. SHEET_COLUMNS 재적재 (기대: FcstNPrice 61 / Sales Price Save All 25)
SELECT SHEET_NAME, COUNT(*) CNT FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
WHERE  PROGRAM_ID='DMF0082' GROUP BY SHEET_NAME ORDER BY 1;

-- V7. EXCEL_COLUMNS (기대: 1행 — STORAGE_SQL_ID='PKG_DMF0082.P_DMF0082_EXCEL_UPLOAD')
SELECT PROGRAM_ID, SHEET_NAME, STORAGE_SQL_ID, SUBSTR(HEADER_CONTENT,1,80) HEAD
FROM   SCM_MGR.SCM_ADM_EXCEL_COLUMNS WHERE PROGRAM_ID='DMF0082';

-- V8. MSG 10종 × 3언어 (기대: 각 3행)
SELECT MSG_ID, COUNT(*) CNT FROM SCM_MGR.SCM_ADM_MSG_M
WHERE  MSG_ID IN ('MSG01001','MSG00328','MSG00457','MSG00458','MSG00459',
                  'MSG00460','MSG00461','MSG00462','MSG00467','MSG01014')
GROUP  BY MSG_ID ORDER BY 1;

-- V9. 런타임 스모크 (BE 재기동·재로그인 후 화면에서):
--   ① 81 division 조회 → Sender Name 등 빈 셀 병합 표시 확인
--   ② Grid Column Setting 모달 목록 표시 (titleset — C_BE 복원분)
--   ③ Excel Form 다운로드 → Upload → [OK] — 저장 소요 수 초 확인 (V81-04 재작성)
--   ④ AS From Site — 판가 행 '-' 아닌 빈칸 표시 확인

-- V5b. 조회조건 정합 CMBO 2본 존재 (2026-08-20 콤보 정합분 — 없으면 Team/End Customer 콤보가 조용히 빈 목록)
