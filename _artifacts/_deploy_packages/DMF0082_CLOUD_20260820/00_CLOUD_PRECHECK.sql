-- 직전 클라우드 패키지 = DMF0082_CLOUD_20260818

-- C1. 마커 기준선 — 본 패키지 BODY 가 담는 신규 마커 10계보. 기준선에서 전부 0 이 정상.
--     (E20260818-* 가 0 이면 직전 0818 패키지도 미적용 상태 — 0818 먼저 적용 후 본 패키지 진행)
SELECT REGEXP_SUBSTR(TEXT,'E202608(1[89]|20)-[A-Z0-9]+') MARKER, COUNT(*) CNT
FROM   ALL_SOURCE
WHERE  OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY'
AND    REGEXP_LIKE(TEXT,'E202608(1[89]|20)-')
GROUP  BY REGEXP_SUBSTR(TEXT,'E202608(1[89]|20)-[A-Z0-9]+') ORDER BY 1;

-- C2. 참조 GTT 존재 (Excel/성능 경로 핵심 12종 — MISSING 있으면 직전 패키지들의 GTT DDL 선적용)
WITH need (G) AS (
  SELECT 'GT_PRDM1_T_MAIN' FROM DUAL UNION ALL SELECT 'GT_PRDM1_T_PRICE' FROM DUAL
  UNION ALL SELECT 'GT_PRDM1_T_FCST' FROM DUAL UNION ALL SELECT 'GT_PRDM1_MSHYCHU1' FROM DUAL
  UNION ALL SELECT 'GT_PRDM1_MSHYCHU2' FROM DUAL UNION ALL SELECT 'GT_DMF0082_PARAM_TOKEN' FROM DUAL
  UNION ALL SELECT 'GT_DMF0082_FCST_PRICE_DAILY' FROM DUAL UNION ALL SELECT 'GT_DMF0082_FCST_PRICE_WEEKLY' FROM DUAL
  UNION ALL SELECT 'GT_DMF0082_FCST_PRICE_UNPIVOT' FROM DUAL UNION ALL SELECT 'GT_DMF0082_FCST_PRICE_EXCEL' FROM DUAL
  UNION ALL SELECT 'GT_DMF0082_TEMP_FCST_N_PRICE' FROM DUAL UNION ALL SELECT 'GTT_TEMP_DM_MST_ITEM_SINGLE_V' FROM DUAL)
SELECT N.G, CASE WHEN T.TABLE_NAME IS NULL THEN 'MISSING ⛔' ELSE 'OK' END STATUS
FROM   need N LEFT JOIN ALL_TABLES T ON T.OWNER='SCM_MGR' AND T.TABLE_NAME=N.G
ORDER  BY 2 DESC, 1;

-- C3. DEFAULT_ON_NULL 현황 (적용 전 0 이 정상 — 03 적용 후 90_VERIFY 로 12/12/13/11/13 확인)
SELECT TABLE_NAME, COUNT(*) CNT
FROM   ALL_TAB_COLUMNS
WHERE  OWNER='SCM_MGR' AND DEFAULT_ON_NULL='YES'
AND    TABLE_NAME IN ('DM_PLN_CFM_MKT_DEMAND_PLAN','DM_PLN_CFM_MKT_DEMAND_PLAN_H',
                      'DM_PLN_CFM_SELLING_PRICE','SCM_MST_FUTURE_PRICE','GT_PRDM1_T_MAIN')
GROUP  BY TABLE_NAME ORDER BY 1;

-- C4. ⛔ 게이트 — 원장 PLANT_SITE_ID 변형 실측 (본 패키지 BODY 는 변형 동일 처리가 삭제된 본문이다.
--     변형이 1건이라도 있으면: 조회 dedup·저장 MERGE 키가 변형별로 갈라져 중복/누락 재발.
--     이 경우 BODY(02) 적용을 보류하고, 사내 절차와 동일한 데이터 정리
--     (_artifacts/_apply_corporate/DMF0082_SENTINEL_20260820/01_BACKUP + 02_DEDUP_NORMALIZE — 본
--     패키지에서는 사용자 지시로 제외됨)를 클라우드 DBA 와 별도 협의 후 진행한다.
--     또한 변형 기록 배치(EXCHANGE_RATE/BATCH_CFM_TO_ALL/BALANCE_MAKE 계열)의 '-' 정규화가
--     클라우드에도 반영되었는지 확인할 것 (사내는 2026-08-20 정규화 완료).
SELECT 'MKT' T, SUM(CASE WHEN PLANT_SITE_ID=' ' OR PLANT_SITE_ID='--' OR INSTR(PLANT_SITE_ID,CHR(0))>0
                          OR PLANT_SITE_ID<>TRIM(PLANT_SITE_ID) THEN 1 ELSE 0 END) VARIANTS
FROM SCM_MGR.DM_PLN_CFM_MKT_DEMAND_PLAN
UNION ALL
SELECT 'SELL', SUM(CASE WHEN PLANT_SITE_ID=' ' OR PLANT_SITE_ID='--' OR INSTR(PLANT_SITE_ID,CHR(0))>0
                         OR PLANT_SITE_ID<>TRIM(PLANT_SITE_ID) THEN 1 ELSE 0 END)
FROM SCM_MGR.DM_PLN_CFM_SELLING_PRICE
UNION ALL
SELECT 'FUT', SUM(CASE WHEN PLANT_SITE_ID=' ' OR PLANT_SITE_ID='--' OR INSTR(PLANT_SITE_ID,CHR(0))>0
                        OR PLANT_SITE_ID<>TRIM(PLANT_SITE_ID) THEN 1 ELSE 0 END)
FROM SCM_MGR.SCM_MST_FUTURE_PRICE;

