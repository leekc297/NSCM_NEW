DECLARE
    v_stmt VARCHAR2(4000);
BEGIN
    DBMS_OUTPUT.PUT_LINE('-- PKG_DMF0003 PROC_M (클라우드 추출 ' || TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI') || ') — INSERT-only NOT EXISTS');
    FOR r IN (SELECT PROC_NM, COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD,
                     CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE
              FROM   SCM_ADM_PROC_M WHERE PROC_NM LIKE 'PKG_DMF0003.%'
              ORDER  BY PROC_NM, SORT_ORD) LOOP
        v_stmt := 'INSERT INTO SCM_MGR.SCM_ADM_PROC_M (PROC_NM, COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)' || CHR(10) ||
                  'SELECT ''' || r.PROC_NM || ''', ''' || r.COL_NM || ''', ''' || r.DATA_TP_CD || ''', ''' || r.COL_TP_CD || ''', ' || r.SORT_ORD ||
                  ', ''' || r.CREATED_BY || ''', TO_DATE(''' || TO_CHAR(r.CREATION_DATE,'YYYYMMDDHH24MISS') || ''',''YYYYMMDDHH24MISS'')' ||
                  ', ''' || r.LAST_UPDATED_BY || ''', TO_DATE(''' || TO_CHAR(r.LAST_UPDATE_DATE,'YYYYMMDDHH24MISS') || ''',''YYYYMMDDHH24MISS'') FROM DUAL' || CHR(10) ||
                  'WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_PROC_M X WHERE X.PROC_NM = ''' || r.PROC_NM || ''' AND X.COL_NM = ''' || r.COL_NM || ''');';
        DBMS_OUTPUT.PUT_LINE(v_stmt);
    END LOOP;
    DBMS_OUTPUT.PUT_LINE('COMMIT;');
END;
