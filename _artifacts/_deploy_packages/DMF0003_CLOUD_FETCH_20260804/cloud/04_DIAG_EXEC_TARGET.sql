-- =============================================================================
-- 04_DIAG_EXEC_TARGET.sql — 클라우드 sqlplus 실행: BE 가 실제 실행하는 객체 실체 특정
-- 상황: FE payload userGroup='wonqthanq' 정상 + SCM_MGR.PKG_DMF0003 직접호출=Y
--       그런데 BE 경유 응답 EDIT_FLAG=N → BE 실행 실체가 패치본이 아니라는 뜻.
-- 후보: (T1) SCMD_APP 등 타 스키마의 PKG_DMF0003 구본 복사본
--       (T2) PKG 합류 전 standalone SP (P_DMF0003_GET_MKT_FCST_DATA) 잔존 + API_M 이 그쪽 지향
--       (T3) BE 데이터소스가 이 sqlplus 와 다른 DB/PDB
-- DBA_* 권한 없으면 해당 구간만 오류 후 계속 — ALL_* 결과로 판독.
-- =============================================================================
SET PAGESIZE 200 LINESIZE 200
COLUMN OWNER FORMAT A14
COLUMN OBJECT_NAME FORMAT A34
COLUMN OBJECT_TYPE FORMAT A14
COLUMN STATUS FORMAT A8
COLUMN LAST_DDL FORMAT A16
COLUMN TABLE_OWNER FORMAT A14
COLUMN TABLE_NAME FORMAT A30
COLUMN GRANTEE FORMAT A14
COLUMN PRIVILEGE FORMAT A12
COLUMN API_URL FORMAT A80

SELECT '[T0] 지금 접속한 DB 정체 — BE application.yml datasource URL 과 비교' AS DESC0 FROM DUAL;
SELECT USER AS CONNECTED_AS,
       SYS_CONTEXT('USERENV','DB_NAME') AS DB_NAME,
       SYS_CONTEXT('USERENV','CON_NAME') AS PDB_NAME,
       SYS_CONTEXT('USERENV','SERVER_HOST') AS HOST
FROM DUAL;

SELECT '[T1] PKG_DMF0003 이름의 전 객체 (기대: SCM_MGR 2건뿐 — 타 OWNER 에 PACKAGE 있으면 그게 범인)' AS DESC1 FROM DUAL;
SELECT OWNER, OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI') AS LAST_DDL
FROM DBA_OBJECTS WHERE OBJECT_NAME = 'PKG_DMF0003' ORDER BY OWNER, OBJECT_TYPE;
-- (DBA 권한 없을 때 대체)
SELECT OWNER, OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI') AS LAST_DDL
FROM ALL_OBJECTS WHERE OBJECT_NAME = 'PKG_DMF0003' ORDER BY OWNER, OBJECT_TYPE;

SELECT '[T1-b] 패치 마커 보유 OWNER (기대: SCM_MGR 3 — 타 OWNER 가 0 이면 구본 복사본 확정)' AS DESC1B FROM DUAL;
SELECT OWNER, COUNT(*) AS MARKS FROM DBA_SOURCE
WHERE NAME='PKG_DMF0003' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%AUTHGROUP 2026-08-04%'
GROUP BY OWNER;
SELECT OWNER, COUNT(*) AS MARKS FROM ALL_SOURCE
WHERE NAME='PKG_DMF0003' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%AUTHGROUP 2026-08-04%'
GROUP BY OWNER;

SELECT '[T1-c] PKG_DMF0003 SYNONYM (기대: SCMD_APP → SCM_MGR)' AS DESC1C FROM DUAL;
SELECT OWNER, TABLE_OWNER, TABLE_NAME FROM ALL_SYNONYMS WHERE SYNONYM_NAME = 'PKG_DMF0003';

SELECT '[T2] standalone 구본 SP 잔존 여부 (기대: 0행 — PROCEDURE 로 나오면 PKG 합류 전 구본 잔존)' AS DESC2 FROM DUAL;
SELECT OWNER, OBJECT_NAME, OBJECT_TYPE, STATUS
FROM ALL_OBJECTS
WHERE OBJECT_NAME LIKE 'P_DMF0003%' AND OBJECT_TYPE = 'PROCEDURE'
ORDER BY OWNER, OBJECT_NAME;

SELECT '[T2-b] API_M 배선 — SEARCH 가 가리키는 SP (기대: PKG_DMF0003.P_DMF0003_GET_MKT_FCST_DATA)' AS DESC2B FROM DUAL;
SELECT API_ID, API_URL FROM SCM_MGR.SCM_ADM_API_M
WHERE API_URL LIKE '%DMF0003%' OR API_ID LIKE '%DMF0003%'
ORDER BY API_ID;

SELECT '[T3] EXECUTE 권한 (BE 계정이 SCM_MGR 본을 실행 가능한가)' AS DESC3 FROM DUAL;
SELECT GRANTEE, PRIVILEGE FROM ALL_TAB_PRIVS
WHERE TABLE_NAME = 'PKG_DMF0003' AND TABLE_SCHEMA = 'SCM_MGR';

SELECT '=== 판독: T1/T1-b 에서 마커 0 인 타 OWNER PACKAGE 발견 → 그 복사본이 실행 실체(제거+SYNONYM). ===' AS FIN1 FROM DUAL;
SELECT '=== T2 에서 PROCEDURE 발견 + T2-b 가 standalone 지향 → API_M 재배선 또는 구본 SP 정리. ===' AS FIN2 FROM DUAL;
SELECT '=== 전부 정상인데도 N → T0 의 DB 정체가 BE datasource 와 다른지 확인(다른 PDB/인스턴스). ===' AS FIN3 FROM DUAL;
