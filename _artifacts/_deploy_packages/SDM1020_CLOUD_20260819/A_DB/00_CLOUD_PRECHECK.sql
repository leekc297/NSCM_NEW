-- 이관 범위 기준(사용자 확정 2026-08-19): 무수정 객체(TABLE DDL·PKG SPEC)는 동봉하지 않음 —
--   클라우드 기생성 전제. 본 파일이 그 실존을 확인한다. 부재 시 즉시 중단·회신(임의 생성 금지).
