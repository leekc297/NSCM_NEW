-- [P1] PKG_SDM1020 SPEC 실존 + VALID (⚠ BODY 만 이관 — SPEC 부재 시 01 실행 금지·회신)
--      기대: PACKAGE 1행 VALID. (BODY 는 01 적용 전 부재/INVALID 여도 무방)
SELECT OBJECT_TYPE, STATUS FROM ALL_OBJECTS
 WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_SDM1020' AND OBJECT_TYPE='PACKAGE';

-- [P2] 원장 테이블 실존 + 컬럼수 (무수정 객체 — 사내 실측: MST 37 / USER_MAP 22)
--      기대: 2행 — SPMS_PROJECT_MST=37 / SPMS_PROJECT_USER_MAP=22 (불일치 = 세대 상이 -> 회신)
SELECT TABLE_NAME, COUNT(*) COLS FROM ALL_TAB_COLUMNS
 WHERE OWNER='SCM_MGR' AND TABLE_NAME IN ('SPMS_PROJECT_MST','SPMS_PROJECT_USER_MAP')
 GROUP BY TABLE_NAME ORDER BY 1;

-- [P3] 상위 메뉴 + 권한그룹 (SDM1010 패키지 기동봉분 — 본 패키지는 화면분만)
--      기대: MNU 2행(SDM/SDM_Project) / 그룹 3행(ADMIN/SPMS Administrator/SPMS Planner)
SELECT MNU_ID, UPPR_MNU_ID, USE_YN FROM SCM_MGR.SCM_ADM_MNU_M WHERE MNU_ID IN ('SDM','SDM_Project');
SELECT USER_GR_ID FROM SCM_MGR.SCM_ADM_USER_GR_M
 WHERE USER_GR_ID IN ('ADMIN','SPMS Administrator','SPMS Planner') ORDER BY 1;

-- [P4] 공유 SP PR_GET_DAY_RANGE 실존(VALID) + PROC_M 기등재 5행 (period 시트 배선 전제)
--      기대: 1행 VALID / PROC_M 5행 (createdBy/month/o_rc1/o_rc2/o_result_cursor)
SELECT OBJECT_TYPE, STATUS FROM ALL_OBJECTS
 WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PR_GET_DAY_RANGE' AND OBJECT_TYPE='PROCEDURE';
SELECT COUNT(*) PROC_DAY_RANGE_EXPECT_5 FROM SCM_MGR.SCM_ADM_PROC_M WHERE PROC_NM='PR_GET_DAY_RANGE';

-- [P5] LOOKUP 선행 상태 (SDM1010_CLOUD_20260813/sql/05_LOOKUP_COMBO.sql 기적용 전제)
--      기대: ① MASTER 2행 ② REG_STATUS 기본 5코드(DRAFT/WRITING/WAITING/COMPLETE/REJECT) 부재 0행
--            ③ REG_CAT 'NEW' 1행 ④ SPMS_CELL_STACK_METHOD 상세 > 0행 (사내 6행)
SELECT LOOKUP_TYPE FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER
 WHERE LOOKUP_TYPE IN ('SPMS_DPJT_REG_STATUS','SPMS_DPJT_REG_CAT') ORDER BY 1;
SELECT COLUMN_VALUE MISSING_BASE_CODE FROM TABLE(SYS.ODCIVARCHAR2LIST('DRAFT','WRITING','WAITING','COMPLETE','REJECT'))
MINUS
SELECT SEGMENT1 FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE='SPMS_DPJT_REG_STATUS' AND VALID_YN='Y';
SELECT COUNT(*) REG_CAT_NEW_EXPECT_1 FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE='SPMS_DPJT_REG_CAT' AND SEGMENT1='NEW' AND VALID_YN='Y';
SELECT COUNT(*) CELL_STACK_DETAIL_EXPECT_GT0 FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE='SPMS_CELL_STACK_METHOD' AND VALID_YN='Y';

-- [P6] 기존 공용 콤보 7종 기존재 (본 패키지 미동봉 — 부재 시 회신. 공유 콤보 임의 수정/신설 금지)
--      기대: 부재 0행
SELECT COLUMN_VALUE MISSING_COMBO FROM TABLE(SYS.ODCIVARCHAR2LIST(
  'Division','DpjtClass','EndCustomerByDivisionDept','CellTypeByDivision',
  'BizTypeByDivision','PlantByDivisionCompany','EndCustomerByDivision'))
MINUS
SELECT SQL_ID FROM SCM_MGR.SCM_ADM_CMBO_SQL_M WHERE USE_YN='Y';

-- [P7] 신규 MSG 채번 충돌 가드 (MSG00704->MSG01001 재채번 사고 계보)
--      기대: 0행. 행이 나오면 그 코드가 클라우드에서 선점된 것 —
--            문구가 04 파일과 동일하면 무해(멱등 skip), 다르면 ⛔ 중단 -> 재채번 회신.
SELECT MSG_ID, LANG_CD, MSG_NM FROM SCM_MGR.SCM_ADM_MSG_M
 WHERE MSG_ID IN ('MSG01002','MSG01003','MSG01004','MSG01005','MSG01006','MSG01007','MNU_SDM1020')
    OR MSG_ID LIKE 'MSG_API_SDM1020%';

-- [P8] 재사용 MSG/LBL 기존재 확인 (이관 제외분 — 부재 코드 발견 시 회신, 임의 INSERT 금지)
--      기대: 부재 0행 (17코드 x 3언어 = 51행 전부 기존재)
SELECT M.MI || '/' || L.LC MISSING_REUSE_CODE
  FROM (SELECT COLUMN_VALUE MI FROM TABLE(SYS.ODCIVARCHAR2LIST(
          'LBL00001','LBL00643','LBL00855','LBL00856','LBL00857','LBL00859',
          'MSG00097','MSG00108','MSG00004','MSG00709','MSG00710','MSG00711','MSG00712',
          'MSG00716','MSG00717','MSG00002','MSG00003'))) M
 CROSS JOIN (SELECT 'KO' LC FROM DUAL UNION ALL SELECT 'EN' FROM DUAL UNION ALL SELECT 'CN' FROM DUAL) L
 WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_MSG_M X WHERE X.MSG_ID = M.MI AND X.LANG_CD = L.LC);

-- [P9] 재이관 여부 확인 (기존 SDM1020 흔적 — 있으면 03 이 대상 한정 DELETE 후 재적재하므로 무해, 기록만)
SELECT 'MNU' AXIS, COUNT(*) CNT FROM SCM_MGR.SCM_ADM_MNU_M WHERE MNU_ID='SDM1020'
UNION ALL SELECT 'SHEET', COUNT(*) FROM SCM_MGR.SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID='SDM1020'
UNION ALL SELECT 'PROC', COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M WHERE PROC_NM LIKE 'PKG_SDM1020.%'
UNION ALL SELECT 'API', COUNT(*) FROM SCM_MGR.SCM_ADM_API_M WHERE API_ID LIKE 'SDM1020%';
