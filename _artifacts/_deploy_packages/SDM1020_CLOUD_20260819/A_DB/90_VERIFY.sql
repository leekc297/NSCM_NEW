-- [V1] PKG 상태 — 기대: PACKAGE=VALID / PACKAGE BODY=VALID (2행 모두 VALID — spec 조용한 실패 계보)
SELECT OBJECT_TYPE, STATUS FROM ALL_OBJECTS
 WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_SDM1020' ORDER BY OBJECT_TYPE;

-- [V2] 정정 마커 2종 실측 — 기대: D3=1 / D12=1 (BODY 내 각 1행)
SELECT 'E20260819-D3' MARKER, COUNT(*) EXPECT_1 FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_SDM1020' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%[E20260819-D3]%'
UNION ALL
SELECT 'E20260819-D12', COUNT(*) FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_SDM1020' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%[E20260819-D12]%';

-- [V3] GRANT + 시노님 — 기대: EXECUTE grantee 에 앱계정(SCMP_APP 또는 환경별 SCMD_APP) / 시노님 1행
SELECT GRANTEE, PRIVILEGE FROM DBA_TAB_PRIVS WHERE OWNER='SCM_MGR' AND TABLE_NAME='PKG_SDM1020';
SELECT OWNER, SYNONYM_NAME, TABLE_OWNER FROM ALL_SYNONYMS WHERE TABLE_NAME='PKG_SDM1020';

-- [V4] 메타 축별 카운트 — 기대(사내 실측): MNU 1 / SHEET 30 / PROC 29 / API 7 / BTN 7 / UGR_MNU 3 / UGR_BTN 21 / CMBO 1
SELECT 'MNU_M' AXIS, COUNT(*) CNT, 1 EXPECT FROM SCM_MGR.SCM_ADM_MNU_M WHERE MNU_ID='SDM1020'
UNION ALL SELECT 'SHEET_COLUMNS', COUNT(*), 30 FROM SCM_MGR.SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID='SDM1020' AND SHEET_NAME='Project List'
UNION ALL SELECT 'PROC_M', COUNT(*), 29 FROM SCM_MGR.SCM_ADM_PROC_M WHERE PROC_NM IN ('PKG_SDM1020.P_SDM1020_GET_PJT_LIST','PKG_SDM1020.P_SDM1020_BTN_REQ_PJT_REG','PKG_SDM1020.P_SDM1020_REQ_PJT_AUTH')
UNION ALL SELECT 'API_M', COUNT(*), 7 FROM SCM_MGR.SCM_ADM_API_M WHERE API_ID IN ('SDM1020_main_SEARCH','SDM1020_main_EXCEL','SDM1020_main_FILTER','SDM1020_main_SORT','SDM1020_main_REQ','SDM1020_main_AUTHREQ','SDM1020_period_SEARCH')
UNION ALL SELECT 'MNU_BTN', COUNT(*), 7 FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID='SDM1020'
UNION ALL SELECT 'UGR_MNU', COUNT(*), 3 FROM SCM_MGR.SCM_ADM_USER_GR_MNU_MPG_M WHERE MNU_ID='SDM1020'
UNION ALL SELECT 'UGR_BTN', COUNT(*), 21 FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE MNU_ID='SDM1020'
UNION ALL SELECT 'CMBO', COUNT(*), 1 FROM SCM_MGR.SCM_ADM_CMBO_SQL_M WHERE SQL_ID='StackMethodByCellType';

-- [V5] SHEET_COLUMNS 정정 반영 검증 — 기대: DEFAULT 'Y' 26 / VISIBLE 'Y' 23 / DIVISION_ID 한정 10
SELECT SUM(CASE WHEN DEFAULT_FLAG='Y' THEN 1 END) DF_Y_EXPECT_26,
       SUM(CASE WHEN VISIBLE_FLAG='Y' THEN 1 END) VI_Y_EXPECT_23,
       SUM(CASE WHEN DIVISION_ID IS NOT NULL THEN 1 END) DIV_SET_EXPECT_10
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID='SDM1020' AND SHEET_NAME='Project List';

-- [V6] PROC_M = ALL_ARGUMENTS positional 대조 — 기대: 3 SP 모두 PROC=ARGS (9/15/5)
SELECT P.PROC_NM, P.CNT PROC_M_CNT, A.CNT ALL_ARGS_CNT
  FROM (SELECT PROC_NM, COUNT(*) CNT FROM SCM_MGR.SCM_ADM_PROC_M
         WHERE PROC_NM LIKE 'PKG_SDM1020.%' GROUP BY PROC_NM) P
  LEFT JOIN (SELECT 'PKG_SDM1020.'||OBJECT_NAME PROC_NM, COUNT(*) CNT FROM ALL_ARGUMENTS
              WHERE OWNER='SCM_MGR' AND PACKAGE_NAME='PKG_SDM1020' GROUP BY OBJECT_NAME) A
    ON A.PROC_NM = P.PROC_NM
 ORDER BY 1;

-- [V7] MSG 신규분 — 기대: MNU_SDM1020=3 / MSG01002~01007=18 / MSG_API_SDM1020_*=21 (합 42)
SELECT 'MNU_SDM1020' GRP, COUNT(*) CNT, 3 EXPECT FROM SCM_MGR.SCM_ADM_MSG_M WHERE MSG_ID='MNU_SDM1020'
UNION ALL SELECT 'MSG01002~7', COUNT(*), 18 FROM SCM_MGR.SCM_ADM_MSG_M WHERE MSG_ID IN ('MSG01002','MSG01003','MSG01004','MSG01005','MSG01006','MSG01007')
UNION ALL SELECT 'MSG_API', COUNT(*), 21 FROM SCM_MGR.SCM_ADM_MSG_M WHERE MSG_ID LIKE 'MSG_API_SDM1020%';

-- [V8] LOOKUP — 기대: REG_STATUS VALID 'Y' = 10행(확정 9항목 — 작성중 DRAFT/WRITING 2코드) /
--      REG_CAT VALID 'Y' = 2행(NEW/MOD) / SP 계약코드 결측 0행
SELECT 'REG_STATUS_Y' GRP, COUNT(*) CNT, 10 EXPECT FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE='SPMS_DPJT_REG_STATUS' AND VALID_YN='Y'
UNION ALL SELECT 'REG_CAT_Y', COUNT(*), 2 FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE='SPMS_DPJT_REG_CAT' AND VALID_YN='Y';
SELECT COLUMN_VALUE MISSING_SP_CONTRACT_CODE FROM TABLE(SYS.ODCIVARCHAR2LIST('DRAFT','WRITING','WAITING','COMPLETE','REJECT','REQ_MOD','MODIFYING'))
MINUS
SELECT SEGMENT1 FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE='SPMS_DPJT_REG_STATUS' AND VALID_YN='Y';

-- [V9] CMBO 원문 길이 — 기대: 338 (사내 SQL_DTL_CTN 실측 — 원문 변형 감지)
SELECT SQL_ID, LENGTH(SQL_DTL_CTN) LEN_EXPECT_338, MDU_DIVS_CD, USE_YN
  FROM SCM_MGR.SCM_ADM_CMBO_SQL_M WHERE SQL_ID='StackMethodByCellType';

-- [V10] ROUTE_PATH — 99 실행 전 기대: NULL / 99(FE 배포 후) 실행 후 기대: 'sdm/project-list'
SELECT MNU_ID, ROUTE_PATH FROM SCM_MGR.SCM_ADM_MNU_M WHERE MNU_ID='SDM1020';
