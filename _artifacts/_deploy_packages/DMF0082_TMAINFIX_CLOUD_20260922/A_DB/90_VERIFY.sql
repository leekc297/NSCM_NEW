DELETE FROM SCM_MGR.GT_PRDM1_T_MAIN;

INSERT INTO SCM_MGR.GT_PRDM1_T_MAIN
     ( ACTION, DIVISION_ID, PROJECT_CODE, END_CUSTOMER, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, MEASURE
     , PLANT_SITE_ID, CELL_PROD_SITE_ID, YYYYMMDD, QTY_PRICE, CREATED_BY )
SELECT 'U', DIVISION_ID, PROJECT_CODE, END_CUSTOMER, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, MEASURE
     , PLANT_SITE_ID, CELL_PROD_SITE_ID, YYYYMMDD, QTY, 'verify'
  FROM (SELECT A.*, ROW_NUMBER() OVER (PARTITION BY MEASURE ORDER BY YYYYMMDD, ITEM_ID) RN
          FROM SCM_MGR.DM_PLN_CFM_MKT_DEMAND_PLAN A
         WHERE DIVISION_ID = '40' AND MEASURE IN ('MKT_FCST','SCM_FCST')
           AND YYYYMMDD >= TO_CHAR(SCM_MGR.FN_NEXT_DAY(SYSDATE,'MON') - 7, 'YYYYMMDD'))
 WHERE RN <= 20;

INSERT INTO SCM_MGR.GT_PRDM1_T_MAIN
     ( ACTION, DIVISION_ID, PROJECT_CODE, END_CUSTOMER, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, MEASURE
     , PLANT_SITE_ID, CELL_PROD_SITE_ID, YYYYMMDD, QTY_PRICE, CREATED_BY )
SELECT ACTION, DIVISION_ID, PROJECT_CODE, END_CUSTOMER, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, 'VMI_In_Req'
     , PLANT_SITE_ID, CELL_PROD_SITE_ID, YYYYMMDD, QTY_PRICE, 'verify-mock'
  FROM SCM_MGR.GT_PRDM1_T_MAIN WHERE MEASURE = 'MKT_FCST' AND ROWNUM <= 5;

SELECT GT1_LOADED, PR_PICK, VMI_MOCK, VMI_NEW, VMI_OLD
     , CASE WHEN GT1_LOADED = 0 THEN '판정 불가(40 당주 이후 원장 0행)'
            WHEN PR_PICK = GT1_LOADED AND VMI_NEW = VMI_MOCK AND VMI_MOCK > 0 AND VMI_OLD = 0 THEN 'PASS'
            ELSE '*** FAIL ***' END AS VERDICT
  FROM (SELECT COUNT(*) AS GT1_LOADED
             , SUM(CASE WHEN DIVISION_ID = '40' AND MEASURE IN ('MKT_FCST','SCM_FCST','VMI_In_Req') THEN 1 ELSE 0 END) AS PR_PICK
             , SUM(CASE WHEN CREATED_BY = 'verify-mock' THEN 1 ELSE 0 END) AS VMI_MOCK
             , SUM(CASE WHEN MEASURE IN ('VMI_In_Req') THEN 1 ELSE 0 END) AS VMI_NEW
             , SUM(CASE WHEN MEASURE IN ('VMI_IN_REQ') THEN 1 ELSE 0 END) AS VMI_OLD
          FROM SCM_MGR.GT_PRDM1_T_MAIN);

ROLLBACK;
