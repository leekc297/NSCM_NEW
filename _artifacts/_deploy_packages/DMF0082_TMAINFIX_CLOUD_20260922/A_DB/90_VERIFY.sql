PROMPT [V6] 비파괴 dry-run — PR 추출 쿼리가 GT_PRDM1_T_MAIN 의 40 행을 받는지 (세션 GTT, ROLLBACK)
PROMPT      EXPECT: GT1_LOADED > 0 이면 PR_PICK = GT1_LOADED, VMI_NEW = VMI_MOCK(>0), VMI_OLD = 0 -> PASS
PROMPT      (40 원장에 당주 이후 행이 없으면 GT1_LOADED=0 -> 판정 불가 표기)
