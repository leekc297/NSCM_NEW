PROMPT [V3] 정정 마커 / 잔존 단언        EXPECT: TMAINFIX=10, OLD_GTT=0, OLD_VMI=0, NEW_GTT_IN_PR=5, NEW_VMI_IN_PR=4 -> PASS
PROMPT ------------------------------------------------------------
WITH S AS (SELECT LINE, TEXT FROM USER_SOURCE WHERE NAME = 'PKG_DMF0082' AND TYPE = 'PACKAGE BODY')
   , R AS (SELECT MIN(CASE WHEN TEXT LIKE 'PROCEDURE P_PR_DM_PLN_CFM_TO_MKT_FCST%' THEN LINE END) AS LO
                , MIN(CASE WHEN TEXT LIKE 'END P_PR_DM_PLN_CFM_TO_MKT_FCST;%'     THEN LINE END) AS HI FROM S)
SELECT TMAINFIX, OLD_GTT, OLD_VMI, NEW_GTT_IN_PR, NEW_VMI_IN_PR
     , CASE WHEN TMAINFIX = 10 AND OLD_GTT = 0 AND OLD_VMI = 0 AND NEW_GTT_IN_PR = 5 AND NEW_VMI_IN_PR = 4
            THEN 'PASS' ELSE '*** FAIL ***' END AS VERDICT
  FROM (SELECT SUM(CASE WHEN S.TEXT LIKE '%E20260922-TMAINFIX%' THEN 1 ELSE 0 END) AS TMAINFIX
             , SUM(CASE WHEN S.TEXT LIKE '%SCM_MGR.GT_PRDM_T_MAIN%' THEN 1 ELSE 0 END) AS OLD_GTT
             , SUM(CASE WHEN S.LINE BETWEEN R.LO AND R.HI AND S.TEXT LIKE '%''VMI_IN_REQ''%'
                         AND S.TEXT NOT LIKE '%''VMI_IN_REQ''->%' THEN 1 ELSE 0 END) AS OLD_VMI
             , SUM(CASE WHEN S.LINE BETWEEN R.LO AND R.HI AND S.TEXT LIKE '%GT_PRDM1_T_MAIN%' AND S.TEXT LIKE '%TMAINFIX%' THEN 1 ELSE 0 END) AS NEW_GTT_IN_PR
             , SUM(CASE WHEN S.LINE BETWEEN R.LO AND R.HI AND S.TEXT LIKE '%''VMI_In_Req''%'  AND S.TEXT LIKE '%TMAINFIX%' THEN 1 ELSE 0 END) AS NEW_VMI_IN_PR
          FROM S CROSS JOIN R);

