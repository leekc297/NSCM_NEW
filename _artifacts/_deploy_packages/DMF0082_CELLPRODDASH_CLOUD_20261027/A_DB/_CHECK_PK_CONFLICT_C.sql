-- _CHECK_PK_CONFLICT_C — 30 에서 PK 충돌로 건너뛴 _C 2개 테이블 점검 (클라우드 · SCM_MGR · 조회 전용 · 전체 F5 · 값 입력 없음)
-- 충돌 = CELL_PROD_SITE_ID '/'(또는 공백) 행과, 그 행을 '-' 로 바꾸면 PK 가 같아지는 '-' 행이 이미 있는 경우 (같은 키 2행)
-- 대상: DM_PLN_MKT_FCST_RESULT_C · DM_PLN_SALES_PLAN_RESULT_C
-- 보는 법
--   K0 클라우드 실제 PK 컬럼 (아래 쿼리의 조인 키와 같아야 한다 — 다르면 회신)
--   K1 테이블별 '/' 행 수 · 그중 충돌 · 충돌 없음(30 이 바꿀 수 있는 행)
--   K2 충돌 분포 — 사업부 · 컷오프 유형 · 메저별 건수 · 컷오프 기간 (어느 적재가 만들었는지)
--   K3 충돌 쌍 값 비교 — QTY 같음/다름 · 어느 쪽이 최근 수정 · QTY 합계 (처리 방식 판단: 삭제 / 합산 / 최신 유지)
--   K4 충돌 '/' 행을 만든 주체 — CREATED_BY · LAST_UPDATED_BY · 생성일 범위
--   K5 충돌 쌍 표본 20건 (양쪽 나란히)
--   K6 최신 컷오프(사업부·유형별 MAX)에 충돌이 있는지 — 화면 조회에 영향 주는 범위
SET LINESIZE 250 PAGESIZE 500
SET DEFINE OFF

-- K0 PK
SELECT 'K0 PK' CHK, C.TABLE_NAME, LISTAGG(CC.COLUMN_NAME, ',') WITHIN GROUP (ORDER BY CC.POSITION) PK_COLUMNS
  FROM USER_CONSTRAINTS C JOIN USER_CONS_COLUMNS CC ON CC.CONSTRAINT_NAME = C.CONSTRAINT_NAME
 WHERE C.TABLE_NAME IN ('DM_PLN_MKT_FCST_RESULT_C', 'DM_PLN_SALES_PLAN_RESULT_C') AND C.CONSTRAINT_TYPE = 'P'
 GROUP BY C.TABLE_NAME ORDER BY 2;

-- ============================== DM_PLN_MKT_FCST_RESULT_C ==============================
-- 조인 키 (사내 PK 기준): DIVISION_ID, VERSION_NO, CUTOFF_TYPE, CUTOFF_YYYYMMDD, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, DOM_EXP, FCST_TYPE, INCOTERMS, MEASURE, PLANT_SITE_ID, YYYYMMDD
-- K1
SELECT 'K1 MFR_C' CHK
     , COUNT(*) SLASH_ROWS
     , SUM(CASE WHEN B.ROWID IS NOT NULL THEN 1 ELSE 0 END) CONFLICT_ROWS
     , SUM(CASE WHEN B.ROWID IS NULL THEN 1 ELSE 0 END) NO_CONFLICT_ROWS
  FROM SCM_MGR.DM_PLN_MKT_FCST_RESULT_C A
  LEFT JOIN SCM_MGR.DM_PLN_MKT_FCST_RESULT_C B
    ON B.CELL_PROD_SITE_ID = '-' AND B.DIVISION_ID = A.DIVISION_ID AND B.VERSION_NO = A.VERSION_NO AND B.CUTOFF_TYPE = A.CUTOFF_TYPE AND B.CUTOFF_YYYYMMDD = A.CUTOFF_YYYYMMDD
   AND B.PROJECT_CODE = A.PROJECT_CODE AND B.SCM_SITE_ID = A.SCM_SITE_ID AND B.ITEM_ID = A.ITEM_ID AND B.DOM_EXP = A.DOM_EXP AND B.FCST_TYPE = A.FCST_TYPE
   AND B.INCOTERMS = A.INCOTERMS AND B.MEASURE = A.MEASURE AND B.PLANT_SITE_ID = A.PLANT_SITE_ID AND B.YYYYMMDD = A.YYYYMMDD
 WHERE A.CELL_PROD_SITE_ID = '/' OR (A.CELL_PROD_SITE_ID IS NOT NULL AND TRIM(A.CELL_PROD_SITE_ID) IS NULL);
-- K2
SELECT 'K2 MFR_C' CHK, A.DIVISION_ID, A.CUTOFF_TYPE, A.MEASURE, COUNT(*) CONFLICTS
     , MIN(A.CUTOFF_YYYYMMDD) CUTOFF_FROM, MAX(A.CUTOFF_YYYYMMDD) CUTOFF_TO, COUNT(DISTINCT A.VERSION_NO) VERSIONS
     , MIN(A.YYYYMMDD) YMD_FROM, MAX(A.YYYYMMDD) YMD_TO
  FROM SCM_MGR.DM_PLN_MKT_FCST_RESULT_C A
  JOIN SCM_MGR.DM_PLN_MKT_FCST_RESULT_C B
    ON B.CELL_PROD_SITE_ID = '-' AND B.DIVISION_ID = A.DIVISION_ID AND B.VERSION_NO = A.VERSION_NO AND B.CUTOFF_TYPE = A.CUTOFF_TYPE AND B.CUTOFF_YYYYMMDD = A.CUTOFF_YYYYMMDD
   AND B.PROJECT_CODE = A.PROJECT_CODE AND B.SCM_SITE_ID = A.SCM_SITE_ID AND B.ITEM_ID = A.ITEM_ID AND B.DOM_EXP = A.DOM_EXP AND B.FCST_TYPE = A.FCST_TYPE
   AND B.INCOTERMS = A.INCOTERMS AND B.MEASURE = A.MEASURE AND B.PLANT_SITE_ID = A.PLANT_SITE_ID AND B.YYYYMMDD = A.YYYYMMDD
 WHERE A.CELL_PROD_SITE_ID = '/' OR (A.CELL_PROD_SITE_ID IS NOT NULL AND TRIM(A.CELL_PROD_SITE_ID) IS NULL)
 GROUP BY A.DIVISION_ID, A.CUTOFF_TYPE, A.MEASURE ORDER BY 2, 3, 4;
-- K3
SELECT 'K3 MFR_C' CHK, COUNT(*) PAIRS
     , SUM(CASE WHEN NVL(A.QTY, 0) = NVL(B.QTY, 0) THEN 1 ELSE 0 END) SAME_QTY
     , SUM(CASE WHEN NVL(A.QTY, 0) <> NVL(B.QTY, 0) THEN 1 ELSE 0 END) DIFF_QTY
     , SUM(CASE WHEN NVL(A.QTY, 0) <> 0 AND NVL(B.QTY, 0) = 0 THEN 1 ELSE 0 END) SLASH_ONLY_NONZERO
     , SUM(CASE WHEN NVL(A.QTY, 0) = 0 AND NVL(B.QTY, 0) <> 0 THEN 1 ELSE 0 END) DASH_ONLY_NONZERO
     , SUM(CASE WHEN A.LAST_UPDATE_DATE > B.LAST_UPDATE_DATE THEN 1 ELSE 0 END) SLASH_NEWER
     , SUM(CASE WHEN A.LAST_UPDATE_DATE < B.LAST_UPDATE_DATE THEN 1 ELSE 0 END) DASH_NEWER
     , SUM(A.QTY) SLASH_QTY_SUM, SUM(B.QTY) DASH_QTY_SUM
  FROM SCM_MGR.DM_PLN_MKT_FCST_RESULT_C A
  JOIN SCM_MGR.DM_PLN_MKT_FCST_RESULT_C B
    ON B.CELL_PROD_SITE_ID = '-' AND B.DIVISION_ID = A.DIVISION_ID AND B.VERSION_NO = A.VERSION_NO AND B.CUTOFF_TYPE = A.CUTOFF_TYPE AND B.CUTOFF_YYYYMMDD = A.CUTOFF_YYYYMMDD
   AND B.PROJECT_CODE = A.PROJECT_CODE AND B.SCM_SITE_ID = A.SCM_SITE_ID AND B.ITEM_ID = A.ITEM_ID AND B.DOM_EXP = A.DOM_EXP AND B.FCST_TYPE = A.FCST_TYPE
   AND B.INCOTERMS = A.INCOTERMS AND B.MEASURE = A.MEASURE AND B.PLANT_SITE_ID = A.PLANT_SITE_ID AND B.YYYYMMDD = A.YYYYMMDD
 WHERE A.CELL_PROD_SITE_ID = '/' OR (A.CELL_PROD_SITE_ID IS NOT NULL AND TRIM(A.CELL_PROD_SITE_ID) IS NULL);
-- K4
SELECT 'K4 MFR_C' CHK, SIDE, CREATED_BY, LAST_UPDATED_BY, COUNT(*) N
     , TO_CHAR(MIN(CREATION_DATE), 'YYYY-MM-DD HH24:MI') CREATED_FROM, TO_CHAR(MAX(CREATION_DATE), 'YYYY-MM-DD HH24:MI') CREATED_TO
  FROM ( SELECT 'SLASH' SIDE, A.CREATED_BY, A.LAST_UPDATED_BY, A.CREATION_DATE
           FROM SCM_MGR.DM_PLN_MKT_FCST_RESULT_C A
           JOIN SCM_MGR.DM_PLN_MKT_FCST_RESULT_C B
             ON B.CELL_PROD_SITE_ID = '-' AND B.DIVISION_ID = A.DIVISION_ID AND B.VERSION_NO = A.VERSION_NO AND B.CUTOFF_TYPE = A.CUTOFF_TYPE AND B.CUTOFF_YYYYMMDD = A.CUTOFF_YYYYMMDD
            AND B.PROJECT_CODE = A.PROJECT_CODE AND B.SCM_SITE_ID = A.SCM_SITE_ID AND B.ITEM_ID = A.ITEM_ID AND B.DOM_EXP = A.DOM_EXP AND B.FCST_TYPE = A.FCST_TYPE
            AND B.INCOTERMS = A.INCOTERMS AND B.MEASURE = A.MEASURE AND B.PLANT_SITE_ID = A.PLANT_SITE_ID AND B.YYYYMMDD = A.YYYYMMDD
          WHERE A.CELL_PROD_SITE_ID = '/' OR (A.CELL_PROD_SITE_ID IS NOT NULL AND TRIM(A.CELL_PROD_SITE_ID) IS NULL)
         UNION ALL
         SELECT 'DASH' SIDE, B.CREATED_BY, B.LAST_UPDATED_BY, B.CREATION_DATE
           FROM SCM_MGR.DM_PLN_MKT_FCST_RESULT_C A
           JOIN SCM_MGR.DM_PLN_MKT_FCST_RESULT_C B
             ON B.CELL_PROD_SITE_ID = '-' AND B.DIVISION_ID = A.DIVISION_ID AND B.VERSION_NO = A.VERSION_NO AND B.CUTOFF_TYPE = A.CUTOFF_TYPE AND B.CUTOFF_YYYYMMDD = A.CUTOFF_YYYYMMDD
            AND B.PROJECT_CODE = A.PROJECT_CODE AND B.SCM_SITE_ID = A.SCM_SITE_ID AND B.ITEM_ID = A.ITEM_ID AND B.DOM_EXP = A.DOM_EXP AND B.FCST_TYPE = A.FCST_TYPE
            AND B.INCOTERMS = A.INCOTERMS AND B.MEASURE = A.MEASURE AND B.PLANT_SITE_ID = A.PLANT_SITE_ID AND B.YYYYMMDD = A.YYYYMMDD
          WHERE A.CELL_PROD_SITE_ID = '/' OR (A.CELL_PROD_SITE_ID IS NOT NULL AND TRIM(A.CELL_PROD_SITE_ID) IS NULL) )
 GROUP BY SIDE, CREATED_BY, LAST_UPDATED_BY ORDER BY 2, 5 DESC FETCH FIRST 40 ROWS ONLY;
-- K5
SELECT 'K5 MFR_C' CHK, A.DIVISION_ID, A.VERSION_NO, A.CUTOFF_TYPE, A.CUTOFF_YYYYMMDD, A.SCM_SITE_ID, A.ITEM_ID, A.MEASURE, A.PLANT_SITE_ID, A.YYYYMMDD
     , A.QTY SLASH_QTY, B.QTY DASH_QTY
     , A.CREATED_BY SLASH_BY, TO_CHAR(A.LAST_UPDATE_DATE, 'YYYY-MM-DD HH24:MI') SLASH_UPD
     , B.CREATED_BY DASH_BY, TO_CHAR(B.LAST_UPDATE_DATE, 'YYYY-MM-DD HH24:MI') DASH_UPD
  FROM SCM_MGR.DM_PLN_MKT_FCST_RESULT_C A
  JOIN SCM_MGR.DM_PLN_MKT_FCST_RESULT_C B
    ON B.CELL_PROD_SITE_ID = '-' AND B.DIVISION_ID = A.DIVISION_ID AND B.VERSION_NO = A.VERSION_NO AND B.CUTOFF_TYPE = A.CUTOFF_TYPE AND B.CUTOFF_YYYYMMDD = A.CUTOFF_YYYYMMDD
