   AND B.INCOTERMS = A.INCOTERMS AND B.MEASURE = A.MEASURE AND B.PLANT_SITE_ID = A.PLANT_SITE_ID AND B.YYYYMMDD = A.YYYYMMDD
 WHERE A.CELL_PROD_SITE_ID = '/' OR (A.CELL_PROD_SITE_ID IS NOT NULL AND TRIM(A.CELL_PROD_SITE_ID) IS NULL)
 ORDER BY A.CUTOFF_YYYYMMDD DESC, A.DIVISION_ID, A.SCM_SITE_ID, A.ITEM_ID, A.YYYYMMDD FETCH FIRST 20 ROWS ONLY;
-- K6
SELECT 'K6 MFR_C' CHK, M.DIVISION_ID, M.CUTOFF_TYPE, M.MAX_CUTOFF
     , (SELECT COUNT(*) FROM SCM_MGR.DM_PLN_MKT_FCST_RESULT_C A
         WHERE A.DIVISION_ID = M.DIVISION_ID AND A.CUTOFF_TYPE = M.CUTOFF_TYPE AND A.CUTOFF_YYYYMMDD = M.MAX_CUTOFF
           AND (A.CELL_PROD_SITE_ID = '/' OR (A.CELL_PROD_SITE_ID IS NOT NULL AND TRIM(A.CELL_PROD_SITE_ID) IS NULL))) SLASH_ROWS_IN_LATEST
  FROM (SELECT DIVISION_ID, CUTOFF_TYPE, MAX(CUTOFF_YYYYMMDD) MAX_CUTOFF FROM SCM_MGR.DM_PLN_MKT_FCST_RESULT_C GROUP BY DIVISION_ID, CUTOFF_TYPE) M
 ORDER BY 2, 3;

