SELECT 'V1 마커' CHK, O.NAME, COUNT(*) N FROM (SELECT 'PKG_DMF0082' NAME, 'PACKAGE BODY' TYPE, 2 EXP FROM DUAL UNION ALL SELECT 'PR_DM_PLN_MKT_FCST_SALES_RESULT_MAPPING', 'PROCEDURE', 3 FROM DUAL) O
  LEFT JOIN USER_SOURCE S ON S.NAME = O.NAME AND S.TYPE = O.TYPE AND S.TEXT LIKE '%E20261027-CELLPRODDASH%' GROUP BY O.NAME ORDER BY 2;
SELECT 'V1 상태' CHK, OBJECT_NAME, OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL,
       (SELECT COUNT(*) FROM USER_ERRORS E WHERE E.NAME = O.OBJECT_NAME AND E.TYPE = O.OBJECT_TYPE) ERR
  FROM USER_OBJECTS O WHERE OBJECT_NAME IN ('PKG_DMF0082','PR_DM_PLN_MKT_FCST_SALES_RESULT_MAPPING') ORDER BY 2, 3;
DECLARE
    v_d VARCHAR2(4000); v_n NUMBER; v_slash NUMBER := 0;
BEGIN
    DBMS_OUTPUT.PUT_LINE('== V3 테이블별 CELL_PROD_SITE_ID DEFAULT · ''/''/공백 행 수');
    FOR t IN (SELECT C.TABLE_NAME, C.DEFAULT_ON_NULL FROM USER_TAB_COLUMNS C JOIN USER_TABLES T ON T.TABLE_NAME = C.TABLE_NAME AND T.TEMPORARY = 'N'
                   WHERE C.COLUMN_NAME = 'CELL_PROD_SITE_ID' AND NOT REGEXP_LIKE(C.TABLE_NAME, '(BAK|_SNAPSHOT|_TMP|_TEST|^CMP[0-9][$]|^ZZ_)') ORDER BY 1) LOOP
        SELECT DATA_DEFAULT INTO v_d FROM USER_TAB_COLUMNS WHERE TABLE_NAME = t.TABLE_NAME AND COLUMN_NAME = 'CELL_PROD_SITE_ID';
        EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM SCM_MGR.' || t.TABLE_NAME || ' WHERE CELL_PROD_SITE_ID = ''/'' OR (CELL_PROD_SITE_ID IS NOT NULL AND TRIM(CELL_PROD_SITE_ID) IS NULL)' INTO v_n;
        v_slash := v_slash + v_n;
        DBMS_OUTPUT.PUT_LINE('   ' || RPAD(t.TABLE_NAME, 36) || ' DEFAULT ' || RPAD(NVL(TRIM(v_d), '(없음)'), 6) || ' ON NULL ' || RPAD(t.DEFAULT_ON_NULL, 3) || ' · ''/''행 ' || TO_CHAR(v_n, 'FM999,999,999'));
    END LOOP;
    DBMS_OUTPUT.PUT_LINE('   합계 ''/''행 ' || TO_CHAR(v_slash, 'FM999,999,999'));
END;
