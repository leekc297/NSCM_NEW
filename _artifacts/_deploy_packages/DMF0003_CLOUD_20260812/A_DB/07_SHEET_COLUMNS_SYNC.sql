-- 07_SHEET_COLUMNS_SYNC.sql — 'Mkt Fcst' 0805 이후 변경 3행 현행값 (MERGE — DELETE 절대 금지 규약)

MERGE INTO SCM_MGR.SCM_MST_SHEET_COLUMNS T
USING (SELECT 'Mkt Fcst' AS SHEET_NAME, 'TEAM_ID' AS COLUMN_NAME FROM DUAL) S
ON (T.SHEET_NAME = S.SHEET_NAME AND T.COLUMN_NAME = S.COLUMN_NAME)
WHEN MATCHED THEN UPDATE SET DIVISION_ID = '40,82,81,81_UC,81_HM,81_ST,81_HD,81_HG', INPUT_TP_CD = 'IM',
     VISIBLE_FLAG = 'N', VALID_YN = 'Y',
     CELL_CONTROL_OBJECT_TYPE_CODE = 'FPComboBox', CELL_COMBO_DATA_TYPE = 'TeambyDivisionAuth',
     LAST_UPDATED_BY = 'admin', LAST_UPDATE_DATE = SYSDATE;
MERGE INTO SCM_MGR.SCM_MST_SHEET_COLUMNS T
USING (SELECT 'Mkt Fcst' AS SHEET_NAME, 'END_CUSTOMER' AS COLUMN_NAME FROM DUAL) S
ON (T.SHEET_NAME = S.SHEET_NAME AND T.COLUMN_NAME = S.COLUMN_NAME)
WHEN MATCHED THEN UPDATE SET DIVISION_ID = '82,81,81_UC,81_HM,81_ST,81_HD,81_HG', INPUT_TP_CD = 'IM',
     VISIBLE_FLAG = 'Y', VALID_YN = 'Y',
     CELL_CONTROL_OBJECT_TYPE_CODE = 'FPComboBox', CELL_COMBO_DATA_TYPE = 'EndCustomerByDivisionDeptAuth',
     LAST_UPDATED_BY = 'admin', LAST_UPDATE_DATE = SYSDATE;
MERGE INTO SCM_MGR.SCM_MST_SHEET_COLUMNS T
USING (SELECT 'Mkt Fcst' AS SHEET_NAME, 'END_CUSTOMER40' AS COLUMN_NAME FROM DUAL) S
ON (T.SHEET_NAME = S.SHEET_NAME AND T.COLUMN_NAME = S.COLUMN_NAME)
WHEN MATCHED THEN UPDATE SET DIVISION_ID = '40', INPUT_TP_CD = 'IM',
     VISIBLE_FLAG = 'Y', VALID_YN = 'Y',
     CELL_CONTROL_OBJECT_TYPE_CODE = 'FPComboBox', CELL_COMBO_DATA_TYPE = 'EndCustomerByDivision40Team',
     LAST_UPDATED_BY = 'admin', LAST_UPDATE_DATE = SYSDATE;
COMMIT;
