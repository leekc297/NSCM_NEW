-- 08_MSG00703.sql — 공통 재조회 확인 MSG (0811 신설 — locales 3본과 3점 동기)

MERGE INTO SCM_MGR.SCM_ADM_MSG_M T
USING (SELECT 'MSG00703' AS MSG_ID, 'CN' AS LANG_CD FROM DUAL) S
ON (T.MSG_ID = S.MSG_ID AND T.LANG_CD = S.LANG_CD)
WHEN MATCHED THEN UPDATE SET MSG_NM = '存在未保存的修改。要重新查询吗？', USE_YN = 'Y', LAST_UPDATED_BY = 'admin', LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (MSG_ID, LANG_CD, MSG_NM, MSG_TP_CD, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES ('MSG00703', 'CN', '存在未保存的修改。要重新查询吗？', 'MSG', 'Y', 'admin', SYSDATE, 'admin', SYSDATE);
