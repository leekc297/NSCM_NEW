SET DEFINE OFF
PROMPT [1] PKG 컴파일 (기대: PACKAGE/PACKAGE BODY 모두 VALID)
SELECT OBJECT_TYPE, STATUS FROM ALL_OBJECTS WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_DMF0003' ORDER BY 1;
PROMPT [2] AUTHGATE 이식 (기대: 1 이상)
SELECT COUNT(*) AS AUTHGATE_LINES FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0003' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%AUTHGATE%';
PROMPT [3] CMBO PlantSiteByItem (기대: 1행 USE_YN=Y)
SELECT SQL_ID, USE_YN FROM SCM_MGR.SCM_ADM_CMBO_SQL_M WHERE SQL_ID='PlantSiteByItem';
PROMPT [4] 82 편집 measure (기대: AS_In_Req / MKT_FCST_RP / VMI_In_Req 3행)
SELECT SEGMENT2 FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
 WHERE LOOKUP_TYPE='MKT_FCST_MEASURE' AND SEGMENT1='82' AND VALID_YN='Y' AND NVL(ATTRIBUTE2,'N') <> 'Y' ORDER BY 1;
PROMPT [5] PROC_M 커서 (기대: OUT 커서 o_rc*/O_RESULT_CURSOR 정정 반영)
SELECT PROC_NM, COL_NM, COL_TP_CD FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM LIKE '%DMF0003%' AND COL_NM IN ('o_rc1','o_rc2','o_rc3','O_RESULT_CURSOR','owner') ORDER BY 1, 2;
PROMPT [6] MSG00703 (기대: 3행)
SELECT LANG_CD, MSG_NM FROM SCM_MGR.SCM_ADM_MSG_M WHERE MSG_ID='MSG00703' ORDER BY 1;
