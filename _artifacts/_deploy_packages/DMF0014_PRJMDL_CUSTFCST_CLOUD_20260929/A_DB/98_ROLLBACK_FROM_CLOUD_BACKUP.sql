-- 98_ROLLBACK_FROM_CLOUD_BACKUP.sql — 05 에서 보관한 클라우드 고유 원문으로 재생성 (롤백 전용 · 평소 실행 안 함)
SET SERVEROUTPUT ON
DECLARE
  PROCEDURE rebuild(p_name VARCHAR2, p_type VARCHAR2) IS
    v CLOB;
  BEGIN
    DBMS_LOB.CREATETEMPORARY(v, TRUE);
    FOR r IN (SELECT TEXT FROM BAK_SRC_DMF0014_20260929 WHERE NAME=p_name AND TYPE=p_type ORDER BY LINE) LOOP
      DBMS_LOB.APPEND(v, r.TEXT);
    END LOOP;
    IF DBMS_LOB.GETLENGTH(v) > 0 THEN
      EXECUTE IMMEDIATE 'CREATE OR REPLACE ' || v;
      DBMS_OUTPUT.PUT_LINE('REBUILT ' || p_name);
    ELSE
      DBMS_OUTPUT.PUT_LINE('SKIP (no backup) ' || p_name);
    END IF;
  END;
BEGIN
  rebuild('PKG_DMF0014', 'PACKAGE BODY');
  rebuild('PR_DM_PLN_CUST_FCST_TO_MKT_FCST', 'PROCEDURE');
  rebuild('PR_DM_PLN_MKT_FCST_MAKE_CUST_FCST', 'PROCEDURE');
END;
/
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM USER_OBJECTS WHERE OBJECT_NAME IN ('PKG_DMF0014','PR_DM_PLN_CUST_FCST_TO_MKT_FCST','PR_DM_PLN_MKT_FCST_MAKE_CUST_FCST');
