-- 05_BACKUP_CLOUD_SOURCE.sql — 적용 직전 클라우드 원문을 테이블로 보관 (비파괴 · 멱등: 이미 있으면 SKIP)
-- 원복 시 98_ROLLBACK_FROM_CLOUD_BACKUP.sql 이 이 테이블로 클라우드 고유 원문을 재생성한다.
SET SERVEROUTPUT ON
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='BAK_SRC_DMF0014_20260929';
  IF n = 0 THEN
    EXECUTE IMMEDIATE q'[CREATE TABLE BAK_SRC_DMF0014_20260929 AS
      SELECT NAME, TYPE, LINE, TEXT, SYSDATE AS BAK_DATE FROM USER_SOURCE
       WHERE (NAME='PKG_DMF0014' AND TYPE='PACKAGE BODY') OR (NAME IN ('PR_DM_PLN_CUST_FCST_TO_MKT_FCST','PR_DM_PLN_MKT_FCST_MAKE_CUST_FCST') AND TYPE='PROCEDURE')]';
    DBMS_OUTPUT.PUT_LINE('BACKUP CREATED');
  ELSE
    -- rev2: 1차 적용 때 이미 만든 테이블이면 아직 백업 안 된 객체(MAKE_CUST_FCST)만 추가 — 기존 백업 행은 건드리지 않음
    EXECUTE IMMEDIATE q'[INSERT INTO BAK_SRC_DMF0014_20260929 (NAME, TYPE, LINE, TEXT, BAK_DATE)
      SELECT S.NAME, S.TYPE, S.LINE, S.TEXT, SYSDATE FROM USER_SOURCE S
       WHERE ((S.NAME='PKG_DMF0014' AND S.TYPE='PACKAGE BODY') OR (S.NAME IN ('PR_DM_PLN_CUST_FCST_TO_MKT_FCST','PR_DM_PLN_MKT_FCST_MAKE_CUST_FCST') AND S.TYPE='PROCEDURE'))
         AND NOT EXISTS (SELECT 1 FROM BAK_SRC_DMF0014_20260929 B WHERE B.NAME=S.NAME AND B.TYPE=S.TYPE)]';
    DBMS_OUTPUT.PUT_LINE('TABLE EXISTS — added rows for missing objects: ' || SQL%ROWCOUNT);
    COMMIT;
  END IF;
END;
/
SELECT NAME, TYPE, COUNT(*) LINES FROM BAK_SRC_DMF0014_20260929 GROUP BY NAME, TYPE;
