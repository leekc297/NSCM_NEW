-- 증상: 1차(10·11) 적용 후 Customer FCST Excel Upload [OK] 저장했는데 CUST_FCST 메저가 생성되지 않음
-- 실행: SCM_MGR 로 **QA · DEV 각각** 실행 (클라우드 DB 2곳 — 화면 BE 가 붙는 쪽 확인이 [D0])
-- 예상 원인: PR_DM_PLN_MKT_FCST_MAKE_CUST_FCST 원천 조회가 MEASURE IN ('Customer Fcst', ...) (대소문자 구분)
--            ↔ 업로드 반영분 MEASURE = 'Customer FCST' → Excel 분 전부 누락 → 12 (rev2) 로 해소
-- ============================================================================================
SET PAGESIZE 300 LINESIZE 250
COLUMN JUDGE FORMAT A60

PROMPT [D0] 접속 DB 실체 (QA/DEV 구분 — BE datasource 와 대조)
SELECT USER, SYS_CONTEXT('USERENV','DB_NAME') DB_NAME, SYS_CONTEXT('USERENV','CON_NAME') CON_NAME,
       SYS_CONTEXT('USERENV','SERVER_HOST') SERVER_HOST, SYS_CONTEXT('USERENV','SERVICE_NAME') SERVICE_NAME FROM DUAL;

PROMPT [D1] 1차 적용 반영 여부 (PKG_DMF0014 CFSEQ 2 · PRJMDL 7 기대 / MAKE 는 rev2 적용 전이면 OLD_CMP 1)
SELECT 'PKG_DMF0014' OBJ,
       SUM(CASE WHEN TEXT LIKE '%E20260929-DMF0014CFSEQ%'  THEN 1 ELSE 0 END) CFSEQ,
       SUM(CASE WHEN TEXT LIKE '%E20260929-DMF0014PRJMDL%' THEN 1 ELSE 0 END) PRJMDL,
       NULL UPPER_CMP, NULL OLD_CMP
  FROM USER_SOURCE WHERE NAME='PKG_DMF0014' AND TYPE='PACKAGE BODY'
UNION ALL
SELECT 'PR_DM_PLN_MKT_FCST_MAKE_CUST_FCST', NULL, NULL,
       SUM(CASE WHEN TEXT LIKE '%UPPER(MEASURE) IN (''CUSTOMER FCST'', ''CUST_FCST_EDI'')%' THEN 1 ELSE 0 END),
       SUM(CASE WHEN TEXT LIKE '%MEASURE IN (''Customer Fcst'', ''CUST_FCST_EDI'')%' THEN 1 ELSE 0 END)
  FROM USER_SOURCE WHERE NAME='PR_DM_PLN_MKT_FCST_MAKE_CUST_FCST' AND TYPE='PROCEDURE';

PROMPT [D2] 오늘 업로드 저장 실행 로그 (DMF0014 업로드 / 반영 / MAKE_CUST_FCST — TARGET DATA 건수가 핵심)
SELECT TO_CHAR(EVENT_DATE,'MM-DD HH24:MI:SS') EV, PROGRAM_NAME, LOG_TYPE, LOG_COUNT,
       SUBSTR(LOG_MESSAGE,1,60) MSG, SUBSTR(DESCRIPTION,1,80) DESCR
  FROM SCM_SYS_LOG_BATCH
 WHERE EVENT_DATE >= TRUNC(SYSDATE)
   AND (PROGRAM_NAME LIKE '%MAKE_CUST_FCST%'
        OR (PROGRAM_NAME LIKE '%DMF0014%' AND LOG_TYPE IN ('240','END','190','START'))
        OR (PROGRAM_NAME LIKE '%CUST_FCST_TO_MKT_FCST%' AND LOG_TYPE IN ('START','END')))
 ORDER BY EVENT_DATE DESC FETCH FIRST 60 ROWS ONLY;
-- 판정: MAKE_CUST_FCST 'TARGET DATA' LOG_COUNT 가 EDI 건수만큼만(또는 0) → 원인 확정(Excel 분 누락)
--       MAKE_CUST_FCST 로그 자체가 없음 → 루프 미실행(1차 CFSEQ 미반영 · Division 40 업로드 · 저장 실패) → [D1]/[D5] 확인

PROMPT [D3] 오늘 업로드 저장분 (DM_PLN_CUSTOMER_PSI · CUST_FCST)
SELECT DIVISION_ID, SCM_SITE_ID, CUSTOMER_PROJECT_CODE, CUSTOMER_MODEL, PROJECT_CODE, ITEM_ID, MEASURE,
       MIN(YYYYMMDD) FR, MAX(YYYYMMDD) TO_, COUNT(*) CNT, MAX(BATCH_RESULT) BATCH_RESULT, CREATED_BY,
       TO_CHAR(MAX(CREATION_DATE),'MM-DD HH24:MI:SS') CREATED
  FROM DM_PLN_CUSTOMER_PSI
 WHERE MEASURE_GROUP='CUST_FCST' AND CREATION_DATE >= TRUNC(SYSDATE)
 GROUP BY DIVISION_ID, SCM_SITE_ID, CUSTOMER_PROJECT_CODE, CUSTOMER_MODEL, PROJECT_CODE, ITEM_ID, MEASURE, CREATED_BY
 ORDER BY CREATED DESC;
-- 판정: BATCH_RESULT = SPLIT_COMPLETED/UPLOAD_COMPLETED → 반영 SP 까지 정상 수행. 'UI' 로 남아 있으면 반영 SP 미수행

PROMPT [D4] 오늘 저장분이 MKT_FCST 에 쓴 메저명 vs 같은 품목의 CUST_FCST (핵심 — 대소문자)
SELECT X.*,
       CASE WHEN X.CUST_FCST_CNT = 0 AND X.MEASURE <> 'Customer Fcst'
            THEN '⚠ CUST_FCST 없음 — 메저명 대소문자 불일치로 MAKE 원천 누락'
            WHEN X.CUST_FCST_CNT = 0 THEN '⚠ CUST_FCST 없음 — MAKE 미실행 의심([D2])'
            ELSE 'OK' END JUDGE
  FROM (SELECT F.DIVISION_ID, F.SCM_SITE_ID, F.PROJECT_CODE, F.ITEM_ID, F.MEASURE, COUNT(*) CNT, SUM(F.QTY) QTY,
               (SELECT COUNT(*) FROM DM_PLN_MKT_FCST C
                 WHERE C.DIVISION_ID=F.DIVISION_ID AND C.SCM_SITE_ID=F.SCM_SITE_ID AND C.PROJECT_CODE=F.PROJECT_CODE
                   AND C.ITEM_ID=F.ITEM_ID AND C.MEASURE='CUST_FCST'
                   AND C.YYYYMMDD >= TO_CHAR(TRUNC(SYSDATE,'IW'),'YYYYMMDD')) CUST_FCST_CNT
          FROM DM_PLN_MKT_FCST F
         WHERE F.CREATION_DATE >= TRUNC(SYSDATE) AND UPPER(F.MEASURE) LIKE 'CUSTOMER%FCST'
           AND F.YYYYMMDD >= TO_CHAR(TRUNC(SYSDATE,'IW'),'YYYYMMDD')
         GROUP BY F.DIVISION_ID, F.SCM_SITE_ID, F.PROJECT_CODE, F.ITEM_ID, F.MEASURE) X
 ORDER BY 1,2,3,4;
-- 판정: MEASURE='Customer FCST' + CUST_FCST_CNT=0 + JUDGE '⚠' → 원인 확정 → 12_PR_DM_PLN_MKT_FCST_MAKE_CUST_FCST.sql 적용

PROMPT [D5] MKT_FCST 원천 메저명 분포 (MAKE 원천 후보 — 대소문자 변형 확인)
SELECT DIVISION_ID, MEASURE, COUNT(*) CNT, TO_CHAR(MAX(CREATION_DATE),'YYYY-MM-DD HH24:MI') LAST_CREATED
  FROM DM_PLN_MKT_FCST
 WHERE UPPER(MEASURE) IN ('CUSTOMER FCST','CUST_FCST_EDI','CUST_FCST')
   AND YYYYMMDD >= TO_CHAR(TRUNC(SYSDATE,'IW'),'YYYYMMDD')
 GROUP BY DIVISION_ID, MEASURE ORDER BY 1,2;
-- 참고: CUST_FCST(MAKE_CUST_FCST) 수 ≈ 'Customer FCST' + 'CUST_FCST_EDI' 키 합집합이어야 정상(rev2 적용 후)

PROMPT [D6] 업로드 저장 오류 여부 (오늘 DMF0014 관련 BE 예외 로그)
SELECT TO_CHAR(CREATION_DATE,'MM-DD HH24:MI:SS') EV, SUBSTR(EXCT_MSG_CTN,1,300) ERR
  FROM SCM_COM_SYS_LOG
 WHERE CREATION_DATE >= TRUNC(SYSDATE) AND EXCT_MSG_CTN IS NOT NULL
   AND (UPPER(EXCT_MSG_CTN) LIKE '%DMF0014%' OR UPPER(EXCT_MSG_CTN) LIKE '%CUST_FCST%')
 ORDER BY CREATION_DATE DESC FETCH FIRST 20 ROWS ONLY;
