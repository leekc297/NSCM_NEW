-- 91_DIAGNOSE_MKT_NO_DATA.sql — DMF0035 (GUBUN=MKT FCST) 클라우드 "데이터 미조회" 진단 (SCM_MGR, 읽기 전용) — 2026-08-27
-- 판정법: ① 의 단계별 LOG_COUNT 를 사내 참조값(우측 주석)과 대조 → 처음 0 이 되는 단계가 원인 축. 그 단계의 원천은 ②~⑥.
-- 사내 참조 (div 40, Current, 2026-08-27 17:44): D1 229 / D2 3222 / D3 533 / D4 532 / D5 8867 / D61 8867 / D65 255
--                                                 E3A1 243064 / E3A2 169935 / E3A3 145883 / E3A4 169935 / E3A6 384 / E3A9 161 / E5 9262
--                                                 G1 TEMP_SCM_SITE 118251 / G2 RAW_DATA COUNT 5864 / H 36 (=최종 행 수)

-- ① 마지막 실행의 단계별 카운트 (+ 오류가 있으면 ERROR 행)
SELECT TO_CHAR(EVENT_DATE,'HH24:MI:SS') DT, LOG_TYPE, SUBSTR(LOG_MESSAGE,1,45) MSG, LOG_COUNT, SQL_ERR_CODE, SUBSTR(SQL_ERR_MSG,1,120) ERR
  FROM SCM_MGR.SCM_SYS_LOG_BATCH
 WHERE PROGRAM_NAME LIKE '%DMF0035_GET_MKT%'
   AND EVENT_DATE >= (SELECT MAX(EVENT_DATE) - 1/1440 FROM SCM_MGR.SCM_SYS_LOG_BATCH WHERE PROGRAM_NAME LIKE '%DMF0035_GET_MKT%' AND LOG_TYPE='START')
 ORDER BY EVENT_DATE, LOG_MESSAGE;
-- ①' 로그 자체가 0건이면 SP 진입 전 실패(권한·배선) → 40_GRANT_SYNONYM.sql + ⑦

-- ② 원천 데이터 (D2/D5 축) — div 40 은 DM_PLN_CFM_MKT_DEMAND_PLAN, 그 외 DM_PLN_MKT_FCST. 조회 division 행이 0 이면 데이터 미적재
SELECT 'CFM_MKT_DEMAND_PLAN' T, DIVISION_ID, COUNT(*) CNT, MIN(YYYYMMDD) MINY, MAX(YYYYMMDD) MAXY, COUNT(DISTINCT MEASURE) MEAS FROM SCM_MGR.DM_PLN_CFM_MKT_DEMAND_PLAN WHERE QTY <> 0 GROUP BY DIVISION_ID
UNION ALL SELECT 'MKT_FCST', DIVISION_ID, COUNT(*), MIN(YYYYMMDD), MAX(YYYYMMDD), COUNT(DISTINCT MEASURE) FROM SCM_MGR.DM_PLN_MKT_FCST WHERE QTY <> 0 GROUP BY DIVISION_ID
UNION ALL SELECT 'MKT_FCST_RESULT', DIVISION_ID, COUNT(*), MIN(YYYYMMDD), MAX(YYYYMMDD), COUNT(DISTINCT MEASURE) FROM SCM_MGR.DM_PLN_MKT_FCST_RESULT WHERE QTY <> 0 GROUP BY DIVISION_ID
ORDER BY 1,2;
-- ②' MEASURE 분포 (SEL_MEASURE 와 JOIN 되는 값: MKT_FCST / RTF / RTF_SYS_RP / CUST_FCST …)
SELECT DIVISION_ID, MEASURE, COUNT(*) FROM SCM_MGR.DM_PLN_CFM_MKT_DEMAND_PLAN WHERE QTY <> 0 GROUP BY DIVISION_ID, MEASURE ORDER BY 1,2;

-- ③ 시트 메타 (D--SELECT MEASURE / G3 컬럼 리스트 원천) — 기대: SHEET_COLUMNS 'Mkt Fcst Waterfall' 행 + SHEET_MEASURE 'Mkt Fcst Waterfall' 행 (사내 값은 90_VERIFY 참조)
SELECT 'COLUMNS' K, SHEET_NAME, COUNT(*) FROM SCM_MGR.SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID='DMF0035' GROUP BY SHEET_NAME
UNION ALL SELECT 'MEASURE', SHEET_NAME, COUNT(*) FROM SCM_MGR.SCM_MST_SHEET_MEASURE WHERE PROGRAM_ID='DMF0035' GROUP BY SHEET_NAME ORDER BY 1,2;
SELECT SHEET_NAME, MEASURE_GROUP, COLUMN_NAME, DEFAULT_FLAG FROM SCM_MGR.SCM_MST_SHEET_MEASURE WHERE PROGRAM_ID='DMF0035' ORDER BY 1,2,3;
-- ③' 사용자 메저 선택 (TITLESET_USER 는 이관 제외 — 없으면 SP 가 기본 메저를 넣지만, 선택이 있는데 원천 MEASURE 와 안 맞으면 D2/D5 = 0)
SELECT USER_ID, SHEET_NAME, COUNT(*) FROM SCM_MGR.SCM_MST_TITLESET_USER WHERE PROGRAM_ID='DMF0035' GROUP BY USER_ID, SHEET_NAME;

-- ④ 버전 (A003) — Current 외 버전 선택 시 DM_MST_VERSION 에 있어야 함
SELECT DIVISION_ID, COUNT(*), MAX(VERSION_NO) FROM SCM_MGR.DM_MST_VERSION GROUP BY DIVISION_ID ORDER BY 1;

-- ⑤ 마스터 (E3A1~E3A6 / G1 축) — 사내: SCP_MST_FINAL_ITEM div40 243064, SCM_MST_SITE, SCM_MST_SITE_ITEM
SELECT 'SCP_MST_FINAL_ITEM' T, DIVISION_ID, COUNT(*) FROM SCM_MGR.SCP_MST_FINAL_ITEM GROUP BY DIVISION_ID
UNION ALL SELECT 'SCM_MST_SITE', DIVISION_ID, COUNT(*) FROM SCM_MGR.SCM_MST_SITE WHERE VALID_YN='Y' GROUP BY DIVISION_ID
UNION ALL SELECT 'SCM_MST_SITE_ITEM', DIVISION_ID, COUNT(*) FROM SCM_MGR.SCM_MST_SITE_ITEM WHERE VALID_YN='Y' GROUP BY DIVISION_ID
UNION ALL SELECT 'SCM_SYS_CALENDAR_M', '-', COUNT(*) FROM SCM_MGR.SCM_SYS_CALENDAR_M WHERE BASIS_YYYYMMDD BETWEEN '20250101' AND '20271231'
ORDER BY 1,2;

-- ⑥ LOOKUP (D1/D3/D4 축) — EDI_END_CUSTOMER 등
SELECT LOOKUP_TYPE, COUNT(*) FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL WHERE LOOKUP_TYPE IN ('EDI_END_CUSTOMER','RPA_END_CUSTOMER','CELL_TYPE_ITEM_CODE','CELL_TYPE_ITEM_GROUP') AND VALID_YN='Y' GROUP BY LOOKUP_TYPE;

-- ⑦ 객체·권한·배선 (SQL ERROR 없이 빈 결과면 보통 해당 없음 — 확인용)
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'MM-DD HH24:MI') FROM ALL_OBJECTS WHERE OWNER='SCM_MGR' AND OBJECT_NAME IN ('PKG_DMF0035','PKG_DMF0022','PKG_DMF0051','PKG_SCM0002') ORDER BY 1,2;
SELECT API_ID, API_URL, USE_YN FROM SCM_MGR.SCM_ADM_API_M WHERE API_ID LIKE 'DMF0035%' ORDER BY 1;
SELECT TABLE_NAME FROM ALL_TABLES WHERE OWNER='SCM_MGR' AND TEMPORARY='Y' AND TABLE_NAME LIKE 'GT_DM35%' ORDER BY 1;
