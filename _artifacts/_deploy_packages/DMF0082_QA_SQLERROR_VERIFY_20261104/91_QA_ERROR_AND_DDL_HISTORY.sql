--   작성 2026-11-04 · 읽기 전용(SELECT 만) · SCM_MGR 접속 · 파일 전체 실행(F5)
--   ⚠ Oracle 은 객체별 DDL 이력을 한 곳에 남기지 않는다 (사내 ZIOUI1 2026-11-04 실측):
--     - ALL_OBJECTS.LAST_DDL_TIME = 마지막 1회만
--     - UNIFIED_AUDIT_TRAIL(기본 ORA_SECURECONFIG) = ANY 권한 사용 DDL(SYSTEM 등)만, 소유자(SCM_MGR) 본인 DDL 은 없음
--     - V$ACTIVE_SESSION_HISTORY / DBA_HIST_ACTIVE_SESS_HISTORY = 누가·언제 PACKAGE DDL 을 실행했는지(표본),
--       대상 객체명은 남지 않음 (CURRENT_OBJ# = -1)
--     - V$SQL / DBA_HIST_SQLTEXT = DDL 문장 남지 않음
--     ⇒ H1~H4 를 시각으로 맞춰 본다. 권한 없음(ORA-00942/01031) 문장은 건너뛰고 나머지 회신.
