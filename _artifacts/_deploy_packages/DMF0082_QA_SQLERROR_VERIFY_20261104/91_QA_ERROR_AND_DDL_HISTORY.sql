-- E1. 09:10 이후 BE 오류 원문 (전 화면) — EXCT_MSG_CTN = ORA 오류 전문
SELECT TO_CHAR(LOG_ST_DTM,'YYYY-MM-DD HH24:MI:SS') AS LOG_TIME,
       LOG_TP_CD, MNU_ID, SHT_NM, MNU_BTN_CD, CREATED_BY,
       SUBSTR(EXCT_MSG_CTN,1,1000)    AS ERROR_TEXT,
       SUBSTR(SYS_LOG_MSG_CTN,1,300)  AS CALL_INFO
  FROM SCM_COM_SYS_LOG
 WHERE LOG_ST_DTM >= TIMESTAMP '2026-11-04 09:10:00'
   AND EXCT_MSG_CTN IS NOT NULL
 ORDER BY LOG_ST_DTM;

-- E2. DMF0082 호출 성공/실패 시간대 (분 단위) — 오류 시작·종료 시각 확인
SELECT TO_CHAR(TRUNC(CAST(LOG_ST_DTM AS DATE),'MI'),'YYYY-MM-DD HH24:MI') AS MINUTE_TS,
       SHT_NM, MNU_BTN_CD,
       SUM(CASE WHEN EXCT_MSG_CTN IS NULL THEN 1 ELSE 0 END)     AS OK_CNT,
       SUM(CASE WHEN EXCT_MSG_CTN IS NOT NULL THEN 1 ELSE 0 END) AS ERR_CNT,
       MIN(SUBSTR(EXCT_MSG_CTN,1,200))                           AS ERR_SAMPLE
  FROM SCM_COM_SYS_LOG
 WHERE LOG_ST_DTM >= TIMESTAMP '2026-11-03 01:00:00'
   AND MNU_ID = 'DMF0082'
 GROUP BY TRUNC(CAST(LOG_ST_DTM AS DATE),'MI'), SHT_NM, MNU_BTN_CD
HAVING SUM(CASE WHEN EXCT_MSG_CTN IS NOT NULL THEN 1 ELSE 0 END) > 0
 ORDER BY 1, 2, 3;

-- E2b. 시트·버튼별 마지막 오류 시각 / 그 뒤 첫 성공 시각 (복구 시점 확인)
SELECT E.SHT_NM, E.MNU_BTN_CD,
       TO_CHAR(E.LAST_ERR,'YYYY-MM-DD HH24:MI:SS') AS LAST_ERR_TIME,
       (SELECT TO_CHAR(MIN(S.LOG_ST_DTM),'YYYY-MM-DD HH24:MI:SS')
          FROM SCM_COM_SYS_LOG S
         WHERE S.MNU_ID = 'DMF0082' AND S.SHT_NM = E.SHT_NM AND S.MNU_BTN_CD = E.MNU_BTN_CD
           AND S.EXCT_MSG_CTN IS NULL AND S.LOG_ST_DTM > E.LAST_ERR) AS FIRST_OK_AFTER
  FROM (SELECT SHT_NM, MNU_BTN_CD, MAX(LOG_ST_DTM) AS LAST_ERR
          FROM SCM_COM_SYS_LOG
         WHERE LOG_ST_DTM >= TIMESTAMP '2026-11-03 01:00:00'
           AND MNU_ID = 'DMF0082'
           AND EXCT_MSG_CTN IS NOT NULL
         GROUP BY SHT_NM, MNU_BTN_CD) E
 ORDER BY 3;

-- E3. DMF0082 오류 ORA 번호별 집계 (첫·마지막 발생 시각)
SELECT REGEXP_SUBSTR(EXCT_MSG_CTN,'ORA-[0-9]{5}')              AS ORA_CODE,
       COUNT(*)                                                 AS CNT,
       TO_CHAR(MIN(LOG_ST_DTM),'YYYY-MM-DD HH24:MI:SS')         AS FIRST_TIME,
       TO_CHAR(MAX(LOG_ST_DTM),'YYYY-MM-DD HH24:MI:SS')         AS LAST_TIME,
       MIN(SUBSTR(EXCT_MSG_CTN,1,400))                          AS SAMPLE
  FROM SCM_COM_SYS_LOG
 WHERE LOG_ST_DTM >= TIMESTAMP '2026-11-03 01:00:00'
   AND MNU_ID = 'DMF0082'
   AND EXCT_MSG_CTN IS NOT NULL
 GROUP BY REGEXP_SUBSTR(EXCT_MSG_CTN,'ORA-[0-9]{5}')
 ORDER BY FIRST_TIME;

-- H1. 2026-11-03 01:00 이후 DDL 이 바뀐 SCM_MGR 객체 (마지막 변경 시각) — PKG_DMF0082 와 같은 시각대 변경 객체 확인
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS,
       TO_CHAR(CREATED,'YYYY-MM-DD HH24:MI:SS')       AS CREATED,
       TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') AS LAST_DDL_TIME
  FROM ALL_OBJECTS
 WHERE OWNER = 'SCM_MGR'
   AND LAST_DDL_TIME >= TIMESTAMP '2026-11-03 01:00:00'
   AND OBJECT_TYPE IN ('PACKAGE','PACKAGE BODY','PROCEDURE','FUNCTION','VIEW','TABLE','TYPE','SYNONYM','TRIGGER')
 ORDER BY LAST_DDL_TIME;

-- H2. 통합 감사 — PKG_DMF0082 및 전체 PACKAGE DDL (ANY 권한 사용분만 기록됨)
SELECT TO_CHAR(EVENT_TIMESTAMP,'YYYY-MM-DD HH24:MI:SS') AS EVENT_TIME,
       DBUSERNAME, OS_USERNAME, USERHOST, CLIENT_PROGRAM_NAME,
       ACTION_NAME, OBJECT_SCHEMA, OBJECT_NAME, RETURN_CODE,
       DBMS_LOB.SUBSTR(SQL_TEXT,80,1) AS SQL_HEAD
  FROM UNIFIED_AUDIT_TRAIL
 WHERE EVENT_TIMESTAMP >= TIMESTAMP '2026-11-03 01:00:00'
   AND ACTION_NAME IN ('CREATE PACKAGE','CREATE PACKAGE BODY','ALTER PACKAGE','ALTER PACKAGE BODY',
                       'DROP PACKAGE','DROP PACKAGE BODY')
 ORDER BY EVENT_TIMESTAMP;

-- H3. ASH(메모리, 최근) — PACKAGE DDL 실행 세션 (94 CREATE PACKAGE / 95 ALTER PACKAGE / 97 CREATE BODY / 98 ALTER BODY)
--   대상 객체명은 남지 않음 → 시각을 H1 LAST_DDL_TIME · E2 오류 시작 시각과 맞춰 본다
SELECT TO_CHAR(MIN(A.SAMPLE_TIME),'YYYY-MM-DD HH24:MI:SS') AS FIRST_SAMPLE,
       TO_CHAR(MAX(A.SAMPLE_TIME),'HH24:MI:SS')            AS LAST_SAMPLE,
       DECODE(A.SQL_OPCODE,94,'CREATE PACKAGE',95,'ALTER PACKAGE',
                           97,'CREATE PACKAGE BODY',98,'ALTER PACKAGE BODY') AS DDL_TYPE,
       U.USERNAME, A.MACHINE, A.PROGRAM, A.MODULE, A.SQL_ID
  FROM V$ACTIVE_SESSION_HISTORY A
  LEFT JOIN DBA_USERS U ON U.USER_ID = A.USER_ID
 WHERE A.SQL_OPCODE IN (94,95,97,98)
   AND A.SAMPLE_TIME >= TIMESTAMP '2026-11-03 01:00:00'
 GROUP BY A.SQL_OPCODE, A.SESSION_ID, A.SESSION_SERIAL#, A.SQL_ID,
          TRUNC(CAST(A.SAMPLE_TIME AS DATE),'MI'), U.USERNAME, A.MACHINE, A.PROGRAM, A.MODULE
 ORDER BY 1;

-- H4. ASH(AWR 보관분, 10초 표본) — H3 이 메모리에서 밀려난 구간 보완
SELECT TO_CHAR(MIN(A.SAMPLE_TIME),'YYYY-MM-DD HH24:MI:SS') AS FIRST_SAMPLE,
       DECODE(A.SQL_OPCODE,94,'CREATE PACKAGE',95,'ALTER PACKAGE',
                           97,'CREATE PACKAGE BODY',98,'ALTER PACKAGE BODY') AS DDL_TYPE,
       U.USERNAME, A.MACHINE, A.PROGRAM, A.MODULE, A.SQL_ID
  FROM DBA_HIST_ACTIVE_SESS_HISTORY A
  LEFT JOIN DBA_USERS U ON U.USER_ID = A.USER_ID
 WHERE A.SQL_OPCODE IN (94,95,97,98)
   AND A.SAMPLE_TIME >= TIMESTAMP '2026-11-03 01:00:00'
 GROUP BY A.SQL_OPCODE, A.SESSION_ID, A.SESSION_SERIAL#, A.SQL_ID,
          TRUNC(CAST(A.SAMPLE_TIME AS DATE),'MI'), U.USERNAME, A.MACHINE, A.PROGRAM, A.MODULE
 ORDER BY 1;

-- H5. 현재 PKG_DMF0082 상태·줄 수 (09:34:44 로컬 소스 반영 후 기준)
SELECT O.OBJECT_TYPE, O.STATUS,
       TO_CHAR(O.LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') AS LAST_DDL_TIME,
       (SELECT COUNT(*) FROM ALL_SOURCE S
         WHERE S.OWNER = O.OWNER AND S.NAME = O.OBJECT_NAME AND S.TYPE = O.OBJECT_TYPE) AS LINE_CNT
  FROM ALL_OBJECTS O
 WHERE O.OWNER = 'SCM_MGR'
   AND O.OBJECT_NAME = 'PKG_DMF0082'
 ORDER BY O.OBJECT_TYPE;
