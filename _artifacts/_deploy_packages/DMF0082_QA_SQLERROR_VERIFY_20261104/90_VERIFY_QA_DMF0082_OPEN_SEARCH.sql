   AND OBJECT_NAME IN ('PKG_DMF0082','PKG_DMF0000','PKG_COM0000',
                       'DMF0002_GET_TITLESET_POPUP','SCM0002_SET_TITLESET_POPUP',
                       'PR_GET_SHEET_COLUMN_LIST','PR_GET_SHEET_MEASURE_LIST')
