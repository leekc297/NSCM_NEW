-- V0. 접속 대상 확인
SELECT SYS_CONTEXT('USERENV','DB_NAME')        AS DB_NAME,
       SYS_CONTEXT('USERENV','SERVICE_NAME')   AS SERVICE_NAME,
       SYS_CONTEXT('USERENV','SESSION_USER')   AS SESSION_USER,
       SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AS CURRENT_SCHEMA,
       TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI:SS') AS NOW_TS
  FROM DUAL;

-- V1. PKG_DMF0082 및 화면 호출 객체 상태
--   기대(사내): PACKAGE VALID / PACKAGE BODY VALID / DMF0002_GET_TITLESET_POPUP VALID
--             PR_GET_SHEET_COLUMN_LIST VALID / PR_GET_SHEET_MEASURE_LIST VALID
