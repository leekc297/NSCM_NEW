-- V2. 컴파일 오류 내용 (기대: 0행)
SELECT OWNER, NAME, TYPE, LINE, POSITION, ATTRIBUTE, SUBSTR(TEXT,1,300) AS TEXT
  FROM ALL_ERRORS
 WHERE OWNER = SYS_CONTEXT('USERENV','CURRENT_SCHEMA')
   AND NAME IN ('PKG_DMF0082','PKG_DMF0000','DMF0002_GET_TITLESET_POPUP',
                'PR_GET_SHEET_COLUMN_LIST','PR_GET_SHEET_MEASURE_LIST')
 ORDER BY NAME, TYPE, SEQUENCE;

-- V3. PKG_DMF0082 가 참조하는 객체 중 INVALID / 없음 (기대: 0행)
SELECT D.NAME, D.TYPE, D.REFERENCED_OWNER, D.REFERENCED_NAME, D.REFERENCED_TYPE,
       NVL(O.STATUS,'MISSING') AS REF_STATUS
  FROM ALL_DEPENDENCIES D
  LEFT JOIN ALL_OBJECTS O
    ON O.OWNER = D.REFERENCED_OWNER
   AND O.OBJECT_NAME = D.REFERENCED_NAME
   AND O.OBJECT_TYPE = D.REFERENCED_TYPE
 WHERE D.OWNER = SYS_CONTEXT('USERENV','CURRENT_SCHEMA')
   AND D.NAME = 'PKG_DMF0082'
   AND D.REFERENCED_OWNER NOT IN ('SYS','PUBLIC')
   AND NVL(O.STATUS,'MISSING') <> 'VALID'
 ORDER BY D.TYPE, D.REFERENCED_NAME;

-- V4. 오픈/조회 프로시저 존재 + 인자 수 (클라우드 실제 정의)
--   기대(사내): P_DMF0082_GET_BUTTON_AUTH 6(IN 3) / P_DMF0082_GET_MAIN_DATA 22(IN 16)
--             P_DMF0082_GET_SPREAD_TITLE 5(IN 4)
--   행이 없으면 = 클라우드 PKG_DMF0082 에 해당 프로시저 없음 (⚠ GET_BUTTON_AUTH 는
--   2026-10-02 신설, 클라우드 이관 패키지 폴더에서 검색 0건 — 미이관 가능성 1순위 확인 대상)
SELECT OBJECT_NAME,
       COUNT(*)                                          AS ARG_CNT,
       SUM(CASE WHEN IN_OUT = 'IN' THEN 1 ELSE 0 END)    AS IN_CNT,
       SUM(CASE WHEN IN_OUT = 'OUT' THEN 1 ELSE 0 END)   AS OUT_CNT
  FROM ALL_ARGUMENTS
 WHERE OWNER = SYS_CONTEXT('USERENV','CURRENT_SCHEMA')
   AND PACKAGE_NAME = 'PKG_DMF0082'
   AND OBJECT_NAME IN ('P_DMF0082_GET_BUTTON_AUTH','P_DMF0082_GET_MAIN_DATA',
                       'P_DMF0082_GET_SPREAD_TITLE')
   AND DATA_LEVEL = 0
   AND ARGUMENT_NAME IS NOT NULL
 GROUP BY OBJECT_NAME
 ORDER BY OBJECT_NAME;

-- V5. PROC_M(BE 바인딩 정의) 행 수 ↔ 실제 인자 수 대조 (기대: 3행 모두 MATCH)
--   사내: BUTTON_AUTH 6=6 / GET_MAIN_DATA 22=22 / GET_SPREAD_TITLE 5=5
--   MISMATCH = BE 가 인자 수 틀린 호출 → PLS-00306 등 SQL ERROR
SELECT P.PROC_NM,
       P.PROC_M_CNT,
       NVL(A.ARG_CNT,0) AS ARG_CNT,
       CASE WHEN P.PROC_M_CNT = NVL(A.ARG_CNT,0) THEN 'MATCH' ELSE 'MISMATCH' END AS JUDGE
  FROM (SELECT PROC_NM, COUNT(*) AS PROC_M_CNT
          FROM SCM_ADM_PROC_M
         WHERE PROC_NM IN ('PKG_DMF0082.P_DMF0082_GET_BUTTON_AUTH',
                           'PKG_DMF0082.P_DMF0082_GET_MAIN_DATA',
                           'PKG_DMF0082.P_DMF0082_GET_SPREAD_TITLE')
         GROUP BY PROC_NM) P
  LEFT JOIN (SELECT 'PKG_DMF0082.' || OBJECT_NAME AS PROC_NM, COUNT(*) AS ARG_CNT
               FROM ALL_ARGUMENTS
              WHERE OWNER = SYS_CONTEXT('USERENV','CURRENT_SCHEMA')
                AND PACKAGE_NAME = 'PKG_DMF0082'
                AND DATA_LEVEL = 0
                AND ARGUMENT_NAME IS NOT NULL
              GROUP BY OBJECT_NAME) A
    ON A.PROC_NM = P.PROC_NM
 ORDER BY P.PROC_NM;

-- V6. PROC_M 상세 — 순서(SORT_ORD ↔ POSITION)·방향(COL_TP_CD ↔ IN_OUT) 대조
--   (PROC_M.COL_NM 은 FE 키(camelCase)라 인자명과 다른 것이 정상 — 순서·방향으로 대조)
--   기대(사내): 0행 / 행이 나오면 그 위치에서 BE 바인딩이 어긋남
SELECT NVL(P.PROC_NM, A.PROC_NM)   AS PROC_NM,
       NVL(P.SORT_ORD, A.POSITION) AS POS,
       P.COL_NM, P.COL_TP_CD,
       A.ARGUMENT_NAME, A.IN_OUT,
       CASE WHEN A.PROC_NM IS NULL THEN 'ARG MISSING'
            WHEN P.PROC_NM IS NULL THEN 'PROC_M MISSING'
            ELSE 'DIRECTION DIFF' END AS JUDGE
  FROM (SELECT PROC_NM, SORT_ORD, COL_NM, COL_TP_CD
          FROM SCM_ADM_PROC_M
         WHERE PROC_NM IN ('PKG_DMF0082.P_DMF0082_GET_BUTTON_AUTH',
                           'PKG_DMF0082.P_DMF0082_GET_MAIN_DATA',
                           'PKG_DMF0082.P_DMF0082_GET_SPREAD_TITLE')) P
  FULL OUTER JOIN
       (SELECT 'PKG_DMF0082.' || OBJECT_NAME AS PROC_NM, POSITION, ARGUMENT_NAME, IN_OUT
          FROM ALL_ARGUMENTS
         WHERE OWNER = SYS_CONTEXT('USERENV','CURRENT_SCHEMA')
           AND PACKAGE_NAME = 'PKG_DMF0082'
           AND OBJECT_NAME IN ('P_DMF0082_GET_BUTTON_AUTH','P_DMF0082_GET_MAIN_DATA',
                               'P_DMF0082_GET_SPREAD_TITLE')
           AND DATA_LEVEL = 0
           AND ARGUMENT_NAME IS NOT NULL) A
    ON A.PROC_NM = P.PROC_NM AND A.POSITION = P.SORT_ORD
 WHERE A.PROC_NM IS NULL
    OR P.PROC_NM IS NULL
    OR SUBSTR(UPPER(P.COL_TP_CD),1,1) <> SUBSTR(A.IN_OUT,1,1)
 ORDER BY 1, 2;

-- V7. 버튼 → API 배선 (오픈/조회 대상 시트)
--   기대(사내): 아래 4행 모두 BTN_USE=Y / API_URL 일치 / API_USE=Y
--     FcstNPrice  SEARCH  P_DMF0082_GET_MAIN_DATA    PKG_DMF0082.P_DMF0082_GET_MAIN_DATA
--     buttonAuth  SEARCH  DMF0082_buttonAuth_SEARCH  PKG_DMF0082.P_DMF0082_GET_BUTTON_AUTH
--     spreadTitle SEARCH  DMF0082_spreadTitle_SEARCH PKG_DMF0082.P_DMF0082_GET_SPREAD_TITLE
--     titleSet    SEARCH  DMF0082_titleSet_SEARCH    DMF0002_GET_TITLESET_POPUP
SELECT B.SHT_NM, B.MNU_BTN_CD, B.API_ID, B.USE_YN AS BTN_USE,
       A.API_URL, A.USE_YN AS API_USE,
       CASE WHEN A.API_ID IS NULL THEN 'API_M MISSING' ELSE 'OK' END AS JUDGE
  FROM SCM_ADM_MNU_BTN_MPG_M B
  LEFT JOIN SCM_ADM_API_M A ON A.API_ID = B.API_ID
 WHERE B.MNU_ID = 'DMF0082'
   AND B.SHT_NM IN ('FcstNPrice','fcstNPrice','buttonAuth','spreadTitle','titleSet')
   AND B.MNU_BTN_CD = 'SEARCH'
 ORDER BY B.SHT_NM;

-- V8. DMF0082 배선 전체 건수 (기대(사내): 26행)
