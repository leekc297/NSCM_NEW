-- V11. 직접 실행 재현 (오픈 = GET_BUTTON_AUTH / 조회 = GET_SPREAD_TITLE)
--   ▶ 아래 v_div / v_user / v_grp 만 QA 에서 실제 오류 난 사용자·Division 으로 바꿔 실행
--     (v_grp 는 권한그룹 ID, 모르면 v_user 와 같게 둠 — FE 도 미확정 시 userId 로 보냄)
--   ▶ DBMS_OUTPUT 결과(Output 탭)의 'ERROR' 줄 = 클라우드 실제 ORA 오류 원문
--   조회 전용 프로시저만 실행 (저장 없음)
DECLARE
  v_div   VARCHAR2(30)  := '40';
  v_user  VARCHAR2(100) := 'minyonglee1';
  v_grp   VARCHAR2(100) := 'minyonglee1';
  v_from  VARCHAR2(8)   := TO_CHAR(TRUNC(SYSDATE,'IW'),'YYYYMMDD');
  v_to    VARCHAR2(8)   := TO_CHAR(ADD_MONTHS(TRUNC(SYSDATE,'MM'),6),'YYYYMMDD');
  c1 SYS_REFCURSOR; c2 SYS_REFCURSOR; c3 SYS_REFCURSOR;
BEGIN
  DBMS_OUTPUT.ENABLE(NULL);
  BEGIN
    EXECUTE IMMEDIATE 'BEGIN PKG_DMF0082.P_DMF0082_GET_BUTTON_AUTH(:1,:2,:3,:4,:5,:6); END;'
      USING v_div, v_user, v_grp, OUT c1, OUT c2, OUT c3;
    DBMS_OUTPUT.PUT_LINE('OK    GET_BUTTON_AUTH');
    IF c1%ISOPEN THEN CLOSE c1; END IF;
    IF c2%ISOPEN THEN CLOSE c2; END IF;
    IF c3%ISOPEN THEN CLOSE c3; END IF;
  EXCEPTION WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('ERROR GET_BUTTON_AUTH : ' || SQLERRM);
    DBMS_OUTPUT.PUT_LINE('      ' || DBMS_UTILITY.FORMAT_ERROR_BACKTRACE);
  END;
  BEGIN
    EXECUTE IMMEDIATE 'BEGIN PKG_DMF0082.P_DMF0082_GET_SPREAD_TITLE(:1,:2,:3,:4,:5); END;'
      USING v_from, v_to, v_user, v_div, OUT c1;
    DBMS_OUTPUT.PUT_LINE('OK    GET_SPREAD_TITLE (' || v_from || '~' || v_to || ')');
    IF c1%ISOPEN THEN CLOSE c1; END IF;
  EXCEPTION WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('ERROR GET_SPREAD_TITLE : ' || SQLERRM);
    DBMS_OUTPUT.PUT_LINE('      ' || DBMS_UTILITY.FORMAT_ERROR_BACKTRACE);
  END;
END;
