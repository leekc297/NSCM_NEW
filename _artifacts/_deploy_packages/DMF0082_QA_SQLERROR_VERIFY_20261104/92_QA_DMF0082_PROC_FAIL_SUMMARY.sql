-- DMF0082 프로시저별 성공/실패 집계 (2026-11-03 01:00 이후, SCM_COM_SQL_LOG) — 읽기 전용
--   2026-11-04 수정: PARAMS 4000자 절단 → 다중 바이트에서 ORA-06502 발생(QA) → CLOB 에서 프로시저명만 추출
SELECT PROC_NM, RESULT,
       COUNT(*) AS CNT,
       TO_CHAR(MIN(EXECUTE_TIME),'YYYY-MM-DD HH24:MI:SS') AS FIRST_TIME,
       TO_CHAR(MAX(EXECUTE_TIME),'YYYY-MM-DD HH24:MI:SS') AS LAST_TIME,
       MIN(ERR_SAMPLE) AS ERR_SAMPLE
  FROM (SELECT DBMS_LOB.SUBSTR(REGEXP_SUBSTR(PARAMS,'call ([A-Za-z0-9_.]+)',1,1,NULL,1),100,1) AS PROC_NM,
               CASE WHEN EXCEPTION IS NULL THEN 'OK' ELSE 'ERR' END AS RESULT,
               DBMS_LOB.SUBSTR(EXCEPTION,200,1) AS ERR_SAMPLE,
               EXECUTE_TIME
          FROM SCM_COM_SQL_LOG
         WHERE EXECUTE_TIME >= TIMESTAMP '2026-11-03 01:00:00'
           AND SQL_ID = 'com.lgcns.nscm.callProc'
           AND DBMS_LOB.INSTR(PARAMS,'"mnuId":"DMF0082"') > 0)
 GROUP BY PROC_NM, RESULT
 ORDER BY 1, 2;
