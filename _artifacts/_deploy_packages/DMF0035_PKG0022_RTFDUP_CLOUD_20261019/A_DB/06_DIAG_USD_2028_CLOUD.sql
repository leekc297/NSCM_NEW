-- 06_DIAG_USD_2028 — 조회 전용 (전체 F5, 값 입력 없음)
-- DMF0035 · PLAN TYPE=SALES PLAN · 40 · SP_W_20261001_V001 · MCCM348014A3 · SCUD_CN_FOC · DAP
-- 증상: [E20261019-000071] 반영 뒤에도 USD 행이 남음 — 2027-12 까지 0, 2028-01 부터 값 존재
-- 확인할 가설: 원천 행 중 CURRENCY 가 비어 있는(NULL / '-' / '/' / 공백) 2028-01 이후 RTF 행이 있고,
--             조회 SP 가 그 행의 통화를 SCM_MST_SITE_ITEM.CURRENCY(USD) 로 채워 별도 행으로 보인다.
--   (PKG_DMF0022: ① RAW_DATA 'CURRENCY IS NULL' → SITE_ITEM.CURRENCY UPDATE
--                 ② 최종 표시 'NVL(TRIM(A.CURRENCY),'/') <> '/' 아니면 C.CURRENCY' — '-' '/' 공백도 대체)
--
-- 판정 표
--   G0  MARKER_LINES=2            → 주석 처리 반영됨 (0 이면 10_APPLY 먼저)
--   G1  BLANK 행이 2028xx 에만 있음 → 가설 성립 (USD = 이 행들)
--   G2  CNY 마지막 월 < BLANK 첫 월 · MKT_FCST 마지막 월 < BLANK 첫 월 → MKT_FCST 기간 밖 RTF 가 통화 없이 적재됨
--   G3  SITE_ITEM 통화 = USD      → 채움 값이 USD 인 이유
--   G4  화면 표시 통화 시뮬레이션 — USD 월·수량이 화면과 같으면 원인 확정
--   G5  같은 버전 40 전체의 공란 통화 행 분포 — 이 키만의 문제인지, 버전 전체 현상인지
--   G6  같은 키 CURRENT 원장(DM_PLN_SALES_PLAN)도 같은 상태인지
SET LINESIZE 260 PAGESIZE 1000
SET DEFINE OFF

SELECT 'G0' CHK, SYS_CONTEXT('USERENV','DB_NAME') DB_NAME, TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI:SS') NOW,
       (SELECT COUNT(*) FROM USER_SOURCE WHERE NAME='PKG_DMF0022' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%E20261019-000071%') MARKER_LINES,
       (SELECT TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0022' AND OBJECT_TYPE='PACKAGE BODY') BODY_LAST_DDL,
       (SELECT STATUS FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0022' AND OBJECT_TYPE='PACKAGE BODY') BODY_STATUS
  FROM DUAL;

-- G1 원천 3표의 공란 통화 행 (이 키) — 월·메저·생성자·생성시각
SELECT 'G1' CHK, SRC, INCOTERMS, MEASURE, SUBSTR(YYYYMMDD,1,6) YM, '[' || CURRENCY || ']' RAW_CURRENCY,
       PROJECT_CODE, CELL_PROD_SITE_ID, COUNT(*) CNT, SUM(QTY) SUM_QTY,
       MIN(CREATED_BY) CREATED_BY, TO_CHAR(MIN(CREATION_DATE),'YYYY-MM-DD HH24:MI:SS') MIN_CREATED,
       MIN(LAST_UPDATED_BY) LAST_UPD_BY, TO_CHAR(MAX(LAST_UPDATE_DATE),'YYYY-MM-DD HH24:MI:SS') MAX_UPDATED
  FROM (SELECT 'SALES_PLAN_C' SRC, A.INCOTERMS, A.MEASURE, A.YYYYMMDD, A.CURRENCY, A.PROJECT_CODE, A.CELL_PROD_SITE_ID, A.QTY,
               A.CREATED_BY, A.CREATION_DATE, A.LAST_UPDATED_BY, A.LAST_UPDATE_DATE
          FROM SCM_MGR.DM_PLN_SALES_PLAN_C A
         WHERE A.VERSION_NO='SP_W_20261001_V001' AND A.DIVISION_ID='40' AND A.ITEM_ID='MCCM348014A3' AND A.SCM_SITE_ID='SCUD_CN_FOC'
        UNION ALL
        SELECT 'ETC_PLAN_C', A.INCOTERMS, A.MEASURE, A.YYYYMMDD, A.CURRENCY, A.PROJECT_CODE, '-', A.QTY,
               A.CREATED_BY, A.CREATION_DATE, A.LAST_UPDATED_BY, A.LAST_UPDATE_DATE
          FROM SCM_MGR.DM_PLN_SALES_ETC_PLAN_C A
         WHERE A.VERSION_NO='SP_W_20261001_V001' AND A.DIVISION_ID='40' AND A.ITEM_ID='MCCM348014A3' AND A.SCM_SITE_ID='SCUD_CN_FOC'
        UNION ALL
        SELECT 'RESULT_C', A.INCOTERMS, A.MEASURE, A.YYYYMMDD, A.CURRENCY, A.PROJECT_CODE, A.CELL_PROD_SITE_ID, A.QTY,
               A.CREATED_BY, A.CREATION_DATE, A.LAST_UPDATED_BY, A.LAST_UPDATE_DATE
          FROM SCM_MGR.DM_PLN_SALES_PLAN_RESULT_C A
         WHERE A.VERSION_NO='SP_W_20261001_V001' AND A.DIVISION_ID='40' AND A.ITEM_ID='MCCM348014A3' AND A.SCM_SITE_ID='SCUD_CN_FOC')
 WHERE NVL(TRIM(CURRENCY),'/') IN ('/','-')
 GROUP BY SRC, INCOTERMS, MEASURE, SUBSTR(YYYYMMDD,1,6), CURRENCY, PROJECT_CODE, CELL_PROD_SITE_ID
 ORDER BY SRC, INCOTERMS, MEASURE, YM;

-- G2 기간 경계 — 메저별 '통화 있는 행' 마지막 날짜 vs '공란 통화 행' 첫 날짜 (SALES_PLAN_C, 이 키, DAP)
SELECT 'G2' CHK, MEASURE,
       MIN(CASE WHEN NVL(TRIM(CURRENCY),'/') NOT IN ('/','-') THEN CURRENCY END) HAS_CURRENCY,
       MAX(CASE WHEN NVL(TRIM(CURRENCY),'/') NOT IN ('/','-') THEN YYYYMMDD END) LAST_YMD_WITH_CURRENCY,
       MIN(CASE WHEN NVL(TRIM(CURRENCY),'/') IN ('/','-') THEN YYYYMMDD END)     FIRST_YMD_BLANK,
       MAX(CASE WHEN NVL(TRIM(CURRENCY),'/') IN ('/','-') THEN YYYYMMDD END)     LAST_YMD_BLANK,
       SUM(CASE WHEN NVL(TRIM(CURRENCY),'/') IN ('/','-') THEN QTY END)          BLANK_QTY
  FROM SCM_MGR.DM_PLN_SALES_PLAN_C
 WHERE VERSION_NO='SP_W_20261001_V001' AND DIVISION_ID='40' AND ITEM_ID='MCCM348014A3' AND SCM_SITE_ID='SCUD_CN_FOC' AND INCOTERMS='DAP'
 GROUP BY MEASURE
 ORDER BY MEASURE;

-- G3 채움 값 — 조회 SP 는 (DIVISION, PROJECT_CODE, SCM_SITE, ITEM) 로 SITE_ITEM.CURRENCY 를 가져온다
SELECT 'G3' CHK, A.PROJECT_CODE, A.CURRENCY SITE_ITEM_CURRENCY, A.VALID_YN,
       (SELECT COUNT(*) FROM SCM_MGR.DM_PLN_SALES_PLAN_C B
         WHERE B.VERSION_NO='SP_W_20261001_V001' AND B.DIVISION_ID=A.DIVISION_ID AND B.PROJECT_CODE=A.PROJECT_CODE
           AND B.SCM_SITE_ID=A.SCM_SITE_ID AND B.ITEM_ID=A.ITEM_ID AND NVL(TRIM(B.CURRENCY),'/') IN ('/','-')) BLANK_ROWS_THIS_PROJECT
  FROM SCM_MGR.SCM_MST_SITE_ITEM A
 WHERE A.DIVISION_ID='40' AND A.ITEM_ID='MCCM348014A3' AND A.SCM_SITE_ID='SCUD_CN_FOC'
 ORDER BY A.PROJECT_CODE;

-- G4 화면 표시 통화 시뮬레이션 (SALES_PLAN_C · 이 키 · DAP · QTY<>0) — 월별 표시 통화와 수량
SELECT 'G4' CHK, A.MEASURE,
       CASE WHEN NVL(TRIM(A.CURRENCY),'/') NOT IN ('/','-') THEN A.CURRENCY ELSE NVL(S.CURRENCY,'(SITE_ITEM NULL)') END DISPLAY_CURRENCY,
       CASE WHEN NVL(TRIM(A.CURRENCY),'/') NOT IN ('/','-') THEN 'own' ELSE 'filled from SITE_ITEM' END HOW,
       SUBSTR(A.YYYYMMDD,1,6) YM, COUNT(*) CNT, SUM(A.QTY) SUM_QTY
  FROM SCM_MGR.DM_PLN_SALES_PLAN_C A
  LEFT JOIN SCM_MGR.SCM_MST_SITE_ITEM S
    ON S.DIVISION_ID=A.DIVISION_ID AND S.PROJECT_CODE=A.PROJECT_CODE AND S.SCM_SITE_ID=A.SCM_SITE_ID AND S.ITEM_ID=A.ITEM_ID
 WHERE A.VERSION_NO='SP_W_20261001_V001' AND A.DIVISION_ID='40' AND A.ITEM_ID='MCCM348014A3' AND A.SCM_SITE_ID='SCUD_CN_FOC'
   AND A.INCOTERMS='DAP' AND A.QTY <> 0
   AND A.MEASURE IN ('RTF_SYS_RP','RTF_PR','RTF_SCP','SalesAmt_KRW','SalesAmt_LOC','SalesAmt_USD','MKT_FCST','SCM_FCST')
 GROUP BY A.MEASURE,
          CASE WHEN NVL(TRIM(A.CURRENCY),'/') NOT IN ('/','-') THEN A.CURRENCY ELSE NVL(S.CURRENCY,'(SITE_ITEM NULL)') END,
          CASE WHEN NVL(TRIM(A.CURRENCY),'/') NOT IN ('/','-') THEN 'own' ELSE 'filled from SITE_ITEM' END,
          SUBSTR(A.YYYYMMDD,1,6)
 HAVING CASE WHEN NVL(TRIM(A.CURRENCY),'/') NOT IN ('/','-') THEN A.CURRENCY ELSE NVL(S.CURRENCY,'(SITE_ITEM NULL)') END <> 'CNY'
 ORDER BY A.MEASURE, YM;

-- G5 같은 버전 40 전체 — 공란 통화 행의 월·메저 분포 (2028 이후에만 몰리는지)
SELECT 'G5' CHK, SUBSTR(YYYYMMDD,1,6) YM, MEASURE, COUNT(*) CNT, COUNT(DISTINCT SCM_SITE_ID || '|' || ITEM_ID) KEYS, SUM(QTY) SUM_QTY
  FROM SCM_MGR.DM_PLN_SALES_PLAN_C
 WHERE VERSION_NO='SP_W_20261001_V001' AND DIVISION_ID='40' AND NVL(TRIM(CURRENCY),'/') IN ('/','-')
 GROUP BY SUBSTR(YYYYMMDD,1,6), MEASURE
 ORDER BY YM, MEASURE;

-- G6 같은 키 CURRENT 원장 — 스냅샷 원천도 같은 상태인지
SELECT 'G6' CHK, INCOTERMS, MEASURE, '[' || CURRENCY || ']' RAW_CURRENCY, MIN(YYYYMMDD) MIN_YMD, MAX(YYYYMMDD) MAX_YMD, COUNT(*) CNT, SUM(QTY) SUM_QTY,
       MIN(CREATED_BY) CREATED_BY, TO_CHAR(MAX(LAST_UPDATE_DATE),'YYYY-MM-DD HH24:MI:SS') MAX_UPDATED
  FROM SCM_MGR.DM_PLN_SALES_PLAN
 WHERE DIVISION_ID='40' AND ITEM_ID='MCCM348014A3' AND SCM_SITE_ID='SCUD_CN_FOC' AND NVL(TRIM(CURRENCY),'/') IN ('/','-')
 GROUP BY INCOTERMS, MEASURE, CURRENCY
 ORDER BY INCOTERMS, MEASURE;
