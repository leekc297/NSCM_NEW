-- 08_DIAG_SR_SUMMARY — 조회 전용 (전체 F5, 값 입력 없음) · 07 출력이 길어 잘리므로 요약형으로 재구성
-- 07 H1 판독(클라우드 OCGSCMQ_P01 · 2026-10-19 13:20):
--   SR 'E20260921-000253' 2026-09-28 15:21~15:24 적재 — 40 · 2027-01~2028-08
--   CURRENT(DM_PLN_SALES_PLAN) 공란 통화 MKT_FCST 1,931행/209키 · 버전(_C) 공란 MKT_FCST 25,401행/217키 · RTF_SYS_RP 11,901행/223키
--   키별로 '앞 기간 통화 있음 → 이후 기간 공란' 패턴
-- 판정 표 (각 블록 수십 행 이내)
--   S1  표별·생성자별 공란 통화 행 요약 (SR 적재분 + 그 키의 SYSTEM 파생분)
--   S2  _C 버전별 공란 통화 행 — 어느 버전 스냅샷까지 번졌는지
--   S3  보정 가능성 요약 — 키(PROJECT·SITE·ITEM·INCOTERMS·DOM_EXP·FCST_TYPE) 단위 판정별 건수
--   S4  보정 판단 필요 키 목록 (같은 키 통화 0종 또는 2종 이상만)
--   S5  같은 키 기존 통화 ≠ SITE_ITEM 통화 인 키 수 (SITE_ITEM 일괄 채움이 틀리는 범위)
--   S6  이 화면 키(SCUD_CN_FOC · MCCM348014A3) CURRENT/_C 공란 행 생성자 요약
SET LINESIZE 260 PAGESIZE 500
SET DEFINE OFF

SELECT 'S0' CHK, SYS_CONTEXT('USERENV','DB_NAME') DB_NAME, TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI:SS') NOW FROM DUAL;

-- S1 공란 통화 행 요약 — SR 키 전체(표 · 생성자 · 메저)
SELECT 'S1' CHK, SRC, CREATED_BY, MEASURE, COUNT(*) CNT, COUNT(DISTINCT KEYV) KEYS, MIN(YYYYMMDD) MIN_YMD, MAX(YYYYMMDD) MAX_YMD,
       TO_CHAR(MIN(CREATION_DATE),'YYYY-MM-DD HH24:MI') MIN_CREATED, TO_CHAR(MAX(CREATION_DATE),'YYYY-MM-DD HH24:MI') MAX_CREATED
  FROM (SELECT 'SALES_PLAN' SRC, A.CREATED_BY, A.MEASURE, A.YYYYMMDD, A.CREATION_DATE,
               A.PROJECT_CODE || '|' || A.SCM_SITE_ID || '|' || A.ITEM_ID KEYV
          FROM SCM_MGR.DM_PLN_SALES_PLAN A
         WHERE A.DIVISION_ID = '40' AND NVL(TRIM(A.CURRENCY),'/') IN ('/','-')
           AND (A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID) IN
               (SELECT DISTINCT PROJECT_CODE, SCM_SITE_ID, ITEM_ID FROM SCM_MGR.DM_PLN_SALES_PLAN
                 WHERE DIVISION_ID = '40' AND CREATED_BY = 'E20260921-000253')
        UNION ALL
        SELECT 'SALES_PLAN_C', A.CREATED_BY, A.MEASURE, A.YYYYMMDD, A.CREATION_DATE,
               A.PROJECT_CODE || '|' || A.SCM_SITE_ID || '|' || A.ITEM_ID
          FROM SCM_MGR.DM_PLN_SALES_PLAN_C A
         WHERE A.DIVISION_ID = '40' AND NVL(TRIM(A.CURRENCY),'/') IN ('/','-')
           AND A.CREATION_DATE >= TO_DATE('2026-09-28','YYYY-MM-DD')
           AND (A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID) IN
               (SELECT DISTINCT PROJECT_CODE, SCM_SITE_ID, ITEM_ID FROM SCM_MGR.DM_PLN_SALES_PLAN
                 WHERE DIVISION_ID = '40' AND CREATED_BY = 'E20260921-000253'))
 GROUP BY SRC, CREATED_BY, MEASURE
 ORDER BY SRC, CREATED_BY, MEASURE;

-- S2 _C 버전별 공란 통화 행 (2026-09-28 이후 생성분 · 40 전체)
SELECT 'S2' CHK, VERSION_NO, COUNT(*) BLANK_ROWS,
       COUNT(DISTINCT PROJECT_CODE || '|' || SCM_SITE_ID || '|' || ITEM_ID) KEYS,
       SUM(CASE WHEN CREATED_BY = 'E20260921-000253' THEN 1 ELSE 0 END) BY_SR,
       SUM(CASE WHEN UPPER(CREATED_BY) = 'SYSTEM' THEN 1 ELSE 0 END) BY_SYSTEM,
       SUM(CASE WHEN CREATED_BY <> 'E20260921-000253' AND UPPER(CREATED_BY) <> 'SYSTEM' THEN 1 ELSE 0 END) BY_OTHER,
       MIN(YYYYMMDD) MIN_YMD, MAX(YYYYMMDD) MAX_YMD
  FROM SCM_MGR.DM_PLN_SALES_PLAN_C
 WHERE DIVISION_ID = '40' AND NVL(TRIM(CURRENCY),'/') IN ('/','-')
   AND CREATION_DATE >= TO_DATE('2026-09-28','YYYY-MM-DD')
 GROUP BY VERSION_NO
 ORDER BY VERSION_NO;

-- S3/S4/S5 보정 가능성 (CURRENT 원장 기준 · SR 키)
WITH BLANK_KEY AS (
    SELECT DISTINCT A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.INCOTERMS, A.DOM_EXP, A.FCST_TYPE
      FROM SCM_MGR.DM_PLN_SALES_PLAN A
     WHERE A.DIVISION_ID = '40' AND NVL(TRIM(A.CURRENCY),'/') IN ('/','-')
       AND (A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID) IN
           (SELECT DISTINCT PROJECT_CODE, SCM_SITE_ID, ITEM_ID FROM SCM_MGR.DM_PLN_SALES_PLAN
             WHERE DIVISION_ID = '40' AND CREATED_BY = 'E20260921-000253')
), J AS (
    SELECT K.PROJECT_CODE, K.SCM_SITE_ID, K.ITEM_ID, K.INCOTERMS, K.DOM_EXP, K.FCST_TYPE,
           COUNT(DISTINCT B.CURRENCY) CUR_KINDS, MIN(B.CURRENCY) CUR_MIN, MAX(B.CURRENCY) CUR_MAX,
           (SELECT MIN(S.CURRENCY) FROM SCM_MGR.SCM_MST_SITE_ITEM S
             WHERE S.DIVISION_ID = '40' AND S.PROJECT_CODE = K.PROJECT_CODE AND S.SCM_SITE_ID = K.SCM_SITE_ID AND S.ITEM_ID = K.ITEM_ID) SI_CUR
      FROM BLANK_KEY K
      LEFT JOIN SCM_MGR.DM_PLN_SALES_PLAN B
        ON  B.DIVISION_ID = '40' AND B.PROJECT_CODE = K.PROJECT_CODE AND B.SCM_SITE_ID = K.SCM_SITE_ID AND B.ITEM_ID = K.ITEM_ID
       AND B.INCOTERMS = K.INCOTERMS AND B.DOM_EXP = K.DOM_EXP AND B.FCST_TYPE = K.FCST_TYPE
       AND NVL(TRIM(B.CURRENCY),'/') NOT IN ('/','-')
     GROUP BY K.PROJECT_CODE, K.SCM_SITE_ID, K.ITEM_ID, K.INCOTERMS, K.DOM_EXP, K.FCST_TYPE
), JJ AS (
    SELECT J.*,
           CASE WHEN CUR_KINDS = 1 THEN 'A_FILLABLE_SAME_KEY'
                WHEN CUR_KINDS = 0 AND SI_CUR IS NOT NULL THEN 'B_NO_SAME_KEY_SITE_ITEM_ONLY'
                WHEN CUR_KINDS = 0 THEN 'C_NO_CURRENCY_ANYWHERE'
                ELSE 'D_AMBIGUOUS' END JUDGE
      FROM J
)
SELECT 'S3' CHK, JUDGE, COUNT(*) KEYS,
       SUM(CASE WHEN JUDGE = 'A_FILLABLE_SAME_KEY' AND SI_CUR IS NOT NULL AND SI_CUR <> CUR_MIN THEN 1 ELSE 0 END) S5_SAMEKEY_NE_SITEITEM
  FROM JJ
 GROUP BY JUDGE
 ORDER BY JUDGE;

WITH BLANK_KEY AS (
    SELECT DISTINCT A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.INCOTERMS, A.DOM_EXP, A.FCST_TYPE
      FROM SCM_MGR.DM_PLN_SALES_PLAN A
     WHERE A.DIVISION_ID = '40' AND NVL(TRIM(A.CURRENCY),'/') IN ('/','-')
       AND (A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID) IN
           (SELECT DISTINCT PROJECT_CODE, SCM_SITE_ID, ITEM_ID FROM SCM_MGR.DM_PLN_SALES_PLAN
             WHERE DIVISION_ID = '40' AND CREATED_BY = 'E20260921-000253')
), J AS (
    SELECT K.PROJECT_CODE, K.SCM_SITE_ID, K.ITEM_ID, K.INCOTERMS, K.DOM_EXP, K.FCST_TYPE,
           COUNT(DISTINCT B.CURRENCY) CUR_KINDS, MIN(B.CURRENCY) CUR_MIN, MAX(B.CURRENCY) CUR_MAX,
           (SELECT MIN(S.CURRENCY) FROM SCM_MGR.SCM_MST_SITE_ITEM S
             WHERE S.DIVISION_ID = '40' AND S.PROJECT_CODE = K.PROJECT_CODE AND S.SCM_SITE_ID = K.SCM_SITE_ID AND S.ITEM_ID = K.ITEM_ID) SI_CUR
      FROM BLANK_KEY K
      LEFT JOIN SCM_MGR.DM_PLN_SALES_PLAN B
        ON  B.DIVISION_ID = '40' AND B.PROJECT_CODE = K.PROJECT_CODE AND B.SCM_SITE_ID = K.SCM_SITE_ID AND B.ITEM_ID = K.ITEM_ID
       AND B.INCOTERMS = K.INCOTERMS AND B.DOM_EXP = K.DOM_EXP AND B.FCST_TYPE = K.FCST_TYPE
       AND NVL(TRIM(B.CURRENCY),'/') NOT IN ('/','-')
     GROUP BY K.PROJECT_CODE, K.SCM_SITE_ID, K.ITEM_ID, K.INCOTERMS, K.DOM_EXP, K.FCST_TYPE
)
SELECT 'S4' CHK, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, INCOTERMS, DOM_EXP, FCST_TYPE, CUR_KINDS, CUR_MIN, CUR_MAX, SI_CUR
  FROM J
 WHERE CUR_KINDS <> 1
 ORDER BY CUR_KINDS DESC, SCM_SITE_ID, ITEM_ID, PROJECT_CODE, INCOTERMS;

-- S6 이 화면 키 — CURRENT / _C(SP_W_20261001_V001) 공란 통화 행 생성자 요약
SELECT 'S6' CHK, SRC, PROJECT_CODE, INCOTERMS, CREATED_BY, COUNT(*) CNT, MIN(YYYYMMDD) MIN_YMD, MAX(YYYYMMDD) MAX_YMD
  FROM (SELECT 'SALES_PLAN' SRC, PROJECT_CODE, INCOTERMS, CREATED_BY, YYYYMMDD FROM SCM_MGR.DM_PLN_SALES_PLAN
         WHERE DIVISION_ID = '40' AND SCM_SITE_ID = 'SCUD_CN_FOC' AND ITEM_ID = 'MCCM348014A3' AND NVL(TRIM(CURRENCY),'/') IN ('/','-')
        UNION ALL
        SELECT 'SALES_PLAN_C', PROJECT_CODE, INCOTERMS, CREATED_BY, YYYYMMDD FROM SCM_MGR.DM_PLN_SALES_PLAN_C
         WHERE VERSION_NO = 'SP_W_20261001_V001' AND DIVISION_ID = '40' AND SCM_SITE_ID = 'SCUD_CN_FOC' AND ITEM_ID = 'MCCM348014A3'
           AND NVL(TRIM(CURRENCY),'/') IN ('/','-'))
 GROUP BY SRC, PROJECT_CODE, INCOTERMS, CREATED_BY
 ORDER BY SRC, PROJECT_CODE, INCOTERMS, CREATED_BY;
