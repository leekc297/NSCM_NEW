-- 07_DIAG_SR_E20260921_000253 — 조회 전용 (전체 F5, 값 입력 없음)
-- 06_DIAG 결과(클라우드 OCGSCMQ_P01 · 2026-10-19 13:14) 판독:
--   SP_W_20261001_V001 · SCUD_CN_FOC · MCCM348014A3 · PROJECT 'SCUD LEV' 의 202801~202808 행 CURRENCY 공란
--   ① MKT_FCST / MKT_AMT_* / SCM_FCST  CREATED_BY = 'E20260921-000253'  2026-09-28 15:24:05  (SR 번호 형식 = 데이터 적재)
--   ② RTF_PR / RTF_SCP / RTF_SYS_RP / SalesAmt_*  CREATED_BY = 'SYSTEM'  2026-09-30 16:10:53  (①을 원천으로 한 배치 파생)
--   ③ LAST_UPDATED_BY = system 2026-10-01 10:10:07 (버전 SP_W_20261001_V001 스냅샷)
--   → 조회 SP 가 공란 통화를 SITE_ITEM 통화(USD)로 채워, DAP 에 USD 행(2028-01~)이 따로 보인다.
--   (CIF 도 공란이지만 CIF 원래 통화가 USD 라 같은 행으로 합쳐져 눈에 띄지 않음)
--
-- 판정 표
--   H1  SR 적재분 범위 — 표·메저·통화·기간·키 수 (CURRENCY 공란이면 적재 시 통화 누락)
--   H2  같은 날 SYSTEM 파생분 — SR 키와 같은 키의 공란 통화 행 (② 확인)
--   H3  이 키 CURRENT 원장의 공란 행 생성자 분포 — SR + SYSTEM 외 생성자가 있으면 다른 원인 병존
--   H4  같은 키(PROJECT·SITE·ITEM·INCOTERMS)에서 통화가 있는 행의 통화 — 보정 시 채울 값 후보
--   H5  보정 가능성 — 공란 키별 '같은 키의 통화 종류 수' (1 = 그 값으로 보정 가능 / 0·2+ = 판단 필요)
--   H6  버전 스냅샷 파급 — SR 키가 들어간 SP_W 버전과 공란 행 수
SET LINESIZE 260 PAGESIZE 2000
SET DEFINE OFF

SELECT 'H0' CHK, SYS_CONTEXT('USERENV','DB_NAME') DB_NAME, TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI:SS') NOW FROM DUAL;

-- H1 SR 적재분 범위 (CURRENT 원장 · 버전 스냅샷)
SELECT 'H1' CHK, SRC, DIVISION_ID, MEASURE, '[' || CURRENCY || ']' RAW_CURRENCY,
       MIN(YYYYMMDD) MIN_YMD, MAX(YYYYMMDD) MAX_YMD, COUNT(*) CNT,
       COUNT(DISTINCT PROJECT_CODE || '|' || SCM_SITE_ID || '|' || ITEM_ID) KEYS, SUM(QTY) SUM_QTY,
       TO_CHAR(MIN(CREATION_DATE),'YYYY-MM-DD HH24:MI:SS') MIN_CREATED, TO_CHAR(MAX(CREATION_DATE),'YYYY-MM-DD HH24:MI:SS') MAX_CREATED
  FROM (SELECT 'SALES_PLAN' SRC, DIVISION_ID, MEASURE, CURRENCY, YYYYMMDD, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, QTY, CREATION_DATE
          FROM SCM_MGR.DM_PLN_SALES_PLAN WHERE CREATED_BY = 'E20260921-000253'
        UNION ALL
        SELECT 'SALES_PLAN_C', DIVISION_ID, MEASURE, CURRENCY, YYYYMMDD, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, QTY, CREATION_DATE
          FROM SCM_MGR.DM_PLN_SALES_PLAN_C WHERE CREATED_BY = 'E20260921-000253'
        UNION ALL
        SELECT 'MKT_FCST', DIVISION_ID, MEASURE, NULL, YYYYMMDD, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, QTY, CREATION_DATE
          FROM SCM_MGR.DM_PLN_MKT_FCST WHERE CREATED_BY = 'E20260921-000253')
 GROUP BY SRC, DIVISION_ID, MEASURE, CURRENCY
 ORDER BY SRC, DIVISION_ID, MEASURE, CURRENCY;

-- H1-b SR 적재 키 목록 (CURRENT 원장 SALES_PLAN 기준)
SELECT 'H1b' CHK, DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, INCOTERMS, '[' || CURRENCY || ']' RAW_CURRENCY,
       MIN(YYYYMMDD) MIN_YMD, MAX(YYYYMMDD) MAX_YMD, COUNT(*) CNT
  FROM SCM_MGR.DM_PLN_SALES_PLAN
 WHERE CREATED_BY = 'E20260921-000253'
 GROUP BY DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, INCOTERMS, CURRENCY
 ORDER BY DIVISION_ID, SCM_SITE_ID, ITEM_ID, PROJECT_CODE, INCOTERMS;

-- H2 SR 키와 같은 키의 공란 통화 행 — 생성자별 (SYSTEM 파생분 확인)
SELECT 'H2' CHK, A.CREATED_BY, A.MEASURE, MIN(A.YYYYMMDD) MIN_YMD, MAX(A.YYYYMMDD) MAX_YMD, COUNT(*) CNT, SUM(A.QTY) SUM_QTY,
       TO_CHAR(MIN(A.CREATION_DATE),'YYYY-MM-DD HH24:MI:SS') MIN_CREATED, TO_CHAR(MAX(A.CREATION_DATE),'YYYY-MM-DD HH24:MI:SS') MAX_CREATED
  FROM SCM_MGR.DM_PLN_SALES_PLAN A
 WHERE NVL(TRIM(A.CURRENCY),'/') IN ('/','-')
   AND (A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID) IN
       (SELECT DISTINCT DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID FROM SCM_MGR.DM_PLN_SALES_PLAN WHERE CREATED_BY = 'E20260921-000253')
 GROUP BY A.CREATED_BY, A.MEASURE
 ORDER BY A.CREATED_BY, A.MEASURE;

-- H3 이 키 CURRENT 원장 — 공란 통화 행의 생성자·기간
SELECT 'H3' CHK, PROJECT_CODE, INCOTERMS, CREATED_BY, MEASURE, MIN(YYYYMMDD) MIN_YMD, MAX(YYYYMMDD) MAX_YMD, COUNT(*) CNT, SUM(QTY) SUM_QTY,
       TO_CHAR(MIN(CREATION_DATE),'YYYY-MM-DD HH24:MI:SS') MIN_CREATED
  FROM SCM_MGR.DM_PLN_SALES_PLAN
 WHERE DIVISION_ID='40' AND ITEM_ID='MCCM348014A3' AND SCM_SITE_ID='SCUD_CN_FOC' AND NVL(TRIM(CURRENCY),'/') IN ('/','-')
 GROUP BY PROJECT_CODE, INCOTERMS, CREATED_BY, MEASURE
 ORDER BY PROJECT_CODE, INCOTERMS, CREATED_BY, MEASURE;

-- H4 같은 키(PROJECT·SITE·ITEM·INCOTERMS)의 통화가 있는 행 — 통화·기간·생성자
SELECT 'H4' CHK, PROJECT_CODE, INCOTERMS, CURRENCY, MIN(YYYYMMDD) MIN_YMD, MAX(YYYYMMDD) MAX_YMD, COUNT(*) CNT,
       MIN(CREATED_BY) MIN_CREATED_BY, MAX(CREATED_BY) MAX_CREATED_BY
  FROM SCM_MGR.DM_PLN_SALES_PLAN
 WHERE DIVISION_ID='40' AND ITEM_ID='MCCM348014A3' AND SCM_SITE_ID='SCUD_CN_FOC' AND NVL(TRIM(CURRENCY),'/') NOT IN ('/','-')
 GROUP BY PROJECT_CODE, INCOTERMS, CURRENCY
 ORDER BY PROJECT_CODE, INCOTERMS, CURRENCY;

-- H5 보정 가능성 — SR 키의 공란 행마다 같은 키(PROJECT·SITE·ITEM·INCOTERMS·DOM_EXP·FCST_TYPE)의 통화 종류
WITH BLANK_KEY AS (
    SELECT DISTINCT A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID, A.INCOTERMS, A.DOM_EXP, A.FCST_TYPE
      FROM SCM_MGR.DM_PLN_SALES_PLAN A
     WHERE NVL(TRIM(A.CURRENCY),'/') IN ('/','-')
       AND (A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID) IN
           (SELECT DISTINCT DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID FROM SCM_MGR.DM_PLN_SALES_PLAN WHERE CREATED_BY = 'E20260921-000253')
), CUR AS (
    SELECT K.DIVISION_ID, K.PROJECT_CODE, K.SCM_SITE_ID, K.ITEM_ID, K.INCOTERMS, K.DOM_EXP, K.FCST_TYPE,
           COUNT(DISTINCT B.CURRENCY) CUR_KINDS, MIN(B.CURRENCY) CUR_MIN, MAX(B.CURRENCY) CUR_MAX,
           (SELECT MIN(S.CURRENCY) FROM SCM_MGR.SCM_MST_SITE_ITEM S
             WHERE S.DIVISION_ID=K.DIVISION_ID AND S.PROJECT_CODE=K.PROJECT_CODE AND S.SCM_SITE_ID=K.SCM_SITE_ID AND S.ITEM_ID=K.ITEM_ID) SITE_ITEM_CURRENCY
      FROM BLANK_KEY K
      LEFT JOIN SCM_MGR.DM_PLN_SALES_PLAN B
        ON  B.DIVISION_ID=K.DIVISION_ID AND B.PROJECT_CODE=K.PROJECT_CODE AND B.SCM_SITE_ID=K.SCM_SITE_ID AND B.ITEM_ID=K.ITEM_ID
       AND B.INCOTERMS=K.INCOTERMS AND B.DOM_EXP=K.DOM_EXP AND B.FCST_TYPE=K.FCST_TYPE
       AND NVL(TRIM(B.CURRENCY),'/') NOT IN ('/','-')
     GROUP BY K.DIVISION_ID, K.PROJECT_CODE, K.SCM_SITE_ID, K.ITEM_ID, K.INCOTERMS, K.DOM_EXP, K.FCST_TYPE
)
SELECT 'H5' CHK, DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID, INCOTERMS, DOM_EXP, FCST_TYPE, CUR_KINDS, CUR_MIN, CUR_MAX, SITE_ITEM_CURRENCY,
       CASE WHEN CUR_KINDS = 1 THEN 'FILLABLE (same-key currency ' || CUR_MIN || ')'
            WHEN CUR_KINDS = 0 THEN 'NO SAME-KEY CURRENCY (decide: SITE_ITEM ' || NVL(SITE_ITEM_CURRENCY,'NULL') || ')'
            ELSE 'AMBIGUOUS (' || CUR_MIN || '/' || CUR_MAX || ')' END JUDGE
  FROM CUR
 ORDER BY DIVISION_ID, SCM_SITE_ID, ITEM_ID, PROJECT_CODE, INCOTERMS;

-- H6 버전 스냅샷 파급 — SR 키의 공란 행이 들어간 버전
SELECT 'H6' CHK, A.VERSION_NO, COUNT(*) BLANK_ROWS, COUNT(DISTINCT A.PROJECT_CODE || '|' || A.SCM_SITE_ID || '|' || A.ITEM_ID) KEYS,
       MIN(A.YYYYMMDD) MIN_YMD, MAX(A.YYYYMMDD) MAX_YMD
  FROM SCM_MGR.DM_PLN_SALES_PLAN_C A
 WHERE NVL(TRIM(A.CURRENCY),'/') IN ('/','-')
   AND (A.DIVISION_ID, A.PROJECT_CODE, A.SCM_SITE_ID, A.ITEM_ID) IN
       (SELECT DISTINCT DIVISION_ID, PROJECT_CODE, SCM_SITE_ID, ITEM_ID FROM SCM_MGR.DM_PLN_SALES_PLAN WHERE CREATED_BY = 'E20260921-000253')
   AND A.CREATION_DATE >= TO_DATE('2026-09-28','YYYY-MM-DD')
 GROUP BY A.VERSION_NO
 ORDER BY A.VERSION_NO;
