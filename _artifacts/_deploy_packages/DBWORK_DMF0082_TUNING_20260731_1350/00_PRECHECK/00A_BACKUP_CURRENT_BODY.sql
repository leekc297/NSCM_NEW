SET LONG 20000000
SET LONGCHUNKSIZE 20000000
SET LINESIZE 32767
SET PAGESIZE 0
SET TRIMSPOOL ON
SET FEEDBACK OFF
SET HEADING OFF
SPOOL BACKUP_PKG_DMF0082_BODY_CLOUD_20260731.sql
SELECT 'CREATE OR REPLACE ' FROM DUAL;
SELECT TEXT FROM DBA_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY'
 ORDER BY LINE;
SELECT '/' FROM DUAL;
SPOOL OFF
SET HEADING ON
SET FEEDBACK ON
SET PAGESIZE 100

-- 현행 라인수 기록 (적용 후 12,920 과 대조)
SELECT MAX(LINE) AS 현행_라인수 FROM DBA_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY';
