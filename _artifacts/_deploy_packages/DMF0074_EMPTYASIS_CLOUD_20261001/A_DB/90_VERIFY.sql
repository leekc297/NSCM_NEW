SET PAGESIZE 200 LINESIZE 300

-- [1] 상태 — PACKAGE / PACKAGE BODY 모두 VALID
SELECT OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME, 'YYYY-MM-DD HH24:MI:SS') LAST_DDL
  FROM USER_OBJECTS WHERE OBJECT_NAME = 'PKG_DMF0074' ORDER BY OBJECT_TYPE;
SELECT TYPE, LINE, POSITION, TEXT FROM USER_ERRORS WHERE NAME = 'PKG_DMF0074' ORDER BY SEQUENCE;

-- [2] 마커 수 — 사내와 동일해야 함: EMPTYASIS 12 / KEYNAMETOCODE 3 / NOLOADGUARD 2
SELECT SUM(CASE WHEN INSTR(TEXT, 'E20261001-EMPTYASIS') > 0 THEN 1 ELSE 0 END)         EMPTYASIS_12
     , SUM(CASE WHEN INSTR(TEXT, 'E20260918-KEYNAMETOCODE') > 0 THEN 1 ELSE 0 END)     KEYNAMETOCODE_3
     , SUM(CASE WHEN INSTR(TEXT, 'E20260827-D4-NOLOADGUARD') > 0 THEN 1 ELSE 0 END)    NOLOADGUARD_2
     , COUNT(*)                                                                        SRC_LINES
  FROM USER_SOURCE WHERE NAME = 'PKG_DMF0074' AND TYPE = 'PACKAGE BODY';

-- [3] 앱 계정 실행 경로 (기존 유지 확인)
SELECT OWNER, SYNONYM_NAME, TABLE_OWNER FROM ALL_SYNONYMS WHERE OWNER = 'SCMP_APP' AND SYNONYM_NAME = 'PKG_DMF0074';
SELECT GRANTEE, TABLE_NAME, PRIVILEGE FROM USER_TAB_PRIVS WHERE GRANTEE = 'SCMP_APP' AND TABLE_NAME = 'PKG_DMF0074';

-- [4] (업로드 테스트 후) 방금 저장한 모델은 금속 7행 · 공란 = '-' / 0
--     &ITEM 에 업로드한 Model Code 입력
SELECT DIVISION_ID, PLAN_YYYYMM, ITEM_ID, METAL_KIND_CODE, METAL_LINK_YN, METAL_EXCEPTION_YN, ENERGY,
       APPLY_PRICE_TYPE_CODE, FROM_PERIOD_YYYYMM, TO_PERIOD_YYYYMM, CONTRACT_UNIT_PRICE, METAL_APPLY_UNIT_PRICE, METAL_REQR_QTY,
       TO_CHAR(LAST_UPDATE_DATE, 'YYYY-MM-DD HH24:MI:SS') LAST_UPD
  FROM DM_BPS_METAL_LINK_PRICE
 WHERE ITEM_ID = '&ITEM'
 ORDER BY PLAN_YYYYMM, DECODE(METAL_KIND_CODE, 'Ni', 1, 'Co', 2, 'Li2CO3', 3, 'LIOH', 4, 'Al', 5, 'Mn', 6, 'Cu', 7);
