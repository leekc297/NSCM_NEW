-- 00_PRECHECK.sql — 클라우드 PKG_DMF0074 현재 판본 점검 (조회 전용 · 변경 없음) · SCM_MGR 로 접속해 실행
--   01 은 BODY 전체 교체이므로, 클라우드 BODY 가 아래 두 조건을 만족할 때만 적용한다.
--   (1) BASE_MISSING 이 비어 있음  = 09-15 이관 판본(DMF0074_EXCELUPLOAD_CLOUD_20260915) 이상
--   (2) CLOUD_ONLY  가 비어 있음  = 클라우드에만 있는 수정이 없음 (있으면 전체 교체 시 유실 → 적용 중지, 결과 공유)
--   VERDICT = 'OK' 이면 01 실행 / 그 외는 결과를 공유해 주세요.
SET PAGESIZE 200 LINESIZE 400
COLUMN BASE_MISSING FORMAT A80
COLUMN CLOUD_ONLY FORMAT A80
COLUMN ALREADY_HAS FORMAT A60

SELECT O.OBJECT_TYPE, O.STATUS, TO_CHAR(O.LAST_DDL_TIME, 'YYYY-MM-DD HH24:MI:SS') LAST_DDL,
       (SELECT COUNT(*) FROM USER_SOURCE S WHERE S.NAME = O.OBJECT_NAME AND S.TYPE = O.OBJECT_TYPE) SRC_LINES
  FROM USER_OBJECTS O
 WHERE O.OBJECT_NAME = 'PKG_DMF0074'
 ORDER BY O.OBJECT_TYPE;

WITH BASE AS (SELECT COLUMN_VALUE M FROM TABLE(SYS.ODCIVARCHAR2LIST(
                'E20260816-NULLFIX', 'E20260818-GTTDEL', 'E20260825-DASHRM', 'E20260825-DATECONV',
                'E20260827-D4', 'E20260827-D5', 'hook#150'))),
     KNOWN AS (SELECT M FROM BASE
               UNION ALL SELECT 'E20260918-KEYNAMETOCODE' FROM DUAL
               UNION ALL SELECT 'E20261001-EMPTYASIS' FROM DUAL),
     CUR AS (SELECT DISTINCT REGEXP_SUBSTR(S.TEXT, 'E20[0-9]{6}-[A-Z0-9_]+|hook#[0-9]+') M
               FROM USER_SOURCE S
              WHERE S.NAME = 'PKG_DMF0074' AND S.TYPE = 'PACKAGE BODY'
                AND REGEXP_LIKE(S.TEXT, 'E20[0-9]{6}-[A-Z0-9_]+|hook#[0-9]+'))
SELECT (SELECT LISTAGG(M, ',') WITHIN GROUP (ORDER BY M) FROM BASE WHERE M NOT IN (SELECT M FROM CUR)) BASE_MISSING,
       (SELECT LISTAGG(M, ',') WITHIN GROUP (ORDER BY M) FROM CUR WHERE M NOT IN (SELECT M FROM KNOWN)) CLOUD_ONLY,
       (SELECT LISTAGG(M, ',') WITHIN GROUP (ORDER BY M) FROM CUR
         WHERE M IN ('E20260918-KEYNAMETOCODE', 'E20261001-EMPTYASIS')) ALREADY_HAS,
       CASE WHEN NOT EXISTS (SELECT 1 FROM BASE WHERE M NOT IN (SELECT M FROM CUR))
             AND NOT EXISTS (SELECT 1 FROM CUR WHERE M NOT IN (SELECT M FROM KNOWN))
            THEN 'OK' ELSE 'STOP - 결과 공유' END VERDICT
  FROM DUAL;

-- 참고: 적재 대상 원장 컬럼 제약 (사내 = 문자 4컬럼 NOT NULL·DEFAULT ON NULL '-' / 숫자 4컬럼 NULL 허용)
SELECT TABLE_NAME, COLUMN_NAME, NULLABLE, DEFAULT_ON_NULL, TRIM(DATA_DEFAULT_VC) DEF
  FROM USER_TAB_COLUMNS
 WHERE TABLE_NAME IN ('DM_BPS_METAL_LINK_PRICE', 'DM_BPS_METAL_LINK_PRICE_H')
   AND COLUMN_NAME IN ('METAL_EXCEPTION_YN', 'APPLY_PRICE_TYPE_CODE', 'FROM_PERIOD_YYYYMM', 'TO_PERIOD_YYYYMM',
                       'ENERGY', 'CONTRACT_UNIT_PRICE', 'METAL_APPLY_UNIT_PRICE', 'METAL_REQR_QTY')
 ORDER BY TABLE_NAME, COLUMN_NAME;
