-- ============================================================================
-- [V] 검증 — 대상 객체 실측 (hook #136). 5행 모두 EXPECTED = ACTUAL 이어야 PASS.
-- ============================================================================
SELECT 'F1 PROJECT_CODE.ATTRIBUTE1' AS ITEM, 'PROJECT' AS EXPECTED,
       NVL(MAX(ATTRIBUTE1), '(행없음)') AS ACTUAL
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID='DMF0082' AND SHEET_NAME='FcstNPrice' AND COLUMN_NAME='PROJECT_CODE'
UNION ALL
SELECT 'F2 PLANT_SITE_ID.COMBO', 'FromSiteByDivision',
       NVL(MAX(CELL_COMBO_DATA_TYPE), '(행없음)')
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID='DMF0082' AND SHEET_NAME='FcstNPrice' AND COLUMN_NAME='PLANT_SITE_ID'
UNION ALL
SELECT 'F3 DEPT_ID has 40', 'Y',
       NVL(MAX(CASE WHEN INSTR(','||DIVISION_ID||',', ',40,')>0 THEN 'Y' ELSE 'N' END),'(행없음)')
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID='DMF0082' AND SHEET_NAME='FcstNPrice' AND COLUMN_NAME='DEPT_ID'
UNION ALL
SELECT 'F3 DEPT_NAME_KO has 40', 'Y',
       NVL(MAX(CASE WHEN INSTR(','||DIVISION_ID||',', ',40,')>0 THEN 'Y' ELSE 'N' END),'(행없음)')
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID='DMF0082' AND SHEET_NAME='FcstNPrice' AND COLUMN_NAME='DEPT_NAME_KO'
UNION ALL
SELECT 'F3 GROUP_ID has 40', 'Y',
       NVL(MAX(CASE WHEN INSTR(','||DIVISION_ID||',', ',40,')>0 THEN 'Y' ELSE 'N' END),'(행없음)')
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID='DMF0082' AND SHEET_NAME='FcstNPrice' AND COLUMN_NAME='GROUP_ID';

-- 회귀 가드 1 — PK 중복 0 (UPDATE 이므로 늘어나면 안 된다)
SELECT 'PK DUP' AS ITEM, COUNT(*) AS DUP_ROWS FROM (
  SELECT COLUMN_NAME FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
   WHERE PROGRAM_ID='DMF0082' AND SHEET_NAME='FcstNPrice'
   GROUP BY COLUMN_NAME HAVING COUNT(*) > 1);

-- 회귀 가드 2 — PLANT_SITE_ID 값 도메인이 조회조건과 정렬됐는지 (교집합 > 0 이어야 정상)
--   정정 전: 그리드(PLANT_ID) ∩ 조회조건(SITE_ID) = 0
SELECT 'PLANT DOMAIN MATCH(div81)' AS ITEM, COUNT(*) AS INTERSECT_ROWS FROM (
  SELECT SCM_SITE_ID V FROM SCM_MGR.SCM_MST_SITE
   WHERE SITE_TYPE='PLANT' AND VALID_YN='Y' AND INSTR(',81,', ','||DIVISION_ID||',')>0
  INTERSECT
  SELECT CODE FROM TABLE(SCM_MGR.PKG_SCM_CMBO.GET_PLANT_SITE('81')));
