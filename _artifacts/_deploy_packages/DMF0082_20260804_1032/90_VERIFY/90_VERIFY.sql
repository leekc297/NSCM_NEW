-- 1) PKG 컴파일 상태 — 기대: PACKAGE/PACKAGE BODY 모두 VALID
SELECT OBJECT_TYPE, STATUS FROM ALL_OBJECTS
WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_DMF0082';

-- 2) 컴파일 에러 — 기대: 0행
SELECT TYPE, LINE, TEXT FROM ALL_ERRORS
WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' ORDER BY SEQUENCE;

-- 3) GET 2종 시그니처 — 기대: 각 13 IN (P_PLANT_SITE_ID 말미, DEFAULT 'ALL') + 6 OUT
SELECT OBJECT_NAME, COUNT(CASE WHEN IN_OUT='IN' THEN 1 END) IN_CNT,
       COUNT(CASE WHEN IN_OUT='OUT' THEN 1 END) OUT_CNT
FROM ALL_ARGUMENTS
WHERE OWNER='SCM_MGR' AND PACKAGE_NAME='PKG_DMF0082'
  AND OBJECT_NAME IN ('P_DMF0082_GET_MAIN_DATA','P_DMF0082_GET_MAIN_DATA_CURRENT')
GROUP BY OBJECT_NAME;

-- 4) PROC_M — 기대: GET 2종 각 19행(MAX SORT_ORD 19, plantSiteId@13) / PKG 전체 = 사내 96행
SELECT PROC_NM, COUNT(*) CNT, MAX(SORT_ORD) MX
FROM SCM_MGR.SCM_ADM_PROC_M WHERE PROC_NM LIKE 'PKG_DMF0082.%'
GROUP BY PROC_NM ORDER BY 1;
SELECT PROC_NM, COL_NM, SORT_ORD FROM SCM_MGR.SCM_ADM_PROC_M
WHERE PROC_NM LIKE 'PKG_DMF0082.P_DMF0082_GET_MAIN_DATA%' AND COL_NM IN ('plantSiteId')
ORDER BY PROC_NM;

-- 5) 배선/권한 — 기대(사내 실측): API_M 15 / BTN_MPG 17 / USER_GR_MNU_MPG 6 / USER_GR_MNU_BTN_MPG 95
SELECT 'API_M' T, COUNT(*) C FROM SCM_MGR.SCM_ADM_API_M
 WHERE API_ID IN (SELECT API_ID FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID='DMF0082')
UNION ALL SELECT 'BTN_MPG', COUNT(*) FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID='DMF0082'
UNION ALL SELECT 'USER_GR_MNU_MPG', COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_MPG_M WHERE MNU_ID='DMF0082'
UNION ALL SELECT 'USER_GR_MNU_BTN_MPG', COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE MNU_ID='DMF0082';

-- 6) 시트 메타 — 기대(사내 실측): SHEET_COLUMNS 69 / SHEET_MEASURE 14
SELECT 'SHEET_COLUMNS' T, COUNT(*) C FROM SCM_MGR.SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID='DMF0082'
UNION ALL SELECT 'SHEET_MEASURE', COUNT(*) FROM SCM_MGR.SCM_MST_SHEET_MEASURE WHERE PROGRAM_ID='DMF0082';

-- 7) 콤보 — 기대: 12행 (FcstPriceUserAuthGroup 은 사내도 미등록 — README F-1)
SELECT SQL_ID FROM SCM_MGR.SCM_ADM_CMBO_SQL_M
WHERE SQL_ID IN ('SalesBucket','FcstPriceEditMeasure','BucketType','EndCustomer','CurrencyList',
                 'MyDivision','TeambyDivision','FcstType','CustomsHandbook','SalesSite',
                 'PlantSitebyEndCustomer','BizType')
ORDER BY SQL_ID;

-- 8) GTT — 기대: 58종 전부 존재 (00_GTT_DDL 참조 목록과 1:1)
SELECT COUNT(*) GTT_CNT FROM ALL_TABLES
WHERE OWNER='SCM_MGR' AND TEMPORARY='Y'
  AND (TABLE_NAME LIKE 'GT\_DMF0082\_%' ESCAPE '\' OR TABLE_NAME LIKE 'GTT\_%' ESCAPE '\'
       OR TABLE_NAME LIKE 'GT\_PRDM%' ESCAPE '\');

-- 9) 공용 선행 — 기대: 전부 VALID (0행/INVALID = 선행 패키지 미적용)
