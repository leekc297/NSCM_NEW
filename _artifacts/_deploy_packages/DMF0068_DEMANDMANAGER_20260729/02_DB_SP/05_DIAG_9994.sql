-- 05_DIAG_9994.sql — 【SCM_MGR 계정 세션】 DMF0068 조회 -9994 / PLS-00201 원인 판별
-- -9994 / `InvocationTargetException: null` 은 **래퍼**다. 그 자체로는 정보가 없다.

-- [1] ⭐ 1순위 — SYNONYM 소유자가 **애플리케이션(BE 접속) 계정과 일치하는가**
--     ⚠️ 계정 이름을 가정하지 말 것 — 클라우드=SCMP_APP(2026-07-30 변경) / 사내=SCMD_APP.
SELECT OWNER, SYNONYM_NAME, TABLE_OWNER
  FROM ALL_SYNONYMS
 WHERE TABLE_NAME IN ('PKG_DMF0068','PKG_DMF0044','PKG_DMF0049')
 ORDER BY SYNONYM_NAME, OWNER;
--     ↑ 정상 동작 중인 화면(PKG_DMF0044 등)의 OWNER = 애플리케이션 계정.
--       PKG_DMF0068 의 OWNER 가 그와 다르거나 없으면 → 그 계정으로 04_APP_SYNONYM_ONLY.sql 실행.

SELECT OWNER, COUNT(*) AS CNT
  FROM ALL_SYNONYMS WHERE TABLE_NAME LIKE 'PKG_%'
 GROUP BY OWNER ORDER BY CNT DESC;      -- 수가 많은 쪽이 애플리케이션 계정

-- [2] 실행 권한 — GRANTEE 가 위에서 확정한 계정이어야 함 (아니면 03_GRANT.sql 실행)
SELECT GRANTEE, PRIVILEGE, GRANTOR
  FROM ALL_TAB_PRIVS WHERE TABLE_NAME = 'PKG_DMF0068';

-- [3] 패키지 상태 (SCM_MGR PACKAGE + PACKAGE BODY 둘 다 VALID / ALL_ERRORS 0행)
SELECT OWNER, OBJECT_TYPE, STATUS, LAST_DDL_TIME
  FROM ALL_OBJECTS WHERE OBJECT_NAME = 'PKG_DMF0068' ORDER BY OBJECT_TYPE;
SELECT LINE, POSITION, TEXT FROM ALL_ERRORS
 WHERE NAME = 'PKG_DMF0068' ORDER BY SEQUENCE;

-- [4] PROC_M 메타 ↔ 실제 시그니처 positional 대조 (불일치 0행이어야 함)
SELECT NVL(p.PROC_NM, 'ARG-ONLY: '||a.PACKAGE_NAME||'.'||a.OBJECT_NAME) AS PROC_NM,
       p.SORT_ORD, p.COL_NM, p.COL_TP_CD, p.DATA_TP_CD,
       a.POSITION, a.ARGUMENT_NAME, a.IN_OUT, a.DATA_TYPE
  FROM (SELECT PROC_NM, COL_NM, COL_TP_CD, DATA_TP_CD, SORT_ORD
          FROM SCM_ADM_PROC_M WHERE PROC_NM LIKE 'PKG_DMF0068.%') p
  FULL OUTER JOIN
       (SELECT PACKAGE_NAME, OBJECT_NAME, POSITION, ARGUMENT_NAME, IN_OUT, DATA_TYPE
          FROM ALL_ARGUMENTS WHERE PACKAGE_NAME = 'PKG_DMF0068' AND POSITION > 0) a
    ON p.PROC_NM = a.PACKAGE_NAME||'.'||a.OBJECT_NAME AND p.SORT_ORD = a.POSITION
 WHERE p.PROC_NM IS NULL OR a.POSITION IS NULL
    OR UPPER(p.COL_NM) <> UPPER(a.ARGUMENT_NAME)
 ORDER BY 1, 2;

-- [5] 실오류 체인 확보 (위 [1]~[4] 가 전부 정상인데도 -9994 일 때)
SELECT LOG_ST_DTM, MNU_ID, MNU_BTN_CD, SHT_NM, EXCT_MSG_CTN, SYS_LOG_MSG_CTN
  FROM SCM_COM_SYS_LOG
 WHERE MNU_ID = 'DMF0068' AND EXCT_MSG_CTN IS NOT NULL
 ORDER BY LOG_ST_DTM DESC FETCH FIRST 20 ROWS ONLY;
-- BE 콘솔의 `Caused by:` 라인도 같은 값을 담고 있다.
