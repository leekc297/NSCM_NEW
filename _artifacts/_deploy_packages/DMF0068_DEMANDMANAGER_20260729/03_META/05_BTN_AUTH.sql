-- DMF0068 Demand Manager — 버튼 권한 (2026-07-29)
-- 확정 정책: 조회는 메뉴 권한(ADMIN / DM ADMIN / DM Viewer)으로 열고,
--            편집 계열(INSERT / EDIT / DELETE / SAVE)은 ADMIN / DM ADMIN 에만 부여한다.
--            (AS-IS 는 조회에도 편집권한을 요구했으나 TO-BE 는 완화 — SP 도 편집권한 뷰를 LEFT 로 정정)
-- 원본 실측: SCM_ADM_USER_GR_MNU_MPG_M 의 DMF0068 등록 그룹 3종
-- 멱등: 동일 (USER_GR_ID, MNU_ID, SHT_NM, MNU_BTN_CD) 존재 시 INSERT 하지 않음

INSERT INTO SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M (USER_GR_ID, MNU_ID, SHT_NM, MNU_BTN_CD, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT G.USER_GR_ID, 'DMF0068', B.SHT_NM, B.MNU_BTN_CD, 'Y', 'admin', SYSDATE, 'admin', SYSDATE
FROM SCM_MGR.SCM_ADM_USER_GR_MNU_MPG_M G
CROSS JOIN SCM_MGR.SCM_ADM_MNU_BTN_MPG_M B
WHERE G.MNU_ID = 'DMF0068'
  AND B.MNU_ID = 'DMF0068'
  AND (
        G.USER_GR_ID IN ('ADMIN', 'DM ADMIN')                       -- 전 버튼
     OR B.MNU_BTN_CD NOT IN ('INSERT', 'EDIT', 'DELETE', 'SAVE')     -- 조회 전용 그룹은 편집 계열 제외
      )
  AND NOT EXISTS (
        SELECT 1 FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M X
        WHERE X.USER_GR_ID = G.USER_GR_ID AND X.MNU_ID = 'DMF0068'
          AND X.SHT_NM = B.SHT_NM AND X.MNU_BTN_CD = B.MNU_BTN_CD
      );

COMMIT;

-- 검증 : ADMIN 12 / DM ADMIN 12 / DM Viewer 8 = 32건 기대
SELECT USER_GR_ID, COUNT(*) AS BTN_CNT
FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M
WHERE MNU_ID = 'DMF0068'
GROUP BY USER_GR_ID ORDER BY 1;
