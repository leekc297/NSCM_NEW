FROM (
    -- ① 메인 조회 : (P_DIVISION_ID, P_VERSION_NO, P_FROMDT, P_TODT, P_USER_ID, P_MENU_ID, O_RC1, O_RC2, O_RESULT_CURSOR)
    SELECT 'PKG_DMF0068.P_DMF0068_GET_ORDERLIST' AS PROC_NM, 'divisionId'      AS COL_NM, 'VARCHAR'     AS DATA_TP_CD, 'IN'  AS COL_TP_CD, '1' AS SORT_ORD FROM DUAL
    UNION ALL SELECT 'PKG_DMF0068.P_DMF0068_GET_ORDERLIST', 'versionNo',       'VARCHAR',     'IN',  '2' FROM DUAL
    UNION ALL SELECT 'PKG_DMF0068.P_DMF0068_GET_ORDERLIST', 'fromDt',          'VARCHAR',     'IN',  '3' FROM DUAL
    UNION ALL SELECT 'PKG_DMF0068.P_DMF0068_GET_ORDERLIST', 'toDt',            'VARCHAR',     'IN',  '4' FROM DUAL
    UNION ALL SELECT 'PKG_DMF0068.P_DMF0068_GET_ORDERLIST', 'sesUserId',       'VARCHAR',     'IN',  '5' FROM DUAL
    UNION ALL SELECT 'PKG_DMF0068.P_DMF0068_GET_ORDERLIST', 'mnuId',           'VARCHAR',     'IN',  '6' FROM DUAL
    UNION ALL SELECT 'PKG_DMF0068.P_DMF0068_GET_ORDERLIST', 'o_rc1',           'CURSOR',      'OUT', '7' FROM DUAL
    UNION ALL SELECT 'PKG_DMF0068.P_DMF0068_GET_ORDERLIST', 'o_rc2',           'CURSOR',      'OUT', '8' FROM DUAL
    UNION ALL SELECT 'PKG_DMF0068.P_DMF0068_GET_ORDERLIST', 'O_RESULT_CURSOR', 'PROC_RESULT', 'OUT', '9' FROM DUAL

    -- ② Project 콤보 : (P_DIVISION_ID, P_VERSION_NO, P_USER_ID, P_MENU_ID, O_RC1, O_RESULT_CURSOR)
    UNION ALL SELECT 'PKG_DMF0068.P_DMF0068_GET_LOOKUPPROJECT', 'divisionId',      'VARCHAR',     'IN',  '1' FROM DUAL
    UNION ALL SELECT 'PKG_DMF0068.P_DMF0068_GET_LOOKUPPROJECT', 'versionNo',       'VARCHAR',     'IN',  '2' FROM DUAL
    UNION ALL SELECT 'PKG_DMF0068.P_DMF0068_GET_LOOKUPPROJECT', 'sesUserId',       'VARCHAR',     'IN',  '3' FROM DUAL
    UNION ALL SELECT 'PKG_DMF0068.P_DMF0068_GET_LOOKUPPROJECT', 'mnuId',           'VARCHAR',     'IN',  '4' FROM DUAL
    UNION ALL SELECT 'PKG_DMF0068.P_DMF0068_GET_LOOKUPPROJECT', 'o_rc1',           'CURSOR',      'OUT', '5' FROM DUAL
    UNION ALL SELECT 'PKG_DMF0068.P_DMF0068_GET_LOOKUPPROJECT', 'O_RESULT_CURSOR', 'PROC_RESULT', 'OUT', '6' FROM DUAL

    -- ③ 버전 팝업 : (P_START_YYYYMMDD, P_END_YYYYMMDD, P_DIVISION_ID, P_VERSION_TYPE, P_DESCRIPTION, P_USER_ID, P_MENU_ID, O_RC1, O_RESULT_CURSOR)
    UNION ALL SELECT 'PKG_DMF0068.P_DMF0068_GET_CONT_VIEW_VERSIONPOPUP', 'startYyyymmdd',   'VARCHAR',     'IN',  '1' FROM DUAL
    UNION ALL SELECT 'PKG_DMF0068.P_DMF0068_GET_CONT_VIEW_VERSIONPOPUP', 'endYyyymmdd',     'VARCHAR',     'IN',  '2' FROM DUAL
    UNION ALL SELECT 'PKG_DMF0068.P_DMF0068_GET_CONT_VIEW_VERSIONPOPUP', 'divisionId',      'VARCHAR',     'IN',  '3' FROM DUAL
    UNION ALL SELECT 'PKG_DMF0068.P_DMF0068_GET_CONT_VIEW_VERSIONPOPUP', 'versionType',     'VARCHAR',     'IN',  '4' FROM DUAL
    UNION ALL SELECT 'PKG_DMF0068.P_DMF0068_GET_CONT_VIEW_VERSIONPOPUP', 'description',     'VARCHAR',     'IN',  '5' FROM DUAL
    UNION ALL SELECT 'PKG_DMF0068.P_DMF0068_GET_CONT_VIEW_VERSIONPOPUP', 'sesUserId',       'VARCHAR',     'IN',  '6' FROM DUAL
    UNION ALL SELECT 'PKG_DMF0068.P_DMF0068_GET_CONT_VIEW_VERSIONPOPUP', 'mnuId',           'VARCHAR',     'IN',  '7' FROM DUAL
    UNION ALL SELECT 'PKG_DMF0068.P_DMF0068_GET_CONT_VIEW_VERSIONPOPUP', 'o_rc1',           'CURSOR',      'OUT', '8' FROM DUAL
    UNION ALL SELECT 'PKG_DMF0068.P_DMF0068_GET_CONT_VIEW_VERSIONPOPUP', 'O_RESULT_CURSOR', 'PROC_RESULT', 'OUT', '9' FROM DUAL

    -- ④ 저장 래퍼 : (P_DATA CLOB, P_USER_ID, P_DIVISION_ID, P_VERSION_NO, O_RESULT_CURSOR)
    UNION ALL SELECT 'PKG_DMF0068.P_DMF0068_SAVE_ORDERLIST_JSON', 'data',            'CLOB',        'IN',  '1' FROM DUAL
    UNION ALL SELECT 'PKG_DMF0068.P_DMF0068_SAVE_ORDERLIST_JSON', 'sesUserId',       'VARCHAR',     'IN',  '2' FROM DUAL
