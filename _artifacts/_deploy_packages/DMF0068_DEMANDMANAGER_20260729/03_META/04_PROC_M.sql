    -- ⑤ 삭제 래퍼 : (P_DATA CLOB, O_RESULT_CURSOR)
    UNION ALL SELECT 'PKG_DMF0068.P_DMF0068_DEL_ORDERLIST_JSON', 'data',            'CLOB',        'IN',  '1' FROM DUAL
    UNION ALL SELECT 'PKG_DMF0068.P_DMF0068_DEL_ORDERLIST_JSON', 'O_RESULT_CURSOR', 'PROC_RESULT', 'OUT', '2' FROM DUAL
