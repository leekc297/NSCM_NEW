WHERE NOT EXISTS (
    SELECT 1 FROM SCM_MGR.SCM_ADM_PROC_M P
    WHERE P.PROC_NM = V.PROC_NM AND P.SORT_ORD = V.SORT_ORD
);

COMMIT;

-- 검증 : PROC_M ↔ ALL_ARGUMENTS positional 대조 (불일치 0행이어야 함)
SELECT P.PROC_NM, P.SORT_ORD, P.COL_NM, P.DATA_TP_CD, P.COL_TP_CD,
       A.ARGUMENT_NAME, A.DATA_TYPE, A.IN_OUT
FROM SCM_MGR.SCM_ADM_PROC_M P
LEFT JOIN ALL_ARGUMENTS A
       ON A.OWNER        = 'SCM_MGR'
      AND A.PACKAGE_NAME = SUBSTR(P.PROC_NM, 1, INSTR(P.PROC_NM, '.') - 1)
      AND A.OBJECT_NAME  = SUBSTR(P.PROC_NM, INSTR(P.PROC_NM, '.') + 1)
      AND A.POSITION     = TO_NUMBER(P.SORT_ORD)
WHERE P.PROC_NM LIKE 'PKG_DMF0068%'
  AND (A.ARGUMENT_NAME IS NULL
       OR (A.IN_OUT = 'IN'  AND P.COL_TP_CD <> 'IN')
       OR (A.IN_OUT = 'OUT' AND P.COL_TP_CD <> 'OUT'))
ORDER BY P.PROC_NM, TO_NUMBER(P.SORT_ORD);
