-- DMF0068 Demand Manager — API_M 배선 (2026-07-29)
-- 시트 3종: ContributeSalesList(main) / versionPopup / lookupProject
-- 클라이언트 전용 버튼(INSERT/EDIT/DELETE 마킹/SORT/FILTER/EXCEL/COLUMN_SETUP)은
-- 기존 화면(DMF0044)과 동일하게 메인 조회 프로시저를 API_URL 로 둔다.
-- 멱등: 동일 API_ID 존재 시 INSERT 하지 않음

INSERT INTO SCM_MGR.SCM_ADM_API_M (API_ID, API_TP_CD, API_MSG_ID, API_MSG_DESC, API_URL, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT V.API_ID, V.API_TP_CD, 'MSG_API_' || V.API_ID, V.DESCR, V.API_URL, 'Y', 'admin', SYSDATE, 'admin', SYSDATE
FROM (
    SELECT 'DMF0068_main_SEARCH'        AS API_ID, 'PROC_SELECT' AS API_TP_CD, 'DMF0068 소형 수주관리 조회 (월 동적 PIVOT)'      AS DESCR, 'PKG_DMF0068.P_DMF0068_GET_ORDERLIST'              AS API_URL FROM DUAL
    UNION ALL SELECT 'DMF0068_main_INSERT',        'PROC_SELECT', 'DMF0068 행 추가 (2행 1세트 — 클라이언트 동작)',   'PKG_DMF0068.P_DMF0068_GET_ORDERLIST'              FROM DUAL
    UNION ALL SELECT 'DMF0068_main_EDIT',          'PROC_SELECT', 'DMF0068 편집 모드 전환 (클라이언트 동작)',        'PKG_DMF0068.P_DMF0068_GET_ORDERLIST'              FROM DUAL
    UNION ALL SELECT 'DMF0068_main_SORT',          'PROC_SELECT', 'DMF0068 정렬 (클라이언트 동작)',               'PKG_DMF0068.P_DMF0068_GET_ORDERLIST'              FROM DUAL
    UNION ALL SELECT 'DMF0068_main_FILTER',        'PROC_SELECT', 'DMF0068 필터 (클라이언트 동작)',               'PKG_DMF0068.P_DMF0068_GET_ORDERLIST'              FROM DUAL
    UNION ALL SELECT 'DMF0068_main_EXCEL',         'PROC_SELECT', 'DMF0068 Excel Export',                    'PKG_DMF0068.P_DMF0068_GET_ORDERLIST'              FROM DUAL
    UNION ALL SELECT 'DMF0068_main_COLUMN_SETUP',  'PROC_SELECT', 'DMF0068 Column Setting 팝업 (공유)',          'DMF0002_GET_TITLESET_POPUP'                       FROM DUAL
    UNION ALL SELECT 'DMF0068_main_SAVE',          'PROC_SAVE',   'DMF0068 수주 저장 (CLOB JSON 래퍼)',            'PKG_DMF0068.P_DMF0068_SAVE_ORDERLIST_JSON'        FROM DUAL
    UNION ALL SELECT 'DMF0068_main_DELETE',        'PROC_SAVE',   'DMF0068 수주 삭제 (Measure 짝 동시 삭제, CLOB JSON 래퍼)', 'PKG_DMF0068.P_DMF0068_DEL_ORDERLIST_JSON' FROM DUAL
    UNION ALL SELECT 'DMF0068_main_SP_VER',        'PROC_SELECT', 'DMF0068 버전 팝업 열기',                      'PKG_DMF0068.P_DMF0068_GET_CONT_VIEW_VERSIONPOPUP' FROM DUAL
    UNION ALL SELECT 'DMF0068_versionPopup_SEARCH','PROC_SELECT', 'DMF0068 버전 목록 조회',                      'PKG_DMF0068.P_DMF0068_GET_CONT_VIEW_VERSIONPOPUP' FROM DUAL
    UNION ALL SELECT 'DMF0068_lookupProject_SEARCH','PROC_SELECT','DMF0068 Project 셀 콤보 목록 조회',            'PKG_DMF0068.P_DMF0068_GET_LOOKUPPROJECT'          FROM DUAL
) V
WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_API_M A WHERE A.API_ID = V.API_ID);

-- API 메시지(설명) 등록 — 3언어 동일 문구(기존 MSG_API_* 관행 준수)
INSERT INTO SCM_MGR.SCM_ADM_MSG_M (MSG_ID, LANG_CD, MSG_NM, MSG_TP_CD, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT A.API_MSG_ID, L.LANG_CD, A.API_MSG_DESC, 'MSG', 'Y', 'admin', SYSDATE, 'admin', SYSDATE
FROM SCM_MGR.SCM_ADM_API_M A
CROSS JOIN (SELECT 'KO' AS LANG_CD FROM DUAL UNION ALL SELECT 'EN' FROM DUAL UNION ALL SELECT 'CN' FROM DUAL) L
WHERE A.API_ID LIKE 'DMF0068%'
  AND NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_MSG_M M WHERE M.MSG_ID = A.API_MSG_ID AND M.LANG_CD = L.LANG_CD);

COMMIT;

-- 검증
SELECT API_ID, API_TP_CD, API_URL FROM SCM_MGR.SCM_ADM_API_M WHERE API_ID LIKE 'DMF0068%' ORDER BY API_ID;
