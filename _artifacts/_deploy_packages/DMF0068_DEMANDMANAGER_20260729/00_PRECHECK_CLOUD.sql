-- DMF0068 Demand Manager — 적용 전 사전 점검 (클라우드/사내 공통)
-- 적용 순서 : 00_PRECHECK → 02_DB_SP(SPEC→BODY) → 03_META(01→02→03→04→05→06) → 99_ROUTE_PATH
-- 목적 : ① 선행 객체 존재 여부 ② 신규 채번 충돌 ③ 권한 미러링 원본 실측

PROMPT ===== 1. 선행 객체 (모두 존재해야 함) =====
SELECT 'TYPE'  AS KIND, OBJECT_NAME, STATUS FROM ALL_OBJECTS
 WHERE OWNER='SCM_MGR' AND OBJECT_NAME IN ('T_DMF0068_ROW','T_DMF0068_TAB')
UNION ALL
SELECT 'TABLE', TABLE_NAME, 'N/A' FROM ALL_TABLES
 WHERE OWNER='SCM_MGR' AND TABLE_NAME IN (
   'DM_PLN_ORDER_MGT','DM_MDF_VERSION','DM_PLN_SALES_PLAN_C','DM_PLN_BP_FCST_C',
   'DM_PLN_SALES_PLAN_RESULT','DM_MST_ITEM_SINGLE_V','SCM_MST_SITE_ITEM','SCM_SYS_CALENDAR_M',
   'GT_DM68_ORD_ITEM_SINGLE_V','GT_DM68_ORD_CELL_PACK_COUNT','GT_DM68_ORD_PJTIFO',
   'GT_DM68_ORD_SRESULT_SPLAN','GT_DM68_ORD_BRESULT_BPLAN')
UNION ALL
SELECT 'VIEW', VIEW_NAME, 'N/A' FROM ALL_VIEWS
 WHERE OWNER='SCM_MGR' AND VIEW_NAME = 'SCM_ADM_USER_MNU_EDIT_AUTH_V'
UNION ALL
SELECT 'PROC', OBJECT_NAME, STATUS FROM ALL_OBJECTS
 WHERE OWNER='SCM_MGR' AND OBJECT_NAME = 'PR_SCM_SYS_LOG_BATCH'
ORDER BY 1, 2;

PROMPT ===== 2. 신규 채번 충돌 (모두 0행이어야 함) =====
SELECT 'MSG 충돌' AS CHK, MSG_ID, LANG_CD, MSG_NM FROM SCM_MGR.SCM_ADM_MSG_M
 WHERE MSG_ID BETWEEN 'MSG00699' AND 'MSG00702';

SELECT 'API 충돌' AS CHK, API_ID FROM SCM_MGR.SCM_ADM_API_M WHERE API_ID LIKE 'DMF0068%';

SELECT 'BTN 충돌' AS CHK, SHT_NM, MNU_BTN_CD FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID = 'DMF0068';

SELECT 'PROC 충돌' AS CHK, PROC_NM, COUNT(*) CNT FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM LIKE 'PKG_DMF0068%' GROUP BY PROC_NM;

PROMPT ===== 3. 채번 기준 (신규 MSG 는 이 MAX 다음이어야 함) =====
SELECT MAX(MSG_ID) AS MAX_MSG_ID FROM SCM_MGR.SCM_ADM_MSG_M
 WHERE REGEXP_LIKE(MSG_ID, '^MSG[0-9]{5}$') AND MSG_ID <> 'MSG99999';

PROMPT ===== 4. 권한 미러링 원본 실측 (3그룹이어야 함 — 0행이면 중단) =====
SELECT USER_GR_ID FROM SCM_MGR.SCM_ADM_USER_GR_MNU_MPG_M WHERE MNU_ID = 'DMF0068' ORDER BY 1;

PROMPT ===== 5. 컬럼 메타 실측 (159행 / 고정 16 + M1~M143) =====
SELECT CASE WHEN REGEXP_LIKE(COLUMN_NAME, '^M[0-9]+$') THEN 'M(월)' ELSE 'FIXED' END AS GRP,
       VISIBLE_FLAG, COUNT(*) AS CNT
FROM SCM_MGR.SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID = 'DMF0068'
GROUP BY CASE WHEN REGEXP_LIKE(COLUMN_NAME, '^M[0-9]+$') THEN 'M(월)' ELSE 'FIXED' END, VISIBLE_FLAG
ORDER BY 1, 2;

PROMPT ===== 6. 메뉴 현황 (slug 정정 대상) =====
SELECT MNU_ID, UPPR_MNU_ID, MNU_URL, ROUTE_PATH, MNU_DESC, UNIT_TP_CD, USE_YN
FROM SCM_MGR.SCM_ADM_MNU_M WHERE MNU_ID = 'DMF0068';

PROMPT ===== 7. 기존 PKG 상태 (적용 후 재확인 대상) =====
SELECT OBJECT_TYPE, STATUS FROM ALL_OBJECTS
 WHERE OWNER = 'SCM_MGR' AND OBJECT_NAME = 'PKG_DMF0068' ORDER BY OBJECT_TYPE;
