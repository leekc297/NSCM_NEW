UNION ALL
SELECT DISTINCT A.SCM_SITE_ID, A.SCM_SITE_ID, 2
FROM SCM_MST_SITE A
LEFT JOIN SCM_MST_SITE_ITEM B ON A.DIVISION_ID = B.DIVISION_ID AND A.SCM_SITE_ID = B.SCM_SITE_ID
