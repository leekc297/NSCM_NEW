LEFT JOIN (SELECT DISTINCT U.USER_ID, U.DEPT_ID FROM SCM_MST_SSO_USER_INFO U JOIN SCM_MST_SSO_DEPT_INFO D2 ON U.DEPT_ID = D2.DEPT_ID) C
  ON B.OWNER = C.USER_ID
WHERE A.SITE_TYPE = ''SALES'' AND A.DIVISION_ID = ''40'' AND A.VALID_YN = ''Y'' AND NVL(A.OPERATION_GROUP, '' '') <> ''W''
  AND (NVL(TRIM(@divisionId), ''ALL'') = ''ALL'' OR INSTR('','' || @divisionId || '','', '',40,'') > 0)
  AND (NVL(TRIM(@deptId), ''ALL'') = ''ALL'' OR INSTR('','' || @deptId || '','', '','' || C.DEPT_ID || '','') > 0)
  AND (NVL(TRIM(@endCustomer), ''ALL'') = ''ALL'' OR INSTR('','' || @endCustomer || '','', '','' || B.PROJECT_CODE || '','') > 0)
