WHEN MATCHED THEN UPDATE SET t.SQL_DTL_CTN='SELECT CODE, NAME FROM (
SELECT DISTINCT A.SCM_SITE_ID AS CODE, A.SCM_SITE_ID AS NAME, 2 AS SORT_ORDER
FROM SCM_MST_SITE A
WHERE A.SITE_TYPE = ''SALES'' AND A.VALID_YN = ''Y'' AND NVL(A.OPERATION_GROUP, '' '') <> ''W''
  AND A.DIVISION_ID <> ''40''
  AND (NVL(TRIM(@divisionId), ''ALL'') = ''ALL'' OR INSTR('','' || @divisionId || '','', '','' || A.DIVISION_ID || '','') > 0)
  AND (NVL(TRIM(@endCustomer), ''ALL'') = ''ALL'' OR INSTR('','' || @endCustomer || '','', '','' || A.END_CUSTOMER || '','') > 0)
