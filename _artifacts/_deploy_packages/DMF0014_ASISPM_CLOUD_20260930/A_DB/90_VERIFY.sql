COLUMN JUDGE FORMAT A40
PROMPT [V1] VALID · 오류 0
SELECT O.OBJECT_TYPE, O.STATUS,
       (SELECT COUNT(*) FROM USER_ERRORS E WHERE E.NAME=O.OBJECT_NAME AND E.TYPE=O.OBJECT_TYPE) ERR_CNT,
       CASE WHEN O.STATUS='VALID' AND (SELECT COUNT(*) FROM USER_ERRORS E WHERE E.NAME=O.OBJECT_NAME AND E.TYPE=O.OBJECT_TYPE)=0
            THEN 'PASS' ELSE '❌ FAIL' END JUDGE
  FROM USER_OBJECTS O WHERE O.OBJECT_NAME='PKG_DMF0014' ORDER BY O.OBJECT_TYPE;
PROMPT [V2] 지문 11483/748077 · 마커 ASISPM 4 · MDLIND 1
SELECT LN || '/' || CH BODY_FP,
       (SELECT COUNT(*) FROM USER_SOURCE WHERE NAME='PKG_DMF0014' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%E20260930-DMF0014ASISPM%') MARK,
       (SELECT COUNT(*) FROM USER_SOURCE WHERE NAME='PKG_DMF0014' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%E20260930-DMF0014MDLIND%') MARK_MDLIND,
       CASE WHEN LN = 11483 AND CH = 748077 THEN 'PASS' ELSE '❌ FAIL' END JUDGE
  FROM (SELECT COUNT(*) LN, SUM(LENGTH(RTRIM(TEXT, CHR(10)||CHR(13)))) CH FROM USER_SOURCE WHERE NAME='PKG_DMF0014' AND TYPE='PACKAGE BODY' AND LINE > 1);
