   WHERE PROGRAM_ID='DMF0003' AND SHEET_NAME='Mkt Fcst'
)
SELECT NVL(CORP.COL, CLD.COLUMN_NAME) AS COLUMN_NAME,
       CORP.VIS  AS CORP_VISIBLE, CLD.VISIBLE_FLAG         AS CLOUD_VISIBLE,
       CORP.DFLT AS CORP_DEFAULT, CLD.DEFAULT_FLAG         AS CLOUD_DEFAULT,
       CORP.USEL AS CORP_USERSEL, CLD.USER_SELECTABLE_FLAG AS CLOUD_USERSEL,
       CORP.VY   AS CORP_VALID,   CLD.VALID_YN             AS CLOUD_VALID,
       CASE WHEN CORP.COL IS NULL THEN 'CLOUD_ONLY(사내에 없음)'
            WHEN CLD.COLUMN_NAME IS NULL THEN 'CORP_ONLY(클라우드에 없음)'
            ELSE 'FLAG_DIFF' END AS DIFF_TYPE
  FROM CORP
  FULL OUTER JOIN CLD ON CLD.COLUMN_NAME=CORP.COL
 WHERE CORP.COL IS NULL
    OR CLD.COLUMN_NAME IS NULL
    OR NVL(CLD.VISIBLE_FLAG,'#')         <> NVL(CORP.VIS,'#')
    OR NVL(CLD.DEFAULT_FLAG,'#')         <> NVL(CORP.DFLT,'#')
    OR NVL(CLD.USER_SELECTABLE_FLAG,'#') <> NVL(CORP.USEL,'#')
    OR NVL(CLD.VALID_YN,'#')             <> NVL(CORP.VY,'#')
 ORDER BY DIFF_TYPE, COLUMN_NAME;
