/* =====================================================================================================
 * DMF0082 조회 속도 진단 · 20_DIAG_REPORT — 10_DIAG_RUN 기록 해석 (조회 전용 · 파일 전체 F5)
 * D0 권한 · D1 사업부별 요약 · D2 단계별 시간 · D3 문장 TOP · D4 계획 줄 TOP · D5 계획 이상 신호 · D6 대기 이벤트
 * D7 GTT 통계 상태 · D8 옵티마이저 환경 · D9 개선 후보 요약
 * 시간 단위: ASH 샘플 1개 ≈ 1초(이 세션이 일하던 시간). 실행(PROC)·읽기(FETCH) 모두 포함된다.
 * 단계(STAGE) = V$SQL.PROGRAM_LINE# 를 GET_MAIN_DATA 시작 줄 기준 상대 줄로 바꿔 판정(1104 원문 줄 기준):
 *   S0 273~496 파라미터 분해 · PATH 497~592 경로/버전 · S1 593~875 사이트·품목 · S2-L 876~1031 룩업 적재 · S2 1032~15508 사업부별 적재 INSERT · S3 15509~16434 동적 PIVOT·출력
 * ===================================================================================================== */
SET DEFINE OFF

-- D0 기록하지 못한 항목(권한 없음 등) — 0행이 정상. 행이 있으면 그 항목은 비어 있으니 함께 회신
SELECT 'D0' CHK, DIV, ITEM, MSG FROM ZB_DMF0082_DIAG_NOTE ORDER BY 2, 3;

-- D1 사업부별 요약 — PROC = 프로시저 실행 · FETCH = 6개 커서 전 행 읽기 · ASH_SEC = 이 세션 샘플(초) · CPU_PCT = 그중 CPU 비율 · TOP_WAIT = 가장 큰 대기
WITH A AS (SELECT DIV, SUM(SAMPLES) S, SUM(CASE WHEN EVENT = 'ON CPU' THEN SAMPLES ELSE 0 END) CPU FROM ZB_DMF0082_DIAG_ASH GROUP BY DIV),
     W AS (SELECT DIV, EVENT, SAMPLES, ROW_NUMBER() OVER (PARTITION BY DIV ORDER BY SAMPLES DESC) RN FROM (SELECT DIV, EVENT, SUM(SAMPLES) SAMPLES FROM ZB_DMF0082_DIAG_ASH WHERE EVENT <> 'ON CPU' GROUP BY DIV, EVENT))
SELECT 'D1' CHK, R.DIV, R.PKG, R.USER_ID, R.PROC_SEC, R.FETCH_SEC, R.PROC_SEC + R.FETCH_SEC TOTAL_SEC, R.R1 ROWS_MAIN, R.C1 COLS_MAIN,
       A.S ASH_SEC, ROUND(A.CPU / NULLIF(A.S, 0) * 100) CPU_PCT, W.EVENT TOP_WAIT, W.SAMPLES TOP_WAIT_SEC, R.ERR
  FROM ZB_DMF0082_DIAG_RUN R LEFT JOIN A ON A.DIV = R.DIV LEFT JOIN W ON W.DIV = R.DIV AND W.RN = 1
 ORDER BY R.DIV;

-- D2 단계별 시간(초 · 비율) — 어느 단계가 가장 큰지
WITH S AS (SELECT SQL_ID, MAX(PROGRAM_ID) PROGRAM_ID, MAX(PROGRAM_LINE) PROGRAM_LINE FROM ZB_DMF0082_DIAG_SQL GROUP BY SQL_ID),
     X AS (SELECT A.DIV, A.SAMPLES,
                  CASE WHEN A.SQL_ID IS NULL THEN 'PL/SQL·기타'
                       WHEN S.PROGRAM_ID IS NULL OR S.PROGRAM_ID <> R.BODY_OBJ_ID THEN '패키지 밖 SQL(' || A.SQL_ID || ')'
                       ELSE CASE WHEN S.PROGRAM_LINE - R.GMD_L1 + 8 BETWEEN 15509 AND 16434 THEN 'S3 동적 PIVOT·출력'
                                 WHEN S.PROGRAM_LINE - R.GMD_L1 + 8 BETWEEN 1032 AND 15508 THEN 'S2 사업부별 적재'
                                 WHEN S.PROGRAM_LINE - R.GMD_L1 + 8 BETWEEN 876 AND 1031 THEN 'S2-L 룩업 적재'
                                 WHEN S.PROGRAM_LINE - R.GMD_L1 + 8 BETWEEN 593 AND 875 THEN 'S1 사이트·품목'
                                 WHEN S.PROGRAM_LINE - R.GMD_L1 + 8 BETWEEN 497 AND 592 THEN 'PATH 경로·버전'
                                 WHEN S.PROGRAM_LINE - R.GMD_L1 + 8 BETWEEN 273 AND 496 THEN 'S0 파라미터'
                                 ELSE '기타 줄 ' || (S.PROGRAM_LINE - R.GMD_L1 + 8) END END STAGE
             FROM ZB_DMF0082_DIAG_ASH A JOIN ZB_DMF0082_DIAG_RUN R ON R.DIV = A.DIV LEFT JOIN S ON S.SQL_ID = A.SQL_ID)
SELECT 'D2' CHK, DIV, STAGE, SUM(SAMPLES) SEC, ROUND(SUM(SAMPLES) / NULLIF(SUM(SUM(SAMPLES)) OVER (PARTITION BY DIV), 0) * 100, 1) PCT
  FROM X GROUP BY DIV, STAGE ORDER BY DIV, SEC DESC;

-- D3 문장 TOP 15(사업부별) — SEC = ASH 초 · REL_LINE = 1104 원문 기준 줄 · EXECS/ELA = V$SQL 누적값(이 세션 외 실행 포함)
WITH S AS (SELECT SQL_ID, MAX(PROGRAM_ID) PROGRAM_ID, MAX(PROGRAM_LINE) PROGRAM_LINE, MAX(EXECUTIONS) EXECS, MAX(ELAPSED_SEC) ELA, MAX(SQL_TEXT) TXT,
                  COUNT(DISTINCT PLAN_HASH) N_PLANS FROM ZB_DMF0082_DIAG_SQL GROUP BY SQL_ID),
     X AS (SELECT A.DIV, A.SQL_ID, SUM(A.SAMPLES) SEC, MAX(A.TEMP_MB) TEMP_MB FROM ZB_DMF0082_DIAG_ASH A GROUP BY A.DIV, A.SQL_ID),
     Y AS (SELECT X.*, ROW_NUMBER() OVER (PARTITION BY X.DIV ORDER BY X.SEC DESC) RN, ROUND(X.SEC / NULLIF(SUM(X.SEC) OVER (PARTITION BY X.DIV), 0) * 100, 1) PCT FROM X)
SELECT 'D3' CHK, Y.DIV, Y.RN, Y.SQL_ID, Y.SEC, Y.PCT, Y.TEMP_MB,
       CASE WHEN S.PROGRAM_ID = R.BODY_OBJ_ID THEN S.PROGRAM_LINE - R.GMD_L1 + 8 END REL_LINE, S.N_PLANS, S.EXECS, S.ELA, SUBSTR(S.TXT, 1, 160) SQL_TEXT
  FROM Y JOIN ZB_DMF0082_DIAG_RUN R ON R.DIV = Y.DIV LEFT JOIN S ON S.SQL_ID = Y.SQL_ID
 WHERE Y.RN <= 15 ORDER BY Y.DIV, Y.RN;

-- D4 실행계획 줄 TOP 20(사업부별) — 어떤 연산·객체에서 시간을 썼는지 (OBJECT 는 SQL Monitor 기록이 있을 때만)
WITH X AS (SELECT DIV, SQL_ID, PLAN_HASH, PLAN_LINE, OPERATION || ' ' || OPTIONS OP, EVENT, SUM(SAMPLES) SEC, MAX(TEMP_MB) TEMP_MB
             FROM ZB_DMF0082_DIAG_ASH WHERE SQL_ID IS NOT NULL GROUP BY DIV, SQL_ID, PLAN_HASH, PLAN_LINE, OPERATION || ' ' || OPTIONS, EVENT),
     Y AS (SELECT X.*, ROW_NUMBER() OVER (PARTITION BY DIV ORDER BY SEC DESC) RN FROM X),
     P AS (SELECT DIV, SQL_ID, PLAN_LINE, MAX(OBJECT_NAME) OBJ, MAX(EST_ROWS) EST_ROWS, MAX(ACT_ROWS) ACT_ROWS, MAX(STARTS) STARTS FROM ZB_DMF0082_DIAG_PMON GROUP BY DIV, SQL_ID, PLAN_LINE)
SELECT 'D4' CHK, Y.DIV, Y.RN, Y.SQL_ID, Y.PLAN_LINE, Y.OP, P.OBJ, Y.EVENT, Y.SEC, Y.TEMP_MB, P.EST_ROWS, P.STARTS, P.ACT_ROWS
  FROM Y LEFT JOIN P ON P.DIV = Y.DIV AND P.SQL_ID = Y.SQL_ID AND P.PLAN_LINE = Y.PLAN_LINE
 WHERE Y.RN <= 20 ORDER BY Y.DIV, Y.RN;

-- D5 계획 이상 신호(SQL Monitor 기록 문장만) — 행 수 오추정 · 행마다 반복 · 카티션 · TEMP 사용
--   EST_ROWS 는 1회 실행당 예상, ACT_ROWS 는 전체 실제(STARTS 회 합계) → 비교는 EST_ROWS × STARTS 기준
SELECT 'D5' CHK, DIV, SQL_ID, PLAN_LINE, DEPTH, OPERATION || ' ' || OPTIONS OP, OBJECT_NAME, EST_ROWS, STARTS, ACT_ROWS, TEMP_MB, READ_MB,
       RTRIM(CASE WHEN ACT_ROWS >= 1000 AND ACT_ROWS > 10 * GREATEST(NVL(EST_ROWS, 0) * GREATEST(STARTS, 1), 1) THEN '과소추정(실제가 10배+) · ' END
          || CASE WHEN ACT_ROWS * 10 < NVL(EST_ROWS, 0) * GREATEST(STARTS, 1) AND NVL(EST_ROWS, 0) * GREATEST(STARTS, 1) >= 10000 THEN '과대추정(예상이 10배+) · ' END
          || CASE WHEN STARTS >= 10000 THEN '행마다 반복(STARTS ' || STARTS || ') · ' END
          || CASE WHEN OPERATION LIKE 'MERGE JOIN' AND OPTIONS LIKE 'CARTESIAN%' THEN '카티션 조인 · ' END
          || CASE WHEN NVL(TEMP_MB, 0) > 0 THEN 'TEMP ' || TEMP_MB || 'MB · ' END, ' · ') SIGNAL
  FROM ZB_DMF0082_DIAG_PMON
 WHERE (ACT_ROWS >= 1000 AND ACT_ROWS > 10 * GREATEST(NVL(EST_ROWS, 0) * GREATEST(STARTS, 1), 1))
    OR (ACT_ROWS * 10 < NVL(EST_ROWS, 0) * GREATEST(STARTS, 1) AND NVL(EST_ROWS, 0) * GREATEST(STARTS, 1) >= 10000)
    OR STARTS >= 10000 OR (OPERATION = 'MERGE JOIN' AND OPTIONS LIKE 'CARTESIAN%') OR NVL(TEMP_MB, 0) > 0
 ORDER BY DIV, SQL_ID, PLAN_LINE;

-- D6 대기 이벤트(사업부별 · 조회 전후 차이 상위 8개) — 'direct path read/write temp' = 정렬·해시 TEMP · 'db file sequential read' = 인덱스/행 단위 읽기 · 'cell/… multiblock' = 전체 스캔
WITH D AS (SELECT A.DIV, A.EVENT, A.WAIT_CLASS, A.WAITS - NVL(B.WAITS, 0) WAITS, ROUND(A.TIME_SEC - NVL(B.TIME_SEC, 0), 2) SEC
             FROM ZB_DMF0082_DIAG_EVT A LEFT JOIN ZB_DMF0082_DIAG_EVT B ON B.DIV = A.DIV AND B.EVENT = A.EVENT AND B.PHASE = 'B'
            WHERE A.PHASE = 'A' AND A.WAIT_CLASS <> 'Idle'),
     Y AS (SELECT D.*, ROW_NUMBER() OVER (PARTITION BY DIV ORDER BY SEC DESC) RN FROM D WHERE SEC > 0)
SELECT 'D6' CHK, DIV, RN, EVENT, WAIT_CLASS, WAITS, SEC FROM Y WHERE RN <= 8 ORDER BY DIV, RN;

-- D7 GT_DMF0082 임시표 통계 상태 — NUM_ROWS/LAST_ANALYZED 가 비어 있으면 통계 없음(동적 샘플링에 의존)
SELECT 'D7' CHK, COUNT(*) GTT_CNT, SUM(CASE WHEN LAST_ANALYZED IS NOT NULL THEN 1 ELSE 0 END) WITH_STATS,
       LISTAGG(CASE WHEN LAST_ANALYZED IS NOT NULL THEN TABLE_NAME || '(' || NUM_ROWS || ')' END, ', ') WITHIN GROUP (ORDER BY TABLE_NAME) STATS_TABLES
  FROM USER_TAB_STATISTICS WHERE TABLE_NAME LIKE 'GT\_DMF0082\_%' ESCAPE '\' AND OBJECT_TYPE = 'TABLE';

-- D8 옵티마이저 환경 (사내 기준: optimizer_dynamic_sampling 2 · optimizer_adaptive_plans TRUE · cursor_sharing EXACT)
SELECT 'D8' CHK, NAME, VALUE FROM ZB_DMF0082_DIAG_ENV ORDER BY NAME;

-- D9 개선 후보 요약(자동 판정 · 근거 숫자 포함) — 이 결과와 D2~D6 을 회신해 주시면 대상 문장을 특정해 개선안을 만듭니다
WITH R AS (SELECT DIV, PROC_SEC, FETCH_SEC FROM ZB_DMF0082_DIAG_RUN),
     T AS (SELECT DIV, SUM(SAMPLES) S,
                  SUM(CASE WHEN EVENT LIKE '%temp%' THEN SAMPLES ELSE 0 END) TEMP_S,
                  SUM(CASE WHEN EVENT IN ('db file sequential read', 'cell single block physical read') THEN SAMPLES ELSE 0 END) SB_S,
                  SUM(CASE WHEN EVENT LIKE '%multiblock%' OR EVENT LIKE 'direct path read' OR EVENT LIKE 'cell smart table scan' THEN SAMPLES ELSE 0 END) MB_S,
                  SUM(CASE WHEN EVENT = 'ON CPU' THEN SAMPLES ELSE 0 END) CPU_S
             FROM ZB_DMF0082_DIAG_ASH GROUP BY DIV),
     P AS (SELECT DIV, SUM(CASE WHEN ACT_ROWS >= 1000 AND ACT_ROWS > 10 * GREATEST(NVL(EST_ROWS, 0) * GREATEST(STARTS, 1), 1) THEN 1 ELSE 0 END) UNDER_EST,
                  SUM(CASE WHEN STARTS >= 10000 THEN 1 ELSE 0 END) NL_REPEAT, SUM(CASE WHEN NVL(TEMP_MB, 0) > 0 THEN 1 ELSE 0 END) TEMP_LINES
             FROM ZB_DMF0082_DIAG_PMON GROUP BY DIV)
SELECT 'D9' CHK, R.DIV, R.PROC_SEC, R.FETCH_SEC,
       RTRIM(CASE WHEN R.FETCH_SEC >= R.PROC_SEC * 0.4 THEN '① 읽기(FETCH) 비중 ' || ROUND(R.FETCH_SEC / NULLIF(R.PROC_SEC + R.FETCH_SEC, 0) * 100) || '% — 출력 열 수(PIVOT)·행 수가 원인 후보 · ' END
          || CASE WHEN T.TEMP_S >= 0.15 * T.S THEN '② TEMP 대기 ' || T.TEMP_S || '초 — 정렬/해시 메모리 부족(PGA) 또는 큰 GROUP BY·PIVOT · ' END
          || CASE WHEN T.SB_S >= 0.15 * T.S THEN '③ 단일 블록 읽기 ' || T.SB_S || '초 — 행 단위 인덱스 접근(NL) · 인덱스/조인 방식 점검 · ' END
          || CASE WHEN T.MB_S >= 0.15 * T.S THEN '④ 다중 블록 읽기 ' || T.MB_S || '초 — 큰 표 전체 스캔 · 조건 범위/인덱스 점검 · ' END
          || CASE WHEN T.CPU_S >= 0.5 * T.S THEN '⑤ CPU ' || T.CPU_S || '초 — 행 처리량(중복 집계·함수 호출) · ' END
          || CASE WHEN NVL(P.UNDER_EST, 0) > 0 THEN '⑥ 과소추정 ' || P.UNDER_EST || '줄 — GTT 통계/카디널리티(D7) · ' END
          || CASE WHEN NVL(P.NL_REPEAT, 0) > 0 THEN '⑦ 행마다 반복 ' || P.NL_REPEAT || '줄 — 조인 방식 · ' END, ' · ') CANDIDATES
  FROM R LEFT JOIN T ON T.DIV = R.DIV LEFT JOIN P ON P.DIV = R.DIV ORDER BY R.DIV;
