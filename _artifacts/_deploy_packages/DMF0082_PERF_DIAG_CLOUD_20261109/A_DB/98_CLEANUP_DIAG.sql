SET SERVEROUTPUT ON SIZE UNLIMITED
DECLARE
    n PLS_INTEGER := 0;
BEGIN
    FOR t IN (SELECT TABLE_NAME FROM USER_TABLES WHERE TABLE_NAME LIKE 'ZB\_DMF0082\_DIAG\_%' ESCAPE '\') LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.TABLE_NAME || ' PURGE';
        DBMS_OUTPUT.PUT_LINE('DROPPED ' || t.TABLE_NAME); n := n + 1;
    END LOOP;
    IF n = 0 THEN DBMS_OUTPUT.PUT_LINE('SKIP — 진단 기록표 없음'); END IF;
END;
