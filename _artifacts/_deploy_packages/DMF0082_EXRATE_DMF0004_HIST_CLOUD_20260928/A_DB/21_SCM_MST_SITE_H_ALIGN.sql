-- [E20260928-D4HIST] SCM_MST_SITE_H ← SCM_MST_SITE 정합 (SITE 컬럼 + HISTORY_SEQ/HISTORY_CREATION_DATE 만 추가) — 조건부·멱등
--   SCM_SITE_ID 60 CHAR / DEPT_ID 맨 끝·NULL 허용·기본값 없음 / VALID_YN DEFAULT 'N' NOT NULL / 감사 4컬럼 NULL 허용 유지
--   DEFAULT ON NULL 은 NOT NULL 을 내포한다: ON NULL 해제(기본값 변경) 시 NOT NULL 도 같이 풀림 → VALID_YN 은 재설정 (사내 실측)
SET SERVEROUTPUT ON
DECLARE
    V_CNT NUMBER; V_LEN NUMBER; V_NULL VARCHAR2(1); V_ONNULL VARCHAR2(3); V_DEF VARCHAR2(4000); V_ID NUMBER; V_MAXID NUMBER;
    PROCEDURE X(P VARCHAR2) IS BEGIN EXECUTE IMMEDIATE P; DBMS_OUTPUT.PUT_LINE('OK   ' || P); END;
    PROCEDURE COL(P_COL VARCHAR2) IS
    BEGIN
        SELECT CHAR_LENGTH, NULLABLE, DEFAULT_ON_NULL, COLUMN_ID INTO V_LEN, V_NULL, V_ONNULL, V_ID
          FROM USER_TAB_COLUMNS WHERE TABLE_NAME='SCM_MST_SITE_H' AND COLUMN_NAME=P_COL;
        SELECT DATA_DEFAULT INTO V_DEF FROM USER_TAB_COLUMNS WHERE TABLE_NAME='SCM_MST_SITE_H' AND COLUMN_NAME=P_COL;
    END;
BEGIN
    SELECT COUNT(*) INTO V_CNT FROM USER_TABLES WHERE TABLE_NAME='SCM_MST_SITE_H_BAK20260928';
    IF V_CNT = 0 THEN X('CREATE TABLE SCM_MST_SITE_H_BAK20260928 AS SELECT * FROM SCM_MST_SITE_H');
    ELSE DBMS_OUTPUT.PUT_LINE('SKIP backup exists'); END IF;

    COL('SCM_SITE_ID');
    IF V_LEN < 60 THEN X('ALTER TABLE SCM_MST_SITE_H MODIFY (SCM_SITE_ID VARCHAR2(60 CHAR))');
    ELSE DBMS_OUTPUT.PUT_LINE('SKIP SCM_SITE_ID len=' || V_LEN); END IF;

    COL('DEPT_ID');
    IF V_ONNULL = 'YES' OR TRIM(V_DEF) IS NOT NULL AND UPPER(TRIM(V_DEF)) <> 'NULL' THEN X('ALTER TABLE SCM_MST_SITE_H MODIFY (DEPT_ID DEFAULT NULL)'); END IF;
    COL('DEPT_ID');
    IF V_NULL = 'N' THEN X('ALTER TABLE SCM_MST_SITE_H MODIFY (DEPT_ID NULL)');
    ELSE DBMS_OUTPUT.PUT_LINE('SKIP DEPT_ID nullable'); END IF;

    COL('VALID_YN');
    IF V_ONNULL = 'YES' OR NVL(TRIM(V_DEF),'-') <> '''N''' THEN X('ALTER TABLE SCM_MST_SITE_H MODIFY (VALID_YN DEFAULT ''N'')'); END IF;
    COL('VALID_YN');
    IF V_NULL = 'Y' THEN X('ALTER TABLE SCM_MST_SITE_H MODIFY (VALID_YN NOT NULL)');
    ELSE DBMS_OUTPUT.PUT_LINE('SKIP VALID_YN not null'); END IF;

    -- 순서: DEPT_ID = 끝에서 두 번째, HISTORY_CREATION_DATE = 마지막
    SELECT MAX(COLUMN_ID) INTO V_MAXID FROM USER_TAB_COLUMNS WHERE TABLE_NAME='SCM_MST_SITE_H';
    COL('DEPT_ID');
    IF V_ID <> V_MAXID - 1 THEN
        X('ALTER TABLE SCM_MST_SITE_H MODIFY (DEPT_ID INVISIBLE)');
        X('ALTER TABLE SCM_MST_SITE_H MODIFY (DEPT_ID VISIBLE)');
        X('ALTER TABLE SCM_MST_SITE_H MODIFY (HISTORY_CREATION_DATE INVISIBLE)');
        X('ALTER TABLE SCM_MST_SITE_H MODIFY (HISTORY_CREATION_DATE VISIBLE)');
    ELSE DBMS_OUTPUT.PUT_LINE('SKIP column order'); END IF;
END;
