SET SERVEROUTPUT ON PAGESIZE 200 LINESIZE 250
PROMPT [V1] 객체 상태 (전부 VALID · standalone HIST 3종 부재 기대)
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM USER_OBJECTS
 WHERE OBJECT_NAME IN ('PKG_DMF0000','PKG_DMF0020','PKG_DMF0004','DMF0020_SAVE_SCM_MST_FUTURE_PRICE_ALL',
                       'PR_DM_MST_SITE_HIST','PR_DM_MST_SITE_SLOC_MAPPING_HIST','PR_DM_MST_BUCKET_CONVERSION_HIST',
                       'PR_SCM_MST_SITE_HIST','PKG_DMF0008','PKG_SCP0001','DMF0008_SAVE_SALES_SITE_EDI_REPAIR')
 ORDER BY 1,2;
PROMPT [V2] PKG_DMF0000 Sales Plan 호출 활성 (ACTIVE=1 · TODO_MARK=0 기대)
SELECT SUM(CASE WHEN REGEXP_LIKE(TEXT,'^\s*SCM_MGR\.PR_DM_ANL_SALES_PLAN_AMT_CREATE_LOCAL_KRW\(V_DIVISION_ID') THEN 1 ELSE 0 END) ACTIVE,
       SUM(CASE WHEN TEXT LIKE '%/* TO-DO 4/1%' THEN 1 ELSE 0 END) TODO_MARK
  FROM USER_SOURCE WHERE NAME='PKG_DMF0000' AND TYPE='PACKAGE BODY';
PROMPT [V3] SCM_MST_SITE_H 정합 단언 (BAD=0 기대 — 순서·타입·길이 / DEPT_ID·VALID_YN NULL·ON NULL / 이력 컬럼 위치)
SELECT COUNT(*) BAD FROM (
    SELECT S.COLUMN_NAME FROM USER_TAB_COLUMNS S
      LEFT JOIN USER_TAB_COLUMNS H ON H.TABLE_NAME='SCM_MST_SITE_H' AND H.COLUMN_NAME=S.COLUMN_NAME
     WHERE S.TABLE_NAME='SCM_MST_SITE'
       AND (H.COLUMN_NAME IS NULL OR H.COLUMN_ID <> S.COLUMN_ID + 1 OR H.DATA_TYPE <> S.DATA_TYPE
            OR NVL(H.CHAR_LENGTH,0) <> NVL(S.CHAR_LENGTH,0) OR NVL(H.DATA_PRECISION,-1) <> NVL(S.DATA_PRECISION,-1)
            OR (S.COLUMN_NAME IN ('DEPT_ID','VALID_YN') AND (H.NULLABLE <> S.NULLABLE OR H.DEFAULT_ON_NULL <> S.DEFAULT_ON_NULL)))
    UNION ALL SELECT 'HISTORY_SEQ' FROM USER_TAB_COLUMNS WHERE TABLE_NAME='SCM_MST_SITE_H' AND COLUMN_NAME='HISTORY_SEQ' AND COLUMN_ID<>1
    UNION ALL SELECT 'HISTORY_CREATION_DATE' FROM USER_TAB_COLUMNS WHERE TABLE_NAME='SCM_MST_SITE_H' AND COLUMN_NAME='HISTORY_CREATION_DATE'
       AND COLUMN_ID <> (SELECT MAX(COLUMN_ID) FROM USER_TAB_COLUMNS WHERE TABLE_NAME='SCM_MST_SITE_H'));
PROMPT [V4] 이력 행수 보존 (BAK 대비 차이 0 기대)
SELECT (SELECT COUNT(*) FROM SCM_MST_SITE_H) H_ROWS, (SELECT COUNT(*) FROM SCM_MST_SITE_H_BAK20260928) BAK_ROWS FROM DUAL;
PROMPT [V5] 이력 멤버 드라이런 (+1/+1/+1 후 ROLLBACK · 영속 0 · 내부 COMMIT 없음)
DECLARE
    V_DIV VARCHAR2(50); V_SITE VARCHAR2(100); N0 NUMBER; N1 NUMBER; L0 NUMBER; L1 NUMBER; B0 NUMBER; B1 NUMBER;
BEGIN
    SELECT S.DIVISION_ID, S.SCM_SITE_ID INTO V_DIV, V_SITE FROM SCM_MST_SITE S
     WHERE S.SITE_TYPE='SALES' AND S.VALID_YN='Y'
       AND EXISTS (SELECT 1 FROM SCM_MST_LOCATION L WHERE L.DIVISION_ID=S.DIVISION_ID AND L.SCM_SITE_ID=S.SCM_SITE_ID)
       AND EXISTS (SELECT 1 FROM DM_MST_BUCKET_CONVERSION B WHERE B.DIVISION_ID=S.DIVISION_ID AND B.SCM_SITE_ID=S.SCM_SITE_ID)
       AND ROWNUM = 1;
    SELECT COUNT(*) INTO N0 FROM SCM_MST_SITE_H; SELECT COUNT(*) INTO L0 FROM SCM_MST_LOCATION_H; SELECT COUNT(*) INTO B0 FROM DM_MST_BUCKET_CONVERSION_H;
    PKG_DMF0004.P_PR_DM_MST_SITE_HIST(V_DIV, V_SITE);
    FOR L IN (SELECT * FROM SCM_MST_LOCATION WHERE DIVISION_ID=V_DIV AND SCM_SITE_ID=V_SITE AND ROWNUM=1) LOOP
        PKG_DMF0004.P_PR_DM_MST_SITE_SLOC_MAPPING_HIST(TO_CHAR(L.LOCATION_SEQ), L.DIVISION_ID, L.LOCATION_CODE, L.LOCATION_DESCRIPTION,
            L.SCM_SITE_ID, L.PLANT_ID, '***', '***', L.STORAGE_ID, NULL, L.VALID_YN, 'VERIFY');
    END LOOP;
    FOR B IN (SELECT * FROM DM_MST_BUCKET_CONVERSION WHERE DIVISION_ID=V_DIV AND SCM_SITE_ID=V_SITE AND ROWNUM=1) LOOP
        PKG_DMF0004.P_PR_DM_MST_BUCKET_CONVERSION_HIST(B.DIVISION_ID, B.SCM_SITE_ID, B.INCOTERMS, B.YYYYMMDD, B.BUCKET_PER, B.CONVERSION_TYPE, 'VERIFY');
    END LOOP;
    SELECT COUNT(*) INTO N1 FROM SCM_MST_SITE_H; SELECT COUNT(*) INTO L1 FROM SCM_MST_LOCATION_H; SELECT COUNT(*) INTO B1 FROM DM_MST_BUCKET_CONVERSION_H;
    DBMS_OUTPUT.PUT_LINE('sample ' || V_DIV || '/' || V_SITE || '  SITE_H +' || (N1-N0) || '  LOCATION_H +' || (L1-L0) || '  BUCKET_H +' || (B1-B0) || '  (기대 +1/+1/+1)');
    ROLLBACK;
    SELECT COUNT(*) INTO N1 FROM SCM_MST_SITE_H; SELECT COUNT(*) INTO L1 FROM SCM_MST_LOCATION_H; SELECT COUNT(*) INTO B1 FROM DM_MST_BUCKET_CONVERSION_H;
    DBMS_OUTPUT.PUT_LINE('after ROLLBACK  ' || (N1-N0) || '/' || (L1-L0) || '/' || (B1-B0) || '  (기대 0/0/0)');
END;
