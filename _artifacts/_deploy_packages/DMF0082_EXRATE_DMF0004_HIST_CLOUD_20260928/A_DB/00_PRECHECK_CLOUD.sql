       CASE WHEN COUNT(*)=1148 AND SUM(LENGTH(RTRIM(TEXT, CHR(10)||CHR(13))))=46825 THEN 'MATCH_BEFORE → 적용 가능'
            WHEN COUNT(*)=1149  AND SUM(LENGTH(RTRIM(TEXT, CHR(10)||CHR(13))))=47086  THEN 'MATCH_AFTER → 이미 적용됨(SKIP 가능)'
            WHEN COUNT(*)=0 THEN 'MISSING'
            ELSE '⚠ MISMATCH → 적용 중단 · 클라우드 본문 차이 확인' END JUDGE
  FROM USER_SOURCE WHERE NAME='PKG_DMF0000' AND TYPE='PACKAGE BODY';


