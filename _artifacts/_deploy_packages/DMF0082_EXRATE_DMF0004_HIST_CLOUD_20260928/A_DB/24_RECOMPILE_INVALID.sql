-- [E20260928-D4HIST] 21(_H DDL)·22/23 이후 INVALID 전이 객체 재컴파일 — 동적·멱등
--   사내 실측 대상: PR_SCM_MST_SITE_HIST · DMF0008_SAVE_SALES_SITE_EDI_REPAIR · PKG_DMF0008 BODY · PKG_SCP0001 BODY
SET SERVEROUTPUT ON
BEGIN
    FOR R IN (SELECT DISTINCT O.OBJECT_NAME, O.OBJECT_TYPE FROM USER_OBJECTS O
               WHERE O.STATUS = 'INVALID'
                 AND O.OBJECT_NAME IN (SELECT NAME FROM USER_DEPENDENCIES
                                        WHERE REFERENCED_NAME IN ('SCM_MST_SITE_H','PKG_DMF0004','PR_DM_MST_SITE_CUSTOMER_HIST'))
               ORDER BY 2 DESC, 1) LOOP
        BEGIN
            IF R.OBJECT_TYPE = 'PACKAGE BODY' THEN
                EXECUTE IMMEDIATE 'ALTER PACKAGE ' || R.OBJECT_NAME || ' COMPILE BODY';
            ELSIF R.OBJECT_TYPE = 'PACKAGE' THEN
                EXECUTE IMMEDIATE 'ALTER PACKAGE ' || R.OBJECT_NAME || ' COMPILE';
            ELSE
                EXECUTE IMMEDIATE 'ALTER ' || R.OBJECT_TYPE || ' ' || R.OBJECT_NAME || ' COMPILE';
            END IF;
            DBMS_OUTPUT.PUT_LINE('COMPILED ' || R.OBJECT_TYPE || ' ' || R.OBJECT_NAME);
        EXCEPTION WHEN OTHERS THEN DBMS_OUTPUT.PUT_LINE('ERR ' || R.OBJECT_NAME || ' ' || SQLERRM);
        END;
    END LOOP;
END;
/
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM USER_OBJECTS WHERE STATUS='INVALID'
   AND OBJECT_NAME IN (SELECT NAME FROM USER_DEPENDENCIES WHERE REFERENCED_NAME IN ('SCM_MST_SITE_H','PKG_DMF0004'));
