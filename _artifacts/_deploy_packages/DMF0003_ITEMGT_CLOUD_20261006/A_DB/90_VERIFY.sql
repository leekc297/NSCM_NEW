 WHERE NOT EXISTS (SELECT 1 FROM USER_TAB_PRIVS P WHERE P.TABLE_NAME = T.COLUMN_VALUE AND P.GRANTEE = R.GRANTEE AND P.PRIVILEGE = R.PRIVILEGE)
UNION ALL
SELECT T.COLUMN_VALUE, S.OWNER, 'SYNONYM', '❌ 시노님 누락 — 10 재실행'
