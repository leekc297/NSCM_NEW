-- 98_ROLLBACK_FROM_CLOUD_BACKUP.sql — 05 보관본으로 SPEC→BODY 복원 (롤백 전용) [E20261006-ITEMGT]
--  임시테이블 4종은 남겨 둔다 (복원된 BODY 가 참조하지 않으며 비어 있음).
SET SERVEROUTPUT ON
DECLARE
  v CLOB;
BEGIN
  FOR t IN (SELECT 'PACKAGE' TYP FROM DUAL UNION ALL SELECT 'PACKAGE BODY' FROM DUAL) LOOP
    DBMS_LOB.CREATETEMPORARY(v, TRUE);
    FOR r IN (SELECT TEXT FROM BAK_SRC_DMF0003_ITEMGT WHERE NAME='PKG_DMF0003' AND TYPE=t.TYP ORDER BY LINE) LOOP
      DBMS_LOB.APPEND(v, r.TEXT);
    END LOOP;
    IF DBMS_LOB.GETLENGTH(v) > 0 THEN
      EXECUTE IMMEDIATE 'CREATE OR REPLACE ' || v;
      DBMS_OUTPUT.PUT_LINE('REBUILT PKG_DMF0003 ' || t.TYP);
    ELSE
      DBMS_OUTPUT.PUT_LINE('SKIP PKG_DMF0003 ' || t.TYP || ' (no backup)');
    END IF;
    DBMS_LOB.FREETEMPORARY(v);
  END LOOP;
END;
/
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM USER_OBJECTS WHERE OBJECT_NAME = 'PKG_DMF0003' ORDER BY 1, 2;
