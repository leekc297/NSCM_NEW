-- 05_BACKUP_CLOUD_SOURCE.sql — 적용 직전 클라우드 SPEC+BODY 원문 보관 (비파괴 · 멱등) [E20261006-ITEMGT]
SET SERVEROUTPUT ON
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='BAK_SRC_DMF0003_ITEMGT';
  IF n = 0 THEN
    EXECUTE IMMEDIATE q'[CREATE TABLE BAK_SRC_DMF0003_ITEMGT AS
      SELECT NAME, TYPE, LINE, TEXT, SYSDATE AS BAK_DATE FROM USER_SOURCE WHERE NAME='PKG_DMF0003' AND TYPE IN ('PACKAGE','PACKAGE BODY')]';
    DBMS_OUTPUT.PUT_LINE('PKG_DMF0003 SOURCE BACKUP CREATED');
  ELSE
    DBMS_OUTPUT.PUT_LINE('PKG_DMF0003 SOURCE BACKUP EXISTS - SKIP');
  END IF;
END;
/
SELECT TYPE, COUNT(*) LINES FROM BAK_SRC_DMF0003_ITEMGT GROUP BY TYPE;
