-- 01_GRANT_SYNONYM_EXCHANGE_RATE_UI.sql
--   DMF0082 환율 모달 [BPS I/F] — SQL ERROR(ORA-06550 / PLS-00201) 정정
--
-- 증상: BPS I/F 클릭 시 `{call PR_SCM_MST_EXCHANGE_RATE_UI( ?, ?)}` 가
--       "PLS-00201: 'PR_SCM_MST_EXCHANGE_RATE_UI' 식별자가 정의되어야 합니다" 로 실패.
-- 원인: 호출이 **스키마 접두 없이** 나가는데, 이 래퍼(2026-08-07 신설 standalone)는
--       앱 계정 노출 세트(시노님 + EXECUTE GRANT)가 **둘 다 누락**돼 있었다.
--       같은 화면의 PKG_DMF0082 / PR_SCM_MST_EXCHANGE_RATE 는 두 계정 모두 보유 — 신설 객체만 빠짐.
--       (사내 시노님 총량 참고: SCMP_APP 소유 SCM_MGR 대상 4,674개)
-- ⚠ 사내 로컬 BE 가 SCM_MGR 직결이면 재현되지 않는다 — 정적 확인 의무.

-- (1) EXECUTE 권한 — SCM_MGR 로 실행
GRANT EXECUTE ON SCM_MGR.PR_SCM_MST_EXCHANGE_RATE_UI TO SCMP_APP;
GRANT EXECUTE ON SCM_MGR.PR_SCM_MST_EXCHANGE_RATE_UI TO SCMD_APP;

-- (2) 시노님 — **DBA 또는 각 앱 계정으로 실행** (SCM_MGR 에는 CREATE ANY SYNONYM 이 없어 ORA-01031)
CREATE OR REPLACE SYNONYM SCMP_APP.PR_SCM_MST_EXCHANGE_RATE_UI FOR SCM_MGR.PR_SCM_MST_EXCHANGE_RATE_UI;
CREATE OR REPLACE SYNONYM SCMD_APP.PR_SCM_MST_EXCHANGE_RATE_UI FOR SCM_MGR.PR_SCM_MST_EXCHANGE_RATE_UI;

-- 검증: GRANT 2행 + 시노님 2행
SELECT 'GRANT' AS AXIS, GRANTEE, PRIVILEGE
  FROM ALL_TAB_PRIVS
 WHERE TABLE_SCHEMA = 'SCM_MGR' AND TABLE_NAME = 'PR_SCM_MST_EXCHANGE_RATE_UI'
UNION ALL
SELECT '시노님', OWNER, TABLE_NAME
  FROM ALL_SYNONYMS
 WHERE TABLE_OWNER = 'SCM_MGR' AND TABLE_NAME = 'PR_SCM_MST_EXCHANGE_RATE_UI'
 ORDER BY 1, 2;
