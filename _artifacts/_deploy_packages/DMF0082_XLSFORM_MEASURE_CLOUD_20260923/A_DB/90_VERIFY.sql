SET PAGESIZE 200 LINESIZE 300
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL
  FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0082' AND OBJECT_TYPE IN ('PACKAGE','PACKAGE BODY');
SELECT NAME, TYPE, LINE, POSITION, TEXT FROM USER_ERRORS WHERE NAME='PKG_DMF0082' ORDER BY SEQUENCE;
SELECT OBJECT_NAME, OBJECT_TYPE FROM USER_OBJECTS WHERE STATUS='INVALID' ORDER BY 1;
-- 마커 반영 확인 (기대 > 0)
SELECT 'E20260923-XLSFORMMEASUREOFF' MARKER, COUNT(*) CNT FROM USER_SOURCE
 WHERE NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND INSTR(TEXT,'E20260923-XLSFORMMEASUREOFF')>0
UNION ALL
SELECT 'E20260923-XLSFORMCURRENCY', COUNT(*) FROM USER_SOURCE
 WHERE NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND INSTR(TEXT,'E20260923-XLSFORMCURRENCY')>0
UNION ALL
SELECT 'E20260923-XLSFORMSORT', COUNT(*) FROM USER_SOURCE
 WHERE NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND INSTR(TEXT,'E20260923-XLSFORMSORT')>0
UNION ALL
SELECT 'E20260923-XLSFORMCURCHAIN', COUNT(*) FROM USER_SOURCE
 WHERE NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND INSTR(TEXT,'E20260923-XLSFORMCURCHAIN')>0;
-- 구 합집합 마커 잔존 0 · 구 CURRENCY 사문식 잔존 0 이어야 함
SELECT COUNT(*) AS UNION_LEFT FROM USER_SOURCE  -- 기대 0 (합집합 잔존 없어야)
 WHERE NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND INSTR(TEXT,'MEASURE IN (''RTF_SYS_RP'',''MKT_FCST'')')>0;
SELECT COUNT(*) AS OLD_EMPTY_SENTINEL_LEFT FROM USER_SOURCE
 WHERE NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND INSTR(TEXT,'NVL(SP.CURRENCY, '''') = ''''')>0;
