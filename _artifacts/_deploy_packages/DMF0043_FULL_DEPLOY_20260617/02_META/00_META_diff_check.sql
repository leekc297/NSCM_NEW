-- DMF0043 / DMF0043_01 메타 사내↔클라우드 차이 진단 (이관 전 cross-check)
-- DDL 정확 기반 작성 (2026-06-17 ORA-00904 사고 후 컬럼명 재정렬)
-- 사용법: 사내 + 클라우드 양쪽 모두 동일 SQL 실행 후 결과 비교 → 차이 row 만 클라우드 INSERT/UPDATE
-- =================================================================================================

-- (1) SCM_ADM_MNU_M — 메뉴 등록
SELECT MNU_ID, UPPR_MNU_ID, MNU_URL, MNU_MSG_ID, SORT_ORD, MNU_LV_NO,
       MNU_TP_CD, UNIT_TP_CD, USE_YN
  FROM SCM_MGR.SCM_ADM_MNU_M
 WHERE MNU_ID IN ('DMF0043', 'DMF0043_01')
 ORDER BY MNU_ID;

-- (2) SCM_ADM_API_M — API 정의 (MNU_ID 없음 — MNU_BTN_MPG_M.API_ID 로 연결)
SELECT API_ID, API_TP_CD, API_MSG_ID, API_URL, USE_YN
  FROM SCM_MGR.SCM_ADM_API_M
 WHERE API_ID IN (
   SELECT DISTINCT API_ID
     FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M
    WHERE MNU_ID IN ('DMF0043', 'DMF0043_01')
      AND API_ID IS NOT NULL
 )
 ORDER BY API_ID;

-- (3) SCM_ADM_PROC_M — SP signature 메타
SELECT PROC_NM, COL_NM, COL_TP_CD, DATA_TP_CD, SORT_ORD
  FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE PROC_NM LIKE 'DMF0043%' OR PROC_NM LIKE 'PKG_DMF0043%'
 ORDER BY PROC_NM, SORT_ORD;

-- (4) SCM_MST_SHEET_COLUMNS — column 메타 (기존 정상 동작 확인)
SELECT PROGRAM_ID, SHEET_NAME, COLUMN_NAME, SORT_ORDER_NO, VISIBLE_FLAG,
       COLUMN_LABEL_NAME, COLUMN_WIDTH, INPUT_TP_CD, HORIZONTAL_ALIGN_CODE,
       CELL_CONTROL_OBJECT_TYPE_CODE, CELL_COMBO_DATA_TYPE, ATTRIBUTE1
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
 WHERE PROGRAM_ID IN ('DMF0043', 'DMF0043_01')
 ORDER BY PROGRAM_ID, SHEET_NAME, SORT_ORDER_NO;

-- (5) SCM_MST_SHEET_MEASURE — measure 메타 (VISIBLE_FLAG 컬럼 없음 — DEFAULT_FLAG/VALID_YN 사용)
SELECT PROGRAM_ID, SHEET_NAME, COLUMN_NAME, COLUMN_LABEL_NAME, SORT_ORDER_NO,
       DEFAULT_FLAG, USER_SELECTABLE_FLAG, VALID_YN, INPUT_TP_CD,
       DIVISION_ID, ATTRIBUTE1
  FROM SCM_MGR.SCM_MST_SHEET_MEASURE
 WHERE PROGRAM_ID IN ('DMF0043', 'DMF0043_01')
 ORDER BY PROGRAM_ID, SHEET_NAME, SORT_ORDER_NO;

-- (6) SCM_ADM_MNU_BTN_MPG_M — 버튼 매핑 (BTN_CD → MNU_BTN_CD, SORT_ORDER_NO 컬럼 없음)
SELECT MNU_ID, SHT_NM, MNU_BTN_CD, API_ID, USE_YN
  FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M
 WHERE MNU_ID IN ('DMF0043', 'DMF0043_01')
 ORDER BY MNU_ID, SHT_NM, MNU_BTN_CD;

-- (7) SCM_ADM_USER_GR_MNU_MPG_M — 메뉴 권한 (GROUP_ID → USER_GR_ID)
SELECT USER_GR_ID, MNU_ID, USE_YN
  FROM SCM_MGR.SCM_ADM_USER_GR_MNU_MPG_M
 WHERE MNU_ID IN ('DMF0043', 'DMF0043_01')
 ORDER BY MNU_ID, USER_GR_ID;

-- (8) SCM_ADM_USER_GR_MNU_BTN_MPG_M — 버튼 권한 (GROUP_ID → USER_GR_ID, BTN_CD → MNU_BTN_CD)
SELECT USER_GR_ID, MNU_ID, SHT_NM, MNU_BTN_CD, USE_YN
  FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M
 WHERE MNU_ID IN ('DMF0043', 'DMF0043_01')
 ORDER BY MNU_ID, USER_GR_ID, SHT_NM, MNU_BTN_CD;

-- (9) SCM_ADM_CMBO_SQL_M — DMF0043 사용 콤보 SQL (USE_FLAG → USE_YN)
SELECT SQL_ID, MDU_DIVS_CD, SQL_NM, USE_YN
  FROM SCM_MGR.SCM_ADM_CMBO_SQL_M
 WHERE SQL_ID IN (
   SELECT DISTINCT ATTRIBUTE1
     FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
    WHERE PROGRAM_ID IN ('DMF0043', 'DMF0043_01')
      AND CELL_CONTROL_OBJECT_TYPE_CODE = 'FPComboBox'
      AND ATTRIBUTE1 IS NOT NULL
 )
 ORDER BY SQL_ID;

-- (10) Row count 요약 (양쪽 비교용)
SELECT 'SCM_ADM_MNU_M' AS TABLE_NM, COUNT(*) AS CNT
  FROM SCM_MGR.SCM_ADM_MNU_M WHERE MNU_ID IN ('DMF0043', 'DMF0043_01')
UNION ALL SELECT 'SCM_ADM_PROC_M', COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M WHERE PROC_NM LIKE 'DMF0043%' OR PROC_NM LIKE 'PKG_DMF0043%'
UNION ALL SELECT 'SCM_MST_SHEET_COLUMNS', COUNT(*) FROM SCM_MGR.SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID IN ('DMF0043', 'DMF0043_01')
UNION ALL SELECT 'SCM_MST_SHEET_MEASURE', COUNT(*) FROM SCM_MGR.SCM_MST_SHEET_MEASURE WHERE PROGRAM_ID IN ('DMF0043', 'DMF0043_01')
UNION ALL SELECT 'SCM_ADM_MNU_BTN_MPG_M', COUNT(*) FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID IN ('DMF0043', 'DMF0043_01')
UNION ALL SELECT 'SCM_ADM_USER_GR_MNU_MPG_M', COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_MPG_M WHERE MNU_ID IN ('DMF0043', 'DMF0043_01')
UNION ALL SELECT 'SCM_ADM_USER_GR_MNU_BTN_MPG_M', COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE MNU_ID IN ('DMF0043', 'DMF0043_01')
UNION ALL SELECT 'SCM_ADM_API_M (via MNU_BTN)', COUNT(DISTINCT A.API_ID)
   FROM SCM_MGR.SCM_ADM_API_M A
   JOIN SCM_MGR.SCM_ADM_MNU_BTN_MPG_M B ON B.API_ID = A.API_ID
  WHERE B.MNU_ID IN ('DMF0043', 'DMF0043_01');
