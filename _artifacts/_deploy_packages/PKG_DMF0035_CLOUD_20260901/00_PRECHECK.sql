-- [사전] 클라우드 PKG_DMF0035 버전 드리프트 확인 (SELECT-only)
-- 기대: 아래 10종 마커가 사내 정본 카운트와 일치. CNT=0 인 마커 = 그 정정분 미적용 → 01 이관 필요.
SELECT M.MARKER, M.EXPECTED,
       (SELECT COUNT(*) FROM ALL_SOURCE S WHERE S.OWNER='SCM_MGR' AND S.NAME='PKG_DMF0035'
         AND S.TYPE='PACKAGE BODY' AND INSTR(S.TEXT, M.MARKER) > 0) AS CLOUD_CNT
  FROM (
    SELECT 'E20260831-W34' MARKER, 2 EXPECTED FROM DUAL UNION ALL
    SELECT 'E20260831-VERCASE', 4 FROM DUAL UNION ALL
    SELECT 'E20260828-ALLCOLS', 1 FROM DUAL UNION ALL
    SELECT 'E20260820-WFITEMPERF', 2 FROM DUAL UNION ALL
    SELECT 'E20260820-VERPUSH2', 5 FROM DUAL UNION ALL
    SELECT 'E20260820-VERPUSH', 6 FROM DUAL UNION ALL
    SELECT 'E20260820-RAWSCALAR', 2 FROM DUAL UNION ALL
    SELECT 'E20260820-DS2', 1 FROM DUAL UNION ALL
    SELECT 'E20260806-WF', 5 FROM DUAL UNION ALL
    SELECT 'E20260123-001715', 3 FROM DUAL
  ) M ORDER BY M.MARKER DESC;

-- 상태·최종배포시각 (사내 정본 = 2026-08-31 21:57:36 VALID)
SELECT OBJECT_NAME, STATUS, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL
  FROM ALL_OBJECTS WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_DMF0035';

-- 종속메저 적재 근거: 사용자 titleset 'M' 에 CUST_FCST 가 있어야 확장이 일어난다
SELECT USER_ID, COUNT(*) MEASURES,
       MAX(CASE WHEN COLUMN_NAME='CUST_FCST' THEN 'Y' ELSE 'N' END) HAS_CUST_FCST
  FROM SCM_MGR.SCM_MST_TITLESET_USER
 WHERE PROGRAM_ID='DMF0035' AND USER_INQUIRY_COLUMN_TYPE_CODE='M'
 GROUP BY USER_ID ORDER BY USER_ID;
