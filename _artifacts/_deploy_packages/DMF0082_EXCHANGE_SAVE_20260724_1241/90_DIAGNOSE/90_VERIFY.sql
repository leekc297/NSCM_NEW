-- [1] PKG_DMF0000 컴파일 상태 — 기대: PACKAGE + PACKAGE BODY 모두 VALID
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM USER_OBJECTS
 WHERE OBJECT_NAME = 'PKG_DMF0000' ORDER BY OBJECT_TYPE;

-- (INVALID 시) 오류 원인
SELECT NAME, TYPE, LINE, POSITION, TEXT FROM USER_ERRORS
 WHERE NAME = 'PKG_DMF0000' ORDER BY SEQUENCE;

-- [2] 의존 오브젝트 — 기대: 4행 (GTT/테이블2/시퀀스)
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM USER_OBJECTS
 WHERE OBJECT_NAME IN ('GT_D000_RESULTS','DM_MST_EXCHANGE_RATE','DM_MST_EXCHANGE_RATE_H',
                       'SEQ1_DM_MST_EXCHANGE_RATE')
 ORDER BY OBJECT_NAME;

-- [3] SP 시그니처 vs PROC_M 위치+이름 대조 — 기대: 9행, MATCH_YN 전부 'Y'
--    (POSITION 1~8 IN + 9 OUT REF CURSOR ↔ SORT_ORD 1~9)
SELECT p.SORT_ORD, p.COL_NM, p.COL_TP_CD, a.ARGUMENT_NAME, a.IN_OUT,
       CASE WHEN (p.COL_TP_CD = 'IN'  AND a.IN_OUT = 'IN')
              OR (p.COL_TP_CD = 'OUT' AND a.IN_OUT = 'OUT') THEN 'Y' ELSE 'N' END AS MATCH_YN
  FROM SCM_ADM_PROC_M p
  LEFT JOIN ALL_ARGUMENTS a
    ON a.OWNER = 'SCM_MGR' AND a.PACKAGE_NAME = 'PKG_DMF0000'
   AND a.OBJECT_NAME = 'P_DMF0000_SAVE_EXCHANGE_POPUP_DATA' AND a.POSITION = p.SORT_ORD
 WHERE p.PROC_NM = 'PKG_DMF0000.P_DMF0000_SAVE_EXCHANGE_POPUP_DATA'
 ORDER BY p.SORT_ORD;

-- [4] API_M — 기대: 1행, API_URL = PKG_DMF0000.P_DMF0000_SAVE_EXCHANGE_POPUP_DATA
SELECT API_ID, API_TP_CD, API_URL, USE_YN FROM SCM_ADM_API_M
 WHERE API_ID = 'DMF0082_futurePriceInfo_SAVE';

-- [5] 버튼 + 그룹 매핑 — 기대: BTN 3행(SAVE/EDIT/INSERT) + 그룹매핑 6행(ADMIN·DM ADMIN×3)
SELECT MNU_BTN_CD, API_ID, USE_YN FROM SCM_ADM_MNU_BTN_MPG_M
 WHERE MNU_ID = 'DMF0082' AND SHT_NM = 'futurePriceInfo'
   AND MNU_BTN_CD IN ('SAVE','EDIT','INSERT') ORDER BY MNU_BTN_CD;

SELECT USER_GR_ID, MNU_BTN_CD, USE_YN FROM SCM_ADM_USER_GR_MNU_BTN_MPG_M
 WHERE MNU_ID = 'DMF0082' AND SHT_NM = 'futurePriceInfo'
   AND MNU_BTN_CD IN ('SAVE','EDIT','INSERT') ORDER BY USER_GR_ID, MNU_BTN_CD;

-- [6] MSG00689 — 기대: 3행(KO/EN/CN), 문구 'Sales Price Recalculation is complete.'
SELECT MSG_ID, LANG_CD, MSG_NM, USE_YN FROM SCM_ADM_MSG_M
 WHERE MSG_ID = 'MSG00689' ORDER BY LANG_CD;

-- [7] GRANT/SYNONYM — 기대: SCMD_APP EXECUTE 1행 + SYNONYM 1행
SELECT GRANTEE, PRIVILEGE FROM ALL_TAB_PRIVS
 WHERE TABLE_NAME = 'PKG_DMF0000' AND TABLE_SCHEMA = 'SCM_MGR' AND GRANTEE = 'SCMD_APP';
SELECT OWNER, SYNONYM_NAME FROM ALL_SYNONYMS
 WHERE TABLE_NAME = 'PKG_DMF0000' AND TABLE_OWNER = 'SCM_MGR' AND OWNER = 'SCMD_APP';
