-- 00_PRECHECK — 조회 전용 (전체 F5, 값 입력 없음). [GAP467 2026-10-15] SYS0014 그룹 원장·사용자 매핑 적용 전 상태
-- * [L1] 추가 대상 4그룹 존재 여부 (대소문자 무시) — 적용 전 0행 기대. 있으면 10 은 그 그룹을 건너뜀(기존 행 무변경)
-- * [L2] 이관 사본 존재 + 대상 3그룹 사본 행 수 (기대: CAPA Planner 220 · System Monitor 1 · '-' 34 — DB 마다 다를 수 있음, 값 회신)
-- * [L3] TO-BE 매핑에 이미 있는 대상 그룹 행 수 (적용 전 0 기대 — 있으면 그 키는 건너뜀)
-- * [L4] 원장에 없는 그룹을 가리키는 행 (사업부 권한 · 사용자 매핑 · 메뉴 · 버튼 · 권한요청) — 참고
SET DEFINE OFF
SET LINESIZE 200 PAGESIZE 200
SELECT 'L1 존재' CHK, USER_GR_ID, USER_GR_NM, USE_YN FROM SCM_ADM_USER_GR_M
 WHERE UPPER(USER_GR_ID) IN ('CAPA PLANNER','SYSTEM MONITOR','SSP ADMIN','-') ORDER BY USER_GR_ID;
SELECT 'L2 사본' CHK, TABLE_NAME, NUM_ROWS FROM USER_TABLES WHERE TABLE_NAME IN ('TB_FX_USERGROUPINFO','TB_FX_GROUPINFO') ORDER BY 2;
SET SERVEROUTPUT ON SIZE UNLIMITED
DECLARE
    n PLS_INTEGER;
    c SYS_REFCURSOR;
    g VARCHAR2(200);
    k PLS_INTEGER;
BEGIN
    SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME = 'TB_FX_USERGROUPINFO';
    IF n = 0 THEN
        DBMS_OUTPUT.PUT_LINE('L2 사본 없음 — 10 은 그룹 원장만 적용하고 매핑은 SKIP');
        RETURN;
    END IF;
    OPEN c FOR 'SELECT GROUPID, COUNT(*) FROM TB_FX_USERGROUPINFO WHERE GROUPID IN (''CAPA Planner'',''System Monitor'',''-'') GROUP BY GROUPID ORDER BY 1';
    LOOP
        FETCH c INTO g, k;
        EXIT WHEN c%NOTFOUND;
        DBMS_OUTPUT.PUT_LINE('L2 사본 행 [' || g || '] ' || k);
    END LOOP;
    CLOSE c;
END;
/
SELECT 'L3 기존매핑' CHK, USER_GR_ID, COUNT(*) N FROM SCM_ADM_USER_GR_MPG_M
 WHERE USER_GR_ID IN ('CAPA Planner','System Monitor','-') GROUP BY USER_GR_ID;
SELECT 'L4 고아' CHK, T, G, N FROM (
    SELECT 'UNIT_AUTH' T, USER_GR_ID G, COUNT(*) N FROM SCM_ADM_USER_GR_UNIT_AUTH_MPG_M GROUP BY USER_GR_ID UNION ALL
    SELECT 'USER_MPG',  USER_GR_ID,   COUNT(*)   FROM SCM_ADM_USER_GR_MPG_M          GROUP BY USER_GR_ID UNION ALL
    SELECT 'MNU',       USER_GR_ID,   COUNT(*)   FROM SCM_ADM_USER_GR_MNU_MPG_M      GROUP BY USER_GR_ID UNION ALL
    SELECT 'MNU_BTN',   USER_GR_ID,   COUNT(*)   FROM SCM_ADM_USER_GR_MNU_BTN_MPG_M  GROUP BY USER_GR_ID UNION ALL
    SELECT 'AUTH_REQ',  GROUP_ID,     COUNT(*)   FROM SCM_MST_AUTH_REQUEST           GROUP BY GROUP_ID ) X
 WHERE NOT EXISTS (SELECT 1 FROM SCM_ADM_USER_GR_M M WHERE M.USER_GR_ID = X.G) ORDER BY G, T;
