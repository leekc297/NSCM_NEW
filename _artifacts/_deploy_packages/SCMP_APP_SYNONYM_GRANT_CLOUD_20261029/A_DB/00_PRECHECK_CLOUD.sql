-- 00_PRECHECK_CLOUD.sql — 읽기 전용. 앱 계정(SCMP_APP) 시노님·권한 보완 전 현재 상태 확인 (system/DBA 계정 실행)
-- 패키지: SCMP_APP_SYNONYM_GRANT_CLOUD_20261029 · 사내 ZIOUI1 적용 2026-10-29 09:35~09:50 · 전체 F5 기준 오류 0

-- 1) 대상 객체 존재·상태 (기대: FP_MGR.SCM_LINE_M TABLE VALID · FP_MGR.SCM_LINE_HIERARCHY_CPS_V VIEW VALID)
SELECT OWNER, OBJECT_NAME, OBJECT_TYPE, STATUS
  FROM DBA_OBJECTS
 WHERE OWNER = 'FP_MGR'
   AND OBJECT_NAME IN ('SCM_LINE_M', 'SCM_LINE_HIERARCHY_CPS_V')
 ORDER BY OBJECT_NAME;

-- 2) 현재 시노님 (SCM_MGR 에는 있고 SCMP_APP·PUBLIC 에는 없던 상태가 사내 보완 전 모습)
SELECT OWNER, SYNONYM_NAME, TABLE_OWNER, TABLE_NAME
  FROM DBA_SYNONYMS
 WHERE SYNONYM_NAME IN ('SCM_MST_LINE_SN', 'SCM_LINE_HIERARCHY_CPS_V_SN')
   AND OWNER IN ('SCM_MGR', 'SCMP_APP', 'PUBLIC')
 ORDER BY SYNONYM_NAME, OWNER;

-- 3) 대상 객체 SELECT 권한 (기대: RL_FP_SEL 에 SELECT — SCM_LINE_M 은 기존, HIERARCHY 뷰는 보완 대상)
SELECT OWNER, TABLE_NAME, GRANTEE, PRIVILEGE, GRANTABLE
  FROM DBA_TAB_PRIVS
 WHERE OWNER = 'FP_MGR'
   AND TABLE_NAME IN ('SCM_LINE_M', 'SCM_LINE_HIERARCHY_CPS_V')
 ORDER BY TABLE_NAME, GRANTEE;

-- 4) SCMP_APP 롤 (기대: RL_FP_SEL 포함 — 없으면 10_APPLY 의 GRANT 대상을 SCMP_APP 으로)
SELECT GRANTED_ROLE FROM DBA_ROLE_PRIVS WHERE GRANTEE = 'SCMP_APP' ORDER BY 1;

-- 5) 이 시노님을 쓰는 콤보 SQL (사내 실측: LineByOperation·LineByOperation1/2_SCP_ALL·LineByOperationPlantId_SCP_ALL·CapaLineMaster*_SCP_ALL·OperationByLine_SCP_ALL 등 28건)
SELECT SQL_ID
  FROM SCM_MGR.SCM_ADM_CMBO_SQL_M
 WHERE UPPER(SQL_DTL_CTN) LIKE '%SCM_MST_LINE_SN%'
    OR UPPER(SQL_DTL_CTN) LIKE '%SCM_LINE_HIERARCHY_CPS_V_SN%'
 ORDER BY SQL_ID;
