-- 90_VERIFY.sql — 읽기 전용. RESULT = 'PASS' 1행이면 적용 완료 (system/DBA 또는 SCM_MGR 계정)
-- PASS 조건: SCMP_APP 시노님 2건이 FP_MGR 대상을 가리키고, FP_MGR.SCM_LINE_HIERARCHY_CPS_V·SCM_LINE_M 의 SELECT 가 RL_FP_SEL(또는 SCMP_APP 직접)에 있음
SELECT CASE WHEN syn_cnt = 2 AND priv_cnt = 2 THEN 'PASS' ELSE 'FAIL' END AS RESULT,
       syn_cnt  AS SYNONYM_OK_COUNT,   -- 기대 2
       priv_cnt AS SELECT_PRIV_COUNT   -- 기대 2
  FROM (SELECT (SELECT COUNT(*) FROM DBA_SYNONYMS
                  WHERE OWNER = 'SCMP_APP'
                    AND ((SYNONYM_NAME = 'SCM_MST_LINE_SN' AND TABLE_OWNER = 'FP_MGR' AND TABLE_NAME = 'SCM_LINE_M')
                      OR (SYNONYM_NAME = 'SCM_LINE_HIERARCHY_CPS_V_SN' AND TABLE_OWNER = 'FP_MGR' AND TABLE_NAME = 'SCM_LINE_HIERARCHY_CPS_V'))) AS syn_cnt,
               (SELECT COUNT(DISTINCT TABLE_NAME) FROM DBA_TAB_PRIVS
                  WHERE OWNER = 'FP_MGR'
                    AND TABLE_NAME IN ('SCM_LINE_M', 'SCM_LINE_HIERARCHY_CPS_V')
                    AND PRIVILEGE IN ('SELECT', 'READ')
                    AND GRANTEE IN ('SCMP_APP', 'PUBLIC', 'RL_FP_SEL')) AS priv_cnt
          FROM DUAL);

-- 상세(참고): 시노님·권한 현황
SELECT 'SYN' AS KIND, OWNER || '.' || SYNONYM_NAME AS NAME, TABLE_OWNER || '.' || TABLE_NAME AS TARGET
  FROM DBA_SYNONYMS
 WHERE OWNER = 'SCMP_APP' AND SYNONYM_NAME IN ('SCM_MST_LINE_SN', 'SCM_LINE_HIERARCHY_CPS_V_SN')
UNION ALL
SELECT 'PRIV', OWNER || '.' || TABLE_NAME, GRANTEE || ':' || PRIVILEGE
  FROM DBA_TAB_PRIVS
 WHERE OWNER = 'FP_MGR' AND TABLE_NAME IN ('SCM_LINE_M', 'SCM_LINE_HIERARCHY_CPS_V')
 ORDER BY 1, 2;
