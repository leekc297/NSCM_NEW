-- 99_ROLLBACK_SYNONYM_GRANT.sql — 10_APPLY 되돌리기 (system/DBA 계정). 시노님 2건 DROP + 뷰 SELECT 권한 REVOKE
-- ⚠ 주의: 이 시노님(SCM_MST_LINE_SN·SCM_LINE_HIERARCHY_CPS_V_SN)은 콤보 SQL 28건이 참조한다. 적용 뒤 다른 화면이 쓰기 시작했다면 롤백하지 않는다.
-- 멱등: 없으면 0건(ORA-01434 시노님 없음 · ORA-01927 권한 없음 은 무시)
BEGIN
  EXECUTE IMMEDIATE 'DROP SYNONYM SCMP_APP.SCM_MST_LINE_SN';
EXCEPTION WHEN OTHERS THEN IF SQLCODE <> -1434 THEN RAISE; END IF;
END;
/
BEGIN
  EXECUTE IMMEDIATE 'DROP SYNONYM SCMP_APP.SCM_LINE_HIERARCHY_CPS_V_SN';
EXCEPTION WHEN OTHERS THEN IF SQLCODE <> -1434 THEN RAISE; END IF;
END;
/
BEGIN
  EXECUTE IMMEDIATE 'REVOKE SELECT ON FP_MGR.SCM_LINE_HIERARCHY_CPS_V FROM RL_FP_SEL';
EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-1927, -1919) THEN RAISE; END IF;
END;
/
BEGIN
  EXECUTE IMMEDIATE 'REVOKE SELECT ON FP_MGR.SCM_LINE_HIERARCHY_CPS_V FROM SCMP_APP';
EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-1927, -1917) THEN RAISE; END IF;
END;
/
