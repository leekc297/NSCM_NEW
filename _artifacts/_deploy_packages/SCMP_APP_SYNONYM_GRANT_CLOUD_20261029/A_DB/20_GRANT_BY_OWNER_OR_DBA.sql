-- 20_GRANT_BY_OWNER_OR_DBA.sql — FP_MGR.SCM_LINE_HIERARCHY_CPS_V 의 SELECT 권한 (★ 뷰 소유자 FP_MGR 또는 GRANT ANY OBJECT PRIVILEGE 가 있는 계정(SYSTEM/DBA)으로만 실행)
-- 2026-10-29 실행 시 다른 계정으로 돌려 ORA-01031(권한 불충분)이 났던 블록. SCM_MGR 은 이 뷰에 SELECT(GRANT OPTION 없음)만 있어 부여할 수 없다.
-- 멱등: 이미 권한이 있으면 그대로(오류 없음). 롤 RL_FP_SEL 이 없는 환경(ORA-01919)이면 SCMP_APP 에 직접 부여.
BEGIN
  EXECUTE IMMEDIATE 'GRANT SELECT ON FP_MGR.SCM_LINE_HIERARCHY_CPS_V TO RL_FP_SEL';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE = -1919 THEN
      EXECUTE IMMEDIATE 'GRANT SELECT ON FP_MGR.SCM_LINE_HIERARCHY_CPS_V TO SCMP_APP';
    ELSE
      RAISE;  -- ORA-01031 이면 실행 계정 권한 부족 → FP_MGR 또는 SYSTEM 으로 다시
    END IF;
END;
/

-- FP_MGR.SCM_LINE_M 은 사내에서 RL_FP_SEL 에 SELECT 가 이미 있었다. 클라우드에 없으면 아래 주석을 풀어 실행
-- GRANT SELECT ON FP_MGR.SCM_LINE_M TO RL_FP_SEL;

-- 확인
SELECT OWNER, TABLE_NAME, GRANTEE, PRIVILEGE
  FROM DBA_TAB_PRIVS
 WHERE OWNER = 'FP_MGR' AND TABLE_NAME IN ('SCM_LINE_HIERARCHY_CPS_V', 'SCM_LINE_M')
 ORDER BY TABLE_NAME, GRANTEE;
