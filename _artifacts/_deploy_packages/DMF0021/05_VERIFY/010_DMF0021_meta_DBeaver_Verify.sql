-- PROC_M ↔ SP signature match
SELECT P.PROC_NM, COUNT(*) AS PROC_M_ROWS,
       (SELECT COUNT(*) FROM ALL_ARGUMENTS A WHERE A.OWNER='SCM_MGR' AND A.OBJECT_NAME=P.PROC_NM AND A.PACKAGE_NAME='PKG_DMF0021') AS SP_ARGS,
       CASE WHEN COUNT(*) = (SELECT COUNT(*) FROM ALL_ARGUMENTS A WHERE A.OWNER='SCM_MGR' AND A.OBJECT_NAME=P.PROC_NM AND A.PACKAGE_NAME='PKG_DMF0021')
            THEN 'MATCH' ELSE 'MISMATCH' END AS STATUS
  FROM SCM_MGR.SCM_ADM_PROC_M P WHERE P.PROC_NM LIKE 'DMF0021%' GROUP BY P.PROC_NM ORDER BY P.PROC_NM;

SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM ALL_OBJECTS WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_DMF0021';
