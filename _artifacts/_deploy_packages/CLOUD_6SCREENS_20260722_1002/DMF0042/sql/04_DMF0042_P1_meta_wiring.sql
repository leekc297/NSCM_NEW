-- ── ① MNU_URL 교체 (라우트 3-SET 정합: route-paths.ts DMF0042 = Router path = MNU_URL 동일 kebab) ──
UPDATE SCM_MGR.SCM_ADM_MNU_M
SET MNU_URL = 'business-plan', LAST_UPDATED_BY = 'admin', LAST_UPDATE_DATE = SYSDATE
WHERE MNU_ID = 'DMF0042' AND MNU_URL = 'dmf0042';

-- ── ② MSG 신규 6종 × 3 LANG (MSG00675~680 — MERGE 멱등) ──
MERGE INTO SCM_MGR.SCM_ADM_MSG_M t
USING (
  -- MSG00675: Manual Cutoff 완료 (AS-IS MSG00151 원문 1:1)
  SELECT 'MSG00675' MSG_ID, 'KO' LANG_CD, 'Manual Cutoff가 완료되었습니다.[Division ID : {0}] {1}' MSG_NM, 'DMF0042 Ver. Cutoff 완료 안내 (AS-IS 00151)' MSG_DESC FROM DUAL
  UNION ALL SELECT 'MSG00675', 'EN', 'Manual Cutoff has been completed. [Division ID : {0}] {1}', 'DMF0042 Ver. Cutoff 완료 안내 (AS-IS 00151)' FROM DUAL
  UNION ALL SELECT 'MSG00675', 'CN', 'Manual Cutoff 已完成. [Division ID : {0}] {1}', 'DMF0042 Ver. Cutoff 완료 안내 (AS-IS 00151)' FROM DUAL
  -- MSG00676: 저장 대상 0건 (AS-IS MSG00275 원문 미등록 → 용법 기준 신설)
  UNION ALL SELECT 'MSG00676', 'KO', '저장할 대상 데이터가 없습니다.', 'DMF0042 저장 대상 0건 (AS-IS 00275 용법)' FROM DUAL
  UNION ALL SELECT 'MSG00676', 'EN', 'There is no data to save.', 'DMF0042 저장 대상 0건 (AS-IS 00275 용법)' FROM DUAL
  UNION ALL SELECT 'MSG00676', 'CN', '没有可保存的数据.', 'DMF0042 저장 대상 0건 (AS-IS 00275 용법)' FROM DUAL
  -- MSG00677: 조회 기간 6년 초과 (AS-IS MSG00276 원문 1:1)
  UNION ALL SELECT 'MSG00677', 'KO', '조회 기간은 6년 이상 설정 할 수 없습니다.', 'DMF0042 조회기간 6년 제한 (AS-IS 00276)' FROM DUAL
  UNION ALL SELECT 'MSG00677', 'EN', 'The search period cannot be set to more than 6 years.', 'DMF0042 조회기간 6년 제한 (AS-IS 00276)' FROM DUAL
  UNION ALL SELECT 'MSG00677', 'CN', '查询期间不能设置为6年以上.', 'DMF0042 조회기간 6년 제한 (AS-IS 00276)' FROM DUAL
  -- MSG00678: 환율 적용 confirm (AS-IS MSG00282 원문 1:1)
  UNION ALL SELECT 'MSG00678', 'KO', '변경된 환율을 적용하시겠습니까?', 'DMF0042 Set Price 환산 confirm (AS-IS 00282)' FROM DUAL
  UNION ALL SELECT 'MSG00678', 'EN', 'Do you want to apply the changed exchange rate?', 'DMF0042 Set Price 환산 confirm (AS-IS 00282)' FROM DUAL
  UNION ALL SELECT 'MSG00678', 'CN', '是否应用更改后的汇率?', 'DMF0042 Set Price 환산 confirm (AS-IS 00282)' FROM DUAL
  -- MSG00679: Business Plan 정수 입력 (AS-IS MSG00289 원문 1:1)
  UNION ALL SELECT 'MSG00679', 'KO', 'Business Plan 데이터는 정수로 입력해 주세요.', 'DMF0042 BP 소수 입력 차단 (AS-IS 00289)' FROM DUAL
  UNION ALL SELECT 'MSG00679', 'EN', 'Business Plan data must be entered as an integer.', 'DMF0042 BP 소수 입력 차단 (AS-IS 00289)' FROM DUAL
  UNION ALL SELECT 'MSG00679', 'CN', 'Business Plan 数据请输入整数.', 'DMF0042 BP 소수 입력 차단 (AS-IS 00289)' FROM DUAL
  -- MSG00680: 변경 중 수행 불가 (AS-IS MSG00142 용법 — TO-BE 00142 선점으로 신설)
  UNION ALL SELECT 'MSG00680', 'KO', '변경 중인 데이터가 있어 수행할 수 없습니다. 저장 또는 취소 후 다시 시도해 주세요.', 'DMF0042 pending 변경 중 기능 차단 (AS-IS 00142 용법)' FROM DUAL
  UNION ALL SELECT 'MSG00680', 'EN', 'Cannot proceed while there are unsaved changes. Save or cancel the changes and try again.', 'DMF0042 pending 변경 중 기능 차단 (AS-IS 00142 용법)' FROM DUAL
  UNION ALL SELECT 'MSG00680', 'CN', '存在未保存的更改, 无法执行. 请保存或取消后重试.', 'DMF0042 pending 변경 중 기능 차단 (AS-IS 00142 용법)' FROM DUAL
