-- 31_ROLLBACK_EXCEL_COLUMNS_DMF0014.sql — 30_ 적용 직전 값으로 되돌리기 (SCM_MGR 접속)
-- 30_ 은 COMMIT 을 포함하므로 트랜잭션 ROLLBACK 은 불가. Oracle Flashback Query(UNDO)로 적용 직전 버전을 읽어 복원한다.
-- 순서: [1] 이력 조회로 "30_ 직전 값" 확인 → [2] 그 시각으로 복원 UPDATE → [3] 확인.
-- ⚠ UNDO 보존시간이 지나면 [1]/[2] 가 ORA-01555 / ORA-08180 으로 실패한다 → 그때는 [4] 수동 복원.
SET PAGESIZE 200 LINESIZE 400 LONG 4000
COLUMN HEADER_CONTENT FORMAT A150
COLUMN STORAGE_SQL_ID FORMAT A50
COLUMN VERSIONS_STARTTIME FORMAT A28
COLUMN VERSIONS_OPERATION FORMAT A3

-- [0] 현재 값 (30_ 적용 후)
SELECT PROGRAM_ID, SHEET_NAME, STORAGE_SQL_ID, HEADER_CONTENT, OPTION_ATTRIBUTE_COLUMN_NUMBER, VALID_YN,
       LAST_UPDATED_BY, TO_CHAR(LAST_UPDATE_DATE,'YYYY-MM-DD HH24:MI:SS') LAST_UPDATE_DATE
  FROM SCM_MGR.SCM_ADM_EXCEL_COLUMNS
 WHERE PROGRAM_ID = 'DMF0014' AND SHEET_NAME = 'FCST Upload';

-- [1] 행 변경 이력 전부 (UNDO 범위 내) — VERSIONS_OPERATION='U' 인 최신 행이 30_ 의 UPDATE,
--     그 바로 아래(이전) 행이 "30_ 직전 값". 그 행의 VERSIONS_ENDTIME 을 [2] 의 시각으로 쓴다.
SELECT VERSIONS_STARTTIME, VERSIONS_ENDTIME, VERSIONS_OPERATION,
       STORAGE_SQL_ID, HEADER_CONTENT, OPTION_ATTRIBUTE_COLUMN_NUMBER, VALID_YN, LAST_UPDATED_BY,
       TO_CHAR(LAST_UPDATE_DATE,'YYYY-MM-DD HH24:MI:SS') LAST_UPDATE_DATE
  FROM SCM_MGR.SCM_ADM_EXCEL_COLUMNS VERSIONS BETWEEN TIMESTAMP MINVALUE AND MAXVALUE
 WHERE PROGRAM_ID = 'DMF0014' AND SHEET_NAME = 'FCST Upload'
 ORDER BY VERSIONS_STARTTIME DESC NULLS FIRST;

-- [2] 복원 — &BEFORE_TS 를 30_ 실행 **직전** 시각으로 바꿔 실행 (예 '2026-09-23 11:20:00' — [1] 의 이전 행 VERSIONS_ENDTIME 보다 1초 앞)
UPDATE SCM_MGR.SCM_ADM_EXCEL_COLUMNS T
   SET (STORAGE_SQL_ID, HEADER_CONTENT, OPTION_ATTRIBUTE_COLUMN_NUMBER, VALID_YN, LAST_UPDATED_BY, LAST_UPDATE_DATE) =
       (SELECT X.STORAGE_SQL_ID, X.HEADER_CONTENT, X.OPTION_ATTRIBUTE_COLUMN_NUMBER, X.VALID_YN, X.LAST_UPDATED_BY, X.LAST_UPDATE_DATE
          FROM SCM_MGR.SCM_ADM_EXCEL_COLUMNS AS OF TIMESTAMP TO_TIMESTAMP('&BEFORE_TS', 'YYYY-MM-DD HH24:MI:SS') X
         WHERE X.PROGRAM_ID = T.PROGRAM_ID AND X.SHEET_NAME = T.SHEET_NAME)
 WHERE T.PROGRAM_ID = 'DMF0014' AND T.SHEET_NAME = 'FCST Upload'
   AND EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_EXCEL_COLUMNS AS OF TIMESTAMP TO_TIMESTAMP('&BEFORE_TS', 'YYYY-MM-DD HH24:MI:SS') X
                WHERE X.PROGRAM_ID = T.PROGRAM_ID AND X.SHEET_NAME = T.SHEET_NAME);
-- 1 row updated 가 아니면(0 rows) 30_ 이전에 행이 없었던 것 → 30_ 이 INSERT 한 행이므로 아래로 삭제 복원:
