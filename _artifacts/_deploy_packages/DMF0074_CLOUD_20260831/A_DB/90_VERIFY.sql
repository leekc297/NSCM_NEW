       (SELECT COUNT(*) FROM SCM_MGR.DM_PLN_SALES_PLAN_C PC WHERE PC.DIVISION_ID='40' AND PC.VERSION_NO=V.VERSION_NO) PLAN_C,
       (SELECT COUNT(*) FROM SCM_MGR.DM_PLN_SALES_PLAN_RESULT_C RC WHERE RC.DIVISION_ID='40' AND RC.VERSION_NO=V.VERSION_NO) RESULT_C
