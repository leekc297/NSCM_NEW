-- DMF0035 VERCOL 적용 검증 — 01 실행 후 전 항목 통과 의무
-- V1. 객체 상태 (기대: PACKAGE / PACKAGE BODY 둘 다 VALID)
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL
  FROM ALL_OBJECTS WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_DMF0035';

-- V2. 컴파일 오류 (기대: 0)
SELECT COUNT(*) ERR_CNT FROM ALL_ERRORS
 WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0035' AND TYPE='PACKAGE BODY';

-- V3. 코드행 기준 패치 판정 — 주석행은 제외한다 (LTRIM LIKE '--%').
--     주의: [E20260909-MEASURECOL] 주석문이 구 NOT IN 문구를 인용하고 있어
--           주석을 포함해 세면 오탐(FAIL)이 난다.
SELECT SUM(CASE WHEN REPLACE(TEXT,' ','') LIKE '%NOTIN(''MEASURE'',''VERSION_NO'')%' THEN 1 ELSE 0 END) OLD_CODE
     , SUM(CASE WHEN REPLACE(TEXT,' ','') LIKE '%NOTIN(''MEASURE'')%'                THEN 1 ELSE 0 END) NEW_CODE
     , SUM(CASE WHEN TEXT LIKE '%,VERSION_NO,''%'                                     THEN 1 ELSE 0 END) GUARD_CNT
  FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0035' AND TYPE='PACKAGE BODY'
   AND LTRIM(TEXT) NOT LIKE '--%';
-- 기대: OLD_CODE=0 · NEW_CODE=1 · GUARD_CNT=1

-- V4. 컬럼목록 재현 — 개인화('C') 보유 계정 기준 VERSION_NO 가 두 목록에 정확히 1회
--     :USER_ID 를 클라우드 실사용 계정으로 바꿔 실행.
SELECT LISTAGG(' ' || COLUMN_NAME || ',', '') WITHIN GROUP (ORDER BY SORT_ORDER_NO) AS V_COL_LIST
     , LISTAGG(' ' || COLUMN_NAME || ' ' || DATA_SORT_METHOD_CODE || ',', '') WITHIN GROUP (ORDER BY SORT_ORDER_NO) AS V_ORDER_LIST
FROM (
    SELECT CASE WHEN C.COLUMN_NAME = 'GROUP_ID' THEN NVL(TU.SORT_ORDER_NO, 95) - 0.5 ELSE U.SORT_ORDER_NO END AS SORT_ORDER_NO
         , C.COLUMN_NAME, U.DATA_SORT_METHOD_CODE
    FROM SCM_MGR.SCM_MST_TITLESET_USER U
    INNER JOIN SCM_MGR.SCM_MST_SHEET_COLUMNS C
            ON U.PROGRAM_ID = C.PROGRAM_ID AND C.SHEET_NAME = 'Mkt Fcst Waterfall'
           AND U.COLUMN_NAME = C.COLUMN_NAME AND U.PROGRAM_ID = 'DMF0035'
           AND U.SHEET_NAME = 'Mkt Fcst Waterfall' AND U.USER_ID = :USER_ID
           AND U.USER_INQUIRY_COLUMN_TYPE_CODE = 'C'
           AND U.COLUMN_NAME NOT IN ('MEASURE')
    LEFT OUTER JOIN SCM_MGR.SCM_MST_TITLESET_USER TU
                 ON TU.PROGRAM_ID = C.PROGRAM_ID AND TU.SHEET_NAME = 'Mkt Fcst Waterfall'
                AND TU.USER_INQUIRY_COLUMN_TYPE_CODE = 'C' AND TU.COLUMN_NAME IN ('ITEM_ID')
                AND TU.USER_ID = :USER_ID
    UNION ALL
    SELECT C.SORT_ORDER_NO, C.COLUMN_NAME, C.DATA_SORT_METHOD_CODE
    FROM SCM_MGR.SCM_MST_SHEET_COLUMNS C
    WHERE C.PROGRAM_ID = 'DMF0035' AND C.SHEET_NAME = 'Mkt Fcst Waterfall'
      AND C.VISIBLE_FLAG = 'N' AND RTRIM(C.DEFAULT_FLAG,' -') IS NULL AND C.VALID_YN = 'Y' AND ROWNUM <= 100
) TBCOLLIST;
-- 기대: 양쪽 문자열에 VERSION_NO 가 각각 정확히 1회 (중복 0)

-- V5. 런타임 — 화면(DMF0035 / TYPE=MKT FCST) 조회 후 그리드 VERSION 열에 값이 채워질 것.
--     SP 직접 검증 시 O_RC1 정적축에 VERSION_SORT·VERSION_NO 가 있고 NULL/빈값 0행이어야 한다.
--     다중 버전(CSV) 조회 시 VERSION_NO 가 버전별로 분리되고 VERSION_SORT DESC 정렬이 적용된다.
