-- 99_ROLLBACK_DATA — [E20261022-SOLDTONULL] 20_DATA 원복 (전체 F5, 값 입력 없음, 멱등)
-- 내용: 백업 DM_PLN_SALES_ETC_REPORT_C_BAK20261022_SOLDTO 의 SOLDTO_CODE 로 되돌린다(현재 NULL 인 행만). 백업 테이블은 남긴다.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET DEFINE OFF
DECLARE
    n  NUMBER;
BEGIN
    SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME = 'DM_PLN_SALES_ETC_REPORT_C_BAK20261022_SOLDTO';
    IF n = 0 THEN
        DBMS_OUTPUT.PUT_LINE('SKIP — 백업 테이블 없음 (20_DATA 미실행). 데이터 무변경');
        RETURN;
    END IF;
    EXECUTE IMMEDIATE 'MERGE INTO DM_PLN_SALES_ETC_REPORT_C A USING DM_PLN_SALES_ETC_REPORT_C_BAK20261022_SOLDTO B ON (A.VERSION_NO = B.VERSION_NO AND A.DIVISION_ID = B.DIVISION_ID AND A.DATA_SEQ = B.DATA_SEQ AND A.MEASURE = B.MEASURE AND A.YYYYMMDD = B.YYYYMMDD)'
                   || ' WHEN MATCHED THEN UPDATE SET A.SOLDTO_CODE = B.SOLDTO_CODE WHERE A.SOLDTO_CODE IS NULL';
    n := SQL%ROWCOUNT;
    COMMIT;
    DBMS_OUTPUT.PUT_LINE('DATA ROLLED BACK — ' || n || '행 COMMIT');
END;
