-- 05_BACKUP_CLOUD_SOURCE.sql — 적용 직전 클라우드 원문·PROC_M 을 테이블로 보관 (비파괴 · 멱등: 이미 있으면 SKIP)
-- 원복 시 98_ROLLBACK_FROM_CLOUD_BACKUP.sql 이 이 테이블로 클라우드 고유 상태를 재생성한다.
SET SERVEROUTPUT ON
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='BAK_SRC_DMF0082_SAVEPERF';
  IF n = 0 THEN
    EXECUTE IMMEDIATE q'[CREATE TABLE BAK_SRC_DMF0082_SAVEPERF AS
      SELECT NAME, TYPE, LINE, TEXT, SYSDATE AS BAK_DATE FROM USER_SOURCE WHERE NAME='PKG_DMF0082' AND TYPE IN ('PACKAGE','PACKAGE BODY')]';
    DBMS_OUTPUT.PUT_LINE('SOURCE BACKUP CREATED');
  ELSE
    DBMS_OUTPUT.PUT_LINE('SOURCE BACKUP EXISTS - SKIP');
  END IF;
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='BAK_PROCM_DMF0082_SAVEPERF';
  IF n = 0 THEN
    EXECUTE IMMEDIATE q'[CREATE TABLE BAK_PROCM_DMF0082_SAVEPERF AS
      SELECT T.*, SYSDATE AS BAK_DATE FROM SCM_ADM_PROC_M T WHERE PROC_NM='PKG_DMF0082.P_DMF0082_SAVE_MAIN_DATA']';
    DBMS_OUTPUT.PUT_LINE('PROC_M BACKUP CREATED');
  ELSE
    DBMS_OUTPUT.PUT_LINE('PROC_M BACKUP EXISTS - SKIP');
  END IF;
END;
/
SELECT NAME, TYPE, COUNT(*) LINES FROM BAK_SRC_DMF0082_SAVEPERF GROUP BY NAME, TYPE;
SELECT COUNT(*) PROCM_ROWS FROM BAK_PROCM_DMF0082_SAVEPERF;
