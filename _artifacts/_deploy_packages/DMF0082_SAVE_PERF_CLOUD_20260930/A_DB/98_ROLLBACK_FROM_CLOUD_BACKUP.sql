-- 98_ROLLBACK_FROM_CLOUD_BACKUP.sql — 05 에서 보관한 클라우드 고유 상태로 복원 (롤백 전용 · 평소 실행 안 함)
-- 순서: PROC_M 복원 → SPEC → BODY
UPDATE SCM_MGR.SCM_ADM_PROC_M T SET (DATA_TP_CD, SORT_ORD) = (SELECT B.DATA_TP_CD, B.SORT_ORD FROM BAK_PROCM_DMF0082_SAVEPERF B
                                                              WHERE B.PROC_NM=T.PROC_NM AND B.COL_NM=T.COL_NM AND B.COL_TP_CD=T.COL_TP_CD)
 WHERE T.PROC_NM = 'PKG_DMF0082.P_DMF0082_SAVE_MAIN_DATA'
   AND EXISTS (SELECT 1 FROM BAK_PROCM_DMF0082_SAVEPERF B WHERE B.PROC_NM=T.PROC_NM AND B.COL_NM=T.COL_NM AND B.COL_TP_CD=T.COL_TP_CD);
COMMIT;
SET SERVEROUTPUT ON
DECLARE
  PROCEDURE rebuild(p_type VARCHAR2) IS
    v CLOB;
  BEGIN
    DBMS_LOB.CREATETEMPORARY(v, TRUE);
    FOR r IN (SELECT TEXT FROM BAK_SRC_DMF0082_SAVEPERF WHERE NAME='PKG_DMF0082' AND TYPE=p_type ORDER BY LINE) LOOP
      DBMS_LOB.APPEND(v, r.TEXT);
    END LOOP;
    IF DBMS_LOB.GETLENGTH(v) > 0 THEN
      EXECUTE IMMEDIATE 'CREATE OR REPLACE ' || v;
      DBMS_OUTPUT.PUT_LINE('REBUILT ' || p_type);
    ELSE
      DBMS_OUTPUT.PUT_LINE('SKIP (no backup) ' || p_type);
    END IF;
  END;
BEGIN
  rebuild('PACKAGE');
  rebuild('PACKAGE BODY');
END;
/
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_DMF0082';
