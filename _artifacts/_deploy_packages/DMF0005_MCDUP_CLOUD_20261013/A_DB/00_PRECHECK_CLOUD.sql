  FROM (SELECT TO_CHAR(B.EVENT_DATE,'MM-DD HH24:MI:SS') T, B.LOG_TYPE
             , SUBSTR(REPLACE(B.LOG_MESSAGE, CHR(10), ' '), 1, 100) MSG, SUBSTR(REPLACE(B.DESCRIPTION, CHR(10), ' '), 1, 100) DESCR
          FROM SCM_SYS_LOG_BATCH B
