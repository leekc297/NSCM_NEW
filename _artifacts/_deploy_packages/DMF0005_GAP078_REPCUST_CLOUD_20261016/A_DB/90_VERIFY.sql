 WHERE NOT EXISTS (SELECT 1 FROM SCM_MST_SITE_CUSTOMER SC WHERE SC.DIVISION_ID = SI.DIVISION_ID AND UPPER(SC.SCM_SITE_ID) = UPPER(SI.SCM_SITE_ID) AND SC.REP_YN = 'Y' AND SC.VALID_YN = 'Y')
