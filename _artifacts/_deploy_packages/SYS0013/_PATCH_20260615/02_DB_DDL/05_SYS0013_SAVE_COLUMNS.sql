CREATE OR REPLACE PROCEDURE         SYS0013_SAVE_COLUMNS (
    P_ACTIVE_FLAG       IN VARCHAR2,
    P_DQ_ID             IN VARCHAR2,
    P_COLUMN_NAME       IN VARCHAR2,
    P_VALUE_YN          IN VARCHAR2,
    P_VALUE_TYPE        IN VARCHAR2,
    P_VALID_YN          IN VARCHAR2,
    P_ATTRIBUTE1        IN VARCHAR2,
    P_CREATED_BY        IN VARCHAR2,
    P_LAST_UPDATED_BY   IN VARCHAR2,
    O_RC1               OUT SYS_REFCURSOR
) IS
BEGIN
    INSERT INTO SCM_ADM_DQ_COLUMN_H (HISTORY_SEQ, DQ_ID, COLUMN_NAME, VALUE_YN, VALUE_TYPE, VALID_YN, ATTRIBUTE1,
                                     CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
    VALUES (SEQ1_SCM_ADM_DQ_COLUMN_H.NEXTVAL, NVL(P_DQ_ID,'-'), NVL(P_COLUMN_NAME,'-'),
            NVL(P_VALUE_YN,'N'), NVL(P_VALUE_TYPE,'STR'), NVL(P_VALID_YN,'Y'), P_ATTRIBUTE1,
            NVL(P_CREATED_BY,'system'), SYSDATE, NVL(P_LAST_UPDATED_BY,'system'), SYSDATE);

    IF P_ACTIVE_FLAG = 'I' THEN
        DELETE FROM SCM_ADM_DQ_COLUMN WHERE DQ_ID=P_DQ_ID AND COLUMN_NAME=P_COLUMN_NAME;
        INSERT INTO SCM_ADM_DQ_COLUMN (DQ_ID, COLUMN_NAME, VALUE_YN, VALUE_TYPE, VALID_YN, ATTRIBUTE1,
                                       CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
        VALUES (NVL(P_DQ_ID,'-'), NVL(P_COLUMN_NAME,'-'), NVL(P_VALUE_YN,'N'), NVL(P_VALUE_TYPE,'STR'),
                NVL(P_VALID_YN,'Y'), P_ATTRIBUTE1, NVL(P_CREATED_BY,'system'), SYSDATE,
                NVL(P_LAST_UPDATED_BY,'system'), SYSDATE);
    ELSIF P_ACTIVE_FLAG = 'M' THEN
        UPDATE SCM_ADM_DQ_COLUMN
           SET VALUE_YN=NVL(P_VALUE_YN,'N'), VALUE_TYPE=NVL(P_VALUE_TYPE,'STR'),
               VALID_YN=NVL(P_VALID_YN,'Y'), ATTRIBUTE1=P_ATTRIBUTE1,
               LAST_UPDATED_BY=NVL(P_LAST_UPDATED_BY,'system'), LAST_UPDATE_DATE=SYSDATE
         WHERE DQ_ID=P_DQ_ID AND COLUMN_NAME=P_COLUMN_NAME;
    ELSIF P_ACTIVE_FLAG = 'D' THEN
        DELETE FROM SCM_ADM_DQ_COLUMN WHERE DQ_ID=P_DQ_ID AND COLUMN_NAME=P_COLUMN_NAME;
    END IF;

    OPEN O_RC1 FOR SELECT 'success' AS CODE FROM DUAL;
END SYS0013_SAVE_COLUMNS;
