CREATE OR REPLACE PROCEDURE         SYS0013_SAVE_QUERY (
    P_ACTIVE_FLAG       IN VARCHAR2,
    P_DQ_ID             IN VARCHAR2,
    P_DIVISION_ID       IN VARCHAR2,
    P_DQ_NAME           IN VARCHAR2,
    P_DESCRIPTION       IN VARCHAR2,
    P_DQ_TEXT           IN CLOB,
    P_VALID_YN          IN VARCHAR2,
    P_ADMIN_ONLY_YN     IN VARCHAR2,
    P_CREATED_BY        IN VARCHAR2,
    P_LAST_UPDATED_BY   IN VARCHAR2,
    O_RC1               OUT SYS_REFCURSOR
) IS
    V_NEW_ID    NUMBER;
BEGIN
    -- HIST INSERT
    INSERT INTO SCM_ADM_DQ_LIST_H (HISTORY_SEQ, DQ_ID, DIVISION_ID, DQ_NAME, DESCRIPTION, DQ_TEXT, VALID_YN, ADMIN_ONLY_YN,
                                   CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
    VALUES (SEQ1_SCM_ADM_DQ_LIST_H.NEXTVAL, NVL(P_DQ_ID,'-'), NVL(P_DIVISION_ID,'-'), NVL(P_DQ_NAME,'-'),
            NVL(P_DESCRIPTION,'-'), NVL(P_DQ_TEXT,'-'), NVL(P_VALID_YN,'Y'), NVL(P_ADMIN_ONLY_YN,'Y'),
            NVL(P_CREATED_BY,'system'), SYSDATE, NVL(P_LAST_UPDATED_BY,'system'), SYSDATE);

    IF P_ACTIVE_FLAG = 'I' THEN
        SELECT NVL(MAX(TO_NUMBER(DQ_ID)),0)+1 INTO V_NEW_ID FROM SCM_ADM_DQ_LIST;
        INSERT INTO SCM_ADM_DQ_LIST (DQ_ID, DIVISION_ID, DQ_NAME, DESCRIPTION, DQ_TEXT, VALID_YN, ADMIN_ONLY_YN,
                                     CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
        VALUES (TO_CHAR(V_NEW_ID), NVL(P_DIVISION_ID,'-'), NVL(P_DQ_NAME,'-'), NVL(P_DESCRIPTION,'-'),
                NVL(P_DQ_TEXT,'-'), NVL(P_VALID_YN,'Y'), NVL(P_ADMIN_ONLY_YN,'Y'),
                NVL(P_CREATED_BY,'system'), SYSDATE, NVL(P_LAST_UPDATED_BY,'system'), SYSDATE);
    ELSIF P_ACTIVE_FLAG = 'M' THEN
        UPDATE SCM_ADM_DQ_LIST
           SET DIVISION_ID=NVL(P_DIVISION_ID,'-'), DQ_NAME=NVL(P_DQ_NAME,'-'),
               DESCRIPTION=NVL(P_DESCRIPTION,'-'), DQ_TEXT=NVL(P_DQ_TEXT,'-'),
               VALID_YN=NVL(P_VALID_YN,'Y'), ADMIN_ONLY_YN=NVL(P_ADMIN_ONLY_YN,'Y'),
               LAST_UPDATED_BY=NVL(P_LAST_UPDATED_BY,'system'), LAST_UPDATE_DATE=SYSDATE
         WHERE DQ_ID = P_DQ_ID;
        V_NEW_ID := TO_NUMBER(P_DQ_ID);
    ELSIF P_ACTIVE_FLAG = 'D' THEN
        DELETE FROM SCM_ADM_DQ_LIST WHERE DQ_ID = P_DQ_ID;
        V_NEW_ID := TO_NUMBER(P_DQ_ID);
    END IF;

    OPEN O_RC1 FOR SELECT 'success' AS CODE, V_NEW_ID AS SEQNO FROM DUAL;
END SYS0013_SAVE_QUERY;
