-- ===== Step 1: PKG_SYS0013 STATUS (BODY VALID 기대) =====
PROMPT === Step 1: PKG_SYS0013 STATUS ===
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') AS LAST_DDL
FROM USER_OBJECTS
WHERE OBJECT_NAME = 'PKG_SYS0013'
ORDER BY OBJECT_TYPE;

-- ===== Step 2: 종속 객체 모두 VALID 기대 =====
PROMPT === Step 2: 종속 객체 STATUS (INVALID 발견 시 root cause) ===
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS
FROM USER_OBJECTS
WHERE OBJECT_TYPE IN ('PROCEDURE', 'FUNCTION', 'TYPE')
  AND (OBJECT_NAME LIKE 'SYS0013%' OR OBJECT_NAME LIKE 'PR_DM_ADM_DQ%' OR OBJECT_NAME LIKE 'FN_DQ%' OR OBJECT_NAME IN ('T_DQ_STOCK_ROW','T_DQ_STOCK_TAB','T_FN_DQ_MKT_FCST_81_ROW','T_FN_DQ_MKT_FCST_81_TAB','FN_DQ_PROD_PLAN_ROW','FN_DQ_PROD_PLAN_TAB','FN_DQ_STOCK_ROW','FN_DQ_STOCK_TAB'))
ORDER BY STATUS DESC, OBJECT_TYPE, OBJECT_NAME;

-- ===== Step 3: SCMD_APP EXECUTE 권한 (PKG + SP + FN 모두 있어야) =====
PROMPT === Step 3: SCMD_APP EXECUTE 권한 ===
SELECT TABLE_NAME, PRIVILEGE
FROM ALL_TAB_PRIVS
WHERE GRANTEE = 'SCMD_APP'
  AND (TABLE_NAME = 'PKG_SYS0013' OR TABLE_NAME LIKE 'SYS0013%' OR TABLE_NAME LIKE 'PR_DM_ADM_DQ%' OR TABLE_NAME LIKE 'FN_DQ%')
ORDER BY TABLE_NAME;

-- ===== Step 4: PUBLIC SYNONYM 존재 (BE 가 PKG_SYS0013 호출 시 schema prefix 없이 사용) =====
PROMPT === Step 4: PUBLIC SYNONYM ===
SELECT SYNONYM_NAME, TABLE_OWNER, TABLE_NAME
FROM ALL_SYNONYMS
WHERE OWNER = 'PUBLIC'
  AND (SYNONYM_NAME = 'PKG_SYS0013' OR SYNONYM_NAME LIKE 'SYS0013%')
ORDER BY SYNONYM_NAME;

