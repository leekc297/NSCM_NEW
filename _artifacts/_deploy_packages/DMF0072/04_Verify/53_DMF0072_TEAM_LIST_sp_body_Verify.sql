-- V1: SP VALID
SELECT 'V1: TEAM SP VALID' AS CHECK_NAME, STATUS AS RESULT,
       CASE WHEN STATUS='VALID' THEN 'PASS' ELSE 'FAIL' END AS VERDICT
  FROM ALL_OBJECTS
 WHERE OWNER='SCM_MGR' AND OBJECT_NAME='DMF0072_GET_TEAM_LIST' AND OBJECT_TYPE='PROCEDURE';

-- V2: body 가 stub 이 아닌지 (라인 수 > 10 으로 충분)
SELECT 'V2: TEAM body line count (>10 expected)' AS CHECK_NAME,
       COUNT(*) AS RESULT_COUNT,
       CASE WHEN COUNT(*) > 10 THEN 'PASS' ELSE 'FAIL' END AS VERDICT
  FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='DMF0072_GET_TEAM_LIST';

-- V3: body 에 SCM_MST_SSO_DEPT_INFO JOIN 존재
SELECT 'V3: TEAM body has DEPT_INFO JOIN' AS CHECK_NAME,
       COUNT(*) AS PATTERN_CNT,
       CASE WHEN COUNT(*) > 0 THEN 'PASS' ELSE 'FAIL' END AS VERDICT
  FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='DMF0072_GET_TEAM_LIST'
   AND UPPER(TEXT) LIKE '%SCM_MST_SSO_DEPT_INFO%';

-- V4: body 에 UF_FX_STRING_SPLIT 사용
SELECT 'V4: TEAM body uses UF_FX_STRING_SPLIT' AS CHECK_NAME,
       COUNT(*) AS PATTERN_CNT,
       CASE WHEN COUNT(*) > 0 THEN 'PASS' ELSE 'FAIL' END AS VERDICT
  FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='DMF0072_GET_TEAM_LIST'
   AND UPPER(TEXT) LIKE '%UF_FX_STRING_SPLIT%';

-- V5: 호출 테스트 — ALL / 81 / 40 의 row 수 출력
SET SERVEROUTPUT ON
DECLARE
    V_RC SYS_REFCURSOR;
    V_CODE VARCHAR2(100);
    V_NAME VARCHAR2(300);
    V_CNT  PLS_INTEGER := 0;

    PROCEDURE COUNT_ROWS(P_DIV VARCHAR2) AS
    BEGIN
        V_CNT := 0;
        SCM_MGR.DMF0072_GET_TEAM_LIST(P_DIV, V_RC);
        LOOP
            FETCH V_RC INTO V_CODE, V_NAME;
            EXIT WHEN V_RC%NOTFOUND;
            V_CNT := V_CNT + 1;
        END LOOP;
        CLOSE V_RC;
        DBMS_OUTPUT.PUT_LINE('V5: TEAM_LIST(' || P_DIV || ') = ' || V_CNT || ' rows');
    END;
BEGIN
    COUNT_ROWS('ALL');
    COUNT_ROWS('81');
    COUNT_ROWS('40');
END;
