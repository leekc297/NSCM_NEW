          LEFT JOIN (SELECT SEGMENT1 AS CODE, SEGMENT2 AS NAME FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
                      WHERE LOOKUP_TYPE = 'ITEM_TYPE_CODE' AND VALID_YN = 'Y') ITC
