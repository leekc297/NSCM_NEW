--   DMF0072 화면 진입 시 -9994.
--   API_M : P_DMF0072_DIVISION_GET → DMF0008_GET_MY_DIVISION_LIST
--   그러나 cloud 에 DMF0008_GET_MY_DIVISION_LIST 미존재 (PLS-00201).
--   DMF0008 작업 시 080/090 SQL 에서 이미 SCM0001_GET_DIVISION 으로 routing 변경됨.
--   DMF0072 도 동일 fix 필요 (lookup combo division 호출).
--
-- 처치:
--   1. SCM_ADM_API_M : P_DMF0072_DIVISION_GET 의 API_URL → SCM0001_GET_DIVISION
--   2. SCM_ADM_PROC_M : SCM0001_GET_DIVISION 의 2-OUT sig 검증 (DMF0008 090 이미 INSERT — 멱등)
--
-- SCM0001_GET_DIVISION sig (SCM_MGR):
--   - O_RC1 OUT REF CURSOR (sort 1)
--   - O_RESULT_CURSOR OUT REF CURSOR (sort 2)
--   - IN 인자 없음
--
-- 작성: 2026-06-05
