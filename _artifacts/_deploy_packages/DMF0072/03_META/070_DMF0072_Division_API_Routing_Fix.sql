SET DEFINE OFF
SET SERVEROUTPUT ON
SET FEEDBACK ON

PROMPT === BLOCK 1 : DMF0072 의 P_DMF0072_DIVISION_GET API_URL 정정 ===

UPDATE SCM_MGR.SCM_ADM_API_M
   SET API_URL          = 'SCM0001_GET_DIVISION',
       LAST_UPDATED_BY  = 'admin',
       LAST_UPDATE_DATE = SYSDATE
 WHERE API_ID = 'P_DMF0072_DIVISION_GET'
   AND API_URL = 'DMF0008_GET_MY_DIVISION_LIST';

PROMPT === BLOCK 2 : SCM0001_GET_DIVISION PROC_M sig 검증 (이미 DMF0008 090 에서 INSERT) ===

SELECT proc_nm, col_nm, data_tp_cd, col_tp_cd, sort_ord
  FROM SCM_MGR.SCM_ADM_PROC_M
 WHERE proc_nm = 'SCM0001_GET_DIVISION'
 ORDER BY sort_ord;

PROMPT === BLOCK 3 : SCM0001_GET_DIVISION PROC_M 미존재 시 보강 (멱등 NOT EXISTS) ===

INSERT INTO SCM_MGR.SCM_ADM_PROC_M
  (PROC_NM, COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD,
   CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'SCM0001_GET_DIVISION', NEW.COL_NM, NEW.DATA_TP_CD, NEW.COL_TP_CD, NEW.SORT_ORD,
       'admin', SYSDATE, 'admin', SYSDATE
  FROM (
    SELECT 'o_rc1'           AS COL_NM, 'CURSOR'      AS DATA_TP_CD, 'OUT' AS COL_TP_CD, 1 AS SORT_ORD FROM DUAL UNION ALL
    SELECT 'O_RESULT_CURSOR',           'PROC_RESULT',                'OUT',                2          FROM DUAL
  ) NEW
 WHERE NOT EXISTS (
   SELECT 1 FROM SCM_MGR.SCM_ADM_PROC_M
    WHERE PROC_NM = 'SCM0001_GET_DIVISION' AND COL_NM = NEW.COL_NM
 );

PROMPT === BLOCK 4 : DMF0072/division/SEARCH chain 최종 검증 ===

SELECT BTN.MNU_ID, BTN.SHT_NM, BTN.MNU_BTN_CD,
       BTN.API_ID, API.API_URL,
       (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M P WHERE P.PROC_NM = API.API_URL) AS PROC_CNT,
       CASE WHEN API.API_URL = 'SCM0001_GET_DIVISION'
             AND (SELECT COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M P WHERE P.PROC_NM = API.API_URL) >= 2
              THEN 'PASS' ELSE 'FAIL' END AS RESULT
  FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M BTN
  LEFT JOIN SCM_MGR.SCM_ADM_API_M API ON API.API_ID = BTN.API_ID
 WHERE BTN.MNU_ID = 'DMF0072' AND BTN.SHT_NM = 'division';

PROMPT === BLOCK 5 : SCM0001_GET_DIVISION 직접 호출 검증 ===

DECLARE
  v_rc SYS_REFCURSOR;
  v_result_rc SYS_REFCURSOR;
  v_cnt PLS_INTEGER := 0;
  v_dummy VARCHAR2(4000);
BEGIN
  SCM_MGR.SCM0001_GET_DIVISION(
    O_RC1           => v_rc,
    O_RESULT_CURSOR => v_result_rc
  );
  BEGIN LOOP FETCH v_rc INTO v_dummy; EXIT WHEN v_rc%NOTFOUND OR v_cnt >= 3; v_cnt := v_cnt + 1; END LOOP;
  EXCEPTION WHEN OTHERS THEN v_cnt := -99; END;
  BEGIN CLOSE v_rc; EXCEPTION WHEN OTHERS THEN NULL; END;
  BEGIN CLOSE v_result_rc; EXCEPTION WHEN OTHERS THEN NULL; END;

  DBMS_OUTPUT.PUT_LINE('SCM0001_GET_DIVISION fetch = ' || v_cnt || ' (-99=multi-col 정상)');
EXCEPTION WHEN OTHERS THEN
  DBMS_OUTPUT.PUT_LINE('ERR ' || SQLCODE || ' / ' || SUBSTR(SQLERRM, 1, 300));
END;
/

COMMIT;

