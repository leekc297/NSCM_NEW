--==============================================================================
-- 55_DMF0072_popup_meta.sql  (SQL*Plus 본체)
--
-- 목적: DMF0072 의 Project/Item 팝업 SP 2종 메타 등록
--
-- 신규 sheet:
--   - projectPopup  : SEARCH → P_DMF0072_PROJECT_POPUP_GET → DMF0072_GET_PROJECT_POPUP_LIST
--   - itemPopup     : SEARCH → P_DMF0072_ITEM_POPUP_GET    → DMF0072_GET_ITEM_POPUP_LIST
--
-- PROC_M 인자 (메모리 feedback_proc_meta_mandatory):
--   - PROJECT: divisionId / deptId / endCustomer / scmSiteId / projectCode / etc + o_rc1
--   - ITEM:    divisionId / deptId / endCustomer / projectCode / scmSiteId / itemId / mdmActiveSw + o_rc1
--
-- BLOCK:
--   B1 MSG_M             : 2 API 메시지
--   B2 API_M             : 2 (P_DMF0072_PROJECT_POPUP_GET, P_DMF0072_ITEM_POPUP_GET)
--   B3 MNU_BTN_MPG_M     : 2 (projectPopup/SEARCH, itemPopup/SEARCH)
--   B4 PROC_M            : 7 + 8 = 15 컬럼
--   B5 GUEST 권한        : 2
--
-- 멱등성: NOT EXISTS 가드
-- 작성: 2026-06-02 (격차 B-2 메타 등록)
--==============================================================================
SET DEFINE OFF
SET SERVEROUTPUT ON
SET FEEDBACK ON
SET LINESIZE 200
WHENEVER SQLERROR EXIT FAILURE

PROMPT === BLOCK 1 : MSG_M (2 API 메시지) ===
INSERT INTO SCM_MGR.SCM_ADM_MSG_M (MSG_ID, LANG_CD, MSG_TP_CD, MSG_NM, MSG_DESC, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT NEW.MSG_ID, 'KO', 'API', NEW.MSG_NM, NEW.MSG_NM, 'Y', 'admin', SYSDATE, 'admin', SYSDATE
  FROM (
    SELECT 'MSG_API_DMF0072_PROJECT_POPUP_GET' AS MSG_ID, 'NN Mapping Project Popup 조회'        AS MSG_NM FROM DUAL UNION ALL
    SELECT 'MSG_API_DMF0072_ITEM_POPUP_GET',              'NN Mapping Model/Nickname Popup 조회'           FROM DUAL
  ) NEW
 WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_MSG_M X WHERE X.MSG_ID = NEW.MSG_ID AND X.LANG_CD='KO');

PROMPT === BLOCK 2 : API_M (2) ===
INSERT INTO SCM_MGR.SCM_ADM_API_M (API_ID, API_TP_CD, API_MSG_ID, API_MSG_DESC, API_URL, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT NEW.API_ID, 'PROC_SELECT', NEW.MSG_ID, NEW.MSG_DESC, NEW.API_URL, 'Y', 'admin', SYSDATE, 'admin', SYSDATE
  FROM (
    SELECT 'P_DMF0072_PROJECT_POPUP_GET' AS API_ID, 'MSG_API_DMF0072_PROJECT_POPUP_GET' AS MSG_ID, 'Project Popup 조회'        AS MSG_DESC, 'DMF0072_GET_PROJECT_POPUP_LIST' AS API_URL FROM DUAL UNION ALL
    SELECT 'P_DMF0072_ITEM_POPUP_GET',              'MSG_API_DMF0072_ITEM_POPUP_GET',              'Model/Nickname Popup 조회',             'DMF0072_GET_ITEM_POPUP_LIST'              FROM DUAL
  ) NEW
 WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_API_M X WHERE X.API_ID = NEW.API_ID);

PROMPT === BLOCK 3 : MNU_BTN_MPG_M (DMF0072 — 2 sheet) ===
INSERT INTO SCM_MGR.SCM_ADM_MNU_BTN_MPG_M (MNU_ID, SHT_NM, MNU_BTN_CD, API_ID, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'DMF0072', NEW.SHT_NM, 'SEARCH', NEW.API_ID, 'Y', 'admin', SYSDATE, 'admin', SYSDATE
  FROM (
    SELECT 'projectPopup' AS SHT_NM, 'P_DMF0072_PROJECT_POPUP_GET' AS API_ID FROM DUAL UNION ALL
    SELECT 'itemPopup',              'P_DMF0072_ITEM_POPUP_GET'              FROM DUAL
  ) NEW
 WHERE NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M X
    WHERE X.MNU_ID='DMF0072' AND X.SHT_NM=NEW.SHT_NM AND X.MNU_BTN_CD='SEARCH');

PROMPT === BLOCK 4 : PROC_M (15 컬럼 — 7 + 8) ===
INSERT INTO SCM_MGR.SCM_ADM_PROC_M (PROC_NM, COL_NM, DATA_TP_CD, COL_TP_CD, SORT_ORD, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT NEW.PROC_NM, NEW.COL_NM, NEW.DATA_TP_CD, NEW.COL_TP_CD, NEW.SORT_ORD, 'admin', SYSDATE, 'admin', SYSDATE
  FROM (
    -- PROJECT POPUP (6 IN + 1 OUT = 7)
    SELECT 'DMF0072_GET_PROJECT_POPUP_LIST' AS PROC_NM, 'divisionId'  AS COL_NM, 'VARCHAR' AS DATA_TP_CD, 'IN'  AS COL_TP_CD, 1 AS SORT_ORD FROM DUAL UNION ALL
    SELECT 'DMF0072_GET_PROJECT_POPUP_LIST',           'deptId',                  'VARCHAR',               'IN',                2 FROM DUAL UNION ALL
    SELECT 'DMF0072_GET_PROJECT_POPUP_LIST',           'endCustomer',             'VARCHAR',               'IN',                3 FROM DUAL UNION ALL
    SELECT 'DMF0072_GET_PROJECT_POPUP_LIST',           'scmSiteId',               'VARCHAR',               'IN',                4 FROM DUAL UNION ALL
    SELECT 'DMF0072_GET_PROJECT_POPUP_LIST',           'projectCode',             'VARCHAR',               'IN',                5 FROM DUAL UNION ALL
    SELECT 'DMF0072_GET_PROJECT_POPUP_LIST',           'etc',                     'VARCHAR',               'IN',                6 FROM DUAL UNION ALL
    SELECT 'DMF0072_GET_PROJECT_POPUP_LIST',           'o_rc1',                   'CURSOR',                'OUT',               7 FROM DUAL UNION ALL
    -- ITEM POPUP (7 IN + 1 OUT = 8)
    SELECT 'DMF0072_GET_ITEM_POPUP_LIST',              'divisionId',              'VARCHAR',               'IN',                1 FROM DUAL UNION ALL
    SELECT 'DMF0072_GET_ITEM_POPUP_LIST',              'deptId',                  'VARCHAR',               'IN',                2 FROM DUAL UNION ALL
    SELECT 'DMF0072_GET_ITEM_POPUP_LIST',              'endCustomer',             'VARCHAR',               'IN',                3 FROM DUAL UNION ALL
    SELECT 'DMF0072_GET_ITEM_POPUP_LIST',              'projectCode',             'VARCHAR',               'IN',                4 FROM DUAL UNION ALL
    SELECT 'DMF0072_GET_ITEM_POPUP_LIST',              'scmSiteId',               'VARCHAR',               'IN',                5 FROM DUAL UNION ALL
    SELECT 'DMF0072_GET_ITEM_POPUP_LIST',              'itemId',                  'VARCHAR',               'IN',                6 FROM DUAL UNION ALL
    SELECT 'DMF0072_GET_ITEM_POPUP_LIST',              'mdmActiveSw',             'VARCHAR',               'IN',                7 FROM DUAL UNION ALL
    SELECT 'DMF0072_GET_ITEM_POPUP_LIST',              'o_rc1',                   'CURSOR',                'OUT',               8 FROM DUAL
  ) NEW
 WHERE NOT EXISTS (
   SELECT 1 FROM SCM_MGR.SCM_ADM_PROC_M X
    WHERE X.PROC_NM = NEW.PROC_NM AND X.COL_NM = NEW.COL_NM AND X.COL_TP_CD = NEW.COL_TP_CD
 );

PROMPT === BLOCK 5 : GUEST 권한 (2) ===
INSERT INTO SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M (USER_GR_ID, MNU_ID, SHT_NM, MNU_BTN_CD, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT 'GUEST', BTN.MNU_ID, BTN.SHT_NM, BTN.MNU_BTN_CD, 'Y', 'admin', SYSDATE, 'admin', SYSDATE
  FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M BTN
 WHERE BTN.MNU_ID='DMF0072' AND BTN.SHT_NM IN ('projectPopup','itemPopup') AND BTN.USE_YN='Y'
   AND NOT EXISTS (SELECT 1 FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M X
     WHERE X.USER_GR_ID='GUEST' AND X.MNU_ID=BTN.MNU_ID AND X.SHT_NM=BTN.SHT_NM AND X.MNU_BTN_CD=BTN.MNU_BTN_CD);

PROMPT === BLOCK 6 : 사후 카운트 ===
SELECT 'POST: API_M (DMF0072 popup, 2 expected)' AS K, COUNT(*) AS V FROM SCM_MGR.SCM_ADM_API_M WHERE API_ID LIKE 'P_DMF0072_%POPUP%'
UNION ALL SELECT 'POST: BTN_MPG (popup sheet, 2)', COUNT(*) FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID='DMF0072' AND SHT_NM IN ('projectPopup','itemPopup')
UNION ALL SELECT 'POST: PROC_M PROJECT_POPUP (7)', COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M WHERE PROC_NM='DMF0072_GET_PROJECT_POPUP_LIST'
UNION ALL SELECT 'POST: PROC_M ITEM_POPUP (8)', COUNT(*) FROM SCM_MGR.SCM_ADM_PROC_M WHERE PROC_NM='DMF0072_GET_ITEM_POPUP_LIST'
UNION ALL SELECT 'POST: GUEST popup perm (2)', COUNT(*) FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE USER_GR_ID='GUEST' AND MNU_ID='DMF0072' AND SHT_NM IN ('projectPopup','itemPopup');

COMMIT;
PROMPT === COMPLETE ===
EXIT;
