-- DMF0035_DB_CLOUD_20260831 적용 후 검증 (SELECT-only)
SELECT 'P1 상태' S, OBJECT_NAME, OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI') LAST_DDL
  FROM ALL_OBJECTS WHERE OWNER='SCM_MGR' AND OBJECT_NAME IN ('PKG_DMF0022','PKG_DMF0035','PKG_DMF0051')
 ORDER BY OBJECT_NAME, OBJECT_TYPE;

SELECT 'P2 컴파일오류' S, NAME, LINE, SUBSTR(TEXT,1,200) ERR FROM ALL_ERRORS
 WHERE OWNER='SCM_MGR' AND NAME IN ('PKG_DMF0022','PKG_DMF0035','PKG_DMF0051') AND ATTRIBUTE='ERROR' ORDER BY NAME, SEQUENCE;

-- 기대값: 0022 W34=4/VERCASE=5 · 0035 W34=3/VERCASE=5 · 0051 W34=3/W41=3/VERCASE=2
SELECT 'P3 마커' S, NAME,
       SUM(CASE WHEN INSTR(TEXT,'E20260831-W34')>0 THEN 1 ELSE 0 END) W34,
       SUM(CASE WHEN INSTR(TEXT,'E20260831-VERCASE')>0 THEN 1 ELSE 0 END) VERCASE,
       SUM(CASE WHEN INSTR(TEXT,'E20260831-W41')>0 THEN 1 ELSE 0 END) W41
  FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME IN ('PKG_DMF0022','PKG_DMF0035','PKG_DMF0051') AND TYPE='PACKAGE BODY'
 GROUP BY NAME ORDER BY NAME;
