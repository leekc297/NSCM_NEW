-- DMF0082_AUTHGATE_CLOUD_20260826 검증
PROMPT ===== V1. PKG_DMF0082 신규 마커 (기대: AUTHVIEW=3, CUSTSUBORPH=1, SCPVMI=1) =====
SELECT 'AUTHVIEW' MARKER, COUNT(*) CNT FROM ALL_SOURCE
WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%E20260826-AUTHVIEW%'
UNION ALL
SELECT 'CUSTSUBORPH', COUNT(*) FROM ALL_SOURCE
WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%E20260826-CUSTSUBORPH%'
UNION ALL
SELECT 'SCPVMI', COUNT(*) FROM ALL_SOURCE
WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%E20260826-SCPVMI%';
PROMPT ===== V2. 공통 권한 SP 마커 (기대 3) =====
SELECT COUNT(*) CNT FROM ALL_SOURCE
WHERE OWNER='SCM_MGR' AND NAME='PKG_NSCM_UI_COM_AUTH' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%E20260826-BTNUSEYN%';
PROMPT ===== V3. 컴파일 상태 (기대 0행) =====
SELECT OBJECT_NAME, STATUS FROM ALL_OBJECTS
WHERE OWNER='SCM_MGR' AND OBJECT_NAME IN ('PKG_DMF0082','PKG_NSCM_UI_COM_AUTH') AND STATUS<>'VALID';
PROMPT ===== V4. 룩업 — SCP 시간창 6행 + DM 계열 A4 18행 + SCM A4 해제(잔존 0) =====
SELECT 'SCP_TUE' AXIS, COUNT(*) CNT FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
WHERE LOOKUP_TYPE='GET_ADMIN_GROUP_MEASURE' AND SEGMENT2='DMF0082' AND SEGMENT1='SCP Planner'
  AND SEGMENT3 LIKE '81%' AND SEGMENT4='MKT_FCST' AND ATTRIBUTE1='TUE'
UNION ALL
SELECT 'DM_A4', COUNT(*) FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
WHERE LOOKUP_TYPE='GET_ADMIN_GROUP_MEASURE' AND SEGMENT2='DMF0082'
  AND SEGMENT1 IN ('DM ADMIN','DM Planner','DM Planner (W/S)') AND SEGMENT3 LIKE '81%'
  AND SEGMENT4='MKT_FCST' AND ATTRIBUTE4='SCP Planner'
UNION ALL
SELECT 'SCM_A4_잔존(기대0)', COUNT(*) FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
WHERE LOOKUP_TYPE='GET_ADMIN_GROUP_MEASURE' AND SEGMENT2='DMF0082'
  AND SEGMENT3 LIKE '81%' AND SEGMENT4='SCM_FCST' AND ATTRIBUTE4 IS NOT NULL;
