-- 04_POSTCHECK — CLOUD_ORA12704_NCHARUNION_20260831 적용 후 검증 (SELECT-only)

-- 1) 3본 상태 — 전부 VALID 이어야 통과
SELECT 'P1 상태' AS SECTION, OBJECT_NAME, OBJECT_TYPE, STATUS,
       TO_CHAR(LAST_DDL_TIME, 'YYYY-MM-DD HH24:MI:SS') AS LAST_DDL
  FROM ALL_OBJECTS
 WHERE OWNER = 'SCM_MGR'
   AND OBJECT_NAME IN ('PKG_DMF0082', 'PKG_DMF0021', 'P_SYS0014_GET_AUTH_LIST_M')
 ORDER BY OBJECT_NAME, OBJECT_TYPE;

-- 2) 컴파일 오류 잔존 — 0행이어야 통과
SELECT 'P2 컴파일오류' AS SECTION, NAME, TYPE, LINE, POSITION, SUBSTR(TEXT, 1, 300) AS ERR
  FROM ALL_ERRORS
 WHERE OWNER = 'SCM_MGR'
   AND NAME IN ('PKG_DMF0082', 'PKG_DMF0021', 'P_SYS0014_GET_AUTH_LIST_M')
   AND ATTRIBUTE = 'ERROR'
 ORDER BY NAME, SEQUENCE;

-- 3) ORA-12704 전체 잔존 스윕 (다른 객체에 같은 계보가 남았는지) — 결과 = 남은 대상 목록
SELECT 'P3 12704잔존' AS SECTION, NAME, TYPE, COUNT(*) AS ERRS
  FROM ALL_ERRORS
 WHERE OWNER = 'SCM_MGR'
   AND ATTRIBUTE = 'ERROR'
   AND TEXT LIKE '%12704%'
 GROUP BY NAME, TYPE
 ORDER BY NAME;

-- 4) 정정 마커 실존 — 각 1 이상이어야 통과
SELECT 'P4 마커' AS SECTION, NAME,
       SUM(CASE WHEN INSTR(TEXT, 'E20260831-NCHARUNION') > 0 THEN 1 ELSE 0 END) AS CNT
  FROM ALL_SOURCE
 WHERE OWNER = 'SCM_MGR'
   AND NAME IN ('PKG_DMF0082', 'PKG_DMF0021', 'P_SYS0014_GET_AUTH_LIST_M')
 GROUP BY NAME
 ORDER BY NAME;

-- 5) 적용 후 화면 재조회 → 오류 재발 여부는 SCM_COM_SQL_LOG 로 재확인
SELECT 'P5 재발확인' AS SECTION, EXECUTE_TIME, SQL_ID, SUBSTR(EXCEPTION, 1, 300) AS EXCEPTION_TEXT
  FROM SCM_MGR.SCM_COM_SQL_LOG
 WHERE UPPER(SQL_TEXT) LIKE '%DMF0082%'
   AND EXCEPTION IS NOT NULL
   AND EXECUTE_TIME >= SYSDATE - 1/24
 ORDER BY EXECUTE_TIME DESC
 FETCH FIRST 10 ROWS ONLY;
