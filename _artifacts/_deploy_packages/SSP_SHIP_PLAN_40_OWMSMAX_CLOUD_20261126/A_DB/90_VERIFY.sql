/* 확인 (조회만). 기대값 : STATUS VALID, ERR_CNT 0, LINE_CNT 3583, SAME_AS_CORP_TOBE Y, MARK_DS2 1, MARK_OWMSMAX 1 */
ALTER SESSION SET CURRENT_SCHEMA = SCM_MGR;
SELECT O.OBJECT_NAME
     , O.STATUS
     , TO_CHAR(O.LAST_DDL_TIME, 'YYYY-MM-DD HH24:MI:SS') AS LAST_DDL_TIME
     , (SELECT COUNT(*) FROM ALL_ERRORS E WHERE E.OWNER = 'SCM_MGR' AND E.NAME = O.OBJECT_NAME) AS ERR_CNT
     , S.LINE_CNT
     , CASE WHEN S.LINE_CNT = 3583 AND S.H = 8003242559807 THEN 'Y' ELSE 'N' END AS SAME_AS_CORP_TOBE
     , S.MARK_DS2
     , S.MARK_OWMSMAX
  FROM ALL_OBJECTS O
     , (SELECT COUNT(*) AS LINE_CNT
             , SUM(ORA_HASH(TEXT)) AS H
             , COUNT(CASE WHEN INSTR(TEXT, 'E20261126-DS2') > 0 THEN 1 END) AS MARK_DS2
             , COUNT(CASE WHEN INSTR(TEXT, 'E20261126-OWMSMAX') > 0 THEN 1 END) AS MARK_OWMSMAX
          FROM ALL_SOURCE
         WHERE OWNER = 'SCM_MGR' AND NAME = 'PR_SSP_ANL_SHIP_PLAN_40' AND TYPE = 'PROCEDURE') S
 WHERE O.OWNER = 'SCM_MGR'
   AND O.OBJECT_NAME = 'PR_SSP_ANL_SHIP_PLAN_40'
   AND O.OBJECT_TYPE = 'PROCEDURE';
