-- DMF0082 FCST&PRICE MGMT 메타 검증
SELECT 'MNU_M' AS CHK, COUNT(*) AS ROW_CNT FROM SCM_MGR.SCM_ADM_MNU_M WHERE MNU_ID='DMF0082';
SELECT 'API_M' AS CHK, COUNT(*) AS ROW_CNT FROM SCM_MGR.SCM_ADM_API_M WHERE API_ID LIKE 'P_DMF0082%';
SELECT 'MNU_BTN_MPG' AS CHK, COUNT(*) AS ROW_CNT FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID='DMF0082';
SELECT 'PROC_M' AS CHK, COUNT(*) AS ROW_CNT FROM SCM_MGR.SCM_ADM_PROC_M WHERE PROC_NM LIKE 'DMF0082%';
SELECT 'SHEET_COLS' AS CHK, COUNT(*) AS ROW_CNT FROM SCM_MGR.SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID='DMF0082';
SELECT 'GUEST_BTN' AS CHK, COUNT(*) AS ROW_CNT FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE USER_GR_ID='GUEST' AND MNU_ID='DMF0082';

SELECT P.PROC_NM, COUNT(*) AS PROC_M_ROWS,
       (SELECT COUNT(*) FROM ALL_ARGUMENTS A WHERE A.OWNER='SCM_MGR' AND A.OBJECT_NAME=P.PROC_NM AND A.PACKAGE_NAME='PKG_DMF0082') AS SP_ARGS
  FROM SCM_MGR.SCM_ADM_PROC_M P WHERE P.PROC_NM LIKE 'DMF0082%' GROUP BY P.PROC_NM;
