-- ===== 진단 2: PROC_M ↔ SP signature mismatch =====
SELECT P.PROC_NM, P.COL_NM, P.SORT_ORD, P.COL_TP_CD AS PROC_M_TYPE,
       (SELECT A.ARGUMENT_NAME FROM ALL_ARGUMENTS A
         WHERE A.OWNER='SCM_MGR' AND A.OBJECT_NAME=P.PROC_NM
           AND A.PACKAGE_NAME='PKG_DMF0014' AND A.POSITION=P.SORT_ORD) AS SP_ARG_NAME,
       (SELECT A.IN_OUT FROM ALL_ARGUMENTS A
         WHERE A.OWNER='SCM_MGR' AND A.OBJECT_NAME=P.PROC_NM
           AND A.PACKAGE_NAME='PKG_DMF0014' AND A.POSITION=P.SORT_ORD) AS SP_IN_OUT
  FROM SCM_MGR.SCM_ADM_PROC_M P
 WHERE P.PROC_NM LIKE 'DMF0014%'
 ORDER BY P.PROC_NM, P.SORT_ORD;


-- ===== 진단 3: PKG body status =====
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS, LAST_DDL_TIME
  FROM ALL_OBJECTS WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_DMF0014';


-- ===== 진단 4: SHEET_COLUMNS ↔ SP 반환 alias case mismatch =====
SELECT PROGRAM_ID, SHT_NM, COLUMN_NAME, HDR_NM, SORT_ORD
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID='DMF0014' ORDER BY SORT_ORD;


-- ===== 진단 5: dedupe (feedback_sql_idempotent_insert_all) =====
