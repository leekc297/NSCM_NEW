SELECT 'API dup' AS CHK, API_ID, COUNT(*) AS CNT FROM SCM_MGR.SCM_ADM_API_M WHERE API_ID LIKE 'P_DMF0014%' GROUP BY API_ID HAVING COUNT(*) > 1;
SELECT 'SHEET dup' AS CHK, COLUMN_NAME, COUNT(*) AS CNT FROM SCM_MGR.SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID='DMF0014' GROUP BY COLUMN_NAME HAVING COUNT(*) > 1;
SELECT 'PROC dup' AS CHK, PROC_NM, COL_NM, COL_TP_CD, COUNT(*) AS CNT FROM SCM_MGR.SCM_ADM_PROC_M WHERE PROC_NM LIKE 'DMF0014%' GROUP BY PROC_NM, COL_NM, COL_TP_CD HAVING COUNT(*) > 1;


