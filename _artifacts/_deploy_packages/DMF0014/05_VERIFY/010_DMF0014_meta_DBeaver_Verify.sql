-- 1. 메뉴 (1 row 예상)
SELECT 'MNU_M' AS CHK, COUNT(*) AS ROW_CNT, 1 AS EXPECT FROM SCM_MGR.SCM_ADM_MNU_M WHERE MNU_ID='DMF0014';

-- 2. API_M (4 endpoint)
SELECT 'API_M' AS CHK, COUNT(*) AS ROW_CNT, 4 AS EXPECT FROM SCM_MGR.SCM_ADM_API_M WHERE API_ID LIKE 'P_DMF0014%';

-- 3. MNU_BTN_MPG (4 row)
SELECT 'MNU_BTN_MPG' AS CHK, COUNT(*) AS ROW_CNT, 4 AS EXPECT FROM SCM_MGR.SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID='DMF0014';

-- 4. PROC_M (47 row = 17 main + 7 title + 18 save + 5 excel upload)
SELECT 'PROC_M' AS CHK, COUNT(*) AS ROW_CNT, 47 AS EXPECT FROM SCM_MGR.SCM_ADM_PROC_M WHERE PROC_NM LIKE 'DMF0014%';

-- 5. SHEET_COLUMNS (15 cols)
SELECT 'SHEET_COLUMNS' AS CHK, COUNT(*) AS ROW_CNT, 15 AS EXPECT FROM SCM_MGR.SCM_MST_SHEET_COLUMNS WHERE PROGRAM_ID='DMF0014';

-- 6. MSG (5 API 메시지)
SELECT 'MSG_M' AS CHK, COUNT(*) AS ROW_CNT, 5 AS EXPECT FROM SCM_MGR.SCM_ADM_MSG_M WHERE MSG_ID LIKE 'MSG_API_DMF0014%';

-- 7. GUEST 메뉴 권한 (1 row)
SELECT 'GUEST_MNU' AS CHK, COUNT(*) AS ROW_CNT, 1 AS EXPECT FROM SCM_MGR.SCM_ADM_USER_GR_MNU_MPG_M WHERE USER_GR_ID='GUEST' AND MNU_ID='DMF0014';

-- 8. GUEST 버튼 권한 (4 row)
SELECT 'GUEST_BTN' AS CHK, COUNT(*) AS ROW_CNT, 4 AS EXPECT FROM SCM_MGR.SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE USER_GR_ID='GUEST' AND MNU_ID='DMF0014';

-- 9. minyonglee1 그룹 메뉴 권한
SELECT 'minyonglee1_MNU' AS CHK, COUNT(*) AS ROW_CNT, 1 AS EXPECT_MIN
  FROM SCM_MGR.SCM_ADM_USER_GR_MNU_MPG_M
 WHERE MNU_ID='DMF0014'
   AND USER_GR_ID IN (SELECT USER_GR_ID FROM SCM_MGR.SCM_ADM_USER_GR_MPG_M WHERE USER_ID='minyonglee1' AND USE_YN='Y');

-- 10. PROC_M ↔ SP signature 매치 (proc-meta-signature-match hook)
SELECT P.PROC_NM,
       COUNT(*) AS PROC_M_ROWS,
       (SELECT COUNT(*) FROM ALL_ARGUMENTS A
         WHERE A.OWNER='SCM_MGR' AND A.OBJECT_NAME=P.PROC_NM AND A.PACKAGE_NAME='PKG_DMF0014') AS SP_ARGS,
       CASE
         WHEN COUNT(*) = (SELECT COUNT(*) FROM ALL_ARGUMENTS A
                           WHERE A.OWNER='SCM_MGR' AND A.OBJECT_NAME=P.PROC_NM AND A.PACKAGE_NAME='PKG_DMF0014')
         THEN 'MATCH' ELSE 'MISMATCH'
       END AS STATUS
  FROM SCM_MGR.SCM_ADM_PROC_M P
 WHERE P.PROC_NM LIKE 'DMF0014%'
 GROUP BY P.PROC_NM
 ORDER BY P.PROC_NM;

-- 11. PKG_DMF0014 status VALID
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS, LAST_DDL_TIME
  FROM ALL_OBJECTS
 WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_DMF0014'
 ORDER BY OBJECT_TYPE;
