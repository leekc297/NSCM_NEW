-- ── ① CMBO 'DMF0042CellProdSite' (표시용 — ALL) ──
MERGE INTO SCM_MGR.SCM_ADM_CMBO_SQL_M t
USING (
  SELECT 'DMF0042CellProdSite' SQL_ID, 'DM' MDU_DIVS_CD,
         'DMF0042 Cell Prod Site (표시 — DM_CELL_PROD_SITE 전체, 코드→한글)' SQL_NM,
'SELECT SEGMENT1 AS CODE
      , ATTRIBUTE1 AS NAME
FROM   SCM_ADM_LOOKUP_MASTER_DETAIL
WHERE  LOOKUP_TYPE = ''DM_CELL_PROD_SITE''
ORDER BY DISPLAY_SEQ' SQL_DTL_CTN
  FROM DUAL
) s
ON (t.SQL_ID = s.SQL_ID)
WHEN MATCHED THEN UPDATE SET t.MDU_DIVS_CD = s.MDU_DIVS_CD, t.SQL_NM = s.SQL_NM,
  t.SQL_DTL_CTN = s.SQL_DTL_CTN, t.USE_YN = 'Y',
  t.LAST_UPDATED_BY = 'admin', t.LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (SQL_ID, MDU_DIVS_CD, SQL_NM, SQL_DTL_CTN, USE_YN,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES (s.SQL_ID, s.MDU_DIVS_CD, s.SQL_NM, s.SQL_DTL_CTN, 'Y',
  'admin', SYSDATE, 'admin', SYSDATE);

-- ── ② CMBO 'DMF0042CellProdSiteValid' (편집용 — VALID_YN='Y' 만, [C20220513-000327]) ──
MERGE INTO SCM_MGR.SCM_ADM_CMBO_SQL_M t
USING (
  SELECT 'DMF0042CellProdSiteValid' SQL_ID, 'DM' MDU_DIVS_CD,
         'DMF0042 Cell Prod Site (신규행 편집 — DM_CELL_PROD_SITE 유효건만)' SQL_NM,
'SELECT SEGMENT1 AS CODE
      , ATTRIBUTE1 AS NAME
FROM   SCM_ADM_LOOKUP_MASTER_DETAIL
WHERE  LOOKUP_TYPE = ''DM_CELL_PROD_SITE''
AND    VALID_YN = ''Y''
ORDER BY DISPLAY_SEQ' SQL_DTL_CTN
  FROM DUAL
) s
ON (t.SQL_ID = s.SQL_ID)
WHEN MATCHED THEN UPDATE SET t.MDU_DIVS_CD = s.MDU_DIVS_CD, t.SQL_NM = s.SQL_NM,
  t.SQL_DTL_CTN = s.SQL_DTL_CTN, t.USE_YN = 'Y',
  t.LAST_UPDATED_BY = 'admin', t.LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (SQL_ID, MDU_DIVS_CD, SQL_NM, SQL_DTL_CTN, USE_YN,
  CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
VALUES (s.SQL_ID, s.MDU_DIVS_CD, s.SQL_NM, s.SQL_DTL_CTN, 'Y',
  'admin', SYSDATE, 'admin', SYSDATE);

-- ── ③ SHEET_COLUMNS — 'Biz Plan'/CELL_PROD_SITE → FPComboBox 배선 (기존 1행 UPDATE — 실측:
--     CTRL/COMBO 공란, DIVISION_ID='40', ATTRIBUTE1='DM_CELL_PROD_SITE', VISIBLE_FLAG='Y') ──
UPDATE SCM_MGR.SCM_MST_SHEET_COLUMNS
   SET CELL_CONTROL_OBJECT_TYPE_CODE = 'FPComboBox',
       CELL_COMBO_DATA_TYPE = 'DMF0042CellProdSite',
       LAST_UPDATED_BY = 'admin',
       LAST_UPDATE_DATE = SYSDATE
 WHERE PROGRAM_ID = 'DMF0042'
   AND SHEET_NAME = 'Biz Plan'
   AND COLUMN_NAME = 'CELL_PROD_SITE';

COMMIT;

