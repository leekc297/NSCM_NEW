-- 00_PRECHECK — 조회 전용 (전체 F5, 값 입력 없음). [DMF0005 SYN SCMP_APP] 적용 전 상태
-- * [L0] 접속 DB · 실행 계정 · 시노님 생성 권한
-- * [L1] 대상 원본 테이블 FP_MGR.SCM_PLANT_M / SCM_COMPANY_M 존재 (없으면 10 실행 금지·회신)
-- * [L2] 기준 시노님 SCM_MGR.SCM_MST_PLANT_SN / SCM_MST_COMPANY_SN 이 가리키는 대상
-- * [L3] 앱계정 SCMP_APP 의 같은 이름 시노님 — 적용 전 0 기대(있으면 10 은 SKIP)
SET LINESIZE 220 PAGESIZE 300
SET DEFINE OFF
SELECT 'L0' CHK, SYS_CONTEXT('USERENV','DB_NAME') DB_NAME, USER RUN_USER, TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI:SS') NOW FROM DUAL;
SELECT 'L0 권한' CHK, PRIVILEGE FROM SESSION_PRIVS WHERE PRIVILEGE IN ('CREATE ANY SYNONYM', 'DROP ANY SYNONYM') ORDER BY 2;
SELECT 'L0 앱계정' CHK, USERNAME, CASE WHEN COUNT(*) OVER () = 1 THEN 'PASS' END JUDGE FROM ALL_USERS WHERE USERNAME = 'SCMP_APP';
SELECT 'L1 원본' CHK, OWNER, OBJECT_NAME, OBJECT_TYPE, STATUS FROM ALL_OBJECTS
 WHERE OWNER = 'FP_MGR' AND OBJECT_NAME IN ('SCM_PLANT_M', 'SCM_COMPANY_M') AND OBJECT_TYPE IN ('TABLE', 'VIEW') ORDER BY 3;
SELECT 'L2 기준' CHK, OWNER, SYNONYM_NAME, TABLE_OWNER, TABLE_NAME FROM ALL_SYNONYMS
 WHERE OWNER = 'SCM_MGR' AND SYNONYM_NAME IN ('SCM_MST_PLANT_SN', 'SCM_MST_COMPANY_SN') ORDER BY 3;
SELECT 'L3 앱계정 시노님' CHK, OWNER, SYNONYM_NAME, TABLE_OWNER, TABLE_NAME FROM ALL_SYNONYMS
 WHERE OWNER = 'SCMP_APP' AND SYNONYM_NAME IN ('SCM_MST_PLANT_SN', 'SCM_MST_COMPANY_SN') ORDER BY 3;
