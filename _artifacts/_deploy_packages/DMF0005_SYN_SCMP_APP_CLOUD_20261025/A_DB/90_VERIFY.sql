-- * [V1] SCMP_APP 시노님 2건 존재·대상 일치
-- * [V2] SCMP_APP 가 원본을 읽을 권한(직접 또는 역할) — 시노님만 있고 권한이 없으면 여전히 ORA-00942/01031
-- * [V3] 콤보 SQL 원문(SCM_ADM_CMBO_SQL_M)이 이 시노님을 쓰는지 — 영향 콤보 목록
SET LINESIZE 220 PAGESIZE 300
SET DEFINE OFF
SELECT 'V1' CHK, S.SYNONYM_NAME, S.TABLE_OWNER || '.' || S.TABLE_NAME TARGET,
       CASE WHEN (S.SYNONYM_NAME = 'SCM_MST_PLANT_SN' AND S.TABLE_NAME = 'SCM_PLANT_M')
              OR (S.SYNONYM_NAME = 'SCM_MST_COMPANY_SN' AND S.TABLE_NAME = 'SCM_COMPANY_M') THEN 'PASS' ELSE 'FAIL — 회신' END JUDGE
  FROM ALL_SYNONYMS S WHERE S.OWNER = 'SCMP_APP' AND S.SYNONYM_NAME IN ('SCM_MST_PLANT_SN', 'SCM_MST_COMPANY_SN') ORDER BY 2;
SELECT 'V1 건수' CHK, COUNT(*) N, CASE WHEN COUNT(*) = 2 THEN 'PASS' ELSE 'FAIL — 10 출력 회신' END JUDGE
  FROM ALL_SYNONYMS WHERE OWNER = 'SCMP_APP' AND SYNONYM_NAME IN ('SCM_MST_PLANT_SN', 'SCM_MST_COMPANY_SN');
SELECT 'V2 직접' CHK, GRANTEE, TABLE_NAME, PRIVILEGE FROM ALL_TAB_PRIVS
 WHERE GRANTEE = 'SCMP_APP' AND TABLE_SCHEMA = 'FP_MGR' AND TABLE_NAME IN ('SCM_PLANT_M', 'SCM_COMPANY_M') AND PRIVILEGE = 'SELECT';
SELECT 'V2 역할' CHK, R.ROLE, R.TABLE_NAME, R.PRIVILEGE FROM ROLE_TAB_PRIVS R
 WHERE R.OWNER = 'FP_MGR' AND R.TABLE_NAME IN ('SCM_PLANT_M', 'SCM_COMPANY_M') AND R.PRIVILEGE = 'SELECT' ORDER BY 2, 3;
-- ↑ V2 역할 행이 나오면 그 역할이 SCMP_APP 에 부여됐는지 DBA 가 DBA_ROLE_PRIVS 로 확인(사내 = RL_FP_SEL 부여됨)
SELECT 'V3 영향 콤보' CHK, SQL_ID FROM SCM_ADM_CMBO_SQL_M
 WHERE USE_YN = 'Y' AND (UPPER(SQL_DTL_CTN) LIKE '%SCM_MST_PLANT_SN%' OR UPPER(SQL_DTL_CTN) LIKE '%SCM_MST_COMPANY_SN%') ORDER BY 2;
