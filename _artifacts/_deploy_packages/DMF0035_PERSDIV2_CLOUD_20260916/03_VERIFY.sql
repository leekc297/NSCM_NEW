-- ⚠ 코드행 판정은 주석 제외(LTRIM(TEXT) NOT LIKE '--%') — 설명 주석이 구 문구를 인용한다.

-- V1. 객체 상태 (기대: 3본 PACKAGE/PACKAGE BODY 전부 VALID)
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL
  FROM ALL_OBJECTS WHERE OWNER='SCM_MGR'
   AND OBJECT_NAME IN ('PKG_DMF0035','PKG_DMF0022','PKG_DMF0051') ORDER BY 1,2;

-- V2. 컴파일 오류 (기대: 0)
SELECT NAME, COUNT(*) ERR FROM ALL_ERRORS
 WHERE OWNER='SCM_MGR' AND NAME IN ('PKG_DMF0035','PKG_DMF0022','PKG_DMF0051') AND TYPE='PACKAGE BODY'
 GROUP BY NAME;

-- V3. 개인화 컬럼 division 필터 코드행 실재 (기대: PKG_DMF0035>=1, PKG_DMF0022>=1)
SELECT NAME, COUNT(*) CNT FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME IN ('PKG_DMF0035','PKG_DMF0022') AND TYPE='PACKAGE BODY'
   AND LTRIM(TEXT) NOT LIKE '--%'
   AND TEXT LIKE '%INSTR('','' || C.DIVISION_ID || '','',%'
 GROUP BY NAME;

-- V4. PKG_DMF0035 메저 정정 — 구 'ROWNUM = 1' 토큰 원천 소멸(기대 0) / 신 토큰식 실재(기대 2)
SELECT SUM(CASE WHEN TEXT LIKE '%ROWNUM = 1) A%' THEN 1 ELSE 0 END) OLD_TOKEN,
       SUM(CASE WHEN TEXT LIKE '%REGEXP_SUBSTR(A.DIVISION_ID, ''[^,]+'', 1, LV.LVL)%' THEN 1 ELSE 0 END) NEW_TOKEN
  FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0035' AND TYPE='PACKAGE BODY'
   AND LTRIM(TEXT) NOT LIKE '--%';

-- V5. PKG_DMF0051 은 **무변경** — 원래부터 두 필터를 보유한다. 존재만 확인(기대: 각 1 이상)
SELECT SUM(CASE WHEN TEXT LIKE '%UF_FX_STRING_SPLIT(C.DIVISION_ID%' THEN 1 ELSE 0 END) COL_FILTER,
       SUM(CASE WHEN TEXT LIKE '%INSTR('','' || M.DIVISION_ID || '','',%' THEN 1 ELSE 0 END) MEASURE_FILTER
  FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0051' AND TYPE='PACKAGE BODY'
   AND LTRIM(TEXT) NOT LIKE '--%';

