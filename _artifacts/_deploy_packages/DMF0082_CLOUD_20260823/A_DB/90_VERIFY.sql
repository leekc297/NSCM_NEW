LEFT   JOIN (SELECT DISTINCT PROC_NM FROM SCM_MGR.SCM_ADM_PROC_M) P ON P.PROC_NM = A.API_URL
LEFT   JOIN ALL_OBJECTS O ON O.OWNER='SCM_MGR'
       AND O.OBJECT_NAME = NVL(REGEXP_SUBSTR(A.API_URL,'^[^.]+'), A.API_URL)
WHERE  B.MNU_ID='DMF0082' AND B.API_ID IS NOT NULL
AND    (A.API_ID IS NULL OR P.PROC_NM IS NULL OR O.OBJECT_NAME IS NULL);

