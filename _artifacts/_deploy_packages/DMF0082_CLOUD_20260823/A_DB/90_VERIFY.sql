PROMPT ===== V9. 배선 체인 (BTN_MPG → API_M → PROC_M → SP 실존) 끊김 검출 (기대 0행) =====
SELECT B.SHT_NM, B.MNU_BTN_CD, B.API_ID,
       CASE WHEN A.API_ID IS NULL THEN 'API_M 없음 ⛔'
            WHEN P.PROC_NM IS NULL THEN 'PROC_M 없음 ⛔'
            ELSE 'SP 없음 ⛔' END GAP
FROM   SCM_MGR.SCM_ADM_MNU_BTN_MPG_M B
