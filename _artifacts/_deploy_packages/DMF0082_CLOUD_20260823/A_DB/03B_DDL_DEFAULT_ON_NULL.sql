-- 5) GT_PRDM1_T_MAIN (13 키 — NULLABLE → DEFAULT ON NULL '-' NOT NULL 승격, 컬럼별 가드)
--    ⭐ 이 승격이 적용되면 신 BODY 의 [E20260820-SENTINELDDL] 전제(구 [PK-NN] N1/N2 정규화 UPDATE 삭제)가 성립.
--    ⚠ ORA-14450 발생 시 = GTT 사용 세션 존재 — BE 중지 후 재실행.
DECLARE
  PROCEDURE one(p_col VARCHAR2) IS
    v_null VARCHAR2(1);
  BEGIN
    SELECT NULLABLE INTO v_null FROM ALL_TAB_COLUMNS
     WHERE OWNER='SCM_MGR' AND TABLE_NAME='GT_PRDM1_T_MAIN' AND COLUMN_NAME=p_col;
    IF v_null = 'Y' THEN
      EXECUTE IMMEDIATE 'ALTER TABLE SCM_MGR.GT_PRDM1_T_MAIN MODIFY ('
        || p_col || ' DEFAULT ON NULL ''-'' NOT NULL)';
    END IF;
  END;
BEGIN
  one('DIVISION_ID');   one('PROJECT_CODE'); one('END_CUSTOMER');      one('SCM_SITE_ID');
  one('ITEM_ID');       one('DOM_EXP');      one('FCST_TYPE');         one('INCOTERMS');
  one('MEASURE');       one('PLANT_SITE_ID');one('CELL_PROD_SITE_ID'); one('YYYYMMDD');
  one('CURRENCY');
END;
/

