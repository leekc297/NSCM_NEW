CREATE OR REPLACE PROCEDURE         SYS0013_SAVE_PARAMETERS (
    P_ACTIVE_FLAG       IN VARCHAR2,
    P_DQ_ID             IN VARCHAR2,
    P_PARAMETER_ID      IN VARCHAR2,
    P_PARAMETER_TYPE    IN VARCHAR2,
    P_OPERATION_ID      IN VARCHAR2,
    P_VALID_YN          IN VARCHAR2,
    P_REP_YN            IN VARCHAR2,
    P_ATTRIBUTE1        IN VARCHAR2,
    P_CREATED_BY        IN VARCHAR2,
    P_LAST_UPDATED_BY   IN VARCHAR2,
    O_RC1               OUT SYS_REFCURSOR
) IS
BEGIN
    INSERT INTO SCM_ADM_DQ_PARAMETER_H (HISTORY_SEQ, DQ_ID, PARAMETER_ID, PARAMETER_TYPE, OPERATION_ID,
                                        VALID_YN, REP_YN, ATTRIBUTE1, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
    VALUES (SEQ1_SCM_ADM_DQ_PARAMETER_H.NEXTVAL, NVL(P_DQ_ID,'-'), NVL(P_PARAMETER_ID,'-'),
            NVL(P_PARAMETER_TYPE,'TEXT'), NVL(P_OPERATION_ID,'-'), NVL(P_VALID_YN,'Y'), NVL(P_REP_YN,'N'),
            P_ATTRIBUTE1, NVL(P_CREATED_BY,'system'), SYSDATE, NVL(P_LAST_UPDATED_BY,'system'), SYSDATE);

    IF P_ACTIVE_FLAG = 'I' THEN
        DELETE FROM SCM_ADM_DQ_PARAMETER WHERE DQ_ID=P_DQ_ID AND PARAMETER_ID=P_PARAMETER_ID;
        INSERT INTO SCM_ADM_DQ_PARAMETER (DQ_ID, PARAMETER_ID, PARAMETER_TYPE, OPERATION_ID, VALID_YN, REP_YN,
                                          ATTRIBUTE1, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
        VALUES (NVL(P_DQ_ID,'-'), NVL(P_PARAMETER_ID,'-'), NVL(P_PARAMETER_TYPE,'TEXT'),
                NVL(P_OPERATION_ID,'-'), NVL(P_VALID_YN,'Y'), NVL(P_REP_YN,'N'), P_ATTRIBUTE1,
                NVL(P_CREATED_BY,'system'), SYSDATE, NVL(P_LAST_UPDATED_BY,'system'), SYSDATE);
    ELSIF P_ACTIVE_FLAG = 'M' THEN
        UPDATE SCM_ADM_DQ_PARAMETER
           SET PARAMETER_TYPE=NVL(P_PARAMETER_TYPE,'TEXT'), OPERATION_ID=NVL(P_OPERATION_ID,'-'),
               VALID_YN=NVL(P_VALID_YN,'Y'), REP_YN=NVL(P_REP_YN,'N'), ATTRIBUTE1=P_ATTRIBUTE1,
               LAST_UPDATED_BY=NVL(P_LAST_UPDATED_BY,'system'), LAST_UPDATE_DATE=SYSDATE
         WHERE DQ_ID=P_DQ_ID AND PARAMETER_ID=P_PARAMETER_ID;
    ELSIF P_ACTIVE_FLAG = 'D' THEN
        DELETE FROM SCM_ADM_DQ_PARAMETER WHERE DQ_ID=P_DQ_ID AND PARAMETER_ID=P_PARAMETER_ID;
    END IF;

    OPEN O_RC1 FOR SELECT 'success' AS CODE FROM DUAL;
END SYS0013_SAVE_PARAMETERS;
