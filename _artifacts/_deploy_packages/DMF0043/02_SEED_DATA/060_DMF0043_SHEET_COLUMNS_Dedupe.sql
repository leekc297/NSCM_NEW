-- 56_DMF0043_SHEET_COLUMNS_Dedupe.sql
--
-- 사고: DMF0043 조회 ORA-01427 (single-row subquery > 1 row).
-- 원인: SCM_MST_SHEET_COLUMNS 에 DMF0043/ContributeMain 의 8개 컬럼이 각 2건씩 중복 seed.
--       (DEPARTMENT_ID, DEPT_ID, DM_BIZ_TYPE, EDIT_FLAG, END_CUST_REPORT,
--        PRODUCT_GROUP, SOLDTO_CUST_REPORT, VER_SEQ)
--       SP 본문 `... > (SELECT TO_NUMBER(SORT_ORDER_NO) FROM GT_TITLE WHERE COLUMN_NAME='EDIT_FLAG')`
--       이 multi-row 되어 폭발.
--
-- 결정: PARTITION BY (COLUMN_NAME, DIVISION_ID) ROW_NUMBER 로 dedupe. rn=1 (oldest ROWID) 유지.
--
-- 작성: 2026-06-01 / minyonglee1
--==============================================================================
SET DEFINE OFF
SET SERVEROUTPUT ON
SET FEEDBACK ON
WHENEVER SQLERROR EXIT FAILURE

PROMPT === BLOCK 1 : Dedupe before/after counts ===
SELECT COUNT(*) AS CNT_BEFORE FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
WHERE PROGRAM_ID='DMF0043' AND SHEET_NAME='ContributeMain';

PROMPT === BLOCK 2 : Delete duplicates (keep MIN ROWID per COLUMN_NAME + DIVISION_ID) ===
DELETE FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
WHERE PROGRAM_ID='DMF0043' AND SHEET_NAME='ContributeMain'
  AND ROWID IN (
    SELECT R FROM (
      SELECT ROWID R,
             ROW_NUMBER() OVER (PARTITION BY COLUMN_NAME, DIVISION_ID ORDER BY ROWID) rn
        FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
       WHERE PROGRAM_ID='DMF0043' AND SHEET_NAME='ContributeMain'
    ) WHERE rn > 1
  );
COMMIT;

PROMPT === BLOCK 3 : After dedupe verification ===
SELECT COUNT(*) AS CNT_AFTER FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
WHERE PROGRAM_ID='DMF0043' AND SHEET_NAME='ContributeMain';

SELECT COLUMN_NAME, DIVISION_ID, COUNT(*) DUP_CNT
FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
WHERE PROGRAM_ID='DMF0043' AND SHEET_NAME='ContributeMain'
GROUP BY COLUMN_NAME, DIVISION_ID
HAVING COUNT(*) > 1;

PROMPT === BLOCK 4 : Caller execute verify ===
DECLARE
  v_rc SYS_REFCURSOR;
  v_title_cnt NUMBER;
  v_temp_cnt  NUMBER;
  v_data_cnt  NUMBER;
BEGIN
  DELETE FROM GT_DMF0043_TITLE;
  DELETE FROM GT_DMF0043_TEMP;
  DELETE FROM GT_DMF0043_TEMP2;
  DELETE FROM GT_DMF0043_TEMP3;
  DELETE FROM GT_DMF0043_DATA_TABLE;

  DMF0043_GET_CONTRIBUTE_MAIN_DATA('2023','8','ALL','N','minyonglee1','',v_rc);

  SELECT COUNT(*) INTO v_title_cnt FROM GT_DMF0043_TITLE;
  SELECT COUNT(*) INTO v_temp_cnt  FROM GT_DMF0043_TEMP;
  SELECT COUNT(*) INTO v_data_cnt  FROM GT_DMF0043_DATA_TABLE;

  DBMS_OUTPUT.PUT_LINE('GT_DMF0043_TITLE      = ' || v_title_cnt || ' rows');
  DBMS_OUTPUT.PUT_LINE('GT_DMF0043_TEMP       = ' || v_temp_cnt  || ' rows');
  DBMS_OUTPUT.PUT_LINE('GT_DMF0043_DATA_TABLE = ' || v_data_cnt  || ' rows');
  BEGIN CLOSE v_rc; EXCEPTION WHEN OTHERS THEN NULL; END;
EXCEPTION WHEN OTHERS THEN
  DBMS_OUTPUT.PUT_LINE('CALLER ERROR: ' || SQLERRM);
END;
/

EXIT;
