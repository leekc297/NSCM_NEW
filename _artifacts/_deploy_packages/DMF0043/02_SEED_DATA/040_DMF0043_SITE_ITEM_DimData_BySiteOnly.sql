--==============================================================================
-- 64_DMF0043_SITE_ITEM_DimData_BySiteOnly.sql
--
-- 63 적용 결과 1 row만 매칭. 원인: 로컬/As-Is 의 ITEM_ID snapshot 차이.
-- 본 fix: (DIVISION_ID, SCM_SITE_ID) 단위로 매칭하여 같은 site 의 모든 ITEM 에 dim 적용.
--==============================================================================
SET DEFINE OFF
SET SERVEROUTPUT ON
SET FEEDBACK ON
WHENEVER SQLERROR EXIT FAILURE

PROMPT === BLOCK 1 : 가용 site_id 확인 ===
SELECT SCM_SITE_ID, COUNT(*) AS ITEM_CNT
FROM SCM_MGR.SCM_MST_SITE_ITEM
WHERE DIVISION_ID='40' AND SCM_SITE_ID IN (
  'Acell_TW_NTC','BAE Systems_US_ENC','Boston Dynamics_US_WLM','C-Tech_TW_TPE',
  'EATON_HK_YUE','Desay_CN_HUI','ReBuild_US_NKP','Rivian Automotive_US_TUN',
  'STL_TW_KHH','Trend Power Singapore_TW_HSZ'
)
GROUP BY SCM_SITE_ID
ORDER BY SCM_SITE_ID;

PROMPT === BLOCK 2 : Site 단위 UPDATE — 모든 row 에 dim 일괄 적용 ===
UPDATE SCM_MGR.SCM_MST_SITE_ITEM SET ATTRIBUTE1='Acell', ATTRIBUTE2='Acell'
 WHERE DIVISION_ID='40' AND SCM_SITE_ID='Acell_TW_NTC';
UPDATE SCM_MGR.SCM_MST_SITE_ITEM SET ATTRIBUTE1='BAE Systems', ATTRIBUTE2='BAE Systems', REPORT_GROUP3='원통형'
 WHERE DIVISION_ID='40' AND SCM_SITE_ID='BAE Systems_US_ENC';
UPDATE SCM_MGR.SCM_MST_SITE_ITEM SET ATTRIBUTE1='Boston Dynamics', ATTRIBUTE2='Boston Dynamics', REPORT_GROUP3='원통형'
 WHERE DIVISION_ID='40' AND SCM_SITE_ID='Boston Dynamics_US_WLM';
UPDATE SCM_MGR.SCM_MST_SITE_ITEM SET ATTRIBUTE1='C-TECH', ATTRIBUTE2='C-Tech_01', REPORT_GROUP3='원통형'
 WHERE DIVISION_ID='40' AND SCM_SITE_ID='C-Tech_TW_TPE';
UPDATE SCM_MGR.SCM_MST_SITE_ITEM SET ATTRIBUTE1='EATON', ATTRIBUTE2='EATON_01', REPORT_GROUP3='원통형'
 WHERE DIVISION_ID='40' AND SCM_SITE_ID='EATON_HK_YUE';
UPDATE SCM_MGR.SCM_MST_SITE_ITEM SET ATTRIBUTE1='Desay_CN', ATTRIBUTE2='NT', REPORT_GROUP3='파우치형'
 WHERE DIVISION_ID='40' AND SCM_SITE_ID='Desay_CN_HUI';
UPDATE SCM_MGR.SCM_MST_SITE_ITEM SET ATTRIBUTE1='ReBuild', ATTRIBUTE2='ReBuild', REPORT_GROUP3='원통형'
 WHERE DIVISION_ID='40' AND SCM_SITE_ID='ReBuild_US_NKP';
UPDATE SCM_MGR.SCM_MST_SITE_ITEM SET ATTRIBUTE1='RIVIAN AUTOMOTIVE', ATTRIBUTE2='RIVIAN AUTOMOTIVE', REPORT_GROUP3='원통형'
 WHERE DIVISION_ID='40' AND SCM_SITE_ID='Rivian Automotive_US_TUN';
UPDATE SCM_MGR.SCM_MST_SITE_ITEM SET ATTRIBUTE1='STL', ATTRIBUTE2='STL_01', REPORT_GROUP3='원통형'
 WHERE DIVISION_ID='40' AND SCM_SITE_ID='STL_TW_KHH';
UPDATE SCM_MGR.SCM_MST_SITE_ITEM SET ATTRIBUTE1='Trend Power Singapore', ATTRIBUTE2='Trend Power_01', REPORT_GROUP3='원통형'
 WHERE DIVISION_ID='40' AND SCM_SITE_ID='Trend Power Singapore_TW_HSZ';

COMMIT;

PROMPT === BLOCK 3 : 결과 검증 ===
SELECT COUNT(*) AS A1_FILLED  FROM SCM_MGR.SCM_MST_SITE_ITEM WHERE DIVISION_ID='40' AND ATTRIBUTE1 IS NOT NULL;
SELECT COUNT(*) AS A2_FILLED  FROM SCM_MGR.SCM_MST_SITE_ITEM WHERE DIVISION_ID='40' AND ATTRIBUTE2 IS NOT NULL;
SELECT COUNT(*) AS RG3_FILLED FROM SCM_MGR.SCM_MST_SITE_ITEM WHERE DIVISION_ID='40' AND REPORT_GROUP3 IS NOT NULL;

EXIT;
