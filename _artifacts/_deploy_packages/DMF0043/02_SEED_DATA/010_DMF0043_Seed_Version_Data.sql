--==============================================================================
-- 46_DMF0043_Seed_Version_Data.sql
-- DM_MST_CONTRIBUTE_VER 테이블이 0건 — DMF0043 Year DROPDOWN 데이터 source
-- 3년 (전년/당년/차년) seed 등록.
--==============================================================================
SET DEFINE OFF
SET FEEDBACK ON
SET LINESIZE 200
WHENEVER SQLERROR EXIT FAILURE

PROMPT === BLOCK 0 : 사전 카운트 ===
SELECT 'PRE: CONTRIBUTE_VER total' AS K, COUNT(*) V FROM DM_MST_CONTRIBUTE_VER;

PROMPT === BLOCK 1 : 3년 seed (전년/당년/차년) ===

INSERT INTO SCM_MGR.DM_MST_CONTRIBUTE_VER (VER_SEQ, YYYY, VERSION_NM, DESCRIPTION, VALID_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT NEW.VER_SEQ, NEW.YYYY, NEW.VERSION_NM, NEW.DESCRIPTION, 'Y', 'admin', SYSDATE, 'admin', SYSDATE
  FROM (
    SELECT 1 AS VER_SEQ, TO_CHAR(EXTRACT(YEAR FROM SYSDATE) - 1) AS YYYY, 'V01_전년' AS VERSION_NM, '전년도 기여율 버전' AS DESCRIPTION FROM DUAL UNION ALL
    SELECT 2,            TO_CHAR(EXTRACT(YEAR FROM SYSDATE))    ,        'V01_당년',                  '당년도 기여율 버전'                  FROM DUAL UNION ALL
    SELECT 3,            TO_CHAR(EXTRACT(YEAR FROM SYSDATE) + 1),        'V01_차년',                  '차년도 기여율 버전'                  FROM DUAL
  ) NEW
 WHERE NOT EXISTS (
   SELECT 1 FROM SCM_MGR.DM_MST_CONTRIBUTE_VER X WHERE X.VER_SEQ = NEW.VER_SEQ
 );

PROMPT === BLOCK 2 : 사후 카운트 ===
SELECT 'POST: CONTRIBUTE_VER total' AS K, COUNT(*) V FROM DM_MST_CONTRIBUTE_VER
UNION ALL SELECT 'POST: VALID_YN=Y', COUNT(*) FROM DM_MST_CONTRIBUTE_VER WHERE VALID_YN='Y';

PROMPT === BLOCK 3 : 등록 결과 확인 ===
COLUMN VERSION_NM FORMAT A20
COLUMN DESCRIPTION FORMAT A30
SELECT VER_SEQ, YYYY, VERSION_NM, DESCRIPTION, VALID_YN FROM DM_MST_CONTRIBUTE_VER ORDER BY YYYY DESC;

COMMIT;
EXIT;
