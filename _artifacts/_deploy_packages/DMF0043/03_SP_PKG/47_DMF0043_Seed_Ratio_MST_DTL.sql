--==============================================================================
-- 47_DMF0043_Seed_Ratio_MST_DTL.sql
-- DM_MST_CONTRIBUTE_RATIO_MST/DTL 0건 → DMF0043 메인 조회 SP 의
-- 동적 PIVOT v_Query 가 v_ColumnData empty 로 invalid → ORA-01001.
--
-- Seed:
--   MST 2 행 (VER_SEQ=2=2026당년, 부서×고객×제품군×Biz 2 조합)
--   DTL 24 행 (MST 2 × 12 월 × 1 OS_CORP=KR_LOCAL)
--==============================================================================
SET DEFINE OFF
SET FEEDBACK ON
SET LINESIZE 200
WHENEVER SQLERROR EXIT FAILURE

PROMPT === BLOCK 0 : 사전 카운트 ===
SELECT 'PRE: MST' AS K, COUNT(*) V FROM DM_MST_CONTRIBUTE_RATIO_MST
UNION ALL SELECT 'PRE: DTL', COUNT(*) FROM DM_MST_CONTRIBUTE_RATIO_DTL;

PROMPT === BLOCK 1 : MST 2 행 ===
INSERT INTO SCM_MGR.DM_MST_CONTRIBUTE_RATIO_MST
  (VER_SEQ, DEPARTMENT_ID, DEPT_ID, END_CUST_REPORT, SOLDTO_CUST_REPORT, PRODUCT_GROUP, DM_BIZ_TYPE, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT NEW.VER_SEQ, NEW.DEPARTMENT_ID, NEW.DEPT_ID, NEW.END_CUST_REPORT, NEW.SOLDTO_CUST_REPORT, NEW.PRODUCT_GROUP, NEW.DM_BIZ_TYPE, 'admin', SYSDATE, 'admin', SYSDATE
  FROM (
    SELECT 2 AS VER_SEQ, 'DEPT001' AS DEPARTMENT_ID, 'TEAM001' AS DEPT_ID, 'CUST_END_A' AS END_CUST_REPORT, 'CUST_SOLD_A' AS SOLDTO_CUST_REPORT, 'PG_AUTO' AS PRODUCT_GROUP, 'B1' AS DM_BIZ_TYPE FROM DUAL UNION ALL
    SELECT 2,                       'DEPT002',                       'TEAM002',                       'CUST_END_B',                       'CUST_SOLD_B',                       'PG_ESS',                       'B2'                       FROM DUAL
  ) NEW
 WHERE NOT EXISTS (
   SELECT 1 FROM SCM_MGR.DM_MST_CONTRIBUTE_RATIO_MST X
    WHERE X.VER_SEQ=NEW.VER_SEQ AND X.DEPARTMENT_ID=NEW.DEPARTMENT_ID AND X.DEPT_ID=NEW.DEPT_ID
      AND X.END_CUST_REPORT=NEW.END_CUST_REPORT AND X.SOLDTO_CUST_REPORT=NEW.SOLDTO_CUST_REPORT
      AND X.PRODUCT_GROUP=NEW.PRODUCT_GROUP AND X.DM_BIZ_TYPE=NEW.DM_BIZ_TYPE
 );

PROMPT === BLOCK 2 : DTL 24 행 (MST 2 × 12 월 × OS_CORP=KR_LOCAL) ===
INSERT INTO SCM_MGR.DM_MST_CONTRIBUTE_RATIO_DTL
  (VER_SEQ, DEPARTMENT_ID, DEPT_ID, END_CUST_REPORT, SOLDTO_CUST_REPORT, PRODUCT_GROUP, DM_BIZ_TYPE, YYYYMM, OS_CORP_CD, CONTRIBUTION_TYPE, CONTRIBUTION_RATIO, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT M.VER_SEQ, M.DEPARTMENT_ID, M.DEPT_ID, M.END_CUST_REPORT, M.SOLDTO_CUST_REPORT, M.PRODUCT_GROUP, M.DM_BIZ_TYPE,
       NEW.YYYYMM, 'KR_LOCAL' AS OS_CORP_CD, 'COMMISSION' AS CONTRIBUTION_TYPE,
       100 AS CONTRIBUTION_RATIO,  -- 단일 OS_CORP 100%
       'admin', SYSDATE, 'admin', SYSDATE
  FROM SCM_MGR.DM_MST_CONTRIBUTE_RATIO_MST M
 CROSS JOIN (
    SELECT TO_CHAR(ADD_MONTHS(TO_DATE('20260101','YYYYMMDD'), LEVEL-1), 'YYYYMM') AS YYYYMM
      FROM DUAL
   CONNECT BY LEVEL <= 12
 ) NEW
 WHERE M.VER_SEQ = 2
   AND NOT EXISTS (
     SELECT 1 FROM SCM_MGR.DM_MST_CONTRIBUTE_RATIO_DTL D
      WHERE D.VER_SEQ=M.VER_SEQ AND D.DEPARTMENT_ID=M.DEPARTMENT_ID AND D.DEPT_ID=M.DEPT_ID
        AND D.END_CUST_REPORT=M.END_CUST_REPORT AND D.SOLDTO_CUST_REPORT=M.SOLDTO_CUST_REPORT
        AND D.PRODUCT_GROUP=M.PRODUCT_GROUP AND D.DM_BIZ_TYPE=M.DM_BIZ_TYPE
        AND D.YYYYMM=NEW.YYYYMM AND D.OS_CORP_CD='KR_LOCAL' AND D.CONTRIBUTION_TYPE='COMMISSION'
   );

PROMPT === BLOCK 3 : 사후 카운트 ===
SELECT 'POST: MST (2)' AS K, COUNT(*) V FROM DM_MST_CONTRIBUTE_RATIO_MST
UNION ALL SELECT 'POST: DTL (24)', COUNT(*) FROM DM_MST_CONTRIBUTE_RATIO_DTL;

COMMIT;
EXIT;
