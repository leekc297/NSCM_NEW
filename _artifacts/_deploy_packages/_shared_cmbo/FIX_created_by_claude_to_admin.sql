-- =====================================================================
-- 메타 감사컬럼 CREATED_BY / LAST_UPDATED_BY = 'claude*' → 'admin' 교정 (2026-07-10)
-- 정책: 메타 생성 ID 에 claude 포함 절대 금지, 'admin' 만 사용.
-- 대상 = 이번까지 claude* ID 로 적재된 전 메타 테이블. 멱등(LIKE 'claude%' 만 대상).
-- 사내 + 클라우드 공통 실행.
-- =====================================================================

-- ── [1] 적용 전 현황 (claude* 잔재 카운트) ────────────────────────────
SELECT 'API_M'        TBL, COUNT(*) CNT FROM SCM_ADM_API_M            WHERE CREATED_BY LIKE 'claude%' OR LAST_UPDATED_BY LIKE 'claude%'
UNION ALL SELECT 'PROC_M',        COUNT(*) FROM SCM_ADM_PROC_M         WHERE CREATED_BY LIKE 'claude%' OR LAST_UPDATED_BY LIKE 'claude%'
UNION ALL SELECT 'MNU_BTN_MPG_M', COUNT(*) FROM SCM_ADM_MNU_BTN_MPG_M WHERE CREATED_BY LIKE 'claude%' OR LAST_UPDATED_BY LIKE 'claude%'
UNION ALL SELECT 'USER_GR_BTN',   COUNT(*) FROM SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE CREATED_BY LIKE 'claude%' OR LAST_UPDATED_BY LIKE 'claude%'
UNION ALL SELECT 'EXCEL_COLUMNS', COUNT(*) FROM SCM_ADM_EXCEL_COLUMNS  WHERE CREATED_BY LIKE 'claude%' OR LAST_UPDATED_BY LIKE 'claude%'
UNION ALL SELECT 'MSG_M',         COUNT(*) FROM SCM_ADM_MSG_M          WHERE CREATED_BY LIKE 'claude%' OR LAST_UPDATED_BY LIKE 'claude%'
UNION ALL SELECT 'MNU_M',         COUNT(*) FROM SCM_ADM_MNU_M          WHERE CREATED_BY LIKE 'claude%' OR LAST_UPDATED_BY LIKE 'claude%'
UNION ALL SELECT 'CMBO_SQL_M',    COUNT(*) FROM SCM_ADM_CMBO_SQL_M     WHERE CREATED_BY LIKE 'claude%' OR LAST_UPDATED_BY LIKE 'claude%';

-- ── [2] 교정 (CREATED_BY / LAST_UPDATED_BY 각각 claude* → admin) ──────
UPDATE SCM_ADM_API_M            SET CREATED_BY='admin' WHERE CREATED_BY LIKE 'claude%';
UPDATE SCM_ADM_API_M            SET LAST_UPDATED_BY='admin' WHERE LAST_UPDATED_BY LIKE 'claude%';
UPDATE SCM_ADM_PROC_M           SET CREATED_BY='admin' WHERE CREATED_BY LIKE 'claude%';
UPDATE SCM_ADM_PROC_M           SET LAST_UPDATED_BY='admin' WHERE LAST_UPDATED_BY LIKE 'claude%';
UPDATE SCM_ADM_MNU_BTN_MPG_M    SET CREATED_BY='admin' WHERE CREATED_BY LIKE 'claude%';
UPDATE SCM_ADM_MNU_BTN_MPG_M    SET LAST_UPDATED_BY='admin' WHERE LAST_UPDATED_BY LIKE 'claude%';
UPDATE SCM_ADM_USER_GR_MNU_BTN_MPG_M SET CREATED_BY='admin' WHERE CREATED_BY LIKE 'claude%';
UPDATE SCM_ADM_USER_GR_MNU_BTN_MPG_M SET LAST_UPDATED_BY='admin' WHERE LAST_UPDATED_BY LIKE 'claude%';
UPDATE SCM_ADM_EXCEL_COLUMNS    SET CREATED_BY='admin' WHERE CREATED_BY LIKE 'claude%';
UPDATE SCM_ADM_EXCEL_COLUMNS    SET LAST_UPDATED_BY='admin' WHERE LAST_UPDATED_BY LIKE 'claude%';
UPDATE SCM_ADM_MSG_M            SET CREATED_BY='admin' WHERE CREATED_BY LIKE 'claude%';
UPDATE SCM_ADM_MSG_M            SET LAST_UPDATED_BY='admin' WHERE LAST_UPDATED_BY LIKE 'claude%';
UPDATE SCM_ADM_MNU_M            SET CREATED_BY='admin' WHERE CREATED_BY LIKE 'claude%';
UPDATE SCM_ADM_MNU_M            SET LAST_UPDATED_BY='admin' WHERE LAST_UPDATED_BY LIKE 'claude%';
UPDATE SCM_ADM_CMBO_SQL_M       SET CREATED_BY='admin' WHERE CREATED_BY LIKE 'claude%';
UPDATE SCM_ADM_CMBO_SQL_M       SET LAST_UPDATED_BY='admin' WHERE LAST_UPDATED_BY LIKE 'claude%';
COMMIT;

-- ── [3] 검증 (전 테이블 claude* = 0) ─────────────────────────────────
SELECT 'REMAIN_API'  T, COUNT(*) C FROM SCM_ADM_API_M            WHERE CREATED_BY LIKE 'claude%' OR LAST_UPDATED_BY LIKE 'claude%'
UNION ALL SELECT 'REMAIN_PROC',  COUNT(*) FROM SCM_ADM_PROC_M         WHERE CREATED_BY LIKE 'claude%' OR LAST_UPDATED_BY LIKE 'claude%'
UNION ALL SELECT 'REMAIN_BTN',   COUNT(*) FROM SCM_ADM_MNU_BTN_MPG_M WHERE CREATED_BY LIKE 'claude%' OR LAST_UPDATED_BY LIKE 'claude%'
UNION ALL SELECT 'REMAIN_UGBTN', COUNT(*) FROM SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE CREATED_BY LIKE 'claude%' OR LAST_UPDATED_BY LIKE 'claude%'
UNION ALL SELECT 'REMAIN_EXCEL', COUNT(*) FROM SCM_ADM_EXCEL_COLUMNS  WHERE CREATED_BY LIKE 'claude%' OR LAST_UPDATED_BY LIKE 'claude%'
UNION ALL SELECT 'REMAIN_MSG',   COUNT(*) FROM SCM_ADM_MSG_M          WHERE CREATED_BY LIKE 'claude%' OR LAST_UPDATED_BY LIKE 'claude%'
