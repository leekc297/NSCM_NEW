-- [E20260818-HSEQ] DM_BPS_METAL_LINK_PRICE_H.HISTORY_SEQ identity 시퀀스 재시드
--
-- 증상 : DMF0074 Excel Upload 의 [OK](P_MODE=1) 가 **다건 업로드에서 ORA-00001**
--        (PK_DM_BPS_METAL_LINK_PRICE_H · HISTORY_SEQ) 로 실패. 단건은 우연히 통과하기도 한다.
-- 원인 : 이력 데이터 1,539행(HISTORY_SEQ 1~1,564)이 **명시값으로 이관**되었는데
--        (GENERATION_TYPE='BY DEFAULT' 라 명시 삽입이 허용된다)
--        identity 시퀀스는 재시드되지 않아 LAST_NUMBER=61 로 뒤처져 있었다(2026-08-18 실측).
--        → nextval 이 이미 점유된 값을 반환하는 즉시 PK 충돌.
-- 조치 : START WITH LIMIT VALUE = MAX(HISTORY_SEQ)+1 로 재시드 (데이터 변경 없음, 카운터만 전진).
-- 주의 : **클라우드도 동일 이관 계보라 같은 상태일 가능성이 높다** — 적용 전 아래 ①로 확인할 것.

-- ① 진단 (적용 전/후 동일 실행)
SELECT (SELECT MAX(HISTORY_SEQ) FROM SCM_MGR.DM_BPS_METAL_LINK_PRICE_H) AS MAX_SEQ,
       (SELECT LAST_NUMBER FROM ALL_SEQUENCES s
         WHERE s.SEQUENCE_OWNER = 'SCM_MGR'
           AND s.SEQUENCE_NAME = (SELECT REGEXP_SUBSTR(i.SEQUENCE_NAME, '[^.]+$')
                                    FROM ALL_TAB_IDENTITY_COLS i
                                   WHERE i.OWNER = 'SCM_MGR'
                                     AND i.TABLE_NAME = 'DM_BPS_METAL_LINK_PRICE_H'
                                     AND i.COLUMN_NAME = 'HISTORY_SEQ')) AS SEQ_LAST_NUMBER
  FROM DUAL;
-- 기대(적용 전): SEQ_LAST_NUMBER <= MAX_SEQ  → 결함 상태
-- 기대(적용 후): SEQ_LAST_NUMBER >  MAX_SEQ  → 정상

-- ② 재시드
ALTER TABLE SCM_MGR.DM_BPS_METAL_LINK_PRICE_H
  MODIFY (HISTORY_SEQ GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE));

-- ③ 검증 — 위 ① 을 재실행해 SEQ_LAST_NUMBER > MAX_SEQ 확인.
--    이후 DMF0074 Excel Upload 다건 [OK] 가 ORA-00001 없이 통과해야 한다.
