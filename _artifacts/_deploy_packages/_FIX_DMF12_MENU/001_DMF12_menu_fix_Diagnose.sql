-- Diagnose (사고 패턴 재진단) — fix 적용 전 / 사고 재발 시 사용
-- hook menu-not-displayed-debug 7단계 cross-check
-- DBeaver 호환 (PROMPT/SET 0건)

-- Diag 1: 12 화면 SCM_ADM_MNU_M 등록 상태 (count = 12 의무)
SELECT 'Diag 1: 12 화면 등록' AS chk,
       COUNT(*) AS actual,
       12 AS expect,
       CASE WHEN COUNT(*)=12 THEN 'PASS' ELSE 'FAIL: 누락 ' || (12 - COUNT(*)) || '건' END AS result
FROM SCM_MGR.SCM_ADM_MNU_M
WHERE MNU_ID IN ('DMF0014','DMF0021','DMF0042','DMF0042_1','DMF0042_2','DMF0042_3',
                 'DMF0044','DMF0048','DMF0049','DMF0074','DMF0081','DMF0082');

-- Diag 2: 부모 메뉴 등록 (Bizplan + Sales_Report = 2 의무)
SELECT 'Diag 2: 부모 메뉴' AS chk,
       COUNT(*) AS actual,
       2 AS expect,
       CASE WHEN COUNT(*)=2 THEN 'PASS' ELSE 'FAIL: 누락 부모' END AS result
FROM SCM_MGR.SCM_ADM_MNU_M
WHERE MNU_ID IN ('Bizplan','Sales_Report');

-- Diag 3: URL slug 의미 (FE 자매 표준 — 'dmf%' 형식 금지)
SELECT 'Diag 3: URL slug 의미' AS chk,
       MNU_ID,
       MNU_URL,
       CASE WHEN MNU_URL LIKE 'dmf%' THEN 'FAIL: 소문자 dmfXXXX 형식' ELSE 'PASS' END AS result
FROM SCM_MGR.SCM_ADM_MNU_M
WHERE MNU_ID IN ('DMF0014','DMF0021','DMF0042','DMF0044','DMF0048','DMF0049','DMF0074','DMF0081')
ORDER BY MNU_ID;

-- Diag 4: UPPR_MNU_ID 정합 (DMF0042 = Bizplan, DMF0044/0049 = Sales_Report)
SELECT 'Diag 4: UPPR_MNU_ID' AS chk,
       MNU_ID,
       UPPR_MNU_ID,
       CASE
         WHEN MNU_ID='DMF0042' AND UPPR_MNU_ID='Bizplan' THEN 'PASS'
         WHEN MNU_ID='DMF0044' AND UPPR_MNU_ID='Sales_Report' THEN 'PASS'
         WHEN MNU_ID='DMF0049' AND UPPR_MNU_ID='Sales_Report' THEN 'PASS'
         WHEN MNU_ID IN ('DMF0042_1','DMF0042_2','DMF0042_3') AND UPPR_MNU_ID='Bizplan' THEN 'PASS'
         ELSE 'FAIL: 예상 UPPR 불일치'
       END AS result
FROM SCM_MGR.SCM_ADM_MNU_M
WHERE MNU_ID IN ('DMF0042','DMF0042_1','DMF0042_2','DMF0042_3','DMF0044','DMF0049')
ORDER BY MNU_ID;

-- Diag 5: MNU_DESC NULL 검증 (hook Step 1.7)
SELECT 'Diag 5: MNU_DESC NULL' AS chk,
       COUNT(*) AS null_cnt,
       CASE WHEN COUNT(*)=0 THEN 'PASS' ELSE 'FAIL: NULL 메뉴 ' || COUNT(*) || '건' END AS result
FROM SCM_MGR.SCM_ADM_MNU_M
WHERE MNU_DESC IS NULL AND USE_YN='Y'
  AND MNU_ID IN ('DMF0014','DMF0021','DMF0042','DMF0042_1','DMF0042_2','DMF0042_3',
                 'DMF0044','DMF0048','DMF0049','DMF0074','DMF0081','DMF0082',
                 'Bizplan','Sales_Report');

-- Diag 6: minyonglee1 권한 14 메뉴 전체 보유 (3 그룹 합산)
SELECT 'Diag 6: minyonglee1 권한 cover' AS chk,
       NEED.MNU_ID,
       CASE WHEN COUNT(GR.USER_GR_ID)>0 THEN 'PASS' ELSE 'FAIL: 권한 누락' END AS result
FROM (
  SELECT 'DMF0014' AS MNU_ID FROM DUAL UNION ALL
  SELECT 'DMF0021' FROM DUAL UNION ALL
  SELECT 'DMF0042' FROM DUAL UNION ALL
  SELECT 'DMF0042_1' FROM DUAL UNION ALL
  SELECT 'DMF0042_2' FROM DUAL UNION ALL
  SELECT 'DMF0042_3' FROM DUAL UNION ALL
  SELECT 'DMF0044' FROM DUAL UNION ALL
  SELECT 'DMF0048' FROM DUAL UNION ALL
  SELECT 'DMF0049' FROM DUAL UNION ALL
  SELECT 'DMF0074' FROM DUAL UNION ALL
  SELECT 'DMF0081' FROM DUAL UNION ALL
  SELECT 'DMF0082' FROM DUAL UNION ALL
  SELECT 'Bizplan' FROM DUAL UNION ALL
  SELECT 'Sales_Report' FROM DUAL
) NEED
LEFT JOIN SCM_MGR.SCM_ADM_USER_GR_MNU_MPG_M GR
  ON GR.MNU_ID = NEED.MNU_ID
 AND GR.USER_GR_ID IN (
   SELECT USER_GR_ID FROM SCM_MGR.SCM_ADM_USER_GR_MPG_M WHERE USER_ID='minyonglee1' AND USE_YN='Y'
 )
GROUP BY NEED.MNU_ID
ORDER BY NEED.MNU_ID;

-- Diag 7: i18n 신규 5 MSG_ID × 3 LANG 정합 (=15)
SELECT 'Diag 7: i18n MSG' AS chk,
       MSG_ID,
       COUNT(DISTINCT LANG_CD) AS lang_cnt,
       CASE WHEN COUNT(DISTINCT LANG_CD)=3 THEN 'PASS' ELSE 'FAIL: LANG 누락' END AS result
FROM SCM_MGR.SCM_ADM_MSG_M
WHERE MSG_ID IN ('MNU_BIZPLAN','MNU_SALES_REPORT','MNU_DMF0042_1','MNU_DMF0042_2','MNU_DMF0042_3')
GROUP BY MSG_ID
ORDER BY MSG_ID;
