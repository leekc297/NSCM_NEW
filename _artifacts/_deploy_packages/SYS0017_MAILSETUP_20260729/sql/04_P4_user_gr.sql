-- ⚠️ 미러링 원본 정정(2026-07-29 실측): SYS0016(notice-setup)은 권한 0건이라 원본 부적합 →
--    admin 표준 그룹을 보유한 SYS0014(group-user: ADMIN 'Y' + SCM PI Admin 'Y')를 원본으로 사용.
--    (SYS 15개 공통 그룹 = ADMIN, SCM PI Admin 은 화면별 Y/N 상이 — SYS0014 정책 채택)

INSERT INTO SCM_ADM_USER_GR_MNU_MPG_M (USER_GR_ID, MNU_ID, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT G.USER_GR_ID, 'SYS0017', G.USE_YN, 'admin', SYSDATE, 'admin', SYSDATE
  FROM SCM_ADM_USER_GR_MNU_MPG_M G
 WHERE G.MNU_ID = 'SYS0014'
   AND NOT EXISTS (SELECT 1 FROM SCM_ADM_USER_GR_MNU_MPG_M X WHERE X.USER_GR_ID = G.USER_GR_ID AND X.MNU_ID = 'SYS0017');
INSERT INTO SCM_ADM_USER_GR_MNU_BTN_MPG_M (USER_GR_ID, MNU_ID, SHT_NM, MNU_BTN_CD, USE_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
SELECT G.USER_GR_ID, 'SYS0017', B.SHT_NM, B.MNU_BTN_CD, 'Y', 'admin', SYSDATE, 'admin', SYSDATE
  FROM (SELECT DISTINCT USER_GR_ID FROM SCM_ADM_USER_GR_MNU_MPG_M WHERE MNU_ID = 'SYS0017' AND USE_YN='Y') G
 CROSS JOIN (SELECT SHT_NM, MNU_BTN_CD FROM SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID = 'SYS0017' AND USE_YN='Y') B
 WHERE NOT EXISTS (SELECT 1 FROM SCM_ADM_USER_GR_MNU_BTN_MPG_M X
                    WHERE X.USER_GR_ID = G.USER_GR_ID AND X.MNU_ID = 'SYS0017'
                      AND X.SHT_NM = B.SHT_NM AND X.MNU_BTN_CD = B.MNU_BTN_CD);

COMMIT;
