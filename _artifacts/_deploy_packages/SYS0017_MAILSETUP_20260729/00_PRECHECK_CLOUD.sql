SET PAGESIZE 200 LINESIZE 200 TRIMSPOOL ON
COLUMN NAME FORMAT A38
COLUMN KIND FORMAT A14
COLUMN STATUS FORMAT A10

PROMPT === [1] 참조 테이블 7종 (없으면 02_DB_DDL/01_tables.sql 실행 필요) ===
SELECT 'TABLE' KIND, TABLE_NAME NAME, 'EXISTS' STATUS
  FROM ALL_TABLES
 WHERE OWNER = 'SCM_MGR'
   AND TABLE_NAME IN ('SCM_ADM_RECIPIENT_LIST','SCM_ADM_RECIPIENT_MESSAGE','SCM_ADM_RECIPIENT_ASSIGN',
                      'SCM_ADM_RECIPIENT_SMS_ASSIGN','SCM_ADM_RECIPIENT_LIST_H',
                      'SCM_ADM_RECIPIENT_MESSAGE_H','SCM_ADM_RECIPIENT_ASSIGN_H')
 ORDER BY TABLE_NAME;

PROMPT === [2] 시퀀스 1 + 의존 SP 3 + 함수 3 (없으면 02_DB_DDL/02,03 실행 필요) ===
SELECT OBJECT_TYPE KIND, OBJECT_NAME NAME, STATUS
  FROM ALL_OBJECTS
 WHERE OWNER = 'SCM_MGR'
   AND OBJECT_NAME IN ('SEQ1_SCM_ADM_RECIPIENT_LIST',
                       'PR_SCM_ADM_RECIPIENT_LIST_HIST','PR_SCM_ADM_RECIPIENT_MESSAGE_HIST',
                       'PR_SCM_ADM_RECIPIENT_ASSIGN_HIST',
                       'FN_GET_SOURCE_CODE','SCM_ARR_SPL_CNT','SCM_ARR_SPL_VAL',
                       'PR_SCM_SYS_LOG_BATCH')
 ORDER BY OBJECT_TYPE, OBJECT_NAME;

