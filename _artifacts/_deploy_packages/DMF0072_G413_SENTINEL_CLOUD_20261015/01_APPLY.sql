--   * 이미 GAP413 표식이 있으면 SKIP (재실행 멱등)
--   * 컴파일 오류 시 같은 블록에서 원래 원문으로 재생성 후 ORA-20414 (자동 원복)
--   * 5개 객체는 서로 독립. 중간에 중단되면 뒤 객체는 실행되지 않음 (원인 해결 후 재실행 시 앞 객체는 SKIP)
