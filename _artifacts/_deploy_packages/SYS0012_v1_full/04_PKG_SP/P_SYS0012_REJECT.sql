ALTER SESSION SET DDL_LOCK_TIMEOUT=120;
CREATE OR REPLACE PROCEDURE         P_SYS0012_REJECT (
    P_SES_USER_ID    IN  VARCHAR2,
    P_DATA           IN  CLOB,
    O_RESULT_CURSOR  OUT SYS_REFCURSOR
)
AS
    V_CNT NUMBER := 0;
BEGIN
    UPDATE SCM_MGR.SCM_MST_AUTH_REQUEST T
       SET T.APPROVAL_RESULT  = 'REJECT',
           T.REJECT_REASON    = (SELECT MAX(V_REASON) FROM JSON_TABLE(P_DATA, '$[*]'
                                   COLUMNS (V_REASON VARCHAR2(4000) PATH '$.REJECT_REASON' NULL ON EMPTY))),
           T.LAST_UPDATED_BY  = P_SES_USER_ID,
           T.LAST_UPDATE_DATE = SYSDATE
     WHERE (T.USER_ID || ':' || T.GROUP_ID || ':' || T.DIVISION_ID || ':' || T.PLANT_ID) IN (
         SELECT V_REQ FROM JSON_TABLE(P_DATA, '$[*]'
             COLUMNS (V_REQ VARCHAR2(400) PATH '$.REQUEST_ID'))
     );
    V_CNT := SQL%ROWCOUNT;
    COMMIT;

    OPEN O_RESULT_CURSOR FOR
    SELECT '0' AS CODE, 'SUCCESS' AS MSG, TO_CHAR(V_CNT) AS EVENT FROM DUAL;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        DECLARE
            V_ERR VARCHAR2(4000) := SUBSTR(SQLERRM, 1, 4000);
        BEGIN
            OPEN O_RESULT_CURSOR FOR
            SELECT '-1' AS CODE, V_ERR AS MSG, '0' AS EVENT FROM DUAL;
        END;
END P_SYS0012_REJECT;
/
SHOW ERRORS;
