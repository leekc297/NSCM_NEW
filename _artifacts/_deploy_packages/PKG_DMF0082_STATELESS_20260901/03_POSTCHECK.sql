-- [E20260901-STATELESS] 03 — 적용 후 검증 (SELECT-only)
-- P1: BODY VALID + 마커 실존 (STATELESS>=4, NCHARUNION=1)
SELECT 'P1' S, (SELECT STATUS FROM ALL_OBJECTS WHERE OWNER='SCM_MGR' AND OBJECT_NAME='PKG_DMF0082' AND OBJECT_TYPE='PACKAGE BODY') BODY_STATUS,
       (SELECT COUNT(*) FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND INSTR(TEXT,'E20260901-STATELESS')>0) STATELESS_CNT,
       (SELECT COUNT(*) FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND INSTR(TEXT,'E20260831-NCHARUNION')>0) NCHARUNION_CNT
  FROM DUAL;

-- P2: ⭐ 무상태 확인 — 실행문에 g_skip_parse 0건 + 바디 전역변수 선언 0건 (이게 04068 재발 차단의 증거)
SELECT 'P2 잔존참조' S, COUNT(*) CNT FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY'
   AND INSTR(TEXT,'g_skip_parse')>0 AND LTRIM(TEXT) NOT LIKE '--%';

-- P3: 플래그 GTT 실존·속성 (TEMPORARY=Y, DURATION=SYS$SESSION)
SELECT 'P3 GTT' S, TABLE_NAME, TEMPORARY, DURATION FROM ALL_TABLES
 WHERE OWNER='SCM_MGR' AND TABLE_NAME='GT_DMF0082_SAVE_FLAG';

-- P4: 앱계정 권한 (SCMP_APP SELECT/INSERT/DELETE 3행)
SELECT 'P4 권한' S, GRANTEE, PRIVILEGE FROM ALL_TAB_PRIVS
 WHERE TABLE_SCHEMA='SCM_MGR' AND TABLE_NAME='GT_DMF0082_SAVE_FLAG' ORDER BY GRANTEE, PRIVILEGE;

-- P5: 컴파일 오류 0
SELECT 'P5 오류' S, LINE, SUBSTR(TEXT,1,200) ERR FROM ALL_ERRORS
 WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0082' AND ATTRIBUTE='ERROR' ORDER BY SEQUENCE;
