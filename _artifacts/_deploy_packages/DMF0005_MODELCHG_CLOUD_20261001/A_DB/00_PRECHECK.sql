-- =====================================================================================================
-- DMF0005 Model Code Change — 클라우드 적용 전 점검 (읽기 전용 · QA / DEV 각각 SCM_MGR)
--   01·02 는 사내 PKG_DMF0005 SPEC·BODY 전체본 (신규 P_DMF0005_SAVE_MODEL_CHANGE_POPUP 포함).
--   클라우드 PKG 가 사내 변경 전 판본과 다르면(클라우드에만 있는 보완이 있으면) 통째로 덮지 말고
--   신규 프로시저 선언·본문만 수동 추가할 것.
-- =====================================================================================================

-- [0] 접속 DB
SELECT USER, SYS_CONTEXT('USERENV','DB_NAME') DB, SYS_CONTEXT('USERENV','SERVER_HOST') HOST FROM DUAL;

-- [1] 현재 클라우드 PKG 판본
--     사내 변경 전 기준: SPEC LAST_DDL 2026-09-30 19:44:24 · BODY 2026-09-30 19:44:25 (BODY 약 1138줄)
--     사내 변경 후     : SPEC 55줄 / HSUM 148833340552 · BODY 1417줄 / HSUM 3047621925256
SELECT O.OBJECT_TYPE, O.STATUS, TO_CHAR(O.LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL,
       COUNT(S.LINE) LINES, SUM(ORA_HASH(S.TEXT)) HSUM,
       SUM(CASE WHEN S.TEXT LIKE '%P_DMF0005_SAVE_MODEL_CHANGE_POPUP%' THEN 1 ELSE 0 END) NEW_PROC_REF   -- 0 = 미반영
  FROM ALL_OBJECTS O JOIN ALL_SOURCE S ON S.OWNER = O.OWNER AND S.NAME = O.OBJECT_NAME AND S.TYPE = O.OBJECT_TYPE
 WHERE O.OWNER = 'SCM_MGR' AND O.OBJECT_NAME = 'PKG_DMF0005'
 GROUP BY O.OBJECT_TYPE, O.STATUS, O.LAST_DDL_TIME;

-- [2] 사내 변경 전 본과 같은 판본인지 — 마커 수 (사내 변경 전 기준: 2026.09.30 AJS 8 / 2026.09.17 AJS 10 / 2026-09-30 / POJ 1)
--     다르면 02 통째 적용 보류 → 신규 프로시저만 수동 추가
SELECT SUM(CASE WHEN TEXT LIKE '%2026.09.30 AJS%'   THEN 1 ELSE 0 END) M_0930_AJS,
       SUM(CASE WHEN TEXT LIKE '%2026.09.17 AJS%'   THEN 1 ELSE 0 END) M_0917_AJS,
       SUM(CASE WHEN TEXT LIKE '%2026-09-30 / POJ%' THEN 1 ELSE 0 END) M_0930_POJ
  FROM ALL_SOURCE WHERE OWNER = 'SCM_MGR' AND NAME = 'PKG_DMF0005' AND TYPE = 'PACKAGE BODY';

-- [3] 신규 SP 가 쓰는 객체 실재 (38 갱신 테이블 + 이력 + 품목 뷰 + 로그) — 0행 = 전부 있음
WITH T AS (
  SELECT COLUMN_VALUE TN FROM TABLE(SYS.ODCIVARCHAR2LIST(
    'DM_ANL_KPI_RTF_DEMAND','DM_ANL_KPI_RTF_SALES','DM_ANL_KPI_SALES_ACCURACY','DM_ANL_KPI_SUMMARY','DM_DNM_EDI_CALLOFF_ITEM',
    'DM_DNM_SALES_RESULT_IF','DM_HI_CUST_FCST_INPUT','DM_HI_MKT_FCST_CHANGE','DM_HI_SALES_INPUT','DM_HI_SITE_ITEM_MAPPING',
    'DM_HI_SITE_ITEM_MAPPING_ROWDATA','DM_MST_BUCKET_CONVERSION','DM_MST_BUCKET_CONVERSION_H','DM_MST_CAPACITY_ALLOCATION',
    'DM_MST_CAPACITY_ALLOCATION_H','DM_MST_CUSTOMER_MODEL','DM_MST_CUSTOMER_MODEL_H','DM_MST_EDI_CUST_MATERIAL_INFO',
    'DM_PLN_BP_FCST','DM_PLN_BP_FCST_H','DM_PLN_CUSTOMER_PSI','DM_PLN_CUSTOMER_PSI_H','DM_PLN_MKT_FCST','DM_PLN_MKT_FCST_CONFIRM',
    'DM_PLN_MKT_FCST_H','DM_PLN_MKT_FCST_PK_DATA_UPDATE_H','DM_PLN_MKT_FCST_RESULT','DM_PLN_PR_DETAIL','DM_PLN_SALES_PLAN',
    'DM_PLN_SALES_PLAN_H','DM_PLN_SALES_PLAN_REPORT_H','DM_PLN_SALES_PLAN_RESULT','SCM_MST_FUTURE_PRICE','SCM_MST_FUTURE_PRICE_H',
    'SCM_MST_SITE_ITEM','SCM_MST_SITE_ITEM_H','SCM_MST_SITE_ITEM_PRIORITY','SCM_MST_SITE_ITEM_PRIORITY_H',
    'DM_DNM_ITEM_CODE_CHANGE_HISTORY','DM_MST_ITEM_SINGLE_V','PR_SCM_SYS_LOG_BATCH')))
SELECT T.TN, '객체 없음' JUDGE FROM T
 WHERE NOT EXISTS (SELECT 1 FROM ALL_OBJECTS O WHERE O.OWNER = 'SCM_MGR' AND O.OBJECT_NAME = T.TN);

-- [4] META 현황 (03 적용 전·후 대조) — 사내 기준 API 1 / PROC_M 3 / 버튼 2 / 권한 6
SELECT (SELECT COUNT(*) FROM SCM_ADM_API_M  WHERE API_ID = 'P_DMF0005_MODELCHANGE_SAVE') API,
       (SELECT COUNT(*) FROM SCM_ADM_PROC_M WHERE PROC_NM = 'PKG_DMF0005.P_DMF0005_SAVE_MODEL_CHANGE_POPUP') PROC_M,
       (SELECT COUNT(*) FROM SCM_ADM_MNU_BTN_MPG_M WHERE MNU_ID = 'DMF0005' AND ((SHT_NM = 'production' AND MNU_BTN_CD = 'MODEL_CHANGE') OR (SHT_NM = 'modelChange' AND MNU_BTN_CD = 'SAVE'))) BTN,
       (SELECT COUNT(*) FROM SCM_ADM_USER_GR_MNU_BTN_MPG_M WHERE MNU_ID = 'DMF0005' AND ((SHT_NM = 'production' AND MNU_BTN_CD = 'MODEL_CHANGE') OR (SHT_NM = 'modelChange' AND MNU_BTN_CD = 'SAVE'))) AUTH
  FROM DUAL;
