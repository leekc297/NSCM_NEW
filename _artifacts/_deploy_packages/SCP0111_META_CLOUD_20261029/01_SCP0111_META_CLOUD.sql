DECLARE
  v_cnt NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_cnt
    FROM ALL_PROCEDURES
   WHERE OWNER = 'SCM_MGR' AND OBJECT_NAME = 'PKG_SCP0111' AND PROCEDURE_NAME = 'P_SCP0111_GET_ESS_PACK_LINE';
  IF v_cnt = 0 THEN
    RAISE_APPLICATION_ERROR(-20001, 'PRECHECK: SCM_MGR.PKG_SCP0111.P_SCP0111_GET_ESS_PACK_LINE 없음 — PKG_SCP0111 선이관 필요');
  END IF;

  SELECT COUNT(*) INTO v_cnt
    FROM SCM_MGR.SCM_ADM_MSG_M
   WHERE MSG_ID IN ('MSG01477', 'MSG01478')
     AND NVL(MSG_DESC, '/') NOT LIKE 'SCP0111 %';
  IF v_cnt > 0 THEN
    RAISE_APPLICATION_ERROR(-20002, 'PRECHECK: MSG01477/MSG01478 이 클라우드에서 다른 용도로 선점됨 — 재채번 필요(적용 중단)');
