/* 3단계 확인 : SLASH_CNT 0, 백업 테이블 건수 = 10 단계 건수 */
ALTER SESSION SET CURRENT_SCHEMA = SCM_MGR;

SELECT COUNT(*) AS SLASH_CNT
  FROM SSP_MST_DELEGATE
 WHERE DELEGATEE_ID = '/'
    OR USER_ID      = '/'
    OR DIVISION_ID  = '/';

SELECT DIVISION_ID, USER_ID, DELEGATEE_ID, FROM_DATE, TO_DATE, VALID_YN, CREATION_DATE
  FROM SSP_MST_DELEGATE_BAK20261125_SLASH
 ORDER BY DIVISION_ID, USER_ID, FROM_DATE;

/* SSP0003 결재 위임 중복 확인 : 오늘 유효 위임이 2건 이상인 위임자 (사내 결과 = Division 81 yhleea 1명, '/' 와 무관) */
SELECT DIVISION_ID, USER_ID, COUNT(*) AS VALID_CNT
  FROM SSP_MST_DELEGATE
 WHERE VALID_YN = 'Y'
   AND TO_CHAR(SYSDATE, 'YYYYMMDD') BETWEEN FROM_DATE AND TO_DATE
 GROUP BY DIVISION_ID, USER_ID
HAVING COUNT(*) > 1;
