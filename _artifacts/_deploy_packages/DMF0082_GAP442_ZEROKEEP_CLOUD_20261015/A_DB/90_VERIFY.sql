-- 90 VERIFY — [GAP442 2026-10-15] GAP 442 조회 전용 (전체 F5, 값 입력 없음)
-- * 기대: V1 마커 4줄 PASS · V2 VALID / 오류 0 / 의존 INVALID 0 · V3 4줄 모두 PASS(구 줄 0 · 신 줄 1)
-- * 화면 확인(README 5단계): 40 수량 칸을 0 으로 고쳐 저장 → V4 를 해당 키로 바꿔 실행하면 MKT_FCST 등 행이 QTY 0 으로 남는다.
SET LINESIZE 220 PAGESIZE 500
SET DEFINE OFF
COLUMN CHK FORMAT A10
COLUMN KIND FORMAT A24
COLUMN JUDGE FORMAT A60
SELECT 'V1 마커' CHK, COUNT(*) N, LISTAGG(LINE, ',') WITHIN GROUP (ORDER BY LINE) LINES,
       CASE WHEN COUNT(*) = 4 THEN 'PASS' ELSE 'FAIL (미적용 또는 마커 수 불일치)' END JUDGE
  FROM USER_SOURCE WHERE NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%GAP442 2026-10-15%';
SELECT 'V2 상태' CHK, O.OBJECT_TYPE, O.STATUS, TO_CHAR(O.LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL,
       (SELECT COUNT(*) FROM USER_ERRORS E WHERE E.NAME=O.OBJECT_NAME AND E.TYPE=O.OBJECT_TYPE) ERR_CNT,
       (SELECT COUNT(*) FROM USER_OBJECTS X WHERE X.STATUS<>'VALID' AND X.OBJECT_NAME IN (SELECT NAME FROM USER_DEPENDENCIES WHERE REFERENCED_NAME='PKG_DMF0082')) DEP_INVALID
  FROM USER_OBJECTS O WHERE O.OBJECT_NAME='PKG_DMF0082' ORDER BY O.OBJECT_TYPE;
SELECT 'V3 문장' CHK, K.KIND,
       SUM(CASE WHEN RTRIM(S.TEXT, CHR(10)||CHR(13)) = K.OLD_TXT THEN 1 ELSE 0 END) OLD_N,
       SUM(CASE WHEN S.TEXT LIKE K.NEW_TXT || '%' THEN 1 ELSE 0 END) NEW_N,
       CASE WHEN SUM(CASE WHEN RTRIM(S.TEXT, CHR(10)||CHR(13)) = K.OLD_TXT THEN 1 ELSE 0 END) = 0
             AND SUM(CASE WHEN S.TEXT LIKE K.NEW_TXT || '%' THEN 1 ELSE 0 END) = 1
            THEN 'PASS' ELSE 'FAIL — 구 줄 잔존 또는 신 줄 수 이상' END JUDGE
  FROM ( SELECT 'D1 Phase1 DELETE 대상' KIND, '    WHERE A.MEASURE IN (''MKT_AMT_KRW'', ''MKT_AMT_LOC'', ''MKT_FCST'', ''VMI_In_Req'', ''SCM_FCST'')' OLD_TXT, '    WHERE A.MEASURE IN (''MKT_AMT_KRW'', ''MKT_AMT_LOC'')' NEW_TXT FROM DUAL UNION ALL
         SELECT 'D2 Phase1 DELETE 내부' KIND, '            FROM SCM_MGR.GT_PRDM1_T_MAIN M WHERE M.MEASURE IN (''MKT_AMT_KRW'', ''MKT_AMT_LOC'', ''MKT_FCST'', ''VMI_In_Req'', ''SCM_FCST'')' OLD_TXT, '            FROM SCM_MGR.GT_PRDM1_T_MAIN M WHERE M.MEASURE IN (''MKT_AMT_KRW'', ''MKT_AMT_LOC'')  --[GAP442 2026-10-15]' NEW_TXT FROM DUAL UNION ALL
         SELECT 'M1 MERGE 소스' KIND, '                 AND M.QTY_PRICE <> 0)' OLD_TXT, '                 AND (M.QTY_PRICE <> 0 OR M.MEASURE IN (''MKT_FCST'', ''VMI_In_Req'', ''SCM_FCST'')))  --[GAP442 2026-10-15]' NEW_TXT FROM DUAL UNION ALL
         SELECT 'M2 MERGE INSERT 조건' KIND, '    , B.CELL_PROD_SITE_ID, B.YYYYMMDD, B.QTY_PRICE, B.CREATED_BY, V_GETDATE, B.CREATED_BY, V_GETDATE);' OLD_TXT, '    WHERE B.QTY_PRICE <> 0;  --[GAP442 2026-10-15]' NEW_TXT FROM DUAL ) K
  LEFT JOIN USER_SOURCE S
    ON S.NAME = 'PKG_DMF0082' AND S.TYPE = 'PACKAGE BODY'
   AND (RTRIM(S.TEXT, CHR(10)||CHR(13)) = K.OLD_TXT OR S.TEXT LIKE K.NEW_TXT || '%')
   AND S.LINE BETWEEN (SELECT MIN(LINE) FROM USER_SOURCE WHERE NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND RTRIM(TEXT, CHR(10)||CHR(13)) = 'PROCEDURE P_DMF0082_SAVE_MAIN_DATA')
                  AND (SELECT MIN(LINE) FROM USER_SOURCE WHERE NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND TEXT LIKE 'PROCEDURE P_DMF0082_GET_EXCEL_FORM_DATA%')
 GROUP BY K.KIND
 ORDER BY K.KIND;
