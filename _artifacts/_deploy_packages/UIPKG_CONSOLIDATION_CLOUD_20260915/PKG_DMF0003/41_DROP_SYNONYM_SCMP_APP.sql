-- PKG_DMF0003 — SCMP_APP 시노님 정리 (SCMP_APP 로 실행 · 40 실행 후 · 원 SP 가 사라진 경우에만)
SET SERVEROUTPUT ON SIZE UNLIMITED
DECLARE n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM USER_SYNONYMS WHERE SYNONYM_NAME = 'SCM_ADM_MAIL_SEND' AND TABLE_OWNER = 'SCM_MGR';
  IF n > 0 THEN
    SELECT COUNT(*) INTO n FROM ALL_OBJECTS WHERE OWNER = 'SCM_MGR' AND OBJECT_NAME = 'SCM_ADM_MAIL_SEND' AND OBJECT_TYPE = 'PROCEDURE';
    IF n = 0 THEN EXECUTE IMMEDIATE 'DROP SYNONYM "SCM_ADM_MAIL_SEND"'; DBMS_OUTPUT.PUT_LINE('DROPPED SYNONYM SCM_ADM_MAIL_SEND');
    ELSE DBMS_OUTPUT.PUT_LINE('SKIP SCM_ADM_MAIL_SEND (SCM_MGR 원 SP 존재)'); END IF;
  END IF;
END;
/
