-- [D] META 현재값 — API_URL 이 standalone 이면 전환 전, PKG.멤버 면 전환 완료
SELECT API_ID, API_URL FROM SCM_ADM_API_M WHERE API_ID IN ('DMF0040_spreadTitle_SEARCH') ORDER BY API_ID;
