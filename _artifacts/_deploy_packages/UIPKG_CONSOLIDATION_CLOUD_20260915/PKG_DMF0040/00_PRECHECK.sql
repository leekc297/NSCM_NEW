-- VERDICT: PRE=사내 적용 전과 동일 → 해당 파일 적용 / POST=이미 적용 → SKIP / ABSENT=없음 / DIFF=클라우드 본문이 다름 → 전체교체 금지·결과 공유
SET PAGESIZE 200 LINESIZE 300
COLUMN OBJ FORMAT A48
COLUMN VERDICT FORMAT A60

-- [A] 교체 대상 객체
SELECT 'PKG_DMF0040' OBJ, 'PACKAGE' TYP, '10_SPEC.sql' FILE_NM,
       (SELECT STATUS FROM USER_OBJECTS WHERE OBJECT_NAME = 'PKG_DMF0040' AND OBJECT_TYPE = 'PACKAGE') CLOUD_STATUS,
       CASE WHEN NOT EXISTS (SELECT 1 FROM USER_OBJECTS WHERE OBJECT_NAME = 'PKG_DMF0040' AND OBJECT_TYPE = 'PACKAGE') THEN 'ABSENT → ⚠ 기존 객체 부재: 선행 이관 필요'
            WHEN H.S = 105613486032 THEN 'POST → 이미 적용됨(SKIP)'
            WHEN H.S = 81857446948 THEN 'PRE → 적용 대상'
            ELSE 'DIFF → ⚠ 클라우드 본문이 사내와 다름: 전체교체 금지·결과 공유' END VERDICT
  FROM (SELECT SUM(ORA_HASH(RTRIM(TEXT, CHR(10)||CHR(13)||CHR(32)||CHR(9)))) S FROM USER_SOURCE WHERE NAME = 'PKG_DMF0040' AND TYPE = 'PACKAGE' AND LINE > 1) H;
SELECT 'PKG_DMF0040' OBJ, 'PACKAGE BODY' TYP, '11_BODY.sql' FILE_NM,
       (SELECT STATUS FROM USER_OBJECTS WHERE OBJECT_NAME = 'PKG_DMF0040' AND OBJECT_TYPE = 'PACKAGE BODY') CLOUD_STATUS,
       CASE WHEN NOT EXISTS (SELECT 1 FROM USER_OBJECTS WHERE OBJECT_NAME = 'PKG_DMF0040' AND OBJECT_TYPE = 'PACKAGE BODY') THEN 'ABSENT → ⚠ 기존 객체 부재: 선행 이관 필요'
            WHEN H.S = 3988127003570 THEN 'POST → 이미 적용됨(SKIP)'
            WHEN H.S = 3018230493799 THEN 'PRE → 적용 대상'
            ELSE 'DIFF → ⚠ 클라우드 본문이 사내와 다름: 전체교체 금지·결과 공유' END VERDICT
  FROM (SELECT SUM(ORA_HASH(RTRIM(TEXT, CHR(10)||CHR(13)||CHR(32)||CHR(9)))) S FROM USER_SOURCE WHERE NAME = 'PKG_DMF0040' AND TYPE = 'PACKAGE BODY' AND LINE > 1) H;

-- [B] DROP 대상 standalone — 멤버 본문 원천. DIFF 면 클라우드에만 있는 수정 → 멤버에 반영 필요(결과 공유)
SELECT 'DMF0040_GET_SPREAD_TITLE' OBJ, (SELECT STATUS FROM USER_OBJECTS WHERE OBJECT_NAME = 'DMF0040_GET_SPREAD_TITLE' AND OBJECT_TYPE = 'PROCEDURE') CLOUD_STATUS,
       CASE WHEN H.S IS NULL THEN 'ABSENT(이미 삭제됐거나 미이관)' WHEN H.S IN (964524118661, 964524118661) THEN 'SAME(사내 원천과 동일)' ELSE 'DIFF → ⚠ 결과 공유' END VERDICT
  FROM (SELECT SUM(ORA_HASH(RTRIM(TEXT, CHR(10)||CHR(13)||CHR(32)||CHR(9)))) S FROM USER_SOURCE WHERE NAME = 'DMF0040_GET_SPREAD_TITLE' AND TYPE = 'PROCEDURE' AND LINE > 1) H;

-- [C] PKG_DMF0040 BODY 의존 객체 — 행이 나오면 MISSING (컴파일 실패 조건)
