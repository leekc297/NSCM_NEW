SET PAGESIZE 300 LINESIZE 250
COLUMN JUDGE FORMAT A70

PROMPT [E0] 접속 DB
SELECT USER USR, SYS_CONTEXT('USERENV','DB_NAME') DB_NAME, SYS_CONTEXT('USERENV','SERVER_HOST') HOST FROM DUAL;

PROMPT [H] BODY 지문 — BEFORE 16176/830176 (= 09-30 QRYPERF 적용본) 이면 11 적용 · AFTER 16177/830657 이면 SKIP
WITH F AS (SELECT COUNT(*) LN, SUM(LENGTH(RTRIM(TEXT, CHR(10)||CHR(13)))) CH FROM USER_SOURCE WHERE NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND LINE > 1),
     S AS (SELECT COUNT(*) LN, SUM(LENGTH(RTRIM(TEXT, CHR(10)||CHR(13)))) CH FROM USER_SOURCE WHERE NAME='PKG_DMF0082' AND TYPE='PACKAGE' AND LINE > 1)
SELECT F.LN || '/' || F.CH BODY_FP, S.LN || '/' || S.CH SPEC_FP,
       (SELECT COUNT(*) FROM USER_SOURCE WHERE NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%E20260930-DMF0082QRYPERF%') QRYPERF_MARK,
       (SELECT COUNT(*) FROM USER_SOURCE WHERE NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%E20260930-DMF0082CLOUDPERF%') CLOUDPERF_MARK,
       CASE WHEN F.LN = 16177 AND F.CH = 830657 THEN 'SKIP — 이미 적용됨 (AFTER)'
            WHEN F.LN = 16176 AND F.CH = 830176 AND S.LN = 111 AND S.CH = 7173 THEN '적용 — 05 → 11 → 90'
            WHEN (SELECT COUNT(*) FROM USER_SOURCE WHERE NAME='PKG_DMF0082' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%E20260930-DMF0082QRYPERF%') = 0
            THEN '⚠ 중단 — QRYPERF 미적용 DB: DMF0082_QRYPERF_CLOUD_20260930 (10 SPEC·11 BODY·20 PROC_M) 먼저'
            ELSE '⚠ 중단 — UNKNOWN 지문 (클라우드 고유 변경 가능 — 원문 diff 필요)' END JUDGE
  FROM F, S;

PROMPT [I] 힌트가 지정하는 인덱스 존재 (1행 VALID 기대 — 없으면 힌트가 무시될 뿐 오류는 없음)
