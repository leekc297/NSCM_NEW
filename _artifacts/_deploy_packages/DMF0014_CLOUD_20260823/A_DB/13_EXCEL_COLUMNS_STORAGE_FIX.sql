-- DMF0014_CLOUD_20260823 / 추가 정정 (2026-08-26) — Excel Upload validProc 배선 구본 정정
-- 증상(클라우드 실측 2026-08-26): Excel Upload 시
--   PLS-00201: identifier 'DMF0014_CUST_FCST_EXCEL_UPLOAD' must be declared
-- 원인: 클라우드 SCM_ADM_EXCEL_COLUMNS.STORAGE_SQL_ID 가 구세대 standalone 명
--   ('DMF0014_CUST_FCST_EXCEL_UPLOAD' — 사내에도 INVALID 잔재만 존재)을 물고 있음.
--   기존 12_EXCEL_COLUMNS.sql 은 INSERT 단문이라 이미 존재하는 구본 행을 못 고침(§1.7 NOT EXISTS+UPDATE 계보).
-- 정본(사내 실측) = 'PKG_DMF0014.P_DMF0014_CUST_FCST_EXCEL_UPLOAD' (PKG, VALID).
-- ⚠ 전제: 클라우드에 PKG_DMF0014 BODY(01/02)가 적용돼 있어야 함 — 말미 검증 ②로 확인.
MERGE INTO SCM_MGR.SCM_ADM_EXCEL_COLUMNS T
USING (SELECT 'DMF0014' P, 'FCST Upload' S FROM DUAL) X
ON (T.PROGRAM_ID = X.P AND T.SHEET_NAME = X.S)
WHEN MATCHED THEN UPDATE SET
       T.STORAGE_SQL_ID = 'PKG_DMF0014.P_DMF0014_CUST_FCST_EXCEL_UPLOAD'
     , T.VALID_YN = 'Y'
     , T.LAST_UPDATED_BY = 'admin', T.LAST_UPDATE_DATE = SYSDATE
WHEN NOT MATCHED THEN INSERT
     ( PROGRAM_ID, SHEET_NAME, STORAGE_SQL_ID, HEADER_CONTENT, OPTION_ATTRIBUTE_COLUMN_NUMBER
     , VALID_YN, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE )
VALUES ( 'DMF0014', 'FCST Upload', 'PKG_DMF0014.P_DMF0014_CUST_FCST_EXCEL_UPLOAD'
     , 'Division*|Sales Site*|Plant Site*|Customer Project*|Customer Model*|Incoterms*|FCST Type*|Customs Handbook*|Measure Group*|Measure*|Upload UOM*|Project|Model|W27|W28|W29|W30|W31'
     , 70, 'Y', 'admin', SYSDATE, 'admin', SYSDATE );
COMMIT;

-- 검증 ① 배선 (기대 1행, STORAGE = PKG 정본)
SELECT PROGRAM_ID, SHEET_NAME, STORAGE_SQL_ID, VALID_YN
FROM   SCM_MGR.SCM_ADM_EXCEL_COLUMNS
WHERE  PROGRAM_ID = 'DMF0014' AND SHEET_NAME = 'FCST Upload';

-- 검증 ② validProc 실존 (기대 1 — 0 이면 01/02 BODY 선행 적용 필요)
SELECT COUNT(*) AS PROC_EXISTS
FROM   ALL_PROCEDURES
WHERE  OWNER = 'SCM_MGR' AND OBJECT_NAME = 'PKG_DMF0014'
AND    PROCEDURE_NAME = 'P_DMF0014_CUST_FCST_EXCEL_UPLOAD';
