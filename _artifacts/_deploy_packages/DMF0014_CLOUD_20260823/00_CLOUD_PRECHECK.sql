PROMPT ===== C5. 공유 CMBO 존재 확인 (본 패키지 미동봉 — 없으면 조회조건이 빈 목록) =====
WITH need (C) AS (
  SELECT 'BucketType' FROM DUAL UNION ALL SELECT 'DOM_EXP' FROM DUAL UNION ALL
  SELECT 'EndCustomer' FROM DUAL UNION ALL SELECT 'FcstType' FROM DUAL UNION ALL
  SELECT 'Incoterms' FROM DUAL UNION ALL SELECT 'Measure' FROM DUAL UNION ALL
  SELECT 'MyDivision' FROM DUAL UNION ALL SELECT 'PlantByDivisionCompany' FROM DUAL UNION ALL
  SELECT 'SalesSite' FROM DUAL)
SELECT N.C, CASE WHEN M.SQL_ID IS NULL THEN 'MISSING ⛔' ELSE 'OK ' || M.USE_YN END STATUS,
       TO_CHAR(M.LAST_UPDATE_DATE,'YYYY-MM-DD') CLOUD_LUD
FROM   need N LEFT JOIN SCM_MGR.SCM_ADM_CMBO_SQL_M M ON M.SQL_ID = N.C
ORDER  BY 2 DESC, 1;
-- 9종 모두 **공유 콤보**(타 화면 다수 소비)라 본 패키지는 동봉하지 않는다. 존재만 확인한다.

