PROMPT ===== C2. ⛔ 배선 메타 현황 — 오늘 클라우드 실오류 2건의 진원지 =====
SELECT PROGRAM_ID, SHEET_NAME, STORAGE_SQL_ID,
       REGEXP_COUNT(HEADER_CONTENT,'[|]') + 1 AS TOKEN_CNT,
       REGEXP_SUBSTR(HEADER_CONTENT,'[^|]+',1,9)  AS SLOT9,
       REGEXP_SUBSTR(HEADER_CONTENT,'[^|]+',1,10) AS SLOT10,
       REGEXP_SUBSTR(HEADER_CONTENT,'[^|]+',1,11) AS SLOT11
FROM   SCM_MGR.SCM_ADM_EXCEL_COLUMNS WHERE PROGRAM_ID LIKE 'DMF0014%';
-- 사내 정본: STORAGE_SQL_ID='PKG_DMF0014.P_DMF0014_CUST_FCST_EXCEL_UPLOAD' / TOKEN_CNT=18
--            SLOT9='Measure Group*' / SLOT10='Measure*' / SLOT11='Upload UOM*'
-- ① STORAGE_SQL_ID 가 'DMF0014_CUST_FCST_EXCEL_UPLOAD'(구 단독 SP) → 업로드 시 PLS-00201
-- ② SLOT 이 한 칸 밀려 있음(예: SLOT10='Upload UOM*') → 전건 'Invalid Measure Upload Bucket.'
--    ⚠ SLOT 이 정상인데도 스테이징 ATTRIBUTE10 에 UOM 값이 들어간다면 **클라우드 BE 빌드**가 원인
--      (`FileServiceImpl.cvtListUploadRows`) — 메타 재적재로는 해소되지 않는다. C3 로 교차 확인.

