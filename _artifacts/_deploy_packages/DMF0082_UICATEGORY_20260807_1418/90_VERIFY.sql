-- [1] PKG 컴파일 (기대: PACKAGE/PACKAGE BODY 모두 VALID)
SELECT OBJECT_TYPE, STATUS FROM ALL_OBJECTS
WHERE  OWNER='SCM_MGR' AND OBJECT_NAME='PKG_DMF0082';

-- [2] GTT 컬럼 수 (기대: GT_DMF0082_MF_SP=79 / GTT_MF_SP=72)
SELECT TABLE_NAME, COUNT(*) COLS FROM ALL_TAB_COLUMNS
WHERE  OWNER='SCM_MGR' AND TABLE_NAME IN ('GT_DMF0082_MF_SP','GTT_MF_SP')
GROUP BY TABLE_NAME;

-- [3] SPEC 시그니처 (기대: GET/CURRENT 에 p_project_code/p_owner/p_sender_code, SAVE 에 p_as_from_site)
SELECT OBJECT_NAME, ARGUMENT_NAME, POSITION, IN_OUT FROM ALL_ARGUMENTS
WHERE  OWNER='SCM_MGR' AND PACKAGE_NAME='PKG_DMF0082'
AND    ARGUMENT_NAME IN ('P_PROJECT_CODE','P_OWNER','P_SENDER_CODE','P_AS_FROM_SITE')
ORDER BY OBJECT_NAME, POSITION;

-- [4] PROC_M (기대: GET 22 / CURRENT 22 / SAVE 18)
SELECT PROC_NM, COUNT(*) CNT,
       SUM(CASE WHEN COL_TP_CD='IN' THEN 1 ELSE 0 END) IN_CNT,
       SUM(CASE WHEN COL_TP_CD='OUT' THEN 1 ELSE 0 END) OUT_CNT
FROM   SCM_MGR.SCM_ADM_PROC_M
WHERE  PROC_NM IN ('PKG_DMF0082.P_DMF0082_GET_MAIN_DATA',
                   'PKG_DMF0082.P_DMF0082_GET_MAIN_DATA_CURRENT',
                   'PKG_DMF0082.P_DMF0082_SAVE_MAIN_DATA')
GROUP BY PROC_NM ORDER BY 1;

-- [5] SHEET_COLUMNS (기대: TOTAL 61 / D40 49 / D81 42 / D82 41)
SELECT COUNT(*) TOTAL,
       SUM(CASE WHEN ','||DIVISION_ID||',' LIKE '%,40,%' THEN 1 ELSE 0 END) D40,
       SUM(CASE WHEN ','||DIVISION_ID||',' LIKE '%,81,%' THEN 1 ELSE 0 END) D81,
       SUM(CASE WHEN ','||DIVISION_ID||',' LIKE '%,82,%' THEN 1 ELSE 0 END) D82
FROM   SCM_MGR.SCM_MST_SHEET_COLUMNS
WHERE  PROGRAM_ID='DMF0082' AND SHEET_NAME='FcstNPrice';

-- [6] 필수 키 5컬럼 토큰 (기대: 5행 전부 '40,81,81_UC,81_HM,81_ST,81_HD,81_HG,82')
SELECT COLUMN_NAME, DIVISION_ID FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
WHERE  PROGRAM_ID='DMF0082' AND SHEET_NAME='FcstNPrice'
AND    COLUMN_NAME IN ('DIVISION_ID','END_CUSTOMER','SCM_SITE_ID','ITEM_ID','CELL_PROD_SITE_ID')
ORDER BY SORT_ORDER_NO;

-- [7] CMBO (기대: FcstPriceUserAuthGroup 1행)
SELECT COUNT(*) CMBO FROM SCM_MGR.SCM_ADM_CMBO_SQL_M WHERE SQL_ID='FcstPriceUserAuthGroup';

-- [8] TITLESET (05 적용 직후 기대: 0 — 이후 사용자 조회마다 증가 = 자동 재시드 정상)
SELECT COUNT(*) TITLESET FROM SCM_MGR.SCM_MST_TITLESET_USER
WHERE  PROGRAM_ID='DMF0082' AND SHEET_NAME='FcstNPrice';

-- [9] (선택·데이터 보유 시) 82 조회 전용 실증 — GET 직접 호출 후 O_RC1 의 EDIT_FLAG 전행 'N' 확인
--   ⚠️ SP 직접 호출 시 p_item_id 는 빈 문자열('')=전체. 'ALL' 전달 시 '%ALL%' LIKE 전멸(0행) — 사내 실측 함정.

-- [10] W/S 지원 (07 적용분) — 기대: CMBO 1행 / 셀 콤보 = FcstTypeByUserGroupDMF0082 / W/S measure 6행
SELECT COUNT(*) CMBO FROM SCM_MGR.SCM_ADM_CMBO_SQL_M WHERE SQL_ID='FcstTypeByUserGroupDMF0082';
SELECT CELL_COMBO_DATA_TYPE FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
WHERE  PROGRAM_ID='DMF0082' AND SHEET_NAME='FcstNPrice' AND COLUMN_NAME='FCST_TYPE';
SELECT COUNT(*) WS_MEASURE FROM SCM_MGR.SCM_ADM_LOOKUP_MASTER_DETAIL
WHERE  LOOKUP_TYPE='GET_ADMIN_GROUP_MEASURE' AND SEGMENT1='DM Planner (W/S)' AND SEGMENT2='DMF0082';
-- [11] 공유 콤보 무변경 (기대: FCST_TYPE_NOT_ETC 소비 = DMF0051_1/DMF0072×2/SCM0002×2 — DMF0082 제외)
SELECT PROGRAM_ID, SHEET_NAME FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
WHERE  CELL_COMBO_DATA_TYPE='FCST_TYPE_NOT_ETC' AND VALID_YN='Y' ORDER BY 1,2;
