-- 00_PRECHECK — 조회 전용 (전체 F5, 값 입력 없음). [GAP476 2026-10-15] GAP 476 적용 전 상태
-- * [L0] 접속 DB · PKG_SYS0014 상태·LAST_DDL
-- * [L1] 대상 — 저장 SP 안 unit_auth DELETE 4키 줄 '     WHERE (T.USER_GR_ID, T.USER_ID, T.UNIT_TP_CD, T.UNIT_ID) IN (' 1 (PASS 기대)
-- * [L2] 권한 테이블 SCM_ADM_USER_GR_UNIT_AUTH_MPG_M 의 UPPR_UNIT_ID 컬럼 존재 (1행 기대)
-- * [L3] 마커 — 적용 전 0
-- * [L4] 참고 — 사업부 줄 없이 남은 하위 권한 줄 수 (이 패치는 이미 남은 줄을 지우지 않는다. 숫자만 회신)
-- * [L5] 지금 PKG_SYS0014 실행 중 세션 (있으면 끝난 뒤 10 실행 — 컴파일이 대기함)
SET LINESIZE 220 PAGESIZE 300
SET DEFINE OFF
COLUMN CHK FORMAT A10
COLUMN KIND FORMAT A50
COLUMN JUDGE FORMAT A70
SELECT 'L0' CHK, SYS_CONTEXT('USERENV','DB_NAME') DB_NAME, TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI:SS') NOW FROM DUAL;
SELECT 'L0' CHK, O.OBJECT_TYPE, O.STATUS, TO_CHAR(O.LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL,
       (SELECT MAX(LINE) FROM USER_SOURCE S WHERE S.NAME=O.OBJECT_NAME AND S.TYPE=O.OBJECT_TYPE) LINES_N
  FROM USER_OBJECTS O WHERE O.OBJECT_NAME='PKG_SYS0014' ORDER BY O.OBJECT_TYPE;
SELECT 'L1 대상' CHK, 'unit_auth DELETE 4키 줄' KIND, COUNT(*) N, CASE WHEN COUNT(*) = 1 THEN 'PASS' ELSE 'FAIL → 10 실행 금지·결과 회신' END JUDGE
  FROM USER_SOURCE S WHERE S.NAME='PKG_SYS0014' AND S.TYPE='PACKAGE BODY'
   AND RTRIM(S.TEXT, CHR(10)||CHR(13)) = '     WHERE (T.USER_GR_ID, T.USER_ID, T.UNIT_TP_CD, T.UNIT_ID) IN ('
   AND S.LINE BETWEEN (SELECT MIN(LINE) FROM USER_SOURCE WHERE NAME='PKG_SYS0014' AND TYPE='PACKAGE BODY' AND TEXT LIKE 'PROCEDURE P_SYS0014_SAVE_GROUP_USER_M (%')
                  AND (SELECT MIN(LINE) FROM USER_SOURCE WHERE NAME='PKG_SYS0014' AND TYPE='PACKAGE BODY' AND TEXT LIKE 'END P_SYS0014_SAVE_GROUP_USER_M;%');
SELECT 'L2 컬럼' CHK, COLUMN_NAME KIND, DATA_TYPE, NULLABLE
  FROM ALL_TAB_COLUMNS WHERE OWNER='SCM_MGR' AND TABLE_NAME='SCM_ADM_USER_GR_UNIT_AUTH_MPG_M' AND COLUMN_NAME='UPPR_UNIT_ID';
SELECT 'L3 마커' CHK, COUNT(*) N, MIN(LINE) LINE,
       CASE WHEN COUNT(*) = 0 THEN '미적용 (기대)' ELSE '적용됨 — 10 재실행은 가드로 무동작' END JUDGE
  FROM USER_SOURCE WHERE NAME='PKG_SYS0014' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%GAP476 2026-10-15%';
SELECT 'L4 참고' CHK, C.UNIT_TP_CD, COUNT(*) N,
       SUM(CASE WHEN NVL(TRIM(C.UPPR_UNIT_ID),'-') IN ('-','/') THEN 1 ELSE 0 END) NO_PARENT_CODE,
       SUM(CASE WHEN NVL(TRIM(C.UPPR_UNIT_ID),'-') NOT IN ('-','/') AND NOT EXISTS (
             SELECT 1 FROM SCM_MGR.SCM_ADM_USER_GR_UNIT_AUTH_MPG_M D
              WHERE D.USER_GR_ID = C.USER_GR_ID AND D.USER_ID = C.USER_ID AND D.UNIT_TP_CD = 'D' AND D.UNIT_ID = C.UPPR_UNIT_ID)
           THEN 1 ELSE 0 END) ORPHAN
  FROM SCM_MGR.SCM_ADM_USER_GR_UNIT_AUTH_MPG_M C WHERE C.UNIT_TP_CD <> 'D' GROUP BY C.UNIT_TP_CD;
SELECT 'L5 실행중' CHK, S.INST_ID, S.SID, S.SERIAL#, S.USERNAME, S.LAST_CALL_ET CALL_SEC
  FROM GV$SESSION S WHERE S.TYPE='USER' AND S.STATUS='ACTIVE'
   AND S.PLSQL_ENTRY_OBJECT_ID = (SELECT OBJECT_ID FROM USER_OBJECTS WHERE OBJECT_NAME='PKG_SYS0014' AND OBJECT_TYPE='PACKAGE');
