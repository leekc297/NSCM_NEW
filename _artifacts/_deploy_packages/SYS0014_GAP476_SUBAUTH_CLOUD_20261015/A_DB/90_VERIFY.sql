-- 90 VERIFY — [GAP476 2026-10-15] GAP 476 조회 전용 (전체 F5, 값 입력 없음)
-- * 기대: V1 마커 1 PASS · V2 VALID / 오류 0 / 의존 INVALID 0 · V3 저장 SP 안 하위 권한 DELETE 1 PASS
SET LINESIZE 220 PAGESIZE 500
SET DEFINE OFF
COLUMN CHK FORMAT A10
COLUMN KIND FORMAT A50
COLUMN JUDGE FORMAT A60
SELECT 'V1 마커' CHK, COUNT(*) N, CASE WHEN COUNT(*) = 1 THEN 'PASS' ELSE 'FAIL (미적용 또는 마커 수 불일치)' END JUDGE
  FROM USER_SOURCE WHERE NAME='PKG_SYS0014' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%GAP476 2026-10-15%';
SELECT 'V2 상태' CHK, O.OBJECT_TYPE, O.STATUS, TO_CHAR(O.LAST_DDL_TIME,'YYYY-MM-DD HH24:MI:SS') LAST_DDL,
       (SELECT COUNT(*) FROM USER_ERRORS E WHERE E.NAME=O.OBJECT_NAME AND E.TYPE=O.OBJECT_TYPE) ERR_CNT,
       (SELECT COUNT(*) FROM USER_OBJECTS X WHERE X.STATUS<>'VALID' AND X.OBJECT_NAME IN (SELECT NAME FROM USER_DEPENDENCIES WHERE REFERENCED_NAME='PKG_SYS0014')) DEP_INVALID
  FROM USER_OBJECTS O WHERE O.OBJECT_NAME='PKG_SYS0014' ORDER BY O.OBJECT_TYPE;
SELECT 'V3 활성' CHK, '저장 SP 안 하위 권한 DELETE' KIND, COUNT(*) N, CASE WHEN COUNT(*) = 1 THEN 'PASS' ELSE 'FAIL — 회신' END JUDGE
  FROM USER_SOURCE S WHERE S.NAME='PKG_SYS0014' AND S.TYPE='PACKAGE BODY'
   AND TRIM(S.TEXT) LIKE 'AND C.UPPR_UNIT_ID = J.V_UNIT_ID%'
   AND S.LINE BETWEEN (SELECT MIN(LINE) FROM USER_SOURCE WHERE NAME='PKG_SYS0014' AND TYPE='PACKAGE BODY' AND TEXT LIKE 'PROCEDURE P_SYS0014_SAVE_GROUP_USER_M (%')
                  AND (SELECT MIN(LINE) FROM USER_SOURCE WHERE NAME='PKG_SYS0014' AND TYPE='PACKAGE BODY' AND TEXT LIKE 'END P_SYS0014_SAVE_GROUP_USER_M;%');
