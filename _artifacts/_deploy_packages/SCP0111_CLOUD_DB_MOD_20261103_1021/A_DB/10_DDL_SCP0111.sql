    FUNCTION exists_obj(p_name VARCHAR2, p_type VARCHAR2) RETURN BOOLEAN IS n PLS_INTEGER;
    BEGIN SELECT COUNT(*) INTO n FROM USER_OBJECTS WHERE OBJECT_NAME = p_name AND OBJECT_TYPE = p_type; RETURN n > 0; END;

