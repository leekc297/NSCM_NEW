SET LINESIZE 200
SET PAGESIZE 100

PROMPT ===== P1. 객체 상태 (둘 다 VALID 여야 함) =====
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'MM-DD HH24:MI:SS') LAST_DDL
  FROM ALL_OBJECTS WHERE OWNER='SCM_MGR'
   AND OBJECT_NAME IN ('PKG_DMF0022','PKG_DMF0051') ORDER BY 1,2;

PROMPT ===== P2. 컴파일 오류 (기대 0행) =====
SELECT NAME, LINE, POSITION, TEXT FROM ALL_ERRORS
 WHERE OWNER='SCM_MGR' AND NAME IN ('PKG_DMF0022','PKG_DMF0051') ORDER BY NAME, SEQUENCE;

PROMPT ===== P3. ⭐ 마커 카운트 (기대치와 일치해야 적용 완료) =====
SELECT PKG, MARKER, EXPECT, ACTUAL, CASE WHEN ACTUAL >= EXPECT THEN 'PASS' ELSE '*** FAIL - 미적용 ***' END VERDICT FROM (
SELECT 'PKG_DMF0022' PKG, 'E20260820-D22PREREDUCE' MARKER, 2 EXPECT, (SELECT COUNT(*) FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0022' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%E20260820-D22PREREDUCE%') ACTUAL FROM DUAL
UNION ALL
SELECT 'PKG_DMF0022' PKG, 'E20260820-D22VERPUSH' MARKER, 2 EXPECT, (SELECT COUNT(*) FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0022' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%E20260820-D22VERPUSH%') ACTUAL FROM DUAL
UNION ALL
SELECT 'PKG_DMF0022' PKG, 'E20260820-DS2' MARKER, 1 EXPECT, (SELECT COUNT(*) FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0022' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%E20260820-DS2%') ACTUAL FROM DUAL
UNION ALL
SELECT 'PKG_DMF0051' PKG, 'E20260820-D51SCALAR' MARKER, 1 EXPECT, (SELECT COUNT(*) FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0051' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%E20260820-D51SCALAR%') ACTUAL FROM DUAL
UNION ALL
SELECT 'PKG_DMF0051' PKG, 'E20260820-D51REGROUP' MARKER, 1 EXPECT, (SELECT COUNT(*) FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0051' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%E20260820-D51REGROUP%') ACTUAL FROM DUAL
UNION ALL
SELECT 'PKG_DMF0051' PKG, 'E20260820-D51SEMI' MARKER, 1 EXPECT, (SELECT COUNT(*) FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0051' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%E20260820-D51SEMI%') ACTUAL FROM DUAL
UNION ALL
SELECT 'PKG_DMF0051' PKG, 'E20260820-D51ITEMPFX' MARKER, 1 EXPECT, (SELECT COUNT(*) FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0051' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%E20260820-D51ITEMPFX%') ACTUAL FROM DUAL
UNION ALL
SELECT 'PKG_DMF0051' PKG, 'E20260820-DS2' MARKER, 1 EXPECT, (SELECT COUNT(*) FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0051' AND TYPE='PACKAGE BODY' AND TEXT LIKE '%E20260820-DS2%') ACTUAL FROM DUAL
) ORDER BY PKG, MARKER;

PROMPT ===== P4. ⚠ 회귀 탐지 — 구세대 덮어쓰기 방지축 =====
--  v_measure_sheet 가 사라지면 SALES PLAN 이 **조용히 0행**이 된다(2026-08-20 실사고 계보).
SELECT 'PKG_DMF0022 / v_measure_sheet' AXIS, 6 EXPECT,
       (SELECT COUNT(*) FROM ALL_SOURCE WHERE OWNER='SCM_MGR' AND NAME='PKG_DMF0022'
         AND TYPE='PACKAGE BODY' AND LOWER(TEXT) LIKE '%v_measure_sheet%') ACTUAL FROM DUAL;

PROMPT ===== P5. ⚠ 권한축 보존 — 제거되면 조회가 0행이 된다 =====
SELECT NAME, COUNT(*) AUTH_JOIN_LINES FROM ALL_SOURCE
 WHERE OWNER='SCM_MGR' AND TYPE='PACKAGE BODY'
   AND NAME IN ('PKG_DMF0022','PKG_DMF0051')
   AND TEXT LIKE '%SCM_ADM_USER_MNU_EDIT_AUTH_V%' GROUP BY NAME ORDER BY 1;

PROMPT ===== P6. 적용 후 성적 확인 (화면 1회 조회 뒤 실행) =====
SELECT SQL_ID, PLAN_HASH_VALUE, EXECUTIONS, ROUND(ELAPSED_TIME/GREATEST(EXECUTIONS,1)/1e6,2) ELA_S,
       BUFFER_GETS, DISK_READS, TO_CHAR(LAST_ACTIVE_TIME,'MM-DD HH24:MI') LAST_ACT,
       SUBSTR(REPLACE(SQL_TEXT,CHR(10),' '),1,80) SQL_HEAD
  FROM V$SQL WHERE PARSING_SCHEMA_NAME='SCM_MGR'
   AND LAST_ACTIVE_TIME > SYSDATE - 30/1440 AND ELAPSED_TIME > 2e6
 ORDER BY ELAPSED_TIME DESC FETCH FIRST 10 ROWS ONLY;

PROMPT ===== 판독 =====
PROMPT   P1 INVALID / P2 행 존재  → 적용 실패. 재컴파일 또는 재적용
PROMPT   P3 FAIL                  → 그 마커분 미반영(대기 중 취소 등). 재적용
PROMPT   P4 ACTUAL <> 6           → **구세대 덮어쓰기** = SALES PLAN 0행 위험. 즉시 재적용
PROMPT   P5 행이 사라짐           → 권한축 훼손. 즉시 원복
