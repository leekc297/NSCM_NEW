SET SERVEROUTPUT ON SIZE UNLIMITED
SET LINESIZE 300
SET VERIFY OFF

PROMPT ################ BEFORE — 시퀀스 vs 테이블 MAX ################
SELECT Q.LAST_NUMBER, Q.INCREMENT_BY, Q.CACHE_SIZE, H.MAX_SEQ, H.MAX_SEQ - Q.LAST_NUMBER + 1 BEHIND_BY,
       CASE WHEN Q.LAST_NUMBER <= H.MAX_SEQ THEN '뒤처짐 — 보정 대상' ELSE '정상 — 보정 불필요' END JUDGE
  FROM (SELECT LAST_NUMBER, INCREMENT_BY, CACHE_SIZE FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'SEQ1_SCM_MST_FUTURE_PRICE_H') Q,
       (SELECT MAX(HISTORY_SEQ) MAX_SEQ FROM SCM_MST_FUTURE_PRICE_H) H;

/* ===== 보정 블록 — 사용자 별도 진행 시 주석 해제 (SCM_MGR) =====
DECLARE
  V_SEQ   VARCHAR2(61) := 'SEQ1_SCM_MST_FUTURE_PRICE_H';
  V_MAX   NUMBER;
  V_LAST  NUMBER;
  V_INC   NUMBER;
  V_CACHE NUMBER;
  V_NEXT  NUMBER;
  V_DUMMY NUMBER;
BEGIN
  SELECT NVL(MAX(HISTORY_SEQ), 0) INTO V_MAX FROM SCM_MST_FUTURE_PRICE_H;
  SELECT LAST_NUMBER, INCREMENT_BY, CACHE_SIZE INTO V_LAST, V_INC, V_CACHE
    FROM USER_SEQUENCES WHERE SEQUENCE_NAME = V_SEQ;
  DBMS_OUTPUT.PUT_LINE('BEFORE: LAST_NUMBER=' || V_LAST || ' MAX(HISTORY_SEQ)=' || V_MAX);

  IF V_LAST > V_MAX THEN
    DBMS_OUTPUT.PUT_LINE('SKIP — 시퀀스가 이미 MAX 보다 앞 (보정 불필요)');
  ELSE
    V_NEXT := V_MAX + 1;
    BEGIN
      EXECUTE IMMEDIATE 'ALTER SEQUENCE ' || V_SEQ || ' RESTART START WITH ' || V_NEXT;
      DBMS_OUTPUT.PUT_LINE('RESTART OK -> START WITH ' || V_NEXT);
    EXCEPTION WHEN OTHERS THEN
      DBMS_OUTPUT.PUT_LINE('RESTART 미지원(' || SQLERRM || ') -> INCREMENT 점프 대체');
      EXECUTE IMMEDIATE 'ALTER SEQUENCE ' || V_SEQ || ' INCREMENT BY ' || (V_NEXT - V_LAST + V_CACHE) || ' NOCACHE';
      EXECUTE IMMEDIATE 'SELECT ' || V_SEQ || '.NEXTVAL FROM DUAL' INTO V_DUMMY;
      EXECUTE IMMEDIATE 'ALTER SEQUENCE ' || V_SEQ || ' INCREMENT BY ' || V_INC || ' CACHE ' || GREATEST(V_CACHE, 2);
      DBMS_OUTPUT.PUT_LINE('대체 경로 소비값 ' || V_DUMMY);
    END;
  END IF;

  SELECT LAST_NUMBER INTO V_LAST FROM USER_SEQUENCES WHERE SEQUENCE_NAME = V_SEQ;
  DBMS_OUTPUT.PUT_LINE('AFTER: LAST_NUMBER=' || V_LAST || CASE WHEN V_LAST > V_MAX THEN ' (PASS)' ELSE ' (❌ 여전히 뒤 — 회신)' END);
END;
/
===== 보정 블록 끝 ===== */

PROMPT ################ AFTER — 02_VERIFY_CLOUD.sql 로 PASS 확인 ################
SELECT Q.LAST_NUMBER, H.MAX_SEQ,
       CASE WHEN Q.LAST_NUMBER > H.MAX_SEQ THEN 'PASS' ELSE '❌ 뒤처짐' END JUDGE
  FROM (SELECT LAST_NUMBER FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'SEQ1_SCM_MST_FUTURE_PRICE_H') Q,
       (SELECT MAX(HISTORY_SEQ) MAX_SEQ FROM SCM_MST_FUTURE_PRICE_H) H;
