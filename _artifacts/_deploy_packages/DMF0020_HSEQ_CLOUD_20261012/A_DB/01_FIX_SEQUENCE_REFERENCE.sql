--   ⚠ 2026-10-12 사용자 지시: "클라우드 시퀀스 작업은 별도로 진행" → 이 파일은 실행 체인에 포함하지 않는다. 필요 시 참고.
--   전체 F5 안전: 살아 있는 문장은 조회 2건만. 보정 블록은 /* */ 안 — 쓰려면 주석 해제.
--   멱등: 시퀀스가 이미 MAX 보다 앞이면 SKIP 출력만. 뒤처졌을 때만 ALTER SEQUENCE ... RESTART START WITH MAX+1
--        (RESTART 미지원이면 INCREMENT BY 점프 → NEXTVAL 1회 → INCREMENT BY 원복 으로 대체)
--   사내 리허설(ZIOUI1 2026-10-12, 임시 시퀀스 ZZ_HSEQ_REHEARSAL_20261012): RESTART 경로 120→5001 OK · 대체 경로 OK · 임시 시퀀스 DROP 완료
--   원복: 시퀀스를 낮추는 원복은 하지 않는다(다시 충돌). 보정 전 LAST_NUMBER 는 아래 BEFORE 조회로 기록만.
