PROMPT ################ [D6] 이력 테이블에 INSERT 하는 모든 객체와 채번 방식 — 시퀀스 외 채번(MAX+1·리터럴) 경로 색출 ################
WITH SRC AS (SELECT U.NAME, U.TYPE, U.LINE, U.TEXT FROM USER_SOURCE U
              WHERE U.TYPE IN ('PACKAGE BODY','PROCEDURE','FUNCTION','TRIGGER')
                AND (UPPER(U.TEXT) LIKE '%FUTURE_PRICE_H%' OR UPPER(U.TEXT) LIKE '%HISTORY_SEQ%')),   -- 1차 LIKE 로 좁힘 (전체 소스 정규식 스캔 회피)
     OBJ AS (SELECT DISTINCT NAME, TYPE FROM SRC
              WHERE TRIM(TEXT) NOT LIKE '--%' AND REGEXP_LIKE(TEXT,'INSERT\s+INTO\s+(SCM_MGR\.)?SCM_MST_FUTURE_PRICE_H(\s|\(|$)','i'))   -- 이력 테이블에 INSERT 하는 객체만 (Oracle 정규식은 \b 미지원)
SELECT S.NAME, S.TYPE, S.LINE, SUBSTR(TRIM(S.TEXT),1,120) T,
       CASE WHEN UPPER(S.TEXT) LIKE '%SEQ1_SCM_MST_FUTURE_PRICE_H.NEXTVAL%' THEN 'seq'
            WHEN REGEXP_LIKE(S.TEXT,'MAX\s*\(\s*(\w+\.)?HISTORY_SEQ','i') THEN '❌ MAX+1 채번'
            WHEN REGEXP_LIKE(S.TEXT,'INSERT\s+INTO\s+(SCM_MGR\.)?SCM_MST_FUTURE_PRICE_H(\s|\(|$)','i') THEN 'insert' ELSE '' END KIND
  FROM SRC S JOIN OBJ O ON O.NAME = S.NAME AND O.TYPE = S.TYPE
 WHERE TRIM(S.TEXT) NOT LIKE '--%'
   AND (REGEXP_LIKE(S.TEXT,'INSERT\s+INTO\s+(SCM_MGR\.)?SCM_MST_FUTURE_PRICE_H(\s|\(|$)','i')
        OR UPPER(S.TEXT) LIKE '%SEQ1_SCM_MST_FUTURE_PRICE_H.NEXTVAL%'
        OR REGEXP_LIKE(S.TEXT,'MAX\s*\(\s*(\w+\.)?HISTORY_SEQ','i'))
 ORDER BY S.NAME, S.TYPE, S.LINE;
