-- 02_VERIFY_CLOUD.sql — 시퀀스 보정(사용자 별도 진행) 뒤 확인 (READ-ONLY, 전체 F5, 값 입력 없음)
--   V1 시퀀스 > MAX(HISTORY_SEQ) · V2 시퀀스 속성 원형(INCREMENT 1 · CACHE 20 · NOCYCLE) · V3 PK/트리거 동형 · V4 보정 뒤 저장 재시도 오류 0
--   화면: DMF0020 Sales Price → 행 INSERT → 저장 → 성공 토스트 + [V4] 에 ORA-00001 새 행 없음 + [V5] 이력 행 증가
-- =============================================================================
SET LINESIZE 300
SET PAGESIZE 200
SET VERIFY OFF
COLUMN JUDGE FORMAT A60
COLUMN ERR FORMAT A100
SPOOL 02_VERIFY_CLOUD_OUT.txt

PROMPT ################ [V1] 시퀀스 vs 테이블 MAX ################
SELECT Q.LAST_NUMBER, Q.CACHE_SIZE, H.MAX_SEQ, Q.LAST_NUMBER - H.MAX_SEQ AHEAD_BY,
       CASE WHEN Q.LAST_NUMBER IS NULL THEN '❌ 시퀀스 없음'
            WHEN Q.LAST_NUMBER > H.MAX_SEQ THEN 'PASS (정상 = AHEAD_BY 1~CACHE_SIZE, 사내 19)'
            ELSE '❌ 뒤처짐 — 보정 미완' END JUDGE
  FROM (SELECT MAX(HISTORY_SEQ) MAX_SEQ FROM SCM_MST_FUTURE_PRICE_H) H
  LEFT JOIN (SELECT LAST_NUMBER, CACHE_SIZE FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'SEQ1_SCM_MST_FUTURE_PRICE_H') Q ON 1=1;

PROMPT ################ [V2] 시퀀스 속성 — 사내 원형 INCREMENT_BY 1 · CACHE 20 · CYCLE N · ORDER N ################
SELECT SEQUENCE_NAME, INCREMENT_BY, CACHE_SIZE, CYCLE_FLAG, ORDER_FLAG, MIN_VALUE,
       CASE WHEN INCREMENT_BY = 1 AND CACHE_SIZE = 20 AND CYCLE_FLAG = 'N' THEN 'PASS'
            WHEN INCREMENT_BY <> 1 THEN '❌ INCREMENT_BY 가 1 이 아님 — 대체 경로 원복 누락'
            ELSE '⚠ 속성 상이 (참고)' END JUDGE
  FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'SEQ1_SCM_MST_FUTURE_PRICE_H';

PROMPT ################ [V3] 이력 PK · 트리거 동형 ################
SELECT C.CONSTRAINT_NAME, LISTAGG(CC.COLUMN_NAME, ',') WITHIN GROUP (ORDER BY CC.POSITION) COLS,
       (SELECT COUNT(*) FROM USER_TRIGGERS T WHERE T.TABLE_NAME = 'SCM_MST_FUTURE_PRICE_H') TRG_CNT,
       CASE WHEN LISTAGG(CC.COLUMN_NAME, ',') WITHIN GROUP (ORDER BY CC.POSITION) = 'HISTORY_SEQ'
             AND (SELECT COUNT(*) FROM USER_TRIGGERS T WHERE T.TABLE_NAME = 'SCM_MST_FUTURE_PRICE_H') = 0 THEN 'PASS' ELSE '⚠ 상이' END JUDGE
  FROM USER_CONSTRAINTS C JOIN USER_CONS_COLUMNS CC ON CC.CONSTRAINT_NAME = C.CONSTRAINT_NAME
 WHERE C.TABLE_NAME = 'SCM_MST_FUTURE_PRICE_H' AND C.CONSTRAINT_TYPE = 'P'
 GROUP BY C.CONSTRAINT_NAME;

PROMPT ################ [V4] 보정 이후 DMF0020 저장 호출 — ORA-00001 PK_SCM_MST_FUTURE_PRICE_H 가 더 나오지 않아야 함 (최근 240분) ################
SELECT TO_CHAR(L.TRNM_ST_DTM,'MM-DD HH24:MI:SS') ST, L.SHT_NM, L.MNU_BTN_CD, L.CREATED_BY,
       CASE WHEN L.EXCT_MSG_CTN LIKE '%PK_SCM_MST_FUTURE_PRICE_H%' THEN '❌ 재발' WHEN L.EXCT_MSG_CTN IS NOT NULL THEN '⚠ 다른 오류' ELSE 'ok' END JUDGE,
       SUBSTR(L.EXCT_MSG_CTN,1,100) ERR
  FROM SCM_COM_SYS_LOG L
 WHERE L.MNU_ID = 'DMF0020' AND UPPER(L.MNU_BTN_CD) LIKE '%SAVE%' AND L.CREATION_DATE >= SYSDATE - 240/1440
 ORDER BY L.TRNM_ST_DTM DESC
 FETCH FIRST 20 ROWS ONLY;

PROMPT ################ [V5] 이력 행 최신 10 — 저장 재시도 뒤 새 HISTORY_SEQ 가 시퀀스에서 발급된 값으로 들어왔는지 ################
SELECT HISTORY_SEQ, DIVISION_ID, CURRENCY, YYYYMMDD, CREATED_BY, TO_CHAR(CREATION_DATE,'YYYY-MM-DD HH24:MI:SS') CRE
  FROM SCM_MST_FUTURE_PRICE_H ORDER BY HISTORY_SEQ DESC FETCH FIRST 10 ROWS ONLY;

SPOOL OFF
