SET PAGESIZE 200 LINESIZE 250
COLUMN JUDGE FORMAT A60

PROMPT [A] 의존 객체 존재·상태 (전부 존재·VALID 기대. 3종 standalone HIST 는 적용 전 존재 / 적용 후 부재)
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS, TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI') LAST_DDL
  FROM USER_OBJECTS
 WHERE OBJECT_NAME IN ('PKG_DMF0004','PR_DM_MST_SITE_CUSTOMER_HIST',
                       'PR_DM_MST_SITE_HIST','PR_DM_MST_SITE_SLOC_MAPPING_HIST','PR_DM_MST_BUCKET_CONVERSION_HIST',
                       'SCM_MST_SITE','SCM_MST_SITE_H','SCM_MST_SITE_CUSTOMER_H','SCM_MST_LOCATION_H','DM_MST_BUCKET_CONVERSION_H',
                       'SEQ1_SCM_MST_SITE_H','SEQ1_SCM_MST_LOCATION_H','SEQ1_DM_MST_BUCKET_CONVERSION_H','SEQ1_SCM_MST_LOCATION',
                       'PR_SCM_SYS_LOG_BATCH','SCM_MST_SITE_H_BAK20260928')
 ORDER BY OBJECT_NAME, OBJECT_TYPE;


PROMPT [H2] PKG_DMF0004 PACKAGE 본문 지문 — 적용 직전(사내)=(71, 2055) / 적용 후(사내)=(77, 2775)
SELECT 'PKG_DMF0004' OBJ, 'PACKAGE' TYP, COUNT(*) LINE_CNT, SUM(LENGTH(RTRIM(TEXT, CHR(10)||CHR(13)))) CHAR_SUM,
       CASE WHEN COUNT(*)=71 AND SUM(LENGTH(RTRIM(TEXT, CHR(10)||CHR(13))))=2055 THEN 'MATCH_BEFORE → 적용 가능'
            WHEN COUNT(*)=77  AND SUM(LENGTH(RTRIM(TEXT, CHR(10)||CHR(13))))=2775  THEN 'MATCH_AFTER → 이미 적용됨(SKIP 가능)'
            WHEN COUNT(*)=0 THEN 'MISSING'
            ELSE '⚠ MISMATCH → 적용 중단 · 클라우드 본문 차이 확인' END JUDGE
  FROM USER_SOURCE WHERE NAME='PKG_DMF0004' AND TYPE='PACKAGE';


PROMPT [H3] PKG_DMF0004 PACKAGE BODY 본문 지문 — 적용 직전(사내)=(1403, 50884) / 적용 후(사내)=(1758, 66725) / 09-29 1차본=(1824, 67889)
SELECT 'PKG_DMF0004' OBJ, 'PACKAGE BODY' TYP, COUNT(*) LINE_CNT, SUM(LENGTH(RTRIM(TEXT, CHR(10)||CHR(13)))) CHAR_SUM,
       CASE WHEN COUNT(*)=1403 AND SUM(LENGTH(RTRIM(TEXT, CHR(10)||CHR(13))))=50884 THEN 'MATCH_BEFORE → 적용 가능'
            WHEN COUNT(*)=1824 AND SUM(LENGTH(RTRIM(TEXT, CHR(10)||CHR(13))))=67889 THEN 'MATCH_PREV_0929_1ST → 1차 이관본(DEPT_ID 컴파일 오류) · 23 재적용'
            WHEN COUNT(*)=1758  AND SUM(LENGTH(RTRIM(TEXT, CHR(10)||CHR(13))))=66725  THEN 'MATCH_AFTER → 이미 적용됨(SKIP 가능)'
            WHEN COUNT(*)=0 THEN 'MISSING'
            ELSE '⚠ MISMATCH → 적용 중단 · 클라우드 본문 차이 확인' END JUDGE
  FROM USER_SOURCE WHERE NAME='PKG_DMF0004' AND TYPE='PACKAGE BODY';

PROMPT [H4] 호출 대상 공용 standalone PR_DM_MST_SITE_CUSTOMER_HIST 지문 (사내 현행과 동일 기대)
SELECT 'PR_DM_MST_SITE_CUSTOMER_HIST' OBJ, COUNT(*) LINE_CNT, SUM(LENGTH(RTRIM(TEXT, CHR(10)||CHR(13)))) CHAR_SUM,
       CASE WHEN COUNT(*)=195 AND SUM(LENGTH(RTRIM(TEXT, CHR(10)||CHR(13))))=5859 THEN 'MATCH' WHEN COUNT(*)=0 THEN 'MISSING' ELSE '⚠ MISMATCH' END JUDGE
  FROM USER_SOURCE WHERE NAME='PR_DM_MST_SITE_CUSTOMER_HIST' AND TYPE='PROCEDURE';

PROMPT [C1] SCM_MST_SITE 컬럼 — 사내 대비 누락/추가 (참고용 · 이력 복사는 실행 시점 SITE∩_H 동적 컬럼이라 DEPT_ID 부재 등 차이 허용)
SELECT (SELECT COUNT(*) FROM (SELECT COLUMN_VALUE C FROM TABLE(SYS.ODCIVARCHAR2LIST('DIVISION_ID','SCM_SITE_ID','PLANT_ID','OPERATION_GROUP','SITE_DESCRIPTION','SITE_TYPE','CITY','COUNTRY','VMI_YN','VALID_YN','NEW_YN','SITE_HRCY_ID','OSP_YN','SHIP_FROZEN','PROD_FROZEN','END_CUSTOMER','SOLDTO_CUSTOMER','FP_PLAN_PERIOD','BUILD_AHEAD','LOGISTIC_PLANT_ID','PACKER_ITEM_ID_SUFFIX','HQ_VENDOR_CODE','COMPANY_ID','SITE_ID','CREATED_BY','CREATION_DATE','LAST_UPDATED_BY','LAST_UPDATE_DATE','ATTRIBUTE1','ATTRIBUTE2','ATTRIBUTE3','ATTRIBUTE4','ATTRIBUTE5','ATTRIBUTE6','ATTRIBUTE7','ATTRIBUTE8','ATTRIBUTE9','ATTRIBUTE10','DEPT_ID')))
         WHERE C NOT IN (SELECT COLUMN_NAME FROM USER_TAB_COLUMNS WHERE TABLE_NAME='SCM_MST_SITE')) MISSING_CNT,
       (SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY COLUMN_ID) FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME='SCM_MST_SITE' AND COLUMN_NAME NOT IN (SELECT COLUMN_VALUE FROM TABLE(SYS.ODCIVARCHAR2LIST('DIVISION_ID','SCM_SITE_ID','PLANT_ID','OPERATION_GROUP','SITE_DESCRIPTION','SITE_TYPE','CITY','COUNTRY','VMI_YN','VALID_YN','NEW_YN','SITE_HRCY_ID','OSP_YN','SHIP_FROZEN','PROD_FROZEN','END_CUSTOMER','SOLDTO_CUSTOMER','FP_PLAN_PERIOD','BUILD_AHEAD','LOGISTIC_PLANT_ID','PACKER_ITEM_ID_SUFFIX','HQ_VENDOR_CODE','COMPANY_ID','SITE_ID','CREATED_BY','CREATION_DATE','LAST_UPDATED_BY','LAST_UPDATE_DATE','ATTRIBUTE1','ATTRIBUTE2','ATTRIBUTE3','ATTRIBUTE4','ATTRIBUTE5','ATTRIBUTE6','ATTRIBUTE7','ATTRIBUTE8','ATTRIBUTE9','ATTRIBUTE10','DEPT_ID')))) EXTRA_COLS
  FROM DUAL;

PROMPT [C2] SCM_MST_SITE ↔ SCM_MST_SITE_H 현재 대조 (적용 전 참고 — 21 적용 후 90_VERIFY [V3] 에서 값 단언)
SELECT S.COLUMN_ID S_ID, NVL(S.COLUMN_NAME,H.COLUMN_NAME) COL, S.CHAR_LENGTH S_LEN, H.CHAR_LENGTH H_LEN,
       S.NULLABLE S_NULL, H.NULLABLE H_NULL, S.DEFAULT_ON_NULL S_ON_NULL, H.DEFAULT_ON_NULL H_ON_NULL, H.COLUMN_ID H_ID
  FROM (SELECT * FROM USER_TAB_COLUMNS WHERE TABLE_NAME='SCM_MST_SITE') S
  FULL OUTER JOIN (SELECT * FROM USER_TAB_COLUMNS WHERE TABLE_NAME='SCM_MST_SITE_H') H ON H.COLUMN_NAME=S.COLUMN_NAME
 ORDER BY NVL(S.COLUMN_ID, 900 + H.COLUMN_ID);

PROMPT [C3] SCM_MST_SITE_H 데이터 제약 사전점검 (전부 0 기대 — 30자 초과·NULL VALID_YN 존재 시 21 의 NOT NULL 재설정 실패)
SELECT (SELECT COUNT(*) FROM SCM_MST_SITE_H WHERE VALID_YN IS NULL) NULL_VALID_YN, (SELECT COUNT(*) FROM SCM_MST_SITE_H) H_ROWS FROM DUAL;

PROMPT [D] SCM_MST_SITE_H 를 쓰는 객체 (21 적용 후 재컴파일 대상 — 24 가 동적 처리)
SELECT OWNER||'.'||NAME||' '||TYPE DEP FROM ALL_DEPENDENCIES WHERE REFERENCED_NAME='SCM_MST_SITE_H' ORDER BY 1;

