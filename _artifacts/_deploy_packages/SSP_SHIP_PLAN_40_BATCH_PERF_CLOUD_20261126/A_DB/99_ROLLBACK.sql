/* 원복 : 05 보관 표 원문으로 3개 SP 되돌림 (문제 있을 때만). 보관 표가 없으면 그 SP 는 건너뜀 */
SET SERVEROUTPUT ON SIZE UNLIMITED
ALTER SESSION SET CURRENT_SCHEMA = SCM_MGR;
DECLARE
    v    CLOB;
    v_st VARCHAR2(30);
    v_n  NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_n FROM ALL_TABLES WHERE OWNER = 'SCM_MGR' AND TABLE_NAME = 'ZB_SSP40_SHIP_20261126';
    IF v_n = 0 THEN DBMS_OUTPUT.PUT_LINE('> SKIP PR_SSP_ANL_SHIP_PLAN_40 보관 표 없음'); RETURN; END IF;
    DBMS_LOB.CREATETEMPORARY(v, TRUE);
    DBMS_LOB.WRITEAPPEND(v, LENGTH('CREATE OR REPLACE '), 'CREATE OR REPLACE ');
    FOR r IN (SELECT TEXT FROM SCM_MGR.ZB_SSP40_SHIP_20261126 ORDER BY LINE) LOOP
        IF r.TEXT IS NOT NULL THEN DBMS_LOB.WRITEAPPEND(v, LENGTH(r.TEXT), r.TEXT); END IF;
    END LOOP;
    BEGIN EXECUTE IMMEDIATE v; EXCEPTION WHEN OTHERS THEN NULL; END;
    SELECT STATUS INTO v_st FROM ALL_OBJECTS WHERE OWNER = 'SCM_MGR' AND OBJECT_NAME = 'PR_SSP_ANL_SHIP_PLAN_40' AND OBJECT_TYPE = 'PROCEDURE';
    DBMS_OUTPUT.PUT_LINE('> ROLLBACK PR_SSP_ANL_SHIP_PLAN_40 · ' || v_st);
END;
/
