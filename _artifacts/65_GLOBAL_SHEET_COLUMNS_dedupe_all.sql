-- 65_GLOBAL_SHEET_COLUMNS_dedupe_all.sql
--
-- 목적: SCM_MST_SHEET_COLUMNS 전체 (모든 PROGRAM_ID) duplicate row 일괄 정리
--
-- 사고 (2026-06-09 사용자 보고 "전체 화면 일괄 점검"):
--   357 program / 755 sheet / 15,167 dup row — 모두 동일 패턴 (TOT = DISTINCT × 2)
--   = 메타 INSERT 가 2회 실행된 안티 패턴 (메모리 `feedback_sql_idempotent_insert_all` 미준수 누적)
--
-- 동작:
--   - (PROGRAM_ID, SHEET_NAME, COLUMN_NAME) 별 MIN(ROWID) 유지, 나머지 삭제
--   - 영향 = SHEET_COLUMNS 메타만 (실제 데이터 SCM_MST_*  영향 0)
--
-- 멱등성: 실행 후 distinct = total. 재실행 안전.
-- 참조 패턴: _artifacts/57_SYS0011_*.sql / 64_SYS0010_*.sql
-- 작성: 2026-06-09
--==============================================================================
SET DEFINE OFF
SET SERVEROUTPUT ON
SET FEEDBACK ON
WHENEVER SQLERROR EXIT FAILURE

PROMPT === BLOCK 1 : 사전 상태 (요약) ===
SELECT
  COUNT(*) AS AFFECTED_SHEETS,
  COUNT(DISTINCT PROGRAM_ID) AS AFFECTED_PROGRAMS,
  SUM(CNT - DISTINCT_CNT) AS TOTAL_DUP_ROWS
FROM (
  SELECT PROGRAM_ID, SHEET_NAME, COUNT(*) AS CNT, COUNT(DISTINCT COLUMN_NAME) AS DISTINCT_CNT
    FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
   GROUP BY PROGRAM_ID, SHEET_NAME
  HAVING COUNT(*) > COUNT(DISTINCT COLUMN_NAME)
);

PROMPT === BLOCK 2 : 전역 duplicate row 제거 ((PROGRAM_ID, SHEET_NAME, COLUMN_NAME) 별 MIN(ROWID) 유지) ===
DELETE FROM SCM_MGR.SCM_MST_SHEET_COLUMNS X
 WHERE X.ROWID NOT IN (
     SELECT MIN(Y.ROWID)
       FROM SCM_MGR.SCM_MST_SHEET_COLUMNS Y
      GROUP BY Y.PROGRAM_ID, Y.SHEET_NAME, Y.COLUMN_NAME
   );

PROMPT === BLOCK 3 : 사후 상태 (요약 — duplicate 0 의무) ===
SELECT
  COUNT(*) AS REMAINING_DUP_SHEETS,
  COUNT(DISTINCT PROGRAM_ID) AS REMAINING_DUP_PROGRAMS,
  SUM(CNT - DISTINCT_CNT) AS REMAINING_DUP_ROWS
FROM (
  SELECT PROGRAM_ID, SHEET_NAME, COUNT(*) AS CNT, COUNT(DISTINCT COLUMN_NAME) AS DISTINCT_CNT
    FROM SCM_MGR.SCM_MST_SHEET_COLUMNS
   GROUP BY PROGRAM_ID, SHEET_NAME
  HAVING COUNT(*) > COUNT(DISTINCT COLUMN_NAME)
);

PROMPT === BLOCK 4 : SHEET_COLUMNS 총 건수 (사후 검증) ===
SELECT COUNT(*) AS TOTAL_ROWS, COUNT(DISTINCT PROGRAM_ID) AS TOTAL_PROGRAMS
  FROM SCM_MGR.SCM_MST_SHEET_COLUMNS;

COMMIT;
PROMPT === COMPLETE ===
EXIT;
