-- BLOCK 2: PROC_M — ALL_ARGUMENTS 동적 등록, PROC 단위 부재 시에만(사내 현행 13행 = GET 5 + SAVE 8 · 무변경)
--   As-is biz:CommonData.CommonDataList = 조회조건 콤보 LookupCommon(@lookupType='OPMZ_PRS_CD') → PROC 아님(등록 대상 아님)
--   As-is SCP.SCP0121_GET_SEARCH_INFO = 콤보 PlanGroup_SCP_ALL 이 대체(진입점 미연결 · allowed_gap) → 등록 대상 아님
DECLARE
  TYPE t_list IS TABLE OF VARCHAR2(128);
  v_objs t_list := t_list('P_SCP0122_GET_PLAN_ACTIVITY_MGMT', 'P_SCP0122_SAVE_PLAN_ACTIVITY_MGMT');
  v_n NUMBER; v_has NUMBER;
BEGIN
  FOR i IN 1 .. v_objs.COUNT LOOP
    SELECT COUNT(*) INTO v_has FROM SCM_ADM_PROC_M WHERE PROC_NM = '&V_PKG_NM' || '.' || v_objs(i);
    IF v_has > 0 THEN
      DBMS_OUTPUT.PUT_LINE('  SKIP ' || v_objs(i) || ' PROC_M 기등록 ' || v_has || '행');
      CONTINUE;
    END IF;
    v_n := 0;
    FOR r IN (SELECT ARGUMENT_NAME, IN_OUT, DATA_TYPE, POSITION FROM ALL_ARGUMENTS
               WHERE OWNER = 'SCM_MGR' AND PACKAGE_NAME = '&V_PKG_NM' AND OBJECT_NAME = v_objs(i)
                 AND DATA_LEVEL = 0 AND ARGUMENT_NAME IS NOT NULL ORDER BY POSITION) LOOP
      v_n := v_n + 1;
      INSERT INTO SCM_ADM_PROC_M (PROC_NM, COL_NM, COL_TP_CD, DATA_TP_CD, SORT_ORD, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE)
      VALUES ('&V_PKG_NM' || '.' || v_objs(i),
              CASE WHEN r.IN_OUT LIKE '%OUT%' THEN LOWER(r.ARGUMENT_NAME) ELSE PKG_NSCM_UI_COMM.FN_TO_CAMEL_CASE(REGEXP_REPLACE(r.ARGUMENT_NAME, '^P_', '')) END,
              CASE WHEN r.IN_OUT LIKE '%OUT%' THEN 'OUT' ELSE 'IN' END,
              CASE WHEN r.ARGUMENT_NAME = 'O_RESULT_CURSOR' THEN 'PROC_RESULT' ELSE PKG_NSCM_UI_COMM.FN_GET_SYSTEM_DATA_TP(r.DATA_TYPE) END,
              v_n, '&V_USER_ID', SYSDATE, '&V_USER_ID', SYSDATE);
    END LOOP;
    DBMS_OUTPUT.PUT_LINE(CASE WHEN v_n = 0 THEN '  WARN ' || v_objs(i) || ' ALL_ARGUMENTS 없음(PKG 미배포) — PKG 배포 후 재실행'
                              ELSE '  OK ' || v_objs(i) || ' 파라미터 ' || v_n || '건' END);
  END LOOP;
END;
