-- BLOCK 8: 검증 — 기대값(사내 2026-10-22 실측): MENU 1 · PROC_M(PKG_SCP0122) 13 · SHEET_COLUMNS 15 · API 2 · MNU_BTN_MPG 5 · GROUP_MENU 4 · GROUP_BTN 16 · I18N 3
