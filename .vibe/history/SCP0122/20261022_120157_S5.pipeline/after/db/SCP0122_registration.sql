ORDER BY 1;
DECLARE v_cur SYS_REFCURSOR; v_proc VARCHAR2(200); v_col VARCHAR2(100); v_dt VARCHAR2(50); v_ct VARCHAR2(50); v_so NUMBER; v_cnt NUMBER;
  TYPE t_list IS TABLE OF VARCHAR2(30); v_btns t_list := t_list('SEARCH', 'SAVE');
BEGIN
  FOR i IN 1 .. v_btns.COUNT LOOP
    v_cnt := 0;
    SCM_MGR.PKG_NSCM_UI_COMM.PR_GET_PROC_INFO_LIST(P_MNU_ID => '&V_MENU_ID', P_SHT_NM => 'main', P_MNU_BTN_CD => v_btns(i), O_CURSOR => v_cur);
    LOOP FETCH v_cur INTO v_proc, v_col, v_dt, v_ct, v_so; EXIT WHEN v_cur%NOTFOUND; v_cnt := v_cnt + 1; END LOOP; CLOSE v_cur;
    DBMS_OUTPUT.PUT_LINE('main/' || v_btns(i) || ' : ' || CASE WHEN v_cnt = 0 THEN 'FAIL 라우팅 없음' ELSE 'OK 파라미터 ' || v_cnt END);
  END LOOP;
END;
